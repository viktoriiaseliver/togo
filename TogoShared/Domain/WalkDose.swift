import Foundation

/// Доза рядом с выходом: сказать про неё в шторке «Просится»
/// и в режиме «На улице».
///
/// Правило дизайна: если доза попадает в ±30 минут от выхода, человек
/// должен это увидеть **до** того, как выйдет, — а если препарат можно
/// дать на улице, то и кнопку «Дал» там же.
///
/// **Два ответа раздельно, и это не удобство вызова.** «Доза через
/// двадцать минут» и «дай на улице» — два разных сообщения, и сводить
/// их в один `Bool` нельзя: у нас уже оплачено тем, что сообщение,
/// покрывающее несколько причин одним текстом, даёт совет, неверный
/// для большинства из них. Человеку с каплями в глаз надо сказать
/// «через двадцать минут доза» и **не** предлагать дать её на улице;
/// человеку с таблеткой — и то, и другое.
///
/// **Ссылки здесь — ИМЕНАМИ, а не номерами строк, и это правка
/// 08.10.2026.** Стояло `Care.swift:329`, поле лежит на `:402`:
/// номер состарился от вставки выше, и ровно так же состарится
/// следующий.
///
/// > **Номер строки в доккомментарии — утверждение о мире, которое
/// > стареет при первой же вставке выше.** Хуже того, он выглядит
/// > ТОЧНЕЕ имени, и поэтому его пересказывают охотнее: имя заставляет
/// > искать и найти, номер — поверить и промахнуться.
///
/// **Поле «можно дать на улице» уже есть, и выводить его нельзя.**
/// Менеджер предложил вывести признак из соседних полей
/// (`fastingBefore > 0`, `dependsOnMeal`, `unitRaw == .ml`) и не
/// заводить нового. Замер 07.10.2026 показал, что заводить и не надо:
/// `Medication.canGiveOutside` существует (`Care.swift`, ищется
/// по имени: `grep -n canGiveOutside TogoShared/Models/Care.swift`),
/// описан в плане схемы именно этой кнопкой (`SchemaVersions.swift`,
/// там же по имени)
/// и лежит в той же группе тринадцати полей V5, заведённых заранее
/// под экраны хендоффа.
///
/// А выводить его было бы **хуже, чем лишняя работа**: вывод решает
/// за человека вопрос, на который человек отвечает сам. Таблетку
/// с едой (`dependsOnMeal`) вывод запретил бы, а хозяйка может носить
/// её с кормом в кармане; сироп (`.ml`) вывод запретил бы, а шприц
/// в сумке бывает. Это тот же класс, который мы ловили весь день:
/// признак, выведенный вместо прочитанного, имеет две причины
/// и различить их нечем.
///
/// > **Поле без писателя и поля нет — разные вещи.** У `canGiveOutside`
/// > нет ни одного места, где его ставят (замер: ноль вхождений
/// > в `Togo/`), и именно поэтому его легко принять за отсутствующее.
/// > Экран, который его поставит, законтрактован; до него флаг читается
/// > как `false`, и это верное значение по умолчанию — не предлагать
/// > давать на улице то, про что никто не сказал «можно».
nonisolated enum WalkDose {

    /// Насколько близко доза считается «рядом с выходом».
    ///
    /// Тридцать минут — правило дизайна, а не замер; в коде этого окна
    /// до 07.10.2026 не было вовсе (`grep '30 \* 60'` давал только
    /// поездки и напоминания, другое).
    static let window: TimeInterval = 30 * 60

    /// Доза рядом и что про неё можно сказать.
    struct Рядом: Equatable, Sendable {
        /// Когда она по расписанию.
        let когда: Date
        /// Со знаком: отрицательное — время уже прошло, положительное —
        /// ещё впереди. Знак нужен тексту: «через двадцать минут»
        /// и «двадцать минут назад» — разные фразы, и выбрать между
        /// ними по модулю нельзя.
        let через: TimeInterval
        /// Можно ли дать её на улице — **ответ человека**, а не наш
        /// вывод из соседних полей.
        let даётсяНаУлице: Bool
        /// Название препарата: в строке «Дал» человек должен видеть,
        /// что именно он даёт, если схем несколько.
        let препарат: String
    }

    /// Есть ли открытая доза в окне ±30 минут от `now`.
    ///
    /// Чистая функция: ничего не создаёт и не сохраняет. Отметки
    /// на день заводит `DoseScheduler.ensureDoses` при открытии экрана —
    /// здесь только чтение того, что уже есть.
    ///
    /// Из нескольких подходящих берётся **ближайшая по времени**,
    /// а не первая в массиве: порядок `doses` нам не принадлежит.
    ///
    /// Что отбрасывается и почему:
    /// - приостановленная и отменённая схема — её не дают вовсе;
    /// - уже отмеченная доза (`givenAt`) — говорить «дай» про данную
    ///   значит предлагать вторую;
    /// - пропущенная (`skippedAt`) и отменённая (`cancelledAt`) —
    ///   решение по ним человек уже принял.
    @MainActor
    static func рядом(_ dog: Dog, at now: Date = Date()) -> Рядом? {
        var ближайшая: Рядом?

        for схема in dog.medications where !схема.isPaused && схема.cancelledAt == nil {
            for доза in схема.doses {
                guard доза.givenAt == nil, доза.skippedAt == nil, доза.cancelledAt == nil
                else { continue }
                let через = доза.scheduledAt.timeIntervalSince(now)
                guard abs(через) <= window else { continue }
                if let текущая = ближайшая, abs(текущая.через) <= abs(через) { continue }
                ближайшая = Рядом(когда: доза.scheduledAt,
                                  через: через,
                                  даётсяНаУлице: схема.canGiveOutside,
                                  препарат: схема.name)
            }
        }
        return ближайшая
    }
}
