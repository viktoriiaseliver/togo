import Foundation

/// Отвечает ли «сколько прошло» ещё на вопрос — или пора называть дату.
///
/// **Четвёртый случай одной формы за полтора месяца, и нашёл его кадр,
/// а не прогон.** 21.09 главный экран говорил «434 ч назад · на улице
/// были» — завели `OutingSilence`. 24.09 то же число той же формой
/// сказала Siri. 28.09 вердикт выговаривал «Не писал 434 ч. Это дольше,
/// чем он когда-либо терпел» — завели `UrineSilence`. А строка фактов
/// под всеми тремя починками печатала
///
///     стул 16 сент. · ел 437 ч 19 мин назад
///
/// — то есть ровно то, от чего правило и заводили: число, выведенное
/// из **отсутствия** записи, выданное за величину. 437 часов это
/// восемнадцать дней, и «19 мин» обещает точность, которой у отсутствия
/// записи быть не может.
///
/// **Довод, что это дефект, а не вкус, лежал в той же функции.**
/// У стула стояло `isDateInToday ? часы : дата`, у еды и прогулки
/// разветвления не было вовсе. Одна функция, три величины, два решения —
/// и второе не выбрано никем, оно просто не написано. Пропуск, который
/// выглядит как решение.
///
/// **Почему свой потолок, а не `UrineSilence.ceiling`.** Числа сейчас
/// совпадают, а вопросы разные, и съехать они должны порознь. Там
/// вопрос «писал ли он» — медицинский, и потолок бережёт от утверждения
/// о собаке. Здесь вопрос «когда в последний раз» — бытовой, и потолок
/// бережёт от ложной точности. Общая ссылка связала бы два решения,
/// которые принимают по разным основаниям.
///
/// **Почему сутки.** Вопрос строки фактов — «когда это было в его
/// распорядке»: кормят несколько раз в день, гуляют несколько раз
/// в день, и внутри суток «сколько прошло» отвечает прямо. За сутками
/// без единой отметки число говорит уже не о собаке, а о дневнике —
/// и говорит длиннее: «437 ч 19 мин» требует считать в уме, «17 сент.»
/// сопоставляется с памятью сразу.
///
/// Стул этим правилом не меряется нарочно и остаётся на `isDateInToday`:
/// у него спрашивают **время суток** (это про консистенцию и режим),
/// а не «сколько прошло». Разветвление у него уже верное, и свести их
/// в одно значило бы потерять «стул сегодня 7:34».
nonisolated enum FactAge {

    /// Дольше этого «сколько прошло» отвечает уже не на тот вопрос.
    static let ceiling: TimeInterval = 24 * 3600

    /// Чем называть величину: прошедшим временем или датой.
    ///
    /// Решение возвращается **случаем**, а не готовой строкой: тексты
    /// у еды и прогулки разные, и собирать их здесь значило бы завести
    /// в домене копию интерфейсных формулировок.
    enum Answer: Equatable {
        /// Внутри суток — «сколько прошло» отвечает прямо.
        case elapsed(TimeInterval)
        /// За сутками — называем дату и не делаем вид, что считали.
        case day(Date)
    }

    static func answer(since date: Date, now: Date) -> Answer {
        let прошло = now.timeIntervalSince(date)
        return прошло >= ceiling ? .day(date) : .elapsed(прошло)
    }
}
