import Foundation

/// Всё, что считается по ВСЕЙ ленте, — посчитанное один раз.
///
/// Три величины лежат вместе не для удобства: они выводятся из одного
/// прохода по дневнику, и считать их по отдельности значит платить
/// за этот проход трижды.
nonisolated struct СрезЛенты: Sendable {
    /// Сколько собака дома прямо сейчас — от конца последнего выхода.
    let дома: TimeInterval?
    /// Конец последнего записанного выхода. Нужен, чтобы за потолком
    /// тишины сказать «выходов нет с такого-то», а не печатать число
    /// часов, которое отвечает уже не на тот вопрос.
    let конецПоследнегоВыхода: Date?
    /// Ритм выходов — средний промежуток дома и надёжность счёта.
    let ритм: WalkRhythm
}

/// Кеш среза на один проход отрисовки.
///
/// # Зачем он вообще нужен
///
/// Замер 28.10.2026 по жалобе «виснет, плохо скроллится и медленно»:
///
/// ```
/// TodayScreen.timeIndoors            обращений за проход body   5
/// TodayScreen.lastOutingEndedAt                                 6
/// TodayScreen.ритм                                              7
/// состояниеПоказания зовётся 4 раза, показаниеПанели — 2,
///   и КАЖДЫЙ их вызов тянет и ленту, и ритм
/// итого полных проходов по дневнику за ОДИН кадр      около 20
/// ```
///
/// Каждый проход — `Diary.active` плюс сортировка с построением блоков,
/// то есть порядка 0,4 мс на 1400 записях. Двадцать таких проходов —
/// это уже больше бюджета кадра (16 мс при 60 кадрах в секунду),
/// и экран физически не успевает.
///
/// > **Вычисляемое свойство в SwiftUI не кеширует ничего.** Оно
/// > выглядит как значение, а ведёт себя как вызов функции — и, если
/// > внутри него полный проход по данным, цена умножается на число
/// > мест, где его прочитали. Чем экран подробнее, тем он медленнее,
/// > и связь эта не видна ни в одной строке кода.
///
/// # Почему кеш, а не прокидывание параметром
///
/// Прокинуть одно вычисление сверху — чище, и для нового экрана я бы
/// так и сделал. Здесь цепочка идёт через пятнадцать свойств
/// полуторатысячестрочного экрана (`плакат` → `тонЭкрана` →
/// `состояниеПоказания` → срез), и каждая правка в ней — шанс сдвинуть
/// то, что человек читает. Величина «сколько собака дома» уже дважды
/// была источником жалоб: «выводили собаку, пишет что не выводили»
/// 23.09 и кадром 24.09.
///
/// # Чем держится свежесть — и это главный вопрос к кешу
///
/// Ключ — отпечаток ТЕХ ПОЛЕЙ, от которых лента зависит. Список взят
/// из кода, а не на память: `TimelineBuilder.blocks` читает `date`,
/// `id`, `kind`, `outcome`, `walkEventID`; `Diary.active` — `deletedAt`;
/// `WalkRhythmAnalyzer.rhythm` — ещё и `origin` (приблизительная
/// дозапись в ритм не идёт).
///
/// **Отпечаток по `events.count` был бы ложным кешем.** Правка
/// существующей записи состава массива не меняет: поправила время
/// прогулки — число записей то же, и устаревший кеш сказал бы старое
/// «дома 4 часа». Такой дефект не ловит ни тест, ни взгляд: экран
/// выглядит работающим, просто цифра не та.
///
/// Поле, появившееся у `LogEvent` позже и попавшее в ленту, обязано
/// попасть и сюда — иначе кеш начнёт врать на нём. Это цена кеша,
/// и она названа здесь, а не в журнале.
@MainActor
final class КешЛенты {
    private var ключ: Int?
    private var значение: СрезЛенты?

    /// Срез для этих записей и этого «сейчас».
    ///
    /// `now` входит в ключ, потому что `дома` отмеряется от него:
    /// экран тикает раз в тридцать секунд, и на каждом тике величина
    /// честно другая.
    func срез(_ события: [LogEvent], now: Date) -> СрезЛенты {
        let новый = отпечаток(события, now: now)
        if новый == ключ, let значение { return значение }

        let живые = Diary.active(события)
        let блоки = TimelineBuilder.blocks(живые)
        let срез = СрезЛенты(
            дома: TimelineBuilder.timeIndoorsNow(блоки, now: now, threshold: 0),
            конецПоследнегоВыхода: блоки.last(where: \.isOuting)?.endedAt,
            ритм: WalkRhythmAnalyzer.rhythm(events: события, now: now)
        )
        ключ = новый
        значение = срез
        return срез
    }

    /// Отпечаток полей, от которых лента зависит.
    ///
    /// Дешевле построения блоков: один проход без сортировки
    /// и без создания структур.
    private func отпечаток(_ события: [LogEvent], now: Date) -> Int {
        var h = Hasher()
        h.combine(события.count)
        h.combine(now.timeIntervalSinceReferenceDate.rounded())
        for e in события {
            h.combine(e.id)
            h.combine(e.date)
            h.combine(e.kindRaw)
            h.combine(e.outcomeRaw)
            h.combine(e.walkEventID)
            h.combine(e.deletedAt)
            h.combine(e.originRaw)
        }
        return h.finalize()
    }
}
