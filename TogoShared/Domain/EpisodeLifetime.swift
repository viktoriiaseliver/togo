import Foundation

/// Сколько живёт эпизод. Правило дизайна («Togo План дизайна», окт 2026,
/// раздел «Режимы с началом и концом»):
///
/// > Эпизод: начало · день · **«закончился»** — `EpisodeCard`.
///
/// То есть у эпизода есть **явный конец, нажатием**, и экран для него
/// нарисован. Это и снимает вопрос, из-за которого правило нельзя было
/// исполнить сразу: автоконец на 48 часах заведён 07.10 как ПОЧИНКА —
/// до него `endedAt` не выставлял никто, эпизод «не заканчивался
/// никогда», и вердикт «просится» замолкал навсегда.
///
/// Замер 07.10.2026: `Episode.endedAt` не присваивает ни одна строка
/// во всём дереве (`grep endedAt` по `Togo/` и `TogoShared/` — только
/// `DayOut`, `HeatRecord` и блоки таймлайна). Значит дороги к концу
/// действительно не было, и автоконец её заменял.
///
/// **Почему правило живёт здесь, а не в модели.** Его спрашивают
/// главный экран, виджет и «остров» — три поверхности, и у Togo
/// записано, чем кончается третья реализация одного правила: виджет
/// считал окно «не кормить» собственной арифметикой, и сторож на вызов
/// был слеп к этому. `Episode.isActive` должен звать отсюда, а не
/// повторять.
nonisolated enum EpisodeLifetime {

    /// Сколько тишины считается концом, когда человек не нажал
    /// «закончился».
    ///
    /// **Это сетка, а не правило.** По дизайну конец ставит человек;
    /// сетка нужна на случай, когда он забыл, — иначе эпизод глушит
    /// вердикт месяцами. Значение то же, что было в модели, чтобы
    /// поведение не поехало вместе с переносом правила.
    static let quietPeriod: TimeInterval = 48 * 3600

    /// Почему эпизод кончился. Нужно не отчёту, а экрану: «закончился»
    /// и «затих сам» — разные новости, и одним текстом их покрывать
    /// нельзя. У Togo за это уже заплатили: ступень отката iCloud
    /// говорила одним текстом на три причины.
    enum End: Sendable, Equatable {
        /// Человек нажал «закончился». Главный случай по дизайну.
        case declared(at: Date)
        /// Никто не нажал, и новых инцидентов нет дольше `quietPeriod`.
        case quiet(since: Date)
    }

    /// Активен ли эпизод.
    ///
    /// Порядок проверок — часть смысла: **объявленный конец сильнее
    /// тишины.** Иначе человек нажал «закончился», а эпизод ожил бы
    /// от того, что инцидент был недавно.
    static func isActive(lastIncidentAt: Date,
                         endedAt: Date?,
                         now: Date = Date()) -> Bool {
        if let endedAt { return now < endedAt }
        return now.timeIntervalSince(lastIncidentAt) < quietPeriod
    }

    /// Чем кончился, если кончился.
    static func end(lastIncidentAt: Date,
                    endedAt: Date?,
                    now: Date = Date()) -> End? {
        if let endedAt, now >= endedAt { return .declared(at: endedAt) }
        guard endedAt == nil else { return nil }
        guard now.timeIntervalSince(lastIncidentAt) >= quietPeriod else { return nil }
        return .quiet(since: lastIncidentAt)
    }

    /// Можно ли сейчас показать кнопку «закончился».
    ///
    /// Отдельная функция, а не `isActive`: кнопку надо скрыть
    /// у законченного эпизода, и если спрашивать это тем же вопросом,
    /// однажды покажут кнопку, которая ничего не делает. У Togo это
    /// уже было — дорога к удалению собаки обещалась текстом
    /// и не существовала.
    ///
    /// **Мест вызова ноль, и подключать НЕЧЕМ: кнопки не существует.**
    /// Замер 05.11.2026 — `EpisodeCard` в дереве нет вовсе, а все
    /// вхождения слова «закончился» про эпизод лежат прозой в этом
    /// файле и в `EpisodeTrigger`; единственное живое — «День
    /// закончился» у выхода (`DayOutScreens.swift:122`), другой
    /// предмет. Контроль того же замера — соседи по этому типу:
    /// `quietPeriod` и `isActive` подключены настоящими вызовами
    /// (`Family.swift:176,182`), то есть модуль живой, и слеп здесь
    /// не инструмент.
    ///
    /// Значит это **не долг на подключение, а ожидание экрана**,
    /// и вопрос о нём адресован Виктории дословно
    /// (`docs/ТЗ-финал-v2-покрытие.md:112-115`): есть кнопка — снимается
    /// автоконец на 48 часах; нет — автоконец остаётся, и править надо
    /// правило дизайна, а не код. Снять эту функцию прежде ответа
    /// значило бы убрать единственную защиту от кнопки, которая ничего
    /// не делает, — до того, как кнопку нарисуют.
    static func canDeclareEnd(lastIncidentAt: Date,
                              endedAt: Date?,
                              now: Date = Date()) -> Bool {
        endedAt == nil && isActive(lastIncidentAt: lastIncidentAt, endedAt: nil, now: now)
    }
}
