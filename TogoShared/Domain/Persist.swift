import Foundation
import SwiftData

extension ModelContext {
    /// Сохранить — или вернуть всё как было и честно сказать «нет».
    ///
    /// **Зачем метод, а не `try?` на месте.** `try? save()` — это молчание:
    /// экран уже нарисовал успех, хранилище о нём не знает, и человек
    /// узнаёт о расхождении в худший момент. Приём был написан для отметок
    /// доз, где цена молчания — вторая таблетка, но жил `private` внутри
    /// `DoseScheduler`, то есть был недоступен ровно там, где нужен:
    /// в восстановлении из файла, в редакторах и в эпизодах. Одна
    /// реализация на всех, а не пятая копия того же `do/catch`.
    ///
    /// **Почему возврат руками, а не `rollback()`.** Проверено на iOS 26
    /// (тест «rollback у SwiftData не возвращает значения» в
    /// `SilentFailureTests`): штатный откат снимает признак изменений,
    /// но **не возвращает значения**. Правленое поле остаётся правленым,
    /// вставленный объект — в связи, а сохранить их потом уже нельзя:
    /// контекст считает себя чистым. То есть `rollback()` делает ровно то,
    /// от чего мы уходим. Поэтому возвращаем ровно те поля, что трогали.
    ///
    /// **Последняя строка здесь была ловушкой и 05.10 сработала.** Стояло:
    /// «покраснеет тот тест — значит Apple починила, и возврат можно
    /// убрать». Apple починила `rollback()` в iOS 27, тест покраснел
    /// на симуляторе 27.0 — и удаление живой защиты выглядело прямо
    /// разрешённым, хотя сломало бы запись дозы у всех, кто не обновился.
    ///
    /// Условие снятия называю поимённо, чтобы его можно было проверить,
    /// а не вспомнить: **убрать ручной возврат можно, когда
    /// `IPHONEOS_DEPLOYMENT_TARGET` станет `27.0`** (сейчас `17.0`,
    /// то есть на iOS 17…26 — восемь поколений — откат по-прежнему
    /// теряет значения). Сам тест теперь версионный и утверждает своё
    /// на обеих ветках.
    ///
    /// > **«Покраснеет — значит можно» верно только там, где у всех
    /// > пользователей одна версия ОС.** У приложения с нижней границей
    /// > 17.0 такого «значит» не бывает: красный тест говорит про новую
    /// > систему, а защита стоит ради старых.
    ///
    /// В самом хранилище при этом ничего не портится: неудавшееся
    /// сохранение не доходит до файла, и прежнее значение там остаётся.
    ///
    /// Результат намеренно **не** помечен `@discardableResult`: ответ «нет»
    /// обязан быть прочитан, иначе метод стал бы тем же `try?`, только
    /// длиннее.
    @MainActor
    func persist(otherwise вернуть: () -> Void) -> Bool {
        do {
            try save()
            return true
        } catch {
            вернуть()
            return false
        }
    }

    /// То же, когда возвращать нечего: вставки не было, полей не трогали,
    /// и при отказе состояние в памяти и так совпадает с хранилищем.
    ///
    /// Отдельное имя, а не `persist(otherwise: {})`: пустые фигурные скобки
    /// в вызове читаются как «возврат забыли написать», и отличить забытый
    /// возврат от ненужного было бы нельзя.
    @MainActor
    func persistNothingToUndo() -> Bool {
        persist(otherwise: {})
    }
}
