import Foundation

/// Когда начинается эпизод. Правило нового дизайна, раздел
/// «7 · Режимы · матрица и эпизод» (`Togo ФИНАЛ v2`, окт 2026):
///
/// > Эпизод включается **третьим жидким стулом или кровью** и живёт
/// > **до явного «закончился»**.
///
/// # Это правило РАСХОДИТСЯ с живым кодом в двух местах
///
/// Замер 07.10.2026, `TogoShared/Models/Family.swift:70-100`:
///
///     | вопрос   | код сейчас                        | дизайн ФИНАЛ v2        |
///     |----------|-----------------------------------|------------------------|
///     | начало   | два инцидента за 24 ч ИЛИ подряд  | третий жидкий стул     |
///     |          | идущие дни с жидким стулом        | ИЛИ кровь              |
///     | конец    | 48 ч тишины, автоматически        | явное «закончился»     |
///
/// **Второе расхождение опасное, и поэтому оно здесь не исполнено.**
/// Автоконец на 48 часах — не недосмотр, а ПОЧИНКА, и она описана
/// в том же файле: до неё `endedAt` не выставлял никто, `isActive`
/// без него возвращал `true`, и «эпизод не заканчивался никогда».
/// Следствие человек видел: после двух инцидентов за сутки вердикт
/// «просится» замолкал навсегда, и причину понять было нельзя.
///
/// Перейти на «только явное „закончился“», не заведя кнопки, значит
/// вернуть ровно тот дефект. У нас это записано классом: **правка
/// по верхней записи, пережившей своё решение**, и сегодня он
/// выстрелил трижды.
///
/// Поэтому здесь сделана **только половина, у которой расхождения
/// нет** — повод НАЧАТЬ. Конец эпизода остаётся за `Episode.isActive`
/// и `quietPeriod` до решения Виктории; вопрос назван в
/// `docs/ТЗ-финал-v2-покрытие.md` и не закрыт молча.
///
/// # Что считается поводом
///
/// Два независимых повода, каждый сам по себе достаточен:
///
/// * **третий жидкий стул** — именно третий, а не третий подряд:
///   считается по окну, см. `window`;
/// * **кровь** — с первого раза, без счёта. У `StoolFlags.blood`
///   и `VomitContent.blood` в коде уже стоит `raisesAlarm == true`,
///   то есть продукт и так считает это поводом поднять тревогу;
///   эпизод от этого отличается длительностью, а не порогом.
///
/// # Мест вызова ноль, и это РЕШЕНИЕ — проверено, а не предположено
///
/// Замер 05.11.2026: у `reasonToStart` и `looseUntilStart` ноль мест
/// вызова, а два вхождения имени `EpisodeTrigger` вне этого файла —
/// **проза** (`CourseFinishSheet.swift:38`, `PosterMode.swift:51`).
/// Контроль того же замера взят соседним модулем, чтобы ломаться
/// вместе с предметом: у `EpisodeLifetime` имя вне своего файла
/// читают настоящие вызовы (`Family.swift:176,182`), то есть
/// инструмент видит подключённый домен.
///
/// **Удалять нельзя: причина названа, и она про ЧТО, а не про долг.**
/// Начало эпизода здесь исполнено по дизайну ФИНАЛ v2, а живой код
/// (`Family.swift:70-100`) считает по прежнему правилу; переключить
/// одно на другое — продуктовое решение, потому что вторая половина
/// (конец эпизода) без кнопки возвращает починенный дефект. Вопрос
/// задан Виктории дословно и не закрыт молча:
/// `docs/ТЗ-финал-v2-покрытие.md:104-115` — «кнопка „эпизод
/// закончился" на экране есть?».
///
/// Тесты у этих двух функций зелены и аргументы подают сами — значит
/// они держат **правило дизайна**, а не поведение приложения, и
/// покраснеть на правке продукта не могут. Это цена отложенного
/// решения, а не дыра в приёмке.
nonisolated enum EpisodeTrigger {

    /// За какое время считаются «три жидких».
    ///
    /// **Число не из дизайна — там его нет, и это сказано вслух.**
    /// Текст правила говорит «третьим жидким стулом», не называя окна.
    /// Взято 24 часа, и вот довод: рядом в том же файле живёт порог
    /// «два инцидента за 24 часа», то есть у продукта уже есть единица
    /// измерения вспышки, и заводить вторую значит получить два правила
    /// на одну мысль. Если Виктория назовёт другое окно — меняется
    /// одна эта величина.
    ///
    /// Записано здесь, а не в голове: число без названной границы
    /// следующий поднимет, число с границей — переживёт.
    static let window: TimeInterval = 24 * 3600

    /// Сколько жидких за окно начинают эпизод.
    static let looseCount = 3

    /// Повод, по которому эпизод начался. Нужен не для отчёта,
    /// а для текста на экране: «третий жидкий за сутки» и «кровь» —
    /// разные новости, и одним текстом их покрывать нельзя.
    ///
    /// У Togo это уже стоило работы: ступень отката iCloud говорила
    /// одним текстом на три причины, и совет в нём двум из трёх
    /// не помогал ничем.
    enum Reason: Sendable, Equatable {
        /// Третий жидкий стул за окно.
        case thirdLoose(count: Int)
        /// Кровь — в стуле или в рвоте.
        case blood
    }

    /// Одно наблюдение, по которому решается вопрос. Плоская структура
    /// вместо `LogEvent` нарочно: правило надо уметь спросить из теста
    /// и из выгрузки, не поднимая хранилище.
    struct Observation: Sendable, Equatable {
        let date: Date
        /// Был ли стул жидким. Про рвоту — `false`: она попадает сюда
        /// только кровью.
        let isLooseStool: Bool
        /// Видна ли кровь — в стуле или в рвоте, всё равно.
        let hasBlood: Bool

        init(date: Date, isLooseStool: Bool, hasBlood: Bool) {
            self.date = date
            self.isLooseStool = isLooseStool
            self.hasBlood = hasBlood
        }
    }

    /// Начинать ли эпизод, и по какому поводу. `nil` — не начинать.
    ///
    /// Кровь проверяется ПЕРВОЙ и без счёта: иначе первая кровь
    /// при одном жидком не дала бы ничего, а правило говорит «или».
    /// Порядок здесь часть смысла — тот же класс, что «вопрос слабее
    /// дефекта, который он ищет».
    static func reasonToStart(_ observations: [Observation],
                              now: Date = Date(),
                              window: TimeInterval = window) -> Reason? {
        let recent = observations.filter {
            let age = now.timeIntervalSince($0.date)
            // Наблюдение «из будущего» — разъехавшиеся часы двух
            // устройств общего дневника, а не причина его выбросить.
            return age < window
        }
        if recent.contains(where: \.hasBlood) { return .blood }
        let loose = recent.filter(\.isLooseStool).count
        guard loose >= looseCount else { return nil }
        return .thirdLoose(count: loose)
    }

    /// Сколько жидких ещё нужно, чтобы эпизод начался. Ноль — уже
    /// начинается.
    ///
    /// Показывается не человеку, а разработчику и тесту: утверждение
    /// «эпизод не начался» без числа неотличимо от «правило не
    /// сработало». Ровно то, за что у нас заведено требование
    /// печатать границы собственного умения.
    static func looseUntilStart(_ observations: [Observation],
                                now: Date = Date(),
                                window: TimeInterval = window) -> Int {
        let loose = observations
            .filter { now.timeIntervalSince($0.date) < window }
            .filter(\.isLooseStool)
            .count
        return max(0, looseCount - loose)
    }
}
