import Foundation

/// Срез для виджетов и локскрина.
///
/// Виджет не лезет в базу: приложение кладёт в общее хранилище маленький
/// снимок, а виджет его читает. Так виджет не зависит от схемы SwiftData
/// и не может подвиснуть на миграции.
nonisolated struct WidgetSnapshot: Codable, Equatable, Sendable {
    var dogName: String

    /// Буква клички для кружка-жетона.
    ///
    /// **С 23.10.2026 читателя нет, и это СЛЕДСТВИЕ РЕДИЗАЙНА,
    /// а не недосмотр.** До «Кино» её рисовал кружок в малом виджете
    /// (`TodayWidgetView`, бывшие строки 70-74). Эталон `16.png`
    /// малую плитку без клички и без жетона рисует вовсе: опознание
    /// собаки макет отдал СРЕДНЕМУ виджету («Стич · дальше»).
    ///
    /// Пометка заведена шестой к пяти прежним по правилу этого файла:
    /// появится читатель — строка станет ложной, и
    /// `grep ЧИТАТЕЛЯ-НЕТ-dogInitial` её найдёт.
    ///
    /// > **Вопрос, который это открывает, не инженерный.** У двух собак
    /// > малая плитка теперь неразличима — а вторая собака продаётся
    /// > в Pro. Соседний слой решил это иначе и по замеру: `inlineText`
    /// > держит кличку в ХВОСТЕ строки именно затем, чтобы «две собаки
    /// > не дали две одинаковые строки», и платит за это обрезкой.
    /// > Малая плитка такой платы не вносит, потому что макет
    /// > одно-собачий. **Решает Виктория**, и это не починка.
    ///
    /// Поле ни убрано, ни показано нарочно: убрать — правка снимка
    /// при живом писателе (`LiveActivityController:79`), показать —
    /// продуктовое решение, а его принимает не сессия.
    var dogInitial: String   // ЧИТАТЕЛЯ-НЕТ-dogInitial
    /// Текст вердикта «просится» — уже посчитанный, без логики на стороне виджета.
    var verdictTitle: String
    /// Подпись под вердиктом — **её не читает НИКТО.**
    ///
    /// **И она не одна: таких полей здесь ПЯТЬ из пятнадцати.**
    /// Замер 07.10.2026 по всему дереву, включая тесты:
    ///
    /// ```
    /// verdictBadge        ни одного чтения
    /// lastStoolSummary    ни одного чтения
    /// lastWalkSummary     ни одного чтения
    /// walkStartedBy       ни одного чтения
    /// updatedAt           ни одного чтения
    /// контроль            dogName 6 · urineSilenceSince 3 · mealsPlanned 3
    ///                     verdictTitle 2 · dogInitial 1 — разбор видит чтения
    /// ```
    ///
    /// То есть **треть снимка** считается, кодируется, кладётся в общее
    /// хранилище App Group и уезжает в расширение — и не показывается
    /// никому. У `walkStartedBy` ловушка отдельная: единственное
    /// совпадение по тексту — `appState.walkStartedBy` на строке ЗАПИСИ,
    /// то есть чужое свойство с тем же именем. Первая редакция этого
    /// замера сочла его читаемым.
    ///
    /// Замер 07.10.2026 (`togo-02`, перемерен этой сессией с контролем):
    ///
    /// ```
    /// пишут    WidgetSnapshot.empty · WidgetGallery ×2 · LiveActivityController
    /// читают   ни одного места
    /// контроль snapshot.verdictTitle читается дважды в TodayWidgetView
    ///          — значит разбор видит чтения, когда они есть
    /// ```
    ///
    /// Поле считается из настоящего вердикта, кладётся в снимок App
    /// Group, уезжает в расширение — и показывается никому. Это зеркало
    /// нашего «имя упомянуто, и от упоминания ничего не происходит»:
    /// там бессилен вызов, здесь **значение некому прочесть**.
    ///
    /// И оно объясняет, почему русское слово в этой строке никто
    /// не замечал: его и по-русски не видел никто.
    ///
    /// **Ни убрано, ни показано, и это решение.** Убрать — правка кода
    /// при замороженном дизайне; показать — продуктовое решение, а его
    /// принимает не сессия. Поэтому поле помечено: **читателя нет;
    /// появится — эта строка станет ложной, и
    /// `grep ЧИТАТЕЛЯ-НЕТ-verdictBadge` её найдёт.**
    ///
    /// Пометка стоит и у каждой из четырёх записей: четыре места —
    /// четыре человека, которые думают, что делают работу.
    var verdictBadge: String   // ЧИТАТЕЛЯ-НЕТ-verdictBadge
    var sinceUrineSeconds: Double?
    /// Дата, с которой про мочу нечего сказать, — если `UrineSilence`
    /// так решил. Не пусто ⇒ виджет печатает дату, а число не печатает
    /// вовсе, каким бы оно ни было.
    ///
    /// **Решение приезжает готовым нарочно.** Виджету хватило бы
    /// `sinceUrineSeconds`, чтобы сравнить с сутками самому, — и это
    /// ровно тот дефект, на котором Togo уже обжигался: окно «не кормить»
    /// виджет считал собственной арифметикой и молчал в двух случаях
    /// из трёх, пока главный экран знал правило. Сторож на вызов такого
    /// не видит: звать нечего.
    var urineSilenceSince: Date?
    var lastStoolSummary: String?   // ЧИТАТЕЛЯ-НЕТ-lastStoolSummary
    var lastWalkSummary: String?   // ЧИТАТЕЛЯ-НЕТ-lastWalkSummary
    var walkStartedAt: Date?
    var walkStartedBy: String?   // ЧИТАТЕЛЯ-НЕТ-walkStartedBy

    /// Когда закончился последний выход — **датой, а не фразой**.
    ///
    /// Заведено 23.10.2026 под «Кино»: эталон `16.png` показывает малый
    /// виджет как «С прогулки · 2:11», то есть ЧИСЛО, которое идёт.
    /// Рядом уже лежал `lastWalkSummary` — и он не годится дважды:
    /// это готовая строка («гулял 2 ч назад»), она застывает в момент
    /// публикации и к следующему пробуждению виджета врёт на пятнадцать
    /// минут, а `Text(_, style: .timer)` ей не воспользуется вовсе.
    ///
    /// **Старое поле не тронуто и остаётся без читателя.** Убрать его —
    /// правка чужого решения (пометка `ЧИТАТЕЛЯ-НЕТ` стоит там с хозяином),
    /// а подменить им это значило бы снова считать время строкой.
    ///
    /// Необязательное нарочно: у `Codable` синтезируется
    /// `decodeIfPresent`, поэтому снимок, записанный прежней версией
    /// приложения, читается без ошибки и даёт `nil`. Виджет живёт
    /// в другом процессе и просыпается на старых данных **штатно**,
    /// а не в виде исключения.
    var lastWalkAt: Date?
    var fastingEndsAt: Date?

    /// Еда: когда в последний раз и сколько из запланированного.
    ///
    /// Замер 23.09.2026 по журналу с телефона: пять сессий из
    /// четырнадцати начинаются с записи еды, и еда — самое частое
    /// действие вообще. Приложение открывают, чтобы покормить,
    /// а виджет об этом не говорил ничего.
    var lastMealAt: Date?
    var mealsToday: Int
    var mealsPlanned: Int

    var updatedAt: Date   // ЧИТАТЕЛЯ-НЕТ-updatedAt

    /// Заглушка виджета — **её человек видит**, а не только мы.
    ///
    /// `TodayWidget.swift:25` отдаёт её из `placeholder(in:)`: это
    /// и галерея при добавлении виджета, и то, что стоит на экране,
    /// пока снимок не прочитан.
    ///
    /// **Три слова здесь рисовались по-русски на любом языке.** Литерал
    /// в `String`-поле — это ЗНАЧЕНИЕ, и до каталога оно не доходит;
    /// `Text(значение)` печатает его дословно. Тот же класс, что
    /// `dog?.name ?? "Собака"` на тридцати поверхностях, только здесь
    /// не про пустоту, а про язык.
    ///
    /// Новых ключей это не заводит: «Собака», «Просится» и «нет данных»
    /// лежат в каталоге на всех четырёх языках. Слова не меняются —
    /// текст заморожен решением Виктории 07.10.2026; меняется только
    /// дорога, которой они идут на экран.
    ///
    /// **Сузить сказанное: из трёх слов до экрана доезжают ДВА.**
    /// «Собака» и «Просится» читаются, «нет данных» — нет:
    /// у `verdictBadge` читателя не существует. То есть локализация
    /// этого слова верна и недостижима, и говорить «локализовали
    /// заглушку» без оговорки — шире сделанного.
    ///
    /// **Адреса читателей здесь НОМЕРОВ СТРОК БОЛЬШЕ НЕ НЕСУТ** — правка
    /// 23.10.2026. Прежняя редакция называла `TodayWidgetView:39,51,61`,
    /// и редизайн «Кино» переписал этот файл целиком: три номера стали
    /// ложными разом, а заметить это было некому — номер строки
    /// не краснеет. Читатели называются ИМЕНАМИ, которые переживают
    /// перенос:
    ///
    /// ```
    /// «Собака»   SnapshotText.inlineText (все три ветви) · подписьДальше
    /// «Просится» TodayWidgetView.шапкаПлитки (ветвь .словами) · средний
    /// проверка   git grep -nP 'verdictTitle|snapshot\.dogName' -- '*.swift'
    /// ```
    static let empty = WidgetSnapshot(
        dogName: String(localized: "Собака"),
        dogInitial: "?",
        verdictTitle: String(localized: "Просится"),
        // ЧИТАТЕЛЯ-НЕТ-verdictBadge: перевод верен и недостижим
        verdictBadge: String(localized: "нет данных"),
        sinceUrineSeconds: nil,
        urineSilenceSince: nil,
        lastStoolSummary: nil,
        lastWalkSummary: nil,
        walkStartedAt: nil,
        walkStartedBy: nil,
        lastWalkAt: nil,
        fastingEndsAt: nil,
        lastMealAt: nil,
        mealsToday: 0,
        mealsPlanned: 0,
        updatedAt: .distantPast
    )
}

/// Мост между приложением и виджетами. Одно место записи и одно чтения.
nonisolated enum WidgetBridge {
    static let key = "widget.snapshot"

    static var defaults: UserDefaults {
        UserDefaults(suiteName: AppIdentifiers.appGroup) ?? .standard
    }

    static func publish(_ snapshot: WidgetSnapshot) {
        guard let data = try? JSONEncoder().encode(snapshot) else { return }
        defaults.set(data, forKey: key)
    }

    static func read() -> WidgetSnapshot {
        guard let data = defaults.data(forKey: key),
              let snapshot = try? JSONDecoder().decode(WidgetSnapshot.self, from: data)
        else { return .empty }
        return snapshot
    }
}
