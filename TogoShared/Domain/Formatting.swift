import Foundation

nonisolated enum Fmt {

    // MARK: Кличка

    /// Кличка, годная для показа, — или `nil`.
    ///
    /// **Единственная реализация правила «что считать кличкой».**
    /// Её зовут `Dog.nameIfAny` и `Dog.displayName`
    /// (все поверхности приложения), `DogPayload.hasUsableName` (приём
    /// снимка из общего дневника и восстановление архива), `SnapshotText`
    /// и `TodayWidgetView` («остров», виджет, экран блокировки).
    ///
    /// **Почему правило живёт здесь, а не на `Dog`.** У виджета модели
    /// нет вовсе: ему достаётся снимок с полем `dogName: String`,
    /// записанный приложением раньше — может быть, прошлой сборкой.
    /// Правило, доступное только через модель, до него не дотянулось бы,
    /// и у «острова» завелась бы вторая реализация. У нас записано
    /// и оплачено: третья реализация одного правила молчала в двух
    /// случаях из трёх.
    ///
    /// Пробелы снимаются вместе с переводами строк и неразрывным
    /// пробелом U+00A0 — последний приезжает опечаткой с французской
    /// клавиатуры и рисуется ровно так же пусто, как `""`.
    /// Имя латиницей — след обхода, который **уже не нужен**, и это
    /// честнее, чем переименовать обратно.
    ///
    /// Первая редакция звалась `Fmt.кличка` и дала два ложных
    /// срабатывания в `LocalizationDebtTests`: тот разбирал литералы
    /// посимвольно и считал кириллицу внутри `"…\(…)…"` непереведённой
    /// строкой. Тогда функцию переименовали, а сторожа оставили как был.
    ///
    /// **Сторож починен в тот же день**: тело интерполяции он теперь
    /// разбирает рекурсивно, как код, и у него есть тест на самого себя
    /// (`разборРазличаетКодИСтроку`). То есть кириллическое имя здесь
    /// снова законно.
    ///
    /// Переименовывать обратно я не стал: тридцать три поверхности
    /// ради вкуса — чужой риск без выгоды. Но причина осталась
    /// записанной, чтобы следующий не считал латиницу здесь правилом
    /// проекта.
    static func dogName(_ raw: String) -> String? { notBlank(raw) }

    /// Непустое значение — или `nil`.
    ///
    /// **То же правило, что у клички, но у него нашлись другие
    /// хозяева.** 07.10.2026 перечисление группировок показало, что
    /// по полю со значением по умолчанию склеиваются не только собаки:
    /// имя участника семьи, место и человек у шага дрессировки — все
    /// `String = ""`. Поэтому правило живёт отдельно от `dogName`,
    /// а `dogName` стала его именем для случая собаки: имя у места
    /// вызова важнее, чем экономия строки.
    static func notBlank(_ raw: String) -> String? {
        let чистая = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        return чистая.isEmpty ? nil : чистая
    }

    /// То же, но с запасным словом из каталога.
    ///
    /// `String(localized:)` **внутри** функции, а не литералом на месте
    /// вызова: возвращается ЗНАЧЕНИЕ типа `String`, и `Text(значение)`
    /// рисует его мимо каталога локализации. Напиши литерал снаружи —
    /// и француз прочтёт русское слово на объявлении о пропаже собаки.
    /// **ЗАПАСНОЕ СЛОВО ЧЕРНОВОЕ — до правки текстов.** Решение
    /// Виктории 07.10.2026: дизайн будет меняться, тексты сегодня
    /// не трогаем. Слово взято самое скучное и уже лежавшее
    /// в каталоге, чтобы не заводить новый вариант. Форма слова
    /// по поверхностям («Собака» в заголовке, «с собакой» в строке) —
    /// текстовая работа, и она НЕ сделана.
    ///
    /// Найти при правке текстов: `grep ЧЕРНОВОЕ-ЗАПАСНОЕ-СЛОВО`.
    /// Пометка станет ложной ровно тогда, когда тексты поправят.
    static func dogNameOrFallback(_ raw: String) -> String {
        // ЧЕРНОВОЕ-ЗАПАСНОЕ-СЛОВО
        dogName(raw) ?? String(localized: "Собака")
    }

    /// «20:00» в России и «8:00 PM» в США — цикл суток выбирает ЛОКАЛЬ.
    ///
    /// # Замер 04.11.2026: `amPM: .omitted` снимал маркер, а час не переводил
    ///
    /// Здесь стояло
    /// `.hour(.twoDigits(amPM: .omitted)).minute(.twoDigits)`. Прочитать
    /// это можно было как «печатаем 24-часовой вид», и так и читали —
    /// но `.omitted` убирает только **указатель**, оставляя час
    /// двенадцатичасовым. В локали с 12-часовыми сутками выходило:
    ///
    /// ```
    /// 20:00  en_US   «08:00»   ← двенадцать часов разницы, без признака
    /// 15:46  en_US   «03:46»
    /// 09:22  en_US   «09:22»   ← ДО ПОЛУДНЯ СОВПАДАЕТ
    /// 20:00  ru_RU   «20:00»   ← и во всех остальных наших языках тоже
    /// ```
    ///
    /// Последние две строки и есть причина, по которой дефект прожил
    /// 71 день: из пяти языков каталога (`ru`, `uk`, `fr`, `kk`, `en`)
    /// четыре 24-часовые, а витрину снимали на 09:22 — в час, когда оба
    /// вида совпадают посимвольно. **Форма, которая врёт только после
    /// полудня и только в одной локали, зелена у всех, кто не смотрел
    /// туда.** Поймал её кадр, у которого контроль лежал внутри:
    /// `витрина-пять-языков-23.10/01-today-en-US.png` — статус-бар iOS
    /// (его рисует СИСТЕМА) показывает 15:46, а наша строка «now» —
    /// 03:46.
    ///
    /// # Почему локаль, а не принудительные 24 часа
    ///
    /// Решение по тому, что прочитает человек, а не по длине кода:
    ///
    /// 1. **Рядом с нашей строкой всегда стоит системная.** В списке
    ///    уведомлений iOS сам ставит на строку свою метку времени, и она
    ///    12-часовая на американском телефоне. Наш текст внутри той же
    ///    строки — наше дело, метка — не наше, переопределить её нечем.
    ///    «20:00» рядом с «8:00 PM» на одной строке читается как
    ///    расхождение.
    /// 2. **Выбор у человека уже есть.** Настройки → Основные → Дата
    ///    и время → «24-часовой формат» меняет `Locale`, и
    ///    `.autoupdatingCurrent` идёт за ним. Принудительные 24 часа
    ///    отменили бы решение, которое владелец уже принял; локаль его
    ///    исполняет — американец, которому нужны 24 часа, их получает.
    /// 3. **Вред здесь — двусмысленность, а не чужеродность.** «08:00»
    ///    вместо дозы в 20:00 не просто непривычно, оно **уверенно
    ///    неверно**. «8:00 PM» прочитать иначе нельзя.
    ///
    /// Так же решено у соседнего проекта (`Timer`, `AppFormat.clock`),
    /// и оттуда же взята поправка, которую легко потерять: **цикл суток
    /// идёт от РЕГИОНА, а не от языка интерфейса.** Замер подтвердил
    /// её и здесь — `ru_US` даёт «8:00 PM». Поэтому локаль берётся
    /// целиком и язык из неё не подменяется, в отличие от
    /// `HistoryScreen.weekdays`, где предмет как раз язык.
    ///
    /// # Локаль параметром, а не из `Locale.current` внутри
    ///
    /// Та же причина, что у `decimal(_:локаль:)` строкой ниже: иначе
    /// сторож не спросит два языка в одном замере и приёмка будет
    /// словом, а не числом. Умолчание оставляет все 90 мест вызова
    /// нетронутыми — правка живёт в одном файле.
    static func clock(_ date: Date, локаль: Locale = .autoupdatingCurrent) -> String {
        date.formatted(.dateTime.hour().minute().locale(локаль))
    }

    /// Тот же час, записанный минутами от полуночи (расписание доз).
    ///
    /// # Вторая половина того же дефекта
    ///
    /// Здесь стояло `String(format: "%02d:%02d", …)` — **всегда**
    /// 24 часа, при любой локали. То есть на одном экране «Здоровье»
    /// время дозы из расписания и время дозы из журнала расходились
    /// на двенадцать часов, и это было устройство, а не случай:
    /// одна функция печатала «20:00», соседняя — «08:00».
    ///
    /// Чинить полагается обе разом, иначе починенная половина делает
    /// расхождение только заметнее.
    ///
    /// # Почему опора собирается и печатается в GMT
    ///
    /// `minuteOfDay` — это **отвлечённое время на часах**, а не момент:
    /// 1320 обязано печататься как «22:00» в Париже, в Алматы и в полёте.
    /// Собери опору в поясе устройства — и перевод часов дважды в год
    /// сдвинул бы час дозы: `начало суток + 1320 минут` в день
    /// перевода даёт 21:00 либо 23:00. Один пояс на обе операции
    /// снимает вопрос целиком, а не прячет его в редкий день.
    ///
    /// Возврат к `String(format:)` в `guard` — не «тихий откат»:
    /// `DateComponents` с часом 0…23 и минутой 0…59 в григорианском
    /// календаре GMT не может не собраться, и ветка существует только
    /// потому, что у API тип опциональный.
    static func clock(minuteOfDay: Int, локаль: Locale = .autoupdatingCurrent) -> String {
        // Отрицательные и «за сутки» сворачиваем, а не обрезаем: минус
        // у `%` в Swift берёт знак делимого, и -30 дало бы «00:-30».
        let минут = ((minuteOfDay % 1440) + 1440) % 1440
        var календарь = Calendar(identifier: .gregorian)
        календарь.timeZone = .gmt
        guard let опора = календарь.date(from: DateComponents(year: 2001, month: 1, day: 1,
                                                              hour: минут / 60,
                                                              minute: минут % 60))
        else { return String(format: "%02d:%02d", минут / 60, минут % 60) }
        var стиль = Date.FormatStyle.dateTime.hour().minute().locale(локаль)
        стиль.timeZone = .gmt
        return стиль.format(опора)
    }

    static func dayTitle(_ date: Date) -> String {
        date.formatted(.dateTime.weekday(.wide)) + " · " + date.formatted(.dateTime.day().month(.wide))
    }

    static func shortDay(_ date: Date) -> String {
        date.formatted(.dateTime.day().month(.abbreviated))
    }

    /// «октябрь 2026» — заголовок группы документов.
    ///
    /// Год стоит всегда, а не «только если не этот»: документы ищут
    /// за прошлые годы чаще, чем за текущий («когда делали прививку»),
    /// и заголовок без года заставил бы считать от сегодняшнего дня.
    ///
    /// Месяц и год печатает система по локали — склеивать их литералом
    /// нельзя: порядок частей у языков разный.
    static func monthTitle(_ date: Date) -> String {
        date.formatted(.dateTime.month(.wide).year())
    }

    /// «5 ч 20 мин» — так же, как в макете, без «5:20:00».
    ///
    /// Единицы печатает система, а не мы. Раньше «ч» и «мин» были
    /// склеены литералами, и у француза выходило «5 ч 20 мин» при
    /// французском интерфейсе. Замер 23.09: системный вывод по-русски
    /// совпадает с прежним посимвольно — «25 мин», «2 ч», «5 ч 20 мин».
    static func duration(_ interval: TimeInterval) -> String {
        часыМинуты(секунд: max(0, Int(interval)))
    }

    /// Часы и минуты средствами системы: ноль-единицы прячем, чтобы
    /// «2 ч» не превращалось в «2 ч 0 мин».
    private static func часыМинуты(секунд: Int) -> String {
        Duration.seconds(секунд).formatted(
            .units(allowed: [.hours, .minutes], width: .abbreviated,
                   maximumUnitCount: 2, zeroValueUnits: .hide))
    }

    /// Число с одним знаком после запятой — и без него, если знак нулевой.
    /// «4 раза в день» читается, «4,0 раза» выглядит отчётом.
    ///
    /// # Разделитель берётся у ЛОКАЛИ, а не прибит запятой
    ///
    /// Замер 28.10.2026. Здесь стояло
    /// `replacingOccurrences(of: ".", with: ",")` — запятая **жёстко**,
    /// при любом языке, то есть англичанин видел `4,5` там, где у него
    /// `4.5`. Это ровно тот дефект, который `LabNumberParsing.показать`
    /// получил в починку 26.10 вместе с разбором; **решение было
    /// принято, но до этой функции не доехало**, хотя обе лежат
    /// в одном слое и зовутся с соседних экранов.
    ///
    /// Разводить два правила про формат одного числа приходится
    /// каждый раз заново, поэтому различитель повторён здесь:
    ///
    /// ```
    /// РАЗРЯДНОСТЬ  сколько знаков. Один знак — решение ПРО ВЕС,
    ///              на медицинском числе это потеря данных, и для
    ///              него есть `числоБезПотери`. Правкой не задето
    /// РАЗДЕЛИТЕЛЬ  запятая или точка. Вид одного числа, данных
    ///              не теряет, обязан идти по локали
    /// ```
    ///
    /// Локаль **параметром с умолчанием**, а не из `Locale.current`
    /// внутри: иначе сторож не спросит два языка в одном замере,
    /// и приёмка будет словом, а не числом. Форма — та же, что
    /// у `показать`, нарочно: две функции одного рода, собранные
    /// по-разному, и разошлись они молча.
    static func decimal(_ value: Double, локаль: Locale = .current) -> String {
        guard value != value.rounded() else { return String(Int(value)) }
        let разделитель = локаль.decimalSeparator ?? "."
        return String(format: "%.1f", value)
            .replacingOccurrences(of: ".", with: разделитель)
    }

    /// Часы и минуты для героя.
    ///
    /// Секундомер здесь не годится — он считает минуты и секунды,
    /// и два с половиной часа превращались в «165:16».
    ///
    /// Раньше здесь стояло сокращение «м» вместо «мин» — решение
    /// макета. Оно стоило локализации: собрать «2 ч 12 м» на любом
    /// языке, кроме русского, нечем. Единицы печатает система.
    static func hoursMinutes(_ interval: TimeInterval) -> String {
        часыМинуты(секунд: max(0, Int(interval) / 60) * 60)
    }

    /// Порядковое числительное для строки «третий раз за шесть часов».
    ///
    /// Дальше десятого не идём: если рвота случилась одиннадцать раз,
    /// человек уже в клинике, а не читает подпись.
    static func ordinal(_ value: Int) -> String {
        let words = ["", String(localized: "первый"), String(localized: "второй"), String(localized: "третий"), String(localized: "четвёртый"), String(localized: "пятый"),
                     String(localized: "шестой"), String(localized: "седьмой"), String(localized: "восьмой"), String(localized: "девятый"), String(localized: "десятый")]
        return words.indices.contains(value) ? words[value] : String(localized: "\(value)-й")
    }

    /// Промежуток для ленты: коротко и без ложной точности.
    ///
    /// «4 ч 58 мин» между записями — это точность, которой там неоткуда
    /// взяться и которая никому не нужна: промежуток читают глазами,
    /// чтобы понять порядок величины. Округляем до получаса, а после двух
    /// часов минуты выбрасываем совсем.
    static func gap(_ interval: TimeInterval) -> String {
        let minutes = max(0, Int(interval / 60))
        if minutes < 90 { return String(localized: "\(minutes) мин") }

        let hours = Double(minutes) / 60
        if minutes >= 120 { return часыМинуты(секунд: Int(hours.rounded()) * 3600) }

        // Округление осталось прежним, сменилась только печать: считаем
        // получасами, а единицы называет система.
        let half = (Double(minutes) / 30).rounded() * 30
        return часыМинуты(секунд: Int(half) * 60)
    }

    static func stopwatch(_ interval: TimeInterval) -> String {
        let total = max(0, Int(interval))
        return String(format: "%d:%02d", total / 60, total % 60)
    }

    /// Вес: единицу и разделитель дробной части выбирает система.
    /// Было `String(format: "%.1f кг")` с ручной заменой точки на запятую —
    /// и «кг» намертво по-русски.
    /// Доза вещества из микрограммов — в читаемую строку.
    ///
    /// **Единственное место перевода мкг → мг в проекте.** Хранится
    /// всегда в микрограммах (`Medication.massPerUnitMcg`), и единицы
    /// рядом с числом нет: пара «значение + единица» позволяет сложить
    /// `0,1 мг` с `50 мкг`, а множитель между ними — тысяча.
    ///
    /// > **Перевод, случающийся в одном месте, нельзя сделать
    /// > по-разному в двух.**
    ///
    /// Порог 1000 мкг, а не «красивее»: ниже тысячи врачи и бланки
    /// говорят микрограммами («66 мкг», «264 мкг/сут» в карте Стича),
    /// выше — миллиграммами. Знаки НЕ округляются до одного:
    /// `Fmt.decimal` писан для веса, и `16,75` он превратил бы
    /// в `16,8` — на медицинском числе это потеря данных.
    static func doseMass(_ mcg: Double) -> String {
        guard mcg > 0 else { return String(localized: "не указана") }
        if mcg < 1000 {
            return "\(числоБезПотери(mcg)) " + String(localized: "мкг")
        }
        return "\(числоБезПотери(mcg / 1000)) " + String(localized: "мг")
    }

    /// Число со всеми знаками и разделителем локали. Намеренно
    /// НЕ `decimal(_:)`: тот округляет до одного знака.
    ///
    /// **Разделитель по локали — замер 28.10.2026, третье место
    /// того же дефекта.** Здесь запятая стояла жёстко, и это
    /// **доза лекарства**: англичанин читал `0,1 мг` там, где у него
    /// `0.1 mg`. У нас на этот разряд красная линия — «не подставлять
    /// там, где подстановка станет утверждением человека», — и вид
    /// числа дозы человек предъявляет врачу.
    ///
    /// `String(число)` печатает точку независимо от локали: это
    /// описание `Double`, а не формат. Поэтому замена идёт от точки
    /// и ровно одна, а у целого разделителя нет вовсе.
    private static func числоБезПотери(_ число: Double,
                                       локаль: Locale = .current) -> String {
        guard число != число.rounded() else { return String(Int(число)) }
        let разделитель = локаль.decimalSeparator ?? "."
        return String(число).replacingOccurrences(of: ".", with: разделитель)
    }

    /// Вес для показа. **Ноль — это «не записан», а не «ноль».**
    ///
    /// # Замер 25.10.2026
    ///
    /// ```
    /// 0,0  → «0,0 г»     ← ЛОЖЬ: вес не вводили, а нарисовано число
    /// 0,4  → «400,0 г»   ← ВЕРНО: щенок четыреста граммов
    /// 4,1  → «4,1 кг»
    /// ```
    ///
    /// Единицу меняет сама `Measurement` с `usage: .personWeight`,
    /// и для щенка это правильно — поэтому гасится **только ноль**,
    /// а не «всё, что меньше килограмма».
    ///
    /// # Почему это стало дороже именно сегодня
    ///
    /// Дефект известен с отзыва TestFlight 06.10.2026 («Много пустых
    /// собак», сборка 271) и тогда лечился с другого конца: закрыли
    /// путь приёма записей без клички. Но 25.10 **вес перестал быть
    /// обязательным в онбординге** — значит ноль теперь бывает
    /// у настоящей, названной собаки, и прежняя починка его не ловит.
    ///
    /// > Это наш класс «условие, привязанное к инструменту, меняет
    /// > знак»: признак был верен, пока ноль означал «запись-мусор»,
    /// > и перевернулся в день, когда ноль стал законным состоянием.
    ///
    /// Куда это доезжало: строка «Вес» на вкладке собаки, опись
    /// в настройках, сводка врачу и **текст „Потерялась собака"**,
    /// который человек отправляет чужим людям.
    ///
    /// # Чего он НЕ делает
    ///
    /// Не годится внутри фразы: «Потерялась собака: Стич, метис, —»
    /// читается хуже, чем без веса вовсе. Для фраз — `weightIfKnown`.
    static func weight(_ kg: Double) -> String {
        guard kg > 0 else { return "—" }
        return Measurement(value: kg, unit: UnitMass.kilograms)
            .formatted(.measurement(width: .abbreviated,
                                    usage: .personWeight,
                                    numberFormatStyle: .number.precision(.fractionLength(1))))
    }

    /// Корм для человека: граммы, пока их можно удержать в голове,
    /// дальше — килограммы.
    ///
    /// # Зачем, замер 27.10.2026
    ///
    /// Отзыв владелицы о списке сборов: «Переведи граммы как-то
    /// в понятные цифры». На кадре — `Корм 13160 г` на поездку
    /// в 62 дня. Тринадцать тысяч сто шестьдесят граммов — верное
    /// число, которое не отвечает на вопрос «влезет ли это в чемодан»;
    /// `13,2 кг` отвечает сразу.
    ///
    /// # Почему порог тысяча, а не «красивее»
    ///
    /// Тот же довод, что у `doseMass`: ниже килограмма корм меряют
    /// граммами и на пачках пишут граммами («порция 70 г», «норма
    /// 210 г в день»). Выше — килограммами, и так же пишут на мешке.
    /// Порог стоит там, где его ставит не мы, а упаковка.
    ///
    /// # Точность НЕ теряется, и это требование, а не любезность
    ///
    /// Единица и разделитель дробной части приходят от системы
    /// (`Measurement`), знаков после запятой до одного — то есть
    /// `13160 г` становится `13,2 кг`, а `13000 г` — `13 кг`,
    /// без хвоста `,0`. Точное число остаётся рядом, подписью: кто
    /// отсыпает корм по зип-пакетам, считает в граммах.
    ///
    /// **`weight(_:)` сюда не годится** — у него `usage: .personWeight`,
    /// то есть мера ЖИВОГО существа, и на фунтовых витринах он
    /// перевёл бы корм в фунты вслед за собакой. Корм покупают
    /// в той мере, в какой он написан на мешке.
    static func foodMass(_ grams: Int) -> String {
        let крупно = grams >= 1000
        // Диапазон `0...1` у обеих веток нарочно: тип у `fractionLength`
        // один, а «до одного знака» одинаково верно и для граммов —
        // они всегда целые, и хвоста там не возникает.
        return Measurement(value: Double(grams), unit: UnitMass.grams)
            .converted(to: крупно ? .kilograms : .grams)
            .formatted(.measurement(width: .abbreviated,
                                    usage: .asProvided,
                                    numberFormatStyle: .number
                                        .precision(.fractionLength(0...1))))
    }

    /// Литры в дорогу. Единицу и запятую называет система.
    ///
    /// Было `String(format: "%.1f л", …)` — и давало `22.0 л`: точку
    /// вместо запятой (у `String(format:)` без локали разделитель
    /// всегда POSIX) и нулевой знак, которого никто не спрашивал.
    /// Рядом на том же экране стояло `4,7 кг` с запятой — две записи
    /// одного рода, собранные по-разному.
    static func litres(_ value: Double) -> String {
        Measurement(value: value, unit: UnitVolume.liters)
            .formatted(.measurement(width: .abbreviated,
                                    usage: .asProvided,
                                    numberFormatStyle: .number
                                        .precision(.fractionLength(0...1))))
    }

    /// Вес для ФРАЗЫ: `nil`, когда он не записан.
    ///
    /// Прочерк хорош в поле, где у него есть подпись слева, и плох
    /// в предложении, где подписи нет. Разные вопросы — разные
    /// функции, и вторая не умолчание первой нарочно: умолчание
    /// выбрал бы за автора фразы тот, кто правит форматтер.
    static func weightIfKnown(_ kg: Double) -> String? {
        kg > 0 ? weight(kg) : nil
    }


    static func days(_ n: Int) -> String { String(localized: "\(n) дней") }
    static func outings(_ n: Int) -> String { String(localized: "\(n) выходов") }
    static func minutes(_ n: Int) -> String { String(localized: "\(n) минут") }
    static func times(_ n: Int) -> String { String(localized: "\(n) раз") }
    static func records(_ n: Int) -> String { String(localized: "\(n) записей") }
    static func actions(_ n: Int) -> String { String(localized: "\(n) действий") }
}
