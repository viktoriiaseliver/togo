import Foundation

/// Когда собака в последний раз сходила в туалет — где угодно.
///
/// **Решение Виктории 29.10.2026: «считали время не тогда, когда собака
/// гуляла, а тогда, когда писяла-какала».** Герой «Сегодня» до этого
/// мерил конец последнего ВЫХОДА (`TimelineBuilder.timeIndoorsNow`).
/// Выход без результата — двадцать минут на улице, «не сходил» — сбрасывал
/// счёт в ноль, хотя вопрос, ради которого на экран смотрят, — «пора ли
/// выводить», и отвечает на него последнее опорожнение, а не последняя
/// дверь.
///
/// # Что считается туалетом
///
/// ```
/// выход «пописал» / «стул» / «и то и другое»   да, на улице
/// отметка «Пописал» внутри прогулки            да, на улице
/// запись стула                                 да
/// инцидент «лужа в доме» / «стул в доме»       да, дома
/// выход «не сходил»                            нет — это и есть сигнал
/// выход и прогулка КОБЕЛЯ без ответа           да (см. ниже)
/// ```
///
/// # Кобель
///
/// Второе решение того же дня: **«поход на улицу для кобеля = туалет,
/// и незачем указывать мочу».** Кобель метит на каждой прогулке, и
/// спрашивать «пописал ли» значит требовать отметку, которую человек
/// перестанет ставить на третий день. Поэтому выход и прогулка кобеля
/// считаются мочой, пока человек прямо не ответил «не сходил».
///
/// Это правило ЧТЕНИЯ, а не записи: в базу мочу за человека мы
/// не кладём (красная линия «не подставлять там, где подстановка станет
/// утверждением человека» — запись потом читает врач).
nonisolated enum ToiletClock {

    enum Место: Sendable, Equatable { case улица, дом }

    struct Момент: Sendable, Equatable {
        let когда: Date
        let где: Место
    }

    /// Последний туалет не позже `now`. Пусто — в дневнике туалета нет.
    static func last(_ events: [LogEvent], male: Bool, now: Date = Date()) -> Момент? {
        var лучший: Момент?
        for event in Diary.active(events) {
            guard let момент = moment(of: event, male: male), момент.когда <= now else { continue }
            if лучший.map({ момент.когда > $0.когда }) ?? true { лучший = момент }
        }
        return лучший
    }

    /// Туалет ли эта запись, и когда именно он был.
    static func moment(of event: LogEvent, male: Bool) -> Момент? {
        switch event.kind {
        // Остановка в дороге — тот же выход, только у машины (29.10.2026).
        case .outing, .travelStop:
            // Развёрнуто явно, а не `case .none?`: у `OutingOutcome`
            // свой случай `.none`, и рядом с `Optional.none` он читается
            // ровно наоборот.
            guard let исход = event.outcome else {
                // Отметка внутри прогулки без исхода не бывает: её
                // заполняет `WalkRecorder.apply`. Сюда попадает выход
                // без ответа — у кобеля это туалет, у суки неизвестно.
                return male ? Момент(когда: event.date, где: .улица) : nil
            }
            switch исход {
            case .urine, .stool, .both: return Момент(когда: event.date, где: .улица)
            case .none: return nil
            }
        case .walk:
            // Конец прогулки, а не начало: кобель метит до самого дома,
            // и считать от двери значило бы приписать ему лишние полчаса.
            guard male else { return nil }
            let конец = event.date.addingTimeInterval(TimeInterval(event.durationSeconds ?? 0))
            return Момент(когда: конец, где: .улица)
        case .stool:
            // Стул дома с 29.10.2026 пишется инцидентом «стул в доме»,
            // значит запись стула — это улица, с прогулкой или без.
            return Момент(когда: event.date, где: .улица)
        case .incident:
            switch event.incidentKind {
            case .puddle?, .stoolIndoors?: return Момент(когда: event.date, где: .дом)
            default: return nil
            }
        default:
            return nil
        }
    }

    /// Сколько раз собака покакала за день.
    ///
    /// Просьба Виктории 29.10.2026: «кол-во того, сколько собака
    /// покакала». Считаются запись стула, стул в доме и выход
    /// со стулом. Выход «стул» и запись стула рядом — один и тот же
    /// стул, отмеченный дважды (сначала ответ «как сходил», потом
    /// форма для врача), поэтому выход в пределах
    /// `Diary.sameEmptyingWindow` от записи стула не считается.
    static func stoolCount(_ events: [LogEvent], on day: Date, calendar: Calendar = .current) -> Int {
        let дня = Diary.active(events).filter { calendar.isDate($0.date, inSameDayAs: day) }
        let записи = дня.filter {
            $0.kind == .stool || ($0.kind == .incident && $0.incidentKind == .stoolIndoors)
        }
        let выходы = дня.filter {
            $0.kind == .outing && ($0.outcome == .stool || $0.outcome == .both)
        }.filter { выход in
            // Склеивается только с записью стула: кучка дома рядом
            // с выходом — это другой стул, а не тот же дважды.
            !записи.contains {
                $0.kind == .stool && abs($0.date.timeIntervalSince(выход.date)) <= Diary.sameEmptyingWindow
            }
        }
        return записи.count + выходы.count
    }
}
