import Foundation

/// Когда спрашивать право на уведомления. Правило нового дизайна,
/// раздел «1 · Первый запуск» (`Togo ФИНАЛ v2`, окт 2026):
///
/// > Разрешение на уведомления спрашиваем **в момент первой дозы**,
/// > до системного окна; после отказа **больше не спрашиваем**.
///
/// **Почему это домен, а не вью.** В правиле две величины, и обе
/// про состояние, а не про экран: повод («первая доза») и запрет
/// («после отказа»). Положи их во вью — и через месяц второй экран
/// спросит снова, потому что про отказ знает только первый. У Togo
/// это уже случалось с правилом «не кормить»: три реализации, две
/// молчали.
///
/// **Чего этот тип нарочно не делает.** Он не ходит в
/// `UNUserNotificationCenter` и не показывает окно. Он отвечает
/// на один вопрос — «сейчас уместно спросить?» — и потому
/// проверяется тестом без симулятора и без разрешений. Системный
/// статус приходит снаружи параметром: спрашивать его здесь значило
/// бы проверять одну реализацию наблюдениями за другой.
nonisolated enum NotificationPriming {

    /// Что приложение уже знает про право на уведомления.
    ///
    /// Нарочно не `UNAuthorizationStatus`: тот живёт в системном
    /// фреймворке и тащит его в тесты. Здесь только то, от чего
    /// зависит решение.
    enum SystemState: Sendable, Equatable {
        /// Система ещё ни о чём не спрашивала — единственный случай,
        /// когда наше окно вообще имеет смысл.
        case notAsked
        /// Разрешено. Спрашивать нечего.
        case granted
        /// Отказано. Системное окно второй раз не появится — iOS
        /// показывает его один раз на установку, — поэтому наше окно
        /// стало бы обещанием, которого приложение не может
        /// выполнить.
        case denied
    }

    /// Что приложение помнит о себе. Одна величина, и она
    /// переживает перезапуск.
    struct Memory: Codable, Sendable, Equatable {
        /// Показывали ли мы своё окно хоть раз.
        var didPrime: Bool = false
        /// Отказался ли человек у НАС (не в системе).
        ///
        /// Хранится отдельно от системного отказа: человек может
        /// закрыть наше окно, не дойдя до системного, и это не отказ
        /// системе, но повторять вопрос всё равно нельзя.
        var didDecline: Bool = false

        init(didPrime: Bool = false, didDecline: Bool = false) {
            self.didPrime = didPrime
            self.didDecline = didDecline
        }
    }

    /// Повод спросить. Список закрыт нарочно: «в момент первой дозы»
    /// — это один повод, и расширять его можно только решением,
    /// а не по ходу работы над экраном.
    enum Occasion: Sendable, Equatable {
        /// Человек собирается отметить первую в жизни дневника дозу.
        case firstDose
        /// Любой другой момент. Повода нет.
        case other
    }

    /// Спрашивать ли сейчас.
    ///
    /// Все четыре запрета названы поимённо и проверяются каждый своим
    /// тестом — иначе «не спрашиваем» выполнялось бы и при отсутствии
    /// предмета, как уже было у Kvit с «уходят не все».
    static func shouldPrime(occasion: Occasion,
                            system: SystemState,
                            memory: Memory) -> Bool {
        guard occasion == .firstDose else { return false }   // нет повода
        guard system == .notAsked else { return false }       // система уже знает ответ
        guard !memory.didPrime else { return false }          // своё окно уже показывали
        guard !memory.didDecline else { return false }        // отказался — больше не спрашиваем
        return true
    }

    /// Память после того, как окно показали и человек ответил.
    ///
    /// Возвращает новое значение, а не правит на месте: так вызов
    /// нельзя забыть — результат некуда девать, кроме как записать.
    static func remember(_ memory: Memory, accepted: Bool) -> Memory {
        Memory(didPrime: true, didDecline: memory.didDecline || !accepted)
    }

    /// Можно ли ещё когда-нибудь получить право, не уходя в системные
    /// настройки.
    ///
    /// Нужно экрану: «включить уведомления» ведёт в настройки, если
    /// системное окно уже отработало, и это надо сказать словом,
    /// а не показать кнопку, которая ничего не делает. У Togo уже был
    /// такой случай — один текст на три причины отката iCloud.
    static func needsSystemSettings(system: SystemState) -> Bool {
        system == .denied
    }
}
