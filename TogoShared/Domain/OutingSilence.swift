import Foundation

/// Когда «давно ли гуляли» перестаёт быть ответом на вопрос.
///
/// **Правило одно на все поверхности, и потому живёт здесь.** Заведено
/// 21.09.2026 на главном экране: после восемнадцати дней без отметок
/// он показал «434 ч назад · на улице были» — приложение сказало
/// **о собаке** то, чего не знало. Знало оно другое: что выходов нет
/// с 3 сентября.
///
/// 24.09 выяснилось, что правило стояло **на одной поверхности из двух**.
/// Siri на тех же данных отвечала «Стич дома 434 ч с прошлого выхода» —
/// ровно та же неправда тем же числом, только голосом. Экран чинили,
/// а голос читал ту же величину мимо потолка.
///
/// Поэтому потолок и решение «что сказать вместо числа» вынесены
/// из вью в общий код: правка, меняющая то, что человек читает,
/// применяется ко всем поверхностям, где та же величина живёт.
nonisolated enum OutingSilence {

    /// Дольше этого число часов отвечает уже не на тот вопрос.
    ///
    /// Сутки не из головы: вопрос экрана — «пора ли выходить», и он
    /// про часы.
    static let ceiling: TimeInterval = 24 * 3600

    /// Дата последнего выхода, если тишина перевалила за потолок.
    /// Пусто во всех остальных случаях, включая «выходили сегодня».
    static func start(indoors: TimeInterval?, lastOutingEndedAt: Date?) -> Date? {
        guard let indoors, indoors >= ceiling, let lastOutingEndedAt else { return nil }
        return lastOutingEndedAt
    }
}
