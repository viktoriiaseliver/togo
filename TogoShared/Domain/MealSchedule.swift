import Foundation

/// Как разложить кормления по суткам.
///
/// Считаем не «внутри дня», а по кругу в 24 часа: ночь — это тоже промежуток
/// между кормлениями, и для собаки он часто самый длинный. Слишком долгий
/// ночной перерыв — известная причина утренней рвоты желчью, поэтому
/// приложение старается его сократить и показывает, что получилось.
///
/// Правила:
/// * первое кормление — вскоре после подъёма, но после первого выхода:
///   собака сначала идёт в туалет, потом ест;
/// * дальше — ровно через 24 ч ÷ число кормлений, чтобы промежутки были
///   одинаковыми и днём, и ночью;
/// * последнее не позже чем за полтора часа до сна — нужно успеть погулять;
/// * если идеальный шаг в это окно не влезает, кормления сжимаются
///   и раскладываются поровну между первым и последним.
nonisolated enum MealSchedule {
    static let minutesInDay = 24 * 60
    /// Сколько ждать после подъёма до первого кормления.
    static let afterWake = 30
    /// За сколько до сна должно пройти последнее кормление.
    static let beforeSleep = 90
    /// Дольше этого ночной перерыв стоит обсудить с врачом.
    static let longNightThreshold = 14 * 60

    /// Итог раскладки: времена и то, что о них стоит знать человеку.
    struct Plan: Equatable, Sendable {
        var times: [Int]
        /// Промежуток между дневными кормлениями.
        var dayInterval: Int?
        /// От последнего кормления до первого следующего дня.
        var nightGap: Int
        /// Идеальный шаг не влез в окно бодрствования — пришлось сжать.
        var isCompressed: Bool

        var hasLongNight: Bool { nightGap > MealSchedule.longNightThreshold }

        /// Насколько ночь длиннее дневного промежутка.
        var nightOverhang: Int? {
            guard let dayInterval else { return nil }
            return max(0, nightGap - dayInterval)
        }
    }

    static func plan(mealsPerDay: Int, wake: Int, sleep: Int) -> Plan {
        let times = evenTimes(mealsPerDay: mealsPerDay, wake: wake, sleep: sleep)
        return Plan(
            times: times,
            dayInterval: dayInterval(times),
            nightGap: nightGap(times),
            isCompressed: isCompressed(mealsPerDay: mealsPerDay, wake: wake, sleep: sleep)
        )
    }

    /// Промежутки у ТЕХ ЧАСОВ, которые стоят, а не у идеальных.
    ///
    /// Два разных вопроса, и до 28.10.2026 на второй отвечали первым:
    ///
    /// ```
    /// plan(mealsPerDay:wake:sleep:)   как разложить, если раскладывать с нуля
    /// plan(times:)                    что получается из поставленного
    /// ```
    ///
    /// Цена замерена на кадре отзыва (27.10, 21:55): строка «план»
    /// показывала её часы `09:30 · 15:30 · 21:30` (ночь 12 ч, днём 6 ч),
    /// а строка под ней — «Ночь 13 ч · днём между едой 5 ч 30 мин»,
    /// то есть промежутки ИДЕАЛЬНОГО расписания `09:30 · 15:00 · 20:30`.
    /// Две строки одной карточки о двух разных расписаниях, и ни одна
    /// этого не говорила.
    ///
    /// `isCompressed` здесь ложно нарочно: сжатие — свойство раскладки,
    /// а у готовых часов раскладки нет. Выводить его из промежутков
    /// значило бы назвать причиной то, что причиной не является.
    static func plan(times: [Int]) -> Plan {
        let упорядоченные = times.sorted()
        return Plan(
            times: упорядоченные,
            dayInterval: dayInterval(упорядоченные),
            nightGap: nightGap(упорядоченные),
            isCompressed: false
        )
    }

    /// Времена кормлений. Первое привязано к подъёму, дальше — ровный шаг
    /// по кругу суток, сжатый при необходимости в окно бодрствования.
    static func evenTimes(mealsPerDay: Int, wake: Int, sleep: Int) -> [Int] {
        guard mealsPerDay > 0 else { return [] }

        let first = normalize(wake + afterWake)
        guard mealsPerDay > 1 else { return [first] }

        let latest = latestMeal(wake: wake, sleep: sleep)
        let window = forward(from: first, to: latest)
        let idealStep = minutesInDay / mealsPerDay
        let idealSpan = idealStep * (mealsPerDay - 1)

        // Ровный шаг по суткам умещается в бодрствование — берём его:
        // одинаковые промежутки днём и ночью лучше всего.
        if idealSpan <= window {
            return (0..<mealsPerDay).map { normalize(first + idealStep * $0) }
        }

        // Не умещается — раскладываем поровну между первым и последним.
        let step = window / (mealsPerDay - 1)
        return (0..<mealsPerDay).map { normalize(first + step * $0) }
    }

    static func isCompressed(mealsPerDay: Int, wake: Int, sleep: Int) -> Bool {
        guard mealsPerDay > 1 else { return false }
        let window = forward(from: normalize(wake + afterWake), to: latestMeal(wake: wake, sleep: sleep))
        return (minutesInDay / mealsPerDay) * (mealsPerDay - 1) > window
    }

    /// Ночной перерыв: от последнего кормления до первого на следующий день.
    static func nightGap(_ times: [Int]) -> Int {
        guard let first = times.first, let last = times.last, times.count > 0 else { return 0 }
        guard times.count > 1 else { return minutesInDay }
        return forward(from: last, to: first)
    }

    /// Дневной промежуток. Если они разные — берём самый короткий:
    /// именно он показывает, насколько ночь выбивается из ритма.
    static func dayInterval(_ times: [Int]) -> Int? {
        guard times.count > 1 else { return nil }
        let gaps = zip(times, times.dropFirst()).map { forward(from: $0, to: $1) }
        return gaps.min()
    }

    // MARK: Мелочи

    /// Сколько минут между подъёмом и отбоем — по кругу суток.
    ///
    /// **Одна точка на три места.** Та же величина считалась руками
    /// в `Dog.awakeMinutes` и в `ScheduleDraft.awakeMinutes`
    /// (`span > 0 ? span : span + 24 * 60`), а здесь — через `forward`.
    /// Разница между копиями была ровно одна и в пользу этой:
    /// `forward` сперва приводит минуты в сутки, а ручная ветка нет,
    /// то есть на значении вне `0…1439` (архив восстанавливает число
    /// как есть) ручная давала отрицательное «бодрствует».
    static func awakeMinutes(wake: Int, sleep: Int) -> Int {
        forward(from: wake, to: sleep)
    }

    static func latestMeal(wake: Int, sleep: Int) -> Int {
        let awake = awakeMinutes(wake: wake, sleep: sleep)
        // Окно короче трёх часов — не режим, а опечатка: оставляем хотя бы час.
        let span = max(60, awake - beforeSleep)
        return normalize(wake + span)
    }

    static func normalize(_ minute: Int) -> Int {
        ((minute % minutesInDay) + minutesInDay) % minutesInDay
    }

    /// Сколько минут вперёд по кругу суток от одного времени до другого.
    static func forward(from: Int, to: Int) -> Int {
        let delta = normalize(to) - normalize(from)
        return delta > 0 ? delta : delta + minutesInDay
    }
}

// MARK: - Что из плана уже сделано

extension MealSchedule {
    /// Предел, дальше которого запись не закрывает слот ни при каком
    /// расписании.
    ///
    /// **Было `doneTolerance = 90 * 60`, плоские полтора часа, и это
    /// оплачено отзывом 30.10.2026, сборка 289:** «2 раза покормила
    /// собаку, пусть в другое время. Пусть приложение предложит либо
    /// сдвинуть ужин… А обед отметить как Дан».
    ///
    /// Арифметика её случая:
    ///
    /// ```
    /// её часы            09:30 · 15:30 · 21:30   промежуток 360 мин
    /// запись             18:00
    /// до 15:30           150 мин  > 90  → слот свободен
    /// до 21:30           210 мин  > 90  → слот свободен
    /// ```
    ///
    /// Человек покормил — приложение говорит, что не кормил, и держит
    /// в плане дня два незакрытых пункта еды. Цена не косметическая:
    /// собака на заместительной терапии, и двойное кормление здесь —
    /// медицинское событие.
    ///
    /// > **Плоская константа не знает расписания, а слот знает.**
    /// > Полтора часа тесны для трёх кормлений в день и широки
    /// > для пяти у щенка — одно число не может быть верным для обоих.
    ///
    /// Потолок нужен из-за НОЧИ: половина ночного промежутка у трёх
    /// кормлений — 540 минут, и без потолка запись в 00:30 закрыла бы
    /// завтрак в 09:30. Три часа — число с измеренной ценой в обе
    /// стороны:
    ///
    /// ```
    /// 90 (как было)   её 18:00 слот НЕ закрывает      ← дефект отзыва
    /// 180             закрывает; 00:30 завтрак не закрывает
    /// без потолка     00:30 закрывает завтрак (540 ≤ 540)
    /// ```
    nonisolated static let потолокЗакрытия = 180 * 60.0

    /// Прежнее имя. Живых читателей у него не осталось (замер
    /// 04.11.2026: оба — `ShiftReport` и `DayPlanActions` — переведены
    /// в тот же день), но имя встречается в доккомментариях
    /// и в живом тесте `FeedingTests`. Без `deprecated`: пометка
    /// дала бы предупреждение на каждой сборке ради строки,
    /// у которой вызовов ноль.
    nonisolated static let doneTolerance = потолокЗакрытия

    /// Сколько запись может отстоять ОТ ЭТОГО слота и всё ещё считаться
    /// им.
    ///
    /// Граница — полпути до соседа, в обе стороны по кругу суток,
    /// но не больше `потолокЗакрытия`.
    ///
    /// **Правило само подстраивается под расписание, и это главное его
    /// свойство:** у трёх кормлений с промежутком 6 часов окно выходит
    /// 180 минут, у щенка с кормлениями в часе друг от друга — 30 минут.
    /// Прежний урок («одна запись закрывала сразу два пункта, день
    /// выглядел выполненным») остаётся выполненным ПО УСТРОЙСТВУ,
    /// а не вторым правилом рядом: ячейки соседей не пересекаются.
    ///
    /// Один слот в расписании — соседа нет, работает только потолок.
    nonisolated static func окно(planned: [Int], слот: Int) -> TimeInterval {
        guard planned.count > 1, planned.indices.contains(слот) else {
            return потолокЗакрытия
        }
        let отсортированы = planned.sorted()
        guard let место = отсортированы.firstIndex(of: planned[слот]) else {
            return потолокЗакрытия
        }
        let предыдущий = отсортированы[(место - 1 + отсортированы.count) % отсортированы.count]
        let следующий = отсортированы[(место + 1) % отсортированы.count]
        let назад = Double(forward(from: предыдущий, to: отсортированы[место])) * 60 / 2
        let вперёд = Double(forward(from: отсортированы[место], to: следующий)) * 60 / 2
        return min(назад, вперёд, потолокЗакрытия)
    }

    /// Сколько выйдет до следующего кормления и сколько стоит в плане.
    ///
    /// Заведено 04.11.2026 по второй половине отзыва 30.10: «Пусть
    /// приложение предложит либо сдвинуть ужин пропорционально или
    /// недокормить ужин или кормить по расписанию».
    ///
    /// **Развилки здесь нет, и это названо, а не забыто.** Любой её
    /// выход, кроме «оставить как есть», надо ЗАПОМНИТЬ на сегодня —
    /// а места для разового исключения на дату в схеме нет (решение
    /// Виктории 04.11: держать разовым исключением на дату; вопрос
    /// о поле вынесен отдельно). Кнопка, которая ничего не запоминает,
    /// это обещание, которого мы не держим.
    ///
    /// Что здесь есть — **исход, названный вслух**. До этой правки
    /// приложение знало, что обед съехал на 18:00, писало это
    /// на закрытом пункте и молчало о последствии: ужин в 21:30
    /// приходит через 3 ч 30 мин вместо шести. Закрытый пункт при этом
    /// свёрнут под «сделано · N», то есть причину человек не видит,
    /// а следствие стоит у него перед глазами без объяснения.
    nonisolated struct Промежуток: Sendable, Equatable {
        /// Когда покормили на самом деле — запись, закрывшая прошлый пункт.
        var факт: Date
        /// Сколько выйдет от неё до часа этого пункта.
        var выйдет: TimeInterval
        /// Сколько стоит между двумя пунктами в расписании.
        var поРасписанию: TimeInterval
        /// Дальше этого расхождение стоит называть человеку.
        var порог: TimeInterval

        /// Положительное — промежуток растянулся, отрицательное — сжался.
        var расхождение: TimeInterval { выйдет - поРасписанию }

        /// **Порог не константа и не придуман здесь.**
        ///
        /// Снизу его держит `LateMarking.grace`: четверть часа ни одного
        /// окна натощак и ни одного напоминания не двигает — об этом
        /// сказано у самого `grace`, и говорить там, где ничего
        /// не меняется, значит приучить пролистывать.
        ///
        /// Сверху — **половина `окно(planned:слот:)` прошлого пункта**,
        /// то есть половина той зоны, которую приложение уже считает
        /// «это всё ещё то же кормление». Величина своя у каждого
        /// расписания: 90 минут у трёх кормлений с промежутком в шесть
        /// часов, 15 минут у щенка с кормлениями в часе друг от друга.
        /// Новой абсолютной цифры не заводится ни одной.
        ///
        /// ```
        /// её случай      обед в 18:00 при слоте 15:30   расхождение 150 мин
        ///                окно слота 15:30 — 180 мин     порог 90   → ГОВОРИМ
        /// обычное утро   завтрак на 20 минут позже      расхождение 20 мин
        ///                тот же порог 90                           → МОЛЧИМ
        /// ```
        var стоитНазвать: Bool { abs(расхождение) > порог }
    }

    /// Что выйдет между прошлым кормлением и этим пунктом плана.
    ///
    /// - Parameters:
    ///   - planned: часы расписания, по возрастанию.
    ///   - слот: пункт, к которому считаем. У первого за день прошлого
    ///     кормления в этих сутках нет — считать не от чего.
    ///   - фактПрошлого: запись, закрывшая ПРЕДЫДУЩИЙ пункт. Не «последняя
    ///     запись о еде»: приложение уже решило, какая запись какой пункт
    ///     закрыла (`разметить`), и второе правило рядом разошлось бы
    ///     с первым — на этом Togo уже ловился трижды.
    ///   - датаСлота: календарный момент этого пункта.
    nonisolated static func промежуток(planned: [Int], слот: Int,
                                       фактПрошлого: Date,
                                       датаСлота: Date) -> Промежуток? {
        guard слот > 0, planned.indices.contains(слот) else { return nil }
        let выйдет = датаСлота.timeIntervalSince(фактПрошлого)
        guard выйдет > 0 else { return nil }
        let поРасписанию = Double(forward(from: planned[слот - 1], to: planned[слот])) * 60
        return Промежуток(факт: фактПрошлого,
                          выйдет: выйдет,
                          поРасписанию: поРасписанию,
                          порог: max(LateMarking.grace,
                                     окно(planned: planned, слот: слот - 1) / 2))
    }

    /// Что вышло из сопоставления плана с записями.
    ///
    /// `закрыто[слот]` — индекс записи, которая его закрыла. Прежний
    /// `matchDone` отдавал только `[Bool]`, и **этого оказалось мало
    /// трижды**: кто закрыл слот, заново искали `ShiftReport`
    /// (±90 мин по ленте) и `DayPlanActions` (при снятии отметки).
    /// Две копии одного правила рядом с третьей — и расходиться они
    /// начали ровно в этом случае.
    nonisolated struct Разметка: Sendable, Equatable {
        /// Индекс записи, закрывшей слот, или `nil`.
        var закрыто: [Int?]
        /// То же в прежней форме — для читателей, которым довольно «да/нет».
        var done: [Bool] { закрыто.map { $0 != nil } }
    }

    /// Разметить пункты плана: какие из них закрыты записями.
    ///
    /// Раньше каждый пункт спрашивал независимо: «есть ли хоть одна запись
    /// в пределах полутора часов». У щенка с пятью кормлениями пункты стоят
    /// в трёх с половиной часах друг от друга, но стоит расставить времена
    /// вручную поближе — и одна запись закрывала сразу два пункта. День
    /// выглядел выполненным, хотя собаку покормили один раз.
    ///
    /// Теперь каждая запись закрывает ровно один пункт — ближайший
    /// к себе и ещё свободный.
    nonisolated static func matchDone(
        planned: [Int],
        logged: [Date],
        startOfDay: Date
    ) -> [Bool] {
        разметить(planned: planned, logged: logged, startOfDay: startOfDay).done
    }

    /// То же, но говорит, КАКАЯ запись закрыла слот.
    ///
    /// - Parameter окно: подменяется только сторожем. Инъекция нужна,
    ///   чтобы ломать окно и «одна запись — один слот» ПО ОТДЕЛЬНОСТИ:
    ///   после перехода на ячейки прежняя подделка (снять `usedRecords`)
    ///   перестала краснеть — соседние ячейки не пересекаются,
    ///   и инвариант держится устройством. Сторож, у которого подделка
    ///   больше не проходит, выглядит исправным и не сторожит ничего.
    nonisolated static func разметить(
        planned: [Int],
        logged: [Date],
        startOfDay: Date,
        окно: (Int) -> TimeInterval = { _ in потолокЗакрытия }
    ) -> Разметка {
        var закрыто = [Int?](repeating: nil, count: planned.count)
        let calendar = Calendar.current
        let slots = planned.map { calendar.date(minuteOfDay: $0, on: startOfDay) }
        // Умолчание параметра не может сослаться на `planned`, поэтому
        // настоящее окно считается здесь — а параметр остаётся дверью
        // для подделки.
        //
        // Считаем СПИСКОМ, а не замыканием: замыкание захватило бы
        // non-escaping параметр, и компилятор это ловит
        // (`escaping closure captures non-escaping parameter`).
        // Заодно выходит дешевле — окно каждого слота считается один
        // раз, а не на каждой паре «слот × запись».
        let окна = planned.indices.map { слот in
            min(окно(слот), Self.окно(planned: planned, слот: слот))
        }

        // Сначала самые «уверенные» пары: у кого расстояние меньше, тот
        // и занимает пункт. Иначе первая по времени запись могла бы забрать
        // пункт, который куда точнее подходит следующей.
        var pairs: [(distance: Double, slot: Int, record: Int)] = []
        for (recordIndex, date) in logged.enumerated() {
            for (slotIndex, slot) in slots.enumerated() {
                let distance = abs(date.timeIntervalSince(slot))
                guard distance <= окна[slotIndex] else { continue }
                pairs.append((distance, slotIndex, recordIndex))
            }
        }
        pairs.sort { $0.distance < $1.distance }

        var usedRecords = Set<Int>()
        for pair in pairs where закрыто[pair.slot] == nil && !usedRecords.contains(pair.record) {
            закрыто[pair.slot] = pair.record
            usedRecords.insert(pair.record)
        }
        return Разметка(закрыто: закрыто)
    }
}
