import Foundation

/// Дата, которая значит ДЕНЬ, а не момент.
///
/// **Зачем это понадобилось, замерено 05.10.2026.** Менеджер поставил
/// вопрос по каждому полю событий с концом: «значит ли оно на другом
/// телефоне то же самое». У `Trip` и `HeatRecord` ответ оказался «нет»,
/// и расходятся они на целые сутки.
///
/// Виктория в Ницце (UTC+2) заводит поездку на 10 октября. `DatePicker`
/// с `displayedComponents: .date` **сохраняет время суток** привязанного
/// значения — то есть в базу уезжает не «10 октября», а конкретный
/// момент, нередко близкий к полуночи. Дальше `dayNumber(on:)` считает
/// `startOfDay` в `Calendar.current`, то есть в поясе ЧИТАЮЩЕГО:
///
/// ```
/// startDate = 10 окт 00:00 +02:00  =  9 окт 22:00 UTC
///
/// пояс семьи            startOfDay(startDate)   «день поездки» 10 окт
/// Ницца        UTC+2    10 окт                             1
/// Токио        UTC+9    10 окт                             1
/// Нью-Йорк     UTC−4     9 окт                             2   ←
/// Лос-Анджелес UTC−7     9 окт                             2   ←
/// ```
///
/// Ситтер западнее владельца видит первый день поездки как второй,
/// а `isActive(on:)` открывает поездку сутками раньше. То же у `HeatRecord`:
/// день цикла смещается, а на нём стоят «опасные дни».
///
/// **Различие, которого в модели не было.** У событий с концом два рода
/// дат, и путать их нельзя:
///
/// - **момент** — `DayOut.startedAt`, `Episode.lastIncidentAt`, время
///   отметки. Абсолютен, одинаков везде, трогать нечего;
/// - **день** — `Trip.startDate`, `HeatRecord.startedAt`. Это запись
///   настенного календаря, и абсолютным моментом она выражается только
///   с точностью до пояса.
///
/// Лечится якорем в **полдень**: от полудня до границы суток двенадцать
/// часов в обе стороны, а обитаемых поясов дальше UTC±12 не бывает
/// (UTC+14 существует, но и там сутки сдвинулись бы лишь при разнице
/// больше двенадцати часов **от полудня владельца** — чего двенадцатью
/// часами запаса и не достичь: крайний случай даёт ровно границу).
/// Полночь же лежит на самой границе, и любой пояс западнее сдвигает её
/// за край.
///
/// > **Поле типа `Date` не говорит, момент это или день.** Тип один,
/// > смысла два, и расходятся они только у второго человека — то есть
/// > ровно там, где никто не смотрит.
nonisolated enum CalendarDay {

    /// Пояс, в котором дневник извлекает КАЛЕНДАРНЫЙ ДЕНЬ.
    ///
    /// **День календаря извлекается в `Europe/Paris` для всех записей.**
    /// Для заякоренных (полдень) пояс не важен вовсе: ±12 часов не
    /// переносят полдень через границу суток, и день выходит один и тот же
    /// хоть в Окленде, хоть в Нью-Йорке. Для записей **до 05.10.2026**
    /// якоря нет, и верность дня держится на **допущении**: все они
    /// заведены в Ницце. Проверить это нечем — пояс автора не сохранялся.
    /// Допущение снимет поле `авторскийПояс` у записи.
    ///
    /// **Куда именно уезжает старая запись — поправлено замером, и первая
    /// редакция этого абзаца говорила обратное.** Я написал «заведённая
    /// западнее», перенеся направление из соседней находки, где западнее
    /// был ЧИТАЮЩИЙ. У автора направление обратное, и красный тест
    /// поймал это раньше, чем текст успел уехать в чужую голову:
    ///
    /// ```
    /// автор, полночь 10 окт     момент в Париже   день в Париже
    /// Токио        UTC+9        9 окт 17:00             9   ← уехал
    /// Москва       UTC+3        9 окт 23:00             9   ← уехал
    /// Ницца        UTC+2       10 окт 00:00            10
    /// Нью-Йорк     UTC−4       10 окт 06:00            10
    /// Лос-Анджелес UTC−7       10 окт 09:00            10
    /// ```
    ///
    /// **И запас на восточной стороне не двенадцать часов, а ноль:**
    /// незаякоренная запись лежит ровно на полуночи, поэтому её сдвигает
    /// назад **любое** смещение к востоку — Москва ломает её так же
    /// надёжно, как Токио. На западной стороне запас, наоборот, полный.
    /// Асимметрия и есть причина якоря: полдень даёт по двенадцать часов
    /// в обе стороны, полночь — двенадцать в одну и ноль в другую.
    ///
    /// **Почему не миграция.** Разбор `togo-45`, и он опроверг вариант
    /// «переписать старые значения» четырьмя доводами:
    ///
    /// 1. `.lightweight` значения не переписывает — нужна `.custom`
    ///    на форме, которую несут **шесть розданных сборок**, без отката;
    /// 2. миграция **стирает улику**: пока момент лежит у полуночи,
    ///    расхождение заметно; после якоря оно неотличимо от правильной
    ///    записи;
    /// 3. **допущение, положенное в данные, становится фактом; положенное
    ///    в чтение — остаётся допущением.** Здесь это одна строка, которую
    ///    заменят на `запись.авторскийПояс`, когда поле появится;
    /// 4. это домашний приём проекта: `fastingBefore`, `schedule`,
    ///    `remaining` — три места, где старая форма разрешается при
    ///    чтении, и ни одного переписанного миграцией.
    ///
    /// И главное в разборе: **обнаруживать «старая или новая» не нужно
    /// вовсе.** Любой признак по времени суток был бы догадкой, которая
    /// однажды совпадёт с настоящим полуночным якорем. Признак, который
    /// не нужно вычислять, не может ошибиться.
    ///
    /// > **Границы самого этого решения, обе — и обе названы тем, что их
    /// > снимет.**
    /// >
    /// > **Первая:** фиксированный пояс верен, пока у дневника один
    /// > владелец в одном поясе. Виктория переедет — и он станет неверен
    /// > молча. Снимет это то же поле `авторскийПояс`.
    /// >
    /// > **Вторая, и её не называл никто:** в этом поясе бьётся на дни
    /// > не только запись, но и **«сегодня» читающего**. Виктория в Токио
    /// > в 06:00 по-местному — это 23:00 вчерашнего дня в Париже, и день
    /// > поездки покажется на единицу меньше её собственного утра.
    /// > Цена принята сознательно: у общего дневника на семью один
    /// > календарь дороже, чем совпадение с часами того, кто уехал.
    /// > Снимет это разделение «день записи» и «сегодня у читающего»
    /// > на два разных вопроса — работа, а не правка.
    static let дневниковыйПояс: TimeZone = TimeZone(identifier: "Europe/Paris")
        ?? TimeZone(secondsFromGMT: 0)!

    /// Календарь дневника. Им считаются ДНИ; моменты календаря не требуют.
    static var дневниковыйКалендарь: Calendar {
        var c = Calendar(identifier: .gregorian)
        c.timeZone = дневниковыйПояс
        return c
    }

    /// Полдень того дня, в который попадает `date` по календарю `calendar`.
    ///
    /// Календарь — аргументом, а не `Calendar.current` внутри: иначе
    /// проверить это по поясам нечем, а непроверяемую поверхность мы
    /// чиним переделкой входа, а не старанием.
    static func anchored(_ date: Date, calendar: Calendar = .current) -> Date {
        let начало = calendar.startOfDay(for: date)
        return calendar.date(byAdding: .hour, value: 12, to: начало) ?? начало
    }

    /// Сколько целых суток прошло от `from` до `to` по календарю.
    ///
    /// Обе границы приводятся к началу своих суток: считаем дни, а не
    /// часы, иначе «с утра до вечера» даёт ноль, а «с вечера до утра» —
    /// единицу при одной и той же разнице в часах.
    static func daysBetween(_ from: Date, _ to: Date, calendar: Calendar = .current) -> Int {
        calendar.dateComponents([.day],
                                from: calendar.startOfDay(for: from),
                                to: calendar.startOfDay(for: to)).day ?? 0
    }
}
