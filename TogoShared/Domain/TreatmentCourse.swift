import Foundation
import SwiftData

/// Курс лечения — это эпизод поверх обычного ухода, а не отдельный продукт.
///
/// Собака болеет две недели в году, а живёт все триста шестьдесят пять.
///
/// ~~«Есть активный курс, есть „Здоровье"; курс завершён — вкладки нет.»~~
/// **Неверно с 08.10.2026 (`02c1e88`): вкладку держит право `.seeMedical`,
/// а не курс.** Прежнее правило убивало вкладку ровно в день конца курса —
/// когда человек идёт за отчётом врачу. Завершение курса трогает **схему
/// и напоминания**, а не вкладку.
///
/// Завершение ничего не стирает: дозы, вес, симптомы и отчёт врачу остаются
/// в истории. Иначе человек боится нажать «Курс завершён» — и схема висит
/// месяцами, где половина препаратов уже отменена.
nonisolated enum TreatmentCourse {

    /// Идёт ли курс сейчас.
    @MainActor
    static func isActive(_ dog: Dog?) -> Bool {
        dog?.isOnTreatment == true
    }

    /// Что уйдёт вместе с курсом — показывается до подтверждения,
    /// а не после.
    ///
    /// **Схема на паузе сюда не входит (29.10.2026).** Её остановили
    /// раньше и отдельно — врач велел прервать, кончились таблетки.
    /// До этой правки конец курса ставил ей `cancelledAt`, а возврат
    /// курса снимал паузу у всех отменённых разом: схема, которую
    /// держали на паузе нарочно, оживала напоминаниями. Курс отменяет
    /// только то, что шло, и возвращает только то, что отменил.
    @MainActor
    static func activeMedications(_ dog: Dog) -> [Medication] {
        dog.medications.filter { $0.cancelledAt == nil && !$0.isPaused }
    }

    /// Начало заметки, которую ставит конец курса. Строкой, а не через
    /// каталог: это метка опознания в базе, а не текст для показа,
    /// и перевод разорвал бы её между телефонами с разным языком.
    static let заметкаКонцаКурса = "Курс завершён"

    /// Схемы, отменённые ПОСЛЕДНИМ концом курса, — и только они.
    ///
    /// # Почему по моменту отмены, а не по всем `cancelledAt` (29.10.2026)
    ///
    /// `resume` возвращал в строй КАЖДУЮ отменённую схему собаки —
    /// и ту, что врач отменил полгода назад отдельным решением. Курс,
    /// возвращённый «врач продлил», воскрешал прошлогодний антибиотик
    /// с напоминаниями.
    ///
    /// Отдельного поля «отменено курсом» нет, а форму схемы без спроса
    /// не меняем. Но `finish` ставит ВСЕМ своим схемам один и тот же
    /// `now` — до миллисекунды. Поэтому опознание — по этому моменту:
    /// самый поздний `cancelledAt` среди схем с заметкой конца курса
    /// и все схемы ровно с ним. Заметка — первый ключ, а не единственный:
    /// `отменить(в:заметка:)` не затирает уже написанную причину, и схема
    /// с причиной врача несёт ту же метку времени без нашей заметки.
    /// Если заметки нет ни у кого (курс завершён до неё), момент берётся
    /// по всем отменённым.
    @MainActor
    static func отменённыеКурсом(_ dog: Dog) -> [Medication] {
        let отменённые = dog.medications.filter { $0.cancelledAt != nil }
        let сЗаметкой = отменённые.filter {
            $0.cancelledNote?.hasPrefix(заметкаКонцаКурса) == true
        }
        let опора = сЗаметкой.isEmpty ? отменённые : сЗаметкой
        guard let момент = опора.compactMap(\.cancelledAt).max() else { return [] }
        return отменённые.filter { $0.cancelledAt == момент }
    }

    /// Завершить курс.
    ///
    /// Препараты не удаляются, а помечаются отменёнными датой: в отчёте
    /// врачу должно быть видно, что давали и до какого числа.
    @MainActor
    static func finish(
        _ dog: Dog,
        at now: Date = Date(),
        by person: String?,
        context: ModelContext
    ) {
        // Через метод модели, а не двумя присваиваниями: мимо него
        // отмену нельзя выразить без паузы, а без паузы она не гасит
        // напоминания ни у кого — вся уборка смотрит на `isPaused`.
        // Разбор — `Medication.отменить(в:заметка:)`.
        for medication in activeMedications(dog) {
            medication.отменить(в: now, заметка: "\(заметкаКонцаКурса) \(Fmt.shortDay(now))")
        }

        // Незакрытые отметки будущих доз — мусор: они бы всплыли завтра
        // в плане дня уже после конца курса.
        for medication in dog.medications {
            for dose in medication.doses
            where dose.givenAt == nil && dose.skippedAt == nil && dose.scheduledAt > now {
                context.delete(dose)
            }
        }

        dog.isOnTreatment = false
        // Курс закончен — из плана дня уходят дозы и напоминания. Если это
        // не записалось, они вернутся при следующем запуске, и человек
        // решит, что приложение «не отпускает» отменённую схему.
        // (Вкладка при этом не двигается: её держит право, не курс.)
        _ = context.persist(otherwise: { dog.isOnTreatment = true })
    }

    /// Контрольный приём — единственное, что переживает курс.
    ///
    /// «Врач ждёт через две недели» — это дело в уходе, а не фраза
    /// на экране прощания. Иначе про приём вспоминают в день приёма.
    static let checkupTitle = "Контрольный приём"
    /// Срок по умолчанию — когда назначение своего срока не называет.
    ///
    /// Две недели — не правило медицины, а частый ответ врача
    /// («посмотрю результат через две недели»), и потому только запас.
    /// Свой срок курса берёт `checkupDelay(for:)`.
    static let checkupDelayDays = 14

    /// Через сколько дней контроль — по НАЗНАЧЕНИЮ курса, если оно есть.
    ///
    /// # Зачем (29.10.2026)
    ///
    /// Срок был прибит числом 14 у всех, хотя врач его называет
    /// и он записан: `Prescription.controlFromWeeks…controlToWeeks`
    /// («контроль через 4–6 недель»), а схема знает своё назначение
    /// по номеру (`Medication.prescriptionNumber`). Экран прощания
    /// напоминал через две недели при назначенных шести.
    ///
    /// Берётся НАЧАЛО окна (`ControlWindow.window(...).opens`) самого
    /// свежего назначения схем этого курса — живых, а если курс уже
    /// завершён, то отменённых им. Окно
    /// считается от даты назначения, как его и пишет врач. Окно уже
    /// открылось или срока нет — `checkupDelayDays`: за врача число
    /// не придумывается, но и «вчера» не назначается.
    @MainActor
    static func checkupDelay(for dog: Dog, now: Date = Date(),
                             calendar: Calendar = .current) -> Int {
        let живые = activeMedications(dog)
        let схемы = живые.isEmpty ? отменённыеКурсом(dog) : живые
        let номера = Set(схемы.compactMap { $0.prescriptionNumber.flatMap(Fmt.notBlank) })
        guard !номера.isEmpty else { return checkupDelayDays }
        let назначение = dog.prescriptions
            .filter { Fmt.notBlank($0.number).map(номера.contains) == true && $0.prescribedControl != nil }
            .max { $0.date < $1.date }
        guard let назначение, let срок = назначение.prescribedControl,
              let окно = ControlWindow.window(prescribedAt: назначение.date, срок, calendar: calendar),
              окно.opens > now else { return checkupDelayDays }
        return max(1, суток(от: now, до: окно.opens, календарь: calendar))
    }

    @MainActor
    @discardableResult
    static func scheduleCheckup(
        for dog: Dog,
        after days: Int = checkupDelayDays,
        from now: Date = Date(),
        context: ModelContext
    ) -> CareTask? {
        let date = Calendar.current.date(byAdding: .day, value: days, to: now) ?? now
        // Второй раз то же дело не заводим: экран прощания можно открыть
        // и закрыть несколько раз подряд.
        // `careTasksStorage`, а НЕ `careTasks`: с 26.10.2026 обёртка
        // отсеивает надгробия, а дедуп — ОПОЗНАНИЕ, не показ. Не увидев
        // удалённое дело, он завёл бы второе с тем же названием, и экран
        // прощания с курсом начал бы плодить «Контроль у врача» парами.
        // Тот же разбор, что у склейки собак по кличке: опознанию нужна
        // правда базы, а не то, что видно человеку.
        if let existing = (dog.careTasksStorage ?? [])
            .first(where: { $0.title == checkupTitle && $0.lastDone == nil }) {
            let былаДата = existing.scheduledDate
            existing.scheduledDate = date
            // Не записалось — не отдаём дело наружу: экран покажет
            // «врач через 10 дней», а напоминания не будет.
            guard context.persist(otherwise: { existing.scheduledDate = былаДата }) else {
                return nil
            }
            return existing
        }

        let task = CareTask(title: checkupTitle,
                            detail: "После курса — врач смотрит результат",
                            kind: .dated,
                            category: .medical,
                            scheduledDate: date)
        task.remindDaysBefore = 3
        task.dog = dog
        context.insert(task)
        guard context.persist(otherwise: { context.delete(task) }) else { return nil }
        return task
    }

    /// Вернуть курс — врач продлил, или нажали не туда.
    ///
    /// Отмена решения обязана быть такой же дешёвой, как решение: без неё
    /// «Курс завершён» становится кнопкой, которую боятся нажимать.
    @MainActor
    static func resume(_ dog: Dog, context: ModelContext) {
        // Парный путь к отмене, и тоже через модель: возврат, снявший
        // `cancelledAt` и забывший `isPaused`, оставил бы схему молча
        // немой — живой на вид и без единого напоминания.
        //
        // Возвращаются только схемы, отменённые ЭТИМ курсом
        // (`отменённыеКурсом`), — не все отменённые у собаки.
        for medication in отменённыеКурсом(dog) {
            medication.вернутьВСтрой()
        }
        dog.isOnTreatment = true
        // Возврат курса — отмена решения, и она обязана быть надёжной:
        // иначе дозы и напоминания пропадут при следующем запуске.
        _ = context.persist(otherwise: { dog.isOnTreatment = false })
    }

    /// Итог курса: сколько шло, сколько доз и какая доля вовремя.
    ///
    /// Считается по уже записанному — ни одного поля «заполните для
    /// отчёта». Единственное место в лечении, где уместна похвала,
    /// и она обязана быть заслуженной: цифры настоящие.
    struct Summary: Equatable {
        /// Сколько СУТОК идёт курс, и суток **календарных**.
        ///
        /// Было `span: TimeInterval` плюс `Int(span / 86400)` в заголовке.
        /// В воскресенье перевода часов в сутках не 24 часа, а 23 или 25,
        /// и курс, перешагнувший такое воскресенье, терял час: ровно
        /// четырнадцать суток давали 13,96, `Int` отрезал до 13 — ветка
        /// `days >= 14` не бралась, и «2 недели позади» превращалось
        /// в «13 дней позади». Два дня в году, на том самом экране, про
        /// который двадцатью строками выше сказано «цифры настоящие».
        ///
        /// Поле хранит уже посчитанное число, а не длительность, нарочно:
        /// длительность считать сутками нельзя **ничем**, и оставить её
        /// рядом значило бы оставить и приглашение поделить её снова.
        /// Единственное место, где сутки получаются, — `суток(от:до:)`.
        var days: Int
        var dosesGiven: Int
        var dosesOnTime: Int
        var skipped: Int

        /// Доля вовремя. Без доз процента не бывает — иначе экран
        /// поздравляет со стопроцентным результатом при нуле отметок.
        var onTimeShare: Double? {
            guard dosesGiven > 0 else { return nil }
            return Double(dosesOnTime) / Double(dosesGiven)
        }

        /// «Шесть недель позади» — неделями, пока это правда неделя.
        var headline: String {
            if days >= 14 {
                let weeks = days / 7
                // **Это была ПОЛОВИНА ПАРЫ, и потому самый тихий случай
                //   из всех.** Внутренний кусок обёрнут правильно
                //   (`\(weeks) недель` — с плюральными формами), а слово
                //   « позади» приклеено СНАРУЖИ обычной интерполяцией
                //   и в каталог не попадало никогда.
                //
                // Грепом такое не ищется: `String(localized:)` в строке
                // ЕСТЬ, и место выглядит переведённым. Видно только
                // при чтении всей строки до конца.
                //
                // > **Обёртка на части строки защищает ту часть,
                // > в которой стоит, и выдаёт переведённой всю строку.**
                //
                // Теперь ключ у ЦЕЛОЙ фразы, а не вложенный: вложение
                // дало бы наружу ключ `%@ позади` — он переводим
                // и переставим, но число и слово оказались бы в разных
                // ключах, и согласовать их носитель уже не смог бы.
                // Один ключ `%lld недель позади` держит и плюральные
                // формы, и порядок слов разом.
                return String(localized: "\(weeks) недель позади")
            }
            if days >= 1 { return String(localized: "\(Fmt.days(days)) позади") }
            return String(localized: "Курс закончен")
        }
    }

    /// Насколько поздняя отметка ещё считается «вовремя».
    ///
    /// **Одна точка на обе сводки — человеку и врачу.** До 28.10.2026
    /// это же число и этот же предикат лежали вторым экземпляром
    /// в `VetSummaryBuilder` (`VetSummary.swift:63` и `:74`),
    /// посимвольно те же три строки. Расхождение было бы не косметикой:
    /// одна сводка показывает «доз вовремя» человеку, вторую он несёт
    /// врачу, и два разных числа про одно и то же читались бы как
    /// разные данные, а не как разные пороги.
    static let onTimeWindow: TimeInterval = 3600

    /// Дана ли доза вовремя.
    ///
    /// На значениях, а не на `DoseRecord`, нарочно: два вызывающих
    /// читают модель каждый в своей изоляции, и общая точка не должна
    /// тащить за собой ни модель, ни главный актор.
    ///
    /// Раннее «дал» сюда попадает: промежуток отрицательный, и он
    /// меньше окна. Так было в обеих копиях — правило здесь
    /// переносится, а не переписывается.
    nonisolated static func даноВовремя(scheduledAt: Date, givenAt: Date?) -> Bool {
        guard let givenAt else { return false }
        return givenAt.timeIntervalSince(scheduledAt) <= onTimeWindow
    }

    /// Сколько суток прошло между двумя моментами — календарём.
    ///
    /// `dateComponents([.day], from:to:)` считает по стенным часам: сутки
    /// перевода, в которых 23 или 25 часов, он засчитывает как одни сутки,
    /// а деление на 86 400 — как 0,96 или 1,04. Разница вылезает один раз
    /// на курс и ровно на границе недели.
    ///
    /// Отрицательное зажимается нулём: первая доза может быть назначена
    /// на завтра, и «минус один день позади» — не то, что читает человек.
    ///
    /// Календарь параметром с умолчанием, а не `Calendar.current` внутри:
    /// расхождение воспроизводится только в конкретном поясе и конкретную
    /// ночь, и без этого параметра проверить его можно было бы лишь
    /// переводом часов на машине прогона. Приложение зовёт без аргумента.
    nonisolated static func суток(от начало: Date, до конец: Date,
                                  календарь: Calendar = .current) -> Int {
        max(0, календарь.dateComponents([.day], from: начало, to: конец).day ?? 0)
    }

    @MainActor
    static func summary(_ dog: Dog, now: Date = Date()) -> Summary {
        let doses = dog.medications.flatMap(\.doses)
        let given = doses.filter(\.isGiven)
        let onTime = given.filter {
            даноВовремя(scheduledAt: $0.scheduledAt, givenAt: $0.givenAt)
        }
        let first = doses.map(\.scheduledAt).min()
        return Summary(
            days: first.map { суток(от: $0, до: now) } ?? 0,
            dosesGiven: given.count,
            dosesOnTime: onTime.count,
            skipped: doses.filter(\.isSkipped).count
        )
    }

    /// Что сказать человеку перед подтверждением.
    @MainActor
    static func farewell(_ dog: Dog) -> String {
        let names = activeMedications(dog).map(\.name)
        let tail = String(localized: "Записи останутся в истории и в отчёте врачу.")
        switch names.count {
        // Про вкладку здесь не говорим: с 08.10.2026 (`02c1e88`) она держится
        // правом `.seeMedical`, а не курсом, и по завершении НЕ прячется.
        case 0: return tail
        case 1: return String(localized: "«\(names[0])» уйдёт из плана дня. \(tail)")
        default:
            return String(localized: "\(names.joined(separator: ", ")) уйдут из плана дня. \(tail)")
        }
    }
}
