import Foundation

/// Акцент стал ВЫБОРОМ, а не значением. Заведено 07.10.2026 под новый
/// дизайн.
///
/// **Почему это логика, а не цвет.** До сих пор акцент был одной
/// величиной: `primitive.color.arctic` = `#D4F75F`, лайм, и семьдесят
/// семь ссылок `semantic/*` и `component/*` смотрели на неё. Новый
/// пакет дизайна («Дневник собаки Togo», окт 2026) устроен иначе:
/// у Figma-коллекции `Accent` **три режима** — Indigo, Orange, Pink, —
/// и каждый несёт свои восемь значений. То есть выбор акцента стал
/// состоянием приложения, которое надо где-то держать, куда-то писать
/// и чем-то проверять.
///
/// Замер 07.10, `tokens/figma-variables.json` нового пакета против
/// `DesignTokens/tokens.json` репозитория:
///
///     коллекция Accent   режимы Indigo · Orange · Pink   24 переменных
///     коллекция Theme    режимы Dark · Light · Dark HC · Light HC
///     репозиторий        один режим, акцент одним значением (лайм)
///
/// **Имена при этом не меняются, и это сделано нарочно** — так написано
/// в описании токена `arctic`: «имя оставлено прежним, сюда смотрят
/// 77 ссылок, смена поколения — одна правка значения, а не
/// переименование по тридцати двум экранам». Значит переход лайм →
/// индиго не трогает ни одного экрана; добавление ВЫБОРА — трогает,
/// и только здесь.
///
/// Этот тип сознательно не знает ни про `Color`, ни про SwiftUI:
/// по решению Виктории 07.10 дизайн и тексты переезжают в Figma и
/// могут меняться, а логика и токены остаются. Всё, что знает тип, —
/// какие варианты существуют, какой из них по умолчанию и как выбор
/// переживает перезапуск.
///
/// **Через варианты ассета этот выбор не кладётся по устройству. Замер
/// 07.10 вечером, `togo-1e`, подробно — `docs/токены-против-фигмы.md`.**
/// `SwiftUI.md` хендоффа велит переносить цвета как «одна Color Set
/// на переменную», и для коллекции `Theme` это верно: её четыре режима
/// (Dark · Light · Dark HC · Light HC) ложатся в четыре слота одного
/// ассета, то есть 68 переменных дают 68 наборов, а не 272.
///
/// С акцентом так нельзя: **вариант ассета выбирает СИСТЕМА (тема,
/// контраст), а акцент выбирает ЧЕЛОВЕК**, и слота под это нет.
/// Устройство коллекции `Accent`: тема запечена в имя переменной
/// (`accent/dark/fill`, `accent/light/fill`), повышенный контраст —
/// только у двух ролей из десяти (`text`, `subtle-text`). Двадцать
/// четыре имени собираются в двенадцать ролей, и носителей нужно
/// 12 × 3 = 36 наборов либо выбор на отрисовке.
///
/// Отсюда следствие, которое стоит знать до первой правки цвета:
/// **в повышенном контрасте заливка главной кнопки не меняется** —
/// HC-значения для `fill` и `pressed` в пакете не заведены вовсе.
/// У Togo контраст этой кнопки уже измеряли, и он был 1,68:1.
nonisolated enum AccentChoice: String, Codable, CaseIterable, Sendable {

    /// По умолчанию. Назван в `tokens/accents.css` нового пакета
    /// прямым текстом: «По умолчанию — индиго».
    case indigo

    /// Коралл. В CSS нового пакета зовётся `data-accent="orange"`,
    /// а в подписи — «коралл». Имя взято из CSS, а не из подписи:
    /// совпадать должно с токеном, а не с текстом.
    case orange

    case pink

    /// Единственное место, где выбор превращается в значение.
    ///
    /// Имя режима в коллекции Figma `Accent` — побайтно то, что лежит
    /// в `figma-variables.json`. Сверять надо именно его: если
    /// переименуют режим, расхождение должно быть видно здесь,
    /// а не проявиться пустым цветом на экране.
    var figmaMode: String {
        switch self {
        case .indigo: "Indigo"
        case .orange: "Orange"
        case .pink: "Pink"
        }
    }

    /// Что подставляется, когда записанного выбора нет или он
    /// нечитаем.
    ///
    /// Отдельная величина, а не `allCases.first`: порядок `CaseIterable`
    /// задаётся порядком объявления, и перестановка случаев молча
    /// сменила бы умолчание у всех, у кого выбор не записан.
    static let fallback: AccentChoice = .indigo

    /// Разобрать записанное. Неизвестное имя — умолчание, а не отказ:
    /// акцент не та величина, из-за которой стоит не показать экран.
    ///
    /// Возвращает ещё и признак «значение было чужим» — чтобы тот, кто
    /// читает, мог сказать об этом вслух, а не считать, что выбора
    /// не делали. Молчаливый откат к умолчанию неотличим от «человек
    /// выбрал индиго».
    static func parse(_ raw: String?) -> (choice: AccentChoice, wasUnknown: Bool) {
        guard let raw, !raw.isEmpty else { return (fallback, false) }
        guard let known = AccentChoice(rawValue: raw) else { return (fallback, true) }
        return (known, false)
    }
}
