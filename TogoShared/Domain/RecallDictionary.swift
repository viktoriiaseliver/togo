import Foundation

/// Слова, по которым разбирается дозапись, — по языкам.
///
/// **Почему это не перевод.** `RecallParser` ищет в напечатанной фразе
/// основы: «понос», «кормил», «вчера». Это ключи разбора, а не подписи,
/// и `String(localized:)` им не подходит — они не показываются человеку
/// и не могут приходить из каталога поштучно: на другом языке их другое
/// число, и «час» по-украински значит время вообще, а часы — «години».
///
/// Замер 23.09.2026: пятьдесят основ лежали в коде русскими литералами,
/// и все пятьдесят при этом переведены в каталоге. Перевод существовал
/// и не работал ни разу — форма та же, что у `Text(строка)` и `Fmt.plural`.
/// Француз писал «il a vomi» и получал `notUnderstood` без объяснения.
///
/// **Апостроф.** Украинская основа `м'як` в исходнике записана U+0027,
/// а клавиатура iOS печатает U+2019. `contains` их равными не считает:
/// тест на строке из исходника прошёл бы, а человек не попал бы никогда.
/// Поэтому и текст, и основы проходят через `нормализовать`.
nonisolated struct RecallDictionary: Sendable {

    /// Основы по виду записи. Порядок важен так же, как и в русском:
    /// первая найденная выигрывает.
    let основы: [(LogKind, [String])]

    /// «сегодня», «вчера», «позавчера» — в том же порядке.
    let сегодня: [String]
    let вчера: [String]
    let позавчера: [String]

    /// Связки периода: «с … по», «с … до». Нужны обе стороны.
    let началоПериода: [String]
    let конецПериода: [String]

    /// Апостроф, дефис и регистр приводятся к одному виду.
    ///
    /// U+2019 (типографский) и U+02BC (модификатор) встречаются в том,
    /// что печатает клавиатура; U+0027 — в том, что пишут в коде.
    static func нормализовать(_ текст: String) -> String {
        текст.lowercased()
            .replacingOccurrences(of: "\u{2019}", with: "'")
            .replacingOccurrences(of: "\u{02BC}", with: "'")
            .replacingOccurrences(of: "\u{0060}", with: "'")
    }

    /// Словарь по языку приложения. Неизвестный язык — русский:
    /// отвечать `notUnderstood` там, где разбор возможен, хуже, чем
    /// разобрать по языку разработки.
    static func дляЯзыка(_ код: String) -> RecallDictionary {
        switch код {
        case "uk": украинский
        case "fr": французский
        default: русский
        }
    }

    static var текущий: RecallDictionary {
        дляЯзыка(String(Locale.preferredLanguages.first?.prefix(2) ?? "ru"))
    }

    // MARK: Языки

    /// Две правки 23.09, обе найдены тестом, а не чтением:
    ///
    /// * **«не ел»** — основа «ел » требует пробела ПОСЛЕ, а фраза
    ///   «вчера не ел» кончается этим словом. Отказ от еды не
    ///   записывался вовсе, а это ровно то, ради чего дневник и ведут,
    ///   когда собака болеет.
    /// * **«дал » с пробелом** — голое «дал» сидит внутри «далеко»,
    ///   и «далеко не гуляли» становилось ДОЗОЙ. В приложении, которое
    ///   защищает от двойной дозы, ложная запись о приёме — худший
    ///   из возможных разборов.
    ///
    /// Оба случая до того найдены в украинском и французском списках;
    /// русский их и подсказал, но сам от них не был защищён.
    static let русский = RecallDictionary(
        основы: [
            (.stool,  ["понос", "стул", "какал", "покакал", "диаре"]),
            (.meal,   ["кормил", "корми", "поел", "не ел", "ел ", "еда", "покормил"]),
            (.dose,   ["таблет", "дал ", "дали", "доза", "препарат", "лекарств"]),
            (.walk,   ["гулял", "гуляли", "прогул", "выгул"]),
            (.outing, ["выходил", "выходили", "пописал", "по делам"]),
            (.incident, ["рвот", "вырвал", "тошнил", "лужа"]),
            (.weight, ["весит", "взвесил", "вес "]),
        ],
        сегодня: ["сегодня"],
        вчера: ["вчера"],
        позавчера: ["позавчера"],
        началоПериода: [" с ", "с "],
        конецПериода: [" по ", " до ", "–", "—"]
    )

    /// Французский ждёт слов. Украинский заполнен 23.09 — ниже.
    ///
    /// Пустой список — это честное «не разбираю», а не «разбираю
    /// по-русски»: русская основа во французской фразе не найдётся
    /// всё равно, а выглядело бы как рабочий словарь.
    /// Слова заводит переводчица; структура готова и ждёт их.
    /// Французский, 23.09.2026. **Слова ждут подтверждения носителем** —
    /// как и украинские: выбор основ сделан переводчицей.
    ///
    /// Французский не склоняет, но спрягает и сокращает: «il a vomi»,
    /// «elle a mangé», «j'ai donné». Поэтому основы — причастия и корни
    /// глаголов, а не инфинитивы: в дневнике пишут о том, что уже было.
    ///
    /// **«caca» голым ставить нельзя: оно внутри «cacahuète».** Тест
    /// «il a mangé une cacahuète» ловился как стул, потому что stool
    /// проверяется раньше meal. Русский список обходит то же самое
    /// («какао») тем, что держит ГЛАГОЛЫ — «какал», «покакал». Во
    /// французском глагола нет, поэтому две формы: «fait caca» —
    /// обычное «il a fait caca», и «caca » с пробелом — «caca mou».
    /// Ни одна не совпадает с «cacahuète».
    ///
    /// **«sorti» стоит только в `outing`.** Оно годилось бы и для
    /// прогулки, но у русского и украинского списков то же разделение:
    /// «promen»/«balade» — прогулка, «sorti»/«dehors» — выход по делам.
    /// Класть одно слово в два вида нельзя: первый найденный выигрывает,
    /// и порядок решал бы за человека.
    static let французский = RecallDictionary(
        основы: [
            (.stool,  ["diarrh", "selles", "fait caca", "caca ", "molle"]),
            (.meal,   ["mang", "nourri", "repas", "croquettes", "gamelle"]),
            (.dose,   ["comprim", "médicament", "cachet", "dose", "donn"]),
            (.walk,   ["promen", "balade"]),
            (.outing, ["sorti", "dehors", "pipi"]),
            (.incident, ["vomi", "flaque", "nausé"]),
            (.weight, ["pèse", "pesé", "poids"]),
        ],
        сегодня: ["aujourd'hui"],
        вчера: ["hier"],
        позавчера: ["avant-hier"],
        началоПериода: [" du ", " de "],
        конецПериода: [" au ", " à ", " jusqu"]
    )

    /// Украинский, 23.09.2026. **Слова ждут подтверждения носителем** —
    /// структура заполнена, но выбор основ сделан переводчицей.
    ///
    /// Здесь действует правило, ОБРАТНОЕ глоссарию. Глоссарий велит для
    /// подписи `стул → випорожнення`; для разбора это бесполезно: человек
    /// пишет в переписке не «випорожнення», а «какав» или «пронос».
    /// Поэтому рядом стоят и літературна форма, и та, которой пользуются,
    /// включая російські запозичення: **ловим то, что печатают, а не то,
    /// что правильно показать.**
    ///
    /// **«пописав» двусмысленно**: по-украински это и «сходил по-малому»,
    /// и «немного пописал» — то есть написал. Рядом поэтому стоит
    /// однозначное «попісяв». Русское «пописал» страдает тем же, и там
    /// это принято; здесь двусмысленность хотя бы названа.
    ///
    /// **«стілець» намеренно НЕ включено.** Глоссарий зовёт его мебелью,
    /// и он прав для подписи. Для разбора русскоязычный українець мог бы
    /// его напечатать — но решать, ловить ли кальку, должен носитель,
    /// а не я. Названо здесь, чтобы решение приняли, а не забыли.
    ///
    /// **Основы, а не формы — но не везде.** Первая редакция писала
    /// «годував», и оно не ловило «годували»: окончания разные. Русский
    /// список решает это тем же приёмом — «корми» вместо «кормил».
    ///
    /// Обратный случай рядом: основа «рідк» ловит **наречие «рідко»**
    /// («нечасто»), и «гуляли рідко» становилось стулом, потому что
    /// stool проверяется раньше walk. Поэтому там три ФОРМЫ прилагательного
    /// — «рідкий», «рідке», «рідка», — и ни одна не совпадает с «рідко».
    ///
    /// **«їв » с пробелом не ловит конец фразы.** «сьогодні не їв»
    /// заканчивается на «їв», пробела после нет — и разбор молчал.
    /// Голое «їв» ставить нельзя: оно содержится в «Київ», а у Того есть
    /// режим поездок. Поэтому явное «не їв» — отказ от еды и есть то,
    /// ради чего эту фразу пишут.
    ///
    /// Поймано тестом. Мой предварительный прогон на Python этого НЕ
    /// нашёл: он повторял сопоставление своей строкой, а не звал
    /// `RecallParser`. Проверка второй реализацией — это проверка
    /// второй реализации.
    ///
    ///     Основа короче — ловит больше своего и чужого.
    ///     Где короткая основа сталкивается с другим словом, нужна форма.
    ///
    /// И то и другое нашлось прогоном по фразам, а не чтением списка.
    ///
    /// Короткие основы («дав», «вага») опасны совпадением: «давно»,
    /// «важко». Там, где можно, оставлен пробел — «дав » ловит «дав
    /// таблетку» и не ловит «давно». Русский список имеет ту же слабость
    /// с «дал», и порядок разбора её частично снимает: «пронос»
    /// проверяется раньше «дав».
    static let украинский = RecallDictionary(
        основы: [
            (.stool,  ["пронос", "понос", "випорожн", "кака", "діаре", "рідкий", "рідке", "рідка"]),
            (.meal,   ["годув", "нагодув", "поїв", "з'їв", "не їв", "їв ", "їсть", "їжа", "корм"]),
            (.dose,   ["таблет", "дав ", "дали", "доза", "препарат", "ліки"]),
            (.walk,   ["гуля", "прогул", "вигул"]),
            (.outing, ["виходи", "вийш", "попісяв", "пописав", "у справах"]),
            (.incident, ["блюв", "вирвал", "нудил", "калюж"]),
            (.weight, ["важить", "зваж", "вага "]),
        ],
        сегодня: ["сьогодні"],
        вчера: ["вчора", "учора"],
        позавчера: ["позавчора"],
        началоПериода: [" з ", "з "],
        конецПериода: [" по ", " до ", "–", "—"]
    )

    /// Есть ли чем разбирать. Пустой словарь означает, что язык заведён,
    /// а слова ещё не написаны, — и человеку об этом надо сказать иначе,
    /// чем «не понял».
    var пустой: Bool { основы.isEmpty }
}
