/// Слова, по которым разбирается дозапись, — по языкам.
///
/// **Почему это не перевод.** `RecallParser` ищет в напечатанной фразе
/// основы: «понос», «кормил», «вчера». Это ключи разбора, а не подписи,
/// и `String(localized:)` им не подходит — они не показываются человеку
/// и не могут приходить из каталога поштучно: на другом языке их другое
/// число, и «час» по-украински значит время вообще, а часы — «години».
///
/// Замер 23.09.2026: пятьдесят основ лежали в коде русскими литералами,
/// и все пятьдесят при этом переведены в каталоге. Перевод существовал
/// и не работал ни разу — форма та же, что у `Text(строка)` и `Fmt.plural`.
/// Француз писал «il a vomi» и получал `notUnderstood` без объяснения.
///
/// **Апостроф.** Украинская основа `м'як` в исходнике записана U+0027,
/// а клавиатура iOS печатает U+2019. `contains` их равными не считает:
/// тест на строке из исходника прошёл бы, а человек не попал бы никогда.
/// Поэтому и текст, и основы проходят через `нормализовать`.
nonisolated struct RecallDictionary: Sendable {

    /// Основы по виду записи. Порядок важен так же, как и в русском:
    /// первая найденная выигрывает.
    let основы: [(LogKind, [String])]

    /// «сегодня», «вчера», «позавчера» — в том же порядке.
    let сегодня: [String]
    let вчера: [String]
    let позавчера: [String]

    /// Связки периода: «с … по», «с … до». Нужны обе стороны.
    let началоПериода: [String]
    let конецПериода: [String]

    /// Единицы после числа: «65 г», «два раза», «полтора часа».
    ///
    /// **Это куски регулярного выражения, а не подписи.** `г\\b`
    /// живёт здесь по той же причине, что и остальные основы: 23.09.2026
    /// он лежал в каталоге переводимым ключом — и его **перевели**.
    /// По-французски вышло `g\\b`, то есть верно, но верно случайно:
    /// переводчик видел в выгрузке `г\\b` без всякого контекста и мог
    /// написать что угодно. Рядом так же перевелись «грамм», «раз»,
    /// «час» и «мин» — и украинское «година» для «час» ровно тот случай,
    /// о котором написано выше: слово верное, а разбор оно ломает.
    ///
    /// Главное же: разбор **брал зашитые литералы**, а не переводы.
    /// То есть перевод существовал, выглядел работающим и не значил
    /// ничего — та же форма, что у `Text(строка)` и `Fmt.plural`.
    let граммы: [String]
    let разы: [String]
    let часы: [String]
    let минуты: [String]

    /// Как человек описывает стул. Порядок важен: первое совпадение
    /// выигрывает, и «жидк» должно проверяться раньше «мягк».
    let формыСтула: [(StoolForm, [String])]

    /// Новые оси разбора по умолчанию пусты — то есть «не разбираю».
    ///
    /// Пустое значение честнее выдуманного: словарь без единиц просто
    /// не найдёт граммы, а словарь с чужими единицами найдёт не то.
    /// Та же причина, по которой пустыми заводились французский
    /// и украинский, пока их не написал носитель.
    init(основы: [(LogKind, [String])],
         сегодня: [String], вчера: [String], позавчера: [String],
         началоПериода: [String], конецПериода: [String],
         граммы: [String] = [], разы: [String] = [],
         часы: [String] = [], минуты: [String] = [],
         формыСтула: [(StoolForm, [String])] = []) {
        self.основы = основы
        self.сегодня = сегодня
        self.вчера = вчера
        self.позавчера = позавчера
        self.началоПериода = началоПериода
        self.конецПериода = конецПериода
        self.граммы = граммы
        self.разы = разы
        self.часы = часы
        self.минуты = минуты
        self.формыСтула = формыСтула
    }

    /// Апостроф, дефис и регистр приводятся к одному виду.
    ///
    /// U+2019 (типографский) и U+02BC (модификатор) встречаются в том,
    /// что печатает клавиатура; U+0027 — в том, что пишут в коде.
    static func нормализовать(_ текст: String) -> String {
        текст.lowercased()
            .replacingOccurrences(of: "\u{2019}", with: "'")
            .replacingOccurrences(of: "\u{02BC}", with: "'")
            .replacingOccurrences(of: "\u{0060}", with: "'")
    }

    /// Словарь по языку приложения. Неизвестный язык — русский:
    /// отвечать `notUnderstood` там, где разбор возможен, хуже, чем
    /// разобрать по языку разработки.
    ///
    /// **`en` и `kk` добавлены 27.10.2026, и до того они были
    /// не «запасным путём», а неработающим.** Запасной русский
    /// задуман для языка, которого у приложения нет (`de`, `es`);
    /// у заявленного языка он означает другое: англичанин печатает
    /// «fed him at 8», словарь ищет «кормил», совпадений ноль, и
    /// человек получает `notUnderstood` на своём же родном языке.
    /// Замер 27.10: десять обиходных фраз, пять английских и пять
    /// казахских, против русских основ — **ноль совпадений
    /// из десяти**.
    ///
    /// > Строка «неизвестный язык — русский» была верна, когда языков
    /// > было три. Пять языков приехали `f7f938d` 22.10, и условие
    /// > **сменило смысл, не изменившись ни буквой**: то, что
    /// > защищало немца, стало отключать англичанина и казаха.
    /// > Ось «у каждого ЗАЯВЛЕННОГО языка свой словарь» сторожит
    /// > `RecallDictionaryTests.уКаждогоЯзыкаПриложенияЕстьСловарь`.
    static func дляЯзыка(_ код: String) -> RecallDictionary {
        switch код {
        case "uk": украинский
        case "fr": французский
        case "en": английский
        case "kk": казахский
        default: русский
        }
    }

