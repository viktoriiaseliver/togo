import Foundation
import SwiftData

/// Запись дозаписи в дневник.
///
/// Разбор (`RecallParser`) текст только понимает. Класть в базу — сюда,
/// и это намеренно два разных места: разбор проверяется тестами без
/// хранилища, а запись обязана считаться с правами, дублями
/// и происхождением.
///
/// **Ничего не пишется без подтверждения человека.** На вход идут
/// черновики, которые он уже увидел списком и поправил: снял лишние дни,
/// подвинул даты, дописал словами. `RecallWriter` не разбирает текст
/// и не угадывает — он только сохраняет согласованное.
///
/// # Мест вызова ноль, и подключать его СЕГОДНЯ нельзя — не по форме
///
/// Замер 08.10.2026 на `ca8b276`: `RecallWriter.` вне `TogoTests/`
/// не встречается нигде. Это держит сторож
/// `SingleDoorTests.дозаписьМертва` — он покраснеет, как только
/// появится первый вызов. Сторож есть, а **причины в голове модуля
/// не было**, и из этого выходило, что подключение — обычный долг.
///
/// Причин две, и обе измерены, а не выведены.
///
/// **Первая: форма входа другая.** Макет `Togo ФИНАЛ v2` § «10 · H1 ·
/// Перерыв в записях» просит форму по дням с тумблерами и чипами
/// «точно / примерно», а не экран чата. Подробности и замер —
/// в голове `RecallParser`.
///
/// **Вторая, и она опаснее: у макета и у модели РАЗНЫЕ ОСИ.**
///
/// Макет делит записи по **точности** — чип «Насколько точно»
/// (`точно` · `примерно`) — и в примечании требует: «„Примерно“ —
/// записи с „≈“ в ленте, Истории и отчёте врачу; ритм „Просится“
/// по ним не учится».
///
/// В модели осей две, и ни одна не отвечает на этот вопрос:
///
/// ```
/// RecordOrigin      ОТКУДА запись: logged · recalled · parsed · period
/// LogEvent.isDayOnly ТОЧНОСТЬ ВРЕМЕНИ: известен ли час
/// насколько человек уверен в САМОМ СОБЫТИИ   — поля нет
/// ```
///
/// Точная дозапись («кормили ровно два раза, помню») и примерная
/// («выходили примерно четырежды») обе придут сюда с `isDayOnly = true`
/// и обе могут прийти с одним `origin`. Отличить их нечем.
///
/// Что по этой части УЖЕ сделано — проверено чтением, а не
/// предположено: `WalkRhythmAnalyzer.rhythm` (`WalkRhythm.swift:71`)
/// держит два набора — `recent` для дней и `precise = recent.filter
/// { !$0.isDayOnly }` для часов. Час у дозаписи уже не врёт:
/// «обычно выходите в 00:00» получиться не может.
///
/// Чего НЕТ: `RecordOrigin.countsAsMoment` (`RecordOrigin.swift:47`)
/// читают **только три теста** — `RecallParserTests:129-131`.
/// В продукте его не спрашивает никто, и `outingsPerDay` считается
/// по `recent`, то есть вместе с дозаписанными днями. Пока этот
/// модуль мёртв, в базе нет ни одной такой записи и дыра невидима.
///
/// ТЗ назвало эту цену прямо 21.09 («статистика должна научиться
/// читать периоды — это и есть основная цена решения»), и цена
/// не заплачена. Поэтому порядок такой: **сперва поле точности
/// и его читатель в ритме, потом кнопка в форме.** Обратный порядок
/// даёт зелёный прогон и число «обычно 4 выхода в день», собранное
/// из того, что человек помнит приблизительно.
///
/// И то, чего этот модуль сделать не вправе: `origin` едет во второй
/// телефон (`SharedDiaryRecords.swift:72`), а человеку не показывается
/// нигде — `RecordOrigin.title` читателей ноль во всём `Togo/`
/// и `TogoWidgets/`. Макет просит «≈» в ленте, Истории **и отчёте
/// врачу**; заказчица 21.09 просила обратного — «в выгрузке дозапись
/// не отличается от истории, пометка видна только пользователю».
/// Это расхождение двух её же решений, и его решает она, а не код.
nonisolated enum RecallWriter {

    /// Что получилось записать.
    public struct Outcome: Equatable {
        public var written: Int
        public var skipped: Int
        /// Дни, которые уже есть в дневнике: второй раз их не пишем.
        public var duplicates: [Date]
    }

    /// Записать подтверждённые дни.
    ///
    /// - Parameters:
    ///   - drafts: черновики после правки человеком.
    ///   - origin: `.parsed`, если пришло из текста, `.recalled` — если
    ///     человек завёл дни руками. Врач разницы не увидит, приложение —
    ///     обязано.
    @MainActor
    @discardableResult
    static func write(
        _ drafts: [RecallParser.DayDraft],
        for dog: Dog,
        author: String,
        origin: RecordOrigin,
        existing: [LogEvent],
        context: ModelContext
    ) -> Outcome {
        let calendar = Calendar.current
        var written = 0
        var вставленные: [LogEvent] = [], skipped = 0
        var duplicates: [Date] = []

        for draft in drafts {
            guard !draft.isExcluded else { skipped += 1; continue }

            // Дубль — это уже записанный **день того же вида**. Час здесь
            // не сравниваем: у дозаписи его нет, и сравнивать было бы
            // нечем. Без этой проверки повторный разбор того же письма
            // удвоил бы две недели истории.
            let alreadyThere = existing.contains { event in
                event.kindRaw == draft.kind.rawValue
                    && calendar.isDate(event.date, inSameDayAs: draft.day)
                    && event.isDayOnly
            }
            if alreadyThere {
                duplicates.append(draft.day)
                skipped += 1
                continue
            }

            let event = LogEvent(kind: draft.kind, date: draft.day, authorName: author)
            event.dog = dog
            event.origin = origin
            event.enteredAt = Date()
            // Час неизвестен — и это записано полем, а не подставлено
            // полуднем. Полдень выглядел бы измерением.
            event.isDayOnly = true
            event.note = draft.note
            if let seconds = draft.durationSeconds { event.durationSeconds = seconds }
            context.insert(event)
            вставленные.append(event)
            written += 1
        }

        // Не записалось — отвечаем честным нулём: человек дописывал
        // день и должен увидеть «не вышло», а не «внесено пять».
        if written > 0, !context.persist(otherwise: { вставленные.forEach(context.delete) }) {
            return Outcome(written: 0, skipped: skipped, duplicates: duplicates)
        }
        return Outcome(written: written, skipped: skipped, duplicates: duplicates)
    }

    /// Строка для выгрузки врачу.
    ///
    /// Требование заказчицы: в теле выгрузки дозапись **не отличается**
    /// от истории — врач читает одну таблицу, а не две. Но врач принимает
    /// решения по этим данным, и «понос 13 сентября» по памяти —
    /// свидетельство другой силы, чем отметка в 14:02.
    ///
    /// Компромисс: пометок у строк нет, а в конце документа — одна строка
    /// числом. Без разбивки, без указания каких именно записей.
    /// Пусто, если по памяти не внесено ничего.
    static func footnote(for events: [LogEvent]) -> String? {
        let recalled = events.filter(\.isRecalled).count
        guard recalled > 0 else { return nil }
        return "\(String(localized: "\(recalled) записей внесены")) "
            + String(localized: "по памяти, из \(events.count)")
    }
}
