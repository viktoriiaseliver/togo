import Foundation

/// Настройки общей группы приложения — одна дверь вместо одиннадцати копий.
///
/// До 04.11.2026 в одиннадцати файлах стояло
/// `AppGroupDefaults.shared`, и запас
/// `.standard` был молчаливым: без группы (сломанное право в профиле,
/// чужая подпись) всё писалось туда, где его не видит ни виджет, ни Live
/// Activity, ни интенты, — и приложение не говорило об этом никому.
/// Запас остаётся (приложению без группы лучше жить, чем падать),
/// но теперь он оставляет след в журнале, и место у него одно.
///
/// Шов для тестов — пачка 3 `docs/аудит-рефакторинга-2026-11-04.md`:
/// подмена хранилища делается здесь, а не в одиннадцати местах.
///
/// Строку `UserDefaults(suiteName:` ищет `DeadLogicTests.общаяГруппаОбъявлена`
/// (манифест приватности обязан объявлять 1C8F.1) — она живёт здесь.
nonisolated enum AppGroupDefaults {
    static var shared: UserDefaults {
        if let группа = UserDefaults(suiteName: AppIdentifiers.appGroup) {
            return группа
        }
        log.error("общей группы приложения нет — настройки уходят в .standard, виджет и интенты их не увидят")
        return .standard
    }
}
