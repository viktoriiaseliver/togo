import Foundation
import SwiftData

/// Такая же запись минуту назад — почти наверняка второй тап,
/// а не второе кормление.
///
/// **Почему отдельно от `EventLog`.** Правило жило внутри `EventLog`,
/// и защищён был ровно один путь — экранный. Запись голосом, кнопкой
/// «Действие» и ярлыком идёт мимо: `QuickLog.record` вставляет событие
/// и сохраняет, не спрашивая ни о правах, ни о дубле. То есть сказать
/// Siri «покорми» дважды подряд можно без всякой защиты, и человек
/// об этом не узнает: второй путь ещё и не пишет в журнал действий,
/// так что в замере его будто нет.
///
/// Замер 23.09.2026 по журналу с телефона: 112 записей, два дубля,
/// оба пойманы экранным путём (`record meal duplicate` через 6 и 8 секунд
/// после записи). Защита работает там, где она есть, — и её нет там,
/// где нажимают не глядя на экран, то есть где второй тап вероятнее всего.
///
/// **Почему в `TogoShared`, а не в `Togo/Store`.** 07.10.2026 нашёлся
/// третий путь записи — `WalkRecorder.record`, — и он лежит здесь,
/// в общем слое, потому что им пишет и метка у двери из виджета.
/// Пока правило жило в цели приложения, позвать его оттуда было нельзя
/// **по устройству проекта**: `TogoShared` собирается и в `Togo`,
/// и в `TogoWidgetsExtension`, а `Togo/Store` — только в приложение.
/// То есть путь шёл мимо не по забывчивости: дороги к правилу не было.
@MainActor
enum DuplicateGuard {

    /// Насколько близко две одинаковые записи считаются одним тапом.
    ///
    /// Не выдумано: в живом дневнике нашлись три записи еды по 65 г
    /// с интервалом в две секунды — человек жал кнопку, не получая отклика,
    /// а потом удалял все три. Отклик починен, но защита нужна всё равно:
    /// палец соскакивает, и кнопку жмут дважды.
    static let window: TimeInterval = 90

    /// Окно для видов, где повтор бывает настоящим.
    ///
    /// Собака и правда писает несколько раз за прогулку — это записано
    /// рядом с набором ниже и верно. Неверным было следствие: раз повтор
    /// бывает настоящим, `.outing` не охранялся вовсе.
    ///
    /// Замер 07.10.2026 — интервалы между отметками «пописал» внутри
    /// одной прогулки, по журналу действий. Секунды, не минуты: в выгрузке
    /// дневника время минутное, то есть грубее любого окна сторожа,
    /// и там этот вопрос неразрешим ни в какую сторону.
    /// Повторяется `Tools/замер_дублей.py`.
    ///
    /// ```
    /// 09-22 20:14   3с · 2с          дубль     тап по одной кнопке
    /// 09-25 08:09   1с               дубль
    /// 10-05 21:50   2с · 1с          дубль
    /// 10-05 17:44   36с · 131с · 213с   настоящие
    /// 09-23 14:06   353с                настоящие
    /// 09-24 08:28   387с                настоящие
    /// 09-25 21:53   387с                настоящие
    /// 09-28 20:39   508с                настоящие
    /// ```
    ///
    /// Разрыв между группами широкий: худший дубль 3 с, ближайший
    /// настоящий повтор 36 с. Десять секунд — в 3,3 раза больше первого
    /// и в 3,6 раза меньше второго.
    ///
    /// **Граница числа:** пять дублей и семь настоящих повторов у одной
    /// собаки, это весь материал. Шире него оно не обосновано; поднимать
    /// его, не перемерив, нельзя — при общем окне 90 секунд
    /// заблокировалась бы отметка 15:45:25, то есть настоящая.
    static let repeatableWindow: TimeInterval = 10

    /// Виды записей, где два тапа подряд почти наверняка ошибка.
    ///
    /// `.outing` здесь с 07.10.2026 — со своим окном, а не с общим:
    /// см. `repeatableWindow`. Остальное повторяемое по смыслу сюда
    /// не входит: воду собака пьёт когда хочет.
    static let deduplicated: Set<LogKind> = [.outing, .meal, .walk, .care, .dose, .weight]

    /// Виды, которым общее окно велико: повтор у них бывает настоящим.
    static let repeatable: Set<LogKind> = [.outing]

    /// Своё окно вида, а не одно на всех.
    static func span(of kind: LogKind) -> TimeInterval {
        repeatable.contains(kind) ? repeatableWindow : window
    }

    /// Есть ли уже такая запись рядом по времени.
    ///
    /// Спрашиваем хранилище напрямую, а не связь `dog.events`. Связь
    /// применяется не мгновенно, и защита не срабатывала вовсе.
    static func recent(of kind: LogKind, dog: Dog, at date: Date,
                       like candidate: LogEvent, in context: ModelContext) -> LogEvent? {
        guard deduplicated.contains(kind) else { return nil }

        let raw = kind.rawValue
        let окно = span(of: kind)
        let from = date.addingTimeInterval(-окно)
        let till = date.addingTimeInterval(окно)
        var descriptor = FetchDescriptor<LogEvent>(
            predicate: #Predicate { $0.kindRaw == raw && $0.date > from && $0.date < till },
            sortBy: [SortDescriptor(\.date, order: .reverse)]
        )
        descriptor.fetchLimit = 30

        let dogID = dog.persistentModelID
        return (try? context.fetch(descriptor))?.first { existing in
            existing.deletedAt == nil
                && existing.dog?.persistentModelID == dogID
                && existing.persistentModelID != candidate.persistentModelID
                && refersToSameThing(existing, candidate)
        }
    }

    /// Две записи одного вида — это правда одно и то же?
    ///
    /// По виду судить мало. В живом дневнике две записи ухода стоят
    /// в секунде друг от друга — «Вычесать» и «Когти», — и это два разных
    /// дела, а не двойной тап. То же с препаратами: два лекарства в один
    /// час дают порознь и намеренно.
    static func refersToSameThing(_ lhs: LogEvent, _ rhs: LogEvent) -> Bool {
        switch lhs.kind {
        case .care: lhs.careTaskID == rhs.careTaskID
        case .dose: lhs.medicationID == rhs.medicationID
        // «Собака попросилась» и «собака пописала» — две записи `.outing`
        // об одном выходе, и обе настоящие. Экран нужды пишет выход
        // без результата (`NeedsSheet.startOuting` не заполняет ничего),
        // отметка прогулки — с `outcome`.
        //
        // Различитель несущий, а не для порядка: замер 07.10.2026 нашёл
        // эти две записи в 8 секундах друг от друга (19:50:16 и 19:50:24),
        // то есть ВНУТРИ десятисекундного окна. Без него второй тип
        // записи блокировал бы первый.
        case .outing: lhs.outcome == rhs.outcome
        default: true
        }
    }

    /// То же правило для двух записей на руках — без хранилища.
    ///
    /// Нужно там, где записи вставляют пачкой: отметки одной прогулки
    /// до `save` в хранилище ещё нет, и `recent` искать их негде.
    /// Опираться на то, увидит ли `fetch` несохранённую вставку, —
    /// значит ставить защиту на поведение, которого мы не мерили;
    /// пачка просеивается явно.
    ///
    /// Все три дубля замера 07.10.2026 лежали **внутри одной пачки** —
    /// три отметки мочи одной прогулки, — так что без этого пути
    /// покрытие `.outing` не достало бы ни до одного из них.
    static func isDuplicate(_ lhs: LogEvent, _ rhs: LogEvent) -> Bool {
        let kind = lhs.kind
        guard kind == rhs.kind, deduplicated.contains(kind) else { return false }
        guard lhs.deletedAt == nil, rhs.deletedAt == nil else { return false }
        guard abs(lhs.date.timeIntervalSince(rhs.date)) < span(of: kind) else { return false }
        return refersToSameThing(lhs, rhs)
    }

    /// Что сказать человеку про найденный дубль.
    static func message(_ kind: LogKind, at date: Date) -> String {
        String(localized: "\(kind.title) уже записана в \(Fmt.clock(date))")
    }
}
