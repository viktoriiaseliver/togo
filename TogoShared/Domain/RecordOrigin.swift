import Foundation

/// Откуда взялась запись в дневнике.
///
/// Заведено 21.09.2026. До этого все записи были одинаковыми, и ровно
/// поэтому две недели без отметок нечем было закрыть: внести еду
/// за прошлый вторник значило соврать, что её отметили тогда.
///
/// Разница видна **пользователю** и не мешает **врачу** — так просила
/// заказчица, и в выгрузке записи идут одной таблицей. Но знать, какие
/// из них восстановлены по памяти, приложение обязано: на этом держится
/// и честность сводки, и решение, можно ли считать по ним статистику.
/// # Почему `nonisolated`, и почему это не снятие изоляции ради вызова
///
/// Замерено 08.10.2026 прогоном, не чтением. `SWIFT_DEFAULT_ACTOR_ISOLATION
/// = MainActor` (`project.pbxproj:424`), а этот тип единственный в
/// `TogoShared/Domain/` объявлен без `nonisolated` — все соседи
/// (`Diary`, `OutingSilence`, `WalkRhythmAnalyzer`, `RecallParser`)
/// его несут. Отсюда:
///
/// ```
/// WalkRhythm.swift:68: error: main actor-isolated property
///                      'countsAsMoment' can not be referenced
///                      from a nonisolated context
/// ```
///
/// **Требование, записанное в доккомментарии `countsAsMoment` 21.09
/// («`WalkRhythm` обязан читать такие записи отдельно»), было
/// НЕВЫПОЛНИМО по изоляции.** `WalkRhythmAnalyzer` — `nonisolated`,
/// и прочитать это свойство он не мог вовсе.
///
/// > **Пока единственные читатели — тесты, изоляция не проверяется:
/// > наборы идут на главном акторе, и свойство выглядит доступным
/// > откуда угодно.** «Читателей нет» и «читать нельзя» — разные
/// > поломки, и вторая прячется за первой.
///
/// И почему здесь верно именно `nonisolated`, а не `@MainActor`
/// на месте вызова, как велит правило 07.10 про `ProGate`: там
/// изолированный фильтр читал свойства `@Model`, то есть снятие
/// изоляции разрешило бы читать собак с любого потока — чужой
/// красный компилятор обменивался на свою гонку данных. Здесь
/// у типа нет ни одного хранимого свойства: `title` и
/// `countsAsMoment` — чистые функции от `self`, тип `Sendable`
/// и `String`-raw. Читать его из любого потока нечем испортить.
///
/// Обратный ход — `@MainActor` на `WalkRhythmAnalyzer` — противоречил
/// бы его собственному объявлению и объявлению всех соседей
/// по каталогу: весь слой `TogoShared/Domain/` вынесен из главного
/// актора нарочно.
///
/// *Здесь в первой редакции стояло «счёт ритма зовут из виджета» —
/// я это ВЫДУМАЛ к верному замеру. Проверка: `WalkRhythm`,
/// `RecordOrigin` и `countsAsMoment` в `TogoWidgets/` не встречаются
/// ни разу. Довод снят, замер остался.*
nonisolated public enum RecordOrigin: String, Codable, CaseIterable, Sendable {
    /// Отмечено в момент события — обычная кнопка в приложении.
    case logged

    /// Внесено задним числом руками: человек открыл форму, выбрал дату.
    case recalled

    /// Разобрано из свободного текста («режим чата»).
    case parsed

    /// Период, а не событие: «гуляли примерно каждый день по 4 часа
    /// с 04.09 по 20.09».
    ///
    /// Отдельный случай, потому что у периода **нет момента**. Разворачивать
    /// его в семнадцать прогулок с придуманным временем нельзя: это данные,
    /// которых не было, и в выгрузке врачу они стали бы неотличимы
    /// от измеренных. Период честен и дыру закрывает так же.
    case period

    /// Как назвать пользователю. Врач этих слов не видит.
    public var title: String {
        switch self {
        case .logged: return String(localized: "отмечено сразу")
        case .recalled: return String(localized: "внесено позже")
        case .parsed: return String(localized: "записано через чат")
        case .period: return String(localized: "период, по памяти")
        }
    }

    /// Можно ли считать по такой записи статистику ритма и медианы.
    ///
    /// По периоду — нельзя как по событию: у него нет момента, и в медиану
    /// он войти не может, не исказив её. `WalkRhythm` обязан читать такие
    /// записи отдельно, а не вперемешку с точными.
    public var countsAsMoment: Bool { self != .period }
}
