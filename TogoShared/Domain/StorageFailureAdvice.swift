import Foundation

/// Что говорить человеку, когда хранилище не открылось.
///
/// **Отдельный тип, а не текст во вью, по двум причинам.** Первая —
/// проверяемость: утверждение «совет не предлагается там, где он
/// губителен» должно уметь краснеть, а вью без кадра этого не покажет.
/// Вторая — у нас уже оплачено: один текст на несколько причин даёт
/// совет, неверный для большинства из них, и сторож теперь требует
/// у каждой причины свой текст.
///
/// **Чем это было до 07.10.2026 и почему это дефект, а не неточность.**
/// `StorageFailureScreen` держал `steps` КОНСТАНТОЙ из трёх пунктов,
/// и третий звал переустановить: «Дневник вернётся из iCloud или
/// из сохранённого файла». Над ним стояло «Это не потеря данных:
/// записи на месте».
///
/// Переустановка сносит контейнер App Group. У человека без iCloud
/// совет уничтожал ровно то, что обещание над ним называло целым, —
/// и уничтожал у того, кому терять дороже всех.
///
/// > **Заголовок верен в момент чтения и становится ложным от
/// > выполнения совета.** Совет — это действие, и его последствие
/// > опровергает обещание над ним. Текст, прочитанный отдельно,
/// > не врёт ни одним словом.
///
/// ## Почему развилка не та, которую заказывали
///
/// Заказана была развилка «есть рабочий iCloud ИЛИ есть сохранённый
/// архив» против «возвращать неоткуда». Замер показал, что обе её
/// половины на этом экране **не наблюдаемы**:
///
/// ```
/// Persistence.isUsingCloud   ставится true ТОЛЬКО когда контейнер
///                            открылся (Persistence.swift:219)
///                            здесь он не открылся → всегда false
/// cloudState() при false      никогда не вернёт .syncing — только
///                            .noEntitlement · .openFailed · .noAccount
///                            · .restricted · .unavailable
/// факт выгрузки               не записывается нигде: ни UserDefaults,
///                            ни файла-отметки (искал grep по lastExport,
///                            lastBackup, exportedAt → ноль)
/// ```
///
/// То есть спрашивать `cloudState()` здесь бессмысленно: он отвечает
/// про СЕЙЧАС, а вопрос человека — «уезжал ли дневник РАНЬШЕ».
///
/// **Наблюдаемый признак один, и он уже на этом экране** — крошки
/// запуска. `Persistence` пишет в них `хранилище: iCloud` при каждом
/// удачном открытии с зеркалом, `StartupLog` дописывает и держит
/// около десяти запусков. Нашлась строка — прошлый запуск уезжал
/// в облако, и переустановка вернёт дневник оттуда.
///
/// **Асимметрия намеренная: находка значит «да», отсутствие не значит
/// «нет».** У самого журнала записано, почему: до 28.09 два писателя
/// затирали друг другу строки, и «по отсутствию строки в таком журнале
/// вывода сделать нельзя». Плюс двести строк — это около десяти
/// запусков, и старая запись законно уходит за край. Поэтому отсутствие
/// даёт не «iCloud нет», а **«подтвердить не можем»** — и совет
/// в этом случае не предлагается вовсе.
nonisolated enum StorageFailureAdvice {

    /// Есть ли подтверждение, что дневник уезжал в облако.
    enum Возврат: Sendable, Equatable {
        /// Крошки запуска несут удачное открытие с зеркалом iCloud.
        case подтверждён
        /// Подтверждения нет. **Это не «iCloud нет»** — это «мы
        /// не знаем», и разница решает, можно ли советовать снос.
        case неизвестен
    }

    /// Признак, который пишет `Persistence` при удачном открытии
    /// с зеркалом. Строка одна на весь проект и берётся отсюда,
    /// а не повторяется в двух местах: два правила на одну мысль
    /// расходятся на второй правке.
    static let признакОблака = "хранилище: iCloud"

    static func возврат(журналЗапуска: String) -> Возврат {
        журналЗапуска.contains(признакОблака) ? .подтверждён : .неизвестен
    }

    /// Подзаголовок баннера. Под ту же развилку, что и шаги: обещание
    /// «это не потеря данных» держится только там, где есть откуда
    /// вернуть.
    static func подзаголовок(_ возврат: Возврат) -> String {
        switch возврат {
        case .подтверждён:
            String(localized: "Это не потеря данных: записи на месте, но приложение сейчас не может до них добраться.")
        case .неизвестен:
            String(localized: "Записи на месте — на этом телефоне. Приложение сейчас не может до них добраться, и переустановка их удалит.")
        }
    }

    /// Что попробовать. Первые два пункта безопасны в любом случае;
    /// третий появляется ТОЛЬКО когда вернуть есть откуда.
    static func шаги(_ возврат: Возврат) -> [String] {
        var шаги = [
            String(localized: "Закрыть приложение полностью и открыть заново."),
            String(localized: "Проверить, что на устройстве есть свободное место."),
        ]
        if возврат == .подтверждён {
            шаги.append(String(localized: "Если не помогло — переустановить. Дневник вернётся из iCloud: прошлые запуски в него уезжали."))
        }
        return шаги
    }

    /// Предупреждение вместо совета — там, где совет губителен.
    ///
    /// Про выгрузку сказано прямо, что её сейчас нет, и это замер:
    /// `BackupService.archive(context:)` требует `ModelContext`, то есть
    /// ровно то хранилище, которое не открылось. Совет «сперва сохрани
    /// файл» человек выполнить не может, а совет, который нельзя
    /// выполнить, хуже молчания: молчание заставляет спросить, неверный
    /// совет — попробовать и увериться.
    static func предупреждение(_ возврат: Возврат) -> String? {
        switch возврат {
        case .подтверждён:
            nil
        case .неизвестен:
            String(localized: "Не переустанавливай. Приложение не нашло следов того, что дневник уезжал в iCloud, — и выгрузить его сейчас нечем: выгрузка читает то же хранилище, которое не открылось. Напиши в поддержку, строки запуска уже ниже.")
        }
    }
}
