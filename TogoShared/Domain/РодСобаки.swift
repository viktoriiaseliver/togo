import Foundation

/// Форма слова по полу собаки: «съел / съела», «он / она», «его / её».
///
/// Аудит двух экранов 29.10.2026 нашёл мужской род, вписанный в тексты
/// намертво: «Как он просит», «у него в среднем», «его норма», «съел» —
/// у суки Стич это читалось как чужая собака. Общего помощника в проекте
/// не было, и каждый текст выбирал род сам, то есть мужской.
///
/// # Почему две ЦЕЛЫЕ строки, а не подстановка окончания
///
/// Род в русском — не окончание одного слова: «он сам подошёл» и «она
/// сама подошла» меняют три слова, а в украинском и казахском — другое
/// число слов. Поэтому место вызова передаёт две целые фразы, каждую
/// через `String(localized:)`, и каталог переводит их порознь.
///
/// # Пол не указан
///
/// Тогда — `нейтрально`, если место вызова его дало, иначе мужская
/// форма. Мужская — как было до помощника, и это названо, а не спрятано:
/// угадывать пол, которого человек не назвал, приложение не должно,
/// поэтому там, где фразу можно сказать без рода, её стоит передать.
nonisolated enum РодСобаки {
    static func форма(_ пол: DogSex?, он: @autoclosure () -> String, она: @autoclosure () -> String,
                      нейтрально: (() -> String)? = nil) -> String {
        switch пол {
        case .female?: return она()
        case .male?: return он()
        default: return нейтрально?() ?? он()
        }
    }

    @MainActor
    static func форма(_ dog: Dog?, он: @autoclosure () -> String, она: @autoclosure () -> String,
                      нейтрально: (() -> String)? = nil) -> String {
        форма(dog?.sex, он: он(), она: она(), нейтрально: нейтрально)
    }
}
