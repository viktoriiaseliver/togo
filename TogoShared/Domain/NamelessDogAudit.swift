import Foundation
import SwiftData

/// Перепись безымянных записей о собаке. **Ничего не удаляет.**
///
/// **Этот файл начинал день удалятелем, и решение перевернулось
/// к вечеру — Викторией, с доводом.** История здесь не для красоты:
/// без неё следующий сочтёт отсутствие удаления недоделкой.
///
/// Утром знали: у человека восемь безымянных строк (отзыв TestFlight
/// 06.10.2026 по сборке 271), и убрать их он не может — кнопка удаления
/// существовала и была недостижима. Логично было убрать за него.
/// К вечеру стало известно три вещи, и каждая против удаления.
///
/// **1. Пустая запись может быть настоящей собакой на полпути.**
/// Крошки запуска с телефона: девять разных `id` за шесть дней, пять
/// исчезли сами. Вероятный источник — зеркало CloudKit, а оно создаёт
/// запись и заполняет атрибуты не одновременно. У такой записи нет
/// ни клички, ни связей, то есть от фантома она неотличима **ничем**,
/// включая оба прежних условия. Условие «видена пустой дважды» окно
/// сужало и не закрывало: при вставшей синхронизации настоящая собака
/// останется голой и через запуск. Померить это гонкой нечем — нужен
/// телефон с живым iCloud.
///
/// **2. Цена ошибки несимметрична, и «не показывать»
/// самоисправляется.**
///
/// ```
/// удалили лишнее       необратимо, уносит одиннадцать каскадов
/// не показали лишнее   обратимо: появится сама, когда доедет кличка
/// ```
///
/// **3. Удаление решало задачу, которой у человека нет.** Он жаловался
/// на строки на экране и на то, что их нечем убрать, — а не на записи
/// в базе. Скрытие закрывает обе жалобы; дорогу к удалению настоящей
/// собаки завели в тот же день.
///
/// **Что осталось и зачем.** Перепись. Она ничего не стирает, и именно
/// поэтому стала ценнее: по ней мы наконец узнаем, **копятся эти записи
/// или живут по одному дню** — вопрос, который до сегодня был
/// неизмерим.
///
/// # Первый вопрос ОТВЕЧЕН, второе обещание было ЛОЖНЫМ
///
/// Замер 08.10.2026 по журналу и выгрузке с телефона Виктории:
///
/// ```
/// строк переписи        60 · разных id 7
/// seenBefore = 1        45 из 60       → КОПЯТСЯ, не живут по дню
/// собак в выгрузке      16 · без клички 15 · с кличкой одна
/// ```
///
/// А здесь стояло: «если у безымянной записи окажется заполнено хоть
/// что-то, это укажет на семя». **Снято как ложное.** У всех
/// шестидесяти строк заполнено ровно одно поле — `dailyNormGrams`, —
/// и заполнили его не семя, а мы:
/// `FeedingMigration` (`TogoApp.swift:261` на 14.10) шла по ВСЕМ собакам
/// без разбора и писала фантому `setDailyGrams(0)` на каждом запуске.
/// Перепись зовётся на `TogoApp.swift:278` — **семнадцать строк позже**.
/// Числа уехали за неделю на сорок две строки; устойчив здесь только
/// разрыв в семнадцать, и проверяется он
/// `grep -n "FeedingMigration.run\|NamelessDogAudit.перепись" Togo/App/TogoApp.swift`.
///
/// > **Сборщик улики читает состояние, которое запуск уже изменил.**
/// > Поле выглядит данными человека и является нашим следом, а строка
/// > «fields [dailyNormGrams]» читается как указание на семя именно
/// > потому, что перепись не знает, кто писал.
///
/// Миграция теперь безымянных пропускает (`FeedingMigration`,
/// `guard dog.canBeShown`), то есть с этого коммита заполненное поле
/// снова что-то значит. **Но обещание сюда не возвращается:** если
/// в следующей выгрузке поле окажется заполненным, первым делом
/// спрашивать, не писал ли его кто-то из нас между сносом базы
/// и переписью, — и только потом считать следом.
///
/// # Происхождение: девять случаев вместо одного (замер 30.10.2026)
///
/// Прежде здесь стояло одно совпадение — девять записей в одну секунду
/// 07.10 и онбординг в ту же секунду, — и оно справедливо не читалось
/// как связь. Теперь случаев **девять, в разные дни и разные сессии**,
/// по журналу телефона Виктории за 27–29.10:
///
/// ```
/// AB8E96E0  created 10-27 19:18:30   секунда ОТКРЫТИЯ ОНБОРДИНГА
/// 4E4BA9D3  created 10-27 20:00:48   секунда переписи сессии 616d4c
/// 6AD792FE  created 10-27 20:57:46   секунда переписи сессии b6b67a
/// 00368F5B  created 10-27 21:47:53   сессия e46abb (перепись 21:47:54)
/// 51B8513D  created 10-28 08:32:10   сессия 13f83f
/// C817066B  created 10-28 17:09:17   сессия 840053 (перепись 17:09:18)
/// 4DA141F2  created 10-29 10:10:59   сессия a94b3f
/// 104DE90E  created 10-29 14:51:10   сессия 77d1ed (перепись 14:51:11)
/// 5C577820  created 10-29 17:54:59   сессия a90b6c
/// ```
///
/// Каждая **впервые показывается переписью СЛЕДУЮЩЕГО запуска** —
/// то есть рождается после того, как перепись собрала список.
/// Онбординг был только у первой; остальные восемь — обычный запуск.
///
/// **Правдоподобный механизм, и он НЕ ДОКАЗАН.** `createdAt` объявлен
/// `= Date()` (`Dog.swift:166`), то есть дефолт вычисляется в момент,
/// когда объект материализуется. Если зеркало заводит локальный объект
/// и доливает атрибуты позже, `created` печатает **момент
/// материализации, а не рождения записи** — и тогда «фантом»
/// и «приехавшая запись без атрибутов» одно и то же явление.
///
/// Прямое подтверждение тому, что дефолты и правда срабатывают
/// на приехавших записях, нашлось в тот же день: у одной и той же
/// `C1469CE8` на двух телефонах `createdAt` — `2023-03-19T12:00:00Z`
/// у владельца и `2026-10-28T13:48:37Z` у гостя. Второе значение —
/// не данные.
///
/// > **Девять совпадений подряд — уже не совпадение, но ещё
/// > не механизм.** Доказать можно одним замером: счёт `Dog`
/// > до и после работы зеркала на телефоне с живым iCloud. У нас
/// > такого телефона нет — приватная база неизмерима (`CLAUDE.md`).
///
/// Прежняя запись о решающем замере оставлена ниже: она про онбординг,
/// и после этих девяти случаев её вес меньше, чем казался.
/// Решающий замер — проход онбординга на стёртом симуляторе со счётом
/// `Dog` после — **назначен** `togo-review-frames-sync`: он нашёл, что
/// под `-UITesting` онбординг не запускается, и пишет первый за всё
/// время прогон онбординга без этого флага.
///
/// Проверить за минуту (адрес нарочно не номером строки — за 14.10
/// он уехал трижды, 219 → 243 → 312, и каждая запись успевала стать
/// преданием):
///
/// ```
/// grep -n "isUITesting || settings.onboardingCompleted" Togo/App/TogoApp.swift
/// ```
///
/// Там же читать **первое** звено условия: к 14.10 перед ним встало
/// `!appState.просмотрОнбординга`, то есть «никогда» перестало быть
/// точным — появился путь показать онбординг и под стендом.
///
/// > **Непроверяемая поверхность накопила дефект потому, что была
/// > непроверяемой.** Онбординг — единственный путь, который тесты
/// > не проходят, и он в центре обеих версий о происхождении.
///
/// Скрытие живёт не здесь, а у правила показа: `Dog.canBeShown`
/// и `[Dog].shownToPerson`.
nonisolated enum NamelessDogAudit {

    /// Кого видели безымянным на прошлых запусках.
    private static let ключВиденыПустыми = "dogs.seenNameless"


    // MARK: Перепись

    /// Пересчитать безымянные записи и записать, что в них лежит.
    ///
    /// Зовётся при запуске **после** `DogOrigin.проверить`: перепись
    /// источников должна попасть в крошки первой.
    ///
    /// Возвращает, сколько безымянных записей найдено.
    @MainActor
    @discardableResult
    static func перепись(in context: ModelContext) -> Int {
        let собаки = (try? context.fetch(FetchDescriptor<Dog>())) ?? []
        let безымянные = собаки.filter { !$0.canBeShown }
        let былиПустыми = прочитать(ключВиденыПустыми)
        записать(Set(безымянные.map(\.id)), в: ключВиденыПустыми)

        for собака in безымянные {
            улика(собака, повторная: былиПустыми.contains(собака.id))
        }
        return безымянные.count
    }

    /// Что лежит в безымянной записи — в журнал действий и в крошки.
    ///
    /// **`повторная` и есть ответ на вопрос, который был неизмерим:**
    /// копятся эти записи или живут по одному дню. Удалятель этого
    /// не узнал бы никогда — он стирал бы улику раньше, чем она
    /// успевала накопиться.
    ///
    /// **Клички здесь нет и не будет**, в том числе у непустых полей:
    /// печатаются только ИМЕНА полей. Та же красная линия, что у крошек
    /// запуска и у `DogOrigin` — диагностический файл не становится
    /// личными данными.
    ///
    /// Зачем это вообще: восемь записей у человека — **единственные
    /// экземпляры дефекта**, семя которого мы не нашли. Если
    /// у безымянной записи окажется заполнено хоть что-то, это
    /// и будет указание на семя. Счёт по связям — нулями, чтобы
    /// «ничего не тянет» был видимым фактом, а не нашим словом.
    @MainActor
    private static func улика(_ dog: Dog, повторная: Bool) {
        let filled = непустыеПоля(dog)
        // Счёт по `*Storage`, а не по обёрткам: с 26.10.2026 восемь
        // обёрток отсеивают надгробия, а **перепись, не видящая
        // удалённого, — не перепись**. Здесь ищут семя дефекта, и ноль
        // по связям обязан значить «связей нет», а не «связи есть,
        // но скрыты». Тот же приём уже стоял в `CloudKitSchemaWarmup`.
        //
        // Массивом, а не цепочкой `+`: на шести слагаемых типизатор
        // уже отвечал «unable to type-check this expression in
        // reasonable time». Разбор — у сборки `line` ниже.
        let rel = [
            "ev \((dog.eventsStorage ?? []).count)",
            "w \((dog.weightsStorage ?? []).count)",
            "care \((dog.careTasksStorage ?? []).count)",
            "med \((dog.medicationsStorage ?? []).count)",
            "step \(dog.trainingSteps.count)",
            "ses \(dog.trainingSessions.count)",
            "trip \(dog.trips.count)",
            "doc \((dog.documentsStorage ?? []).count)",
            "out \(dog.daysOut.count)",
            "heat \(dog.heats.count)",
            "stock \(dog.stocks.count)",
        ].joined(separator: " ")
        let iso = ISO8601DateFormatter()
        // ПОЧЕМУ запись не показывается — словом, а не догадкой
        // читателя. `canBeShown` ложен по двум разным причинам, и до
        // 30.10.2026 строка не называла ни одной.
        //
        // Цена измерена в тот же день: у гостя нашлась безымянная
        // запись с 268 связями (214 событий, 25 весов, 19 уходов,
        // 10 лекарств), и по строке нельзя было сказать, её это живой
        // дневник без клички или надгробие с каскадом. **Решения
        // по этим случаям противоположные**, а улика их не различала.
        //
        // > **Улика, не называющая, какое из двух условий ложно,
        // > отвечает на вопрос «почему» молчанием** — и читатель
        // > подставляет то, что ждёт увидеть.
        //
        // Кличка по-прежнему НЕ печатается: пишется факт пустоты,
        // а не значение. Та же красная линия, что у всего файла.
        var части: [String] = []
        if dog.nameIfAny == nil { части.append("безКлички") }
        if dog.deletedAt != nil { части.append("удалена") }
        // Пустая причина здесь невозможна: в перепись попадают только
        // `!canBeShown`. Если она всё-таки напечаталась — это находка,
        // и слово должно быть такое, чтобы её нельзя было прочитать
        // как прочерк «нечего сказать».
        let причина = части.isEmpty ? "ПРОТИВОРЕЧИЕ" : части.joined(separator: "+")
        let поля = filled.isEmpty ? "—" : filled.joined(separator: " ")

        // **Цепочка собирается массивом, а не длинным `+`.** Добавление
        // одного слагаемого к прежней цепочке из пяти уже дало
        // «compiler is unable to type-check this expression in
        // reasonable time». У проекта это не теория: 07.10.2026 срыв
        // типизатора в длинной цепочке стоил шести красных прогонов
        // подряд, и он бывает в коде, не будучи в сборке.
        let line = [
            String(dog.id.uuidString.prefix(8)),
            "почему [\(причина)]",
            "created \(iso.string(from: dog.createdAt))",
            "changed \(iso.string(from: dog.changedAt))",
            "fields [\(поля)]",
            "rel [\(rel)]",
        ].joined(separator: " ")

        UsageLog.note(.open, "namelessDog: \(line) seenBefore \(повторная ? 1 : 0)",
                      on: .settings)

        // **И в крошки запуска — потому что их нельзя выключить.**
        // `UsageLog.isOn` человек гасит в настройках приватности,
        // и это его право. Но удаление необратимо, а улика, которую
        // можно выключить тумблером, уликой не является: мы бы
        // удалили единственные экземпляры дефекта и не узнали даже,
        // что они были.
        //
        // Личного здесь нет ни в одном из двух файлов: ни клички,
        // ни заметок, ни граммов — восемь знаков идентификатора,
        // две даты, ИМЕНА заполненных полей и нули по связям.
        StartupLog.note("безымянная собака — \(line) видена раньше: \(повторная ? "да" : "нет")")
    }

    /// Имена заполненных полей. Значений нет ни у одного.
    ///
    /// Список руками, и это его слабое место: поле, добавленное
    /// в `Dog` завтра, здесь не появится, и улика промолчит о нём.
    /// Вывести из исходника, как это делает `DeviceLocalFieldTests`,
    /// отсюда нельзя — рефлексии по хранимым свойствам `@Model`
    /// у нас нет. Названо, а не спрятано.
    @MainActor
    private static func непустыеПоля(_ dog: Dog) -> [String] {
        var имена: [String] = []
        if dog.снимок != nil { имена.append("photo") }
        if dog.breed?.isEmpty == false { имена.append("breed") }
        if dog.birthDate != nil { имена.append("birthDate") }
        if dog.weightKg != 0 { имена.append("weightKg") }
        if dog.targetWeightLow != nil { имена.append("targetWeightLow") }
        if dog.targetWeightHigh != nil { имена.append("targetWeightHigh") }
        if !dog.foodBrand.isEmpty { имена.append("foodBrand") }
        if dog.dailyNormGrams != nil { имена.append("dailyNormGrams") }
        if !dog.forbiddenFoods.isEmpty { имена.append("forbiddenFoods") }
        if !dog.rewards.isEmpty { имена.append("rewards") }
        if dog.isOnTreatment { имена.append("isOnTreatment") }
        if dog.chipNumber?.isEmpty == false { имена.append("chipNumber") }
        if dog.passportNumber?.isEmpty == false { имена.append("passportNumber") }
        if dog.insuranceNumber?.isEmpty == false { имена.append("insuranceNumber") }
        if dog.vetName?.isEmpty == false { имена.append("vetName") }
        if dog.vetPhone?.isEmpty == false { имена.append("vetPhone") }
        if dog.clinicName?.isEmpty == false { имена.append("clinicName") }
        if dog.clinicPhone?.isEmpty == false { имена.append("clinicPhone") }
        if dog.distinctiveMarks?.isEmpty == false { имена.append("distinctiveMarks") }
        if !dog.sitterFood.isEmpty { имена.append("sitterFood") }
        if !dog.sitterDose.isEmpty { имена.append("sitterDose") }
        if !dog.sitterWalks.isEmpty { имена.append("sitterWalks") }
        if !dog.sitterForbidden.isEmpty { имена.append("sitterForbidden") }
        if !dog.sitterEscalation.isEmpty { имена.append("sitterEscalation") }
        return имена
    }

    // MARK: Память

    private static func прочитать(_ ключ: String) -> Set<UUID> {
        Set((UserDefaults.standard.stringArray(forKey: ключ) ?? [])
            .compactMap(UUID.init(uuidString:)))
    }

    private static func записать(_ значение: Set<UUID>, в ключ: String) {
        UserDefaults.standard.set(значение.map(\.uuidString), forKey: ключ)
    }
}
