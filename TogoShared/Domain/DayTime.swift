import Foundation

/// Время суток из минуты от полуночи.
///
/// Расписания в приложении хранятся минутами: доза в 480 — это 08:00.
/// Превращать их в дату сложением «начало дня плюс столько-то секунд»
/// нельзя: в сутках перевода часов не 24 часа, а 23 или 25, и восьмичасовая
/// доза в такой день оказывается в 07:00 или в 09:00. Календарь знает
/// про перевод, арифметика секунд — нет.
///
/// Собрано в одном месте, потому что сложение было скопировано в семь
/// файлов: план дня, расписание кормлений, окно дозы, разбор пропуска,
/// правка схемы, демо-данные. Раз в полгода они разъезжались все сразу.
extension Calendar {
    /// Момент дня, соответствующий минуте от полуночи.
    ///
    /// - Parameters:
    ///   - minute: минут от полуночи. 0…1439; большее просто уедет вперёд.
    ///   - day: любой момент нужного дня.
    nonisolated func date(minuteOfDay minute: Int, on day: Date) -> Date {
        let hour = minute / 60
        let rest = minute % 60
        // Часа может не существовать вовсе — 02:30 в ночь перевода вперёд.
        // Тогда календарь отдаёт ближайшее следующее реальное время,
        // и это ровно то поведение, которого ждёт человек.
        if hour < 24,
           let exact = date(bySettingHour: hour, minute: rest, second: 0, of: day) {
            return exact
        }
        return startOfDay(for: day).addingTimeInterval(Double(minute) * 60)
    }
}
