import Foundation

/// Когда «сколько не писал» перестаёт быть ответом на вопрос.
///
/// **Третий случай одной формы, и первые два уже стоят в `OutingSilence`.**
/// 21.09 главный экран сказал «434 ч назад · на улице были» — приложение
/// сказало о собаке то, чего не знало. 24.09 то же число тем же способом
/// сказала Siri. В обоих случаях чинили величину «давно ли гуляли».
///
/// Величина «давно ли писал» жила мимо этого правила до 28.09 и
/// выговаривала худшее из трёх: «Не писал 434 ч. Это дольше, чем он
/// когда-либо терпел» — с вердиктом «срочно». Отсутствие записи показано
/// не просто как отсутствие события, а как **медицинское утверждение**
/// о собаке, которого приложение сделать не может: знает он только то,
/// что никто ничего не отмечал восемнадцать дней.
///
/// **Почему у мочи своё правило, а не потолок `OutingSilence`.**
/// Молчание дневника и задержка мочи различимы, и различие стоит денег
/// в обе стороны. Если выходы отмечали, а мочи в них нет — это
/// настоящий сигнал, и гасить его нельзя: ради него к врачу и идут.
/// Если не отмечали и выходов — говорить нечего, и мы говорим именно это.
/// Решение Виктории 28.09: разделять по дневнику, а не глушить всё
/// за потолком.
///
/// Потолок поэтому **не** ссылается на `OutingSilence.ceiling`: числа
/// сейчас совпадают, а вопросы разные, и съехать они должны порознь.
nonisolated enum UrineSilence {

    /// Дольше этого «не писал» отвечает уже не на тот вопрос.
    ///
    /// Сутки не из головы: обычный интервал у собаки — часы, и своё
    /// «дольше, чем когда-либо терпел» приложение считает по записанной
    /// истории. За сутками без единой отметки вероятнее не задержка,
    /// а то, что дневник забросили.
    static let ceiling: TimeInterval = 24 * 3600

    /// Дата последней отметки мочи, если про мочу молчат дольше потолка
    /// **и дневник о выходах молчит тоже**. Пусто во всех остальных
    /// случаях — включая тот, ради которого правило и разделено:
    /// выход отмечен недавно, мочи в нём нет.
    ///
    /// Свежесть выхода мерится тем же потолком нарочно: выход,
    /// отмеченный восемнадцать дней назад, — это часть той же тишины,
    /// а не свидетельство, что дневник ведут. Первая редакция сравнивала
    /// выход с мочой по порядку (`выход позже мочи`) и на паре
    /// «моча 3 сент. 10:00, выход 3 сент. 18:00» оставляла ровно ту
    /// неправду, от которой правило заведено.
    static func start(now: Date, lastUrineAt: Date?, lastOutingAt: Date?) -> Date? {
        guard let lastUrineAt, now.timeIntervalSince(lastUrineAt) >= ceiling else { return nil }
        if let lastOutingAt, now.timeIntervalSince(lastOutingAt) < ceiling { return nil }
        return lastUrineAt
    }
}
