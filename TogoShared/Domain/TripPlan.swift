import Foundation

/// Что поездка обещает посчитать — и до 29.10.2026 не считала.
///
/// Аудит поездки по просьбе Виктории («проверь логику поездки: что можно
/// отмечать, как меняет режим»). Два обещания стояли текстом на экране
/// без единой строки кода под ними:
///
/// ```
/// «Остановки каждые 2 часа… Приложение напомнит    напоминаний не ставил
///  и запишет остановку одним тапом»                 никто; LogKind.travelStop
///                                                   не создавался нигде
/// «Если собака на терапии, приложение сведёт их     сведения не было:
///  с приёмами и покажет, где конфликт»              окна и дозы не встречались
/// ```
///
/// Правила здесь, а не во вью: их читают экран поездки, «Сегодня»
/// и постановщик уведомлений, и три копии одного шага разошлись бы.
nonisolated enum TripPlan {

    /// Шаг остановок на машине — тот, что обещан в `windowsExplainer`.
    static let шагОстановки: TimeInterval = 2 * 3600

    /// Моменты остановок: каждые два часа после выезда, пока едем.
    ///
    /// Остановки в момент приезда нет: приехали — это уже не остановка.
    /// Ровно на границе (4 ч пути, шаг 2 ч) — одна, на втором часу.
    static func остановки(выезд: Date, вДороге часы: Double) -> [Date] {
        let приезд = выезд.addingTimeInterval(max(0, часы) * 3600)
        var итог: [Date] = []
        var момент = выезд.addingTimeInterval(шагОстановки)
        while момент < приезд, итог.count < 12 {
            итог.append(момент)
            момент = момент.addingTimeInterval(шагОстановки)
        }
        return итог
    }

    /// Доза, попавшая в окна дороги.
    struct ДозаВДороге: Equatable, Sendable {
        let препарат: String
        let когда: Date
        /// До выезда, в окне «последней еды», — или уже в пути.
        let вПути: Bool
    }

    /// Дозы дня выезда от начала окон до приезда.
    ///
    /// Окна начинаются с самого раннего из `TransportKind.windows`
    /// (у самолёта −4 ч, у машины и поезда −2 ч). Схема на паузе
    /// не считается — как в `DoseScheduler.ensureDoses`.
    static func дозыВДороге(_ лекарства: [(название: String, минуты: [Int], пауза: Bool)],
                            выезд: Date, вДороге часы: Double, началоОкон: Date,
                            calendar: Calendar = .current) -> [ДозаВДороге] {
        let приезд = выезд.addingTimeInterval(max(0, часы) * 3600)
        let день = calendar.startOfDay(for: выезд)
        // Дорога может перевалить за полночь — смотрим и следующие сутки.
        let дни = [день, calendar.date(byAdding: .day, value: 1, to: день)].compactMap { $0 }
        var итог: [ДозаВДороге] = []
        for лекарство in лекарства where !лекарство.пауза {
            for d in дни {
                for минута in лекарство.минуты {
                    let когда = calendar.date(minuteOfDay: минута, on: d)
                    guard когда >= началоОкон, когда <= приезд else { continue }
                    итог.append(.init(препарат: лекарство.название, когда: когда, вПути: когда >= выезд))
                }
            }
        }
        return итог.sorted { $0.когда < $1.когда }
    }
}
