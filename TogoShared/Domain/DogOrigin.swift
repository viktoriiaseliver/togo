import Foundation
import SwiftData

/// Откуда взялась собака: завели здесь или приехала обменом.
///
/// Зачем. 23.09.2026 у человека в дневнике оказались две собаки с одной
/// кличкой, записи разошлись пополам — 56 и 45. Причину назвать не вышло:
/// вторая карточка появилась накануне, а крошки запуска за тот час уже
/// затёрлись. То есть дело было не в том, что мы не нашли причину,
/// а в том, что **найти её было нечем**.
///
/// Здесь чинится именно это. Гейт не «нашли причину», а «сможем найти
/// в следующий раз»: первое может не наступить никогда.
///
/// **Ничего о собаке не пишем.** В крошки идут только первые восемь
/// знаков идентификатора и источник — та же красная линия, что у журнала
/// действий: диагностический файл не должен становиться личными данными.
/// Кличка, вес, порода сюда не попадают ни при каких условиях.
nonisolated enum DogOrigin {

    private static let ключЗнакомых = "dogs.known"
    private static let ключСвоих = "dogs.createdHere"
    /// О каких пропажах уже сказали. Без этого «исчезла» печаталась бы
    /// на каждом запуске до конца времён.
    private static let ключСообщённых = "dogs.reportedGone"

    /// Отметить, что собаку завели на этом устройстве.
    ///
    /// Вызывается там, где человек нажал «Добавить собаку», а не там,
    /// где объект появился: появиться он может и сам, из обмена.
    static func заведенаЗдесь(_ id: UUID) {
        var свои = Set(UserDefaults.standard.stringArray(forKey: ключСвоих) ?? [])
        свои.insert(id.uuidString)
        UserDefaults.standard.set(Array(свои), forKey: ключСвоих)
    }

    /// Сверить состав собак с прошлым запуском и записать разницу.
    ///
    /// Приехавшую собаку никакой код приложения не создаёт — её кладёт
    /// зеркало CloudKit мимо нас. Поймать её можно только так: помнить
    /// состав и замечать прибавление.
    @MainActor
    static func проверить(in context: ModelContext) {
        let собаки = (try? context.fetch(FetchDescriptor<Dog>())) ?? []
        let сейчас = Set(собаки.map(\.id.uuidString))
        let знакомые = Set(UserDefaults.standard.stringArray(forKey: ключЗнакомых) ?? [])
        let свои = Set(UserDefaults.standard.stringArray(forKey: ключСвоих) ?? [])

        let новые = сейчас.subtracting(знакомые)
        for id in новые.sorted() {
            let источник = свои.contains(id) ? "заведена здесь" : "приехала обменом"
            StartupLog.note("собака \(id.prefix(8)) — \(источник)")
        }

        // О каждой пропаже говорим ОДИН раз.
        var сообщённые = Set(UserDefaults.standard.stringArray(forKey: ключСообщённых) ?? [])
        let пропавшие = знакомые.subtracting(сейчас).subtracting(сообщённые)
        for id in пропавшие.sorted() {
            StartupLog.note("собака \(id.prefix(8)) — исчезла")
            сообщённые.insert(id)
        }
        // Вернулась — забываем, что о ней говорили: следующая пропажа
        // должна быть слышна.
        сообщённые.subtract(сейчас)
        UserDefaults.standard.set(Array(сообщённые), forKey: ключСообщённых)

        if собаки.count > 1 {
            // Само по себе не дефект: вторая собака бывает настоящей.
            // Но если дубликат появится снова, в крошках будет и час,
            // и источник, и сколько их стало.
            StartupLog.note("собак в дневнике: \(собаки.count)")

            // И перепись поимённо — по одной строке на собаку.
            //
            // **Заведено 28.09, потому что счётчика оказалось мало.**
            // В журнале с телефона Виктории он показал ШЕСТЬ собак
            // на одну живую, и число росло по дням: 2, 3, 4, 5, 5, 6.
            // Назвать причину было нечем: счётчик говорит «сколько»,
            // и молчит про «какие».
            //
            // Три кандидата различаются ровно этими полями:
            //   · остаток отладочного прогрева — ноль записей, час
            //     создания кучный с другими такими же;
            //   · дубликат зеркала CloudKit — записи есть, час создания
            //     совпадает с настоящей собакой;
            //   · настоящая вторая собака — записи есть, час свой,
            //     и она «заведена здесь».
            //
            // **Клички здесь нет и не будет.** Та же красная линия, что
            // у журнала действий: диагностический файл не становится
            // личными данными. Различать хватает и без неё.
            let формат = ISO8601DateFormatter()
            for собака in собаки.sorted(by: { $0.createdAt < $1.createdAt }) {
                let id = собака.id.uuidString.prefix(8)
                let источник = свои.contains(собака.id.uuidString) ? "здесь" : "обменом"
                let записей = собака.eventsStorage?.count ?? 0
                StartupLog.note("  \(id) · \(источник) · \(формат.string(from: собака.createdAt))"
                                + " · записей \(записей)")
            }
        }

        // **Память только растёт, и это починка 28.09.**
        //
        // Раньше здесь стояло `set(сейчас)` — снимок затирал знание.
        // Зеркало CloudKit доносит записи не разом: выборка на запуске
        // бывает неполной, и собака, которой в ней не оказалось,
        // ВЫПАДАЛА из памяти. На следующем запуске она приезжала
        // «обменом» заново — в журнале с телефона одна и та же собака
        // объявлена приехавшей дважды за одну сессию.
        //
        // «Знакомая» значит «видели хотя бы раз», а не «была в прошлой
        // выборке». Такое знание терять нельзя: именно на нём стоит
        // весь смысл слова «исчезла».
        UserDefaults.standard.set(Array(знакомые.union(сейчас)), forKey: ключЗнакомых)
    }
}
