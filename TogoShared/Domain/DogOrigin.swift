import Foundation
import SwiftData

/// Откуда взялась собака: завели здесь или приехала обменом.
///
/// Зачем. 23.09.2026 у человека в дневнике оказались две собаки с одной
/// кличкой, записи разошлись пополам — 56 и 45. Причину назвать не вышло:
/// вторая карточка появилась накануне, а крошки запуска за тот час уже
/// затёрлись. То есть дело было не в том, что мы не нашли причину,
/// а в том, что **найти её было нечем**.
///
/// Здесь чинится именно это. Гейт не «нашли причину», а «сможем найти
/// в следующий раз»: первое может не наступить никогда.
///
/// **Ничего о собаке не пишем.** В крошки идут только первые восемь
/// знаков идентификатора и источник — та же красная линия, что у журнала
/// действий: диагностический файл не должен становиться личными данными.
/// Кличка, вес, порода сюда не попадают ни при каких условиях.
nonisolated enum DogOrigin {

    private static let ключЗнакомых = "dogs.known"
    private static let ключСвоих = "dogs.createdHere"

    /// Отметить, что собаку завели на этом устройстве.
    ///
    /// Вызывается там, где человек нажал «Добавить собаку», а не там,
    /// где объект появился: появиться он может и сам, из обмена.
    static func заведенаЗдесь(_ id: UUID) {
        var свои = Set(UserDefaults.standard.stringArray(forKey: ключСвоих) ?? [])
        свои.insert(id.uuidString)
        UserDefaults.standard.set(Array(свои), forKey: ключСвоих)
    }

    /// Сверить состав собак с прошлым запуском и записать разницу.
    ///
    /// Приехавшую собаку никакой код приложения не создаёт — её кладёт
    /// зеркало CloudKit мимо нас. Поймать её можно только так: помнить
    /// состав и замечать прибавление.
    @MainActor
    static func проверить(in context: ModelContext) {
        let собаки = (try? context.fetch(FetchDescriptor<Dog>())) ?? []
        let сейчас = Set(собаки.map(\.id.uuidString))
        let знакомые = Set(UserDefaults.standard.stringArray(forKey: ключЗнакомых) ?? [])
        let свои = Set(UserDefaults.standard.stringArray(forKey: ключСвоих) ?? [])

        let новые = сейчас.subtracting(знакомые)
        for id in новые.sorted() {
            let источник = свои.contains(id) ? "заведена здесь" : "приехала обменом"
            StartupLog.note("собака \(id.prefix(8)) — \(источник)")
        }

        let пропавшие = знакомые.subtracting(сейчас)
        for id in пропавшие.sorted() {
            StartupLog.note("собака \(id.prefix(8)) — исчезла")
        }

        if собаки.count > 1 {
            // Само по себе не дефект: вторая собака бывает настоящей.
            // Но если дубликат появится снова, в крошках будет и час,
            // и источник, и сколько их стало.
            StartupLog.note("собак в дневнике: \(собаки.count)")
        }

        UserDefaults.standard.set(Array(сейчас), forKey: ключЗнакомых)
    }
}
