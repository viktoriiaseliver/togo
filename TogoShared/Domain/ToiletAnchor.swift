import Foundation

/// От чего считается главное показание: последний туалет, а без него —
/// конец выхода.
///
/// **Вынесено 29.10.2026 ради виджета, и это вторая поверхность одного
/// правила, а не второе правило.** Решение Виктории того же дня — «считали
/// время не тогда, когда собака гуляла, а тогда, когда писяла-какала» —
/// легло в героя «Сегодня» приватным свойством `якорьСчёта`. Виджет
/// при этом считал «С прогулки» от НАЧАЛА последней прогулки
/// (`signals.lastWalk` — это `.walk`, а не выход и не туалет), то есть
/// на одном телефоне стояли два разных числа под одним вопросом.
///
/// Тело здесь — дословно то, что в `TodayScreen.якорьСчёта`. Экран
/// на эту функцию ещё не переведён: файл «Сегодня» в этот день правят
/// другие руки, и трогать его мимо них нельзя. **Пока экран не зовёт
/// сюда, копий две**, и расходиться им есть где — названо, а не спрятано.
///
/// Чистая функция нарочно: виджет живёт в другом процессе и считает
/// показание сам на каждой записи ленты (`TodayWidget.getTimeline`),
/// потому что снимок пересобирается редко, а число должно идти.
/// Решает он при этом не своей арифметикой, а этой же функцией —
/// ровно та граница, на которой Togo однажды обжёгся с окном
/// «не кормить».
nonisolated enum ToiletAnchor {

    /// Откуда идёт счёт — это подпись над числом.
    enum Откуда: Sendable, Equatable {
        /// Туалет на улице: выход с результатом, отметка на прогулке,
        /// запись стула, прогулка кобеля.
        case улица
        /// Лужа или кучка дома — инцидент.
        case дом
        /// Туалета нет или он устарел — считаем от конца выхода.
        case выход
    }

    struct Якорь: Sendable, Equatable {
        let когда: Date
        let откуда: Откуда
    }

    /// Якорь счёта на момент `now`.
    ///
    /// - `туалет` — `ToiletClock.last(…)?.когда`, `дома` — его `где == .дом`;
    /// - `выход` — конец последнего выхода (`TimelineBlock.endedAt`).
    ///
    /// Туалет старше потолка тишины при более свежем выходе — это не
    /// «терпит трое суток», а «перестали отвечать», и тогда считаем
    /// от выхода. Разбор — у `TodayScreen.якорьСчёта`.
    static func якорь(туалет: Date?, дома: Bool, выход: Date?, now: Date) -> Якорь? {
        guard let туалет else { return выход.map { Якорь(когда: $0, откуда: .выход) } }
        let отТуалета = Якорь(когда: туалет, откуда: дома ? .дом : .улица)
        guard let выход, выход > туалет else { return отТуалета }
        return now.timeIntervalSince(туалет) < OutingSilence.ceiling
            ? отТуалета
            : Якорь(когда: выход, откуда: .выход)
    }

    /// Дата, которую надо назвать вместо числа, — или пусто, пока число
    /// отвечает на вопрос. Тем же правилом, что герой: `OutingSilence`.
    static func тишина(_ якорь: Якорь, now: Date) -> Date? {
        OutingSilence.start(indoors: max(0, now.timeIntervalSince(якорь.когда)),
                            lastOutingEndedAt: якорь.когда)
    }
}
