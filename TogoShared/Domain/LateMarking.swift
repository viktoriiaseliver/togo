import Foundation

/// Отметили не тогда, когда дали.
///
/// Еду и дозу часто отмечают позже: покормила в семь, руки дошли в девять.
/// До 28.09 приложение записывало такую отметку моментом **нажатия**,
/// и это не мелочь: от времени дозы считается окно натощак и защита
/// от двойной дозы, от времени еды — «пора ли кормить». Сдвиг на два
/// часа уезжал в обе стороны молча.
///
/// Решение Виктории 28.09: **спрашивать только когда опоздали.** Отметка
/// вовремя остаётся в один тап. Еда — самое частое действие в журнале
/// (пять сессий из четырнадцати начинаются с неё), и лишний шаг на каждой
/// записи стоил бы больше, чем чинит.
nonisolated enum LateMarking {

    /// Насколько можно опоздать, чтобы разницу считать несущественной.
    ///
    /// Четверть часа не из головы: окно натощак и напоминания о дозе
    /// считаются получасовыми шагами (`t+30`, `t+60`), и сдвиг меньше
    /// пятнадцати минут ни одного из них не меняет. Спрашивать там, где
    /// ответ ни на что не влияет, — это шаг, который научат пролистывать,
    /// а потом пролистают и нужный.
    static let grace: TimeInterval = 15 * 60

    /// Спросить ли, когда на самом деле дали.
    ///
    /// Только для того, у чего есть назначенный час: у дела ухода его нет
    /// вовсе — зубы чистят «сегодня», а не в 19:40, и спрашивать там нечего.
    static func asksWhenGiven(scheduled: Date, now: Date, hasTime: Bool) -> Bool {
        guard hasTime else { return false }
        return now.timeIntervalSince(scheduled) > grace
    }
}
