import Foundation

/// Нет стула третий день — проблема или не отметили?
///
/// **Вопрос Виктории 29.10.2026, дословно: «если собака не какает третий
/// день — это проблема или не отметили? нужно продумать логику, если
/// это проблема».**
///
/// Отсутствие записи — не отсутствие события; на этом проект обжигался
/// трижды («434 ч назад», `OutingSilence`, `UrineSilence`). Здесь та же
/// развилка, и решается она тем же способом: **смотрим, ведут ли
/// дневник**, а не только на сам стул.
///
/// ```
/// стула нет меньше порога вопроса          молчим
/// больше порога вопроса, дневник тихий    «не отмечали — был?»
/// больше порога тревоги, а выходы         «стула нет с …» — повод
///   С ОТВЕТОМ отмечаются хотя бы два дня     звонить врачу
/// ```
///
/// «С ответом» — это выход, где человек сказал «пописал» / «не сходил» /
/// «стул», или прогулка с отметками: значит, туалет отмечают, и стул
/// просто не случился. Выход без ответа о стуле не говорит ничего.
///
/// # Пороги
///
/// Двое суток — вопрос, трое — тревога: ветеринарная граница «запора»
/// у собаки — 48–72 ч без стула, и звонить советуют на третьи сутки,
/// раньше — если не ест, рвёт или тужится. У собаки, которая и так
/// ходит раз в два дня, пороги растягиваются по её же медиане:
/// ×1,5 и ×2 от обычного промежутка — чужая норма не должна будить её
/// хозяина тревогой.
nonisolated enum StoolSilence {

    enum Оценка: Equatable, Sendable {
        case норма
        /// Стула давно нет, а дневник об этом молчит — спросить.
        case неОтмечали(с: Date)
        /// Туалет отмечают, а стула нет — это сигнал.
        case тревога(с: Date)
    }

    static let порогВопроса: TimeInterval = 48 * 3600
    static let порогТревоги: TimeInterval = 72 * 3600

    /// Сколько разных дней с ответом нужно, чтобы считать, что дневник ведут.
    static let днейСОтветом = 2

    static func assess(_ events: [LogEvent], now: Date = Date(),
                       calendar: Calendar = .current) -> Оценка {
        let живые = Diary.active(events).filter { $0.date <= now }
        let стулья = живые.filter(Self.этоСтул).map(\.date).sorted()
        // Стула не отмечали никогда — значит, его здесь не ведут вовсе,
        // и будить человека вопросом про то, чего он не отмечает, незачем.
        guard let последний = стулья.last else { return .норма }

        let прошло = now.timeIntervalSince(последний)
        let (вопрос, тревога) = пороги(стулья)
        guard прошло >= вопрос else { return .норма }

        let сОтметками = Set(живые.compactMap(\.walkEventID))
        let дниСОтветом = Set(
            живые
                .filter { $0.date > последний && Self.ответОТуалете($0, прогулкиСОтметками: сОтметками) }
                .map { calendar.startOfDay(for: $0.date) }
        )
        if прошло >= тревога, дниСОтветом.count >= днейСОтветом {
            return .тревога(с: последний)
        }
        return .неОтмечали(с: последний)
    }

    /// Пороги по медиане этой собаки — не ниже общих.
    static func пороги(_ стулья: [Date]) -> (вопрос: TimeInterval, тревога: TimeInterval) {
        let промежутки = zip(стулья, стулья.dropFirst())
            .map { $1.timeIntervalSince($0) }
            .filter { $0 > Diary.sameEmptyingWindow }
            .sorted()
        // Меньше четырёх промежутков — это не норма собаки, а случай.
        guard промежутки.count >= 4 else { return (порогВопроса, порогТревоги) }
        let медиана = промежутки[промежутки.count / 2]
        return (max(порогВопроса, медиана * 1.5), max(порогТревоги, медиана * 2))
    }

    static func этоСтул(_ e: LogEvent) -> Bool {
        switch e.kind {
        case .stool: return true
        case .incident: return e.incidentKind == .stoolIndoors
        case .outing, .travelStop: return e.outcome == .stool || e.outcome == .both
        default: return false
        }
    }

    /// Запись, которая доказывает, что туалет отмечают.
    static func ответОТуалете(_ e: LogEvent, прогулкиСОтметками: Set<UUID>) -> Bool {
        switch e.kind {
        case .outing, .travelStop:
            // Отметка внутри прогулки — тоже ответ: человек тапал кнопки.
            return e.outcome != nil
        case .walk:
            return прогулкиСОтметками.contains(e.id)
        case .incident:
            return e.incidentKind == .puddle
        default:
            return false
        }
    }
}
