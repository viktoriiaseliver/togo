// MARK: - Что выбрал человек

/// Три режима фона. Решение дизайна 22.10.2026, хендофф iOS 28.
nonisolated enum BackgroundMode: String, Codable, Sendable, CaseIterable {
    /// Как задумано: фото собаки под всеми разделами, а без него — чёрный.
    ///
    /// **Смысл этого режима сменился 23.10.2026, и это решение дизайна,
    /// а не починка.** Прежде он значил «у каждого раздела своё фото,
    /// подобранное дизайном», и набора таких фотографий ждали. Ответ
    /// круга 2 (`Дизайн/редизайн-ios28/ОТВЕТЫ-круг-2.md`, пункт 1) закрыл
    /// ожидание прямо: «Набор фото разделов мы не отдаём. Фото в прототипе
    /// взяты с Unsplash как заглушки… „Кино“ строится на фото собаки
    /// пользователя». Цепочка названа там же и исполнена в `photoName`.
    case auto
    /// Одно фото для всех экранов.
    case single
    /// Пять фото вперемешку: у каждого экрана своё, меняется при запуске.
    case random
}

/// Выбор человека целиком. Значение, а не объект: его читают два
/// процесса — приложение и расширение виджетов.
nonisolated struct BackgroundChoice: Codable, Equatable, Sendable {
    var mode: BackgroundMode
    /// Имена файлов в общем контейнере, в порядке добавления.
    /// Первое — то, которое показывается в режиме «одно для всех».
    var items: [String]

    /// Больше пяти не кладём: это решение дизайна, а не предел техники.
    ///
    /// **У этого числа с 22.10.2026 ДВА дома, и они разойдутся молча.**
    /// Второй — `component.backdrop.maxPhotos` в `DesignTokens/tokens.json`,
    /// заведён той же датой другой сессией. Числом пользуется домен:
    /// предел проверяет `BackgroundStore.добавить`, и он работает
    /// в расширении виджетов, куда `Token.Component.*` не ходит
    /// (`ComponentTokenScopeTests`). Проверка за минуту, и она обязана
    /// стоять рядом с числом:
    ///
    /// ```
    /// python3 -c "import json;print(json.load(open('DesignTokens/tokens.json'))['component']['backdrop']['maxPhotos']['\$value'])"
    /// ```
    ///
    /// Разошлось — правит тот, кто меняет предел, **в обоих местах**;
    /// хозяин числа — дизайн.
    static let maxPhotos = 5

    static let пусто = BackgroundChoice(mode: .auto, items: [])

    init(mode: BackgroundMode = .auto, items: [String] = []) {
        self.mode = mode
        self.items = items
    }

    /// **Единственная реализация правила выбора.** Её зовут и приложение,
    /// и виджет; отдельной арифметики у виджета нет нарочно — Того уже
    /// обжигался на том, что виджет считал окно «не кормить» сам
    /// и молчал в двух случаях из трёх.
    ///
    /// - Parameters:
    ///   - ключ: какой экран спрашивает.
    ///   - seed: затравка запуска. Ноль — значит «не спрашивали», берём 7,
    ///     как в прототипе.
    ///   - запасное: фото собаки, если своих человек не добавил.
    /// - Returns: имя файла или `nil` — «фона нет, экран чёрный».
    func photoName(for ключ: ScreenKey, seed: UInt64, fallback запасное: String?) -> String? {
        switch mode {
        case .auto:
            // **Цепочка дизайна, ответ круга 2, пункт 1:**
            //
            //     1. своё фото раздела, если человек его задал
            //     2. иначе Dog.photo
            //     3. иначе чёрный #000 БЕЗ ПОДЛОЖКИ
            //
            // Первая ступень у нас недостижима ПО УСТРОЙСТВУ, и это
            // названо, а не умолчано: приписки «фото → раздел» в описи
            // нет вовсе, а первый же добавленный снимок переводит режим
            // в `single` (`добавить`). То есть в `auto` своих снимков
            // не бывает, и ступень первая сворачивается во вторую.
            // Заводить её — отдельная работа с хозяином-дизайном,
            // а не ветка здесь.
            //
            // До 23.10 тут стоял безусловный `nil` с доводом «фото
            // раздела кладёт дизайн, а не мы». Довод умер в тот день,
            // когда дизайн ответил «набора не будет»: условие было
            // привязано к ОЖИДАЕМОМУ НАБОРУ, и в момент отказа от него
            // поменяло знак.
            // **Третья ступень сменилась 27.10.2026 решением Виктории.**
            // Было «иначе чёрный #000 БЕЗ подложки» — ответ круга 2.
            // Стало: иначе встроенная подложка. Её слово: «добавь фото
            // как в прототипе какие-то наши, пусть люди их меняют».
            //
            // Порядок при этом НЕ ТРОНУТ: фото собаки по-прежнему
            // старше встроенных, и человек, заведший свою собаку,
            // чужой не увидит никогда.
            return запасное ?? Self.встроеннаяДля(ключ, seed: seed)
        case .single:
            return items.first ?? запасное ?? Self.встроеннаяДля(ключ, seed: seed)
        case .random:
            let свои = items.isEmpty ? [запасное].compactMap { $0 } : items
            // Встроенные подмешиваются ТОЛЬКО при пустом своём списке:
            // иначе человек, добавивший два снимка, получил бы вперемешку
            // свои и чужую собаку — и прочёл бы это как дефект.
            let список = свои.isEmpty ? BackgroundBridge.встроенные : свои
            guard !список.isEmpty else { return nil }
            return список[Self.индекс(ключ: ключ.name, seed: seed, из: список.count)]
        }
    }

    /// Какая из встроенных подложек достаётся экрану.
    ///
    /// **Назначение ТОЧНОЕ, по прототипу v10, а не по хэшу.** Виктория
    /// назвала раскладку дословно 27.10.2026 и дополнила её 28.10.2026,
    /// когда фоны разделов приехали в ресурсы. Раскладка целиком —
    /// `BackgroundBridge.раскладкаРазделов`; здесь только правило
    /// выбора, и второй копии раскладки тут нет нарочно.
    ///
    /// # Чем это было до 28.10.2026 и сколько стоило
    ///
    /// Раздатчик смотрел **только на `ключ.kind`**, а видов всего
    /// четыре:
    ///
    /// ```
    /// case .today            → портрет
    /// case .tab, .sub, .walk → герой
    /// ```
    ///
    /// То есть он мог вернуть ровно **два** имени из тринадцати, и все
    /// десять фонов разделов, внесённых в `встроенные` коммитом
    /// `6dbfc79`, были недостижимы **по устройству** в режимах
    /// «как задумано» и «одно для всех» — то есть во всех, кроме
    /// «вперемешку». Список расширили, раздатчик остался прежним.
    ///
    /// > **Жалоба владелицы 28.10.2026 — «изображения всё ещё
    /// > = изображения Стича» — была верна буквально:** два снимка
    /// > Стича и были единственным, что эта функция умела вернуть.
    ///
    /// Сторож на это не покраснел и не мог: `встроенныеЛежатВБандле`
    /// проверяет, что у каждого имени из `встроенные` есть байты, —
    /// байты есть у всех тринадцати. Ось сторожа «файл доедет
    /// до бандла», предмет «экран получит своё фото», и первое
    /// читалось как второе.
    ///
    /// # Почему умолчание по виду экрана осталось
    ///
    /// Подэкранов сорок, в раскладке названы не все: «профиль,
    /// настройки, виджеты» Виктория отдала герою одной строкой.
    /// Значит неназванный экран обязан получить героя, а не чёрное
    /// полотно, — и это ровно прежнее поведение, то есть неназванные
    /// экраны правка не трогает.
    ///
    /// `.walk` получает героя вместе с `.tab` и `.sub` — так в списке:
    /// «На улице» названо среди экранов героя. Аватар не раздаётся
    /// **никогда**: жетон в шапке, «остров» и экран блокировки —
    /// не подложка, и за них отвечает не этот метод. Кадр 1:1
    /// на полном экране «Сегодня» был бы виден сразу.
    ///
    /// - Parameter seed: на раскладку НЕ влияет, и это проверено
    ///   (`встроенныеПоПрототипу`: тот же ответ при `seed` 1
    ///   и 999 999). Параметр остаётся в подписи, потому что её зовут
    ///   из `photoName`, где затравка решает режим «вперемешку».
    static func встроеннаяДля(_ ключ: ScreenKey, seed: UInt64) -> String? {
        let список = BackgroundBridge.встроенные
        guard !список.isEmpty else { return nil }
        let имя = BackgroundBridge.подложкаЭкрана[ключ.name] ?? поВиду(ключ.kind)
        // Если файла в бандле нет — не молчим чёрным экраном, а берём
        // любой другой: отсутствие одного снимка не повод оставить
        // человека без фона. Своё фото это всё равно вытесняет.
        return список.contains(имя) ? имя : список[0]
    }

    /// Умолчание для экрана, которого в раскладке нет: «профиль,
    /// настройки, виджеты» — герой, «Сегодня» — портрет.
    private static func поВиду(_ вид: BackdropKind) -> String {
        switch вид {
        case .today: BackgroundBridge.портрет
        case .tab, .sub, .walk: BackgroundBridge.герой
        }
    }

    /// Хэш из прототипа: `h = h * 31 + байт`, по имени экрана поверх
    /// затравки запуска.
    ///
    /// **Своя арифметика вместо `hashValue` — не изобретательство.**
    /// `Hasher` в Swift засевается случайно в каждом процессе: одно
    /// и то же имя даёт разные числа в приложении и в расширении, то есть
    /// виджет показал бы не то фото, что экран. Проверяется это
    /// не рассуждением, а замером с заранее известным ответом —
    /// см. `BackgroundStoreTests.хэшНеЗависитОтПроцесса`.
    static func индекс(ключ: String, seed: UInt64, из количество: Int) -> Int {
        guard количество > 0 else { return 0 }
        var h: UInt64 = seed == 0 ? 7 : seed
        for байт in ключ.utf8 {
            h = h &* 31 &+ UInt64(байт)
        }
        return Int(h % UInt64(количество))
    }
}

