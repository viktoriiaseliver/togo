/// Мост между приложением и расширением. Одно место записи, одно чтения —
/// тот же порядок, что у `WidgetBridge`.
///
/// Байты лежат **файлами в контейнере группы**, а не в `UserDefaults`:
/// пять снимков по 1000 px — это мегабайты, а `UserDefaults` читается
/// целиком при каждом пробуждении виджета. В `UserDefaults` уезжает
/// только опись: режим, имена файлов и затравка запуска.
nonisolated enum BackgroundBridge {
    /// Ключ из хендоффа (`backdrop.settings.storageKey`), чтобы опись
    /// в приложении и в прототипе звалась одинаково.
    static let key = "togo-ios28-bg"
    static let seedKey = "togo-ios28-bg.seed"
    /// Имя файла с фото собаки — запасное для режима «одно для всех».
    static let dogFallbackName = "dog-fallback.jpg"

    static var defaults: UserDefaults {
        UserDefaults(suiteName: AppIdentifiers.appGroup) ?? .standard
    }

    /// Папка со снимками внутри контейнера группы.
    ///
    /// Нет контейнера — нет и папки: `nil` значит «права на группу
    /// не выданы», и это другое состояние, чем «фото не добавляли».
    static var каталог: URL? {
        guard let корень = FileManager.default
            .containerURL(forSecurityApplicationGroupIdentifier: AppIdentifiers.appGroup)
        else { return nil }
        return корень.appendingPathComponent("Backgrounds", isDirectory: true)
    }

    // MARK: Опись

    static func читатьВыбор() -> BackgroundChoice {
        guard let data = defaults.data(forKey: key),
              let выбор = try? JSONDecoder().decode(BackgroundChoice.self, from: data)
        else { return .пусто }
        return выбор
    }

    static func записатьВыбор(_ выбор: BackgroundChoice) {
        guard let data = try? JSONEncoder().encode(выбор) else { return }
        defaults.set(data, forKey: key)
    }

    // MARK: Затравка запуска

    /// Та затравка, с которой сейчас живут все экраны и виджет.
    static func читатьЗатравку() -> UInt64 {
        let число = defaults.object(forKey: seedKey) as? Int ?? 0
        return UInt64(max(0, число))
    }

    /// Новая затравка на запуск. Зовётся один раз за процесс, из
    /// `BackgroundStore.init`.
    @discardableResult
    static func перемешать() -> UInt64 {
        // Потолок — чтобы число влезало в `Int` на всех разрядностях
        // и читалось глазами в `defaults read`.
        let новая = UInt64.random(in: 1...1_000_000)
        defaults.set(Int(новая), forKey: seedKey)
        return новая
    }

    // MARK: Снимки

    /// Три подложки, которые едут В БАНДЛЕ и видны с первого запуска.
    ///
    /// **Решение Виктории 27.10.2026, и оно отменяет ответ дизайна.**
    /// Круг 2, пункт 1 говорил прямо: «Набор фото разделов мы
    /// не отдаём. Фото в прототипе взяты с Unsplash как заглушки…
    /// „Кино" строится на фото собаки пользователя». Её слово:
    /// «добавь фото как в прототипе какие-то наши, пусть люди
    /// их меняют».
    ///
    /// Что это меняет для человека: до сегодня приложение без фото
    /// собаки показывало чёрное полотно — по устройству темы, а не
    /// от ошибки, но первый запуск выглядел пустым. Теперь он
    /// выглядит так, как нарисовано в прототипе.
    ///
    /// **Снимки НЕ из Unsplash**: это фотографии Стича из того же
    /// пакета (`prototypes/assets/stitch-*.png`), пережатые в JPEG
    /// по 238 КБ вместо 0,7–3,4 МБ. Запрет пакета касался заглушек
    /// со стока, и он не нарушен.
    ///
    /// > **Они стартовые, а не постоянные.** Любое своё фото человека
    /// > вытесняет их целиком: `photoName` спрашивает выбор человека
    /// > ПЕРВЫМ, и встроенные подложки участвуют только тогда,
    /// > когда своих нет ни одной.
    /// Портрет Стича — вертикальный кадр под полный экран «Сегодня».
    static let портрет = "стич-портрет.jpg"  // внутреннее: имя файла в бандле, человек его не видит
    /// Герой — кадр под вкладки, подэкраны и «На улице».
    static let герой = "стич-герой.jpg"  // внутреннее: имя файла в бандле, человек его не видит
    /// Аватар — лицо под жетон в шапке и «остров».
    static let аватар = "стич-аватар.jpg"  // внутреннее: имя файла в бандле, человек его не видит

    static let встроенные = [портрет, герой, аватар] + фоныРазделов

    // ФОНЫ РАЗДЕЛОВ ИЗ ПРОТОТИПА — ЗАГЛУШКИ UNSPLASH, И ОНИ ОБЯЗАНЫ
    // БЫТЬ ЗАМЕНЕНЫ ДО РЕЛИЗА.
    //
    // Решение Виктории 27.10.2026: «добавь из Unsplash, потом
    // заменим», адреса она же и назвала. Её же оговорка, записанная
    // дважды и ею самой: «лицензия Unsplash — свободно для макетов,
    // но НЕ ДЛЯ СТОРА без замены».
    //
    // Имя файла начинается с `unsplash-` НАРОЧНО: по этому признаку
    // их находит сторож `UnsplashВПродуктеTests`, который краснеет,
    // пока хоть один такой файл лежит в ресурсах. Без сторожа «потом
    // заменим» — это обещание без читателя, а уедет оно молча,
    // в обычной сборке.
    //
    // Идентификатор в имени — это адрес оригинала целиком:
    // https://unsplash.com/photos/<id после дефиса>. Переименуешь
    // «покрасивее» — потеряешь единственный способ найти источник
    // и проверить лицензию.
    static let фоныРазделов = [
        "unsplash-1601758228041-f3b2795255f1.jpg",  // онбординг, семья, документы, приглашение
        "unsplash-1477884213360-7e9d7dcc1e48.jpg",  // история, порог, «как это работает»
        "unsplash-1628009368231-7bb7cfcb0def.jpg",  // здоровье, визит, рецепт, анализы
        "unsplash-1589924691995-400dc9ecc119.jpg",  // кормление
        "unsplash-1516734212186-a967f81ad0d7.jpg",  // уход
        "unsplash-1583337130417-3346a1be7dee.jpg",  // вес
        "unsplash-1587300003388-59208cc962cb.jpg",  // занятия, матрица, сессия
        "unsplash-1548199973-03cce0bbc87b.jpg",     // течка, курс
        "unsplash-1530281700549-e82e7bf110d6.jpg",  // поездка
        "unsplash-1558788353-f76d92427f16.jpg",     // бирка у двери
    ]

    /// Байты встроенной подложки, если имя — её.
    ///
    /// Ищется в бандле того таргета, который спрашивает: приложение
    /// и расширение виджетов несут ресурсы порознь, и `Bundle.main`
    /// у них разный. `Bundle.module` здесь не годится — проект
    /// не пакетный.
    static func встроеннаяПодложка(_ имя: String) -> Data? {
        guard встроенные.contains(имя) else { return nil }
        let база = (имя as NSString).deletingPathExtension
        let тип = (имя as NSString).pathExtension
        guard let путь = Bundle.main.path(forResource: база, ofType: тип)
                ?? Bundle.main.path(forResource: база, ofType: тип,
                                    inDirectory: "Подложки")  // внутреннее: имя каталога в бандле, не подпись
        else { return nil }
        return try? Data(contentsOf: URL(fileURLWithPath: путь))
    }

    static func данные(файла имя: String) -> Data? {
        // Встроенные проверяются ПЕРВЫМИ и живут не в контейнере:
        // `каталог` у них пустой, и без этой ветки они отдавали бы nil
        // на устройстве без прав на группу приложений.
        if let встроенная = встроеннаяПодложка(имя) { return встроенная }
        guard let каталог else { return nil }
        return try? Data(contentsOf: каталог.appendingPathComponent(имя))
    }

    @discardableResult
    static func положить(_ data: Data, под имя: String) -> Bool {
        guard let каталог else { return false }
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            try data.write(to: каталог.appendingPathComponent(имя), options: .atomic)
            return true
        } catch {
            return false
        }
    }

    static func убрать(файл имя: String) {
        guard let каталог else { return }
        try? FileManager.default.removeItem(at: каталог.appendingPathComponent(имя))
    }

    /// Есть ли запасное фото собаки. Пусто — значит режим «одно для всех»
    /// у человека без своих снимков покажет то же, что «как задумано».
    static var запасноеФото: String? {
        данные(файла: dogFallbackName) == nil ? nil : dogFallbackName
    }

    // MARK: Чтение, которым пользуется виджет

    /// Фото экрана целиком, без приложения и без базы.
    ///
    /// Виджет зовёт **это**, а не своё правило: смотри разбор
    /// у `BackgroundChoice.photoName`.
    static func photo(for ключ: ScreenKey) -> BackgroundPhoto? {
        let выбор = читатьВыбор()
        guard let имя = выбор.photoName(for: ключ,
                                        seed: читатьЗатравку(),
                                        fallback: запасноеФото),
              let data = данные(файла: имя)
        else { return nil }
        return BackgroundPhoto(name: имя, data: data)
    }
}

// MARK: - Хозяин фона на стороне приложения

/// Один `BackgroundStore` на приложение: экраны спрашивают
/// `background(for:)`, и больше никто не решает, какое фото показать.
///
/// **Затравка запуска берётся здесь.** `init` перемешивает её один раз
/// за процесс — отсюда и «меняется при каждом запуске» в режиме
/// «вперемешку». Но перемешивается она в момент **первого обращения**
/// к `shared`, а не в момент старта приложения: пока `TogoApp` не тронет
/// хранилище строкой `_ = BackgroundStore.shared`, человек, ни разу
/// не заходивший в настройки фона, живёт на затравке прошлого запуска.
/// Строка эта — в чужом файле, и она записана открытой в отчёте.
@MainActor
@Observable
final class BackgroundStore {
    static let shared = BackgroundStore()

    private(set) var choice: BackgroundChoice
    /// Затравка этого запуска. Снаружи только читается.
    private(set) var seed: UInt64

    /// Байты не наблюдаются: перерисовку вызывает смена `choice`,
    /// а не наполнение кэша.
    @ObservationIgnored private var кэш: [String: Data] = [:]

    init() {
        choice = BackgroundBridge.читатьВыбор()
        seed = BackgroundBridge.перемешать()
    }

    // MARK: Что показать

    /// Фото для экрана. `nil` — **«фона нет, рисуй чёрный БЕЗ подложки»**,
    /// и это третья ступень цепочки дизайна, а не отсутствие ответа.
    ///
    /// Так отвечают все три режима у человека, который своих снимков
    /// не добавил и фото собаки не завёл. Что делать с этим ответом,
    /// сказано в ответе круга 2 дословно: «иначе чёрный #000 без подложки:
    /// без фото, без `--bd-scrim`, без затемнения шапки. Шапка стоит
    /// на #000, контраст 21:1». То есть `nil` обязан снимать И затемнение
    /// шапки тоже — иначе экран кладёт полупрозрачный чёрный на чёрный
    /// и платит слоем за ничто.
    func background(for ключ: ScreenKey) -> BackgroundPhoto? {
        guard let имя = choice.photoName(for: ключ,
                                         seed: seed,
                                         fallback: BackgroundBridge.запасноеФото)
        else { return nil }
        if let готовое = кэш[имя] {
            return BackgroundPhoto(name: имя, data: готовое)
        }
        guard let data = BackgroundBridge.данные(файла: имя) else { return nil }
        кэш[имя] = data
        return BackgroundPhoto(name: имя, data: data)
    }

    /// Снимки человека для предпросмотра в настройках, в порядке
    /// добавления.
    var мои: [BackgroundPhoto] {
        choice.items.compactMap { имя in
            BackgroundBridge.данные(файла: имя).map { BackgroundPhoto(name: имя, data: $0) }
        }
    }

    var сколькоМоих: Int { choice.items.count }
    var естьМесто: Bool { choice.items.count < BackgroundChoice.maxPhotos }

    // MARK: Что меняет человек

    func выбрать(_ mode: BackgroundMode) {
        guard choice.mode != mode else { return }
        choice.mode = mode
        сохранить(detail: "background.mode." + mode.rawValue)
    }

    /// Положить снимок. Ужимать до 1000 px и жать в JPEG 0.8 — забота
    /// вызывающего (`ФонФото.ужать`): здесь уже байты.
    ///
    /// **Первый снимок в режиме «как задумано» переводит режим
    /// в «одно фото для всех», и это не вольность.** Так делает
    /// прототип — `addBg` в `Togo-RU.dc.html:945`:
    ///
    /// ```js
    /// this.saveBg({ mode: b.mode && b.mode !== 'auto' ? b.mode : 'single', … })
    /// ```
    ///
    /// Без этого человек в режиме по умолчанию добавляет фотографию
    /// и **не видит ничего**: `auto` фото не подменяет по устройству.
    /// Получился бы ровно тот дефект, от которого этот экран и сделан, —
    /// действие без исхода. Уже выбранный `single` или `random`
    /// не трогаем: человек выбрал его сам.
    ///
    /// - Returns: `false`, если места больше нет или контейнер группы
    ///   недоступен. Два разных отказа, и человеку про них говорят
    ///   разными словами — поэтому исход возвращается, а не глотается.
    @discardableResult
    func добавить(_ data: Data) -> Bool {
        guard естьМесто else { return false }
        let имя = UUID().uuidString + ".jpg"
        guard BackgroundBridge.положить(data, под: имя) else { return false }
        кэш[имя] = data
        choice.items.append(имя)
        if choice.mode == .auto { choice.mode = .single }
        сохранить(detail: "background.add")
        return true
    }

    /// Убрать свои снимки. Режим остаётся выбранным: человек просил
    /// убрать фотографии, а не вернуть «как задумано».
    func убратьМои() {
        for имя in choice.items {
            BackgroundBridge.убрать(файл: имя)
            кэш[имя] = nil
        }
        choice.items = []
        сохранить(detail: "background.clear")
    }

    /// Запомнить фото собаки как запасное — для всех трёх режимов.
    ///
    /// Зовётся экраном «Фон приложения» при открытии: база с собакой
    /// живёт в приложении, а виджету нужны байты в общей группе. Без
    /// этого «первое из твоих **или фото собаки**» было бы обещанием
    /// без механизма.
    ///
    /// # ВХОДОВ ПЯТЬ, И ЭТО ДВА РАЗНЫХ СОБЫТИЯ
    ///
    /// ~~Замер 23.10.2026: живых вызовов ровно один —
    /// `BackgroundScreen.swift:56`, в `.task` экрана «Фон приложения».~~
    /// **Устарело за сутки, переписано, не удалено.** Замер был верен
    /// в свой день; 23.10 к нему добавили три вызова у точек записи
    /// байтов, 24.10 — пятый, у смены активной собаки.
    ///
    /// ```sh
    /// # замер 24.10.2026 на 8eecc89
    /// grep -rn --no-ignore-files "запомнитьФотоСобаки(" --include="*.swift" Togo TogoShared
    /// #   BackgroundScreen.swift:56      открытие экрана «Фон приложения»
    /// #   ВыборФотоСобаки.swift:75       оба входа снимка (DogTab, ЖетонСобаки)
    /// #   OnboardingFlow.swift:332       заведение собаки на первом запуске
    /// #   Backup.swift:480               восстановление копии
    /// #   AppState.swift:select(_:)      СМЕНА АКТИВНОЙ СОБАКИ (24.10)
    /// ```
    ///
    /// **Величину меняют два разных события, и путать их дорого.**
    /// Первое — сменились **байты** у собаки (четыре вызова выше).
    /// Второе — сменилась **собака**, у которой эти байты берут: фото
    /// здесь по определению фото *активной* собаки, и определяет это
    /// `BackgroundScreen.swift:56` выражением
    /// `appState.activeDog(from: dogs)?.photo`. Вход второго вида был
    /// один, и он лежал на экране настроек, куда незачем заходить, —
    /// человек с двумя собаками видел под вкладками фото первой.
    ///
    /// > **ОДНА ПОЛОВИНА ПО-ПРЕЖНЕМУ НЕ СДЕЛАНА, И ХОЗЯИНА У НЕЁ НЕТ.**
    /// > `nil` у этой функции значит «нечего класть», а не «убрать»:
    /// > `guard let data else { return }` стоит первой строкой. Значит
    /// > собака **без** снимка подложку не гасит, а должна — цепочка
    /// > дизайна (круг 2, п. 1) кончается на «→ чёрный». Снятие нельзя
    /// > добавить сюда молча: функцию зовут ещё четверо, и у одного
    /// > из них — онбординга — `dog.photo` **всегда** `nil` (писателя
    /// > у `DogDraft.photo` нет, шаг со снимком убран решением дизайна
    /// > 23.10). Стирание на `nil` снесло бы живое фото при повторном
    /// > проходе онбординга. Это решение, а не уборка.
    func запомнитьФотоСобаки(_ data: Data?) {
        guard let data else { return }
        guard BackgroundBridge.данные(файла: BackgroundBridge.dogFallbackName) != data else { return }
        BackgroundBridge.положить(data, под: BackgroundBridge.dogFallbackName)
        кэш[BackgroundBridge.dogFallbackName] = data
    }

    private func сохранить(detail: String) {
        BackgroundBridge.записатьВыбор(choice)
        UsageLog.note(.setting, detail, on: .settings)
        #if canImport(WidgetKit)
        // Виджет берёт то же фото — значит он обязан узнать о смене.
        // Иначе «виджеты используют то же фото» верно в хранилище
        // и ложно на экране до следующего пятнадцатиминутного срока.
        WidgetCenter.shared.reloadAllTimelines()
        #endif
    }
}
