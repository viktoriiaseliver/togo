import Foundation

/// Кто я в этом дневнике и что мне можно, если себя не опознали.
///
/// **Почему отдельным местом.** До 23.09.2026 это решение жило дважды:
/// в `AppState.adoptMe` — для экранов, и в `QuickLog.можно` — для
/// голоса и кнопки «Действие». Общей роли у них быть не может:
/// интент живёт в своём процессе, `AppState` там нет, а роль вообще
/// не хранится на диске — её вычисляют при запуске из списка семьи.
///
/// Поэтому общей сделана не роль, а **решение**. И вовремя: две
/// реализации одного правила, написанные в один день одной рукой,
/// уже разошлись в двух местах:
///
/// 1. **Пустая семья.** На экранах пустота у гостя означала
///    «наблюдатель», а голосом — «можно всё». У гостя, принявшего
///    приглашение, есть момент, когда он уже гость, а карточки семьи
///    ещё не приехали: локально их ноль. В этот момент голосом
///    записывалась и доза.
/// 2. **Единственная карточка.** На экранах она считается моей только
///    при `isMe`, голосом — бралась любая. На гостевом телефоне при
///    частичной синхронизации единственной приехавшей естественно
///    оказывается карточка **владельца** — и гость получал `giveDose`
///    и `editTreatment`.
///
/// Обе дыры одного рода: **правило было одно, а проверок две, и
/// разошлись они в краю** — там, где данные неполны. Край и есть то
/// место, ради которого правило пишут.
nonisolated enum FamilyResolver {

    /// Моя карточка в списке семьи, если её удалось опознать.
    ///
    /// Сначала по запомненному идентификатору: он лежит на устройстве
    /// и в общий дневник не уезжает — в отличие от `isMe`, который
    /// однажды уже приехал на второй телефон карточкой владельца
    /// (`5c70324`).
    ///
    /// Запасной путь — единственный участник, помеченный `isMe`,
    /// **и только в своём дневнике**.
    ///
    /// `isMe` хранится в модели и потому **уезжает в общий дневник**:
    /// на втором телефоне «я» уже однажды оказалась карточкой владельца
    /// (`5c70324`). Значит у гостя эта метка не значит ничего — и при
    /// частичной синхронизации единственной приехавшей карточкой
    /// естественно оказывается как раз владелец, с правом на дозу
    /// и на схему лечения.
    ///
    /// Своей у гостя карточка становится только одним способом:
    /// её идентификатор запомнен **на этом устройстве**.
    static func меня(среди участники: [FamilyMember],
                     запомненный: UUID?,
                     гость: Bool = false) -> FamilyMember? {
        if let запомненный,
           let мой = участники.first(where: { $0.id == запомненный }) {
            return мой
        }
        guard !гость, участники.count == 1 else { return nil }
        return участники.first(where: { $0.isMe })
    }

    /// Потолок прав второго человека — **временно, до прихода роли
    /// по обмену.**
    ///
    /// # Что чинится
    ///
    /// До 14.10.2026 опознанный гость получал права СВОЕЙ карточки —
    /// а её ставит онбординг, и ставит владельческой
    /// (`OnboardingFlow.saveDog`: `FamilyMember(role: .owner, isMe: true)`,
    /// там же `myMemberID`). То есть человек, который сперва завёл
    /// свой дневник, а потом принял приглашение, ходил по ЧУЖОМУ
    /// дневнику со всеми правами, включая `editTreatment` — схемы
    /// лечения. Это красная линия проекта.
    ///
    /// Запасной путь (`рольБезОпознания`) от этого был защищён, прямой —
    /// нет: `меня(…)` возвращает карточку по запомненному `id`, и флаг
    /// `гость` на неё не влияет.
    ///
    /// # Почему снимается именно это и не больше
    ///
    /// Снято ровно то, чего второй человек **не мог получить законно**:
    /// `editTreatment` (схема лечения) и `manageFamily` (звать и менять
    /// роли; слой обмена это уже держит отдельно —
    /// `FamilyShare.swift:109`, `:262`). Всё остальное оставлено
    /// намеренно: человека звали помогать, и запереть его —
    /// не починка, а вторая беда того же механизма. Её мы сегодня
    /// чиним с другого края (`EventLog`, `DayPlanActions`,
    /// `QuickLogIntents` — отказ, называющий выход).
    ///
    /// # Чем это заменится, и адрес записан нарочно
    ///
    /// **Решение Виктории 14.10.2026: «пусть выбираете вы при
    /// приглашении»** — роль приглашённого должна ехать вместе
    /// с `CKShare` и приезжать к гостю. Сегодня она не ездит вовсе:
    /// `Permission`, `FamilyRole`, `can(` дают ноль вхождений во всех
    /// девяти файлах `TogoShared/Sync/`. Когда роль поедет, этот
    /// потолок снимается целиком — он затычка, а не правило.
    ///
    /// # Почему функция, а не две проверки
    ///
    /// Входов два: `AppState.permissions` (экраны) и `права(…)` ниже
    /// (голос, кнопка «Действие», виджет). Правило при этом одно.
    /// 23.09 мы уже платили за то, что одно правило жило двумя
    /// проверками и разошлось в краю — там, где данные неполны.
    static func потолокГостя(_ права: Set<Permission>, гость: Bool) -> Set<Permission> {
        guard гость else { return права }
        return права.subtracting([.editTreatment, .manageFamily])
    }

    /// Что можно, когда себя опознать не удалось.
    ///
    /// **Свой дневник** — владелец. Участники там карточки, которые
    /// завёл сам хозяин, и себя среди них он мог не заводить; отнять
    /// права значило бы запереть человека в собственном дневнике.
    ///
    /// **Чужой** — наблюдатель. Мы не знаем, кто за телефоном,
    /// и выдавать всё нельзя: читать можно, писать нельзя.
    static func рольБезОпознания(гость: Bool) -> FamilyRole {
        гость ? .observer : .owner
    }

    /// Права на этом телефоне: короткий путь для тех, у кого нет
    /// `AppState`, — интентов и виджетов.
    static func права(среди участники: [FamilyMember],
                      запомненный: UUID?,
                      гость: Bool) -> Set<Permission> {
        if let мой = меня(среди: участники, запомненный: запомненный, гость: гость) {
            return потолокГостя(мой.permissions, гость: гость)
        }
        return потолокГостя(рольБезОпознания(гость: гость).defaultPermissions, гость: гость)
    }
}
