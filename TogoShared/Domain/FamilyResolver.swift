import Foundation

/// Кто я в этом дневнике и что мне можно, если себя не опознали.
///
/// **Почему отдельным местом.** До 23.09.2026 это решение жило дважды:
/// в `AppState.adoptMe` — для экранов, и в `QuickLog.можно` — для
/// голоса и кнопки «Действие». Общей роли у них быть не может:
/// интент живёт в своём процессе, `AppState` там нет, а роль вообще
/// не хранится на диске — её вычисляют при запуске из списка семьи.
///
/// Поэтому общей сделана не роль, а **решение**. И вовремя: две
/// реализации одного правила, написанные в один день одной рукой,
/// уже разошлись в двух местах:
///
/// 1. **Пустая семья.** На экранах пустота у гостя означала
///    «наблюдатель», а голосом — «можно всё». У гостя, принявшего
///    приглашение, есть момент, когда он уже гость, а карточки семьи
///    ещё не приехали: локально их ноль. В этот момент голосом
///    записывалась и доза.
/// 2. **Единственная карточка.** На экранах она считается моей только
///    при `isMe`, голосом — бралась любая. На гостевом телефоне при
///    частичной синхронизации единственной приехавшей естественно
///    оказывается карточка **владельца** — и гость получал `giveDose`
///    и `editTreatment`.
///
/// Обе дыры одного рода: **правило было одно, а проверок две, и
/// разошлись они в краю** — там, где данные неполны. Край и есть то
/// место, ради которого правило пишут.
nonisolated enum FamilyResolver {

    /// Моя карточка в списке семьи, если её удалось опознать.
    ///
    /// Сначала по запомненному идентификатору: он лежит на устройстве
    /// и в общий дневник не уезжает — в отличие от `isMe`, который
    /// однажды уже приехал на второй телефон карточкой владельца
    /// (`5c70324`).
    ///
    /// Запасной путь — единственный участник, помеченный `isMe`,
    /// **и только в своём дневнике**.
    ///
    /// `isMe` хранится в модели и потому **приезжает извне**: на втором
    /// телефоне «я» уже однажды оказалась карточкой владельца
    /// (`5c70324`). Значит у гостя эта метка не значит ничего — и при
    /// частичной синхронизации единственной приехавшей карточкой
    /// естественно оказывается как раз владелец, с правом на дозу
    /// и на схему лечения.
    ///
    /// # ПОПРАВКА 25.10.2026: канал, названный здесь, УМЕР — а запрет жив
    ///
    /// Прежняя редакция говорила «уезжает **в общий дневник**». Это
    /// перестало быть верным 08.10.2026, когда `FamilyMember` убрали
    /// из обмена (`SharedDiary.swift:78`, с пометкой «обратно его
    /// заводить не надо»). То есть довод, на котором стоит условие
    /// `участники.count == 1`, к этому дню был мёртв.
    ///
    /// **Правило при этом остаётся верным, и это замер, а не осторожность.**
    /// Каналов доставки чужого `isMe` по-прежнему два:
    ///
    /// ```
    /// архив             Backup.swift:68 пишет isMe в снимок,
    ///                   :496 восстанавливает — чужой архив приносит
    ///                   чужую метку «я»
    /// зеркало CD_*      FamilyMember.self стоит в схеме SwiftData
    ///                   (SchemaVersions:68 и :396), то есть карточки
    ///                   едут приватной базой на ДРУГИЕ устройства
    ///                   владельца
    /// контроль замера   то же поле `role` находится тем же запросом
    ///                   по тем же файлам — разбор состоялся
    /// ```
    ///
    /// > **Вывод был верен, а причина под ним умерла.** Это зеркало
    /// > нашего класса «объяснение наследует достоверность замера
    /// > и не имеет своей»: здесь замер жив, объяснение нет, и следующий
    /// > стал бы рассуждать от мёртвого канала. Снять условие по такому
    /// > рассуждению значило бы отдать гостю право на дозу.
    ///
    /// # Что это стоит НА ЭКРАНЕ, и почему всё равно так
    ///
    /// Пилюля «это я» в списке «Семьи» спрашивает этот резолвер
    /// (`FamilyScreen.swift:417`, правка `025b3ba`). При нескольких
    /// участниках и ненаписанном `myMemberID` — а его пишет **только
    /// онбординг** (`OnboardingFlow:329`) — она не показывается ни у кого.
    /// Так вышло на кадре витрины 25.10: засеянный сценарий онбординг
    /// не проходит, и жетона на кадре нет вовсе.
    ///
    /// **Это не регрессия показа, а цена верного ответа:** поставить
    /// «это я» на чужого человека хуже, чем не поставить никому. Вход,
    /// которым человек говорит «это я», есть и работает — кнопка
    /// в `MemberScreen` (`FamilyScreen.swift:1000`).
    ///
    /// Своей у гостя карточка становится только одним способом:
    /// её идентификатор запомнен **на этом устройстве**.
    static func меня(среди участники: [FamilyMember],
                     запомненный: UUID?,
                     гость: Bool = false) -> FamilyMember? {
        if let запомненный,
           let мой = участники.first(where: { $0.id == запомненный }) {
            return мой
        }
        guard !гость, участники.count == 1 else { return nil }
        return участники.first(where: { $0.isMe })
    }

    /// Кому перейдёт дежурство. Правило, а не «кто попался первым».
    ///
    /// # Чего стоило отсутствие правила
    ///
    /// Замер 25.10.2026. В экране стояло
    /// `members.first { $0.can(.giveDose) && $0.id != current.id }`
    /// при `@Query` БЕЗ сортировки — то есть при источнике, чей
    /// порядок меняется между запусками. «Передать» предлагало
    /// **каждый запуск другого человека**, и выбор этот про дежурство
    /// над собакой: кто получит напоминания о дозах.
    ///
    /// > **`first` по многозначному предикату — это выбор без правила.**
    /// > Он выглядит детерминированным, потому что код один и тот же,
    /// > а меняется то, чего код не называет: порядок источника.
    ///
    /// Порядок у запроса теперь задан, но этого мало: правило,
    /// живущее «первым элементом массива», нельзя ни прочесть,
    /// ни проверить. Здесь оно названо и сортирует САМО —
    /// независимо от того, что отдал источник.
    ///
    /// Правило: **по имени**, и это выбор. Поля «кого завели раньше»
    /// у `FamilyMember` нет; завести — правка формы схемы, решение
    /// Виктории. До тех пор имя даёт порядок, предсказуемый человеку.
    ///
    /// Себя исключаем по `id`, а не по `isMe`: `isMe` приезжает извне
    /// и однажды уже указал на владельца (`5c70324`).
    static func сменщик(после текущий: FamilyMember,
                        среди участники: [FamilyMember]) -> FamilyMember? {
        участники
            .filter { $0.id != текущий.id && $0.can(.giveDose) }
            .sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
            .first
    }

    /// Кому адресован брифинг ситтеру — тем же правилом.
    ///
    /// Тот же дефект и та же цена: заголовок «Брифинг для Ани» брал
    /// `members.first { … }` по предикату, которому подходят несколько
    /// человек, и имя в заголовке менялось между запусками само.
    /// Брифинг пишут одному человеку, и он читает его как адресованный
    /// себе.
    static func адресатБрифинга(среди участники: [FamilyMember]) -> FamilyMember? {
        участники
            .filter { !$0.isMe && !$0.can(.seeMedical) }
            .sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
            .first
    }

    /// Потолок прав второго человека — **временно, до прихода роли
    /// по обмену.**
    ///
    /// # Что чинится
    ///
    /// До 14.10.2026 опознанный гость получал права СВОЕЙ карточки —
    /// а её ставит онбординг, и ставит владельческой
    /// (`OnboardingFlow.saveDog`: `FamilyMember(role: .owner, isMe: true)`,
    /// там же `myMemberID`). То есть человек, который сперва завёл
    /// свой дневник, а потом принял приглашение, ходил по ЧУЖОМУ
    /// дневнику со всеми правами, включая `editTreatment` — схемы
    /// лечения. Это красная линия проекта.
    ///
    /// Запасной путь (`рольБезОпознания`) от этого был защищён, прямой —
    /// нет: `меня(…)` возвращает карточку по запомненному `id`, и флаг
    /// `гость` на неё не влияет.
    ///
    /// # Почему снимается именно это и не больше
    ///
    /// Снято ровно то, чего второй человек **не мог получить законно**:
    /// `editTreatment` (схема лечения) и `manageFamily` (звать и менять
    /// роли; слой обмена это уже держит отдельно —
    /// `FamilyShare.swift:109`, `:262`). Всё остальное оставлено
    /// намеренно: человека звали помогать, и запереть его —
    /// не починка, а вторая беда того же механизма. Её мы сегодня
    /// чиним с другого края (`EventLog`, `DayPlanActions`,
    /// `QuickLogIntents` — отказ, называющий выход).
    ///
    /// # Чем это заменится, и адрес записан нарочно
    ///
    /// **Решение Виктории 14.10.2026: «пусть выбираете вы при
    /// приглашении»** — роль приглашённого должна ехать вместе
    /// с `CKShare` и приезжать к гостю. Сегодня она не ездит вовсе:
    /// `Permission`, `FamilyRole`, `can(` дают ноль вхождений во всех
    /// девяти файлах `TogoShared/Sync/`.
    ///
    /// ~~Когда роль поедет, этот потолок снимается целиком — он
    /// затычка, а не правило.~~ **ЛОЖНО, и снято замером 25.10.2026,
    /// в тот день, когда роль поехала.** Роль теперь приезжает
    /// (`НазначениеРоли.swift`, поле на записи общего доступа),
    /// и по этой записи потолок полагалось снять — то есть условие,
    /// привязанное к появлению механизма, **поменяло бы знак
    /// в момент успеха**, из запрета в разрешение. Это наш
    /// названный класс, и вот почему здесь он особенно дорог:
    ///
    /// ```
    /// что приезжает   роль, выбранная владельцем, — по каналу,
    ///                 записи в который мы ПРОВЕРИТЬ НЕ МОЖЕМ:
    ///                 приватная база CloudKit неизмерима без её
    ///                 личного iCloud, второго конца у связи нет
    /// что держит       потолок — единственное место, где
    ///                 `editTreatment` отнимается у второго телефона
    ///                 БЕЗ доверия приехавшему значению
    /// ```
    ///
    /// То есть ровно в тот день, когда права начали приезжать извне,
    /// потолок перестал быть затычкой и **стал правилом**: он держит
    /// красную линию независимо от того, что пришло по проводу.
    /// Приехать может и `.owner` — наряд читается нами, а не проверяется.
    ///
    /// > **Условие снятия привязано к ПРАВИЛУ, а не к наличию
    /// > механизма.** Снять его может только решение Виктории о том,
    /// > что второй человек правит схему лечения, — и больше ничто.
    ///
    /// **И ровно половину этого адреса я сперва записал неверно.**
    /// Первая редакция называла единственным условием снятия приезд
    /// роли. Но у дефекта две причины, и вторую снимает макет ветки
    /// «Позвали» (решение Виктории, рисунком): приглашённый **не
    /// проходит онбординг владельца** — «своей собаки не создаём».
    /// Нет онбординга — нет карточки `.owner` и запомненного
    /// `myMemberID`, `меня(…)` вернёт `nil`, и сработает запасной путь
    /// `рольБезОпознания(гость:) = .observer`. Потолку нечего снимать.
    ///
    /// **Но снимать его после появления той ветки всё равно нельзя.**
    /// У тех, кто прошёл онбординг РАНЬШЕ, карточка `.owner`
    /// и `myMemberID` уже лежат на телефоне, и новая ветка их
    /// не тронет. Снять потолок «потому что теперь собаку не заводят»
    /// значит вернуть красную линию всем, у кого приложение уже стоит.
    ///
    /// > Условие снятия привязано к **приезду роли**, а не к появлению
    /// > новой ветки входа. Две причины — два срока, и совпадать они
    /// > не обязаны.
    ///
    /// # Почему функция, а не две проверки
    ///
    /// Входов два: `AppState.permissions` (экраны) и `права(…)` ниже
    /// (голос, кнопка «Действие», виджет). Правило при этом одно.
    /// 23.09 мы уже платили за то, что одно правило жило двумя
    /// проверками и разошлось в краю — там, где данные неполны.
    static func потолокГостя(_ права: Set<Permission>, гость: Bool) -> Set<Permission> {
        guard гость else { return права }
        return права.subtracting([.editTreatment, .manageFamily])
    }

    /// Что можно, когда себя опознать не удалось.
    ///
    /// **Свой дневник** — владелец. Участники там карточки, которые
    /// завёл сам хозяин, и себя среди них он мог не заводить; отнять
    /// права значило бы запереть человека в собственном дневнике.
    ///
    /// **Чужой** — наблюдатель. Мы не знаем, кто за телефоном,
    /// и выдавать всё нельзя: читать можно, писать нельзя.
    static func рольБезОпознания(гость: Bool) -> FamilyRole {
        гость ? .observer : .owner
    }

    /// Права, которые дало приехавшее назначение, — или `nil`, если
    /// применять нечего.
    ///
    /// # Почему приехавшее сильнее своей карточки, и только у гостя
    ///
    /// У гостя карточка — **именно то, чему верить нельзя**. Либо её
    /// поставил онбординг владельца, и тогда она `.owner` со всеми
    /// правами (ради этого случая и написан потолок), либо она приехала
    /// с телефона хозяйки, и тогда «я» в ней — хозяйка (`5c70324`).
    /// Назначение же пришло **оттуда, где его выбирал человек**.
    ///
    /// У себя дома наоборот: участники — карточки, которые завёл сам
    /// хозяин, и чужой наряд их не отменяет. Поэтому `гость` стоит
    /// в условии первым, а не подразумевается.
    ///
    /// **`права ?? роль.defaultPermissions`** — тот же порядок, что
    /// в модели (`FamilyMember.permissions`, `Family.swift:63`):
    /// именные сильнее пресета, пресет работает, когда именных нет.
    /// Третьей реализации этого правила в проекте быть не должно.
    static func приехавшее(_ назначение: НазначеннаяРоль?, гость: Bool) -> Set<Permission>? {
        guard гость, let назначение, let роль = назначение.роль else { return nil }
        return назначение.права ?? роль.defaultPermissions
    }

    /// Чья это роль по-нашему — для того, кто показывает СЛОВО.
    ///
    /// Отдельно от прав, потому что вопросы разные: право отвечает
    /// «можно ли нажать», роль — «как это называется человеку»
    /// (`РольВДневнике`, три места одним утверждением). Обратного
    /// перевода из набора прав в роль не существует, и собрать слово
    /// из `права(…)` нельзя.
    static func роль(среди участники: [FamilyMember],
                     запомненный: UUID?,
                     гость: Bool,
                     назначение: НазначеннаяРоль? = nil) -> FamilyRole {
        if гость, let роль = назначение?.роль { return роль }
        if let мой = меня(среди: участники, запомненный: запомненный, гость: гость) {
            return мой.role
        }
        return рольБезОпознания(гость: гость)
    }

    /// Права на этом телефоне: короткий путь для тех, у кого нет
    /// `AppState`, — интентов и виджетов.
    ///
    /// **`назначение` со значением по умолчанию `nil` нарочно.** Так
    /// вызов, который о приехавшей роли не знает, ведёт себя ровно
    /// как до правки, а не как «роль не приехала»: разницы в исходе
    /// нет, но разница в том, сколько мест надо поправить, чтобы
    /// правило не разошлось. Живых входов два, и оба названы поимённо
    /// в `ПотолокГостяTests`.
    static func права(среди участники: [FamilyMember],
                      запомненный: UUID?,
                      гость: Bool,
                      назначение: НазначеннаяРоль? = nil) -> Set<Permission> {
        // Потолок стоит и здесь. Приехавшее значение — чужая строка,
        // а не разрешение: наряд пишет владелец, но проверить, что
        // его писал именно он, нам нечем.
        if let приехало = приехавшее(назначение, гость: гость) {
            return потолокГостя(приехало, гость: гость)
        }
        if let мой = меня(среди: участники, запомненный: запомненный, гость: гость) {
            return потолокГостя(мой.permissions, гость: гость)
        }
        return потолокГостя(рольБезОпознания(гость: гость).defaultPermissions, гость: гость)
    }
}
