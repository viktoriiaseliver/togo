import Foundation

/// Какой день показывает главный экран — и чем этот день отличается
/// от «сейчас».
///
/// **Заведено 28.09, потому что до этого у экрана было одно `now`
/// на два разных смысла.** Им отвечали и на «который час» (таймер
/// прогулки, тихие часы, срок дозы, «взяла на себя · 45 минут»),
/// и на «за какой день считать» (лента, сводка, счёт выходов, план).
/// Пока показывают сегодня, это одно и то же, и различие не видно.
/// В ту секунду, когда человек листает на вчера, оно решает всё:
/// лента должна уехать во вчера, а таймер идущей прогулки — нет.
///
/// Поэтому здесь две даты и ни одной производной от другой.
nonisolated struct ScreenDay: Equatable, Sendable {

    /// Настоящие часы. Тикают, в фоне стоят, к выбранному дню
    /// отношения не имеют.
    let сейчас: Date
    /// Начало показываемого дня.
    let начало: Date
    let calendar: Calendar

    init(показать день: Date, сейчас: Date, calendar: Calendar = .current) {
        self.сейчас = сейчас
        self.calendar = calendar
        self.начало = calendar.startOfDay(for: день)
    }

    var этоСегодня: Bool { calendar.isDate(начало, inSameDayAs: сейчас) }

    /// Последнее мгновение показываемого дня.
    var конец: Date {
        (calendar.date(byAdding: .day, value: 1, to: начало) ?? начало)
            .addingTimeInterval(-1)
    }

    /// Момент, от которого считается всё «на этот день»: что уже
    /// прошло, что просрочено, сколько времени дома.
    ///
    /// Сегодня это настоящие часы. В прошлом дне — его конец, а не
    /// `сейчас`: иначе план вчерашнего дня показал бы всё несделанным
    /// «потому что ещё не наступило», а сутки давно закрыты.
    ///
    /// **И не начало дня.** С началом вчерашний день выглядел бы так,
    /// будто он ещё не начинался: ноль выходов, ноль еды, всё впереди.
    var отсчёт: Date { этоСегодня ? сейчас : конец }

    /// Вперёд нельзя дальше сегодня. Записи в будущем ломают всё, что
    /// считается «от последнего раза», — у Togo такая запись в живом
    /// дневнике уже появлялась.
    var можноВперёд: Bool { !этоСегодня }

    func сдвинуть(на дней: Int) -> ScreenDay {
        let новый = calendar.date(byAdding: .day, value: дней, to: начало) ?? начало
        // Вперёд — не дальше сегодня. Ограничение стоит ЗДЕСЬ, а не
        // в кнопке: кнопка одна из поверхностей, а правило одно.
        let сегодня = calendar.startOfDay(for: сейчас)
        return ScreenDay(показать: min(новый, сегодня), сейчас: сейчас, calendar: calendar)
    }

    /// Момент, которым записывать быструю отметку.
    ///
    /// Сегодня — настоящие часы. **В прошлом дне его нет**, и это
    /// не недоделка: «сейчас» во вчерашнем дне не существует, и
    /// подставить туда любое время значило бы соврать о часе записи.
    /// Кто записывает в прошлый день, обязан час назвать.
    var моментБыстройЗаписи: Date? { этоСегодня ? сейчас : nil }
}
