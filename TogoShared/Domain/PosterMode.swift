import Foundation

/// Какого цвета блок плаката. Решение дизайна окт 2026 (`DECISIONS.md`,
/// «Сегодня — Плакат»):
///
/// > Верхняя треть экрана — цветной блок состояния… **цвет блока =
/// > режим** (индиго-800 · тёмный янтарь натощак · акцент целиком
/// > для дозы, кнопка под ним инверсная · тёмный терракот тревога)…
/// > ночь и первый день — нейтральный `fill-1`.
///
/// **Почему правило живёт здесь, а не во вью.** Плакат применяется
/// на «Сегодня» и «На улице», а цвет состояния спрашивают ещё виджет
/// и «остров» — то есть четыре поверхности. У Togo записано, чем
/// кончается третья реализация одного правила: виджет считал окно
/// «не кормить» собственной арифметикой, и сторож на вызов был к этому
/// слеп. Поэтому здесь чистая функция, а вью только красит.
///
/// **Чего этот тип не знает нарочно.** Ни `Color`, ни SwiftUI, ни имён
/// токенов: по решению Виктории 07.10 дизайн переезжает в Figma
/// и может меняться, а логика остаётся. Он отвечает на один вопрос —
/// **какой режим**, — а чем режим покрашен, решают токены
/// `semantic.poster.*`.
nonisolated enum PosterMode: String, CaseIterable, Sendable {

    /// Обычный день. Индиго.
    case usual

    /// Натощак. Тёмный янтарь — и янтарь у Togo разрешён **только**
    /// этому состоянию, подложка наследует ограничение.
    case fasting

    /// Час дозы. Акцент заливает блок целиком, и кнопка под ним
    /// становится инверсной — это единственный режим, где надпись
    /// на блоке берёт `labelOnDose`, а не `label`.
    case dose

    /// Тревога. Тёмный терракот.
    case alarm

    /// Ночь и первый день. Нейтральный, без цвета состояния:
    /// ночью нечего подсвечивать, а в первый день нечего измерять.
    case quiet

    /// Что приложение знает о дне. Плоская структура нарочно: правило
    /// надо уметь спросить из теста, из виджета и из «острова»,
    /// не поднимая хранилище.
    struct DayState: Sendable, Equatable {
        /// Тревога: инцидент, кровь, активный эпизод — что угодно,
        /// что уже решено считать тревогой. Этот тип не выводит
        /// тревогу сам: у неё свои правила (`AlarmThreshold`,
        /// `EpisodeTrigger`), и дублировать их здесь значило бы
        /// завести вторую реализацию.
        let isAlarm: Bool
        /// Идёт окно натощак перед дозой.
        let isFasting: Bool
        /// Час дозы наступил и доза не отмечена.
        let isDoseDue: Bool
        /// Ночь по часам тихого режима.
        let isNight: Bool
        /// Первый день: ритма ещё нет, измерять нечего.
        let isFirstDay: Bool

        init(isAlarm: Bool = false,
             isFasting: Bool = false,
             isDoseDue: Bool = false,
             isNight: Bool = false,
             isFirstDay: Bool = false) {
            self.isAlarm = isAlarm
            self.isFasting = isFasting
            self.isDoseDue = isDoseDue
            self.isNight = isNight
            self.isFirstDay = isFirstDay
        }
    }

    /// Режим по состоянию дня.
    ///
    /// **Порядок проверок и есть правило, а не оформление.** Он выведен
    /// из того, что человек должен увидеть, когда верны сразу два:
    ///
    /// ```
    /// тревога      сильнее всего: это единственное состояние, из-за
    ///              которого берут телефон, когда с собакой плохо
    /// ночь / первый день   сильнее дозы и натощак: подсвечивать
    ///              нечего, а цветной блок в три ночи — это свет в лицо
    /// доза         сильнее натощак: натощак ВЕДЁТ к дозе, и когда
    ///              час наступил, окно уже не главное
    /// натощак      ограничение, которое надо держать перед дозой
    /// ```
    ///
    /// Переставь две средние строки — и в три ночи человек получит
    /// акцентную заливку во весь верх экрана. Это не вкус, у нас
    /// записано решение про тихие часы.
    static func mode(_ state: DayState) -> PosterMode {
        if state.isAlarm { return .alarm }
        if state.isNight || state.isFirstDay { return .quiet }
        if state.isDoseDue { return .dose }
        if state.isFasting { return .fasting }
        return .usual
    }

    /// Нужна ли инверсная подпись на блоке.
    ///
    /// Отдельный вопрос, а не производное от `mode`: вью иначе однажды
    /// спросит `mode == .dose` своей рукой, и появится вторая
    /// реализация одного правила. Здесь у правила одно место.
    var needsInverseLabel: Bool { self == .dose }

    /// Несёт ли режим цвет состояния. `false` — блок нейтральный.
    ///
    /// Нужно тому, кто решает, показывать ли статусную подпись: на
    /// нейтральном блоке подписи статусным цветом нечего делать.
    var carriesStatusColour: Bool { self != .quiet }
}
