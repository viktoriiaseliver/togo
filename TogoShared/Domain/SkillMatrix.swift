import Foundation

/// Матрица навыка: где и с кем получается. Функция Pro из нового
/// дизайна, раздел «7 · Режимы · матрица и эпизод»
/// (`Togo ФИНАЛ v2`, окт 2026). На экране — таблица «Удачных из 10 ·
/// последние попытки»: строки Дом · Подъезд · Двор · Улица, столбцы
/// по участникам семьи.
///
/// **Чего в коде не было.** `SkillProgress` считает успех одной
/// величиной на навык: `status(successes:attempts:)`. Это отвечает
/// на вопрос «получается ли», и не отвечает на тот, ради которого
/// матрицу и рисуют: **получается ли ЗДЕСЬ и С ЭТИМ человеком.**
/// Сводное число эти два измерения схлопывает — ровно как сальдо
/// «−38» у храповика локализации спрятало и завышение, и занижение
/// на разных строках.
///
/// Практический смысл для человека: «дома 10 из 10, на улице 3 из 10»
/// значит не «собака не умеет», а «отрабатывать надо на улице».
/// Сводные 7 из 10 не говорят ни того, ни другого.
///
/// **Порог берётся у соседа, а не заводится свой.** Статус клетки
/// считает `SkillProgress.status` — тот же, что у навыка целиком.
/// Два правила на одну мысль расходятся на второй правке; у Togo
/// это записано трижды.
///
/// # Мест вызова ноль. Подключать нельзя — и это НЕ половина функции
///
/// Замер 08.10.2026 на `7c61a21`, наряд был «подключить». Первым делом
/// проверено не «кто читает матрицу», а **кто заводит попытку**, —
/// и оказалось, что записи одной попытки в модели нет вовсе:
///
/// ```
/// Attempt (здесь)          place: Place (ЗАКРЫТЫЙ enum) · memberID: UUID
///                          · succeeded · date
/// ProcedureSkill.record()  attempts += 1 — СЧЁТЧИК. Ни места,
/// (Training.swift:118)     ни участника, ни даты, ни строки попытки
/// TrainingStep / Session   place: String — СВОБОДНЫЙ ТЕКСТ («Коридор»)
/// (Training.swift:10, 46)  person: String — ИМЯ («Виктория»)
/// SkillAttemptSheet        знает только `skill: ProcedureSkill`:
///                          ни места, ни участника у входа нет
/// ```
///
/// Три блокера, независимых друг от друга:
///
/// 1. **Попытка нигде не хранится по одной.** Матрица и «последние
///    попытки» из макета требуют строк, а в модели счётчики. Это новая
///    сущность, то есть форма схемы, — и перед отпечатком сборки
///    её не правят.
/// 2. **Место — свободный текст и не та ось.** «Коридор» не Дом,
///    не Подъезд, не Двор и не Улица. Отображения не существует,
///    и придумывать его в коде нельзя: закрытый список — решение
///    дизайна, а в живых данных стоит «Коридор».
/// 3. **Участник — имя, а не `memberID`.** То есть модель хранит ровно
///    то, что голова этого файла запрещает двумя абзацами выше.
///    Собранная поверх имени матрица переносила бы историю в другую
///    клетку при переименовании участника — молча.
///
/// > **«Подключить» здесь дало бы не половину функции, а таблицу,
/// > которая выглядит работающей и врёт при первом переименовании.**
///
/// Что нужно прежде первой строки, и это вопрос не к коду: дизайн
/// называет либо отображение «Коридор → одно из четырёх», либо новую
/// сущность, которая пишет `Place` сразу. Пока ответа нет, модуль
/// остаётся **решением не подключать**, а не долгом.
nonisolated enum SkillMatrix {

    /// Где происходила попытка. Список закрыт и упорядочен по
    /// возрастанию сложности — так он и читается на экране сверху
    /// вниз, и порядок здесь часть смысла, а не оформление.
    enum Place: String, Codable, CaseIterable, Sendable {
        case home       // Дом
        case entrance   // Подъезд
        case yard       // Двор
        case street     // Улица
    }

    /// Одна попытка. Нарочно плоская и без ссылок на модели: матрицу
    /// надо уметь посчитать и из архива, и из теста, и из выгрузки.
    struct Attempt: Sendable, Equatable {
        let place: Place
        /// Кто был с собакой. Идентификатор участника, не имя:
        /// имя переименовывается, а клетка должна остаться той же.
        let memberID: UUID
        let succeeded: Bool
        let date: Date

        init(place: Place, memberID: UUID, succeeded: Bool, date: Date) {
            self.place = place
            self.memberID = memberID
            self.succeeded = succeeded
            self.date = date
        }
    }

    /// Клетка матрицы.
    struct Cell: Sendable, Equatable {
        let place: Place
        let memberID: UUID
        let successes: Int
        let attempts: Int

        /// Статус — у `SkillProgress`, своего порога здесь нет.
        var status: SkillStatus {
            SkillProgress.status(successes: successes, attempts: attempts)
        }

        /// Сколько попыток ещё нужно, прежде чем клетка вообще может
        /// что-то утверждать. Показывается человеку вместо числа:
        /// «3 из 4» выглядит оценкой, «ещё одна попытка» — счётом.
        var attemptsUntilVerdict: Int {
            SkillProgress.attemptsUntilVerdict(attempts: attempts)
        }
    }

    /// Сколько последних попыток берём в клетку. Десять — из подписи
    /// экрана («Удачных из 10 · последние попытки»), а не из головы.
    ///
    /// Окно обязательно: без него клетка помнит прошлогоднее, и
    /// собака, которая НАУЧИЛАСЬ, вечно висит с «учится», потому что
    /// в знаменателе двести попыток двухлетней давности.
    static let window = 10

    /// Посчитать клетки.
    ///
    /// **Пустые клетки не заводятся.** На экране «—» стоит там, где
    /// попыток не было, и это должно приходить из отсутствия клетки,
    /// а не из клетки с нулями: ноль из нуля и «не пробовали» —
    /// разные утверждения, и `SkillProgress.status` отвечает на них
    /// по-разному (`.notStarted` против деления на ноль).
    ///
    /// Группировка по `(place, memberID)` — и вот почему тут нет
    /// значения по умолчанию ни у одного из двух: **группировка по
    /// полю со значением по умолчанию собирает в одну группу всё, что
    /// это поле не заполнило.** 07.10 этот класс выстрелил у Togo пять
    /// раз за день, включая склейку собак по пустой кличке. Попытка
    /// без участника здесь не группируется в «ничьи», а отбрасывается
    /// явно — и это видно числом, см. `discarded`.
    static func cells(_ attempts: [Attempt], window: Int = window) -> [Cell] {
        var buckets: [Place: [UUID: [Attempt]]] = [:]
        for attempt in attempts {
            buckets[attempt.place, default: [:]][attempt.memberID, default: []].append(attempt)
        }
        var result: [Cell] = []
        for place in Place.allCases {
            guard let byMember = buckets[place] else { continue }
            for (memberID, list) in byMember {
                let recent = list.sorted { $0.date > $1.date }.prefix(window)
                guard !recent.isEmpty else { continue }
                result.append(Cell(place: place,
                                   memberID: memberID,
                                   successes: recent.filter(\.succeeded).count,
                                   attempts: recent.count))
            }
        }
        return result
    }

    /// Где отрабатывать: место с попытками, но без успеха.
    ///
    /// Отвечает на вопрос, ради которого матрица и существует.
    /// Возвращает **самое простое** из непройденных, а не самое
    /// трудное: учить начинают с того, что ближе к получающемуся,
    /// и порядок `Place.allCases` для этого и упорядочен.
    ///
    /// Пусто — значит либо везде получается, либо нигде не хватает
    /// попыток для вердикта. Это два разных ответа, и различать их
    /// должен тот, кто спрашивает: функция намеренно не склеивает их
    /// в «всё хорошо».
    static func nextPlaceToPractise(_ cells: [Cell]) -> Place? {
        // Разбито на два шага нарочно: одним выражением
        // `Place.allCases.first { cells.contains { … } }` компилятор
        // не укладывается в разумное время и просит разбить сам.
        var learning: Set<Place> = []
        for cell in cells where cell.status == .learning {
            learning.insert(cell.place)
        }
        return Place.allCases.first { learning.contains($0) }
    }

    /// Хватает ли матрице данных, чтобы её вообще показывать.
    ///
    /// Нужно экрану: таблица из четырнадцати «—» выглядит поломкой,
    /// а не пустым состоянием. Рядом с правилом «любой группе
    /// проверок нужна проверка, что ей было что проверять».
    static func hasAnythingToShow(_ cells: [Cell]) -> Bool {
        cells.contains { $0.attempts > 0 }
    }
}
