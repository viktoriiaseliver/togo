import Foundation

/// Дела «Анализ крови · N нед от начала» — заводятся вместе со схемой
/// и обязаны уходить вместе с ней.
///
/// **До 29.10.2026 они жили сами по себе** (аудит «Здоровья», решение
/// Виктории «да, всё исправь»):
///
/// ```
/// схему отменили / курс завершили   дела оставались и звали сдать кровь
///                                   по лечению, которого больше нет
/// схема удалена                     то же
/// начало схемы в прошлом            недели, которые уже прошли,
///                                   заводились задним числом —
///                                   «просроченное» дело в первый же день
/// ```
///
/// # Как дело узнаётся без связи в схеме
///
/// Связи «дело → схема» в модели нет, и заводить её — правка формы
/// хранилища. Дело узнаётся по тому, как его заводит `MedicationEditorSheet`:
/// медицинское, на дату, ещё не сделанное, заголовок — один из
/// `заголовки`, пояснение начинается с имени схемы. Граница названа:
/// дело, заведённое на другом языке интерфейса, по заголовку не узнается
/// и останется — это мягче, чем снять чужое дело.
nonisolated enum КонтрольКрови {

    /// Недели, на которые редактор вообще умеет заводить дела.
    static let недели = 1...12

    static func заголовок(недели n: Int) -> String {
        String(localized: "Анализ крови · \(n) нед от начала")
    }

    static var заголовки: Set<String> { Set(недели.map(заголовок)) }

    /// Неделя уже прошла — дело на неё не заводится.
    static func прошла(_ день: Date, now: Date, calendar: Calendar = .current) -> Bool {
        calendar.startOfDay(for: день) < calendar.startOfDay(for: now)
    }

    /// Дело ли это контроля крови этой схемы.
    static func относится(_ дело: CareTask, к схема: Medication, заголовки: Set<String>) -> Bool {
        guard дело.category == .medical, дело.kind == .dated,
              заголовки.contains(дело.title) else { return false }
        let имя = схема.name.trimmingCharacters(in: .whitespaces)
        return имя.isEmpty || дело.detail.hasPrefix(имя)
    }

    /// Снять будущие несделанные дела схемы надгробием в момент `момент`.
    ///
    /// Надгробие, а не `delete`: снятие обязано доехать до второго
    /// телефона (разбор у `Medication.deletedAt`), и по тому же моменту
    /// `вернуть` поднимает ровно эти дела, когда схему возвращают в строй.
    @discardableResult
    static func снять(для схема: Medication, в момент: Date) -> [CareTask] {
        guard let dog = схема.dog else { return [] }
        let заголовки = заголовки
        let снятые = dog.careTasks.filter { дело in
            относится(дело, к: схема, заголовки: заголовки)
                && дело.lastDone == nil
                && (дело.scheduledDate.map { !прошла($0, now: момент) } ?? false)
        }
        for дело in снятые {
            дело.deletedAt = момент
            дело.changedAt = момент
        }
        return снятые
    }

    /// Вернуть дела, снятые вместе со схемой в момент `момент`.
    static func вернуть(для схема: Medication, снятые момент: Date) {
        guard let dog = схема.dog else { return }
        let заголовки = заголовки
        for дело in dog.careTasksStorage ?? []
        where дело.deletedAt == момент && относится(дело, к: схема, заголовки: заголовки) {
            дело.deletedAt = nil
            дело.changedAt = Date()
        }
    }
}
