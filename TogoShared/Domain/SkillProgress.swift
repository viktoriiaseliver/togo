import Foundation

/// Когда навык процедуры считается получающимся.
///
/// **Заведено 28.09, потому что рычага не было вовсе.** `ProcedureSkill`
/// создавали, показывали и удаляли, а `attempts`, `successes`
/// и `statusRaw` не менял никто во всём дереве. Следствия человек видел
/// каждый раз: строка «N из M» не появлялась ни разу (`attempts > 0`
/// не бывало истинным), статус вечно «не начинали», а нажатие
/// на навык предлагало только удалить его.
///
/// Тот же класс, что три находки 02.09: механизм есть, рычага к нему
/// нет. Решение Виктории 28.09 — подключить запись попыток.
///
/// **Число взято у соседа, а не придумано.** У шага обучения
/// (`TrainingStep`) в проекте уже записано: «шаг закрыт, когда
/// получилось 4 раза из 5 в двух занятиях подряд». Здесь занятий нет,
/// есть попытки — поэтому те же четыре из пяти, но по счёту попыток.
/// Второе правило на ту же мысль расходится с первым на второй же
/// правке; у Togo это записано трижды.
nonisolated enum SkillProgress {

    /// Меньше этого числа попыток «получается» не говорим ни при каких
    /// успехах.
    ///
    /// Не строгость ради строгости: одна удачная попытка из одной даёт
    /// сто процентов, и приложение сказало бы «получается» про навык,
    /// который пробовали один раз. Это ровно то, за что вердикт
    /// «просится» молчит первые четыре дня, — утверждение из данных,
    /// которых нет.
    static let minimumAttempts = 5

    /// Доля успеха, при которой навык считается получающимся: 4 из 5.
    static let goodRatioNumerator = 4
    static let goodRatioDenominator = 5

    /// Статус по счёту. Чистая функция: её можно спросить из теста.
    static func status(successes: Int, attempts: Int) -> SkillStatus {
        guard attempts > 0 else { return .notStarted }
        guard attempts >= minimumAttempts else { return .learning }
        // Сравнение целыми, без деления: `Double` здесь дал бы
        // 0.7999999 на 4 из 5 при неудачном округлении.
        return successes * goodRatioDenominator >= attempts * goodRatioNumerator
            ? .works
            : .learning
    }

}
