import Foundation

/// Удалённая запись остаётся зачёркнутым следом до конца дня. Правило
/// нового дизайна, раздел «3 · Записи · дубль и след»
/// (`Togo ФИНАЛ v2`, окт 2026):
///
/// > Удалённая запись после тоста остаётся зачёркнутым следом
/// > до конца дня.
///
/// **Зачем след.** Тост «Отменить» живёт пять секунд, а вопрос «я же
/// отмечал еду, куда она делась» приходит через час. След отвечает
/// на него, не возвращая запись в счёт: в общем дневнике на семью
/// удалить может не тот, кто записывал, и молчаливое исчезновение
/// строки читается как сбой приложения.
///
/// **Три величины, которые нельзя путать, и у Togo для них три
/// разных окна.** Их свели бы в одно при первой же правке, поэтому
/// названы рядом:
///
///     DuplicateGuard        90 с   ЗАПРЕТ второй записи
///     .outing (замер 07.10) 10 с   тот же запрет, своё окно
///     Diary.mergeCandidates 20 мин ПРЕДЛОЖЕНИЕ слияния двум авторам
///     DeletedTrace          до конца дня   ПОКАЗ того, чего больше нет
///
/// Первые два не дают записать, третье спрашивает, четвёртое ничего
/// не решает — оно только помнит. Одинаковой формы у них нет ни у
/// одной, и общего числа тоже быть не должно.
nonisolated enum DeletedTrace {

    /// Что показывать на месте удалённой записи.
    enum Visibility: Sendable, Equatable {
        /// Строка видна зачёркнутой, в счёт дня не входит.
        case struckThrough
        /// Строки нет совсем.
        case gone
    }

    /// Виден ли след.
    ///
    /// «До конца дня» считается по календарю того, кто смотрит, —
    /// не по «двадцати четырём часам с удаления». Разница не
    /// умозрительная: запись, удалённая в 23:50, при счёте сутками
    /// висела бы зачёркнутой весь следующий день, то есть ровно тогда,
    /// когда человек её уже не ищет.
    ///
    /// Календарь приходит параметром, а не берётся `.current`:
    /// иначе тест зависел бы от часового пояса машины, а у нас уже
    /// был замер, где журнал в UTC, а дневник в местном, и первый
    /// проход дал ноль записей.
    static func visibility(deletedAt: Date,
                           now: Date = Date(),
                           calendar: Calendar = .current) -> Visibility {
        guard calendar.isDate(deletedAt, inSameDayAs: now) else { return .gone }
        // Удаление «в будущем» — это разъехавшиеся часы двух устройств
        // в общем дневнике, а не повод спрятать след.
        return .struckThrough
    }

    /// Момент, когда след пропадёт. Нужен тому, кто хочет перерисовать
    /// экран ровно тогда, а не опрашивать каждую минуту.
    ///
    /// Пусто, если след уже не виден: «когда исчезнет» у исчезнувшего
    /// не спрашивают, и `nil` здесь честнее любой даты в прошлом.
    static func disappearsAt(deletedAt: Date,
                             now: Date = Date(),
                             calendar: Calendar = .current) -> Date? {
        guard visibility(deletedAt: deletedAt, now: now, calendar: calendar) == .struckThrough
        else { return nil }
        return calendar.startOfDay(for: now).addingTimeInterval(24 * 3600)
    }

    /// Входит ли удалённая запись в счёт дня. Всегда нет — и это
    /// отдельная функция, а не комментарий, чтобы на неё можно было
    /// сослаться тестом.
    ///
    /// Без неё след однажды попадёт в сумму: строка на экране есть,
    /// значит её посчитают. Так уже было у Kvit — шапка говорила
    /// «0,00 € · 0 чеков», а строкой ниже лежали три чека, потому что
    /// сумма и лента брали разное.
    static var countsTowardDayTotals: Bool { false }
}
