import Foundation

/// Часы от приёма дозы до забора — и почему без них результат не число.
/// Медицинский слой, `docs/ТЗ-медицинский-слой.md` §2.1, §3.2, §3.3.
///
/// Главный довод ТЗ, и он из настоящей карты Стича:
///
/// ```
/// 07.09.2025  Т4 10,3  забор +11,5 ч  доза 100 мкг/сут   провал
/// 07.09.2025  Т4 16,7  забор  +3,5 ч  доза 100 мкг/сут   то же число, другой смысл
/// ```
///
/// Один день, одна доза, два забора — и выводы противоположные.
/// Врач написала буквально: «в направлении обязательно указать
/// „левотироксин принят … часов назад“». Без этого числа результат
/// **не интерпретируется**.
///
/// Отсюда устройство, и оно всё про отказ притворяться:
///
/// > Если человек пропустил время забора, результат помечается «время
/// > не указано» и на графике стоит пустым кружком, **а не притворяется
/// > сравнимым**.
nonisolated enum LabSampleTiming {

    /// Что известно о времени забора.
    enum Timing: Sendable, Equatable {
        /// Известно: столько часов прошло от приёма дозы до забора.
        case hoursSinceDose(Double)
        /// Лечения нет — вопрос не задавался и не должен задаваться.
        /// Это НЕ пропуск: у здоровой собаки часам неоткуда взяться.
        case noTreatment
        /// Лечение есть, а время не указали. Единственный случай,
        /// который обязан быть виден на графике отдельно.
        case unknownDuringTreatment
    }

    /// Посчитать. Чистая функция: расписание приходит датой последней
    /// дозы, а не хранилищем.
    ///
    /// Доза «после забора» — не ошибка ввода, а разъехавшиеся часы или
    /// доза, данная позже; часы тогда неизвестны, и говорить «минус
    /// два» нельзя: отрицательное число на подписи точки прочтут как
    /// опечатку, а не как «неизвестно».
    static func timing(sampledAt: Date?,
                       lastDoseAt: Date?,
                       hasActiveTreatment: Bool) -> Timing {
        guard hasActiveTreatment else { return .noTreatment }
        guard let sampledAt, let lastDoseAt else { return .unknownDuringTreatment }
        let hours = sampledAt.timeIntervalSince(lastDoseAt) / 3600
        guard hours >= 0 else { return .unknownDuringTreatment }
        return .hoursSinceDose(hours)
    }

    /// Можно ли сравнивать два результата между собой.
    ///
    /// **Это и есть главная функция файла.** ТЗ: «точки с разным
    /// временем забора различимы на вид: иначе человек сравнит
    /// несравнимое, что и произошло в карте дважды».
    ///
    /// Порог взят из той же карты: 3,5 ч против 11,5 ч дали
    /// противоположные выводы при одной дозе. Три часа — половина
    /// меньшего из двух наблюдённых интервалов; шире него число
    /// не обосновано, и так и записано.
    static let comparableSpreadHours: Double = 3

    /// Сравнимы ли. `false` не значит «ошибка» — значит «рядом эти две
    /// точки ставить нельзя без оговорки».
    static func comparable(_ first: Timing, _ second: Timing) -> Bool {
        switch (first, second) {
        case (.hoursSinceDose(let a), .hoursSinceDose(let b)):
            return abs(a - b) <= comparableSpreadHours
        case (.noTreatment, .noTreatment):
            // Без лечения время забора ни на что не влияет.
            return true
        default:
            // Любая пара с «не указано» несравнима, и пара
            // «лечение / без лечения» тоже: это разные режимы.
            return false
        }
    }

    /// Подпись у точки. Словом, а не только видом точки, — ТЗ §3.2
    /// требует этого ради VoiceOver и дальтоника.
    static func caption(_ timing: Timing) -> String? {
        switch timing {
        case .hoursSinceDose(let hours):
            // Полчаса — наименьшая осмысленная единица: в карте есть
            // «+3,5 ч» и «+11,5 ч». Формат берётся у домашнего
            // помощника, а не собирается здесь: иначе вторая
            // поверхность напишет часы по-своему.
            let rounded = (hours * 2).rounded() / 2
            return String(localized: "забор через \(Fmt.hoursMinutes(rounded * 3600)) после дозы")
        case .noTreatment:
            return nil
        case .unknownDuringTreatment:
            return String(localized: "время забора не указано")
        }
    }

    /// То же, но БЕЗ округления до получаса — для экрана ввода.
    ///
    /// **Повод измерен 08.10.2026 кадром, снятым не автором.** На шаге
    /// ввода анализа рядом стоят два числа:
    ///
    /// ```
    /// время забора   19:38   (точно, до минуты — его ввёл человек)
    /// caption        «забор через 11 ч 30 мин после дозы»
    /// арифметика     11 ч 38 мин
    /// ```
    ///
    /// Оба верны по отдельности: `caption` округляет нарочно, полчаса —
    /// наименьшая осмысленная единица для графика и списка. Но **человек,
    /// который сложит два числа с одной карточки, получит разницу
    /// в восемь минут** и не поймёт, которому верить.
    ///
    /// > **Округление, уместное в показе итога, становится ошибкой рядом
    /// > с точным слагаемым.** Дефект не в округлении и не во времени —
    /// > он в том, что их поставили рядом.
    ///
    /// И цена названа тем же кадром: протокол контроля говорит ОКНАМИ
    /// («забор в окне 4–6 ч»), а округление вниз двигает пробу через край
    /// окна. На вводе, где человек ещё может поправить время, точность
    /// дороже краткости.
    ///
    /// Формат по-прежнему берётся у `Fmt`, а не собирается на месте:
    /// иначе вторая поверхность напишет часы по-своему. Две функции
    /// здесь — это два РЕШЕНИЯ о точности в одном файле, а не две копии
    /// формата в разных.
    static func captionExact(_ timing: Timing) -> String? {
        switch timing {
        case .hoursSinceDose(let hours):
            return String(localized: "забор через \(Fmt.hoursMinutes(hours * 3600)) после дозы")
        case .noTreatment:
            return nil
        case .unknownDuringTreatment:
            return String(localized: "время забора не указано")
        }
    }

    /// Можно ли рисовать график.
    ///
    /// ТЗ: «при одном анализе график **не рисуется**: показываем строку
    /// и объясняем, что сравнивать не с чем. Один результат на графике
    /// выглядит как тренд».
    ///
    /// Рядом с нашим правилом «любой группе проверок нужна проверка,
    /// что ей было что проверять»: у графика это проверка, что ему было
    /// что рисовать.
    static func chartMakesSense(resultCount: Int) -> Bool {
        resultCount >= 2
    }
}
