import Foundation
import SwiftData

/// Повторяющееся дело: когти, вычёсывание, антипаразитарка, прививка, взвешивание.
/// Всё это собирается в одну утреннюю сводку, а не в восемь отдельных напоминаний.
@Model
final class CareTask {
    var id: UUID = UUID()
    var title: String = ""
    var detail: String = ""
    var kindRaw: String = CareKind.periodic.rawValue
    var categoryRaw: String = CareCategory.grooming.rawValue

    // MARK: Прививка — шаг 0 медицинского слоя, 07.10.2026
    //
    // **Повод назван днём, а не вероятностью:** у Стича срок бешенства
    // истёк 03.10.2026, и напомнить об этом приложение не могло —
    // «годен до» ему было негде хранить. Все три поля есть в карте
    // у каждой прививки (§2.5 ТЗ), то есть это не запас на будущее.
    //
    // Опциональные, потому что у дел ухода, которые не прививки,
    // их не бывает, и подставлять им что-либо значило бы печатать
    // человеку срок, которого он не вводил.

    /// Номер партии с наклейки: «Nobivac Rabies L12345».
    var vaccineBatch: String?

    /// «Годна до» — дата, от которой считается напоминание.
    ///
    /// Отличается от `scheduledDate` («когда следующая») тем, что это
    /// факт с наклейки, а не наш расчёт. Путать их нельзя: расчёт
    /// меняется от интервала, факт — нет.
    var vaccineValidUntil: Date?

    /// Где делали. Связь со справочником, а не строка: иначе
    /// одиннадцать организаций карты рассыплются на столько групп,
    /// сколько было опечаток.
    var clinic: Clinic?

    /// Для регулярного: раз в сколько дней.
    var intervalDays: Int = 30
    /// Для «по дате»: когда именно и за сколько дней предупредить.
    var scheduledDate: Date?
    var remindDaysBefore: Int = 14

    var lastDone: Date?
    /// Для ежедневного: сколько дней подряд делали. Не награда, а зеркало.
    var streak: Int = 0

    /// Сезонное само знает про сезон: капли от клещей молчат зимой.
    var seasonStartMonth: Int?
    var seasonEndMonth: Int?

    /// Отложенное дважды подсвечивается в сводке, но не переходит в тревогу.
    var snoozeCount: Int = 0

    /// Когда этот телефон в последний раз трогал дело ухода.
    /// Расписание ездит в общем дневнике с 23.09.2026: без него «план
    /// дня» у гостя пуст, и приглашение приводит в комнату без дел.
    var changedAt: Date = Date()

    /// Надгробие удаления — разбор у `Medication.deletedAt`.
    /// Ставить только через `ОбщееУдаление`.
    var deletedAt: Date?

    var dog: Dog?

    init(
        title: String,
        detail: String,
        kind: CareKind = .periodic,
        intervalDays: Int = 30,
        category: CareCategory = .grooming,
        lastDone: Date? = nil,
        scheduledDate: Date? = nil
    ) {
        self.title = title
        self.detail = detail
        self.kindRaw = kind.rawValue
        self.intervalDays = intervalDays
        self.categoryRaw = category.rawValue
        self.lastDone = lastDone
        self.scheduledDate = scheduledDate
    }

    var kind: CareKind {
        get { CareKind(rawValue: kindRaw) ?? .periodic }
        set { kindRaw = newValue.rawValue }
    }

    var category: CareCategory {
        get { CareCategory(rawValue: categoryRaw) ?? .grooming }
        set { categoryRaw = newValue.rawValue }
    }

    // MARK: Когда

    /// Даты нет: для регулярного не знаем, когда делали, для «по дате»
    /// не назначен день. Это не просрочка — но и не молчание навсегда:
    /// такое дело видно в отдельной группе и просит поставить дату.
    ///
    /// Раньше здесь была дыра: дело без даты никогда не становилось сроком,
    /// то есть заведённое напоминание не напоминало вообще ни о чём.
    var needsDate: Bool {
        switch kind {
        case .daily: false
        case .periodic: lastDone == nil
        case .dated: scheduledDate == nil
        }
    }

    var isNeverDone: Bool { needsDate }

    var dueDate: Date? {
        switch kind {
        case .daily:
            return Calendar.current.startOfDay(for: .now)
        case .periodic:
            guard let lastDone else { return nil }
            return Calendar.current.date(byAdding: .day, value: intervalDays, to: lastDone)
        case .dated:
            return scheduledDate
        }
    }

    func daysUntilDue(from date: Date = Date()) -> Int? {
        guard let dueDate else { return nil }
        let calendar = Calendar.current
        return calendar.dateComponents([.day],
                                       from: calendar.startOfDay(for: date),
                                       to: calendar.startOfDay(for: dueDate)).day
    }

    func isDoneToday(on date: Date = Date()) -> Bool {
        guard let lastDone else { return false }
        return Calendar.current.isDate(lastDone, inSameDayAs: date)
    }

    func isInSeason(on date: Date = Date()) -> Bool {
        guard let start = seasonStartMonth, let end = seasonEndMonth else { return true }
        let month = Calendar.current.component(.month, from: date)
        return start <= end ? (month >= start && month <= end) : (month >= start || month <= end)
    }

    /// Просится ли на главный экран прямо сейчас.
    func isDue(on date: Date = Date()) -> Bool {
        guard isInSeason(on: date) else { return false }
        switch kind {
        case .daily:
            return !isDoneToday(on: date)
        case .periodic:
            guard let days = daysUntilDue(from: date) else { return false }
            return days <= 0
        case .dated:
            guard let days = daysUntilDue(from: date) else { return false }
            return days <= remindDaysBefore
        }
    }

    /// Просрочено по-настоящему — это только про даты и регулярное.
    /// У ежедневного просрочки нет: пропущенный день не долг.
    func isOverdue(on date: Date = Date()) -> Bool {
        guard kind != .daily, isInSeason(on: date), let days = daysUntilDue(from: date) else { return false }
        return days < 0
    }

    /// Что написать в строке справа. Одна фраза на все три сорта ухода.
    func statusText(on date: Date = Date()) -> String {
        guard isInSeason(on: date) else { return String(localized: "вне сезона") }
        switch kind {
        case .daily:
            if isDoneToday(on: date) { return streak > 1 ? String(localized: "\(Fmt.days(streak)) подряд") : String(localized: "сегодня сделали") }
            return streak > 1 ? String(localized: "серия \(Fmt.days(streak))") : String(localized: "сегодня")
        case .periodic:
            guard let days = daysUntilDue(from: date) else { return String(localized: "когда делали?") }
            if days < 0 { return String(localized: "просрочено на \(Fmt.days(-days))") }
            if days == 0 { return String(localized: "сегодня") }
            if days == 1 { return String(localized: "завтра") }
            return String(localized: "через \(Fmt.days(days))")
        case .dated:
            guard let days = daysUntilDue(from: date) else { return String(localized: "когда делали?") }
            if days < 0 { return String(localized: "просрочено") }
            if days == 0 { return String(localized: "сегодня") }
            return Fmt.shortDay(dueDate ?? date)
        }
    }

    /// Отметить сделанным. Для ежедневного ведёт серию, для «по дате»
    /// двигает дату на следующий раз.
    func markDone(at date: Date = Date()) {
        if kind == .daily {
            let calendar = Calendar.current
            if let lastDone, let yesterday = calendar.date(byAdding: .day, value: -1, to: date),
               calendar.isDate(lastDone, inSameDayAs: yesterday) {
                streak += 1
            } else if !isDoneToday(on: date) {
                streak = 1
            }
        }
        if kind == .dated, let scheduled = scheduledDate, intervalDays > 0 {
            scheduledDate = Calendar.current.date(byAdding: .day, value: intervalDays, to: scheduled)
        }
        lastDone = date
        snoozeCount = 0
    }

    /// Отменить отметку.
    ///
    /// Отметили не то — обычное дело: сработал свайп, зубы почистил
    /// кто-то другой, прививку перенесли. Без отката отметка о прививке
    /// сдвигала дату на год вперёд, и вернуть её было нельзя ничем,
    /// кроме как завести напоминание заново.
    func undoDone(previousDone: Date?) {
        if kind == .dated, let scheduled = scheduledDate, intervalDays > 0 {
            scheduledDate = Calendar.current.date(byAdding: .day, value: -intervalDays,
                                                  to: scheduled)
        }
        if kind == .daily {
            streak = max(0, streak - 1)
        }
        lastDone = previousDone
    }
}

/// Схему лечения меняет только владелец. Остальные видят и исполняют.
@Model
final class Medication {
    var id: UUID = UUID()
    var name: String = ""
    var doseText: String = ""
    /// Минуты от полуночи.
    var times: [Int] = []

    /// Расписание с количеством на каждое время.
    ///
    /// **Почему слотом, а не вторым массивом рядом с `times`.** Экран
    /// запаса показывает «½ утром, 1 вечером» — то есть количество
    /// привязано к часу, а не к препарату. Два параллельных массива
    /// («времена» и «количества») разъезжаются длинами молча, и тогда
    /// половина таблетки приземляется на чужой час. У слота
    /// разъезжаться нечем: час и количество лежат в одной записи.
    ///
    /// Пусто — значит расписание ведётся прежним способом, по `times`
    /// с количеством 1. Читать это поле напрямую не надо: `schedule`
    /// ниже отвечает за обе формы сразу.
    var doseSlotsData: [DoseSlot] = []

    /// Таблетки, миллилитры или «доза» без единицы.
    ///
    /// Капли считаются в мл и списываются дробно; таблетки бывают
    /// половинками. Без единицы «осталось 7» ничего не значит:
    /// семь таблеток — это неделя, семь миллилитров — один приём.
    var unitRaw: String = MedUnit.tab.rawValue

    /// Сколько ВЕЩЕСТВА в одной единице формы — **в микрограммах**.
    ///
    /// Заведено 08.10.2026 решением Виктории («А: завести числовую дозу
    /// в мкг/мг») по замеру: массы в модели не было ни в одном поле.
    /// `doseText` — свободная строка («½ таблетки», «0,1 мг»),
    /// `dailyUse` — счёт единиц формы, `MedUnit` знает только
    /// `tab`/`ml`/`dose`.
    ///
    /// **Зачем поле, если есть `doseText`.** График Т4 существует ради
    /// вопроса «почему Т4 не растёт при росте дозы», а счёт таблеток
    /// на него отвечает неверно: врач меняет силу таблетки с 0,05
    /// на 0,1 мг, счёт остаётся «2», и столбик не шевельнётся,
    /// пока доза выросла вдвое.
    ///
    /// > **Величина, верная сама по себе, рядом с другой начинает
    /// > отвечать на вопрос, которого ей не задавали:** «сколько
    /// > таблеток» встаёт на место «сколько вещества».
    ///
    /// ## Почему ОДНА единица хранения, а не пара «число + единица»
    ///
    /// Хранится всегда в микрограммах, и единицы рядом НЕТ намеренно.
    /// Пара «значение + единица» позволяет сложить `0,1 мг` с `50 мкг`
    /// и получить `50,1` — между мг и мкг множитель тысяча, и ошибка
    /// в нём даёт не кривой график, а неверную дозу на медицинском
    /// экране.
    ///
    /// > **Невозможность надёжнее дисциплины.** Одна единица хранения
    /// > делает ошибку перевода не «редкой», а несуществующей:
    /// > переводить нечего, потому что выбора нет.
    ///
    /// Перевод случается РОВНО ОДИН РАЗ — на вводе, где человек выбрал
    /// «мг» или «мкг». Показ собирается `Fmt.doseMass` там же, где
    /// живёт это поле.
    ///
    /// ## Почему на ЕДИНИЦУ ФОРМЫ, а не на приём и не на сутки
    ///
    /// `DoseSlot.quantity` считает единицы формы и умеет половинки
    /// («½ таблетки»). Положи массу «на приём» — и половинка таблетки
    /// перестанет считаться; положи «на сутки» — и смена расписания
    /// молча испортит массу. На единицу формы оба случая считаются
    /// умножением, и `dailyUse` остаётся единственным хозяином
    /// расписания.
    ///
    /// Пусто — значит **не введено**, и это не ноль: ноль был бы
    /// настоящей дозой «ничего». Поэтому `Double?`, а не `Double`.
    var massPerUnitMcg: Double?

    /// Окно натощак после дозы: еда внутри него мешает всасыванию.
    var fastingMinutes: Int = 0

    /// Окно натощак ПЕРЕД дозой: к приёму желудок должен быть пустым.
    ///
    /// Половина правила, которой в модели не было. «Натощак» — это
    /// про пустой желудок, а пустым он бывает ДО таблетки, не после.
    /// Схема «покормили в 20:55, таблетка в 21:00» проходила прежнюю
    /// проверку целиком: окно после дозы соблюдено, а сама доза выпита
    /// на полный желудок.
    var fastingBeforeMinutes: Int = 0

    /// Сколько нельзя кормить перед дозой на самом деле.
    ///
    /// **Ноль у старой схемы читается как «столько же, сколько после»,
    /// и это исправление, а не догадка.** Натощак без окна «до» не
    /// бывает: доза сразу после еды не натощак по определению. Схемы,
    /// заведённые до появления поля, физически не могли его заполнить,
    /// и отдавать по ним «кормить можно» значило бы отвечать неверно
    /// там, где ответ известен.
    ///
    /// Явный ноль поставить всё же можно — через `fastingBeforeMinutes`
    /// у схемы, у которой `fastingMinutes` тоже ноль: тогда лекарство
    /// не натощак вовсе, и запирать нечего.
    var fastingBefore: Int { fastingBeforeMinutes > 0 ? fastingBeforeMinutes : fastingMinutes }

    /// Доза с условием: открывается через N минут после еды.
    ///
    /// Инсулин колют не по часам, а после того, как собака поела —
    /// иначе сахар падает в пустой желудок. Такая доза стоит в плане дня
    /// замком: отметить её раньше нельзя, а таймер стартует сам от
    /// отметки еды. Не поела — укол не открывается вовсе, и это не сбой,
    /// а вопрос к врачу.
    ///
    /// Ноль — обычная доза по часам.
    var minutesAfterMeal: Int = 0

    /// Есть ли у дозы условие по еде.
    var dependsOnMeal: Bool { minutesAfterMeal > 0 }
    var isPaused: Bool = false

    /// Сколько таблеток осталось и сколько было в пачке.
    ///
    /// Дыра, которой не было в списке: пропуски чаще случаются не
    /// из забывчивости, а потому что таблетки кончились в пятницу
    /// вечером. Счёт живёт на отметках приёма — отдельного учёта вести
    /// не надо, минус одна с каждой отметкой.
    ///
    /// Ноль в `stockTotal` значит «не считаем»: навязывать учёт тому,
    /// кто покупает по коробке в год, незачем.
    var stockLeft: Int = 0
    var stockTotal: Int = 0

    /// Тот же запас дробно: половинки таблеток и миллилитры.
    ///
    /// **Почему новое поле, а не смена типа у `stockLeft`.** Int → Double
    /// — это смена типа под уже отгруженной формой, а `.lightweight`
    /// выводит добавление поля и не выводит превращение. Шесть розданных
    /// сборок несут `stockLeft: Int`; сменить ему тип значило бы увести
    /// их хранилище в память молча.
    ///
    /// `nil` — значит дробный учёт этому препарату не заводили, и правду
    /// говорит целый `stockLeft`. Читать надо `remaining` и `packSize`
    /// ниже: они отвечают за обе формы, как `fastingBefore` отвечает
    /// за окно натощак у схем до и после появления поля.
    var stockLeftAmount: Double?
    var packAmount: Double?

    /// Курс до какого числа. `nil` — курс бессрочный.
    ///
    /// **Поле, которого не хватало уже написанному коду, а не новая
    /// функция.** `PillSupply.shortfallDays` считает нехватку на курс
    /// и покрыт тестами, но тесты передают дату курса сами, аргументом,
    /// — а экран передать её не может: в модели её нет. Значит строка
    /// «курс идёт до такого-то, не хватит столько-то» не показывалась
    /// никому ни разу. Замер togo-9e, 05.10.2026.
    var courseEnd: Date?

    /// Годен до — с упаковки. Месяц и год; день в сроке годности
    /// лекарств не печатают, поэтому здесь конец месяца.
    var expiry: Date?

    /// Когда вскрыли флакон. `nil` — ещё не вскрыт.
    ///
    /// **Это НЕ срок годности, и путать их нельзя.** У капель после
    /// вскрытия свой срок, обычно короче остатка годности, и шторка
    /// «Купил» переключает одно в другое тумблером «Сразу вскрыл».
    /// Одним полем разница потерялась бы молча — и проявилась бы
    /// у человека с открытым флаконом, то есть там, где цена ошибки
    /// измеряется дозой.
    var openedAt: Date?

    /// Сколько дней годен после вскрытия. Ноль — срок после вскрытия
    /// не задан, и тогда действует только `expiry`.
    var shelfAfterOpenDays: Int = 0

    /// Напоминать о покупке за месяц до конца срока годности.
    var remindBeforeExpiry: Bool = false

    /// Можно ли дать этот препарат на улице.
    ///
    /// Нужно не «Запасу», а прогулке: в шторке «Просится» и в режиме
    /// «На улице» появляется строка «Дал», если доза попадает в ±30 минут
    /// от выхода. Таблетку натощак на улице не дают, капли в глаз — дают.
    var canGiveOutside: Bool = false

    /// Номер назначения: «№ 8935331».
    ///
    /// Шаг 0 медицинского слоя. Связь со назначением (`Prescription`)
    /// появится на шаге 1; пока это номер строкой — ровно то, что
    /// человек видит на бланке и чем назначение опознаётся в клинике.
    ///
    /// Строкой, а не числом: в карте встречаются «№ 32063» и
    /// «№ 07350» — ведущий ноль значащий, и числом он потерялся бы.
    var prescriptionNumber: String?

    var prescriber: String?
    /// С какого дня идёт схема. **Необязательно, и это не «сегодня».**
    ///
    /// Просьба Виктории 28.10.2026: схему часто заводят в приложении
    /// позже, чем начали давать, — и тогда «сегодня» было бы утверждением
    /// приложения о мире. Пустое значит «не названо»: тогда за начало
    /// берётся первая доза в журнале (`началоСхемы`), как и до V8.
    ///
    /// От этой даты считаются контрольные анализы через N недель
    /// и то, какая схема шла в день забора (график показателя).
    var startedAt: Date?
    var cancelledAt: Date?
    var cancelledNote: String?

    /// Когда этот телефон в последний раз трогал схему.
    /// Схемы ездят с 23.09.2026: дозы ездили и раньше, а препарат,
    /// к которому они относятся, — нет, и у гостя приёмы были
    /// без названия.
    var changedAt: Date = Date()

    /// Надгробие: когда запись удалили. `nil` — запись жива.
    ///
    /// # Зачем надгробие вместо `context.delete` — замер 15.10.2026
    ///
    /// До 26.10.2026 надгробие было только у `LogEvent`. У остальных
    /// одиннадцати типов общего дневника удаление было жёстким, и
    /// **до второго человека не доезжало вовсе**: исходящая очередь
    /// собирается из уведомления `ModelContext.didSave`, а удалённая
    /// запись не приходит ни в `inserted`, ни в `updated` — её больше
    /// нет, и собрать по ней `CKRecord` неоткуда.
    ///
    /// Самый дорогой случай — этот тип, и он не придуман:
    ///
    /// > Виктория отменила схему лечения, у мамы она жива, мама даёт
    /// > препарат и получает напоминания о дозах.
    ///
    /// Проект мерит дозы правилом «не дать отменённую таблетку
    /// безопаснее, чем дать» (`SharedDiaryMerge.resolve(local:remote:)`
    /// для схемы, `isPaused = local || remote`). Здесь это правило было
    /// нарушено **в точности наоборот**: отмену у себя мы исполняли,
    /// а второму человеку не сообщали.
    ///
    /// # Чем надгробие отличается от отмены схемы
    ///
    /// `cancelledAt` — решение врача: курс отменён, препарат остался
    /// в карте. `deletedAt` — решение человека о ЗАПИСИ: схемы не было
    /// вовсе, завели по ошибке. Первое показывают, второе скрывают,
    /// и склеить их значило бы потерять разницу между «отменено»
    /// и «удалено» у того, кто даёт таблетки.
    ///
    /// # Почему удаление едет обычной правкой, а не `.deleteRecord`
    ///
    /// Надгробие — поле, то есть мягкое удаление приезжает в `didSave`
    /// ключом `"updated"`, который очередь уже читает: **правки
    /// в сборщике очереди не нужно вовсе.** Плюс спор: удаление
    /// сильнее правки (`SharedDiaryMerge`), а удалённая на сервере
    /// запись вернулась бы от второго телефона первой же его правкой.
    ///
    /// Ставится и читается в одном месте — `ОбщееУдаление`
    /// (`TogoShared/Sync/ОбщееУдаление.swift`). Руками здесь не
    /// присваивать: пара «надгробие + `changedAt`» половиной
    /// не работает, а половина пары опаснее целой.
    ///
    /// **Работает только вперёд.** Что удалено до 26.10.2026, у второго
    /// человека останется: надгробия на эти записи не ставил никто.
    var deletedAt: Date?

    var dog: Dog?

    @Relationship(deleteRule: .cascade, inverse: \DoseRecord.medication)
    var dosesStorage: [DoseRecord]?

    init(name: String, doseText: String, times: [Int], fastingMinutes: Int = 0) {
        self.name = name
        self.doseText = doseText
        self.times = times
        self.fastingMinutes = fastingMinutes
    }

    // CloudKit требует опциональных связей — см. пояснение в Dog.
    /// Отметки приёма.
    ///
    /// **Фильтра надгробий здесь НЕТ, и это не забывчивость — это пара,
    /// вторая половина которой заперта чужой работой** (26.10.2026).
    ///
    /// Это самое нагруженное узкое место из четырнадцати: через него
    /// идёт вся арифметика доз — `DoseScheduler`, `ReminderScheduler`,
    /// `FeedingGate`, `TreatmentCourse`, `WalkDose`, `AlarmThreshold`,
    /// `ScheduleChange`, `VetSummary` и семь экранов, около двадцати
    /// четырёх читателей. Поставить фильтр **нельзя в одиночку**:
    /// `DoseScheduler.removeOrphans` обязано видеть удалённое, иначе
    /// невидимая сирота останется в базе навсегда — её не найдёт
    /// ни один читатель, то есть убрать её будет уже нечем.
    /// `DoseScheduler.swift` в этот час держит другая сессия,
    /// и поимённый коммит взял бы её незакоммиченную работу.
    ///
    /// **Цена задержки сегодня НУЛЕВАЯ, и это замерено, а не принято
    /// на веру:** надгробие дозе не ставит никто. `ОбщееУдаление
    /// .удалить(_: DoseRecord)` вызовов не имеет, а пересчёт расписания
    /// (`DoseScheduler`, `ScheduleChange`) ставить его не должен
    /// по решению — пересчёт у каждого телефона свой, и надгробие
    /// от одного погасило бы дозу у второго. То есть фильтровать пока
    /// нечего, и поставленный в одиночку фильтр был бы чистым риском
    /// без выигрыша.
    ///
    /// Класть обе половины одним коммитом, когда файл освободится.
    var doses: [DoseRecord] { dosesStorage ?? [] }

    /// Отменить схему — **единственный путь**, которым это делается.
    ///
    /// # Почему метод, а не два присваивания на месте
    ///
    /// Вся уборка напоминаний смотрит на `isPaused`, а `cancelledAt`
    /// схемы не спрашивает **нигде** — ни `ReminderScheduler:167`,
    /// ни `:240`, ни `DoseRecord.ждётОтметкиСУчётомСхемы`.
    ///
    /// > Отмена, поставившая только `cancelledAt`, не погасила бы
    /// > напоминания **ни у кого, включая хозяйку**: человек получал бы
    /// > «Через 10 минут доза» по лечению, которого больше нет.
    ///
    /// Сторож на это есть (`ОтменаСтавитОбаПоляTests`), и он остаётся.
    /// Но **сторож — страховка, а метод — починка**: мимо метода
    /// неверный путь не выражается вовсе. Отмена по одной схеме сейчас
    /// в работе, и кнопка, которой ещё нет, попадёт в верный путь сама.
    ///
    /// # Заметка ставится только в пустую
    ///
    /// «Курс завершён» не должно затирать причину, написанную врачом
    /// или человеком, — поведение то же, что было в `TreatmentCourse`,
    /// перенесено без изменения.
    func отменить(в момент: Date = Date(), заметка: String? = nil) {
        cancelledAt = момент
        isPaused = true
        if let заметка, cancelledNote?.isEmpty ?? true {
            cancelledNote = заметка
        }
    }

    /// Вернуть схему в строй — парный путь к `отменить(в:заметка:)`.
    ///
    /// Пара нужна по той же причине, что и сам метод: возврат, снявший
    /// `cancelledAt` и забывший `isPaused`, оставил бы схему **молча
    /// немой** — она числилась бы живой, а напоминаний по ней не было бы,
    /// потому что уборка смотрит на паузу. Снаружи это неотличимо
    /// от «лечение идёт, а приложение молчит».
    ///
    /// Отмена решения обязана быть такой же дешёвой, как решение: без
    /// этого «Курс завершён» становится кнопкой, которую боятся нажать.
    func вернутьВСтрой() {
        cancelledAt = nil
        cancelledNote = nil
        isPaused = false
    }

    var scheduleSummary: String {
        let clock = times.sorted().map { String(format: "%02d:%02d", $0 / 60, $0 % 60) }.joined(separator: String(localized: " и "))
        return fastingMinutes > 0 ? String(localized: "\(clock) · натощак \(fastingMinutes) мин") : clock
    }

    var unit: MedUnit {
        get { MedUnit(rawValue: unitRaw) ?? .tab }
        set { unitRaw = newValue.rawValue }
    }

    /// Расписание в одной форме — безразлично, как оно записано.
    ///
    /// Схемы, заведённые до появления слотов, физически не могли их
    /// заполнить: у них есть только `times`, и количество там одно
    /// на каждый час. Отдавать по ним пустое расписание значило бы
    /// сказать «доз нет» там, где они есть, — то же, чем был опасен
    /// ноль у окна натощак.
    var schedule: [DoseSlot] {
        doseSlotsData.isEmpty
            ? times.sorted().map { DoseSlot(minuteOfDay: $0, quantity: 1) }
            : doseSlotsData.sorted { $0.minuteOfDay < $1.minuteOfDay }
    }

    /// Сколько осталось — дробно, если дробный учёт заведён.
    var remaining: Double { stockLeftAmount ?? Double(stockLeft) }

    /// Сколько в упаковке или флаконе — дробно, если заведено.
    var packSize: Double { packAmount ?? Double(stockTotal) }

    /// Сколько уходит в день по расписанию.
    var dailyUse: Double { schedule.map(\.quantity).reduce(0, +) }

    /// Доза в сутки, микрограммы. `nil`, пока масса не введена —
    /// и это ОТВЕТ «не знаем», а не ноль.
    ///
    /// Считается здесь, а не на экране: иначе вторая поверхность
    /// умножит по-своему. У Togo это уже было — виджет считал окно
    /// «не кормить» собственной арифметикой и расходился с главным
    /// экраном.
    var dailyMassMcg: Double? {
        guard let masse = massPerUnitMcg, masse > 0 else { return nil }
        let вСутки = dailyUse
        guard вСутки > 0 else { return nil }
        return masse * вСутки
    }

    /// Поставить остаток — обе формы разом.
    ///
    /// **Почему методом в модели, а не строкой на экране.** Запас
    /// хранится в двух полях: целое `stockLeft` для розданных сборок
    /// и дробное `stockLeftAmount` для половинок и миллилитров. Читается
    /// он через `remaining`, то есть **из дробного, когда оно есть**.
    /// Значит писатель, тронувший только `stockLeft`, нажимается
    /// и не меняет ничего: человек жмёт «+ 30 шт», видит прежнее число
    /// и жмёт снова.
    ///
    /// Поймал togo-9e на кнопке «+ 30 шт» 05.10.2026, починил на экране
    /// — и сказал вслух, что писателей будет больше одного: шторка
    /// «Купил» с кадра 33 пополняет запас у всей семьи. Правило,
    /// живущее на одной поверхности из двух, у нас уже стоило дня
    /// трижды, поэтому оно здесь, а не там.
    ///
    /// Целое поле получает **пол** от дробного: половина таблетки,
    /// невидимая старой сборке, лучше неверной целой.
    /// Возвращает прежний остаток — чтобы вызывающий мог его вернуть.
    ///
    /// **Откат обязан быть дробным.** У `DoseScheduler.markGiven` откат
    /// снимается до списания и возвращается, если сохранение не прошло:
    /// там `try?` стоил бы второй дозы. Целочисленный снимок вернул бы
    /// не то, что было, — и ошибка легла бы на запас лекарства.
    /// Замечание togo-9e, 05.10.2026, до коммита.
    @discardableResult
    func setStock(_ сколько: Double) -> Double {
        let прежний = remaining
        let итог = max(0, сколько)
        stockLeftAmount = итог
        stockLeft = Int(итог.rounded(.down))
        return прежний
    }

    /// Пополнить запас на столько-то — для кнопки «Купил».
    @discardableResult
    func addStock(_ сколько: Double) -> Double { setStock(remaining + сколько) }

    /// Списать дозу — ровно столько, сколько стоит в слоте.
    ///
    /// Половина таблетки списывает 0,5, а не одну: иначе запас
    /// кончается на бумаге вдвое раньше, человек покупает лишнее
    /// и перестаёт верить числу.
    @discardableResult
    func takeDose(_ сколько: Double) -> Double { setStock(remaining - сколько) }

    /// Вернуть дозу в пачку — отметку сняли.
    ///
    /// Потолок берётся у `packSize`, а не у `stockTotal`: у препарата
    /// с дробным учётом целое поле мёртво, и потолок пришёл бы не оттуда.
    @discardableResult
    func returnDose(_ сколько: Double) -> Double {
        let потолок = packSize > 0 ? packSize : .greatestFiniteMagnitude
        return setStock(min(потолок, remaining + сколько))
    }

    /// Сколько даёт доза, назначенная на это время.
    ///
    /// Слот ищется по минуте суток, а не по дате: расписание суточное,
    /// а доза — конкретного дня. Нет слота на этот час — доза считается
    /// за единицу: так ведут себя все схемы, заведённые до появления
    /// слотов, и у них это верно.
    ///
    /// Слоты на один час **складываются**, а не берётся первый: врач
    /// делит дозу надвое, и «8:00 ½ и 8:00 ½» это одна таблетка утром.
    /// Поиск первого списал бы половину назначенного — вопрос togo-9e,
    /// закрыт до того, как такая схема появилась в редакторе.
    func quantity(at scheduled: Date, calendar: Calendar = .current) -> Double {
        let части = calendar.dateComponents([.hour, .minute], from: scheduled)
        let минута = (части.hour ?? 0) * 60 + (части.minute ?? 0)
        let подходящие = schedule.filter { $0.minuteOfDay == минута }
        return подходящие.isEmpty ? 1 : подходящие.map(\.quantity).reduce(0, +)
    }

    /// До какого дня препарат годен на самом деле.
    ///
    /// Два срока, и побеждает ближний: вскрытый флакон портится раньше,
    /// чем кончается срок на упаковке, и наоборот — вскрытый за месяц
    /// до конца годности живёт до конца годности, а не дольше.
    func goodUntil(calendar: Calendar = .current) -> Date? {
        let после = openedAt.flatMap { opened in
            shelfAfterOpenDays > 0
                ? calendar.date(byAdding: .day, value: shelfAfterOpenDays, to: opened)
                : nil
        }
        return [expiry, после].compactMap { $0 }.min()
    }
}

/// Один приём в расписании: час и сколько дать.
///
/// `quantity` дробное, потому что половина таблетки — обычное
/// назначение, а капли мерят миллилитрами. Единица у препарата
/// одна (`Medication.unit`), поэтому в слоте её нет: иначе два слота
/// одного препарата могли бы разойтись в единицах, а такого
/// назначения не бывает.
nonisolated struct DoseSlot: Codable, Hashable, Sendable {
    /// Минуты от полуночи — та же мера, что у `Medication.times`.
    var minuteOfDay: Int
    var quantity: Double

    var clock: String {
        String(format: "%02d:%02d", minuteOfDay / 60, minuteOfDay % 60)
    }
}

@Model
final class DoseRecord {
    var id: UUID = UUID()
    var scheduledAt: Date = Date()
    var givenAt: Date?
    var givenBy: String?
    /// «Беру на себя» с TTL 45 минут снимает двойную дозу.
    var claimedBy: String?
    var claimedAt: Date?
    /// Отмена дозы оставляет запись об отмене, а не стирает её.
    var cancelledAt: Date?
    var cancelReason: String?
    /// Когда этот телефон в последний раз трогал отметку. См. `LogEvent`.
    var changedAt: Date = Date()

    /// Надгробие удаления — разбор у `Medication.deletedAt`.
    /// Ставить только через `ОбщееУдаление`.
    ///
    /// **У дозы надгробие дороже, чем у остальных десяти.** Доза
    /// исчезает не только от руки человека: её снимает пересчёт
    /// расписания (`DoseScheduler`, `ScheduleChange`), и такое
    /// удаление надгробия НЕ СТАВИТ нарочно — пересчёт случается
    /// у каждого телефона свой, и надгробие от одного погасило бы
    /// дозу у второго, которую тот ещё не пересчитал. Надгробие
    /// у дозы ставит только отмена курса и рука.
    var deletedAt: Date?

    /// Дозу решили пропустить.
    ///
    /// Пропуск — это запись, а не пустота: врач спрашивает именно про
    /// него, а иначе в истории непонятно, забыли отметить или правда
    /// не дали.
    var skippedAt: Date?
    var skippedBy: String?

    var medication: Medication?

    /// Чего доза ждёт, если схема ещё не приехала.
    ///
    /// Связь `medication` — это ссылка на объект, и у неё нет памяти:
    /// ничья доза не помнит, чьей она хотела быть. Пока схемы не ездили,
    /// это было неважно — их искали по имени в момент приёма и на этом
    /// всё. Теперь схема может приехать ПОСЛЕ своих доз (обмен включили
    /// посреди курса), и без этих двух полей подобрать их нечем:
    /// ничья доза на экране не показывается вовсе, то есть второй
    /// человек видит приём открытым и даёт вторую таблетку.
    ///
    /// Заполняется только у приехавших доз и только когда схема
    /// не нашлась. Своя доза всегда заводится со схемой в руках.
    var awaitedMedicationID: UUID?
    var awaitedMedicationName: String?

    init(scheduledAt: Date) {
        self.scheduledAt = scheduledAt
    }

    /// Устойчивая отметка приёма: один и тот же id у всех телефонов.
    ///
    /// **Зачем.** `id` по умолчанию — свежий `UUID()`, а отметки заводит
    /// `DoseScheduler.ensureDoses` **на каждом телефоне отдельно**, при
    /// открытии экрана, дедуплицируя по паре (схема, минута). Приём
    /// чужой отметки ищет её только по `id`
    /// (`SharedDiaryPayloads`, `#Predicate { $0.id == id }`), а
    /// `SharedDiaryMerge.resolve` начинается с
    /// `precondition(local.id == remote.id)`. Значит два телефона,
    /// оба открывшие «Сегодня», держали **две** записи на один приём,
    /// и спор между ними не формулировал никто.
    ///
    /// Измерено прогоном 08.10.2026, набор `ДозаОдинНаСлотTests`:
    ///
    /// ```
    /// две дозы на один слот                      да
    /// баннер «не отмечена» после чужого «дано»   остаётся
    /// ```
    ///
    /// Второе и есть ущерб: человек видит красную тревогу о дозе,
    /// которую второй человек уже дал, — и это прямой повод дать
    /// лекарство ещё раз рукой. Защита от двойной дозы при этом
    /// смотрит на одну запись из двух (`.first` из связи, порядок
    /// не наш), то есть **может** пропустить второй приём; что
    /// пропустит обязательно — не измерено.
    ///
    /// **Почему минута, а не секунда.** Слот считается из расписания
    /// (`Medication.times` — минуты от полуночи), секунды у обоих
    /// телефонов нулевые. Округление вниз делает величину одинаковой,
    /// даже если чей-то `Date` принесёт дробь.
    ///
    /// **Граница, названная до того, как выстрелит:** слот — момент
    /// абсолютного времени. Два человека в **разных часовых поясах**
    /// получат разные слоты из одного расписания, то есть разные id —
    /// и дубль вернётся. Прогоном это не проверено, в код не заложено
    /// и здесь названо нарочно: `Medication.times` хранит минуты
    /// от полуночи без пояса, и чей это полдень — вопрос продуктовый.
    ///
    /// Старые отметки свои `id` не меняют: правка снимает расхождение
    /// у новых, а не лечит уже разошедшиеся. Для существующих баз это
    /// безразлично — снос базы разрешён решением Виктории 08.10.2026.
    nonisolated static func устойчивыйID(medication: UUID, scheduledAt: Date) -> UUID {
        let минута = Int64((scheduledAt.timeIntervalSince1970 / 60).rounded(.down))
        let соль = UInt64(bitPattern: минута)

        // Порядок байтов закреплён явно. На двух iPhone он и так один,
        // но тогда об этом знал бы только тот, кто помнит про arm64:
        // молчаливое совпадение и закреплённое правило снаружи
        // неразличимы, а ломается первое.
        let (старшее, младшее) = withUnsafeBytes(of: medication.uuid) { сырые in
            (UInt64(littleEndian: сырые.loadUnaligned(fromByteOffset: 0, as: UInt64.self)),
             UInt64(littleEndian: сырые.loadUnaligned(fromByteOffset: 8, as: UInt64.self)))
        }
        let первое = перемешать(старшее ^ соль).littleEndian
        let второе = перемешать(младшее &+ соль).littleEndian

        var байты = [UInt8](repeating: 0, count: 16)
        withUnsafeBytes(of: первое) { байты.replaceSubrange(0..<8, with: $0) }
        withUnsafeBytes(of: второе) { байты.replaceSubrange(8..<16, with: $0) }

        return UUID(uuid: (байты[0], байты[1], байты[2], байты[3],
                           байты[4], байты[5], байты[6], байты[7],
                           байты[8], байты[9], байты[10], байты[11],
                           байты[12], байты[13], байты[14], байты[15]))
    }

    /// splitmix64 — лавинная функция с известным поведением.
    ///
    /// Берётся готовая, а не своя: самодельное перемешивание выглядит
    /// так же и расходится на редких входах, а проверить это нечем.
    nonisolated private static func перемешать(_ исходное: UInt64) -> UInt64 {
        var z = исходное &+ 0x9E37_79B9_7F4A_7C15
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        return z ^ (z >> 31)
    }

    static let claimTTL: TimeInterval = 45 * 60

    var isGiven: Bool { givenAt != nil }
    var isSkipped: Bool { skippedAt != nil }

    /// Доза всё ещё ждёт, что её отметят.
    ///
    /// **Одно определение на двух читателей, и это не вкус.** 14.10.2026
    /// правило «доза больше не ждёт» завелось в двух местах за один час:
    /// в уборке запросов `ReminderScheduler.снятьНеждущие` и в приёме
    /// чужой отметки `FamilySync.apply`. Два разбора одного правила
    /// расходятся молча — у Togo так жили три реализации «не кормить»,
    /// и две из трёх молчали. Поэтому определение одно и лежит в модели,
    /// то есть там, куда дотягиваются оба таргета.
    ///
    /// Про **схему** здесь не спрашивается нарочно: пауза и выключенное
    /// лечение — свойство схемы, а не дозы, и смешать их значило бы
    /// ответить «доза отмечена» про дозу, которую просто перестали ждать.
    /// Читателю, которому нужны обе половины, их надо сложить у себя —
    /// `снятьНеждущие` так и делает.
    var ждётОтметки: Bool {
        !isGiven && skippedAt == nil && cancelledAt == nil
    }

    /// Ждёт ли доза отметки **с учётом схемы**.
    ///
    /// Вторая половина к `ждётОтметки`, и сведена она сюда по той же
    /// причине, что первая: правило уже расходилось двумя разборами
    /// за час. Складывать его руками у каждого читателя — значит
    /// заводить третье место, где оно разойдётся молча.
    ///
    /// Читателей двое, и они в разных таргетах: уборка запросов
    /// (`ReminderScheduler.снятьНеждущие`, только приложение) и приём
    /// чужой правки (`FamilySync.apply`, `TogoShared` — оба таргета).
    ///
    /// # Почему `isPaused`, а не `cancelledAt`
    ///
    /// Это замер, а не вкус. Вся уборка запросов смотрит на `isPaused`;
    /// `cancelledAt` схемы она не спрашивает нигде. Сегодня это
    /// сходится, потому что единственное место, отменяющее схему
    /// (`TreatmentCourse.finish:42-43`), ставит **оба** поля сразу.
    ///
    /// > Кнопка, которая поставит только `cancelledAt`, не погасит
    /// > напоминания **ни у кого, включая хозяйку**, и ни один сторож
    /// > об этом не скажет. Держит `ОтменаСтавитОбаПоляTests`.
    ///
    /// # У сироты ответ «не ждёт», и это выбранная сторона ошибки
    ///
    /// `medication` или `dog` пусты — состояние схемы спросить не у кого.
    /// Предикат **гасит** напоминания, и для него дешевле снять лишний
    /// запрос, чем оставить звонить по дозе, которой не управляет никто.
    /// Это не недосмотр: обратный выбор означал бы «звоним, пока
    /// не разберёмся», а звонит оно про лекарство.
    /// **Четвёртое условие — надгробие схемы, и оно закрывает тот самый
    /// случай, ради которого надгробия заведены** (26.10.2026).
    ///
    /// Виктория удалила схему лечения. Снимок с `deletedAt` уезжает
    /// обычной правкой, у мамы `SharedDiaryInbox.accept` ставит
    /// надгробие, и `FamilySync.apply` в ветке `.medication` **уже**
    /// обходит дозы этой схемы циклом `where
    /// !доза.ждётОтметкиСУчётомСхемы` и гасит запросы. То есть вся
    /// доставка на приёме держится на этой строке: без неё дозы
    /// удалённой схемы по-прежнему «ждут», и мама получает
    /// «Через 10 минут доза» по лечению, которого нет.
    ///
    /// Своё `deletedAt` у дозы спрашивать здесь НЕ надо: удалённую дозу
    /// отсеивает `Medication.doses` раньше любого читателя этого
    /// предиката, а единственные, кто ходит мимо фильтра
    /// (`снятьНеждущие` и `removeOrphans`), обязаны видеть удалённое —
    /// им как раз и нужно, чтобы предикат ответил «не ждёт».
    var ждётОтметкиСУчётомСхемы: Bool {
        guard let medication, medication.deletedAt == nil,
              !medication.isPaused,
              medication.dog?.isOnTreatment == true
        else { return false }
        return ждётОтметки
    }

    func claimIsActive(at date: Date = Date()) -> Bool {
        guard let claimedAt else { return false }
        return date.timeIntervalSince(claimedAt) < Self.claimTTL
    }

    /// Лестница эскалации: ступени т−10, т+30, т+60 и запись «пропуск».
    ///
    /// **АДРЕСАТОВ ЗДЕСЬ НЕТ, И НИГДЕ НЕТ** (замер 21.10.2026). Прежняя
    /// редакция этой строки называла их — «т−10 дежурному, т+30
    /// со-владельцам, т+60 всем», — и это читалось как устройство
    /// механизма. Механизма нет: функция возвращает **только номер
    /// ступени**, все три уведомления уходят `NotificationCenterService
    /// .scheduleDose` локально, то есть на телефон владельца, а
    /// `CKSubscription` в проекте ноль (`FamilySync.swift:730,810`
    /// говорят об этом прямо). Три сообщения приходят одному человеку.
    ///
    /// Почему строка опасна была не ошибкой, а **адресатом**: её читает
    /// тот, кто правит эскалацию, и из неё следует, что осталось
    /// дописать текст, а не канал. Обещание человеку живёт отдельно —
    /// в онбординге (`OnboardingSteps.swift:459`: «сначала дежурному,
    /// потом остальным»), и вот оно расходится с механизмом. Снять
    /// обещание или сделать канал — решение Виктории, не правка.
    ///
    /// **Пропуск снимает лестницу так же, как приём.** Раньше здесь
    /// не было `isSkipped`, и «пропустить» не гасило тревогу: человек
    /// принимал решение, записывал его — а красное «не отмечена»
    /// оставалось и через сутки, и через неделю. Лестница существует
    /// ровно для того случая, когда решения ещё НЕТ; пропуск — это
    /// решение и запись, врач спрашивает именно про него.
    func escalationStage(at date: Date = Date()) -> Int {
        if isGiven || isSkipped || cancelledAt != nil { return 0 }
        let minutes = date.timeIntervalSince(scheduledAt) / 60
        if minutes >= 60 { return 3 }
        if minutes >= 30 { return 2 }
        if minutes >= -10 { return 1 }
        return 0
    }
}

