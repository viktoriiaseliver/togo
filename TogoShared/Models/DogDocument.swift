        case callNow
        case watch

        var title: String {
            switch self {
            case .callNow: String(localized: "Звони врачу сейчас")
            case .watch: String(localized: "Наблюдай и позвони при симптомах")
            }
        }
    }

    var id: String { name }
    var name: String
    var urgency: Urgency
    var detail: String

    /// Список короткий намеренно: длинный никто не дочитает в панике.
