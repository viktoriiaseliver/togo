import Foundation
import SwiftData

/// Фотография документа: паспорт, чип, результат анализа, назначение.
///
/// Лежит на телефоне рядом с дневником, потому что нужна ровно там же —
/// у врача, на границе и когда собака потерялась. Никуда не отправляется.
@Model
final class DogDocument {
    var id: UUID = UUID()
    var title: String = ""
    /// Снимок лежит рядом с базой, а не внутри неё: страница паспорта
    /// весит куда больше всех записей дневника вместе взятых.
    @Attribute(.externalStorage) var image: Data?
    var addedAt: Date = Date()
    var note: String?

    // MARK: Шаг 0 медицинского слоя, 07.10.2026
    //
    // Четыре поля из §2.5 ТЗ: в карте Стича документы — паспорт, чип,
    // договор, сертификат, — и у каждого есть тип, номер и срок.
    // Без них список документов это список картинок, по которому
    // нельзя ни напомнить о сроке, ни назвать номер в клинике.

    /// Паспорт · чип · договор · сертификат · прочее.
    /// Ключ группировки списка — и потому `Raw`-строка с перечислением
    /// рядом, а не свободный текст.
    var kindRaw: String = DocumentKind.other.rawValue

    /// Номер документа: «FR 123456», «250269606000000».
    /// Строкой: ведущие нули и буквы значащие.
    var number: String?

    /// Кем выдан — клиника, ветврач или организация.
    var issuedBy: String?

    /// До какого числа действует. Пусто — «бессрочно или неизвестно»,
    /// и это РАЗНЫЕ вещи, которые модель не различает: различит экран,
    /// когда появится, а выдумывать здесь нельзя.
    var validUntil: Date?

    var kind: DocumentKind {
        get { DocumentKind(rawValue: kindRaw) ?? .other }
        set { kindRaw = newValue.rawValue }
    }

    // MARK: Шаг 1 — дата события, направление, клиника. V8, 28.10.2026
    //
    // Решение Виктории 28.10.2026, её словами: «не просто записывать
    // данные, а фотографировать результаты и подписывать их правильно —
    // что это такое, чтоб потом быстро находить документы по датам
    // и то, какие были сделаны анализы и в каком направлении».
    //
    // Три поля отвечают на три её вопроса — «когда», «что это»,
    // «где делали», — и ни на один из них нельзя было ответить
    // имеющимися: `addedAt` отвечает про телефон, `kindRaw` про вид
    // бумаги, `issuedBy` — свободный текст, по которому не сгруппируешь.

    /// Когда случилось то, о чём документ: забор крови, приём,
    /// подписание договора, выдача паспорта.
    ///
    /// **Отдельно от `addedAt`, и это весь смысл поля.** `addedAt` —
    /// когда СФОТОГРАФИРОВАЛИ; бланк от 16.10 сняли 27-го, и искать
    /// человек будет по первой дате. Одним полем разница потерялась бы
    /// молча, а проявилась бы у врача — там, где спрашивают «когда
    /// сдавали», и неверный ответ меняет назначение.
    ///
    /// **Почему имя не называет род события.** Для бланка анализа
    /// день забора и день выдачи отчёта — разные даты, и лаборатория
    /// печатает обе. Назови поле `issuedOn`, и первый же человек,
    /// вписавший туда день забора, сделает имя ложным; назови
    /// `sampledOn` — то же с паспортом, который никто не «сдавал».
    /// `occurredOn` не утверждает, КАКОЕ это событие, поэтому
    /// не становится неправдой ни на одном виде документа.
    ///
    /// **Опциональное, и это не осторожность.** Дата на бумаге бывает
    /// нечитаемой или отсутствует вовсе (чип), и подставить сюда
    /// `addedAt` значило бы сказать за человека, что анализ сдан
    /// в день съёмки. Запрет свода: «не подставлять там, где
    /// подстановка станет утверждением человека» — запись потом читает
    /// врач.
    ///
    /// Соседняя величина, с которой её нельзя путать, —
    /// `LabResult.sampledOn`: там день забора у РАЗОБРАННОЙ строки
    /// анализа, здесь — день события у СНИМКА бумаги. Две величины
    /// могут честно разойтись: человек снял бланк и ввёл день отчёта,
    /// а строки с него разобрал по дню забора. Сводить их одним
    /// присваиванием нельзя.
    var occurredOn: Date?

    /// В каком направлении сделан анализ: гормоны, ОАК, биохимия,
    /// визуальное, микробиология, прививки, прочее.
    ///
    /// # Почему отдельное поле, а не шестое значение `DocumentKind`
    ///
    /// Два разных вопроса, и у них разные области определения.
    /// `kindRaw` отвечает «что это за бумага» (паспорт, договор)
    /// и служит **ключом группировки списка**; направление отвечает
    /// «про какую медицину она». У паспорта направления нет вовсе,
    /// у бланка гормонов нет вида сверх «прочее».
    ///
    /// Сложи их в одно перечисление — и ключ группировки начнёт
    /// отвечать на два вопроса разом: «паспорт» и «гормоны» встанут
    /// в один ряд как взаимоисключающие, хотя документ бывает и тем
    /// и другим одновременно (ветпаспорт с вклеенным бланком). Это наш
    /// класс «две величины одного имени, прочитанные как одна».
    ///
    /// # Почему опциональное и БЕЗ значения по умолчанию
    ///
    /// В отличие от `kindRaw`, у которого умолчание `.other` стоит
    /// нарочно (пустой ключ группировки рассыпал бы список), здесь
    /// умолчания быть не должно. «Направления нет» и «направление
    /// прочее» — разные состояния: у паспорта его нет, у цитологии
    /// оно прочее. Поставь умолчанием `.other`, и все паспорта
    /// соберутся в группу «прочие анализы», которой они не являются.
    ///
    /// > **Ключ со значением по умолчанию собирает в одну группу всё,
    /// > что это поле не заполнило** — ровно то, о чём предупреждает
    /// > голова `Clinic`, только с обратным знаком: там умолчание
    /// > спасало, здесь оно лжёт.
    var directionRaw: String?

    /// Направление как перечисление. `nil` значит «не медицинский
    /// документ или направление не названо», и ПОДСТАВЛЯТЬ сюда
    /// `.прочее` нельзя — разбор у `directionRaw`.
    var direction: DocumentDirection? {
        get { directionRaw.flatMap(DocumentDirection.init(rawValue:)) }
        set { directionRaw = newValue?.rawValue }
    }

    /// Где сделали: клиника или лаборатория из справочника.
    ///
    /// **Связь со справочником, а не строка, — то же решение, что
    /// у `CareTask.clinic`, `VetVisit.clinic` и `Prescription.clinic`.**
    /// Единообразие здесь дороже изящества: четвёртый способ хранить
    /// одно и то же дал бы четыре списка «где делали», которые
    /// не сходятся между собой. В карте Стича шестнадцать организаций,
    /// и набранные руками они рассыпятся на столько групп, сколько
    /// было опечаток.
    ///
    /// Обратная сторона связи (`Clinic.documentsStorage`) **обязательна
    /// и это не стиль:** зеркало CloudKit отказывается открывать
    /// хранилище у связи без обратной — `CloudKit integration requires
    /// that all relationships have an inverse`. Замер `togo-1e`
    /// 07.10.2026, и это был не красный тест, а контейнер,
    /// не открывшийся вовсе: у человека это молчаливый откат в память.
    ///
    /// `issuedBy` при этом остаётся и не дублирует: «кем выдан» — это
    /// то, что НАПЕЧАТАНО в документе (бывает «Préfecture», бывает
    /// фамилия врача), а `clinic` — организация из справочника,
    /// по которой группируют и звонят.
    var clinic: Clinic?

    /// Когда этот телефон в последний раз трогал запись — для спора
    /// двух телефонов, как у собаки, клиники и взвешивания.
    ///
    /// **Появилось 07.10.2026 вместе с обменом документов**, и без него
    /// спор решать нечем: `addedAt` — это когда документ ЗАВЕЛИ,
    /// а не когда правили номер. Решать по `addedAt` значило бы,
    /// что исправление опечатки в номере всегда проигрывает более
    /// свежей записи — то есть опечатка остаётся навсегда.
    ///
    /// > **День заведения и день правки — разные величины, и у них
    /// > разные вопросы.** Та же пара, что `WeightEntry.date`
    /// > и `WeightEntry.changedAt`.
    var changedAt: Date = Date()

    /// Надгробие удаления — разбор у `Medication.deletedAt`.
    /// Ставить только через `ОбщееУдаление`.
    var deletedAt: Date?

    var dog: Dog?

    init(title: String, image: Data? = nil, note: String? = nil) {
        self.title = title
        self.image = image
        self.note = note
    }
}

/// То, что собака может съесть и от чего бывает плохо.
///
/// Приложение не лечит и не ставит диагнозов — оно только помнит список
/// и говорит, звонить прямо сейчас или наблюдать. Решение всегда за врачом,
/// и это написано на самом экране.
