import Foundation
import SwiftData

/// День, который собака проводит с человеком: по делам, в дороге, в гостях.
///
/// Такой день устроен иначе, чем обычный, и приложение должно вести себя
/// иначе тоже.
///
/// Что меняется:
///
/// * **Кормить по часам.** Дома миска стоит и собака подходит сама;
///   в разъездах кормят тогда, когда вспомнили, — а значит, напомнить надо.
/// * **Воду предлагать регулярно.** Дома вода стоит всегда. На улице
///   её нет, и собака терпит молча.
/// * **Не дёргать про «пописал».** Она весь день с человеком и выходит
///   постоянно; вердикт «просится» в такой день считает ерунду и только
///   мешает.
/// * **Считать часы.** После долгого дня собаке нужен спокойный следующий,
///   и об этом стоит сказать заранее, а не когда она уже спит сутки.
///
/// Поездка — тот же день с собакой, только длинный. Отдельной механики
/// у неё нет: `Trip` заводит режим на несколько дней, `DayOut` — на часть
/// одного.
@Model
final class DayOut {
    var id: UUID = UUID()
    var startedAt: Date = Date()
    /// Пусто — день ещё идёт.
    var endedAt: Date?
    /// На сколько рассчитывали, когда выходили. Нужно, чтобы посчитать,
    /// сколько еды взять, — и чтобы потом сравнить с тем, как вышло.
    var plannedHours: Int = 4
    var note: String?

    var dog: Dog?

    init(startedAt: Date = Date(), plannedHours: Int = 4) {
        self.startedAt = startedAt
        self.plannedHours = plannedHours
    }

    func isActive(at date: Date = Date()) -> Bool {
        endedAt == nil && date >= startedAt
    }

    func duration(at date: Date = Date()) -> TimeInterval {
        max(0, (endedAt ?? date).timeIntervalSince(startedAt))
    }

    var hours: Double { duration() / 3600 }

    /// Долгий день — тот, после которого собаке нужен спокойный.
    ///
    /// Шесть часов не из головы: это примерно рабочий день с дорогой,
    /// после которого собака отсыпается. Точную границу назвать нельзя —
    /// у щенка и у пожилой она разная, — поэтому приложение не запрещает
    /// и не советует, а только показывает.
    static let longDayHours: Double = 6

    func wasLong(at date: Date = Date()) -> Bool {
        duration(at: date) / 3600 >= Self.longDayHours
    }
}
