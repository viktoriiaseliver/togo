import Foundation

/// Направление анализа у сфотографированного документа.
///
/// # Зачем и чьё решение
///
/// Решение Виктории 28.10.2026: «чтоб потом быстро находить документы
/// по датам и то, какие были сделаны анализы и в каком направлении».
/// Список семи значений она утвердила целиком — он не выведен из карты
/// Стича и не придуман здесь, и дописывать в него значения **без её
/// слова нельзя**: направление это ось показа, и восьмое значение
/// меняет не данные, а то, по чему человек ищет.
///
/// # Почему это НЕ шестое значение `DocumentKind`
///
/// Разбор лежит у поля — `DogDocument.directionRaw`, — а не здесь,
/// потому что читают его у поля. Коротко: `DocumentKind` отвечает
/// «что это за бумага», направление — «про какую медицину она», и у
/// паспорта второго ответа нет вовсе.
///
/// # Почему файл свой, а не рядом с `DocumentKind`
///
/// `DocumentKind` живёт в `TogoShared/Models/Enums+Care.swift` — там
/// перечисления слоя ухода. **Грепать надо оба имени:** поле `kindRaw`
/// и поле `directionRaw` стоят в одной модели, а их перечисления —
/// в разных файлах, и читатель, нашедший одно, легко решит, что второго
/// нет. Адрес назван здесь затем, чтобы искать не приходилось.
///
/// # Чего в списке НЕТ, и это названо, а не замолчано
///
/// Моча (ОАМ), паразитология, цитология и гистология своего значения
/// не получили — они попадают в `.other`. Это не полная таксономия
/// ветеринарной лаборатории, а семь ящиков, по которым хозяйка
/// раскладывает свои бумаги. **Условие, при котором список вырастет:**
/// её слово о конкретном восьмом направлении. Выдумать его за неё
/// нельзя — ящик, которым никто не пользуется, разбавляет фильтр
/// и делает поиск хуже, а не лучше.
///
/// # Почему значения латиницей
///
/// `rawValue` уезжает в хранилище и в CloudKit навсегда, как
/// у `DocumentKind` рядом: переименовать его потом нельзя — ни
/// `.lightweight`-миграция, ни зеркало переименования полей не выводят.
/// Подпись для человека берётся из `title` и живёт в каталоге строк,
/// то есть переводится и правится без правки формы хранилища.
nonisolated enum DocumentDirection: String, Codable, CaseIterable, Sendable {
    /// Гормоны: Т4 свободный, ТТГ, кортизол. У Стича это главное
    /// направление, по которому бумаг больше всего.
    case hormones

    /// Общий анализ крови.
    case blood

    /// Биохимия крови.
    case biochemistry

    /// Визуальное: УЗИ, рентген. Одно значение на два метода нарочно —
    /// человек ищет «картинку изнутри», а не аппарат.
    case imaging

    /// Микробиология: посев, чувствительность к антибиотикам.
    case microbiology

    /// Прививки: сертификат, бланк, наклейка с партией.
    case vaccination

    /// Прочее — для бумаги, направление которой есть, но своего ящика
    /// не получило. **Это не то же самое, что `directionRaw == nil`:**
    /// там направления нет вовсе (паспорт, договор), здесь оно есть
    /// и не названо. Разбор у `DogDocument.directionRaw`.
    case other

    var title: String {
        switch self {
        case .hormones: String(localized: "гормоны")
        case .blood: String(localized: "кровь (ОАК)")
        case .biochemistry: String(localized: "биохимия")
        case .imaging: String(localized: "визуальное (УЗИ, рентген)")
        case .microbiology: String(localized: "микробиология")
        case .vaccination: String(localized: "прививки")
        case .other: String(localized: "прочее направление")
        }
    }
}
