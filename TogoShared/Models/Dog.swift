    var markerKind: MarkerKind {
        get { MarkerKind(rawValue: markerKindRaw) ?? .clicker }
        set { markerKindRaw = newValue.rawValue }
    }

    /// Кличка для показа человеку — **единственная точка на все
    /// поверхности**.
    ///
    /// Отзыв TestFlight 06.10.2026 по сборке 271: «Много пустых собак».
    /// Замер `togo-02` нашёл не три поверхности, а **двадцать одну**,
    /// и разделил их на два класса:
    ///
    /// ```
    /// КЛАСС А  откат есть, написан на nil, слеп к ""    12 мест
    /// КЛАСС Б  отката НЕТ вовсе, кличка вклеивается      9 мест
    /// ```
    ///
    /// Класс А — это `dog?.name ?? "Собака"`: `??` отвечает на `nil`,
    /// а кличка по типу непустая строка, и у безымянной она `""`.
    /// Откат написан на отсутствие, а приходит пустота — тот же класс,
    /// что `guard let name = record["name"] as? String` на приёме
    /// снимка.
    ///
    /// Класс Б страшнее, и три места из девяти не косметика:
    ///
    /// ```
    /// EmergencyScreen   «Потерялась собака: , метис, 4,1 кг»
    /// AlarmThreshold    «, 4,1 кг. <тревога>»
    /// QuickLogIntents   «Записала · еда · »
    /// ```
    ///
    /// Первое человек копирует в чат района в тот час, когда собака
    /// потерялась. Запятая на месте имени читается как сбой приложения
    /// ровно тогда, когда на приложение надеются больше всего.
    ///
    /// **Почему одна точка, а не двадцать одна подстановка.** Двадцать
    /// одна локальная починка расходится молча: у нас это записано
    /// и оплачено трижды — «правка применяется ко всем поверхностям,
    /// где та же строка живёт», и каждый раз доезжала до одной из трёх.
    ///
    /// **Запасной текст идёт из каталога, и это не придирка.**
    /// `String(localized:)` внутри функции, а не литерал на месте
    /// вызова: вычисляемое свойство возвращает ЗНАЧЕНИЕ типа `String`,
    /// а `Text(значение)` рисует его мимо каталога. Напиши литерал
    /// снаружи — и француз увидит русское слово на объявлении
    /// о пропаже. Ключ «Собака» в каталоге уже есть на все четыре
    /// языка; нового ключа эта правка не заводит.
    ///
    /// Решение по самому слову — менеджера, 07.10: берётся то, которое
    /// уже стояло откатом вкладки в `RootView`, чтобы не заводить
    /// двадцать второй вариант.
    /// **Две формы одного правила, и вторая нужна из-за падежей.**
    ///
    /// На местах вызова уже написаны откаты в нужном падеже — «Едем
    /// с собакой», «Дневник · собаки», «Ты с собакой». Подставить туда
    /// именительное «Собака» значило бы починить пустоту и сломать
    /// русский. Поэтому `nameIfAny` отдаёт `nil`, и падежный откат,
    /// написанный на месте, срабатывает и для пустой клички тоже:
    ///
    /// ```swift
    /// было   "Едем с \(dog?.name ?? "собакой")"
    /// стало  "Едем с \(dog.flatMap(\.nameIfAny) ?? "собакой")"
    /// ```
    ///
    /// `displayName` — для класса Б, где отката нет вовсе
    /// и подставить надо хоть что-то.
    var nameIfAny: String? { Fmt.dogName(name) }

    /// Можно ли показать эту запись человеку.
    ///
    /// **Решение Виктории 07.10.2026, обратное утреннему: безымянные
    /// записи не удаляем, а не показываем.** Утром знали только, что
    /// их восемь и убрать их человек не может. К вечеру — три вещи,
    /// и каждая против удаления.
    ///
    /// **1. Пустая запись может быть настоящей собакой на полпути.**
    /// Замер крошек запуска: девять разных `id` за шесть дней, пять
    /// исчезли сами. Вероятный источник — зеркало CloudKit, а оно
    /// создаёт запись и заполняет атрибуты НЕ одновременно. У такой
    /// записи нет ни клички, ни связей — то есть от фантома она
    /// неотличима ничем.
    ///
    /// **2. Цена ошибки несимметрична.**
    ///
    /// ```
    /// удалили лишнее       необратимо, уносит одиннадцать каскадов
    /// не показали лишнее   обратимо: появится сама, когда доедет кличка
    /// ```
    ///
    /// Приём «не показывать» **самоисправляется**, удаление — нет.
    /// Это тот же выбор, что 05.10 по дням календаря: допущение,
    /// положенное в данные, становится фактом; положенное в чтение —
    /// остаётся допущением.
    ///
    /// **3. Удаление решало задачу, которой у человека нет.** Он
    /// жаловался не на записи в базе, а на строки на экране и на то,
    /// что их нечем убрать. Дорога к удалению заведена в тот же день —
    /// настоящую собаку он уберёт сам.
    ///
    /// **Условий здесь одно, а не три.** Безымянность и есть то, что
    /// мешает показать: ни «ничего не тянет», ни «видена дважды» для
    /// скрытия не нужны — они были защитой от необратимости, которой
    /// больше нет.
    /// **С 26.10.2026 условий два: кличка и надгробие.** Удалённая
    /// собака остаётся в базе, чтобы удаление доехало до второго
    /// человека (разбор — `Medication.deletedAt`), и показывать её
    /// нельзя. Точка выбрана по описи чтений: через `shownToPerson`
    /// идут одиннадцать вызовов `AppState.activeDog`, переключатель,
    /// список в настройках, Siri и **счётчик пейволла**
    /// (`ProGate:178`) — то есть удалённая собака иначе считалась бы
    /// второй и запирала бы человека за платным порогом.
    ///
    /// Опознание и склейка дубликатов сюда НЕ ходят нарочно
    /// (`DuplicateMerge`, `DuplicateDogCard`): им нужна правда базы.
    ///
    /// # ТРЕТИЙ СЛУЧАЙ, КОТОРОГО 07.10 НЕ БЫЛО: без клички, НО С ИСТОРИЕЙ
    ///
    /// Довод «от фантома она неотличима ничем» был верен ровно до тех
    /// пор, пока безымянные записи ничего не тянули. Замер 30.10.2026
    /// по журналу маминого телефона — три такие записи, и каждая
    /// с историей:
    ///
    /// ```
    /// 07A377E6   ev 214  w 25  care 19  med 10     — 268 связей
    /// 71FBB678   ev 44   doc 15                    —  59 связей
    /// 42377768   ev 13   care 1                    —  14 связей
    /// ```
    ///
    /// Её экран в ту же минуту: «Дневник едет на этот телефон», «Пока
    /// пусто» и четыре нуля (кадр `.отзывы/Togo/2026-10-30_0947-…-1.jpg`).
    /// Плашка рисуется при `dog == nil` (`TodayScreen:236`), то есть
    /// **кадр доказывает, что `shownToPerson` отдал ноль** при 341 связи
    /// в базе.
    ///
    /// **И это НЕ «на полпути».** У той же записи `C1469CE8` на двух
    /// телефонах разошлось соседнее поле того же вида:
    ///
    /// ```
    /// у владельца   created 2023-03-19T12:00:00Z   ev 28 w 24 care 8 …
    /// у гостя       created 2026-10-28T13:48:37Z   связей 0
    /// ```
    ///
    /// `createdAt` объявлен `= Date()` (строка 166), и второе значение —
    /// не данные, а **дефолт, сработавший при материализации объекта**.
    /// `name` объявлен `= ""` там же (строка 30) и не доехал тем же
    /// способом. Двадцать одно поле из двадцати двух приехало.
    ///
    /// > **Самоисправление, на которое ссылался довод 2, не наступило
    /// > за три дня и не наступит:** «появится сама, когда доедет
    /// > кличка» верно для недогруженной записи и ложно для
    /// > недоставленного атрибута. А цена, которая считалась
    /// > обратимой, оказалась «человек третий день держит пустое
    /// > приложение поверх полного дневника».
    ///
    /// Поэтому условие «есть кличка» смягчено до «есть кличка **или**
    /// есть что показывать». Надгробие по-прежнему скрыто: `deletedAt`
    /// проверяется раньше и связи у него считаются через обёртки,
    /// которые удалённое отсеивают.
    ///
    /// Фантом от этого видимым не становится: у него ноль связей
    /// по всем пятнадцати, и в этом вся разница с тремя записями выше.
    var canBeShown: Bool { deletedAt == nil && (nameIfAny != nil || несётИсторию) }

    /// Тянет ли запись хоть что-нибудь, что человек заводил сам.
    ///
    /// Короткое замыкание нарочно: у здоровой собаки ответ приходит
    /// на первом же `events`, и остальные четырнадцать связей
    /// из хранилища не поднимаются. `isEmpty` вместо `count` — по той
    /// же причине.
    ///
    /// Обёртки, а не `*Storage`: удалённые события не должны оживлять
    /// запись, иначе скрытие надгробий, заведённое 26.10, развалится
    /// с другого конца.
    private var несётИсторию: Bool {
        !events.isEmpty || !weights.isEmpty || !careTasks.isEmpty
            || !medications.isEmpty || !documents.isEmpty
            || !trips.isEmpty || !daysOut.isEmpty || !heats.isEmpty
            || !stocks.isEmpty || !labResults.isEmpty || !vetVisits.isEmpty
            || !diagnoses.isEmpty || !prescriptions.isEmpty
            || !trainingSteps.isEmpty || !trainingSessions.isEmpty
    }

    var displayName: String { Fmt.dogNameOrFallback(name) }

    /// **Чего эта точка НЕ касается, и это важнее списка поверхностей.**
    ///
    /// Не каждое чтение `name` — показ. Три разных дела:
    ///
    /// ```
    /// показ человеку   экран, виджет, «остров», уведомление, Siri → сюда
    /// данные           снимок архива, нагрузка обмена            → name, как есть
    /// опознание        группировка по кличке, склейка дубликатов → name, как есть
    /// ```
    ///
    /// Третье — ловушка, в которую легко въехать этой самой починкой.
    /// `DuplicateMerge` и `DuplicateDogCard` группируют собак
    /// по `\.name`. Проведи их через запасное слово — и **все безымянные
    /// соберутся в одну группу «Собака» и поедут на склейку**: починка
    /// показа уничтожила бы данные. То же у `Backup`: в архив идёт
    /// настоящая кличка, иначе восстановление подменит пустоту словом
    /// и улика о дефекте исчезнет.
    ///
    /// И отладочная перепись (`CloudKitSchemaWarmup`) печатает `name`
    /// нарочно: она существует, чтобы отличать маркерные записи
    /// от настоящих, а запасное слово сделало бы их неразличимыми.

    /// Буква для кружка аватара.
    ///
    /// **Двадцать вторая поверхность, в замере её не было.** У пустой
    /// клички `name.prefix(1)` — пустая строка, то есть кружок без
    /// буквы. Идёт через ту же точку показа, и буква берётся
    /// у запасного слова.
    var initial: String { String(displayName.prefix(1)).uppercased() }

    /// Снимок, если он ЕСТЬ, — то есть не пустой.
    ///
    /// # Откуда вообще берётся пустой снимок
    ///
    /// Замер 28.10.2026, прогон теста миграции: при переходе V7 → V8
    /// поле `photo` получило `@Attribute(.externalStorage)`,
    /// и SwiftData перенесла **`nil` как `Data()` нулевой длины**.
    /// У собаки, которой фотографию не ставили никогда, поле после
    /// обновления перестало быть пустым:
    ///
    /// ```
    /// до перехода    photo == nil
    /// после          photo == Optional(0 bytes)   ← НЕ nil
    /// ```
    ///
    /// Это поймал сторож, написанный ради другого: первое его
    /// ожидание — что байты фотографии доходят целыми — прошло,
    /// упало второе, про собаку БЕЗ фотографии. Вторая собака
    /// в том тесте заведена именно затем, что перенос пустого
    /// значения ломается отдельно от непустого.
    ///
    /// # Чем это опасно, если читать поле напрямую
    ///
    /// `UIImage(data:)` от пустых данных вернёт `nil`, и картинка
    /// просто не нарисуется — там, где её пытаются открыть. А вот
    /// три места спрашивали иначе, «есть ли поле»:
    ///
    /// ```
    /// ВыборФотоСобаки   `photo == nil` → предложение снять фото
    ///                   перестало бы показываться
    /// NamelessDogAudit  `photo != nil` → у безымянной собаки
    ///                   «есть фото» там, где его нет
    /// BackgroundStore   `guard let data` пропустил бы ноль байт
    ///                   в App Group — и подложка стала бы ЧЁРНОЙ
    /// ```
    ///
    /// > Третье и есть цена: пустые байты, доехавшие до хранилища
    /// > фонов, выглядят как установленная фотография, и человек
    /// > получает чёрный экран вместо собаки. Ровно ту жалобу
    /// > («у мамы изображения нет») чинили этим утром по другой
    /// > причине.
    ///
    /// Одна дорога вместо трёх проверок нарочно: три копии правила
    /// «пустое — это не фото» разошлись бы молча, и разошлись бы
    /// именно в том месте, где его забудут.
    var снимок: Data? {
        guard let photo, !photo.isEmpty else { return nil }
        return photo
    }

    /// Возраст в месяцах. Нужен не для красоты: щенку до года и собаке
    /// старше семи подходят разные режимы кормления и нагрузки.
    var ageMonths: Int? {
        guard let birthDate else { return nil }
        return Calendar.current.dateComponents([.month], from: birthDate, to: .now).month
    }

    var ageDescription: String? {
        guard let months = ageMonths else { return nil }
        if months < 12 { return String(localized: "\(months) месяцев") }
        let years = months / 12
        let rest = months % 12
        let base = String(localized: "\(years) лет")
        return rest == 0 ? base : base + " " + String(localized: "\(rest) месяцев")
    }

    enum LifeStage: String, Sendable {
        case puppy, adult, senior

        var title: String {
            switch self {
            case .puppy: String(localized: "щенок")
            case .adult: String(localized: "взрослая")
            case .senior: String(localized: "пожилая")
            }
        }
    }

    /// Возрастные рамки грубые и намеренно такие: у мелких пород старость
    /// начинается позже, чем у крупных, и точную границу называет врач.
    var lifeStage: LifeStage? {
        guard let months = ageMonths else { return nil }
        if months < 12 { return .puppy }
        return months >= 7 * 12 ? .senior : .adult
    }

    /// Сколько собака съедает за сутки.
    ///
    /// Спрашивать можно с двух концов — кто-то знает норму с упаковки,
    /// кто-то отмеряет порцию за раз, — но храним всегда дневную.
    var dailyGrams: Int { dailyNormGrams ?? max(0, portionGrams * mealsPerDay) }

    /// Сколько класть в миску за раз: норма, поделённая на число кормлений.
    ///
    /// Округляем до пяти граммов — точнее на кухонных весах всё равно
    /// не отмерить, а число вроде «103 г» выглядит как требование.
    ///
    /// **Нормы нет — порции нет, и это НОЛЬ, а не пол `max(5, …)`**
    /// (замер 25.10.2026). Пол отвечал «5 г» на вопрос, которого никто
    /// не задавал: у собаки без нормы пятёрка печаталась в плане дня,
    /// в брифинге ситтера, в сборах в поездку, в ответе Siri — и уезжала
    /// в саму запись о кормлении, то есть в то, что потом читает врач.
    /// От нормы считается порция, значит **без нормы порция не считается
    /// вовсе**, а каждое место показа обязано поставить прочерк.
    ///
    /// Ноль здесь — не значение, а отсутствие, и показывать его числом
    /// нельзя: «врач назначил 0» такое же утверждение, как «врач назначил
    /// 120». Различитель для показа один — `dailyGrams > 0`; он же стоит
    /// в `FeedingAnalyzer.status`, то есть счёт эту разницу знал всегда,
    /// а показ её не знал.
    var servingGrams: Int {
        Self.servingGrams(dailyGrams: dailyGrams, mealsPerDay: mealsPerDay)
    }

    /// Та же арифметика для черновика, у которого собаки ещё нет.
    ///
    /// **Копий этой формулы было три** (замер 28.10.2026): здесь,
    /// в `ScheduleDraft.servingGrams` и внутри
    /// `ScheduleDraft.NormEntry.для(норма:кормлений:)`. Все три
    /// совпадали посимвольно, и ни одна не ссылалась на другую —
    /// то есть правка округления в одной расходилась бы с остальными
    /// молча, а третья копия решает, КАКОЙ шаговик человек увидит
    /// над нормой врача.
    ///
    /// Форма «статика на значениях, а не на модели» выбрана потому,
    /// что черновик редактора `Dog` не держит по устройству:
    /// в онбординге собаки ещё нет.
    static func servingGrams(dailyGrams: Int, mealsPerDay: Int) -> Int {
        guard dailyGrams > 0 else { return 0 }
        guard mealsPerDay > 0 else { return dailyGrams }
        return max(5, Int((Double(dailyGrams) / Double(mealsPerDay) / 5).rounded()) * 5)
    }

    /// Задать дневную норму. Порция пересчитывается сама.
    func setDailyGrams(_ grams: Int) {
        dailyNormGrams = max(0, grams)
        portionGrams = servingGrams
    }

    /// Задать порцию за раз — норма получается умножением.
    func setServingGrams(_ grams: Int) {
        setDailyGrams(max(0, grams) * max(1, mealsPerDay))
    }

    /// Держать расход единственного корма равным норме.
    ///
    /// Когда корм один, «сколько в день» у него — это и есть дневная норма,
    /// и отдельно её не спрашивают. Но норму можно поменять в режиме
    /// питания, и без этой синхронизации обратный отсчёт запаса продолжал
    /// бы считать по старой цифре — молча и незаметно.
    func syncSingleFoodShare() {
        guard stocks.count == 1 else { return }
        stocks[0].gramsPerDay = dailyGrams
    }

    /// Поменять число кормлений, не меняя, сколько собака съедает за сутки.
    ///
    /// Это и была самая обидная путаница: человек переводил щенка с двух
    /// кормлений на три, а приложение молча поднимало дневную еду
    /// в полтора раза — потому что хранило порцию, а не норму.
    func setMealsPerDay(_ count: Int) {
        let daily = dailyGrams
        mealsPerDay = max(1, count)
        setDailyGrams(daily)
    }

    /// Норма воды примерно 50 мл на килограмм — используется только как ориентир
    /// в поездке, где смена воды чаще всего даёт сбой.
    var waterNormMl: Int { Int((weightKg * 50).rounded()) }

    /// Сколько часов в сутках собака бодрствует. Меньше шести не бывает —
    /// это защита от опечатки, а не медицинская норма.
    ///
    /// Считает `MealSchedule`, а не эта строка: ровно то же «от подъёма
    /// до отбоя по кругу суток» стояло ещё в `ScheduleDraft.awakeMinutes`
    /// и внутри `MealSchedule.latestMeal` — три копии одного правила
    /// на 28.10.2026.
    var awakeMinutes: Int {
        MealSchedule.awakeMinutes(wake: wakeMinuteOfDay, sleep: sleepMinuteOfDay)
    }

    /// Кормления по суткам: ровный шаг, сокращённая ночь, последнее
    /// кормление с запасом до сна. Вся арифметика — в `MealSchedule`.
    func mealPlan(count: Int? = nil) -> MealSchedule.Plan {
        MealSchedule.plan(mealsPerDay: count ?? mealsPerDay,
                          wake: wakeMinuteOfDay,
                          sleep: sleepMinuteOfDay)
    }

    func evenMealTimes(count: Int? = nil) -> [Int] {
        mealPlan(count: count).times
    }

    /// **Ворота, а не показ.** `true` при отсутствующем коридоре —
    /// верно и нарочно: «коридора нет, не тревожь».
    ///
    /// Показу этого предиката НЕДОСТАТОЧНО, и это замерено:
    /// он отвечает `true` на **два разных состояния** — «вес внутри
    /// коридора» и «коридора не существует», — а экран печатал по нему
    /// «в норме». Для показа есть `weightVerdict` ниже; этот предикат
    /// оставлен как есть, потому что для ворот он прав.
    var isWeightInRange: Bool {
        guard let low = targetWeightLow, let high = targetWeightHigh else { return true }
        return weightKg >= low && weightKg <= high
    }

    /// Коридор веса в том же виде, в каком медслой держит норму анализа.
    ///
    /// **Форма не своя.** `LabNorm.Reference` уже различает «диапазон»
    /// и «нормы нет», и правило «нормы нет → так и скажи, а не „в
    /// норме“» в проекте записано, применено к анализам и **названо
    /// человеку вслух** (`LabResultScreens.swift:81`). Завести рядом
    /// свою копию трёх состояний значило бы повторить то, за что мы
    /// сегодня дважды заплатили: две реализации одного правила живут
    /// независимо, и вторая молчит.
    /// **Половина коридора считается его отсутствием, и это решение.**
    /// У `LabNorm.Reference` есть `.upperBound` и `.lowerBound`, и
    /// взять их было бы технически можно. Не берём: односторонний
    /// порог у анализа — это **форма бланка** («ТТГ `<0,50`»), а у веса
    /// коридор называет врач двумя числами. Одно заполненное поле
    /// значит «вводили и не дозаполнили», а не «врач назвал только
    /// низ», и строить из недозаполненной формы вердикт о весе значило
    /// бы угадать, что имел в виду человек.
    var weightReference: LabNorm.Reference {
        guard let low = targetWeightLow, let high = targetWeightHigh else { return .unknown }
        return .range(low: low, high: high)
    }

    /// Где собака в коридоре веса — **три состояния, а не два.**
    ///
    /// ```
    /// коридор есть, вес внутри    .withinRange
    /// коридор есть, вес снаружи   .below / .above
    /// КОРИДОРА НЕТ                .normUnknown   ← его и теряли
    /// ```
    ///
    /// **Цена третьего состояния названа не абстрактно:** вес — та
    /// величина, от которой считается доза лекарства. Зелёное «в норме»
    /// под весом, коридор которого никто не задавал, читает человек,
    /// принимающий решение о дозе. Это утверждение, которого приложение
    /// сделать не может.
    var weightVerdict: LabNorm.Deviation {
        LabNorm.deviation(value: .measured(weightKg), from: weightReference)
    }
}
