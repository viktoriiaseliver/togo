    /// У профиля нет поля, где «позже» было бы опасно: вес и порция —
    /// это факты, которые уточняют, а не мнения, которыми меняются.
    ///
    /// Ставится не на экранах, а в `FamilySync` при сохранении: профиль
    /// правят из полутора десятков мест прямыми привязками полей, и
    /// позвать «пометь изменённым» забудут ровно там, где это важнее.
    var changedAt: Date = Date()

    /// Надгробие удаления — разбор у `Medication.deletedAt`.
    /// Ставить только через `ОбщееУдаление`.
    ///
    /// **У собаки надгробие дороже всех одиннадцати, и вот чем.**
    /// Связи от неё идут с `deleteRule: .cascade`: жёсткое удаление
    /// собаки уносит её ленту, веса, дела, схемы и всю медкнижку.
    /// Мягкое — не уносит ничего, и это нарочно: надгробие на собаке
    /// значит «этой собаки у нас нет», а не «сотрите её историю
    /// у второго человека». Каскад по надгробию не ходит, и наводить
    /// его нельзя: чужие записи сносит человек у себя, а не мы за него.
    var deletedAt: Date?

