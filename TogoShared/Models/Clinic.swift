import Foundation
import SwiftData

/// Клиника или лаборатория — справочник, а не строка в каждой записи.
///
/// **Зачем справочник, а не текст.** В карте Стича одиннадцать
/// организаций, и каждая встречается в среднем в четырёх записях
/// (замер по медкнижке, §2.5 ТЗ). Без справочника человек наберёт
/// «Vet Riviera» двенадцать раз по-разному, и группировка сломается —
/// наш собственный класс, оплаченный сегодня четырьмя случаями:
/// ключ со значением по умолчанию собирает в одну группу всё, что это
/// поле не заполнило, а ключ, набранный руками, рассыпается на столько
/// групп, сколько было опечаток.
///
/// **`isLab` — из контракта дизайна, а не из ТЗ.** В `ClinicPicker.d.ts`
/// у клиники стоит `lab?: boolean`, и это различение в §2.5 ТЗ
/// отсутствует. Оно нужно: анализ сдают в лабораторию (IDEXX, Antech),
/// а приём идёт в клинику, и в выборе «где сдавали» и «кто принимал»
/// список должен быть разным. Назван здесь вслух, потому что поле,
/// приехавшее из экрана мимо ТЗ, иначе однажды прочтут как лишнее.
@Model
final class Clinic {
    var id: UUID = UUID()

    /// Как её называет человек. **Ключ группировки**, и потому
    /// непустота проверяется при вводе, а не здесь: пустое имя
    /// клиникой не является, и `Fmt.notBlank` — то же правило,
    /// что у клички собаки.
    var name: String = ""

    /// Город, адрес или чем она отличается от соседней с тем же именем.
    var detail: String?

    /// Лаборатория, а не клиника: туда сдают анализы, там не принимают.
    var isLab: Bool = false

    var phone: String?

    /// Когда запись завели на этом телефоне.
    var createdAt: Date = Date()

    /// Когда этот телефон в последний раз трогал запись.
    /// Нужно для спора двух телефонов, как у собаки и схемы лечения.
    var changedAt: Date = Date()

    /// Дела ухода, сделанные в этой клинике.
    ///
    /// **Обратная сторона связи обязательна, и это не стиль.** Зеркало
    /// CloudKit отказывается открывать хранилище, если у связи нет
    /// обратной: `CloudKit integration requires that all relationships
    /// have an inverse, the following do not: CareTask: clinic`. Замер
    /// `togo-1e` 07.10.2026 — и это был не красный тест, а **контейнер,
    /// не открывшийся вовсе**: у человека это молчаливый откат в память,
    /// рабочий экран, отметка дозы и запись в никуда.
    ///
    /// **`.nullify`, а НЕ `.cascade`, и здесь выбор дороже синтаксиса.**
    /// У одиннадцати связей `Dog` стоит каскад: события существуют
    /// только вместе с собакой. Клиника — наоборот: прививка остаётся
    /// фактом, даже если организацию убрали из справочника. Каскад
    /// здесь значил бы, что человек, прибирающий список клиник,
    /// стирает себе историю прививок, — а он уверен, что правит
    /// справочник.
    @Relationship(deleteRule: .nullify, inverse: \CareTask.clinic)
    var careTasksStorage: [CareTask]?

    /// Наружу — обычный массив: CloudKit требует опциональности
    /// у хранимого, остальному коду про это знать незачем.
    var careTasks: [CareTask] { careTasksStorage ?? [] }

    init(name: String, detail: String? = nil, isLab: Bool = false, phone: String? = nil) {
        self.name = name
        self.detail = detail
        self.isLab = isLab
        self.phone = phone
    }
}
