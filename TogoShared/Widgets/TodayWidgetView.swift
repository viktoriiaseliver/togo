import SwiftUI
import WidgetKit

/// Вид виджета «сегодня» — вынесен из `TogoWidgets` 05.10.2026,
/// переписан под «Кино» (iOS 28) 23.10.2026.
///
/// **Зачем переезд.** Виджет рисует SpringBoard, и `app.screenshot()`
/// до него не достаёт: три поверхности правила тишины (виджет,
/// «остров», лист вердикта) были закрыты сторожем только на уровне
/// строк. «Что человек УВИДИТ» не проверял никто, и не по недосмотру —
/// **смотреть было не на что**.
///
/// > Прежде чем проверять поверхность, проверь, что её МОЖНО проверить.
/// > Поверхность без кадра — не «непроверенная», а «непроверяемая»,
/// > и первое лечится взглядом, второе только переделкой входа.
///
/// **Семейство приходит значением, а не из среды.** `@Environment(\.widgetFamily)`
/// вне виджета не задать ничем надёжным, и вью, читающая его сама,
/// остаётся непроверяемой даже после переезда. Среду читает тонкая
/// обёртка на стороне `TogoWidgets`, здесь — обычный параметр.
///
/// **`now` тоже параметром.** Внутри стоял `Date()`, и строка про еду
/// меняла бы кадр каждый час: кадр, который нельзя повторить, нельзя
/// и сравнить.
///
/// ## Раскладка «Кино» — откуда числа
///
/// Эталон — `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/16.png`,
/// разметка — `Дизайн/редизайн-ios28/prototypes/Togo-RU.dc.html:326-330`.
///
/// ```
/// шапка плитки     13 / 600, Ink.secondary, значок 18, зазор 6
/// крупное число    40 / вес 300 / Rounded / tabular, line-height 1
/// подпись низа     13, Ink.secondary
/// отступ плитки    14          радиус 24 (ставит система виджета)
/// средний виджет   подпись 13/600 secondary + значение 17/600
/// ```
///
/// **Вес 300 у крупного числа — исключение, записанное решением:**
/// «Время и важные значения — всегда semibold», и тут же «Крупные
/// показания Rounded 300 — исключение» (`Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`).
///
/// ## Чего в этой раскладке НЕТ, и почему это решения
///
/// **Полосы-косточки нет.** В макете под числом лежит полоса
/// (`width:{{ b.pct }}`, заливка `var(--text-link)` = `#A2C1FE`).
/// У полосы нужен **знаменатель** — сколько времени считается полным
/// интервалом между выходами. В снимке его нет, и вывести его здесь
/// было бы третьей реализацией правила: Того уже обжигался на том,
/// что виджет считал окно «не кормить» собственной арифметикой
/// и молчал в двух случаях из трёх. В прототипе `pct` приходит
/// из панели показания «Сегодня» (`ReadingTone`), то есть считает
/// его приложение. **Появится в снимке процент — полоса станет
/// пятью строками.**
///
/// **Плитки «Доза» нет.** В макете вторая плитка — час дозы
/// и «левотироксин 0,1 мг». В `WidgetSnapshot` про лекарства нет
/// ни одного поля (замер 23.10: `dose|доза|drug|medic` → 0 вхождений
/// при контроле `walk` → 7). Нарисовать её значило бы завести
/// **механизм без входа**, а подставить дозу — нарушить красную линию
/// «не подставлять там, где подстановка станет утверждением человека»:
/// запись потом читает врач.
///
/// **Кнопки «Гулять» нет.** `Button(intent:)` требует, чтобы тип
/// интента был собран В РАСШИРЕНИИ. `StartWalkIntent` живёт
/// в `Togo/Intents/WalkIntents.swift`, то есть в приложении, и тянет
/// за собой `Persistence`, `ModelContext` и `QuickLog`. Перенести его
/// в общий слой значит завести SwiftData в расширение — а это прямо
/// отменяет записанное устройство: «виджет не лезет в базу… так виджет
/// не зависит от схемы SwiftData и не может подвиснуть на миграции».
/// ~~Второй путь — `Link` на `togo://walk`, но такой ссылки приложение
/// не обрабатывает (`RootView:139` знает только `join`).~~
/// **ПОСЫЛКА УМЕРЛА, И УМЕРЛА В ДЕНЬ, КОГДА БЫЛА НАПИСАНА.** Замер
/// 24.10.2026: хост `walk` разобран `RootView.адресат(_:)` с коммита
/// `7c84552` (23.10) и ведёт на `.прогулка` → вкладка «Сегодня» +
/// `открытьПрогулку`. Адрес `RootView:139` тоже устарел — там теперь
/// строка про вкладку.
///
/// ```sh
/// # замер 24.10.2026, контроль в той же команде
/// git log -1 -S'case "walk"' -- Togo/App/RootView.swift   # 7c84552, 23.10
/// git log -1 -- Togo/App/RootView.swift                   # контроль: 3297ad8, путь живой
/// ```
///
/// Это наш класс «**условие, привязанное к наличию инструмента,
/// при его появлении меняет знак**» — из запрета в разрешение,
/// и ровно в тот момент, когда никто не ждёт плохих новостей: запрет
/// писали и инструмент заводили в один день, две разные руки.
///
/// > **Запрет снят, решение НЕ принято — и это разные вещи.** Вторая
/// > половина довода пережила посылку и держится сама: `Link` **открыл
/// > бы приложение**, а макет обещает отметку, не переход. То есть
/// > `togo://walk` годится для кнопки «открыть прогулку» и не годится
/// > для кнопки «начать прогулку», которую рисует макет. Чем из двух
/// > это должно быть — слово дизайна, не моё.
///
/// Оба пути меняют чужие решения — **называю, а не выбираю молча.**
struct TodayWidgetView: View {
    let snapshot: WidgetSnapshot
    let family: WidgetFamily
    var now: Date = Date()

    var body: some View {
        switch family {
        case .accessoryInline:
            Text(SnapshotText.inlineText(snapshot))
        case .accessoryRectangular:
            // Аксессуары локскрана система рисует своим вибрантным
            // монохромом: наши цвета туда не доезжают как цвета,
            // и красить их значило бы объявить управление, которого нет.
            // Поэтому здесь только иерархия кеглей, без токенов цвета.
            VStack(alignment: .leading, spacing: 2) {
                Text(snapshot.verdictTitle).font(.headline)
                Text(SnapshotText.sinceText(snapshot)).font(.caption)
                Text(SnapshotText.mealLine(snapshot, now: now)).font(.caption2)
            }
        case .systemMedium:
            средний
        default:
            малый
        }
    }

    // MARK: - Что показывает крупное число

    /// Три состояния с числом и одно без него.
    ///
    /// **Порядок не случаен.** Идущий выход старше всего: он
    /// единственный меняется ежесекундно и единственный говорит
    /// «прямо сейчас». Дальше — время с последнего выхода, ради
    /// которого плитка и нарисована в макете. Если не отмечали
    /// ни разу, числа нет вовсе, и плитка переходит на слова: это
    /// та самая ступень тишины, ради которой заводилась галерея.
    private enum Показание {
        case наУлице(с: Date)
        case сПрогулки(с: Date)
        case словами
    }

    private var показание: Показание {
        if let начало = snapshot.walkStartedAt { return .наУлице(с: начало) }
        if let последний = snapshot.lastWalkAt { return .сПрогулки(с: последний) }
        return .словами
    }

    private var шапкаПлитки: (String, String) {
        switch показание {
        case .наУлице: (String(localized: "На улице"), "figure.walk")
        case .сПрогулки: (String(localized: "С прогулки"), "figure.walk")
        case .словами: (snapshot.verdictTitle, "pawprint")
        }
    }

    // MARK: - Малый

    private var малый: some View {
        VStack(alignment: .leading, spacing: Token.Space.s8) {
            шапка
            Spacer(minLength: 0)
            крупное
            Spacer(minLength: 0)
            подписьНиза
        }
    }

    private var шапка: some View {
        let (текст, значок) = шапкаПлитки
        return HStack(spacing: Token.Space.s6) {
            Image(systemName: значок)
                .font(.system(size: 18, weight: .regular))
            Text(текст)
                .font(.system(size: 13, weight: .semibold))
                .lineLimit(1)
                .minimumScaleFactor(0.8)
        }
        .foregroundStyle(Token.Ink.secondary)
    }

    /// Крупное показание — или строка тишины, если считать нечего.
    ///
    /// **Ужимается, а не обрезается.** Обрезка у часов превращает одно
    /// число в другое, и читается оно как правда; ужатие оставляет
    /// то же число мелким.
    ///
    /// ## Два показания разной природы, и формат у них разный
    ///
    /// **Идущий выход — живой `Text(_, style: .timer)`.** Он тикает
    /// без пробуждения виджета, и секунды здесь настоящие. Форма
    /// совпадает с макетом: до часа `.timer` печатает «12:34», ровно
    /// как на эталоне живой активности.
    ///
    /// **Время с прогулки — `Fmt.hoursMinutes`, и дизайн это
    /// подтвердила 23.10.** Было названо как РАСХОЖДЕНИЕ С МАКЕТОМ
    /// («на эталоне `16.png` стоит „2:11"»), и ответ круга 2, §7
    /// снимает макет, а не нас:
    ///
    /// > «Словами: „47 мин", „2 ч 11 мин". „2:11" на кадре 16
    /// > не держим. **Формат один, в `Fmt`.**»
    ///
    /// Обе названные формы — ровно то, что печатает `Fmt.hoursMinutes`
    /// (через общий `часыМинуты`): 47 мин → «47 мин», 2 ч 11 мин →
    /// «2 ч 11 мин». **Переделывать нечего, и своего формата здесь
    /// по-прежнему нет ни одного** — замер 23.10 по трём каталогам
    /// (`TogoShared/Widgets`, `TogoShared/LiveActivity`, `TogoWidgets`)
    /// искал ручную сборку длительности: печать строкой по шаблону,
    /// системный форматировщик компонент даты, прямой вызов стиля
    /// единиц, склеенные руками «ч» и «мин».
    ///
    /// ```
    /// предмет              0 вхождений в коде
    /// контроль `Fmt.`      16 в двух каталогах   ← инструмент видит
    /// контроль третий      TogoWidgets виден: 12 вхождений `Token.`
    /// отрицательный        rc=1, пусто
    /// ```
    ///
    /// Контроли стоят рядом нарочно: у `git grep` «не найдено» — это
    /// штатный `rc=1`, то есть ложный ноль здесь неотличим от правды
    /// без второго вопроса с известным заранее ответом. И повторять
    /// замер надо **по коду без комментариев**: эта самая строка
    /// описывает искомое словами, чтобы не стать его вхождением.
    ///
    /// Ниже — разбор, оставленный целиком: он объясняет, ПОЧЕМУ здесь
    /// не `.timer`, и этот довод от ответа дизайна не зависит.
    /// Поставить туда `.timer` я пробовал — кадр показал «2:11:00»:
    ///
    /// ```
    /// .timer при интервале < часа   12:34      мм:сс   ← совпало с макетом
    /// .timer при интервале > часа   2:11:00    ч:мм:сс ← НЕ совпало
    /// ```
    ///
    /// Два довода против того, чтобы подгонять:
    ///
    /// 1. **Секунды здесь — ложная точность.** Снимок пересобирается
    ///    раз в пятнадцать минут, и всё остальное на плитке (еда,
    ///    вердикт, окно натощак) этого возраста. Тикающие секунды рядом
    ///    со стоящими пятнадцатью минутами обещают точность, которой
    ///    на плитке нет.
    /// 2. **«2:11» читается как ЧАС НА ЧАСАХ.** Рядом значок человечка:
    ///    «гуляли в 2:11» — ровно то прочтение, от которого у нас
    ///    заведено правило печатать слово исхода рядом с числом.
    ///    «2 ч 11 мин» двусмысленным не бывает.
    ///
    /// Своего формата я не завожу нарочно: «ч:мм» двоеточием у нас
    /// не печатает никто, а вторая реализация форматирования — наша
    /// записанная болезнь («правку сделали на одной поверхности
    /// из трёх»). Единицы печатает система, то есть строка переводится.
    ///
    /// ## ГДЕ WIDGETKIT НЕ УМЕЕТ НАРИСОВАННОГО
    ///
    /// «Формат один, в `Fmt`» держится для всякой **стоящей**
    /// длительности и **не может** держаться для **идущей**.
    /// Самообновляющийся текст в WidgetKit бывает ровно трёх видов —
    /// `Text(_, style: .timer)`, `.relative`, `.offset`, — и ни один
    /// из них не спрашивает `Fmt`: формат им выбирает система.
    /// Строка, собранная `Fmt` на отрисовке, **замирает** до следующего
    /// пересбора снимка (у виджета это раз в пятнадцать минут,
    /// у живой активности — до следующего обновления от приложения).
    ///
    /// ```
    /// идущий выход   .timer   «23:14» тикает сам      формат НЕ из Fmt
    /// с прогулки     Fmt      «2 ч 11 мин» стоит      формат из Fmt
    /// ```
    ///
    /// Выбор здесь не между «красиво» и «правильно», а между «тикает»
    /// и «словами»: у идущего выхода человек смотрит на секунды,
    /// и замершее «23 мин» было бы неверным числом, а не грубым.
    /// **Названо, а не подогнано** — ровно как просила дизайн про
    /// границы мокапа.
    ///
    /// > **Перемер по переснятому эталону снимает последнее сомнение.**
    /// > `16.png` пересняли 23.10 (`401e496`, все восемнадцать), и на
    /// > новой редакции стоит ровно это разделение: плитка виджета —
    /// > «С прогулки · **2 ч 10 мин**», словами; таймер живой активности
    /// > рядом — «**12:34**», цифрами. То есть дизайн и сама держит
    /// > цифры у тикающего, а слова у стоящего, и спора здесь нет.
    ///
    /// Кегль у слов меньше (28 против 40): «2 ч 11 мин» вдвое длиннее
    /// «12:34», и на плитке 158 pt сорокапунктовое ужалось бы
    /// до нечитаемого. Это не два разных решения о размере, а одно —
    /// «крупнейшее, что влезает целиком».
    @ViewBuilder
    private var крупное: some View {
        switch показание {
        case .наУлице(let с):
            Text(с, style: .timer)
                .font(.system(size: 40, weight: .light, design: .rounded).monospacedDigit())
                .foregroundStyle(Token.Ink.primary)
                .lineLimit(1)
                .minimumScaleFactor(0.5)
        case .сПрогулки(let с):
            Text(Fmt.hoursMinutes(now.timeIntervalSince(с)))
                .font(.system(size: 28, weight: .light, design: .rounded).monospacedDigit())
                .foregroundStyle(Token.Ink.primary)
                .lineLimit(1)
                .minimumScaleFactor(0.5)
        case .словами:
            // Числа нет — и подставлять его неоткуда. Тишина говорится
            // словами той же функцией, что на локскране и в «острове»:
            // `sinceText` знает, что при отсутствии отметок печатается
            // дата, а не посчитанный интервал.
            Text(SnapshotText.sinceText(snapshot))
                .font(.system(size: 17, weight: .semibold))
                .foregroundStyle(Token.Ink.primary)
                .lineLimit(3)
                .minimumScaleFactor(0.8)
        }
    }

    /// Низ плитки: окно «не кормить» важнее строки про еду.
    ///
    /// Решение приезжает готовым: `fastingEndsAt` считает приложение
    /// тем же правилом, что и главный экран. Своей арифметики у виджета
    /// нет нарочно — на ней он однажды уже молчал в двух случаях из трёх.
    @ViewBuilder
    private var подписьНиза: some View {
        if let натощак = snapshot.fastingEndsAt, натощак > now {
            Label {
                // Через `String(localized:)` и `Fmt.clock`, а не
                // `Text(fasting, style: .time)`. Ключ получается тот же
                // (`не кормить до %@`), переводы уже лежат — но путь
                // в каталог теперь виден и сторожу, и человеку.
                Text(String(localized: "не кормить до \(Fmt.clock(натощак))"))
            } icon: {
                Image(systemName: "clock.badge.exclamationmark")
            }
            .font(.system(size: 13, weight: .medium))
            .foregroundStyle(Token.Status.waitingText)
            // **Две строки, а не одна, и это поймал кадр.** При
            // `lineLimit(1)` на плитке 158 pt выходило
            // «не кормить до 21:…» — обрезан ЧАС, то есть ровно то
            // единственное, ради чего строку читают. Остальное
            // («не кормить») человек и так знает из значка.
            //
            // > У нас записано: «в хвост идёт то, что деградирует,
            // > оставаясь полезным» (`SnapshotText.inlineText`, замер
            // > по лестнице ширин 05.10). Здесь в хвосте стояло
            // > НЕЗАМЕНИМОЕ, и обрезка убивала строку целиком.
            //
            // Перенос дешевле сокращения: своей фразы заводить
            // не надо, ключ и переводы остаются те же.
            .lineLimit(2)
            .minimumScaleFactor(0.8)
        } else {
            Text(SnapshotText.mealLine(snapshot, now: now))
                .font(.system(size: 13))
                .foregroundStyle(Token.Ink.secondary)
                .lineLimit(2)
        }
    }

    // MARK: - Средний

    /// Средний виджет: слева подпись и значение, справа крупное число.
    ///
    /// Макет кладёт справа белую пилюлю «Гулять»; её здесь нет,
    /// и причина названа в голове файла. Пустое место отдано числу —
    /// тому же, что в малом, — чтобы средний отвечал на тот же вопрос
    /// крупнее, а не говорил меньше малого.
    private var средний: some View {
        HStack(alignment: .center, spacing: Token.Space.s12) {
            VStack(alignment: .leading, spacing: Token.Space.s2) {
                Text(подписьДальше)
                    .font(.system(size: 13, weight: .semibold))
                    .foregroundStyle(Token.Ink.secondary)
                    .lineLimit(1)
                    .minimumScaleFactor(0.8)
                Text(snapshot.verdictTitle)
                    .font(.system(size: 17, weight: .semibold))
                    .foregroundStyle(Token.Ink.primary)
                    .lineLimit(2)
                подписьНиза
            }
            Spacer(minLength: Token.Space.s8)
            крупное
                .layoutPriority(1)
        }
    }

    /// «Стич · дальше» — кличка через `Fmt.dogName`, без именительного
    /// отката.
    ///
    /// `dogNameOrFallback` здесь не годится: «Собака · дальше» читается
    /// как вторая собака по имени «Собака», а не как отсутствие клички.
    /// Отзыв 06.10 был ровно про безымянные записи.
    private var подписьДальше: String {
        guard let кличка = Fmt.dogName(snapshot.dogName) else {
            return String(localized: "дальше")
        }
        return кличка + " · " + String(localized: "дальше")
    }
}
