import SwiftUI

nonisolated extension Color {
    /// Единственное место, где в приложении разбирается hex.
    /// Сырые значения приходят только из сгенерированных токенов.
    /// `0xRRGGBB` или `0xRRGGBBAA`.
    ///
    /// Прозрачность нужна тёмной теме: вторичный текст, хайрлайны
    /// и тинты в ней заданы не своим цветом, а долей белого поверх
    /// поверхности. Записывать их сплошным хексом значило бы привязать
    /// каждый к той поверхности, над которой его посчитали.
    ///
    /// # Здесь НЕТ угадывания разрядности, и это починка 23.10.2026
    ///
    /// Стояло `hasAlpha = hex > 0xFFFFFF` — решение про альфу по величине
    /// числа. У `UInt32` ведущих нулей нет: `0x0000008C` это 140,
    /// что ≤ 0xFFFFFF, альфы «нет», и чёрный под 55 % рисовался
    /// непрозрачным синим `#00008C`.
    ///
    /// ```
    /// восьмизначных литералов   55
    /// ТЕРЯЛИ АЛЬФУ              16 вхождений, 9 значений
    /// контроль — не теряли      39, например 0x10111252
    /// худшее  0x000000FF → #0000FF  ЧИСТЫЙ СИНИЙ вместо чёрного
    /// ```
    ///
    /// Разрядность не восстановить из числа — она теряется при переводе
    /// строки в `UInt32`. Поэтому её не угадывают здесь, а сохраняют
    /// раньше: `Tools/generate_tokens.py` дополняет шестизначные до
    /// `0xRRGGBBAA` на входе, пока значение ещё строка. Этот
    /// инициализатор принимает **только восемь разрядов** и ничего
    /// не решает.
    ///
    /// > Проверка, что соглашение соблюдено, стоит не здесь: число,
    /// > записанное шестью разрядами, тут неотличимо от восьми
    /// > с нулевой альфой. Её место — сторож по сгенерированному файлу.
    init(hex: UInt32) {
        let value = hex
        self.init(
            .sRGB,
            red: Double((value >> 24) & 0xFF) / 255,
            green: Double((value >> 16) & 0xFF) / 255,
            blue: Double((value >> 8) & 0xFF) / 255,
            opacity: Double(value & 0xFF) / 255
        )
    }
}
