/// Вид живой активности «выход идёт» — вынесен из `TogoWidgets` 07.10.2026,
/// переписан под «Кино» (iOS 28) 23.10.2026.
///
/// **Зачем переезд, и это не аккуратность.** До него карточка «острова»
/// принимала `ActivityViewContext<WalkActivityAttributes>`, а его **вне
/// живой активности не построить ничем** — ни тестом, ни превью,
/// ни галереей. То есть поверхность, которую человек видит, когда
/// телефон лежит в кармане на улице, была единственной в продукте,
/// которую нельзя принять кадром: ни подписей, ни кнопок, ни контраста
/// на ней не проверял глазами никто, потому что было нечем.
///
/// > **Поверхность без кадра — это не «непроверенная», а
/// > «непроверяемая».** Первое лечится взглядом, второе только
/// > переделкой входа.
///
/// Цена такой поверхности у нас уже оплачена, на соседнем проекте:
/// у Timer карточка Live Activity была ровно в этом положении,
/// и отзыв «проблемы с виджетом» жил незамеченным не потому, что плохо
/// смотрели, а потому что смотреть было не на что.
///
/// **Вид не знает ни про `ActivityKit`, ни про контекст.** Он принимает
/// четыре обычных значения, и это нарочно: пока в нём оставалась хоть
/// одна строка, читающая среду, его нельзя было построить в галерее —
/// вернулась бы и непроверяемость. Расширение превращает контекст
/// в значения и больше не делает ничего.
///
/// ## Раскладка «Кино» — откуда числа
///
/// Эталон — `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/16.png`
/// («Виджеты и Live Activity»), разметка — `Дизайн/редизайн-ios28/
/// prototypes/Togo-RU.dc.html:332-335`. Числа сняты **замером пикселя
/// на кадре**, а не глазами, и сошлись с разметкой пакета:
///
/// > **`16.png` ЭТАЛОНОМ БОЛЬШЕ НЕ СЛУЖИТ — и это не «кадр плохой»,
/// > а «кадр показывает снятые решения»** (`Дизайн/эталонные-кадры/
/// > ios28-кино-22.10/ПОДПИСИ.md`, раздел про 16). Ответами дизайна
/// > 23.10 с него сняты ровно три вещи: старая пилюля (лапа · «Стич» ·
/// > белое время), кнопка «Домой» на блокировке и «2:11» вместо слов.
/// > **Геометрия, кегли и раскладка на нём по-прежнему годны** — числа
/// > ниже взяты именно оттуда и остаются в силе. Пилюля сверяется
/// > по `08.png`. Прототипы `prototypes/*.dc.html` страдают тем же:
/// > в них та же старая пилюля и «Домой».
/// >
/// > У «устарел целиком» и «устарели три строки» разная цена,
/// > и вторую надо называть точно.
///
/// ```
/// фон карточки      #000000  → Token.Surface.screen   (night1 dark)
/// подпись           #C7C7CC  → Token.Ink.secondary    (inkMuted) ТОЧНО
/// тёмная кнопка     #2C2C2E  → Token.Surface.raised   (night3)   ТОЧНО
/// белая кнопка      #FFFFFF  → Token.Action.primary   (arctic dark)
/// текст на белой    #111111  → Token.Ink.onAccent     (arcticInk) ТОЧНО
/// жетон             44×44, круг        заголовок 15/600
/// таймер            34 / вес 300 / Rounded / tabular
/// кнопки            высота 44, радиус 999, 15/600, значок 20, зазор 8
/// отступ карточки   16, зазор строк 12
/// ```
///
/// **Вес 300 у таймера — это исключение, записанное решением**, а не
/// промах: «Время и важные значения — всегда semibold», и тут же
/// «Крупные показания Rounded 300 — исключение»
/// (`Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`). Поэтому `.light`, а не `.semibold`.
///
/// **Радиуса карточки здесь НЕТ нарочно.** В макете он `28px`, но форму
/// живой активности рисует система и обрезает содержимое сама; задать
/// его отсюда значило бы объявить управление, которого нет. То же
/// про фон: `.activityBackgroundTint` — это **просьба**, а не результат.
///
/// ## Чего этот вид НЕ делает, и это решения, а не недоделки
///
/// **Кнопки «Домой» нет, и это больше не наш суд — это ответ дизайна.**
/// В макете вторая кнопка белая «Домой», то есть конец прогулки
/// с заблокированного экрана. У нас записано обратное: итог выхода
/// спрашивается **один раз и только в приложении**, когда человек уже
/// вернулся и остановился — у необратимого действия адресат
/// предупреждения тот, кто его совершает, а на блокировке его никто
/// не предупредит.
///
/// ```
/// круг 2, §6   «Остаёмся на вашем правиле… только отметки:
///              „Пописал" и „Стул", обе ВТОРИЧНОЙ заливкой.
///              „Домой" убираем»            ОТВЕТЫ-круг-2.md
/// круг 3, §1   «Подтверждаю ответ круга 2: правило „необратимое
///              предупреждает ДО" сильнее макета… Конец прогулки —
///              в приложении: тап по активности → „На улице" →
///              слайдер „Домой" → итог. Кадр 16 устарел»
///                                          ОТВЕТЫ-круг-3.md
/// ```
///
/// Обе кнопки — отметки, и обе `Surface.raised`, то есть вторичная
/// заливка: это теперь не наш вывод «у двух равных отметок старшей
/// нет», а **названное требование дизайна**. Белая в макете
/// принадлежала «Домой», которой нет.
///
/// **Переделывать тут нечего — проверено, а не предположено:** решение
/// принято сессией виджетов 23.10 своим судом, дизайн согласилась
/// по той же формулировке.
///
/// **Жетон рисует букву, а не фото.** В макете там `stitch-avatar.png`.
/// У нас фото собаки до этой поверхности не доходит дважды:
/// `WalkActivityAttributes` его не несёт вовсе, и — глубже — у `Dog.photo`
/// **нет входа**. Замер 23.10.2026 с контролями:
///
/// ```
/// git grep -P '\.photo\s*=\s'      2 писателя: OnboardingFlow:299
///                                  (из DogDraft.photo) и Backup:563
/// DogDraft.photo                   объявлено и ПРОЧИТАНО, не записано
///                                  ни разу: `photo` в Onboarding/*.swift
///                                  встречается 2 раза — объявление и чтение
/// PhotosPicker по дереву           2 места, оба чужие (фон и документы)
/// контроль .name= 57 · .breed= 11 · отрицательный 0
/// ```
///
/// То есть при свежей установке `Dog.photo` всегда `nil`, и нарисовать
/// фото было бы **механизмом без входа**: отличить его от рабочего
/// нельзя ни тестом, ни компилятором.
///
/// > **Вход назван дизайном 23.10 (круг 2, §9) и на 23.10 ещё
/// > не заведён:** `PhotosPicker` на вкладке собаки плюс тап по пустому
/// > аватару-жетону в шапке «Сегодня». Оба места — чужие файлы
/// > (`Togo/Features/**`). Пока входа нет, жетон рисует букву, и это
/// > по-прежнему решение, а не недоделка.
/// >
/// > **И когда вход появится, фото сюда поедет НЕ полноразмерным.**
/// > Расширение живёт в жёстком пределе памяти: снимок 3000 px
/// > разворачивается примерно в 36 МБ и убивает его молча. Договор
/// > проекта — 1000 px, JPEG 0,8 (тот же, что у фона приложения).
/// > `WalkActivityAttributes` сегодня фото не несёт вовсе, и заводить
/// > поле раньше ужимателя нельзя.
///
/// **Подпись осталась «кто вывел», а не «вышли в 19:52», и дизайн
/// с этим согласилась** (круг 2, §8: «„вышли в 19:52" — упрощение
/// макета, а не замена. Подзаголовок — **кто вывел**, в вашей
/// формулировке. Время показывает таймер»). В макете подзаголовок
/// нёс ВРЕМЯ. Рядом с ним стоит таймер, который время уже показывает, —
/// а КТО вывел не показывает больше ничто, и ради этого живая
/// активность и заведена («не спрашивать „ты уже вывела?“
/// в мессенджере»). **Переделывать нечего: сделанное совпало
/// с ответом.**
public struct WalkActivityView: View {
    public let dogName: String
    public let startedBy: String
    public let startedAt: Date
    public let tally: String?

    public init(dogName: String, startedBy: String, startedAt: Date, tally: String?) {
        self.dogName = dogName
        self.startedBy = startedBy
        self.startedAt = startedAt
        self.tally = tally
    }

    /// Заголовок карточки: «Прогулка · Стич».
    ///
    /// Кличка через `Fmt.dogName`, а не `dogNameOrFallback`: при пустой
    /// кличке строка обязана остаться «Прогулка», а не стать
    /// «Прогулка · Собака» — именительный откат тут читается как вторая
    /// собака по имени «Собака». Отзыв 06.10 был ровно про безымянные
    /// записи, и это самая тесная поверхность, куда такой дефект выходит.
    public var заголовок: String {
        guard let кличка = Fmt.dogName(dogName) else {
            return String(localized: "Прогулка")
        }
        return String(localized: "Прогулка") + " · " + кличка
    }

    /// Подпись под заголовком: что успели отметить, иначе — кто вывел.
    ///
    /// Своя защита нужна потому, что вид принимает значение от кого
    /// угодно: место вызова (`LiveActivityController`) кличку уже
    /// защищает, но функция обязана держаться сама — ровно так защищены
    /// `SnapshotText.inlineText` и текст уведомления натощак. Без неё
    /// при пустой кличке строка читалась бы «Виктория вывела »,
    /// с висящим пробелом вместо имени.
    ///
    /// **Откат падежный, и это не придирка — это кадр 07.10.2026.**
    /// Первая редакция ставила сюда `Fmt.dogNameOrFallback`, то есть
    /// именительное «Собака», и галерея показала «Виктория вывела
    /// **Собака**». Висящий пробел я убрала и завела неграмотность:
    /// слот здесь винительный, а запасное слово написано для слотов
    /// именительных — заголовка профиля и подписи вкладки.
    ///
    /// > **Кадр поймал то, чего не видел ни один сторож:** строка
    /// > непустая, кличка подставлена, разделитель на месте —
    /// > и по-русски так не говорят.
    ///
    /// **Откат идёт через каталог — правка 07.10.2026, `togo-08`.**
    /// `"собаку"` в каталог не шло вовсе, и француз с украинцем видели
    /// русское слово в «острове».
    public var подпись: String {
        Self.подпись(startedBy: startedBy, dogName: dogName, tally: tally)
    }

    /// Единственная реализация правила «что написано под заголовком».
    ///
    /// **Вынесено в `static` 23.10.2026, и повод — не аккуратность,
    /// а найденный дефект.** У развёрнутого «острова»
    /// (`WalkIslandView.Bottom`) была СВОЯ, вторая реализация той же
    /// подписи, и она **не читала `startedBy` вовсе**: поле объявлено,
    /// передано из `WalkLiveActivity`, и ни одного читателя. Замер
    /// 23.10 грепом по `TogoShared/LiveActivity`: все вхождения
    /// `startedBy` — объявление, инициализатор, присваивание; чтений
    /// ровно два, и оба в этом файле выше, то есть на локскране.
    ///
    /// > **Поле без читателя грепом находится, а видом — нет:** имя
    /// > встречается, значение приезжает, вызова нет. Снаружи это
    /// > выглядело как «в „острове" подпись просто короче».
    ///
    /// Цена дефекта названа самой дизайном (круг 2, §8): подзаголовок —
    /// **кто вывел**, время показывает таймер. «Вывел Стича» без имени
    /// человека роняет ровно тот единственный семейный сигнал, ради
    /// которого живая активность и заведена, — и роняет его на той
    /// поверхности, где текста и так меньше всего.
    ///
    /// **Две целые фразы, а не слово в дырке.** Откат словом —
    /// `… вывела \(кличка ?? "собаку")` — закрывает ключ и НЕ закрывает
    /// человека: сама фраза собиралась бы обычным литералом и в каталог
    /// не шла вовсе, а готовый перевод ключа `%@ вывела %@`
    /// (fr `%@ a sorti %@`, uk `%@ вивела %@`) лежал и не вызывался
    /// ни разу. Целая фраза несёт падеж сама.
    ///
    /// **Все четыре ключа уже в каталоге на четырёх языках** — замер
    /// 23.10 по `Localizable.xcstrings`, контроль на заведомо живом
    /// ключе «На улице» и отрицательный контроль. Поэтому правка
    /// не трогает каталог и не требует `make texts`, который портит
    /// общий файл всем. (Казахского у этих ключей нет — это известный
    /// долг перевода, а не след этой правки.)
    ///
    /// Имя человека защищается так же, как кличка, и по той же причине:
    /// функция обязана держаться сама. При пустом `startedBy` остаётся
    /// **короткая форма** — та, что до 23.10 жила в «острове»; ключи
    /// у неё переведены, и место им нашлось настоящее.
    nonisolated static func подпись(startedBy: String,
                                    dogName: String,
                                    tally: String?) -> String {
        if let tally { return tally }
        let кличка = Fmt.dogName(dogName)
        guard let кто = Fmt.notBlank(startedBy) else {
            guard let кличка else { return String(localized: "вывел собаку") }
            return String(localized: "вывел \(кличка)")
        }
        guard let кличка else { return String(localized: "\(кто) вывела собаку") }
        return String(localized: "\(кто) вывела \(кличка)")
    }

    public var body: some View {
        VStack(alignment: .leading, spacing: Token.Space.s12) {
            HStack(spacing: Token.Space.s12) {
                жетон
                VStack(alignment: .leading, spacing: Token.Space.s2) {
                    Text(заголовок)
                        .font(.system(size: 15, weight: .semibold))
                        .foregroundStyle(Token.Ink.primary)
                        .lineLimit(1)
                    Text(подпись)
                        .font(.system(size: 13))
                        .foregroundStyle(Token.Ink.secondary)
                        .lineLimit(1)
                }
                Spacer(minLength: Token.Space.s8)
                // **Таймер ужимается, а не обрезается.** Прогулка
                // длиннее часа даёт «1:23:45» — на треть шире, чем
                // «12:34», под который считан макет. Обрезанное время
                // («1:23:4…») читается как другое число, а ужатое —
                // как то же самое; у часов это разница между неверным
                // показанием и мелким.
                Text(startedAt, style: .timer)
                    .font(.system(size: 34, weight: .light, design: .rounded).monospacedDigit())
                    .foregroundStyle(Token.Ink.primary)
                    .lineLimit(1)
                    .minimumScaleFactor(0.6)
                    .layoutPriority(1)
            }
            WalkMarkButtons()
        }
        .padding(Token.Space.s16)
    }

    /// Круглый жетон с буквой клички — 44 pt по макету.
    ///
    /// Буква берёт `Ink.primary`, то есть переворачивается вместе
    /// с темой. Прибитый белый здесь уже стоил дефекта на соседней
    /// поверхности: в виджете подложка `Action.done` на светлой теме
    /// композитилась в `#E7F5EF`, и белая буква давала **1,12:1**.
    private var жетон: some View {
        Text(Fmt.dogName(dogName).map { String($0.prefix(1)).uppercased() } ?? "•")
            .font(.system(size: 17, weight: .semibold))
            .foregroundStyle(Token.Ink.primary)
            .frame(width: 44, height: 44)
            .background(Token.Surface.raised, in: Circle())
            .accessibilityHidden(true)
    }
}

/// Развёрнутый «остров»: три области, каждая своим видом.
///
/// Разделены потому, что `DynamicIslandExpandedRegion` принимает
/// содержимое по одной области и собрать их в один вид нельзя —
/// а значит кадром надо брать каждую отдельно, иначе «сняли остров»
/// будет значить «сняли одну треть».
///
/// **Компактные части лежат здесь же с 23.10.2026, и это починка
/// по правилу самого файла.** До неё `compactLeading`/`compactTrailing`/
/// `minimal` были написаны прямо в `WalkLiveActivity.swift`, то есть
/// в расширении, — а у обёртки записано условие: «появится здесь логика
/// или хоть одна подпись — вернётся и непроверяемость». Редизайн
/// добавляет компактной части и подпись («На улице»), и цвет, то есть
/// ровно то, ради чего условие и писалось. Теперь они строятся
/// значениями и попадают под кадр.
public enum WalkIslandView {

    /// Зелёный компактного «острова».
    ///
    /// **В макете это `#7CE0A0` — цвет КАТЕГОРИИ «выход»**
    /// (`--cat-walk`), а не разовый оттенок: в пакете он встречается
    /// шесть раз.
    ///
    /// ## Дизайн ответила, и ответ снимает прежнюю замену
    ///
    /// Круг 2, §5, дословно: «`category.*` переводим в семантику:
    /// `Token.Category.walk` = #7CE0A0… Значение одно во всех режимах,
    /// на #000 контраст 13:1. **Виджету и Live Activity — можно.**
    /// `Action.doneText` для выхода **не использовать: это другая
    /// роль**.»
    ///
    /// То есть прежний довод «ближайший семантический — `Action.doneText`
    /// (`spruceText`, `#7FD3A8`)» теперь **прямо отменён**: совпадение
    /// оттенка не делает роль той же. «Выполнено» и «выход» — две разные
    /// вещи, и красить одну именем другой значит завести расхождение,
    /// которое не покраснеет никогда.
    ///
    /// ## Почему не компонентный токен того же значения
    ///
    /// `Token.Component.CategoryBadge.walk` несёт ровно `0x7CE0A0`
    /// и брать его отсюда **нельзя**: компонентные токены за пределы
    /// дизайн-системы не уходят (`ComponentTokenScopeTests`, счёт
    /// только вниз), а виджету они и не видны по устройству сборки.
    /// Именно из-за этого здесь до 23.10 стоял суррогат — и то же
    /// сказано в описании самого токена: «из компонентного слоя двое
    /// из трёх достать его не могли и подставляли суррогат».
    ///
    /// ## Стык закрыт замером, а не ожиданием
    ///
    /// ```
    /// 23.10, первая попытка   enum Category в Tokens.generated.swift
    ///                         в РАБОЧЕМ ДЕРЕВЕ есть, в HEAD НЕТ
    ///                         → имя не писалось: чужая сборка упала бы
    ///                           на `has no member 'Category'`
    /// 23.10, перемер          Token.Category.walk в git, коммит 6c3c326,
    ///                         `= Color(hex: 0x7CE0A0)`
    ///                         контроль тем же запросом: enum Surface — 1
    /// ```
    ///
    /// > **Текст в рабочем дереве выглядит как текст в git**, и
    /// > единственный различитель — `git show <коммит>:<путь>`. Здесь
    /// > он решал не стиль, а собираемость у всех остальных.
    ///
    /// Замер пикселя на эталоне дал `#7FCCAA` (кадр 08) и `#7BDD9E`
    /// (кадр 16): **сам макет с собой побайтно не сходится**, обе формы —
    /// антиалиасинг `#7CE0A0`. Значение токена одно во всех четырёх
    /// режимах, на `#000` контраст 13:1 — то есть пилюля читается
    /// и в светлой теме, где «остров» всё равно чёрный.
    static var зелёныйВыхода: Color { Token.Category.walk }

    public struct Leading: View {
        public let dogName: String
        public init(dogName: String) { self.dogName = dogName }
        public var body: some View {
            Label(Fmt.dogNameOrFallback(dogName), systemImage: "figure.walk")
                .font(.caption)
        }
    }

    public struct Trailing: View {
        public let startedAt: Date
        public init(startedAt: Date) { self.startedAt = startedAt }
        public var body: some View {
            Text(startedAt, style: .timer)
                .font(.system(.title3, design: .rounded).monospacedDigit())
                .frame(maxWidth: 64)
        }
    }

    public struct Bottom: View {
        public let startedBy: String
        public let dogName: String
        public let tally: String?
        public init(startedBy: String, dogName: String, tally: String?) {
            self.startedBy = startedBy
            self.dogName = dogName
            self.tally = tally
        }

        /// Та же подпись, что на локскране, и теперь буквально та же
        /// функция.
        ///
        /// **До 23.10.2026 здесь жила вторая реализация, и она теряла
        /// имя человека.** Записано было «подпись короче, чем
        /// на локскране: места меньше» — довод про место, а не про
        /// смысл, и под ним `startedBy` не читался ни разу при живом
        /// параметре. Дизайн ответом круга 2, §8 назвала подзаголовок
        /// **«кто вывел»**: короткая форма роняет ровно то, ради чего
        /// подпись существует.
        ///
        /// Место при этом есть: нижняя область развёрнутого «острова»
        /// идёт во всю его ширину, а подпись стоит `.caption2`.
        /// Короткая форма осталась **откатом** на случай, когда имени
        /// нет, — там она и уместна.
        public var подпись: String {
            WalkActivityView.подпись(startedBy: startedBy,
                                     dogName: dogName,
                                     tally: tally)
        }

        public var body: some View {
            VStack(spacing: Token.Space.s6) {
                Text(подпись)
                    .font(.caption2)
                    // внутреннее: системная роль цвета, а не наш токен,
                    // и это решение, а не недосмотр. Развёрнутый
                    // «остров» рисуется СИСТЕМНЫМ ВИБРАНТНЫМ
                    // МОНОХРОМОМ — граница названа автором `Dyn`
                    // (`DynamicColor.swift:27-32`). Наш `Token.Ink.*`
                    // туда не доезжает КАК ЦВЕТ, то есть подставить его
                    // значило бы объявить управление, которого нет.
                    .foregroundStyle(.secondary)
                WalkMarkButtons()
            }
        }
    }

    /// Левая половина свёрнутой пилюли: значок и «На улице».
    ///
    /// Эталон — кадр `08.png`, живая пилюля: значок человечка, белое
    /// «На улице», зелёное время. В разметке пакета это
    /// `Togo-RU.dc.html:747`, `text: 'На улице'`, `c: '#7CE0A0'`.
    ///
    /// > **Расхождение двух кадров закрыто ответом дизайна 23.10**
    /// > (круг 2, §2): «Верен **08**: значок прогулки, „На улице",
    /// > время цветом `category.walk`. Это компактная пилюля Dynamic
    /// > Island во время прогулки. **16 — тот же элемент в старой
    /// > редакции мокапа**… Второго состояния нет.»
    /// >
    /// > То есть выбор, сделанный здесь 23.10 утром своим судом
    /// > («взят 08, потому что он показывает живую пилюлю»), **совпал
    /// > с ответом**, и переделывать нечего. На `16.png` — лапа
    /// > и кличка («Стич») вместо значка и «На улице», время белое
    /// > (`Togo-RU.dc.html:336`); эта редакция отменена целиком,
    /// > второго состояния пилюли у продукта нет.
    ///
    /// **Ширина принадлежит системе, и это не оговорка для порядка.**
    /// Свёрнутый «остров» режет содержимое сам, по своему бюджету,
    /// и `08.png` снят с пилюли шириной 232 pt — значения из прототипа,
    /// а не из WidgetKit. Поэтому подпись `lineLimit(1)` и ужимается:
    /// на узком бюджете «На улице» обязано уступить время, а не наоборот.
    public struct CompactLeading: View {
        public init() {}
        public var body: some View {
            HStack(spacing: Token.Space.s4) {
                // **Значок зелёный, подпись белая — и это замер, а не
                // вкус.** На `08.png` зелёные ДВА элемента из трёх:
                // человечек слева и время справа; «На улице» между ними
                // белое. Разметка пакета говорит то же и без глаз:
                // шаблон красит `island.c` и значок, и значение
                // (`Togo-RU.dc.html:747` — `icon`, `val`, `c: '#7CE0A0'`),
                // а `island.text` оставляет цвету по умолчанию.
                //
                // До 23.10 здесь цвета не было вовсе, и значок
                // наследовал белый от системы: расхождение с эталоном
                // было видно только на кадре, потому что пилюля
                // непустая и подпись верная.
                Image(systemName: "figure.walk")
                    .font(.system(size: 14, weight: .semibold))
                    .foregroundStyle(WalkIslandView.зелёныйВыхода)
                Text(String(localized: "На улице"))
                    .font(.system(size: 13, weight: .semibold))
                    .lineLimit(1)
                    .minimumScaleFactor(0.8)
            }
        }
    }

    /// Правая половина свёрнутой пилюли: время выхода, зелёным.
    public struct CompactTrailing: View {
        public let startedAt: Date
        public init(startedAt: Date) { self.startedAt = startedAt }
        public var body: some View {
            Text(startedAt, style: .timer)
                .font(.system(size: 15, weight: .semibold, design: .rounded).monospacedDigit())
                .foregroundStyle(WalkIslandView.зелёныйВыхода)
                .lineLimit(1)
                .minimumScaleFactor(0.7)
                .frame(maxWidth: 52)
        }
    }

    /// Пилюля, свёрнутая до значка: рядом живёт чужая активность.
    public struct Minimal: View {
        public init() {}
        public var body: some View {
            Image(systemName: "figure.walk")
                .font(.system(size: 14, weight: .semibold))
                .foregroundStyle(WalkIslandView.зелёныйВыхода)
        }
    }
