import Foundation
import CloudKit

/// Серверные версии записей, которые мы отправляли.
///
/// **Почему без этого терялось каждое второе сохранение.** CloudKit
/// принимает правку записи, только если в ней стоит тот же
/// `recordChangeTag`, что лежит на сервере. Прежде каждая отправка
/// собирала НОВЫЙ `CKRecord` — без тега вовсе. Первое сохранение
/// проходило (записи на сервере ещё нет), а второе — «дано», правка
/// граммов, удаление — падало на `serverRecordChanged` и больше
/// не повторялось: в журнал уходила строка, и на этом всё. До второго
/// телефона доезжала только самая первая версия записи, а отметка
/// приёма дозы не доезжала никогда.
///
/// Тег сервера взять неоткуда, кроме как с самого сервера. Поэтому
/// здесь лежат три источника одного и того же: записи, которые сервер
/// подтвердил, записи, которые он прислал, и записи из ошибки спора.
@MainActor
final class SharedDiaryOutbox {

    private var known: [CKRecord.ID: CKRecord] = [:]

    /// Серверная версия, поверх которой надо слать свою правку.
    func base(for id: CKRecord.ID) -> CKRecord? { known[id] }

    func remember(_ record: CKRecord) { known[record.recordID] = record }

    func remember(_ records: [CKRecord]) {
        for record in records { remember(record) }
    }

    /// Запись больше не наша забота — или её тег заведомо протух.
    func forget(_ id: CKRecord.ID) { known[id] = nil }

    func forgetAll() { known.removeAll() }

    /// Правка, которая наружу не уехала и повторена не будет.
    ///
    /// Несёт **признак объявленности**, потому что «не повторяем
    /// по записанному доводу» и «не повторяем, и довода нет» — разные
    /// вещи, и у них разные адресаты. Первое читает тот, кто правит
    /// обмен; второе — человек, у которого исчезла запись.
    struct Потеря {
        let id: CKRecord.ID
        /// `nil` — отказ не распознан как `CKError` вовсе.
        let код: CKError.Code?
        /// Есть ли в коде довод, почему повтора не будет.
        let объявлено: Bool
    }

    /// Исход разбора: что повторим и что потеряли.
    ///
    /// **Две группы вместо одного массива, и это главное в правке.**
    /// Прежде функция возвращала только `[CKRecord.ID]` — то, что
    /// повторим. Всё остальное не возвращалось никуда, и вызывающий
    /// не имел способа узнать, что правка исчезла: разницы между
    /// «отказов не было» и «отказы были и все потеряны» в типе
    /// не существовало.
    struct Разбор {
        var повторим: [CKRecord.ID] = []
        var потеряно: [Потеря] = []
    }

    /// Разобрать неудавшиеся отправки.
    ///
    /// Спор о версии — это не отказ, а «возьми свежую и пришли ещё
    /// раз»; молча потерять отметку здесь нельзя, ради неё весь обмен
    /// и затевался.
    ///
    /// ## Почему тип возврата сменился — замер 14.10.2026
    ///
    /// Я шёл проверять **две** ветки и нашёл **четыре** пути, из которых
    /// три молчали:
    ///
    /// ```
    /// serverRecordChanged   повтор                     объявлено
    /// unknownItem           повтор                     объявлено
    /// zoneNotFound          повтора НЕТ — довод есть   объявлено
    /// default               повтора НЕТ — ДОВОДА НЕТ   ← дефект
    /// не CKError вовсе      до switch не доходит       ← и это тоже
    /// ```
    ///
    /// Последний нашёлся только потому, что я читал `guard` на входе,
    /// а не один `switch`: `raw.domain == CKErrorDomain` отбрасывает
    /// отказ, пришедший не от CloudKit, тем же `continue`. Пятый путь
    /// при этом **снаружи неотличим** от четвёртого.
    ///
    /// > **Ось `retries` построена на том, что отказ относится
    /// > к ЗАПИСИ.** Отказ, относящийся к схеме, к квоте или к сети,
    /// > она мерит той же меркой — и отвечает на него молчанием.
    ///
    /// И цена молчания была не в журнале, а на экране:
    /// `SharedDiaryScreen:95` печатает человеку «Своё не уехало» числом
    /// из `FamilySync.pending`, а `pending` — это длина очереди. Запись,
    /// выбывшая из очереди навсегда, **уменьшает** это число. То есть
    /// подпись говорила «всё уехало» ровно в тот момент, когда правка
    /// пропала.
    ///
    /// `zoneNotFound` оставлен объявленным и переклассифицирован НЕ был:
    /// довод автора («зону пересоздаёт движок, а не мы») — решение,
    /// а не пробел. Вернётся ли запись после пересоздания зоны —
    /// **не измерено**, и я этого не выдумываю.
    func retries(after failures: [(id: CKRecord.ID, error: Error)]) -> Разбор {
        var разбор = Разбор()

        for failure in failures {
            // Через `NSError`, а не через `as? CKError`: тот же разбор
            // работает и для ошибки, собранной в тесте, — CloudKit
            // в тест не поставить вовсе.
            let raw = failure.error as NSError
            guard raw.domain == CKErrorDomain,
                  let code = CKError.Code(rawValue: raw.code)
            else {
                // Пятый путь. Прежде здесь стоял `continue`, и отказ
                // не от CloudKit исчезал, не оставив даже кода.
                разбор.потеряно.append(
                    Потеря(id: failure.id, код: nil, объявлено: false)
                )
                continue
            }

            switch code {
            case .serverRecordChanged:
                // Сервер прислал свою версию — с ней и пойдём во второй раз.
                if let server = raw.userInfo[CKRecordChangedErrorServerRecordKey] as? CKRecord {
                    remember(server)
                }
                разбор.повторим.append(failure.id)

            case .unknownItem:
                // На сервере записи нет: наш тег указывает в пустоту.
                // Шлём заново, с чистого листа.
                forget(failure.id)
                разбор.повторим.append(failure.id)

            case .zoneNotFound, .userDeletedZone:
                // Зоны нет — теги всех записей бессмысленны. Повторять
                // нечего: зону пересоздаёт движок, а не мы.
                forgetAll()
                разбор.потеряно.append(
                    Потеря(id: failure.id, код: code, объявлено: true)
                )

            default:
                разбор.потеряно.append(
                    Потеря(id: failure.id, код: code, объявлено: false)
                )
            }
        }

        return разбор
    }
}
