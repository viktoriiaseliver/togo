import Foundation
import CloudKit

/// Серверные версии записей, которые мы отправляли.
///
/// **Почему без этого терялось каждое второе сохранение.** CloudKit
/// принимает правку записи, только если в ней стоит тот же
/// `recordChangeTag`, что лежит на сервере. Прежде каждая отправка
/// собирала НОВЫЙ `CKRecord` — без тега вовсе. Первое сохранение
/// проходило (записи на сервере ещё нет), а второе — «дано», правка
/// граммов, удаление — падало на `serverRecordChanged` и больше
/// не повторялось: в журнал уходила строка, и на этом всё. До второго
/// телефона доезжала только самая первая версия записи, а отметка
/// приёма дозы не доезжала никогда.
///
/// Тег сервера взять неоткуда, кроме как с самого сервера. Поэтому
/// здесь лежат три источника одного и того же: записи, которые сервер
/// подтвердил, записи, которые он прислал, и записи из ошибки спора.
@MainActor
final class SharedDiaryOutbox {

    private var known: [CKRecord.ID: CKRecord] = [:]

    /// Сколько раз отправка этой записи уже отказывала.
    ///
    /// Счётчик нужен **только** потолку: без него повтор на все коды
    /// превращается в вечную очередь на отказе, который не пройдёт
    /// никогда (чужой аккаунт, запись не по схеме, кончилось место).
    private var попытки: [CKRecord.ID: Int] = [:]

    /// Сколько раз повторяем, прежде чем назвать запись потерянной.
    ///
    /// **Число без хозяина, и я называю это вслух.** Пять выбрано мной
    /// (`projects-9b`, 26.10.2026) по доводу, а не по замеру: отказ,
    /// проходящий сам, проходит за секунды-минуты, и пяти заходов
    /// движка хватает, чтобы пережить лифт, метро и двор. Цена ошибки
    /// в обе стороны: меньше — теряем запись на длинном туннеле;
    /// больше — дольше держим в очереди то, что не уедет никогда,
    /// и человек дольше видит растущее «Своё не уехало».
    ///
    /// Поменять стоит одну строку. Хозяина у числа нет — спросить
    /// Викторию, когда появится хоть один замер живого отказа.
    static let потолокПовторов = 5

    /// Серверная версия, поверх которой надо слать свою правку.
    func base(for id: CKRecord.ID) -> CKRecord? { known[id] }

    func remember(_ record: CKRecord) { known[record.recordID] = record }

    func remember(_ records: [CKRecord]) {
        for record in records { remember(record) }
    }

    /// Сервер **принял** эти записи: тег свежий, счётчик попыток обнулён.
    ///
    /// **Отдельно от `remember`, и это не вкус.** `remember` зовётся
    /// ещё в двух местах — для серверной версии из спора и для записи,
    /// приехавшей с чужого телефона. Обнуляй счётчик там — и потолок
    /// не сработает никогда: спор о версии сам кладёт серверную запись
    /// в `known` перед каждым повтором, то есть сбрасывал бы себе счёт
    /// на каждом круге. Потолок без этого разделения — потолок только
    /// на бумаге.
    func подтверждены(_ records: [CKRecord]) {
        for record in records {
            known[record.recordID] = record
            попытки[record.recordID] = nil
        }
    }

    /// Запись больше не наша забота — или её тег заведомо протух.
    ///
    /// Счётчик попыток **не трогает** нарочно: `unknownItem` зовёт
    /// `forget` перед каждым повтором, и обнуление здесь дало бы
    /// бесконечный круг «тега нет → шлём заново → тега нет».
    func forget(_ id: CKRecord.ID) { known[id] = nil }

    func forgetAll() {
        known.removeAll()
        попытки.removeAll()
    }

    /// Теги одной зоны протухли — зоны на сервере нет.
    ///
    /// **Счётчики попыток НЕ трогает, и в этом вся правка 29.10.2026.**
    /// Прежде на `zoneNotFound` стоял `forgetAll()`, а он обнуляет
    /// и попытки — у ВСЕХ записей, не только у той, что упала. Потолок
    /// повторов держится на этом счёте, то есть каждый отказ зоны
    /// возвращал всей очереди полный запас: запись, которая не уйдёт
    /// никогда, крутилась бы в очереди вечно, лишь бы рядом иногда
    /// падала зона. Это тот же класс, что разобран у `forget`:
    /// обнуление на круге повтора — потолок только на бумаге.
    func забытьТеги(зоны зона: CKRecordZone.ID) {
        known = known.filter { $0.key.zoneID != зона }
    }

    /// Правка, которая наружу не уехала и повторена не будет.
    ///
    /// Несёт **признак объявленности**, потому что «не повторяем
    /// по записанному доводу» и «не повторяем, и довода нет» — разные
    /// вещи, и у них разные адресаты. Первое читает тот, кто правит
    /// обмен; второе — человек, у которого исчезла запись.
    struct Потеря {
        let id: CKRecord.ID
        /// `nil` — отказ не распознан как `CKError` вовсе.
        let код: CKError.Code?
        /// Есть ли в коде довод, почему повтора не будет.
        let объявлено: Bool
        /// Сколько раз повторяли, прежде чем сдаться.
        ///
        /// **Ноль и пятёрка — разные события, и человеку они говорят
        /// разное.** Ноль значит «решили не повторять» (зона);
        /// пятёрка — «повторяли и не вышло», то есть отказ держится,
        /// и это уже не про наш обмен, а про сеть или про аккаунт.
        /// Без этого числа оба исхода выглядят одной потерей.
        var попыток: Int = 0
    }

    /// Исход разбора: что повторим и что потеряли.
    ///
    /// **Две группы вместо одного массива, и это главное в правке.**
    /// Прежде функция возвращала только `[CKRecord.ID]` — то, что
    /// повторим. Всё остальное не возвращалось никуда, и вызывающий
    /// не имел способа узнать, что правка исчезла: разницы между
    /// «отказов не было» и «отказы были и все потеряны» в типе
    /// не существовало.
    struct Разбор {
        var повторим: [CKRecord.ID] = []
        var потеряно: [Потеря] = []
        /// Зоны, которых нет на сервере и которые надо завести заново.
        ///
        /// Решает, заводить ли, вызывающий: зону можно создать только
        /// в СВОЕЙ личной базе, а гость пишет в общую — там отказ зоны
        /// значит «владелец перестал делиться», и создать её некому.
        var зоныСоздать: Set<CKRecordZone.ID> = []
    }

    /// Разобрать неудавшиеся отправки.
    ///
    /// Спор о версии — это не отказ, а «возьми свежую и пришли ещё
    /// раз»; молча потерять отметку здесь нельзя, ради неё весь обмен
    /// и затевался.
    ///
    /// ## Почему тип возврата сменился — замер 14.10.2026
    ///
    /// Я шёл проверять **две** ветки и нашёл **четыре** пути, из которых
    /// три молчали:
    ///
    /// ```
    /// serverRecordChanged   повтор                     объявлено
    /// unknownItem           повтор                     объявлено
    /// zoneNotFound          повтора НЕТ — довод есть   объявлено   (до 29.10)
    /// default               повтора НЕТ — ДОВОДА НЕТ   ← дефект
    /// не CKError вовсе      до switch не доходит       ← и это тоже
    /// ```
    ///
    /// ## ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕФЕКТА — замер 26.10.2026
    ///
    /// Правка 14.10 закрыла **молчание**, а не потерю. Две нижние
    /// строки таблицы перестали исчезать без следа — и повтора
    /// по-прежнему не получали **ни одного**:
    ///
    /// ```
    /// было 14.10   default → потеря, не объявлена, повтора НЕТ
    /// стало 26.10  default → ПОВТОР до потолка, потом объявленная
    ///                        потеря с числом попыток
    /// ```
    ///
    /// Отказы, которые тут бывают чаще всего, проходят сами: обрыв
    /// сети, таймаут, `requestRateLimited`, `serviceUnavailable`,
    /// `zoneBusy`. Запись пропадала **с первой попытки**, и для
    /// второго человека в дневнике это самый вероятный отказ вообще —
    /// отмечают с телефона на улице, а не за столом.
    ///
    /// > **Починка, снявшая молчание, выглядит починкой потери.**
    /// > Подпись «Своё не уехало» перестала врать — и ровно поэтому
    /// > никто больше не спрашивал, уезжает ли запись. Видимый дефект
    /// > закрывает собой невидимый.
    ///
    /// Теперь таблица такая, и у каждой потери есть **число попыток**:
    ///
    /// ```
    /// serverRecordChanged   повтор ≤ потолка
    /// unknownItem           повтор ≤ потолка, тег сброшен
    /// zoneNotFound          повтор ≤ потолка, зона — в `зоныСоздать`   ← 29.10
    /// userDeletedZone       потеря, объявлена, попыток 0  ← решение
    /// default               повтор ≤ потолка, потом потеря, попыток 5
    /// не CKError вовсе      то же: «не знаю, что это» — довод
    ///                       повторить, а не сдаться
    /// ```
    ///
    /// Последний нашёлся только потому, что я читал `guard` на входе,
    /// а не один `switch`: `raw.domain == CKErrorDomain` отбрасывает
    /// отказ, пришедший не от CloudKit, тем же `continue`. Пятый путь
    /// при этом **снаружи неотличим** от четвёртого.
    ///
    /// > **Ось `retries` построена на том, что отказ относится
    /// > к ЗАПИСИ.** Отказ, относящийся к схеме, к квоте или к сети,
    /// > она мерит той же меркой — и отвечает на него молчанием.
    ///
    /// И цена молчания была не в журнале, а на экране:
    /// `SharedDiaryScreen:95` печатает человеку «Своё не уехало» числом
    /// из `FamilySync.pending`, а `pending` — это длина очереди. Запись,
    /// выбывшая из очереди навсегда, **уменьшает** это число. То есть
    /// подпись говорила «всё уехало» ровно в тот момент, когда правка
    /// пропала.
    ///
    /// ## `zoneNotFound` — замер чтением 29.10.2026
    ///
    /// Довод прежней редакции «зону пересоздаёт движок, а не мы» был
    /// предположением, а не свойством: `CKSyncEngine` зон сам
    /// не заводит — их ему кладут `pendingDatabaseChanges` (`.saveZone`),
    /// и в этом коде такой строки не было ни одной. Зону заводит только
    /// `FamilyShare.invite`, то есть **до первого приглашения** зоны
    /// у владельца нет, и всё, что он писал с включённым обменом,
    /// терялось с первой попытки «объявленной потерей» — включая засев,
    /// который при этом отмечался сделанным.
    ///
    /// Теперь: запись повторяется под тем же потолком, зона уходит
    /// в `зоныСоздать`, и создаёт её вызывающий — один раз. Теги
    /// забываются **только этой зоны**, а счёт попыток — ничей: разбор
    /// у `забытьТеги(зоны:)`.
    ///
    /// `userDeletedZone` оставлен объявленной потерей: это человек
    /// стёр данные приложения в настройках iCloud, и заводить зону
    /// заново за его спиной значило бы отменить его решение.
    ///
    /// Вернётся ли запись после пересоздания зоны на живом телефоне —
    /// **НЕ ИЗМЕРЕНО**: приватная база неизмерима отсюда.
    func retries(after failures: [(id: CKRecord.ID, error: Error)]) -> Разбор {
        var разбор = Разбор()

        for failure in failures {
            // Через `NSError`, а не через `as? CKError`: тот же разбор
            // работает и для ошибки, собранной в тесте, — CloudKit
            // в тест не поставить вовсе.
            let raw = failure.error as NSError
            guard raw.domain == CKErrorDomain,
                  let code = CKError.Code(rawValue: raw.code)
            else {
                // Пятый путь: отказ не от CloudKit. Прежде здесь стоял
                // `continue`, потом — немедленная потеря. Теперь повтор
                // под потолком: про такой отказ мы не знаем ВООБЩЕ
                // ничего, и «не знаю» — довод повторить, а не сдаться.
                повторитьИлиСдаться(failure.id, код: nil, в: &разбор)
                continue
            }

            switch code {
            case .serverRecordChanged:
                // Сервер прислал свою версию — с ней и пойдём во второй раз.
                if let server = raw.userInfo[CKRecordChangedErrorServerRecordKey] as? CKRecord {
                    remember(server)
                }
                повторитьИлиСдаться(failure.id, код: code, в: &разбор)

            case .unknownItem:
                // На сервере записи нет: наш тег указывает в пустоту.
                // Шлём заново, с чистого листа.
                forget(failure.id)
                повторитьИлиСдаться(failure.id, код: code, в: &разбор)

            case .zoneNotFound:
                // Зоны нет — теги её записей бессмысленны. Запись
                // повторяем, зону заказываем вызывающему: сам движок
                // её не заведёт. Счёт попыток НЕ обнуляется — иначе
                // потолок не сработал бы никогда (`забытьТеги(зоны:)`).
                забытьТеги(зоны: failure.id.zoneID)
                разбор.зоныСоздать.insert(failure.id.zoneID)
                повторитьИлиСдаться(failure.id, код: code, в: &разбор)

            case .userDeletedZone:
                // Человек сам стёр данные приложения в iCloud. Зону
                // за него не возвращаем — решение его, а не наше.
                забытьТеги(зоны: failure.id.zoneID)
                разбор.потеряно.append(
                    Потеря(id: failure.id, код: code, объявлено: true, попыток: 0)
                )

            default:
                // **Здесь и была дыра, и она пережила свою починку.**
                // 14.10 `default: continue` заменили на «назвать
                // потерей» — правку человека перестали терять МОЛЧА,
                // но терять не перестали: повтора не было ни одного.
                //
                // А большинство отказов, которые тут бывают, проходят
                // сами: обрыв сети, таймаут, `requestRateLimited`,
                // `serviceUnavailable`, `zoneBusy`. Для мамы это самый
                // вероятный отказ из всех — она отмечает дозу в лифте,
                // в метро, во дворе, — и запись пропадала с ПЕРВОЙ
                // попытки.
                //
                // > **«Назвали потерей» выглядит починкой «теряли
                // > молча» и ею не является.** Первое лечит молчание,
                // > второе — потерю. Подпись перестала врать, а запись
                // > как пропадала, так и пропадает.
                //
                // Какой именно код CloudKit отвечает в каждом случае —
                // **НЕ ИЗМЕРЕНО и измерить нечем**: приватная база
                // неизмерима без её iCloud, второго конца у связи нет.
                // Вывод от этого не зависит — чинится поведение класса
                // «код не из трёх», а не угаданный код. Ближайшую
                // похожую причину под верный замер не придумываем.
                повторитьИлиСдаться(failure.id, код: code, в: &разбор)
            }
        }

        return разбор
    }

    /// Повторить, пока не исчерпан потолок; потом — назвать потерей.
    ///
    /// Потеря по исчерпанному потолку **объявлена** (довод есть
    /// и записан — «повторяли столько-то»), но от этого не перестаёт
    /// быть потерей: запись человека не уехала. Различает их
    /// `попыток`, и адресаты у них разные — решение про зону читает
    /// тот, кто правит обмен, а исчерпанный потолок читает тот,
    /// у кого пропала отметка.
    private func повторитьИлиСдаться(_ id: CKRecord.ID,
                                     код: CKError.Code?,
                                     в разбор: inout Разбор) {
        let отказов = (попытки[id] ?? 0) + 1
        попытки[id] = отказов

        guard отказов > Self.потолокПовторов else {
            разбор.повторим.append(id)
            return
        }

        // Сдались: держать тег и счёт дальше незачем, а очередь
        // не должна расти на том, что уже названо потерянным.
        попытки[id] = nil
        known[id] = nil
        разбор.потеряно.append(
            Потеря(id: id, код: код, объявлено: true, попыток: Self.потолокПовторов)
        )
    }
}
