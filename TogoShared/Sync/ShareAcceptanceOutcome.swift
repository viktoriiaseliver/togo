import Foundation
import CloudKit

/// Чем кончился приём приглашения — и что об этом сказать человеку.
///
/// # Зачем это существует
///
/// До 08.10.2026 отказ приёма не говорил человеку **ничего**: в
/// `ShareAcceptance.accept` стоял `log.notice`, и всё. Мама нажимала
/// ссылку, приложение открывалось обычным — и она считала, что вошла.
/// Узнала бы обратное, не увидев ни одной записи и решив, что дневник
/// пуст.
///
/// > **Снаружи «принялось» и «не принялось» были неотличимы.**
/// > Различал только журнал устройства, а он достаётся по кабелю.
///
/// # Почему причин несколько, а не одна
///
/// Падать есть от чего ровно в мамином сценарии, и совет у причин
/// разный:
///
/// ```
/// нет сети                «попробуй ещё раз» — помогает
/// iCloud просит подождать «через несколько минут» — сразу НЕ помогает
/// iCloud не вошёл         «войди в iCloud»  — помогает
/// сторона приложения      не помогает НИЧЕГО, и сказать надо,
///                         что дело не в его настройках
/// ```
///
/// Один текст на три причины даёт совет, **неверный для двух из трёх**.
/// Это хуже молчания: молчание заставляет спросить, а неверный совет —
/// попробовать и увериться. Цена измерена 22.09.2026, когда сборка
/// сказала «iCloud недоступен» четверым, и причину выясняли догадками.
///
/// # И четвёртая, без которой остальные три врут
///
/// `.неизвестно` — «не приняли, и мы не знаем почему». Она честнее
/// трёх угадываний: выбрать одну из трёх, не умея отличить, значит
/// дать неверный совет с уверенным лицом.
public enum ShareAcceptanceOutcome: Equatable, Sendable {

    /// Принято. Несёт **имя владельца дневника**, а не факт успеха:
    /// «вы в общем дневнике» не отвечает на вопрос, в чьём именно.
    case принято(чей: String?)

    case нетСети
    /// iCloud жив и сеть есть, но сервер просит подождать: слишком
    /// часто, зона занята, сервис на обслуживании.
    ///
    /// **Отдельно от `.нетСети` с 29.10.2026.** Прежде `requestRateLimited`
    /// и `serviceUnavailable` уходили в «нет связи» (а `zoneBusy` —
    /// в «не знаем почему»), и совет был неверный дважды: человек
    /// со связью шёл чинить связь, а «попробуй ещё раз» сразу —
    /// ровно то, что продлевает просьбу подождать.
    case iCloudПросилПодождать
    case нетiCloud
    /// Наша сторона: тип записи не выложен, права схемы, отказ сервера.
    /// Человеку делать нечего, и сказать надо именно это.
    case сторонаПриложения
    case неизвестно

    public var принято_ли: Bool {
        if case .принято = self { return true }
        return false
    }

    /// По ошибке CloudKit — какая это из причин.
    ///
    /// **Неизвестный код даёт `.неизвестно`, а не ближайшую похожую.**
    /// Подгонять незнакомый отказ под знакомый совет — то же самое,
    /// что один текст на три причины, только незаметнее.
    public static func причина(_ error: Error) -> ShareAcceptanceOutcome {
        guard let ck = error as? CKError else { return .неизвестно }
        switch ck.code {
        case .networkUnavailable, .networkFailure:
            return .нетСети
        case .requestRateLimited, .zoneBusy, .serviceUnavailable:
            return .iCloudПросилПодождать
        case .notAuthenticated, .accountTemporarilyUnavailable:
            return .нетiCloud
        case .badContainer, .badDatabase, .permissionFailure, .invalidArguments,
             .unknownItem, .serverRejectedRequest, .incompatibleVersion,
             .constraintViolation, .managedAccountRestricted:
            return .сторонаПриложения
        default:
            return .неизвестно
        }
    }

    /// Короткое имя причины — для журнала действий, не для человека.
    ///
    /// **Заведено 30.10.2026, и вот чем оплачено.** Журнал писал
    /// `acceptByLink:failed` и ничего больше (`ПозваливСемью:224`), хотя
    /// причина к этому моменту уже вычислена и человеку показана. Разбор
    /// отказа 30.10 09:34 на мамином телефоне уткнулся ровно в это:
    /// по журналу нельзя сказать, чинить нам свою сторону или ждать,
    /// пока iCloud отпустит, — а весь смысл этого перечисления в том,
    /// что совет у четырёх причин разный.
    ///
    /// > **Различитель, вычисленный и выброшенный, стоит дороже
    /// > невычисленного:** он создаёт видимость, что отказ записан.
    ///
    /// Личного здесь нет и быть не может: у `принято` имя владельца
    /// **не берётся** — в журнал уходит только факт. Та же красная
    /// линия, что у `NamelessDogAudit` и крошек запуска.
    ///
    /// **Коды латиницей, и это не стиль.** Первая редакция писала их
    /// по-русски и покраснела у `LocalizationDebtTests` — «пять
    /// непереведённых при долге 0», — и сторож был прав дважды.
    /// Во-первых, русский литерал в коде неотличим от забытой подписи.
    /// Во-вторых, journal читают грепом, а кириллица в логах уже стоила
    /// проекту ложных нулей: имена хранятся в двух нормализациях
    /// Unicode разом (NFC и NFD) и совпадают не всегда.
    ///
    /// > Исключить файл целиком было нельзя: рядом живёт `текст` —
    /// > настоящие подписи, которые переводятся. Сторож требовал
    /// > различить диагностику и речь, а не замолчать обе.
    public var кодДляЖурнала: String {
        switch self {
        case .принято: return "ok"
        case .нетСети: return "noNetwork"
        case .iCloudПросилПодождать: return "iCloudBusy"
        case .нетiCloud: return "noICloud"
        case .сторонаПриложения: return "ourSide"
        case .неизвестно: return "unknown"
        }
    }

    /// Что человек прочтёт. Одна строка на причину, и ни одна
    /// не повторяет другую — это держит `ShareAcceptanceTextTests`.
    public var текст: String {
        switch self {
        case .принято(let чей):
            if let чей = Fmt.notBlank(чей ?? "") {
                return String(localized: "Готово: ты в дневнике — \(чей).")
            }
            // Имени может не быть: `CKShare` отдаёт его не всегда.
            // Говорим это прямо, а не делаем вид, что дневник ничей.
            return String(localized: "Готово: ты в общем дневнике. Чей он — приложение пока не знает.")
        case .нетСети:
            return String(localized: "Приглашение не открылось: нет связи. Попробуй ещё раз, когда появится интернет.")
        case .iCloudПросилПодождать:
            return String(localized: "Приглашение не открылось: iCloud просит подождать. Нажми ссылку снова через несколько минут.")
        case .нетiCloud:
            return String(localized: "Приглашение не открылось: на телефоне не выполнен вход в iCloud. Войди и нажми ссылку снова.")
        case .сторонаПриложения:
            return String(localized: "Приглашение не открылось, и дело не в твоих настройках — это на нашей стороне. Напиши нам, пожалуйста.")
        case .неизвестно:
            return String(localized: "Приглашение не открылось, и мы не знаем почему. Попробуй ещё раз; если повторится — напиши нам.")
        }
    }
}
