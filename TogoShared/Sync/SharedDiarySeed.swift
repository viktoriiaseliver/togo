import Foundation
import CloudKit
import SwiftData

/// Засев общей зоны: отправить второму человеку то, что уже лежит
/// в хранилище.
///
/// # Чего не было до 08.10.2026
///
/// Единственный путь наружу — подписка на `ModelContext.didSave`
/// (`FamilySync.start()`): уезжает только то, что **сохранят после**
/// включения обмена. Отправки уже существующих записей не было
/// ни строкой.
///
/// ```
/// уедет к маме        то, что сохранят ПОСЛЕ приглашения
/// не уедет никогда    весь дневник, накопленный ДО: профиль собаки,
///                     взвешивания, медкнижка, схемы, справочник, лента
/// ```
///
/// Собаку заводят один раз и потом не правят — **мама в день
/// приглашения видела пустую комнату**, и выходом сборки это
/// не чинилось.
///
/// # Почему это отдельный путь, а не ещё одна подписка
///
/// Дозаливка **не должна зависеть от того, что кто-то что-то
/// сохранит**: иначе это четвёртая реализация, висящая на том же
/// событии, которое и было причиной. Здесь обход хранилища — свой.
///
/// # Почему тут только СБОР, а отправка в `FamilySync`
///
/// Чтобы решение можно было проверить. Движок обмена в тест
/// не поставить: ему нужны живой контейнер CloudKit и вошедший
/// аккаунт. А «какие записи считаются накопленными» — обычная
/// функция над хранилищем, и её проверяет `ЗасевTests`.
///
/// Тот же приём, которым отделили `ShareAcceptance.accepted`
/// от делегата сцены: дверь непроверяема, решение проверяемо.
///
/// # Устойчивый id дозы обязан лежать РАНЬШЕ этого
///
/// Без него засев **размножит** отметки приёма: каждый телефон зальёт
/// свои со своими случайными `id`, а приём чужой дозы ищет только
/// по `id`. Лежит с `4243076` (`DoseRecord.устойчивыйID`).
///
/// Это наш замер, а не совет Apple: у Apple про устойчивое имя записи
/// сказано **обратное по акценту** («derive … from an object that
/// guarantees uniqueness, such as a UUID»).
public enum SharedDiarySeed {

    /// Что надо отправить, чтобы второй человек увидел накопленное.
    ///
    /// Возвращает **только сохранения**. Удалений здесь нет, и это
    /// не упущение: надгробие (`deletedAt`) есть лишь у `LogEvent`,
    /// а `.deleteRecord` в обмене не ставится нигде — то есть «что
    /// у второго удалено» нам неизвестно. Класть сюда удаления значило
    /// бы выдумать знание.
    ///
    /// И порядок: `.saveRecord` вместе с `.deleteRecord` по одной
    /// записи даёт **только delete** — ещё одна причина не смешивать.
    @MainActor
    public static func изменения(
        context: ModelContext, zone: CKRecordZone.ID
    ) throws -> [CKSyncEngine.PendingRecordZoneChange] {
        // Все типы, которые умеют ездить, — из реестра
        // (`РеестрОбмена.всеГодные`), а не своим списком. До 05.11.2026
        // здесь стояли двенадцать вызовов `собрать(X.self…)`, и список
        // обязан был совпадать с `SharedDiary.RecordType` по договорённости:
        // новый тип поехал бы только «вперёд», а накопленное по нему
        // не уехало бы никогда, и снаружи это неотличимо от «обмен
        // не работает». Теперь список один, и пропустить тип нечем.
        //
        // **Ворота наружу — те же, что у второй двери, а не своя копия.**
        //
        // `FamilySync.enqueueLocalChanges` отсеивает негодное на пути
        // «сохранили → отправили». Засев — ВТОРАЯ дверь наружу, и он
        // идёт в `engine.state` напрямую, мимо того пути: без ворот он
        // залил бы второму человеку ровно тех безымянных собак, которых
        // там запретили, при зелёном стороже. Масштаб измерен по выгрузке
        // с телефона 08.10.2026: **пятнадцать пустых из шестнадцати**.
        // И отладочную запись прогрева схемы (одна из 182, дата 2001-01-01).
        //
        // > **Два пути наружу — два места для одного запрета. Пока он
        // > стоит в одном, второй о нём не знает.**
        //
        // Ворота — `Обменный.годитсяНаружу`, одно свойство на тип,
        // и его же спрашивают постановка и сборка записи.
        return try РеестрОбмена.всеГодные(context: context, zone: zone)
    }
}

/// Засеяли ли общую зону — и **чью именно**.
///
/// **Ключ несёт владельца зоны нарочно.** Человек может выйти
/// из одного дневника и войти в другой: флаг «я уже засеял» без имени
/// владельца сказал бы «засеяно» про чужую зону, в которую не уехало
/// ничего. Одно состояние на два вопроса — то же слипание, что
/// у `SharedDiarySettings.isOn` («чего хочет человек» против «работает
/// ли обмен»).
///
/// # Что его сбрасывает и что будет, если он соврёт
///
/// Сбрасывает: смена владельца зоны (ключ другой) и **выключение
/// обмена** — снимает его сеттер `SharedDiarySettings.isOn`, когда
/// в него кладут `false`.
///
/// До 15.10.2026 здесь стоял `FamilySync.stop()`, и запись была верна.
/// Сброс переехал, потому что в `stop()` он зависел от **инструмента**:
/// `SharedDiaryScreen` зовёт `sync?.stop()` опциональной цепью, и без
/// живого движка выключение не снимало флаг, хотя настройка уже стояла
/// в `false`. Теперь условие привязано к **правилу** — «человек
/// выключил», — и срабатывает из любого места, включая те, которых
/// ещё нет.
///
/// **Если соврёт «засеяно», когда не засеяли** — накопленное
/// не уедет, и мама снова увидит пустую комнату; симптом тот же,
/// что был до этой работы.
///
/// **Если соврёт «не засеяно», когда засеяли** — засев пойдёт второй
/// раз. Это безопасно **только потому, что записи адресуются
/// устойчивым `id`**: повторная заливка перезапишет те же записи
/// CloudKit, а не создаст вторые. Без устойчивого `id` дозы второй
/// засев размножил бы отметки приёма — и это, а не экономия запросов,
/// главная причина, по которой флаг вообще существует.
nonisolated enum SyncSeedState {

    private static var defaults: UserDefaults {
        AppGroupDefaults.shared
    }

    /// **Это не подпись, и `String(localized:)` здесь был бы дефектом,
    /// а не починкой.** Слово уходит в ИМЯ КЛЮЧА: переведи его —
    /// и ключ станет зависеть от языка (`sharedDiary.seeded.сам`
    /// против `sharedDiary.seeded.soi`). Сменив язык, человек получил
    /// бы флаг «не засеяно» и второй засев. Голова этого файла
    /// объясняет, почему второй засев безопасен только из-за
    /// устойчивых `id`, — а полагаться на это там, где можно просто
    /// не ломать ключ, незачем.
    ///
    /// `Tools/эталон-прогона.json` до 13.10.2026 предписывал обратное
    /// («лечится `?? String(localized: "сам")`»). Запись пережила свою
    /// правду и стала нарядом на внесение дефекта.
    private static func key(_ owner: String?) -> String {
        "sharedDiary.seeded." + (owner ?? "сам")  // внутреннее: суффикс ключа UserDefaults, перевод сбросил бы флаг засева
    }

    static func засеяно(владелец owner: String?) -> Bool {
        defaults.bool(forKey: key(owner))
    }

    static func отметить(владелец owner: String?) {
        defaults.set(true, forKey: key(owner))
    }

    static func сбросить(владелец owner: String?) {
        defaults.removeObject(forKey: key(owner))
    }
}
