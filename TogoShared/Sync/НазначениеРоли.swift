import Foundation

/// Роль, выбранная владельцем при приглашении, — в том виде, в каком
/// она едет ко второму человеку.
///
/// # Почему едет и роль, и набор прав
///
/// Можно было везти что-то одно, и оба варианта теряют половину
/// предмета:
///
/// ```
/// только набор прав   слово назвать нечем: наборы и роли не взаимно
///                     однозначны, а человеку показывают СЛОВО
///                     («ты смотришь, отмечает мама»). Обратного
///                     перевода из множества в роль не существует
/// только роль         именные правки владельца пропадают молча.
///                     Он переключает их на «Семье»
///                     (`FamilyScreen.swift:837` → `FamilyMember
///                     .permissions`), а приезжал бы пресет
/// ```
///
/// Поэтому едет и то и другое — **ровно в той форме, в какой это уже
/// хранит модель**: `роль` плюс `права`, где `nil` значит «по роли»
/// (`FamilyMember.customPermissionsRaw`, `Family.swift:14`). Второй
/// формы для одних данных не заводится: два пути расходятся молча,
/// и у этого проекта это оплачено единицей дозы
/// (`MedicationPayload.unitRaw`).
///
/// # Почему строками, а не значениями перечислений
///
/// `Codable` по `FamilyRole` и `Set<Permission>` отказал бы на имени,
/// которого не знает **эта** сборка, — и отказ разбора уронил бы
/// **весь** наряд, а не одно поле. У второго человека телефон
/// обновляется не в ту же минуту, и это обычное состояние, а не край.
///
/// Поэтому имена разбираются поимённо и по отдельности:
/// неузнанное право отбрасывается, неузнанная роль даёт `nil`.
/// **Обе формы незнания сужают права, а не расширяют** — в эту сторону
/// ошибаться дешевле, и это то же решение, что у спора о взвешивании
/// («при ничьей — меньший вес», `SharedDiary.swift:767`).
nonisolated struct НазначеннаяРоль: Equatable, Sendable, Codable {

    /// Имя роли, как его пишет `FamilyRole.rawValue`.
    var рольRaw: String

    /// Права, выданные поимённо. `nil` — «по роли».
    ///
    /// Пустой список и `nil` — **разные** состояния, и разница в них
    /// та же, что в модели: «мы ничего не меняли» против «мы всё сняли
    /// руками».
    var праваRaw: [String]?

    init(роль: FamilyRole, права: Set<Permission>? = nil) {
        self.рольRaw = роль.rawValue
        self.праваRaw = права.map { $0.map(\.rawValue).sorted() }
    }

    /// Роль, если имя узнано.
    ///
    /// **Неузнанное имя даёт `nil`, а НЕ `.helper`** — в отличие
    /// от `FamilyMember.role`, который подставляет помощника
    /// (`Family.swift:56`). Разница не в стиле, а в происхождении
    /// значения: там строка своя, с этого телефона, и подстановка
    /// чинит свою же опечатку. Здесь строка **чужая**, приехавшая,
    /// и подставить ей роль значило бы выдать права по догадке.
    /// `nil` уводит на запасной путь — наблюдателя.
    var роль: FamilyRole? { FamilyRole(rawValue: рольRaw) }

    /// Набор прав, если он ехал поимённо.
    ///
    /// Неузнанные имена отбрасываются поштучно. Список, в котором
    /// не узнано ничего, даёт **пустое множество, а не `nil`**: пустое
    /// значит «ничего не разрешено», `nil` значило бы «по роли», то есть
    /// шире. Из двух прочтений чужой строки берётся узкое.
    var права: Set<Permission>? {
        guard let праваRaw else { return nil }
        return Set(праваRaw.compactMap(Permission.init))
    }
}

/// Кому что назначил владелец — одна запись на весь дневник.
///
/// # Почему один наряд, а не запись на человека
///
/// Общий доступ у зоны **один** (`CKRecordNameZoneWideShare`,
/// `FamilyShare.swift:124`), и его видят все участники. Класть
/// назначения по одному на человека означало бы завести записи,
/// у которых нет ни типа обмена, ни надгробия, ни разбора, —
/// то есть второй механизм рядом с работающим. Ровно это запрещено
/// решением 08.10.2026, которым из обмена убрали `FamilyMember`
/// (`SharedDiary.swift:78`).
nonisolated struct НарядРолей: Equatable, Sendable, Codable {

    /// Какого формата этот наряд.
    var версия: Int

    /// Кому что назначено.
    ///
    /// Ключ — **непрозрачный идентификатор участника CloudKit**
    /// (`CKUserIdentity.userRecordID.recordName`), а не почта и не имя.
    /// Почта у участника может отсутствовать вовсе (`participants()`
    /// уже знает это и потому берёт имя, иначе почту,
    /// `FamilyShare.swift:239`), а имя не уникально.
    var поУчастникам: [String: НазначеннаяРоль]

    /// Что получает тот, кого в списке ещё нет.
    ///
    /// **Это не удобство, а единственный способ исполнить решение
    /// «пусть выбираете вы при приглашении».** В момент приглашения
    /// участника не существует: владелец отдаёт `CKShare` системному
    /// листу «Поделиться», а CloudKit заводит участника **после** того,
    /// как человек примет. Ключа, под который писать роль, в ту минуту
    /// нет ни у кого.
    ///
    /// Поэтому выбранное при приглашении ложится сюда, а поимённое
    /// назначение — в `поУчастникам`, и поимённое сильнее.
    var новичкам: НазначеннаяРоль?

    init(версия: Int = РолиВОбмене.текущаяВерсия,
         поУчастникам: [String: НазначеннаяРоль] = [:],
         новичкам: НазначеннаяРоль? = nil) {
        self.версия = версия
        self.поУчастникам = поУчастникам
        self.новичкам = новичкам
    }
}

/// Наряд ролей в обмене: как он кодируется и кто под него подходит.
///
/// Вынесено сюда целиком и работает на простых значениях, а не
/// на CloudKit, — **по той же причине, что и `SharedDiaryMerge`:
/// это можно проверить тестами, не имея двух телефонов**
/// (`SharedDiary.swift:17`). Приватную базу CloudKit мы измерить
/// не можем вовсе, и значит всё, что можно вынести из неё в чистое
/// значение, обязано быть вынесено.
nonisolated enum РолиВОбмене {

    /// Имя поля на записи общего доступа.
    ///
    /// Латиницей нарочно, и причин две. Первая: это имя поля CloudKit,
    /// а не подпись, и человек его не видит никогда. Вторая: своё поле
    /// на `CKShare` — **не наш тип записи**, его не знает
    /// `Tools/deploy_cloudkit_schema.sh` (замер: `grep -i share`
    /// по скрипту даёт две строки, обе про `SharedDiaryRecords`),
    /// и значит `make cloudkit-check` про него ничего не скажет
    /// ни в какую сторону.
    static let полеНаряда = "togoRoleAssignment"

    /// Формат наряда. Поднимать вместе с правкой состава полей.
    static let текущаяВерсия = 1

    static func закодировать(_ наряд: НарядРолей) -> String? {
        let кодировщик = JSONEncoder()
        // Порядок ключей устойчив: иначе одна и та же роль каждый раз
        // давала бы другую строку, и запись в облако шла бы при каждом
        // чтении.
        кодировщик.outputFormatting = [.sortedKeys]
        guard let данные = try? кодировщик.encode(наряд) else { return nil }
        return String(data: данные, encoding: .utf8)
    }

    /// Разобрать наряд. Непонятое — `nil`, и `nil` сужает права.
    ///
    /// **Наряд новее нашего формата читается как отсутствующий.**
    /// Это проигрыш в правах у того, кому владелец их уже дал, — и он
    /// выбран сознательно: прочесть незнакомый формат наполовину
    /// значило бы выдать права по догадке, а здесь догадка стоит дозы.
    /// Старее — читается: поля, которых не было, приедут `nil`.
    static func разобрать(_ строка: String?) -> НарядРолей? {
        guard let строка, let данные = строка.data(using: .utf8),
              let наряд = try? JSONDecoder().decode(НарядРолей.self, from: данные),
              наряд.версия <= текущаяВерсия
        else { return nil }
        return наряд
    }

    /// Что назначено этому участнику.
    ///
    /// Поимённое сильнее общего: владелец, поправивший роль мамы после
    /// того, как та вошла, ожидает, что подействует именно правка.
    ///
    /// **Участник без идентификатора получает назначение новичка,
    /// а не `nil`.** CloudKit отдаёт `userRecordID` не всегда — ровно
    /// как и `nameComponents`, о чём этот слой уже знает
    /// (`ShareAcceptance.чьёИмя`). Считать такого человека
    /// неназначенным значило бы отнять у него то, что владелец выбрал
    /// при приглашении, то есть сломать единственную дорогу решения
    /// Виктории.
    static func назначение(из наряд: НарядРолей?, участник: String?) -> НазначеннаяРоль? {
        guard let наряд else { return nil }
        if let участник, let своё = наряд.поУчастникам[участник] { return своё }
        return наряд.новичкам
    }
}

/// Назначение, приехавшее на ЭТОТ телефон.
///
/// # Почему в группе приложений, а не в `AppState`
///
/// Входов в права два, и это измерено, а не предположено:
/// `AppState.permissions` — экраны; `FamilyResolver.права(…)` — голос,
/// кнопка «Действие», виджет. У второго `AppState` нет вовсе: интент
/// живёт в своём процессе (`FamilyResolver` говорит это первым абзацем).
///
/// Положи назначение в `AppState` — и голос останется с прежним
/// ответом, то есть одно правило снова будет жить двумя проверками
/// и разойдётся в краю. За это уже платили 23.09.2026, и платили дозой.
///
/// Устроено как `SharedZoneOwner` и `НеудачаПриёма` — тем же ключом
/// в той же группе, третьей формы хранения не заводится.
nonisolated enum НазначениеПоОбмену {
    private static let key = "sharedDiary.roleAssignment"

    private static var defaults: UserDefaults {
        UserDefaults(suiteName: AppIdentifiers.appGroup) ?? .standard
    }

    /// Роль и права, выбранные владельцем для меня. `nil` — не приезжало.
    static var текущее: НазначеннаяРоль? {
        get {
            guard let строка = defaults.string(forKey: key),
                  let данные = строка.data(using: .utf8)
            else { return nil }
            return try? JSONDecoder().decode(НазначеннаяРоль.self, from: данные)
        }
        set {
            guard let newValue,
                  let данные = try? JSONEncoder().encode(newValue),
                  let строка = String(data: данные, encoding: .utf8)
            else {
                defaults.removeObject(forKey: key)
                return
            }
            defaults.set(строка, forKey: key)
        }
    }

    static func reset() { defaults.removeObject(forKey: key) }
}
