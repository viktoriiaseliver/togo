import Foundation
import SwiftData

/// Удаление, которое доезжает до второго человека.
///
/// # Чем это оплачено
///
/// Надгробие (`deletedAt`) было только у `LogEvent`. У остальных
/// одиннадцати типов общего дневника удаление было жёстким
/// (`context.delete`), и **до второго человека не доезжало ни по одному
/// типу, кроме отметок**.
///
/// Механизм, по которому не доезжало, — не пропущенный флаг.
/// Исходящая очередь собирается из уведомления `ModelContext.didSave`
/// (`FamilySync.enqueueLocalChanges`), а удалённая запись не приходит
/// ни в `inserted`, ни в `updated`: её больше нет, собрать по ней
/// `CKRecord` неоткуда, и места, где флаг можно было бы поставить,
/// в этом пути не существует.
///
/// Самый дорогой случай назван отдельно, потому что он про лекарство:
///
/// > Виктория отменила схему лечения, у мамы она жива, мама даёт
/// > препарат и получает напоминания о дозах.
///
/// Проект мерит дозы правилом «не дать отменённую таблетку безопаснее,
/// чем дать». Здесь оно было нарушено **в точности наоборот**.
///
/// # Почему надгробие, а не `.deleteRecord`
///
/// Три довода, и первый — замер:
///
/// 1. **Правки в сборщике очереди не требуется вовсе.** Надгробие —
///    обычное поле, значит мягкое удаление приезжает в `didSave`
///    ключом `"updated"`, который очередь уже читает. Дописывать
///    `"deleted"` в список ключей не нужно, и это сильнее, чем
///    «недостаточно»: ключ `"deleted"` в этом механизме не участвует.
/// 2. **Спор разрешим.** Удалённая на сервере запись вернулась бы
///    от второго телефона первой же его правкой; надгробие сильнее
///    правки по правилу (`SharedDiaryMerge.надгробиеРешает`).
/// 3. **Путь уже проверен** на `LogEvent` с 22.09.2026.
///
/// # ПАРА, А НЕ ПОЛЕ
///
/// Надгробие без `changedAt` не уезжает: отметка времени — то, по чему
/// `FamilySync` понимает, что запись трогали, и то, чем решается спор.
/// Поэтому присваивать `deletedAt` руками нельзя — **половина пары
/// опаснее целой**: запись исчезнет у себя и останется у второго
/// человека, то есть ровно тот дефект, от которого всё это написано,
/// только теперь молча и с виду починенный.
///
/// Отсюда устройство: одиннадцать коротких перегрузок одного имени,
/// и пара стоит в каждой ровно один раз. Общей функции по протоколу
/// здесь нет нарочно — `TogoShared` компилируется в два таргета
/// с разной изоляцией по умолчанию (у приложения `MainActor`,
/// у `TogoWidgetsExtension` нет), и протокол с изолированным
/// соответствием дал бы красное только в расширении.
///
/// # Чего здесь НЕТ и почему
///
/// **`deletedBy` только у `LogEvent`.** У ленты он живой: удаление
/// обратимо пять секунд, и человек видит, кто удалил. У этих
/// одиннадцати ни одного читателя нет, а поле без читателя — это
/// одиннадцать полей в схеме CloudKit, которые надо выложить
/// в production и которые никому ничего не говорят.
///
/// **Возврата (`вернуть`) нет.** У ленты он есть, потому что там
/// удаление — частое и обратимое действие с кнопкой «Отменить».
/// Здесь удаление подтверждают шторкой, и кнопки отмены ни на одном
/// экране нет. Заводить путь, которым никто не ходит, значит заводить
/// механизм без входа.
///
/// **Каскада по надгробию нет.** У `Dog` все связи
/// `deleteRule: .cascade`, и жёсткое удаление собаки уносило её ленту,
/// веса, дела, схемы и медкнижку. Надгробие не уносит ничего: оно
/// значит «этой собаки у нас нет», а не «сотрите её историю
/// у второго человека». Чужие записи сносит человек у себя.
///
/// # Граница, которую нельзя сузить
///
/// **Работает только вперёд.** Что удалено до 26.10.2026, у второго
/// человека останется навсегда: надгробий на те записи не ставил никто,
/// а восстановить их неоткуда — записи нет ни у нас, ни в истории.
///
/// # Что ЕЩЁ обязано случиться вместе с надгробием
///
/// Мягкое удаление не делает двух дел, которые жёсткое делало само,
/// и оба названы здесь, а не в журнале, потому что их забывают:
///
/// ```
/// снятие напоминаний   запросы уведомлений по дозам удалённой схемы
///                      снимает ReminderScheduler.снятьНеждущие, и она
///                      обязана ходить к `medicationsStorage`, а не
///                      к отфильтрованному `medications`
/// фильтр на чтении     22 места показа и счёта. Надгробие, которое
///                      видно человеку, — не удаление, а порча экрана
/// ```
@MainActor
enum ОбщееУдаление {

    /// Удалить так, чтобы удаление доехало до второго человека.
    ///
    /// Запись остаётся в своей базе надгробием: без неё `FamilySync`
    /// не соберёт `CKRecord` и отправлять будет нечего. Видимость
    /// закрывают фильтры на чтении, а не этот вызов.
    ///
    /// Сохранение здесь НЕ делается нарочно: его делает вызывающий
    /// своим `context.persist(otherwise:)`, у которого есть откат.
    /// Два сохранения на одно действие дали бы два круга обмена.
    static func удалить(_ запись: Dog, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: CareTask, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: Medication, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: DoseRecord, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: WeightEntry, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: Clinic, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: DogDocument, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: LabResult, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: VetVisit, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: Diagnosis, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }

    static func удалить(_ запись: Prescription, когда: Date = Date()) {
        запись.deletedAt = когда
        запись.changedAt = когда
    }
}
