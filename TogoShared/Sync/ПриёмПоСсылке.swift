import Foundation

/// Что человек вставил в поле «ссылка на приглашение» — и что из этого
/// следует.
///
/// # Зачем это существует
///
/// До 26.10.2026 приглашение можно было принять **только снаружи**:
/// человек нажимал ссылку в переписке, iOS показывала системную шторку
/// и звала `windowScene(_:userDidAcceptCloudKitShareWith:)`
/// (`TogoApp.swift:42`). Кто открыл Togo **раньше**, чем нажал ссылку,
/// попадал на экран «Тебя позвали» и искал там поле для адреса. Поля
/// не было, и экран говорил об этом вслух: `TGIconRow(symbol:
/// "keyboard", title: "Адрес вводить негде")`.
///
/// Граница была названа верно (`AppRoot`, `TogoApp.swift:531`:
/// «**Чего это НЕ чинит:** человека, который открыл приложение **до**
/// того, как нажал ссылку»), и из неё сделали неверный вывод.
///
/// ```
/// ЧТО БЫЛО ИЗМЕРЕНО   `togo.app/j/7KQ2-VX` из макета не существует:
///                     своего домена с редиректом у нас нет
/// ЧТО ИЗ ЭТОГО ВЫВЕЛИ «вводить негде»
/// ЧЕГО НЕ ПРОВЕРИЛИ   CloudKit выдаёт НАСТОЯЩИЙ адрес на `icloud.com`,
///                     и приём по нему — одна строка:
///                     `CKContainer.shareMetadata(for:)`
/// ```
///
/// > **Из «короткой ссылки не бывает» не следует «вводить негде».**
/// > Отвергнут был вид адреса, а снят — вход. Это наша же обратная
/// > форма: запрет, исполненный снятием входа, выглядит сломанной
/// > дорогой, и отличает её один вопрос — а что нарисовано ВМЕСТО.
///
/// Замер 26.10.2026, `CKFetchShareMetadataOperation` — ноль вхождений
/// при живом контроле (`userDidAcceptCloudKitShareWith` — четыре).
/// Операция и не нужна: у `CKContainer` есть асинхронный
/// `shareMetadata(for:)` (`CKContainer.h:379`,
/// `NS_REFINED_FOR_SWIFT_ASYNC(2)`), и он проверен типизацией
/// с отрицательным контролем.
///
/// # Почему разбор отдельно от приёма
///
/// Приём трогает облако, и проверить его без её личного iCloud нельзя
/// ни одним замером. Разбор строки — чистое значение, и он покрыт
/// тестами целиком. Тот же довод, которым `РолиВОбмене` вынесен
/// из `FamilyShare`: что можно вынести из неизмеримого в измеримое —
/// обязано быть вынесено.
nonisolated enum ПриёмПоСсылке {

    /// Что мы поняли из вставленного — **до** того, как спросили облако.
    ///
    /// Четыре исхода, а не «годится / не годится», потому что совет
    /// у них разный, и это ровно тот урок, который уже оплачен
    /// в `ShareAcceptanceOutcome`: один текст на несколько причин даёт
    /// совет, неверный для большинства из них.
    enum Разбор: Equatable, Sendable {

        /// Похоже на приглашение CloudKit — можно спрашивать облако.
        /// Окончательный ответ всё равно за ним: мы проверяем вид
        /// адреса, а не его существование.
        case годится(URL)

        /// Пусто. Это не ошибка человека, и красного текста тут быть
        /// не должно: он ещё не начал.
        case пусто

        /// `togo.app/j/…` — вид из макета, которого не существует.
        ///
        /// Назван **отдельной причиной**, а не свален в «не похоже»,
        /// по измеренной причине: этот вид человеку могли показать мы
        /// сами. Макет рисовал его в поле ввода, и если он где-то
        /// просочился в текст приглашения, то отказ наш, а не его, —
        /// и сказать надо, где взять настоящий.
        case короткаяСсылка

        /// Ссылки в этом нет вовсе, либо она не про приглашение.
        case неПриглашение

        var годная: URL? {
            if case .годится(let адрес) = self { return адрес }
            return nil
        }

        /// Что человек прочтёт под полем. `nil` — говорить нечего.
        ///
        /// **У `.годится` и `.пусто` текста нет нарочно.** Подпись
        /// «всё верно» под полем, которое ещё ничего не сделало, —
        /// это обещание вместо ответа: нажмёт и получит отказ облака.
        /// Исход приёма говорит `ShareAcceptanceOutcome`, и шестого
        /// текста для него здесь не заводится.
        var текст: String? {
            switch self {
            case .годится, .пусто:
                return nil
            case .короткаяСсылка:
                return String(localized: "Такой короткой ссылки у Togo нет. Нужен адрес, который начинается на icloud.com — его присылает приложение вместе с приглашением.")
            case .неПриглашение:
                return String(localized: "Это не похоже на приглашение. Нужна ссылка на icloud.com — её присылают из Togo, «Семья» → «Позвать в дневник».")
            }
        }
    }

    /// Хост, который выдаёт CloudKit. Своего домена с редиректом у нас
    /// нет, и `togo.app/j/…` из макета — выдумка, названная ниже
    /// отдельным исходом.
    static let хостПриглашения = "icloud.com"

    /// Начало пути у ссылки общего доступа: `icloud.com/share/<токен>`.
    static let путьПриглашения = "/share/"

    /// Домен из макета. Лежит здесь, а не в прозе, чтобы вид был
    /// опознаваемым, а не угадываемым по тексту отказа.
    static let выдуманныйХост = "togo.app"

    /// Знаки, которые приезжают приклеенными к ссылке из переписки.
    ///
    /// Человек копирует не адрес, а **сообщение**, и в нём адрес стоит
    /// в предложении: «вот ссылка: https://… , открой». Точка в конце
    /// фразы ломает `URL(string:)` молча — то есть «ссылка не годится»
    /// сказало бы про наш разбор, а не про его ссылку.
    private static let мусор = CharacterSet(charactersIn: ".,;:!?…()[]{}<>«»\"'“”`")

    /// Разобрать вставленное.
    ///
    /// Идём по словам, а не одной регуляркой: вставляют и целое
    /// сообщение, и голый адрес, и адрес без схемы
    /// («www.icloud.com/share/…» — именно так его показывает Safari).
    /// Все три случая измеримы тестами, и каждый лежит в наборе.
    static func разобрать(_ ввод: String) -> Разбор {
        guard !ввод.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return .пусто
        }

        // Выдуманный вид запоминаем и **не возвращаем сразу**: в одном
        // сообщении может лежать и он, и настоящий адрес, и тогда
        // настоящий сильнее. Отказать при живой ссылке рядом было бы
        // отказом нашим.
        var виделВыдуманный = false

        for кусок in ввод.split(whereSeparator: { $0.isWhitespace || $0.isNewline }) {
            guard let адрес = адрес(String(кусок)),
                  let хост = адрес.host()?.lowercased()
            else { continue }

            if свой(хост, хостПриглашения) {
                // Путь проверяем здесь, а не оставляем облаку, и это
                // выбор с названной ценой. Отправь мы в облако любой
                // адрес с `icloud.com` — на ссылку из «Фото» придёт
                // `unknownItem`, то есть `.сторонаПриложения`, то есть
                // «дело не в твоих настройках». Это было бы ложью
                // в самую дорогую сторону: мы бы взяли на себя чужую
                // опечатку и человек перестал бы её искать.
                guard адрес.path().lowercased().hasPrefix(путьПриглашения) else {
                    continue
                }
                return .годится(адрес)
            }

            if свой(хост, выдуманныйХост) { виделВыдуманный = true }
        }

        return виделВыдуманный ? .короткаяСсылка : .неПриглашение
    }

    /// Тот ли это домен — **целиком или поддоменом**.
    ///
    /// Сравнение префиксом здесь дало бы `icloud.com.phish.ru`,
    /// а сравнение «содержит» — вообще что угодно. Это наш
    /// оплаченный класс: `hasPrefix("struct Swatch")` находит
    /// `struct SwatchRow`.
    private static func свой(_ хост: String, _ домен: String) -> Bool {
        хост == домен || хост.hasSuffix("." + домен)
    }

    /// Слово из сообщения — в адрес, если это адрес.
    private static func адрес(_ слово: String) -> URL? {
        let чистое = слово.trimmingCharacters(in: мусор)
        guard !чистое.isEmpty else { return nil }

        let нижний = чистое.lowercased()
        if нижний.hasPrefix("https://") || нижний.hasPrefix("http://") {
            return URL(string: чистое)
        }
        // Без схемы `URL(string:)` отдаёт адрес **без хоста**, и проверка
        // домена ниже получила бы `nil` — то есть «не похоже
        // на приглашение» про верную ссылку. Схему дописываем сами.
        guard чистое.contains("."), !чистое.contains("://") else { return nil }
        return URL(string: "https://" + чистое)
    }
}
