import XCTest

/// Дорога к анализам и три шага ввода — чтобы их БЫЛО ЧЕМ снять.
///
/// **Повод записан замером, а не пожеланием.** 08.10.2026 я попросил
/// кадры нового экрана, и тестировщик ответил: пять из шести снять
/// нечем. Не «не сняли» — **нечем**:
///
/// ```
/// дорог к LabResultsScreen в приложении   1  (HealthScreen → «Анализы»)
/// UI-тестов, проходящих по ней            0
/// ```
///
/// То есть экран существовал, был достижим человеком и **непроверяем
/// стендом**. У нас это записано прямо: «прежде чем проверять
/// поверхность, проверь, что её МОЖНО проверить. Поверхность без кадра —
/// это не „непроверенная“, это „непроверяемая“, и первое лечится
/// взглядом, второе только переделкой входа».
///
/// > **Кадр появляется не тогда, когда его попросили, а тогда, когда
/// > к поверхности есть дорога у стенда.** Просьба без дороги — это
/// > наряд, который нельзя выполнить.
///
/// Этот файл и есть дорога. Он ничего не утверждает про цвет
/// и расстановку — он доводит приложение до шести состояний и кладёт
/// кадры файлами. Судит их человек.
nonisolated final class Анализы: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-анализов")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        // Сценарий с лечением: вкладка «Здоровье» и расписание доз
        // нужны шагу 3 — без активного лечения алерт про время
        // не показывается ВОВСЕ, и это верное поведение, а не дефект.
        app.launchArguments = ["-UITesting", "-Сценарий", "amber"]
        app.launch()
    }

    /// Суффикс имени кадра — тема и язык приходят СНАРУЖИ.
    ///
    /// Тест не знает, в какой теме его запустили, и угадывать не должен:
    /// **ярлык, который печатает сам инструмент, не является его
    /// замером** — 07.10.2026 кадр с подписью «светлая тема» оказался
    /// тёмным, потому что подпись не зависела от исхода. Поэтому имя
    /// различает партии по переменной окружения, а какая тема на кадре
    /// — решает тот, кто сравнивает яркость.
    ///
    /// Без суффикса две партии перезаписали бы друг друга и разошлись
    /// бы молча: у соседа сегодня двадцать пять кадров различало
    /// только имя.
    ///
    /// **Имя переменной ЛАТИНИЦЕЙ, и это не вкусовщина — замерено.**
    /// Первая редакция звала её `КАДР_СУФФИКС`, и запуск из оболочки
    /// падал с кодом **127**:
    ///
    /// ```
    /// КАДР_СУФФИКС=тёмная xcodebuild …   → rc=127, command not found
    /// KADR_SUFFIX=dark xcodebuild …      → работает
    /// ```
    ///
    /// Кириллическое имя переменной окружения оболочка не заводит —
    /// это первое правило в своде правил этого проекта, и я наступил
    /// на него, потому что **сторож на кириллицу проверяет shell-скрипты,
    /// а имя жило в Swift**. Запрет был записан для одной стороны стыка,
    /// а сломалось на другой.
    ///
    /// > **Правило, проверяемое только на одной стороне стыка, на другой
    /// > не действует** — даже когда это буквально то же правило.
    ///
    /// Значение может быть любым, в том числе кириллическим: в имя файла
    /// оно идёт как есть. Запрет касается ИМЕНИ переменной, не значения.
    ///
    /// ## Ставится ТОЛЬКО с приставкой `TEST_RUNNER_`, и это замерено
    ///
    /// ```
    /// KADR_SUFFIX=dark xcodebuild … test-without-building
    ///     → rc=0, ** TEST EXECUTE SUCCEEDED **, кадры БЕЗ суффикса
    /// TEST_RUNNER_KADR_SUFFIX=dark xcodebuild … test-without-building
    ///     → rc=0, кадры «…-dark.png»
    /// ```
    ///
    /// `xcodebuild` не передаёт своё окружение процессу теста; он
    /// передаёт переменные с приставкой `TEST_RUNNER_`, снимая её.
    ///
    /// > **Первый прогон прошёл успешно и снял восемь кадров под
    /// > неверными именами.** Ни кода возврата, ни строки итога, ни числа
    /// > кадров не хватило бы, чтобы это заметить: отличало только имя
    /// > файла. Партия «светлая» перезаписала бы «тёмную» молча, и пара
    /// > кадров для сравнения яркости перестала бы существовать —
    /// > при зелёном прогоне.
    ///
    /// Поэтому зовётся так:
    /// `TEST_RUNNER_KADR_SUFFIX=light xcodebuild … -only-testing:TogoUITests/Анализы`
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    /// Кадр файлом, а не `XCTAttachment`: выгрузка вложений у нас
    /// измерена — не сработала пять раз из девяти. Вложение, которое
    /// не выгружается, — это кадр, которого нет.
    ///
    /// Отказ записи НЕ роняет тест (`try?` у вызывающего не нужен —
    /// ошибка печатается): кадр — это улика, а не ворота, и падение
    /// на съёмке лишило бы нас остальных семи.
    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    /// Прокрутить до элемента: строка раздела лежит в середине списка,
    /// и «не нашёл» без прокрутки означало бы «не доскроллил» —
    /// то есть говорило бы о дороге, а не об экране.
    private func докрутить(до элемент: XCUIElement, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if элемент.exists && элемент.isHittable { return true }
            app.swipeUp()
        }
        return элемент.exists && элемент.isHittable
    }

    func testДорогаКАнализамИТриШагаСняты() throws {
        XCTAssertTrue(app.staticTexts["Стич"].firstMatch.waitForExistence(timeout: 20),
                      "сценарий с лечением не построился — снимать нечего")

        // --- место вызова ---------------------------------------------
        let вкладка = app.tabBars.buttons["Здоровье"]
        XCTAssertTrue(вкладка.waitForExistence(timeout: 15), """
            вкладки «Здоровье» нет. Либо сценарий перестал ставить \
            лечение, либо вкладку закрывает право `seeMedical` — \
            и тогда это находка, а не повод пропускать.
            """)
        вкладка.tap()
        _ = app.navigationBars["Здоровье"].waitForExistence(timeout: 10)

        let строкаАнализов = app.buttons["Анализы"].firstMatch
        let дошли = докрутить(до: строкаАнализов)

        // **Кадр СНИМАЕТСЯ ДО проверки, которая может прервать тест.**
        // При `continueAfterFailure = false` всё, что стоит после
        // упавшей проверки, не исполняется никогда: сегодня у соседа
        // `add(кадр)` на `:88` не сработал ни разу, потому что падало
        // на `:71`, — и «кадра нет» читалось бы как свойство продукта.
        //
        // > **Пустой результат за упавшей проверкой неотличим от пустого
        // > результата измеренного мира.** Поэтому здесь сначала улика,
        // > потом суждение: если строки «Анализы» нет, кадр покажет,
        // > ЧТО было на экране вместо неё.
        снять("01-здоровье-строка-анализов")

        XCTAssertTrue(дошли, """
            на «Здоровье» нет строки «Анализы» даже после прокрутки.
            Это ТО САМОЕ состояние, в котором медслой пролежал \
            до 08.10.2026: экран есть, дороги нет. Сторож \
            `ДорогаКАнализамTests` проверяет упоминание в исходнике \
            и этого случая не видит — он тут и ловится.
            Кадр 01 снят ДО этой проверки — смотри, что на нём.
            """)

        строкаАнализов.tap()
        let открылся = app.navigationBars["Анализы"].waitForExistence(timeout: 10)
        снять("02-анализы-список")
        XCTAssertTrue(открылся,
                      "строка «Анализы» есть, а экран не открылся — имя упомянуто, и от упоминания ничего не происходит")

        // --- шаг 1 ----------------------------------------------------
        // Кнопка есть в двух местах: в тулбаре и в пустом состоянии.
        // Берём любую достижимую — пустой список или список с записями
        // зависит от сценария, и тест не должен падать от этого.
        let добавить = app.buttons["Добавить анализ"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 10), """
            кнопки «Добавить анализ» нет ни в тулбаре, ни в пустом \
            состоянии. Либо роль не даёт править лечение, либо ввод \
            недостижим — второе хуже и это находка.
            """)
        добавить.tap()

        let шаг1 = app.staticTexts["Когда и где"].waitForExistence(timeout: 10)
        снять("03-ввод-шаг1-когда-и-где")
        XCTAssertTrue(шаг1, "первый шаг ввода не открылся — смотри кадр 03")

        let лаборатория = app.textFields["Лаборатория"].firstMatch
        if лаборатория.waitForExistence(timeout: 5) {
            лаборатория.tap()
            лаборатория.typeText("IDEXX")
        }
        let номер = app.textFields["Номер бланка"].firstMatch
        if номер.exists {
            номер.tap()
            номер.typeText("VF120682")
        }

        app.buttons["Дальше"].firstMatch.tap()

        // --- шаг 2 ----------------------------------------------------
        let шаг2 = app.staticTexts["Показатели"].waitForExistence(timeout: 10)
        let показатель = app.textFields["Показатель"].firstMatch
        let полеЕсть = показатель.waitForExistence(timeout: 10)
        if !шаг2 || !полеЕсть { снять("04-ввод-шаг2-НЕ-ОТКРЫЛСЯ") }
        XCTAssertTrue(шаг2, "второй шаг не открылся")
        XCTAssertTrue(полеЕсть, "поля «Показатель» нет — вводить нечего")
        показатель.tap()
        показатель.typeText("Т4 общий")

        let число = app.textFields["Число"].firstMatch
        if число.exists {
            число.tap()
            // ЗАПЯТАЯ нарочно: `Double("12,9")` возвращает `nil`,
            // и если разбор сломается, запись ляжет без значения
            // при заполненном поле. Кадр этого не покажет — покажет
            // список после сохранения.
            число.typeText("16,75")
        }
        let единица = app.textFields["Единица"].firstMatch
        if единица.exists {
            единица.tap()
            единица.typeText("нмоль/л")
        }

        // Кадр снимается ПОСЛЕ заполнения: пустая форма показывает
        // расстановку, заполненная — то, что увидит человек, включая
        // как ложатся длинные единицы рядом с числом.
        снять("04-ввод-шаг2-показатели")

        app.buttons["Дальше"].firstMatch.tap()

        // --- шаг 3 ----------------------------------------------------
        let шаг3 = app.staticTexts["Забор во сколько?"].waitForExistence(timeout: 10)
        снять("05-ввод-шаг3-без-времени")
        XCTAssertTrue(шаг3, "третий шаг не открылся — смотри кадр 05")

        // Тумблер времени: с ним на экране появляются часы от дозы —
        // первый живой вызов `LabSampleTiming` в приложении.
        let тумблер = app.switches.firstMatch
        if тумблер.waitForExistence(timeout: 5) {
            тумблер.tap()
            снять("06-ввод-шаг3-с-временем-и-часами")
            тумблер.tap()
        }

        // --- алерт: при лечении шаг не пропускается молча -------------
        app.buttons["Сохранить анализ"].firstMatch.tap()

        let алерт = app.staticTexts["Сохранить без времени?"].firstMatch
        let есть = алерт.waitForExistence(timeout: 10)
        снять("07-алерт-сохранить-без-времени")
        XCTAssertTrue(есть, """
            алерта «Сохранить без времени?» нет, а лечение активно. \
            Значит шаг пропускается МОЛЧА — ровно то, от чего модель \
            защищается словами «при активном лечении время обязательно». \
            Поле не подставлено, а трение потеряно.
            Кадр 07 снят ДО этой проверки — на нём видно, что было вместо алерта.
            """)

        // Сохраняем так — и проверяем, что запись доехала. Без этого
        // кадры доказывали бы показ и ничего не говорили про сохранение.
        app.buttons["Сохранить так"].firstMatch.tap()

        let вернулись = app.navigationBars["Анализы"].waitForExistence(timeout: 10)
        let строка = app.staticTexts["Т4 общий"].firstMatch
        let появилась = строка.waitForExistence(timeout: 10)
        снять("08-анализы-список-с-записью")
        XCTAssertTrue(вернулись, "после сохранения не вернулись к списку")
        XCTAssertTrue(появилась, """
            анализ не появился в списке после сохранения. Три шага \
            собрали черновик и не дошли до хранилища — это не вопрос \
            показа, и сторож на вызов такого не видит.
            Кадр 08 снят ДО этой проверки — на нём видно, что в списке.
            """)

        // Контроль, что снимали НЕ заглушку: иначе восемь кадров
        // пустого экрана выглядели бы приёмкой.
        XCTAssertFalse(app.staticTexts["Анализов пока нет"].exists, """
            на последнем кадре пустое состояние при сохранённой записи — \
            либо список не перечитался, либо запись легла не этой собаке.
            """)

        print("СНЯТО КАДРОВ: 8 · \(каталог.path)")
    }
}
