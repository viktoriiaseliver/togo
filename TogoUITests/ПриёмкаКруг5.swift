import XCTest

/// Кадры приёмки ответов дизайна, круг 5, пункты 1 и 2.
///
/// # Чего этот файл добивается и чем он отличается от соседей
///
/// Предмет — **то, что человек читает**, а не то, что посчитано.
/// Поэтому здесь кадры, и один из них обязан быть **с поднятой
/// клавиатурой**: ровно в этом состоянии живёт вся правка пункта 1
/// (панель над клавиатурой, просвет до поля, строка отказа под полем).
///
/// Кадров такого вида у Togo на 15.10.2026 было три, и все три негодные
/// (`Togo/CLAUDE.md`, «Тестированию»). Этот — четвёртый.
///
/// ## Вход выбран по предмету, а не по цене
///
/// ```
/// пункт 1, онбординг   БЕЗ -UITesting, стёртое устройство
///                      под флагом AppRoot идёт мимо онбординга
///                      (TogoApp.swift, `isUITesting || …`)
/// пункт 2, гость       -UITesting -ЧужаяЗона Виктория
///                      признак гостя — ключ группы приложений,
///                      сценарий демо-базы его не касается
/// ```
///
/// **Стирать обязательно, и не только ради онбординга.** Без `-UITesting`
/// `применитьЧужуюЗону` не зовётся вовсе — то есть чужая зона,
/// оставленная предыдущим гостевым прогоном, НЕ снимется, и
/// `AppRoot` покажет дневник вместо онбординга
/// (`isUITesting || onboardingCompleted || SharedZoneOwner.isGuest`).
/// Отказ пришёл бы в виде «онбординга нет», то есть ровно как дефект.
nonisolated final class ПриёмкаКруг5: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-круг5")
    }

    override func setUp() {
        continueAfterFailure = false
        снято = []
        app = XCUIApplication()
    }

    /// Счёт печатается ВСЕГДА, в том числе после падения: «снято пять»
    /// и «упал на втором, снято один» выглядят в логе одинаково —
    /// во втором случае строк про кадры просто нет, а их отсутствия
    /// не ищет никто.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ПриёмкаКруг5")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    // MARK: - Пункт 1 · онбординг

    /// Весь пункт 1 одним проходом — потому что онбординг **потребляется**
    /// первым же тестом партии: второй заход на стёртое устройство
    /// получит уже пройденный флаг.
    func testОнбордингКличкаОбязательнаВесНет() throws {
        app.launchArguments = []
        app.launch()

        // **Пропуск, а не падение, и это решение.**
        //
        // Онбординг ПОТРЕБЛЯЕТСЯ первым же тестом партии: кто дошёл
        // до него раньше, тот поставил `onboardingCompleted`. По алфавиту
        // перед этим классом идёт `ОнбордингНиз` (О < П), то есть
        // в полном прогоне сюда онбординга не доедет НИКОГДА.
        //
        // Красным это делать нельзя: красное без хозяина уезжает
        // в эталон и там живёт. Пропуск называет причину и рецепт,
        // и его видно в логе — в отличие от зелёного.
        //
        // Снято этим тестом вручную 25.10.2026 на 7e5e104, четыре кадра,
        // `Дизайн/кадры-приёмки/круг5-онбординг-и-гость-25.10/`.
        let начать = app.buttons["Начать"]
        guard начать.waitForExistence(timeout: 20) else {
            throw XCTSkip("""
                Онбординга на экране нет — стенд не тот, а не код плохой.
                Нужно ВСЁ сразу, и порядок важен:
                  1. xcrun simctl shutdown <udid> && xcrun simctl erase <udid>
                  2. xcrun simctl boot <udid> && xcrun simctl bootstatus <udid> -b
                  3. defaults write com.apple.keyboard.preferences \
                       DidShowContinuousPathIntroduction -bool true
                     (и DidShowGestureKeyboardIntroduction) — иначе первая
                     клавиатура приведёт обучалку QuickPath и закроет низ
                  4. -only-testing этого теста ОДНОГО, запуск БЕЗ -UITesting
                Чужая зона от гостевого прогона тоже сюда не пускает:
                под SharedZoneOwner.isGuest AppRoot показывает дневник,
                а снимает этот ключ только запуск С -UITesting.
                """)
        }
        начать.tap()

        let кличка = app.textFields["Кличка"]
        XCTAssertTrue(кличка.waitForExistence(timeout: 10), "Шаг «Кто у тебя живёт» не открылся")

        // ── Состояние 1: «Дальше» при пустой кличке ───────────────────
        //
        // Предмет кадра. До правки кнопка была ВЫКЛЮЧЕНА и не нажималась
        // вовсе; теперь она нажимается и отвечает тремя вещами разом:
        // слово под полем, фокус в поле (клавиатура поднимается ЗДЕСЬ)
        // и хаптика, которой на кадре не видно.
        let дальше = app.buttons["Дальше"]
        XCTAssertTrue(дальше.isEnabled, """
            «Дальше» выключена при пустой кличке. Правило круга 5:
            выключенная кнопка допустима только если рядом словом
            сказано, чего не хватает, — иначе она включена и объясняет.
            """)
        дальше.tap()

        let отказ = app.staticTexts["Напиши кличку — так её будет звать дневник"]
        XCTAssertTrue(отказ.waitForExistence(timeout: 5),
                      "Строки отказа под полем нет — кнопка промолчала")

        // Клавиатура обязана стоять: отказ уводит фокус в кличку.
        // Это и есть то состояние, ради которого снимается кадр.
        let клавиатура = app.keyboards.element(boundBy: 0)
        XCTAssertTrue(клавиатура.waitForExistence(timeout: 5), """
            Клавиатуры нет. Фокус в поле клички не уехал — значит кадр
            снят НЕ в том состоянии, в котором живёт предмет правки.
            """)

        // ── КОНТРОЛЬ, без которого весь замер ниже про другое ─────────
        //
        // На СТЁРТОМ устройстве первая клавиатура приводит с собой
        // обучалку QuickPath («Speed up your typing by sliding your
        // finger…» + Continue). XCUITest отдаёт её тем же
        // `app.keyboards.element`, и геометрия «панель над клавиатурой»
        // меряется тогда **по обучалке**, а не по клавиатуре: замер
        // 25.10.2026 дал зелёное «просвет 113 pt, панель выше» на кадре,
        // где панель лежит поперёк карточки веса.
        //
        // > **Стирать обязательно ради онбординга — и ровно стирание
        // > призывает обучалку.** То есть кадр онбординга с клавиатурой
        // > на этом стенде испорчен ПО УСТРОЙСТВУ, пока обучалку
        // > не погасить. Похоже, это и есть причина, по которой трёх
        // > прежних кадров такого вида хватило ровно на то, чтобы
        // > назвать их негодными.
        //
        // Гасится настройкой симулятора ПОСЛЕ стирания, до запуска:
        //   xcrun simctl spawn <udid> defaults write \
        //     com.apple.keyboard.preferences \
        //     DidShowContinuousPathIntroduction -bool true
        //   (и DidShowGestureKeyboardIntroduction)
        //
        // Контроль стоит ЗДЕСЬ, в том же замере, что предмет: взятый
        // отдельной командой до прогона, он ответил бы про настройку,
        // а не про то, что видно на кадре.
        XCTAssertFalse(app.buttons["Continue"].exists, """
            На экране обучалка клавиатуры QuickPath. Кадр снят НЕ с
            клавиатурой, и всякая геометрия низа ниже — про обучалку.
            Погасить настройкой симулятора после erase (рецепт выше).
            """)
        XCTAssertLessThan(клавиатура.frame.height, app.frame.height * 0.5, """
            «Клавиатура» высотой \(клавиатура.frame.height) при экране
            \(app.frame.height) — это не клавиатура, а лист поверх неё.
            """)

        // Геометрия, а не взгляд: просвет между нижним краем поля
        // и верхом панели обязан быть ≥ 16 pt (дизайн, круг 5 п. 1).
        let просвет = дальше.frame.minY - кличка.frame.maxY
        print("ПРОСВЕТ поле→панель: \(просвет) pt · " +
              (просвет >= 16 ? "выходит" : "НЕ ХВАТАЕТ"))
        print("ПОЛЕ maxY=\(кличка.frame.maxY) · ПАНЕЛЬ minY=\(дальше.frame.minY) " +
              "· КЛАВИАТУРА minY=\(клавиатура.frame.minY)")
        снять("01-кличка-пуста-клавиатура-поднята")
        XCTAssertGreaterThanOrEqual(просвет, 16, """
            Между нижним краем поля клички и панелью \(просвет) pt.
            Дизайн просит ≥ 16. Поле под панелью не оказывается никогда.
            """)
        XCTAssertLessThan(дальше.frame.maxY, клавиатура.frame.minY, """
            Панель «Дальше» залезла на клавиатуру или ушла под неё:
            панель maxY=\(дальше.frame.maxY), клавиатура minY=\(клавиатура.frame.minY).
            Панель обязана ехать НАД клавиатурой.
            """)

        // ── Состояние 2: строка исчезает с первым символом ────────────
        кличка.typeText("Стич")
        XCTAssertFalse(отказ.exists, "Строка отказа не ушла с первым символом")
        снять("02-кличка-названа-отказ-ушёл")

        // ── Состояние 3: вес НЕ введён, а «Дальше» уводит дальше ──────
        //
        // Главное утверждение пункта 1. До правки здесь кнопка гасла
        // на `weightValue != nil` и человек не проходил вовсе.
        let весПустой = app.textFields["Вес"]
        if весПустой.exists {
            XCTAssertEqual(весПустой.value as? String ?? "", "4,1",
                           "В поле веса что-то введено — замер «без веса» не состоялся")
        }
        снять("03-вес-пуст-можно-позже")
        дальше.tap()

        let режим = app.staticTexts["Режим дня"]
        XCTAssertTrue(режим.waitForExistence(timeout: 10), """
            С пустым весом дальше не пустило. Вес в онбординге
            не обязателен (ОТВЕТЫ-круг-5, п. 1).
            """)
        снять("04-прошли-без-веса")
    }

    // MARK: - Пункт 2 · гость узнаёт роль

    /// «Сегодня»: строка роли ВМЕСТО кнопок, и она ведёт в «Семью».
    func testГостьВидитРольНаСегодняИПопадаетВСемью() throws {
        app.launchArguments = ["-UITesting", "-ЧужаяЗона", "Виктория"]
        app.launch()

        let строка = app.buttons.containing(
            NSPredicate(format: "label BEGINSWITH %@", "Ты смотришь дневник")
        ).firstMatch
        XCTAssertTrue(строка.waitForExistence(timeout: 20), """
            Строки роли на «Сегодня» нет. Либо -ЧужаяЗона не доехала
            до SharedZoneOwner, либо право .logBasics у наблюдателя есть.
            """)

        // Кнопок записи у того, кто не отмечает, быть не должно вовсе:
        // «убрать», а не «выключить» (решение дизайна, круг 5 п. 2).
        XCTAssertFalse(app.buttons["Записать"].exists,
                       "Круглая «+» осталась у того, кто не отмечает")
        XCTAssertFalse(app.buttons["Просится"].exists,
                       "Главная кнопка осталась у того, кто не отмечает")
        снять("05-сегодня-строка-роли-вместо-кнопок")

        // Тап ведёт в «Семью» — это единственное место, где человек
        // может что-то с этим сделать: попросить роль у того, кто её выдаёт.
        строка.tap()
        let своя = app.staticTexts.containing(
            NSPredicate(format: "label BEGINSWITH %@", "Ты · ")
        ).firstMatch
        XCTAssertTrue(своя.waitForExistence(timeout: 10),
                      "Тап по строке роли не довёл до «Семьи»")
        снять("06-семья-своя-строка-первой")

        // Своя строка обязана стоять ПЕРВОЙ в карточке участников:
        // выше любой карточки семьи.
        let участники = app.staticTexts.matching(
            NSPredicate(format: "label == %@", "Виктория")
        ).firstMatch
        if участники.exists {
            XCTAssertLessThan(своя.frame.minY, участники.frame.minY, """
                Своя строка стоит ниже участника «Виктория»:
                своя minY=\(своя.frame.minY), её minY=\(участники.frame.minY).
                Дизайн просит «своя строка первой».
                """)
        }
        print("СВОЯ СТРОКА: «\(своя.label)» · minY=\(своя.frame.minY)")
    }
}
