import XCTest

/// Приёмка плаката 07.10.2026: пять режимов, снятых кадром, и замер
/// точки вместо взгляда.
///
/// **Почему замер, а не взгляд.** У Togo это оплачено главной кнопкой
/// приложения: `Component.Button.Primary.label` стоял и был правильным,
/// токен был верен всегда, тест требовал ровно его — а кнопка давала
/// 1,68:1 и не читалась ни разу за всё время. Кадры снимались и раньше,
/// подпись читали глазами и соглашались, потому что привыкли. Поймал
/// **замер пикселя**, а не взгляд.
///
/// **Что именно здесь измеряется и почему не цвет темы.** Соблазн —
/// вписать `0x2A3670` и сверять. Так делать нельзя по двум причинам,
/// и обе измерены сегодня:
///
/// 1. `togo-08` переводит токены на динамические значения: одно и то же
///    имя даёт разный hex в тёмной и светлой. Жёстко вписанное число
///    покраснеет на верном коде при первой смене темы;
/// 2. `togo-3b` поймал худшее: **кадр может быть снят не в той теме,
///    которую просили, и проверка это подтвердит.** У него тест печатал
///    «светлая тема» и проходил, а карточка была тёмная — обе половины
///    сломались одинаково и сошлись.
///
/// Поэтому проверка от **отношений между режимами**, а не от значений:
/// пять подложек обязаны отличаться друг от друга, а подпись на дозе —
/// от подписи на остальных. Это ровно то, что ломается, если вид
/// перестанет спрашивать режим; и это верно в любой теме.
///
/// > **Утверждение, не зависящее от темы, сильнее утверждения о цвете:
/// > второе проверяет и тему, и вид одной проверкой — и путает их,
/// > когда краснеет.**
nonisolated final class ПлакатВГалерееUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testПятьРежимовПлакатаСнимаютсяИОтличаются() throws {
        let настройки = app.buttons[подписи("Настройки")].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 20), "не дождались главного экрана")
        настройки.tap()

        let плакат = найти("Плакат", в: app)
        XCTAssertTrue(плакат.waitForExistence(timeout: 10),
                      "нет входа «Плакат» — галерея под `#if DEBUG`")
        плакат.tap()

        // Контроль: галерея ПОСТРОИЛАСЬ. Без него все проверки ниже
        // выполняются на пустом экране, и набор зелен, не проверив
        // ничего.
        let первый = app.staticTexts["режим · обычный день"].firstMatch
        XCTAssertTrue(первый.waitForExistence(timeout: 10), """
            галереи плаката на экране нет. Это не «с плакатом всё \
            хорошо» — это нечем смотреть.
            """)

        // **Ночь: подпись ПЕРЕДАНА нарочно и появиться не должна.**
        // `carriesStatusColour` у этого режима ложно, и проверка идёт
        // от того, что дефект нарушает: появление строки значит, что
        // вид спрашивает не у режима, а у себя.
        //
        // Проверяется ДО прокрутки к ночи — элемент «существует»
        // и не будучи построенным на экране, поэтому запрет по всему
        // дереву, а не по видимости.
        XCTAssertFalse(app.staticTexts["ЭТОЙ СТРОКИ НА КАДРЕ БЫТЬ НЕ ДОЛЖНО"].exists, """
            на нейтральном блоке появилась статусная подпись. Вид \
            не спросил `PosterMode.carriesStatusColour`, а решил сам — \
            и это ровно та вторая реализация правила, из-за которой \
            правило и вынесли из вью.
            """)

        // Опознаём блоки по `rawValue` режима, а не по русской подписи:
        // подпись переводится, `rawValue` — нет.
        let режимы = ["usual", "fasting", "dose", "alarm", "quiet"]
        var цветаПодложек: [String: UInt32] = [:]

        // **Замер идёт только по тому, что НА ЭКРАНЕ.** Первая редакция
        // считала точку от рамки заголовка раздела и промахивалась:
        // три замера из четырёх вернули `nil`, потому что точка
        // уезжала за кадр. Поймала это не моя внимательность,
        // а собственная проверка «замерено N из четырёх» — без неё
        // тест был бы ЗЕЛЁНЫМ при одном измерении, потому что
        // «все значения различны» для одного значения истинно всегда.
        //
        // > Любой группе проверок нужна проверка, что ей было что
        // > проверять, и ставится она первой.
        //
        // `isHittable`, а не `exists`: второе истинно и для элемента
        // вне экрана — замечание togo-02, из-за которого «крутить,
        // пока не появится» может не прокрутить ни разу.
        for шаг in 0..<8 {
            if шаг > 0 { app.swipeUp() }

            let кадр = app.screenshot()
            if шаг == 0 || шаг == 3 || шаг == 6 {
                let вложение = XCTAttachment(screenshot: кадр)
                вложение.name = "11-плакат-экран-\(шаг)"
                вложение.lifetime = .keepAlways
                add(вложение)
            }

            for режим in режимы where цветаПодложек[режим] == nil {
                let блок = app.otherElements["плакат-\(режим)"].firstMatch
                guard блок.exists, блок.isHittable else { continue }
                // Точка — верхний ПРАВЫЙ угол блока: весь текст
                // плаката выровнен по левому краю, значит справа сверху
                // гарантированно подложка, а не буква.
                let точка = CGPoint(x: блок.frame.maxX - 10,
                                    y: блок.frame.minY + 10)
                if let цвет = цветВТочке(кадр: кадр, точка: точка) {
                    цветаПодложек[режим] = цвет
                }
            }
            if цветаПодложек.count == режимы.count { break }
        }

        let печать = цветаПодложек
            .map { "\($0.key)=#\(String(format: "%06X", $0.value))" }
            .sorted().joined(separator: " · ")

        // **Сначала — было ли что мерить.** Эта проверка стоит ПЕРЕД
        // проверкой различия нарочно: при одном замере «все значения
        // различны» истинно всегда, и зелёный ничего не значил бы.
        XCTAssertEqual(цветаПодложек.count, режимы.count, """
            замерено \(цветаПодложек.count) подложек из \(режимы.count): \(печать).
            Замер не состоялся — значит проверка различия ниже \
            ничего не утверждает, какой бы ни был её исход.
            """)

        // **Пять режимов обязаны отличаться подложкой.** Это и есть
        // проверка того, что вид спрашивает режим: совпали два — значит
        // один покрашен не своим токеном либо вид вовсе не смотрит
        // на `mode`.
        //
        // Проверка от ОТНОШЕНИЯ, а не от значения: она верна в любой
        // теме, а «подложка равна `0x2A3670`» покраснела бы на верном
        // коде при первой смене темы — и уже покраснела бы сегодня,
        // потому что светлую завели вечером.
        XCTAssertEqual(Set(цветаПодложек.values).count, цветаПодложек.count,
                       "подложки режимов совпали: \(печать)")

        // Напечатать замер обязательно, даже когда всё сошлось: иначе
        // «пять разных» нечем отличить от «пять одинаково неверных».
        print("замер подложек плаката: \(печать)")
    }

    /// Цвет точки кадра около рамки элемента — или `nil`, если
    /// измерить не удалось.
    ///
    /// **Байты чужого `cgImage` не читаем напрямую.** Порядок каналов
    /// и наличие альфы у него свои, и «верить его порядку» значит
    /// получить `BGRA`, прочитанное как `RGBA`, — цвет, которого
    /// на экране нет. Перерисовываем одну точку в формат, который
    /// задали сами.
    private func цветВТочке(кадр: XCUIScreenshot, точка: CGPoint) -> UInt32? {
        let картинка = кадр.image
        let масштаб = картинка.scale
        let px = CGPoint(x: точка.x * масштаб, y: точка.y * масштаб)
        guard let cg = картинка.cgImage,
              px.x >= 0, px.y >= 0,
              Int(px.x) < cg.width, Int(px.y) < cg.height else { return nil }

        var байты = [UInt8](repeating: 0, count: 4)
        guard let пространство = CGColorSpace(name: CGColorSpace.sRGB),
              let контекст = CGContext(data: &байты, width: 1, height: 1,
                                       bitsPerComponent: 8, bytesPerRow: 4,
                                       space: пространство,
                                       bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
        else { return nil }
        контекст.draw(cg, in: CGRect(x: -px.x, y: px.y - CGFloat(cg.height) + 1,
                                     width: CGFloat(cg.width), height: CGFloat(cg.height)))
        return (UInt32(байты[0]) << 16) | (UInt32(байты[1]) << 8) | UInt32(байты[2])
    }
}
