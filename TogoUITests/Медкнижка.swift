import XCTest

/// Кадр медкнижки — и снимает его НЕ автор экрана.
///
/// `4c00d2a` автор принял сам, и в теме коммита честно: «кадр нашёл
/// в нём то, чего не увидел зелёный тест». Это хорошо и этого мало:
/// у нас записано, что **автор не принимает свою работу** — он
/// смотрит туда, куда смотрел, когда писал. 07.10.2026 этот порядок
/// поймал четыре ложных вывода, и дважды — у автора находки на себе
/// же.
///
/// Снимается галерея `MedicalRecordGallery`: она собрана автором
/// под шесть трудных случаев разом (предел обнаружения, коридор
/// в окне и вне окна, текстовый результат, анализ без референса,
/// показатель без раздела) и живёт в памяти — ни хранилища на диске,
/// ни чужого симулятора ей не нужно.
///
/// **Проверяется глазом, а не числом.** Четыре решения автора, каждое
/// ломается показом, и ни одно не берётся текстом:
///
/// ```
/// значение в трёх формах   «<0,1 нг/дл» НЕ превращается в «0,1»
/// отметка лаборатории      показывается ТОЛЬКО вместе с нашим вердиктом
///                          и подписанная — кто сказал
/// «через сколько после дозы»  «не записано» — ОТВЕТ, а не пустота
/// группировка              гормоны · биохимия · бактериология не смешаны
/// ```
nonisolated final class Медкнижка: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-медкнижки")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Иначе «снято всё» и «упал на третьем» выглядят
        // в логе ОДИНАКОВО: во втором случае строк `КАДР:` просто
        // меньше, а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своей проверкой, а не эта печать.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "Медкнижка")
        super.tearDown()
    }

    /// Кадр окна приложения файлом.
    ///
    /// Файлом, а не `XCTAttachment`: выгрузка вложений у нас измерена —
    /// не сработала пять раз из девяти. Вложение, которое
    /// не выгружается, — это кадр, которого нет.
    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        снято.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    func testГалереяМедкнижкиСнятаДляЧеловека() throws {
        // Кнопка настроек уехала в меню «…» 22.10; дорогу знает
        // один `открытьНастройки`.
        XCTAssertTrue(открытьНастройки(в: app),
                      "до настроек не дошли — кадра нет, и это не «экрана нет»")

        // Ссылка лежит в отладочном разделе, низко: без прокрутки
        // её не видно, и «не нашёл» означало бы «не доскроллил».
        let ссылка = app.buttons["Медкнижка"].firstMatch
        for _ in 0..<8 where !ссылка.exists { app.swipeUp() }
        XCTAssertTrue(ссылка.waitForExistence(timeout: 5), """
            ссылки «Медкнижка» нет. Либо отладочный раздел собран
            не в этой конфигурации, либо до него не доскроллили —
            и тогда «кадра нет» говорит о дороге, а не об экране.
            """)
        ссылка.tap()

        // Галерея собирает срез в памяти — ей нужен такт.
        let заголовок = app.staticTexts["Медкнижка"].firstMatch
        XCTAssertTrue(заголовок.waitForExistence(timeout: 10),
                      "галерея не открылась")

        // Снимается НЕСКОЛЬКО кадров: шесть случаев в один экран
        // не помещаются, а кадр, на котором видно половину, —
        // это приёмка половины.
        var пути: [URL] = []
        for шаг in 0..<4 {
            пути.append(try снять("медкнижка-\(шаг + 1)"))
            app.swipeUp()
        }

        // Контроль, что снимали НЕ пустоту: без него четыре кадра
        // «Собираю срез…» выглядели бы приёмкой.
        XCTAssertFalse(app.staticTexts["Собираю срез…"].exists, """
            галерея так и не собрала срез — на кадрах заглушка,
            а не медкнижка. Кадры: \(пути.map(\.lastPathComponent))
            """)

        print("СНЯТО КАДРОВ: \(пути.count) · \(каталог.path)")
    }
}
