import XCTest

/// Шесть шагов онбординга кадрами — по одному на шаг, партиями по теме.
///
/// **Имя по роли: он снимает ПОВЕРХНОСТЬ, а не проверяет число.**
/// Соседний `ОнбордингНиз` меряет геометрию — уходит ли нижний текст
/// под закреплённую панель, — и его предмет не тема и не полнота.
/// Переделывать его под кадры было бы подменой предмета: он четыре
/// шага из шести трогает ради замера, а `welcome` и `care` не снимает
/// вовсе.
///
/// ## Чего до него не существовало
///
/// ```
/// кадров онбординга в проекте   2, оба светлых, один помечен НЕГОДЕН
/// тема в них                    СИСТЕМНАЯ по умолчанию, тестом
///                               не задавалась — записано в README
///                               каталога кадров 08.10
/// шагов снято                   4 из 6 (нет welcome, нет care),
///                               и то ради замера низа, а не показа
/// ```
///
/// То есть «светлая» в тех кадрах — не выбор, а то, что досталось
/// от устройства. По картинке «светлая нарочно» и «светлая случайно»
/// не различаются ничем.
///
/// ## Как запускать, и почему двумя заходами
///
/// ```
/// TEMA=dark  KADR_SUFFIX=dark  Tools/прогон-ui.sh …
/// TEMA=light KADR_SUFFIX=light Tools/прогон-ui.sh …
/// ```
///
/// `Tools/прогон-ui.sh` (`f5d5870`) задаёт положение устройства,
/// печатает его **всегда** и при заданном сверяет «просили →
/// получили», объявляя прогон несостоявшимся кодом 9 при расхождении.
/// Без него тема берётся та, что осталась от предыдущей сессии:
/// положение живёт в устройстве и переживает прогон.
///
/// > **Состояние, пережившее прогон, неотличимо на экране
/// > от состояния, заданного прогоном.**
///
/// Суффикс партии доезжает **только** как `TEST_RUNNER_KADR_SUFFIX`:
/// `xcodebuild` отдаёт процессу теста лишь переменные с этой
/// приставкой, снимая её. Без неё обе партии пишутся одними именами,
/// и вторая молча затирает первую — прогон при этом зелёный, и кадров
/// столько же, сколько ожидалось.
///
/// ## Вход, без которого этого файла не могло быть
///
/// `-UITesting -Сценарий onboarding -Онбординг` (`1c1508d`, `f5d614f`,
/// `bd4783d`). Первый даёт базу в памяти, второй — **пустую**, третий
/// открывает ворота `AppRoot`. Без второго `isReplay` истинен
/// и снимется справка вместо шагов; без третьего — главный экран.
///
/// **Чего этот путь НЕ делает, и это надо знать, читая кадры.** Он
/// обходит оба ворота, а не проходит их: `пишемВБазу` ложно, поэтому
/// засев, `DogOrigin.заведенаЗдесь` и первая запись веса
/// не случаются. Кадры показывают **вид** шагов, а не след, который
/// проход оставляет в хранилище. На второй вопрос отвечает
/// `ОнбордингНиз` без `-UITesting` на стёртом устройстве.
nonisolated final class ПоверхностьОнбординга: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-онбординга-поверхность")
    }

    /// Имя переменной латиницей: кириллическое оболочка не заводит
    /// вовсе, и подстановка молча отдаёт пустоту (`rc=127`).
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    private var снято: [String] = []

    override func setUp() {
        continueAfterFailure = false
        снято = []
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "onboarding", "-Онбординг"]
        app.launch()
    }

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения на третьем
        // шаге. Иначе «снято шесть» и «упал на третьем, снято два»
        // выглядят в логе одинаково — просто во втором случае строки
        // про кадры нет, а её отсутствие никто не ищет.
        print("КАДРОВ СНЯТО: \(снято.count) из 6 · \(снято.joined(separator: ", "))")
    }

    // MARK: - Инструменты

    @discardableResult
    private func снять(_ имя: String) -> Bool {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return true
        } catch {
            // Не `XCTFail`: падать здесь значит потерять оставшиеся
            // пять кадров из-за одного. Отказ записи назван в логе
            // и виден в итоговом счёте.
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return false
        }
    }

    /// Бюджет в секундах, а не число попыток.
    ///
    /// Число попыток меряет машину, на которой его выбрали: смена кадра
    /// на занятой занимает больше, чем весь бюджет из десяти опросов
    /// по четверти секунды. Сегодня машина за смену ходила от `load 6`
    /// до `load 640`.
    private func дождаться(_ заголовок: String, секунд: TimeInterval = 40) -> Bool {
        app.staticTexts[заголовок].firstMatch.waitForExistence(timeout: секунд)
    }

    /// Убрать клавиатуру после ввода.
    ///
    /// Из-за неё первый кадр шага собаки 08.10 вышел негодным: ввод
    /// поднимает клавиатуру, она остаётся, вёрстка под ней едет.
    ///
    /// > **Стенд, оставивший после себя клавиатуру, меряет клавиатуру.**
    private func убратьКлавиатуру() {
        guard app.keyboards.element.exists else { return }
        app.staticTexts.allElementsBoundByIndex.first { $0.exists && $0.isHittable }?.tap()
        _ = app.keyboards.element.waitForNonExistence(timeout: 10)
    }

    /// Тап по КНОПКЕ с таким именем, а не по любому элементу.
    ///
    /// На витрине компонентов этим уже спотыкались: тап попадал
    /// в подпись внутри строки, а не в кнопку, и экран не открывался
    /// при зелёном поиске элемента.
    private func нажать(_ подпись: String, файл: StaticString = #filePath,
                        строка: UInt = #line) {
        let кнопка = app.buttons[подпись].firstMatch
        XCTAssertTrue(кнопка.waitForExistence(timeout: 40),
                      "Кнопки «\(подпись)» нет — дальше по шагам не пройти.",
                      file: файл, line: строка)
        кнопка.tap()
    }

    // MARK: - Шесть шагов подряд

    func testШестьШаговСняты() {
        // 1 · Приветствие. Опознаётся по кнопке, а не по заголовку:
        // «Дневник» живёт и на главном экране, а «Добавить собаку»
        // стоит только здесь и только при ложном isReplay — при
        // повторном прохождении там «Перечитать».
        XCTAssertTrue(app.buttons["Добавить собаку"].firstMatch.waitForExistence(timeout: 40), """
            Первый шаг не показался. Три разные причины, и по этому
            сообщению их не различить — смотреть так:
              • «Перечитать» вместо «Добавить собаку» → база НЕ пуста,
                то есть не доехал -Сценарий onboarding;
              • виден таб-бар → не доехал -Онбординг, ворота закрыты;
              • пусто вовсе → приложение не поднялось.
            """)
        снять("01-приветствие")
        нажать("Добавить собаку")

        // 2 · Кличка и вес. Кадр снимается ДО ввода: в макете это
        // «02 Кличка», то есть пустая форма, а не заполненная.
        XCTAssertTrue(дождаться("Кто у тебя живёт"), "Шаг собаки не открылся.")
        снять("02-кто-у-тебя-живёт")

        // Ввод нужен не кадру, а проходу: «Дальше» включается только
        // при непустой кличке и разобранном весе (`DogDraft.isValid`).
        let кличка = app.textFields["Стич"].firstMatch
        if кличка.waitForExistence(timeout: 10) {
            кличка.tap()
            кличка.typeText("Стич")
        }
        let вес = app.textFields["4,1"].firstMatch
        if вес.exists {
            вес.tap()
            вес.typeText("4,1")
        }
        убратьКлавиатуру()
        нажать("Дальше")

        // 3 · Режим дня.
        XCTAssertTrue(дождаться("Режим дня"), "Шаг режима дня не открылся.")
        снять("03-режим-дня")
        нажать("Дальше")

        // 4 · Уход. Подпись кнопки зависит от числа отмеченного:
        // по умолчанию отмечено то, что `isDefault`, то есть «Дальше · N».
        // Пустой случай («Пропустить») тоже возможен, если умолчания
        // снимут, — поэтому проверяются обе.
        XCTAssertTrue(дождаться("Что делаешь для ухода"), "Шаг ухода не открылся.")
        снять("04-что-делаешь-для-ухода")
        let дальшеСчётом = app.buttons.matching(NSPredicate(format: "label BEGINSWITH 'Дальше'"))
            .firstMatch
        if дальшеСчётом.exists {
            дальшеСчётом.tap()
        } else {
            нажать("Пропустить")
        }

        // 5 · Семья.
        XCTAssertTrue(дождаться("Кто ещё за ним ходит"), "Шаг семьи не открылся.")
        снять("05-кто-ещё-за-ним-ходит")
        // «Пока сама», а не «Отправить ссылку»: вторая заводит участника
        // «Приглашение» и при этом ничего не отправляет — известное
        // ложное обещание, оставленное в описи решением 14.10.
        нажать("Пока сама")

        // 6 · Уведомления. Кадр снимается, кнопка «Разрешить» НЕ жмётся:
        // это системный запрос, а системный алерт блокирует всё, что
        // идёт следом. В просмотре он и так молчит, но полагаться
        // на это в тесте значит проверять свою же правку её же словами.
        XCTAssertTrue(дождаться("Что будет прерывать"), "Шаг уведомлений не открылся.")
        снять("06-что-будет-прерывать")

        XCTAssertEqual(снято.count, 6, """
            Снято \(снято.count) кадров из шести: \(снято.joined(separator: ", ")).
            Недостающие — не «не успели», а не записались: смотреть
            строки «КАДР НЕ ЗАПИСАН» в логе, каталог \(каталог.path).
            """)
    }
}
