import XCTest

/// Кадр экрана «Показать в аптеке» — и снимает его НЕ автор экрана.
///
/// Экран сдан `16b935f`: номер рецепта на весь экран, чтобы провизор
/// разобрал его через стекло в чужом свете. Проверяется он **только
/// глазом**: крупно ли, читается ли, не обрезан ли — ни одно из трёх
/// не берётся ни тестом, ни чтением кода.
///
/// # Чего этот кадр НЕ доказывает, и это надо сказать первым
///
/// Рядом с номером живёт `fa62faa` — подъём яркости на время показа.
/// **Его этим кадром не принять ни при каком объёме работы.**
/// В симуляторе `UIScreen.brightness` — обычное свойство, подсветки
/// нет: поднятие не меняет отрисованные пиксели, и снимки до и после
/// совпадут. «Светлее не стало» было бы утверждением о симуляторе,
/// прозвучавшим как находка о продукте.
///
/// Дороги возврата яркости держит `ВозвратЯркостиTests` (три дороги,
/// «Закрыть» среди них нет, доказанно краснеет на снятом
/// `onDisappear`). Физическая яркость уходит проверкой на живом
/// телефоне — это не долг кода, а то, чего мы измерить не можем.
///
/// # Дорога тут длинная, и это не прихоть
///
/// Галереи для аптеки нет, значит идём настоящим приложением:
///
/// ```
/// вкладка «Здоровье» → «Назначения» → «+» → редактор
/// → заполнить препарат (без него «Добавить» выключена)
/// → «Добавить» → строка списка → редактор снова
/// → «Показать в аптеке» → полноэкранный номер
/// ```
///
/// Кнопка «Показать в аптеке» живёт у СУЩЕСТВУЮЩЕГО назначения,
/// поэтому рецепт сперва заводится, а потом открывается заново.
///
/// У каждого шага свой контроль с объяснением: «кадра нет» должно
/// отличаться от «экрана нет». Пять кадров витрины с чужим
/// приложением мы уже снимали при зелёном прогоне.
nonisolated final class ЭкранАптеки: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-аптеки")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Кадр окна ПРИЛОЖЕНИЯ, а не экрана устройства.
    ///
    /// `app.screenshot()`, не `XCUIScreen.main.screenshot()`: экран
    /// принадлежит симулятору, окно — приложению, и на общем
    /// симуляторе в кадр уже попадало чужое приложение.
    ///
    /// Файлом, а не вложением: выгрузка вложений у нас не сработала
    /// пять раз из девяти, а вложение, которое не выгружается, —
    /// это кадр, которого нет.
    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    private func докрутить(до элемент: XCUIElement, шагов: Int = 8) {
        for _ in 0..<шагов where !элемент.exists { app.swipeUp() }
    }

    func testНомерДляАптекиСнятДляЧеловека() throws {
        // 1. Вкладка «Здоровье». С 08.10.2026 её держит ПРАВО,
        //    а не лечение, — значит у владельца она есть всегда.
        let здоровье = app.buttons["Здоровье"].firstMatch
        XCTAssertTrue(здоровье.waitForExistence(timeout: 10), """
            вкладки «Здоровье» нет. Это НЕ «экрана аптеки нет»: \
            до него мы просто не дошли. Условие показа — \
            `appState.can(.seeMedical)`.
            """)
        здоровье.tap()

        // 2. «Назначения» — ссылка внутри экрана, может быть ниже сгиба.
        let назначения = app.buttons["Назначения"].firstMatch
        докрутить(до: назначения)
        XCTAssertTrue(назначения.waitForExistence(timeout: 5), """
            ссылки «Назначения» нет на экране «Здоровье» — \
            дорога оборвалась здесь, а не в аптеке.
            """)
        назначения.tap()

        // 3. Завести рецепт: кнопка «+» в тулбаре либо действие
        //    пустого состояния — у них ОДНА подпись.
        let добавить = app.buttons["Добавить назначение"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 5), """
            нечем завести назначение. Кнопка есть только при праве \
            `editTreatment` — если его нет, дорога закрыта правом, \
            а не сломана.
            """)
        добавить.tap()

        // 4. Препарат — единственное обязательное поле: без него
        //    «Добавить» выключена (`можноСохранить`).
        let препарат = app.textFields["Левотироксин"].firstMatch
        XCTAssertTrue(препарат.waitForExistence(timeout: 5), "редактор не открылся")
        препарат.tap()
        препарат.typeText("Левотироксин")

        let номерПоля = app.textFields["8935331"].firstMatch
        if номерПоля.exists {
            номерПоля.tap()
            номерПоля.typeText("8935331")
        }

        let сохранить = app.buttons["Добавить"].firstMatch
        докрутить(до: сохранить)
        XCTAssertTrue(сохранить.waitForExistence(timeout: 5), "кнопки «Добавить» нет")
        XCTAssertTrue(сохранить.isEnabled, """
            «Добавить» выключена при заполненном препарате — \
            значит условие сохранения не то, что мы думаем.
            """)
        сохранить.tap()

        // 5. Открыть заведённое: «Показать в аптеке» есть только
        //    у существующего назначения.
        let строка = app.buttons.containing(
            NSPredicate(format: "label CONTAINS[c] %@", "8935331")
        ).firstMatch
        XCTAssertTrue(строка.waitForExistence(timeout: 5), """
            назначение не появилось в списке. Либо сохранение \
            не прошло, либо строка подписана иначе — и тогда \
            «кадра нет» говорит о дороге.
            """)
        строка.tap()

        // 6. Сама кнопка. Ищем КНОПКУ, а не любой элемент с этим
        //    текстом: заголовки у нас рисуются прописными, и проверка
        //    по тексту однажды уже искала не то.
        let вАптеке = app.buttons["Показать в аптеке"].firstMatch
        докрутить(до: вАптеке)
        XCTAssertTrue(вАптеке.waitForExistence(timeout: 5), """
            кнопки «Показать в аптеке» нет у существующего назначения. \
            Вот ЭТО уже находка об экране, а не о дороге: всё \
            предыдущее прошло.
            """)
        вАптеке.tap()

        // 7. Контроль, что мы НА ТОМ экране, а не на редакторе.
        //    Без него кадр редактора прошёл бы за кадр аптеки.
        let номер = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "8935331")
        ).firstMatch
        XCTAssertTrue(номер.waitForExistence(timeout: 5), """
            на полноэкранном показе нет номера рецепта. Снимать \
            нечего: кадр без номера — это приёмка пустоты.
            """)

        try снять("аптека-номер")

        // Что на кадре КРУПНО и читается — решает человек, который
        // на него посмотрит. Тест довёл до экрана и доказал, что
        // на экране номер; остальное не берётся числом.
        print("""
            ГРАНИЦА: кадр доказывает, что номер показан на весь экран. \
            Читается ли он провизором через стекло — смотрит человек. \
            Яркость этим кадром НЕ проверяется вовсе.
            """)
    }
}
