import XCTest

/// Онбординг: доходит ли последний блок до конца прокрутки, не уходя
/// под закреплённый низ.
///
/// **Повод — приёмка `3a72afc`, и до этого файла её нельзя было снять
/// вовсе.** Замер 08.10 нашёл три слота `} bottom: {`, у которых запас
/// под панелью меньше её настоящей высоты, и все три оказались
/// в онбординге:
///
/// ```
/// OnboardingSteps:301  шаг приглашения   занято 126, запас 120   −6
/// OnboardingSteps:346  уведомления       занято 126, запас 120   −6
/// OnboardingSteps:130  кто у тебя живёт  занято 120, запас 120    0
/// ```
///
/// ## Почему без `-UITesting`, и это главное в файле
///
/// Онбординг **не рисуется ни в одном нашем прогоне**, и ворот двое,
/// независимых:
///
/// ```
/// TogoApp.swift:219   isUITesting || onboardingCompleted → RootView()
///                     то есть под -UITesting ВСЕГДА мимо онбординга
/// OnboardingFlow:20   isReplay = !dogs.isEmpty
///                     .dog    → HowItWorksScreen       вместо DogStep
///                     .family → HowItWorksReplayEnd    вместо FamilyStep
///                     .schedule → HowItWorksReplayEnd(onDone: finish)
/// ```
///
/// Путь «пройти онбординг заново» из настроек подменяет **ровно те
/// шаги, которые сломаны**, и кончает поток до шага уведомлений.
///
/// > **Три экрана, которые мы чиним, были единственными тремя, которые
/// > нельзя принять кадром.** Это «снять нечем», а не «не сняли»:
/// > лечится переделкой входа, а не взглядом.
///
/// Поэтому запуск здесь **без** `-UITesting`: на стёртом симуляторе
/// `onboardingCompleted` ложно, собак нет, `isReplay` ложен — и поток
/// рисует настоящие шаги подряд. Платой идёт отсутствие демо-базы;
/// онбордингу она и не нужна.
///
/// Симулятор обязан быть стёртым непосредственно перед прогоном
/// (`shutdown → erase → boot`), и **не общий**: чужой заход оставляет
/// и пройденный онбординг, и форму базы.
///
/// ## Приёмка числом, а не взглядом
///
/// Кадр здесь — улика для человека, а судит **геометрия**: у самого
/// нижнего текста берётся `maxY`, у кнопки низа — `minY`. Текст вышел
/// из-под панели, если `maxY ≤ minY`.
///
/// Это обходит то, на чём остановился соседний замер: плотность тёмных
/// пикселей наложение не различает (верхний слой **замещает** нижний,
/// а не суммируется, и 155 против 162 — ответ на другой вопрос).
/// Дерево доступности о перекрытии не знает тем более — и именно
/// поэтому отдаёт рамку текста, **спрятанного под непрозрачной
/// кнопкой**. То, чего не видно глазом, здесь measurable в точках.
///
/// ## Чего этот файл НЕ делает
///
/// Он ничего не утверждает про вид: ни про цвет, ни про то, права ли
/// панель без подложки. Он доводит приложение до четырёх состояний,
/// печатает две координаты на каждом и кладёт кадры файлами.
nonisolated final class ОнбордингНиз: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-онбординга")
    }

    /// Суффикс партии приходит СНАРУЖИ и только как
    /// `TEST_RUNNER_KADR_SUFFIX`: `xcodebuild` отдаёт процессу теста
    /// лишь переменные с этой приставкой, снимая её. Без приставки
    /// прогон зелёный, кадров столько же, имена — без суффикса,
    /// и светлая партия перезаписывает тёмную молча.
    ///
    /// Имя переменной латиницей: кириллическое оболочка не заводит
    /// вовсе (`rc=127`).
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        // -UITesting НЕ ставится нарочно: с ним онбординга не бывает.
        // Смотри разбор в шапке файла; это не упущение.
        app.launch()
    }

    // MARK: - Инструменты

    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    /// Прокрутить до упора: свайпы, пока нижний текст перестанет ехать.
    ///
    /// Счётчиком свайпов ограничиваться нельзя — число шагов зависит
    /// от длины экрана, а «сколько-то раз свайпнул» не значит «доехал
    /// до конца». Признак конца — координата перестала меняться.
    private func докрутитьДоКонца(шагов: Int = 12) {
        var прошлая: CGFloat = -1
        for _ in 0..<шагов {
            let текущая = нижнийТекст()?.frame.maxY ?? -1
            if текущая == прошлая { return }
            прошлая = текущая
            app.swipeUp()
        }
    }

    /// Самый нижний видимый текст экрана.
    ///
    /// Берётся по рамке, а не по известной строке: строку пришлось бы
    /// держать второй копией рядом с кодом экрана, и она разошлась бы
    /// молча при первой правке текста.
    private func нижнийТекст() -> XCUIElement? {
        let тексты = app.staticTexts.allElementsBoundByIndex.filter {
            $0.exists && $0.frame.height > 0 && !$0.label.isEmpty
        }
        return тексты.max { $0.frame.maxY < $1.frame.maxY }
    }

    /// Дождаться, пока вёрстка встанет.
    ///
    /// **Ранний кадр покажет обрезку, которой нет.** `TGScreen` выводит
    /// запас из настоящей высоты панели, а `высотаНиза` стартует
    /// с нуля: один кадр экран живёт с запасом `s24` вместо полного.
    /// Снимок в этот момент воспроизвёл бы ровно прежний дефект —
    /// и починка была бы принята как несработавшая.
    ///
    /// ## Покой считается ДВУМЯ подряд совпадениями, а не одним
    ///
    /// Одно совпадение подряд — это «между двумя опросами ничего
    /// не поехало», и на загруженной машине оно наступает **раньше,
    /// чем вёрстка встала**: кадр просто не успел смениться между
    /// опросами. Два подряд отличают «встало» от «не успело поехать».
    ///
    /// ## Бюджет по времени, а не по числу опросов
    ///
    /// Первая редакция ждала `10 × 0,25 с` = две с половиной секунды
    /// и звалась «десять попыток». Это число я выбрал на свободной
    /// машине, и оно молча становится негодным на занятой: смена кадра
    /// там занимает больше, чем весь бюджет.
    ///
    /// > **Ожидание, записанное числом попыток, меряет мою машину,
    /// > а не вёрстку.** Бюджет в секундах переживает чужую нагрузку;
    /// > число попыток — нет.
    ///
    /// Сам замер от нагрузки не зависит вовсе: `maxY` против `minY`
    /// — это геометрия уже установившегося кадра. Нагрузка влияет
    /// только на то, **дождались ли мы** установления, и лечится
    /// именно ожиданием, а не поправкой к числу.
    @discardableResult
    private func дождатьсяПокоя(секунд бюджет: TimeInterval = 12) -> Bool {
        let шаг: TimeInterval = 0.25
        let дедлайн = Date().addingTimeInterval(бюджет)
        var прошлая: CGFloat = -1
        var совпадений = 0
        while Date() < дедлайн {
            let текущая = нижнийТекст()?.frame.maxY ?? -1
            if текущая > 0 && текущая == прошлая {
                совпадений += 1
                if совпадений >= 2 { return true }
            } else {
                совпадений = 0
            }
            прошлая = текущая
            Thread.sleep(forTimeInterval: шаг)
        }
        return false
    }

    /// Дождаться заголовка шага.
    ///
    /// **Сорок секунд, а не десять, и это замерено, а не на всякий
    /// случай.** Первый прогон упал на `Что делаешь для ухода` с десятью:
    /// весь проход занял 226 секунд там, где на свободной машине ушло бы
    /// секунд тридцать. Короткое ожидание на занятой машине даёт отказ,
    /// неотличимый от «экрана нет» — то есть превращает загрузку
    /// в находку.
    private func дождаться(_ заголовок: String, секунд: TimeInterval = 40) -> Bool {
        app.staticTexts[заголовок].firstMatch.waitForExistence(timeout: секунд)
    }

    /// Убрать клавиатуру после ввода.
    ///
    /// **Из-за неё первый замер `:130` вышел негодным.** Клавиатура
    /// поднимается на `typeText` и остаётся: вёрстка под ней едет,
    /// нижний текст не встаёт никогда, и `дождатьсяПокоя` честно
    /// сдаётся. То есть экран был ни при чём — мешал наш собственный
    /// ввод.
    ///
    /// > **Стенд, оставивший после себя клавиатуру, меряет клавиатуру.**
    ///
    /// Закрывается нажатием по заголовку экрана: он не кнопка
    /// и не поле, тап по нему только снимает фокус.
    private func убратьКлавиатуру() {
        guard app.keyboards.element.exists else { return }
        let заголовок = app.staticTexts.allElementsBoundByIndex.first {
            $0.exists && $0.isHittable
        }
        заголовок?.tap()
        // Клавиатура уезжает анимацией; без ожидания следующий замер
        // поймает её на полпути.
        _ = app.keyboards.element.waitForNonExistence(timeout: 10)
    }

    /// Замер одного экрана: доходит ли нижний текст до конца прокрутки.
    ///
    /// Возвращает перекрытие в точках: положительное — текст уходит
    /// под панель и не выходит, ноль и меньше — выходит.
    @discardableResult
    private func замерить(_ имя: String, кнопка подпись: String) -> CGFloat? {
        let кнопка = app.buttons[подпись].firstMatch
        guard кнопка.waitForExistence(timeout: 40) else {
            XCTFail("\(имя): кнопки «\(подпись)» нет — экран не тот или не открылся")
            return nil
        }
        дождатьсяПокоя()
        докрутитьДоКонца()
        let встало = дождатьсяПокоя()

        guard let текст = нижнийТекст() else {
            XCTFail("\(имя): на экране не нашлось ни одного текста")
            return nil
        }
        let перекрытие = текст.frame.maxY - кнопка.frame.minY

        // **Замер по неустоявшейся вёрстке печатается как НЕГОДНЫЙ,
        // а не как число.** Иначе он выглядит точно так же, как годный:
        // те же две координаты, та же разность. Отличить их потом будет
        // нечем, и «−6 pt» от перегруженной машины уедет в отчёт
        // наравне с измеренным.
        guard встало else {
            print("""
            ЗАМЕР \(имя) — НЕГОДЕН: вёрстка не встала за отведённое время
              это про машину, а не про экран: нижний текст продолжал ехать
              между опросами. Перекрытие не печатаю НАРОЧНО — число здесь
              неотличимо по виду от измеренного.
            """)
            снять("\(имя)-НЕГОДЕН-вёрстка-не-встала")
            return nil
        }

        print("""
        ЗАМЕР \(имя)
          нижний текст   maxY=\(текст.frame.maxY)  «\(текст.label.prefix(70))»
          кнопка низа    minY=\(кнопка.frame.minY)  «\(подпись)»
          перекрытие     \(перекрытие) pt \(перекрытие > 0 ? "← НЕ ВЫХОДИТ" : "выходит")
        """)
        снять(имя)
        return перекрытие
    }

    // MARK: - Проход

    func testНижниеБлокиОнбордингаВыходятИзПодПанели() throws {
        // Шаг 1 · приветствие. Если его нет — онбординг не показался,
        // и дальше мерить нечего: это отказ СТЕНДА, а не находка.
        let начать = app.buttons["Добавить собаку"].firstMatch
        XCTAssertTrue(начать.waitForExistence(timeout: 30), """
            Онбординг не открылся. Симулятор стёрт? Запуск без -UITesting? \
            С -UITesting приложение всегда идёт мимо онбординга.
            """)
        начать.tap()

        // Шаг 2 · «Кто у тебя живёт» — слот :130, запас был ровно нулевым.
        XCTAssertTrue(дождаться("Кто у тебя живёт"))
        let кличка = app.textFields["Стич"].firstMatch
        if кличка.waitForExistence(timeout: 20) {
            кличка.tap()
            кличка.typeText("Стич")
        }
        let вес = app.textFields["4,1"].firstMatch
        if вес.exists {
            вес.tap()
            вес.typeText("4,7")
        }
        убратьКлавиатуру()
        замерить("130-кто-у-тебя-живёт", кнопка: "Дальше")
        app.buttons["Дальше"].firstMatch.tap()

        // Шаг 3 · «Режим дня» — КОНТРОЛЬ. Запас был +52, то есть этот
        // экран не падал ни до починки, ни после. Снимается тем же
        // прогоном нарочно: если обрезан и он, разница про способ
        // снимать, а не про экраны, и тогда остальным трём верить нельзя.
        XCTAssertTrue(дождаться("Режим дня"))
        замерить("154-режим-дня-КОНТРОЛЬ", кнопка: "Дальше")
        app.buttons["Дальше"].firstMatch.tap()

        // Шаг 4 · уход — проходим насквозь, слот :205 не падал.
        XCTAssertTrue(дождаться("Что делаешь для ухода"))
        let дальшеУход = app.buttons.matching(
            NSPredicate(format: "label BEGINSWITH 'Дальше' OR label == 'Пропустить'")).firstMatch
        XCTAssertTrue(дальшеУход.waitForExistence(timeout: 20))
        дальшеУход.tap()

        // Шаг 5 · «Кто ещё за ним ходит» — слот :301, −6 pt.
        // Здесь обрывалась строка про то, что двое бесплатно, то есть
        // объяснение ровно на шаге приглашения.
        XCTAssertTrue(дождаться("Кто ещё за ним ходит"))
        замерить("301-кто-ещё-за-ним-ходит", кнопка: "Пока сама")
        app.buttons["Пока сама"].firstMatch.tap()

        // Шаг 6 · «Что будет прерывать» — слот :346, −6 pt.
        XCTAssertTrue(дождаться("Что будет прерывать"))
        замерить("346-что-будет-прерывать", кнопка: "Не сейчас")
    }

    /// Сколько собак осталось после прохода онбординга.
    ///
    /// **Это не про вёрстку, и стоит здесь потому, что дорога одна.**
    /// Выгрузка с телефона 08.10 дала 16 собак, из них 15 без клички,
    /// девять — в одну секунду, и в журнале та же секунда помечена
    /// `open onboarding`. Онбординг — единственный путь, которого
    /// не проходит ни один тест, и ровно он создаёт пустые записи.
    ///
    /// > **Непроверяемая поверхность накопила дефект, потому что была
    /// > непроверяемой.** Утренний разбор «ни одно из шести мест
    /// > создания `Dog` не может дать пустое имя» был верен по тем
    /// > шести и слеп к этой ветке — она проверялась чтением, потому
    /// > что прогоном не проверялась вовсе.
    ///
    /// Счёт берётся с экрана настроек, а не из хранилища: у теста нет
    /// доступа к `ModelContext`. Пустая запись видна там же, где её
    /// увидела Виктория, — строкой без клички.
    func testПослеОнбордингаСобакаРовноОдна() throws {
        let начать = app.buttons["Добавить собаку"].firstMatch
        XCTAssertTrue(начать.waitForExistence(timeout: 30),
                      "онбординг не открылся — отказ стенда, а не находка")
        начать.tap()

        XCTAssertTrue(app.staticTexts["Кто у тебя живёт"].waitForExistence(timeout: 10))
        let кличка = app.textFields["Стич"].firstMatch
        if кличка.waitForExistence(timeout: 5) {
            кличка.tap()
            кличка.typeText("Стич")
        }
        let вес = app.textFields["4,1"].firstMatch
        if вес.exists { вес.tap(); вес.typeText("4,7") }
        убратьКлавиатуру()
        app.buttons["Дальше"].firstMatch.tap()

        // Пройти остаток насквозь, ничего не выбирая.
        //
        // **Список подписей по порядку здесь не годится, и первый
        // прогон это показал.** Шагов больше, чем подписей: «Дальше»
        // встречается дважды подряд, а порядок зависит от того, что
        // человек выбрал раньше. Проход списком один раз тапнул четыре
        // кнопки из шести и встал посреди потока — а падение пришло
        // позже и под именем «до настроек не дошли», то есть указало
        // на конец, а не на место.
        //
        // Поэтому цикл: пока на экране есть любая кнопка «вперёд» —
        // жать её. Выход по вкладке «Настройки», то есть по признаку
        // ЦЕЛИ, а не по счёту шагов.
        let вперёд = NSPredicate(format:
            "label BEGINSWITH 'Дальше' OR label == 'Пропустить' "
            + "OR label == 'Пока сама' OR label == 'Не сейчас' "
            + "OR label == 'Вернуться к дневнику'")
        for _ in 0..<10 {
            if app.buttons["Настройки"].firstMatch.exists { break }
            let кнопка = app.buttons.matching(вперёд).firstMatch
            guard кнопка.waitForExistence(timeout: 20) else { break }
            кнопка.tap()
        }

        // Настройки → секция «собаки».
        let настройки = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 40),
                      "онбординг не завершился — до настроек не дошли")
        настройки.tap()

        XCTAssertTrue(дождаться("собаки"))
        снять("после-онбординга-настройки-собаки")

        // Строка без клички показывает только вес. Их быть не должно
        // ни одной: онбординг заводит ровно одну собаку, и она с кличкой.
        let безымянные = app.staticTexts.allElementsBoundByIndex.filter {
            $0.exists && $0.label.hasPrefix("0,0")
        }
        // Подписи собираются замыканием, а не `map(\.label)`: ключевой
        // путь к `label` в Swift 6 — ОШИБКА компиляции («cannot form key
        // path to main actor-isolated property»), а то же обращение
        // внутри замыкания — предупреждение. Поймано сборкой, не чтением.
        let подписи = безымянные.map { $0.label }
        print("ЗАМЕР собак: строк «0,0 …» на экране настроек — \(подписи.count)")
        XCTAssertEqual(подписи.count, 0,
                       "онбординг оставил безымянные записи: \(подписи)")
    }
}
