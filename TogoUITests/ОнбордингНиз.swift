                + "OR label == 'Потом, в настройках' "
                + "OR label == 'Вернуться к дневнику'")).firstMatch
            guard кнопка.waitForExistence(timeout: 20) else { break }
            кнопка.tap()
        }

        // Настройки → секция «собаки».
        let настройки = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 40),
                      "онбординг не завершился — до настроек не дошли")
        настройки.tap()

        // **Было `дождаться("собаки")` — ось стояла НАВЫВОРОТ.**
        //
        // `SettingsScreen:254` печатает заголовок секции так:
        // `показываемые.count > 1 ? "собаки" : "собака"`. То есть
        // множественное число появляется ТОЛЬКО при двух и более
        // собаках — ровно в том состоянии, которое этот тест обязан
        // ловить. Ожидание «собаки» сбывалось при дефекте и не
        // сбывалось при норме.
        //
        // Замер 15.10: тест прогнан ОДИН на свежестёртом устройстве,
        // то есть без причины «первый тест класса потребил предусловие
        // второго», — и упал здесь. `Tap "Настройки"` в логе один раз:
        // до экрана дошёл, упал на заголовке.
        //
        // > **Верное объяснение закрывает поиск надёжнее неверного.**
        // > Красное объясняли семь дней причиной, которая существует
        // > и описана в этом же файле на двадцать строк. Объяснение
        // > правдиво — и потому за ним не пошёл никто.
        //
        // Различитель теперь работает в ОБЕ стороны: одна собака даёт
        // «собака», две — «собаки», и второе красит тест.
        XCTAssertTrue(дождаться("собака"), """
            На экране настроек нет заголовка «собака». Три причины,
            и они не равны:
              • заголовок «собаки» → собак ДВЕ И БОЛЬШЕ, онбординг
                завёл лишнюю — это находка, ради неё тест и живёт;
              • заголовка нет вовсе → до секции собак не доскроллили
                или экран не тот;
              • собак НОЛЬ → онбординг не записал ничего.
            Смотреть кадр, он снимается строкой ниже.
            """)
        снять("после-онбординга-настройки-собаки")

        // Строка без клички показывает только вес. Их быть не должно
        // ни одной: онбординг заводит ровно одну собаку, и она с кличкой.
        let безымянные = app.staticTexts.allElementsBoundByIndex.filter {
            $0.exists && $0.label.hasPrefix("0,0")
        }
        // Подписи собираются замыканием, а не `map(\.label)`: ключевой
        // путь к `label` в Swift 6 — ОШИБКА компиляции («cannot form key
        // path to main actor-isolated property»), а то же обращение
        // внутри замыкания — предупреждение. Поймано сборкой, не чтением.
        let подписи = безымянные.map { $0.label }
        print("ЗАМЕР собак: строк «0,0 …» на экране настроек — \(подписи.count)")
        XCTAssertEqual(подписи.count, 0,
                       "онбординг оставил безымянные записи: \(подписи)")
    }

    /// Возврат на шаг собаки и проход заново не заводят вторую.
    ///
    /// **Это вторая половина приёмки починки обрыва (`677fc79`),
    /// и без неё первая зелена при сломанной починке.**
    ///
    /// Прямой проход не доказывает ничего: `saveDog()` зовётся на нём
    /// ровно один раз **по построению** (`OnboardingFlow.advance():172`,
    /// условие `step == .schedule`). Чтобы место записи было пройдено
    /// дважды, через него надо пройти дважды — то есть спуститься
    /// назад ниже `.schedule` и подняться снова.
    ///
    /// ```
    /// .dog → .schedule → .care        первый проход через место записи
    /// .care → Назад → .schedule → Назад → .dog
    /// .dog → .schedule → .care        ВТОРОЙ проход через то же место
    /// ```
    ///
    /// До `677fc79` защита от второй собаки держалась **случайно**:
    /// после `saveDog()` ложным становился `пишемВБазу`, и повтор
    /// не писал. Починка заменила это явным полем — значит прежняя
    /// защита снята, и если новое поле окажется не там, дубль родится
    /// **молча**: у него та же кличка «Стич», и в списке он выглядит
    /// как первая собака.
    ///
    /// > **Запрет держит дорогу, число держит значение.** Прямой проход
    /// > держит дорогу; этот тест держит значение.
    ///
    /// ## Различитель — заголовок секции, а не строки без клички
    ///
    /// `SettingsScreen:254` печатает `count > 1 ? "собаки" : "собака"`,
    /// то есть экран **сам** отличает одну от многих, и отличает
    /// в обе стороны. Счёт строк без клички (как у соседнего теста)
    /// здесь не годится **по устройству**: дубль создаётся из того же
    /// черновика, у него есть кличка, и безымянных он не оставляет.
    ///
    /// Исход объявлен до прогона: **«собака» есть → зелено; появилось
    /// «собаки» → дубль, и это находка, ради которой тест написан.**
    func testВозвратНаШагСобакиНеЗаводитВторую() throws {
        // Настоящий вход по той же причине, что у соседа: предмет —
        // ЗАПИСЬ собаки при повторном проходе места записи, а дешёвый
        // вход в базу не пишет вовсе.
        запуститьНастоящимВходом()

        let начать = app.buttons["Начать"].firstMatch
        XCTAssertTrue(начать.waitForExistence(timeout: 30), """
            Онбординг не открылся. Устройство стёрто? Этот тест, как
            и соседние, требует ПУСТОЙ базы и запускается без
            -UITesting нарочно.
            """)
        начать.tap()

        // Шаг собаки — заполняем, иначе «Дальше» выключена.
        XCTAssertTrue(дождаться("Кто у тебя живёт"))
        let кличка = app.textFields["Кличка"].firstMatch
        if кличка.waitForExistence(timeout: 20) {
            кличка.tap()
            кличка.typeText("Стич")
        }
        let вес = app.textFields["4,1"].firstMatch
        if вес.exists { вес.tap(); вес.typeText("4,7") }
        убратьКлавиатуру(заголовок: "Кто у тебя живёт")
        app.buttons["Дальше"].firstMatch.tap()

        // Первый проход через место записи.
        XCTAssertTrue(дождаться("Режим дня"))
        app.buttons["Дальше"].firstMatch.tap()

        // До 677fc79 сюда не доходил никто пятьдесят дней.
        XCTAssertTrue(дождаться("Что делаешь для ухода"), """
            Шаг ухода не открылся. Если вместо него экран «Это всё» —
            это ВОЗВРАТ обрыва, который чинил 677fc79, а не дефект
            этого теста.
            """)
        снять("возврат-01-дошли-до-ухода")

        // Спуск назад ниже шага записи. Кнопка «Назад» живёт в тулбаре
        // потока (`OnboardingFlow:177`, `Label("Назад", …)`).
        назад(к: "Режим дня")
        назад(к: "Кто у тебя живёт")
        снять("возврат-02-вернулись-на-собаку")

        // Второй проход через то же место.
        app.buttons["Дальше"].firstMatch.tap()
        XCTAssertTrue(дождаться("Режим дня"))
        app.buttons["Дальше"].firstMatch.tap()
        XCTAssertTrue(дождаться("Что делаешь для ухода"),
                      "второй проход не дошёл до ухода")
        снять("возврат-03-второй-раз-уход")

        // Досидеть до конца тем же циклом, что у соседнего теста:
        // список подписей по порядку не годится, шагов больше, чем
        // подписей, и порядок зависит от выбранного раньше.
        for _ in 0..<10 {
            if app.buttons["Настройки"].firstMatch.exists { break }
            let кнопка = app.buttons.matching(NSPredicate(format:
                "label BEGINSWITH 'Дальше' OR label == 'Пропустить' "
                + "OR label == 'Потом, в настройках' "
                + "OR label == 'Вернуться к дневнику'")).firstMatch
            guard кнопка.waitForExistence(timeout: 20) else { break }
            кнопка.tap()
        }

        let настройки = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 40),
                      "онбординг не завершился — до настроек не дошли")
        настройки.tap()

        снять("возврат-04-настройки-после-возврата")
        XCTAssertFalse(app.staticTexts["собаки"].firstMatch.exists, """
            НА ЭКРАНЕ ЗАГОЛОВОК «собаки» — СОБАК ДВЕ ИЛИ БОЛЬШЕ.
            Возврат на шаг собаки завёл дубль: место записи пройдено
            дважды, и явное поле «собака уже сохранена» его не удержало.
            Дубль с той же кличкой «Стич», в списке неотличим от первой.
            Кадр «возврат-04» снят строкой выше.
            """)
        XCTAssertTrue(дождаться("собака"), """
            Заголовка «собака» нет, и «собаки» тоже. Значит собак НОЛЬ
            или экран не тот — и это другой дефект, не дубль.
            """)
    }

    /// Нажать «Назад» и дождаться НАЗВАННОГО экрана.
    ///
    /// Ожидание именно названного, а не «любого другого»: тап по
    /// «Назад» в этом потоке один раз уже уводил на первый экран,
    /// и падение приходило позже, под чужим именем. Проверка здесь —
    /// половина цены разбора потом.
    private func назад(к заголовок: String,
                       файл: StaticString = #filePath, строка: UInt = #line) {
        let кнопка = app.buttons["Назад"].firstMatch
        XCTAssertTrue(кнопка.waitForExistence(timeout: 20),
                      "кнопки «Назад» нет — спуститься по шагам нечем",
                      file: файл, line: строка)
        кнопка.tap()
        XCTAssertTrue(дождаться(заголовок),
                      "после «Назад» ожидался экран «\(заголовок)»",
                      file: файл, line: строка)
    }
