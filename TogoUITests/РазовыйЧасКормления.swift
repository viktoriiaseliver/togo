import XCTest

/// Кадр шторки «Во сколько кормить сегодня?» — и доказательство,
/// что у механизма есть ВХОД.
///
/// # Зачем UI-прогон, когда есть `ImageRenderer`
///
/// `ImageRenderer` отдаёт `TGSheet` **пустым** — замер 04.11.2026:
/// на кадре полоска `TGSheetHandle` и чернота, два разных состояния
/// дали файлы байт в байт. Причина не установлена, кандидатов три.
/// Значит шторка снимается только отсюда.
///
/// # Что этот тест проверяет, кроме кадра
///
/// **Что до шторки можно дойти пальцем.** До 05.11.2026 тап
/// по ТЕКСТУ неотмеченного кормления не делал ничего: `open(_:)`
/// доходил до `guard item.isDone` и возвращался. Вход у механизма
/// взят из этого мёртвого нажатия — и проверить, что он живой,
/// нельзя ничем, кроме прогона: ни компилятор, ни модульный тест
/// не знают, доходит ли палец до `onOpen`.
///
/// > Механизм без входа не «почти работает» — он не работает.
///
/// # Тему ставить СНАРУЖИ процесса теста
///
/// `XCUIDevice.shared.appearance = .dark` компилируется, выполняется
/// и **не работает**: кадры останутся светлыми при зелёном прогоне
/// (находка соседней сессии, 05.11.2026). Тёмный кадр снимают так:
/// `xcrun simctl ui <udid> appearance dark` до прогона.
nonisolated final class РазовыйЧасКормления: XCTestCase {
    private var app: XCUIApplication!
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-разовое-исключение")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Счёт печатается ВСЕГДА, в том числе после падения: «снят один»
    /// и «упал до съёмки» выглядят в логе одинаково — во втором
    /// случае строки просто нет, а её отсутствия никто не ищет.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) из 2 · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "РазовыйЧасКормления")
    }

    func testШторкаОткрываетсяТапомПоТекстуКормления() {
        XCTAssertTrue(app.staticTexts["Стич"].waitForExistence(timeout: 20),
                      "главный экран не поднялся — всё ниже мерило бы пустоту")

        // Строка плана дня: кнопка текста, а не круга. У круга подпись
        // начинается с «Отметить» (`TGCheckRow.checkbox`), у текста —
        // с заголовка пункта. Разводим предикатом, а не порядком:
        // порядок зависит от раскладки и молча меняется.
        let текстКормления = app.buttons.matching(
            NSPredicate(format: "label BEGINSWITH %@", "Еда")
        ).firstMatch
        XCTAssertTrue(текстКормления.waitForExistence(timeout: 20), """
            в плане дня нет ни одного пункта еды с кнопкой текста. \
            Либо план не собрался, либо строка уехала под хрому — \
            и тогда тап ниже бил бы в пустоту, а отказ читался бы \
            как «шторка не открылась».
            """)

        кадр("01-план-дня-до-шторки")
        текстКормления.tap()

        // Заголовок шторки — её единственный устойчивый признак:
        // кнопки и строки выбора меняются, заголовок называет вопрос.
        let заголовок = app.staticTexts["Во сколько кормить сегодня?"]
        XCTAssertTrue(заголовок.waitForExistence(timeout: 10), """
            шторка не открылась. Тап по ТЕКСТУ неотмеченного кормления \
            до 05.11.2026 не делал ничего, и вход механизма взят \
            именно из него — значит красное здесь значит «входа снова \
            нет», а не «шторка нарисовалась неправильно».
            """)

        // Обе ветки развилки обязаны быть на экране. Их ровно две,
        // и различаются они ИСХОДОМ: «сдвинуть пропорционально»
        // на её расписании не двигает ничего (замер 04.11), а час,
        // названный человеком, пробивает предел `latestMeal`.
        XCTAssertTrue(app.buttons.matching(
            NSPredicate(format: "label BEGINSWITH %@", "Оставить")
        ).firstMatch.exists, "нет ветки «оставить назначенный час»")
        XCTAssertTrue(app.buttons["Кормить в другое время"].exists,
                      "нет ветки «кормить в другое время»")
        XCTAssertTrue(app.buttons["Только на сегодня"].exists,
                      "нет кнопки записи — шторка без выхода")

        кадр("02-шторка-во-сколько-кормить-сегодня")
    }

    private func кадр(_ имя: String) {
        let снимок = app.screenshot()
        let вложение = XCTAttachment(screenshot: снимок)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        снято.append(имя)
        do {
            try FileManager.default.createDirectory(at: каталог,
                                                    withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя).png")
            try снимок.pngRepresentation.write(to: путь)
            print("КАДР: \(путь.path) · \(снимок.pngRepresentation.count) байт")
        } catch {
            // Не падаем на записи файла: вложение уже добавлено,
            // и терять из-за диска проверку дороги глупо.
            print("КАДР НЕ ЛЁГ НА ДИСК: \(имя) · \(error.localizedDescription)")
        }
    }
}
