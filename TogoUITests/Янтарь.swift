import XCTest

/// Три янтарных состояния — впервые на кадре.
///
/// **Чем это оплачено.** 05.10.2026 приёмка смены палитры искала янтарь
/// по всем двенадцати кадрам витрины и не нашла **ни одного пикселя**.
/// Контроль тем же инструментом нашёл лайм на десяти кадрах из двенадцати
/// — значит мерка цела, а янтаря в мире нет.
///
/// Причина была не в небрежности, а во входе: `SeedData` не создавал
/// ни одного объекта в этих состояниях. Навыки заводились без статуса,
/// препарата с окном натощак не было вовсе, отметки `.almost` не было.
/// То есть **ни один из трёх жёлтых смыслов не видел глазами никто**,
/// и не потому что не смотрели, а потому что смотреть было не на что.
///
/// Вход завёл `SeedData.Scenario.amber`; эти кадры — вторая половина
/// той же работы. Правило проекта: прежде чем проверять поверхность,
/// проверь, что её МОЖНО проверить; непроверяемое лечится входом,
/// а не взглядом.
///
/// **Почему три кадра, а не один.** Состояния живут на разных экранах —
/// «Сегодня», «Уход» и занятие, — и на один экран они не сводятся:
/// у хендоффа дизайна есть правило «не больше одного мотива на экран».
///
/// Кадры смотрят глазами и мерят пикселем. Зелёный прогон этого класса
/// доказывает, что съёмка состоялась, и **не** доказывает, что янтарь
/// на кадре есть: `shoot(...)` в исходнике — намерение, кадр — то, что
/// увидит человек.
nonisolated final class Янтарь: XCTestCase {
    private var app: XCUIApplication!

    /// Подписи на языке прогона — тест водит приложение по надписям,
    /// и вторую копию их заводить нельзя: разойдётся молча.
    private let т = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "amber"]
        app.launch()
        // Таймаут 15, а не 10: на общей машине рядом идут чужие сборки,
        // и 05.10 два кадра потерялись ровно на десяти секундах —
        // «приложение не поднялось» было про стенд, не про код.
        XCTAssertTrue(app.staticTexts["Стич"].waitForExistence(timeout: 15),
                      "приложение не поднялось на языке «\(т.язык)» — "
                      + "проверь, не идёт ли рядом чужая сборка")
    }

    private func capture(_ name: String) {
        let shot = XCTAttachment(screenshot: app.screenshot())
        shot.name = name
        shot.lifetime = .keepAlways
        add(shot)
    }

    /// Окно натощак — плашка `TGBanner` с тоном `.waiting` на главном.
    ///
    /// Окно считается от ОТМЕТКИ дозы, а не от назначенного времени:
    /// назначенная доза его не открывает. Поэтому сценарий отмечает дозу
    /// двадцатью минутами ранее при окне сорок минут.
    func testЯ1Натощак() {
        capture("amber-1-fasting")
        app.swipeUp()
        capture("amber-1-fasting-scrolled")
    }

    /// «Почти вовремя» — `MarkAccuracy.almost` на занятии.
    ///
    /// В сценарии три задержки: 420 мс даёт `.onTime`, 640 и 870 — `.almost`.
    /// Третья нужна не для полноты, а чтобы на кадре янтарь стоял рядом
    /// с зелёным: цвет, которому нечего противопоставить, не читается
    /// как состояние.
    func testЯ2Занятие() {
        // **ДВА РАЗНЫХ «Ещё», и тест жал не то** (правка 26.10.2026).
        // В шапке «Ещё» открывает меню настроек; «Занятие» лежит
        // во ВТОРОЙ шторке записи:
        //
        // ```
        // «+» (низ-записать) → шторка «Записать» (TodayBottom)
        //                      Инцидент · Стул · Еда · Ещё
        //   строка «Ещё»     → шторка .more (TodayRouter)
        //                      Лакомство · Занятие · Заметка · …
        // ```
        //
        // Отказ звучал «кнопки занятия нет — кадра этого состояния
        // не будет вовсе» и читался как дефект продукта.
        let плюс = app.buttons["низ-записать"].firstMatch
        guard плюс.waitForExistence(timeout: 15) else {
            XCTFail("кнопки «Записать» нет — до занятия не дойти"); return
        }
        плюс.tap()
        let ещё = app.buttons.containing(
            NSPredicate(format: "label BEGINSWITH %@", т("Ещё"))
        ).firstMatch
        guard ещё.waitForExistence(timeout: 10) else {
            XCTFail("в шторке «Записать» нет строки «Ещё»"); return
        }
        ещё.tap()
        let занятие = app.buttons.containing(
            NSPredicate(format: "label BEGINSWITH %@", т("Занятие"))
        ).firstMatch
        guard занятие.waitForExistence(timeout: 10) else {
            XCTFail("кнопки занятия нет — путь к «почти вовремя» не открылся, "
                    + "а значит кадра этого состояния не будет вовсе")
            return
        }
        занятие.tap()
        _ = app.staticTexts[т("Он сделал")].waitForExistence(timeout: 10)
        capture("amber-2-training")
    }

    /// «Навык тренируется» — `SkillStatus.learning`, и уход, где стоит доза.
    ///
    /// Вкладка зовётся кличкой собаки, а не словом: `RootView` подписывает
    /// её `dog?.name`. Поэтому «Стич» здесь — не подпись интерфейса
    /// и не переводится.
    func testЯ3Уход() {
        let вкладка = app.tabBars.buttons["Стич"]
        guard вкладка.waitForExistence(timeout: 10) else {
            XCTFail("вкладки собаки нет — до «Ухода» не дойти")
            return
        }
        вкладка.tap()
        capture("amber-3-dog")

        let уход = app.buttons.containing(
            NSPredicate(format: "label BEGINSWITH %@", т("Уход"))
        ).firstMatch
        guard уход.waitForExistence(timeout: 10) else {
            XCTFail("ссылки «Уход» нет — кадра навыка в обучении не будет")
            return
        }
        уход.tap()
        _ = app.navigationBars[т("Уход")].waitForExistence(timeout: 10)
        capture("amber-3-care")
        app.swipeUp()
        capture("amber-3-care-scrolled")
    }
}
