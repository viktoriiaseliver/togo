import XCTest

/// Кадры приёмки вкладки собаки и экрана «Семья» под тему «Кино».
///
/// **Приёмка этой работы — кадр рядом с кадром дизайна, а не зелёный
/// набор.** Эталоны лежат в
/// `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/`: `09.png`
/// (вкладка собаки) и `12.png` («Семья»). Тест проверяет, верно ли
/// посчитано; кадр — верно ли сказано, и у правки, меняющей то, что
/// человек читает, зелёный набор приёмку не заменяет.
///
/// ## Чего эти кадры НЕ покажут, и это надо знать до того, как на них
/// посмотрят
///
/// **Фотографии в шапке не будет.** Не потому, что шапка не работает,
/// а потому, что класть в `dog.photo` было нечего: замер 23.10.2026
/// по `Togo` и `TogoShared` нашёл ровно два присваивания —
/// `OnboardingFlow.swift:299` (из `DogDraft.photo`, которое не пишет
/// никто: объявлено на `:281`, присваивания нет) и восстановление
/// из архива. Контроль тем же запросом по `breed` — девять мест,
/// среди них редактор. То есть поле читали три экрана и виджет,
/// а положить в него снимок человек не мог нигде.
///
/// Вход для этого заведён той же правкой — фотоаппарат на описи
/// собаки, — но **стендом он непроверяем**: `PhotosPicker` работает
/// в отдельном процессе, и то же самое записано у `ФонПриложения`.
/// Поверхность без кадра лечится переделкой входа, а не старанием;
/// здесь вход сделан, а кадра у него нет, и это разные вещи.
///
/// Значит на кадрах видна шапка **на полотне**: затемнение, кикер,
/// крупный заголовок и стеклянная карточка. Геометрию, порядок блоков
/// и текст по ним сверять можно; цвет фотографии — нельзя.
nonisolated final class ВкладкаСобакиИСемья: XCTestCase {

    private var app: XCUIApplication!

    /// Кадры ложатся в `build/кадры-кино-вкладка/`, путь выведен
    /// из `#filePath`. `build/` в `.gitignore`: то, что нужно сохранить,
    /// выносится в `Дизайн/кадры-приёмки/` и коммитится отдельно.
    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-кино-вкладка")
    }

    private var снято: [String] = []

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Счёт печатается ВСЕГДА и ПЕРВОЙ строкой, в том числе после
    /// падения посреди прохода.
    ///
    /// «Снято четыре» и «упал на втором, снято одно» выглядят в логе
    /// одинаково: строк `КАДР:` просто меньше, а отсутствия никто
    /// не ищет. Из девяти пишущих кадры тестов счёт печатал один —
    /// этот второй.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ВкладкаСобакиИСемья")
    }

    /// Кадр окна файлом, а не `XCTAttachment`: выгрузка вложений в этом
    /// проекте измерена и не сработала пять раз из девяти. Вложение,
    /// которое не выгружается, — это кадр, которого нет.
    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        снято.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    /// Вкладка собаки названа **кличкой**, а не словом «Собака»
    /// (`RootView.swift:68`), то есть её имя — данные. Поэтому берём
    /// по порядку: «Сегодня» · {кличка} · «История» · «Здоровье».
    ///
    /// Порядковый номер тут надёжнее имени, и это не лень: подставь
    /// сюда «Стич» — и тест начнёт падать в тот день, когда демо-собаку
    /// переименуют, причём падать будет на «вкладки нет», а не на
    /// «кличка другая».
    private func открытьВкладкуСобаки() throws {
        let бар = app.tabBars.firstMatch
        XCTAssertTrue(бар.waitForExistence(timeout: 15), "таб-бара нет — приложение не дошло до главного экрана")
        XCTAssertEqual(бар.buttons.count, 4, """
            вкладок \(бар.buttons.count), а решением 22.10.2026 их четыре: \
            Сегодня · {кличка} · История · Здоровье. Кадр ниже снимал бы не тот экран.
            """)
        бар.buttons.element(boundBy: 1).tap()
    }

    func testКадрыВкладкиСобакиИСемьи() throws {
        try открытьВкладкуСобаки()

        // Предмет спрашивается по тому, что на экране есть только у него.
        // «Что-то появилось» годным признаком не бывает: при четырёх
        // вкладках соседний экран выглядит так же.
        // Строка звалась «Семья и дежурство» до 29.10.2026; переименована
        // в «Семья» решением Виктории — тем же именем, что экран и пункт
        // меню «…». Тест ищет строку, а не прежнюю подпись.
        let опознание = app.staticTexts["Семья"].firstMatch
        XCTAssertTrue(опознание.waitForExistence(timeout: 10), """
            строки «Семья» нет. Либо вкладка открылась не та, \
            либо строка переименована — и тогда кадр снимать нельзя: \
            он был бы кадром другого экрана под именем этого.
            """)

        try снять("09-вкладка-собаки-верх")
        app.swipeUp()
        try снять("09-вкладка-собаки-ниже")

        // Возврат наверх: иначе строка семьи осталась бы за краем,
        // и тап ушёл бы в то, что оказалось на её месте.
        app.swipeDown()
        app.swipeDown()
        XCTAssertTrue(опознание.waitForExistence(timeout: 5),
                      "после прокрутки строка семьи не вернулась на экран")
        опознание.tap()

        let семья = app.navigationBars["Семья"].firstMatch
        XCTAssertTrue(семья.waitForExistence(timeout: 10), """
            экран «Семья» не открылся. Вход у него один — эта строка \
            плюс пункт меню «…»; своей вкладки у «Семьи» нет с 22.10.2026.
            """)

        try снять("12-семья-верх")
        app.swipeUp()
        try снять("12-семья-ниже")

        XCTAssertEqual(снято.count, 4, "кадров снято \(снято.count) из четырёх")
    }
}
