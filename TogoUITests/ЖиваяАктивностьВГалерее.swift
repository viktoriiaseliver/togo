import XCTest

/// Приёмка переделки входа 07.10.2026: карточка живой активности стала
/// снимаемой кадром.
///
/// **До сегодня эту поверхность не видел глазами никто, и это было
/// не недосмотром, а устройством.** `WalkLiveActivity` принимала
/// `ActivityViewContext<WalkActivityAttributes>`, а его вне живой
/// активности не построить ничем: ни тестом, ни превью, ни галереей.
/// То, что человек читает с заблокированного экрана на улице — там,
/// где он и отмечает, — было **непроверяемым**, а не непроверенным.
///
/// > Первое лечится взглядом, второе только переделкой входа.
///
/// Цена такой поверхности оплачена на соседнем проекте: у Timer
/// карточка Live Activity стояла ровно так, и отзыв «проблемы
/// с виджетом» жил незамеченным не потому, что плохо смотрели,
/// а потому что смотреть было не на что.
///
/// **Этот тест — не доказательство, что «остров» верен.** Он
/// доказывает ровно одно: поверхность теперь можно построить и снять.
/// Ширины настоящего «острова» принадлежат системе; галерея отвечает
/// «что написано и как свёрстано», а не «влезет ли».
nonisolated final class ЖиваяАктивностьВГалерееUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testКарточкаВыходаСнимаетсяКадром() {
        // ДОРОГА, А НЕ ГЛАВНЫЙ ЭКРАН (правка 25.10.2026).
        //
        // Стояло три строки: `app.buttons["Настройки"]`, ожидание
        // и тап, — и отказ говорил «не дождались главного экрана».
        // Это НЕВЕРНО дважды: экран поднимался (соседние проверки
        // проходили), а не находилась кнопка настроек, которая
        // решением Виктории 22.10 ушла в меню «…».
        //
        // > **Отказ называл не ту сторону.** Сообщение винило запуск
        // > приложения, а предмет был в адресации органа; я потеряла
        // > на этом два ложных объяснения подряд, прежде чем прочла
        // > имя переменной — она звалась `настройки`.
        //
        // Помощник `открытьНастройки(в:)` знает обе дороги и говорит
        // о себе правду.
        XCTAssertTrue(открытьНастройки(в: app), """
            в настройки не попасть ни прямой кнопкой, ни через меню «…». \
            Это отказ ДОРОГИ, а не запуска: если бы не поднялось \
            приложение, не нашлось бы и меню.
            """)

        let виджет = найти("Виджет", в: app)
        XCTAssertTrue(виджет.waitForExistence(timeout: 10),
                      "нет входа «Виджет» — галерея под `#if DEBUG`")
        виджет.tap()

        // Крутим до упора: раздел живой активности стоит последним,
        // а элемент «существует» и не будучи построенным на экране.
        //
        // **Читать список элементов ВНУТРИ цикла прокрутки нельзя.**
        // Первая редакция сверяла снимки экрана, чтобы остановиться,
        // когда он перестанет меняться, — и падала на
        // `Failed to get matching snapshot: No matches found for
        // Element at index 105`: пока перечисляются индексы, список
        // под рукой уже другой. Падение выглядело как дефект галереи,
        // а было дефектом обхода.
        //
        // Поэтому фиксированное число махов: раздел последний,
        // лишние махи у низа — пустая операция, а список читается
        // один раз и после.
        // ПРОКРУТКА ДО НАХОДКИ, А НЕ ФИКСИРОВАННОЕ ЧИСЛО МАХОВ
        // (правка 25.10.2026).
        //
        // Стояло `for _ in 0..<14 { app.swipeUp() }`, и основание
        // было написано рядом: «раздел последний, лишние махи у низа —
        // пустая операция». **Основание устарело.** Замер: раздел
        // «Живая активность · выход идёт» — ЧЕТВЁРТЫЙ ИЗ ШЕСТИ
        // (`WidgetGallery.swift`, порядок `group(`), после него завели
        // «Дата: все двенадцать месяцев» и «Инлайн». Четырнадцать махов
        // его проносят, и заголовок уходит за верхний край.
        //
        // > **Фиксированное число махов — прокси для «раздел
        // > последний».** Новый раздел снизу гасит его молча: тест
        // > ищет то, что есть, не находит и винит продукт. Его отказ
        // > так и говорил — «переделка входа не доехала», — а переделка
        // > доехала, уехал раздел.
        //
        // Ищем до находки с потолком: потолок втрое больше прежнего
        // числа, то есть заведомо хватит, а бесконечного цикла
        // в прогоне не бывает.
        // **ОСЬ — СОДЕРЖИМОЕ КАРТОЧКИ, А НЕ ЗАГОЛОВОК РАЗДЕЛА**
        // (правка 25.10.2026, по логу прежнего отказа).
        //
        // Предыдущая редакция искала «выход идёт» — заголовок `group(`.
        // Он и был прокси для «раздел построен», и прокси погас
        // от самой прокрутки: в хвосте отказа стоят
        //
        // ```
        // «остров» развёрнутый · три области | Виктория вывела Стич |
        // Виктория вывела собаку | Пописал | Стул
        // ```
        //
        // то есть **раздел построен и виден**, а заголовка в списке
        // нет — он ушёл выше верхнего края, и `allElementsBoundByIndex`
        // его не отдаёт. Тест докручивал до низа и говорил «карточки
        // нет», имея её на экране.
        //
        // > **Заголовок виден, пока карточка НЕ доехала, и исчезает
        // > ровно тогда, когда она доехала.** Прокси не просто
        // > неточный — он обратен предмету.
        //
        // Ищем текст самой карточки: он и есть то, ради чего раздел
        // открывали, и он же проверяется ниже по существу.
        // **ПЕРЕЧИСЛЕНИЯ ПО ИНДЕКСАМ ЗДЕСЬ БОЛЬШЕ НЕТ ВОВСЕ**
        // (правка 25.10.2026, второй заход).
        //
        // Голова этого файла запрещает читать список элементов внутри
        // цикла прокрутки — и предыдущая редакция, ища карточку
        // махами, запрет вернула. Прогон ответил дословно тем же,
        // чем первый раз:
        //
        // ```
        // ЖиваяАктивностьВГалерее.swift:121: Failed to get matching
        // snapshot: No matches found for Element at index 99
        // ```
        //
        // Пока `allElementsBoundByIndex` разрешает индексы, прокрутка
        // ещё идёт, и под рукой уже другой список. Падение выглядит
        // как дефект галереи, а это дефект обхода.
        //
        // > **Запрет, записанный в голове файла, не держит правку,
        // > сделанную в теле.** Прошлая редакция чинила ОСЬ поиска
        // > и внесла обратно то, от чего файл уже лечили: своя правка
        // > не видна как помеха.
        //
        // Предикатный запрос гонке не подвержен: он не перечисляет,
        // а спрашивает про совпадение.
        let карточка = app.staticTexts
            .containing(NSPredicate(format: "label CONTAINS %@", "вывела собаку"))
            .firstMatch
        for мах in 0...42 {
            if карточка.exists { break }
            if мах == 42 { break }
            app.swipeUp()
        }

        // Контроль: раздел ПОСТРОИЛСЯ. Без него все запреты ниже
        // выполняются на экране, где нет ничего, и тест зелен,
        // не проверив ничего.
        XCTAssertTrue(карточка.exists, """
            карточки живой активности в галерее нет ПОСЛЕ 42 МАХОВ. \
            Это не «с ней всё хорошо» — это нечем смотреть.

            Прежде чем винить продукт: ищется ТЕКСТ КАРТОЧКИ \
            («…вывела собаку»), а не заголовок раздела. Заголовок \
            «Живая активность · выход идёт» уходит выше края ровно \
            тогда, когда карточка доезжает, — на нём тест уже \
            обжёгся 25.10.2026.

            Если карточку переименовали — поправить подстроку ЗДЕСЬ, \
            в условии выхода из цикла и в проверке ниже РАЗОМ: их три.
            """)

        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "10-живая-активность-галерея"
        кадр.lifetime = .keepAlways
        add(кадр)

        // **Пустая кличка — третье состояние в разделе, и оно там
        // не для полноты.** Подпись активности собирается из клички,
        // а 06.10 пришёл отзыв про безымянные записи: это ровно то
        // место, где дефект вышел бы на самую тесную поверхность.
        //
        // От запрета: «подпись содержит кличку» при пустой кличке
        // истинно у любой строки. Проверяем то, что дефект нарушает, —
        // висящий хвост там, где должно стоять имя.
        // Спрашиваем ПРЕДИКАТОМ, а не перебором: ось та же, а гонки
        // с прокруткой нет. `count` считает совпадения, не разрешая
        // чужие индексы.
        let оборвана = app.staticTexts
            .matching(NSPredicate(format: "label == %@", "Виктория вывела")).count
        XCTAssertEqual(оборвана, 0, """
            подпись активности оборвана на «Виктория вывела» — кличка \
            подставилась пустой (\(оборвана) шт.). На локскране это \
            читается как потеря данных, и переспросить человеку некого.
            """)

        let сДвойным = app.staticTexts
            .matching(NSPredicate(format: "label BEGINSWITH %@ AND label CONTAINS %@",
                                  "Виктория вывела", "  ")).count
        XCTAssertEqual(сДвойным, 0,
                       "двойной пробел на месте клички: \(сДвойным) подписей")

        // Обратная половина: откат обязан СРАБОТАТЬ, а не просто
        // не сломать строку.
        //
        // **Слово здесь винительное — «вывела собаку», а не «Собака».**
        // Первая редакция и вида, и этого теста ставила именительное
        // запасное (`Fmt.dogNameOrFallback`, то же слово, что у подписи
        // вкладки), и кадр 07.10 показал «Виктория вывела Собака».
        // Висящий пробел я убрала и завела неграмотность: слот
        // винительный, а запасное слово написано для именительных.
        //
        // Проверка идёт на русском прогоне: падеж — свойство языка,
        // и требовать его на французском бессмысленно.
        guard подписи.язык == "ru" else { return }
        // Отдельный контроль на именительное: его отсутствие —
        // не то же, что присутствие винительного, и спрашивать надо
        // оба. Запрет без утверждения выполняется и на пустом экране.
        let именительное = app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", "вывела Собака")).count
        XCTAssertTrue(карточка.exists, """
            в разделе нет строки «вывела собаку». Либо состояние \
            с пустой кличкой из галереи убрали — и тогда проверять \
            нечего, — либо откат до подписи активности не доехал.
            """)
        XCTAssertEqual(именительное, 0, """
            именительное «Собака» вернулось в винительный слот \
            (\(именительное) шт.): «Виктория вывела Собака». Запасное \
            слово взято у подписи вкладки, где падеж другой.
            """)
    }
}
