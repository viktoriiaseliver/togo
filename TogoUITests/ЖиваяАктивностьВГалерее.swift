import XCTest

/// Приёмка переделки входа 07.10.2026: карточка живой активности стала
/// снимаемой кадром.
///
/// **До сегодня эту поверхность не видел глазами никто, и это было
/// не недосмотром, а устройством.** `WalkLiveActivity` принимала
/// `ActivityViewContext<WalkActivityAttributes>`, а его вне живой
/// активности не построить ничем: ни тестом, ни превью, ни галереей.
/// То, что человек читает с заблокированного экрана на улице — там,
/// где он и отмечает, — было **непроверяемым**, а не непроверенным.
///
/// > Первое лечится взглядом, второе только переделкой входа.
///
/// Цена такой поверхности оплачена на соседнем проекте: у Timer
/// карточка Live Activity стояла ровно так, и отзыв «проблемы
/// с виджетом» жил незамеченным не потому, что плохо смотрели,
/// а потому что смотреть было не на что.
///
/// **Этот тест — не доказательство, что «остров» верен.** Он
/// доказывает ровно одно: поверхность теперь можно построить и снять.
/// Ширины настоящего «острова» принадлежат системе; галерея отвечает
/// «что написано и как свёрстано», а не «влезет ли».
nonisolated final class ЖиваяАктивностьВГалерееUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testКарточкаВыходаСнимаетсяКадром() {
        // ДОРОГА, А НЕ ГЛАВНЫЙ ЭКРАН (правка 25.10.2026).
        //
        // Стояло три строки: `app.buttons["Настройки"]`, ожидание
        // и тап, — и отказ говорил «не дождались главного экрана».
        // Это НЕВЕРНО дважды: экран поднимался (соседние проверки
        // проходили), а не находилась кнопка настроек, которая
        // решением Виктории 22.10 ушла в меню «…».
        //
        // > **Отказ называл не ту сторону.** Сообщение винило запуск
        // > приложения, а предмет был в адресации органа; я потеряла
        // > на этом два ложных объяснения подряд, прежде чем прочла
        // > имя переменной — она звалась `настройки`.
        //
        // Помощник `открытьНастройки(в:)` знает обе дороги и говорит
        // о себе правду.
        XCTAssertTrue(открытьНастройки(в: app), """
            в настройки не попасть ни прямой кнопкой, ни через меню «…». \
            Это отказ ДОРОГИ, а не запуска: если бы не поднялось \
            приложение, не нашлось бы и меню.
            """)

        let виджет = найти("Виджет", в: app)
        XCTAssertTrue(виджет.waitForExistence(timeout: 10),
                      "нет входа «Виджет» — галерея под `#if DEBUG`")
        виджет.tap()

        // Крутим до упора: раздел живой активности стоит последним,
        // а элемент «существует» и не будучи построенным на экране.
        //
        // **Читать список элементов ВНУТРИ цикла прокрутки нельзя.**
        // Первая редакция сверяла снимки экрана, чтобы остановиться,
        // когда он перестанет меняться, — и падала на
        // `Failed to get matching snapshot: No matches found for
        // Element at index 105`: пока перечисляются индексы, список
        // под рукой уже другой. Падение выглядело как дефект галереи,
        // а было дефектом обхода.
        //
        // Поэтому фиксированное число махов: раздел последний,
        // лишние махи у низа — пустая операция, а список читается
        // один раз и после.
        for _ in 0..<14 { app.swipeUp() }

        let тексты = app.staticTexts.allElementsBoundByIndex.map { $0.label }

        // Контроль: раздел ПОСТРОИЛСЯ. Без него все запреты ниже
        // выполняются на экране, где нет ничего, и тест зелен,
        // не проверив ничего.
        XCTAssertTrue(тексты.contains(where: { $0.contains("выход идёт") }), """
            карточки живой активности в галерее нет. Это не «с ней всё \
            хорошо» — это нечем смотреть, то есть переделка входа \
            не доехала.

            Строк на экране \(тексты.count), хвост: \
            \(тексты.suffix(20).joined(separator: " | "))
            """)

        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "10-живая-активность-галерея"
        кадр.lifetime = .keepAlways
        add(кадр)

        // **Пустая кличка — третье состояние в разделе, и оно там
        // не для полноты.** Подпись активности собирается из клички,
        // а 06.10 пришёл отзыв про безымянные записи: это ровно то
        // место, где дефект вышел бы на самую тесную поверхность.
        //
        // От запрета: «подпись содержит кличку» при пустой кличке
        // истинно у любой строки. Проверяем то, что дефект нарушает, —
        // висящий хвост там, где должно стоять имя.
        for строка in тексты where строка.hasPrefix("Виктория вывела") {
            XCTAssertNotEqual(строка.trimmingCharacters(in: .whitespaces), "Виктория вывела", """
                подпись активности оборвана на «\(строка)» — кличка \
                подставилась пустой. На локскране это читается как \
                потеря данных, и переспросить человеку некого.
                """)
            XCTAssertFalse(строка.contains("  "),
                           "двойной пробел на месте клички: «\(строка)»")
        }

        // Обратная половина: откат обязан СРАБОТАТЬ, а не просто
        // не сломать строку.
        //
        // **Слово здесь винительное — «вывела собаку», а не «Собака».**
        // Первая редакция и вида, и этого теста ставила именительное
        // запасное (`Fmt.dogNameOrFallback`, то же слово, что у подписи
        // вкладки), и кадр 07.10 показал «Виктория вывела Собака».
        // Висящий пробел я убрала и завела неграмотность: слот
        // винительный, а запасное слово написано для именительных.
        //
        // Проверка идёт на русском прогоне: падеж — свойство языка,
        // и требовать его на французском бессмысленно.
        guard подписи.язык == "ru" else { return }
        XCTAssertTrue(тексты.contains(where: { $0.contains("вывела собаку") }), """
            в разделе нет строки «вывела собаку». Либо состояние \
            с пустой кличкой из галереи убрали — и тогда проверять \
            нечего, — либо откат до подписи активности не доехал, \
            либо кто-то вернул именительное «Собака» в винительный слот.

            Строки раздела: \(тексты.suffix(20).joined(separator: " | "))
            """)
    }
}
