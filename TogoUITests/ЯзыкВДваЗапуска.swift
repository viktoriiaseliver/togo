import XCTest

/// Смена языка в два запуска: нажал → перезапустил → интерфейс сменился.
///
/// **Эту дорогу не проверял никто, и французские кадры её не проверяют
/// тоже.** Кадры снимаются ключом `xcodebuild -testLanguage fr`. Ключ
/// ставит язык ТЕМ ЖЕ механизмом, в который пишет наш экран, —
/// `AppleLanguages` в `UserDefaults` (`AppState.swift`,
/// `Settings.preferredLanguage`), — но ставит его **снаружи, аргументом
/// запуска**. Два разных вопроса, и ответ на первый читается как ответ
/// на второй:
///
/// ```
/// -testLanguage fr     каталог доехал до бандла, строки французские
/// тап по «Français»    НАШ экран пишет ключ, iOS читает его при
///                      следующем запуске, и выбор переживает запуск
/// ```
///
/// Первое выполняется и при совершенно мёртвом экране «Язык»: убери
/// из `Settings.preferredLanguage` запись в `AppleLanguages` — ни один
/// французский кадр не покраснеет. Ровно наш класс «сторож на прокси».
///
/// ## Почему набор гоняется БЕЗ `-testLanguage`
///
/// Аргументы запуска приложения лежат в `NSArgumentDomain`, и он старше
/// постоянного домена, в который пишем мы. То есть с ключом замер
/// не состоялся бы **по устройству, а не по невезению**: приложение
/// показало бы французский и во втором запуске, и при мёртвой записи.
/// Контроль на это стоит первой строкой теста — прогон обязан
/// начинаться по-русски, иначе проверка «стало французским» выполнена
/// заранее и не доказывает ничего.
///
/// ## Что этот тест НЕ проверяет
///
/// * **Перевод.** Он спрашивает, сменился ли язык, а не верны ли слова.
///   Полнота каталога — `LocalizationCoverageTests`, имена языков —
///   `…уЯзыковБандлаЕстьИмена`, вид списка — кадр
///   `Дизайн/кадры-приёмки/язык-пять-строк-23.10/`.
/// * **Остальные три языка.** Дорога одна на все пять, и проверяется
///   она один раз; пятикратный прогон стоил бы десять запусков
///   приложения и не задавал бы нового вопроса.
/// * **Системные настройки iOS** («Открыть языки в настройках iOS») —
///   это чужое приложение, из прогона недостижимо.
///
/// ## Тест обязан прибрать за собой, и это не вежливость
///
/// Язык живёт в `UserDefaults` приложения и переживает прогон. Тест,
/// упавший посередине, оставил бы симулятор французским — и все
/// остальные наборы на нём посыпались бы **не на своём предмете**:
/// они водят приложение по русским подписям. Поэтому возврат стоит
/// в `tearDown` и выполняется в том числе после падения.
nonisolated final class ЯзыкВДваЗапускаUITests: XCTestCase {
    private var app: XCUIApplication!

    /// Подписи русского запуска — с чего начинаем и чем кончаем.
    private let ру = Подписи(язык: "ru")
    /// Подписи французского — что обязано приехать после перезапуска.
    private let фр = Подписи(язык: "fr")

    /// Тронут ли язык приложения. Читает `tearDown`: пока флаг поднят,
    /// симулятор не русский, и убирать за собой обязательно.
    private var языкСменён = false

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    override func tearDown() {
        guard языкСменён, app != nil else { return }
        // Две попытки, и обе с перезапуска: если тест упал на том, что
        // язык НЕ сменился, экран остался русским, и французские
        // подписи до него не дотянутся. Перезапуск между попытками
        // обязателен — после неудачи приложение стоит не на корне.
        for подписи in [фр, ру] {
            app.terminate()
            app.launch()
            if вернутьСистемныйЯзык(подписи: подписи) {
                языкСменён = false
                break
            }
        }
        XCTAssertFalse(языкСменён, """
            НЕ УДАЛОСЬ ВЕРНУТЬ ЯЗЫК СИМУЛЯТОРА. Он остался не русским, \
            и следующие наборы на нём посыплются не на своём предмете — \
            они водят приложение по русским подписям. Лечится руками: \
            `xcrun simctl erase <UDID>`.
            """)
    }

    // MARK: Дорога

    /// Шапка-меню «…» → «Настройки» → строка «Язык» → экран языка.
    ///
    /// Кнопка меню берётся по **идентификатору** `шапка-меню`
    /// (`HeaderMenu.swift`): он один на все языки, а её озвучка «Ещё»
    /// переводится. Остальные три шага — по подписям того языка,
    /// на котором сейчас стоит приложение.
    private func открытьЯзык(подписи т: Подписи) -> Bool {
        let меню = app.buttons["шапка-меню"].firstMatch
        guard меню.waitForExistence(timeout: 30) else { return false }
        меню.tap()

        let настройки = app.buttons[т("Настройки")].firstMatch
        guard настройки.waitForExistence(timeout: 10) else { return false }
        настройки.tap()

        let строка = найти(т("Язык"), в: app)
        guard строка.waitForExistence(timeout: 10) else { return false }
        строка.tap()
        return app.navigationBars[т("Язык")].waitForExistence(timeout: 10)
    }

    /// Строка «Как в системе» в списке языков.
    ///
    /// **Ищется по НАЧАЛУ подписи, и это замер, а не осторожность.**
    /// Прогон 24.10.2026: точное совпадение не нашло «Comme le système»
    /// при живой строке на экране. У ряда два текста — имя и пояснение
    /// (`LanguageScreen.row`, `detail:` = имя системного языка), SwiftUI
    /// склеивает их в одну подпись кнопки, и точное равенство мимо.
    /// У «Français» пояснения нет, поэтому там равенство совпало —
    /// **и это худший случай: половина формы работает**.
    private func строкаСистемногоЯзыка(подписи т: Подписи) -> XCUIElement {
        app.buttons
            .matching(NSPredicate(format: "label BEGINSWITH %@", т("Как в системе")))
            .firstMatch
    }

    /// Вернуть «Как в системе» — тем же путём, которым человек и ходит.
    private func вернутьСистемныйЯзык(подписи т: Подписи) -> Bool {
        guard открытьЯзык(подписи: т) else { return false }
        let какВСистеме = строкаСистемногоЯзыка(подписи: т)
        guard какВСистеме.waitForExistence(timeout: 5) else { return false }
        какВСистеме.tap()
        return true
    }

    // MARK: Предмет

    func testВыборЯзыкаПереживаетПерезапуск() {
        // ── Контроль ПЕРВЫМ, и он про то, было ли что проверять ──────
        XCTAssertTrue(app.tabBars.buttons[ру("Сегодня")].waitForExistence(timeout: 30), """
            прогон начался не по-русски: вкладки «\(ру("Сегодня"))» нет. \
            Либо симулятор остался чужим от упавшего прошлого прогона, \
            либо набор запущен с `-testLanguage` — тогда замер \
            не состоится по устройству, см. голову файла.
            """)
        XCTAssertFalse(app.tabBars.buttons[фр("Сегодня")].exists, """
            на первом запуске уже французская вкладка «\(фр("Сегодня"))». \
            Проверка «стало французским» ниже выполнена заранее \
            и не доказала бы ничего.
            """)

        XCTAssertTrue(открытьЯзык(подписи: ру),
                      "дорога «…» → «Настройки» → «Язык» по-русски не открылась")

        // Имя языка — эндоним и НЕ переводится (`LanguageScreen.names`),
        // поэтому ищется литералом: на любом языке интерфейса строка
        // зовётся одинаково. Это и делает возврат в `tearDown` возможным.
        let француз = app.buttons["Français"].firstMatch
        XCTAssertTrue(француз.waitForExistence(timeout: 10), """
            в списке языков нет строки «Français». До 23.10.2026 экран \
            предлагал один русский — если строка исчезла снова, это \
            решение `Settings.предлагаемыеЯзыки`, а не поломка дороги.
            """)
        француз.tap()
        языкСменён = true

        // Обещание перезапуска. Не предмет, но без него человек решит,
        // что тап не сработал, — и тапнет ещё раз по другому языку.
        XCTAssertTrue(app.staticTexts[ру("Закрой и открой приложение")]
                        .waitForExistence(timeout: 5), """
            язык выбран, а приложение не сказало, что нужен перезапуск. \
            На лету iOS не перерисовывает — человек увидит прежний язык \
            и прочтёт это как «кнопка не работает».
            """)

        // ── Второй запуск: ровно то, чего не проверял никто ──────────
        app.terminate()
        app.launch()

        XCTAssertTrue(app.tabBars.buttons[фр("Сегодня")].waitForExistence(timeout: 30), """
            ВТОРОЙ ЗАПУСК ОСТАЛСЯ РУССКИМ. Вкладки «\(фр("Сегодня"))» нет. \
            Выбор языка записан в `Settings.preferredLanguage` \
            (`AppState.swift`), оттуда в ключ `AppleLanguages` — \
            и либо запись не доехала, либо iOS её не прочитала. \
            Французские кадры `-testLanguage` про это не знают ничего: \
            они ставят тот же ключ сами, снаружи.
            """)
        XCTAssertFalse(app.tabBars.buttons[ру("Сегодня")].exists, """
            после перезапуска на экране ОДНОВРЕМЕННО французская \
            и русская вкладки — значит сменилась часть интерфейса, \
            а не интерфейс.
            """)

        // ── И обратно: выбор снимается тем же экраном ────────────────
        XCTAssertTrue(открытьЯзык(подписи: фр),
                      "по-французски дорога «…» → «Réglages» → «Langue» не открылась")
        let какВСистеме = строкаСистемногоЯзыка(подписи: фр)
        XCTAssertTrue(какВСистеме.waitForExistence(timeout: 10), """
            в списке нет строки «\(фр("Как в системе"))» — снять свой \
            выбор человеку нечем, и язык приложения останется выбранным \
            навсегда.
            """)
        какВСистеме.tap()

        app.terminate()
        app.launch()
        XCTAssertTrue(app.tabBars.buttons[ру("Сегодня")].waitForExistence(timeout: 30), """
            обратный путь не сработал: после «\(фр("Как в системе"))» \
            и перезапуска интерфейс не вернулся к системному языку. \
            Ключ `AppleLanguages` снимается `removeObject` — значит \
            не снялся.
            """)
        языкСменён = false
    }
}
