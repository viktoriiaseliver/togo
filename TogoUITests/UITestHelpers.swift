import XCTest

/// Общий поиск по началу подписи с прокруткой.
///
/// Подписи в приложении составные («Профиль собаки, Стич»), поэтому точное
/// совпадение по идентификатору не годится, а копия этого метода жила
/// в трёх тестовых классах.
///
/// # СОВПАДЕНИЕ ИМЁН — НЕ «КНОПКИ НЕТ», А ХУЖЕ: КНОПКА ЕСТЬ, И ОНА ЧУЖАЯ
///
/// Запись перенесена сюда 03.11.2026 из `ScreenshotTests.test04Занятие`
/// перед его удалением — она пережила свой тест, и больше нигде
/// её нет. **Этот метод подвержен ровно тому же:** он ищет по началу
/// подписи и про идентификатор не спрашивает.
///
/// Замер, которым она оплачена. Тест жал `app.buttons[т("Ещё")]`
/// и, не найдя за ней «Занятие», выходил по `guard … else { return }`
/// — зелёным и без кадра. Прогон 23.10 печатал «12 тестов, 6 отказов»
/// и **пять** вложений: шестой зелёный не снял ничего.
///
/// Хуже того, тап в пустоту не уходил. После редизайна
/// `buttons["Ещё"]` на «Сегодня» существует — это озвучка шапки-меню
/// «…» (`HeaderMenu.swift:82`, `accessibilityLabel("Ещё")`). Тест
/// открывал МЕНЮ НАСТРОЕК, не находил там занятия и уходил довольным.
///
/// > Искомого нет — ожидаемый исход; **нашлось чужое с тем же
/// > именем — исход, которого не ждёт никто**, и отличить их
/// > по `exists` нельзя. Различает только идентификатор.
///
/// Поэтому: ищешь элемент, у которого в приложении есть тёзка, —
/// добавляй `identifier != …` в предикат, как делал тот тест. Здесь
/// такого фильтра нет намеренно (подписи составные и разные), и это
/// граница метода, а не недосмотр.
nonisolated extension XCTestCase {
    func найти(_ подпись: String, в app: XCUIApplication, попыток: Int = 6) -> XCUIElement {
        for попытка in 0..<попыток {
            let элемент = app.descendants(matching: .any)
                .matching(NSPredicate(format: "label BEGINSWITH %@", подпись))
                .firstMatch
            if элемент.exists && элемент.isHittable && !подХромой(элемент, в: app) {
                return элемент
            }
            // Направление прокрутки зависит от того, ПОЧЕМУ элемент
            // не взят. Не дошли — крутить вверх; заехал под хрому —
            // крутить обратно, иначе каждая попытка уводит его глубже.
            //
            // **Скорость `.slow` — это замер, а не вкус.** Первая
            // редакция этой границы крутила полноэкранными свайпами
            // и дала МАЯТНИК: вверх — элемент под хромой, вниз — ушёл
            // за нижний сгиб, и так все шесть попыток (прогон 17:35,
            // в логе шесть пар «Swipe up / Swipe down» подряд и ни
            // одного тапа). Амплитуда была больше расстояния, которое
            // надо пройти.
            if попытка < попыток - 1 {
                if элемент.exists && подХромой(элемент, в: app) {
                    app.swipeDown(velocity: .slow)
                } else {
                    app.swipeUp(velocity: .slow)
                }
            }
        }
        return app.descendants(matching: .any)
            .matching(NSPredicate(format: "label BEGINSWITH %@", подпись))
            .firstMatch
    }

    /// Открыть «Настройки» — откуда бы мы ни стояли.
    ///
    /// **Шестерёнки в шапке нет НИГДЕ** — решение Виктории 22.10.2026:
    /// одна кнопка «…», а настройки её первым пунктом.
    ///
    /// > Здесь стояло «на „Истории" и „Здоровье" шестерёнка пока
    /// > осталась: эти файлы правят другие агенты». **Это устарело**,
    /// > и замер 25.10.2026 прямой: `gearshape` в `HistoryScreen`,
    /// > `HealthScreen` и `КиноЭкран` — **ноль вхождений** при живом
    /// > контроле (`HeaderMenu(` — по одному в `HistoryScreen`
    /// > и `КиноЭкран`). Оба экрана идут через `КиноЭкран`, и меню
    /// > у них общее.
    ///
    /// Поэтому порядок путей ПЕРЕВЁРНУТ: сперва меню, прямая кнопка —
    /// запасным. Прежний порядок ждал прямую кнопку по две секунды
    /// на каждом вызове, а её нет ни на одном экране: при двадцати
    /// вызовах это сорок секунд впустую за прогон, и ровно столько же
    /// на каждый отказ — ожидание отрабатывало полностью, прежде чем
    /// тест шёл в меню.
    ///
    /// Прямая кнопка оставлена, а не удалена: она найдётся, если
    /// шестерёнку когда-нибудь вернут, и тогда тесты не придётся
    /// править обратно.
    ///
    /// > **Дети `Menu` не существуют в дереве доступности, пока меню
    /// > не открыто.** Это не «кнопки нет» — это третье состояние,
    /// > и без явного шага «открыть меню» оно неотличимо от первого.
    /// > Двадцать три UI-теста искали `buttons["Настройки"]` напрямую;
    /// > помощник заведён, чтобы у этой правки было ОДНО место,
    /// > а не двадцать три.
    @discardableResult
    /// Открыть экран «Семья».
    ///
    /// **Вкладки «Семья» нет с 22.10.2026** — экран уехал в меню «…»
    /// (`HeaderMenu.swift:64`), туда же, куда настройки. Тесты,
    /// искавшие `tabBars.buttons["Семья"]`, говорили «вкладки нет —
    /// кадра нет» и читались как отказ запуска.
    ///
    /// > **Дорогу держит ОДИН помощник.** Настройки переносили один
    /// > раз, и семь тестов чинились по одному; второй раз повторять
    /// > это незачем.
    func открытьСемью(в app: XCUIApplication) -> Bool {
        // **СНАЧАЛА ВКЛАДКА СОБАКИ, и это поправка к моей же правке
        // часом раньше.** Пункт «Семья» живёт в меню «…», но меню
        // получает его только от `DogTab` (`DogTab.swift:100`,
        // `семья:` — необязательный довод `HeaderMenu`). На «Сегодня»
        // пункта нет, и первая редакция помощника искала его там:
        // «экран «Семья» не открылся» при живом меню.
        //
        // > Опись говорила «вкладка Семья уехала в собаку», я написала
        // > «уехала в меню». Верно и то и другое — **в меню ВНУТРИ
        // > собаки**, — и половина правды стоила прогона.
        //
        // Вкладка опознаётся номером, а не словом: она подписана
        // кличкой собаки (`RootView:136`), то есть у разных фикстур
        // зовётся по-разному.
        let вкладкаСобаки = app.tabBars.buttons.element(boundBy: 1)
        guard вкладкаСобаки.waitForExistence(timeout: 10) else { return false }
        вкладкаСобаки.tap()
        let меню = app.buttons["Ещё"].firstMatch
        guard меню.waitForExistence(timeout: 10) else { return false }
        меню.tap()
        let пункт = app.buttons["Семья"].firstMatch
        guard пункт.waitForExistence(timeout: 5) else { return false }
        пункт.tap()
        return true
    }

    func открытьНастройки(в app: XCUIApplication) -> Bool {
        // СНАЧАЛА ДОЖДАТЬСЯ, ЧТО ЭКРАН ЕСТЬ, и это не перестраховка.
        //
        // Прежний порядок начинался с ожидания прямой кнопки
        // на две секунды. Кнопки нет ни на одном экране, то есть
        // ожидание всегда отрабатывало полностью — и служило
        // НЕЧАЯННОЙ ПАУЗОЙ, за которую приложение успевало
        // подняться. Я убрала её как бесполезную, и `ЖиваяАктивность
        // ВГалерее` сразу перестал доходить до настроек: он
        // не ждёт главного экрана сам.
        //
        // > **Оптимизация сняла случайную гарантию, на которой кто-то
        // > держался.** Две секунды выглядели платой ни за что, а были
        // > платой за то, чего в коде не написано. Теперь ожидание
        // > явное: оно называет, чего ждёт, и не исчезнет от правки
        // > соседней строки.
        //
        // Ждём шапку, а не «Настройки»: шапка есть на всех четырёх
        // поверхностях и не зависит от того, куда уехал пункт меню.
        let шапка = app.buttons["Ещё"].firstMatch
        _ = шапка.waitForExistence(timeout: 10)

        // Сперва меню — живая дорога. Разбор порядка ниже.
        let меню = app.buttons["Ещё"].firstMatch
        if меню.waitForExistence(timeout: 3) {
            меню.tap()
            let пункт = app.buttons["Настройки"].firstMatch
            if пункт.waitForExistence(timeout: 3) {
                пункт.tap()
                return true
            }
            // Меню нашлось, а пункта в нём нет — это НЕ то же, что
            // «меню не нашлось», и возвращать общий `false` здесь
            // значило бы склеить два разных отказа. Дальше пробуем
            // прямую: если меню оказалось чужим, прямая ещё может
            // сработать.
        }
        let прямая = app.buttons["Настройки"].firstMatch
        guard прямая.waitForExistence(timeout: 2), прямая.isHittable else { return false }
        прямая.tap()
        return true
    }

    /// Элемент заехал под верхнюю хрому навигации.
    ///
    /// **`isHittable` отвечает про видимость, а не про достижимость
    /// тапом, и здесь он лжёт** — замер 21.10.2026 по дереву элементов
    /// из `.xcresult` упавшего прогона:
    ///
    /// ```
    /// кнопка «Записать корм»   {{34, 121.7}, {334, 44}}   isHittable = true
    /// поверх неё               Other {{0,0},{402,170.8}}, Image
    ///                          'AdditionalDimmingOverlay' — в AX-дереве
    ///                          ПОСЛЕ ScrollView, то есть выше по z
    /// исход тапа               XCUITest бьёт в {201.0, 143.7},
    ///                          NavigationLink НЕ выстреливает
    /// ```
    ///
    /// Три теста `FoodStockUITests` падали на этом так, что экран
    /// `FoodStockScreen` не рисовался ни разу (в 1915 объектах бандла
    /// «Чем кормим» — ноль при живых контролях), а отказ приезжал
    /// строками ниже и читался как «нет кнопки „Добавить корм"».
    ///
    /// > Тап в элемент, накрытый хромой, — это не «не нашли»
    /// > и не «нажали»: это третье состояние, и без него оно
    /// > неотличимо от второго.
    private func подХромой(_ элемент: XCUIElement, в app: XCUIApplication) -> Bool {
        let хрома = app.navigationBars.firstMatch
        guard хрома.exists, элемент.exists else { return false }
        return элемент.frame.minY < хрома.frame.maxY
    }
}

/// Вынос снятых кадров из `build/` — встроенный в прогон, а не ручной.
///
/// # Зачем это здесь, а не в инструкции
///
/// Кадры пишутся в `build/кадры-*`, а `build/` — в `.gitignore`. Правило
/// «нужное выносить в `Дизайн/кадры-приёмки/` и коммитить» записано
/// в своде и **не исполняется**: за месяц кадры дважды спасал тот, кто
/// пришёл убирать диск, — 12.10.2026 сто шестнадцать штук, 27.10 ещё
/// двадцать шесть, и среди них `154-режим-дня-КОНТРОЛЬ`, то есть
/// контроль, переставший быть контролем под `.gitignore`.
///
/// > **Механизм без входа не «почти работает» — он не работает.**
/// > Правило, которое держится на памяти исполнителя, тремя отчётами
/// > подряд показало, чего стоит эта память.
///
/// # Почему каталог отслеживается git, а не прячется
///
/// Снятые кадры уезжают в `Дизайн/кадры-приёмки/_последний-прогон/<набор>/`
/// — **вне `build/`, то есть уборка их не трогает, и вне `.gitignore`,
/// то есть `git status` о них говорит**. Это нарочно: кадр, которого
/// не видно в `status`, ничем не лучше кадра в `build/` — его точно так
/// же не заметит следующий. Шум здесь и есть сообщение «кадры сняты,
/// посмотри на них».
///
/// Каталог **перезаписывается** каждым прогоном набора: это рабочая
/// площадка, а не архив. Годное из неё переносят в именованный каталог
/// с датой (`витрина-вычитка-27.10/`) и коммитят — тогда у кадра
/// появляется адрес и повод.
nonisolated extension XCTestCase {

    /// - Parameters:
    ///   - откуда: каталог, куда тест писал кадры (обычно `build/кадры-…`).
    ///   - набор: имя подкаталога-получателя; обычно имя класса теста.
    func вынестиКадры(из откуда: URL, набор: String) {
        let фм = FileManager.default
        guard let файлы = try? фм.contentsOfDirectory(atPath: откуда.path),
              !файлы.filter({ $0.hasSuffix(".png") }).isEmpty else { return }

        let корень = откуда.deletingLastPathComponent().deletingLastPathComponent()
        let куда = корень
            .appendingPathComponent("Дизайн/кадры-приёмки/_последний-прогон")
            .appendingPathComponent(набор)
        do {
            try фм.createDirectory(at: куда, withIntermediateDirectories: true)
        } catch {
            print("КАДРЫ НЕ ВЫНЕСЕНЫ: каталог не создан — \(error.localizedDescription)")
            return
        }

        var вынесено = 0
        for имя in файлы where имя.hasSuffix(".png") {
            let цель = куда.appendingPathComponent(имя)
            // Перезапись, а не пропуск: прогон показывает ТЕКУЩЕЕ
            // состояние экрана, и вчерашний кадр под тем же именем —
            // это ровно тот случай, когда старое выдаёт себя за новое.
            try? фм.removeItem(at: цель)
            do {
                try фм.copyItem(at: откуда.appendingPathComponent(имя), to: цель)
                вынесено += 1
            } catch {
                print("КАДР НЕ ВЫНЕСЕН: \(имя) — \(error.localizedDescription)")
            }
        }
        // Счёт печатается и здесь, рядом со счётом снятых: «снято пять,
        // вынесено пять» читается одной строкой, а «снято пять»
        // и молчание про вынос — нет.
        print("КАДРОВ ВЫНЕСЕНО: \(вынесено) → Дизайн/кадры-приёмки/_последний-прогон/\(набор)/")
    }
}
