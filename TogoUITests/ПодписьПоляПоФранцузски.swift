import XCTest

/// Приёмка порога `LabeledField` — **`.xxLarge` против `.xxxLarge`,
/// по-французски, на SE 375**.
///
/// # Что проверяется
///
/// `ef7578b` сменил порог столбцовой раскладки подписи с
/// `isAccessibilitySize` на `размерТекста >= .xxxLarge`. `.xxxLarge` —
/// последняя НЕдоступная ступень, и прежний предикат её не захватывал:
/// работала строчная ветка, где у подписи стоит `fixedSize()` — она
/// не ужимается и не переносится, всю тесноту забирает поле, и человек
/// не видит того, что сам вписал.
///
/// `14c804c` до того сменил тип подписи со `String` на `Надпись`:
/// до этой правки `Text(label)` брал дословную перегрузку, и подпись
/// **не переводилась ни на одном из пяти языков** при готовом переводе
/// в каталоге. То есть французский кадр проверяет сразу обе правки,
/// и без второй первая была бы не видна: по-русски подписи короче.
///
/// # Контроль здесь важнее предмета, и это слова автора правки
///
/// ```
/// .xxLarge     строка остаётся строкой       ← КОНТРОЛЬ
/// .xxxLarge    подпись встаёт НАД полем      ← предмет
/// ```
///
/// Снять только `.xxxLarge` нельзя: столбец на одной ступени
/// неотличим от столбца на всех ступенях, и тогда не видно, что порог
/// стоит ТАМ, ГДЕ НАЗВАН. Поэтому обе ступени — в одном заходе,
/// на одном устройстве, одной сборкой.
///
/// # Почему экран «Анализы», и поправка к адресу приёмки
///
/// Автор назвал адресом `LabResultScreens.swift:703`/`:1092` — там
/// лежит `LabeledField(label: "Отметка лаборатории")`, самая длинная
/// подпись ИЗ РУССКИХ ЛИТЕРАЛОВ (19 знаков). Он же в том же коммите
/// пишет, что этой подписи **в каталоге нет вовсе**.
///
/// Оба утверждения верны, а вместе дают не тот адрес: на французском
/// прогоне `Отметка лаборатории` покажется **по-русски**, потому что
/// французского у неё нет. Перемер по всем 43 подписям `LabeledField`
/// (длина того, что УВИДИТ француз, то есть перевод либо русский
/// исходник при его отсутствии):
///
/// ```
/// 22  Quelle quantité donner    Сколько давать       PrescriptionScreens:256
/// 22  Intervalle à partir de    Норма от             LabResultScreens:681, :973
/// 19  Отметка лаборатории       (нет fr — РУССКОЕ)   LabResultScreens:703, :1092
/// 18  Intervalle jusqu'à        Норма до             LabResultScreens:687, :979
/// 17  Avec quoi on paie         Чем платим
/// ```
///
/// То есть худший случай — **22 знака, и их ДВА**, а не один. Второй
/// из них, `Норма от`, живёт ровно на «Анализах», в той же карточке
/// ввода, что `Норма до` (18) и `Отметка лаборатории` (19). Значит
/// адрес автора годен — но по подписи, которой он не называл,
/// и соседство трёх длинных подписей в одной карточке делает его
/// лучше, а не хуже названного.
///
/// `Сколько давать` (`PrescriptionScreens:256`) этим кадром
/// НЕ ПОКРЫВАЕТСЯ, и это сказано, а не пропущено.
///
/// # Как ставится язык
///
/// `-AppleLanguages (fr)` в `launchArguments`, то есть в доменe
/// аргументов приложения, а не `xcodebuild -testLanguage fr`.
/// Причина: `-testLanguage` ставит язык и раннеру, а раннер нужен
/// русским — тест водит приложение по подписям из каталога
/// (`Подписи(язык: "fr")`), и ему нужен тот же каталог, что
/// в приложении, а не своя локаль.
///
/// **Язык ПРОЧИТАН ОБРАТНО, а не объявлен:** первым делом тест
/// проверяет, что в дереве лежит французская подпись, и падает
/// до съёмки, если её нет. Иначе кадр с русским интерфейсом уедет
/// под именем «fr» — ровно та подделка, которую снаружи не отличить.
nonisolated final class ПодписьПоляПоФранцузски: XCTestCase {

    /// `.xxLarge` и `.xxxLarge` в терминах `UIContentSizeCategory`.
    /// Имена взяты у `КегльAX5`, где этот способ ЗАМЕРЕН
    /// (`ЗондКрупногоКегля`: высота подписи 24,00 → 62,33 pt).
    /// Окружение SwiftUI здесь не годится: `UIFontMetrics` читает
    /// настройку ПРОЦЕССА.
    static let xxLarge = "UICTContentSizeCategoryXXL"
    static let xxxLarge = "UICTContentSizeCategoryXXXL"

    private var app: XCUIApplication!
    private let подписи = Подписи(язык: "fr")
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-подпись-поля-fr")
    }

    /// Суффикс партии доезжает ТОЛЬКО как `TEST_RUNNER_KADR_SUFFIX`:
    /// `xcodebuild` отдаёт процессу теста переменные с этой приставкой,
    /// сняв её. Задашь `KADR_SUFFIX` обычной — не доедет, обе партии
    /// запишутся одними именами, вторая затрёт первую, и прогон будет
    /// зелёным при верном числе кадров.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        // `true`: кадр снимается и после неудачной дороги. Кадр не с того
        // экрана видно глазами, а отсутствие кадра неотличимо от «тест
        // не дошёл».
        continueAfterFailure = true
        снято = []
    }

    override func tearDown() {
        print("FR-КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ПодписьПоляПоФранцузски")
    }

    private func запустить(кегль: String) {
        if app != nil { app.terminate() }
        app = XCUIApplication()
        app.launchArguments = [
            "-UITesting", "-Сценарий", "amber",
            "-AppleLanguages", "(fr)", "-AppleLocale", "fr_FR",
            "-UIPreferredContentSizeCategoryName", кегль,
        ]
        app.launch()
    }

    private func снять(_ имя: String) {
        let кадр = app.screenshot()
        let вложение = XCTAttachment(screenshot: кадр)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("FR-КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        } catch {
            print("FR-КАДР НЕ ЛЁГ: \(имя) · \(error.localizedDescription)")
        }
    }

    @discardableResult
    private func докрутить(до элемент: XCUIElement, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if элемент.exists && элемент.isHittable { return true }
            app.swipeUp()
        }
        return элемент.exists && элемент.isHittable
    }

    /// Дорога до карточки ввода показателя, где лежат три длинные
    /// подписи разом. Возвращает `false`, назвав место обрыва, —
    /// и кадр места обрыва при этом уже снят.
    private func дойтиДоВводаПоказателя(_ ступень: String) -> Bool {
        // ЯЗЫК ЧИТАЕТСЯ ОБРАТНО. Ждём французскую вкладку «Santé»:
        // если её нет, язык не встал, и всё дальнейшее — кадры
        // русского интерфейса под французским именем.
        let вкладка = app.tabBars.buttons[подписи("Здоровье")]
        guard вкладка.waitForExistence(timeout: 60) else {
            снять("00-ОТКАЗ-язык-или-запуск-\(ступень)")
            XCTFail("""
                вкладки «\(подписи("Здоровье"))» нет за 60 с (ступень \(ступень)).
                Либо язык не встал (тогда на кадре русский интерфейс \
                и партию снимать нельзя), либо сценарий `amber` \
                не поставил лечение. Смотри кадр 00.
                """)
            return false
        }
        вкладка.tap()
        _ = app.navigationBars[подписи("Здоровье")].waitForExistence(timeout: 15)

        let строка = app.buttons[подписи("Анализы")].firstMatch
        guard докрутить(до: строка) else {
            снять("00-ОТКАЗ-нет-строки-анализов-\(ступень)")
            XCTFail("на «\(подписи("Здоровье"))» нет строки «\(подписи("Анализы"))»")
            return false
        }
        строка.tap()
        guard app.navigationBars[подписи("Анализы")].waitForExistence(timeout: 15) else {
            снять("00-ОТКАЗ-анализы-не-открылись-\(ступень)")
            XCTFail("строка нажата, экран «\(подписи("Анализы"))» не открылся")
            return false
        }

        let добавить = app.buttons[подписи("Добавить анализ")].firstMatch
        guard докрутить(до: добавить) else {
            снять("00-ОТКАЗ-нет-кнопки-добавить-\(ступень)")
            XCTFail("кнопки «\(подписи("Добавить анализ"))» нет ни в тулбаре, ни в пустом состоянии")
            return false
        }
        добавить.tap()

        guard app.staticTexts[подписи("Когда и где")].waitForExistence(timeout: 15) else {
            снять("00-ОТКАЗ-шаг1-не-открылся-\(ступень)")
            XCTFail("первый шаг ввода не открылся")
            return false
        }
        // Шаг 1 снимается тоже: на нём живёт `Номер бланка`
        // → `Numéro de fiche` (15 знаков), третья по длине подпись.
        снять("01-шаг1-когда-и-где-\(ступень)")

        let дальше = app.buttons[подписи("Дальше")].firstMatch
        guard докрутить(до: дальше) else {
            снять("00-ОТКАЗ-нет-кнопки-дальше-\(ступень)")
            XCTFail("на шаге 1 нет кнопки «\(подписи("Дальше"))» — на узком экране её могло выдавить")
            return false
        }
        дальше.tap()

        guard app.staticTexts[подписи("Показатели")].waitForExistence(timeout: 15) else {
            снять("00-ОТКАЗ-шаг2-не-открылся-\(ступень)")
            XCTFail("второй шаг «\(подписи("Показатели"))» не открылся — там предмет")
            return false
        }
        return true
    }

    /// Одна ступень: дорога, кадр верха карточки, кадр с подписями
    /// `Норма от`/`Норма до` после прокрутки.
    private func ступень(_ имя: String, кегль: String) {
        запустить(кегль: кегль)
        guard дойтиДоВводаПоказателя(имя) else { return }

        // Кадр ДО прокрутки: `Paramètre` · `Valeur` · `Unité`.
        снять("02-шаг2-показатель-\(имя)")

        // Предмет: `Intervalle à partir de` (22) и `Intervalle jusqu'à`
        // (18) лежат ниже, в той же карточке. Прокрутка до них —
        // по подписи, а не на глазок.
        let нормаОт = app.staticTexts[подписи("Норма от")].firstMatch
        let дошли = докрутить(до: нормаОт)
        снять("03-шаг2-норма-от-до-\(имя)")
        if !дошли {
            print("FR-ЗАМЕР: подписи «\(подписи("Норма от"))» не видно после прокрутки (ступень \(имя)) — смотри кадр 03")
        }
    }

    /// Обе ступени одним тестом и одним заходом: иначе контроль
    /// и предмет окажутся в разных прогонах, а у контроля срок
    /// годности — минуты.
    func testПорогПодписиНаДвухСтупенях() {
        ступень("xxLarge", кегль: Self.xxLarge)
        ступень("xxxLarge", кегль: Self.xxxLarge)
    }
}
