import XCTest

/// Приёмка редизайна iOS 28: кадр каждого из ПЯТИ исходов вердикта
/// и кадр экрана «Питание и режим».
///
/// # Зачем отдельный набор рядом с `ПроситсяСостоянияUITests`
///
/// Тот отвечает на вопрос «**строятся ли** девять состояний галереи»
/// и снимает кадры ШАГАМИ ПРОКРУТКИ — `13-просится-шаг-03`. Имя шага
/// ничего не обещает о содержимом, и это там написано прямо: «кадр
/// называется номером шага, а не тем, что я ожидаю на нём увидеть».
///
/// Приёмка дизайна спрашивает другое: **выглядит ли каждый исход так,
/// как на кадре 07** — и ответ на это даёт только кадр, у которого
/// в имени стоит исход. Поэтому здесь прокрутка идёт ДО исхода,
/// а снимок делается, когда он на экране.
///
/// ```
/// тест проверяет, верно ли посчитано   VerdictEngineTests
/// кадр проверяет, верно ли сказано     здесь
/// ```
///
/// # Что проверяется числом, а не глазом
///
/// **«Вывожу» первая во всех пяти исходах** — красная линия продукта:
/// приложение не знает лучше хозяина. Это проверяется геометрией
/// (`minY` кнопки «Вывожу» меньше, чем у второго действия той же
/// шторки), а не взглядом на кадр: перестановка двух кнопок местами
/// на картинке заметна, только если её искать.
///
/// # Чего кадр отсюда НЕ доказывает
///
/// - **Что собака доведёт приложение до этого состояния.** Факты
///   в галерее собраны значениями, а не прожиты. Вердикт при этом
///   считает настоящий `VerdictEngine` — подставлен срез фактов,
///   а не готовый вердикт.
/// - **Что совпало с макетом.** Совпадение решает человек, положив
///   кадр рядом с `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/07.png`.
///   Тест доводит до состояния и доказывает, что на экране оно.
///
/// **Куда пишет.** `build/кадры-просится-кино/`, путь из `#filePath` —
/// значит набор ломается от уборки каталога, и ломается не на своём
/// предмете. `build/` в `.gitignore`: то, что нужно сохранить,
/// выносится в `Дизайн/кадры-приёмки/` и коммитится.
nonisolated final class ПроситсяКиноUITests: XCTestCase {

    private var app: XCUIApplication!
    private let подписи = Подписи()

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-просится-кино")
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода: «снято пять» и «упал на третьем» выглядят в логе
        // одинаково — во втором случае строк `КАДР:` просто меньше,
        // а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своими проверками.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    /// Кадр окна ПРИЛОЖЕНИЯ, а не экрана устройства: на общем симуляторе
    /// в кадр уже попадало чужое приложение. Файлом, а не вложением —
    /// выгрузка вложений не сработала пять раз из девяти, а вложение,
    /// которое не выгружается, это кадр, которого нет.
    /// Байты уже снятых кадров — для проверки на дубликат.
    ///
    /// **Дубликат кадра и снятое состояние снаружи неразличимы**: имена
    /// разные, вес правдоподобный, прогон зелёный. Первая редакция этого
    /// набора сняла два побайтно одинаковых кадра, и поймал их `sha256`,
    /// а не прогон. Раз это ловится байтами, пусть ловит прогон.
    private var байты: [String: Data] = [:]

    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        let данные = кадр.pngRepresentation
        if let (прежнее, _) = байты.first(where: { $0.value == данные }) {
            XCTFail("""
                кадр «\(имя)» побайтно совпал с «\(прежнее)» — \
                это один и тот же экран под двумя именами. Прокрутка \
                решила, что докручивать некуда, и «состояние снято» \
                стало неотличимо от «снят предыдущий экран».
                """)
        }
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try данные.write(to: путь)
        байты[имя] = данные
        снято.append(имя)
        print("КАДР: \(путь.path) · \(данные.count) байт")
        return путь
    }

    // MARK: Пять исходов

    /// Один исход вердикта: как его узнать и что под ним обязано стоять.
    private struct Исход {
        /// Подпись состояния В ГАЛЕРЕЕ — по ней и прокручиваем.
        /// Берётся из `VerdictGallery`, не придумывается здесь.
        let подписьГалереи: String
        /// Заголовок исхода на самой шторке (`NeedVerdict.title`).
        let заголовок: String
        /// Второе действие (`NeedVerdict.alternativeAction`). Оно обязано
        /// стоять НИЖЕ «Вывожу».
        let второе: String
        /// Имя файла кадра.
        let имя: String
    }

    /// Порядок — **как в галерее сверху вниз**, иначе прокрутка пойдёт
    /// вверх-вниз маятником. Пять из девяти состояний: у `.unknown`
    /// три причины, и четыре лишних состояния галереи — её дело,
    /// а не пять исходов продукта.
    private let исходы: [Исход] = [
        .init(подписьГалереи: "МАЛО ДАННЫХ", заголовок: "Непонятно",
              второе: "Играем, не пойдём", имя: "07-просится-1-непонятно"),
        .init(подписьГалереи: "СРОЧНО", заголовок: "Выведи сейчас",
              второе: "Не сейчас", имя: "07-просится-2-срочно"),
        .init(подписьГалереи: "ПОХОЖЕ НА НУЖДУ", заголовок: "Выведи",
              второе: "Не сейчас", имя: "07-просится-3-похоже-на-нужду"),
        .init(подписьГалереи: "СКОРЕЕ ВНИМАНИЯ", заголовок: "Скорее внимания",
              второе: "Поиграю с ним", имя: "07-просится-4-скорее-внимания"),
        .init(подписьГалереи: "ЭПИЗОД", заголовок: "Выводи по первому знаку",
              второе: "Не сейчас", имя: "07-просится-5-эпизод"),
    ]

    func testПятьИсходовСнятыКадромИВывожуПервая() throws {
        открытьГалерею()

        for исход in исходы {
            let метка = прокрутитьДо(исход.подписьГалереи)
            XCTAssertTrue(метка != nil, """
                состояния «\(исход.подписьГалереи)» в галерее нет. \
                Это НЕ «исход сломался»: до него могли не докрутить, \
                а могли убрать само состояние из `VerdictGallery`. \
                Снято к этому месту: \(снято.joined(separator: ", "))
                """)
            guard метка != nil else { continue }

            try снять(исход.имя)

            // Кнопки той же шторки: берём пару, стоящую ближе всего
            // друг к другу по вертикали. Галерея держит девять шторок
            // подряд, и «первая найденная кнопка» — это кнопка чьей-то
            // чужой шторки.
            let второе = ближайшая(подписи(исход.второе))
            XCTAssertTrue(второе != nil, """
                на кадре «\(исход.имя)» нет второго действия \
                «\(исход.второе)». Либо исход другой, либо \
                `NeedVerdict.alternativeAction` разошёлся с тем, \
                что здесь записано.
                """)
            guard let второе else { continue }

            XCTAssertTrue(вывожуВышеВТойЖеШторке(второе), """
                «Вывожу» не стоит первой в исходе «\(исход.заголовок)». \
                Это не вёрстка: приложение не знает лучше хозяина, \
                и вердикт не блокирует выход. Кнопка «\(исход.второе)» \
                оказалась выше.
                """)
        }

        XCTAssertEqual(снято.count, исходы.count, """
            снято \(снято.count) кадров из \(исходы.count): \
            \(снято.joined(separator: ", ")). Кадра на исход не хватает — \
            приёмка дизайна у этого исхода не снята вовсе.
            """)
    }

    // MARK: Живая шторка

    /// Та же шторка, но с НАСТОЯЩЕЙ собакой — и это не дубль галереи.
    ///
    /// Галерея подставляет срез фактов мимо базы и собаку не передаёт
    /// вовсе (`NeedsSheet(dog: nil, …)`). Из-за этого **две поверхности
    /// шторки на её кадрах не строятся ни на одном из пяти**:
    ///
    /// ```
    /// фото собаки в круге        нет собаки → заглушка «·»
    /// чипы «как попросил»        условие спрашивает события собаки
    /// строка дозы и кнопка «Дал» условие спрашивает схемы лечения
    /// ```
    ///
    /// Это ровно наш класс «поверхность без кадра»: пока смотреть
    /// не на что, дефект на ней живёт сколько угодно. Лечится входом,
    /// а не взглядом — вот он.
    ///
    /// **Чего кадр НЕ обещает.** Какой именно исход тут выпадет, решают
    /// засеянные данные, и он может меняться от прогона к прогону:
    /// кадр отвечает за состав шторки, а за пять исходов отвечает
    /// соседний тест.
    func testЖиваяШторкаПроситсяСнятаКадром() throws {
        let просится = app.buttons[подписи("Просится")].firstMatch
        XCTAssertTrue(просится.waitForExistence(timeout: 20), """
            на «Сегодня» нет кнопки «Просится». Это может быть \
            не дефект: главная кнопка меняется по состоянию дня, \
            и в час дозы там «Дал», а на прогулке «Открыть». \
            Тогда кадр снимать не с чего, и сказать надо именно это.
            """)
        просится.tap()

        // КОНТРОЛЬ, что открылась именно она: подзаголовок шторки
        // больше нигде в приложении не встречается.
        let подзаголовок = найти(подписи("по времени и прошлым дням"), в: app)
        XCTAssertTrue(подзаголовок.waitForExistence(timeout: 10), """
            шторка «Просится» не открылась — снимать нечего. \
            Кадр главного экрана прошёл бы за кадр вердикта.
            """)

        try снять("07-просится-живая-собака")

        // Чипы «как попросил» показываются по `Diary.shouldAskHowAsked`.
        // Их отсутствие — НЕ дефект: правило спрашивает историю выходов.
        // Но сказать, чего на кадре нет, обязан тот, кто его снял,
        // иначе следующий прочтёт кадр как «чипов не сделали».
        let чипы = app.descendants(matching: .any)
            .matching(NSPredicate(format: "label CONTAINS[c] %@",
                                  подписи("как попросил")))
            .firstMatch
        print("""
            ГРАНИЦА: чипы «как попросил» на этом кадре \
            \(чипы.exists ? "ЕСТЬ" : "ОТСУТСТВУЮТ — правило \
            `Diary.shouldAskHowAsked` сказало «не спрашивать», \
            и это состояние, а не дефект").
            """)
    }

    // MARK: Питание и режим

    func testПитаниеИРежимСнятоКадром() throws {
        // Вкладка собаки подписана кличкой — она приходит из данных,
        // и перевода у неё нет и быть не может. Ищем вход по строке
        // экрана, а не по кличке: иначе тест завязан на засеянное имя.
        let вкладка = app.tabBars.buttons.element(boundBy: 1)
        XCTAssertTrue(вкладка.waitForExistence(timeout: 20), """
            таб-бара нет — до вкладки собаки мы не дошли, и «кадра \
            питания нет» говорит о дороге, а не об экране.
            """)
        вкладка.tap()

        let питание = найти(подписи("Питание и режим"), в: app)
        XCTAssertTrue(питание.waitForExistence(timeout: 10), """
            строки «Питание и режим» на вкладке собаки нет. Вход \
            единственный — `DogTab`, и если его переименовали, \
            экран стал недостижим, а не сломан.
            """)
        питание.tap()

        // КОНТРОЛЬ, что мы НА ТОМ экране: «норма врача ÷ кормления» —
        // надпись блока нормы и больше нигде в приложении её нет.
        // Без контроля кадр вкладки собаки прошёл бы за кадр питания.
        let норма = app.descendants(matching: .any)
            .matching(NSPredicate(format: "label CONTAINS[c] %@",
                                  подписи("норма врача")))
            .firstMatch
        XCTAssertTrue(норма.waitForExistence(timeout: 10), """
            на экране нет надписи «норма врача ÷ кормления» — блок \
            нормы не построился. Снимать нечего: кадр без него \
            это приёмка пустоты.
            """)

        try снять("13-питание-верх")

        // Низ экрана — «ЧАСЫ» и «ЗАПАС КОРМА»: на кадре 13 они оба
        // видны, у нас шапка выше и они уезжают под сгиб.
        for _ in 0..<3 { app.swipeUp() }
        try снять("13-питание-часы-и-запас")

        print("""
            ГРАНИЦА: кадры доказывают, что блоки построились и в каком \
            они порядке. Совпадение с `13.png` решает человек, положив \
            их рядом. Шапка-фото подэкрана (backdropSub 360) здесь \
            НЕ сделана — стоит прежняя полоса `posterHeader`, \
            и это расхождение названо в отчёте.
            """)
    }

    // MARK: Дорога

    /// Главный экран → «…» → «Настройки» → галерея «Просится».
    ///
    /// **Шестерёнки в шапке больше нет** — решение Виктории 22.10.2026,
    /// «Шапка: одна кнопка „…“ (меню): Настройки · Другой день · Семья».
    /// Соседний набор `ПроситсяСостоянияUITests` всё ещё жмёт кнопку
    /// «Настройки» прямо на главном и падает «не дождались главного
    /// экрана»: дорога изменилась, а сообщение говорит про экран.
    /// Чинить его — не моя правка, но назвать надо: это не «главный
    /// экран не построился», это «входа больше нет там, где искали».
    private func открытьГалерею() {
        let меню = app.buttons["шапка-меню"].firstMatch
        XCTAssertTrue(меню.waitForExistence(timeout: 20), """
            на главном экране нет кнопки «…» (`шапка-меню`). Это \
            не «главный экран не построился» — проверь сперва его: \
            кнопка могла переехать вместе с шапкой.
            """)
        меню.tap()

        let настройки = app.buttons[подписи("Настройки")].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 10), """
            в меню «…» нет пункта «Настройки». Пункт есть всегда \
            по решению дизайна — Apple ждёт настройки в предсказуемом \
            месте, и его отсутствие это дефект, а не состояние.
            """)
        настройки.tap()

        let вход = найти(подписи("Просится"), в: app)
        XCTAssertTrue(вход.waitForExistence(timeout: 10), """
            в настройках нет входа «Просится» — галерея живёт под \
            `#if DEBUG`, и в Release-сборке этой проверки не существует
            """)
        вход.tap()
    }

    /// Крутить вниз, пока подпись состояния не окажется **на экране**.
    ///
    /// Спрашиваем предикатом, а не перечислением: пока перечисляются
    /// индексы, список под рукой уже другой — первая редакция соседнего
    /// набора падала с «No matches found for Element at index 51»,
    /// и падение выглядело дефектом галереи при дефекте обхода.
    ///
    /// **Проверяется не `exists`, а положение в окне.** `exists`
    /// отвечает про дерево доступности, в котором SwiftUI держит
    /// и то, что за сгибом: кадр тогда снимался бы «для состояния»,
    /// которого на картинке нет. Это ровно тот случай, где
    /// «мне сказали да» и «я это вижу» — разные вопросы.
    ///
    /// **И `intersects` тоже отвечает не на тот вопрос. Замер
    /// 23.10.2026, на себе:**
    ///
    /// ```
    /// окно                        (0, 0, 402, 874)
    /// подпись «СРОЧНО · …»        (18, 873.667, 258.7, 13.33)
    /// CGRect.intersects           true     ← пересечение в ТРЕТЬ ТОЧКИ
    /// на экране                   нет вовсе, она под индикатором
    /// ```
    ///
    /// Первая редакция на этом сняла **два побайтно одинаковых кадра**
    /// под разными именами (`sha256` совпал): прокрутка решила, что
    /// докручивать некуда, и «состояние снято» было неотличимо
    /// от «снят предыдущий экран». Поймал это не прогон — он был
    /// зелёный, имена разные, вес правдоподобный, — а хеш.
    ///
    /// **Предикат строится ВНУТРИ цикла, и это не стиль.** Вынесенный
    /// наружу, он уезжает через `app.swipeUp()` в другой контекст
    /// изоляции, и сборка схемы падает «sending 'предикат' risks causing
    /// data races» — ровно та ошибка, на которой 14.10 сосед потерял
    /// прогон, разбирая её как свой дефект.
    private func прокрутитьДо(_ подпись: String, шагов: Int = 14) -> XCUIElement? {
        for шаг in 0...шагов {
            let элемент = app.descendants(matching: .any)
                .matching(NSPredicate(format: "label BEGINSWITH %@", подпись))
                .firstMatch
            if элемент.exists, вверхуЭкрана(элемент) { return элемент }
            if шаг < шагов { app.swipeUp() }
        }
        return nil
    }

    /// Элемент целиком в окне — ни верхним краем выше, ни нижним ниже.
    private func наЭкране(_ элемент: XCUIElement) -> Bool {
        let окно = app.frame
        let рамка = элемент.frame
        guard рамка.height > 0, рамка.width > 0 else { return false }
        return рамка.minY >= окно.minY && рамка.maxY <= окно.maxY
    }

    /// Элемент в верхней части окна — настолько, что под ним помещается
    /// шторка состояния целиком.
    ///
    /// Шторка галереи 560 pt, окно 874 — значит подпись обязана стоять
    /// не ниже 314-й точки, иначе подвал с кнопками уедет за сгиб
    /// и кадр покажет исход без главного действия. Число выведено
    /// из двух известных, а не подобрано.
    private func вверхуЭкрана(_ элемент: XCUIElement) -> Bool {
        let окно = app.frame
        let рамка = элемент.frame
        guard рамка.height > 0, рамка.width > 0 else { return false }
        return рамка.minY >= окно.minY
            && рамка.minY <= окно.maxY - Self.высотаШторкиГалереи
    }

    /// Высота одной шторки в `VerdictGallery` — `.frame(height: 560)`.
    /// Вторая копия числа, и она названа: разойдётся молча, если
    /// галерея сменит высоту. Проверка за минуту —
    /// `grep "frame(height:" Togo/DesignSystem/VerdictGallery.swift`.
    private static let высотаШторкиГалереи: CGFloat = 560

    /// Видимая на экране кнопка с такой подписью. `nil` — такой нет.
    private func ближайшая(_ подпись: String) -> XCUIElement? {
        let кнопки = app.buttons.matching(NSPredicate(format: "label == %@", подпись))
        for i in 0..<кнопки.count {
            let кнопка = кнопки.element(boundBy: i)
            guard кнопка.exists, наЭкране(кнопка) else { continue }
            return кнопка
        }
        return nil
    }

    /// Стоит ли «Вывожу» выше этой кнопки и в ТОЙ ЖЕ шторке.
    ///
    /// «В той же» решает расстояние: подвал шторки — две кнопки подряд,
    /// между ними меньше высоты одной цели касания с запасом. Без этого
    /// ограничения «Вывожу» соседней шторки, стоящей выше, доказывала бы
    /// порядок в чужом исходе.
    private func вывожуВышеВТойЖеШторке(_ второе: XCUIElement) -> Bool {
        let вывожу = app.buttons.matching(
            NSPredicate(format: "label == %@", подписи("Вывожу")))
        for i in 0..<вывожу.count {
            let кнопка = вывожу.element(boundBy: i)
            guard кнопка.exists else { continue }
            let разрыв = второе.frame.minY - кнопка.frame.minY
            if разрыв > 0, разрыв < Self.подвалШторки { return true }
        }
        return false
    }

    /// Насколько далеко друг от друга стоят две кнопки одного подвала.
    /// Главная 60 pt плюс зазор; 120 — с запасом на крупный кегль
    /// и мало для того, чтобы захватить соседнюю шторку (560 pt).
    private static let подвалШторки: CGFloat = 120
}
