import XCTest

/// Вход в онбординг: работает ли он и ничего ли не пишет.
///
/// **Приёмка правки `1c1508d · f5d614f · bd4783d · 62b8be8`**, и больше
/// ничего. Про вид онбординга этот файл не утверждает **ничего**: ни
/// про цвет, ни про тему, ни про геометрию. Партии кадров для дизайна —
/// предмет соседа, здесь одно утверждение: код рисует онбординг, когда
/// его об этом просят, и не трогает хранилище, когда смотрят.
///
/// ## Почему два запуска, а не один
///
/// «Онбординг виден» само по себе не доказывает ничего: он мог быть
/// виден и до правки — например, потому что на этом устройстве его
/// просто не проходили. Нужна пара, и вторым идёт **контроль**:
///
/// ```
/// -Сценарий onboarding -Онбординг   должен быть ШАГ (кнопка «Добавить собаку»)
/// -Сценарий onboarding              должен быть ГЛАВНЫЙ (таб-бар)
/// ```
///
/// Второй запуск — это прежнее поведение: под `-UITesting` ворота
/// закрыты. Покраснеет он — значит сломаны ворота, а не вход, и чинить
/// надо другое. Без него красное первого не отличить от «у нас тут
/// всегда онбординг».
///
/// ## Что этот вход НЕ делает, и это надо знать до чтения зелени
///
/// Он **обходит** оба воротa, а не проходит их. Пропуск собаки, засев,
/// `DogOrigin.заведенаЗдесь` и первая запись веса по этому пути
/// не случаются вовсе — `пишемВБазу` ложно. То есть зелёное здесь
/// значит «код нарисует онбординг, если попросить», а не «так увидит
/// человек на первом запуске телефона». На второй вопрос отвечает
/// `ОнбордингНиз`, и он нарочно запускается **без** `-UITesting`
/// на стёртом устройстве.
///
/// > **Дешёвый вход и настоящий вход — разные входы.** Выбирать между
/// > ними надо по тому, про что вопрос, а не по цене прогона.
///
/// ## Третий тест — про собственную ошибку автора
///
/// Запись в базу сперва выключалась одним местом, и рядом стоял
/// комментарий, что оно единственное. Мимо него писали **три шага
/// из шести**, и самый дорогой — `CareStep.save()`: он кладёт дела
/// ухода на `dogs.first`, а в просмотре с кнопки настроек собака
/// **есть**, живая, та, у которой весь дневник.
///
/// Дыра была не видна оттого, что просмотр проверяли на сценарии
/// `onboarding`, где хранилище пустое и писать не на что: там он
/// безопасен **по построению**, а не по защите. Поэтому третий тест
/// идёт по второму пути — живая база, вход кнопкой из настроек, —
/// и считает дела ухода до и после. Проверять починку там же, где
/// её не было видно, значит проверять себя.
nonisolated final class ВходОнбордингаРаботает: XCTestCase {

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-входа-онбординга")
    }

    /// Суффикс партии доезжает только как `TEST_RUNNER_KADR_SUFFIX`:
    /// `xcodebuild` отдаёт процессу теста лишь переменные с этой
    /// приставкой, снимая её. Без неё прогон зелёный, кадры есть,
    /// имена без суффикса — и вторая партия молча затирает первую.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        continueAfterFailure = false
    }

    private func запустить(_ аргументы: [String]) -> XCUIApplication {
        let app = XCUIApplication()
        app.launchArguments = аргументы
        app.launch()
        return app
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Иначе «снято всё» и «упал на третьем» выглядят
        // в логе ОДИНАКОВО: во втором случае строк `КАДР:` просто
        // меньше, а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своей проверкой, а не эта печать.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ app: XCUIApplication, _ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    // MARK: - 1. С аргументом виден настоящий первый шаг

    func testСАргументомВиденПервыйШагОнбординга() {
        let app = запустить(["-UITesting", "-Сценарий", "onboarding", "-Онбординг"])

        // Опознаём шаг по КНОПКЕ, а не по заголовку: заголовок
        // «Дневник» живёт и на главном экране, а «Добавить собаку»
        // стоит только на первом шаге онбординга и только когда
        // `isReplay` ложен — при повторе там «Перечитать».
        let добавить = app.buttons["Добавить собаку"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 20), """
            Первый шаг онбординга не показался при -Онбординг.
            Две разные поломки, и по этому сообщению их не различить —
            смотреть надо так:
              • ворота: TogoApp.swift AppRoot.body, условие
                `!appState.просмотрОнбординга, isUITesting || …`;
              • подмена шагов: OnboardingFlow.isReplay — если база
                оказалась НЕ пустой, кнопка будет «Перечитать»,
                и это про -Сценарий onboarding, а не про -Онбординг.
            """)

        снять(app, "01-первый-шаг-с-аргументом")

        // Таб-бара на онбординге нет вовсе: пока он не пройден, вкладок
        // не показывают. Это второе, независимое доказательство того,
        // что мы не на главном экране, — на случай если кнопка с таким
        // именем однажды появится и там.
        XCTAssertFalse(app.tabBars.firstMatch.exists,
                       "На онбординге таб-бара быть не должно — похоже, это главный экран.")
    }

    // MARK: - 2. Контроль: без аргумента всё как раньше

    func testБезАргументаВоротаЗакрытыИВиденГлавный() {
        let app = запустить(["-UITesting", "-Сценарий", "onboarding"])

        XCTAssertTrue(app.tabBars.firstMatch.waitForExistence(timeout: 20), """
            Главный экран не показался БЕЗ -Онбординг. Это говорит
            про ворота `isUITesting || onboardingCompleted`, а не про вход:
            прежнее поведение сломано, и зелень первого теста при такой
            красноте ничего не стоит.
            """)

        снять(app, "02-контроль-главный-без-аргумента")

        XCTAssertFalse(app.buttons["Добавить собаку"].firstMatch.exists,
                       "Без -Онбординг онбординга быть не должно.")
    }

    // MARK: - 3. Просмотр на ЖИВОЙ базе ничего не записывает

    func testПросмотрИзНастроекНеТрогаетХранилище() {
        // Сценарий `today` нарочно: здесь собака ЕСТЬ, и дела ухода
        // у неё уже заведены засевом. Это тот самый второй мир,
        // в котором дыра и жила.
        let app = запустить(["-UITesting", "-Сценарий", "today"])

        XCTAssertTrue(app.tabBars.firstMatch.waitForExistence(timeout: 20),
                      "Главный экран не поднялся — дальше мерить нечего.")

        app.buttons["Настройки"].firstMatch.tap()

        let кнопка = app.buttons["Посмотреть онбординг как новый"].firstMatch
        // Пункт лежит ниже сгиба: в дереве доступности его нет, пока
        // не прокрутили. Тапать надо КНОПКУ, а не любой элемент с этим
        // именем, — на этом уже спотыкались с витриной компонентов.
        for _ in 0..<8 where !кнопка.exists { app.swipeUp() }
        XCTAssertTrue(кнопка.waitForExistence(timeout: 5), """
            Кнопки «Посмотреть онбординг как новый» нет в настройках.
            С 62b8be8 она вне #if DEBUG — если прогон идёт на более
            старом коммите, это объясняет красноту полностью.
            """)
        кнопка.tap()

        // Шаг «Кто у тебя живёт» — настоящий, а не справка: при
        // повторном прохождении здесь был бы HowItWorksScreen.
        let дальше = app.buttons["Дальше"].firstMatch
        XCTAssertTrue(app.staticTexts["Кто у тебя живёт"].firstMatch.waitForExistence(timeout: 10)
                      || дальше.waitForExistence(timeout: 5), """
            Просмотр с живой базой не дошёл до настоящего шага собаки.
            Если видно «Как это работает» — isReplay не выключился,
            то есть `!dogs.isEmpty && !просмотр` считает не то.
            """)

        снять(app, "03-просмотр-на-живой-базе")

        // Выходим просмотром назад, а не доходя до конца: пройти поток
        // целиком значило бы нажать «Разрешить уведомления», а это
        // системный алерт — он блокирует всё, что идёт следом.
        app.terminate()

        // Второй запуск на том же сценарии: база демо-собрана заново,
        // то есть «не прибавилось» здесь проверяется не числом записей,
        // а отсутствием второй собаки на экране выбора. Числовую
        // приёмку запись/не запись даёт модульный тест; этот отвечает
        // на вопрос, который модульным не задашь: не сломался ли вход
        // в пути человека.
        let снова = запустить(["-UITesting", "-Сценарий", "today"])
        XCTAssertTrue(снова.tabBars.firstMatch.waitForExistence(timeout: 20),
                      "После просмотра приложение не поднялось на главный экран.")
        снять(снова, "04-после-просмотра-главный")
    }
}
