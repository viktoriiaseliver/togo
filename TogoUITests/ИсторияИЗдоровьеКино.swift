import XCTest

/// Кадры «Истории», «Здоровья» и «Анализов» после перевода на тему «Кино».
///
/// **Зачем кадр, когда набор зелёный.** Тест проверяет, верно ли
/// посчитано; кадр — верно ли сказано. Правка меняет ровно то, что
/// человек читает: шапку, фильтры, карточку запаса, блок показания.
/// Зелёный прогон этого не видит и видеть не может.
///
/// **С чем сверять — названо поимённо, и не всё сверяемо.**
///
/// ```
/// кадр стенда          эталон дизайна
/// 10-история           Дизайн/эталонные-кадры/ios28-кино-22.10/10.png
/// 11-здоровье          …/11.png
/// 14-анализы           …/14.png — НО СОСТОЯНИЕ ДРУГОЕ, см. ниже
/// ```
///
/// На `14.png` нарисован экран с четырьмя анализами, нормой с бланка
/// и часами от дозы. **Ни один демо-сценарий не заводит `LabResult`:**
/// `SeedData.Scenario` на 23.10.2026 даёт `today`, `silence`,
/// `urineSilence`, `amber`, `emptyDogs` и пустое хранилище, и записей
/// анализов нет ни в одном. Значит кадр `14-анализы` снимается
/// с ПУСТОГО состояния, и сверять его с `14.png` нельзя — он
/// доказывает дорогу и шапку, а не верхний блок.
///
/// > **Состояние недостижимо — это не «кадр не снят».** Первое
/// > лечится входом (сценарием с анализами), второе взглядом, и путать
/// > их дорого: пустой кадр с именем «анализы» читается как принятый.
///
/// **Куда пишет.** `build/кадры-кино/`, путь выведен из `#filePath`.
/// `build/` в `.gitignore`: то, что нужно сохранить, выносится
/// в `Дизайн/кадры-приёмки/` и коммитится отдельно.
nonisolated final class ИсторияИЗдоровьеКино: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []

    /// Сколько кадров обязан дать проход. Число живёт в одном месте
    /// и печатается рядом со счётом: «снято четыре» и «упал на третьем»
    /// выглядят в логе одинаково, если ожидаемого не назвать.
    private let ожидается = 4

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-кино")
    }

    /// Суффикс партии приходит СНАРУЖИ и только с приставкой
    /// `TEST_RUNNER_` — `xcodebuild` своё окружение процессу теста
    /// не передаёт. Без него вторая партия перезаписывает первую молча.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        // `amber` — единственный сценарий, где есть препарат с окном
        // натощак, то есть карточке лечения и карточке запаса есть что
        // показать. На `today` обе были бы пусты, и кадр утверждал бы
        // про пустой экран.
        app.launchArguments = ["-UITesting", "-Сценарий", "amber"]
        app.launch()
    }

    /// Счёт печатается ВСЕГДА и в том числе после падения посреди
    /// прохода: строк про кадры в этом случае просто меньше,
    /// а отсутствия никто не ищет.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) из \(ожидается) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    func testКадрыИсторииЗдоровьяИАнализов() throws {
        let вкладки = app.tabBars.buttons
        XCTAssertTrue(вкладки.firstMatch.waitForExistence(timeout: 30),
                      "панель вкладок не появилась — приложение не поднялось")

        // 1. История.
        let история = вкладки["История"]
        XCTAssertTrue(история.waitForExistence(timeout: 10), "вкладки «История» нет")
        история.tap()
        XCTAssertTrue(app.navigationBars["История"].waitForExistence(timeout: 10), """
            панель навигации «История» не найдена. Она остаётся нарочно:
            по ней экраны адресуют три UI-теста медслоя. Пропала —
            значит шапку сняли вместе с панелью.
            """)
        снять("10-история")

        // 2. Фильтр-чип переключается. Это не косметика: сегментированный
        //    выбор убран, и если чип не нажимается, фильтра на экране нет.
        let стул = app.buttons["Стул"].firstMatch
        let чипНайден = стул.waitForExistence(timeout: 5)
        if чипНайден {
            стул.tap()
            снять("10-история-фильтр-стул")
        } else {
            // Говорим вслух, а не молчим: неснятый кадр и пустой кадр
            // снаружи одинаковы.
            print("ЧИП «Стул» НЕ НАЙДЕН: фильтры на «Истории» не нажимаются")
        }

        // 3. Здоровье.
        let здоровье = вкладки["Здоровье"]
        XCTAssertTrue(здоровье.waitForExistence(timeout: 10), """
            вкладки «Здоровье» нет. Её держит ПРАВО `.seeMedical`,
            а не включённое лечение (решение 08.10.2026): пропала —
            значит условие лечения вернули.
            """)
        здоровье.tap()
        XCTAssertTrue(app.navigationBars["Здоровье"].waitForExistence(timeout: 10),
                      "панель навигации «Здоровье» не найдена")
        снять("11-здоровье")

        // 4. Анализы. Строка названа предикатом, а не точным ярлыком:
        //    у `TGListRow` в метку озвучки склеиваются заголовок
        //    и значение («Анализы, 1 запись»), и точное совпадение
        //    не нашло бы живую строку — а «не нашёл» прочиталось бы
        //    как «дороги нет».
        let строка = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", "Анализы")
        ).firstMatch
        for _ in 0..<10 where !строка.exists { app.swipeUp() }
        XCTAssertTrue(строка.waitForExistence(timeout: 10), """
            на «Здоровье» нет строки «Анализы». Экран анализов
            существует и недостижим — то состояние, в котором медслой
            пролежал до 08.10.2026.
            """)
        строка.tap()
        XCTAssertTrue(app.navigationBars["Анализы"].waitForExistence(timeout: 10),
                      "строка есть, а экран за ней не открылся")
        снять("14-анализы")

        // **Приёмка — ЧИСЛО снятого, а не отсутствие падения.** Проход,
        // оборвавшийся посередине, печатает те же строки, только их
        // меньше, и разницы в логе не видно. Признак чипа взят
        // в момент, когда он мерился: спросить `стул.exists` здесь
        // значило бы спросить про ДРУГОЙ экран и получить «нет» при
        // снятом кадре.
        XCTAssertEqual(снято.count, чипНайден ? ожидается : ожидается - 1, """
            кадров снято \(снято.count), ожидалось \(чипНайден ? ожидается : ожидается - 1).
            """)
    }

    /// Кадр файлом, не вложением: выгрузка вложений у нас не сработала
    /// пять раз из девяти. Отказ записи НЕ роняет тест — кадр это улика,
    /// а не ворота.
    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }
}
