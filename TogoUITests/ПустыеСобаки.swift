import XCTest

/// Отзыв TestFlight 06.10.2026, сборка 271: «Много пустых собак».
///
/// **Что эти тесты делают и чего НЕ делают.** Они снимают кадры состояния,
/// построенного сценарием (`emptyDogs`, `wipedName`), и отвечают на вопрос
/// «что человек видит и может ли он из этого выйти». Они **не** отвечают
/// на вопрос «откуда записи берутся»: состояние здесь построено руками,
/// а не приехало обменом. Построить и воспроизвести — разные утверждения,
/// и кадр, снятый с построенного состояния, доказывает только отрисовку.
///
/// Механизм измерен отдельно (`togo-05`): приём записи с пустой кличкой,
/// `SharedDiaryRecords`. Эти тесты — про цену дефекта, а не про причину.
nonisolated final class ПустыеСобакиUITests: XCTestCase {
    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = false
    }

    private func запустить(сценарий: String) {
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", сценарий]
        app.launch()
    }

    private func снять(_ имя: String) {
        // Кадр берётся у ОКНА приложения, а не у экрана симулятора:
        // экран принадлежит симулятору, окно — приложению, и на общей
        // машине это разные вещи.
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    private func открытьНастройки() {
        let шестерёнка = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(шестерёнка.waitForExistence(timeout: 15),
                      "не дождались главного экрана — состояние не построилось")
        шестерёнка.tap()
    }

    // MARK: Восемь лишних строк

    /// Кадр списка — ровно то, что прислал человек.
    func testСписокСобакСВосемьюПустыми() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()

        let заголовок = app.staticTexts["собаки"].firstMatch
        XCTAssertTrue(заголовок.waitForExistence(timeout: 10), "секции «собаки» нет")

        // Проверка, что проверять БЫЛО ЧТО: без неё остальные утверждения
        // зелены на пустом экране и не значат ничего.
        let настоящая = app.staticTexts["Стич"].firstMatch
        XCTAssertTrue(настоящая.waitForExistence(timeout: 10),
                      "настоящей собаки в списке нет — сценарий не тот")

        снять("01-список-восемь-пустых")

        // Строки без клички считаем по подписи веса: «0,0 г» рисует
        // Measurement при нуле, и это единственное, чем пустая строка
        // отличается от разделителя.
        let нули = app.staticTexts.matching(NSPredicate(format: "label CONTAINS '0,0'")).count
        XCTAssertGreaterThan(нули, 0,
                             "пустых строк на экране не видно — проверять нечего")
    }

    /// Дорога наружу. Подпись под списком обещает: «Удалить собаку можно
    /// в её профиле, внизу». У строки без клички эта дорога либо есть,
    /// либо обещание ложное — третьего нет.
    ///
    /// **РОЖДЁН КРАСНЫМ 07.10.2026, и это не поломка оснастки.** Он падает
    /// на живом дефекте: `DogEditorScreen` не вызывается с собакой ни разу
    /// (`grep 'DogEditorScreen(dog'` → 0), значит `isNew` всегда истинно
    /// и блок удаления не рисуется никогда. Позеленеет он тогда, когда
    /// у собаки появится достижимая дорога к удалению, — и до тех пор
    /// он и есть приёмка. Красный здесь называет находку числом, как
    /// `SpacingGridTests` с пятью примитивами вне сетки.
    func testИзПустойСтрокиЕстьДорогаНаружу() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()
        XCTAssertTrue(app.staticTexts["Стич"].firstMatch.waitForExistence(timeout: 15),
                      "список не построился")

        let пустая = app.staticTexts.matching(NSPredicate(format: "label CONTAINS '0,0'")).firstMatch
        XCTAssertTrue(пустая.waitForExistence(timeout: 5), "пустой строки нет")
        пустая.tap()

        снять("02-профиль-безымянной")

        // Ищем именно удаление, а не «какой-нибудь экран открылся»:
        // открывшийся профиль без выхода — тот же тупик, что и ненажимаемая
        // строка, только дороже, потому что выглядит рабочим.
        let удалить = app.descendants(matching: .any)
            .matching(NSPredicate(format: "label CONTAINS[c] 'Удалить'")).firstMatch
        var нашлось = удалить.waitForExistence(timeout: 3)
        for _ in 0..<6 where !нашлось {
            app.swipeUp()
            нашлось = удалить.exists
        }
        снять("03-низ-профиля-безымянной")
        XCTAssertTrue(нашлось,
                      "подпись под списком обещает удаление в профиле, внизу — а его там нет")
    }

    // MARK: Пропавшая кличка у живой собаки

    /// Самое дорогое из двух: у собаки со всем дневником пропало имя.
    func testУЖивойСобакиСтёртаКличка() {
        запустить(сценарий: "wipedName")

        // Вкладка собаки подписана её кличкой. Пустая кличка — вкладка
        // без подписи, и это первое, что человек увидит, ещё не дойдя
        // до настроек.
        снять("04-главный-кличка-стёрта")

        открытьНастройки()
        XCTAssertTrue(app.staticTexts["собака"].firstMatch.waitForExistence(timeout: 15)
                      || app.staticTexts["собаки"].firstMatch.exists,
                      "секции собаки нет")
        снять("05-список-кличка-стёрта")

        XCTAssertFalse(app.staticTexts["Стич"].firstMatch.exists,
                       "кличка на месте — сценарий не воспроизвёл стирание")
    }
}
