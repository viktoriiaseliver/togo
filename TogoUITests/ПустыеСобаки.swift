import XCTest

/// Отзыв TestFlight 06.10.2026, сборка 271: «Много пустых собак».
///
/// **Что эти тесты делают и чего НЕ делают.** Они снимают кадры состояния,
/// построенного сценарием (`emptyDogs`, `wipedName`), и отвечают на вопрос
/// «что человек видит и может ли он из этого выйти». Они **не** отвечают
/// на вопрос «откуда записи берутся»: состояние здесь построено руками,
/// а не приехало обменом. Построить и воспроизвести — разные утверждения,
/// и кадр, снятый с построенного состояния, доказывает только отрисовку.
///
/// Механизм измерен отдельно (`togo-05`): приём записи с пустой кличкой,
/// `SharedDiaryRecords`. Эти тесты — про цену дефекта, а не про причину.
nonisolated final class ПустыеСобакиUITests: XCTestCase {
    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = false
    }

    private func запустить(сценарий: String) {
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", сценарий]
        app.launch()
    }

    private func снять(_ имя: String) {
        // Кадр берётся у ОКНА приложения, а не у экрана симулятора:
        // экран принадлежит симулятору, окно — приложению, и на общей
        // машине это разные вещи.
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Своя обёртка без аргумента — чтобы не трогать тринадцать мест
    /// вызова. Дорогу держит общий `открытьНастройки(в:)`.
    ///
    /// **Частная копия, стоявшая здесь, ЗАТЕНЯЛА общий помощник**
    /// и жала кнопку «Настройки» напрямую — её нет с 22.10. Отказ
    /// звучал «не дождались главного экрана — состояние
    /// не построилось», то есть обвинял фикстуру данных.
    ///
    /// > **Своя копия помощника не стареет вместе с общим.** Она
    /// > и выглядит как помощник, и имя у неё то же — поэтому
    /// > починка общего мимо неё проходит молча.
    private func открытьНастройки() {
        XCTAssertTrue(открытьНастройки(в: app),
                      "в настройки не попасть — дорога, а не состояние")
    }

    /// Доехать до раздела собак в настройках и вернуть, вышло ли.
    ///
    /// **Раздел лежит ниже сгиба** — после переделки «Кино» над ним
    /// стоят «подписка», «как выглядит» и «что прерывает». Без
    /// прокрутки `exists` отвечает «нет», и отказ звучит «секции
    /// собаки нет» — то есть **утверждение о продукте вместо
    /// утверждения о положении экрана**.
    ///
    /// Замер 26.10.2026: прокрутку завели в
    /// `testПустыеЗаписиЗаведеныИНеВидныНиОдна` и **не завели
    /// в `testУЖивойСобакиСтёртаКличка`**, хотя дорога у них общая.
    /// Второй падал с «секции собаки нет» при живом разделе — он есть
    /// на кадре `настройки-одна-строка-пустые-скрыты.png` того же
    /// прогона.
    ///
    /// > **Починка, положенная в один тест, до соседнего не доезжает
    /// > сама.** Этот набор лечили тем же способом 22.10 — частная
    /// > копия `открытьНастройки()` затеняла общий помощник, — и
    /// > сегодня та же болезнь вернулась копией дороги, а не копией
    /// > помощника.
    ///
    /// Поэтому путь лежит здесь один, а не двумя списками свайпов.
    /// # Направление прокрутки — часть замера, а не мелочь
    ///
    /// Замер 26.10.2026, второй заход. Первая редакция крутила только
    /// `swipeUp` — это верно, когда раздел НИЖЕ, и ровно неверно
    /// при возврате: к переписи экран уезжает вниз, и каждый `swipeUp`
    /// уводит его **дальше** от раздела. Отказ при этом звучал
    /// «к разделу собак не вернуться» — то есть опять про продукт,
    /// хотя речь о стороне, в которую крутили.
    ///
    /// > **Ошибка знака неотличима от отсутствия предмета:** обе дают
    /// > «не нашли после восьми махов».
    ///
    /// Поэтому стороны пробуются обе и начиная с той, что ближе
    /// к текущему положению: сперва вниз (возврат), потом вверх (первый
    /// проход). `найти(_:в:)` здесь не годится — он требует
    /// `isHittable`, а заголовок секции не интерактивен и hittable
    /// не бывает.
    @discardableResult
    private func дойтиДоРазделаСобак() -> Bool {
        let заголовок = app.staticTexts["собака"].firstMatch
        let заголовокМн = app.staticTexts["собаки"].firstMatch
        var виден: Bool { заголовок.exists || заголовокМн.exists }

        _ = заголовок.waitForExistence(timeout: 15)
        if виден { return true }

        for _ in 0..<8 where !виден { app.swipeDown() }
        for _ in 0..<8 where !виден { app.swipeUp() }
        return виден
    }

    // MARK: Восемь лишних строк

    /// Приёмка решения Виктории от 07.10.2026: пустые записи
    /// **не удаляем, а не показываем** (`2e1edf7`, `Dog.canBeShown`).
    ///
    /// **Утверждение этого теста перевернулось в тот же день, и это
    /// не ошибка, а смена предмета.** Утром он требовал, чтобы восемь
    /// пустых строк БЫЛО видно: тогда он описывал цену дефекта — ровно
    /// то, что человек прислал кадром. Теперь он требует, чтобы их
    /// не было видно ни одной.
    ///
    /// Переписан он, а не заведён второй, нарочно. Второй оставил бы
    /// в наборе утверждение «восемь строк видны» — верное вчера
    /// и ложное сегодня, и завтрашняя сессия чинила бы по нему
    /// несуществующий дефект.
    ///
    /// **Обе половины обязательны.** «Пустых строк не видно» истинно
    /// и у экрана, где не видно ничего: сперва доказываем, что
    /// настоящая собака на месте, и только потом — что пустых нет.
    func testПустыеЗаписиЗаведеныИНеВидныНиОдна() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()

        // Раздел ниже сгиба — дорога в `дойтиДоРазделаСобак()`, одна
        // на оба теста. Копия этого списка свайпов стояла здесь
        // и **не стояла** в `testУЖивойСобакиСтёртаКличка`, отчего тот
        // падал с «секции собаки нет» при живом разделе.
        XCTAssertTrue(дойтиДоРазделаСобак(), """
            секции собаки нет даже после восьми махов. Строки «собака» \
            и «собаки» в `SettingsScreen` ЕСТЬ — значит либо раздел \
            закрыт условием, либо до настроек мы не дошли.
            """)

        // Половина первая: проверять БЫЛО ЧТО. Через `найти(_:в:)`,
        // потому что он прокручивает, — секция уходит под сгиб.
        let настоящая = найти("Стич", в: app)
        XCTAssertTrue(настоящая.waitForExistence(timeout: 10),
                      "настоящей собаки в списке нет — сценарий не тот")

        снять("01-список-пустые-скрыты")

        // **Контроль: записи ЗАВЕДЕНЫ.** Без него «ни одной пустой
        // строки не видно» зелено и на пустой базе — тест прошёл бы,
        // не проверив ничего. Ровно наш приём с `devicectl`: прежде
        // чем докладывать «ничего нет», снять копию заведомо
        // существующего пути.
        //
        // Читаем отладочный список: он берёт `name` сырым
        // (`CloudKitSchemaWarmup:204`) и потому видит скрытые —
        // у безымянной выходит «» вместо клички. Это единственное
        // место в приложении, которое показывает то, что от человека
        // спрятано, и ровно поэтому оно здесь годится.
        let переписьКнопка = найти("Отладка · что лежит у каждой собаки", в: app)
        XCTAssertTrue(переписьКнопка.waitForExistence(timeout: 10), """
            нет отладочной кнопки переписи собак — проверить, что \
            восемь записей заведены, нечем, и утверждение «их не видно» \
            ничего не значит
            """)
        переписьКнопка.tap()

        var перепись = app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS[c] %@", "заведена")).firstMatch
        for _ in 0..<6 where !перепись.exists {
            app.swipeUp()
            перепись = app.staticTexts
                .matching(NSPredicate(format: "label CONTAINS[c] %@", "заведена")).firstMatch
        }
        XCTAssertTrue(перепись.exists, """
            перепись не напечаталась. Это не «записей нет» — это нечем \
            посмотреть: без неё утверждение «пустых не видно» зелено \
            и на пустой базе.
            """)
        let безымянных = перепись.label.components(separatedBy: "«»").count - 1
        XCTAssertEqual(безымянных, 8, """
            в хранилище \(безымянных) безымянных записей вместо восьми. \
            Сценарий `emptyDogs` кладёт ровно восемь (`SeedData`); \
            другое число значит, что проверять было нечего — либо \
            сценарий не тот, либо записи всё-таки удаляются, а решение \
            07.10 было их СОХРАНИТЬ и не показывать.

            Перепись: \(перепись.label.prefix(600))
            """)

        // Половина вторая: строк собак ровно столько, сколько НАЗВАННЫХ
        // собак в переписи.
        //
        // # Ось переставлена 25.10.2026, и прежняя была прокси
        //
        // Раньше здесь стояло «ни одной подписи, содержащей „0,0"»:
        // пустую строку узнавали по весу, потому что `Fmt.weight(0)`
        // печатал «0,0 г» — `Measurement` с `usage: .personWeight`
        // сама меняет единицу на граммы.
        //
        // **Это гасилось починкой форматтера, и гасилось бы тихо.**
        // Поставь на нуле прочерк — строк с «0,0» не станет
        // НЕЗАВИСИМО от того, показываются пустые записи или нет,
        // и сторож зеленел бы навсегда, перестав видеть предмет.
        // Форматтер чинится тем же коммитом, что эта правка, —
        // значит окна, в котором сторож зелен по прокси, не было.
        //
        // Новая ось — сама строка: `accessibilityIdentifier`
        // у `LabeledContent` в `SettingsScreen.dogSection`. Он не
        // зависит ни от подписи, ни от формата числа, ни от языка.
        //
        // Ожидаемое берётся ИЗ ПЕРЕПИСИ, а не числом здесь: перепись
        // уже прочитана выше и знает, сколько записей названных.
        // Копия числа в тесте однажды отстанет от сценария.
        let названных = перепись.label.components(separatedBy: "заведена").count - 1 - безымянных

        // **ВЕРНУТЬСЯ К РАЗДЕЛУ ПРЕЖДЕ, ЧЕМ СЧИТАТЬ** (замер 26.10.2026).
        //
        // Дорога к переписи крутит экран вниз до шести раз, а `List`
        // отдаёт в дерево доступности ТОЛЬКО отрисованные ячейки.
        // Считать отсюда — значит мерить не раздел, а то место, куда
        // уехал экран:
        //
        // ```
        // счёт сразу после переписи   0 строк   ОТКАЗ при здоровом продукте
        // кадр того же прогона        1 строка «Стич · 4,1 кг»
        // ```
        //
        // Кадр `Дизайн/кадры-приёмки/онбординг-26.10/настройки-одна-строка-пустые-скрыты.png`
        // снят этим же заходом и показывает раздел целиком: одна
        // названная, восьми безымянных нет ни одной. То есть решение
        // 07.10 работало, а краснел крючок.
        //
        // > **Ось была переставлена с прокси на предмет верно — ослепло
        // > МЕСТО замера, а не его ось.** Снаружи это неотличимо
        // > от «пустые показались»: оба дают расхождение с переписью.
        //
        // `найти(_:в:)` крутит в обе стороны и сам решает направление —
        // поэтому возврат и не написан свайпами руками.
        XCTAssertTrue(дойтиДоРазделаСобак(), """
            к разделу собак не вернуться после переписи — считать \
            строки неоткуда. Это дорога, а не состояние.
            """)

        // Граница счёта названа здесь, а не подразумевается: считаются
        // ОТРИСОВАННЫЕ строки. Для сценария `emptyDogs` с одной
        // названной собакой этого довольно; вырастет число названных
        // сверх экрана — счёт придётся собирать прокруткой, и тогда
        // этот тест обязан покраснеть, а не промолчать.
        let строк = app.descendants(matching: .any)
            .matching(identifier: "настройки-строка-собаки").count
        XCTAssertEqual(строк, названных, """
            строк собак видно \(строк) при \(названных) названных \
            в переписи и \(безымянных) безымянных. Решение 07.10 — \
            пустые не показывать: записи остаются в хранилище (человек \
            не терял ничего), но человек их не видит и они не могут \
            стать активными.

            Если \(строк) == 0 при \(названных) > 0 — это НЕ «фильтр \
            работает»: это «крючка нет в дереве», то есть сторож \
            не нашёл бы и настоящую строку. Половина первая выше \
            («Стич» на экране) отвечает именно на это и обязана быть \
            зелёной рядом.
            """)

        // Заголовок секции: при восьми скрытых он обязан стать
        // единственным числом — «собака», а не «собаки». Число
        // в заголовке считается по ТОМУ ЖЕ списку, что рисует строки,
        // иначе фильтр сядет на одну поверхность из двух.
        XCTAssertFalse(app.staticTexts["собаки"].firstMatch.exists, """
            заголовок секции стоит во множественном числе при одной \
            видимой собаке — значит число считается не по тому списку, \
            по которому рисуются строки. Фильтр сел на одну поверхность \
            из двух.
            """)
    }

    /// Дорога наружу. Подпись под списком обещает: «Удалить собаку можно
    /// в её профиле, внизу» — и это обещание либо выполнимо, либо ложно,
    /// третьего нет.
    ///
    /// **Рождён красным 07.10.2026 утром, позеленел в тот же день —
    /// и запись правится, а не остаётся как была.** Утром
    /// `DogEditorScreen` не вызывался с собакой ни разу
    /// (`grep 'DogEditorScreen(dog'` → 0): `isNew` всегда истинно,
    /// блок удаления не рисовался никогда, и обещание
    /// `SettingsScreen:217` было ложным для КАЖДОЙ собаки, не только
    /// безымянной. Дорогу завели в `ProfileScreen:231`.
    ///
    /// Запись правится потому, что иначе она станет преданием: через
    /// неделю «РОЖДЁН КРАСНЫМ» прочтут как живой дефект, а он починен.
    /// Комментарий о дефекте врёт в обе стороны ровно так же, как
    /// комментарий о починке.
    ///
    /// **Зелёный проверен на причину, а не принят на веру.** Он мог
    /// прийти от того, что убрали само обещание, — обещание на месте.
    /// И он чуть не пришёл слишком дёшево: дорога подписана
    /// «Прав**ить и удалить**», а поиск шёл подстрокой `CONTAINS
    /// 'Удалить'` — ссылка ловилась вместо кнопки. Теперь дорога
    /// проходится целиком, до самой кнопки.
    func testОбещаниеУдаленияВыполнимо() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()
        let строка = найти("Стич", в: app)
        XCTAssertTrue(строка.waitForExistence(timeout: 15), "список не построился")

        // **Имя теста и его предмет сменились вместе, и это важно.**
        // Утром он шёл от БЕЗЫМЯННОЙ строки: тогда их было видно восемь,
        // и вопрос стоял «может ли человек убрать вот эту». После
        // решения 07.10 безымянных в списке нет вовсе, и такой путь
        // недостижим — тест падал бы на «пустой строки нет», то есть
        // на отсутствии предмета, а не на дефекте.
        //
        // Предмет остался тот же и был им всегда: подпись под списком
        // обещает «Удалить собаку можно в её профиле, внизу» — и утром
        // это было ложью для КАЖДОЙ собаки, не только безымянной
        // (`DogEditorScreen(dog` → 0 вхождений). Поэтому путь идёт
        // через настоящую запись, а имя теста переписано: имя теста —
        // утверждение о поведении, и стареет оно молча.
        строка.tap()

        снять("02-профиль-собаки")

        // **Подстрокой здесь искать нельзя, и это стоило бы ложного
        // зелёного.** Дорога в редактор подписана «Править и удалить»,
        // и `label CONTAINS 'Удалить'` ловит ЕЁ: тест позеленел бы
        // на ссылке, ни разу не дойдя до самой кнопки удаления. Тот же
        // класс, что `hasPrefix("struct Swatch")` у Gamut, который
        // месяцами находил `SwatchRow`.
        //
        // Поэтому дорога проходится целиком: профиль → редактор →
        // кнопка → подтверждение. Приёмка дороги — не существование
        // ссылки, а то, что по ней можно дойти.
        let вРедактор = найти("Править и удалить", в: app)
        XCTAssertTrue(вРедактор.waitForExistence(timeout: 5), """
            из профиля нет дороги в редактор, а подпись под списком \
            обещает «Удалить собаку можно в её профиле, внизу»
            """)
        вРедактор.tap()

        let кнопка = app.buttons["Удалить собаку"].firstMatch
        var нашлась = кнопка.waitForExistence(timeout: 5)
        for _ in 0..<6 where !нашлась {
            app.swipeUp()
            нашлась = кнопка.exists
        }
        снять("03-низ-редактора-безымянной")
        XCTAssertTrue(нашлась, "в редакторе нет кнопки «Удалить собаку» — обещание всё ещё ложно")
    }

    /// Подтверждение обязано назвать цену, а не спросить «точно?».
    ///
    /// У `Dog` одиннадцать связей с `.cascade`: удаление уносит весь
    /// дневник — отметки, взвешивания, уход, схемы лечения с дозами,
    /// занятия, поездки, документы, выезды, течки, запас корма.
    /// Вопрос «Удалить собаку?» без этого — сообщение, покрывающее
    /// несколько исходов одним текстом: человек отвечает «да» на один
    /// вопрос, а соглашается на другой.
    ///
    /// Проверяется **числом видов, а не формулировкой**: тексты
    /// заморожены 07.10 до правки дизайна, и шлифовать здесь нечего.
    /// Сверять надо, что цена названа, а не как она названа.
    func testПодтверждениеУдаленияНазываетЦену() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()
        XCTAssertTrue(найти("Стич", в: app).waitForExistence(timeout: 15),
                      "список не построился")
        найти("Стич", в: app).tap()

        let вРедактор = найти("Править и удалить", в: app)
        XCTAssertTrue(вРедактор.waitForExistence(timeout: 5), "нет дороги в редактор")
        вРедактор.tap()

        let кнопка = app.buttons["Удалить собаку"].firstMatch
        var нашлась = кнопка.waitForExistence(timeout: 5)
        for _ in 0..<6 where !нашлась {
            app.swipeUp()
            нашлась = кнопка.exists
        }
        XCTAssertTrue(нашлась, "нет кнопки удаления")
        кнопка.tap()

        // Системный лист подтверждения. Кадр снимается ДО отмены:
        // между ним и отменой не должно успеть вклиниться ничто.
        let лист = app.sheets.firstMatch
        XCTAssertTrue(лист.waitForExistence(timeout: 5), "подтверждение не появилось")
        снять("06-подтверждение-удаления")

        // Замыкание, а не `map(\.label)`: класс `nonisolated`,
        // а `label` изолирован главным актором — ключевой путь
        // к нему не строится.
        let текст = лист.descendants(matching: .staticText)
            .allElementsBoundByIndex.map { $0.label }.joined(separator: " ")
        let кнопки = лист.descendants(matching: .button)
            .allElementsBoundByIndex.map { $0.label }

        // Состав листа ЗАМЕРЕН и приложен, а не пересказан. Иначе
        // утверждение «кнопки нет» опирается на то, что я разглядела
        // на кадре, — а кадр показывает, что нарисовано, и молчит
        // о том, чего не нарисовано, но объявлено.
        // Полное дерево листа, а не только кнопки.
        //
        // **Четыре клетки замера 07.10 совпали все четыре** — наш экран
        // и контрольный, iOS 27.0 и 26.5, везде ровно одна кнопка.
        // Ровный край диапазона по нашему правилу сперва подозревает
        // инструмент, а не мир: «ничего не сошлось» подозрительно так же,
        // как «всё сошлось». Запрос по `.button` мог просто не видеть
        // системную отмену — поэтому спрашиваем поддерево целиком
        // и кладём его в прогон как есть.
        let опись = XCTAttachment(string: """
            кнопки листа: \(кнопки)

            текст: \(текст)

            ПОЛНОЕ ДЕРЕВО ЛИСТА (контроль инструмента):
            \(лист.debugDescription)
            """)
        опись.name = "06-состав-листа-подтверждения"
        опись.lifetime = .keepAlways
        add(опись)

        XCTAssertTrue(текст.contains("одиннадцать") || текст.contains("11"), """
            подтверждение не называет цену числом. Текст листа: «\(текст)». \
            У Dog одиннадцать каскадов, и человек должен знать, на что \
            соглашается, а не отвечать «да» на «точно?».
            """)

        // **У необратимого действия обязан быть видимый выход.**
        // `Button("Отмена", role: .cancel)` в коде объявлена
        // (`Editors.swift:69`) — проверяем не объявление, а то, что
        // человек её видит: имя упомянуто ≠ от упоминания что-то
        // происходит. Запрет формулируется так, чтобы нарисованная
        // одна-единственная «Удалить» его нарушала.
        // **Отдельный замер: произносим ли выход.**
        //
        // Тап мимо пузыря невидим — это видно на кадре. Но он ещё
        // и непроизносим, если в дереве доступности нет ни кнопки
        // закрытия, ни действия отмены: человеку с VoiceOver «закрой,
        // нажав мимо» не объявляет никто. Тогда у необратимого
        // действия нет выхода не только видимого, но и доступного,
        // а это уже не вид, а доступность.
        //
        // Здесь ничего не утверждается — только прикладывается замер.
        // Пустой результат тут так же ценен, как находка.
        let всеЭлементы = лист.descendants(matching: .any)
            .allElementsBoundByIndex.prefix(40)
            .map { "\($0.elementType.rawValue) «\($0.label)» id=\($0.identifier)" }
        let доступ = XCTAttachment(string: """
            ДОСТУПНОСТЬ ЛИСТА — есть ли произносимый выход
            кнопок: \(кнопки)
            элементов поддерева (до 40):
            \(всеЭлементы.joined(separator: "\n"))
            """)
        доступ.name = "08-доступность-листа"
        доступ.lifetime = .keepAlways
        add(доступ)

        // Дерево печатается ПРЯМО В СООБЩЕНИИ, а не вложением: вложение
        // живёт в `.xcresult`, а он 07.10 дважды не достроился, и замер
        // оказался недостижим при живом прогоне. Сообщение проверки
        // доезжает до лога всегда.
        // **ОБЛАСТЬ ПОИСКА РАСШИРЕНА ДО ПРИЛОЖЕНИЯ** (замер 26.10.2026).
        // Прежде отмена искалась в поддереве `app.sheets.firstMatch`,
        // и замер дал `["Удалить"]` — вывод «у необратимого действия
        // нет выхода» был бы **о продукте**, а кнопка есть в коде
        // (`Editors.swift:244`, `Button("Отмена", role: .cancel)`).
        //
        // У `confirmationDialog` отмена рисуется ОТДЕЛЬНОЙ группой
        // и в поддерево листа не попадает. Человек её видит.
        //
        // > **Сузив область поиска, легко получить вывод о мире.**
        // > Здесь он был бы страшным и ложным разом: «необратимое
        // > действие без выхода» — ровно та находка, ради которой
        // > тест и писался, и потому её не стали бы перепроверять.
        let отменаВезде = app.buttons.matching(
            NSPredicate(format: "label CONTAINS[c] %@", "Отмена")).count > 0
        XCTAssertTrue(кнопки.contains(where: { $0.localizedCaseInsensitiveContains("Отмена") })
                      || отменаВезде, """
            в подтверждении удаления нет видимой кнопки отмены \
            НИ В ЛИСТЕ, НИ ВО ВСЁМ ДЕРЕВЕ. \
            Замер листа: \(кнопки). Единственный выход — тап мимо \
            пузыря, и его не видно: человек стоит перед необратимым \
            действием, у которого нарисована только кнопка «Удалить».

            ДЕРЕВО ЛИСТА, чтобы отличить «кнопки нет» от «запрос её не видит»:
            \(лист.debugDescription.prefix(1500))
            """)

        // Уходим НЕ нажимая «Удалить»: тест не удаляет ничего.
        // Тап мимо листа работает независимо от того, есть ли кнопка, —
        // значит уборка за собой не зависит от предмета проверки.
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.95)).tap()
    }

    /// **Контроль к находке про отмену — не про собак, а про инструмент.**
    ///
    /// Утверждение «в листе нет кнопки отмены» имеет две причины,
    /// снаружи неразличимые: отмены правда нет — или мой запрос
    /// её не видит. Это ровно наш приём с `devicectl`: прежде чем
    /// докладывать «данных нет», снять контрольную копию заведомо
    /// существующего пути. Приехала — инструмент цел, и «ноль» говорит
    /// о мире; не приехала — «ноль» говорит об инструменте.
    ///
    /// Контрольный путь — второй такой же `confirmationDialog`
    /// в проекте (`DataPrivacyScreen:73`, «Удалить все данные?»).
    /// Код у них одинаков до символа, различается только текст.
    ///
    /// ```
    /// обе дали ["Удалить…"]        причина НЕ в экране собаки: либо
    ///                              запрос не видит системную отмену,
    ///                              либо её нет во всём приложении
    /// наша без отмены, эта с ней   причина локальная
    /// ```
    ///
    /// **Рантайм — часть замера, а не фон.** Отзыв пришёл с iOS 27.0.1;
    /// `Togo-02` держит 27.0, `Togo-1b` — 26.5. Один и тот же тест
    /// на двух рантаймах закрывает вторую ось. Поэтому он НИЧЕГО
    /// не утверждает про отмену, а только прикладывает замер: вывод
    /// делается по четырём клеткам сразу, а не по одной.
    func testКонтрольСоставЛистаНаДругомЭкране() {
        запустить(сценарий: "emptyDogs")
        открытьНастройки()

        let вход = найти("Данные и приватность", в: app)
        XCTAssertTrue(вход.waitForExistence(timeout: 15), "не нашли «Данные и приватность»")
        вход.tap()

        let кнопка = app.buttons["Удалить все данные"].firstMatch
        var нашлась = кнопка.waitForExistence(timeout: 5)
        for _ in 0..<6 where !нашлась {
            app.swipeUp()
            нашлась = кнопка.exists
        }
        XCTAssertTrue(нашлась, "на контрольном экране нет кнопки — контроль не состоялся")
        кнопка.tap()

        let лист = app.sheets.firstMatch
        XCTAssertTrue(лист.waitForExistence(timeout: 5), "контрольное подтверждение не появилось")
        снять("07-контроль-подтверждение-данных")

        let кнопки = лист.descendants(matching: .button)
            .allElementsBoundByIndex.map { $0.label }
        let опись = XCTAttachment(string: """
            КОНТРОЛЬ · DataPrivacyScreen «Удалить все данные?»
            кнопки листа: \(кнопки)
            """)
        опись.name = "07-состав-контрольного-листа"
        опись.lifetime = .keepAlways
        add(опись)

        // Утверждается только то, что контроль СОСТОЯЛСЯ: лист открылся
        // и в нём хоть что-то нашлось. Есть ли там отмена — это замер,
        // а не требование, и читается он рядом с замером нашего листа.
        XCTAssertFalse(кнопки.isEmpty, """
            в контрольном листе не нашлось ни одной кнопки. Тогда «ноль» \
            говорит об инструменте, а не о мире, и находка про отмену \
            на экране собаки не доказана.
            """)

        app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.95)).tap()
    }

