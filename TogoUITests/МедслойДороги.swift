import XCTest

/// Дороги стенда к визитам, диагнозам и назначениям.
///
/// **Повод тот же, что у `Анализы.swift`, и он измерен.** 08.10.2026
/// три новых экрана уехали в git принятыми **компилятором и прогоном**:
/// место вызова есть, сторож зелёный, формы собираются. Расстановку
/// и слова на них не видел никто, и снять было нечем — UI-тестов,
/// проходящих по этим дорогам, ноль.
///
/// > **Три новых экрана без кадра — это три поверхности, про которые
/// > завтра будут думать, что они приняты.** Зелёный сторож на вызов
/// > этому способствует: он говорит «дорога есть» и молчит о том,
/// > что по ней видно.
///
/// Файл ничего не утверждает про цвет и расстановку — он доводит
/// приложение до состояний и кладёт кадры файлами. Судит человек.
///
/// Приёмка каждой дороги двойная: кадр показывает ПОКАЗ, а проверка
/// «запись появилась в списке» — что форма дошла до хранилища. Второго
/// кадр не видит: три шага или одна шторка могут собрать черновик
/// и не позвать `context.insert`.
nonisolated final class МедслойДороги: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-медслоя")
    }

    /// Суффикс партии приходит СНАРУЖИ и только с приставкой
    /// `TEST_RUNNER_` — `xcodebuild` своё окружение процессу теста
    /// не передаёт. Замерено на `Анализы.swift`: без приставки прогон
    /// проходит, кадры снимаются и **имена у них без суффикса**, то есть
    /// вторая партия перезаписывает первую молча.
    ///
    ///     TEST_RUNNER_KADR_SUFFIX=light xcodebuild … -only-testing:TogoUITests/МедслойДороги
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Иначе «снято всё» и «упал на третьем» выглядят
        // в логе ОДИНАКОВО: во втором случае строк `КАДР:` просто
        // меньше, а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своей проверкой, а не эта печать.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    /// Кадр файлом, не вложением: выгрузка вложений у нас не сработала
    /// пять раз из девяти. Отказ записи НЕ роняет тест — кадр это улика,
    /// а не ворота.
    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "amber"]
        app.launch()
    }

    /// Элемент НА ЭКРАНЕ, а не просто «существует».
    ///
    /// **Повод — поправка тестировщика 08.10.2026, и она про мою
    /// оснастку.** Кадр `32-назначение-окно-контроля` в его прогоне
    /// не содержал окна контроля: блок остался ниже сгиба, `exists`
    /// вернул `true`, кадр снялся и получил имя, утверждающее
    /// содержание.
    ///
    /// > **Имя кадра утверждает содержание, а содержание зависит
    /// > от позиции прокрутки в конкретном прогоне.** Это тот же класс,
    /// > что ярлык темы в строке вывода: имя печатается ДО съёмки
    /// > и не ломается, что бы на кадре ни оказалось.
    ///
    /// `exists` отвечает «в дереве доступности есть», `isHittable` —
    /// «можно коснуться» (и у подписи внутри прокрутки врёт). Нужен
    /// третий вопрос: **попадает ли рамка элемента в рамку окна.**
    private func наЭкране(_ элемент: XCUIElement) -> Bool {
        guard элемент.exists else { return false }
        let окно = app.windows.firstMatch.frame
        let рамка = элемент.frame
        guard рамка.height > 0, рамка.width > 0 else { return false }
        return окно.contains(CGPoint(x: рамка.midX, y: рамка.midY))
    }

    /// Есть ли на экране подпись, СОДЕРЖАЩАЯ эту строку.
    ///
    /// Нужен потому, что статус диагноза с 08.10.2026 стоит внутри
    /// составной строки, а не отдельным значением. Точное совпадение
    /// по `staticTexts["…"]` покраснело бы на верном экране — то есть
    /// дало бы ложную находку про продукт из-за формы пробы.
    private func содержит(_ строка: String) -> Bool {
        app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", строка)).firstMatch.exists
    }

    /// Убрать клавиатуру, **не предполагая, что у неё есть Return.**
    ///
    /// **Замер 08.10.2026: у `.decimalPad` клавиши Return НЕТ.** Моя
    /// прежняя проба спрашивала `app.keyboards.element.exists` и тут же
    /// жала `buttons["Return"]` — на числовом поле это падало с
    /// «No matches found for … "Return" IN identifiers», и падало ПОСЛЕ
    /// сорока секунд ввода, то есть съедало весь заход.
    ///
    /// > **Наличие клавиатуры не означает наличия клавиши.** Проба
    /// > спрашивала про одно, а жала другое — и вопрос был верным,
    /// > а вывод из него нет.
    ///
    /// Поэтому: жмём Return, только если он ЕСТЬ; иначе гасим
    /// клавиатуру тапом по заголовку шторки — он всегда на экране
    /// и ничего не меняет.
    private func убратьКлавиатуру() {
        guard app.keyboards.element.exists else { return }
        let ret = app.buttons["Return"].firstMatch
        if ret.exists { ret.tap(); return }
        // Тап по статичному тексту: он не поле и не кнопка действия,
        // то есть не меняет состояние формы.
        //
        // **Спрашиваем `наЭкране`, а не `.exists`** — замер 21.10.2026
        // по иерархии из `.xcresult`: `app.staticTexts.firstMatch`
        // резолвится в ярлык **0×0 у ВЫКЛЮЧЕННОЙ** системной кнопки
        // `dictation` («Диктовать», `Disabled`), и тап по нему падает
        // `Failed to scroll to visible … kAXErrorCannotComplete`
        // после трёх попыток. `.exists` про это не знает: элемент
        // существует, у него просто нет площади.
        //
        // Ветка-запаска отработала здесь **впервые за свою жизнь**:
        // на форме «Анализы» клавиатура `decimalPad`, и кнопки `Return`
        // у неё нет вовсе. Соседний `testДорогаКНазначениямСнята` зовёт
        // эту же функцию и уходит в первую ветку — поэтому он зелен.
        // Тест, поля и эта ветка родились одним коммитом `b742fba`
        // (08.10), то есть тест не проходил НИ РАЗУ: это не регрессия.
        //
        // > Вторую половину инструмента гонять на живых данных прежде,
        // > чем считать её готовой. Здесь она пролежала непрогнанной
        // > тринадцать дней.
        let нейтральное = app.staticTexts.firstMatch
        if наЭкране(нейтральное) { нейтральное.tap() }
    }

    private func докрутить(до элемент: XCUIElement, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if элемент.exists && элемент.isHittable { return true }
            app.swipeUp()
        }
        return элемент.exists && элемент.isHittable
    }

    /// Дойти до раздела «Здоровья» по имени строки.
    /// Возвращает, дошли ли, — но кадр снимается у вызывающего ДО
    /// суждения, иначе при падении кадра не будет вовсе.
    /// **Предусловие — панель вкладок, а не кличка на «Сегодня»** —
    /// замер 21.10.2026. Здесь стояло
    /// `app.staticTexts["Стич"].waitForExistence(timeout: 20)`,
    /// и это верно только на главном экране: хвост цикла оставляет
    /// приложение на «Здоровье», где «Стич» существует **лишь как
    /// кнопка таб-бара** (`Button identifier: 'pawprint'`), а не как
    /// текст. Второй заход в «Анализы» ждал его двадцать секунд
    /// впустую — при том, что сама строка «Анализы, 1 запись» была
    /// на экране.
    ///
    /// Тест и этот помощник родились одним коммитом `b742fba` (08.10),
    /// то есть второй заход не проходил **тринадцать дней**.
    ///
    /// И подпись строки составная: `«Анализы, 1 запись»` — поиск идёт
    /// по началу, иначе точное совпадение промахнётся ровно после того,
    /// как в разделе появится первая запись. Тот же класс, что
    /// у кнопки просмотра онбординга.
    private func открытьРаздел(_ имя: String) -> Bool {
        let вкладка = app.tabBars.buttons["Здоровье"]
        guard вкладка.waitForExistence(timeout: 20) else { return false }
        вкладка.tap()
        _ = app.navigationBars["Здоровье"].waitForExistence(timeout: 10)
        let строка = app.buttons
            .matching(NSPredicate(format: "label BEGINSWITH %@", имя))
            .firstMatch
        guard докрутить(до: строка) else { return false }
        строка.tap()
        return app.navigationBars[имя].waitForExistence(timeout: 10)
    }

    // MARK: Визиты

    func testДорогаКВизитамСнята() throws {
        let открылось = открытьРаздел("Визиты к врачу")
        снять("10-визиты-список")
        XCTAssertTrue(открылось, """
            до «Визитов к врачу» не дошли. Кадр 10 снят ДО этой проверки —
            на нём видно, где остановились: на «Здоровье» без строки
            или на экране, который не открылся.
            """)

        let добавить = app.buttons["Добавить визит"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 10),
                      "кнопки «Добавить визит» нет — ввод недостижим")
        добавить.tap()

        let врач = app.textFields["Врач"].firstMatch
        let формаОткрылась = врач.waitForExistence(timeout: 10)
        if формаОткрылась {
            врач.tap()
            врач.typeText("Кочубина")
        }
        снять("11-визит-форма")
        XCTAssertTrue(формаОткрылась, "форма визита не открылась — смотри кадр 11")

        app.buttons["Добавить"].firstMatch.tap()

        let вернулись = app.navigationBars["Визиты к врачу"].waitForExistence(timeout: 10)
        let появился = app.staticTexts["Кочубина"].firstMatch.waitForExistence(timeout: 10)
            || app.staticTexts.containing(NSPredicate(format: "label CONTAINS 'Кочубина'")).firstMatch.exists
        снять("12-визиты-список-с-записью")
        XCTAssertTrue(вернулись, "после сохранения не вернулись к списку")
        XCTAssertTrue(появился, """
            визит не появился в списке. Форма собрала черновик и не дошла
            до хранилища — кадр этого не видит, и сторож на вызов тоже.
            """)
    }

    // MARK: Диагнозы

    func testДорогаКДиагнозамСнята() throws {
        let открылось = открытьРаздел("Диагнозы")
        снять("20-диагнозы-список")
        XCTAssertTrue(открылось, "до «Диагнозов» не дошли — смотри кадр 20")

        let добавить = app.buttons["Добавить диагноз"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 10),
                      "кнопки «Добавить диагноз» нет — ввод недостижим")
        добавить.tap()

        let формулировка = app.textFields["Формулировка"].firstMatch
        let формаОткрылась = формулировка.waitForExistence(timeout: 10)
        if формаОткрылась {
            формулировка.tap()
            формулировка.typeText("гипотиреоз")
        }
        снять("21-диагноз-форма")
        XCTAssertTrue(формаОткрылась, "форма диагноза не открылась — смотри кадр 21")

        app.buttons["Добавить"].firstMatch.tap()

        let вернулись = app.navigationBars["Диагнозы"].waitForExistence(timeout: 10)
        // ПОДСТРОКОЙ, как и статус ниже: строка списка составная
        // («гипотиреоз · рабочая гипотеза»), и точное совпадение
        // по формулировке краснеет на ВЕРНОМ экране.
        //
        // Я завёл `содержит(_:)` ровно против этого класса — и оставил
        // здесь одно точное совпадение, потому что правил строки статуса
        // и не искал остальные пробы в том же тесте. Прогон покраснел
        // сообщением «форма не дошла до хранилища», то есть обвинил
        // продукт в том, что сделала проба.
        //
        // > **Починив класс в одном месте, надо пройти по ВСЕМ местам
        // > того же класса, а не по тем, которые правил.** Иначе
        // > остаток класса докладывает о продукте словами своего
        // > сообщения, и верит ему читатель лога, а не автор пробы.
        let появился = содержит("гипотиреоз")
            || app.staticTexts.containing(
                NSPredicate(format: "label CONTAINS %@", "гипотиреоз")
            ).firstMatch.waitForExistence(timeout: 10)
        снять("22-диагнозы-список-с-записью")
        XCTAssertTrue(вернулись, "после сохранения не вернулись к списку")
        XCTAssertTrue(появился, """
            диагноза нет в списке после сохранения. Прежде чем читать это
            как «форма не дошла до хранилища», посмотри кадр 22: строка
            списка СОСТАВНАЯ, и точное совпадение по формулировке здесь
            покраснело бы на верном экране.
            """)

        // Статус показан СЛОВОМ, а не только значком. Проверяется
        // здесь, а не кадром: цвет и форму судит человек, а наличие
        // слова — машина, и это та половина, которую машина может.
        // Статус ищется ПОДСТРОКОЙ: с 08.10.2026 он стоит в одной
        // строке с формулировкой («гипотиреоз · рабочая гипотеза»),
        // а не отдельным значением справа. Точное совпадение здесь
        // покраснело бы на верном экране.
        // Ищется КОРОТКОЕ слово статуса: с третьей редакции строки
        // список показывает `shortTitle` («гипотеза»), а не полное
        // «рабочая гипотеза». Полное осталось в форме правки, в отчёте
        // врачу и в архиве — там ширина не спорит.
        //
        // Я раньше писал обратное («в списке остаётся полное, там место
        // есть») — и кадр показал, что места НЕТ: из трёх строк вёрстку
        // держала одна. Премисса была ложной, а не вывод из неё.
        XCTAssertTrue(содержит("гипотеза"), """
            статуса диагноза нет СЛОВОМ в списке. Если он передаётся
            только значком или цветом — это дефект доступности:
            глиф для речи то же, что цвет для зрения.
            И значками он НЕ держится: замер 08.10.2026 дал разброс
            чернил 8 % между `checkmark.seal`, `questionmark.circle`
            и `slash.circle`, а у двух из трёх контур — один круг.
            Слово здесь единственный надёжный носитель.
            """)

        // --- и три статуса РАЗОМ, иначе силуэты не сравнить ----------
        //
        // **Поправка тестировщика 08.10.2026, и она не про показ,
        // а про возможность приёмки.** Он не смог ответить на мой же
        // вопрос «различимы ли значки по силуэту»: в списке была ОДНА
        // запись, то есть один значок из трёх.
        //
        // > **Вопрос «различимы ли три знака» нельзя задать кадру,
        // > на котором один знак.** Это не недосмотр съёмки — это
        // > отсутствие состояния, в котором вопрос имеет смысл.
        //
        // Лечится не взглядом, а входом: тест заводит все три статуса
        // и снимает список, где вопрос становится задаваемым.
        for (статус, кличка) in [("подтверждён", "гипотиреоз подтверждён"),
                                 ("снят", "аллергия снята")] {
            let плюс = app.buttons["Добавить диагноз"].firstMatch
            guard плюс.waitForExistence(timeout: 10) else { break }
            плюс.tap()
            let поле = app.textFields["Формулировка"].firstMatch
            guard поле.waitForExistence(timeout: 10) else { break }
            поле.tap()
            поле.typeText(кличка)
            // Сегмент подписан КОРОТКИМ названием (`shortTitle`):
            // «рабочая гипотеза» обрезалась многоточием на стандартном
            // кегле, и это починено тем же коммитом.
            let деление = app.buttons[статус].firstMatch
            if деление.exists { деление.tap() }
            app.buttons["Добавить"].firstMatch.tap()
            _ = app.navigationBars["Диагнозы"].waitForExistence(timeout: 10)
        }

        let всеТри = содержит("гипотеза")
            && содержит("подтверждён")
            && содержит("снят")
        снять("23-диагнозы-три-статуса")
        XCTAssertTrue(всеТри, """
            в списке не все три статуса. Кадр 23 снят ДО этой проверки —
            на нём видно, какие есть. Без трёх разом вопрос
            «различимы ли значки по силуэту» задать НЕЧЕМУ,
            и он останется открытым, а не отвеченным.
            """)
    }

    // MARK: Назначения

    func testДорогаКНазначениямСнята() throws {
        let открылось = открытьРаздел("Назначения")
        снять("30-назначения-список")
        XCTAssertTrue(открылось, "до «Назначений» не дошли — смотри кадр 30")

        let добавить = app.buttons["Добавить назначение"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 10),
                      "кнопки «Добавить назначение» нет — ввод недостижим")
        добавить.tap()

        let препарат = app.textFields["Препарат"].firstMatch
        let формаОткрылась = препарат.waitForExistence(timeout: 10)
        if формаОткрылась {
            препарат.tap()
            препарат.typeText("Левотироксин")
            let номер = app.textFields["Номер"].firstMatch
            if номер.exists {
                номер.tap()
                номер.typeText("8935331")
            }
        }
        снять("31-назначение-форма")
        XCTAssertTrue(формаОткрылась, "форма назначения не открылась — смотри кадр 31")

        // Окно контроля считается и показывается ДО сохранения.
        // Если строки нет — либо срок не выбран по умолчанию, либо
        // `ControlWindow` вернул `nil`, и тогда человек сохранит рецепт
        // без срока, не узнав об этом.
        //
        // **Клавиатуру убираем ПЕРЕД поиском, и ищем по `exists`,
        // а не по `isHittable`.** Первая редакция делала наоборот
        // и дважды сняла кадр «окна-контроля-НЕТ» при живом окне:
        // поднятая клавиатура закрывала нижнюю часть формы, а подпись
        // внутри прокрутки не считается «достижимой», пока не видна.
        //
        // > **Проба, спрашивающая `isHittable` у ПОДПИСИ, отвечает
        // > не про существование, а про видимость в этот момент.**
        // > Для кнопки это верный вопрос, для текста — нет, и ответ
        // > «нет» читается как «в приложении этого нет».
        убратьКлавиатуру()
        let окно = app.staticTexts["Окно контроля"].firstMatch
        var видно = наЭкране(окно)
        for _ in 0..<8 where !видно {
            app.swipeUp()
            видно = наЭкране(окно)
        }
        // Кадр получает имя «окно-контроля» ТОЛЬКО если окно на экране.
        // Иначе имя соврало бы про содержание — а проверка ниже упадёт
        // и назовёт кадр, по которому это видно.
        снять(видно ? "32-назначение-окно-контроля" : "32-назначение-окна-контроля-НЕ-ВИДНО")
        XCTAssertTrue(видно, """
            блок «Окно контроля» не доехал до экрана за восемь прокруток.
            Смотри кадр 32-назначение-окна-контроля-НЕ-ВИДНО: либо блока
            нет вовсе (тогда `ControlWindow.window` вернул nil, и человек
            сохранит рецепт, не увидев дат контроля), либо он ниже сгиба
            и недостижим прокруткой при поднятой клавиатуре.
            Это РАЗНЫЕ беды, и кадр их различает.
            """)
        app.buttons["Добавить"].firstMatch.tap()

        let вернулись = app.navigationBars["Назначения"].waitForExistence(timeout: 10)
        let появилось = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS '8935331'")).firstMatch.waitForExistence(timeout: 10)
        снять("33-назначения-список-с-записью")
        XCTAssertTrue(вернулись, "после сохранения не вернулись к списку")
        XCTAssertTrue(появилось, """
            назначение не появилось в списке. Это не только про показ:
            `ReminderScheduler` берёт напоминания о контроле ИЗ рецептов,
            и незаписанный рецепт означает, что напоминания не будет,
            а человек будет считать, что оно заведено.
            """)
    }

    // MARK: График

    /// **Дорога к графику, и она заводит данные сама — иначе снимать
    /// нечего.**
    ///
    /// Замер 08.10.2026: `-Сценарий amber` не заводит ни одного
    /// `LabResult` (в `SeedData` его нет вовсе). То есть у графика
    /// в любом прогоне было бы пустое состояние, и кадр «График»
    /// показывал бы надпись «Рисовать пока нечего», а не график.
    ///
    /// > **Поверхность, для которой нет данных, непроверяема так же,
    /// > как поверхность, к которой нет дороги.** И лечится тем же —
    /// > переделкой входа, а не взглядом.
    ///
    /// Поэтому тест вводит два анализа одного показателя через ту же
    /// форму, которой пользуется человек: заодно это приёмка того,
    /// что трёхшаговый ввод работает дважды подряд.
    func testДорогаКГрафикуСнята() throws {
        // --- два анализа через форму -----------------------------------
        for (значение, суффиксИмени) in [("14,2", "первый"), ("6,0", "второй")] {
            let открылось = открытьРаздел("Анализы")
            XCTAssertTrue(открылось, "до «Анализов» не дошли (\(суффиксИмени))")

            let добавить = app.buttons["Добавить анализ"].firstMatch
            XCTAssertTrue(добавить.waitForExistence(timeout: 10),
                          "кнопки «Добавить анализ» нет (\(суффиксИмени))")
            добавить.tap()

            // Шаг 1 — бланк. Номер разный, иначе две строки склеятся
            // в один бланк; на графике это неважно, но в списке врало бы.
            let номер = app.textFields["Номер бланка"].firstMatch
            if номер.waitForExistence(timeout: 10) {
                номер.tap()
                номер.typeText(суффиксИмени == "первый" ? "VF1" : "VF2")
            }
            app.buttons["Дальше"].firstMatch.tap()

            // Шаг 2 — показатель ОДИН И ТОТ ЖЕ: график строится
            // по одному показателю, две разные величины рядом
            // не рисуются одной линией.
            let показатель = app.textFields["Показатель"].firstMatch
            XCTAssertTrue(показатель.waitForExistence(timeout: 10),
                          "поля «Показатель» нет (\(суффиксИмени))")
            показатель.tap()
            показатель.typeText("Т4 общий")

            let число = app.textFields["Число"].firstMatch
            if число.exists {
                число.tap()
                число.typeText(значение)
            }
            let единица = app.textFields["Единица"].firstMatch
            if единица.exists {
                единица.tap()
                единица.typeText("нмоль/л")
            }
            // Норма — чтобы на графике была ПОЛОСА, а не только точки.
            let нормаОт = app.textFields["Норма от"].firstMatch
            if нормаОт.exists {
                нормаОт.tap()
                нормаОт.typeText("12,9")
            }
            let нормаДо = app.textFields["Норма до"].firstMatch
            if нормаДо.exists {
                нормаДо.tap()
                нормаДо.typeText("51,5")
            }
            убратьКлавиатуру()
            app.buttons["Дальше"].firstMatch.tap()

            // Кадр ВНУТРИ цикла: прежняя редакция снимала первый кадр
            // только ПОСЛЕ двух заведённых анализов — и когда ввод упал
            // на сороковой секунде, улик не осталось ни одной.
            //
            // > **Кадр после длинной подготовки — это кадр, которого
            // > не будет при падении подготовки.**
            снять("39-ввод-\(суффиксИмени)-шаг3")

            // Шаг 3 — сохраняем без времени: алерт назовёт последствие.
            XCTAssertTrue(app.staticTexts["Забор во сколько?"].waitForExistence(timeout: 10),
                          "третий шаг не открылся (\(суффиксИмени))")
            app.buttons["Сохранить анализ"].firstMatch.tap()
            if app.staticTexts["Сохранить без времени?"].waitForExistence(timeout: 5) {
                app.buttons["Сохранить так"].firstMatch.tap()
            }
            _ = app.navigationBars["Анализы"].waitForExistence(timeout: 10)

            // Назад на «Здоровье», чтобы следующий заход начался оттуда же.
            app.navigationBars.buttons.firstMatch.tap()
            _ = app.navigationBars["Здоровье"].waitForExistence(timeout: 10)
        }

        // --- собственно график ----------------------------------------
        // Поиск по НАЧАЛУ подписи: строки этого раздела составные —
        // соседняя зовётся «Анализы, 1 запись», и точное совпадение
        // промахивается ровно после того, как в разделе появляется
        // первая запись. Третий случай того же класса за день
        // (кнопка просмотра онбординга, строка «Анализы», эта).
        let строкаГрафика = app.buttons
            .matching(NSPredicate(format: "label BEGINSWITH %@", "График показателя"))
            .firstMatch
        let дошли = докрутить(до: строкаГрафика)
        снять("40-здоровье-строка-графика")
        XCTAssertTrue(дошли, """
            на «Здоровье» нет строки «График показателя» даже после
            прокрутки. Кадр 40 снят ДО этой проверки.
            """)
        строкаГрафика.tap()

        let открылся = app.navigationBars["График"].waitForExistence(timeout: 10)
        снять("41-график-две-точки")
        XCTAssertTrue(открылся, "экран графика не открылся — смотри кадр 41")

        // Приёмка: именно ГРАФИК, а не пустое состояние и не «одна точка».
        XCTAssertFalse(содержит("Рисовать пока нечего"), """
            на экране графика пустое состояние при двух заведённых
            анализах. Значит либо анализы не сохранились, либо график
            их не нашёл по показателю.
            """)
        XCTAssertFalse(содержит("Сравнивать пока не с чем"), """
            график говорит «Сравнивать пока не с чем» при двух точках.
            Либо вторая запись не легла, либо показатели разошлись
            по написанию.
            """)
        // Отклонение СЛОВОМ — требование доступности, не украшение:
        // 6,0 при норме 12,9–51,5 обязано быть названо «ниже нормы».
        XCTAssertTrue(содержит("ниже нормы"), """
            отклонения нет СЛОВОМ в таблице под графиком. Направление,
            переданное только положением точки и цветом, не читается
            ни VoiceOver, ни дальтоником.
            """)
    }
