import XCTest

/// Экран общего дневника — **ноль кадров из двухсот четырнадцати**.
///
/// # Чем это отличается от «ещё одного экрана»
///
/// Замер 14.10.2026 по `Дизайн/кадры-приёмки/`: 214 файлов, среди них
/// `today`, `needs-verdict`, `stool`, `training`, `history`, `family`,
/// `paywall` — и ни одного с экраном общего дневника. Ни один
/// UI-тест на него не заходит: `grep` по `TogoUITests/` даёт одно
/// упоминание, и то в доккомментарии про другое.
///
/// А через этот экран проходит **вся дорога второго человека**:
///
/// ```
/// включение обмена        turn(on:) — SharedDiaryScreen:194
/// исход приёма            отказПриёма = НеудачаПриёма.текущая — :66
/// снятие жалобы           НеудачаПриёма.текущая = nil — :203
/// ```
///
/// Здесь же человек читает, **что обменивается, а что нет**, — и
/// решает, включать ли. Эти тексты не видел глазами никто.
///
/// # Почему тест, а не «посмотреть руками»
///
/// Кадр существует, когда он снят и на него посмотрели. Смотреть
/// руками придётся заново после каждой правки, а `shoot(…)`
/// в исходнике доказывает намерение, не результат. Отсюда файл.
///
/// # Чего этот тест НЕ утверждает
///
/// Что обмен работает. В симуляторе нет вошедшего iCloud, и
/// `FamilySync.start()` упрётся в `accountStatus()`. Это **верное**
/// состояние для кадра — так экран выглядит у человека без iCloud, —
/// но выводить из него «обмен поднялся» нельзя. Здесь снимается
/// только то, что человек видит.
///
/// И отдельно: сам обмен к этому экрану шире, чем экран. Из двенадцати
/// типов общего дневника в контейнере существуют пять (`cktool
/// export-schema`, замер 14.10), а из записи `Dog` в production
/// отбивается каждая. Экран об этом не знает и знать не может.
///
/// # Куда пишет
///
/// `build/кадры-общего-дневника/`, путь из `#filePath`. Значит тест
/// ломается от уборки каталога — и ломается не на своём предмете.
/// `build/` в `.gitignore`: что нужно сохранить, выносится
/// в `Дизайн/кадры-приёмки/` и коммитится.
nonisolated final class ОбщийДневникВидно: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-общего-дневника")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Вернуть обмен выключенным — **обязательно**.
    ///
    /// `SharedDiarySettings.isOn` лежит в `UserDefaults` группы
    /// приложений (`FamilySync.swift:765`) и переживает запуск.
    /// Оставить включённым значит отдать следующему тесту набора
    /// поднимающийся `FamilySync` — и он будет ждать CloudKit там,
    /// где его никто не звал.
    override func tearDown() {
        guard app?.state == .runningForeground else { return }
        if тумблер.exists, (тумблер.value as? String) == "1" { тумблер.tap() }
    }

    private var тумблер: XCUIElement {
        app.switches.firstMatch
    }

    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    func testЭкранОбщегоДневникаСнятДляЧеловека() throws {
        let вкладка = app.tabBars.buttons["Семья"].firstMatch
        XCTAssertTrue(вкладка.waitForExistence(timeout: 15),
                      "вкладки «Семья» нет — кадра нет, и это не «экрана нет»")
        вкладка.tap()

        // Ищется НЕ только среди `buttons`, и это не перестраховка.
        // `sharedDiaryLink` (`FamilyScreen.swift:247`) — это
        // `NavigationLink` с карточкой в метке: в дереве доступности
        // он может оказаться и кнопкой, и ячейкой, и `other`,
        // в зависимости от того, как SwiftUI свернул карточку.
        // `app.buttons[…]` ответил бы «нет» и тогда, когда ссылка
        // на экране есть, — то есть ответил бы про мерку, а не
        // про экран, и мы записали бы «карточки больше нет».
        let ссылка = app.descendants(matching: .any)
            .containing(NSPredicate(format: "label CONTAINS %@", "Общий дневник"))
            .firstMatch
        for _ in 0..<6 where !ссылка.exists { app.swipeUp() }
        XCTAssertTrue(ссылка.waitForExistence(timeout: 5), """
            ссылки «Общий дневник» нет на экране семьи. Либо карточка
            уехала с прокруткой, либо её там больше нет — и это разные
            вещи: первое про дорогу, второе про продукт.
            """)
        ссылка.tap()

        // ПРОВЕРКА, ЧТО БЫЛО ЧТО СНИМАТЬ. Ставится первой: без неё
        // три кадра пустого экрана выглядели бы приёмкой.
        XCTAssertTrue(тумблер.waitForExistence(timeout: 10), """
            экран общего дневника не построился — переключателя нет.
            Кадры ниже были бы кадрами пустоты под именем экрана.
            """)

        var пути: [URL] = []
        пути.append(try снять("1-обмен-выключен"))

        // Объяснения «что обменивается, а что нет» лежат ниже сгиба:
        // человек читает их, решая, включать ли. Снимаем отдельно —
        // кадр, на котором видно половину, это приёмка половины.
        app.swipeUp()
        пути.append(try снять("2-что-обменивается"))
        app.swipeUp()
        пути.append(try снять("3-что-не-обменивается"))

        // Возвращаемся наверх к переключателю: свайпы увели экран,
        // и `tap` по невидимому элементу — отдельный класс ошибок.
        for _ in 0..<4 where !тумблер.isHittable { app.swipeDown() }
        XCTAssertTrue(тумблер.isHittable, "до переключателя не добрались назад")

        // С `bd4783d` это утверждение значит **не то, что значило
        // при написании**, и разница важна.
        //
        // Было: «ключ мог достаться от предыдущего теста» — ключ
        // `sharedDiary.on` живёт в UserDefaults группы приложений
        // и переживает запуск, а не чистил его никто.
        // Стало: `TogoApp.выключитьОбмен()` (`:170`, зовётся из
        // `init()` под `-UITesting`) гасит его на каждом старте.
        //
        // Значит теперь это не наблюдение, а **приёмка чужой правки**:
        // красное здесь говорит, что `выключитьОбмен` не сработал,
        // а не что сосед наследил. Утверждение то же, предмет другой.
        let былоДо = (тумблер.value as? String) == "1"
        XCTAssertFalse(былоДо, """
            обмен УЖЕ включён на чистом запуске. С `bd4783d` его гасит
            `TogoApp.выключитьОбмен()` — значит либо он не отработал,
            либо экран показывает не тот ключ. Кадр «выключено» выше
            при этом снят не того состояния, и смотреть на него нельзя.
            """)

        тумблер.tap()

        // Чего тут нет и быть не должно: утверждения, что обмен
        // поднялся. Без вошедшего iCloud он и не поднимется.
        // Снимается то, что ВИДИТ человек в этот момент, — включая
        // случай «включил, а ничего не произошло».
        _ = тумблер.waitForExistence(timeout: 3)
        пути.append(try снять("4-обмен-включён"))

        print("СНЯТО КАДРОВ: \(пути.count) · \(каталог.path)")
        print("""
            ВЫВОД ДЛЯ ГЛАЗА: на кадре 4 человек только что включил
            обмен. Вопрос к кадру один — сказано ли ему, что дальше.
            Если экран выглядит так же, как на кадре 1, человек
            не знает, случилось ли что-нибудь.
            """)
    }
}
