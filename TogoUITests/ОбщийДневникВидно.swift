import XCTest

/// Экран общего дневника — **ноль кадров из двухсот четырнадцати**.
///
/// # Чем это отличается от «ещё одного экрана»
///
/// Замер 14.10.2026 по `Дизайн/кадры-приёмки/`: 214 файлов, среди них
/// `today`, `needs-verdict`, `stool`, `training`, `history`, `family`,
/// `paywall` — и ни одного с экраном общего дневника. Ни один
/// UI-тест на него не заходит: `grep` по `TogoUITests/` даёт одно
/// упоминание, и то в доккомментарии про другое.
///
/// А через этот экран проходит **вся дорога второго человека**:
///
/// ```
/// включение обмена        turn(on:) — SharedDiaryScreen:194
/// исход приёма            отказПриёма = НеудачаПриёма.текущая — :66
/// снятие жалобы           НеудачаПриёма.текущая = nil — :203
/// ```
///
/// Здесь же человек читает, **что обменивается, а что нет**, — и
/// решает, включать ли. Эти тексты не видел глазами никто.
///
/// # Почему тест, а не «посмотреть руками»
///
/// Кадр существует, когда он снят и на него посмотрели. Смотреть
/// руками придётся заново после каждой правки, а `shoot(…)`
/// в исходнике доказывает намерение, не результат. Отсюда файл.
///
/// # Чего этот тест НЕ утверждает
///
/// Что обмен работает. В симуляторе нет вошедшего iCloud, и
/// `FamilySync.start()` упрётся в `accountStatus()`. Это **верное**
/// состояние для кадра — так экран выглядит у человека без iCloud, —
/// но выводить из него «обмен поднялся» нельзя. Здесь снимается
/// только то, что человек видит.
///
/// И отдельно: сам обмен к этому экрану шире, чем экран. Из двенадцати
/// типов общего дневника в контейнере существуют пять (`cktool
/// export-schema`, замер 14.10), а из записи `Dog` в production
/// отбивается каждая. Экран об этом не знает и знать не может.
///
/// # Куда пишет
///
/// `build/кадры-общего-дневника/`, путь из `#filePath`. Значит тест
/// ломается от уборки каталога — и ломается не на своём предмете.
/// `build/` в `.gitignore`: что нужно сохранить, выносится
/// в `Дизайн/кадры-приёмки/` и коммитится.
nonisolated final class ОбщийДневникВидно: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-общего-дневника")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Вернуть обмен выключенным — **обязательно**.
    ///
    /// `SharedDiarySettings.isOn` лежит в `UserDefaults` группы
    /// приложений (`FamilySync.swift:765`) и переживает запуск.
    /// Оставить включённым значит отдать следующему тесту набора
    /// поднимающийся `FamilySync` — и он будет ждать CloudKit там,
    /// где его никто не звал.
    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода, и ПЕРВОЙ строкой — ниже стоит `guard … else { return }`,
        // то есть за ним печать уже не выполнилась бы.
        //
        // Иначе «снято всё» и «упал на третьем» выглядят в логе
        // ОДИНАКОВО: строк `КАДР:` просто меньше, а отсутствия
        // никто не ищет.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ОбщийДневникВидно")
        guard app?.state == .runningForeground else { return }
        if тумблер.exists, (тумблер.value as? String) == "1" { тумблер.tap() }
    }

    private var тумблер: XCUIElement {
        app.switches.firstMatch
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        снято.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    /// Дойти до переключателя общего дневника и убедиться, что пришли.
    ///
    /// **Вынесено, когда у сценария появился второй читатель.** Пока
    /// читатель был один, дорога жила внутри теста и это было верно;
    /// вторая копия разошлась бы с первой молча — а разбор, почему
    /// `containing` уводил на чужой экран, стоил прогона и хранится
    /// ниже. Копировать его вместе с дорогой значило бы завести два
    /// места, где он может устареть порознь.
    private func дойтиДоТумблера(файл: StaticString = #filePath,
                                 строка: UInt = #line) throws {
        // Вкладки «Семья» нет с 22.10 — экран в меню «…»; дорогу
        // знает `открытьСемью`. Прежний отказ «вкладки нет — кадра
        // нет» читался как отказ запуска при поднявшемся приложении.
        XCTAssertTrue(открытьСемью(в: app),
                      "экран «Семья» не открылся — кадра нет, и это не «экрана нет»")

        // **Здесь стоял `containing`, и это была ошибка мерки,
        // пойманная кадром, а не тестом.**
        //
        // `XCUIElementQuery.containing(_:)` отбирает элементы, у которых
        // есть ПОТОМОК под предикат, а не элементы с таким ярлыком.
        // Значит `firstMatch` вернул корневое окно — оно содержит этого
        // потомка, — и `tap()` пришёлся в случайное место экрана.
        // Прогон 17:17 увёл на карточку участника «Мама»; тест упал
        // ниже, на тумблере, и обвинил чужую правку `выключитьОбмен`.
        // Красное было про мою навигацию.
        //
        // > Тест сказал, ЧТО не сошлось. Кадр показал, что мы были
        // > не на том экране. Второе не выводится из первого.
        //
        // Теперь спрашивается ярлык САМОГО элемента, и по очереди —
        // кнопка, ячейка, текст: `sharedDiaryLink`
        // (`FamilyScreen.swift:247`) — `NavigationLink` с карточкой
        // в метке, и SwiftUI волен сложить его любым из трёх.
        let кандидаты = [
            app.buttons["Общий дневник"].firstMatch,
            app.cells["Общий дневник"].firstMatch,
            app.staticTexts["Общий дневник"].firstMatch,
        ]
        var ссылка: XCUIElement?
        for _ in 0..<6 {
            if let найдено = кандидаты.first(where: { $0.exists && $0.isHittable }) {
                ссылка = найдено
                break
            }
            app.swipeUp()
        }
        guard let ссылка else {
            XCTFail("""
                ссылки «Общий дневник» нет на экране семьи ни кнопкой,
                ни ячейкой, ни текстом. Либо карточка не доскроллилась,
                либо её там больше нет — это разные вещи: первое про
                дорогу, второе про продукт.
                """)
            return
        }
        ссылка.tap()

        // ПРИШЛИ ЛИ ТУДА. Проверяется ДО кадров: экран семьи, карточка
        // участника и экран общего дневника на кадре отличимы только
        // глазом, а в отчёте все три называются «кадр снят».
        XCTAssertTrue(app.navigationBars["Общий дневник"].waitForExistence(timeout: 10), """
            после тапа мы НЕ на экране общего дневника. Кадры ниже
            сняли бы другой экран под его именем — ровно это и случилось
            в прогоне 17:17, когда `containing` вернул корневое окно.
            """)

        // ПРОВЕРКА, ЧТО БЫЛО ЧТО СНИМАТЬ. Ставится первой: без неё
        // три кадра пустого экрана выглядели бы приёмкой.
        XCTAssertTrue(тумблер.waitForExistence(timeout: 10), """
            экран общего дневника не построился — переключателя нет.
            Кадры ниже были бы кадрами пустоты под именем экрана.
            """, file: файл, line: строка)
    }

    /// Отказ приёма приглашения показан человеку, а не стёрт его же тапом.
    ///
    /// **Предмет — не баннер, а то, что НЕ произошло.** До починки тап
    /// по тумблеру стирал жалобу первой строкой, поднимал обмен,
    /// и `SharedZoneRouting` при неизвестном владельце отдавал **свою**
    /// зону в личной базе. Экран писал «Обмен: готов», человек вёл
    /// собственный дневник, считая, что вошёл в чужой, и записей
    /// Виктории не увидел бы никогда. Единственный признак, по которому
    /// можно было догадаться, **стирал его же тап**.
    ///
    /// ```
    /// ДО починки    тумблер включился · «Обмен: готов» · жалобы нет
    /// ПОСЛЕ         тумблер ОСТАЛСЯ ВЫКЛЮЧЕННЫМ · баннер с причиной
    /// ```
    ///
    /// Оба условия нужны **разом** (`SharedDiaryScreen:263`): владелец
    /// зоны неизвестен И отказ приёма не починен. У Виктории это
    /// не срабатывает ни разу — ей никто не присылал приглашения.
    ///
    /// Запуск **без** `-ЧужаяЗона` нарочно: с ней владелец известен,
    /// первое условие ложно, и экран повёл бы себя как у владельца —
    /// то есть кадр отвечал бы про другой случай.
    func testОтказПриёмаНеСтираетсяТапомЧеловека() throws {
        // setUp поднял приложение с одним `-UITesting`. Предмет здесь —
        // состояние ПОСЛЕ неудачного приёма, его задаёт второй аргумент.
        app.terminate()
        app.launchArguments = ["-UITesting", "-ИсходПриёма", "нетСети"]
        app.launch()

        try дойтиДоТумблера()

        // Состояние ДО тапа. Снимается отдельно: «баннер был и до тапа»
        // и «баннер появился от тапа» — разные утверждения, и по одному
        // кадру они неразличимы.
        let доТапа = try снять("5-отказ-приёма-до-тапа")

        XCTAssertFalse((тумблер.value as? String) == "1", """
            обмен уже включён на запуске с отказом приёма. Тогда кадр
            ниже снят не того состояния: предмет теста — что делает ТАП,
            а тапать по включённому нечего.
            """)

        тумблер.tap()
        _ = тумблер.waitForExistence(timeout: 3)
        let послеТапа = try снять("6-отказ-приёма-после-тапа")

        // **Главное утверждение: тумблер НЕ включился.**
        XCTAssertFalse((тумблер.value as? String) == "1", """
            ТУМБЛЕР ВКЛЮЧИЛСЯ ПРИ НЕПОЧИНЕННОМ ОТКАЗЕ ПРИЁМА.
            Это возврат того, что чинил `SharedDiaryScreen:263`: человек
            поднял обмен в СВОЕЙ зоне, экран скажет «готов», и чужих
            записей он не увидит никогда. Кадр «6-отказ-приёма-после-тапа»
            показывает, что он при этом видит.
            """)

        // И причина названа человеку, а не только удержана. Текст берётся
        // готовый из `ShareAcceptanceOutcome`, поэтому ищем не точную
        // строку, а признак баннера отказа — иначе тест ломался бы
        // от правки текста, не меняющей поведения.
        let естьПричина = app.staticTexts.allElementsBoundByIndex.contains {
            $0.exists && ($0.label.contains("ссылку") || $0.label.contains("Не получилось"))
        }
        XCTAssertTrue(естьПричина, """
            тумблер удержан, но причина человеку НЕ названа. Это
            половина починки: отказ без адреса действия человек читает
            как поломку приложения, а не как «открой ссылку снова».
            """)

        print("СНЯТО КАДРОВ: 2 · \(доТапа.lastPathComponent), \(послеТапа.lastPathComponent)")
    }

    func testЭкранОбщегоДневникаСнятДляЧеловека() throws {
        try дойтиДоТумблера()

        var пути: [URL] = []
        пути.append(try снять("1-обмен-выключен"))

        // Объяснения «что обменивается, а что нет» лежат ниже сгиба:
        // человек читает их, решая, включать ли. Снимаем отдельно —
        // кадр, на котором видно половину, это приёмка половины.
        app.swipeUp()
        пути.append(try снять("2-что-обменивается"))
        app.swipeUp()
        пути.append(try снять("3-что-не-обменивается"))

        // Возвращаемся наверх к переключателю: свайпы увели экран,
        // и `tap` по невидимому элементу — отдельный класс ошибок.
        for _ in 0..<4 where !тумблер.isHittable { app.swipeDown() }
        XCTAssertTrue(тумблер.isHittable, "до переключателя не добрались назад")

        // С `bd4783d` это утверждение значит **не то, что значило
        // при написании**, и разница важна.
        //
        // Было: «ключ мог достаться от предыдущего теста» — ключ
        // `sharedDiary.on` живёт в UserDefaults группы приложений
        // и переживает запуск, а не чистил его никто.
        // Стало: `TogoApp.выключитьОбмен()` (`:170`, зовётся из
        // `init()` под `-UITesting`) гасит его на каждом старте.
        //
        // Значит теперь это не наблюдение, а **приёмка чужой правки**:
        // красное здесь говорит, что `выключитьОбмен` не сработал,
        // а не что сосед наследил. Утверждение то же, предмет другой.
        let былоДо = (тумблер.value as? String) == "1"
        XCTAssertFalse(былоДо, """
            обмен УЖЕ включён на чистом запуске. С `bd4783d` его гасит
            `TogoApp.выключитьОбмен()` — значит либо он не отработал,
            либо экран показывает не тот ключ. Кадр «выключено» выше
            при этом снят не того состояния, и смотреть на него нельзя.
            """)

        тумблер.tap()

        // Чего тут нет и быть не должно: утверждения, что обмен
        // поднялся. Без вошедшего iCloud он и не поднимется.
        // Снимается то, что ВИДИТ человек в этот момент, — включая
        // случай «включил, а ничего не произошло».
        _ = тумблер.waitForExistence(timeout: 3)
        пути.append(try снять("4-обмен-включён"))

        print("СНЯТО КАДРОВ: \(пути.count) · \(каталог.path)")
        print("""
            ВЫВОД ДЛЯ ГЛАЗА: на кадре 4 человек только что включил
            обмен. Вопрос к кадру один — сказано ли ему, что дальше.
            Если экран выглядит так же, как на кадре 1, человек
            не знает, случилось ли что-нибудь.
            """)
    }
}
