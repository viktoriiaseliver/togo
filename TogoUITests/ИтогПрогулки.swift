import XCTest

/// Итог прогулки: гейт по правилу ФИНАЛа и кадр состояния со срывом.
///
/// **Два разных предмета в одном файле нарочно.** Гейт решает, открыть
/// ли шторку; галерея показывает, что в ней написано. Первое проверяется
/// поведением, второе — взглядом, и путать их нельзя: «шторка
/// не открылась» ничего не говорит о том, что было бы внутри.
nonisolated final class ИтогПрогулкиUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Кадр состояний, которых не видел глазами никто.
    ///
    /// До 07.10.2026 `WalkSummarySheet` строился только внутри живой
    /// прогулки: чтобы дойти до экрана со срывом, надо было выйти
    /// с собакой, отметить срыв и вернуться. Тесты при этом считали
    /// срывы верно — `WalkSessionTests:223` требует `reactions == 4`.
    ///
    /// > Тест проверяет, верно ли посчитано. Кадр — верно ли сказано.
    /// > Второго вопроса здесь не задавал никто.
    func testСостоянияИтогаСнимаютсяКадром() {
        // ДОРОГА, А НЕ ГЛАВНЫЙ ЭКРАН (правка 25.10.2026).
        //
        // Стояло три строки: `app.buttons["Настройки"]`, ожидание
        // и тап, — и отказ говорил «не дождались главного экрана».
        // Это НЕВЕРНО дважды: экран поднимался (соседние проверки
        // проходили), а не находилась кнопка настроек, которая
        // решением Виктории 22.10 ушла в меню «…».
        //
        // > **Отказ называл не ту сторону.** Сообщение винило запуск
        // > приложения, а предмет был в адресации органа; я потеряла
        // > на этом два ложных объяснения подряд, прежде чем прочла
        // > имя переменной — она звалась `настройки`.
        //
        // Помощник `открытьНастройки(в:)` знает обе дороги и говорит
        // о себе правду.
        XCTAssertTrue(открытьНастройки(в: app), """
            в настройки не попасть ни прямой кнопкой, ни через меню «…». \
            Это отказ ДОРОГИ, а не запуска: если бы не поднялось \
            приложение, не нашлось бы и меню.
            """)

        let вход = найти("Итог прогулки", в: app)
        XCTAssertTrue(вход.waitForExistence(timeout: 10), """
            в настройках нет входа «Итог прогулки» — галерея живёт \
            под `#if DEBUG`, и в Release-сборке этой проверки \
            не существует
            """)
        вход.tap()

        // Контроль: раздел ПОСТРОИЛСЯ. Без него запреты ниже
        // выполняются на пустом экране.
        // **Регистр: `TGSectionHeader` вешает `.textCase(.uppercase)`**
        // (`TGRows.swift:12`), и на экране стоит «НА ЧТО СОРВАЛСЯ».
        // Я уже наступала на это сегодня с «ДАННЫХ НЕТ ВОВСЕ» —
        // и наступила второй раз, зная про ловушку. Поэтому поиск
        // без учёта регистра стоит здесь отдельной строкой, а не
        // держится на памяти: правило, записанное в голове, держится
        // до первой спешки.
        func безРегистра(_ что: String) -> XCUIElement {
            app.descendants(matching: .any)
                .matching(NSPredicate(format: "label CONTAINS[c] %@", что)).firstMatch
        }
        let заголовок = безРегистра(подписи("на что сорвался"))
        var есть = заголовок.waitForExistence(timeout: 10)
        for _ in 0..<8 where !есть {
            app.swipeUp()
            есть = безРегистра(подписи("на что сорвался")).exists
        }
        XCTAssertTrue(есть, """
            в галерее нет блока «на что сорвался» — состояние со срывом \
            не построилось, и снимать нечего. Это не «со срывом всё \
            хорошо», это нечем смотреть.
            """)

        снять("11-итог-прогулки-состояния")

        // Множественное число заголовка — отдельное состояние, и оно
        // ловится только перечислением: у одного срыва «на что
        // сорвался», у трёх «на что срывался».
        // **`exists` истинно и для элемента ВНЕ экрана**, поэтому цикл
        // «крутить, пока не появится» не прокрутил ни разу: условие
        // было выполнено сразу. Тест при этом зеленел, а второй кадр
        // повторял первый — состояние «срывов три» не снималось вовсе.
        //
        // Поймала это взглядом на кадр, а не прогоном: зелёный тест
        // и дубликат кадра снаружи неразличимы. Я писала ровно этот
        // комментарий утром в галерее виджета — и повторила ошибку
        // здесь, зная о ней.
        //
        // > Правило, которое держится на памяти, держится до первой
        // > спешки. Поэтому крутим фиксированное число раз, а не «пока
        // > не появится».
        var естьМнож = безРегистра(подписи("на что срывался")).exists
        for _ in 0..<6 { app.swipeUp() }
        естьМнож = естьМнож || безРегистра(подписи("на что срывался")).exists
        // Кадр назван по тому, что на нём ВИДНО, а не по тому, что
        // проверяет строка ниже: шесть махов доезжают до хвоста
        // галереи, и в кадр попадает последнее состояние —
        // недостижимая ветка «без отметок». Назови его «срывов три» —
        // и имя врало бы ровно так же, как врут устаревшие имена
        // тестов, только про картинку.
        снять("12-итог-прогулки-хвост-и-недостижимая-ветка")
        XCTAssertTrue(естьМнож, """
            состояние «срывов три» не нашлось: заголовок остался \
            в единственном числе. Либо галерея его не строит, либо \
            форма числа считается не по количеству срывов.

            Проверка ПО ДЕРЕВУ, а не по кадру: на кадре выше хвост \
            галереи, и состояния «срывов три» на нём нет. Разные \
            вопросы — «построилось ли» и «как выглядит», и смешивать \
            их в одном утверждении нельзя.
            """)
    }
}
