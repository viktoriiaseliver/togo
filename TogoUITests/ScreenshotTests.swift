    /// Дождаться ЗНАЧЕНИЯ у элемента, а не его существования.
    ///
    /// `waitForExistence` отвечает про наличие кнопки; значение приезжает
    /// позже — отметка кладётся в сессию, вид перерисовывается, озвучка
    /// пересчитывает `accessibilityValue`. Чтение без ожидания взяло бы
    /// снимок, снятый до перерисовки, и покраснело бы на здоровом коде.
    private func дождаться(значения ожидаемое: String, у элемент: XCUIElement,
                           timeout: TimeInterval = 5) -> Bool {
        let ожидание = XCTNSPredicateExpectation(
            predicate: NSPredicate(format: "value == %@", ожидаемое),
            object: элемент
        )
        return XCTWaiter().wait(for: [ожидание], timeout: timeout) == .completed
    }

    /// Значение озвучки у кнопки отметки (`WalkMode.широкая`/`плитки`).
    ///
    /// Собирается форматом, а не склейкой: ключ каталога — `отмечено %lld`,
    /// и в казахском число стоит ПЕРВЫМ («%lld белгіленді»). Склейка
    /// «слово + число» дала бы на `kk` строку, которой приложение
    /// не печатает, то есть красный на верном коде.
    private func отмечено(_ сколько: Int) -> String {
        String(format: т("отмечено %lld"), сколько)
    }

    /// Отметка режима выгула — по ИДЕНТИФИКАТОРУ, а не по подписи.
    ///
    /// Подпись «Пописал» на этом экране принадлежит ДВУМ кнопкам:
    /// пока прогулка идёт, такая же стоит в низу «Сегодня»
    /// (`TodayBottom`) и остаётся в дереве под шторкой. Поиск
    /// по подписи брал закрытую — разбор в `WalkMode.имяОтметки`.
    ///
    /// Берётся `descendants`, а не `buttons`: `accessibilityElement
    /// (children: .ignore)` собирает контейнер типа `Other`, и значение
    /// («отмечено N») висит на нём, а не на вложенной кнопке. Замер
    /// 24.10.2026: `app.buttons["Пописал"].value` == `""` при живом
    /// `Other … value: не отмечено` в том же дереве.
    private func отметка(_ имя: String) -> XCUIElement {
        app.descendants(matching: .any).matching(identifier: "отметка-\(имя)").firstMatch
    }

    /// Режим выгула. Ось — **появилась ли отметка**, а не «нажалось ли».
    ///
    /// **Здесь стоял сторож на прокси, и это главное в этом тесте.**
    /// Прежняя редакция жала «Пописал» дважды, «Стул» один раз и снимала
    /// кадр — ни одна строка не спрашивала, что из этого записалось.
    /// На кадре 24.10.2026 стояло «Пописал · 1» при двух нажатиях,
    /// и прогон был ЗЕЛЁНЫЙ: ось «я нажал» удовлетворяется при
    /// несостоявшемся «запись появилась».
    ///
    /// Ось взята у того, что человек читает, и у двух разных мест:
    ///
    /// ```
    /// значение отметки  accessibilityValue = «отмечено N», а N — это
    ///                   session.count(of:) прямо из модели
    ///                   (WalkMode.широкая / .плитки)
    /// сводка под        session.tally — «пописал ×2 · стул»
    /// таймером          (ActiveSession.swift, `var tally`), её человек
    ///                   и видит под секундомером
    /// ```
    ///
    /// **И вместе с осью пришлось сменить АДРЕС.** Прежняя редакция
    /// жала `app.buttons["Пописал"]`, а таких кнопок на экране две:
    /// пока прогулка идёт, такая же стоит в низу «Сегодня» под шторкой.
    /// Брался закрытый двойник, первый тап уходил в плитку «Сорвался»,
    /// второй — в `hit point {-1, -1}`, и ни одна отметка не ставилась.
    /// Разбор с замером — `WalkMode.имяОтметки`.
    ///
    /// Два сторожа на одно место нарочно, и подделки у них разные:
    /// значение кнопки держит ЧИСЛО у одной отметки, сводка — СОСТАВ
    /// всех трёх. Снятый `appState.mark(kind)` роняет оба; отметка,
    /// уехавшая не в ту сессию, роняет только сводку.
    ///
    /// **Первой стоит проверка, что было что проверять:** до тапов
    /// значение обязано быть «не отмечено». Без неё обе проверки ниже
    /// прошли бы и на демо-базе, в которой отметки уже лежат, —
    /// и прогон доложил бы про чужие записи как про свои.
    func test12Прогулка() {
        app.buttons[т("Гулять")].firstMatch.tap()
        let пошли = app.buttons[т("Пошли")].firstMatch
        XCTAssertTrue(пошли.waitForExistence(timeout: 5))
        пошли.tap()

        let пописал = отметка("urine")
        XCTAssertTrue(пописал.waitForExistence(timeout: 5), "таймер должен пойти сразу")

        // Контроль — ПЕРВЫМ, и снят он в том же прогоне, что предмет.
        XCTAssertEqual(пописал.value as? String, т("не отмечено"), """
            до первого тапа у «Пописал» значение «\(пописал.value as? String ?? "nil")», \
            а ожидалось «\(т("не отмечено"))». Пусто здесь — это НЕ «ноль \
            отметок»: пустое значение отдаёт чужая кнопка с той же \
            подписью. Непустое и ненулевое — отметки пришли не от теста, \
            и обе проверки ниже не доказывают ничего.
            """)

        пописал.tap()
        пописал.tap()

        XCTAssertTrue(дождаться(значения: отмечено(2), у: пописал), """
            два тапа по «Пописал» — а в сессии \
            «\(пописал.value as? String ?? "nil")» вместо «\(отмечено(2))».
            Это НЕ про кадр и не про вёрстку: значение — это \
            session.count(of: .urine) из модели. Тап либо не долетел, \
            либо долетел в соседнюю плитку.
            """)

        let стул = отметка("stool")
        XCTAssertEqual(стул.value as? String, т("не отмечено"),
                       "контроль второй отметки: «Стул» до тапа уже отмечен")
        стул.tap()
        XCTAssertTrue(дождаться(значения: отмечено(1), у: стул), """
            тап по «Стул» не стал записью: значение \
            «\(стул.value as? String ?? "nil")».
            """)

        // Вторая ось: то же самое, но из другого места — сводка под
        // секундомером. Она считается по ВСЕМ отметкам сразу, поэтому
        // ловит отметку, уехавшую не в ту сессию, которую счётчик
        // одной кнопки не видит.
        let сводка = "\(т("Пописал").lowercased()) ×2 · \(т("Стул").lowercased())"
        XCTAssertTrue(app.staticTexts[сводка].waitForExistence(timeout: 5), """
            под секундомером нет сводки «\(сводка)» — значит в сессии \
            лежит не то, что отмечали. Счётчики кнопок при этом могли \
            сойтись: они спрашивают по одному виду, сводка — все сразу.
            """)

        capture("12-walk-mode")
    }

