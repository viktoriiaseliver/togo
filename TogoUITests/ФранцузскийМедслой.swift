import XCTest

/// Приёмка девяноста пяти заведённых ключей — **на четырёх адресах,
/// которые показывают ОДНУ строку, по-французски, с русским контролем
/// в том же заходе**.
///
/// # Что именно закрывается
///
/// `93f4840` завёл 95 ключей показа, которых в каталоге не было
/// **вовсе** — не «перевод не доехал», а строка, которая никогда
/// не извлекалась. Приёмки у этого коммита нет: теста на эти адреса
/// не существовало, а зелёный `LocalizationCoverageTests` отвечает
/// про **каталог**, не про экран. Разница оплачена в этом проекте
/// отдельно: «сторож на прокси гасится любым действием, которое прокси
/// удовлетворяет», и ровно этот сторож гасило извлечение строк Xcode.
///
/// > **Каталог отвечает, что ключ переведён. Экран отвечает, что
/// > человек увидел перевод. Это два разных вопроса, и до сегодня
/// > задавался только первый.**
///
/// # Ожидаемое, названное ДО прогона
///
/// ```
/// fr-прогон, все четыре адреса   французский абзац  ← ПРЕДМЕТ
/// ru-прогон, те же четыре        русский абзац      ← КОНТРОЛЬ
/// выполнено тестов               1  (Test run with 1 test)
/// кадров                         8  (4 адреса × 2 языка)
/// ```
///
/// # Почему ОДИН тест на оба языка, а не два
///
/// У контроля срок годности — минуты, и он обязан быть снят в том же
/// замере, что предмет. Два метода разошлись бы по прогонам при первом
/// же `-only-testing` на одно имя; здесь русский проход нельзя
/// не сделать — он внутри предмета. Форма взята у
/// `ПодписьПоляПоФранцузски`, где она оплачена той же причиной.
///
/// `continueAfterFailure = true` нарочно: при `false` отказ на первом
/// адресе съел бы и остальные три, и русский контроль вместе с ними —
/// а **два нуля вместе значат «вопрос не тот», а не «предмета нет»**.
/// Здесь это была бы ложная находка про продукт.
///
/// # Чего этот файл НЕ утверждает
///
/// - **Что абзац ВИДНО.** Спрашивается `label` подписи, то есть
///   её ТЕКСТ, и спрашивается нарочно: предмет здесь — **язык строки**,
///   а не её геометрия. `isHittable` у подписи внутри прокрутки врёт
///   (оплачено 08.10.2026), и переделка этой пробы в «видно ли» дала бы
///   ложный красный на верном экране. Про видимость отвечает кадр,
///   и кадр снимается на каждом адресе.
/// - **Что перевод ХОРОШИЙ.** Все пять локалей стоят
///   `needs_review`. Тест отвечает «француз читает французское»,
///   а не «французское написано правильно».
/// - **Что остальные 91 ключа доехали.** Предмет — четыре адреса,
///   названные нарядом. Про остальные не сказано ничего.
/// - **Что каталог лежит в бандле приложения.** Проект собран
///   синхронизированными группами (`PBXFileSystemSynchronizedRootGroup`,
///   7 штук), поимённого членства в `project.pbxproj` нет — `grep`
///   по `xcstrings` даёт честный ноль при живом контроле. На этот вопрос
///   отвечает **обратное чтение языка** ниже, а не файл проекта.
///
/// # Язык читается ОБРАТНО, и для `ru` это сказано честно
///
/// Прежде дороги тест ждёт вкладку `подписи("Здоровье")`: по-французски
/// это `Santé`, и её отсутствие значит, что язык не встал — тогда весь
/// проход снимал бы русские кадры под французскими именами.
///
/// > **У русского прохода обратное чтение НЕ РАЗЛИЧАЕТ «ru встал»
/// > и «не встало ничего»:** русский и есть запас. Это названная
/// > граница контроля, а не дыра — контроль здесь отвечает на вопрос
/// > «показывает ли экран русское, когда язык русский», и на него
/// > он отвечает.
///
/// # Локаль названа ЯВНО у каждого сравнения
///
/// Ни одна строка в этом файле не сравнивается с литералом: ожидаемое
/// берётся из того же каталога, который уезжает в бандл, через
/// `Подписи(язык:)`. Повод — замер `projects-9b` 26.10.2026: три
/// проверки сравнивались с `"12,87"` **без названной локали**, и пока
/// запятая стояла в коде, они сходились у всех; с локалью стали бы
/// краснеть у одного и зеленеть у другого, а причину не нашёл бы никто.
///
/// > **Проверка без названной локали не «проверяет умолчание» — она
/// > делает исход зависимым от стенда.**
///
/// # Вход: `-ДемоТ4` обязателен, и это замер
///
/// Четвёртый адрес (`LabResultScreens:1028`) живёт в `LabResultRowEditor`,
/// а тот открывается только нажатием на **существующую** строку анализа
/// (`LabResultScreens.swift:116`, `.sheet(item: $правка)`). Ни один
/// сценарий `LabResult` не заводит (`SeedData.swift:837`, замер 08.10,
/// повторён 23.10) — значит без `-ДемоТ4` четвёртая дорога ведёт
/// в пустой список, и адрес **недостижим**, а не «не проверен».
///
/// Второе предусловие — **справочник клиник обязан быть ПУСТ**: абзац
/// стоит под `if доступные.isEmpty`. `Clinic` в `SeedData` ноль вхождений
/// (контроль в том же запросе: `LabResult` — 5, инструмент рабочий),
/// то есть условие выполняется само. **Заведи кто-нибудь клинику
/// в засев — все четыре адреса станут недостижимы, и тест покраснеет
/// на здоровом коде.** Тогда чинить надо вход, а не сторожа.
nonisolated final class ФранцузскийМедслой: XCTestCase {

    /// Ключ — он же русский исходник. Все четыре адреса показывают
    /// **одну и ту же** строку, и это не совпадение: у них один повод
    /// (пустой справочник) и одно лечение.
    private static let ключСправочника =
        "Справочник пуст. Клиники и лаборатории заводятся в «Здоровье» → «Клиники и лаборатории» — оттуда они и попадают в этот выбор."

    private let фр = Подписи(язык: "fr")
    private let рус = Подписи(язык: "ru")

    private var app: XCUIApplication!
    private var снято: [String] = []
    /// Вердикт по каждому адресу, одной строкой. Печатается в `tearDown`
    /// ВСЕГДА — в том числе после падения посреди прохода.
    private var вердикты: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-fr-медслой")
    }

    /// Суффикс партии доезжает ТОЛЬКО как `TEST_RUNNER_KADR_SUFFIX`:
    /// `xcodebuild` отдаёт процессу теста переменные с этой приставкой,
    /// сняв её. Задашь `KADR_SUFFIX` обычной — не доедет, обе партии
    /// запишутся одними именами, вторая затрёт первую, **и прогон будет
    /// зелёным при верном числе кадров**.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        continueAfterFailure = true
        снято = []
        вердикты = []
    }

    override func tearDown() {
        // Счёт и вердикты печатаются ВСЕГДА. Иначе «снято восемь»
        // и «упал на третьем, снято два» выглядят в логе ОДИНАКОВО:
        // во втором случае строк просто меньше, а отсутствия никто
        // не ищет. Ожидаемого числа здесь НЕТ нарочно — вторая копия
        // разошлась бы с первой молча; сколько кадров должно быть,
        // утверждает сам тест своей проверкой.
        print("FR-МЕДСЛОЙ · КАДРОВ СНЯТО: \(снято.count) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ФранцузскийМедслой")
        for строка in вердикты { print("FR-МЕДСЛОЙ · \(строка)") }
        super.tearDown()
    }

    // MARK: Предмет

    func testЧетыреАдресаСправочникаНаДвухЯзыках() {
        проход(язык: "fr")
        проход(язык: "ru")
    }

    /// Один язык — четыре адреса, каждый со своего запуска.
    ///
    /// **Перезапуск на каждый адрес, а не одна сессия на четыре.**
    /// Шторку формы пришлось бы закрывать подписью «Отмена»/«Закрыть»,
    /// которая у четырёх экранов разная и тоже переводится; отказ
    /// закрытия утащил бы за собой все следующие дороги и дал бы
    /// три отказа там, где дефект один. Восемь запусков стоят секунд,
    /// а разбор слипшихся отказов — захода.
    private func проход(язык: String) {
        let свои = язык == "fr" ? фр : рус
        let чужие = язык == "fr" ? рус : фр

        замер(язык: язык, номер: "1", имя: "визит",
              адресВКоде: "VisitDiagnosisScreens.swift:195",
              свои: свои, чужие: чужие, дорога: дорогаДоВизита)

        замер(язык: язык, номер: "2", имя: "назначение",
              адресВКоде: "PrescriptionScreens.swift:279",
              свои: свои, чужие: чужие, дорога: дорогаДоНазначения)

        замер(язык: язык, номер: "3", имя: "бланк",
              адресВКоде: "LabResultScreens.swift:610",
              свои: свои, чужие: чужие, дорога: дорогаДоБланка)

        замер(язык: язык, номер: "4", имя: "правка-строки",
              адресВКоде: "LabResultScreens.swift:1028",
              свои: свои, чужие: чужие, дорога: дорогаДоПравкиСтроки)
    }

    /// Один адрес на одном языке: запуск, обратное чтение языка, дорога,
    /// кадр, приговор.
    private func замер(язык: String, номер: String, имя: String,
                       адресВКоде: String,
                       свои: Подписи, чужие: Подписи,
                       дорога: (Подписи) -> Bool) {
        let метка = "\(язык)-\(номер)-\(имя)"
        запустить(язык: язык)

        // --- язык ОБРАТНЫМ чтением, до всякой дороги ------------------
        let вкладка = app.tabBars.buttons[свои("Здоровье")]
        guard вкладка.waitForExistence(timeout: 60) else {
            снять("00-ОТКАЗ-язык-\(метка)")
            вердикты.append("\(метка) · ОТКАЗ: язык не встал")
            XCTFail("""
                вкладки «\(свои("Здоровье"))» нет за 60 с (\(метка)).
                Либо язык не встал — тогда на кадре интерфейс ДРУГОГО \
                языка, и приговор про перевод выносить нельзя вовсе, — \
                либо приложение не запустилось. Смотри кадр \
                `00-ОТКАЗ-язык-\(метка)`.
                """)
            return
        }

        // --- дорога ---------------------------------------------------
        let дошли = дорога(свои)

        // --- предмет: ЧЕЙ абзац на экране -----------------------------
        //
        // Три вопроса вместо одного, и это нарочно. «Нашлось моё»
        // отвечает на предмет; «нашлось чужое» называет, какой язык
        // на экране ЕСТЬ; полное совпадение отличает «не тот язык»
        // от «тот язык, текст разошёлся с каталогом». Одним булевым
        // эти три исхода неразличимы, а лечатся они по-разному.
        let ожидаемое = свои(Self.ключСправочника)
        let чужое = чужие(Self.ключСправочника)
        let мойФрагмент = первоеПредложение(ожидаемое)
        let чужойФрагмент = первоеПредложение(чужое)

        _ = докрутитьДоПодписи(мойФрагмент)

        let моё = подписьСодержащая(мойФрагмент)
        let чужоеНаЭкране = подписьСодержащая(чужойФрагмент)
        let полное = подписьСодержащая(ожидаемое) != nil

        // Кадр ДО приговора: при падении кадра иначе не будет вовсе.
        снять("\(номер)-\(имя)-\(язык)")

        // --- что именно увидели, СЛОВАМИ ------------------------------
        let увидено: String
        if let моё {
            увидено = "«\(обрезать(моё.label))»"
        } else if let чужоеНаЭкране {
            увидено = "ЧУЖОЙ ЯЗЫК: «\(обрезать(чужоеНаЭкране.label))»"
        } else {
            увидено = "абзаца нет ни на одном языке; длинные подписи "
                + "на экране: \(длинныеПодписи())"
        }
        вердикты.append("""
            \(метка) · \(адресВКоде) · дорога \(дошли ? "дошла" : "НЕ ДОШЛА") \
            · моё \(моё != nil ? "есть" : "НЕТ") · чужое \
            \(чужоеНаЭкране != nil ? "ЕСТЬ" : "нет") · полное совпадение \
            \(полное ? "да" : "нет") · \(увидено)
            """)

        XCTAssertTrue(дошли, """
            \(метка): до адреса \(адресВКоде) не дошли. Кадр \
            `\(номер)-\(имя)-\(язык)` снят ДО этой проверки — на нём \
            видно, где остановились. **Прежде чем читать это как дефект \
            перевода, проверь вход:** абзац стоит под \
            `if доступные.isEmpty`, и если в засев завели клинику, \
            адрес стал недостижим, а перевод тут ни при чём.
            """)

        // Разводка двух РАЗНЫХ бед одним словом в отказе: «чужой язык
        // есть» значит, что ключ не разрешается; «нет ни одного» значит,
        // что абзаца на экране нет вовсе, и чинить надо ВХОД. Считается
        // до сообщения, а не в нём: вложенный однострочный литерал
        // не умеет переноса `\` многострочного, и это стоило одного
        // typecheck.
        let чужойПриговор = чужоеНаЭкране != nil
            ? "ЕСТЬ — значит ключ не переводится, а не «не доехал»"
            : "нет — значит абзаца нет вовсе, и это про ВХОД, а не про перевод"

        XCTAssertNotNil(моё, """
            \(метка): на \(адресВКоде) нет абзаца на языке «\(язык)».
            Ожидалось начало «\(мойФрагмент)».
            Чужой язык на экране: \(чужойПриговор).
            Это ровно тот дефект, который закрывал `93f4840`: строка, \
            которая никогда не извлекалась. Каталог при этом зелёный — \
            он отвечает про себя.
            """)

        XCTAssertNil(чужоеНаЭкране, """
            \(метка): на \(адресВКоде) стоит абзац ЧУЖОГО языка \
            («\(чужойФрагмент)»). На французском прогоне это значит, \
            что `LocalizedStringKey` не разрешился: либо ключ в каталоге \
            не тот, либо строка собрана дословной перегрузкой \
            (`Text(verbatim:)` / `String`), и тогда перевод в каталоге \
            не прочтёт никто. Второе уже было в этом проекте — \
            `14c804c`, подпись `LabeledField` со `String` вместо \
            `Надпись`: перевод лежал готовый и не показывался \
            ни на одном из пяти языков.
            """)

        if моё != nil && !полное {
            // НЕ падение: язык верный, а текст разошёлся с каталогом.
            // Это другая беда, и лечится она не здесь.
            print("""
                FR-МЕДСЛОЙ · ЗАМЕЧАНИЕ \(метка): язык верный, но полного \
                совпадения с каталогом нет. Либо строка на экране \
                обрезана, либо каталог разошёлся с показом. Смотри кадр.
                """)
        }
    }

    // MARK: Дороги

    private func дорогаДоВизита(_ п: Подписи) -> Bool {
        guard открытьРаздел(п("Визиты к врачу"), п) else { return false }
        let добавить = app.buttons[п("Добавить визит")].firstMatch
        guard добавить.waitForExistence(timeout: 10) else { return false }
        добавить.tap()
        return app.textFields[п("Врач")].waitForExistence(timeout: 10)
    }

    private func дорогаДоНазначения(_ п: Подписи) -> Bool {
        guard открытьРаздел(п("Назначения"), п) else { return false }
        let добавить = app.buttons[п("Добавить назначение")].firstMatch
        guard добавить.waitForExistence(timeout: 10) else { return false }
        добавить.tap()
        return app.textFields[п("Препарат")].waitForExistence(timeout: 10)
    }

    /// Шаг 1 трёхшагового ввода («Когда и где») — там пикер лаборатории.
    ///
    /// **У входа ДВА имени, и зависят они от того, пуст ли список**
    /// (замер 26.10.2026, `LabResultScreens`): пустой список рисует
    /// `EmptyStateCard` с «Добавить анализ», непустой — раздел «добавить»
    /// с «Ввести с бланка», потому что кнопки «+» в шапке по дизайну
    /// больше нет. С `-ДемоТ4` список НЕ пуст, то есть ждать надо
    /// второе имя; первое оставлено на случай, если флаг однажды снимут,
    /// — иначе тест упадёт отказом, правдивым про кнопку и ложным
    /// про продукт.
    private func дорогаДоБланка(_ п: Подписи) -> Bool {
        guard открытьРаздел(п("Анализы"), п) else { return false }
        let сБланка = найти(п("Ввести с бланка"), в: app)
        let добавить = app.buttons[п("Добавить анализ")].firstMatch
        let вход: XCUIElement
        if сБланка.exists {
            вход = сБланка
        } else if добавить.waitForExistence(timeout: 5) {
            вход = добавить
        } else {
            return false
        }
        вход.tap()
        return app.staticTexts[п("Когда и где")].waitForExistence(timeout: 10)
    }

    /// Правка существующей строки анализа — четвёртый адрес.
    ///
    /// **Пробник здесь ДАННЫЕ, а не интерфейс.** Подпись строки списка —
    /// `.готовая(анализ.indicator)` (`LabResultScreens.swift:94`), то есть
    /// «Т4 общий» из `-ДемоТ4`: она одна и та же на всех пяти языках,
    /// и брать её из каталога было бы неверно — в каталоге её нет
    /// и быть не должно.
    private func дорогаДоПравкиСтроки(_ п: Подписи) -> Bool {
        guard открытьРаздел(п("Анализы"), п) else { return false }
        let строка = app.buttons
            .matching(NSPredicate(format: "label CONTAINS %@", "Т4"))
            .firstMatch
        guard докрутитьДоЭлемента(строка) else { return false }
        строка.tap()
        // Ворота — подпись, стоящая СРАЗУ ПОД предметом
        // (`LabResultScreens.swift:1031`): так «шторка не открылась»
        // не слипается с «открылась, абзаца нет».
        return app.staticTexts[п("Номер бланка")].waitForExistence(timeout: 10)
    }

    /// Дойти до раздела «Здоровья» по началу подписи строки.
    ///
    /// **Предусловие — панель вкладок, а не кличка на «Сегодня»**
    /// (замер 21.10.2026): хвост сценария оставляет приложение
    /// на «Здоровье», где кличка существует лишь как кнопка таб-бара.
    /// И подпись строки СОСТАВНАЯ («Анализы, 1 запись») — поиск идёт
    /// по началу, иначе точное совпадение промахнётся ровно после того,
    /// как в разделе появится первая запись.
    private func открытьРаздел(_ имя: String, _ п: Подписи) -> Bool {
        let вкладка = app.tabBars.buttons[п("Здоровье")]
        guard вкладка.waitForExistence(timeout: 30) else { return false }
        вкладка.tap()
        _ = app.navigationBars[п("Здоровье")].waitForExistence(timeout: 10)
        let строка = app.buttons
            .matching(NSPredicate(format: "label BEGINSWITH %@", имя))
            .firstMatch
        guard докрутитьДоЭлемента(строка) else { return false }
        строка.tap()
        return app.navigationBars[имя].waitForExistence(timeout: 10)
    }

    // MARK: Оснастка

    private func запустить(язык: String) {
        if app != nil { app.terminate() }
        app = XCUIApplication()
        // `-AppleLanguages` в домен аргументов ПРИЛОЖЕНИЯ, а не
        // `xcodebuild -testLanguage fr`: тот ставит язык и раннеру,
        // а раннеру нужен русский — он водит приложение по ключам
        // каталога, и ключ здесь русский по устройству
        // (`sourceLanguage: ru`).
        //
        // `-ДемоТ4` поверх `amber`: без него четвёртый адрес недостижим
        // (ни один сценарий не заводит `LabResult`). `amber` при этом
        // обязателен сам — `-ДемоТ4` требует активной схемы с дозой
        // в 08:00 и падает предусловием, а не рисует другой экран.
        app.launchArguments = [
            "-UITesting", "-Сценарий", "amber", "-ДемоТ4",
            "-AppleLanguages", "(\(язык))",
            "-AppleLocale", язык == "fr" ? "fr_FR" : "ru_RU",
        ]
        app.launch()
    }

    /// Кадр файлом И вложением: выгрузка вложений у нас не сработала
    /// пять раз из девяти, а файл переживает уборку `build/` ровно
    /// до уборки `build/`. Отказ записи НЕ роняет тест — кадр это улика,
    /// а не ворота.
    private func снять(_ имя: String) {
        let кадр = app.screenshot()
        let вложение = XCTAttachment(screenshot: кадр)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("FR-КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        } catch {
            print("FR-КАДР НЕ ЛЁГ: \(имя) · \(error.localizedDescription)")
        }
    }

    /// Подпись, СОДЕРЖАЩАЯ строку, — двумя запросами подряд.
    ///
    /// `matching` спрашивает атрибут самого элемента, `containing` —
    /// наличие подходящего потомка. Для листовой подписи верен первый,
    /// но в этом проекте работающим замерен второй
    /// (`МедслойДороги.содержит(_:)`), и какой из двух отвечает
    /// на `staticTexts`, у нас не померено ни разу. Поэтому
    /// **второй замер другим способом встроен в саму пробу**: ложный
    /// ноль от формы запроса здесь был бы неотличим от отсутствия
    /// перевода — то есть совпал бы с ожидаемым ответом, а это самый
    /// опасный вид ложного нуля.
    /// **Предикат строится НА МЕСТЕ каждого вызова, и общей переменной
    /// здесь быть не может.** `NSPredicate` не `Sendable`; отданный
    /// в два изолированных вызова, он разводит регионы изоляции,
    /// и сборка падает `sending 'предикат' risks causing data races`.
    /// Я положил ровно это в вершину коммитом `1b3693c` — при том, что
    /// тот же отказ, с тем же именем переменной, записан в своде
    /// проекта (`ГостьНеПишет.swift:289`).
    ///
    /// > **`-typecheck` этот класс НЕ ВИДИТ ПО УСТРОЙСТВУ:** диагностика
    /// > `sending` рождается в обязательных проходах SIL, а `-typecheck`
    /// > до SIL не доходит вовсе. Мой «0 error:, rc=0» был честным
    /// > ответом на другой вопрос. Проверять этот класс — `-emit-sil`
    /// > либо сборка схемы.
    ///
    /// Второй путь — пометить изоляцию — дороже и трогает соседей:
    /// `подписьСодержащая` зовут три места, включая `докрутитьДоПодписи`
    /// в цикле. Два дешёвых предиката дешевле одной чужой правки.
    private func подписьСодержащая(_ фрагмент: String) -> XCUIElement? {
        let свой = app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", фрагмент))
            .firstMatch
        if свой.exists { return свой }
        let потомком = app.staticTexts
            .containing(NSPredicate(format: "label CONTAINS %@", фрагмент))
            .firstMatch
        if потомком.exists { return потомком }
        return nil
    }

    private func докрутитьДоПодписи(_ фрагмент: String, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if подписьСодержащая(фрагмент) != nil { return true }
            app.swipeUp(velocity: .slow)
        }
        return подписьСодержащая(фрагмент) != nil
    }

    private func докрутитьДоЭлемента(_ элемент: XCUIElement, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if элемент.exists && элемент.isHittable { return true }
            app.swipeUp(velocity: .slow)
        }
        return элемент.exists && элемент.isHittable
    }

    /// Первое предложение — тот фрагмент, по которому язык опознаётся
    /// надёжнее всего: `Справочник пуст` против
    /// `Le répertoire est vide`. Берётся ИЗ КАТАЛОГА, а не пишется
    /// рядом: вторая копия разошлась бы молча, и сравнение стало бы
    /// проверкой самого теста.
    private func первоеПредложение(_ строка: String) -> String {
        guard let точка = строка.firstIndex(of: ".") else { return строка }
        return String(строка[строка.startIndex..<точка])
    }

    private func обрезать(_ строка: String, до предел: Int = 140) -> String {
        строка.count <= предел ? строка : String(строка.prefix(предел)) + "…"
    }

    /// Длинные подписи экрана — улика на случай «абзаца нет ни на одном
    /// языке». Без неё отказ сообщает только о себе: «не нашёл» —
    /// это отчёт о СВОЁМ поиске, а не факт о экране.
    private func длинныеПодписи(_ сколько: Int = 3) -> String {
        // Замыканием, а не `map(\.label)`: `label` изолирован
        // `MainActor`, и key path к нему **не формируется** —
        // это не предупреждение, а ошибка компиляции под
        // `-default-isolation MainActor`. Замыкание проходит при обеих
        // настройках таргета, а key path — только при одной, и какая
        // стоит у `TogoUITests`, у нас не померено.
        let все = app.staticTexts.allElementsBoundByIndex
            .prefix(60)
            .map { $0.label }
            .filter { $0.count > 40 }
            .prefix(сколько)
        return все.isEmpty ? "ни одной длиннее 40 знаков" : все.map { "«\(обрезать($0, до: 80))»" }.joined(separator: " | ")
    }
