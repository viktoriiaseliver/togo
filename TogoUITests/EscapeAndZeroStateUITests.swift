import XCTest

/// Проверки того, что нельзя проверить модульно: из любого места есть выход,
/// а на пустой базе ни один экран не превращается в белый лист.
nonisolated final class EscapeAndZeroStateUITests: XCTestCase {
    private var app: XCUIApplication!


    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
        _ = app.staticTexts["Стич"].waitForExistence(timeout: 10)
    }

    /// У каждой шторки есть явная кнопка закрытия.
    ///
    /// **Список предметов был устаревшим, и тест винил продукт**
    /// (правка 26.10.2026). Стояло `["Просится", "Стул", "Еда",
    /// "Инцидент"]`, и отказ звучал «у шторки «Просится» нет явной
    /// кнопки закрытия» — при том, что
    ///
    /// ```
    /// «Просится»  не шторка ВОВСЕ: главная кнопка действия
    ///             (`TodayScreen.swift:975`, «Вывожу» / «Остановка»).
    ///             Нажатие записывает выход, а не открывает лист
    /// «Еда»       кнопки нет с 24.10 — `ActionGrid` удалён
    /// ```
    ///
    /// > **Тест, перечисляющий предметы руками, стареет молча
    /// > и обвиняет продукт в том, что сам смотрит не туда.**
    ///
    /// Теперь предметы берутся из живой шторки «Записать» (её
    /// открывает «+», крючок `низ-записать`): что в ней есть сегодня,
    /// то и проверяется. Список внутри — `TodayRouter`.
    func testУКаждойШторкиЕстьКрестик() {
        let плюс = app.buttons["низ-записать"].firstMatch
        XCTAssertTrue(плюс.waitForExistence(timeout: 10),
                      "кнопки «Записать» нет — шторок не открыть ни одной")
        var проверено = 0
        var безКрестика: [String] = []
        // Три строки первой шторки (`TodayBottom`), четвёртая — «Ещё»,
        // она ведёт во вторую и проверяется отдельным тестом.
        for пункт in ["Инцидент", "Стул", "Еда"] {
            плюс.tap()
            let строка = найти(пункт, в: app)
            guard строка.waitForExistence(timeout: 5) else {
                XCTFail("в шторке «Записать» нет строки «\(пункт)»")
                continue
            }
            строка.tap()
            проверено += 1
            let закрыть = app.buttons["Закрыть"].firstMatch
            if закрыть.waitForExistence(timeout: 5) {
                закрыть.tap()
            } else {
                безКрестика.append(пункт)
            }
            // Внешняя шторка закрывается «Отменой», а не «Закрыть»:
            // она ничего не создаёт сама, только выбирает, что создавать
            // (`TodayBottom`, кадр 06). Разные слова — разный смысл,
            // и подставить одно вместо другого нельзя.
            let отмена = app.buttons["Отмена"].firstMatch
            if отмена.waitForExistence(timeout: 3) { отмена.tap() }
            _ = плюс.waitForExistence(timeout: 5)
        }
        XCTAssertEqual(проверено, 3,
                       "осмотрено \(проверено) шторок из трёх — замер не состоялся")
        XCTAssertTrue(безКрестика.isEmpty,
                      "нет явной кнопки закрытия у шторок: \(безКрестика)")
    }

    /// Из шторки «Записать» можно уйти на вкладку собаки.
    ///
    /// **Тест жал не ту кнопку** (правка 26.10.2026). Стояло
    /// `app.buttons["Ещё"]`, а «Ещё» в шапке открывает МЕНЮ настроек;
    /// «Всё про собаку» живёт в шторке «Записать» (`TodayRouter:101`),
    /// и открывает её «+» — `низ-записать`.
    ///
    /// > Два разных входа с похожим смыслом «что ещё можно сделать».
    /// > Отказ при этом звучал как дефект продукта.
    func testИзШторкиЗаписатьМожноУйтиНаВкладкуСобаки() {
        let плюс = app.buttons["низ-записать"].firstMatch
        XCTAssertTrue(плюс.waitForExistence(timeout: 10), "кнопки «Записать» нет")
        плюс.tap()
        // ДВА шага, а не один: «Всё про собаку» лежит во ВТОРОЙ шторке,
        // за строкой «Ещё» (`TodayBottom` → `.more` → `TodayRouter`).
        // Первая редакция этой правки искала его сразу после «+»
        // и покраснела бы — правдиво про экран и ложно про продукт.
        let ещё = найти("Ещё", в: app)
        XCTAssertTrue(ещё.waitForExistence(timeout: 5),
                      "в шторке «Записать» нет строки «Ещё»")
        ещё.tap()
        let всё = найти("Всё про собаку", в: app)
        XCTAssertTrue(всё.waitForExistence(timeout: 5),
                      "во второй шторке нет строки «Всё про собаку»")
        всё.tap()
        // Шторка закрывается и переключает вкладку, а не строит дерево внутри себя.
        XCTAssertTrue(найти("Питание и режим", в: app).waitForExistence(timeout: 5),
                      "вкладка собаки не открылась")
    }

    func testПитаниеВДвухТапахОтВкладки() {
        app.tabBars.buttons["Стич"].tap()
        let питание = найти("Питание и режим", в: app)
        XCTAssertTrue(питание.waitForExistence(timeout: 5))
        питание.tap()
        XCTAssertTrue(app.navigationBars["Питание"].waitForExistence(timeout: 5))
    }

    /// Настройки ДОСТИЖИМЫ с каждой вкладки.
    ///
    /// **Ось сменилась 26.10.2026: была «шестерёнка есть», стала
    /// «дорога ведёт».** Кнопка настроек уехала внутрь меню «…»
    /// 22.10, и тест, искавший `buttons["Настройки"]` прямо на экране,
    /// говорил «шестерёнка должна быть на вкладке «История»» —
    /// правдиво про кнопку и ложно про доступность.
    ///
    /// > **Сторож на КНОПКУ гаснет от переноса кнопки, даже когда
    /// > предмет цел.** Спрашивать надо то, ради чего кнопка есть.
    ///
    /// Дорогу знает один `открытьНастройки`: он сперва открывает меню,
    /// потом ищет пункт. Держать знание о дороге в каждом тесте
    /// значит чинить их по одному при следующем переносе.
    func testНастройкиДоступныСКаждойВкладки() {
        var недостижимо: [String] = []
        var осмотрено = 0
        for вкладка in ["Сегодня", "Стич", "История", "Здоровье"] {
            let кнопка = app.tabBars.buttons[вкладка].firstMatch
            guard кнопка.waitForExistence(timeout: 5) else { continue }
            кнопка.tap()
            осмотрено += 1
            if открытьНастройки(в: app) {
                // Вернуться, иначе следующая вкладка меряется
                // из настроек, а не с вкладки.
                let назад = app.navigationBars.buttons.firstMatch
                if назад.exists { назад.tap() }
            } else {
                недостижимо.append(вкладка)
            }
        }
        // Сперва — было ли что мерить: при нулевом осмотре
        // «недостижимых нет» истинно всегда.
        XCTAssertGreaterThanOrEqual(осмотрено, 3, """
            вкладок нашлось \(осмотрено) — замер не состоялся.
            «Здоровье» может отсутствовать по праву `.seeMedical`,
            остальные три обязаны быть.
            """)
        XCTAssertTrue(недостижимо.isEmpty,
                      "настройки недостижимы с вкладок: \(недостижимо)")
    }

    func testИнструкциюМожноПеречитать() {
        XCTAssertTrue(открытьНастройки(в: app), "в настройки не попасть")
        let как = найти("Как это работает", в: app)
        XCTAssertTrue(как.waitForExistence(timeout: 5))
        как.tap()
        XCTAssertTrue(app.navigationBars["Как это работает"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.navigationBars.buttons.firstMatch.exists, "должна быть кнопка назад")
    }

    /// Удаление данных подтверждается баннером. **К онбордингу
    /// при этом НЕ возвращает, и тест этого не проверяет.**
    ///
    /// Имя было `…ВозвращаетКОнбордингу` и было ложным с рождения:
    /// `DataPrivacyScreen.удалитьВсё` стирает 16 моделей и
    /// `settings.onboardingCompleted` **не трогает**. Тело теста
    /// при этом верное — оно всегда проверяло только баннер.
    ///
    /// > **Имя теста — утверждение о поведении.** Всякий, кто шёл
    /// > грепом «возвращает ли удаление к онбордингу», получал
    /// > зелёный тест с нужным словом в имени и уходил с обратной
    /// > историей.
    ///
    /// Что человек видит на самом деле: данных нет, онбординга нет,
    /// главный экран пустой. Для второго телефона в семье это путь,
    /// на котором приложение нечем объяснить — **дефект назван,
    /// хозяина у него нет** (замер 14.10). Чинить его здесь нельзя:
    /// тест не решает, каким быть поведению.
    func testУдалениеВсехДанныхПоказываетПодтверждение() {
        XCTAssertTrue(открытьНастройки(в: app), "в настройки не попасть")

        let данные = найти("Данные и приватность", в: app)
        XCTAssertTrue(данные.waitForExistence(timeout: 5))
        данные.tap()

        let удалить = найти("Удалить все данные", в: app)
        XCTAssertTrue(удалить.waitForExistence(timeout: 5))
        удалить.tap()

        let подтвердить = app.buttons["Удалить всё"].firstMatch
        XCTAssertTrue(подтвердить.waitForExistence(timeout: 3))
        подтвердить.tap()

        XCTAssertTrue(app.staticTexts["Всё удалено"].waitForExistence(timeout: 5),
                      "приложение должно подтвердить, что данных не осталось")
    }
}
