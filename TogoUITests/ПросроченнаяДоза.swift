import XCTest

/// Дорога стенда к листу просроченной дозы.
///
/// **Повод: дороги не было ни одной, и без неё кадр не снять.**
/// Разведка `[54082f]` назвала это точнее всего — «кадр без дороги это
/// не снимок, а сценарий».
///
/// Предмет не косметический. Лист предлагает три выхода после
/// пропуска, и его текст обещал «следующая доза **сдвинется**
/// на 22:40» — а расписание не сдвигается ничем, кроме явной смены
/// схемы. Человек прочёл бы это и **не дал дозу в 21:00, когда она
/// стоит**: обещание переноса читается как разрешение не давать.
/// Текст уже переписан другой рукой; эта дорога нужна, чтобы увидеть
/// результат глазом, а не поверить стражу.
///
/// ## Почему новый сценарий, а не `amber`
///
/// У `amber` часы `[8:00, 20:00]`. Просрочка там наступает после 09:00
/// и кончается в 20:00 — то есть прогон в 08:30 прошёл бы зелёным
/// при отсутствующем листе.
///
/// > **Тест, зеленеющий по времени суток, хуже отсутствующего:**
/// > он отвечает на вопрос «который час», а читается как ответ
/// > на вопрос «есть ли лист».
///
/// Сценарий `missedDose` считает часы от `now`: пропущенная доза
/// три часа назад при окне просрочки в один час.
///
/// ## Чего эта дорога НЕ закрывает
///
/// С 00:00 до ~01:10 по местному времени в сутках нет минуты,
/// отстоящей больше чем на час назад: план дня строится
/// на календарный день. В этот час лист не покажется. Тест в таком
/// случае падает **с объяснением**, а не проходит молча — пустой
/// результат за упавшей проверкой неотличим от пустого результата
/// измеренного мира.
nonisolated final class ПросроченнаяДоза: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-просроченной-дозы")
    }

    /// Суффикс партии — только с приставкой `TEST_RUNNER_`.
    ///
    /// `xcodebuild` своё окружение процессу теста не передаёт. Замерено
    /// на `Анализы.swift`: без приставки прогон зелёный, кадры снимаются
    /// и **имена у них без суффикса** — вторая партия перезаписывает
    /// первую молча, и пара для сравнения перестаёт существовать
    /// при зелёном прогоне.
    ///
    ///     TEST_RUNNER_KADR_SUFFIX=light xcodebuild … -only-testing:TogoUITests/ПросроченнаяДоза
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Иначе «снято всё» и «упал на третьем» выглядят
        // в логе ОДИНАКОВО: во втором случае строк `КАДР:` просто
        // меньше, а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своей проверкой, а не эта печать.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ПросроченнаяДоза")
        super.tearDown()
    }

    /// Кадр файлом, а не вложением: выгрузка вложений у нас не сработала
    /// пять раз из девяти. Отказ записи не роняет тест — кадр это улика,
    /// а не ворота.
    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "missedDose"]
        app.launch()
    }

    /// Элемент НА ЭКРАНЕ, а не просто «существует».
    ///
    /// `exists` отвечает «есть в дереве доступности», `isHittable` —
    /// «можно коснуться», и у ПОДПИСИ внутри прокрутки второй врёт.
    /// Нужен третий вопрос: попадает ли рамка элемента в рамку окна.
    /// Иначе имя кадра утверждает содержание, которого на нём нет.
    private func наЭкране(_ элемент: XCUIElement) -> Bool {
        guard элемент.exists else { return false }
        let окно = app.windows.firstMatch.frame
        let рамка = элемент.frame
        guard рамка.height > 0, рамка.width > 0 else { return false }
        return окно.contains(CGPoint(x: рамка.midX, y: рамка.midY))
    }

    private func содержит(_ строка: String) -> Bool {
        app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", строка)).firstMatch.exists
    }

    func testЛистПросроченнойДозыСнят() throws {
        // Первая проверка — что сценарий вообще построился.
        // Набор, которому нечего проверять, молчит так же, как набор,
        // у которого всё хорошо.
        XCTAssertTrue(app.staticTexts["Стич"].firstMatch.waitForExistence(timeout: 20),
                      "сценарий missedDose не построился — снимать нечего")

        // Час суток, в который дорога заведомо не работает, называется
        // ДО того, как тест упадёт на отсутствующем листе: иначе
        // «листа нет» прочтётся как дефект продукта.
        let часы = Calendar.current.component(.hour, from: Date())
        let минуты = Calendar.current.component(.minute, from: Date())
        let мёртвыйЧас = часы == 0 || (часы == 1 && минуты < 10)

        снять("01-план-дня-с-просроченной")

        // Строка дозы в плане дня: ищем по названию препарата.
        let строкаДозы = app.buttons.containing(
            NSPredicate(format: "label CONTAINS %@", "Левотироксин")).firstMatch
        var нашли = наЭкране(строкаДозы)
        for _ in 0..<6 where !нашли {
            app.swipeUp()
            нашли = наЭкране(строкаДозы)
        }

        if !нашли {
            снять("02-строки-дозы-НЕТ")
        }
        XCTAssertTrue(нашли, """
            строки дозы «Левотироксин» нет в плане дня\(мёртвыйЧас ? " (и сейчас МЁРТВЫЙ ЧАС: с 00:00 до ~01:10 просроченной минуты в сутках не существует — это свойство суток, не дефект)" : "").
            Если час не мёртвый — проверь три условия: `dog.isOnTreatment`,
            минута слота больше часа назад, и отсутствие `DoseRecord`
            на эту минуту. Кадр 01 снят ДО этой проверки.
            """)

        строкаДозы.tap()

        // Лист просроченной дозы. Снимаем ДО проверки: если его нет,
        // кадр покажет, что открылось вместо него, — а это разные беды.
        let лист = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "Доза")).firstMatch
        let открылся = лист.waitForExistence(timeout: 10)
        снять("03-лист-просроченной-дозы")
        XCTAssertTrue(открылся, """
            по тапу на просроченную дозу лист не открылся.
            `TodayScreen:836` отдаёт `MissedDoseTarget` только когда
            `MissedDoseAdvisor.evaluate` вернул не `nil`, — то есть
            условие просрочки не сошлось, либо тап попал не в ту строку.
            Смотри кадр 03.
            """)

        // Прокрутить лист и снять второй кадр: три выхода и текст
        // про следующую дозу в один экран могут не влезть, а кадр,
        // на котором видно половину, — это приёмка половины.
        app.swipeUp()
        снять("04-лист-прокручен")

        // ПРЕДМЕТ КАДРА, названный словами: обещание переноса.
        // Текст не должен утверждать, что расписание сдвинется, —
        // оно не сдвигается ничем, кроме явной смены схемы.
        let обещаетСдвиг = содержит("двинется") || содержит("двинутся")
        print("ОБЕЩАНИЕ СДВИГА НА ЭКРАНЕ: \(обещаетСдвиг ? "ЕСТЬ" : "нет")")
        print("""
            Это НЕ проверка: слово могло остаться в верном смысле
            («не сдвинется», «сдвинется, если сменить схему»).
            Судит человек по кадрам 03 и 04 — у него есть и текст,
            и расстановка. Строка выше нужна тому, кто читает лог
            и решает, стоит ли вообще открывать кадр.
            """)
    }
}
