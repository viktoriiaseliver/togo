import XCTest

/// Пересъёмка двух НАЛОЖЕНИЙ узкого экрана после починки каркаса.
///
/// # Что пересматривается и почему прежние кадры мертвы
///
/// `Дизайн/кадры-приёмки/узкий-экран-25.10/SE-375x667/` держит два
/// кадра с суффиксом `-НАЛОЖЕНИЕ`:
///
/// ```
/// 15-онбординг-4-что-прерывает-НАЛОЖЕНИЕ   ссылка «Потом, в настройках»
///                                          напечатана ПОВЕРХ абзаца
///                                          карточки напоминания
/// 16-онбординг-2-с-клавиатурой-НАЛОЖЕНИЕ   нижняя панель поперёк поля
///                                          веса (это БЫЛО на обоих
///                                          размерах, не только узком)
/// ```
///
/// Оба сняты на `8822698` (25.10, 18:11). Каркас переписан
/// на `.safeAreaInset` коммитом `654d4f5` (25.10, 20:39) — то есть
/// **позже съёмки**, и `654d4f5` потомок `8822698`. Значит кадры
/// показывают состояние ДО починки, а состояния ПОСЛЕ не показывает
/// ни один кадр.
///
/// > «Кадра узкого экрана нет» верно — но про починку, а не про
/// > дефект. Дефект-то как раз заснят.
///
/// # Почему не `ПоверхностьОнбординга`
///
/// Он снимает те же шаги и на 402 проходит их все, а на SE 375
/// **обрывается на третьем из четырёх** — замер 26.10.2026,
/// `ПоверхностьОнбординга.swift:240`:
///
/// ```
/// Failed to get matching snapshot: No matches found for
/// `Descendants matching type TextField` ->
/// `Elements matching predicate '"4,1" IN identifiers'`
/// ```
///
/// Поле веса опознаётся по ПОДСКАЗКЕ («4,1»), `exists` было истинно
/// и `tap()` прошёл, а `typeText` уже не нашёл элемента. Шаги 3 и 4
/// после этого не снимаются вовсе — и именно шаг 4 держит главное
/// наложение. 25.10 это обошли руками («шаги 3 и 4 здесь сняты
/// обходом»), то есть обрыв не чинился, а переступался.
///
/// Поэтому дорога здесь **не трогает поле веса совсем**: вес
/// в онбординге необязателен (`DogDraft.isValid` удалён), воротам
/// нужна только непустая кличка. Один вход меньше — один обрыв
/// меньше, а предмет партии от веса не зависит ни на один пиксель.
///
/// # Клавиатура поднимается КЛИЧКОЙ, а не весом
///
/// Предмет кадра 16 — «панель поперёк поля под поднятой клавиатурой»,
/// и какое именно поле поднимает клавиатуру, к нему отношения
/// не имеет. Кличка работает (её `typeText` прошёл в том же логе),
/// вес — нет.
nonisolated final class УзкийЭкранОнбординг: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-узкий-онбординг")
    }

    /// Только как `TEST_RUNNER_KADR_SUFFIX`: `Tools/прогон-ui.sh`
    /// приставку не ставит, и без неё партии затирают друг друга
    /// при верном числе кадров.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        // `true`: кадр снимается и после обрыва. Предмет — последний
        // шаг из четырёх, и падение на втором не должно уносить третий.
        continueAfterFailure = true
        снято = []
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "onboarding", "-Онбординг"]
        app.launch()
    }

    override func tearDown() {
        print("УЗКИЙ-КАДРОВ СНЯТО: \(снято.count) · \(снято.joined(separator: ", "))")
        // Размер окна печатается ВСЕГДА и читается у приложения,
        // а не берётся из таблицы Apple: кадр, снятый не на том
        // устройстве, снаружи неотличим от снятого на том, а имя файла
        // про устройство молчит.
        if app != nil {
            print("УЗКИЙ-ОКНО: \(app.frame)")
        }
    }

    @discardableResult
    private func снять(_ имя: String) -> Bool {
        let кадр = app.screenshot()
        let вложение = XCTAttachment(screenshot: кадр)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("УЗКИЙ-КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return true
        } catch {
            print("УЗКИЙ-КАДР НЕ ЛЁГ: \(имя) · \(error.localizedDescription)")
            return false
        }
    }

    private func дождаться(_ заголовок: String, секунд: TimeInterval = 40) -> Bool {
        app.staticTexts[заголовок].firstMatch.waitForExistence(timeout: секунд)
    }

    /// Тап по КНОПКЕ, а не по любому элементу с такой подписью.
    @discardableResult
    private func нажать(_ подпись: String) -> Bool {
        let кнопка = app.buttons[подпись].firstMatch
        guard кнопка.waitForExistence(timeout: 40) else {
            снять("ОТКАЗ-нет-кнопки-\(подпись)")
            XCTFail("кнопки «\(подпись)» нет — дальше по шагам не пройти. Смотри кадр отказа.")
            return false
        }
        кнопка.tap()
        return true
    }

    /// Убрать клавиатуру тапом по НАЗВАННОМУ заголовку, не наугад:
    /// тап наугад уходил по «Назад» на первый экран, и кадров
    /// выходило ноль (`ПоверхностьОнбординга:156`).
    private func убратьКлавиатуру(заголовок: String) {
        guard app.keyboards.element.exists else { return }
        let цель = app.staticTexts[заголовок].firstMatch
        guard цель.exists else {
            XCTFail("убратьКлавиатуру: заголовка «\(заголовок)» нет, тап наугад запрещён")
            return
        }
        цель.tap()
        _ = app.keyboards.element.waitForNonExistence(timeout: 10)
    }

    func testЧетыреШагаНаУзком() {
        // 1 · Приветствие. Опознаётся кнопкой: «Начать» стоит только
        // здесь и только при пустой базе (иначе «Перечитать»).
        XCTAssertTrue(app.buttons["Начать"].firstMatch.waitForExistence(timeout: 40), """
            Первый шаг не показался. «Перечитать» вместо «Начать» → \
            не доехал -Сценарий onboarding; виден таб-бар → не доехал \
            -Онбординг; пусто вовсе → приложение не поднялось.
            """)
        снять("12-онбординг-1-приветствие")
        guard нажать("Начать") else { return }

        // 2 · Кличка. Кадр ДО ввода: в макете форма пустая.
        XCTAssertTrue(дождаться("Кто у тебя живёт"), "Шаг собаки не открылся")
        снять("13-онбординг-2-кто-живёт")

        // 2-бис · ТОТ ЖЕ ШАГ С ПОДНЯТОЙ КЛАВИАТУРОЙ — предмет кадра 16.
        let кличка = app.textFields["Кличка"].firstMatch
        if кличка.waitForExistence(timeout: 10) {
            кличка.tap()
            // Ждём саму клавиатуру, а не «немного»: кадр, пойманный
            // на полпути её выезда, показывает не то положение панели.
            if app.keyboards.element.waitForExistence(timeout: 10) {
                снять("16-онбординг-2-с-клавиатурой")
            } else {
                снять("16-ОТКАЗ-клавиатура-не-поднялась")
                print("УЗКИЙ-ЗАМЕР: тап по полю клички клавиатуру не поднял")
            }
            кличка.typeText("Стич")
        } else {
            снять("16-ОТКАЗ-нет-поля-клички")
            XCTFail("поля «Кличка» нет — клавиатуру поднять нечем, кадр 16 не снят")
        }

        // Поле ВЕСА нарочно не трогается: ровно на нём обрывается
        // `ПоверхностьОнбординга` на этом устройстве (разбор в голове).
        убратьКлавиатуру(заголовок: "Кто у тебя живёт")
        guard нажать("Дальше") else { return }

        // 3 · Режим дня.
        if дождаться("Режим дня") {
            снять("14-онбординг-3-режим-дня")
            guard нажать("Дальше") else { return }
        } else {
            снять("14-ОТКАЗ-режим-дня-не-открылся")
            XCTFail("шаг «Режим дня» не открылся — смотри кадр отказа")
            return
        }

        // 4 · Что будет прерывать — ГЛАВНЫЙ предмет партии.
        // «Разрешить» не жмём: системный алерт блокирует всё следом.
        if дождаться("Что будет прерывать") {
            снять("15-онбординг-4-что-прерывает")
            проверитьДостижимостьНапоминания()
        } else {
            снять("15-ОТКАЗ-уведомления-не-открылись")
            XCTFail("шаг «Что будет прерывать» не открылся — смотри кадр отказа")
        }
    }

    /// **«Наложения нет» и «того, что накладывалось, нет на экране» —
    /// разные утверждения, и кадр сверху их не различает.**
    ///
    /// На кадре 15 после починки наложения действительно нет: три
    /// карточки прерываний читаются целиком, «Разрешить» и «Потом,
    /// в настройках» стоят внизу с воздухом. Но **карточки «Одно
    /// напоминание в 08:00» на кадре нет вовсе** — а 25.10 поверх неё
    /// как раз и печаталась ссылка, и на 402 pt она видна
    /// (`онбординг-26.10/04-что-будет-прерывать-dark.png`).
    ///
    /// Отсюда два исхода, и по кадру сверху они одинаковы:
    ///
    /// ```
    /// карточка ниже сгиба, прокруткой достаётся  → починка, вид
    ///                                              как у всякого
    ///                                              длинного экрана
    /// карточка НЕ достаётся                      → ПОТЕРЯ СОДЕРЖИМОГО,
    ///                                              и это хуже
    ///                                              наложения
    /// ```
    ///
    /// Правило проекта записано дословно у соседа
    /// (`КегльAX5:342`): «„Карточку подрезает кнопка" и „карточку
    /// НЕ ДОСТАТЬ" — разные утверждения». Карточка в коде стоит
    /// **безусловно** (`OnboardingSteps:726`), то есть вопрос ровно
    /// о достижимости.
    ///
    /// Заголовок карточки содержит час из настроек, поэтому ищется
    /// по НАЧАЛУ подписи, а не целиком: «08:00» — данные, и прибивать
    /// их в тест значит завести вторую копию значения.
    private func проверитьДостижимостьНапоминания() {
        let карточка = app.staticTexts.matching(
            NSPredicate(format: "label BEGINSWITH %@", "Одно напоминание")).firstMatch

        let виднаСразу = карточка.exists
        var дошли = виднаСразу
        if !дошли {
            for _ in 0..<6 {
                app.swipeUp()
                if карточка.exists { дошли = true; break }
            }
        }
        снять("15b-онбординг-4-низ-прокручен")

        // ГЕОМЕТРИЯ — ДРУГОЙ КАНАЛ, ЧЕМ ПИКСЕЛИ, и здесь он решает.
        //
        // `exists` отвечает про ДЕРЕВО и истинно для элемента, уехавшего
        // за край: первый заход 26.10 напечатал «достижима=true»,
        // а кадр до и кадр после шести свайпов вышли ПОБАЙТОВО
        // одинаковыми (md5 `f69715dc…`). То есть `exists` здесь —
        // прокси, и он показал ровно обратное правде.
        //
        // Рамка различает два исхода, которые пиксели не различают:
        //
        //   рамка ниже окна          разложена, но не прокручивается
        //   рамка нулевая / в окне   не разложена вовсе
        //
        // Печатается и рамка окна: «ниже окна» без высоты окна —
        // число без оси.
        let окно = app.frame
        let рамка = карточка.exists ? карточка.frame : .zero
        print("УЗКИЙ-ЗАМЕР: «Одно напоминание» exists=\(виднаСразу) · "
              + "после свайпов exists=\(дошли) · hittable=\(карточка.exists ? карточка.isHittable : false)")
        print("УЗКИЙ-ГЕОМЕТРИЯ: окно \(окно) · рамка карточки \(рамка)")
        if рамка != .zero {
            print("УЗКИЙ-ГЕОМЕТРИЯ: карточка ниже окна на \(рамка.minY - окно.maxY) pt "
                  + "(минус = внутри окна)")
        }
        // Приёмка — ВИДНА ЛИ, а не лежит ли в дереве.
        let видна = карточка.exists && карточка.isHittable
        дошли = видна
        XCTAssertTrue(дошли, """
            Карточка «Одно напоминание в …» не достаётся прокруткой \
            на 375 × 667. В коде она стоит безусловно \
            (`OnboardingSteps:726`), значит это ПОТЕРЯ СОДЕРЖИМОГО, \
            а не косметика, и она хуже прежнего наложения: там текст \
            был нечитаем, здесь его нет совсем. Кадр — 15b.
            """)
    }
}
