import XCTest

/// Экран семьи с ПОДНЯТОЙ КЛАВИАТУРОЙ — состояние, которого не было
/// ни на одном из 209 кадров приёмки.
///
/// **Почему это отдельное условие, а не частность.** В `CLAUDE.md`
/// записано: «Кадров с поднятой клавиатурой нет ни одного — это
/// условие стенда, которого не было, и оно отдельное от „узкий
/// экран“ и „крупный кегль“». Крупный кегль и узкий экран сжимают
/// раскладку сверху; клавиатура съедает её снизу и прячет **кнопку
/// подтверждения** — то есть ровно то, ради чего человек на экран
/// пришёл.
///
/// **Почему именно экран семьи.** Это единственное место, куда мама
/// вводит текст о себе: `FamilyScreen.swift:489`, поле с плейсхолдером
/// «Мама». Кнопка «Добавить» лежит в подвале листа
/// (`FamilyScreen.swift:513`) и гаснет на пустом имени — значит
/// человек обязан печатать, а потом дотянуться до кнопки, которой
/// в этот момент может не быть на экране.
///
/// **Что кадр отвечает, а тест — нет.** Тест проверяет, верно ли
/// посчитано; кадр — верно ли сказано. Здесь нет числа, которое
/// можно сверить: есть раскладка, которую видит человек, и вопрос
/// «видно ли кнопку, когда клавиатура поднята». Ответ берётся глазом.
///
/// **Чего этот тест НЕ проверяет, и это надо сказать вслух.** Он
/// снимает кадр от ВЛАДЕЛЬЦА. Состояние мамы — наблюдателя в чужом
/// дневнике — ни одним входом стенда не достижимо: во всех десяти
/// сценариях `SeedData.Scenario` «я» это
/// `FamilyMember(name: "Виктория", role: .owner, isMe: true)`
/// (`SeedData.swift:346`), а признак гостя `SharedZoneOwner.isGuest`
/// лежит в `UserDefaults` группы приложений (`SharedZone.swift:20-23`),
/// куда `launchArguments` не достают. Поверхность без входа лечится
/// переделкой входа, а не старанием — и до неё этот файл не дотянется.
///
/// **Куда пишет.** Кадры ложатся в `build/кадры-клавиатуры/`, путь
/// выведен из `#filePath`. Значит тест ломается от уборки каталога —
/// и ломается не на своём предмете. `build/` в `.gitignore`: то,
/// что нужно сохранить, выносится в `Дизайн/кадры-приёмки/` и
/// коммитится отдельно.
nonisolated final class КлавиатураНаСемье: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-клавиатуры")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Вернуть Pro в исходное — **обязательно, а не вежливо.**
    ///
    /// `debugOverride` пишется в `UserDefaults.standard`
    /// (`Subscriptions.swift:25`) и переживает запуск. Оставить его
    /// включённым значит отдать следующему тесту набора подписку,
    /// которой у него быть не должно, — и он позеленеет не на том
    /// состоянии. Это та же грабля, по которой в `TogoApp.init():95`
    /// стоит `ActiveSessionStore.save(nil)`: «прогулка переживает
    /// предыдущий тест».
    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода, и ПЕРВОЙ строкой — ниже стоит `guard … else { return }`,
        // то есть за ним печать уже не выполнилась бы.
        //
        // Иначе «снято всё» и «упал на третьем» выглядят в логе
        // ОДИНАКОВО: строк `КАДР:` просто меньше, а отсутствия
        // никто не ищет.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        guard app?.state == .runningForeground else { return }
        переключитьPro(в: false)
    }

    /// Включить или выключить Pro **тем же путём, что и человек**.
    ///
    /// Сперва здесь стоял `-debug.pro 1` в `launchArguments` — расчёт
    /// на то, что значение осядет в `NSArgumentDomain` и его прочтёт
    /// `UserDefaults.standard.object(forKey:) as? Bool`
    /// (`Subscriptions.swift:43`). Отброшено: аргумент командной
    /// строки хранится строкой, `as? Bool` на строке даёт `nil`,
    /// и ворот **молча** остался бы закрытым. Тест упал бы на
    /// «лист не открылся», и причину пришлось бы искать там, где её
    /// нет.
    ///
    /// Настоящий путь надёжнее допущения: переключатель
    /// `SettingsScreen.swift:89` — то, чем это включают руками.
    @discardableResult
    private func переключитьPro(в состояние: Bool) -> Bool {
        let шестерёнка = app.buttons["Настройки"].firstMatch
        guard шестерёнка.waitForExistence(timeout: 10) else { return false }
        шестерёнка.tap()

        // Переключатель лежит в разделе подписки, низко: «не нашёл»
        // без прокрутки значило бы «не доскроллил».
        let тумблер = app.switches["Отладка · включить Pro"].firstMatch
        for _ in 0..<10 where !тумблер.exists { app.swipeUp() }
        guard тумблер.waitForExistence(timeout: 5) else { return false }

        // `value` у тумблера — "0"/"1". Жмём, только если надо
        // изменить: повторное нажатие вернуло бы всё назад.
        let было = включён(тумблер)
        if было != состояние {
            // **Тап по КООРДИНАТЕ, а не по элементу** — замер 21.10.2026
            // по дереву из `.xcresult` упавшего прогона:
            //
            // ```
            // то, что берёт firstMatch   контейнер строки {{16,368.3},{370,52}}
            // сам управляющий Switch     {{309.0,380.3},{63,28}} — на 108 pt правее
            // куда бил тап               {201.0, 394.3} — в ПОДПИСЬ
            // исход                      value остался "0" весь опрос, пять секунд
            // ```
            //
            // Через вложенность не берётся: приложение само пишет в лог
            // «Switch, value: 0 is not actually a child of Switch,
            // label: 'Отладка · включить Pro'» — два `Switch`-узла
            // в AX-дереве НЕ родитель и ребёнок, поэтому
            // `тумблер.switches.firstMatch` до внутреннего может
            // не дойти. Координата от правого края контейнера попадает
            // в контрол при любой его вложенности.
            тумблер.coordinate(withNormalizedOffset: CGVector(dx: 0.9, dy: 0.5)).tap()
        }

        // **ИСХОД НАДО ДОЖДАТЬСЯ, А НЕ ПРОЧИТАТЬ.**
        //
        // Прогон 17:35 сказал «тумблер нажат» и не включил Pro —
        // я починил это проверкой исхода вместо намерения. Прогон
        // 18:28 упал уже на самой проверке, и причина оказалась
        // в ней же: `value` читался **сразу** после `tap()`, а дерево
        // доступности обновляется асинхронно. То есть я поймал гонку
        // и прочитал старое значение.
        //
        // > Проверять исход — правильно. Но исход бывает ещё не
        // > наступившим, и мгновенное чтение отвечает про **момент**,
        // > а не про результат.
        //
        // Это третья редакция одного места, и каждая предыдущая
        // ошибка была честной формой предыдущей правды.
        let дождались = ждать(до: 5) { включён(тумблер) == состояние }
        guard дождались else {
            // Улика, а не только вердикт: без кадра «почему не
            // переключился» разбирается следующим слотом стенда.
            try? снять("0-ОТКАЗ-тумблер-не-переключился")
            print("ТУМБЛЕР: value=\(тумблер.value ?? "nil") надо=\(состояние)")
            return false
        }

        app.navigationBars.buttons.firstMatch.tap()
        return true
    }

    /// Состояние тумблера одним вопросом.
    ///
    /// `value` у `Toggle` приходит строкой "0"/"1", но SwiftUI волен
    /// отдать и `Bool`, и `NSNumber`. Спрашивать одну форму значит
    /// получить ответ про мерку: `as? String` на `NSNumber` даёт `nil`,
    /// то есть «выключен» — и это читалось бы как состояние продукта.
    private func включён(_ тумблер: XCUIElement) -> Bool {
        switch тумблер.value {
        case let s as String: return s == "1" || s == "true"
        case let b as Bool: return b
        case let n as NSNumber: return n.boolValue
        default: return false
        }
    }

    /// Подождать условия, опрашивая его. Возвращает, наступило ли.
    ///
    /// Не `waitForExistence`: тот спрашивает про существование
    /// элемента, а нам нужно **изменение значения** у существующего.
    private func ждать(до секунд: TimeInterval, _ условие: () -> Bool) -> Bool {
        let край = Date().addingTimeInterval(секунд)
        while Date() < край {
            if условие() { return true }
            _ = XCTWaiter.wait(for: [XCTestExpectation(description: "такт")],
                               timeout: 0.2)
        }
        return условие()
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    /// Кадр окна файлом, а не `XCTAttachment`.
    ///
    /// Выгрузка вложений в этом проекте уже измерена: не сработала
    /// пять раз из девяти. Вложение, которое не выгружается, — это
    /// кадр, которого нет.
    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        снято.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    func testКлавиатураНаВводеИмениСнятаДляЧеловека() throws {
        // Ворот «двое бесплатно» (`ProGate.familyBeyondTwo`,
        // порог `members.count < 2` в `ProLimit`) при ПЯТИ участниках
        // демо-базы закрыт, и кнопка «Добавить человека» уводит
        // на пейволл. Снят был бы ПЕЙВОЛЛ — кадр, похожий на нужный
        // ровно настолько, чтобы обмануть.
        XCTAssertTrue(переключитьPro(в: true), """
            до переключателя Pro не дошли — значит ворот подписки
            остался закрытым, и всё ниже снимало бы не тот экран.
            Это отказ ВХОДА, и он не равен «экрана семьи нет».
            """)

        let вкладка = app.tabBars.buttons["Семья"].firstMatch
        XCTAssertTrue(вкладка.waitForExistence(timeout: 10),
                      "вкладки «Семья» нет — кадра нет, и это не «экрана нет»")
        вкладка.tap()
        XCTAssertTrue(app.navigationBars["Семья"].waitForExistence(timeout: 5),
                      "экран семьи не открылся")

        var пути: [URL] = []
        пути.append(try снять("1-семья-без-клавиатуры"))

        let добавить = app.buttons["Добавить человека"].firstMatch
        XCTAssertTrue(добавить.waitForExistence(timeout: 5),
                      "кнопки «Добавить человека» нет")
        добавить.tap()

        // КАДР СНИМАЕТСЯ ДО УТВЕРЖДЕНИЯ, и это не лишний файл.
        //
        // Прогон 17:35 упал ровно здесь — «лист не открылся», — и кадра
        // того, что было на экране ВМЕСТО листа, не осталось. Пейволл
        // это, пустота или лист с другим заголовком, разбиралось бы
        // следующим заходом, то есть ещё одним слотом стенда.
        //
        // > Фильтр, убирающий шум, убирает и улику.
        пути.append(try снять("2-после-нажатия-добавить"))

        // Ворот подписки мог не открыться — и тогда перед нами пейволл,
        // а не лист. Это РАЗНЫЕ кадры, и спутать их значит принять
        // чужой экран за свой. Спрашиваем предмет по заголовку листа,
        // а не по тому, что «что-то появилось».
        let лист = app.staticTexts["Новый участник"].firstMatch
        XCTAssertTrue(лист.waitForExistence(timeout: 5), """
            лист «Новый участник» не открылся. Если на экране пейволл —
            значит Pro не включился, несмотря на пройденный
            переключатель, и ворот `ProGate.familyBeyondTwo` увёл
            кнопку в покупку. Тогда это отказ ВХОДА, а не отсутствие
            экрана, и разбирать надо вход.
            """)
        пути.append(try снять("3-лист-до-клавиатуры"))

        // Поле ищется по плейсхолдеру: `FamilyScreen.swift:489`
        // объявляет `TextField("Мама", …)`, и плейсхолдер здесь —
        // единственное имя, которое у поля есть.
        let поле = app.textFields["Мама"].firstMatch
        XCTAssertTrue(поле.waitForExistence(timeout: 5),
                      "поля ввода имени нет — печатать негде")
        поле.tap()

        // КЛЮЧЕВАЯ ПРОВЕРКА. Без неё кадр «с клавиатурой» мог бы
        // оказаться кадром без неё, а отличить их на глаз в отчёте
        // уже нельзя: оба выглядят как экран. `isHittable` тут
        // не годится — он отвечает про видимость, а вопрос
        // про существование.
        XCTAssertTrue(app.keyboards.element.waitForExistence(timeout: 5), """
            клавиатура НЕ поднялась. Кадр ниже снимать нельзя: он был бы
            обычным листом под именем «с клавиатурой» — то есть приёмкой
            условия, которого на кадре нет.
            """)
        пути.append(try снять("4-клавиатура-поднята-поле-пустое"))

        поле.typeText("Мама")

        // Кнопка подтверждения живёт в подвале листа и гаснет
        // на пустом имени (`FamilyScreen.swift:513`). Теперь имя
        // введено — значит она ДОЛЖНА быть доступна. Спрашиваем
        // существование и попадаемость РАЗНЫМИ вопросами: «кнопка
        // есть, но её не достать из-под клавиатуры» — это и есть
        // предмет кадра, и он не равен «кнопки нет».
        let подтвердить = app.buttons["Добавить"].firstMatch
        let естьКнопка = подтвердить.waitForExistence(timeout: 5)
        let достатьМожно = естьКнопка && подтвердить.isHittable
        пути.append(try снять("5-клавиатура-поднята-имя-введено"))

        print("""
            ВЫВОД ДЛЯ ГЛАЗА:
              кнопка «Добавить» существует : \(естьКнопка)
              до неё можно дотянуться      : \(достатьМожно)
            Если первое ИСТИНА, а второе ЛОЖЬ — кнопка под клавиатурой,
            и человек с поднятой клавиатурой завершить ввод не может.
            """)

        XCTAssertTrue(естьКнопка, """
            кнопки «Добавить» нет вовсе при введённом имени — это уже
            не про клавиатуру, а про подвал листа.
            """)

        print("СНЯТО КАДРОВ: \(пути.count) · \(каталог.path)")
    }
}
