import XCTest

/// Кадры приёмки по двум решениям дизайна от 23.10.2026:
/// демо-набор Т4 (пункт 10) и жетон фото собаки (пункт 9).
///
/// # Почему без этого файла приёмки не было
///
/// Ни один сценарий не заводил `LabResult` — замер 08.10.2026,
/// повторён 23.10, — и кадр `14-анализы` снимался **на пустом
/// экране**. Сверять его с `Дизайн/эталонные-кадры/ios28-кино-22.10/
/// screenshots/14.png` было нельзя: это «состояние недостижимо»,
/// а не «кадр не снят», и лечится оно входом, а не взглядом.
///
/// Вход — флаг `-ДемоТ4` поверх сценария `amber`. **Он живёт только
/// в отладочной сборке** (`#if DEBUG` в `SeedData`), решение Виктории
/// 23.10.2026: «включается при запуске отладочной сборки и в
/// UI-тестах, в релиз не попадает». Человеку этого входа не дают
/// намеренно — владеет им стенд.
///
/// # Чего этот файл НЕ утверждает
///
/// - **Что набора нет в релизе.** Тест собирается в Debug и видит
///   флаг по устройству. Про релиз отвечают символы в бинарнике.
/// - **Что системный выбор фото открылся.** `PhotosPicker` работает
///   в отдельном процессе, стенд его не достаёт. Проверяется только
///   то, что у жетона есть имя, признак кнопки и он достижим.
/// - **Что кадр совпал с эталоном.** Кадры кладутся файлами, судит
///   их человек.
nonisolated final class ДемоТ4: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-демо-т4")
    }

    /// Суффикс партии приходит СНАРУЖИ и только с приставкой
    /// `TEST_RUNNER_` — иначе `xcodebuild` его не передаёт, а кадры
    /// разных тем перезаписали бы друг друга молча (замер
    /// `TogoUITests/Анализы.swift:81-98`).
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    private var снято: [String] = []

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        // `amber` несёт схему левотироксина с дозами 08:00 и 20:00 —
        // без неё часы от дозы не посчитать, и заготовка падает
        // предусловием, а не рисует кадр с другими подписями.
        app.launchArguments = ["-UITesting", "-Сценарий", "amber", "-ДемоТ4"]
        app.launch()
    }

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода: «снято всё» и «упал на втором» выглядят в логе
        // одинаково, а отсутствия строк никто не ищет.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    private func докрутить(до элемент: XCUIElement, шагов: Int = 8) -> Bool {
        for _ in 0..<шагов {
            if элемент.exists && элемент.isHittable { return true }
            app.swipeUp()
        }
        return элемент.exists && элемент.isHittable
    }

    // MARK: Жетон в шапке «Сегодня»

    /// Снимается ПЕРВЫМ и до перехода на другие вкладки: у второго
    /// входа то же имя для озвучки, что у первого («Снимок собаки»),
    /// и ключ каталога у них общий нарочно — новых строк правка
    /// не заводит. Пока вкладка собаки не открыта, имя в дереве одно.
    func testЖетонВШапкеСегодняОткрываетВыборФото() throws {
        XCTAssertTrue(app.staticTexts["Стич"].firstMatch.waitForExistence(timeout: 20),
                      "сценарий не построился — снимать нечего")

        let жетон = app.buttons["Снимок собаки"].firstMatch
        let есть = жетон.waitForExistence(timeout: 10)

        // Кадр ДО проверки: при `continueAfterFailure = false` всё, что
        // стоит за упавшим утверждением, не исполняется никогда, и
        // «кадра нет» прочлось бы как свойство продукта.
        снять("20-сегодня-жетон-пустой")

        XCTAssertTrue(есть, """
            в шапке «Сегодня» нет кнопки «Снимок собаки». Либо жетон \
            снова немой аватар, либо `TGAvatar` спрятал его от озвучки \
            и элемент не собрался — второе хуже: вход есть, а слепой \
            человек его не найдёт.
            Кадр 20 снят ДО этой проверки — смотри, что в шапке.
            """)
        XCTAssertTrue(жетон.isHittable,
                      "жетон есть, но до него не дотянуться — вход без механизма")
    }

    // MARK: Демо-набор Т4

    func testЭкранАнализовСДемоНабором() throws {
        XCTAssertTrue(app.staticTexts["Стич"].firstMatch.waitForExistence(timeout: 20),
                      "сценарий не построился — снимать нечего")

        let вкладка = app.tabBars.buttons["Здоровье"]
        XCTAssertTrue(вкладка.waitForExistence(timeout: 15),
                      "вкладки «Здоровье» нет — либо лечения нет, либо её закрыло право `seeMedical`")
        вкладка.tap()
        _ = app.navigationBars["Здоровье"].waitForExistence(timeout: 10)

        // Ярлык строки несёт счёт записей («Анализы, 4 записи»),
        // поэтому предикат по началу, а не точное совпадение.
        let строка = app.buttons.containing(
            NSPredicate(format: "label BEGINSWITH %@", "Анализы")
        ).firstMatch
        let дошли = докрутить(до: строка)
        снять("21-здоровье-строка-анализов")
        XCTAssertTrue(дошли, "на «Здоровье» нет строки «Анализы» даже после прокрутки")

        строка.tap()
        let открылся = app.navigationBars["Анализы"].waitForExistence(timeout: 10)
        снять("22-анализы-демо-т4")
        XCTAssertTrue(открылся, "экран анализов не открылся")

        // **Контроль, что снимали не заглушку.** Без него кадр пустого
        // состояния выглядел бы приёмкой — ровно то, что случилось
        // с кадром `14-анализы` 23.10.2026.
        XCTAssertFalse(app.staticTexts["Анализов пока нет"].exists, """
            на кадре пустое состояние при четырёх записях заготовки. \
            Либо флаг `-ДемоТ4` не доехал до `SeedData`, либо записи \
            легли не этой собаке.
            """)

        // Четыре числа с кадра 14 — по одному утверждению на точку,
        // чтобы красное называло, какая именно разошлась.
        for число in ["1,8", "2,6", "2,9", "3,1"] {
            XCTAssertTrue(
                app.staticTexts.containing(
                    NSPredicate(format: "label CONTAINS %@", число)
                ).firstMatch.waitForExistence(timeout: 5),
                "на экране нет значения \(число) — набор разошёлся с кадром 14")
        }
    }
}
