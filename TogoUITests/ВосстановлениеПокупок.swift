import XCTest

/// Кадр поверхности, которую до 30.09 не видел глазами никто.
///
/// **Почему её нельзя было снять.** Отказ восстановления показывается
/// только после броска `AppStore.sync()`, а живого отказа в симуляторе
/// не добиться: локальная конфигурация StoreKit под `xcodebuild`
/// не подхватывается, симулятор идёт в песочницу живого магазина.
/// Поверхность была не «непроверенной», а **непроверяемой**, и лечится
/// это входом — аргументом `-Восстановление`, — а не внимательностью.
///
/// **Что именно доказывает этот файл, помимо кадра.** Тексты отказа
/// присваивались литералом в `String?` и рисовались **дословно мимо
/// каталога**: французский и украинский лежали в каталоге готовыми
/// и не доезжали до экрана ни разу. Полнота каталога этого не ловит
/// по устройству — ключ есть, перевод есть, на экране прежнее. Ловит
/// только сравнение **того, что на экране**, с тем, что лежит
/// в каталоге для языка прогона, — и `Подписи` берёт его из того же
/// файла, который собирается в бандл.
///
/// Прогон на языке: `xcodebuild … -testLanguage fr`.
///
/// **Граница.** Файл смотрит на экран приложения. Он не отвечает
/// на вопрос, бросит ли живой магазин именно эту ошибку: набор случаев
/// `StoreKitError` прочитан в SDK, а не измерен.
nonisolated final class ВосстановлениеПокупок: XCTestCase {

    private let т = Подписи()

    private func запустить(исход: String) -> XCUIApplication {
        let app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Восстановление", исход]
        app.launch()
        XCTAssertTrue(app.staticTexts["Стич"].waitForExistence(timeout: 10),
                      "приложение не поднялось на языке «\(т.язык)»")
        // ЧЕРЕЗ ПОМОЩНИКА, А НЕ НАПРЯМУЮ (правка 25.10.2026).
        //
        // Прямой `buttons["Настройки"]` перестал находиться: решением
        // Виктории 22.10 шестерёнка ушла в меню «…», и **дети `Menu`
        // не существуют в дереве доступности, пока меню не открыто**.
        // Это не «кнопки нет» — третье состояние, и от первого
        // неотличимо.
        //
        // Все пять тестов класса падали здесь. Замер: на вершине,
        // в одиночку, своё устройство — 5 отказов из 5, то есть
        // ни нагрузка, ни чужая фикстура, а дорога.
        XCTAssertTrue(открытьНастройки(в: app),
                      "в настройки не попасть ни прямой кнопкой, ни через «…»")
        XCTAssertTrue(app.navigationBars[т("Настройки")].waitForExistence(timeout: 5),
                      "не открылись настройки — дальше смотреть не на что")
        return app
    }

    private func снять(_ app: XCUIApplication, _ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "\(т.язык)-\(имя)"
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Первой — проверка, что входу вообще есть что показать.
    ///
    /// Без неё остальные были бы зелёными, ничего не проверив: экран
    /// без плашки не содержит ни верного текста, ни неверного, и
    /// «неверного нет» на нём истинно всегда.
    func test01ВходСтавитПлашкуОтказа() {
        let app = запустить(исход: "storefront")
        XCTAssertTrue(app.staticTexts[т("Не получилось")].waitForExistence(timeout: 5),
                      "плашки отказа нет вовсе — аргумент -Восстановление не сработал, "
                      + "и всё, что скажут остальные проверки этого файла, будет про экран без неё")
        снять(app, "01-отказ-витрина-страны")
    }

    /// Тот самый дефект: текст обязан быть **из каталога**, а не русским
    /// литералом. Проверка от обратного — требует присутствия перевода,
    /// а не отсутствия русского: «русского нет» было бы истинно и на
    /// пустом экране.
    func test02ТекстОтказаПриходитИзКаталога() {
        let app = запустить(исход: "storefront")
        let ожидаемый = т("В App Store твоей страны подписки Togo нет. Дело не в твоём Apple ID.")
        XCTAssertTrue(app.staticTexts[ожидаемый].waitForExistence(timeout: 5),
                      "на языке «\(т.язык)» экран не показывает перевод, который лежит "
                      + "в каталоге: ожидалось «\(ожидаемый)». Именно так выглядит строка, "
                      + "присвоенная литералом мимо каталога")
    }

    /// Вторая причина — второй текст. Один текст на несколько причин
    /// и есть починенный дефект, и кадр обязан показать, что их два.
    func test03УВторойПричиныДругойТекст() {
        let app = запустить(исход: "notEntitled")
        let ожидаемый = т("Дело не в твоих настройках: приложению не разрешено спрашивать App Store. Напиши нам.")
        XCTAssertTrue(app.staticTexts[ожидаемый].waitForExistence(timeout: 5),
                      "у причины «прав нет у сборки» на экране не её текст")
        снять(app, "02-отказ-прав-нет-у-сборки")
    }

    /// Совет «проверь связь» верен для одной причины из четырёх.
    /// На этой — неверен, и его тут быть не должно.
    func test04СоветПроСвязьНеПоказываетсяТамГдеНеПомогает() {
        let app = запустить(исход: "storefront")
        let сетевой = т("Не удалось восстановить покупки. Проверь связь и попробуй ещё раз.")
        XCTAssertFalse(app.staticTexts[сетевой].waitForExistence(timeout: 2),
                       "на отказе про витрину страны экран советует проверить связь — "
                       + "это и есть починенный дефект, вернувшийся на поверхность")
    }

    /// Отмена человеком — не отказ, и красной плашки быть не должно.
    ///
    /// Проверка именно на **отсутствие** плашки, поэтому рядом стоит
    /// `test01`: он доказывает, что плашка вообще умеет появляться,
    /// и без него это «отсутствие» ничего не значило бы.
    func test05ЗакрытоеОкноВходаНеРисуетОтказа() {
        let app = запустить(исход: "cancelled")
        XCTAssertFalse(app.staticTexts[т("Не получилось")].waitForExistence(timeout: 2),
                       "человек сам закрыл окно входа в App Store, а экран говорит ему "
                       + "о поломке")
        снять(app, "03-отмена-человеком-молчит")
    }
}
