import XCTest

/// Норма врача: экран не называет нормой то, чего никто не называл.
///
/// **Предмет — красная линия проекта**, записанная в `CLAUDE.md`
/// дословно: «Не подставлять там, где подстановка станет утверждением
/// человека. Время забора, вес у рецепта, норма с бланка, предел
/// прибора — пустые намеренно. Подсказку человек подтверждает,
/// подстановку — нет, а запись потом читает врач».
///
/// Что было до этого файла (замер 25.10.2026):
///
/// ```
/// ScheduleDraft.dailyGrams = 120            умолчание ЧЕРНОВИКА
/// OnboardingFlow.saveDog() → apply(to:)     → dog.setDailyGrams(120)
/// ModeStep (шаг «Режим дня»)                граммов НЕ СПРАШИВАЕТ
/// FeedingScreen:207                         «НОРМА ВРАЧА ÷ КОРМЛЕНИЯ»
/// FeedingScreen:210                         «120 ÷ 2 = 60 г»
/// FeedingScreen:266                         «приложение её не выдумывает»
/// ```
///
/// То есть человек, который ни одного раза не вводил норму, читал наше
/// умолчание как назначение врача — и абзацем ниже читал обещание, что
/// приложение норму не выдумывает.
///
/// ## Почему настоящий вход, а не `-Онбординг`
///
/// Дешёвый вход `-UITesting -Онбординг` рисует шаги по просьбе,
/// но `пишемВБазу` у него **ложно** — собака не заводится вовсе.
/// А предмет здесь ровно в том, **что записалось в базу** и что потом
/// показано как норма. Значит нужен настоящий первый запуск
/// на стёртом устройстве, и цена этого — своё, не общее устройство.
///
/// ## Вес не вводится НАРОЧНО
///
/// Вес с 23.10.2026 не обязателен, и проход без него — это и есть
/// самый частый проход: человек жмёт «Дальше», не заполняя того, чего
/// у него под рукой нет. Норма врача под рукой тем более не лежит.
///
/// ## Ось сторожа — число, выданное за чужое слово, а не «есть ли блок»
///
/// Сторож на «есть ли заголовок» был бы прокси: его погасило бы любое
/// переименование. Здесь ось — **видно ли на экране число, которого
/// никто не называл**, и рядом, в том же замере, стоит положительный
/// контроль «мы вообще дошли до экрана питания». Без контроля зелёное
/// этого файла неотличимо от «экран не открылся»: подписи «120» нет
/// и на пустом экране тоже.
nonisolated final class НормаВрачаНеВыдумана: XCTestCase {

    private var app: XCUIApplication!

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-нормы")
    }

    /// Суффикс партии доезжает только как `TEST_RUNNER_KADR_SUFFIX`:
    /// `xcodebuild` отдаёт процессу теста лишь переменные с этой
    /// приставкой, снимая её.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    private var снято: [String] = []

    override func setUp() {
        continueAfterFailure = false
        снято = []
        app = XCUIApplication()
    }

    /// Счёт печатается ВСЕГДА, в том числе после падения посреди прохода:
    /// «снято пять» и «упал на третьем» выглядят в логе одинаково —
    /// во втором случае строк `КАДР:` просто меньше, а отсутствия
    /// не ищет никто.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "НормаВрачаНеВыдумана")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ имя: String) -> URL? {
        let кадр = app.screenshot()
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return путь
        } catch {
            print("КАДР НЕ ЗАПИСАН: \(имя) · \(error)")
            return nil
        }
    }

    /// Все непустые подписи экрана.
    ///
    /// Берутся по всему дереву, а не у `staticTexts`: у строки нормы
    /// стоит `accessibilityElement(children: .ignore)`, и её число
    /// живёт в подписи КОНТЕЙНЕРА, а не в тексте. Проверка только
    /// по `staticTexts` дала бы ложное зелёное.
    private func подписи() -> [String] {
        app.descendants(matching: .any).allElementsBoundByIndex
            .filter { $0.exists && !$0.label.isEmpty }
            .map { $0.label }
    }

    /// Отказ называет, ЧТО на экране, а не только чего на нём нет.
    private func дождаться(_ заголовок: String, секунд: TimeInterval = 90) -> Bool {
        if app.staticTexts[заголовок].firstMatch.waitForExistence(timeout: секунд) {
            return true
        }
        let всё = подписи()
        print("""
        НЕ ДОЖДАЛСЯ «\(заголовок)» за \(Int(секунд)) с. Что на экране:
          подписей \(всё.count), кнопок \(app.buttons.count)
          клавиатура \(app.keyboards.element.exists ? "ПОДНЯТА" : "убрана")
          первые: \(всё.prefix(12).joined(separator: " · "))
        """)
        снять("НЕ-ДОЖДАЛСЯ-\(заголовок)")
        return false
    }

    /// Убрать клавиатуру тапом по заголовку экрана.
    ///
    /// Заголовок приходит аргументом, а не ищется «первым подходящим»:
    /// в тулбаре шага нажимаемых текстов два, и один из них —
    /// «Назад». Тап наугад уводит на первый экран, и кадров выходит
    /// ноль (замер 14.10.2026 у соседнего файла).
    private func убратьКлавиатуру(заголовок: String) {
        guard app.keyboards.element.exists else { return }
        let цель = app.staticTexts[заголовок].firstMatch
        guard цель.exists else {
            XCTFail("убратьКлавиатуру: заголовка «\(заголовок)» нет. Тап наугад запрещён.")
            return
        }
        цель.tap()
        print("КЛАВИАТУРА: \(app.keyboards.element.waitForNonExistence(timeout: 15) ? "убралась" : "ОСТАЛАСЬ")")
    }

    /// Доскроллить до кнопки и нажать. Признак конца — координата
    /// перестала меняться, а не число свайпов: число меряет длину
    /// экрана, а не наличие кнопки.
    private func доскроллитьИНажать(содержит подстрока: String, шагов: Int = 14) -> Bool {
        for _ in 0..<шагов {
            let кнопка = app.buttons.matching(NSPredicate(format: "label CONTAINS %@", подстрока)).firstMatch
            if кнопка.exists && кнопка.isHittable {
                кнопка.tap()
                return true
            }
            app.swipeUp()
        }
        print("ДОСКРОЛЛ: кнопки с «\(подстрока)» не нашлось. Подписи: \(подписи().prefix(15).joined(separator: " · "))")
        return false
    }

    // MARK: - Проход

    func testОнбордингБезНормыНеОставляетНормуВрача() {
        // Настоящий вход: пустые аргументы на стёртом устройстве.
        // Под `-UITesting` онбординга не бывает ни у кого, под
        // `-Онбординг` он не пишет в базу — а предмет здесь именно
        // записанное.
        app.launchArguments = []
        app.launch()

        let начать = app.buttons["Начать"].firstMatch
        XCTAssertTrue(начать.waitForExistence(timeout: 90), """
            Онбординг не открылся. Это отказ СТЕНДА, а не находка:
            устройство обязано быть стёртым (shutdown → erase → boot)
            непосредственно перед прогоном и НЕ общим — чужой заход
            оставляет пройденный онбординг.
            """)
        снять("01-приветствие")
        начать.tap()

        // Шаг «Собака»: только кличка. Вес НЕ вводим — он с 23.10
        // не обязателен, и проход без него самый частый.
        XCTAssertTrue(дождаться("Кто у тебя живёт"))
        let кличка = app.textFields["Кличка"].firstMatch
        if кличка.waitForExistence(timeout: 30) {
            кличка.tap()
            кличка.typeText("Стич")
        }
        убратьКлавиатуру(заголовок: "Кто у тебя живёт")
        снять("02-кличка-без-веса")
        app.buttons["Дальше"].firstMatch.tap()

        // Шаг «Режим дня» — ЗДЕСЬ И ЕСТЬ УЛИКА. Это единственный шаг,
        // где спрашивают про еду, и граммов он не спрашивает: значит
        // всё, что окажется на экране питания, человек не вводил.
        XCTAssertTrue(дождаться("Режим"))
        let наРежиме = подписи()
        print("""
        ШАГ «Режим дня» · подписей \(наРежиме.count)
          \(наРежиме.prefix(20).joined(separator: " · "))
        """)
        XCTAssertFalse(наРежиме.contains { $0.contains("грамм") || $0.contains(" г") && $0.contains("120") }, """
            Шаг режима дня показывает граммы — тогда посылка этого теста
            неверна, и его вывод про «человек нормы не вводил» надо
            снимать, а не чинить экран.
            """)
        снять("03-режим-дня-граммов-не-спрашивают")
        app.buttons["Дальше"].firstMatch.tap()

        // Остаток прохода насквозь: кнопка «вперёд», пока не появится
        // таб-бар. Выход по признаку ЦЕЛИ, а не по счёту шагов —
        // шагов было шесть, стало четыре, и счёт разошёлся бы молча.
        for _ in 0..<10 {
            if app.tabBars.buttons.count > 0 { break }
            let кнопка = app.buttons.matching(NSPredicate(format:
                "label BEGINSWITH 'Дальше' OR label == 'Пропустить' "
                + "OR label == 'Потом, в настройках' "
                + "OR label == 'Вернуться к дневнику'")).firstMatch
            guard кнопка.waitForExistence(timeout: 40) else { break }
            кнопка.tap()
        }

        XCTAssertTrue(app.tabBars.element.waitForExistence(timeout: 90),
                      "онбординг не завершился — таб-бара нет, до дневника не дошли")
        снять("04-дневник-после-онбординга")

        // Вкладка собаки подписана кличкой, а не словом «Собака»
        // (`RootView:136`, `nameIfAny`).
        let вкладка = app.tabBars.buttons["Стич"].firstMatch
        XCTAssertTrue(вкладка.waitForExistence(timeout: 30), """
            Вкладки «Стич» нет. Подписи таб-бара: \
            \(app.tabBars.buttons.allElementsBoundByIndex.map { $0.label })
            """)
        вкладка.tap()

        // Строка входа в питание несёт ЗНАЧЕНИЕ — «N г в день»
        // (`DogTab:388`). Это второе место, где умолчание выглядит
        // данными человека, и оно видно раньше самого экрана.
        XCTAssertTrue(дождаться("каждый день") || app.buttons.matching(
            NSPredicate(format: "label CONTAINS 'Питание и режим'")).firstMatch
            .waitForExistence(timeout: 40),
                      "вкладка собаки не открылась")
        let наВкладке = подписи()
        print("""
        ВКЛАДКА СОБАКИ · подписей \(наВкладке.count)
          строки про питание: \(наВкладке.filter { $0.contains("Питание") })
        """)
        снять("05-вкладка-собаки-строка-питания")

        XCTAssertTrue(доскроллитьИНажать(содержит: "Питание и режим"),
                      "входа «Питание и режим» на вкладке собаки нет")

        // MARK: Предмет и контроль — в одном замере

        // Положительный КОНТРОЛЬ: мы на экране питания. Без него
        // отсутствие «120» ниже неотличимо от «экран не открылся» —
        // на пустом экране его тоже нет.
        let наПитании = app.buttons.matching(
            NSPredicate(format: "label CONTAINS 'Записать корм' OR label CONTAINS 'Чем кормим'")
        ).firstMatch.waitForExistence(timeout: 60)
        XCTAssertTrue(наПитании, """
            КОНТРОЛЬ НЕ ВЗЯЛСЯ: экрана питания нет, значит зелень
            по предмету ниже была бы ложной. Подписи: \
            \(подписи().prefix(15).joined(separator: " · "))
            """)

        let всё = подписи()
        снять("06-питание-и-режим-норма")
        print("""
        ЭКРАН ПИТАНИЯ · подписей \(всё.count)
          \(всё.prefix(30).joined(separator: " · "))
        """)

        // ПРЕДМЕТ. Число, которого никто не называл, на экране
        // не стоит — ни в арифметике, ни в подписи для озвучки.
        let сЧислом = всё.filter { $0.contains("120") || $0.contains("÷ 2") }
        XCTAssertTrue(сЧислом.isEmpty, """
            Экран показывает норму, которой никто не называл: \(сЧислом)

            Умолчание `ScheduleDraft.dailyGrams` уехало в базу через
            `OnboardingFlow.saveDog() → ScheduleDraft.apply(to:)`
            и встало под заголовком «норма врача». Шаг режима дня
            граммов не спрашивал — это проверено выше в том же проходе.
            """)

        // И вторая сторона той же лжи: пустая норма не читается как
        // «врач назначил ноль».
        let сНулём = всё.filter { $0.contains("0 ÷") || $0.contains("Норма 0 грамм") }
        XCTAssertTrue(сНулём.isEmpty, """
            Пустая норма показана нулём: \(сНулём)
            «Врач назначил 0» — такое же утверждение, как «врач
            назначил 120», и от нормы считается порция.
            """)
    }
}
