    /// Приёмка записи попыток: счёт обязан вырасти, а не остаться нулём.
    ///
    /// До 28.09 `attempts` не увеличивал никто, и строка «N из M»
    /// не появлялась ни разу. Тест снимает ДО и ПОСЛЕ — иначе «ноль»
    /// и «не показали» неотличимы.
    func testНавыкПопытка() {
        app.tabBars.buttons["Стич"].tap()
        let процедуры = app.buttons.matching(
            NSPredicate(format: "label CONTAINS %@", "роцедур")).firstMatch
        guard процедуры.waitForExistence(timeout: 5) else {
            XCTFail("не нашла вход в «Процедуры» — проверь вкладку собаки")
            return
        }
        процедуры.tap()
        capture("навык-01-до")
        // **Два прогона одного и того же кода разошлись 23.10.2026** —
        // 17:3x зелёный, 17:5x «No matches found for „Дать лапу
        // и не забирать"». Механизм не установлен, и ближайшую похожую
        // причину сюда писать нельзя. Что сделано: поиск переведён
        // на общий `найти`, который **прокручивает** и не бьёт под
        // хрому, — на крупном кегле список длиннее экрана, и прямой
        // `staticTexts[…].tap()` зависел от того, докуда он дорисовался.
        // Это снимает один из путей отказа, а не доказывает, что он был
        // единственным.
        let первый = найти("Дать лапу и не забирать", в: app)
        XCTAssertTrue(первый.waitForExistence(timeout: 5),
                      "в «Процедурах» нет навыка «Дать лапу и не забирать»")
        первый.tap()
        _ = app.buttons["Получилось"].waitForExistence(timeout: 5)
        app.buttons["Получилось"].tap()
        app.buttons["Получилось"].tap()
        capture("навык-02-лист")
        app.buttons["Закрыть"].firstMatch.tap()
        capture("навык-03-после")
    }

