        бар.buttons.element(boundBy: 1).tap()

        let строка = найти("Семья и дежурство", в: app)
        XCTAssertTrue(строка.waitForExistence(timeout: 10),
                      "во вкладке собаки нет строки «Семья и дежурство» — входа в семью")
