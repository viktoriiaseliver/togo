        capture("xl-04-family")
        let первый = app.descendants(matching: .any)
            .matching(NSPredicate(format: "label BEGINSWITH %@", "Виктория"))
            .firstMatch
        if первый.waitForExistence(timeout: 3) {
            первый.tap()
            capture("xl-05-permissions")
        }
    }
