    /// Режим выгула на `AccessibilityXL`.
    ///
    /// **Почему он здесь появился только 25.10.2026.** Набор снимал
    /// «Просится» (кадр `xl-02`) — это **шторка вердикта**, а не режим
    /// выгула: она кончается кнопкой «Вывожу», и за ней начинается
    /// другой экран, которого ни один кадр не показывал. Низ экранов
    /// мерили 24.10 и получили запас +34…+44 pt — но мерили те экраны,
    /// до которых доходили кадры, и этого среди них не было.
    ///
    /// Предмет назван до кадра, чтобы кадр было с чем сверять:
    /// во всём `Togo/Features/Needs/` **ни одного** обращения
    /// к `dynamicTypeSize` (замер 25.10.2026, `git grep -c` по каталогу
    /// даёт пусто), а низ режима — это ряд из двух органов в строку:
    /// «Пауза»/«Продолжить» и слайдер «Домой».
    ///
    /// Снимается ДВА состояния, и второе важнее первого: на паузе
    /// подпись кнопки становится «Продолжить» — вдвое длиннее «Паузы», —
    /// и ровно тогда ряд обязан разъехаться, если он тесен.
    func testXL13РежимВыгула() {
        // «Гулять» — второе действие низа «Сегодня» (`TodayScreen:998`).
        // На крупном кегле низ раскладывается столбцом (`TodayBottom:53`),
        // то есть кнопка полноширинная, а не треть ряда.
        let гулять = app.buttons["Гулять"].firstMatch
        let открыть = app.buttons["Открыть"].firstMatch
        if гулять.waitForExistence(timeout: 10) {
            гулять.tap()
            // Прогулки ещё нет — поднимается `startSheet` с «Пошли».
            let пошли = app.buttons["Пошли"].firstMatch
            XCTAssertTrue(пошли.waitForExistence(timeout: 5),
                          "«Гулять» нажата, а шторка «Прогулка» с кнопкой «Пошли» не поднялась")
            capture("xl-13-walk-start")
            пошли.tap()
        } else if открыть.waitForExistence(timeout: 3) {
            // Прогулка уже идёт — главное действие зовётся «Открыть».
            открыть.tap()
        } else {
            XCTFail("""
                на «Сегодня» нет ни «Гулять», ни «Открыть» — в режим \
                выгула не войти. Это дороги, а не предмета: обе \
                приходят от `главноеДействие`/`второеДействие` \
                в `TodayScreen`.
                """)
            return
        }

        // Якорь — ИДЕНТИФИКАТОР, а не подпись. Пока прогулка идёт,
        // «Пописал» лежит на экране ДВАЖДЫ: в шторке выгула и в низу
        // «Сегодня» под ней, и `firstMatch` по подписи берёт нижнюю
        // (замер 24.10.2026, `WalkMode.имяОтметки`).
        let пописал = app.buttons[WalkModeИмена.urine].firstMatch
        XCTAssertTrue(пописал.waitForExistence(timeout: 10), """
            режим выгула не открылся: кнопки с идентификатором \
            «\(WalkModeИмена.urine)» в дереве нет. По подписи её \
            спрашивать нельзя — под шторкой лежит одноимённая чужая.
            """)
        capture("xl-13-walk-active")

        // Низ ряда отдельным кадром: предмет — слайдер «Домой»
        // и соседняя кнопка, а на общем кадре они внизу и мелко.
        app.swipeUp()
        capture("xl-13-walk-scrolled")

        // Пауза — худший случай ряда: «Продолжить» вдвое длиннее «Паузы».
        let пауза = app.buttons["Пауза"].firstMatch
        if пауза.waitForExistence(timeout: 5) {
            пауза.tap()
            XCTAssertTrue(app.buttons["Продолжить"].firstMatch.waitForExistence(timeout: 5),
                          "«Пауза» нажата, а подпись не сменилась на «Продолжить»")
            capture("xl-13-walk-paused")
        } else {
            print("КНОПКИ «Пауза» НЕТ: худший случай ряда не снят")
        }
    }

    /// Сетка снимков документов на `AccessibilityXL` — две колонки
    /// вместо трёх (ответ дизайна 25.10.2026, круг 5, пункт 6).
    ///
    /// **Границу замера называю здесь, а не в отчёте: СНИМКОВ НА СТЕНДЕ
    /// НЕТ НИ ОДНОГО.** `SeedData` не заводит ни одного `DogDocument`
    /// (замер 25.10.2026: единственное вхождение типа вне экрана —
    /// `SharedDiarySeed.swift:115`, это обмен, а не демо-данные).
    /// Значит кадр показывает сетку из одной плитки «Снять» и поясняющий
    /// текст, и про то, **помещаются ли картинки**, он не отвечает вовсе.
    ///
    /// > Это наш класс «поверхность без кадра»: лечится не взглядом,
    /// > а переделкой входа — демо-документом в `SeedData`. Хозяина
    /// > у такой правки тест назначить не может.
    ///
    /// Что кадр всё-таки отвечает: не разъезжается ли на AX сама
    /// карточка — шапка «снимки» с длинным подзаголовком, пояснение
    /// и плитка «Снять» с подписью под значком 28 pt.
    func testXL14СнимкиДокументов() {
        let бар = app.tabBars.firstMatch
        XCTAssertTrue(бар.waitForExistence(timeout: 10),
                      "таб-бара нет — приложение не дошло до главного экрана")
        // Вкладка собаки названа кличкой, то есть её имя — данные;
        // берём по порядку, как в `КрупныйКегльБезДвухРаскладок`.
        бар.buttons.element(boundBy: 1).tap()

        let вход = app.buttons.matching(
            NSPredicate(format: "label CONTAINS %@", "Документы и контакты")).firstMatch
        XCTAssertTrue(вход.waitForExistence(timeout: 15), """
            строки «Документы и контакты» на вкладке собаки нет — \
            до сетки снимков не дойти. Это ЕДИНСТВЕННАЯ дорога \
            к `DocumentsScreen` (замер 23.10.2026).
            """)
        вход.tap()

        XCTAssertTrue(app.staticTexts["Чип"].firstMatch.waitForExistence(timeout: 15),
                      "экран «Документы и контакты» не открылся: подписи «Чип» на нём нет")
        capture("xl-14-documents")

        // Сетка лежит ниже полей документа — на AX до неё надо доехать.
        // Плитка «Снять» есть всегда, когда есть право правки, и она же
        // единственный живой элемент сетки на стенде.
        let снять = app.buttons.matching(
            NSPredicate(format: "label CONTAINS %@", "Снять")).firstMatch
        for _ in 0..<6 where !снять.exists { app.swipeUp() }
        if снять.exists {
            capture("xl-14-documents-grid")
        } else {
            app.swipeUp()
            capture("xl-14-documents-grid")
            print("ПЛИТКИ «Снять» НЕ НАШЛОСЬ: кадр снят по положению прокрутки, не по предмету")
        }
    }
}

