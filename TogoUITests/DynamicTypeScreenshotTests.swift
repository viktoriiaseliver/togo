/// собирал, — предупреждение оправдалось дословно. Это третья граница
/// рецепта «собирается ли», записанная в `Togo/CLAUDE.md`: без
/// `SWIFT_DEFAULT_ACTOR_ISOLATION` целого класса ошибок **не возникает
/// вовсе**, а не прячется.
///
/// Цена пропуска — не свой красный: поломка в UI-таргете убивает
/// прогон ВСЕМ, включая тех, кто гонит `-only-testing:TogoTests`.
nonisolated enum WalkModeИмена {
