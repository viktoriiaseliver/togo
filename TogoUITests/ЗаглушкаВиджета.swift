import XCTest

/// Заглушка виджета — то, что человек видит в галерее iOS при добавлении
/// виджета и пока снимок ещё не прочитан.
///
/// **Приёмка правки 07.10.2026.** `WidgetSnapshot.empty` держала три
/// слова литералами в полях типа `String`:
///
/// ```
/// dogName: "Собака" · verdictTitle: "Просится" · verdictBadge: "нет данных"
/// ```
///
/// Литерал в `String`-поле — это ЗНАЧЕНИЕ, и до каталога оно не доходит:
/// `Text(значение)` печатает его дословно. Значит француз, добавляя
/// виджет, видел три русских слова. Починено через `String(localized:)`;
/// слова и ключи те же, переводы в каталоге лежали всё время.
///
/// **Почему этот файл вообще может существовать.** Сам виджет рисует
/// SpringBoard, и `app.screenshot()` до него не достаёт — поверхность
/// была непроверяемой, пока 05.10 вид не уехал из расширения
/// в `TogoShared/Widgets`. `WidgetGallery` — единственное место, где
/// строки виджета можно УВИДЕТЬ.
///
/// **Тест работает на ЛЮБОМ языке прогона, а не требует `-testLanguage fr`.**
/// Первая редакция требовала французского и падала в общем прогоне
/// UI-набора — то есть добавляла красный там, где дефекта нет, а это
/// дороже пропущенного дефекта: после такого сторожа перестают читать.
/// Язык берётся у раннера через `Подписи`, как у остальных языковых
/// тестов проекта; ожидаемые слова приходят из того же каталога,
/// который собирается в бандл.
///
/// **Граница, и она существенная.** Галерея доказывает, что строка
/// доходит до каталога и рисуется переводом. Она НЕ доказывает, что
/// по-французски будет и в самой галерее iOS: язык расширения берёт
/// система, а не приложение, и `-testLanguage` красит только
/// приложение под тестом. Это разные утверждения, и второе нашими
/// инструментами не берётся вовсе.
nonisolated final class ЗаглушкаВиджетаUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testЗаглушкаВиджетаГоворитНаЯзыкеПрогона() {
        let настройки = app.buttons[подписи("Настройки")].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 20),
                      "не дождались главного экрана (язык прогона — «\(подписи.язык)»)")
        настройки.tap()

        // «Виджет» — отладочный пункт под `#if DEBUG`, литерал в коде
        // и в каталог не заведён: ищем его русским на любом языке.
        let виджет = найти("Виджет", в: app)
        XCTAssertTrue(виджет.waitForExistence(timeout: 10), """
            в настройках нет входа «Виджет» — галерея живёт под `#if DEBUG`, \
            и в Release-сборке этой проверки не существует
            """)
        виджет.tap()

        // **Крутим до упора, а не до `exists`.** Элемент «существует»
        // и не будучи на экране, а строки ПОД ним в этот момент
        // не построены: группа с пустым снимком стоит последней,
        // и список текстов обрывался на середине. Утверждение
        // «перевода нет» вышло бы тогда про непрокрученный экран.
        //
        // **Читать список элементов ВНУТРИ цикла прокрутки нельзя.**
        // Прежняя редакция останавливалась, когда склейка подписей
        // перестанет меняться, — и падала устойчиво, три прогона
        // из трёх: `Failed to get matching snapshot: No matches found
        // for Element at index 105`, `rc=65`, 30,4 · 24,8 · 24,6 с.
        // Пока перечисляются индексы, список под рукой уже другой:
        // падение выглядит дефектом галереи, а это дефект обхода.
        //
        // Починка была написана 07.10 в соседнем файле
        // (`ЖиваяАктивностьВГалерее.swift:48-59`) и не доехала два
        // файла. Третий раз её чинить незачем — число махов
        // фиксированное, раздел последний, лишние махи у низа
        // пустая операция, а список читается один раз и после.
        for _ in 0..<14 { app.swipeUp() }

        // **Кадр снимается ДО первой проверки, способной прервать тест.**
        // `continueAfterFailure = false`, и прежде `add(кадр)` стоял
        // после утверждения о группе — то есть при падении кадр
        // не снимался НИКОГДА, и «кадра виджета нет» прочиталось бы
        // как свойство продукта. Ложная пустота: пустой результат
        // за упавшей проверкой неотличим от пустого результата
        // измеренного мира. Кадр — улика, и нужна она именно тогда,
        // когда проверка красная.
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "09-заглушка-виджета-\(подписи.язык)"
        кадр.lifetime = .keepAlways
        add(кадр)

        let тексты = app.staticTexts.allElementsBoundByIndex.map { $0.label }

        // Заголовок группы — тоже отладочный литерал, но `TGSectionHeader`
        // вешает `.textCase(.uppercase)` (`TGRows.swift:12`), и на экране
        // стоит «ДАННЫХ НЕТ ВОВСЕ». Искать строку из исходника — значит
        // искать не то, что нарисовано; у нас это записано ценой
        // `dsCaps()`, который рисует «ШАГ» там, где в коде «Шаг».
        //
        // Сверяется по уже прочитанному списку, а не вторым обходом
        // дерева: два обхода одного экрана расходятся молча, и у нас
        // это записано про два разбора одного места.
        XCTAssertTrue(тексты.contains(where: { $0.localizedCaseInsensitiveContains("Данных нет вовсе") }), """
            группы с пустым снимком в галерее нет — проверять нечего.

            Строк на экране \(тексты.count), хвост: \
            \(тексты.suffix(20).joined(separator: " | "))
            """)

        // **Требование, а не запрет, и здесь это можно.** Обычно «строка
        // содержит нужное» проверяется ненадёжно — у нужного десять форм.
        // Здесь форма одна: три конкретных значения из каталога.
        //
        // Сверяется ГОЛОВА строки: во французском «Просится» перед «?»
        // стоит U+202F (узкий неразрывный пробел), и побайтная сверка
        // разошлась бы НА ПРАВИЛЬНОМ символе — покраснела там, где всё
        // верно.
        // **Ключей два, а не три, и третий — отдельная находка.**
        // Починка 07.10 локализовала три слова заглушки; на экране
        // проверяемы два. `verdictBadge` («нет данных») не читает
        // НИКТО: замер по дереву — четыре места пишут его
        // (`WidgetSnapshot:64`, `WidgetGallery:46` и `:59`,
        // `LiveActivityController:81`) и ни одно не читает.
        //
        // То есть его перевод верен и недостижим: значение правильное,
        // показа нет. Наш класс «имя упомянуто — и от упоминания ничего
        // не происходит». Требовать его здесь значило бы завести красный
        // на поверхности, которой не существует.
        for ключ in ["Собака", "Просится"] {
            let ожидаемое = подписи(ключ)
            let голова = String(ожидаемое.prefix(max(1, ожидаемое.count - 2)))
            XCTAssertTrue(тексты.contains(where: { $0.contains(голова) }), """
                в заглушке виджета нет «\(ожидаемое)» (язык прогона \
                «\(подписи.язык)», ключ «\(ключ)»). Либо литерал снова \
                пошёл мимо каталога, либо перевод не доехал до этой \
                поверхности.

                ЧТО НА ЭКРАНЕ — всего строк \(тексты.count), показан ХВОСТ: \
                группа с пустым снимком стоит последней, и срез с головы \
                до неё не доезжает. Вложения в `.xcresult` 07.10 трижды \
                не выгрузились, поэтому замер идёт сообщением.
                \(тексты.suffix(20).joined(separator: " | "))
                """)
        }

        // Обратная половина, и только для нерусского прогона: русских
        // слов заглушки на экране быть не должно. Без неё проверка выше
        // прошла бы и у экрана, где рядом с переводом осталось русское.
        guard подписи.язык != "ru" else { return }
        for русское in ["Собака", "Просится"] {
            XCTAssertFalse(тексты.contains(where: { $0 == русское }), """
                на экране языка «\(подписи.язык)» стоит русское \
                «\(русское)» — ровно то слово заглушки, которое чинили.
                """)
        }
    }
}
