import XCTest

/// ЗОНД, а не сторож. Снимает экраны с фотографией на подложке, чтобы
/// посмотреть на наложение слоёв своими глазами.
///
/// Девять отзывов из двадцати двух за 27–30.10.2026 говорят об одном:
/// «слои неправильно наложились», «подложка под текст ужас»,
/// «обрезается наложение», «не тот цвет применяет», «перекрытие
/// элементов». На кадрах человека видно вертикальный шов примерно
/// на 82 % ширины у «Истории» и чёрную полосу над фото у «Собаки».
///
/// Воспроизвести у себя не удавалось: без `-ФонФикстура` подложки нет
/// вовсе, и экран выглядит здоровым. Этот зонд ставит фикстуру
/// и проходит по четырём экранам, снимая каждый.
///
/// **Удалить, когда дефект найден и закрыт сторожем.** Зонд ничего
/// не утверждает — он только смотрит, и зелёный у него ничего
/// не значит.
nonisolated final class ЗондФонаUITests: XCTestCase {

    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = true
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-ФонФикстура", "-Сценарий", "today"]
        app.launch()
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Главный экран БЕЗ собаки: на кадре мамы 30.10 статус-бар наезжал
    /// на заголовок карточки «Дневник едет на этот телефон».
    ///
    /// Запускается своим сценарием, поэтому `setUp` здесь переигрывается:
    /// нужна пустая база, а не `today`.
    func testГлавныйБезСобаки() {
        app.terminate()
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "onboarding"]
        app.launch()
        XCTAssertTrue(app.wait(for: .runningForeground, timeout: 20),
                      "приложение не поднялось — снимать нечего")
        sleep(3)
        снять("05-главный-без-собаки")
        print("КАДРОВ СНЯТО: 1")
    }

    func testЧетыреЭкранаСФоном() {
        XCTAssertTrue(app.wait(for: .runningForeground, timeout: 20),
                      "приложение не поднялось — снимать нечего")
        sleep(3)
        снять("01-сегодня")

        for (подпись, имя) in [("Собака", "02-собака"),
                               ("История", "03-история"),
                               ("Здоровье", "04-здоровье")] {
            let вкладка = app.buttons[подпись].firstMatch
            if вкладка.waitForExistence(timeout: 6) {
                вкладка.tap()
                sleep(2)
                снять(имя)
            } else {
                // Вкладка подписана кличкой собаки, а не словом «Собака»:
                // печатаем, что видим, вместо молчаливого пропуска.
                снять("\(имя)-ВКЛАДКИ-НЕТ")
            }
        }

        // Подписи всех кнопок панели — чтобы знать, по чему стучать,
        // если вкладка не нашлась по слову.
        let панель = app.tabBars.firstMatch
        // Замыканием, а не `map(\.label)`: `label` изолирован
        // главным актором, и ключевой путь к нему не построить.
        print("КНОПКИ ПАНЕЛИ:", панель.buttons.allElementsBoundByIndex.map { $0.label })
        print("КАДРОВ СНЯТО: 4")
    }
}
