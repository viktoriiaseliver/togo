import XCTest

/// Четыре текста, которые мама читает в худшую свою минуту, —
/// и которых не видел глазами никто.
///
/// # Что здесь проверяется, чего не проверяет эталон
///
/// `ShareAcceptanceOutcome` заводился ровно затем, чтобы человек,
/// у которого приглашение не открылось, узнал **почему**. Цена
/// измерена на мамином пути и записана в `FamilyShare.swift:398`:
/// она входит публичной ссылкой, видит отказ, не успевает прочесть —
/// и остаётся уверенной, что вошла.
///
/// Проверено это сегодня двумя способами, и ни один не глаз:
///
/// ```
/// ПриёмПриглашенияГоворитTests   сверяет ТЕКСТЫ как строки
/// ЗнакТостаTests:299-308         сверяет, что показ ЕСТЬ, — грепом
///                                по исходнику: экран.contains("…")
/// ```
///
/// Второй — наш записанный класс «сканирующий сторож меряет прозу»:
/// он зелен от того, что строка написана в файле, и останется
/// зелёным, если экран перестанет её показывать.
///
/// > Исходник говорит, что задумали; показ — что увидят. Пять разных
/// > вопросов, и ответ на один читается как ответ на остальные.
///
/// # Почему четыре, а не пять
///
/// `.принято(чей:)` берётся **отсутствием** аргумента, а не им:
/// у успеха ассоциированное значение, и в ключе `НеудачаПриёма`
/// успех и так значит снятие причины. Кадр успеха — отдельный путь,
/// не этот.
///
/// # Вход
///
/// `-ИсходПриёма <код>` — пишет `share.acceptance.failure`
/// в `UserDefaults` группы приложений до первого чтения. Заведён
/// `togo-onboarding-status-check` 14.10 в одном блоке с `-ЧужаяЗона`:
/// обе двери второго человека живут в одной группе, и окно записи
/// у них одно.
///
/// Незнакомый код **валит запуск**. Это не строгость: `НеудачаПриёма`
/// разбирает строку с `default: nil` (`FamilyShare.swift:432`), и
/// опечатка дала бы «причины не было» — спокойный экран, зелёный
/// тест и четыре исхода, записанных снятыми, при одном и том же
/// снятом ничём.
///
/// # Куда пишет
///
/// `build/кадры-приёма/`, путь из `#filePath`; ломается от уборки
/// каталога и ломается не на своём предмете. Что нужно сохранить —
/// в `Дизайн/кадры-приёмки/`.
nonisolated final class ПриёмПриглашенияВидно: XCTestCase {

    /// Код исхода и кусок текста, по которому его узнают на экране.
    ///
    /// Кусок, а не вся фраза: сверка целиком покраснела бы
    /// на правке текста — то есть на работе редактора, а не
    /// на поломке. Кусок выбран так, чтобы **различать исходы между
    /// собой**: в этом и предмет.
    private static let исходы: [(код: String, примета: String)] = [
        ("нетСети", "нет связи"),
        ("нетiCloud", "не выполнен вход в iCloud"),
        ("сторонаПриложения", "на нашей стороне"),
        ("неизвестно", "не знаем почему"),
    ]

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-приёма")
    }

    override func setUp() { continueAfterFailure = false }

    private func открытьОбщийДневник(_ app: XCUIApplication) {
        let вкладка = app.tabBars.buttons["Семья"].firstMatch
        XCTAssertTrue(вкладка.waitForExistence(timeout: 15),
                      "приложение не поднялось — это отказ запуска, не показа")
        вкладка.tap()

        // Кандидаты по типам, а не `descendants(.any)`: `NavigationLink`
        // с карточкой в метке SwiftUI волен сложить кнопкой, ячейкой
        // или текстом, а запрос по всему дереву вернул бы контейнер —
        // и `tap()` пришёлся бы в случайное место.
        //
        // Это уже стоило прогона 17:17: там стоял `containing(_:)`,
        // который отбирает элементы с ПОТОМКОМ под предикат, то есть
        // вернул корневое окно. Тест упал ниже и обвинил чужую правку,
        // а кадр показал, что мы были на карточке участника «Мама».
        let кандидаты = [
            app.buttons["Общий дневник"].firstMatch,
            app.cells["Общий дневник"].firstMatch,
            app.staticTexts["Общий дневник"].firstMatch,
        ]
        var ссылка: XCUIElement?
        for _ in 0..<6 {
            if let найдено = кандидаты.first(where: { $0.exists && $0.isHittable }) {
                ссылка = найдено
                break
            }
            app.swipeUp()
        }
        guard let ссылка else {
            XCTFail("ссылки «Общий дневник» нет — до экрана не дошли")
            return
        }
        ссылка.tap()

        // Пришли ли ТУДА. Без этого кадры исходов снимались бы с любого
        // экрана, на который увёл тап, и назывались бы именами исходов.
        XCTAssertTrue(app.navigationBars["Общий дневник"].waitForExistence(timeout: 10),
                      "после тапа мы не на экране общего дневника")
    }

    private func текстНаЭкране(_ app: XCUIApplication, _ кусок: String) -> Bool {
        app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", кусок))
            .firstMatch.waitForExistence(timeout: 5)
    }

    /// Имена записанных КАДРОВ. Отдельно от местного `снято`
    /// в самом тесте: то считает **видимые исходы**, то есть другой
    /// предикат. Кадр пишется всегда, исход засчитывается только
    /// при `виден` — складывать их в одно число значило бы отвечать
    /// одним числом на два вопроса.
    private var кадры: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Здесь это не теория: `XCTAssertTrue(виден, …)` стоит
        // внутри цикла по исходам, и на первом невидимом тест
        // обрывается — а печать «СНЯТО ИСХОДОВ» лежит ПОСЛЕ цикла
        // и в этом случае не выполняется вовсе.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча.
        print("КАДРОВ СНЯТО: \(кадры.count) · \(name) · \(кадры.joined(separator: ", "))")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ app: XCUIApplication, _ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        кадры.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    // MARK: - Контроль: без аргумента отказа нет

    /// Ставится первым. Без него четыре кадра ниже могли бы оказаться
    /// кадрами одного и того же спокойного экрана: «текст есть»
    /// проверяется, а «текста не было до того» — нет.
    func testБезАргументаНиОдногоОтказаНеПоказано() throws {
        let app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
        открытьОбщийДневник(app)

        for исход in Self.исходы {
            XCTAssertFalse(текстНаЭкране(app, исход.примета), """
                на чистом запуске показан отказ «\(исход.код)». Значит
                ключ `share.acceptance.failure` достался от предыдущего
                теста — он в UserDefaults группы и переживает запуск.
                Тогда все кадры ниже сняты не того состояния.
                """)
        }
    }

    // MARK: - Предмет: четыре отказа

    func testЧетыреОтказаПриёмаСнятыДляЧеловека() throws {
        var снято: [String] = []

        for исход in Self.исходы {
            let app = XCUIApplication()
            app.launchArguments = ["-UITesting", "-ИсходПриёма", исход.код]
            app.launch()
            открытьОбщийДневник(app)

            let виден = текстНаЭкране(app, исход.примета)
            try снять(app, "приём-\(исход.код)")
            if виден { снято.append(исход.код) }

            XCTAssertTrue(виден, """
                исход «\(исход.код)» не показан. Три разные причины,
                и они не равны друг другу:
                  · аргумент не доехал до UserDefaults группы;
                  · `SharedDiaryScreen:66` перестал читать
                    `НеудачаПриёма.текущая`;
                  · текст показан, но другой — тогда ищи, какой
                    именно, на кадре.
                Третья — худшая: человек читает не свою причину
                и чинит не то.
                """)

            // Различимость исходов. Без неё «показано четыре раза»
            // и «показано одно и то же четыре раза» неотличимы,
            // а именно ради различения причин всё и заводилось.
            for чужой in Self.исходы where чужой.код != исход.код {
                XCTAssertFalse(текстНаЭкране(app, чужой.примета), """
                    вместе с «\(исход.код)» на экране виден
                    и «\(чужой.код)». Либо показываются все причины
                    разом, либо примета выбрана неразличимой — второе
                    чинится здесь, первое в продукте.
                    """)
            }

            app.terminate()
        }

        print("СНЯТО ИСХОДОВ: \(снято.count) из \(Self.исходы.count) · \(каталог.path)")
        XCTAssertEqual(снято.count, Self.исходы.count,
                       "сняты не все исходы: \(снято)")
    }
}
