import XCTest

/// Почему содержимое шага 4 онбординга не достаётся на 375 × 667 —
/// замер, разделяющий ТРИ механизма одним заходом.
///
/// # Что уже померено, и чего в этом замере НЕ ХВАТАЕТ
///
/// `УзкийЭкранОнбординг` 26.10.2026 (коммит `c642e0a`, окно прочитано
/// у `app.frame`) снял на iPhone SE 3:
///
/// ```
/// окно                        (0, 0, 375, 667)
/// рамка «Одно напоминание»     (34, 557, 263, 24)   hittable = false
/// шесть app.swipeUp()          кадр ПОБАЙТНО тот же, md5 f69715dc…
/// КОНТРОЛЬ 402 × 874           карточка видна целиком, прокрутка не нужна
/// ```
///
/// Замер верен, и вывод «ПОТЕРЯ СОДЕРЖИМОГО» из него **не следует**:
/// `app.swipeUp()` отвечает «я не сдвинул», а не «оно не двигается».
/// Карточка стоит в коде безусловно (`OnboardingSteps:726`), то есть
/// вопрос ровно один — **достижима ли она прокруткой**.
///
/// # Три механизма, и по кадру сверху они одинаковы
///
/// ```
/// A  .safeAreaInset НЕ вычитается из области прокрутки — панель
///    просто накрывает хвост. Тогда крутить всё же есть что: ровно
///    на столько, на сколько содержимое выходит за НИЖНИЙ КРАЙ ОКНА
/// B  inset работает, прокрутка была доступна всё время, а жест
///    app.swipeUp() начинался ВНУТРИ нижней панели и до ScrollView
///    не доходил вовсе. Тогда дефекта в продукте нет, а есть дефект
///    замера
/// D  прокрутки нет вообще (содержимое не длиннее окна либо
///    ScrollView разложен по содержимому). Тогда потеря настоящая
///    и чинить надо каркас
/// ```
///
/// # Ожидаемое названо ДО съёмки — иначе числу нечем разойтись
///
/// Арифметика по кадрам партии 26.10 и значениям токенов
/// (`screenPadding 18`, `stack 12`, `s24 24`, `s16 16`, `s12 12`;
/// высота карточки на 402 померена по кадру — 142 pt):
///
/// ```
/// карточка в покое      minY 557                       ← замерено 26.10
/// низ содержимого       557 − 16 + 142 + 24 ≈ 707 pt    ← расчёт
/// верх нижней панели    ≈ 532 pt  (кнопка «Разрешить» minY 542 − s10)
/// окно                  667 pt
///
/// дельта 0 … 10 pt      → механизм D: крутить нечего
/// дельта 25 … 70 pt     → механизм A: вычитается ОКНО, а не панель.
///                         Хвост карточки остаётся под панелью навсегда
/// дельта 140 … 200 pt   → механизм B: прокрутка работала всё время
/// ```
///
/// **Приёмка — не дельта, а положение:** карточка целиком выше верха
/// панели и `hittable = true`. Дельта только называет механизм.
///
/// > **Метрика разности удовлетворяется отсутствием предмета.**
/// > Поэтому прежде всякой разности печатается, **существуют ли обе
/// > величины**: рамка карточки и рамка кнопки низа. Нулевая рамка
/// > даёт «помещается: ДА» на пустом месте — этим уже заплачено
/// > сегодня.
///
/// # Контроль снимается тем же инструментом и в том же заходе
///
/// Контроль здесь — **возврат**: после протяжки вверх та же протяжка
/// вниз обязана вернуть карточку на `minY ≈ 557`. Он подвержен ровно
/// тому же отказу, что предмет: сломайся протяжка как инструмент —
/// обнулятся оба. Два нуля вместе значат «вопрос не тот», а не
/// «предмета нет».
///
/// Контроль из другого семейства (`app.swipeUp()`) здесь был бы
/// бесполезен: он и есть подозреваемый.
///
/// # Чего этот файл НЕ делает
///
/// Он ничего не чинит и ничего не утверждает про вид панели.
/// Он доводит приложение до шага 4, печатает рамки до и после трёх
/// разных воздействий и кладёт три кадра файлами. Кнопку «Разрешить»
/// он не нажимает и начинать жест с неё не может: системный запрос
/// разрешения поднимает модальный алерт и останавливает заход.
nonisolated final class ПрокруткаПодПанелью: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-прокрутка-под-панелью")
    }

    /// Только как `TEST_RUNNER_KADR_SUFFIX`: `xcodebuild` отдаёт процессу
    /// теста лишь переменные с этой приставкой, снимая её.
    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        // Кадр снимается и после обрыва: предмет — последний шаг
        // из четырёх, и падение на втором не должно уносить третий.
        continueAfterFailure = true
        снято = []
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "onboarding", "-Онбординг"]
        app.launch()
    }

    override func tearDown() {
        print("ПАНЕЛЬ-КАДРОВ СНЯТО: \(снято.count) · \(снято.joined(separator: ", "))")
        // Размер окна печатается ВСЕГДА и читается у приложения:
        // кадр, снятый не на том устройстве, снаружи неотличим
        // от снятого на том.
        if app != nil { print("ПАНЕЛЬ-ОКНО: \(app.frame)") }
        super.tearDown()
    }

    // MARK: - Инструменты

    @discardableResult
    private func снять(_ имя: String) -> Bool {
        let кадр = app.screenshot()
        let вложение = XCTAttachment(screenshot: кадр)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("ПАНЕЛЬ-КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
            return true
        } catch {
            print("ПАНЕЛЬ-КАДР НЕ ЛЁГ: \(имя) · \(error.localizedDescription)")
            return false
        }
    }

    private func дождаться(_ заголовок: String, секунд: TimeInterval = 40) -> Bool {
        app.staticTexts[заголовок].firstMatch.waitForExistence(timeout: секунд)
    }

    @discardableResult
    private func нажать(_ подпись: String) -> Bool {
        let кнопка = app.buttons[подпись].firstMatch
        guard кнопка.waitForExistence(timeout: 40) else {
            снять("ОТКАЗ-нет-кнопки-\(подпись)")
            XCTFail("кнопки «\(подпись)» нет — дальше по шагам не пройти")
            return false
        }
        кнопка.tap()
        return true
    }

    private func убратьКлавиатуру(заголовок: String) {
        guard app.keyboards.element.exists else { return }
        let цель = app.staticTexts[заголовок].firstMatch
        guard цель.exists else {
            XCTFail("убратьКлавиатуру: заголовка «\(заголовок)» нет, тап наугад запрещён")
            return
        }
        цель.tap()
        let убралась = app.keyboards.element.waitForNonExistence(timeout: 10)
        print("ПАНЕЛЬ-КЛАВИАТУРА: \(убралась ? "убралась" : "ОСТАЛАСЬ")")
    }

    /// Карточка напоминания. Ищется по НАЧАЛУ подписи: час приезжает
    /// из настроек, и прибивать его тут значит завести вторую копию
    /// значения.
    private var карточка: XCUIElement {
        app.staticTexts.matching(
            NSPredicate(format: "label BEGINSWITH %@", "Одно напоминание")).firstMatch
    }

    /// Протяжка СТРОГО внутри названной полосы по вертикали.
    ///
    /// Не `swipeUp()`, и это предмет файла: у жеста элемента точку
    /// начала выбирает XCUITest, а здесь она названа числом и лежит
    /// заведомо выше верха панели. Медленная протяжка, а не бросок:
    /// бросок добавляет инерцию, и дельта перестаёт быть измеримой
    /// величиной.
    private func протянуть(от: CGFloat, до: CGFloat, зачем: String) {
        let x = app.frame.midX
        let начало = app.coordinate(withNormalizedOffset: CGVector(dx: 0, dy: 0))
            .withOffset(CGVector(dx: x, dy: от))
        let конец = app.coordinate(withNormalizedOffset: CGVector(dx: 0, dy: 0))
            .withOffset(CGVector(dx: x, dy: до))
        print("ПАНЕЛЬ-ПРОТЯЖКА (\(зачем)): x=\(x) · y \(от) → \(до)")
        начало.press(forDuration: 0.1, thenDragTo: конец)
    }

    /// Рамка карточки, и отдельно — есть ли она вообще.
    ///
    /// `exists` истинно и для элемента ЗА ЭКРАНОМ, поэтому печатается
    /// тройка: в дереве · рамка · попадает ли палец.
    @discardableResult
    private func замерить(_ когда: String) -> CGRect {
        let есть = карточка.exists
        let рамка: CGRect = есть ? карточка.frame : .zero
        print("ПАНЕЛЬ-ЗАМЕР \(когда): в дереве=\(есть) · рамка \(рамка) · "
              + "hittable=\(есть ? карточка.isHittable : false)")
        return рамка
    }

    // MARK: - Замер

    func testЧтоИменноНеПрокручиваетсяНаШагеЧетыре() {
        XCTAssertTrue(app.buttons["Начать"].firstMatch.waitForExistence(timeout: 40), """
            Первый шаг не показался. «Перечитать» вместо «Начать» → \
            не доехал -Сценарий onboarding; виден таб-бар → не доехал \
            -Онбординг; пусто вовсе → приложение не поднялось.
            """)
        guard нажать("Начать") else { return }

        XCTAssertTrue(дождаться("Кто у тебя живёт"), "Шаг собаки не открылся")
        let кличка = app.textFields["Кличка"].firstMatch
        guard кличка.waitForExistence(timeout: 20) else {
            снять("ОТКАЗ-нет-поля-клички")
            XCTFail("поля «Кличка» нет — ворота шага не пройти")
            return
        }
        кличка.tap()
        кличка.typeText("Стич")
        // Поле ВЕСА нарочно не трогается: ровно на нём обрывается
        // `ПоверхностьОнбординга` на этом устройстве (замер 26.10).
        убратьКлавиатуру(заголовок: "Кто у тебя живёт")
        guard нажать("Дальше") else { return }

        guard дождаться("Режим дня") else {
            снять("ОТКАЗ-режим-дня-не-открылся")
            XCTFail("шаг «Режим дня» не открылся")
            return
        }
        guard нажать("Дальше") else { return }

        guard дождаться("Что будет прерывать") else {
            снять("ОТКАЗ-уведомления-не-открылись")
            XCTFail("шаг «Что будет прерывать» не открылся")
            return
        }

        let окно = app.frame
        print("ПАНЕЛЬ-ОКНО-В-ЗАМЕРЕ: \(окно)")

        // Обе величины разности называются ПРЕЖДЕ самой разности.
        //
        // Верх панели берётся у «Разрешить» — она главная и стоит
        // первой. Если её нет, разность не считается вовсе: «нет
        // предмета» и «ноль» обязаны различаться.
        let главная = app.buttons["Разрешить"].firstMatch
        let тихая = app.buttons["Потом, в настройках"].firstMatch
        let рамкаГлавной: CGRect = главная.exists ? главная.frame : .zero
        let рамкаТихой: CGRect = тихая.exists ? тихая.frame : .zero
        print("ПАНЕЛЬ-КНОПКИ: «Разрешить» есть=\(главная.exists) рамка \(рамкаГлавной)"
              + " · «Потом, в настройках» есть=\(тихая.exists) рамка \(рамкаТихой)")
        guard главная.exists, главная.frame.height > 0 else {
            снять("ОТКАЗ-панели-нет")
            XCTFail("кнопки «Разрешить» на экране нет — мерить разность не от чего")
            return
        }
        let верхПанели = главная.frame.minY

        // 1 · ПОКОЙ. Это то же состояние, что на кадре 15 партии 26.10.
        let вПокое = замерить("в покое")
        снять("01-покой")
        guard вПокое != CGRect.zero else {
            XCTFail("""
                Карточки «Одно напоминание» нет в дереве вовсе — это НЕ то, \
                что мерили 26.10 (там рамка была (34, 557, 263, 24)). \
                Значит изменился экран, а не прокрутка, и весь дальнейший \
                замер отвечал бы про другой предмет.
                """)
            return
        }

        // 2 · ПОВТОР ЧУЖОГО ЗАМЕРА тем же инструментом. Ожидание,
        //     названное заранее: рамка НЕ меняется.
        for _ in 0..<3 { app.swipeUp() }
        let послеSwipe = замерить("после 3 × app.swipeUp()")
        снять("02-после-swipeUp")
        print("ПАНЕЛЬ-ДЕЛЬТА swipeUp: \(вПокое.minY - послеSwipe.minY) pt")

        // 3 · ПРЕДМЕТ. Протяжка строго внутри области содержимого:
        //     начало на 40 pt выше верха панели, конец под шапкой.
        //     Обе точки названы числом, а не доверены XCUITest.
        let откуда = верхПанели - 40
        let куда = окно.minY + 120
        guard откуда > куда else {
            XCTFail("область содержимого короче хода протяжки: панель \(верхПанели), окно \(окно)")
            return
        }
        протянуть(от: откуда, до: куда, зачем: "предмет — тянем содержимое")
        let послеПротяжки = замерить("после протяжки вверх")
        снять("03-после-протяжки")
        let дельта = вПокое.minY - послеПротяжки.minY
        print("ПАНЕЛЬ-ДЕЛЬТА протяжки: \(дельта) pt · ход жеста \(откуда - куда) pt")

        // 4 · КОНТРОЛЬ ТЕМ ЖЕ ИНСТРУМЕНТОМ И В ТОМ ЖЕ ЗАХОДЕ: возврат.
        //     Ломается ВМЕСТЕ с предметом — в этом и смысл.
        протянуть(от: куда, до: откуда, зачем: "контроль — возврат вниз")
        let послеВозврата = замерить("после возврата вниз")
        print("ПАНЕЛЬ-КОНТРОЛЬ возврат: minY \(послеВозврата.minY) "
              + "против \(вПокое.minY) в покое")

        // 5 · ВЕРДИКТ. Механизм называется числом, а не впечатлением.
        let механизм: String
        switch дельта {
        case ..<10:
            механизм = """
                D или сломанный инструмент. Протяжка не сдвинула ничего. \
                Если и контроль-возврат дал ноль — это ДВА НУЛЯ, то есть \
                «вопрос не тот»: сперва инструмент, потом продукт.
                """
        case 10..<100:
            механизм = """
                A: вычитается нижний край ОКНА, а не панель. Прокрутка \
                кончается раньше, чем карточка выходит из-под панели, \
                и хвост её недостижим при любом числе жестов.
                """
        default:
            механизм = """
                B: область прокрутки уменьшена панелью верно, содержимое \
                достижимо. Тогда 26.10 померен НЕ продукт, а точка начала \
                жеста app.swipeUp(): она попадает в нижнюю панель.
                """
        }
        print("ПАНЕЛЬ-МЕХАНИЗМ: дельта \(дельта) pt → \(механизм)")

        // Приёмка — ПОЛОЖЕНИЕ, а не дельта. После протяжки карточка
        // обязана стоять целиком выше верха панели и попадать пальцем.
        let нижнийКрай = послеПротяжки.maxY
        print("ПАНЕЛЬ-ПРИЁМКА: низ карточки \(нижнийКрай) против верха панели \(верхПанели)")
        XCTAssertTrue(послеПротяжки != CGRect.zero && нижнийКрай <= верхПанели
                      && карточка.isHittable, """
            Карточка «Одно напоминание в …» не выходит из-под нижней панели \
            даже протяжкой, начатой заведомо внутри содержимого. \
            Дельта \(дельта) pt при ходе жеста \(откуда - куда) pt. \
            Механизм по числу: \(механизм)
            """)
    }
}
