import XCTest

/// Шапка не смеет говорить «записей нет», стоя над записью.
///
/// **Кадр от 24.09.2026, телефон мамы.** Шапка «Записей нет с 22 сент.»
/// стояла над лентой с едой в 15:23 и дозой в 15:24 — над записями,
/// сделанными тремя минутами раньше. Герой знает только выходы:
/// `indoors` и `lastOutingEndedAt` считаются по блокам выхода, еда
/// и дозы в них не входят вовсе. Строка обобщала «нет выходов»
/// до «нет записей» и говорила о дневнике то, чего не знала.
///
/// **Снять это было нечем.** В демо-наборе два выхода за сегодня,
/// и ветка тишины не рисовалась ни в одном кадре — ни в UI-тестах,
/// ни в превью. Поэтому рядом с починкой заведён сценарий
/// `SeedData.Scenario.silence`: выход позавчера, еда сегодня.
/// Непроверяемая поверхность лечится входом, а не внимательностью.
nonisolated final class ТишинаДольшеСуток: XCTestCase {
    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "silence"]
        app.launch()
        _ = app.staticTexts["Стич"].waitForExistence(timeout: 10)
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Первым — что сценарий вообще наполнил базу.
    ///
    /// Без этой проверки остальные были бы зелёными, ничего не проверив:
    /// пустой экран не содержит ни «Записей нет», ни еды.
    func test01СценарийПоставилЗаписьЗаСегодня() {
        XCTAssertTrue(app.staticTexts["Еда"].firstMatch.waitForExistence(timeout: 5),
                      "в ленте нет записи о еде — сценарий silence не наполнил базу, "
                      + "и всё, что скажут остальные проверки этого файла, будет про пустой экран")
    }

    /// От обратного: не «шапка говорит что-нибудь про выходы», а
    /// «шапки „записей нет“ на экране с записью нет ни в каком виде».
    ///
    /// Утверждение «шапка упоминает выходы» выполнялось бы и тогда, когда
    /// рядом осталась вторая, ложная строка.
    func test02ШапкаНеГоворитЧтоЗаписейНет() {
        let ложная = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "Записей нет")
        ).firstMatch
        XCTAssertFalse(ложная.waitForExistence(timeout: 2),
                       "на экране с записью за сегодня стоит «записей нет» — "
                       + "приложение говорит о дневнике то, чего не знает: "
                       + "оно знает только, что не было выходов")
    }

    func test03ШапкаНазываетИменноВыходы() {
        let верная = app.staticTexts.containing(
            NSPredicate(format: "label BEGINSWITH %@", "Выходов нет с")
        ).firstMatch
        XCTAssertTrue(верная.waitForExistence(timeout: 5),
                      "за сутками тишины герой обязан сказать «Выходов нет с …»: "
                      + "число часов на этот вопрос уже не отвечает, а «записей нет» — "
                      + "неправда, пока в ленте есть запись")
        снять("тишина-дольше-суток")
    }
}
