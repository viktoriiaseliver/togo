import XCTest

/// Мама жмёт «покормила» — и что из этого выходит.
///
/// # Зачем этот файл существует
///
/// Замер 14.10.2026: **ни один из 1072 тестов ни разу не был мамой.**
/// Во всех десяти сценариях демо-базы «я» это
/// `FamilyMember(name: "Виктория", role: .owner, isMe: true)`
/// (`SeedData.swift:346`), а двадцать два файла показа ветвятся
/// по роли или праву. Права посчитаны одиннадцатью модульными
/// сюитами; **сказаны — ни разу**.
///
/// Отсюда и цена: дыра прав на экране семьи жила месяц при зелёном
/// наборе. Это не «не заметили» — заметить было нечем.
///
/// > Механизм без входа тестом не отличается от рабочего: тесты
/// > заводят записи сами.
///
/// # Кого именно изображает этот стенд — и кого НЕ изображает
///
/// Сказать «так видит мама» было бы неправдой, и это уточнение
/// пришло замером `togo-russian-testflight-fix` 14.10, до того как
/// кадр был снят и подписан.
///
/// Права гость теряет **не всегда**. `FamilyResolver.меня`
/// (`FamilyResolver.swift:50`) сперва ищет карточку по запомненному
/// `myMemberID`, и если находит — отдаёт её права **даже гостю**.
/// А `myMemberID` ставится при онбординге (`OnboardingFlow:162`).
/// Значит мама, прошедшая онбординг на своём телефоне, прав
/// не теряет, и отказа у неё не будет вовсе.
///
/// Отказ наступает там, где **себя опознать не удалось в чужом
/// дневнике**:
///
/// ```
/// приняла приглашение, не пройдя онбординг
/// переустановила приложение   myMemberID в UserDefaults, карточки
///                             в базе — теряются порознь
/// восстановилась из архива    карточки приехали, запомненный id нет
/// карточка удалена или слита
/// ```
///
/// **Стенд воспроизводит именно это состояние, и воспроизводит
/// верно:** `SeedData` заводит владельца с `isMe: true`, но
/// `myMemberID` не ставит (его ставят только `OnboardingFlow:162`
/// и кнопка «Это я»), а запасной путь «единственная карточка
/// с `isMe`» у гостя отключён явным `guard !гость`
/// (`FamilyResolver.swift:57`).
///
/// Поэтому подпись к кадру — «так видит второй человек, когда себя
/// опознать не удалось», а не «так видит мама». Иначе вышло бы наше
/// же: объяснение, придуманное к верному замеру, наследует его
/// достоверность и своей не имеет.
///
/// # Что именно проверяется
///
/// Второй человек в чужом дневнике до опознания — `.observer`
/// («читает всё, не пишет», `FamilyResolver.swift:69-71`).
/// `EventLog.swift:62` — единственная дверь, которой запись попадает
/// в дневник, и она же единственное место, где право проверяется.
/// На отказе стоит `showFailure` и `return nil`: запись НЕ создана.
///
/// Это важно отличать от прежнего поведения, которое там же описано:
/// раньше отказ уезжал через `showUndo`, то есть **под галочку
/// «готово»** — человек жал «покормила», в дневник не попадало
/// ничего, и приложение подтверждало успех.
///
/// # Почему здесь ДВА запуска, а не один
///
/// Зелёный тест на одном запуске доказывал бы не то. «Записи нет»
/// получается и когда права отняты верно, и когда кнопка просто
/// сломана, — и эти два исхода на экране неотличимы. Поэтому сперва
/// владелец проходит путь до конца (контроль: путь рабочий), и только
/// потом тот же путь проходит гость.
///
/// **Направление проверки решает цену:** сторож, который не краснеет
/// на здоровом коде, ничего не доказывает.
///
/// # Чего этот файл НЕ проверяет
///
/// Что запись доехала до второго телефона. Этого стендом не взять
/// вовсе: нужны два живых iCloud. И отдельно — из двенадцати типов
/// общего дневника в контейнере существуют пять
/// (`cktool export-schema`, замер 14.10): `WeightEntry`, `Clinic`,
/// `DogDocument`, `LabResult`, `VetVisit`, `Diagnosis`, `Prescription`
/// отсутствуют. То есть даже с починенными правами мама сможет
/// кормить и гулять, но взвешивание у неё уйдёт в молчание.
/// Здесь это не проверяется и проверено быть не может.
nonisolated final class ГостьНеПишет: XCTestCase {

    /// Начало текста отказа — из `EventLog.swift:85`.
    ///
    /// **Ищется вхождением, а не равенством, и это не послабление.**
    /// Первая редакция сверяла строку целиком, и через двадцать минут
    /// `11dfc13` дописал к фразе вторую строку — адрес действия
    /// («Семья → Это я»), которого раньше не было. Сверка равенством
    /// покраснела бы на **улучшении** продукта и потребовала бы
    /// разбирать починку как поломку.
    ///
    /// Что здесь проверяется по существу: человеку сказано, **кто**
    /// записывает. Чем именно продолжена фраза — дело того, кто
    /// правит текст; что она есть — дело этого теста.
    private let отказ = "Это записывает тот, кому разрешено"

    /// Элемент с этим текстом внутри — любой глубины.
    ///
    /// `staticTexts[строка]` спрашивает точное совпадение
    /// идентификатора, то есть отвечает «нет» и тогда, когда текст
    /// на экране есть, но длиннее. Для многострочной плашки это
    /// ответ про мерку, а не про экран.
    private func плашкаОтказа(_ app: XCUIApplication) -> XCUIElement {
        app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", отказ))
            .firstMatch
    }

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-гостя")
    }

    override func setUp() {
        continueAfterFailure = false
    }

    private func запустить(_ аргументы: [String]) -> XCUIApplication {
        let app = XCUIApplication()
        app.launchArguments = аргументы
        app.launch()
        return app
    }

    /// Имена записанных кадров. Печатаются в `tearDown` ВСЕГДА.
    private var снято: [String] = []

    override func tearDown() {
        // Счёт печатается ВСЕГДА, в том числе после падения посреди
        // прохода. Иначе «снято всё» и «упал на третьем» выглядят
        // в логе ОДИНАКОВО: во втором случае строк `КАДР:` просто
        // меньше, а отсутствия никто не ищет.
        //
        // Ожидаемого числа здесь НЕТ нарочно: вторая копия числа
        // разошлась бы с первой молча. Сколько кадров должно быть,
        // утверждает сам тест своей проверкой, а не эта печать.
        print("КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
        super.tearDown()
    }

    @discardableResult
    private func снять(_ app: XCUIApplication, _ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        снято.append(имя)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    /// Пройти путь «Еда → Записать». Возвращает приложение на том
    /// экране, где исход уже виден.
    private func отметитьЕду(_ app: XCUIApplication) {
        // **Дорога изменилась 24.10.2026.** Кнопки «Еда» на главном
        // нет — `ActionGrid` удалён; еда записывается из шторки
        // «Записать» («+», крючок `низ-записать`). Прежний текст
        // отказа был верен по форме («это отказ ДОРОГИ, а не прав»)
        // и всё равно читался как дефект продукта.
        let плюс = app.buttons["низ-записать"].firstMatch
        XCTAssertTrue(плюс.waitForExistence(timeout: 15), """
            кнопки «Записать» нет на главном. Это отказ ДОРОГИ,
            а не прав: до проверки права мы даже не дошли.
            """)
        плюс.tap()
        let еда = найти("Еда", в: app)
        XCTAssertTrue(еда.waitForExistence(timeout: 5), """
            в шторке «Записать» нет строки «Еда» — снова отказ дороги.
            """)
        еда.tap()

        let записать = app.buttons["Записать"].firstMatch
        XCTAssertTrue(записать.waitForExistence(timeout: 5), """
            лист еды не открылся или в нём нет «Записать» — снова
            отказ дороги, и он не равен отказу права.
            """)
        записать.tap()
    }

    // MARK: - Контроль: путь рабочий

    /// Хозяин проходит путь до конца.
    ///
    /// Без этого теста второй ничего не значит: «записи нет» одинаково
    /// выходит и у отнятого права, и у сломанной кнопки.
    func testВладелецЗаписываетЕдуИВидитОтмену() throws {
        let app = запустить(["-UITesting"])
        отметитьЕду(app)

        XCTAssertTrue(app.buttons["Отменить"].waitForExistence(timeout: 5), """
            у ВЛАДЕЛЬЦА запись не прошла. Значит сломан путь, а не права,
            и тест про гостя ниже доказывал бы не то.
            """)
        XCTAssertFalse(плашкаОтказа(app).exists,
                       "владельцу показан отказ по праву — права перепутаны местами")
    }

    // MARK: - Предмет: гость

    /// Гость в чужом дневнике жмёт «покормила».
    ///
    /// Запуск с `-ЧужаяЗона <имя>`: аргумент пишет
    /// `SharedZoneOwner.name` в `UserDefaults` группы приложений
    /// до первого чтения (вход заводит `togo-onboarding-status-check`,
    /// смена 14.10). Непустое имя делает `SharedZoneOwner.isGuest`
    /// истинным, `FamilyResolver.меня` отдаёт `nil`, и роль становится
    /// `.observer`.
    func testГостьЖмётПокормилаИВидитОтказАНеГалочку() throws {
        let app = запустить(["-UITesting", "-ЧужаяЗона", "Виктория"])

        // Сперва убеждаемся, что аргумент вообще доехал. Если роль
        // осталась владельцем, всё ниже позеленеет не по той причине,
        // и мы запишем «гость не пишет» про хозяина.
        // **Вкладки «Семья» нет с 22.10** — экран уехал в меню «…»
        // (`HeaderMenu.swift:64`), и прежняя проверка говорила
        // «приложение не поднялось» про поднявшееся приложение.
        //
        // Здесь ДВА разных вопроса, и прежде они были слиты в один:
        //
        // ```
        // поднялось ли приложение   шапка «Ещё» есть на всех экранах
        // доехал ли аргумент роли   экран «Семья» показывает гостю
        //                           строку «Ты в этом дневнике гость»
        // ```
        //
        // Второе — **контроль в другом канале, чем предмет**: предмет
        // ниже это отказ при записи еды, а роль подтверждается
        // текстом на чужом экране. Контроль из того же канала
        // сломался бы вместе с предметом.
        XCTAssertTrue(app.buttons["Ещё"].firstMatch.waitForExistence(timeout: 15),
                      "приложение не поднялось: шапки нет")
        отметитьЕду(app)

        let плашка = плашкаОтказа(app)
        let естьОтказ = плашка.waitForExistence(timeout: 5)
        let естьОтмена = app.buttons["Отменить"].exists

        // **КОНТРОЛЬ РОЛИ — ПОСЛЕ ПРЕДМЕТА, и это порядок по замеру.**
        // `открытьСемью` уводит на вкладку собаки навигационным
        // переходом (`DogTab:108`, `navigationDestination`), а «+»
        // живёт только на «Сегодня». Возврат оттуда дважды не удался,
        // и тест падал с «кнопки Записать нет на главном» — будучи
        // не на главном.
        //
        // > **Если контроль мешает замеру, меняют порядок, а не
        // > контроль.** Он по-прежнему в другом канале, чем предмет,
        // > и по-прежнему обязателен: без него зелёное «гость
        // > не пишет» могло бы относиться к хозяину.
        XCTAssertTrue(открытьСемью(в: app), "экран «Семья» не открылся")
        XCTAssertTrue(найти("Ты в этом дневнике гость", в: app)
                        .waitForExistence(timeout: 5), """
            на экране «Семья» нет строки о гостевой роли — значит
            аргумент `-ЧужаяЗона` НЕ доехал, роль осталась владельцем,
            и всё ниже позеленело бы не по той причине.
            """)
        // **Вернуться НА ВКЛАДКУ «Сегодня», а не просто закрыть
        // экран.** `открытьСемью` уводит на вкладку собаки (пункт
        // меню живёт только там), и «назад» возвращает в собаку,
        // а «+» (`низ-записать`) есть лишь на «Сегодня». Первая
        // редакция жала только «назад» и получала «кнопки Записать
        // нет на главном» — будучи не на главном.
        let назад = app.navigationBars.buttons.firstMatch
        if назад.exists { назад.tap() }
        let сегодня = app.tabBars.buttons.element(boundBy: 0)
        if сегодня.waitForExistence(timeout: 10) { сегодня.tap() }



        // Адрес действия — вторая половина починки `11dfc13`: отказ,
        // не называющий выхода, оставляет человека в стене без двери.
        // Проверяется ОТДЕЛЬНО от самого отказа: «сказано, что нельзя»
        // и «сказано, что делать» — разные обещания, и второе
        // не следует из первого.
        let естьВыход = app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", "Это я"))
            .firstMatch.exists

        try снять(app, "гость-жмёт-еду")

        print("""
            ВЫВОД ДЛЯ ГЛАЗА:
              отказ по праву показан : \(естьОтказ)
              адрес выхода показан   : \(естьВыход)
              тост отмены показан    : \(естьОтмена)
            Третье ИСТИНА при первом ЛОЖЬ — значит запись ПРОШЛА,
            то есть роль гостя не применилась либо право не проверено.
            Первое ИСТИНА при втором ЛОЖЬ — отказ честен, но выхода
            человеку не назвал: ровно та стена без двери, которую
            чинил `11dfc13`.
            """)

        XCTAssertTrue(естьВыход, """
            отказ показан, а выхода нет. `EventLog.swift:85` собирает
            фразу из трёх ключей, второй строкой — «Семья → Это я».
            Если её не видно, либо правка `11dfc13` не в этом дереве,
            либо вторая строка обрезана показом — и тогда человек
            снова упирается в стену без двери.
            """)

        XCTAssertFalse(естьОтмена, """
            гостю показан тост отмены — значит запись СОЗДАНА. Либо
            `-ЧужаяЗона` не доехал до `SharedZoneOwner`, либо право
            `.logBasics` у наблюдателя не отнято. Это разные поломки,
            и различает их экран семьи: посмотри кадр.
            """)
        XCTAssertTrue(естьОтказ, """
            гость не увидел НИЧЕГО: ни записи, ни отказа. Это худший
            из трёх исходов — человек жмёт и не понимает, случилось ли
            что-нибудь. Ровно так выглядела бы потеря, если бы отказ
            молчал.
            """)
    }

    // MARK: - Вторая дорога к тому же запрету

    /// Право `.logBasics` проверяется в ДВУХ местах, и тексты разные.
    ///
    /// ```
    /// EventLog.swift:85          «Это записывает тот, кому разрешено»
    ///                            путь: кнопка «Еда» → лист → «Записать»
    /// DayPlanActions.swift:104   «Записывать может тот, кому это
    ///                             разрешено»
    ///                            путь: тап по пункту плана дня
    /// ```
    ///
    /// Один запрет, два текста. Адрес действия («Семья → Это я»)
    /// дописан к обоим — `11dfc13` и `a689361`, — но **разными
    /// правками и в разные часы**: первая дорога была починена,
    /// вторая жила ещё полчаса. Сведение самих формулировок отдано
    /// решением наверх: оно осиротило бы ключ с готовым французским
    /// переводом, и это размен, а не уборка.
    ///
    /// Поэтому дороги проверяются **по отдельности**: зелёная первая
    /// ничего не говорит о второй — мы это сегодня и наблюдали.
    ///
    /// Пункт плана опознаётся по заголовку `"Еда · <N> г"`
    /// (`DayPlanBuilder.swift:28`). Это не та же кнопка, что «Еда»
    /// в сетке действий, и спутать их нельзя: у сетки заголовок без
    /// точки и граммов.
    /// Пункт плана дня, опознанный по заголовку `"Еда · <N> г"`.
    ///
    /// Ищется среди **кнопок и ячеек**, а не по всему дереву:
    /// `TGCheckRow` (`DayPlan.swift:174`) кладёт в дерево доступности
    /// и текст, и нажимаемый элемент. Тап по тексту не делает ничего
    /// и **выглядит как сделанный** — ровно та дыра, из-за которой
    /// прогон 18:29 не смог ответить, что произошло.
    /// **Предикат строится ВНУТРИ цикла, и это не стиль.**
    ///
    /// Вынесенный наружу `let предикат = NSPredicate(…)` сломал сборку
    /// UI-таргета у всей смены: `NSPredicate` не `Sendable`, и передача
    /// его в `запрос.matching(_:)` пересекает границу изоляции —
    /// `sending 'предикат' risks causing data races`. Поломка моя,
    /// `be2721e`.
    ///
    /// Дороже обычной красноты она тем, что **приходит не по адресу**:
    /// `xcodebuild` собирает всю схему, поэтому даже
    /// `-only-testing:TogoTests` умирает на UI-таргете, не дойдя
    /// ни до одного теста. Соседу это выглядит как «мой набор
    /// не собрался».
    ///
    /// > **Отказ пришёл в той же форме, что собственный дефект.**
    /// > `projects-c3` потратил на это прогон и полчаса, прежде чем
    /// > посмотрел, чей файл.
    ///
    /// И отдельно: `swiftc -typecheck` по `Togo` + `TogoShared`,
    /// которым я проверял вершину перед стартом, **этого не видит
    /// по устройству** — тест-таргеты он не берёт. Рецепт был слеп
    /// ровно там, где я сломал.
    /// **Прокрутка обязательна, и её здесь не было ни одной** — замер
    /// 21.10.2026 по дереву элементов из `.xcresult`:
    ///
    /// ```
    /// app.buttons … «Еда · 60 г, 19:30»   exists = TRUE
    ///                                     isHittable = FALSE
    /// рамка строки   {{90,0; 770,7},{278,0; 40,3}}
    /// нижняя панель  {{0; 726,2},{402; 147,8}}   ← строка целиком ВНУТРИ
    /// ```
    ///
    /// То есть пункт в дереве был, лежал под нижней панелью, и помощник
    /// возвращал `nil` — а оба теста читали это как «пункта плана нет».
    ///
    /// > **Оба теста обнулились ВМЕСТЕ — предмет и его контроль.**
    /// > В тексте написано «если контрольный тест владельца зелёный,
    /// > значит дело в роли»; он не зелёный, и по своду два нуля вместе
    /// > значат «вопрос не тот», а не находку о правах. Про отказ
    /// > наблюдателю (`DayPlanActions.swift`) этот прогон не говорит
    /// > ничего, и вторая дорога гостя остаётся непомеренной с 14.10.
    /// **Ищем КРУГ ОТМЕТКИ, а не текст строки** — замер 21.10.2026
    /// по AX-дереву: у строки плана ДВЕ живых кнопки, и они делают
    /// разное.
    ///
    /// ```
    /// 'Отметить · Еда · 60 г'          {{34, 382.7},{44, 44}}   отмечает
    /// 'Еда · 60 г, 18:30 · Acana…'     {{90, 384.3},{278, 40.3}} открывает
    /// ```
    ///
    /// Прежний предикат `BEGINSWITH "Еда · "` попадал **только
    /// во вторую** — у круга подпись начинается с «Отметить», и под
    /// старое условие он не попадал по устройству. А `open()` у
    /// неотмеченного пункта молча выходит (`TodayScreen` —
    /// `guard item.isDone else { return }`): открывать нечего,
    /// записи ещё нет.
    ///
    /// > **Тап попал — в другую настоящую кнопку.** «Не попал» и «попал
    /// > не туда» снаружи одинаковы: и там и там ничего не произошло.
    /// > Кадр из прогона это и показал — круг пустой, тоста нет,
    /// > «сделано · 1» не изменилось.
    ///
    /// Поэтому и контрольный тест владельца был красным: дорога
    /// создания записи в том прогоне **не трогалась ни разу**, и про
    /// права гостя он не говорил ничего.
    private func пунктПланаЕда(_ app: XCUIApplication) -> XCUIElement? {
        for запрос in [app.buttons, app.cells] {
            let найдено = запрос
                .matching(NSPredicate(format: "label BEGINSWITH %@", "Отметить · Еда"))
                .firstMatch
            guard найдено.exists else { continue }
            if найдено.isHittable { return найдено }
            // Есть, но не достать: докручиваем. Шесть шагов — столько же,
            // сколько у общего `найти`, чтобы срок ожидания был один
            // на весь набор.
            for _ in 0..<6 {
                app.swipeUp()
                if найдено.isHittable { return найдено }
            }
        }
        return nil
    }

    // MARK: - Контроль второй дороги: тап вообще срабатывает?

    /// **Владелец тапает тот же пункт плана, и запись создаётся.**
    ///
    /// Заведён после прогона 18:29, где гость тапнул пункт плана
    /// и не увидел ни записи, ни отказа. Кадр показал пустой экран —
    /// и на два разных вывода отвечал одинаково:
    ///
    /// ```
    /// тап не попал в отметку        → про мерку
    /// отказ не показан              → про продукт
    /// ```
    ///
    /// > Два разных вывода, на которые инструмент отвечает одинаково, —
    /// > это не «не сняли», это **снять нечем**. Лечится не вторым
    /// > кадром того же места, а контролем на здоровом пути.
    ///
    /// Поэтому здесь тот же тап делает **владелец**. Пройдёт —
    /// значит тап попадает, и отсутствие отказа у гостя есть находка
    /// о продукте. Не пройдёт — значит мерка не достаёт до отметки,
    /// и про гостя этим путём нельзя утверждать ничего.
    func testВладелецТапаетПунктПланаИЗаписьСоздаётся() throws {
        let app = запустить(["-UITesting"])

        guard let пункт = пунктПланаЕда(app) else {
            XCTFail("""
                пункта плана «Еда · …» нет среди кнопок и ячеек даже
                у ВЛАДЕЛЬЦА. Значит мерка не достаёт до нажимаемого
                элемента, и тест про гостя ниже не докажет ничего:
                его пустой экран будет про нас, а не про продукт.
                """)
            return
        }
        пункт.tap()

        XCTAssertTrue(app.buttons["Отменить"].waitForExistence(timeout: 5), """
            у ВЛАДЕЛЬЦА тап по пункту плана не создал запись. Либо
            путь требует шторки «когда дали» (LateMarking), либо тап
            не попал. В обоих случаях вторая дорога у гостя остаётся
            НЕРАЗЛИЧИМОЙ, и так её и надо записать.
            """)
    }

    func testГостьЖмётПунктПланаИВидитВторойОтказ() throws {
        let app = запустить(["-UITesting", "-ЧужаяЗона", "Виктория"])

        // Приложению надо подняться прежде, чем спрашивать план дня:
        // `пунктПланаЕда` не ждёт, он смотрит на текущее дерево.
        _ = app.tabBars.buttons["Семья"].firstMatch.waitForExistence(timeout: 15)

        // ТА ЖЕ мерка, что в контрольном тесте выше. Разные мерки
        // у контроля и у предмета обессмыслили бы контроль: он
        // доказывал бы проходимость другого пути.
        guard let пункт = пунктПланаЕда(app) else {
            XCTFail("""
                пункта плана «Еда · …» нет среди кнопок и ячеек.
                Это отказ ДОРОГИ, а не прав: до проверки права
                мы не дошли, и вывода о правах делать нельзя.
                Если контрольный тест владельца при этом зелёный —
                значит дело в роли, и это уже находка.
                """)
            return
        }
        пункт.tap()

        let второй = "Записывать может тот, кому это разрешено"
        let естьВторойОтказ = app.staticTexts
            .matching(NSPredicate(format: "label CONTAINS %@", второй))
            .firstMatch.waitForExistence(timeout: 5)

        try снять(app, "гость-жмёт-пункт-плана")

        XCTAssertFalse(app.buttons["Отменить"].exists, """
            по второй дороге запись ПРОШЛА. Значит `checkPermission`
            в `DayPlanActions` пропустил наблюдателя — при том, что
            первая дорога его остановила. Один запрет, две двери,
            и закрыта одна.
            """)
        XCTAssertTrue(естьВторойОтказ, """
            второй отказ не показан. Либо текст изменён (тогда
            поправить здесь — это нормальный ход), либо шторка
            «когда дали» открылась ВПЕРЁД проверки права. Второе —
            предмет: `TodayScreen.swift:897` ставит `checkPermission`
            до шторки нарочно, чтобы не заставлять человека делать
            работу, которую всё равно выбросят.
            """)
    }
