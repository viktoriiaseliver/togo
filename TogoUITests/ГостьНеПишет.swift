import XCTest

/// Мама жмёт «покормила» — и что из этого выходит.
///
/// # Зачем этот файл существует
///
/// Замер 14.10.2026: **ни один из 1072 тестов ни разу не был мамой.**
/// Во всех десяти сценариях демо-базы «я» это
/// `FamilyMember(name: "Виктория", role: .owner, isMe: true)`
/// (`SeedData.swift:346`), а двадцать два файла показа ветвятся
/// по роли или праву. Права посчитаны одиннадцатью модульными
/// сюитами; **сказаны — ни разу**.
///
/// Отсюда и цена: дыра прав на экране семьи жила месяц при зелёном
/// наборе. Это не «не заметили» — заметить было нечем.
///
/// > Механизм без входа тестом не отличается от рабочего: тесты
/// > заводят записи сами.
///
/// # Что именно проверяется
///
/// Второй человек в чужом дневнике до опознания — `.observer`
/// («читает всё, не пишет», `FamilyResolver.swift:69-71`).
/// `EventLog.swift:62` — единственная дверь, которой запись попадает
/// в дневник, и она же единственное место, где право проверяется.
/// На отказе стоит `showFailure` и `return nil`: запись НЕ создана.
///
/// Это важно отличать от прежнего поведения, которое там же описано:
/// раньше отказ уезжал через `showUndo`, то есть **под галочку
/// «готово»** — человек жал «покормила», в дневник не попадало
/// ничего, и приложение подтверждало успех.
///
/// # Почему здесь ДВА запуска, а не один
///
/// Зелёный тест на одном запуске доказывал бы не то. «Записи нет»
/// получается и когда права отняты верно, и когда кнопка просто
/// сломана, — и эти два исхода на экране неотличимы. Поэтому сперва
/// владелец проходит путь до конца (контроль: путь рабочий), и только
/// потом тот же путь проходит гость.
///
/// **Направление проверки решает цену:** сторож, который не краснеет
/// на здоровом коде, ничего не доказывает.
///
/// # Чего этот файл НЕ проверяет
///
/// Что запись доехала до второго телефона. Этого стендом не взять
/// вовсе: нужны два живых iCloud. И отдельно — из двенадцати типов
/// общего дневника в контейнере существуют пять
/// (`cktool export-schema`, замер 14.10): `WeightEntry`, `Clinic`,
/// `DogDocument`, `LabResult`, `VetVisit`, `Diagnosis`, `Prescription`
/// отсутствуют. То есть даже с починенными правами мама сможет
/// кормить и гулять, но взвешивание у неё уйдёт в молчание.
/// Здесь это не проверяется и проверено быть не может.
nonisolated final class ГостьНеПишет: XCTestCase {

    /// Начало текста отказа — из `EventLog.swift:85`.
    ///
    /// **Ищется вхождением, а не равенством, и это не послабление.**
    /// Первая редакция сверяла строку целиком, и через двадцать минут
    /// `11dfc13` дописал к фразе вторую строку — адрес действия
    /// («Семья → Это я»), которого раньше не было. Сверка равенством
    /// покраснела бы на **улучшении** продукта и потребовала бы
    /// разбирать починку как поломку.
    ///
    /// Что здесь проверяется по существу: человеку сказано, **кто**
    /// записывает. Чем именно продолжена фраза — дело того, кто
    /// правит текст; что она есть — дело этого теста.
    private let отказ = "Это записывает тот, кому разрешено"

    /// Элемент с этим текстом внутри — любой глубины.
    ///
    /// `staticTexts[строка]` спрашивает точное совпадение
    /// идентификатора, то есть отвечает «нет» и тогда, когда текст
    /// на экране есть, но длиннее. Для многострочной плашки это
    /// ответ про мерку, а не про экран.
    private func плашкаОтказа(_ app: XCUIApplication) -> XCUIElement {
        app.staticTexts
            .containing(NSPredicate(format: "label CONTAINS %@", отказ))
            .firstMatch
    }

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-гостя")
    }

    override func setUp() {
        continueAfterFailure = false
    }

    private func запустить(_ аргументы: [String]) -> XCUIApplication {
        let app = XCUIApplication()
        app.launchArguments = аргументы
        app.launch()
        return app
    }

    @discardableResult
    private func снять(_ app: XCUIApplication, _ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    /// Пройти путь «Еда → Записать». Возвращает приложение на том
    /// экране, где исход уже виден.
    private func отметитьЕду(_ app: XCUIApplication) {
        let еда = app.buttons["Еда"].firstMatch
        XCTAssertTrue(еда.waitForExistence(timeout: 15), """
            кнопки «Еда» нет на главном. Это отказ ДОРОГИ, а не прав:
            до проверки права мы даже не дошли.
            """)
        еда.tap()

        let записать = app.buttons["Записать"].firstMatch
        XCTAssertTrue(записать.waitForExistence(timeout: 5), """
            лист еды не открылся или в нём нет «Записать» — снова
            отказ дороги, и он не равен отказу права.
            """)
        записать.tap()
    }

    // MARK: - Контроль: путь рабочий

    /// Хозяин проходит путь до конца.
    ///
    /// Без этого теста второй ничего не значит: «записи нет» одинаково
    /// выходит и у отнятого права, и у сломанной кнопки.
    func testВладелецЗаписываетЕдуИВидитОтмену() throws {
        let app = запустить(["-UITesting"])
        отметитьЕду(app)

        XCTAssertTrue(app.buttons["Отменить"].waitForExistence(timeout: 5), """
            у ВЛАДЕЛЬЦА запись не прошла. Значит сломан путь, а не права,
            и тест про гостя ниже доказывал бы не то.
            """)
        XCTAssertFalse(плашкаОтказа(app).exists,
                       "владельцу показан отказ по праву — права перепутаны местами")
    }

    // MARK: - Предмет: гость

    /// Гость в чужом дневнике жмёт «покормила».
    ///
    /// Запуск с `-ЧужаяЗона <имя>`: аргумент пишет
    /// `SharedZoneOwner.name` в `UserDefaults` группы приложений
    /// до первого чтения (вход заводит `togo-onboarding-status-check`,
    /// смена 14.10). Непустое имя делает `SharedZoneOwner.isGuest`
    /// истинным, `FamilyResolver.меня` отдаёт `nil`, и роль становится
    /// `.observer`.
    func testГостьЖмётПокормилаИВидитОтказАНеГалочку() throws {
        let app = запустить(["-UITesting", "-ЧужаяЗона", "Виктория"])

        // Сперва убеждаемся, что аргумент вообще доехал. Если роль
        // осталась владельцем, всё ниже позеленеет не по той причине,
        // и мы запишем «гость не пишет» про хозяина.
        let вкладкаСемья = app.tabBars.buttons["Семья"].firstMatch
        XCTAssertTrue(вкладкаСемья.waitForExistence(timeout: 15),
                      "приложение не поднялось")

        отметитьЕду(app)

        let плашка = плашкаОтказа(app)
        let естьОтказ = плашка.waitForExistence(timeout: 5)
        let естьОтмена = app.buttons["Отменить"].exists

        // Адрес действия — вторая половина починки `11dfc13`: отказ,
        // не называющий выхода, оставляет человека в стене без двери.
        // Проверяется ОТДЕЛЬНО от самого отказа: «сказано, что нельзя»
        // и «сказано, что делать» — разные обещания, и второе
        // не следует из первого.
        let естьВыход = app.staticTexts
            .containing(NSPredicate(format: "label CONTAINS %@", "Это я"))
            .firstMatch.exists

        try снять(app, "гость-жмёт-еду")

        print("""
            ВЫВОД ДЛЯ ГЛАЗА:
              отказ по праву показан : \(естьОтказ)
              адрес выхода показан   : \(естьВыход)
              тост отмены показан    : \(естьОтмена)
            Третье ИСТИНА при первом ЛОЖЬ — значит запись ПРОШЛА,
            то есть роль гостя не применилась либо право не проверено.
            Первое ИСТИНА при втором ЛОЖЬ — отказ честен, но выхода
            человеку не назвал: ровно та стена без двери, которую
            чинил `11dfc13`.
            """)

        XCTAssertTrue(естьВыход, """
            отказ показан, а выхода нет. `EventLog.swift:85` собирает
            фразу из трёх ключей, второй строкой — «Семья → Это я».
            Если её не видно, либо правка `11dfc13` не в этом дереве,
            либо вторая строка обрезана показом — и тогда человек
            снова упирается в стену без двери.
            """)

        XCTAssertFalse(естьОтмена, """
            гостю показан тост отмены — значит запись СОЗДАНА. Либо
            `-ЧужаяЗона` не доехал до `SharedZoneOwner`, либо право
            `.logBasics` у наблюдателя не отнято. Это разные поломки,
            и различает их экран семьи: посмотри кадр.
            """)
        XCTAssertTrue(естьОтказ, """
            гость не увидел НИЧЕГО: ни записи, ни отказа. Это худший
            из трёх исходов — человек жмёт и не понимает, случилось ли
            что-нибудь. Ровно так выглядела бы потеря, если бы отказ
            молчал.
            """)
    }
}
