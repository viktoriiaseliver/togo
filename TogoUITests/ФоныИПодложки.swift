import XCTest

/// Фоны и подложки на живом приложении: **помещается ли картинка**.
///
/// # Чем этот набор отличается от четырёх прежних
///
/// Подложки — самые большие картинки в приложении, и кадров по ним
/// почти не было. Причина не в лени, а в двух стенах, и обе названы:
///
/// ```
/// PhotosPicker          отдельный процесс, прогон туда не достаёт
/// ImageRenderer экрана  402 × 760 со знаком запрета — ЗАГЛУШКА
///                       SwiftUI «этот вид отрисовать нельзя»
/// ```
///
/// Вторая дороже первой. **Отказ отрисовки приходит в виде кадра:**
/// файл записан, счёт напечатан, прогон зелёный — и кадр не про экран.
/// Тот тест сняли, и правильно: кадр-заглушка хуже отсутствия кадра,
/// потому что выглядит приёмкой.
///
/// Здесь отрисовщик — **сам UIKit на симуляторе**, а не `ImageRenderer`:
/// `app.screenshot()` снимает то, что нарисовало живое приложение.
/// `PhotosPicker` при этом не нужен вовсе — байты кладёт
/// `-ФонФикстура` (`ФонФикстураСтенда`), минуя выбор фотографии.
///
/// # Чем доказано, что кадр настоящий, а не заглушка
///
/// Признак заглушки — знак запрета на жёлтом и НИ ОДНОГО элемента
/// в дереве. Поэтому у каждого кадра здесь стоит `XCTAssert`
/// на предмет, который на заглушке существовать не может:
/// `navigationBars["Фон приложения"]`, вкладки, кнопки отметок.
/// Зелёное утверждение о дереве и кадр снимаются **в одном заходе**,
/// и первое означает, что второе не заглушка.
///
/// > Это не замена взгляду. Всякий кадр здесь открыт и просмотрен
/// > глазами — у заглушки это единственный честный различитель,
/// > а утверждение про дерево лишь делает её невозможной молча.
///
/// # Фикстура вертикальная и с приметами
///
/// ```
/// 600 × 800      портрет 3 : 4. У `scaledToFill` вертикальный снимок
///                ПЕРЕРАСТАЕТ окно: 600 × 800 в окне 60 × 50 → 60 × 80
/// четыре края    красный верх · синий низ · зелёный слева · жёлтый
///                справа — видно, КАКОЙ край срезала рамка
/// цифра 1…5      в режиме «вперемешку» вся суть в том, что фото разные
/// ```
///
/// > **Однотонная фикстура прежних наборов на этот вопрос не отвечает
/// > по устройству:** однотонное фото обрезается в себя самого.
/// > Срежь ему верх, низ, бока, переверни круг в эллипс — кадр
/// > не изменится ни на пиксель.
///
/// # Контроль — в том же заходе, и он второй тест этого класса
///
/// `testБезФикстурыПодложекНет` запускает то же приложение **без**
/// флага. Без него «приметы видны» неотличимо от «отрисовщик рисует
/// хоть что-нибудь», а «фикстура снялась» — от «снятие не работает
/// и фон унаследован от прошлого прогона». Контроль взят в другой
/// канал, чем предмет: предмет смотрит на цвет пикселей, контроль —
/// на опись в хранилище и на отсутствие плиток.
///
/// **Куда пишет.** `build/кадры-фонов/`, путь выведен из `#filePath`.
/// `build/` в `.gitignore`: сохраняемое выносится
/// в `Дизайн/кадры-приёмки/` и коммитится отдельно.
nonisolated final class ФоныИПодложки: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []
    private var ожидалось = 0

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-фонов")
    }

    override func setUp() {
        continueAfterFailure = false
        снято = []
    }

    /// Счёт печатается ВСЕГДА и первой строкой, в том числе после
    /// падения посреди прохода: «снято семь» и «упал на третьем»
    /// выглядят в логе одинаково — строк про кадры просто меньше,
    /// а отсутствия никто не ищет.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) из \(ожидалось) · \(name) · \(снято.joined(separator: ", "))")
        вынестиКадры(из: каталог, набор: "ФоныИПодложки")
        app = nil
    }

    private func поднять(фикстура: Bool) {
        app = XCUIApplication()
        // Снятие просится ЯВНО. Молчаливая уборка на всяком запуске
        // с `-UITesting` лезла в путь сорока чужих тестов — разбор
        // и замер в `ФонФикстураСтенда.применить`.
        app.launchArguments = фикстура
            ? ["-UITesting", "-ФонФикстура"]
            : ["-UITesting", "-ФонФикстураСнять"]
        app.launch()
    }

    // MARK: - Предмет: пять подложек со снимком, имеющим приметы

    /// Пять поверхностей подряд на одном запуске: четыре подложки
    /// и экран, который ими распоряжается.
    ///
    /// Одним тестом, а не пятью, нарочно: фикстура кладётся при старте
    /// процесса, и каждый новый запуск перемешивал бы затравку режима
    /// «вперемешку» заново. Пять кадров одного запуска сравнимы между
    /// собой, пять кадров пяти запусков — нет.
    func testПодложкиСоСнимкомВмещаютЕго() {
        ожидалось = 7
        поднять(фикстура: true)


        // 01 · «Сегодня» — `CinemaBackdrop(экран: .today)`, высота 640.
        //
        // **ЭТИ КАДРЫ ПОЙМАЛИ ДЕФЕКТ РАСКЛАДКИ** (замер 26.10.2026).
        // Фото перерастало подложку и уводило содержимое влево:
        // «Сегодня» обрезалось в «егодня», кнопка «Просится»
        // начиналась за левым краем. Причина — `scaledToFill`
        // сообщает наружу размер переросшего снимка, а `.clipped()`
        // режет только рисование. Починено в `CinemaBackdrop`.
        //
        // Кадры до починки читать как приёмку геометрии нельзя;
        // снятые после — можно, и они единственные, на которых
        // вопрос «помещается ли» вообще задан.
        //
        // > **Набор сделал ровно то, что обещает его голова** —
        // > «помещается ли картинка», — и ответ был «нет». Два дня
        // > кадры лежали снятыми и просмотренными, а сдвиг читался
        // > как особенность служебного снимка: приметы объясняют
        // > собой всё, что на кадре не так.
        //
        // Число 640 тест не проверяет (оно стоит только здесь и в имени
        // кадра), поэтому ложного зелёного нет. Но имя файла — это
        // утверждение о геометрии, и до починки сверять по нему высоту
        // было нельзя.
        let вкладки = app.tabBars.buttons
        XCTAssertTrue(вкладки.firstMatch.waitForExistence(timeout: 90),
                      "приложение не поднялось: вкладок в дереве нет")
        кадр("01-сегодня-подложка-640")

        // 02 · вкладка собаки — `ФотоШапка`, высота `backdropTab` 420.
        let собака = вкладки.element(boundBy: 1)
        if собака.waitForExistence(timeout: 10), собака.isHittable {
            собака.tap()
            кадр("02-вкладка-собаки-подложка-420")
        } else {
            XCTFail("второй вкладки нет — до подложки `.dog` не дойти")
        }

        // 03 · «История» — `КиноЭкран(экран: .history)`.
        let история = вкладки["История"]
        if история.waitForExistence(timeout: 10), история.isHittable {
            история.tap()
            кадр("03-история-подложка-420")
        } else {
            XCTFail("вкладки «История» нет")
        }

        // 04 · «Здоровье» — та же высота, другой ключ. Вкладку держит
        // право `.seeMedical`: нет её — это про роль, а не про подложку.
        let здоровье = вкладки["Здоровье"]
        if здоровье.waitForExistence(timeout: 10), здоровье.isHittable {
            здоровье.tap()
            кадр("04-здоровье-подложка-420")
        }

        // 05 · экран «Фон приложения» — ГЛАВНЫЙ ПРЕДМЕТ.
        // Тут разом: окна предпросмотра (60 × 50, вертикальный снимок
        // их перерастает), полоска своих плиток и подложка самого
        // экрана (`.sub("background")`, высота 360).
        вкладки.element(boundBy: 0).tap()
        XCTAssertTrue(открытьНастройки(в: app),
                      "в настройки не войти ни прямой кнопкой, ни через «…»")
        let строка = найти("Фон приложения", в: app)
        XCTAssertTrue(строка.waitForExistence(timeout: 10),
                      "в настройках нет строки «Фон приложения» — механизм без входа")
        строка.tap()
        // Утверждение, невозможное на заглушке SwiftUI: у неё в дереве
        // нет ничего, кроме корня, и `navigationBars` пуст.
        XCTAssertTrue(app.navigationBars["Фон приложения"].waitForExistence(timeout: 10),
                      "строка есть, а экран за ней не открылся")
        кадр("05-фон-приложения-режим-одно-фото")

        // 06 · «что получится» — ОКНА ПРЕДПРОСМОТРА, 60 × 50.
        //
        // Самое узкое место всего предмета, и починка `807c196` лежит
        // ровно здесь. Вертикальный снимок ПЕРЕРАСТАЕТ такое окно:
        // 600 × 800 при ширине 60 даёт высоту 80 против полусотни.
        // До 25.10 стеклянная полоса стояла `.overlay`-ем на самом
        // `Image`, мерила себя по НЁМ и уезжала под обрез целиком —
        // оставалась ≈ 1 строка пикселей из 3840. Горизонтальный
        // снимок дефекта не показывал вовсе.
        for _ in 0..<6 where !app.staticTexts["что получится"].exists {
            app.swipeUp(velocity: .slow)
        }
        кадр("06-окна-предпросмотра-60x50")

        // 07 · тот же экран в режиме «вперемешку»: у каждого окна
        // обязана оказаться СВОЯ цифра. Иначе «вперемешку» — слово
        // без исхода.
        //
        // **Крутить вверх, а не вниз.** Прогон 19:04 упал здесь
        // «режима „5 фото вперемешку“ на экране нет» — при живой
        // строке: мы стояли внизу, у предпросмотра, а строки режимов
        // остались ВЫШЕ. Помощник `найти` крутит `swipeUp`, то есть
        // уводил от предмета дальше с каждой попыткой. Отказ пришёл
        // в форме «такого на экране нет».
        for _ in 0..<6 where !app.staticTexts["как выбирается фото"].exists {
            app.swipeDown(velocity: .slow)
        }
        let вперемешку = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", "5 фото вперемешку")
        ).firstMatch
        if вперемешку.waitForExistence(timeout: 10) {
            вперемешку.tap()
            for _ in 0..<6 where !app.staticTexts["что получится"].exists {
                app.swipeUp(velocity: .slow)
            }
            кадр("07-окна-предпросмотра-вперемешку")
        } else {
            XCTFail("режима «5 фото вперемешку» на экране нет")
        }
    }

    // MARK: - Режим выгула отдельным запуском

    /// `WalkMode.фон` — пятая подложка, и до починки 25.10 она была
    /// единственной, которая выбор человека не исполняла.
    ///
    /// **Отдельным запуском, а не хвостом предыдущего теста, и это
    /// замер, а не вкус.** Первая редакция шла сюда прямо с экрана
    /// «Фон приложения», и прогон упал на `вкладки.element(boundBy: 0)`:
    ///
    /// ```
    /// Failed to tap Button (Element at index 0): No matches found
    /// for Descendants matching type TabBar
    /// ```
    ///
    /// Кнопка «назад» уводит на «Настройки», а они сами лежат поверх
    /// вкладок — панели вкладок в дереве нет, и «не нашёл» читалось бы
    /// как «вкладок не существует». Свой запуск заодно возвращает режим
    /// `single`: фикстура кладётся при старте процесса, а предыдущий
    /// тест оставил в хранилище `random`, выбранный тапом.
    func testРежимВыгулаПоказываетВыбранноеФото() {
        ожидалось = 1
        поднять(фикстура: true)

        XCTAssertTrue(app.tabBars.buttons.firstMatch.waitForExistence(timeout: 90),
                      "приложение не поднялось")
        // `isHittable` у «Гулять» НЕ спрашиваем. Прогон 19:05 ушёл мимо
        // обеих веток и упал на якоре: кнопка существовала, а хиттабла
        // в тот миг не была. `isHittable` отвечает про видимость,
        // и ответ «нет» прочитался бы как «кнопки нет».
        // Живой образец, который ходит этой дорогой годами, —
        // `DynamicTypeScreenshotTests.testXL13РежимВыгула` — его
        // и повторяем дословно.
        let гулять = app.buttons["Гулять"].firstMatch
        let открыть = app.buttons["Открыть"].firstMatch
        if гулять.waitForExistence(timeout: 15) {
            гулять.tap()
            let пошли = app.buttons["Пошли"].firstMatch
            if пошли.waitForExistence(timeout: 8) { пошли.tap() }
        } else if открыть.waitForExistence(timeout: 3) {
            открыть.tap()
        } else {
            кадр("09-ОТКАЗ-дороги-в-выгул")
            XCTFail("на «Сегодня» нет ни «Гулять», ни «Открыть»")
            return
        }
        // Якорь — ИДЕНТИФИКАТОР: пока прогулка идёт, «Пописал» лежит
        // в дереве дважды, и `firstMatch` по подписи берёт чужую,
        // из низа «Сегодня» под шторкой.
        // Якорь — «Пауза», а НЕ `отметка-urine`.
        //
        // **Замер 19:10: по идентификатору отметки прогон не дождался
        // кнопки за 20 с — на снятом тут же кадре отказа шторка выгула
        // стояла целиком, с «Пописал» во всю ширину.** То есть
        // «кнопки нет» было про мой запрос, а не про экран, и кадр
        // отказа это показал за секунду. Строку
        // `app.buttons["отметка-urine"]` оставляю ниже
        // необязательной справкой: она про дерево доступности,
        // а предмет этого набора — подложка.
        //
        // «Пауза» годится якорем по устройству: она живёт только
        // в идущей прогулке, и совпасть ей не с чем.
        let пауза = app.buttons["Пауза"].firstMatch
        let отметка = app.buttons["отметка-urine"].firstMatch
        let вошли = пауза.waitForExistence(timeout: 20) || отметка.exists
        if вошли {
            кадр("09-режим-выгула-подложка")
            print("ЯКОРЬ: «Пауза» \(пауза.exists) · «отметка-urine» \(отметка.exists)")
        } else {
            // Кадр снимается И при отказе: «не дошли» и «дошли, а
            // подложки нет» в логе неотличимы, а на картинке видно сразу.
            кадр("09-ОТКАЗ-где-мы-оказались")
            XCTFail("""
                в режим выгула не войти: ни «Пауза», ни «отметка-urine». \
                Это про дорогу, а не про подложку. \
                Где оказались — на кадре «09-ОТКАЗ-где-мы-оказались».
                """)
        }
    }

    // MARK: - Контроль того же захода

    /// Без флага фикстуры не должно быть ни плиток, ни приметных краёв.
    ///
    /// **Контроль в другом канале, чем предмет.** Предмет читает
    /// пиксели кадра; этот читает ДЕРЕВО — есть ли на экране «Фон
    /// приложения» строка «Убрать мои фото». Она показывается только
    /// при `сколькоМоих > 0` (`BackgroundScreen.снимки`), то есть
    /// отвечает прямо про опись в хранилище.
    ///
    /// Чего он стоит. Без него два разных исхода выглядят одинаково:
    ///
    /// ```
    /// приметы на кадре есть   → фикстура легла          ← хотим
    /// приметы на кадре есть   → легла В ПРОШЛОМ прогоне, снятие
    ///                           не работает, и кадр не про этот запуск
    /// ```
    ///
    /// Второе и есть то, от чего заведено снятие в `ФонФикстураСтенда`:
    /// контейнер группы переживает запуск, и унаследованный фон
    /// от заданного на кадре не отличить ничем.
    func testБезФикстурыПодложекНет() {
        ожидалось = 1
        поднять(фикстура: false)

        // Кадр ДО утверждения, и это починка формулировки, а не
        // перестраховка. Замер 19:19: здесь стояло
        // «приложение не поднялось» — а у приложения был живой pid,
        // и мерилось вовсе не поднятие, а наличие ПАНЕЛИ ВКЛАДОК.
        // Отчёт инструмента о собственном запросе был выдан за факт
        // о приложении; что на экране, не знал никто.
        let панель = app.tabBars.buttons.firstMatch.waitForExistence(timeout: 90)
        if !панель { кадр("08-ОТКАЗ-ни-одной-вкладки") }
        XCTAssertTrue(панель, """
            панели вкладок нет за 90 с. Это НЕ «приложение не поднялось»: \
            у него живой процесс. Что на экране — на кадре \
            «08-ОТКАЗ-ни-одной-вкладки».
            """)
        XCTAssertTrue(открытьНастройки(в: app), "в настройки не войти")
        let строка = найти("Фон приложения", в: app)
        XCTAssertTrue(строка.waitForExistence(timeout: 10), "строки «Фон приложения» нет")
        строка.tap()
        XCTAssertTrue(app.navigationBars["Фон приложения"].waitForExistence(timeout: 10),
                      "экран не открылся")
        кадр("08-контроль-без-фикстуры")

        let убрать = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", "Убрать мои фото")
        ).firstMatch
        XCTAssertFalse(убрать.waitForExistence(timeout: 3), """
            «Убрать мои фото» есть при запуске БЕЗ `-ФонФикстура`. \
            Значит снимок остался от прошлого прогона — снятие \
            в `ФонФикстураСтенда` не работает, и всякий кадр предмета \
            рассказывает не про свой запуск.
            """)
    }

    private func кадр(_ имя: String) {
        let снимок = app.screenshot()
        let вложение = XCTAttachment(screenshot: снимок)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            try снимок.pngRepresentation.write(to: каталог.appendingPathComponent(имя + ".png"))
            снято.append(имя)
            print("КАДР: \(каталог.appendingPathComponent(имя + ".png").path)")
        } catch {
            print("КАДР НЕ ЛЁГ НА ДИСК: \(имя) · \(error.localizedDescription)")
        }
    }
}
