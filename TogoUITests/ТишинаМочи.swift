import XCTest

/// Кадр ступени, которую до 05.10.2026 не видел глазами никто.
///
/// **Что на ней стоит.** 28.09 из вердикта убрали «Не писал 434 ч. Это
/// дольше, чем он когда-либо терпел» — медицинское утверждение о собаке,
/// выведенное из **отсутствия** записи. Вместо него приложение говорит,
/// с какого числа отметок нет, и вслух называет, чего не знает.
/// Проверено это было только арифметикой: «верно ли посчитано» знал
/// сторож, «верно ли сказано» не знал никто.
///
/// **Почему кадра не было, и почему причина оказалась не той, что
/// записана.** В журнале стояло, что сценария «мочу не отмечали» нет,
/// а `silence` — «про выходы». Замер 05.10 показал другое: `silence`
/// кладёт выход позавчера с `outcome = .both`, а `.both` считается
/// мочой (`Diary.urineEvents`), то есть `signals.urineSilence` там
/// срабатывает. Не доезжал **вердикт**: событий два, `daysOfData` даёт
/// 3, `minimumDaysOfData` равен 4, и `guard` про нехватку данных стоит
/// выше тишины. Экран честно отвечал «записей всего за 3 дня», и кадр
/// с него сошёл бы за кадр тишины.
///
/// > Вывод был верный, причина — нет. Верный вывод на неверной причине
/// > ломается молча: починивший причину решил бы, что снял границу.
///
/// Лечится входом: `SeedData.Scenario.urineSilence` — четыре дня
/// дневника и восемнадцать дней молчания.
///
/// **Границы этого файла:**
/// 1. Прогон идёт на русском, и надписи здесь русские литералы, как
///    в `TodayFlowUITests`. Французский и украинский он не проверяет
///    ВОВСЕ. *Снимет границу:* перевод навигации и запретных строк
///    через `Подписи`, который берёт ожидаемое из того же каталога,
///    что собирается в бандл, — как сделано в `ВосстановлениеПокупок`.
///    Не сделано здесь потому, что каталог 05.10 правит другая сессия,
///    и сверяться с движущимся файлом значит мерить движущуюся мишень.
/// 2. Файл смотрит на **лист вердикта**. Две строки виджета —
///    `sinceText` и `inlineText` — он не видит: виджет рисует
///    SpringBoard, `app.screenshot()` до него не достаёт. Их сторожит
///    `TogoTests/WidgetSilenceTextTests.swift`, и сторожит поведением,
///    а не кадром. *Снимет границу:* превью `TodayWidgetView`
///    с подставленным снимком в галерее отладки.
nonisolated final class ТишинаМочи: XCTestCase {
    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting", "-Сценарий", "urineSilence"]
        app.launch()
        XCTAssertTrue(app.staticTexts["Стич"].waitForExistence(timeout: 10),
                      "приложение не поднялось — дальше смотреть не на что")
        app.buttons["Просится"].firstMatch.tap()
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Первым — что сценарий довёл приложение именно до тишины.
    ///
    /// Без этой проверки остальные были бы зелёными, ничего не проверив:
    /// на экране «записей всего за 3 дня» нет ни «терпел», ни «Не писал»,
    /// и все запреты ниже выполняются сами собой. Ровно так сценарий
    /// `silence` пять дней выглядел сценарием про мочу, не будучи им.
    func test01СценарийДовёлДоСтупениТишины() {
        // `CONTAINS`, а не `BEGINSWITH`: 05.10 дату увели с конца фразы
        // в начало, и сторож, привязанный к началу строки, покраснел бы
        // на самой починке. Проверяем предмет, а не порядок слов.
        let тишина = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "отметок мочи нет")
        ).firstMatch
        XCTAssertTrue(тишина.waitForExistence(timeout: 5),
                      "на листе вердикта нет строки про отсутствие отметок мочи — "
                      + "сценарий urineSilence до ступени тишины не довёл, "
                      + "и всё, что скажут остальные проверки этого файла, "
                      + "будет про другой экран")
    }

    /// Находка кадра 05.10: `Fmt.shortDay` приносит свою точку
    /// (8 месяцев из 12 по-русски, 12 из 12 по-украински — замер
    /// сессии-переводчицы), а шаблон ставил вторую.
    ///
    /// Проверяется на экране, а не в строке: ровно здесь это и увидели
    /// глазами, а счётчик не ловит — ключ есть, перевод есть,
    /// подстановка верна.
    func test04НаЭкранеНетДвухТочекПодряд() {
        let двойная = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "..")
        ).firstMatch
        XCTAssertFalse(двойная.waitForExistence(timeout: 2),
                       "на листе вердикта две точки подряд: сокращение месяца "
                       + "принесло свою, а шаблон поставил вторую. "
                       + "Чинится местом даты в предложении, не пунктуацией: "
                       + "сокращение кончается точкой не во всех языках")
    }

    /// От обратного: не «есть верная строка», а «утверждения о собаке
    /// на экране нет ни в каком виде».
    ///
    /// Требование «есть верная строка» выполнялось бы и тогда, когда
    /// рядом осталась вторая, прежняя.
    func test02НаЭкранеНетУтвержденияОСобаке() {
        let запретное = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "терпел")
        ).firstMatch
        XCTAssertFalse(запретное.waitForExistence(timeout: 2),
                       "на дневнике, который забросили, приложение снова говорит "
                       + "«дольше, чем он когда-либо терпел» — это утверждение "
                       + "о собаке, выведенное из отсутствия записи")

        let числом = app.staticTexts.containing(
            NSPredicate(format: "label BEGINSWITH %@", "Не писал")
        ).firstMatch
        XCTAssertFalse(числом.waitForExistence(timeout: 2),
                       "вердикт снова открывается числом «Не писал …» — а число "
                       + "за сутками молчания отвечает не на тот вопрос: "
                       + "приложение знает только, что никто ничего не отмечал")
    }

    /// Кадр. Приёмка правки, меняющей то, что человек читает, — кадр,
    /// и зелёный набор её не заменяет.
    func test03Кадр() {
        XCTAssertTrue(app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", "не знает")
        ).firstMatch.waitForExistence(timeout: 5),
                      "приложение не говорит вслух, чего не знает: без этой "
                      + "половины «отметок нет с 17 сент.» читается как упрёк "
                      + "человеку, а не как признание незнания")
        снять("тишина-мочи-вердикт")
    }
}
