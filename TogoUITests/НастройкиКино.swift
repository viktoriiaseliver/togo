import XCTest

/// Кадры настроек и их подэкранов под темой «Кино» плюс доказательство,
/// что вход в настройки из шапки-меню «…» живой.
///
/// **Эталонного кадра у этих экранов НЕТ НИ ОДНОГО.** `15.png`
/// («Настройки · фон») из пакета хендоффа негоден: вместо экрана
/// во весь кадр нарисована лавандовая пилюля, читаются только часы
/// и обрезки таб-бара — дефект выгрузки
/// (`Дизайн/эталонные-кадры/ios28-кино-22.10/ПОДПИСИ.md`). Сверять
/// снятое здесь не с чем, и «сверено с дизайном» про эти кадры писать
/// нельзя. Соседние ГОДНЫЕ кадры подэкранов — `13.png` (Питание)
/// и `14.png` (Анализы Т4) — показывают язык темы, но это ЧУЖИЕ экраны:
/// основание косвенное.
///
/// **Чем этот набор отличается от `ФонПриложения`.** Тот проверяет
/// механику выбора (режим меняется, предпросмотр говорит другое,
/// настройки называют выбранное). Этот проверяет **вид**: заголовок,
/// шапку, полотно. Тест проверяет, верно ли посчитано; кадр — верно ли
/// сказано.
///
/// **Чего кадры показать не могут.** Фотографию под шапкой: положить
/// снимок можно только через `PhotosPicker`, а он работает в отдельном
/// процессе, куда стенд не достаёт. Значит на всех кадрах здесь —
/// состояние «своих фото нет», то есть ровно то, что видит человек
/// на первом запуске: чёрное полотно темы «Кино» без снимка. Вторая
/// половина — «как выглядит фон со своим фото» — кадром не проверяется
/// по устройству, и лечится это не старанием.
///
/// **Куда пишет.** `build/кадры-настроек/`, путь выведен из `#filePath`.
/// `build/` в `.gitignore`: то, что нужно сохранить, выносится
/// в `Дизайн/кадры-приёмки/` и коммитится отдельно.
nonisolated final class НастройкиКино: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []
    private static let всегоКадров = 6

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-настроек")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Счёт печатается ВСЕГДА и в том числе после падения: «снято пять»
    /// и «упал на втором» выглядят в логе одинаково — строк про кадры
    /// просто меньше, а их отсутствия никто не ищет.
    override func tearDown() {
        print("КАДРОВ СНЯТО: \(снято.count) из \(Self.всегоКадров) · \(name) · \(снято.joined(separator: ", "))")
    }

    func testНастройкиИПодэкраныПодКино() throws {
        открытьНастройки()
        кадр("01-настройки")

        подэкран("Фон приложения", бар: "Фон приложения", кадр: "02-фон-приложения")
        подэкран("Язык", бар: "Язык", кадр: "03-язык")
        подэкран("Как это работает", бар: "Как это работает", кадр: "04-как-это-работает")
        // Было «Политика конфиденциальности» прямо из настроек. С 24.10.2026
        // четыре правовые строки собраны в один экран «Правила»
        // (эталон `v10-прототип-24.10/screenshots/47-screens.jpg`), и путь
        // к политике стал на шаг длиннее. Кадр снимается с «Правил»:
        // это и есть новый экран, которого раньше не было, а дорогу
        // до самой политики целиком проходит
        // `TodayFlowUITests.testНастройкиСодержатОбязательныеРазделы`.
        подэкран("Правила", бар: "Правила", кадр: "05-правила")
        переносСCSV()
    }

    /// Кадр «Переноса» снимается НЕ через `подэкран`, и причина
    /// не в удобстве: предмет кадра лежит **ниже сгиба**.
    ///
    /// CSV — третья карточка экрана (эталон
    /// `v10-прототип-24.10/screenshots/45-screens.jpg`, строка
    /// «CSV · 14 столбцов»), а `подэкран` снимает сразу после открытия.
    /// Кадр верхней части экрана доказал бы, что экран открылся,
    /// и ничего — про строку, ради которой он снят.
    ///
    /// Поэтому строка **сперва ищется**, и только потом щёлкает затвор:
    /// у нас записано, что «кадр существует, когда он снят и на него
    /// посмотрели», а кадр без предмета — это кадр, на который смотреть
    /// нечего.
    private func переносСCSV() {
        // **Сперва наверх, и это оплачено прогоном.** Первая редакция
        // искала строку только прокруткой ВНИЗ — и упала с «в настройках
        // нет строки «Перенос и восстановление»» при живой строке
        // на экране (замер 24.10.2026, `rc=65`, «КАДРОВ СНЯТО: 5 из 6»).
        //
        // Причина в порядке разделов: «данные» стоят ВЫШЕ «правового»,
        // а мы приходим сюда с «Правил», то есть снизу. Прокрутка вниз
        // от нижней точки не двигает ничего, и отказ читается как
        // «входа нет» — тот самый отчёт инструмента о себе, выданный
        // за факт об экране.
        for _ in 0..<12 { app.swipeDown() }

        let строка = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", "Перенос и восстановление")
        ).firstMatch
        for _ in 0..<10 where !строка.exists { app.swipeUp() }
        XCTAssertTrue(строка.waitForExistence(timeout: 10),
                      "в настройках нет строки «Перенос и восстановление»")
        строка.tap()

        // Ярлык шапки («Копия») и ярлык строки («Перенос
        // и восстановление») — разные нарочно, и это не опечатка:
        // `navigationTitle` у `BackupScreen` короткий.
        //
        // ШАПКА ПЕРЕИМЕНОВАНА 25.10.2026 словом дизайна (`ОТВЕТЫ-круг-5`,
        // пункт 8: «Экран про резервную копию, перенос — его следствие»).
        // Строка настроек НЕ тронута, и это названо, а не забыто:
        // дизайн назвал ЭКРАН, а не строку, и за строкой стоят два
        // UI-теста (этот и `ScreenshotTests.test10Перенос`). Расхождение
        // «строка Перенос → экран Копия» открыто и ждёт слова.
        XCTAssertTrue(app.navigationBars["Копия"].waitForExistence(timeout: 10),
                      "строка нажата, а экран «Копия» не открылся")

        let csv = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", "CSV")
        ).firstMatch
        for _ in 0..<8 where !csv.exists { app.swipeUp() }
        XCTAssertTrue(csv.waitForExistence(timeout: 5), """
            на экране «Копия» нет строки CSV. Надстрочник экрана \
            обещает «iCloud · JSON · CSV» три слова — дорог должно быть три.
            """)
        кадр("06-перенос-csv")

        app.navigationBars["Копия"].buttons.firstMatch.tap()
        XCTAssertTrue(app.navigationBars["Настройки"].waitForExistence(timeout: 10),
                      "с экрана «Копия» не вышло вернуться в настройки")
    }

    // MARK: Дорога

    /// Вход в настройки — только через шапку-меню «…».
    ///
    /// **Шестерёнки в шапке больше нет** (решение Виктории 22.10.2026,
    /// коммит `f4b5db9`): в шапке одна кнопка «…», и настройки — её
    /// первый пункт. До 23.10.2026 этот путь в стенде не проверял никто:
    /// `ФонПриложения` искал `app.buttons["Настройки"]` сразу после
    /// запуска, то есть пункт закрытого меню, — тест падал на первой
    /// строке и печатал «КАДРОВ СНЯТО: 0 из 3».
    ///
    /// > Падение читалось как «входа в настройки нет». Вход был;
    /// > не было у теста знания, что шапка переехала.
    private func открытьНастройки() {
        let меню = app.buttons["шапка-меню"].firstMatch
        XCTAssertTrue(меню.waitForExistence(timeout: 20),
                      "приложение не поднялось или шапки-меню «…» нет на главном экране")
        меню.tap()

        let пункт = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(пункт.waitForExistence(timeout: 10),
                      "меню «…» открылось, а пункта «Настройки» в нём нет")
        пункт.tap()

        XCTAssertTrue(app.navigationBars["Настройки"].waitForExistence(timeout: 10),
                      "пункт нажат, а экран настроек не открылся")
    }

    /// Открыть подэкран по названию строки, снять кадр и вернуться.
    ///
    /// Строка ищется предикатом, а не точным ярлыком: у `TGListRow`
    /// в метку озвучки склеиваются заголовок и значение, и
    /// `buttons["Фон приложения"]` не совпал бы при живой строке
    /// на экране — «не нашёл» прочиталось бы как «входа нет».
    private func подэкран(_ строка: String, бар: String, кадр имя: String) {
        let цель = app.descendants(matching: .any).matching(
            NSPredicate(format: "label BEGINSWITH %@", строка)
        ).firstMatch
        for _ in 0..<10 where !цель.exists { app.swipeUp() }
        XCTAssertTrue(цель.waitForExistence(timeout: 10),
                      "в настройках нет строки «\(строка)» — механизм без входа")
        цель.tap()

        XCTAssertTrue(app.navigationBars[бар].waitForExistence(timeout: 10),
                      "строка «\(строка)» есть, а экран за ней не открылся")
        кадр(имя)

        app.navigationBars[бар].buttons.firstMatch.tap()
        XCTAssertTrue(app.navigationBars["Настройки"].waitForExistence(timeout: 10),
                      "с экрана «\(бар)» не вышло вернуться в настройки")
    }

    private func кадр(_ имя: String) {
        let снимок = app.screenshot()
        let вложение = XCTAttachment(screenshot: снимок)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            try снимок.pngRepresentation.write(to: каталог.appendingPathComponent(имя + ".png"))
            снято.append(имя)
            print("КАДР: \(каталог.appendingPathComponent(имя + ".png").path)")
        } catch {
            // Не падаем на записи файла: кадр уже лежит вложением
            // в `.xcresult`, и терять из-за этого проверку дороги глупо.
            print("КАДР НЕ ЛЁГ НА ДИСК: \(имя) · \(error.localizedDescription)")
        }
    }
}
