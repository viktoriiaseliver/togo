import XCTest

/// Приёмка медкнижки кадром, 07.10.2026.
///
/// **Зачем кадр, когда обмен и архив зелёные.** Они отвечают, верно ли
/// посчитано и доехало ли: круги по значениям закрыли предел
/// обнаружения, повод визита «онлайн», статус диагноза, вес на дату
/// рецепта. Чего человек **прочитает**, не проверял никто — экрана
/// медкнижки не существовало вовсе, и Виктория, поставив сборку 273,
/// написала «часть функций не работает».
///
/// > **Отличить «сломано» от «нет поверхности» человек не может
/// > по устройству.**
///
/// # Что здесь измеряется, а не осматривается
///
/// Три утверждения, каждое из которых **ломается ровно тем дефектом,
/// против которого стоит**:
///
/// 1. **Предел обнаружения остался пределом.** На экране обязано быть
///    `<0,1`, и обязано НЕ быть голого `0,1`. Это не косметика: от этого
///    числа считают дозу, и подмена отдала бы тихо неверное значение
///    вместо видимо неизвестного;
/// 2. **«Не записано, через сколько часов» показано словом.** Третий
///    исход `LabNorm` — это ответ, а не пустота. Исчезнув, он стал бы
///    молчанием, и человек прочитал бы соседний вердикт как полный;
/// 3. **Отметка лаборатории стоит только рядом с нашим вердиктом.**
///    Проверяется счётом: подписей «лаборатория:» не больше, чем
///    «по нашей норме:». Одна галочка без источника — худший исход,
///    и он невидим на взгляд.
///
/// # Чего этот кадр НЕ доказывает, и это печатается в падении
///
/// Что загрузка архива даст такую же картину (здесь срез собран
/// значениями); что так будет при крупном шрифте и по-французски;
/// что это читается в кабинете поверх цифр и дельты сводки.
nonisolated final class МедкнижкаВГалерееUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testМедкнижкаСнимаетсяИНеТеряетПредел() throws {
        let настройки = app.buttons[подписи("Настройки")].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 20), "не дождались главного экрана")
        настройки.tap()

        let медкнижка = найти("Медкнижка", в: app)
        XCTAssertTrue(медкнижка.waitForExistence(timeout: 10),
                      "нет входа «Медкнижка» — галерея под `#if DEBUG`")
        медкнижка.tap()

        // **Контроль: галерея ПОСТРОИЛАСЬ.** Без него все проверки ниже
        // выполняются на пустом экране, и набор зелен, ничего
        // не проверив. Срез собирается в памяти в `.task`, поэтому
        // ждём появления первого раздела, а не мгновенного состояния.
        let заголовок = app.staticTexts["АНАЛИЗЫ"].firstMatch
        XCTAssertTrue(заголовок.waitForExistence(timeout: 15), """
            раздела «Анализы» на экране нет. Это не «с медкнижкой всё \
            хорошо» — это нечем смотреть: либо срез не собрался, либо \
            разделы не построились.
            """)

        // Собираем текст всего экрана по мере прокрутки: разделы
        // не влезают в один кадр, а `exists` истинно и для того,
        // что за кадром, — значит одного прохода мало для КАДРОВ,
        // но достаточно для текста.
        var кадров = 0
        for шаг in 0..<6 {
            if шаг > 0 { app.swipeUp() }
            кадров += 1
            let вложение = XCTAttachment(screenshot: app.screenshot())
            вложение.name = "медкнижка-\(шаг)"
            вложение.lifetime = .keepAlways
            add(вложение)
        }
        XCTAssertEqual(кадров, 6, "кадры не снялись — смотреть будет нечего")

        // Замыканием, а не ключевым путём: `XCUIElement.label`
        // изолирован главным актором, и `\.label` даёт
        // `cannot form key path to main actor-isolated property`.
        // Ошибка компилятора — цена, которую просят вперёд.
        let строки = app.staticTexts.allElementsBoundByIndex.map { $0.label }
        XCTAssertGreaterThan(строки.count, 20, """
            строк на экране \(строки.count) — дерево доступности почти \
            пусто, и проверки ниже зелены на пустом множестве.
            """)

        // 1. Предел обнаружения остался пределом.
        XCTAssertTrue(строки.contains { $0.contains("<0,1") || $0.contains("<0.1") }, """
            предела «<0,1» на экране нет. Либо он не показан вовсе, \
            либо показан числом — а `<0,1` это НЕ 0,1: от этого числа \
            считают дозу, и подмена отдаёт тихо неверное значение \
            вместо видимо неизвестного.

            Все строки экрана: \(строки.joined(separator: " | "))
            """)

        // И обратная половина: голого `0,1` рядом быть не должно.
        // Без неё проверка выше проходит и при показе ОБОИХ.
        XCTAssertFalse(строки.contains { $0 == "0,1 нг/дл" || $0 == "0.1 нг/дл" }, """
            на экране есть голое «0,1 нг/дл» — предел обнаружения \
            превратился в число.
            """)

        // 2. Третий исход показан СЛОВОМ, а не пустотой.
        XCTAssertTrue(строки.contains { $0.contains("через сколько часов") }, """
            «не записано, через сколько часов после дозы» на экране \
            нет. Это ОТВЕТ, а не пустота: подставить «вероятно, 4–6» \
            значило бы изобрести норму из удобства, а промолчать — \
            дать прочитать соседний вердикт как полный.
            """)

        // 3. Отметка лаборатории — только рядом с нашим вердиктом.
        //
        // **Счётом, а не взглядом.** Глазами это не ловится: одна
        // галочка без подписи выглядит аккуратнее двух подписанных,
        // и именно поэтому так и сделали бы.
        let нашихВердиктов = строки.filter { $0.contains("по нашей норме") }.count
        let отметокЛаборатории = строки.filter { $0.contains("лаборатория:") }.count
        XCTAssertGreaterThan(нашихВердиктов, 0, """
            ни одного «по нашей норме» — вердикт не показан вовсе, \
            и тогда отметка лаборатории осталась бы единственным \
            показанием, без источника.
            """)
        XCTAssertLessThanOrEqual(отметокЛаборатории, нашихВердиктов, """
            отметок лаборатории (\(отметокЛаборатории)) больше, чем \
            наших вердиктов (\(нашихВердиктов)). Значит где-то \
            лабораторная галочка стоит ОДНА — и человек прочтёт её \
            как наш ответ.

            Расхождение между нами и лабораторией — находка, а не \
            ошибка: референс Т4 в карте менялся трижды. Спрятать его \
            за одним значком значит соврать молча.
            """)

        // Границы кадра — печатаются, а не хранятся в чьей-то памяти.
        print("""
            ГРАНИЦЫ ЭТОГО КАДРА:
            · срез собран ЗНАЧЕНИЯМИ, а не загрузкой архива — путь
              «файл → восстановление → экран» здесь не проверен;
            · тема, крупный шрифт и французский — не проверены,
              у них свои кадры;
            · как это читается в кабинете поверх цифр и дельты сводки —
              галерея рисует разделы отдельно.
            Замерено: вердиктов \(нашихВердиктов), отметок \
            \(отметокЛаборатории), строк \(строки.count).
            """)
    }
}
