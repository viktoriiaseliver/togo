import XCTest

/// Кадр строк виджета — поверхности, которую до 05.10.2026 не видел
/// глазами никто.
///
/// **Почему её нельзя было снять.** Виджет рисует SpringBoard,
/// `app.screenshot()` до него не достаёт, а `TodayWidgetView` читала
/// семейство из `@Environment(\.widgetFamily)` и строилась только внутри
/// живого виджета. Сторож на строки был — поведенческий, на
/// `SnapshotText`, — и он отвечает «верно ли посчитано», а не «верно ли
/// сказано». Поверхность была **непроверяемой**, а не непроверенной.
///
/// Вылечено входом: вид уехал в `TogoShared`, семейство и час приходят
/// значениями, галерея отладки показывает все три семейства. Тот же ход,
/// что у Timer с карточкой Live Activity.
///
/// **Что этот кадр отвечает и чего не отвечает.** Он показывает, какие
/// строки встанут в каждом семействе и какая из них длиннее. Настоящую
/// ширину слота на локскране он **не воспроизводит** — она принадлежит
/// системе. Поэтому в галерее лестница ширин с подписями: вопрос
/// «что короче» получает ответ, вопрос «влезет ли» остаётся открытым
/// и назван открытым прямо на экране.
///
/// Прогон на языке: `xcodebuild … -testLanguage fr` (и `uk`). Надписи
/// навигации здесь русские литералы: экран отладочный, в каталог его
/// строки не попадают — выгрузка идёт Release-сборкой, `#if DEBUG`
/// в неё не входит.
nonisolated final class ВиджетПодТишиной: XCTestCase {
    private var app: XCUIApplication!
    private let т = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
        XCTAssertTrue(app.staticTexts["Стич"].waitForExistence(timeout: 10),
                      "приложение не поднялось на языке «\(т.язык)»")
        // Через помощника: шестерёнка ушла в меню «…» (22.10), а дети
        // `Menu` не существуют в дереве доступности, пока меню
        // не открыто.
        XCTAssertTrue(открытьНастройки(в: app),
                      "в настройки не попасть ни прямой кнопкой, ни через «…»")
        XCTAssertTrue(app.navigationBars[т("Настройки")].waitForExistence(timeout: 5),
                      "не открылись настройки")

        let ссылка = app.buttons["Виджет"].firstMatch
        var шагов = 0
        while !ссылка.isHittable && шагов < 12 {
            app.swipeUp()
            шагов += 1
        }
        XCTAssertTrue(ссылка.isHittable,
                      "до ссылки «Виджет» не доскроллили за \(шагов) шагов — "
                      + "кадр был бы снят с экрана настроек, а не с галереи")
        ссылка.tap()
    }

    /// Опознаём галерею по её собственной подписи, а не по навбару.
    ///
    /// Первая редакция ждала `app.navigationBars["Виджет"]` и падала
    /// на всех трёх тестах: `TGScreen` рисует заголовок **обычным
    /// текстом** с чертой заголовка, а навигационной панели с таким
    /// именем не создаёт вовсе. То есть тест проверял то, чего
    /// дизайн-система не делает, и падение говорило о тесте,
    /// а не о приложении.
    ///
    /// Подпись семейства — дословная строка (`Text(значение: String)`),
    /// она одинакова на всех языках и принадлежит только этому экрану.
    private var галереяОткрыта: XCUIElement {
        app.staticTexts["accessoryInline · «остров» и локскран"].firstMatch
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "\(т.язык)-\(имя)"
        кадр.lifetime = .keepAlways
        add(кадр)
    }

    /// Первым — что галерея вообще нарисовала строки тишины.
    ///
    /// Без этого остальное было бы зелёным, ничего не проверив: пустой
    /// экран не содержит ни верной строки, ни неверной.
    func test01ГалереяПоказываетСтрокиТишины() {
        XCTAssertTrue(галереяОткрыта.waitForExistence(timeout: 5),
                      "галерея виджета не открылась")
        let тишина = app.staticTexts.containing(
            NSPredicate(format: "label CONTAINS %@", т("нет отметок"))
        ).firstMatch
        XCTAssertTrue(тишина.waitForExistence(timeout: 5),
                      "в галерее нет инлайновой строки тишины «\(т("нет отметок"))» — "
                      + "дальше смотреть не на что")
    }

    /// От обратного: числа из тишины на виджете быть не должно
    /// ни в одном семействе.
    ///
    /// Поведенческий сторож проверяет это на строке; здесь то же самое
    /// проверяется **на экране** — ровно тот зазор, из-за которого
    /// у Togo каталог бывал полон при русском экране.
    func test02НиОдноСемействоНеПечатаетЧисло() {
        XCTAssertTrue(галереяОткрыта.waitForExistence(timeout: 5))
        for запретное in ["434", "437"] {
            let число = app.staticTexts.containing(
                NSPredicate(format: "label CONTAINS %@", запретное)
            ).firstMatch
            XCTAssertFalse(число.waitForExistence(timeout: 1),
                           "на виджете снова число «\(запретное)» из отсутствия записи — "
                           + "приложение знает только, что никто ничего не отмечал")
        }
    }

    /// Кадр. Ради него экран и заводился.
    func test03Кадр() {
        XCTAssertTrue(галереяОткрыта.waitForExistence(timeout: 5))
        снять("01-виджет-тишина")
        // Лестница ширин — ниже первого экрана, и именно она отвечает
        // на вопрос переводчицы, какой из двух вариантов короче.
        app.swipeUp()
        снять("02-инлайн-по-ширинам")
    }
}
