import XCTest

/// Приёмка затемнения режима выгула: **восемь стопов поверх настоящей
/// фотографии**.
///
/// # Чего не было, пока этот набор не завёлся
///
/// `6ebcac9` заменил три стопа на восемь и сам сказал: «Кадра на эту
/// правку нет — стенд у `projects-4e`. Вид меняется, значит приёмка
/// кадром обязательна». Я и есть стенд, и первый заход кадра не дал —
/// но не потому, что прогон упал.
///
/// **Замер 26.10.2026.** Партию сняли существующим
/// `ФоныИПодложки.testРежимВыгулаПоказываетВыбранноеФото`
/// с `-ФонФикстура`: прогон зелёный, «Executed 1 test, 0 failures»,
/// кадр записан — и **фотографии на кадре нет**. Чёрный экран, серый
/// кружок с лапой на месте снимка.
///
/// ```
/// WalkMode.фон:286   if let photo = dog?.photo    ← БАЗА приложения
/// -ФонФикстура       BackgroundBridge.положить    ← APP GROUP
/// ```
///
/// Два разных хранилища. Три прежних флага кормят подложку «Фона
/// приложения»; `WalkMode.фон` читает поле модели, а в него пишут
/// ровно три места, и ни одно не достижимо со стенда:
/// `ВыборФотоСобаки:49` (PhotosPicker — отдельный процесс),
/// `OnboardingFlow:412` (оттуда же через черновик), `Backup:587`
/// (восстановление копии). `SeedData` фотографию не ставил никогда.
///
/// > **Весь слой `TGBackdropScrim` лежит ВНУТРИ `if let photo`.**
/// > Без фото в собаке он не рисуется вовсе — то есть приёмка восьми
/// > стопов была не «не сошлась», а НЕВОЗМОЖНА. И зелёный прогон
/// > с пустым кадром выглядел ровно как снятая партия.
///
/// Имя чужого теста при этом обещает предмет, которого его проверка
/// не касается: он ждёт якоря «Пауза», то есть спрашивает «вошли ли
/// в режим выгула», а зовётся «показывает выбранное фото». Кадр был
/// единственным свидетелем по фото, и на него не смотрели.
///
/// Лечится это входом, а не взглядом: заведён четвёртый флаг
/// `-ФотоСобакиФикстура` (`ФонФикстураСтенда.снимокСобаки`), который
/// кладёт снимок с приметами в `Dog.photo` при засеве.
///
/// # Что смотреть на кадре — слова автора правки
///
/// ```
///  доля высоты фото   три стопа   восемь
///  0,30 … 0,38            22→13 %    15 %   ← ПЛАТО: окно, где
///                                             собаку видно. В трёх
///                                             стопах плато нет вовсе
///  0,76                      52 %   100 %   ← под белой кнопкой
///  0,90                      80 %   100 %     «Пописал» мех НЕ должен
///                                             просвечивать
/// ```
///
/// Снимок фикстуры нарочно **с приметами** (четыре цветных края,
/// перекрестье, цифра): по ровному полю не видно, где слой гасит,
/// а где нет. На однотонном белом этот вопрос не проверяется вовсе —
/// белая фикстура заведена под другую гарантию.
nonisolated final class ЗатемнениеНадФото: XCTestCase {

    private var app: XCUIApplication!
    private var снято: [String] = []

    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-затемнение-фото")
    }

    private var суффикс: String {
        let значение = ProcessInfo.processInfo.environment["KADR_SUFFIX"] ?? ""
        return значение.isEmpty ? "" : "-\(значение)"
    }

    override func setUp() {
        continueAfterFailure = true
        снято = []
    }

    override func tearDown() {
        print("ЗАТЕМНЕНИЕ-КАДРОВ СНЯТО: \(снято.count) · \(name) · \(снято.joined(separator: ", "))")
    }

    private func запустить(сФото: Bool) {
        if app != nil { app.terminate() }
        app = XCUIApplication()
        var аргументы = ["-UITesting"]
        if сФото { аргументы.append("-ФотоСобакиФикстура") }
        app.launchArguments = аргументы
        app.launch()
    }

    private func снять(_ имя: String) {
        let кадр = app.screenshot()
        let вложение = XCTAttachment(screenshot: кадр)
        вложение.name = имя
        вложение.lifetime = .keepAlways
        add(вложение)
        do {
            try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            let путь = каталог.appendingPathComponent("\(имя)\(суффикс).png")
            try кадр.pngRepresentation.write(to: путь)
            снято.append(имя)
            print("ЗАТЕМНЕНИЕ-КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        } catch {
            print("ЗАТЕМНЕНИЕ-КАДР НЕ ЛЁГ: \(имя) · \(error.localizedDescription)")
        }
    }

    /// Дорога в идущую прогулку. Якорь — «Пауза»: она живёт только
    /// в идущей прогулке, и совпасть ей не с чем. `отметка-urine`
    /// якорем НЕ годится — у неё
    /// `.accessibilityElement(children: .ignore)` без
    /// `.isButton`, и в дереве она лежит как `Other`
    /// (замер 25.10, `КегльAX5:139`).
    private func войтиВВыгул(_ метка: String) -> Bool {
        guard app.tabBars.buttons.firstMatch.waitForExistence(timeout: 90) else {
            снять("ОТКАЗ-приложение-не-поднялось-\(метка)")
            XCTFail("приложение не поднялось (\(метка))")
            return false
        }
        // `isHittable` у «Гулять» НЕ спрашиваем: ответ «нет» про
        // видимость прочитался бы как «кнопки нет».
        let гулять = app.buttons["Гулять"].firstMatch
        let открыть = app.buttons["Открыть"].firstMatch
        if гулять.waitForExistence(timeout: 15) {
            гулять.tap()
            let пошли = app.buttons["Пошли"].firstMatch
            if пошли.waitForExistence(timeout: 8) { пошли.tap() }
        } else if открыть.waitForExistence(timeout: 3) {
            открыть.tap()
        } else {
            снять("ОТКАЗ-нет-дороги-в-выгул-\(метка)")
            XCTFail("на «Сегодня» нет ни «Гулять», ни «Открыть» (\(метка))")
            return false
        }
        let пауза = app.buttons["Пауза"].firstMatch
        guard пауза.waitForExistence(timeout: 20) else {
            снять("ОТКАЗ-где-мы-оказались-\(метка)")
            XCTFail("в режим выгула не войти: «Паузы» нет (\(метка)). Это про дорогу, не про затемнение")
            return false
        }
        return true
    }

    /// Предмет: восемь стопов поверх снимка с приметами.
    func test01ВыгулСФотографией() {
        запустить(сФото: true)
        guard войтиВВыгул("с-фото") else { return }
        снять("01-выгул-восемь-стопов-над-фото")
    }

    /// **Контроль в другом канале и в том же заходе.** Тот же экран,
    /// тот же путь, разница ровно в одном флаге.
    ///
    /// Он отвечает на вопрос, который кадр предмета задать не может:
    /// **фотография на кадре — наша фикстура или что-то, оставшееся
    /// от прошлого прогона?** Если без флага на кадре тоже окажется
    /// снимок, значит он приехал не отсюда, и первый кадр не про
    /// `-ФотоСобакиФикстура`.
    ///
    /// И он же — тот самый кадр, которым дефект был НЕВИДИМ: чёрный
    /// экран без слоя затемнения вовсе.
    func test02КонтрольБезФотографии() {
        запустить(сФото: false)
        guard войтиВВыгул("без-фото") else { return }
        снять("02-контроль-выгул-без-фото")
    }
}
