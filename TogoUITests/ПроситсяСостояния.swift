import XCTest

/// «Просится» — семь состояний вердикта, снятые кадром.
///
/// **Вердикт покрыт тестами давно, и они отвечают на другой вопрос.**
/// `VerdictEngineTests` перебирает все случаи и проверяет, **верно ли
/// посчитано**. Что человек прочитает на экране, не проверял никто:
/// чтобы увидеть «отметок мочи нет», надо было восемнадцать дней
/// не вести дневник, а чтобы «мало данных» — завести собаку заново.
///
/// > Тест проверяет, верно ли посчитано. Кадр — верно ли сказано.
///
/// Галерея подставляет **срез фактов**, а не готовый вердикт: считает
/// настоящий `VerdictEngine`. Подставь готовый — и тест доказывал бы,
/// что подпись под картинкой совпадает с картинкой.
nonisolated final class ПроситсяСостоянияUITests: XCTestCase {
    private var app: XCUIApplication!
    private let подписи = Подписи()

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    func testСемьСостоянийВердиктаСнимаютсяКадром() {
        let настройки = app.buttons[подписи("Настройки")].firstMatch
        XCTAssertTrue(настройки.waitForExistence(timeout: 20), "не дождались главного экрана")
        настройки.tap()

        let вход = найти("Просится", в: app)
        XCTAssertTrue(вход.waitForExistence(timeout: 10), """
            в настройках нет входа «Просится» — галерея живёт под \
            `#if DEBUG`, и в Release-сборке этой проверки не существует
            """)
        вход.tap()

        // **Перечислять элементы внутри цикла прокрутки нельзя**, и это
        // не осторожность, а замер: первая редакция падала с `Failed
        // to get matching snapshot: No matches found for Element
        // at index 51` — пока перечисляются индексы, список под рукой
        // уже другой. Падение выглядит как дефект галереи, а дефект
        // в обходе. Я писала ровно этот комментарий в соседнем файле
        // утром и повторила ошибку здесь, зная о ней.
        //
        // Поэтому ищем **предикатом**: он спрашивает про конкретную
        // строку и ничего не перебирает. Семь листов по 560 точек
        // в дерево целиком не помещаются, значит спрашивать надо
        // на каждом шаге прокрутки и копить ответы.
        //
        // Махов фиксированное число, а не «пока не появится»:
        // условие «появилось» выполняется сразу и не крутит ни разу.
        var найдено = Set<String>()
        let искомое = ["Выведи сейчас", "Выведи", "Непонятно",
                       "Скорее внимания", "Выводи по первому знаку",
                       "срочно", "похоже на нужду", "неясно",
                       "отметок мочи нет", "эпизод",
                       "записей всего за", "Через три-четыре дня",
                       "Приложение не знает, писал он или просто никто не отметил",
                       "живой истории здесь нет",
                       // Восьмое состояние — не исход, а расхождение.
                       // Подпись галереи ищем отдельно от текста экрана:
                       // найдись только она — значит состояние есть,
                       // а лист под ней не построился.
                       "РАСХОЖДЕНИЕ"]

        func спросить() {
            for что in искомое where !найдено.contains(что) {
                let предикат = NSPredicate(format: "label CONTAINS[c] %@", подписи(что))
                if app.descendants(matching: .any).matching(предикат).firstMatch.exists {
                    найдено.insert(что)
                }
            }
        }
        // **Кадры снимаются каждые три маха, а не в начале и в конце.**
        // Первая редакция снимала три кадра — верх, «середина» на шаге
        // 10 и хвост, — и два из трёх вышли ПОБАЙТНО одинаковыми:
        // прокрутка упёрлась в низ задолго до десятого шага, а
        // оставшиеся махи были пустой операцией. Прогон при этом был
        // зелёный, вес файлов правдоподобный, имена разные.
        //
        // > Поймали это `sha256` и взгляд, а не прогон. Дубликат кадра
        // > и снятое состояние снаружи неразличимы.
        //
        // Имена без обещаний о содержимом: кадр называется номером
        // шага, а не тем, что я ожидаю на нём увидеть. Устаревшее имя
        // кадра врёт так же, как устаревшее имя теста, — только про
        // картинку, и проверить его можно лишь взглядом.
        спросить()
        снять("13-просится-шаг-00")
        for шаг in 1...15 {
            app.swipeUp()
            спросить()
            if шаг % 3 == 0 { снять(String(format: "13-просится-шаг-%02d", шаг)) }
        }

        // КОНТРОЛЬ, и он стоит первым: галерея ПОСТРОИЛАСЬ.
        // Без него все запреты ниже выполняются на пустом экране,
        // и набор, которому нечего проверять, молчит так же, как
        // набор, у которого всё хорошо. Ищем пояснение САМОЙ галереи —
        // строку, которой нет больше нигде в приложении.
        XCTAssertTrue(найдено.contains("живой истории здесь нет"), """
            пояснения галереи на экране нет — она не построилась. \
            Это не «с состояниями всё хорошо», это нечем смотреть.

            Нашлось из \(искомое.count): \(найдено.sorted().joined(separator: " | "))
            """)

        func есть(_ что: String) -> Bool { найдено.contains(что) }

        // Пять заголовков. Их ровно пять, а состояний семь: у `.unknown`
        // три причины, и `title` сводит их к одному «Непонятно».
        for заголовок in ["Выведи сейчас", "Выведи", "Непонятно",
                          "Скорее внимания", "Выводи по первому знаку"] {
            XCTAssertTrue(есть(заголовок), """
                нет заголовка «\(заголовок)». Либо состояние из галереи \
                убрали, либо движок перестал в него попадать на тех же \
                фактах — второе важнее.

                Нашлось: \(найдено.sorted().joined(separator: " | "))
                """)
        }

        // Шесть подписей. Их шесть при семи состояниях: «неясно» носят
        // три — «мало данных» и оба пути в `.ambiguous`.
        for подпись in ["срочно", "похоже на нужду", "неясно",
                        "отметок мочи нет", "эпизод"] {
            XCTAssertTrue(есть(подпись), "нет подписи «\(подпись)»")
        }

        // Счётчик дней доезжает до экрана. Без этого `notEnoughData(days:)`
        // носил бы число, которого человек не видит: заголовок и подпись
        // у него общие с «неясно», и отличает его только объяснение.
        XCTAssertTrue(есть("записей всего за"), """
            в объяснении «мало данных» нет счётчика записей. Число \
            `days` доезжает до человека только здесь: заголовок \
            «Непонятно» и подпись «неясно» у этого состояния общие \
            с двумя другими.
            """)

        // Восьмое состояние на месте. Оно не исход вердикта, а
        // расхождение: `.probablyAttention` пишет «Вышли N назад»,
        // считая N по времени мочи. В остальных семи оба числа заданы
        // одинаковыми, и расхождение на кадре неразличимо — состояние
        // существует только затем, чтобы его стало видно.
        XCTAssertTrue(есть("РАСХОЖДЕНИЕ"), """
            состояние «расхождение» из галереи пропало. Если его убрали \
            намеренно — убери и эту проверку; если оно просто перестало \
            строиться, то единственный кадр, на котором видно, что \
            «Вышли N назад» считается по МОЧЕ, исчез молча.
            """)

        // Подсказка показывается ТОЛЬКО при «мало данных» — значит
        // она же доказывает, что в это состояние попали, а не
        // прочитали похожий текст.
        XCTAssertTrue(есть("Через три-четыре дня"), """
            нет подсказки «через три-четыре дня» — состояние «мало \
            данных» не построилось либо условие её показа разошлось \
            с вердиктом
            """)

        // Починка 28.09: восемнадцать дней без отметок обязаны читаться
        // как молчание дневника. От обратного — запрещаем то, что
        // дефект говорил: «дольше, чем он когда-либо терпел» на тишине.
        XCTAssertTrue(есть("Приложение не знает, писал он или просто никто не отметил"), """
            состояние тишины не нашлось. До 28.09 на этих же фактах \
            приложение говорило «Не писал 434 ч. Это дольше, чем он \
            когда-либо терпел» — медицинское утверждение, выведенное \
            из отсутствия записи.
            """)

        // Две точки подряд — дефект 05.10 на этой же строке:
        // `Fmt.shortDay` отдаёт сокращение месяца со своей точкой,
        // а шаблон ставил свою. Ловится только на русском: где
        // сокращение кончается не точкой, повода нет.
        // Спрашиваем предикатом, а не перебором: вопрос «есть ли где-то
        // на экране две точки» задаётся одной строкой запроса, и список
        // под рукой при этом не перебирается.
        guard подписи.язык == "ru" else { return }
        var сДвумяТочками: [String] = []
        for _ in 0..<6 {
            app.swipeDown()
            let плохие = app.descendants(matching: .any)
                .matching(NSPredicate(format: "label CONTAINS %@ AND NOT label CONTAINS %@",
                                      "..", "..."))
            if плохие.firstMatch.exists { сДвумяТочками.append(плохие.firstMatch.label) }
        }
        XCTAssertTrue(сДвумяТочками.isEmpty, """
            две точки подряд: \(сДвумяТочками.joined(separator: " | "))

            Это возврат дефекта 05.10: `Fmt.shortDay` несёт точку \
            сокращения, и вторая приходит из шаблона. Чинить надо \
            структурой фразы — убрать точку из шаблона нельзя, \
            сокращение кончается точкой не во всех языках.
            """)
    }

    private func снять(_ имя: String) {
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = имя
        кадр.lifetime = .keepAlways
        add(кадр)
    }
}
