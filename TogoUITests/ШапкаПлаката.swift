        }
        var байты = [UInt8](repeating: 0, count: cg.width * cg.height * 4)
        let пространство = CGColorSpaceCreateDeviceRGB()
        guard let контекст = CGContext(
            data: &байты, width: cg.width, height: cg.height,
            bitsPerComponent: 8, bytesPerRow: cg.width * 4, space: пространство,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
