                поднимет её сильнее всего;
              · контраст им принимать НЕЛЬЗЯ. Контраст меряется парой
                «цвет поверх своего фона после наложения», и у нас это
                оплачено кнопкой 1,68:1, где токен был верен всегда;
              · он ловит ровно одно, зато то, чего не ловит ничто
                другое: **тема не переключилась вовсе**. Так 07.10.2026
