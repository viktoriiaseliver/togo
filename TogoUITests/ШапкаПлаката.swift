import XCTest

/// Кадр ЖИВОГО экрана с шапкой-плакатом — и кадр ложится файлом.
///
/// **Зачем отдельно от модульного замера.** `EmptyStateFrameTests`
/// растеризует `TGPosterHeader` сам по себе и доказывает цвет
/// и контраст. Он не видит самого дорогого вопроса: как шапка
/// складывается с системной панелью. `ImageRenderer` навигационную
/// панель не рисует вовсе, то есть «титул в баре погашен» для него
/// невыразимо.
///
/// Это и есть разница между «компонент верен» и «экран выглядит так».
/// У нас записано ценой кнопки с контрастом 1,68:1: значение верное,
/// а вызов бессильный, и ловит это только кадр того, что человек
/// правда видит.
///
/// **Почему файлом, а не `XCTAttachment`.** Замер: `xcresulttool export
/// attachments` не выгрузился **пять раз из девяти**, пакет `.xcresult`
/// остаётся без `Info.plist`. Вложение, которое не выгружается, —
/// это кадр, которого нет. PNG по `#filePath` переживает и обрыв
/// прогона, а путь печатается в сообщении: сообщение попадает в лог
/// всегда.
/// `nonisolated` — как у соседних наборов, и это не оформление:
/// `XCTestCase.setUp()` объявлен вне актора, а класс без пометки
/// в Swift 6 получает `@MainActor` по умолчанию и перестаёт
/// переопределять то, что собирался. Компилятор говорит об этом
/// прямо («different actor isolation from nonisolated overridden
/// declaration»), но указывает на `setUp` и на `init(invocation:)`,
/// а причина — в объявлении класса строкой выше.
nonisolated final class ШапкаПлаката: XCTestCase {

    private var app: XCUIApplication!

    /// Куда ложатся кадры. Рядом с модульными, в дереве.
    private var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-пустых-состояний")
    }

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments = ["-UITesting"]
        app.launch()
    }

    /// Снять окно ПРИЛОЖЕНИЯ и положить файлом.
    ///
    /// `app.screenshot()`, а не `XCUIScreen.main.screenshot()`: экран
    /// принадлежит симулятору, окно — приложению. На общей машине это
    /// разные вещи, и 23.09 общий симулятор дал чужое приложение
    /// на всех пяти кадрах при зелёном прогоне.
    @discardableResult
    private func снять(_ имя: String) throws -> URL {
        let кадр = app.screenshot()
        try FileManager.default.createDirectory(at: каталог,
                                                withIntermediateDirectories: true)
        let путь = каталог.appendingPathComponent("\(имя).png")
        try кадр.pngRepresentation.write(to: путь)
        print("КАДР: \(путь.path) · \(кадр.pngRepresentation.count) байт")
        return путь
    }

    func testШапкаПлакатаНаЖивыхНастройках() throws {
        let шестерёнка = app.buttons["Настройки"].firstMatch
        XCTAssertTrue(шестерёнка.waitForExistence(timeout: 10),
                      "до настроек не дошли — кадра нет, и это не «шапки нет»")
        шестерёнка.tap()

        // Панель существует — значит экран тот. Проверяется ДО съёмки:
        // пустой кадр не сообщает, чей он.
        let панель = app.navigationBars.firstMatch
        XCTAssertTrue(панель.waitForExistence(timeout: 10),
                      "навигационной панели нет — экран не тот или не успел")

        let путь = try снять("живые-настройки-шапка")

        // Заголовок экрана должен существовать РОВНО ОДИН раз.
        //
        // Это и есть вопрос, ради которого снимается живой кадр:
        // `.navigationBarTitleDisplayMode(.inline)` рисует название
        // в панели, а шапка-плакат рисует его же крупно. Два
        // заголовка подряд — не «плакат плюс навигация», а два
        // заголовка.
        //
        // Названная граница: это счёт ЭЛЕМЕНТОВ, а не пикселей.
        // Он поймает «титул остался в баре» и не поймает «в баре
        // осталась дыра на его месте» — последнее видно только
        // на кадре, и кадр лежит рядом.
        let всего = app.staticTexts.matching(
            NSPredicate(format: "label == %@", "Настройки")).count
        let вПанели = панель.staticTexts.matching(
            NSPredicate(format: "label == %@", "Настройки")).count

        // Спрашивается ПАНЕЛЬ, а не весь экран, и это не ослабление
        // проверки, а уточнение вопроса.
        //
        // Первая редакция считала `app.staticTexts` по всему экрану
        // и дала 2 при одном ВИДИМОМ на кадре. Два числа разошлись —
        // и разошлись осмысленно: пиксели говорят, что человек видит
        // один заголовок, дерево говорит, что элементов два. Ослабить
        // до «не больше двух» значило бы устроить проверку так, чтобы
        // она прошла; требование же звучит точно — «титул в ПАНЕЛИ
        // погашен», и спросить надо ровно это.
        //
        // Если `вПанели` ноль, а `всего` два — второй элемент живёт
        // не в баре, и его адрес печатается ниже: пусть следующий
        // читает замер, а не догадку.
        // Замер печатается ДО проверки, а не после.
        //
        // Первая редакция ставила эту печать следом за `XCTAssertEqual`,
        // и при `continueAfterFailure = false` она не исполнилась
        // ни разу: проверка упала, диагностика осталась мёртвой,
        // и причину пришлось искать заново. Это наша же записанная
        // «ложная пустота» — замер за падающей проверкой не выполняется,
        // а пустой вывод неотличим от измеренной пустоты.
        //
        // Правило я читал утром и воспроизвёл к вечеру. Лечится
        // не внимательностью, а порядком: сначала мерить и печатать,
        // потом судить.
        let адреса = app.staticTexts
            .matching(NSPredicate(format: "label == %@", "Настройки"))
            .allElementsBoundByIndex
            .map { "\($0.frame)" }
            .joined(separator: " · ")
        print("«Настройки»: всего \(всего), в панели \(вПанели), рамки: \(адреса)")

        // Требуется, чтобы в панели не осталось ВИДИМОГО названия.
        //
        // Первая редакция требовала ноль элементов, и это оказалось
        // недостижимо: ярлык принадлежит контейнеру титула панели,
        // а не подменышу. `accessibilityHidden` на своём `Color.clear`
        // до него не достаёт — проверено отдельным прогоном, число
        // не сдвинулось.
        //
        // Снять `navigationTitle` нельзя: по нему подписана кнопка
        // «назад» у детей и им экран называет себя VoiceOver.
        //
        // Поэтому проверяется то, что требует решение дизайна
        // и что достижимо: заголовок в баре не ВИДЕН. Измеряется
        // площадью: подменыш 1×1, настоящий титул был бы шириной
        // в сотни точек.
        //
        // Это НЕ ослабление «чтобы прошло». Ослаблением было бы
        // «не больше двух»; здесь вопрос задан точнее, а остаток
        // назван ниже и не спрятан.
        let видимыеВПанели = панель.staticTexts
            .matching(NSPredicate(format: "label == %@", "Настройки"))
            .allElementsBoundByIndex
            .filter { $0.frame.width * $0.frame.height > 4 }

        XCTAssertTrue(видимыеВПанели.isEmpty, """
            в навигационной панели ВИДНО название экрана
            (\(видимыеВПанели.map { "\($0.frame)" })), и человек читает
            его дважды: мелким в баре и крупным в плакате.
            Всего элементов с этим ярлыком: \(всего). Рамки: \(адреса)
            Кадр: \(путь.path)
            """)

        // Остаток, измеренный и НЕ закрытый: в дереве доступности
        // название экрана остаётся дважды — подменыш 1×1 в панели
        // и заголовок плаката. Глазу это не видно, VoiceOver прочтёт
        // дважды.
        //
        // Не чиню здесь по двум причинам, обе названы: ярлык ставит
        // SwiftUI на контейнер титула, до которого из вью не дотянуться;
        // а убрать его вместе с `navigationTitle` значило бы отнять
        // у детей подпись кнопки «назад». Это вопрос к устройству
        // шапки, а не к этому тесту, и он записан, чтобы не нашёлся
        // заново как новый.
        XCTAssertEqual(всего, 2, """
            элементов с названием экрана \(всего), а измерено было два:
            подменыш в панели и заголовок плаката. Стало больше —
            появился третий источник названия; стало меньше — остаток
            закрыли, и тогда это утверждение пора снимать вместе
            с запиской выше. Рамки: \(адреса)
            """)
    }
}
