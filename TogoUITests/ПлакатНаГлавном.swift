import XCTest

/// Приёмка подключения плаката к «Сегодня» 07.10.2026: кадр
/// **настоящего** экрана, а не галереи.
///
/// **Галерея отвечает на другой вопрос.** Она показывает, как выглядит
/// режим; этот тест — тот ли режим показан. Между ними дыра, и она
/// ровно того класса, который у Togo уже стоил дня: правило верно,
/// токен верен, значение верно — а на экране не то, потому что экрану
/// передали не то состояние.
///
/// > **Три зелёные части не складываются в зелёный сценарий.** Зелёная
/// > часть ничего не обещает про стык, а стыков всегда больше, чем
/// > частей.
///
/// **Пять режимов, и все пять достижимы с 07.10.2026.** Трёх сценариев
/// не существовало, и первая редакция этого абзаца честно писала
/// «кадры не сняты». Теперь они есть:
///
/// ```
/// usual     today        индиго
/// dose      amber        светлый акцент, инверсные цифры
/// quiet     firstDay     записей нет вовсе → rhythm.days == 0
/// fastingOnly            окно натощак БЕЗ просроченной дозы
/// vomitAlarm             три рвоты за три часа — порог ровно на краю
/// ```
///
/// Два последних пришлось заводить не потому, что данных не хватало,
/// а потому что **порядок проверок** в `PosterMode` делал состояния
/// недостижимыми: в `amber` доза перебивает натощак, а `emptyDogs`
/// делит события с `today`.
///
/// > Состояние бывает недостижимо не из-за отсутствия данных,
/// > а из-за порядка проверок — и сценарий, написанный без этого
/// > знания, дал бы третий `dose` и выглядел бы рабочим.
///
nonisolated final class ПлакатНаГлавномUITests: XCTestCase {
    // `подписи` отсюда снято вместе с пиксельным замером: поле держало
    // ожидаемые цвета, которых теперь не существует.

    /// Запустить приложение в сценарии и дождаться главного экрана.
    private func запустить(_ сценарий: String) -> XCUIApplication {
        let app = XCUIApplication()
        // ~~«`-ФонФикстура` здесь обязателен, и это замер»~~ — **СНЯТ
        // 26.10.2026, и снят по кадру.** Он был нужен прежней,
        // пиксельной оси: без фото `usual` и `quiet` неразличимы.
        // Оси этой больше нет, а вред от флага есть.
        //
        // **Фикстура фона ЛОМАЕТ РАСКЛАДКУ.** Кадры, снятые с ней,
        // показывают содержимое шире экрана и сдвинутым влево:
        //
        // ```
        // с -ФонФикстура    «Сегодня»→«егодня» · «07:02»→«7:02»
        //                   «Просится» начинается за левым краем,
        //                   «+» срезан справа; таб-бар стоит ровно
        // без флага         всё внутри, ничего не обрезано
        //                   (`Дизайн/кадры-приёмки/витрина-вершина-25.10/
        //                     01-today.png`)
        // ```
        //
        // > **Я померила свой стенд и написала вывод про продукт.**
        // > Рамка `(-39.0, 61.67, 480.0, 360.0)`, на которой стоял
        // > разбор «блок шире экрана», снята ПОД ФИКСТУРОЙ. Про экран
        // > человека она не говорит ничего.
        //
        // Кадры этого теста — приёмка цвета панели, и под фикстурой
        // они негодны вдвойне: поверх фото лежат цветные приметы.
        app.launchArguments = ["-UITesting", "-Сценарий", сценарий]
        app.launch()
        // Неизвестный сценарий роняет приложение намеренно
        // (`fatalError` в `TogoApp.uiTestingScenario`): молча подставить
        // обычный день значит дать тесту снять не то состояние
        // и назвать это успехом.
        // ПРИЗНАК ПОДНЯТИЯ — МЕНЮ «…», А НЕ «НАСТРОЙКИ» (правка 25.10.2026).
        //
        // Кнопка настроек ушла внутрь меню 22.10, и дети `Menu`
        // не существуют в дереве доступности, пока меню не открыто.
        // Ждать её — значит ждать вечно и доложить «главный экран
        // не поднялся» про поднявшийся экран.
        //
        // Меню живёт в шапке и видно сразу; этот тест в настройки
        // не ходит вовсе, ему нужен только признак «экран есть».
        XCTAssertTrue(app.buttons["Ещё"].firstMatch.waitForExistence(timeout: 25),
                      "главный экран не поднялся в сценарии «\(сценарий)»")
        return app
    }

    /// Какой чип состояния показан сейчас.
    ///
    /// **Замена пиксельному замеру, и это решение по замеру, а не
    /// отступление** (25.10.2026). Три редакции подряд мерили цвет
    /// точки и три раза попадали не туда: доля экрана → шестерёнка
    /// настроек; верхний угол блока → полоса навигации; нижний
    /// угол блока → фон экрана ниже панели. Четвёртый заход сказал,
    /// почему четвёртой редакции не будет:
    ///
    /// ```
    /// панель.exists = FALSE   даже запросом по ЛЮБОМУ типу
    /// блок.exists   = true    rect = (-39.0, 61.67, 480.0, 360.0)
    /// ```
    ///
    /// Панели **нет в дереве доступности** — это и решает: держать
    /// пиксельный замер не на чем, доступной рамки у крашеной
    /// поверхности просто нет.
    ///
    /// > **А вот рамку из второй строки читать как факт о продукте
    /// > НЕЛЬЗЯ, и я это сделала.** Замер снят под `-ФонФикстура`,
    /// > а фикстура ломает раскладку: на её кадрах «Сегодня» обрезано
    /// > в «егодня», кнопка «Просится» начинается за левым краем.
    /// > Без флага тот же экран лежит ровно
    /// > (`Дизайн/кадры-приёмки/витрина-вершина-25.10/01-today.png`).
    /// > «480 при 402» — число про СТЕНД. Флаг отсюда снят 26.10.2026.
    ///
    /// > **Когда у замера нет годной оси, меняют вопрос, а не точку.**
    /// > Цвет теперь сторожат токены — `ЧернилаПанелиПарныеЗаливкеTests`
    /// > меряет пары «чернила ↔ заливка» на двух этажах, 32 сочетания.
    /// > Здесь остаётся то, чего не видит ни один модульный тест:
    /// > **доходит ли до экрана верный режим дня.**
    ///
    /// Чип называет режим словами и живёт в дереве доступности
    /// обычным текстом. Это та же ось, ради которой тест писался:
    /// «`PosterMode.mode(состояниеДня)` на экране получает одно
    /// и то же состояние». Кадры по-прежнему снимаются — цвет
    /// проверяется ими, и это записано как долг, а не как сделанное.
    private func чипВиден(_ app: XCUIApplication, _ текст: String) -> Bool {
        app.staticTexts[текст].firstMatch.waitForExistence(timeout: 10)
    }

    /// Режим дня доходит до экрана: у каждого сценария свой чип.
    ///
    /// Тексты взяты из `TodayScreen.чипСостояния` **литералами**,
    /// а не пересчётом той же функции: тест, вычисляющий ожидание
    /// тем же кодом, что и предмет, зелен при любой общей ошибке.
    ///
    /// У `today` литерала нет нарочно: там `обычныйЧип`, и его подпись
    /// зависит от ВИДА ПОКАЗАНИЯ, а не от режима. Поэтому про него
    /// утверждается то, что про него известно, — **ни один из четырёх
    /// именных чипов**.
    func testРежимДняДоходитДоЭкрана() {
        let именные = [("amber", "Доза по часам"),
                       ("firstDay", "Первый день"),
                       ("fastingOnly", "Натощак"),
                       ("vomitAlarm", "Похоже, пора звонить")]
        var увидено: [String: String] = [:]
        var осмотрено = 0

        for (сценарий, ожидаемый) in именные {
            let app = запустить(сценарий)
            осмотрено += 1
            let кадр = XCTAttachment(screenshot: app.screenshot())
            кадр.name = "12-плакат-главный-\(сценарий)-ждём-\(ожидаемый)"
            кадр.lifetime = .keepAlways
            add(кадр)
            if чипВиден(app, ожидаемый) { увидено[сценарий] = ожидаемый }
            app.terminate()
        }

        // Обычный день: ни одного из четырёх именных.
        let app = запустить("today")
        осмотрено += 1
        let кадр = XCTAttachment(screenshot: app.screenshot())
        кадр.name = "12-плакат-главный-today-ждём-обычный"
        кадр.lifetime = .keepAlways
        add(кадр)
        let чужие = именные.map(\.1).filter { app.staticTexts[$0].firstMatch.exists }
        app.terminate()

        // **Сначала — было ли что мерить.** При нулевом осмотре
        // «все сценарии прошли» истинно всегда.
        XCTAssertEqual(осмотрено, 5,
                       "поднято \(осмотрено) сценариев из пяти — замер не состоялся")

        XCTAssertEqual(увидено.count, именные.count, """
            свой чип показали \(увидено.count) сценария из \(именные.count): \(увидено).
            Не показавший — это режим, который до экрана НЕ дошёл:
            правило `PosterMode` может быть верным, и модульные тесты
            зелёными, между ними дыра, ради которой тест и написан.
            """)

        XCTAssertTrue(чужие.isEmpty, """
            обычный день показал чужой чип: \(чужие).
            Значит `состояниеВерхнее` на сценарии «today» попало
            в именную ветку, и два сценария рисуют одно и то же.
            """)
    }
}
