import XCTest

/// Приёмка подключения плаката к «Сегодня» 07.10.2026: кадр
/// **настоящего** экрана, а не галереи.
///
/// **Галерея отвечает на другой вопрос.** Она показывает, как выглядит
/// режим; этот тест — тот ли режим показан. Между ними дыра, и она
/// ровно того класса, который у Togo уже стоил дня: правило верно,
/// токен верен, значение верно — а на экране не то, потому что экрану
/// передали не то состояние.
///
/// > **Три зелёные части не складываются в зелёный сценарий.** Зелёная
/// > часть ничего не обещает про стык, а стыков всегда больше, чем
/// > частей.
///
/// **Пять режимов, и все пять достижимы с 07.10.2026.** Трёх сценариев
/// не существовало, и первая редакция этого абзаца честно писала
/// «кадры не сняты». Теперь они есть:
///
/// ```
/// usual     today        индиго
/// dose      amber        светлый акцент, инверсные цифры
/// quiet     firstDay     записей нет вовсе → rhythm.days == 0
/// fastingOnly            окно натощак БЕЗ просроченной дозы
/// vomitAlarm             три рвоты за три часа — порог ровно на краю
/// ```
///
/// Два последних пришлось заводить не потому, что данных не хватало,
/// а потому что **порядок проверок** в `PosterMode` делал состояния
/// недостижимыми: в `amber` доза перебивает натощак, а `emptyDogs`
/// делит события с `today`.
///
/// > Состояние бывает недостижимо не из-за отсутствия данных,
/// > а из-за порядка проверок — и сценарий, написанный без этого
/// > знания, дал бы третий `dose` и выглядел бы рабочим.
///
nonisolated final class ПлакатНаГлавномUITests: XCTestCase {
    private let подписи = Подписи()

    /// Запустить приложение в сценарии и дождаться главного экрана.
    private func запустить(_ сценарий: String) -> XCUIApplication {
        let app = XCUIApplication()
        // **`-ФонФикстура` здесь обязателен, и это замер.** Два режима
        // из пяти — `usual` и `quiet` — панель сплошным НЕ кроют
        // (`ReadingPanel.поверхность`: материал, не заливка), и
        // различает их только `tone.dimsPhoto` — затемнение ФОТО
        // на 30 %. Поверх чёрного оно тождество, а без фикстуры фона
        // подложка и есть `Token.Surface.screen` = `#000000`.
        //
        // То есть без фото требование «пять режимов — пять цветов»
        // ложно ПО УСТРОЙСТВУ, а не по дефекту: замер 25.10 дал
        // `firstDay` и `today` одним значением `#1F201E`.
        //
        // Берём ветку `положить()`. Отказ 4 из 4, записанный
        // в `ФонФикстураСтенда` (первый запуск встаёт на онбординге),
        // снят с ветки **снятия**, которая влезала в путь сорока чужих
        // тестов; механизм там не установлен, поэтому ручаться
        // за ветку укладки нельзя — но она другая, и её цена здесь
        // проверяется прогоном, а не рассуждением.
        app.launchArguments = ["-UITesting", "-ФонФикстура", "-Сценарий", сценарий]
        app.launch()
        // Неизвестный сценарий роняет приложение намеренно
        // (`fatalError` в `TogoApp.uiTestingScenario`): молча подставить
        // обычный день значит дать тесту снять не то состояние
        // и назвать это успехом.
        // ПРИЗНАК ПОДНЯТИЯ — МЕНЮ «…», А НЕ «НАСТРОЙКИ» (правка 25.10.2026).
        //
        // Кнопка настроек ушла внутрь меню 22.10, и дети `Menu`
        // не существуют в дереве доступности, пока меню не открыто.
        // Ждать её — значит ждать вечно и доложить «главный экран
        // не поднялся» про поднявшийся экран.
        //
        // Меню живёт в шапке и видно сразу; этот тест в настройки
        // не ходит вовсе, ему нужен только признак «экран есть».
        XCTAssertTrue(app.buttons["Ещё"].firstMatch.waitForExistence(timeout: 25),
                      "главный экран не поднялся в сценарии «\(сценарий)»")
        return app
    }

    /// Цвет точки внутри блока плаката.
    ///
    /// **Точка берётся по РАМКЕ блока, а не по доле экрана, и это
    /// исправление, а не предпочтение.** Первая редакция мерила 92 %
    /// ширины и 9 % высоты — и попадала в шестерёнку настроек:
    ///
    /// ```
    /// today=#96B2EC · emptyDogs=#96B2EC · amber=#9BBAF5
    /// ```
    ///
    /// Светло-синие, тогда как подложки плаката тёмные (`#2A3670`,
    /// `#4A3A14`, `#181818`). Два значения совпали, тест покраснел —
    /// и покраснел **правдиво про замер и ложно про плакат**: вывод
    /// «плакат одного цвета в разных режимах» был бы обратен правде.
    ///
    /// > Координата, посчитанная от края экрана, измеряет экран.
    /// > Рамка элемента измеряет элемент.
    ///
    /// ~~«Справа сверху внутри блока — гарантированно подложка: весь
    /// текст плаката выровнен по левому краю».~~ **Эта строка
    /// разошлась с кодом рядом с собой**: код мерил НИЗ (`maxY − 20`)
    /// с собственным обоснованием про полосу навигации, а строка
    /// говорила «сверху». Два утверждения об одном замере в одном
    /// файле, и ни одно не ссылалось на другое.
    ///
    /// > **Поправка, вписанная рядом, не отменяет прежнюю — она
    /// > становится вторым ответом на тот же вопрос.** Прежнюю
    /// > зачёркивать, а не оставлять «для истории»: читающий возьмёт
    /// > ту, которая попалась первой.
    ///
    /// Верное — в комментарии у самого замера ниже: рамка ПАНЕЛИ,
    /// нижняя полоса, свободная от текста по устройству.
    private func цветПлаката(_ app: XCUIApplication) -> UInt32? {
        // **Рамка ПАНЕЛИ, а не блока, и это третий промах того же
        // замера, снятый 25.10.2026.** Блок несёт
        // `.accessibilityElement(children: .contain)`, то есть его
        // рамка — ОБЪЕДИНЕНИЕ рамок всех детей, а цвет тона живёт
        // только в панели показания (`ReadingPanel.поверхность`).
        // Нижний правый угол объединения уходил НИЖЕ панели, на фон
        // экрана:
        //
        // ```
        // amber=#000000 · fastingOnly=#000000 · vomitAlarm=#000000
        // firstDay=#1F201E · today=#1F201E
        // ```
        //
        // Три тона, кроющих панель сплошным, дали ОДИН чёрный —
        // `Token.Surface.screen` темы «Кино», а `#1F201E` в токенах
        // не значится вовсе: это пиксель фотографии.
        //
        // > `children: .contain` делает рамку шире предмета. Прежние
        // > две редакции мерили долю экрана и верхний угол; обе
        // > поправки были верны и обе оставили рамку БЛОКА.
        let панель = app.otherElements["панель-показания"].firstMatch
        guard панель.waitForExistence(timeout: 10), панель.frame.width > 0 else { return nil }
        let кадр = app.screenshot()
        let картинка = кадр.image
        guard let cg = картинка.cgImage else { return nil }
        // Рамка в точках, кадр в пикселях — переводим масштабом кадра.
        let масштаб = Double(cg.width) / Double(кадр.image.size.width)
        // Нижняя полоса панели свободна от текста **по устройству**,
        // а не по виду на кадре: внутренний стек несёт
        // `.padding(.bottom, Token.Space.s16)`, и уже поверх него
        // стоит `.frame(minHeight:)` — если содержимое короче, пустого
        // места внизу становится только больше. Сверху брать нельзя
        // (полоса навигации с материалом дала `#0D0F1B` там, где блок
        // индиго `#2A3670`), справа сверху — пилюля запаса.
        let x = Int((панель.frame.maxX - 12) * масштаб)
        let y = Int((панель.frame.maxY - 8) * масштаб)
        guard x >= 0, y >= 0, x < cg.width, y < cg.height else { return nil }
        var байты = [UInt8](repeating: 0, count: 4)
        guard let пространство = CGColorSpace(name: CGColorSpace.sRGB),
              let контекст = CGContext(data: &байты, width: 1, height: 1,
                                       bitsPerComponent: 8, bytesPerRow: 4,
                                       space: пространство,
                                       bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
        else { return nil }
        контекст.draw(cg, in: CGRect(x: -Double(x), y: Double(y) - Double(cg.height) + 1,
                                     width: Double(cg.width), height: Double(cg.height)))
        return (UInt32(байты[0]) << 16) | (UInt32(байты[1]) << 8) | UInt32(байты[2])
    }

    func testПлакатНаГлавномМеняетЦветСРежимом() {
        var замер: [String: UInt32] = [:]

        // **Два сценария, а не три, и это замер, а не экономия.**
        // Первая редакция брала `today`, `emptyDogs`, `amber` и ждала
        // от них `usual`, `quiet`, `fasting`. Кадры показали другое:
        //
        // ```
        // SeedData:272   case .today, .amber, .emptyDogs, .wipedName:
        //                → ОДНИ И ТЕ ЖЕ события, значит один режим
        // amber          → dose, а НЕ fasting: `isDoseDue` проверяется
        //                  РАНЬШЕ `isFasting`, и у сценария есть
        //                  неотмеченная доза 08:00 — видно на кадре
        //                  плашкой «Доза 08:00 не отмечена»
        // ```
        //
        // Второе — не дефект, а документированное правило `PosterMode`:
        // «доза сильнее натощак: натощак ВЕДЁТ к дозе, и когда час
        // наступил, окно уже не главное». То есть тест ждал не того,
        // а код был прав.
        //
        // > Ожидание, записанное в имени кадра, — такое же утверждение
        // > о поведении, как имя теста, и стареет так же молча.
        for (сценарий, ожидаемыйРежим) in [("today", "usual"),
                                           ("amber", "dose"),
                                           ("firstDay", "quiet"),
                                           ("fastingOnly", "fasting"),
                                           ("vomitAlarm", "alarm")] {
            let app = запустить(сценарий)

            let кадр = XCTAttachment(screenshot: app.screenshot())
            кадр.name = "12-плакат-главный-\(сценарий)-ждём-\(ожидаемыйРежим)"
            кадр.lifetime = .keepAlways
            add(кадр)

            if let цвет = цветПлаката(app) { замер[сценарий] = цвет }
            app.terminate()
        }

        // **Сначала — было ли что мерить.** Эта проверка стоит ПЕРЕД
        // проверкой различия: при одном замере «все значения различны»
        // истинно всегда. Поймано на галерее тем же способом — там
        // из четырёх точек измерилась одна.
        XCTAssertEqual(замер.count, 5, """
            замерено \(замер.count) сценариев из пяти: \(печать(замер)).
            Замер не состоялся — значит всё, что ниже, ничего
            не утверждает.
            """)

        // Цвет плаката обязан отличаться между режимами. Проверка
        // от ОТНОШЕНИЯ: она верна в любой теме, а «подложка равна
        // 0x2A3670» покраснела бы на верном коде при смене темы.
        XCTAssertEqual(Set(замер.values).count, замер.count, """
            плакат одного цвета в разных режимах: \(печать(замер)).

            Это значит, что `PosterMode.mode(состояниеДня)` на экране
            получает одно и то же состояние. Правило при этом может
            быть верным, и галерея — зелёной: между ними дыра, ради
            которой этот тест и написан.
            """)

        print("замер плаката на главном: \(печать(замер))")
    }

    private func печать(_ замер: [String: UInt32]) -> String {
        замер.map { "\($0.key)=#\(String(format: "%06X", $0.value))" }
            .sorted().joined(separator: " · ")
    }
}
