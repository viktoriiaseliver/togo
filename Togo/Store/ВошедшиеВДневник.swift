import Foundation

/// Кто из приглашённых уже вошёл — чтобы сказать об этом владельцу.
///
/// Просьба Виктории 29.10.2026: «чтобы человек видел, что его позвали,
/// что он добавился и что всё получилось». До этого вход мамы в дневник
/// не замечал никто: `CKShare` менял `acceptanceStatus` молча, и узнать
/// «получилось ли» можно было только открыв третий экран.
///
/// Два адресата — два отдельных счёта, и это не дубль: уведомление
/// приходит, когда приложение закрыто, а строка «Мама — в дневнике»
/// в «Семье» — когда его открыли. Отметь один общий счёт «уже сказали»,
/// и тот, кто прочитал пуш, не увидел бы строки, а тот, кто открыл
/// экран раньше обмена, — не получил бы пуша.
@MainActor
enum ВошедшиеВДневник {
    enum Адресат: String { case экран, уведомление }

    private static func ключ(_ адресат: Адресат) -> String { "family.accepted.seen.\(адресат.rawValue)" }

    /// Подписи вошедших, о ком этому адресату ещё не говорили. Отмечает
    /// их сказанными. Владельца и себя не считает.
    static func новые(среди состав: [УчастникДневника], для адресат: Адресат) -> [String] {
        let вошли = состав.filter { $0.принял && !$0.владелец && !$0.я }
        let видели = Set(UserDefaults.standard.stringArray(forKey: ключ(адресат)) ?? [])
        let новые = вошли.filter { !видели.contains($0.id) }
        guard !новые.isEmpty else { return [] }
        UserDefaults.standard.set(Array(видели.union(вошли.map(\.id))), forKey: ключ(адресат))
        return новые.map { $0.подпись ?? String(localized: "Новый участник") }
    }

    /// Проверить после обмена и сказать владельцу уведомлением.
    ///
    /// Зовётся из `ЧужоеПринято` (после каждой выборки чужого): вход
    /// участника меняет `CKShare`, и выборка — первый момент, когда
    /// этот телефон может об этом узнать, в том числе в фоне.
    static func проверить() async {
        guard SharedDiarySettings.isOn, !SharedZoneOwner.isGuest else { return }
        let состав = await FamilyShare.участники()
        for имя in новые(среди: состав, для: .уведомление) {
            _ = await NotificationCenterService.scheduleJoined(
                id: "family-joined-\(UUID().uuidString)",
                title: String(localized: "\(имя) — в дневнике"),
                body: String(localized: "Приглашение открыто: записи теперь общие."))
        }
    }
}
