import SwiftUI

/// Как экраны попадают в журнал действий.
///
/// Один модификатор вместо пары `onAppear`/`onDisappear` на каждом экране:
/// пары расходятся — где-то забудут закрывающую половину, и всё, что человек
/// сделал дальше, окажется записано на чужой экран.
extension View {
    /// Отметить, что человек стоит на этом экране.
    ///
    /// **`nil` значит «не записывать», и заведён он ради галерей.**
    /// Галерея строит настоящий экран настоящим модификатором — то есть
    /// шесть демо-состояний «Просится» положили бы в журнал шесть
    /// посещений `.needs`, которых человек не делал. Журналом меряют,
    /// куда уходит время: у Togo уже был случай, когда 44 захода
    /// на «Семью» прочли как «экран плохо устроен», а это была одна
    /// незавершённая настройка. Фантомные посещения — ровно та же
    /// находка, только выдуманная инструментом наблюдения.
    ///
    /// > Поверхность, которую сделали проверяемой, не должна за это
    /// > платить искажением другого замера.
    func usageScreen(_ screen: UsageLog.Screen?) -> some View {
        onAppear { if let screen { UsageLog.entered(screen) } }
            .onDisappear { if let screen { UsageLog.left(screen) } }
    }
}
