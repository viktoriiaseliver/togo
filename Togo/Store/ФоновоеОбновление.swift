import Foundation
import BackgroundTasks

/// Фоновое обновление напоминаний — `BGAppRefreshTask`.
///
/// # Зачем, если напоминания и так пересобираются на запуске
///
/// Запрос уведомления — это текст и время, поставленные **заранее**.
/// Всё, что случилось после постановки и не открыло приложение, в нём
/// не отражено: маму отметила дозу у себя, дело закрыли на втором
/// телефоне, горизонт в три дня (`ReminderScheduler.горизонтСуток`)
/// истёк. До 29.10.2026 единственным, кто пересобирал напоминания,
/// был человек, открывший «Сегодня».
///
/// Фоновое обновление — четвёртый вход (разбор у
/// `ReminderScheduler.refreshAll`): система будит приложение без
/// интерфейса, мы забираем свежее из общего дневника, если он включён,
/// и пересобираем напоминания всех собак.
///
/// # Чего оно НЕ обещает, и это надо знать до того, как на него опираться
///
/// **Когда разбудить, решает iOS, а не мы.** `earliestBeginDate` —
/// это «не раньше», а не «в». Приложение, которое человек смахнул
/// из многозадачности, система не будит вовсе, а в режиме
/// энергосбережения откладывает. Поэтому фон — запасной вход, а не
/// основной: основной — горизонт в трое суток, поставленный на каждом
/// открытии и каждом сохранении.
///
/// В симуляторе `submit` отвечает отказом всегда — он пишется в лог
/// и больше ничего не ломает.
///
/// # Проводка, без которой это мёртвый код
///
/// ```
/// Configuration/Togo-Info.plist
///   UIBackgroundModes                 + fetch
///   BGTaskSchedulerPermittedIdentifiers  идентификатор ниже
/// TogoApp.body                        .backgroundTask(.appRefresh(…))
///                                     — регистрирует обработчик
/// TogoApp, уход в фон                 запросить() — ставит следующий
/// выполнить()                         тоже запросить() — цепочка
/// ```
///
/// Идентификатор записан литералом в обоих местах, а не подстановкой
/// `$(APP_BUNDLE_ID)` в plist: строка в plist и строка здесь обязаны
/// совпасть посимвольно, а подстановка развернулась бы только в plist.
/// Литерал с префиксом пакета (`Shared.xcconfig`: `app.togo.diary`)
/// сверяется глазами; разъехавшиеся строки система не прощает —
/// `submit` отвечает `notPermitted`, и фон молчит.
enum ФоновоеОбновление {
    static let идентификатор = "app.togo.diary.reminders-refresh"

    /// Не чаще раза в шесть часов: чаще система всё равно не даст,
    /// а горизонт в трое суток с этим запасом не кончается.
    static let промежуток: TimeInterval = 6 * 3600

    /// Попросить систему разбудить нас позже.
    ///
    /// Повторный запрос с тем же идентификатором заменяет прежний —
    /// звать можно сколько угодно раз.
    static func запросить() {
        let запрос = BGAppRefreshTaskRequest(identifier: идентификатор)
        запрос.earliestBeginDate = Date().addingTimeInterval(промежуток)
        do {
            try BGTaskScheduler.shared.submit(запрос)
        } catch {
            log.error("Фоновое обновление не запрошено: \(error.localizedDescription)")
        }
    }

    /// Что делает приложение, когда система его разбудила.
    ///
    /// Сначала — следующий запрос: обработчик может не дожить до конца
    /// (система снимает задачу по истечении своего времени), и цепочка
    /// не должна рваться на этом.
    static func выполнить() async {
        запросить()
        guard let container = Persistence.shared else { return }
        // Чужие отметки — прежде пересборки: доза, которую дали
        // на втором телефоне, иначе получила бы свежий звонок.
        if SharedDiarySettings.isOn {
            _ = await FamilySync.обновитьПоПушу()
        }
        await ReminderScheduler.refreshAll(context: container.mainContext,
                                           activeDogID: AppState.запомненнаяСобака,
                                           settings: Settings())
    }
}
