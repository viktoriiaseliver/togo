import Foundation

/// Что открывает Pro — **одно место на все три вещи**.
///
/// **Чем это оплачено.** До 07.10.2026 правило жило восемью `store.isPro`
/// по вью, и ворот среди них было три (`TrainingScreens:110`,
/// `SettingsScreen:217`, `FamilyScreen:57`), а остальные пять
/// показывали состояние подписки. Места, где перечислены сами три
/// вещи, у ворот не было вовсе: список `SubscriptionStore.proFeatures`
/// существовал **для показа** в пейволле и ключа, по которому ворота
/// могли бы на него опереться, не имел.
///
/// Цена такого устройства измерена в этом же проекте дважды:
///
/// * `SettingsScreen:217` считал безымянные записи за собак, и человек
///   без подписки видел «Добавить вторую собаку» с пейволлом вместо
///   «Добавить собаку» — то есть завести ПЕРВУЮ собаку ему предлагали
///   за деньги. Правило стояло на одной поверхности, и починили его
///   там же;
/// * обещание «ссылка ситтера» трижды уезжало в подпись пейволла
///   без дороги в коде — потому что подпись и ворота жили врознь,
///   и сверить их было нечем.
///
/// > **Пока правило списано по местам применения, «ровно три вещи» —
/// > утверждение, которое нечем проверить.**
///
/// Поэтому здесь перечисление, а не свод `if`-ов: у `ProFeature`
/// закрытый набор случаев, и четвёртая вещь не может появиться
/// в воротах, не появившись в подписи пейволла, — `proFeatures`
/// выводится отсюда.
/// **Порядок случаев — это порядок строк в пейволле**, и он изменён
/// 23.10.2026 под эталонный кадр `17.png` темы «Кино». Третья строка,
/// «Матрица переноса», снята 24.10.2026 решением Виктории — обещание
/// не имело дороги, разбор ниже у снятого случая.
/// `allCases` отдаёт случаи в порядке объявления, `proFeatures`
/// выводится из него — значит порядок показа задаётся здесь, а не
/// во вью. Второй копии списка под другой порядок заводить нельзя:
/// две копии разойдутся молча, и обе будут зелёными.
nonisolated enum ProFeature: String, CaseIterable, Sendable {
    /// Вторая и следующие собаки. Бесплатно — одна.
    case secondDog

    /// Семья больше двух человек. Бесплатно — двое.
    case familyBeyondTwo

    // ПЕРЕНОС НАВЫКА УБРАН ИЗ PRO 24.10.2026, решение Виктории:
    // «убери обещание и матрицу, это просто помощь».
    //
    // Сверка с эталоном v10 показала, за что именно платили: пейволл
    // обещал «Матрицу переноса навыка · кто просит × где просят × что
    // вокруг», на эталоне `29-screens.jpg` это СЕТКА навык × контекст
    // с 1–3 точками в ячейках, а на экране стоят три отдельных списка —
    // где, кто просит, дистанция. Пересечений, ради которых матрица
    // и нужна, нет нигде.
    //
    // > **Обещать можно только то, у чего есть дорога** — правило
    // > этого файла, и оно сработало третий раз. Дважды до этого
    // > убирали «ссылку ситтера» и «ситтера со сроком»; оба раза
    // > возвращались через макет, потому что причина лежала
    // > в комментарии Swift, а макет комментарии не читает.
    //
    // Поэтому здесь только снятие из списка. Экран жив и открыт всем:
    // ворота сняты в `TrainingScreens.swift`, а решение записано
    // в `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md` — там, где его прочтёт автор макета.

    // MARK: Подпись

    /// Значок, название и пояснение для пейволла.
    ///
    /// **Строки взяты из `SubscriptionStore.proFeatures` дословно, и это
    /// не копия, а переезд:** список оттуда теперь выводится из этого
    /// перечисления. Копия рядом с оригиналом разошлась бы молча —
    /// оба были бы зелёными, каждый про своё, как разошлись бы два
    /// списка полей у `DeviceLocalFieldTests` и `DogPayloadParityTests`,
    /// если бы второй не брал первый.
    ///
    /// **Трогать эти строки нельзя, не прочитав
    /// `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`, раздел про Pro.** Там
    /// таблицей записано, какое обещание убирали трижды и что должно
    /// появиться в коде, чтобы его вернуть. Короткая версия: обещать
    /// можно только то, у чего есть дорога. «Ссылка ситтера» и «ситтер
    /// со сроком» дороги не имеют — `FamilyMember.accessExpiresAt`
    /// никто не ставит, кроме прогрева схемы и восстановления; продать
    /// это значит получить отказ по 3.1.2, как уже дважды и было.
    var подпись: (значок: String, название: String, пояснение: String) {
        switch self {
        case .secondDog:
            // **«Вкладка „Собака"» — это обещание адреса, которого нет
            // у большинства.** `RootView.swift:132` берёт подпись вкладки
            // как `dog.flatMap(\.nameIfAny) ?? String(localized: "Собака")`:
            // слово «Собака» стоит там только ПОКА кличка не введена,
            // а вводят её первым же шагом онбординга. То есть человек,
            // который видит этот пейволл, почти наверняка видит внизу
            // «Стич» — и ищет «Собаку», которой на экране нет.
            //
            // Кавычки здесь и были дефектом: они читаются как цитата
            // интерфейса, а цитировать можно только НЕИЗМЕННУЮ подпись.
            // Эта меняется от данных, значит цитаты у неё быть не может
            // ни в одной формулировке — лечится не подбором слова,
            // а отказом от цитаты. Описание вкладки РОЛЬЮ верно в обоих
            // случаях, и в том, где кличка есть, и в том, где её нет.
            ("pawprint.circle", "Вторая и следующие собаки",
             "переключатель на вкладке собаки")
        case .familyBeyondTwo:
            ("person.3", "Семья больше двух человек",
             "роли, дежурство, инструкция ситтеру")
        }
    }

    /// Что перестанет работать после отключения подписки.
    ///
    /// Значок берётся из `подпись` — он один у вещи в обоих списках;
    /// название и пояснение свои, потому что покупку называют
    /// возможностью («Семья больше двух человек»), а потерю —
    /// действием, которое станет недоступно («Приглашать третьего»).
    /// Вещь при этом одна и та же: оба списка выводятся из `allCases`.
    ///
    /// **Заведено 28.10.2026, и заведено по находке.** До этого
    /// `SubscriptionStore.lostOnDowngrade` был отдельным списком
    /// рядом с `proFeatures`, который уже выводился отсюда, — то есть
    /// ровно той второй копией, про которую предупреждает комментарий
    /// в голове этого файла. Копия разошлась: первой строкой она
    /// обещала «Матрицу переноса навыка», снятую из Pro 24.10.2026,
    /// а её экраны удалены 28.10 (`82ba1e46`). Человек при отмене
    /// читал, что потеряет то, чего у него нет.
    ///
    /// > **Копия, которую не из чего вывести, расходится молча, и обе
    /// > стороны при этом зелёные.** Снятие случая отсюда теперь
    /// > убирает вещь сразу из пейволла и из списка потерь —
    /// > забыть вторую половину больше нельзя.
    var подписьПотери: (значок: String, название: String, пояснение: String) {
        switch self {
        case .secondDog:
            (подпись.значок, "Вторая и следующие собаки",
             "их записи сохранятся и вернутся при возобновлении")
        case .familyBeyondTwo:
            (подпись.значок, "Приглашать третьего человека",
             "те, кто уже в семье, остаются с прежними правами")
        }
    }
}

/// Сколько даёт бесплатный план.
///
/// Числа **сняты с кода, который был**, а не назначены заново:
/// `показываемые.isEmpty || isPro` — это «одна собака», а
/// `members.count < 2` — «двое человек». Перенос ворот не должен менять
/// поведение, иначе он не перенос, а продуктовое решение, принятое
/// по дороге.
nonisolated enum ProLimit {
    /// Собак у бесплатного плана. Считаются **показываемые**.
    static let dogs = 1

    /// Человек в семье у бесплатного плана, включая себя.
    static let familyMembers = 2
}

/// Вопрос к воротам: вещь плюс ровно та величина, которая ей нужна.
///
/// **Почему случаи со значениями, а не один «скоуп» со всеми
/// счётчиками.** Общий скоуп заставил бы каждое место передавать и
/// собак, и состав семьи — а экран матрицы не знает ни того, ни
/// другого. Значение по умолчанию решало бы за ворота: ноль собак
/// у вещи без счётчика безвреден, а ноль собак у `secondDog`
/// **открывает** вторую собаку бесплатно, и такой промах компилируется.
/// Пример с матрицей снят вместе с самой матрицей 24.10.2026; довод
/// от этого не зависит и остаётся в силе для любой будущей вещи
/// без своего счётчика.
///
/// > **Величина, которой у места нет, не должна иметь значения
/// > по умолчанию: умолчание — это решение, принятое там, где знаний
/// > нет.**
///
/// Здесь спросить нечего лишнего и нечего забыть: у каждого случая
/// свой вход, и пропустить его компилятор не даст.
nonisolated enum ProRequest: Sendable {
    // `skillMatrix` убран 24.10.2026 вместе с обещанием: у ворот
    // не осталось предмета. Перенос навыка открыт всем.
    case secondDog(dogsShown: Int)
    case familyBeyondTwo(familyMembers: Int)

    /// Вторая собака — **считая только показываемых**.
    ///
    /// Это защита входа, а не удобство. 07.10.2026 восемь безымянных
    /// записей сделали `dogs.isEmpty` ложным, и ворота запросили денег
    /// за ПЕРВУЮ настоящую собаку. `dogs.count` и
    /// `dogs.shownToPerson.count` — один тип и разный смысл, то есть
    /// промах проходит проверку типов.
    ///
    /// Там, где ошибка проходит проверку типов, её убирают из входа,
    /// а не из памяти: вью зовёт эту фабрику и фильтр не пишет сама.
    ///
    /// **`@MainActor` здесь, а не снятая изоляция у `shownToPerson`.**
    /// Первая редакция этой фабрики была `nonisolated` и уронила сборку
    /// у семи сессий: фильтр читает свойства `@Model`, а модели
    /// не `Sendable`. Снять изоляцию у фильтра было делом одного слова
    /// — и это обменяло бы красный компилятор на гонку данных, которую
    /// компилятор больше не поймает: первое видно сразу, второе раз
    /// в сто запусков.
    ///
    /// > **Ошибка компилятора — цена, которую просят вперёд.**
    /// > Отказ её платить переносит расход в рантайм, где у него
    /// > не будет ни файла, ни строки, ни воспроизведения.
    ///
    /// Фабрика и так работает с моделями, то есть на главном акторе ей
    /// место по смыслу; `ProGate.isOpen` остаётся чистым и `nonisolated`
    /// — он берёт уже посчитанное число.
    /// **Гость за собак не платит, и это починка 28.10.2026.**
    ///
    /// Дефект был такой: Аня завела свою собаку бесплатно, мама
    /// позвала её в дневник Стича — и у Ани стало две показываемые
    /// собаки, то есть пейвол за собаку, которую она не заводила,
    /// не может удалить и которая исчезнет, если мама отзовёт
    /// приглашение. Брать деньги за чужую вещь нельзя.
    ///
    /// **Различитель взят из того, что уже есть, — схему не трогаем**
    /// (решение Виктории 28.10): `SharedZoneOwner.isGuest` означает
    /// ровно «мы в чужом дневнике», а не похожее на это. Поля
    /// «пришла по приглашению» у `Dog` нет, и заводить его — новая
    /// версия схемы и миграция живых хранилищ.
    ///
    /// Умолчание читается в месте вызова, как у `AppState.permissions`
    /// и `adoptMe(from:гость:)`: гостем человек становится позже,
    /// приняв приглашение в уже открытом приложении, и проверка
    /// в месте чтения это переживает. Параметр — чтобы вход был
    /// у теста, а не только у жизни.
    ///
    /// **Огрубление названо, а не скрыто:** гость с двумя СВОИМИ
    /// собаками тоже не заплатит. Различить своих и чужих без поля
    /// в схеме нечем, а из двух ошибок эта — в пользу человека,
    /// и она обратима: сняли приглашение — ворота вернулись. Обратная
    /// ошибка берёт деньги за чужое и незаметна тому, кто её сделал.
    @MainActor
    static func secondDog(among dogs: [Dog],
                          гость: Bool = SharedZoneOwner.isGuest) -> ProRequest {
        .secondDog(dogsShown: гость ? 0 : dogs.shownToPerson.count)
    }

    /// Семья больше двух — **по составу ОБЩЕГО ДОСТУПА, а не по карточкам
    /// на этом телефоне.**
    ///
    /// # Чем это оплачено (замер 29.10.2026)
    ///
    /// ```
    /// ProGate.isOpen(…)        3   FamilyScreen:199 (.familyBeyondTwo)
    ///                              DogSwitcher:205 · SettingsScreen:373
    /// ShareLink(item: invite)  2   FamilyScreen:573 · SharedDiaryScreen:186
    ///                              ← ни одного ProGate
    /// контроль: ShareLink(item:) в EmergencyScreen — 2, запрос жив
    /// ```
    ///
    /// Единственные ворота семьи стояли на `TGButton("Добавить человека")`,
    /// а он заводит **локальную карточку** `FamilyMember`
    /// (`FamilyScreen:1388`). Настоящий доступ к дневнику выдаёт `CKShare`
    /// через системный лист «Поделиться», и `FamilyMember` по обмену
    /// не ездит с 08.10.2026 (`SharedDiary.swift:78`). Значит
    /// `members.count` у владельца **от вошедшего не растёт никогда**:
    /// бесплатный план пускал в дневник сколько угодно людей, а платить
    /// просил за третье имя в списке, которое никому ничего не открывает.
    ///
    /// > **Ворота стояли на прокси, и прокси не двигался.** Это наш
    /// > класс «сторож на прокси гасится чужим действием», только здесь
    /// > прокси не гас, а никогда и не зажигался.
    ///
    /// # Почему `[УчастникДневника]`, а не `Int`
    ///
    /// Тот же довод, что у `secondDog(among:)` строкой выше:
    /// `members.count` и `участники.count` — **один тип и разный смысл**,
    /// то есть промах между ними проходит проверку типов. Там, где ошибка
    /// компилируется, её убирают из входа: вью отдаёт список, а число
    /// считает фабрика.
    ///
    /// # Ноль здесь значит «не знаю» наравне с «никого» — и потому ОТКРЫВАЕТ
    ///
    /// `FamilyShare.участники()` стоит на `try?` и отдаёт пустой список
    /// и когда делиться ещё не начали, и когда запрос упал (это уже
    /// названо в `SharedDiaryScreen.swift:119`). Различить их здесь
    /// нечем — значит ошибаться надо в сторону человека: пустой состав
    /// ворота **открывает**. Обратная ошибка запирала бы владельца
    /// в собственном дневнике из-за отсутствия сети.
    ///
    /// Гостя здесь нет и не нужно: `потолокГостя` снимает `manageFamily`
    /// безусловно (`FamilyResolver.swift:241`), то есть до этой фабрики
    /// гость не доходит ни одним путём. Параметр `гость:`, как
    /// у `secondDog`, стал бы полем без читателя.
    static func familyBeyondTwo(среди участники: [УчастникДневника]) -> ProRequest {
        .familyBeyondTwo(familyMembers: участники.count)
    }

    /// Какой вещи соответствует вопрос — для подписи и для перебора.
    var feature: ProFeature {
        switch self {
        case .secondDog: .secondDog
        case .familyBeyondTwo: .familyBeyondTwo
        }
    }
}

/// Открыта ли вещь — чистая функция, одна на обе.
nonisolated enum ProGate {
    /// `true` — вещь доступна, пейволл показывать не надо.
    ///
    /// Стоит на `isPro`, а **не** на `entitled` и не на `debugOverride`:
    /// у `isPro` два тела (`Subscriptions.swift:28` под `#if DEBUG`
    /// с отладочным тумблером и `:30` без него), и только он существует
    /// в обеих конфигурациях. Ворота, написанные на `entitled`,
    /// перестали бы слушаться отладочного тумблера, и проверять
    /// «а как у человека без подписки» стало бы нечем.
    static func isOpen(_ request: ProRequest, isPro: Bool) -> Bool {
        if isPro { return true }
        return switch request {
        case .secondDog(let dogsShown): dogsShown < ProLimit.dogs
        case .familyBeyondTwo(let familyMembers): familyMembers < ProLimit.familyMembers
        }
    }

    /// На сколько состав общего доступа **уже** превысил бесплатный предел.
    ///
    /// # Это НЕ то же самое, что закрытые ворота, и путать их дорого
    ///
    /// ```
    /// участников 2   ворота ЗАКРЫТЫ (третьего звать нельзя)   сверх = 0
    /// участников 3   ворота закрыты                           сверх = 1
    /// ```
    ///
    /// Два разных вопроса: «можно ли позвать ещё» и «сколько человек
    /// уже внутри сверх бесплатного». Первый решает, показывать ли
    /// раздачу; второй — сказать ли человеку, что он за пределом.
    ///
    /// # Превышение БЫВАЕТ, и починить его воротами нельзя
    ///
    /// Системный лист «Поделиться» принимает **нескольких получателей
    /// за раз**: ворота на входе в лист ограничивают, когда его открыли,
    /// а не сколько в нём назвали. Значит состав узнаётся ПОСЛЕ, и это
    /// единственный момент, когда правду вообще можно сказать.
    ///
    /// # Что мы при этом НЕ делаем — и это решение, а не недоделка
    ///
    /// Доступ у живого человека **не отнимается**. Ровно это уже решено
    /// в этом проекте 28.09.2026 (`SubscriptionStore.lostOnDowngrade`):
    /// понизить участника за чужую отмену подписки значит, что в дневнике
    /// на семью двое из четверых перестанут отмечать дозы — и узнают
    /// об этом в ту минуту, когда собаке нужна таблетка. Поэтому здесь
    /// только ЧИСЛО: показ скажет словом, а убрать человека владелец
    /// решит сам, поимённо («Кто имеет доступ»).
    ///
    /// С подпиской превышения не бывает по определению — `0`.
    static func сверхПредела(_ участники: [УчастникДневника], isPro: Bool) -> Int {
        guard !isPro else { return 0 }
        return max(0, участники.count - ProLimit.familyMembers)
    }
