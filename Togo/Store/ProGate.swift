import Foundation

/// Что открывает Pro — **одно место на все три вещи**.
///
/// **Чем это оплачено.** До 07.10.2026 правило жило восемью `store.isPro`
/// по вью, и ворот среди них было три (`TrainingScreens:110`,
/// `SettingsScreen:217`, `FamilyScreen:57`), а остальные пять
/// показывали состояние подписки. Места, где перечислены сами три
/// вещи, у ворот не было вовсе: список `SubscriptionStore.proFeatures`
/// существовал **для показа** в пейволле и ключа, по которому ворота
/// могли бы на него опереться, не имел.
///
/// Цена такого устройства измерена в этом же проекте дважды:
///
/// * `SettingsScreen:217` считал безымянные записи за собак, и человек
///   без подписки видел «Добавить вторую собаку» с пейволлом вместо
///   «Добавить собаку» — то есть завести ПЕРВУЮ собаку ему предлагали
///   за деньги. Правило стояло на одной поверхности, и починили его
///   там же;
/// * обещание «ссылка ситтера» трижды уезжало в подпись пейволла
///   без дороги в коде — потому что подпись и ворота жили врознь,
///   и сверить их было нечем.
///
/// > **Пока правило списано по местам применения, «ровно три вещи» —
/// > утверждение, которое нечем проверить.**
///
/// Поэтому здесь перечисление, а не свод `if`-ов: у `ProFeature`
/// закрытый набор случаев, и четвёртая вещь не может появиться
/// в воротах, не появившись в подписи пейволла, — `proFeatures`
/// выводится отсюда.
/// **Порядок случаев — это порядок строк в пейволле**, и он изменён
/// 23.10.2026 под эталонный кадр `17.png` темы «Кино»: там сверху вниз
/// «Вторая собака» · «Семья больше двух» · «Матрица переноса».
/// `allCases` отдаёт случаи в порядке объявления, `proFeatures`
/// выводится из него — значит порядок показа задаётся здесь, а не
/// во вью. Второй копии списка под другой порядок заводить нельзя:
/// две копии разойдутся молча, и обе будут зелёными.
nonisolated enum ProFeature: String, CaseIterable, Sendable {
    /// Вторая и следующие собаки. Бесплатно — одна.
    case secondDog

    /// Семья больше двух человек. Бесплатно — двое.
    case familyBeyondTwo

    /// Матрица переноса навыка. Закрыта целиком.
    case skillMatrix

    // MARK: Подпись

    /// Значок, название и пояснение для пейволла.
    ///
    /// **Строки взяты из `SubscriptionStore.proFeatures` дословно, и это
    /// не копия, а переезд:** список оттуда теперь выводится из этого
    /// перечисления. Копия рядом с оригиналом разошлась бы молча —
    /// оба были бы зелёными, каждый про своё, как разошлись бы два
    /// списка полей у `DeviceLocalFieldTests` и `DogPayloadParityTests`,
    /// если бы второй не брал первый.
    ///
    /// **Трогать эти строки нельзя, не прочитав
    /// `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`, раздел про Pro.** Там
    /// таблицей записано, какое обещание убирали трижды и что должно
    /// появиться в коде, чтобы его вернуть. Короткая версия: обещать
    /// можно только то, у чего есть дорога. «Ссылка ситтера» и «ситтер
    /// со сроком» дороги не имеют — `FamilyMember.accessExpiresAt`
    /// никто не ставит, кроме прогрева схемы и восстановления; продать
    /// это значит получить отказ по 3.1.2, как уже дважды и было.
    var подпись: (значок: String, название: String, пояснение: String) {
        switch self {
        case .skillMatrix:
            ("square.grid.3x3", "Матрица переноса навыка",
             "кто просит × где просят × что вокруг")
        case .secondDog:
            ("pawprint.circle", "Вторая и следующие собаки",
             "переключатель на вкладке «Собака»")
        case .familyBeyondTwo:
            ("person.3", "Семья больше двух человек",
             "роли, дежурство, инструкция ситтеру")
        }
    }
}

/// Сколько даёт бесплатный план.
///
/// Числа **сняты с кода, который был**, а не назначены заново:
/// `показываемые.isEmpty || isPro` — это «одна собака», а
/// `members.count < 2` — «двое человек». Перенос ворот не должен менять
/// поведение, иначе он не перенос, а продуктовое решение, принятое
/// по дороге.
nonisolated enum ProLimit {
    /// Собак у бесплатного плана. Считаются **показываемые**.
    static let dogs = 1

    /// Человек в семье у бесплатного плана, включая себя.
    static let familyMembers = 2
}

/// Вопрос к воротам: вещь плюс ровно та величина, которая ей нужна.
///
/// **Почему случаи со значениями, а не один «скоуп» со всеми
/// счётчиками.** Общий скоуп заставил бы каждое место передавать и
/// собак, и состав семьи — а экран матрицы не знает ни того, ни
/// другого. Значение по умолчанию решало бы за ворота: ноль собак
/// у матрицы безвреден, а ноль собак у `secondDog` **открывает**
/// вторую собаку бесплатно, и такой промах компилируется.
///
/// > **Величина, которой у места нет, не должна иметь значения
/// > по умолчанию: умолчание — это решение, принятое там, где знаний
/// > нет.**
///
/// Здесь спросить нечего лишнего и нечего забыть: у каждого случая
/// свой вход, и пропустить его компилятор не даст.
nonisolated enum ProRequest: Sendable {
    case skillMatrix
    case secondDog(dogsShown: Int)
    case familyBeyondTwo(familyMembers: Int)

    /// Вторая собака — **считая только показываемых**.
    ///
    /// Это защита входа, а не удобство. 07.10.2026 восемь безымянных
    /// записей сделали `dogs.isEmpty` ложным, и ворота запросили денег
    /// за ПЕРВУЮ настоящую собаку. `dogs.count` и
    /// `dogs.shownToPerson.count` — один тип и разный смысл, то есть
    /// промах проходит проверку типов.
    ///
    /// Там, где ошибка проходит проверку типов, её убирают из входа,
    /// а не из памяти: вью зовёт эту фабрику и фильтр не пишет сама.
    ///
    /// **`@MainActor` здесь, а не снятая изоляция у `shownToPerson`.**
    /// Первая редакция этой фабрики была `nonisolated` и уронила сборку
    /// у семи сессий: фильтр читает свойства `@Model`, а модели
    /// не `Sendable`. Снять изоляцию у фильтра было делом одного слова
    /// — и это обменяло бы красный компилятор на гонку данных, которую
    /// компилятор больше не поймает: первое видно сразу, второе раз
    /// в сто запусков.
    ///
    /// > **Ошибка компилятора — цена, которую просят вперёд.**
    /// > Отказ её платить переносит расход в рантайм, где у него
    /// > не будет ни файла, ни строки, ни воспроизведения.
    ///
    /// Фабрика и так работает с моделями, то есть на главном акторе ей
    /// место по смыслу; `ProGate.isOpen` остаётся чистым и `nonisolated`
    /// — он берёт уже посчитанное число.
    @MainActor
    static func secondDog(among dogs: [Dog]) -> ProRequest {
        .secondDog(dogsShown: dogs.shownToPerson.count)
    }

    /// Какой вещи соответствует вопрос — для подписи и для перебора.
    var feature: ProFeature {
        switch self {
        case .skillMatrix: .skillMatrix
        case .secondDog: .secondDog
        case .familyBeyondTwo: .familyBeyondTwo
        }
    }
}

/// Открыта ли вещь — чистая функция, одна на все три.
nonisolated enum ProGate {
    /// `true` — вещь доступна, пейволл показывать не надо.
    ///
    /// Стоит на `isPro`, а **не** на `entitled` и не на `debugOverride`:
    /// у `isPro` два тела (`Subscriptions.swift:28` под `#if DEBUG`
    /// с отладочным тумблером и `:30` без него), и только он существует
    /// в обеих конфигурациях. Ворота, написанные на `entitled`,
    /// перестали бы слушаться отладочного тумблера, и проверять
    /// «а как у человека без подписки» стало бы нечем.
    static func isOpen(_ request: ProRequest, isPro: Bool) -> Bool {
        if isPro { return true }
        return switch request {
        case .skillMatrix: false
        case .secondDog(let dogsShown): dogsShown < ProLimit.dogs
        case .familyBeyondTwo(let familyMembers): familyMembers < ProLimit.familyMembers
        }
    }
}
