/// Планировщик напоминаний.
///
/// До этого весь `NotificationCenterService` был написан и не вызывался
/// ни разу: приложение спрашивало разрешение в онбординге и после этого
/// молчало навсегда. Ни утренней сводки, ни дозы по часам, ни окна
/// натощак — то есть ровно те три вещи, ради которых разрешение и просили.
///
/// Правило из макета зашито здесь: **прерывать человека имеют право только
/// доза, окно натощак и лестница эскалации.** Всё остальное ждёт сводки.
///
/// **Прерываний при этом ЧЕТЫРЕ, и четвёртое — `remindToWatch`** (замер
/// 21.10.2026). «Как он сейчас?» уходит тем же `scheduleDose`, то есть
/// с `interruptionLevel = .timeSensitive` — это прерывание веса дозы,
/// а правило выше называет три. Устарело **правило, а не функция**:
/// возврат к разговору после «подожду» заведён сознательно и объяснён
/// у самого `remindToWatch`. Правило переписано здесь, а не в журнале,
/// потому что сверять его приходит тот, кто правит этот файл.
///
/// # Тихие часы — с 29.10.2026 планировщик их читает
///
/// До этого `Settings.quietHoursStart/End` хранились и не доходили
/// сюда ни одной строкой: тихие часы знали только два места
/// `TodayScreen`. Теперь правило такое, и у каждой строки свой довод:
///
/// ```
/// сводка по уходу      сдвигается на конец тихих часов
/// «Можно кормить»      сдвигается на конец тихих часов — и только
///                      если кормить в тот момент правда можно
///                      (`моментМожноКормить`)
/// доза, t−10/t+30/t+60 НЕ сдвигается и НЕ глушится
/// «Как он сейчас?»     НЕ сдвигается
/// ```
///
/// **Почему доза звонит и в тихие часы.** Доза в 23:00 — это доза
/// в 23:00: её час назначил врач, а не приложение. Сдвинуть напоминание
/// на 07:00 значит промолчать про лекарство до утра, и цена этого
/// молчания медицинская, а цена звонка — разбуженный человек. Человек,
/// поставивший приём на 23:00, этот час выбрал сам. Отсюда и t+30/t+60:
/// лестница существует ровно на случай «не отметили», и ночью этот
/// случай не реже.
///
/// **Почему «Как он сейчас?» не сдвигается.** Его текст говорит «час
/// назад было три эпизода подряд»; сдвинутый на утро, он утверждал бы
/// неправду о времени, а сам вопрос — про возможный звонок врачу.
///
/// Сводка и «Можно кормить» прерывать имеют право меньше всех:
/// первая — это и есть то, что «ждёт», вторая — разрешение, а не
/// запрет, и разрешение в 07:00 так же верно, как в 23:40.
///
/// **Исход постановки с 29.10.2026 читается, а не выбрасывается.**
/// Было три `try? await center.add(request)` — отказ системы
/// не доходил никуда, и человек не узнавал, что напоминания о дозе
/// не будет. Теперь каждый вызов отдаёт `ИсходЗапроса`, его читает
/// `сообщить(_:про:)`, и отказ виден в «Настройки → Журнал действий».
/// Границу этого — чего оно НЕ делает — см. у самой `сообщить`.
///
/// **Текст уведомления с 29.10.2026 идёт через каталог.** Было восемь
/// голых литералов в аргументах `title:`/`body:` — пять названных
/// в задании и три с подстановкой, найденные рядом. Все восемь имели
/// в каталоге ключ с живым переводом на en/fr/kk/uk, и ни один
/// до перевода не доезжал: `scheduleDose(title:body:)` принимает
/// `String`, а не `LocalizedStringKey`, и литерал на месте вызова
/// каталог не спрашивает вовсе. То есть сторож полноты всё это время
/// честно отвечал «переведено» про строку, уходившую русской в пять
/// локалей. Кадром это не ловится: пуш рисуется, когда приложение
/// закрыто. Держит `ТекстУведомленияЧерезКаталогTests`.
///
/// И рядом улика: `NotificationCenterService.Category.escalation`
/// объявлен и **не имеет ни одного читателя** — один `grep` находит
/// только объявление. Это та самая форма, где «поле без читателя»
/// выглядит отсутствующим: канал эскалации назван, а адресации нет.
@MainActor
enum ReminderScheduler {
    /// Напомнить вернуться к наблюдению.
    ///
    /// Отказ от звонка не должен быть тупиком: человек решил подождать,
    /// и приложение обязано вернуться к разговору само.
    static func remindToWatch(at date: Date) async {
        guard await isAllowed() else { return }
        let исход = await NotificationCenterService.scheduleDose(
            id: "watch-\(Int(date.timeIntervalSince1970))",
            at: date,
            title: String(localized: "Как он сейчас?"),
            body: String(localized: "Час назад было три эпизода подряд. Если повторилось — стоит позвонить."),
            собака: nil
        )
        сообщить(исход, про: "watch")
    }

    /// Пересобрать все напоминания заново.
    ///
    /// Дешевле и надёжнее, чем следить за отдельными изменениями: их мало,
    /// а расходятся они молча.
    static func refresh(dog: Dog?, settings: Settings, at now: Date = Date()) async {
        guard await isAllowed() else { return }

        await scheduleBrief(dog: dog, settings: settings, at: now)
        await scheduleDoses(dog: dog, at: now)
        await scheduleFasting(dog: dog, settings: settings, at: now)
    }

    /// Пересобрать напоминания всех собак — без экрана «Сегодня».
    ///
    /// # Зачем, если есть `refresh`
    ///
    /// **Жалоба владельца 29.10.2026: «уведомления срабатывают
    /// ненадёжно».** Замер по дереву: `refresh` звали четыре места,
    /// и все четыре — экраны (`TodayScreen.task`, `DayPlanActions`
    /// дважды, `NeedsSheet`). То есть напоминания вставали, только
    /// когда человек открывал «Сегодня», и ставились при этом **на один
    /// день** — `scheduleDoses` брал только заведённые отметки, а их
    /// `ensureDoses` заводит на сегодня. Не открыл приложение до
    /// полуночи — завтрашняя утренняя доза не звонила вовсе.
    ///
    /// Теперь входов пять, и ни один не требует экрана:
    ///
    /// ```
    /// запуск приложения            TogoApp, .task
    /// возврат на передний план     TogoApp, scenePhase == .active
    /// любое сохранение схемы,      TogoApp, ModelContext.didSave —
    ///   дозы, собаки, дела         в том числе чужая правка по обмену
    /// фоновое обновление iOS       ФоновоеОбновление (BGAppRefreshTask)
    /// экраны, как и раньше         refresh(dog:…)
    /// ```
    ///
    /// Собаки — ВСЕ, а не открытая: доза второй собаки звонит так же,
    /// как первой, а экран «Сегодня» показывает одну. Сводка — одна,
    /// по выбранной собаке, как и в настройках.
    static func refreshAll(context: ModelContext, activeDogID: UUID?,
                           settings: Settings, at now: Date = Date()) async {
        guard await isAllowed() else { return }
        let собаки: [Dog]
        do {
            собаки = try context.fetch(FetchDescriptor<Dog>())
        } catch {
            log.error("Напоминания не пересобраны: собаки не прочитались — \(error.localizedDescription)")
            UsageLog.note(.failure, "reminders-not-refreshed", outcome: .failed)
            return
        }
        await scheduleBrief(dog: AppState.activeDog(from: собаки, выбрана: activeDogID),
                            settings: settings, at: now)
        for собака in собаки {
            await scheduleDoses(dog: собака, at: now)
            await scheduleFasting(dog: собака, settings: settings, at: now)
        }
    }

    /// Касается ли сохранение того, из чего считаются напоминания.
    ///
    /// Читает `userInfo` уведомления `ModelContext.didSave` — те же
    /// ключи, что читает исходящая очередь обмена (`FamilySync`).
    /// Имена типов, а не объекты: удалённую запись в контексте уже
    /// не достать, а имя типа у идентификатора есть всегда.
    ///
    /// `LogEvent` сюда НЕ входит нарочно: запись в ленту случается
    /// десятки раз в день, а напоминаний не меняет — кроме отметки дозы,
    /// которая приходит своим типом `DoseRecord`.
    static func касаетсяНапоминаний(_ userInfo: [AnyHashable: Any]?) -> Bool {
        let типы: Set<String> = ["Dog", "Medication", "DoseRecord", "CareTask", "Prescription"]
        for ключ in ["inserted", "updated", "deleted"] {
            guard let ids = userInfo?[ключ] as? [PersistentIdentifier] else { continue }
            if ids.contains(where: { типы.contains($0.entityName) }) { return true }
        }
        return false
    }

    private static func isAllowed() async -> Bool {
        switch await NotificationCenterService.authorizationStatus() {
        case .authorized, .provisional, .ephemeral: true
        default: false
        }
    }

    // MARK: Куда уходит отказ

    /// Довести исход постановки до человека.
    ///
    /// # Почему журнал действий, а не плашка
    ///
    /// Плашку показывает `AppState.showFailure`, и слой `Store`
    /// достаёт до него ровно одним способом — **принимает ссылку
    /// параметром**, как это делает `EventLog`
    /// (`Togo/Store/EventLog.swift:16`, три вызова `showFailure`).
    /// У `ReminderScheduler` ссылки нет, и завести её, не тронув
    /// места вызова, нельзя: их шесть, и все в `Togo/Features/` —
    /// `TodayScreen:567` и `:661`, `DayPlanActions:224` и `:317`,
    /// `NeedsSheet:387`, `SettingsScreen:625`.
    ///
    /// Параметр `appState: AppState? = nil` был бы **хуже молчания**.
    /// Он выглядит подключённым, компилируется, тесты зелёные —
    /// и не зовётся ниоткуда. Это наш класс «механизм без входа»,
    /// и от рабочего он не отличается ни одним признаком.
    ///
    /// Поэтому исход уходит туда, где вход и читатель уже есть:
    /// **Настройки → «Журнал действий» → «Что чинить»**
    /// (`SettingsScreen:393` ведёт на `UsageLogScreen`; корзину
    /// `failure` собирает `UsageReport.frictionList`, заголовок —
    /// «Приложение не справилось», и в строке видно, чего именно
    /// не вышло и сколько раз).
    ///
    /// # Чего это НЕ делает, и это названо здесь, а не в журнале
    ///
    /// **В момент отказа человека не прерывает ничто.** Он узнает,
    /// когда откроет журнал, — то есть позже, а по замыслу экрана
    /// (`UsageLogScreen`, шапка) и вовсе «через пару недель».
    /// Для дозы это мало, и назвать это починкой нельзя:
    ///
    /// ```
    /// отказ записан            закрыто этой правкой
    /// отказ виден в журнале    закрыто этой правкой
    /// человек прерван сразу    ОТКРЫТО: нужен appState у шести мест
    ///                          вызова, это файлы Togo/Features/
    /// ```
    ///
    /// # Почему `detail` латиницей
    ///
    /// Это опознавательная метка, а не фраза: журнал читают
    /// на пяти языках, и русская строка без перевода легла бы русской
    /// во все пять. Остальные вызовы `UsageLog.note` пишут сюда ровно
    /// такие метки (`kind.rawValue`, `"briefHour"`). Новых строк
    /// интерфейса эта правка не вводит ни одной.
    private static func сообщить(_ исход: NotificationCenterService.ИсходЗапроса,
                                 про что: String) {
        switch исход {
        case .поставлен, .нечегоСтавить:
            return
        case let .отказСистемы(причина):
            log.error("Напоминание «\(что)» не встало: \(причина)")
            UsageLog.note(.failure, "\(что)-not-scheduled", outcome: .failed)
        case let .очередьПолна(ожидает):
            log.error("""
                Очередь уведомлений полна: ждёт \(ожидает) \
                из \(NotificationCenterService.потолокОжидающих), \
                партия «\(что)» влезает не целиком
                """)
            UsageLog.note(.failure, "\(что)-queue-full", outcome: .failed)
        }
    }

    // MARK: Утренняя сводка

    /// Всё повторяющееся — одним сообщением в выбранный час.
    ///
    /// # По запросу на день, а не один повторяющийся — 29.10.2026
    ///
    /// Был один запрос с `repeats: true`, и текст в нём замерзал
    /// в момент последнего открытия: «Когти — сегодня» приходило каждое
    /// утро и после того, как когти подстригли. Повторяющийся запрос
    /// несёт один текст на все дни **по устройству**, поэтому чинится
    /// это не текстом, а формой: на каждый из `горизонтСуток` дней свой
    /// разовый запрос со строками **этого** дня.
    ///
    /// Чего это НЕ гарантирует: текст по-прежнему собран заранее.
    /// Дело, закрытое на другом телефоне, пока этот спит, останется
    /// в сводке до следующей пересборки — а она случается на открытии,
    /// на каждом сохранении (в том числе приехавшем по обмену) и в фоне.
    /// Дальше горизонта сводка не ставится вовсе: не открывали
    /// приложение трое суток и фон не будили — сводка замолкает,
    /// а не врёт.
    ///
    /// Сводка, попавшая в тихие часы, приходит в их конец. Строки
    /// при этом берутся на день, КОГДА она придёт: сдвинутая на утро,
    /// она говорит про утро, а не про вчерашний вечер.
    static func scheduleBrief(dog: Dog?, settings: Settings, at now: Date = Date()) async {
        let calendar = Calendar.current
        let сегодня = calendar.startOfDay(for: now)

        // Снимаем ВСЁ своё прежде постановки: старый повторяющийся
        // `"brief"` (иначе у обновившихся он звонил бы рядом с новыми
        // вечно) и дни горизонта с запасом — час сводки мог уехать,
        // и тогда запрос прошлой раскладки лежит под другим днём.
        var снять = [NotificationCenterService.Category.morningBrief.rawValue]
        for сдвиг in -1...(горизонтСуток + 1) {
            if let день = calendar.date(byAdding: .day, value: сдвиг, to: сегодня) {
                снять.append(idСводки(день, calendar: calendar))
            }
        }
        NotificationCenterService.cancel(ids: снять)

        for сдвиг in 0..<горизонтСуток {
            guard let день = calendar.date(byAdding: .day, value: сдвиг, to: сегодня) else { continue }
            let когда = внеТихихЧасов(
                calendar.date(minuteOfDay: settings.briefHour * 60, on: день),
                начало: settings.quietHoursStart, конец: settings.quietHoursEnd,
                calendar: calendar)
            guard когда > now else { continue }
            let исход = await NotificationCenterService.scheduleMorningBrief(
                id: idСводки(когда, calendar: calendar), at: когда,
                lines: briefLines(dog: dog, наДень: когда, calendar: calendar))
            сообщить(исход, про: "brief")
        }
    }

    /// `brief-20261029` — по дню, когда сводка придёт.
    ///
    /// Латиницей и числом, а не `Fmt`: это идентификатор запроса,
    /// он не показывается человеку и не должен зависеть от языка.
    static func idСводки(_ день: Date, calendar: Calendar = .current) -> String {
        let ч = calendar.dateComponents([.year, .month, .day], from: день)
        return "brief-\((ч.year ?? 0) * 10000 + (ч.month ?? 0) * 100 + (ч.day ?? 0))"
    }

    /// Что попадёт в сводку, которую соберут сейчас и пришлют завтра.
    ///
    /// Прежний вход, и смысл у него прежний: «на завтра от `now`».
    /// Постановка с 29.10.2026 зовёт `briefLines(dog:наДень:calendar:)`
    /// с днём, когда сводка придёт.
    static func briefLines(dog: Dog?, at now: Date = Date()) -> [String] {
        let calendar = Calendar.current
        let tomorrow = calendar.date(byAdding: .day, value: 1, to: now) ?? now
        return briefLines(dog: dog, наДень: tomorrow, calendar: calendar)
    }

    /// Что попадёт в сводку этого дня. Отложенное дважды подсвечивается,
    /// но в тревогу не превращается.
    ///
    /// Параметр назван `tomorrow` внутри по истории: до 29.10.2026 это
    /// был всегда «завтрашний» день от момента сборки.
    static func briefLines(dog: Dog?, наДень tomorrow: Date,
                           calendar: Calendar = .current) -> [String] {
        guard let dog else { return [] }

        // Срок контроля идёт ПЕРВЫМ, а дела — после: сводка обрезается
        // до четырёх строк, и порядок решает, что человек увидит.
        // Груминг, отложенный дважды, переживёт ещё день; окно
        // контроля — это последний день, когда можно сдать анализ.
        //
        // Двумя `let` с явными типами, а не одним выражением через `+`.
        // Первая редакция этой правки склеивала вызов и цепочку
        // `filter → sorted → prefix → map` одним `+`, и это ровно та
        // форма, которую я в этот же вечер мерил в `DuplicateMerge`:
        // 3199 мс типизации на одиннадцати слагаемых. Склейка двух
        // коллекций оператором `+` оставляет компилятору выводить
        // и тип элемента, и перегрузку оператора поверх всей цепочки.
        // Явный тип у каждой половины снимает перебор целиком —
        // а не уменьшает его.
        let контроль: [String] = строкиКонтроля(dog: dog, на: tomorrow, calendar: calendar)
        let дела: [String] = dog.careTasks
            .filter { $0.isDue(on: tomorrow) }
            .sorted { ($0.daysUntilDue(from: tomorrow) ?? 0) < ($1.daysUntilDue(from: tomorrow) ?? 0) }
            .prefix(4)
            .map { task in
                let status = task.statusText(on: tomorrow)
                let snoozed = task.snoozeCount >= 2 ? " · откладывали \(Fmt.times(task.snoozeCount))" : ""
                return "\(task.title) — \(status)\(snoozed)"
            }
        var строки: [String] = контроль
        строки.append(contentsOf: дела)
        return строки
    }

    // MARK: Срок контроля из назначения

    /// Окно контроля в сводке — в день открытия и в последний день.
    ///
    /// **Почему в сводке, а не отдельным пушем, хотя ТЗ говорит
    /// «два напоминания».** Правило макета, зашитое в этом файле,
    /// прямое: прерывать человека имеют право только доза, окно
    /// натощак и лестница эскалации. Срок контроля не из этих трёх.
    /// Завести ему свой пуш значило бы расширить список прерываний
    /// по ходу работы над модулем, а он закрыт решением.
    ///
    /// ТЗ при этом исполнено по существу: **два дня, а не два пуша.**
    /// В день открытия окна сводка говорит «пора на контроль»,
    /// в последний день — «последний день контроля». Это разные
    /// новости, и одним текстом их покрывать нельзя: «можно сдать
    /// до 20-го» и «сегодня последний» — разные действия человека.
    ///
    /// > **Расхождение ТЗ («два напоминания») с правилом прерываний
    /// > («только три вещи») — продуктовый вопрос, а не кодовый.**
    /// > Решено в сторону правила, потому что правило записано
    /// > решением, а «напоминание» в ТЗ не сказано пушем.
    ///
    /// Текст берётся у `ControlWindow.word`, а не пишется здесь:
    /// иначе вторая поверхность — «Здоровье», виджет — напишет своё,
    /// и три формулировки разойдутся молча.
    ///
    /// Чего здесь НЕТ, и это названо: **срок прививки**
    /// (`DogDocument.validUntil`). Поле есть, напоминания нет —
    /// и завести его нельзя, не придумав, за сколько дней напоминать.
    /// Это число не в коде и не в ТЗ: напоминание в день истечения
    /// бесполезно (прививку делают заранее), а любой выбранный запас
    /// был бы придуман за врача — ровно то, из-за чего срок контроля
    /// стал окном, а не датой. Вопрос к Виктории, не к этому файлу.
    static func строкиКонтроля(dog: Dog,
                               на день: Date,
                               calendar: Calendar) -> [String] {
        dog.prescriptions.compactMap { рецепт -> String? in
            guard let назначено = рецепт.prescribedControl,
                  let окно = ControlWindow.window(prescribedAt: рецепт.date,
                                                  назначено,
                                                  calendar: calendar)
            else { return nil }

            let ступень = ControlWindow.stage(окно, now: день, calendar: calendar)
            // Только два дня из всего окна. `.open` в середине окна
            // молчит нарочно: напоминать каждый день две недели —
            // это сторож, который кричит, а такого читать перестанут.
            // `.missed` тоже молчит: напоминание о прошедшем сроке —
            // не напоминание, а упрёк, и о нём говорит экран.
            switch ступень {
            case .lastDay:
                return "\(рецепт.medicationName) — \(ControlWindow.word(ступень))"
            case .open where calendar.isDate(день, inSameDayAs: окно.opens):
                return "\(рецепт.medicationName) — \(ControlWindow.word(ступень))"
            default:
                return nil
            }
        }
    }

    // MARK: Доза по часам

    /// На сколько суток вперёд ставятся доза и сводка: сегодня и ещё два дня.
    ///
    /// **Почему не сутки, как было до 29.10.2026.** Отметки приёма
    /// заводит `ensureDoses` при открытии «Сегодня», и прежняя постановка
    /// шла только по ним — то есть по сегодняшним. Человек, не открывший
    /// приложение до полуночи, утром не получал напоминания о дозе
    /// вовсе. Трое суток — это выходные без приложения в руках.
    ///
    /// **Почему не неделя.** Потолок iOS — 64 ожидающих запроса, а доза
    /// стоит три запроса. Три препарата по три приёма — двадцать семь
    /// в сутки, и трое суток уже упираются в потолок; дальше горизонт
    /// урезается бюджетом (`scheduleDoses`), а не этим числом.
    static let горизонтСуток = 3

    /// Сколько мест под потолком оставлять тому, что ставится ПОСЛЕ доз:
    /// окно натощак и «Как он сейчас?». Сводка ставится раньше доз
    /// и в очереди уже сосчитана.
    static let запасПослеДоз = 2

    /// Один запрос лестницы — то, что будет поставлено.
    struct Ступень: Equatable {
        let id: String
        let когда: Date
        let title: String
        let body: String
    }

    /// Все ступени лестницы на горизонт — по расписанию схемы, а не
    /// по заведённым отметкам. Ближайшие первыми.
    ///
    /// # Почему по расписанию
    ///
    /// Отметок на завтра нет: `ensureDoses` заводит их лениво, на день,
    /// при открытии экрана, и заводить их на трое суток вперёд ради
    /// уведомлений значило бы писать в общий дневник записи, которых
    /// человек не видел. Расписание же известно: `Medication.times`,
    /// тот же час через `Calendar.date(minuteOfDay:on:)`, что берёт
    /// `ensureDoses`.
    ///
    /// # Почему идентификатор не разойдётся с будущей отметкой
    ///
    /// Слот без отметки называется `DoseRecord.устойчивыйID` — ровно
    /// тем id, который отметка получит, когда её заведут. Значит запрос,
    /// поставленный сегодня на завтра, и запрос, поставленный завтра
    /// по заведённой отметке, — **один и тот же запрос** (`add` с тем же
    /// id заменяет), а `cancelDose(отметка)` снимает и то, что стояло
    /// до её рождения. Отметка, если она есть, решает сама: её id (у
    /// отметок до 08.10.2026 он не устойчивый) и её «ждёт ли».
    ///
    /// # Чего здесь НЕТ, и это то же, что у экрана
    ///
    /// `courseEnd` и `startedAt` не спрашиваются: их не спрашивает
    /// и `ensureDoses`, то есть экран покажет дозу в последний день
    /// курса и после него. Напоминание обязано говорить то же, что
    /// экран; расходиться с ним в одну сторону — значит звонить про
    /// дозу, которой на экране нет, или молчать про ту, что есть.
    ///
    /// Вчерашний день в обходе нарочно: доза в 23:30 вчера держит
    /// ступень t+60 в 00:30 сегодня. Прошедшие ступени отсекаются
    /// по одной, а не по дозе — t+30 и t+60 дозы, чей час уже прошёл,
    /// встают, пока доза ждёт отметки.
    static func ступениДоз(dog: Dog, now: Date,
                           calendar: Calendar = .current) -> [Ступень] {
        guard dog.isOnTreatment, dog.deletedAt == nil else { return [] }
        let сегодня = calendar.startOfDay(for: now)
        var итог: [Ступень] = []

        for medication in dog.medications where !medication.isPaused {
            // Без повторов: два одинаковых часа дали бы один id дважды.
            let часы = Array(Set(medication.times)).sorted()
            for сдвиг in -1..<горизонтСуток {
                guard let день = calendar.date(byAdding: .day, value: сдвиг, to: сегодня)
                else { continue }
                for минута in часы {
                    let слот = calendar.date(minuteOfDay: минута, on: день)
                    let отметка = medication.doses.first {
                        calendar.isDate($0.scheduledAt, equalTo: слот, toGranularity: .minute)
                    }
                    // Пропущенная доза уведомлений не заводит — по той же
                    // причине, по которой она не поднимает лестницу
                    // эскалации (`DoseRecord.escalationStage`): пропуск это
                    // решение и запись, а не пустота. Без этой оговорки
                    // человек нажимал «пропустить» и всё равно получал пуш
                    // «Доза 21:30 не отмечена».
                    if let отметка, !отметка.ждётОтметки { continue }
                    let доза = отметка?.id
                        ?? DoseRecord.устойчивыйID(medication: medication.id, scheduledAt: слот)

                    // `title`/`body` — через каталог на месте вызова
                    // (`String(localized:)`, с 29.10.2026). Дальше тип
                    // `String`, и каталог по дороге не спрашивается ни
                    // разу. Держит это `ТекстУведомленияЧерезКаталогTests`.
                    let лестница: [Ступень] = [
                        // За десять минут.
                        Ступень(id: doseID(доза, stage: "t-10"),
                                когда: слот.addingTimeInterval(-10 * 60),
                                title: String(localized: "Через 10 минут доза"),
                                body: String(localized: "\(medication.name) \(medication.doseText) в \(Fmt.clock(слот))")),
                        // Через полчаса — если так и не отметили.
                        Ступень(id: doseID(доза, stage: "t+30"),
                                когда: слот.addingTimeInterval(30 * 60),
                                title: String(localized: "Доза \(Fmt.clock(слот)) не отмечена"),
                                body: String(localized: "Кто-то один — отметьте. Если дали, поправьте время.")),
                        // Через час — запись «пропуск». Не ругаем, предлагаем поправить.
                        Ступень(id: doseID(доза, stage: "t+60"),
                                когда: слот.addingTimeInterval(60 * 60),
                                title: String(localized: "Доза \(Fmt.clock(слот)) пропущена"),
                                body: String(localized: "Отметь в Togo: дали или пропустили.")),
                    ]
                    итог.append(contentsOf: лестница.filter { $0.когда > now })
                }
            }
        }
        return итог.sorted { $0.когда < $1.когда }
    }

    /// Единственное, что имеет право на time-sensitive, плюс эскалация.
    ///
    /// # Потолок 64 считается ЗДЕСЬ, и только здесь
    ///
    /// Доза ставит **три запроса на каждый приём** (`t-10`, `t+30`,
    /// `t+60`). Три препарата по три приёма в сутки — это двадцать семь
    /// запросов в день. Лишнее система **не отбивает**: `add` отвечает
    /// успехом, а в очереди остаются ближайшие 64.
    ///
    /// # Партия урезается С КОНЦА, и только с 29.10.2026
    ///
    /// Пока ставился один день, партию ставили целиком: своя обрезка
    /// по порядку обхода схем отдала бы слот завтрашней дозе и выбросила
    /// сегодняшнюю. Теперь ступени отсортированы по времени
    /// (`ступениДоз`), и обрезка с хвоста совпадает с тем, что сделала
    /// бы система, — только мы при этом знаем, ЧТО выпало. Выпал хвост
    /// третьих суток — это просто короче горизонт, и о нём молчим.
    /// Выпало что-то в ближайшие сутки — вот это и есть «часть
    /// напоминаний до человека не дойдёт», и об этом говорим.
    ///
    /// # Уборка своих запросов
    ///
    /// Запрос, стоящий в очереди за этой собакой (метка `userInfo`,
    /// `NotificationCenterService.ожидающиеДозы`) и не попавший
    /// в новую партию, снимается: час передвинули, схему поставили
    /// на паузу или удалили, дозу отметили на другом телефоне.
    /// Чужую собаку уборка не трогает — у её запросов другая метка.
    ///
    /// Чего этот счёт НЕ знает: снятие
    /// (`removePendingNotificationRequests`) система выполняет
    /// не мгновенно, и очередь на момент замера может быть длиннее
    /// настоящей. Ошибка тогда идёт в сторону ЛИШНЕЙ строки в журнале
    /// и короче горизонта, а не потерянной сегодняшней дозы, — и это
    /// та сторона, в которую ошибаться можно.
    ///
    /// # Дежурство здесь НЕ спрашивается — и это решение
    ///
    /// Карточки семьи (`FamilyMember.isOnDuty`) живут на одном телефоне
    /// и по обмену не ездят (решение 08.10.2026, `SharedDiary.swift:78`).
    /// Телефон дежурного о своём дежурстве не знает, если назначили его
    /// не на нём. Заглушить дозу на «недежурном» телефоне значило бы
    /// заглушить её, не убедившись, что она звонит где-то ещё, — то есть
    /// промолчать про лекарство по местной пометке. Поэтому дозы звонят
    /// на каждом телефоне с разрешением, и подпись в «Семье» говорит
    /// ровно это (`FamilyScreen.подписьДежурства`).
    static func scheduleDoses(dog: Dog?, at now: Date = Date()) async {
        guard let dog else { return }

        // Снятие идёт ПЕРЕД постановкой и до ворот `isOnTreatment`:
        // выключенное лечение — такая же причина снять запрос, как
        // отметка. Иначе ворота возвращают управление раньше уборки,
        // и запросы переживают само лечение. Эта уборка — по отметкам,
        // и она же снимает запросы, поставленные до метки собаки.
        снятьНеждущие(dog)

        // Очередь снимается ДО постановки: иначе в ней окажутся запросы,
        // которые мы сами же и добавили, и переполнение объявлялось бы
        // всегда.
        let ожидают = await NotificationCenterService.ожидающие()
        let прежниеСвои = await NotificationCenterService.ожидающиеДозы(собаки: dog.id)

        let кандидаты = ступениДоз(dog: dog, now: now)
        // Свои прежние в счёт не идут: каждый из них либо заменится
        // тем же id, либо будет снят ниже.
        let план = NotificationCenterService.планПартии(
            ожидают: ожидают.subtracting(прежниеСвои),
            ставим: кандидаты.map(\.id),
            потолок: NotificationCenterService.потолокОжидающих - запасПослеДоз)
        let влезает = max(0, кандидаты.count - план.лишних)
        let ставим = Array(кандидаты.prefix(влезает))
        let идентификаторы = Set(ставим.map(\.id))

        let устаревшие = прежниеСвои.subtracting(идентификаторы)
        if !устаревшие.isEmpty {
            NotificationCenterService.cancel(ids: Array(устаревшие))
        }

        // Одна дверь на все ступени: иначе исход читался бы в трёх
        // местах, и забыть его в одном из них ничто бы не помешало.
        for ступень in ставим {
            let исход = await NotificationCenterService.scheduleDose(
                id: ступень.id, at: ступень.когда,
                title: ступень.title, body: ступень.body,
                собака: dog.id)
            сообщить(исход, про: "dose")
        }

        // Переполнение считается ПОСЛЕ партии, но по очереди,
        // снятой ДО неё: это единственный способ узнать о нём вообще.
        // Ни кода возврата, ни исключения у потерянного запроса нет —
        // `add` отвечает успехом и на шестьдесят пятый.
        if let первыйВыпавший = кандидаты.dropFirst(влезает).first,
           первыйВыпавший.когда < now.addingTimeInterval(24 * 3600) {
            сообщить(.очередьПолна(ожидает: план.ожидает), про: "dose")
        }
    }

    /// Снять напоминания по дозе: её отметили или отменили.
    static func cancelDose(_ dose: DoseRecord) {
        cancelDose(дозаID: dose.id)
    }

    /// То же по одному идентификатору — когда живой модели под рукой нет.
    ///
    /// **Заведено 29.10.2026 для приёма чужой страницы.** Страница
    /// обмена живёт в своём контексте и выбрасывается вместе с ним
    /// (`SharedDiaryInbox.открытаяСтраница`); вынести из неё наружу
    /// живую `DoseRecord` значило бы отдать приложению модель, которая
    /// переживёт свой контекст. А снимающему запрос от дозы нужен
    /// ровно `id` — форма строки одна на оба входа.
    ///
    /// Метка отдельная (`дозаID:`), а не вторая перегрузка без ярлыка:
    /// `FamilySync` берёт эту функцию **ссылкой**, а ссылка на имя
    /// с двумя безъярлычными перегрузками разрешается по ожидаемому
    /// типу, то есть молча поменяла бы смысл при правке типа поля.
    static func cancelDose(дозаID id: UUID) {
        NotificationCenterService.cancel(ids: ["t-10", "t+30", "t+60"].map { doseID(id, stage: $0) })
    }

    /// Снять запросы у доз, которые больше не ждут отметки.
    ///
    /// **Замер 14.10.2026: `cancelDose` во всём проекте звали из одного
    /// места — `DayPlanActions:286`, то есть своей рукой.** Значит
    /// снять запрос мог только тот человек, который и отмечал дозу.
    /// Мама отмечает у себя — у Виктории телефон продолжает звонить
    /// «Доза 21:30 не отмечена» и через час «пропущена».
    ///
    /// Почему починка здесь, а не на приёме чужой отметки. Приём живёт
    /// в `TogoShared/Sync/`, а `TogoShared` синхронизированной группой
    /// входит **в оба таргета** — `Togo` и `TogoWidgetsExtension`,
    /// исключений членства в `project.pbxproj` ноль. `ReminderScheduler`
    /// лежит в `Togo/Store/`, то есть только в приложении: вызов оттуда
    /// не собрался бы в расширении. Это не стиль, это замер.
    ///
    /// И ось вышла лучше заказанной. Событие «приехала чужая отметка» —
    /// один источник из нескольких; **состояние «доза больше не ждёт»**
    /// покрывает их все разом: чужую отметку, восстановление из архива,
    /// отмену схемы, паузу, выключенное лечение. Этого списка никто
    /// не писал — он следует из условия.
    ///
    /// > Постановка уже умеет пропускать то, что не ждёт
    /// > (`scheduleDoses:166`). Пропустить — не то же, что снять:
    /// > пропуск оставляет в очереди запрос, поставленный прошлый раз.
    ///
    /// Снимаем по **всем** препаратам, включая поставленные на паузу
    /// и УДАЛЁННЫЕ: цикл постановки их отфильтровывает, и значит их
    /// запросы иначе не снял бы никто.
    ///
    /// # Почему здесь `*Storage`, а не обёртки — 26.10.2026
    ///
    /// С этого дня `Dog.medications` и `Medication.doses` отсеивают
    /// надгробия (`Medication.deletedAt`), чтобы удалённое не попадало
    /// человеку на экран. Эта функция — **единственное место, которому
    /// удалённое обязано быть видно**, и читать её через обёртки нельзя:
    ///
    /// ```
    /// через обёртки   схема с надгробием в цикл НЕ ПОПАДАЕТ
    ///                 → её дозы не попадают в `снимаем`
    ///                 → cancel их не видит
    ///                 → запросы t−10 / t+30 / t+60 живут
    ///                 → человек удалил лечение и получает
    ///                   «Доза 21:30 не отмечена» по тому, чего нет
    /// ```
    ///
    /// То есть фильтр показа без этой строки заводит **тот же дефект,
    /// ради которого надгробия и сделаны**, только с другого конца
    /// и в сторону звонка про лекарство. Пара неразделима: либо обе
    /// правки, либо ни одной.
    ///
    /// Соблюдать это правило заставляет не память, а шапка выше: она
    /// уже говорила «по всем препаратам», и обёртка сделала бы её
    /// ложной в момент коммита.
    private static func снятьНеждущие(_ dog: Dog) {
        var снимаем: [String] = []
        let лечениеИдёт = dog.isOnTreatment
        for medication in (dog.medicationsStorage ?? []) {
            let схемаЖдёт = лечениеИдёт && !medication.isPaused
                && medication.deletedAt == nil
            for dose in (medication.dosesStorage ?? []) {
                // Определение «доза ждёт» переехало в модель
                // (`DoseRecord.ждётОтметки`): его спрашивает ещё и приём
                // чужой отметки в `FamilySync.apply`, а два разбора
                // одного правила расходятся молча.
                guard !(схемаЖдёт && dose.ждётОтметки) else { continue }
                снимаем.append(doseID(dose, stage: "t-10"))
                снимаем.append(doseID(dose, stage: "t+30"))
                снимаем.append(doseID(dose, stage: "t+60"))
            }
        }
        guard !снимаем.isEmpty else { return }
        NotificationCenterService.cancel(ids: снимаем)
    }

    private static func doseID(_ dose: DoseRecord, stage: String) -> String {
        doseID(dose.id, stage: stage)
    }

    /// Тот же id по одному идентификатору дозы — для слота, у которого
    /// отметки ещё нет (`ступениДоз`). Форма строки одна на оба входа.
    private static func doseID(_ id: UUID, stage: String) -> String {
        "dose-\(id.uuidString)-\(stage)"
    }

    // MARK: Окно натощак

    /// Не ошибка, а «подожди»: одно уведомление на момент, когда кормить
    /// снова можно.
    ///
    /// # Правило — то же, что у экрана, с 29.10.2026
    ///
    /// Было `DoseScheduler.fastingEnds`: оно знает только окно ПОСЛЕ
    /// отметки приёма. Экран, виджет и живая активность спрашивают
    /// `FeedingGate`, у которого окна два — после дозы и ДО неё.
    /// Расхождение было не косметическим: доза в 08:00 с окном «до»
    /// в час, отмечена в 06:00 с окном «после» на час — уведомление
    /// «Можно кормить» приходило в 07:00, а экран в ту же минуту
    /// говорил «не кормить до 08:00». Пуш разрешал ровно то, что
    /// запрещал экран.
    ///
    /// Теперь момент берёт `моментМожноКормить`, и он спрашивает
    /// `FeedingGate` **о самом моменте доставки**. Разойтись с экраном
    /// нельзя по устройству: ответ в момент звонка — это ответ экрана
    /// в ту же минуту.
    ///
    /// Идентификатор называет собаку (`fasting-<собака>-<время>`): иначе
    /// снять устаревший запрос — дозу отметили обратно, окно сдвинулось —
    /// было нечем, и он звонил по окну, которого больше нет. Запросы
    /// прежней формы (`fasting-<время>`) снимаются здесь же: они
    /// посчитаны старым правилом.
    static func scheduleFasting(dog: Dog?, settings: Settings, at now: Date = Date()) async {
        guard let dog else { return }
        let префикс = "fasting-\(dog.id.uuidString)-"
        let когда: Date? = dog.isOnTreatment && dog.deletedAt == nil
            ? моментМожноКормить(лекарства: dog.medications, now: now,
                                 начало: settings.quietHoursStart,
                                 конец: settings.quietHoursEnd)
            : nil
        let id = когда.map { префикс + String(Int($0.timeIntervalSince1970)) }

        let прежние = await NotificationCenterService.ожидающие().filter { стоит in
            guard стоит != id else { return false }
            if стоит.hasPrefix(префикс) { return true }
            // Прежняя форма: `fasting-1761730000` — число сразу за дефисом.
            return стоит.hasPrefix("fasting-")
                && Int(стоит.dropFirst("fasting-".count)) != nil
        }
        if !прежние.isEmpty {
            NotificationCenterService.cancel(ids: Array(прежние))
        }

        guard let когда, let id else { return }
        let исход = await NotificationCenterService.scheduleFastingEnd(
            id: id,
            at: когда,
            dogName: dog.displayName
        )
        сообщить(исход, про: "fasting")
    }

    /// Когда «Можно кормить» будет правдой — или ничего.
    ///
    /// Ответ есть, только если кормить нельзя СЕЙЧАС из-за окна после
    /// дозы: тогда момент известен — конец окна. Если нельзя из-за окна
    /// ДО дозы, момента нет: кормить станет можно после того, как дозу
    /// дадут и пройдёт её окно «после», а когда дадут — не знает никто.
    /// Звонить «можно кормить» в час дозы значило бы разрешить еду
    /// ровно тогда, когда таблетка ещё не дана.
    ///
    /// Каждый найденный момент проверяется тем же `FeedingGate`:
    /// у двух препаратов окна кончаются в разное время, и конец первого
    /// может упереться во второе — тогда смотрим конец второго. Четыре
    /// шага — больше препаратов натощак одновременно не бывает в жизни;
    /// не нашлось за четыре — молчим, а не угадываем.
    ///
    /// Тихие часы сдвигают момент на их конец, и сдвинутый момент
    /// проверяется заново: в 07:00 может уже открыться окно «до»
    /// утренней дозы, и тогда «можно кормить» в 07:00 — неправда.
    /// Такой звонок не ставится вовсе.
    static func моментМожноКормить(лекарства: [Medication], now: Date,
                                   начало: Int, конец: Int,
                                   calendar: Calendar = .current) -> Date? {
        guard var блок = FeedingGate.block(for: лекарства, now: now, calendar: calendar)
        else { return nil }
        for _ in 0..<4 {
            guard case .after = блок else { return nil }
            let когда = внеТихихЧасов(блок.freeAt, начало: начало, конец: конец,
                                      calendar: calendar)
            guard let дальше = FeedingGate.block(for: лекарства, now: когда, calendar: calendar)
            else { return когда }
            блок = дальше
        }
        return nil
    }

    // MARK: Тихие часы

    /// Первый момент не раньше данного, который не попадает в тихие часы.
    ///
    /// Правило «тихий ли час» — `Settings.тихийЛиЧас`, то же, что у
    /// экрана «Сегодня»; здесь только «куда сдвинуть». Сдвиг — на конец
    /// тихих часов, ровно в его час: `23 → 7` и 23:40 дают 07:00
    /// следующего дня, 05:30 — 07:00 того же.
    ///
    /// Зовут это сводка и «Можно кормить». Дозу — нет; почему, записано
    /// в голове файла.
    static func внеТихихЧасов(_ момент: Date, начало: Int, конец: Int,
                              calendar: Calendar = .current) -> Date {
        let час = calendar.component(.hour, from: момент)
        guard Settings.тихийЛиЧас(час, начало: начало, конец: конец) else { return момент }
        let деньМомента = calendar.startOfDay(for: момент)
        // Конец тихих часов — в тот же день, если они не переходят
        // через полночь или момент уже после полуночи; иначе — завтра.
        let деньКонца = (начало < конец || час < конец)
            ? деньМомента
            : (calendar.date(byAdding: .day, value: 1, to: деньМомента) ?? деньМомента)
        return calendar.date(minuteOfDay: конец * 60, on: деньКонца)
    }
