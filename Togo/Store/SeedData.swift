    #if DEBUG
    /// Минута утренней дозы, от которой считаются часы забора.
    ///
    /// Своим числом, а не `8 * 60` на месте, чтобы предусловие
    /// и сами точки спорили об одной величине, а не о двух копиях.
    static let демоТ4УтренняяДоза = 8 * 60

    /// Демо-набор Т4 — **четыре точки с эталонного кадра 14**.
    ///
    /// # ЭТО ДЕМО-ЗНАЧЕНИЯ ПРОТОТИПА, А НЕ ДАННЫЕ СТИЧА
    ///
    /// Числа заданы дизайном 23.10.2026 (`Дизайн/редизайн-ios28/
    /// ОТВЕТЫ-круг-2.md`, пункт 10, коммит `816a96a`) ровно затем, чтобы
    /// кадр приёмки сверялся с `Дизайн/эталонные-кадры/ios28-кино-22.10/
    /// screenshots/14.png` **один к одному**. В настоящей карте Стича
    /// Т4 другой — там нмоль/л идут десятками (см. `LabSampleTiming`:
    /// «Т4 10,3 · Т4 16,7»), и спутать одно с другим стоило бы врачу
    /// времени. Через месяц эти четыре строки будут выглядеть историей
    /// болезни, поэтому сказано здесь, а не только в наряде.
    ///
    /// # Зачем он вообще
    ///
    /// Ни один сценарий не заводит `LabResult` (замер 08.10.2026,
    /// повторён 23.10) — значит экран «Анализы» **нельзя привести
    /// в состояние с кадра**, и кадр `14-анализы` снимался на пустом
    /// экране. Это «состояние недостижимо», а не «кадр не снят»:
    /// первое лечится входом, второе взглядом.
    ///
    /// # Чего здесь НЕ подставлено, и это главное
    ///
    /// ```
    /// май, август   время забора ПУСТОЕ — так задал дизайн
    /// лаборатория   пусто: дизайн её не называл
    /// номер бланка  пусто: дизайн его не называл
    /// ```
    ///
    /// Две точки из четырёх без времени стоят **нарочно**: красная
    /// линия проекта — «не подставлять там, где подстановка станет
    /// утверждением человека», и `LabSampleTiming` отличает
    /// «не указано» от «лечения нет» отдельным случаем ровно для этого.
    /// Экран обязан показывать оба случая разом, иначе ветку
    /// `.unknownDuringTreatment` не видел бы никто.
    ///
    /// Лабораторию и номер не выдумываю по той же причине: кадр
    /// сверяется один к одному, и всякое моё слово в нём прочтётся
    /// как слово дизайна.
    ///
    /// # Часы от дозы здесь НЕ ХРАНЯТСЯ — они считаются
    ///
    /// У `LabResult` поля «часов от дозы» нет и быть не должно: счёт
    /// живёт в `DoseScheduler.sampleTiming` и берёт расписание схемы.
    /// Поэтому время забора поставлено так, чтобы счёт дал числа кадра
    /// при утренней дозе в 08:00:
    ///
    /// ```
    /// март    забор 11:00   → 3 ч от дозы   маркер ● (≤ 4 ч)
    /// май     времени нет   → «время забора не указано»   ○
    /// август  времени нет   → «время забора не указано»   ○
    /// октябрь забор 13:00   → 5 ч от дозы   маркер ■ (4–8 ч)
    /// ```
    ///
    /// Расписания своего заготовка не заводит и берёт чужое — отсюда
    /// предусловие ниже. Завести второй левотироксин рядом с янтарным
    /// значило бы получить две схемы у одной собаки и часы, посчитанные
    /// неизвестно по какой.
    ///
    /// # Даты АБСОЛЮТНЫЕ, и это обратное решение к `добавитьЯнтарь`
    ///
    /// У янтаря времена считаются от «сейчас», потому что его предмет —
    /// открытое окно натощак, и абсолютный час сделал бы кадр зелёным
    /// по расписанию. Здесь предмет другой: **подписи месяцев
    /// на кадре** — «мар · май · авг · окт». Относительные даты уехали
    /// бы с кадра через месяц, а год на экране не печатается нигде
    /// (`шапкаПоказателя` берёт `.month(.abbreviated)`, заголовок
    /// бланка — `Fmt.shortDay`), поэтому фиксированные даты сверяются
    /// с кадром и в будущем году.
    ///
    /// > **Правило «считать от сейчас» привязано к предмету замера,
    /// > а не к файлу.** Перенести его сюда значило бы сломать ровно то,
    /// > ради чего заготовка заведена.
    @MainActor
    static func добавитьДемоТ4(to dog: Dog, context: ModelContext) {
        // Предусловие, а не тихая подстановка: без активной схемы
        // с дозой в 08:00 `DoseScheduler.sampleTiming` ответит
        // `.noTreatment`, подписей «3 ч» и «не указано» не будет вовсе,
        // и кадр разойдётся с эталоном МОЛЧА — четыре числа на месте,
        // а строки под ними другие. Громкий отказ дешевле такого кадра.
        let схемы = dog.medications.filter { !$0.isPaused }
        guard схемы.contains(where: { $0.times.contains(демоТ4УтренняяДоза) }) else {
            preconditionFailure("""
                -ДемоТ4 просит активную схему с дозой в 08:00, а у собаки \
                её нет (непаузных схем \(схемы.count)). Заготовка кладётся \
                ПОВЕРХ сценария с лечением: `-Сценарий amber -ДемоТ4`. \
                Без расписания часы от дозы не посчитать, и кадр разойдётся \
                с эталоном 14.png на подписях, а не на числах.
                """)
        }

        func дата(месяц: Int, день: Int, час: Int) -> Date {
            var части = DateComponents()
            части.year = 2026
            части.month = месяц
            части.day = день
            части.hour = час
            guard let момент = Calendar.current.date(from: части) else {
                preconditionFailure("демо-Т4: календарь не собрал \(день).\(месяц).2026 \(час):00")
            }
            return момент
        }

        /// Одна точка. `время` пустое — значит забор не записан,
        /// и подставлять его нечем и незачем.
        func точка(месяц: Int, день: Int, часЗабора: Int?,
                   значение: Double, доза: String) -> LabResult {
            let анализ = LabResult(sampledOn: дата(месяц: месяц, день: день,
                                                   час: часЗабора ?? 12),
                                   indicator: "Т4 общий",
                                   section: "гормоны")
            анализ.sampledAt = часЗабора.map { дата(месяц: месяц, день: день, час: $0) }
            анализ.value = значение
            анализ.unit = "нмоль/л"
            // Норма 1,0–4,5 нмоль/л — с кадра 14 и из ответа дизайна.
            анализ.referenceLow = 1.0
            анализ.referenceHigh = 4.5
            // Доза стоит в заметке, потому что поля под неё у `LabResult`
            // нет, а на кадре 14 она у каждой строки есть. Заводить поле
            // ради заготовки нельзя: это форма схемы, её не меняют без
            // спроса. Расхождение названо в отчёте, а не замазано.
            анализ.note = "доза \(доза)"
            анализ.dog = dog
            return анализ
        }

        // Порядок вставки — по возрастанию даты; экран сортирует сам,
        // но так видно, что «↑ с 2,9» в шапке берётся из августа.
        [
            точка(месяц: 3, день: 12, часЗабора: 11, значение: 1.8, доза: "0,05 мг"),
            точка(месяц: 5, день: 14, часЗабора: nil, значение: 2.6, доза: "0,1 мг"),
            точка(месяц: 8, день: 20, часЗабора: nil, значение: 2.9, доза: "0,1 мг"),
            точка(месяц: 10, день: 9, часЗабора: 13, значение: 3.1, доза: "0,1 мг"),
        ].forEach(context.insert)
    }
    #endif
