    private static let calendarNow = Calendar.current

    /// Что лежит в демо-базе UI-тестов.
    ///
    /// Заведено 24.09.2026 ради одного состояния, которое **нечем было
    /// снять**: выходов нет дольше суток, а записи за сегодня есть.
    /// Именно его прислала кадром мама — шапка «Записей нет с 22 сент.»
    /// стояла над едой в 15:23. Демо-набор сюда не попадал никогда:
    /// в нём два выхода за сегодня, и ветка тишины не рисуется вовсе.
    ///
    /// Правило проекта: прежде чем проверять поверхность, проверь, что
    /// её МОЖНО проверить. Непроверяемое лечится входом, а не взглядом.
    enum Scenario: String {
        /// Обычный день: два выхода и завтрак.
        case today
        /// Выходов нет двое суток, еда за сегодня записана.
        case silence
        /// Дневник вели четыре дня и забросили восемнадцать дней назад.
        ///
        /// Заведён 05.10.2026 ради ступени, которую **не видел глазами
        /// никто ни на одной поверхности** — `.unknown(.silence)`
        /// у вердикта и «отметок мочи нет с …» на виджете. Починка
        /// 28.09 сняла оттуда «Не писал 434 ч. Это дольше, чем он
        /// когда-либо терпел», и проверена она была только арифметикой.
        ///
        /// **Почему отдельный сценарий, а не дни в `silence`.** Казалось
        /// бы, `silence` уже годится: выход там позавчера, `outcome`
        /// у него `.both`, а `.both` считается мочой
        /// (`Diary.urineEvents`) — то есть `signals.urineSilence`
        /// срабатывает. Но вердикта на экране не будет: событий
        /// в `silence` два, `daysOfData` даёт 3, `minimumDaysOfData`
        /// равен 4, и `guard` про нехватку данных стоит ВЫШЕ тишины.
        /// Экран честно отвечает «записей всего за 3 дня».
        ///
        /// Дописать дни в `silence` значило бы сдвинуть вердикт
        /// под живым UI-тестом `ТишинаДольшеСуток`, который снимает
        /// там шапку героя. Поэтому миры разные.
        case urineSilence

        /// Три смысла янтаря разом — и ни один из них до 05.10.2026
        /// не был достижим ни одним сценарием.
        ///
        /// **Как это нашлось.** togo-5a снял все 12 кадров (`rc` 0,
        /// `TEST SUCCEEDED`, 12 выполнено) и искал янтарь `#F7C75F`
        /// с допуском 20: **ноль попаданий на двенадцати кадрах**. Ноль
        /// из двенадцати — край диапазона, то есть симптом инструмента,
        /// пока не доказано обратное. Он это и проверил той же меркой,
        /// сменив только цель: лайм нашёлся на 10 кадрах из 12, от 5 896
        /// до 280 856 пикселей. Значит мерка работает, а янтаря нет
        /// в мире.
        ///
        /// Причина была в данных, не в навигации:
        ///
        /// - препарата с окном натощак в демо не было вовсе;
        /// - `ProcedureSkill` заводились без статуса, то есть
        ///   в `.notStarted`, а янтарь у `.learning`;
        /// - отметок с `MarkAccuracy.almost` не было ни одной.
        ///
        /// Виктория отдельным решением оставила янтарю все три смысла
        /// против требования хендоффа «янтарь только натощак» — то есть
        /// в коде защищено поведение, которого **никто ни разу
        /// не видел**. Это ровно тот класс, что карточка Live Activity,
        /// которую нельзя было построить вне живой активности: «состояние
        /// недостижимо, кадра нет» лечится входом, а «кадр не снят» —
        /// взглядом, и путать их дорого.
        ///
        /// Три состояния живут на разных экранах нарочно: «Сегодня»,
        /// «Уход» и дрессировка. На одном они столкнулись бы, а правило
        /// хендоффа «не больше одного мотива на экран» и здравый смысл
        /// требуют проверять их по отдельности.
        case amber

        /// Восемь пустых собак рядом с настоящей — состояние из отзыва
        /// TestFlight 06.10.2026 на сборке 271 («много пустых собак»).
        ///
        /// **Это построенное состояние, а не воспроизведённое.** Механизм,
        /// которым пустые собаки заводятся у человека, на 07.10 не найден;
        /// сценарий существует затем, чтобы снять кадр списка и кадр дороги
        /// наружу — то есть ответить, что человек ВИДИТ и может ли он это
        /// убрать. На вопрос «откуда они берутся» он не отвечает и отвечать
        /// не должен: построить состояние руками и воспроизвести путь —
        /// разные утверждения, и путать их дороже, чем не иметь сценария.
        case emptyDogs

        /// Пустое хранилище: ни собаки, ни участников, ни дел.
        ///
        /// **Единственный сценарий, который ничего не строит, и это
        /// его смысл.** Онбординг показывает настоящие шаги только там,
        /// где собак нет вовсе: `OnboardingFlow.isReplay` смотрит
        /// ровно на `dogs.isEmpty`, и при живой собаке три шага из шести
        /// подменяются справкой, а поток кончается на третьем экране.
        ///
        /// Соседний `emptyDogs` для этого не годится и выглядит
        /// подходящим по имени: там живая собака плюс восемь пустых,
        /// то есть `isReplay` истинен.
        case onboarding

        /// У ЖИВОЙ собаки стёрта кличка, всё остальное на месте.
        ///
        /// Вторая половина того же дефекта, замер `togo-05`: пустой снимок
        /// с поздним `changedAt` побеждает в слиянии и затирает кличку
        /// настоящей собаки. Отличие от `emptyDogs` принципиальное —
        /// там восемь лишних строк, которые можно не замечать, здесь
        /// **пропадает имя собаки, у которой весь дневник**.
        ///
        /// Вес оставлен настоящий (4,1) нарочно: так на кадре видно,
        /// что запись не пустая, а именно обезличенная.
        case wipedName

        // MARK: Три режима плаката, недостижимые до 07.10.2026
        //
        // Заведены под приёмку плаката кадром. **Это не полнота ради
        // полноты:** у плаката пять режимов, экран показывает ровно
        // тот, который сегодня, и до этих трёх сценариев посмотреть
        // на них было нечем — поверхность была НЕПРОВЕРЯЕМОЙ,
        // а не непроверенной.
        //
        // Существующие шесть не трогал: под ними живёт чужая приёмка,
        // и наполнение сценария — это чужой стенд, а не наши данные.
        // Про `urineSilence` это прямо записано выше, и повторять
        // ту же ошибку в обратную сторону незачем.

        /// Первый день: собака заведена, записей НЕТ ни одной.
        ///
        /// Режим плаката `quiet` — нейтральный блок. Условие на экране
        /// — `rhythm.days == 0`, то есть ритма нет **вовсе**.
        ///
        /// **Почему не `emptyDogs`, как я думал сначала.** Тот делит
        /// события с `today` (один `case` на четыре сценария), и кадр
        /// 07.10 показал у обоих один и тот же индиго: два сценария,
        /// один режим. Проверка «подложки разных режимов отличаются»
        /// при этом честно покраснела — ждали разного от одинакового.
        case firstDay

        /// Окно натощак открыто, и доз **не просрочено ни одной**.
        ///
        /// Режим плаката `fasting` — тёмный янтарь.
        ///
        /// **Почему нельзя было взять `amber`, хотя окно там есть.**
        /// `PosterMode.mode` проверяет `isDoseDue` РАНЬШЕ `isFasting`,
        /// и у `amber` висит неотмеченная доза 08:00 — на кадре она
        /// видна плашкой «Доза 08:00 не отмечена». Режим выходит
        /// `dose`, и это документированное правило, а не дефект:
        /// «натощак ВЕДЁТ к дозе, и когда час наступил, окно уже
        /// не главное».
        ///
        /// > **Состояние бывает недостижимо не из-за отсутствия
        /// > данных, а из-за ПОРЯДКА проверок.** Знать это важнее,
        /// > чем сам пропуск: сценарий, написанный без этого знания,
        /// > дал бы третий `dose` и выглядел бы рабочим.
        ///
        /// Поэтому здесь доза отмечена данной — окно считается
        /// от ОТМЕТКИ, — а следующая назначена на будущее.
        case fastingOnly

        /// Доза просрочена и не отмечена — лист `MissedDoseSheet`.
        ///
        /// **Заведён 08.10.2026, потому что дороги к этому листу
        /// не было ни одной.** Лист предлагает три выхода после
        /// пропуска, и его текст обещал «следующая доза СДВИНЕТСЯ
        /// на 22:40» — а расписание не сдвигается ничем, кроме явной
        /// смены схемы. Человек прочёл бы это и **не дал дозу в 21:00,
        /// когда она стоит**. Текст переписан; кадр нужен, чтобы это
        /// увидеть глазом, а не поверить стражу.
        ///
        /// **Почему не годился `amber`, где схема уже есть.** У него
        /// часы `[8:00, 20:00]`, то есть «просрочено» наступает только
        /// после 09:00 и до 20:00. Прогон в 08:30 дал бы зелёное
        /// при отсутствующем листе — тест зеленел бы по времени суток,
        /// а не по коду.
        ///
        /// Здесь часы считаются ОТ `now`: первый слот — три часа назад,
        /// второй — через девять часов. Окно `MissedDoseAdvisor` равно
        /// часу, так что три часа просрочки не зависят ни от часового
        /// пояса, ни от минуты запуска. Два слота нужны затем, что
        /// `evaluate` считает «сдвиг» только при `times.count > 1`, —
        /// а обещание сдвига и есть предмет кадра.
        ///
        /// > **Граница, которую этот сценарий закрыть НЕ может:**
        /// > с 00:00 до ~01:10 по местному времени в сутках нет минуты,
        /// > отстоящей на час с лишним назад, — план дня строится
        /// > на календарный день. В этот час лист не покажется,
        /// > и это свойство суток, а не дефект. Тест говорит об этом
        /// > прямо, вместо того чтобы молча пройти.
        case missedDose

        /// Три рвоты за три часа — порог тревоги достигнут.
        ///
        /// Режим плаката `alarm` — тёмный терракот.
        ///
        /// **Имя сценария называет то, что он строит, а не то, что
        /// я сначала задумал.** Первая редакция звалась `bloodAlarm`:
        /// «кровь» — первое, что приходит в голову со словом тревога.
        /// Замер `AlarmThreshold:36-45` показал другое — порог считает
        /// `kind == .incident`, группирует по `incidentKind` и требует
        /// **три эпизода одного вида за шесть часов**. Крови он
        /// не знает вовсе.
        ///
        /// > Имя сценария — такое же утверждение о поведении, как имя
        /// > теста. `bloodAlarm`, строящий три рвоты, врал бы с первого
        /// > дня и грепом искался бы не тем, кому нужен.
        case vomitAlarm
    }

    @MainActor
