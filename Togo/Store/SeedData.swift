    /// Завести заготовки навыков, если их нет ни одной.
    ///
    /// # Почему здесь, а не на экране процедур
    ///
    /// До 25.10.2026 экран сеял их сам при первом заходе и помнил
    /// об этом флагом `@AppStorage("procedureSkills.seeded")` —
    /// **в `UserDefaults`, то есть на устройстве**, тогда как сами
    /// навыки лежат в SwiftData и едут личным зеркалом CloudKit.
    ///
    /// ```
    /// удалил навык на айфоне   skills пусто, seeded = true
    /// открыл айпад             skills пусто, seeded = FALSE
    ///                          → заготовки завелись заново
    ///                          → уехали обратно на айфон
    /// ```
    ///
    /// Дефект, ради которого флаг и заводили, был закрыт на одном
    /// устройстве и открыт на двух.
    ///
    /// **Посев — событие, а не состояние экрана.** Навыки общие,
    /// к собаке не привязаны (`ProcedureSkill` поля `dog` не имеет),
    /// поэтому заводить их на каждую собаку нельзя — вторая удвоит
    /// список. Место одно: онбординг, который проходят один раз.
    ///
    /// Проверка `isEmpty` здесь — **не замена флага**, а защита
    /// от повторного прохода: человек, прошедший онбординг заново
    /// и не удалявший навыков, не получит их вторым комплектом.
    /// Удалил сам — получит при следующем онбординге или кнопкой
    /// «Вернуть заготовки», и оба раза это его выбор, а не наш.
    @MainActor
    static func seedProcedureSkillsIfNone(context: ModelContext) {
        let есть = (try? context.fetchCount(FetchDescriptor<ProcedureSkill>())) ?? 0
        guard есть == 0 else { return }
        let заведённые = procedureSkills()
        заведённые.forEach(context.insert)
        _ = context.persist(otherwise: { заведённые.forEach(context.delete) })
    }

