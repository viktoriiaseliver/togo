        //    а найденный на прокрутке — это «18:30 · Acana ягнёнок»,
        //    то есть ОЖИДАЕМОЕ кормление, другой смысл янтаря.
        //    Тот же класс, из-за которого сценарий и завели — вход есть,
        //    состояние недостижимо, — только на уровень глубже:
        //    **проверять надо не «данные лежат», а «кадр показал».**
        dog.isOnTreatment = true
