    /// и каждое проверено по месту, а не по памяти:
    ///
    /// ```
    /// dog.isOnTreatment            DayPlanBuilder:50 без него не строит дозы вовсе
    /// минута слота > часа назад    MissedDoseAdvisor.window = 60 * 60
    /// нет DoseRecord на эту минуту DayPlanBuilder:54 сверяет по минуте
