    private static func добавитьПросроченнуюДозу(to dog: Dog, context: ModelContext) {
        dog.isOnTreatment = true

        let календарь = Calendar.current
        let минутаСейчас = календарь.component(.hour, from: .now) * 60
            + календарь.component(.minute, from: .now)
