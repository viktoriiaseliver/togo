        // при одном приёме в день сдвигать нечего, и ровно та ветка
        // текста, ради которой кадр, не выполнилась бы.
        let следующая = min(24 * 60 - 1, пропущенная + 540)

        let препарат = Medication(name: "Левотироксин",
                                  doseText: "½ таблетки",
                                  times: [пропущенная, следующая],
                                  fastingMinutes: 40)
        препарат.unit = .tab
        препарат.setStock(14)
        препарат.packAmount = 30
        препарат.stockTotal = 30
        препарат.dog = dog
        context.insert(препарат)
    }

