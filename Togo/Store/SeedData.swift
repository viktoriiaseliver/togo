    /// Демо-набор для превью и UI-тестов. В обычный запуск не попадает.
    private static let calendarNow = Calendar.current

    /// Что лежит в демо-базе UI-тестов.
    ///
    /// Заведено 24.09.2026 ради одного состояния, которое **нечем было
    /// снять**: выходов нет дольше суток, а записи за сегодня есть.
    /// Именно его прислала кадром мама — шапка «Записей нет с 22 сент.»
    /// стояла над едой в 15:23. Демо-набор сюда не попадал никогда:
    /// в нём два выхода за сегодня, и ветка тишины не рисуется вовсе.
    ///
    /// Правило проекта: прежде чем проверять поверхность, проверь, что
    /// её МОЖНО проверить. Непроверяемое лечится входом, а не взглядом.
    enum Scenario: String {
        /// Обычный день: два выхода и завтрак.
        case today
        /// Выходов нет двое суток, еда за сегодня записана.
        case silence
        /// Дневник вели четыре дня и забросили восемнадцать дней назад.
        ///
        /// Заведён 05.10.2026 ради ступени, которую **не видел глазами
        /// никто ни на одной поверхности** — `.unknown(.silence)`
        /// у вердикта и «отметок мочи нет с …» на виджете. Починка
        /// 28.09 сняла оттуда «Не писал 434 ч. Это дольше, чем он
        /// когда-либо терпел», и проверена она была только арифметикой.
        ///
        /// **Почему отдельный сценарий, а не дни в `silence`.** Казалось
        /// бы, `silence` уже годится: выход там позавчера, `outcome`
        /// у него `.both`, а `.both` считается мочой
        /// (`Diary.urineEvents`) — то есть `signals.urineSilence`
        /// срабатывает. Но вердикта на экране не будет: событий
        /// в `silence` два, `daysOfData` даёт 3, `minimumDaysOfData`
        /// равен 4, и `guard` про нехватку данных стоит ВЫШЕ тишины.
        /// Экран честно отвечает «записей всего за 3 дня».
        ///
        /// Дописать дни в `silence` значило бы сдвинуть вердикт
        /// под живым UI-тестом `ТишинаДольшеСуток`, который снимает
        /// там шапку героя. Поэтому миры разные.
        case urineSilence

        /// Три смысла янтаря разом — и ни один из них до 05.10.2026
        /// не был достижим ни одним сценарием.
        ///
        /// **Как это нашлось.** togo-5a снял все 12 кадров (`rc` 0,
        /// `TEST SUCCEEDED`, 12 выполнено) и искал янтарь `#F7C75F`
        /// с допуском 20: **ноль попаданий на двенадцати кадрах**. Ноль
        /// из двенадцати — край диапазона, то есть симптом инструмента,
        /// пока не доказано обратное. Он это и проверил той же меркой,
        /// сменив только цель: лайм нашёлся на 10 кадрах из 12, от 5 896
        /// до 280 856 пикселей. Значит мерка работает, а янтаря нет
        /// в мире.
        ///
        /// Причина была в данных, не в навигации:
        ///
        /// - препарата с окном натощак в демо не было вовсе;
        /// - `ProcedureSkill` заводились без статуса, то есть
        ///   в `.notStarted`, а янтарь у `.learning`;
        /// - отметок с `MarkAccuracy.almost` не было ни одной.
        ///
        /// Виктория отдельным решением оставила янтарю все три смысла
        /// против требования хендоффа «янтарь только натощак» — то есть
        /// в коде защищено поведение, которого **никто ни разу
        /// не видел**. Это ровно тот класс, что карточка Live Activity,
        /// которую нельзя было построить вне живой активности: «состояние
        /// недостижимо, кадра нет» лечится входом, а «кадр не снят» —
        /// взглядом, и путать их дорого.
        ///
        /// Три состояния живут на разных экранах нарочно: «Сегодня»,
        /// «Уход» и дрессировка. На одном они столкнулись бы, а правило
        /// хендоффа «не больше одного мотива на экран» и здравый смысл
        /// требуют проверять их по отдельности.
        case amber

        /// Восемь пустых собак рядом с настоящей — состояние из отзыва
        /// TestFlight 06.10.2026 на сборке 271 («много пустых собак»).
        ///
        /// **Это построенное состояние, а не воспроизведённое.** Механизм,
        /// которым пустые собаки заводятся у человека, на 07.10 не найден;
        /// сценарий существует затем, чтобы снять кадр списка и кадр дороги
        /// наружу — то есть ответить, что человек ВИДИТ и может ли он это
        /// убрать. На вопрос «откуда они берутся» он не отвечает и отвечать
        /// не должен: построить состояние руками и воспроизвести путь —
        /// разные утверждения, и путать их дороже, чем не иметь сценария.
        case emptyDogs

        /// Пустое хранилище: ни собаки, ни участников, ни дел.
        ///
        /// **Единственный сценарий, который ничего не строит, и это
        /// его смысл.** Онбординг показывает настоящие шаги только там,
        /// где собак нет вовсе: `OnboardingFlow.isReplay` смотрит
        /// ровно на `dogs.isEmpty`, и при живой собаке три шага из шести
        /// подменяются справкой, а поток кончается на третьем экране.
        ///
        /// Соседний `emptyDogs` для этого не годится и выглядит
        /// подходящим по имени: там живая собака плюс восемь пустых,
        /// то есть `isReplay` истинен.
        case onboarding

        /// У ЖИВОЙ собаки стёрта кличка, всё остальное на месте.
        ///
        /// Вторая половина того же дефекта, замер `togo-05`: пустой снимок
        /// с поздним `changedAt` побеждает в слиянии и затирает кличку
        /// настоящей собаки. Отличие от `emptyDogs` принципиальное —
        /// там восемь лишних строк, которые можно не замечать, здесь
        /// **пропадает имя собаки, у которой весь дневник**.
        ///
        /// Вес оставлен настоящий (4,1) нарочно: так на кадре видно,
        /// что запись не пустая, а именно обезличенная.
        case wipedName

        // MARK: Три режима плаката, недостижимые до 07.10.2026
        //
        // Заведены под приёмку плаката кадром. **Это не полнота ради
        // полноты:** у плаката пять режимов, экран показывает ровно
        // тот, который сегодня, и до этих трёх сценариев посмотреть
        // на них было нечем — поверхность была НЕПРОВЕРЯЕМОЙ,
        // а не непроверенной.
        //
        // Существующие шесть не трогал: под ними живёт чужая приёмка,
        // и наполнение сценария — это чужой стенд, а не наши данные.
        // Про `urineSilence` это прямо записано выше, и повторять
        // ту же ошибку в обратную сторону незачем.

        /// Первый день: собака заведена, записей НЕТ ни одной.
        ///
        /// Режим плаката `quiet` — нейтральный блок. Условие на экране
        /// — `rhythm.days == 0`, то есть ритма нет **вовсе**.
        ///
        /// **Почему не `emptyDogs`, как я думал сначала.** Тот делит
        /// события с `today` (один `case` на четыре сценария), и кадр
        /// 07.10 показал у обоих один и тот же индиго: два сценария,
        /// один режим. Проверка «подложки разных режимов отличаются»
        /// при этом честно покраснела — ждали разного от одинакового.
        case firstDay

        /// Окно натощак открыто, и доз **не просрочено ни одной**.
        ///
        /// Режим плаката `fasting` — тёмный янтарь.
        ///
        /// **Почему нельзя было взять `amber`, хотя окно там есть.**
        /// `PosterMode.mode` проверяет `isDoseDue` РАНЬШЕ `isFasting`,
        /// и у `amber` висит неотмеченная доза 08:00 — на кадре она
        /// видна плашкой «Доза 08:00 не отмечена». Режим выходит
        /// `dose`, и это документированное правило, а не дефект:
        /// «натощак ВЕДЁТ к дозе, и когда час наступил, окно уже
        /// не главное».
        ///
        /// > **Состояние бывает недостижимо не из-за отсутствия
        /// > данных, а из-за ПОРЯДКА проверок.** Знать это важнее,
        /// > чем сам пропуск: сценарий, написанный без этого знания,
        /// > дал бы третий `dose` и выглядел бы рабочим.
        ///
        /// Поэтому здесь доза отмечена данной — окно считается
        /// от ОТМЕТКИ, — а следующая назначена на будущее.
        case fastingOnly

        /// Доза просрочена и не отмечена — лист `MissedDoseSheet`.
        ///
        /// **Заведён 08.10.2026, потому что дороги к этому листу
        /// не было ни одной.** Лист предлагает три выхода после
        /// пропуска, и его текст обещал «следующая доза СДВИНЕТСЯ
        /// на 22:40» — а расписание не сдвигается ничем, кроме явной
        /// смены схемы. Человек прочёл бы это и **не дал дозу в 21:00,
        /// когда она стоит**. Текст переписан; кадр нужен, чтобы это
        /// увидеть глазом, а не поверить стражу.
        ///
        /// **Почему не годился `amber`, где схема уже есть.** У него
        /// часы `[8:00, 20:00]`, то есть «просрочено» наступает только
        /// после 09:00 и до 20:00. Прогон в 08:30 дал бы зелёное
        /// при отсутствующем листе — тест зеленел бы по времени суток,
        /// а не по коду.
        ///
        /// Здесь часы считаются ОТ `now`: первый слот — три часа назад,
        /// второй — через девять часов. Окно `MissedDoseAdvisor` равно
        /// часу, так что три часа просрочки не зависят ни от часового
        /// пояса, ни от минуты запуска. Два слота нужны затем, что
        /// `evaluate` считает «сдвиг» только при `times.count > 1`, —
        /// а обещание сдвига и есть предмет кадра.
        ///
        /// > **Граница, которую этот сценарий закрыть НЕ может:**
        /// > с 00:00 до ~01:10 по местному времени в сутках нет минуты,
        /// > отстоящей на час с лишним назад, — план дня строится
        /// > на календарный день. В этот час лист не покажется,
        /// > и это свойство суток, а не дефект. Тест говорит об этом
        /// > прямо, вместо того чтобы молча пройти.
        case missedDose

        /// Три рвоты за три часа — порог тревоги достигнут.
        ///
        /// Режим плаката `alarm` — тёмный терракот.
        ///
        /// **Имя сценария называет то, что он строит, а не то, что
        /// я сначала задумал.** Первая редакция звалась `bloodAlarm`:
        /// «кровь» — первое, что приходит в голову со словом тревога.
        /// Замер `AlarmThreshold:36-45` показал другое — порог считает
        /// `kind == .incident`, группирует по `incidentKind` и требует
        /// **три эпизода одного вида за шесть часов**. Крови он
        /// не знает вовсе.
        ///
        /// > Имя сценария — такое же утверждение о поведении, как имя
        /// > теста. `bloodAlarm`, строящий три рвоты, врал бы с первого
        /// > дня и грепом искался бы не тем, кому нужен.
        case vomitAlarm
    }

    @MainActor
    static func makePreviewContainer(_ scenario: Scenario = .today) -> ModelContainer {
        let container = Persistence.container()
        let context = container.mainContext

        // Выход ДО первой вставки, а не фильтр после: сценарий
        // онбординга требует пустого хранилища, и «вставить, потом
        // удалить» оставило бы следы — `DogOrigin` уже записал бы
        // прибавление, а выбранная собака легла бы в `UserDefaults`.
        if scenario == .onboarding { return container }

        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.breed = "Шипперке"
        dog.foodBrand = "Acana ягнёнок"
        dog.setServingGrams(60)
        dog.targetWeightLow = 4.0
        dog.targetWeightHigh = 4.3
        dog.rewards = ["сыр", "индейка", "мячик"]
        dog.forbiddenFoods = ["курица", "кукуруза"]
        context.insert(dog)
        attachStarterCare(to: dog, context: context)

        // Пустые собаки заводятся ПОСЛЕ настоящей и без единого поля:
        // на кадре отзыва настоящая стоит первой, а у пустых нет ни клички,
        // ни веса. Значения по умолчанию у `Dog` — `name = ""` и
        // `weightKg = 0`, то есть такую запись даёт любой путь, который
        // вставил `Dog` и ничего в него не положил.
        if scenario == .emptyDogs {
            for _ in 0..<8 { context.insert(Dog(name: "", weightKg: 0)) }
        }
        // Кличка стирается ПОСЛЕ того, как собака наполнена: тест обязан
        // снимать обезличенную запись с живым дневником, а не пустую.
        if scenario == .wipedName { dog.name = "" }

        for suggestion in careSuggestions.filter(\.isDefault) {
            let task = suggestion.makeTask()
            if task.kind == .periodic {
                task.lastDone = calendarNow.date(byAdding: .day, value: -task.intervalDays / 2, to: .now)
            }
            if task.kind == .dated {
                task.scheduledDate = calendarNow.date(byAdding: .day, value: 40, to: .now)
            }
            task.dog = dog
            context.insert(task)
        }

        let me = FamilyMember(name: "Виктория", role: .owner, isMe: true)
        let teo = FamilyMember(name: "Тео", role: .coOwner)
        teo.isOnDuty = true
        teo.dutyUntil = Calendar.current.date(bySettingHour: 22, minute: 0, second: 0, of: .now)
        [me, teo,
         FamilyMember(name: "Мама", role: .caregiver),
         FamilyMember(name: "Лея", role: .helper),
         FamilyMember(name: "Dr. Ferrand", role: .observer)].forEach(context.insert)

        let calendar = Calendar.current
        let startOfDay = calendar.startOfDay(for: .now)
        func at(_ hour: Int, _ minute: Int) -> Date {
            calendar.date(minuteOfDay: hour * 60 + minute, on: startOfDay)
        }

        let события: [LogEvent]
        switch scenario {
        // Янтарь живёт поверх обычного дня: ступень янтаря — не особый
        // мир, а строка на нормальном экране, и проверять её надо
        // в нормальном окружении.
        // `missedDose` живёт поверх обычного дня по той же причине,
        // что и янтарь: лист просроченной дозы — не особый мир,
        // а шторка над нормальным планом дня. В пустом окружении
        // он открылся бы, но кадр показал бы экран, которого
        // у человека не бывает.
        //
        // Компилятор поймал это сразу: `switch` по сценариям
        // исчерпывающий, и новый случай нельзя добавить молча.
        // Будь здесь `default`, сценарий получил бы пустой день —
        // и я бы увидел это только на кадре, если бы вообще увидел.
        case .today, .amber, .emptyDogs, .wipedName, .missedDose:
            let morning = LogEvent(kind: .outing, date: at(7, 2), authorName: "Виктория")
            morning.outcome = .urine
            let breakfast = LogEvent(kind: .meal, date: at(7, 34), authorName: "Виктория")
            breakfast.grams = 60
            breakfast.note = "съел всё"
            let second = LogEvent(kind: .outing, date: at(8, 15), authorName: "Тео")
            second.outcome = .both
            события = [morning, breakfast, second]

        case .firstDay:
            // Пусто нарочно: `rhythm.days == 0` — ритма нет ВОВСЕ,
            // и плакат обязан быть нейтральным. Один выход уже сделал
            // бы `days` единицей и увёл режим в `usual`.
            события = []

        case .fastingOnly:
            // Обычный день: плакат должен стоять на нормальном фоне,
            // а не в особом мире. Окно натощак добавляется ниже
            // отдельно — оно живёт на дозах, а не на событиях.
            let morning = LogEvent(kind: .outing, date: at(7, 2), authorName: "Виктория")
            morning.outcome = .urine
            let breakfast = LogEvent(kind: .meal, date: at(7, 34), authorName: "Виктория")
            breakfast.grams = 60
            события = [morning, breakfast]

        case .vomitAlarm:
            // Три эпизода ОДНОГО вида за шесть часов — ровно порог
            // (`AlarmThreshold.minimumEpisodes` = 3, окно 6 ч).
            // Два дали бы `nil` и кадр обычного дня: порог проверяется
            // на своём краю, а не «где-то рядом».
            func рвота(_ назадМинут: Int) -> LogEvent {
                let e = LogEvent(kind: .incident,
                                 date: Date.now.addingTimeInterval(-Double(назадМинут) * 60),
                                 authorName: "Виктория")
                e.incidentKind = .vomit
                return e
            }
            let выход = LogEvent(kind: .outing, date: at(7, 2), authorName: "Виктория")
            выход.outcome = .urine
            события = [выход, рвота(170), рвота(95), рвота(20)]

        case .silence:
            // Последний выход — позавчера вечером: больше суток, значит
            // герой уходит в ветку тишины. Еда — сегодня днём, ровно как
            // на кадре: именно она и делает шапку «записей нет» ложной.
            let позавчера = calendarNow.date(byAdding: .day, value: -2, to: at(18, 40)) ?? at(18, 40)
            let выход = LogEvent(kind: .outing, date: позавчера, authorName: "Виктория")
            выход.outcome = .both
            let обед = LogEvent(kind: .meal, date: at(15, 23), authorName: "Мама")
            обед.grams = 70
            события = [выход, обед]

        case .urineSilence:
            // Четыре дня нормального дневника — и восемнадцать дней
            // молчания. Четыре не из головы: `minimumDaysOfData`
            // равен четырём, и ниже этого вердикт отвечает «записей
            // мало», не доходя до тишины вовсе.
            //
            // Интервалы мочи нужны настоящие: без них вердикт уходит
            // в `.ambiguous` через `guard` про `typical`. Внутри дня
            // они часов по шесть, через ночь — по двенадцать, и все
            // шире окна `sameEmptyingWindow`, то есть в медиану попадут.
            func днейНазад(_ дней: Int, _ час: Int, _ минута: Int) -> Date {
                calendarNow.date(byAdding: .day, value: -дней, to: at(час, минута))
                    ?? at(час, минута)
            }
            func выход(_ дней: Int, _ час: Int, _ минута: Int,
                       _ исход: OutingOutcome, _ автор: String = "Виктория") -> LogEvent {
                let событие = LogEvent(kind: .outing, date: днейНазад(дней, час, минута),
                                       authorName: автор)
                событие.outcome = исход
                return событие
            }
            func еда(_ дней: Int, _ час: Int, _ минута: Int, _ граммов: Int) -> LogEvent {
                let событие = LogEvent(kind: .meal, date: днейНазад(дней, час, минута),
                                       authorName: "Виктория")
                событие.grams = граммов
                return событие
            }

            события = [
                выход(21, 7, 10, .urine), еда(21, 7, 40, 60),
                выход(21, 13, 20, .urine), выход(21, 19, 5, .both, "Тео"),
                выход(20, 7, 5, .both), еда(20, 7, 35, 60),
                выход(20, 14, 0, .urine), выход(20, 20, 10, .urine, "Тео"),
                выход(19, 7, 15, .urine), еда(19, 7, 45, 60),
                выход(19, 13, 40, .both), выход(19, 19, 30, .urine),
                // Последние отметки — и дальше тишина. Ровно та картина,
                // на которой приложение говорило «дольше, чем он
                // когда-либо терпел»: знает оно только, что никто
                // ничего не отмечал.
                выход(18, 7, 0, .urine), еда(18, 7, 30, 60),
            ]
        }

        for event in события {
            event.dog = dog
            context.insert(event)
        }

        if scenario == .amber {
            добавитьЯнтарь(to: dog, context: context)
        }
        if scenario == .fastingOnly {
            добавитьТолькоНатощак(to: dog, context: context)
        }
        if scenario == .missedDose {
            добавитьПросроченнуюДозу(to: dog, context: context)
        }

        return container
    }

    /// Окно натощак — и **ни одной просроченной дозы**.
    ///
    /// Заведено 07.10.2026 под режим плаката `fasting`, которого
    /// не давал ни один сценарий.
    ///
    /// **Почему не годился `amber`, где окно уже есть.**
    /// `PosterMode.mode` проверяет `isDoseDue` раньше `isFasting`,
    /// а у `amber` расписание `[8:00, 20:00]`, и `DoseScheduler
    /// .ensureDoses` заводит при открытии экрана отметку на 8:00 —
    /// неотмеченную, то есть просроченную. Режим выходит `dose`.
    /// Это документированное правило, а не дефект: «натощак ВЕДЁТ
    /// к дозе, и когда час наступил, окно уже не главное».
    ///
    /// > **Состояние бывает недостижимо не из-за отсутствия данных,
    /// > а из-за ПОРЯДКА проверок.**
    ///
    /// Поэтому здесь **расписания нет вовсе** (`times` пуст): создавать
    /// нечего, и просроченной дозы не возникнет ни в каком часу.
    /// Окно при этом открывается — замер `FeedingGate:63-69`: ветка
    /// `.after` смотрит на ОТМЕТКУ приёма и `fastingMinutes`, а не
    /// на расписание.
    ///
    /// Время считается **от «сейчас»**, а не ставится часами: иначе
    /// кадр был бы зелёным или красным в зависимости от того, когда
    /// его снимают, — сторож по расписанию. Тот же довод, что
    /// у `добавитьЯнтарь`.
    ///
    /// `isOnTreatment` обязателен: `TodayScreen.fastingWindow` выходит
    /// через `guard dog.isOnTreatment`, и без флага окно не считается
    /// вовсе — на этом уже обожглись 05.10, когда плашки натощак
    /// не было ни в одном сценарии при верном расчёте.
    @MainActor
    private static func добавитьТолькоНатощак(to dog: Dog, context: ModelContext) {
        dog.isOnTreatment = true
        let препарат = Medication(name: "Левотироксин",
                                  doseText: "½ таблетки",
                                  times: [],
                                  fastingMinutes: 40)
        препарат.unit = .tab
        препарат.setStock(14)
        препарат.packAmount = 30
        препарат.stockTotal = 30
        препарат.dog = dog
        context.insert(препарат)

        let доза = DoseRecord(scheduledAt: Date.now.addingTimeInterval(-20 * 60))
        доза.givenAt = доза.scheduledAt
        доза.givenBy = "Виктория"
        доза.medication = препарат
        context.insert(доза)
    }

    /// Схема с часами В ПРОШЛОМ и БЕЗ отметки приёма.
    ///
    /// Три условия должны сойтись разом, иначе лист не покажется,
    /// и каждое проверено по месту, а не по памяти:
    ///
    /// ```
    /// dog.isOnTreatment            DayPlanBuilder:50 без него не строит дозы вовсе
    /// минута слота > часа назад    MissedDoseAdvisor.window = 60 * 60
    /// нет DoseRecord на эту минуту DayPlanBuilder:54 сверяет по минуте
    /// ```
    ///
    /// Отметки нет НАМЕРЕННО: в `fastingOnly` она есть, и именно она
    /// там гасит просрочку. Скопируй я тот сценарий целиком — получил
    /// бы схему, выглядящую рабочей, и лист, который не показывается.
    private static func добавитьПросроченнуюДозу(to dog: Dog, context: ModelContext) {
        dog.isOnTreatment = true

        let календарь = Calendar.current
        let минутаСейчас = календарь.component(.hour, from: .now) * 60
            + календарь.component(.minute, from: .now)
        // Три часа назад — с запасом к часовому окну просрочки.
        // Ниже нуля не уходим: минута дня не бывает отрицательной,
        // а в первый час суток сценарий честно не сработает (см. `case`).
        let пропущенная = max(0, минутаСейчас - 180)
        // Второй слот — чтобы `evaluate` посчитал интервал и «сдвиг»:
        // при одном приёме в день сдвигать нечего, и ровно та ветка
        // текста, ради которой кадр, не выполнилась бы.
        let следующая = min(24 * 60 - 1, пропущенная + 540)

        let препарат = Medication(name: "Левотироксин",
                                  doseText: "½ таблетки",
                                  times: [пропущенная, следующая],
                                  fastingMinutes: 40)
        препарат.unit = .tab
        препарат.setStock(14)
        препарат.packAmount = 30
        препарат.stockTotal = 30
        препарат.dog = dog
        context.insert(препарат)
    }

    /// Три янтарных состояния — препарат натощак, навык «учится»,
    /// отметка «почти вовремя».
    ///
    /// Времена здесь считаются **от «сейчас»**, а не ставятся часами:
    /// окно натощак открыто ровно двадцать минут от момента запуска.
    /// Абсолютный час сделал бы кадр зелёным или красным в зависимости
    /// от того, когда его снимают, — то есть сторож работал бы
    /// по расписанию.
    @MainActor
    private static func добавитьЯнтарь(to dog: Dog, context: ModelContext) {
        // 1. Натощак. Окно считается от ОТМЕТКИ дозы
        //    (`FeedingGate`, `fastingMinutes`), поэтому дозу надо не просто
        //    назначить, а отметить данной: назначенная и не отмеченная
        //    окна не открывает вовсе.
        //
        //    **И флаг «на лечении» — тоже вход, а не украшение.**
        //    `TodayScreen:482` выходит через `guard dog.isOnTreatment`,
        //    а `isOnTreatment` по умолчанию `false` и во всём `SeedData`
        //    не встречался ни разу. То есть первая редакция этого
        //    сценария заводила препарат, считала окно верно — и плашка
        //    натощак не рисовалась ни в одном сценарии, включая этот.
        //
        //    Поймал togo-5a кадром: янтаря на `amber-1-fasting` нет,
        //    а найденный на прокрутке — это «18:30 · Acana ягнёнок»,
        //    то есть ОЖИДАЕМОЕ кормление, другой смысл янтаря.
        //    Тот же класс, из-за которого сценарий и завели — вход есть,
        //    состояние недостижимо, — только на уровень глубже:
        //    **проверять надо не «данные лежат», а «кадр показал».**
        dog.isOnTreatment = true
        let левотироксин = Medication(name: "Левотироксин",
                                      doseText: "½ таблетки",
                                      times: [8 * 60, 20 * 60],
                                      fastingMinutes: 40)
        левотироксин.unit = .tab
        левотироксин.doseSlotsData = [DoseSlot(minuteOfDay: 8 * 60, quantity: 0.5),
                                      DoseSlot(minuteOfDay: 20 * 60, quantity: 1)]
        левотироксин.setStock(14)
        левотироксин.packAmount = 30
        левотироксин.stockTotal = 30
        левотироксин.dog = dog
        context.insert(левотироксин)

        let доза = DoseRecord(scheduledAt: Date.now.addingTimeInterval(-20 * 60))
        доза.givenAt = доза.scheduledAt
        доза.givenBy = "Виктория"
        доза.medication = левотироксин
        context.insert(доза)

        // 2. Навык «учится». Статус ставится явно: конструктор оставляет
        //    `.notStarted`, и демо-набор восемь месяцев не выходил
        //    из серого.
        let лапа = ProcedureSkill(title: "Дать лапу и не забирать",
                                  detail: "5 дней подряд · по 2 минуты")
        лапа.statusRaw = SkillStatus.learning.rawValue
        лапа.attempts = 7
        лапа.successes = 4
        context.insert(лапа)

        // 3. «Почти вовремя». `MarkAccuracy.from(delayMilliseconds:)`
        //    даёт `.almost` на 501–1000 мс; 640 и 870 — внутри, 420 —
        //    `.onTime`, чтобы на экране стояли обе ступени и янтарь
        //    было с чем сравнить.
        let занятие = TrainingSession(cue: "Лапу", place: "кухня",
                                      person: "Виктория", distanceMeters: 0)
        занятие.markDelaysMs = [420, 640, 870]
        занятие.attempts = 3
        занятие.successes = 2
        занятие.dog = dog
        context.insert(занятие)
    }
