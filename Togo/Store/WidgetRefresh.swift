import Foundation
import SwiftData
// Ради одного имени уведомления: импорт зеркала iCloud (свои же
// телефоны одного Apple ID) сообщает о себе только через Core Data.
import CoreData

/// Снимок виджета пересобирается после КАЖДОЙ записи, а не только
/// пока открыт экран «Сегодня».
///
/// **Дефект, ради которого это заведено (29.10.2026).** Писатель снимка
/// был один — тик `TodayScreen`. Значит виджет и локскрин знали ровно
/// то, что было на экране в последний раз, когда его открывали:
///
/// ```
/// путь записи                         снимок пересобирался
/// экран «Сегодня»                     да, тиком
/// Siri, «Команды», метка NFC          нет
/// кнопки живой активности             нет
/// второй телефон (тихий пуш, обмен)   нет
/// ```
///
/// Каждую дверь звать руками — значит помнить шесть мест и забыть
/// седьмое. Поэтому здесь два слушателя, и оба про ПОСЛЕДСТВИЕ, а не
/// про дверь: `ModelContext.didSave` (любое сохранение базы в этом
/// процессе — интент, экран, приём чужих записей `FamilySync`)
/// и `ActiveSessionStore.изменилась` (прогулка началась, кончилась,
/// получила отметку — она живёт не в базе, а в группе приложений).
///
/// **Почему ещё и явный вызов из `QuickLog`.** Интент выполняется
/// в процессе, который система может усыпить сразу после ответа:
/// отложенная пересборка там рискует не случиться вовсе. Голосовой путь
/// поэтому зовёт `сейчас()` сам, до того как вернуть ответ, а слушатель
/// остаётся страховкой для остальных.
///
/// Что пересборка НЕ лечит: вердикт «просится» по-прежнему считает
/// приложение, и при закрытом приложении без новых записей он стоит.
/// Время с туалета виджет считает от даты сам (`SnapshotText`), вердикт
/// — нет: правило вердикта живёт в `VerdictEngine`, и переносить его
/// в расширение значило бы завести SwiftData в виджет.
@MainActor
enum WidgetRefresh {

    private static var слушатели: [NSObjectProtocol] = []
    private static var запланировано = false

    /// Повесить слушателей. Зовётся один раз при запуске (`TogoApp.init`);
    /// повторный вызов безвреден.
    static func начать() {
        guard слушатели.isEmpty else { return }
        let центр = NotificationCenter.default
        // Третье имя — зеркало SwiftData в личном iCloud: записи со своего
        // же второго устройства приезжают фоновым импортом, который
        // `ModelContext.didSave` не шлёт. **Шлёт ли SwiftData это
        // уведомление вообще — не измерено** (нужен второй телефон
        // с тем же Apple ID); не шлёт — слушатель просто молчит.
        for имя in [ModelContext.didSave, ActiveSessionStore.изменилась,
                    .NSPersistentStoreRemoteChange] {
            let слушатель = центр.addObserver(forName: имя, object: nil, queue: .main) { _ in
                Task { @MainActor in WidgetRefresh.запланировать() }
            }
            слушатели.append(слушатель)
        }
    }

    /// Пересобрать на следующем ходу главного потока — одним разом
    /// на пачку сохранений. Приём обмена сохраняет запись за записью,
    /// и пересборка на каждую была бы работой впустую.
    static func запланировать() {
        guard !запланировано else { return }
        запланировано = true
        Task { @MainActor in
            запланировано = false
            сейчас()
        }
    }

    /// Пересобрать сейчас, из базы и сохранённой прогулки.
    ///
    /// Контекст свой и новый: связь `dog.events` в чужом контексте может
    /// не знать о только что сохранённой записи — ровно по этой причине
    /// `DuplicateGuard` спрашивает хранилище, а не связь.
    static func сейчас(now: Date = Date()) {
        guard let container = Persistence.shared else { return }
        let context = ModelContext(container)
        guard let dog = try? QuickLog.activeDog(in: context) else { return }
        let эпизоды = (try? context.fetch(FetchDescriptor<Episode>())) ?? []
        // Законченная на блокировке прогулка ещё лежит в хранилище —
        // её допишет приложение при открытии, — но собака уже дома.
        // «На улице» с тикающим таймером здесь было бы неправдой.
        let прогулка = ActiveSessionStore.load(now: now)
            .flatMap { $0.закончиласьНаБлокировке == nil ? $0 : nil }
        LiveActivityController.publishSnapshot(
            dog: dog,
            episodeActive: эпизоды.contains { $0.isActive(at: now) },
            walkStartedAt: прогулка?.startedAt,
            walkStartedBy: прогулка?.startedBy,
            now: now)
    }
}
