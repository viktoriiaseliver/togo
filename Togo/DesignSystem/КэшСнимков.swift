import UIKit

/// Раскодированные снимки — один `UIImage` на одни и те же байты.
///
/// # Зачем
///
/// `UIImage(data:)` внутри `body` — это новое декодирование JPEG на главном
/// потоке при каждом рисовании: новый объект не знает, что такой снимок
/// уже раскладывали в пиксели. Разбор 28.10.2026 (отзыв «Плохо
/// скроллиться… идёт зависание») нашёл его в девяти местах `body`:
/// подложка экранов, аватар собаки в шапке «Сегодня», фон и кольцо
/// прогулки (на ней `now` тикает раз в секунду — то есть снимок
/// раскладывался каждую секунду прогулки), фото момента, плитки документов.
///
/// # Ключ — сами байты
///
/// Не имя и не идентификатор: снимок под тем же именем человек может
/// заменить, и картинка по старому ключу показала бы чужое фото. `Data`
/// хэшируется по началу и длине, а равенство сверяет байты целиком —
/// это дешевле декодирования на порядки.
///
/// # Предел
///
/// Шесть снимков. Раскодированный кадр 1000–2000 px — это 4–16 МБ,
/// и копить их без счёта значило бы обменять зависание на выгрузку
/// приложения системой. Шести хватает на один экран целиком (подложка,
/// аватар, пара документов); при переполнении кэш просто начинается заново.
@MainActor
enum КэшСнимков {
    private static var готовые: [Data: UIImage] = [:]
    private static let предел = 6

    static func картинка(_ data: Data) -> UIImage? {
        if let готовая = готовые[data] { return готовая }
        guard let картинка = UIImage(data: data) else { return nil }
        if готовые.count >= предел { готовые.removeAll(keepingCapacity: true) }
        готовые[data] = картинка
        return картинка
    }
}
