import UIKit

/// Раскодированные снимки — один `UIImage` на одни и те же байты.
///
/// # Зачем
///
/// `UIImage(data:)` внутри `body` — это новое декодирование JPEG на главном
/// потоке при каждом рисовании: новый объект не знает, что такой снимок
/// уже раскладывали в пиксели. Разбор 28.10.2026 (отзыв «Плохо
/// скроллиться… идёт зависание») нашёл его в девяти местах `body`:
/// подложка экранов, аватар собаки в шапке «Сегодня», фон и кольцо
/// прогулки (на ней `now` тикает раз в секунду — то есть снимок
/// раскладывался каждую секунду прогулки), фото момента, плитки документов.
///
/// # Ключ — сами байты
///
/// Не имя и не идентификатор: снимок под тем же именем человек может
/// заменить, и картинка по старому ключу показала бы чужое фото. `Data`
/// хэшируется по началу и длине, а равенство сверяет байты целиком —
/// это дешевле декодирования на порядки.
///
/// # Полок две, и вытеснение по давности, а не `removeAll`
///
/// **Замер 05.11.2026. До него предел был один (шесть) и при
/// переполнении кэш делал `removeAll` — то есть на СЕДЬМОЙ картинке
/// стирал все шесть.** Сетка документов — `LazyVGrid` на три колонки
/// (`DocumentPhotos.swift:310`), и при семи и более снимках каждый кадр
/// прокрутки вытирал полку целиком и раскладывал JPEG заново на главном
/// потоке. Ровно та зависимость, против которой кэш и заведён.
///
/// # Чинят это ТРИ разные правки, и ни одна не заменяет остальных
///
/// Замер — `Tools/автономная-проверка-производительности.sh`: он режет
/// чистую часть этого файла текстом и считает декодирования на двух
/// моделях доступа. Вторая строка таблицы и есть та, на которую
/// жаловались.
///
/// ```
/// модель доступа                       предел 6        предел 18
///                                   removeAll  LRU  removeAll  LRU
/// прокрутка: окно 9 плиток,
///   шаг один ряд, 30 снимков            51      30      33      30
/// семь плиток на экране ЦЕЛИКОМ,
///   десять кадров подряд                70      70       7       7
/// ```
///
/// Что читается в этих числах:
///
/// - **У зависания виноват ПРЕДЕЛ, а не `removeAll`.** Когда все
///   плитки видны сразу, предел 6 даёт 70 декодирований на десять
///   кадров — по семь на кадр — и вытеснение по давности не помогает
///   ничем (те же 70). Это классический худший случай LRU: окно
///   доступа больше полки, и каждый проход выбивает ровно тот ключ,
///   который понадобится следующим. Лечит только предел ≥ окна: 70 → 7,
///   то есть каждый снимок раскладывается ОДИН раз за десять кадров.
/// - **У прокрутки виноват `removeAll`.** Там окно скользит, полки
///   хватает, и давность даёт оптимум — 30 декодирований на 30 снимков,
///   по одному. `removeAll` при том же пределе даёт 51 и 33.
/// - **Поднять предел можно только вместе с миниатюрами** — разбор
///   ниже, это вопрос памяти.
///
/// > **Две правки лечат два разных случая, и каждая по отдельности
/// > оставляла бы вторую половину жалобы в силе.** Если бы я сделал
/// > только давность, замер показал бы 70 на той самой модели, с которой
/// > пришёл отзыв.
///
/// # Почему нельзя было просто поднять предел
///
/// Потому что предел шесть держался не на вкусе, а на памяти, и его
/// прежнее обоснование («4–16 МБ на кадр») **занижено**: в сетке лежат
/// снимки документов, и у заведённых до 25.10.2026 длинная сторона
/// до 4800 px — `DocumentPhoto.shrink` до той даты умножал запрошенные
/// 1600 на масштаб устройства (разбор там же).
///
/// ```
/// снимок 1600 × 1200 px   1,92 Мпикс × 4 Б  = 7,7 МБ раскладки
/// снимок 4800 × 3600 px  17,3  Мпикс × 4 Б  = 69  МБ раскладки
/// шесть таких                                 414 МБ — выгрузка
///                                             приложения системой
/// ```
///
/// То есть поднять предел полноразмерных значило обменять зависание
/// на выгрузку — ровно то, чем прежняя редакция этого комментария
/// предел шесть и оправдывала. Поэтому полок две:
///
/// ```
/// полка          предел  раскладка одной      худший случай
/// полноразмерные      6  до 69 МБ             как было, но LRU
/// миниатюры          18  800 × 600 = 1,9 МБ   34 МБ
/// ```
///
/// Восемнадцать миниатюр — шесть рядов сетки по три, то есть больше
/// одного экрана прокрутки; сторона 800 px взята по самой крупной
/// плитке, какая бывает: две колонки при AX-размерах на экране 440 pt
/// дают клетку 184 × 245 pt, то есть 552 × 736 px на `@3x`. В обычном
/// размере клетка 120 × 160 pt — 360 × 480 px, и запас двукратный.
///
/// > **Миниатюра — не экономия места, а смена предмета.** Плитке
/// > 120 pt полноразмерная раскладка не нужна ничем: на ней всё равно
/// > видно 480 px. Полноразмерная остаётся там, где её разглядывают, —
/// > в просмотре документа и в шапке экрана.
@MainActor
enum КэшСнимков {
    /// Полноразмерные раскладки: просмотр документа, подложка экрана,
    /// аватар собаки, фото момента.
    private static var полные: [Data: UIImage] = [:]
    private static var давностьПолных = ПорядокДавности<Data>(предел: пределПолных)

    /// Миниатюры под сетку. Своя полка, потому что свой предел:
    /// миниатюр можно держать втрое больше при вдвое меньшей памяти.
    private static var миниатюры: [КлючМиниатюры: UIImage] = [:]
    private static var давностьМиниатюр = ПорядокДавности<КлючМиниатюры>(предел: пределМиниатюр)

    static let пределПолных = 6
    static let пределМиниатюр = 18

    /// Длинная сторона миниатюры в ПИКСЕЛЯХ. Разбор числа — в голове файла.
    static let сторонаПлитки: CGFloat = 800

    /// Сколько раз байты пришлось раскладывать в пиксели.
    ///
    /// **Приёмка кэша смотрит сюда, а не на предел.** Сторож на
    /// объявленную константу («предел равен шести») удовлетворяется,
    /// не раскодировав ни одного снимка, — тот же класс, на котором
    /// уже спотыкался `StructuralGapsTests` с `maxSide == 1600`
    /// (разбор у `DocumentPhoto.shrink`). Это число — выход помощника,
    /// а не его объявление.
    ///
    /// Считается ПОПЫТКА, а не успех: битые байты раскладкой тоже
    /// занимают главный поток, и повторяются они при каждом кадре —
    /// на полку им лечь нечем.
    private(set) static var декодирований = 0

    static func картинка(_ data: Data) -> UIImage? {
        if let готовая = полные[data] {
            // Попадание ОСВЕЖАЕТ давность: без этого порядок считался
            // бы по времени укладки, и часто смотримый снимок вытеснялся
            // бы наравне с забытым.
            давностьПолных.тронут(data)
            return готовая
        }
        декодирований += 1
        guard let картинка = UIImage(data: data) else { return nil }
        полные[data] = картинка
        for выбывший in давностьПолных.тронут(data) { полные[выбывший] = nil }
        return картинка
    }

    /// Миниатюра под длинную сторону `сторона` (в пикселях).
    ///
    /// Ключ — байты И сторона: та же страница паспорта в сетке и в ряду
    /// списка это два разных растра, и один по ключу другого показал бы
    /// мыло либо лишние мегабайты.
    static func миниатюра(_ data: Data, сторона: CGFloat = сторонаПлитки) -> UIImage? {
        let ключ = КлючМиниатюры(байты: data, сторона: Int(сторона.rounded()))
        if let готовая = миниатюры[ключ] {
            давностьМиниатюр.тронут(ключ)
            return готовая
        }
        декодирований += 1
        guard let полная = UIImage(data: data) else { return nil }
        let вПикселях = CGSize(width: полная.size.width * полная.scale,
                               height: полная.size.height * полная.scale)
        let нужный = КлючМиниатюры.размер(вПикселях, сторона: сторона)
        // Отказ `preparingThumbnail` кладёт на полку ПОЛНУЮ раскладку:
        // показать снимок важнее, чем сэкономить память, а главное —
        // класть на полку надо что-то. Иначе каждый кадр заходил бы
        // сюда заново, то есть отказ превратился бы в зависание.
        let готовая = полная.preparingThumbnail(of: нужный) ?? полная
        миниатюры[ключ] = готовая
        for выбывший in давностьМиниатюр.тронут(ключ) { миниатюры[выбывший] = nil }
        return готовая
    }
}

