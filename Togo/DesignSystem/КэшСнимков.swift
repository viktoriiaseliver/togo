// Ниже — всё, что считается без UIKit и без экрана. Отсюда её берёт
// ТЕКСТОМ `Tools/автономная-проверка-производительности.sh`: копии
// логики не существует, скрипт режет этот самый файл по маркерам.
// Маркеры не украшение: если их не станет, извлечение даст пустоту,
// и скрипт обязан сказать «проверять было нечего», а не «зелено».

// ЧИСТАЯ-ЧАСТЬ-НАЧАЛО
/// Порядок давности ключей: кто тронут давнее всех — выбывает первым.
///
/// **Вытесняется ОДИН ключ, а не полка целиком.** Разница измерена
/// на сетке документов: `removeAll` на седьмом снимке давал шесть
/// декодирований в том же кадре, давность даёт одно.
///
/// Массив, а не связный список и не словарь с метками времени:
/// ключей здесь шесть и восемнадцать, и линейный поиск по восемнадцати
/// дешевле любой книги учёта. Порядок — от давнего к свежему.
nonisolated struct ПорядокДавности<Ключ: Hashable> {
    let предел: Int
    private var ключи: [Ключ] = []

    /// Предел меньше единицы — это кэш, который не кэширует.
    /// Выпрямляется здесь, а не у вызывающего: ноль и минус единица
    /// приехали бы сюда из арифметики, а не из решения.
    init(предел: Int) {
        self.предел = max(1, предел)
    }

    /// Ключ тронут — чтением или укладкой. Возвращает тех, кто выбыл.
    ///
    /// Пустой ответ значит «никто не выбыл», и это НЕ то же самое, что
    /// «предмета нет»: ответ пустой и при попадании в живой кэш,
    /// и при укладке в недобитую полку.
    @discardableResult
    mutating func тронут(_ ключ: Ключ) -> [Ключ] {
        if let место = ключи.firstIndex(of: ключ) { ключи.remove(at: место) }
        ключи.append(ключ)
        var выбыли: [Ключ] = []
        while ключи.count > предел { выбыли.append(ключи.removeFirst()) }
        return выбыли
    }

    /// Сколько ключей под учётом. Для приёмки: расхождение этого числа
    /// с размером самой полки значит, что учёт и полка разъехались.
    var глубина: Int { ключи.count }

    func содержит(_ ключ: Ключ) -> Bool { ключи.contains(ключ) }

    /// Порядок как он есть — от давнего к свежему. Только для приёмки:
    /// кто именно выбудет следующим, решает не вызывающий.
    var отДавнегоКСвежему: [Ключ] { ключи }
}

/// Ключ полки миниатюр: байты И сторона.
nonisolated struct КлючМиниатюры: Hashable {
    let байты: Data
    /// В пикселях и целым: `CGFloat` как часть ключа словаря дал бы
    /// промах кэша на разнице в одну стотысячную, которой человек
    /// не видит.
    let сторона: Int

    /// Размер под длинную сторону, пропорции сохраняются.
    ///
    /// **Только вниз.** Снимок меньше запрошенного растягивать нельзя:
    /// памяти это стоит как увеличение, а показать больше, чем снято,
    /// не может.
    ///
    /// Арифметика та же, что у `DocumentPhoto.shrink`, и предмет
    /// другой: тот переписывает БАЙТЫ на диск, этот — только раскладку
    /// в памяти. Сходство названо здесь нарочно, чтобы расхождение
    /// двух мест не выглядело находкой, когда его заметят.
    static func размер(_ исходный: CGSize, сторона: CGFloat) -> CGSize {
        let длинная = max(исходный.width, исходный.height)
        guard длинная > сторона, длинная > 0 else { return исходный }
        let доля = сторона / длинная
        return CGSize(width: исходный.width * доля, height: исходный.height * доля)
    }
}
