/// Медкнижка — четыре раздела, которые можно **увидеть**.
///
/// ## Зачем галерея, а не прогон
///
/// Обмен и архив медкнижки закрыты кругами по значениям: предел
/// обнаружения не становится числом, повод визита «онлайн» доезжает,
/// статус диагноза не подменяется. Они отвечают, **верно ли посчитано
/// и доехало ли**.
///
/// Чего человек прочитает на экране, не проверял никто — и не мог:
/// чтобы увидеть медкнижку в приложении, надо было загрузить архив
/// с картой Стича, а экрана для неё не существовало до 07.10.2026.
///
/// > **Кадр существует, когда он снят и на него посмотрели.**
///
/// ## Что здесь собрано нарочно — шесть трудных случаев, а не красивые
///
/// ```
/// 1  Т4 с ПРЕДЕЛОМ обнаружения      «<0,1 нг/дл» — не число 0,1
/// 2  Т4 в окне коридора 4–6 ч       читается по коридору 27–69
/// 3  Т4 с НЕЗАПИСАННЫМИ часами      «не записано, через сколько часов»
/// 4  бактериология ТЕКСТОМ          числа нет вовсе
/// 5  биохимия без референса          «норма не указана», не «в норме»
/// 6  показатель с ПУСТЫМ разделом    отдельная группа «без раздела»
/// ```
///
/// Пятый и шестой — про ключи со значением по умолчанию: пустой раздел
/// собрал бы в себя всё, что его не заполнило, а отсутствие референса
/// без оговорки прочиталось бы как «в норме».
///
/// ## Чего кадр отсюда НЕ доказывает
///
/// - **Что загрузка архива приведёт к такой же картине.** Здесь записи
///   собраны значениями в памяти, а не прожиты через `BackupService`.
///   Путь «файл → восстановление → экран» этим кадром не проверен;
///   его закрывают круговые тесты, и они зелёные.
/// - **Что отметка лаборатории разойдётся с нашей нормой именно так.**
///   Расхождение здесь задано руками, чтобы его было ВИДНО: в карте
///   Стича референс Т4 менялся трижды, и лаборатория считала по своему.
/// - **Как это выглядит у врача в кабинете.** Галерея рисует разделы
///   отдельно от сводки; на живом экране над ними стоят цифры, дельта
///   и фильтр периода.
/// - **Крупный шрифт и французский.** Их проверяют своими кадрами.
///
/// Вердикт при этом считает **настоящий** `LabNorm`: подставлены
/// только данные, правило своё.
struct MedicalRecordGallery: View {
    @State private var контейнер: ModelContainer?
    @State private var собака: Dog?

    var body: some View {
        TGScreen {
            TGExplainer(text: """
                Шесть трудных случаев, собранных нарочно: предел \
                обнаружения, коридор в окне и вне окна, текстовый \
                результат, анализ без референса и показатель без раздела.
                """)
            if let собака {
                MedicalRecordCards(dog: собака,
                                   from: Date(timeIntervalSince1970: 1_700_000_000),
                                   to: Date(timeIntervalSince1970: 2_000_000_000))
            } else {
                TGCard { Text("Собираю срез…").textStyle(AppFont.caption) }
            }
        }
        .navigationTitle("Медкнижка")
        .task { собрать() }
    }

    /// Срез собирается в памяти: галерее не нужно ни хранилище
    /// на диске, ни чужой симулятор.
    private func собрать() {
        guard контейнер == nil else { return }
        guard let хранилище = try? ModelContainer(
            for: Dog.self,
            configurations: ModelConfiguration(isStoredInMemoryOnly: true,
                                               cloudKitDatabase: .none)
        ) else { return }
        контейнер = хранилище
        let контекст = ModelContext(хранилище)

        let dog = Dog(name: "Стич", weightKg: 4.1)
        // Лечение включено нарочно: без него коридора не существует,
        // и `LabNorm` ответит «читаем по референсу» на все анализы —
        // то есть третий и второй случаи стали бы неразличимы.
        dog.isOnTreatment = true
        контекст.insert(dog)

        let клиника = Clinic(name: "Vet Riviera", detail: "Ницца",
                             isLab: false, phone: "+33 4 93 00 00 00")
        контекст.insert(клиника)
        let лаборатория = Clinic(name: "IDEXX", isLab: true)
        контекст.insert(лаборатория)

        // Отметка приёма — чтобы «часы после дозы» были не догадкой.
        // Второй случай опирается на неё: забор через пять часов.
        let схема = Medication(name: "Lévothyrox", doseText: "66", times: [420])
        схема.unitRaw = MedUnit.ml.rawValue
        схема.prescriptionNumber = "2026/0417"
        схема.dog = dog
        контекст.insert(схема)
        let приём = DoseRecord(scheduledAt: часы(назад: 29))
        приём.givenAt = часы(назад: 29)
        приём.medication = схема
        контекст.insert(приём)

        for анализ in анализы(dog) { контекст.insert(анализ) }
        for запись in визиты(dog, клиника) { контекст.insert(запись) }
        for диагноз in диагнозы(dog) { контекст.insert(диагноз) }
        контекст.insert(рецепт(dog, клиника))

        try? контекст.save()
        собака = dog
    }

    private func часы(назад: Double) -> Date {
        Date().addingTimeInterval(-назад * 3600)
    }

    private func анализы(_ dog: Dog) -> [LabResult] {
        // 1. Предел обнаружения. `<0,1` — НЕ число 0,1: записав
        //    пределом, экран отдал бы тихо неверное значение вместо
        //    видимо неизвестного, а от него считают дозу.
        let предел = LabResult(sampledOn: часы(назад: 24 * 30),
                               indicator: "Т4 свободный", section: "гормоны",
                               laboratory: "IDEXX", reportNumber: "VF120682")
        предел.belowLimit = 0.1
        предел.unit = "нг/дл"
        предел.referenceLow = 12.9
        предел.referenceHigh = 51.5
        предел.method = "равновесный диализ"
        предел.labMark = "↓"
        предел.dog = dog

        // 2. Забор в окне 4–6 ч: читается по коридору 27–69, и отметка
        //    лаборатории с нашим вердиктом РАСХОДЯТСЯ — 16,7 внутри
        //    референса и ниже коридора. Это и есть находка, которую
        //    нельзя спрятать за одной галочкой.
        let вОкне = LabResult(sampledOn: часы(назад: 24),
                              indicator: "Т4 общий", section: "гормоны",
                              laboratory: "IDEXX", reportNumber: "VF120683")
        вОкне.sampledAt = часы(назад: 24)
        вОкне.value = 16.7
        вОкне.unit = "нмоль/л"
        вОкне.referenceLow = 12.9
        вОкне.referenceHigh = 51.5
        вОкне.labMark = "норма"
        вОкне.note = "на бланке Т+5ч"
        вОкне.dog = dog

        // 3. Часы не записаны — и это ОТВЕТ, а не пустота: «мы
        //    не спросили». Подставить «вероятно, 4–6» значило бы
        //    изобрести норму из удобства.
        let безЧасов = LabResult(sampledOn: часы(назад: 24 * 60),
                                 indicator: "Т4 общий", section: "гормоны",
                                 laboratory: "Antech", reportNumber: "337637858")
        безЧасов.value = 31.4
        безЧасов.unit = "нмоль/л"
        безЧасов.referenceLow = 12.9
        безЧасов.referenceHigh = 51.5
        безЧасов.dog = dog

        // 4. Числа нет вовсе: бактериология даёт описание.
        let посев = LabResult(sampledOn: часы(назад: 24 * 10),
                              indicator: "посев", section: "бактериология",
                              laboratory: "Antech", reportNumber: "337637901")
        посев.textValue = "выделен штамм коагулазо-отрицательного стафилококка"
        посев.dog = dog

        // 5. Референса нет — `LabNorm` обязан сказать «норма
        //    не указана», а не «в норме». ТЗ запрещает подставлять
        //    норму из интернета.
        let безНормы = LabResult(sampledOn: часы(назад: 24 * 12),
                                 indicator: "мочевина", section: "биохимия",
                                 laboratory: "IDEXX", reportNumber: "VF120684")
        безНормы.value = 7.2
        безНормы.unit = "ммоль/л"
        безНормы.dog = dog

        // 6. Раздел не заполнен: отдельная группа «без раздела»,
        //    а не слияние с первой попавшейся.
        let безРаздела = LabResult(sampledOn: часы(назад: 24 * 14),
                                   indicator: "СОЭ", section: "",
                                   laboratory: "клиника")
        безРаздела.value = 4
        безРаздела.unit = "мм/ч"
        безРаздела.dog = dog

        return [предел, вОкне, безЧасов, посев, безНормы, безРаздела]
    }

    private func визиты(_ dog: Dog, _ клиника: Clinic) -> [VetVisit] {
        // Онлайн-консультация — ТАКОЙ ЖЕ визит: у Стича их две,
        // и одна дала рабочую гипотезу диагноза.
        let онлайн = VetVisit(date: часы(назад: 24 * 20), doctor: "Кочубина",
                              reasonRaw: VisitReason.online.rawValue)
        онлайн.conclusion = "рабочая гипотеза: вторичный характер, проверить ТТГ"
        онлайн.dog = dog

        let приём = VetVisit(date: часы(назад: 24 * 3), doctor: "Кочубина",
                             reasonRaw: VisitReason.control.rawValue)
        приём.conclusion = "дозу оставить, контроль через 4–6 недель"
        приём.clinic = клиника
        приём.dog = dog
        return [онлайн, приём]
    }

    private func диагнозы(_ dog: Dog) -> [Diagnosis] {
        // Три статуса рядом нарочно: по подтверждённому лечат,
        // по гипотезе ищут, снятый не лечат вовсе. На кадре видно,
        // что это три разные новости, а не три оттенка одной.
        let подтверждён = Diagnosis(wording: "первичный гипотиреоз",
                                    madeOn: часы(назад: 24 * 90),
                                    statusRaw: DiagnosisStatus.confirmed.rawValue)
        подтверждён.madeBy = "Кочубина, Vet Riviera"
        подтверждён.evidence = "VF120682"
        подтверждён.dog = dog

        let гипотеза = Diagnosis(wording: "вторичный характер — проверить гипофиз",
                                 madeOn: часы(назад: 24 * 20),
                                 statusRaw: DiagnosisStatus.hypothesis.rawValue)
        гипотеза.madeBy = "Кочубина, онлайн"
        гипотеза.dog = dog

        let снят = Diagnosis(wording: "аллергический дерматит",
                             madeOn: часы(назад: 24 * 200),
                             statusRaw: DiagnosisStatus.withdrawn.rawValue)
        снят.madeBy = "клиника на Либерасьон"
        снят.evidence = "посев отрицательный"
        снят.dog = dog
        return [подтверждён, гипотеза, снят]
    }

    private func рецепт(_ dog: Dog, _ клиника: Clinic) -> Prescription {
        let р = Prescription(number: "8935331", date: часы(назад: 24 * 3),
                             medicationName: "Lévothyrox")
        р.doctor = "Кочубина"
        // Вес на дату — ЧАСТЬ назначения: доза считается от него,
        // и история взвешиваний ко второму человеку поехала только
        // сегодня.
        р.dogWeightKg = 4.1
        р.dosage = "66 мкг"
        р.schedule = "дважды в день натощак"
        р.duration = "до контроля"
        р.pharmacyForm = "магистральный"
        // Окно, а не дата: три врача назвали три интервала, и свести
        // их к одному дню значило бы придумать число за врача.
        р.controlFromWeeks = 4
        р.controlToWeeks = 6
        р.dispensed = "4 таблетки"
        р.instruction = "не кормить 45 минут после"
        // Происхождение решает споры: в карте девятнадцать пробелов,
        // где назначение известно письмом, а бланка нет вовсе.
        р.source = "PDF-ордоннанс"
        р.clinic = клиника
        р.dog = dog
        return р
    }
}
