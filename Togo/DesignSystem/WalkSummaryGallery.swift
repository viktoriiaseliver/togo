/// Итог прогулки — единственное место, где его состояния можно **увидеть**.
///
/// **До 07.10.2026 экран со срывом не видел глазами никто, и это
/// не недосмотр.** Тесты считали срывы верно (`WalkSessionTests:223`
/// требует `session.reactions == 4`), а сам вид не строился нигде,
/// кроме живой прогулки: чтобы до него дойти, надо выйти с собакой,
/// отметить срыв и вернуться. Ровно наш зазор — **тест проверяет,
/// верно ли посчитано, кадр — верно ли сказано**, и второго вопроса
/// здесь не задавал никто.
///
/// Строится он при этом обычными значениями (`ActiveSession`, `Dog?`),
/// то есть переделки входа не потребовал — в отличие от карточки
/// «острова», которую пришлось выносить из расширения. **Поверхность
/// была проверяемой и непроверенной**, а это лечится взглядом.
///
/// **Гейт 07.10 изменил состав состояний.** Шторка больше не
/// открывается, если не было ни срыва, ни инцидента, ни заметки
/// (`WalkMode.показатьИтог`). Поэтому «прогулка без отметок» стоит
/// здесь **последней и подписана недостижимой**: она показывает
/// ветку, до которой человек больше не доходит, и держится ради
/// одного — чтобы при снятии гейта было с чем сравнить.
///
/// **Чего кадр отсюда НЕ доказывает:** что человек увидит это после
/// настоящей прогулки. Здесь сессия собрана значениями, а не прожита;
/// порядок отметок, время и паузы в настоящей могут быть другими.
/// Галерея отвечает «что написано и как свёрстано», а не «что
/// случится».
struct WalkSummaryGallery: View {
    /// Час фиксирован: кадр, который нельзя повторить, нельзя
    /// и сравнить. Длительность считается от `startedAt` до «сейчас»,
    /// поэтому берётся не фикса, а сдвиг — иначе в кадре будут часы
    /// вместо минут. Тот же довод, что у таймера живой активности.
    private static var начало: Date { Date().addingTimeInterval(-27 * 60) }

    var body: some View {
        TGScreen(title: "Итог прогулки") {
            TGExplainer(text: "Сессия собрана значениями, живой прогулки здесь нет. Длительность считается от «начала» до сейчас, поэтому она всегда около 27 минут.")

            состояние("срыв один · «на что сорвался» и «как близко»",
                      [.urine, .reaction])
            состояние("срывов три · заголовок во множественном",
                      [.urine, .reaction, .reaction, .reaction])
            состояние("заметка · текст спрашивают здесь, не на улице",
                      [.urine, .note])
            состояние("срыв и заметка вместе · два блока подряд",
                      [.urine, .stool, .reaction, .note])
            состояние("БЕЗ ОТМЕТОК · с 07.10 недостижимо, гейт закрывает молча",
                      [])
        }
    }

    private func состояние(_ подпись: String,
                           _ виды: [ActiveSession.Mark.Kind]) -> some View {
        VStack(alignment: .leading, spacing: Token.Space.s8) {
            Text(подпись)
                .font(.caption2.monospaced())
                .foregroundStyle(Token.Ink.secondary)
            WalkSummarySheet(session: сессия(виды), dog: nil) {}
                .frame(height: 520)
                .clipShape(RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous))
                .overlay(
                    RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous)
                        .strokeBorder(Token.Ink.silhouette.opacity(0.25), lineWidth: 1)
                )
        }
        .padding(.top, Token.Space.s12)
    }

    /// Собака не передаётся нарочно (`dog: nil`).
    ///
    /// Блок про стул спрашивает у дневника, обычная ли форма
    /// (`Diary.usualStool`), и без собаки честно показывает ветку
    /// «форму не угадываем». Подставить сюда демо-собаку значило бы
    /// показать кадр, зависящий от её истории, — то есть кадр,
    /// который завтра другой.
    private func сессия(_ виды: [ActiveSession.Mark.Kind]) -> ActiveSession {
        var s = ActiveSession(kind: .walk, startedAt: Self.начало, startedBy: "Виктория")
        s.marks = виды.enumerated().map { номер, вид in
            ActiveSession.Mark(kind: вид,
                               at: Self.начало.addingTimeInterval(Double(номер + 1) * 180))
        }
        return s
    }
}

