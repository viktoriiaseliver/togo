import SwiftUI

/// Заливка под отметкой — и цвет текста, который на ней читается.
///
/// **Одно место на обе величины, и это не стиль, а починка.**
/// До 08.10.2026 заливку выбирал экран прогулки, а подпись красил
/// `markLabel` — один `Token.Ink.primary` на все три плитки. Для двух
/// тёмных это верно, для акцентной нет, и кнопка, которую на прогулке
/// жмут чаще всего, была нечитаемой:
///
/// ```
///                             dark    light   darkHC  lightHC   порог
/// «Пописал» · ink             1,64 ✗  1,47 ✗  1,64 ✗  1,47 ✗     4,5
/// счётчик «2 раза» · inkMuted 1,17 ✗  1,94 ✗  1,08 ✗  1,40 ✗
/// «Стул» · ink на night3     14,97   14,98   14,97   14,98
/// «Реакция» · ink на amberBg 11,10   16,10   11,10   16,10
/// ```
///
/// **ЭТО СНИМОК НА 08.10.2026, А НЕ СЕГОДНЯШНИЕ ЧИСЛА**, и оставлен
/// он снимком нарочно: переписанное свидетельство о себе
/// не предупреждает. Что с ним сталось, замер 26.10.2026:
///
/// ```
/// «Реакция» · ink на amberBg   dark 12,2211   darkHC 14,3177
/// ```
///
/// Разошлось по двум причинам, и обе названы. Первая — **чернила**:
/// столбцы `dark`/`darkHC` снимка посчитаны с `ink` = `#F4F4F2`
/// (воспроизводится до сотой: 11,0974), а с 22.10 («Кино») `ink`
/// в тёмных равен `#FFFFFF`. Вторая — **HC-ступень у янтаря**,
/// заведённая решением Виктории 26.10.2026: `amberBg.darkHC`
/// ушёл #4A300A → #3B2608, и столбец `darkHC` перестал быть копией
/// `dark`.
///
/// Строка `night3` под тот же счёт НЕ воспроизвелась (вышло 12,6552
/// против записанных 14,97), и чем она посчитана — **не установлено**.
/// Ближайшая похожая причина сюда не пишется.
///
/// Сломана была ровно одна плитка из трёх — та, у которой заливка
/// светлая. Числа сошлись с живым кадром (`1,47` и `1,64`
/// у `light-theme-togo-verification`), и это совпадение про мир:
/// кадр читает пиксель, а не наш `tokens.json`.
///
/// **Это ТРЕТЬЯ поверхность одного правила.** Первую починили
/// у `BigAction` (`ActionGrid.swift:116-119`, сторож
/// `ButtonLabelOnFillTests`), и сторож остался зелёным здесь: он
/// смотрит в один файл. У Togo это записано классом — «починка
/// на одной поверхности из трёх».
///
/// > **Заливку и подпись выбирает один тип.** Пока их выбирают двое,
/// > они разойдутся — и разойдутся молча, потому что компилятор
/// > не знает, что эти два цвета связаны.
///
/// # Почему тип живёт ЗДЕСЬ, а не на экране прогулки
///
/// Первая редакция стояла внутри `WalkModeScreen`, и её поправил
/// чужой сторож — `ComponentTokenScopeTests`: «обращений
/// к компонентным токенам вне дизайн-системы не прибавилось»,
/// 12 при записанных 10. Он был прав, и прав не по букве:
/// `Token.Component.Button.*` — словарь дизайн-системы, и экран,
/// который в него заглядывает, становится вторым местом, где решают,
/// как выглядит кнопка.
///
/// > **Храповик на охват сказал про архитектуру то, чего я сам
/// > не увидел.** Я переиспользовал ПРАВИЛЬНЫЙ токен и положил его
/// > в неправильный слой; числа после переноса те же, а второго места
/// > решения не стало.
///
/// `PosterPaint` сюда не растянут нарочно: ось у неё другая
/// (`PosterMode` — состояние дня, здесь — какая заливка под плиткой),
/// общего только принцип. Вторая копия той же развилки была бы хуже
/// двух честных типов.
nonisolated enum MarkFill: CaseIterable {

    /// Главная кнопка: та же заливка, что у `Button.Primary`.
    case accent
    /// Тёмная плитка.
    case quiet
    /// Плитка «реакция» — жёлтая плашка ожидания.
    case waiting

    /// Для сообщений сторожа: число без имени роли не чинится.
    var name: String {
        switch self {
        case .accent: "акцентная кнопка прогулки"
        case .quiet: "тёмная плитка прогулки"
        case .waiting: "плитка «реакция»"
        }
    }

    var color: Color {
        switch self {
        case .accent: Token.Component.Button.Primary.background
        case .quiet: Token.Surface.sunken
        case .waiting: Token.Status.waitingBg
        }
    }

    /// Подпись и значок. У акцента — компонентный токен кнопки, тот же,
    /// что зовёт `BigAction`: один адрес на обе поверхности.
    var label: Color {
        switch self {
        case .accent: Token.Component.Button.Primary.label
        case .quiet, .waiting: Token.Ink.primary
        }
    }

    /// Счётчик под подписью. Тише подписи, но читаемый: иерархия
    /// «что отметили громче, сколько раз тише» держится на разнице
    /// цветов, а не на размере одного.
    var counter: Color {
        switch self {
        case .accent: Token.Ink.onAccentQuiet
        case .quiet, .waiting: Token.Ink.secondary
        }
    }
}
