import SwiftUI

/// Затемнение фотографии-подложки сверху вниз — **все восемь стопов
/// дизайна**, а не три подобранных вручную.
///
/// # Что здесь починено 26.10.2026
///
/// До этого компонента `CinemaBackdrop` рисовал затемнение **тремя**
/// стопами, выраженными долями от `Token.Surface.screen`
/// (0,85 · 0,55 = 0,47 · 0,25 · 0,55 = 0,14). Это был **обход
/// настоящего дефекта**, и дефекта к тому дню уже не существовало:
///
/// ```
/// было          Token.Surface.scrim рисовался СИНИМ: Color+Hex решал
///               про альфу по величине числа, а 0x0000008C это 140,
///               что ≤ 0xFFFFFF → «альфы нет» → непрозрачный #00008C
/// починено      23.10.2026, в генераторе, ровно там, где комментарий
///               обхода и предписывал: generate_tokens.py дополняет
///               шестизначные до 0xRRGGBBAA, пока значение ещё СТРОКА,
///               а Color+Hex принимает только восемь разрядов
///               и ничего не решает
/// проверено     Tokens.generated.swift: scrim = 0x0000008C — восемь
///               разрядов, альфа 8C = 140 = 55 %
/// осталось      обход. Причина ушла, три стопа остались, и
///               объяснение рядом читалось как действующее
/// ```
///
/// > **Наш класс «условие, привязанное к инструменту, меняет знак»** —
/// > и меняет в момент успеха, когда никто не ждёт плохих новостей.
///
/// # Цена трёх стопов была не в оттенке
///
/// У восьми стопов есть **плато между 30 % и 38 %** — и это не лишний
/// стоп, а **окно фото**: самое светлое место кадра, где собаку видно.
/// В трёх стопах плато нет вовсе, то есть расхождение с макетом — не
/// цвет, а пропавшее окно.
///
/// Замер 23.10.2026 по эталонному кадру 01 (424 × 896) отдельно
/// называет, что плато держит, а что нет: шапка с кличкой на 9,8 %,
/// крупный заголовок на 17 %, чип состояния на 25 % — **все три текста
/// стоят ВЫШЕ плато**, в зоне затемнения 70 → 45 %, и держит их именно
/// она. Плато начинается на 30 % и кончается до панели показания
/// (47 %). Прежняя редакция описания говорила «там лежит шапка» — это
/// было неверно, и числа стопов при этом были верны: объяснение,
/// придуманное к верному числу, наследует его достоверность и не имеет
/// своей.
///
/// # Почему компонентом
///
/// `Token.Component.*` экрану звать нельзя — `ComponentTokenScopeTests`
/// держит счёт таких обращений из экранов на нуле, и запрет измерен:
/// главная кнопка давала 1,68:1 при верном токене и зелёном тесте,
/// потому что экран собрал кнопку сам. Поэтому токен читает компонент,
/// а экран читает компонент — та же форма, что у `TGHeaderScrim`.
///
/// Это семейство, а не один случай: `ReadingPanel.glassRadius`
/// и `ReadingPanel.height` ждут того же.
struct TGBackdropScrim: View {

    var body: some View {
        LinearGradient(
            stops: Token.Component.Backdrop.scrim.map {
                Gradient.Stop(color: $0.color, location: $0.position)
            },
            startPoint: .top,
            endPoint: .bottom
        )
    }
}
