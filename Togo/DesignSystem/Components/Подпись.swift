import SwiftUI

/// Готовая строка там, где компонент ждёт ключ каталога.
///
/// Компоненты дизайн-системы принимают `LocalizedStringKey`: литерал
/// в коде — это ключ, и он переводится. Так и должно быть, и до 23.09
/// было не так: поля объявлялись `String`, `Text(строка)` рисовал текст
/// дословно, и французский кадр витрины показал «Просится» и «Гулять»
/// по-русски при живом переводе.
///
/// Но часть надписей приходит уже собранной, и переводить её второй раз
/// нельзя. Таких случаев два:
///
/// 1. **Текст из данных человека** — кличка собаки, марка корма, имя
///    участника. Их перевод — это «Stitch» вместо «Стич» у того, кто сам
///    назвал собаку.
/// 2. **Фраза, собранная в коде** — перечисление или расчёт, где перевод
///    уже взят через `String(localized:)`.
///
/// `.готовая(…)` называет это прямо в месте вызова: по виду
/// `LocalizedStringKey(строка)` намерения не скажешь, а по виду
/// `.готовая(строка)` скажешь.
///
/// # Но ЗАЩИТЫ ОТ ПЕРЕВОДА она не даёт, и прежняя редакция этой строки
/// обещала обратное
///
/// Здесь было написано: «Каталог такого ключа **не знает**, и SwiftUI
/// показывает его как есть». Это неверно, и неверно **молча**:
/// `.готовая(s)` — это `LocalizedStringKey(s)`, то есть обычный ключ,
/// и поиск по каталогу он **выполняет**. Дословно строка покажется
/// ровно до тех пор, пока такого ключа в каталоге нет.
///
/// Замер 15.10.2026, живой отзыв `AEXYTDmy` «Где-то stitch а где то Стич»:
///
/// ```
/// TextField("Стич", …)     плейсхолдер клички, ЗАКОННАЯ строка показа
///                          → уехала ключом → переведена: en/fr «Stitch», uk «Стіч»
/// человек назвал собаку    данные СОВПАЛИ с ключом побуквенно
/// .готовая(кличка)         TodayRouter:70  → поиск находит ключ → «Stitch»
/// .значение(кличка)        ProfileScreen:32 → Text(String) → «Стич»
/// ```
///
/// **Условие привязано не к правилу, а к содержимому каталога — а оно
/// растёт само, при каждом `make texts`.** То есть защита слабеет
/// с каждым прогоном экспорта, и автор вызова об этом не узнаёт:
/// его код не менялся.
///
/// Настоящая дословность — только `Text(verbatim:)` или компонент
/// с явным случаем для значения, как `TGPosterHeader.Название.значение`.
/// Разбор целиком — `docs/кличка-переводится.md`.
///
/// Поэтому `.готовая(…)` годится **только для второго случая** — фразы,
/// собранной в коде, где перевод уже взят через `String(localized:)`.
/// Для имени, клички, названия препарата и клиники — не годится.
extension LocalizedStringKey {
    static func готовая(_ строка: String) -> LocalizedStringKey {
        LocalizedStringKey(строка)
    }
}
