import SwiftUI

/// Готовая строка там, где компонент ждёт ключ каталога.
///
/// Компоненты дизайн-системы принимают `LocalizedStringKey`: литерал
/// в коде — это ключ, и он переводится. Так и должно быть, и до 23.09
/// было не так: поля объявлялись `String`, `Text(строка)` рисовал текст
/// дословно, и французский кадр витрины показал «Просится» и «Гулять»
/// по-русски при живом переводе.
///
/// Но часть надписей приходит уже собранной, и переводить её второй раз
/// нельзя. Таких случаев два:
///
/// 1. **Текст из данных человека** — кличка собаки, марка корма, имя
///    участника. Их перевод — это «Stitch» вместо «Стич» у того, кто сам
///    назвал собаку.
/// 2. **Фраза, собранная в коде** — перечисление или расчёт, где перевод
///    уже взят через `String(localized:)`.
///
/// `.готовая(…)` называет это прямо в месте вызова. Каталог такого ключа
/// не знает, и SwiftUI показывает его как есть — поведение
/// документированное, но по виду `LocalizedStringKey(строка)` этого
/// не скажешь, а по виду `.готовая(строка)` скажешь.
extension LocalizedStringKey {
    static func готовая(_ строка: String) -> LocalizedStringKey {
        LocalizedStringKey(строка)
    }
}
