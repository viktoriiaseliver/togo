import SwiftUI

/// Ровное затемнение под текстом шапки поверх фотографии плюс спад под ним.
///
/// # Зачем он есть
///
/// Чтобы белый текст шапки пережил светлое место фотографии. Восьми
/// стопов `--bd-scrim` для этого не хватает — прямой ответ дизайна
/// 23.10.2026 (`943de49`, решение 3): «на белом кадре на 10 % высоты
/// α .52 → 4,3:1, на 25 % α .24 → 1,8:1. Гарантию даёт отдельный слой,
/// привязанный к шапке». У шапки подэкранов это стоило **1,89:1**,
/// у панели «Сегодня» — 2,4 при пороге 4,5.
///
/// Гарантия хендоффа дословно: «белый текст ≥ 4.5:1 (4.74) на однотонном
/// белом кадре, HC ≥ 7:1 (8.45); блендинг в sRGB, канал округлён
/// до 8 бит». Держит её `TogoTests/ШапкаНаФотоTests` — рендерит
/// `ImageRenderer`'ом на синтетическом белом снимке и мерит **по пикселю**,
/// отдельно для трёх геометрий, потому что у `ФотоШапка`, подэкрана
/// и вкладки подложка разной высоты, а значит разный композит.
///
/// # Почему компонентом, а не копией в каждом экране
///
/// До 26.10.2026 этот слой стоял **тремя дословными копиями** —
/// `ФотоШапка`, `CinemaHeader`, `ReadingPanel`, — и числа в них были
/// литералами: α `.55`, в повышенном контрасте `.70`, спад `48`.
/// Каждая копия несла доккомментарий «токена у них пока нет, хозяин —
/// сессия токенов; когда токен появится, три шапки переводятся вместе».
///
/// Токен появился (`backdrop.headerScrim`), и перевести три экрана
/// на него напрямую **нельзя**: `ComponentTokenScopeTests` держит счёт
/// обращений к `Token.Component.*` из экранов на НУЛЕ, и любое новое
/// красит набор. Запрет не формальный — он измерен: главная кнопка
/// давала 1,68:1 при верном токене и зелёном тесте, потому что экран
/// **собрал кнопку сам**, а токен существовал для компонента.
///
/// > Значит правильный ответ на «три копии одного слоя» — не токен
/// > в трёх местах, а **один компонент**, который токен и читает.
/// > Иначе дубль остаётся дублем, только с красивым именем.
///
/// # Что остаётся у экрана
///
/// **Условие «рисовать ли вообще»** — у него. Слой нужен только когда
/// под шапкой есть фотография: на `#000` без подложки белый текст и так
/// даёт 21:1, а безусловный слой был бы невидимой ошибкой (чёрный под
/// α .55 поверх чёрного даёт ровно чёрный — кадр её не покажет, сторож
/// на контраст не покраснеет, а композитор платил бы на каждой
/// перерисовке). И вторая половина, которая дороже первой: в день, когда
/// `Surface.screen` перестанет быть чистым чёрным, безусловный слой
/// начнёт подкрашивать шапку там, где фона нет, и причину будут искать
/// в шапке.
///
/// Условие берётся у того же хозяина, что решает, рисовать ли фото.
/// Второй ответ на тот же вопрос разошёлся бы молча.
///
/// # Геометрия
///
/// `.background` меряется по хозяину — значит слой ровно той высоты,
/// какой вышла надпись. Это и есть «привязан к шапке»: отступи кикер
/// на вторую строку в длинном языке, и затемнение уедет вместе с ним,
/// а не останется на своих процентах.
///
/// Спад вылезает ВНИЗ отрицательным отступом: без него он съел бы
/// `fadePt` самой шапки, и ровная часть кончилась бы раньше текста.
struct TGHeaderScrim: View {

    @Environment(\.colorSchemeContrast) private var контраст

    var body: some View {
        VStack(spacing: 0) {
            // ПРОДОЛЖЕНИЕ ВВЕРХ — то, чего не было до 27.10.2026.
            //
            // Отзыв Виктории, 20:31: «Какие то тени, наложения прям
            // видно. Как будто слои неправильно наложились. Там где
            // навигация и затемнённые блоки». На кадре экрана
            // «Настройки» затемнение лежит поверх фотографии
            // ПРЯМОУГОЛЬНИКОМ с резкой верхней кромкой.
            //
            // Причина не в цвете и не в плотности: ровная часть
            // начиналась там, где начинается ТЕКСТ шапки
            // (`CinemaHeader` даёт ей `.padding(.top, s2)`), а выше —
            // под статус-баром и вырезом — фотография оставалась
            // открытой. Снизу спад был с самого начала, сверху
            // не было ничего, и граница читалась как шов между слоями.
            //
            // > Снизу слой растворяли, сверху — обрезали. Один и тот же
            // > край, решённый по-разному, и виден именно необработанный.
            //
            // Высота взята с запасом на самый высокий вырез и уводится
            // за рамку отрицательным отступом — ровно тем приёмом,
            // которым снизу уже уведён спад. Раскладку это не двигает:
            // обе величины гасятся своими `padding`.
            Token.Surface.screen.opacity(плотность)
                .frame(height: Self.продолжениеВверх)
            Token.Surface.screen.opacity(плотность)
            LinearGradient(
                colors: [Token.Surface.screen.opacity(плотность),
                         Token.Surface.screen.opacity(0)],
                startPoint: .top, endPoint: .bottom
            )
            .frame(height: Token.Component.Backdrop.HeaderScrim.fadePt)
        }
        .padding(.top, -Self.продолжениеВверх)
        .padding(.bottom, -Token.Component.Backdrop.HeaderScrim.fadePt)
        // ПРОДОЛЖЕНИЕ В СТОРОНЫ — третий край. История в двух шагах.
        //
        // Отзыв 29.10.2026, сборка 285: «Podlogka pod tezt ujas». Под
        // заголовком «Фон приложения» затемнение лежало ПРЯМОУГОЛЬНИКОМ
        // с вертикальными кромками: шапка там — ячейка `List`
        // (`.insetGrouped`), её ширина — ширина ячейки, и `List`
        // обрезает содержимое ячейки по её рамке (`padding(.horizontal,
        // -120)` упирался в этот клип, снят 04.11).
        //
        // 04.11 (`655bf65b`) слою дали скругление карточки — и отзыв
        // остался в силе: кадр `якорь-кадрирования-04.11/05-…` показывает
        // тот же блок, теперь тёмным СКРУГЛЁННЫМ прямоугольником.
        // > **Форму не прятали, а меняли.** Прямоугольник стал
        // > скруглённым и остался видимым — человек видит не «рваную
        // > кромку», а «плашку под текстом», и это ровно его слова.
        //
        // С 05.11.2026 скругления нет, и лечение не здесь: в ячейке
        // списка этот слой до краёв экрана не дотянется НИКАК. Поэтому
        // на экранах под `cinemaScreen(экран:)` шапка его не рисует
        // вовсе, а сообщает, где кончается, — и затемнение во всю ширину
        // рисует экран, ПОД списком (`TGHeaderScrimЭкрана` ниже). Здесь
        // слой остаётся для хозяев, которые и так во всю ширину
        // (`ФотоШапка`, `ReadingPanel`), и для шапки вне каркаса
        // (превью, `ШапкаНаФотоTests`).
        .accessibilityHidden(true)
    }

    /// Насколько ровная часть продолжается ВВЕРХ, за рамку шапки.
    ///
    /// 240 pt — не подбор: статус-бар с динамическим островом занимает
    /// до 59 pt, плюс отступ шапки от верха экрана. Запас взят так,
    /// чтобы кромки не появилось ни на одном живом размере, включая
    /// крупный шрифт, который опускает заголовок ниже.
    ///
    /// Токена у этого числа нет по той же причине, что у `alpha`
    /// и `fadePt` рядом: в пакете дизайна они есть, в нашем
    /// `tokens.json` — нет, хозяин сессия токенов. Когда токен
    /// появится, сюда приедет и эта величина.
    private static let продолжениеВверх: CGFloat = 240

    /// `backdrop.headerScrim.alpha` = .55, `alphaHC` = .70.
    ///
    /// Два отдельных числа, а не модальный токен: у дизайнера они
    /// различаются по **контрасту**, а не по теме. Светлых режимов
    /// на устройстве нет вовсе (`UIUserInterfaceStyle = Dark` в обоих
    /// plist, решение Виктории 23.10.2026 «Кино. Одна тема»), так что
    /// живых значений здесь два, а не четыре.
    private var плотность: Double { Self.плотность(контраст) }

    /// Одна формула плотности на оба слоя — в ячейке и во всю ширину.
    /// Две копии разошлись бы молча, и шов между ними был бы виден
    /// ровно на той границе, которую слой во всю ширину и убирает.
    static func плотность(_ контраст: ColorSchemeContrast) -> Double {
        контраст == .increased
            ? Token.Component.Backdrop.HeaderScrim.alphaHC
            : Token.Component.Backdrop.HeaderScrim.alpha
    }
}

// MARK: - Затемнение шапки во всю ширину экрана

/// Где кончается шапка `CinemaHeader` — в координатах окна.
///
/// Заводит его `cinemaScreen(экран:)` (по одному на экран), пишет шапка,
/// читает `TGHeaderScrimЭкрана`. Связь через объект, а не через
/// `PreferenceKey`: шапка живёт ячейкой `List`, а предпочтения из ячеек
/// списка наружу доходят не всегда — объект доходит по устройству.
///
/// `nil` — шапки на экране нет, или она не на фотографии. Условие
/// «на фото ли» остаётся у шапки: она пишет только тогда, когда
/// рисовала бы свой слой сама (`CinemaHeader.наФото`).
@Observable
final class ЗамерШапки {
    var низ: CGFloat?
}

private struct ЗамерШапкиKey: EnvironmentKey {
    static let defaultValue: ЗамерШапки? = nil
}

extension EnvironmentValues {
    var замерШапки: ЗамерШапки? {
        get { self[ЗамерШапкиKey.self] }
        set { self[ЗамерШапкиKey.self] = newValue }
    }
}

/// Тот же слой, что `TGHeaderScrim`, но во всю ширину экрана и под
/// содержимым, а не под текстом в ячейке.
///
/// Отзыв 29.10 («Podlogka pod tezt ujas») и кадр
/// `якорь-кадрирования-04.11/05-…`: в ячейке списка слой виден ФОРМОЙ —
/// сначала прямоугольником, после 04.11 скруглённым. У этого слоя формы
/// нет: ровная часть от верха экрана до низа шапки, ниже спад `fadePt`
/// к нулю, по горизонтали — от края до края. Числа те же
/// (`backdrop.headerScrim`), значит контраст под текстом тот же,
/// что мерит `ШапкаНаФотоTests` на слое в ячейке.
///
/// Слой едет вместе с шапкой при прокрутке: низ приходит из её рамки
/// на каждом кадре. Ушла шапка вверх — ровная часть схлопывается,
/// и спад уезжает за верх экрана целиком, без скачка.
struct TGHeaderScrimЭкрана: View {

    let замер: ЗамерШапки

    @Environment(\.colorSchemeContrast) private var контраст

    var body: some View {
        GeometryReader { рамка in
            if let низ = замер.низ {
                let доНиза = низ - рамка.frame(in: .global).minY
                let плотность = TGHeaderScrim.плотность(контраст)
                VStack(spacing: 0) {
                    Token.Surface.screen.opacity(плотность)
                        .frame(height: max(0, доНиза))
                    LinearGradient(
                        colors: [Token.Surface.screen.opacity(плотность),
                                 Token.Surface.screen.opacity(0)],
                        startPoint: .top, endPoint: .bottom
                    )
                    .frame(height: Token.Component.Backdrop.HeaderScrim.fadePt)
                }
                .offset(y: min(0, доНиза))
                .frame(width: рамка.size.width, alignment: .top)
            }
        }
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }
}
