import SwiftUI

/// Выход с цифровой клавиатуры: панель «Готово» над ней.
///
/// # ЗАВЁЛ ПОЛЕ `.decimalPad` — ПРИМЕНИ ЭТОТ МОДИФИКАТОР
///
/// Иначе у поля **не будет выхода вовсе**: у `.decimalPad` нет клавиши
/// возврата, это системное. Проза не выполняется, поэтому проверка
/// стоит здесь же и занимает минуту:
///
/// ```bash
/// grep -rn --include='*.swift' 'keyboardType(.decimalPad)' Togo/ | grep -vc '///'
/// grep -rn --include='*.swift' '\.готовоНадКлавиатурой'    Togo/ | grep -vc '///'
/// ```
///
/// На 15.10.2026 это **11 и 1**: выход заведён на одном шаге из семи,
/// остальные шесть экранов ждут кадра. Разошлись не на эту разницу —
/// у кого-то выхода нет.
///
/// # Первая редакция этой проверки была сломана, и сломал её ЭТОТ файл
///
/// Она искала слово `decimalPad` без оси и без вырезания
/// комментариев — и дала **20** вместо 11, потому что посчитала прозу,
/// в том числе девять упоминаний `.decimalPad` в доккомментариях,
/// которые я же здесь и написал.
///
/// ```
/// grep по слову decimalPad                 20   ← считает прозу
/// grep по keyboardType(.decimalPad)        12   ← одно в чужом /// тоже
/// то же, с вырезанным ///                  11   ← поля
/// ```
///
/// > **Проверка, запрещающая писать о себе, ломается первой же
/// > записью о себе.** Класс известен («сторож меряет прозу»),
/// > и всё равно поймал автора на расстоянии двадцати строк
/// > от собственного описания: ось берётся от того, **что
/// > вызывается** (`keyboardType(.decimalPad)`), а не от того, как
/// > предмет называется в тексте.
///
/// **Повод измерен, а не предположен.** До 15.10.2026 снятия фокуса
/// в проекте не было вообще: на 206 файлах `@FocusState` — ноль,
/// `endEditing` и `resignFirstResponder` — ноль,
/// `.scrollDismissesKeyboard` — ноль, `ToolbarItemGroup(placement:
/// .keyboard)` — ноль. Полей `.decimalPad` при этом одиннадцать:
/// `HealthScreen:510` · `LabResultScreens` ×6 ·
/// `PrescriptionScreens:253` · `Editors:33` и `:533` ·
/// `OnboardingSteps:102`.
///
/// # Почему модификатор принимает действие, а не поле
///
/// Поле у каждого экрана своё: на пяти экранах оно одно (`Bool`
/// достаточно), на двух — по три, и там нужно перечисление
/// (`LabResultEntryFlow:211`, `LabResultRowEditor:535`). Модификатор,
/// который знал бы поле, пришлось бы писать в двух видах. Он знает
/// только, **что нажали**, а снимает фокус экран — тот, кто им владеет.
///
/// # Чего этот путь НЕ даёт, и это надо знать до того, как положиться
///
/// `@FocusState` защищают тем, что связь видна компилятору. Выгода
/// **неполная**: удали поле — `case` перечисления и `@FocusState`
/// останутся, и компилятор промолчит. Он краснеет на опечатке в имени
/// `case`, а не на исчезновении поля.
///
/// > Новое поле `.decimalPad` молча останется без выхода. Это наш
/// > класс «механизм есть, вход не заведён», и здесь он лечится
/// > не компилятором, а двумя командами выше.
///
/// Выбран этот путь, а не `UIApplication.sendAction(resignFirstResponder)`
/// (он снимал бы фокус у любого поля одним адресом на экран, без
/// объявлений). Решение менеджера 15.10 при названной цене: 27 правок
/// против 7. Разбор обоих вариантов целиком —
/// `docs/journal/2026-10-15-storozh-otbrakovyvaet-sostoyanie-defekta.md`.
/// **Замена одного пути на другой стоит один файл** — этот: панель,
/// её место и условие показа у обоих вариантов одни и те же,
/// различается только то, что делает кнопка. Ни один адрес применения
/// при замене не меняется.
///
/// # Этот модификатор не чинит вёрстку
///
/// Содержимое, уехавшее под закреплённый низ при поднятой клавиатуре,
/// — **другой дефект** (`safeAreaInset` на том же шаге, `d7e275b`).
/// Один без другого оставляет человека либо без выхода, либо без «Даты
/// рождения» на экране. Проверять оба — **одним кадром**, иначе
/// зелёное одного прочтётся как готовность обоих.
extension View {
    func готовоНадКлавиатурой(снять: @escaping () -> Void) -> some View {
        toolbar {
            // `Spacer` первым: панель клавиатуры тянется во всю ширину,
            // и без него «Готово» встало бы слева, где его ищут
            // последним.
            //
            // Строка в каталоге уже есть и переведена на все четыре
            // языка (`en` Done · `fr` OK · `ru`/`uk` Готово) — долга
            // перевода правка не добавляет. Проверено
            // по `localizations`, а не по наличию ключа: ключ без
            // перевода выглядит так же, и на этом гас сторож перевода.
            ToolbarItemGroup(placement: .keyboard) {
                Spacer()
                Button("Готово", action: снять)
            }
        }
    }
}
