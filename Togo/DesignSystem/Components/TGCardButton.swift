import SwiftUI

/// Стиль кнопки-карточки: выключенное состояние решают ТОКЕНЫ,
/// а не системное гашение.
///
/// # Зачем он есть, если есть `.buttonStyle(.plain)`
///
/// `.plain` вместе с `.disabled()` гасит **весь слой метки** примерно
/// вполовину — и заливку, и уже покрашенные `Text`. Гашение приезжает
/// ПОСЛЕ того, как цвет выбран, поэтому правильный токен его не
/// переживает: значение верное, нарисованное — другое.
///
/// Замер по пикселю 25.10.2026, `04-training.png` набора
/// `витрина-279-25.10` (коммит стенда `341c31a`), занятие не начато:
///
/// ```
///                         токен      НАРИСОВАНО   контраст   порог
/// заливка карточки        #2C2C2E    #161617         —
/// заголовок               #FFFFFF    #8B8B8B      5,31:1      4,5
/// подпись                 #C7C7CC    #6F6F72      3,61:1      4,5  ✗
/// ```
///
/// Ни одного `.opacity` в экране при этом нет: `grep -c opacity`
/// по `TrainingSessionScreen.swift` даёт ноль. Гасит система, и это
/// тот же класс, что «прозрачность съедает запас» — только
/// прозрачность не наша, и в исходнике её не видно вовсе.
///
/// **Проверка этого утверждения лежала в том же кадре.** Пилюля
/// «Не получилось» стоит на `TGButtonStyle` — своём стиле, а не
/// на `.plain`, — и в том же состоянии, в тот же прогон, нарисована
/// токенами точно: `#C7C7CC` на `#3A3A3C`, 6,74:1. То есть свой
/// `ButtonStyle` системного гашения не получает, и это замер на двух
/// кнопках одного кадра, а не правило из документации.
///
/// # Чего он НЕ решает
///
/// Отличать выключенное от включённого он сам не умеет — это работа
/// того, кто подставляет цвета (`CardInk`). Стиль только убирает
/// чужое гашение и оставляет нажатие видимым.
struct TGCardButtonStyle: ButtonStyle {

    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            // Нажатие — состояние на доли секунды, его читаемость
            // никто не меряет. Выключенность — состояние, в котором
            // экран стоит до первого тапа, и её решают токены.
            .opacity(configuration.isPressed ? 0.82 : 1)
            .animation(.easeOut(duration: Token.Duration.instant),
                       value: configuration.isPressed)
    }
}

/// Чернила карточки-кнопки: один адрес на выключенную подпись.
///
/// Живёт в дизайн-системе, потому что `Token.Component.*` за её
/// пределами запрещён (`ComponentTokenScopeTests`), а адрес нужен
/// тот же, которым `TGButton` красит свою выключенную подпись:
/// два места, решающих, как выглядит выключенное, разойдутся молча.
nonisolated enum CardInk {

    /// Подпись и заголовок выключенной карточки.
    ///
    /// `Button.Disabled.label` — это `inkMuted`, и выбран он
    /// решением Виктории 25.10.2026 (круг 5, пункт 4): просьба
    /// автора макета про `#8E8E93` отклонена, потому что три режима
    /// из четырёх не проходили 4,5. На `surface.sunken` текущий
    /// токен даёт 8,2755 · 5,2438 · 10,1480 · 7,2840 — по значениям.
    ///
    /// > **Заливку выключенной карточки здесь НЕ трогаем.**
    /// > `Disabled.background` и `Surface.sunken` с 25.10 равны
    /// > байт в байт во всех четырёх режимах, то есть «уводить»
    /// > выключенное заливкой сейчас нечем. Вопрос «куда уводим
    /// > выключенную кнопку» Виктории не задан и остаётся открытым
    /// > в `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`.
    static var disabledLabel: Color { Token.Component.Button.Disabled.label }
}
