import SwiftUI

/// Верхняя панель над фотографией: прозрачна в покое, закрывает
/// содержимое, когда его прокрутили под неё.
///
/// # Отзыв 293
///
/// Кадр `якорь-кадрирования-04.11/06-окна-предпросмотра-60x50.png`:
/// прокрученный список настроек, и текст карточек читается под часами
/// и под кнопкой «Настройки». Человек назвал это «навигация сломалась» —
/// кнопка «назад» стоит на тексте.
///
/// Причина — `.toolbarBackground(.hidden, for: .navigationBar)`, который
/// стоял у `cinemaScreen` и у `фотоШапкаЭкрана` ради фотографии
/// до статус-бара. Он снимает подложку панели **во всех состояниях**,
/// а не только в покое: у системы отняли тот самый слой, который
/// появляется, когда содержимое уезжает под панель. Вуаль 04.11
/// (градиент ~140 pt, `ВуальПанели`) текст затемняла, но не закрывала —
/// на кадре 06 он читается.
///
/// # Что вместо
///
/// Видимость фона панели — `.automatic`, то есть системная:
///
/// ```
/// в покое (список у верхнего края)   панель прозрачна, фото видно
///                                    до статус-бара — как было
/// содержимое под панелью             iOS 17–18: материал панели;
///                                    iOS 26: размытие края прокрутки
///                                    (scroll edge effect) — оно
///                                    размывает только прокручиваемое
///                                    содержимое, фото фоном не трогает
/// ```
///
/// Своё размытие с маской-градиентом не взято нарочно: оно размывало бы
/// фото и в покое (слой не знает, прокручен ли список), а знание
/// «прокручен ли» у системы уже есть и точнее нашего.
///
/// **Чего здесь не доказано.** Поведение проверено рассуждением и
/// компилятором, не кадром: стенд 05.11 занят. Приёмка — кадр покоя
/// (фото до статус-бара, без материала) и кадр прокрутки (текст под
/// панелью не читается) на iOS 26 и, если есть, на iOS 18.
///
/// # Почему компонентом
///
/// Мест два — `cinemaScreen(экран:)` (подэкраны, История, Здоровье)
/// и `фотоШапкаЭкрана()` (вкладка собаки, «Семья»), — и дефект в них
/// был один и тот же строкой. Копия починки разошлась бы с оригиналом
/// молча, как три копии слоя шапки до 26.10 (`TGHeaderScrim`).
extension View {

    func панельНадФото() -> some View {
        self
            .toolbarBackground(.automatic, for: .navigationBar)
            // Тема одна, тёмная (`UIUserInterfaceStyle = Dark`), но
            // материал панели берёт схему у панели, а не у приложения:
            // без этой строки на прокрутке мог бы выйти светлый.
            .toolbarColorScheme(.dark, for: .navigationBar)
    }
}
