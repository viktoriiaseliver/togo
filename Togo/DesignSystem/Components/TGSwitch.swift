import SwiftUI
import UIKit

/// Figma: `Toggle`. Переключатель, у которого видно ползунок — в обоих
/// состояниях.
///
/// # Зачем он есть: белое по белому, 1,00:1
///
/// `TogoApp.swift:340` ставит на всё окно `.tint(Token.Action.primary)`,
/// а в теме «Кино» `action.primary` — это **`#FFFFFF`** (решение
/// Виктории 22.10.2026, «БЕЛАЯ PRIMARY»). Системный `Toggle` красит
/// тинтом **включённую дорожку**, а ползунок у него белый **всегда** —
/// значит включённый переключатель выходит белой капсулой без ползунка.
///
/// Это замер по кадру, а не рассуждение. `Дизайн/кадры-приёмки/
/// витрина-редизайн-23.10/09-permissions.png`, экран прав участника,
/// три переключателя подряд:
///
/// ```
/// горизонтальный срез через центр капсулы, 37 проб
///   #1C1C1E ×4 · #FFFFFF ×31 · #1C1C1E ×2     ← ни одного пикселя ползунка
/// ползунок к дорожке   #FFFFFF на #FFFFFF     1,00:1
/// ```
///
/// Цена не косметическая: это экран, на котором человек раздаёт право
/// «Видеть медицинское».
///
/// # Значение взято у дизайна, а не придумано здесь
///
/// Хендофф рисует переключатель сам — `Дизайн/редизайн-ios28/prototypes/
/// Togo-RU.dc.html:774`, и те же 774 в EN/FR/KK/UK:
///
/// ```js
/// tBg:  on ? 'var(--text-link)' : 'var(--control-toggle-off)'
/// knob: on ? '22px' : '2px'      // 27×27, background:#fff, всегда белый
/// ```
///
/// `--text-link` в «Кино» — `#A2C1FE`, то есть ровно `Token.Ink.link`
/// во всех четырёх режимах (`#A2C1FE` / `#1F4FFF` / `#C2D6FF` /
/// `#0E14A1`). **Включённая дорожка у дизайна не белая никогда**, и
/// столкновения с белой `action.primary` в макете нет вовсе: оно
/// родилось в коде, из общего тинта окна, и в хендоффе его не найти.
///
/// # Выключенная дорожка — своя с 25.10.2026
///
/// ~~Выключенная дорожка остаётся системной… токена под него
/// в `DesignTokens/tokens.json` нет~~ — **снято ответом дизайна,
/// круг 5, пункт 3** (`Дизайн/редизайн-ios28/ОТВЕТЫ-круг-5.md`).
/// Запись была верна в момент написания и устарела ровно тогда, когда
/// пришли оба значения: `control.toggle.off` `#767676`, повышенный
/// контраст `#8E8E93`. Роль заведена как
/// `Token.Component.Toggle.trackOff`.
///
/// ```
/// дорожка к карточке   #767676 на #1C1C1E   3,7459   дизайн назвал 3,74
/// то же в HC           #8E8E93 на #242426   4,7520   дизайн назвал 4,67 ↑
/// ползунок к дорожке   #FFFFFF на #767676   4,5422   дизайн назвал 4,5
/// то же в HC           #FFFFFF на #8E8E93   3,2605   дизайн НЕ НАЗЫВАЛ ↓
/// ```
///
/// Две стрелки — не придирка. **`4,67` против нашего `4,7520`**
/// разошлось на 0,08 в нашу пользу: либо они считали на другой
/// подложке, либо округляли иначе; число названо здесь, чтобы
/// расхождение было видно, а не сглажено. **А `3,2605` — то, чего
/// в ответе нет вовсе:** в повышенном контрасте дорожка светлеет,
/// ползунок уже белый и светлеть ему некуда, поэтому пара
/// «ползунок к дорожке» там ПАДАЕТ. Это тот же механизм, которым
/// 15.10 белая подпись плаката догнала заголовок. Дефектом это
/// не является — дизайн прямым словом сказал, что WCAG 1.4.11 эту пару
/// не проверяет, — но человек, включивший «Повысить контраст», получает
/// дорожку заметнее и ползунок тише, и знать об этом надо.
///
/// # Почему UIKit, а не `ToggleStyle`
///
/// Прежняя редакция называла цену своего `ToggleStyle` верно:
/// «забрал бы протаскивание ползунка, кривую анимации и то, как система
/// рисует этот орган в повышенном контрасте и при „Уменьшении
/// движения"». Цена не изменилась, поэтому `ToggleStyle` здесь так
/// и не появился. **Вместо него — сам `UISwitch`**: это тот же
/// системный орган, все его повадки при нём, а две величины, которых
/// SwiftUI наружу не отдаёт, у UIKit отдаются свойствами.
///
/// ```
/// onTintColor        включённая дорожка   есть и в SwiftUI (.tint)
/// backgroundColor    ВЫКЛЮЧЕННАЯ дорожка  в SwiftUI НЕТ ВОВСЕ
/// layer.cornerRadius капсула под неё      в SwiftUI НЕТ ВОВСЕ
/// ```
///
/// `backgroundColor` без `cornerRadius` даёт прямоугольник с углами
/// вокруг капсулы — поэтому обе величины идут вместе, и поэтому
/// `UISwitch.appearance()` тут не годится: `layer.cornerRadius`
/// не входит в `UIAppearance`, и через прокси выставить его нельзя.
///
/// # ЧЕГО ЗДЕСЬ НЕ ИЗМЕРЕНО, И ЭТО ГРАНИЦА, А НЕ ПРИСКАЗКА
///
/// **Кадра с пикселем выключенной дорожки нет.** Числа выше — замер
/// ЗНАЧЕНИЙ, то есть «какой цвет мы просим», а не «какой цвет виден».
/// Между ними помещается ровно тот класс, которым этот файл
/// и родился: на кадре `09-permissions.png` токены были верны,
/// а на экране выходила белая капсула без ползунка. Приёмка этой
/// правки — пиксель на дорожке выключенного переключателя, снятый
/// в тёмной теме и в повышенном контрасте, и до него правка числится
/// сделанной, но не принятой.
///
/// Отдельно: `Token.Surface.controlPressed` (`#48484A`) под эту роль
/// **не берётся**. Он заведён 23.10 как «нажатая плашка контрола».
/// # Три повадки `Toggle`, которые пришлось вернуть руками
///
/// Подмена органа забирает не только вид. Каждая строка ниже —
/// возвращённая повадка, а не украшение, и без любой из них правка
/// была бы регрессией на экране, где раздают право «Видеть
/// медицинское»:
///
/// ```
/// .disabled(…)     SwiftUI кладёт его в \.isEnabled, а до UIKit-органа
///                  оно САМО НЕ ДОЕЗЖАЕТ — гость переключал бы право,
///                  которого ему не выдадут. Передаётся явно
/// тап по строке    у `Toggle` переключает вся строка, у `LabeledContent`
///                  только орган. Возвращено contentShape + onTapGesture,
///                  и тап глохнет, когда выключено
/// озвучка          `LabeledContent` отдаёт подпись и орган ДВУМЯ
///                  элементами, `Toggle` — одним «переключатель, …».
///                  Возвращено accessibilityRepresentation
/// ```
struct TGSwitch<Label: View>: View {
    @Binding var isOn: Bool
    @ViewBuilder var label: Label

    @Environment(\.isEnabled) private var доступен

    var body: some View {
        LabeledContent {
            СистемныйПереключатель(isOn: $isOn)
        } label: {
            label
        }
        .contentShape(Rectangle())
        .onTapGesture { if доступен { isOn.toggle() } }
        .accessibilityRepresentation { Toggle(isOn: $isOn) { label } }
    }
}

/// `UISwitch` как есть, с двумя покрашенными величинами.
///
/// Цвета берутся у `Color` через `UIColor(_:)`, а не копией числа:
/// сторож, сверяющий свою копию с источником, меряет себя — `0x5972FE`
/// в тесте однажды пережил замену цвета в приложении на два дня.
/// `UIColor` из динамического `Color` остаётся динамическим и сам
/// идёт за темой и за «Повысить контраст», поэтому отдельной ветки
/// на режимы здесь нет и быть не должно.
private struct СистемныйПереключатель: UIViewRepresentable {
    @Binding var isOn: Bool

    /// `.disabled(…)` до UIKit-органа сам не доезжает: SwiftUI кладёт
    /// его в среду, а `UIView` среды не читает. Без этой строки гость
    /// переключал бы право, которого ему не выдадут.
    @Environment(\.isEnabled) private var доступен

    func makeUIView(context: Context) -> UISwitch {
        let орган = UISwitch()
        орган.addTarget(context.coordinator,
                        action: #selector(Координатор.переключили(_:)),
                        for: .valueChanged)
        // Капсула под заливкой. Высота `UISwitch` фиксирована системой
        // (31 pt), но берём её у органа, а не числом: число разошлось бы
        // молча на первом же изменении системы.
        орган.layer.cornerRadius = орган.intrinsicContentSize.height / 2
        орган.clipsToBounds = true
        return орган
    }

    func updateUIView(_ орган: UISwitch, context: Context) {
        context.coordinator.isOn = $isOn
        if орган.isOn != isOn { орган.setOn(isOn, animated: true) }
        орган.isEnabled = доступен
        орган.onTintColor = UIColor(Token.Ink.link)
        орган.backgroundColor = UIColor(Token.Component.Toggle.trackOff)
    }

    func makeCoordinator() -> Координатор { Координатор(isOn: $isOn) }

    final class Координатор: NSObject {
        var isOn: Binding<Bool>
        init(isOn: Binding<Bool>) { self.isOn = isOn }

        @objc func переключили(_ орган: UISwitch) { isOn.wrappedValue = орган.isOn }
    }
}
