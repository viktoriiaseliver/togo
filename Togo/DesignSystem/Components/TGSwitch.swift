import SwiftUI

/// Figma: `Toggle`. Переключатель, у которого видно ползунок — в обоих
/// состояниях.
///
/// # Зачем он есть: белое по белому, 1,00:1
///
/// `TogoApp.swift:340` ставит на всё окно `.tint(Token.Action.primary)`,
/// а в теме «Кино» `action.primary` — это **`#FFFFFF`** (решение
/// Виктории 22.10.2026, «БЕЛАЯ PRIMARY»). Системный `Toggle` красит
/// тинтом **включённую дорожку**, а ползунок у него белый **всегда** —
/// значит включённый переключатель выходит белой капсулой без ползунка.
///
/// Это замер по кадру, а не рассуждение. `Дизайн/кадры-приёмки/
/// витрина-редизайн-23.10/09-permissions.png`, экран прав участника,
/// три переключателя подряд:
///
/// ```
/// горизонтальный срез через центр капсулы, 37 проб
///   #1C1C1E ×4 · #FFFFFF ×31 · #1C1C1E ×2     ← ни одного пикселя ползунка
/// ползунок к дорожке   #FFFFFF на #FFFFFF     1,00:1
/// ```
///
/// Цена не косметическая: это экран, на котором человек раздаёт право
/// «Видеть медицинское».
///
/// # Значение взято у дизайна, а не придумано здесь
///
/// Хендофф рисует переключатель сам — `Дизайн/редизайн-ios28/prototypes/
/// Togo-RU.dc.html:775`, и те же 775 в EN/FR/KK/UK:
///
/// ```js
/// tBg:  on ? 'var(--text-link)' : 'var(--control-toggle-off)'
/// knob: on ? '22px' : '2px'      // 27×27, background:#fff, всегда белый
/// ```
///
/// `--text-link` в «Кино» — `#A2C1FE`, то есть ровно `Token.Ink.link`
/// во всех четырёх режимах (`#A2C1FE` / `#1F4FFF` / `#C2D6FF` /
/// `#0E14A1`). **Включённая дорожка у дизайна не белая никогда**, и
/// столкновения с белой `action.primary` в макете нет вовсе: оно
/// родилось в коде, из общего тинта окна, и в хендоффе его не найти.
///
/// # Чего здесь НЕТ и почему
///
/// **Выключенная дорожка остаётся системной.** У хендоффа на неё есть
/// своё значение — `--control-toggle-off` `#767676`
/// (`prototypes/tokens/palette.css:34`), — но токена под него в
/// `DesignTokens/tokens.json` нет, а повышенного контраста пакет для
/// этой роли не даёт вовсе. Завести роль с выдуманными значениями HC
/// значило бы принять решение о цвете за Викторию; это её решение,
/// ровно как у `Component.Button.Disabled.background`
/// (`ПлашкиКонтролаTests`, запись 23.10.2026).
///
/// Отдельно: `Token.Surface.controlPressed` (`#48484A`) под эту роль
/// **не берётся**. Он заведён 23.10 как «нажатая плашка контрола»
/// и держится свободным под открытый вопрос о выключенной кнопке;
/// «плашка второстепенной кнопки» он только в Dark HC, в тёмной
/// второстепенная — `#3A3A3C`.
///
/// **Системный `Toggle` оставлен целиком.** Собственный `ToggleStyle`
/// дал бы обе дорожки, но забрал бы протаскивание ползунка, кривую
/// анимации и то, как система рисует этот орган в повышенном контрасте
/// и при «Уменьшении движения». Здесь меняется ровно одна величина —
/// тинт, — и это вся правка.
struct TGSwitch<Label: View>: View {
    @Binding var isOn: Bool
    @ViewBuilder var label: Label

    var body: some View {
        Toggle(isOn: $isOn) { label }
            .tint(Token.Ink.link)
    }
}
