import SwiftUI

/// Якорь кадрирования: **какая точка снимка остаётся в окне подложки**,
/// когда снимок перерастает окно.
///
/// # Отзыв, которым это оплачено
///
/// 28.10.2026, живой отзыв: на портретном снимке подложка **срезает
/// голову**. Это не дефект отрисовки — это умолчание SwiftUI, принятое
/// за решение: `scaledToFill` + `.clipped()` кадрируют **по центру**,
/// и у вертикального снимка центр приходится на корпус собаки.
///
/// Замер лежал в репозитории за три дня до отзыва и был прочитан как
/// «не дефект» (`Дизайн/кадры-приёмки/фоны-и-подложки-25.10/ПОДПИСИ.md`,
/// раздел «Ось: где снимок срезан и почему это не дефект»):
///
/// ```
/// высота 640 («Сегодня»)  масштаб 0,80 → 480 × 640. По высоте ровно,
///                         режется ШИРИНА: 39 pt с каждого края.
///                         Красный верх цел
/// высота 420 (вкладки)    масштаб 0,67 → 402 × 536. По ширине ровно,
///                         режется ВЫСОТА: ~58 pt сверху и снизу.
///                         Красного верха не остаётся
/// ```
///
/// Та запись кончалась словами «Поведение штатное… **Менять не стал:
/// это вопрос к Виктории, а не уборка**». Вопрос задал человек через
/// три дня, и ответ у дизайна был готов с самого начала — см. ниже.
///
/// > **Штатное поведение инструмента и принятое решение выглядят
/// > одинаково.** Различает их не кадр, а вопрос «кто это выбрал»:
/// > у центрирования автора не было ни одного — его выбрал `SwiftUI`.
///
/// # Откуда числа: ПРОТОТИП, а не хендофф, и это замер
///
/// Позиция кадрирования у дизайна названа **прямо**, и мы её не взяли:
/// при переносе темы «Кино» из прототипа забрали высоту (`bd.h`),
/// маску (`maskStops`) и затемнение (`scrimStops`), а третье поле
/// того же узла — `bd.pos`, то самое `background-position`, — прошло
/// мимо.
///
/// ```
/// Дизайн/редизайн-ios28/prototypes/Togo-RU.dc.html:57
///     background-size:cover; background-position:{{ bd.pos }}
/// …:922  map = { today: [портрет,  '50% 22%', '640px'],
///                 dog:   [герой,    '50% 35%', '520px'],
///                 history: [заглушка Unsplash, '50% 40%', '420px'],
///                 health:  [заглушка Unsplash, '50% 30%', '420px'] }
/// …:924  if (S.sub) m = [SUBP[kind], '50% 35%', '360px']
/// ```
///
/// **В хендоффе токенов этой величины НЕТ**, и это проверено, а не
/// предположено: `Дизайн/редизайн-ios28/tokens/togo-ios28.tokens.json`,
/// узел `backdrop` — есть `height`, `scrimStops`, `maskStops`, `tint`,
/// `headerScrim`; ключа про позицию нет ни одного. Контроль в том же
/// замере: `backdrop.height` там есть и читается кодом
/// (`Token.Size.backdropTab`), то есть разбор файла состоялся.
///
/// Поэтому дом числа сегодня — **прототип**, а не `tokens.json`, и это
/// названный долг, а не умолчание: хозяин токена `backdrop.position` —
/// дизайн. Ровно тот же путь уже прошли числа блока «Metric» (`КиноМетрика`:
/// стояли копиями с прототипа, дизайн выдал токены, копии ушли).
///
/// # Почему у вкладки 0,35, а не 0,40 и не 0,30
///
/// У прототипа три вкладки и три разных доли — но различаются они
/// **снимками, а не видами экрана**: `history` и `health` стоят
/// на заглушках Unsplash, а их «набора фото разделов мы не отдаём»
/// (ответ круга 2, пункт 1; заглушки заменены своими кадрами 04.11).
/// Единственная вкладка, чей снимок у нас есть и остаётся, — `dog`,
/// и у неё `50% 35%`. То же число прототип даёт **всем подэкранам
/// без исключения**.
///
/// > **Копировать таблицу прототипа построчно было бы переносом
/// > не правила, а его данных.** Высоты уже разошлись так же:
/// > у прототипа `dog` 520 px, у хендоффа вкладка 420 — и спор решён
/// > в пользу хендоффа (круг 2), потому что у прототипа высота
/// > подобрана под конкретную картинку.
///
/// `walk` прототип подложкой не рисует вовсе (там круглый кадр), —
/// берём долю собаки, и это названо, а не выведено.
nonisolated struct ЯкорьКадра: Equatable, Sendable {

    /// Доля ШИРИНЫ снимка, которая встанет в середину окна. 0 — левый
    /// край, 1 — правый.
    let x: CGFloat

    /// Доля ВЫСОТЫ снимка, которая встанет в середину окна. 0 — макушка,
    /// 1 — лапы.
    let y: CGFloat

    /// Прежнее поведение: ровно то, что делает `scaledToFill` сам.
    ///
    /// Нужен не для красоты — **это контроль**. Сторож, который мерит
    /// сдвиг, обязан уметь получить ноль от правила, а не только
    /// от сломанного инструмента: «сдвига нет» у центра и «сдвига нет»
    /// потому, что счёт не состоялся, иначе неразличимы.
    static let центр = ЯкорьКадра(x: 0.5, y: 0.5)

    /// Доля по горизонтали у прототипа одна на все экраны — `50 %`.
    /// Заведена именованно, чтобы случай «подвинули по вертикали,
    /// а по горизонтали забыли» был виден в одном месте.
    private static let поСередине: CGFloat = 0.5

    /// Правило по виду экрана. Числа — из прототипа, разбор в голове типа.
    static func по(виду вид: BackdropKind) -> ЯкорьКадра {
        switch вид {
        // «Сегодня»: прототип ставит портрет выше всех — 22 %.
        // На снимке 3 : 4 это ничего не меняет (там режется ширина),
        // и в том всё дело: доля начинает работать на снимке 9 : 16,
        // то есть на фотографии, снятой телефоном вертикально.
        case .today: return ЯкорьКадра(x: поСередине, y: 0.22)
        case .tab, .sub, .walk: return ЯкорьКадра(x: поСередине, y: 0.35)
        }
    }

    /// Сдвиг снимка относительно **центрированного** кадрирования.
    ///
    /// База — центр, а не верх, нарочно: ноль здесь значит «как было»,
    /// и всякий разбор начинается с вопроса «на сколько отличается
    /// от прежнего», а не «на сколько отличается от края».
    ///
    /// - Returns: `.zero`, если снимка нет, окна нет или снимок
    ///   окно не перерастает. Последнее — не вырожденный случай,
    ///   а половина всех живых: горизонтальную фотографию правило
    ///   по вертикали не трогает вовсе.
    func сдвиг(снимка снимок: CGSize, в окно: CGSize) -> CGSize {
        guard снимок.width > 0, снимок.height > 0,
              окно.width > 0, окно.height > 0 else { return .zero }
        let масштаб = max(окно.width / снимок.width, окно.height / снимок.height)
        return CGSize(
            width: Self.поОси(итог: снимок.width * масштаб, окно: окно.width, доля: x),
            height: Self.поОси(итог: снимок.height * масштаб, окно: окно.height, доля: y))
    }

    /// Одна ось. Снаружи видно только результат, поэтому ось называется
    /// в имени параметров целиком: `итог` — сколько снимок занимает
    /// ПОСЛЕ масштабирования, `окно` — сколько видно.
    private static func поОси(итог: CGFloat, окно: CGFloat, доля: CGFloat) -> CGFloat {
        let избыток = итог - окно
        guard избыток > 0 else { return 0 }
        // Куда хочет встать верх (левый край) окна в координатах снимка.
        // Прижимается к краям: доля 0,22 на низком окне увела бы окно
        // ЗА снимок, и там нечего показывать.
        let желаемое = min(max(доля * итог - окно / 2, 0), избыток)
        return избыток / 2 - желаемое
    }
}

/// Снимок, заполняющий отведённое место **по якорю**, а не по центру.
///
/// Заменяет собой три строки, которые до 04.11.2026 стояли копиями
/// в трёх местах (`CinemaBackdrop`, `ФотоШапка`, `WalkMode.фон`):
/// `Image(uiImage:).resizable().scaledToFill()`. Копий правила было
/// три, и ни одна не знала про якорь.
///
/// # Почему `GeometryReader`, а не `.frame(…, alignment: .top)`
///
/// Выравнивание даёт **девять точек**, а доля у дизайна — 22 % и 35 %,
/// и ни одна из них не край. Подменить 35 % на `.top` значит принять
/// решение за дизайн и не заметить этого: на окне 420 оба способа дают
/// один и тот же кадр, а на окне 360 расходятся на 7,6 pt.
///
/// > **Два способа, совпадающие на сегодняшнем наборе высот, выглядят
/// > одним.** Различает их не кадр, а третья высота.
///
/// Размер окна здесь нужен **числом**: доля считается от размера
/// снимка ПОСЛЕ масштабирования, а он зависит от обеих сторон окна.
/// Ширина подложки — `.infinity`, то есть снаружи она неизвестна,
/// и спросить её можно только у раскладки.
///
/// Наружу о себе вид не сообщает ничего: `.frame` по размеру окна
/// докладывает хозяину ровно размер хозяина. Это та самая починка,
/// которой уже оплачены два кадра — `scaledToFill` сообщает наружу
/// размер ПЕРЕРОСШЕГО снимка, и содержимое экрана уезжает влево
/// (разбор в `ФонФикстураСтенда.применить`). Здесь она сохранена,
/// а не заведена заново.
@MainActor
struct КадрПоЯкорю: View {
    let картинка: UIImage
    let якорь: ЯкорьКадра

    var body: some View {
        GeometryReader { окно in
            Image(uiImage: картинка)
                .resizable()
                .scaledToFill()
                .frame(width: окно.size.width, height: окно.size.height)
                .offset(якорь.сдвиг(снимка: картинка.size, в: окно.size))
        }
    }
}
