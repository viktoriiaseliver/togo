import SwiftUI

// MARK: - Стекло

/// Стекло темы «Кино»: таб-бар, плавающие кнопки, пилюли, панель показания.
///
/// **Единственное место, где выбирается путь отрисовки стекла.** Путей три,
/// и выбор между ними — не вкус, а требование рекомендации 1 и 7 хендоффа
/// iOS 28:
///
/// ```
/// Reduce Transparency включён   СПЛОШНОЙ Token.Surface.raised, блюра НЕТ
/// iOS 26 и новее                системный glassEffect(_:in:)
/// iOS 17…25                     Material: ultraThin в тёмной, regular в светлой
/// ```
///
/// Порядок веток именно такой, и это не стиль. Доступность спрашивается
/// ПЕРВОЙ: если спросить версию системы первой, то на iOS 26 человек
/// с выключенной прозрачностью получит стекло — ветка доступности
/// до него не доедет. Отказ в такой форме не красный, его видно только
/// в «Настройках» телефона, и проверить его нечем, кроме кадра.
///
/// **Чего этот тип НЕ делает, названо сразу.** Он не рисует фон-фото
/// и не знает про тон состояния: тон выбирает экран, а сюда приходит
/// уже готовая форма. Стекло — поверхность, а не состояние.
///
/// **Здесь стояло «`Token.Component.ReadingTone.*` выбирает экран».
/// Это ЛОЖНО, и ложно было в момент записи** (замер 26.10.2026):
/// у всего слоя `Token.Component.ReadingTone.*` **ноль обращений
/// вне прозы**, и единственным его вхождением в `Togo/` была ровно
/// эта строка. Экран не мог его читать по устройству — компонентные
/// токены за пределами дизайн-системы запрещены
/// (`ComponentTokenScopeTests`), — и красит тон через
/// `Token.Poster.labelOnDoseTone` / `labelOnAlarmTone` /
/// `labelOnFasting` (`ReadingPanel.swift:613-615`).
///
/// > **Доккомментарий назвал путь, которого нет, и сам был его
/// > единственным следом.** Грепом такой путь выглядит живым:
/// > одно вхождение есть, и это вхождение — утверждение о себе.
///
/// Контроль того же замера: `Token.Component.Backdrop` — 6 обращений
/// в 3 файлах, то есть инструмент видит живые компонентные токены.
/// Мёртвый путь `component.readingTone.dose.fg` удалён решением
/// Виктории 26.10.2026; остальные 25 токенов слоя оставлены —
/// решения на них нет.
///
/// **Свои rgba здесь не употребляются ни в одной ветке, и это замер,
/// а не обещание.** `Token.Glass.*` существует для двух других читателей —
/// веб-макета (`DesignTokens/build/tokens.css`) и Фигмы; в Swift на него
/// смотрит только запасной путь, и только затем, чтобы НЕ смотреть:
/// `Material` системный, а не собранный из наших долей. Разбор —
/// в описании группы `semantic.glass` в `tokens.json`.
nonisolated enum TGGlass {

    /// Плотность стекла. Два значения, потому что в хендоффе их два:
    /// `--g-bg` (плавающее) и `--g-strong` (панель показания).
    nonisolated enum Плотность: Sendable {
        /// Плавающее: таб-бар, круглые кнопки, пилюли.
        case плавающее
        /// Плотное: панель показания на «Сегодня», панель тона.
        case плотное
    }
}

private struct СтеклоModifier: ViewModifier {
    @Environment(\.accessibilityReduceTransparency) private var безПрозрачности
    @Environment(\.colorScheme) private var схема

    let плотность: TGGlass.Плотность
    let радиус: CGFloat

    func body(content: Content) -> some View {
        // Доступность ПЕРВОЙ веткой. См. разбор у `TGGlass`.
        if безПрозрачности {
            content.background(Token.Surface.raised, in: форма)
        } else if #available(iOS 26.0, *) {
            content.glassEffect(стекло, in: .rect(cornerRadius: радиус))
        } else {
            content.background(материал, in: форма)
        }
    }

    private var форма: RoundedRectangle {
        RoundedRectangle(cornerRadius: радиус, style: .continuous)
    }

    @available(iOS 26.0, *)
    private var стекло: Glass {
        плотность == .плотное ? .regular : .regular.interactive()
    }

    /// Запасной путь для iOS 17…25. Материал РАЗНЫЙ по схеме нарочно:
    /// рекомендация 1 хендоффа говорит дословно «dark/cinema →
    /// ultraThinMaterial, light → regularMaterial». В тёмной теме
    /// `regularMaterial` даёт молочную плёнку поверх чёрного фона —
    /// тот самый случай, когда «единообразие» хуже разных значений.
    private var материал: Material {
        схема == .dark ? .ultraThinMaterial : .regularMaterial
    }
}

nonisolated extension View {
    /// Стекло с заданным радиусом.
    ///
    /// Радиус обязателен и умолчания не имеет нарочно: у `glassEffect`
    /// форма — аргумент, и забытая форма даёт прямоугольник, неотличимый
    /// от «стекло не применилось» на тёмном фоне.
    func стекло(_ плотность: TGGlass.Плотность = .плавающее,
                радиус: CGFloat) -> some View {
        modifier(СтеклоModifier(плотность: плотность, радиус: радиус))
    }
}

// MARK: - Движение

/// Анимация, которой нет при Reduce Motion.
///
/// **Отдельным модификатором, а не `withAnimation` на месте вызова.**
/// Рекомендация 7 хендоффа гасит анимацию ауры и кольца; на местах
/// вызова таких анимаций будет много, и флаг, который спрашивают
/// в каждом, однажды забудут в одном — а забытый выглядит как работающий.
///
/// `nil` вместо `.default` — это именно «без анимации», а не «быстро»:
/// короткая анимация остаётся движением, и человеку, который её выключил,
/// она всё равно показывается.
private struct БезДвиженияModifier<Значение: Equatable>: ViewModifier {
    @Environment(\.accessibilityReduceMotion) private var безДвижения

    let анимация: Animation
    let значение: Значение

    func body(content: Content) -> some View {
        content.animation(безДвижения ? nil : анимация, value: значение)
    }
}

/// **`nonisolated` здесь было и валило сборку схемы** — замер 22.10.2026:
///
/// ```
/// TGGlass.swift:122:18: error: sending 'значение' risks causing
/// data races [#RegionIsolation::SendingRisksDataRace]
/// ** TEST BUILD FAILED **, rc=65
/// ```
///
/// `Значение` ограничено только `Equatable`, то есть `Sendable` не обязано;
/// `БезДвиженияModifier` изолирован `MainActor` умолчанием таргета, и
/// передача значения из неизолированного расширения в изолированный тип —
/// гонка. Снято `nonisolated`, а не добавлено `& Sendable`: **замер
/// показал, что второй таргет этого не просит.**
///
/// ```
/// вызовов `.плавно(` во всём дереве        0
/// из них в TogoWidgets                      0
/// контроль (`Token.` в TogoWidgets)         2 файла  ← grep работает
/// ```
///
/// > **И вторая половина, которую надо назвать, а не замолчать: у этого
/// > механизма НЕТ НИ ОДНОГО ЧИТАТЕЛЯ.** Reduce Motion по рекомендации 7
/// > хендоффа объявлен и не подключён ни к одной анимации. Грепом такое
/// > находится один раз — в объявлении — и выглядит работающим.
/// > Пока вызовов ноль, Reduce Motion в приложении **не сделан**,
/// > и зелёная сборка об этом не скажет.
extension View {
    /// Анимация, которая выключается системной настройкой.
    func плавно<Значение: Equatable>(_ анимация: Animation = .default,
                                     значение: Значение) -> some View {
        modifier(БезДвиженияModifier(анимация: анимация, значение: значение))
    }
}
