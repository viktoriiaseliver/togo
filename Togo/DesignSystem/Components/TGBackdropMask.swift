import SwiftUI

/// Маска исчезновения фотографии-подложки: сплошная до 45 % высоты,
/// прозрачная к 92 % — **оба стопа из `Token.Component.Backdrop.mask`**.
///
/// # Что здесь починено 26.10.2026
///
/// Третий случай одного семейства (`projects-68`) в том же компонентном
/// узле, что `scrim` и `headerScrim`, и найден он **контролем к ним**:
/// у `Backdrop.scrim` читатель появился (`TGBackdropScrim`, `30a2835`),
/// а у соседнего `Backdrop.mask` читателей в Swift было **ноль**, при том
/// что экран рисовал свою копию тех же двух стопов руками
/// (`CinemaBackdrop.маска`, `CinemaHeader.swift:465`).
///
/// ```
/// Token.Component.Backdrop.mask      читателей 0, значение верное
/// CinemaHeader.swift:466-469         Ink.primary @0.45 → opacity(0) @0.92
/// совпадение позиций                 до цифры, 0.45 и 0.92
/// доккомментарий рядом               «те же, что в прототипе
///                                     и в `component.backdrop.mask`»
/// ```
///
/// > **Доккомментарий назвал токен по имени и всё равно не был вызовом.**
/// > Грепом такое ищется и находится — находится **в прозе**, а проза
/// > вырезается до разбора, потому что иначе сторож меряет прозу.
/// > Поэтому `ComponentTokenScopeTests` молчал честно: обращения не было.
///
/// # Почему это безопасная правка, а не смена вида
///
/// `.mask` читает **только альфа-канал**, и обе записи дают по альфе
/// дословно одно и то же:
///
/// ```
/// было    Token.Ink.primary            @0.45 → альфа 1
///         Token.Ink.primary.opacity(0) @0.92 → альфа 0
/// стало   #000000FF                    @0.45 → альфа 1
///         #00000000                    @0.92 → альфа 0
/// ```
///
/// То есть ни один пиксель не меняется, и кадровой приёмки эта правка
/// не требует — в отличие от восьми стопов затемнения, где вид поехал.
/// Отличие только в том, **откуда взяты числа**: раньше из экрана,
/// теперь из токена, который дизайнер правит.
///
/// Прежний обход и его причина записаны там же: литеральный `.black`
/// слой вида не пускает (`DesignLiteralTests`, «цветов строго ноль»),
/// поэтому экран брал альфу у первого попавшегося **сплошного** токена.
/// Довод был верен, выбор — произволен: `Token.Ink.primary` не имеет
/// к маске отношения, и в день, когда у него появится своя альфа,
/// маска поедет без всякой связи с макетом.
///
/// # Почему компонентом
///
/// `Token.Component.*` экрану звать нельзя — `ComponentTokenScopeTests`
/// держит счёт таких обращений из экранов на нуле, и запрет измерен:
/// главная кнопка давала 1,68:1 при верном токене и зелёном тесте,
/// потому что экран собрал кнопку сам.
///
/// # Чего этот тип НЕ решает
///
/// **Нужна ли маска вообще** — у экрана: на `#000` без подложки маскировать
/// нечего, а безусловная маска стоила бы прохода композитора и не меняла
/// бы ни одного пикселя. Условие берётся у того же хозяина, что решает,
/// рисовать ли фото (`BackgroundStore`), — второй ответ на тот же вопрос
/// разошёлся бы молча.
struct TGBackdropMask: View {

    var body: some View {
        LinearGradient(
            stops: Token.Component.Backdrop.mask.map {
                Gradient.Stop(color: $0.color, location: $0.position)
            },
            startPoint: .top,
            endPoint: .bottom
        )
    }
}
