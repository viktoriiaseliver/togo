import SwiftUI

/// Стеклянная панель показания на «Сегодня» и высота блока, в котором она
/// лежит, — **оба числа из `Token.Component.ReadingPanel.*`**, а не
/// литералом и не через соседнее имя.
///
/// # Что здесь починено 26.10.2026
///
/// Семейство `projects-68`: значение в источнике правды верное, а на экране
/// другое, и грепом это не ищется — имя есть, значение есть, **вызова нет**.
/// Замер по шести токенам группы `component.readingPanel`:
///
/// ```
/// токен          значение  читателей в Swift  что стояло на экране
/// glassRadius        24            0          ЛИТЕРАЛ 24
///                                             (`ReadingPanel.swift:376`)
/// height            360            0          Token.Size.hero
/// heightAX          220            0          Token.Size.heroAX
/// radius             32            0          блок рамки не имеет вовсе
/// readingSize        56            0          ЛИТЕРАЛ 56
/// captionSize        14            0          AppFont.captionEmphasis
/// контроль: Backdrop.HeaderScrim.alpha → 1 читатель (`TGHeaderScrim`)
/// ```
///
/// Этот файл закрывает первые три. Три нижние названы, а не умолчаны, —
/// разбор в конце головы.
///
/// # Почему `Token.Size.hero` вместо токена панели — это дефект, а не синоним
///
/// `component.readingPanel.height` — **алиас** `{primitive.size.hero}`, то
/// есть сегодня оба имени дают 360, и подмена не видна ни кадром,
/// ни сторожем. Цена у неё не в числе, а в том, что алиас **уезжает
/// дизайнеру отдельной переменной**:
///
/// ```
/// DesignTokens/build/figma-variables.json
///   {"name": "readingPanel/height", "alias": "size/hero",
///    "aliasCollection": "Primitive"}
///   {"name": "readingPanel/glassRadius", "alias": "radius/card", …}
/// ```
///
/// Компонентный слой существует ровно затем, чтобы его **перенаправляли**:
/// переставь `component.readingPanel.height` на другой примитив — в Figma
/// панель поедет, а Swift останется на `size.hero` и промолчит. Это тот же
/// случай, за который мы уже платили `Token.FontSize.micro = 14` при живом
/// `AppFont.micro = 15`: применивший ступень в макете получал одно число,
/// а приложение рисовало другое.
///
/// > **Два имени одного примитива — не копия значения, а копия РЕШЕНИЯ
/// > о том, откуда значение берут.** Разойдутся они в тот день, когда
/// > кто-нибудь воспользуется компонентным слоем по назначению.
///
/// # Почему компонентом, а не токеном в экране
///
/// `ComponentTokenScopeTests` держит счёт обращений к `Token.Component.*`
/// из `Togo/Features` на **нуле**, и запрет измерен: главная кнопка давала
/// 1,68:1 при верном токене и зелёном тесте, потому что экран **собрал
/// кнопку сам**. Поэтому токен читает компонент, а экран читает компонент —
/// та же форма, что у `TGHeaderScrim` (`440e4e5`) и `TGBackdropScrim`
/// (`30a2835`).
///
/// # Чего этот тип НЕ делает
///
/// **Он не знает про тон.** `ReadingTone` живёт в `Togo/Features/Today/`,
/// и дизайн-системе на него смотреть нельзя по слоям; решение «кроет ли
/// заливка стекло» принимает экран и передаёт готовый цвет. Это та же
/// граница, что у `TGHeaderScrim`: условие «рисовать ли вообще» остаётся
/// у того, кто знает состояние.
///
/// **Он не зовёт `.стекло(радиус:)`, и это решение с ценой.**
/// Здесь было записано, что `TGGlass.Плотность.плотное` объявлено
/// дословно «панель показания на „Сегодня“, панель тона» и не имеет
/// ни одного вызова во всём дереве. Замер был верен, и **26.10.2026
/// Виктория решила этот разрыв в другую сторону: не подключать
/// механизм, а удалить его.** `плотное` вместе с перечислением
/// и параметром убрано; у стекла осталась одна плотность, бывшая
/// `плавающее`.
///
/// Разрыв, который запись называла, этим НЕ закрыт, а снят с повестки:
/// панель по-прежнему красит себя сама, и вид у неё другой, чем
/// у общего стекла:
///
/// ```
///                        здесь                 .стекло(радиус:)
/// Reduce Transparency     Surface.card          Surface.raised
/// iOS 26 и новее          .ultraThinMaterial    glassEffect(.regular
///                                                 .interactive())
/// ```
///
/// Поведение сохранено **дословно**, и расхождение названо по-прежнему:
/// следующий, кто решит «унифицировать стекло», должен знать, что это
/// две правки, а не одна, и что у второй есть хозяин — Виктория,
/// потому что это смена вида, а приёмка у вида кадр.
///
/// # Токены группы, у которых читателей нет
///
/// Их было три. `radius` (32, «панель целиком») **удалён 26.10.2026**
/// решением Виктории: рисовать ему было нечему — блок лежит во всю
/// ширину и рамки не имеет, — и читателей у него не было ни одного
/// при живом контроле `glassRadius` (1 читатель, он ниже в этом
/// файле). Нужна ли панели внешняя рамка — вопрос к макету, не
/// к коду, и ответ на него заведёт токен заново.
///
/// Осталось два, и они НЕ удаляются: решения на них нет.
/// `readingSize` (56) и `captionSize` (14) — типографика; 56 стоит
/// литералом в `показаниеКрупно`, и его держит храповик
/// `DesignLiteralTests`. Трогать их этой правкой нельзя: кегль на этом
/// экране — чужой предмет, а снижение чужого храповика смешало бы две
/// приёмки.
struct TGGlassPanel<Содержимое: View>: View {

    /// Заливка, кроющая стекло целиком. `nil` — стекло остаётся стеклом.
    ///
    /// **Умолчания нет нарочно.** Забытый аргумент дал бы стекло там, где
    /// тон обязан крыть панель насмерть, — а это ровно тот отказ, который
    /// не виден ни компилятору, ни сторожу: панель выглядит целой, просто
    /// сквозь неё светит фотография. Явный `nil` читается как решение.
    var заливка: Color?

    @ViewBuilder var содержимое: Содержимое

    /// Прозрачность выключена в системе — блюра не будет, будет сплошная
    /// поверхность (хендофф, «Рекомендации» 7).
    @Environment(\.accessibilityReduceTransparency) private var безПрозрачности

    var body: some View {
        содержимое
            .padding(Token.Space.s16)
            // `background { … }` со слотом, а не `background(_:in:)`:
            // поверхность тут ВЬЮ (материал либо заливка), а не `ShapeStyle`,
            // и форму ей задаёт обрезка. Компилятор сказал это прямо —
            // «requires that 'some View' conform to 'ShapeStyle'».
            .background {
                поверхность
                    .clipShape(RoundedRectangle(
                        cornerRadius: Token.Component.ReadingPanel.glassRadius,
                        style: .continuous))
            }
    }

    @ViewBuilder
    private var поверхность: some View {
        if let заливка {
            // Янтарь, синий и терракот кроют панель целиком — стекла
            // под ними нет вовсе, и блюр тут ничего не решает.
            Rectangle().fill(заливка)
        } else if безПрозрачности {
            Rectangle().fill(Token.Surface.card)
        } else {
            Rectangle().fill(.ultraThinMaterial)
        }
    }
}

// MARK: - Высота блока показания

/// Высота блока, в котором лежит панель: `component.readingPanel.height`
/// 360, при крупном кегле `heightAX` 220.
///
/// **Ось крупного кегля — НАША, у хендоффа её нет.** Панель ужимается,
/// чтобы кнопки низа остались на экране. Правило переехало сюда из
/// `ReadingPanel.высота` вместе с токенами: держать ось в экране, а числа
/// в компонентном слое значило бы, что при смене числа правок две,
/// а помнит о них один.
///
/// Вторая копия этой же оси живёт в `CinemaBackdrop.высота`
/// (`guard !размерТекста.isAccessibilitySize else { return Token.Size.heroAX }`)
/// и **сюда не сведена нарочно**: там она меряет ПОДЛОЖКУ, а дизайн
/// 23.10.2026 сказал про неё дословно «`size.hero` (360) — карточка-герой,
/// к подложке не относится. Подложку от него отвязать». Свести две оси
/// в одну — значит снова связать то, что велено развязать; у подложки
/// свои четыре высоты (`Token.Component.Backdrop.Height.*`), и ответа
/// про её крупный кегль в хендоффе нет. Вопрос открыт и адресован
/// дизайну, а не закрыт здесь молча.
private struct ВысотаПанелиПоказанияModifier: ViewModifier {

    @Environment(\.dynamicTypeSize) private var размерТекста

    func body(content: Content) -> some View {
        content.frame(minHeight: размерТекста.isAccessibilitySize
                      ? Token.Component.ReadingPanel.heightAX
                      : Token.Component.ReadingPanel.height)
    }
}

extension View {

    /// Минимальная высота блока показания — из `component.readingPanel`,
    /// с осью крупного кегля внутри.
    func высотаПанелиПоказания() -> some View {
        modifier(ВысотаПанелиПоказанияModifier())
    }
}
