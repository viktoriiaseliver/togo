import SwiftUI

/// Ряд чисел, который на доступных размерах становится столбцом.
///
/// Долг назван в `TGRows.swift` у самого `TGStat`, дословно: «на
/// доступных размерах ряду из трёх чисел нужна другая раскладка —
/// столбцом, как у плиток и карточки дежурства. Мест таких двенадцать,
/// и это отдельная работа, а не довесок к этой». Починено было одно —
/// «Питание» (`FeedingScreen.стрелкаЧиселСегодня`), и форма взята
/// оттуда дословно: явный `if`, одни и те же дети у обеих ветвей,
/// `s10` в столбце и `0` в строке.
///
/// ## Чего он НЕ делает
///
/// Не ужимает и не обрезает. Ограничение строк и `minimumScaleFactor`
/// живут внутри `TGStat` и там же объяснены; здесь только **ось
/// раскладки**. Без этой оси ужатие работает и содержимое остаётся —
/// но три длинных русских слова в четырёхстах точках не помещаются
/// по устройству, и `TGStat` честно давал их вдвое мельче просимого.
///
/// ## Почему тип, а не `if` в каждом из одиннадцати мест
///
/// У соседа по этому же долгу записано, зачем дети вынесены в одну
/// переменную: «Дети у обеих раскладок — буквально одни и те же.
/// Разойдись они, и ветка, которую реже видят, отстанет молча». Это
/// верно и на уровень выше: через одиннадцать копий самого `if`
/// расходится уже раскладка. В этом проекте такая история записана
/// у `TGLink` — связка была скопирована в двух десятках мест, копии
/// разошлись, и строка красилась в синий там, где забыли модификатор.
///
/// ## `ViewThatFits` запрещён, и не по вкусу
///
/// Он держит в дереве обе ветки, и озвучка находит два одинаковых
/// органа. Явный `if` в `body` даёт `_ConditionalContent` — в дереве
/// ровно одна ветка. Тот же запрет: `TodayBottom:45`.
struct РядЧисел<Числа: View>: View {
    /// Выравнивание строки на обычных размерах.
    ///
    /// По умолчанию `.center`: так стоит в десяти местах из одиннадцати.
    /// `TodaySummaryStrip` просит `.top` и передаёт его сам. Параметр
    /// есть ровно затем, чтобы правка не поехала по виду на обычном
    /// кегле: ось приёмки — «содержимое не теряется ни на одной
    /// ступени, косметику держим до `.xxxLarge`», то есть на обычном
    /// кегле не должно измениться ничего.
    var выравнивание: VerticalAlignment = .center

    @ViewBuilder var числа: Числа

    @Environment(\.dynamicTypeSize) private var размерТекста

    var body: some View {
        if размерТекста.isAccessibilitySize {
            // Столбец, а не строка: каждому числу достаётся вся ширина
            // карточки, и подпись перестаёт ломаться посреди слова.
            VStack(spacing: Token.Space.s10) { числа }
        } else {
            HStack(alignment: выравнивание, spacing: 0) { числа }
        }
    }
}
