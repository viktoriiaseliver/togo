/// «Просится» — восемь состояний вердикта, которые можно **увидеть**.
///
/// **Пять случаев `NeedVerdict`, шесть объяснений, восемь экранов.**
/// У `.unknown` три причины; `VerdictEngine.explanation` различает все
/// три, а `.ambiguous` приходит двумя разными путями — «интервалов нет
/// вовсе» и «интервалы есть, картина ровная». Текст у них один, строка
/// фактов разная, и поэтому они стоят отдельно: кадр отвечает на вопрос
/// «что человек прочитает», а прочитает он их по-разному.
///
/// Восьмое состояние — не исход, а **расхождение**: `.probablyAttention`
/// пишет «Вышли N назад», считая N по времени мочи. В остальных семи
/// оба числа заданы одинаковыми, и на кадре это неразличимо.
///
/// **Число «четыре исхода» стояло в двух файлах и было неверным.**
/// Посчитано 07.10.2026; `.episode` и `.silence` приехали позже,
/// а строка осталась и читалась вместо кода.
///
/// ## Почему это галерея, а не шесть тестов
///
/// Тесты на вердикт есть и они зелёные — `VerdictEngineTests` перебирает
/// все случаи. Они отвечают, **верно ли посчитано**. Чего человек
/// прочитает на экране, не проверял никто: до сегодня, чтобы увидеть
/// «отметок мочи нет», надо было восемнадцать дней не вести дневник.
///
/// ## Чего кадр отсюда НЕ доказывает
///
/// - **Что собака доведёт приложение до этого состояния.** Здесь срез
///   фактов собран значениями, а не прожит. Галерея отвечает «что
///   написано и как свёрстано», а не «случится ли».
/// - **Что `Diary.signals` соберёт такой же срез из событий.** Шов
///   подставляет `NeedSignals` мимо базы; путь «события → сигналы»
///   остаётся непроверенным этим кадром и проверяется тестами.
/// - **Ритм выходов.** `WalkRhythmCard` читает `dog?.events`, а собаки
///   здесь нет: во всех восьми он показывает ветку «данных нет». Это
///   не дефект состояния, а отсутствие собаки.
///
/// Вердикт при этом считает **настоящий** `VerdictEngine`: подставлен
/// срез фактов, а не готовый вердикт. Подставь готовый — и кадр
/// доказывал бы, что верна подпись под картинкой.
struct VerdictGallery: View {
    private static let час: TimeInterval = 3600
    private static var сейчас: Date { Date() }

    var body: some View {
        TGScreen(title: "Просится") {
            TGExplainer(text: "Факты собраны значениями, живой истории здесь нет. Собака не передана, поэтому блок ритма во всех восьми показывает «данных нет» — это отсутствие собаки, а не состояние вердикта.")

            состояние("МАЛО ДАННЫХ · «Непонятно» · неясно",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(3),
                                  lastStool: Self.назад(9),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  daysOfData: 2,
                                  lastOutingAt: Self.назад(3)))

            состояние("СРОЧНО · дольше, чем когда-либо терпел",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(14),
                                  lastStool: Self.назад(20),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  lastOutingAt: Self.назад(14)))

            состояние("ПОХОЖЕ НА НУЖДУ · дольше обычного, но не рекорд",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(8),
                                  lastStool: Self.назад(11),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  lastOutingAt: Self.назад(8)))

            состояние("СКОРЕЕ ВНИМАНИЯ · вышли только что, и он сходил",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(1),
                                  lastStool: Self.назад(1),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  lastOutingHadResult: true,
                                  lastOutingAt: Self.назад(1)))

            состояние("НЕЯСНО · интервалы есть, картина ровная",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(4),
                                  lastStool: Self.назад(7),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  lastOutingAt: Self.назад(4)))

            // Второй путь в ту же `.ambiguous`: данных хватает по дням,
            // а интервалов нет. Текст совпадает с состоянием выше,
            // строка фактов — нет, и это единственное, чем они
            // различаются на экране.
            //
            // Стул здесь не задан нарочно: это единственное состояние,
            // показывающее ветку «стула ещё не было». Еда и прогулка
            // стоят, как у остальных шести, — иначе строка фактов
            // отличалась бы сразу двумя вещами, и сравнить было бы
            // нечего.
            состояние("НЕЯСНО · дней хватает, интервалов нет вовсе",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(4),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  daysOfData: 10,
                                  lastOutingAt: Self.назад(4)))

            // Здесь и проверяется починка 28.09: восемнадцать дней без
            // отметок обязаны читаться как молчание дневника, а не как
            // «дольше, чем он когда-либо терпел». И 05.10 на этом же
            // состоянии кадр поймал две точки подряд — `Fmt.shortDay`
            // несёт точку сокращения, шаблон ставил свою.
            состояние("ОТМЕТОК МОЧИ НЕТ · 18 дней молчания, выходов тоже нет",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(18 * 24),
                                  lastStool: Self.назад(18 * 24),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 30,
                                  lastOutingAt: Self.назад(18 * 24)))

            // **Состояние заведено, чтобы РАСХОЖДЕНИЕ стало видно.**
            // `explanation` для `.probablyAttention` пишет «Вышли N
            // назад», а N берёт из `sinceUrine` — времени последней
            // мочи, не выхода. В шести состояниях выше оба числа
            // заданы одинаковыми, и на кадре это неразличимо.
            //
            // Здесь моча час назад, а выход — три. Экран скажет
            // «Вышли 1 ч назад» про выход, которому три часа.
            // В жизни зазор ровно такой: собака писает в конце
            // прогулки, а вышли вы в начале.
            //
            // > Величина определена как «сколько не писал» и показана
            // > как «когда вышли». Сокращают не слова, а область
            // > действия утверждения — и по самой строке этого
            // > не видно.
            //
            // Какое число тут верное — решение продуктовое, не моё.
            // Дело тестировщика — чтобы его принимали, глядя на кадр,
            // а не на структуру.
            состояние("РАСХОЖДЕНИЕ · «Вышли 1 ч назад», а выход был 3 ч назад",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(1),
                                  lastStool: Self.назад(1),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  lastOutingHadResult: true,
                                  lastOutingAt: Self.назад(3)))

            состояние("ЭПИЗОД · вердикт не считается вовсе",
                      NeedSignals(now: Self.сейчас,
                                  lastUrine: Self.назад(5),
                                  lastStool: Self.назад(2),
                                  lastMeal: Self.назад(5),
                                  lastWalk: Self.назад(3),
                                  urineIntervals: [4 * Self.час, 6 * Self.час, 12 * Self.час],
                                  daysOfData: 10,
                                  episodeActive: true,
                                  lastOutingAt: Self.назад(5)))
        }
    }

    private static func назад(_ часов: Double) -> Date {
        сейчас.addingTimeInterval(-часов * час)
    }

    private func состояние(_ подпись: String, _ сигналы: NeedSignals) -> some View {
        VStack(alignment: .leading, spacing: Token.Space.s8) {
            Text(подпись)
                .font(.caption2.monospaced())
                .foregroundStyle(Token.Ink.secondary)
            NeedsSheet(dog: nil, демоСигналы: сигналы)
                .frame(height: 560)
                .clipShape(RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous))
                .overlay(
                    RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous)
                        .strokeBorder(Token.Ink.silhouette.opacity(0.25), lineWidth: 1)
                )
        }
        .padding(.top, Token.Space.s12)
    }
}

