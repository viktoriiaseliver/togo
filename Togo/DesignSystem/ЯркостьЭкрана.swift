import SwiftUI
import UIKit

/// Поднять яркость экрана на время показа и **вернуть её обратно**.
///
/// Нужно там, где с экрана читает ДРУГОЙ человек в чужом свете: номер
/// рецепта в аптеке, сводка врачу. Своя яркость у человека обычно
/// выставлена под себя и под экономию, а не под то, чтобы провизор
/// разобрал восемь цифр через стекло.
///
/// ## Возврат — не вежливость, а предмет этого файла
///
/// Обязательство записано в голове `PrescriptionScreens` ещё до того,
/// как экран появился, и оно же делало задачу неоднострочной:
///
/// > **Яркость надо вернуть.** Забытый возврат — молчаливый расход
/// > батареи, который человек свяжет с чем угодно, кроме рецепта.
///
/// Поэтому возврат висит на ТРЁХ событиях, а не на кнопке «Закрыть»:
///
/// ```
/// onDisappear        ушли с экрана — в том числе свайпом, а не кнопкой
/// scenePhase != .active   свернули, позвонили, заблокировали
/// scenePhase == .active   вернулись — поднимаем снова, пока экран открыт
/// ```
///
/// **Кнопки «Закрыть» среди них нет нарочно.** Уход кнопкой — один
/// случай из четырёх, и повесить возврат на него значило бы починить
/// одну дорогу из четырёх: ровно тот класс, которым у нас оплачены
/// «починка на одной поверхности из трёх» и «проверка, стоящая после
/// действия, которое она сторожит».
///
/// ## Исходная яркость сохраняется ОДИН раз
///
/// `поднять()` пишет `исходная` только когда она пуста. Без этой
/// проверки второй вызов (возврат из фона, повторный `onAppear`
/// у `fullScreenCover`) сохранил бы **единицу** как «исходную» —
/// и возврат вернул бы максимум. Экран бы потускнел ровно никогда,
/// а виноват был бы не он.
///
/// ## Экран берётся у сцены, а не у `UIScreen.main`
///
/// `UIScreen.main` не различает сцен и размечен к выводу. Сцена
/// ищется **без требования `foregroundActive`**: в момент возврата
/// яркости при сворачивании активной сцены уже нет, и строгий фильтр
/// оставил бы яркость поднятой именно в том случае, ради которого
/// возврат и заведён.
@MainActor
private enum ЭкранСцены {
    static var текущий: UIScreen? {
        UIApplication.shared.connectedScenes
            .compactMap { $0 as? UIWindowScene }
            .first?
            .screen
    }
}

private struct ЯркостьНаМаксимум: ViewModifier {
    @Environment(\.scenePhase) private var фаза
    @State private var исходная: CGFloat?

    func body(content: Content) -> some View {
        content
            .onAppear { поднять() }
            .onDisappear { вернуть() }
            .onChange(of: фаза) { _, новая in
                if новая == .active { поднять() } else { вернуть() }
            }
    }

    private func поднять() {
        guard let экран = ЭкранСцены.текущий else { return }
        // Только если ещё не сохраняли: иначе «исходной» станет единица.
        if исходная == nil { исходная = экран.brightness }
        экран.brightness = 1.0
    }

    private func вернуть() {
        guard let экран = ЭкранСцены.текущий, let было = исходная else { return }
        экран.brightness = было
        // Обнуляем, чтобы следующий `поднять()` сохранил настоящее
        // текущее значение. Если человек подкрутил яркость, пока
        // приложение было свёрнуто, его выбор и станет новой исходной —
        // это верно, а не досадно.
        исходная = nil
    }
}

extension View {
    /// Яркость на максимум, пока экран открыт, и обратно при любом уходе.
    ///
    /// Чего этот модификатор НЕ умеет, и это написано, а не подразумевается:
    ///
    /// - **убийство процесса.** Если приложение снимут из многозадачности
    ///   с открытым экраном, `onDisappear` не придёт ни разу, и яркость
    ///   останется поднятой до следующей правки человеком. Системного
    ///   способа вернуть её из небытия нет; поэтому возврат висит и на
    ///   `scenePhase` — сворачивание наступает раньше убийства почти
    ///   всегда;
    /// - **разные сцены.** Берётся первая оконная сцена. На iPhone она
    ///   одна; на iPad в двух окнах яркость общая у устройства, так что
    ///   выбор сцены на исход не влияет;
    /// - **кадр.** Что на экране стало светлее, модификатор не
    ///   доказывает. Это проверяется кадром и измерением яркости кадра,
    ///   а не чтением кода: у нас уже был случай, где подпись «светлая
    ///   тема» стояла над тёмным кадром.
    func яркостьНаМаксимум() -> some View {
        modifier(ЯркостьНаМаксимум())
    }
}
