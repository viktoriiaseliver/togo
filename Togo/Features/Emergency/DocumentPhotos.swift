import SwiftUI
import SwiftData
import PhotosUI
import UIKit

/// Фотографии документов: паспорт, чип, прививки, анализы.
///
/// Модель `DogDocument` лежала в схеме с самого начала — с полем под снимок
/// и каскадным удалением, — но экрана у неё не было ни одного. При этом
/// на «Документах» уже было написано, что фотографии паспорта удобно
/// держать здесь же: текст обещал то, чего в приложении не существовало.
struct DocumentPhotosCard: View {
    let dog: Dog

    @Environment(\.modelContext) private var context
    @Environment(AppState.self) private var appState

    /// Запросом, а не через связь: только что вставленный документ
    /// в обратной связи появляется не сразу, и список остался бы пустым.
    @Query(sort: \DogDocument.addedAt, order: .reverse) private var allDocuments: [DogDocument]

    @State private var picked: PhotosPickerItem?
    @State private var pendingImage: Data?
    @State private var viewing: DogDocument?

    /// Крупный системный кегль сужает сетку. Ответ дизайна 25.10.2026,
    /// круг 5, пункт 6: «3 колонки… при AX-размерах — 2 колонки».
    @Environment(\.dynamicTypeSize) private var размер

    /// Какое направление выбрано. `nil` — все.
    @State private var направление: DocumentDirection?

    private var documents: [DogDocument] {
        // Надгробия мимо: `@Query` идёт мимо фильтра `dog.documents`.
        allDocuments.filter {
            $0.dog?.persistentModelID == dog.persistentModelID && $0.deletedAt == nil
        }
    }

    /// Снимки выбранного направления.
    private var отобранные: [DogDocument] {
        guard let направление else { return documents }
        return documents.filter { $0.direction == направление }
    }

    /// Направления, у которых СНИМКИ ЕСТЬ, по порядку перечисления.
    ///
    /// **Пустые чипы не показываются нарочно.** Семь направлений
    /// плюс «все» — восемь органов управления над сеткой из трёх
    /// плиток; шесть из них ответили бы пустотой. Чип, который
    /// заведомо ничего не найдёт, — это не фильтр, а обещание
    /// данных, которых нет.
    ///
    /// Порядок берётся у `allCases`, а не у частоты: список
    /// направлений человек читает глазами, и порядок, меняющийся
    /// от того, что он снял последним, искать мешает.
    private var направленияСоСнимками: [DocumentDirection] {
        let есть = Set(documents.compactMap(\.direction))
        return DocumentDirection.allCases.filter(есть.contains)
    }

    /// Снимки по месяцам события, новые сверху.
    ///
    /// # Почему по `occurredOn`, а не по `addedAt`
    ///
    /// Её слова 28.10.2026, прямым текстом: «чтоб потом быстро
    /// находить документы по датам и то какие были сделаны анализ
    /// а в каком направлении». Дата, которую ищут, — **когда это
    /// сделали**, а не когда сфотографировали: карту Стича снимали
    /// одним вечером, и по `addedAt` все анализы за два года легли
    /// бы в один день.
    ///
    /// # Снимки без даты события лежат ОТДЕЛЬНО, а не подставляются
    ///
    /// Поставить им `addedAt` было бы подстановкой, которая становится
    /// утверждением человека: «анализ сделан 28 октября» — это запись,
    /// которую потом читает врач. Поэтому у них своя группа в конце,
    /// и она заодно показывает, чему дату стоит проставить.
    ///
    /// Ключ `nil` в кортеже и значит «даты события нет».
    private var поМесяцам: [(месяц: Date?, снимки: [DogDocument])] {
        let календарь = Calendar.current
        var группы: [Date?: [DogDocument]] = [:]
        for снимок in отобранные {
            let ключ = снимок.occurredOn.map {
                календарь.date(from: календарь.dateComponents([.year, .month], from: $0)) ?? $0
            }
            группы[ключ, default: []].append(снимок)
        }
        // Внутри месяца — по дню события, новые сверху. У группы без
        // даты сортировать по событию нечем, там порядок по съёмке.
        let сНазванной = группы
            .compactMap { ключ, снимки -> (месяц: Date?, снимки: [DogDocument])? in
                guard let ключ else { return nil }
                return (ключ, снимки.sorted {
                    ($0.occurredOn ?? $0.addedAt) > ($1.occurredOn ?? $1.addedAt)
                })
            }
            .sorted { ($0.месяц ?? .distantPast) > ($1.месяц ?? .distantPast) }
        let безДаты = группы[Date?.none].map {
            [(месяц: Date?.none, снимки: $0.sorted { $0.addedAt > $1.addedAt })]
        } ?? []
        return сНазванной + безДаты
    }

    /// # Снимки закрыты МЕДИЦИНСКИМ правом, а не `editProfile`
    ///
    /// Здесь лежит ветпаспорт с прививками, анализы и назначения —
    /// виды документов называют это прямо (`DocumentKind`: паспорт,
    /// чип, договор, сертификат). Тот же класс данных, что
    /// у `LabResultScreens` и `PrescriptionScreens`, и у всего
    /// медицинского слоя приёмка прав одна: **видеть — `seeMedical`,
    /// править — `editTreatment`** (четыре экрана «Здоровья»,
    /// `docs/матрица-ролей.md`). Собственный разбор проекта
    /// (`docs/медкнижка-покрытие.md`, слой 2) считает `DogDocument`
    /// частью медкнижки, а не профиля.
    ///
    /// **До 26.10.2026 здесь стоял `editProfile` — и это был обход
    /// права, а не решение.** Причём дыра шире, чем «не то право»:
    /// `editProfile` закрывал ТОЛЬКО плитку «Снять». Показ снимков
    /// и кнопка «Удалить снимок» в просмотре не спрашивали **ничего**,
    /// поэтому ветпаспорт листал и удалял любой, кто дошёл до экрана.
    ///
    /// ```
    ///                seeMedical  editTreatment   БЫЛО: editProfile
    /// владелец            ✔            ✔                ✔
    /// со-владелец         ✔            ✘                ✔
    /// ухаживающий         ✔            ✘                ✘   ← входа не видел
    /// помощник            ✘            ✘                ✘   ← СНИМКИ ВИДЕЛ
    /// наблюдатель         ✔            ✘                ✘   ← входа не видел
    /// ```
    ///
    /// Старое право промахивалось в обе стороны сразу: выгульщику
    /// без `seeMedical` показывало анализы, а ухаживающему
    /// и наблюдателю, у которых `seeMedical` есть, не показывало
    /// даже входа. Разрешение «на неделю ситтеру» выдаётся поимённо
    /// (`FamilyMember.permissions`) — для этого права и не потолок.
    ///
    /// Отказ рисует `ПлашкаПрава`, а не свой баннер: имя права человек
    /// ищет в «Семье» по тому же `Permission.title`, и своими словами
    /// его называть нельзя.
    private var canSee: Bool { appState.can(.seeMedical) }
    private var canEdit: Bool { appState.can(.editTreatment) }

    var body: some View {
        TGCard(spacing: 0) {
            TGSectionHeader(title: "снимки",
                            subtitle: "паспорт и прививки спрашивают первыми — у врача, на границе и в гостинице")

            if !canSee {
                // Снимки не показываются вовсе — плашка вместо них,
                // а не сетка в выключенном виде: выключенная сетка
                // всё равно показывала бы страницы документов.
                ПлашкаПрава(право: .seeMedical)
            } else {
                if documents.isEmpty {
                    TGExplainer(text: "Пока ничего не сфотографировано. Снимки лежат на телефоне и никуда не отправляются.")
                }

                просрочка
                чипыНаправлений
                сетка
            }
        }
        .onChange(of: picked) { _, item in load(item) }
        .sheet(item: Binding(get: { pendingImage.map(PendingPhoto.init) },
                            set: { if $0 == nil { pendingImage = nil } })) { pending in
            DocumentFieldsSheet(image: pending.data, draft: DocumentDraft()) { draft in
                add(image: pending.data, draft: draft)
            }
        }
        .sheet(item: $viewing) { document in
            DocumentViewerSheet(document: document,
                                canEdit: canEdit,
                                onChange: { сохранить() },
                                onDelete: { delete(document) })
        }
    }

    /// Истёкший срок — наверху карточки, а не внутри плитки.
    ///
    /// **Плитку не трогаю нарочно:** её состав задан ответом дизайна
    /// 25.10.2026, круг 5, пункт 6, до числа («подпись на снимке:
    /// стекло, отступ 8, радиус 8, высота от 28, поля 4 × 8»), и
    /// значок срока там — правка по чужому решению. А без показа
    /// снаружи истёкший паспорт нашёлся бы только тыканьем в десять
    /// плиток по очереди — то есть ровно тогда, когда уже поздно.
    ///
    /// **Здесь «истёк», и только «истёк».** «Истекает через N дней»
    /// требует запаса в днях, которого нет ни в коде, ни в ТЗ;
    /// по этой же причине `ReminderScheduler` отказался заводить
    /// напоминание о сроке — разбор там, в `строкиКонтроля`.
    @ViewBuilder
    private var просрочка: some View {
        let истёкшие = documents.filter { СрокДокумента.у($0).истёк }
        if !истёкшие.isEmpty {
            // Названия ИНТЕРПОЛИРУЮТСЯ, а не склеиваются `.готовая`:
            // название вводит человек, и `.готовая` отправила бы его
            // в каталог искать перевод («паспорт» там ключ и есть).
            // Тот же приём, что у `ПлашкаПрава` с именем права.
            //
            // Слово «проверь:» в подписи — не украшение: подпись
            // из ОДНОЙ интерполяции дала бы каталогу ключ `%@`,
            // то есть ключ без текста, который столкнётся с любым
            // другим таким же.
            TGBanner(tone: .alarm,
                     title: "Срок истёк",
                     subtitle: "проверь: \(истёкшие.map(\.title).joined(separator: ", "))",
                     systemImage: "exclamationmark.triangle")
        }
    }

    // MARK: Сетка снимков

    /// Сетка 3 в ряд из плиток-фотографий плюс плитка «Снять».
    ///
    /// # Почему сетка, а не список
    ///
    /// Эталон v10, `36-screens.jpg`: шесть плиток по три в ряд, подпись
    /// лежит НА снимке слева внизу, последняя плитка — тёмная, со
    /// значком камеры и словом «Снять». У нас тут стоял вертикальный
    /// список строк с миниатюрой 44×44.
    ///
    /// Разница не в красоте. Снимок документа ищут **в спешке и глазами**
    /// — у врача, на границе, в гостинице, — и ищут по тому, КАК
    /// страница выглядит, а не по тому, как её назвали при съёмке.
    /// Миниатюра 44 pt этого не даёт: на ней не отличить страницу
    /// паспорта от страницы прививок. Шесть строк по 44 занимают
    /// столько же места, сколько шесть плиток, на которых видно.
    ///
    /// # Форма взята, а не придумана
    ///
    /// `LazyVGrid` в проекте живёт в четырёх местах; ближайшее
    /// по смыслу — `IncidentSheet:29`: `GridItem(.flexible())`,
    /// повторённый по числу колонок, с одинаковым зазором по обеим осям.
    /// Здесь то же самое, колонок три.
    ///
    /// # «Снять» — плитка сетки, а не строка под ней
    ///
    /// Так на кадре, и так же она ведёт себя правильно при нуле
    /// снимков: сетка из одной плитки «Снять» — это и есть пустое
    /// состояние, у которого вход виден. Отдельная строка под сеткой
    /// при нуле снимков оставляла бы пустую сетку и строку, то есть
    /// два пустых места вместо одного действия.
    /// Чипы направлений — та же форма, что фильтр истории.
    ///
    /// Показываются, только когда направлений БОЛЬШЕ ОДНОГО: при одном
    /// фильтровать не из чего, и «все · гормоны» было бы двумя
    /// кнопками с одинаковым ответом.
    @ViewBuilder
    private var чипыНаправлений: some View {
        if направленияСоСнимками.count > 1 {
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: Token.Space.s8) {
                    КиноЧип(подпись: "все", выбран: направление == nil) {
                        направление = nil
                    }
                    ForEach(направленияСоСнимками, id: \.self) { вид in
                        КиноЧип(подпись: .готовая(вид.title),
                                выбран: направление == вид) {
                            // Второе нажатие на выбранный снимает отбор:
                            // иначе выйти из направления можно только
                            // через «все», а его на узком экране
                            // приходится искать прокруткой назад.
                            направление = (направление == вид) ? nil : вид
                        }
                    }
                }
                .padding(.vertical, Token.Space.s2)
            }
            .accessibilityElement(children: .contain)
            .accessibilityLabel("Направление")
        }
    }

    @ViewBuilder
    private var сетка: some View {
        // Заголовок месяца показывается, только когда групп больше
        // одной: над единственной группой он был бы шумом, а при
        // отборе по направлению групп часто ровно одна.
        let группы = поМесяцам
        let сЗаголовками = группы.count > 1

        ForEach(Array(группы.enumerated()), id: \.offset) { индекс, группа in
            if сЗаголовками {
                TGSectionHeader(title: заголовокГруппы(группа.месяц),
                                subtitle: nil)
                    .padding(.top, индекс == 0 ? 0 : Token.Space.s8)
            }
            плитки(группа.снимки, сКнопкойСъёмки: индекс == группы.count - 1)
        }

        // Группы нет вовсе — ни одного снимка в выбранном направлении
        // или ни одного вообще. Кнопку съёмки всё равно показать надо:
        // иначе при пустом отборе экран теряет единственный вход.
        if группы.isEmpty {
            плитки([], сКнопкойСъёмки: true)
        }
    }

    /// Подпись группы. У снимков без даты события она говорит ровно
    /// это, а не подставляет день съёмки.
    private func заголовокГруппы(_ месяц: Date?) -> LocalizedStringKey {
        guard let месяц else { return "без даты события" }
        return .готовая(Fmt.monthTitle(месяц))
    }

    @ViewBuilder
    private func плитки(_ снимки: [DogDocument], сКнопкойСъёмки: Bool) -> some View {
        LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: Token.Space.s8),
                                 count: Сетка.колонок(размер)),
                  spacing: Token.Space.s8) {
            ForEach(снимки) { document in
                Button { viewing = document } label: {
                    ПлиткаСнимка(документ: document)
                }
                .buttonStyle(.plain)
                .accessibilityLabel(Text(verbatim: document.title))
                .accessibilityAddTraits(.isButton)
            }

            if canEdit && сКнопкойСъёмки {
                PhotosPicker(selection: $picked, matching: .images, photoLibrary: .shared()) {
                    ПлиткаСнять()
                }
                .buttonStyle(.plain)
                .accessibilityLabel("Сфотографировать документ")
            }
        }
        .padding(.top, Token.Space.s8)
    }

    // MARK: Действия

    private func load(_ item: PhotosPickerItem?) {
        guard let item else { return }
        Task {
            // Полноразмерный снимок с камеры — это десятки мегабайт.
            // В дневнике он не нужен: читать надо номер, а не разглядывать
            // текстуру бумаги.
            //
            // `picked` снимается ПЕРВЫМ и при любом исходе: иначе неудача
            // оставляла его выбранным, и повторный выбор того же снимка
            // не давал `onChange` — плитка «Снять» выглядела мёртвой.
            // Неудача говорит о себе тем же текстом, что у фото собаки.
            picked = nil
            guard let raw = try? await item.loadTransferable(type: Data.self),
                  let shrunk = DocumentPhoto.shrink(raw)
            else {
                appState.showFailure(String(localized: "Снимок не открылся · попробуй другой"))
                return
            }
            pendingImage = shrunk
        }
    }

    private func add(image: Data, draft: DocumentDraft) {
        let document = DogDocument(title: draft.title, image: image)
        // Поля переносит сам черновик — одним местом на создание
        // и на правку, чтобы «номер» и «кем выдан» не разъехались
        // по двум спискам присваиваний.
        draft.применить(к: document)
        document.dog = dog
        context.insert(document)
        // Сохраняем сразу: обратная связь применяется не мгновенно,
        // и список остался бы прежним.
        guard context.persist(otherwise: { context.delete(document) }) else {
            return неСохранилось("Снимок не сохранился · попробуй ещё раз")
        }
        pendingImage = nil
        Haptics.success()
    }

    /// Правка уже заведённого документа.
    ///
    /// Нужна не для порядка: четыре поля появились 07.10.2026,
    /// а вводить их стало можно только сейчас — у человека уже лежат
    /// снимки без типа, номера и срока. Без правки срок в них
    /// не внести никогда, то есть починка не работала бы именно
    /// у тех, у кого документы есть.
    private func сохранить() {
        // Откатывать нечего по устройству: `@Model` уже изменён
        // в памяти, а отката у `persist` нет. Поэтому отказ человеку
        // ГОВОРЯТ — «кажется, сохранил» про номер паспорта дороже
        // обычного.
        guard context.persistNothingToUndo() else {
            return неСохранилось("Правка не сохранилась · попробуй ещё раз")
        }
        Haptics.success()
    }

    private func delete(_ document: DogDocument) {
        // Надгробие вместо `context.delete`: подпись документа ездит
        // ко второму человеку с 07.10.2026, а её удаление — не ездило.
        // Скан при этом остаётся у каждого свой, он не ездил никогда.
        let откат = ОбщееУдаление.удалить(document)
        guard context.persist(otherwise: откат) else {
            return неСохранилось("Снимок не удалился · попробуй ещё раз")
        }
        viewing = nil
        Haptics.warning()
    }

    /// Отказ виден человеку: снимок документа — то, что ищут в спешке,
    /// и «кажется, сохранил» здесь дороже обычного.
    private func неСохранилось(_ текст: String) {
        Haptics.warning()
        appState.showFailure(текст)
    }
}

/// Обёртка, чтобы снимок можно было отдать в `.sheet(item:)`.
private struct PendingPhoto: Identifiable {
    let data: Data
    var id: Int { data.hashValue }
}

/// Плитка сетки: сам снимок, подпись лежит НА нём слева внизу.
///
/// **Подпись не под плиткой, а на ней — и это не вкус.** Под плиткой
/// она задавала бы высоту ряда по самому длинному названию
/// («Ветпаспорт» против «Чип»), и три плитки в ряду разъезжались бы
/// по высоте от слов. На снимке подпись стоит на своей подложке
/// и высоту ряда не трогает вовсе.
///
/// Подложка под подписью обязательна по той же причине, что слой
/// затемнения у `CinemaHeader`: белый текст на СНИМКЕ — это текст
/// на неизвестном фоне, и светлая страница паспорта съедает его
/// целиком. Здесь фон под подписью свой и непрозрачный, поэтому пара
/// считается без снимка.
///
/// `Text(verbatim:)` у названия — потому что название **вводит
/// человек** (умолчанием от вида в `DocumentFieldsSheet` либо своим
/// словом):
/// Числа сетки — одно место на обе плитки.
///
/// Ответ дизайна 25.10.2026, круг 5, пункт 6: «3 колонки, зазор 8,
/// ячейка 3 : 4, радиус 16; при AX-размерах — 2 колонки».
///
/// **Пропорция была 4 : 5 и стала 3 : 4, и разница не косметическая:**
/// при трёх колонках на 402 pt клетка 118 pt шириной даёт высоту 147
/// против 157 — ряд становится ниже на десять точек, и четвёртый ряд
/// на экран помещается там, где раньше помещалось три с половиной.
/// Число 3 : 4 — пропорция бумажного листа ближе, чем 4 : 5, а в сетке
/// лежат именно листы: паспорт, справка, выписка.
///
/// **Две колонки при AX — не «красивее», а единственный способ
/// оставить подпись читаемой:** у штампа есть пол высоты 28 и поля
/// 4 × 8, и на трети ширины при AX5 в него не влезает ни одно слово
/// целиком. Порог взят у системы (`DynamicTypeSize.isAccessibilitySize`),
/// а не числом точек: число точек пришлось бы держать в согласии
/// с системной шкалой руками.
private enum Сетка {
    /// `aspectRatio` принимает ОТНОШЕНИЕ ШИРИНЫ К ВЫСОТЕ, и 3 : 4
    /// здесь значит «уже, чем выше», то есть 0,75. Записано дробью,
    /// а не числом 0.75, чтобы в коде читалось то же, что в ответе
    /// дизайна: прочитанное как 4 : 3 перевернуло бы клетку набок.
    static let пропорция = 3.0 / 4.0

    static func колонок(_ размер: DynamicTypeSize) -> Int {
        размер.isAccessibilitySize ? 2 : 3
    }
}

/// это значение, а не ключ каталога, и `Text(ключ)` искал бы перевод
/// для «Ветпаспорт Стича».
private struct ПлиткаСнимка: View {
    let документ: DogDocument

    var body: some View {
        // **Пропорцию держит `Color.clear`, а не содержимое.**
        // `.aspectRatio(_:contentMode: .fit)`, надетый на стопку
        // с текстом, вписывает в пропорцию СОДЕРЖИМОЕ и размера клетке
        // не задаёт — ряд разъезжается от длины подписи. Гибкая пустая
        // подложка принимает предложенную ширину и из неё считает
        // высоту, а снимок и подпись ложатся на неё слоями.
        Color.clear
            .aspectRatio(Сетка.пропорция, contentMode: .fit)
            .overlay { снимок }
            .overlay(alignment: .bottomLeading) { подпись }
            .clipShape(RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous))
            .contentShape(RoundedRectangle(cornerRadius: Token.Radius.tile, style: .continuous))
    }

    /// # Плитка берёт МИНИАТЮРУ, а не полную раскладку (замер 05.11.2026)
    ///
    /// Отзыв 28.10.2026 — «плохо скроллиться… идёт зависание» — указывал
    /// сюда, и кэш, заведённый тогда же, этого места не вылечил:
    /// предел стоял шесть на весь экран, а сетка документов трёхколоночная
    /// (`плитки(_:сКнопкойСъёмки:)` выше). **На седьмом снимке прежний
    /// `КэшСнимков` делал `removeAll`** — то есть каждый кадр прокрутки
    /// вытирал полку и раскладывал JPEG заново на главном потоке.
    ///
    /// Поднять предел было нельзя, пока плитка просила ПОЛНУЮ раскладку:
    /// у снимков, заведённых до 25.10.2026, длинная сторона до 4800 px
    /// (`DocumentPhoto.shrink` умножал запрошенные 1600 на масштаб
    /// устройства), и один такой кадр — это 69 МБ в памяти. Шесть —
    /// 414 МБ, то есть выгрузка приложения системой.
    ///
    /// ```
    /// плитка на экране        120 × 160 pt, то есть 360 × 480 px на @3x
    /// просила до сих пор      до 4800 × 3600 px — в сто раз больше пикселей,
    ///                         чем видно
    /// просит теперь           800 px по длинной стороне (разбор числа —
    ///                         в голове `КэшСнимков`)
    /// ```
    ///
    /// > **Это не экономия, а смена предмета.** Полноразмерная раскладка
    /// > остаётся там, где снимок разглядывают, — в `DocumentViewerSheet`
    /// > ниже. На плитке её не видно ничем.
    @ViewBuilder
    private var снимок: some View {
        if let data = документ.image, let image = КэшСнимков.миниатюра(data) {
            Image(uiImage: image)
                .resizable()
                .scaledToFill()
                .accessibilityHidden(true)
        } else {
            // Снимка нет — плитка остаётся плиткой, а не схлопывается
            // в полоску: пустое место в сетке читалось бы как «тут
            // ничего нет», а запись есть и её открывают.
            Token.Surface.sunken
                .overlay {
                    Image(systemName: "doc.text.image")
                        .font(.system(size: Token.Size.iconLg, weight: Token.FontWeight.medium))
                        .foregroundStyle(Token.Ink.secondary)
                }
                .accessibilityHidden(true)
        }
    }

    /// Числа — ответ дизайна 25.10.2026, круг 5, пункт 6, дословно:
    /// «подпись на снимке: стекло, отступ от краёв 8 (было 6), радиус 8
    /// (16 − 8), высота от 28, поля 4 × 8, 12 / 600».
    ///
    /// Четыре величины из пяти сделаны. **Кегль НЕ сделан, и это
    /// не забывчивость:** 12 ниже пола 14, поставленного решением
    /// Виктории 15.10.2026 («Пол 14, макет поправить»). Её
    /// формулировка называет и сторону починки — правится макет.
    /// Разбор с числами — в `$description` у `font.size.micro`
    /// в `DesignTokens/tokens.json`. Здесь остаётся `AppFont.micro`,
    /// то есть 14/400 против названных 12/600.
    ///
    /// «Было 6» в ответе дизайна — наш код, а не их макет: они
    /// смотрели сюда. Значит и остальные четыре числа читать надо
    /// как правку по месту, а не как общий стиль.
    private var подпись: some View {
        Text(verbatim: документ.title)
            .textStyle(AppFont.micro, color: Token.Poster.labelOnColor)
            .lineLimit(1)
            .minimumScaleFactor(0.7)
            .padding(.horizontal, Token.Space.s8)
            .padding(.vertical, Token.Space.s4)
            .frame(minHeight: Token.Size.stampMin)
            .стекло(радиус: Token.Radius.stamp)
            .padding(Token.Space.s8)
    }
}

