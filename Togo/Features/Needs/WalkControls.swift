import SwiftUI
import UIKit

/// Фото собаки в кольце времени — то, на что смотрят, пока идёт прогулка.
///
/// Кадр 08 хендоффа `design_handoff_togo_ios28`: **портрет собаки**
/// с тонкой светлой обводкой, а вокруг него — кольцо.
///
/// ## ~~«Прогресса здесь нет намеренно»~~ — отменено отзывом 28.10.2026
///
/// Здесь стояло: «у прогулки нет назначенной длины, и кольцо,
/// заполняющееся „до нормы“, сказало бы, что она есть. В прототипе
/// `pct` считается от 25 минут — числа, которого никто не назначал».
/// **Довод верен, вывод из него — нет**, и это её слово, 28.10 08:08:
/// «нет кольца таймера как в дизайне».
///
/// Прототип кольцо рисует, и рисует именно его
/// (`Дизайн/редизайн-ios28/prototypes/Togo-RU.dc.html:214` и `:734`):
///
/// ```
/// бокс 220 · обводка 14 · фото 164      ← пропорции взяты отсюда
/// ringOff = 628 × (1 − min(1, el/25мин))  ← ЧИСЛО 25 НЕ ВЗЯТО
/// ringC   = пауза ? text-secondary : BLUE ← взято
/// ```
///
/// Отказ от двадцати пяти минут остаётся в силе: нормы прогулки
/// никто не назначал. Поэтому **один оборот здесь — час**, то есть
/// кольцо работает циферблатом, а не целью: полный круг значит «гуляем
/// час или больше», и ничего не обещает. Доля считается с потолком
/// (`min(1, …)`), а не по кругу: кольцо, уехавшее назад на 61-й минуте,
/// читалось бы как «время кончилось».
///
/// ## И вторая половина правки: кольца не было, а таймера не было ТОЖЕ
///
/// Замер по двум кадрам одной сборки (282):
///
/// ```
/// кадр приёмки 26.10, отметок НЕТ   «0:01» и подпись ВИДНЫ
///   (ветка без ScrollView)
/// кадр отзыва 28.10 09:46, 3 отметки  таймера НЕТ, списка «отмечено» НЕТ,
///   (ветка со ScrollView)             круг висит в пустоте по центру
/// ```
///
/// Причина — в этом файле, а не в `WalkMode`. `портрет` — это `Color`
/// (или `Image.resizable`), то есть по вертикали он гибкий до бесконечности;
/// `containerRelativeFrame(.horizontal)` закрепляет **только ширину**,
/// а `aspectRatio(1, .fit)` стоял СНАРУЖИ и предлагал квадрат
/// `min(ширина, высота)` — то есть высоту экрана. В `ScrollView`
/// круг забирал весь видимый кусок, и таймер со списком отметок
/// уезжали **под обрез**: они рисовались, их просто не было видно
/// без прокрутки.
///
/// > **Два разных дефекта выглядели одним: «на экране нет кольца
/// > и нет цифр».** Первый — решение, второй — раскладка, и второй
/// > показывался только с отметками, то есть после первого же нажатия
/// > на улице. Кадр приёмки снимали до нажатия.
///
/// Лечится не числом, а порядком: квадрат считается ОТ ЗАКРЕПЛЁННОЙ
/// ШИРИНЫ (`aspectRatio` внутри `containerRelativeFrame`), и высота
/// больше не зависит от того, сколько места предложили.
///
/// ## Кнопки камеры здесь нет, и это решение
///
/// На кадре справа внизу у круга стоит круглая кнопка камеры. Входа
/// для неё в продукте **нет**: у `ActiveSession` нет поля под фото
/// (замер 22.10.2026 — `kind`, `startedAt`, `startedBy`, `marks`,
/// `pausedAt`, `pausedTotal`, и всё), и запись прогулки собирается
/// в `finish()` без снимков. Нарисовать кнопку поверх несуществующего
/// механизма — это «вход есть, механизма нет»: человек нажмёт и получит
/// отказ, **и отказ будет нашим, а не его**. Названо в отчёте.
struct WalkRing: View {
    let dog: Dog?
    /// Сколько уже идёт прогулка, без пауз.
    var прошло: TimeInterval = 0
    var наПаузе: Bool = false

    /// Какую долю ширины занимает круг целиком. Доля, а не точки:
    /// на кадре круг — 0,46 ширины, и в точках он соврал бы на SE
    /// и на iPad.
    private static let доляШирины: CGFloat = 0.46

    /// Пропорции с прототипа, бокс 220: обводка 14, фото 164.
    /// Числа лежат дробью, а не посчитанными: так видно, откуда они.
    private static let доляОбводки: CGFloat = 14.0 / 220.0
    private static let доляФото: CGFloat = 164.0 / 220.0

    /// Один оборот кольца. Час — это циферблат, а не норма прогулки.
    static let оборот: TimeInterval = 60 * 60

    private var доляОборота: CGFloat {
        guard прошло > 0 else { return 0 }
        return min(1, CGFloat(прошло / Self.оборот))
    }

    var body: some View {
        // `Color.clear` берёт ровно тот квадрат, который разрешит
        // `aspectRatio` ВНУТРИ закреплённой ширины, — и выше него
        // не растёт. Разбор — в голове типа.
        Color.clear
            .aspectRatio(1, contentMode: .fit)
            .containerRelativeFrame(.horizontal) { ширина, _ in
                ширина * Self.доляШирины
            }
            .overlay { содержимое }
            .accessibilityHidden(true)
    }

    private var содержимое: some View {
        GeometryReader { место in
            let сторона = min(место.size.width, место.size.height)
            let обводка = сторона * Self.доляОбводки
            ZStack {
                // Дорожка видна всегда: кольцо без дорожки в начале
                // прогулки неотличимо от «кольца нет».
                Circle().strokeBorder(Token.Line.control, lineWidth: обводка)

                Circle()
                    .inset(by: обводка / 2)
                    .trim(from: 0, to: доляОборота)
                    .stroke(наПаузе ? Token.Ink.secondary : Token.Action.primary,
                            style: StrokeStyle(lineWidth: обводка, lineCap: .round))
                    .rotationEffect(.degrees(-90))

                портрет
                    .clipShape(Circle())
                    .overlay {
                        // Тонкая светлая обводка с кадра: она отделяет
                        // портрет от фона-фотографии, иначе тёмная собака
                        // на тёмном фоне сливается краем.
                        Circle().strokeBorder(Token.Surface.glassEdge,
                                              lineWidth: Token.Size.hairline * 2)
                    }
                    .padding(сторона * (1 - Self.доляФото) / 2)
            }
            .frame(width: место.size.width, height: место.size.height)
        }
    }

    @ViewBuilder
    private var портрет: some View {
        if let photo = dog?.photo, let image = КэшСнимков.картинка(photo) {
            Image(uiImage: image).resizable().scaledToFill()
        } else {
            // Без фото — силуэт, а не пустой круг: пустой круг читается
            // как «не загрузилось».
            ZStack {
                Token.Surface.sunken
                Image(systemName: "pawprint.fill")
                    .font(.system(size: Token.FontSize.display,
                                  weight: Token.FontWeight.light))
                    .foregroundStyle(Token.Ink.silhouette)
            }
        }
    }
}

/// Слайдер «Домой» — им заканчивают прогулку.
///
/// Хендофф, раздел «На улице»: слайдер вместо кнопки. Причина не в моде:
/// прогулку заканчивают **один раз**, а отмечают десять, и «Закончить»
/// рядом с «Пописал» ловила промахи — отзыв «нажатие на один из таймеров
/// закрывает экран» ровно про это. Смахом промахнуться нельзя.
///
/// Ручка слева, белый круг со значком дома — с кадра 08.
struct WalkHomeSlider: View {
    var onHome: () -> Void

    @Environment(\.accessibilityReduceMotion) private var беДвижения
    @State private var сдвиг: CGFloat = 0
    @State private var сработал = false

    /// Какую долю дорожки надо пройти. Меньше половины — случайный смах
    /// по экрану закончил бы прогулку; больше трёх четвертей — не достать
    /// большим одной рукой, а ровно за этим слайдер и ставили.
    private static let порог: CGFloat = 0.65

    /// Ниже какой прозрачности подпись «Домой» гаснуть не имеет права.
    ///
    /// Ниже 0,7 белый на `Surface.control` в Dark HC теряет порог 4,5.
    /// Решение Виктории 26.10.2026; **0,7, а не 0,6** — замер показал,
    /// что порог начинается с 0,6008, то есть 0,6 не хватает на сотую:
    ///
    /// ```
    /// белый на Surface.control, α =   1       0,545 (на пороге)   0,6      0,7
    /// dark      #3A3A3C            11,3490   4,6308 выходит     5,2483   6,5030
    /// darkHC    #48484A             9,1250   4,0105 НЕ ХВАТАЕТ   4,4927   5,4620
    ///                                                           ↑ 0,6 НЕ ГОДИТСЯ
    /// ```
    ///
    /// Без пола в точке срабатывания жеста (`порог` = 0,65) выходило
    /// α = 0,545, и в Dark HC подпись давала 4,0105 при пороге 4,5:
    /// **человек, включивший «Повысить контраст», видел здесь ХУЖЕ,
    /// чем без него**, — он просил обратного.
    ///
    /// `internal`, а не `private`, нарочно: на эту величину стоит
    /// сторож `ПолПодписиДомойTests`, и сторож, меряющий свою копию
    /// числа, мерил бы себя.
    static let полПодписи: Double = 0.7

    /// Высота дорожки, **растущая вместе с системным кеглем**.
    ///
    /// Здесь стояло `Token.Size.capsule` числом — 60 pt при любой
    /// настройке. Внутри лежит `Text("Домой")` стилем `cardTitle`
    /// (кегль 20, `relativeTo: .title3`), и на `AccessibilityXXXL`
    /// он вырастает втрое: в шестьдесят точек не помещается ни строка,
    /// ни ручка рядом с ней. Кадр 25.10.2026 (`06-выгул-ax5.png`):
    /// от подписи осталось «…» между значком дома и шевроном —
    /// **единственная дорога закончить прогулку перестала называть
    /// себя словом**.
    ///
    /// **Почему не `minHeight:`.** Модификатор надет на `GeometryReader`,
    /// а тот — жадный: он берёт всю предложенную высоту и при
    /// `minHeight:` в `VStack` раздулся бы на весь свободный остаток
    /// экрана. Высота обязана остаться определённой; меняется
    /// не её вид, а её число.
    ///
    /// Считается `UIFontMetrics` — тем же способом, которым в проекте
    /// уже растят геометрию под кегль (`DayTimeline:145`, `TGChip:89`,
    /// `FamilyScreen:778`), и по той же ступени `.title3`, к которой
    /// привязан сам `cardTitle`. Иначе дорожка росла бы не в такт
    /// подписи, которую она обязана вмещать.
    private var высотаДорожки: CGFloat {
        UIFontMetrics(forTextStyle: .title3).scaledValue(for: Token.Size.capsule)
    }

    /// Ручка растёт вместе с дорожкой, **но не больше полутора своих**.
    ///
    /// 54 из 60 — это «дорожка минус три точки с каждой стороны»
    /// (`Token.Space.s4` слева по разметке ниже). Оставить ручку
    /// постоянной значило бы кружок 54 pt в дорожке 156 pt: цель
    /// не сломается, но смахивать будут за край ручки, а не за ручку.
    ///
    /// **Потолок — замер, а не вкус.** Первая редакция растила ручку
    /// без него, и кадр (`06-выгул-ax5`, прогон 25.10 после первой
    /// правки) показал, чем это кончается: ручка 148 pt съела ширину,
    /// подпись «Домой» перенеслась на «Домо / й», и вторая строка
    /// ушла под нижний край дорожки. Высоту я вылечил, а ширину
    /// отнял — **починка одной оси забрала вторую**.
    ///
    /// > Это тот же случай, что в своде назван «у числа про геометрию
    /// > ось называется в той же строке»: у слайдера их две, и растить
    /// > надо ровно ту, которой не хватает.
    private var размерРучки: CGFloat {
        min(Token.Size.controlXL * 1.5,
            max(Token.Size.controlXL, высотаДорожки - Token.Space.s4 * 2))
    }

    var body: some View {
        GeometryReader { geo in
            let ручка = размерРучки
            let ход = max(0, geo.size.width - ручка - Token.Space.s4 * 2)

            ZStack(alignment: .leading) {
                // ДОРОЖКА НЕ БРАЛА ПОРОГА ГРАНИЦЫ ОРГАНА (замер 25.10.2026).
                //
                // `Surface.control` — `#3A3A3C` в тёмной, `#48484A`
                // в повышенном контрасте. Против чёрного экрана это
                // **1,85 и 2,30** при пороге WCAG 1.4.11 равном 3:1,
                // то есть дорожку не видно как орган. Померено пикселем
                // на кадре, а не выведено из токенов.
                //
                // ```
                // дорожка #3A3A3C на #000000   1,85   НЕ ХВАТАЕТ
                // контур  #767676              4,62   ✔
                // дорожка HC #48484A           2,30   НЕ ХВАТАЕТ
                // контур  HC #8E8E93           6,44   ✔
                // ```
                //
                // Заливку не трогаем: `#3A3A3C` — прямое слово дизайна
                // от 23.10. Контур тем же `Line.control`, которым
                // круг 6 закрыл второстепенную кнопку: **нового цвета
                // не заводится**, одно значение на две роли.
                //
                // > Дизайн оставлял это открытым вопросом с доводом
                // > «ручка слайдера белая, орган находится и без
                // > дорожки». Довод верен про НАХОДИМОСТЬ и молчит
                // > про порог; контур закрывает порог, ручку не трогая.
                Capsule()
                    .fill(Token.Surface.control)
                    .overlay {
                        Capsule().strokeBorder(Token.Line.control,
                                               lineWidth: Token.Size.hairline)
                    }

                HStack(spacing: Token.Space.s4) {
                    Spacer(minLength: ручка)
                    Text("Домой")
                        .textStyle(AppFont.cardTitle, color: Token.Ink.primary)
                        // **Одна строка и ужатие — потому что дорожка
                        // обязана остаться определённой высоты.**
                        // В поле фиксированной высоты перенос — это
                        // не перенос, а обрез: вторая строка уходит
                        // под край и читается как брак отрисовки
                        // (кадр `06-выгул-ax5` до этой правки:
                        // «Домо / й»).
                        //
                        // Ужимать текст на кнопках в проекте нельзя
                        // (`TGButton`: «длинная подпись переносится,
                        // а кнопка становится выше»), и это правило
                        // верное — но оно про орган, который МОЖЕТ
                        // вырасти. Этот не может: `GeometryReader`
                        // требует числа. Из двух исходов — ужатая
                        // целая подпись и обрезанная половина —
                        // выбран первый.
                        .lineLimit(1)
                        .minimumScaleFactor(0.6)
                    Image(systemName: "chevron.compact.right")
                        .foregroundStyle(Token.Ink.secondary)
                        .accessibilityHidden(true)
                    Spacer(minLength: 0)
                }
                .padding(.horizontal, Token.Space.s12)
                // Подпись гаснет по мере хода: к концу под ручкой её
                // всё равно не видно, а мигание на последних точках
                // читалось бы как сбой. ГАСНЕТ ДО ПОЛА, не до нуля —
                // см. `полПодписи`: без пола в Dark HC подпись уходила
                // под порог 4,5 ровно там, где палец доводит жест.
                //
                // `Double(...)` не украшение: `сдвиг / ход` это CGFloat,
                // а `max` — generic по одному типу, и смешанную пару
                // он не принимает.
                .opacity(ход > 0
                         ? max(Self.полПодписи, 1 - Double(min(1, сдвиг / ход)) * 0.7)
                         : 1)

                ручкаВида
                    .offset(x: сдвиг)
                    .padding(.leading, Token.Space.s4)
                    .gesture(жест(ход: ход))
            }
        }
        .frame(height: высотаДорожки)
        // Смах недоступен озвучке и моторике: у слайдера обязан быть
        // второй путь, иначе прогулку нельзя закончить вовсе.
        // Это не дубль кнопки — это тот же механизм другим входом.
        .accessibilityElement(children: .ignore)
        .accessibilityLabel("Домой")
        .accessibilityHint("Заканчивает прогулку")
        .accessibilityAddTraits(.isButton)
        .accessibilityAction { сработать() }
    }

    private var ручкаВида: some View {
        Image(systemName: "house.fill")
            .font(.system(size: Token.Size.iconMd, weight: Token.FontWeight.semibold))
            .foregroundStyle(Token.Ink.onAccent)
            .frame(width: размерРучки, height: размерРучки)
            .background(Token.Action.primary, in: Circle())
    }

    private func жест(ход: CGFloat) -> some Gesture {
        DragGesture(minimumDistance: 1)
            .onChanged { значение in
                guard !сработал, ход > 0 else { return }
                сдвиг = min(ход, max(0, значение.translation.width))
            }
            .onEnded { _ in
                guard !сработал, ход > 0 else { return }
                if сдвиг >= ход * Self.порог {
                    сдвиг = ход
                    сработать()
                } else {
                    // Не дошёл — ручка возвращается. Оставить её на месте
                    // значило бы показать наполовину сделанное действие.
                    withAnimation(беДвижения ? nil : .spring(duration: Token.Duration.quick)) {
                        сдвиг = 0
                    }
                }
            }
    }

    /// Один раз за жизнь вида: прогулка заканчивается однажды, и повторный
    /// вызов закрыл бы уже закрытую сессию.
    private func сработать() {
        guard !сработал else { return }
        сработал = true
        Haptics.success()
        onHome()
    }
}
