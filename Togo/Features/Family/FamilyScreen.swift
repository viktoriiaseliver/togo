/// Семья · роли, дежурство, вид ситтера.
/// Роли — не лестница: наблюдатель читает и не пишет, помощник пишет
/// бытовое и не видит медицинского.
///
/// **С 23.10.2026 экран переписан под тему «Кино».** Эталон — кадр
/// `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/12.png`, мерено
/// по нему. Что изменилось против прежней редакции:
///
/// ```
/// плоская полоса `.posterHeader`    → фото 360 pt, надстрочник, «Семья» 36
/// карточка дежурства в потоке       → стеклом на фотографии
/// «Сегодня дежурит Вика» одной      → «Дежурит сегодня» / имя / «до 22:55 ·
///   строкой, «передать» текстом       пуши дозы приходят тебе» + «Передать»
/// «участники · N» внутри карточки   → заголовком над карточкой
/// в строке участника нет «это я»    → пилюля «это я»
/// «Роли — не лестница» прозой       → «Пять ролей, восемь прав» + пилюли ролей
/// «Инструкция ситтеру · написана»   → «Брифинг для {имя}» + кнопка «Открыть»
/// ```
///
/// **Кнопки «…» в шапке этого экрана НЕТ, хотя на кадре она есть.**
/// Кадр `12` рисует «Семью» экраном верхнего уровня — в прототипе
/// у неё своя вкладка. У нас её нет с 22.10: экран пушится из вкладки
/// собаки, и у него есть «назад». Решение того же дня говорит дословно
/// «Больше кнопок в шапке нет», а второй вход в настройки с пушнутого
/// экрана — ровно та кнопка, которую решение запрещает. Расхождение
/// с кадром здесь **следствие нашей навигации**, а не недоделка.
struct FamilyScreen: View {
    /// Экран открыт **внутри** чужого `NavigationStack` — строкой
    /// во вкладке собаки, а не своей вкладкой.
    ///
    /// Своей вкладки у «Семьи» нет с 22.10.2026 (решение Виктории,
    /// `design_handoff_togo_ios28`, «Навигация (решено)»): она уехала
    /// первой строкой во вкладку собаки. А вложенный
    /// `NavigationStack` внутри другого — это два заголовка, две
    /// панели и сломанный «назад», поэтому подложку надо уметь
    /// не рисовать.
    ///
    /// Умолчание `false` оставлено нарочно: экран может понадобиться
    /// корневым (своя шторка, свой маршрут), и тогда стек ему нужен.
    /// Сегодня живой вход ровно один — `DogTab`.
    var встроенный: Bool = false

    @Environment(AppState.self) private var appState
    @Environment(SubscriptionStore.self) private var store
    @Environment(\.modelContext) private var context
    /// Настройка размера текста в iOS: от неё зависит раскладка строк,
    /// а не только кегль.
    @Environment(\.dynamicTypeSize) private var размерТекста
    /// ПОРЯДОК ЗАДАН ЯВНО, и это не косметика (замер 25.10.2026).
    ///
    /// Без `sort:` SwiftData отдаёт участников в порядке, который
    /// меняется между запусками. Сессия крупного кегля померила это
    /// на двух прогонах подряд:
    ///
    /// ```
    /// Ты · Dr.Ferrand · Мама · Тео · Виктория · Лея
    /// Ты · Виктория · Лея · Мама · Dr.Ferrand · Тео
    /// ```
    ///
    /// Показ — меньшая половина беды. От порядка зависели два ВЫБОРА,
    /// и оба человек видит:
    ///
    /// ```
    /// successor(after:)     кому перейдёт ДЕЖУРСТВО — «Передать»
    ///                       предлагало каждый запуск другого
    /// заголовокБрифинга     «Брифинг для Ани» — имя адресата
    ///                       менялось само
    /// ```
    ///
    /// Оба зовут `members.first { … }` по предикату, которому подходят
    /// НЕСКОЛЬКО человек, — то есть «первый подходящий» был первым
    /// по случайности.
    ///
    /// > **`first` по многозначному предикату — это выбор без правила.**
    /// > Он выглядит детерминированным, потому что код один и тот же,
    /// > а меняется то, что код не называет: порядок источника.
    ///
    /// Ключ — имя, и это ВЫБОР, а не единственный путь: поля даты
    /// создания у `FamilyMember` нет, завести его значило бы править
    /// форму схемы, а это решение Виктории. Имя даёт порядок
    /// предсказуемый человеку и стабильный между запусками; если нужен
    /// порядок «кого завели раньше» — это поле в схеме и её слово.
    ///
    /// «Своя строка первой» этим не задета: она рисуется отдельно,
    /// до `ForEach` (ОТВЕТЫ-круг-5, п. 2).
    @Query(sort: \FamilyMember.name) private var members: [FamilyMember]
    @Query private var dogs: [Dog]

    @State private var showInvite = false
    @State private var handingOver: Передача?
    @State private var editingBriefing = false
    @State private var showPaywall = false
    @State private var invite: DiaryInvite?
    @State private var inviteFailure: String?
    @State private var isPreparingInvite = false
    /// Кто **реально** имеет доступ — ось ворот семьи.
    ///
    /// Не `members`: локальная карточка `FamilyMember` живёт на этом
    /// телефоне и по обмену не ездит с 08.10.2026
    /// (`SharedDiary.swift:78`), то есть от вошедшего по приглашению
    /// `members.count` не растёт никогда. Разбор и замер —
    /// `ProRequest.familyBeyondTwo(среди:)`.
    ///
    /// Пустой список значит и «делиться ещё не начали», и «спросить
    /// не удалось»; различить их здесь нечем, и ворота на пустом
    /// **открыты** — ошибаться надо в сторону человека.
    @State private var состав: [УчастникДневника] = []
    /// Роль, которую получит тот, кто войдёт по этой ссылке.
    ///
    /// **Владельца в списке нет намеренно:** приглашают не себя,
    /// а роль `.owner` по ссылке отдала бы дневник целиком — включая
    /// право позвать следующего. Такого решения никто не принимал.
    @State private var рольНовичка: FamilyRole = .caregiver
    /// Роль, которая СЕЙЧАС лежит в наряде (`НарядРолей.новичкам`).
    /// `nil` — наряда в облаке нет вовсе, то есть не выбрано ничего
    /// и гость войдёт наблюдателем.
    ///
    /// Отдельно от `рольНовичка`, потому что это разные предметы:
    /// одно — что видно в органе, другое — что лежит в облаке.
    /// Их совпадением и проверяется, надо ли писать.
    @State private var рольВОблаке: FamilyRole?
    /// Спрашивали ли наряд хоть раз.
    ///
    /// **«Ещё не спросили» и «спросили, наряда нет» — разные
    /// состояния**, а выглядят одинаково пустым `рольВОблаке`.
    /// Без этого различителя орган писал бы в облако от своей же
    /// загрузки — ровно та же пара состояний, что у `спросили`
    /// в `УчастникиДневника`.
    @State private var рольПрочитана = false
    @State private var сохраняемРоль = false

    private var dog: Dog? { appState.activeDog(from: dogs) }
    private var duty: FamilyMember? { members.first(where: \.isOnDuty) }
    private var canManageFamily: Bool { appState.can(.manageFamily) }

