/// Две записи об одном событии в пределах 20 минут дают карточку слияния
/// обоим авторам. Приложение не удаляет чужое молча.
struct MergeConflictCard: View {
    let left: LogEvent
    let right: LogEvent

    @Environment(\.modelContext) private var context
    @State private var resolved = false

    var body: some View {
        if !resolved {
            TGCard {
                Text("Две записи об одном").textStyle(AppFont.cardTitle)
                Text("Похоже, вы оба отметили одно и то же. Одна из записей пришла позже — вероятно, автор был без сети.")
                    .textStyle(AppFont.caption)
                TGDivider()
                ConflictRow(event: left)
                ConflictRow(event: right)
                HStack(spacing: Token.Space.s8) {
                    TGButton(title: "Это одно и то же", variant: .secondary, size: .medium) { merge() }
                    TGButton(title: "Нет, было дважды", variant: .secondary, size: .medium) { resolved = true }
                }
                TGExplainer(text: "Что ни выбери, обе записи останутся в истории. Приложение не удаляет чужое молча.")
            }
        }
    }

    /// Слияние сохраняет следы обеих: вторая помечается удалённой, а не стирается.
    ///
    /// **`deletedBy` здесь не переводится, и причина не «это служебное»,
    /// а замер.** 13.10.2026: у поля ноль читателей НА ПОКАЗ — везде,
    /// кроме этой строки, в него кладут `appState.currentUserName`,
    /// а наружу оно уходит только в CloudKit (`SharedDiaryRecords:65`)
    /// и в архив (`Backup.swift:129`). Ни один экран его не рисует.
    /// Перевести значило бы положить в общее поле слово на языке
    /// автора — рядом с именами людей, которые не переводятся.
    ///
    /// Один признак, ноль читателей означает в двух случаях
    /// противоположное: «нужно показать» и «показывать нечего».
    /// Если у поля появится показ — пометку снять и строку перевести.
    private func merge() {
        right.deletedAt = Date()
        right.deletedBy = "слияние"  // внутреннее: маркер в общем поле автора, показа у поля нет (замер 13.10.2026)
        left.note = [left.note, "объединено с записью \(right.authorName)"].compactMap { $0 }.joined(separator: " · ")
        resolved = true
        Haptics.success()
    }
}

