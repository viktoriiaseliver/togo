/// приглашение делает CloudKit своей ссылкой (`CKShare`
/// в `FamilyShare:208`), принимают его по iCloud-личности, и наш токен
/// в этом пути не участвует вовсе. Строкой ниже, в самом списке
/// участников, это уже разобрано: «"ждёт" было обещанием, а "истекло"
