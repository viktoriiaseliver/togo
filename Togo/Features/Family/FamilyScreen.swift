            // по этому правилу надо записать неизмеримым, а не
            // не делать. Измеримую половину (ключ участника, снятие
            // наряда, запрет на владельца) из облака вынесли в чистые
            // значения и покрыли тестами — ровно так же, как
            // `РолиВОбмене`.
            //
            // Кнопка остаётся кнопкой УБОРКИ СПИСКА, и подпись говорит
            // это: удаление карточки само по себе осмысленно, ложным
            // было обещание закрытого доступа.
            if appState.myMemberID != member.id {
                TGExplainer(text: "Уберёт карточку с этого телефона. Доступ к дневнику этим не закроется: его закрывают в «Кто имеет доступ», и там же — только этому человеку.")
                TGButton(title: "Убрать из списка", variant: .destructive, size: .medium, systemImage: "person.badge.minus") {
                    убратьСпрошено = true
                }
            }
        }
        // Удаление было в одно касание, без вопроса и без сохранения
        // (аудит 28.10.2026). Карточка — автор записей и дежурный,
        // убрать её случайно дороже, чем один лишний вопрос.
        .confirmationDialog(.готовая(String(localized: "Убрать \(member.name) из списка?")),
                            isPresented: $убратьСпрошено, titleVisibility: .visible) {
            Button("Убрать", role: .destructive) {
                context.delete(member)
                guard context.persistNothingToUndo() else {
                    Haptics.warning()
                    appState.showFailure(String(localized: "Не удалилось · проверь после перезапуска"))
                    return
                }
                dismiss()
            }
            Button("Отмена", role: .cancel) {}
        } message: {
            Text("Записи этого человека останутся в дневнике.")
        }
        .navigationTitle(member.name)
        .cinemaScreen(экран: .sub("family"))
        .task { имя = member.name }
    }

    /// Сохранить имя честно: при отказе хранилища имя возвращается,
    /// и подпись автора на этом телефоне остаётся прежней.
    private func сохранитьИмя() {
        guard let новое = Fmt.notBlank(имя), новое != member.name else { return }
        let было = member.name
        member.name = новое
        guard context.persist(otherwise: { member.name = было }) else {
            Haptics.warning()
            appState.showFailure(String(localized: "Не сохранилось · нажми ещё раз"))
            return
        }
        // Своё имя — это ещё и подпись автора, которую держит
        // `AppState`. Без этой строки карточка сказала бы «Аня»,
        // а следующая отметка подписалась бы прежним «Я».
        if appState.myMemberID == member.id { appState.currentUserName = новое }
        Haptics.success()
    }
}

