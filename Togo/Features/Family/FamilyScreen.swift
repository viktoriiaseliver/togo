        // не «героя», а свой фон раздела.
        BackgroundStore.shared.background(for: .family)?.data ?? dog?.photo
    }

    /// «3 ЧЕЛОВЕКА · ДЕЖУРИТ ВИКА» — дословно с кадра `12`.
    ///
    /// Собирается `String`'ом: в нём имя человека, а `.готовая(…)` —
    /// это обычный ключ каталога, и поиск по каталогу он выполняет
    /// (разбор — `Подпись.swift`). Рисует `Text(verbatim:)`.
    ///
    /// **Кадр говорит «3 ЧЕЛОВЕКА», а у нас стоит «в семье 5», и это
    /// расхождение с названной ценой, а не вольность.** Первая редакция
    /// писала дословно с кадра — `"\(members.count) человека"`, по тому
    /// же образцу, что `Fmt.days`, — и первый же кадр стенда показал
    /// **«5 ЧЕЛОВЕКА»**. По-русски так не говорят ни при каком числе,
    /// кроме двух, трёх и четырёх.
    ///
    /// Чинится это множественными формами в каталоге
    /// (`one/few/many/other` для ru и uk) — а каталог
    /// `TogoShared/Resources/Localizable.xcstrings` на 23.10.2026 отдан
    /// другой сессии распоряжением Виктории, и трогать его нельзя.
    /// Значит выбор был между «сломанным русским на кадре сейчас»
    /// и «другой формулировкой, верной при любом числе». Взята вторая:
    /// «в семье 5» грамматично и на пяти, и на одном.
    ///
    /// > Форма — временная, и у неё есть хозяин: когда у ключа появятся
    /// > плюралы, сюда возвращается текст кадра. Пока плюралов нет,
    /// > дословность кадра была бы дефектом, который видит каждый.
    private var надстрочник: String? {
        var части = [String(localized: "в семье \(members.count)")]
        if let duty { части.append(String(localized: "дежурит \(duty.name)")) }
        return части.joined(separator: " · ")
    }

    // MARK: Дежурство

    /// Передача держит ОБОИХ: кому уходит смена, решено в момент открытия
    /// шторки, а не в момент нажатия «Принять смену».
    ///
    /// Прежде подпись и действие спрашивали список дважды — шторка звала
    /// `successor(after:)`, чтобы назвать имя, и `passDuty` звал его снова,
    /// чтобы назначить. `@Query` участников идёт без дескриптора сортировки
    /// (`:15`), и порядок воспроизведён разным трижды (08.10, 12.10, 14.10),
    /// то есть между двумя вызовами список мог прийти иначе: шторка называла
    /// Лею, дежурство уходило Тео. Расхождение молчит — обе строки верны
    /// по отдельности.
    private struct Передача: Identifiable {
        let id: UUID
        let сдающий: FamilyMember
        let принимающий: FamilyMember?
    }

    /// Карточка дежурства.
    ///
    /// **На доступных размерах кнопка уезжает под текст, а не стоит
    /// сбоку.** Три колонки в строке — аватар, текст, действие — делят
    /// ширину, и на крупном системном шрифте средней не остаётся почти
    /// ничего: кадр 28.09 показал «Сегод / ня дежу / рит Teo»
    /// и «передат / ь». Перенос внутри слова хуже любого другого:
    /// слово перестаёт узнаваться.
    ///
    /// Ужать было нечем — это уже шрифт, который человек и увеличивал.
    /// Тот же ответ, что у ряда плиток на главном: не ужимать, а менять
    /// раскладку.
    /// **Три строки вместо одной, и это кадр, а не вкус.** На `12`
    /// карточка читается сверху вниз: «Дежурит сегодня» — тихо, имя —
