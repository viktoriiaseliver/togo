    /// Положить роль новичкам, когда приглашение уже создано.
    ///
    /// Отказ показывается плашкой, а не уходит в журнал: роль —
    /// это право на дозу, и «не вышло» обязано стоять рядом с тем
    /// органом, который его вызвал.
    private func применитьРольНовичка(_ роль: FamilyRole) async {
        сохраняемРоль = true
        inviteFailure = nil
        defer { сохраняемРоль = false }
        do {
            try await FamilyShare.назначитьНовичкам(роль)
            рольВОблаке = роль
            UsageLog.note(.record, "invite:роль", on: .family)
        } catch {
            inviteFailure = error.localizedDescription
            UsageLog.note(.record, "invite:роль:\(FamilyShare.причина(error))",
                          on: .family, outcome: .failed)
        }
    }

    /// Одна общая ссылка на зону: `FamilyShare.invite` сам вернёт уже
    /// созданную, если делились раньше, — новая отрезала бы принявших.
    private func makeInvite() async {
        isPreparingInvite = true
        inviteFailure = nil
        defer { isPreparingInvite = false }
        do {
            let share = try await FamilyShare.invite(dogName: dog.flatMap(\.nameIfAny) ?? String(localized: "собаки"))
            // Наряд кладётся ДО того, как ссылка ушла человеку.
            //
            // Порядок важен: приглашение и назначение — две разные
            // записи в облаке, и принявший читает наряд при входе.
            // Отправь ссылку раньше наряда — и быстрый человек войдёт
            // наблюдателем, а роль приедет ему потом, вторым заходом
            // `FamilySync.fetchNow`. Лишняя минута, в которую он видит
            // не то, что ему выдали.
            //
            // Отказ назначения НЕ отменяет приглашения: ссылка уже
            // создана в облаке, и выбрасывать её значит отрезать тех,
            // кто принял раньше. Человек войдёт наблюдателем — это
            // состояние, которое было до всей этой работы, и оно
            // безопасное. Владелец поменяет роль, и она доедет
            // следующим обменом.
            //
            // **ОТКАЗ ЗДЕСЬ БОЛЬШЕ НЕ ГЛОТАЕТСЯ (27.10.2026).** Он
            // уходил одной строкой в журнал действий, который читают
            // раз в неделю и не на этом экране, — а владелец видел
            // «приглашение создано» и уходил уверенным, что роль
            // выдана. Роль при этом не ложилась никуда, и гость
            // садился на `.observer`. Это наш класс «отказ, о котором
            // сказали после нажатия, — наша поломка в глазах
            // человека», только здесь не сказали вовсе.
            //
            // Приглашение всё равно остаётся созданным — строка ниже
            // стоит ВНЕ этого `do`, — а плашка говорит, что не вышло
            // именно у роли.
            do {
                try await FamilyShare.назначитьНовичкам(рольНовичка)
                рольВОблаке = рольНовичка
                рольПрочитана = true
            } catch {
                inviteFailure = error.localizedDescription
                UsageLog.note(.record, "invite:роль:\(FamilyShare.причина(error))",
                              on: .family, outcome: .failed)
            }
            invite = DiaryInvite(share: share)
            // Состав — тем же заходом: до этой строки `состав` пуст,
            // а пустой состав ворота открывает. Без неё ветка «ссылку
            // только что создали» показывала бы раздачу владельцу,
            // у которого в дневнике уже есть люди (ссылка одна на зону,
            // и `invite` возвращает ранее созданную).
            состав = await FamilyShare.участники()
            UsageLog.note(.record, "invite", on: .family)
        } catch {
            inviteFailure = error.localizedDescription
            // Без этой строки журнал молчит о пути целиком: 44 захода
            // на «Семью» за девять сессий и ни одного события
            // приглашения — и нельзя было понять, не нашли его
            // или он отказал. Вид отказа — в названии события:
            // «не получилось» без причины лечить так же нечем.
            UsageLog.note(.record, "invite:\(FamilyShare.причина(error))",
                          on: .family, outcome: .failed)
        }
    }

