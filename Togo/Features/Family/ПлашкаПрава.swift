import SwiftUI

/// «Этого права у тебя нет» — одной плашкой на все экраны.
///
/// # Зачем отдельный тип, а не плашка на каждом экране
///
/// Правило дизайна круга 5, п. 1: **выключенная кнопка допустима,
/// только если рядом словом сказано, чего не хватает. Иначе кнопка
/// включена и объясняет при нажатии.** Выключают орган по праву
/// одиннадцать экранов, и `.disabled` молчит у всех одиннадцати
/// по устройству: человек жал строку и получал тишину.
///
/// Писать плашку на каждом экране руками значило бы завести
/// одиннадцать копий одного отказа. Они разошлись бы молча — и это
/// не опасение, а измеренный в этом проекте класс: «две копии
/// разойдутся молча» стоит в своде отдельной строкой.
///
/// # Имя права берётся из `Permission.title`, а не пишется словами
///
/// Подпись посылает человека в «Семью» искать право по имени. Назови
/// мы его своими словами — он не найдёт его в списке, и экран, вся
/// работа которого сказать «куда смотреть», соврёт. `QuotedNamesTests`
/// ловил ровно это трижды за сутки 25.10.2026, в том числе на образце
/// этой плашки (`3c9a713`: «Modifier le protocole» вместо лежавшего
/// в каталоге «Modifier le traitement»).
///
/// Поэтому имя **интерполируется**: ключ в каталоге один —
/// `Право «%@» выдаёт владелец в разделе «Семья».` — а внутрь кавычек
/// приезжает `title`, уже переведённый. Расхождению взяться негде:
/// источник имени один и тот же в обоих местах.
///
/// # Чего эта плашка НЕ делает
///
/// Она не отменяет ответ дизайна по гостю (ОТВЕТЫ-круг-5, п. 2):
/// «органы, которых роль не даёт, гостю **не показываются**;
/// выключенными их не делаем». Там, где орган можно убрать совсем,
/// правильнее убрать. Плашка — для одиннадцати экранов, которые
/// выключают орган уже сегодня: она закрывает молчание, а не вопрос
/// «показывать ли вообще». Второе — решение дизайна, и оно открыто.
struct ПлашкаПрава: View {
    let право: Permission

    var body: some View {
        TGBanner(tone: .waiting,
                 title: .готовая(право.отказ),
                 subtitle: "Право «\(право.title)» выдаёт владелец в разделе «Семья».",
                 systemImage: "lock")
    }
}
