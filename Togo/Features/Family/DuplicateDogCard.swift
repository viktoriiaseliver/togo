import SwiftUI
import SwiftData

/// Две собаки с одной кличкой — и что с этим делать.
///
/// Замер 23.09.2026 на живом телефоне: две «Стич», записи разошлись
/// пополам — 56 у одной и 45 у другой. Человек видит две одинаковые
/// карточки и не понимает, которая «настоящая»; половина дня лежит
/// в той, которую он не смотрит.
///
/// Откуда берётся: приложение может открыть хранилище локально, а позже
/// получить право на iCloud — и тогда к локальной собаке приезжает
/// её облачная копия, заведённая раньше. У сборок 80 и 85 право
/// на iCloud как раз чинили, так что случиться это могло у любого.
///
/// Эвристики, по которым сделано именно так:
///
/// - **№1, видимость состояния.** Пока карточки нет, приложение молчит
///   о том, что знает: дубликат виден только человеку и только если он
///   заметит. Карточка называет вещь своим именем.
/// - **№5, предотвращение ошибок.** Очевидное действие — удалить
///   «лишнюю» собаку — уносит её записи каскадом. Поэтому удаления
///   здесь нет вовсе: есть слияние, и оно переносит.
/// - **№9, распознать и исправить.** Сказано, сколько записей переедет
///   и какая карточка останется, — до нажатия, а не после.
struct DuplicateDogCard: View {
    @Environment(\.modelContext) private var context
    @Query private var dogs: [Dog]

    @State private var слито: String?
    @State private var ошибка: String?

    /// Дубликаты — **только по настоящей кличке**.
    ///
    /// **Четвёртый случай одного класса за 07.10.2026, и единственный
    /// живой: эта карточка не под `#if DEBUG`**, её рисует
    /// `FamilyScreen:35` в розданной сборке.
    ///
    /// Группировка шла по `\.name`, а у `Dog.name` значение
    /// по умолчанию — `""`. У человека с кадра отзыва лежало восемь
    /// безымянных записей, то есть карточка говорила ему:
    ///
    /// ```
    /// «одна собака записана дважды»
    /// «»  в дневнике дважды, и записи разошлись…
    /// [Свести в одну]
    /// ```
    ///
    /// Кнопка переносит связи на самую раннюю запись группы и убирает
    /// остальные. При восьми фантомах это ложная тревога с разрушительной
    /// кнопкой; а если среди безымянных окажется НАСТОЯЩАЯ собака,
    /// которой кличку затёрло слиянием профиля (дефект того же дня),
    /// — её дневник переедет на фантом, заведённый раньше, а её запись
    /// исчезнет.
    ///
    /// > **Группировка по полю со значением по умолчанию собирает
    /// > в одну группу всё, что это поле не заполнило.**
    ///
    /// Своя дока этой карточки объясняет, почему здесь нет удаления:
    /// «очевидное действие — удалить „лишнюю“ собаку — уносит её записи
    /// каскадом». Осторожность была верной и обходилась с другой
    /// стороны: удаления нет, но **выбор «лишней» делался по пустому
    /// ключу**.
    /// **Надгробие отсеивается, кличка — нет, и это две разные оси.**
    ///
    /// Замер 26.10.2026. `@Query` здесь без предиката, то есть отдаёт
    /// собак из базы ЦЕЛИКОМ. До появления надгробия у `Dog` это было
    /// верно по устройству: удалённой собаки в базе не было. С `f546719`
    /// удаление собаки мягкое (`Editors.swift:373`), запись остаётся —
    /// и карточка начала считать дубликатом то, что человек уже удалил.
    ///
    /// Ущерб не в лишнем баннере. `главная` — `по_дате.first`, самая
    /// РАННЯЯ запись, а дубликат из облака по доке этого файла заведён
    /// раньше локального. Удали человек именно её — и «Свести в одну»
    /// перенесло бы весь дневник на НАДГРОБИЕ: `canBeShown` у неё
    /// ложно, `shownToPerson` её не отдаёт, и дневник исчез бы с экрана
    /// целиком, тем самым действием, которым его хотели починить.
    ///
    /// > **Введённое надгробие меняет смысл каждого нефильтрованного
    /// > чтения, и опаснее всех то, которое не показывает, а ВЫБИРАЕТ.**
    ///
    /// Фильтр стоит на `deletedAt`, а **не** на `canBeShown`: модель
    /// запрещает водить опознание через точку показа (`Dog.swift:417`),
    /// потому что запасное слово собрало бы всех безымянных в одну
    /// группу и отправило на склейку. Кличка по-прежнему берётся
    /// у `nameIfAny` — правда базы; надгробие отсеивается отдельным
    /// условием. Две оси, два условия.
    private var дубликаты: [String: [Dog]] {
        // Через `dog.nameIfAny`, а не `Fmt.notBlank(dog.name)`: правило
        // то же, но дорога к нему одна. Сторож `togo-02` поймал вторую
        // дорогу в тот же час, когда я её завёл, — на то он и заведён.
        // Тело, а не тройной оператор: у этого файла измеренная история
        // срывов типизатора (3333 мс, разбор у `связанных`), и `nil`
        // в ветке тройного оператора выводится из соседней ветки —
        // лишняя работа ровно там, где её уже не хватало.
        Dictionary(grouping: dogs.compactMap { dog -> (Dog, String)? in
            guard dog.deletedAt == nil, let кличка = dog.nameIfAny else { return nil }
            return (dog, кличка)
        }, by: \.1)
        .mapValues { $0.map(\.0) }
        .filter { $0.value.count > 1 }
    }

    var body: some View {
        if let ошибка {
            TGBanner(tone: .alarm, title: "Не получилось",
                     subtitle: .готовая(ошибка), systemImage: "exclamationmark.triangle")
        } else if let слито {
            TGBanner(tone: .done, title: "Собаки слиты",
                     subtitle: .готовая(слито), systemImage: "checkmark.circle")
        } else if let (кличка, группа) = дубликаты.sorted(by: { $0.key < $1.key }).first {
            TGCard {
                TGSectionHeader(title: "одна собака записана дважды")
                TGExplainer(text: .готовая(объяснение(кличка, группа)))
                TGButton(title: "Свести в одну", systemImage: "arrow.triangle.merge") {
                    свести(группа)
                }
            }
        }
    }

    private func объяснение(_ кличка: String, _ группа: [Dog]) -> String {
        let по_дате = группа.sorted { $0.createdAt < $1.createdAt }
        let старшая = по_дате[0]
        let переезжает = по_дате.dropFirst().map(ОбъединениеСобак.связанных).reduce(0, +)
        let когда = старшая.createdAt.formatted(date: .numeric, time: .shortened)
        let первое = String(localized: "«\(кличка)» в дневнике дважды, и записи разошлись: часть в одной карточке, часть в другой.")
        let второе = String(localized: "Сведу в ту, что заведена \(когда), и перенесу в неё \(переезжает) записей. Ничего не удалится.")
        return первое + " " + второе
    }

    private func свести(_ группа: [Dog]) {
        do { try слить(группа) }
        catch {
            слито = nil
            ошибка = String(localized: "Не вышло свести: \(error.localizedDescription)")
        }
    }

    /// Молчать здесь нельзя: человек нажал «свести», и если не вышло,
    /// он должен это увидеть, а не гадать, почему карточка осталась.
    ///
    /// **Надгробие вместо `context.delete`, с 26.10.2026.** Жёсткое
    /// удаление лишней карточки до второго человека не доезжало
    /// по устройству: удалённую запись `FamilySync.enqueueLocalChanges`
    /// не получает ни в `inserted`, ни в `updated`, собрать по ней
    /// `CKRecord` неоткуда. То есть Виктория сводила дубликат у себя,
    /// а у мамы оставались ДВЕ карточки — и вторая теперь пустая,
    /// потому что перенос связей до неё как раз доезжает. Починка
    /// дубликата у одного человека делала его хуже у второго.
    ///
    /// Пара «надгробие + `changedAt`» ставится только через
    /// `ОбщееУдаление`: половина пары опаснее целой.
    ///
    /// **Каскад здесь не при чём и раньше был при чём.** Связи
    /// перевешены выше, и ради этого стоял `save()` до удаления.
    /// Надгробие каскад не трогает вовсе, но `save()` оставлен:
    /// он гарантирует, что дети легли в хранилище ПРЕЖДЕ надгробия,
    /// и обрыв между двумя записями не оставит их на удалённой карточке.
    private func слить(_ группа: [Dog]) throws {
        let по_дате = группа.sorted { $0.createdAt < $1.createdAt }
        guard let главная = по_дате.first else { return }
        var перенесено = 0
        for лишняя in по_дате.dropFirst() {
            // Перенос — ОДНОЙ дорогой, `ОбъединениеСобак.перенести`.
            //
            // Здесь стояла вторая копия списка связей, и обе копии
            // были неполны одинаково: четыре связи медицинского слоя
            // (анализы, визиты, диагнозы, рецепты) не переносил никто.
            // Разбор — в голове `ОбъединениеСобак.перенести`.
            перенесено += ОбъединениеСобак.перенести(с: лишняя, на: главная)
            // Связи записываются ДО надгробия — разбор в доке метода.
            try context.save()
            // `_ =` обязателен: Xcode 26.3 считает брошенное замыкание ошибкой даже при
            // `@discardableResult` (CI, 04.11.2026: «function is unused»).
            _ = ОбщееУдаление.удалить(лишняя)
        }
        try context.save()
        слито = String(localized: "Перенесено записей: \(перенесено). Дневник снова один.")
        Haptics.success()
    }

    /// Сколько записей висит на собаке — по всем одиннадцати связям.
    ///
    /// **Сумма набирается в цикле, а не одним выражением, и это
    /// не стиль.** Прежняя редакция складывала одиннадцать слагаемых
    /// вида `(x?.count ?? 0)` в одном выражении, и на раннере CI
    /// компилятор не уложился:
    ///
    /// ```
    /// The compiler is unable to type-check this expression
    /// in reasonable time; try breaking up the expression
    /// → Testing cancelled because the build failed
    /// ```
    ///
    /// **Локально оно собиралось**, и потому дефект был невидим: сборка
    /// на моей машине и сборка на раннере отличались загрузкой, а
    /// не кодом. Шесть прогонов CI подряд падали на нём, и сверка
    /// эталона честно говорила «сверять нечем» — то есть инструмент
    /// наблюдения отказывался называть это и зелёным, и красным,
    /// а мы час искали регрессии, которых не было.
    ///
    /// Срыв типизатора у `??` в длинной цепочке `+` — известная форма:
    /// у каждого слагаемого два возможных типа, и перебор растёт
    /// степенью. Цикл убирает перебор целиком.
    /// **Вторая редакция, и первая сняла отказ, не восстановив запас.**
    /// Замер 07.10.2026 флагом `-warn-long-function-bodies=500`:
    ///
    /// ```
    /// цикл по литералу массива   3333 мс   ← самое медленное в проекте
    /// сложение по одному         ниже порога 500, в список не попало
    /// ```
    ///
    /// Перебор не исчез от перехода к циклу — он **переехал**: литерал
    /// `[a?.count, b?.count, …]` из одиннадцати элементов требует вывести
    /// общий тип элемента, и кандидатов у каждого по-прежнему два.
    /// Три с лишним секунды — та же близость к пределу, под которой этот
    /// файл упал на раннере: разница между машинами здесь загрузка,
    /// а не код.
    ///
    /// > **Отказ снят ≠ запас восстановлен.** Следующий, кто добавит
    /// > двенадцатую связь, снова получит красный CI и снова не поймёт,
    /// > почему локально собирается.
    ///
    /// Сложение по одному выражению на строку выводить нечего: у каждой
    /// строки тип известен из `всего`. Длиннее на вид и дешевле по сути.
}
