import SwiftUI

/// Что человек узнаёт о своей роли — одним местом на три экрана.
///
/// # Зачем отдельным типом, а не тремя строками по местам
///
/// Дизайн назвал три места, где человек узнаёт роль
/// (`Дизайн/редизайн-ios28/ОТВЕТЫ-круг-5.md`, п. 2):
///
/// ```
/// вход по ссылке     карточка перед принятием
/// «Собака → Семья»   своя строка ПЕРВОЙ
/// «Сегодня»          строка на месте кнопок, тап ведёт в «Семью»
/// ```
///
/// **Первого места в коде нет, и не будет — решено 05.11.2026.**
/// Ссылку из сообщения система открывает своим листом приглашения
/// (с названием «Дневник · <кличка>» и владельцем), а вставленный
/// руками адрес человек принимает сам, и исход называет, чей это
/// дневник (`ShareAcceptance.принять(ссылку:)`). Своя карточка перед
/// принятием была бы вторым вопросом о том же. Формулировки
/// `зовётВДневник` и `сможешь` ждали её с 25.10 (`c754d386`) без
/// единого вызова и сняты.
///
/// Три места, одно утверждение — «ты смотришь, отмечает <кто-то>».
/// Разнеси его по трём файлам, и копии разойдутся молча: у этого
/// проекта это уже оплачено трижды («сам он их не поменяет» встречалось
/// в трёх местах разом). Поэтому здесь не вид, а **формулировка**:
/// каждое из трёх мест рисует себя само, а слова берёт отсюда.
///
/// # Слово роли берётся ИЗ РОЛИ, а не печатается рукой
///
/// Дизайн сказал прямо: «Когда права начнут ехать через обмен, слова
/// „наблюдатель / ухаживающий" берутся из роли, строки те же». Значит
/// сегодня, пока роль гостя потолком прибита к `.observer`
/// (`FamilyResolver.потолокГостя`), здесь всё равно стоит `роль.title`,
/// а не литерал «наблюдатель»: в день, когда роль поедет по обмену,
/// править будет нечего.
///
/// Регистр — строчный, как в макете, и `lowercased()` поверх перевода
/// здесь **не изобретение, а здешний приём**: ровно так собрана подпись
/// соседней строки списка (`MemberRow.подпись`,
/// `FamilyScreen.swift:770`). Две строки стоят в одной карточке друг
/// под другом, и разойтись регистром им нельзя.
///
/// # Имя владельца подставляется, и его может не быть
///
/// `SharedZoneOwner.name` для этого **не годится**: там лежит
/// непрозрачный идентификатор зоны CloudKit (`_a1b2…`), человеку его
/// показывать нельзя — это написано в его же описании
/// (`FamilyShare.accepted(ownerName:)`). Человеческое имя живёт
/// в карточке участника с ролью `.owner`, которая приезжает гостю
/// общим дневником.
///
/// Имени может не быть вовсе: пока карточки семьи не доехали, список
/// у гостя пуст. Тогда вместо имени — слово «владелец». Это не
/// подстановка наугад, а **то же самое утверждение без имени**:
/// «отмечает владелец» верно всегда.
struct РольВДневнике {
    let роль: FamilyRole
    /// Имя владельца дневника для человека. `nil` — ещё не знаем.
    let имяВладельца: String?

    /// Собрать из того, что есть на этом телефоне.
    ///
    /// - Parameters:
    ///   - роль: `AppState.role` — она уже прошла опознание и потолок
    ///     гостя, и переспрашивать её здесь нечем.
    ///   - участники: список семьи. Ищем в нём владельца, а не «не меня»:
    ///     участников может быть много, владелец один.
    static func текущая(роль: FamilyRole, среди участники: [FamilyMember]) -> РольВДневнике {
        let владелец = участники.first { $0.role == .owner }
        return РольВДневнике(роль: роль,
                             имяВладельца: Fmt.notBlank(владелец?.name ?? ""))
    }

    /// Рисовать ли свою строку НАД списком семьи — и `nil`, если не надо.
    ///
    /// # Почему решение переехало сюда из экрана
    ///
    /// В `FamilyScreen` оно было одним условием — «своей карточки
    /// не нашлось», — и это **прокси**, а не предмет. Опознание
    /// (`FamilyResolver.меня`) держится на `myMemberID`, который пишет
    /// ТОЛЬКО онбординг (`FamilyResolver.swift:82`), и на `isMe`,
    /// который берётся лишь при единственном участнике. Любая причина,
    /// по которой опознание не состоялось, включает строку — в том
    /// числе у хозяина, которому её обещали не показывать.
    ///
    /// Так и вышло на четырёх кадрах витрины 27.10 (ru · en · fr · uk):
    /// роль упала в `рольБезОпознания(гость: false) = .owner`, и экран
    /// нарисовал **«Ты · владелец» над карточкой «Виктория · владелец»**.
    /// Человек не может сказать, какая из двух строк он, — а экран
    /// решает, кто имеет право ставить дозу.
    ///
    /// # Ось — утверждение МОДЕЛИ, а не признак опознания
    ///
    /// «Участников может быть много, владелец один» записано строкой
    /// ниже, у `текущая(роль:среди:)`, и это не оговорка, а устройство:
    /// роль `.owner` по приглашению не раздаётся вовсе
    /// (`FamilyScreen.swift:958`, `allCases.filter { $0 != .owner }`).
    /// Значит владелец в списке + моя роль `.owner` означает «я и есть
    /// эта карточка, просто неопознанная», и своя строка меня **удвоит**.
    ///
    /// Обратное — поставить «это я» на найденную карточку владельца —
    /// делать **нельзя**: резолвер отказывается от догадки нарочно,
    /// «поставить „это я" на чужого человека хуже, чем не поставить
    /// никому» (`FamilyResolver.swift:88`). Здесь мы убираем лишнюю
    /// строку, а не придумываем опознание.
    ///
    /// У гостя ничего не меняется: его роль потолком прибита
    /// к `.observer` (`FamilyResolver.потолокГостя`), совпасть
    /// с владельцем списка ей нечем, и строка «Ты · наблюдатель»
    /// остаётся — она и есть единственный ответ на «а что мне здесь
    /// можно». И у хозяина, который себя в список не заводил вовсе,
    /// строка тоже остаётся: владельца в списке нет, удваивать нечего.
    ///
    /// - Parameter опознан: нашлась ли СВОЯ карточка в списке.
    ///   Приходит исходом `FamilyResolver.меня(…)`, а не пересчитывается
    ///   здесь: два вызова одного резолвера в одном экране уже
    ///   расходились (починка 25.10.2026).
    static func своя(роль: FamilyRole,
                     среди участники: [FamilyMember],
                     опознан: Bool) -> РольВДневнике? {
        guard !опознан else { return nil }
        if роль == .owner, участники.contains(where: { $0.role == .owner }) {
            return nil
        }
        return текущая(роль: роль, среди: участники)
    }

    /// Сколько строк нарисует карточка участников.
    ///
    /// **Заголовок берёт число ОТСЮДА, а не из `members.count`.**
    /// До 04.11.2026 он печатал длину списка, а карточка рисовала
    /// на одну строку больше — свою. На кадрах витрины 27.10 выходило
    /// «УЧАСТНИКИ · 5» над шестью строками на всех четырёх языках;
    /// собственный старый кадр `Дизайн/кадры-приёмки/журнал-приёмки/
    /// семья-низ-f0bda5c-ПОСЛЕ-3a72afc-ДЕФЕКТ-ЖИВ.png` показывает «5»
    /// над ровно пятью — то есть это регрессия, а не замысел.
    ///
    /// Число и строки считаются **одним выражением**: пока их два,
    /// они расходятся молча, и расходились.
    static func строк(среди участники: [FamilyMember], своя: РольВДневнике?) -> Int {
        участники.count + (своя == nil ? 0 : 1)
    }

    /// «Ты · наблюдатель» — строка своей роли в списке семьи.
    var ты: String {
        String(localized: "Ты · \(роль.title.lowercased())")
    }

    /// «смотришь всё · отмечает владелец» — подпись под ней.
    ///
    /// Имя здесь НЕ подставляется нарочно, хотя рядом в «Сегодня»
    /// подставляется. Это соседняя строка со списком семьи, где имя
    /// владельца стоит через две строки своей карточкой: повторить его
    /// значило бы написать одно имя дважды в одном поле зрения.
    var чтоМогу: String {
        роль.canWrite
            ? String(localized: "отмечаешь и смотришь · приглашает владелец")
            : String(localized: "смотришь всё · отмечает владелец")
    }

    /// «Ты смотришь дневник · отмечает Виктория» — строка на «Сегодня».
    ///
    /// Здесь имя подставляется: это единственное место, где человек
    /// видит строку **без** списка семьи рядом, и «отмечает владелец»
    /// не отвечает на вопрос, к кому идти.
    var строкаСегодня: String {
        guard let имяВладельца else {
            return String(localized: "Ты смотришь дневник · отмечает владелец")
        }
        return String(localized: "Ты смотришь дневник · отмечает \(имяВладельца)")
    }
}
