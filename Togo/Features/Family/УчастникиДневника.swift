import SwiftUI

/// Кто в общем дневнике — и два рычага, которых у владельца не было.
///
/// # Что здесь чинится, и почему это не новая фича
///
/// В `ВОПРОСЫ.md` лежали два открытых пункта, и оба описывали не выбор,
/// а отсутствие органа:
///
/// ```
/// 2-бис  «Чем владелец закрывает доступ ОДНОМУ человеку»
///        `removeParticipant` — ноль вхождений. Рычаг один и всеобщий:
///        «Перестать делиться» закрывает дневник сразу для всех
/// 1-бис  «Роль уже вошедшему не поменять никак»
///        роль ехала только с приглашением, одна на всех вошедших
///        по этой ссылке
/// ```
///
/// Оба закрыты 26.10.2026, и **ни один не потребовал правки формы
/// схемы**. Разбор, почему не потребовал, стоит у `FamilyShare
/// .назначить(_:права:участнику:)`: ключ наряда отдаёт сам CloudKit,
/// а не локальная карточка, и поле `поУчастникам` существует в наряде
/// с первой версии.
///
/// # Почему это ОТДЕЛЬНЫЙ экран, а не кнопки на карточке участника
///
/// `MemberScreen` показывает **локальную карточку** `FamilyMember`.
/// Это другой предмет, и разница измерена:
///
/// ```
/// FamilyMember         живёт на ЭТОМ телефоне. Из обмена убран
///                      решением 08.10.2026 (`SharedDiary.swift:78`),
///                      на второй телефон не уезжает вовсе
/// участник CloudKit    живёт в записи общего доступа. Его видят все,
///                      и права гостя решаются ЕГО ключом
/// ```
///
/// Связи между ними нет, и завести её — правка формы схемы, то есть
/// решение Виктории. Нарисовать «закрыть доступ» на карточке значило бы
/// обещать, что эта кнопка знает, какому участнику карточка
/// соответствует. Она не знает, и угадать нельзя: имена не уникальны.
///
/// > **Поэтому список участников — свой, и он называет людей так, как
/// > их знает CloudKit.** Это не дубль «Семьи»: там карточки, которые
/// > завёл хозяин, здесь — те, кто реально имеет доступ. Две разные
/// > правды, и путать их дороже, чем показать дважды.
///
/// # Чего отзыв доступа НЕ делает, и это сказано человеку
///
/// Записи, которые гость уже получил, остаются у него на телефоне:
/// забрать показанное iCloud не умеет. Отзыв закрывает будущее,
/// а не прошлое — так же, как «Перестать делиться», где это уже
/// написано.
struct УчастникиДневника: View {

    @State private var участники: [УчастникДневника] = []
    /// Спрашивали ли облако хоть раз.
    ///
    /// **Отдельно от пустого списка, и это предмет.** «Ещё не спросили»
    /// и «спросили, никого нет» — разные состояния, а показываются
    /// одинаково пустым списком. Пустое состояние, выданное за ответ,
    /// говорит владельцу «ты один в дневнике» в ту секунду, когда
    /// приложение просто не успело спросить.
    @State private var спросили = false
    @State private var выбранный: УчастникДневника?

    var body: some View {
        TGScreen {
            if SharedZoneOwner.isGuest {
                гостю
            } else {
                содержимое
            }
        }
        .navigationTitle("Доступ к дневнику")
        .cinemaScreen(экран: .sub("family"))
        .task { await обновить() }
        .refreshable { await обновить() }
        .sheet(item: $выбранный) { участник in
            ДоступУчастника(участник: участник) {
                Task { await обновить() }
            }
        }
    }

    @ViewBuilder
    private var содержимое: some View {
        TGCard {
            TGSectionHeader(title: "кто имеет доступ · \(участники.count)")
            if !спросили {
                TGExplainer(text: "Спрашиваю iCloud…")
            } else if участники.isEmpty {
                // Пусто здесь значит одно из двух, и оба безобидны:
                // делиться ещё не начали, либо список не приехал.
                // Ни в одном случае нельзя сказать «ты один» — у этого
                // дневника может быть принявший участник, которого
                // мы просто не спросили.
                TGExplainer(text: "Приглашение ещё не создано — или список не приехал. Создай приглашение в «Семье» и позови человека.")
            } else {
                ForEach(участники) { участник in
                    строка(участник)
                    if участник.id != участники.last?.id { TGDivider(inset: 38) }
                }
            }
        }

        TGExplainer(text: "Это те, кто реально видит дневник через iCloud. Список семьи рядом — карточки на твоём телефоне, они нужны для подписи записей и живут отдельно.")
    }

    /// Гость сюда попасть не должен, и кнопку ему не рисуют
    /// (`потолокГостя` снимает `manageFamily` безусловно). Но экран
    /// доступен маршрутом, а маршрут переживает правку кнопки —
    /// поэтому отказ назван здесь, а не оставлен пустому списку.
    private var гостю: some View {
        TGBanner(tone: .waiting,
                 title: "Доступом управляет владелец",
                 subtitle: "Ты в чужом дневнике. Кого пускать и какую роль дать — решает тот, кто позвал.",
                 systemImage: "eye")
    }

    private func строка(_ участник: УчастникДневника) -> some View {
        Button {
            // Владельца не трогают: ни роль, ни доступ. Открывать лист
            // ему незачем, и выключенная строка обещала бы, что когда-то
            // будет можно.
            guard !участник.владелец else { return }
            выбранный = участник
        } label: {
            HStack(spacing: Token.Space.s12) {
                TGAvatar(initial: буква(участник), tint: Token.Surface.raised)
                VStack(alignment: .leading, spacing: Token.Space.s2) {
                    Text(.готовая(имя(участник))).textStyle(AppFont.bodyEmphasis).wraps()
                    Text(.готовая(подпись(участник))).textStyle(AppFont.caption).wraps()
                }
                Spacer(minLength: Token.Space.s8)
                if !участник.владелец {
                    Image(systemName: "chevron.right")
                        .font(.system(size: Token.Size.iconSm, weight: .semibold))
                        .foregroundStyle(Token.Ink.secondary)
                }
            }
            .frame(minHeight: Token.Size.controlXL)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .disabled(участник.владелец)
    }

    /// Имя для показа. **`nil` называется словом, а не подставляется.**
    ///
    /// CloudKit отдаёт `nameComponents` не всегда, и почты у участника
    /// может не быть вовсе — это уже знает `ShareAcceptance.чьёИмя`
    /// и говорит об этом прямо. Подставить сюда «Участник 2» значило бы
    /// выдать наш счётчик за имя человека.
    private func имя(_ участник: УчастникДневника) -> String {
        участник.подпись ?? String(localized: "Без имени")
    }

    private func буква(_ участник: УчастникДневника) -> String {
        участник.подпись.map { String($0.prefix(1)) } ?? "?"
    }

    /// Вторая строка: кто он здесь. Четыре состояния, и ни одно
    /// не покрывается текстом другого.
    private func подпись(_ участник: УчастникДневника) -> String {
        var части: [String] = []
        if участник.владелец { части.append(String(localized: "владелец дневника")) }
        if участник.я { части.append(String(localized: "это ты")) }
        if !участник.принял && !участник.владелец {
            части.append(String(localized: "позвали, ещё не вошёл"))
        }
        if let роль = участник.роль {
            // Заголовок роли уже переведён внутри перечисления —
            // второй раз переводить нельзя.
            части.append(роль.title.lowercased())
        } else if участник.принял && !участник.владелец {
            части.append(String(localized: "роль из приглашения"))
        }
        return части.joined(separator: " · ")
    }

    private func обновить() async {
        участники = await FamilyShare.участники()
        спросили = true
    }
}

/// Роль и доступ **одному** человеку.
///
/// # Почему роль и отзыв в одном листе
///
/// Это один вопрос владельца, заданный в одну минуту: «что этому
/// человеку можно». Понижение и отзыв — две точки одной шкалы, и держать
/// их на разных экранах значило бы заставить выбирать между ними,
/// не видя второй. Ситтеру на неделю чаще нужно понижение, а не отзыв,
/// — и пока отзыв был единственным рычагом (всеобщим), владелец
/// закрывал дневник всей семье.
struct ДоступУчастника: View {
    let участник: УчастникДневника
    /// Что-то изменилось — список снаружи обязан перечитать облако.
    var приПравке: () -> Void

    @Environment(\.dismiss) private var dismiss

    @State private var работаем = false
    @State private var отказ: String?
    @State private var подтверждаемОтзыв = false
    /// Роль, которую уже применили в этом листе, — чтобы выбранный чип
    /// не отъезжал назад до того, как список перечитает облако.
    @State private var выбраннаяРоль: FamilyRole?

    private var роль: FamilyRole? { выбраннаяРоль ?? участник.роль }

    var body: some View {
        TGSheet(title: .готовая(участник.подпись ?? String(localized: "Без имени")),
                subtitle: "роль и доступ") {
            рольКарточка
            доступКарточка
            if let отказ {
                TGBanner(tone: .alarm, title: "Не получилось",
                         subtitle: .готовая(отказ),
                         systemImage: "exclamationmark.triangle")
            }
        } footer: {
            EmptyView()
        }
        .presentationDetents([.large])
        .confirmationDialog("Закрыть доступ этому человеку?",
                            isPresented: $подтверждаемОтзыв, titleVisibility: .visible) {
            Button("Закрыть доступ", role: .destructive) { Task { await отозвать() } }
            Button("Отмена", role: .cancel) { }
        } message: {
            Text("Новые записи к нему приходить перестанут. То, что он уже получил, останется у него на телефоне: забрать показанное iCloud не умеет. Остальные в дневнике останутся.")
        }
    }

    @ViewBuilder
    private var рольКарточка: some View {
        TGCard {
            TGSectionHeader(title: "роль", subtitle: "уезжает на его телефон")
            if участник.ключНаряда == nil {
                // ЭТО НЕ «ПОКА НЕЛЬЗЯ» — ЭТО «ЕЩЁ НЕ СУЩЕСТВУЕТ КЛЮЧА».
                //
                // Роль лежит в наряде под `userRecordID.recordName`,
                // а его CloudKit заводит в момент, когда человек принял
                // приглашение. До тех пор писать некуда, и орган здесь
                // был бы входом без механизма: владелец выбрал бы роль,
                // увидел бы выбранный чип и ушёл уверенным.
                //
                // Поэтому чипов нет вовсе, а вместо них сказано, что
                // действует: роль из приглашения. Доступ при этом
                // отзывается и у него — ключ наряда для этого не нужен,
                // CloudKit знает его по почте.
                TGExplainer(text: "Человек ещё не вошёл. Ему приедет роль, выбранная в приглашении; поменять её можно будет, когда он войдёт.")
            } else {
                TGChipGroup(
                    // Владельца в списке нет: роль `.owner` по обмену
                    // отдала бы дневник целиком, включая право позвать
                    // следующего. Такого решения никто не принимал —
                    // тот же состав, что в приглашении
                    // (`FamilyScreen.swift:571`).
                    items: FamilyRole.allCases.filter { $0 != .owner },
                    title: \.title,
                    subtitle: { $0.permissionSummary },
                    isSelected: { $0 == роль }
                ) { выбор in
                    Task { await назначить(выбор) }
                }
                .disabled(работаем)
                TGExplainer(text: "Роль доедет при следующем обмене — обычно в течение минуты. Схему лечения второй телефон не правит ни при какой роли.")
            }
        }
    }

    @ViewBuilder
    private var доступКарточка: some View {
        TGCard {
            TGSectionHeader(title: "доступ")
            TGExplainer(text: "Закроет дневник только этому человеку. Остальные останутся, и приглашение заново создавать не нужно.")
            TGButton(title: работаем ? "Закрываю…" : "Закрыть доступ",
                     variant: .destructive, size: .medium,
                     systemImage: "person.badge.minus",
                     isEnabled: !работаем) {
                подтверждаемОтзыв = true
            }
        }
    }

    private func назначить(_ выбор: FamilyRole) async {
        guard let ключ = участник.ключНаряда else { return }
        работаем = true
        отказ = nil
        defer { работаем = false }
        do {
            try await FamilyShare.назначить(выбор, участнику: ключ)
            выбраннаяРоль = выбор
            Haptics.success()
            UsageLog.note(.record, "roleByParticipant", on: .family)
            приПравке()
        } catch {
            // Вид отказа — в названии события: «не получилось» без
            // причины лечить так же нечем.
            отказ = error.localizedDescription
            Haptics.warning()
            UsageLog.note(.record, "roleByParticipant:\(FamilyShare.причина(error))",
                          on: .family, outcome: .failed)
        }
    }

    private func отозвать() async {
        работаем = true
        отказ = nil
        defer { работаем = false }
        do {
            try await FamilyShare.убрать(участника: участник.id)
            Haptics.success()
            UsageLog.note(.record, "revokeAccess", on: .family)
            приПравке()
            dismiss()
        } catch {
            отказ = error.localizedDescription
            Haptics.warning()
            UsageLog.note(.record, "revokeAccess:\(FamilyShare.причина(error))",
                          on: .family, outcome: .failed)
        }
    }
}
