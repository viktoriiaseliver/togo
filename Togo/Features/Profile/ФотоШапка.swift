import SwiftUI

/// Блок `Hero` темы «Кино»: фото во всю ширину, надстрочник, крупный
/// заголовок и прижатая к низу карточка.
///
/// Эталоны — `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/09.png`
/// (вкладка собаки) и `12.png` («Семья»). Решение Виктории 22.10.2026,
/// `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`, раздел «РЕДИЗАЙН iOS 28»: «Фото под
/// шапкой на каждом экране, высота 640 (Сегодня) / 420 (вкладка) /
/// 360 (подэкран)».
///
/// **Это НЕ `TGPosterHeader`.** Тот — плоская цветная полоса `--poster-bg`
/// из поколения Graphite, и на двух этих экранах он снят: в «Кино» под
/// шапкой лежит фотография, а не заливка. `TGPosterHeader` остаётся
/// живым у остальных сорока с лишним экранов, и трогать его отсюда
/// нельзя — `Togo/DesignSystem/**` правит другая сессия.
///
/// # Почему блок живёт в `Togo/Features`, а не в дизайн-системе
///
/// Правильное место для него — `Togo/DesignSystem/Components/`, рядом
/// с `TGPosterHeader`. Он там и должен оказаться, и это **открытый
/// вопрос, а не умолчание**: на 23.10.2026 `Togo/DesignSystem/**` отдан
/// другой сессии, и заводить туда файл значит класть правку в чужое
/// незакоммиченное.
///
/// Цена переезда названа здесь, чтобы её не искали: при переезде тип
/// переименовывается в `TGBackdrop` и забирает себе
/// `Token.Component.Backdrop.*` — см. следующий раздел.
///
/// # Чего этот блок НЕ рисует, и это замер, а не упрощение
///
/// Дизайн задаёт затемнение фотографии **восемью стопами** с плато
/// между 30 % и 38 % («там лежит шапка, и затемнение там не растёт»)
/// плюс отдельную маску исчезновения на двух позициях. Оба значения
/// в проекте есть и лежат в `Token.Component.Backdrop.scrim` и `.mask`.
///
/// **Позвать их отсюда нельзя по устройству храповика.** Замер
/// 23.10.2026, `git grep` по `*.swift` вне `Generated`:
///
/// ```
/// Token.Component.Backdrop     0 читателей
/// Token.FontSize.titleLarge    0 читателей
/// Token.FontTracking.titleLarge 0 читателей
/// контроль Token.FontSize.poster  найден (Typography.swift, 2 вхождения)
/// ```
///
/// `ComponentTokenScopeTests` запрещает `Token.Component.*` в
/// `Togo/Features` — и запрещает правильно: «если компонентный токен
/// спрашивает экран, значит экран пересобирает компонент». Компонента,
/// которому эти стопы принадлежат, **не существует**, а место, где ему
/// положено быть, мне закрыто. Поэтому здесь двухстоповое затемнение,
/// и расхождение с макетом названо, а не замазано.
///
/// И вторая половина, найденная кадром: взять эти стопы сегодня было бы
/// **хуже**, чем не взять. Все восемь рисуются непрозрачным синим —
/// разбор у `затемнение`.
///
/// > **Источник правды содержит решение, которого не исполняет ни один
/// > читатель.** Ровно тот же случай, что `Token.FontSize.micro = 14`
/// > при живом `AppFont.micro = 15`: имя есть, значение есть, вызова
/// > по имени нет. Опусти стопы до двух — не покраснеет ничто.
///
/// Кегль заголовка — `Token.FontSize.titleLarge` (36) с трекингом
/// `Token.FontTracking.titleLarge` (−0,9 pt). Стиля под них в `AppFont`
/// нет, поэтому `TextStyleToken` собирается здесь; завести стиль
/// в `Typography.swift` — тот же закрытый каталог.
struct ФотоШапка<Низ: View>: View {

    /// Снимок, который показывается фоном. Пусто — остаётся полотно:
    /// это честное состояние, а не ошибка. У человека, который фото
    /// не клал, его и нет.
    let фото: Data?

    /// Высота блока. Приходит `Token.Size.backdropTab` или
    /// `.backdropSub` — числа отсюда не берутся нарочно, у них один дом.
    let высота: CGFloat

    /// Якорь кадрирования снимка. Разбор и происхождение чисел —
    /// в голове `ЯкорьКадра`; коротко: без него подложка кадрируется
    /// по центру и у портретной фотографии срезает голову (отзыв 28.10.2026).
    ///
    /// **Обязательный параметр, а не умолчание, и это решение.** Доля
    /// у `.tab` и у `.sub` сегодня одна и та же — 0,35, — то есть
    /// умолчание `.по(виду: .tab)` работало бы верно на обоих живых
    /// местах вызова и **перестало бы работать молча** в день, когда
    /// дизайн разведёт эти два вида. Это наш записанный класс «условие,
    /// привязанное к сегодняшнему совпадению, меняет знак в момент,
    /// когда плохих новостей не ждут». Здесь оно стоит рядом с высотой,
    /// на той же паре строк: кто выбирает одно, выбирает и второе.
    let якорь: ЯкорьКадра

    /// Надстрочник: «ШИППЕРКЕ · 3 ГОДА», «3 ЧЕЛОВЕКА · ДЕЖУРИТ ВИКА».
    ///
    /// `String`, а не `LocalizedStringKey`, и рисуется `Text(verbatim:)`.
    /// Причина — замер, записанный в `Подпись.swift`: `.готовая(строка)`
    /// это обычный ключ каталога, и поиск по каталогу он **выполняет**.
    /// В надстрочнике стоят кличка и имя человека; собранный ключ
    /// однажды совпал с данными побуквенно, и живой отзыв `AEXYTDmy`
    /// сказал «где-то stitch а где-то Стич». Перевод берётся
    /// `String(localized:)` на месте сборки.
    let надстрочник: String?

    /// Заголовок. Случай `.значение` — для клички: её переводить нечем.
    let заголовок: TGPosterHeader.Название

    /// Карточка, прижатая к низу фотографии. На кадре `09` это опись
    /// собаки, на `12` — карточка дежурства.
    @ViewBuilder let низ: Низ

    // Повышенный контраст в системе читает теперь `TGHeaderScrim`:
    // у слоя затемнения своя плотность, и выбирает её компонент.
    // Объявление снято 26.10.2026 как оставшееся без читателей
    // (замер: `grep` по файлу с вырезанной прозой — одна строка,
    // и это само объявление). Решением 23.10.2026 повышенный контраст
    // у «Кино» наконец описан — и описан он теперь в токенах
    // (`alphaHC`), а не в трёх копиях тернарника.

    /// **Фотография уехала в `.background`, а не лежит слоем `ZStack`,
    /// и это починка, пойманная кадром.**
    ///
    /// Первая редакция складывала подложку и надпись в
    /// `ZStack(alignment: .bottom)`. На пустой подложке всё было верно;
    /// кадр 23.10 с настоящим снимком показал, что **кикер исчез**,
    /// а заголовок уехал на его место:
    ///
    /// ```
    /// без фото   ШИППЕРКЕ / Стич / … / опись     ← всё на месте
    /// с фото     Стич / … / опись                ← «ШИППЕРКЕ» срезан сверху
    /// ```
    ///
    /// Причина — не отступы. `Image.resizable().scaledToFill()` имеет
    /// **огромный идеальный размер**, `ZStack` предлагает его соседям,
    /// `Spacer` внутри надписи растягивается по предложенному, стопка
    /// становится выше блока — и при выравнивании по низу верх уходит
    /// под обрез. Фотография двигала надпись, которую должна была
    /// только подпирать.
    ///
    /// `.background` обратной связи не даёт: его содержимому предлагают
    /// размер хозяина, а не наоборот. Поэтому снимок больше не участвует
    /// в раскладке вовсе.
    ///
    /// > **Пустое состояние показало блок исправным.** Отличить
    /// > «работает» от «нечему ломаться» было нечем, пока в `dog.photo`
    /// > не легло хоть что-то, — а положить туда до этой правки было
    /// > нечего. Проверка на пустых данных отвечает про данные.
    var body: some View {
        VStack(alignment: .leading, spacing: Token.Space.s12) {
            шапка
            Spacer(minLength: Token.Space.s16)
            низ.padding(.horizontal, Token.Spacing.screenPadding)
        }
        .padding(.top, Token.Space.s8)
        .padding(.bottom, Token.Space.s16)
        .frame(maxWidth: .infinity, minHeight: минимумБлока, alignment: .leading)
        .background { подложка }
        // Заголовок экрана озвучивается один раз: `navigationTitle`
        // у этих двух экранов остаётся ради кнопки «назад», а читает
        // человек то, что нарисовано.
        .accessibilityElement(children: .contain)
    }

    /// Сколько блок занимает **наименьшее**. Пусто — не занимает ничего.
    ///
    /// # Высота 360 принадлежит ПОДЛОЖКЕ, а не содержимому
    ///
    /// Здесь стояло `.frame(height: высота)` — жёсткая высота на блок
    /// целиком. Это читало число не того предмета: `backdrop.height`
    /// описывает **фотографию**, и у соседа по теме
    /// (`CinemaBackdrop`) она так и заведена — подложка в `.background`,
    /// содержимое течёт своей высотой. Здесь же 360 назначались
    /// надписи и карточке, а `Spacer` внутри разгонял их по краям
    /// блока.
    ///
    /// **Без фотографии это давало треть экрана пустоты.** Замер
    /// по кадру `Дизайн/кадры-приёмки/витрина-редизайн-23.10/06-family.png`
    /// (402×874 pt): заголовок «Семья» кончается на 181 pt, карточка
    /// дежурного начинается на 347 pt — **166 pt чёрного между ними**,
    /// и дальше список участников уезжает под плавающую пилюлю.
    /// На эталоне `screenshots/12.png` карточка стоит сразу под
    /// заголовком, а 360 pt занимает **фон за ней и за списком**.
    ///
    /// Третью ступень цепочки фона дизайн назвал прямо (ОТВЕТЫ-круг-2,
    /// пункт 1): «чёрный `#000` **без подложки**… не «пустая картинка»,
    /// а ДРУГОЙ режим отрисовки». `CinemaBackdrop` это исполняет,
    /// `ФотоШапка` — нет: место под подложку она держала и тогда,
    /// когда подложки не существует.
    ///
    /// **`minHeight`, а не `height`, и это вторая половина починки.**
    /// Жёсткая высота на крупном системном кегле работала в другую
    /// сторону: заголовок 36 pt растёт, карточка дежурного растёт,
    /// а 360 остаются — и нижнее выдавливается за край блока. Минимум
    /// держит кадр при фотографии и пускает блок расти, когда текста
    /// больше. У соседа это сделано отдельной ступенью (`heroAX`);
    /// минимум закрывает оба случая одной величиной.
    ///
    /// Приёмка тут — **кадр**, а не число: прогон пустоты не видит
    /// по устройству (ПОДПИСИ.md витрины называет это прямым словом).
    private var минимумБлока: CGFloat? {
        фото == nil ? nil : высота
    }

    // MARK: Фон

    /// Полотно, снимок поверх него, затемнение поверх снимка.
    ///
    /// **Под статус-бар этот блок НЕ уходит, хотя на кадрах `09` и `12`
    /// фотография доходит до самого верха экрана.** Замер 23.10.2026:
    /// `.ignoresSafeArea(edges: .top)` на подложке верх не поднял
    /// и при этом срезал кикер — то есть ответил не на тот вопрос.
    ///
    /// Чинится это не модификатором, а **каркасом экрана**: содержимое
    /// `TGScreen` живёт в `ScrollView`, у которого свой отступ под
    /// навигационную панель, и снять его может только тот, кто этот
    /// `ScrollView` строит. `TGScreen` лежит в `Togo/DesignSystem`,
    /// отданном другой сессии. Расхождение названо и измерено, а не
    /// обойдено.
    private var подложка: some View {
        Token.Surface.page
            .overlay {
                if let фото, let снимок = КэшСнимков.картинка(фото) {
                    // Было `Image….resizable().scaledToFill()` — центр
                    // снимка в центре окна. У портрета 3 : 4 в окне 420
                    // это срезало ~58 pt сверху и снизу (замер кадром
                    // 25.10.2026), то есть макушку. Отзыв 28.10 назвал
                    // это словами человека: «срезает голову».
                    КадрПоЯкорю(картинка: снимок, якорь: якорь)
                }
            }
            .overlay { затемнение }
            // Фотография шире блока: без обрезки `scaledToFill` вылезает
            // за края и наезжает на соседей по прокрутке.
            .clipped()
            .accessibilityHidden(true)
    }

    /// Два стопа вместо восьми — см. разбор в голове типа.
    ///
    /// Низ уходит в `Token.Surface.screen`, а не в `page`: ниже блока
    /// рисует `TGScreen`, и полотно там именно `screen`. Увести низ
    /// в `page` значило бы завести видимый стык там, где его сейчас
    /// нет, — то самое, от чего `page` и отличается от `screen`
    /// «одним шагом светлоты».
    ///
    /// # Почему здесь НЕ `Token.Surface.scrim`, хотя роль ровно его
    ///
    /// **Потому что он рисуется синим.** Первый кадр этой шапки показал
    /// индиговую шапку на чёрном экране, и причина не в шапке:
    ///
    /// ```
    /// Token.Surface.scrim, dark   0x0000008C   задумано rgba(0,0,0,0.55)
    /// Color+Hex.swift:13          hasAlpha = hex > 0xFFFFFF
    /// 0x0000008C == 140           НЕ больше 0xFFFFFF → альфы «нет»
    /// значение                    (140 << 8) | 0xFF = 0x00008CFF
    /// на экране                   НЕПРОЗРАЧНЫЙ #00008C — тёмно-синий
    /// ```
    ///
    /// Целое число не помнит, сколько у него было цифр: ведущие нули
    /// в литерале есть, в значении их нет. Значит **всякий чёрный
    /// с альфой** (`R == 00`) теряет прозрачность и становится синим.
    /// Замер по `Tokens.generated.swift` с контролем: восьмизначных
    /// значений 55, из них теряют альфу **16**; шестизначных 130 —
    /// то есть регулярка искала и замер состоялся.
    ///
    /// Задеты поимённо: `Surface.scrim`, `Glass.shadow`, `Glass.line`
    /// (светлая), оба стопа `Component.Backdrop.mask` и **все восемь**
    /// стопов `Component.Backdrop.scrim` — то есть ровно то затемнение,
    /// которое эта шапка и должна была взять.
    ///
    /// > Это не гипотеза о будущем: `Togo/Features/Needs/WalkMode.swift:188`
    /// > кладёт `Token.Surface.scrim` градиентом поверх фотографии уже
    /// > сейчас. Там он тоже синий, и кадра у этого места нет.
    ///
    /// # ВСЁ ВЫШЕ ПРО ПОТЕРЮ АЛЬФЫ — ПОЧИНЕНО 23.10.2026, обход снят 26.10
    ///
    /// ~~Чинится не здесь. Из целого числа разрядность не восстановить,
    /// значит правка — в генераторе (`DesignTokens/`) или в форме
    /// вызова, а оба каталога на 23.10.2026 отданы другим сессиям.~~
    ///
    /// Правка в генераторе **состоялась в тот же день**, и состоялась
    /// ровно там, куда этот разбор и указывал: `generate_tokens.py`
    /// дополняет шестизначные до `0xRRGGBBAA`, пока значение ещё
    /// строка, а `Color+Hex.swift` принимает только восемь разрядов
    /// и про альфу ничего не решает. Замер 26.10.2026:
    /// `Tokens.generated.swift` отдаёт `scrim = 0x0000008C` — восемь
    /// разрядов, альфа `8C` = 140 = 55 %.
    ///
    /// Разбор выше остаётся как есть — он верен для своего дня
    /// и объясняет, почему обход был правильным решением. Снят только
    /// сам обход: три стопа долями от `Token.Surface.screen`
    /// (0,7 → 0 → 1) заменены компонентом `TGBackdropScrim`, у которого
    /// **все восемь стопов дизайна**, включая плато 30–38 % — окно
    /// фото, самое светлое место кадра, где собаку видно. В трёх стопах
    /// плато отсутствовало: на 0,38 у них ноль, а у дизайнера 15 %.
    ///
    /// > **Обход переживает свою причину молча.** У него нет сторожа:
    /// > он верен по виду, верен по числу на краях и ошибается только
    /// > в середине, которой никто не мерил. Нашлось это не проверкой
    /// > обхода, а чтением того, на что он ссылался.
    ///
    /// Третье место того же обхода — `CinemaHeader.затемнение`, снято
    /// тем же коммитом. Четвёртое, `WalkMode.swift:226`, зовёт
    /// `Token.Surface.scrim` НАПРЯМУЮ и после починки генератора
    /// рисует верно; кадра у того места по-прежнему нет.
    private var затемнение: some View {
        TGBackdropScrim()
    }

    // MARK: Надпись

    /// Надпись шапки и её собственный слой затемнения.
    ///
    /// # Почему кикер БЕЛЫЙ, а не тихий
    ///
    /// Первая редакция красила его `Token.Poster.captionOnColor`
    /// (`#B2B2AE`) — тихой подписью на цветном блоке. **Дизайн прямо
    /// запретил это 23.10.2026**, отвечая на вопрос «шапка поверх фото»
    /// (`943de49`, `Дизайн/редизайн-ios28/README.md`, решение 3):
    ///
    /// > «Текст на фото — только `#FFFFFF`; `text-secondary` на фото
    /// > не ставить (при α .55 это 2.8:1)».
    ///
    /// Ближайшая наша роль — `Token.Poster.labelOnColor` (`#F4F4F2`
    /// в тёмной): это «текст НА ЦВЕТНОМ блоке», ровно та роль. Две
    /// единицы до чистого белого — расхождение названное: токена
    /// `#FFFFFF` под эту роль в `tokens.json` нет, а литеральный цвет
    /// в слое вида запрещён строго («цвета и теней ноль»).
    ///
    /// # Слой затемнения привязан к ШАПКЕ, а не к процентам высоты
    ///
    /// Тем же решением: **восьми стопов `backdrop.scrimStops` для
    /// контраста НЕ ХВАТАЕТ.** Замер дизайна по белому кадру —
    /// на 10 % высоты α .52 даёт 4,3:1, на 25 % α .24 даёт **1,8:1**.
    /// Гарантию даёт отдельный ровный слой: α **.55** (в повышенном
    /// контрасте **.70**) от верха до низа последнего текста шапки,
    /// затем спад 48 pt. Обещано ≥ 4,5:1 (4,76) и ≥ 7:1 (8,52) в HC.
    ///
    /// > Это ответ на открытый вопрос, а не моя догадка: до 23.10
    /// > повышенный контраст темы «Кино» пакет не описывал вовсе.
    private var шапка: some View {
        VStack(alignment: .leading, spacing: Token.Space.s4) {
            if let надстрочник, !надстрочник.isEmpty {
                Text(verbatim: надстрочник)
                    .textStyle(AppFont.caps.color(Token.Poster.labelOnColor))
                    .textCase(.uppercase)
                    .wraps()
            }
            Group {
                switch заголовок {
                case .ключ(let ключ): Text(ключ)
                case .значение(let строка): Text(verbatim: строка)
                }
            }
            .textStyle(крупный)
            .tracking(Token.FontTracking.titleLarge)
            .wraps()
            .accessibilityAddTraits(.isHeader)
        }
        .padding(.horizontal, Token.Spacing.screenPadding)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(alignment: .top) { слойШапки }
    }

    /// Ровное затемнение под текстом шапки плюс спад под ним —
    /// компонент `TGHeaderScrim`, он же у `CinemaHeader`
    /// и `ReadingPanel`.
    ///
    /// **До 26.10.2026 здесь стояла своя копия слоя с литералами**
    /// α `.55` / `.70` и спадом `48`, и доккомментарий просил перевести
    /// три шапки вместе, когда у чисел появится токен. Токен появился
    /// (`backdrop.headerScrim`), и перевод оказался не заменой чисел
    /// на имена, а **снятием трёх копий**: `Token.Component.*` экрану
    /// звать нельзя (`ComponentTokenScopeTests`, счёт обращений — ноль),
    /// значит токен читает компонент, а экран читает компонент.
    ///
    /// Условие «рисовать ли вообще» осталось здесь: у этой шапки фото
    /// есть всегда по устройству, поэтому слой безусловный — в отличие
    /// от `CinemaHeader` и `ReadingPanel`, где он под `наФото`.
    ///
    /// Геометрия — в голове компонента: `.background` меряется
    /// по хозяину, спад вылезает вниз отрицательным отступом.
    private var слойШапки: some View {
        TGHeaderScrim()
    }

    /// Крупный заголовок «Кино»: 36 / −0,025em, белый на фотографии.
    ///
    /// `relativeTo: .largeTitle`, как у `AppFont.screenTitle`: у крупного
    /// заголовка свой темп роста при Dynamic Type, иначе шапка выдавит
    /// карточку за нижний край блока.
    private var крупный: TextStyleToken {
        TextStyleToken(size: Token.FontSize.titleLarge,
                       weight: Token.FontWeight.bold,
                       color: Token.Poster.labelOnColor,
                       relativeTo: .largeTitle)
    }
}

// ЧИСЛА СЛОЯ ЗАТЕМНЕНИЯ УЕХАЛИ В ТОКЕН 26.10.2026.
//
// Здесь стоял `private enum ЧислаШапки { static let спад: CGFloat = 48 }`
// и при нём доккомментарий на двадцать строк: «это ЧИСЛА ДИЗАЙНА,
// и токена у них пока нет… место им — `Token.Component.Backdrop.headerScrim`,
// хозяин — сессия токенов». Токен заведён (`aea3640`), числа читает
// `TGHeaderScrim`, константа снята как мёртвая.
//
// Две записи оттуда стоит сохранить, потому что обе — замеры, а не проза:
//
// 1. Отдельным типом, а не константой внутри `ФотоШапка`, она была
//    потому, что та обобщённая: `static let` в generic-типе Swift
//    не разрешён вовсе («static stored properties not supported
//    in generic types»). Поймала это СБОРКА СХЕМЫ, а `-typecheck`
//    увидел бы; `test-without-building` следом прогнал старый бинарник
//    и напечатал ЗЕЛЁНОЕ при `rc=65` у сборки — два свидетеля,
//    и второй отвечал про предыдущую сборку.
// 2. **Именованная константа уводит число из-под `DesignLiteralTests`:**
//    его шаблон «размер» ищет цифру сразу после `height:`, а
//    `height: ЧислаШапки.спад` не совпадал. Долг тогда не исчез,
//    он стал невидимым для сторожа. Теперь число в токене,
//    и у сторожа больше нет причины его искать — но сам механизм
//    (константа гасит шаблон) жив и ждёт следующего, кто заменит
//    литерал на имя, не сказав об этом.

extension ФотоШапка where Низ == EmptyView {
    init(фото: Data?, высота: CGFloat, якорь: ЯкорьКадра,
         надстрочник: String?, заголовок: TGPosterHeader.Название) {
        self.init(фото: фото, высота: высота, якорь: якорь,
                  надстрочник: надстрочник,
                  заголовок: заголовок, низ: { EmptyView() })
    }
}

// MARK: - Как блок ставится в экран

extension View {

    /// Прозрачная в покое навигационная панель над фотографией
    /// (с 05.11.2026 — системная видимость фона, `панельНадФото()`).
    ///
    /// **Титул в панели гасится подменой, а не снятием** — приём взят
    /// у `posterHeader` вместе с его замером: `navigationTitle` нужен
    /// кнопке «назад» на дочерних экранах и озвучке, поэтому гасится
    /// показ, а не значение. `EmptyView()` в `ToolbarItem` SwiftUI
    /// считает отсутствием пункта — подмены не происходит вовсе,
    /// и живой кадр показал название экрана дважды.
    ///
    /// Рамки `1×1` у подменыша здесь нет, и это не небрежность:
    /// `DesignLiteralTests` держит храповик на `\.frame(width: N`,
    /// вид «размер» объявлен красным (42 при долге 36, хозяин назван),
    /// и два новых литерала сделали бы объявленное красное хуже.
    /// Озвучку закрывает `accessibilityHidden`, а не размер.
    func фотоШапкаЭкрана() -> some View {
        self
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .principal) {
                    Color.clear.accessibilityHidden(true)
                }
            }
            // Было `.toolbarBackground(.hidden)`: фон панели снят во ВСЕХ
            // состояниях, и прокрученный текст вкладки собаки и «Семьи»
            // читался под часами — тот же дефект, что отзыв 293 на
            // подэкранах. Лечение одно на оба места — разбор
            // в `TGПанельНадФото.swift`.
            .панельНадФото()
    }
}
