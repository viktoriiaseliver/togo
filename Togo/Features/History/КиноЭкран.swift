/// Имена, под которыми экраны зовут токены блока «Metric».
///
/// # Долг закрыт 23.10.2026 — числа ушли в токены
///
/// Прежняя редакция держала здесь пять констант, снятых с прототипа
/// дословно, с таким доводом: «имён в `DesignTokens/tokens.json` у них
/// сегодня нет ни одного — замер 23.10.2026, `grep -i metric` дал ноль…
/// хозяин у долга — дизайн: завести `component.metric.*` и убрать
/// отсюда». Дизайн их выдал в тот же день (`Дизайн/редизайн-ios28/
/// ОТВЕТЫ-круг-2.md`, пункт 4), долг закрыт, и копии чисел здесь больше
/// нет — только имена.
///
/// # Почему не `Token.Component.Metric.*`, когда токены названы именно так
///
/// `ComponentTokenScopeTests` запрещает `Token.Component.*` за пределами
/// `Togo/DesignSystem/**`, и запрет верен: экран, берущий компонентный
/// токен, пересобирает компонент сам. Но `КиноМетрика` **и есть**
/// компонент — он лежит в `Features` только потому, что дизайн-система
/// на 23.10 занята другой сессией (тот же разбор в голове
/// `CinemaHeader.swift`). Поэтому здесь взяты ПРИМИТИВЫ, на которые
/// компонентные токены ссылаются, — ровно тот путь, которым уже ходит
/// высота подложки (`Token.Size.backdropTab`). Второго дома у числа
/// при этом не заводится: дом один, в `tokens.json`.
///
/// Здесь стояло «`component.backdrop.height.tab` → `Token.Size.backdropTab`»;
/// **левая половина удалена 27.10.2026** вместе с 55 другими компонентными
/// листьями без читателя (решение Виктории). Путь от этого не изменился:
/// примитив `Token.Size.backdropTab` цел и остаётся домом числа — исчез
/// компонентный псевдоним, который на него смотрел.
///
/// **Переезд в `Togo/DesignSystem` снимет и это, и оговорку выше.**
/// До него менять значения — в `tokens.json`, а не здесь: тут нечего
/// менять.
nonisolated enum КиноРазмеры {
    /// Кегль числа метрики, 48 (`metric.number.size`).
    /// Начертание — `Token.FontWeight.light` на месте вызова.
    static let метрика = Token.FontSize.metric
    /// Высота полосы столбиков, 48 (`metric.bars.height`).
    /// **Не `метрика`, хотя число то же:** высота в точках и кегль —
    /// две роли, и смена одной не должна тащить другую.
    static let полоса = Token.Size.metricBars
    /// Зазор между столбиками, 3 (`metric.bars.gap`).
    static let зазорСтолбика = Token.Size.metricBarGap
    /// Скругление столбика, 3 (`metric.bars.radius`).
    static let радиусСтолбика = Token.Radius.bar
    /// День без записей всё равно виден: иначе пустые дни читаются
    /// как «графика нет», а не как «в эти дни не выходили».
    ///
    /// **Число НАШЕ, у дизайна его нет** — в ответах круга 2 полоса
    /// описана шестью величинами, и минимума среди них не названо.
    /// Поэтому оно остаётся здесь литералом, а не притворяется токеном:
    /// у `metric.normLine.width` то же значение 2 и совсем другая роль,
    /// и взять его было бы парой по совпадению числа.
    static let минимумСтолбика: CGFloat = 2
    /// Сколько значений показывает полоса, 14.
    ///
    /// Дизайн называет то же число (`metric.bars.count`), но в токены
    /// оно **не перенесено нарочно**: это предмет домена — сколько дней
    /// истории человек видит, — а не оформления. Разбор лежит рядом
    /// с остальными непереносами, в `$description` узла
    /// `component.metric` в `DesignTokens/tokens.json`.
    static let днейВПолосе = 14
}

