import SwiftUI

/// Каркас вкладки темы «Кино»: фото под шапкой, надпись капсом, крупный
/// заголовок 36 и одна кнопка «…».
///
/// Решение Виктории 22.10.2026 («перепиши всё под дизайн») и 23.10.2026
/// («Кино. Одна тема»). Состав снят **с кадров**
/// `Дизайн/эталонные-кадры/ios28-кино-22.10/` — `10.png` («История»),
/// `11.png` («Здоровье»), `14.png` («Анализы»), — а не с прозы README:
/// где они расходятся, исполнен кадр, расхождение названо в отчёте.
///
/// ## Шапку и фон рисует НЕ этот файл
///
/// `CinemaHeader`, `CinemaBackdrop` и `.cinemaScreen(экран:)` уже живут
/// в `Togo/Features/Settings/CinemaHeader.swift` (коммит `f06c9a3`,
/// волна 3). Первая редакция этого файла несла **свою** шапку с фото,
/// своей маской и своим гашением титула — то есть вторую копию одного
/// правила, которая разошлась бы молча. Копия снята, вызовы переведены
/// на готовое.
///
/// Здесь остаётся ровно то, чего у соседа нет: **кнопка «…» в строке
/// заголовка** (её нет у настроек, потому что там шапка без меню)
/// и блоки, из которых собраны «История», «Здоровье» и «Анализы»:
/// чип-пилюля, полоса столбиков, блок показания.
///
/// ## Чем этот каркас НЕ занимается
///
/// Он **не прячет навигационную панель**. Соблазн велик — на кадрах
/// её нет, — но `TogoUITests/МедслойДороги` адресует экраны по
/// `app.navigationBars["Здоровье"]`, `["Анализы"]`, `["График"]`
/// и возвращается назад через `app.navigationBars.buttons.firstMatch`.
/// Панель остаётся: `.cinemaScreen` снимает её фон и гасит титул,
/// `navigationTitle` сохраняется ради кнопки «назад» и озвучки.
///
/// ~~**Высота фото — 360, а не 420.** `CinemaBackdrop` берёт
/// `Token.Size.hero`; у вкладки в хендоффе стоит `backdropTab` = 420.
/// Расхождение названо, а не исправлено форком: параметр высоты
/// заводится в `CinemaBackdrop`, а он в чужом файле.~~
///
/// **ЗАКРЫТО 23.10.2026, и закрыто в `CinemaBackdrop`, а не форком.**
/// Подложка берёт высоту по `ScreenKey.kind`: вкладка 420, «Сегодня»
/// 640, подэкран 360, «На улице» 520 — требование дизайна (ОТВЕТЫ-круг-2,
/// пункт 3). `Token.Size.hero` к подложке отношения не имеет вовсе,
/// это карточка-герой. Запись оставлена зачёркнутой, а не стёрта:
/// расхождение было верным, когда его писали, и следующий, кто увидит
/// на вкладке 420, не должен искать, кто и зачем «поднял 360».
struct КиноЭкран<Содержимое: View>: View {

    /// Какой экран спрашивает фон. Через него работает «Фон приложения»
    /// (решение 22.10.2026): режим «вперемешку» раздаёт снимки по ключу.
    let экран: ScreenKey
    /// Строка капсом над заголовком: «ВСЁ · 30 ДНЕЙ»,
    /// «СХЕМА · ЗАПАС · АНАЛИЗЫ».
    var кикер: LocalizedStringKey?
    let заголовок: LocalizedStringKey
    /// Что делает «…». Пункт в меню один — «Настройки»: «Другой день»
    /// живёт на «Сегодня», «Семья» — на вкладке собаки.
    var настройки: () -> Void
    @ViewBuilder var содержимое: Содержимое

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: Token.Spacing.stack) {
                шапка
                VStack(alignment: .leading, spacing: Token.Spacing.stack) {
                    содержимое
                }
                .padding(.horizontal, Token.Spacing.screenPadding)
            }
            .padding(.bottom, Token.Space.s28)
        }
        .scrollBounceBehavior(.basedOnSize)
        // То же, что делает `TGScreen`: карточки внутри спрашивают
        // окружение, на какой поверхности они стоят.
        .themeSurface(.screen)
        .navigationTitle(заголовок)
        .cinemaScreen(экран: экран)
    }

    /// Шапка и «…» в одной строке — как на кадрах 10, 11 и 14.
    ///
    /// **Боковой отступ кладёт САМА `CinemaHeader`, и это замер,
    /// а не догадка.** Первая редакция звала её с `отступы: false` —
    /// такой параметр у неё есть **в рабочем дереве и нет в git**
    /// (`git show HEAD:…/CinemaHeader.swift` — безусловный
    /// `.padding(.horizontal, Token.Spacing.screenPadding)`), и сборка
    /// схемы сказала «extra argument». Ровно тот класс, что записан
    /// в своде: текст в рабочем дереве выглядит как текст в git,
    /// различитель один — `git show`, и его не делает никто, потому что
    /// файл «вот же он». Поэтому содержимое отступ получает своей
    /// колонкой, а шапка — от соседа, и ей остаётся только правый край
    /// под кнопку.
    /// # Кнопка ПОВЕРХ шапки, а не рядом с ней — замер 30.10.2026
    ///
    /// ~~`HStack { CinemaHeader; HeaderMenu }` с `.padding(.trailing)`.~~
    /// В таком ряду `CinemaHeader` у́же экрана на кнопку, зазор
    /// и отступ — 68 pt из 402, то есть 17 %. А шапка несёт **свой слой
    /// затемнения** (`слойШапки` → `TGHeaderScrim`), и он рисуется
    /// по её ширине. Справа затемнения не было вовсе.
    ///
    /// На чёрном полотне это невидимо — чёрный под α .55 поверх чёрного
    /// даёт чёрный. На ФОТОГРАФИИ видно сразу: правые 17 % светлее
    /// остальной шапки, и граница вертикальная.
    ///
    /// ```
    /// история/здоровье, ШИРОКИЙ снимок      ШОВ на 0,83 ширины
    /// они же, вертикальный снимок           чисто
    /// «Сегодня» (не этот каркас)            чисто
    /// 402 − 44 (кнопка) − 8 − 16 = 334      334 / 402 = 0,83 ← сошлось
    /// ```
    ///
    /// Девять отзывов из двадцати двух за 27–30.10 — про это:
    /// «как будто слои неправильно наложились», «обрезается наложение»,
    /// «подложка под текст ужас», «там где навигация».
    ///
    /// **Почему не повторялось у нас девять дней:** штатная фикстура
    /// стенда вертикальная, 600×800. `scaledToFill` масштабирует её
    /// по ширине, и в правый угол попадает ровный серый центр —
    /// разницу в затемнении на нём не различить. На широком снимке
    /// туда попадает край кадра, и шов бросается в глаза. Условие было
    /// в ДАННЫХ, а не в коде.
    ///
    /// > **Гипотеза «виновато `.стекло()` у кнопки» опровергнута
    /// > опытом** (кадр `04-здоровье-БЕЗ-СТЕКЛА`): стекло сняли,
    /// > пилюля исчезла, заплатка осталась. Деление сходилось потому,
    /// > что оба признака живут в одном каркасе.
    ///
    /// Теперь шапка занимает всю ширину — и её затемнение тоже, —
    /// а кнопка лежит поверх. `.trailing` у оверлея держит прежнее
    /// вертикальное центрирование, которое давал `HStack(alignment:
    /// .center)`.
    private var шапка: some View {
        CinemaHeader(заголовок, надпись: кикер, экран: экран)
            .overlay(alignment: .trailing) {
                HeaderMenu(настройки: настройки)
                    .tint(Token.Poster.labelOnColor)
                    .foregroundStyle(Token.Poster.labelOnColor)
                    .стекло(радиус: Token.Size.tapTarget / 2)
                    .padding(.trailing, Token.Spacing.screenPadding)
            }
    }
}

