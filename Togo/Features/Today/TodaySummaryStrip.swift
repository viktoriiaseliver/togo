import SwiftUI

/// Три числа за день: сколько съел, сколько кормлений, сколько выходов.
///
/// Вынесена из `TodayScreen` 28.09 вместе с шапкой.
///
/// **Число выходов приходит аргументом, а не считается здесь.** Это
/// не стиль, а починка: до 28.09 карточка брала `summary.outings`
/// (события `.outing`), а шапка над ней — блоки таймлайна, и на одном
/// кадре отзыва стояло «2 выхода из 4 за день» над «3 выхода». Обе
/// арифметики были верны; расходились смыслы. Пока число приходит
/// снаружи одним значением, разойтись нечему.
///
/// При выносе убрана мёртвая пара строк: карточка считала
/// `timeIndoorsNow` в локальную переменную и нигде её не читала —
/// то же самое считает герой выше.
struct TodaySummaryStrip: View {
    let summary: Diary.DaySummary
    /// Выходы за день — блоками, не событиями. См. `TimelineBuilder.outingsCount`.
    let outings: Int
    /// Сколько раз покакал за день — `ToiletClock.stoolCount`.
    ///
    /// Просьба Виктории 29.10.2026. Отдельным числом, а не подписью
    /// у выходов: врач спрашивает «сколько раз в день стул», и выходы
    /// на этот вопрос не отвечают — кобель выходит пять раз и какает два.
    let стул: Int

    var body: some View {
        TGCard {
            РядЧисел(выравнивание: .top) {
                TGStat(value: "\(summary.eatenGrams) г",
                       caption: summary.dailyGrams > 0 ? "из \(summary.dailyGrams) съел" : "съел")
                // «С прогулки» отсюда убрано: на этот вопрос отвечает
                // герой вверху экрана крупной цифрой, и повторять его
                // мелким шрифтом — ровно тот дубль, который аудит
                // и просил вычистить.
                // У кормлений своего `Fmt` нет — формы живут прямо
                // в каталоге. Ключ тот же, что стоял здесь до выноса.
                TGStat(value: "\(summary.meals)",
                       caption: .готовая(подпись(String(localized: "\(summary.meals) кормлений"),
                                                 summary.meals)))
                TGStat(value: "\(outings)",
                       caption: .готовая(подпись(Fmt.outings(outings), outings)))
                TGStat(value: "\(стул)", caption: "стул")
            }
            if summary.trainingGrams > 0 {
                TGDivider()
                TGExplainer(text: "\(summary.trainingGrams) г ушло на занятие — вечерняя порция уже уменьшена.")
            }
        }
    }

    /// `Fmt` возвращает число ВМЕСТЕ со словом, а число здесь уже
    /// напечатано крупным. Снимаем его — иначе выходит «3 3 выхода».
    /// Тот же дефект жил в строке «5 5 напоминаний ждут даты».
    private func подпись(_ сЧислом: String, _ число: Int) -> String {
        // НЕ `String(localized:)`: это не текст для человека, а кусок
        // для отрезания от уже переведённой строки. Перевод здесь
        // подставил бы чужой разделитель, и число осталось бы в подписи.
        // Автоматическая обёртка 28.09 сюда попала по признаку «ключ
        // есть в каталоге» — признак верный, вывод неверный.
        сЧислом.replacingOccurrences(of: "\(число) ", with: "")
    }
}
