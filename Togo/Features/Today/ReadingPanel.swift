import SwiftUI

/// Верхний блок «Сегодня»: фото, шапка, крупный заголовок, чип состояния
/// и стеклянная панель показания.
///
/// Решение Виктории 22.10.2026, источник — `design_handoff_togo_ios28`.
/// **Геометрия и состав сняты с КАДРОВ** (`screenshots/01.png` — обычный
/// день, `02.png` — время дозы), а не с прозы README: они расходятся,
/// и расхождения названы ниже поимённо.
///
/// ```
/// README говорит                        на кадре 01/02 видно
/// «пилюля второго состояния (≤ 1)»      пилюль ДВЕ, и места разные:
///                                       «Запас 5 дн» справа В СТРОКЕ
///                                       ЗАГОЛОВКА, «Доза по часам»
///                                       отдельной строкой слева
/// про крупный заголовок молчит          «Сегодня» 36 pt белым есть,
///                                       и он несёт правую пилюлю
/// «строка „Дальше · {когда}“ 17 sb»     строки ДВЕ, и вторая красится
///                                       тоном ВТОРОГО состояния
///                                       (на 02 — янтарём)
/// «панель показания (высота 360)»       360 — это блок с фото целиком,
///                                       а стеклянная панель внутри него
/// ```
///
/// > **Кадр старше прозы.** Проза README описывает не всё и местами
/// > иначе; где они разошлись, здесь исполнен кадр, а расхождение
/// > названо в отчёте — чтобы правил его тот, у кого есть право.
///
/// ## Красные линии, которые тут стреляют
///
/// **Прозрачности на тексте нет ни в одном состоянии.** Текст берёт
/// сплошной цвет; считать контраст надо по **композиту** — панель
/// поверх фото, — а не по исходному цвету панели. Это работа приёмки
/// по кадру, компилятор такого не ловит.
///
/// **`ViewThatFits` не применяется** — запрещён в проекте: он держал
/// в дереве обе раскладки, и озвучка находила две кнопки «Отменить».
/// Раскладка выбирается явным `if` по `dynamicTypeSize`, как
/// в `ActionGrid` и `UndoToastView`.
struct ReadingPanel<Шапка: View>: View {
    /// Тон — он один на панель, чип, фото и главную кнопку.
    let tone: ReadingTone
    /// Чип состояния: отдельная строка слева под заголовком.
    /// На кадре 01 это «Дома», на 02 — «Доза по часам · 17:59».
    let чип: Чип
    /// Пилюля справа в строке заголовка. Независима от тона:
    /// на обоих кадрах «Запас 5 дн» терракотовая, хотя тона разные.
    var пилюля: Пилюля?
    /// Само показание.
    let показание: Показание
    /// «гулял в 15:44 · обычно до 22:44» — две подписи под показанием.
    var откуда: String?
    var докуда: String?
    /// Насколько заполнена полоса-косточка, 0…1. Пусто — полосы нет.
    var доля: Double?
    /// Шапка: аватар, кличка, «вес · дежурит», кнопка «…».
    @ViewBuilder var шапка: Шапка

    /// Сниженная прозрачность снимает фотографию под блоком: человек,
    /// попросивший систему убрать полупрозрачность, просил читаемости,
    /// а текст поверх фотографии — ровно то, от чего он отказывается.
    /// Про саму поверхность панели её спрашивает теперь `TGGlassPanel`.
    @Environment(\.accessibilityReduceTransparency) private var безПрозрачности
    // Размер текста читает теперь `.высотаПанелиПоказания()`. Объявление
    // снято 26.10.2026 как оставшееся без единого читателя после переезда
    // оси в модификатор (замер: `grep "размерТекста"` по файлу — одна
    // строка, и это само объявление).
    // Уровень контраста системы читает теперь `TGHeaderScrim`.
    // Объявление снято 26.10.2026 как оставшееся без единого читателя
    // после переезда слоя в компонент (замер: `grep` по файлу
    // с вырезанной прозой — одна строка, и это само объявление).

    /// Чип состояния — светлый на обычном дне, цветной на дозе.
    struct Чип {
        let символ: String
        let текст: LocalizedStringKey
        /// Тон чипа. Обычно равен тону экрана, но не всегда: на кадре 01
        /// экран нейтральный, а чип «Дома» светлый.
        var цветной: Bool = false
    }

    /// Пилюля в строке заголовка.
    struct Пилюля {
        let символ: String
        let текст: LocalizedStringKey
    }

    /// Что стоит крупно.
    ///
    /// Три вида, и у каждого свой смысл — правило взято у
    /// `TGPoster.Reading`: **число без имени читается как что угодно**,
    /// поэтому вид показания решает, нужна ли подпись.
    enum Показание {
        /// Часы и минуты. Принимает **интервал**, а не пару чисел:
        /// строку печатает `Fmt.hoursMinutes`, у которого единицы
        /// печатает система.
        ///
        /// Прототип собирал это склейкой — `h + 'ч' + m + 'мин'`, —
        /// и ровно такие склейки хендофф запрещает переносить:
        /// 154 фрагмента («` мин`», «`гулял в `») в `xcstrings`
        /// **не включены** нарочно. Собрать «2 ч 12 мин» на любом
        /// языке, кроме русского, из кусков нечем.
        case часыМинуты(TimeInterval)
        /// Минуты и секунды — идущий выход. `Fmt.stopwatch`.
        case минутыСекунды(TimeInterval)
        /// Фраза: «Сегодня ещё не выходили».
        case фраза(LocalizedStringKey)
    }

    // ~~Токенов с такими именами в проекте ещё НЕТ: их заводит другой
    // агент. Пока они константами с адресом источника.~~
    //
    // **УСТАРЕЛО. Токены есть, и высота переведена на них 26.10.2026.**
    // `Token.Size.hero` = 360 и `Token.Size.heroAX` = 220 живут
    // в генерате (`Tokens.generated.swift:339,341`), и до этой правки
    // у `Token.Size.hero` НЕ БЫЛО НИ ОДНОГО ЖИВОГО ЧИТАТЕЛЯ: `git grep
    // "Token\.Size\.hero\b"` давал только упоминания в прозе, при
    // живом контроле `heroAX` (один вызов, `CinemaHeader.swift:392`).
    //
    // > Это ровно случай `Token.FontSize.micro = 14`, за который мы уже
    // > платили: имя есть, значение верное, вызова по имени нет. Правка
    // > токена не меняла на экране ничего, а дизайнер, применивший
    // > `size.hero` в Figma, получал рассинхрон с кодом. Грепом не
    // > видно — объявление находится один раз и выглядит работающим.
    //
    // Остальные величины этого списка **не переведены, и причина
    // названа, а не умолчана**:
    //
    // ~~  size.heroPanelRadius  24  → ЭКРАНУ ЗВАТЬ НЕЛЬЗЯ, нужен
    //      компонент в `Togo/DesignSystem/`.~~
    //
    // **ЗАКРЫТО 26.10.2026 компонентами `TGGlassPanel`
    // и `.высотаПанелиПоказания()`.** Радиус (литерал `24`) и высота
    // (`Token.Size.hero`) переведены на `Token.Component.ReadingPanel.*`,
    // и перевод высоты — не косметика: `Token.Size.hero`
    // и `component.readingPanel.height` сегодня дают одно число, потому
    // что второй — АЛИАС первого, но в Фигму уезжает отдельной
    // переменной `readingPanel/height`. Перенаправь алиас — макет поедет,
    // а Swift промолчит. Разбор и замер по шести токенам группы —
    // в голове `TGGlassPanel`.
    //
    // Остальные величины этого списка **не переведены, и причина
    // названа, а не умолчана**:
    //
    //   type.reading      56/300  → `Token.FontSize.hero` = 56 есть,
    //                               и `component.readingPanel.readingSize`
    //                               тоже, читателей у обоих ноль, а кегль
    //                               стоит литералом в `показаниеКрупно`.
    //                               Кегль на этом экране — чужой предмет,
    //                               и литерал держит храповик
    //                               `DesignLiteralTests`: снижать чужой
    //                               храповик своей правкой значит смешать
    //                               две приёмки.
    //   cinema.titleLarge 36/−0.025 → `primitive.font.size.titleLarge`
    //                               и `tracking.titleLarge` = −0,9px
    //                               (пересчёт em→pt: −0,025 × 36).
    //
    // Объявление `@Environment(\.dynamicTypeSize)` снято вместе
    // с `высота`: ось крупного кегля уехала в модификатор, и здесь
    // у переменной не осталось ни одного читателя. Форма та же, что
    // у `colorSchemeContrast` выше.

    var body: some View {
        ZStack(alignment: .topLeading) {
            фон
            VStack(alignment: .leading, spacing: Token.Space.s8) {
                // Шапка, заголовок и чип лежат ПРЯМО НА ФОТОГРАФИИ —
                // стекла под ними нет. Поэтому у них свой слой
                // затемнения, привязанный к тексту; разбор — у
                // `слойШапки`.
                VStack(alignment: .leading, spacing: Token.Space.s8) {
                    шапка
                    строкаЗаголовка
                    чипСостояния
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(.horizontal, Token.Spacing.screenPadding)
                .background(alignment: .top) { слойШапки }
                Spacer(minLength: Token.Space.s12)
                стекляннаяПанель
                    .padding(.horizontal, Token.Spacing.screenPadding)
            }
            .padding(.bottom, Token.Space.s16)
        }
        .высотаПанелиПоказания()
        // Опознаётся приёмкой по РАМКЕ блока, а не по доле экрана:
        // координата от края экрана меряет экран, рамка меряет элемент.
        // На этом однажды уже промахнулись — точка «92 % ширины, 9 %
        // высоты» попадала в шестерёнку настроек.
        .accessibilityElement(children: .contain)
        .accessibilityIdentifier("панель-показания")
    }

    // MARK: Фон

    /// Подкраска блока тоном.
    ///
    /// **Фотографии и затемнения здесь больше НЕТ, и это снятие второго
    /// механизма, а не упрощение** (23.10.2026). Панель рисовала свой
    /// снимок из `dog?.photo`, мимо `BackgroundStore` — то есть мимо
    /// выбора человека на экране «Фон приложения», — и рисовала его
    /// ВНУТРИ `ScrollView`, где `.ignoresSafeArea` за обрезку прокрутки
    /// не выходит. Отсюда и бралась полоса под статус-баром, которую
    /// экран закрашивал отдельно `PosterPaint.background` — индиго.
    ///
    /// Теперь подложку «Сегодня» рисует `CinemaBackdrop(экран: .today)`
    /// у экрана, под прокруткой и под статус-баром: тот же вид, что
    /// у вкладок и подэкранов, тот же хозяин снимка
    /// (`BackgroundStore`), та же цепочка `запомнитьФотоСобаки`.
    ///
    /// **Тон красит ФОТО, а не только панель** — это видно на кадре 02:
    /// при дозе синим залит весь верх экрана, не один прямоугольник.
    /// В токенах это `backdrop.tint` (`softLight`, 55–60 % прозрачности).
    /// Граница названа: подкраска кроет РАМКУ БЛОКА (360 pt), а подложка
    /// экрана выше — 640 pt (`Token.Size.backdropToday`). Ниже блока
    /// фотография остаётся неподкрашенной, и это расхождение с кадром,
    /// а не решение: перенос подкраски в `CinemaBackdrop` означал бы
    /// отдать тону «Сегодня» чужой общий вид.
    private var фон: some View {
        ZStack {
            if let подкраска {
                // **`.opacity(0.55)` здесь СНЯТ, и это обязательная
                // половина правки токена.** Прозрачность живёт
                // в самом значении (`#1F4FFF8C` = 55 %, `#D5251999`
                // = 60 %), а прежние источники её не имели вовсе —
                // поэтому множитель и стоял рядом. С токенами, которые
                // несут альфу, он перемножился бы: 0,55 × 0,55 = 0,30,
                // и подкраска вышла бы вдвое бледнее задуманной.
                //
                // > Две прозрачности перемножаются МОЛЧА: ни одна
                // > сторона не выглядит неверной, и число нигде
                // > не печатается.
                подкраска.blendMode(.softLight)
            }
            // Ночь: `saturate(.3) brightness(.7)` — приглушается ФОТО,
            // а не панель.
            if tone.dimsPhoto {
                Token.Surface.screen.opacity(0.30)
            }
        }
        // Фото — оформление. Голосом его читать нечем, а подпись
        // к нему была бы выдумкой: мы не знаем, что на фотографии.
        .accessibilityHidden(true)
    }

    /// Лежит ли под блоком фотография **сейчас**.
    ///
    /// Спрашивается у того же хозяина и с той же оговоркой про сниженную
    /// прозрачность, что в `CinemaHeader.наФото` и `CinemaBackdrop`:
    /// второй ответ на тот же вопрос разошёлся бы молча.
    private var наФото: Bool {
        guard !безПрозрачности else { return false }
        return BackgroundStore.shared.background(for: .today) != nil
    }

    /// Ровное затемнение под шапкой, заголовком и чипом плюс спад под
    /// ними — **только когда под блоком есть фотография**.
    ///
    /// **Слой обязателен, и это замер, а не осторожность.** Восьми
    /// стопов `--bd-scrim` для контраста не хватает — прямой ответ
    /// дизайна 23.10.2026 (`943de49`, решение 3): «на белом кадре
    /// на 10 % высоты α .52 → 4,3:1, на 25 % α .24 → 1,8:1. Гарантию
    /// даёт отдельный слой, привязанный к шапке». У шапки подэкранов
    /// это стоило **1,89:1** (`CinemaHeader.слойШапки`), и здесь тот же
    /// текст на том же снимке: `Poster.labelOnColor` без слоя даёт
    /// на светлой фотографии 2,4 при пороге 4,5.
    ///
    /// Числа и форма — те же, что у `CinemaHeader`: `backdrop.headerScrim`
    /// α `.55`, в повышенном контрасте `.70`, спад `fadePt` = 48. Токена
    /// у них пока нет, хозяин — сессия токенов; когда токен появится,
    /// три шапки переводятся вместе (`CinemaHeader`, `ФотоШапка`, эта).
    @ViewBuilder
    private var слойШапки: some View {
        if наФото {
            TGHeaderScrim()
        }
    }

    /// Подкраска фото по тону. Пусто — фото остаётся как есть.
    /// Подкраска фотографии тоном дня.
    ///
    /// **Все четыре значения брались не оттуда, и одно было белым.**
    /// Замер 25.10.2026 — прочёсывание всех 145 сгенерированных
    /// токенов на читателей:
    ///
    /// ```
    ///           её токен      экран клал           чем это было
    /// доза      #1F4FFF8C     Action.primary       в «Кино» = #FFFFFF
    /// тревога   #D5251999     Status.overdueText   #FF7A66, светлее
    /// натощак   #FFC2338C     Status.waitingText   #F7C75F, БЕЗ альфы
    /// ночь      #14143C99     nil                  подкраски не было
    /// ```
    ///
    /// То есть в час дозы фотография получала **белую засветку**
    /// вместо синей, а по кадру 02 при дозе синим залит весь верх
    /// экрана. У ночи подкраски не было вовсе.
    ///
    /// > **Токен существовал всё это время.** `backdrop.tint.*` лежит
    /// > в компонентном слое, экранам он закрыт ратчетом, живого
    /// > читателя у него не было ни одного — и потому ни один сторож
    /// > не мог заметить, что экран красит чем-то другим.
    /// > Грепом такое не ищется: имя есть, значение есть, **вызова
    /// > по имени нет**.
    ///
    /// Три брались у ролей ТЕКСТА (`Status.*`, `Action.primary`)
    /// в роли заливки. У `Status.waitingText` вдобавок нет альфы,
    /// а у подкраски своя (.55) — две прозрачности перемножились бы
    /// молча, если бы токен её имел.
    private var подкраска: Color? {
        switch tone {
        case .dose: Token.Poster.tintDose
        case .fasting: Token.Poster.tintFasting
        case .alarm: Token.Poster.tintAlarm
        case .night: Token.Poster.tintNight
        case .normal, .walk: nil
        }
    }

    // MARK: Заголовок и чипы

    /// «Сегодня» крупно и пилюля запаса справа.
    ///
    /// Заголовок рисуем **сами**, а не `navigationTitle`: по кадру он
    /// лежит поверх фотографии и делит строку с пилюлей, чего системный
    /// заголовок не умеет.
    ///
    /// **Цвет — `Poster.labelOnColor`, и это починка, а не вкус**
    /// (замер кадром 23.10.2026, `ЧернилаНаФотоКадрTests`). Здесь стоял
    /// `Ink.onAccent`, и в теме «Кино» он равен **#111111**: акцент стал
    /// белым, а `onAccent` — чернилами НА нём. Заголовок же лежит
    /// не на акценте, а на фотографии, и чёрным по ней давал
    /// **3,08 · 1,67 · 1,11** на трёх светлотах снимка при пороге 4,5.
    /// Ту же пару уже носит `CinemaHeader` (`наФото ? Poster.labelOnColor`),
    /// и её держит зелёный сторож `ШапкаНаФотоTests`, заказанный дизайном.
    private var строкаЗаголовка: some View {
        HStack(alignment: .firstTextBaseline, spacing: Token.Space.s8) {
            Text("Сегодня")
                .textStyle(AppFont.screenTitle, color: Token.Poster.labelOnColor)
                .wraps()
            Spacer(minLength: Token.Space.s8)
            if let пилюля { пилюляВида(пилюля) }
        }
    }

    private func пилюляВида(_ п: Пилюля) -> some View {
        HStack(spacing: Token.Space.s6) {
            Image(systemName: п.символ)
                .font(.system(size: Token.Size.iconSm, weight: .semibold))
                .accessibilityHidden(true)
            Text(п.текст).textStyle(AppFont.captionEmphasis, color: Token.Status.stockLowText)
                .wraps()
        }
        .foregroundStyle(Token.Status.stockLowText)
        .padding(.horizontal, Token.Space.s10)
        // Не кнопка, но высота — как у цели касания: так пилюля
        // не схлопывается на мелком кегле и остаётся читаемой.
        .frame(minHeight: Token.Size.tapTarget)
        .background(Token.Status.stockLowBg, in: Capsule())
    }

    /// Чип состояния — отдельной строкой слева под заголовком.
    private var чипСостояния: some View {
        HStack(spacing: Token.Space.s6) {
            Image(systemName: чип.символ)
                .font(.system(size: Token.Size.iconSm, weight: .semibold))
                .accessibilityHidden(true)
            Text(чип.текст)
                .textStyle(AppFont.captionEmphasis, color: чернилаЧипа)
                .wraps()
        }
        .foregroundStyle(чернилаЧипа)
        .padding(.horizontal, Token.Space.s10)
        .frame(minHeight: Token.Size.tapTarget)
        .background(заливкаЧипа, in: Capsule())
        .frame(maxWidth: .infinity, alignment: .leading)
    }

    // MARK: Стеклянная панель

    /// **Поверхность и радиус переехали в `TGGlassPanel` 26.10.2026.**
    /// Радиус стоял здесь литералом `24` при живом
    /// `Token.Component.ReadingPanel.glassRadius` = 24, а звать токен
    /// экрану нельзя (`ComponentTokenScopeTests`). Разбор, замер по шести
    /// токенам группы и причина, по которой компонент НЕ зовёт
    /// общее `.стекло(радиус:)`, — в голове `TGGlassPanel`.
    /// (Плотность `.плотное`, объявленная когда-то ровно для этой
    /// панели, удалена 26.10.2026 решением Виктории: вызовов у неё
    /// не было ни одного.)
    ///
    /// **Решение «кроет ли заливка стекло» осталось здесь, и это граница,
    /// а не недоделка:** `ReadingTone` живёт в этом слое, дизайн-системе
    /// на него смотреть нельзя. Компонент получает готовый цвет либо
    /// `nil` — та же форма, что у `TGHeaderScrim`, которому экран отдаёт
    /// условие «есть ли под шапкой фото».
    private var стекляннаяПанель: some View {
        TGGlassPanel(заливка: tone.paintsPanel ? заливкаПанели : nil) {
            VStack(alignment: .leading, spacing: Token.Space.s8) {
                показаниеКрупно
                if откуда != nil || докуда != nil { строкаСДо }
                if let доля { полосаКосточка(доля) }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    /// Показание крупно: SF Rounded 300, 56 pt.
    ///
    /// **Кегль через `relativeTo:`, а не голым `Font.system(size:)`** —
    /// голый размер настройку iOS не спрашивает, и на кадре 28.09
    /// половина экрана выросла, а половина осталась мелкой. Это хуже,
    /// чем если бы не вырос никто: выглядит поломкой, а не ограничением.
    @ViewBuilder
    private var показаниеКрупно: some View {
        let шрифт = Font.system(size: 56, weight: .light, design: .rounded)
        switch показание {
        case .часыМинуты(let интервал):
            Text(Fmt.hoursMinutes(интервал))
                .font(шрифт)
                .foregroundStyle(чернила)
                .minimumScaleFactor(0.5)
                .wraps()
        case .минутыСекунды(let интервал):
            Text(Fmt.stopwatch(интервал))
                .font(шрифт)
                .monospacedDigit()
                .foregroundStyle(чернила)
                .minimumScaleFactor(0.5)
        case .фраза(let текст):
            // Фраза кеглем 56 не влезет никогда — у неё свой стиль.
            // Это не «мельче ради места», а другой вид показания:
            // число отвечает «сколько», фраза — «нечего считать».
            Text(текст)
                .textStyle(AppFont.cardTitle, color: чернила)
                .wraps()
        }
    }

    /// «гулял в 15:44 · обычно до 22:44» — 14 semibold.
    private var строкаСДо: some View {
        HStack(spacing: Token.Space.s6) {
            if let откуда {
                Text(откуда).textStyle(AppFont.captionEmphasis, color: чернилаПодписи)
            }
            if откуда != nil, докуда != nil {
                Text(verbatim: "·").foregroundStyle(чернилаПодписи)
            }
            if let докуда {
                Text(докуда).textStyle(AppFont.captionEmphasis, color: чернилаПодписи)
            }
        }
        .wraps()
    }

    /// Полоса-косточка: сколько прошло от выхода до следующего.
    ///
    /// Доля приходит готовой — считать её здесь значило бы завести
    /// вторую реализацию ритма рядом с `WalkRhythmAnalyzer`.
    private func полосаКосточка(_ доля: Double) -> some View {
        GeometryReader { proxy in
            ZStack(alignment: .leading) {
                Capsule().fill(чернила.opacity(0.18))
                Capsule()
                    .fill(чернилаПолосы)
                    .frame(width: max(0, min(1, доля)) * proxy.size.width)
            }
        }
        .frame(height: Token.Size.bone)
        // Полоса — графика, а не орган управления: число уже сказано
        // показанием выше, и читать её голосом нечем.
        .accessibilityHidden(true)
    }

    // MARK: Цвета тона

    // Поверхность панели (`Reduce Transparency` → сплошная, иначе
    // `.ultraThinMaterial` по `togo-ios28.tokens.json`, `glass.swiftui`)
    // переехала в `TGGlassPanel` 26.10.2026 вместе с радиусом: там же
    // лежит токен, и там же названо, почему она не зовёт общее
    // `.стекло(радиус:)`. Плотность `.плотное`, которую стекло
    // объявляло ровно для этой панели, в тот же день удалена решением
    // Виктории — вызовов у неё не было ни одного, и разрыв «механизм
    // есть, входа нет» закрыт удалением механизма, а не подключением.

    /// Заливка панели у тех трёх тонов, что её красят.
    ///
    /// ~~«Токенов с этими именами в проекте ещё нет, и завести их мне
    /// нельзя — чужие пути. Здесь ближайшие живые токены того же
    /// смысла».~~ Токены завелись (пункт 5 Виктории, 25.10.2026),
    /// а эта строка осталась — и держала заливку на «ближайших живых»
    /// ещё сутки после того, как перестала быть верной.
    ///
    /// **Цена промедления — не вид, а читаемость, и она измерена:**
    ///
    /// ```
    /// чернила уехали на её палитру    labelOnFasting  #2A1D00
    /// заливка осталась на нашей       status.waitingBg #4A300A
    /// контраст ПАРЫ                   1,35
    /// объявлено было                  «1,92 → 8,59»
    /// на её панели #FFC233            10,22  (её счёт: 10,2)
    /// ```
    ///
    /// То есть правка, закрывавшая нечитаемость, сделала её **хуже**,
    /// а доклад назвал число, верное только для панели, которую
    /// не читала ни одна строка Swift.
    ///
    /// > **Перевести половину пары — опаснее, чем не переводить вовсе:**
    /// > каждая сторона по отдельности выглядит верной, и обе ссылаются
    /// > на её палитру. Цвет виден только в паре, а грепом пара
    /// > не ищется — ищутся два имени, оба живые.
    ///
    /// Поэтому приёмка здесь — `ЧернилаПанелиПарныеЗаливкеTests`:
    /// считает **контраст пары** из `tokens.json`, а не каждую сторону.
    /// И `alarm` прежде читал `Status.overdueText` — токен **текста**
    /// в роли фона: имя говорило про чернила, значением красили
    /// поверхность, и сторожа на такую подмену нет ни одного.
    private var заливкаПанели: Color {
        switch tone {
        case .fasting: Token.Poster.panelFasting
        case .dose: Token.Poster.panelDose
        case .alarm: Token.Poster.panelAlarm
        case .normal, .night, .walk: Token.Surface.card
        }
    }

    /// Чернила показания.
    ///
    /// Три случая, а не два, и разводит их **чем закрыта панель**:
    ///
    /// ```
    /// натощак          янтарь кроет панель     Poster.labelOnFasting
    /// доза             индиго кроет панель     Poster.labelOnDose
    /// тревога          терракот кроет панель   Poster.labelOnColor
    /// обычный/ночь/    под панелью ФОТОГРАФИЯ  Poster.labelOnColor
    /// прогулка
    /// ```
    ///
    /// **Три верхние строки правлены 25.10.2026** — до того дня первая
    /// несла `Ink.primary` (в тёмной это БЕЛЫЙ, 1,92 на янтаре),
    /// вторая и третья `Ink.onAccent` (#111111, 2,86 и 3,23). Разбор
    /// ниже.
    ///
    /// **Третья строка была `Ink.onAccent`, и это ломалось молча.**
    /// Прежняя проза объясняла выбор так: «на стекле — `onAccent`,
    /// потому что под стеклом фотография, и нейтральные чернила там
    /// нечитаемы». Довод верен, а токен перестал ему соответствовать:
    /// в «Кино» акцент стал белым, и `Ink.onAccent` = **#111111**.
    /// Замер кадром 23.10.2026 (`ЧернилаНаФотоКадрTests`): показание
    /// и подпись давали 1,1…3,2 при пороге 4,5 на трёх светлотах снимка.
    /// `Poster.labelOnColor` / `captionOnColor` — роль «текст НА цветном
    /// блоке», та же пара, что носит `CinemaHeader` на фото.
    /// # ПОКАЗАНИЕ НА ПАНЕЛИ БЫЛО НЕЧИТАЕМО У ВСЕХ ТРЁХ ТОНОВ
    ///
    /// Замер 25.10.2026, тёмная тема, порог для текста 4,5:
    ///
    /// ```
    /// тон        панель     чернила были   было    стало
    /// натощак    #EBB22F    Ink.primary    1,92    8,59
    ///                       (в тёмной БЕЛЫЙ)
    /// доза       #1C48EB    Ink.onAccent   2,86    6,00
    ///                       (#111111)
    /// тревога    #C42217    Ink.onAccent   3,23    5,31
    /// ```
    ///
    /// Это **большая цифра показания на главном экране** — то, на что
    /// человек смотрит первым.
    ///
    /// # Причина была не в недосмотре
    ///
    /// Значения дизайна для этих панелей **лежали в проекте**:
    /// `component.readingTone.fasting.fg` = `#2A1D00`,
    /// `…dose.fg` и `…alarm.fg` = `posterInk`. Читателей у них было
    /// **ноль**: `Token.Component.*` экранам запрещён
    /// (`ComponentTokenScopeTests`), и экран не мог их достать,
    /// поэтому подставлял общие чернила.
    ///
    /// **27.10.2026 все три удалены** — решением Виктории, вместе
    /// с 53 другими компонентными листьями без читателя. Значит
    /// «значения дизайна лежат в проекте» больше не верно для этой
    /// роли: в `tokens.json` их нет, и вернуть их можно только
    /// из хендоффа (`Дизайн/редизайн-ios28/tokens/togo-ios28.tokens.json`)
    /// либо из истории — `git show fd2a948^:DesignTokens/tokens.json`.
    /// Разбор ниже оставлен целиком: он объясняет **механизм**
    /// («источник правды содержал решение, которого не исполнял никто»),
    /// и механизм от удаления не изменился.
    ///
    /// > **Источник правды содержал решение, которого не исполнял
    /// > ни один читатель.** Грепом это не видно: имя есть, значение
    /// > есть, вызова по имени нет.
    ///
    /// Ровно этот случай Виктория уже решала 23.10.2026 про
    /// `semantic.category`: «цвет спрашивают кружок ленты, ВИДЖЕТ
    /// и ЖИВАЯ АКТИВНОСТЬ, а `Component` за пределами дизайн-системы
    /// запрещён — то есть из компонентного слоя двое из трёх достать
    /// его не могли и подставляли суррогат». Решение то же: роли
    /// заведены в `semantic.poster`, рядом с уже существующими
    /// `labelOnDose` · `captionOnDose` · `barOnDose`.
    ///
    /// # Чем подтверждается, что считал дизайн ту же палитру
    ///
    /// Его третье число для натощак — «10,2». `#2A1D00` на СПЛОШНОМ
    /// янтаре `#FFC233` даёт **10,22**, сошлось до сотой. То есть
    /// он считал по значениям, которые в коде есть и не читаются, —
    /// и предупредил об этом сам: «у разработчика свои значения,
    /// перед тем как принимать, сверь цифры с его прогоном».
    ///
    /// # Иерархия проверена отдельно от порога
    ///
    /// Подпись обязана быть ТИШЕ показания, и порог этого не ловит:
    /// натощак 8,59 против 4,89 · доза 6,00 против 5,42 · тревога
    /// 5,31 против 4,78. Все три тише, все три выше 4,5.
    private var чернила: Color {
        switch tone {
        case .fasting: Token.Poster.labelOnFasting
        // Роли ПАНЕЛИ, а не плаката, и это замер по её кадру
        // `04-p5-panel.png`, 25.10.2026. Прежде стояли `labelOnDose`
        // (= `posterInk` `#F4F4F2`) и `labelOnColor` — обе общие
        // с плакатом и нижней кнопкой:
        //
        // ```
        //              posterInk   чистый белый   её кадр
        // доза HC         7,44         8,20         8,2
        // тревога HC      7,14         7,86         7,9
        // ```
        //
        // Правкой самого `posterInk` это чинить нельзя: его читают
        // `TGPoster.swift:100` и `TodayBottom.swift:178`.
        case .dose: Token.Poster.labelOnDoseTone
        case .alarm: Token.Poster.labelOnAlarmTone
        default: Token.Poster.labelOnColor
        }
    }

    private var чернилаПодписи: Color {
        switch tone {
        case .fasting: Token.Poster.captionOnFasting
        // Роли ПАНЕЛИ, а не плаката: у двух тонов в повышенном
        // контрасте значения РАЗНЫЕ (#C7D3FF против #FFE3E0),
        // и `captionOnDose` трогать нельзя — её читает шапка-плакат,
        // и на неё стоит сторож.
        case .dose: Token.Poster.captionOnDoseTone
        case .alarm: Token.Poster.captionOnAlarmTone
        default: Token.Poster.captionOnColor
        }
    }

    /// Полоса — не текст, порог 3,0 (WCAG 1.4.11). Но и его не брала.
    ///
    /// ```
    /// доза      2,86 → 6,00   НЕ ХВАТАЛО
    /// тревога   3,23 → 5,31   хватало, стало лучше
    /// натощак   9,84 → 8,59   хватало, значение дизайна
    /// ```
    private var чернилаПолосы: Color {
        tone.paintsPanel ? чернила : Token.Action.primary
    }

    /// Подпись чипа — текст, порог 4,5. У двух тонов не брала.
    ///
    /// ```
    /// доза      3,26 → 5,27   НЕ ХВАТАЛО
    /// тревога   3,69 → 4,64   НЕ ХВАТАЛО
    /// натощак  11,70 → 10,22  хватало; значение дизайна чуть ниже
    ///                         прежнего и это НЕ ухудшение: #2A1D00 —
    ///                         то, что назвал дизайн, а 11,70 давал
    ///                         суррогат #111111
    /// ```
    ///
    /// **Ветка «чип не цветной» не тронута нарочно.** Там фон —
    /// `arctic`, он светлый, и `Ink.onAccent` (#111111) на нём верен.
    /// Подставить туда чернила тона значило бы покрасить белым
    /// по светлому: починка одной ветки сломала бы вторую, и это
    /// тот класс, который в проекте уже стоил кадра.
    /// **Чернила и заливка чипа берутся ПАРОЙ и от тона, замер
    /// 25.10.2026.** Прежде заливка была одна на все тоны —
    /// `Action.primary`, а в «Кино» это `#FFFFFF`, — а чернила брались
    /// у ПАНЕЛИ:
    ///
    /// ```
    ///           было                        стало по её токенам
    /// натощак   #2A1D00 на #FFFFFF  16,48   #2A1D00 на #FFC233  10,22
    /// доза      #FFFFFF на #FFFFFF   1,00   #F4F4F2 на #1F4FFF   5,27
    /// тревога   #FFFFFF на #FFFFFF   1,00   #F4F4F2 на #D52519   4,64
    /// ```
    ///
    /// У дозы и тревоги чип был **не виден вовсе**. У натощак выходило
    /// читаемо — и потому молчало: одна ветка из трёх держала
    /// правдоподобие.
    ///
    /// > **Чернила панели и чернила чипа — разные поверхности под
    /// > одним именем.** Пока панель и чип красились одинаково, это
    /// > было незаметно; как только у панели появился свой цвет,
    /// > общее имя стало красить чип цветом соседа.
    private var чернилаЧипа: Color {
        // Нецветной чип — СВЕТЛАЯ пилюля (`Action.primary` = #FFFFFF
        // в «Кино»), значит чернила тёмные. См. разбор у `заливкаЧипа`.
        guard чип.цветной else { return Token.Ink.onAccent }
        guard tone.paintsPanel else { return Token.Ink.onAccent }
        return tone == .fasting ? Token.Poster.chipLabelFasting
                                : Token.Poster.chipLabelOnTone
    }

    /// # Нецветной чип был ТЁМНЫМ при светлом на эталоне
    ///
    /// **Найдено отзывом Виктории 27.10.2026 и сверкой с кадром
    /// `ios28-кино-22.10/screenshots/01.png`:** там чип «Дома» —
    /// светлая пилюля с тёмным текстом и значком. У нас была тёмная
    /// карточка с белым текстом.
    ///
    /// Здесь же стоял комментарий, описывавший ПРАВИЛЬНОЕ поведение:
    /// «там фон `arctic`, он светлый, и `Ink.onAccent` (#111111)
    /// на нём верен». Код при этом брал `Surface.card` = `night2`
    /// = #1C1C1E, то есть ровно наоборот.
    ///
    /// > **Проза описывала замысел, код делал другое, и расходились
    /// > они молча.** Ни один сторож этого не ловил: оба цвета
    /// > из палитры, контраст у обеих пар проходит порог, и красным
    /// > стать было нечему. Поймал только взгляд на эталон рядом
    /// > с кадром приложения.
    ///
    /// Теперь ветка делает то, что про неё написано: `Action.primary`
    /// (#FFFFFF в «Кино») плюс `Ink.onAccent` (#111111) — 21:1.
    private var заливкаЧипа: Color {
        guard чип.цветной else { return Token.Action.primary }
        switch tone {
        case .fasting: return Token.Poster.chipFasting
        case .dose: return Token.Poster.chipDose
        case .alarm: return Token.Poster.chipAlarm
        // Прогулка и ночь панель не красят — чип остаётся светлым,
        // и `Ink.onAccent` на нём читается. Перечисление полное
        // нарочно: добавят тон — компилятор потребует решить.
        case .normal, .night, .walk: return Token.Action.primary
        }
    }
