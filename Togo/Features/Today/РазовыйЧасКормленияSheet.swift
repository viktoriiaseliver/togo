import SwiftUI

/// «Во сколько кормить сегодня?» — разовое исключение на одни сутки.
///
/// # Почему развилка именно такая
///
/// В отзыве 30.10 человек назвал три выхода: «сдвинуть пропорционально»,
/// «недокормить ужин», «оставить как есть». Форма шторки взята **не
/// оттуда**, и это замер, а не вкус (04.11.2026, настоящим
/// `MealSchedule`):
///
/// ```
/// её случай: обед съехал на 18:00     двинулось 0 кормлений из 1
/// КОНТРОЛЬ: съехал бы ЗАВТРАК         обед 15:30 → 17:00 (+90)
/// КОНТРОЛЬ: два кормления в день      19:30 → 21:00 (+90)
/// ```
///
/// Последнее кормление сжатого расписания стоит ровно на пределе
/// `latestMeal` = отбой − 90 мин = 21:30, и двигать его вперёд некуда
/// **по устройству**. То есть ветка «сдвинуть» на её расписании —
/// пустая: кнопка, которая ничего не делает.
///
/// > **А «сегодня ужин в 22:00» этот предел пробивает**, потому что
/// > это слово человека, а не производная расписания. Автоматика
/// > такого часа назвать не может и не должна — поэтому здесь
/// > спрашивают час, а не предлагают сдвиг.
///
/// Третье слово отзыва — «недокормить ужин» — про граммы, и его здесь
/// нет намеренно: подставить граммы значит сказать за человека то,
/// что потом прочитает врач. Это отдельный вопрос с отдельной ценой.
///
/// # Чего эта шторка НЕ делает
///
/// Не правит расписание. `Dog.mealTimes` остаётся как был; исключение
/// живёт одни сутки и отбрасывается читателем по дате
/// (`Dog.часыКормленийНа(_:)`). Чистилки по таймеру нет намеренно —
/// это была бы вторая механика, и её пришлось бы сторожить.
struct РазовыйЧасКормленияSheet: View {
    @Environment(\.dismiss) private var dismiss

    /// Подпись пункта плана — «Еда · 180 г».
    let title: String

    /// Час, на котором пункт стоит сейчас: либо из расписания, либо
    /// из уже стоящего исключения. Это и есть вторая ветка развилки —
    /// «оставить 21:30».
    let назначено: Date

    /// Начало суток, на которые ставится исключение. Приходит снаружи,
    /// потому что человек листает дни: план показывают и за вчера,
    /// и `Date()` внутри шторки поставил бы исключение не на тот день.
    let началоСуток: Date

    /// Стоит ли исключение на эти сутки уже. От этого зависит третий
    /// выход — «вернуть расписание», — и его нельзя показывать, когда
    /// возвращать нечего: кнопка без предмета читается как «расписание
    /// сейчас нарушено».
    let исключениеСтоит: Bool

    /// Час выбран. Минуты от полуночи считает зовущий — он же знает,
    /// в каком календаре живёт день.
    var onPick: (Date) -> Void

    /// Вернуть расписание этих суток.
    var onReset: () -> Void

    private enum Выбор: Hashable { case оставить, другое }

    @State private var выбор: Выбор = .оставить
    @State private var свой: Date

    init(title: String, назначено: Date, началоСуток: Date,
         исключениеСтоит: Bool,
         onPick: @escaping (Date) -> Void,
         onReset: @escaping () -> Void) {
        self.title = title
        self.назначено = назначено
        self.началоСуток = началоСуток
        self.исключениеСтоит = исключениеСтоит
        self.onPick = onPick
        self.onReset = onReset
        // Ползунок начинается от назначенного часа: от него и
        // отсчитывают, когда двигают.
        _свой = State(initialValue: назначено)
    }

    /// Конец суток. Исключение — про ОДИН день, и 02:00 следующего
    /// он не значит: такой час человек назвал бы завтрашним днём.
    private var пределСуток: Date {
        началоСуток.addingTimeInterval(24 * 3600 - 60)
    }

    var body: some View {
        TGSheet(title: "Во сколько кормить сегодня?", subtitle: .готовая(title)) {
            TGCard(padding: Token.Space.s4) {
                VStack(spacing: 0) {
                    строка(.оставить,
                           text: String(localized: "Оставить \(Fmt.clock(назначено))"))
                    TGDivider()
                    строка(.другое, text: String(localized: "Кормить в другое время"))

                    if выбор == .другое {
                        TGDivider()
                        // **Потолка расписания здесь нет нарочно.**
                        // `MealSchedule.latestMeal` держит последнее
                        // кормление на «отбой − 90 мин», и это верно
                        // для расписания, которое приложение строит
                        // само. Час, названный человеком, этот предел
                        // пробивает — ради этого исключение и заведено.
                        DatePicker("Время", selection: Binding(
                            get: { min(max(свой, началоСуток), пределСуток) },
                            set: { свой = min(max($0, началоСуток), пределСуток) }
                        ), in: началоСуток...пределСуток, displayedComponents: .hourAndMinute)
                        .textStyle(AppFont.body)
                        .frame(minHeight: Token.Size.tapTarget)
                    }
                }
                .padding(.horizontal, Token.Space.s12)
            }

            TGButton(title: "Только на сегодня", variant: .primary, size: .medium) {
                onPick(выбрано)
                dismiss()
            }

            if исключениеСтоит {
                TGButton(title: "Вернуть расписание", variant: .secondary, size: .medium) {
                    onReset()
                    dismiss()
                }
            }

            TGExplainer(text: "Расписание останется прежним — меняется только сегодняшний день. Семья увидит этот час у себя.")
        }
    }

    private var выбрано: Date {
        switch выбор {
        case .оставить: назначено
        case .другое: min(max(свой, началоСуток), пределСуток)
        }
    }

    /// Строка выбора. Галочка, а не одна заливка: направление выбора
    /// одним цветом не передаётся — у Togo это записанное правило.
    private func строка(_ значение: Выбор, text: String) -> some View {
        Button {
            выбор = значение
        } label: {
            HStack(spacing: Token.Space.s8) {
                Image(systemName: выбор == значение ? "checkmark.circle.fill" : "circle")
                    .font(.system(size: Token.Size.iconSm, weight: .bold))
                    .foregroundStyle(выбор == значение ? Token.Action.doneText : Token.Ink.secondary)
                    .accessibilityHidden(true)
                Text(text).textStyle(AppFont.body)
                Spacer(minLength: 0)
            }
            .frame(minHeight: Token.Size.tapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(выбор == значение ? [.isButton, .isSelected] : .isButton)
    }
}
