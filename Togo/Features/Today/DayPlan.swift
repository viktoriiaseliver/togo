import SwiftUI

// Режим дня: что нужно сделать сегодня и что уже сделано.
//
// Жил в одном файле с лентой, и файл дорос до шестисот сорока строк.
// Лента показывает, что **было**; режим дня — что **надо**. Это два
// разных вопроса, и правка одного заставляла листать другой.

struct DayPlanItem: Identifiable, Equatable {
    enum Kind { case meal, dose, care }

    let id: String
    let time: Date
    let title: String
    var hint: String?
    let kind: Kind
    var isDone: Bool
    /// К какому препарату относится пункт — нужно, чтобы отметить приём,
    /// а не только записать строку в ленту.
    var medication: Medication?
    /// К какому делу ухода. Уход переехал сюда из отдельной карточки:
    /// она говорила, что надо сделать, но сделать оттуда было нельзя —
    /// приходилось идти на вкладку собаки и искать дело руками.
    var careTask: CareTask?
    /// У ухода часа нет: зубы чистят не в 19:40, а «сегодня».
    var showsTime: Bool = true

    /// Когда на самом деле покормили, если это было не в час слота.
    ///
    /// Заведено 04.11.2026 по отзыву 30.10: «2 раза покормила собаку,
    /// пусть в другое время… А обед отметить как Дан».
    ///
    /// Галочка на слоте 15:30 от записи в 18:00 без этой приписки —
    /// **вторая неправда вместо первой**: было «ты не кормила»,
    /// стало бы «ты кормила в 15:30». Час называется прямо.
    var фактВремя: Date?

    /// Сколько выйдет от прошлого кормления до этого часа.
    ///
    /// Заведено 04.11.2026 по второй половине отзыва 30.10. Прошлый
    /// пункт, закрытый записью не в свой час, свёрнут под «сделано · N»
    /// — то есть **причину человек не видит, а следствие стоит у него
    /// перед глазами**: ужин в 21:30 после еды в 18:00 приходит через
    /// 3 ч 30 мин вместо шести, и до этой правки об этом не говорил
    /// никто.
    ///
    /// `nil` — считать не от чего (первый пункт дня либо прошлый
    /// не закрыт).
    var промежуток: MealSchedule.Промежуток?

    /// Какая запись закрыла пункт.
    ///
    /// До 04.11.2026 этого не знал никто: `matchDone` отдавал только
    /// «да/нет», и **кто закрыл слот, искали заново в двух других
    /// местах** — `ShiftReport` (±90 мин по ленте) и `DayPlanActions`
    /// (при снятии отметки). Три копии одного правила, и расходиться
    /// они начали ровно на записи вне слота.
    var закрытаЗаписью: UUID?

    /// В какую часть дня встанет пункт без часа.
    ///
    /// Заведено 04.11.2026 по отзыву 28.10: «Почему уход днем? Хочу
    /// выбирать часть дня сама». Настройку сделали в тот же день
    /// (`afc9e769`), а ЭТОТ экран — тот самый, который она
    /// сфотографировала, — продолжал печатать слово жёстко.
    ///
    /// > **Отзыв был закрыт формально и остался открытым глазами.**
    /// > Человек выбирает «вечером», план дня по-прежнему говорит
    /// > «днём» — и это хуже, чем если бы настройки не было вовсе:
    /// > теперь приложение не молчит, а противоречит.
    ///
    /// `nil` — часть дня неизвестна (вызов без часа сводки);
    /// подпись тогда остаётся прежней.
    var частьДня: ЧастьДня?
    /// Доза ждёт таймера от еды — отметить её раньше нельзя.
    var gate: DoseGate.State = .open

    /// Час этого пункта стоит по **разовому исключению на сегодня**,
    /// а не по расписанию.
    ///
    /// Нужно сказать вслух, и вот почему: на втором телефоне «ужин
    /// в 22:00» неотличим от правки расписания, а это разные вещи —
    /// завтра собака снова ест в 21:30. Без приписки второй человек
    /// либо решит, что расписание сменили, либо «починит» его обратно.
    ///
    /// Входит в `==` ниже по тому же доводу, что `промежуток`: пункт,
    /// у которого сменилось ТОЛЬКО это, обязан перерисоваться.
    var сегодняИначе: Bool = false

    /// **Равенство решает, перерисуется ли строка, и до 04.11.2026 оно
    /// не знало про час и промежуток.**
    ///
    /// Три поля из четырнадцати. Пока менялись только они, это было
    /// дешёвым сравнением; с `промежуток` оно стало ЛОЖНЫМ, и вот чем:
    ///
    /// ```
    /// отметили еду в 18:00
    ///   пункт 15:30   isDone false → true   → не равен, перерисуется
    ///   пункт 21:30   id, time, isDone ТЕ ЖЕ, появился промежуток
    ///                                       → РАВЕН, строка не придёт
    /// ```
    ///
    /// То есть правка работала бы «через раз» — до ближайшей чужой
    /// перерисовки, — а прогон был бы зелёным в обеих версиях: кадр
    /// снимается с готового списка и этой разницы не видит по
    /// устройству. Ровно та же форма, что у кромок затемнения 04.11.
    ///
    /// `фактВремя` добавлено тем же доводом. Сегодня оно приходит
    /// вместе с `isDone` на ОДНОМ пункте и потому «работало» —
    /// но держалось это на совпадении, а не на правиле.
    static func == (lhs: DayPlanItem, rhs: DayPlanItem) -> Bool {
        lhs.id == rhs.id && lhs.isDone == rhs.isDone && lhs.time == rhs.time
            && lhs.фактВремя == rhs.фактВремя
            && lhs.промежуток == rhs.промежуток
            && lhs.сегодняИначе == rhs.сегодняИначе
    }
}

/// Свайп вправо означает «сделано» — и в режиме дня, и у ситтера.
struct DayPlanList: View {
    let items: [DayPlanItem]
    let now: Date
    var onComplete: (DayPlanItem) -> Void
    /// Вернуть пункт в невыполненные. Отметили не то — должно быть
    /// куда отступить.
    var onUndo: (DayPlanItem) -> Void = { _ in }
    /// Открыть запись пункта: тап по тексту, а не по кругу.
    var onOpen: (DayPlanItem) -> Void = { _ in }
    /// Сколько дел ухода ждут даты. Пока её нет, дело не станет сроком
    /// и не напомнит ни о чём — а выглядит заведённым.
    var awaitingDate: Int = 0
    var onOpenCare: () -> Void = {}

    /// Показывать ли сделанное. По умолчанию свёрнуто.
    @State private var showsDone = false

    private var pending: [DayPlanItem] { items.filter { !$0.isDone } }
    private var done: [DayPlanItem] { items.filter(\.isDone) }

    var body: some View {
        if !items.isEmpty {
            TGCard {
                header
                // «Всё сделано» говорит одна шапка (решение Виктории
                // 29.10.2026). Здесь стояло ещё пояснение «На сегодня всё.
                // Ниже — что уже сделали», и «всё» читалось дважды подряд,
                // а на прошлом дне «на сегодня» было неправдой: план
                // показывают и за вчера. Шапка про день не говорит вовсе —
                // она верна на любом, — а «ниже» уже сказано строкой
                // «сделано · N» с раскрытием.
                if !pending.isEmpty { rows(pending) }

                if !done.isEmpty {
                    TGDivider()
                    doneToggle
                    if showsDone { rows(done, isDone: true) }
                }

                if awaitingDate > 0 {
                    TGDivider()
                    awaitingDateRow
                }
            }
        }
    }

    /// Шапка говорит, сколько осталось, а не сколько всего: остаток —
    /// единственное, ради чего в режим дня заглядывают.
    private var header: some View {
        HStack {
            Text(pending.isEmpty
                 ? "план дня · всё сделано"
                 : "план дня · осталось \(pending.count) из \(items.count)")
                .textStyle(AppFont.micro)
                .foregroundStyle(Token.Ink.secondary)
            Spacer(minLength: 0)
        }
    }

    /// Сделанное сворачивается, но не исчезает.
    ///
    /// Выполненные пункты весь день висели наравне с невыполненными,
    /// и остаток приходилось выискивать глазами. Просто убрать их тоже
    /// нельзя: «я точно кормила?» — вопрос, который задают каждый вечер.
    private var doneToggle: some View {
        Button {
            withAnimation(.easeInOut(duration: Token.Duration.quick)) { showsDone.toggle() }
        } label: {
            HStack(spacing: Token.Space.s6) {
                Image(systemName: showsDone ? "chevron.down" : "chevron.right")
                    .font(AppFont.icon.font)
                Text("сделано · \(done.count)")
                    .textStyle(AppFont.captionEmphasis)
                Spacer(minLength: 0)
            }
            .foregroundStyle(Token.Action.doneText)
            .frame(minHeight: Token.Size.tapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .accessibilityLabel(showsDone ? "Скрыть сделанное" : "Показать сделанное, \(done.count)")
    }

    /// Дела, которые заведены, но молчат.
    ///
    /// Напоминание без даты никогда не станет сроком: у «раз в 28 дней»
    /// нет точки отсчёта, у прививки нет дня. Такие дела выглядят
    /// заведёнными и не напоминают ни о чём — а узнать об этом можно
    /// было, только зайдя в уход и увидев их там отдельной группой.
    private var awaitingDateRow: some View {
        Button(action: onOpenCare) {
            HStack(spacing: Token.Space.s8) {
                Image(systemName: "calendar.badge.exclamationmark")
                    .font(AppFont.icon.weight(Token.FontWeight.medium).font)
                    .foregroundStyle(Token.Status.waitingText)
                    .accessibilityHidden(true)
                // `Fmt.plural` возвращает число ВМЕСТЕ со словом. Число
                // перед ним печаталось второй раз: «5 5 напоминаний».
                Text("\(String(localized: "\(awaitingDate) напоминаний ждут")) даты")
                    .textStyle(AppFont.caption)
                    .foregroundStyle(Token.Ink.secondary)
                    .wraps()
                Spacer(minLength: 0)
                Image(systemName: "chevron.right")
                    .font(AppFont.icon.font)
                    .foregroundStyle(Token.Ink.secondary)
            }
            .frame(minHeight: Token.Size.tapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
    }

    /// Что стоит под названием: время и, у сделанного, кто и когда.
    private func subtitle(for item: DayPlanItem, isDone: Bool) -> String? {
        // Замок говорит сам за себя: время дозы, которая ещё не открылась,
        // человеку ничего не даёт.
        if let waiting = DoseGate.caption(item.gate, now: now) { return waiting }
        var parts: [String] = []
        if item.showsTime {
            parts.append(Fmt.clock(item.time))
        } else {
            // Слово берётся у `ЧастьДня`, а не литералом: там
            // единственный дом трёх названий, и перевод у них общий
            // с настройкой, в которой человек их и выбирает.
            parts.append((item.частьДня ?? .день).title)
        }
        // Пустая подсказка — не подсказка. У еды сюда приходит марка
        // корма, а она чаще всего пустая СТРОКА, а не `nil`, — и строка
        // плана читалась «15:30 ·» с точкой, за которой ничего нет
        // (кадр 28.10.2026).
        // ЧАС НАЗЫВАЕТСЯ, КОГДА ОН РАЗОШЁЛСЯ СО СЛОТОМ.
        //
        // Отзыв 30.10.2026: покормили в 18:00, слот стоит на 15:30.
        // Теперь запись слот закрывает — и без этой строки человек
        // увидел бы галочку на 15:30, то есть **вторую неправду вместо
        // первой**: было «ты не кормила», стало бы «ты кормила в 15:30».
        //
        // Порог тот же, что у вопроса «когда дали» (`LateMarking.grace`),
        // а не свой: два порога про одно расхождение разошлись бы молча.
        if let факт = item.фактВремя,
           abs(факт.timeIntervalSince(item.time)) > LateMarking.grace {
            parts.append(String(localized: "покормлено в \(Fmt.clock(факт))"))
        }
        // ИСХОД НАЗЫВАЕТСЯ ЧИСЛОМ И СЛОВОМ, А НЕ ОДНИМ ЧИСЛОМ.
        //
        // Строка выше говорит о пункте, который УЖЕ закрыт, — а закрытое
        // свёрнуто под «сделано · N». Человек смотрит на невыполненное,
        // и там до этой правки стояло «21:30 · Эдгар Купер» и ни слова
        // о том, что до этого ужина осталось 3 ч 30 мин вместо шести.
        //
        // «3 ч 30 мин» в одиночку читалось бы как «через 3 ч 30 мин
        // от сейчас» — поэтому в строке стоят ОБА числа и час, от которого
        // считали: у величины названа ось, у оси — источник.
        //
        // Только у невыполненного: у закрытого пункта это уже не прогноз,
        // а другой вопрос — сколько прошло между двумя записями.
        if !item.isDone, let п = item.промежуток, п.стоитНазвать {
            parts.append(String(localized:
                "после еды в \(Fmt.clock(п.факт)) — \(Fmt.duration(п.выйдет)) вместо \(Fmt.duration(п.поРасписанию))"))
        }
        // ЧАС ПО ИСКЛЮЧЕНИЮ НАЗЫВАЕТСЯ ИСКЛЮЧЕНИЕМ.
        //
        // «22:00» само по себе говорит, что расписание такое. На втором
        // телефоне это прямая неправда: расписание прежнее, сдвинут
        // один вечер. Без этих слов второй человек либо решит, что
        // расписание сменили, либо вернёт его «как было» — и собака
        // получит ужин в 21:30, о котором никто не договаривался.
        if item.сегодняИначе { parts.append(String(localized: "только сегодня")) }
        if let hint = item.hint.flatMap(Fmt.notBlank) { parts.append(hint) }
        return parts.joined(separator: " · ")
    }

    /// Чем красить подпись: ожидание — мятой, просрочка — жёлтым.
    private func tint(for item: DayPlanItem) -> Color? {
        if !item.gate.isOpen { return Token.Status.doneText }
        return isOverdue(item) ? Token.Status.waitingText : nil
    }

    /// Просрочка желтеет — но только у того, у чего есть час.
    private func isOverdue(_ item: DayPlanItem) -> Bool {
        item.showsTime && !item.isDone && item.time < now
    }

    private func rows(_ list: [DayPlanItem], isDone: Bool = false) -> some View {
        VStack(spacing: 0) {
            ForEach(list) { item in
                TGCheckRow(title: .готовая(item.title),
                           subtitle: subtitle(for: item, isDone: isDone).map { .готовая($0) },
                           isDone: isDone,
                           isLocked: !item.gate.isOpen,
                           subtitleTint: tint(for: item),
                           onCheck: {
                               // Закрытую дозу нажатие не отмечает —
                               // оно объясняет, чего ждём.
                               //
                               // Круг уже данной ДОЗЫ тоже не снимает
                               // отметку, а открывает замок (29.10.2026).
                               // Комментарий у `TodayScreen.open` это
                               // обещал, а нажатие шло в `onUndo`: тот,
                               // кто хотел проверить «дали ли», одним
                               // касанием возвращал дозу в план — и её
                               // давали второй раз. Снять отметку можно
                               // и теперь, но явной кнопкой в замке.
                               if !item.gate.isOpen { onOpen(item) }
                               else if isDone, item.kind == .dose { onOpen(item) }
                               else if isDone { onUndo(item) } else { onComplete(item) }
                           },
                           onOpen: { onOpen(item) })
                if item.id != list.last?.id { TGDivider(inset: 52) }
            }
        }
    }
}
