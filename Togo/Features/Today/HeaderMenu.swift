import SwiftUI

/// Единственная кнопка шапки — «…».
///
/// Решение Виктории 22.10.2026 («перепиши всё под дизайн»), источник —
/// `design_handoff_togo_ios28/README.md`, «Навигация (решено)»:
/// *«Шапка: одна кнопка «…» (меню): Настройки · Другой день
/// (на «Сегодня») · Семья (на вкладке собаки). Больше кнопок в шапке
/// нет»*.
///
/// До этого на каждой вкладке стояла шестерёнка (`SettingsToolbarItem`,
/// пять мест). Шестерёнка снята с «Сегодня» и со вкладки собаки; сам
/// тип оставлен объявленным, потому что его зовут `HealthScreen`
/// и `HistoryScreen` — чужие пути.
///
/// **Пункты приходят замыканиями, а не `NavigationLink`.** Внутри
/// `Menu` ссылка навигации ведёт себя непредсказуемо: меню закрывается
/// раньше, чем успевает сработать переход. Поэтому меню только
/// называет намерение, а переход делает хозяин экрана —
/// `navigationDestination(isPresented:)` у себя.
struct HeaderMenu: View {
    /// Настройки есть всегда: Apple ждёт их в предсказуемом месте.
    var настройки: () -> Void
    /// «Другой день» — только на «Сегодня». Пусто — пункта нет.
    var другойДень: (() -> Void)?
    /// «Семья» — только на вкладке собаки. Пусто — пункта нет.
    var семья: (() -> Void)?

    init(настройки: @escaping () -> Void,
         другойДень: (() -> Void)? = nil,
         семья: (() -> Void)? = nil) {
        self.настройки = настройки
        self.другойДень = другойДень
        self.семья = семья
    }

    var body: some View {
        Menu {
            // Порядок — из хендоффа дословно, а не по алфавиту
            // и не по частоте: «Настройки · Другой день · Семья».
            Button {
                настройки()
            } label: {
                Label("Настройки", systemImage: "gearshape")
            }

            if let другойДень {
                Button {
                    другойДень()
                } label: {
                    Label("Другой день", systemImage: "calendar")
                }
            }

            if let семья {
                Button {
                    семья()
                } label: {
                    Label("Семья", systemImage: "person.2")
                }
            }
        } label: {
            Image(systemName: "ellipsis")
                .font(.system(size: Token.Size.iconSm, weight: .semibold))
                // Цель касания — не меньше 44 pt. Глиф «…» мелкий,
                // и без явной рамки кнопка выходила по размеру глифа:
                // хендофф просит `size.headerButton = 44`, а токена
                // с таким именем в проекте ещё нет — взят
                // `Token.Size.tapTarget`, он ровно 44 и держится
                // `ПолКегляTests`.
                .frame(width: Token.Size.tapTarget,
                       height: Token.Size.tapTarget)
                .contentShape(Rectangle())
        }
        // Имя голосом — словом, а не «многоточие»: озвучка читает
        // глиф буквально, и человек слышал бы «точка точка точка».
        .accessibilityLabel("Ещё")
        .accessibilityIdentifier("шапка-меню")
    }
}
