import Foundation

/// Один тон на всё показание: панель, чип, главная кнопка и фильтр фото.
///
/// Решение Виктории 22.10.2026, прямым словом в чате («перепиши всё
/// под дизайн»); источник — `design_handoff_togo_ios28/README.md`,
/// раздел «Рекомендации» 2: *«Один `ReadingTone`
/// (normal/fasting/dose/alarm/night/walk) управляет панелью, чипом,
/// главной кнопкой и тоном фото — как `TONE` в прототипе.
/// Не размазывать цвета по экранам»*.
///
/// **Чего этот тип не знает нарочно.** Ни `Color`, ни SwiftUI, ни имён
/// токенов — ровно по той же причине, по которой их не знает
/// `PosterMode`: дизайн переезжает в Figma и может меняться, а логика
/// остаётся. Он отвечает на один вопрос — **какой тон**, — а чем тон
/// покрашен, решают токены (`tokens/togo-ios28.tokens.json`,
/// раздел `readingTone`).
///
/// ## Почему это НЕ `PosterMode` и почему два типа живут рядом
///
/// `PosterMode` отвечает на похожий вопрос и **остаётся на месте**:
/// его спрашивают виджет, «остров» и «На улице», а у нас записано, чем
/// кончается третья реализация одного правила. Снести его отсюда
/// значило бы править чужие поверхности вслепую.
///
/// Но свести их в один тип нельзя, и это **замер, а не вкус** —
/// у них разный порядок, и расходится он там, где видно человеку:
///
/// ```
/// PosterMode.mode   alarm → (night ИЛИ firstDay) → dose → fasting → usual
/// хендофф 22.10     alarm → dose → fasting → episode → … → normal,
///                   а night — ЗАПАСНОЙ исход, ниже normal
/// ```
///
/// То есть в три часа ночи при неотмеченной дозе `PosterMode` даёт
/// нейтральный блок, а хендофф — синюю панель. Старое поведение стоит
/// на записанном решении про тихие часы («цветной блок в три ночи —
/// это свет в лицо»), новое — на решении Виктории 22.10.2026.
///
/// > **Два решения с адресами противоречат друг другу, и выбрать
/// > за Викторию я не могу.** Здесь исполнен хендофф, потому что он
/// > назван прямым словом и позже; `PosterMode` не тронут, потому что
/// > он чужих поверхностей. Расхождение закреплено тестом
/// > `ReadingToneTests.ночьНеГаситДозу` — чтобы оно было громким,
/// > а не молчало до первой ночной дозы.
///
/// Порядок взят не из прозы README, а из прототипа — он назван
/// источником правды по поведению (`Togo-RU.dc.html:597`, массив
/// `states` и строка `const top`). Проза README перечисляет восемь
/// состояний, прототип — десять: `threshold` и `away` в прозу
/// не попали.
nonisolated enum ReadingTone: String, CaseIterable, Sendable {

    /// Обычный день. Панель — стекло (`--g-strong`), полоса синяя.
    case normal

    /// Окно натощак. Янтарь, тёмный текст `#2A1D00`.
    case fasting

    /// Час дозы. Синяя панель, белый текст, главная кнопка синяя.
    case dose

    /// Тревога. Терракот, белый текст.
    case alarm

    /// Ночь и тихие часы. Панель остаётся стеклом, меняется **фото**:
    /// `saturate(.3) brightness(.7)`.
    case night

    /// Идёт выход. Панель — стекло, чип синий, содержимое — таймер.
    case walk

    /// Красит ли тон главную кнопку своим цветом.
    ///
    /// Отдельный вопрос, а не производное от тона: иначе вью однажды
    /// спросит `tone == .dose` своей рукой, и появится вторая
    /// реализация одного правила.
    ///
    /// **`false` значит «кнопка белая с текстом `#111`»** — решение
    /// Виктории 22.10.2026, прямым выбором из трёх вариантов с ценой:
    /// «Кино» заменяет Graphite **целиком**, индиго `#1F4FFF` как цвет
    /// главной кнопки отменено, флага `look` не будет.
    ///
    /// **Но белая — это обычное состояние, а не все шесть.** У дозы
    /// кнопка синяя (`readingTone.dose.primaryButton = #1F4FFF`),
    /// у тревоги терракотовая (`#D52519`) — и ровно ради этих двух
    /// состояний экран вообще красится. Прибить белую кнопку
    /// безусловно значит отнять цвет у дозы и тревоги, то есть
    /// у единственных двух случаев, где он что-то значит.
    var tintsPrimaryButton: Bool { self == .dose || self == .alarm }

    /// Красит ли тон саму панель. `false` — панель остаётся стеклом,
    /// и тон виден только на фото и чипе.
    ///
    /// Нужно тому, кто решает, брать ли на тексте светлые чернила:
    /// на стекле их берёт тема, на заливке — тон.
    var paintsPanel: Bool {
        switch self {
        case .fasting, .dose, .alarm: true
        case .normal, .night, .walk: false
        }
    }

    /// Приглушает ли тон фото. Единственный такой — ночь.
    var dimsPhoto: Bool { self == .night }
}

/// Состояние дня «Сегодня» — то, из-за чего экран выглядит так,
/// а не иначе.
///
/// Полный список — `SCREENS.md`. **Там он назван числом «14 состояний»
/// и тут же перечисляет восемнадцать имён** (замер 22.10.2026: обычно,
/// первый день, доза, «взяла на себя», не отмечена, натощак, тревога,
/// повторы, эпизод, поездка, со мной весь день, ситтер, запас,
/// нет сети, хранилище, ночь, долго без выходов, прошлый день).
/// Число в документе и число имён рядом с ним расходятся — считать
/// по именам, а не по числу.
///
/// Здесь заведены те, у которых есть **свой тон или своё место
/// в очереди**. «Взяла на себя», «не отмечена» и «повторы» — это
/// подвиды дозы и тревоги, они меняют подпись, а не тон, и живут
/// в показании, а не здесь.
nonisolated enum TodayState: String, CaseIterable, Sendable {
    /// Кровь, рвота, инцидент — то, из-за чего берут телефон.
    case alarm
    /// Счёт дошёл сам: три одинаковых инцидента за шесть часов.
    case threshold
    /// Час дозы наступил, доза не отмечена.
    case dose
    /// Идёт окно натощак перед дозой.
    case fasting
    /// Активный эпизод наблюдения.
    case episode
    /// Поездка.
    case trip
    /// Ситтер.
    case sitter
    /// Собака со мной весь день.
    case away
    /// Запас таблеток кончается (≤ 3 дней).
    case stock
    /// Нет сети — общий дневник не доехал.
    case offline
    /// Идёт выход.
    case walk
    /// Записей ещё не было вовсе.
    case first
    /// Выходов нет больше суток.
    case silence
    /// Ночь по тихим часам.
    case night
    /// Обычный день.
    case normal

    /// Каким тоном красится экран, когда это состояние — главное.
    ///
    /// **Тонов шесть, состояний пятнадцать**, и это не упущение:
    /// хендофф просит «не размазывать цвета по экранам». Поездка,
    /// ситтер и запас меняют строку «Дальше» и пилюлю, а не цвет
    /// панели — цвет тратится только на то, из-за чего экран открыли.
    var tone: ReadingTone {
        switch self {
        case .alarm, .threshold:            .alarm
        case .dose:                         .dose
        case .fasting:                      .fasting
        case .walk:                         .walk
        case .night:                        .night
        case .episode, .trip, .sitter, .away, .stock, .offline,
             .first, .silence, .normal:     .normal
        }
    }
}

/// Очередь состояний «Сегодня»: кто главный, кто в «Дальше», кто пилюлей.
///
/// Имя не `TodayRouter` нарочно — он занят с 28.09 и отвечает на другой
/// вопрос («какую шторку показать по кнопке»). Хендофф называет этим
/// словом порядок состояний; в коде это два разных предмета, и слепить
/// их значило бы получить тип, который решает и навигацию, и цвет.
nonisolated enum TodayStateRouter {

    /// Что приложение знает о дне.
    ///
    /// Плоская структура нарочно — ровно по образцу `PosterMode.DayState`:
    /// правило надо уметь спросить из теста, не поднимая хранилище.
    /// **Ни один флаг здесь не выводится заново** — все приходят
    /// от тех же анализаторов, что красят баннеры ниже на экране.
    struct DayState: Sendable, Equatable {
        var isAlarm: Bool = false
        var isThreshold: Bool = false
        var isDoseDue: Bool = false
        var isFasting: Bool = false
        var isEpisode: Bool = false
        var isTrip: Bool = false
        var isSitter: Bool = false
        var isAway: Bool = false
        /// Запас ≤ 3 дней. Порог живёт у вызывающего, а не здесь:
        /// число «3» — продуктовое решение, и второй его копии
        /// в проекте быть не должно.
        var isStockLow: Bool = false
        var isOffline: Bool = false
        var isWalking: Bool = false
        /// Записей нет вовсе. Не «ритма ещё нет»: `PosterMode` на этом
        /// однажды дал нейтральный плакат на трое суток, потому что
        /// `WalkRhythm.minimumDays == 3`.
        var hasNoEntries: Bool = false
        /// Выходов нет больше суток.
        var isSilent: Bool = false
        var isNight: Bool = false

        init() {}
    }

    /// Все состояния дня по убыванию важности.
    ///
    /// **Порядок и есть правило, а не оформление.** Он снят
    /// с прототипа — `Togo-RU.dc.html:597`:
    ///
    /// ```
    /// if (d.alarm) states.push('alarm'); if (d.threshold) …'threshold';
    /// if (ds) …'dose'; if (fastingLeft) …'fast'; if (d.episode) …;
    /// if (d.trip) …; if (d.sitter) …; if (d.away) …;
    /// if (d.meds && stockDays <= 3) …'stock'; if (d.offline) …;
    /// const top = (walking && S.walkMin) ? 'walk' : states[0]
    ///   || (!lastWalk ? 'first' : silence ? 'silence'
    ///       : isNight ? 'night' : 'normal');
    /// ```
    ///
    /// Два следствия, которые из прозы README не видно:
    ///
    /// 1. **Выход перебивает всё**, включая тревогу: пока человек
    ///    на улице, экран показывает таймер. В прототипе это `walkMin`
    ///    — свёрнутый вид; у нас выход идёт, только когда его начали,
    ///    то есть человек уже смотрит на него.
    /// 2. **Ночь — запасной исход, а НЕ ступень очереди.** Она
    ///    применяется, только когда не верно ничего выше, то есть
    ///    ночью при неотмеченной дозе панель синяя. Это и есть
    ///    расхождение с `PosterMode`, описанное у `ReadingTone`.
    static func states(_ s: DayState) -> [TodayState] {
        if s.isWalking { return [.walk] }
        var queue: [TodayState] = []
        if s.isAlarm { queue.append(.alarm) }
        if s.isThreshold { queue.append(.threshold) }
        if s.isDoseDue { queue.append(.dose) }
        if s.isFasting { queue.append(.fasting) }
        if s.isEpisode { queue.append(.episode) }
        if s.isTrip { queue.append(.trip) }
        if s.isSitter { queue.append(.sitter) }
        if s.isAway { queue.append(.away) }
        if s.isStockLow { queue.append(.stock) }
        if s.isOffline { queue.append(.offline) }
        if !queue.isEmpty { return queue }
        // Запасные исходы — ровно в том порядке, что в прототипе.
        if s.hasNoEntries { return [.first] }
        if s.isSilent { return [.silence] }
        if s.isNight { return [.night] }
        return [.normal]
    }

    /// Главное состояние — оно красит панель и главную кнопку.
    static func top(_ s: DayState) -> TodayState {
        states(s).first ?? .normal
    }

    /// Тон экрана.
    static func tone(_ s: DayState) -> ReadingTone { top(s).tone }

    /// Второе состояние — уезжает в строку «Дальше». Пусто, если
    /// состояние ровно одно.
    static func second(_ s: DayState) -> TodayState? {
        let queue = states(s)
        return queue.count > 1 ? queue[1] : nil
    }

    /// Третье состояние — уезжает пилюлей под шапку. Пилюля ровно одна:
    /// хендофф разрешает «≤ 1».
    static func third(_ s: DayState) -> TodayState? {
        let queue = states(s)
        return queue.count > 2 ? queue[2] : nil
    }
}
