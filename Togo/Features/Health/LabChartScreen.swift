/// График показателя во времени — то, ради чего медслой затевался.
///
/// **Вопрос, на который он отвечает:** «почему Т4 не растёт при росте
/// дозы». В карте Стича доза выросла в пять раз, а Т4 упал до 6,0 —
/// и увидеть это можно только рядом, во времени.
///
/// ## Первая часть из двух, и она самодостаточна
///
/// Здесь: линия показателя, полоса нормы фоном, **форма маркера
/// по времени забора**, отклонение словом в таблице, период
/// и «Сравнивать пока не с чем» на одной точке.
///
/// Второй частью идут **столбики дозы** у каждой точки и карточка
/// по тапу (четыре величины словами). Их нет не потому, что забыли:
/// доза на дату — отдельный расчёт по расписанию схемы, и её лучше
/// заводить вместе с карточкой точки, где она и названа словом.
///
/// Разделено так нарочно: половина графика, которая **собирается
/// и показывает полосу нормы**, — это работа. Половина в дереве —
/// брошенное.
///
/// ## Три правила, которые здесь исполняются, а не упоминаются
///
/// **1. Отклонение — словом, а не только цветом и положением.**
/// Слово берётся у `LabNorm.word`, а не пишется здесь: иначе вторая
/// поверхность напишет своё, и у Togo это уже было — виджет считал
/// окно «не кормить» собственной арифметикой.
///
/// **2. Разное время забора — не расхождение.** `LabSampleTiming`
/// держит порог в три часа, и он взят из карты: 3,5 ч против 11,5 ч
/// при одной дозе дали **противоположные выводы**. Поэтому форма
/// маркера различает время забора, а несравнимые точки прямо названы
/// в таблице.
///
/// **3. Подпись часов — ОКРУГЛЁННАЯ (`caption`), не точная.**
/// Две функции лежат в одном файле, и завёл их я же: на вводе нужна
/// точность до минуты, на графике — получас, как в дизайне («+3,5 ч»,
/// «+11,5 ч»).
///
/// > Я помню про себя «я сделал точную» — и именно поэтому адрес
/// > назван буквой: здесь `caption`. Память о своём решении сильнее
/// > кода, и особенно у автора.
///
/// Цвета: показатель — акцент, норма — нейтраль. **Янтарь и терракот
/// не используются: они заняты** состояниями дозы и просрочки.
struct LabChartScreen: View {
    var dog: Dog?

    @Environment(AppState.self) private var appState
    @Query private var медикаменты: [Medication]

    @State private var показатель: String?

    /// `начальныйПоказатель` — с какого показателя открыться
    /// (29.10.2026): карточка показателя на «Здоровье» ведёт сразу
    /// на свой график, а не на последний сданный. Без него — как
    /// раньше, первый из `доступныеПоказатели`.
    init(dog: Dog?, начальныйПоказатель: String? = nil) {
        self.dog = dog
        _показатель = State(initialValue: начальныйПоказатель)
    }
    @State private var период: Период = .всё
    @State private var выбраннаяТочка: Точка?
    /// Единица ряда, выбранная человеком. Пусто — единица последнего
    /// анализа (`выбраннаяЕдиница`).
    @State private var единица: String?

    enum Период: String, CaseIterable, Identifiable {
        case полгода = "6 мес", год = "год", всё = "всё"
        var id: String { rawValue }
        /// Подпись — ключом каталога, а не `rawValue` дословно
        /// (29.10.2026): `Text(verbatim:)` показывал «6 мес / год / всё»
        /// по-русски на всех языках, хотя ключи переведены.
        var подпись: LocalizedStringKey {
            switch self {
            case .полгода: "6 мес"
            case .год: "год"
            case .всё: "всё"
            }
        }
        var месяцев: Int? {
            switch self {
            case .полгода: 6
            case .год: 12
            case .всё: nil
            }
        }
    }

    /// Одна точка графика. Собирается здесь, а не во вью: вью не должен
    /// знать, как считается время от дозы.
    struct Точка: Identifiable {
        let id: UUID
        let дата: Date
        let значение: Double
        let единица: String
        let вердикт: LabNorm.Deviation
        let время: LabSampleTiming.Timing
        let норма: LabNorm.Reference
    }

    private var всеАнализы: [LabResult] { dog?.labResults ?? [] }

    /// Показатели, у которых есть хотя бы одно ЧИСЛО. Текстовые
    /// результаты (бактериология) в график не идут — им нечего рисовать,
    /// и это не пропуск, а природа величины.
    private var доступныеПоказатели: [String] { Self.показатели(всеАнализы) }

    /// Тот же список для «Здоровья» — один источник, а не копия:
    /// кандидаты в карточки показателей (`ПоказателиНаЗдоровье`)
    /// обязаны совпадать с тем, что умеет рисовать этот экран.
    /// Свежие первыми; имя — без пробелов по краям.
    static func показатели(_ анализы: [LabResult]) -> [String] {
        var видели = Set<String>()
        var порядок: [String] = []
        for анализ in анализы.sorted(by: { $0.sampledOn > $1.sampledOn }) {
            guard анализ.value != nil else { continue }
            let имя = анализ.indicator.trimmingCharacters(in: .whitespaces)
            guard !имя.isEmpty, !видели.contains(имя) else { continue }
            видели.insert(имя)
            порядок.append(имя)
        }
        return порядок
    }

    /// Выбранный — только из тех, что есть: начальный показатель
    /// мог исчезнуть (строку удалили на другом телефоне), и тогда
    /// экран открывается на первом, а не на пустом графике.
    private var выбранный: String? {
        let есть = доступныеПоказатели
        if let показатель, есть.contains(показатель) { return показатель }
        return есть.first
    }

    /// Единицы выбранного показателя, свежая первой.
    ///
    /// **Ряд делится по единице — решение Виктории 29.10.2026.** Две
    /// лаборатории дают один показатель в разных единицах (нмоль/л
    /// и мкг/дл), и на одной линии `16` и `1,3` читались падением
    /// в двенадцать раз, которого не было. Пересчёт между единицами
    /// приложение не делает: множитель у каждого вещества свой, и
    /// выдуманный коэффициент в медицинском показе хуже двух графиков.
    /// Сравнение «без единицы» с «нмоль/л» тоже не склеивается:
    /// пустая единица — своя группа.
    private var единицыПоказателя: [String] {
        guard let выбранный else { return [] }
        var видели = Set<String>()
        var порядок: [String] = []
        for анализ in всеАнализы.sorted(by: { $0.sampledOn > $1.sampledOn })
        where анализ.value != nil && анализ.indicator.trimmingCharacters(in: .whitespaces) == выбранный {
            let е = Self.ключЕдиницы(анализ.unit)
            if видели.insert(е).inserted { порядок.append(е) }
        }
        return порядок
    }

    /// Единица без пробелов и регистра: «нмоль/л» и «Нмоль/л » — одна.
    static func ключЕдиницы(_ единица: String) -> String {
        единица.trimmingCharacters(in: .whitespaces).lowercased()
    }

    private var выбраннаяЕдиница: String? {
        let есть = единицыПоказателя
        if let единица, есть.contains(единица) { return единица }
        return есть.first
    }

    /// Время забора относительно последней дозы — **из домена**.
    ///
    /// Здесь стояли два своих расчёта: «идёт ли лечение» и «последняя
    /// доза до забора». Второй был дословной копией такого же
    /// в `LabResultEntryFlow`, и копии хватило, чтобы третий экран
    /// (список анализов) часы от дозы не показывал вовсе. С 23.10.2026
    /// счёт один — `DoseScheduler.sampleTiming`, и заодно он берёт час
    /// приёма DST-безопасно; разбор — в голове той функции.
    private func времяЗабора(_ анализ: LabResult) -> LabSampleTiming.Timing {
        DoseScheduler.sampleTiming(sampledAt: анализ.sampledAt,
                                   of: dog, among: медикаменты)
    }

    /// Точки выбранного показателя за выбранный период.
    ///
    /// **Функция, а не вычисляемое свойство, и зовётся ОДИН раз
    /// в `body`** (29.10.2026). Свойством её читали девять мест одной
    /// перерисовки — счёт, полоса, линия, столбики, подпись оси,
    /// заголовок, таблица, проверка сравнимости, пустой случай, —
    /// и каждое заново фильтровало анализы и звало
    /// `DoseScheduler.sampleTiming` на каждую точку. Выбор точки
    /// в таблице платил за девять сборок графика.
    private func собратьТочки() -> [Точка] {
        guard let выбранный else { return [] }
        let порог: Date? = период.месяцев.flatMap {
            Calendar.current.date(byAdding: .month, value: -$0, to: Date())
        }
        let своя = выбраннаяЕдиница
        return всеАнализы
            .filter { $0.indicator.trimmingCharacters(in: .whitespaces) == выбранный }
            .filter { своя == nil || Self.ключЕдиницы($0.unit) == своя }
            .filter { порог == nil || $0.sampledOn >= порог! }
            .compactMap { анализ -> Точка? in
                guard let значение = анализ.value else { return nil }
                return Точка(
                    id: анализ.id,
                    дата: анализ.sampledOn,
                    значение: значение,
                    единица: анализ.unit,
                    вердикт: LabNorm.deviation(value: .measured(значение), from: анализ.reference),
                    время: времяЗабора(анализ),
                    норма: анализ.reference)
            }
            .sorted { $0.дата < $1.дата }
    }

    /// Полоса нормы — только когда она ОДНА у всех точек с нормой.
    ///
    /// До 29.10.2026 полоса бралась у последней точки и прикладывалась
    /// ко всем: норма одной лаборатории ложилась под точки другой,
    /// и точка «в норме» по своему бланку читалась выходом за полосу.
    /// Нормы на бланках разные — полосы нет, и это сказано словом
    /// (`нормыРазные`); своя норма каждой точки — в её карточке.
    /// Нормы нет ни у одной — полосы нет, **и это не повод
    /// не рисовать точки**: так записано у `bandBounds`.
    /// Ярлыки кортежа взяты у `bandBounds` (`low`/`high`), а не свои:
    /// компилятор не приводит `(low:high:)` к `(низ:верх:)`, и переводить
    /// их здесь значило бы заводить второе имя одной величины.
    private func полоса(_ точки: [Точка]) -> (low: Double?, high: Double?)? {
        let нормы = точки.map(\.норма).filter { LabNorm.bandBounds($0) != nil }
        guard let первая = нормы.first, нормы.allSatisfy({ $0 == первая }) else { return nil }
        return LabNorm.bandBounds(первая)
    }

    /// У точек с нормой нормы не совпадают — полосы поэтому нет.
    private func нормыРазные(_ точки: [Точка]) -> Bool {
        let нормы = точки.map(\.норма).filter { LabNorm.bandBounds($0) != nil }
        guard let первая = нормы.first else { return false }
        return !нормы.allSatisfy { $0 == первая }
    }

    var body: some View {
        TGScreen {
            CinemaHeader("График", отступы: false)
            if доступныеПоказатели.isEmpty {
                EmptyStateCard(
                    subject: .health,
                    title: "Рисовать пока нечего",
                    message: "График появится, когда будет хотя бы один анализ с числом. Бактериология и описания в график не идут — им нечего рисовать."
                )
            } else {
                let точки = собратьТочки()
                выборПоказателя
                if точки.count < 2 { нечегоСравнивать(точки) } else { график(точки) }
                таблица(точки)
            }
        }
        .navigationTitle("График")
        .cinemaScreen(экран: .sub("labs"))
        .sheet(item: $выбраннаяТочка) { точка in
            ТочкаКарточка(точка: точка,
                          дозаЧислом: дозаЧислом(на: точка.дата),
                          дозаТекстом: дозаТекстом(на: точка.дата),
                          вес: весНаДату(точка.дата))
        }
    }

    // MARK: Четыре величины словами

    /// Доза в тот день — **ТЕКСТОМ, как её ввёл человек.**
    ///
    /// **Замер 08.10.2026: числа дозы в модели нет вовсе.** `doseText`
    /// это свободная строка («½ таблетки», «0,1 мг»), `dailyUse` — счёт
    /// приёмов, а `MedUnit` знает только `tab`/`ml`/`dose`: массы
    /// (мг, мкг) нет ни в одном поле.
    ///
    /// Макет рисует столбики и подписывает «264 мкг/сут». Этого числа
    /// неоткуда взять, а вывести разбором `doseText` нельзя: между мг
    /// и мкг множитель тысяча, и ошибка в нём даёт не кривой график,
    /// а неверную дозу на медицинском экране.
    ///
    /// > **Разбор свободного текста в медицинское число — изобретение
    /// > числа, а не его чтение.**
    ///
    /// И счёт таблеток вместо массы здесь хуже, чем ничего: врач меняет
    /// силу таблетки с 0,05 на 0,1 мг, счёт остаётся «2» — столбик
    /// не шевельнётся, а доза вырастет вдвое. На графике, который
    /// существует ради вопроса «почему Т4 не растёт при росте дозы»,
    /// это ответ наоборот.
    ///
    /// Поэтому доза здесь — строка человека, а столбиков нет.
    /// Условие, при котором они появятся: у `Medication` заведётся
    /// числовая доза с единицей массы. Это правка ФОРМЫ ХРАНИЛИЩА,
    /// и она отдельным решением.
    private func дозаТекстом(на дата: Date) -> String? {
        let свои = схемы(на: дата)
        let строки = свои.compactMap { лекарство -> String? in
            guard let доза = Fmt.notBlank(лекарство.doseText) else { return nil }
            let имя = Fmt.notBlank(лекарство.name) ?? ""
            let приёмов = лекарство.times.count
            let хвост = приёмов > 1 ? " × \(приёмов)" : ""
            return имя.isEmpty ? доза + хвост : "\(имя): \(доза)\(хвост)"
        }
        return строки.isEmpty ? nil : строки.joined(separator: "\n")
    }

    /// Доза в сутки ЧИСЛОМ, микрограммы — для столбиков.
    ///
    /// Берётся у `Medication.dailyMassMcg`, то есть у модели, а не
    /// считается здесь: масса на единицу формы × расписание — её
    /// решение, и второй копии у него быть не должно.
    ///
    /// `nil` значит «масса не введена», и столбика тогда нет вовсе.
    /// Нулевой столбик был бы утверждением «дозы не было», а это
    /// другое: мы просто не знаем силу таблетки.
    private func дозаЧислом(на дата: Date) -> Double? {
        let суммы = схемы(на: дата)
            .compactMap(\.dailyMassMcg)
        guard !суммы.isEmpty else { return nil }
        return суммы.reduce(0, +)
    }

    /// Схемы, которые шли В ДЕНЬ ЗАБОРА, а не сегодня.
    ///
    /// **Здесь стояло `activeSchedules` — схемы, действующие СЕЙЧАС,** при
    /// том что обе функции выше принимают дату и не пользовались ею.
    /// Мартовская точка показывала сегодняшнюю дозу, все столбики дозы
    /// были одной высоты — на графике, который существует ради вопроса
    /// «изменился ли Т4 после смены дозы» (разбор 28.10.2026).
    ///
    /// Начало — `startedAt` (V8, 28.10.2026), а у схем, где его не назвали,
    /// первая доза в журнале; конец — `cancelledAt`. Схема на паузе без даты отмены не берётся:
    /// когда её поставили на паузу, неизвестно, и это прежнее поведение.
    /// Схема без единой дозы в журнале считается шедшей всегда — так же
    /// отвечал и прежний счёт.
    private func схемы(на дата: Date) -> [Medication] {
        guard let dog else { return [] }
        return медикаменты.filter { лекарство in
            guard лекарство.dog?.persistentModelID == dog.persistentModelID,
                  лекарство.deletedAt == nil else { return false }
            if let конец = лекарство.cancelledAt {
                guard конец > дата else { return false }
            } else if лекарство.isPaused {
                return false
            }
            // Начало — `startedAt` (V8), если его назвали; иначе первая
            // доза журнала, как до V8.
            if let начало = лекарство.startedAt ?? лекарство.doses.map(\.scheduledAt).min(),
               начало > дата {
                return false
            }
            return true
        }
    }


    /// Вес В ТОТ ЖЕ ДЕНЬ, а не ближайший.
    ///
    /// Ближайшее взвешивание не подставляется намеренно: от веса считают
    /// дозу, и вес с другого дня означал бы, что дозу считали от числа,
    /// которого в тот день не было. Нет записи — «—» с причиной,
    /// как в макете.
    private func весНаДату(_ дата: Date) -> Double? {
        guard let dog else { return nil }
        let календарь = Calendar.current
        return dog.weights
            .first { календарь.isDate($0.date, inSameDayAs: дата) }?
            .kg
    }

    // MARK: Выбор

    private var выборПоказателя: some View {
        TGCard {
            if доступныеПоказатели.count > 1 {
                Picker("Показатель", selection: Binding(
                    get: { выбранный ?? "" },
                    set: { показатель = $0 }
                )) {
                    ForEach(доступныеПоказатели, id: \.self) { Text(verbatim: $0).tag($0) }
                }
                .pickerStyle(.menu)
                .frame(minHeight: Token.Size.tapTarget)
                TGDivider()
            }
            // Единиц у показателя несколько — выбор, а не смесь на одной
            // линии (см. `единицыПоказателя`).
            if единицыПоказателя.count > 1 {
                Picker("Единица", selection: Binding(
                    get: { выбраннаяЕдиница ?? "" },
                    set: { единица = $0 }
                )) {
                    ForEach(единицыПоказателя, id: \.self) { е in
                        if е.isEmpty { Text("без единицы").tag(е) } else { Text(verbatim: е).tag(е) }
                    }
                }
                .pickerStyle(.menu)
                .frame(minHeight: Token.Size.tapTarget)
                TGExplainer(text: "Анализы в разных единицах — из разных лабораторий. На одной линии их не сравнить, поэтому каждая единица — свой график.")
                TGDivider()
            }
            Picker("Период", selection: $период) {
                ForEach(Период.allCases) { Text($0.подпись).tag($0) }
            }
            .pickerStyle(.segmented)
        }
    }

    /// **Одна точка — не график.** Так и сказано словами, а не пустой
    /// областью: пустая область читается как «не загрузилось».
    private func нечегоСравнивать(_ точки: [Точка]) -> some View {
        TGCard {
            TGSectionHeader(title: .готовая(выбранный ?? ""))
            Text("Сравнивать пока не с чем")
                .textStyle(AppFont.body)
            TGExplainer(text: точки.isEmpty
                        ? "За выбранный период анализов с числом нет. Поменяй период — или заведи анализ."
                        : "Есть одна точка. График начнёт говорить со второй: он про то, как величина меняется, а не какая она сейчас.")
        }
    }

    // MARK: График

    private func график(_ точки: [Точка]) -> some View {
        // Доза на дату точки — один раз на точку, а не трижды: её
        // спрашивали проверка «есть ли хоть где-то», столбики и подпись
        // оси, и каждый вопрос фильтровал все схемы базы.
        let дозы: [UUID: Double] = Dictionary(
            точки.compactMap { точка in дозаЧислом(на: точка.дата).map { (точка.id, $0) } },
            uniquingKeysWith: { первая, _ in первая })
        return TGCard {
            TGSectionHeader(title: .готовая(заголовокГрафика(точки)))
            Chart {
                // Полоса нормы — ФОНОМ и нейтралью. Рисуется первой,
                // чтобы линия шла поверх неё.
                if let границы = полоса(точки), let низ = границы.low, let верх = границы.high {
                    RectangleMark(
                        yStart: .value("низ нормы", низ),
                        yEnd: .value("верх нормы", верх)
                    )
                    .foregroundStyle(Token.Ink.silhouette.opacity(0.18))
                }

                ForEach(точки) { точка in
                    LineMark(
                        x: .value("дата", точка.дата),
                        y: .value("значение", точка.значение)
                    )
                    .foregroundStyle(Token.Action.primary)

                    PointMark(
                        x: .value("дата", точка.дата),
                        y: .value("значение", точка.значение)
                    )
                    .foregroundStyle(Token.Action.primary)
                    // **Форма маркера — время забора.** Требование
                    // дизайна и ТЗ: точки с разным временем забора
                    // обязаны быть различимы НА ВИД, иначе человек
                    // сравнит несравнимое — в карте это случилось дважды.
                    .symbol(символ(точка.время))
                }
            }
            .chartYAxis {
                AxisMarks(position: .leading)
            }
            .frame(height: 220)
            // Доступность: сам график для VoiceOver — одна фигура,
            // поэтому ниже лежит таблица, и она не дубль, а вторая
            // поверхность той же правды.
            .accessibilityHidden(true)

            if !дозы.isEmpty { столбикиДозы(точки, дозы: дозы) }

            if нормыРазные(точки) {
                TGExplainer(text: "Полосы нормы нет: на бланках этих анализов нормы разные. Норма каждого — в карточке точки.")
            }
            легенда
        }
    }

    /// Столбики дозы — **отдельной панелью под линией, общая ось X.**
    ///
    /// ## Почему не в одном `Chart`, как в макете
    ///
    /// Макет рисует столбики и линию в одной области. У Swift Charts
    /// одна ось Y на область, а величины несоизмеримы:
    ///
    /// ```
    /// Т4    6–50 нмоль/л
    /// доза  264 мкг/сут
    /// ```
    ///
    /// В одной области либо линия прижмётся к нулю и перестанет
    /// читаться, либо дозу придётся **поделить на подобранный
    /// множитель**, чтобы «влезла».
    ///
    /// > **Множитель, подобранный ради вида, — это придуманное число
    /// > в медицинском показе.** Он не виден на кадре, не назван
    /// > на оси и переживёт любого, кто его поставил.
    ///
    /// Две панели с общей осью X дают то же, ради чего макет рисовал
    /// столбики («видно без пояснений: столбики растут, линия
    /// падает»), и у каждой величины остаётся СВОЯ шкала со своей
    /// подписью. Расхождение с макетом названо здесь нарочно:
    /// это решение, а не недоделка.
    ///
    /// Нет массы ни у одной точки — панели нет вовсе, и это честнее
    /// нулевых столбиков: ноль утверждал бы «дозы не было», а мы
    /// не знаем силу таблетки.
    private func столбикиДозы(_ точки: [Точка], дозы: [UUID: Double]) -> some View {
        VStack(alignment: .leading, spacing: Token.Space.s4) {
            Text("Доза в сутки")
                .textStyle(AppFont.caption.color(Token.Ink.secondary))
            Chart {
                ForEach(точки) { точка in
                    if let доза = дозы[точка.id] {
                        BarMark(
                            x: .value("дата", точка.дата),
                            y: .value("доза", доза)
                        )
                        // Нейтраль: доза НЕ акцент — акцент занят
                        // показателем, а янтарь и терракот заняты
                        // состояниями дозы и просрочки.
                        .foregroundStyle(Token.Ink.silhouette.opacity(0.55))
                    }
                }
            }
            .chartYAxis { AxisMarks(position: .leading) }
            .frame(height: 90)
            .accessibilityHidden(true)
            Text(verbatim: подписьОсиДозы(дозы))
                .textStyle(AppFont.caption.color(Token.Ink.secondary))
        }
    }

    /// Единица оси дозы — словом, потому что на оси стоят только числа.
    /// Берётся у `Fmt.doseMass`, единственного места перевода мкг → мг.
    private func подписьОсиДозы(_ дозы: [UUID: Double]) -> String {
        let максимум = дозы.values.max() ?? 0
        let единица = максимум >= 1000
            ? String(localized: "мг/сут")
            : String(localized: "мкг/сут")
        return String(localized: "ось дозы — \(единица); наибольшая \(Fmt.doseMass(максимум))")
    }

    private func заголовокГрафика(_ точки: [Точка]) -> String {
        let единица = точки.compactMap { Fmt.notBlank($0.единица) }.last
        let имя = выбранный ?? ""
        return единица.map { "\(имя), \($0)" } ?? имя
    }

    /// Пустой кружок — «время забора не указано», и это ОТВЕТ,
    /// а не пропуск: `LabSampleTiming` держит этот случай отдельным
    /// видом ровно затем, чтобы он был виден на графике.
    private func символ(_ время: LabSampleTiming.Timing) -> BasicChartSymbolShape {
        switch время {
        case .hoursSinceDose: .circle
        case .noTreatment: .square
        case .unknownDuringTreatment: .cross
        }
    }

    private var легенда: some View {
        VStack(alignment: .leading, spacing: Token.Space.s4) {
            Text("Полоса — норма с бланка. Форма точки — время забора: круг — часы от дозы известны, крест — не записаны, квадрат — лечения в тот день не было.")
                .textStyle(AppFont.caption.color(Token.Ink.secondary))
                .wraps()
        }
    }

    // MARK: Таблица — она же доступность

    /// Таблица, а не подпись у точки.
    ///
    /// **Это не дубль графика, а требование доступности:** на крупных
    /// размерах шрифта и для VoiceOver график не читается вовсе,
    /// и дизайн прямо требует таблицу вместо него. Каждая строка
    /// читается целиком: дата, значение, отклонение СЛОВОМ, часы.
    private func таблица(_ точки: [Точка]) -> some View {
        TGCard(spacing: 0) {
            TGSectionHeader(title: "по датам")
            ForEach(Array(точки.reversed().enumerated()), id: \.element.id) { индекс, точка in
                if индекс > 0 { TGDivider() }
                Button { выбраннаяТочка = точка } label: {
                VStack(alignment: .leading, spacing: Token.Space.s2) {
                    HStack(alignment: .firstTextBaseline) {
                        Text(verbatim: Fmt.shortDay(точка.дата))
                            .textStyle(AppFont.body)
                        Spacer(minLength: Token.Space.s8)
                        Text(verbatim: ЧислоСБланка.показать(точка.значение)
                             + (Fmt.notBlank(точка.единица).map { " \($0)" } ?? ""))
                            .textStyle(AppFont.numeric(15))
                    }
                    // Отклонение СЛОВОМ, из LabNorm — не своё.
                    Text(verbatim: LabNorm.word(точка.вердикт))
                        .textStyle(AppFont.caption.color(Token.Ink.secondary))
                    // Часы ОКРУГЛЁННО: `caption`, не `captionExact`.
                    // `если(_:)` из MedicalRecordCards здесь недоступен —
                    // он приватный, и копировать его ради одной строки
                    // значило бы завести второго хозяина у помощника.
                    if let подпись = LabSampleTiming.caption(точка.время) {
                        Text(verbatim: подпись)
                            .textStyle(AppFont.caption.color(Token.Ink.secondary))
                    }
                }
                .frame(minHeight: Token.Size.tapTarget)
                .frame(maxWidth: .infinity, alignment: .leading)
                .accessibilityElement(children: .combine)
                }
                .buttonStyle(.plain)
            }

            if несравнимыеЕсть(точки) {
                TGExplainer(text: "Точки сняты в разное время после дозы — такие значения рядом не сравнивают без оговорки. Время забора у каждой строки выше.")
            }
        }
    }

    /// Есть ли в наборе пара, которую сравнивать нельзя.
    /// Спрашивается у `LabSampleTiming.comparable`, а не считается здесь:
    /// порог три часа — его решение, и второй копии у него быть не должно.
    private func несравнимыеЕсть(_ точки: [Точка]) -> Bool {
        let времена = точки.map(\.время)
        for левый in времена.indices {
            for правый in времена.indices where правый > левый {
                if !LabSampleTiming.comparable(времена[левый], времена[правый]) { return true }
            }
        }
        return false
    }
}

// MARK: - Карточка точки

/// Четыре величины словами — как в макете `8.4`, «Тап по точке».
///
/// **Открывается тапом по СТРОКЕ таблицы, а не по точке графика.**
/// Разница названа, а не умолчана: в макете тап по точке, и это лучше
/// — но попадание в точку требует сопоставления координат жеста
/// с данными, а строка таблицы тапается надёжно и уже существует как
/// поверхность доступности. Ни одна величина от этого не становится
/// недостижимой; когда появится тап по точке, карточка та же.
///
/// **Нет значения — «—» с причиной, а не пустота.** Пустая клетка
/// читается как «не загрузилось»; «не записан в этот день» — как ответ.
private struct ТочкаКарточка: View {
    let точка: LabChartScreen.Точка
    /// Доза числом, микрограммы — если сила таблетки введена.
    let дозаЧислом: Double?
    /// Доза строкой, как её ввёл человек, — есть всегда, когда есть схема.
    let дозаТекстом: String?
    let вес: Double?

    @Environment(\.dismiss) private var dismiss

    var body: some View {
        TGSheet(title: .готовая(заголовок), closeTitle: "Готово") {
            TGCard(spacing: 0) {
                строка(значок: "testtube.2",
                       подпись: "Показатель",
                       значение: значениеСОтклонением)
                TGDivider()
                // **Числом И текстом, когда есть оба.** Число отвечает
                // «сколько вещества» и годится для сравнения между
                // датами; строка человека отвечает «что он ввёл»
                // и не теряется — в ней бывает «½ таблетки», чего
                // в микрограммах не видно.
                //
                // Нет числа — остаётся строка, и это не пропуск:
                // силу таблетки можно не вводить, и тогда столбиков
                // на графике нет, а строка есть.
                строка(значок: "pills",
                       подпись: "Доза в тот день",
                       значение: дозаСтрокой)
                TGDivider()
                строка(значок: "clock",
                       подпись: "После приёма",
                       значение: LabSampleTiming.caption(точка.время)
                        ?? нет("лечения в тот день не было"))
                TGDivider()
                строка(значок: "scalemass",
                       подпись: "Вес",
                       значение: вес.map { Fmt.weight($0) }
                        ?? нет("не записан в этот день"))
            }

            TGCard {
                TGExplainer(text: "Доза показана так, как её ввёл человек: числа дозы в миллиграммах приложение не хранит и не считает само. Вес берётся за тот же день — не за ближайший.")
            }
        } footer: {
            TGButton(title: "Готово") { dismiss() }
        }
        .presentationDetents([.medium, .large])
    }

    /// Доза для карточки: число, строка, или одно из двух.
    private var дозаСтрокой: String {
        let числом = дозаЧислом.map { Fmt.doseMass($0) + " " + String(localized: "в сутки") }
        switch (числом, дозаТекстом) {
        case let (число?, текст?): return "\(число) · \(текст)"
        case let (число?, nil): return число
        case let (nil, текст?): return текст
        case (nil, nil): return нет("схемы лечения в тот день не было")
        }
    }

    private var заголовок: String {
        let имя = Fmt.notBlank(точка.единица).map { "\(точка.значениеСтрокой) \($0)" }
            ?? точка.значениеСтрокой
        return "\(имя) · \(Fmt.shortDay(точка.дата))"
    }

    /// Значение, отклонение СЛОВОМ и норма — в одной строке,
    /// потому что по отдельности они читаются как три разные новости.
    private var значениеСОтклонением: String {
        var части = [точка.значениеСтрокой + (Fmt.notBlank(точка.единица).map { " \($0)" } ?? "")]
        части.append(LabNorm.word(точка.вердикт))
        if let норма = нормаСтрокой { части.append(норма) }
        return части.joined(separator: " · ")
    }

    /// **Три ключа, по одному на вид предела, а не склейка «норма » + число.**
    ///
    /// Замер 26.10.2026: все три строки шли обычной интерполяцией
    /// и в каталог не попадали **никогда** — `make texts` видит только
    /// `String(localized:)` и литерал `Text("…")`. На экране с языком,
    /// отличным от русского, человек читал **референсный предел анализа
    /// по-русски**, а это утверждение о его собаке, а не подпись к кнопке.
    ///
    /// Порядок слов здесь не декоративный: во французском и казахском
    /// предлог и число встают иначе, чем в «норма до 5,2». Поэтому ключ
    /// у **целой фразы с подстановками** — переставить можно, только
    /// если есть что переставлять.
    ///
    /// > У нас записано «не подставлять там, где подстановка станет
    /// > утверждением человека». Здесь она им уже стала.
    private var нормаСтрокой: String? {
        guard let границы = LabNorm.bandBounds(точка.норма) else { return nil }
        switch (границы.low, границы.high) {
        case let (низ?, верх?):
            return String(localized: "норма \(ЧислоСБланка.показать(низ))–\(ЧислоСБланка.показать(верх))")
        case let (nil, верх?):
            return String(localized: "норма до \(ЧислоСБланка.показать(верх))")
        case let (низ?, nil):
            return String(localized: "норма от \(ЧислоСБланка.показать(низ))")
        case (nil, nil):
            return nil
        }
    }

    /// «—» с причиной. Тире отдельно от причины нарочно: тире говорит
    /// «значения нет», причина — почему, и одно без другого даёт либо
    /// пустоту, либо текст без величины.
    private func нет(_ причина: String) -> String { "— \(причина)" }

    private func строка(значок: String, подпись: LocalizedStringKey, значение: String) -> some View {
        TGListRow(title: подпись,
                  value: .готовая(значение),
                  systemImage: значок,
                  accessory: .none)
    }
}

extension LabChartScreen.Точка {
    /// Показ числа — через `ЧислоСБланка`, не через `Fmt.decimal`:
    /// тот округляет до одного знака, и `16,75` стало бы `16,8`.
    var значениеСтрокой: String { ЧислоСБланка.показать(значение) }
}
