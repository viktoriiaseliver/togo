import Foundation

/// Число с бланка анализа: разбор ввода и показ.
///
/// **Заведено прежде формы, а не после.** `Double("12,9")` возвращает
/// `nil`, и наивный разбор дал бы пустое значение при заполненном поле —
/// то есть «анализ без числа» вместо «12,9». Это молчаливый путь: поле
/// заполнено, кнопка сохранения активна, в базе пусто, и ни один
/// код возврата об этом не скажет.
///
/// Русский человек набирает запятую. На `keyboardType(.decimalPad)`
/// разделитель зависит от раскладки системы, то есть **оба вида придут
/// в одно и то же поле**, и выбирать между ними нельзя.
enum ЧислоСБланка {

    /// Пустая строка → `nil` **намеренно**, и это не то же, что ошибка
    /// разбора. У референса «не введено» значит «норма не указана»,
    /// и `LabNorm.Reference.unknown` скажет именно это, а не «в норме».
    /// Подставлять норму из интернета ТЗ запрещает.
    static func разобрать(_ строка: String) -> Double? {
        let чистое = строка
            .trimmingCharacters(in: .whitespaces)
            .replacingOccurrences(of: ",", with: ".")
            // Неразрывный и узкий неразрывный приезжают вставкой из PDF
            // бланка вместе с числом, и `trimmingCharacters(in: .whitespaces)`
            // их не снимает — для Foundation это не пробелы. Тот же класс,
            // что многобайтная кавычка, приклеившаяся к имени переменной:
            // лишний байт пришёл не из числа, а из соседнего символа.
            .replacingOccurrences(of: "\u{00A0}", with: "")
            .replacingOccurrences(of: "\u{202F}", with: "")
            .replacingOccurrences(of: " ", with: "")
        guard !чистое.isEmpty else { return nil }
        return Double(чистое)
    }

    /// Текст поля ВВОДА из значения модели. Точка остаётся точкой:
    /// человек правит то, что сам набрал, а `.decimalPad` примет оба вида.
    static func текст(_ число: Double?) -> String {
        guard let число else { return "" }
        return число == число.rounded() ? String(Int(число)) : String(число)
    }

    /// ПОКАЗ числа анализа. **Намеренно не `Fmt.decimal`.**
    ///
    /// `Fmt.decimal` округляет до одного знака (`%.1f`) — он писан для
    /// веса и для «4 раза в день», где «4,0 раза» выглядит отчётом.
    /// На бланке это округление меняет медицинское число молча: референс
    /// Т4 в карте Стича менялся трижды — `12,9–51,5`, **`12,87–51,48`**,
    /// `13–51`, — и через `Fmt.decimal` вторая запись стала бы первой.
    ///
    /// > **Форматирование, верное для одной величины, для другой является
    /// > потерей данных.** Округление до одного знака — решение про вес,
    /// > и доехало бы до медицины только потому, что функция оказалась
    /// > под рукой.
    ///
    /// Поэтому знаки сохраняются все, а разделитель ставится на показе:
    /// в хранилище `Double`, человеку — его запись.
    ///
    /// # Разделитель берётся у ЛОКАЛИ, а не прибит запятой
    ///
    /// Замер 26.10.2026: здесь стояло
    /// `replacingOccurrences(of: ".", with: ",")` — запятая **жёстко**,
    /// при любом языке. На английском человек видел `16,75 нмоль/л`
    /// вместо `16.75`, и это **число анализа**, то есть ровно тот
    /// разряд, где у нас красная линия «не подставлять там, где
    /// подстановка станет утверждением человека».
    ///
    /// > **Показ и разбор — РАЗНЫЕ предметы, и сузить второй по локали
    /// > было бы дефектом, которого сейчас нет.** Человек вводит число
    /// > **с бланка**, а бланк напечатан в той стране, где сдавали
    /// > анализ: француз в Ницце получит бланк с запятой и наберёт
    /// > запятую даже при английском интерфейсе. Поэтому `разобрать`
    /// > остаётся терпимым к обоим видам и по локали НЕ сужается.
    /// > Решение менеджера смены, 26.10.2026.
    ///
    /// # Чего эта правка НЕ касается, и различитель написан здесь
    ///
    /// Запрет «округление до одного знака — только для веса» остаётся
    /// в силе целиком. **Два правила про формат одного числа легко
    /// слипаются**, поэтому разводятся прямо здесь:
    ///
    /// ```
    /// РАЗРЯДНОСТЬ  сколько знаков. 16,75 → 16,8 — ПОТЕРЯ ДАННЫХ,
    ///              запрещено, и этой правкой не задето
    /// РАЗДЕЛИТЕЛЬ  запятая или точка. Вид одного и того же числа,
    ///              данных не теряет, обязан идти по локали
    /// ```
    ///
    /// `String(число)` печатает точку независимо от локали — это
    /// описание `Double`, а не формат, — поэтому замена идёт от точки
    /// и ровно одна. У целого разделителя нет вовсе, и `String(Int(…))`
    /// правка не задевает.
    ///
    /// Локаль **параметром с умолчанием**, а не из `Locale.current`
    /// внутри: иначе сторож не смог бы спросить два языка в одном
    /// замере, и приёмка была бы словом, а не числом.
    static func показать(_ число: Double, локаль: Locale = .current) -> String {
        let строка = число == число.rounded() ? String(Int(число)) : String(число)
        let разделитель = локаль.decimalSeparator ?? "."
        return строка.replacingOccurrences(of: ".", with: разделитель)
    }
}
