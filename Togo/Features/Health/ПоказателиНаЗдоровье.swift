import SwiftUI

/// Какие показатели стоят карточками на «Здоровье» — и в каком порядке.
///
/// # Зачем (29.10.2026)
///
/// Просьба Виктории дословно: «мне нужно чтобы я могла настроить какой
/// график показывать там»; раньше в отзыве — «Хочу настраивать какой
/// график и сколько графиков». До этой правки карточка была одна
/// и показывала **последний сданный** анализ: сдали общий анализ
/// крови — и Т4, ради которого экран открывают, уходил с глаз.
///
/// # Хранение — на ЭТОМ телефоне, а не в базе, и это решение
///
/// Выбор лежит в `UserDefaults` под ключом с `Dog.id`, массивом имён
/// показателей. Это **настройка вида**, а не запись дневника: маме
/// интересен вес, хозяйке — Т4, и общий на семью выбор означал бы,
/// что один человек переставляет экран другому. Заодно не трогается
/// форма схемы — новое поле `@Model` потребовало бы новой версии.
///
/// Цена названа: на новом телефоне выбор начинается заново, и он
/// не попадает в архив. Если понадобится переносить — это поле
/// в схеме и отдельное решение, а не правка этого файла.
///
/// # Чего НЕ меняется у тех, кто не настраивал
///
/// Пустой или незаданный выбор — ровно прежнее поведение: одна
/// карточка, последний сданный показатель. Ничего не исчезает
/// у человека, который этот экран никогда не открывал.
///
/// Логика — чистая, на строках: её читает `ПоказателиНаЗдоровьеTests`
/// без базы и без экрана.
nonisolated enum ПоказателиНаЗдоровье {
    /// Имя кандидата «вес». Не совпадает ни с одним названием
    /// показателя с бланка: те вводит человек, и «@» в начале
    /// там не встречается, а пробелы по краям обрезаются.
    static let вес = "@вес"

    /// Больше четырёх карточек не ставим: ниже них — схема лечения
    /// и запас, то есть то, ради чего экран открывают каждый день.
    /// Пятая карточка уводит дозу на второй экран прокрутки.
    static let предел = 4

    static func ключ(собака: UUID) -> String {
        "health.indicatorCards.\(собака.uuidString)"
    }

    /// Кандидаты в карточки: показатели с числом (свежие первыми —
    /// порядок `LabChartScreen.показатели`) и вес, если взвешивания есть.
    static func кандидаты(показатели: [String], естьВес: Bool) -> [String] {
        показатели + (естьВес ? [вес] : [])
    }

    /// Какие карточки рисовать.
    ///
    /// · выбора нет или он пуст — последний сданный показатель, как
    ///   до 29.10.2026 (`показатели.first`);
    /// · показатель, которого больше нет в данных, молча пропускается;
    /// · повтор имени — один раз; больше `предел` — отрезается;
    /// · если из выбора не осталось НИЧЕГО (все исчезли) — снова
    ///   прежнее поведение, а не пустое место на экране.
    static func карточки(выбор: [String]?, показатели: [String], естьВес: Bool) -> [String] {
        let доступные = Set(кандидаты(показатели: показатели, естьВес: естьВес))
        var видели = Set<String>()
        let живые = (выбор ?? []).filter { доступные.contains($0) && видели.insert($0).inserted }
        guard !живые.isEmpty else { return показатели.first.map { [$0] } ?? [] }
        return Array(живые.prefix(предел))
    }

    /// Включить или выключить кандидата. Сверх `предел` не добавляет —
    /// выбор возвращается как был, и шторка говорит почему.
    static func переключить(_ имя: String, в выбор: [String]) -> [String] {
        if выбор.contains(имя) { return выбор.filter { $0 != имя } }
        guard выбор.count < предел else { return выбор }
        return выбор + [имя]
    }

    /// Сдвинуть на одну позицию: `-1` — выше, `+1` — ниже.
    /// За край не сдвигается.
    static func сдвинуть(_ имя: String, на шаг: Int, в выбор: [String]) -> [String] {
        guard let откуда = выбор.firstIndex(of: имя) else { return выбор }
        let куда = откуда + шаг
        guard выбор.indices.contains(куда) else { return выбор }
        var новый = выбор
        новый.swapAt(откуда, куда)
        return новый
    }

    /// Высоты столбиков — доля от наибольшего в ряду.
    ///
    /// **Это и есть починка «пустых столбиков» ТТГ.** `КиноСтолбики`
    /// делит на `max(наибольшее, 1)`: у ряда ТТГ 0,1–0,4 потолок
    /// становился единицей, и все столбики падали на минимальную
    /// высоту — ряд выглядел пустым, как будто значений нет. Доля
    /// от своего наибольшего возвращает ряду форму, а ноль остаётся
    /// нулём: шкала от нуля, не от наименьшего, — иначе 4,0 и 4,2
    /// выглядели бы как «вдвое».
    ///
    /// Пропусков в ряду нет по устройству: ряд собирается только
    /// из анализов с ЧИСЛОМ (`compactMap(\.value)`), предел прибора
    /// («<0,03») и текст в него не входят и нулём не рисуются.
    static func доли(_ значения: [Double]) -> [Double] {
        guard let потолок = значения.max(), потолок > 0, потолок.isFinite else { return значения }
        return значения.map { max(0, $0) / потолок }
    }

    // MARK: Хранение

    /// `nil` — человек не настраивал (или вернул «как было»).
    static func прочитать(собака: UUID, хранилище: UserDefaults = .standard) -> [String]? {
        хранилище.stringArray(forKey: ключ(собака: собака))
    }

    /// Пустой выбор хранится как отсутствие: «ничего не выбрано»
    /// и «не настраивал» значат одно — прежнее поведение.
    static func записать(_ выбор: [String]?, собака: UUID, хранилище: UserDefaults = .standard) {
        if let выбор, !выбор.isEmpty {
            хранилище.set(выбор, forKey: ключ(собака: собака))
        } else {
            хранилище.removeObject(forKey: ключ(собака: собака))
        }
    }
}

/// Шторка «Какие графики показывать».
///
/// Право — то же, что у самой вкладки (`.seeMedical`): настройка вида
/// ничего не пишет в базу, и закрывать её правом лечения значило бы
/// запретить маме поставить себе вес на первое место.
///
/// Порядок — стрелками, а не перетаскиванием: `onMove` живёт только
/// в `List`, а `List` внутри прокрутки шторки не меряется. Стрелки
/// к тому же доступны озвучке без режима правки.
struct НастройкаПоказателейSheet: View {
    /// Все кандидаты, свежие первыми, вес — последним.
    let кандидаты: [String]
    /// С чего начинается шторка — то, что СЕЙЧАС на экране.
    let начальный: [String]
    /// Выбор сохранён — `nil` значит «как было».
    var сохранить: ([String]?) -> Void

    @Environment(\.dismiss) private var dismiss
    @State private var выбор: [String] = []
    @State private var загружено = false

    private var остальные: [String] { кандидаты.filter { !выбор.contains($0) } }
    private var полно: Bool { выбор.count >= ПоказателиНаЗдоровье.предел }

    var body: some View {
        TGSheet(title: "Какие графики показывать",
                subtitle: .готовая(String(localized: "выбрано \(выбор.count) из \(ПоказателиНаЗдоровье.предел)")),
                closeTitle: "Отмена") {
            if выбор.isEmpty {
                TGCard {
                    TGExplainer(text: "Ничего не выбрано — на «Здоровье» останется последний сданный анализ.")
                }
            } else {
                TGCard(spacing: 0) {
                    TGSectionHeader(title: "на экране, по порядку")
                    ForEach(Array(выбор.enumerated()), id: \.element) { номер, имя in
                        if номер > 0 { TGDivider() }
                        строкаВыбранного(имя, номер: номер)
                    }
                }
            }
            if !остальные.isEmpty {
                TGCard(spacing: 0) {
                    TGSectionHeader(title: "можно добавить")
                    ForEach(Array(остальные.enumerated()), id: \.element) { номер, имя in
                        if номер > 0 { TGDivider() }
                        Toggle(isOn: Binding(
                            get: { false },
                            set: { if $0 { выбор = ПоказателиНаЗдоровье.переключить(имя, в: выбор) } }
                        )) {
                            подпись(имя)
                        }
                        .frame(minHeight: Token.Size.tapTarget)
                        .disabled(полно)
                    }
                }
                if полно {
                    // Выключенный орган — только со словом рядом
                    // (правило дизайна круга 5).
                    TGExplainer(text: "Больше четырёх не ставим: карточки встали бы длинной лентой, и схема лечения ушла бы под них. Убери одну — освободится место.")
                }
            }
            TGExplainer(text: "Настройка вида — только на этом телефоне. В дневник она не пишет, и у других в семье экран не меняется.")
        } footer: {
            VStack(spacing: Token.Space.s8) {
                TGButton(title: "Готово") {
                    сохранить(выбор.isEmpty ? nil : выбор)
                    dismiss()
                }
                TGButton(title: "Как было: последний сданный анализ",
                         variant: .secondary, size: .medium) {
                    сохранить(nil)
                    dismiss()
                }
            }
        }
        .presentationDetents([.medium, .large])
        .task {
            guard !загружено else { return }
            загружено = true
            выбор = начальный
        }
    }

    /// Строка выбранного: выключатель и стрелки порядка.
    ///
    /// Имя — `.wraps()`: «Т4 общий» на 320 точках рядом с тремя
    /// органами по 44 переносится, а не режется.
    private func строкаВыбранного(_ имя: String, номер: Int) -> some View {
        HStack(spacing: Token.Space.s4) {
            Toggle(isOn: Binding(
                get: { true },
                set: { if !$0 { выбор = ПоказателиНаЗдоровье.переключить(имя, в: выбор) } }
            )) {
                подпись(имя)
            }
            стрелка("chevron.up", подсказка: "Выше", доступна: номер > 0) {
                выбор = ПоказателиНаЗдоровье.сдвинуть(имя, на: -1, в: выбор)
            }
            стрелка("chevron.down", подсказка: "Ниже", доступна: номер < выбор.count - 1) {
                выбор = ПоказателиНаЗдоровье.сдвинуть(имя, на: 1, в: выбор)
            }
        }
        .frame(minHeight: Token.Size.tapTarget)
    }

    private func стрелка(_ значок: String, подсказка: LocalizedStringKey, доступна: Bool,
                         действие: @escaping () -> Void) -> some View {
        Button(action: действие) {
            Image(systemName: значок)
                .foregroundStyle(доступна ? Token.Action.primary : Token.Ink.secondary)
                .frame(minWidth: Token.Size.tapTarget, minHeight: Token.Size.tapTarget)
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .disabled(!доступна)
        .accessibilityLabel(подсказка)
    }

    /// Вес — словом каталога; показатель — как на бланке, дословно.
    @ViewBuilder
    private func подпись(_ имя: String) -> some View {
        if имя == ПоказателиНаЗдоровье.вес {
            Text("Вес").textStyle(AppFont.body).wraps()
        } else {
            Text(verbatim: имя).textStyle(AppFont.body).wraps()
        }
    }
}
