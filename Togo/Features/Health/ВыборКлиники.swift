import SwiftUI
import SwiftData

// # Пикер организации из справочника — одно место вместо пяти (05.11.2026)
//
// Текст объяснителя «Справочник пуст…» лежал **байт в байт** в пяти
// местах: `LabResultScreens.swift` (дважды), `PrescriptionScreens.swift`,
// `VisitDiagnosisScreens.swift` и `Editors.swift`. Пять копий одного
// обещания человеку — это пять мест, где его можно поправить
// по отдельности, и они уже разошлись.
//
// ## Что именно расходилось, и почему сводить это пришлось с замером
//
// Копии разъехались по **сохранению уже записанного значения**, и три
// формы жили одновременно:
//
// ```
// место                                     форма      «записанное до справочника»
// ──────────────────────────────────────────────────────────────────────────────
// LabResultRowEditor        (:1102)         String      ЕСТЬ — своёЗначение строкой
// VetVisitEditor            (:185)          Clinic?     ЕСТЬ — выбранная слита в список
// PrescriptionEditor        (:281)          Clinic?     ЕСТЬ — то же
// CareTaskEditorSheet       (:777)          Clinic?     ЕСТЬ — то же
// LabResultEntryFlow        (:659)          String      НЕТ НИ ОДНОЙ
// ```
//
// Свести пять копий к той, у которой ветки нет, значило бы **потерять
// защиту от молчаливой порчи данных**: `LabResultRowEditor` правит
// существующий бланк, и его `лаборатория` читается из
// `result.laboratory` (`:1253`), а пишется обратно (`:1303`). Пропади
// строка из списка — пикер показал бы «не указана» при заполненном
// поле, человек сохранил бы форму не трогая его, и правка одного
// показателя переписала бы **ключ группировки всего бланка**.
//
// Замер, который решил, какая ветка правильная (05.11.2026):
//
// ```
// LabResultEntryFlow.лаборатория   объявлено :501, читается :904.
//                                  ПРИСВАИВАНИЙ ИЗ ЗАПИСИ НОЛЬ —
//                                  это поток СОЗДАНИЯ, у него нет
//                                  «уже записанного»
// LabResultRowEditor.лаборатория   объявлено :974, ЧИТАЕТСЯ ИЗ
//                                  result.laboratory :1253,
//                                  пишется обратно :1303 — правка
// ```
//
// > **Расхождение было не дефектом, а разной работой двух форм** — и
// > ровно поэтому его нельзя было сводить «по большинству». У потока
// > создания ветка не нужна, у правки обязательна, и единственная
// > копия без ветки оказалась именно той, где она не нужна.
//
// Поэтому ветка уехала **внутрь компонента**, а не продублирована
// по вызовам: в потоке создания она инертна по устройству (поле пусто
// → `своё` равно `nil`), а забыть её на новом шестом экране больше
// нечем. Механизм, который нельзя не позвать, дешевле правила, которое
// надо помнить.
//
// ## Чего компонент НЕ берёт, и это решение
//
// **Фильтр и порядок остаются у вызова.** `Clinic.isLab`
// несимметричен — он запрещает приём в лаборатории и НЕ запрещает
// забор в клинике, — то есть у «кто принимал» и «где сдавали» списки
// обязаны быть разными. Это измеренное решение 26.10.2026, и его
// сторожит `ДорогаКСправочникуКлиникTests.пикерыФильтруютНесимметрично`
// отдельно по трём файлам. Унеси фильтр сюда — и один общий список
// дал бы верный ответ одному вопросу из двух, молча.
//
// Компонент отвечает за **показ**: подпись, строку «не указана»,
// сохранение записанного и объяснение пустого справочника. Чем
// наполнен список — спрашивает тот, кто знает свой вопрос.

/// Объяснение пустого справочника — **один литерал на оба пикера**.
///
/// Отдельным типом, а не строкой в каждом из двух `body`: две копии
/// в одном файле расходятся так же молча, как пять копий в четырёх.
/// Ровно из-за этого и затевалась сводка — не хватало бы иронии
/// оставить её на дне.
private struct ПустойСправочник: View {
    var body: some View {
        TGExplainer(text: "Справочник пуст. Клиники и лаборатории заводятся в «Здоровье» → «Клиники и лаборатории» — оттуда они и попадают в этот выбор.")
    }
}

/// Выбор организации, хранимой **ссылкой** (`Clinic?`).
///
/// Выбранная обязана остаться в `доступные` на стороне вызова, даже
/// если она лаборатория или уже надгробие: иначе фильтр показа станет
/// молчаливым удалением данных. Разбор — у `доступные` каждого вызова.
struct ВыборКлиники: View {
    let подпись: LocalizedStringKey
    @Binding var выбор: Clinic?
    let доступные: [Clinic]

    var body: some View {
        Picker(подпись, selection: $выбор) {
            Text("не указана").tag(nil as Clinic?)
            ForEach(доступные) { Text(verbatim: $0.name).tag($0 as Clinic?) }
        }
        .pickerStyle(.menu)
        .frame(minHeight: Token.Size.tapTarget)
        if доступные.isEmpty { ПустойСправочник() }
    }
}

/// Выбор организации, хранимой **именем** (`String`).
///
/// Так хранят лабораторию бланки анализов. Значение, которого
/// в справочнике нет, остаётся выбранным своей строкой — см. разбор
/// в голове файла: бланки, заведённые до справочника, несут
/// лабораторию текстом, и она ключ группировки.
struct ВыборКлиникиПоИмени: View {
    let подпись: LocalizedStringKey
    @Binding var выбор: String
    let доступные: [Clinic]

    /// Записанное, чего в справочнике нет. `nil` — значит выбранное
    /// и так есть в списке либо поле пусто (поток создания).
    private var своёЗначение: String? {
        let имя = выбор.trimmingCharacters(in: .whitespaces)
        guard !имя.isEmpty else { return nil }
        return доступные.contains { $0.name == имя } ? nil : имя
    }

    var body: some View {
        Picker(подпись, selection: $выбор) {
            Text("не указана").tag("")
            if let своё = своёЗначение {
                // Записанное до справочника. Подпись не врёт,
                // что это выбор из списка.
                Text(verbatim: своё).tag(своё)
            }
            ForEach(доступные) { Text(verbatim: $0.name).tag($0.name) }
        }
        .pickerStyle(.menu)
        .frame(minHeight: Token.Size.tapTarget)
        if доступные.isEmpty { ПустойСправочник() }
    }
}
