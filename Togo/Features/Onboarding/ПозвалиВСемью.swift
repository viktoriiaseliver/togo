import SwiftUI

/// Вход ветки «Меня позвали в семью» — первый экран человека, которого
/// позвали в чужой дневник.
///
/// # Зачем он существует
///
/// До 14.10.2026 этой ветки в коде не было вовсе. Приглашённый попадал
/// в онбординг владельца, заводил **свою** собаку и получал чужой
/// дневник поверх своего — а заодно карточку `role: .owner`
/// и запомненный `myMemberID`, из-за которых ходил по чужому дневнику
/// с полными правами (закрыто потолком, `FamilyResolver.потолокГостя`).
///
/// Решение Виктории, принятое рисунком в макете: **«своей собаки
/// не создаём»**. Этот экран — место, где человек говорит, что он
/// не заводит дневник, а присоединяется к чужому.
///
/// # ЭКРАН БЫЛ УКАЗАТЕЛЕМ, И ЭТО ПОЧИНЕНО 26.10.2026
///
/// Здесь стояла строка `TGIconRow(symbol: "keyboard", title: "Адрес
/// вводить негде")` и доккомментарий, объяснявший, почему поля
/// не будет никогда. Объяснение держалось на верном замере и неверном
/// выводе:
///
/// ```
/// ИЗМЕРЕНО      `togo.app/j/7KQ2-VX` из макета не существует —
///               своего домена с редиректом у нас нет
/// ВЫВЕДЕНО      «вводить негде», и строка сказала это человеку
/// НЕ ПРОВЕРЕНО  CloudKit выдаёт НАСТОЯЩИЙ адрес на `icloud.com`,
///               и приём по нему — одна строка контейнера
/// ```
///
/// > **Отвергнут был вид адреса, а снят — вход.** Запрет, исполненный
/// > снятием входа, снаружи неотличим от сломанной дороги, и отличает
/// > их один вопрос: а что нарисовано ВМЕСТО? Вместо поля стояла
/// > строка о том, что поля нет.
///
/// Поле вставки теперь есть, и оно закрывает единственное состояние,
/// которое не закрывал приём по ссылке: **человек открыл Togo раньше,
/// чем нажал ссылку.** Это состояние названо в `AppRoot`
/// (`TogoApp.swift:531`, «Чего это НЕ чинит») — названо верно
/// и восемь суток читалось как «и чинить нечем».
///
/// Разбор вставленного — `ПриёмПоСсылке`, приём — `ShareAcceptance
/// .принять(ссылку:)`, исход — `ShareAcceptanceOutcome`. Своих текстов
/// отказа экран не пишет: пять уже есть, и у каждого свой совет.
struct ПозвалиВСемью: View {
    var onBack: () -> Void

    /// Что человек вставил. Пустая строка — он ещё не начал, и красного
    /// текста под полем быть не должно.
    @State private var адрес = ""
    @State private var работаем = false
    /// Чем кончился приём. `nil` — ещё не пробовали.
    @State private var исход: ShareAcceptanceOutcome?

    private var разбор: ПриёмПоСсылке.Разбор { ПриёмПоСсылке.разобрать(адрес) }

    var body: some View {
        TGScreen {
            VStack(alignment: .leading, spacing: Token.Space.s6) {
                Text("Тебя позвали").textStyle(AppFont.display)
                Text("в чужой дневник").textStyle(AppFont.display.color(Token.Action.primary))
            }
            .padding(.top, Token.Space.s32)

            Text("Свою собаку заводить не нужно — она появится сама, вместе с записями того, кто позвал.")
                .textStyle(AppFont.body.color(Token.Ink.secondary))

            TGCard {
                TGSectionHeader(title: "что сделать")
                TGIconRow(symbol: "link",
                          title: "Открой ссылку из сообщения",
                          detail: "Её присылают из Togo. Нажми прямо в переписке — телефон сам откроет приглашение и спросит, принимаешь ли ты его.")
                TGIconRow(symbol: "icloud",
                          title: "Нужен iCloud на телефоне",
                          detail: "Дневник ездит через твой личный iCloud, а не через чужой сервер. Аккаунт в Togo не нужен.")
            }
            .padding(.top, Token.Space.s8)

            ссылкой

            // Отказ назван здесь, а не после нажатия: человек, которому
            // ссылка не пришла, иначе упрётся в экран без выхода.
            TGExplainer(text: "Ссылки нет? Попроси прислать её заново — приглашение отправляют из Togo: «Семья» → «Позвать в дневник».")
        } bottom: {
            TGButton(title: "Понятно", action: onBack)
            Text("Пока ссылку не открыли, дневник остаётся только на этом телефоне.")
                .textStyle(AppFont.micro)
                .frame(maxWidth: .infinity)
        }
        .navigationTitle("Меня позвали")
        .navigationBarTitleDisplayMode(.inline)
    }

    /// Вторая дорога — для того, кто уже стоит в приложении.
    ///
    /// **Карточкой в потоке, а не главной кнопкой внизу, и это выбор.**
    /// Нажать ссылку в переписке проще, и у большинства она открыта
    /// в другом окне. Поле нужно тому, у кого первая дорога не сработала
    /// — он уже здесь и ищет, куда вставить. Поставь его главным — и
    /// всем остальным придётся читать про буфер обмена вместо того,
    /// чтобы нажать ссылку.
    @ViewBuilder
    private var ссылкой: some View {
        TGCard {
            TGSectionHeader(title: "Вставь ссылку или код приглашения")
            TGExplainer(text: "Если нажать ссылку в переписке не получается — скопируй её и вставь сюда. Это тот же самый адрес, он начинается на icloud.com.")

            // Подсказка в поле — `Text(verbatim:)`, а подпись — ключ
            // каталога.
            //
            // Это не вкус: `TextField("icloud.com/share/…", text:)`
            // положило бы **адрес** ключом в каталог строк, и его
            // уехало бы переводить на четыре языка. Тот же случай уже
            // оплачен рядом — `TextField("Стич", …)` в `OnboardingSteps`
            // (`:200`). Подпись при этом нужна: без неё озвучка читает
            // поле как «текстовое поле» и не говорит, чего в него ждут.
            TGTile {
                TextField(text: $адрес,
                          prompt: Text(verbatim: "icloud.com/share/…")) {
                    Text("Ссылка приглашения")
                }
                .textContentType(.URL)
                .keyboardType(.URL)
                .textInputAutocapitalization(.never)
                .autocorrectionDisabled()
                .disabled(работаем)
                .padding(.horizontal, Token.Space.s12)
            }

            // Разбор говорит ДО нажатия, когда может сказать.
            //
            // Вид адреса проверяется у нас, существование — в облаке,
            // и путать эти два ответа нельзя: отправь мы в CloudKit
            // ссылку из «Фото», он ответил бы `unknownItem`, то есть
            // «дело не в твоих настройках» — ложь в самую дорогую
            // сторону. Разбор — в голове `ПриёмПоСсылке`.
            if let подсказка = разбор.текст {
                Text(.готовая(подсказка))
                    .textStyle(AppFont.caption.color(Token.Status.overdueText))
                    .wraps()
            }

            // Правило дизайна круга 5, п. 1: выключенная кнопка
            // допустима только если рядом словом сказано, чего
            // не хватает. При пустом поле не хватает ссылки, и это
            // сказано строкой выше кнопки — по образцу `InviteSheet`.
            if разбор == .пусто {
                Text("Вставь ссылку — её присылают из Togo вместе с приглашением")
                    .textStyle(AppFont.caption.color(Token.Status.overdueText))
                    .wraps()
            }

            TGButton(title: работаем ? "Проверяю…" : "Войти по ссылке",
                     systemImage: "arrow.right.circle",
                     isEnabled: !работаем && разбор.годная != nil) {
                Task { await войти() }
            }

            if let исход {
                TGBanner(tone: исход.принято_ли ? .done : .alarm,
                         title: исход.принято_ли ? "Готово" : "Не получилось",
                         subtitle: .готовая(исход.текст),
                         systemImage: исход.принято_ли
                             ? "checkmark.circle" : "exclamationmark.triangle")
            }
        }
    }

    /// Нажали «Войти по ссылке».
    ///
    /// **Исход показывается здесь, а не только плашкой поверх
    /// приложения.** Плашка живёт пять секунд и заведена для холодного
    /// старта по ссылке, когда повторить её нечем; здесь человек стоит
    /// на экране с полем, и ответ обязан висеть рядом с тем, что его
    /// вызвало, пока он не поправит.
    ///
    /// # Плашка исхода работает на ОТКАЗ, а не на успех
    ///
    /// Первая редакция этого комментария говорила «экран сам
    /// не закрывается на успехе, и „Понятно“ выводит в дневник». **Это
    /// ложно, и ложно было в момент записи** — я прочитал свой же
    /// соседний коммит и не сложил два звена:
    ///
    /// ```
    /// 1. `принять(…)` внутри себя зовёт `объявить`, то есть ПОСТИТ
    ///    `.familyShareAccepted` — ДО того, как вернёт исход
    /// 2. `AppRoot` на это уведомление перечитывает ворота, видит
    ///    `SharedZoneOwner.isGuest` и показывает `RootView()`
    /// 3. `OnboardingFlow` с этим листом уносит вместе с веткой,
    ///    и `исход = ответ` ниже присваивается тому, чего уже нет
    /// ```
    ///
    /// То есть на успехе человека уносит в дневник **не кнопка, а
    /// ворота**, и сказать ему «готово, ты в дневнике — Виктория»
    /// успевает существующий тост `TogoApp` по тому же уведомлению.
    /// Место для этих слов есть, и оно правильнее: тост лежит поверх
    /// дневника, который он пришёл смотреть.
    ///
    /// Плашка остаётся и нужна **для отказа**: отказ ворот не открывает
    /// (`isGuest` остаётся ложным, и `AppRoot` не перечитывается),
    /// лист стоит на месте, и ответ висит рядом с полем, пока человек
    /// не поправит. На успехе она безвредна — её просто не увидят.
    ///
    /// > **Прогоном это не проверено:** симулятор 26.10 занят другой
    /// > сессией. Написано по чтению кода двух файлов, и если порядок
    /// > окажется другим, неверна будет ЭТА запись, а не поведение:
    /// > оба исхода человеку сказаны, вопрос только в том, которым
    /// > из двух мест.
    private func войти() async {
        guard let ссылка = разбор.годная else { return }
        работаем = true
        исход = nil
        defer { работаем = false }

        let ответ = await ShareAcceptance.принять(ссылку: ссылка)
        исход = ответ
        if ответ.принято_ли {
            Haptics.success()
            UsageLog.note(.record, "acceptByLink", on: .family)
        } else {
            Haptics.warning()
            UsageLog.note(.record, "acceptByLink:failed", on: .family, outcome: .failed)
        }
    }
}
