import SwiftUI

/// Вход ветки «Меня позвали в семью» — первый экран человека, которого
/// позвали в чужой дневник.
///
/// # Зачем он существует
///
/// До 14.10.2026 этой ветки в коде не было вовсе. Приглашённый попадал
/// в онбординг владельца, заводил **свою** собаку и получал чужой
/// дневник поверх своего — а заодно карточку `role: .owner`
/// и запомненный `myMemberID`, из-за которых ходил по чужому дневнику
/// с полными правами (закрыто потолком, `FamilyResolver.потолокГостя`).
///
/// Решение Виктории, принятое рисунком в макете: **«своей собаки
/// не создаём»**. Этот экран — место, где человек говорит, что он
/// не заводит дневник, а присоединяется к чужому.
///
/// # Чего этот экран НЕ делает, и это названо заранее
///
/// Он **не принимает ссылку**. Приём приглашения сегодня идёт одной
/// дорогой — человек открывает ссылку из сообщения, iOS показывает
/// системную шторку и зовёт `windowScene(_:userDidAcceptCloudKitShareWith:)`
/// (`TogoApp.swift:42`). Поля для вставки адреса в коде нет, и завести
/// его нельзя «просто так»: приём по URL — это
/// `CKFetchShareMetadataOperation`, которого в проекте ноль вхождений
/// (замер 14.10.2026).
///
/// В макете экран 12 просит вставить `togo.app/j/7KQ2-VX` — **такой
/// ссылки не бывает**: CloudKit выдаёт адрес на `icloud.com`, а короткий
/// вид это свой домен с редиректом, то есть инфраструктура, которой нет.
/// Нарисовать поле с такой подсказкой значило бы отправить человека
/// вводить то, что заведомо не примут, и отказ был бы **наш**, а не его.
///
/// Поэтому экран честно говорит, что делать **сегодня**, и ждёт решения
/// Виктории по трём исходам (принимать адрес iCloud / заводить короткую
/// ссылку / оставить только шторку). Когда исход назван — сюда приедет
/// либо поле, либо ничего, и текст не придётся переписывать.
struct ПозвалиВСемью: View {
    var onBack: () -> Void

    var body: some View {
        TGScreen {
            VStack(alignment: .leading, spacing: Token.Space.s6) {
                Text("Тебя позвали").textStyle(AppFont.display)
                Text("в чужой дневник").textStyle(AppFont.display.color(Token.Action.primary))
            }
            .padding(.top, Token.Space.s32)

            Text("Свою собаку заводить не нужно — она появится сама, вместе с записями того, кто позвал.")
                .textStyle(AppFont.body.color(Token.Ink.secondary))

            TGCard {
                TGSectionHeader(title: "что сделать")
                TGIconRow(symbol: "link",
                          title: "Открой ссылку из сообщения",
                          detail: "Её присылают из Togo. Нажми прямо в переписке — телефон сам откроет приглашение и спросит, принимаешь ли ты его.")
                TGIconRow(symbol: "icloud",
                          title: "Нужен iCloud на телефоне",
                          detail: "Дневник ездит через твой личный iCloud, а не через чужой сервер. Аккаунт в Togo не нужен.")
            }
            .padding(.top, Token.Space.s8)

            // Отказ назван здесь, а не после нажатия: человек, которому
            // ссылка не пришла, иначе упрётся в экран без выхода.
            TGExplainer(text: "Ссылки нет? Попроси прислать её заново — приглашение отправляют из Togo: «Семья» → «Позвать в дневник».")
        } bottom: {
            TGButton(title: "Понятно", action: onBack)
            Text("Пока ссылку не открыли, дневник остаётся только на этом телефоне.")
                .textStyle(AppFont.micro)
                .frame(maxWidth: .infinity)
        }
        .navigationTitle("Меня позвали")
        .navigationBarTitleDisplayMode(.inline)
    }
}
