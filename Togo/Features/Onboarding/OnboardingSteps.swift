/// Поток слов: вью раскладываются как слова в абзаце — подряд, слева
/// направо, с переносом по месту.
///
/// Нужна ровно затем, зачем в прототипе стоит `<p>`: подчёркнутое
/// слово обязано стоять **внутри** предложения, а не отдельной
/// строкой. `HStack` переноса не умеет вовсе, `VStack` разрывает
/// фразу всегда — третьего в SwiftUI до `Layout` не было.
///
/// **Приватна файлу и остаётся приватной, пока читатель один.**
/// Второй абзац с нажимаемыми словами — повод вынести её
/// в `DesignSystem/Components`; этот — нет.
///
/// Высота строки — максимум высот её кусков. Значит цель касания 44
/// (`Token.Size.tapTarget`) у подчёркнутого слова раздвигает строки
/// абзаца: при кегле 20 текст занимает ~24 pt, а строка встаёт 44.
/// Цена названа у `ModeStep`, а не спрятана.
private struct ПотокСлов: Layout {
    var межсловный: CGFloat
    var междустрочный: CGFloat

    private struct Кусок {
        let индекс: Int
        let размер: CGSize
    }

    private struct Строка {
        var куски: [Кусок] = []
        var ширина: CGFloat = 0
        var высота: CGFloat = 0
    }

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews,
                      cache: inout ()) -> CGSize {
        // `proposal.width` берётся напрямую, а не через
        // `replacingUnspecifiedDimensions()`: последний подставляет
        // 10×10, то есть абзац бы схлопнулся в столбец по слову.
        let доступно = proposal.width ?? .infinity
        let строки = разложить(ширина: доступно, subviews: subviews)
        let высота = строки.reduce(CGFloat.zero) { $0 + $1.высота }
            + междустрочный * CGFloat(max(0, строки.count - 1))
        let занято = строки.map(\.ширина).max() ?? 0
        return CGSize(width: доступно.isFinite ? доступно : занято, height: высота)
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize,
                       subviews: Subviews, cache: inout ()) {
        var верх = bounds.minY
        for строка in разложить(ширина: bounds.width, subviews: subviews) {
            var слева = bounds.minX
            for кусок in строка.куски {
                subviews[кусок.индекс].place(
                    at: CGPoint(x: слева,
                                y: верх + (строка.высота - кусок.размер.height) / 2),
                    proposal: ProposedViewSize(кусок.размер))
                слева += кусок.размер.width + межсловный
            }
            верх += строка.высота + междустрочный
        }
    }

    /// Разбивка на строки.
    ///
    /// Кусок, который не влез бы даже в пустую строку (длинная кличка,
    /// крупный кегль), меряется повторно по ширине абзаца и переносится
    /// внутри себя сам — иначе он уехал бы за край, а не обрезался:
    /// `Layout` ничего не кадрирует.
    private func разложить(ширина: CGFloat, subviews: Subviews) -> [Строка] {
        var строки: [Строка] = []
        var текущая = Строка()
        for индекс in subviews.indices {
            var размер = subviews[индекс].sizeThatFits(.unspecified)
            if размер.width > ширина {
                размер = subviews[индекс].sizeThatFits(
                    ProposedViewSize(width: ширина, height: nil))
            }
            let сКуском = текущая.куски.isEmpty
                ? размер.width
                : текущая.ширина + межсловный + размер.width
            if !текущая.куски.isEmpty, сКуском > ширина {
                строки.append(текущая)
                текущая = Строка(куски: [Кусок(индекс: индекс, размер: размер)],
                                 ширина: размер.width,
                                 высота: размер.height)
            } else {
                текущая.куски.append(Кусок(индекс: индекс, размер: размер))
                текущая.ширина = сКуском
                текущая.высота = max(текущая.высота, размер.height)
            }
        }
        if !текущая.куски.isEmpty { строки.append(текущая) }
        return строки
    }
}

/// Режим одной фразой: сколько ест, когда встаёт, пьёт ли лекарства.
///
/// # Эталон — прототип, и он прочитан из файла, а не по памяти
///
/// `Дизайн/редизайн-ios28/prototypes/Togo-RU.dc.html`, ветка
/// `onb.isMode`:
///
/// ```html
/// <p style="font-size:30px;font-weight:700;line-height:1.25">{{ onb.name }}
///   ест <u>{{ onb.meals }}</u>, ходит <u>{{ onb.place }}</u>,
///   лекарства <u>{{ onb.meds }}</u>.</p>
/// <span class="t2" style="font-size:15px">Нажми подчёркнутое, чтобы поменять.</span>
/// ```
///
/// Один абзац, три подчёркнутых слова **в потоке текста**, одна
/// короткая подпись — и больше на экране ничего.
///
/// # Что было до вечера 27.10.2026 и почему это правка, а не вкус
///
/// Отзыв Виктории 27.10.2026, 19:19, двумя кадрами (прототип и наш
/// экран): «Подтяни дизайн».
///
/// ```
/// до 16:50       список: три строки «ЕСТ · ВСТАЁТ · ЛЕКАРСТВА»
///                надзаголовками капсом и с шевронами
/// 5ae3097 16:50  список назван фразой — но остался ТРЕМЯ СТРОКАМИ
///                в `VStack`, и каждая высотой 44 (цель касания).
///                На кадре TestFlight 280 это три разнесённых
///                обрывка, а не предложение
/// стало          один поток: куски текста и подчёркнутые слова
///                переносятся как слова в абзаце
/// ```
///
/// **Чего это стоило: в файл заведён `ПотокСлов`** — раскладка
/// `Layout`, которой в проекте не было. Прежняя редакция этой головы
/// говорила «`WrappingHStack` в проекте нет, и заводить его ради
/// одного экрана не нужно» — и ровно это решение и дало три обрывка:
/// **без переноса по словам «связная фраза» неисполнима в принципе**,
/// а не «выглядит иначе на узком экране». Разница видна не только
/// глазом: прежний довод («подчёркнутое слово — цель размером
/// со слово») починки не требовал, цель держит `minHeight`, а не
/// отдельная строка.
///
/// # Чего из прототипа здесь нет — названо, а не пропущено
///
/// ```
/// кегль 30/700      НЕ СДЕЛАН. Ступени 30 в шкале нет вовсе
///                   (`Token.FontSize`: 20 · 22 · 34 · 36 · 40),
///                   а числом её вписать нельзя — храповик
///                   `DesignLiteralTests` на кегль. Фраза остаётся
///                   на `cardTitle` 20, как её поставил 5ae3097.
///                   ЦЕНА: при кегле 20 строка текста ~24 pt, а цель
///                   касания 44, и строки абзаца стоят реже, чем
///                   в прототипе, где 30 × 1,25 ≈ 37 почти совпадает
///                   с 44. Лечится ступенью в `DesignTokens/tokens.json`
///                   и решением дизайна, а не правкой этого файла
/// «ходит на улице»  НЕ СДЕЛАНО, и дело не в вёрстке: такого поля нет
///                   нигде — `пелёнк|лоток|ходит дома` ноль вхождений
///                   во всём дереве (замер 23.10.2026). Нарисовать
///                   выбор, которому некуда записаться, значит завести
///                   вход без механизма. Вместо него подъём
///                   (`wakeMinuteOfDay`), из которого раскладываются
///                   кормления и выходы, — место с дорогой
/// плашка «Медкнижка включится»   СНЯТА, разбор ниже
/// ```
///
/// Порядок слов переводчик менять **не может**: фраза собрана кусками,
/// и на языке, где сказуемое уходит в конец, она рассыплется. Для пяти
/// наших языков порядок один и тот же. Это ограничение, а не свойство.
///
/// **Граммы и отбой остались умолчанием** `ScheduleDraft` (120 г,
/// 23:00) и правятся в «Режиме дня» профиля. Это ровно то, что получал
/// человек, нажимавший «Дальше» не меняя полей.
///
/// # Подпись укорочена до прототипа, и половина её ушла
///
/// Было: «Нажми подчёркнутое, чтобы поменять. **Приблизительно —
/// приложение сверит это с тем, как ты кормишь на самом деле,
/// и поправит.**» Вторая половина снята — её нет в прототипе, и на неё
/// указала Виктория. Механизм, который она описывала, жив и стоит
/// на своём месте: `FeedingScreen.applySchedule()` предлагает часы
/// по настоящим кормлениям и пересчитывает порцию. Обещание уехало
/// туда, где его исполняют; здесь оно стояло за четыре экрана до двери.
///
/// # Плашка «Медкнижка включится» снята, и это замер, а не вкус
///
/// Она показывалась при `draft.isOnTreatment` и обещала три вещи.
/// Проверены все три:
///
/// ```
/// «Появится вкладка „Здоровье"»  ЛОЖНО. Вкладку держит ПРАВО
///                                `.seeMedical`, и только оно
///                                (`RootView.body`, решение 08.10.2026,
///                                держат `MedicalAccessTests`:
///                                «закрыта правом И ТОЛЬКО правом»).
///                                У владельца она видна всегда, в том
///                                числе ДО этого шага, — то есть
///                                обещание сбывается само и не от его
///                                выбора
/// «окно натощак и защита         ВЕРНО, и сказано ДВАЖДЫ дальше
///  от двойной дозы»              по дороге: следующий шаг онбординга
///                                (`NotificationsPrimingStep`, строки
///                                «Доза по часам» и «Окно натощак»)
///                                и пустой экран «Здоровья» —
///                                `HealthScreen.swift`, «Добавь
///                                препарат — приложение начнёт
///                                напоминать про дозу, держать окно
///                                натощак и защищать от двойной дозы»
/// «препарат добавишь потом»      ВЕРНО, и сказано ТАМ ЖЕ, рядом
///                                с кнопкой «Добавить препарат»
/// ```
///
/// > **Обещание, снятое с шага, живёт у той двери, в которую зовёт.**
/// > Единственное, что плашка говорила первой строкой, было неверно,
/// > а верное она говорила раньше, чем им можно воспользоваться.
///
/// Два ключа каталога («Медкнижка включится» и её подпись) и длинная
/// подпись остались в `Localizable.xcstrings` без читателя. Мёртвые
/// ключи убирают разом и своим инструментом
/// (`~/Projects/Tools/мёртвые-ключи.py`), а не попутной правкой
/// каталога на 3696 записей: `json.dump` по нему переписал бы формат
/// всего файла.
struct ModeStep: View {
    @Binding var draft: DogDraft
    @Binding var schedule: ScheduleDraft
    var onNext: () -> Void

    private var кличка: String { Fmt.dogNameOrFallback(draft.name) }

    var body: some View {
        // Под фразой — одна подпись, и дальше пусто. Так рисует
        // прототип, и пустота здесь работа, а не недоделка: список
        // спрашивает три раза («ест?», «встаёт?», «лекарства?»),
        // фраза УТВЕРЖДАЕТ — человек правит неверное и пропускает
        // остальное. Всё, что встаёт под ней, возвращает экрану вид
        // анкеты.
        TGScreen(title: "Режим") {
            фраза
            TGExplainer(text: "Нажми подчёркнутое, чтобы поменять.")
        } bottom: {
            TGButton(title: "Дальше", action: onNext)
        }
    }

    /// Сколько раз в день кормят. Четыре — потолок не наш: больше
    /// четырёх раз кормят щенков, и у них свой расчёт, которого
    /// в приложении пока нет.
    private static let сколькоРаз = [1, 2, 3, 4]

    /// Часы подъёма получасовым шагом с пяти до одиннадцати.
    /// Границы — не круглое число, а то, за чем режим перестаёт быть
    /// режимом: раньше пяти это смена, позже одиннадцати — не подъём.
    private static let подъём: [Int] = stride(from: 5 * 60, through: 11 * 60, by: 30).map { $0 }

    /// Связная фраза про режим: три подчёркнутых слова в потоке текста.
    ///
    /// Куски идут в `ПотокСлов` ровно в том порядке, в каком читаются,
    /// и переносятся как слова абзаца. Знак препинания приклеен
    /// к слову, после которого стоит, а не идёт отдельным куском:
    /// иначе запятая переносилась бы на новую строку одна.
    ///
    /// **Кличка рисуется `Text(verbatim:)`, и это не стиль.** До этой
    /// правки стояло `.готовая(кличка + " " + …)`, то есть
    /// `LocalizedStringKey`, а он **всегда** ищет по каталогу —
    /// и в день, когда собранная строка совпадёт с ключом, кличка
    /// молча переведётся. Так уже было: живой отзыв `AEXYTDmy`
    /// «Где-то stitch а где то Стич», разбор —
    /// `docs/кличка-переводится.md` и голова `Подпись.swift`.
    /// Остальные куски собраны через `String(localized:)`, то есть
    /// перевод у них уже взят.
    private var фраза: some View {
        let сколькоЕст = String(localized: "\(Fmt.times(schedule.mealsPerDay)) в день")
        let когдаВстаёт = Fmt.clock(minuteOfDay: schedule.wakeMinuteOfDay)
        let какЛекарства = draft.isOnTreatment ? String(localized: "пьёт")
                                               : String(localized: "не пьёт")
        return ПотокСлов(межсловный: Token.Space.s6, междустрочный: Token.Space.s2) {
            Text(verbatim: кличка + " " + String(localized: "ест"))
                .textStyle(AppFont.cardTitle)
            слово(ответ: сколькоЕст,
                  вслух: String(localized: "ест") + " " + сколькоЕст,
                  хвост: ",") {
                ForEach(Self.сколькоРаз, id: \.self) { сколько in
                    Button(.готовая(Fmt.times(сколько))) { schedule.mealsPerDay = сколько }
                }
            }
            Text("встаёт в").textStyle(AppFont.cardTitle)
            слово(ответ: когдаВстаёт,
                  вслух: String(localized: "встаёт в") + " " + когдаВстаёт,
                  хвост: ",") {
                ForEach(Self.подъём, id: \.self) { минута in
                    Button(.готовая(Fmt.clock(minuteOfDay: минута))) {
                        schedule.wakeMinuteOfDay = минута
                    }
                }
            }
            Text("лекарства").textStyle(AppFont.cardTitle)
            слово(ответ: какЛекарства,
                  вслух: String(localized: "лекарства") + " " + какЛекарства,
                  хвост: ".") {
                Button("не пьёт") { draft.isOnTreatment = false }
                Button("пьёт") { draft.isOnTreatment = true }
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
    }

    /// Одно изменяемое слово внутри фразы: подчёркнуто и нажимается.
    ///
    /// Цель касания держит `minHeight`, а не глиф: подчёркнутое «пьёт» —
    /// четыре буквы, и без этого в него не попасть пальцем.
    ///
    /// `вслух` — отдельный параметр, а не `ответ`, и это починка,
    /// а не украшение: прежний комментарий обещал, что озвучка скажет
    /// «ест 2 раза в день, кнопка», а `accessibilityLabel` стоял
    /// на одном ответе, то есть человек слышал «2 раза в день» без
    /// глагола. В потоке это хуже, чем в списке: соседний текст
    /// озвучка читает отдельным элементом, и связь теряется совсем.
    ///
    /// `хвост` рисуется `Text(verbatim:)`: запятая и точка одинаковы
    /// во всех пяти языках, и ключ из них был бы строкой, которую
    /// нечего переводить.
    private func слово<Пункты: View>(ответ: String, вслух: String, хвост: String,
                                     @ViewBuilder пункты: () -> Пункты) -> some View {
        Menu {
            пункты()
        } label: {
            HStack(alignment: .firstTextBaseline, spacing: 0) {
                Text(.готовая(ответ))
                    .textStyle(AppFont.cardTitle.color(Token.Ink.link))
                    .underline()
                    .wraps()
                Text(verbatim: хвост).textStyle(AppFont.cardTitle)
            }
            .frame(minHeight: Token.Size.tapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .accessibilityLabel(Text(verbatim: вслух))
        .accessibilityHint("Нажми, чтобы поменять")
    }
}

/// Строка «подпись — поле». Вынесена, потому что повторяется на трёх экранах.
///
/// Подпись отдаётся полю и как accessibility-имя: без этого VoiceOver
/// называет поле плейсхолдером («4,1», «+33…»), а два телефона подряд
/// на экране «Если что-то случилось» звучат одинаково.
/// `spokenLabel` — для случаев, когда видимая подпись коротка нарочно
/// («Телефон» под заголовком «Ветеринар»), а вслух нужна полная.
///
/// > **`ViewThatFits` отсюда СНЯТ 23.10.2026** — он запрещён красной
/// > линией проекта: держал в дереве обе раскладки, и озвучка находила
/// > две копии поля. Раскладка выбирается явным `if`
/// > по `dynamicTypeSize`, как в `UndoToastView` и `TGListRow`.
/// >
/// > Прежняя редакция этой головы говорила, что снять его «нельзя
/// > попутно: `LabeledField` зовут девятнадцать мест в `Health`,
/// > `Family` и `Profile`». **Довод был не про тот предмет.** Подпись
/// > типа не меняется ни на символ — меняется только внутренняя
/// > раскладка, — поэтому места вызова не правятся вовсе, и открытость
/// > их каталогов для этой замены не требуется. Девятнадцать вызовов
/// > были доводом за приёмку кадром, а не против починки.
/// > **ПОДПИСЬ НЕ ПЕРЕВОДИЛАСЬ ВОВСЕ — замер 26.10.2026.** Поле было
/// > объявлено `String`, и `Text(label)` брал **дословную** перегрузку:
/// > ключ уходил в каталог при `make texts`, переводился на пять языков
/// > и на экран не доезжал ни на одном. Француз читал медицинскую форму
/// > по-русски при готовом французском в каталоге.
/// >
/// > ```
/// > сторож локализации   «переведён ли ключ»      ЗЕЛЁН по всем пяти
/// > предмет              «показан ли перевод»     НЕ СПРАШИВАЕТ НИКТО
/// > ```
/// >
/// > Это тот же класс, что «сторож на прокси», и у него своя цена:
/// > **вычитка носителем бессмысленна там, где перевод не доезжает
/// > до экрана.**
/// >
/// > Тип сменён на `Надпись`, а не на `LocalizedStringKey`, и это
/// > не вкусовщина. `LocalizedStringKey` **всегда** ищет по каталогу,
/// > и в день, когда данные человека совпадут с ключом, имя молча
/// > переведётся — так уже случилось с кличкой (`docs/кличка-переводится.md`,
/// > живой отзыв `AEXYTDmy` «Где-то stitch а где-то Стич»). `Надпись`
/// > заставляет место вызова объявить намерение: литерал — ключ,
/// > данные человека — `.значение(…)`.
/// >
/// > Замер перед сменой типа: вызовов **59**, из них литералом **48**,
/// > через `String(localized:)` **11**, переменной — **НОЛЬ**. То есть
/// > данные человека в подпись не идут сегодня ни в одном месте,
/// > и компилятор удержит это завтра.
struct LabeledField<Content: View>: View {
    /// Настройка размера текста: от неё зависит, строкой или столбцом
    /// раскладывать подпись и поле.
    @Environment(\.dynamicTypeSize) private var размерТекста

    let label: Надпись
    var spokenLabel: Надпись? = nil
    @ViewBuilder var content: Content

    /// Порог раскладки: **`.xxxLarge`, а не `isAccessibilitySize`.**
    ///
    /// `.xxxLarge` — последняя НЕдоступная ступень, и прежний порог
    /// её не захватывал: ветка столбцом не срабатывала ровно там, где
    /// поле уже не помещалось. Виктория назвала эту ступень осью
    /// приёмки дословно — «содержимое не теряется везде, косметика
    /// до `.xxxLarge`», — то есть на ней показ обязан быть ещё целым.
    ///
    /// СЧЁТ, которым это найдено (это СЧЁТ, не кадр):
    ///
    ///     самая длинная подпись из 59   фр. «Quelle quantité donner»
    ///                                   22 знака против 14 русских
    ///     AppFont.body на .xxxLarge     ~23 pt
    ///     подпись занимает              ~253 pt
    ///     доступно на SE 375            ~307 pt (минус поля экрана
    ///                                   и карточки)
    ///     полю остаётся                 ~42 pt  ← три знака
    ///
    /// Длиннее всех оказался **французский**, не казахский с украинским:
    /// у «Сколько давать» ru 14 · en 16 · fr 22 · kk 16 · uk 14.
    /// Подписи `Отметка лаборатории` (19 знаков по-русски) в каталоге
    /// нет вовсе — её французский может быть ещё длиннее, то есть счёт
    /// выше **занижен**, а не завышен.
    ///
    /// `fixedSize()` в строчной ветке не даёт подписи ни ужаться,
    /// ни перенестись, поэтому всю тесноту забирает поле: человек
    /// не видит того, что сам вписал.
    ///
    /// **Кадром НЕ ПРОВЕРЕНО, и это названо.** Приёмка — `.xxxLarge`
    /// на SE 375 по-французски, экран «Анализы»
    /// (`LabResultScreens.swift:703`, `:1092` — там живёт самая длинная
    /// подпись). Ожидаемое названо заранее: на `.xxLarge` строка
    /// остаётся строкой и кадр совпадает с прежним ПОБАЙТОВО,
    /// на `.xxxLarge` подпись встаёт над полем.
    ///
    /// Порог тронут **только здесь**. У прочих мест с
    /// `isAccessibilitySize` тот же вопрос открыт и не померен —
    /// переносить правило без проверки устройства нельзя, предмет
    /// у каждого свой.
    private var столбцом: Bool { размерТекста >= .xxxLarge }

    var body: some View {
        Group {
            if столбцом {
                // При крупной системной настройке подпись и поле
                // перестают помещаться рядом — тогда поле уезжает под
                // подпись, а не сжимается в щель.
                VStack(alignment: .leading, spacing: Token.Space.s4) {
                    Text(label).textStyle(AppFont.caption)
                    content
                        .multilineTextAlignment(.leading)
                        .textStyle(AppFont.body)
                        .accessibilityLabel(Text(spokenLabel ?? label))
                }
            } else {
                HStack {
                    Text(label).textStyle(AppFont.body).fixedSize()
                    Spacer(minLength: Token.Space.s12)
                    content
                        .multilineTextAlignment(.trailing)
                        .textStyle(AppFont.body)
                        .accessibilityLabel(Text(spokenLabel ?? label))
                }
            }
        }
        .frame(minHeight: Token.Size.tapTarget)
    }
}

// MARK: - Шаг 3 · разрешение на уведомления

/// Разрешение спрашиваем не на старте, а когда уже понятно, за что оно.
/// Отказ ничего не ломает: дневник работает целиком без уведомлений.
///
/// # Третьей строки макета здесь нет, и это запрет, а не пропуск
///
/// Прототип показывает три строки: «Доза по часам», «Окно натощак»
/// и **«Тревога · кровь, рвота — со звуком»**. Третьей дороги в коде
/// НЕТ: у `NotificationCenterService.Category` четыре случая —
/// `morningBrief`, `dose`, `fasting`, `escalation`, — и тревоги среди
/// них нет вовсе (замер 23.10.2026). Нарисовать её значило бы обещать
/// уведомление, которое не придёт в тот единственный раз, когда оно
/// нужнее всего.
///
/// Поэтому третьей строкой остаётся лестница эскалации — у неё
/// категория есть. **Её подпись не тронута ни словом, и это тоже
/// решение:** «сначала дежурному, потом остальным» обещает адресатов,
/// а пуши у нас локальные (`CKSubscription` — ноль вхождений). Долг
/// открыт, наряд — `docs/спринт-канал-эскалации.md`; усиливать
/// обещание нельзя, чинить его — не эта работа.
struct NotificationsPrimingStep: View {
    /// В просмотре — ложно, и тогда шаг ничего не меняет.
    ///
    /// Здесь не хранилище, а две вещи вне его, и обе необратимы
    /// по-своему: `notificationsAsked` в `UserDefaults` и **системный
    /// запрос разрешения**. Второй хуже: у человека он спросит
    /// по-настоящему, а в прогоне поднимет модальный алерт, который
    /// никто не ждёт и который останавливает весь дальнейший заход.
    var пишемВБазу: Bool = true
    var onDone: () -> Void

    @Environment(Settings.self) private var settings
    @State private var isRequesting = false

    var body: some View {
        TGScreen(title: "Что будет прерывать") {
            TGExplainer(text: "Прерывают ровно три вещи. Всё остальное ждёт утра — это единственный способ не превратить дневник в источник тревоги.")

            VStack(spacing: Token.Space.s8) {
                InterruptRow(symbol: "pills", title: "Доза по часам",
                             detail: "и то только если собака на лечении")
                InterruptRow(symbol: "clock.badge.exclamationmark", title: "Окно натощак",
                             detail: "еда внутри окна мешает всасыванию")
                InterruptRow(symbol: "bell.badge", title: "Лестница эскалации",
                             detail: "если дозу не отметили — сначала дежурному, потом остальным")
            }

            TGCard {
                Text("Одно напоминание в \(Fmt.clock(minuteOfDay: settings.briefHour * 60))").textStyle(AppFont.cardTitle)
                Text("Груминг, антипаразитарка, прививки, взвешивание — не восемь напоминаний, а одно в выбранный час. Час можно сдвинуть в настройках.")
                    .textStyle(AppFont.caption)
            }
        } bottom: {
            // Пока системный запрос висит, кнопка выключена —
            // и говорит об этом словом (правило круга 5, п. 1).
            // Шаг единственной двери в приложение: молчащая кнопка
            // здесь читается как «приложение зависло».
            TGButton(title: isRequesting ? "Спрашиваю разрешение…" : "Разрешить",
                     systemImage: "bell", isEnabled: !isRequesting) {
                Task { await request() }
            }
            // «Потом, в настройках», а не «Не сейчас»: дорога есть
            // и названа — «Настройки → Уведомления», оттуда же открывается
            // системный экран разрешений. Отказ без адреса читается как
            // «больше не спросят».
            TGButton(title: "Потом, в настройках", variant: .quiet, size: .medium) {
                if пишемВБазу { settings.notificationsAsked = true }
                onDone()
            }
        }
    }

    private func request() async {
        // В просмотре кнопка доводит до конца шага и ничего не просит:
        // спрашивать разрешение у человека, который зашёл посмотреть,
        // значит задать ему вопрос от его же имени.
        guard пишемВБазу else { return onDone() }
        isRequesting = true
        _ = await NotificationCenterService.requestAuthorization()
        settings.notificationsAsked = true
        isRequesting = false
        onDone()
    }
}

struct InterruptRow: View {
    let symbol: String
    let title: String
    let detail: String

    var body: some View {
        TGCard(padding: Token.Space.s14) {
            TGIconRow(symbol: symbol, title: .готовая(title), detail: .готовая(detail),
                      tint: Token.Status.waitingText)
        }
    }
}

