import SwiftUI
import SwiftData

/// Онбординг темы «Кино» — **четыре экрана плюс ветка «Меня позвали»**.
///
/// Эталон — `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/18.png`
/// (приветствие) и прототип `Дизайн/редизайн-ios28/prototypes/Togo-RU.dc.html`
/// (три шага). `SCREENS.md` пакета называет это «Онбординг (4 шага +
/// „Меня позвали“)».
///
/// # Что изменилось 23.10.2026 и чего это стоило
///
/// ```
/// было   welcome · dog · schedule · care · family · notifications   ШЕСТЬ
/// стало  welcome · dog · mode · notifications                       ЧЕТЫРЕ
/// ```
///
/// Снято два шага, и ни один не снят «за ненадобностью»:
///
/// * **Уход** (`CareStep`) — выбор дел ухода. Умолчания никуда
///   не делись: `SeedData.attachStarterCare(to:context:)` по-прежнему
///   зовётся из `saveDog()`, то есть человек получает тот же стартовый
///   набор, что выбрал бы сам, — просто не выбирая его на третьей минуте
///   знакомства. Правится в «Уходе» в любой момент.
/// * **Семья** (`FamilyStep`) — приглашение. Снято **с выгодой**: та
///   кнопка «Отправить ссылку» заводила участника «Приглашение»
///   и ничего не отправляла (известное ложное обещание, оставленное
///   в описи решением 14.10). Настоящее приглашение живёт в «Семье»,
///   и дорога к нему одна.
///
/// **Чего при этом нет и быть не должно: записи, которую человек
/// не увидел.** Сокращение шагов не меняет того, что пишется
/// в хранилище, кроме выбора дел ухода — он теперь приходит
/// умолчанием, и это названо выше, а не умолчано.
///
/// # Чего из макета здесь нет — названо, а не пропущено
///
/// ```
/// «С примером» (третья кнопка приветствия)
///   УБРАНО ИЗ v1 РЕШЕНИЕМ ВИКТОРИИ 23.10.2026, дизайн подтвердила
///   тем же днём (`Дизайн/редизайн-ios28/ОТВЕТЫ-круг-3.md`, п. 3):
///   «макет обещал больше, чем стоит делать сейчас». Демо-дневнику
///   нужны отдельное хранилище, правило «семья его не видит» и выход
///   без следов — это спринт, а ценность до первого выхода с собакой
///   низкая. Инженерная причина при этом тоже стоит и никуда не делась:
///   `SeedData.makePreviewContainer` строит контейнер В ПАМЯТИ и живёт
///   только под `-UITesting` (`TogoApp.swift:63`), то есть кнопка была
///   бы входом без механизма.
///
///   **На первом экране остаются ровно две кнопки** — «Начать»
///   (главная) и «Меня позвали» (вторичная, во всю ширину).
///
/// фото во весь экран на приветствии
///   НЕ СДЕЛАНО, и сделать нечем: фото в макете — плейсхолдеры
///   Unsplash («в продукт не включать», README пакета), а своего фото
///   у человека на первом запуске ещё нет по построению. Вместо него
///   иллюстрация «линия», сцена `onboarding`.
///
/// лента цитат («Боб и Аня · мама отмечает дозу — я вижу»)
///   УБРАНА ИЗ v1 ТЕМ ЖЕ РЕШЕНИЕМ (п. 4). Это **выдуманные отзывы** —
///   App Review 2.3.1/3.1 и наше «ничего не обещаем ложно», а не
///   вопрос вёрстки. Та же лента стояла и на пейволле.
/// ```
///
/// > **Три верхних строки — решение, а не долг.** Условия возврата
/// > лежат в `Дизайн/РЕШЕНИЯ-ДИЗАЙНА.md`, раздел «Убрано из v1
/// > по App Review», а не здесь: макет комментарии Swift не читает,
/// > и у этого проекта обещание уже возвращалось через макет.
/// > Двенадцать ключей этих лент удалены из каталога строк
/// > (`TogoShared/Resources/Localizable.xcstrings`, 3415 → 3403),
/// > то есть вернуть их «заодно вёрсткой» нечем.
struct OnboardingFlow: View {
    /// Просмотр: показать настоящие шаги и ничего не записать.
    ///
    /// Отличается от повторного прохождения тем же, чем показ от установки:
    /// повтор — это чтение справки человеком, который уже всё настроил,
    /// просмотр — взгляд на то, что увидит новый. Сверять макет можно
    /// только со вторым.
    var просмотр: Bool = false

    @Environment(\.modelContext) private var context
    @Environment(Settings.self) private var settings
    @Environment(AppState.self) private var appState
    @Query private var dogs: [Dog]

    @State private var step: Step = .welcome
    @State private var draft = DogDraft()
    @State private var schedule = ScheduleDraft()
    /// Собаку пропустили: создавать её на выходе нельзя.
    @State private var skippedDog = false

    /// Открыта ветка «меня позвали в семью».
    ///
    /// Отдельным состоянием, а не шагом `Step`, и это не экономия:
    /// шаги считаются человеку строкой «N из 3», а ветка «позвали» —
    /// не шаг онбординга, а **выход из него**. Добавь её в `Step`,
    /// и у всех остальных сдвинется номер, то есть человек, заводящий
    /// собаку, увидит «1 из 4» ради дороги, по которой он не идёт.
    @State private var позвали = false

    /// Какой это поток. **Поле, а не вычисление, и это предмет.**
    ///
    /// Онбординг можно пройти заново из настроек. Тогда собака уже есть,
    /// и шаги, которые её создают, надо пропустить — иначе получится
    /// вторая. В просмотре собака тоже есть, а подменять шаги нельзя:
    /// смотрят ровно их, и вместо подмены выключается запись
    /// (`пишемВБазу`). Три разных случая, поэтому три случая
    /// перечисления, а не один флаг.
    ///
    /// Было: `isReplay = !dogs.isEmpty && !просмотр` — то есть режим
    /// потока вычислялся из базы, в которую этот же поток пишет.
    /// `saveDog()` на шаге записи вставлял собаку, `@Query dogs`
    /// перестаёт быть пустым, `isReplay` переворачивался **посреди
    /// первого прохода**, и следующий шаг отдавал «Это всё» с `finish`.
    /// Три шага из шести были недостижимы по построению. Жило
    /// с `0653a4e` (26.08.2026 01:33) и уехало во всех двенадцати
    /// сборках.
    ///
    /// Два звена при этом прожили вместе час тридцать шесть безвредно:
    /// переворот происходил, но читателя у перевёрнутого знака не было.
    /// Поэтому `git log -S` называет не виновного, а всю эволюцию.
    enum Режим { case первыйПроход, повтор, просмотр }

    /// Ставится один раз при входе в поток и больше не меняется.
    @State private var режим: Режим?

    /// Пока не поставлен — считаем как раньше. Так первый кадр
    /// не отличается от нынешнего поведения, и у перечитывающего
    /// не мигает подпись кнопки на `.welcome`.
    private var режимСейчас: Режим {
        режим ?? (просмотр ? .просмотр : (dogs.isEmpty ? .первыйПроход : .повтор))
    }

    private var isReplay: Bool { режимСейчас == .повтор }

    /// Единственное место, где решается, трогать ли хранилище.
    ///
    /// Отдельным именем, а не третьим условием в `advance()`: запрет
    /// на запись — это предмет, а не частность перехода. Ошибись здесь,
    /// и просмотр заведёт человеку вторую собаку, то есть инструмент
    /// сверки испортит её данные.
    private var пишемВБазу: Bool { режимСейчас == .первыйПроход && !skippedDog }

    /// Собака уже записана этим проходом.
    ///
    /// **Отдельным флагом, а не следствием из `пишемВБазу`.** До правки
    /// от второй собаки защищал побочный эффект: после `saveDog()`
    /// база перестаёт быть пустой, `isReplay` становится истинным,
    /// `пишемВБазу` — ложным, и повторный проход через шаг записи
    /// («Назад» на `.dog`, потом снова вперёд) второй раз не писал.
    /// Заморозка режима эту защиту снимает — и дубль родился бы молча,
    /// а дубль собаки это первая карточка на экране «Семья».
    ///
    /// То есть починка одного отказа делала тихим соседний. Поэтому
    /// запрет назван своим именем, а не унаследован.
    @State private var собакаСохранена = false

    /// Четыре экрана. Нумеруется человеку только то, что после
    /// приветствия, — отсюда «\(rawValue) из 3».
    enum Step: Int, CaseIterable {
        case welcome, dog, mode, notifications

        var index: Int { rawValue }
        var progress: String? { self == .welcome ? nil : String(localized: "\(rawValue) из 3") }
    }

    var body: some View {
        NavigationStack {
            Group {
                switch step {
                case .welcome:
                    WelcomeStep(isReplay: isReplay,
                                onNext: { advance() },
                                // Ветка «позвали» НЕ продвигает онбординг
                                // и ничего не пишет в базу: человек ещё
                                // не решил, он здесь или нет. Решает
                                // за него система, когда он откроет
                                // ссылку, — и тогда сработает делегат
                                // сцены, а не этот экран.
                                onJoin: { позвали = true })
                case .dog:
                    if isReplay {
                        // Собака уже есть — вместо формы показываем то,
                        // ради чего онбординг и перечитывают.
                        HowItWorksScreen()
                            .safeAreaInset(edge: .bottom) {
                                TGButton(title: "Дальше") { advance() }
                                    .padding(.horizontal, Token.Spacing.screenPadding)
                                    .padding(.bottom, Token.Space.s8)
                                    .background(.regularMaterial)
                            }
                    } else {
                        DogStep(draft: $draft, onNext: { advance() }, onSkip: { skipDog() })
                    }
                case .mode:
                    if isReplay {
                        HowItWorksReplayEnd(onDone: finish)
                    } else {
                        ModeStep(draft: $draft, schedule: $schedule) { advance() }
                    }
                case .notifications:
                    // Здесь `!просмотр`, а НЕ общий `пишемВБазу`, и это
                    // не описка. `пишемВБазу` ложно и при «Пока без
                    // собаки» — а человек, пропустивший собаку, проходит
                    // настоящий онбординг, и разрешение на уведомления
                    // у него надо спросить по-настоящему. Не спросить
                    // значит отнять у него пуши молча.
                    NotificationsPrimingStep(пишемВБазу: !просмотр, onDone: finish)
                }
            }
            .background(Token.Surface.screen)
            // **Первый читатель `.плавно(` во всём дереве.** До 23.10.2026
            // вызовов у него было ноль: Reduce Motion по рекомендации 7
            // хендоффа был объявлен и не подключён ни к одной анимации —
            // механизм без читателя, который грепом находится один раз,
            // в объявлении, и выглядит работающим.
            //
            // Поэтому `withAnimation` из `advance()`/`back()` снят: две
            // анимации на один переход спорили бы, и выключить обе одной
            // настройкой было бы нечем.
            .плавно(.easeInOut(duration: Token.Duration.quick), значение: step)
            // Лист, а не шаг: из ветки «позвали» человек возвращается
            // туда же, откуда пришёл, ничего не потеряв. Онбординг
            // под ним стоит на месте — он не пройден и не отменён.
            .sheet(isPresented: $позвали) {
                ПозвалиВСемью { позвали = false }
            }
            .toolbar {
                if let progress = step.progress, !isReplay {
                    ToolbarItem(placement: .principal) {
                        Text(progress).textStyle(AppFont.micro)
                    }
                }
                // Шаг назад есть везде, кроме первого экрана: человек должен
                // иметь право передумать, а не только идти вперёд.
                if step != .welcome {
                    ToolbarItem(placement: .topBarLeading) {
                        Button {
                            back()
                        } label: {
                            Label("Назад", systemImage: "chevron.left")
                        }
                    }
                }
                // Выход есть и отсюда: перечитал — и вернулся к дневнику.
                if isReplay {
                    ToolbarItem(placement: .topBarTrailing) {
                        Button("Закрыть") { finish() }
                    }
                }
            }
            // Режим ставится ОДИН раз, на входе в поток, и дальше
            // не пересчитывается. Без этой строки `режимСейчас` остаётся
            // прежним вычислением из базы — то есть дефект возвращается
            // целиком, молча и без красного теста.
            .task {
                if режим == nil {
                    режим = просмотр ? .просмотр
                        : (dogs.isEmpty ? .первыйПроход : .повтор)
                }
            }
            .usageScreen(.onboarding)
            // Где человек застревает в онбординге, видно только по шагам:
            // «дошёл до режима дня и вышел» — это претензия к шагу,
            // а не к приложению целиком.
            .onChange(of: step) { _, next in
                UsageLog.note(.open, String(describing: next), on: .onboarding)
            }
        }
    }

    /// Пропустить собаку.
    ///
    /// **В макете этой дороги нет, и она оставлена нарочно.** Убрать её
    /// значило бы принять продуктовое решение «без собаки в приложение
    /// не войти» — а его никто не принимал: макет про такого человека
    /// просто молчит, а молчание макета не отмена дороги. Шаг режима
    /// следом настраивает именно собаку, поэтому пропускается вместе
    /// с ней: спрашивать, сколько раз ест собака, которой нет,
    /// бессмысленно. Завести её можно в любой момент
    /// («Настройки → Добавить собаку»).
    private func skipDog() {
        skippedDog = true
        UsageLog.note(.open, "dogSkipped", on: .onboarding)
        step = .notifications
    }

    private func advance() {
        // Повторное прохождение ничего не создаёт: это чтение, а не установка.
        // Второе условие — про ЭТОТ проход, а не про режим: человек может
        // вернуться «Назад» на карточку собаки и пойти вперёд снова.
        //
        // **Ворота переехали с `.schedule` на `.mode` вместе с шагом.**
        // Записывать надо после того, как собраны обе половины карточки:
        // кличка с весом (шаг `.dog`) и режим дня (шаг `.mode`).
        if step == .mode, пишемВБазу, !собакаСохранена {
            saveDog()
            собакаСохранена = true
        }
        step = Step(rawValue: step.rawValue + 1) ?? .notifications
    }

    private func back() {
        // Назад после «Пока без собаки» — на саму собаку, и пропуск снят.
        // Иначе флаг жил до конца прохода: человек возвращался, заводил
        // собаку, шёл вперёд — и `пишемВБазу` оставался ложным, собака
        // молча не сохранялась, а онбординг заканчивался как ни в чём
        // не бывало. Первый же шаг «Назад» к тому же приводил на режим
        // собаки, которой нет (разбор 28.10.2026).
        if skippedDog, step == .notifications {
            skippedDog = false
            step = .dog
            return
        }
        step = Step(rawValue: step.rawValue - 1) ?? .welcome
    }

    private func saveDog() {
        let dog = draft.makeDog()
        DogOrigin.заведенаЗдесь(dog.id)
        schedule.apply(to: dog)
        context.insert(dog)
        SeedData.attachStarterCare(to: dog, context: context)
        // Заготовки навыков заводятся ЗДЕСЬ, а не на экране процедур.
        //
        // Экран сеял их сам и помнил флагом в `UserDefaults` — то есть
        // отметка о данных лежала на устройстве, а данные в облаке,
        // и на втором телефоне заготовки воскресали. Разбор —
        // `SeedData.seedProcedureSkillsIfNone`.
        //
        // Навыки общие, не привязаны к собаке: завести их на каждую
        // значило бы удвоить список второй собакой. Онбординг проходят
        // один раз — это и есть то единственное событие, которое им
        // соответствует.
        SeedData.seedProcedureSkillsIfNone(context: context)
        let me = FamilyMember(name: draft.ownerName, role: .owner, isMe: true)
        context.insert(me)
        // Своя карточка запоминается на телефоне: `isMe` уезжает в общий
        // дневник и на втором устройстве указывает не на того.
        appState.myMemberID = me.id
        // **Фото собаки — это подложка всего приложения, и сказать
        // о нём надо здесь.** Решение дизайна 23.10.2026 (круг 2, п. 1):
        // цепочка «своё фото раздела → `Dog.photo` → чёрный».
        // `BackgroundStore` живёт в App Group и базу не читает.
        //
        // **Онбординг — самый важный из трёх входов**, потому что он
        // первый: человек заводит собаку с фотографией и сразу попадает
        // на вкладки. Без этой строки он увидит чёрное — при том, что
        // фото у него уже есть, а дизайн обещает подложку. Поправить
        // это можно было бы только зайдя в Настройки → «Фон
        // приложения», куда на первом запуске незачем идти.
        //
        // Замер 23.10: `запомнитьФотоСобаки` звало ОДНО место — `.task`
        // того самого экрана настроек, — а пишется фото в трёх.
        BackgroundStore.shared.запомнитьФотоСобаки(dog.photo)
    }

    private func finish() {
        // Просмотр не «проходят» — из него выходят. Поставить здесь флаг
        // значило бы записать человеку прохождение онбординга за то,
        // что он посмотрел на него, а стенду — закрыть вторую партию
        // кадров: `просмотрОнбординга` гасится, и следующий запуск
        // в тот же онбординг уже не попадёт.
        guard !просмотр else {
            appState.просмотрОнбординга = false
            return
        }
        settings.onboardingCompleted = true
        settings.lastSeenVersion = settings.appVersion
    }
}

/// Черновик собаки живёт отдельно от модели: пока человек не дошёл до конца шага,
/// в базе ничего нет.
struct DogDraft {
    var name = ""
    var weight = ""
    var breed = ""
    var sex: DogSex = .unknown
    var isNeutered = false
    var birthDate: Date?
    var hasBirthDate = false
    var isOnTreatment = false
    var photo: Data?
    var ownerName = "Я"

    // **`isValid` УДАЛЁН 25.10.2026, и удалён потому, что перестал
    // быть прочитанным.** Он значил «кличка непуста И вес разобран»
    // и держал две кнопки: «Дальше» на шаге собаки и «Сохранить»
    // в профиле. Первую с него сняли 25.10 (вес в онбординге
    // не обязателен, ОТВЕТЫ-круг-5 п. 1), вторую — тем же днём
    // и по другой причине: `DogEditorScreen.save()` пустой вес
    // переживает сам, то есть условие кнопки и действие смотрели
    // на разные величины.
    //
    // > **Решение без живого читателя не «почти работает» — его нет.**
    // > Оставь я `isValid` лежать, следующий взял бы его как правило
    // > («кличка и вес обязательны») из объявления, а не из мест,
    // > где ворота стоят на самом деле.
    //
    // Ворота теперь у каждого экрана свои и названы словами:
    // `DogStep.кличкаПуста` и `DogEditorScreen.кличкаПуста`.

    var weightValue: Double? {
        Double(weight.replacingOccurrences(of: ",", with: "."))
    }

    /// Режим питания приезжает отдельным шагом — здесь только то,
    /// что человек ввёл на карточке собаки.
    ///
    /// **Порода, пол, кастрация и дата рождения спрашиваются теперь
    /// в профиле, а не в онбординге** (макет iOS 28: на шаге «Собака»
    /// только кличка и вес). Поля черновика оставлены: их пишет
    /// `makeDog()`, и убрать их значило бы переписать заодно профиль,
    /// который этой смене не открыт.
    func makeDog() -> Dog {
        let dog = Dog(name: name.trimmingCharacters(in: .whitespaces), weightKg: weightValue ?? 0)
        dog.breed = breed.isEmpty ? nil : breed
        dog.sex = sex
        dog.isNeutered = isNeutered
        dog.birthDate = hasBirthDate ? birthDate : nil
        dog.isOnTreatment = isOnTreatment
        dog.photo = photo
        return dog
    }
