/// «Правила» — один экран вместо четырёх строк в настройках.
///
/// Эталон `Дизайн/эталонные-кадры/v10-прототип-24.10/screenshots/47-screens.jpg`:
/// надстрочник «ПОЛИТИКА, УСЛОВИЯ», заголовок «Правила», карточка
/// с четырьмя строками. У нас эти четыре строки стояли секцией
/// «правовое» прямо в `SettingsScreen` (`:355`), то есть четырьмя
/// соседями среди двух десятков других строк настроек.
///
/// **Почему это не косметика, хотя выглядит косметикой.** App Review
/// ищет здесь ровно два документа — политику и условия, — и ищет глазами
/// по списку настроек. Четыре строки правового среди «Фон приложения»,
/// «Тихие часы» и «Запас корма» читаются как такие же пункты; собранные
/// под своим именем — как раздел, к которому ведёт одно слово.
///
/// **Ни одного нового литерала.** «Правила», «политика, условия»,
/// «Условия», «Не медицинский совет», «дисклеймер» уже лежат
/// в `Localizable.xcstrings` переведёнными на четыре языка и до сегодня
/// не имели в Swift ни одного читателя — текст к этому экрану заказали
/// и перевели раньше, чем экран построили.
///
/// Длинные имена дверей («Политика конфиденциальности») остались
/// длинными: внутри раздела место есть, а короткое «Условия» рядом
/// с ними читается как пара, а не как обрывок.
struct LegalScreen: View {
    var body: some View {
        TGScreen {
            CinemaHeader("Правила", надпись: "политика, условия", отступы: false)
            TGCard(spacing: 0) {
                TGLink(title: "Политика конфиденциальности",
                       systemImage: "hand.raised") { PrivacyPolicyScreen() }
                TGDivider(inset: 38)
                TGLink(title: "Условия",
                       systemImage: "doc.text") { TermsScreen() }
                TGDivider(inset: 38)
                TGLink(title: "Не медицинский совет",
                       value: "дисклеймер",
                       systemImage: "cross.case") { MedicalDisclaimerScreen() }
                TGDivider(inset: 38)
                TGLink(title: "Открытый код",
                       systemImage: "chevron.left.forwardslash.chevron.right") { AcknowledgementsScreen() }
            }
        }
        .navigationTitle("Правила")
        .cinemaScreen(экран: .sub("legal"))
    }
}
