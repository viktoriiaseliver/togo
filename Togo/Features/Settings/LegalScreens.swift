import SwiftUI

/// Правовые тексты и справка. Один каркас на все документы: заголовок,
/// дата обновления и разделы. Так их не нужно верстать заново каждый раз.
///
/// **Поля — `LocalizedStringKey`, и это не стиль, а условие перевода.**
/// `Text(String)` рисует текст дословно; `Text(LocalizedStringKey)` ищет
/// ключ в каталоге. Литерал в коде — это ключ.
///
/// Тот же дефект здесь уже находили: `956c6cd` 23.09.2026, «Половина
/// интерфейса не переводилась: Text(String) рисует дословно», поймано
/// французским кадром витрины — «Просится» и «Гулять» по-русски при
/// живом переводе. Тогда починили компоненты дизайн-системы и ввели
/// `.готовая(_:)` для случаев, где строка уже собрана. **Этот файл
/// и `HowItWorksScreen` пропустили, и они прожили так 22 дня:**
/// экспортёр Xcode ключи в каталог положил и перевёл на четыре языка,
/// а код по ним не искал — перевод существовал как данные и не читался
/// при показе.
///
/// `updated` остаётся `String` НАРОЧНО: он идёт внутрь
/// `Text("обновлено \(updated)")`, то есть в ключ с подстановкой.
/// Но само значение — русский литерал («25 августа 2026»), и у француза
/// дата приедет по-русски. Это отдельный долг, он здесь не лечится.
struct LegalDocument: View {
    struct Section: Identifiable {
        let id = UUID()
        let title: LocalizedStringKey
        let body: [LocalizedStringKey]
    }

    let title: LocalizedStringKey
    let updated: String
    let intro: LocalizedStringKey?
    let sections: [Section]

    var body: some View {
        TGScreen {
            VStack(alignment: .leading, spacing: Token.Space.s4) {
                CinemaHeader(title, отступы: false)
                Text("обновлено \(updated)").textStyle(AppFont.micro)
            }
            .padding(.top, Token.Space.s4)

            if let intro {
                TGCard {
                    Text(intro).textStyle(AppFont.body)
                }
            }

            ForEach(sections) { section in
                TGCard {
                    Text(section.title).textStyle(AppFont.cardTitle)
                    ForEach(Array(section.body.enumerated()), id: \.offset) { _, paragraph in
                        Text(paragraph).textStyle(AppFont.caption.color(Token.Ink.secondary))
                    }
                }
            }
        }
        .navigationTitle(title)
        // Заголовок приходит сюда `LocalizedStringKey`, а не `String`,
        // и это условие перевода, а не стиль. У плаката, который здесь
        // стоял до 23.10.2026, была перегрузка `.значение(_:)` для текста
        // ИЗ ДАННЫХ (кличка, город, имя участника) — и однажды «Политика
        // конфиденциальности» уехала в неё: ключ печатался по-русски
        // при живом переводе в каталоге. У `CinemaHeader` разведение
        // то же самое и по той же причине.
        .cinemaScreen(экран: .sub("legal"))
    }
}

