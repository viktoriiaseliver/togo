import SwiftUI

/// Правовые тексты и справка. Один каркас на все документы: заголовок,
/// дата обновления и разделы. Так их не нужно верстать заново каждый раз.
struct LegalDocument: View {
    struct Section: Identifiable {
        let id = UUID()
        let title: String
        let body: [String]
    }

    let title: String
    let updated: String
    let intro: String?
    let sections: [Section]

    var body: some View {
        TGScreen {
            VStack(alignment: .leading, spacing: Token.Space.s4) {
                Text(title).textStyle(AppFont.screenTitle)
                Text("обновлено \(updated)").textStyle(AppFont.micro)
            }
            .padding(.top, Token.Space.s4)

            if let intro {
                TGCard {
                    Text(intro).textStyle(AppFont.body)
                }
            }

            ForEach(sections) { section in
                TGCard {
                    Text(section.title).textStyle(AppFont.cardTitle)
                    ForEach(Array(section.body.enumerated()), id: \.offset) { _, paragraph in
                        Text(paragraph).textStyle(AppFont.caption.color(Token.Ink.secondary))
                    }
                }
            }
        }
        .navigationTitle(title)
        .navigationBarTitleDisplayMode(.inline)
    }
}

