import SwiftUI
import UIKit

/// Шапка экрана темы «Кино»: надпись капсом, крупный заголовок 36/−0,9
/// и фотография под ними.
///
/// **Заменяет `posterHeader` на настройках и их подэкранах.** Решение
/// Виктории 22.10.2026 («Кино» ЗАМЕНЯЕТ Graphite, не ложится третьим
/// набором) снимает индиговую полосу плаката: в «Кино» экран чёрный,
/// заголовок крупный, под шапкой лежит фото, а не заливка. `TGPosterHeader`
/// не тронут — он живёт в `Togo/DesignSystem`, у него сорок пять мест
/// вызова в чужих каталогах, и снимать его целиком — работа волн 4–6,
/// а не этой.
///
/// **Где этому файлу место на самом деле.** Рядом с `TGPosterHeader`,
/// в дизайн-системе: это компонент, а не экран. Он лежит здесь потому,
/// что `Togo/DesignSystem/**` на 23.10.2026 правит другая сессия, и два
/// автора в одном каталоге — это чужая незакоммиченная работа в общем
/// дереве. Переезд — отдельным коммитом, когда каталог освободится;
/// тогда же стиль заголовка уедет в `AppFont`, а размеры — на
/// компонентные токены (см. ниже).
///
/// ## Чем это НЕ является
///
/// Это не `TGPoster` (блок состояния «Сегодня») и не панель показания
/// (`ReadingPanel`). У шапки подэкрана нет ни режима, ни тона: «Настройки»
/// не бывают натощак.
///
/// ## ВТОРАЯ ТАКАЯ ШАПКА В ДЕРЕВЕ ЕСТЬ, И ЭТО НАЗВАНО, А НЕ СКРЫТО
///
/// `Togo/Features/History/КиноЭкран.swift` — каркас той же темы, его
/// пишет сессия вкладок (История, Здоровье). Обнаружен **после** того,
/// как этот файл был собран и закоммичен: на старте моей смены дерево
/// было чистым, файл появился в нём незакоммиченным по ходу работы,
/// и грепом до своей первой строки я его найти не мог.
///
/// ```
/// КиноЭкран      контейнер для ScrollView-экранов: сам рисует полотно,
///                шапку с «…» и подложку. Вкладки и подэкраны волны 6
/// CinemaHeader   шапка-строка плюс модификатор `cinemaScreen` для
///                экранов на `List` (настройки и восемь подэкранов):
///                в список контейнер не вставить — он заменил бы List
/// ```
///
/// Разбор маски, затемнения и подмены титула у обоих сошёлся до строки —
/// оба читали одни кадры и один `posterHeader`. **Это не значит, что
/// копии можно оставить:** две реализации одного правила у Того уже
/// расходились молча. Решение, какой из двух домов общий, принимает
/// не исполнитель: оба файла должны сперва оказаться в git, иначе один
/// автор будет строить на том, что у другого ещё может исчезнуть.
///
/// ## Откуда числа
///
/// ```
/// кегль 36, трекинг −0,9    Token.FontSize.titleLarge, Token.FontTracking.titleLarge
///                           ЖИВЫХ ЧИТАТЕЛЕЙ У ОБОИХ БЫЛО НОЛЬ (замер 23.10.2026:
///                           grep titleLarge по *.swift — объявление и комментарий,
///                           ни одного вызова). Эта шапка — первый.
/// прототип говорит 34/−0,02em  Togo-RU.dc.html, `.bigt` в шапке страницы.
///                           Расхождение прозы и токена названо, а не усреднено:
///                           взят ТОКЕН, потому что источник правды по токенам —
///                           DesignTokens/tokens.json, и ступень 36 заведена
///                           в него решением 22.10 (`6821646`).
/// высота фото 360           `Token.Size.backdropSub`. Прототип говорит то же
///                           число: `if (S.sub) m = [SUBP[kind], '50% 35%', '360px']`.
///                           Первая редакция этого файла брала `Token.Size.hero`
///                           (тоже 360) — «одно число, два имени». Исправлено
///                           перемером: ступень с нужным ИМЕНЕМ в токенах уже
///                           была, я её не нашёл, потому что грепал по списку
///                           имён, который сам же и придумал.
/// маска 45 % → 92 %         прототип, `-webkit-mask-image`; в токенах
///                           `component.backdrop.mask` теми же двумя стопами.
/// ```
///
/// **Эталонного кадра у этой шапки НЕТ.** `15.png` («Настройки · фон»)
/// негоден — во весь кадр лавандовая пилюля, экрана под ней не видно
/// (`Дизайн/эталонные-кадры/ios28-кино-22.10/ПОДПИСИ.md`). Состав снят
/// с ГОДНЫХ кадров соседних подэкранов — `13.png` (Питание) и `14.png`
/// (Анализы): надпись капсом, под ней крупный заголовок, за ними фото,
/// гаснущее к низу. Это подэкраны ЧУЖИХ волн, то есть основание
/// косвенное, и выдавать его за «сверено с дизайном» нельзя.
@MainActor
struct CinemaHeader: View {

    // Уровень контраста системы читает теперь `TGHeaderScrim` — он
    // и выбирает плотность слоя (.55 против .70). Здесь объявление
    // снято 26.10.2026 как оставшееся БЕЗ ЕДИНОГО ЧИТАТЕЛЯ: после
    // переезда слоя в компонент `контраст` встречался в файле только
    // в своём `@Environment` и в прозе. Замер — `grep` по файлу
    // с вырезанными комментариями: одна строка, и это объявление.
    //
    // Запись, которую стоит сохранить: читать его надо ИЗ ОКРУЖЕНИЯ,
    // а не из `UITraitCollection` — внутри `body` верно первое.
    // В компоненте так и сделано.

    /// Название экрана: ключ каталога либо готовое значение.
    ///
    /// Разведено типом по той же причине, что у `TGPosterHeader.Название`:
    /// `Text` со значением типа `String` рисует текст **дословно, мимо
    /// каталога**, и 23.09.2026 это стоило наполовину русского
    /// французского экрана. `.ключ` — для литералов, `.значение` —
    /// для клички, города, имени участника.
    enum Название {
        case ключ(LocalizedStringKey)
        case значение(String)
    }

    let title: Название
    var надпись: LocalizedStringKey?
    /// Чей фон лежит под шапкой. От этого зависит **семья текста**,
    /// а не только вид: на фотографии честны `Poster.labelOnColor`
    /// и `Poster.captionOnColor` — у них белое значение и в тёмном
    /// столбце, и в светлом, то есть подпись на снимке остаётся
    /// читаемой независимо от того, что лежит в токене.
    ///
    /// **Это НЕ ветка по теме.** Решение Виктории 23.10.2026 — «Кино.
    /// Одна тема»: `UIUserInterfaceStyle = Dark` стоит в обоих plist,
    /// и светлые значения токенов на устройство больше не попадают.
    /// Выбор здесь — между «текст на фотографии» и «текст на чёрном»,
    /// а не между светлой и тёмной.
    ///
    /// Ключ, а не `Bool`: «есть ли фото» обязан отвечать тот же
    /// `BackgroundStore`, который его и рисует. Два ответа на один
    /// вопрос из разных мест разойдутся молча — у нас это записано
    /// про две копии любого числа.
    var экран: ScreenKey?

    /// Класть ли свои боковые отступы.
    ///
    /// На каркасе `TGScreen` отступ уже положен контейнером, и второй
    /// дал бы двойной — поэтому там `false`. Параметр, а не догадка
    /// по окружению: окружение решало бы молча, а здесь видно на месте
    /// вызова.
    ///
    /// ~~«В списке шапка едет строкой с нулевыми `listRowInsets`
    /// и отступ кладёт себе сама».~~ **ЛОЖНО, замер пикселем
    /// 25.10.2026.** `listRowInsets(EdgeInsets())` снимает отступ
    /// СТРОКИ внутри секции и НЕ трогает боковое поле самой секции:
    /// у `.insetGrouped` оно своё, 16 pt, и наши 18 ложатся поверх него.
    ///
    /// ```
    ///                     карточки     глиф шапки   чем снято
    /// Язык       (List)     16,00 pt     35,00 pt   витрина-279-25.10
    /// Настройки  (List)     16,00 pt     33,33 pt   настройки-кино-23.10
    /// Фон        (List)     16,00 pt     35,33 pt   настройки-кино-23.10
    /// Как это работает      18,00 pt         —      КОНТРОЛЬ, не List
    /// История · Семья ·     18,00 pt     19–20 pt   витрина-279-25.10
    /// Питание · Сегодня
    /// ```
    ///
    /// То есть на четырёх экранах из списка шапка стояла на 17–18 pt
    /// правее своих же карточек, а на остальных тридцати шести —
    /// вровень. **Поэтому в `List` тоже `false`:** строка с нулевыми
    /// вставками начинается там же, где секция, — на 16 pt.
    ///
    /// Остаётся названным и НЕ починенным: 16 pt у `List` против 18 pt
    /// у `TGScreen`. Боковое поле `.insetGrouped` кладёт система,
    /// и подвинуть его на 18 нельзя иначе как через внешний вид
    /// `UITableView` целиком. Два пункта между экранами — меньшее зло,
    /// чем восемнадцать внутри одного.
    var отступы: Bool = true

    init(_ title: LocalizedStringKey,
         надпись: LocalizedStringKey? = nil,
         экран: ScreenKey? = nil,
         отступы: Bool = true) {
        self.title = .ключ(title)
        self.надпись = надпись
        self.экран = экран
        self.отступы = отступы
    }

    init(значение: String,
         надпись: LocalizedStringKey? = nil,
         экран: ScreenKey? = nil,
         отступы: Bool = true) {
        self.title = .значение(значение)
        self.надпись = надпись
        self.экран = экран
        self.отступы = отступы
    }

    @Environment(\.accessibilityReduceTransparency) private var снизитьПрозрачность

    /// Лежит ли под шапкой фотография **сейчас**. Спрашивается у того же
    /// хозяина и с той же оговоркой про сниженную прозрачность, что
    /// в `CinemaBackdrop`: иначе текст оденется в белое там, где фона
    /// уже нет.
    private var наФото: Bool {
        // Ключ берётся из окружения, если не передан явно (облачная
        // сессия 28.10), а условие `!снизитьПрозрачность` СНЯТО
        // (наша починка 27.10) — разбор ниже у самой отрисовки.
        guard let экран = экран ?? экранОкружения else { return false }
        return BackgroundStore.shared.background(for: экран) != nil
    }

    /// Ключ экрана, который назвал `cinemaScreen(экран:)`. Свой шапке
    /// передают только «Настройки»; остальные подэкраны называют себя
    /// ОДИН раз — в подложке, — и шапка берёт ключ отсюда.
    @Environment(\.экранКино) private var экранОкружения

    /// Крупный заголовок «Кино». Стиль собран здесь, а не в `AppFont`,
    /// потому что `AppFont` живёт в чужом сегодня каталоге; значения —
    /// токены, а не числа.
    private var стильЗаголовка: TextStyleToken {
        TextStyleToken(size: Token.FontSize.titleLarge,
                       weight: Token.FontWeight.bold,
                       color: наФото ? Token.Poster.labelOnColor : Token.Ink.primary,
                       relativeTo: .largeTitle)
    }

    private var стильНадписи: TextStyleToken {
        AppFont.caps.color(наФото ? Token.Poster.captionOnColor : Token.Ink.secondary)
    }

    var body: some View {
        VStack(alignment: .leading, spacing: Token.Space.s2) {
            if let надпись {
                Text(надпись)
                    .textStyle(стильНадписи)
                    .textCase(.uppercase)
                    .kerning(0.6)
                    .wraps()
            }
            заголовок
                .tracking(Token.FontTracking.titleLarge)
                // **Две строки и ужатие — находка кадра 23.10.2026.**
                // «Политика конфиденциальности» в 36 pt не помещается
                // в 402 точки ширины, и SwiftUI ломал её ПОСРЕДИ СЛОВА:
                // «конфиденциальност / и». Перенос внутри слова хуже
                // мелкого кегля — слово перестаёт узнаваться.
                //
                // Ограничение строк здесь ОБЯЗАТЕЛЬНО: без него
                // `minimumScaleFactor` не работает вовсе — тексту,
                // которому разрешено расти вниз, ужимать нечего.
                // Тот же разбор записан у `TGStat`.
                .lineLimit(2)
                .minimumScaleFactor(0.6)
                .accessibilityAddTraits(.isHeader)
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .padding(.horizontal, отступы ? Token.Spacing.screenPadding : 0)
        // **Отрицательного отступа здесь быть не может, и это замер,
        // а не осторожность.** `List` кладёт свой верхний запас плюс
        // промежуток перед первой секцией: между кнопкой «назад»
        // и надписью выходит около девяноста точек пустоты, а на годных
        // кадрах подэкранов (13, 14) заголовок стоит почти вплотную.
        // Попытка снять лишнее через `.padding(.top, -s24)` кадр 23.10
        // отверг: строка списка обрезает то, что уезжает за её рамку, —
        // надпись капсом оказалась срезана по верхней кромке. Пустота
        // остаётся названным расхождением с кадрами, а не чинится
        // способом, который портит текст.
        .padding(.top, Token.Space.s2)
        .padding(.bottom, Token.Space.s10)
        // **Свой слой затемнения, и он ОБЯЗАТЕЛЕН — замер пикселем
        // 23.10.2026.** Без него шапка подэкрана на белом снимке давала
        // **1,89:1** при пороге 4,5 (композит `#B0B0DC` под `#F4F4F2`,
        // 7870 глифов в 65 строках, кадр
        // `03-подэкран-белое-обычный.png`).
        //
        // Держало её только общее затемнение `CinemaBackdrop` —
        // то самое, про которое **дизайн прямо сказал 23.10**, отвечая
        // на вопрос «шапка поверх фото» (`943de49`, решение 3):
        //
        // > «Восемь стопов `--bd-scrim` контраст **не гарантируют**:
        // > на белом кадре на 10 % высоты α .52 → 4,3:1, на 25 % α .24
        // > → 1,8:1. Гарантию даёт отдельный слой, привязанный
        // > к шапке.»
        //
        // Наш замер вышел 1,89 — то есть ровно её «на 25 % → 1,8»,
        // с точностью до строки, на которой стоит заголовок. Предсказание
        // дизайна и наш пиксель сошлись независимо.
        //
        // Привязка **к тексту, а не к процентам высоты**: ровная часть
        // кончается там, где кончается шапка, дальше спад 48 pt.
        // Отрицательный отступ уводит спад **за** рамку, чтобы он
        // не раздвигал строку списка.
        .background(alignment: .top) { слойШапки }
    }

    /// Ровное затемнение под текстом шапки плюс спад под ним —
    /// **только когда под шапкой есть фотография**.
    ///
    /// `backdrop.headerScrim`: α `.55`, в повышенном контрасте `.70`,
    /// спад `fadePt` = 48. Числа дизайна; токена у них пока нет —
    /// в пакете лежат, в нашем `tokens.json` нет, хозяин — сессия
    /// токенов. То же записано у `ФотоШапка`, и когда токен появится,
    /// обе шапки переводятся вместе.
    ///
    /// # Почему условие, а не безусловный слой
    ///
    /// Третья ступень цепочки фона — «чёрный #000 **без подложки**:
    /// без фото, без `--bd-scrim`, **без затемнения шапки**» (ответ
    /// круга 2, пункт 1). Это не экономия и не вкус: затемнение нужно,
    /// чтобы белый текст пережил светлое место фотографии, а на `#000`
    /// он и так даёт 21:1.
    ///
    /// **Глазами разницы НЕ ВИДНО, и в этом всё дело.** Слой красится
    /// `Token.Surface.screen` — а это и есть `#000000` темы «Кино»;
    /// чёрный под α .55 поверх чёрного даёт ровно чёрный. То есть
    /// безусловный слой был бы невидимой ошибкой: кадр её не покажет,
    /// сторож на контраст не покраснеет, а экран на каждой перерисовке
    /// платил бы за проход композитора по прямоугольнику во всю ширину.
    /// И вторая половина, которая дороже первой: в день, когда
    /// `Surface.screen` перестанет быть чистым чёрным (светлая тема —
    /// открытый вопрос Виктории), безусловный слой начнёт **подкрашивать
    /// шапку там, где фона нет**, и причину будут искать в шапке.
    ///
    /// Условие берётся у `наФото` — у того же хозяина, что решает,
    /// рисовать ли фото. Второй ответ на тот же вопрос разошёлся бы молча.
    @ViewBuilder
    private var слойШапки: some View {
        if наФото {
            TGHeaderScrim()
        }
    }

    private var заголовок: Text {
        switch title {
        case .ключ(let ключ): Text(ключ).textStyle(стильЗаголовка)
        case .значение(let строка): Text(строка).textStyle(стильЗаголовка)
        }
    }
}

/// Фотография под шапкой: 360 точек сверху, маска к низу, затемнение.
///
/// **Это первый живой читатель `BackgroundStore.background(for:)`
/// в приложении.** Замер 23.10.2026: вызовов `background(for:` — три,
/// и все три свои (объявление в `BackgroundStore`, два в предпросмотре
/// `BackgroundScreen`). Фото человека показывал **только виджет**
/// (`TogoWidgets/TodayWidget.swift`, два обращения к `BackgroundBridge`),
/// а в самом приложении его не видел никто: фича «Фон приложения»
/// складывала снимки в App Group и не рисовала их ни на одном экране.
/// Это наш класс «механизм без входа», только наоборот — **вход есть,
/// показа нет**.
///
/// **Чего он НЕ показывает и почему — ВОПРОС ЗАКРЫТ 23.10.2026.**
/// Прежняя редакция этого абзаца говорила «фото раздела кладёт дизайн,
/// а у нас их нет, и это открытый вопрос к Виктории». Дизайн ответил
/// прямо (`Дизайн/редизайн-ios28/ОТВЕТЫ-круг-2.md`, пункт 1): набора фото
/// разделов не будет вовсе, в прототипе это заглушки Unsplash. Цепочка
/// названа и исполнена в `BackgroundChoice.photoName`:
///
/// ```
/// 1  своё фото раздела        приписки «фото → раздел» у нас нет, и первый
///                             же снимок переводит режим в `single`
/// 2  Dog.photo                `BackgroundBridge.запасноеФото`
/// 3  чёрный #000 БЕЗ ПОДЛОЖКИ не «пустая картинка», а ДРУГОЙ режим
///                             отрисовки: ни маски, ни затемнения
/// ```
///
/// **Третья ступень — решение, а не дыра.** «Чистая установка без фото
/// собаки даёт чёрные вкладки — это нормально» (там же). Шапка стоит
/// на `#000`, белое по нему 21:1, и класть на это затемнение незачем:
/// слой стоил бы прохода композитора и не менял бы ни одного пикселя.
@MainActor
struct CinemaBackdrop: View {
    let экран: ScreenKey

    /// Сниженная прозрачность снимает не блюр (его здесь нет), а само
    /// фото: человек, попросивший систему убрать полупрозрачность,
    /// просил читаемости, а текст поверх фотографии — ровно то,
    /// от чего он отказывается.
    @Environment(\.accessibilityReduceTransparency) private var снизитьПрозрачность
    @Environment(\.dynamicTypeSize) private var размерТекста

    private var store: BackgroundStore { .shared }

    /// Высота подложки — **по типу экрана, а не одна на все**.
    ///
    /// Прямой ответ дизайна на круг 2, пункт 3: «`backdrop.height` —
    /// требование, по типу экрана: „Сегодня“ 640, вкладка 420, подэкран
    /// 360, „На улице“ 520. Стопы `--bd-scrim` заданы в процентах от этой
    /// высоты. При 360 на вкладке плато фото уезжает на 54 pt вверх под
    /// шапку. `size.hero` (360) — карточка-герой, к подложке не относится.
    /// Подложку от него отвязать».
    ///
    /// До 23.10 здесь стоял один `Token.Size.backdropSub` на все четыре
    /// вида — и это было **верно для подэкрана и неверно для трёх
    /// остальных**: 360 и 360 совпадали по числу, поэтому расхождение
    /// не видел ни компилятор, ни сторож. Ветка по `экран.kind`, а не
    /// по своему перечислению: имена случаев `BackdropKind` совпадают
    /// с ключами токена побуквенно нарочно.
    ///
    /// Крупный кегль по-прежнему ужимает подложку до `heroAX`: иначе
    /// шапка выдавливает содержимое за экран. Это НАША ось, у хендоффа
    /// её нет, и она старше ответа круга 2 — правило взято у `ReadingPanel`
    /// и у `КиноЭкран`.
    private var высота: CGFloat {
        guard !размерТекста.isAccessibilitySize else { return Token.Size.heroAX }
        switch экран.kind {
        case .today: return Token.Size.backdropToday
        case .tab: return Token.Size.backdropTab
        case .sub: return Token.Size.backdropSub
        case .walk: return Token.Size.backdropWalk
        }
    }

    var body: some View {
        ZStack(alignment: .top) {
            Token.Surface.screen
            // ФОТО РИСУЕТСЯ И ПРИ СНИЖЕННОЙ ПРОЗРАЧНОСТИ.
            //
            // Было `if !снизитьПрозрачность` — и человек с этой
            // настройкой получал ЧЁРНЫЙ ЭКРАН вместо фотографии
            // на каждом экране приложения. Жалоба 27.10.2026: «у мамы
            // в новой сборке тоже изображения нет».
            //
            // Настройка системы называется «Уменьшение прозрачности»
            // и убирает РАЗМЫТИЯ И ПОЛУПРОЗРАЧНОСТЬ — материалы,
            // сквозь которые видно нижележащее. Фотография
            // непрозрачна; к прозрачности она отношения не имеет.
            // Мы убирали её заодно, и заодно убирали весь замысел
            // «Кино».
            //
            // > Настройку доступности прочитали как «поменьше
            // > красивого». Она про ЧИТАЕМОСТЬ, а чёрный экран
            // > читаемости не прибавляет — он отнимает смысл.
            //
            // Что при этом ДЕЙСТВИТЕЛЬНО меняется: затемнение под
            // текстом становится плотнее (`TGHeaderScrim` берёт
            // `alphaHC`), то есть белые буквы держат контраст без
            // стеклянной подложки. Стекло у панелей по-прежнему
            // заменяется сплошной плашкой — там условие верное
            // и осталось нетронутым (`TGGlass`, `TGGlassPanel`).
            // `КэшСнимков` вместо `UIImage(data:)` — из облачной
            // сессии 28.10: декодирование JPEG в `body` на главном
            // потоке было одной из причин зависания «Сегодня».
            if let фото = store.background(for: экран),
               let картинка = КэшСнимков.картинка(фото.data) {
                // **Размер даёт `Color.clear`, а не снимок, и это
                // починка раскладки, а не стиль** (замер 26.10.2026).
                //
                // Было `Image….scaledToFill().frame(maxWidth:.infinity)
                // .frame(height:).clipped()`. `.clipped()` режет
                // РИСОВАНИЕ и не уменьшает место, которое вид занимает
                // в раскладке: `scaledToFill` сообщает наружу размер
                // переросшего снимка.
                //
                // ```
                // снимок 600×800, подложка 402×640
                // scaledToFill → max(402/600, 640/800) = 0,8 → 480×640
                // рамка блока в дереве доступности  480 при экране 402
                // содержимое центрируется в 402 и уезжает на −39
                // ```
                //
                // На кадре это читалось так: «Сегодня» обрезано
                // в «егодня», «07:02» в «7:02», кнопка «Просится»
                // начинается за левым краем. Фото при этом обрезано
                // ПРАВИЛЬНО — полосы примет срезаны ровно на 39 pt
                // с каждой стороны, — и потому дефект выглядел как
                // особенность снимка.
                //
                // > **Я сперва списала это на служебную фикстуру
                // > и записала «фикстура ломает раскладку».** Неверно:
                // > фикстура — первый случай, когда фотография вообще
                // > появилась. Чистый кадр лежал ровно не потому, что
                // > он честнее, а потому что фона на нём не было
                // > вовсе. Любое портретное фото собаки даёт то же.
                //
                // **Форма взята у `ФотоШапка.swift:200`, а не придумана
                // своя.** Там этот же механизм разобран и починен
                // раньше — «`.background` обратной связи не даёт: его
                // содержимому предлагают размер хозяина, а не наоборот.
                // Поэтому снимок больше не участвует в раскладке
                // вовсе». Починили в одном месте и не перенесли
                // в соседнее.
                //
                // `Color.clear` здесь нельзя: литеральный цвет
                // заворачивает `DesignLiteralTests` («цветов строго
                // ноль») — тем же запретом, что отмёл `.black`
                // в маске ниже.
                //
                // **ЯКОРЬ КАДРИРОВАНИЯ, 04.11.2026.** Здесь стояло
                // `Image….resizable().scaledToFill()` — и кадрировало
                // ПО ЦЕНТРУ, потому что так делает `scaledToFill`,
                // а не потому, что так решили. На портретном снимке
                // центр приходится на корпус собаки, и отзыв 28.10
                // сказал ровно это: «срезает голову».
                //
                // Доля — из прототипа (`bd.pos`), разбор и замер
                // отсутствия токена — в голове `ЯкорьКадра`. На
                // «Сегодня» правило не меняет ни пикселя у снимка
                // 3 : 4: там режется ширина, а по ширине якорь 50 %,
                // то есть центр. Это не совпадение и не осторожность —
                // 25.10 кадром измерено, что верх цел только там.
                Token.Surface.screen
                    .frame(maxWidth: .infinity)
                    .frame(height: высота)
                    .overlay {
                        КадрПоЯкорю(картинка: картинка,
                                    якорь: .по(виду: экран.kind))
                    }
                    .clipped()
                    .mask { маска }
                    .overlay { затемнение }
                    // Фото — оформление. Голосом его читать нечем,
                    // а подпись к нему была бы выдумкой: мы не знаем,
                    // что на фотографии человека.
                    .accessibilityHidden(true)
            }
        }
    }

    /// Фото гаснет к низу: сплошное до 45 % высоты, прозрачное к 92 % —
    /// компонент `TGBackdropMask`, оба стопа из токена.
    ///
    /// # Здесь стояла своя копия тех же двух стопов
    ///
    /// ~~«Два стопа — те же, что в прототипе и в `component.backdrop.mask`.
    /// Цвет берётся из `Token.Ink.primary` не ради цвета: маску читает
    /// только альфа-канал, а литеральный `.black` слой вида не пускает
    /// (`DesignLiteralTests`, „цветов строго ноль“)».~~
    ///
    /// Довод про `.black` был верен, а вывод из него — нет: токен
    /// `Token.Component.Backdrop.mask` несёт **те же** два стопа чёрным
    /// с альфой, и звать его можно, нельзя только из экрана. Замер
    /// 26.10.2026: читателей у токена в Swift было **ноль** при живом
    /// контроле на соседнем `Backdrop.scrim` (один, `TGBackdropScrim`).
    ///
    /// > **Доккомментарий назвал токен по имени и всё равно не был
    /// > вызовом.** Проза вырезается до разбора, поэтому
    /// > `ComponentTokenScopeTests` молчал честно.
    ///
    /// Правка **не меняет ни одного пикселя**: `.mask` читает только
    /// альфа-канал, а по альфе `Ink.primary`/`opacity(0)` и
    /// `#000000FF`/`#00000000` совпадают. Меняется то, откуда взяты
    /// числа, — и это не косметика: `Token.Ink.primary` к маске
    /// отношения не имеет, и в день, когда у него появится своя альфа,
    /// маска поедет без всякой связи с макетом. Разбор — в голове
    /// `TGBackdropMask`.
    private var маска: some View {
        TGBackdropMask()
    }

    /// Затемнение сверху и к низу — компонент `TGBackdropScrim`,
    /// все восемь стопов дизайна. Без затемнения заголовок ложится
    /// на светлое место фотографии и пропадает.
    ///
    /// # Здесь стояли ТРИ стопа вручную, и это был обход
    ///
    /// Разбор, замеры и происхождение — в голове `TGBackdropScrim`.
    /// Коротко: `Token.Surface.scrim` **рисовался синим** (`Color+Hex`
    /// решал про альфу по величине числа, а `0x0000008C` это 140,
    /// что ≤ 0xFFFFFF), обход выражал ту же величину долями
    /// от `Token.Surface.screen` — и **дефект починили 23.10.2026
    /// в генераторе**, ровно там, где обход и предписывал. Причина
    /// ушла, обход остался на три дня, а объяснение рядом с ним
    /// читалось как действующее.
    ///
    /// Цена была не в оттенке: у восьми стопов есть **плато 30–38 %,
    /// окно фото** — самое светлое место кадра, где собаку видно.
    /// В трёх стопах его не было вовсе.
    ///
    /// Замер 23.10.2026 по кадру `01-today.png` (1206×2622): верхняя
    /// треть «Сегодня» шла чистым `rgb(0, 0, B)` — B 98 наверху,
    /// 22 в середине, 140 внизу. Это ровно `#00008C` под 0,70 · 0,15 ·
    /// 1,00 поверх чёрного полотна, до единицы. То есть «индиговая
    /// подложка» — не плакат, а потерянная альфа.
    ///
    /// ~~Чинится не здесь: из целого числа разрядность
    /// не восстановить, правка — в генераторе токенов.~~
    ///
    /// # ПРИЧИНА ОБХОДА УШЛА 23.10.2026, А ОБХОД ОСТАЛСЯ
    ///
    /// Замер 26.10.2026. Дефект потери альфы **починен в тот же день,
    /// когда был найден**, и починен ровно там, где эта строка
    /// и предписывала — в генераторе:
    ///
    /// ```
    /// Color+Hex.swift:13-35   «Здесь НЕТ угадывания разрядности,
    ///                          и это починка 23.10.2026».
    ///                          `hasAlpha = hex > 0xFFFFFF` снято;
    ///                          инициализатор принимает ТОЛЬКО восемь
    ///                          разрядов и ничего не решает
    /// generate_tokens.py       дополняет шестизначные до 0xRRGGBBAA
    ///                          на входе, пока значение ещё СТРОКА
    /// Tokens.generated.swift:78
    ///   scrim = Dyn(dark: 0x0000008C, …)   восемь разрядов, альфа 8C
    ///                                       = 140 = 55 %. Корректно
    /// ```
    ///
    /// То есть `Token.Surface.scrim` **больше не рисуется синим**,
    /// и доли от `Token.Surface.screen` (0,85 · 0,55 = 0,47;
    /// 0,25 · 0,55 = 0,14) — обход причины, которой нет.
    ///
    /// > **Это наш класс «условие, привязанное к инструменту, меняет
    /// > знак»** — и меняет в момент успеха, когда никто не ждёт
    /// > плохих новостей. Обход был верен, пока парсер терял альфу;
    /// > парсер починили, а обход остался и продолжает читаться как
    /// > действующее объяснение. Утверждение «потому что он рисуется
    /// > синим» устарело молча.
    ///
    /// И цена обхода была не в красоте: у дизайнера затемнение — **восемь
    /// стопов** (`backdrop.scrimStops`, `Token.Component.Backdrop.scrim`),
    /// с плато между 30 % и 38 %, которое и есть ОКНО ФОТО, самое
    /// светлое место кадра, где собаку видно. Здесь стояли **три**,
    /// и плато в них не было вовсе: расхождение с макетом было
    /// не оттенком, а пропавшим окном.
    ///
    /// ~~«Возврат восьми стопов — работа общая с
    /// `ReadingPanel.glassRadius`/`height`: у всех трёх одна форма —
    /// экрану нельзя звать `Token.Component.*`, нужен компонент-читатель
    /// в `Togo/DesignSystem/`, как `TGHeaderScrim`».~~
    ///
    /// **ВСЕ ТРИ ЗАКРЫТЫ, и перечитать это некому было бы без правки
    /// рядом.** Восемь стопов приехали компонентом `TGBackdropScrim`
    /// (`30a2835`), `glassRadius` и `height` — `TGGlassPanel`
    /// и `.высотаПанелиПоказания()` (26.10.2026). Строка выше
    /// утверждала «здесь стоят три» уже при `TGBackdropScrim()`
    /// в теле — то есть устарела **в том же коммите, который её
    /// опроверг**, и прожила так до следующего, кто пришёл за соседним
    /// токеном.
    ///
    /// > **Запись, называющая долг, обязана умирать вместе с долгом.**
    /// > Оставленная, она читается как действующее описание кода,
    /// > который лежит двадцатью строками ниже и говорит обратное.
    ///
    /// Что здесь по-прежнему **не** закрыто: решение о смене вида —
    /// Виктории, и кадровой приёмки у восьми стопов до сих пор нет
    /// (стенд у `projects-4e`). Четвёртый случай того же семейства
    /// в этом же узле — `Backdrop.mask`, закрыт `TGBackdropMask` выше.
    private var затемнение: some View {
        TGBackdropScrim()
    }
}

extension View {

    /// Надеть на экран тему «Кино»: чёрный фон, прозрачная панель
    /// навигации и фотография под шапкой.
    ///
    /// **Заголовок в панели навигации гасится, а `navigationTitle`
    /// остаётся.** Снять его нельзя: по нему подписана кнопка «назад»
    /// у дочерних экранов и им экран называет себя VoiceOver. Поэтому
    /// гасится ПОКАЗ, и гасится он **непустым** видом — замер
    /// `TGPosterHeader` 07.10.2026: `EmptyView()` в `ToolbarItem` SwiftUI
    /// считает отсутствием пункта, подмены не происходит вовсе, и на
    /// живом кадре название экрана выходило ДВАЖДЫ. Подменыш прячется
    /// от озвучки — иначе `Color.clear` наследует ярлык у `navigationTitle`
    /// и VoiceOver читает название дважды.
    ///
    /// **Фон панели скрыт, а не перекрашен:** в кадрах 13 и 14 фотография
    /// уходит под статус-бар, и материал системной панели её бы срезал.
    ///
    /// - Parameter экран: чьё фото показывать. `nil` — экран без фото,
    ///   просто чёрный.
    ///
    ///   **С 04.11.2026 это значит ровно то, что написано.** Прежняя
    ///   редакция добавляла: «так сделаны подэкраны на каркасе
    ///   `TGScreen`, который рисует свою непрозрачную подложку
    ///   и фотографию под собой не пропустит», — и это было верно
    ///   про каркас и неверно про замысел. Каркас правился в тот же
    ///   день (`TGScaffolds.swift`, полотно стало условным), и теперь
    ///   `nil` выбирают, а не получают по умолчанию.
    func cinemaScreen(экран: ScreenKey? = nil) -> some View {
        self
            // Шапка внутри берёт ключ отсюда — одно место на экран,
            // а не два, которые разойдутся.
            .environment(\.экранКино, экран)
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .principal) {
                    Color.clear
                        .frame(width: Token.Size.hairline, height: Token.Size.hairline)
                        .accessibilityHidden(true)
                }
            }
            .background(alignment: .top) {
                Group {
                    if let экран {
                        CinemaBackdrop(экран: экран)
                    } else {
                        Token.Surface.screen
                    }
                }
                .ignoresSafeArea()
            }
            .toolbarBackground(.hidden, for: .navigationBar)
            // ВУАЛЬ ПОД ВЕРХНЕЙ ПАНЕЛЬЮ. Отзыв 04.11.2026, сборка 293:
            // «фотки не подгрузились и навигация сломалась».
            //
            // На кадре прокрученный список: текст из середины экрана
            // виден под кнопкой «назад» и под часами. Содержимое
            // уезжает вверх, а панель прозрачна (`toolbarBackground
            // .hidden` строкой выше — он нужен, чтобы фотография
            // доходила до статус-бара).
            //
            // Пока под панелью было ЧЁРНОЕ ПОЛОТНО каркаса, это
            // не бросалось в глаза: чёрный текст на чёрном. Сегодня
            // полотно стало условным, фотография раскрылась — и то же
            // наложение стало видно.
            //
            // > **Правка раскрыла фон и обнажила дефект, который был
            // > всё это время.** Человек прочитал его как «сломалась
            // > навигация», и он прав: кнопка «назад» стоит на тексте.
            //
            // Градиент, а не плашка: ровная кромка дала бы тот же шов,
            // за который платили 27.10. Высота — под самый высокий
            // вырез плюс панель; слой не скроллится и живёт над фото,
            // но под содержимым панели.
            .overlay(alignment: .top) {
                LinearGradient(
                    colors: [Token.Surface.screen.opacity(0.75),
                             Token.Surface.screen.opacity(0)],
                    startPoint: .top, endPoint: .bottom)
                .frame(height: ВуальПанели.высота)
                .ignoresSafeArea()
                .allowsHitTesting(false)
                .accessibilityHidden(true)
            }
    }


}

