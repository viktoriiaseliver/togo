import SwiftUI

/// «Вне приложения» — виджет, живая активность и голос.
///
/// ## Зачем экран понадобился
///
/// Виджеты, Live Activity и интенты Siri в проекте **написаны
/// и работают** (`TogoShared/Widgets/`, `TogoShared/LiveActivity/`,
/// `Togo/Intents/`), а человек из приложения не узнавал о виджете
/// ничего: единственным местом, где его можно было увидеть, оставалась
/// отладочная галерея под `#if DEBUG` (`SettingsScreen.swift:487`).
/// Механизм есть, входа к нему нет — та самая форма, которую
/// не ловит ни компилятор, ни тест.
///
/// Замер 28.10.2026, которым это найдено:
///
/// ```
/// «Вне приложения»                  0 вызовов в Swift
/// «Виджеты и блокировка»            0
/// «Live Activity и Dynamic Island»  0
/// «Виджеты и Live Activity»         только в КОММЕНТАРИЯХ двух файлов
/// контроль: «Поддержка»             2 файла, живая ссылка в настройках
/// ```
///
/// > **Строка, которая встречается только в комментарии, грепом
/// > выглядит живой.** Заголовки этого экрана переведены на четыре
/// > языка — работа переводчика была оплачена, — и ни один из них
/// > не доходил до экрана.
///
/// ## Границы
///
/// Голос и метка у двери **намеренно не дублируются**: про них
/// целиком рассказывает `DoorTagScreen` («Метка у двери»), включая
/// Siri, кнопку «Действие» и Пункт управления. Здесь — только то,
/// чего не показывает никто: виджет и живая активность. Вторая копия
/// рассказа разошлась бы с первой молча.
///
/// Все строки взяты из каталога, где они **уже лежали с переводами
/// на en/fr/kk/uk**. Новых строк экран не вводит намеренно: русская
/// строка без перевода легла бы русской в пять локалей, и это хуже
/// отсутствия экрана. `LocalizedStringKey` у `TGIconRow`
/// и `TGExplainer` проверен по их объявлениям — `Text(String)` рисовал
/// бы дословно, и так уже было в `HowItWorksScreen` и в пейволле.
struct ВнеПриложенияScreen: View {
    var body: some View {
        TGScreen {
            // Надпись — «Виджеты», а не «iOS 28» из прототипа: «iOS 28»
            // завело бы в каталог новый ключ, а «Виджеты» там уже лежит
            // с переводом на четыре языка. Технический ярлык вроде `NFC`
            // в каталоге живёт без переводов, но заводить такой ради
            // украшения шапки незачем.
            CinemaHeader("Вне приложения", надпись: "Виджеты", отступы: false)

            TGCard {
                TGSectionHeader(title: "Виджеты и блокировка")
                TGIconRow(symbol: "square.grid.2x2",
                          title: "Виджет",
                          detail: "Снимки лежат на телефоне и уезжают только в виджет — он берёт то же фото, что и экран. Длинная сторона ужимается до тысячи точек, чтобы не занимать место.")
            }

            TGCard {
                TGSectionHeader(title: "Live Activity и Dynamic Island")
                TGIconRow(symbol: "timer",
                          title: "На блокировке",
                          detail: "Запускает таймер прогулки, не открывая приложение. Отметки можно ставить с экрана блокировки.")
            }

            TGExplainer(text: "«Togo: прогулка» — Siri поймёт и на часах.")
        }
        .navigationTitle("Вне приложения")
        // Имени «outside» в раскладке нет — подложку этому экрану
        // не назначали, и он берёт запасную по виду (`герой`),
        // как все соседние экраны настроек.
        //
        // Ключ нужен не ради фона, а ради ОДНООБРАЗИЯ: до 04.11.2026
        // это был единственный безключевой вызов из сорока четырёх,
        // и после того, как полотно `TGScreen` стало условным, он
        // остался бы единственным чёрным экраном среди фотографий —
        // причём не по решению, а по тому, что его забыли.
        .cinemaScreen(экран: .sub("outside"))
    }
}
