import Foundation

extension AppState {
    /// Можно ли этому человеку править и удалять запись.
    ///
    /// Раньше экраны спрашивали только `can(.editRecords)`, а сводка роли
    /// «Ухаживающий» обещала «правка 24 ч» — срока не было нигде. Теперь
    /// право и срок роли проверяются одной функцией (`FamilyRole.mayEdit`).
    ///
    /// Возраст записи считается от момента, когда её **записали**
    /// (`enteredAt`), а у обычных записей, где это поле пусто, — от `date`:
    /// там они совпадают, пока `date` не правили. Перед первой правкой
    /// времени редактор закрепляет момент записи
    /// (`LogEvent.закрепитьМоментЗаписи`) — иначе перенос записи на
    /// «сейчас» продлевал бы срок роли.
    func canEdit(_ event: LogEvent, at now: Date = Date()) -> Bool {
        role.mayEdit(recordedAt: event.enteredAt ?? event.date,
                     with: permissions, at: now)
    }
}

extension LogEvent {
    /// Запомнить, когда запись сделали, до того как ей передвинут время.
    ///
    /// Пустой `enteredAt` значит «записали тогда же, когда случилось» —
    /// и это перестаёт быть правдой с первой правкой `date`. Без
    /// закрепления срок правки ухаживающего (24 ч) отсчитывался бы
    /// от нового времени: перенёс запись на сейчас — и правь её ещё сутки.
    /// Уже заполненный момент (запись по памяти) не трогаем.
    func закрепитьМоментЗаписи() {
        if enteredAt == nil { enteredAt = date }
    }
}
