/// Входы стенда к трём местам `РядЧисел`, **недостижимым ни одним
/// сценарием** на 26.10.2026.
///
/// # Зачем это существует
///
/// Правка «ряд из трёх чисел становится столбцом на крупном кегле»
/// (`475072b`) легла в семь мест. Кадром подтвердить удалось **два**
/// (`Дизайн/кадры-приёмки/четыре-партии-26.10/ПОДПИСИ.md`), и причина
/// у остальных пяти — не раскладка, а вход:
///
/// ```
/// место              почему кадра не было        чем лечится
/// ─────────────────────────────────────────────────────────────────
/// HeatScreen         строки «Цикл» НЕТ в дереве  данные (здесь)
/// UsageLogScreen     report.isEmpty → плашка     данные (здесь)
///                    ВМЕСТО блока с рядом
/// FoodStockScreen    gramsPerDay == 0 → ряда     данные (здесь)
///                    нет даже в редакторе
/// TrainingScreens    дорога не писалась          ТЕСТ, не данные
/// TodaySummaryStrip  прокрутка встала раньше     ТЕСТ, не данные
/// ```
///
/// > **Две последние строки — не отказ стенда, и это замер, а не
/// > поправка к формулировке.** `TrainingSessionScreen.finish()`
/// > не требует ни отметок, ни трёх минут (`guard let dog` —
/// > единственное условие), то есть шторка итога занятия достижима
/// > «Начать занятие» → «Закончить на удаче» **без всякой фикстуры**.
/// > Класть сюда вход для неё значило бы завести данные, без которых
/// > экран и так открывается, — и спрятать за ними настоящую причину:
/// > дороги не было написано.
///
/// # Три флага, а не один и не правка общего засева
///
/// Решение менеджера смены 26.10 дословно: «заводи отдельные флаги,
/// а не правь общий засев так, чтобы поехали живые партии». Цена
/// общего засева измерена в тот же день — фотография собаки из App
/// Group пережила перезапуск и заразила чужой прогон, устройство
/// пришлось стирать.
///
/// Поэтому: без флага **ни одно поле не трогается вовсе**, и сорок
/// с лишним чужих UI-тестов идут ровно тем путём запуска, что
/// и до этого файла.
///
/// # Журнал действий держится В ПАМЯТИ, а не на диске
///
/// `UsageLog.entries()` читает `usage.jsonl` из `.documentDirectory`
/// приложения, и файл **переживает запуск**. Положи фикстуру туда —
/// и её унаследует каждый следующий прогон молча: `test12ЖурналДействий`
/// проверяет ровно обратное («журнал выключен и пуст»), и погас бы он
/// не от правки, а от соседа по смене.
///
/// Снятие фикстуры на каждом запуске с `-UITesting` — тоже не выход:
/// ровно это 25.10 стоило шести заходов (`ФонФикстураСтенда`, разбор
/// «Снятие — ОТДЕЛЬНЫЙ флаг»). Поэтому записи **не пишутся никуда**:
/// место вызова (`UsageLogScreen.reload`) берёт их отсюда вместо
/// диска. Нечего наследовать — нечего и снимать.
nonisolated enum ФикстурыМестРядаЧисел {

    static let флагЦикла = "-ФикстураЦикла"
    static let флагЗапаса = "-ФикстураЗапаса"
    static let флагЖурнала = "-ФикстураЖурнала"

    private static func просили(_ флаг: String) -> Bool {
        ProcessInfo.processInfo.arguments.contains(флаг)
    }

    /// Единственная дверь для засева. Зовётся из `SeedData`
    /// **после** наполнения собаки: цикл правит её поля, а запас
    /// читает `dailyGrams`.
    @MainActor
    static func применить(к dog: Dog, context: ModelContext, стенд: Bool) {
        guard стенд else { return }
        if просили(флагЦикла) { положитьЦикл(к: dog, context: context) }
        if просили(флагЗапаса) { положитьЗапас(к: dog, context: context) }
    }

    // MARK: - Цикл

    /// Пол и три записи течки.
    ///
    /// # Пол — это и есть вход, а не украшение
    ///
    /// `Dog.tracksHeat` равно `sex == .female && !isNeutered`
    /// (`Dog.swift:303`), а ссылка «Цикл» стоит под `if dog.tracksHeat`
    /// (`DogTab.swift:463`). `SeedData` пол не ставит **ни в одном
    /// из одиннадцати сценариев** — `sexRaw` остаётся `.unknown`,
    /// то есть строки «Цикл» нет в природе стенда, и экран недостижим
    /// не «неудобно», а **никак**.
    ///
    /// # Почему три записи, а не одна
    ///
    /// Ряд чисел живёт в `forecastCard`, а тот рисуется только при
    /// `!records.isEmpty`. Одной записи хватило бы для показа, но
    /// не для предмета: `HeatCycle.forecast` даёт среднее лишь
    /// от двух промежутков (`minimumRecordsForAverage`), а без него
    /// `averageIntervalDays` равен `nil` и третье число ряда
    /// печатается прочерком — **ряд из трёх чисел, в котором одно
    /// число не число.** На кадре «—» не отличить от обрезанной
    /// подписи, то есть предмет приёмки был бы наполовину съеден
    /// данными.
    ///
    /// Поэтому записей три: промежутки 185 и 165 дней, среднее 175,
    /// `isEstimate` ложно, все три числа настоящие.
    ///
    /// # Даты считаются ОТ «сейчас», и это обратное решение к `-ДемоТ4`
    ///
    /// У демо-Т4 даты абсолютные, потому что его предмет — подписи
    /// месяцев на кадре. Здесь предмет — **раскладка ряда**, и абсолютные
    /// даты сделали бы «дней осталось» отрицательным через полгода:
    /// кадр покраснел бы по календарю, а не по коду. Тот же довод,
    /// что у `добавитьЯнтарь`.
    ///
    /// # Заметка длинная НАРОЧНО
    ///
    /// `строкаИстории` (`HeatScreen.swift:118`) — **второе место
    /// на этом экране с ветвлением по кеглю**, и его тоже не видел
    /// никто. Короткая заметка не отличила бы столбец от строки:
    /// обе ветки выглядели бы одинаково. Длинная показывает ровно то,
    /// ради чего ветка написана, — перенос по словам вместо многоточия.
    @MainActor
    private static func положитьЦикл(к dog: Dog, context: ModelContext) {
        dog.sex = .female
        dog.isNeutered = false

        func назад(_ дней: Int) -> Date {
            Calendar.current.date(byAdding: .day, value: -дней, to: .now) ?? .now
        }

        // Все три ЗАКОНЧЕНЫ: незакрытая запись подняла бы над карточкой
        // баннер «Идёт · день N» (`ongoingCard`), а он сдвигает ряд ниже
        // сгиба на крупном кегле — то есть фикстура сама унесла бы
        // предмет с кадра.
        let записи = [
            HeatRecord(startedAt: назад(370), endedAt: назад(370 - 20),
                       note: "первая, прошла спокойно"),
            HeatRecord(startedAt: назад(185), endedAt: назад(185 - 19),
                       note: "беспокойная, на прогулках тянула к кобелям — "
                           + "держала на коротком поводке всю третью неделю"),
            HeatRecord(startedAt: назад(20), endedAt: назад(1),
                       note: "как обычно"),
        ]
        for запись in записи {
            запись.dog = dog
            context.insert(запись)
        }
        print("ФИКСТУРА-ЦИКЛА: пол female, записей \(записи.count), "
              + "промежутки 185 и 165 дней → среднее 175, прогноз НЕ ориентир")
    }

    // MARK: - Запас корма

    /// Один корм с заполненными полями.
    ///
    /// # Чего именно не хватало
    ///
    /// Ряд лежит в шторке редактора под `if let days = preview.daysLeft()`
    /// (`FoodStockScreen.swift:426`), а `daysLeft()` отвечает `nil` при
    /// `gramsPerDay == 0` (`FoodStock.swift:91`). `FoodStock`
    /// в `SeedData` не заводится **ни одного**, то есть на экране «Чем
    /// кормим» стенда пусто, а у новой записи `gramsPerDay` это `0`
    /// по умолчанию (`@State`, `:216`).
    ///
    /// # Граммы в день ставятся ЯВНО, а не берутся у собаки молча
    ///
    /// `save()` у редактора пишет `isOnlyFood ? dog.dailyGrams
    /// : gramsPerDay` (`:475`), то есть у живой записи с единственным
    /// кормом в поле лежит дневная норма. Фикстура повторяет **результат
    /// сохранения**, а не обходит его: иначе она строила бы состояние,
    /// которого путь человека не даёт.
    ///
    /// Ноль в норме — громкий отказ, а не подстановка: без него
    /// `daysLeft()` снова вернёт `nil`, ряд не нарисуется, и кадр выйдет
    /// пустым при зелёном прогоне. Ровно та цена, из-за которой этот
    /// файл и заведён.
    ///
    /// Остаток дробный (2,5 мешка) нарочно: `packsLeft` объявлен
    /// `Double` потому, что мешок початый, и целое число скрыло бы,
    /// работает ли формат.
    @MainActor
    private static func положитьЗапас(к dog: Dog, context: ModelContext) {
        let вДень = dog.dailyGrams
        guard вДень > 0 else {
            preconditionFailure("""
                -ФикстураЗапаса просит дневную норму, а у собаки \
                dailyGrams == 0. Ряд «хватит на · кончится · купить \
                на месяц» лежит под `if let days = preview.daysLeft()`, \
                и при нулевой норме его не нарисует ничто — кадр выйдет \
                пустым, а прогон зелёным. Фикстура кладётся поверх \
                сценария, у которого норма записана (`today` и соседи: \
                setServingGrams(60) × 2 кормления = 120 г).
                """)
        }
        let запас = FoodStock(kind: .dry, brand: "Acana ягнёнок",
                              packGrams: 3000, packsLeft: 2.5,
                              gramsPerDay: вДень)
        запас.dog = dog
        context.insert(запас)
        print("ФИКСТУРА-ЗАПАСА: сухой, 3000 г × 2,5 мешка, \(вДень) г в день "
              + "→ хватит на \(запас.daysLeft().map(String.init) ?? "—") дней")
    }

    // MARK: - Журнал действий

    /// Записи журнала **вместо чтения диска**, или `nil` — тогда место
    /// вызова читает диск, как и было.
    ///
    /// # Почему ряд был недостижим
    ///
    /// `UsageLogScreen:22` при `report.isEmpty` рисует плашку «Журнал
    /// пока пуст» **вместо** блока `summary`, в котором лежит ряд.
    /// А `UsageLog.isOn` под `-UITesting` возвращает `false`
    /// принудительно (`UsageLog.swift:187`) — и правильно: робот,
    /// нажимающий всё подряд за минуту, наполнил бы журнал действиями,
    /// которых человек не делал. Снимать этот запрет нельзя; обойти
    /// его данными — можно.
    ///
    /// # Что именно построено
    ///
    /// Три сеанса в три разных дня. Числа ряда выходят из состава,
    /// а не задаются: `total` — все записи, `records` — только
    /// `.record` с исходом `.done`, `sessions.count` — сеансы.
    ///
    /// Сеанс определяется промежутком в четверть часа
    /// (`UsageLog.sessionGap`), но `UsageReport.sessionList` группирует
    /// по **полю `session`**, а не по времени, — поэтому имена сеансов
    /// здесь разные, и разнесены они ещё и по дням, чтобы `report.days`
    /// не вышел единицей и карточка «по дням» нарисовалась тоже.
    ///
    /// Два действия нарочно не `.done`: `UsageReport` считает трения
    /// по исходам, и блок «что чинить» без них рисует баннер «ни одного
    /// трения», то есть на кадре не было бы половины экрана.
    static func записиЖурнала(стенд: Bool) -> [UsageLog.Entry]? {
        guard стенд, просили(флагЖурнала) else { return nil }

        func когда(_ днейНазад: Int, _ час: Int, _ минута: Int) -> Date {
            let календарь = Calendar.current
            let день = календарь.date(byAdding: .day, value: -днейНазад, to: .now) ?? .now
            return календарь.date(bySettingHour: час, minute: минута, second: 0, of: день) ?? день
        }

        func запись(_ сеанс: String, _ когдаТо: Date, _ экран: UsageLog.Screen,
                    _ действие: UsageLog.Action, _ уточнение: String? = nil,
                    _ исход: UsageLog.Outcome = .done) -> UsageLog.Entry {
            UsageLog.Entry(at: когдаТо, session: сеанс, screen: экран.rawValue,
                           action: действие.rawValue, outcome: исход.rawValue,
                           detail: уточнение)
        }

        let записи: [UsageLog.Entry] = [
            // Позавчера утром: обычный заход с записью еды и выхода.
            запись("стенд-1", когда(2, 7, 30), .today, .open),
            запись("стенд-1", когда(2, 7, 32), .today, .record, "meal"),
            запись("стенд-1", когда(2, 7, 41), .needs, .open),
            запись("стенд-1", когда(2, 7, 43), .needs, .record, "outing"),
            запись("стенд-1", когда(2, 7, 44), .today, .undo, "outing", .cancelled),

            // Вчера вечером: прогулка целиком.
            запись("стенд-2", когда(1, 19, 10), .today, .open),
            запись("стенд-2", когда(1, 19, 11), .walk, .start),
            запись("стенд-2", когда(1, 19, 18), .walk, .mark, "urine"),
            запись("стенд-2", когда(1, 19, 26), .walk, .mark, "stool"),
            запись("стенд-2", когда(1, 19, 34), .walk, .finish),
            запись("стенд-2", когда(1, 19, 35), .walk, .record, "walk"),

            // Сегодня: заход в настройки и здоровье, один отказ по правам.
            запись("стенд-3", когда(0, 9, 5), .today, .open),
            запись("стенд-3", когда(0, 9, 6), .health, .tab),
            запись("стенд-3", когда(0, 9, 8), .health, .dose, "given"),
            запись("стенд-3", когда(0, 9, 12), .settings, .open),
            запись("стенд-3", когда(0, 9, 13), .settings, .setting, "theme"),
            запись("стенд-3", когда(0, 9, 15), .family, .edit, nil, .blocked),
            запись("стенд-3", когда(0, 9, 16), .usageLog, .open),
        ]
        print("ФИКСТУРА-ЖУРНАЛА: записей \(записи.count), сеансов 3, дней 3 — "
              + "в память, НА ДИСК НЕ ПИШЕТСЯ")
        return записи
    }
}
