#if DEBUG
import UIKit

/// Снимки с приметами в хранилище фона — **вход стенда, которого
/// у `PhotosPicker` быть не может**.
///
/// # Зачем это существует
///
/// Экран «Фон приложения» и все четыре подложки (`CinemaBackdrop`,
/// `WalkMode.фон`, `WidgetBackdrop`, окна предпросмотра) рисуют
/// **фотографию человека**. Положить её на стенд было нечем:
///
/// ```
/// PhotosPicker          отдельный процесс, прогон туда не достаёт
/// ImageRenderer экрана  отдал 402 × 760 со знаком запрета — ЗАГЛУШКУ
///                       SwiftUI «этот вид отрисовать нельзя»
/// ```
///
/// Второе дороже первого, и разбор его лежит в
/// `Дизайн/кадры-приёмки/картинки-в-рамке-25.10/README.md`: **отказ
/// отрисовки пришёл в виде кадра.** Файл записан, счёт напечатан,
/// прогон зелёный — и кадр при этом не про экран. Тест тогда сняли:
/// кадр-заглушка хуже отсутствия кадра, потому что выглядит приёмкой.
///
/// Поэтому вход заводится здесь: байты пишутся прямо в контейнер
/// группы, а экран рисует их **живым приложением на симуляторе**, где
/// отрисовщиком служит сам UIKit, а не `ImageRenderer`.
///
/// # Снимок нарочно вертикальный и с приметами
///
/// ```
/// 600 × 800        портрет 3 : 4, как с телефона. У `scaledToFill`
///                  вертикальный снимок ПЕРЕРАСТАЕТ окно: 600 × 800
///                  в окне 60 × 50 даёт 60 × 80
/// четыре края      красный верх · синий низ · зелёный слева ·
///                  жёлтый справа — видно, КАКОЙ край срезала рамка
/// цифра в центре   1…5, разные у пяти снимков: в режиме «вперемешку»
///                  вся суть в том, что у экранов фото РАЗНЫЕ
/// ```
///
/// > **Однотонная фикстура прежних четырёх наборов на этот вопрос
/// > не отвечает по устройству.** Однотонное фото обрезается в себя
/// > самого: срежь ему верх, низ, бока, переверни круг в эллипс —
/// > кадр не изменится ни на пиксель. Для их предмета (контраст)
/// > это верно; вопроса «помещается ли» стенд не задавал ни разу.
///
/// Края одинаковы у всех пяти, а различает их только цифра: так один
/// и тот же кадр отвечает на два вопроса сразу — «помещается ли»
/// читается по краям в любом окне, «разные ли» — по цифрам.
///
/// # Имена фиксированные, а не UUID
///
/// `BackgroundStore.добавить` даёт `UUID().uuidString` — для человека
/// верно, для кадра нет: подпись «твоё фото № 2» и порядок плиток
/// обязаны повторяться от прогона к прогону, иначе два кадра одного
/// экрана не сравнить. Поэтому байты кладутся через `BackgroundBridge`
/// напрямую, а опись пишется целиком.
///
/// # Чистится ВСЕГДА, а не только когда просили
///
/// Ключи и файлы живут в контейнере группы приложений, **а он
/// переживает запуск**. Положил фикстуру один прогон — и дальше
/// её наследует каждый следующий, молча: отличить унаследованный фон
/// от заданного на кадре нечем. Поэтому `применить()` при отсутствии
/// флага **снимает** фикстуру, ровно как `применитьЧужуюЗону` снимает
/// владельца зоны.
///
/// Снимается только своё: файлы с нашим префиксом и опись, в которой
/// нет ничего, кроме них. Чужого снимка (если его когда-нибудь положат
/// на этот симулятор руками) мы не трогаем.
///
/// Под `#if DEBUG` целиком — та же граница, что у `-ДемоТ4`: вход,
/// пишущий картинки в хранилище фона человека, в релизной сборке
/// существовать не должен вовсе.
nonisolated enum ФонФикстураСтенда {
    static let флаг = "-ФонФикстура"
    static let флагСнять = "-ФонФикстураСнять"

    /// Однотонный белый снимок вместо снимка с приметами.
    ///
    /// **Заведён 26.10.2026 под замер, который до него был невозможен.**
    /// Гарантия дизайна к слою затемнения шапки сформулирована дословно
    /// так: «белый текст ≥ 4.5:1 (4.74) на ОДНОТОННОМ БЕЛОМ кадре,
    /// HC ≥ 7:1 (8.45)». А `сПриметами` рисует средне-серый
    /// `UIColor(white: 0.5)` плюс четыре цветные полосы и перекрестье —
    /// на нём число выходит ДРУГОЕ, и принять или опровергнуть 4,74
    /// таким кадром нельзя ни в какую сторону.
    ///
    /// > Фотографий у собак в `SeedData` нет ни у одной, поэтому
    /// > единственный вход с фотографией — эта фикстура. Пока у неё
    /// > не было белого варианта, **условие гарантии не существовало
    /// > в стенде вовсе**, и кадр отвечал бы на вопрос, которого
    /// > никто не задавал.
    ///
    /// Приметы здесь не нужны и были бы вредны: они проверяют
    /// геометрию (не уехало ли фото, работает ли спад), а это другой
    /// вопрос и другой флаг. Смешать их в одном снимке значит получить
    /// кадр, по которому не ответить ни на один из двух.
    static let флагБелая = "-ФонФикстураБелая"

    /// Префикс в имени файла — он же признак «это наше, можно убирать».
    static let префикс = "стенд-фикстура-"

    static var сколько: Int { BackgroundChoice.maxPhotos }

    static func имя(_ номер: Int) -> String { "\(префикс)\(номер).png" }

    static var просили: Bool {
        ProcessInfo.processInfo.arguments.contains(флаг)
    }

    static var просилиСнять: Bool {
        ProcessInfo.processInfo.arguments.contains(флагСнять)
    }

    static var просилиБелую: Bool {
        ProcessInfo.processInfo.arguments.contains(флагБелая)
    }

    /// Выставить или снять — **только** под `-UITesting` и **только
    /// когда попросили явно одним из двух флагов**.
    ///
    /// # ~~ФИКСТУРА ЛОМАЕТ РАСКЛАДКУ~~ — ЛОЖНО, снято в тот же день
    ///
    /// **Фикстура ничего не ломала. Она первый раз подложила
    /// фотографию, и раскладку сломала фотография.** Механизм нашёлся
    /// через час и оказался уже разобранным в этом же репозитории
    /// (`ФотоШапка.swift:113`):
    ///
    /// ```
    /// снимок 600×800, подложка 402×640
    /// scaledToFill → max(402/600, 640/800) = 0,8 → 480×640
    /// .clipped() режет РИСОВАНИЕ и не уменьшает место в раскладке
    /// содержимое центрируется в 402 и уезжает на −39
    /// ```
    ///
    /// Починено в `CinemaBackdrop`: размер даёт рамка, снимок лежит
    /// в `overlay` и наружу о себе не сообщает.
    ///
    /// > **«Служебное» — самое дешёвое объяснение, и потому
    /// > не объяснение.** Чистый кадр лежал ровно не потому, что
    /// > он честнее, а потому что **фона на нём не было вовсе**:
    /// > я сравнила «с фикстурой» и «без фото» и приписала разницу
    /// > фикстуре. Любое портретное фото собаки давало то же.
    ///
    /// Ниже оставлен прежний замер — он верен как НАБЛЮДЕНИЕ, неверен
    /// был вывод о виновнике.
    ///
    /// # Что именно наблюдалось, замер 26.10.2026
    ///
    /// Кадры, снятые с `-ФонФикстура`, показывают содержимое **шире
    /// экрана и сдвинутым влево**:
    ///
    /// ```
    /// с флагом    «Сегодня»→«егодня» · «воскресенье»→«оскресенье»
    ///             «07:02»→«7:02» · «Просится» начинается за левым
    ///             краем · «+» срезан справа. Таб-бар стоит РОВНО
    /// без флага   всё внутри, ничего не обрезано
    ///             (`Дизайн/кадры-приёмки/витрина-вершина-25.10/01-today.png`)
    /// рамка блока (-39.0, 61.67, 480.0, 360.0) при экране 402 pt
    /// ```
    ///
    /// Механизм УСТАНОВЛЕН и назван выше: `scaledToFill` сообщает
    /// наружу размер переросшего снимка, `.clipped()` режет рисование
    /// и раскладку не трогает. Догадка «кто-то берёт ширину у снимка»
    /// оказалась верной — но писать её как причину было нельзя,
    /// и правильно, что не написали: верной она стала от ЗАМЕРА,
    /// а не от правдоподобия.
    ///
    /// > **Приметы на снимке объясняют собой всё, что на кадре
    /// > не так.** Они видны сразу и выглядят единственным отличием
    /// > от настоящего фона — поэтому сдвиг раскладки списался на них
    /// > и прожил ложным час.
    ///
    /// Голова этого файла говорила про `scaledToFill` **прямо**:
    /// «вертикальный снимок ПЕРЕРАСТАЕТ окно». Строка написана
    /// автором фикстуры как объяснение, ЗАЧЕМ снимок вертикальный, —
    /// и прочитана мной как свойство фикстуры, а не продукта.
    ///
    /// > **Фикстура сработала ровно как задумана: она задала вопрос
    /// > „помещается ли“, которого стенд не задавал ни разу.** Ответ
    /// > был «нет», и я сперва обвинила того, кто спросил.
    ///
    /// Флаг брать там, где нужна сама фотография. Для приёмки цвета
    /// и раскладки снимать **обе** формы — с фото и без: кадр без фото
    /// не отвечает на «помещается ли», отвечать там нечему.
    ///
    /// # Снятие — ОТДЕЛЬНЫЙ флаг, и это починка, а не вкус
    ///
    /// Первая редакция снимала фикстуру на **каждом** запуске
    /// с `-UITesting`, у которого нет `-ФонФикстура`. То есть правка
    /// в хранилище фона влезала в путь запуска **всех сорока с лишним
    /// UI-тестов**, которые про фон ничего не спрашивают.
    ///
    /// Чем это кончилось, замер 25.10.2026, шесть заходов:
    ///
    /// ```
    /// снятие РЕАЛЬНО отработало (фикстура лежала)   4 из 4 — ОТКАЗ:
    ///   первый запуск сессии встаёт на ОНБОРДИНГЕ, панели вкладок нет
    ///   за 90–105 с, и это при нагрузке 49 — не от занятости машины
    /// снятие вышло пустым (фикстуры не было)        2 из 2 — порядок
    /// тот же тест сразу после чужого прогона        порядок, 24 с
    /// ```
    ///
    /// Корреляция шесть из шести. **Механизм я не установил** и потому
    /// не называю: онбординг под `-UITesting` не рисуется по устройству
    /// (`TogoApp:527`, ветка `isUITesting ||`), а он нарисовался — кадр
    /// `08-ОТКАЗ-ни-одной-вкладки.png`. Писать сюда ближайшую похожую
    /// причину значило бы выдать догадку за замер.
    ///
    /// Но решение от механизма не зависит: **запуск, который про фон
    /// не спрашивал, трогать нельзя.** С отдельным флагом путь запуска
    /// сорока чужих тестов снова ровно тот, что был до 25.10, —
    /// а кому нужна чистота, тот говорит об этом вслух.
    ///
    /// Запрет на `-UITesting` остаётся и поверх этого, тот же, что
    /// у чужой зоны и по той же причине: на машине человека в этом
    /// хранилище лежат его собственные фотографии, и затереть опись
    /// значило бы не «испортить прогон», а убрать у человека
    /// выбранный фон.
    static func применить(стенд: Bool) {
        guard стенд else { return }
        // Белая идёт ПЕРВОЙ в разборе нарочно: она подвид «положить»,
        // и если прогон попросил оба флага, однотонный белый важнее —
        // на нём стоит замер гарантии, а приметы проверяют геометрию,
        // которую видно и на сером.
        if просилиБелую {
            положить(однотонноБелым: true)
        } else if просили {
            положить()
        } else if просилиСнять {
            снять()
        }
    }

    private static func положить(однотонноБелым белый: Bool = false) {
        var имена: [String] = []
        for номер in 1...сколько {
            let снимок = белый ? однотонная() : сПриметами(номер)
            guard let png = снимок.pngData() else { continue }
            guard BackgroundBridge.положить(png, под: имя(номер)) else { continue }
            имена.append(имя(номер))
        }
        // Режим `single`: он единственный ДЕТЕРМИНИРОВАН. У `random`
        // затравку перемешивает `BackgroundStore.init` при первом
        // обращении к `shared`, то есть ПОСЛЕ нас, и подложить ей
        // число отсюда нельзя — кадр был бы разным каждый прогон.
        // Тест переключает режим сам, тапом по строке, как человек.
        BackgroundBridge.записатьВыбор(BackgroundChoice(mode: .single, items: имена))
        print("ФОН-ФИКСТУРА: положено снимков \(имена.count) из \(сколько) · режим single · \(имена.joined(separator: ", "))")
    }

    private static func снять() {
        let было = BackgroundBridge.читатьВыбор()
        let наши = было.items.filter { $0.hasPrefix(префикс) }
        guard !наши.isEmpty else { return }
        for имя in наши { BackgroundBridge.убрать(файл: имя) }
        let остались = было.items.filter { !$0.hasPrefix(префикс) }
        BackgroundBridge.записатьВыбор(BackgroundChoice(mode: остались.isEmpty ? .auto : было.mode,
                                                        items: остались))
        print("ФОН-ФИКСТУРА: снято снимков \(наши.count), чужих осталось \(остались.count)")
    }

    // MARK: Снимок с приметами

    /// Четыре края четырёх цветов, перекрестье и цифра.
    ///
    /// `format.scale = 1` обязателен: без него `UIGraphicsImageRenderer`
    /// рисует в масштабе устройства (на телефоне 3×), и помощник,
    /// обещающий 600 × 800, отдаёт 1800 × 2400. Тот же замер уже оплачен
    /// в `ФонФото.ужать` — просили 1000, получали 3000.
    /// Однотонный снимок без единой приметы — условие гарантии дизайна.
    ///
    /// `white: 1.0` буквально: гарантия названа «на однотонном белом
    /// кадре», и любая примета на нём сделала бы замер контраста
    /// зависящим от того, куда попала полоса. Самый тяжёлый случай для
    /// белого текста — именно чистый белый фон, то есть этот кадр ещё
    /// и худший из возможных, а не средний.
    ///
    /// `scale = 1` и `opaque = true` — по той же причине, что
    /// у `сПриметами`: рендерер иначе отдаёт снимок в масштабе
    /// устройства, и 600 × 800 превращаются в 1800 × 2400.
    private static func однотонная(ширина: CGFloat = 600,
                                   высота: CGFloat = 800) -> UIImage {
        let размер = CGSize(width: ширина, height: высота)
        let формат = UIGraphicsImageRendererFormat.default()
        формат.scale = 1
        формат.opaque = true
        return UIGraphicsImageRenderer(size: размер, format: формат).image { ctx in
            UIColor(white: 1.0, alpha: 1).setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
        }
    }

    private static func сПриметами(_ номер: Int,
                                   ширина: CGFloat = 600,
                                   высота: CGFloat = 800) -> UIImage {
        let размер = CGSize(width: ширина, height: высота)
        let полоса = ширина * 0.12
        let формат = UIGraphicsImageRendererFormat.default()
        формат.scale = 1
        формат.opaque = true
        return UIGraphicsImageRenderer(size: размер, format: формат).image { ctx in
            UIColor(white: 0.5, alpha: 1).setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
            UIColor.red.setFill()
            ctx.fill(CGRect(x: 0, y: 0, width: ширина, height: полоса))
            UIColor.blue.setFill()
            ctx.fill(CGRect(x: 0, y: высота - полоса, width: ширина, height: полоса))
            UIColor.green.setFill()
            ctx.fill(CGRect(x: 0, y: 0, width: полоса, height: высота))
            UIColor.yellow.setFill()
            ctx.fill(CGRect(x: ширина - полоса, y: 0, width: полоса, height: высота))
            UIColor.white.setFill()
            ctx.fill(CGRect(x: ширина / 2 - 4, y: 0, width: 8, height: высота))
            ctx.fill(CGRect(x: 0, y: высота / 2 - 4, width: ширина, height: 8))
            // Цифра — единственное, чем пять снимков различаются.
            let надпись = "\(номер)" as NSString
            let стиль = NSMutableParagraphStyle()
            стиль.alignment = .center
            let атрибуты: [NSAttributedString.Key: Any] = [
                .font: UIFont.systemFont(ofSize: ширина * 0.5, weight: .heavy),
                .foregroundColor: UIColor.black,
                .paragraphStyle: стиль,
            ]
            let высотаСтроки = ширина * 0.6
            надпись.draw(in: CGRect(x: 0, y: высота / 2 - высотаСтроки / 2,
                                    width: ширина, height: высотаСтроки),
                         withAttributes: атрибуты)
        }
    }
}
