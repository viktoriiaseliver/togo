import SwiftUI
import SwiftData
import CloudKit

/// Приём приглашения в общий дневник.
///
/// Ссылку открывает система, а не приложение: человек нажимает её
/// в мессенджере, iOS проверяет, что он тот, кого звали, и отдаёт нам
/// уже готовое приглашение. Своего кода проверки здесь нет и быть
/// не должно — за это отвечает iCloud.
///
/// **Приглашение приходит на делегат СЦЕНЫ, а не приложения.** У
/// приложения со сценами — а SwiftUI-приложение со сценами всегда —
/// UIKit зовёт `windowScene(_:userDidAcceptCloudKitShareWith:)`.
/// Одноимённый метод `UIApplicationDelegate` не зовётся вовсе, и пока
/// обработчик стоял на нём, гость нажимал ссылку, а не происходило
/// ничего: без принятого приглашения не работало и всё остальное.
///
/// Делегат сцены подключается единственным способом, который у
/// SwiftUI есть, — `configurationForConnecting`. Своего окна он
/// не заводит: окно по-прежнему строит `WindowGroup`.
final class ShareAcceptDelegate: NSObject, UIApplicationDelegate {
    func application(_ application: UIApplication,
                     configurationForConnecting connectingSceneSession: UISceneSession,
                     options: UIScene.ConnectionOptions) -> UISceneConfiguration {
        let configuration = UISceneConfiguration(name: nil,
                                                 sessionRole: connectingSceneSession.role)
        configuration.delegateClass = ShareAcceptSceneDelegate.self
        return configuration
    }
}

/// Та самая дверь, в которую стучится система с принятым приглашением.
///
/// Дверей две, и обе нужны. Приложение уже открыто — приходит
/// `windowScene(_:userDidAcceptCloudKitShareWith:)`. Приложение
/// запускает сама ссылка — приглашение лежит в `ConnectionOptions`
/// первой сцены, и метод выше в этом случае может не прийти вовсе.
/// Повторный приём безвреден: `ShareAcceptance` помнит, что уже принял.
final class ShareAcceptSceneDelegate: NSObject, UIWindowSceneDelegate {
    func windowScene(_ windowScene: UIWindowScene,
                     userDidAcceptCloudKitShareWith metadata: CKShare.Metadata) {
        ShareAcceptance.accept(metadata)
    }

    func scene(_ scene: UIScene, willConnectTo session: UISceneSession,
               options connectionOptions: UIScene.ConnectionOptions) {
        if let metadata = connectionOptions.cloudKitShareMetadata {
            ShareAcceptance.accept(metadata)
        }
    }
}

@main
struct TogoApp: App {
    @UIApplicationDelegateAdaptor(ShareAcceptDelegate.self) private var shareDelegate
    @Environment(\.scenePhase) private var scenePhase
    @State private var appState = AppState()
    @State private var settings = Settings()
    @State private var subscriptions = SubscriptionStore()
    /// Может быть nil: если хранилище не открылось, приложение показывает
    /// экран с объяснением, а не исчезает с экрана без единого слова.
    private let container: ModelContainer? = TogoApp.isUITesting
        ? SeedData.makePreviewContainer(TogoApp.uiTestingScenario)
        : Persistence.appContainer()



    /// UI-тесты запускаются на чистой базе в памяти с демо-собакой:
    /// так тест не зависит от того, что человек уже записал на этом устройстве.
    static var isUITesting: Bool {
        ProcessInfo.processInfo.arguments.contains("-UITesting")
    }

    /// Какой демо-набор просит тест: `-Сценарий silence`.
    ///
    /// Без аргумента — обычный день, как было. Незнакомое имя **валит
    /// запуск нарочно**: молча подставить обычный день значит дать тесту
    /// снять не то состояние и назвать это успехом. Набор, которому нечего
    /// проверять, молчит так же, как набор, у которого всё хорошо.
    static var uiTestingScenario: SeedData.Scenario {
        let args = ProcessInfo.processInfo.arguments
        guard let место = args.firstIndex(of: "-Сценарий") else { return .today }
        let имя = args.indices.contains(место + 1) ? args[место + 1] : ""
        guard let сценарий = SeedData.Scenario(rawValue: имя) else {
            fatalError("неизвестный сценарий демо-базы: «\(имя)»")
        }
        return сценарий
    }

    // MARK: Чем запуск стенда отличается от запуска у человека

    /// Отличия перечислены здесь, и каждое объявлено отдельно.
    ///
    /// **Это одно место нарочно.** Два разных предмета — онбординг
    /// и роль гостя — упёрлись в одну и ту же стену: под `-UITesting`
    /// приложение всегда идёт коротким путём, и состояние, которое
    /// нужно снять, недостижимо. Пока отличия заводятся по флагу
    /// на предмет, список того, чем стенд не похож на телефон, не лежит
    /// нигде целиком — а именно его и надо читать, когда зелёный набор
    /// месяц не замечает дыру.
    ///
    /// # Перечень флагов на 23.10.2026
    ///
    /// ```
    /// -UITesting                AppRoot всегда идёт на главный экран
    /// -Сценарий <имя>           какой демо-набор класть в базу
    /// -Онбординг                показать все шаги; В БАЗУ НЕ ПИШЕТ
    /// -ЧужаяЗона <…>            роль гостя в общем дневнике
    /// -ПрогревЗеркала           завести типы CD_* в CloudKit
    /// -ДемоТ4                   четыре точки Т4 поверх сценария,
    ///                           ТОЛЬКО В DEBUG — см. ниже
    /// ```
    ///
    /// **`-ДемоТ4` дописан сюда отдельно от своей работы, и причина
    /// названа автором заготовки:** он пропустил эту строку сознательно,
    /// потому что файл был горячим — три автора за сутки, — и правка
    /// в одну строку стоила бы чужого конфликта дороже, чем приносила.
    /// Пропуск он назвал вслух в отчёте; строка дописана, когда дерево
    /// освободилось.
    ///
    /// > **Смысл этого списка в том, что он ЦЕЛЫЙ.** Шестой флаг,
    /// > не попавший в перечень, ровно тем и опасен: читающий увидит
    /// > пять, решит, что знает все отличия стенда от телефона,
    /// > и список перестанет отвечать на вопрос, ради которого заведён.
    ///
    /// `-ДемоТ4` единственный из шести живёт **под `#if DEBUG`**
    /// и в релизную сборку не попадает — проверено двумя каналами
    /// на Release-сборке (символы `nm` и побайтный поиск литералов,
    /// у обоих контроли в том же замере).
    ///
    /// Показать настоящий онбординг: все шаги подряд, а не три.
    ///
    /// Число шагов здесь не названо нарочно: 23.10.2026 редизайн свёл
    /// их с шести к четырём, и «шесть» в трёх местах стало ложным
    /// за один коммит. Счёт в прозе — утверждение о коде, которое
    /// стареет молча.
    ///
    /// Без этого онбординг нельзя было снять вовсе. Ворот двое, и оба
    /// независимы: `AppRoot` под `-UITesting` всегда уходит на главный
    /// экран, а `OnboardingFlow.isReplay` при живой собаке подменяет
    /// справкой ровно те три шага, которые надо смотреть. Единственный
    /// годный прогон онбординга (08.10) шёл **без** `-UITesting`
    /// на стёртом вручную симуляторе и до нужных экранов не дошёл.
    static var просмотрОнбординга: Bool {
        ProcessInfo.processInfo.arguments.contains("-Онбординг")
    }

    /// Имя владельца чужой зоны: стенд запускается гостем.
    ///
    /// Ни один из тысячи с лишним тестов ни разу не был мамой —
    /// во всех сценариях «я» владелец, и дыра в правах на экране семьи
    /// поэтому прожила месяц при зелёном наборе. Её не «не заметили»,
    /// её нечем было заметить.
    ///
    /// Почему аргументом, а не сценарием демо-базы: признак гостя —
    /// `SharedZoneOwner.name` в `UserDefaults` группы приложений,
    /// а сценарий строит **контейнер**, настроек группы он не касается.
    static var чужаяЗона: String? {
        let args = ProcessInfo.processInfo.arguments
        guard let место = args.firstIndex(of: "-ЧужаяЗона"),
              args.indices.contains(место + 1) else { return nil }
        return args[место + 1]
    }

    /// Выставить или снять чужую зону — **только** под `-UITesting`.
    ///
    /// Два запрета, и второй дороже первого.
    ///
    /// **Писать можно только на стенде.** `sharedDiary.ownerName`
    /// на машине человека живой: общий дневник принят, им пользуются
    /// двое. Затереть этот ключ — не «испортить прогон», а сломать
    /// работающий дневник у двоих людей.
    ///
    /// **Снимать обязательно.** Ключ живёт в группе приложений,
    /// а она переживает запуск: без очистки второй прогон унаследует
    /// чужую зону от первого и позеленеет не на том состоянии —
    /// молча, потому что отличить унаследованное от заданного на экране
    /// нечем. Ровно поэтому рядом стоит `ActiveSessionStore.save(nil)`.
    private static func применитьЧужуюЗону() {
        guard isUITesting else { return }
        SharedZoneOwner.name = чужаяЗона
    }

    /// Обмен на стенде всегда выключен, и аргумента для него нет.
    ///
    /// Третий ключ той же группы приложений — `sharedDiary.on`
    /// (`FamilySync.swift:765`), и он переживает запуск ровно так же,
    /// как владелец зоны и причина отказа. Включил его кто-то один раз
    /// — тест или человек руками на этом симуляторе, — и дальше
    /// **каждый** заход поднимает `FamilySync` (`startSyncIfOn`), и тот
    /// идёт ждать CloudKit там, где его не звали. На экране это
    /// неотличимо от нормы, в логе — непонятные таймауты у соседей.
    ///
    /// **Почему `-ЧужаяЗона` его НЕ включает, хотя в жизни включён.**
    /// У настоящего гостя `FamilyShare.accepted()` ставит и владельца
    /// зоны, и `isOn`, так что стендовый гость на полшага отличается
    /// от живого. Разница названа нарочно и оставлена: включить обмен
    /// значит в каждом тесте роли гостя поднять сетевой слой, который
    /// этим тестам не нужен — права от `isOn` не зависят, — и заплатить
    /// за точность чужими таймаутами. Понадобится гость с обменом —
    /// это отдельный аргумент с отдельным доводом, а не тихая добавка
    /// к этому.
    private static func выключитьОбмен() {
        guard isUITesting else { return }
        SharedDiarySettings.isOn = false
    }

    /// Причина неудавшегося приёма приглашения: `-ИсходПриёма нетСети`.
    ///
    /// Пять текстов, которые человек читает в худшую свою минуту, не
    /// видел глазами никто: их сверяют как строки и проверяют **грепом
    /// по исходнику** (`ЗнакТостаTests` ищет `НеудачаПриёма.текущая`
    /// в тексте экрана). Сторож, меряющий прозу, зелен, пока строка
    /// написана, и о показе не знает ничего.
    ///
    /// **Незнакомый код валит запуск, и это главное в этом месте.**
    /// `НеудачаПриёма.текущая` разбирает строку с `default: nil`:
    /// опечатка дала бы «причины не было», экран показал бы спокойствие,
    /// кадр снялся бы пустым — и пять исходов записались бы снятыми,
    /// будучи одним и тем же ничем. Тот же довод, по которому валит
    /// `uiTestingScenario`.
    ///
    /// `.принято` сюда не берём: успех — это снятие причины, а снимает
    /// её отсутствие аргумента.
    private static func применитьИсходПриёма() {
        guard isUITesting else { return }
        let args = ProcessInfo.processInfo.arguments
        guard let место = args.firstIndex(of: "-ИсходПриёма") else {
            // Снимаем всегда: ключ живёт в группе приложений и переживает
            // запуск. Без этого второй прогон унаследует причину отказа
            // от первого и позеленеет не на том экране.
            НеудачаПриёма.текущая = nil
            return
        }
        let код = args.indices.contains(место + 1) ? args[место + 1] : ""
        switch код {
        case "нетСети": НеудачаПриёма.текущая = .нетСети
        case "нетiCloud": НеудачаПриёма.текущая = .нетiCloud
        case "сторонаПриложения": НеудачаПриёма.текущая = .сторонаПриложения
        case "неизвестно": НеудачаПриёма.текущая = .неизвестно
        default: fatalError("неизвестный исход приёма: «\(код)»")
        }
    }

    init() {
        // Порядок важен: зона выставляется ДО первого чтения.
        // `SharedZoneOwner.isGuest` спрашивают и права при запуске,
        // и обмен; прочитанное однажды значение уже не переспросят.
        // Три ключа одной группы приложений, и все три переживают запуск.
        // Чистить надо все: вычищенные две трети выглядят как вычищенное
        // целое, и следующий прочтёт именно это.
        Self.применитьЧужуюЗону()
        Self.применитьИсходПриёма()
        Self.выключитьОбмен()
        // Прогулка теперь переживает закрытие приложения — значит, она
        // переживает и предыдущий тест. Для UI-тестов состояние чистится:
        // иначе второй тест открывает чужую прогулку вместо своей.
        if Self.isUITesting {
            ActiveSessionStore.save(nil)
        }
        Persistence.shared = container
        #if DEBUG
        Self.прогретьЗеркалоЕслиПросили(container)
        #endif
    }

    #if DEBUG
    /// Прогрев зеркала CloudKit аргументом запуска: `-ПрогревЗеркала`.
    ///
    /// Зачем не только кнопкой. Кнопка в «Настройках» (`SettingsScreen`)
    /// требует тапов, то есть человека у экрана, и повторить её нельзя
    /// ни скриптом, ни прогоном. Прогрев при этом — не разовое действие:
    /// каждая новая модель и каждое новое поле заводят в контейнере свой
    /// тип и свой ключ, и замеры 23.09 и 14.10 оба нашли отставание
    /// **снаружи**, когда поправить его было уже дорого.
    ///
    /// **Чего аргумент НЕ делает, и это надо знать до запуска.** Он
    /// записывает объекты в локальное хранилище — дальше их отправляет
    /// зеркало SwiftData, и только при живом Apple ID с включённым
    /// iCloud. На симуляторе без аккаунта записи лягут локально,
    /// контейнер не изменится, и `make cloudkit-check` покажет ровно то
    /// же, что до запуска. Это не отказ прогрева: это отсутствие канала,
    /// и отличить одно от другого можно только сверкой, а не выводом.
    ///
    /// Под `#if DEBUG` целиком, и это граница, а не осторожность:
    /// прогрев заводит служебные объекты с меткой, а в релизной сборке
    /// вход, пишущий такие объекты в дневник человека, существовать
    /// не должен вовсе.
    private static func прогретьЗеркалоЕслиПросили(_ container: ModelContainer?) {
        guard ProcessInfo.processInfo.arguments.contains("-ПрогревЗеркала"),
              let container else { return }
        do {
            let n = try CloudKitSchemaWarmup.create(in: container.mainContext)
            print("ПРОГРЕВ ЗЕРКАЛА: создано объектов \(n). Записи уедут, только если iCloud живой; приёмка — make cloudkit-check, а не эта строка.")
        } catch {
            print("ПРОГРЕВ ЗЕРКАЛА: НЕ СОХРАНИЛОСЬ — \(error)")
        }
    }
    #endif

    /// Обмен поднимается, только если его включили руками. Пока он
    /// выключен, приложение ведёт себя ровно так же, как до него.
    @State private var sync: FamilySync?

    private func startSyncIfOn() async {
        guard SharedDiarySettings.isOn, let container else { return }
        // Снятие напоминаний передаётся сюда, а не зовётся из `FamilySync`
        // напрямую: `ReminderScheduler` живёт в цели приложения, а
        // `TogoShared` входит в обе — вызов оттуда не собрался бы
        // в расширении виджета. Параметр у `FamilySync` без умолчания
        // нарочно: обратный вызов, который можно забыть, — это механизм
        // без входа, а он от рабочего не отличается ни тестом, ни
        // компилятором. Здесь компилятор и решает: точка создания одна.
        if sync == nil {
            sync = FamilySync(modelContainer: container,
                              дозаБольшеНеЖдёт: ReminderScheduler.cancelDose)
        }
        await sync?.start()
    }

    var body: some Scene {
        WindowGroup {
            Group {
                if let container {
                    AppRoot()
                        .environment(appState)
                        .environment(settings)
                        .environment(subscriptions)
                        .environment(\.familySync, sync)
                        .modelContainer(container)
                } else {
                    StorageFailureScreen()
                }
            }
            // Полная мята — интерактив, и вкладка с шестерёнкой это он:
            // их нажимают. «Сделано» окрашено иначе — плашкой, — потому
            // что галочка выполненного не должна читаться такой же
            // активной, как кнопка.
            .tint(Token.Action.primary)
            // ТЕМУ ВЫБИРАЕТ СИСТЕМА — строки `.preferredColorScheme(.dark)`
            // здесь больше нет, и её отсутствие важнее любой строки,
            // которую можно было бы поставить вместо.
            //
            // **Светлая тема существовала в токенах и не доходила
            // до экрана.** 07.10.2026 заведены четыре режима — 24 примитива,
            // 57 ссылок на 27 общих цветов, 19 пар контраста измерены
            // в каждом из четырёх, — а этот модификатор прибивал схему
            // к тёмной. Приложение показывало тёмное при любой настройке
            // телефона.
            //
            // > **Значение верное, вызов бессильный.** Токены верны,
            // > сторож контраста зелен, инструкция тестировщику зовёт
            // > переключать тему — и ни одно из трёх не смотрит на то,
            // > СПРАШИВАЕТ ли приложение систему.
            //
            // Комментарий, который здесь стоял, был верен в день
            // написания: «макет собран на чёрном, и светлой пары к нему
            // нет». Светлая пара появилась, комментарий остался — и держал
            // код. Сторож `ТемаНеПрибитаTests` краснеет, если модификатор
            // вернётся.
            .task {
                StartupLog.note("интерфейс показан")
                // Журнал действий подрезаем на старте, а не по таймеру:
                // приложение открывают каждый день, и этого достаточно.
                // Отдельной задачей: за две недели там тысячи строк,
                // и разбирать их на главном потоке — это задержка показа
                // первого экрана.
                Task.detached(priority: .utility) { UsageLog.trim() }
            }
            // Пока телефон лежал в кармане, отметку могли поставить
            // кнопкой на живой активности. Перечитываем прогулку,
            // иначе первое же изменение затёрло бы такую отметку.
            .onChange(of: scenePhase) { _, phase in
                // Уходим в фон — дописываем журнал действий на диск:
                // систему никто не спрашивает, когда она выгрузит процесс,
                // а последние действия перед уходом самые ценные.
                if phase != .active { UsageLog.flushNow() }
                if phase == .active {
                    appState.reloadSession()
                    // Пока телефон лежал в кармане, второй человек мог
                    // что-то отметить. Спрашиваем сразу, а не ждём push:
                    // он может и не дойти.
                    Task { await sync?.fetchNow() }
                }
            }
            .task { await startSyncIfOn() }
            // Одно место на оба исхода приёма приглашения, и говорят
            // они разное.
            //
            // Пока отказ кончался записью в журнал, человек не узнавал
            // ничего: приложение открывалось обычным, и гость считал,
            // что вошёл. Успех при этом тоже молчал — «вы в общем
            // дневнике» ему никто не говорил, а чей это дневник,
            // не говорили тем более.
            //
            // Обмен поднимается ТОЛЬКО на успехе: на отказе поднимать
            // нечего, зона не наша.
            .onReceive(NotificationCenter.default.publisher(for: .familyShareAccepted)) { _ in
                let исход = ShareAcceptance.исход
                if исход?.принято_ли != false {
                    Task { await startSyncIfOn() }
                }
                if let исход {
                    // Знак и слово обязаны говорить одно. До 09.10.2026
                    // отказ показывался `showUndo`, то есть с зелёной
                    // галочкой «готово»: четыре исхода из пяти — отказы,
                    // и все пять были зелёными. Глаз берёт значок раньше
                    // фразы, и человек уходил уверенным, что вошёл.
                    if исход.принято_ли {
                        appState.showUndo(исход.текст)
                    } else {
                        // Путь собран из ДВУХ СУЩЕСТВУЮЩИХ ключей, а не
                        // написан новой строкой: шестого текста нет,
                        // пробелов на en/fr/uk не возникает, и пара
                        // становится цитатой интерфейса — местом, где
                        // две строки обязаны совпасть. Таких у Togo 59,
                        // и сторож цитат держит их бесплатно.
                        //
                        // Склейка НЕ обёрнута в `String(localized:)`
                        // нарочно: обёртка завела бы седьмой ключ
                        // из уже переведённых частей.
                        let путь = "\(String(localized: "Семья")) → \(String(localized: "Общий дневник"))"
                        appState.showFailure("\(исход.текст)\n\(путь)")
                    }
                    // Снимается только показ. Сама причина осталась
                    // в `НеудачаПриёма` и ждёт в постоянном месте:
                    // плашка живёт пять секунд, а приём случается
                    // на холодном старте по ссылке.
                    ShareAcceptance.исходПрочитан()
                }
            }
        }
    }
}

/// Онбординг — 90 секунд и аккаунт не нужен. Пока он не пройден,
/// вкладок нет вовсе: показывать пустую навигацию новому человеку не за чем.
struct AppRoot: View {
    @Environment(Settings.self) private var settings
    @Environment(AppState.self) private var appState
    @Environment(\.modelContext) private var context
    @Query private var dogs: [Dog]
    @Query private var members: [FamilyMember]
    @State private var showsWhatsNew = false

    var body: some View {
        // Собаки может не быть намеренно: на шаге «Кто у тебя живёт» есть
        // «Пока без собаки». Раньше здесь стояло `&& dogs.first != nil`,
        // и пропуск не удержался бы — приложение вернуло бы в онбординг.
        // Предохранителем от пустого хранилища это условие тоже больше
        // не служит: сломанную базу ловит `Persistence.openContainer`
        // и показывает «Дневник не открылся».
        //
        // Просмотр онбординга побеждает оба условия — и флаг, и стенд.
        // Иначе его нельзя было бы показать ни человеку (флаг у него
        // давно стоит), ни стенду (под `-UITesting` ворота закрыты
        // всегда).
        //
        // # Третье условие: приглашение принято
        //
        // **Это не ещё один способ сказать «онбординг пройден».**
        //
        // Что было до 15.10.2026: мама открывает ссылку, приём
        // срабатывает, зона записана, обмен поднимается, записи едут —
        // и она видит **приветствие, а не дневник**. Дневник у неё
        // на телефоне есть, а экрана с ним нет. Состояние снято журналом
        // действий ещё 09.10 (`docs/journal/2026-10-09-tri-otkaza…:322-328`:
        // первая строка `usage.jsonl` это `open/onboarding`, а через
        // шесть секунд в дневнике шестнадцать записей, которых
        // на чистой установке мог принести только iCloud) — разбирали
        // под другой вопрос и следствий не назвали.
        //
        // **Почему не ставить `onboardingCompleted = true` в приёме.**
        // Это поле означает «человек прошёл онбординг». Приглашённый
        // его не проходил. Сложи два смысла в одно поле — и следующий
        // получит ровно тот дефект, который чинили здесь же утром
        // 15.10: режим потока, вычисляемый из поля, означающего другое
        // (`OnboardingFlow.Режим`, три случая вместо одного флага).
        // Поле остаётся про прохождение; право видеть дневник приезжает
        // своим признаком.
        //
        // **Почему живой признак, а не новый флаг.** `SharedZoneOwner`
        // уже опознаёт гостя в пяти местах — потолок прав
        // (`AppState:102`), второй вход в права (`:133`), быстрые
        // действия (`QuickLogIntents:87`), запреты владельца
        // (`FamilyShare:109`, `:262`). Писателей у живого человека
        // **ровно один** — `FamilyShare.accepted():363`, то есть
        // настоящий приём приглашения; второй (`:148`) стоит
        // под `guard isUITesting`. Значит ворота не открываются чужим
        // действием: это не прокси, а сам предмет.
        //
        // **Почему признак, а не реакция на событие.** Обработчик
        // `.familyShareAccepted` не годится воротами: при холодном
        // старте по ссылке `accept` случается в
        // `scene(_:willConnectTo:)`, то есть может пройти **до** того,
        // как SwiftUI подпишется, — уведомление тогда некому поймать.
        // Ключ в группе приложений запуск переживает.
        //
        // **Граница, названная заранее.** Гость не проходит онбординг,
        // значит не видит и его запроса на уведомления. Прав это
        // не отнимает молча: второй повод штатный и приходит на первой
        // дозе (`DayPlanActions:198`, `occasion: .firstDose`) — а доза
        // и есть то, ради чего маму звали.
        //
        // **Чего это НЕ чинит:** человека, который открыл приложение
        // **до** того, как нажал ссылку. Он стоит на приветствии,
        // и ветка «Меня позвали в семью» ему по-прежнему указатель,
        // а не дверь.
        if !appState.просмотрОнбординга,
           TogoApp.isUITesting || settings.onboardingCompleted || SharedZoneOwner.isGuest {
            RootView()
                // «Что нового» показывается один раз после обновления —
                // и никогда поверх работы на первом запуске.
                .sheet(isPresented: $showsWhatsNew) {
                    NavigationStack { WhatsNewScreen() }
                }
                .task {
                    checkVersion()
                    // Роль и права берутся из своей карточки при каждом
                    // запуске. Без этого выданная роль не применялась
                    // нигде: `adopt` звали только при ручной правке
                    // карточки, а до тех пор на телефоне действовал
                    // владелец по умолчанию.
                    appState.adoptMe(from: members)
                    // Уход у тех, кто ставил приложение до переделки, чинится
                    // один раз и молча: человек не должен ничего править руками.
                    let fixed = CareMigration.run(context: context)
                    FeedingMigration.run(context: context)
                    WalkLinkStartup.run(context: context)
                    if fixed > 0 { StartupLog.note("уход починен: \(fixed)") }
                    // Откуда взялась собака — запись на будущее. 23.09
                    // дубликат появился, а причину было нечем найти:
                    // крошки за тот час затёрлись. Теперь прибавление
                    // и пропажа называются в момент, когда случились.
                    DogOrigin.проверить(in: context)
                    // Перепись безымянных — ПОСЛЕ переписи источников:
                    // та печатает по каждой собаке источник, час
                    // создания и счёт записей.
                    //
                    // Ничего не удаляет. Решение 07.10.2026: пустые
                    // записи не показываем (`Dog.canBeShown`), а не
                    // стираем — «не показать» самоисправляется, когда
                    // доедет кличка, а удаление необратимо и уносит
                    // одиннадцать каскадов.
                    let безымянных = NamelessDogAudit.перепись(in: context)
                    if безымянных > 0 { StartupLog.note("безымянных записей: \(безымянных)") }
                    Persistence.removeLegacyStoreIfSafe(context: context)
                }
        } else {
            OnboardingFlow(просмотр: appState.просмотрОнбординга)
        }
    }

    private func checkVersion() {
        guard !settings.lastSeenVersion.isEmpty, settings.lastSeenVersion != settings.appVersion else {
            settings.lastSeenVersion = settings.appVersion
            return
        }
        showsWhatsNew = true
        settings.lastSeenVersion = settings.appVersion
    }
}


/// Хранилище не открылось. Экран вместо молчаливого падения: человек
/// должен понимать, что случилось, и иметь что нажать.
///
/// Письмо здесь — последняя дверь: дневник не открылся, и больше
/// в приложении делать нечего. `mailto:` на телефоне без настроенной
/// почты не открывается ничем — человек получает системный алерт,
/// а за ним пусто. Поэтому «не открылось» обрабатывается, а адрес
/// уходит в буфер: та же починка, что на экране поддержки, и по тому же
/// правилу — правка, меняющая читаемое, применяется ко всем поверхностям,
/// где та же строка живёт.
struct StorageFailureScreen: View {
    @Environment(\.openURL) private var openURL
    @State private var копияАдреса: String?

    /// Крошки запуска читаются ОДИН раз: по ним же решается, можно ли
    /// советовать переустановку, и два чтения разошлись бы, если файл
    /// дописали между ними.
    private let журналЗапуска = StartupLog.read()

    private var возврат: StorageFailureAdvice.Возврат {
        StorageFailureAdvice.возврат(журналЗапуска: журналЗапуска)
    }

    var body: some View {
        TGScreen(title: "Дневник не открылся") {
            TGBanner(tone: .alarm, title: "Не удалось открыть хранилище",
                     subtitle: .готовая(StorageFailureAdvice.подзаголовок(возврат)),
                     systemImage: "externaldrive.badge.exclamationmark")

            if let предупреждение = StorageFailureAdvice.предупреждение(возврат) {
                TGBanner(tone: .alarm, title: "Переустановка удалит дневник",
                         subtitle: .готовая(предупреждение),
                         systemImage: "exclamationmark.triangle.fill")
            }

            TGCard {
                Text("Что попробовать").textStyle(AppFont.cardTitle)
                ForEach(StorageFailureAdvice.шаги(возврат), id: \.self) { step in
                    HStack(alignment: .top, spacing: Token.Space.s8) {
                        Image(systemName: "circle.fill")
                            .font(.system(size: 5))
                            .foregroundStyle(Token.Ink.secondary)
                            .padding(.top, 7)
                            .accessibilityHidden(true)
                        Text(step)
                            .textStyle(AppFont.caption)
                            .wraps()
                        Spacer(minLength: 0)
                    }
                }
            }

            TGCard {
                TGSectionHeader(title: "что записало приложение при запуске")
                Text(журналЗапуска)
                    .textStyle(AppFont.numeric(12, weight: .regular))
                    .wraps()
                TGExplainer(text: "Здесь только этапы запуска — ничего о собаке. Эти строки помогают понять причину.")
            }

            TGButton(title: "Написать в поддержку", variant: .secondary,
                     size: .medium, systemImage: "envelope") {
                // Тему письма человек ВИДИТ в окне почты, прежде чем
                // отправить. Русская строка здесь — то же самое, что
                // русская подпись на кнопке, только замечают её позже.
                //
                // Переводом мы платим тем, что в поддержку темы придут
                // на трёх языках. Это не потеря, а сигнал: по теме сразу
                // видно, на каком языке человеку отвечать.
                guard let url = Contacts.mail(Contacts.support,
                                              subject: String(localized: "Дневник не открылся")) else { return }
                openURL(url) { открылось in
                    guard !открылось else { return }
                    UIPasteboard.general.string =
                        "\(Contacts.support)\n\n\(StartupLog.read())"
                    копияАдреса = Contacts.support
                    Haptics.warning()
                }
            }
            if let копияАдреса {
                TGBanner(tone: .alarm, title: "Почта на телефоне не настроена",
                         // `.готовая` тут и раньше стояла — а строка под ней
                         // была сырым русским литералом и в каталог
                         // не попадала ни разу. Маркер обещает «текст уже
                         // собран и переведён», и под ним это проверять
                         // перестают: пропуск с обоснованием читается
                         // как решение.
                         //
                         // Экран отказа — та поверхность, которую француз
                         // видит ИМЕННО когда у него что-то сломалось.
                         subtitle: .готовая(String(localized: "Адрес и строки запуска скопированы: \(копияАдреса). Напиши с другого устройства.")),
                         systemImage: "envelope.badge.shield.half.filled")
            }
        }
    }

    // `steps` был КОНСТАНТОЙ из трёх пунктов, и третий звал
    // переустановить, обещая возврат «из iCloud или из сохранённого
    // файла». Переустановка сносит контейнер App Group, и у человека
    // без iCloud совет уничтожал то, что баннер над ним называл целым.
    //
    // Правило переехало в `StorageFailureAdvice` — чтобы его можно было
    // спросить из теста. Вью текстов больше не держит.
}
