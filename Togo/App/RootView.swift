import SwiftUI
import SwiftData

/// Четыре вкладки: Сегодня · {кличка} · История · Здоровье.
///
/// **Семья уехала из таб-бара первой строкой во вкладку собаки** —
/// решение Виктории 22.10.2026, прямым словом в чате («перепиши всё
/// под дизайн»); источник — `design_handoff_togo_ios28/README.md`,
/// раздел «Навигация (решено)». Было пять вкладок, стало четыре.
/// Глубина по-прежнему ≤ 3: вкладка → экран → форма.
///
/// **«Здоровье» держится ПРАВОМ `.seeMedical`, а не включённым лечением** —
/// решение 08.10.2026, `02c1e88`, и оно **не отменено хендоффом**: README
/// говорит ровно то же («скрыто у помощника без `seeMedical`»).
/// Пока условием было лечение, вкладка исчезала ровно в день конца
/// курса, то есть тогда, когда нужен отчёт врачу. Значит у здоровой
/// собаки владелец её видит; не видит только помощник. Условие — ниже
/// в этом же файле.
///
/// > **Прежняя редакция этой головы противоречила условию ниже в том же
/// > файле, и это записано в проекте как случай.** Поэтому голова
/// > переписана вместе с кодом, а не оставлена говорить про пять
/// > вкладок: доккомментарий, разошедшийся с кодом, читается как
/// > решение и живёт дольше кода.
///
/// **Шестерёнки настроек в шапке больше нет** — настройки уехали
/// в меню «…» (там же «Другой день» на «Сегодня» и «Семья» на вкладке
/// собаки).
///
/// > **Здесь стояло «сам тип `SettingsToolbarItem` оставлен
/// > объявленным: его зовут `HealthScreen` и `HistoryScreen`». Это было
/// > верно 22.10 и стало ложным 23.10**, когда `3e8eed6` снял
/// > шестерёнку и с них. Тип снесён 23.10 замером: три вхождения, ни
/// > одного вызова, контроль `HeaderMenu(` — три вызова.
/// >
/// > Запись не удалена, а переписана, потому что дорога здесь не
/// > шестерёнка, а класс: **причина «не трогаю, это зовут чужие пути»
/// > живёт ровно до чужого коммита и о своей смерти не сообщает.**
/// > Голова модуля читается как решение, а была сводкой состояния —
/// > у такой записи обязан стоять способ проверки, а не только довод.
struct RootView: View {
    @Environment(AppState.self) private var appState
    @Query private var dogs: [Dog]
    @State private var selection: Tab = .today
    /// Приглашение в семью пришло ссылкой: вкладки «Семья» больше нет,
    /// и человека надо довести до экрана, а не до вкладки, где он
    /// должен сам догадаться искать строку в списке.
    @State private var открытьСемью = false
    /// Тап по живой активности прогулки: `togo://walk`. Вкладки
    /// у «На улице» нет — это шторка «Сегодня», и дойти до неё можно
    /// только через экран, который её держит.
    @State private var открытьПрогулку = false

    enum Tab: Hashable { case today, dog, history, health }

    /// Значки вкладок — **из пакета дизайна, а не по смыслу**.
    ///
    /// Источник: `Дизайн/КОНТРАКТ-ПАКЕТА.md:242`, таблица
    /// «Material → SF Symbols», и эталонный кадр
    /// `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/10.png`,
    /// прочитанный увеличением таб-бара. Два источника сошлись
    /// на трёх значках из четырёх:
    ///
    /// ```
    ///            было          контракт               кадр 10
    /// Сегодня    sun.horizon   calendar               календарь    ✗ было не то
    /// {кличка}   pawprint      pawprint               лапа         ✓ совпадало
    /// История    calendar      clock.arrow.circlepath часы со стрелкой ✗
    /// Здоровье   cross.case    heart.text.square      СЕРДЦЕ       ✗ расходятся
    /// ```
    ///
    /// **Календарь стоял на «Истории», а должен на «Сегодня»** — два
    /// значка поменялись смыслами, и `sun.horizon` в пакете не назван
    /// вовсе.
    ///
    /// **`cross.case` — чужой значок.** Контракт отдаёт его
    /// `emergency_home`, то есть экстренной карточке, а не медслою.
    /// Он был взят «по смыслу» и обоими источниками опровергается.
    ///
    /// **Расхождение по «Здоровью» названо, а не усреднено.** Контракт
    /// говорит `heart.text.square` (квадрат с сердцем и строками),
    /// кадр `10.png` рисует **простое сердце без рамки** — это разные
    /// глифы, а не разрешение растра. Взят кадр: правило этого
    /// редизайна записано в головах `КиноЭкран` и `HistoryScreen`
    /// дословно — «исполнен **кадр**, а не проза README: где они
    /// расходятся, расхождение названо в отчёте». Если Виктория
    /// выберет контракт — это одно слово здесь.
    ///
    /// > И рядом то, чему этот контракт **уже не хозяин**: та же
    /// > страница (`:46`) говорит «„Здоровье" появляется, только если
    /// > включено лечение». Решением 08.10.2026 вкладку держит право
    /// > `.seeMedical`, и это решение не отменено (разбор — голова
    /// > этого файла). То есть пакет местами старше кода, и ссылаться
    /// > на него целиком нельзя.
    ///
    /// Приёмка здесь — **кадр, а не компиляция**: несуществующее имя
    /// символа даёт пустое место, а не ошибку сборки. Снято после
    /// правки, `Дизайн/кадры-приёмки/низ-и-верх-кино-23.10/`.
    private enum Значок {
        static let today = "calendar"
        static let dog = "pawprint"
        static let history = "clock.arrow.circlepath"
        static let health = "heart"
    }

    private var dog: Dog? { appState.activeDog(from: dogs) }

    /// На «Сегодня» под тостом стоит нижняя полоса — её высоту надо
    /// перешагнуть. На остальных вкладках хватает высоты таб-бара.
    ///
    /// **Число уменьшено вместе с полосой.** Было 150 под сетку из двух
    /// рядов (две большие кнопки плюс четыре плитки); стало — одна
    /// строка «главная кнопка · вторая · круглая +», высота 60 плюс
    /// отступы. Приёмка тут не число, а **кадр**: тост обязан быть
    /// виден целиком.
    private var toastInset: CGFloat {
        selection == .today ? 100 : 20
    }

    /// Переключить вкладку снаружи — например из шторки «Ещё», которая
    /// больше не строит навигацию сама.
    func show(_ tab: Tab) { selection = tab }

    var body: some View {
        TabView(selection: $selection) {
            TodayScreen(onOpenDog: { selection = .dog },
                        открытьПрогулку: $открытьПрогулку,
                        // Тот же ход, что у ссылки `togo://join`,
                        // и нарочно тем же вызовом: «Семья» не вкладка,
                        // довести до неё — это вкладка ПЛЮС пуш.
                        открытьСемью: показатьСемью)
                .tabItem { Label("Сегодня", systemImage: Значок.today) }
                .tag(Tab.today)

            DogTab(открытьСемью: $открытьСемью)
                .tabItem { Label(dog.flatMap(\.nameIfAny) ?? String(localized: "Собака"), systemImage: Значок.dog) }
                .tag(Tab.dog)

            HistoryScreen()
                .tabItem { Label("История", systemImage: Значок.history) }
                .tag(Tab.history)

            // Вкладку держит ПРАВО, и только оно. Решение Виктории
            // 08.10.2026: «вкладка всегда видна тому, кому можно».
            //
            // **Условие лечения снято, и возвращать его не надо.**
            // Пока оно стояло, «Здоровье» исчезало в тот день, когда
            // курс закончился, — то есть ровно тогда, когда нужен отчёт
            // врачу и история курса. Прежняя редакция этого комментария
            // объясняла, почему права тут не было вовсе (`seeMedical`
            // спрашивался в трёх местах, и все три — на «Сегодня»),
            // и под новым решением читалась наоборот: будто лечение
            // здесь обязательная половина.
            //
            // Держат это `MedicalAccessTests`: «закрыта правом И ТОЛЬКО
            // правом» краснеет на возврате `isOnTreatment`, и доказанно —
            // оба утверждения были красными до этой правки.
            // Разбор по всем пяти ролям — docs/матрица-ролей.md.
            if appState.can(.seeMedical) {
                HealthScreen()
                    .tabItem { Label("Здоровье", systemImage: Значок.health) }
                    .tag(Tab.health)
            }
        }
        // Активная вкладка красится акцентом темы, а не системным синим.
        //
        // На эталоне `screenshots/10.png` активная «История» — синий
        // значок и синяя подпись. Без `.tint` их красит `accentColor`
        // приложения, и на кадрах витрины активная выходила белой:
        // от неактивных её отличала только серая пилюля.
        //
        // **Пилюлю мы не снимаем, и это расхождение с прототипом
        // названо, а не устранено.** Её рисует сам `TabView` в iOS 26;
        // убрать её можно только своим таб-баром вместо системного.
        // Прототип — HTML 424×896, системного компонента там нет вовсе,
        // поэтому «на эталоне пилюли нет» говорит про прототип,
        // а не про требование к нам. Решение — Виктории.
        .tint(Token.Ink.link)
        // Тост подтверждения должен быть виден, а не прятаться за сеткой
        // кнопок: «нажала — и ничего не произошло» — худшее, что может
        // сделать приложение, которое просят отмечать по десять раз в день.
        .overlay(alignment: .bottom) {
            UndoToastView().padding(.bottom, toastInset)
        }
        // Возврата на «Сегодня» по концу курса здесь больше нет, и это
        // половина того же решения от 08.10.2026.
        //
        // Он был СЛЕДСТВИЕМ условия лечения: вкладка исчезала вместе
        // с выбором, и `TabView` оставался на пустом месте — человека
        // приходилось уводить. Теперь вкладку держит право, она
        // по концу курса не исчезает, и увод стал бы скачком без
        // причины — прямо из-под руки у того, кто читает историю
        // закончившегося курса.
        .onChange(of: selection) { _, tab in
            UsageLog.note(.tab, String(describing: tab), on: screen(for: tab))
        }
        .onOpenURL(perform: handle)
    }

    /// Вкладка — это и есть экран: журнал действий не должен считать
    /// переключение вкладки действием на предыдущей.
    private func screen(for tab: Tab) -> UsageLog.Screen {
        switch tab {
        case .today: .today
        case .dog: .profile
        case .history: .history
        case .health: .health
        }
    }

    /// Две ссылки, и у обеих вкладка и экран ставятся **вместе**.
    ///
    /// ```
    /// togo://join/<token>   приглашение в семью из мессенджера
    /// togo://walk           тап по живой активности прогулки
    /// ```
    ///
    /// **Вкладки «Семья» больше нет, и одного переключения вкладки
    /// теперь мало.** Переключить на собаку и остановиться — это
    /// «вход есть, механизма нет»: человек пришёл по приглашению
    /// и получил список про питание и уход, а то, ради чего он нажал
    /// ссылку, лежит строкой, которую надо найти.
    ///
    /// **`walk` заведён 23.10.2026 — вторая половина цепочки дизайна**
    /// (круг 2 §6: «Тап по активности открывает „На улице"»).
    /// `WalkLiveActivity.widgetURL` стоял в дереве один, и неизвестный
    /// хост здесь молча проваливался: тап открывал просто приложение.
    /// Отказа человек не видел — поэтому дыру и не было видно ничем,
    /// кроме чтения двух файлов рядом.
    ///
    /// > **Приёмка этого — телефон, а не прогон.** Ни один сторож
    /// > не задаёт вопроса «каким путём человек сюда попадает»:
    /// > открыть живую активность и тапнуть по ней. Прогон накрывает
    /// > ровно половину — что ссылка **разобрана** в адресат
    /// > (`ГлубокиеСсылкиTests`), и не отвечает на «показалось ли».
    /// Довести до «Семьи» — **два шага, и оба обязательны.**
    ///
    /// Вынесено из `handle` 25.10.2026, когда у дороги появился второй
    /// вход: строка роли на «Сегодня» (ОТВЕТЫ-круг-5, п. 2 — «тап ведёт
    /// в „Семью"»). Переключить вкладку и остановиться — это ровно
    /// тот дефект, который здесь уже описан у ссылки `togo://join`:
    /// человек получает список про питание и уход, а то, ради чего
    /// он нажал, лежит строкой, которую надо найти.
    ///
    /// Поэтому способ один на оба входа, а не скопирован: две копии
    /// двухшагового перехода разойдутся молча, и разойдутся в сторону
    /// «переключили вкладку и всё».
    func показатьСемью() {
        selection = .dog
        открытьСемью = true
    }

    private func handle(_ url: URL) {
        switch RootView.адресат(url) {
        case .семья:
            показатьСемью()
        case .прогулка:
            selection = .today
            открытьПрогулку = true
        case nil:
            break
        }
    }

    /// Куда ведёт ссылка. Отдельным значением, а не ветками внутри
    /// `handle`, по одной причине: **разбор ссылки — единственная
    /// половина цепочки, которую можно спросить прогоном.** Внутри
    /// `handle` он недостижим ни одному тесту, и «хост `walk` забыли»
    /// снова стало бы находкой чтения, а не сторожа.
    ///
    /// Схема сверяется здесь, а не у вызывающего: `AppIdentifiers.urlScheme`
    /// стоит ещё в `URL_SCHEME` конфигурации и в `WalkLiveActivity.тапВедёт`,
    /// и три копии разошлись бы молча.
    enum Адресат: Equatable { case семья, прогулка }

    static func адресат(_ url: URL) -> Адресат? {
        guard url.scheme == AppIdentifiers.urlScheme else { return nil }
        switch url.host {
        case "join": return .семья
        case "walk": return .прогулка
        default: return nil
        }
    }
}

/// Каждая запись отменяется тостом; удаление обратимо 5 секунд.
struct UndoToastView: View {
    @Environment(AppState.self) private var appState
    /// Настройка размера текста: от неё зависит, строкой или столбцом
    /// раскладывать плашку.
    @Environment(\.dynamicTypeSize) private var размерТекста
    @Environment(\.modelContext) private var context

    var body: some View {
        @Bindable var appState = appState
        if let toast = appState.undo {
            // Подпись вешаем на текст, а не на всю плашку: иначе она
            // перекрывает собственное имя кнопки «Отменить», и до неё
            // не добраться ни голосом, ни тестом.
            let текст = Text(toast.message)
                .textStyle(AppFont.caption)
                .foregroundStyle(Token.Ink.primary)
                .wraps()
            // Кнопка — только когда есть что отменять. Без этого условия
            // она стояла во всех плашках, а делала что-то в пяти
            // из пятидесяти одной: у остальных `action` нет, и нажатие
            // проваливалось в `case nil: break`.
            //
            // Это ровно тот дефект, который описан выше у `Action`
            // и там же назван починенным — у удаления. Починка стояла
            // у одной двери из пятидесяти одной.
            let отменить = Button("Отменить") { undo(toast) }
                .textStyle(AppFont.captionEmphasis)
                .foregroundStyle(Token.Status.overdueText)
                .fixedSize()
                .frame(minHeight: Token.Size.tapTarget)
            let естьЧтоОтменять = toast.action != nil

            // Знак берётся у тона, а не стоит безусловно. Галочка поверх
            // «не сохранилось» читается раньше самой фразы: глаз берёт
            // значок первым, и человек уходит уверенным, что записал.
            let знак = Image(systemName: toast.tone == .успех
                             ? "checkmark.circle.fill"
                             : "exclamationmark.triangle.fill")
                .foregroundStyle(toast.tone == .успех
                                 ? Token.Action.doneText
                                 : Token.Status.overdueText)
                .accessibilityHidden(true)

            // Строка — пока текст и кнопка делят ширину. На крупной
            // системной настройке они её не делят: кадр 28.09 показал
            // «Записан / о · Еда» и «Отмени / ть» — перенос ВНУТРИ слова,
            // и в кнопке отмены тоже. Тогда столбцом: места вдвое
            // больше, порядок чтения тот же. Четвёртый случай одного
            // класса за день после плиток, дежурства и чипов ролей.
            Group {
                if размерТекста.isAccessibilitySize {
                    VStack(alignment: .leading, spacing: Token.Space.s8) {
                        HStack(spacing: Token.Space.s12) {
                            знак
                            текст
                        }
                        if естьЧтоОтменять { отменить }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                } else {
                    HStack(spacing: Token.Space.s12) {
                        знак
                        текст
                        Spacer(minLength: Token.Space.s8)
                        if естьЧтоОтменять { отменить }
                    }
                }
            }
            .padding(.horizontal, Token.Space.s16)
            .padding(.vertical, Token.Space.s12)
            .background(Token.Surface.card,
                        in: RoundedRectangle(cornerRadius: Token.Radius.sheet, style: .continuous))
            .shadow(color: Token.Ink.primary.opacity(0.12), radius: 14, y: 4)
            .padding(.horizontal, Token.Spacing.screenPadding)
            // Плашка ПРИЕЗЖАЕТ и УЕЗЖАЕТ анимацией — это `transition`
            // ниже, и он нужен. А подпись внутри неё при смене сообщения
            // не анимируется вовсе, и это `contentTransition`.
            //
            // # Два тоста накладывались буквами, и это замерено
            //
            // Отметь на прогулке «Занятие», следом «Стул» — и человек
            // читает «Отмечено · Стултие». Плашка ОДНА, галочка ОДНА:
            // `if let toast` остаётся истинным, структурная тождественность
            // вида не меняется, `transition` не срабатывает — значит
            // накладываются не плашки, а ТЕКСТ сам с собой.
            //
            // Причина — `AppState.show`: присваивание `undo` обёрнуто
            // в `withAnimation(.spring(duration: 0.28))`. Смена строки
            // внутри анимации идёт по `contentTransition`, а он по
            // умолчанию `.interpolate`: для двух разных строк это
            // перекрёстное растворение, то есть обе строки нарисованы
            // РАЗОМ.
            //
            // ```
            // кадр 1 (сразу после тапа)   «Отмечено · Стултие»   ← каша
            // кадр 4 (через ~0,3 с)       «Отмечено · Стул»      ← само прошло
            // ```
            //
            // Замер 23.10.2026 на `4625bc6`, кадры и дорога —
            // `Дизайн/кадры-приёмки/тост-наложение-23.10/`.
            // **Дефект проходит сам за 0,28 с, а кадры идут раз
            // в 0,22 с — его ловит ОДИН кадр.** Поэтому приёмка здесь
            // не «кадр чистый», а три прогона подряд плюс то, что
            // у соседних кадров пропала разница в байтах.
            //
            // **`.id(toast.id)` сюда не годится, хотя и компилируется:**
            // он завёл бы вторую плашку и прогнал бы `transition`
            // на обеих — вместо каши из букв человек получил бы две
            // пилюли внахлёст. Здесь задумано анимировать прибытие
            // плашки, а не подмену слов в ней.
            .contentTransition(.identity)
            .transition(.move(edge: .bottom).combined(with: .opacity))
            .task(id: toast.id) {
                try? await Task.sleep(for: .seconds(5))
                guard appState.undo?.id == toast.id else { return }
                withAnimation(.easeOut(duration: 0.2)) { appState.undo = nil }
            }
        }
    }

    /// Отмена записи дозы обязана снять и саму ОТМЕТКУ приёма.
    ///
    /// Запись в ленте — половина дозы. Вторая — `DoseRecord.givenAt`:
    /// от неё считается окно натощак, защита от второй дозы и запас,
    /// по ней снимаются напоминания. Тост «Отменить» прятал только
    /// запись, и доза оставалась «дана» (аудит 28.10.2026, G2): человек
    /// видел, что отменил, а телефон больше не напоминал.
    ///
    /// Снимает `DoseScheduler.unmark` — тот же путь, что у «снять
    /// отметку» в плане дня: таблетка возвращается в пачку, сохранение
    /// своё. Дозу ищем по препарату записи и моменту, когда её дали.
    private func снятьДозу(записью event: LogEvent) {
        guard event.kind == .dose,
              let схемаID = event.medicationID,
              let схема = event.dog?.medications.first(where: { $0.id == схемаID }),
              let доза = схема.doses.first(where: {
                  guard let дали = $0.givenAt else { return false }
                  return abs(дали.timeIntervalSince(event.date)) < 60
              })
        else { return }
        if !DoseScheduler.unmark(схема, scheduledAt: доза.scheduledAt, context: context) {
            appState.showFailure("Запись убрана, а отметка дозы — нет · сними её в плане дня")
        }
    }

    private func undo(_ toast: AppState.UndoToast) {
        switch toast.action {
        case .removeCreated(let id):
            if let event = event(id) {
                UsageLog.note(.undo, event.kind.rawValue)
                // Мягко, тем же способом, что и остальные четыре места
                // в проекте: удаление оставляет след.
                //
                // Жёсткое `context.delete` до второго телефона не
                // доезжало вовсе — обмен слушает `inserted`/`updated`,
                // и удалённой строки в этих списках нет. Запись успевала
                // уехать, а отмена — нет: у второго человека «покормила»
                // оставалось в ленте навсегда. Мягкое удаление приходит
                // к нему обычной правкой.
                event.deletedAt = Date()
                event.deletedBy = appState.currentUserName
                снятьДозу(записью: event)
            }
        case .restoreDeleted(let ids):
            UsageLog.note(.undo, "restore")
            // Прогулка возвращается вместе с отметками — тем же составом,
            // каким уходила.
            for id in ids {
                guard let event = event(id) else { continue }
                event.deletedAt = nil
                event.deletedBy = nil
            }
        case nil:
            break
        }
        // Отмена — это действие человека, и если она не записалась,
        // он обязан узнать: на экране запись вернулась, в хранилище нет.
        // Возврат здесь не пишем: состояние до отмены восстановит
        // следующая загрузка из хранилища, а молчание не восстановит
        // ничего.
        if context.persist(otherwise: {}) {
            appState.undo = nil
        } else {
            Haptics.warning()
            // Через `showFailure`, а не постройкой `UndoToast` руками:
            // у структуры `tone` объявлен с умолчанием `.успех`
            // (`AppState`), и прямая постройка молча получала знак
            // успеха — на сообщении о том, что отмена НЕ сохранилась,
            // при уже сработавшей `Haptics.warning()` строкой выше.
            //
            // То есть приложение знало, что это отказ, и показывало
            // галочку. Это была ТРЕТЬЯ дверь к плашке: сторож знака
            // проверял `showUndo` и `showFailure`, а здесь не было
            // вызова вовсе — и оба его утверждения оставались зелёными.
            appState.showFailure("Отмена не сохранилась · попробуй ещё раз",
                                 action: toast.action)
        }
    }

    private func event(_ id: UUID) -> LogEvent? {
        let descriptor = FetchDescriptor<LogEvent>(predicate: #Predicate { $0.id == id })
        return try? context.fetch(descriptor).first
    }
