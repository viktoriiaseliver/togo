#!/usr/bin/env python3
"""Что общий дневник пишет в CloudKit — выведено из кода, не из файла.

    python3 Tools/схема_общего_дневника.py            # таблица для человека
    python3 Tools/схема_общего_дневника.py --json     # для сверки скриптом

**Зачем этот файл появился 14.10.2026.** Ворота приёмки схемы
(`Tools/deploy_cloudkit_schema.sh`) сверяли production с
`CloudKit/schema.ckdb`, а тот описывает **два** типа — `LogEvent`
и `DoseRecord`. Код к этому дню писал **двенадцать**. То есть ворота
говорили «в production есть всё из файла» и были правы, а вопрос,
на который их звали, был другой: «есть ли в production всё, что пишет
код». Эталон отстал на двадцать дней, и заметить это по зелёному было
нельзя ничем.

> **Сверка с рукописным эталоном отвечает про эталон.** Чтобы она
> отвечала про код, эталон надо выводить из кода.

Поэтому здесь не копия и не список, а **разбор**: единственный источник
— `TogoShared/Sync/SharedDiaryRecords.swift`, где присвоение
`record["поле"] = …` и есть отправка поля в CloudKit, и
`TogoShared/Sync/SharedDiary.swift`, где `enum RecordType` даёт имена
типов. Ни одного имени поля здесь не записано руками: запишешь — и эта
копия разойдётся с кодом ровно так же, как разошёлся `schema.ckdb`.

**Чего этот разбор НЕ делает.** Он не знает типов значений
(`STRING`/`TIMESTAMP`/`INT64`), потому что в месте присвоения их нет:
`record["grams"] = payload.grams` не говорит, что `grams` целое.
Выводить тип отсюда значило бы угадывать, а угаданный тип в файле
схемы молчит до первой записи. Поэтому инструмент отвечает только
на вопрос «какие ПОЛЯ каких ТИПОВ ЗАПИСЕЙ код отправляет» — и ворота
строятся на нём, а не на догадке.

**Приёмка встроена, и это не украшение.** Разбор регулярками — тот
самый класс, который в этом проекте врал чаще всего: `grep` без
`--no-ignore-files` даёт ложный ноль, сторож полей моделей считал
уровень тела класса нулевым и находил ноль полей у всех. Пустой ответ
и «нечего отправлять» здесь неотличимы на глаз, поэтому инструмент
**падает**, если результат выглядит вырожденным: нет всех типов из
`enum RecordType`, или у какого-то типа ноль полей. Отказ называет,
что именно не сошлось, а не печатает пустую таблицу.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORDS = os.path.join(ROOT, "TogoShared/Sync/SharedDiaryRecords.swift")
DIARY = os.path.join(ROOT, "TogoShared/Sync/SharedDiary.swift")


def читать(path):
    if not os.path.exists(path):
        sys.exit(f"нет файла {path} — замер не состоялся, это ответ про путь, а не про код")
    with open(path, encoding="utf-8") as f:
        return f.read()


def типы_записей(text):
    """`case dog = "Dog"` → {"dog": "Dog"}. Только внутри enum RecordType.

    **Закомментированные строки отбрасываются, и за это уже заплачено
    в первом же прогоне этого файла.** В `RecordType` лежит снятый
    08.10 `// case member = "FamilyMember"` с объяснением, почему его
    не надо заводить обратно. Разбор без этой строки нашёл тринадцать
    типов вместо двенадцати и объявил `FamilyMember` пропавшим
    из production — то есть **предъявил счёт за намеренно снятое**.

    Поймала собственная приёмка этого файла, а не чтение: вырожденный
    результат она называет, а не печатает.
    """
    начало = text.find("enum RecordType")
    if начало < 0:
        sys.exit("в SharedDiary.swift не найден `enum RecordType` — замер не состоялся")
    # Конец перечисления — первая строка, закрывающая его тело.
    хвост = text[начало:]
    конец = хвост.find("\n    }")
    тело = хвост[:конец if конец > 0 else len(хвост)]
    живые = [s for s in тело.splitlines() if not s.lstrip().startswith(("//", "///"))]
    return dict(re.findall(r'case (\w+) = "(\w+)"', "\n".join(живые)))


def тело_функции(text, начало):
    """От `{` после сигнатуры до парной `}`. Счётом скобок, не отступом.

    Отступ врёт: `final class X {` уже открыла скобку, и разбор
    по уровню отступа однажды дал ноль полей у всех моделей сразу.
    """
    i = text.find("{", начало)
    if i < 0:
        return ""
    глубина = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            глубина += 1
        elif text[j] == "}":
            глубина -= 1
            if глубина == 0:
                return text[i + 1:j]
    return ""


def поля_по_снимку(text):
    """`apply(_ payload: XPayload, to record:)` → поля, которые он пишет."""
    out = {}
    for m in re.finditer(r"static func apply\(_ payload: (\w+), to record: CKRecord\)", text):
        тело = тело_функции(text, m.end())
        out[m.group(1)] = sorted(set(re.findall(r'record\["(\w+)"\]\s*=', тело)))
    return out


def снимок_по_типу(text, кейсы):
    """`record(_ payload: XPayload…)` + `RecordType.<кейс>` → XPayload → имя типа."""
    out = {}
    for m in re.finditer(r"static func record\(_ payload: (\w+)", text):
        тело = тело_функции(text, m.end())
        найден = re.search(r"SharedDiary\.RecordType\.(\w+)\.rawValue", тело)
        if найден and найден.group(1) in кейсы:
            out[m.group(1)] = кейсы[найден.group(1)]
    return out


def собрать():
    записи = читать(RECORDS)
    кейсы = типы_записей(читать(DIARY))
    поля = поля_по_снимку(записи)
    тип_по_снимку = снимок_по_типу(записи, кейсы)

    схема = {}
    for снимок, имя in тип_по_снимку.items():
        if снимок in поля:
            схема[имя] = поля[снимок]

    # Приёмка. Пустой ответ и «нечего отправлять» на глаз неотличимы.
    беды = []
    пропали = sorted(set(кейсы.values()) - set(схема))
    if пропали:
        беды.append("типы объявлены в RecordType, но разбор их не нашёл: " + ", ".join(пропали))
    for имя, список in sorted(схема.items()):
        if not список:
            беды.append(f"{имя}: ноль полей — разбор не состоялся")
    if беды:
        sys.exit("ЗАМЕР НЕ СОСТОЯЛСЯ:\n  " + "\n  ".join(беды))

    return схема


# Swift → CloudKit. Таблица короткая нарочно: всё, чего в ней нет,
# попадает в «не выведено» и едет к человеку списком, а не угадывается.
#
# Решает не тип свойства, а ВЫРАЖЕНИЕ присвоения: `payload.isNeutered ? 1 : 0`
# кладёт число, какой бы ни была декларация. Поэтому выражение читается
# первым, и только если оно ничего не говорит — смотрим тип.
#
# **`Bool` → `INT64` — решение менеджера смены 14.10.2026, и у него
# восемь измеренных прецедентов в этом же контейнере**, четыре из которых
# завела не наша рука: `isNeutered`, `isOnTreatment`, `fromPortion`,
# `isPaused` (наши, через `? 1 : 0`) и `CD_isNeutered`, `CD_isPaused`,
# `CD_isDayOnly`, `CD_toldFamily` (зеркало SwiftData). Булева типа
# у CloudKit нет вовсе.
#
# **Сначала этой строки здесь не было нарочно, и час она не появлялась.**
# Три поля — `Clinic.isLab`, `Medication.canGiveOutside`,
# `Medication.remindBeforeExpiry` — присваиваются как `Bool` напрямую,
# без `? 1 : 0`, а читаются `record["isLab"] as? Bool`. Я выдвинул, что
# после круга через CloudKit значение придёт `NSNumber` с `objCType=q`,
# мостик `as? Bool` отдаст `nil`, и `?? false` закрепит ложь навсегда.
# Предложил не заводить поля, пока не поправлена пара запись/чтение.
#
# **Замер это опроверг, и правка оказалась не нужна:**
#
#     NSNumber(Bool true)   objCType=c   as? Bool = true
#     NSNumber(Int64 1)     objCType=q   as? Bool = true
#     NSNumber(Int 1)       objCType=q   as? Bool = true
#
# Мостик Swift сверяет ЗНАЧЕНИЕ на точную представимость, а не
# `objCType`. Чтение переживает круг при любом из трёх.
#
# > **Опасение было правдоподобным, стоило пяти строк на проверку
# > и не пережило их.** Разница между «поправить код» и «добавить поле»
# > здесь — целая чужая правка в файле, который мне даже не принадлежал.
SWIFT_В_CLOUDKIT = {
    "String": "STRING",
    "Date": "TIMESTAMP",
    "Int": "INT64",
    "Double": "DOUBLE",
    "Bool": "INT64",        # булева типа у CloudKit нет
    "UUID": "STRING",       # едет через .uuidString
    "Data": "BYTES",
    "[String]": "LIST<STRING>",
    "[Int]": "LIST<INT64>",
    "[Double]": "LIST<DOUBLE>",
}


def поля_снимков(text):
    """Объявления `struct XPayload { var имя: Тип }` → {снимок: {имя: тип}}.

    Разбор по снимкам, а не общим словарём: `clinicID` объявлен
    в трёх снимках, и общий словарь отдал бы тип последнего. Такая
    ошибка молчит — имя совпало, тип подменился.
    """
    out = {}
    for m in re.finditer(r"struct (\w+Payload)[^{]*\{", text):
        тело = тело_функции(text, m.end() - 1)
        поля = {}
        for имя, тип in re.findall(r"^\s+var (\w+): ([^\n=]+?)\s*(?:=.*)?$", тело, re.M):
            поля[имя] = тип.strip()
        out[m.group(1)] = поля
    return out


def выражения(text):
    """`apply(_ payload: XPayload…)` → ({поле: правая часть}, {местная: тип}).

    Местные объявления нужны, потому что не всякое поле присваивается
    из снимка напрямую. `doseSlotsData` кладётся через переменную:

        let слотыJSON: Data? = payload.doseSlotsData
            .flatMap { try? JSONEncoder().encode($0) }
        record["doseSlotsData"] = слотыJSON

    Тип здесь объявлен явно и **измеряется**, а не угадывается по имени.
    Без этого шага поле попадало в «не выведено» и ехало к человеку
    вопросом, на который ответ лежал двумя строками выше.
    """
    out = {}
    for m in re.finditer(r"static func apply\(_ payload: (\w+), to record: CKRecord\)", text):
        тело = тело_функции(text, m.end())
        местные = dict(re.findall(r"^\s+let (\w+): ([^\n=]+?)\s*=", тело, re.M))
        out[m.group(1)] = (dict(re.findall(r'record\["(\w+)"\]\s*=\s*(.+)', тело)), местные)
    return out


def тип_поля(выражение, тип_свойства):
    """Тип CloudKit. Возвращает None, если не выводится однозначно."""
    # Выражение сильнее объявления: оно говорит, ЧТО лёг в запись.
    if "? 1 : 0" in выражение or "{ $0 ? 1 : 0 }" in выражение:
        return "INT64"
    if ".uuidString" in выражение:
        return "STRING"
    if ".rawValue" in выражение and тип_свойства is None:
        return None
    if тип_свойства is None:
        return None
    голый = тип_свойства.rstrip("?").strip()
    return SWIFT_В_CLOUDKIT.get(голый)


def ckdb(схема_полей):
    """Собрать DEFINE SCHEMA. Возвращает (текст, список невыведенных)."""
    записи = читать(RECORDS)
    кейсы = типы_записей(читать(DIARY))
    снимки = поля_снимков(читать(DIARY))
    выраж = выражения(записи)
    тип_по_снимку = снимок_по_типу(записи, кейсы)

    строки, невыведено = [], []
    for снимок, имя_типа in sorted(тип_по_снимку.items(), key=lambda kv: kv[1]):
        if имя_типа not in схема_полей:
            continue
        присвоения, местные = выраж.get(снимок, ({}, {}))
        поля = []
        for поле in схема_полей[имя_типа]:
            выражение = присвоения.get(поле, "")
            свойство = выражение.split(".")[-1].split(" ")[0].rstrip("?)")
            тип_св = (снимки.get(снимок, {}).get(свойство)
                      or местные.get(выражение.strip()))
            т = тип_поля(выражение, тип_св)
            if т is None:
                невыведено.append(f"{имя_типа}.{поле}  ←  {выражение.strip()}"
                                  f"  (свойство {свойство}: {тип_св or 'не найдено'})")
            else:
                поля.append((поле, т))
        if not поля:
            continue
        # Две служебные отметки CloudKit заводит сам у каждого типа.
        # В выгрузке production они есть у всех пяти живых типов, и файл
        # схемы их перечисляет (`CloudKit/schema.ckdb:24-25`). Импорт
        # заменяет описание типа ЦЕЛИКОМ — значит файл без них читается
        # как «эти поля удалить», а удаление поля CloudKit не делает:
        # он отвечает отказом. Потерять их молча тут нельзя.
        поля += [("createdTimestamp", "TIMESTAMP"),
                 ("modifiedTimestamp", "TIMESTAMP")]
        ширина = max(len(f) for f, _ in поля)
        тело = "".join(f"        {f.ljust(ширина)} {t},\n" for f, t in sorted(поля))
        строки.append(
            f"    RECORD TYPE {имя_типа} (\n{тело}"
            '        GRANT WRITE TO "_creator",\n'
            '        GRANT CREATE TO "_icloud",\n'
            '        GRANT READ TO "_world"\n'
            "    );\n"
        )
    return "DEFINE SCHEMA\n\n" + "\n".join(строки), невыведено


def дополнить(основа, выведенное):
    """Живая выгрузка плюс недостающее. Основа не переписывается.

    **Почему слиянием, а не вместо.** `cktool import-schema` заменяет
    схему контейнера ЦЕЛИКОМ. Файл на двенадцать типов читался бы как
    «остальные одиннадцать удалить», а среди них зеркало `CD_*`, форму
    которого задаёт SwiftData, — и CloudKit отвечает «invalid attempt
    to delete cloudkit managed record type» и падает. Это уже случалось
    22.09.2026 и записано в `deploy_cloudkit_schema.sh:33-38`.

    Отсюда и устройство: берём выгрузку живого контейнера и **только
    дописываем**. Всё, что уже есть, остаётся побуквенно тем же —
    значит расхождение в существующем поле невозможно по устройству,
    а не по аккуратности. Там, где нельзя ошибиться, лучше не иметь
    возможности ошибиться.
    """
    def разобрать(текст):
        out = {}
        for имя, тело in re.findall(r"RECORD TYPE (\w+) \((.*?)\)\s*;", текст, re.S):
            поля = {}
            for строка in тело.splitlines():
                строка = строка.strip().rstrip(",")
                if not строка or строка.startswith("GRANT"):
                    continue
                части = строка.split()
                поля[части[0].strip('"')] = " ".join(части[1:])
            out[имя] = поля
        return out

    есть, надо = разобрать(основа), разобрать(выведенное)
    результат = основа.rstrip("\n")
    дописано_полей, новых_типов = 0, []

    # 1. Недостающие поля у существующих типов — строкой перед GRANT.
    for имя in sorted(надо):
        if имя not in есть:
            continue
        новые = [(f, t) for f, t in sorted(надо[имя].items()) if f not in есть[имя]]
        if not новые:
            continue
        дописано_полей += len(новые)
        блок = re.search(r"(    RECORD TYPE %s \(\n)(.*?)(^\s+GRANT)" % имя,
                         результат, re.S | re.M)
        ширина = max(len(f) for f, _ in новые)
        вставка = "".join(f"        {f.ljust(ширина)} {t},\n" for f, t in новые)
        результат = (результат[:блок.end(2)] + вставка + результат[блок.end(2):])

    # 2. Типы, которых нет вовсе — блоками в конец.
    хвост = []
    for имя in sorted(надо):
        if имя in есть:
            continue
        новых_типов.append(имя)
        блок = re.search(r"(    RECORD TYPE %s \(.*?\);\n)" % имя, выведенное, re.S)
        хвост.append(блок.group(1))

    if хвост:
        результат = результат.rstrip("\n") + "\n\n" + "\n".join(хвост)

    sys.stderr.write(
        f"дополнено: полей {дописано_полей}, новых типов {len(новых_типов)}"
        + (" — " + ", ".join(новых_типов) if новых_типов else "") + "\n")
    return результат if результат.endswith("\n") else результат + "\n"


def main():
    схема = собрать()
    if "--json" in sys.argv:
        print(json.dumps(схема, ensure_ascii=False, sort_keys=True, indent=2))
        return
    if "--ckdb" in sys.argv:
        текст, невыведено = ckdb(схема)
        if "--основа" in sys.argv:
            основа = sys.argv[sys.argv.index("--основа") + 1]
            текст = дополнить(читать(основа), текст)
        if невыведено:
            sys.stderr.write(
                "ТИП НЕ ВЫВЕДЕН — НЕ УГАДЫВАТЬ, решать человеком "
                f"({len(невыведено)}):\n  " + "\n  ".join(невыведено) + "\n\n")
        print(текст, end="")
        if невыведено:
            sys.exit(2)
        return
    всего = 0
    for имя in sorted(схема):
        поля = схема[имя]
        всего += len(поля)
        print(f"{имя} ({len(поля)})")
        print("    " + " · ".join(поля))
    print(f"\nтипов {len(схема)}, полей {всего} — выведено из "
          f"TogoShared/Sync/SharedDiaryRecords.swift")


if __name__ == "__main__":
    main()
