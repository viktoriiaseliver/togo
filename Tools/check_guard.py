#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Того · проверка сторожа подделкой, с откатом внутри инструмента.

    python3 Tools/check_guard.py \\
        --файл Togo/Features/Today/ActionGrid.swift \\
        --было  'SmallAction(title: "Еда"' \\
        --стало 'SmallAction(title: "Кормёжка"' \\
        --набор TogoTests/AddressedQuotesTests

Сторож, который не краснеет на сегодняшнем коде, ничего не доказывает —
это записано в брифе спринта. Способ узнать один: внести дефект, который
он обязан поймать, и посмотреть. Способ дешёвый и, как выяснилось
23.09.2026, опасный: за один час три подделки обошлись дороже того,
что проверяли.

ЧТО ИМЕННО СЛОМАЛОСЬ В ТОТ ДЕНЬ, И ПОЧЕМУ КАЖДОЕ ЗДЕСЬ ЗАКРЫТО

1. **Подделка не применилась, а прогон был зелёным.** Дважды: замена
   по регулярному выражению не совпала, и питоновская строка упала
   на синтаксисе. Зелёное на неприменённой подделке читается как
   «сторож не ловит» — вывод, обратный правде.
   → Здесь подделка проверяется чтением файла заново, и без этого
     прогон не запускается вовсе.

2. **Подделка осталась в общем дереве.** Прогон упал по таймауту
   оболочки до строки отката, и испорченный код пролежал двадцать
   минут — ровно тогда, когда рядом запустили сборку. `xcodebuild`
   архивирует диск, а не коммит.
   → **Рабочее дерево не трогается вовсе.** Подделка живёт в отдельном
     `git worktree` во временном каталоге, и прогон идёт там же.

   Первая редакция полагалась на `finally` и обработчики сигналов —
   и провалилась на первом же запуске ровно так, как предыдущие три
   раза: оболочка убила процесс неперехватываемым сигналом, `finally`
   не наступил, подделка осталась лежать. **Откат, зависящий от того,
   что процесс доживёт до строки отката, — это обещание, а не защита.**
   Единственная надёжная защита — не портить то, что жалко.

3. **Откат снёс настоящую правку.** `git checkout --` возвращает файл
   целиком, а не подделку: вместе с ней ушла работа получасом раньше.
   → Инструмент **отказывается подделывать файл с незакоммиченными
     правками**. Тогда откат через git безопасен по построению, и
     второй механизм отката не нужен — как и записано в своде.

4. **Стенд стёр то, что проверял.** Заглушки закрыли дорогую команду
   и пропустили разрушительную.
   → Здесь подделывается только текст в файле; ничего не удаляется
     и не пересобирается.

И пятое, без чего проверка ничего не значит: **сторож обязан быть
зелёным ДО подделки.** Красный до неё и красный после — это не «поймал»,
это «был сломан».
"""

import argparse
import shutil
import tempfile
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def сказать(строка):
    print(строка, flush=True)


def git(*аргументы):
    return subprocess.run(
        ["git", "--no-optional-locks", *аргументы],
        cwd=КОРЕНЬ, capture_output=True, text=True)


def прогон(набор, где):
    """Прогнать набор. Возвращает (зелёный, хвост вывода).

    Код возврата берётся у самого `xcodebuild`, а не у конвейера:
    `xcodebuild … | grep` возвращает код `grep`, и падение читается
    как успех. Здесь конвейера нет вовсе.
    """
    udid = subprocess.run(
        [sys.executable, "Tools/ci_simulator.py"],
        cwd=КОРЕНЬ, capture_output=True, text=True).stdout.strip().splitlines()[-1]

    готово = subprocess.run(
        ["xcodebuild", "-project", "Togo.xcodeproj", "-scheme", "Togo",
         "-destination", f"platform=iOS Simulator,id={udid}",
         "test", "-only-testing:" + набор,
         # Своя папка сборки: общая с рабочим деревом означала бы, что
         # подделка попадает в те же артефакты, из которых потом
         # собирают настоящее.
         "-derivedDataPath", str(где / "build-подделка")],
        cwd=где, capture_output=True, text=True)

    вывод = готово.stdout + готово.stderr
    интересное = [с for с in вывод.splitlines()
                  if "✘ Test" in с or "✔ Test" in с or "TEST SUCCEEDED" in с
                  or "TEST FAILED" in с or "error:" in с]
    return готово.returncode == 0, "\n".join(интересное[-12:])


def main():
    разбор = argparse.ArgumentParser(
        description="Проверить сторожа подделкой в отдельном дереве.")
    разбор.add_argument("--файл", required=True)
    разбор.add_argument("--было", required=True, help="что заменить (точная строка)")
    разбор.add_argument("--стало", required=True, help="на что заменить")
    разбор.add_argument("--набор", required=True,
                        help="например TogoTests/AddressedQuotesTests")
    аргументы = разбор.parse_args()

    цель = КОРЕНЬ / аргументы.файл
    if not цель.exists():
        sys.exit(f"✗ файла нет: {аргументы.файл}")

    # Подделывается то, что закоммичено. Незакоммиченная правка
    # в отдельное дерево не попадёт, и проверка пойдёт не по тому коду,
    # который ты только что написал, — а выглядеть будет одинаково.
    грязно = git("status", "--porcelain", "--", аргументы.файл).stdout.strip()
    if грязно:
        sys.exit(f"""✗ у файла есть незакоммиченные правки:

  {грязно}

Отдельное дерево берёт коммит, а не диск: проверка пошла бы по коду
без твоей правки и ничего бы о ней не сказала. Закоммить — и запускай.""")

    if аргументы.было not in цель.read_text(encoding="utf-8"):
        sys.exit(f"✗ в файле нет строки «{аргументы.было[:60]}» — подделывать нечего")

    дерево = Path(tempfile.mkdtemp(prefix="togo-подделка-"))
    сказать(f"── отдельное дерево: {дерево}")
    завели = git("worktree", "add", "--detach", str(дерево), "HEAD")
    if завели.returncode != 0:
        sys.exit(f"✗ не завелось отдельное дерево:\n{завели.stderr}")

    try:
        копия = дерево / аргументы.файл
        исходное = копия.read_text(encoding="utf-8")

        сказать(f"── сторож до подделки: {аргументы.набор}")
        зелёный_до, хвост = прогон(аргументы.набор, дерево)
        if not зелёный_до:
            сказать(хвост)
            sys.exit("\n✗ сторож красный ДО подделки. Красный до и красный после — "
                     "это не «поймал», это «был сломан». Сначала почини.")
        сказать("   зелёный")

        копия.write_text(исходное.replace(аргументы.было, аргументы.стало, 1),
                         encoding="utf-8")

        # Подделка подтверждается чтением файла заново, а не верой
        # в успех замены: дважды 23.09 замена не совпадала, и зелёный
        # прогон читался как «сторож не ловит».
        проверка = копия.read_text(encoding="utf-8")
        if аргументы.стало not in проверка or проверка == исходное:
            sys.exit("✗ подделка не применилась — прогонять нечего.")
        сказать("── подделка применена и подтверждена (в отдельном дереве)")

        зелёный_после, хвост = прогон(аргументы.набор, дерево)
    finally:
        # Даже если это не выполнится — рабочее дерево не тронуто,
        # и единственная цена забытой уборки в том, что на диске
        # останется каталог. Это и есть смысл всей перестройки.
        git("worktree", "remove", "--force", str(дерево))
        shutil.rmtree(дерево, ignore_errors=True)
        сказать("── отдельное дерево убрано")

    сказать("")
    сказать(хвост)
    if зелёный_после:
        sys.exit("\n✗ СТОРОЖ НЕ ПОЙМАЛ. Он зелёный и с дефектом — значит "
                 "проверяет не то, что думает, и ничего не доказывает.")
    сказать("\n✓ сторож поймал подделку; рабочее дерево не трогалось")


if __name__ == "__main__":
    main()
