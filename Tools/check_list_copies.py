#!/usr/bin/env python3
"""Сторож класса «копии одного утверждения расходятся молча».

    python3 Tools/check_list_copies.py [--перепись ПУТЬ] [--подробно]

Предмет — **утверждение-перечисление**: список, записанный прозой
в нескольких местах, где одно из мест — источник в коде, а остальные
переписаны рукой и на пяти языках. Такой список расходится не однажды,
а **поштучно**: 03.11.2026 четыре копии «бесплатно навсегда» правились
в три разных дня тремя руками, и четвёртая лежала в шапке того самого
файла, чьё тело описывает снятие пункта.

Перепись — `Tools/копии-списков.json`. **Копии самого списка в ней
нет:** ключи раздела «живые» сверяются с извлечённым из источника,
и расхождение между ними — первая находка.

# Три оси, и сильная — вторая

```
A  ПЕРЕПИСЬ ПРОТИВ ИСТОЧНИКА   пункт ушёл или пришёл — красный, пока
                               перепись не поправлена
B  НАДГРОБИЕ                   снятый пункт обязан отсутствовать
                               во ВСЕХ копиях
C  ОТКРЫТИЕ                    фрагмент, где сошлось «порог» пунктов,
                               а в переписи его нет — находка
```

**Замкнутость даёт B.** Снять пункт из источника и остаться зелёным
нельзя: ось A покраснеет, пока пункт не перенесён в «снятые», а перенос
немедленно красит каждую копию, которая его ещё держит. То есть
единственная дорога к зелёному — поправить все копии; забыть половину
нельзя по устройству, а не по памяти.

**Класс, а не перечень, даёт C.** Ось A и B работают по объявленным
адресам, то есть защищают от расхождения, но не от **новой копии,
которую никто не объявлял**. Именно её 03.11 нашли глазами. C ищет
со-встречаемость пунктов в одном фрагменте по всему дереву и требует,
чтобы каждое найденное место было объявлено — копией, разбором
или долгом с хозяином.

# Чего этот сторож НЕ делает — печатается последней строкой

Главное: он **не читает App Store Connect и живые страницы сайта**.
Витрина и тексты покупки живут вне git, правятся на отдельных ручках,
и 03.11 выяснилось, что витрину поправили 24.10, а восемь полей
покупки обещали снятую вещь ещё девять дней. Здесь сверяется
**репозиторий**, то есть то, чего мы хотим.

# Почему отказ не умеет выглядеть успехом

Извлечение из источника, ненайденный якорь и пустая перепись —
**находки, а не пропуски**. Ноль извлечённых пунктов значит «источник
не прочитан», и зелёный при нём был бы ровно тем ложным нулём, против
которого весь этот файл: вывод «0 расхождений» при нуле проверенного
читается как «всё сошлось».
"""
import argparse
import json
import os
import re
import subprocess
import sys
import unicodedata

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПЕРЕПИСЬ = os.path.join(КОРЕНЬ, "Tools/копии-списков.json")

# Открытие идёт по тексту. Расширения названы поимённо, а не «всё, что
# не картинка»: `git ls-files` отдаёт и кадры приёмки, и .fig, и чтение
# их байтов как UTF-8 — это ловушка того же вида, что `grep` без `-a`
# на двоичном логе: отказ приходит в форме пустого ответа.
ТЕКСТОВЫЕ = {".swift", ".txt", ".md", ".json", ".py", ".sh", ".html", ".css",
             ".js", ".yml", ".yaml", ".strings", ".stringsdict", ".storekit",
             ".xcconfig", ".plist", ".pbxproj", ".entitlements", ".xml", ".svg"}

ОКНО = 4  # строк: шапка Subscriptions занимает три, строка таблицы — одну


def норм(текст):
    """Невидимое и типографское — к простому, и всё в нижний регистр.

    Три причины, все замеренные в этом проекте:

    * **NFC против NFD.** Кириллица в git и в логах сборки хранится
      в двух нормализациях разом, и побайтная сверка даёт ложный ноль;
    * **узкий неразрывный пробел** U+202F стоит у французского перед
      `?` и `!` — правильная типографика, на которой побайтная сверка
      покраснела бы на верном переводе;
    * **апостроф**: украинское «сім'я» в `subscriptions.json` набрано
      прямым U+0027, французское «l’aide» — типографским U+2019.
    """
    текст = unicodedata.normalize("NFC", текст)
    for пробел in (" ", " ", " ", " "):
        текст = текст.replace(пробел, " ")
    for апостроф in ("’", "ʼ", "′", "`", "´"):
        текст = текст.replace(апостроф, "'")
    for тире in ("—", "–", "−"):
        текст = текст.replace(тире, "-")
    return текст.lower()


def читать(путь):
    полный = os.path.join(КОРЕНЬ, путь)
    if not os.path.exists(полный):
        return None
    with open(полный, encoding="utf-8", errors="replace") as дескриптор:
        return дескриптор.read()


# ─────────────────────────────── ОСЬ A ───────────────────────────────

def извлечь(источник):
    """Пункты из кода. Возвращает (список, объяснение_отказа).

    Отказ называется словом, а не пустым списком: пустой список
    и «символа нет» читаются одинаково, и второе — не ответ про мир.
    """
    текст = читать(источник["путь"])
    if текст is None:
        return [], f"файла нет: {источник['путь']}"
    вид = источник["вид"]

    if вид == "swift-массив-строк":
        # Тело вычисляемого свойства: от объявления до строки, которая
        # закрывает его на том же отступе. Разбирать Swift целиком тут
        # нечем и незачем — зато промах виден по числу пунктов.
        начало = re.search(
            r"^(\s*)(?:static\s+)?var\s+" + re.escape(источник["символ"])
            + r"\s*:\s*\[String\]\s*\{", текст, re.M)
        if not начало:
            return [], (f"символ «{источник['символ']}» не найден "
                        f"в {источник['путь']} — переименован или переехал")
        отступ = начало.group(1)
        хвост = текст[начало.end():]
        конец = re.search(r"^" + отступ + r"\}", хвост, re.M)
        тело = хвост[:конец.start()] if конец else хвост
        пункты = re.findall(r'String\(localized:\s*"((?:[^"\\]|\\.)*)"', тело)
        if not пункты:
            return [], (f"тело «{источник['символ']}» прочитано, а строк "
                        f"String(localized:) в нём нет — форма списка сменилась")
        return пункты, None

    if вид == "swift-случаи-перечисления":
        начало = re.search(r"^(\s*)(?:\w+\s+)*enum\s+"
                           + re.escape(источник["символ"]) + r"\b[^\{]*\{",
                           текст, re.M)
        if not начало:
            return [], (f"перечисление «{источник['символ']}» не найдено "
                        f"в {источник['путь']}")
        отступ = начало.group(1)
        хвост = текст[начало.end():]
        конец = re.search(r"^" + отступ + r"\}", хвост, re.M)
        тело = хвост[:конец.start()] if конец else хвост
        # Только объявления случаев верхнего уровня перечисления:
        # `case .secondDog:` внутри switch отличается точкой и двоеточием.
        пункты = []
        for строка in тело.splitlines():
            совпало = re.match(r"\s*case\s+([a-zA-Zа-яёА-ЯЁ_][\w]*)\s*(?:,|$)",
                               строка)
            if совпало and not строка.lstrip().startswith("case ."):
                пункты.extend(
                    имя.strip() for имя in
                    re.sub(r"^\s*case\s+", "", строка).split(",")
                    if re.fullmatch(r"[a-zA-Zа-яёА-ЯЁ_][\w]*", имя.strip()))
        if not пункты:
            return [], (f"тело перечисления «{источник['символ']}» прочитано, "
                        f"а случаев в нём нет")
        return пункты, None

    return [], f"неизвестный вид источника: {вид}"


# ─────────────────────────────── ОСЬ B ───────────────────────────────

def фрагмент(копия):
    """Строки копии по якорю. Возвращает (текст, номер_строки, отказ).

    **Ненайденный якорь — находка.** Копию переписали или переместили,
    и молчаливый пропуск здесь дал бы зелёный на непроверенном: ровно
    тот ложный ноль, от которого этот сторож и стоит.
    """
    текст = читать(копия["путь"])
    if текст is None:
        return None, 0, f"файла нет: {копия['путь']}"
    строки = текст.splitlines()
    якорь = норм(копия["якорь"])
    сколько = копия.get("строк", 1)
    for номер, строка in enumerate(строки):
        if якорь in норм(строка):
            кусок = "\n".join(строки[номер:номер + сколько])
            return кусок, номер + 1, None
    return None, 0, (f"якорь «{копия['якорь']}» в {копия['путь']} не найден — "
                     f"копия переписана, переехала или удалена")


def метки(узел, язык):
    """Метки пункта для языка копии. Нет языка — нет и проверки."""
    if язык in узел:
        return узел[язык]
    return []


def есть(фраг, список_меток):
    норм_фраг = норм(фраг)
    return any(норм(метка) in норм_фраг for метка in список_меток)


# ─────────────────────────────── ОСЬ C ───────────────────────────────

def дерево():
    """Отслеживаемые текстовые файлы. Только git — не диск.

    `core.quotePath=false` обязателен: иначе путь с кириллицей приезжает
    экранированным, `os.path.exists` его не находит, и файл молча
    выпадает из открытия. Ложный ноль про путь — наш отдельный класс.
    """
    готово = subprocess.run(
        ["git", "-c", "core.quotePath=false", "ls-files", "-z"],
        cwd=КОРЕНЬ, capture_output=True, text=True)
    if готово.returncode != 0:
        return [], f"git ls-files отказал: rc={готово.returncode}"
    пути = [п for п in готово.stdout.split("\0") if п]
    if not пути:
        return [], "git ls-files вернул пусто — замер не состоялся"
    return [п for п in пути
            if os.path.splitext(п)[1].lower() in ТЕКСТОВЫЕ], None


def словарь_меток(список):
    """Метки всех языков, нормализованные ОДИН раз на список.

    Вынесено из `открытие` замером: при широких стеблях («подвійн»,
    «наказ») пересборка словаря и `норм` каждой метки внутри цикла
    по окнам сто́ила больше двух минут на 907 файлах. Теперь
    нормализация — один проход, и у файла без ни одной метки цикл
    по окнам не начинается вовсе.
    """
    живые = {п: [норм(м) for язык, мм in узел.items() if язык != "_"
                 for м in mm_list(мм)]
             for п, узел in список["живые"].items() if п != "_"}
    снятые = {п: [норм(м) for язык, мм in узел["метки"].items() if язык != "_"
                  for м in mm_list(мм)]
              for п, узел in список.get("снятые", {}).items()}
    return живые, снятые


def открытие(путь, список, вне):
    """Где в файле сошлось «порог» пунктов списка. Возвращает список находок.

    Окно в `ОКНО` строк, шаг один: шапка `Subscriptions.swift` занимает
    три строки, строка таблицы в markdown — одну, абзац `description.txt`
    — одну длинную. Одно окно покрывает все три формы.
    """
    текст = читать(путь)
    if текст is None:
        return []
    порог = список.get("порог_открытия", 2)
    все_метки, снятые_метки = список["_метки_норм"]

    # Быстрый отказ: нет ни одной метки во всём файле — нет и окон.
    # Это не оптимизация ради скорости, а снятие класса: цикл, который
    # идёт по всем 907 файлам и всем окнам, на широких стеблях
    # не укладывался в две минуты и был снят по таймауту — то есть
    # замер не состоялся бы, а отказ выглядел бы как зависание.
    весь = норм(текст)
    if not any(м in весь for мм in list(все_метки.values())
               + list(снятые_метки.values()) for м in мм):
        return []

    строки = [норм(с) for с in текст.splitlines()]
    находки = []
    for начало in range(len(строки)):
        окно = "\n".join(строки[начало:начало + ОКНО])
        if not окно.strip():
            continue
        сошлось = [п for п, мм in все_метки.items()
                   if any(м in окно for м in мм)]
        мёртвые = [п for п, мм in снятые_метки.items()
                   if any(м in окно for м in мм)]
        # Снятый пункт ловится ПООДИНОЧКЕ: его фраза мертва, и любое
        # вхождение подозрительно само по себе. Живые — только скопом:
        # отдельное слово «натощак» это предмет приложения, а не список.
        if len(сошлось) >= порог or мёртвые:
            находки.append((начало + 1, сошлось, мёртвые))
    # Склеить перекрывающиеся окна в одно место.
    сжато = []
    for номер, сошлось, мёртвые in находки:
        if сжато and номер - сжато[-1][0] < ОКНО:
            прежние = сжато[-1]
            сжато[-1] = (прежние[0],
                         sorted(set(прежние[1]) | set(сошлось)),
                         sorted(set(прежние[2]) | set(мёртвые)))
        else:
            сжато.append((номер, sorted(сошлось), sorted(мёртвые)))
    return сжато


def mm_list(значение):
    return значение if isinstance(значение, list) else [значение]


# ─────────────────────────────── СВОД ────────────────────────────────

def разобрать_список(имя, список, подробно):
    находки, объяснённые = [], []
    print(f"\n{'═' * 70}\n{имя} — {список['о_чём']}")

    # ── ОСЬ A ────────────────────────────────────────────────────────
    пункты, отказ = извлечь(список["источник"])
    живые = [к for к in список["живые"] if к != "_"]
    снятые = list(список.get("снятые", {}))
    print(f"  источник  {список['источник']['путь']} · "
          f"{список['источник']['символ']}")
    if отказ:
        находки.append(f"ИСТОЧНИК НЕ ПРОЧИТАН: {отказ}.\n"
                       f"      Это находка, а не пропуск: ноль пунктов "
                       f"и «всё сошлось» выглядят одинаково.")
        print(f"  ✘ {отказ}")
    else:
        print(f"  пунктов   извлечено {len(пункты)} · в переписи {len(живые)}"
              f" · снятых {len(снятые)}")
        лишние = [п for п in пункты if п not in живые]
        пропавшие = [п for п in живые if п not in пункты]
        for п in лишние:
            находки.append(
                f"В ИСТОЧНИКЕ ЕСТЬ ПУНКТ, КОТОРОГО ПЕРЕПИСЬ НЕ ЗНАЕТ: «{п}».\n"
                f"      Допиши его в «живые» с метками на пяти языках — "
                f"и сторож назовёт каждую копию, которая его ещё не называет.")
        for п in пропавшие:
            находки.append(
                f"ПЕРЕПИСЬ ЗНАЕТ ПУНКТ, КОТОРОГО В ИСТОЧНИКЕ НЕТ: «{п}».\n"
                f"      Если его сняли — перенеси в «снятые» с датой и причиной. "
                f"Перенос покрасит каждую копию, которая его ещё держит, "
                f"и это единственная дорога к зелёному.")
        вернувшиеся = [п for п in снятые if п in пункты]
        for п in вернувшиеся:
            находки.append(
                f"СНЯТЫЙ ПУНКТ ВЕРНУЛСЯ В ИСТОЧНИК: «{п}», "
                f"снят {список['снятые'][п]['когда']}.\n"
                f"      Либо это решение — тогда убери его из «снятых» "
                f"и прочитай причину снятия; либо возврат не замечен.")
        if подробно and not (лишние or пропавшие):
            for п in пункты:
                print(f"            · {п}")

    # ── ОСЬ B ────────────────────────────────────────────────────────
    простить = {(п["копия"], п["пункт"]): п["почему"]
                for п in список.get("пробелы_объяснённые", [])}
    print(f"  копий     {len(список['копии'])}")
    for копия in список["копии"]:
        фраг, строка, отказ = фрагмент(копия)
        if отказ:
            находки.append(f"{отказ}\n"
                           f"      Якорь — вход сторожа в копию. Нет якоря — "
                           f"копия не проверена ни одной осью.")
            print(f"    ✘ {копия['путь']}  {отказ}")
            continue
        пробелы, мёртвые = [], []
        for пункт in живые:
            мм = метки(список["живые"].get(пункт, {}), копия["язык"])
            if not мм:
                находки.append(
                    f"у пункта «{пункт}» нет метки для языка "
                    f"«{копия['язык']}» — копия {копия['путь']} "
                    f"не проверяется по этому пункту вовсе")
                continue
            if not есть(фраг, мм):
                почему = простить.get((копия["путь"], пункт))
                if почему:
                    объяснённые.append(
                        f"{копия['путь']}:{строка} не называет «{пункт}» — "
                        f"{почему}")
                else:
                    пробелы.append(пункт)
        for пункт, узел in список.get("снятые", {}).items():
            if есть(фраг, метки(узел["метки"], копия["язык"])):
                мёртвые.append(пункт)
        знак = "✔"
        if пробелы:
            знак = "✘"
            находки.append(
                f"КОПИЯ ОТСТАЛА: {копия['путь']}:{строка} ({копия['язык']}) "
                f"не называет {', '.join('«' + п + '»' for п in пробелы)}.\n"
                f"      Источник её называет. Либо копия потеряла пункт, "
                f"либо пересказ его растворил — тогда объяви это "
                f"в «пробелы_объяснённые» с замером.")
        if мёртвые:
            знак = "✘"
            for пункт in мёртвые:
                узел = список["снятые"][пункт]
                находки.append(
                    f"КОПИЯ ДЕРЖИТ СНЯТЫЙ ПУНКТ: {копия['путь']}:{строка} "
                    f"({копия['язык']}) называет «{пункт}», снятый "
                    f"{узел['когда']}.\n      {узел['почему']}")
        print(f"    {знак} {копия['путь']}:{строка} "
              f"({копия['язык']})"
              + (f"  ОТСТАЛА: {', '.join(пробелы)}" if пробелы else "")
              + (f"  СНЯТОЕ: {', '.join(мёртвые)}" if мёртвые else ""))

    # ── ОСЬ C ────────────────────────────────────────────────────────
    объявлено = {к["путь"] for к in список["копии"]}
    объявлено.add(список["источник"]["путь"])
    разборы = {р["путь"]: р for р in список.get("разборы", [])}
    вне = список.get("_вне", [])
    пути, отказ = дерево()
    if отказ:
        находки.append(f"ОТКРЫТИЕ НЕ СОСТОЯЛОСЬ: {отказ}")
        print(f"  ✘ открытие: {отказ}")
        return находки, объяснённые

    чужие, долги, датированные = [], [], []
    осмотрено = 0
    корни = список.get("_корни", [])
    список["_метки_норм"] = словарь_меток(список)
    for путь in пути:
        if any(путь.startswith(п) for п in вне):
            continue
        осмотрено += 1
        места = открытие(путь, список, вне)
        if not места:
            continue
        if путь in объявлено:
            continue
        if путь in разборы:
            узел = разборы[путь]
            строка = f"{путь}:{места[0][0]} — {узел['почему']}"
            (долги if "хозяин" in узел else чужие).append(
                (узел.get("хозяин"), строка))
            continue
        подробность = "; ".join(
            f"стр. {н}: живых {len(ж)}"
            + (f", СНЯТОЕ {', '.join(м)}" if м else "")
            for н, ж, м in места[:3])
        # Корни живого текста — то, что человек или ревьюер читает СЕЙЧАС.
        # Вне них лежат датированные артефакты: прототипы с датой в имени
        # папки, эталонные кадры, черновики перевода, карточки «на 20.10».
        # В них утверждение привязано ко дню, и правка задним числом портит
        # улику — ровно как в журнале.
        #
        # **Корни — это слабое место, и оно названо нарочно.** В этом же
        # проекте `LocalizationDebtTests` оказался слеп именно так: один
        # корень при двух таргетах, и его зелёное читалось как «долга нет».
        # Поэтому вне корней не МОЛЧАНИЕ, а счёт с путями: слепота должна
        # быть видна в выводе, а не жить в чужой памяти.
        if корни and not any(путь.startswith(к) for к in корни):
            датированные.append(f"{путь}:{места[0][0]}")
            continue
        находки.append(
            f"НЕОБЪЯВЛЕННАЯ КОПИЯ: {путь} повторяет список "
            f"({подробность}).\n"
            f"      Объяви его в переписи: «копии» — если человек читает "
            f"это как обещание; «разборы» — если это история или тест. "
            f"Третьего ответа нет: необъявленное место расходится молча.")
    print(f"  открытие  осмотрено {осмотрено} отслеживаемых текстовых "
          f"файлов; корней живого {len(корни)}")
    for хозяин, строка in чужие:
        print(f"    · разбор  {строка}")
    for хозяин, строка in долги:
        print(f"    ⚠ ДОЛГ (хозяин: {хозяин})  {строка}")
        объяснённые.append(f"ДОЛГ, хозяин {хозяин}: {строка}")
    if датированные:
        print(f"    · вне корней живого: {len(датированные)} мест "
              f"(датированные артефакты и черновики — не судим)")
        for строка in датированные:
            print(f"        {строка}")
    return находки, объяснённые


