#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""С какого коммита взяты файлы — печатать прежде записи наружу.

Из shell:
    python3 Tools/происхождение.py            # напечатать и выйти 0
    python3 Tools/происхождение.py --отказать  # 1, если чекаут отстал

Из python:
    from происхождение import назвать, отстал
    назвать("asc_storefront_locale")   # печатает строку происхождения
    if отстал(): ...

# Зачем, и чем оплачено

Находка соседней смены 03.11.2026, проверенная здесь замером:
**инструмент читает рабочий чекаут, а не живую ветку, и молчит
об этом.** В Timer чекаут стоял на ветке от 13.10, отстав на 77
коммитов; `git status` был чист, коммит на месте, и всё выглядело
рабочим. Скрипт отдавал список по 645 ключам вместо 784 — успешный
на вид, просто без последнего раунда.

> **У отчёта отставший чекаут даёт неверный отчёт — это видно при
> следующем чтении. У записи наружу он даёт УСПЕШНУЮ ЗАПИСЬ
> НЕ ТОГО ПОКОЛЕНИЯ**, и успех виден в App Store Connect или
> в CloudKit, а не в логе git.

Замер по Togo (03.11, этот файл): четыре инструмента пишут наружу
и ни один не печатал коммит.

    Tools/deploy_cloudkit_schema.sh     → схема в контейнер CloudKit
    Tools/asc_storefront_locale.py      → тексты витрины в ASC
    Tools/setup_subscriptions.sh        → продукты подписок в ASC
    Tools/сверка_токенов_с_фигмой.py    → токены в Figma

Контроль того же замера: `upload_testflight.sh` даёт 2 вхождения
`rev-parse` — то есть разбор видит тех, кто коммит печатает,
и четыре нуля не про слепоту инструмента.

Дороже всех `deploy_cloudkit_schema.sh`: у `cktool` нет команды
отката, а схему в production переносят руками Виктории.

# Почему один модуль, а не проверка в каждом скрипте

Два из четырёх на bash, два на python. Две реализации одного правила
разошлись бы молча — класс, который сегодня выстрелил четыре раза
(«копии списка расходятся поштучно»). Поэтому проверка одна,
а bash зовёт её тем же `python3`.

# Что считается «отстал»

Локальная ветка ПОЗАДИ своей `origin/<ветка>`. Сравнение с `main`
здесь неверно по устройству: работа идёт в ветках `claude/…`, и они
обгоняют `main` намеренно — отставание от неё норма, а не беда.

Случай «локальная впереди origin» (не запушено) — **не отставание**.
Это обычное состояние работы, и отказывать на нём значило бы
запретить заливать до пуша.
"""
from __future__ import annotations
import os
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _git(*слова: str) -> tuple[int, str]:
    готово = subprocess.run(["git", "-C", КОРЕНЬ, "--no-optional-locks",
                             *слова], capture_output=True, text=True)
    return готово.returncode, готово.stdout.strip()


def свежайшая() -> tuple[str | None, int | None]:
    """Самая свежая ветка репозитория и наше отставание от неё.

    # ВТОРОЙ ПРИЗНАК, И ОН ЛОВИТ ДРУГОЕ

    Добавлен 03.11.2026 после встречного замера соседней смены.
    Мой первый признак сравнивал с `origin/<своя ветка>` — и этого
    мало:

        Timer, чекаут release-1-0-audit-fixes
          от свежайшей ветки репозитория   78   ← ловит этот признак
          от origin СВОЕЙ ветки             0   ← первый молчит

    Ветка может быть синхронна со своим origin и при этом быть
    заброшенной: работа давно ушла в другую, а эта стоит с октября.
    `git status` чист, origin совпадает, всё выглядит рабочим.

    > **Два признака ловят разное, и ни один не покрывает второй.**
    > Отставание от origin — «я не подтянул чужое в свою ветку».
    > Отставание от свежайшей — «я сижу не в той ветке вовсе».

    Почему это не слито в один признак: у них разные лечения.
    Первое чинится `git pull`, второе — переходом в другую ветку,
    и путать их значит давать неверный совет.

    Граница: «свежайшая» определяется по дате коммита, а дата
    коммита — не дата работы. Ветка, в которую перенесли старый
    коммит, выглядит свежее, чем есть. Поэтому это ПРЕДУПРЕЖДЕНИЕ,
    а не отказ.
    """
    код, строки = _git("for-each-ref", "--sort=-committerdate",
                       "--format=%(refname:short)", "refs/heads", "refs/remotes")
    if код != 0 or not строки.strip():
        return None, None
    первая = строки.split("\n")[0].strip()
    if not первая:
        return None, None
    код, счёт = _git("rev-list", "--count", f"HEAD..{первая}")
    if код != 0 or not счёт.isdigit():
        return первая, None
    return первая, int(счёт)


def состояние() -> dict:
    """Всё, что нужно знать о происхождении файлов. Без исключений."""
    о = {"коммит": None, "ветка": None, "отстал": None,
         "впереди": None, "грязь": None, "почему": None,
         "свежайшая": None, "от_свежайшей": None}
    код, хеш = _git("rev-parse", "HEAD")
    if код != 0:
        о["почему"] = "git не отдал HEAD — это не репозиторий или он сломан"
        return о
    о["коммит"] = хеш
    _, ветка = _git("rev-parse", "--abbrev-ref", "HEAD")
    о["ветка"] = ветка or None
    код, грязь = _git("status", "--porcelain")
    о["грязь"] = len([с for с in грязь.split("\n") if с.strip()]) if код == 0 else None
    о["свежайшая"], о["от_свежайшей"] = свежайшая()

    if not ветка or ветка == "HEAD":
        о["почему"] = "отсоединённая голова — у неё нет origin, сравнивать не с чем"
        return о
    код, _ = _git("rev-parse", "--verify", f"origin/{ветка}")
    if код != 0:
        о["почему"] = f"ветки origin/{ветка} нет — сравнивать не с чем"
        return о
    код, счёт = _git("rev-list", "--left-right", "--count",
                     f"HEAD...origin/{ветка}")
    if код != 0 or "\t" not in счёт:
        о["почему"] = "git не посчитал расхождение с origin"
        return о
    впереди, позади = счёт.split("\t")
    о["впереди"], о["отстал"] = int(впереди), int(позади)
    return о


def назвать(кто: str = "") -> dict:
    """Печатает строку происхождения. Возвращает состояние."""
    о = состояние()
    подпись = f"[{кто}] " if кто else ""
    if о["коммит"] is None:
        print(f"  ⚠ {подпись}происхождение НЕ УСТАНОВЛЕНО: {о['почему']}")
        return о
    строка = f"  {подпись}файлы взяты с {о['коммит'][:9]}"
    if о["ветка"]:
        строка += f" · ветка {о['ветка']}"
    if о["грязь"]:
        строка += f" · В ДЕРЕВЕ {о['грязь']} НЕЗАКОММИЧЕННЫХ"
    if о["отстал"] is None:
        строка += f" · с origin не сверено: {о['почему']}"
    elif о["отстал"]:
        строка += f" · ОТСТАЛ НА {о['отстал']} от origin/{о['ветка']}"
    elif о["впереди"]:
        строка += f" · впереди origin на {о['впереди']} (не запушено)"
    else:
        строка += " · совпадает с origin"
    print(строка)
    # Второй признак печатается ОТДЕЛЬНОЙ строкой, а не дописывается
    # к первой: он про другое, и слепленные в одну они читались бы
    # как уточнение друг друга.
    if о["от_свежайшей"] and о["свежайшая"] != о["ветка"]:
        print(f"  ⚠ {подпись}в репозитории есть ветка свежее: "
              f"{о['свежайшая']} — ты отстал от неё на {о['от_свежайшей']} "
              f"коммитов. Это не «подтяни», а «ты не в той ветке»")
    return о


def отстал() -> bool:
    """True только при ДОКАЗАННОМ отставании.

    Неизвестность (`отстал is None`) — не отставание: отказывать там,
    где не померили, значит запрещать работу из-за отсутствия замера.
    Но и молчать нельзя, поэтому `назвать` эту неизвестность печатает.
    """
    return bool(состояние()["отстал"])


def главное() -> int:
    о = назвать(" ".join(sys.argv[1:2]) if len(sys.argv) > 1
                and not sys.argv[1].startswith("--") else "")
    if "--отказать" not in sys.argv:
        return 0
    if о["отстал"]:
        print(f"""
  ✗ ОТКАЗ: чекаут отстал на {о['отстал']} коммитов от origin/{о['ветка']}.

  Запись наружу с отставшего дерева — это успешная запись НЕ ТОГО
  поколения. Успех будет виден в App Store Connect или в CloudKit,
  а в логе git его не будет вовсе.

  Подтяни ветку и повтори:  git pull --ff-only""", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(главное())
