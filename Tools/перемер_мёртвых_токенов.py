def производные() -> dict:
    """Тексты, в которых токен может иметь читателя ВНЕ Swift.

    Считаются только РУКОПИСНЫЕ: см. разбор у `КОПИИ_ОБЪЯВЛЕНИЯ` выше.
    Сгенерированные читаются тоже — но лишь затем, чтобы напечатать
    их объём рядом и чтобы следующий не завёл по ним ось заново.
    """
    тексты = {}
    пути = [ПЛАГИН] + КОПИИ_ОБЪЯВЛЕНИЯ
    корень_ядра = os.path.join(КОРЕНЬ, ЯДРО)
    if os.path.isdir(корень_ядра):
        for имя in sorted(os.listdir(корень_ядра)):
            if имя.endswith((".json", ".css")):
                пути.append(os.path.join(ЯДРО, имя))
    for отн in пути:
        путь = os.path.join(КОРЕНЬ, отн)
        try:
            тексты[отн] = open(путь, encoding="utf-8").read()
        except Exception:
            тексты[отн] = ""
    return тексты


def карта_имён() -> dict:
    """Swift-путь → (ключ `tokens.json`, имя в CSS, имя в Фигме).

    СООТВЕТСТВИЕ БЕРЁТСЯ У ГЕНЕРАТОРА ИМПОРТОМ, А НЕ ВОССОЗДАЁТСЯ
    РАЗБОРОМ. `Tools/generate_tokens.py` пишет все три файла из одного
    плоского ключа, и правило там объявлено: таблица `GROUPS` для
    примитивов и семантики, `pascal`/`camel` для компонентного дерева,
    `"--" + ключ.replace(".", "-")` для CSS, `"/".join(ключ[1:])`
    для Фигмы. Своя копия этого соглашения разошлась бы молча.

    Разойтись ей есть на чём, и это замер, а не осторожность:

        Swift         Token.Space.s8
        оба экспорта  space/8  ·  --primitive-space-8

    Буква `s` существует только потому, что идентификатор Swift
    не может начинаться с цифры (`generate_tokens.swift_name`).
    Механический матчер «путь через слэш, строчная первая» промахнулся
    бы на ВСЁМ семействе шага сетки из-за одного символа — и напечатал
    бы «читателей вне Swift нет» про тринадцать живых переменных.

    Пустая карта означает отказ импорта, а не «токенов нет»: это
    проверяется контролем в `главное()`, иначе отказ генератора
    приедет ровно как «всё мёртво».
    """
    try:
        плоские = ген.walk(ген.load(), [])
    except Exception as отказ:          # noqa: BLE001 — причина печатается
        print("!! генератор не прочитан: %s" % отказ)
        return {}
    карта = {}
    for ключ in sorted(плоские):
        части = ключ.split(".")
        путь = None
        if части[0] == "component" and len(части) >= 2:
            хвост = части[1:]
            путь = ".".join(["Token", "Component"]
                            + [ген.pascal(ч) for ч in хвост[:-1]]
                            + [ген.camel(хвост[-1])])
        else:
            for префикс, имя_enum, _вид, _опис in ген.GROUPS:
                if ключ.startswith(префикс + "."):
                    лист = ключ[len(префикс) + 1:]
                    путь = "Token.%s.%s" % (имя_enum, ген.swift_name(лист))
                    break
        if путь is None:
            continue
        _вид, _знач, причина = плоские[ключ]
        карта[путь] = (ключ,
                       "--" + ключ.replace(".", "-"),
                       "/".join(части[1:]),
                       (причина or "").strip())
    return карта


АЛИАСЫ = {}   # заполняется в главное(); пустой словарь = ось не спрошена


def алиасные_читатели() -> dict:
    """ключ `tokens.json` → кто ссылается на него алиасом `{путь}`.

    ЧЕТВЁРТЫЙ ЯЗЫК ЧИТАТЕЛЕЙ, И САМЫЙ ПРОПУСКАЕМЫЙ: ссылка живёт
    в самом `tokens.json`, рукой, и ни в Swift, ни в экспортах её нет.
    Без этой оси весь примитивный слой читается как мёртвый — а он
    по устройству и не должен иметь читателя в коде:

        GROUPS, строка про primitive.space
        «Шаг сетки. Прикладной код берёт Spacing, а не это.»

    То есть у `Token.Space.s8` ноль прикладных вызовов — ЗАМЫСЕЛ,
    а не долг, и читает его `semantic.spacing.*` алиасом. Замер
    26.10.2026: алиасом читаются 147 ключей из 381, всего 225 ссылок.

    Режимные значения разбираются порознь: алиас может стоять
    в одном режиме из четырёх (`dark` ссылкой, `light` литералом),
    и спросив только строковое значение, такой читатель не найдёшь.
    """
    try:
        плоские = ген.walk(ген.load(), [])
    except Exception:
        return {}
    цели = {}
    for ключ, (_вид, знач, _n) in плоские.items():
        кандидаты = [str(v) for v in знач.values()] if isinstance(знач, dict) else [str(знач)]
        for к in кандидаты:
            м = ген.ALIAS.match(к.strip())
            if м:
                цели.setdefault(м.group(1), []).append(ключ)
    return цели


def вне_swift(путь_токена: str, карта: dict, тексты: dict) -> list:
    """Рукописные читатели токена вне Swift. Имена точные, от генератора.

    Сгенерированные экспорты здесь НЕ СПРАШИВАЮТСЯ вовсе — разбор
    у `КОПИИ_ОБЪЯВЛЕНИЯ`.
    """
    запись = карта.get(путь_токена)
    if запись is None:
        # В `tokens.json` такого ключа нет: объявление написано
        # в сгенерированном файле рукой (общая палитра) либо карта устарела.
        # Это НЕ «мёртв» и НЕ «мост» — отдельное состояние, и печатается оно
        # своим словом, а не растворяется в ближайшей корзине.
        return ["вне tokens.json"]
    ключ, имя_css, имя_фигмы, _причина = запись
    где = []
    ссылки = АЛИАСЫ.get(ключ, [])
    if ссылки:
        где.append("алиас в tokens.json ×%d" % len(ссылки))
    # Плагин пар держит СВОЙ конец связи Swift-путём, дословно.
    if re.search(r'"\s*:\s*"%s"' % re.escape(путь_токена), тексты.get(ПЛАГИН, "")):
        где.append("плагин пар")
    for отн, текст in тексты.items():
        if отн == ПЛАГИН or отн in КОПИИ_ОБЪЯВЛЕНИЯ or not текст:
            continue
        if имя_css in текст or ('"%s"' % имя_фигмы) in текст:
            где.append(os.path.basename(отн))
    return где


def в_копиях(путь_токена: str, карта: dict, тексты: dict) -> int:
    """Сколько СГЕНЕРИРОВАННЫХ копий объявления содержат это имя.

    Печатается нарочно: число у живого и у мёртвого токена одинаковое,
    и ровно это делает признак негодным для оси. Видно — не завёдётся
    заново.
    """
    запись = карта.get(путь_токена)
    if запись is None:
        return 0
    _ключ, имя_css, имя_фигмы, _причина = запись
    счёт = 0
    for отн in КОПИИ_ОБЪЯВЛЕНИЯ:
        текст = тексты.get(отн, "")
        if имя_css in текст or ('"%s"' % имя_фигмы) in текст:
            счёт += 1
    return счёт


def главное():
    пути = объявления()
    файлы = код_дерева()
    экспорты = производные()
    # Общие — внутренний слой дедупликации, не токен для экранов.
    пути = [п for п in пути if not п.startswith("Token.Общие.")]
    пути = [п for п in пути if п.startswith("Token.")]

    карта = карта_имён()
    global АЛИАСЫ
    АЛИАСЫ = алиасные_читатели()

    живые, мост, мёртвые, вне_json = {}, {}, {}, {}
    for п in пути:
        места = считать(п, файлы)
        где = вне_swift(п, карта, экспорты)
        if где == ["вне tokens.json"]:
            вне_json[п] = места
            continue
        if места:
            живые[п] = места
            continue
        if где:
            мост[п] = где
        else:
            мёртвые[п] = (карта.get(п, ("", "", "", ""))[3])

    с_причиной = [п for п in мёртвые if мёртвые[п]]

    print("ФАЙЛОВ ПРОСМОТРЕНО: %d" % len(файлы))
    print("ТОКЕНОВ ОБЪЯВЛЕНО:  %d" % len(пути))
    print("СОПОСТАВЛЕНО С tokens.json: %d из %d" % (len(карта), len(пути)))
    print()
    print("ЖИВЫХ В SWIFT:          %d" % len(живые))
    print("ЧИТАТЕЛЬ ВНЕ SWIFT (рукописный): %d" % len(мост))
    print("БЕЗ ЧИТАТЕЛЯ ВОВСЕ:     %d  (из них с названной причиной в $description: %d)"
          % (len(мёртвые), len(с_причиной)))
    print("ВНЕ tokens.json:        %d" % len(вне_json))
    print()
    print("--- КОНТРОЛЬ, снят в этом же прогоне ---")
    for отн, текст in экспорты.items():
        ярлык = "КОПИЯ ОБЪЯВЛЕНИЯ, в ось не входит" if отн in КОПИИ_ОБЪЯВЛЕНИЯ else "рукописный"
        print("  %-54s %-34s %s" % (отн, ("%d байт" % len(текст)) if текст else "НЕ ПРОЧИТАН", ярлык))
    print()
    # `s8` стоит здесь нарочно: это ТОТ промах, на котором механический разбор
    # имён врал про всё семейство шага сетки (`Token.Space.s8` против `space/8`).
    # Столбец «копий» — улика к разбору выше: у живого и у мёртвого он ОДИН
    # И ТОТ ЖЕ, то есть по нему ось строить нельзя.
    print("  алиасом читаются ключей: %d, всего ссылок %d"
          % (len(АЛИАСЫ), sum(len(v) for v in АЛИАСЫ.values())))
    print()
    print("  %-46s %-32s %-34s %s" % ("токен", "ожидание", "рукописные читатели", "копий"))
    for имя, ожидание in [
            ("Token.Space.s8", "ловушка s8/8; алиас обязан быть"),
            ("Token.Surface.card", "живой в Swift"),
            ("Token.Component.Backdrop.Height.today", "ноль в Swift — вот и вопрос"),
            ("Token.ТакогоТокенаНетВовсе", "отрицательный: «вне tokens.json»")]:
        print("  %-46s %-32s %-34s %d" % (
            имя, ожидание,
            ", ".join(вне_swift(имя, карта, экспорты)) or "нет",
            в_копиях(имя, карта, экспорты)))
    print()
    print("--- КОНТРОЛЬ, снят в этом же прогоне ---")
    for имя, ожидание in [("Token.Space.s8", "заведомо живой"),
                          ("Token.Surface.card", "заведомо живой"),
                          ("Token.Space.s1", "ПРЕФИКСНАЯ ловушка: такого токена нет"),
                          ("Token.ТакогоТокенаНетВовсе", "отрицательный контроль")]:
        print("  %-34s %-34s %d" % (имя, ожидание, len(считать(имя, файлы))))
    print()
    if len(sys.argv) > 1 and sys.argv[1] == "--список":
        print("--- БЕЗ ЧИТАТЕЛЯ ВОВСЕ: предмет разбора. Причина или удаление ---")
        for п in sorted(мёртвые):
            причина = мёртвые[п]
            print("  %-52s %s" % (п, причина.split("\n")[0] if причина else "— причины нет"))
        print()
        print("--- ЧИТАТЕЛЬ ВНЕ SWIFT, рукописный. НЕ УДАЛЯТЬ ---")
