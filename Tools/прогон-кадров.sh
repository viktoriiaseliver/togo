#!/bin/bash
# Снять партию кадров онбординга в заданной теме.
#
#   Tools/прогон-кадров.sh светлая
#   Tools/прогон-кадров.sh тёмная
#   DEVICE=Togo-моё Tools/прогон-кадров.sh тёмная
#
# ## Зачем отдельный скрипт, а не цель в Makefile
#
# `ОнбордингНиз` — единственный тест, который показывает онбординг,
# и он требует условий, которых нет ни у одной цели:
#
#   запуск БЕЗ -UITesting   под флагом главный экран показывается
#                           ПО УМОЛЧАНИЮ (не «всегда»: с -Онбординг,
#                           заведённым 14.10, рисуются настоящие шаги)
#   стёртое устройство      onboardingCompleted снимается только так
#   НЕ общее устройство     чужой заход оставляет и пройденный
#                           онбординг, и форму базы
#
# Адрес ворот здесь не назван нарочно: за один день `TogoApp.swift`
# переехал `:219 → :243 → :388`, и первые два успели попасть
# в документы как текущее состояние. Проверка за минуту —
# `grep -n "просмотрОнбординга" Togo/App/TogoApp.swift`.
#
# Почему скрипт остаётся на дорогом пути, хотя дешёвый появился:
# `-Онбординг` **обходит** оба ворота, а не проходит их, и в базу
# не пишет ничего. Для геометрии низа разницы нет; для вопроса
# «что увидит человек на первом запуске телефона» — есть.
#
# ## Почему тема читается обратно
#
# **Ярлык печатается до работы и от её исхода не зависит, значит
# не может оказаться неверным.** 07.10.2026 тест печатал «КАДРЫ
# (светлая тема)» над тёмным кадром. Суффикс в имени файла — такой же
# ярлык: его печатает этот скрипт, а не симулятор.
#
# Поэтому `simctl ui … appearance` ставится, а потом **спрашивается
# обратно**, и при расхождении прогон не начинается вовсе. Замер
# `russian-togo-testflight-review` 14.10: все три команды постановки
# (`appearance`, `increase_contrast`, `content_size`) возвращают ПУСТОЙ
# вывод — «поставилось» узнаётся только обратным чтением.
#
# Третий свидетель — яркость самого PNG: `Tools/замер-кадра.py --пара`.
# `simctl` отвечает про настройку системы, яркость — про то, что вышло
# на картинке. Разные стороны одного вопроса.
#
# ## Чего этот скрипт НЕ делает
#
# Не заводит устройство. Заведение — необратимое для чужого замера
# действие, и имя устройства должно быть решением человека, а не
# умолчанием скрипта. `TOGO_SIM` здесь не используется НАРОЧНО: он
# заводит на НОВЕЙШЕМ рантайме, то есть на iOS 27.0, где стенд
# отказывает (`Cannot use staged migration`, 10 тестов из 1074).
# Нужное устройство заводится руками и явно:
#
#   xcrun simctl create "Togo-<сессия>-кадры" "iPhone 17 Pro" \
#       com.apple.CoreSimulator.SimRuntime.iOS-26-5

# ## Имена переменных латиницей, и это не стиль
#
# Первая редакция держала `ТЕМА`, `УСТРОЙСТВО`, `РАНТАЙМ` — и не
# запустилась ни разу: `bash` кириллическое имя переменной не заводит
# вовсе, читает `ТЕМА=светлая` как имя команды (`rc=127`).
#
# Хуже отказа — то, что **подстановка при этом не падает, а молча
# врёт**: `$ТЕМА` разбирается как `$Т` (пусто) плюс литерал `ЕМА`.
# Без `set -e` скрипт дошёл бы до конца и снял партию с неверной
# темой — ровно та подделка, против которой он и написан.
#
# И проверка в терминале это не ловит: оболочка здесь `zsh`, а в нём
# всё работает. Шебанг говорит `bash`.
#
# Урок был записан заранее и в соседнем файле — `ОнбордингНиз.swift:80`:
# «Имя переменной латиницей: кириллическое оболочка не заводит вовсе
# (`rc=127`)». Тот же `rc=127`, восемь дней спустя, в скрипте, который
# этот самый файл и запускает.
#
# И второй капкан, который правило «только латиницей» НЕ ПОКРЫВАЕТ:
# имя латиницей, а лишний байт пришёл от соседа. `«$THEME»` — закрывающая
# кавычка многобайтная, она приклеилась к имени, и вышло `THEME»:
# unbound variable`. Лечится `${THEME}»`. Поймал это `set -u`; без него
# подстановка отдала бы пустое и молчала.
#
# Оба капкана записаны в `.claude/rules/стенд-и-прогоны.md`, раздел
# «Кириллица в скриптах — два разных запрета». Я прочитал его ПОСЛЕ
# того, как наступил на оба.

set -euo pipefail

THEME="${1:-}"
DEVICE="${DEVICE:-Togo-4b-кадры}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

case "$THEME" in
    светлая) APPEARANCE=light ;;
    тёмная)  APPEARANCE=dark ;;
    *) echo "Тема: светлая | тёмная. Получено: «${THEME}»" >&2; exit 2 ;;
esac

FOUND=$(xcrun simctl list devices --json | python3 -c "
import json, sys
имя = sys.argv[1]
d = json.load(sys.stdin)
for рантайм, устройства in d['devices'].items():
    for у in устройства:
        if у['name'] == имя:
            print(у['udid'], рантайм.rsplit('.', 1)[-1])
            raise SystemExit
raise SystemExit('нет такого устройства')
" "$DEVICE") || { echo "Устройство «${DEVICE}» не найдено. Заведи явно — см. голову файла." >&2; exit 1; }

RUNTIME=${FOUND#* }
UDID=${FOUND%% *}

# Рантайм печатается ВСЕГДА, а не только при ошибке: кадры приёмки
# сравнивают с эталонными глазами, и «снято на другом рантайме» —
# единственное объяснение, которое потом уже не восстановить.
echo "устройство  $DEVICE  $UDID  $RUNTIME"

# Версия НАЗЫВАЕТСЯ, а не подбирается. Форма общая на все скрипты
# смены (`RUNTIME_IOS`), закреплена главным менеджером: корень один
# и уже на трёх адресах. `Tools/прогон-ui.sh` создавал устройство
# на `tail -1`, то есть на новейшем рантайме — сегодня это 27.0,
# где стенд Togo отказывает по устройству. Две потери оплачены,
# и обе выглядели как дефект продукта.
RUNTIME_IOS="${RUNTIME_IOS:-26.5}"
WANT="iOS-${RUNTIME_IOS//./-}"
if [[ "$RUNTIME" != "$WANT" ]]; then
    echo "ОТКАЗ: устройству нужен ${WANT}, у него ${RUNTIME}." >&2
    echo "На 27.0 стенд отдаёт 10 тестов из 1074 (staged migration)." >&2
    echo "Установленные рантаймы:" >&2
    xcrun simctl list runtimes | grep -i "^iOS" >&2
    exit 9
fi

echo "стираю (shutdown → erase → boot) …"
xcrun simctl shutdown "$UDID" 2>/dev/null || true
xcrun simctl erase "$UDID"
xcrun simctl boot "$UDID"
xcrun simctl bootstatus "$UDID" -b >/dev/null

xcrun simctl ui "$UDID" appearance "$APPEARANCE"

# ## Читаются ВСЕ ТРИ положения, а не только выставленное
#
# Замер `light-theme-onboarding-fix` 14.10: **положение стенда
# наследуется между сессиями.** У живого `Togo-b6` посреди чужого
# прогона стояло `appearance=light`, `increase_contrast=enabled`,
# `content_size=AX5` — кто-то выставил руками и не вернул. Все кадры
# с того устройства — Light HC AX5 под обычными именами.
#
# > **«Новое устройство, значит родное положение» — это вывод,
# > а не замер.** Здесь устройство ещё и стирается перед прогоном,
# > и всё равно спрашивается: `erase` сбрасывает эти ключи —
# > утверждение, которого никто не мерил.
#
# Поэтому печатаются все три, всегда, задавал их кто-нибудь или нет.
# Сверка «просили → получили» идёт только по теме: контраст и кегль
# здесь не задаются, и их дело — попасть в запись рядом с кадрами,
# чтобы «почему этот кадр крупнее» не пришлось выяснять через месяц.
READBACK=$(xcrun simctl ui "$UDID" appearance)
CONTRAST=$(xcrun simctl ui "$UDID" increase_contrast)
TEXTSIZE=$(xcrun simctl ui "$UDID" content_size)

echo "тема        просили «${APPEARANCE}» · получили «${READBACK}»"
echo "контраст    ${CONTRAST}"
echo "кегль       ${TEXTSIZE}"

if [[ "$READBACK" != "$APPEARANCE" ]]; then
    echo "ОТКАЗ СТЕНДА: просили «${APPEARANCE}», получили «${READBACK}»." >&2
    echo "Это не упавшие тесты. Партия не снимается:" >&2
    echo "светлый кадр под именем «тёмная» неотличим от настоящего." >&2
    exit 9
fi

# Контраст и кегль прогон не валят: кадр Light HC AX5 — годный кадр,
# просто другой. Валит молчание о нём.
#
# Расхождение «просили → получили» валит потому, что там есть
# ЗАЯВЛЕННОЕ НАМЕРЕНИЕ и факт ему противоречит. «Не исходное
# положение» намерения не содержит вовсе.
if [[ "$CONTRAST" != "disabled" || "$TEXTSIZE" != "large" ]]; then
    echo
    echo "ВНИМАНИЕ: стенд не в исходном положении."
    echo "Кадры выйдут ${CONTRAST}/${TEXTSIZE}, а не обычными."
fi

mkdir -p build/logs build/кадры-онбординга
LOG="build/logs/кадры-${THEME}-$(date +%Y%m%d-%H%M%S)-$$.log"

# ## Положение пишется РЯДОМ С КАДРАМИ, а не только в лог
#
# Первая редакция печатала «впиши в README партии рукой» —
# и это **механизм без входа**: он опирается на то, что человек,
# увидевший строку в логе, вспомнит про неё, когда будет смотреть
# кадры. А кадры смотрят потом и в другом месте.
#
# > **Предупреждение, адресованное будущему читателю, работает,
# > только если лежит рядом с предметом.** Предмет здесь — каталог
# > партии, и говорить он будет без участия чьей-либо памяти.
#
# Поправка `light-theme-onboarding-fix`, 14.10.
STATEFILE="build/кадры-онбординга/ПОЛОЖЕНИЕ-${THEME}.txt"
{
    echo "партия        ${THEME}"
    echo "снято         $(date '+%Y-%m-%d %H:%M:%S')"
    echo "устройство    ${DEVICE}  ${UDID}"
    echo "рантайм       ${RUNTIME}"
    echo "appearance    просили ${APPEARANCE} · получили ${READBACK}"
    echo "contrast      ${CONTRAST}"
    echo "content_size  ${TEXTSIZE}"
    echo "коммит        $(git rev-parse --short HEAD 2>/dev/null || echo '—')"
    echo
    echo "Все три величины ПРОЧИТАНЫ У СИМУЛЯТОРА, а не напечатаны"
    echo "по намерению. Имя файла кадра про контраст и кегль молчит."
} > "$STATEFILE"
echo "положение   ${STATEFILE}"
# Своя DerivedData с PID: сессий на этом дереве несколько, общий путь
# отдавал бы одной сессии результат другой.
DERIVED="build/DerivedData-кадры-$$"

echo "прогон      лог $LOG"
set +e
TEST_RUNNER_KADR_SUFFIX="$THEME" \
xcodebuild -project Togo.xcodeproj -scheme Togo -configuration Debug \
    -derivedDataPath "$DERIVED" \
    -destination "platform=iOS Simulator,id=$UDID" \
    test -only-testing:TogoUITests/ОнбордингНиз \
    > "$LOG" 2>&1
rc=$?
set -e

# ## Вложения .xcresult выносятся В ЛЮБОМ ИСХОДЕ
#
# **Прогон пишет ВИДЕОЗАПИСЬ каждого теста, и мы выбрасывали её
# вместе с `build/`.** Замер 14.10 по связке упавшего прогона:
# 42 текста (дампы иерархии доступности), 14 плистов, ДВА видео,
# 1 JSON, PNG — ноль.
#
# > **Кадр отвечает на вопрос «что на экране в этот момент».
# > Запись — на вопрос «как мы сюда пришли».**
#
# Шесть дней про заход 08.10 стояло «до :301 не дошли», и всё это
# время запись всего прохода лежала в связке и показывала, ГДЕ
# оборвалось. Второй вопрос мы весь месяц задавали коду.
#
# Вынос стоит ДО печати итогов и не под `if`: при нулевом исходе
# от захода не остаётся ничего, и ровно тогда улика нужнее всего.
# Утверждено менеджером 14.10 по двум независимым заявкам.
ULIKI="build/улики-${THEME}-$(date +%Y%m%d-%H%M%S)-$$"
BUNDLE=$(ls -dt "${DERIVED}"/Logs/Test/*.xcresult 2>/dev/null | head -1 || true)
if [[ -n "${BUNDLE}" ]]; then
    mkdir -p "${ULIKI}"
    # Отказ выгрузки НЕ глотается: связка — ненадёжный носитель,
    # 07.10 экспорт отказал пять раз из девяти.
    if xcrun xcresulttool export attachments \
            --path "${BUNDLE}" --output-path "${ULIKI}" > /dev/null 2>&1; then
        VIDEO=$(ls -1 "${ULIKI}" 2>/dev/null | grep -c '\.mp4$' || true)
        VSEGO=$(ls -1 "${ULIKI}" 2>/dev/null | wc -l | tr -d ' ')
        echo "улики       ${ULIKI} · файлов ${VSEGO}, из них видео ${VIDEO}"
    else
        echo "улики       ОТКАЗ ВЫГРУЗКИ из ${BUNDLE} — связка цела, вложения не вынуты" >&2
    fi
else
    echo "улики       связки .xcresult нет в ${DERIVED}/Logs/Test — прогон не дошёл до неё" >&2
fi

# Приёмка прогона — число выполненных, а не код возврата: «4 из 845»
# это отказ стенда, даже когда строка итога говорит passed.
grep -E "Test run|ЗАМЕР |НЕГОДЕН|КЛАВИАТУРА|Онбординг не открылся|error:|\*\* TEST" "$LOG" || true
echo "xcodebuild: код возврата $rc"
echo

# ## Счёт кадров считает СКРИПТ, а не `tearDown`
#
# Две причины, и вторая сильнее.
#
# 1. `tearDown` может не дожить: тест, умерший раньше, не напечатает
#    ничего — а «снято четыре» и «упал на первом, снято ноль»
#    различаются только присутствием строк `КАДР:`, **и отсутствия
#    этих строк никто не ищет**.
# 2. **Печать теста уходит в лог раннера, который под руку не берут.**
#    14.10 двое независимо искали строку `КЛАВИАТУРА:` и не нашли её
#    там, где смотрели.
#
# > **Печать, которую нельзя прочитать, равна отсутствующей.**
#
# Поэтому число считается СНАРУЖИ и печатается ВСЕГДА, включая ноль:
# ноль, сказанный вслух, — это замер; ноль, выраженный молчанием, —
# это ничего.
SNYATO=$(ls -1 build/кадры-онбординга/*"${THEME}"*.png 2>/dev/null | wc -l | tr -d ' ')
BRAK=$(ls -1 build/кадры-онбординга/*"${THEME}"*.png 2>/dev/null | grep -c 'НЕГОДЕН' || true)
echo "СНЯТО КАДРОВ: ${SNYATO}, из них отбраковано ${BRAK}"
echo "кадры:"
ls -1 build/кадры-онбординга/*"${THEME}"* 2>/dev/null || echo "  НИ ОДНОГО — смотри $LOG"

# **Напечатать код возврата и вернуть его — разные действия.** Без этой
# строки наружу уходил бы код `ls`, то есть ноль при любом исходе
# прогона: печать видит человек, читающий лог, а код видит тот, кто
# решает, зелено ли, — и обманывает его именно печать.
#
# Код не является вердиктом: приёмка здесь — кадры и числа, а `rc`
# у `xcodebuild` бывает ненулевым на ожидаемо красном. Но ноль при
# несостоявшемся прогоне хуже любого честного числа.
exit $rc
