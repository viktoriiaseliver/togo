#!/bin/bash
#
# Прогон UI-набора, который ВИДИТ САМО ПРИЛОЖЕНИЕ.
#
# Зачем он есть
# =============
# Лог `xcodebuild` для UI-прогона содержит вывод РАННЕРА, а не
# приложения: приложение живёт отдельным процессом, и его `os_log`
# в этот лог не попадает ни строкой. Замерено 08.10.2026 на
# `/tmp/прогон-медслой.log` — 272 строки, и `Togo[` в них НОЛЬ
# вхождений при наблюдённом падении приложения.
#
#     Наблюдение «Critical process Togo crashed in (null)» без единой
#     строки о том, что процесс делал, — это форма без содержания.
#     Пятый такой заход не отличается от первого.
#
# И хуже: эти нули читаются как ответ про мир. В тот вечер по ним
# чуть не сняли живого кандидата — «зеркалирования ноль, значит версия
# опровергнута», — хотя ноль был про лог.
#
#     Ноль от инструмента и ноль про мир снаружи неразличимы.
#     Различает только контроль.
#
# Поэтому здесь контроль встроен: если в логе приложения не оказалось
# самого приложения, прогон объявляется НЕСОСТОЯВШИМСЯ и возвращает
# свой код, а не «тесты прошли».
#
# Чем пользоваться
# ================
#   Tools/прогон-ui.sh TogoUITests/МедслойДороги
#   Tools/прогон-ui.sh TogoUITests/МедслойДороги Togo-мояСессия
#
# Переменные окружения:
#   BEZ_SBORKI=1   прогон без сборки (`test-without-building`)
#
# Имена переменных только латиницей: кириллическое имя в bash
# не заводится вовсе и следующая строка выполняется как ни в чём
# не бывало. Поймано трижды за один день 23.09.2026.
#
# СТОРОЖА НА ЭТО У TOGO НЕТ. Прежняя редакция этой строки говорила
# «держит сторож `testShellScriptsHaveNoCyrillicVariables`» — он
# существует, но живёт в Gamut (`Gamut/Tests/UITestHygieneTests.swift`),
# а в Togo, Timer и Kvit его нет ни одного. Замер 09.10.2026: правило
# держалось привычкой девяти скриптов и сломалось на первом, кто пришёл
# со стороны — девять кириллических имён в новом скрипте при нуле
# во всех остальных. Спас `set -u`, а не сторож.
#
# Ссылка на имя чужого теста читается как «правило под охраной» —
# поэтому она снята, а не уточнена. Сторож для Togo заводится отдельно;
# пока его нет, здесь обязан стоять `set -u`: без него этот класс
# молчит и даёт пустую строку, то есть вывод, обратный правде.
set -uo pipefail

SUITE="${1:-}"
if [ -z "$SUITE" ]; then
    echo "нужен набор: Tools/прогон-ui.sh TogoUITests/<Набор>" >&2
    exit 2
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2

RUN_ID="$$"
SIM_NAME="${2:-Togo-ui-$RUN_ID}"
OUT_DIR="$ROOT/build/ui-$RUN_ID"
mkdir -p "$OUT_DIR"
RUN_LOG="$OUT_DIR/прогон.log"
APP_LOG="$OUT_DIR/приложение.log"

echo "набор:      $SUITE"
echo "симулятор:  $SIM_NAME"
echo "логи:       $OUT_DIR"

# Состояние машины печатается РЯДОМ с результатом, а не вместо него:
# условие, при котором дефект виден (машина под нагрузкой), и условие,
# при котором замеру можно верить, исключают друг друга — значит числа
# про машину обязаны стоять в том же отчёте.
#
# ПОЧЕМУ НЕ ОДИН `load average`. Он не отвечает ни на «идёт ли наша
# работа», ни на «есть ли место»: в него попадает и то, что ждёт
# памяти, и при исчерпанном swap он растёт ОТ НЕХВАТКИ ПАМЯТИ, выглядя
# как десять чужих сборок. Замерено 08.10.2026: `load 229` при простое
# процессора 57 % — это была память, а не процессор.
#
# Поэтому три величины, и читать их вместе:
#   swap свободно мало + смерть   → кандидат «ресурс», а не код
#   swap свободно много + смерть  → версия «ресурс» СНЯТА, искать в коде
sostoyanie_mashiny() {
    local kogda="$1"
    echo "--- машина ${kogda} ---"
    echo "  load:   $(uptime | sed 's/.*averages: //')"
    echo "  swap:   $(sysctl -n vm.swapusage)"
    echo "  память: $(memory_pressure 2>/dev/null | grep -i 'free percentage' | tr -d '\n')"
    for name in xcodebuild swift-frontend; do
        # Скобки вокруг имени не ради bash — `$name:` он разбирает верно, —
        # а ради сканера: шаблон «цифра/символ вплотную к имени» краснеет
        # на этой строке ложно, и следующий потратит заход на здоровый код.
        echo "  ${name}: $(pgrep -x "$name" | wc -l | tr -d ' ')"
    done
}

sostoyanie_mashiny "ДО"

# Своё устройство, а не общее: общее даёт чужое приложение в кадре
# и чужой заход между erase и прогоном.
UDID="$(xcrun simctl list devices | grep -F "$SIM_NAME (" | head -1 \
        | sed -E 's/.*\(([0-9A-F-]{36})\).*/\1/')"
if [ -z "$UDID" ]; then
    # Рантайм НАЗЫВАЕТСЯ, а не выбирается «самый новый».
    #
    # До 14.10.2026 здесь стоял `| tail -1`, то есть новейший
    # установленный. Сегодня новейший — iOS 27.0, где стенд Togo
    # отказывает по устройству: `Cannot use staged migration with
    # an unknown model version`, перезапуски, 10 тестов из 1074.
    # Скрипт вёл новые прогоны ровно в сломанный рантайм и сам
    # об этом не говорил — две потери уже оплачены, и обе выглядели
    # как дефект продукта.
    #
    # Почему не «брать 26.5» одной строкой. Это снова условие,
    # привязанное к ИНСТРУМЕНТУ — к тому, что сейчас стоит на машине, —
    # и оно поменяет знак в момент успеха: выйдет 27.1, где стенд
    # заработает, а прибитая 26.5 останется; уберут 26.5 при уборке —
    # и `tail` снова возьмёт что попало. Условие привязывается
    # к ПРАВИЛУ: версия задана явно, и если её нет, скрипт отказывает
    # С ИМЕНЕМ, а не берёт ближайшую. Иначе следующий получит
    # «staged migration» и третий день будет искать причину в коде.
    RUNTIME_IOS="${RUNTIME_IOS:-26.5}"
    RUNTIME="com.apple.CoreSimulator.SimRuntime.iOS-${RUNTIME_IOS//./-}"

    # ТИП УСТРОЙСТВА — ПАРА К РАНТАЙМУ, а не отдельная настройка.
    #
    # Замер 26.10.2026: `RUNTIME_IOS=18.6` при прибитом `iPhone 17 Pro`
    # даёт `Incompatible device` (code=403) — устройство НОВЕЕ системы,
    # такой пары не существует. Переменная рантайма была, а
    # воспользоваться ею было нельзя: тип оставался от 26.5.
    #
    # > **Потолок защищает от нового рантайма и тем же механизмом
    # > запирает старый.** Условие привязано к тому, что стоит
    # > на машине, а не к правилу; знак оно сменило в тот момент,
    # > когда понадобилось мерить ВНИЗ, а не вверх.
    #
    # Поэтому тип задаётся РЯДОМ и по умолчанию соответствует
    # умолчанию рантайма. Меняешь одно — проверь второе: «iPhone 17 Pro
    # + 18.6» и «iPhone 16 Pro + 27.0» одинаково не заводятся,
    # а отказ приходит до прогона и выглядит как поломка стенда.
    DEVICE_TYPE="${DEVICE_TYPE:-com.apple.CoreSimulator.SimDeviceType.iPhone-17-Pro}"
    if ! xcrun simctl list runtimes available | grep -qF "$RUNTIME"; then
        cat >&2 <<KONEC

ЗАМЕР НЕ СОСТОЯЛСЯ: рантайма iOS ${RUNTIME_IOS} на машине нет.

Прогон идёт на НАЗВАННОЙ версии, а не на самой новой: на iOS 27.0
стенд Togo отказывает (Cannot use staged migration), и прогон там
умирает на тридцатом тесте из тысячи — внешне это неотличимо
от дефекта продукта.

Установлено сейчас:
$(xcrun simctl list runtimes available | grep -F 'com.apple.CoreSimulator.SimRuntime.iOS-' | sed 's/^/  /')

Поставить нужную версию (Xcode → Settings → Components) либо
назвать другую осознанно: RUNTIME_IOS=27.0 Tools/прогон-ui.sh ...
KONEC
        exit 9
    fi
    UDID="$(xcrun simctl create "$SIM_NAME" \
        "$DEVICE_TYPE" "$RUNTIME" 2>&1)"

    # ОТКАЗ `simctl create` ПРИХОДИТ В ПЕРЕМЕННОЙ, А НЕ КОДОМ.
    #
    # Замер 26.10.2026: при несовместимой паре он печатает
    # «Unable to create a device for device type: … runtime: …»
    # НА МЕСТЕ UDID. Дальше этот текст уезжает в `simctl ui`,
    # в `-destination` и в имя лога, и прогон отказывает три раза
    # подряд, ни разу не назвав причину: «Invalid device: Unable
    # to create…» читается как поломка стенда, а не как «такой пары
    # не бывает».
    #
    # > **Отказ назвал сторону, которая отказала, и не назвал причину** —
    # > наш первый пункт свода, пойманный на себе.
    #
    # Проверяется формой: UDID — это 36 символов UUID и ничего больше.
    if ! printf '%s' "$UDID" | grep -qE '^[0-9A-F-]{36}$'; then
        cat >&2 <<KONEC

ЗАМЕР НЕ СОСТОЯЛСЯ: устройство «${SIM_NAME}» не завелось.

Пара «тип + рантайм» несовместима либо тип не существует:
  тип:     $DEVICE_TYPE
  рантайм: iOS $RUNTIME_IOS

simctl ответил вместо UDID:
$UDID

Тип устройства не может быть НОВЕЕ рантайма: «iPhone 17 Pro + 18.6»
не бывает, как и «iPhone 16 Pro + 27.0». Назвать пару явно:
  DEVICE_TYPE=com.apple.CoreSimulator.SimDeviceType.iPhone-16-Pro \\
  RUNTIME_IOS=18.6 Tools/прогон-ui.sh <набор>

Доступные типы: xcrun simctl list devicetypes
KONEC
        exit 9
    fi
    echo "создан:     $UDID (iOS $RUNTIME_IOS, $DEVICE_TYPE)"
fi
echo "udid:       $UDID"

xcrun simctl bootstatus "$UDID" -b >/dev/null 2>&1

# ПОЛОЖЕНИЕ СТЕНДА: тема, контраст, кегль — ЧИТАЮТСЯ ОБРАТНО,
# а не объявляются.
#
# Замер 14.10.2026, живой симулятор `Togo-b6` посреди чужого прогона:
#
#     appearance        light
#     increase_contrast enabled
#     content_size      accessibility-extra-extra-extra-large
#
# Никто этого не задавал: `simctl ui` до сегодня не звал ни один наш
# скрипт и ни одна цель `Makefile`. Положение осталось от прошлого
# захода и ЛИПНЕТ к устройству, а кадры следующего прогона получают
# имена, в которых о нём нет ни слова. Так у проекта и появились
# «светлые кадры 12.10»: сняты не нарочно, а потому что стенд так стоял.
#
# Здесь две разные вещи, и вторая важнее первой:
#
#   TEMA / KONTRAST / KEGEL   задают положение. По умолчанию НЕ задают
#                             ничего — ни один существующий вызов
#                             не меняет поведения;
#   чтение обратно            печатается ВСЕГДА, и при заданном
#                             положении сверяется.
#
# Почему мало выставить. Выставить и поверить своему же аргументу —
# это ярлык, напечатанный ДО работы: он не зависит от исхода и потому
# не может оказаться неверным. У проекта это оплачено дважды —
# `generate_tokens.py` год печатал в Фигму «modes: Light», отправляя
# тёмную палитру, и `iosName()` печатала 135 имён, которых в Swift
# не существует ни одного. Единственная защита — спросить у системы,
# что она в итоге имеет, и сверить с тем, что просили.
#
# Имена переменных латиницей: кириллическое имя в bash не заводится
# вовсе, и следующая строка выполняется как ни в чём не бывало.
polozhenie_stenda() {
    local kogda="$1"
    echo "--- стенд ${kogda} ---"
    echo "  тема:     $(xcrun simctl ui "$UDID" appearance 2>&1)"
    echo "  контраст: $(xcrun simctl ui "$UDID" increase_contrast 2>&1)"
    echo "  кегль:    $(xcrun simctl ui "$UDID" content_size 2>&1)"
}

# Сверка «просили → получили». Расхождение здесь — отказ стенда,
# а не мелочь: кадр, снятый не в том положении, снаружи НЕ отличается
# от снятого в том, и принять его может кто угодно. Поэтому выход
# ненулевой, как у контроля лога приложения ниже.
#
# ФИГУРНЫЕ СКОБКИ В СООБЩЕНИИ НИЖЕ НЕ ЛИШНИЕ. `${prosili}»` — это
# защита от капкана, пойманного 14.10.2026 в соседнем скрипте стенда:
# многобайтная кавычка `»` ПРИКЛЕИВАЕТСЯ к имени переменной, и bash
# ищет `prosili»` — `unbound variable`. Имя при этом латиницей, то есть
# правило «только латиницей» этот класс НЕ покрывает: лишний байт
# пришёл от соседа по строке. Снимете скобки как лишние — получите
# отказ ровно в той ветке, которая и существует, чтобы сообщать
# об отказе.
sverit_polozhenie() {
    local chto="$1" prosili="$2" fakt
    fakt="$(xcrun simctl ui "$UDID" "$chto" 2>&1)"
    if [ "$fakt" != "$prosili" ]; then
        cat >&2 <<KONEC

ЗАМЕР НЕ СОСТОЯЛСЯ: просили ${chto}=«${prosili}», стенд отвечает «${fakt}».

Это НЕ «тесты упали» — прогон даже не начинался. Кадр, снятый
в непрошенном положении, снаружи неотличим от снятого в прошенном,
и его примут. Чинить стенд (поднялось ли устройство, умеет ли
рантайм эту настройку), а не считать результат.
KONEC
        exit 9
    fi
}

TEMA="${TEMA:-}"
KONTRAST="${KONTRAST:-}"
KEGEL="${KEGEL:-}"

[ -n "$TEMA" ]     && xcrun simctl ui "$UDID" appearance        "$TEMA"     >/dev/null 2>&1
[ -n "$KONTRAST" ] && xcrun simctl ui "$UDID" increase_contrast "$KONTRAST" >/dev/null 2>&1
[ -n "$KEGEL" ]    && xcrun simctl ui "$UDID" content_size      "$KEGEL"    >/dev/null 2>&1

polozhenie_stenda "ДО"

[ -n "$TEMA" ]     && sverit_polozhenie appearance        "$TEMA"
[ -n "$KONTRAST" ] && sverit_polozhenie increase_contrast "$KONTRAST"
[ -n "$KEGEL" ]    && sverit_polozhenie content_size      "$KEGEL"

# Ловим вывод САМОГО приложения. Без этого весь прогон бессмыслен:
# именно эта строка отличает инструмент от предыдущего захода.
xcrun simctl spawn "$UDID" log stream \
    --level debug --style compact \
    --predicate 'process == "Togo"' > "$APP_LOG" 2>/dev/null &
STREAM_PID=$!
sleep 2

ACTION="test"
[ "${BEZ_SBORKI:-0}" = "1" ] && ACTION="test-without-building"

xcodebuild -project Togo.xcodeproj -scheme Togo -configuration Debug \
    -destination "platform=iOS Simulator,id=$UDID" \
    -derivedDataPath "$OUT_DIR/dd" \
    "$ACTION" -only-testing:"$SUITE" > "$RUN_LOG" 2>&1
RC=$?

kill "$STREAM_PID" 2>/dev/null
wait "$STREAM_PID" 2>/dev/null

sostoyanie_mashiny "ПОСЛЕ"

# КОНТРОЛЬ НОЛЬ: СОБРАЛОСЬ ли вообще. Стоит ПЕРЕД контролем лога.
#
# Замер 14.10.2026, собственным заходом: сборка упала на чужой
# незавершённой правке в общем дереве
# (`FamilySync.swift:458: value of type 'SharedDiaryOutbox.Разбор'
# has no member 'isEmpty'`), приложение не запускалось ни разу — и
# контроль ниже честно сказал «в логе приложения нет приложения»,
# отправив чинить ОСНАСТКУ: симулятор, предикат, поток логов.
#
# > **Вердикт был верен, направление поиска — нет.** «Приложения
# > не видно» — следствие, и у него две разные причины: не запускали
# > и не собралось. Вторая дешевле первой на порядок, а ищут первую,
# > потому что про неё написан текст.
#
# Различитель: тесты либо запускались (`Test run with …`), либо нет.
# Если не запускались и в логе есть `error:` — это компилятор, и надо
# печатать ЕГО строки, а не советовать проверять симулятор.
#
# И отдельно: при общем дереве `xcodebuild` берёт ДИСК, а не коммит.
# Чужая правка, начатая в минуты твоей компиляции, ломает твой замер
# и выглядит как твой дефект. Лечится не этим скриптом, а worktree
# на названном коммите — но назвать причину скрипт обязан.
TESTY_SHLI="$(grep -cE '^Test Suite|Test run with' "$RUN_LOG" 2>/dev/null)"
TESTY_SHLI="${TESTY_SHLI:-0}"
if [ "$TESTY_SHLI" -eq 0 ]; then
    OSHIBKI="$(grep -cE ' error: ' "$RUN_LOG" 2>/dev/null)"
    OSHIBKI="${OSHIBKI:-0}"
    echo "тестов не запускалось · строк 'error:' в логе: $OSHIBKI" >&2
    cat >&2 <<'KONEC'

ЗАМЕР НЕ СОСТОЯЛСЯ: СБОРКА НЕ СОСТОЯЛАСЬ — тесты не запускались.

Это НЕ отказ оснастки и НЕ дефект продукта. Приложение не собралось,
то есть проверять симулятор, предикат и поток логов НЕ НАДО.

Первые ошибки компилятора:
KONEC
    grep -E ' error: ' "$RUN_LOG" | head -5 | sed 's/^/  /' >&2
    cat >&2 <<'KONEC'

Если этих ошибок нет в твоих файлах — смотри `git status`: при общем
дереве xcodebuild берёт ДИСК, а не коммит, и чужая незавершённая
правка ломает твой замер под твоим именем. Прогон — из `git worktree`
на названном коммите.
KONEC
    exit 8
fi

# КОНТРОЛЬ: видно ли в логе само приложение.
#
# Стоит ПОСЛЕ прогона и ДО любого вывода о результате — потому что
# при нуле все числа ниже рассказывают про инструмент, а не про мир,
# и печатать их как результат нельзя.
# Считаем ПРЕДМЕТ, а не слово.
#
# Первая редакция считала вхождения `Togo` — и пропустила пустой
# захват как годный. Замерено первым же запуском 08.10.2026: в логе
# была РОВНО ОДНА строка, и это баннер самого потока логов —
#
#     Filtering the log data using "process == "Togo""
#
# В нём есть слово `Togo`, порог «> 0» он берёт, а вывода приложения
# при этом ноль. Контроль говорил «годен» на пустоте.
#
# Ищем форму `Togo[` — процесс с номером, которую печатает только
# сам процесс. `-F` обязателен: без него `[` открывает класс символов
# и шаблон молча не совпадает ни с чем.
APP_LINES="$(grep -cF 'Togo[' "$APP_LOG" 2>/dev/null)"
APP_LINES="${APP_LINES:-0}"
echo "строк приложения в логе: $APP_LINES"
