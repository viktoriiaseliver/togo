def отметка_нормы(дата: str, показатель: str, value, low, high) -> str:
    """«Отметки нет, потому что значение в норме» — НЕ ПРОБЕЛ документа.

    Первая версия этой сборки звала `пусто()` на каждой записи
    без отметки и выдала 102 пробела вместо 24: семьдесят восемь из них
    были значениями В ПРЕДЕЛАХ НОРМЫ, у которых лаборатория ничего
    не помечает по природе бланка.

    > Смешав «бланк не процитирован» с «значение в границах», список
    > пробелов раздувается в четыре раза — и настоящие пять пробелов
    > по общему Т4 в нём больше не видны. Список, в котором тонет
    > находка, хуже отсутствия списка.

    Поэтому различаем по тому, ЕСТЬ ЛИ ЧЕМ СУДИТЬ: границы названы
    и значение в них — пишем «без отметки, в границах нормы», это факт
    бланка. Границ нет — пробел настоящий, и он должен быть виден.
    """
    if value is not None and low is not None and high is not None:
        if low <= value <= high:
            return "без отметки — значение в границах нормы"
        return "вне границ нормы бланка"
    if value is not None and high is not None and low is None:
        return ("без отметки — значение в границах нормы"
                if value <= high else "вне границ нормы бланка")
    return пусто(f"labResults[{дата} · {показатель}].labMark",
                 "референс с бланка в своде не процитирован — судить "
                 "об отметке нечем")


