# просто перестала притворяться отметками.
ГОРИЗОНТ_ДОЗ_ДНЕЙ = 60


def дозы_для(имя_схемы: str) -> list:
    """Приёмы одной схемы: по дню на каждый час из расписания.

    Старше `ГОРИЗОНТ_ДОЗ_ДНЕЙ` не восстанавливаются — разбор выше.
    """
    порог = СОБРАНО.date() - dt.timedelta(days=ГОРИЗОНТ_ДОЗ_ДНЕЙ)
    дозы = []
    for имя, с, по, часы in ПЕРИОДЫ_ПРИЁМА:
        if имя != имя_схемы:
            continue
        д1 = dt.date(*reversed([int(x) for x in с.split(".")]))
        д2 = dt.date(*reversed([int(x) for x in по.split(".")]))
        день = max(д1, порог)
        while день <= д2:
            дата = ддммгггг(день)
            for минута in часы:
                # День перехода: вечер уже новой схемы, утро — старой.
                if (дата, минута) == ПЕРЕХОД_26_10:
                    if имя_схемы != "Эутирокс 88 мкг (левотироксин натрия)":
                        continue
                elif дата == ПЕРЕХОД_26_10[0] and \
                        имя_схемы == "Эутирокс 88 мкг (левотироксин натрия)":
                    continue
                сдвиг, примечание = ИСКЛЮЧЕНИЯ_ДОЗ.get(
                    (дата, минута), (минута, None))
                # ПРИЁМ, КОТОРОГО ЕЩЁ НЕ БЫЛО, ОТМЕЧАТЬ НЕЛЬЗЯ.
                #
                # Пока период кончался литералом «27.10.2026», этого
                # случая не возникало. Стоило привязать конец к дню
                # сборки — и последняя доза встала на сегодняшний
                # вечер с проставленным `givenAt`: карта утверждала,
                # что вечернюю таблетку уже дали, хотя до неё десять
                # часов. Восстановление задним числом на то и задним,
                # что дальше «сейчас» не заходит.
                если = dt.datetime.fromisoformat(
                    час(дата, сдвиг // 60, сдвиг % 60))
                if если > СОБРАНО:
                    continue
                дозы.append({
                    "scheduledAt": час(дата, минута // 60, минута % 60),
                    "givenAt": час(дата, сдвиг // 60, сдвиг % 60),
                    "givenBy": ПОДПИСЬ_ДОЗЫ + (
                        f"; {примечание}" if примечание else ""),
                    "cancelledAt": None,
                    "cancelReason": None,
                    "skippedAt": None,
                    "skippedBy": None,
                    "claimedBy": None,
                    "claimedAt": None,
                    "awaitedMedicationName": None,
                })
            день += dt.timedelta(days=1)
    return дозы

