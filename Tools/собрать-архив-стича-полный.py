def поля_снимков_из_кода() -> dict:
    """Какие поля ЖДЁТ `BackupArchive.swift` — читается из исходника.

    # Зачем читать код, а если он недоступен — молчать

    28.10.2026 замер по готовому файлу нашёл тринадцать полей, которых
    в нём не было ВОВСЕ: девять у лекарств (`canGiveOutside`,
    `fastingBeforeMinutes`, `courseEnd`…) и четыре у документов
    (`occurredOn`, `directionRaw`, `clinicName`, `deletedAt`).

    > Отсутствующее поле и поле со значением `null` при восстановлении
    > дают одно и то же — и ровно поэтому расхождение невидимо: файл
    > выглядит полным, просто четверти полей в нём нет.

    Снимки архива растут (V8 добавила три поля документу в тот же
    день), а генератор о них не узнаёт никак: он пишет словари, и ни
    компилятор, ни тест Swift его не проверяют. Единственная дорога —
    прочитать объявления.

    **Отказ чтения возвращает пустое и НЕ выдумывает ответа.** Пустой
    словарь означает «проверить нечем», и сверка ниже это печатает
    отдельной строкой: ложное «всё сошлось» здесь дороже, чем
    честное «не проверял».
    """
    код = ОТКУДА / "TogoShared" / "Domain" / "BackupArchive.swift"
    if not код.exists():
        return {}
    текст = код.read_text(encoding="utf-8")
    снимки = {}
    for м in re.finditer(r"struct (\w+Snapshot)[^{]*\{(.*?)\n    \}",
                         текст, re.S):
        поля = re.findall(r"^\s{8}var (\w+):", м.group(2), re.M)
        if поля:
            снимки[м.group(1)] = set(поля)
    return снимки


# Коллекция собаки → имя снимка. Выводится из `DogSnapshot`, а не
# печатается рукой: список коллекций меняется вместе со схемой.
def коллекции_и_снимки(снимки: dict) -> dict:
    код = ОТКУДА / "TogoShared" / "Domain" / "BackupArchive.swift"
    if not код.exists():
        return {}
    м = re.search(r"struct DogSnapshot[^{]*\{(.*?)\n    \}",
                  код.read_text(encoding="utf-8"), re.S)
    if not м:
        return {}
    пары = re.findall(r"^\s{8}var (\w+):\s*\[(\w+Snapshot)\]", м.group(1), re.M)
    return {имя: снимок for имя, снимок in пары if снимок in снимки}


def сверить_со_схемой(пёс: dict, архив=None) -> list[str]:
    """Каждое поле снимка обязано ПРИСУТСТВОВАТЬ хотя бы в одной записи.

    Ось — присутствие ключа, а не его значение: `None` это законный
    ответ («спрашивали, не нашли»), отсутствие ключа — нет.

    Проверяется по ОБЪЕДИНЕНИЮ полей всех записей коллекции, а не
    по первой: записи честно бывают разными, и требовать все поля
    от каждой значило бы запретить необязательные.

    # Дыра, через которую 28.10 прошли ещё пять ключей

    Сверка глядела ТОЛЬКО внутрь непустых коллекций. Поэтому
    `photo`, `stocks`, `heats`, `daysOut` и корневой `procedureSkills`
    она не заметила: у первого нет коллекции вовсе, у трёх остальных
    коллекция была пуста — а точнее, её не было в словаре, и отличить
    «пусто» от «забыли» сверке было нечем. Днём раньше тот же класс
    стоил тринадцати полей, и починили тогда только следствие.

    Теперь сверяются ТРИ слоя:
      · сам `DogSnapshot` — все его поля, включая скаляры и пустые списки;
      · `BackupArchive` — корневые ключи, включая `procedureSkills`;
      · содержимое непустых коллекций, как и прежде.
    """
    снимки = поля_снимков_из_кода()
    if not снимки:
        return ["СВЕРЯТЬ НЕЧЕМ: BackupArchive.swift не прочитан — "
                "поля снимков не проверены ни одним замером"]
    пары = коллекции_и_снимки(снимки)
    if not пары:
        return ["СВЕРЯТЬ НЕЧЕМ: в DogSnapshot не нашлось ни одной "
                "коллекции — разбор исходника не состоялся"]
    беды = []

    # Слой 1: поля самой собаки. `deletedAt` — надгробие, его в файле
    # живой собаки нет по смыслу, и требовать его значило бы просить
    # пометить Стича удалённым.
    живой_пёс = снимки.get("DogSnapshot", set()) - {"deletedAt"}
    нет_у_собаки = живой_пёс - set(пёс)
    if нет_у_собаки:
        беды.append("dogs[0]: в снимке собаки нет ключей вовсе: "
                    + ", ".join(sorted(нет_у_собаки)))

    # Слой 2: корень архива. Поля читаются из `struct BackupArchive`
    # тем же разбором, что и снимки, — руками список не печатается.
    if архив is not None:
        код = ОТКУДА / "TogoShared" / "Domain" / "BackupArchive.swift"
        м = re.search(r"struct BackupArchive[^{]*\{(.*?)\n    struct ",
                      код.read_text(encoding="utf-8"), re.S) \
            if код.exists() else None
        корневые = set(re.findall(r"^\s{4}var (\w+):", м.group(1), re.M)) \
            if м else set()
        нет_в_корне = корневые - set(архив)
        if корневые and нет_в_корне:
            беды.append("корень архива: нет ключей вовсе: "
                        + ", ".join(sorted(нет_в_корне)))
        elif not корневые:
            беды.append("СВЕРЯТЬ НЕЧЕМ: поля BackupArchive не разобраны — "
                        "корневые ключи не проверены")

    for ключ, снимок in sorted(пары.items()):
        записи = пёс.get(ключ)
        if not isinstance(записи, list) or not записи:
            continue
        есть = set().union(*(set(з) for з in записи if isinstance(з, dict)))
        нет = снимки[снимок] - есть
        if нет:
            беды.append(f"{ключ}: снимок ждёт полей, которых нет "
                        f"НИ В ОДНОЙ из {len(записи)} записей: "
                        f"{', '.join(sorted(нет))}")
    return беды


