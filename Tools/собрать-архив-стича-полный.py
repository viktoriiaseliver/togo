def рецепты_снимками():
    """«Рецепты.csv» + два из раздела 15 + выписка 01.09.2026."""
    снимки = []
    строк = 0
    путь = ТАБЛИЦЫ / "Рецепты.csv"
    with путь.open(encoding="utf-8") as ф:
        for строка in csv.DictReader(ф):
            дата = excel(строка.get("Дата"))
            if дата is None:
                continue
            строк += 1
            номер_сырой = (строка.get("№ рецепта") or "").strip()
            # В графе номера местами стоит проза: «без № (fiche de
            # consultation)», «без № (рецепта в почте нет)». Это НЕ номер,
            # и подставлять её в поле номера значит печатать бессмыслицу
            # там, где её назовут в аптеке. Проза уходит в `source`.
            похож = bool(номер_сырой) and not номер_сырой.startswith("без №")
            клиника_сырая = (строка.get("Клиника") or "").strip()
            клиника = КЛИНИКА_ПО_ТАБЛИЦЕ.get(клиника_сырая)
            препарат = (строка.get("Препарат") or "").strip()
            источник = (строка.get("Источник") or "").strip()
            if not похож and номер_сырой:
                источник = f"{источник}; в бланке номера нет — {номер_сырой}"
            от_до = КОНТРОЛЬ_НЕДЕЛИ.get(номер_сырой, (0, 0))
            снимки.append({
                "number": номер_сырой if похож else пусто(
                    f"prescriptions[{ддммгггг(дата)} · {препарат[:40]}]"
                    ".number",
                    f"номера у документа нет: {номер_сырой or 'графа пуста'}"),
                "date": д(ддммгггг(дата)),
                "clinicName": клиника,
                "doctor": (строка.get("Врач (+ № ордена)") or "").strip(),
                "dogWeightKg": число(строка.get("Вес собаки (кг)")),
                "medicationName": препарат,
                "dosage": (строка.get("Дозировка") or "").strip(),
                "schedule": (строка.get("Схема приёма") or "").strip(),
                "duration": (строка.get("Длительность") or "").strip(),
                "pharmacyForm": None,
                "controlFromWeeks": от_до[0],
                "controlToWeeks": от_до[1],
                "dispensed": "",
                "instruction": (строка.get("Инструкция (кратко)") or "").strip(),
                "source": источник,
            })
    for (номер, дата, клиника, врач, вес, препарат, доза, схема, длит,
         форма, выдано, инструкция, источник) in (
            ДОБАВОЧНЫЕ_РЕЦЕПТЫ + [ВЫПИСКА_01_09]):
        от_до = КОНТРОЛЬ_НЕДЕЛИ.get(номер or "", (0, 0))
        if номер is None:
            от_до = (4, 6)    # §24: контроль через 4–6 недель, слова врача
        снимки.append({
            "number": номер if номер else пусто(
                f"prescriptions[{дата} · {препарат[:40]}].number",
                "это выписка из медкарты, номера у неё нет"),
            "date": д(дата),
            "clinicName": клиника,
            "doctor": врач,
            "dogWeightKg": вес,
            "medicationName": препарат,
            "dosage": доза,
            "schedule": схема,
            "duration": длит,
            "pharmacyForm": форма,
            "controlFromWeeks": от_до[0],
            "controlToWeeks": от_до[1],
            "dispensed": выдано,
            "instruction": инструкция,
            "source": источник,
        })
    return снимки, строк


