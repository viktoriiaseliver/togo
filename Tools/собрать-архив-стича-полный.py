def проверить(архив: dict) -> list[str]:
    """Сверки, которые обязаны пройти. Красное печатается и валит прогон."""
    беды = []
    if архив["formatVersion"] != 1:
        беды.append(f"formatVersion = {архив['formatVersion']}, нужен 1")
    for обязательное in ("createdAt", "appVersion", "dogs", "members",
                         "episodes"):
        if обязательное not in архив:
            беды.append(f"нет обязательного поля {обязательное}")
    пёс = архив["dogs"][0]
    # Связь с клиникой держится ТОЧНЫМ СОВПАДЕНИЕМ ИМЕНИ. Промах
    # не падает и не кричит — он оставляет связь пустой, и файл
    # выглядит целым. Поэтому сверка здесь, а не на глаз.
    справочник = {к["name"] for к in архив["clinics"]}
    for вид in ("careTasks", "vetVisits", "prescriptions"):
        for запись in пёс[вид]:
            имя = запись.get("clinicName")
            if имя and имя not in справочник:
                беды.append(f"{вид}: клиники «{имя}» нет в справочнике")
    # Дробных секунд в датах быть не должно: JSONDecoder на .iso8601
    # их не берёт, и отказ придёт у человека, а не здесь.
    def даты(о, путь=""):
        if isinstance(о, dict):
            for к, з in о.items():
                yield from даты(з, f"{путь}.{к}")
        elif isinstance(о, list):
            for i, з in enumerate(о):
                yield from даты(з, f"{путь}[{i}]")
        elif isinstance(о, str) and len(о) >= 19 and о[4] == "-" and о[10] == "T":
            yield путь, о
    for путь, значение in даты(архив):
        if "." in значение.split("T")[1]:
            беды.append(f"дробные секунды в дате {путь}: {значение}")
    # Предел прибора числом — тот самый класс, от которого три поля
    # значения и завели. Ни у одной записи `value` и `belowLimit`
    # не смеют стоять вместе.
    for а in пёс["labResults"]:
        если = [к for к in ("value", "belowLimit", "aboveLimit", "textValue")
                if а.get(к) is not None]
        if len(если) > 1:
            беды.append(f"labResults[{а['indicator']}]: сразу "
                        f"{', '.join(если)} — значение должно быть одно")
    for з in пёс["medications"]:
        if з.get("isPaused") and not з.get("cancelledAt"):
            беды.append(f"medications[{з['name']}]: отменена без cancelledAt")
    return беды


