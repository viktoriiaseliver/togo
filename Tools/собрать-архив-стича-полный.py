def совпадаетВид(дело: str, историческое: str) -> bool:
    """Одна ли это прививка — по марке И названию, а не по одной марке.

    Прежде сравнивалось ПЕРВОЕ СЛОВО, и этого хватало, пока в истории
    висели одни даты. Но «Canigen» — марка сразу двух РАЗНЫХ вакцин:
    `Canigen CHPPi/L` (чума, гепатит, парво, параграпп) и `Canigen L4`
    (лептоспироз). По первому слову обе истории ложились в обе
    карточки, и, открыв лептоспироз, человек читал про чуму.

    > Ключ, различающий меньше, чем различает предметная область,
    > не ошибается заметно — он просто показывает лишнее, и это
    > принимают за полноту.

    Сравнение теперь по ПРЕФИКСУ: `Canigen CHPPi` короче, чем
    `Canigen CHPPi/L`, и одно продолжает другое — это один вид.
    `Canigen L4` не продолжает `Canigen CHPPi` ни с какой стороны.
    Хвост после «—» и «,» отсекается: он описательный
    («— лептоспироз», «, ревакцинация»).
    """
    def ключ(s: str) -> str:
        голова = s.split("—")[0].split(",")[0]
        return " ".join(голова.lower().split())
    а, б = ключ(дело), ключ(историческое)
    return а.startswith(б) or б.startswith(а)


def прививки_делами():
    """Пять дел по видам прививок — СРОК ВПЕРЁД, а не запись о прошлом.

    `scheduledDate` — СЛЕДУЮЩАЯ дата (её возвращает `dueDate`
    для `.dated`), `lastDone` — когда делали в последний раз.
    До правки 27.10 в обоих полях стояла дата прививки, и приложение
    честно считало все одиннадцать просроченными с 2023 года.
    """
    дела = []
    for дата, имя, партия, следующая, клиника in ПРИВИВКИ:
        подробно = ПРИВИВКИ_ПОДРОБНО.get((дата, партия), "")
        деталь = (f"Последняя вакцинация {дата}, партия (лот) {партия}. "
                  f"Следующая — {следующая}.")
        if подробно:
            деталь += " " + подробно
        # ИСТОРИЯ ЭТОГО ЖЕ ВИДА — ВНУТРЬ КАРТОЧКИ, а не только в ленту.
        #
        # Жалоба Виктории 27.10.2026: «часть инфы не залилась куда надо,
        # а просто упала в историю». Прошлые прививки лежали записями
        # дневника — и только там: открыв «Бешенство», человек видел
        # одну дату и не видел, что до неё была первичная 2023 года
        # с другой вакциной и другим сроком.
        #
        # Сама модель истории не держит: у `CareTask` одно `lastDone`,
        # и второго места для прежних дат в ней нет. Поэтому они идут
        # В ТЕКСТ дела — там, где человек их ищет, открыв прививку.
        #
        # **28.10.2026 карточка стала ЕДИНСТВЕННЫМ местом.** Прежде те же
        # шесть прививок ехали ещё и записями ленты, «чтобы лента отвечала,
        # что было в тот день». Решение Виктории: в ленте остаются только
        # наблюдения владельца, структурное из неё уходит. Поэтому сюда
        # переехало и ПРИМЕЧАНИЕ каждой прошлой прививки — шестое поле
        # `ПРИВИВКИ_ИСТОРИЯ`: без него пропали бы «первая доза двухдозовой
        # схемы», «паспорт стр. 6–9» и отрицательный Speed Leish K.
        прежние = [(д, им, лот, до, прим)
                   for д, им, лот, до, _, прим in ПРИВИВКИ_ИСТОРИЯ
                   if совпадаетВид(имя, им)]
        if прежние:
            части = [f"{д} — {им}, лот {лот}"
                     + (f", до {до}" if до else "")
                     + (f" ({прим.rstrip('.')})" if прим else "")
                     for д, им, лот, до, прим in прежние]
            деталь += " ПРЕЖДЕ: " + "; ".join(части) + "."
        дела.append({
            "title": имя,
            "detail": деталь,
            "kindRaw": "dated",
            "categoryRaw": "medical",
            # Срок годности минус дата прививки: интервал, который дала
            # сама вакцина, а не наше предположение про год.
            "intervalDays": дней(дата, следующая),
            "scheduledDate": д(следующая),   # КОГДА СЛЕДУЮЩАЯ
            "lastDone": д(дата),             # когда делали
            "remindDaysBefore": 14,
            "streak": 0,
            "snoozeCount": 0,
            "clinicName": клиника,
            "vaccineBatch": партия,
            "vaccineValidUntil": д(следующая),
        })
    return дела


def дней(от: str, до: str) -> int:
    д1, м1, г1 = (int(x) for x in от.split("."))
    д2, м2, г2 = (int(x) for x in до.split("."))
    return (dt.date(г2, м2, д2) - dt.date(г1, м1, д1)).days


