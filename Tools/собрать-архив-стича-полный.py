def прививки_делами():
    """Пять дел по видам прививок — СРОК ВПЕРЁД, а не запись о прошлом.

    `scheduledDate` — СЛЕДУЮЩАЯ дата (её возвращает `dueDate`
    для `.dated`), `lastDone` — когда делали в последний раз.
    До правки 27.10 в обоих полях стояла дата прививки, и приложение
    честно считало все одиннадцать просроченными с 2023 года.
    """
    дела = []
    for дата, имя, партия, следующая, клиника in ПРИВИВКИ:
        подробно = ПРИВИВКИ_ПОДРОБНО.get((дата, партия), "")
        деталь = (f"Последняя вакцинация {дата}, партия (лот) {партия}. "
                  f"Следующая — {следующая}.")
        if подробно:
            деталь += " " + подробно
        дела.append({
            "title": имя,
            "detail": деталь,
            "kindRaw": "dated",
            "categoryRaw": "medical",
            # Срок годности минус дата прививки: интервал, который дала
            # сама вакцина, а не наше предположение про год.
            "intervalDays": дней(дата, следующая),
            "scheduledDate": д(следующая),   # КОГДА СЛЕДУЮЩАЯ
            "lastDone": д(дата),             # когда делали
            "remindDaysBefore": 14,
            "streak": 0,
            "snoozeCount": 0,
            "clinicName": клиника,
            "vaccineBatch": партия,
            "vaccineValidUntil": д(следующая),
        })
    return дела


def дней(от: str, до: str) -> int:
    д1, м1, г1 = (int(x) for x in от.split("."))
    д2, м2, г2 = (int(x) for x in до.split("."))
    return (dt.date(г2, м2, д2) - dt.date(г1, м1, д1)).days


