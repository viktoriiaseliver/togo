def дополнить_лечение(схемы: list) -> list:
    """Девять полей `MedicationSnapshot`, которых в записях не было вовсе.

    # Это не пустые значения — полей НЕ БЫЛО

    Замер 28.10.2026 по файлу на рабочем столе: `canGiveOutside`,
    `courseEnd`, `expiry`, `fastingBeforeMinutes`, `minutesAfterMeal`,
    `openedAt`, `remindBeforeExpiry`, `shelfAfterOpenDays`,
    `stockLeftAmount` встречались **в 0 записях из 9**. Снимок архива
    их знает, генератор — нет.

    > Отсутствующее поле и поле со значением `null` при восстановлении
    > дают одно и то же, и ровно поэтому расхождение не видно глазом:
    > файл выглядит полным, в нём просто нет четверти полей.

    # Окно натощак ДО приёма — не копия окна после

    `fastingMinutes` в записях есть, `fastingBeforeMinutes` не было.
    Медкнижка, раздел «Правила приёма», говорит про оба конца прямо:
    «за 1 час до приёма и 1 час после собака не ела».

    Поэтому окно «до» берётся равным окну «после» — но только там,
    где окно «после» вообще задано. У двух действующих схем оно `0`
    нарочно: с 01.09.2026 по назначению Кочубиной «давать можно
    независимо от еды», и подставлять туда час значило бы вернуть
    отменённое врачом ограничение.

    # Чего здесь НЕТ и почему

    `expiry`, `openedAt`, `shelfAfterOpenDays`, `courseEnd` остаются
    `None`: в медкнижке этих величин нет, а подставить их — значит
    записать за человека то, чего он не говорил. Поля при этом
    ПРИСУТСТВУЮТ со значением `null`: так видно, что их спрашивали
    и ответа не нашли, — это другое состояние, чем «поле забыли».

    `canGiveOutside` — `False` у всех: приём левотироксина привязан
    к часам дома, а не к прогулке, и строку «Дал» в режиме прогулки
    она не просила.
    """
    for схема in схемы:
        натощак = схема.get("fastingMinutes") or 0
        схема.setdefault("fastingBeforeMinutes", натощак)
        схема.setdefault("minutesAfterMeal", None)
        схема.setdefault("canGiveOutside", False)
        схема.setdefault("courseEnd", None)
        схема.setdefault("expiry", None)
        схема.setdefault("openedAt", None)
        схема.setdefault("remindBeforeExpiry", True)
        схема.setdefault("shelfAfterOpenDays", None)
        # `stockLeft` в записях уже есть — это штуки; `stockLeftAmount`
        # то же самое в единицах дозы. Для таблеток они совпадают.
        схема.setdefault("stockLeftAmount", схема.get("stockLeft"))
    return схемы


