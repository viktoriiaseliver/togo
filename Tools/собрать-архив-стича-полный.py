def д(строка: str) -> str:
    """ДД.ММ.ГГГГ → ISO-8601, полдень UTC. ДЕНЬ КАЛЕНДАРЯ."""
    день, месяц, год = строка.split(".")
    return dt.datetime(int(год), int(месяц), int(день), 12, 0,
                       tzinfo=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def час(строка: str, чч: int, мм: int) -> str:
    """ДД.ММ.ГГГГ + часы:минуты по Ницце → ISO-8601 со смещением.

    МОМЕНТ НА ЧАСАХ, а не день: время забора крови интерпретирует
    результат, и сдвиг на два часа менял вывод врача (§26 медкнижки).
    """
    день, месяц, год = строка.split(".")
    м = dt.datetime(int(год), int(месяц), int(день), чч, мм, tzinfo=НИЦЦА)
    return м.strftime("%Y-%m-%dT%H:%M:%S%z")[:-2] + ":" + \
        м.strftime("%z")[-2:]


def excel(значение) -> dt.date | None:
    с = str(значение).strip()
    if not с or с == "—":
        return None
    try:
        return EXCEL_EPOCH + dt.timedelta(days=float(с))
    except ValueError:
        return None


def ддммгггг(д_: dt.date) -> str:
    return д_.strftime("%d.%m.%Y")


def число(значение) -> float | None:
    с = str(значение).strip().replace(",", ".")
    if not с or с in ("—", "нет данных", "не указана", "не назначался"):
        return None
    try:
        return float(с)
    except ValueError:
        return None


