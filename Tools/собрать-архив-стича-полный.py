# значит раздувать файл впустую.
СКАН_СТОРОНА = 1400
СКАН_КАЧЕСТВО = 60

_ВРЕМЕНКА = None


def скан(относительный: str) -> str | None:
    """Первая страница бумаги → base64 JPEG. Не вышло — `None` и строка в отчёт.

    `DogDocument.image` рисуется через `UIImage(data:)`
    (`DocumentPhotos.swift:479`) — **PDF туда класть нельзя**, он не
    нарисуется и выглядеть это будет как «снимка нет». Растрируем
    системным `sips`: он берёт и PDF (первую страницу), и PNG, и JPEG,
    и стоит на машине всегда — ImageMagick и `pdftoppm` здесь нет.

    Отказ НЕ валит прогон: карта без снимка документа остаётся верной
    картой, а вот карта без анализов — нет. Каждый непрочитанный файл
    называется в конце прогона поимённо.
    """
    global _ВРЕМЕНКА
    бумага = БУМАГИ / относительный
    if not бумага.exists():
        ПУСТЫЕ_ОБЯЗАТЕЛЬНЫЕ.append(
            f"documents.image: файла нет на месте — {относительный}")
        return None
    if shutil.which("sips") is None:
        ПУСТЫЕ_ОБЯЗАТЕЛЬНЫЕ.append(
            "documents.image: `sips` не найден, ни одна бумага не снята")
        return None
    if _ВРЕМЕНКА is None:
        _ВРЕМЕНКА = tempfile.mkdtemp(prefix="стич-сканы-")
    куда = pathlib.Path(_ВРЕМЕНКА) / (uuid.uuid4().hex + ".jpg")
    итог = subprocess.run(
        ["sips", "-s", "format", "jpeg",
         "-s", "formatOptions", str(СКАН_КАЧЕСТВО),
         "--resampleHeightWidthMax", str(СКАН_СТОРОНА),
         str(бумага), "--out", str(куда)],
        capture_output=True, text=True)
    if итог.returncode != 0 or not куда.exists():
        ПУСТЫЕ_ОБЯЗАТЕЛЬНЫЕ.append(
            f"documents.image: `sips` не справился с {относительный} — "
            f"{(итог.stderr or '').strip().splitlines()[-1:] or 'без вывода'}")
        return None
    return base64.b64encode(куда.read_bytes()).decode("ascii")


