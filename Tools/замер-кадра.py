#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Средняя яркость кадра — чем отличают тёмную партию от светлой.

## Зачем он есть

Приёмка кадра в этом проекте не бывает «посмотрели и согласились»:
оба кадра главного экрана снимались и раньше, подпись читали глазами
и соглашались, а она давала 1,10:1. Различает только число.

А число про тему нужно потому, что **ярлык печатается до работы
и от её исхода не зависит, значит не может оказаться неверным.**
07.10 тест печатал «КАДРЫ (светлая тема)» над тёмным кадром. Имя файла
«…-тёмная» — такой же ярлык: его печатает человек или скрипт, а не
симулятор.

Отсюда правило съёмки: тема ставится `simctl ui <udid> appearance`,
**читается обратно** оттуда же, и третьим свидетелем идёт яркость
самого PNG. Три замера с разных сторон; `simctl` отвечает про
настройку системы, этот файл — про то, что вышло на картинке.

## Чем он НЕ является

Он не считает контраст пары «текст на фоне». Это другой вопрос
и другой инструмент — `Tools/contrast_graphite.py`, и тот считает
по hex из `colors.css`, то есть по тому, что ЗАДУМАНО. Здесь —
по тому, что НАРИСОВАНО, и только одной величиной: средней яркостью
всего кадра.

## Почему свой декодер

Замер инструментов на этой машине (запуском, а не предположением):

    PIL · numpy · PyObjC · ffmpeg · ImageMagick    нет ни одного
    sips                                           есть, статистики не считает
    swift                                          есть

Поэтому PNG разбирается здесь: `zlib` плюс четыре фильтра строки.
Поддержано ровно то, чем снимает симулятор — 8 бит, colortype 2 и 6,
без интерлейса. Встретится другое — скажет отказом, а не числом.

## Приёмка самого инструмента

**Инструмент проверки подвержен ровно тому классу, который ищет.**
Поэтому у него есть `--приёмка`: три пары из
`Дизайн/кадры-приёмки/журнал-приёмки/README.md`, у которых ответ
записан заранее. Пока они не воспроизведены, число этого файла —
не замер.

Формула взята не из головы: Rec.709 выбрана потому, что только она
воспроизвела записанные 0,9444 и 0,0760 до четвёртого знака.
Среднее RGB давало 0,9457 и 0,0749 — похоже, и мимо.

Использование:

    python3 Tools/замер-кадра.py кадр.png [ещё.png …]
    python3 Tools/замер-кадра.py --пара светлый.png тёмный.png
    python3 Tools/замер-кадра.py --приёмка
    python3 Tools/замер-кадра.py --точно кадр.png   # без уменьшения
"""

import os
import struct
import subprocess
import sys
import tempfile
import zlib

# Пары с ответом, записанным до того, как появился этот файл.
# Источник — Дизайн/кадры-приёмки/журнал-приёмки/README.md.
ИЗВЕСТНЫЕ = [
    ("виджет, заглушка в галерее",
     "виджет-заглушка-светлая-принят.png", 0.9444,
     "виджет-заглушка-тёмная-контроль.png", 0.0760),
    ("«остров», живая активность",
     "остров-живая-активность-светлая-принят.png", 0.9452,
     "остров-живая-активность-тёмная-контроль.png", 0.0743),
    ("главный экран",
     "главный-светлая-ПОСЛЕ-принят-5_04.png", 0.6536,
     "главный-тёмная-контроль-5_31.png", 0.2064),
]

ЖУРНАЛ = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "Дизайн", "кадры-приёмки", "журнал-приёмки")


class ОтказЗамера(Exception):
    """Замер не состоялся. Это не ноль яркости и не чёрный кадр."""


def разобрать_png(путь):
    """Вернуть (ширина, высота, каналов, байты пикселей)."""
    with open(путь, "rb") as ф:
        d = ф.read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        raise ОтказЗамера(f"{путь}: не PNG")

    поз, idat, шапка = 8, bytearray(), None
    while поз < len(d):
        (длина,) = struct.unpack(">I", d[поз:поз + 4])
        тип = d[поз + 4:поз + 8]
        тело = d[поз + 8:поз + 8 + длина]
        if тип == b"IHDR":
            шапка = struct.unpack(">IIBBBBB", тело)
        elif тип == b"IDAT":
            idat += тело
        elif тип == b"IEND":
            break
        поз += 12 + длина

    if шапка is None:
        raise ОтказЗамера(f"{путь}: нет IHDR")
    ш, в, бит, цвет, _, _, интерлейс = шапка
    if бит != 8 or интерлейс != 0 or цвет not in (2, 6):
        raise ОтказЗамера(
            f"{путь}: не поддержано — бит={бит} colortype={цвет} "
            f"интерлейс={интерлейс}. Кадры симулятора бывают 8/2 и 8/6; "
            f"это что-то другое, и молча считать его нельзя")

    к = 3 if цвет == 2 else 4
    сырое = zlib.decompress(bytes(idat))
    шаг = ш * к
    итог = bytearray(в * шаг)
    пред = bytearray(шаг)
    p = 0
    for y in range(в):
        ф = сырое[p]
        p += 1
        стр = bytearray(сырое[p:p + шаг])
        p += шаг
        if ф == 1:
            for i in range(к, шаг):
                стр[i] = (стр[i] + стр[i - к]) & 255
        elif ф == 2:
            for i in range(шаг):
                стр[i] = (стр[i] + пред[i]) & 255
        elif ф == 3:
            for i in range(шаг):
                a = стр[i - к] if i >= к else 0
                стр[i] = (стр[i] + ((a + пред[i]) >> 1)) & 255
        elif ф == 4:
            for i in range(шаг):
                a = стр[i - к] if i >= к else 0
                b = пред[i]
                c = пред[i - к] if i >= к else 0
                пр = a + b - c
                па, пб, пц = abs(пр - a), abs(пр - b), abs(пр - c)
                стр[i] = (стр[i] + (a if (па <= пб and па <= пц)
                                    else (b if пб <= пц else c))) & 255
        elif ф != 0:
            raise ОтказЗамера(f"{путь}: неизвестный фильтр строки {ф}")
        итог[y * шаг:(y + 1) * шаг] = стр
        пред = стр
    return ш, в, к, итог


def яркость(путь, точно=False):
    """Средняя яркость кадра, 0…1. Rec.709.

    По умолчанию кадр уменьшается `sips` до 128 px по большей стороне:
    полный разбор кадра симулятора на чистом питоне идёт около минуты,
    а партия из восьми кадров — восемь минут, и инструментом с такой
    ценой не пользуются. Уменьшение проверено на трёх известных парах
    (`--приёмка`): до четвёртого знака не расходится.

    `точно=True` считает по всем пикселям — для спора о четвёртом знаке.
    """
    времянка = None
    try:
        if not точно:
            времянка = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
            времянка.close()
            исход = subprocess.run(
                ["sips", "-Z", "128", "-s", "format", "png", путь,
                 "--out", времянка.name],
                capture_output=True, text=True)
            if исход.returncode != 0:
                raise ОтказЗамера(
                    f"{путь}: sips отказал — {исход.stderr.strip()}")
            цель = времянка.name
        else:
            цель = путь

        ш, в, к, пиксели = разобрать_png(цель)
        сумма = 0
        for i in range(0, len(пиксели), к):
            сумма += (0.2126 * пиксели[i]
                      + 0.7152 * пиксели[i + 1]
                      + 0.0722 * пиксели[i + 2])
        return сумма / (ш * в) / 255.0
    finally:
        if времянка:
            os.unlink(времянка.name)


def приёмка():
    """Воспроизвести три пары, у которых ответ записан заранее."""
    print("ПРИЁМКА ИНСТРУМЕНТА — три пары из журнала приёмки\n")
    всё_сошлось = True
    for имя, светлый, ож_с, тёмный, ож_т in ИЗВЕСТНЫЕ:
        пс, пт = os.path.join(ЖУРНАЛ, светлый), os.path.join(ЖУРНАЛ, тёмный)
        if not (os.path.exists(пс) and os.path.exists(пт)):
            print(f"  {имя}: КАДРА НЕТ НА ДИСКЕ — пара пропущена, "
                  f"и это отказ приёмки, а не её успех")
            всё_сошлось = False
            continue
        с, т = яркость(пс), яркость(пт)
        рс, рт = abs(с - ож_с), abs(т - ож_т)
        годно = рс < 0.005 and рт < 0.005
        всё_сошлось &= годно
        print(f"  {имя}")
        print(f"    светлая  {с:.4f}  ожидалось {ож_с:.4f}  "
              f"расхождение {рс:.4f}")
        print(f"    тёмная   {т:.4f}  ожидалось {ож_т:.4f}  "
              f"расхождение {рт:.4f}")
        print(f"    кратность {с / т:.1f}×   {'сошлось' if годно else 'НЕ СОШЛОСЬ'}\n")

    if всё_сошлось:
        print("Инструмент воспроизвёл все три пары. Числам можно верить.")
        return 0
    print("ИНСТРУМЕНТ НЕ ВОСПРОИЗВЁЛ ЗАПИСАННОЕ.\n"
          "Его числа замером не являются, пока это не починено.")
    return 1


def main(арг):
    if "--приёмка" in арг:
        return приёмка()

    точно = "--точно" in арг
    арг = [a for a in арг if a != "--точно"]

    if арг and арг[0] == "--пара":
        if len(арг) != 3:
            print("--пара хочет ровно два кадра: светлый и тёмный")
            return 2
        с, т = яркость(арг[1], точно), яркость(арг[2], точно)
        print(f"светлый  {с:.4f}  {арг[1]}")
        print(f"тёмный   {т:.4f}  {арг[2]}")
        if т == 0:
            print("кратность не считается: у тёмного ноль")
            return 1
        print(f"кратность {с / т:.1f}×")
        # Ниже двух крат пара темами не является: так различались
        # кадры, снятые на одном симуляторе и названные по-разному.
        if с / т < 2.0:
            print("\nПАРА НЕ РАЗЛИЧАЕТСЯ ПО ЯРКОСТИ.\n"
                  "\n"
                  "Частая причина — обе партии сняты на одном симуляторе,\n"
                  "а тему задал только суффикс в имени файла.\n"
                  "\n"
                  "НО НЕ ЕДИНСТВЕННАЯ, и вторая важнее. Правило «в тёмной\n"
                  "теме фон тёмный» верно, только пока экран красится\n"
                  "`Surface.screen` (`Dyn(dark: 0x050503, light: 0xFFFFFF)`).\n"
                  "У ПЛАКАТА своя пара, и в тёмной теме он СВЕТЛЫЙ:\n"
                  "макет онбординга даёт `--poster-bg` `#a2c1fe` в Dark\n"
                  "против `#1f4fff` в Light (замер по Figma 14.10).\n"
                  "На таком экране эта проверка даст ложный дефект.\n"
                  "\n"
                  "Решающий свидетель тогда один — обратное чтение\n"
                  "`simctl ui <udid> appearance` ДО съёмки. Яркость\n"
                  "перестаёт быть вторым замером и становится описанием.")
            return 1
        return 0

    if not арг:
        print(__doc__)
        return 2

    for путь in арг:
        try:
            print(f"{яркость(путь, точно):.4f}  {путь}")
        except ОтказЗамера as e:
            print(f"ОТКАЗ   {e}")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
