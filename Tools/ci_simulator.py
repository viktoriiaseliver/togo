# -*- coding: utf-8 -*-
"""Найти симулятор для прогона тестов — или завести его.

**Зачем.** В `ci.yml` назначение называлось именем устройства:
`platform=iOS Simulator,name=iPhone 17 Pro`. Имя — ловушка. Прогоны
#44 и #45 от 21.09.2026 выбрали ОДИН И ТОТ ЖЕ Xcode 26.3 (17C529):
первый прошёл за 12 минут, второй упал за полторы с

    Unable to find a device matching the provided destination specifier:
        { platform:iOS Simulator, OS:latest, name:iPhone 17 Pro }

и списком, в котором из симуляторов остались только заглушки
«Any iOS Simulator Device». То есть машина образа на машину образа
не приходится: где-то устройство зарегистрировано, где-то нет.
Красный при этом выглядел как «сломал тот, кто последним пушил».

Поэтому устройство здесь **ищется, а не называется**, а если готового
нет — заводится. Печатает UDID в stdout; всё остальное идёт в stderr,
чтобы вывод можно было подставить прямо в назначение.

    python3 Tools/ci_simulator.py                    # → UDID, общий выбор
    TOGO_SIM=<сессия> python3 Tools/ci_simulator.py  # → UDID устройства
                                                     #   «Togo-<сессия>»

Не нашлось и завести не удалось — выходим с ненулевым кодом и печатаем
ВСЁ, что видно: среды выполнения, типы устройств, сам Xcode. Молчаливое
падение здесь дороже длинного лога: именно из-за него красный CI
провисел незамеченным с обновления образа.
"""
import json
import os
import re
import subprocess
import sys


def simctl(*args):
    out = subprocess.check_output(["xcrun", "simctl", "list", *args, "--json"])
    return json.loads(out)


def версия(строка):
    """`com.apple.CoreSimulator.SimRuntime.iOS-26-2` → (26, 2)."""
    числа = re.findall(r"\d+", строка.rsplit(".", 1)[-1])
    return tuple(int(n) for n in числа)


# То же устройство, что стоит в `DESTINATION` Makefile. Совпадение
# с локальным прогоном не обязательно, но когда оно достижимо — лучше
# совпасть: разбирать расхождение «у меня зелено, в CI красно» дороже.
ЖЕЛАЕМОЕ = "iPhone 17 Pro"

# Устройство на СЕССИЮ, если её назвали.
#
# **Зачем, и это замер, а не предосторожность.** Выбор ниже
# детерминирован: ключ `(имя == ЖЕЛАЕМОЕ, версия среды, имя)`, лучший
# побеждает. Значит при одинаковом списке устройств **все сессии
# получают один и тот же UDID по построению** — не по гонке, не иногда.
# Запасной путь тоже общий: `завести()` создаёт устройство с прибитым
# именем `ci-iphone`.
#
# Прошлой смене общее устройство стоило двух отказов контроля, и оба
# напечатали `✔ passed` на тринадцати тестах из тысячи. Своё состояние
# симулятора — часть стенда, и стареет оно молча: форма базы в App Group
# от чужого прогона даёт `Cannot use staged migration` у того, кто
# ничего не менял.
#
# **Почему на сессию, а не на прогон.** У `DerivedData` в пути стоит
# PID, и это верно: каталог никто не считает. Устройство считают —
# 08.10 на машине было загружено пять одновременно, и это была
# занятость, а не мусор. Поэтому PID остаётся в `DerivedData`,
# а в имя устройства идёт только сессия: заводится однажды,
# переиспользуется.
#
# **Имя переменной латиницей, и это не стиль.** Имя переменной
# окружения живёт по обе стороны стыка «оболочка ↔ инструмент»,
# а кириллическое имя `bash` за имя не считает вовсе: `КАДР_СУФФИКС=…`
# отвечает `command not found` и следующая строка выполняется как
# ни в чём не бывало.
#
# Префикс `TEST_RUNNER_` здесь НЕ нужен и добавлять его не надо:
# он требуется переменным, которые должны доехать до процесса тестов,
# а эту читает сам скрипт, до запуска чего-либо.
#
# Пусто — поведение прежнее, ни одного отличия. CI остаётся как был:
# там одна сессия, и общий выбор для неё верен.
СЕССИЯ = os.environ.get("TOGO_SIM", "").strip()


# ПОТОЛОК СРЕДЫ. Выше него не выбираем и не заводим.
#
# **Зачем потолок, а не чёрный список.** 09.10.2026 пять прогонов трёх
# сессий умерли на iOS 27.0 — `Cannot use staged migration`, перезапуски,
# 10 тестов из 1074 со словом `passed` в строке итога. Кандидаты сняты
# замером поимённо: загрузка, форма базы в App Group, параллельность,
# 0x8BADF00D, локальная ветка, семья круга архива. Осталась среда,
# и она ПОДТВЕРЖДЕНА, а не «не различена». Почему именно 27.0 —
# не установлено и не выдумано.
#
# Чёрный список `{27.0}` был бы условием, привязанным к НАЛИЧИЮ:
# в день, когда рядом встанет 27.1, он **поменяет знак молча** —
# из запрета в разрешение, и случится это в момент успеха, когда
# никто не ждёт плохих новостей. Это наш записанный класс, и проект
# за него уже платил. Потолок держит знак до тех пор, пока кто-то
# не поднимет его ОСОЗНАННО, положив рядом замер.
#
# Поднимать — как номер сборки: рукой, с замером в соседней строке.
# Форма записи та же, потому что величина той же природы — решение,
# а не производная от того, что оказалось установлено.
ПОТОЛОК = (26, 5)

# Разовая отмена потолка — для того, кто ПРИШЁЛ мерить новую среду.
# Громко в stderr: молчаливая отмена неотличима от отсутствия потолка,
# а человек, увидевший красный прогон, должен знать, на чём он гонял.
БЕЗ_ПОТОЛКА = os.environ.get("TOGO_RUNTIME_ANY", "").strip()


def под_потолком(идентификатор_среды):
    """Среда не новее потолка. Отмена — громкая, и о ней сказано."""
    if БЕЗ_ПОТОЛКА:
        return True
    return версия(идентификатор_среды) <= ПОТОЛОК


def сказать_про_потолок():
    предел = ".".join(str(ч) for ч in ПОТОЛОК)
    if БЕЗ_ПОТОЛКА:
        print(f"TOGO_RUNTIME_ANY: потолок среды ({предел}) СНЯТ на этот "
              "запуск. На iOS 27.0 стенд отказывает — замер 09.10.2026, "
              "пять прогонов трёх сессий.", file=sys.stderr)
    return предел


def готовое_устройство():
    """Желаемый iPhone, а если его нет — самый новый ПОД ПОТОЛКОМ."""
    девайсы = simctl("devices", "available")["devices"]
    лучшее = None
    for runtime, список in девайсы.items():
        if "iOS" not in runtime or not под_потолком(runtime):
            continue
        for dev in список:
            if not dev.get("isAvailable") or "iPhone" not in dev.get("name", ""):
                continue
            ключ = (dev["name"] == ЖЕЛАЕМОЕ, версия(runtime), dev["name"])
            if лучшее is None or ключ > лучшее[0]:
                лучшее = (ключ, dev["udid"], runtime, dev["name"])
    return лучшее


def устройство_по_имени(имя):
    """UDID устройства с таким именем, если оно есть и доступно.

    Сравнение ПО ИМЕНИ ЦЕЛИКОМ, а не по началу. У нас уже оплачено:
    сторож сравнивал `hasPrefix("struct Swatch")` и находил
    `struct SwatchRow`, то есть всё время сверял другой компонент
    и молчал об этом. Здесь то же: `Togo-02` начинается так же,
    как `Togo-02-проба`.
    """
    for runtime, список in simctl("devices", "available")["devices"].items():
        if "iOS" not in runtime:
            continue
        for dev in список:
            if dev.get("isAvailable") and dev.get("name") == имя:
                return dev["udid"], runtime
    return None


def новейшая_среда_и_типы():
    """Самая новая среда iOS ПОД ПОТОЛКОМ и типы iPhone, от новых к старым.

    Вынесено из `завести()`, чтобы у заведения устройства была ОДНА
    реализация, а не две. Два разбора одного правила расходятся молча —
    у Togo так жили три реализации «не кормить», и две из трёх
    молчали.

    **Потолок стоит здесь, а не только в общем выборе, и это предмет
    правки 14.10.2026.** Именная ветка (`TOGO_SIM=<сессия>`) заводила
    устройство через эту функцию, то есть на НОВЕЙШЕЙ среде — ровно
    на 27.0, где стенд отказывает. Общий выбор при этом был здоров
    случайно: `ЖЕЛАЕМОЕ` стоит у него первым разрядом ключа, и пока
    `iPhone 17 Pro` существует только на 26.5, версия не решает ничего.
    То есть **сломано было у того, кто послушался совета завести своё
    устройство**, а совет этот раздавал `CLAUDE.md` проекта. Два прогона
    потеряны на этом.
    """
    среды = [r for r in simctl("runtimes")["runtimes"]
             if r.get("isAvailable") and "iOS" in r.get("name", "")
             and под_потолком(r["identifier"])]
    if not среды:
        return None, []
    среда = max(среды, key=lambda r: версия(r["identifier"]))

    типы = [t for t in simctl("devicetypes")["devicetypes"]
            if "iPhone" in t.get("name", "")]

    # Сортировка по ИМЕНИ ставила «iPhone Xʀ» выше «iPhone 17 Pro», потому
    # что лексикографически «X» больше «1»: запасной путь заводил старое
    # устройство, а кадры приёмки сняты на 17 Pro. Сортируем по числу
    # в имени, а слова — на своих местах.
    #
    # **ЖЕЛАЕМОЕ идёт первым ключом, и это поймал прогон, а не чтение.**
    # Первая редакция сортировала только по числу — и завела сессии
    # `iPhone 18 Pro Max` вместо `iPhone 17 Pro`, то есть **другую
    # модель, чем та, на которой сняты кадры приёмки**. Файл сам
    # называет это выше: «когда совпадение достижимо — лучше совпасть».
    # Разбирать «у меня кадр другой» дороже, чем взять желаемый тип,
    # пока он есть.
    def новизна(t):
        цифры = [int(ч) for ч in re.findall(r"\d+", t["name"])]
        return (t["name"] == ЖЕЛАЕМОЕ, max(цифры) if цифры else 0, t["name"])

    return среда, sorted(типы, key=новизна, reverse=True)


def завести_с_именем(имя):
    """Создать устройство с заданным именем. Возвращает UDID или None."""
    среда, типы = новейшая_среда_и_типы()
    if среда is None:
        return None
    for тип in типы:
        try:
            udid = subprocess.check_output(
                ["xcrun", "simctl", "create", имя,
                 тип["identifier"], среда["identifier"]],
                stderr=subprocess.DEVNULL).decode().strip()
        except subprocess.CalledProcessError:
            continue
        return udid, среда["name"], тип["name"]
    return None


def завести():
    """Готовых нет — собрать свой из самой новой доступной среды.

    Имя `ci-iphone` прибито нарочно и остаётся прибитым: это путь
    для CI, где сессия одна. Фильтр по `supportedDeviceTypes` был
    мёртвым (`… or True` истинно всегда) и снят; создание само скажет,
    подходит тип или нет.
    """
    return завести_с_именем("ci-iphone")


def сдаться():
    print("Симулятора для прогона нет, и завести не вышло.", file=sys.stderr)
    # Причину называем САМИ. Список сред ниже печатается полностью,
    # и человек, увидев в нём живую 27.0, прочтёт отказ как поломку
    # инструмента: среда-то есть. Отказ, не называющий своей причины,
    # сообщает только сторону, которая отказала.
    if not БЕЗ_ПОТОЛКА:
        предел = ".".join(str(ч) for ч in ПОТОЛОК)
        print(f"\nПОТОЛОК СРЕДЫ — {предел}. Среды новее него не берутся "
              "и не заводятся нарочно: на iOS 27.0 стенд отказывает "
              "(замер 09.10.2026). Если в списке ниже есть только они — "
              "дело в потолке, а не в отсутствии симулятора.\n"
              "  Поставить 26.5: Xcode → Settings → Components.\n"
              "  Мерить новую среду нарочно: TOGO_RUNTIME_ANY=1",
              file=sys.stderr)
    for заголовок, args in (("Среды выполнения", ["runtimes"]),
                            ("Типы устройств", ["devicetypes"]),
                            ("Устройства", ["devices", "available"])):
        print(f"\n── {заголовок}", file=sys.stderr)
        subprocess.run(["xcrun", "simctl", "list", *args], stderr=sys.stderr)
    subprocess.run(["xcodebuild", "-version"], stderr=sys.stderr)
    sys.exit(1)


# Назвали сессию — устройство только её, и общий выбор ниже
# не исполняется вовсе. Так, а не «попробовать своё, иначе общее»:
# откат на общее устройство молча вернул бы ровно тот дефект, от
# которого эта ветка заводится, и отличить его было бы нечем — UDID
# в логе выглядит одинаково в обоих случаях.
ПРЕДЕЛ = сказать_про_потолок()

if СЕССИЯ:
    имя_устройства = f"Togo-{СЕССИЯ}"
    своё = устройство_по_имени(имя_устройства)
    if своё:
        udid, runtime = своё
        # Готовое устройство тоже меряется потолком, а не только новое.
        # Устройство переживает правку этого файла: заведённое вчера
        # на 27.0 будет переиспользовано сегодня, и UDID в логе
        # от здорового не отличить ничем. Отказ здесь дешевле прогона:
        # на 27.0 он умирает на десятом тесте из тысячи и печатает
        # при этом слово `passed`.
        if not под_потолком(runtime):
            print(f"Устройство сессии «{имя_устройства}» заведено на "
                  f"{runtime} — новее потолка {ПРЕДЕЛ}. Стенд на 27.0 "
                  "отказывает (замер 09.10.2026, пять прогонов трёх "
                  "сессий), и прогон будет потерян.\n"
                  f"  Лечится пересозданием: xcrun simctl delete "
                  f"'{имя_устройства}' и повторный запуск — заведётся "
                  "под потолком.\n"
                  "  Мерить новую среду нарочно: TOGO_RUNTIME_ANY=1",
                  file=sys.stderr)
            sys.exit(1)
        print(f"Устройство сессии: {имя_устройства} · {runtime}", file=sys.stderr)
        print(udid)
        sys.exit(0)

    создано = завести_с_именем(имя_устройства)
    if создано:
        udid, среда, тип = создано
        print(f"Завёл устройство сессии: {имя_устройства} · {тип} · {среда}",
              file=sys.stderr)
        print(udid)
        sys.exit(0)

    # Отказ громкий и БЕЗ подмены общим устройством. Молчаливый откат
    # здесь дал бы прогон на чужом симуляторе под видом своего —
    # и прошлой смене это стоило двух отказов контроля, напечатавших
    # `✔ passed` на тринадцати тестах из тысячи.
    print(f"TOGO_SIM={СЕССИЯ}: устройства «{имя_устройства}» нет "
          "и завести не вышло. Общее устройство НЕ подставляю нарочно: "
          "прогон на чужом симуляторе от своего в логе не отличить.",
          file=sys.stderr)
    сдаться()

готовое = готовое_устройство()
if готовое:
    _, udid, runtime, имя = готовое
    print(f"Беру готовый: {имя} · {runtime}", file=sys.stderr)
    print(udid)
    sys.exit(0)

создано = завести()
if создано:
    udid, среда, тип = создано
    print(f"Готовых не было, завёл: {тип} · {среда}", file=sys.stderr)
    print(udid)
    sys.exit(0)

сдаться()
