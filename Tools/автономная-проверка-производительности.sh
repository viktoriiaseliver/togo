build_cache() {   # $1 — файл с чистой частью, $2 — куда собрать
    { printf 'import Foundation\nimport CoreGraphics\n'; cat "$1"; cat "$WORK/cache-main.swift"; } > "$2"
}

build_cache "$WORK/cache-pure.swift" "$WORK/cache-live.swift"
run_swift "$WORK/cache-live.swift" "$WORK/cache-live.log"
RC="$(cat "$WORK/cache-live.log.rc")"
if [ "$RC" = "0" ]; then
    ok "живой текст: $(grep -a 'ПРОВЕРОК' "$WORK/cache-live.log")"
    grep -a "^ЗАМЕР" "$WORK/cache-live.log" | sed 's/^/          /'
else
    bad "живой текст КРАСНЫЙ (rc=$RC)"
    grep -a "ПРОВАЛ\|error:" "$WORK/cache-live.log" | head -20 | sed 's/^/          /'
fi

# ПОДДЕЛКА А: возвращаем прежнее поведение — переполнение вытирает полку
# целиком (`removeAll` в прежней редакции `КэшСнимков`).
sed 's|while ключи.count > предел { выбыли.append(ключи.removeFirst()) }|if ключи.count > предел { выбыли = ключи.filter { $0 != ключ }; ключи = [ключ] }|' \
    "$WORK/cache-pure.swift" > "$WORK/cache-fake-a.swift"
if ! diff -q "$WORK/cache-pure.swift" "$WORK/cache-fake-a.swift" > /dev/null; then
    ok "КОНТРОЛЬ 1а: подделка А применилась (строка вытеснения подменена)"
else
    bad "КОНТРОЛЬ 1а: подделка А НЕ применилась — красное ниже было бы про sed, а не про тест"
fi
build_cache "$WORK/cache-fake-a.swift" "$WORK/cache-fake-a-run.swift"
run_swift "$WORK/cache-fake-a-run.swift" "$WORK/cache-fake-a.log"
RC="$(cat "$WORK/cache-fake-a.log.rc")"
if [ "$RC" != "0" ]; then
    ok "ПОДДЕЛКА А (старое removeAll) КРАСНАЯ, rc=$RC — $(grep -ac 'ПРОВАЛ' "$WORK/cache-fake-a.log") провалов"
    grep -a "^ПРОВАЛ" "$WORK/cache-fake-a.log" | head -4 | sed 's/^/          /'
    grep -a "^ЗАМЕР" "$WORK/cache-fake-a.log" | sed 's/^/          /'
else
    bad "ПОДДЕЛКА А прошла зелёной — набор не ловит прежнее поведение"
fi

# ПОДДЕЛКА Б: вытесняем САМОГО СВЕЖЕГО вместо самого давнего. Другая
# ось, чем у А: А ломает ЧИСЛО вытесненных, Б — их ПОРЯДОК.
sed 's|ключи.removeFirst()|ключи.removeLast()|' "$WORK/cache-pure.swift" > "$WORK/cache-fake-b.swift"
if ! diff -q "$WORK/cache-pure.swift" "$WORK/cache-fake-b.swift" > /dev/null; then
    ok "КОНТРОЛЬ 1б: подделка Б применилась (порядок вытеснения перевёрнут)"
else
    bad "КОНТРОЛЬ 1б: подделка Б НЕ применилась"
fi
build_cache "$WORK/cache-fake-b.swift" "$WORK/cache-fake-b-run.swift"
run_swift "$WORK/cache-fake-b-run.swift" "$WORK/cache-fake-b.log"
RC="$(cat "$WORK/cache-fake-b.log.rc")"
if [ "$RC" != "0" ]; then
    ok "ПОДДЕЛКА Б (вытесняет свежего) КРАСНАЯ, rc=$RC — $(grep -ac 'ПРОВАЛ' "$WORK/cache-fake-b.log") провалов"
else
    bad "ПОДДЕЛКА Б прошла зелёной — набор не различает порядок давности"
fi

# ---------------------------------------------------------------------
# 2. Правовые документы: identity раздела по содержимому, не по UUID
# ---------------------------------------------------------------------
say ""
say "=== ПРЕДМЕТ 2: LegalDocument.Section — устойчивая identity"

LEGAL_SRC="$ROOT/Togo/Features/Settings/LegalScreens.swift"
extract "$LEGAL_SRC" "РАЗДЕЛ-НАЧАЛО" "РАЗДЕЛ-КОНЕЦ" > "$WORK/legal-pure.swift"
