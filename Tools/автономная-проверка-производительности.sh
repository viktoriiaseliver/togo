          "получено \(пустой)")

// --- ключ различает сторону --------------------------------------
let байты = Data([1, 2, 3, 4, 5])
проверить("ключ.сторона-различает",
          КлючМиниатюры(байты: байты, сторона: 800) != КлючМиниатюры(байты: байты, сторона: 400))
проверить("ключ.те-же-байты-та-же-сторона",
          КлючМиниатюры(байты: байты, сторона: 800) == КлючМиниатюры(байты: байты, сторона: 800))

// --- ЗАМЕР: сколько раскладок стоит прокрутка ---------------------
// Модель `LazyVGrid`: на экране ОКНО плиток, шаг прокрутки — один ряд.
// Каждое касание ключа, которого нет на полке, это декодирование JPEG
// на главном потоке.
func раскладок(предел: Int, снимков: Int, окно: Int, шаг: Int) -> Int {
    var полка = ПорядокДавности<Int>(предел: предел)
    var счёт = 0
    var верх = 0
    while верх + окно <= снимков {
        for k in верх..<(верх + окно) {
            if !полка.содержит(k) { счёт += 1 }
            полка.тронут(k)
        }
        верх += шаг
    }
    return счёт
}
// Сметка на месте: семь плиток помещаются на экран целиком, кадры
// идут один за другим (на прогулке `now` тикает раз в секунду).
func раскладокНаМесте(предел: Int, снимков: Int, кадров: Int) -> Int {
    var полка = ПорядокДавности<Int>(предел: предел)
    var счёт = 0
    for _ in 1...кадров {
        for k in 1...снимков {
            if !полка.содержит(k) { счёт += 1 }
            полка.тронут(k)
        }
    }
    return счёт
}
print("ЗАМЕР окно9-шаг3-снимков30 предел6=\(раскладок(предел: 6, снимков: 30, окно: 9, шаг: 3)) предел18=\(раскладок(предел: 18, снимков: 30, окно: 9, шаг: 3))")
print("ЗАМЕР наместе-7-снимков-10-кадров предел6=\(раскладокНаМесте(предел: 6, снимков: 7, кадров: 10)) предел18=\(раскладокНаМесте(предел: 18, снимков: 7, кадров: 10))")

print("ПРОВЕРОК \(проверок) ПРОВАЛОВ \(провалов)")
exit(провалов == 0 ? 0 : 1)
