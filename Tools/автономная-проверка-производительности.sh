let послеОсвежения = о.тронут(4)
проверить("освежение.выбыл-второй", послеОсвежения == [2],
          "выбыло=\(послеОсвежения) порядок=\(о.отДавнегоКСвежему)")

// --- повтор не растит глубину ------------------------------------
var п = ПорядокДавности<Int>(предел: 3)
var вытесненийНаПовторах = 0
for _ in 1...5 { вытесненийНаПовторах += п.тронут(42).count }
проверить("повтор.глубина-один", п.глубина == 1 && вытесненийНаПовторах == 0,
          "глубина=\(п.глубина) вытеснений=\(вытесненийНаПовторах)")

// --- предел выпрямляется -----------------------------------------
проверить("предел.ноль-становится-единицей", ПорядокДавности<Int>(предел: 0).предел == 1)
проверить("предел.минус-становится-единицей", ПорядокДавности<Int>(предел: -5).предел == 1)

// --- размер миниатюры --------------------------------------------
func почти(_ a: CGFloat, _ b: CGFloat) -> Bool { abs(a - b) < 0.5 }
