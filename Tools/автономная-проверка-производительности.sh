#!/bin/bash
# Автономная приёмка трёх починок производительности от 05.11.2026.
# Прогона схемы для неё не нужно: чистая часть правленых файлов режется
# ТЕКСТОМ по маркерам и запускается `swift` как скрипт.
#
# ПОЧЕМУ ТЕКСТОМ, А НЕ КОПИЕЙ. Копия логики разошлась бы с предметом
# молча, и приёмка начала бы отчитываться о собственном прошлом. Здесь
# источник один — сам правленый файл; если маркеры из него уйдут,
# извлечение даст пустоту, и это КРАСНОЕ, а не зелёное (контроль 0).
#
# ПОРЯДОК. Контроли идут ПЕРВЫМИ и отдельными заходами:
#   контроль 0  инструмент отвечает: `swift` собирает здоровый файл
#               И ВАЛИТ битый. Без второй половины зелёное ниже
#               не значит ничего.
#   контроль 1  извлечение что-то нашло, и в нём есть решающие слова.
#   предмет     живой текст обязан быть ЗЕЛЁНЫМ.
#   подделка    текст с возвращённым старым поведением обязан быть
#               КРАСНЫМ. Тест, не краснеющий на старом коде,
#               не доказывает ничего.
#
# Имена переменных латиницей НАРОЧНО: в bash кириллица в имени даёт
# «not a valid identifier» при rc=0 — разбор в ~/Projects/CLAUDE.md.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${TMPDIR:-/tmp}/togo-perf-$$"
mkdir -p "$WORK"
FAILED=0
PASSED=0

say() { printf '%s\n' "$*"; }
ok()   { PASSED=$((PASSED + 1)); say "  ЗЕЛЕНО  $*"; }
bad()  { FAILED=$((FAILED + 1)); say "  КРАСНО  $*"; }

# Запустить файл, положить вывод и код возврата. Код возврата пишется
# ОТДЕЛЬНОЙ командой: через конвейер он приезжает от последнего звена.
run_swift() {
    swift "$1" > "$2" 2>&1
    printf '%s' "$?" > "$2.rc"
}

extract() {
    awk -v a="$2" -v b="$3" 'index($0, a) { f = 1; next } index($0, b) { f = 0 } f' "$1"
}

say "=== КОНТРОЛЬ 0: отвечает ли сам инструмент"

printf 'print("живой")\n' > "$WORK/control-ok.swift"
run_swift "$WORK/control-ok.swift" "$WORK/control-ok.log"
RC="$(cat "$WORK/control-ok.log.rc")"
if [ "$RC" = "0" ] && grep -aq "живой" "$WORK/control-ok.log"; then
    ok "swift собирает и выполняет здоровый файл (rc=$RC)"
else
    bad "swift не выполнил здоровый файл (rc=$RC) — дальше мерить нечем"
    cat "$WORK/control-ok.log"
    exit 1
fi

printf 'let x: Int = "строка"\n' > "$WORK/control-bad.swift"
run_swift "$WORK/control-bad.swift" "$WORK/control-bad.log"
RC="$(cat "$WORK/control-bad.log.rc")"
if [ "$RC" != "0" ]; then
    ok "swift ВАЛИТ битый файл (rc=$RC) — красное отличимо от зелёного"
else
    bad "битый файл прошёл с rc=0 — зелёное ниже ничего не значит"
    exit 1
fi

# ---------------------------------------------------------------------
# 1. Кэш снимков: вытеснение по давности вместо removeAll
# ---------------------------------------------------------------------
say ""
say "=== ПРЕДМЕТ 1: КэшСнимков — вытеснение и размер миниатюры"

CACHE_SRC="$ROOT/Togo/DesignSystem/КэшСнимков.swift"
extract "$CACHE_SRC" "ЧИСТАЯ-ЧАСТЬ-НАЧАЛО" "ЧИСТАЯ-ЧАСТЬ-КОНЕЦ" > "$WORK/cache-pure.swift"

LINES="$(grep -ac "" "$WORK/cache-pure.swift")"
HAS_TYPE="$(grep -ac "struct ПорядокДавности" "$WORK/cache-pure.swift")"
HAS_EVICT="$(grep -ac "while ключи.count > предел" "$WORK/cache-pure.swift")"
if [ "$LINES" -gt 20 ] && [ "$HAS_TYPE" = "1" ] && [ "$HAS_EVICT" = "1" ]; then
    ok "КОНТРОЛЬ 1: извлечено $LINES строк, тип и строка вытеснения на месте"
else
    bad "КОНТРОЛЬ 1: извлечено $LINES строк, тип=$HAS_TYPE вытеснение=$HAS_EVICT — ПРОВЕРЯТЬ БЫЛО НЕЧЕГО"
    exit 1
fi

cat > "$WORK/cache-main.swift" <<'SWIFT'
// Приёмка чистой части. Тест, а не копия логики: предмет приехал
// текстом из правленого файла и лежит выше этой строки.
var провалов = 0
var проверок = 0
func проверить(_ имя: String, _ условие: Bool, _ факт: String = "") {
    проверок += 1
    if условие { return }
    провалов += 1
    print("ПРОВАЛ \(имя) \(факт)")
}

// --- контроль набора: ему было что проверять ---------------------
var д = ПорядокДавности<Int>(предел: 6)
var вытесненийВсего = 0
var попаданийВсего = 0
for k in 1...6 { вытесненийВсего += д.тронут(k).count }
проверить("контроль.шесть-влезли-без-вытеснения", вытесненийВсего == 0 && д.глубина == 6,
          "вытеснений=\(вытесненийВсего) глубина=\(д.глубина)")
if д.содержит(1) { попаданийВсего += 1 }
проверить("контроль.попадание-есть", попаданийВсего == 1, "попаданий=\(попаданийВсего)")

// --- предмет: седьмой ключ выгоняет ОДНОГО, самого давнего -------
let выбыли = д.тронут(7)
проверить("седьмой.выбыл-ровно-один", выбыли.count == 1, "выбыло=\(выбыли.count) \(выбыли)")
проверить("седьмой.выбыл-самый-давний", выбыли.first == 1, "выбыл=\(String(describing: выбыли.first))")
проверить("седьмой.полка-полна", д.глубина == 6, "глубина=\(д.глубина)")
for k in 2...7 {
    проверить("седьмой.остался-\(k)", д.содержит(k), "ключа \(k) нет")
}

// --- освежение: чтение переводит ключ в свежие -------------------
var о = ПорядокДавности<Int>(предел: 3)
о.тронут(1); о.тронут(2); о.тронут(3)
