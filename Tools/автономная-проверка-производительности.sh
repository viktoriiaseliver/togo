cat > "$WORK/legal-main.swift" <<'SWIFT'
var провалов = 0
var проверок = 0
func проверить(_ имя: String, _ условие: Bool, _ факт: String = "") {
    проверок += 1
    if условие { return }
    провалов += 1
    print("ПРОВАЛ \(имя) \(факт)")
}

// Контроль НАБОРА первым: два РАЗНЫХ ключа обязаны дать разные id.
// Без него «все id равны» прошло бы как устойчивость, и подделка,
// возвращающая UUID, осталась бы зелёной по другой причине.
let а = Section(title: "Что хранится", body: ["раз", "два"]).ключ("storage")
let б = Section(title: "Что хранится", body: ["раз", "два"]).ключ("rights")
проверить("контроль.разные-ключи-разные-id", а.id != б.id, "\(а.id) == \(б.id)")

// Предмет: тот же раздел, пересобранный заново, сохраняет identity.
// Именно это делал `body` вызывающего на каждой перерисовке.
let первый = Section(title: "Что хранится", body: ["раз", "два"]).ключ("storage")
let второй = Section(title: "Что хранится", body: ["раз", "два"]).ключ("storage")
проверить("пересборка.id-тот-же", первый.id == второй.id, "\(первый.id) != \(второй.id)")

// Десять перерисовок подряд — ни одного нового id.
var собранные = Set<String>()
for _ in 1...10 {
    собранные.insert(Section(title: "Что хранится", body: ["раз"]).ключ("storage").id)
}
проверить("десять-перерисовок.один-id", собранные.count == 1, "разных id: \(собранные.count)")

проверить("id.не-пустой", !первый.id.isEmpty)

// Раздел без ключа ОСТАЁТСЯ ПУСТЫМ, и это факт, а не пожелание:
// на нём стоит сторож `ключиНепустыеИРазные` в TogoTests.
проверить("без-ключа.id-пустой", Section(title: "Х", body: ["у"]).id.isEmpty,
          "пустой id ожидался, получено \(Section(title: "Х", body: ["у"]).id)")

print("ПРОВЕРОК \(проверок) ПРОВАЛОВ \(провалов)")
exit(провалов == 0 ? 0 : 1)
