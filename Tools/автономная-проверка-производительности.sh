# ---------------------------------------------------------------------
# 3. Цепочка «код → сайт»: тот же разбор, что у Tools/build_site.py
# ---------------------------------------------------------------------
say ""
say "=== ПРЕДМЕТ 3: LegalScreens.swift читается сборщиком сайта"

# Почему это здесь. Текст политики и условий живёт ТОЛЬКО в этом файле
# (`build_site.py:10`), и сборщик достаёт его РЕГУЛЯРКОЙ. Правка формы
# литерала ломает сайт, не ломая приложение, — и ломает молча: пустой
# разбор выходит пустой страницей условий, а промах `field("title")`
# ставит заголовком раздел. Второе я поймал на себе 05.11.2026, переставив
# массив разделов выше `body`.
python3 - "$LEGAL_SRC" <<'PY' > "$WORK/site.log" 2>&1
import io, re, sys

ЭКРАНЫ = ["PrivacyPolicyScreen", "TermsScreen", "MedicalDisclaimerScreen",
          "AcknowledgementsScreen"]
source = io.open(sys.argv[1], encoding="utf-8").read()
беда = 0
всего = 0
for экран in ЭКРАНЫ:
    start = source.find("struct %s" % экран)
    if start < 0:
        print("НЕТ ЭКРАНА %s" % экран); беда += 1; continue
    end = source.find("\nstruct ", start + 1)
    block = source[start:end if end > 0 else len(source)]

    def field(name):
        m = re.search(r'%s: "((?:[^"\\]|\\.)*)"' % name, block)
        return m.group(1) if m else None

    sections = [(m.group(1), re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2)))
                for m in re.finditer(
                    r'\.init\(title: "((?:[^"\\]|\\.)*)", body: \[(.*?)\]\)', block, re.S)]
    заголовок = field("title")
    if not sections:
        print("%s: НИ ОДНОГО РАЗДЕЛА — поменялась форма литерала" % экран); беда += 1; continue
    if not заголовок:
        print("%s: нет заголовка документа" % экран); беда += 1; continue
    # Решающая проверка, и она ПРАВИЛО, а не список: заголовок документа
    # не может совпадать с заголовком своего раздела. Совпал — значит
    # `field("title")` нашёл первым раздел, то есть разделы встали выше
    # `body`, и на сайт уехало не то.
    if заголовок in [т for т, _ in sections]:
        print("%s: ЗАГОЛОВОК ДОКУМЕНТА РАВЕН ЗАГОЛОВКУ РАЗДЕЛА (%r) — "
              "разбор нашёл раздел раньше документа" % (экран, заголовок))
        беда += 1
        continue
    if not field("updated"):
        print("%s: нет даты обновления" % экран); беда += 1; continue
    пустых = [т for т, п in sections if not п]
    if пустых:
        print("%s: разделы без текста: %s" % (экран, пустых)); беда += 1; continue
    всего += len(sections)
    print("%s: %d разделов, заголовок %r" % (экран, len(sections), заголовок))

print("РАЗДЕЛОВ ВСЕГО %d, БЕД %d" % (всего, беда))
# Контроль «было что проверять»: меньше десяти разделов на четыре
# документа значит, что разбор не состоялся, а не что документы короткие.
if всего < 10:
    print("разобрано всего %d разделов — РАЗБОР НЕ СОСТОЯЛСЯ" % всего)
    беда += 1
sys.exit(1 if беда else 0)
