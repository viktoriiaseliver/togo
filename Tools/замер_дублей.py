#!/usr/bin/env python3
"""Сколько в живом дневнике дублей и какие из них настоящие.

Зачем файлом, а не командой в истории: 07.10.2026 это число трижды
назвали разным — 202, 41, 43, — и каждый раз спор шёл о числе, а не
о способе. Способ и есть содержание замера.

Три вещи, которые этот скрипт обязан печатать, потому что без них
число читается не тем, чем является:

1. **Ключ группировки.** «202 дубля» вышли из группировки по полю
   со значением по умолчанию: 161 из них — пустые заметки, одинаковые
   друг другу. Ключ печатается целиком, до чисел.
2. **Единицу измерения против порога.** В выгрузке дневника время
   МИНУТНОЕ, а окно сторожа — 10 и 90 секунд. Замер в единицах грубее
   порога не подтверждает и не опровергает его ни в какую сторону,
   и счёт по минуте завышает. Секунды есть только в журнале действий.
3. **Чего он не считал.** Последней строкой, иначе ноль прочтут
   как «чисто».

Запуск: python3 Tools/замер_дублей.py
"""

from __future__ import annotations

import collections
import csv
import datetime as dt
import json
import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ВЫГРУЗКА = КОРЕНЬ / ".данные-вне-git" / "дневник-выгрузка-2026-10-07.csv"
ЖУРНАЛ = КОРЕНЬ / "docs" / "журнал-устройства" / "usage-2026-10-07.jsonl"

# Виды под сторожем и окно каждого — зеркало `DuplicateGuard`.
# Расхождение этой таблицы с кодом ловит `DuplicateGuardTests`,
# а не этот скрипт: он про данные, не про код.
ОКНО = {"Выход": 10, "Еда": 90, "Прогулка": 90, "Уход": 90, "Доза": 90, "Взвешивание": 90}

# Журнал действий в UTC, дневник — в местном времени (Ницца).
# Первый проход искал местное время в UTC-строках, нашёл ноль записей
# и прочитался бы как «журнала нет».
СДВИГ_ЧАСОВ = 2


def состояние_дерева() -> str:
    """Коммит замера и крик, если в дереве есть незакоммиченное.

    Отчёт без состояния — это утверждение о файле, которого больше нет.
    """
    def git(*args: str) -> str:
        return subprocess.run(["git", "--no-optional-locks", *args],
                              cwd=КОРЕНЬ, capture_output=True, text=True).stdout.strip()

    коммит = git("log", "-1", "--format=%h %s") or "коммита нет"
    грязь = git("status", "--short")
    строки = [f"коммит замера: {коммит}"]
    if грязь:
        строки.append("!!! В ДЕРЕВЕ НЕЗАКОММИЧЕННЫЕ ПРАВКИ — числа ниже про диск, не про коммит:")
        строки += [f"    {s}" for s in грязь.splitlines()]
    return "\n".join(строки)


def различитель(строка: dict[str, str]) -> str:
    """«Это правда одно и то же дело?» — зеркало `refersToSameThing`.

    Уход различается делом, доза — лекарством (оба лежат в заметке
    выгрузки). Выход различается РЕЗУЛЬТАТОМ: «собака попросилась»
    и «собака пописала» — две записи об одном выходе, и обе настоящие.
    """
    тип = строка["тип"]
    if тип in ("Уход", "Доза"):
        return строка["заметка"]
    if тип == "Выход":
        return строка["результат"]
    return ""


def читать_выгрузку() -> list[dict[str, str]]:
    with ВЫГРУЗКА.open(encoding="utf-8") as ф:
        строки = list(csv.DictReader(ф, delimiter=";"))
    # Запись прогрева схемы CloudKit — не человеческая, в счёт не идёт.
    return [с for с in строки if с["автор"] != "ПРОГРЕВ СХЕМЫ"]


def счёт_по_выгрузке(строки: list[dict[str, str]]) -> dict[str, list[int]]:
    группы: dict[tuple, list[dict]] = collections.defaultdict(list)
    for с in строки:
        группы[(с["дата"], с["время"], с["тип"], различитель(с))].append(с)

    # [всего лишних, до 23.09, с 23.09]
    итог: dict[str, list[int]] = collections.defaultdict(lambda: [0, 0, 0])
    for (дата, _время, тип, _р), группа in группы.items():
        if len(группа) < 2:
            continue
        лишних = len(группа) - 1
        итог[тип][0] += лишних
        итог[тип][1 if дата <= "2026-09-22" else 2] += лишних
    return итог


def читать_журнал() -> list[dict]:
    записи = []
    with ЖУРНАЛ.open(encoding="utf-8") as ф:
        for строка in ф:
            строка = строка.strip()
            if строка:
                записи.append(json.loads(строка))
    return записи


def интервалы_отметок(записи: list[dict]) -> list[tuple[str, list[int]]]:
    """Секунды между соседними отметками мочи внутри одной прогулки.

    Это единственный источник, отвечающий на вопрос сторожа: у него
    есть секунды. Отметки группируются по сессии приложения и разрыву
    больше получаса — то есть по прогулке, а не по дню.
    """
    отметки = sorted(
        (r for r in записи if r["action"] == "mark" and r.get("detail") == "urine"),
        key=lambda r: (r["session"], r["at"]),
    )
    прогулки: list[tuple[str, list[dt.datetime]]] = []
    for r in отметки:
        когда = dt.datetime.strptime(r["at"], "%Y-%m-%dT%H:%M:%SZ")
        если_новая = (
            not прогулки
            or прогулки[-1][0] != r["session"]
            or (когда - прогулки[-1][1][-1]).total_seconds() > 1800
        )
        if если_новая:
            прогулки.append((r["session"], [когда]))
        else:
            прогулки[-1][1].append(когда)

    ответ = []
    for сессия, времена in прогулки:
        if len(времена) < 2:
            continue
        местное = времена[0] + dt.timedelta(hours=СДВИГ_ЧАСОВ)
        разрывы = [int((б - а).total_seconds()) for а, б in zip(времена, времена[1:])]
        ответ.append((f"{местное:%Y-%m-%d %H:%M} местн · сессия {сессия}", разрывы))
    return ответ


def артефакты_журнала(записи: list[dict]) -> list[str]:
    """Что в журнале сказано про журнал, а не про мир."""
    ключ = lambda r: (r["session"], r["action"], r.get("detail"), r["at"],
                      r["outcome"], r["screen"])  # noqa: E731
    счёт = collections.Counter(ключ(r) for r in записи)
    лишних = len(записи) - len(счёт)
    пойманные = {ключ(r) for r in записи if r["outcome"] == "duplicate"}
    строк_про_пойманные = sum(счёт[к] for к in пойманные)
    return [
        f"журнал продублировал сам себя: {лишних} строк из {len(записи)} — "
        "это про запись лога, а не про дневник",
        f"outcome=duplicate: {строк_про_пойманные} строк, но событий за ними "
        f"{len(пойманные)} — счёт строк завысил бы пойманное в "
        f"{строк_про_пойманные // max(1, len(пойманные))} раза",
    ]


def главное() -> int:
    for файл in (ВЫГРУЗКА, ЖУРНАЛ):
        if not файл.exists():
            print(f"нет файла: {файл}", file=sys.stderr)
            print("Выгрузка дневника лежит вне git намеренно — это личные "
                  "данные. Снять заново: экспорт из приложения.", file=sys.stderr)
            return 2

    print(состояние_дерева())
    print()
    print("КЛЮЧ ГРУППИРОВКИ = (дата, время, тип, различитель)")
    print("  различитель: Уход → дело · Доза → лекарство · Выход → результат · прочее → пусто")
    print("  пустое поле в ключ входит ТОЛЬКО там, где оно и есть различитель:")
    print("  группировка по полю со значением по умолчанию собирает в одну группу всё,")
    print("  что его не заполнило, — так 161 пустая заметка стала «161 дублем».")
    print()

    строки = читать_выгрузку()
    итог = счёт_по_выгрузке(строки)
    print(f"ВЫГРУЗКА ({len(строки)} записей, время МИНУТНОЕ):")
    print(f"  {'тип':14} {'окно':>5} {'лишних':>7} {'≤22.09':>7} {'с 23.09':>8}")
    for тип in sorted(итог, key=lambda т: -итог[т][0]):
        всего, рано, поздно = итог[тип]
        окно = ОКНО.get(тип)
        print(f"  {тип:14} {str(окно) + 'с' if окно else '—':>5} "
              f"{всего:7d} {рано:7d} {поздно:8d}")
    под = sum(v[0] for т, v in итог.items() if т in ОКНО)
    print(f"  под сторожем {под} · вне сторожа {sum(v[0] for v in итог.values()) - под}")
    print()
    print("  ВАЖНО: минута грубее любого окна сторожа (10с и 90с).")
    print("  Эти числа — верхняя граница, а не счёт дублей. Вопрос сторожа")
    print("  они не решают ни в какую сторону.")
    print()

    записи = читать_журнал()
    print(f"ЖУРНАЛ ДЕЙСТВИЙ ({len(записи)} записей, СЕКУНДЫ, UTC → местное +{СДВИГ_ЧАСОВ}ч):")
    print("  интервалы между отметками «пописал» внутри одной прогулки —")
    print("  единственный замер, у которого единица мельче окна:")
    for подпись, разрывы in интервалы_отметок(записи):
        метки = " · ".join(
            f"{с}с{'  ← ДУБЛЬ' if с < ОКНО['Выход'] else ''}" for с in разрывы)
        print(f"    {подпись}: {метки}")
    print()

    print("АРТЕФАКТЫ ИНСТРУМЕНТОВ (не находки):")
    for строка in артефакты_журнала(записи):
        print(f"  · {строка}")
    print(f"  · 161 «дубль» заметок — пустые записи, до 48 копий в одну минуту")
    print()

    print("ЧЕГО ЭТОТ ЗАМЕР НЕ СЧИТАЛ:")
    print("  · дубли, приехавшие с другого телефона через CloudKit. Сторож")
    print("    локальный и чужую запись до слияния не видит. Проверить нечем:")
    print("    приватную базу консоль открывает правами владельца данных,")
    print("    не разработчика. Записано неизмеримым, а не «похоже на».")
    print("  · «Уход · Зубы» 2026-10-06 23:59 ×2 — журнал этот момент")
    print("    не покрывает (12 записей за весь день), объяснения НЕТ.")
    print("  · дубли вне двух этих файлов: что не выгружено, то не посчитано.")
    print("  · правда ли отметка на 36 секундах настоящая. Замер говорит, что")
    print("    она НЕ похожа на тап; что собака правда пописала — не говорит")
    print("    никто, кроме человека, который там был.")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
