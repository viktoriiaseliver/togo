#!/bin/bash
# Того · языки считаются внутри КАЖДОГО бандла, а не внутри приложения.
#
# Как звать:
#   Tools/check_bundle_languages.sh build/Togo.xcarchive
#   Tools/check_bundle_languages.sh build/dd/Build/Products/Debug-iphonesimulator/Togo.app
#
# Зачем. 24.09.2026 паспорт архива 216 говорил «языки в .app: fr ru uk —
# внутри бандла, а не по каталогу». Считали в `Togo.app` и не заглянули
# в `PlugIns/`: в `TogoWidgetsExtension.appex` не было ни одной `.lproj`.
# Француз и украинец видели русский на экране блокировки — там, где
# стоят самые короткие и самые заметные строки продукта.
#
# «Внутри бандла» звучит как конец цепочки и им не является, если
# бандлов два. Отсюда правило: проверять ПОСЛЕДНЕЕ звено, а сторожа
# держать на нём, а не на каталоге и не на исходнике.
#
# Зелёный прогон тут не доказательство и сторож на project.pbxproj тоже:
# первый меряет арифметику, второй — объявление цели. Этот скрипт меряет
# то, что уедет в App Store.
#
# ─────────────────────────────────────────────────────────────────────
# ПРАВКА 15.10.2026, `projects-d9`. Три дыры, и все три найдены не
# чтением, а запуском сторожа на четырёх бандлах, лежавших на диске.
#
#   1. ГОДНОСТЬ БАНДЛА не спрашивалась вовсе. Четыре `Togo.app`
#      в `build/` (dd-c5, DD-03, ui-14379, ui-44306): ни одного
#      `Info.plist`, ни одного исполняемого файла, ни одного `.appex`
#      внутри `PlugIns/`. Внутри трёх — по 0-3 файла (`Assets.car`
#      и две иконки), внутри четвёртого — 25 и четыре `.lproj`.
#      Это не четыре сборки с разным составом языков, а ОДНА фаза
#      копирования ресурсов, остановленная в четырёх разных местах.
#      Запись «`en.lproj` появлялся в одной сборке из четырёх одного
#      кода, и предсказать этого мы не умеем» объясняется этим целиком.
#      Ось «какие языки дала сборка» и ось «докуда доехала сборка»
#      давали ОДИН И ТОТ ЖЕ ответ — отсутствие папок.
#
#   2. СОДЕРЖИМОЕ `.lproj` не печаталось. Папка с одним
#      `AppShortcuts.strings` (её завозит извлечение AppIntents —
#      механизм другой, фаза другая) считалась языком наравне
#      с полным каталогом. Это и есть `en.lproj`, который 09.10
#      «появился сам и нёс один файл»: не язык, а побочный продукт
#      чужой фазы.
#
#   3. `.appex` ИСКАЛСЯ ТОЛЬКО В `PlugIns/`. На Debug-симуляторе
#      расширение лежит СОСЕДОМ приложения в `Products`, и языки
#      в нём есть — все четыре. Сторож же говорил «расширение
#      не вошло в сборку» и отправлял читателя искать членство цели
#      в генераторе, где всё в порядке (`generate_project.py:113-121`,
#      фаза `Embed Foundation Extensions`, `dstSubfolderSpec = 13`).
#      Отказ назвал сторону, которая отказала, а не свою причину.
#
# Отсюда код возврата 3, отдельный от 1: «замер не состоялся» —
# не то же, что «не сошлось», и смешивать их значит получать красное,
# которое читается как дефект продукта.
#
#   0  сошлось
#   1  ЯЗЫКИ РАЗОШЛИСЬ — предмет сторожа
#   2  звать не умеют: путь не тот, аргумента нет
#   3  ЗАМЕР НЕ СОСТОЯЛСЯ: бандл негоден либо расширение не там,
#      где оно уедет. Разбирать инструмент, а не продукт
# ─────────────────────────────────────────────────────────────────────
set -euo pipefail

if [ $# -lt 1 ]; then
    echo "Как звать: Tools/check_bundle_languages.sh <путь к .app или .xcarchive>" >&2
    exit 2
fi

TARGET="$1"
# Архив и голый `.app` — разные вопросы, и различать их обязательно.
# В архив расширение ОБЯЗАНО быть встроено: он и есть то, что уедет.
# У Debug-симулятора встраивания может не быть вовсе, и это не дефект
# продукта — это другая форма продукта, о которой архив ничего не знает.
MODE="app"

if [ -d "$TARGET/Products/Applications" ]; then
    APP="$(find "$TARGET/Products/Applications" -maxdepth 1 -name '*.app' | head -1)"
    MODE="archive"
elif [ -d "$TARGET" ] && [ "${TARGET##*.}" = "app" ]; then
    APP="$TARGET"
else
    echo "✗ не нашёл .app по пути $TARGET" >&2
    exit 2
fi

[ -n "${APP:-}" ] && [ -d "$APP" ] || { echo "✗ не нашёл .app внутри $TARGET" >&2; exit 2; }

# ── Годность бандла. Спрашивается ПРЕЖДЕ состава языков, потому что
# недособранный каталог отвечает на вопрос о языках так же, как
# бандл без каталога: пусто. Ось — три признака, и все три ставит
# сборка в самом конце: `Info.plist`, исполняемый файл по имени
# из него, и каталог `PlugIns`.
bundle_broken() {
    local b="$1"
    local plist="$b/Info.plist"
    local exe=""
    if [ ! -f "$plist" ]; then
        echo "Info.plist НЕТ"
        return 0
    fi
    exe="$(plutil -extract CFBundleExecutable raw "$plist" 2>/dev/null || true)"
    if [ -z "$exe" ]; then
        echo "CFBundleExecutable в Info.plist НЕТ"
        return 0
    fi
    if [ ! -f "$b/$exe" ]; then
        echo "исполняемого файла «${exe}» НЕТ"
        return 0
    fi
    return 1
}

if BROKEN="$(bundle_broken "$APP")"; then
    echo "✗ ЗАМЕР НЕ СОСТОЯЛСЯ: $(basename "$APP") — не бандл. ${BROKEN}." >&2
    echo "  Состав языков по такому каталогу не читается вовсе: сборка" >&2
    echo "  не доехала до конца, и отсутствие .lproj тут значит" >&2
    echo "  «ресурсы не скопированы», а не «языка нет в продукте»." >&2
    echo "  Внутри лежит: $(find "$APP" -maxdepth 1 -mindepth 1 | wc -l | tr -d ' ') элементов." >&2
    echo "  Разбирать сборку, а не продукт." >&2
    exit 3
fi

# Языки — по папкам `.lproj`, а не по CFBundleLocalizations: ключ
# в Info.plist называет обещанное, папки — записанное. И каталог в дереве
# не считается вовсе: он трижды за день оказывался полным при пустом
# экране.
bundle_langs() {
    find "$1" -maxdepth 1 -name '*.lproj' -exec basename {} .lproj \; | sort | tr '\n' ' '
}

# Печать СОДЕРЖИМОГО каждой папки. «Файл есть ≠ строки есть» было
# написано в хвосте этого скрипта и не проверялось им ни одной строкой.
# Здесь не приёмка (сторож не знает, сколько ключей должно быть),
# а то, без чего читающий не отличит язык от побочного продукта
# чужой фазы сборки.
#
# И отдельная ось внутри той же печати — `Localizable.stringsdict`.
# Её принёс `projects-22` замером 15.10.2026, и у неё СВОЙ пострадавший:
#
#     ru.lproj/Localizable.stringsdict        34 записи
#     у скольких формы различаются            34 из 34
#     без неё SwiftUI отдаёт сам ключ:        «1 доз» вместо «1 доза»,
#                                             «1 выходов» вместо «1 выход»
#
# То есть от доезда каталога зависит и РУССКИЙ, просто ломается он
# не словами, а числами — и это тише втрое: строка на экране остаётся
# русской и выглядит нашей опечаткой, а не пропавшим файлом.
print_langs() {
    local b="$1"
    find "$b" -maxdepth 1 -name '*.lproj' | sort | while read -r dir; do
        local files size plural
        files="$(find "$dir" -maxdepth 1 -type f -exec basename {} \; | sort | tr '\n' ' ')"
        size="$(du -sk "$dir" | awk '{print $1}')"
        plural=""
        [ -f "$dir/Localizable.strings" ] && [ ! -f "$dir/Localizable.stringsdict" ] \
            && plural="  ← .stringsdict НЕТ: формы числа отдадутся ключом"
        printf "     %-10s %5s КБ  %s%s\n" "$(basename "$dir")" "${size}" "${files:-ПУСТАЯ ПАПКА}" "$plural"
    done
}

APP_LANGS="$(bundle_langs "$APP")"
echo "── $(basename "$APP"): ${APP_LANGS:-НИ ОДНОГО}"
print_langs "$APP"

if [ -z "$APP_LANGS" ]; then
    echo "✗ в самом приложении нет ни одной .lproj — и бандл при этом" >&2
    echo "  годен (Info.plist и бинарь на месте). Это уже предмет:" >&2
    echo "  каталог не доехал до приложения." >&2
    exit 1
fi

FAIL=0
FOUND=0
WHERE="PlugIns/"

check_ext() {
    local ext="$1"
    local ext_langs
    FOUND=$((FOUND + 1))
    ext_langs="$(bundle_langs "$ext")"
    echo "── $(basename "$ext") [${WHERE}]: ${ext_langs:-НИ ОДНОГО}"
    print_langs "$ext"
    if [ "$ext_langs" != "$APP_LANGS" ]; then
        # Скобки обязательны: «$APP_LANGS»» bash читает как имя
        # переменной ВМЕСТЕ с закрывающей кавычкой-ёлочкой — байты
        # `»` идут в идентификатор, и при `set -u` скрипт падает
        # «unbound variable» ровно в той ветке, ради которой написан.
        # Поймано на архиве 216 при первом же красном прогоне.
        echo "✗ $(basename "$ext") несёт «${ext_langs:-ничего}», а приложение «${APP_LANGS}»." >&2
        echo "  Расширение читает СВОЙ бандл: чего нет здесь, человек увидит" >&2
        echo "  по-русски — на экране блокировки, в «острове» и в виджете." >&2
        echo "  Каталог должен лежать в папке, синхронизированной в обе цели" >&2
        echo "  (TogoShared/Resources/), а не у приложения." >&2
        FAIL=1
    fi
}

if [ -d "$APP/PlugIns" ]; then
    for EXT in "$APP/PlugIns"/*.appex; do
        [ -d "$EXT" ] || continue
        check_ext "$EXT"
    done
fi

# Проверка, которой было что проверять. Скрипт, не нашедший ни одного
# расширения, молчит так же, как тот, у которого всё сошлось, — а у Того
# расширение виджета есть всегда.
#
# И отдельно — ГДЕ оно найдено. В архиве только `PlugIns/`: архив и есть
# то, что уедет, и невстроенное расширение там — дефект. У голого `.app`
# с симулятора расширение штатно лежит соседом, и мерить его можно,
# но называть этот замер ответом про архив нельзя.
if [ "$FOUND" -eq 0 ]; then
    SIBLINGS="$(find "$(dirname "$APP")" -maxdepth 1 -name '*.appex' 2>/dev/null | sort)"
    if [ "$MODE" = "archive" ]; then
        echo "✗ в архиве нет ни одного .appex внутри $(basename "$APP")/PlugIns/." >&2
        echo "  Архив — это то, что уедет: расширение обязано быть ВСТРОЕНО." >&2
        if [ -n "$SIBLINGS" ]; then
            echo "  Рядом с приложением оно при этом лежит — значит собралось," >&2
            echo "  а фаза «Embed Foundation Extensions» до него не дошла:" >&2
            echo "$SIBLINGS" | sed 's/^/    /' >&2
        fi
        exit 1
    fi
    if [ -z "$SIBLINGS" ]; then
        echo "✗ ЗАМЕР НЕ СОСТОЯЛСЯ: расширений нет ни в PlugIns/, ни рядом" >&2
        echo "  с приложением, а у Того есть TogoWidgetsExtension." >&2
        echo "  Либо путь не тот, либо сборка не дошла до расширения." >&2
        exit 3
    fi
    echo "── расширения в PlugIns/ НЕТ, но они лежат соседом приложения."
    echo "   Это штатная форма Debug-симулятора, а не дефект. Меряю их," >&2
    echo "   но ответом про архив этот замер не считается." >&2
    WHERE="рядом, не внутри"
    while read -r EXT; do
        [ -n "$EXT" ] || continue
        check_ext "$EXT"
    done <<< "$SIBLINGS"
    [ "$FAIL" -eq 0 ] || exit 1
    echo "✓ языки совпадают во всех $((FOUND + 1)) бандлах: $APP_LANGS"
    echo "✗ ЗАМЕР НЕ О ТОМ, ЧТО УЕДЕТ: расширение здесь не встроено" >&2
    echo "  в приложение. Про архив спрашивать на архиве." >&2
    exit 3
fi

[ "$FAIL" -eq 0 ] || exit 1

echo "✓ языки совпадают во всех $((FOUND + 1)) бандлах: $APP_LANGS"
echo "  Чего это НЕ значит: что строки переведены. Совпадение папок .lproj"
echo "  говорит только, что каталог доехал до каждого бандла."
echo "  И чего это НЕ значит тем более: что ключ в каталоге ЕСТЬ."
echo "  У нас sourceLanguage: ru, ключ сам есть русская строка — значит"
echo "  пропущенный ключ рендерится по-русски, НЕ ОСТАВЛЯЯ русских байт"
echo "  в чужом .lproj. Поиск русского текста в нерусском каталоге"
echo "  к этому классу слеп по устройству (замер 15.10: во fr.lproj"
echo "  2175 ключей, русских значений 0, пропусков против ru — 0,"
echo "  а смесь языков на экране при этом живёт в отзывах)."
