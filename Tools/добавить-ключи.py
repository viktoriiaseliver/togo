#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Внести в каталог ключи, которые код СТРОИТ, а каталог не знает.

Разовый инструмент, 27.10.2026. Предмет — `String(localized:)`,
у которого нет записи в `Localizable.xcstrings`: такая строка
показывается ПО-РУССКИ на всех языках, и молча. Четыре из найденных
десяти живут в сводке врачу, которую показывают ветеринару.

ПОЧЕМУ НЕ `xcodebuild -exportLocalizations`. Штатное извлечение —
правильный путь и остаётся им; здесь оно не применяется по одной
причине: извлечение проходит ВЕСЬ проект и переписывает каталог
целиком, а у нас в нём лежит 158 свежих правок вычитки, не уехавших
в сборку. Разница between «добавить десять ключей» и «перегенерировать
3658» — это риск потерять чужую работу, а не вкус.

ФОРМАТ ДЕРЖИТСЯ ТЕКСТОМ. Вставка идёт готовым блоком в то место,
куда его положил бы Xcode (сортировка регистронезависимая), а JSON
разбирается только для проверок. `json.dump` переписал бы все 3658
записей: Xcode пишет `"ключ" : значение`, Python — без пробела.
"""
from __future__ import annotations
import json
import re
import sys

КАТАЛОГ = "TogoShared/Resources/Localizable.xcstrings"


def блок_простой(ключ: str, переводы: dict, состояние: str = "translated") -> str:
    строки = [f'    "{экр(ключ)}" : {{',
              '      "extractionState" : "manual",',
              '      "localizations" : {']
    языки = sorted(переводы)
    for n, язык in enumerate(языки):
        строки += [f'        "{язык}" : {{',
                   '          "stringUnit" : {',
                   f'            "state" : "{состояние}",',
                   f'            "value" : "{экр(переводы[язык])}"',
                   '          }',
                   '        }' + ("," if n < len(языки) - 1 else "")]
    строки += ['      }', '    },']
    return "\n".join(строки) + "\n"


def блок_плюральный(ключ: str, переводы: dict, состояние: str = "translated") -> str:
    """переводы: {язык: {форма: значение}}"""
    строки = [f'    "{экр(ключ)}" : {{',
              '      "extractionState" : "manual",',
              '      "localizations" : {']
    языки = sorted(переводы)
    for n, язык in enumerate(языки):
        формы = переводы[язык]
        строки += [f'        "{язык}" : {{',
                   '          "variations" : {',
                   '            "plural" : {']
        имена = [ф for ф in ["one", "few", "many", "other"] if ф in формы]
        for m, форма in enumerate(имена):
            строки += [f'              "{форма}" : {{',
                       '                "stringUnit" : {',
                       f'                  "state" : "{состояние}",',
                       f'                  "value" : "{экр(формы[форма])}"',
                       '                }',
                       '              }' + ("," if m < len(имена) - 1 else "")]
        строки += ['            }', '          }',
                   '        }' + ("," if n < len(языки) - 1 else "")]
    строки += ['      }', '    },']
    return "\n".join(строки) + "\n"


def экр(s: str) -> str:
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\t", "\\t"))


def вставить(сырой: str, ключ: str, блок: str) -> str:
    """В место, куда положил бы Xcode: регистронезависимо по возрастанию."""
    места = [(m.start(), m.group(1)) for m in
             re.finditer(r'\n    "((?:[^"\\]|\\.)*)" : \{', сырой)]
    цель = ключ.casefold()
    for поз, имя in места:
        if имя.casefold() > цель:
            return сырой[:поз + 1] + блок + сырой[поз + 1:]
    # за последним ключом — перед закрывающей скобкой strings
    последняя = места[-1][0]
    конец = сырой.index('\n  },', последняя)
    return сырой[:конец + 1] + блок + сырой[конец + 1:]


def главное() -> int:
    данные = json.load(open(НОВЫЕ, encoding="utf-8"))
    сырой = open(КАТАЛОГ, encoding="utf-8").read()
    было = len(json.loads(сырой)["strings"])

    добавлено, пропущено = [], []
    for запись in данные:
        ключ = запись["ключ"]
        if f'\n    "{экр(ключ)}" : {{' in сырой:
            пропущено.append((ключ, "уже есть в каталоге"))
            continue
        # «состояние»: `needs_review` для перевода, который носитель
        # не читал, — иначе машинный перевод молча проходит храповик
        # `LocalizationCoverageTests.долг` как вычитанный.
        состояние = запись.get("состояние", "translated")
        блок = (блок_плюральный(ключ, запись["переводы"], состояние)
                if запись.get("плюральный") else
                блок_простой(ключ, запись["переводы"], состояние))
        сырой = вставить(сырой, ключ, блок)
        добавлено.append(ключ)

    новые = json.loads(сырой)          # приёмка: файл остался JSON
    стало = len(новые["strings"])
    if стало != было + len(добавлено):
        print(f"ОТКАЗ: ключей было {было}, добавлено {len(добавлено)}, стало {стало}")
        return 1
    open(КАТАЛОГ, "w", encoding="utf-8").write(сырой)

    print(f"добавлено: {len(добавлено)}")
    for к in добавлено:
        print(f"   {к[:64]!r}")
    for к, п in пропущено:
        print(f"   пропущен {к[:48]!r}: {п}")
    print(f"ключей: {было} → {стало}")
    return 0


НОВЫЕ = sys.argv[1] if len(sys.argv) > 1 else "/tmp/новые-ключи.json"

if __name__ == "__main__":
    sys.exit(главное())
