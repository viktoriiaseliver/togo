#!/usr/bin/env python3
"""Сверить падения модульного прогона с эталоном — ПО ИМЕНАМ.

Зачем не по счёту. Сравнение числа issue ловит «стало восемь вместо
семи» и не ловит «одно наше ушло, одно чужое пришло»: счёт совпадает,
и прогон зелёный при живой регрессии. Это наш записанный класс —
проверка, которая выполняется и при дефекте.

Две половины, и вторая обязательна:

    появилось имя не из эталона   → регрессия
    ожидаемо красный ПОЗЕЛЕНЕЛ    → причина умерла, а запись осталась

Вторая не для симметрии. Запись, чья причина умерла, молча разрешает
настоящую регрессию под тем же именем: исключение, закрывающее то,
чего нет, — лишняя дыра, про которую никто не помнит.

Запуск — лог и бандл отвечают на РАЗНЫЕ вопросы, поэтому лучше оба:

    python3 Tools/сверить_эталон.py --лог build/logs/unit.log \
                                    --бандл build/Togo.xcresult
    python3 Tools/сверить_эталон.py --лог build/logs/unit.log   # запасной
    python3 Tools/сверить_эталон.py build/Togo.xcresult         # без стенда

    лог    СОСТОЯЛСЯ ли прогон: ноль тестов, перезапуски, смерть
           симулятора. В бандле этого не видно, и прогон, умерший
           от стенда, прочтётся как нашедший дефекты.
    бандл  ИМЕНА упавших — из структуры, а не из печати. Печать имена
           портит: замерено 07.10.2026, см. `починить_байты`.

Код возврата: 0 — прогон сошёлся с эталоном, 1 — нет, 2 — сверить
нечем (сам инструмент не смог прочитать прогон; это НЕ «всё хорошо»).
"""

import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ЭТАЛОН = КОРЕНЬ / "Tools" / "эталон-прогона.json"


ВОСЬМЕРИЧНЫЙ_БАЙТ = re.compile(rb"\\([0-3][0-7][0-7])")


def починить_байты(имя: str) -> str:
    """Собрать кириллицу, которую `xcodebuild` выдал восьмеричными escape.

    **Замерено 07.10.2026 на `unit-20261007-145210`.** В сводной строке
    падения один байт имени уехал экранированным, а в `started`
    и `recorded an issue` того же теста имя цело:

        ◇ Test "Ни один ключ не остался без перевода" started
        ✘ Test "Ни один ключ не остался бе\\320\\267 перевода" failed

    `0o320 0o267` = `0xD0 0xB7` = UTF-8 для «з». То есть это не чужая
    кодировка и не битый лог — это восьмеричные escape тех же самых
    байтов, и они собираются обратно однозначно.

    Почему это починка, а не косметика: сверка берёт имена из обеих
    строк, и мятое имя не совпадало с эталоном. Один упавший тест давал
    **разом** верное совпадение и фантом «красное, которого нет
    в эталоне» — в том прогоне напечатано четыре красных вне эталона
    при трёх настоящих.

    > Сверка по имени из человекочитаемого лога ломается на кодировке —
    > и ломается в сторону ЛОЖНОЙ находки. А ложное срабатывание
    > не остаётся шумом: его закрывают записью в эталоне, то есть
    > гасят сторож.

    **Граница:** собирается только форма, которую мы видели, —
    восьмеричные escape байтов UTF-8. Если `xcodebuild` однажды выдаст
    имя иначе (`\\M-P`, `^[`), мятое имя снова станет фантомом, и это
    правильнее, чем угадывать: фантом видно, тихую подмену имени — нет.
    """
    if "\\" not in имя:
        return имя
    сырое = имя.encode("utf-8", errors="surrogateescape")
    собрано = ВОСЬМЕРИЧНЫЙ_БАЙТ.sub(lambda m: bytes([int(m.group(1), 8)]), сырое)
    try:
        return собрано.decode("utf-8")
    except UnicodeDecodeError:
        # Собралось не в текст — значит форма не та, что мы знаем.
        # Отдаём как было: пусть лучше станет видимым фантомом.
        return имя


def имена_из_лога(текст: str) -> tuple[set[str], list[str]]:
    """Имена упавших тестов из вывода xcodebuild — ЗАПАСНОЙ путь.

    Берутся только строки `recorded an issue at <файл>:<строка>`:
    у них есть адрес, то есть за именем стоит структура, а не печать.
    Сводная строка `✘ Test "…" failed` как источник **не годится** —
    именно она портит имена, см. `починить_байты`.

    Второе возвращаемое — имена из сводных строк, которым не нашлось
    пары среди адресных. Это не регрессии, это **непрочитанные имена**,
    и ответ на них «сверять нечем», а не «появилось новое красное».

    Замер 07.10.2026 по пяти логам этой сессии: 20 кириллических имён
    в сводных строках, испорчено **одно**. То есть порча редкая
    и случайная — похоже на границу буфера, а не на кодировку. А значит
    испортиться может **любое** длинное имя, не только кириллическое:
    усечение или склейка с чужим выводом не оставят `\\320` и обратной
    сборкой не починятся. Поэтому запасной путь не угадывает, а честно
    говорит «не прочитал».
    """
    адресные = {
        починить_байты(имя)
        for имя in re.findall(r'✘ Test "([^"]+)" recorded an issue at ', текст)
    }
    сводные = {починить_байты(имя)
               for имя in re.findall(r'✘ Test "([^"]+)" failed', текст)}
    return адресные, sorted(сводные - адресные)


def имена_из_xcresult(путь: pathlib.Path) -> set[str]:
    """То же из .xcresult — на случай, когда лога нет, а бандл есть."""
    готово = subprocess.run(
        ["xcrun", "xcresulttool", "get", "test-results", "tests",
         "--path", str(путь), "--format", "json"],
        capture_output=True, text=True,
    )
    if готово.returncode != 0:
        raise RuntimeError(готово.stderr.strip()[:400])

    упали: set[str] = set()

    def обойти(узел: dict) -> None:
        if узел.get("result") == "Failed" and узел.get("nodeType") == "Test Case":
            # В xcresult имя приходит с хвостом «()» и иногда с набором.
            упали.add(узел.get("name", "").removesuffix("()"))
        for ребёнок in узел.get("children", []) or []:
            обойти(ребёнок)

    for узел in json.loads(готово.stdout).get("testNodes", []) or []:
        обойти(узел)
    return упали


def прогон_состоялся(текст: str, порог: int) -> tuple[bool, str]:
    """Отличить «тестов не было» от «тесты прошли».

    Прогон, упавший от стенда, снаружи неотличим от прогона, нашедшего
    дефект: оба дают код 65 и ноль значков ✘. Отличает «сколько
    выполнилось» — и спрашивать надо **против ожидаемого**, а не
    «ноль или нет».

    > **Ноль выполненных заметен. Пять из восьмисот — нет**, и строка
    > итога у такого прогона несёт слово `passed`.

    Шесть отказов стенда за один час 07.10.2026 прошли через эту
    функцию, и каждый дал своё слово: `Mach error -308`, `Early
    unexpected exit`, пять `Restarting after unexpected exit`
    (4 и 6 тестов из 845), `uncaught exception` при нуле выполненных.
    Список симптомов рос по замеру, а не по догадке, и потому
    **он не полон**: порог против ожидаемого ловит и те, которых
    в списке ещё нет.
    """
    if "Mach error -308" in текст or "server died" in текст:
        return False, "умер сервер симулятора (Mach error -308) — это стенд, а не код"
    if "Early unexpected exit" in текст:
        return False, "тест-раннер не запустился (Early unexpected exit) — это стенд"
    # Замерено `viktoriias-25` 07.10.2026: прогон разбился
    # (`No eligible connection available`) и напечатал
    # «✔ Test run with 0 tests in 1 suite passed». Падение и пустой
    # прогон дают одинаковую строку, и она со словом `passed`.
    if "uncaught exception" in текст or "Terminating app due to" in текст:
        return False, "приложение разбилось необработанным исключением — это стенд"

    счёты = [int(n) for n in re.findall(r"Test run with (\d+) tests", текст)]
    if not счёты:
        return False, "в логе нет строки «Test run with N tests» — прогон не дошёл до конца"
    перезапуски = текст.count("Restarting after unexpected exit")
    if перезапуски:
        return False, f"перезапусков после неожиданного выхода: {перезапуски} — это стенд"

    # Берём наименьшее из напечатанных: при перезапусках отчёт сводит
    # тотали переживших сюит, и большее число — про то, чего не было.
    выполнено = min(счёты)
    if выполнено < порог:
        return False, (f"выполнено {выполнено} тестов, а эталон ждёт "
                       f"не меньше {порог} — замер не состоялся. "
                       "Это НЕ «ноль красных»: прогон, умерший после "
                       "пятого теста, печатает строку итога со словом "
                       "`passed`")
    return True, ""


def занятость_стенда(текст: str) -> str:
    """Строка «СТЕНД ПЕРЕД СТАРТОМ: …», если `make unit` её положил.

    **Зачем печатать её при отказе стенда.** 25.10.2026 на машине жили
    53 worktree, 11 поднятых симуляторов и до пяти `xcodebuild` разом;
    `load average` за четыре минуты сходил от 115 до 502. При каждом
    отказе спорили, виноват код или соседи, — и числа, которым этот спор
    решается, не было: снимать его надо ДО прогона, а спрашивают ПОСЛЕ.

    Порога тут нет и отказа по нему тоже: за день набрался один отказ
    из пяти прогонов, и порог из одного случая был бы числом без замера.
    Строка копит замеры, чтобы порог однажды стало чем назвать.

    Старые логи этой строки не содержат — возвращаем пустоту, и это
    не отказ: отсутствие признака здесь значит «прогон запускали
    рецептом постарше», а не «машина была свободна».
    """
    for строка in текст.split("\n", 5)[:5]:
        if строка.startswith("СТЕНД ПЕРЕД СТАРТОМ:"):
            return строка.strip()
    return ""


def main() -> int:
    аргументы = sys.argv[1:]
    эталон = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    ожидаемые = {з["тест"]: з for з in эталон["ожидаемо_красные"]}
    # Ожидаемое число — ЗАРАНЕЕ и в одном месте. Две копии разойдутся
    # молча, поэтому сверка его не держит, а читает.
    порог = int(эталон.get("выполнено_тестов_не_менее", 0))

    # Список, в который входит почти всё, — это сторож, который
    # не может покраснеть. Печатаем долю, а не длину.
    print(f"Эталон: {len(ожидаемые)} ожидаемо красных — {ЭТАЛОН.relative_to(КОРЕНЬ)}")

    # Лог и бандл отвечают на РАЗНЫЕ вопросы, и нужны оба.
    #
    #   лог    состоялся ли прогон вообще (ноль тестов, перезапуски,
    #          смерть симулятора) — в бандле этого не видно
    #   бандл  ИМЕНА упавших: они приходят из структуры, а не из печати,
    #          и печать их портит
    #
    # Поэтому `--лог` оставлен обязательным, а `--бандл` — предпочтительным
    # источником имён. Был бы только бандл — потеряли бы отличие
    # «упало от стенда» от «упало от кода», а это главная половина сверки.
    лог = бандл = None
    for i, арг in enumerate(аргументы):
        if арг == "--лог" and i + 1 < len(аргументы):
            лог = pathlib.Path(аргументы[i + 1])
        elif арг == "--бандл" and i + 1 < len(аргументы):
            бандл = pathlib.Path(аргументы[i + 1])
        elif i == 0 and not арг.startswith("--"):
            бандл = pathlib.Path(арг)

    if лог is None and бандл is None:
        print("Нечего сверять: укажи --лог <файл> и/или --бандл <.xcresult>",
              file=sys.stderr)
        return 2

    непрочитанные: list[str] = []
    try:
        # Стенд — по логу, если он дан. Без этой проверки прогон, умерший
        # от симулятора, прочтётся как прогон, нашедший дефекты.
        if лог is not None:
            текст = лог.read_text(encoding="utf-8", errors="replace")
            цел, почему = прогон_состоялся(текст, порог)
            if not цел:
                print(f"СВЕРЯТЬ НЕЧЕМ: {почему}.", file=sys.stderr)
                стенд = занятость_стенда(текст)
                if стенд:
                    print(стенд, file=sys.stderr)
                    print("  ↑ занятость машины НА МОМЕНТ СТАРТА этого прогона. "
                          "Порога у неё нет: он не замерен. Число печатается, "
                          "чтобы замеры накапливались у отказов, а не у споров.",
                          file=sys.stderr)
                else:
                    print("Занятость машины на старте неизвестна: лог снят "
                          "рецептом без строки «СТЕНД ПЕРЕД СТАРТОМ». "
                          "Это не «машина была свободна».", file=sys.stderr)
                print("Это не «эталон сошёлся» и не «не сошёлся» — это отказ "
                      "инструмента наблюдения. Повтори прогон.", file=sys.stderr)
                return 2

        почему_не_бандл = None
        упали = None

        if бандл is not None and бандл.exists():
            try:
                упали = имена_из_xcresult(бандл)
                источник = f"{бандл} — структура прогона"
            except Exception as отказ:  # noqa: BLE001
                # Бандл оборванного прогона испорчен: `Info.plist` в нём
                # нет вовсе. Замерено 07.10.2026 — прогон остановили
                # на пятом перезапуске, и `xcresulttool` ответил
                # «result bundle might be corrupted».
                #
                # Отказываться целиком тут нельзя: лог рядом лежит
                # и читается. Иначе лучший источник, сломавшись,
                # отнимал бы и худший — а оборванные прогоны бывают
                # чаще здоровых.
                почему_не_бандл = f"бандл не прочитался: {отказ}"
        elif бандл is not None:
            почему_не_бандл = f"бандла нет на диске: {бандл}"
        else:
            почему_не_бандл = "бандл не передан"

        if упали is None:
            if лог is None:
                print(f"СВЕРЯТЬ НЕЧЕМ: {почему_не_бандл}", file=sys.stderr)
                return 2
            источник = (f"{лог} — ПЕЧАТЬ прогона, запасной путь "
                        f"({почему_не_бандл})")
            упали, непрочитанные = имена_из_лога(текст)
    except Exception as ошибка:  # noqa: BLE001 — любой отказ чтения равнозначен
        print(f"СВЕРЯТЬ НЕЧЕМ: прогон не прочитался — {ошибка}", file=sys.stderr)
        return 2

    # Откуда взяты имена — вслух. Путей два, и «сверено по запасному»
    # обязано отличаться от «сверено по бандлу»: у запасного имена
    # приходят из печати, и печать их портит.
    print(f"Источник имён: {источник}")

    # Имя, которого не прочитали, — это НЕ новое красное.
    if непрочитанные:
        print("\nСВЕРЯТЬ НЕЧЕМ: в сводных строках есть имена без пары "
              "среди адресных:", file=sys.stderr)
        for имя in непрочитанные:
            print(f"  ? {имя}", file=sys.stderr)
        print("\nЛибо печать испортила имя (граница буфера — замерено "
              "07.10.2026), либо тест упал без `recorded an issue` — "
              "например от краша. В обоих случаях сверить нельзя, "
              "и объявлять регрессию по непрочитанному имени нельзя тем "
              "более: ложная находка дороже пропущенной, после неё "
              "перестают читать саму сверку.\n"
              "Сверяй по бандлу: python3 Tools/сверить_эталон.py "
              "build/Togo.xcresult", file=sys.stderr)
        return 2

    # Защита от расхождения ФОРМАТА имён, названная togo-05.
    # В `.xcresult` имя приходит с хвостом `()` и иногда с набором.
    # Разойдись формат — все записи эталона станут «позеленевшими»
    # разом, и это прочтётся как катастрофа, а не как расхождение.
    if упали and ожидаемые and not (упали & set(ожидаемые)):
        print("\nСВЕРЯТЬ НЕЧЕМ: падения есть, но с эталоном не совпало "
              "НИ ОДНО имя.", file=sys.stderr)
        print(f"  упало:   {sorted(упали)}", file=sys.stderr)
        print(f"  эталон:  {sorted(ожидаемые)}", file=sys.stderr)
        print("\nСкорее всего разошёлся формат имени (хвост `()`, префикс "
              "набора), а не поведение: чтобы все три записи эталона "
              "позеленели ровно в том прогоне, где появились новые "
              "падения, нужно совпадение, которого не бывает. "
              "Сверь формат, прежде чем верить любой из двух половин.",
              file=sys.stderr)
        return 2

    лишние = sorted(упали - set(ожидаемые))
    позеленевшие = sorted(set(ожидаемые) - упали)

    print(f"Упало тестов: {len(упали)}")
    for имя in sorted(упали & set(ожидаемые)):
        print(f"  ожидаемо красный · {имя}")

    плохо = False

    if лишние:
        плохо = True
        print("\nКРАСНОЕ, КОТОРОГО НЕТ В ЭТАЛОНЕ:", file=sys.stderr)
        for имя in лишние:
            print(f"  ✘ {имя}", file=sys.stderr)
        print("\nЭто регрессия, пока не доказано обратное. Если тест обязан "
              "быть красным — впиши его в эталон С ПРИЧИНОЙ и хозяином, "
              "а не убери из набора.", file=sys.stderr)

    if позеленевшие:
        плохо = True
        print("\nОЖИДАЕМО КРАСНЫЙ ПОЗЕЛЕНЕЛ:", file=sys.stderr)
        for имя in позеленевшие:
            з = ожидаемые[имя]
            print(f"  ✔ {имя}", file=sys.stderr)
            print(f"      держало: {з['держит']}", file=sys.stderr)
            print(f"      хозяин:  {з['хозяин']}", file=sys.stderr)
        print("\nПричина умерла, а запись осталась. Убери её из эталона: "
              "пока она там, она молча разрешает настоящую регрессию "
              "под тем же именем.", file=sys.stderr)

    # Границы собственного умения — последней строкой, всегда.
    print("\nЧего эта сверка НЕ проверяет:")
    print("  · UI-набор, кадры и поведение на рантайме iOS 27.0 — их закрывают руками;")
    print("  · что ожидаемо красный красен по ТОЙ ЖЕ причине: имя совпало, причину")
    print("    знает только человек, читающий текст падения;")
    print("  · число issue внутри одного теста — сверяются имена, а не счёт;")
