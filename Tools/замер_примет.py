#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сколько примет фикстуры видно на кадре — числом, а не глазом.

Фикстура (`ФонФикстураСтенда`) красит четыре края четырьмя цветами:
красный верх, синий низ, зелёный слева, жёлтый справа. Этот замер
считает, сколько пикселей каждого цвета дожило до кадра, — то есть
какой край срезала рамка.

Почему не PIL. Его на машине нет (`python3` 3.9.6, системный), как нет
и PyObjC. Поэтому кадр переводится в BMP через `sips`, а BMP разбирается
руками: формат без сжатия, заголовок фиксированный.

Приёмка самого замера — отдельный ключ `--контроль`: кадр, на котором
фикстуры нет вовсе, обязан дать нули по всем четырём цветам. Без этого
«красного ноль» у предмета неотличимо от «мой порог никого не ловит».
"""
from __future__ import annotations

import struct
import subprocess
import sys
import tempfile
from pathlib import Path

# Пороги широкие нарочно: поверх фотографии лежит затемнение подложки
# (`Token.Surface.scrim`) и маска-градиент, и чистого #FF0000 на кадре
# не бывает НИ ОДНОГО. Узкий порог дал бы ноль у живой приметы.
ЦВЕТА = {
    "красный_верх": lambda r, g, b: r > 60 and r > g * 2 and r > b * 2,
    "синий_низ": lambda r, g, b: b > 60 and b > r * 2 and b > g * 2,
    "зелёный_слева": lambda r, g, b: g > 60 and g > r * 2 and g > b * 2,
    "жёлтый_справа": lambda r, g, b: r > 60 and g > 60 and r > b * 2 and g > b * 2,
}


def в_bmp(путь: Path, ширина: int = 300) -> Path:
    """Кадр в BMP, ужатый по ширине: цвета считаются те же, а байтов меньше."""
    цель = Path(tempfile.mkdtemp()) / "кадр.bmp"
    subprocess.run(
        ["sips", "-Z", str(ширина), "-s", "format", "bmp", str(путь), "--out", str(цель)],
        check=True, capture_output=True,
    )
    return цель


def пиксели(bmp: Path):
    data = bmp.read_bytes()
    смещение = struct.unpack_from("<I", data, 10)[0]
    ширина, высота = struct.unpack_from("<ii", data, 18)
    бит = struct.unpack_from("<H", data, 28)[0]
    if бит not in (24, 32):
        raise SystemExit("BMP не 24/32 бита: %d" % бит)
    байт = бит // 8
    ряд = ((ширина * байт + 3) // 4) * 4
    снизу_вверх = высота > 0
    h = abs(высота)
    for y in range(h):
        строка = смещение + (h - 1 - y if снизу_вверх else y) * ряд
        for x in range(ширина):
            p = строка + x * байт
            b, g, r = data[p], data[p + 1], data[p + 2]
            yield x, y, ширина, h, r, g, b


def замер(путь: Path) -> dict:
    """Счёт И ось. Число без оси тут уже один раз соврало.

    Замер 25.10.2026: «красный 3303» на вкладке собаки я прочитал как
    «верхняя примета цела» — а красные пиксели лежали ВНИЗУ, в карточке
    «Если что-то случилось». Та же величина, другая ось, обратный вывод.
    Поэтому рядом с каждым счётом печатается, на какой высоте кадра
    цвет найден: `верх` — первые 12 % кадра, `низ` — последние 12 %.
    """
    счёт = {имя: 0 for имя in ЦВЕТА}
    сверху = {имя: 0 for имя in ЦВЕТА}
    строки = {имя: [] for имя in ЦВЕТА}
    всего = 0
    for _x, y, _w, h, r, g, b in пиксели(в_bmp(путь)):
        всего += 1
        for имя, годен in ЦВЕТА.items():
            if годен(r, g, b):
                счёт[имя] += 1
                строки[имя].append(y)
                if y < h * 0.12:
                    сверху[имя] += 1
    итог = {"всего_пикселей": всего}
    for имя in ЦВЕТА:
        итог[имя] = счёт[имя]
        итог[имя + "_в_верхних_12%"] = сверху[имя]
        итог[имя + "_медиана_строки"] = (
            sorted(строки[имя])[len(строки[имя]) // 2] if строки[имя] else -1
        )
    итог["высота"] = h if всего else 0
    return итог


def main() -> int:
    пути = [Path(a) for a in sys.argv[1:] if not a.startswith("--")]
    if not пути:
        print("нечего мерить: передай кадры путями")
        return 2
    print("ось: «вверху» — сколько пикселей цвета попало в верхние 12 % кадра;")
    print("     «мед» — медианная строка цвета в процентах высоты кадра.\n")
    print("%-38s %16s %16s %16s %16s" % (
        "кадр", "красн/вверху/мед", "син/вверху/мед",
        "зелён/вверху/мед", "жёлт/вверху/мед"))
    for путь in пути:
        if not путь.exists():
            print("%-38s НЕТ ФАЙЛА" % путь.name[:38])
            continue
        c = замер(путь)
        h = max(1, c["высота"])
        ячейки = []
        for имя in ("красный_верх", "синий_низ", "зелёный_слева", "жёлтый_справа"):
            мед = c[имя + "_медиана_строки"]
            ячейки.append("%5d/%5d/%3s" % (
                c[имя], c[имя + "_в_верхних_12%"],
                ("%d%%" % (мед * 100 // h)) if мед >= 0 else "—"))
        print("%-38s %16s %16s %16s %16s" % (путь.name[:38], *ячейки))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
