#!/bin/bash
# Что осталось сделать руками после того, как отладочная сборка встала
# на телефон: подпись кнопки читается ИЗ ИСХОДНИКА приложения.
#
#   bash Tools/зеркало-дальше.sh
#
# ЗАЧЕМ ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ `echo` В MAKEFILE.
#
# Инструкция называет кнопку в продукте. Напечатанное имя и настоящее
# имя — две копии одной строки, и расходятся они молча: 14.10.2026
# трижды за смену выяснялось, что обещанный вход в продукте выглядит
# иначе, чем о нём написано. Человек в такой момент ищет кнопку, не
# находит и делает вывод о приложении, а не о нашей записи.
#
# Поэтому подпись здесь не записана, а ДОБЫВАЕТСЯ. Кнопка переименована
# — скрипт **отказывает громко**, а не печатает старое имя. Отказ
# дешевле: он случается у нас, а не у неё с телефоном в руках.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ: `Д="файл"` bash за присвоение
# не считает вовсе, следующая строка выполняется как ни в чём
# не бывало, и под `set -u` это падение, а без него — пустая строка
# в инструкции.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
screen="$root/Togo/Features/Settings/SettingsScreen.swift"
warmup="$root/Togo/Store/CloudKitSchemaWarmup.swift"

fail() { echo "✗ $1" >&2; exit 1; }

[ -f "$screen" ] || fail "нет $screen — инструкцию составить не из чего"

# Подпись кнопки прогрева. Берём ровно ту, что вызывает `create`:
# в разделе отладки пять кнопок, и четыре из них делают другое
# («убрать прогрев», «слить дубликаты», …).
#
# Через `awk`, а не `grep -B1`: первая редакция брала одну строку выше
# вызова и получала `do {` — между подписью и вызовом стоит
# `do`-блок. **Расстояние в строках — свойство разметки, а не связи**,
# и на нём держаться нельзя: кто-нибудь вставит строку, и инструкция
# замолчит. `awk` помнит последнюю встреченную подпись и печатает её
# в тот момент, когда дошёл до вызова, — сколько бы строк между ними
# ни лежало.
#
# И имя переменной внутри `awk` — ЛАТИНИЦЕЙ. Первая редакция звала её
# `последняя`, и `awk` на macOS ответил `syntax error … >>> п <<<`.
# Правило «имена только латиницей» записано в своде про shell, и здесь
# оно повторилось у второго инструмента — а я процитировал его
# двумя строками выше и тут же нарушил. Третий раз в этом же файле:
# до него были обратные кавычки в двойных и расстояние в строках.
label="$(awk '
    /Button\("/ { if (match($0, /Button\("[^"]+"/)) {
                      last = substr($0, RSTART + 8, RLENGTH - 9) } }
    /CloudKitSchemaWarmup\.create/ { if (last != "") { print last; exit } }
' "$screen")"

[ -n "$label" ] || fail "кнопку прогрева в $screen не нашёл.
Либо её переименовали, либо убрали, либо она больше не зовёт
CloudKitSchemaWarmup.create. Старое имя НЕ печатаю нарочно: инструкция,
называющая кнопку, которой нет, дороже отсутствующей инструкции —
человек ищет её на телефоне и делает вывод о приложении."

# Вход у раздела есть? Кнопка, объявленная и не показанная, — это
# механизм без входа, и от рабочего он не отличается ни тестом,
# ни компилятором.
# Обратные кавычки здесь НЕ ставить: в двойных кавычках bash исполняет
# их как команду. Поймано на себе при первом же запуске этого скрипта —
# и это тот же класс, что кириллица в именах переменных: синтаксис
# верен, беда молчит.
grep -q '^[[:space:]]*warmupSection$' "$screen" \
    || fail "раздел отладки объявлен, но в тело экрана не включён:
warmupSection не вызывается. Кнопка существует в исходнике и не
существует на экране."

# Прогрев обязан быть целиком под `#if DEBUG`: на этом держится всё
# утверждение «записи прогрева не могут оказаться там, где мама».
head -1 "$warmup" | grep -q '#if DEBUG' \
    || fail "$warmup больше не начинается с #if DEBUG.
Тогда утверждение «прогрев не может попасть в TestFlight» неверно,
и инструкцию отдавать нельзя, пока это не разобрано."

cat <<ИНСТРУКЦИЯ

────────────────────────────────────────────────────────────────
Сборка на телефоне. Осталось два нажатия — одно в приложении,
второе в дашборде. Это РАЗНЫЕ каналы, и их уже путали дважды.

1. На телефоне: «Настройки» Того → в самом низу → «${label}»
   Жди минуту при живой сети. Приложение напечатает, сколько
   объектов создало.

2. Здесь: make cloudkit-check
   Скажет, чего ещё нет. Пять типов и 83 поля должны пропасть
   из списка.

3. В дашборде iCloud: контейнер iCloud.app.togo.diary →
   Schema → «Deploy Schema Changes…» (из Development в Production).
   Это вторая кнопка, и без неё шаг 1 не доедет до TestFlight.
────────────────────────────────────────────────────────────────

Почему это безопасно, и проверено прежде печати:

  · весь CloudKitSchemaWarmup лежит под #if DEBUG — в сборке
    TestFlight этого кода НЕТ ВОВСЕ, значит сборка, которая
    у мамы, создать записи прогрева не может по устройству;
  · отладочная сборка с кабеля ходит в Development, TestFlight —
    в Production: это разные базы;
  · «Отладка · убрать прогрев» удаляет объекты, а типы и поля
    в схеме остаются — они и были целью.

ИНСТРУКЦИЯ
