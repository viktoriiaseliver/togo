#!/usr/bin/env python3
"""Ворота перед отправкой: витрина обещает только то, что умеет бандл.

    python3 Tools/check_storefront_languages.py [путь/к/Togo.app]

По умолчанию берётся `build/Togo.xcarchive/Products/Applications/Togo.app` —
бандл **того архива, который собираются заливать**, а не любой сборки.
Отпечаток печатается рядом: «та ли сборка» должно быть вопросом с ответом,
а не мнением.

Проверяет две вещи, и обе — про расхождение между тем, чем заняты
разные люди.

**1. Язык метаданных без языка в бандле.** У витрины два разных списка:
локали описаний (их задаёт `appStoreVersionLocalizations`) и языки
приложения — их Apple берёт **из бинарника**. Первый растёт росчерком
в API, второй — только переводом. 05.10.2026 локаль `en-US` заведена
при нуле английских строк в приложении, и поймать это было нечем:
сторожа не существовало.

**2. Цитату интерфейса в описании витрины.** Английское описание зовёт
кнопки по именам («NEEDS TO GO OUT?»), и эти имена обязаны совпасть
со строками приложения дословно, иначе человек пойдёт искать и не найдёт.
Внутри каталога такие места охраняет `QuotedNamesTests` — 56 цитат;
между каталогом и витриной не охраняло ничто.

Почему скриптом, а не тестом: тест читает каталог, а каталог — это то,
что мы думаем. Бандл — то, что получилось.
"""
import glob
import json
import os
import plistlib
import re
import subprocess
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_APP = os.path.join(ROOT, "build/Togo.xcarchive/Products/Applications/Togo.app")

# Цитата витрины ↔ ключ каталога. Ключ — он же русская строка.
#
# Требование формулируется про ТЕКСТ КЛЮЧА, а не про регистр в описании:
# «Просится» цитируется дважды — прописными в заголовке раздела
# и строчными в тексте, — а ключ один. Сверка без этой оговорки дала бы
# ложное расхождение, а ложное расхождение дороже пропущенного дефекта:
# после девятого сторожа перестают читать.
QUOTE_PAIRS = {
    "Просится": "Needs to go out?",
    "Непонятно": "not sure",
    "Вывожу": "Taking her out",
    "как попросил": "how she asked",
}

# Чужие имена, которые описание вправе цитировать: они не наши, и в нашем
# бандле их нет по устройству. Список короткий и с причиной у каждого —
# длинный превратился бы в способ заглушить находку.
СИСТЕМНЫЕ_ЦИТАТЫ = {
    "settings",            # iOS, путь отмены подписки
    "subscriptions",       # iOS, там же
    "cancel subscription",  # iOS, там же
}

# Шестая пара — «не брал еду» → «didn't take food» — СНЯТА 03.11.2026,
# и снята потому, что сторож ТРЕБОВАЛ мёртвое обещание.
#
# Занятия удалены 28.10 (`82ba1e46`), пункт «„Не брал еду" в занятии»
# убран из `SubscriptionStore.freeForever` тем же днём. Описание витрины
# держало его ещё шесть дней — а эта пара означала «цитата обязана
# стоять в описании», то есть правка описания красила сторожа, а сторож
# велел вернуть цитату.
#
# > **Сторож, стоящий на цитате, охраняет не связь, а формулировку:**
# > когда формулировка умирает, он просит её вернуть. Пара обязана
# > умирать вместе с предметом, и устройства для этого у неё нет.
#
# Теперь это умеет `Tools/check_list_copies.py`: снятый пункт переносится
# в «снятые» переписи `Tools/копии-списков.json`, и после переноса сторож
# красит каждую копию, которая его ещё держит, — знак обратный.
#
# ОСЬ РАЗВЁРНУТА 04.11.2026, И ЭТО ТОТ ЖЕ УРОК, ТОЛЬКО ПРИМЕНЁННЫЙ
# ПРАВИЛОМ, А НЕ К ОДНОЙ СТРОКЕ.
#
# После `47b1d414` («витрина вернулась в git из ASC») английское
# описание стало ПЕРЕСКАЗОМ и кнопок по именам не зовёт вовсе. Замер
# 03.11.2026: все четыре оставшиеся пары — 0 вхождений, и ворота дали
# четыре находки, то есть попросили вернуть четыре формулировки разом.
#
# > **Сторож требовал цитату, а предмет его — СВЯЗЬ.** Пока ось
# > говорила «цитата обязана стоять», всякая правка текста витрины
# > красила ворота, и красила их тем сильнее, чем честнее копирайтер
# > переписал описание.
#
# Теперь ось обратная: **витрина вольна не цитировать, но если взяла
# имя в типографские кавычки — оно обязано найтись в бандле.** Дефект,
# ради которого ворота заводились («человек пойдёт искать и не
# найдёт»), ловится по-прежнему, а пересказ перестал быть нарушением.
#
# Что это даёт и чего стоит, замерено прежде правки:
#
#     старое описание (47b1d414^)   6 цитат, все шесть сошлись бы
#     новое описание                0 цитат → rc=0 БЕЗ правки витрины
#
# То есть ни одной прошлой находки ось не теряет. Цена названа вслух:
# нулю цитат сторожить нечего, и «зелено» здесь значит «описание
# ничего не обещает», а не «обещанное сошлось». Число цитат поэтому
# ПЕЧАТАЕТСЯ всегда — ноль обязан быть виден, а не выглядеть успехом.
#
# `QUOTE_PAIRS` оставлены и работают второй половиной: пара, которая
# ВСЁ ЕЩЁ стоит в описании, сверяется с каталогом по ключу. Это ловит
# случай, которого широкая ось не видит, — английский перевод ключа
# переписали, цитата осталась законной английской строкой, но
# принадлежит уже другому месту.
#
# ЧЕГО ЭТА ПРАВКА НЕ РЕШАЕТ, и хозяин тут по-прежнему витрина: русское
# описание потеряло свои цитаты тем же коммитом и той же рукой
# (замер 04.11: «Просится», «Непонятно», «Вывожу», «как попросил» —
# 0 вхождений в `ru/description.txt`). Ось выше смотрит только
# на английское, потому что предмет ворот — английский бандл.

# Седьмая цитата убрана из описания 05.10.2026 НАМЕРЕННО: точного ключа
# под «dose → blood draw» нет, строка живёт внутри длинной фразы. Названа
# здесь, чтобы следующий не завёл под неё ключ ради витрины.
REMOVED_QUOTE = "dose → blood draw"


def norm(text):
    """Невидимое к видимому: узкий неразрывный пробел — это пробел.

    У французского «Просится» стоит U+202F перед `?` — правильная
    типографика, из-за которой побайтная сверка покраснела бы на верном
    переводе.
    """
    text = unicodedata.normalize("NFC", text)
    for space in (" ", " ", " "):
        text = text.replace(space, " ")
    return text.strip()


def bundle_languages(app):
    """Языки бандла — папки `.lproj`, в которых есть `Localizable.strings`.

    **Не всякая `.lproj` — язык.** Замер 05.10.2026: `en.lproj` с единственным
    файлом `nlu.appintents` появился в одной сборке из четырёх одного кода
    (его порождает Xcode для английского сам, причина не установлена).
    Считать его языком значит остановить выгрузку из-за служебного
    артефакта, то есть научить не верить красному.
    """
    real, service = {}, {}
    for path in sorted(glob.glob(os.path.join(app, "*.lproj"))):
        code = os.path.basename(path)[:-len(".lproj")]
        if code == "Base":
            continue
        strings = os.path.join(path, "Localizable.strings")
        if os.path.exists(strings):
            real[code] = strings
        else:
            service[code] = sorted(os.listdir(path))
    return real, service


def read_strings(path):
    with open(path, "rb") as handle:
        head = handle.read(8)
    if head.startswith(b"bplist"):
        with open(path, "rb") as handle:
            return plistlib.load(handle)
    # Текстовый .strings бывает у несобранных ресурсов — через plutil,
    # чтобы не писать свой разбор формата.
    out = subprocess.run(["plutil", "-convert", "json", "-o", "-", path],
                         capture_output=True)
    return json.loads(out.stdout) if out.returncode == 0 else {}


def metadata_locales():
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "fastlane/metadata/*"))):
        if not os.path.isdir(path) or not os.path.exists(
                os.path.join(path, "description.txt")):
            continue
        locale = os.path.basename(path)
        out[locale] = locale.split("-")[0]
    return out



def debt_report():
    """Долг вычитки — рядом с зелёным, а не вместо него.

    **Эти ворота — последнее место перед выгрузкой**, и именно здесь
    человек решает отгружать. 05.10.2026 сторож полноты каталога впервые
    напечатал ноль пробелов на всех языках — и ноль читается
    «переведено», хотя значит только «у каждого ключа есть строка».
    Английский в этот день лёг черновиком целиком: ни одной строки
    не читал носитель.

    У нас записано: «пустой результат докладывать так же подробно, как
    находку, и называть, чего он НЕ значит». Напечатанное воротами
    доезжает до того, кто решает; сказанное человеком в журнале
    теряется при первой передаче.
    """
    states = {}
    totals = {}
    for name in ("TogoShared/Resources/Localizable.xcstrings",
                 "Togo/Resources/AppShortcuts.xcstrings"):
        path = os.path.join(ROOT, name)
        if not os.path.exists(path):
            continue
        for body in json.load(open(path, encoding="utf-8"))["strings"].values():
            for language, node in body.get("localizations", {}).items():
                if "stringUnit" in node:
                    marks = [node["stringUnit"].get("state")]
                else:
                    marks = [form.get("stringUnit", {}).get("state")
                             for form in node.get("variations", {})
                             .get("plural", {}).values()]
                totals[language] = totals.get(language, 0) + 1
                if any(m in ("needs_review", "new") for m in marks):
                    states[language] = states.get(language, 0) + 1
    if not states:
        return
    print("\nвычитка носителем:")
    for language in sorted(states):
        print(f"  {language}: непроверенных {states[language]} "
              f"из {totals.get(language, 0)}")
    print("  полнота каталога и вычитка — разные вещи: ноль пробелов "
          "не значит,\n  что строку читал носитель или что её видели "
          "на экране.")


def main():
    app = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_APP
    if not os.path.isdir(app):
        sys.exit(f"нет бандла: {app}\n"
                 f"собери архив (`make archive`) или укажи путь первым аргументом")

    fingerprint = subprocess.run(
        ["shasum", "-a", "256", os.path.join(app, os.path.basename(app)[:-4])],
        capture_output=True, text=True).stdout.split()
    print(f"бандл      {app}")
    if fingerprint:
        print(f"отпечаток  {fingerprint[0][:16]}…  (бинарник)")

    real, service = bundle_languages(app)
    print(f"языки      {sorted(real)}")
    for code, files in service.items():
        print(f"  служебная {code}.lproj без Localizable.strings: {files} — не язык")

    locales = metadata_locales()
    print(f"локали витрины в fastlane/metadata: {sorted(locales)}")

    problems = []

    for locale, language in sorted(locales.items()):
        if language not in real:
            problems.append(
                f"локаль витрины «{locale}» обещает язык «{language}», "
                f"которого в бандле нет.\n"
                f"    Описание на этом языке человек прочтёт, а приложение "
                f"откроется на языке разработки.")

    # Цитаты: сверяем с бандлом, а не с каталогом.
    description = os.path.join(ROOT, "fastlane/metadata/en-US/description.txt")
    цитат_найдено = 0
    if os.path.exists(description) and "en" in real:
        text = open(description, encoding="utf-8").read()
        english = read_strings(real["en"])

        # КОНТРОЛЬ ПЕРВЫМ, И ОН ТУТ НЕ ФОРМАЛЬНОСТЬ. Ось ниже устроена
        # так, что ПУСТОЙ словарь бандла объявил бы несуществующей
        # КАЖДУЮ цитату — лавина находок; а словарь из трёх ключей
        # пропустил бы всё, кроме них. Оба исхода выглядят работой.
        if len(english) < 100:
            problems.append(
                f"из бандла прочитано {len(english)} английских строк — "
                f"это не похоже на каталог приложения.\n"
                f"    Сверка цитат НЕ СОСТОЯЛАСЬ, и её молчание здесь "
                f"ничего не значит.")
            english = None

        if english is not None:
            значения = {norm(v).lower() for v in english.values()}
            цитаты = [norm(c) for c in re.findall(r"“([^”]+)”", text)]
            цитат_найдено = len(цитаты)
            print(f"цитат в кавычках в английском описании: {цитат_найдено}")

            for цитата in цитаты:
                if цитата.lower() in СИСТЕМНЫЕ_ЦИТАТЫ:
                    continue
                if цитата.lower() in значения:
                    continue
                # Цитата есть, строки нет. Подсказываем ближайшую пару,
                # если она опознаётся по ключу: без этого сообщение
                # говорит «не нашлось» и не говорит, где искать.
                ключ = next((k for k, v in QUOTE_PAIRS.items()
                             if norm(v).lower() == цитата.lower()), None)
                адрес = f" (ключ «{ключ}»)" if ключ else ""
                problems.append(
                    f"описание цитирует «{цитата}»{адрес}, а в английском "
                    f"бандле такой строки нет.\n"
                    f"    Человек пойдёт искать и не найдёт.")

            # Вторая половина, и она про ДРУГОЕ: пара, которая ещё стоит
            # в описании, обязана совпасть с каталогом ПО КЛЮЧУ. Это ловит
            # случай, когда английский перевод ключа переписали, а витрину
            # нет: цитата при этом остаётся законной английской строкой,
            # просто принадлежит уже другому месту.
            for key, expected in sorted(QUOTE_PAIRS.items()):
                if norm(expected).lower() not in norm(text).lower():
                    continue
                actual = english.get(key)
                if actual is None:
                    problems.append(
                        f"ключ «{key}» не переведён на английский, а витрина "
                        f"цитирует его как «{expected}».")
                elif norm(actual).lower() != norm(expected).lower():
                    problems.append(
                        f"витрина зовёт «{expected}», приложение говорит "
                        f"«{actual}» (ключ «{key}»).\n"
                        f"    Человек пойдёт искать и не найдёт.")
        if REMOVED_QUOTE in text and f"“{REMOVED_QUOTE}”" in text:
            problems.append(
                f"«{REMOVED_QUOTE}» снова в кавычках в описании. Точного "
                f"ключа под эту строку нет: она живёт внутри длинной фразы. "
                f"Либо убрать кавычки, либо завести ключ — и тогда дописать "
                f"пару сюда.")
    elif os.path.exists(description):
        print("  цитаты не сверялись: английского в бандле нет "
              "(и это уже названо выше проблемой)")

    debt_report()

    print()
    if problems:
        print(f"✘ находок: {len(problems)}")
        for item in problems:
            print(f"  • {item}")
    else:
        print("✔ витрина не обещает языка, которого нет, и цитирует "
              "приложение дословно")

    # Границы собственного умения — последней строкой, а не в чьей-то памяти.
    print("""
Что эти ворота НЕ проверяют:
  · полноту перевода — язык в бандле может быть почти пустым (сторож
    полноты каталога — `LocalizationCoverageTests`);
  · локали, заведённые в App Store Connect и не лежащие в
    `fastlane/metadata` — витрина живёт вне git, сверять её состояние
    отдельно: `Tools/asc_storefront_locale.py <локаль>`;
  · остальной текст описания: сверяется только то, что описание само
    взяло в типографские кавычки — пересказ своими словами ворота
    не трогают;
  · русское описание: ось стоит на английском бандле, и цитаты
    в «…» не сверяются ни с чем;
  · седьмая цитата «dose → blood draw» снята с кавычек намеренно —
    ключа под неё нет и заводить его ради витрины не надо.
Узкий неразрывный пробел, неразрывный и тонкий приравнены к обычному:
иначе правильная французская типографика читалась бы расхождением.""")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
