#!/bin/bash
#
# Отпечаток архива: одно число на всё дерево .xcarchive.
#
# Зачем. «Сборка N собрана из коммита X» — утверждение без основания,
# пока его нечем проверить: xcodebuild архивирует ДИСК, а не коммит.
# Отпечаток превращает «та ли это сборка» из мнения в вопрос с ответом.
#
# Почему заведён только 28.09.2026. Рецепта у Togo не было ВОВСЕ —
# ни одного `shasum` по дереву архива в `Tools/`. При этом числа
# `sha256` за сборки 189 и 191 лежат в `СТАТУС.md`, то есть снимались
# руками и неизвестно чем.
#
#   ЧИСЛА 189 И 191 ИЗ `СТАТУС.md` ЭТИМ СКРИПТОМ НЕ ВОСПРОИЗВОДЯТСЯ.
#   Не сверяй с ними: расхождение будет означать «другой рецепт»,
#   а не «другой архив». Паспорт без предъявителя.
#
# Рецепт согласован с поставкой 28.09 — сортировка обязательна.
# Без `sort` порядок файлов у `find` зависит от файловой системы,
# и тот же архив даёт разные числа: у Timer прежний скрипт выдал
# семь разных на семь запусков, то есть все выданные им паспорта
# не отвечали ни на что.
#
# Имена переменных ТОЛЬКО латиницей. Кириллица в именах переменных
# bash не заводится и не падает: `Д="файл"` отвечает `No such file
# or directory`, а следующая строка выполняется как ни в чём
# не бывало. За 23.09 эта ловушка сработала трижды и один раз
# испортила рабочий файл без отката.

set -u
set -o pipefail

archive="${1:-build/Togo.xcarchive}"

if [ ! -d "$archive" ]; then
    echo "Нет такого архива: $archive" >&2
    echo "Использование: bash Tools/archive_fingerprint.sh [путь/к/Togo.xcarchive]" >&2
    exit 1
fi

# Граница рецепта, названная до числа, а не после.
#
# `xargs` без -0 рвёт имена по пробелам и переводам строк. В архиве
# Apple такие имена встречаются (например «Assets.car» безопасен,
# а вот пути внутри .lproj и dSYM бывают всякие), и если хоть одно
# найдётся — число посчитается, но будет считать не то, что кажется.
# Поэтому проверяем ДО, и громко.
suspicious=$(cd "$archive" && find . -type f -print | grep -c '[[:space:]]' || true)
if [ "$suspicious" -gt 0 ]; then
    echo "ОСТОРОЖНО: $suspicious файлов с пробелом или табом в имени." >&2
    echo "Рецепт с xargs без -0 на них считает НЕ ТО. Число ниже недостоверно." >&2
fi

files=$(cd "$archive" && find . -type f | wc -l | tr -d ' ')

# Тот же рецепт, которым поставка считает 248. Один в один — иначе
# числа не сойдутся, и расхождение прочтут как расхождение архивов.
digest=$(cd "$archive" && find . -type f | sort | xargs shasum -a 256 | shasum -a 256)
rc=$?
if [ $rc -ne 0 ]; then
    echo "Отпечаток не посчитался, код $rc" >&2
    exit $rc
fi

plist="$archive/Info.plist"
build="—"
version="—"
if [ -f "$plist" ]; then
    # Номер берётся из Info.plist АРХИВА, а не из аргумента скрипта
    # сборки: аргумент говорит, что собирались положить, plist —
    # что положили.
    build=$(plutil -extract ApplicationProperties.CFBundleVersion raw "$plist" 2>/dev/null || echo "—")
    version=$(plutil -extract ApplicationProperties.CFBundleShortVersionString raw "$plist" 2>/dev/null || echo "—")
fi

commit=$(git --no-optional-locks rev-parse --short HEAD 2>/dev/null || echo "—")
dirty=$(git --no-optional-locks status --porcelain 2>/dev/null | wc -l | tr -d ' ')

echo "архив    $archive"
echo "версия   $version   сборка $build"
echo "файлов   $files"
echo "sha256   ${digest%% *}"
echo "коммит   $commit"

# Готовый архив в build/ НЕ значит свежий, и это проверяется, а не
# предупреждается.
#
# Повод настоящий: 28.09 в общем `build/` лежала сборка 216 —
# четырёхдневная, разминувшаяся с починкой на 18 минут, — и выглядела
# готовой к выгрузке. `upload_testflight.sh` берёт `build/Togo.xcarchive`
# ОТНОСИТЕЛЬНО текущего каталога: запуск из корня репозитория выгрузил
# бы её с зелёным отчётом.
#
# Номер сборки у Togo — это `git rev-list --count HEAD`
# (`upload_testflight.sh:61`), то есть ожидаемый номер известен точно.
# Сравнение даёт ответ, а не намёк.
expected=$(git --no-optional-locks rev-list --count HEAD 2>/dev/null || echo "")
if [ -n "$expected" ] && [ "$build" != "—" ] && [ "$build" != "$expected" ]; then
    echo "АРХИВ НЕ ОТ ЭТОГО КОММИТА: в нём сборка $build, у HEAD вышла бы $expected" >&2
    echo "Выгружать его сейчас — значит отправить чужой, более старый срез." >&2
fi

# Дерево проверяется отдельно и вслух. Архив берёт диск, а не коммит:
# без этой строки «сборка = коммит» остаётся утверждением без основания.
if [ "$dirty" -gt 0 ]; then
    echo "ДЕРЕВО ГРЯЗНОЕ: $dirty незакоммиченных файлов — «сборка = коммит» здесь НЕВЕРНО" >&2
fi

echo
echo "Граница: число считается по ДЕРЕВУ архива на диске. Оно не говорит,"
echo "из какого коммита архив собран, — только то, что два архива с одним"
echo "числом совпадают пофайлово. Числа 189 и 191 из СТАТУС.md сняты другим"
echo "рецептом и с этим не сравниваются."
