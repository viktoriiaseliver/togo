#!/bin/bash
# Заводит запись в журнале проекта за сегодня и пересобирает оглавление.
#
#   make journal СЛАГ=dozapis-ne-golosovaya
#
# Журнал — не changelog. Changelog отвечает «что изменилось в приложении»,
# журнал — «что делали, почему именно так и что дальше». Через полгода
# полезнее второе.
#
# # Почему слаг ОБЯЗАТЕЛЕН, а не удобен
#
# Прежняя редакция заводила файл по одной дате — `docs/journal/$DATE.md`
# — и при существующем файле печатала «уже есть» и выходила С НУЛЁМ.
# Живая договорённость другая: записей за день несколько, у каждой слаг,
# пишут руками. Отсюда три дефекта, все измерены 15.10.2026:
#
#   1. Запись без слага заведена, строка в оглавление вписана, сам файл
#      в git не уехал — А СТРОКА УЕХАЛА. Оглавление утверждало запись,
#      которой нет: `journal/2026-10-13.md`, битая ссылка с пустым
#      описанием, при двух живых записях за тот же день.
#   2. Выход с нулём при существующем файле — отказ в форме успеха:
#      вторая запись за день молча не заводилась.
#   3. Оглавление отстало на 52 записи из 68, включая все записи
#      за 14.10 и 15.10.
#
# Поэтому слаг проверяется ДО создания чего-либо, а файла без слага
# этот скрипт не заводит вовсе — ни при каких аргументах.
#
# # И одна оплаченная мелочь про сам этот файл
#
# Переменные здесь названы латиницей не из вкуса: **bash не разрешает
# кириллицу в именах переменных.** Первая редакция писала `СЛАГ="${1:-}"`
# и падала на этой строке с `command not found` и кодом 127 — то есть
# отказ по синтаксису приходил в форме «нет такой команды», как будто
# не хватает инструмента. `set -u` от этого не защищает, и прогон
# трёх подделок был единственным, что это нашло. В Makefile
# кириллическое имя цели-параметра (`СЛАГ=`) законно — make не bash,
# и `$(ФАЙЛ)` у соседних целей работает годами.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DATE="$(date +%Y-%m-%d)"
HUMAN="$(date +'%-d %B %Y')"
DIR="$ROOT/docs/journal"
SLUG="${1:-}"

if [ -z "$SLUG" ]; then
    cat >&2 <<'HELP'
Как звать: make journal СЛАГ=<слаг>

Слаг обязателен: за день записей несколько, и различает их только он.
Латиницей, строчными, через дефис — коротко про предмет, не про дату:

    make journal СЛАГ=oglavlenie-rvetsya-mekhanizmom
HELP
    exit 1
fi

if ! printf '%s' "$SLUG" | grep -Eq '^[a-z0-9]+(-[a-z0-9]+)*$'; then
    # Фигурные скобки обязательны: без них bash съедает «»» в ИМЯ
    # переменной и падает «SLUG»: unbound variable», то есть отказ
    # по слагу приходит как отказ по переменной — и человек не видит
    # сообщения вовсе. Поймано подделкой со слагом кириллицей.
    echo "Слаг только латиницей, строчными и через дефис: «${SLUG}» не годится." >&2
    echo "Кириллица в имени файла стоила бы ложных нулей на каждом grep и ls-tree." >&2
    exit 1
fi

FILE="$DIR/$DATE-$SLUG.md"
mkdir -p "$DIR"

if [ -f "$FILE" ]; then
    echo "Запись уже есть: docs/journal/$DATE-$SLUG.md"
    echo "Оглавление пересобираю всё равно — оно могло отстать."
    python3 "$ROOT/Tools/journal_index.py"
    exit 0
fi

cat > "$FILE" <<TEMPLATE
# $HUMAN — $SLUG

## Что сделали

-

## Почему именно так

-

## Что это меняет для человека с собакой

-

## Что дальше и зачем

-

## Открытые вопросы

-
TEMPLATE

echo "docs/journal/$DATE-$SLUG.md"

# Оглавление собирается ЗАНОВО из файлов на диске, а не дописывается
# строкой: дописывание требует, чтобы каждая сессия помнила команду,
# — допущение, которое не сработало 52 раза из 68. Подробности и ось
# приёмки — в голове Tools/journal_index.py.
python3 "$ROOT/Tools/journal_index.py"
