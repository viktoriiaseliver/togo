#!/usr/bin/env python3
"""Цвет пикселя на кадре — без PIL, которого на этой машине нет.

# Зачем это существует

Приёмку цвета в этом проекте решает **замер пикселя на кадре**, а не
взгляд: правило `.claude/rules/токены-и-дизайн.md` записано дословно
так — «проверяется замером пикселя на кадре, а не взглядом: оба кадра
снимались и раньше, подпись читали глазами и соглашались».

А мерить было нечем. На машине нет ни PIL, ни numpy, ни ImageMagick,
ни ffmpeg (замер 26.10.2026, пять имён подряд). `sips` умеет
конвертировать и читать метаданные, но **значение пикселя не отдаёт
вовсе**.

```
magick · convert · ffmpeg   НЕТ
PIL · numpy                 НЕТ
sips                        есть, но -g про пиксель не умеет
```

Поэтому PNG разбирается здесь руками: заголовок, склейка `IDAT`,
`zlib`, снятие построчных фильтров. Формат кадров XCTest —
8 бит на канал, RGB или RGBA, без чередования, то есть ровно тот
случай, который разбирается просто и проверяемо.

# Чего он НЕ делает

Не считает контраст и не судит о прохождении порога: для этого есть
`Tools/contrast_graphite.py`, у которого своя ось (WCAG меряет
яркость). Здесь только «какой цвет лежит в этой точке» — вход для
любого из них.

# Почему координаты в ТОЧКАХ, а не в пикселях

Кадр симулятора приходит в масштабе устройства (3× на iPhone 17 Pro),
и рамка, которую печатает XCUITest, — **в точках**. Сравнивать их
в разных единицах значит промахиваться втрое, поэтому умолчание —
точки, а масштаб берётся из ширины самого кадра делением на ширину
окна, которую называет вызывающий.

Python на машине 3.9.6, поэтому аннотаций `X | None` здесь нет
(замер 21.10.2026: такая аннотация валит файл при определении
функции).
"""
from __future__ import annotations

import argparse
import struct
import sys
import zlib


def прочитать_png(путь):
    """Вернуть (ширина, высота, каналов, байты) — распакованные пиксели."""
    with open(путь, "rb") as ф:
        данные = ф.read()
    if данные[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{путь}: это не PNG")

    смещение = 8
    ширина = высота = глубина = тип_цвета = None
    куски = []
    while смещение < len(данные):
        (длина,) = struct.unpack(">I", данные[смещение:смещение + 4])
        имя = данные[смещение + 4:смещение + 8]
        тело = данные[смещение + 8:смещение + 8 + длина]
        if имя == b"IHDR":
            ширина, высота, глубина, тип_цвета = struct.unpack(">IIBB", тело[:10])
            чередование = тело[12]
            if чередование != 0:
                raise ValueError(f"{путь}: чередование Adam7 не разбираю")
        elif имя == b"IDAT":
            куски.append(тело)
        elif имя == b"IEND":
            break
        смещение += 12 + длина

    if глубина != 8:
        raise ValueError(f"{путь}: {глубина} бит на канал, разбираю только 8")
    каналов = {0: 1, 2: 3, 4: 2, 6: 4}.get(тип_цвета)
    if каналов is None:
        raise ValueError(f"{путь}: тип цвета {тип_цвета} (палитра?) не разбираю")

    сырое = zlib.decompress(b"".join(куски))
    строка_байт = ширина * каналов
    итог = bytearray(высота * строка_байт)

    # Снятие построчных фильтров PNG. Пишется развёрнуто нарочно:
    # ошибка здесь даёт не отказ, а НЕВЕРНЫЙ ЦВЕТ — то есть ложный
    # замер, который выглядит замером.
    позиция = 0
    for y in range(высота):
        фильтр = сырое[позиция]
        позиция += 1
        строка = сырое[позиция:позиция + строка_байт]
        позиция += строка_байт
        начало = y * строка_байт
        выше = начало - строка_байт
        for x in range(строка_байт):
            значение = строка[x]
            слева = итог[начало + x - каналов] if x >= каналов else 0
            сверху = итог[выше + x] if y > 0 else 0
            слева_сверху = итог[выше + x - каналов] if (y > 0 and x >= каналов) else 0
            if фильтр == 0:
                пиксель = значение
            elif фильтр == 1:
                пиксель = значение + слева
            elif фильтр == 2:
                пиксель = значение + сверху
            elif фильтр == 3:
                пиксель = значение + ((слева + сверху) >> 1)
            elif фильтр == 4:
                p = слева + сверху - слева_сверху
                pa, pb, pc = abs(p - слева), abs(p - сверху), abs(p - слева_сверху)
                предсказание = слева if (pa <= pb and pa <= pc) else (
                    сверху if pb <= pc else слева_сверху)
                пиксель = значение + предсказание
            else:
                raise ValueError(f"{путь}: неизвестный фильтр строки {фильтр}")
            итог[начало + x] = пиксель & 0xFF

    return ширина, высота, каналов, bytes(итог)


def цвет(кадр, x, y):
    ширина, высота, каналов, байты = кадр
    if not (0 <= x < ширина and 0 <= y < высота):
        raise ValueError(f"точка ({x}, {y}) вне кадра {ширина}×{высота}")
    начало = (y * ширина + x) * каналов
    if каналов == 1:
        g = байты[начало]
        return (g, g, g)
    return tuple(байты[начало:начало + 3])


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("кадры", nargs="+", help="PNG-файлы (два и больше — сравнение)")
    разбор.add_argument("--точка", action="append", default=[], metavar="X,Y",
                        help="координата; можно несколько раз")
    разбор.add_argument("--окно", type=float, default=0,
                        help="ширина окна в точках; задана — координаты в ТОЧКАХ")
    разбор.add_argument("--отличия", action="store_true",
                        help="посчитать, сколько пикселей отличается у двух кадров")
    дано = разбор.parse_args()

    кадры = [(путь, прочитать_png(путь)) for путь in дано.кадры]
    for путь, к in кадры:
        масштаб = (к[0] / дано.окно) if дано.окно else 1.0
        print(f"{путь}: {к[0]}×{к[1]} px, каналов {к[2]}, масштаб {масштаб:g}")

    for сырая in дано.точка:
        x_т, y_т = (float(ч) for ч in сырая.split(","))
        print(f"\nточка ({x_т:g}, {y_т:g})" + (" pt" if дано.окно else " px"))
        for путь, к in кадры:
            масштаб = (к[0] / дано.окно) if дано.окно else 1.0
            r, g, b = цвет(к, int(x_т * масштаб), int(y_т * масштаб))
            print(f"  {путь.split('/')[-1]:34} #{r:02X}{g:02X}{b:02X}  rgb({r}, {g}, {b})")

    if дано.отличия and len(кадры) >= 2:
        (п1, к1), (п2, к2) = кадры[0], кадры[1]
        if (к1[0], к1[1]) != (к2[0], к2[1]):
            print("\nразмеры разные — сравнивать нечего")
            return 2
        всего = к1[0] * к1[1]
        различных = 0
        for i in range(всего):
            a = к1[3][i * к1[2]:i * к1[2] + 3]
            b = к2[3][i * к2[2]:i * к2[2] + 3]
            if a != b:
                различных += 1
        доля = 100.0 * различных / всего
        print(f"\nотличается пикселей: {различных} из {всего} ({доля:.2f} %)")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
