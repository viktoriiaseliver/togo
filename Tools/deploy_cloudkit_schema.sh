#!/bin/bash
# Выкладывает схему общего дневника в CloudKit.
#
# Зачем: в отладке типы записей CloudKit заводит сам, при первой же
# отправке. В production — не заводит: там схему выкладывают явно.
# Без этого шага обмен в TestFlight молча не работает — записи уходят
# в никуда с ошибкой «unknown record type».
#
# ВАЖНОЕ УТОЧНЕНИЕ, которого здесь не было и которое стоило сверки
# не с тем эталоном: типы и поля заводит первая запись СО ЗНАЧЕНИЕМ.
# Поле, которое человек ни разу не заполнил, в схеме не появляется
# вовсе — ни в development, ни потом в production. Поэтому «прогнали
# отладочный засев» и «схема полна» — разные утверждения, и второе
# из первого не следует.
#
# И две проверки ниже отвечают про РАЗНЫЕ каналы; читать их как одну
# нельзя, это уже случалось 14.10.2026:
#
#   типы без префикса  Dog, LogEvent, Medication…  — ОБЩИЙ ДНЕВНИК,
#                      то, что видит второй человек
#   типы CD_*          CD_Dog, CD_Medication…      — ЗЕРКАЛО приватной
#                      базы, то есть резервная копия в своём iCloud
#
# Один канал может быть полон, когда второй пуст: в тот день зеркало
# CD_Dog имело все 38 полей, а общий дневник Dog — 26 из 35.
#
# Один раз нужен токен управления:
#   1. https://icloud.developer.apple.com/dashboard → Settings → Tokens
#   2. Create Management Token, скопировать
#   3. xcrun cktool save-token --type management
#
# Потом:
#   Tools/deploy_cloudkit_schema.sh
#
# ВАЖНО: последний шаг делается руками, и это не забывчивость.
# Раньше здесь стояло `cktool deploy-schema-changes` — такой команды
# у cktool нет вовсе, и скрипт падал ровно на том шаге, ради которого
# его и писали. Прямой импорт в production CloudKit тоже запрещает:
# «endpoint not applicable in the environment production». Перенос
# development → production делается только кнопкой в дашборде.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

CONTAINER="${CONTAINER:-iCloud.app.togo.diary}"
TEAM="${TEAM:-L7CPH7W5QW}"

echo "Контейнер: $CONTAINER"

# Раньше здесь стоял `import-schema`, и до 22.09 он работал. После того
# как зеркало SwiftData завело в контейнере типы `CD_*`, импорт стал
# невозможен: файл их не описывает, а импорт заменяет схему целиком —
# CloudKit отвечает «invalid attempt to delete cloudkit managed record
# type» и падает. Описывать `CD_*` в файле нельзя тоже: их форму задаёт
# модель, и рукописная копия разошлась бы с ней молча.
#
# Поэтому проверка, а не запись. В development CloudKit заводит типы
# и поля сам при первой отправке, так что толкать их туда не нужно.
# Проверяем ТОТ файл, который импортируется, а не прежний на два типа.
#
# `CloudKit/schema.ckdb` описывает `LogEvent` и `DoseRecord` — им этот
# шаг говорил «✅ Schema is valid» и был прав про них. Живой файл
# импорта — `CloudKit/схема-для-импорта.ckdb`: выгрузка контейнера плюс
# дописанные семь типов и недостающие поля. Проверять надо его: у файла,
# который никуда не едет, годность ничего не значит.
echo "→ проверяю файл схемы"
xcrun cktool validate-schema \
    --team-id "$TEAM" \
    --container-id "$CONTAINER" \
    --environment development \
    --file CloudKit/схема-для-импорта.ckdb

echo "→ проверяю production"
PRODUCTION="$(xcrun cktool export-schema \
    --team-id "$TEAM" \
    --container-id "$CONTAINER" \
    --environment production)"

# Сверяем не только типы, но и поля — и сверяем С КОДОМ, а не с файлом.
#
# Раньше здесь проверялось наличие LogEvent и DoseRecord — и скрипт
# говорил «работает», когда в production не было поля medicationName.
# Отметка дозы при этом валила отправку целиком, а тут было написано,
# что всё хорошо. Проверка, которая не краснеет на сломанном, не
# проверяет ничего.
#
# ЭТО БЫЛА ПОЛОВИНА ПОЧИНКИ, и вторая обошлась в двадцать дней.
# 14.10.2026 замер: эталоном сверки был CloudKit/schema.ckdb, а он
# описывает ДВА типа — LogEvent и DoseRecord. Код к этому дню писал
# ДВЕНАДЦАТЬ. Сверка при этом была верна: в production действительно
# есть всё, что перечислено в файле. Неверен был вопрос, на который
# её звали.
#
#   сверка говорила   «production содержит всё из schema.ckdb»
#   звали её за       «production содержит всё, что пишет код»
#   цена разницы      7 типов и 103 поля из 185 — не заведены,
#                     и ворота пять раз подряд были зелёными
#
# > Сверка с рукописным эталоном отвечает ПРО ЭТАЛОН. Чтобы она
# > отвечала про код, эталон надо выводить из кода — и тогда у него
# > нет отдельной жизни, в которой он мог бы отстать.
#
# Поэтому эталон теперь считает Tools/схема_общего_дневника.py прямо
# из SharedDiaryRecords.swift. Он падает сам, если разбор выродился:
# пустая таблица и «нечего отправлять» на глаз неотличимы.
PROD_FILE="$(mktemp)"
printf '%s\n' "$PRODUCTION" > "$PROD_FILE"
CODE_FILE="$(mktemp)"
if ! python3 Tools/схема_общего_дневника.py --json > "$CODE_FILE" 2>&1; then
    echo
    echo "Разбор кода не состоялся — сверять не с чем, и это отказ, а не «сошлось»:"
    cat "$CODE_FILE"
    rm -f "$PROD_FILE" "$CODE_FILE"
    exit 1
fi
MISSING="$(python3 - "$PROD_FILE" "$CODE_FILE" <<'PY'
import json, re, sys

def parse(path):
    types = {}
    for name, body in re.findall(r'RECORD TYPE (\w+) \((.*?)\)\s*;',
                                 open(path).read(), re.S):
        fields = set()
        for line in body.splitlines():
            line = line.strip().rstrip(',')
            if not line or line.startswith('GRANT'):
                continue
            field = line.split()[0].strip('"')
            if not field.startswith('___'):
                fields.add(field)
        types[name] = fields
    return types

prod = parse(sys.argv[1])
want = {k: set(v) for k, v in json.load(open(sys.argv[2])).items()}
gaps = []
for name, fields in sorted(want.items()):
    if name not in prod:
        gaps.append(f"{name} — типа нет вовсе, полей {len(fields)}")
        continue
    gaps += [f"{name}.{f}" for f in sorted(fields - prod[name])]
print("\n".join(gaps))
PY
)"
rm -f "$PROD_FILE" "$CODE_FILE"

# Вторая проверка: зеркало SwiftData.
#
# Типы `CD_*` заводит не этот файл и не человек, а само зеркало —
# при первой записи объекта, и только в development. Скрипт до 23.09
# о них не знал вовсе и говорил «работает», когда из шестнадцати
# моделей зеркалились пять: прогулки, дозы, занятия, поездки и
# документы не уезжали в iCloud НИ У КОГО, а политика в приложении
# обещала копию базы. Проверка, которая не краснеет на этом,
# проверяет не то место.
echo "→ проверяю зеркало SwiftData"
DEV_FILE="$(mktemp)"
xcrun cktool export-schema \
    --team-id "$TEAM" \
    --container-id "$CONTAINER" \
    --environment development > "$DEV_FILE"
PROD_FILE2="$(mktemp)"
printf '%s\n' "$PRODUCTION" > "$PROD_FILE2"

# Сверку ведёт Tools/derive_cloudkit_mirror.py: он знает правило, по
# которому зеркало превращает поле модели в поле записи, и потому видит
# не только отсутствующие типы, но и отсутствующие ПОЛЯ. Своя проверка
# здесь считала только типы и говорила «все шестнадцать зеркал на
# месте», когда у CD_Dog не хватало десяти полей.
MIRRORS=""
if ! python3 Tools/derive_cloudkit_mirror.py < "$DEV_FILE" > "$DEV_FILE.отчёт" 2>&1; then
    MIRRORS="$(cat "$DEV_FILE.отчёт")"
fi
rm -f "$DEV_FILE.отчёт"
rm -f "$DEV_FILE" "$PROD_FILE2"

# ОБЕ ПРОВЕРКИ ПЕЧАТАЮТСЯ, и выход один — в конце.
#
# До 14.10.2026 здесь стоял `exit 1` сразу после зеркала, и из-за него
# отчёт по общему дневнику не печатался НИКОГДА, пока зеркало неполно.
# А неполно оно с 23.09. В тот день, когда сверку перевели с файла
# на код и она впервые увидела 103 ненайденных поля, человек этого
# отчёта всё равно бы не увидел: его съел ранний выход на меньшей
# находке.
#
# > **Ранний выход — это фильтр, а фильтр, убирающий шум, убирает
# > и улику.** Прятать можно то, что уже объяснено; здесь пряталось
# > то, о чём ещё не знал никто.
if [ -n "$MIRRORS" ]; then
    cat <<MIRROR

Зеркало SwiftData неполно — это не уезжает в iCloud:

$MIRRORS

Файлом это не чинится ни для типа, ни для поля: и то и другое заводит
само зеркало при первой записи СО ЗНАЧЕНИЕМ, и только в development.
Нужен отладочный прогон с живым Apple ID — «Настройки → Отладка ·
завести зеркало в iCloud». После этого — кнопка «Deploy Schema
Changes…» в дашборде.

Пока зеркало неполно, «копия базы лежит в твоей приватной библиотеке
iCloud» из политики — неправда для этих полей.

ЭТО ПЕРВЫЙ ИЗ ДВУХ КАНАЛОВ. Ниже — второй, общий дневник; он про то,
что видит второй человек, и отвечает отдельно.
MIRROR
fi

if [ -z "$MISSING" ] && [ -n "$MIRRORS" ]; then
    echo
    echo "Общий дневник: в production есть все типы и поля, которые"
    echo "ПИШЕТ КОД. Неполно только зеркало — см. выше."
    exit 1
fi

if [ -z "$MISSING" ]; then
    echo
    echo "Готово. В production есть все типы и поля, которые ПИШЕТ КОД"
    echo "(эталон считает Tools/схема_общего_дневника.py из"
    echo "SharedDiaryRecords.swift), и все шестнадцать зеркал SwiftData"
    echo "на месте в обеих средах."
    exit 0
fi

cat <<NOTE

Схема в development обновлена, но в production её ещё нет.
Не хватает:

$MISSING

Перенести development → production умеет только дашборд — у cktool
такой команды нет, а прямой импорт в production CloudKit запрещает.
Одна кнопка, один раз:

  1. https://icloud.developer.apple.com/dashboard
  2. Контейнер $CONTAINER → Schema
  3. «Deploy Schema Changes…» → Deploy

Потом запусти этот скрипт снова — он проверит и скажет, что готово.

ОТКАЗ БУДЕТ НЕ ТОТ, который тут стоял до 26.10.2026, и искать его
надо иначе.

Прежняя редакция говорила «записи уходят с ошибкой unknown record
type». Это описывало состояние, когда в production НЕ БЫЛО ТИПОВ.
Поправка Виктории 26.10.2026: типы там теперь все, и такого отказа
быть не должно — не хватает только ПОЛЕЙ, значит CloudKit отобьёт
не запись целиком, а правку, в которой это поле заполнено.

    типа нет в production    отказ про тип, вся отправка мимо
    поля нет в production    отказ приходит ТОЛЬКО на тех записях,
                             где поле заполнено, — остальные уезжают

Второе коварнее первого: обмен работает, и кажется, что работает
весь. Молчат ровно те записи, которые человек только что тронул.

ТОЧНОЙ ФОРМУЛИРОВКИ ОТКАЗА У НАС НЕТ, и выдумывать её нельзя: она
не измерена ни разу, а записанная наугад похожая строка — это ровно
то, по чему следующий пойдёт грепом и получит ложный ноль. Поэтому:

> **Искать по КОДУ `CKError`, а не по тексту.** Код печатает система,
> текст печатает кто угодно и на языке устройства. Код лежит в логе
> строкой «Общий дневник: правка ПОТЕРЯНА — повтора нет и довода нет.
> Код <N>» (`FamilySync`, ветка `разбор.потеряно`) — и ненулевой
> счётчик потерь там уже сам по себе находка.

Для человека это по-прежнему видно одинаково — «у второго телефона
ничего не появилось», — и именно поэтому различать приходится
по логу, а не по жалобе.
NOTE
exit 1
