#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Контраст пары «текст на фоне» — по ПИКСЕЛЮ кадра, а не по токену.

## Зачем он есть, когда рядом лежат два инструмента про контраст

```
Tools/contrast_graphite.py   пары из CSS-ядра пакета, по ЗНАЧЕНИЯМ hex
Tools/контраст_токенов.py    пары из tokens.json, по ЗНАЧЕНИЯМ hex
этот файл                    пара с КАДРА, по тому, что НАРИСОВАНО
```

Оба соседа печатают свою границу сами: «замер по значениям, не по
кадру; `opacity` на тексте, перекрытие цвета стилем, контур вместо
заливки видны только на пикселе». Этого инструмента до 25.10.2026
не было вовсе — то есть граница была названа, а закрыта не была.

Цена пропуска измерена дважды и обе цены записаны:

* подпись маркера занятия давала **1,00:1** — `#FFFFFF` на `#FFFFFF`,
  слово было невидимо ровно в том состоянии, в котором кнопку жмут;
* главная кнопка давала **1,68:1** при ЗЕЛЁНОМ тесте, проверявшем
  ровно это место: значение `Component.Button.Primary.label` было
  верным, а `AppFont` красил `Text` сам и побеждал `foregroundStyle`.

И третья, снятая этим инструментом в первый же прогон: у выключенных
карточек занятия подпись давала **3,61:1**. Соседи этого не видели
и не могли — `Button.Disabled.*` в `contrast_graphite.py` нет вовсе
(ноль вхождений при живом контроле, замер 25.10.2026).

## Как он отвечает

Берёт прямоугольник кадра в ИСХОДНЫХ пикселях, считает гистограмму
цветов и называет:

```
фон      самый частый цвет прямоугольника
текст    самый далёкий от фона по яркости среди тех, чья доля
         не ниже порога (по умолчанию 0,3 % пикселей рамки)
```

Порог нужен, чтобы сглаживание не выдавало за цвет текста одиночный
пиксель кромки. Доля печатается рядом с числом — **если доля текста
меньше процента, рамка взята мимо глифа, и число не про текст.**

## Два контроля, и они В РАЗНЫХ КАНАЛАХ — это не перестраховка

У нас записаны два правила, которые тянут в разные стороны, и оба
оплачены. Выполнены оба, потому что ловят они разное:

```
--самопроверка   ДРУГОЙ канал: синтетический PNG, чьи пиксели
   (всегда)      известны до запуска, и пары hex, посчитанные рукой
                 по формуле WCAG. Ловит «декодер и арифметика врут
                 СОГЛАСОВАННО» — когда предмет и кадровый контроль
                 ошиблись бы вместе и молча
кадровые пары    ТОТ ЖЕ канал: тот же файл, та же команда, тот же
   («контроль»)  проход. Ловит «замер не состоялся» — рамка мимо,
                 файл подменён, кадр пересняли
```

Почему мало одного кадрового: `(projects-19)` контроль из того же
семейства ломается и чинится ВМЕСТЕ с предметом. Если бы разбор PNG
собирал строку с фильтром Paeth неверно, белый заголовок на чёрном
всё равно дал бы «около двадцати» и сошёлся бы с ожиданием, а серая
подпись на тёмно-сером уехала бы молча. Синтетический кадр проходит
все пять типов фильтра строки и сверяется **побайтно**.

Почему мало одной самопроверки: она ничего не знает о том, тот ли
файл открыт и попала ли рамка в глиф.

**Кадровые контроли объявляются в том же файле пар, что и предмет**,
и считаются тем же проходом. Контроль, прибитый к координатам одного
кадра, но запущенный по любому переданному пути, меряет неизвестно
что и сходится неизвестно почему — так было в первой редакции
этого файла.

## Цветовое пространство объявляет сам файл, и это проверяется

Формула WCAG написана для sRGB. Если кадр придёт в Display P3
(чанк `iCCP`), те же байты значат другой цвет, и число будет
синтаксически безупречным и неверным. Инструмент читает чанки и
**отказывается считать** при `iCCP` без `sRGB`. У витрины 279
измерено: чанк `sRGB` есть, `iCCP` нет.

## Порог

```
обычный текст        4,5:1
повышенный контраст  7,0:1
```

Рядом с числом печатается слово исхода («выходит» / НЕ ХВАТАЕТ):
шапку читают один раз, строку с числом — каждый раз.

Использование:

    python3 Tools/контраст-пикселя.py --самопроверка
    python3 Tools/контраст-пикселя.py кадр.png X Y Ш В "имя пары"
    python3 Tools/контраст-пикселя.py --пары Tools/пары-пикселя.json
    python3 Tools/контраст-пикселя.py --гистограмма кадр.png X Y Ш В

Разбор кадра 1206×2622 чистым питоном идёт около двадцати секунд
(PIL и numpy на этой машине нет — замер запуском, а не догадкой),
поэтому распакованные пиксели кэшируются в `build/.кэш-пикселя/`
по sha256 **содержимого** файла: пересняли кадр — кэш не совпадёт
сам, без чьей-либо памяти о том, что его надо сбросить.
"""

from __future__ import annotations

import hashlib
import json
import os
import struct
import sys
import zlib
from collections import Counter

ПОРОГ_ОБЫЧНЫЙ = 4.5
ПОРОГ_HC = 7.0
ДОЛЯ_ТЕКСТА = 0.003   # 0,3 % пикселей рамки

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КЭШ_НА_ДИСКЕ = os.path.join(КОРЕНЬ, "build", ".кэш-пикселя")


class ОтказЗамера(Exception):
    """Замер не состоялся. Это не ноль контраста и не серый текст."""


# ──────────────────────────────────────────────────────────────────
#  Разбор PNG
# ──────────────────────────────────────────────────────────────────

def разобрать_png(данные, имя="<байты>"):
    """Вернуть (ширина, высота, каналов, байты пикселей).

    Тот же разбор, что в `Tools/замер-кадра.py`: PIL на этой машине нет
    (замер 14.10.2026 запуском, а не предположением). Поддержано ровно
    то, чем снимает симулятор — 8 бит, colortype 2 и 6, без интерлейса.
    """
    d = данные
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        raise ОтказЗамера(f"{имя}: не PNG")

    поз, idat, шапка = 8, bytearray(), None
    есть_srgb = есть_iccp = False
    while поз < len(d):
        (длина,) = struct.unpack(">I", d[поз:поз + 4])
        тип = d[поз + 4:поз + 8]
        тело = d[поз + 8:поз + 8 + длина]
        if тип == b"IHDR":
            шапка = struct.unpack(">IIBBBBB", тело)
        elif тип == b"IDAT":
            idat += тело
        elif тип == b"sRGB":
            есть_srgb = True
        elif тип == b"iCCP":
            есть_iccp = True
        elif тип == b"IEND":
            break
        поз += 12 + длина

    if шапка is None:
        raise ОтказЗамера(f"{имя}: нет IHDR")
    if есть_iccp and not есть_srgb:
        raise ОтказЗамера(
            f"{имя}: в файле чанк iCCP и нет sRGB — байты значат цвет "
            f"в ДРУГОМ пространстве, и формула WCAG к ним неприменима. "
            f"Это отказ, а не низкий контраст.")

    ш, в, бит, цвет, _, _, интерлейс = шапка
    if бит != 8 or интерлейс != 0 or цвет not in (2, 6):
        raise ОтказЗамера(
            f"{имя}: не поддержано — бит={бит} colortype={цвет} "
            f"интерлейс={интерлейс}")

    к = 3 if цвет == 2 else 4
    сырое = zlib.decompress(bytes(idat))
    шаг = ш * к
    итог = bytearray(в * шаг)
    пред = bytearray(шаг)
    p = 0
    for y in range(в):
        ф = сырое[p]
        p += 1
        стр = bytearray(сырое[p:p + шаг])
        p += шаг
        if ф == 0:
            pass
        elif ф == 1:
            for i in range(к, шаг):
                стр[i] = (стр[i] + стр[i - к]) & 255
        elif ф == 2:
            стр = bytearray((a + b) & 255 for a, b in zip(стр, пред))
        elif ф == 3:
            for i in range(шаг):
                a = стр[i - к] if i >= к else 0
                стр[i] = (стр[i] + ((a + пред[i]) >> 1)) & 255
        elif ф == 4:
            for i in range(шаг):
                a = стр[i - к] if i >= к else 0
                b = пред[i]
                c = пред[i - к] if i >= к else 0
                пр = a + b - c
                па, пб, пц = abs(пр - a), abs(пр - b), abs(пр - c)
                стр[i] = (стр[i] + (a if (па <= пб and па <= пц)
                                    else (b if пб <= пц else c))) & 255
        else:
            raise ОтказЗамера(f"{имя}: неизвестный фильтр строки {ф}")
        итог[y * шаг:(y + 1) * шаг] = стр
        пред = стр
    return ш, в, к, итог


_КЭШ = {}


def кадр(путь):
    """Распакованные пиксели. Кэш на диске — по sha256 СОДЕРЖИМОГО.

    Ключ берётся от байтов файла, а не от имени и не от даты: кадр
    пересняли — ключ разошёлся сам. Имя и дата этого не обещают,
    а `mtime` ещё и переживает `git checkout`.
    """
    if путь in _КЭШ:
        return _КЭШ[путь]
    with open(путь, "rb") as ф:
        байты = ф.read()
    ключ = hashlib.sha256(байты).hexdigest()[:32]
    файл_кэша = os.path.join(КЭШ_НА_ДИСКЕ, ключ)
    if os.path.exists(файл_кэша):
        with open(файл_кэша, "rb") as ф:
            ш, в, к = struct.unpack(">IIB", ф.read(9))
            данные = (ш, в, к, bytearray(ф.read()))
    else:
        данные = разобрать_png(байты, os.path.basename(путь))
        os.makedirs(КЭШ_НА_ДИСКЕ, exist_ok=True)
        врем = файл_кэша + f".{os.getpid()}"
        with open(врем, "wb") as ф:
            ф.write(struct.pack(">IIB", данные[0], данные[1], данные[2]))
            ф.write(bytes(данные[3]))
        os.replace(врем, файл_кэша)
    _КЭШ[путь] = данные
    return данные


# ──────────────────────────────────────────────────────────────────
#  Арифметика WCAG
# ──────────────────────────────────────────────────────────────────

def относительная_яркость(rgb):
    """WCAG 2.x relative luminance. sRGB → линейное → Rec.709."""
    части = []
    for c in rgb:
        c = c / 255.0
        части.append(c / 12.92 if c <= 0.04045
                     else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * части[0] + 0.7152 * части[1] + 0.0722 * части[2]


def контраст(a, b):
    la, lb = относительная_яркость(a), относительная_яркость(b)
    светлее, темнее = max(la, lb), min(la, lb)
    return (светлее + 0.05) / (темнее + 0.05)


def из_hex(s):
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))


def hex16(c):
    return "#%02X%02X%02X" % c


# ──────────────────────────────────────────────────────────────────
#  Замер по рамке
# ──────────────────────────────────────────────────────────────────

def гистограмма(путь, x, y, ш_р, в_р):
    ш, в, к, пиксели = кадр(путь)
    if x < 0 or y < 0 or x + ш_р > ш or y + в_р > в:
        raise ОтказЗамера(
            f"рамка {x},{y} {ш_р}×{в_р} выходит за кадр {ш}×{в}")
    счёт = Counter()
    for ry in range(y, y + в_р):
        база = ry * ш * к
        for rx in range(x, x + ш_р):
            i = база + rx * к
            счёт[(пиксели[i], пиксели[i + 1], пиксели[i + 2])] += 1
    return счёт, ш_р * в_р


def пара(путь, x, y, ш_р, в_р, доля_текста=ДОЛЯ_ТЕКСТА):
    """Вернуть (фон, доля_фона, текст, доля_текста, контраст)."""
    счёт, всего = гистограмма(путь, x, y, ш_р, в_р)
    фон, фон_n = счёт.most_common(1)[0]
    яф = относительная_яркость(фон)
    порог = max(5, int(всего * доля_текста))

    лучший, лучший_n, лучшая_дельта = фон, фон_n, -1.0
    for цвет, n in счёт.items():
        if n < порог:
            continue
        дельта = abs(относительная_яркость(цвет) - яф)
        if дельта > лучшая_дельта:
            лучший, лучший_n, лучшая_дельта = цвет, n, дельта
    return (фон, фон_n / всего, лучший, лучший_n / всего,
            контраст(фон, лучший))


def строка(имя, путь, x, y, ш_р, в_р, порог=ПОРОГ_ОБЫЧНЫЙ):
    try:
        фон, дф, текст, дт, к = пара(путь, x, y, ш_р, в_р)
    except ОтказЗамера as e:
        print(f"  ОТКАЗ      {имя}: {e}")
        return None
    исход = "выходит" if к >= порог else "НЕ ХВАТАЕТ"
    мимо = "  ← ДОЛЯ МАЛА, рамка могла пройти мимо глифа" if дт < 0.01 else ""
    print(f"  {к:5.2f}:1  {исход:10s}  {имя}")
    print(f"            текст {hex16(текст)} ({дт:.1%})  "
          f"на фоне {hex16(фон)} ({дф:.1%})  порог {порог}{мимо}")
    return к


# ──────────────────────────────────────────────────────────────────
#  Контроль 1: ДРУГОЙ канал — синтетика и арифметика
# ──────────────────────────────────────────────────────────────────

def _собрать_png(ширина, высота, пиксели, фильтры):
    """Собрать PNG с ЗАДАННЫМ типом фильтра у каждой строки."""
    шаг = ширина * 3
    сырое = bytearray()
    пред = bytearray(шаг)
    for y in range(высота):
        ф = фильтры[y % len(фильтры)]
        стр = bytearray(пиксели[y * шаг:(y + 1) * шаг])
        вых = bytearray(шаг)
        for i in range(шаг):
            a = стр[i - 3] if i >= 3 else 0
            b = пред[i]
            c = пред[i - 3] if i >= 3 else 0
            if ф == 0:
                вых[i] = стр[i]
            elif ф == 1:
                вых[i] = (стр[i] - a) & 255
            elif ф == 2:
                вых[i] = (стр[i] - b) & 255
            elif ф == 3:
                вых[i] = (стр[i] - ((a + b) >> 1)) & 255
            else:
                пр = a + b - c
                па, пб, пц = abs(пр - a), abs(пр - b), abs(пр - c)
                вых[i] = (стр[i] - (a if (па <= пб and па <= пц)
                                    else (b if пб <= пц else c))) & 255
        сырое += bytes([ф]) + вых
        пред = стр

    def чанк(тип, тело):
        return (struct.pack(">I", len(тело)) + тип + тело
                + struct.pack(">I", zlib.crc32(тип + тело) & 0xFFFFFFFF))

    return (b"\x89PNG\r\n\x1a\n"
            + чанк(b"IHDR", struct.pack(">IIBBBBB", ширина, высота,
                                        8, 2, 0, 0, 0))
            + чанк(b"sRGB", b"\x00")
            + чанк(b"IDAT", zlib.compress(bytes(сырое)))
            + чанк(b"IEND", b""))


# Пары, посчитанные РУКОЙ по формуле WCAG 2.x, а не этим файлом.
# `#767676` на белом — документированная граница 4,5 у W3C; соседнее
# `#777777` её уже не проходит. Если арифметика уедет, разойдётся
# знак исхода у двух соседних серых, а не только третий знак числа.
#
# ТРИ ЧИСТЫХ КАНАЛА ЗДЕСЬ ОБЯЗАТЕЛЬНЫ, и это замер, а не осторожность.
# 25.10.2026 я подменил веса Rec.709 (0,2126 / 0,7152 / 0,0722) на три
# равные трети и прогнал этот список. Из шести пар подделку поймала
# ОДНА. Причина по устройству: у нейтрального серого R=G=B, и тогда
# ЛЮБЫЕ веса, дающие в сумме единицу, возвращают то же число. Контроль
# из одних серых не способен увидеть неверный вес канала вовсе —
# он меряет не то, что проверяет. Красный, зелёный и синий порознь
# прибивают каждый вес по отдельности.
АРИФМЕТИКА = [
    ("#FFFFFF", "#000000", 21.00, "белое на чёрном — предел шкалы"),
    ("#000000", "#FFFFFF", 21.00, "тот же предел наоборот"),
    ("#FFFFFF", "#FFFFFF", 1.00, "цвет сам с собой — низ шкалы"),
    ("#767676", "#FFFFFF", 4.54, "граница W3C: ПРОХОДИТ 4,5"),
    ("#777777", "#FFFFFF", 4.48, "на тон светлее: НЕ ПРОХОДИТ"),
    ("#FF0000", "#FFFFFF", 4.00, "вес КРАСНОГО 0,2126 порознь"),
    ("#00FF00", "#000000", 15.30, "вес ЗЕЛЁНОГО 0,7152 порознь"),
    ("#0000FF", "#FFFFFF", 8.59, "вес СИНЕГО 0,0722 порознь"),
    ("#6F6F72", "#161617", 3.61, "подпись выключенной карточки 04"),
]


def _шумное_поле(ш, в):
    """Детерминированный шум: соседние строки и пиксели РАЗНЫЕ.

    Нужен именно шум, и это тоже замер. Первая редакция брала картинку
    из двух сплошных половин — у неё все строки одинаковы, и тогда
    предсказатели Up, Paeth и Average дают один и тот же байт.
    Подделка «считать Paeth как Up» прошла такую самопроверку
    ЗЕЛЁНОЙ. Картинка, у которой строки не отличаются, не отличает
    и фильтры: контроль был на вид полным и не мог покраснеть.
    """
    с = 0x2545F491
    поле = bytearray()
    for _ in range(ш * в * 3):
        с = (с * 1103515245 + 12345) & 0x7FFFFFFF
        поле.append((с >> 16) & 255)
    return поле


def самопроверка():
    """Контроль в ДРУГОМ канале: синтетика + арифметика рукой."""
    print("САМОПРОВЕРКА — другой канал, чем кадры")
    ок = True

    print("  арифметика WCAG против чисел, посчитанных рукой:")
    for a, b, ждали, что in АРИФМЕТИКА:
        дали = контраст(из_hex(a), из_hex(b))
        сошлось = abs(дали - ждали) < 0.005 * max(1.0, ждали)
        ок &= сошлось
        print(f"    {a} на {b}  ждали {ждали:5.2f}  дали {дали:5.2f}  "
              f"{'сошлось' if сошлось else 'НЕ СОШЛОСЬ'}   {что}")

    # Кадр для ДЕКОДЕРА: шум, у которого ни одна строка не повторяет
    # соседнюю, и все пять типов фильтра по кругу. Сверка побайтная.
    шш, шв = 60, 50
    шум = _шумное_поле(шш, шв)
    print("  разбор PNG против пикселей, известных до запуска:")
    try:
        ш2, в2, к2, вышло = разобрать_png(
            _собрать_png(шш, шв, шум, [0, 1, 2, 3, 4]), "<шум>")
        побайтно = (ш2 == шш and в2 == шв and к2 == 3 and вышло == шум)
        ок &= побайтно
        расход = sum(1 for a, b in zip(вышло, шум) if a != b)
        print(f"    шум {шш}×{шв}, 5 типов фильтра строки (0,1,2,3,4)  "
              f"{'совпало ПОБАЙТНО' if побайтно else f'РАЗОШЛОСЬ в {расход} байтах'}")
    except ОтказЗамера as e:
        ок = False
        побайтно = False
        print(f"    РАЗБОР ОТКАЗАЛ: {e}")

    # Кадр для КОНВЕЙЕРА: две заливки, чтобы у пары был известный ответ.
    ш, в = 60, 50
    лево, право = из_hex("#123456"), из_hex("#ABCDEF")
    пиксели = bytearray()
    for _ in range(в):
        for x in range(ш):
            пиксели += bytes(лево if x < ш // 2 else право)
    байты = _собрать_png(ш, в, пиксели, [0, 1, 2, 3, 4])

    if побайтно:
        # Та же рамка через весь конвейер: гистограмма + выбор пары.
        врем = os.path.join(КЭШ_НА_ДИСКЕ, f"самопроверка-{os.getpid()}.png")
        os.makedirs(КЭШ_НА_ДИСКЕ, exist_ok=True)
        with open(врем, "wb") as ф:
            ф.write(байты)
        try:
            фон, дф, текст, дт, к = пара(врем, 0, 0, ш, в)
            ждали = контраст(лево, право)
            конвейер = (abs(к - ждали) < 0.01
                        and {hex16(фон), hex16(текст)}
                        == {"#123456", "#ABCDEF"})
            ок &= конвейер
            print(f"    весь конвейер на той же синтетике: "
                  f"{hex16(текст)} на {hex16(фон)}  {к:5.2f}:1  "
                  f"ждали {ждали:5.2f}  "
                  f"{'сошлось' if конвейер else 'НЕ СОШЛОСЬ'}")

            # Отрицательный: рамка целиком в одной половине — текста
            # нет, доля «текста» обязана быть 100 % и контраст 1,00.
            _, _, _, дт0, к0 = пара(врем, 0, 0, ш // 2, в)
            пусто = abs(к0 - 1.0) < 0.001 and дт0 > 0.99
            ок &= пусто
            print(f"    отрицательный: рамка в одноцветной половине  "
                  f"{к0:5.2f}:1  доля «текста» {дт0:.0%}  "
                  f"{'сошлось' if пусто else 'НЕ СОШЛОСЬ — в пустоте нашёлся текст'}")
        finally:
            _КЭШ.pop(врем, None)
            if os.path.exists(врем):
                os.remove(врем)

    print("  ИТОГ САМОПРОВЕРКИ: "
          + ("инструмент воспроизвёл всё известное"
             if ок else "ИНСТРУМЕНТ НЕ ВОСПРОИЗВЁЛ ИЗВЕСТНОЕ"))
    return ок


