#  Контроль 2: ТОТ ЖЕ канал — пары с кадра, объявленные в файле пар
# ──────────────────────────────────────────────────────────────────

def кадровый_контроль(контроли):
    """Пары с кадров, чей ответ известен ДО запуска.

    Лежат в том же файле пар и считаются тем же проходом, что предмет:
    контроль, снятый отдельной командой, отвечает про другой вызов
    и про другое состояние файла.
    """
    print("\nКОНТРОЛЬ НА КАДРАХ — тот же канал, тот же проход")
    ок = True
    for к in контроли:
        имя = к["имя"]
        try:
            фон, дф, текст, дт, зн = пара(
                к["кадр"], к["x"], к["y"], к["ш"], к["в"])
        except ОтказЗамера as e:
            print(f"  ОТКАЗ  {имя}: {e}")
            ок = False
            continue
        низ = к.get("не_ниже")
        верх = к.get("не_выше")
        сошлось = ((низ is None or зн >= низ)
                   and (верх is None or зн <= верх))
        ок &= сошлось
        ждали = (f"≥ {низ}" if верх is None else
                 (f"≤ {верх}" if низ is None else f"{низ}…{верх}"))
        print(f"  {зн:5.2f}:1  ждали {ждали:9s}  "
              f"{'сошлось' if сошлось else 'НЕ СОШЛОСЬ'}  {имя}")
        print(f"            {hex16(текст)} ({дт:.1%}) на {hex16(фон)} ({дф:.1%})")
    return ок


