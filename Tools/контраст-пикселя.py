def main(арг):
    if not арг:
        print(__doc__)
        return 2

    if арг[0] == "--самопроверка":
        return 0 if самопроверка() else 1

    if арг[0] == "--гистограмма":
        путь, x, y, ш_р, в_р = арг[1], *map(int, арг[2:6])
        счёт, всего = гистограмма(путь, x, y, ш_р, в_р)
        print(f"{путь}  рамка {x},{y} {ш_р}×{в_р}  {всего} пикселей")
        for цвет, n in счёт.most_common(10):
            print(f"  {hex16(цвет)}  {n:7d}  {n / всего:6.2%}  "
                  f"яркость {относительная_яркость(цвет):.4f}")
        return 0

    if арг[0] == "--пары":
        with open(арг[1], encoding="utf-8") as ф:
            набор = json.load(ф)

        # Самопроверка идёт ПЕРВОЙ и в том же прогоне: если инструмент
        # не воспроизвёл известного, числа ниже замером не являются.
        здоров = самопроверка()

        плохих, всего_пар, текущий = 0, 0, None
        print("\nПРЕДМЕТ")
        for п in набор["пары"]:
            if п.get("кадр") != текущий:
                текущий = п["кадр"]
                print(f"\n{os.path.basename(текущий)}")
            порог = ПОРОГ_HC if п.get("hc") else ПОРОГ_ОБЫЧНЫЙ
            зн = строка(п["имя"], п["кадр"], п["x"], п["y"],
                        п["ш"], п["в"], порог)
            всего_пар += 1
            if зн is None or зн < порог:
                плохих += 1

        кадрами = кадровый_контроль(набор.get("контроль", []))

        print(f"\nНЕ ХВАТАЕТ порога: {плохих} пар из {всего_пар}")
        if not (здоров and кадрами):
            print("КОНТРОЛЬ НЕ СОШЁЛСЯ — числа выше замером НЕ ЯВЛЯЮТСЯ.")
            return 2
        return 1 if плохих else 0

    путь, x, y, ш_р, в_р = арг[0], *map(int, арг[1:5])
    имя = арг[5] if len(арг) > 5 else f"рамка {x},{y}"
    зн = строка(имя, путь, x, y, ш_р, в_р)
    return 0 if (зн is not None and зн >= ПОРОГ_ОБЫЧНЫЙ) else 1


