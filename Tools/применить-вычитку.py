#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Применить правки вычитки к Localizable.xcstrings. Временный, 27.10.2026.

Правки приходят списком от вычитки по языкам:
    {"ключ", "путь", "было", "стало", "почему"}

ПОЧЕМУ ПРАВКА ТЕКСТОМ, А НЕ json.dump. Каталог — общий файл на 3,7 МБ,
и `json.dump` переписал бы ФОРМАТ всего файла: Xcode пишет
`"ключ" : значение` с пробелом перед двоеточием, Python без него.
Это оплачено 15.10.2026 на соседнем файле — 94 951 строка дифа вместо
двух. Поэтому здесь замена по точному вхождению, а объект разбирается
только для проверок.

КОНТРОЛЬ «БЫЛО», И ОН ГЛАВНЫЙ. Правка применяется, только если текущее
значение совпадает с тем, что вычитка видела. Иначе правка устарела:
между выгрузкой и применением строку мог сменить кто-то ещё, и наш
`стало` затёр бы чужую работу молча. Несовпавшие не применяются и
печатаются отдельным списком — это находка, а не досада.
"""
from __future__ import annotations
import json
import re
import sys

КАТАЛОГ = "TogoShared/Resources/Localizable.xcstrings"


def узел_языка(запись: dict, язык: str, путь: str):
    """Спуск к stringUnit по пути вычитки ('' либо 'plural/one')."""
    место = (запись.get("localizations") or {}).get(язык)
    if место is None:
        return None
    for шаг in [ш for ш in путь.split("/") if ш]:
        место = (место or {}).get(шаг)
        if место is None:
            return None
    return (место or {}).get("stringUnit")


def применить(язык: str, правки: list, сырой: str, данные: dict):
    применено, устарело, ненайдено = [], [], []
    for п in правки:
        ключ, путь = п["ключ"], п.get("путь", "")
        стало, было = п["стало"], п["было"]
        запись = данные["strings"].get(ключ)
        if запись is None:
            ненайдено.append((ключ, "ключа нет в каталоге"))
            continue
        ед = узел_языка(запись, язык, путь)
        if ед is None:
            ненайдено.append((ключ, f"нет узла {язык}/{путь or 'stringUnit'}"))
            continue
        текущее = ед.get("value", "")
        if текущее != было:
            устарело.append((ключ, текущее, было))
            continue
        if текущее == стало:
            continue

        # Замена в ТЕКСТЕ: ищем блок ключа, внутри него — блок языка,
        # внутри него — ровно одну пару state/value. Узко нарочно:
        # одно и то же значение встречается у разных ключей, и
        # глобальная замена задела бы чужие.
        метка = f'\n    "{экранировать(ключ)}" : {{'
        i = сырой.find(метка)
        if i < 0:
            ненайдено.append((ключ, "блок ключа не найден в тексте"))
            continue
        j = сырой.find('\n    "', i + len(метка))
        if j < 0:
            j = len(сырой)
        блок = сырой[i:j]
        старое_знач = f'"value" : "{экранировать(было)}"'
        новое_знач = f'"value" : "{экранировать(стало)}"'
        if блок.count(старое_знач) != 1:
            ненайдено.append(
                (ключ, f"в блоке {блок.count(старое_знач)} вхождений значения, нужно ровно 1"))
            continue
        новый = блок.replace(старое_знач, новое_знач)
        новый = пометить(новый, старое_знач, новое_знач)
        сырой = сырой[:i] + новый + сырой[j:]
        применено.append((ключ, было, стало))
    return сырой, применено, устарело, ненайдено


def пометить(блок: str, старое: str, новое: str) -> str:
    """Рядом с поправленным значением состояние становится translated.

    Состояние и значение лежат в одном объекте, причём state ВЫШЕ
    value — ищем ближайший предшествующий needs_review.
    """
    i = блок.find(новое)
    if i < 0:
        return блок
    начало = блок.rfind('"state" : "needs_review"', 0, i)
    if начало < 0:
        return блок
    return блок[:начало] + '"state" : "translated"' + блок[начало + len('"state" : "needs_review"'):]


def экранировать(s: str) -> str:
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\t", "\\t"))


def главное() -> int:
    языки = sys.argv[1:] or ["en", "fr", "kk", "uk"]
    сырой = open(КАТАЛОГ, encoding="utf-8").read()
    данные = json.loads(сырой)

    итог = {}
    for язык in языки:
        путь = f"/tmp/вычитка/правки-{язык}.json"
        try:
            правки = json.load(open(путь, encoding="utf-8"))
        except FileNotFoundError:
            print(f"{язык}: файла правок нет — пропускаю")
            continue
        сырой, прим, уст, нет = применить(язык, правки, сырой, данные)
        итог[язык] = (len(правки), прим, уст, нет)

    # Приёмка ПЕРЕД записью: файл обязан остаться валидным JSON,
    # и число ключей не должно измениться ни на один.
    новые = json.loads(сырой)
    было_ключей = len(данные["strings"])
    стало_ключей = len(новые["strings"])
    if было_ключей != стало_ключей:
        print(f"ОТКАЗ: ключей было {было_ключей}, стало {стало_ключей}")
        return 1

    open(КАТАЛОГ, "w", encoding="utf-8").write(сырой)

    for язык, (всего, прим, уст, нет) in итог.items():
        print(f"\n=== {язык}: предложено {всего} ===")
        print(f"  применено: {len(прим)}")
        for к, б, с in прим[:60]:
            print(f"     {к[:38]!r}: {б[:30]!r} → {с[:30]!r}")
        if уст:
            print(f"  УСТАРЕЛО (значение сменилось между выгрузкой и правкой): {len(уст)}")
            for к, тек, б in уст[:20]:
                print(f"     {к[:38]!r}: сейчас {тек[:28]!r}, вычитка видела {б[:28]!r}")
        if нет:
            print(f"  НЕ ПРИМЕНЕНО: {len(нет)}")
            for к, п in нет[:20]:
                print(f"     {к[:38]!r}: {п}")
    print(f"\nключей в каталоге: {стало_ключей} (не изменилось)")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
