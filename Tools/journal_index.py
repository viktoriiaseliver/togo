#!/usr/bin/env python3
"""Пересобирает docs/JOURNAL.md из файлов docs/journal/ на диске.

    make journal-index

# Почему пересборка, а не дописывание строки

Дописывание требует, чтобы КАЖДАЯ сессия помнила вызвать команду.
Замер 15.10.2026: это допущение не сработало 52 раза из 68 — именно
столько записей лежало на диске мимо оглавления, включая все записи
за 14.10 и 15.10. Пересборка сходится независимо от того, кто что
забыл, и битая ссылка исчезает ПО ПОСТРОЕНИЮ, а не починкой.

# Чего этот скрипт НЕ делает, и это главное

**Он никогда не перезаписывает описание, написанное рукой.**

Замер того же дня: шестнадцать описаний в оглавлении — плотные сводки,
написанные людьми («приложение подтверждало галочкой запись, которой
не сделало…»). Первый абзац самой записи — это учётная шапка («Сессия
`projects-b9`. Предмет взят из…»). То есть пересборка «описание берём
из первого абзаца» СНЕСЛА БЫ шестнадцать сводок и подставила вместо
них шум, причём молча и необратимо.

Поэтому ось такая: описание существующей строки переносится дословно,
генерируется только у тех записей, у которых строки НЕ БЫЛО. Скрипт
идемпотентен: второй прогон подряд не меняет файл.

# Откуда берётся описание у новой записи

Из хвоста заголовка после тире: «# 8 октября 2026 — дозапись: не долг,
а модуль с переопределённой формой» → «дозапись: не долг, а модуль
с переопределённой формой». Хвост заголовка несёт ПРЕДМЕТ, а первый
абзац — учёт; дату несёт имя файла, и в описании она не нужна.
Если тире в заголовке нет — первая фраза первого абзаца, и это
худший случай, а не обычный: такую строку человек потом перепишет,
и скрипт её больше не тронет.
"""

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
КАТАЛОГ = КОРЕНЬ / "docs" / "journal"
ОГЛАВЛЕНИЕ = КОРЕНЬ / "docs" / "JOURNAL.md"

ШАПКА = """# Журнал проекта

Не changelog. Changelog отвечает на вопрос «что изменилось
в приложении», журнал — «что делали, почему именно так и что дальше».
Через полгода полезнее второе: решения забываются быстрее кода.

Новая запись заводится командой `make journal СЛАГ=<слаг>`. Оглавление
пересобирается из файлов на диске — `make journal-index`; описание,
написанное рукой, пересборка не трогает.
"""

МЕСЯЦЫ = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля",
    5: "мая", 6: "июня", 7: "июля", 8: "августа",
    9: "сентября", 10: "октября", 11: "ноября", 12: "декабря",
}

# Имя файла: YYYY-MM-DD[-слаг].md
ИМЯ = re.compile(r"^(\d{4})-(\d{2})-(\d{2})(?:-(.+))?\.md$")
# Строка оглавления: - [текст](journal/файл.md) — описание
СТРОКА = re.compile(r"^- \[(?P<текст>[^\]]*)\]\(journal/(?P<файл>[^)]+)\)"
                    r"(?:\s+—\s*(?P<описание>.*))?$")


def человеческая_дата(год: int, месяц: int, день: int) -> str:
    return f"{день} {МЕСЯЦЫ[месяц]} {год}"


def прочитать_оглавление() -> dict[str, dict[str, str]]:
    """Что уже написано рукой — по имени файла, на который ссылаются."""
    если_нет: dict[str, dict[str, str]] = {}
    if not ОГЛАВЛЕНИЕ.exists():
        return если_нет
    for сырая in ОГЛАВЛЕНИЕ.read_text(encoding="utf-8").splitlines():
        совпало = СТРОКА.match(сырая.strip())
        if not совпало:
            continue
        описание = (совпало.group("описание") or "").strip()
        если_нет[совпало.group("файл")] = {
            "текст": совпало.group("текст").strip(),
            "описание": описание,
        }
    return если_нет


def разобрать_запись(путь: Path) -> tuple[str, str, str]:
    """Заголовок записи, хвост заголовка после тире и первый абзац.

    Третий запасной источник — первый подзаголовок `## …`. Он нужен
    для записей вида «# 24.09.2026»: ни хвоста, ни абзаца у них нет,
    а предмет назван именно подзаголовком. Без этого запаса строка
    осталась бы с пустым описанием — ровно тот вид, который и выдал
    сломанный механизм 13.10.
    """
    заголовок, абзац, подзаголовок = "", "", ""
    строки = путь.read_text(encoding="utf-8").splitlines()
    for индекс, строка in enumerate(строки):
        if строка.startswith("# "):
            заголовок = строка[2:].strip()
            остаток = [s.strip() for s in строки[индекс + 1:]]
            куски: list[str] = []
            for s in остаток:
                if s.startswith("#"):
                    break
                if s:
                    куски.append(s)
                elif куски:
                    break
            абзац = " ".join(куски)
            for s in остаток:
                if s.startswith("## "):
                    подзаголовок = s[3:].strip()
                    break
            break
    абзац = абзац or подзаголовок
    # Тире бывает трёх видов, и в заголовках проекта встречаются все.
    for тире in ("—", "–", " - "):
        if тире in заголовок:
            return заголовок, заголовок.split(тире, 1)[1].strip(), абзац
    return заголовок, "", абзац


def первая_фраза(текст: str) -> str:
    if not текст:
        return ""
    точка = re.search(r"(?<!\d)\.\s", текст + " ")
    фраза = текст[: точка.start()] if точка else текст
    return фраза.strip().rstrip(".")


def проверить() -> int:
    """Сходится ли оглавление с диском. Для приёмки и для сторожа.

    Нужно потому, что между пересборкой и коммитом в общем дереве
    лежат минуты, а за минуты файл появляется и исчезает: замер
    15.10.2026 — чужая сессия завела запись, пересборка её вписала,
    через минуту файла не стало, и строка осталась висеть. Пересборка
    лечит состояние, а эта проверка — ПРАВО закоммитить, и звать её
    надо непосредственно перед `git commit`, а не за минуту до.
    """
    было = прочитать_оглавление()
    на_диске = {
        путь.name for путь in КАТАЛОГ.glob("*.md") if ИМЯ.match(путь.name)
    }
    строка_без_файла = sorted(set(было) - на_диске)
    файл_без_строки = sorted(на_диске - set(было))
    пустые = sorted(ф for ф, з in было.items() if not з["описание"])

    for имя, список in (("строка без файла", строка_без_файла),
                        ("файл без строки", файл_без_строки),
                        ("строка с пустым описанием", пустые)):
        print(f"{имя}: {len(список)}" + (f" — {', '.join(список)}" if список else ""))

    плохо = len(строка_без_файла) + len(файл_без_строки) + len(пустые)
    print("СХОДИТСЯ" if not плохо else "РАСХОДИТСЯ — нужен make journal-index")
    return 0 if not плохо else 1


def собрать() -> int:
    if not КАТАЛОГ.is_dir():
        print(f"нет каталога {КАТАЛОГ}", file=sys.stderr)
        return 1

    было = прочитать_оглавление()
    записи = []
    for путь in sorted(КАТАЛОГ.glob("*.md")):
        совпало = ИМЯ.match(путь.name)
        if not совпало:
            print(f"пропущено, имя не по форме: {путь.name}", file=sys.stderr)
            continue
        год, месяц, день = (int(совпало.group(номер)) for номер in (1, 2, 3))
        прежнее = было.get(путь.name)
        _, хвост, абзац = разобрать_запись(путь)

        if прежнее and прежнее["описание"]:
            описание, откуда = прежнее["описание"], "перенесено"
        else:
            описание = хвост or первая_фраза(абзац)
            откуда = "сгенерировано"

        if прежнее and прежнее["текст"]:
            текст = прежнее["текст"]
        else:
            дата = человеческая_дата(год, месяц, день)
            текст = f"{дата} — {хвост}" if хвост else дата

        записи.append({
            "ключ": (год, месяц, день, путь.name),
            "файл": путь.name,
            "текст": текст,
            "описание": описание,
            "откуда": откуда,
        })

    записи.sort(key=lambda з: з["ключ"], reverse=True)

    куски = [ШАПКА, ""]
    for з in записи:
        строка = f"- [{з['текст']}](journal/{з['файл']})"
        if з["описание"]:
            строка += f" — {з['описание']}"
        куски.append(строка)
    ОГЛАВЛЕНИЕ.write_text("\n".join(куски) + "\n", encoding="utf-8")

    перенесено = sum(1 for з in записи if з["откуда"] == "перенесено")
    живые = {з["файл"] for з in записи}
    битые = sorted(set(было) - живые)

    print(f"записей на диске      {len(записи)}")
    print(f"строк было            {len(было)}")
    print(f"описаний перенесено   {перенесено}")
    print(f"описаний сгенерировано {len(записи) - перенесено}")
    print(f"битых ссылок убрано   {len(битые)}"
          + (f" — {', '.join(битые)}" if битые else ""))
    return 0


if __name__ == "__main__":
    if "--проверить" in sys.argv[1:]:
        sys.exit(проверить())
    sys.exit(собрать())
