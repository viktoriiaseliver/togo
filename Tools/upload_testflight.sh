# и заметки новой сборки уедут прежней, а перечитанный состав группы
# это ПОДТВЕРДИТ, потому что отвечает на «то ли положили», а не
# «то ли взяли». Ворота номера там теперь стоят; эти — первые из двух.
#
# Почему опрос, а не один запрос: обработка занимает 5–30 минут,
# и сборка появляется в списке не сразу. Один запрос дал бы отказ
# на здоровом случае — а ложная тревога дороже пропущенного дефекта:
# после третьего раза сторожа перестают читать.
#
# Приёмка — ПОЯВЛЕНИЕ НОМЕРА в списке, а не `processingState`:
# «залито» и «обработано» разные вопросы, и здесь задан первый.
echo "── приёмка прибытия: спрашиваю App Store Connect про $BUILD"
ARRIVAL_RC=0
BUILD="$BUILD" python3 - <<'PY' || ARRIVAL_RC=$?
import os, sys, time
sys.path.insert(0, os.path.expanduser("~/Projects/Timer/timer-app/Tools"))
import asc

APP = "6805876636"
ждём = os.environ["BUILD"]
токен = asc.token()
номера = []

for попытка in range(1, 21):          # 20 × 30 с = до десяти минут
    d = asc.get(f"builds?filter[app]={APP}&sort=-version&limit=10", токен)
    номера = [b["attributes"]["version"] for b in d["data"]]
    if ждём in номера:
        свой = next(b for b in d["data"]
                    if b["attributes"]["version"] == ждём)["attributes"]
        print(f"✓ ПРИБЫЛА: сборка {ждём} · состояние "
              f"{свой.get('processingState')} · залито {свой.get('uploadedDate')}")
        print("  Чего это НЕ значит: что она обработана и что её кто-то видит.")
        print("  «Залито», «роздано» и «привязано к версии» — три разных вопроса.")
        sys.exit(0)
    print(f"  ещё не видно ({попытка}/20); новейшие там: {номера[:4]}")
    time.sleep(30)

print(f"""
✗ ПРИБЫТИЕ НЕ ПОДТВЕРЖДЕНО: за десять минут сборка {ждём}
  в App Store Connect не появилась. Новейшие там: {номера[:4]}

  Это НЕ значит, что выгрузка провалилась, — и не значит, что прошла.
  Значит, что приёмка не состоялась, и `make beta` запускать НЕЛЬЗЯ:
  он возьмёт новейшую в ASC, то есть ЧУЖУЮ сборку, и распишет ей
  заметки этой. Ворота номера в publish_beta.sh это остановят,
  но проверить надо здесь.

  Повтори вручную:
    source ~/Projects/Gamut/.env.asc
    GET /v1/builds?filter[app]={APP}&sort=-version&limit=1""", file=sys.stderr)
sys.exit(1)
PY

if [ "$ARRIVAL_RC" -ne 0 ]; then
