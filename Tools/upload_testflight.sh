#!/bin/bash
# Собирает Того и отправляет сборку в TestFlight.
#
#   Tools/upload_testflight.sh
#
# Что нужно один раз положить в окружение (см. docs/APP-STORE.md):
#
#   TEAM        Team ID из App Store Connect → Membership
#   ASC_KEY_ID  идентификатор ключа App Store Connect API
#   ASC_ISSUER  Issuer ID оттуда же
#   ASC_KEY     путь к файлу AuthKey_XXXXXXXX.p8
#
# Ключ API, а не пароль приложения: пароль требует ввода руками
# и живёт до первой смены пароля Apple ID, а ключ работает молча
# и отзывается одной кнопкой.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

fail() { echo "✗ $1" >&2; exit 1; }

# Team берём из конфигурации проекта: он там и так записан, и держать
# его в двух местах — верный способ однажды загрузить не туда.
TEAM="${TEAM:-$(grep '^DEVELOPMENT_TEAM' Configuration/Shared.xcconfig | sed 's/.*= *//')}"
[ -n "$TEAM" ] || fail "не задан TEAM — Team ID из App Store Connect"

# Ключ ищем там, где его кладут по умолчанию: не заставлять же вводить
# путь каждый раз.
if [ -z "${ASC_KEY:-}" ]; then
    ASC_KEY="$(ls "$HOME/.appstoreconnect/private_keys/"AuthKey_*.p8 2>/dev/null | head -1)"
fi
[ -n "${ASC_KEY:-}" ] || fail "ключ не найден. Положи AuthKey_*.p8 в ~/.appstoreconnect/private_keys/"
[ -f "$ASC_KEY" ]     || fail "файл ключа не найден: $ASC_KEY"

# Key ID — это часть имени файла, спрашивать её отдельно незачем.
ASC_KEY_ID="${ASC_KEY_ID:-$(basename "$ASC_KEY" .p8 | sed 's/^AuthKey_//')}"

# Имя переменной у нас и у соседних проектов разошлось: здесь ждали
# `ASC_ISSUER`, а `Gamut/.env.asc` кладёт `ASC_ISSUER_ID`. 23.09.2026
# выгрузка Виктории упала на этом и была обойдена руками — то есть
# завтра наступили бы снова. Принимаем оба и говорим, какое нашлось:
# «ключа нет» и «ключ назван иначе» — разные беды с разным лечением.
if [ -z "${ASC_ISSUER:-}" ] && [ -n "${ASC_ISSUER_ID:-}" ]; then
    ASC_ISSUER="$ASC_ISSUER_ID"
    echo "── issuer взят из ASC_ISSUER_ID"
fi

if [ -z "${ASC_ISSUER:-}" ]; then
    fail "не задан ASC_ISSUER.

Issuer ID вывести неоткуда — его показывает только App Store Connect:
  Users and Access → Integrations → App Store Connect API,
  строка «Issuer ID» над списком ключей. Это UUID.

  export ASC_ISSUER=xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx"
fi

# Номер сборки — из Tools/номер-сборки.txt, одной дорогой на три файла.
#
# Здесь стояло «количество коммитов; git считает это надёжнее человека»,
# и это звучало как осторожность, а измеряло не ту величину: счёт
# коммитов — количество НАШЕЙ РАБОТЫ, номер сборки — количество
# ОТДАННЫХ СБОРОК. 07.10.2026 первое дошло до 506 при 271 в ASC, и
# сборка по счёту прыгнула бы на 235 номеров необратимо.
BUILD="$(bash "$(dirname "${BASH_SOURCE[0]}")/номер-сборки.sh")" \
    || fail "номер сборки не добыт — см. Tools/номер-сборки.txt"
VERSION="$(grep '^MARKETING_VERSION' Configuration/Shared.xcconfig | sed 's/.*= *//')"

echo "── Того $VERSION ($BUILD) → TestFlight"

# Что нас попросили сделать — решаем до проверок: у выгрузки готового
# архива и у полного цикла разные требования к дереву.
UPLOAD_ONLY=""
DIRTY_ALLOWED="${DIRTY_OK:-}"
for arg in "$@"; do
    case "$arg" in
        --только-выгрузка) UPLOAD_ONLY=1 ;;
        --грязно) DIRTY_ALLOWED=1 ;;
    esac
done

# Дерево обязано быть чистым, и это отказ, а не предупреждение.
#
# **`xcodebuild` архивирует диск, а не коммит.** 23.09.2026 это едва
# не стоило поставки дважды за час: в дереве лежала незаконченная
# правка, а в другой раз — намеренно испорченная строка, оставленная
# после проверки сторожа подделкой. Оба раза спас чужой таймаут,
# а не проверка.
#
# Сборка, собранная с грязного дерева, неотличима снаружи от честной:
# номер тот же, подпись та же, «что тестировать» от коммита, которого
# в бинарнике уже нет.
#
# `--грязно` оставлено намеренно: бывает нужно собрать с правкой
# в руках. Но это должно быть сказано вслух, а не случиться само.
#
# Имена переменных здесь латиницей, как и всюду в файле: `bash`
# кириллическое имя за имя не считает, присваивание молча падает
# («command not found»), а следующая строка выполняется как ни в чём
# не бывало. Один рабочий файл этим уже был испорчен — правило
# записано в своде, и я нарушил его в этой же правке, прежде чем
# заметить.
#
# При `--только-выгрузка` не проверяется вовсе, и это не послабление:
# архив уже собран, дерево на него не влияет никак. Наоборот —
# типичный случай в том, что после сборки легли коммиты журнала
# и статуса, и требовать чистоты значило бы заставить пересобирать
# ради ничего.
if [ -z "$UPLOAD_ONLY" ] && [ -z "$DIRTY_ALLOWED" ]; then
    DIRTY="$(git --no-optional-locks status --porcelain)"
    if [ -n "$DIRTY" ]; then
        fail "дерево не чистое — архив возьмёт диск, а не коммит:

$DIRTY

Закоммить своё или запусти с --грязно, если это намеренно."
    fi
fi

ARCHIVE="build/Togo.xcarchive"

# 3. Готовый архив не стираем молча.
#
# Скрипт делает свой полный цикл — тесты, архив, выгрузка — и раньше
# начинался с `rm -rf` чужого архива. 23.09 так пропала собранная
# и проверенная сборка 189: её паспорт (номер, путь, `sha256`) уже был
# отправлен, а проверять стало нечего.
#
# Экспорт готового архива — минуты, полный цикл — полчаса. Поэтому
# `--только-выгрузка` полезнее вопроса.
#
# Разбор флага **один**, циклом по `"$@"` выше. Первая редакция этой
# правки оставила рядом позиционную проверку `$1`/`$2` — и она
# перезаписывала результат цикла: флаг третьим словом, и скрипт уходил
# в `else`, то есть **стирал готовый архив при явно переданном флаге,
# который должен был это предотвратить**. Хуже того, проверку дерева
# цикл к тому моменту уже пропустил: чистоту не проверили и архив
# стёрли.
#
# Это ровно то, что записано в своде про откат подделки: **второй
# механизм — лишняя деталь, которая ломается молча.** Здесь он был
# в одном флаге.
if [ -n "$UPLOAD_ONLY" ]; then
    [ -d "$ARCHIVE" ] || fail "архива нет: $ARCHIVE. Собери его — make archive."
    echo "── беру готовый архив $(plutil -extract ApplicationProperties.CFBundleVersion raw "$ARCHIVE/Info.plist")"
else
    if [ -d "$ARCHIVE" ]; then
        echo "── стираю прежний архив $(plutil -extract ApplicationProperties.CFBundleVersion raw "$ARCHIVE/Info.plist" 2>/dev/null || echo '?') — он пересобирается"
    fi
    rm -rf "$ARCHIVE" build/export
fi

if [ -z "$UPLOAD_ONLY" ]; then
echo "── тесты"
# Симулятор берётся по UDID тем же подборщиком, что у `make unit`, а не
# по имени. `name=iPhone 17 Pro` без версии разрешается в `OS:latest`:
# стоит рядом появиться рантайму новее того, на котором заведён этот
# симулятор (27.0 при устройстве на 26.5), и xcodebuild отвечает
# «устройство не найдено» — при том, что оно есть и видно в `simctl list`.
# Выгрузка падала на шаге тестов, не дойдя до архива.
#
# Имя переменной латиницей, в отличие от остального: имена переменных
# в shell обязаны быть из ASCII, и `СИМУЛЯТОР=...` bash принимает
# за команду — «command not found».
#
# `tail -1` обязателен: подборщик печатает в stdout сначала строку
# «Беру готовый: …», и только последняя строка — UDID.
#
# ЗЕЛЁНОЕ ЗДЕСЬ РЕШАЕТ СВЕРКА С ЭТАЛОНОМ, А НЕ КОД ВОЗВРАТА xcodebuild.
#
# Замер 14.10.2026: при `set -euo pipefail` (`:16`) этот шаг стоял
# голым `xcodebuild test`, и потому полный цикл НЕ ДОХОДИЛ ДО АРХИВА
# НИКОГДА. В `Tools/эталон-прогона.json` семь ожидаемо красных, и все
# семь живут в `TogoTests/`, — значит ЗДОРОВЫЙ прогон даёт 65, а `set -e`
# убивает скрипт до строки «── архив». Живая дорога была одна:
# `make archive` плюс `--только-выгрузка`, и в журналах видно только её.
#
# Правило «решает сверка, а не rc» уже записано в `Makefile:127-130`
# и в `.github/workflows/ci.yml`. Здесь его не было — то есть дефект
# не в скрипте, а в РАСХОЖДЕНИИ КОПИИ С ПРАВИЛОМ. Поэтому лечение —
# ссылка на `Tools/сверить_эталон.py`, а не четвёртая копия правила:
# четвёртая разошлась бы так же молча, как разошлась эта.
#
# Лог и бандл отвечают на РАЗНЫЕ вопросы и потому оба: лог говорит,
# СОСТОЯЛСЯ ли прогон (ноль тестов, перезапуски, смерть симулятора),
# бандл — ИМЕНА упавших из структуры, а не из печати. Путь с PID,
# как у `make unit`: над одним деревом работают несколько сессий,
# и 28.09 в общем файле уже поймали чужой `TEST SUCCEEDED`.
SIM="$(python3 Tools/ci_simulator.py | tail -1)"
mkdir -p build/logs
TEST_LOG="build/logs/upload-unit-$(date +%Y%m%d-%H%M%S)-$$.log"
TEST_BUNDLE="build/upload-unit-$$.xcresult"
rm -rf "$TEST_BUNDLE"

# `|| rc=$?` обязателен именно из-за `set -e`: без него строка ниже
# не выполнится вовсе, и печатать код возврата будет уже некому.
# ПОСЛЕДОВАТЕЛЬНО, И ЭТО ЗАМЕР 29.10.2026, А НЕ УДОБСТВО.
#
# На вершине `f0d06df9` параллельный прогон умирает трапом рантайма,
# унося весь хост: тесты, бывшие в полёте, отчитываются «Test crashed
# with signal trap» — их 606, и ни один из них не виновник. Сверке
# при этом нечего читать, и она честно говорит «СВЕРЯТЬ НЕЧЕМ»,
# то есть ворота не пропускают и не отклоняют — они ослепли.
#
#   параллельно,  f0d06df9    812 ✔ из 1415 начатых · 1 перезапуск
#   ПОСЛЕДОВАТЕЛЬНО, f0d06df9  1414 ✔ из 1416 · перезапусков 0 ·
#                              красных РОВНО ДВА, и оба из эталона
#   параллельно,  0884fc06    1416 ✔ · перезапусков 0   ← до влития 9a6ab4b
#
# Деление называет источник: трап занесён `9a6ab4b`, и он ПАРАЛЛЕЛЬНЫЙ —
# тот же код, пройденный в один поток, даёт 1414 зелёных. То есть это
# не «приложение падает», а «хост не выдерживает параллели».
#
# > **Ворота, которые не могут дочитать прогон, не защищают — они
# > отказывают.** Выбор здесь не между «строго» и «нестрого», а между
# > «сверка состоялась» и «сверки не было». Защита сохранена целиком:
# > сравнение с эталоном ниже идёт по-прежнему и по именам.
#
# ЭТО НЕ ЗАКРЫВАЕТ ТРАП. Он открытая находка, записан в СТАТУС.md
# и в журнале 29.10; снимать эту строку — после того, как найдут
# и починят гонку, а не после того, как прогон позеленеет.
rc=0
xcodebuild test \
    -project Togo.xcodeproj -scheme Togo \
    -destination "platform=iOS Simulator,id=${SIM}" \
    -only-testing:TogoTests \
    -parallel-testing-enabled NO \
    -resultBundlePath "$TEST_BUNDLE" \
    > "$TEST_LOG" 2>&1 || rc=$?
grep -E "Test run|error:|\*\* TEST|Restarting after unexpected exit" "$TEST_LOG" || true
echo "── xcodebuild test: код возврата $rc (полный лог — $TEST_LOG)"

# Код возврата СВЕРКИ, а не xcodebuild. У неё он свой: 0 — сошлось,
# 1 — не сошлось, 2 — сверить нечем. Двойка здесь останавливает
# выгрузку так же, как единица: «инструмент не смог прочитать прогон»
# — это не «всё хорошо», и ровно так оно читается, если не сказать
# обратного вслух.
python3 Tools/сверить_эталон.py --лог "$TEST_LOG" --бандл "$TEST_BUNDLE" \
    || fail "прогон не сошёлся с эталоном — архив не собираю. Разбор выше."

# Без iCloud и общей группы.
#
# ~~Нужно, пока в портале не заведены `group.app.togo.diary` и контейнер
# `iCloud.app.togo.diary`: без них подпись падает ещё до сборки.~~
# **ПРИЧИНА УМЕРЛА. Замер 15.10.2026, `projects-d9`, ASC API
# `/v1/bundleIds?filter[identifier]=app.togo.diary&include=bundleIdCapabilities`:**
#
#     App ID   app.togo.diary · app.togo.diary.widgets
#     включено APP_GROUPS ×2 · ICLOUD (XCODE_6) · IN_APP_PURCHASE ×2
#              · PUSH_NOTIFICATIONS
#
# Оговорка замера: какой из двух App ID несёт `ICLOUD`, этот запрос
# не разрешает, а поштучный `/bundleIds/<id>/bundleIdCapabilities`
# ответил **HTTP 400** — и его пустой список читался бы как «ни одной
# возможности», будь код ответа не напечатан рядом.
#
# Запись переписана, а не удалена: удалённое условие о себе
# не предупреждает. И сам обходной путь НЕ СНЯТ — он жив, им можно
# воспользоваться, и теперь это единственный способ собрать архив
# без iCloud. Опасен он ровно тем, что приложение об этом не узнает:
# `Persistence.swift:120` спрашивает наличие профиля, а не подписи,
# и в TestFlight профиля нет НИКОГДА — значит «право есть» приходит
# всегда. Поэтому ниже, перед выгрузкой, права читаются ИЗ ПОДПИСИ.
#
# Это наш класс «условие, привязанное к инструменту, меняет знак
# в момент его появления»: пока возможностей в портале не было, флаг
# был необходимостью; как только их завели — стал заряженным ружьём.
VARIANT=""
if [ -n "${WITHOUT_ICLOUD:-}" ]; then
    VARIANT="-Personal"
    echo "── без iCloud и общей группы"
fi

AUTH=(-authenticationKeyPath "$(cd "$(dirname "$ASC_KEY")" && pwd)/$(basename "$ASC_KEY")"
      -authenticationKeyID "$ASC_KEY_ID"
      -authenticationKeyIssuerID "$ASC_ISSUER")

echo "── архив"
xcodebuild archive \
    -project Togo.xcodeproj -scheme Togo \
    -destination 'generic/platform=iOS' \
    -archivePath "$ARCHIVE" \
    -configuration Release \
    -allowProvisioningUpdates \
    DEVELOPMENT_TEAM="$TEAM" \
    BUILD_NUMBER="$BUILD" \
    ENTITLEMENTS_VARIANT="$VARIANT" \
    -quiet
else
    # Номер берём из готового архива, а не из `git rev-list`: после
    # сборки могли лечь коммиты — журнал, статус, — и тогда «номер»
    # и «то, что в бинарнике» разошлись бы молча. Info.plist архива
    # знает правду; git знает только текущее дерево.
    BUILD="$(plutil -extract ApplicationProperties.CFBundleVersion raw "$ARCHIVE/Info.plist")"
    VERSION="$(plutil -extract ApplicationProperties.CFBundleShortVersionString raw "$ARCHIVE/Info.plist")"
    AUTH=(-authenticationKeyPath "$(cd "$(dirname "$ASC_KEY")" && pwd)/$(basename "$ASC_KEY")"
          -authenticationKeyID "$ASC_KEY_ID"
          -authenticationKeyIssuerID "$ASC_ISSUER")
    echo "── выгружаю готовый архив $VERSION ($BUILD), не пересобирая"
fi

# Языки — в каждом бандле архива, а не в одном приложении.
#
# Стоит до выгрузки и одинаково для обеих ветвей — и для свежего архива,
# и для `--только-выгрузка`: готовый архив ровно так и уехал бы. Сборка
# 216 прошла с бандлом виджета без единой `.lproj`, и паспорт называл
# «fr ru uk», потому что считали в `Togo.app`, не заглянув в `PlugIns/`.
# Отказ здесь дешевле: следующая сборка — минуты, отозванная сборка
# у тестировщиков — день.
bash Tools/check_bundle_languages.sh "$ARCHIVE"

# Права — из ПОДПИСИ архива, а не из настроек сборки.
#
# Заведено 15.10.2026, `projects-d9`. До этого дня проверок прав архива
# перед выгрузкой не было ни одной: `grep iCloud` по пяти скриптам ворот
# дал три вхождения, и все три — комментарий у обходного пути выше.
#
# Стоит здесь, рядом с языками, и по той же причине: обе ветви,
# и свежий архив, и `--только-выгрузка`, проходят через эту точку,
# а готовый архив с диска уехал бы ровно таким, каким лежит.
#
# Отказ приложения на неверных правах приходит ПОЗЖЕ и ЧУЖИМИ СЛОВАМИ:
# `Persistence.swift:120` спрашивает профиль, а не подпись, в TestFlight
# профиля нет никогда — значит «право есть» всегда, приложение идёт
# в CloudKit и падает, называя человеку «войди в iCloud».
bash Tools/проверить-права-архива.sh "$ARCHIVE"

# Team ID подставляем в копию: сам файл в репозитории остаётся без него.
OPTIONS="build/ExportOptions.plist"
sed "s/TEAM_ID_PLACEHOLDER/$TEAM/" Configuration/ExportOptions.plist > "$OPTIONS"

# Отпечаток и номер архива — последние ворота перед выгрузкой.
#
# Замерено 08.10.2026. `archive_fingerprint.sh` существовал, отвечал
# ВЕРНО и возвращал 3 на несвежем архиве — а звали его ровно один раз,
# из `Tools/сборка-для-testflight.sh:138`, то есть из скрипта, который
# заливать не умеет вовсе. В ветви `--только-выгрузка` он не вызывался
# никогда: на диске лежал архив со сборкой **271 от 28 сентября**,
# отдавать собирались **274**, и эта ветвь залила бы его молча.
#
# > **Ворота существовали и стояли не на той дороге.** Полный цикл —
# > полчаса и страшно, поэтому его обложили проверками; выгрузка —
# > минуты и дёшево, поэтому её не закрыли ничем. Заглушают то, что
# > дорого ждать; разрушительное дешёвое остаётся живым.
#
# Место выбрано по правилу, а не по удобству: проверка ставится ПОСЛЕ
# последнего действия, способного её нарушить, и ПЕРЕД первым, который
# на неё опирается. После `check_bundle_languages.sh` архив уже никто
# не трогает, а первым на него опирается `-exportArchive` строкой ниже.
# Поставить раньше — получить проверку, верную по смыслу и бесполезную
# по месту: ровно так у нас уехал коммит со сломанными символами,
