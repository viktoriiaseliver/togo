#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Где именно два кадра разошлись: полосы строк и столбцов.

PIL на машине нет, ImageMagick нет. PNG из XCUIScreenshot — 8 бит,
RGBA или RGB, без чересстрочности, поэтому хватает своего разбора:
IHDR → склейка IDAT → zlib → снятие фильтра построчно.

Печатает не «отличаются/нет», а АДРЕС расхождения: диапазоны строк
и столбцов. Без адреса «хеши разошлись» не говорит, часы это
или предмет.
"""
from __future__ import annotations
import struct
import sys
import zlib


def читать_png(путь):
    данные = open(путь, "rb").read()
    assert данные[:8] == b"\x89PNG\r\n\x1a\n", f"{путь}: не PNG"
    поз = 8
    idat = []
    ширина = высота = глубина = тип = None
    while поз < len(данные):
        (длина,) = struct.unpack(">I", данные[поз:поз + 4])
        имя = данные[поз + 4:поз + 8]
        тело = данные[поз + 8:поз + 8 + длина]
        if имя == b"IHDR":
            ширина, высота, глубина, тип, _, _, черес = struct.unpack(">IIBBBBB", тело)
            assert черес == 0, "чересстрочный PNG не разбираю"
            assert глубина == 8, f"глубина {глубина} не 8"
        elif имя == b"IDAT":
            idat.append(тело)
        elif имя == b"IEND":
            break
        поз += 12 + длина
    каналов = {0: 1, 2: 3, 4: 2, 6: 4}[тип]
    сырое = zlib.decompress(b"".join(idat))
    шаг = ширина * каналов
    строки = []
    прежняя = bytearray(шаг)
    и = 0
    for _ in range(высота):
        фильтр = сырое[и]
        и += 1
        строка = bytearray(сырое[и:и + шаг])
        и += шаг
        if фильтр == 1:
            for x in range(каналов, шаг):
                строка[x] = (строка[x] + строка[x - каналов]) & 0xFF
        elif фильтр == 2:
            for x in range(шаг):
                строка[x] = (строка[x] + прежняя[x]) & 0xFF
        elif фильтр == 3:
            for x in range(шаг):
                слева = строка[x - каналов] if x >= каналов else 0
                строка[x] = (строка[x] + ((слева + прежняя[x]) >> 1)) & 0xFF
        elif фильтр == 4:
            for x in range(шаг):
                a = строка[x - каналов] if x >= каналов else 0
                b = прежняя[x]
                c = прежняя[x - каналов] if x >= каналов else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                пр = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                строка[x] = (строка[x] + пр) & 0xFF
        строки.append(bytes(строка))
        прежняя = строка
    return ширина, высота, каналов, строки


def полосы(номера):
    """Соседние номера сворачиваются в диапазоны."""
    если_пусто = []
    if not номера:
        return если_пусто
    начало = прошлый = номера[0]
    итог = []
    for н in номера[1:]:
        if н == прошлый + 1:
            прошлый = н
            continue
        итог.append((начало, прошлый))
        начало = прошлый = н
    итог.append((начало, прошлый))
    return итог


def главное():
    а, б = sys.argv[1], sys.argv[2]
    ш1, в1, к1, строки1 = читать_png(а)
    ш2, в2, к2, строки2 = читать_png(б)
    print(f"{а}: {ш1}x{в1}, каналов {к1}")
    print(f"{б}: {ш2}x{в2}, каналов {к2}")
    if (ш1, в1, к1) != (ш2, в2, к2):
        print("РАЗМЕР РАЗНЫЙ — дальше не сравниваю")
        return
    плохие_строки = []
    плохие_столбцы = set()
    всего_пикселей = 0
    for y in range(в1):
        if строки1[y] == строки2[y]:
            continue
        плохие_строки.append(y)
        s1, s2 = строки1[y], строки2[y]
        for x in range(ш1):
            i = x * к1
            if s1[i:i + к1] != s2[i:i + к1]:
                плохие_столбцы.add(x)
                всего_пикселей += 1
    if not плохие_строки:
        print("СОВПАЛИ ПОБАЙТОВО")
        return
    стб = sorted(плохие_столбцы)
    print(f"различных пикселей: {всего_пикселей} из {ш1 * в1} "
          f"({100.0 * всего_пикселей / (ш1 * в1):.4f}%)")
    print(f"строк затронуто: {len(плохие_строки)}  "
          f"полосы (px): {полосы(плохие_строки)[:12]}")
    print(f"столбцов затронуто: {len(стб)}  "
          f"полосы (px): {полосы(стб)[:12]}")
    print(f"в точках (÷3): строки "
          f"{[(a // 3, b // 3) for a, b in полосы(плохие_строки)[:12]]}")
    print(f"в точках (÷3): столбцы "
          f"{[(a // 3, b // 3) for a, b in полосы(стб)[:12]]}")


if __name__ == "__main__":
    главное()
