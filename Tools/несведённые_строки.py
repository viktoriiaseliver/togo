#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Кириллица в КОДЕ показа, которой нет в каталоге строк.

Отвечает на вопрос, который не задаёт ни один сторож полноты:
`пробеловНет` сверяет языки у того, что **в каталоге**, — а строка,
которая в каталог не попадала, ему не видна по устройству. Так на
французском экране «Анализы» стоял целый русский абзац при пяти живых
языках (разбор — коммит `93f4840`, 26.10.2026).

    python3 Tools/несведённые_строки.py            # сводка
    python3 Tools/несведённые_строки.py --список   # с адресами
    python3 Tools/несведённые_строки.py --контроль # самопроверка

ЗАЧЕМ ОТДЕЛЬНЫЙ РАЗБОРЩИК, А НЕ ГРЕП. Греп не отличает код от прозы,
а в этом проекте проза объёмнее кода и полна имён строк показа. Замер
26.10.2026 на предмете наряда:

    grep -rn "Отметка лаборатории" Togo TogoShared    8 строк
    из них КОД (LabeledField(label:))                 2
    из них `//` комментарий                           3
    из них `///` доккомментарий                       3

Приёмочное число, снятое грепом, завышало предмет вчетверо.

ДВА ЛОЖНЫХ ОТВЕТА, КОТОРЫЕ ЭТОТ ИНСТРУМЕНТ ДАВАЛ САМ. Оба — ровно тот
класс, который он ищет, и оба были синтаксически безупречны:

 1. Литерал обрывался на кавычке ВНУТРИ интерполяции:
    `"\\(dog.name ?? String(localized: "Собака")) · ты помощник"`
    приезжал обрубком и числился непокрытым при живом ключе в каталоге.
    Это тот самый дефект, от которого предостерегает голова
    `extract_texts.py`, — и он был повторён, зная о нём.
 2. Сверка с каталогом сравнивала литерал с ключом ДОСЛОВНО, а Xcode
    при извлечении превращает `\\(x)` в `%@`/`%lld`. Из 937 «непокрытых»
    448 были ложными ровно по этой причине.

Поэтому: интерполяция проходится со счётом скобок и перескоком
вложенных литералов, а сверка идёт ПО ОБРАЗЦУ — обе стороны
нормализуются заменой подстановки на дозорный символ.

ЧТО ЭТОТ ИНСТРУМЕНТ НЕ ОТВЕЧАЕТ. Он читает ДИСК, а не коммит: при
нескольких сессиях гонять из `git worktree` на названном коммите,
иначе ответ не относится ни к одному коммиту. И он говорит «строки нет
в каталоге», а не «человек видит русский»: последнее решает кадр.
"""
from __future__ import annotations

import json
import os
import re
import sys

КИРИЛЛИЦА = re.compile(r'[а-яёА-ЯЁ]')
ДОЗОРНЫЙ = '\x00'
СПЕЦИФИКАТОР = re.compile(
    r'%(?:\d+\$)?[-+ #0]*[\d*]*(?:\.\d+)?(?:hh|h|ll|l|q|L|z|j|t)?'
    r'[@dioubxXeEfgGaAcsSpn]')

ИСТОЧНИКИ = ("Togo", "TogoShared", "TogoWidgets")
КАТАЛОГ = "TogoShared/Resources/Localizable.xcstrings"

# Диагностика в консоль: человек этого не видит.
ДИАГНОСТИКА = re.compile(
    r'\b(?:log|logger|Log|StartupLog|UsageLog|ОтладочныйЖурнал)\s*\.\s*'
    r'(?:error|notice|note|debug|info|warning|fault|critical|trace)\s*\(|'
    r'\bprint\s*\(|\bdebugPrint\s*\(|\bfatalError\s*\(|'
    r'\bpreconditionFailure\s*\(|\bassert(?:ionFailure)?\s*\(|'
    r'\bos_log|#warning|#error')
ИДЕНТИФИКАТОР = re.compile(r'accessibilityIdentifier\s*\(')
# Имя `Notification.Name` — не подпись; в каталог уезжает извлечением.
ИМЯ_СОБЫТИЯ = re.compile(r'Notification\.Name\s*\(')
# Основы разбора дозаписи: голова `RecallDictionary.swift` объясняет,
# почему каталог им не подходит. Исключение файловое и верное
# по существу: живых подписей в файле нет.
ФАЙЛЫ_МИМО = {"RecallDictionary.swift"}


def литералы(текст):
    """(номер строки, литерал) для КОДА: комментарии выброшены.

    Знает `//`, вложенные блочные, многострочные литералы в три
    кавычки, raw-литералы с решёткой и интерполяцию с вложенными
    литералами внутри неё.
    """
    out = []
    i, n, строка = 0, len(текст), 1

    def вперёд(j):
        nonlocal строка
        if текст[j] == '\n':
            строка += 1

    while i < n:
        c = текст[i]

        if c == '/' and i + 1 < n and текст[i + 1] == '/':
            while i < n and текст[i] != '\n':
                вперёд(i); i += 1
            continue

        if c == '/' and i + 1 < n and текст[i + 1] == '*':
            глубина = 0
            while i < n:
                if текст[i] == '/' and i + 1 < n and текст[i + 1] == '*':
                    глубина += 1
                    вперёд(i); i += 1; вперёд(i); i += 1
                    continue
                if текст[i] == '*' and i + 1 < n and текст[i + 1] == '/':
                    глубина -= 1
                    вперёд(i); i += 1; вперёд(i); i += 1
                    if глубина == 0:
                        break
                    continue
                вперёд(i); i += 1
            continue

        if c == '#':
            j, решётки = i, 0
            while j < n and текст[j] == '#':
                решётки += 1; j += 1
            if j < n and текст[j] == '"':
                тройной = текст[j:j + 3] == '"""'
                закрытие = ('"""' if тройной else '"') + '#' * решётки
                нач = строка
                k = j + (3 if тройной else 1)
                буфер = []
                while k < n and текст[k:k + len(закрытие)] != закрытие:
                    буфер.append(текст[k]); k += 1
                for q in range(i, min(k + len(закрытие), n)):
                    вперёд(q)
                out.append((нач, ''.join(буфер)))
                i = k + len(закрытие)
                continue

        if текст[i:i + 3] == '"""':
            нач = строка
            k = i + 3
            буфер = []
            while k < n:
                if текст[k] == '\\' and k + 1 < n:
                    буфер.append(текст[k:k + 2]); k += 2
                    continue
                if текст[k:k + 3] == '"""':
                    break
                буфер.append(текст[k]); k += 1
            for q in range(i, min(k + 3, n)):
                вперёд(q)
            out.append((нач, ''.join(буфер)))
            i = k + 3
            continue

        if c == '"':
            нач = строка
            k = i + 1
            буфер = []
            while k < n:
                # Интерполяция: пройти целиком, считая скобки, и НЕ дать
                # внутренним кавычкам закрыть литерал. См. ложный ответ 1
                # в голове файла.
                if текст[k] == '\\' and k + 1 < n and текст[k + 1] == '(':
                    глубина, j = 0, k + 1
                    while j < n:
                        if текст[j] == '"':
                            j += 1
                            while j < n and текст[j] != '"':
                                if текст[j] == '\\':
                                    j += 1
                                j += 1
                        elif текст[j] == '(':
                            глубина += 1
                        elif текст[j] == ')':
                            глубина -= 1
                            if глубина == 0:
                                break
                        j += 1
                    буфер.append(текст[k:min(j + 1, n)])
                    k = j + 1
                    continue
                if текст[k] == '\\' and k + 1 < n:
                    буфер.append(текст[k:k + 2]); k += 2
                    continue
                if текст[k] == '"' or текст[k] == '\n':
                    break
                буфер.append(текст[k]); k += 1
            for q in range(i, min(k + 1, n)):
                вперёд(q)
            out.append((нач, ''.join(буфер)))
            i = k + 1
            continue

        вперёд(i); i += 1
    return out


def нормализовать_литерал(s):
    """`\\(выражение)` → дозорный, escape-пары разворачиваются."""
    out, i, n = [], 0, len(s)
    while i < n:
        if s[i] == '\\' and i + 1 < n and s[i + 1] == '(':
            глубина, j = 0, i + 1
            while j < n:
                if s[j] == '"':
                    j += 1
                    while j < n and s[j] != '"':
                        if s[j] == '\\':
                            j += 1
                        j += 1
                elif s[j] == '(':
                    глубина += 1
                elif s[j] == ')':
                    глубина -= 1
                    if глубина == 0:
                        break
                j += 1
            out.append(ДОЗОРНЫЙ)
            i = j + 1
            continue
        if s[i] == '\\' and i + 1 < n:
            пара = s[i:i + 2]
            out.append({'\\n': '\n', '\\t': '\t', '\\"': '"',
                        '\\\\': '\\', "\\'": "'", '\\0': '\0'}.get(пара, пара))
            i += 2
            continue
        out.append(s[i]); i += 1
    return ''.join(out)


def нормализовать_ключ(k):
    return СПЕЦИФИКАТОР.sub(ДОЗОРНЫЙ, k)


def под_debug(путь):
    try:
        with open(путь, encoding='utf-8') as f:
            return f.readline().strip() == '#if DEBUG'
    except OSError:
        return False


def собрать(корень):
    ключи = set()
    путь_каталога = os.path.join(корень, КАТАЛОГ)
    if os.path.exists(путь_каталога):
        with open(путь_каталога, encoding='utf-8') as f:
            ключи = set(json.load(f)['strings'].keys())
    по_образцу = {нормализовать_ключ(k) for k in ключи}

    итог = {'прочитано_файлов': 0, 'кириллических_в_коде': 0,
            'нет_наивно': 0, 'ключей_в_каталоге': len(ключи),
            'корзины': {}}
    корзины = {}

    for источник in ИСТОЧНИКИ:
        for база, _, файлы in os.walk(os.path.join(корень, источник)):
            for имя in sorted(файлы):
                if not имя.endswith('.swift'):
                    continue
                путь = os.path.join(база, имя)
                отн = os.path.relpath(путь, корень)
                итог['прочитано_файлов'] += 1
                with open(путь, encoding='utf-8') as f:
                    текст = f.read()
                строки_файла = текст.split('\n')
                debug = под_debug(путь)
                for номер, лит in литералы(текст):
                    if not КИРИЛЛИЦА.search(лит):
                        continue
                    итог['кириллических_в_коде'] += 1
                    if лит not in ключи:
                        итог['нет_наивно'] += 1
                    if лит in ключи or нормализовать_литерал(лит) in по_образцу:
                        continue
                    код = (строки_файла[номер - 1].strip()
                           if 0 < номер <= len(строки_файла) else '')
                    корзина = ('DEBUG-файл · стенд, в продукт не идёт' if debug
                               else 'основы разбора, не подписи' if имя in ФАЙЛЫ_МИМО
                               else 'диагностика в консоль' if ДИАГНОСТИКА.search(код)
                               else 'крючок стенда' if ИДЕНТИФИКАТОР.search(код)
                               else 'имя события, не подпись' if ИМЯ_СОБЫТИЯ.search(код)
                               else 'ПОКАЗ — разбирать глазами')
                    корзины.setdefault(корзина, []).append((отн, номер, лит, код))
    итог['корзины'] = корзины
    return итог


def main():
    корень = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    итог = собрать(корень)
    print('прочитано файлов      : %d' % итог['прочитано_файлов'])
    print('ключей в каталоге     : %d' % итог['ключей_в_каталоге'])
    print('кириллицы в коде      : %d' % итог['кириллических_в_коде'])
    print('нет в каталоге наивно : %d  ← ЗАВЫШЕНО: интерполяция' % итог['нет_наивно'])
    всего = sum(len(v) for v in итог['корзины'].values())
    print('нет в каталоге по обр.: %d' % всего)
    print()
    for имя in sorted(итог['корзины'], key=lambda k: -len(итог['корзины'][k])):
        записи = итог['корзины'][имя]
        print('  %4d  %s' % (len(записи), имя))
    показ = итог['корзины'].get('ПОКАЗ — разбирать глазами', [])
    if '--список' in sys.argv:
        print()
        print('=== ПОКАЗ, поимённо ===')
        for отн, номер, лит, код in показ:
            print('%s:%d' % (отн, номер))
            print('    %s' % код[:120])
    print()
    if показ:
        print('ПОКАЗ: %d. Каждая — строка, которую человек увидит '
              'по-русски на четырёх языках из пяти.' % len(показ))
        print('Лечится так: `make texts` заводит ключ, затем перевод '
              'на en/fr/kk/uk, затем долг в')
        print('`LocalizationCoverageTests.долг` — каждым коммитом '
              'и с причиной рядом.')
    else:
        print('ПОКАЗА НЕТ. Это НЕ значит «переводы готовы»: инструмент '
              'сверяет НАЛИЧИЕ ключа,')
        print('а не качество перевода и не то, что доезжает до экрана. '
              'Доезжает — решает кадр.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
