#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Выгрузка строк каталога на проверку носителем языка.

Зачем скриптом, а не руками: выгрузку придётся повторить — носитель
вернёт правки, мы их вольём, и понадобится второй круг. Выгрузка,
сделанная руками, во второй раз выйдет другой, и сравнить круги будет
нечем.

Что на выходе (в `docs/перевод/на-проверку-<дата>/`):

    все-языки.tsv        один ключ — одна строка, пять языков рядом
    <язык>-на-проверку.tsv   ru + целевой язык + пустая колонка правки

ОСЬ ВАЖНОСТИ. Сортировка не по алфавиту, а по цене ошибки: первыми
медицинские строки. Причина названа Викторией 26.10.2026:
непроверенный перевод медицинской строки — это утверждение о лечении
на языке, которого никто не вычитывал.

ЧТО ИСКЛЮЧЕНО И ПОЧЕМУ:

  · `shouldTranslate: false` — помечено намеренно (бренд, числа,
    пунктуация: «Togo», «Pro», «NFC», « · »);
  · склеенные фрагменты из `Дизайн/редизайн-ios28/i18n/strings.json`
    (`fragment: true`) — их заменяет интерполяция. Носитель, увидев
    « ч », решит, что мы не умеем работать. Замер 26.10.2026: таких
    записей 154, и в каталог дошли ДЕВЯТЬ — остальные 145 в каталоге
    не лежат вовсе, то есть исключать там нечего.

ГРАНИЦА ЗАМЕРА: колонка «где встречается» снята грепом по литералам
Swift и находит место у ~73 % ключей — это НЕ значит, что остальные
27 % мертвы. Литерал собирается из частей, приходит из данных или
лежит в другом таргете. Пустая клетка здесь значит «дешёвым способом
не нашлось», и ничего больше.
"""
from __future__ import annotations   # Python на машине 3.9.6

import csv
import json
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЯЗЫКИ = ["en", "fr", "kk", "uk"]
ИМЕНА = {"en": "английский", "fr": "французский",
         "kk": "казахский", "uk": "украинский"}
КАТАЛОГИ = [
    ("Localizable", "TogoShared/Resources/Localizable.xcstrings"),
    ("AppShortcuts", "Togo/Resources/AppShortcuts.xcstrings"),
]

# ─── ось важности ────────────────────────────────────────────────────
# Слова, по которым строка считается медицинской. Список намеренно
# широкий: ложно попавшая в первый тир строка стоит минуты внимания
# носителя, а пропущенная — непроверенного утверждения о лечении.
МЕД = re.compile(
    r"доз|натощак|норм|схем|лечени|лекарств|препарат|таблет|капл|укол|"
    r"инъекц|мг\b|мл\b|анализ|забор|кров|моч|стул|рвот|вес\b|весе|веса|"
    r"привив|вакцин|врач|клиник|осмотр|температур|симптом|диагноз|курс|"
    r"приём|приема|приёма|глист|клещ|обработк|кастрац|стерилиз|аллерг|"
    r"зуд|хромае|хромот|боль|болит|опухол|шишк|рана|шов|швы|антибиотик|"
    r"гормон|щитовид|Lévothyrox|левотирокс|почк|печен|сустав|эпилепс|"
    r"приступ|судорог|ветеринар|медкниж|медицин|терапи|капельниц|наркоз|"
    r"операци|узи|рентген|прогноз|ремисси|обезбол|противогл|дегельминт",
    re.IGNORECASE)
ТРЕВОГА = re.compile(
    r"не удалось|ошибк|отказ|внимани|срочн|опасн|нельзя|потерял|пропал|"
    r"сбеж|укусил|отрави|задыха|скорая|неотложн|тревог|предупрежд",
    re.IGNORECASE)
ДЕНЬГИ = re.compile(
    r"подписк|оплат|покупк|купить|пробн|тариф|Pro\b|цена|стоимост|"
    r"возврат|магазин|восстанов.{0,12}покупк", re.IGNORECASE)

ТИРЫ = [("1-МЕД", МЕД), ("2-ТРЕВОГА", ТРЕВОГА), ("3-ДЕНЬГИ", ДЕНЬГИ)]
ПОДСТАНОВКА = re.compile(r"%(?:\d+\$)?(?:lld|ld|lu|d|u|@|\.?\d*l?f)")


def тир(текст: str) -> str:
    for имя, шаблон in ТИРЫ:
        if шаблон.search(текст):
            return имя
    return "4-ПРОЧЕЕ"


# ─── исключения ──────────────────────────────────────────────────────
def фрагменты() -> set:
    путь = os.path.join(КОРЕНЬ, "Дизайн/редизайн-ios28/i18n/strings.json")
    if not os.path.exists(путь):
        print("ВНИМАНИЕ: файла фрагментов нет — исключать нечем", file=sys.stderr)
        return set()
    д = json.load(open(путь, encoding="utf-8"))
    return {з["ru"] for з in д if з.get("fragment") is True}


# ─── где встречается ─────────────────────────────────────────────────
ДЫРА = "\x00"
# Сопоставление «литерал Swift ↔ ключ каталога» идёт по СКЕЛЕТУ:
# текст с дырками на месте подстановок. Перебором регекспов это те же
# 3562 × 13 000 = 46 млн сравнений — первый заход не уложился и в две
# минуты; по скелету это словарь и O(1) на ключ.
ДЫРА_В_КЛЮЧЕ = re.compile(r"%(?:\d+\$)?(?:lld|ld|lu|d|u|@|\.?\d*l?f)")


def скелет_ключа(ключ: str) -> str:
    return ДЫРА_В_КЛЮЧЕ.sub(ДЫРА, ключ)


def место() -> dict:
    """скелет -> (это_тест, путь, строка). Приложение предпочитается
    тестам: спрашивали про интерфейс, а не про фикстуру."""
    путь = "/tmp/вызовы.json"
    if not os.path.exists(путь):
        print("ВНИМАНИЕ: индекса литералов нет, колонка «где» будет пуста",
              file=sys.stderr)
        return {}
    итог = {}
    for г in json.load(open(путь, encoding="utf-8")):
        # Скелет приходит от разборщика литералов, а не вырезается
        # регекспом из показанного вида: `\(Int(report.x))` содержит
        # вложенные скобки, и `\\\([^)]*\)` обрубил бы его посередине.
        скелет = г["skel"]
        тест = г["path"].startswith(("TogoTests/", "TogoUITests/"))
        прежнее = итог.get(скелет)
        if прежнее is None or (прежнее[0] and not тест):
            итог[скелет] = (тест, г["path"], г["line"])
    return итог


def найти(ключ: str, индекс: dict, кеш: dict):
    if ключ in кеш:
        return кеш[ключ]
    скелет = скелет_ключа(ключ)
    найдено = индекс.get(скелет)
    if найдено is None:
        # `%%` в ключе — это ОДИН процент в исходнике: экранирование
        # добавляет извлечение, и без этой ветки строки про проценты
        # выглядели бы мёртвыми (замер 26.10: таких две).
        найдено = индекс.get(скелет.replace("%%", "%"))
    кеш[ключ] = "" if найдено is None else (
        ("только в тестах: " if найдено[0] else "") +
        "%s:%d" % (найдено[1], найдено[2]))
    return кеш[ключ]


# ─── чтение каталога ─────────────────────────────────────────────────
def строка_языка(узел):
    """Вернуть (текст, состояние). У ключа с формами числа формы
    склеиваются в одну клетку: носителю нужны все три русские формы
    рядом, иначе он не увидит, что согласование вообще есть."""
    if узел is None:
        return "", "НЕТ СТРОКИ"
    if "stringUnit" in узел:
        return узел["stringUnit"].get("value", ""), \
               узел["stringUnit"].get("state", "")
    if "variations" in узел:
        куски, состояния = [], set()
        for вид, формы in sorted(узел["variations"].items()):
            for форма, значение in sorted(формы.items()):
                е = значение.get("stringUnit", {})
                куски.append("%s: %s" % (форма, е.get("value", "")))
                состояния.add(е.get("state", ""))
        состояние = "needs_review" if (
            "needs_review" in состояния or "new" in состояния) else "translated"
        return " | ".join(куски), состояние
    return "", "НЕТ СТРОКИ"


def чисто(текст: str) -> str:
    """TSV ломается на табе и переводе строки. Таб заменяем пробелом,
    перевод строки — знаком, который виден глазами."""
    return текст.replace("\t", " ").replace("\r", "").replace("\n", " ⏎ ")


def собрать():
    исключить_фрагменты = фрагменты()
    индекс, кеш = место(), {}
    записи, пропущено = [], {"shouldTranslate": 0, "фрагмент": 0}

    for имя_каталога, относительный in КАТАЛОГИ:
        путь = os.path.join(КОРЕНЬ, относительный)
        д = json.load(open(путь, encoding="utf-8"))
        for ключ, узел in д["strings"].items():
            if узел.get("shouldTranslate") is False:
                пропущено["shouldTranslate"] += 1
                continue
            if ключ in исключить_фрагменты:
                пропущено["фрагмент"] += 1
                continue
            локализации = узел.get("localizations") or {}
            # sourceLanguage = ru: записи `ru` может не быть вовсе,
            # и тогда русская строка — САМ КЛЮЧ.
            ru, ru_состояние = строка_языка(локализации.get("ru"))
            if not ru:
                ru, ru_состояние = ключ, "источник (ключ)"
            з = {
                "каталог": имя_каталога,
                "ключ": ключ,
                "ru": ru,
                "ru_состояние": ru_состояние,
                "важность": тир(ключ + " " + ru),
                "подстановка": "да" if ПОДСТАНОВКА.search(ключ) else "",
                "формы": "да" if "variations" in (
                    локализации.get("ru") or {}) else "",
                "где": найти(ключ, индекс, кеш),
            }
            for я in ЯЗЫКИ:
                з[я], з[я + "_состояние"] = строка_языка(локализации.get(я))
            записи.append(з)

    # Внутри тира — длинные фразы первыми: в них смысл и в них цена
    # ошибки, короткие подписи носитель проверит за секунды.
    записи.sort(key=lambda з: (з["важность"], -len(з["ru"]), з["ключ"]))
    return записи, пропущено


ШАПКА = (
    "# ПОРЯДОК НОМЕРОВ В ПОДСТАНОВКАХ МЕНЯТЬ НЕЛЬЗЯ. %1$@ и %2$lld — это "
    "места, куда приложение подставляет имя, число и дату. Номер говорит, "
    "ЧТО именно подставится. Переставите номера — собака получит чужую дозу, "
    "а дата встанет на место веса. Слова вокруг них переставляйте свободно, "
    "сами %-метки оставляйте как есть и в том же количестве."
)


def записать(записи, пропущено, папка):
    os.makedirs(папка, exist_ok=True)
    # utf-8-sig: без BOM Excel и Numbers ломают кириллицу
    общие = ["№", "важность", "каталог", "ключ", "ru"] + ЯЗЫКИ + \
            ["состояние en", "состояние fr", "состояние kk",
             "состояние uk", "подстановка", "формы числа", "где встречается"]
    путь = os.path.join(папка, "все-языки.tsv")
    with open(путь, "w", encoding="utf-8-sig", newline="") as ф:
        п = csv.writer(ф, delimiter="\t", quoting=csv.QUOTE_MINIMAL)
        п.writerow([ШАПКА])
        п.writerow(общие)
        for н, з in enumerate(записи, 1):
            п.writerow([н, з["важность"], з["каталог"], чисто(з["ключ"]),
                        чисто(з["ru"])] +
                       [чисто(з[я]) for я in ЯЗЫКИ] +
                       [з[я + "_состояние"] for я in ЯЗЫКИ] +
                       [з["подстановка"], з["формы"], з["где"]])
    печать = ["все-языки.tsv: %d строк" % len(записи)]

    for я in ЯЗЫКИ:
        # Носителю дают только непроверенное: подтверждённое он уже
        # читал, и повторная вычитка — потраченный зря вечер.
        свои = [з for з in записи
                if з[я + "_состояние"] in ("needs_review", "new", "НЕТ СТРОКИ")]
        путь = os.path.join(папка, "%s-на-проверку.tsv" % я)
        with open(путь, "w", encoding="utf-8-sig", newline="") as ф:
            п = csv.writer(ф, delimiter="\t", quoting=csv.QUOTE_MINIMAL)
            п.writerow([ШАПКА])
            п.writerow(["№", "важность", "русский источник",
                        "наш перевод (%s)" % ИМЕНА[я],
                        "ПРАВКА НОСИТЕЛЯ — пишите здесь",
                        "состояние", "подстановка", "формы числа",
                        "где встречается"])
            for н, з in enumerate(свои, 1):
                п.writerow([н, з["важность"], чисто(з["ru"]), чисто(з[я]), "",
                            з[я + "_состояние"], з["подстановка"],
                            з["формы"], з["где"]])
        печать.append("%s-на-проверку.tsv: %d строк (из них мед %d)" % (
            я, len(свои), sum(1 for з in свои if з["важность"] == "1-МЕД")))
    return печать


if __name__ == "__main__":
    папка = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        КОРЕНЬ, "docs/перевод/на-проверку-26.10")
    записи, пропущено = собрать()
    for строка in записать(записи, пропущено, папка):
        print(строка)
    print("исключено: shouldTranslate=false %d · фрагментов %d"
          % (пропущено["shouldTranslate"], пропущено["фрагмент"]))
    import collections
    print("по важности:", dict(collections.Counter(
        з["важность"] for з in записи)))
    print("без места:", sum(1 for з in записи if not з["где"]))
