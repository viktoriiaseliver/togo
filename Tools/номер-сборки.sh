#!/bin/bash
# Печатает номер следующей сборки. Единственная дорога к этому числу.
#
# Читатели: Makefile (цель `archive`), Tools/upload_testflight.sh,
# Tools/archive_fingerprint.sh. Прежде каждый считал сам
# `git rev-list --count HEAD` — три копии одного допущения, и третья
# была сторожем, который потребовал бы неверный номер.
#
# `BUILD_NUMBER` в окружении побеждает файл: разовая сборка не должна
# требовать коммита. Но она и не должна его молча заменять, поэтому
# подмена печатается в stderr — её видно в логе, и она не влияет
# на stdout, который читают подстановкой.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ. Первая редакция этого файла
# была написана с `КОРЕНЬ`, `ФАЙЛ`, `НОМЕР` — то есть автор нарушил
# правило, которое сам же в этот день трижды цитировал другим.
# `Д="файл"` не заводится вовсе и следующая строка выполняется как
# ни в чём не бывало; под `set -u` это падение, без него — пустой
# номер и успешная сборка.
#
# `set -u` обязателен и по второй причине: многобайтная кавычка рядом
# с именем приклеивается к нему (`"$probe»"` → переменная `probe\xc2\xbb`).
# Без `set -u` этот класс молчит.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
file="$root/Tools/номер-сборки.txt"

if [ -n "${BUILD_NUMBER:-}" ]; then
    echo "номер-сборки: взят из окружения BUILD_NUMBER=$BUILD_NUMBER, файл не читался" >&2
    echo "$BUILD_NUMBER"
    exit 0
fi

if [ ! -f "$file" ]; then
    echo "номер-сборки: нет файла $file." >&2
    echo "Это не повод подставить число: номер обязан расти от загрузки" >&2
    echo "к загрузке, и угаданный номер либо отказ в ASC, либо прыжок" >&2
    echo "вперёд, который необратим." >&2
    exit 1
fi

# Первая значащая строка — число; остальное объяснение. Пустые строки
# и начинающиеся с решётки отбрасываются.
number="$(grep -vE '^[[:space:]]*(#|$)' "$file" | head -1 | tr -d '[:space:]')"

# Проверка ФОРМЫ, а не наличия: пустая строка и «273abc» снаружи
# неразличимы от числа, пока их не спросить.
if ! printf '%s' "$number" | grep -qE '^[0-9]+$'; then
    # `${number}` в фигурных скобках, а не `$number»`: многобайтная
    # кавычка прилипает к имени, и оболочка ищет переменную `number»`.
    # Первая редакция этой строки была написана ТРЕМЯ СТРОКАМИ НИЖЕ
    # комментария, объясняющего этот самый класс, — и поймал его
    # не автор чтением, а подделка с битым числом: отказ вышел верным
    # по коду возврата и ложным по сообщению.
    echo "номер-сборки: в $file первая значащая строка не число: «${number}»" >&2
    exit 1
fi

if [ "$number" -le 0 ]; then
    echo "номер-сборки: номер должен быть больше нуля, прочитано $number" >&2
    exit 1
fi

echo "$number"
