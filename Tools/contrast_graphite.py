# Требовать с неё восемь значило бы завести ложную находку на тексте,
# который автор написал осознанно. А вот РАСХОЖДЕНИЕ двух его
# собственных чисел — находка настоящая, и она ниже отдельной строкой.
ОБЕЩАНИЯ = {
    ("--poster-fg", "--poster-bg"): ("Dark", 8.0),
    ("--poster-sub", "--poster-bg"): (None, 4.5),
    ("--poster-bar", "--poster-track"): (None, 3.0),
}


def main():
    если_нет = [f for f in ("colors.css", "togo.css") if not (ПАКЕТ / f).exists()]
    if если_нет:
        print(f"НЕТ ФАЙЛОВ ПАКЕТА: {если_нет} — мерить нечего", file=sys.stderr)
        return 2

    блоки = [разобрать((ПАКЕТ / f).read_text(encoding="utf-8"))
             for f in ("colors.css", "togo.css")]

    print(f"ИСТОЧНИК: {ПАКЕТ}")
    print("НЕ репозиторий: DesignTokens/tokens.json всё ещё лайм #D4F75F,")
    print("смена поколения акцента не принята. Числа ниже — про пакет.\n")

    всего = провалов = 0
    неизмеренные = []
    нарушенные_обещания = []

    for режим, селекторы in РЕЖИМЫ.items():
        таблица = собрать(блоки, селекторы)
        print(f"=== {режим} " + "=" * (56 - len(режим)))
        for перед, зад, порог, зачем, подложка_имя, требование in ПАРЫ:
            сырой_перед = разрешить(таблица.get(перед), таблица)
            сырой_зад = разрешить(таблица.get(зад), таблица)
            if сырой_перед is None or сырой_зад is None:
                неизмеренные.append((режим, перед, зад, "переменной нет в режиме"))
                continue
            if не_цвет(сырой_перед) or не_цвет(сырой_зад):
                неизмеренные.append((режим, перед, зад,
                                     f"не считается: {сырой_перед} / {сырой_зад}"))
                continue
            ц_перед, ц_зад = в_rgb(сырой_перед), в_rgb(сырой_зад)
            if ц_перед is None or ц_зад is None:
                неизмеренные.append((режим, перед, зад, "не разобран цвет"))
                continue
            # **Подложка берётся из пары, а не из страницы.** Полупрозрачное
            # лежит на том, поверх чего нарисовано: дорожка плаката — на
            # блоке, а не на фоне экрана. Ошибка в подложке даёт ложную
            # находку с правдоподобным числом.
            имя_подложки = подложка_имя or "--page"
            подложка = в_rgb(разрешить(таблица.get(имя_подложки), таблица)) or (0, 0, 0)
            подложка = наложить(подложка, (0, 0, 0))
            ц_зад = наложить(ц_зад, подложка)
            ц_перед = наложить(ц_перед, ц_зад)
            к = контраст(ц_перед, ц_зад)
            всего += 1
            ок = к >= порог
            if требование:
                провалов += 0 if ок else 1
                знак = "✔" if ок else "✘"
            else:
                знак = "·" if ок else "·"
            print(f"  {знак} {к:5.2f}:1  (порог {порог})  {перед} / {зад}")
            print(f"      {зачем}" + ("" if требование else "   [справочно, не провал]"))
            запись = ОБЕЩАНИЯ.get((перед, зад))
            if запись is not None:
                чей, обещано = запись
                if (чей is None or чей == режим) and к < обещано:
                    нарушенные_обещания.append((режим, перед, зад, обещано, к))
        print()

    print("=" * 62)
    print(f"ИЗМЕРЕНО ПАР: {всего} · НЕ ПРОХОДЯТ ПОРОГ: {провалов}")

    if нарушенные_обещания:
        print("\nПАКЕТ НАРУШАЕТ СОБСТВЕННЫЕ ЧИСЛА:")
        for режим, п, з, обещано, факт in нарушенные_обещания:
            print(f"  {режим}: {п} / {з} — обещано ≥{обещано}, намерено {факт:.2f}")

    print(f"\nНЕИЗМЕРЕННЫЕ ПАРЫ: {len(неизмеренные)}")
    for режим, п, з, почему in неизмеренные:
        print(f"  {режим}: {п} / {з} — {почему}")

    print("""
ГРАНИЦА ЭТОГО ЗАМЕРА — печатается всегда, а не хранится в памяти:
· это пакет, а не приложение; в репозитории акцент другой;
· `color-mix(...)` не считался: результат зависит от движка —
  такие пары выше перечислены как неизмеренные, а не пропущены молча;
· замер по значениям, а не по кадру. «Значение верное, а вызов
  бессильный» он не ловит: `opacity` на тексте, перекрытие цвета
  стилем, градиент под подписью — всё это видно только на пикселе;
· пары взяты из ролей слоя и обещаний `togo.css`. Пара, которой
  в списке нет, не проверена — не «хороша».""")
    return 1 if (провалов or нарушенные_обещания) else 0


if __name__ == "__main__":
    sys.exit(main())
