def разобрать(текст):
    """{селектор: {переменная: значение}} из CSS без вложенности.

    **Комментарии срезаются ДО разбора, и это не аккуратность.**
    Первая редакция чистила их внутри селектора — и `:root`,
    перед которым в `colors.css` стоит двухстрочный комментарий,
    не опознавался вовсе. Тёмная тема дала НОЛЬ пар, а ноль — это
    край диапазона, то есть симптом инструмента, пока не доказано
    обратное. Доказалось про инструмент.
    """
    текст = re.sub(r'/\*.*?\*/', '', текст, flags=re.S)
    блоки = {}
    for сел, тело in re.findall(r'([^{}]+)\{([^{}]*)\}', текст, re.S):
        сел = ' '.join(сел.split())
        пары = блоки.setdefault(сел, {})
        for имя, знач in re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', тело):
            пары[имя] = знач.strip()
    return блоки


def собрать(блоки_списком, селекторы):
    итог = {}
    for блоки in блоки_списком:
        for сел in селекторы:
            for ключ, знач in блоки.get(сел, {}).items():
                итог[ключ] = знач
    return итог


def разрешить(значение, таблица, глубина=0):
    """var(--x) → значение. Циклы и неизвестные — None."""
    if глубина > 10 or значение is None:
        return None
    значение = значение.strip()
    м = re.fullmatch(r'var\((--[\w-]+)\)', значение)
    if м:
        return разрешить(таблица.get(м.group(1)), таблица, глубина + 1)
    return значение


def в_rgb(цвет):
    """#RGB/#RRGGBB → (r,g,b). #RRGGBBAA и rgba(...) → (r,g,b,a). Иначе None."""
    if не_цвет(цвет):
        return None
    цвет = цвет.strip()
    if цвет.startswith('#'):
        h = цвет[1:]
        if len(h) == 3:
            h = ''.join(c * 2 for c in h)
        # Восьмизначный хекс РАЗБИРАЕТСЯ, а не отбрасывается.
        #
        # Прежде здесь стоял `return None`, и это давало не ошибку,
        # а ТИШИНУ: пара с полупрозрачным токеном уходила в список
        # «не разобран цвет» и в итог не попадала. Пока таких токенов
        # было два, цена была нулевой; с темой «Кино» их девятнадцать —
        # всё стекло, все панели тонов и весь тон фото заданы долей.
        # Молчаливое «не разобран» на двух третях новых токенов
        # выглядело бы как измеренный аудит.
        if len(h) == 8:
            r, g, b, a = (int(h[i:i + 2], 16) for i in (0, 2, 4, 6))
            return (r, g, b, a / 255)
        if len(h) != 6:
            return None
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    м = re.fullmatch(r'rgba?\(([^)]+)\)', цвет)
    if м:
        части = [ч.strip() for ч in м.group(1).split(',')]
        if len(части) < 3:
            return None
        r, g, b = (int(float(ч)) for ч in части[:3])
        a = float(части[3]) if len(части) > 3 else 1.0
        return (r, g, b, a)
    return None


def не_цвет(значение):
    if значение is None:
        return True
    з = значение.strip()
    return (з.startswith('color-mix') or з.startswith('linear-gradient')
            or з.startswith('repeating-') or з in ('transparent', 'none', 'block'))


def наложить(верх, низ):
    """rgba поверх непрозрачного → непрозрачный."""
    if len(верх) == 3:
        return верх
    r, g, b, a = верх
    return tuple(round(a * в + (1 - a) * н) for в, н in zip((r, g, b), низ))


def яркость(rgb):
    def канал(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (канал(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def контраст(a, b):
    la, lb = яркость(a), яркость(b)
    тёмн, светл = min(la, lb), max(la, lb)
    return (светл + 0.05) / (тёмн + 0.05)


