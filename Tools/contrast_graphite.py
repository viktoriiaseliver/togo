"""Аудит контраста пакета Graphite — по ПАКЕТУ, а не по репозиторию.

**Первое, что обязан сказать отчёт, и поэтому оно стоит в начале файла.**
`DesignTokens/tokens.json` в репозитории Togo всё ещё несёт лайм
(`primitive.color.arctic = #D4F75F`). Смена поколения акцента —
решение Виктории, и оно не принято. Значит этот аудит меряет **пакет
`DesignTokens/ядро-дизайна/tokens/`**, а не живое приложение,
и ни одно число отсюда не описывает того, что человек видит сегодня.

Иначе отчёт прочтут как замер продукта — наш класс «артефакт
устаревает молча, и выглядит это как измерение», только наоборот:
артефакт из будущего.

**Что считается и как.**

* Четыре режима собираются наследованием, как в CSS:
  `Dark = :root`, `Light = :root + [data-theme=light]`,
  `Dark HC = :root + [data-contrast=high]`,
  `Light HC = :root + [data-theme=light] + оба селектора high`.
* `var(--x)` разрешается по тому же режиму.
* **`rgba(...)` НАКЛАДЫВАЕТСЯ на свой фон до замера.** Прозрачность
  съедает запас: `#666` под `opacity .85` — это уже `#7D7D7D`
  и 4,12:1. Мерить надо то, что нарисовано, а не исходный цвет.
* `color-mix(...)` **не считается** — результат зависит от движка
  и цветового пространства. Такие пары печатаются отдельным списком
  как НЕИЗМЕРЕННЫЕ. Промолчать о них значило бы выдать неполный
  аудит за полный.

Пороги WCAG 2.1: 4,5 — мелкий текст, 3,0 — крупный текст и графика.
"""
