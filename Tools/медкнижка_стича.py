import json
from datetime import datetime, timezone

def д(строка: str) -> str:
    """ДД.ММ.ГГГГ → ISO-8601 в полдень UTC.

    Полдень, а не полночь: это ДЕНЬ КАЛЕНДАРЯ, а не момент. Замер
    05.10.2026 на Togo — запись у полуночи читается на запад как
    предыдущий день, и у даты прививки это меняет срок действия.
    Полдень устойчив в пределах ±12 часов для всех поясов.
    """
    д_, м, г = строка.split('.')
    return datetime(int(г), int(м), int(д_), 12, 0, tzinfo=timezone.utc).isoformat()


