#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Прирост долга непроверенных переводов — за секунду, а не за прогон.

    python3 Tools/долг-локализации.py            # сверить с храповиком
    python3 Tools/долг-локализации.py --откуда   # декомпозиция по коммитам

Код возврата: 0 — долг не вырос, 1 — вырос, 2 — разбор не состоялся.

# Зачем, и чем оплачено

03.11.2026 заливка 291 отказала ДВАЖДЫ подряд, и второй отказ был вот
этим: `LocalizationCoverageTests.непроверенныхНеБольше` покраснел,
потому что 13 новых ключей переполнили храповик.

Цена: **два прогона по двенадцать минут**, чтобы узнать то, что
считается за секунду. Прогон идёт после сборки схемы, а схема —
после разрешения зависимостей; ворота, стоящие так глубоко, сообщают
о мелком расхождении дороже всех.

> **Ворота должны стоить дешевле того, что охраняют.** Иначе их
> обходят — не из лени, а потому что цена проверки выше цены ошибки.

Отдельно: храповик стоял **впритык** — четыре числа из четырёх
совпадали с фактом до единицы. Значит он красен при любой честной
работе с каталогом, и узнавать об этом надо до прогона, а не после.

# Почему числа читаются ИЗ файла сторожа, а не лежат здесь

Копия разошлась бы молча — ровно тот класс, что этот инструмент
и помогает ловить. Источник один: `private static let долг`
в `TogoTests/LocalizationCoverageTests.swift`. Меняют его там.

# Разбор каталога — ВТОРАЯ реализация, и это названо вслух

Сторож на Swift, инструмент на Python; общего кода у них нет, и
совпадение их чисел — **свидетельство, а не доказательство**.
03.11 они разошлись на 37: мой первый разбор не брал формы числа
из `variations`, а сторож брал. Правым оказался сторож.

Поэтому здесь `variations` читаются, и при расхождении с прогоном
верить надо прогону: он считает то, что собрано, а я — то, что
в файлах.
"""
from __future__ import annotations
import collections
import json
import os
import re
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СТОРОЖ = "TogoTests/LocalizationCoverageTests.swift"
# Те же три корня, что обходит сторож: `Togo`, `TogoShared`, `TogoWidgets`.
# Четвёртым появится таргет — и разойдётся молча, поэтому список
# сверяется с тем, что лежит на диске, а не принимается на веру.
КОРНИ_КАТАЛОГОВ = ["Togo", "TogoShared", "TogoWidgets"]


def храповик() -> dict[str, int] | None:
    """Числа долга из файла сторожа. None — разбор не состоялся."""
    путь = os.path.join(КОРЕНЬ, СТОРОЖ)
    if not os.path.exists(путь):
        return None
    текст = open(путь, encoding="utf-8").read()
    место = re.search(r"let\s+долг\s*:\s*\[String:\s*Int\]\s*=\s*\[(.*?)\]",
                      текст, re.S)
    if not место:
        return None
    пары = re.findall(r'"([a-z\-A-Z]+)"\s*:\s*(\d+)', место.group(1))
    return {я: int(ч) for я, ч in пары} if пары else None


def каталоги() -> list[str]:
    найдено = []
    for корень in КОРНИ_КАТАЛОГОВ:
        путь = os.path.join(КОРЕНЬ, корень)
        for папка, _, файлы in os.walk(путь):
            for имя in файлы:
                if имя.endswith(".xcstrings"):
                    найдено.append(os.path.join(папка, имя))
    return sorted(найдено)


def счёт(содержимое: list[dict]) -> collections.Counter:
    """Непроверенных по языкам, СЧИТАЯ формы числа.

    Формы числа лежат не в `stringUnit`, а в `variations → plural →
    форма → stringUnit`, и первая редакция этого счёта их не брала.
    Разница на живом каталоге — 37 строк из 3753.
    """
    счётчик = collections.Counter()
    for данные in содержимое:
        for запись in (данные.get("strings") or {}).values():
            for язык, узел in (запись.get("localizations") or {}).items():
                состояние = None
                единица = узел.get("stringUnit")
                if единица:
                    состояние = единица.get("state")
                else:
                    формы = ((узел.get("variations") or {}).get("plural") or {})
                    for форма in формы.values():
                        вложенная = (форма or {}).get("stringUnit") or {}
                        if вложенная.get("state") in ("needs_review", "new"):
                            состояние = "needs_review"
                            break
                if состояние in ("needs_review", "new"):
                    счётчик[язык] += 1
    return счётчик


def содержимое_на(ссылка: str | None) -> list[dict] | None:
    """Каталоги на коммите (или с диска, если ссылка не задана)."""
    пути = [os.path.relpath(п, КОРЕНЬ) for п in каталоги()]
    if not пути:
        return None
    собрано = []
    for путь in пути:
        if ссылка is None:
            собрано.append(json.load(open(os.path.join(КОРЕНЬ, путь),
                                          encoding="utf-8")))
            continue
        готово = subprocess.run(
            ["git", "-C", КОРЕНЬ, "--no-optional-locks", "show",
             f"{ссылка}:{путь}"], capture_output=True, text=True)
        if готово.returncode != 0:
            continue          # файла на том коммите могло не быть
        собрано.append(json.loads(готово.stdout))
    return собрано or None


def откуда(долг: dict[str, int]) -> None:
    """Какие коммиты дали прирост — по одному, а не общим числом."""
    готово = subprocess.run(
        ["git", "-C", КОРЕНЬ, "--no-optional-locks", "log", "--format=%H %ad %s",
         "--date=format:%d.%m %H:%M", "-20", "--"]
        + [os.path.relpath(п, КОРЕНЬ) for п in каталоги()],
        capture_output=True, text=True)
    строки = [с for с in готово.stdout.split("\n") if с.strip()]
    if not строки:
        print("  git не отдал ни одного коммита по каталогам — "
              "разбор не состоялся")
        return
    print("\n  ОТКУДА ПРИРОС, по коммитам (новые сверху):\n")
    print(f"      {'коммит':10} {'когда':12} " +
          " ".join(f"{я:>6}" for я in sorted(долг)))
    прежний = None
    for строка in reversed(строки):
        хеш, когда, час, *слова = строка.split()
        данные = содержимое_на(хеш)
        if данные is None:
            continue
        c = счёт(данные)
        ряд = " ".join(f"{c[я]:>6}" for я in sorted(долг))
        дельта = ""
        if прежний is not None:
            дельта = "   Δ " + " ".join(
                f"{c[я] - прежний[я]:+d}" for я in sorted(долг))
        print(f"      {хеш[:9]:10} {когда} {час}  {ряд}{дельта}")
        прежний = c
    print(f"\n      {'ХРАПОВИК':23} " +
          " ".join(f"{долг[я]:>6}" for я in sorted(долг)))


def главное() -> int:
    долг = храповик()
    if not долг:
        print(f"✗ не прочитал числа долга из {СТОРОЖ} — "
              f"разбор не состоялся, и это НЕ «долг не вырос»",
              file=sys.stderr)
        return 2

    файлы = каталоги()
    if not файлы:
        print(f"✗ ни одного .xcstrings в {КОРНИ_КАТАЛОГОВ} — "
              f"разбор не состоялся", file=sys.stderr)
        return 2

    данные = содержимое_на(None)
    сейчас = счёт(данные)
    if not сейчас:
        print("✗ в каталогах ноль непроверенных строк на ВСЕХ языках — "
              "так не бывает, разбор не состоялся", file=sys.stderr)
        return 2

    print(f"  каталогов прочитано: {len(файлы)}")
    for путь in файлы:
        print(f"      {os.path.relpath(путь, КОРЕНЬ)}")
    print()
    print(f"  {'язык':6} {'храповик':>9} {'сейчас':>8} {'дельта':>8}")
    беда = []
    for язык in sorted(долг):
        было, стало = долг[язык], сейчас.get(язык, 0)
        знак = стало - было
        метка = "ВЫРОС" if знак > 0 else ("" if знак == 0 else "запас")
        print(f"  {язык:6} {было:>9} {стало:>8} {знак:>+8}  {метка}")
        if знак > 0:
            беда.append((язык, было, стало))

    # Языки, которых в храповике нет вовсе: молчание о них читалось бы
    # как «долга нет», а означает «за ними никто не следит».
    безнадзорные = sorted(set(сейчас) - set(долг))
    if безнадзорные:
        print(f"\n  ⚠ язык есть в каталоге и НЕ числится в храповике: "
              f"{безнадзорные}")
        print(f"      непроверенных у него "
              f"{', '.join(f'{я}={сейчас[я]}' for я in безнадзорные)} — "
              f"растёт без надзора")

    if "--откуда" in sys.argv:
        откуда(долг)

    if не_выросло := not беда:
        print("\n  ✓ долг не вырос — прогон на этом не покраснеет")
        return 0 if не_выросло else 1

    print(f"""
  ✗ ДОЛГ ВЫРОС — прогон покраснеет на `непроверенныхНеБольше`.

  Это не повод править число молча: «правку числа в долге считать
  вычиткой нельзя» (сторож говорит это сам). Порядок такой:

    1. `python3 Tools/долг-локализации.py --откуда` — какой коммит дал
       прирост и сколько;
    2. если прирост законный (завели новые ключи машинным переводом,
       и они помечены `needs_review` нарочно) — поднять числа
       в {СТОРОЖ}
       И ПОЛОЖИТЬ ДЕКОМПОЗИЦИЮ РЯДОМ, как сделано 03.11.2026;
    3. если прирост незаконный — значит `translated` где-то стал
       `needs_review`, и это регрессия вычитки.

  Храповик стоит ВПРИТЫК (замер 03.11): он красен при любой честной
  работе с каталогом. Это не дефект сторожа — это цена точности,
  и платить её дешевле здесь, чем двенадцатиминутным прогоном.""")
    return 1


if __name__ == "__main__":
    sys.exit(главное())
