КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТОКЕНЫ = os.path.join(КОРЕНЬ, "DesignTokens/tokens.json")
РЕЖИМЫ = ("dark", "light", "darkHC", "lightHC")
ССЫЛКА = re.compile(r"^\{([^}]+)\}$")


def загрузить():
    with open(ТОКЕНЫ, encoding="utf-8") as ф:
        return json.load(ф)


def достать(дерево, путь):
    узел = дерево
    for часть in путь.split("."):
        if not isinstance(узел, dict) or часть not in узел:
            return None
        узел = узел[часть]
    return узел


def значение(дерево, путь, режим, глубина=0):
    """Развернуть ссылку до цвета. Возвращает (цвет, цепь)."""
    if глубина > 12:
        return None, [f"{путь}: ЦИКЛ ССЫЛОК"]
    узел = достать(дерево, путь)
    if узел is None:
        return None, [f"{путь}: НЕТ ТАКОГО ПУТИ"]
    v = узел.get("$value") if isinstance(узел, dict) else None
    if v is None:
        return None, [f"{путь}: нет $value"]
    if isinstance(v, dict):
        if режим not in v:
            return None, [f"{путь}: режима {режим} нет"]
        v = v[режим]
    if isinstance(v, str):
        м = ССЫЛКА.match(v.strip())
        if м:
            цвет, цепь = значение(дерево, м.group(1), режим, глубина + 1)
            return цвет, [путь] + цепь
        return v.strip(), [путь]
    return None, [f"{путь}: значение не строка ({type(v).__name__})"]


def в_rgb(цвет):
    c = цвет.lstrip("#")
    if len(c) == 8:            # RRGGBBAA — альфу здесь отбрасываем
        c = c[:6]
    if len(c) == 3:
        c = "".join(ч * 2 for ч in c)
    if len(c) != 6:
        return None
    try:
        return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))
    except ValueError:
        return None


def альфа(цвет):
    """Доля непрозрачности 0..1, или None если её в записи нет."""
    c = цвет.lstrip("#")
    if len(c) != 8:
        return None
    try:
        return int(c[6:8], 16) / 255.0
    except ValueError:
        return None


def наложить(перёд, зад):
    """Смешать полупрозрачный передний план с ПОДЛОЖКОЙ.

    Почему это считается, а не объявляется неизмеримым. Полупрозрачная
    заливка на известном фоне — величина вычислимая: `a·перёд +
    (1−a)·зад`. Отказ её считать стоил дороже ошибки: `timeline.syncedMark`
    и `sheet.handleColor` числились «не замер вовсе» и потому
    не проверялись ВООБЩЕ, а `button.finish.label` дал в сводке 1,64
    и чуть не уехал как дефект подписи.

    И ГРАНИЦА, которая остаётся: если альфа у ЗАДНЕГО плана, под ним
    неизвестно что, и смешивать не с чем. Это по-прежнему
    не измеряется — но теперь неизмеримых случаев единицы, а не все.
    """
    a = альфа(перёд)
    rп, rз = в_rgb(перёд), в_rgb(зад)
    if a is None or rп is None or rз is None:
        return None
    return tuple(round(a * rп[i] + (1 - a) * rз[i]) for i in range(3))


def яркость(rgb):
    def к(к8):
        s = к8 / 255.0
        return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4
    r, g, b = (к(x) for x in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def контраст(a, b):
    """Контраст переда к заду. Альфу переда СМЕШИВАЕТ, альфу зада — нет.

    Возвращает (число, пометка). Пометка пуста, когда замер полный.
    """
    if альфа(b) is not None:
        return None, "НЕ ИЗМЕРЯЕТСЯ: альфа у ЗАДНЕГО плана, под ним неизвестно что"
    rb = в_rgb(b)
    if rb is None:
        return None, "задний план не разобран"
    if альфа(a) is not None:
        ra = наложить(a, b)
        пометка = f"альфа {альфа(a):.0%} смешана с подложкой"
    else:
        ra = в_rgb(a)
        пометка = ""
    if ra is None:
        return None, "передний план не разобран"
    la, lb = яркость(ra), яркость(rb)
    светлее, темнее = max(la, lb), min(la, lb)
    return (светлее + 0.05) / (темнее + 0.05), пометка


