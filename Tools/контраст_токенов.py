ГЕНЕРАТ = os.path.join(КОРЕНЬ, "TogoShared/Generated/Tokens.generated.swift")
ИСХОДНИКИ = ("Togo", "TogoShared", "TogoWidgets")

# Переименования слоя: в JSON роль зовётся одним словом, в Swift другим.
# Список короткий нарочно — он не угадывается, а читается из
# `Tools/generate_tokens.py`, и если там заведут новое, здесь
# появится «символ не опознан», а не тихий ноль.
ПЕРЕИМЕНОВАНИЯ = {"text": "Ink"}


def свифт_имя(путь):
    """`component.button.secondary.background` → `Button.Secondary.background`.

    Первый сегмент (`component`/`semantic`/`primitive`) в Swift
    не печатается: там это `Token.Component.Button…`, но искать удобнее
    по хвосту — он однозначен и переживает смену обёртки.
    """
    части = путь.split(".")[1:]
    if not части:
        return None
    голова = [ПЕРЕИМЕНОВАНИЯ.get(ч, ч[:1].upper() + ч[1:]) for ч in части[:-1]]
    return ".".join(голова + [части[-1]])


_кэш_читателей = {}


def читатели(путь):
    """Сколько раз роль зовут в ЖИВОМ коде, мимо сгенерированного.

    ЗАЧЕМ ЭТО ВНУТРИ ИНСТРУМЕНТА, А НЕ РЯДОМ С НИМ. Прежняя редакция
    печатала о себе: «живых читателей роли он не считает — роль без
    читателя даёт тот же счёт, что роль на главном экране». Автор этой
    строки (я) прочитал её и всё равно вывел из двух пар «байт в байт»
    утверждение о двух экранах: `actionTile.background`
    и `chip.restBackground` сидят на `night4`, дают честное 1,0000:1
    и **не зовутся ниоткуда** — ни один экран ими не красится.

    > Напечатанная граница защищает не больше, чем знание правила.
    > Защищает только команда, которую после неё запускаешь.

    Отличать «ноль читателей» от «я не сумел собрать имя» обязательно:
    первое — свойство продукта, второе — отказ инструмента, и молча
    они выглядят одинаково.
    """
    if путь in _кэш_читателей:
        return _кэш_читателей[путь]
    имя = свифт_имя(путь)
    итог = (None, "имя не собралось")
    if имя:
        try:
            with open(ГЕНЕРАТ, encoding="utf-8") as ф:
                генерат = ф.read()
        except OSError as e:
            итог = (None, f"сгенерированный не прочитан: {e}")
        else:
            лист = имя.rsplit(".", 1)[-1]
            владелец = имя.rsplit(".", 1)[0] if "." in имя else ""
            # Объявление ищем по листу: обёртки `enum` вложены, и полного
            # пути в одной строке нет ни у одного токена.
            if f"let {лист} " not in генерат and f"let {лист}:" not in генерат:
                итог = (None, f"символ «{имя}» в сгенерированном НЕ НАЙДЕН")
            else:
                цель = f"{владелец}.{лист}" if владелец else лист
                n = 0
                for корень in ИСХОДНИКИ:
                    путь_к = os.path.join(КОРЕНЬ, корень)
                    for вверх, _, файлы in os.walk(путь_к):
                        if "Generated" in вверх:
                            continue
                        for ф_имя in файлы:
                            if not ф_имя.endswith(".swift"):
                                continue
                            with open(os.path.join(вверх, ф_имя),
                                      encoding="utf-8", errors="replace") as ф:
                                n += ф.read().count(цель)
                итог = (n, цель)
    _кэш_читателей[путь] = итог
    return итог


def все_цветные(дерево, корень="component"):
    """Все цветовые токены ветки — перечислением, а не руками.

    Ради слепого места, которое этот инструмент печатает о себе сам:
    «пара, которой в списке нет, НЕ ПРОВЕРЕНА, а не хороша». Список
    из 14 пар собран руками, и руками же он кончается там, где кончилось
    терпение автора: C-1 нашёлся в `button.secondary`, а в `chip`,
    `actionTile` и `timeline` никто не смотрел ни разу.
    """
    def обойти(o, путь):
        if isinstance(o, dict):
            if "$value" in o:
                if o.get("$type") == "color":
                    yield путь
                return
            for k, v in o.items():
                if k.startswith("$"):
                    continue
                yield from обойти(v, f"{путь}.{k}" if путь else k)
    return list(обойти(достать(дерево, корень) or {}, корень))


# Хвосты имён, по которым видно роль. Это ДОГАДКА об оси, и она
# печатается как догадка: автоматический провал — повод посмотреть,
# а не названный дефект. Разница не косметическая: у названной руками
# пары есть автор и порог, у этой нет ни того, ни другого.
ЗАЛИВКА = ("background", "backgrounddose", "bar", "marker", "mark", "color")
НАДПИСЬ = ("label", "text", "title", "sub")


def сплошной_обход(дерево):
    """Каждая заливка — к фону экрана и к карточке; надпись — к своей
    заливке, если она есть у соседа."""
    пары = []
    все = все_цветные(дерево)
    for путь in все:
        хвост = путь.rsplit(".", 1)[-1].lower()
        if any(хвост.endswith(с) for с in НАДПИСЬ):
            родитель = путь.rsplit(".", 1)[0]
            сосед = None
            for кандидат in все:
                if (кандидат.startswith(родитель + ".")
                        and кандидат.rsplit(".", 1)[-1].lower()
                        .endswith("background")):
                    сосед = кандидат
                    break
            if сосед:
                пары.append((путь, сосед, 4.5,
                             f"АВТО · надпись на своей заливке"))
            continue
        if any(хвост.endswith(с) for с in ЗАЛИВКА):
            пары.append((путь, "semantic.surface.screen", 3.0,
                         "АВТО · заливка к фону экрана"))
            пары.append((путь, "semantic.surface.card", 3.0,
                         "АВТО · заливка к карточке"))
    return пары


def main():
    дерево = загрузить()
    провалы = []
    неизмеренные = []
    пары = list(ПАРЫ)
    сплошной = "--все" in sys.argv
    if сплошной:
        названные = {(п, з) for п, з, _, _ in ПАРЫ}
        пары += [т for т in сплошной_обход(дерево)
                 if (т[0], т[1]) not in названные]
    print("=" * 74)
    print("КОНТРАСТ ПО ТОКЕНАМ ПРИЛОЖЕНИЯ (DesignTokens/tokens.json)")
    if сплошной:
        print(f"СПЛОШНОЙ ОБХОД: {len(ПАРЫ)} пар названо руками, "
              f"{len(пары) - len(ПАРЫ)} добрано перечислением")
        print("У ДОБРАННЫХ ОСЬ НЕ НАЗВАНА ЧЕЛОВЕКОМ — их провал это")
        print("«посмотреть», а не дефект: роль угадана по хвосту имени,")
        print("а на чём элемент лежит на самом деле, инструмент не знает.")
    else:
        print("пары названы руками. Сплошной обход — ключ --все")
    print("=" * 74)
    for перёд, зад, порог, ось in пары:
        print()
        print(f"· {ось}")
        n, как = читатели(перёд)
        if n is None:
            чит = f"читателей НЕ СОСЧИТАНО — {как}"
        elif n == 0:
            чит = f"живых читателей НОЛЬ (искал «{как}») — роль не зовут ниоткуда"
        else:
            чит = f"живых читателей {n} (искал «{как}»)"
        print(f"  {перёд}")
        print(f"  {чит}")
        print(f"  на {зад}   порог {порог}")
        for режим in РЕЖИМЫ:
            цп, цепь_п = значение(дерево, перёд, режим)
            цз, цепь_з = значение(дерево, зад, режим)
            if цп is None or цз is None:
                причина = цепь_п[-1] if цп is None else цепь_з[-1]
                print(f"    {режим:<8} НЕ ИЗМЕРЕНО — {причина}")
                неизмеренные.append((перёд, зад, режим, причина))
                continue
            k, пометка = контраст(цп, цз)
            if k is None:
                print(f"    {режим:<8} НЕ ИЗМЕРЕНО — {пометка} "
                      f"({цп} / {цз})")
                неизмеренные.append((перёд, зад, режим, пометка))
                continue
            альфа = f"  ← {пометка}" if пометка else ""
            знак = "✔" if k >= порог else "✘"
            if k < порог:
                провалы.append((перёд, зад, режим, k, порог, ось))
            print(f"    {режим:<8} {знак} {k:7.4f}:1   "
                  f"{цп} на {цз}{альфа}")
            if k < 1.05:
                print(f"             ↳ цепь переда: "
                      f"{' → '.join(цепь_п)}")
                print(f"             ↳ цепь зада:   "
                      f"{' → '.join(цепь_з)}")
    print()
    print("=" * 74)
    print(f"ПАР: {len(пары)} × {len(РЕЖИМЫ)} режима = "
          f"{len(пары) * len(РЕЖИМЫ)} замеров")
    названные_провалы = [п for п in провалы if not п[5].startswith("АВТО")]
    авто_провалы = [п for п in провалы if п[5].startswith("АВТО")]
    print(f"НЕ ПРОХОДЯТ ПОРОГ: {len(названные_провалы)} у названных пар · "
          f"{len(авто_провалы)} у добранных · "
          f"НЕ ИЗМЕРЕНО: {len(неизмеренные)}")
    if названные_провалы:
        print()
        print("НЕ ПРОХОДЯТ — ПАРЫ С НАЗВАННОЙ ОСЬЮ:")
        for перёд, зад, режим, k, порог, ось in названные_провалы:
            print(f"  {режим:<8} {k:7.4f}:1 (порог {порог})  {ось}")
    # Байт в байт — отдельно от «слабо»: это разные состояния, и лечатся
    # они разным. 1,0000 значит, что элемента на экране НЕТ, а 1,4 —
    # что он слабый, но есть (системная рампа Apple держит заливку
    # на 1,26–1,52 и считает это нормой для неактивного).
    байт_в_байт = sorted({(п[0], п[1], п[2]) for п in провалы
                          if п[3] < 1.0001})
    if байт_в_байт:
        # Разделение по читателям обязательно: «элемента на экране нет»
        # и «роль никто не зовёт» дают ОДНО И ТО ЖЕ число и означают
        # противоположное. На этом я построил неверное письмо.
        живые, мины, тёмные = [], [], []
        for перёд, зад, режим in байт_в_байт:
            n, _ = читатели(перёд)
            (живые if n else (тёмные if n is None else мины)).append(
                (перёд, зад, режим))
        if живые:
            print()
            print("БАЙТ В БАЙТ И РОЛЬ ЗОВУТ — ЭЛЕМЕНТА НА ЭКРАНЕ НЕТ ВОВСЕ:")
            for перёд, зад, режим in живые:
                n, _ = читатели(перёд)
