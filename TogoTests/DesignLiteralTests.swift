import Testing
import Foundation

/// Числа и цвета в слое вида.
///
/// Связывание с Figma держится на том, что оформление приходит из
/// токенов: один и тот же кегль в макете и в коде — это одно значение,
/// а не два похожих. Число, вписанное в вид руками, разрывает связь
/// молча — макет меняется, приложение нет, и никто не узнаёт.
///
/// Цвет и тень здесь **строго ноль**: на 23.09 их в слое вида нет
/// ни одного, и сторож не даёт появиться первому. Кегли, радиусы
/// и размеры — долг, он может только уменьшаться.
///
/// Опись и решения — `docs/FIGMA-ПОДГОТОВКА.md`.
@Suite("Оформление без литералов")
struct DesignLiteralTests {

    private static let слойВида = ["Togo/DesignSystem", "Togo/Features"]

    /// Долг по видам. Кегль перемерен 14.10.2026, остальное — 23.09.2026.
    ///
    /// **Кегль задаётся числом ДВУМЯ формами, а сторож видел одну.**
    /// До 14.10 здесь стоял единственный вид «кегль» с долгом 36,
    /// и искал он `.font(.system(size: N))` — 33 вхождения, честно
    /// зелёный с запасом в три. Второй формы, `AppFont.numeric(N)`,
    /// он не видел вовсе, а её **сорок девять**.
    ///
    /// Защиты не было именно там, где её считали стоящей: добавь
    /// кто-нибудь кегль через `AppFont.numeric` — сторож не шелохнулся
    /// бы. И хуже: вторая форма короче и удобнее первой, то есть долг
    /// **перетекал в слепую зону** и выглядел убывающим.
    ///
    /// > **Храповик, считающий одну форму из двух, растёт молча
    /// > и показывает убыль.**
    ///
    /// **Два вида вместо одной суммы 82, и это не педантизм.** Общий
    /// порог позволяет ровно то же перетекание внутри себя: убрал одно
    /// `.font(.system(size:))`, добавил один `AppFont.numeric` — сумма
    /// прежняя, сторож молчит, а долг переехал в форму, которую мы
    /// только что признали опасной. Два числа ловят это сразу.
    ///
    /// 33 и 49 — не «стало хуже», а «впервые измерено».
    /// Разбор сорока девяти мест — отдельная работа и не сегодня.
    ///
    /// **`размер` = 36 при 42 на вершине — НЕ ошибка и не поднимать.**
    /// Это решение с хозяином, записанное в `Tools/эталон-прогона.json`:
    /// из шести приростов только два (`LabChartScreen:343` и `:403`)
    /// являются размерами в смысле сторожа, остальные — холсты
    /// отладочных галерей и якорь `1x1` у `TGPosterHeader`. Порог
    /// не поднят сознательно: поднятый по непринятому стал бы дырой
    /// ровно того размера. Хозяин — дизайн и менеджер содержимого.
    private let долг: [String: Int] = [
        "кегль": 33,
        "кегль-numeric": 49,
        "радиус": 3,
        "размер": 36,
    ]

    @Test("Цвета и теней в слое вида нет ни одного")
    func цветаНет() throws {
        let цвет = try Self.посчитать(
            #"\.(red|blue|green|yellow|orange|purple|pink|gray|grey|black|white)\b"#,
            // **Три формы дописаны 22.10.2026, и дописаны по тому же разбору,
            // что сосед снизу: храповик, считающий одну форму из двух, растёт
            // молча и показывает убыль.**
            //
            // Прежние три шаблона ловили имя системного цвета, `Color(red:…)`
            // и хекс со знаком решётки. Формы, которыми цвет задаётся в ЭТОМ
            // проекте, среди них не было ни одной: сгенерированные токены
            // печатают `Color(hex: 0xRRGGBBAA)`, то есть `Color(hex:` плюс
            // целое с `0x`, а решётки там нет вовсе. Сторож на цвет был слеп
            // ровно к тому виду записи, который в проекте и употребляется, —
            // и «строго ноль» в его заголовке это скрывало.
            //
            // Добавлены после ЗАМЕРА, а не на всякий случай: по 109 файлам
            // слоя вида `Color(hex:` — 0, `0x` с шестью цифрами — 0,
            // `UIColor(` — 0. То есть шаблоны закрывают дыру и не заводят
            // долга. `.opacity(` ИЗМЕРЕНО И НЕ ДОБАВЛЕНО: семь живых
            // вхождений, и прозрачность — не сырой цвет.
            //
            // **Чего эта правка не доказывает.** Подделкой она не проверена:
            // `make guard` на этом наборе не работает по устройству
            // `check_guard.py` — у набора есть объявленное красное («размер»
            // 36 при 42), и инструмент отказывается до подделки. Значит
            // основание здесь — измеренный ноль по трём шаблонам, а не
            // пойманная подделка, и это слабее.
            плюс: [#"Color\(red:"#, "#[0-9A-Fa-f]{6}",
                   #"Color\(hex:"#, "0x[0-9A-Fa-f]{6}", #"UIColor\("#])
        #expect(цвет.всего == 0, """
            литеральный цвет в слое вида: \(цвет.примеры.prefix(3).joined(separator: " | ")).
            Цвет приходит из Token.*, иначе макет и приложение расходятся молча.
            """)
        let тень = try Self.посчитать(#"\.shadow\("#)
        #expect(тень.всего == 0, """
            литеральная тень: \(тень.примеры.prefix(3).joined(separator: " | ")).
            Тень — токен уровня, а не четыре числа в месте применения.
            """)
    }

    @Test("Кеглей, радиусов и размеров числом не становится больше")
    func долгНеРастёт() throws {
        let виды: [String: String] = [
            "кегль": #"\.font\(\.system\(size: *[0-9]"#,
            // Вторая форма того же: `AppFont.numeric` принимает кегль
            // `CGFloat` первым аргументом, и число там — такой же
            // литерал оформления, как в `.system(size:)`. Своим видом,
            // а не частью первого шаблона: см. разбор у `долг`.
            "кегль-numeric": #"AppFont\.numeric\( *[0-9]"#,
            "радиус": #"cornerRadius: *[0-9]|\.cornerRadius\( *[0-9]"#,
            "размер": #"\.frame\((width|height|minWidth|minHeight|maxHeight): *[0-9]"#,
        ]
        // Проверка, что проверять БЫЛО ЧТО, и она первая.
        //
        // Сканирующий сторож молчит одинаково и когда всё хорошо,
        // и когда он ослеп: ошибка в шаблоне, переехавший каталог,
        // `enumerator`, вернувший пустоту. Ноль найденного по всем
        // видам сразу — это отказ инструмента, а не чистый код:
        // литералы здесь есть, они объявлены долгом в этом же файле.
        let всегоПоВсемВидам = try виды.values.reduce(0) { $0 + (try Self.посчитать($1).всего) }
        #expect(всегоПоВсемВидам > 0, """
            сканер не нашёл НИ ОДНОГО литерала ни по одному виду — \
            это отказ сторожа, а не чистый слой вида: долг в этом же \
            файле объявлен ненулевым. Смотреть каталоги \(Self.слойВида) \
            и обход файлов, а не код продукта.
            """)

        for (вид, шаблон) in viedSorted(виды) {
            let найдено = try Self.посчитать(шаблон)
            let разрешено = долг[вид] ?? 0
            #expect(найдено.всего <= разрешено, """
                \(вид): числом \(найдено.всего) при долге \(разрешено). \
                Нет подходящего токена — завести его в DesignTokens/tokens.json, \
                а не подставить число. Примеры: \
                \(найдено.примеры.prefix(3).joined(separator: " | "))
                """)
        }
    }

    private func viedSorted(_ виды: [String: String]) -> [(String, String)] {
        виды.sorted { $0.key < $1.key }.map { ($0.key, $0.value) }
    }

    private static func посчитать(_ шаблон: String,
                                  плюс дополнительные: [String] = []) throws
        -> (всего: Int, примеры: [String]) {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        var выражения = [try NSRegularExpression(pattern: шаблон)]
        выражения += try дополнительные.map { try NSRegularExpression(pattern: $0) }

        var всего = 0
        var примеры: [String] = []
        for каталог in слойВида {
            let база = корень.appendingPathComponent(каталог)
            let обход = FileManager.default.enumerator(at: база, includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
                for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                    let код = строка.components(separatedBy: "//")[0]
                    guard !код.contains("Token."), !код.isEmpty else { continue }
                    let диапазон = NSRange(код.startIndex..., in: код)
                    guard выражения.contains(where: {
                        $0.firstMatch(in: код, range: диапазон) != nil
                    }) else { continue }
                    всего += 1
                    if примеры.count < 5 {
                        примеры.append("\(элемент.lastPathComponent):\(номер + 1)")
                    }
                }
            }
        }
        return (всего, примеры)
    }
}
