    /// Условие «список уменьшается и не растёт» соблюдалось буквально,
    /// зрение не росло — а соблюдённое условие читается как движение.
    ///
    /// Поэтому здесь стоит не только список, но и его доля: мерить надо
    /// отношение, а не длину. Голая длина не скажет, много это или всё.
    ///
    /// Разбор распределён менеджером поимённо 05.10: `Medication`
    /// и `DoseRecord` — togo-5a, три тренировочные — togo-9e, `Dog` —
    /// togo-f5, события с концом — togo-f2, три мелкие — менеджер,
    /// `FoodStock` — togo-45 (сделан).
    ///
    /// **Пусто с 07.10.2026 — разобраны все шестнадцать.** Из раздачи
    /// 05.10 доехали `Dog` и `FoodStock`; остальные двенадцать
    /// (123 поля) разобрал togo-16 одним заходом, потому что раздача
    /// поимённо за два дня закрыла две модели из четырнадцати, а список
    /// всё это время читался как движение.
    ///
    /// **Список пуст — и именно поэтому он остаётся здесь, а не
    /// удаляется.** Пустой он работает воротами: новая модель не может
    /// попасть ни в него, ни мимо него незаметно — `долгНеРастёт`
    /// требует разложить её поля, а `доляОсмотренного` ниже печатает
    /// отношение, а не длину. Удали его — и у следующей модели
    /// появится место, куда её можно отложить молча.
    ///
    /// Дописывать сюда модель можно, но тогда доля перестанет быть
    /// полной, и проверка скажет это числом.
    private static let ещёНеРазобраны: Set<String> = []

    /// Хранимые поля каждой `@Model` — из исходника, а не списком.
    ///
    /// Членом класса считается только то, что стоит на уровне тела:
    /// разбор по одной строке не отличает поле от локальной переменной
    /// внутри вычисляемого свойства и ошибается **в сторону полноты**.
    /// Так 23.09 снимок схемы вышел на поле богаче настоящего, и
    /// хранилище не открылось.
    private func поля() throws -> [String: [String]] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models")
        var собрано: [String: [String]] = [:]

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }

            let строки = текст.components(separatedBy: .newlines)
            var i = 0
            while i < строки.count {
                guard строки[i].trimmingCharacters(in: .whitespaces) == "@Model",
                      i + 1 < строки.count,
                      let имя = строки[i + 1]
                        .firstMatch(#"(?:nonisolated )?final class (\w+)"#)
                else { i += 1; continue }

                var глубина = 0
                var найденные: [String] = []
                var j = i + 1
                while j < строки.count {
                    let строка = строки[j]
                    // Уровень тела класса — **единица**, а не ноль:
                    // строка `final class X {` уже открыла скобку.
                    // Первая редакция сравнивала с нулём, не находила
                    // ни одного поля и была зелёной при любом новом —
                    // поймала подделка, а не чтение.
                    let член = глубина == 1 && строка.firstMatch(#"^    \S"#) != nil
                    глубина += строка.filter { $0 == "{" }.count
                    глубина -= строка.filter { $0 == "}" }.count
                    if j > i + 1, глубина == 0 { break }
                    guard член else { j += 1; continue }
                    let голая = строка.trimmingCharacters(in: .whitespaces)
                        .replacingOccurrences(of: #"^@\w+\([^)]*\)\s*"#,
                                              with: "", options: .regularExpression)
                    if !голая.contains("{"),
                       let поле = голая.firstMatch(#"^var (\w+): "#) {
                        найденные.append(поле)
                    }
                    j += 1
                }
                собрано[имя] = найденные
                i = j
            }
        }
        return собрано
    }

    @Test("Каждое поле разобранной модели попало ровно в один список")
    func третьегоНеДано() throws {
        let модели = try поля()
        #expect(модели.count >= 14, """
            моделей разобрано \(модели.count) — разбор не состоялся.
            Набор, которому нечего проверять, молчит так же, как набор,
            у которого всё хорошо.
            """)

        // **Счёт полей, а не только моделей.** Первая редакция этой
        // проверки считала модели и молчала: поля разбирались в пустой
        // список, «без решения» получалось ноль, и сторож был зелёным
        // при любом новом поле. Поймала подделка — дописанное
        // `lastSeenOnThisPhone` прошло насквозь.
        //
        // Сканер, переставший что-либо находить, молчит так же, как
        // тот, кому нечего сказать.
        #expect(модели["FamilyMember"]?.count ?? 0 >= 10, """
            у FamilyMember разобрано \(модели["FamilyMember"]?.count ?? 0) полей —
            разбор полей не состоялся, и сторож зелен впустую.
            """)
        #expect(модели["LogEvent"]?.count ?? 0 >= 10, """
            у LogEvent разобрано \(модели["LogEvent"]?.count ?? 0) полей.
            """)

        var безРешения: [String] = []
        var вДвух: [String] = []
        for (модель, поля) in модели.sorted(by: { $0.key < $1.key })
        where !Self.ещёНеРазобраны.contains(модель) {
            for поле in поля {
                let ключ = "\(модель).\(поле)"
                let телефон = Self.проЭтотТелефон[ключ] != nil
                let семья = Self.проСемью.contains(ключ)
                if телефон && семья { вДвух.append(ключ) }
                if !телефон && !семья { безРешения.append(ключ) }
            }
        }

        #expect(вДвух.isEmpty, "поле и ездит, и не ездит: \(вДвух)")
        #expect(безРешения.isEmpty, """
            у поля не записано, про семью оно или про этот телефон:
            \(безРешения)

            Ответь на один вопрос: значит ли это поле на ДРУГОМ телефоне
            то же самое? Если нет — оно про устройство, и уезжать ему
            нельзя. Так `isMe` сделал своей карточку владельца.
            """)
    }

    @Test("Список неразобранных только уменьшается")
    func долгНеРастёт() throws {
        let модели = Set(try поля().keys)
        let лишние = Self.ещёНеРазобраны.subtracting(модели).sorted()
        #expect(лишние.isEmpty, """
            в списке неразобранных числятся модели, которых нет:
            \(лишние). Убери их — список, переживший свои строки,
            разрешает вернуть то, что уже разобрано.
            """)

        let новые = модели.subtracting(Self.ещёНеРазобраны)
            .subtracting(Self.разобраны)
            .sorted()
        #expect(новые.isEmpty, """
            появилась модель, которую никто не разбирал: \(новые).
            Впиши её поля в один из двух списков — или в список
            неразобранных, но тогда назови это вслух.
            """)
    }

    /// Доля осмотренного — числом, а не длиной списка.
    ///
    /// **Почему отношение, а не список.** Условие «список уменьшается
    /// и не растёт» соблюдалось буквально с 05.10 и было соблюдено
    /// при зрении в 12,5 %: моделей шестнадцать, в списке четырнадцать,
    /// осматривались две. Соблюдённое условие читается как движение,
    /// и прочитали его так дважды — замером togo-f5 и верхом
    /// `СТАТУС.md`, который звал «двенадцать неразобранных» ещё через
    /// двое суток после того, как их стало меньше.
    ///
    /// Поэтому проверка печатает обе величины рядом — осмотрено
    /// и всего. Строка, отвечающая на вопрос «есть ли охрана»,
    /// читается как ответ на «вся ли»; различает их только дробь.
    /// **Имя теста намеренно без чисел.** Первая редакция звалась
    /// «Осмотрено 16 моделей из 16 и 226 полей из 226» — то есть несла
    /// утверждение, которое устареет при первой новой модели, а тело
    /// останется верным. Имя читают ВМЕСТО кода, и стареет оно молча:
    /// у Gamut такой `…AddingLeadsToPaywall` пять дней рассказывал
    /// обратную историю при починенном теле.
    ///
    /// Числа живут ниже, в порогах, где их проверяет прогон.
    @Test("Осмотрены все модели и все их поля, доля печатается")
    func доляОсмотренного() throws {
        let модели = try поля()
        let всегоМоделей = модели.count
        let осмотреноМоделей = модели.keys
            .filter { !Self.ещёНеРазобраны.contains($0) }.count
        let всегоПолей = модели.values.map(\.count).reduce(0, +)
        let осмотреноПолей = модели
            .filter { !Self.ещёНеРазобраны.contains($0.key) }
            .values.map(\.count).reduce(0, +)

        let дробь = """
            осмотрено \(осмотреноМоделей) из \(всегоМоделей) моделей \
            и \(осмотреноПолей) из \(всегоПолей) полей
            """

        // **Порог на ЗНАМЕНАТЕЛЬ, и без него вся проверка — обман.**
        // Разбор перестанет находить `@Model` — и обе проверки ниже
        // дадут `0 == 0`, то есть полную долю при нулевом знаменателе.
        // Я написал эту проверку против «списка, который не может
        // покраснеть», и с первого раза сделал проверку, которая
        // не может покраснеть, тем же способом с другого конца;
        // нашёл togo-1e, у которого пустой разбор архива точно так же
        // выдавал бы «снимка нет вовсе» про все шестнадцать моделей.
        //
        // Числа сняты на 047f2e0 двумя независимыми разборами, и это
        // не самозамер: мой (этот файл, по скобкам) и разбор
        // `Tools/замер_паритета_архива.py` togo-1e, написанный врознь
        // и из другого вопроса, дали одно — 16 моделей и 226 полей
        // (181 данных + 21 служебное + 24 связи дерева).
        #expect(всегоМоделей >= 16, """
            разбор нашёл \(всегоМоделей) моделей вместо 16 и более.
            Сканер, переставший что-либо находить, молчит так же, как
            тот, кому нечего сказать, — а доля при этом выйдет полной.
            """)
        #expect(всегоПолей >= 226, """
            разбор нашёл \(всегоПолей) полей вместо 226 и более.
            Это про разбор, а не про модели: поля не исчезают,
            исчезает зрение.
            """)

        // **Порог числом СЛАБЕЕТ с каждым новым полем, и это сказано
        // здесь, а не оставлено следующему.** 226 снято на `047f2e0`;
        // на 07.10 вечером в каталоге уже 242. Значит порог ловит
        // «разбор ослеп целиком» и всё хуже ловит «ослеп наполовину»:
        // при 242 полях он промолчит о потере шестнадцати.
        //
        // Поднимать его руками — обещание, которое держится до первой
        // спешки. Поэтому ниже два счёта, которые растут сами.
        // Проверять одну реализацию наблюдениями за другой нельзя,
        // но СРАВНИВАТЬ два независимых разбора можно и нужно: спор
        // между ними видно, а молчание одного — нет.

        // Нижняя граница — там, где зрение было на 047f2e0. Она ловит
        // откат: вернувший модель в список получит красное, а не
        // формально соблюдённое «список не вырос».
        #expect(осмотреноМоделей == всегоМоделей, """
            \(дробь).
            Непросмотренные: \(модели.keys.filter { Self.ещёНеРазобраны.contains($0) }.sorted()).
            Было 4 из 16 моделей и 103 из 226 полей (047f2e0, 07.10).
            Список, в который входит почти всё, — это сторож, который
            не может покраснеть.
            """)
        #expect(осмотреноПолей == всегоПолей, "\(дробь)")
    }

    /// Разбор не ослеп наполовину: два счёта не спорят, и ни одна
    /// модель не пуста.
    ///
    /// **Чем это оплачено и почему порога числом не хватает.** Порог
    /// `всегоПолей >= 226` снят на `047f2e0`; к вечеру того же дня
    /// медицинский слой довёл каталог до 242. Порог от этого не сломался
    /// — он **ослаб**: теперь между ним и правдой шестнадцать полей,
    /// и потерю половины модели он пропустит молча. Поднимать его руками
    /// — обещание, держащееся до первой спешки; у нас это записано
    /// про сторожей трижды.
    ///
    /// Поэтому здесь две проверки, которые растут сами:
    ///
    /// * **два независимых счёта моделей.** Разбор сторожа идёт
    ///   по скобкам и зависит от `final class` на следующей строке
    ///   и от баланса фигурных; наивный счёт строк `@Model` не зависит
    ///   ни от того, ни от другого. Сойтись они могут только если
    ///   оба правы; разойтись — значит один ослеп, и видно, который;
    /// * **ни одной модели без полей.** Ослепший наполовину разбор
    ///   даёт модель, у которой нет ни одного поля, и доля при этом
    ///   остаётся полной: `осмотрено == всего`, потому что обе
    ///   величины считает он же. Замер 07.10: минимум полей у модели
    ///   — четыре (`WeightEntry`), ноль не бывает ни у одной.
    ///
    /// > **Проверять одну реализацию наблюдениями за другой нельзя,
    /// > но сравнивать два независимых разбора можно и нужно: спор
    /// > между ними видно, а молчание одного — нет.**
    @Test("Разбор не ослеп: два счёта моделей не спорят, пустых моделей нет")
    func разборНеОслеп() throws {
        let модели = try поля()
        let наивно = try Self.наивныйСчётМоделей()

        #expect(модели.count == наивно, """
            два разбора спорят: по скобкам \(модели.count) моделей, \
            строк `@Model` \(наивно).
            Один из них ослеп, и спор говорит, который: меньше нашёл —
            тот и слеп. Пока они спорят, доля осмотренного ничего
            не утверждает: её считает тот же разбор, что и знаменатель.
            """)

        let пустые = модели.filter { $0.value.isEmpty }.keys.sorted()
        #expect(пустые.isEmpty, """
            модель без единого поля: \(пустые).
            Так выглядит разбор, ослепший НАПОЛОВИНУ — и доля при этом
            полная, потому что `осмотрено` и `всего` считает он же.
            Замер 07.10: минимум у модели четыре поля (WeightEntry).
            """)
    }

    /// Счёт моделей вторым способом — строками `@Model`, без скобок.
    ///
    /// Нарочно примитивный: его задача не разобрать, а **не зависеть**
    /// от того, от чего зависит разбор сторожа.
    private static func наивныйСчётМоделей() throws -> Int {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models")
        var счёт = 0
        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            счёт += текст.components(separatedBy: .newlines)
                .filter { $0.trimmingCharacters(in: .whitespaces) == "@Model" }
                .count
        }
        return счёт
    }

    /// В списках нет полей, которых в моделях нет.
    ///
    /// **Ключ с опечаткой — мёртвый груз, и он молчит.** Список,
    /// переживший своё поле, не падает и ничего не охраняет:
    /// `третьегоНеДано` смотрит из моделей в списки, а не наоборот,
    /// и лишний ключ ему просто не встретится. Переименуй поле — и его
    /// охрана останется в файле строкой, которая выглядит охраной.
    ///
    /// Тот же класс, что у «списка неразобранных, пережившего свои
    /// строки», только у списков решений, где он дороже: там лишняя
    /// строка разрешала вернуть разобранное, здесь она делает вид,
    /// что поле разобрано.
    @Test("В списках нет полей, которых в моделях нет")
    func нетПризрачныхКлючей() throws {
        let живые = Set(try поля().flatMap { модель, поля in
            поля.map { "\(модель).\($0)" }
        })
        let призраки = Self.проСемью.union(Self.проЭтотТелефон.keys)
            .subtracting(живые).sorted()
        #expect(призраки.isEmpty, """
            в списках числятся поля, которых в моделях нет: \(призраки).
            Опечатка или переименование: ключ не охраняет ничего
            и при этом читается как решение.
            """)
    }

    @Test("У каждого «не ездит» записана причина")
    func причиныЕсть() {
        let безПричины = Self.проЭтотТелефон
            .filter { $0.value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            .map(\.key).sorted()
        #expect(безПричины.isEmpty, """
            «не ездит» без причины: \(безПричины).
            Исключение без причины через месяц неотличимо от дыры.
            """)
    }
}

private extension String {
    /// Первая группа первого совпадения — или `nil`.
    func firstMatch(_ образец: String) -> String? {
        guard let re = try? NSRegularExpression(pattern: образец),
              let m = re.firstMatch(in: self, range: NSRange(startIndex..., in: self))
        else { return nil }
        let группа = m.numberOfRanges > 1 ? 1 : 0
        return Range(m.range(at: группа), in: self).map { String(self[$0]) }
    }
}
