import Testing
import Foundation
@testable import Togo

/// `WalkDose` зовут из продукта, а не только из тестов.
///
/// # Зачем сторож на ВЫЗОВ, а не на поведение
///
/// `WalkDose.рядом` был написан, покрыт девятью тестами и **не вызывался
/// ниоткуда**: единственными его читателями были сами тесты. Такой
/// модуль снаружи неотличим от работающего — компилятор молчит, набор
/// зелёный, а человек окна дозы не видит никогда.
///
/// > **Зелёный тест без места вызова значит две разные вещи, и снаружи
/// > они неразличимы: «не доделали» и «решили не делать».**
///
/// Здесь это было первое: в голове модуля причина описывает ФОРМУ
/// («окно ±30 минут, два ответа раздельно»), а не решение не делать.
///
/// # Почему разбор режет комментарии
///
/// В `NeedsSheet.swift` имя `WalkDose` стоит и в прозе — в объяснении,
/// почему два ответа нельзя сводить в один признак. Сторож, не
/// различающий код и прозу, остался бы зелёным на удалённом вызове:
/// у нас это уже случалось дважды, и один раз сторож покраснел
/// на комментарии о починке.
///
/// Проверяется это самим набором — `прозаНеСчитаетсяКодом` ниже.
@Suite("Доза рядом с выходом: модуль подключён")
struct ДозаРядомСВыходомTests {

    private static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь),
                          encoding: .utf8)
    }

    /// Код без комментариев: и `//`, и `///` режутся одинаково.
    private static func кодБезПрозы(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    private static let шторка = "Togo/Features/Needs/NeedsSheet.swift"

    @Test("Исходник шторки разобран")
    func былоЧтоСторожить() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.шторка))
        #expect(код.count > 500, """
            разбор `\(Self.шторка)` дал \(код.count) знаков — файл \
            не прочитан или вырезание съело код целиком.
            """)
        #expect(код.contains("TGSheet"), """
            в коде шторки нет даже `TGSheet` — разбор не состоялся, \
            и проверка ниже прошла бы на пустоте.
            """)
    }

    @Test("Шторка «Просится» зовёт WalkDose, а не только упоминает его")
    func шторкаЗовётМодуль() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.шторка))

        #expect(код.contains("WalkDose.рядом("), """
            `WalkDose.рядом(` не вызывается из шторки «Просится». \
            Модуль написан и покрыт тестами, но человек окна дозы \
            не увидит: механизм без места вызова снаружи неотличим \
            от работающего.
            """)
    }

    /// Два ответа раздельно — требование головы модуля, и оно
    /// проверяется здесь, потому что свести их обратно в один признак
    /// можно одной правкой вёрстки.
    @Test("«Можно дать на улице» показывается отдельно от времени дозы")
    func дваОтветаРаздельно() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.шторка))

        #expect(код.contains("даётсяНаУлице"), """
            шторка не читает `даётсяНаУлице` — значит либо «дай \
            на улице» не показывается вовсе, либо оно слито со временем \
            дозы в одно сообщение. Второе хуже: человеку с каплями \
            в глаз нельзя предлагать дать их на улице.
            """)
    }

    /// Обратная половина: доказать, что разбор режет прозу.
    @Test("Проза не считается кодом")
    func прозаНеСчитаетсяКодом() throws {
        let текст = try Self.исходник(Self.шторка)

        // Контроль: имя ЕСТЬ в комментариях. Если его там не станет,
        // проверка ниже начнёт проходить на пустом месте и скажет
        // об этом.
        let строкиПрозы = текст.components(separatedBy: .newlines)
            .filter { $0.trimmingCharacters(in: .whitespaces).hasPrefix("//") }
            .joined(separator: "\n")
        #expect(строкиПрозы.contains("WalkDose"), """
            в комментариях шторки больше нет имени `WalkDose` — контроль \
            пропал, и проверка ниже ничего не доказывает.
            """)

        let безПрозы = Self.кодБезПрозы(строкиПрозы)
            .trimmingCharacters(in: .whitespacesAndNewlines)
        #expect(!безПрозы.contains("WalkDose"), """
            вырезание комментариев не работает: имя выжило в прозе. \
            Значит сторож выше мерит комментарий, а не код, и останется \
            зелёным на удалённом вызове.
            """)
    }
}
