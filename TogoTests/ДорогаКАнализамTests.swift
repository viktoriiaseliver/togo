import Foundation
import Testing

/// К анализам есть дорога с «Здоровья», и создаются они не только
/// в отладочной галерее.
///
/// **Повод — замер 08.10.2026, и это не гипотеза.** У медицинского слоя
/// были четыре модели, обмен, архив, карточки и дорога посмотреть
/// («Сводка врачу»), а **ввода руками не было вовсе**: единственное место,
/// где создавался `LabResult`, — `MedicalRecordGallery`, и она целиком
/// под `#if DEBUG`.
///
/// > **Модель без места ввода — это не «почти готово», это ноль.**
/// > Набор при этом был зелёным: тесты создавали записи сами и проверяли,
/// > что модель считает верно. Пока вызов есть в тесте — зелено; когда
/// > его нет в приложении — зелено тоже.
///
/// Поэтому сторож стоит на **ВЫЗОВЕ**, а не на модели, и написан
/// **от запрета**: «нет ни одной дороги» спрашивается надёжно, а «есть
/// ли нужная» — нет, у дороги десяток форм.
@Suite("Дорога к анализам")
struct ДорогаКАнализамTests {

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()

    private static func текст(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Строки кода без комментариев: сканирующий сторож, не различающий
    /// код и прозу, меряет прозу. В `HealthScreen` ровно над нужной
    /// строкой лежит комментарий, называющий `LabResultsScreen`
    /// поимённо, — без вырезания сторож прошёл бы на объяснении.
    private static func строкиКода(_ текст: String) -> [String] {
        текст.split(separator: "\n", omittingEmptySubsequences: false)
            .map(String.init)
            .filter { строка in
                let о = строка.trimmingCharacters(in: .whitespaces)
                return !о.hasPrefix("//") && !о.hasPrefix("///")
                    && !о.hasPrefix("*") && !о.hasPrefix("/*")
            }
    }

    // MARK: Было что сторожить

    @Test("Экран анализов и экран «Здоровье» на месте")
    func былоЧтоСторожить() throws {
        let здоровье = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))
        let анализы = try Self.строкиКода(Self.текст("Togo/Features/Health/LabResultScreens.swift"))
        #expect(здоровье.count > 200, "HealthScreen подозрительно короток — проверь путь, а не вывод")
        #expect(анализы.contains { $0.contains("struct LabResultsScreen") },
                "экрана анализов нет — сторожить нечего, и это находка, а не повод чинить сторожа")
        #expect(анализы.contains { $0.contains("struct LabResultEntryFlow") },
                "ввода анализа нет; дорога без формы — это дорога в пустоту")
    }

    // MARK: Дорога

    @Test("С «Здоровья» есть дорога к анализам")
    func дорогаЕсть() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))
        let ведут = строки.filter { $0.contains("LabResultsScreen") }
        #expect(!ведут.isEmpty, """
            на «Здоровье» нет ни одной дороги к анализам.
            Экран существует и недостижим — это ровно то состояние,
            в котором медслой пролежал до 08.10.2026: модель, обмен,
            архив и карточки были, а завести запись человек не мог.
            Снявший ссылку — верни её, а не правь сторожа.
            """)
    }

    /// Дорога обязана вести на ЖИВОЙ экран, а не на отладочный.
    @Test("Дорога не ведёт в отладочную галерею")
    func дорогаНеВГалерею() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))
        let вГалерею = строки.filter { $0.contains("MedicalRecordGallery") }
        #expect(вГалерею.isEmpty, """
            «Здоровье» ведёт в MedicalRecordGallery: \(вГалерею).
            Галерея целиком под `#if DEBUG` и строит шесть трудных
            случаев — это стенд, а не форма ввода. В сборке для человека
            такая дорога исчезает молча.
            """)
    }

    // MARK: Создание — не только под #if DEBUG

    /// **Главная проверка набора.** Создание записи обязано существовать
    /// вне отладочной сборки: именно этого не было, и именно это
    /// не ловилось ничем.
    @Test("LabResult создаётся не только в отладочной сборке")
    func созданиеВнеОтладки() throws {
        let живые = ["Togo/Features/Health/LabResultScreens.swift"]
        var нашли: [String] = []
        for путь in живые {
            let строки = try Self.строкиКода(Self.текст(путь))
            if строки.contains(where: { $0.contains("LabResult(") }) { нашли.append(путь) }
        }
        #expect(!нашли.isEmpty, """
            `LabResult(` не создаётся ни в одном живом экране.
            Если создание осталось только в `MedicalRecordGallery`
            (`#if DEBUG`), человек не может завести анализ, а набор
            при этом зелёный: тесты создают записи сами.
            """)

        // И условие, при котором эта проверка перестанет быть верной:
        // галерея не должна оказаться единственным местом снова.
        let галерея = try Self.текст("Togo/DesignSystem/MedicalRecordGallery.swift")
        #expect(галерея.contains("#if DEBUG"), """
            `MedicalRecordGallery` больше не под `#if DEBUG` — тогда
            отладочный стенд уезжает людям, и это отдельная находка.
            """)
    }

    // MARK: Остальные медицинские сущности

    /// **Один сторож на все четыре, а не четыре сторожа.**
    ///
    /// Класс был общий: `LabResult`, `VetVisit`, `Diagnosis`
    /// и `Prescription` все четыре создавались только в отладочной
    /// галерее. Чинится он тоже общим — поэтому проверка перебирает
    /// пары «сущность → экран», а не повторяется четырежды.
    ///
    /// **Все четыре закрыты 08.10.2026**, и флаг `естьФорма` у каждой
    /// стоит `true`. Поле оставлено не для красоты: пятая сущность
    /// медслоя добавится со `false`, и тогда долг напечатается строкой
    /// «ДОЛГ МЕДСЛОЯ» сам, а не будет жить в переписке.
    ///
    /// Несколько часов назад здесь стояло «`Prescription` с ожиданием
    /// КРАСНОГО: формы у него ещё нет». Правка флага без правки этого
    /// абзаца оставила бы **комментарий, описывающий отменённое
    /// состояние** — ровно то, из-за чего у нас имя теста пять дней
    /// рассказывало обратную историю при верном теле.
    @Test("У каждой медицинской сущности есть дорога с «Здоровья»")
    func дорогиУВсехСущностей() throws {
        let здоровье = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))

        let ожидаем: [(сущность: String, экран: String, естьФорма: Bool)] = [
            ("LabResult", "LabResultsScreen", true),
            ("VetVisit", "VetVisitsScreen", true),
            ("Diagnosis", "DiagnosesScreen", true),
            // Назначения доделаны 08.10.2026 тем же ходом: форма,
            // список, дорога. Флаг переведён в `true` — то есть долг
            // не «забыли убрать», а закрыт, и проверка теперь требует
            // дорогу, а не печатает про её отсутствие.
            ("Prescription", "PrescriptionsScreen", true),
        ]

        // График — не сущность, а поверхность над ними, и дорога к нему
        // нужна по той же причине: экран существует и недостижим,
        // если ссылки нет. Проверяется отдельной строкой, чтобы
        // в перечне сущностей не появился пятый, которого там нет.
        #expect(здоровье.contains { $0.contains("LabChartScreen") }, """
            на «Здоровье» нет дороги к графику показателя.
            График — то, ради чего медслой затевался («почему Т4
            не растёт при росте дозы»), и без ссылки его не видит никто.
            """)

        var безДороги: [String] = []
        for пункт in ожидаем where пункт.естьФорма {
            if !здоровье.contains(where: { $0.contains(пункт.экран) }) {
                безДороги.append("\(пункт.сущность) → \(пункт.экран)")
            }
        }
        #expect(безДороги.isEmpty, """
            сущности без дороги с «Здоровья»: \(безДороги).
            Экран есть, дойти нельзя — ровно то состояние, в котором
            медслой пролежал до 08.10.2026.
            """)

        // Долг печатается, а не молчит: так его видно в выводе прогона
        // даже когда всё зелёное.
        let долг = ожидаем.filter { !$0.естьФорма }.map(\.сущность)
        print("ДОЛГ МЕДСЛОЯ · ввода руками ещё нет: \(долг.joined(separator: ", "))")
    }

    @Test("Назначение создаётся не только в отладочной сборке")
    func созданиеНазначенийВнеОтладки() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/PrescriptionScreens.swift"))
        #expect(строки.contains { $0.contains("Prescription(") }, """
            `Prescription(` не создаётся в живом экране. А `ReminderScheduler`
            уже читает рецепты и считает окна контроля по `ControlWindow` —
            то есть напоминания написаны и никогда ни о чём не напомнят:
            механизм без входа не работает вовсе.
            """)
    }

    @Test("Визиты и диагнозы создаются не только в отладочной сборке")
    func созданиеВизитовИДиагнозовВнеОтладки() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/VisitDiagnosisScreens.swift"))
        #expect(строки.contains { $0.contains("VetVisit(") }, """
            `VetVisit(` не создаётся в живом экране — значит визит
            по-прежнему заводится только в галерее под `#if DEBUG`.
            """)
        #expect(строки.contains { $0.contains("Diagnosis(") }, """
            `Diagnosis(` не создаётся в живом экране.
            """)
    }

    // MARK: Граница

    @Test("Границы сторожа дороги к анализам: чего он не умеет")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит: в исходнике «Здоровья» есть упоминание
            `LabResultsScreen`, в экране анализов есть `LabResult(`,
            и дорога не ведёт в отладочную галерею. И только это.

            НЕ проверяется:
            · что человек ДОЙДЁТ. Сторож видит, что имя упомянуто,
              и не видит, что от упоминания ничего не происходит:
              `TGLink` может оказаться за `if`, который всегда ложен,
              или под недостижимой ролью. Это ловится кадром, а здесь
              невидимо по устройству;
            · что форма СОХРАНЯЕТ. Три шага могут собрать черновик
              и не дойти до `context.insert` — проверка на это
              поведенческая, и её здесь нет;
            · порядок разделов на экране и то, попадает ли строка
              в видимую часть без прокрутки;
            · остальные три медицинские модели. `VetVisit`, `Diagnosis`
              и `Prescription` ввода руками ПО-ПРЕЖНЕМУ не имеют —
              замер 08.10.2026, и это названный долг, а не пропуск
              этого сторожа.
            """
        #expect(границы.isEmpty == false)
        // Проверяется за минуту:
        //   grep -n "LabResultsScreen" Togo/Features/Health/HealthScreen.swift
        //   grep -rn "LabResult(" Togo/Features/
    }
}
