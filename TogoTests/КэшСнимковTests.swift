import Testing
import Foundation
import UIKit
@testable import Togo

/// Кэш снимков обязан перестать вытираться на седьмой картинке.
///
/// # Чем это мерится и почему не пределом
///
/// Приёмка смотрит на `КэшСнимков.декодирований` — число РАСКЛАДОК
/// байтов в пиксели, то есть на выход помощника. Сторож на объявленную
/// константу («предел равен восемнадцати») удовлетворяется, не
/// раскодировав ни одного снимка: это прокси, и в этом же проекте
/// он уже один раз был зелёным на сломанном коде —
/// `StructuralGapsTests` проверял `DocumentPhoto.maxSide == 1600`,
/// пока помощник выдавал 4800 px (разбор у `DocumentPhoto.shrink`).
///
/// # Почему без сброса кэша
///
/// Сбрасывать нечего и не надо: каждый тест заводит СВОИ байты,
/// которых на полке заведомо не было, и смотрит на ПРИРОСТ счётчика,
/// а не на его значение. Метод сброса был бы продуктовым API,
/// существующим только ради теста.
@Suite("Кэш снимков: вытесняется один, а не полка")
@MainActor
struct КэшСнимковTests {

    /// Уникальный JPEG. Цвет свой у каждого — значит и байты свои.
    private func байты(_ номер: Int, сторона: CGFloat = 40) throws -> Data {
        let размер = CGSize(width: сторона, height: сторона * 0.75)
        let формат = UIGraphicsImageRendererFormat.default()
        формат.scale = 1
        формат.opaque = true
        let картинка = UIGraphicsImageRenderer(size: размер, format: формат).image { ctx in
            UIColor(red: CGFloat(номер % 97) / 97.0,
                    green: CGFloat((номер * 7) % 89) / 89.0,
                    blue: 0.42, alpha: 1).setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
        }
        return try #require(картинка.jpegData(compressionQuality: 1))
    }

    @Test("Девятнадцатая миниатюра выгоняет первую, а не все восемнадцать")
    func миниатюрыВытесняютсяПоОдной() throws {
        let сколько = КэшСнимков.пределМиниатюр + 1
        let снимки = try (0..<сколько).map { try байты($0) }

        // КОНТРОЛЬ ПЕРВЫМ: фикстуре было что проверять. Одинаковые байты
        // легли бы на полку одним ключом, и «ни одного вытеснения»
        // оказалось бы правдой о фикстуре, а не о кэше.
        #expect(Set(снимки).count == сколько,
                "фикстура дала \(Set(снимки).count) разных блобов из \(сколько) — проверять было нечего")

        let доПрогрева = КэшСнимков.декодирований
        for данные in снимки { _ = КэшСнимков.миниатюра(данные) }
        let заПрогрев = КэшСнимков.декодирований - доПрогрева
        #expect(заПрогрев == сколько,
                "прогрев \(сколько) разных снимков дал \(заПрогрев) раскладок")

        // Предмет: свежие восемнадцать лежат на полке. На старом коде
        // (`removeAll` при переполнении) полка после девятнадцатого
        // снимка содержала РОВНО ОДИН снимок, и этот блок давал 18.
        let доПовтора = КэшСнимков.декодирований
        for данные in снимки.dropFirst() { _ = КэшСнимков.миниатюра(данные) }
        let заПовтор = КэшСнимков.декодирований - доПовтора
        #expect(заПовтор == 0,
                "повторный проход по \(сколько - 1) свежим снимкам стоил \(заПовтор) раскладок — полку вытерло")

        // И вытеснили ИМЕННО самый давний: он один обязан раскладываться
        // заново. Без этой половины «ноль раскладок» прошёл бы и у кэша,
        // который не вытесняет вовсе.
        let доПервого = КэшСнимков.декодирований
        _ = КэшСнимков.миниатюра(снимки[0])
        #expect(КэшСнимков.декодирований - доПервого == 1,
                "самый давний снимок обязан быть вытесненным — он остался на полке")
    }

    @Test("Полноразмерная полка тоже вытесняет по одному")
    func полныеВытесняютсяПоОдному() throws {
        let сколько = КэшСнимков.пределПолных + 1
        // Смещение номеров, чтобы байты не совпали с прошлым тестом:
        // полки разные, а порядок выполнения тестов — нет.
        let снимки = try (1_000..<(1_000 + сколько)).map { try байты($0) }
        #expect(Set(снимки).count == сколько, "фикстура дала одинаковые блобы")

        let доПрогрева = КэшСнимков.декодирований
        for данные in снимки { _ = КэшСнимков.картинка(данные) }
        #expect(КэшСнимков.декодирований - доПрогрева == сколько)

        let доПовтора = КэшСнимков.декодирований
        for данные in снимки.dropFirst() { _ = КэшСнимков.картинка(данные) }
        #expect(КэшСнимков.декодирований - доПовтора == 0,
                "на старом коде здесь было \(КэшСнимков.пределПолных) раскладок")
    }

    @Test("Миниатюра и полная раскладка — разные полки, а не один ключ")
    func полкиНеПутаются() throws {
        let данные = try байты(2_000)
        _ = КэшСнимков.миниатюра(данные)
        // Полная после миниатюры обязана РАСКЛАДЫВАТЬСЯ: иначе плитка
        // подсунула бы просмотру документа свою уменьшенную копию.
        let до = КэшСнимков.декодирований
        _ = КэшСнимков.картинка(данные)
        #expect(КэшСнимков.декодирований - до == 1,
                "полная раскладка пришла с полки миниатюр")
    }

    @Test("Миниатюра ужимается, а мелкий снимок не растягивается")
    func размерМиниатюры() throws {
        let крупный = try байты(3_000, сторона: 1_600)
        let миниатюра = try #require(КэшСнимков.миниатюра(крупный))
        let длинная = max(миниатюра.size.width * миниатюра.scale,
                          миниатюра.size.height * миниатюра.scale)
        #expect(длинная <= КэшСнимков.сторонаПлитки + 1,
                "длинная сторона миниатюры \(длинная) при запросе \(КэшСнимков.сторонаПлитки)")

        // Контроль в другую сторону: мелкий снимок обязан остаться
        // мелким. Правило «только вниз» без этой проверки прошло бы
        // и у помощника, который всегда отдаёт 800.
        let мелкий = try байты(3_001, сторона: 40)
        let какБыл = try #require(КэшСнимков.миниатюра(мелкий))
        #expect(какБыл.size.width * какБыл.scale <= 41,
                "мелкий снимок растянут до \(какБыл.size.width * какБыл.scale) px")
    }
}
