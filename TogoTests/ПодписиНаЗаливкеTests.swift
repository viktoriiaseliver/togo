            ось из перечисления есть только у поверхности прогулки.
            """)
    }

    // MARK: Поверхность 3 · плашки TGBanner, ось из allCases

    /// Подпись плашки читается на своей заливке во всех четырёх темах —
    /// **и ось берётся из `TGTone.allCases`**, а не списком руками.
    ///
    /// # Повод: одна пара из четырёх не имела сторожа вовсе
    ///
    /// Замер 26.10.2026. `TGBanner` в тихом режиме (48 плашек из 49)
    /// красит обе стороны через `TGTone.foreground`/`.background`
    /// (`TGSurfaces.swift:74-97`). Покрытие было такое:
    ///
    /// ```
    /// .done   → doneText/doneBg      ПОКРЫТА ThemeContrastTests:72
    /// .alarm  → overdueText/overdueBg ПОКРЫТА ThemeContrastTests:98-99
    /// .waiting→ waitingText/waitingBg НЕ ПОКРЫТА НИ ОДНИМ СТОРОЖЕМ
    /// .neutral→ Ink.primary/Surface.sunken  то же
    /// ```
    ///
    /// `ThemeContrastTests:73` мерит `waitingText` на `Surface.card` —
    /// **другую заливку**, не свою. То есть сторож на эту роль был,
    /// и спрашивал он не ту пару.
    ///
    /// `TGBanner(tone: .waiting, …)` зовётся минимум в двенадцати
    /// местах: `DayOutScreens`, `FamilyScreen` (дважды), `ПлашкаПрава`,
    /// `FeedingScreen` (трижды), `DoseGateSheet`, `HealthScreen`,
    /// `WalkMode`, `DataPrivacyScreen`, `UsageLogScreen`,
    /// `TrainingScreens`.
    ///
    /// # Почему это заводится ДО того, как сломалось
    ///
    /// Счётный замер 26.10.2026 говорит, что пара сейчас проходит:
    /// dark 7,73 · light 4,57 · darkHC 7,73 · lightHC 6,71 при пороге
    /// 4,5. **Но в светлой запас 0,07**, и это ровно тот класс, что дал
    /// на панели показания 1,35 при доложенных 8,59: половину пары
    /// перевели на палитру дизайнера, вторая осталась на нашей, и
    /// грепом пара не ищется — каждая сторона по отдельности верна.
    ///
    /// > **Сторож на отношение ставится, пока пара здорова.** Поставить
    /// > его после поломки значит узнать о поломке не от него.
    ///
    /// И отдельно названное: у `amber`/`amberBg` **нет HC-ступени**,
    /// поэтому `darkHC` в точности равен `dark`. Это не поломка —
    /// но и не «повышенный контраст сработал»: человек, включивший
    /// «Повысить контраст», получает здесь то же самое. Числа печатаются
    /// рядом, чтобы разницу было видно без отдельного замера.
    @Test("Плашки TGBanner: подпись читается на своей заливке в каждой теме")
    func плашкиВоВсехТемах() throws {
        var провалы: [String] = []
        var замеры: [String] = []
        var осмотрено = 0

        for тон in TGTone.allCases {
            for тема in ThemeContrastTests.режимы {
                осмотрено += 1
                let k = ThemeContrastTests.контраст(тон.foreground,
                                                   на: тон.background,
                                                   режим: тема)
                let ключ = "\(тон.rawValue) · \(тема.имя)"
                let исход = k < Self.порог ? "НЕ ХВАТАЕТ" : "проходит"
                замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) \(исход.padding(toLength: 11, withPad: " ", startingAt: 0)) \(ключ)")
                if k < Self.порог {
                    провалы.append("  \(ключ): \(Self.два(k)) при пороге \(Self.два(Self.порог)) — НЕ ХВАТАЕТ")
                }
            }
        }

        // Проверка, что было что проверять, и она первая: ось из
        // перечисления может опустеть при рефакторинге молча.
        #expect(осмотрено == TGTone.allCases.count * ThemeContrastTests.режимы.count)
        #expect(осмотрено >= 16, "тонов стало меньше четырёх — ось обеднела, а не поверхность")

        #expect(провалы.isEmpty, """
            подписи плашек ниже порога в \(провалы.count) клетках:

            \(провалы.joined(separator: "\n"))
            """)

        print("""
            ЗАМЕР, плашки TGBanner × четыре темы (ось из TGTone.allCases):

            \(замеры.joined(separator: "\n"))

            ГРАНИЦА: это замер ЗНАЧЕНИЙ, разрешённых системой, а не
            пикселя. `TGBanner` в тихом режиме кладёт заливку без
            прозрачности, но `opacity` на месте вызова этот сторож
            не видит — у нас записано, что прозрачность съедает запас
            (`#666` под 0,85 это уже 4,12). Перекрытие стилем тоже
            не видно: `AppFont` несёт свой `color` и побеждает
            `foregroundStyle` предка. Приёмка того и другого — кадр.
            """)
    }

    // MARK: Поверхность 4 · тихая заливка, пара названа в самом токене

    /// `Action.onSubtle` на `Action.subtle` — пара, у которой **имя
    /// второй половины записано в описании первой**.
    ///
    /// # Повод: половина пары, прожившая незамеченной
    ///
    /// Замер 26.10.2026. Бейдж «это я» (`FamilyScreen.swift:920`)
    /// красил подпись `Token.Ink.primary` на заливке
    /// `Token.Action.subtle`, а парный токен `Action.onSubtle` имел
    /// **ноль читателей** во всём дереве.
    ///
    /// ```
    ///                        dark    darkHC   light   lightHC
    /// Ink.primary            11,03    8,23     1,71 ✗  1,71 ✗
    ///   на Action.subtle
    /// ```
    ///
    /// > **На устройстве это было безопасно ПО СОВПАДЕНИЮ:**
    /// > `Ink.primary` в тёмной равен `#FFFFFF`, то есть тому же
    /// > значению, что правильный `onSubtle`. Пара разошлась бы молча
    /// > в день, когда `Ink.primary` получит оттенок, — грепом её
    /// > не найти, обе стороны по отдельности верны.
    ///
    /// Это формула, уже оплаченная 25.10 на панели показания: 1,35
    /// при доложенных 8,59.
    ///
    /// # Почему сторож проверяет ДВЕ вещи, а не одну
    ///
    /// Контраст пары — половина ответа. Вторая половина: **у `onSubtle`
    /// должен быть живой читатель.** Токен без читателя находится
    /// грепом один раз, в объявлении, и выглядит работающим — за это
    /// уже платили `Token.FontSize.micro = 14` при живом
    /// `AppFont.micro = 15`. Поэтому ниже стоит проверка по исходнику,
    /// а не только по числу.
    @Test("Подпись на тихой заливке берётся из своей пары, и у пары есть читатель")
    func тихаяЗаливкаПарная() throws {
        var провалы: [String] = []
        var замеры: [String] = []

        for тема in ThemeContrastTests.режимы {
            let k = ThemeContrastTests.контраст(Token.Action.onSubtle,
                                               на: Token.Action.subtle,
                                               режим: тема)
            let исход = k < Self.порог ? "НЕ ХВАТАЕТ" : "проходит"
            замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) \(исход.padding(toLength: 11, withPad: " ", startingAt: 0)) onSubtle · \(тема.имя)")
            if k < Self.порог {
                провалы.append("  onSubtle · \(тема.имя): \(Self.два(k)) при пороге \(Self.два(Self.порог)) — НЕ ХВАТАЕТ")
            }
        }

        #expect(провалы.isEmpty, """
            подпись на тихой заливке ниже порога в \(провалы.count) клетках:

            \(провалы.joined(separator: "\n"))
            """)

        // ВТОРАЯ ПОЛОВИНА: у токена есть живой читатель в экранах.
        // Ось — исходник, а не значение: значение верно и у мёртвого.
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let экраны = корень.appendingPathComponent("Togo/Features")
        var читателей = 0
        var контроль = 0
        if let обход = FileManager.default.enumerator(at: экраны, includingPropertiesForKeys: nil) {
            for case let файл as URL in обход where файл.pathExtension == "swift" {
                guard let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
                // Прозу вырезаем: сторож, не различающий код и комментарий,
                // меряет прозу — и запрещает писать про ошибку в файле,
                // где её не совершают.
                let код = текст.split(separator: "\n", omittingEmptySubsequences: false)
                    .filter { !$0.trimmingCharacters(in: .whitespaces).hasPrefix("//") }
                    .joined(separator: "\n")
                читателей += код.components(separatedBy: "Token.Action.onSubtle").count - 1
                контроль += код.components(separatedBy: "Token.Action.subtle").count - 1
            }
        }

        // Контроль в том же проходе и подверженный тому же отказу:
        // если обход каталога сломается, обнулятся ОБА — а это
        // невозможно при живой заливке, и несовместимость видна
        // без знания причины.
        #expect(контроль > 0, "обход экранов дал ноль и на заливке — сломан сам обход, а не предмет")
        #expect(читателей > 0, """
            у `Token.Action.onSubtle` ноль читателей в `Togo/Features`,
            при \(контроль) вхождениях парной заливки `Action.subtle`.

            Значит заливку кто-то кладёт, а подпись берёт не из этой
            пары — ровно то, что было у бейджа «это я» до 26.10.2026.
            """)

        print("""
            ЗАМЕР, тихая заливка:

            \(замеры.joined(separator: "\n"))

              читателей `Action.onSubtle` в Togo/Features: \(читателей)
              вхождений парной `Action.subtle` (контроль):  \(контроль)
            """)
    }

    // MARK: Запрет

    /// В режиме прогулки подпись не красится нейтральным напрямую.
    ///
    /// Числовой сторож выше меряет то, что `MarkFill` отдаёт сегодня,
    /// и останется зелёным, если завтра кто-то поставит в подпись
    /// четвёртый `Text` с `Token.Ink.primary` мимо развилки. Этот
    /// запрет закрывает ту дорогу.
    ///
    /// Разрешено ровно внутри самой `MarkFill` — она живёт
    /// в дизайн-системе, и там нейтральные чернила есть ответ для
    /// тёмных плиток. Поэтому проверяется **тело одной функции**,
    /// а не весь файл: запрет на файл покраснел бы на здоровом коде,
    /// а красный без дефекта учит не верить красному.
    ///
    /// # ОСЬ ПЕРЕВЕДЕНА 23.10.2026: предмет ПЕРЕИМЕНОВАН, а не удалён
    ///
    /// До сегодня здесь стояло имя `markLabel`, и сторож краснел
    /// `Issue.record`'ом «не найден — смотрю в пустоту». Редизайн «На
    /// улице» (`f9419cb`, 22.10 18:08) разобрал `markLabel` на две
    /// функции, и широкая кнопка отметки стала `широкая(_:на:высота:)`.
    /// Предмет жив и цел: `заливка.label` она зовёт дважды, нейтральных
    /// чернил в её теле нет. Ось переведена на живое имя — это не
    /// снятие сторожа и не подгонка.
    ///
    /// **Граница: соседняя `плитки(_:)` сюда НЕ входит, и нарочно.**
    /// Там подпись берёт `Token.Ink.primary` напрямую, и это верно:
    /// плитка — `TGTile` на `Surface.sunken`, заливка у неё одна
    /// на все виды, развилки по заливке нет. Запрет держит ту кнопку,
    /// у которой заливок три и одна из них светлая.
    @Test("Подпись широкой кнопки отметки не красится нейтральным напрямую")
    func вПодписиНетНейтральныхНапрямую() throws {
        let путь = "Togo/Features/Needs/WalkMode.swift"
        let имяФункции = "private func широкая("
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let текст = try String(contentsOf: корень.appendingPathComponent(путь),
                               encoding: .utf8)
        let код = текст.components(separatedBy: "\n")
            .map { $0.components(separatedBy: "//")[0] }

        // Тело функции — от объявления до закрывающей скобки того же
        // отступа. Имя целиком, не префиксом: `hasPrefix` у нас
        // находил `SwatchRow` вместо `Swatch` и сверял другой компонент.
        guard let начало = код.firstIndex(where: { $0.contains(имяФункции) })
        else {
            Issue.record("""
                `\(имяФункции)` не найден в \(путь) — сторож смотрит в пустоту. \
                Функцию переименовали или перенесли: переведи ось на живое \
                имя, а не снимай запрет.
                """)
            return
        }
        let хвост = код[(начало + 1)...]
        let конец = хвост.firstIndex(where: { $0 == "    }" }) ?? хвост.endIndex
        let тело = Array(код[начало..<конец])

        #expect(тело.count > 5, "тело подписи вырезано пустым: \(тело.count) строк")
        #expect(тело.contains { $0.contains("заливка.label") }, """
            широкая кнопка отметки перестала звать `заливка.label`. Значит цвет
            снова собирается на месте, а не берётся у развилки, —
            так подпись и оказалась 1,47:1 на светлой заливке.
            """)

        let нарушения = тело.enumerated()
            .filter { $0.element.contains("Token.Ink.") }
            .map { "  \(путь):\(начало + $0.offset + 1): \($0.element.trimmingCharacters(in: .whitespaces))" }

        #expect(нарушения.isEmpty, """
            в теле широкой кнопки отметки \(нарушения.count) нейтральных чернил напрямую:

            \(нарушения.joined(separator: "\n"))

            Цвет берётся у `Заливка.подпись` / `.счётчик` — там и живёт
            ответ для тёмных плиток. Нейтральный цвет прямо в подписи
            значит, что он один на все три заливки, а они разные.
            """)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }
