import Testing
import Foundation
import SwiftUI
@testable import Togo

/// Ни одна подпись кнопки не стоит на своей заливке ниже порога —
/// ни на одной поверхности, ни в одной из четырёх тем.
///
/// **Это расширение `ButtonLabelOnFillTests` ВОПРОСОМ, а не парой,
/// и повод у него измерен.** Тот сторож верен, зелён и слеп:
///
/// ```
/// что он мерит   Token.Component.Button.{Primary,Secondary,Destructive}
///                плюс тело BigAction в ОДНОМ файле (ActionGrid.swift)
/// в одной теме   UIColor(цвет).cgColor без разрешения по трейтам
/// чего не видит  любую другую поверхность с заливкой
/// ```
///
/// Соседней поверхностью оказался **режим прогулки**. `markLabel`
/// красил подпись одним `Token.Ink.primary` на три разные плитки,
/// и на той, у которой заливка светлая, подпись не читалась:
///
/// ```
///                                dark    light   darkHC  lightHC
/// «Пописал» · ink                1,64 ✗  1,47 ✗  1,64 ✗  1,47 ✗
/// счётчик «2 раза» · inkMuted    1,17 ✗  1,94 ✗  1,08 ✗  1,40 ✗
/// «Стул» · ink на night3        14,97   14,98   14,97   14,98
/// «Реакция» · ink на amberBg    11,10   16,10   11,10   16,10
/// ```
///
/// Сломана ровно одна плитка из трёх. И это **третья поверхность
/// одного правила**: первую починили у `BigAction`, сторож заводили
/// под неё же, а подпись на светлой заливке в прогулке осталась —
/// у Togo это записано классом «починка на одной поверхности из трёх».
///
/// Цена именно здесь выше, чем у шапки: **эту кнопку жмут на улице,
/// одной рукой, на солнце.** Шапка — то, что не прочитали; эта
/// кнопка — то, что не нажали, а продукт стоит на «два тапа».
///
/// **Ось берётся из перечисления, а не из списка.** `WalkModeScreen.Заливка`
/// объявлена `CaseIterable` ради этого: четвёртая заливка, добавленная
/// завтра, попадёт под порог сама. Список руками знает только то, что
/// в него положили.
///
/// **Граница.** Это замер значений, разрешённых системой, а не пикселя.
/// `opacity` он не видит — и на этом же экране `opacity(0.4)` висит
/// на паузе прогулки (`WalkMode.swift`, `.disabled`): выключенный
/// орган управления WCAG из порога выводит, поэтому в счёт он здесь
/// не входит, но знать об этом надо. Перекрытие стилем тоже не видно:
/// приёмка — кадр, и снимает его не автор.
@MainActor
@Suite("Подписи кнопок читаются на своих заливках")
struct ПодписиНаЗаливкеTests {

    /// Порог текста по WCAG 1.4.3. Крупного текста здесь нет: подпись
    /// плитки — 17pt и меньше.
    static let порог = 4.5

    // MARK: Поверхность 1 · режим прогулки, ось из allCases

    @Test("Режим прогулки: подпись и счётчик читаются на каждой заливке")
    func прогулкаВоВсехТемах() throws {
        var провалы: [String] = []
        var замеры: [String] = []
        var осмотрено = 0

        for заливка in WalkModeScreen.Заливка.allCases {
            for роль in [("подпись", заливка.подпись), ("счётчик", заливка.счётчик)] {
                for тема in ThemeContrastTests.режимы {
                    осмотрено += 1
                    let k = ThemeContrastTests.контраст(роль.1, на: заливка.цвет, режим: тема)
                    let ключ = "\(роль.0) · \(заливка.имя) · \(тема.имя)"
                    замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) \(ключ)")
                    if k < Self.порог {
                        провалы.append("  \(ключ): \(Self.два(k)) при пороге \(Self.два(Self.порог))")
                    }
                }
            }
        }

        let ожидалось = WalkModeScreen.Заливка.allCases.count * 2 * ThemeContrastTests.режимы.count
        #expect(осмотрено == ожидалось, """
            осмотрено \(осмотрено) из \(ожидалось). Заливок
            \(WalkModeScreen.Заливка.allCases.count), ролей 2, тем
            \(ThemeContrastTests.режимы.count). Набору, которому нечего
            проверять, молчать так же легко, как набору, у которого
            всё хорошо.
            """)

        #expect(провалы.isEmpty, """
            на заливках режима прогулки \(провалы.count) клеток ниже порога:

            \(провалы.joined(separator: "\n"))

            Цвет подписи и цвет заливки выбирает ОДИН тип —
            `WalkModeScreen.Заливка`. Если здесь красно, значит пара
            в нём разошлась; правь её, а не место вызова, и не порог:
            число, поднятое под дефект, становится дырой ровно того
            размера.
            """)

        print("""
            ЗАМЕР, \(осмотрено) клеток режима прогулки:

            \(замеры.joined(separator: "\n"))
            """)
    }

    // MARK: Поверхность 2 · компонентные кнопки, во всех четырёх темах

    /// Тот же вопрос к `Token.Component.Button.*`.
    ///
    /// `ButtonLabelOnFillTests` эти пары уже проверяет — и **в одной
    /// теме**: его счётчик берёт `UIColor(цвет).cgColor` без
    /// разрешения по трейтам, то есть отвечает про тёмную и молчит
    /// про три остальные. Светлая тема включена `052c562`, и до неё
    /// вопроса не существовало.
    ///
    /// `Disabled` сюда не входит: выключенный орган управления WCAG
    /// из порога выводит (1.4.3), и требовать от него 4,5 значило бы
    /// завести ложное срабатывание — а после ложных сторожа перестают
    /// читать.
    @Test("Компонентные кнопки читаются во всех четырёх темах")
    func кнопкиВоВсехТемах() throws {
        let пары: [(String, Color, Color)] = [
            ("primary", Token.Component.Button.Primary.label,
             Token.Component.Button.Primary.background),
            ("secondary", Token.Component.Button.Secondary.label,
             Token.Component.Button.Secondary.background),
            ("destructive", Token.Component.Button.Destructive.label,
             Token.Component.Button.Destructive.background),
            ("finish", Token.Component.Button.Finish.label,
             Token.Component.Button.Finish.background),
        ]

        var провалы: [String] = []
        var замеры: [String] = []
        var осмотрено = 0

        for (имя, подпись, заливка) in пары {
            for тема in ThemeContrastTests.режимы {
                осмотрено += 1
                let k = ThemeContrastTests.контраст(подпись, на: заливка, режим: тема)
                let ключ = "\(имя) · \(тема.имя)"
                замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) \(ключ)")
                if k < Self.порог {
                    провалы.append("  \(ключ): \(Self.два(k)) при пороге \(Self.два(Self.порог))")
                }
            }
        }

        #expect(осмотрено == пары.count * ThemeContrastTests.режимы.count)
        #expect(провалы.isEmpty, """
            подписи кнопок ниже порога в \(провалы.count) клетках:

            \(провалы.joined(separator: "\n"))
            """)

        print("""
            ЗАМЕР, компонентные кнопки × четыре темы:

            \(замеры.joined(separator: "\n"))

            ГРАНИЦА: в списке четыре роли из шести — `Disabled` выведен
            из порога по WCAG, `Icon` подписи не несёт. Список составлен
            руками, и потому он знает только то, что в него положили;
            ось из перечисления есть только у поверхности прогулки.
            """)
    }

    // MARK: Запрет

    /// В режиме прогулки подпись не красится нейтральным напрямую.
    ///
    /// Числовой сторож выше меряет то, что `Заливка` отдаёт сегодня,
    /// и останется зелёным, если завтра кто-то поставит в `markLabel`
    /// четвёртый `Text` с `Token.Ink.primary` мимо развилки. Этот
    /// запрет закрывает ту дорогу.
    ///
    /// Разрешено ровно внутри самой `Заливка`: там нейтральные чернила
    /// и есть ответ для тёмных плиток. Поэтому проверяется **тело
    /// `markLabel`**, а не весь файл: запрет на файл покраснел бы
    /// на здоровом коде, а красный без дефекта учит не верить красному.
    @Test("markLabel не красит подпись нейтральным напрямую")
    func вПодписиНетНейтральныхНапрямую() throws {
        let путь = "Togo/Features/Needs/WalkMode.swift"
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let текст = try String(contentsOf: корень.appendingPathComponent(путь),
                               encoding: .utf8)
        let код = текст.components(separatedBy: "\n")
            .map { $0.components(separatedBy: "//")[0] }

        // Тело функции — от объявления до закрывающей скобки того же
        // отступа. Имя целиком, не префиксом: `hasPrefix` у нас
        // находил `SwatchRow` вместо `Swatch` и сверял другой компонент.
        guard let начало = код.firstIndex(where: { $0.contains("private func markLabel(") })
        else {
            Issue.record("`markLabel` не найден в \(путь) — сторож смотрит в пустоту")
            return
        }
        let хвост = код[(начало + 1)...]
        let конец = хвост.firstIndex(where: { $0 == "    }" }) ?? хвост.endIndex
        let тело = Array(код[начало..<конец])

        #expect(тело.count > 5, "тело markLabel вырезано пустым: \(тело.count) строк")
        #expect(тело.contains { $0.contains("заливка.подпись") }, """
            markLabel перестал звать `заливка.подпись`. Значит цвет
            снова собирается на месте, а не берётся у развилки, —
            так подпись и оказалась 1,47:1 на светлой заливке.
            """)

        let нарушения = тело.enumerated()
            .filter { $0.element.contains("Token.Ink.") }
            .map { "  \(путь):\(начало + $0.offset + 1): \($0.element.trimmingCharacters(in: .whitespaces))" }

        #expect(нарушения.isEmpty, """
            в теле `markLabel` \(нарушения.count) нейтральных чернил напрямую:

            \(нарушения.joined(separator: "\n"))

            Цвет берётся у `Заливка.подпись` / `.счётчик` — там и живёт
            ответ для тёмных плиток. Нейтральный цвет прямо в подписи
            значит, что он один на все три заливки, а они разные.
            """)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }
}
