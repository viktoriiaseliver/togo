import Testing
import Foundation
@testable import Togo

/// Иллюстрация выбирается в одном месте, и ни один экран её не называет.
///
/// **Чего этот набор НЕ доказывает, и это главное.** Он текстовый.
/// Что иллюстрация **нарисуется** и нарисуется тем цветом, которым
/// задумана, он не видит по устройству: два слоя-шаблона красятся
/// токенами на отрисовке, и «значение верное, а вызов бессильный»
/// у нас оплачено кнопкой с контрастом 1,68:1, где токен был верен
/// всегда. **Приёмка показа — кадр, а не этот прогон.**
///
/// Здесь проверяется только то, что проверяемо текстом: что таблица
/// соответствия одна и что к ней есть дорога от каждого пустого
/// состояния.
@Suite("Пустые состояния берут иллюстрацию из одной таблицы")
struct EmptyStateIllustrationTests {

    /// В день написания: 12 мест, где показывается пустое состояние.
    private static let вызововНеМенее = 12

    /// Файл, которому СВОЕЙ рукой называть картинку можно: в нём
    /// и живёт таблица.
    private static let таблица = "TGLoading.swift"

    /// Места, где сцена выбирается по таблице. Список **объявленный**,
    /// а не «одно».
    ///
    /// Прежняя ось звучала «иллюстрацию зовёт только таблица» и держала
    /// правильную вещь не за то место. Правило, ради которого она
    /// заводилась, — «соответствие экран → сцена существует в одном
    /// экземпляре»; привязано оно было к **таблице пустых состояний**.
    /// Онбординг пустым состоянием не является, и законного входа
    /// у его сцены не было вовсе: `TGIllustration.Scene.onboarding`
    /// объявлена, оба слоя лежат в ассетах, читателей ноль. Запрет,
    /// привязанный к инструменту вместо правила, меняет знак в момент
    /// успеха — у нас это оплачено дважды.
    ///
    /// Новая ось — ниже, в `сценаНеНазванаДважды`: таблиц может быть
    /// несколько, но **одна сцена принадлежит ровно одному месту
    /// показа во всём приложении**. Добавляя сюда файл, добавь рядом
    /// и его таблицу в `сценыПоТаблицам`, иначе проверка ослепнет
    /// на новом месте и промолчит.
    ///
    /// **Граница, которую эта ось не видит** (наблюдение
    /// `togo-onboarding-theme-setup`, 14.10): вторая реализация
    /// появляется не только от небрежности, но и от **границы
    /// таргетов**. Все 26 файлов дизайн-системы лежат в
    /// `Togo/DesignSystem/`, а виджет собирается из `TogoWidgets`
    /// + `TogoShared` и компонентов не видит по устройству сборки.
    /// Понадобится сцена виджету — она будет названа по одному разу
    /// в каждом из двух миров, и этот сторож смолчит: формально
    /// дважды не названа ни разу.
    ///
    /// **`OnboardingSteps.swift` объявлен 23.10.2026** — ровно тем
    /// механизмом, который эта ось для него и заводила. Вызов
    /// `TGIllustration(scene: .onboarding)` поставил `f942ec4`
    /// («Онбординг стал четырьмя экранами под дизайн iOS 28», 10:20),
    /// и до объявления сторож честно краснел: «зовут из мест, которых
    /// нет в списке». Это корзина C — новый код того же дня, — и
    /// закрывается она объявлением, а не исключением: сцена
    /// `.onboarding` принадлежит теперь ровно одному месту показа,
    /// и `сценаНеНазванаДважды` это стережёт.
    private static let местаВыбораСцены = ["TGLoading.swift", "OnboardingSteps.swift"]

    private func исходники() -> [(имя: String, путь: String, строки: [String])] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [(String, String, [String])] = []
        for цель in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(цель), includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8)
                else { continue }
                найдено.append((элемент.lastPathComponent,
                                "\(цель)/\(элемент.lastPathComponent)",
                                текст.components(separatedBy: .newlines)))
            }
        }
        return найдено
    }

    /// Тело вызова — по БАЛАНСУ СКОБОК, а не по числу строк.
    ///
    /// Первая редакция этой проверки брала окно в четырнадцать строк
    /// и покраснела на `CareScreen`: ниже карточки стоит
    /// `TGButton(… systemImage: "plus")`, и ему символ положен.
    /// Красный без дефекта учит не верить красному, поэтому окно
    /// кончается там, где кончается вызов.
    private func телоВызова(_ строки: [String], от начало: Int) -> String {
        var глубина = 0
        var куски: [String] = []
        for строка in строки[начало...] {
            let код = строка.components(separatedBy: "//")[0]
            куски.append(код)
            глубина += код.filter { $0 == "(" }.count
            глубина -= код.filter { $0 == ")" }.count
            if глубина <= 0 { break }
        }
        return куски.joined(separator: "\n")
    }

    private func вызовы() -> [(где: String, тело: String)] {
        var найдено: [(String, String)] = []
        for файл in исходники() where файл.имя != Self.таблица {
            for (i, строка) in файл.строки.enumerated() {
                let код = строка.components(separatedBy: "//")[0]
                guard код.contains("EmptyStateCard(") || код.contains("TGStateful(")
                else { continue }
                найдено.append(("\(файл.путь):\(i + 1)",
                                телоВызова(файл.строки, от: i)))
            }
        }
        return найдено
    }

    @Test("Обход нашёл пустые состояния, а не промолчал")
    func былоЧтоПроверять() {
        let найдено = вызовы()
        #expect(найдено.count >= Self.вызововНеМенее, """
            вызовов пустого состояния найдено \(найдено.count),
            а в день написания было \(Self.вызововНеМенее). Либо места
            переехали, либо обход перестал их видеть — и тогда проверки
            ниже зелены потому, что им нечего смотреть.
            """)
    }

    @Test("Ни один экран не называет картинку своей рукой")
    func экранНеВыбираетКартинку() {
        var нарушения: [String] = []
        for вызов in вызовы() {
            for маркер in ["systemImage:", "emptyImage:", "TGIllustration("] {
                if вызов.тело.contains(маркер) {
                    нарушения.append("  \(вызов.где) несёт `\(маркер)`")
                }
            }
        }
        #expect(нарушения.isEmpty, """
            пустое состояние выбирает картинку на месте вызова:

            \(нарушения.joined(separator: "\n"))

            Экран называет ПРЕДМЕТ (`subject:`/`emptySubject:`) — то,
            про что он пуст. Чем это нарисовать, решает
            `EmptyStateCard.Subject.look`, и это единственная таблица
            соответствия. Вторая разойдётся с первой молча.
            """)
    }

    @Test("У каждого пустого состояния назван предмет")
    func предметНазванВсюду() {
        var безПредмета: [String] = []
        for вызов in вызовы() {
            let есть = вызов.тело.contains("subject:")
                || вызов.тело.contains("emptySubject:")
            if !есть { безПредмета.append(вызов.где) }
        }
        #expect(безПредмета.isEmpty,
                "пустое состояние без предмета: \(безПредмета)")
    }

    @Test("Иллюстрацию зовут только объявленные места")
    func иллюстрациюЗовутТолькоОбъявленныеМеста() {
        let зовут = исходники()
            .filter { $0.имя != "TGIllustration.swift" }
            .filter { файл in
                файл.строки.contains { строка in
                    строка.components(separatedBy: "//")[0].contains("TGIllustration(")
                }
            }
            .sorted { $0.путь < $1.путь }

        let незаявленные = зовут
            .filter { !Self.местаВыбораСцены.contains($0.имя) }
            .map(\.путь)

        #expect(незаявленные.isEmpty, """
            `TGIllustration` зовут из мест, которых нет в списке:

            \(незаявленные.joined(separator: "\n"))

            Объявленные места: \(Self.местаВыбораСцены).

            Сцену выбирает таблица, а не вью. Новое место показа
            заводится ОБЪЯВЛЕНИЕМ — строкой в `местаВыбораСцены`
            и таблицей в `сценыПоТаблицам`, — а не тем, что кто-то
            написал вызов.
            """)
    }

    /// Та же проверка с другого конца: объявили место — объявите
    /// и его таблицу.
    ///
    /// Без неё список мест можно расширить одной строкой, и сцены
    /// нового места не попадут в проверку на двойное имя. Группе
    /// проверок нужна проверка, что ей было что проверять.
    @Test("У каждого объявленного места есть объявленная таблица")
    func уМестаЕстьТаблица() {
        let безТаблицы = Self.местаВыбораСцены
            .filter { Self.сценыПоТаблицам[$0] == nil }

        #expect(безТаблицы.isEmpty, """
            место показа объявлено, а его таблица — нет: \(безТаблицы).

            Проверка на двойное имя сцены смотрит только в объявленные
            таблицы. Место без таблицы делает её слепой ровно на том,
            что добавили последним.
            """)
    }

    /// Сцены, разобранные по таблицам. Ключ — файл из
    /// `местаВыбораСцены`.
    ///
    /// Таблиц две. Первая — пустые состояния, читается из кода
    /// (`EmptyStateCard.Subject.look`), то есть расходится с ним
    /// не молча. Вторая — онбординг: его сцена адреса в пустых
    /// состояниях не имеет нарочно, а адрес в макете у неё есть,
    /// и показывается она ровно в одном месте одним значением.
    ///
    /// **Вторая записана списком, а не разобрана из исходника,
    /// и это граница, а не лень.** Сцена онбординга выбирается
    /// литералом у места показа (`TGIllustration(scene: .onboarding)`),
    /// таблицы-перечисления у неё нет. Значит эта строка — ПРОКСИ:
    /// она держит «одна сцена — одно место показа» и не заметит,
    /// если в `OnboardingSteps.swift` допишут вызов с другой сценой.
    private static var сценыПоТаблицам: [String: [TGIllustration.Scene]] {
        ["TGLoading.swift": EmptyStateCard.Subject.allCases.compactMap {
            if case .illustration(let s) = $0.look { return s }
            return nil
        },
         "OnboardingSteps.swift": [.onboarding]]
    }

    @Test("Ни одна сцена не названа дважды во всём приложении")
    func сценаНеНазванаДважды() {
        var где: [TGIllustration.Scene: [String]] = [:]
        for (таблица, сцены) in Self.сценыПоТаблицам {
            for сцена in сцены { где[сцена, default: []].append(таблица) }
        }
        let двойные = где.filter { $0.value.count > 1 }

        #expect(двойные.isEmpty, """
            одна сцена названа в двух таблицах: \(двойные).

            Человек увидит один рисунок на двух разных экранах
            и прочтёт это как ошибку приложения. Таблиц может быть
            несколько — сцена принадлежит ровно одной.
            """)
    }

    /// Адреса, названные планом дизайна прямо.
    ///
    /// Проверяется ПОВЕДЕНИЕ таблицы, а не её текст: сравнение
    /// исходника с исходником сказало бы только, что я не переписал
    /// строку.
    @Test("Названные дизайном адреса ведут на свои сцены")
    func адресаДизайнаНаМесте() {
        func сцена(_ предмет: EmptyStateCard.Subject) -> TGIllustration.Scene? {
            if case .illustration(let s) = предмет.look { return s }
            return nil
        }
        #expect(сцена(.history) == .history, "«пустая история — иллюстрация history»")
        #expect(сцена(.foodStock) == .stock, "«пустой запас — иллюстрация stock»")
        #expect(сцена(.offline) == .offline, "«офлайн — иллюстрация offline»")
        // Эти два взяты не с глаз, а по определению самой сцены
        // в `TGIllustration.Scene`: `feed // кормление`,
        // `family // общий дневник`.
        #expect(сцена(.feeding) == .feed)
        #expect(сцена(.family) == .family)
    }

    @Test("Каждая сцена пакета названа ровно одним предметом")
    func сценаНеРаздвоилась() {
        var кто: [TGIllustration.Scene: [EmptyStateCard.Subject]] = [:]
        for предмет in EmptyStateCard.Subject.allCases {
            if case .illustration(let s) = предмет.look {
                кто[s, default: []].append(предмет)
            }
        }
        let раздвоенные = кто.filter { $0.value.count > 1 }
        #expect(раздвоенные.isEmpty, """
            одна сцена на несколько предметов: \(раздвоенные).
            Человек увидит один и тот же рисунок на двух разных
            пустых экранах и прочтёт это как ошибку приложения.
            """)
    }

    /// Границы — последней строкой, как у остальных сторожей.
    @Test("Границы: чего не проверяет набор про иллюстрации пустых состояний")
    func границыНазваны() {
        // · Что иллюстрация НАРИСУЕТСЯ и нужным цветом — только кадр.
        //   Слои красятся токенами на отрисовке, и перекрытие стилем
        //   текстом не видно.
        // · Что `Tools/иллюстрации.py` разложил слои по смыслу: он
        //   делит по ЦВЕТУ, и ошейник, покрашенный контурным цветом,
        //   уедет в контур. Инструмент это печатает сам.
        // · Что рядом не стоят «следы» и «жетон». Правило дизайна
        //   («рядом с иллюстрацией следы и жетон не ставятся») про
        //   СОСЕДСТВО на экране, а соседство в теле вызова
        //   не выражается. Сейчас проверять нечего — ни следов,
        //   ни жетона в коде нет вовсе; но в `DECISIONS.md:32`
        //   элемент `EmptyState` описан С следами, а `:41` их рядом
        //   с иллюстрацией запрещает. Тот, кто заведёт следы, прочтёт
        //   первую строку и не прочтёт вторую.
        #expect(Bool(true))
    }
}
