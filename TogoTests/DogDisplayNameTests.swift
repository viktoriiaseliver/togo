import Testing
import Foundation
@testable import Togo

/// Единственная точка показа клички — и единственное место, поломка
/// которого ломает сразу все поверхности.
///
/// **Почему этот набор понадобился именно 07.10.2026.** Утром кличка
/// подставлялась напрямую в тридцати местах; к вечеру `togo-05` свёл
/// их к `Fmt.dogName` / `Fmt.dogNameOrFallback`. Сведение к одной точке
/// — верное решение, но оно **меняет форму риска, а не убирает его**:
/// было тридцать мест, каждое ломается по отдельности; стало одно,
/// которое ломает тридцать разом. На момент написания эту точку
/// не проверял ни один тест во всём дереве (`grep dogNameOrFallback
/// TogoTests/` → пусто).
///
/// **Чего здесь нарочно нет.** Проверок «кличка доехала до экрана»:
/// это другой вопрос и другой инструмент — кадр. Здесь только то, что
/// функция обещает сама. Сторож на подстановку (`DogNameSubstitutionTests`)
/// рядом следит, чтобы мимо этой точки никто не ходил; вместе они
/// закрывают «через точку» и «точка верна», и ни один не закрывает
/// «а что увидел человек».
@Suite("Кличка для показа")
struct DogDisplayNameTests {

    /// Запасное слово берётся из каталога **внутри** `Fmt`, поэтому
    /// сверяться с литералом здесь нельзя: тест на русской машине
    /// прошёл бы, а на французской — нет, и покраснел бы он на верном
    /// коде. Спрашиваем у того же каталога тем же ключом.
    ///
    /// Помечено словом, по которому его найдут, когда тексты разморозят:
    /// запасное слово 07.10 объявлено черновым решением Виктории.
    private var запасное: String { String(localized: "Собака") }  // ЧЕРНОВОЕ-ЗАПАСНОЕ-СЛОВО

    // MARK: - 1. Проверка, что проверять было что

    /// Стоит первой и отдельно.
    ///
    /// Все проверки ниже — про то, что пустая кличка подменяется.
    /// Если `dogNameOrFallback` начнёт возвращать запасное слово
    /// ВСЕГДА, они останутся зелёными: подмена-то происходит. Поэтому
    /// первым делом — что настоящая кличка доходит нетронутой.
    @Test("Настоящая кличка возвращается как есть, а не подменяется запасным")
    func настоящаяНеТрогается() {
        #expect(Fmt.dogNameOrFallback("Стич") == "Стич")
        #expect(Fmt.dogName("Стич") == "Стич")
        #expect(Fmt.dogNameOrFallback("Стич") != запасное, """
            точка показа подменяет даже непустую кличку. Тогда все
            проверки на пустоту ниже зелены по причине, к пустоте
            отношения не имеющей.
            """)
    }

    // MARK: - 2. Пустая кличка

    @Test("Пустая кличка не доезжает до человека пустым местом")
    func пустаяПодменяется() {
        #expect(Fmt.dogName("") == nil)
        #expect(Fmt.dogNameOrFallback("") == запасное, """
            при пустой кличке показ отдал «\(Fmt.dogNameOrFallback(""))».
            Пустое место на экране человек читает как «данные не дошли»,
            а на объявлении о пропаже строка начинается с запятой.
            """)
        #expect(!Fmt.dogNameOrFallback("").isEmpty)
    }

    /// **Пробелы — не пустота, и это главная тонкость точки.**
    ///
    /// Проверка на `isEmpty` без подрезки пропускает кличку из одних
    /// пробелов: по типу строка непустая, на экране — то же пустое
    /// место. Отзыв 06.10 пришёл про `""`, но обмен приносит и `" "`,
    /// и перевод строки: на том конце кличку печатает человек.
    @Test("Кличка из одних пробелов — тоже пустая")
    func пробелыЭтоПустота() {
        for сырая in [" ", "   ", "\t", "\n", " \n\t "] {
            #expect(Fmt.dogName(сырая) == nil, """
                «\(сырая.debugDescription)» признано настоящей кличкой.
                На экране это пустое место, неотличимое от потерянных
                данных, — а проверка `isEmpty` его пропускает.
                """)
            #expect(Fmt.dogNameOrFallback(сырая) == запасное)
        }
    }

    @Test("Пробелы по краям срезаются, а кличка внутри остаётся")
    func краяСрезаются() {
        #expect(Fmt.dogName("  Стич  ") == "Стич")
        #expect(Fmt.dogNameOrFallback("\nБелладонна\n") == "Белладонна")
        // Пробел ВНУТРИ клички — часть имени, а не мусор: «Леди Баг»
        // это одна собака с пробелом, и срезать его нельзя.
        #expect(Fmt.dogName("Леди Баг") == "Леди Баг")
    }

    // MARK: - 3. Запасное слово обязано быть переводимым

    /// **Запрет, а не требование.** «Запасное слово переведено» грепом
    /// не проверяется, а вот «запасное слово не пришло сюда литералом
    /// с места вызова» — проверяется: литерал снаружи вернулся бы
    /// одинаковым при любом языке.
    ///
    /// Довод оплачен нами дважды: `Text(значение)` типа `String` рисует
    /// текст мимо каталога, и ровно так у Togo французский экран
    /// оказался наполовину русским при полном каталоге.
    @Test("Запасное слово приходит из каталога, а не литералом")
    func запасноеИзКаталога() {
        #expect(Fmt.dogNameOrFallback("") == String(localized: "Собака"), """
            запасное слово разошлось с ключом каталога. Если оно
            вклеено литералом внутри `Fmt`, француз прочтёт русское
            слово — в том числе на объявлении о пропаже собаки.
            """)
    }
}
