import Foundation
import Testing

/// К справочнику клиник есть дорога с «Здоровья», и заводятся клиники
/// не только приёмом извне и отладочной галереей.
///
/// **Повод — замер 26.10.2026, и это не гипотеза.** У `Clinic` были
/// модель с подробной головой, обмен (`ClinicPayload`), архив
/// (`ClinicSnapshot`), миграция, два `@Query` в живых экранах —
/// и **ни одного человеческого места создания**:
///
/// ```
/// SharedDiaryPayloads.swift:797   приём ИЗВНЕ, со второго телефона
/// Backup.swift:395                откат архива
/// CloudKitSchemaWarmup.swift:234  маркер схемы
/// MedicalRecordGallery.swift:93   целиком под `#if DEBUG`
/// ```
///
/// > **Это на шаг хуже, чем `LabResult` до 08.10.2026.** Там экран
/// > существовал и был недостижим. Здесь ДВА живых экрана —
/// > `VetVisitEditor` и `PrescriptionEditor` — рисовали
/// > `Picker("Клиника")` поверх пустого `@Query`, то есть
/// > **спрашивали то, на что ответить нельзя**, и выглядело это
/// > не нашей поломкой, а невнимательностью человека.
///
/// Сторож стоит на **ВЫЗОВЕ**, а не на модели, и написан **от
/// запрета**: «нет ни одной дороги» спрашивается надёжно, а «есть ли
/// нужная» — нет, у дороги десяток форм. Образец и причина формы —
/// `ДорогаКАнализамTests`.
@Suite("Дорога к справочнику клиник")
struct ДорогаКСправочникуКлиникTests {

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()

    private static func текст(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Строки кода без комментариев: сканирующий сторож, не различающий
    /// код и прозу, меряет прозу. Над нужной строкой в `HealthScreen`
    /// лежит комментарий, называющий `ClinicsScreen` поимённо, —
    /// без вырезания сторож прошёл бы на объяснении. Этот класс
    /// в проекте оплачен отдельно: «комментарий с именем вызова красит
    /// сторожа зелёным».
    private static func строкиКода(_ текст: String) -> [String] {
        текст.split(separator: "\n", omittingEmptySubsequences: false)
            .map(String.init)
            .filter { строка in
                let о = строка.trimmingCharacters(in: .whitespaces)
                return !о.hasPrefix("//") && !о.hasPrefix("///")
                    && !о.hasPrefix("*") && !о.hasPrefix("/*")
            }
    }

    // MARK: Было что сторожить

    /// **Без этого теста весь набор — ложный зелёный.** Переименуй
    /// кто-нибудь файл, и `текст(_:)` бросит, а не соврёт; но подсунь
    /// пустой файл — и все проверки ниже прошли бы на пустоте.
    @Test("Экран справочника и экран «Здоровье» на месте")
    func былоЧтоСторожить() throws {
        let здоровье = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))
        let справочник = try Self.строкиКода(Self.текст("Togo/Features/Health/ClinicScreens.swift"))
        #expect(здоровье.count > 200, "HealthScreen подозрительно короток — проверь путь, а не вывод")
        #expect(справочник.contains { $0.contains("struct ClinicsScreen") },
                "экрана справочника нет — сторожить нечего, и это находка, а не повод чинить сторожа")
        #expect(справочник.contains { $0.contains("struct ClinicEditor") },
                "формы клиники нет; дорога без формы — это дорога в пустоту")
    }

    // MARK: Дорога

    @Test("С «Здоровья» есть дорога к справочнику клиник")
    func дорогаЕсть() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/HealthScreen.swift"))
        let ведут = строки.filter { $0.contains("ClinicsScreen") }
        #expect(!ведут.isEmpty, """
            на «Здоровье» нет ни одной дороги к справочнику клиник.
            Значит `Clinic` снова недостижим — а `VetVisitEditor`
            и `PrescriptionEditor` продолжают рисовать `Picker("Клиника")`
            поверх `@Query [Clinic]`, и у человека там одна строка
            «не указана». Экран спрашивает то, на что ответить нельзя.
            Снявший ссылку — верни её, а не правь сторожа.
            """)
    }

    // ЗДЕСЬ БЫЛА КОПИЯ ЧУЖОЙ ПРОВЕРКИ, снята 26.10.2026.
    //
    // `@Test("Дорога к справочнику клиник не ведёт в отладочную галерею")` стоял и здесь,
    // и в `ДорогаКАнализамTests.swift:75` — **дословно тот же тест**:
    // оба читали `Togo/Features/Health/HealthScreen.swift` и искали
    // в нём `MedicalRecordGallery`.
    //
    // Это не «два сторожа на одно место» (у тех запрет держит ДОРОГУ,
    // а число — ЗНАЧЕНИЕ, и подделка нарушает ровно одно из двух).
    // Это копия: подделка нарушила бы обе разом, и различить их
    // нечем — а «две копии разойдутся молча» у нас уже оплачено.
    //
    // Проверка живёт в `ДорогаКАнализамTests` и относится к ЭКРАНУ
    // «Здоровье», а не к дороге в справочник клиник: галерея одна
    // на весь медслой, и дорог в неё тоже одна на экран. Снявший её
    // там — не заводи здесь, предмет общий.
    //
    // Нашлось это не чтением: имя теста было ДУБЛЕМ на всё дерево
    // (1290 `@Test`, единственный повтор), и сторож
    // `TestNameUniquenessTests` его и держит. То есть сторож на имена
    // поймал копию ПРОВЕРКИ — не ту ось, на которую заводился,
    // но ровно тот предмет.

    // MARK: Создание — не только извне и не только под #if DEBUG

    /// **Главная проверка набора.** Создание обязано существовать
    /// в живом экране: именно этого не было, и именно это не ловилось
    /// ничем — набор был зелёным, потому что тесты создают клиники сами
    /// (`BackupTests`, `SharedDiarySyncTests`, `ЗасевTests`).
    @Test("Clinic создаётся в живом экране, а не только приёмом извне")
    func созданиеВнеОтладки() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/ClinicScreens.swift"))
        #expect(строки.contains { $0.contains("Clinic(") }, """
            `Clinic(` не создаётся ни в одном живом экране.
            Остаются только приём извне (SharedDiaryPayloads), откат
            архива (Backup), маркер схемы (CloudKitSchemaWarmup)
            и галерея под `#if DEBUG` — ни одного человеческого.
            Модель без места ввода — это не «почти готово», это ноль.
            """)

        // Условие, при котором эта проверка перестанет быть верной.
        let галерея = try Self.текст("Togo/DesignSystem/MedicalRecordGallery.swift")
        #expect(галерея.contains("#if DEBUG"), """
            `MedicalRecordGallery` больше не под `#if DEBUG` — тогда
            отладочный стенд уезжает людям, и это отдельная находка.
            """)
    }

    // MARK: Поля, которые экран обещает

    /// **`isLab`, `phone` и `detail` — ввод, а не только объявление.**
    ///
    /// Все три были мёртвыми с обоих концов: ноль вхождений
    /// в `Togo/Features/`. `isLab` при этом объяснён в модели
    /// на шести строках — «в выборе „где сдавали" и „кто принимал"
    /// список должен быть разным», — а оба пикера перечисляли клиники
    /// БЕЗ ФИЛЬТРА.
    ///
    /// Сторож спрашивает именно **ввод**, а не упоминание: поле
    /// без читателя грепом находится один раз, в объявлении,
    /// и выглядит отсутствующим; поле без ПИСАТЕЛЯ выглядит точно так же.
    @Test("У всех трёх полей клиники есть ввод")
    func поляИмеютВвод() throws {
        let строки = try Self.строкиКода(Self.текст("Togo/Features/Health/ClinicScreens.swift"))
        let тело = строки.joined(separator: "\n")

        var безВвода: [String] = []
        for поле in ["isLab", "phone", "detail"] where !тело.contains(поле) {
            безВвода.append(поле)
        }
        #expect(безВвода.isEmpty, """
            поля клиники без ввода в форме: \(безВвода).
            Модель объясняет `isLab` на шести строках, а телефон держит
            тест обмена словами «название клиники без номера не помогает
            в тот час, когда…». Поле, которое некому записать, — такой же
            ноль, как поле, которое некому прочесть.
            """)
    }

    /// **`isLab` НЕСИММЕТРИЧЕН, и сторож проверяет обе стороны.**
    ///
    /// Наряд просил «фильтр в двух пикерах по `isLab`». Перемер
    /// 26.10.2026 показал, что одинаковый фильтр на три пикера был бы
    /// дефектом в одном из них:
    ///
    /// ```
    /// «кто принимал» (визит)       лаборатория приём НЕ ведёт
    ///                              → исключать isLab        ✔ фильтр
    /// «кто назначил» (рецепт)      рецепт выписывает принимающий
    ///                              → исключать isLab        ✔ фильтр
    /// «где сдавали» (анализ)       `Medical.swift:41`: «IDEXX · Antech
    ///                              · КЛИНИКА» — анализ часто сдают
    ///                              в обычной клинике
    ///                              → НЕ фильтровать       ✘ фильтр ЗАПРЕЩЁН
    /// ```
    ///
    /// > **Признак запрещает приём в лаборатории и НЕ запрещает забор
    /// > в клинике.** Один фильтр на два вопроса дал бы верный ответ
    /// > одному из них, а второму — такой же молчаливый дефект, какой
    /// > был до фильтра: человек, сдавший кровь у своего врача,
    /// > не смог бы указать, где сдавал.
    ///
    /// Поэтому третья строка написана **от запрета**: она падает,
    /// если в пикер анализа однажды принесут исключение лабораторий
    /// «за компанию» с двумя соседями.
    @Test("Пикеры «кто принимал» исключают лаборатории, пикер «где сдавали» — нет")
    func пикерыФильтруютНесимметрично() throws {
        for путь in ["Togo/Features/Health/VisitDiagnosisScreens.swift",
                     "Togo/Features/Health/PrescriptionScreens.swift"] {
            let тело = try Self.строкиКода(Self.текст(путь)).joined(separator: "\n")
            #expect(тело.contains("!$0.isLab"), """
                \(путь): пикер «кто принимал» не исключает лаборатории.
                Модель (`Clinic.swift:34`): «туда сдают анализы,
                там не принимают». До 26.10.2026 фильтра не было вовсе,
                и в списке стояли IDEXX и Antech — организации,
                которые приём не ведут по устройству.
                """)
        }

        let анализы = try Self.строкиКода(Self.текст("Togo/Features/Health/LabResultScreens.swift"))
            .joined(separator: "\n")
        #expect(!анализы.contains("!$0.isLab"), """
            пикер «где сдавали» исключает лаборатории — а должен
            включать И лаборатории, И клиники. `Medical.swift:41`:
            «Лаборатория: IDEXX · Antech · КЛИНИКА» — анализ часто сдают
            в обычной клинике. Это НЕ тот же фильтр, что у «кто
            принимал»: признак несимметричен, и перенесённый сюда
            «за компанию» он отнимает у человека возможность указать,
            где он сдавал кровь.
            """)
        #expect(анализы.contains("isLab"), """
            пикер «где сдавали» не читает `isLab` вовсе.
            Фильтра тут быть не должно, а порядок — должен:
            лаборатории идут первыми, это частый случай.
            """)
    }

    /// **Надгробия не показываются.** `ОбщееУдаление` говорит это
    /// прямо: «надгробие, которое видно человеку, — не удаление,
    /// а порча экрана», и называет 22 места показа и счёта.
    /// Четыре из них — этот справочник, его счётчик и два пикера.
    @Test("Справочник и пикеры не показывают надгробия")
    func надгробияНеПоказываются() throws {
        let пути = [
            "Togo/Features/Health/ClinicScreens.swift",
            "Togo/Features/Health/HealthScreen.swift",
            "Togo/Features/Health/VisitDiagnosisScreens.swift",
            "Togo/Features/Health/PrescriptionScreens.swift",
        ]
        var безФильтра: [String] = []
        for путь in пути {
            let тело = try Self.строкиКода(Self.текст(путь)).joined(separator: "\n")
            if !тело.contains("deletedAt") { безФильтра.append(путь) }
        }
        #expect(безФильтра.isEmpty, """
            показ клиник без фильтра надгробий: \(безФильтра).
            Клиника, удалённая на втором телефоне, обязана исчезнуть
            и в справочнике, и в счётчике на «Здоровье», и в обоих
            пикерах. Иначе человек выберет организацию, которой у семьи
            больше нет.
            """)
    }

    // MARK: Граница

    @Test("Границы сторожа дороги к справочнику: чего он не умеет")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит: в исходнике «Здоровья» есть упоминание
            `ClinicsScreen`, в `ClinicScreens.swift` есть `Clinic(`,
            три имени полей и `isLab` в трёх пикерах, `deletedAt`
            в четырёх файлах показа. И ТОЛЬКО ЭТО.

            НЕ проверяется:
            · что человек ДОЙДЁТ. Сторож видит упоминание имени
              и не видит, что от упоминания ничего не происходит:
              `TGLink` может оказаться за `if`, который всегда ложен.
              Ловится кадром, здесь невидимо по устройству;
            · что форма СОХРАНЯЕТ. `context.insert` плюс `persist`
              здесь не спрашиваются — проверка поведенческая;
            · что фильтр по `isLab` стоит в НУЖНУЮ сторону. Сторож
              видит имя поля, а не знак условия: лаборатории в списке
              «кто принимал» он пропустит. Это ось, которую может
              проверить только кадр или поведенческий тест;
            · что телефон НАЖИМАЕТСЯ. `tel://` в исходнике доказывает
              намерение, а не работу: `openURL` на симуляторе
              телефонию не поднимает вовсе.

            Последние два пункта — названный долг, а не пропуск.
            """
        #expect(границы.isEmpty == false)
        // Проверяется за минуту:
        //   grep -n "ClinicsScreen" Togo/Features/Health/HealthScreen.swift
        //   grep -rn "Clinic(" Togo/Features/
    }
}
