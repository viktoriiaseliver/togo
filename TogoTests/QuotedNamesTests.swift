import Testing
import Foundation
@testable import Togo

/// Текст, посылающий к экрану по имени, называет его так же, как он подписан.
///
/// Замер 23.09.2026 во французском Togo, отгруженном четверым: **пять мест**,
/// где текст указывает на то, чего нет.
///
/// | текст говорит | экран подписан |
/// |---|---|
/// | `«s'il s'est passé quelque chose»` | `En cas de problème` |
/// | `« Alimentation »` | `Repas` |
/// | `« Carnet illisible »` | `Le journal ne s'est pas ouvert` |
/// | `«Promenade par étiquette»` | `Promenade par l'étiquette` |
/// | `« Terminé »` | `OK` |
///
/// Это не стилистика. Каждая посылает человека искать то, чего он не найдёт,
/// и именно на тех экранах, вся работа которых — сказать, куда смотреть.
/// Самая острая — четвёртая: в «Командах» действия ищут **по имени**,
/// и пропавший артикль значит «такого действия нет».
///
/// **Класс, которого не ловит ни словарь, ни счётчик.** Все слова написаны
/// верно, перевод полон, форм числа хватает. Ловится только сверкой цитаты
/// с подписью — то есть вопросом «а есть ли то, на что мы показываем».
///
/// Русский здесь опора: в нём цитата — это ключ каталога, и перевод цитаты
/// обязан совпадать с переводом ключа.
@Suite("Цитата экрана совпадает с его подписью")
struct QuotedNamesTests {

    private struct Каталог {
        let строки: [String: [String: String]]   // ключ → язык → перевод

        func перевод(_ ключ: String, _ язык: String) -> String? {
            строки[ключ]?[язык]
        }
    }

    private func каталог() throws -> Каталог {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Resources/Localizable.xcstrings")
        let данные = try Data(contentsOf: url)
        let корень = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]

        var собранное: [String: [String: String]] = [:]
        for (ключ, запись) in строки {
            let локализации = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
            var по_языкам: [String: String] = [:]
            for (язык, значение) in локализации {
                if let текст = ((значение as? [String: Any])?["stringUnit"]
                    as? [String: Any])?["value"] as? String {
                    по_языкам[язык] = текст
                }
            }
            собранное[ключ] = по_языкам
        }
        return Каталог(строки: собранное)
    }

    /// Что стоит в «ёлочках». Пробелы внутри кавычек во французском
    /// типографские и к имени не относятся.
    private func цитаты(_ текст: String) -> [String] {
        let образец = try? NSRegularExpression(pattern: "«([^»]{1,60})»")
        let диапазон = NSRange(текст.startIndex..., in: текст)
        return (образец?.matches(in: текст, range: диапазон) ?? []).compactMap {
            Range($0.range(at: 1), in: текст).map {
                текст[$0].trimmingCharacters(in: .whitespaces)
            }
        }
    }

    @Test("Во всех языках цитата экрана переведена так же, как сам экран")
    func цитатыСовпадаютСПодписями() throws {
        let к = try каталог()
        #expect(к.строки.count > 500, """
            каталог прочитан не весь (\(к.строки.count) ключей).
            Сканер, переставший что-либо находить, молчит так же,
            как тот, кому нечего сказать.
            """)

        var расхождения: [String] = []
        var проверено = 0

        for (ключ, переводы) in к.строки {
            let русский = переводы["ru"] ?? ключ
            for цитата in цитаты(русский) {
                // Проверяем только те цитаты, что сами есть в каталоге:
                // «Настройки → собака → Питание и режим» это путь, а не ключ.
                guard let имена = к.строки[цитата] else { continue }
                for (язык, перевод) in переводы where язык != "ru" {
                    guard let имя = имена[язык] else { continue }
                    проверено += 1
                    guard !цитаты(перевод).contains(имя) else { continue }
                    расхождения.append("""
                        [\(язык)] ключ «\(ключ.prefix(50))»
                          цитирует: \(цитаты(перевод).map { "«\($0)»" }.joined(separator: " "))
                          а «\(цитата)» подписан как «\(имя)»
                        """)
                }
            }
        }

        #expect(проверено > 5, """
            сверено всего \(проверено) цитат — проверка не состоялась.
            Скорее всего сломался разбор кавычек.
            """)
        #expect(расхождения.isEmpty, """
            текст посылает к экрану по имени, которого у экрана нет:

            \(расхождения.sorted().joined(separator: "\n\n"))

            Человек пойдёт искать и не найдёт. В «Командах» хуже:
            действия ищут по имени, и неточная цитата значит
            «такого действия не существует».
            """)
    }

    /// Разбор кавычек проверяется отдельно: сканер, который перестал
    /// находить цитаты, прошёл бы молча и выглядел бы как зелёный.
    @Test("Кавычки разбираются")
    func кавычкиРазбираются() {
        #expect(цитаты("на экране «Питание»") == ["Питание"])
        #expect(цитаты("sur l'écran « Repas »") == ["Repas"])
        #expect(цитаты("«Еда» и «Уход»") == ["Еда", "Уход"])
        #expect(цитаты("без кавычек").isEmpty)
    }
}
