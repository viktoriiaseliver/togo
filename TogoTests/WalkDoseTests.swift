import Testing
import Foundation
import SwiftData
@testable import Togo

/// Доза рядом с выходом.
///
/// Правило дизайна: доза в ±30 минут от выхода видна человеку **до**
/// того, как он выйдет, а если препарат можно дать на улице — там же
/// и кнопка «Дал». Замер 07.10.2026: окна тридцати минут в коде
/// не было вовсе, `canGiveOutside` не читался ниоткуда.
@Suite("Доза рядом с выходом")
@MainActor
struct WalkDoseTests {

    private func контекст() -> ModelContext {
        ModelContext(Persistence.container())
    }

    /// Собака на лечении, одна схема, одна открытая доза в `через`
    /// от `сейчас`.
    private func собакаСДозой(через: TimeInterval,
                              наУлице: Bool = false,
                              сейчас: Date,
                              in context: ModelContext) -> Dog {
        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.isOnTreatment = true
        context.insert(dog)

        let схема = Medication(name: "Lévothyrox", doseText: "66 мкг",
                               times: [7 * 60], fastingMinutes: 45)
        схема.canGiveOutside = наУлице
        схема.dog = dog
        context.insert(схема)

        let доза = DoseRecord(scheduledAt: сейчас.addingTimeInterval(через))
        доза.medication = схема
        context.insert(доза)
        return dog
    }

    // MARK: 0. Было ли что проверять

    /// **Первой проверкой — что набору было что проверять.**
    ///
    /// Без неё остальные зеленеют на пустом расписании: «дозы рядом нет»
    /// верно и тогда, когда доз нет вовсе, и тогда, когда сценарий
    /// не наполнил стор. Набор, которому нечего проверять, молчит так
    /// же, как набор, у которого всё хорошо.
    @Test("Сценарий правда наполнил расписание")
    func сценарийНаполнилРасписание() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 10 * 60, сейчас: сейчас, in: context)
        try context.save()

        #expect(dog.isOnTreatment, "собака не на лечении — дозы не считаются вовсе")
        #expect(dog.medications.count == 1, "схем \(dog.medications.count) — сценарий пуст")
        let дозы = try context.fetch(FetchDescriptor<DoseRecord>())
        #expect(дозы.count == 1, "отметок \(дозы.count) — проверять нечего")
        #expect(дозы.first?.givenAt == nil, "доза уже отмечена — она не открытая")
    }

    // MARK: 1. Окно

    @Test("Доза через двадцать минут — рядом")
    func черезДвадцатьМинутРядом() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 20 * 60, сейчас: сейчас, in: context)
        try context.save()

        let рядом = try #require(WalkDose.рядом(dog, at: сейчас), """
            доза через двадцать минут не найдена рядом с выходом,
            а правило дизайна — тридцать.
            """)
        #expect(рядом.через > 0, "знак потерян: «через» и «назад» — разные фразы")
        #expect(рядом.препарат == "Lévothyrox")
    }

    @Test("Доза двадцать минут назад — тоже рядом")
    func двадцатьМинутНазадТожеРядом() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: -20 * 60, сейчас: сейчас, in: context)
        try context.save()

        let рядом = try #require(WalkDose.рядом(dog, at: сейчас), """
            окно односторонее: пропущенную двадцать минут назад дозу
            человеку сказать надо не меньше, чем будущую.
            """)
        #expect(рядом.через < 0, "знак потерян")
    }

    @Test("Доза через час — не рядом")
    func черезЧасНеРядом() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 60 * 60, сейчас: сейчас, in: context)
        try context.save()

        #expect(WalkDose.рядом(dog, at: сейчас) == nil, """
            доза через час названа рядом с выходом. Окно, которое
            срабатывает всегда, ничего не говорит: человек перестанет
            читать строку.
            """)
    }

    // MARK: 2. Два ответа раздельно

    /// **Главный тест файла.** «Доза рядом» и «можно дать на улице» —
    /// два разных ответа, и второй не следует из первого.
    @Test("Доза рядом есть, а давать на улице нельзя — это два ответа")
    func дваОтветаРаздельно() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 10 * 60, наУлице: false, сейчас: сейчас, in: context)
        try context.save()

        let рядом = try #require(WalkDose.рядом(dog, at: сейчас))
        #expect(рядом.даётсяНаУлице == false, """
            «рядом» и «можно на улице» слились в один ответ. Человеку
            с каплями в глаз надо сказать «через десять минут доза»
            и НЕ предлагать дать её на улице: сообщение, покрывающее
            две причины одним текстом, даёт совет, неверный для одной
            из них.
            """)
    }

    @Test("Разрешённую на улице отдаём с флагом «можно»")
    func разрешённуюОтдаёмСФлагом() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 10 * 60, наУлице: true, сейчас: сейчас, in: context)
        try context.save()

        #expect(WalkDose.рядом(dog, at: сейчас)?.даётсяНаУлице == true, """
            флаг «можно дать на улице» не доехал. Это ОТВЕТ ЧЕЛОВЕКА,
            а не наш вывод из соседних полей: вывод решал бы за него
            вопрос, на который он отвечает сам.
            """)
    }

    // MARK: 3. Что отбрасывается

    @Test("Уже отмеченную дозу рядом не предлагаем")
    func отмеченнуюНеПредлагаем() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 10 * 60, сейчас: сейчас, in: context)
        let доза = try #require(dog.medications.first?.doses.first)
        доза.givenAt = сейчас.addingTimeInterval(-60)
        try context.save()

        #expect(WalkDose.рядом(dog, at: сейчас) == nil, """
            предложили дать дозу, которую уже дали. Это единственное
            место в приложении, где ошибка обмена не путаница
            в дневнике, а вторая таблетка.
            """)
    }

    @Test("Пропущенную и отменённую рядом не предлагаем")
    func пропущеннуюНеПредлагаем() throws {
        let сейчас = Date()
        for пометить in [0, 1] {
            let context = контекст()
            let dog = собакаСДозой(через: 10 * 60, сейчас: сейчас, in: context)
            let доза = try #require(dog.medications.first?.doses.first)
            if пометить == 0 { доза.skippedAt = сейчас } else { доза.cancelledAt = сейчас }
            try context.save()
            #expect(WalkDose.рядом(dog, at: сейчас) == nil,
                    "решение по дозе человек уже принял, а мы предлагаем заново")
        }
    }

    @Test("Приостановленную схему не предлагаем")
    func приостановленнуюНеПредлагаем() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 10 * 60, сейчас: сейчас, in: context)
        dog.medications.first?.isPaused = true
        try context.save()

        #expect(WalkDose.рядом(dog, at: сейчас) == nil,
                "приостановленную схему не дают вовсе")
    }

    // MARK: 4. Ближайшая, а не первая

    @Test("Из двух подходящих берётся ближайшая по времени")
    func берётсяБлижайшая() throws {
        let сейчас = Date()
        let context = контекст()
        let dog = собакаСДозой(через: 25 * 60, сейчас: сейчас, in: context)
        let схема = try #require(dog.medications.first)
        let ближе = DoseRecord(scheduledAt: сейчас.addingTimeInterval(5 * 60))
        ближе.medication = схема
        context.insert(ближе)
        try context.save()

        let рядом = try #require(WalkDose.рядом(dog, at: сейчас))
        #expect(abs(рядом.через - 5 * 60) < 1, """
            взята не ближайшая доза. Порядок массива `doses` нам
            не принадлежит, и «первая подходящая» — это лотерея.
            """)
    }

    // MARK: 5. Границы набора

    /// Названы здесь, а не в чьей-то памяти.
    @Test("Границы: что этот набор НЕ проверяет")
    func границыНазваны() {
        // Зелёный здесь значит: функция отвечает верно на вопрос
        // «есть ли доза рядом и можно ли её дать на улице».
        //
        // Он НЕ значит, что строка появилась на экране: ни шторка
        // «Просится», ни режим «На улице» эту функцию пока не зовут —
        // у неё ноль вызовов из `Togo/`, и это намеренно: текст
        // и дизайн заморожены решением Виктории 07.10.2026, а строка
        // на экране — текст.
        //
        // Тот же зазор, что между `SnapshotText` и видом «острова»:
        // значение проверяемо, поверхность — нет. Поймать «строки нет»
        // может только кадр.
        //
        // И второе: функция читает УЖЕ ЗАВЕДЁННЫЕ отметки. Заводит их
        // `DoseScheduler.ensureDoses` при открытии экрана; если его
        // не позвали, дозы рядом не найдётся, и виновата будет не эта
        // функция.
        #expect(WalkDose.window == 30 * 60, """
            окно изменилось. Тридцать минут — правило дизайна
            (`CLAUDE.md` пакета), а не замер: менять его можно только
            вместе с правилом.
            """)
    }
}
