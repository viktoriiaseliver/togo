import Foundation
import Testing

/// Кириллический литерал, склеенный через `+`, уходит человеку русским
/// на всех пяти языках — и ни один другой сторож этого не видит.
///
/// **Механизм.** `"…\(x)…" + "…"` — это обычный `String`, мимо каталога.
/// Куски при этом могут лежать в каталоге переведёнными (их туда заводит
/// разборщик текста), и полнота каталога выглядит соблюдённой: ключ есть,
/// переводы есть, читателя нет. `.готовая(_:)` ищет в каталоге уже
/// СОБРАННУЮ фразу с подставленным именем и временем и не находит её.
///
/// Ревизия 05.11.2026 нашла пять таких склеек (и ещё три литерала справа от `??`), и первая — красная
/// плашка «Сейчас кормить нельзя» (`FeedingScreen.fastingCard`): объяснение
/// окна натощак, то есть медицинский текст, по-русски на en/fr/kk/uk.
///
/// **Ось — от устройства, а не от перечня:** любой строковый литерал
/// с кириллицей, у которого соседний значимый знак — `+` (слева или
/// справа, включая `+=`). Одна фраза — один `String(localized:)`.
///
/// **Чего сторож НЕ видит, названо:** литерал справа от `??` — это ось
/// соседа, `FallbackLiteralTests` (храповик долга по файлам); литералы
/// внутри `\( … )` интерполяции — разбор их пропускает целиком; и всё,
/// что вне `Togo/Features` и `Togo/DesignSystem` (домен, `Store`).
///
/// Читает с диска `Togo/Features` и `Togo/DesignSystem` через `#filePath`.
struct СклейкаМимоКаталогаTests {

    private static var корень: URL {
        URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
    }

    /// Литерал и его соседи по обе стороны, без пробелов и комментариев.
    struct Литерал {
        let текст: String
        let строка: Int
        let слева: Character?
        /// Знак перед левым соседом: отличает `+=` от `=` и `==`.
        let слева2: Character?
        let справа: Character?
    }

    /// Разбор Swift-исходника до литералов: комментарии вырезаются,
    /// интерполяция `\( … )` пропускается с учётом вложенных скобок
    /// и вложенных строк, тройные кавычки — один литерал.
    static func литералы(_ код: String) -> [Литерал] {
        let з = Array(код)
        var итог: [Литерал] = []
        var i = 0
        var строка = 1
        var последнийЗначимый: Character? = nil
        var предпоследнийЗначимый: Character? = nil

        func пропуститьСтроку(_ i: inout Int, тройная: Bool, строка: inout Int) -> String {
            var текст = ""
            while i < з.count {
                let c = з[i]
                if c == "\n" { строка += 1 }
                if c == "\\", i + 1 < з.count {
                    if з[i + 1] == "(" {
                        // интерполяция: до парной скобки, вложенные строки — целиком
                        i += 2
                        var глубина = 1
                        while i < з.count, глубина > 0 {
                            let d = з[i]
                            if d == "\n" { строка += 1 }
                            if d == "(" { глубина += 1 }
                            if d == ")" { глубина -= 1 }
                            if d == "\"" {
                                i += 1
                                _ = пропуститьСтроку(&i, тройная: false, строка: &строка)
                                continue
                            }
                            i += 1
                        }
                        текст.append("•")
                        continue
                    }
                    текст.append(з[i + 1]); i += 2; continue
                }
                if тройная {
                    if c == "\"", i + 2 < з.count, з[i + 1] == "\"", з[i + 2] == "\"" {
                        i += 3; return текст
                    }
                } else if c == "\"" {
                    i += 1; return текст
                }
                текст.append(c); i += 1
            }
            return текст
        }

        while i < з.count {
            let c = з[i]
            if c == "\n" { строка += 1; i += 1; continue }
            if c == "/", i + 1 < з.count, з[i + 1] == "/" {
                while i < з.count, з[i] != "\n" { i += 1 }
                continue
            }
            if c == "/", i + 1 < з.count, з[i + 1] == "*" {
                i += 2
                while i + 1 < з.count, !(з[i] == "*" && з[i + 1] == "/") {
                    if з[i] == "\n" { строка += 1 }
                    i += 1
                }
                i += 2
                continue
            }
            if c == "\"" {
                let начало = строка
                let тройная = i + 2 < з.count && з[i + 1] == "\"" && з[i + 2] == "\""
                i += тройная ? 3 : 1
                let текст = пропуститьСтроку(&i, тройная: тройная, строка: &строка)
                // правый сосед: первый значимый знак после литерала
                var j = i
                while j < з.count, з[j] == " " || з[j] == "\t" || з[j] == "\n" { j += 1 }
                let справа: Character? = j < з.count ? з[j] : nil
                итог.append(Литерал(текст: текст, строка: начало,
                                    слева: последнийЗначимый, слева2: предпоследнийЗначимый,
                                    справа: справа))
                предпоследнийЗначимый = последнийЗначимый
                последнийЗначимый = "\""
                continue
            }
            if !c.isWhitespace {
                предпоследнийЗначимый = последнийЗначимый
                последнийЗначимый = c
            }
            i += 1
        }
        return итог
    }

    /// Блоки `#if DEBUG … #endif` гасятся пустыми строками (номера строк
    /// сохраняются): отладочные кнопки человек из App Store не видит.
    /// Граница: `#else` такого блока тоже гасится — релизный код
    /// в нём этим сторожем не читается.
    static func безОтладки(_ код: String) -> String {
        var глубина = 0
        return код.components(separatedBy: "\n").map { строка in
            let т = строка.trimmingCharacters(in: .whitespaces)
            if глубина == 0 {
                if т.hasPrefix("#if DEBUG") { глубина = 1; return "" }
                return строка
            }
            if т.hasPrefix("#if") { глубина += 1 }
            if т.hasPrefix("#endif") { глубина -= 1 }
            return ""
        }.joined(separator: "\n")
    }

    static func кириллица(_ s: String) -> Bool {
        s.unicodeScalars.contains { (0x0400...0x04FF).contains($0.value) }
    }

    /// Склейка: `+` справа от литерала либо `+` / `+=` слева от него.
    static func склейки(_ код: String) -> [Литерал] {
        литералы(код).filter { л in
            кириллица(л.текст) && (л.справа == "+" || л.слева == "+"
                                     || (л.слева == "=" && л.слева2 == "+"))
        }
    }

    // MARK: Разбор умеет то, на что опирается вердикт

    @Test("Разбор находит склейку с обеих сторон и не путает её с кодом в интерполяции и комментарием")
    func разборУмеет() {
        let образец = #"""
        let a = "кот " + имя
        let b = имя + " пёс"
        let c = "\(x + y) мышь"
        // let d = "нет" + x
        /* "тоже нет" + x */
        let e = "ёж"
        e += "ещё"
        if e == "ёж" {}
        let f = String(localized: "до \(Fmt.clock(до))") + " · " + кому
        #if DEBUG
        let g = "отладка" + x
        #endif
        """#
        let найдено = Self.склейки(Self.безОтладки(образец)).map(\.текст)
        #expect(найдено == ["кот ", " пёс", "ещё"], "разбор вернул \(найдено)")
        // и без гашения отладки тот же образец даёт четвёртую — гашение не пустое
        #expect(Self.склейки(образец).count == 4)
    }

    // MARK: Предмет

    @Test("В экранах и компонентах нет кириллических литералов, склеенных через +")
    func нетСклеек() throws {
        let fm = FileManager.default
        var файлов = 0
        var литераловСКириллицей = 0
        var нарушения: [String] = []
        for папка in ["Togo/Features", "Togo/DesignSystem"] {
            let url = Self.корень.appendingPathComponent(папка)
            guard let обход = fm.enumerator(at: url, includingPropertiesForKeys: nil) else {
                Issue.record("папки нет: \(url.path) — сторож смотрит не туда")
                return
            }
            for case let файл as URL in обход where файл.pathExtension == "swift" {
                let код = Self.безОтладки(try String(contentsOf: файл, encoding: .utf8))
                файлов += 1
                let все = Self.литералы(код)
                литераловСКириллицей += все.filter { Self.кириллица($0.текст) }.count
                for л in Self.склейки(код) {
                    нарушения.append("\(папка)/…/\(файл.lastPathComponent):\(л.строка)  «\(л.текст)»")
                }
            }
        }
        // Проверка, что было что проверять: на 05.11.2026 файлов в двух
        // папках 118, кириллических литералов 2653 (без гашения отладки).
        #expect(файлов >= 100, "прочитано файлов \(файлов) — сторож смотрит не туда")
        #expect(литераловСКириллицей >= 2000,
                "кириллических литералов \(литераловСКириллицей) — разбор ослеп")
        #expect(нарушения.isEmpty, """
            Кириллический литерал склеен через «+» — это String мимо каталога, \
            человек увидит русский на всех языках. Одна фраза — один \
            String(localized:), ключ в каталог на пять языков:
            \(нарушения.joined(separator: "\n"))
            """)
    }
}
