@testable import Togo

/// Роль, выбранная владельцем, доезжает до второго человека.
///
/// # Чего стоил дефект
///
/// Замер 25.10.2026. `Permission` по всем девяти файлам
/// `TogoShared/Sync/` давал два вхождения, и **оба** — `publicPermission`,
/// то есть чужой API CloudKit; контроли при этом были живы (`FamilyRole`
/// вне `Sync` — семь файлов, код в `Sync` — девять). Прав в слое обмена
/// не было ни одного. Следствие: владелец зовёт маму «ухаживающей»
/// с правами «доза, правка 24 ч», мама открывает дневник
/// и **не может отметить дозу** — `рольБезОпознания(гость:)` отдавал
/// `.observer` безусловно.
///
/// # Почему запасной путь остаётся запасным, а не единственным
///
/// `.observer` при неузнанном человеке — верное решение, и оно
/// не снимается: мы не знаем, кто за телефоном. Менялось другое —
/// у него не было соперника. Теперь путей три, и порядок между ними
/// проверяется здесь:
///
/// ```
/// приехало назначение   сильнее всего — у ГОСТЯ. Его карточка это
///                       как раз то, чему верить нельзя
/// своя карточка         свой дневник: участников заводил сам хозяин
/// не опознали           наблюдатель у гостя, владелец у себя
/// ```
///
/// # Чего эти тесты НЕ проверяют, и это названо здесь
///
/// **Облака в них нет ни одного.** Приватная база CloudKit неизмерима
/// без личного iCloud Виктории — ни ключ ASC, ни токен GitHub её
/// не открывают, второго конца у связи нет. Проверено то, что вынесено
/// в чистые значения: формат, разбор, выбор назначения и применение.
/// Что поле на `CKShare` действительно сохраняется и действительно
/// приезжает на второй телефон — **не проверено ничем** и проверяется
/// только у неё на двух телефонах.
///
/// **Хранилище `НазначениеПоОбмену` тоже не покрыто, и нарочно.** Оно
/// повторяет `SharedZoneOwner` строка в строку и живёт в группе
/// приложений, то есть в состоянии, общем на весь прогон. Записать
/// в него из теста значило бы менять ответ соседей, которые зовут
/// `adoptMe(гость: true)` без явного назначения (`PermissionTests:212`),
/// — а набор идёт параллельно, и окна между записью и уборкой хватит.
/// Поэтому назначение здесь всюду передаётся **явно**.
@Suite("Роль из приглашения доезжает")
@MainActor
struct ПриехавшаяРольTests {

    /// Карточка, какой её заводит онбординг: владелец, со всеми правами.
    /// Ровно она и делала гостя владельцем чужого дневника.
    private func карточкаОнбординга() -> FamilyMember {
        FamilyMember(name: "Мама", role: .owner, isMe: true)
    }

    // MARK: Приёмка — приехала роль X, стали права Y

    /// **Первым — что проверять было ЧТО.**
    ///
    /// Без этой проверки всё, что ниже, прошло бы и на пустом
    /// множестве: «дозы нет» выполняется и когда назначение работает,
    /// и когда права не считаются вовсе.
    @Test("Контроль: у роли ухаживающего доза в пресете ЕСТЬ")
    func пресетУхаживающегоНеПуст() {
        #expect(FamilyRole.caregiver.defaultPermissions.contains(.giveDose), """
            пресет ухаживающего потерял право на дозу. Тогда всё, что \
            этот файл проверяет ниже, проверяет пустоту: «мама не может \
            отметить дозу» стало бы верным по другой причине.
            """)
        #expect(FamilyRole.observer.defaultPermissions.contains(.giveDose) == false,
                "наблюдатель дозу не отмечает — иначе различителя нет")
    }

    @Test("Приехала роль ухаживающего — доза разрешена")
    func приехалУхаживающий() {
        let права = FamilyResolver.права(
            среди: [], запомненный: nil, гость: true,
            назначение: НазначеннаяРоль(роль: .caregiver))

        #expect(права.contains(.giveDose), """
            мама с ролью «ухаживающая» не может отметить дозу — ровно \
            тот дефект, ради которого роль и поехала. Владелец назвал \
            права «доза, правка 24 ч», а второй телефон их не получил.
            """)
        #expect(права.contains(.logBasics), "и записывает бытовое")
        #expect(права.contains(.editRecords))
        #expect(права.contains(.seeMedical), "без схемы она не поймёт, что даёт")
    }

    /// **Отрицательный контроль к тесту выше, и он обязателен.**
    ///
    /// «Доза разрешена» выполняется и тогда, когда права перестали
    /// считаться вовсе и возвращают всё. Различает только пара:
    /// назначение есть — доза есть; назначения нет — дозы нет,
    /// и оба случая заданы явно в одном замере.
    @Test("Назначение не приехало — остаётся наблюдатель")
    func неПриехалоНичего() {
        let права = FamilyResolver.права(
            среди: [], запомненный: nil, гость: true, назначение: nil)

        #expect(!права.contains(.giveDose), """
            без приехавшей роли второй человек получил право на дозу. \
            Запасной путь обязан оставаться самым узким: мы не знаем, \
            кто за телефоном.
            """)
        #expect(!права.contains(.logBasics))
        #expect(права == FamilyRole.observer.defaultPermissions, """
            запасной путь перестал быть наблюдателем. Это не «меньше \
            прав» и не «больше» — это другой набор, и его надо назвать.
            """)
    }

    // MARK: Кто кого сильнее

    /// Тот самый дефект: карточка гостя — владельческая, и верить ей
    /// нельзя. До 25.10 она была единственным источником прав у того,
    /// кто себя опознал.
    @Test("Приехавшее сильнее своей карточки — у гостя")
    func приехавшееСильнееКарточки() {
        let моя = карточкаОнбординга()
        let права = FamilyResolver.права(
            среди: [моя], запомненный: моя.id, гость: true,
            назначение: НазначеннаяРоль(роль: .helper))

        #expect(!права.contains(.giveDose), """
            приехала роль помощника, а права взялись из карточки \
            онбординга — владельческой. Назначение владельца должно \
            быть сильнее того, что человек завёл себе сам.
            """)
        #expect(права.contains(.logBasics), "помощник пишет выходы и еду")
        #expect(права != FamilyRole.owner.defaultPermissions)
    }

    @Test("В СВОЁМ дневнике приехавшее не действует")
    func вСвоёмНеДействует() {
        let моя = карточкаОнбординга()
        let права = FamilyResolver.права(
            среди: [моя], запомненный: моя.id, гость: false,
            назначение: НазначеннаяРоль(роль: .observer))

        #expect(права.contains(.editTreatment), """
            чужой наряд отнял права в СОБСТВЕННОМ дневнике. Участники \
            здесь — карточки, которые завёл сам хозяин, и запереть его \
            в своём дневнике хуже исходного дефекта.
            """)
        #expect(права == Set(Permission.allCases))
    }

    @Test("Именные права сильнее пресета роли")
    func именныеСильнееПресета() {
        let права = FamilyResolver.права(
            среди: [], запомненный: nil, гость: true,
            назначение: НазначеннаяРоль(роль: .observer, права: [.logBasics]))

        #expect(права.contains(.logBasics), """
            владелец выдал право поимённо поверх роли, и оно не доехало. \
            Переключатели на «Семье» существуют ровно для этого случая: \
            мама по факту ухаживает за собакой больше всех.
            """)
        #expect(!права.contains(.seeMedical), """
            именной набор дополнили пресетом роли. Тогда снять право \
            руками было бы нельзя, а «мы всё сняли» и «мы ничего \
            не меняли» — разные состояния.
            """)
    }

    // MARK: Красная линия: потолок стоит и на приехавшем

    /// **Это главный тест файла.**
    ///
    /// Наряд едет по каналу, записи в который мы проверить не можем:
    /// приватная база CloudKit неизмерима. Значит приехать может что
    /// угодно, в том числе `.owner`. Потолок — единственное место, где
    /// `editTreatment` отнимается у второго телефона БЕЗ доверия
    /// приехавшему значению.
    ///
    /// > Условие снятия потолка до 25.10 было привязано к приезду роли
    /// > («когда поедет — снимается целиком»). В день приезда оно
    /// > поменяло бы знак из запрета в разрешение — и сделало бы это
    /// > в момент успеха, когда плохих новостей никто не ждёт.
    @Test("Приехал владелец — схему лечения он всё равно не правит")
    func потолокСтоитИНаПриехавшем() {
        let права = FamilyResolver.права(
            среди: [], запомненный: nil, гость: true,
            назначение: НазначеннаяРоль(роль: .owner))

        #expect(!права.contains(.editTreatment), """
            по обмену приехала роль владельца, и второй телефон получил \
            право менять схему лечения. Красная линия проекта: схему \
            меняет владелец, а запись потом читает врач. Наряд пишет \
            владелец — но ПРОВЕРИТЬ, что писал именно он, нам нечем.
            """)
        #expect(!права.contains(.manageFamily), """
            по обмену приехало право звать людей в чужой дневник. \
            Слой обмена это держит отдельно (FamilyShare:109), и показ \
            обязан совпадать с тем, что разрешено на деле.
            """)
        #expect(права.count == Permission.allCases.count - 2, """
            снято не два права, а другое число. Потолок обязан снимать \
            ровно editTreatment и manageFamily — и на приехавшем тоже.
            """)
    }

    // MARK: Чужая строка читается в узкую сторону

