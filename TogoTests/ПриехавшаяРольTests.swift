    // MARK: Правило ПРИМЕНЯЕТСЯ, а не просто существует

    /// **Все проверки выше зовут `FamilyResolver` сами — значит ни одна
    /// не заметит, если продукт перестанет передавать назначение.**
    ///
    /// Наш записанный класс: «вырезаны все шесть вызовов
    /// `rebuildDerived()` — набор остался зелёным. Сторож на ВЫЗОВ,
    /// а не на модель». Цена здесь та же, что у потолка: механизм без
    /// входа от рабочего не отличить ни тестом, ни компилятором.
    ///
    /// Ось — от объявления: входов в права два, и оба обязаны нести
    /// назначение. Комментарии вырезаются до разбора, иначе сторож
    /// померил бы прозу — имя `НазначениеПоОбмену` встречается
    /// в объяснениях обоих файлов.
    @Test("Оба входа в права НЕСУТ назначение, а не просто знают о нём")
    func обаВходаНесутНазначение() throws {
        let экраны = try безКомментариев(исходник("AppState.swift"))
        let голос = try безКомментариев(исходник("QuickLogIntents.swift"))

        #expect(экраны.contains("НазначениеПоОбмену"), """
            AppState больше не берёт приехавшее назначение — значит \
            на ЭКРАНАХ мама снова наблюдатель, какую бы роль ей \
            ни выбрали при приглашении.
            """)
        #expect(голос.contains("НазначениеПоОбмену"), """
            голос, кнопка «Действие» и виджет не несут назначение \
            в `FamilyResolver.права`. Одно правило снова живёт двумя \
            проверками и разойдётся в краю — ровно за это платили 23.09.
            """)

        // Контроль инструмента, в том же замере: без него обе проверки
        // прошли бы и на пустой строке, если разбор однажды вернёт
        // пустоту.
        #expect(экраны.contains("func adoptMe"), """
            разбор AppState.swift вернул текст без `func adoptMe` — \
            значит прочитан не тот файл или не прочитан вовсе, и всё, \
            что сказано выше, сказано про пустоту.
            """)
        #expect(голос.contains("FamilyResolver"), """
            разбор QuickLogIntents.swift вернул текст без `FamilyResolver` \
            — проверять было нечего.
            """)
    }

    // MARK: Применение в состоянии приложения

    @Test("Состояние приложения подхватывает приехавшую роль")
    func состояниеПодхватывает() {
        let state = AppState()
        state.myMemberID = nil
        state.adoptMe(from: [], гость: true,
                      назначение: НазначеннаяРоль(роль: .caregiver))

        #expect(state.role == .caregiver, """
            приехавшая роль не легла в состояние. Слово читает человек \
            («ты смотришь, отмечает мама»), и берётся оно из роли, \
            а не печатается рукой.
            """)
        #expect(state.can(.giveDose), """
            роль легла, а право на дозу не появилось — значит `permissions` \
            считает не от неё.
            """)
    }

    /// Порядок присвоения в `adoptMe` — часть смысла, а не вкус:
    /// у `role` есть `didSet`, гасящий `customPermissions`. Поставь
    /// права раньше роли — они стёрлись бы молча, и именные правки
    /// владельца пропали бы при живом на вид механизме.
    @Test("Именные права переживают присвоение роли")
    func именныеПереживаютРоль() {
