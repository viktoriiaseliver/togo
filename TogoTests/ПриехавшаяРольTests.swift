    // MARK: Разбор исходников

    private func исходник(_ имя: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        for каталог in ["Togo", "TogoShared"] {
            let папка = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.lastPathComponent == имя,
                      let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                return текст
            }
        }
        throw ОшибкаРазбора.исходникНеНайден(имя)
    }

    /// Построчно: `/* … */` не видит. Для предмета хватает — полный
    /// разбор Swift был бы второй реализацией компилятора.
    private func безКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    enum ОшибкаРазбора: Error { case исходникНеНайден(String) }
