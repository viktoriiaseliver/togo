    // MARK: Формат наряда

    @Test("Наряд переживает кодирование и разбор")
    func кодированиеКруговое() throws {
        let наряд = НарядРолей(
            поУчастникам: ["_a1b2": НазначеннаяРоль(роль: .caregiver)],
            новичкам: НазначеннаяРоль(роль: .helper, права: [.logBasics]))

        let строка = try #require(РолиВОбмене.закодировать(наряд),
                                  "наряд не закодировался вовсе")
        #expect(РолиВОбмене.разобрать(строка) == наряд)

        // Контроль инструмента: разбор, возвращающий что попало,
        // прошёл бы проверку выше, если бы кодирование вернуло то же
        // что попало. Заведомо негодная строка обязана дать nil.
        #expect(РолиВОбмене.разобрать("не json вовсе") == nil)
        #expect(РолиВОбмене.разобрать(nil) == nil)
    }

    @Test("Наряд новее нашего формата читается как отсутствующий")
    func нарядИзБудущего() throws {
        let будущий = НарядРолей(версия: РолиВОбмене.текущаяВерсия + 1,
                                 новичкам: НазначеннаяРоль(роль: .owner))
        let строка = try #require(РолиВОбмене.закодировать(будущий))

        #expect(РолиВОбмене.разобрать(строка) == nil, """
            наряд незнакомого формата разобран наполовину. Здесь \
            догадка стоит дозы: прочесть половину незнакомого значит \
            выдать права по тому, что случайно совпало.
            """)

        // Контроль в том же замере: тот же наряд текущей версии
        // разбирается. Без него «nil» читался бы как «разбор умер».
        let нынешний = НарядРолей(новичкам: НазначеннаяРоль(роль: .owner))
        let своя = try #require(РолиВОбмене.закодировать(нынешний))
        #expect(РолиВОбмене.разобрать(своя) != nil, """
            разбор вернул nil и на СВОЕЙ версии — значит предыдущая \
            проверка ничего не доказала: оба нуля вместе значат \
            «вопрос не тот».
            """)
    }

