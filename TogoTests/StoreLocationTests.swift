import Testing
import Foundation
import SwiftData
@testable import Togo

/// Хранилище открылось — но **то ли это хранилище**.
///
/// **Откуда вопрос.** 05.10.2026 togo-5a строил стенд на флаг
/// «дневник в памяти» и первой редакцией взял несуществующий путь
/// (`/dev/null/…`). Стенд дал неожиданное: контейнер **открылся**,
/// флаг остался `false`, то есть до ветки памяти дело не дошло вовсе.
/// Он назвал это «SwiftData такой путь отказом не считает и открывает
/// хранилище где-то ещё» — и починил стенд правами на каталог.
///
/// Для его теста это был шум. Для слоя хранилища — вопрос, которого
/// никто не задавал: **если негодный адрес не отказ, то по какому
/// адресу открылось?** Цена неверного ответа была бы выше всего, что
/// мы сегодня чинили: `AppRoot` показывает онбординг, когда собак ноль,
/// и человек с полным дневником увидел бы чистую установку, а записи
/// лежали бы целыми по другому адресу. Лестница отката такой случай
/// не ловит: она разбирает «не открылось», а здесь открылось.
///
/// **Замер 05.10 ответил, и его объяснение не подтвердилось.** Подмены
/// адреса нет ни на одном из трёх входов — `configurations.url` всегда
/// равен запрошенному, и в логе четыре раза «хранилище: локальное»,
/// ноль «не открылось»:
///
/// ```
/// каталога нет, но можно завести   открылось · адрес тот · каталог завела сама
/// /dev/null/… — завести нельзя     открылось · адрес ТОТ ЖЕ
/// каталог есть                     открылось · адрес тот · файл появился
/// ```
///
/// Значит «открывает где-то ещё» — не то, что происходит. Происходит
/// другое и меньшее: **`ModelContainer` открывается отложенно, и
/// негодный адрес отказом на открытии не становится.** Риск не «чужой
/// дневник», а «открылось, а записать не выйдет» — и эта половина уже
/// сторожится отдельно («persist отвечает „да“, когда хранилище
/// пишет»).
///
/// Набор оставлен, потому что проверяет он **адрес** — единственное,
/// о чём не спрашивал ни один сторож хранилища, — и потому что
/// утверждение «подмены нет» надо держать: его легко сломать правкой
/// лестницы отката, и тогда ни один другой тест не покраснеет.
@Suite("Хранилище открывается там, где просили")
struct StoreLocationTests {

    private func несуществующийПуть() -> URL {
        URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("togo-адрес-\(UUID().uuidString)")
            .appendingPathComponent("каталога-нет")
            .appendingPathComponent("Togo.store")
    }

    /// Либо отказ, либо тот самый адрес. Третьего быть не должно.
    ///
    /// Утверждение нарочно двустороннее: «открылось» и «не открылось» —
    /// оба законных исхода, и выбор между ними не наш. Незаконен ровно
    /// один: открылось **по другому адресу**, и приложение об этом
    /// молчит.
    @Test("Негодный адрес даёт отказ, а не чужое хранилище")
    func чужогоАдресаНеБывает() throws {
        let просили = несуществующийПуть()
        defer {
            try? FileManager.default.removeItem(
                at: просили.deletingLastPathComponent().deletingLastPathComponent())
        }

        let контейнер = Persistence.openContainer(storeURL: просили, allowCloud: false)

        guard let контейнер else {
            // Отказ — законный исход, и тогда лестница отката уже
            // проверена другими наборами. Здесь нечего добавить.
            #expect(Persistence.isEphemeral == false || Persistence.isEphemeral,
                    "ветка отказа разбирается в SchemaMigrationTests и EphemeralFlagTests")
            return
        }

        let адреса = контейнер.configurations.compactMap(\.url)
        #expect(!адреса.isEmpty, """
            контейнер открылся, а адреса у него нет вовсе — тогда
            непонятно, куда лягут записи, и это хуже отказа.
            """)
        #expect(адреса.allSatisfy { $0.standardizedFileURL == просили.standardizedFileURL }, """
            хранилище открылось НЕ ТАМ, где просили.
            просили: \(просили.path(percentEncoded: false))
            открылось: \(адреса.map { $0.path(percentEncoded: false) })

            Это не отказ, и лестница отката его не ловит: она разбирает
            «не открылось». `AppRoot` показывает онбординг, когда собак
            ноль, — человек с полным дневником увидел бы чистую
            установку и решил, что записей больше нет, а они лежали бы
            целыми по другому адресу.
            """)
    }

    /// Адрес, по которому каталог завести НЕЛЬЗЯ никогда.
    ///
    /// Отличается от предыдущего ровно одним: там каталога не было,
    /// но завести его можно, и SwiftData его заводит сама — замер
    /// показал «хранилище: локальное» и адрес ровно тот, что просили.
    /// Здесь каталог невозможен по устройству: `/dev/null` — символьное
    /// устройство, внутри него не бывает путей.
    ///
    /// Именно этот случай дал togo-5a неожиданное «контейнер открылся»,
    /// и его объяснение было «открывает хранилище где-то ещё».
    /// **Замер объяснение не подтвердил:** открылось, и адрес —
    /// запрошенный. То есть открытие отложенное, а не подменяющее.
    /// Для его стенда вывод тот же (этот путь отказом не считается),
    /// а механизм другой, и разница решает, что чинить: подмену адреса
    /// — нечем, её нет; отложенность — сторожем на запись, он есть.
    @Test("Невозможный адрес не подменяется другим")
    func невозможныйАдресНеПодменяется() throws {
        let просили = URL(fileURLWithPath: "/dev/null")
            .appendingPathComponent("каталога-быть-не-может")
            .appendingPathComponent("Togo.store")

        let контейнер = Persistence.openContainer(storeURL: просили, allowCloud: false)

        guard let контейнер else { return }  // Отказ — законный исход.

        let адреса = контейнер.configurations.compactMap(\.url)
        #expect(адреса.allSatisfy { $0.standardizedFileURL == просили.standardizedFileURL }, """
            контейнер открылся по ДРУГОМУ адресу: \(адреса.map(\.path)).
            Просили \(просили.path). Записи лягут не туда, где их будут
            искать, и человек увидит онбординг чистой установки.
            """)
    }

    /// И обратная половина: по хорошему адресу открывается именно он.
    ///
    /// **Проверка, что набору было что проверять.** Без неё тест выше
    /// зелен и при `openContainer`, который не открывает ничего никогда:
    /// отказ он считает законным исходом. Набор, которому нечего
    /// проверять, молчит так же, как набор, у которого всё хорошо.
    @Test("По годному адресу открывается именно он")
    func годныйАдресСоблюдается() throws {
        let папка = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("togo-адрес-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: папка, withIntermediateDirectories: true)
        let просили = папка.appendingPathComponent("Togo.store")
        defer { try? FileManager.default.removeItem(at: папка) }

        let контейнер = try #require(
            Persistence.openContainer(storeURL: просили, allowCloud: false),
            "по годному адресу хранилище обязано открыться — иначе проверять нечего")

        let адреса = контейнер.configurations.compactMap(\.url)
        #expect(адреса.allSatisfy { $0.standardizedFileURL == просили.standardizedFileURL },
                "просили \(просили.lastPathComponent), открылось \(адреса)")
        #expect(FileManager.default.fileExists(atPath: просили.path(percentEncoded: false)),
                "файл по запрошенному адресу не появился — значит записи лягут не сюда")
    }
}
