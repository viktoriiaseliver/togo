import Testing
import Foundation
@testable import Togo

/// Яркость, поднятая ради аптеки, возвращается при ЛЮБОМ уходе.
///
/// # Почему это сторож, а не кадр
///
/// Проверить кадром нельзя по устройству: в симуляторе
/// `UIScreen.brightness` — обычное свойство, подсветки нет, и поднятие
/// яркости **не меняет отрисованные пиксели**. Снимки до и после
/// совпадут, и «светлее не стало» было бы утверждением
/// о симуляторе, прозвучавшим как находка о продукте.
///
/// > **Физическую яркость мы измерить не можем.** Это не долг кода,
/// > а граница стенда, и она названа здесь, чтобы её не искали
/// > кадром второй раз.
///
/// Что проверяемо — **дороги возврата**. Их три, и выбраны они
/// нарочно:
///
/// ```
/// onDisappear             ушли с экрана, в том числе СВАЙПОМ
/// scenePhase != .active   свернули, позвонили, заблокировали
/// scenePhase == .active   вернулись — поднимаем снова
/// ```
///
/// **Кнопки «Закрыть» среди них нет, и это предмет сторожа.** Уход
/// кнопкой — один случай из четырёх; повесить возврат на него значило
/// бы починить одну дорогу из четырёх. Забытый возврат — молчаливый
/// расход батареи, который человек свяжет с чем угодно, кроме рецепта.
///
/// # Разбор режет комментарии, и это не перестраховка
///
/// В самом `ЯркостьЭкрана.swift` слова «Закрыть» и «onDisappear»
/// стоят **в прозе**: головной комментарий объясняет, почему кнопки
/// среди дорог нет. Сторож, не различающий код и объяснение,
/// покраснел бы на самом объяснении — у нас это уже случалось дважды.
@Suite("Возврат яркости висит на трёх дорогах")
struct ВозвратЯркостиTests {

    private static func исходник() throws -> String {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/DesignSystem/ЯркостьЭкрана.swift")
        return try String(contentsOf: url, encoding: .utf8)
    }

    private static func кодБезПрозы(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    @Test("Разбор состоялся: проза отделена от кода возврата яркости")
    func былоЧтоСторожить() throws {
        let весь = try Self.исходник()
        let код = Self.кодБезПрозы(весь)

        #expect(код.count > 300, """
            разбор дал \(код.count) знаков — файл не прочитан или \
            вырезание съело код целиком.
            """)
        // Контроль: «Закрыть» в прозе ЕСТЬ и обязано исчезнуть после
        // вырезания. Без контроля проверка «кнопки нет» прошла бы
        // и на сломанном разборе.
        #expect(весь.contains("Закрыть"), """
            в файле больше нет слова «Закрыть» даже в объяснении — \
            контроль пропал, и проверка ниже ничего не доказывает.
            """)
        #expect(!Self.кодБезПрозы(весь).contains("Закрыть"), """
            вырезание комментариев не работает: «Закрыть» выжило \
            в прозе. Значит сторож ниже мерит комментарий, а не код.
            """)
    }

    @Test("Возврат висит на уходе с экрана — в том числе свайпом")
    func возвратНаУходе() throws {
        let код = Self.кодБезПрозы(try Self.исходник())

        #expect(код.contains(".onDisappear"), """
            возврата яркости на `onDisappear` нет. Уход свайпом \
            (а не кнопкой) оставит экран на максимуме, и человек \
            свяжет расход батареи с чем угодно, кроме рецепта.
            """)
        #expect(код.contains("вернуть()"), "в коде нет самого возврата")
    }

    @Test("Возврат висит на сворачивании, и подъём — на возвращении")
    func возвратНаФазе() throws {
        let код = Self.кодБезПрозы(try Self.исходник())

        #expect(код.contains("onChange(of: фаза)"), """
            возврат не висит на смене фазы сцены: свернули, позвонили \
            или заблокировали — яркость осталась поднятой.
            """)
        #expect(код.contains("== .active"), """
            нет разбора `.active`: без него возврат из фона не поднимет \
            яркость обратно, пока экран рецепта всё ещё открыт.
            """)
    }

    /// Самое главное и самое хрупкое: дорог именно ТРИ.
    @Test("Дорог возврата три, и «Закрыть» среди них нет")
    func трогиДорогиИНиОднойКнопки() throws {
        let код = Self.кодБезПрозы(try Self.исходник())

        #expect(!код.contains("Закрыть"), """
            возврат яркости привязан к кнопке «Закрыть». Уход кнопкой — \
            один случай из четырёх: свайп, сворачивание и блокировка \
            оставят экран на максимуме.
            """)

        // Утвердительно и числом: «кнопки нет» выполнялось бы и в файле,
        // где нет вообще ничего.
        let дорог = [".onDisappear", "onChange(of: фаза)", "== .active"]
            .filter { код.contains($0) }.count
        #expect(дорог == 3, """
            дорог возврата \(дорог), а должно быть три: уход с экрана, \
            сворачивание и возвращение. Проверка «кнопки нет» без этого \
            счёта проходит и на пустом файле.
            """)
    }

    /// Исходная яркость сохраняется один раз — иначе возврат вернёт максимум.
    @Test("Исходная яркость сохраняется только когда ещё не сохраняли")
    func исходнаяСохраняетсяОдинРаз() throws {
        let код = Self.кодБезПрозы(try Self.исходник())

        #expect(код.contains("исходная == nil"), """
            `исходная` перезаписывается при каждом подъёме. Второй вызов \
            (возврат из фона, повторный `onAppear` у `fullScreenCover`) \
            сохранит ЕДИНИЦУ как исходную — и возврат вернёт максимум. \
            Экран не потускнеет никогда, а виноват будет не он.
            """)
    }
}
