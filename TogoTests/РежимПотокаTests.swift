import Testing
import Foundation
@testable import Togo

/// Режим онбординга не вычисляется из базы, в которую онбординг пишет.
///
/// **Повод измерен, а не предположен.** `OnboardingFlow` держал
/// `isReplay = !dogs.isEmpty && !просмотр`, а `advance()` на шаге
/// `.schedule` звал `saveDog()` → `context.insert(dog)`. `@Query dogs`
/// перестаёт быть пустым, `isReplay` переворачивается **посреди первого
/// прохода**, и `case .care` отдаёт `HowItWorksReplayEnd(onDone: finish)`.
/// Поток кончается на третьем шаге из шести: уход, семья и уведомления
/// недостижимы **по построению**, а не по медленности.
///
/// ```
/// 8257198  25.08 23:42  isReplay ЕСТЬ · saveDog на .schedule НЕТ · в .care НЕТ
/// a38c0a8  25.08 23:57  isReplay ЕСТЬ · saveDog ПОЯВИЛСЯ        · в .care НЕТ
/// 0653a4e  26.08 01:33  все три звена                            ← СЛОМАЛ
/// ```
///
/// Два звена прожили вместе час тридцать шесть **безвредно**: переворот
/// происходил, но у него не было читателя. Дефекту пятьдесят дней,
/// и он уехал во всех двенадцати сборках, какие существуют.
///
/// # Почему сторож стоит на исходнике, а не на поведении
///
/// Поведение проверяется только проходом **без обоих флагов запуска**
/// (`-UITesting` и `-Онбординг`), на стёртом симуляторе: под любым
/// из них `просмотр` истинно, `пишемВБазу` ложно, собака не вставляется
/// и дефект **невозможен по построению**. Поэтому ни один из тысячи
/// с лишним тестов его не ловил и не мог: все идут в режимах, где его нет.
///
/// > **Инструмент, сделанный чтобы показать, что видит новый человек,
/// > по построению не может показать именно то, чего новый человек
/// > не видит.** Кнопка «Посмотреть онбординг как новый» показывает
/// > шесть здоровых шагов; новый человек видит три.
///
/// Этот сторож держит **причину**, проход держит предмет. Нужны оба.
///
/// # Форма — от запрета, и ось НЕ на отсутствии строки
///
/// `dogs.isEmpty` остаётся в файле легально — в `режимСейчас`, которая
/// подставляет прежнее вычисление до первой отрисовки, чтобы
/// у перечитывающего не мигала подпись кнопки на `.welcome`. Поэтому
/// запрет ставится не на присутствие строки в файле, а на **то, что
/// читает именно `isReplay`**.
///
/// # Приёмка: правило прогнано на живых данных ДО того, как стало тестом
///
/// Восемь прогонов, здоровый и семь подделок. Каждая краснит ровно своё:
///
/// ```
/// ЗДОРОВЫЙ (вариант C)                            ЗЕЛЁН
/// А  прежний код                                  dogs в isReplay + вся заморозка
/// Б  убран .task                                  ТОЛЬКО «.task есть»
/// В  isReplay переименован                        «объявлений == 1» → 0
/// Г  в тело isReplay возвращено чтение базы        ТОЛЬКО «не читает dogs»
/// Д  флаг переименован                            флаг + ворота
/// Е  поле режим переименовано                     ТОЛЬКО «поле объявлено»
/// Ж  флаг объявлен, ворота его НЕ спрашивают       ТОЛЬКО «ворота спрашивают флаг»
/// ```
///
/// **Две редакции правила до этой были неверны, и обе — одним классом.**
/// Сперва объявление искалось подстрокой `"var isReplay"`, и подделка В
/// (`var isReplayOld`) прошла **зелёной**: подстрока нашлась в новом
/// имени. Починил — и ровно та же ошибка оказалась во второй проверке:
/// `собакаСохраненаXX` содержит `собакаСохранена`, подделка Д прошла
/// зелёной тоже.
///
/// > **Правило я знал и записал его в своде сам. Защитила не память,
/// > а прогон на живых данных.** Сравнение префиксом там, где нужно имя
/// > целиком, — наш известный класс (`struct SwatchRow` против
/// > `struct Swatch`, `Space.s16` против `Space.s1`), и я совершил его
/// > дважды в одном файле за десять минут.
///
/// Поэтому имена сверяются `\b…\b`, а не `contains`.
///
/// # Чего этот сторож НЕ видит
///
/// Он отвечает «режим заморожен и ворота спрашивают флаг», а не «три
/// шага открываются». Случай «заморозили, но не тем значением» — не его
/// класс: для него нужен проход, и у прохода два утверждения, второе
/// обязательно («собак в базе ровно одна»), иначе приёмка будет зелёной
/// на починке, вводящей дубль.
@Suite("Режим онбординга не вычисляется из базы, в которую поток пишет")
struct РежимПотокаTests {

    private static var исходник: String {
        get throws {
            let корень = URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent().deletingLastPathComponent()
            return try String(
                contentsOf: корень.appendingPathComponent(
                    "Togo/Features/Onboarding/OnboardingFlow.swift"),
                encoding: .utf8)
        }
    }

    /// Строки кода без комментариев: сторож, не различающий код и прозу,
    /// меряет прозу — а прямо над правкой стоит абзац, в котором прежнее
    /// выражение `!dogs.isEmpty && !просмотр` приведено как то, чего
    /// делать нельзя. Без вырезания комментариев этот сторож краснел бы
    /// на собственном объяснении.
    private static func код(_ текст: String) -> [String] {
        текст.components(separatedBy: "\n")
            .map { $0.components(separatedBy: "//")[0] }
    }

    /// Имя целиком, не подстрока. Причина — в шапке сюиты: на подстроке
    /// две подделки из семи прошли зелёными.
    private static func есть(_ образец: String, в текст: String) -> Bool {
        текст.range(of: образец, options: .regularExpression) != nil
    }

    @Test("isReplay не читает базу, и объявление ровно одно")
    func режимНеИзБазы() throws {
        let строки = Self.код(try Self.исходник)

        // Своё зрение первым. Файл, который перестали находить, молчит
        // так же, как чистый; и вырезание комментариев, съевшее весь
        // файл, тоже.
        #expect(строки.count > 150, """
            в OnboardingFlow.swift \(строки.count) строк кода — файл не тот
            или прочитан пустым.
            """)
        #expect(строки.contains { $0.contains("struct OnboardingFlow") }, """
            `OnboardingFlow` переименован или уехал из файла — сторож
            смотрит в пустоту.
            """)

        // Было ли что сторожить. Ноль нарушений при нуле найденных
        // объявлений значит «нечего было смотреть», а не «чисто».
        let объявления = строки.filter { Self.есть(#"\bvar\s+isReplay\s*:"#, в: $0) }
        #expect(объявления.count == 1, """
            объявлений `var isReplay:` найдено \(объявления.count), ожидалось 1.
            Ноль — предмет переименован и сторож смотрит не туда;
            больше одного — предмет размножился, и запрет ниже проверяет
            не все копии.
            """)

        // Нарушение — чтение базы в теле ИМЕННО `isReplay`.
        // Не «есть ли dogs в файле»: `режимСейчас` читает базу законно,
        // один раз, до заморозки.
        let тело = объявления.first ?? ""
        #expect(!объявления.isEmpty && !тело.contains("dogs"), """
            `isReplay` снова читает базу:

              \(тело.trimmingCharacters(in: .whitespaces))

            Режим потока не вычисляется из базы, в которую поток пишет.
            `saveDog()` на шаге `.schedule` вставляет собаку, `@Query dogs`
            перестаёт быть пустым, и режим переворачивается ПОСРЕДИ
            первого прохода: `case .care` уходит в «Это всё» с `finish`,
            а уход, семья и уведомления становятся недостижимы.

            Так было с 26.08.2026 (`0653a4e`) по 15.10.2026 — пятьдесят
            дней и все двенадцать сборок. Ни один тест этого не ловил
            и не мог: под `-UITesting` и под `-Онбординг` дефект
            невозможен по построению.

            Режим берётся у поля `режим`, поставленного один раз
            на входе в поток.
            """)
    }

    @Test("Заморозка существует: поле, место постановки и ворота записи")
    func заморозкаЕсть() throws {
        let строки = Self.код(try Self.исходник)
        let тело = строки.joined(separator: "\n")

        #expect(Self.есть(#"@State\s+private\s+var\s+режим\s*:"#, в: тело), """
            поля `режим` больше нет. Значит режим снова откуда-то
            вычисляется, а не запоминается на входе.
            """)

        // Поле без того, кто его ставит, — это «механизм без входа»:
        // от рабочего он не отличается ни тестом, ни компилятором,
        // потому что `режимСейчас` подставляет прежнее вычисление
        // и поток ведёт себя ровно как до починки. Молча.
        #expect(Self.есть(#"\.task\s*\{"#, в: тело), """
            поле `режим` объявлено, а ставить его некому: `.task` в теле
            больше нет. `режимСейчас` подставляет прежнее вычисление
            из базы до первой отрисовки — значит без этой строки
            заморозки не наступает НИКОГДА, и дефект возвращается
            целиком, при зелёном первом тесте этой сюиты.
            """)

        // Защита от второй собаки названа своим именем, а не унаследована
        // от побочного эффекта.
        let флаг = тело.ranges(of: #"\bсобакаСохранена\b"#)
        #expect(флаг.count >= 2, """
            флаг `собакаСохранена` встречается \(флаг.count) раз,
            ожидалось не меньше двух (объявление и чтение).

            До заморозки режима от второй собаки защищал побочный эффект:
            после `saveDog()` база перестаёт быть пустой, `пишемВБазу`
            становится ложным, и повторный проход через `.schedule`
            («Назад» на карточку собаки, потом снова вперёд) второй раз
            не писал. Заморозка эту защиту снимает. Без явного флага
            дубль собаки родится молча — и увидим мы его не здесь,
            а на экране «Семья», первой карточкой (`DuplicateDogCard`).
            """)

        // **Самая дорогая проверка сюиты, и единственная, которой
        // в первой редакции не было.** Объявленный флаг, который никто
        // не спрашивает, — это та же мина, только под зелёным сторожем:
        // подделка «убрать `!собакаСохранена` из условия» проходила
        // зелёной, пока ось стояла на наличии флага, а не на воротах.
        let ворота = строки.filter { Self.есть(#"step\s*==\s*\.schedule"#, в: $0) }
        #expect(ворота.count == 1, """
            строк с `step == .schedule` найдено \(ворота.count), ожидалась 1.
            Ворота записи собаки либо уехали, либо размножились — во втором
            случае проверка ниже смотрит не на все.
            """)
        #expect(!ворота.isEmpty && Self.есть(#"\bсобакаСохранена\b"#, в: ворота[0]), """
            ворота записи собаки не спрашивают флаг:

              \(ворота.first?.trimmingCharacters(in: .whitespaces) ?? "—")

            Флаг объявлен и не читается там, где он единственно нужен.
            Человек, вернувшийся «Назад» на карточку собаки и пошедший
            вперёд снова, получит ВТОРУЮ собаку — молча, при зелёном
            наборе.
            """)
    }
}
