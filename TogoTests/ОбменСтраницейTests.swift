/// Приём чужой страницы — ОДНИМ контекстом от начала до конца.
///
/// **Замер чтением 29.10.2026.** Каждый `SharedDiaryInbox.accept` звал
/// `save()` сам: страница движка в сотни записей — сотни сохранений
/// на главном потоке подряд, каждое со своим `didSave` и перерисовкой
/// всех `@Query`. Экран стоял, пока шла пачка. Сколько именно стоял
/// на живом телефоне — **НЕ ИЗМЕРЕНО**: стенда с двумя iCloud нет.
///
/// # Почему страница живёт в своём контексте, а не в главном
///
/// Партия 29.10 убрала сотню сохранений, но честность отказа оставила
/// на откатах: каждый `accept` клал замыкание «вернуть как было»,
/// и при неудаче они прокручивались назад. Форма держится для правки
/// поля и **не держится для вставки** — замер того же дня, запертое
/// хранилище, одна вставка, пять форм:
///
/// ```
/// [А] delete сразу после упавшего save    остался 1
/// [Б] fetch МЕЖДУ упавшим save и delete   стало 0 — работает
/// [В] rollback внутри otherwise           остался 1, hasChanges=false
/// [Г] rollback после возврата persist     остался 1, hasChanges=false
/// [Д] fetch сразу после упавшего save     отдал ОДНУ вставку ДВАЖДЫ
/// ```
///
/// Решение Виктории — **путь 1 и целиком**: вся страница живёт в одном
/// контексте от начала до конца, не записалась — контекст выброшен,
/// и в главном её не было вовсе. Четыре сторожа ниже — её условия,
/// и каждый держит свою половину: отказ, успех, лекарства, «вне
/// страницы как раньше».
///
/// > **Четвёртое условие тем же решением осталось НЕЗАКРЫТЫМ:**
/// > «после сборки — проверка на двух телефонах, отменить курс
/// > на одном и убедиться, что на втором пропали и напоминания,
/// > и сама доза в плане». Эти тесты отвечают про ОДИН контекст,
/// > а дефект живёт между двумя телефонами, и приватная база CloudKit
/// > неизмерима ни ключом ASC, ни токеном GitHub.
@Suite("Обмен · страница одним сохранением", .serialized)
@MainActor
struct ОбменСтраницейTests {

    private func клиника(_ id: UUID = UUID(), имя: String = "Vet Riviera",
                         телефон: String? = nil, когда: Date) -> ClinicPayload {
        ClinicPayload(id: id, name: имя, detail: nil, isLab: false,
                      phone: телефон, createdAt: когда, changedAt: когда)
    }

    /// Мерило — `hasChanges` контекста САМОЙ страницы после каждой
    /// записи, а не счёт `didSave`: уведомление ловили бы и соседние
    /// наборы, идущие параллельно, а несохранённое изменение видно
    /// только у своего контекста.
    @Test("Страница из трёх записей сохраняется ОДИН раз, в конце")
    func одноСохранение() throws {
        let главный = try НеЗаписывающееХранилище.рабочийКонтекст()
        let когда = Date()
        var несохранённоПосле: [Bool] = []

        let страница = SharedDiaryInbox.партией(контейнер: главный.container) { приём in
            for имя in ["Vet Riviera", "Clinique du Port", "Labo Azur"] {
                SharedDiaryInbox.accept(клиника(имя: имя, когда: когда), context: приём)
                несохранённоПосле.append(приём.hasChanges)
            }
        }

        #expect(несохранённоПосле == [true, true, true], """
            внутри страницы запись сохранилась сама: \(несохранённоПосле). \
            Сохранение на запись — это и есть замерзающий экран \
            на догоняющей странице в сотни записей.
            """)
        #expect(страница.записано)
        #expect(try главный.fetch(FetchDescriptor<Clinic>()).count == 3,
                "страница не сохранилась в конце")
        #expect(!главный.hasChanges, """
            главный контекст оказался грязным — страница писала в него, \
            а не в свой.
            """)
    }

    /// Контроль: вне страницы приём пишет сразу, как писал всегда —
    /// его зовут архив и тесты, и ждать конца страницы им не у кого.
    ///
    /// **Четвёртый сторож решения 29.10.** Он держит дорогу, которую
    /// легче всего закрыть заодно: различитель внутри `записать` —
    /// тождество контекста, и стоит ему стать флагом «страница
    /// открыта», как всякий сосед, зовущий `accept` со своим
    /// контекстом, получит молчаливое «записано» без сохранения.
    @Test("Вне партии приём записывает сразу")
    func внеПартииСразу() {
        let context = ModelContext(Persistence.container())
        SharedDiaryInbox.accept(клиника(когда: Date()), context: context)
        #expect(!context.hasChanges, "вне партии запись осталась несохранённой")
    }

    /// **Первый сторож решения 29.10: отказ.**
    ///
    /// В главном контексте не должно оказаться ни вставки, ни слияния.
    /// Раньше это держалось на откатах и для вставки не держалось
    /// вовсе; теперь держится тем, что главный контекст страницы
    /// не видел — его в неё не передают.
    @Test("Не записалась страница — возвращено всё, что она тронула")
    func откатВсейСтраницы() throws {
        let старая = UUID()
        let давно = Date(timeIntervalSince1970: 1_000_000)
        let context = try НеЗаписывающееХранилище.контекст { пишущий in
            let своя = Clinic(name: "Vet Riviera")
            своя.id = старая
            своя.createdAt = давно
            своя.changedAt = давно
            пишущий.insert(своя)
        }

        // Объект загружен в главный контекст ДО страницы и держится
        // ссылкой всё время, пока она идёт: «в хранилище не попало»
        // и «в памяти не изменилось» — два разных утверждения,
        // и экран читает второе.
        let загруженаДо = try #require(
            context.fetch(FetchDescriptor<Clinic>()).first { $0.id == старая })

        let позже = давно.addingTimeInterval(3600)
        let страница = SharedDiaryInbox.партией(контейнер: context.container) { приём in
            // Слияние: чужая правка позже — телефон бы переписался.
            SharedDiaryInbox.accept(клиника(старая, телефон: "+33 4 93 00 00 00", когда: позже),
                                    context: приём)
            // И вставка новой.
            SharedDiaryInbox.accept(клиника(имя: "Labo Azur", когда: позже), context: приём)
        }

        #expect(страница.записано == false, "запертое хранилище обязано ответить «нет»")
        #expect(страница.большеНеЖдут.isEmpty, """
            страница не записалась, а гасить что-то всё равно решила: \
            \(страница.большеНеЖдут). Решение принято по тому, \
            что не доехало.
            """)

        let клиники = try context.fetch(FetchDescriptor<Clinic>())
        #expect(клиники.count == 1, """
            вставка из несохранившейся страницы осталась в контексте: \
            \(клиники.map(\.name)). Экран показал бы запись, которой \
            в хранилище нет.
            """)

        // Предмет берётся ПО ID, а не `.first`: у `fetch` без `sortBy`
        // порядка нет, и когда откат вставки отказывал, `.first`
        // отдавал «Labo Azur» — запись с чужими полями. Два ожидания
        // про слияние читали тогда НЕ ТУ клинику и отвечали про неё:
        // `phone == nil` проходило (у вставки телефона и не было),
        // `changedAt` падало. Один дефект выглядел тремя, и ни одно
        // из трёх сообщений не называло его.
        let своя = клиники.first { $0.id == старая }
        #expect(своя != nil, "своя клиника пропала из контекста целиком")
        #expect(своя?.phone == nil, "слияние из несохранившейся страницы не возвращено")
        #expect(своя?.changedAt == давно, """
            `changedAt` остался чужим: \(своя?.changedAt.description ?? "—") \
            при \(давно). Страница шла в свой контекст — главного она \
            трогать не могла.
            """)
        #expect(загруженаДо.phone == nil, """
            объект, загруженный ДО страницы, получил чужой телефон \
            в памяти: \(загруженаДо.phone ?? "—"). В хранилище его нет, \
            а на экране он есть — ровно то расхождение, от которого \
            заведён весь этот слой.
            """)
    }

    /// **Второй сторож решения 29.10: успех.**
    ///
    /// Страница записалась — главный контекст обязан увидеть её сразу,
    /// **в том числе у объекта, загруженного ДО неё**. Это цена пути 1
    /// и единственное, что он мог сломать: до него приём шёл прямо
    /// в главный контекст, и вопроса «увидит ли» не было вовсе.
    /// В `FamilySync` про это стояло отдельной строкой — «главный
    /// контекст, а не свой новый на каждый вызов: чужая запись должна
    /// появиться на экране сразу».
    ///
    /// Загруженный заранее объект — не придирка: `fetch` сходит
    /// в хранилище и принесёт новое, а вот у объекта, который главный
    /// контекст уже держит, значения лежат в памяти. Именно его держат
    /// открытые экраны.
    @Test("Записалась страница — главный контекст видит её сразу, и у загруженного ДО")
    func успехВиденГлавному() throws {
        let главный = try НеЗаписывающееХранилище.рабочийКонтекст()
        let старая = UUID()
        let давно = Date(timeIntervalSince1970: 1_000_000)
        let своя = Clinic(name: "Vet Riviera")
        своя.id = старая
        своя.createdAt = давно
        своя.changedAt = давно
        главный.insert(своя)
        try главный.save()

        let загруженаДо = try #require(
            главный.fetch(FetchDescriptor<Clinic>()).first { $0.id == старая })
        #expect(загруженаДо.phone == nil, "контроль: до страницы телефона нет")

        let позже = давно.addingTimeInterval(3600)
        let страница = SharedDiaryInbox.партией(контейнер: главный.container) { приём in
            SharedDiaryInbox.accept(клиника(старая, телефон: "+33 4 93 00 00 00", когда: позже),
                                    context: приём)
            SharedDiaryInbox.accept(клиника(имя: "Labo Azur", когда: позже), context: приём)
        }

        #expect(страница.записано, "страница в рабочем хранилище обязана записаться")

        let клиники = try главный.fetch(FetchDescriptor<Clinic>())
        #expect(клиники.count == 2, """
            главный контекст не видит вставку из записанной страницы: \
            \(клиники.map(\.name)). Чужая запись доехала до хранилища, \
            а на экране её нет.
            """)
        #expect(загруженаДо.phone == "+33 4 93 00 00 00", """
            объект, загруженный ДО страницы, остался со старым телефоном: \
            \(загруженаДо.phone ?? "—"). Запись в хранилище новая, \
            а открытый экран держит прежнюю — расхождение то же самое, \
            только в другую сторону.
            """)
    }

    /// **Третий сторож решения 29.10: лекарства.**
    ///
    /// Отмена или пауза схемы, приехавшая страницей, гасит напоминания
    /// по её дозам **тем же проходом** — не когда человек откроет
    /// приложение.
    ///
    /// Цена пропуска называется прямо, потому что она про лекарство:
    /// Виктория отменила курс, у мамы он жив, и мама получает «Через
    /// 10 минут доза» по лечению, которого больше нет.
    ///
    /// **Решение принимается ВНУТРИ страницы и до сохранения**, и это
    /// условие Виктории дословно: спрошенный в главном контексте,
    /// он ответил бы по прежней картине — отменённый курс выглядел бы
    /// живым. Поэтому список приходит из самой страницы
    /// (`ИтогСтраницы.большеНеЖдут`), а не собирается вызывающим.
    ///
    /// Контроль стоит ПЕРВЫМ и в том же замере: страница с живой схемой
    /// не гасит ничего. Без него «погасло» читалось бы как «гасит
    /// всегда», и сторож зеленел бы на коде, который снимает
    /// напоминания у живого курса.
    @Test("Отмена схемы страницей гасит напоминания по её дозам тем же проходом")
    func отменаСхемыГаситДозы() throws {
        let главный = try НеЗаписывающееХранилище.рабочийКонтекст()
        let когда = Date()
        let (_, схема) = НеЗаписывающееХранилище.собакаСоСхемой(in: главный, время: когда)
        let доза = DoseRecord(scheduledAt: когда)
        доза.medication = схема
        главный.insert(доза)
        try главный.save()
        #expect(доза.ждётОтметкиСУчётомСхемы, "контроль: до страницы доза ждёт отметки")

        // Контроль: та же схема, живая, только с поздней правкой.
        var живая = схема.payload
        живая.changedAt = когда.addingTimeInterval(30)
        let безОтмены = SharedDiaryInbox.партией(контейнер: главный.container) { приём in
            SharedDiaryInbox.accept(живая,
                                    dog: SharedDiaryInbox.dog(forDogID: живая.dogID, context: приём),
                                    context: приём)
        }
        #expect(безОтмены.записано)
        #expect(безОтмены.большеНеЖдут.isEmpty, """
            страница с ЖИВОЙ схемой погасила напоминания: \
            \(безОтмены.большеНеЖдут). Человек перестанет получать \
            запросы по курсу, который идёт.
            """)

        // Предмет: та же схема, поставленная на паузу.
        var отменённая = схема.payload
        отменённая.isPaused = true
        отменённая.changedAt = когда.addingTimeInterval(60)
        let страница = SharedDiaryInbox.партией(контейнер: главный.container) { приём in
            SharedDiaryInbox.accept(отменённая,
                                    dog: SharedDiaryInbox.dog(forDogID: отменённая.dogID,
                                                              context: приём),
                                    context: приём)
        }

        #expect(страница.записано)
        #expect(страница.большеНеЖдут == [доза.id], """
            отмена схемы приехала, а гасить решили \
            \(страница.большеНеЖдут.count) доз вместо одной. Запись \
            о дозе приезжает отдельным типом и могла не приехать вовсе — \
            ветка схемы единственная, кто про эти дозы говорит.
            """)
    }
}

/// iCloud просит подождать — это не «нет сети» и не поломка.
@Suite("Обмен · просьба iCloud подождать")
@MainActor
struct ПросьбаПодождатьTests {

    private func отказ(_ код: CKError.Code, через секунд: Double? = nil) -> Error {
        var сведения: [String: Any] = [:]
        if let секунд { сведения[CKErrorRetryAfterKey] = NSNumber(value: секунд) }
        return NSError(domain: CKErrorDomain, code: код.rawValue, userInfo: сведения)
    }

    @Test("Три кода — просьба подождать, со сроком из самого отказа")
    func коды() {
        #expect(FamilySync.просьбаПодождать([отказ(.requestRateLimited, через: 90)]) == 90)
        #expect(FamilySync.просьбаПодождать([отказ(.zoneBusy, через: 5)]) == 5)
        #expect(FamilySync.просьбаПодождать([отказ(.serviceUnavailable)]) == 0,
                "просьба без срока — ноль, а не выдуманный срок")
    }

    @Test("Обрыв сети и чужой отказ — не просьба подождать")
    func неПросьба() {
        #expect(FamilySync.просьбаПодождать([отказ(.networkFailure)]) == nil)
        #expect(FamilySync.просьбаПодождать([NSError(domain: "мой.домен", code: 7)]) == nil)
        #expect(FamilySync.просьбаПодождать([]) == nil)
    }

    /// `fetchChanges` отдаёт составной отказ, а срок лежит по записям.
    @Test("Из составного отказа берётся больший срок")
    func составной() {
        let составной = NSError(
            domain: CKErrorDomain, code: CKError.Code.partialFailure.rawValue,
            userInfo: [CKPartialErrorsByItemIDKey: [
                "а": отказ(.zoneBusy, через: 30),
                "б": отказ(.requestRateLimited, через: 300),
                "в": отказ(.unknownItem),
            ] as [AnyHashable: Error]])
        #expect(FamilySync.просьбаПодождать([составной]) == 300, """
            раньше большего срока не пустят никого — меньший обещал бы \
            человеку повтор, который снова упрётся в ту же просьбу
            """)
    }

    @Test("Человек читает «подождать», а не английский текст CloudKit")
    func текст() {
        guard case .failed(let текст) = FamilySync.состояние(
            послеОтказов: [отказ(.requestRateLimited, через: 90)], lastSync: nil) else {
            Issue.record("просьба подождать не стала видимым состоянием")
            return
        }
        #expect(текст.contains("подождать"), "«\(текст)»")
        #expect(текст.contains("2"), "90 секунд — это «через 2 мин», вверх: «\(текст)»")
    }

    @Test("Минуты — вверх и не меньше одной")
    func минуты() {
        #expect(FamilySync.текстПаузы(секунд: 1).contains("1"))
        #expect(FamilySync.текстПаузы(секунд: 61).contains("2"))
        #expect(FamilySync.текстПаузы(секунд: 0) != FamilySync.текстПаузы(секунд: 60),
                "«срока не назвали» и «одна минута» — разные ответы")
    }
}
