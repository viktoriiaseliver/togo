@testable import Togo

/// Всё, что рисуется на подложке плаката, обязано на ней читаться.
///
/// **Вопрос здесь шире, чем в `ThemeContrastTests`, и это главное
/// в файле.** Там девятнадцать пар перечислены руками, и пары плаката
/// среди них есть: `labelOnDose` на `backgroundDose`, `captionOnColor`
/// на `backgroundAlarm` и так далее. Все они верны, набор зелёный
/// и прав — **он меряет компонент, который починили, и ничего не знает
/// про соседа на той же подложке.**
///
/// Соседом оказалась шапка экрана. `TGPoster` берёт её как `trailing`
/// и прямо пишет: «она на цветном, а не над ним», — а `TodayHeader`
/// спрашивал нейтральные `Token.Ink.primary` / `Ink.secondary`.
/// Замер трёх её текстов по пяти режимам и четырём темам: **16 клеток
/// из 20 ниже порога**, и худшее не там, где заметили:
///
/// ```
///                            dark    light   darkHC  lightHC
/// кличка на дозе             1,64 ✗  1,47 ✗  1,64 ✗  1,47 ✗
/// вес и дата на обычном      5,31    1,10 ✗  6,73    1,53 ✗
/// вес и дата на натощак      5,18    1,23 ✗  6,56    1,71 ✗
/// вес и дата на тревоге      5,39    1,18 ✗  6,84    1,64 ✗
/// вес и дата на дозе         1,17 ✗  1,94 ✗  1,08 ✗  1,40 ✗
/// всё на тихом               8,35    5,65   10,58    7,85   ← чисто
/// ```
///
/// Чисто ровно на `backgroundQuiet` — там, где `Tokens.generated.swift:155`
/// нейтральные чернила и разрешает: «ТОЛЬКО НЕЙТРАЛЬНЫЙ БЛОК». То есть
/// матрица не нашла нового правила, она показала, где записанное
/// нарушено.
///
/// **Почему это не лежало год.** Ключ `UIUserInterfaceStyle=Dark` снят
/// `052c562`; до него колонок `light` и `lightHC` на устройстве
/// не существовало вовсе. Восемь клеток из шестнадцати родились вместе
/// со светлой темой и в руках у людей не были ни разу — это проявка,
/// а не регрессия: поверхность попала под измерение и отдала то, что
/// в ней было с момента включения темы.
///
/// **Форма вопроса — от запрета.** Не «шапка красится правильно»
/// (требование: у правильного десять форм, и проверить его надёжно
/// нельзя), а «на подложке плаката не стоит ни один цвет ниже порога»
/// и «в шапке не осталось ни одного нейтрального `Ink`». Запрет
/// узнаётся по своему корню и потому проверяется надёжно.
///
/// **Граница, названная вслух.** Это замер ЗНАЧЕНИЙ, разрешённых
/// системой, а не пикселя. Кадром подтверждена **одна клетка
/// из двадцати** — доза в тёмной теме, живой кадр дал 1,76 / 1,22 / 1,23
/// против арифметических 1,64 / 1,17 / 1,17. Расхождение на уровне
/// джипега и направление одно, то есть арифметике можно верить, —
/// но это основание доверять счёту, а **не доказательство, что
/// остальные девятнадцать клеток выглядят так же**. «Значение верное,
/// вызов бессильный» здесь не ловится: приёмка — кадр, и снимает его
/// не автор.
@MainActor
@Suite("Чернила на плакате")
struct ПлакатЧерниламиTests {

    /// Роль, цвет которой спрашивают у `PosterPaint`, и её порог.
    ///
    /// Порог у роли, а не у вкуса: текст — 4,5 (WCAG 1.4.3), графика
    /// и крупный текст — 3,0 (1.4.11). Косточка и тонкие полосы —
    /// графика, и потому у них три.
    struct Роль: Sendable {
        let имя: String
        let порог: Double
        let цвет: @Sendable (PosterMode) -> Color
    }

    /// Роли, которые на экране ВИДНЫ, — только они под порогом.
    static let роли: [Роль] = [
        .init(имя: "заголовок", порог: 4.5, цвет: { PosterPaint.label($0) }),
        .init(имя: "подпись", порог: 4.5, цвет: { PosterPaint.caption($0) }),
    ]

    /// Роль, которую мерим и НЕ судим, потому что её никто не рисует.
    ///
    /// Косточка (`TGPoster.bone`) — единственный потребитель
    /// `PosterPaint.bar`, и единственный живой вызов плаката передаёт
    /// `progress: nil` (`TodayScreen.swift:653`). Замер по ней даёт
    /// шесть клеток ниже 3,0 — и это **не находка о продукте**:
    /// у этих значений нет дороги на экран, а у трети из них ещё
    /// и `opacity(0.25)` сверху, которого счёт не видит.
    ///
    /// > **Девять ложных находок хуже одной пропущенной: после них
    /// > сторожа перестают читать.**
    ///
    /// Числа печатаются, чтобы не пропасть, а условие, при котором
    /// роль обязана переехать под порог, сторожит
    /// `косточкуНиктоНеРисует()`.
    static let мерим: [Роль] = [
        .init(имя: "косточка и полосы", порог: 3.0, цвет: { PosterPaint.bar($0) }),
    ]

    // MARK: Вопрос

    @Test("Ни один цвет на подложке плаката не ниже порога — все режимы × все темы")
    func всёНаПодложкеЧитается() throws {
        var провалы: [String] = []
        var замеры: [String] = []
        var осмотрено = 0

        for режим in PosterMode.allCases {
            let подложка = PosterPaint.background(режим)
            for роль in Self.роли + Self.мерим {
                for тема in ThemeContrastTests.режимы {
                    осмотрено += 1
                    let k = ThemeContrastTests.контраст(роль.цвет(режим),
                                                        на: подложка, режим: тема)
                    let ключ = "\(роль.имя) на «\(режим.rawValue)» · \(тема.имя)"
                    let судим = Self.роли.contains { $0.имя == роль.имя }
                    замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) "
                                  + "\(ключ)\(судим ? "" : "   · не на экране, не судим")")
                    if судим, k < роль.порог {
                        провалы.append("  \(ключ): \(Self.два(k)) при пороге \(Self.два(роль.порог))")
                    }
                }
            }
        }

        // Набору, которому нечего проверять, молчать так же легко,
        // как набору, у которого всё хорошо. Пять режимов × три роли ×
        // четыре темы: число стоит здесь, чтобы шестой режим,
        // добавленный без цвета, не прошёл молча.
        let всехРолей = Self.роли.count + Self.мерим.count
        let ожидалось = PosterMode.allCases.count * всехРолей * ThemeContrastTests.режимы.count
        #expect(осмотрено == ожидалось, """
            осмотрено \(осмотрено) из \(ожидалось) клеток.
            Режимов \(PosterMode.allCases.count), ролей \(всехРолей), тем \(ThemeContrastTests.режимы.count).
            """)

        #expect(провалы.isEmpty, """
            на подложке плаката \(провалы.count) клеток ниже порога:

            \(провалы.joined(separator: "\n"))

            Порог у роли, а не у вкуса. Правку порога починкой считать
            нельзя: число, поднятое под дефект, становится дырой ровно
            того размера.
            """)

        print("""
            ЗАМЕР, \(осмотрено) клеток (режим × роль × тема):

            \(замеры.joined(separator: "\n"))

            ГРАНИЦА: мерены ЗНАЧЕНИЯ, разрешённые системой, а не пиксель.
            Кадром подтверждена ОДНА клетка из \(осмотрено) — доза в тёмной.
            Ноль провалов значит «эти \(осмотрено) клеток целы», а не
            «шапка читается»: `opacity`, перекрытие стилем и всё, чего
            нет в списке ролей, этот счёт не видит.
            """)
    }

    // MARK: Условие, при котором исключение перестанет быть верным

    /// Косточку плаката не рисует ни один живой экран.
    ///
    /// **Это сторож на ПРИЧИНУ исключения, а не на само исключение.**
    /// `PosterPaint.bar` даёт шесть клеток ниже порога 3,0 в светлых
    /// темах, и под порог я их не поставил — потому что у них нет
    /// дороги на экран:
    ///
    /// ```
    /// TodayScreen.swift:653     progress: nil          ← живой экран
    /// PosterGallery.swift       progress: 0.4 … 1      ← #if DEBUG, отладка
    /// ```
    ///
    /// Объявить исключение и записать условие его смерти — разные
    /// действия, и второго у нас не делают почти никогда. Условие
    /// здесь: как только роль появится на живом экране, этот тест
    /// покраснеет и скажет, что перемерить.
    ///
    /// Исключение по ИМЕНИ ФАЙЛА, а не «везде»: галерея отладочная
    /// и несёт настоящие значения нарочно, а файловое исключение
    /// на `Togo/Features/` закрыло бы ровно то, что сторожим.
    ///
    /// # ОСЬ ПЕРЕВЕДЕНА 23.10.2026: СМОТРЕТЬ НАДО ШИРЕ, ЧЕМ `Features`
    ///
    /// Редизайн «Кино» снял плакат со всех экранов, и сторож покраснел
    /// на собственном зрении: «в `Togo/Features` не нашлось ни одного
    /// `TGPoster(` при 79 прочитанных файлах». Он был прав — смотрел
    /// в пустоту.
    ///
    /// ```
    /// замер 23.10.2026, обход всего Togo/
    /// TGPoster( всего            4   PosterGallery.swift, #if DEBUG
    /// из них ВНЕ галереи         0   живых экранов с плакатом НЕТ
    /// косточка на живом          0
    /// ```
    ///
    /// **Исключение не умерло — оно окрепло.** Раньше основанием было
    /// «единственный живой вызов передаёт `progress: nil`», теперь —
    /// «живых вызовов нет вовсе». Косточку по-прежнему не рисует никто,
    /// и шесть клеток `PosterPaint.bar` ниже 3,0 судить по-прежнему
    /// незачем.
    ///
    /// Переведено ровно одно: **где искать**. Обход идёт по всему
    /// `Togo/`, а не по `Togo/Features` — иначе зрение сторожа умирает
    /// вместе с предметом и он не может отличить «плаката нет»
    /// от «каталог не найден».
    ///
    /// > **Зрение и предмет разведены по разным числам.** `TGPoster(`
    /// > всего — это проверка, что разбор видит вызовы вообще (их
    /// > четыре, в галерее); вызовы вне галереи — предмет. Обнулись
    /// > они разом — значит сломан разбор, а не починен экран,
    /// > и несовместимость видна БЕЗ знания причины.
    @Test("Косточку плаката не рисует ни один живой экран")
    func косточкуНиктоНеРисует() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let живые = корень.appendingPathComponent("Togo")

        /// Отладочная галерея: несёт настоящие значения нарочно,
        /// вся под `#if DEBUG`, человеку не показывается.
        let отладочная = "PosterGallery.swift"

        var найдено: [String] = []
        var осмотрено = 0
        var вызовов = 0
        var живыхВызовов = 0
        let обход = FileManager.default.enumerator(at: живые, includingPropertiesForKeys: nil)
        while let url = обход?.nextObject() as? URL {
            guard url.pathExtension == "swift" else { continue }
            guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
            осмотрено += 1
            let код = текст.components(separatedBy: "\n")
                .map { $0.components(separatedBy: "//")[0] }

            // **Считается АРГУМЕНТ вызова, а не слово.**
            //
            // Первая редакция искала `progress:` по всему каталогу
            // и покраснела на `OnboardingFlow.swift:26` —
            // `var progress: String?`, объявлении, которое к плакату
            // отношения не имеет вовсе. То есть сторож ответил
            // на вопрос «нет такой строки», а спрашивали «нет такого
            // вызова», и это ровно тот класс, который он сам
            // и сторожит.
            //
            // > **Ноль и единица от `grep` отвечают про текст.
            // > Про вызов отвечает только разбор от места вызова.**
            //
            // Поэтому идём от `TGPoster(` и смотрим окно его
            // аргументов: конструктор занимает несколько строк,
            // но не десятки.
            let этоГалерея = url.lastPathComponent == отладочная
            for (номер, строка) in код.enumerated() where строка.contains("TGPoster(") {
                вызовов += 1
                if !этоГалерея { живыхВызовов += 1 }
                guard !этоГалерея else { continue }
                let окно = код[номер..<min(номер + 10, код.count)]
                for (сдвиг, аргумент) in окно.enumerated()
                where аргумент.contains("progress:") && !аргумент.contains("progress: nil") {
                    найдено.append("  \(url.lastPathComponent):\(номер + сдвиг + 1): "
                                   + аргумент.trimmingCharacters(in: .whitespaces))
                }
            }
        }

        // Своё зрение первым: каталог, который перестали находить,
        // молчит так же, как чистый.
        #expect(осмотрено > 100, """
            осмотрено \(осмотрено) файлов в Togo/ — каталог не найден
            или прочитан не тот (замер 23.10.2026: 129). Ноль находок
            при нуле файлов значит «не смотрел», а не «чисто».
            """)

        // Счётчик ВЫЗОВОВ, а не файлов — и это ЗРЕНИЕ, а не предмет.
        //
        // Четыре вызова живут в отладочной галерее и с экранов сняты
        // быть не могут: они и есть доказательство, что разбор находит
        // `TGPoster(` вообще. Обнулится он — значит плакат переименован
        // или разбор сломан, и тогда ноль ниже ничего не значит.
        #expect(вызовов >= 1, """
            во всём `Togo/` не нашлось ни одного `TGPoster(` при
            \(осмотрено) прочитанных файлах. Сторож смотрит в пустоту:
            плакат переименован, удалён целиком или зовётся иначе.
            Если его убрали насовсем — снимать надо роль «косточка
            и полосы» из `мерим`, а не этот тест.
            """)

        // ПРЕДМЕТ: плаката нет ни на одном живом экране.
        //
        // Это не требование — это ЗАМЕР, на котором стоит исключение.
        // Вернётся плакат на экран — число станет ненулевым, и тогда
        // проверять придётся уже `progress:` у него, что тест ниже
        // и делает.
        print("""
            ПЛАКАТ: осмотрено \(осмотрено) файлов · `TGPoster(` всего \
            \(вызовов) (зрение) · вне отладочной галереи \(живыхВызовов) \
            (предмет) · с косточкой \(найдено.count)
            """)

        #expect(найдено.isEmpty, """
            живой экран передаёт плакату косточку в \(найдено.count) местах:

            \(найдено.joined(separator: "\n"))

            Значит исключение для роли «косточка и полосы» больше
            не верно: перенеси её из `мерим` в `роли` и починяй.
            Замер 08.10.2026 по токенам: 2,1458 на «usual», 2,3941
            на «fasting», 2,2892 на «alarm» — обе светлые темы, порог 3,0.
            Учти, что подложка косточки идёт под `opacity(0.25)`
            (`TGPoster.bone`), то есть настоящее число ХУЖЕ посчитанного.
            """)
    }

    // MARK: Запрет

    /// В шапке не осталось нейтральных чернил.
    ///
    /// **Зачем текстовая проверка рядом с числовой.** Числовая выше
    /// меряет `PosterPaint` — то, что шапка СПРАШИВАЕТ сегодня. Она
    /// останется зелёной, если завтра кто-то добавит в шапку четвёртый
    /// текст с `Token.Ink.primary`: цвет мимо развилки она не увидит
    /// по устройству. Этот запрет закрывает ровно ту дорогу.
    ///
    /// Четвёртым элементом, кстати, уже оказались стрелки листания —
    /// их в присланной матрице не было, нашлись чтением файла целиком.
    ///
    /// > **Матрица меряет то, что в неё положили. Соседа по той же
    /// > подложке она не ищет.**
    @Test("В шапке «Сегодня» нет ни одного нейтрального Ink")
    func вШапкеНетНейтральныхЧернил() throws {
        let путь = "Togo/Features/Today/TodayHeader.swift"
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let текст = try String(contentsOf: корень.appendingPathComponent(путь),
                               encoding: .utf8)

        // Комментарии режем до разбора: у Togo записано, что сканирующий
        // сторож, не различающий код и прозу, меряет прозу — и краснеет
        // на объяснении, почему так делать нельзя. Ровно это объяснение
        // в файле и стоит.
        let строки = текст.components(separatedBy: "\n")
        let код = строки.map { $0.components(separatedBy: "//")[0] }

        let нарушения = код.enumerated()
            .filter { $0.element.contains("Token.Ink.") }
            .map { "  \(путь):\($0.offset + 1): \($0.element.trimmingCharacters(in: .whitespaces))" }

        // Своё зрение — первым. Файл, который перестали находить, молчит
        // так же, как чистый; вырезание комментариев, съевшее весь файл,
        // тоже. Оба случая у нас оплачены.
        #expect(код.count > 50, """
            в \(путь) \(код.count) строк — файл не тот или не прочитан.
            """)
        let спрашиваетРазвилку = код.filter { $0.contains("PosterPaint.") }.count
        #expect(спрашиваетРазвилку >= 2, """
            шапка зовёт PosterPaint \(спрашиваетРазвилку) раз, ожидалось
            не меньше двух (заголовок и подпись). Ноль нарушений при нуле
            вызовов значит, что цвет взялся откуда-то третьего, а не что
            всё в порядке.
            """)

        #expect(нарушения.isEmpty, """
            в шапке \(нарушения.count) нейтральных чернил на цветной подложке:

            \(нарушения.joined(separator: "\n"))

            Шапка рисуется ВНУТРИ блока (`TGPoster` берёт её как
            `trailing`), а `Tokens.generated.swift:155` разрешает
            нейтральные чернила «ТОЛЬКО НЕЙТРАЛЬНЫЙ БЛОК». Цвет берётся
            у `PosterPaint.label` / `.caption` / `.bar` — и ВМЕСТО
            стилевого (`textStyle(_:color:)`), а не поверх него:
            `AppFont` несёт свой `color` и красит сам `Text`.
            """)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }
}
