import Testing
import Foundation
@testable import Togo

/// Каждый ключ переведён на каждый язык каталога.
///
/// **Почему это завели только 23.09.2026, и что оно стоило.** Сторожа
/// полноты у Togo не было вовсе. `LocalizationTests` проверяет, что
/// в бандле нет дублей языков, — другая забота. В тот день три ключа
/// виджета легли в русский и украинский, французский остался пустым,
/// и **ничто не покраснело**. Нашлось случайно, через час, когда
/// переводчица свела матрицу покрытия по трём приложениям сразу.
///
/// **Пробел — это не пустое место.** Недостающая строка откатывается
/// на язык разработки, то есть на русский. Француз увидел бы русский
/// текст на карточке экрана блокировки — на той самой, которую в тот
/// день завели ради самого частого вопроса. И выглядит это намеренным.
///
/// Четыре условия выведены из чужих граблей того же дня:
///
/// 1. **Языки берутся из каталога, а не списком руками.** У Gamut
///    список руками не знал про украинский; как только его внесли —
///    немедленно тринадцать дефектов. Список руками знает только то,
///    что в него положили.
/// 2. **Ноль пробелов, без порога.** Порог превращает сторожа
///    в счётчик долга, а долг по переводу не бывает осмысленным:
///    строка либо переведена, либо человек читает чужой язык.
/// 3. **Строки расширений тоже.** Каталог один на все таргеты,
///    и ключи виджета лежат в нём же — но это надо проверять,
///    а не предполагать.
/// 4. **Называть язык и ключ, а не число.** «Пробелов 3» не лечится;
///    «fr: „ещё не ели"» лечится за минуту.
///
/// И причина, по которой это стоит сторожа, а не скрипта:
/// **сторож в репозитории валит сборку, а инструмент надо не забыть
/// запустить.**
@Suite("Каталог полон на всех языках")
struct LocalizationCoverageTests {

    private struct Запись {
        let ключ: String
        let переводы: [String: String]
        let состояния: [String: String]
    }

    private func каталог() throws -> [Запись] {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: url))
            as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]

        return строки.map { ключ, запись in
            let локализации = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
            var переводы: [String: String] = [:]
            var состояния: [String: String] = [:]
            for (язык, значение) in локализации {
                let узел = значение as? [String: Any]

                // Плоская строка.
                if let единица = узел?["stringUnit"] as? [String: Any] {
                    if let текст = единица["value"] as? String { переводы[язык] = текст }
                    if let состояние = единица["state"] as? String { состояния[язык] = состояние }
                    continue
                }

                // Формы числа лежат иначе: `variations → plural → форма →
                // stringUnit`. Первая редакция сторожа об этом не знала
                // и насчитала 55 «пробелов» у переведённых ключей —
                // «%lld банок», «%lld выходов». Разбор, не видящий
                // половину формата, сообщает о пробелах, которых нет,
                // и после третьего ложного срабатывания в него
                // перестают смотреть.
                let формы = ((узел?["variations"] as? [String: Any])?["plural"]
                    as? [String: Any]) ?? [:]
                let единицы = формы.values.compactMap {
                    ($0 as? [String: Any])?["stringUnit"] as? [String: Any]
                }
                guard !единицы.isEmpty else { continue }
                переводы[язык] = единицы.compactMap { $0["value"] as? String }
                    .joined(separator: " · ")
                // Формы перечитывают целиком: если хоть одна ждёт
                // проверки, ждёт и ключ.
                состояния[язык] = единицы.compactMap { $0["state"] as? String }
                    .first { $0 == "needs_review" || $0 == "new" }
                    ?? (единицы.first?["state"] as? String)
            }
            return Запись(ключ: ключ, переводы: переводы, состояния: состояния)
        }
    }

    /// Языки — из самого каталога: какой язык встретился хоть у одного
    /// ключа, тот и обязан быть у всех.
    ///
    /// Русский сюда не входит намеренно: **ключ и есть русская строка**,
    /// и Xcode не пишет запись `ru`, когда она совпала бы с ключом.
    /// Первая редакция сторожа этого не знала и насчитала 139 «пробелов»,
    /// из которых 28 были ровно этим. Сторож, считающий мнимое, учит
    /// не верить своему счёту.
    private func языки(_ записи: [Запись]) -> Set<String> {
        Set(записи.flatMap(\.переводы.keys)).subtracting(["ru"])
    }

    /// Строки, которым перевод не нужен.
    ///
    /// Первая — по форме: если после вычёркивания подстановок в ключе
    /// не осталось ни одной буквы, переводить нечего. Это `%@ — %@`,
    /// `%lld%%`, `4,1` — одиннадцать таких.
    ///
    /// Вторая — имена собственные, и их четыре. Список короткий
    /// намеренно: длинный список исключений — это сторож, который
    /// не может покраснеть.
    private static let именаСобственные: [String: String] = [
        "Dr. Ferrand": "имя врача в примере",
        "Lévothyrox": "торговое название препарата",
        "Pro": "название подписки, одно на все языки",
        "T+%@": "отсчёт от события, букв нет",
    ]

    private func переводНеНужен(_ ключ: String) -> Bool {
        if Self.именаСобственные[ключ] != nil { return true }
        let безПодстановок = ключ.replacingOccurrences(
            of: "%[0-9.+\\- #]*(lld|ld|@|d|f|s|%)",
            with: "", options: .regularExpression)
        return !безПодстановок.contains { $0.isLetter }
    }

    /// Код страны в подсказке — это не формат, а предположение о том,
    /// где человек живёт.
    ///
    /// **Отдельной проверкой, а не через «нужен ли перевод», и это
    /// важно.** Правило «букв не осталось — переводить нечего»
    /// пропустило `+33…`: букв там нет. Первая попытка починки —
    /// «считать такие строки требующими перевода» — давала **неверный
    /// совет**: дописать `uk → +380…` значит закрепить допущение
    /// «язык ⇒ страна», которым дефект и вызван. Украиноязычный в Ницце
    /// набирает `+33`, а номер принадлежит стране, где **ветеринар**,
    /// а не где настроен телефон.
    ///
    /// Верный ответ — убрать догадку: `+…` говорит формат и не врёт
    /// никому. Поэтому здесь своя проверка со своим сообщением.
    ///
    /// Замер 23.09.2026: подсказка в поле телефона ветеринара и клиники
    /// была `+33…` на всех трёх языках — у ключа не было локализаций
    /// вовсе, он рисовался дословно. Украинец читал форму
    /// `ім'я … +33…`: три подсказки свои, четвёртая чужая. Это поле
    /// заполняют заранее, чтобы найти номер в минуту, когда с собакой
    /// плохо.
    @Test("В подсказках нет кода чужой страны")
    func кодаСтраныНет() throws {
        let подозрительные = try каталог()
            .map(\.ключ)
            // Именно подсказка целиком, а не «+4 и +6 часов» в тексте:
            // строка начинается с плюса и цифры.
            .filter { $0.range(of: "^\\s*\\+[0-9]", options: .regularExpression) != nil }
            .sorted()

        #expect(подозрительные.isEmpty, """
            в подсказке стоит код страны: \(подозрительные).

            Это не формат, а предположение о том, где человек живёт.
            Переводить его нельзя — перевод закрепит допущение
            «язык значит страна». Убери код: «+…» говорит формат
            и верно везде.
            """)
    }

    @Test("Ни один ключ не остался без перевода")
    func пробеловНет() throws {
        let записи = try каталог()
        #expect(записи.count > 500, """
            каталог прочитан не весь (\(записи.count) ключей).
            Сканер, переставший что-либо находить, молчит так же,
            как тот, кому нечего сказать.
            """)

        let все = языки(записи)
        #expect(все.count >= 2, """
            языков перевода в каталоге \(все.sorted()) — меньше двух.
            Разбор не состоялся: кроме русского их два.
            """)

        // Исключения обязаны существовать: список, переживший свои
        // строки, разрешает вернуть то, что уже переведено.
        let ключи = Set(записи.map(\.ключ))
        let протухшие = Self.именаСобственные.keys.filter { !ключи.contains($0) }.sorted()
        #expect(протухшие.isEmpty, "исключения без строк: \(протухшие). Убери их.")
        #expect(Self.именаСобственные.count <= 6,
                "исключений \(Self.именаСобственные.count): длинный список — сторож, который не может покраснеть")

        var пробелы: [String] = []
        for запись in записи.sorted(by: { $0.ключ < $1.ключ })
        where !переводНеНужен(запись.ключ) {
            for язык in все.sorted() where запись.переводы[язык] == nil {
                пробелы.append("  [\(язык)] \(запись.ключ.prefix(70))")
            }
        }

        #expect(пробелы.isEmpty, """
            ключей без перевода: \(пробелы.count).

            \(пробелы.prefix(25).joined(separator: "\n"))\
            \(пробелы.count > 25 ? "\n  …и ещё \(пробелы.count - 25)" : "")

            Пробел — не пустое место: строка откатится на язык
            разработки, и человек прочитает русский текст посреди
            своего экрана. Выглядеть это будет намеренным.
            """)
    }

    /// Пустая строка проходит проверку на существование и не проходит
    /// проверку глазами. Такой перевод хуже пробела: пробел видно,
    /// а пустоту — нет.
    @Test("Переводы не пустые")
    func переводыНеПустые() throws {
        let пустые = try каталог()
            .flatMap { запись in
                запись.переводы
                    .filter { $0.value.trimmingCharacters(in: .whitespaces).isEmpty }
                    .map { "  [\($0.key)] \(запись.ключ.prefix(70))" }
            }
            .sorted()
        #expect(пустые.isEmpty, "перевод есть и пуст:\n\(пустые.joined(separator: "\n"))")
    }

    /// `needs_review` и `new` — «положили и не перечитали».
    ///
    /// Отдельно от пробела, и требование здесь слабее: пробел — это
    /// чужой язык на экране, а непроверенный перевод уже читается
    /// на своём и может быть верным. Поэтому храповик, а не ноль.
    ///
    /// **Замер 23.09.2026:** `uk` 2040, `fr` 97, `ru` 13. Числа больше
    /// первого замера не потому, что стало хуже, а потому, что разбор
    /// стал полнее: формы числа лежат в `variations`, и первая редакция
    /// их не видела вовсе. Украинский
    /// не вычитан носителем вовсе — это известно и написано
    /// в «что тестировать». Число может только уменьшаться.
    ///
    /// Почему всё-таки проверяем, если числа велики: без этого
    /// «перевод есть» и «перевод перечитан» — одно и то же слово,
    /// и вторая половина работы становится невидимой. У украинского
    /// уже нашлось слово, которое существует и значит не то
    /// («рідше» вместо «жиже»), — счётчик существования слеп к этому
    /// целиком.
    //
    // 23.09 вечером числа выросли на единицу у `fr` и `uk`, и это
    // **названная прибавка, а не порча храповика**: строку про кнопку
    // «Написать владельцу» пришлось переписать целиком — кнопки такой
    // в приложении нет вовсе. Ключ каталога и есть русский текст,
    // поэтому правка завела новый ключ, а перевод к нему написан мной
    // и носителем не перечитан. Молча оставить старый текст было бы
    // хуже: он обещал то, чего нет.
    //
    // Вечером 23.09 прибавка ещё на две строки, и тоже названная:
    // подсказка «Dr. Ferrand» заменена на «врач или клиника» (имя
    // человека одной страны в поле, которое заполняют везде), а
    // «Lévothyrox» стал переводимым — «Эутирокс» по-русски,
    // «L-тироксин» по-украински. Оба перевода написаны не носителем
    // и ждут вычитки; оставить как было значило бы оставить чужую
    // страну в подсказке.
    private static let долг: [String: Int] = ["uk": 2042, "fr": 99, "ru": 13]

    @Test("Непроверенных переводов не становится больше")
    func непроверенныхНеБольше() throws {
        var посчитано: [String: Int] = [:]
        var примеры: [String: String] = [:]
        for запись in try каталог() {
            for (язык, состояние) in запись.состояния
            where состояние == "needs_review" || состояние == "new" {
                посчитано[язык, default: 0] += 1
                if примеры[язык] == nil { примеры[язык] = String(запись.ключ.prefix(60)) }
            }
        }

        for (язык, сколько) in посчитано.sorted(by: { $0.key < $1.key }) {
            let разрешено = Self.долг[язык] ?? 0
            #expect(сколько <= разрешено, """
                [\(язык)] непроверенных \(сколько) при долге \(разрешено),
                например: \(примеры[язык] ?? "—").
                Правку числа в долге считать вычиткой нельзя.
                """)
        }

        // Долг, которого больше нет, надо убирать: иначе он разрешает
        // вернуть то, что уже вычитано.
        let протухшие = Self.долг.keys.filter { посчитано[$0] == nil }.sorted()
        #expect(протухшие.isEmpty,
                "в долге числятся языки без непроверенных строк: \(протухшие). Убери их.")
    }
}
