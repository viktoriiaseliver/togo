        for запись in записи.sorted(by: { $0.ключ < $1.ключ })
        where запись.переводить && !переводНеНужен(запись.ключ) {
            for язык in все.sorted() where запись.переводы[язык] == nil {
                guard !Self.известныеПробелы.contains("\(язык)|\(запись.ключ)") else { continue }
                пробелы.append("  [\(язык)] \(запись.ключ.prefix(70))")
            }
        }

        // Закрытый пробел обязан уйти из списка: иначе он разрешает
        // вернуть себя обратно. Тот же храповик, что у долга вычитки,
        // только поимённый.
        var протухшиеПробелы: [String] = []
        for пара in Self.известныеПробелы.sorted() {
            let части = пара.split(separator: "|", maxSplits: 1)
            guard части.count == 2 else { continue }
            let язык = String(части[0]), ключ = String(части[1])
            if let запись = записи.first(where: { $0.ключ == ключ }),
               запись.переводы[язык] != nil {
                протухшиеПробелы.append(пара)
            }
        }
        #expect(протухшиеПробелы.isEmpty, """
            эти пробелы уже закрыты — убери их из списка:
            \(протухшиеПробелы.joined(separator: "\n"))
            """)

        #expect(пробелы.isEmpty, """
            ключей без перевода: \(пробелы.count).

            \(пробелы.prefix(25).joined(separator: "\n"))\
            \(пробелы.count > 25 ? "\n  …и ещё \(пробелы.count - 25)" : "")

            Пробел — не пустое место: строка откатится на язык
            разработки, и человек прочитает русский текст посреди
            своего экрана. Выглядеть это будет намеренным.
            """)
    }

    /// Пустая строка проходит проверку на существование и не проходит
    /// проверку глазами. Такой перевод хуже пробела: пробел видно,
    /// а пустоту — нет.
    /// Проект и каталоги согласны о том, какие языки есть.
    ///
    /// **Сверка в обе стороны, и каждая сторона ловит своё:**
    ///
    /// - язык есть в каталогах и не объявлен в `knownRegions` —
    ///   он **живёт без охраны**. Сторож полноты, берущий языки
    ///   у проекта (а брать их надо именно там: копия списка в тесте
    ///   однажды отстанет), спросит про объявленные и промолчит про
    ///   этот. Плюс `xcodebuild -exportLocalizations` берёт языки
    ///   оттуда же — каталог не выгрузить носителю стандартным путём;
    /// - язык объявлен и его нет в каталогах — обещан язык, которого
    ///   не существует.
    ///
    /// Замер 23.09.2026: у Togo `knownRegions` знал `en fr ru`,
    /// а каталоги — `fr ru uk`. Украинский собирался в бандл
    /// (`uk.lproj` на месте, язык не терялся) и при этом не охранялся
    /// ничем. Доказано подделкой у Gamut, не рассуждением: убрали `uk`
    /// из списка — покрытие прошло зелёным, согласие упало.
    @Test("Языки проекта и каталогов сходятся")
    func языкиСходятся() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let проект = try String(
            contentsOf: корень.appendingPathComponent("Togo.xcodeproj/project.pbxproj"),
            encoding: .utf8)

        let блок = try #require(
            проект.range(of: "knownRegions = \\(([^)]+)\\)", options: .regularExpression)
                .map { String(проект[$0]) },
            "в проекте нет knownRegions — разбор не состоялся")
        let объявленные = Set(блок
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: CharacterSet(charactersIn: " \t,")) }
            .filter { !$0.isEmpty && $0 != "knownRegions = (" && $0 != ")" && $0 != "Base" })

        // Русский добавляется вручную, и это не натяжка: **ключ
        // каталога и есть русская строка**, поэтому записи `ru` у него
        // может не быть вовсе — `языки()` его поэтому и вычитает.
        // Без этой строки сторож объявил бы «обещан язык, которого
        // не существует» про язык, на котором написано приложение.
        let вКаталогах = языки(try каталог()).union(["ru"])

        #expect(объявленные.count >= 3, """
            языков в проекте разобрано \(объявленные.sorted()) — разбор
            не состоялся.
            """)

        let безОхраны = вКаталогах.subtracting(объявленные).sorted()
        #expect(безОхраны.isEmpty, """
            язык есть в каталогах и не объявлен в knownRegions:
            \(безОхраны).

            Он собирается в бандл и при этом не охраняется ничем:
            сторож спросит про объявленные и промолчит про него,
            а `-exportLocalizations` не выгрузит его носителю.
            Объявляется в `Tools/generate_project.py`, а не в pbxproj:
            файл проекта генерируется.
            """)

        // `en` объявлен и каталогов не имеет намеренно: английского
        // в приложении нет вовсе, а `Base` — не язык.
        let обещаныИНет = объявленные.subtracting(вКаталогах).subtracting(["en"]).sorted()
        #expect(обещаныИНет.isEmpty, """
            язык объявлен в проекте, а переводов нет: \(обещаныИНет).
            Обещан язык, которого не существует.
            """)
    }

    @Test("Переводы не пустые")
    func переводыНеПустые() throws {
        let пустые = try каталог()
            .flatMap { запись in
                запись.переводы
                    .filter { $0.value.trimmingCharacters(in: .whitespaces).isEmpty }
                    .map { "  [\($0.key)] \(запись.ключ.prefix(70))" }
            }
            .sorted()
        #expect(пустые.isEmpty, "перевод есть и пуст:\n\(пустые.joined(separator: "\n"))")
    }

    /// `needs_review` и `new` — «положили и не перечитали».
    ///
    /// Отдельно от пробела, и требование здесь слабее: пробел — это
    /// чужой язык на экране, а непроверенный перевод уже читается
    /// на своём и может быть верным. Поэтому храповик, а не ноль.
    ///
    /// **Замер 23.09.2026:** `uk` 2040, `fr` 97, `ru` 13. Числа больше
    /// первого замера не потому, что стало хуже, а потому, что разбор
    /// стал полнее: формы числа лежат в `variations`, и первая редакция
    /// их не видела вовсе. Украинский
    /// не вычитан носителем вовсе — это известно и написано
    /// в «что тестировать». Число может только уменьшаться.
    ///
    /// Почему всё-таки проверяем, если числа велики: без этого
    /// «перевод есть» и «перевод перечитан» — одно и то же слово,
    /// и вторая половина работы становится невидимой. У украинского
    /// уже нашлось слово, которое существует и значит не то
    /// («рідше» вместо «жиже»), — счётчик существования слеп к этому
    /// целиком.
    //
    // 23.09 вечером числа выросли на единицу у `fr` и `uk`, и это
    // **названная прибавка, а не порча храповика**: строку про кнопку
    // «Написать владельцу» пришлось переписать целиком — кнопки такой
    // в приложении нет вовсе. Ключ каталога и есть русский текст,
    // поэтому правка завела новый ключ, а перевод к нему написан мной
    // и носителем не перечитан. Молча оставить старый текст было бы
    // хуже: он обещал то, чего нет.
    //
    // Вечером 23.09 прибавка ещё на две строки, и тоже названная:
    // подсказка «Dr. Ferrand» заменена на «врач или клиника» (имя
    // человека одной страны в поле, которое заполняют везде), а
    // «Lévothyrox» стал переводимым — «Эутирокс» по-русски,
    // «L-тироксин» по-украински. Оба перевода написаны не носителем
    // и ждут вычитки; оставить как было значило бы оставить чужую
    // страну в подсказке.
    //
    // 23.09, вечер: числа выросли ещё раз, и снова не потому, что стало
    // хуже. Сторож начал читать **все** каталоги, а не один: фразы Siri
    // лежат в своём `AppShortcuts.xcstrings`, и двадцать их переводов
    // сторож прежде не видел вовсе.
    //
    // 24.09: русский поднят с 13 до 26 **один раз и с объяснением.**
    // Извлечение строк завело сорок шесть новых ключей, и тридцать пять
    // из них — ключи интерполированных строк, которые делает Xcode:
    // `"\(лекарство) в \(Fmt.clock(doseAt)) — натощак"` превращается
    // в `%@ в %@ — натощак`. Это **живые строки без перевода**
    // у французов и украинцев, а не артефакты.
    //
    // Артефактов среди сорока шести оказалось всего два — ` · `
    // и `%lld `, — плюс два названия продукта. Все четыре помечены
    // `shouldTranslate: false`: вычищенные руками, они вернулись бы
    // следующим же извлечением.
    //
    // Русские значения помечены `new` самим извлечением: это язык
    // источника, и ставить им `translated` за переводчицу нельзя.
    // Дальше число только вниз.
    //
    // Числа считаны по **обоим** каталогам: у `AppShortcuts` десять
    // ключей на каждый нерусский язык. Мой первый замер читал один
    // файл и разошёлся со сторожем ровно на эти десять — тот же
    // класс, ради которого сторожа и научили обходить все каталоги.
    private static let долг: [String: Int] = ["uk": 2047, "fr": 109, "ru": 26]

    @Test("Непроверенных переводов не становится больше")
    func непроверенныхНеБольше() throws {
        var посчитано: [String: Int] = [:]
        var примеры: [String: String] = [:]
        for запись in try каталог() {
            for (язык, состояние) in запись.состояния
            where состояние == "needs_review" || состояние == "new" {
                посчитано[язык, default: 0] += 1
                if примеры[язык] == nil { примеры[язык] = String(запись.ключ.prefix(60)) }
            }
        }

        for (язык, сколько) in посчитано.sorted(by: { $0.key < $1.key }) {
            let разрешено = Self.долг[язык] ?? 0
            #expect(сколько <= разрешено, """
                [\(язык)] непроверенных \(сколько) при долге \(разрешено),
                например: \(примеры[язык] ?? "—").
                Правку числа в долге считать вычиткой нельзя.
                """)
        }

        // Долг, которого больше нет, надо убирать: иначе он разрешает
        // вернуть то, что уже вычитано.
        let протухшие = Self.долг.keys.filter { посчитано[$0] == nil }.sorted()
        #expect(протухшие.isEmpty,
                "в долге числятся языки без непроверенных строк: \(протухшие). Убери их.")
    }
