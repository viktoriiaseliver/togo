import Testing
import Foundation
@testable import Togo

/// Каждый ключ переведён на каждый язык каталога.
///
/// **Почему это завели только 23.09.2026, и что оно стоило.** Сторожа
/// полноты у Togo не было вовсе. `LocalizationTests` проверяет, что
/// в бандле нет дублей языков, — другая забота. В тот день три ключа
/// виджета легли в русский и украинский, французский остался пустым,
/// и **ничто не покраснело**. Нашлось случайно, через час, когда
/// переводчица свела матрицу покрытия по трём приложениям сразу.
///
/// **Пробел — это не пустое место.** Недостающая строка откатывается
/// на язык разработки, то есть на русский. Француз увидел бы русский
/// текст на карточке экрана блокировки — на той самой, которую в тот
/// день завели ради самого частого вопроса. И выглядит это намеренным.
///
/// Четыре условия выведены из чужих граблей того же дня:
///
/// 1. **Языки берутся из каталога, а не списком руками.** У Gamut
///    список руками не знал про украинский; как только его внесли —
///    немедленно тринадцать дефектов. Список руками знает только то,
///    что в него положили.
/// 2. **Ноль пробелов, без порога.** Порог превращает сторожа
///    в счётчик долга, а долг по переводу не бывает осмысленным:
///    строка либо переведена, либо человек читает чужой язык.
/// 3. **Строки расширений тоже.** Каталог один на все таргеты,
///    и ключи виджета лежат в нём же — но это надо проверять,
///    а не предполагать.
/// 4. **Называть язык и ключ, а не число.** «Пробелов 3» не лечится;
///    «fr: „ещё не ели"» лечится за минуту.
///
/// И причина, по которой это стоит сторожа, а не скрипта:
/// **сторож в репозитории валит сборку, а инструмент надо не забыть
/// запустить.**
@Suite("Каталог полон на всех языках")
struct LocalizationCoverageTests {

    private struct Запись {
        let ключ: String
        /// `false` — Xcode не отдаёт строку на перевод вовсе.
        ///
        /// Флаг самого каталога, и читать его обязан всякий, кто
        /// считает пробелы: вычищенные руками артефакты вернулись бы
        /// следующим же извлечением, а помеченные — нет. Так помечены
        /// разделитель ` · `, «число с пробелом» и два названия
        /// продукта.
        let переводить: Bool
        let переводы: [String: String]
        let состояния: [String: String]
    }

    /// Все живые каталоги проекта, а не один.
    ///
    /// **Замер 23.09.2026, и он про два приложения из трёх.** Фразы Siri
    /// лежат в своём каталоге `AppShortcuts.xcstrings`, и там были
    /// только русские ключи — при отгруженных французском и украинском.
    /// Француз видел в «Командах» русские фразы и не мог позвать голосом
    /// ничего. У Gamut тем же заходом нашлось, что доступ к фотоплёнке
    /// просится по-русски: у него свой `InfoPlist.xcstrings`.
    ///
    /// Причина одна на оба: **счёт по `Localizable` говорит «язык
    /// покрыт», когда язык не покрыт.** Этот сторож сам был тому
    /// примером — читал один файл и молчал про второй.
    ///
    /// Выгруженные `.xcloc` пропускаются: это снимки для переводчика,
    /// а не источник.
    private func каталоги() throws -> [URL] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [URL] = []
        for место in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(место), includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "xcstrings" else { continue }
                найдено.append(элемент)
            }
        }
        return найдено.sorted { $0.path < $1.path }
    }

    private func каталог() throws -> [Запись] {
        var строки: [String: Any] = [:]
        for файл in try каталоги() {
            let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: файл))
                as? [String: Any]
            for (ключ, запись) in корень?["strings"] as? [String: Any] ?? [:] {
                строки[ключ] = запись
            }
        }

        return строки.map { ключ, запись in
            let локализации = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
            var переводы: [String: String] = [:]
            var состояния: [String: String] = [:]
            for (язык, значение) in локализации {
                let узел = значение as? [String: Any]

                // Плоская строка.
                if let единица = узел?["stringUnit"] as? [String: Any] {
                    if let текст = единица["value"] as? String { переводы[язык] = текст }
                    if let состояние = единица["state"] as? String { состояния[язык] = состояние }
                    continue
                }

                // Формы числа лежат иначе: `variations → plural → форма →
                // stringUnit`. Первая редакция сторожа об этом не знала
                // и насчитала 55 «пробелов» у переведённых ключей —
                // «%lld банок», «%lld выходов». Разбор, не видящий
                // половину формата, сообщает о пробелах, которых нет,
                // и после третьего ложного срабатывания в него
                // перестают смотреть.
                let формы = ((узел?["variations"] as? [String: Any])?["plural"]
                    as? [String: Any]) ?? [:]
                let единицы = формы.values.compactMap {
                    ($0 as? [String: Any])?["stringUnit"] as? [String: Any]
                }
                guard !единицы.isEmpty else { continue }
                переводы[язык] = единицы.compactMap { $0["value"] as? String }
                    .joined(separator: " · ")
                // Формы перечитывают целиком: если хоть одна ждёт
                // проверки, ждёт и ключ.
                состояния[язык] = единицы.compactMap { $0["state"] as? String }
                    .first { $0 == "needs_review" || $0 == "new" }
                    ?? (единицы.first?["state"] as? String)
            }
            let флаг = (запись as? [String: Any])?["shouldTranslate"] as? Bool
            return Запись(ключ: ключ, переводить: флаг ?? true,
                          переводы: переводы, состояния: состояния)
        }
    }

    /// Языки — из самого каталога: какой язык встретился хоть у одного
    /// ключа, тот и обязан быть у всех.
    ///
    /// Русский сюда не входит намеренно: **ключ и есть русская строка**,
    /// и Xcode не пишет запись `ru`, когда она совпала бы с ключом.
    /// Первая редакция сторожа этого не знала и насчитала 139 «пробелов»,
    /// из которых 28 были ровно этим. Сторож, считающий мнимое, учит
    /// не верить своему счёту.
    private func языки(_ записи: [Запись]) -> Set<String> {
        Set(записи.flatMap(\.переводы.keys)).subtracting(["ru"])
    }

    /// Строки, которым перевод не нужен.
    ///
    /// Первая — по форме: если после вычёркивания подстановок в ключе
    /// не осталось ни одной буквы, переводить нечего. Это `%@ — %@`,
    /// `%lld%%`, `4,1` — одиннадцать таких.
    ///
    /// Вторая — имена собственные, и их четыре. Список короткий
    /// намеренно: длинный список исключений — это сторож, который
    /// не может покраснеть.
    //
    // 05.10.2026 из списка убран `Lévothyrox`: он стоял здесь как
    // «торговое название препарата», а переведён во всех четырёх языках
    // и переводиться обязан — ru «Эутирокс», uk «L-тироксин»,
    // en «Synthroid». Это не бренд, одинаковый всюду, а подсказка,
    // которую человек должен узнать в своей аптеке. Исключение,
    // закрывающее то, чего нет, — лишняя дыра: указал на него
    // `PlaceholderOriginTests`, когда приехал английский.
    private static let именаСобственные: [String: String] = [
        "Pro": "название подписки, одно на все языки",
        "T+%@": "отсчёт от события, букв нет",
        "T0 / +4 / +6": "обозначение протокола контроля, одно на все языки",
    ]

    private func переводНеНужен(_ ключ: String) -> Bool {
        if Self.именаСобственные[ключ] != nil { return true }
        let безПодстановок = ключ.replacingOccurrences(
            of: "%[0-9.+\\- #]*(lld|ld|@|d|f|s|%)",
            with: "", options: .regularExpression)
        return !безПодстановок.contains { $0.isLetter }
    }

    /// Код страны в подсказке — это не формат, а предположение о том,
    /// где человек живёт.
    ///
    /// **Отдельной проверкой, а не через «нужен ли перевод», и это
    /// важно.** Правило «букв не осталось — переводить нечего»
    /// пропустило `+33…`: букв там нет. Первая попытка починки —
    /// «считать такие строки требующими перевода» — давала **неверный
    /// совет**: дописать `uk → +380…` значит закрепить допущение
    /// «язык ⇒ страна», которым дефект и вызван. Украиноязычный в Ницце
    /// набирает `+33`, а номер принадлежит стране, где **ветеринар**,
    /// а не где настроен телефон.
    ///
    /// Верный ответ — убрать догадку: `+…` говорит формат и не врёт
    /// никому. Поэтому здесь своя проверка со своим сообщением.
    ///
    /// Замер 23.09.2026: подсказка в поле телефона ветеринара и клиники
    /// была `+33…` на всех трёх языках — у ключа не было локализаций
    /// вовсе, он рисовался дословно. Украинец читал форму
    /// `ім'я … +33…`: три подсказки свои, четвёртая чужая. Это поле
    /// заполняют заранее, чтобы найти номер в минуту, когда с собакой
    /// плохо.
    /// Ось сторожа: «плюс, до трёх цифр, и СНОВА ЦИФРА» — группы номера.
    ///
    /// **Правилась 22.10.2026, и правилась потому, что ось никогда
    /// не совпадала с намерением, записанным строкой выше.** Прежняя
    /// форма была `^\s*\+[0-9]` — «плюс и цифра», — а комментарий рядом
    /// обещал «именно подсказка целиком, а не „+4 и +6 часов" в тексте».
    /// Обещание не исполнялось ни одного дня: `+4 ч` под ту форму
    /// попадает.
    ///
    /// > **Сторож был зелёным ПО ОТСУТСТВИЮ предмета, а не по верности
    /// > оси.** Строк вида `+N ед.` в каталоге не было, поэтому
    /// > расхождение формы с намерением никого не кусало. Привёз их
    /// > хендофф `design_handoff_togo_ios28` (часы протокола контроля
    /// > `T0 / +4 / +6`), и сторож покраснел на СВОЕЙ ошибке, а не
    /// > на предмете.
    ///
    /// Замер 22.10.2026, предмет и контроль сняты одной функцией
    /// и в одном прогоне — см. `осьРазличаетНомерИЧасы` ниже.
    private func похожеНаКодСтраны(_ ключ: String) -> Bool {
        // `+33 4 93 …` → плюс, «33», пробел, «4» — цифра после группы.
        // `+4 ч`       → плюс, «4», пробел, «ч» — буква, значит единица.
        ключ.range(of: "^\\s*\\+[0-9]{1,3}[\\s\u{00A0}]*[0-9]",
                   options: .regularExpression) != nil
    }

    /// Контроль оси — в том же прогоне, что и предмет.
    ///
    /// У нас записано и оплачено: **контроль, снятый не в том же замере,
    /// меряет не то.** Поэтому положительные и отрицательные примеры
    /// лежат здесь, рядом с осью, а не в журнале: сузив ось под свой
    /// импорт, следующий увидит, что именно он при этом обязан сохранить.
    ///
    /// `+33…` — это строка из замера 23.09.2026, ради которой сторож
    /// заведён: подсказка в поле телефона ветеринара и клиники.
    @Test("Ось различает номер телефона и часы протокола")
    func осьРазличаетНомерИЧасы() {
        let номера = ["+33…", "+33 4 93 … · 1,2 км",
                      "+380 44 123 45 67", "+7 495 1234567"]
        let неНомера = ["+4 ч", "+6 ч", "+…", "+ «дальше» и «Гулять»", "+ %lld шт"]

        for строка in номера {
            #expect(похожеНаКодСтраны(строка), """
                ось перестала видеть номер телефона: \(строка).
                Ради этой строки сторож и заведён — замер 23.09.2026,
                подсказка в поле телефона ветеринара.
                """)
        }
        for строка in неНомера {
            #expect(!похожеНаКодСтраны(строка), """
                ось считает кодом страны то, что им не является:
                \(строка). `+N ед.` — это величина, а не номер.
                """)
        }
    }

    @Test("В подсказках нет кода чужой страны")
    func кодаСтраныНет() throws {
        let подозрительные = try каталог()
            .map(\.ключ)
            .filter(похожеНаКодСтраны)
            .sorted()

        #expect(подозрительные.isEmpty, """
            в подсказке стоит код страны: \(подозрительные).

            Это не формат, а предположение о том, где человек живёт.
            Переводить его нельзя — перевод закрепит допущение
            «язык значит страна». Убери код: «+…» говорит формат
            и верно везде.
            """)
    }

    /// Пробелы, о которых **известно поимённо**.
    ///
    /// Не порог, а список, и разница принципиальная: порог впитал бы
    /// следующий пробел молча, а список — нет. Ключа в нём нет —
    /// сторож краснеет, как и должен.
    ///
    /// Откуда взялись. 24.09.2026 извлечение строк завело сорок шесть
    /// новых ключей, и тридцать пять из них — ключи интерполированных
    /// строк, которые делает Xcode. Скрипт их не заводил и не должен:
    /// он не знает ни типа подставляемого, ни экранирования процента.
    ///
    /// **Закрыт целиком 05.10.2026, и список пуст намеренно** — пустым
    /// он остаётся сторожем: следующий пробел в нём не числится,
    /// значит падение будет сразу.
    ///
    /// Что выяснилось при закрытии, и это важнее самих сорока двух
    /// строк. **Двадцать четыре из них были уже переведены** — и
    /// французский, и украинский лежали в том же каталоге под
    /// ключом-двойником, где `%@` вместо `%lld`: `«Дальше · %@»`
    /// при живом `«Дальше · %lld»`. Половина работы, записанной как
    /// «перевода нет», состояла в переносе готового текста и правке
    /// одного спецификатора.
    ///
    /// > **«Перевода нет» и «перевод есть и не доезжает» — разные
    /// > диагнозы, а снаружи оба выглядят пустой клеткой.**
    ///
    /// Механика двойников — в `двойниковНеБольше` ниже.
    ///
    /// **Список только уменьшается** — проверяется ниже.
    private static let известныеПробелы: Set<String> = []

    @Test("Ни один ключ не остался без перевода")
    func пробеловНет() throws {
        let записи = try каталог()
        #expect(записи.count > 500, """
            каталог прочитан не весь (\(записи.count) ключей).
            Сканер, переставший что-либо находить, молчит так же,
            как тот, кому нечего сказать.
            """)

        let все = языки(записи)
        #expect(все.count >= 2, """
            языков перевода в каталоге \(все.sorted()) — меньше двух.
            Разбор не состоялся: кроме русского их два.
            """)

        // Исключения обязаны существовать: список, переживший свои
        // строки, разрешает вернуть то, что уже переведено.
        let ключи = Set(записи.map(\.ключ))
        let протухшие = Self.именаСобственные.keys.filter { !ключи.contains($0) }.sorted()
        #expect(протухшие.isEmpty, "исключения без строк: \(протухшие). Убери их.")
        #expect(Self.именаСобственные.count <= 6,
                "исключений \(Self.именаСобственные.count): длинный список — сторож, который не может покраснеть")

        var пробелы: [String] = []
        for запись in записи.sorted(by: { $0.ключ < $1.ключ })
        where запись.переводить && !переводНеНужен(запись.ключ) {
            for язык in все.sorted() where запись.переводы[язык] == nil {
                guard !Self.известныеПробелы.contains("\(язык)|\(запись.ключ)") else { continue }
                пробелы.append("  [\(язык)] \(запись.ключ.prefix(70))")
            }
        }

        // Закрытый пробел обязан уйти из списка: иначе он разрешает
        // вернуть себя обратно. Тот же храповик, что у долга вычитки,
        // только поимённый.
        var протухшиеПробелы: [String] = []
        for пара in Self.известныеПробелы.sorted() {
            let части = пара.split(separator: "|", maxSplits: 1)
            guard части.count == 2 else { continue }
            let язык = String(части[0]), ключ = String(части[1])
            if let запись = записи.first(where: { $0.ключ == ключ }),
               запись.переводы[язык] != nil {
                протухшиеПробелы.append(пара)
            }
        }
        #expect(протухшиеПробелы.isEmpty, """
            эти пробелы уже закрыты — убери их из списка:
            \(протухшиеПробелы.joined(separator: "\n"))
            """)

        #expect(пробелы.isEmpty, """
            ключей без перевода: \(пробелы.count).

            \(пробелы.prefix(25).joined(separator: "\n"))\
            \(пробелы.count > 25 ? "\n  …и ещё \(пробелы.count - 25)" : "")

            Пробел — не пустое место: строка откатится на язык
            разработки, и человек прочитает русский текст посреди
            своего экрана. Выглядеть это будет намеренным.
            """)

        напечататьДолгРядомСНулём(записи)
    }

    /// Рядом с нулём пробелов печатается долг вычитки. Всегда, в том
    /// числе на зелёном.
    ///
    /// **Замер 05.10.2026: в этот день ноль появился впервые** — все три
    /// языка покрыты полностью, английский целиком черновиком. И тем же
    /// днём стало видно, что ноль читается как «переведено», хотя значит
    /// другое: 4479 строк ждут носителя, половина объёма — объяснения,
    /// которые человек читает в тревоге, а часть коротких строк выбрана
    /// **по длине, а не по точности**.
    ///
    /// У нас записано: «пустой прогон — исчерпание метода, а не
    /// подтверждение качества», и «пустой результат докладывать так же
    /// подробно, как находку, называя, чего он НЕ значит». Пока эту
    /// границу называет человек в журнале, она теряется при первой
    /// передаче. Напечатанная сторожем — доезжает до всех, включая того,
    /// кто решает отгружать.
    ///
    /// Числа берутся из каталога, а не из `долг`: копия числа в тесте
    /// однажды отстанет, и тогда сторож станет печатать неправду
    /// уверенным тоном.
    ///
    /// Префикс `ВЫЧИТКА:` не украшение — по нему строки вытаскивает
    /// `make unit`, иначе они утонут в логе на двадцать тысяч строк.
    private func напечататьДолгРядомСНулём(_ записи: [Запись]) {
        var непроверенных: [String: Int] = [:]
        var всего: [String: Int] = [:]
        for запись in записи {
            for (язык, состояние) in запись.состояния {
                всего[язык, default: 0] += 1
                if состояние == "needs_review" || состояние == "new" {
                    непроверенных[язык, default: 0] += 1
                }
            }
        }
        let строки = непроверенных.sorted { $0.key < $1.key }
            .map { "\($0.key) \($0.value) из \(всего[$0.key] ?? 0)" }
            .joined(separator: " · ")
        print("""
            ВЫЧИТКА: пробелов ноль — это НЕ «переведено».
            ВЫЧИТКА: непроверенных носителем: \(строки).
            ВЫЧИТКА: ноль значит «каждый ключ каталога имеет строку \
            на каждом языке» и не значит ни того, что строку читал \
            носитель, ни того, что её видели на экране.
            ВЫЧИТКА: отгружать по этому нулю нельзя.
            """)
    }

    /// Пустая строка проходит проверку на существование и не проходит
    /// проверку глазами. Такой перевод хуже пробела: пробел видно,
    /// а пустоту — нет.
    /// Проект и каталоги согласны о том, какие языки есть.
    ///
    /// **Сверка в обе стороны, и каждая сторона ловит своё:**
    ///
    /// - язык есть в каталогах и не объявлен в `knownRegions` —
    ///   он **живёт без охраны**. Сторож полноты, берущий языки
    ///   у проекта (а брать их надо именно там: копия списка в тесте
    ///   однажды отстанет), спросит про объявленные и промолчит про
    ///   этот. Плюс `xcodebuild -exportLocalizations` берёт языки
    ///   оттуда же — каталог не выгрузить носителю стандартным путём;
    /// - язык объявлен и его нет в каталогах — обещан язык, которого
    ///   не существует.
    ///
    /// Замер 23.09.2026: у Togo `knownRegions` знал `en fr ru`,
    /// а каталоги — `fr ru uk`. Украинский собирался в бандл
    /// (`uk.lproj` на месте, язык не терялся) и при этом не охранялся
    /// ничем. Доказано подделкой у Gamut, не рассуждением: убрали `uk`
    /// из списка — покрытие прошло зелёным, согласие упало.
    @Test("Языки проекта и каталогов сходятся")
    func языкиСходятся() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let проект = try String(
            contentsOf: корень.appendingPathComponent("Togo.xcodeproj/project.pbxproj"),
            encoding: .utf8)

        let блок = try #require(
            проект.range(of: "knownRegions = \\(([^)]+)\\)", options: .regularExpression)
                .map { String(проект[$0]) },
            "в проекте нет knownRegions — разбор не состоялся")
        let объявленные = Set(блок
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: CharacterSet(charactersIn: " \t,")) }
            .filter { !$0.isEmpty && $0 != "knownRegions = (" && $0 != ")" && $0 != "Base" })

        // Русский добавляется вручную, и это не натяжка: **ключ
        // каталога и есть русская строка**, поэтому записи `ru` у него
        // может не быть вовсе — `языки()` его поэтому и вычитает.
        // Без этой строки сторож объявил бы «обещан язык, которого
        // не существует» про язык, на котором написано приложение.
        let вКаталогах = языки(try каталог()).union(["ru"])

        #expect(объявленные.count >= 3, """
            языков в проекте разобрано \(объявленные.sorted()) — разбор
            не состоялся.
            """)

        let безОхраны = вКаталогах.subtracting(объявленные).sorted()
        #expect(безОхраны.isEmpty, """
            язык есть в каталогах и не объявлен в knownRegions:
            \(безОхраны).

            Он собирается в бандл и при этом не охраняется ничем:
            сторож спросит про объявленные и промолчит про него,
            а `-exportLocalizations` не выгрузит его носителю.
            Объявляется в `Tools/generate_project.py`, а не в pbxproj:
            файл проекта генерируется.
            """)

        // 05.10.2026 исключение для `en` убрано: английский в каталоге
        // появился (2152 ключа, черновиком). Исключение, закрывающее
        // то, чего больше нет, — лишняя дыра, про которую никто
        // не помнит.
        let обещаныИНет = объявленные.subtracting(вКаталогах).sorted()
        #expect(обещаныИНет.isEmpty, """
            язык объявлен в проекте, а переводов нет: \(обещаныИНет).
            Обещан язык, которого не существует.
            """)

        // ТРЕТЬЯ СТОРОНА, заведена 22.10.2026 вместе с казахским.
        //
        // `CFBundleLocalizations` в `Configuration/Togo-Info.plist` —
        // список руками, и до 22.10 его не было вовсе. Появился он
        // не потому, что был нужен App Store (витрина читает папки
        // `*.lproj`, замер лежит в `Tools/extract_texts.py`), а потому,
        // что состав языков стало нужно объявить системе и прочитать
        // в одном месте.
        //
        // Сверка заведена В ТОТ ЖЕ ДЕНЬ, что и ключ, нарочно. Две копии
        // расходятся молча — это записано и оплачено; третья копия без
        // сторожа была бы повторением случая Gamut 23.09.2026, где
        // список руками не знал про украинский и язык жил без охраны.
        //
        // Границу назвать: plist читается ТЕКСТОМ, а не `Bundle`, —
        // проверяется ИСХОДНИК, а не бандл. «Исходник говорит, что
        // задумали; бандл — что получилось», и бандл здесь спрашивает
        // соседний тест `уЯзыковБандлаЕстьИмена`.
        let plist = try String(
            contentsOf: корень.appendingPathComponent("Configuration/Togo-Info.plist"),
            encoding: .utf8)
        let массив = try #require(
            plist.range(of: "<key>CFBundleLocalizations</key>\\s*<array>(.*?)</array>",
                        options: [.regularExpression, .dotMatchesLineSeparators])
                .map { String(plist[$0]) },
            """
            в `Configuration/Togo-Info.plist` нет `CFBundleLocalizations` —
            разбор не состоялся. Если ключ убрали нарочно, убери и эту
            проверку: сторож, которому нечего проверять, молчит так же,
            как тот, у кого всё сошлось.
            """)
        var вPlist: Set<String> = []
        var остаток = Substring(массив)
        while let открыт = остаток.range(of: "<string>"),
              let закрыт = остаток[открыт.upperBound...].range(of: "</string>") {
            вPlist.insert(String(остаток[открыт.upperBound..<закрыт.lowerBound]))
            остаток = остаток[закрыт.upperBound...]
        }
        #expect(вPlist.count >= 3, """
            языков в plist разобрано \(вPlist.sorted()) — разбор
            не состоялся.
            """)

        #expect(вPlist == вКаталогах, """
            `CFBundleLocalizations` разошёлся с каталогами строк.

            в plist, а переводов нет:  \(вPlist.subtracting(вКаталогах).sorted())
            переводы есть, в plist нет: \(вКаталогах.subtracting(вPlist).sorted())

            Это список руками, и он знает только то, что в него
            положили. Сверяется с каталогами, а не с `knownRegions`:
            источник языка — наличие перевода, а оба списка — его копии.
            """)
    }

    @Test("Переводы не пустые")
    func переводыНеПустые() throws {
        let пустые = try каталог()
            .flatMap { запись in
                запись.переводы
                    .filter { $0.value.trimmingCharacters(in: .whitespaces).isEmpty }
                    .map { "  [\($0.key)] \(запись.ключ.prefix(70))" }
            }
            .sorted()
        #expect(пустые.isEmpty, "перевод есть и пуст:\n\(пустые.joined(separator: "\n"))")
    }

    /// `needs_review` и `new` — «положили и не перечитали».
    ///
    /// Отдельно от пробела, и требование здесь слабее: пробел — это
    /// чужой язык на экране, а непроверенный перевод уже читается
    /// на своём и может быть верным. Поэтому храповик, а не ноль.
    ///
    /// **Замер 23.09.2026:** `uk` 2040, `fr` 97, `ru` 13. Числа больше
    /// первого замера не потому, что стало хуже, а потому, что разбор
    /// стал полнее: формы числа лежат в `variations`, и первая редакция
    /// их не видела вовсе. Украинский
    /// не вычитан носителем вовсе — это известно и написано
    /// в «что тестировать». Число может только уменьшаться.
    ///
    /// Почему всё-таки проверяем, если числа велики: без этого
    /// «перевод есть» и «перевод перечитан» — одно и то же слово,
    /// и вторая половина работы становится невидимой. У украинского
    /// уже нашлось слово, которое существует и значит не то
    /// («рідше» вместо «жиже»), — счётчик существования слеп к этому
    /// целиком.
    //
    // 23.09 вечером числа выросли на единицу у `fr` и `uk`, и это
    // **названная прибавка, а не порча храповика**: строку про кнопку
    // «Написать владельцу» пришлось переписать целиком — кнопки такой
    // в приложении нет вовсе. Ключ каталога и есть русский текст,
    // поэтому правка завела новый ключ, а перевод к нему написан мной
    // и носителем не перечитан. Молча оставить старый текст было бы
    // хуже: он обещал то, чего нет.
    //
    // Вечером 23.09 прибавка ещё на две строки, и тоже названная:
    // подсказка «Dr. Ferrand» заменена на «врач или клиника» (имя
    // человека одной страны в поле, которое заполняют везде), а
    // «Lévothyrox» стал переводимым — «Эутирокс» по-русски,
    // «L-тироксин» по-украински. Оба перевода написаны не носителем
    // и ждут вычитки; оставить как было значило бы оставить чужую
    // страну в подсказке.
    //
    // 23.09, вечер: числа выросли ещё раз, и снова не потому, что стало
    // хуже. Сторож начал читать **все** каталоги, а не один: фразы Siri
    // лежат в своём `AppShortcuts.xcstrings`, и двадцать их переводов
    // сторож прежде не видел вовсе.
    //
    // 24.09: русский поднят с 13 до 26 **один раз и с объяснением.**
    // Извлечение строк завело сорок шесть новых ключей, и тридцать пять
    // из них — ключи интерполированных строк, которые делает Xcode:
    // `"\(лекарство) в \(Fmt.clock(doseAt)) — натощак"` превращается
    // в `%@ в %@ — натощак`. Это **живые строки без перевода**
    // у французов и украинцев, а не артефакты.
    //
    // Артефактов среди сорока шести оказалось всего два — ` · `
    // и `%lld `, — плюс два названия продукта. Все четыре помечены
    // `shouldTranslate: false`: вычищенные руками, они вернулись бы
    // следующим же извлечением.
    //
    // Русские значения помечены `new` самим извлечением: это язык
    // источника, и ставить им `translated` за переводчицу нельзя.
    // Дальше число только вниз.
    //
    // Числа считаны по **обоим** каталогам: у `AppShortcuts` десять
    // ключей на каждый нерусский язык. Мой первый замер читал один
    // файл и разошёлся со сторожем ровно на эти десять — тот же
    // класс, ради которого сторожа и научили обходить все каталоги.
    // 24.09 вечер: `uk` 2047 → 2048. Прибавила ровно одна новая строка —
    // «Записи семьи не пришли: %@», та, что показывает отказ чтения
    // общего дневника. Украинский к ней написал не носитель, поэтому
    // она и лежит `needs_review`: число выросло не потому, что стало
    // хуже, а потому, что появилась строка, которой раньше не было.
    // Вычиткой эта правка не является и за вычитку не засчитывается.
    // 28.09: `uk` 2048 → 2051, `fr` 109 → 112. Прибавили ровно три
    // строки, и обе прибавки — одни и те же три ключа из `f115761`:
    // «отметок мочи нет», «отметок мочи нет с %@» и «Отметок мочи нет
    // с %@. Приложение не знает…». Их завела переводчица под правило
    // тишины, и они лежат `needs_review` у обоих языков, потому что
    // писал не носитель.
    //
    // Число выросло не потому, что стало хуже, а потому, что появились
    // строки, которых раньше не было. Вычиткой эта правка не является
    // и за вычитку не засчитывается — как и запись от 24.09 выше.
    // 30.09: `uk` 2051 → 2054, `fr` 112 → 115. Прибавили ровно три
    // строки, и у обоих языков это одни и те же три — тексты отказа
    // восстановления покупок, заведённые вместе с разбором причины:
    // «App Store не ответил…», «В App Store твоей страны подписки Togo
    // нет…» и «Дело не в твоих настройках…». Французский и украинский
    // к ним написал не носитель, а разработчик, — поэтому `needs_review`
    // у обоих.
    //
    // Число выросло не потому, что стало хуже, а потому, что появились
    // строки, которых раньше не было. Вычиткой эта правка не является
    // и за вычитку не засчитывается — как и записи от 24.09 и 28.09.
    //
    // Четвёртый текст того же разбора — «Не удалось восстановить
    // покупки…» — долга не прибавил: ключ и оба перевода лежали
    // в каталоге с прежних времён и до экрана не доезжали, потому что
    // присваивались литералом мимо каталога. Он теперь доезжает,
    // а `needs_review` у него был и остался.
    // 05.10: `uk` 2054 → 2150, `fr` 115 → 169, `ru` 26 → 36. Самая
    // крупная прибавка за всё время, и она целиком про появление строк,
    // а не про ухудшение. Разобрать её надо по трём причинам, иначе
    // число читается как провал вычитки.
    //
    // 1. **Девяносто восемь ключей получили перевод, которого не было.**
    //    Сорок два из них числились в `известныеПробелы` поимённо,
    //    пятьдесят шесть не числились нигде: их **не знал сам каталог**.
    //    Извлечение строк (`xcodebuild -exportLocalizations`) завело их
    //    в файл впервые — то есть до 05.10 сторож полноты их не видел
    //    и показывал ноль пробелов, считая только то, о чём каталогу
    //    уже рассказали.
    //
    //    > **«Пробелов нет» значило «нет среди ключей, которые
    //    > в каталоге уже есть».** Граница сторожа проходила не там,
    //    > где её читали.
    //
    // 2. **Украинский весь `needs_review` по устройству**, поэтому
    //    +96 у `uk` — это ровно 96 новых записей. У `fr` +54, а не +98:
    //    сорок четыре французские строки перенесены с ключа-двойника,
    //    где они лежали `translated`. Текст тот же до буквы, изменился
    //    один спецификатор — читать его заново человеку не надо, и
    //    выдавать перенос за новый непроверенный перевод было бы
    //    неправдой в другую сторону.
    //
    // 3. **`ru` +10** — язык источника: извлечение помечает новые
    //    русские значения `new` само. Четыре ключа получили русские
    //    формы числа (`translated`): «Принять смену и %lld дело»
    //    печатало «2 дело», «Удалить прогулку и %lld отметки» —
    //    «1 отметки». Это дефект источника, а не перевода, и живёт он
    //    в каталоге, где формы правит переводчик.
    //
    // Вычиткой эта правка не является и за вычитку не засчитывается —
    // как и записи от 24.09, 28.09 и 30.09 выше.
    //
    // 05.10 вечер: `uk` 2150 → 2153, `fr` 169 → 173, `ru` 36 → 37.
    // Прибавили ровно пять ключей, и каждый назван:
    //
    // * `Файл сделан %@, внутри: %@.` — мой, вместо
    //   `В файле: %@. Сделан %@.`: дата стояла перед точкой и давала
    //   «Сделан 17 сент..». Замер сокращений месяца — ru 8 точек
    //   из 12, fr 8 из 12, uk 12 из 12, en 0 из 12, — поэтому ни
    //   оставить точку, ни убрать её нельзя: лечится структурой;
    // * `Добавлено новых записей: %lld…` — перенос с двойника `%@`.
    //   Французский пришёл `translated` (текст тот же до буквы,
    //   изменился спецификатор), поэтому у `fr` +4, а не +5;
    // * `С %@ отметок мочи нет…`, `ел %@`, `гулял %@` — ключи соседней
    //   сессии из `3d9fc28`. Русский её, французский и украинский мои,
    //   писал не носитель.
    //
    // Заодно удалены два мёртвых ключа — `В файле: %@. Сделан %@.`
    // и `Добавлено новых записей: %@…`: оба больше не зовутся ниоткуда,
    // место вызова проверено. Это первая пара из семидесяти четырёх,
    // снятая по-настоящему, — поэтому `двойников` остался 74, а не стал 75.
    //
    // 05.10 ночь: прибавился `en` — 2153. Это **весь английский**:
    // Виктория решила отгрузить его в 1.0 черновиком, вычитку носителями
    // оставить на после релиза. Ни одной английской строки не читал
    // носитель, и ни одну не видели на экране.
    //
    // > **Это не долг, который кто-то забыл закрыть, а решение
    // > об объёме.** Записано здесь, потому что счётчик пробелов
    // > покажет ноль и работа будет выглядеть законченной.
    //
    // 2153, а не 2152: `Lévothyrox` переведён отдельно, вне черновика —
    // он числился в исключениях сторожа как «торговое название», а его
    // потребовал `PlaceholderOriginTests`, и правильно: ru «Эутирокс»,
    // uk «L-тироксин», en «Synthroid».
    // 07.10 вечер, перед сборкой 274. Число выросло, и прибавка
    // **состоит из двух разных вещей** — поэтому записана двумя
    // строками, а не одной суммой.
    //
    //     язык   было   застал   стало    из них не моё   моё
    //     en     2153     2158    2217          +5        +59
    //     fr      173      179     239          +6        +60
    //     uk     2153     2158    2217          +5        +59
    //     ru       37       76      72         +39         −4
    //
    // **Столбец «застал» — это состояние ДО моей правки**, и храповик
    // в нём уже был красным. Кто внёс эти +5/+6/+5/+39, я не знаю:
    // прибавка приехала чужими коммитами за вечер и нигде не названа.
    // Записываю её отдельно нарочно: слей я её со своей, разница между
    // «мы решили» и «кто-то не доделал» исчезла бы, а эталон тем
    // и держится, что их различает.
    //
    // **Моя прибавка — перевод 60 ключей на en, fr и uk**, все
    // `needs_review`: писал не носитель. Пробелы при этом упали
    // **76 → 2** в каждом из трёх языков. Это не ухудшение, а обмен:
    // до правки француз видел на шестидесяти поверхностях русский
    // текст — в том числе на экране «Дневник не открылся», который
    // он откроет ровно тогда, когда уже напуган, и на медкнижке,
    // которую читают в тревоге.
    //
    // > **Пробел и непрочитанный перевод — разные беды, и вторая
    // > меньше.** Пробел показывает чужой язык; непрочитанный перевод
    // > показывает свой и может быть верным.
    //
    // `ru` −4: четырнадцать ключей-форматов (`%@ · %@`, `%lld%%`,
    // `+…`, `T0 / +4 / +6`, `Pro`, пустая строка и прочие) помечены
    // `shouldTranslate: false`. Это не слова: переведёнными они
    // вернулись бы следующим извлечением, а в счёте пробелов стояли
    // как настоящая работа.
    //
    // **Два ключа не переведены нарочно и остаются пробелами:**
    // `контроль через %lld нед.` и `контроль через %lld–%lld нед.`.
    // Им нужны формы числа — украинскому четыре, французскому две, —
    // и у Togo уже записано, чем кончается, когда формы ставят
    // «чтобы были»: четыре совпавшие до буквы формы читаются так,
    // будто вопрос задали и ответили. Отдаю носителю.
    //
    // Вычиткой эта правка не является и за вычитку не засчитывается —
    // как и записи от 24.09, 28.09, 30.09 и 05.10 выше.
    private static let долг: [String: Int] = ["uk": 2217, "fr": 239, "ru": 72, "en": 2217]

    @Test("Непроверенных переводов не становится больше")
    func непроверенныхНеБольше() throws {
        var посчитано: [String: Int] = [:]
        var примеры: [String: String] = [:]
        for запись in try каталог() {
            for (язык, состояние) in запись.состояния
            where состояние == "needs_review" || состояние == "new" {
                посчитано[язык, default: 0] += 1
                if примеры[язык] == nil { примеры[язык] = String(запись.ключ.prefix(60)) }
            }
        }

        for (язык, сколько) in посчитано.sorted(by: { $0.key < $1.key }) {
            let разрешено = Self.долг[язык] ?? 0
            #expect(сколько <= разрешено, """
                [\(язык)] непроверенных \(сколько) при долге \(разрешено),
                например: \(примеры[язык] ?? "—").
                Правку числа в долге считать вычиткой нельзя.
                """)
        }

        // Долг, которого больше нет, надо убирать: иначе он разрешает
        // вернуть то, что уже вычитано.
        let протухшие = Self.долг.keys.filter { посчитано[$0] == nil }.sorted()
        #expect(протухшие.isEmpty,
                "в долге числятся языки без непроверенных строк: \(протухшие). Убери их.")
    }

    /// Сколько в каталоге пар «тот же текст, другой спецификатор».
    /// Замер 05.10.2026. Число может только уменьшаться.
    private static let двойников = 74

    /// Один и тот же текст не должен лежать под двумя ключами.
    ///
    /// **Замер 05.10.2026, и он объясняет половину дневной работы.**
    /// `«Дальше · %@»` и `«Дальше · %lld»` — это один текст и два ключа.
    /// Живой ровно один: подставляется целое число, и компилятор
    /// извлекает `%lld`. Второй завёл когда-то `Tools/extract_texts.py`,
    /// который типа подставляемого не знает и ставит `%@` всегда.
    ///
    /// Почему мёртвый не исчезает сам: у рукописных ключей стоит
    /// `"extractionState": "manual"`, и Xcode их **не вычищает** —
    /// проверено в тот же день на `«переходит%@ · %lld»`, который
    /// извлечение убрало само, как только пропал из кода, потому что
    /// `manual` у него не стояло.
    ///
    /// Цена: перевод уезжает в мёртвую половину и на экран не попадает,
    /// а живая выглядит непереведённой. Сорок четыре французские строки
    /// из девяноста восьми, закрытых 05.10, лежали готовыми именно так —
    /// под ключом, которого приложение не спрашивает.
    ///
    /// > **Ключ, которого компилятор не находит, — не «запас на всякий
    /// > случай», а место, куда уходит работа.**
    ///
    /// Сторож — на число, а не на список: список из семидесяти четырёх
    /// пар читать не станет никто. Удалять мёртвую половину нельзя
    /// вслепую: доказательством служит не отсутствие ключа в коде,
    /// а наличие живого двойника, — поэтому пары снимаются по одной,
    /// с проверкой места вызова, и число идёт вниз.
    @Test("Ключей-двойников по спецификатору не становится больше")
    func двойниковНеБольше() throws {
        let записи = try каталог()
        #expect(записи.count > 500, "каталог прочитан не весь (\(записи.count) ключей)")

        func безТипа(_ ключ: String) -> String {
            ключ.replacingOccurrences(
                of: "%(\\d+\\$)?lld", with: "%@", options: .regularExpression)
                .replacingOccurrences(of: "%%", with: "%")
        }

        var группы: [String: [String]] = [:]
        for запись in записи { группы[безТипа(запись.ключ), default: []].append(запись.ключ) }
        let пары = группы.filter { $0.value.count > 1 }

        #expect(пары.count <= Self.двойников, """
            пар «тот же текст, другой спецификатор»: \(пары.count) \
            при замере \(Self.двойников).

            \(пары.values.sorted { $0[0] < $1[0] }.prefix(5)
                .map { "  " + $0.sorted().joined(separator: "  ↔  ") }
                .joined(separator: "\n"))

            Живой ключ — тот, что извлёк компилятор (`%lld` у целого).
            Второй собирает переводы, которых никто не увидит.
            """)
    }

    /// У каждого языка бандла есть имя на экране «Язык».
    ///
    /// **Замер 05.10.2026: украинского в списке имён не было.** Ряд
    /// не падал и не пустовал — он подписывался кодом, «UK», между
    /// «Русский» и «Français», при 2044 переведённых строках. Код вместо
    /// имени читается не дырой, а решением: будто язык служебный.
    ///
    /// Сторож нужен именно здесь: словарь имён — **список руками**,
    /// а языки приходят из бандла. Такая пара расходится молча, и уже
    /// расходилась у Gamut, где список руками не знал про украинский.
    ///
    /// **Сверка только в одну сторону, и это замер, а не лень.** Первая
    /// редакция проверяла и обратное — «имя есть, языка в бандле нет», —
    /// и через десять минут упала на `en`: в бандле лежал `en.lproj`
    /// с единственным файлом `nlu.appintents`, который Xcode порождает
    /// для английского сам.
    ///
    /// Четыре сборки 05.10.2026, `en.lproj` был **в одной**:
    /// `DerivedData` — нет, `dd` — **есть**, `dd-verify` (каталог стёрт
    /// перед сборкой) — нет, архив 28.09 — нет. Догадка «чистая против
    /// инкрементальной» опровергнута третьей: она чистая и без `en`.
    ///
    /// > **`Bundle.main.localizations` не одинаков у разных сборок
    /// > одного кода, и предсказать этого мы не умеем.** Обратная сверка
    /// > поэтому была бы красной то здесь, то там — без всякой правки
    /// > кода, то есть учила бы не верить красному.
    ///
    /// Рядом с этим стоит старое «несколько русских языков»
    /// из `СТАТУС.md`, помеченное как «не воспроизводится по коду»:
    /// по коду оно и не воспроизведётся.
    ///
    /// Прямая сторона держится при любой сборке и ловит то, ради чего
    /// завели: язык в бандле без имени подписывается кодом.
    @Test("У каждого языка бандла есть имя")
    func уЯзыковБандлаЕстьИмена() {
        let языкиБандла = Set(Bundle.main.localizations).subtracting(["Base"])
        #expect(языкиБандла.count >= 2, """
            языков в бандле \(языкиБандла.sorted()) — меньше двух,
            разбор не состоялся.
            """)

        let безымянные = языкиБандла.subtracting(LanguageScreen.names.keys).sorted()
        #expect(безымянные.isEmpty, """
            язык есть в бандле, а имени у него нет: \(безымянные).

            В настройках он подпишется кодом в верхнем регистре —
            `LanguageScreen.names`. Имя пишется на самом языке.
            """)

        // `en` появляется только на чистой сборке, поэтому требуем имя
        // для него всегда: иначе сторож зелёный на инкрементальной
        // и красный на той, из которой собирают архив.
        #expect(LanguageScreen.names["en"] != nil, """
            у `en` нет имени. Он приходит в бандл с `nlu.appintents`
            на чистой сборке — то есть ровно на той, из которой
            собирают архив.
            """)
    }
