import Testing
import Foundation
import CloudKit
@testable import Togo

/// Приём приглашения говорит человеку, чем он кончился.
///
/// # Что было до 08.10.2026
///
/// `ShareAcceptance.accept` на отказе делал `log.notice` и больше
/// ничего. Приложение открывалось обычным, гость считал, что вошёл,
/// и узнал бы обратное, не увидев ни одной записи и решив, что дневник
/// пуст.
///
/// > **Снаружи «принялось» и «не принялось» были неотличимы.**
/// > Различал только журнал устройства, а он достаётся по кабелю.
///
/// # Почему причин четыре
///
/// Совет у них разный, и три из четырёх человеку помогают по-разному:
/// «попробуй ещё раз» при отсутствии сети, «войди в iCloud» при
/// невходе, и **«дело не в твоих настройках»**, когда виноваты мы.
/// Один текст на три причины даёт совет, неверный для двух — это хуже
/// молчания, потому что молчание заставляет спросить, а неверный совет
/// — попробовать и увериться.
///
/// Четвёртая, `.неизвестно`, честнее трёх угадываний: выбрать одну
/// из трёх, не умея отличить, значит дать неверный совет с уверенным
/// лицом.
@Suite("Приём приглашения говорит, чем кончился")
@MainActor
struct ПриёмПриглашенияГоворитTests {

    private let отказы: [ShareAcceptanceOutcome] = [
        .нетСети, .iCloudПросилПодождать, .нетiCloud, .сторонаПриложения, .неизвестно
    ]

    @Test("У каждой причины свой текст, и ни один не повторяет другой")
    func текстыРазные() {
        let тексты = отказы.map(\.текст)

        #expect(тексты.count >= 5, "причин меньше пяти — проверять нечего")
        #expect(Set(тексты).count == тексты.count, """
            две причины отказа говорят ОДНО И ТО ЖЕ: \(тексты).
            Один текст на несколько причин даёт совет, неверный для \
            остальных, — и это хуже молчания.
            """)
        for текст in тексты {
            #expect(текст.count > 20, "текст «\(текст)» слишком короткий, чтобы нести совет")
        }
    }

    /// Самая дорогая из четырёх: когда виноваты мы.
    @Test("При нашей вине человека НЕ отправляют в его настройки")
    func нашаВинаНеОтправляетВНастройки() {
        let текст = ShareAcceptanceOutcome.сторонаПриложения.текст

        #expect(текст.localizedCaseInsensitiveContains("не в тво"), """
            при отказе на нашей стороне человеку не сказано, что дело \
            не в нём: «\(текст)».
            22.09.2026 сборка сказала «iCloud недоступен» четверым, \
            и причину выясняли догадками.
            """)
        for ложныйСовет in ["Войди", "войди в iCloud", "настройках телефона"] {
            #expect(!текст.contains(ложныйСовет), """
                при нашей вине человеку советуют «\(ложныйСовет)» — \
                совет, который не помогает. Совет не ставят там, \
                где он не работает.
                """)
        }
    }

    @Test("Незнакомый отказ даёт «не знаем почему», а не ближайшую похожую причину")
    func незнакомыйОтказНеПодгоняется() {
        let чужая = NSError(domain: "ЧтоТоСовсемДругое", code: 42)
        #expect(ShareAcceptanceOutcome.причина(чужая) == .неизвестно)

        // И у CloudKit-кода, которого мы не разбирали, — тоже.
        //
        // Здесь стоял `zoneBusy`, и 29.10.2026 он стал разобранным:
        // это просьба подождать (`.iCloudПросилПодождать`). Предмет
        // теста — «незнакомый не подгоняется», поэтому код заменён
        // на заведомо не наш: про файл ассета приём не знает ничего.
        let неразобранный = CKError(.assetFileNotFound)
        #expect(ShareAcceptanceOutcome.причина(неразобранный) == .неизвестно, """
            неразобранный код CloudKit подогнан под знакомую причину. \
            Подгонять незнакомый отказ под знакомый совет — то же самое, \
            что один текст на три причины, только незаметнее.
            """)
        #expect(ShareAcceptanceOutcome.неизвестно.текст.localizedCaseInsensitiveContains("не знаем"), """
            причина «неизвестно» не говорит, что мы не знаем, — \
            а именно это и есть честный ответ.
            """)
    }

    @Test("Знакомые коды разбираются по своим причинам")
    func знакомыеКодыРазбираются() {
        #expect(ShareAcceptanceOutcome.причина(CKError(.networkUnavailable)) == .нетСети)
        #expect(ShareAcceptanceOutcome.причина(CKError(.networkFailure)) == .нетСети)
        // Просьба подождать — НЕ «нет связи» (29.10.2026): связь есть,
        // а «попробуй ещё раз» сразу эту просьбу продлевает.
        for код in [CKError.Code.requestRateLimited, .zoneBusy, .serviceUnavailable] {
            #expect(ShareAcceptanceOutcome.причина(CKError(код)) == .iCloudПросилПодождать, """
                код \(код.rawValue) — просьба iCloud подождать, а разобран \
                иначе. Человек со связью пошёл бы чинить связь.
                """)
        }
        #expect(ShareAcceptanceOutcome.причина(CKError(.notAuthenticated)) == .нетiCloud)
        #expect(ShareAcceptanceOutcome.причина(CKError(.permissionFailure)) == .сторонаПриложения)
        #expect(ShareAcceptanceOutcome.причина(CKError(.unknownItem)) == .сторонаПриложения)
    }

    /// Успех обязан назвать, ЧЕЙ дневник открыт.
    @Test("Успех называет имя владельца, а не «общий дневник»")
    func успехНазываетЧей() {
        let сИменем = ShareAcceptanceOutcome.принято(чей: "Виктория").текст
        #expect(сИменем.contains("Виктория"), """
            успех не называет, чей дневник открыт: «\(сИменем)». \
            Гость приходит по ссылке и видит чужие записи о чужой собаке — \
            «вы в общем дневнике» не отвечает на вопрос, в чьём именно.
            """)
    }

    /// И обратная половина: имени может не быть.
    @Test("Имени нет — это сказано прямо, а не спрятано")
    func безымянныйСлучайНазван() {
        for пусто in [nil, "", "   "] {
            let текст = ShareAcceptanceOutcome.принято(чей: пусто).текст
            #expect(текст.localizedCaseInsensitiveContains("не знает"), """
                владелец без имени подан как обычный успех: «\(текст)». \
                CloudKit отдаёт `nameComponents` не всегда, и молчание \
                здесь читается как «дневник ничей».
                """)
        }
    }

    /// Пробел перевода, заведённый ЯВНО.
    ///
    /// **Этот тест рождён красным нарочно, и это не недоделка.**
    /// Пять новых строк написаны по-русски 08.10.2026; переводов нет
    /// ни на одном из трёх языков. Решение Виктории — путь 1: строки
    /// заводим, пробелы называем явно, долг краснеет честно.
    ///
    /// # Почему без него долг был бы НЕВИДИМЫМ
    ///
    /// `LocalizationCoverageTests` меряет пробелы **среди ключей,
    /// о которых каталогу рассказали**, а ключи интерполированных
    /// строк заводит извлечение (`xcodebuild -exportLocalizations`),
    /// а не компилятор и не скрипт. Пока извлечение не прогнали,
    /// каталог моих строк не знает — и сторож полноты честно печатает
    /// «пробелов нет».
    ///
    /// ```
    /// пробел виден как дыра
    /// ОТСУТСТВУЮЩИЙ КЛЮЧ виден как полнота
    /// ```
    ///
    /// Цена — не абзац в CI: пробел откатывается на язык разработки,
    /// то есть **француз увидит русский текст ровно тогда, когда
    /// у него не открылось приглашение**. Худший момент из возможных.
    ///
    /// Снимается одним из двух: прогнать извлечение и перевести, либо
    /// перевести и внести ключи. Хозяин — **перевод**, запись в
    /// `Tools/эталон-прогона.json`.
    @Test("Пять новых строк приёма приглашения есть в каталоге")
    func строкиПриёмаЕстьВКаталоге() throws {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let каталог = try String(contentsOf: url, encoding: .utf8)

        // Контроль: каталог прочитан и это он, а не пустота. Без этого
        // «ключей нет» означало бы отказ чтения, а не отсутствие ключей.
        #expect(каталог.count > 10_000, """
            каталог прочитан на \(каталог.count) знаков — чтение \
            не состоялось, и «ключей нет» ниже сказало бы про инструмент.
            """)

        let мои = [
            "нет связи",
            "не выполнен вход в iCloud",
            "дело не в твоих настройках",
            "мы не знаем почему",
            "ты в дневнике",
        ]
        let нет = мои.filter { !каталог.contains($0) }
        #expect(нет.isEmpty, """
            каталог не знает \(нет.count) из \(мои.count) строк приёма \
            приглашения: \(нет.joined(separator: " · ")).

            Это НЕ пробел перевода — это отсутствующий ключ, и сторож \
            полноты его не видит по устройству. Француз увидит русский \
            текст в тот момент, когда у него не открылось приглашение.

            Снять: прогнать `xcodebuild -exportLocalizations` и перевести. \
            Хозяин — перевод.
            """)
    }

    @Test("Принято и не принято различимы по самому исходу")
    func исходРазличим() {
        #expect(ShareAcceptanceOutcome.принято(чей: "Аня").принято_ли)
        for отказ in отказы {
            #expect(!отказ.принято_ли, "\(отказ) считается принятым")
        }
    }
}
