import Testing
import Foundation
@testable import Togo

/// Расписание приёма — предписание врача, и приложение его не двигает.
///
/// # Что было
///
/// Лист пропущенной дозы говорил: «Следующая **сдвинется** на 22:40 —
/// интервал 6 ч». Это было обещание, которого приложение не выполняет:
/// `MissedDose.nextIfGivenNow` — расчёт «куда бы она попала, если бы
/// схема двигалась», а схема не двигается.
///
/// Проверено кодом, а не предположено: `Medication.times` меняет
/// единственный путь — явная смена схемы (`ScheduleChange`), отметка
/// приёма не трогает расписание ничем.
///
/// > **Цена не косметическая.** Человек прочитал бы, что вечерняя доза
/// > уехала на 22:40, и не дал бы её в 21:00, когда она на самом деле
/// > стоит. Текст не «неточный» — он назначает другое лечение.
///
/// Решение Виктории 08.10.2026: **сдвигается только окно натощак**,
/// расписание — предписание врача. Отсюда А4: назвать близость
/// следующей дозы, НЕ сдвигая её.
///
/// # Почему сторож текстовый
///
/// Предмет — то, что человек прочтёт. Величины (`nextScheduled`,
/// `nextIfGivenNow`) посчитаны верно и были верны всё это время;
/// неверен был **выбор**, какую из двух показать. Такое ловится
/// только на строке.
@Suite("Расписание приёма не сдвигается")
struct РасписаниеНеСдвигаетсяTests {

    private static func лист() throws -> String {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features/Health/MissedDoseSheet.swift")
        return try String(contentsOf: url, encoding: .utf8)
    }

    /// Код без комментариев: в этом файле «сдвинется» стоит в прозе,
    /// объясняя, почему так говорить нельзя. Сторож, не различающий
    /// код и прозу, покраснел бы на самом объяснении.
    private static func кодБезПрозы(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    @Test("Разбор состоялся: проза отделена от кода листа расписания")
    func былоЧтоСторожить() throws {
        let весь = try Self.лист()
        let код = Self.кодБезПрозы(весь)

        #expect(код.count > 500, """
            разбор дал \(код.count) знаков — файл не прочитан или \
            вырезание съело код целиком.
            """)
        // Контроль: слово ЕСТЬ в прозе и обязано исчезнуть после
        // вырезания. Без него проверка ниже проходит на пустом месте.
        #expect(весь.contains("сдвинется"), """
            в файле больше нет слова «сдвинется» даже в объяснении — \
            контроль пропал, и проверка ниже ничего не доказывает.
            """)
    }

    @Test("Человеку не обещают, что следующая доза сдвинется")
    func сдвигНеОбещают() throws {
        let код = Self.кодБезПрозы(try Self.лист())

        #expect(!код.contains("сдвинется"), """
            лист пропущенной дозы снова обещает сдвиг расписания. \
            Приложение его не делает: `Medication.times` меняет только \
            явная смена схемы. Человек прочтёт, что доза уехала, \
            и не даст её вовремя.
            """)
    }

    /// Утвердительная половина: близость обязана быть НАЗВАНА.
    ///
    /// Без неё «сдвиг не обещают» выполнялось бы и на пустом листе —
    /// то есть и тогда, когда человеку не говорят вообще ничего.
    @Test("Близость следующей дозы названа, и названа по расписанию")
    func близостьНазвана() throws {
        let код = Self.кодБезПрозы(try Self.лист())

        #expect(код.contains("nextScheduled"), """
            лист не показывает `nextScheduled` — то есть не называет \
            ту дозу, которая правда стоит в расписании.
            """)
        #expect(код.contains("Следующая по схеме"), """
            в листе нет строки про следующую дозу по схеме. Назвать \
            близость — половина А4; без неё человек не узнает, \
            что доза рядом.
            """)
        #expect(код.contains("Схема не сдвигается") || код.contains("схема не сдвигается"), """
            лист не говорит прямо, что схема не сдвигается. Молчание \
            здесь читается как «сдвинется»: прежний текст приучил \
            именно к этому.
            """)
    }
}
