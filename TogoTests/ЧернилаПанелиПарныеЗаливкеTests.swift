import Testing
import SwiftUI
@testable import Togo

/// Чернила панели показания читаются **на своей заливке**.
///
/// ## Зачем отдельный набор, когда контраст уже сторожат четыре
///
/// Потому что ни один из них не меряет **пару**. Замер 25.10.2026:
///
/// ```
/// чернила натощак уехали на палитру Виктории   labelOnFasting   #2A1D00
/// заливка осталась на нашей                    status.waitingBg #4A300A
/// контраст ПАРЫ                                1,35
/// доложено было                                «1,92 → 8,59»
/// на её панели #FFC233                         10,22   (её счёт 10,2)
/// ```
///
/// Правка, закрывавшая нечитаемость, сделала её **хуже** — и обе
/// стороны по отдельности выглядели верными: чернила ссылались
/// на её палитру, заливка ссылалась на живой токен того же смысла.
///
/// > **Перевести половину пары опаснее, чем не переводить вовсе.**
/// > Цвет виден только в паре, а грепом пара не ищется — ищутся два
/// > имени, и оба живые. Сторож на сторону такое не ловит
/// > по устройству: у каждой стороны своё значение верное.
///
/// Ось здесь — **отношение двух токенов**, не значение одного.
/// Поэтому набор краснеет и когда подменят чернила, и когда подменят
/// заливку, и остаётся зелёным, пока их меняют вместе.
///
/// ## Чего набор НЕ меряет
///
/// Он меряет **токены, которые читает `ReadingPanel`**, а не пиксель
/// на экране. Между ними живут `opacity` на месте вызова, наложение
/// стеклом и подкраска фотографии — их видно только на кадре.
/// Доккомментарий `ThemeContrastTests` говорит то же про себя.
///
/// И отдельно: `.alarm` берёт чернила `labelOnColor`, общие с плакатом,
/// а не свои. Это не находка — так в исходнике; если значение разойдётся
/// с панелью тревоги, покраснеет здесь.
@Suite("Чернила панели показания парны своей заливке")
struct ЧернилаПанелиПарныеЗаливкеTests {

    private struct Пара {
        let тон: String
        let заливка: Color
        let показание: Color
        let подпись: Color
    }

    /// Тон, его заливка и обе роли текста на ней.
    ///
    /// Составлено **по исходнику** `ReadingPanel.заливкаПанели`,
    /// `чернила` и `чернилаПодписи`, а не по смыслу имён: у `.alarm`
    /// чернила общие с плакатом, и угадать это нельзя.
    private static let пары: [Пара] = [
        Пара(тон: "натощак", заливка: Token.Poster.panelFasting,
             показание: Token.Poster.labelOnFasting,
             подпись: Token.Poster.captionOnFasting),
        Пара(тон: "доза", заливка: Token.Poster.panelDose,
             показание: Token.Poster.labelOnDose,
             подпись: Token.Poster.captionOnDoseTone),
        Пара(тон: "тревога", заливка: Token.Poster.panelAlarm,
             показание: Token.Poster.labelOnColor,
             подпись: Token.Poster.captionOnAlarmTone),
    ]

    /// Порог. 4,5 — текст по WCAG 1.4.3; показание 112 pt формально
    /// крупное (хватило бы 3:1), но порог берём общий и строгий:
    /// подпись рядом с ним мелкая, а разводить два порога на одной
    /// панели значит заводить две копии решения.
    private static let порог = 4.5

    /// Четыре пары, не берущие порог, и **все четыре — в светлых
    /// режимах**.
    ///
    /// ```
    /// light   · доза    · подпись   4,29
    /// light   · тревога · подпись   3,92
    /// lightHC · доза    · подпись   4,29
    /// lightHC · тревога · подпись   3,92
    /// ```
    ///
    /// **Что держит:** значения подписи Виктории белые (`#FFFFFFE0`)
    /// и рассчитаны на тёмную тему. В светлой панель composited
    /// светлеет, и белое по ней падает. Светлая тема на устройство
    /// **не попадает** — `UIUserInterfaceStyle = Dark` стоит в обоих
    /// plist (решение «Кино. Одна тема», 23.10.2026), поэтому человек
    /// этого не видит.
    ///
    /// **Хозяин — Виктория.** Цена в обе стороны: оставить — макет
    /// показывает дизайнеру нечитаемую пару, и применивший получит
    /// её в Фигме; поправить — это новые светлые значения, и называет
    /// их она. Та же развилка, что у записи эталона про подпись
    /// плаката в светлом HC.
    ///
    /// > **Исключение обязано доказывать, что оно ещё нужно.** Иначе
    /// > это прокси: пара починится, список останется, и следующий
    /// > провал спрячется за старым именем. Поэтому ниже стоит тест
    /// > `исключенияВсёЕщёНужны` — он краснеет, когда пара ВЫШЛА
    /// > на порог, а имя из списка не убрали.
    private static let известныеСветлые: Set<String> = [
        "Light · доза · подпись",
        "Light · тревога · подпись",
        "Light HC · доза · подпись",
        "Light HC · тревога · подпись",
    ]

    // MARK: Было ли что мерить

    /// **Первым номером: было ли что мерить.**
    ///
    /// Без этого тесты ниже не проверяют ничего: пустой список пар
    /// даёт «ноль провалов». Плюс контроль самого счёта — его ответ
    /// известен заранее и не зависит ни от одного нашего токена.
    @Test("Пары, режимы и счёт на месте, иначе ниже мерить нечего")
    func былоЧтоМерить() {
        #expect(Self.пары.count == 3, """
            пар \(Self.пары.count), а тонов, красящих панель, три
            (`ReadingPanel.заливкаПанели`). Разошлось — значит либо
            тон добавили и сюда не внесли, либо список обрезан.
            """)
        #expect(ThemeContrastTests.режимы.count == 4, """
            режимов \(ThemeContrastTests.режимы.count) вместо четырёх:
            пара обязана держаться в каждом, HC-значения у дозы
            и тревоги РАЗНЫЕ.
            """)

        let k = ThemeContrastTests.контраст(.black, на: .white,
                                            режим: ThemeContrastTests.режимы[0])
        #expect(k > 20.9, """
            счёт контраста отвечает \(Self.два(k)) там, где обязан
            ответить 21,00 (чёрное на белом). Значит ВСЁ, что ниже,
            ничего не утверждает — числа пришли от сломанного счёта.
            """)
    }

    // MARK: Предмет

    @Test("Показание читается на своей заливке во всех четырёх режимах")
    func показаниеНаЗаливке() {
        проверить(роль: "показание") { $0.показание }
    }

    @Test("Подпись читается на своей заливке; светлые — по именам")
    func подписьНаЗаливке() {
        проверить(роль: "подпись") { $0.подпись }
    }

    /// Разные тоны обязаны быть РАЗЛИЧИМЫ между собой.
    ///
    /// Иначе пара формально цела, а человек не видит разницы между
    /// дозой и тревогой.
    @Test("Три заливки панели различимы между собой")
    func заливкиРазличимы() {
        var провалы: [String] = []
        var осмотрено = 0
        for режим in ThemeContrastTests.режимы {
            for i in Self.пары.indices {
                for j in Self.пары.indices where j > i {
                    осмотрено += 1
                    let k = ThemeContrastTests.контраст(Self.пары[i].заливка,
                                                        на: Self.пары[j].заливка,
                                                        режим: режим)
                    if k < 1.3 {
                        провалы.append("\(режим.имя) · \(Self.пары[i].тон) ↔ "
                                       + "\(Self.пары[j].тон) · \(Self.два(k)) "
                                       + "НЕ ХВАТАЕТ до 1,30")
                    }
                }
            }
        }
        #expect(осмотрено == 12, "осмотрено \(осмотрено) сочетаний вместо 12")
        #expect(провалы.isEmpty, """
            заливки двух тонов неразличимы:
            \(провалы.joined(separator: "\n"))
            """)
    }

    // MARK: Исключения обязаны доказывать, что ещё нужны

    /// Четвёртая корзина: **погасший прокси**. Пара вышла на порог,
    /// а имя из списка исключений не убрали — и следующий провал
    /// спрячется за ним молча.
    @Test("Каждое светлое исключение всё ещё не берёт порог")
    func исключенияВсёЕщёНужны() {
        var лишние: [String] = []
        var проверено = 0
        for режим in ThemeContrastTests.режимы {
            for пара in Self.пары {
                let адрес = "\(режим.имя) · \(пара.тон) · подпись"
                guard Self.известныеСветлые.contains(адрес) else { continue }
                проверено += 1
                let k = ThemeContrastTests.контраст(пара.подпись, на: пара.заливка,
                                                    режим: режим)
                if k >= Self.порог {
                    лишние.append("\(адрес) · \(Self.два(k)) УЖЕ ВЫХОДИТ")
                }
            }
        }
        #expect(проверено == Self.известныеСветлые.count, """
            из \(Self.известныеСветлые.count) имён в списке нашлось
            только \(проверено). Имя, которого нет среди живых пар,
            не исключение, а опечатка — и она ничего не покрывает,
            зато выглядит покрытием.
            """)
        #expect(лишние.isEmpty, """
            исключение больше не нужно — убери имя из `известныеСветлые`:
            \(лишние.joined(separator: "\n"))

            Пока имя стоит, провал в этой паре будет считаться
            ожидаемым, и следующая поломка спрячется за ним.
            """)
    }

    // MARK: Счёт

    private func проверить(роль: String, _ взять: (Пара) -> Color) {
        var провалы: [String] = []
        var осмотрено = 0
        for режим in ThemeContrastTests.режимы {
            for пара in Self.пары {
                осмотрено += 1
                let адрес = "\(режим.имя) · \(пара.тон) · \(роль)"
                let k = ThemeContrastTests.контраст(взять(пара), на: пара.заливка,
                                                    режим: режим)
                // Слово исхода рядом с числом, в ТОЙ ЖЕ строке: «4,12»
                // без него читается как успех у того, кто не помнит порог.
                if k < Self.порог, !Self.известныеСветлые.contains(адрес) {
                    провалы.append("\(адрес) · \(Self.два(k)) НЕ ХВАТАЕТ "
                                   + "до \(Self.два(Self.порог))")
                }
            }
        }
        #expect(осмотрено == Self.пары.count * ThemeContrastTests.режимы.count,
                "осмотрено \(осмотрено) пар вместо ожидаемых 12 — замер не состоялся")
        #expect(провалы.isEmpty, """
            \(роль) не читается на своей заливке:
            \(провалы.joined(separator: "\n"))

            Это пара «чернила ↔ заливка», и покраснеть она могла
            с ЛЮБОЙ стороны. Прежде чем править цвет, посмотри,
            не перевели ли на новую палитру только одну половину:
            ровно так появились 1,35 у натощак 25.10.2026.
            """)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.2f", x).replacingOccurrences(of: ".", with: ",")
    }
}
