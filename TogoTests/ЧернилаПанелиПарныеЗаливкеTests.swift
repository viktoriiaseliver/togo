    /// Чип состояния и главная кнопка — там, где 1,00 и жило.
    ///
    /// Исключений здесь **нет ни одного**, и это замер: все двадцать
    /// сочетаний выходят, минимум 4,64 (тревога в тёмной и Dark HC).
    /// Пустой список исключений — утверждение, а не умолчание: если
    /// он понадобится, его заведут с причиной и хозяином.
    @Test("Чип и главная кнопка читаются на своих заливках, без исключений")
    func второйЭтажЧитается() {
