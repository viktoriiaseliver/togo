    /// Разные тоны обязаны быть РАЗЛИЧИМЫ между собой.
    ///
    /// Иначе пара формально цела, а человек не видит разницы между
    /// дозой и тревогой.
    ///
    /// # Ось здесь ΔE, и это исправление моего же сторожа
    ///
    /// Первая редакция спрашивала различимость **отношением WCAG**
    /// и покраснела на здоровом коде:
    ///
    /// ```
    /// Dark    · доза ↔ тревога   1,07   ← отношение WCAG
    /// Dark HC · доза ↔ тревога   1,04
    /// те же пары по ΔE76         133,1 и 124,1
    /// ```
    ///
    /// Синий `#1F4FFF` и красный `#D52519` почти равны **по яркости**,
    /// а отношение WCAG яркость и меряет — в нём нет тона вовсе.
    /// Замер был верен, вопрос не тот.
    ///
    /// > **Инструмент, взятый у соседней задачи, приносит её ось.**
    /// > Контраст лежал рядом, был проверен и уже считал composited-пары
    /// > — поэтому и подошёл на вид. Читаемость текста на фоне и
    /// > различимость двух фонов — разные вопросы, и общего у них
    /// > только слово «цвет».
    ///
    /// Порог 20 при измеренном минимуме 65,4 (натощак ↔ тревога):
    /// запас троекратный, и поймает он то, чего мы боимся на самом
    /// деле — два токена, нацеленных на один примитив (тогда ΔE = 0).
    /// Контроли оси: чёрное ↔ белое даёт 100,0 (весь диапазон `L`),
    /// цвет сам с собой — 0,0.
    @Test("Три заливки панели различимы между собой по ΔE")
    func заливкиРазличимы() {
        var провалы: [String] = []
        var осмотрено = 0
        for режим in ThemeContrastTests.режимы {
            for i in Self.пары.indices {
                for j in Self.пары.indices where j > i {
                    осмотрено += 1
                    let e = Self.дельтаE(Self.пары[i].заливка, Self.пары[j].заливка,
                                         режим: режим)
                    if e < Self.порогΔE {
                        провалы.append("\(режим.имя) · \(Self.пары[i].тон) ↔ "
                                       + "\(Self.пары[j].тон) · ΔE \(Self.два(e)) "
                                       + "НЕ ХВАТАЕТ до \(Self.два(Self.порогΔE))")
                    }
                }
            }
        }
        #expect(осмотрено == 12, "осмотрено \(осмотрено) сочетаний вместо 12")

        // Контроль оси в том же замере: ответ известен заранее
        // и не зависит ни от одного нашего токена.
        let предел = Self.дельтаE(.black, .white, режим: ThemeContrastTests.режимы[0])
        let сСобой = Self.дельтаE(Self.пары[0].заливка, Self.пары[0].заливка,
                                  режим: ThemeContrastTests.режимы[0])
        #expect(предел > 99, """
            ΔE чёрного и белого \(Self.два(предел)) вместо 100,00 —
            счёт сломан, и всё выше ничего не утверждает.
            """)
        #expect(сСобой < 0.01, """
            ΔE цвета с самим собой \(Self.два(сСобой)) вместо нуля —
            счёт сломан в другую сторону: он покажет различие там,
            где два токена нацелены на один примитив.
            """)

        #expect(провалы.isEmpty, """
            заливки двух тонов неразличимы:
            \(провалы.joined(separator: "\n"))
            """)
    }

    /// Порог различимости двух заливок. ΔE76; 10 принято за «явно
    /// разные цвета», берём 20 при измеренном минимуме 65,4.
    private static let порогΔE = 20.0

    /// ΔE76 между двумя цветами, **наложенными на страницу**: альфа
    /// у всех трёх заливок 0,92, и без наложения число было бы
    /// про цвет, которого на экране нет.
    private static func дельтаE(_ a: Color, _ b: Color,
                                режим: ThemeContrastTests.Режим) -> Double {
        let la = лаб(a, режим: режим, на: Token.Surface.screen)
        let lb = лаб(b, режим: режим, на: Token.Surface.screen)
        return ((la.0 - lb.0) * (la.0 - lb.0)
                + (la.1 - lb.1) * (la.1 - lb.1)
                + (la.2 - lb.2) * (la.2 - lb.2)).squareRoot()
    }

    private static func лаб(_ цвет: Color, режим: ThemeContrastTests.Режим,
                            на фон: Color?) -> (Double, Double, Double) {
        var c = rgba(цвет, режим)
        if let фон {
            let н = rgba(фон, режим)
            let a = c.3
            c = (c.0 * a + н.0 * (1 - a), c.1 * a + н.1 * (1 - a),
                 c.2 * a + н.2 * (1 - a), 1)
        }
        func лин(_ x: Double) -> Double {
            x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4)
        }
        let r = лин(c.0), g = лин(c.1), b = лин(c.2)
        let x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
        let y = 0.2126 * r + 0.7152 * g + 0.0722 * b
        let z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
        func ф(_ t: Double) -> Double {
            t > 0.008856 ? pow(t, 1.0 / 3.0) : 7.787 * t + 16.0 / 116.0
        }
        let fx = ф(x), fy = ф(y), fz = ф(z)
        return (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))
    }

    private static func rgba(_ цвет: Color,
                             _ режим: ThemeContrastTests.Режим)
        -> (Double, Double, Double, Double) {
        #if canImport(UIKit)
        let hex = цвет.resolvedHex(dark: режим.тёмная, highContrast: режим.контраст)
        return (Double((hex >> 24) & 0xFF) / 255, Double((hex >> 16) & 0xFF) / 255,
                Double((hex >> 8) & 0xFF) / 255, Double(hex & 0xFF) / 255)
        #else
        return (0, 0, 0, 1)
        #endif
    }

    // MARK: Исключения обязаны доказывать, что ещё нужны

    /// Четвёртая корзина: **погасший прокси**. Пара вышла на порог,
    /// а имя из списка исключений не убрали — и следующий провал
    /// спрячется за ним молча.
    @Test("Каждое светлое исключение всё ещё не берёт порог")
    func исключенияВсёЕщёНужны() {
        var лишние: [String] = []
        var проверено = 0
        for режим in ThemeContrastTests.режимы {
            for пара in Self.пары {
                let адрес = "\(режим.имя) · \(пара.тон) · подпись"
                guard Self.известныеСветлые.contains(адрес) else { continue }
                проверено += 1
                let k = ThemeContrastTests.контраст(пара.подпись, на: пара.заливка,
                                                    режим: режим)
                if k >= Self.порог {
                    лишние.append("\(адрес) · \(Self.два(k)) УЖЕ ВЫХОДИТ")
                }
            }
        }
        #expect(проверено == Self.известныеСветлые.count, """
            из \(Self.известныеСветлые.count) имён в списке нашлось
            только \(проверено). Имя, которого нет среди живых пар,
            не исключение, а опечатка — и она ничего не покрывает,
            зато выглядит покрытием.
            """)
        #expect(лишние.isEmpty, """
            исключение больше не нужно — убери имя из `известныеСветлые`:
            \(лишние.joined(separator: "\n"))

            Пока имя стоит, провал в этой паре будет считаться
            ожидаемым, и следующая поломка спрячется за ним.
            """)
    }

    // MARK: Счёт

    private func проверить(роль: String, _ взять: (Пара) -> Color) {
        var провалы: [String] = []
        var осмотрено = 0
        for режим in ThemeContrastTests.режимы {
            for пара in Self.пары {
                осмотрено += 1
                let адрес = "\(режим.имя) · \(пара.тон) · \(роль)"
                let k = ThemeContrastTests.контраст(взять(пара), на: пара.заливка,
                                                    режим: режим)
                // Слово исхода рядом с числом, в ТОЙ ЖЕ строке: «4,12»
                // без него читается как успех у того, кто не помнит порог.
                if k < Self.порог, !Self.известныеСветлые.contains(адрес) {
                    провалы.append("\(адрес) · \(Self.два(k)) НЕ ХВАТАЕТ "
                                   + "до \(Self.два(Self.порог))")
                }
            }
        }
        #expect(осмотрено == Self.пары.count * ThemeContrastTests.режимы.count,
                "осмотрено \(осмотрено) пар вместо ожидаемых 12 — замер не состоялся")
        #expect(провалы.isEmpty, """
            \(роль) не читается на своей заливке:
            \(провалы.joined(separator: "\n"))

            Это пара «чернила ↔ заливка», и покраснеть она могла
            с ЛЮБОЙ стороны. Прежде чем править цвет, посмотри,
            не перевели ли на новую палитру только одну половину:
            ровно так появились 1,35 у натощак 25.10.2026.
            """)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.2f", x).replacingOccurrences(of: ".", with: ",")
    }
