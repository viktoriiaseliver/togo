/// Чернила панели показания читаются **на своей заливке**.
///
/// ## Зачем отдельный набор, когда контраст уже сторожат четыре
///
/// Потому что ни один из них не меряет **пару**. Замер 25.10.2026:
///
/// ```
/// чернила натощак уехали на палитру Виктории   labelOnFasting   #2A1D00
/// заливка осталась на нашей                    status.waitingBg #4A300A
/// контраст ПАРЫ                                1,35
/// доложено было                                «1,92 → 8,59»
/// на её панели #FFC233                         10,22   (её счёт 10,2)
/// ```
///
/// Правка, закрывавшая нечитаемость, сделала её **хуже** — и обе
/// стороны по отдельности выглядели верными: чернила ссылались
/// на её палитру, заливка ссылалась на живой токен того же смысла.
///
/// > **Перевести половину пары опаснее, чем не переводить вовсе.**
/// > Цвет виден только в паре, а грепом пара не ищется — ищутся два
/// > имени, и оба живые. Сторож на сторону такое не ловит
/// > по устройству: у каждой стороны своё значение верное.
///
/// Ось здесь — **отношение двух токенов**, не значение одного.
/// Поэтому набор краснеет и когда подменят чернила, и когда подменят
/// заливку, и остаётся зелёным, пока их меняют вместе.
///
/// ## Чего набор НЕ меряет
///
/// Он меряет **токены, которые читает `ReadingPanel`**, а не пиксель
/// на экране. Между ними живут `opacity` на месте вызова, наложение
/// стеклом и подкраска фотографии — их видно только на кадре.
/// Доккомментарий `ThemeContrastTests` говорит то же про себя.
///
/// И отдельно: `.alarm` берёт чернила `labelOnColor`, общие с плакатом,
/// а не свои. Это не находка — так в исходнике; если значение разойдётся
/// с панелью тревоги, покраснеет здесь.
@Suite("Чернила панели показания парны своей заливке")
struct ЧернилаПанелиПарныеЗаливкеTests {

