import Testing
import Foundation
@testable import Togo

/// Голос обязан молчать о числе там, где экран о нём молчит.
///
/// **Замер 24.09.2026.** Потолок тишины стоял на главном экране с 21.09
/// и не стоял в `TimeIndoorsIntent` вовсе: на тех же данных, где экран
/// честно говорит «Выходов нет с 3 сент.», Siri отвечала «Стич дома
/// 434 ч с прошлого выхода». Это ровно та неправда, ради которой
/// потолок и заводили, — только голосом, то есть там, где человек
/// не видит ленты и проверить нечем.
@Suite("Что Siri говорит про выходы")
struct SiriSilenceTests {

    @Test("За сутками голос называет дату, а не часы")
    func заПотолкомДата() {
        let позавчера = Date().addingTimeInterval(-2 * 24 * 3600)
        let ответ = TimeIndoorsIntent.ответ(
            dogName: "Стич", indoors: 2 * 24 * 3600, lastOutingEndedAt: позавчера)

        // От обратного: не «ответ упоминает выходы», а «числа часов
        // в нём нет». Утверждение «упоминает выходы» выполнялось бы
        // и во фразе «дома 48 ч с прошлого выхода».
        #expect(!ответ.contains("дома"), """
            Siri отвечает «\(ответ)» — то есть числом часов за потолком тишины. \
            Экран в этом состоянии говорит «Выходов нет с …», и голос обязан \
            говорить то же: число часов отвечает уже не на тот вопрос.
            """)
        #expect(ответ.hasPrefix("Выходов нет с"), "ответ: «\(ответ)»")
    }

    @Test("До потолка голос отвечает числом — иначе проверка выше ничего не значит")
    func доПотолкаЧисло() {
        let ответ = TimeIndoorsIntent.ответ(
            dogName: "Стич", indoors: 3 * 3600,
            lastOutingEndedAt: Date().addingTimeInterval(-3 * 3600))
        #expect(ответ.contains("Стич"))
        #expect(ответ.contains("дома"), """
            в обычном случае голос обязан отвечать числом: если он молчит о нём \
            всегда, первая проверка зелена по причине, к потолку не относящейся
            """)
    }

    /// Голос — поверхность, которую **нельзя снять кадром**, и это
    /// единственная причина, по которой проверка здесь, а не на кадре.
    ///
    /// Отзыв TestFlight 06.10.2026 на сборке 271 пришёл про пустые
    /// клички. На экране пустую видно; голос же произносит фразу,
    /// и пустая кличка в ней не «выглядит пусто» — она **проглатывается**:
    /// « дома 3 ч с прошлого выхода». Человек услышит предложение
    /// без подлежащего и решит, что ослышался.
    ///
    /// **От запрета, а не от требования.** `ответ.contains(кличка)`
    /// проверить нельзя: при пустой кличке это истинно у любой строки,
    /// включая пустую — замерено 07.10, `"15 ч · ".contains("")` → `true`.
    /// Запрет «фраза не начинается с пробела и не несёт двойного» дефект
    /// нарушает, его и проверяем.
    ///
    /// Чинится там же, где `SnapshotText.inlineText`, — подстановкой
    /// через `Fmt.dogNameOrFallback` внутри самой функции. Починка
    /// у места вызова (`dog.displayName`) эту проверку не закрывает:
    /// `ответ` принимает строку от кого угодно и обязан держаться сам.
    @Test("Голос не произносит пустоту вместо клички")
    func голосНеГлотаетКличку() {
        let ответ = TimeIndoorsIntent.ответ(
            dogName: "", indoors: 3 * 3600,
            lastOutingEndedAt: Date().addingTimeInterval(-3 * 3600))

        // Контроль: взята ветка С кличкой, а не ветка тишины — иначе
        // запреты ниже выполнены по причине, к кличке не относящейся.
        #expect(ответ.contains("дома"), """
            взята не та ветка: ответ «\(ответ)» — про тишину, кличка
            в нём не участвует, проверять нечего.
            """)

        #expect(!ответ.hasPrefix(" "), """
            голос произносит «\(ответ)» — фраза начинается с пустого
            места на месте клички. Это предложение без подлежащего.
            """)
        #expect(!ответ.contains("  "), "двойной пробел на месте клички: «\(ответ)»")
    }

    /// Граница этой пары: она смотрит на русский текст.
    ///
    /// Что перевод **достижим**, доказывает не она, а то, что строка
    /// собирается через `String(localized:)`. До 24.09 здесь стоял
    /// `IntentDialog(stringLiteral:)` с уже собранной интерполяцией:
    /// перевод `%@ дома %@ с прошлого выхода.` лежал в каталоге
    /// на французском и украинском и не мог быть показан ни разу.
    @Test("Ключ, который спрашивает голос, в каталоге есть")
    func ключЕстьВКаталоге() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let data = try Data(contentsOf: корень.appendingPathComponent(
            "TogoShared/Resources/Localizable.xcstrings"))
        let каталог = try JSONSerialization.jsonObject(with: data) as? [String: Any]
        let строки = каталог?["strings"] as? [String: Any] ?? [:]

        for ключ in ["%@ дома %@ с прошлого выхода.", "Выходов нет с %@"] {
            let запись = строки[ключ] as? [String: Any]
            let языки = (запись?["localizations"] as? [String: Any])?.keys.sorted() ?? []
            #expect(запись != nil, "ключа «\(ключ)» нет в каталоге — голос заговорит по-русски всем")
            #expect(языки.contains("fr") && языки.contains("uk"),
                    "у ключа «\(ключ)» есть только \(языки)")
        }
    }
}
