import Testing
import Foundation

/// Имя файла, полученное обходом каталога, обязано открываться.
///
/// # Чем это оплачено: `resolvingSymlinksInPath()` портит кириллицу
///
/// 30.10.2026 ворота заливщика отказали на `Code=260` — «не удалось
/// открыть файл `ПозваливСемью.swift`». Файла с таким именем нет:
/// на диске `ПозвалиВСемью.swift`, с заглавной «В». Замер обходом
/// с печатью байтов:
///
/// ```
/// lastPathComponent          … d092 …   «В» заглавная, как на диске
/// адрес.path                 … d092 …   верно
/// resolvingSymlinksInPath()  … d0b2 …   «В» стала строчной «в»
/// ```
///
/// **Девять дней это молчало, и вот почему.** Том регистронезависим:
/// на хосте испорченное имя открывается (проверено — файл прочитался,
/// 10 442 символа). Тесты бегут в симуляторе, и там тот же путь даёт
/// «No such file or directory». А из `git worktree` под `/tmp` резолв
/// имя не портит вовсе — то есть прогон, сделанный по своду
/// («мерить из worktree»), был зелёным, и дефект доставался только
/// тому, кто мерил из рабочего дерева.
///
/// > **Одна строка защищала от одного класса и вводила другой.** Оба
/// > дают `Code=260` на первом же файле, и различить их по симптому
/// > нельзя. Разбор прежнего класса — в голове
/// > `СнятиеНапоминанийПодключеноTests.исходники()`.
///
/// # Ось: не «зовут ли резолв», а «открывается ли имя»
///
/// Сторож на имя механизма («в тестах нет `resolvingSymlinksInPath`»)
/// покраснел бы от правильного вызова у основания и промолчал бы
/// о любом новом способе испортить имя. Поэтому спрашиваем предмет:
/// **каждое имя, собранное нашим обходом, обязано открываться
/// и совпадать с тем, что лежит на диске.**
@Suite("Имена файлов при обходе каталогов")
struct ИменаФайловПриОбходеTests {

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private static let каталоги = ["Togo", "TogoShared", "TogoWidgets"]

    /// Контроль стоит ПЕРВЫМ: без кириллических имён проверять нечего,
    /// и «все имена открылись» было бы зелено на пустом множестве.
    @Test("Кириллица в именах исходников есть — иначе проверять нечего")
    func контрольЕстьЧтоПроверять() throws {
        let кириллические = try Self.всеИсходники()
            .filter { $0.lastPathComponent.range(of: "[А-Яа-яЁё]", options: .regularExpression) != nil }

        #expect(кириллические.count >= 20, """
            кириллических имён \(кириллические.count) при ожидаемых \
            двадцати с лишним (на 30.10.2026 их было 28). Либо файлы \
            переименовали, либо обход не дошёл до них — и тогда \
            проверка ниже зелена, не проверив ничего.
            """)
    }

    /// Предмет: имя, собранное так, как его собирает сторож, обязано
    /// открываться. Это ловит и прежний класс (`/private/tmp`),
    /// и новый (case-folding), и любой третий.
    @Test("Каждое имя из обхода открывается")
    func всеИменаОткрываются() throws {
        var непрочитанные: [String] = []
        for адрес in try Self.всеИсходники() {
            if (try? String(contentsOf: адрес, encoding: .utf8)) == nil {
                непрочитанные.append(адрес.path)
            }
        }
        #expect(непрочитанные.isEmpty, """
            не открылись \(непрочитанные.count) файлов из обхода:
            \(непрочитанные.prefix(5).joined(separator: "\n"))

            Имя, по которому нельзя открыть файл, сторож получает
            на первом же шаге и падает не на своём предмете.
            """)
    }

    /// И главное: **ни один сторож не собирает путь к файлу строкой
    /// из резолвленного пути.**
    ///
    /// # Почему ось здесь — наш код, а не поведение Foundation
    ///
    /// Первая редакция этого теста требовала «`resolvingSymlinksInPath()`
    /// не меняет имя» и была бы **красной с рождения**: резолв портит
    /// кириллицу прямо сейчас, в рабочем дереве. Такой тест уехал бы
    /// в эталон ожидаемо красным — то есть узаконил бы красное под
    /// именем, которое завтра покраснеет от настоящей потери.
    ///
    /// > **Поведение Foundation нам не подчиняется. Подчиняется только
    /// > то, как мы им пользуемся** — её и спрашиваем.
    ///
    /// Искомая форма — связка в одном файле: берут `.path`
    /// у резолвленного адреса и срезают из него префикс строкой.
    /// Именно она девять дней жила в `СнятиеНапоминанийПодключеноTests`
    /// и падала на каждом двадцатом файле обхода.
    @Test("Сторожа не собирают путь строкой из резолвленного адреса")
    func путьНеСобираютСтрокой() throws {
        let тесты = try Self.файлыТестов()

        // Контроль ПЕРВЫМ: без него «ноль нарушений» зелено и на пустом
        // списке — ровно тот ложный ноль, против которого весь свод.
        #expect(тесты.count >= 50, """
            файлов тестов найдено \(тесты.count) при ожидаемых пятидесяти \
            с лишним. Обход не дошёл до каталога — и «нарушений нет» \
            говорит про инструмент, а не про код.
            """)
        let сОбходом = тесты.filter { $0.текст.contains("resolvingSymlinksInPath") }
        #expect(!сОбходом.isEmpty, """
            ни один тест не зовёт `resolvingSymlinksInPath` — значит \
            разбор не видит даже правильных вызовов, и отсутствие \
            неправильных ничего не значит.
            """)

        var нарушители: [String] = []
        for файл in сОбходом {
            // Сам сторож — исключение, и с причиной: обе искомые формы
            // стоят у него в ТЕКСТЕ сообщения об ошибке, где они
            // и должны стоять. Комментарии разбор вырезает, строковые
            // литералы — нет, и учить его этому дороже, чем назвать
            // один файл по имени.
            guard файл.имя != "ИменаФайловПриОбходеTests.swift" else { continue }
            let код = файл.текст
                .components(separatedBy: .newlines)
                .map { $0.components(separatedBy: "//")[0] }
                .joined(separator: "\n")
            guard код.contains("resolvingSymlinksInPath") else { continue }
            if код.contains("resolvingSymlinksInPath().path")
                && код.contains("replacingOccurrences") {
                нарушители.append(файл.имя)
            }
        }

        #expect(нарушители.isEmpty, """
            путь к файлу собирают строкой из резолвленного адреса: \
            \(нарушители.joined(separator: ", ")).

            `resolvingSymlinksInPath()` делает case-folding кириллицы \
            (замер в голове этого набора), и собранное имя открывается \
            на хосте, но не в симуляторе. Отказ приходит как `Code=260` \
            на первом же файле обхода — и выглядит дефектом продукта.

            Как надо: резолв оставить у ОСНОВАНИЯ (он нужен против \
            `/tmp` → `/private/tmp`), относительный путь считать числом \
            компонентов, а файл читать по адресу, который отдал обход. \
            Образец — `СнятиеНапоминанийПодключеноTests.исходники()`.
            """)
    }

    // MARK: Обход

    /// Исходники тестов — вместе с текстом, чтобы читать их один раз.
    private static func файлыТестов() throws -> [(имя: String, текст: String)] {
        var итог: [(имя: String, текст: String)] = []
        for каталог in ["TogoTests", "TogoUITests"] {
            let основание = корень.appendingPathComponent(каталог).resolvingSymlinksInPath()
            guard let обход = FileManager.default.enumerator(
                at: основание, includingPropertiesForKeys: nil) else { continue }
            for случай in обход {
                guard let адрес = случай as? URL, адрес.pathExtension == "swift",
                      let текст = try? String(contentsOf: адрес, encoding: .utf8)
                else { continue }
                итог.append((адрес.lastPathComponent, текст))
            }
        }
        return итог
    }

    /// Тот же обход, что у сторожей: резолв у основания, имя — от
    /// `enumerator`, без склейки строкой.
    private static func всеИсходники() throws -> [URL] {
        var итог: [URL] = []
        for каталог in каталоги {
            let основание = корень.appendingPathComponent(каталог).resolvingSymlinksInPath()
            guard let обход = FileManager.default.enumerator(
                at: основание, includingPropertiesForKeys: nil) else { continue }
            for случай in обход {
                guard let адрес = случай as? URL, адрес.pathExtension == "swift" else { continue }
                итог.append(адрес)
            }
        }
        return итог
    }
}
