        итог["поездки"] = try context.fetch(FetchDescriptor<Trip>()).count
        итог["люди"] = try context.fetch(FetchDescriptor<FamilyMember>()).count
        return итог
    }

    /// Счёт по видам одной строкой — для сообщения упавшего теста.
    private func описание(_ счёт: [String: Int]) -> String {
        счёт.sorted { $0.key < $1.key }
            .map { "\($0.key) \($0.value)" }
            .joined(separator: " · ")
    }

