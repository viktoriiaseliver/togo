        итог["документы"] = try context.fetch(FetchDescriptor<DogDocument>()).count
        итог["запасы"] = try context.fetch(FetchDescriptor<FoodStock>()).count
        итог["течки"] = try context.fetch(FetchDescriptor<HeatRecord>()).count
        итог["выезды"] = try context.fetch(FetchDescriptor<DayOut>()).count
        итог["шаги обучения"] = try context.fetch(FetchDescriptor<TrainingStep>()).count
