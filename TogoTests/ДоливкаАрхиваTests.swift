/// «Добавить недостающее» обязано доливать ВСЁ, а не одну ленту.
///
/// # Что оплатило этот набор
///
/// Отзыв владелицы, 29.10.2026, дословно: «добавило в логи истории,
/// а не туда куда надо». Разбор нашёл ветку из пяти строк
/// (`Backup.restore`, случай «собака с такой кличкой уже есть»):
/// она звала `attachEvents` и уходила по `continue`. То есть
/// `makeDog` и `attachRest` не звались вовсе, и мимо проезжало
/// четырнадцать коллекций из пятнадцати:
///
/// ```
/// доезжало     лента дневника
/// не доезжало  профиль · веса · дела ухода · схемы лечения · дозы
///              анализы · визиты · диагнозы · рецепты · документы
///              запасы · течки · выезды · обучение · поездки
/// что видел    «Добавлено новых записей: N»
/// человек      — то есть УДАЧНЫЙ исход
/// ```
///
/// > **Ветка, которая делает часть обещанного и считает сделанное,
/// > выглядит удачной.** Счётчик был прав про ленту и молчал про
/// > остальное — он отчитывался о том, что сделал, а не о том, что
/// > обещал экран.
///
/// # Почему круговые тесты, а не проверка полей
///
/// `ArchiveParityTests` сверяет ИМЕНА — что поле объявлено в снимке —
/// и сам пишет о себе, что не проверяет ни заполнение при сборке, ни
/// чтение при восстановлении. Здесь дефект был ровно в третьем месте:
/// снимок полный, сборщик полный, **читатель ветки неполный**. Такое
/// ловится только кругом: выгрузили → долили → посчитали приехавшее.
///
/// Существующие круговые тесты (`BackupTests`) этого не ловили и
/// не могли: все они шли веткой `.replace` либо сверяли по доливке
/// только собак и ленту.
@Suite("Доливка архива: «Добавить недостающее» переносит всё")
@MainActor
