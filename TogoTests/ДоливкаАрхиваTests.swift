        let данные = try архивДругогоТелефона()
        let (телефон, стич) = try телефонСоСтичем()

        try BackupService.restore(try BackupService.decode(данные),
                                  into: телефон, strategy: .merge)

        // Вторая «Стич» не завелась — слияние по кличке работает
        // по-прежнему. Без этой строки все проверки ниже прошли бы
        // и на другом механизме: записи приехали бы ко ВТОРОЙ собаке.
        #expect(try телефон.fetch(FetchDescriptor<Dog>()).count == 1, """
            собак стало больше одной — слияние по кличке сломалось, \
            и записи ниже приехали не к той карточке.
            """)

        #expect(стич.events.count == 2, "лента доливалась и прежде — тут проверять нечего")

        let анализы = стич.labResults
        #expect(анализы.count == 1, """
            анализов у собаки \(анализы.count) из одного. Это самый \
            дорогой класс данных в приложении: бумажные бланки остались \
            в клиниках, письма врачей — в почте, а у Стича 127 строк, \
            собранных за год. Ветка «Добавить недостающее» не звала \
            `attachRest` вовсе.
            """)
        #expect(анализы.first?.reportNumber == "VF120682", "номер отчёта потерян")
        #expect(анализы.first?.value == 18.4, "значение анализа потеряно")

        let прививки = стич.careTasks.filter { $0.title == "Бешенство" }
        #expect(прививки.count == 1, """
            прививка не доехала: дел ухода у собаки \
            \(стич.careTasks.count). Медкнижка без дат прививок — \
            не медкнижка, её спрашивает врач.
            """)
        #expect(прививки.first?.vaccineBatch == "L3421-07", "номер партии потерян")
        #expect(прививки.first?.clinic?.name == "Vet Riviera", """
            связь прививки с клиникой не восстановлена, хотя справочник \
            доливка ведёт: клиника ищется ПО ИМЕНИ в уже вставленном \
            списке.
            """)

        let схемы = стич.medications
        #expect(схемы.count == 1, """
            схем лечения \(схемы.count) из одной. Лечение — то, ради \
            чего в приложении есть вкладка «Здоровье».
            """)
        #expect(схемы.first?.prescriptionNumber == "2026/0417", "номер назначения потерян")
        #expect(схемы.first?.unitRaw == MedUnit.tab.rawValue, """
            единица дозы потеряна: «0,5» без неё не значит ничего, \
            и ошибка здесь — передозировка, а не путаница в дневнике.
            """)
        #expect(схемы.first?.doses.count == 1, """
            доза не доехала. Доза — это отметка «дали в 7:00», \
            и по ней врач считает пропуски.
            """)

        #expect(стич.vetVisits.count == 1, "визит не доехал")
        #expect(стич.vetVisits.first?.reasonRaw == VisitReason.online.rawValue, """
            повод визита потерян: онлайн-консультация — такой же визит, \
            и став «осмотром», она соврёт про то, чего не было.
            """)
        #expect(стич.prescriptions.count == 1, "рецепт не доехал")
        #expect(стич.prescriptions.first?.number == "8935331", """
            номер рецепта потерян — в аптеке по нему получают лекарство.
            """)
        #expect(стич.diagnoses.count == 1, "диагноз не доехал")
        #expect(стич.documents.count == 1, "документ не доехал")
        #expect(стич.documents.first?.number == "FR-2024-88120", "номер документа потерян")

        // Остальные шесть коллекций — тем же молчанием, что медчасть.
        #expect(стич.weights.count == 1, "взвешивание не доехало")
        #expect(стич.stocks.count == 1, "запас корма не доехал")
        #expect(стич.heats.count == 1, "течка не доехала")
        #expect(стич.daysOut.count == 1, "выезд не доехал")
        #expect(стич.trainingSteps.count == 1, "шаг обучения не доехал")
        #expect(стич.trainingSessions.count == 1, "занятие не доехало")
        #expect(стич.trips.count == 1, "поездка не доехала")
    }

    /// Повторный долив того же файла не задваивает НИ ОДНУ коллекцию.
    ///
    /// Это обещание напечатано человеку перед нажатием —
    /// `Strategy.merge.detail`: «существующие записи останутся, повторы
    /// не задвоятся». До 29.10.2026 держать его было нечем: четырнадцать
    /// коллекций не приезжали вовсе, и не задваивалось ровно то, чего
    /// не было.
    ///
    /// Счёт по КАЖДОЙ коллекции, а не суммой: сумма сойдётся и при
    /// «одно задвоилось, другое пропало».
    @Test("Повторный долив того же файла не задваивает ни одну коллекцию")
    func повторныйДоливНеЗадваивает() throws {
        let данные = try архивДругогоТелефона()
        let (телефон, _) = try телефонСоСтичем()

        try BackupService.restore(try BackupService.decode(данные),
                                  into: телефон, strategy: .merge)
        let послеПервого = try счёт(телефон)

        try BackupService.restore(try BackupService.decode(данные),
                                  into: телефон, strategy: .merge)
        let послеВторого = try счёт(телефон)

        // КОНТРОЛЬ ПЕРВЫМ: было чему задваиваться. Без него тест
        // зеленел бы на пустом хранилище — «ноль не задвоился» верно
        // всегда, и ровно так он и зеленел бы ДО починки.
        let пустые = послеПервого.filter { $0.value == 0 }.keys.sorted()
        #expect(пустые.isEmpty, """
            после первого долива пусты: \(пустые.joined(separator: ", ")). \
            Проверять «не задвоилось» нечего: ноль не задваивается \
            никогда, и тест зелен впустую.
            """)

        var задвоилось: [String] = []
        for (коллекция, стало) in послеВторого.sorted(by: { $0.key < $1.key })
        where стало != послеПервого[коллекция] {
            задвоилось.append("\(коллекция): \(послеПервого[коллекция] ?? 0) → \(стало)")
        }
        #expect(задвоилось.isEmpty, """
            повторный долив того же файла изменил счёт: \
            \(задвоилось.joined(separator: " · ")).

            Экран обещает перед нажатием: «существующие записи \
            останутся, повторы не задвоятся». Опознать «та же запись» \
            сперва по `id`, потом по содержанию — и разошёлся, значит, \
            опознание по id либо естественный ключ: смотри перечень \
            ключей у `BackupService.attachRest`.
            """)
    }

    /// Доливка заполняет пустое и не трогает заполненное руками.
    ///
    /// **«Добавить недостающее» буквально это и значит.** Архив здесь
    /// источник более старый, чем телефон: номер чипа, врача и приметы
    /// человек мог поправить ПОСЛЕ того, как снял файл. То же правило
    /// уже держит справочник клиник — «слияние перезаписало телефон
    /// из архива поверх местного».
    ///
    /// Обе стороны в одном тесте нарочно: «не перезаписывает» в
    /// одиночку выполняется и тогда, когда доливка профиля
    /// не происходит вовсе — то есть ровно в том состоянии, которое
    /// чинится.
    @Test("Чип, вписанный руками, долив не трогает, а пустой — заполняет")
    func чипПерезаписиНеПодлежит() throws {
        let данные = try архивДругогоТелефона()

        // Телефон первый: чип вписан руками и ОТЛИЧАЕТСЯ от файла.
        let (сЧипом, стичСЧипом) = try телефонСоСтичем()
        стичСЧипом.chipNumber = "900108001234567"
        try сЧипом.save()
        try BackupService.restore(try BackupService.decode(данные),
                                  into: сЧипом, strategy: .merge)
        #expect(стичСЧипом.chipNumber == "900108001234567", """
            долив затёр номер чипа, вписанный руками: стало \
            \(стичСЧипом.chipNumber ?? "пусто"). Чип перечиповывают \
            и исправляют с бумаги, и файл здесь источник более старый, \
            чем телефон. «Добавить недостающее» не значит «заменить \
            заполненное».
            """)
        // А рядом, у того же человека, пустое — заполнилось. Без этой
        // пары тест прошёл бы и на доливке, которая не делает ничего.
        #expect(стичСЧипом.vetName == "д-р Моро", """
            пустое поле профиля осталось пустым: врач из файла \
            не доехал. Врача спрашивают, когда хозяина нет рядом.
            """)
        #expect(стичСЧипом.sitterFood == "60 г утром и вечером", """
            лист ситтера не долился. Его пишут один раз, и переустановка \
            телефона стирала его без следа.
            """)
        #expect(стичСЧипом.weightKg == 4.2, """
