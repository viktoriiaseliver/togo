    /// Счётчик «Добавлено новых записей» считает медчасть.
    ///
    /// **Число в подтверждении — это утверждение о деле**, и до
    /// 29.10.2026 оно расходилось с делом дважды: `attachRest`
    /// не возвращал ничего, а в ветке доливки не звался вовсе.
    /// Сверяется он здесь не с константой, а с тем, сколько записей
    /// в хранилище прибавилось: константа стареет молча, а эта сверка
    /// краснеет, как только счётчик и дело разойдутся.
    @Test("Счётчик долива считает медчасть, а не одну ленту")
    func счётчикСчитаетМедчасть() throws {
        let данные = try архивДругогоТелефона()
        let (телефон, _) = try телефонСоСтичем()

        let было = try счёт(телефон)
        let добавлено = try BackupService.restore(try BackupService.decode(данные),
                                                  into: телефон, strategy: .merge)
        let стало = try счёт(телефон)

        let приехало = стало.values.reduce(0, +) - было.values.reduce(0, +)
        // Сводки считаются ДО макроса и отдельными строками. Тяжёлым
        // выражениям внутри `#expect` не место: у `силаТаблетки…`
        // типизатор на таком сорвался молча, и целью становится
        // не сообщение теста, а то, собирается ли набор вообще.
        let сводкаДо = описание(было)
        let сводкаПосле = описание(стало)
        let лента = стало["лента"] ?? 0

        #expect(приехало >= 17, """
            в хранилище прибавилось \(приехало) записей — фикстура \
            обеднела, и сверка счётчика ниже мерит уже не то. В файле \
            по одной записи каждого из семнадцати считаемых видов. \
            Стало: \(сводкаПосле).
            """)
        #expect(добавлено == приехало, """
            счётчик вернул \(добавлено), а записей прибавилось \
            \(приехало). Человек читает это число как отчёт о деле: \
            пока `attachRest` ничего не возвращал, «Добавлено новых \
            записей» считало одну ленту — и собака, приехавшая со 140 \
            анализами, давала число отметок дневника.

            Было: \(сводкаДо).
            Стало: \(сводкаПосле).
            """)
        #expect(добавлено > лента, """
            счётчик (\(добавлено)) не больше числа записей ленты \
            (\(лента)) — похоже, медчасть в него по-прежнему не входит.
            """)
    }
