import SwiftData
@testable import Togo

/// Второй человек не правит схему лечения в чужом дневнике.
///
/// # Чего стоил дефект
///
/// Замер 14.10.2026. Опознанный гость получал права **своей** карточки,
/// а её ставит онбординг — владельческой (`OnboardingFlow.saveDog`:
/// `FamilyMember(role: .owner, isMe: true)`, там же `myMemberID`).
/// Значит человек, который сперва завёл свой дневник, а потом принял
/// приглашение, ходил по ЧУЖОМУ дневнику со всеми правами, включая
/// `editTreatment`. Это красная линия проекта: схему лечения меняет
/// владелец, а запись потом читает врач.
///
/// Запасной путь был защищён (`рольБезОпознания(гость:) = .observer`),
/// прямой — нет: `меня(…)` отдаёт карточку по запомненному `id`,
/// и флаг `гость` на неё не влияет вовсе.
///
/// # Почему проверок две, а правило одно
///
/// Входов в права два, и это измерено, а не предположено:
/// `AppState.permissions` — экраны; `FamilyResolver.права(…)` — голос,
/// кнопка «Действие», виджет. 23.09 мы платили за то, что одно правило
/// жило двумя проверками и разошлось в краю. Поэтому правило живёт
/// одной функцией `потолокГостя`, а здесь проверяется, что **оба входа
/// её зовут** — порознь, одинаковым вопросом.
///
/// # Чем этот сторож станет временным
///
/// Решение Виктории 14.10.2026: «пусть выбираете вы при приглашении» —
/// роль поедет вместе с `CKShare`. Когда поедет, потолок снимается,
/// и этот файл переписывается на проверку приехавшей роли. До тех пор
/// он держит красную линию.
@Suite("Потолок прав второго человека")
struct ПотолокГостяTests {

    /// Карточка, какой её заводит онбординг: владелец, со всеми правами.
    private func карточкаОнбординга() -> FamilyMember {
        FamilyMember(name: "Мама", role: .owner, isMe: true)
    }

    /// Первым — что проверять было ЧТО.
    ///
    /// Без этой проверки обе ниже прошли бы на пустом множестве:
    /// «прав нет» выполняется и когда потолок работает, и когда
    /// карточка не нашлась вовсе.
    @Test("У владельца онбординга в СВОЁМ дневнике права полные")
    func уВладельцаПраваПолные() {
        let свой = FamilyResolver.потолокГостя(карточкаОнбординга().permissions, гость: false)

        #expect(свой.contains(.editTreatment), """
            у владельца в своём дневнике пропало право на схему лечения —
            значит потолок срабатывает не только у гостя, и человек
            заперт в собственном дневнике. Это не починка, а вторая беда.
            """)
        #expect(свой.contains(.manageFamily))
        #expect(свой == Set(Permission.allCases), """
            набор прав владельца перестал быть полным. Либо у роли
            `.owner` отняли право, либо потолок трогает не только гостя.
            """)
    }

    @Test("Тот же человек в ЧУЖОМ дневнике не правит лечение и не зовёт людей")
    func уГостяПотолокСрабатывает() {
        let чужой = FamilyResolver.потолокГостя(карточкаОнбординга().permissions, гость: true)

        #expect(!чужой.contains(.editTreatment), """
            второй человек правит схему лечения в чужом дневнике.
            Красная линия: «поле с обязательством показа», и запись
            потом читает врач.
            """)
        #expect(!чужой.contains(.manageFamily), """
            второй человек зовёт людей в чужой дневник и меняет роли.
            Слой обмена это держит отдельно (FamilyShare:109), но
            показ обязан совпадать с тем, что разрешено на деле.
            """)
    }

    /// **Ось от запрета, а не от требования.** «Прав стало меньше»
    /// выполняется и при пустом множестве — то есть при запертом
    /// человеке. Проверяется именно то, что осталось.
    @Test("Гостю оставлено ровно то, ради чего его звали")
    func гостюОставленоНужное() {
        let чужой = FamilyResolver.потолокГостя(карточкаОнбординга().permissions, гость: true)

        #expect(чужой.contains(.logBasics), """
            у второго человека отняли запись выходов и еды — то есть
            ровно то, ради чего его звали. Это не потолок, а запрет.
            """)
        #expect(чужой.contains(.giveDose), """
            у второго человека отняли отметку приёма дозы. Отметить
            «дал» и не суметь записать — хуже, чем не отметить:
            второй человек даст таблетку повторно.
            """)
        #expect(чужой.contains(.seeMedical))
        #expect(чужой.count == Permission.allCases.count - 2, """
            снято не два права, а другое число. Потолок обязан снимать
            ровно editTreatment и manageFamily — всё, чего второй человек
            не мог получить законно, и ничего сверх.
            """)
    }

    /// Второй вход в права — тот, которым ходят голос, кнопка
    /// «Действие» и виджет. Экранов там нет, и ошибка не видна никому.
    @Test("Второй вход в права зовёт то же правило")
    func второйВходЗовётТоЖеПравило() throws {
        let context = ModelContext(Persistence.container())
        let мама = карточкаОнбординга()
        context.insert(мама)
        try context.save()

        let вЧужом = FamilyResolver.права(среди: [мама], запомненный: мама.id, гость: true)
        let вСвоём = FamilyResolver.права(среди: [мама], запомненный: мама.id, гость: false)

        #expect(!вЧужом.contains(.editTreatment), """
            голос и виджет дают право на схему лечения в чужом дневнике,
            хотя экраны его уже не дают. Правило снова живёт двумя
            проверками — ровно то, за что платили 23.09.
            """)
        #expect(вЧужом.contains(.logBasics))
        #expect(вСвоём.contains(.editTreatment), """
            в своём дневнике второй вход отнял право на лечение —
            потолок применяется не к тому человеку.
            """)
    }
}
