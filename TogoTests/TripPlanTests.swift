import Testing
import Foundation
@testable import Togo

/// Поездка обещала остановки и сведение с дозами — и не делала ни того,
/// ни другого (аудит 29.10.2026). Здесь каждое обещание — тестом.
@Suite("Поездка: остановки и дозы в дороге")
@MainActor
struct TripPlanTests {
    private let календарь = Calendar.current
    private var выезд: Date {
        календарь.date(bySettingHour: 9, minute: 0, second: 0,
                       of: Date(timeIntervalSince1970: 1_800_000_000))!
    }

    @Test("Пять часов на машине — остановки в 11:00 и 13:00, у приезда нет")
    func остановкиКаждыеДваЧаса() {
        let остановки = TripPlan.остановки(выезд: выезд, вДороге: 5)
        #expect(остановки == [выезд.addingTimeInterval(2 * 3600), выезд.addingTimeInterval(4 * 3600)])
    }

    @Test("Ровно четыре часа — одна остановка: в момент приезда её нет")
    func границаПриезда() {
        #expect(TripPlan.остановки(выезд: выезд, вДороге: 4).count == 1)
    }

    @Test("Короткая дорога — без остановок")
    func короткая() {
        #expect(TripPlan.остановки(выезд: выезд, вДороге: 1.5).isEmpty)
    }

    @Test("Доза в дороге и доза в окне до выезда различаются; пауза и вне окон не берутся")
    func дозыВДороге() {
        let дозы = TripPlan.дозыВДороге(
            [("Эутирокс", [8 * 60, 21 * 60], false),
             ("Ветмедин", [11 * 60], false),
             ("Пауза", [10 * 60], true)],
            выезд: выезд, вДороге: 5,
            началоОкон: выезд.addingTimeInterval(-2 * 3600))
        #expect(дозы.map(\.препарат) == ["Эутирокс", "Ветмедин"])
        #expect(дозы.map(\.вПути) == [false, true])
    }
}
