    /// Сквозной путь целиком: те же данные → тот же снимок, что кладёт
    /// `publishSnapshot` → строки, которые человек прочтёт на виджете.
    @Test("На сценарии обе строки снимка молчат про число")
    func строкиСнимкаНаЖивыхДанных() throws {
        let s = try сигналыСценария()
        var снимок = WidgetSnapshot.empty
        снимок.dogName = "Стич"
        снимок.sinceUrineSeconds = s.sinceUrine
        снимок.urineSilenceSince = s.urineSilence

        let секунды = try #require(снимок.sinceUrineSeconds)
        let моча = try #require(s.lastUrine)
        let число = Fmt.duration(секунды)

        #expect(снимок.urineSilenceSince != nil, "решение о тишине не доехало до снимка")
        #expect(SnapshotText.sinceText(снимок).contains(число) == false)
        #expect(SnapshotText.inlineText(снимок).contains(число) == false)
        #expect(SnapshotText.sinceText(снимок).contains(Fmt.shortDay(моча)))
    }
