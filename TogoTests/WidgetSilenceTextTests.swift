/// Сторож на две строки виджета под тишиной мочи — `SnapshotText.sinceText`
/// и `SnapshotText.inlineText`.
///
/// **Почему этот файл появился только 05.10, и это главное в нём.**
/// `UrineSilenceTests` 28.09 в 08:10 напечатал своей границей: «две строки
/// виджета — `private var` внутри `TogoWidgets`, `TogoTests` живёт
/// на `@testable import Togo` и не достаёт до них ни при какой
/// формулировке; поверхность НЕПРОВЕРЯЕМАЯ, а не непроверенная». Это была
/// правда — семь часов. В 15:05 того же дня `10500d5` вынес строки
/// в `TogoShared/Domain/SnapshotText.swift`, и поверхность стала
/// достижимой. Печать границы осталась прежней.
///
/// > **Напечатанная граница собственного умения соврала в пользу
/// > бездействия.** Правило «сторож печатает границы последней строкой»
/// > заведено затем, чтобы граница доезжала до всех, — и доехала: пять
/// > дней всякий читавший узнавал, что делать нечего, и был прав
/// > по тексту и неправ по миру. Поверхность перешла
/// > из «непроверяемой» в «проверяемую и непроверенную», и этого
/// > не заметил никто.
///
/// Отсюда требование к печати границ, которого у нас не было:
/// **граница обязана называть, что́ её снимет.** Не «пока вход
/// не переделан», а «пока `sinceText` живёт `private` в `TogoWidgets`» —
/// тогда переезд находит `grep`, а не человек через пять дней. Та же
/// форма, что у правила «комментарий „пока нет X“ обязан называть X
/// поимённо».
///
/// **Цепочка правила — три звена, и этот файл закрывает два.**
/// Правило (`UrineSilence`) → производитель снимка
/// (`LiveActivityController.publishSnapshot`) → строка (`SnapshotText`).
/// Первое звено сторожит `UrineSilenceTests`, третье и второе — здесь.
@Suite("Тишина мочи доезжает до виджета и «острова»")
struct WidgetSilenceTextTests {

    // MARK: - Один мир на весь набор

    /// Сигналы берутся у `UrineSilenceTests`, а не собираются заново.
    ///
    /// Вторая копия мира разошлась бы с первой молча, и тогда два набора
    /// проверяли бы разные вещи под одними именами — у нас это уже
    /// случалось внутри одного файла. Здесь нужен ровно тот сценарий:
    /// дневник молчит, выходов нет тоже.
    static func снимок(мочаЧасовНазад: Double,
                       выходЧасовНазад: Double? = nil) -> (WidgetSnapshot, NeedSignals) {
        let сигналы = UrineSilenceTests.сигналы(мочаЧасовНазад: мочаЧасовНазад,
                                                выходЧасовНазад: выходЧасовНазад)
        var снимок = WidgetSnapshot.empty
        снимок.dogName = "Стич"
        снимок.dogInitial = "С"
        // Ровно те две строки, что стоят в `publishSnapshot`, и больше
        // ничего: это шов между производителем и строкой, и он здесь
        // назван вслух. Сторож на сам производитель — последним тестом.
        снимок.sinceUrineSeconds = сигналы.sinceUrine
        снимок.urineSilenceSince = сигналы.urineSilence
        return (снимок, сигналы)
    }

    // MARK: - 1. Проверка, что набору было что проверять

    /// Стоит первой и отдельным тестом, а не внутри остальных.
    ///
    /// «Строка не содержит числа» истинно и у строки, в которой нет
    /// ничего: достать `SnapshotText` из теста ≠ наполнить снимок.
    /// Набор, которому нечего проверять, молчит так же, как набор,
    /// у которого всё хорошо.
    ///
    /// Последние два `#expect` проверяют **инструмент, а не мир**:
    /// дальше набор запрещает числу появляться на экране, и запрет
    /// осмыслен только пока искомое число не лежит в дате случайно.
    /// «3 ч» внутри «3 окт.» дало бы красный без дефекта, а он учит
    /// не верить красному и стоит дороже пропущенной находки.
    @Test("Снимок доехал до теста непустым, и запрет на число осмыслен")
    func наборуЕстьЧтоПроверять() throws {
        let (снимок, сигналы) = Self.снимок(мочаЧасовНазад: 434)

        let тишинаС = try #require(снимок.urineSilenceSince, """
            решение о тишине не доехало до снимка: `signals.urineSilence`
            пусто на дневнике, который молчит 434 часа. Всё, что скажут
            остальные проверки этого файла, будет про снимок без тишины.
            """)
        let секунды = try #require(снимок.sinceUrineSeconds, """
            в снимке нет «сколько прошло» — значит и прятать нечего,
            и запрет на печать числа выполнится сам собой.
            """)
        #expect(секунды == 434 * 3600)
        #expect(тишинаС == сигналы.lastUrine)

        // Инструмент: число, которого мы дальше запрещаем, обязано быть
        // непустым и обязано отличаться от даты, которую мы требуем.
        let число = Fmt.duration(секунды)
        let дата = Fmt.shortDay(тишинаС)
        #expect(число.isEmpty == false)
        #expect(дата.isEmpty == false)
        #expect(дата.contains(число) == false, """
            дата «\(дата)» содержит число «\(число)» — на этих величинах
            запрет «строка не печатает число» неотличим от запрета
            «строка не печатает дату». Сдвинь `сейчас` в сценарии.
            """)
        #expect(число.contains(дата) == false)
    }

    // MARK: - 2. Виджет: число не печатается, дата печатается

    /// От обратного и про РЕЗУЛЬТАТ, а не про вызов.
    ///
    /// «`sinceText` читает `urineSilenceSince`» выполнялось бы и тогда,
    /// когда строка прочла поле и всё равно напечатала число следующей
    /// ветвью. Проверяется то, что вернёт функция.
    @Test("Под тишиной строка виджета не несёт «сколько прошло»")
    func виджетНеПечатаетЧисло() throws {
        let (снимок, _) = Self.снимок(мочаЧасовНазад: 434)
        let тишинаС = try #require(снимок.urineSilenceSince)
        let число = Fmt.duration(try #require(снимок.sinceUrineSeconds))

        let строка = SnapshotText.sinceText(снимок)

        #expect(строка.contains(число) == false, """
            на виджете снова «моча \(число) назад» на дневнике, который
            забросили. Это утверждение о собаке, выведенное из отсутствия
            записи: приложение знает только, что никто ничего не отмечал.
            Ровно эта строка стояла на главном экране 21.09 и в ответе
            Siri 24.09.
            """)
        // Дата — измеренное, и она обязана быть: без неё человеку нечего
        // сопоставить с собственной памятью, а молчание он прочтёт как
        // «приложение сломалось».
        #expect(строка.contains(Fmt.shortDay(тишинаС)), """
            строка не называет, с какого числа отметок нет. «Нечего
            сказать» без даты — это не честность, а молчание.
            """)
    }

    // MARK: - 3. «Остров»: та же величина, и места под дату там нет

    /// Самая тесная поверхность и самая опасная: число стоит одно,
    /// без подписи, и верят ему больше всего.
    @Test("Под тишиной строка «острова» не несёт числа и не теряет кличку")
    func островНеПечатаетЧисло() throws {
        let (снимок, _) = Self.снимок(мочаЧасовНазад: 434)
        let число = Fmt.duration(try #require(снимок.sinceUrineSeconds))

        let строка = SnapshotText.inlineText(снимок)

        #expect(строка.contains(число) == false, """
            в «острове» снова голое «\(число)» рядом с кличкой. Здесь
            у числа нет ни подписи, ни даты — прочитать его можно только
            как «столько он терпит», а это ровно то, чего приложение
            не знает.
            """)
        #expect(строка.contains(снимок.dogName), "в «острове» потерялась кличка")
        #expect(строка != снимок.dogName, """
            «остров» под тишиной показывает одну кличку и молчит о моче
            вовсе. Пустое место читается как «данные не дошли»; сказать
            «нет отметок» короче и честнее.
            """)
    }

    // MARK: - 4. Обратная половина: настоящий сигнал обязан печататься

    /// Без неё набор остался бы зелёным у поверхности, которая молчит
    /// про мочу ВСЕГДА. Запрет «числа нет» выполняется и при отсутствии
    /// предмета — поэтому к нему обязана стоять пара.
    ///
    /// Сценарий тот самый, который Виктория просила сохранить: выход
    /// отмечен два часа назад, мочи в нём нет. Ради этого сигнала
    /// к врачу и идут, и заглушить его легче всего.
    @Test("Выход свежий, мочи в нём нет — обе строки печатают число")
    func настоящийСигналДоезжаетДоОбеихСтрок() throws {
        let (снимок, _) = Self.снимок(мочаЧасовНазад: 26, выходЧасовНазад: 2)

        #expect(снимок.urineSilenceSince == nil, """
            тишина погасила настоящую задержку: дневник ведут, выход
            отмечен два часа назад. Это не «нечего сказать», это сигнал.
            """)
        let число = Fmt.duration(try #require(снимок.sinceUrineSeconds))

        #expect(SnapshotText.sinceText(снимок).contains(число), """
            виджет молчит про мочу при настоящей задержке — тогда и запрет
            из проверки выше не значит ничего.
            """)
        #expect(SnapshotText.inlineText(снимок).contains(число),
                "«остров» молчит про мочу при настоящей задержке")
    }

    // MARK: - 5. Второе звено: производитель передаёт решение, а не считает

    /// Сторож на ВЫЗОВ, и потому слабый — назван слабым нарочно.
    ///
    /// Он видит, что имя упомянуто, и не видит, что от упоминания
    /// происходит. Поведенческого здесь нет и дешёвого нет:
    /// `publishSnapshot` просит `Dog` и `AppState`, пишет в `UserDefaults`
    /// и зовёт `WidgetCenter`, а возвращает `Void` — снимок из него
    /// не достать. Шов назван в `снимок(мочаЧасовНазад:)` выше.
    ///
    /// Запретная половина важнее требовательной: четвёртая реализация
    /// правила — это уже случившийся у Togo дефект. Виджет считал окно
    /// «не кормить» собственной арифметикой и молчал в двух случаях
    /// из трёх, пока главный экран правило знал.
    @Test("Снимок берёт решение о тишине готовым, а не сравнивает с сутками сам")
    func производительНеСчитаетСам() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let производитель = try String(
            contentsOf: корень.appendingPathComponent("Togo/Store/LiveActivityController.swift"),
            encoding: .utf8)

        #expect(производитель.contains("urineSilenceSince: signals.urineSilence"), """
            снимок больше не передаёт решение о тишине. Поле осталось,
            строки его читают — и получают `nil` всегда, то есть печатают
            число на заброшенном дневнике. Пропажа тихая: ни одна строка
            не ломается, просто ветка тишины не наступает никогда.
            """)
        #expect(производитель.contains("UrineSilence.ceiling") == false, """
            производитель снимка снова сравнивает с потолком сам. Правило
            живёт в `UrineSilence.start` и зовётся из `NeedSignals`;
            вторая реализация уедет при первой правке правила и промолчит.
            """)
    }

    // MARK: - 6. Границы этого набора

    /// Стоит последним нарочно, и к каждой границе названо, **что её
    /// снимет** — иначе граница переживёт свою причину, как пережила
    /// печать из `UrineSilenceTests` 28.09.
    @Test("Границы: что этот набор НЕ проверяет")
    func границыНабора() {
        // 1. **Что человек УВИДИТ — не проверено.** Набор меряет строку,
        //    а не кадр. Виджет живёт в `TogoWidgets`, его рисует
        //    SpringBoard, и `app.screenshot()` до него не достаёт.
        //    *Снимет границу:* кадр виджета любым способом — хоть
        //    превью `TodayWidgetView` в галерее отладки с подставленным
        //    снимком. Вью достижима, снимок собирается тремя строками;
        //    не сделано здесь, а не невозможно.
        //
        // 2. **Ступень тишины мочи не видел глазами никто ни на одной
        //    поверхности.** Проверено 05.10: `-Сценарий silence` до неё
        //    не доходит, и ПРИЧИНА не та, что была записана. Сценарий
        //    кладёт выход позавчера с `outcome = .both`, а `.both`
        //    считается мочой (`Diary.urineEvents`), — то есть моча там
        //    двухдневной давности, и `signals.urineSilence` срабатывает.
        //    Не доезжает вердикт: событий в сценарии два, `daysOfData`
        //    даёт 3, а `VerdictEngine.minimumDaysOfData` равен 4,
        //    и `guard` про нехватку данных стоит ВЫШЕ тишины. Экран
        //    отвечает «записей всего за 3 дня».
        //    *Снимет границу:* сценарий с историей от четырёх дней,
        //    в котором последние сутки пусты. Заведён отдельно
        //    от `silence`: добавить дни в `silence` значило бы сдвинуть
        //    вердикт под живым UI-тестом `ТишинаДольшеСуток`.
        //
        // 3. **Французского и украинского здесь нет.** Набор идёт
        //    на языке разработки и сравнивает вывод с выводом того же
        //    `Fmt`, то есть к переводу слеп по устройству. И язык виджета
        //    берёт СИСТЕМА, а не приложение: `-testLanguage` красит
        //    приложение под тестом, расширение остаётся на языке
        //    симулятора.
        //    *Снимет границу:* проверка, берущая ожидаемую строку
        //    из каталога, который собирается в бандл, — как сделано
        //    в `ВосстановлениеПокупок`.
        //
        //    И то, почему эта граница дороже, чем кажется, — замер
        //    сессии-переводчицы 05.10, не мой. Ключа `нет отметок`
        //    в каталоге не было ВОВСЕ: 2103 ключа на `933b13c`, его
        //    среди них нет. Значит `String(localized:)` отдавал литерал,
        //    и француз с украинцем читали в «острове» русское «нет
        //    отметок» — не «перевод лежал и не доезжал», а «переводить
        //    было нечего». Ключи `SnapshotText` заводит извлечение
        //    компилятором, а его после `10500d5` не запускал никто;
        //    `-exportLocalizations` 05.10 вырастил каталог до 2158,
        //    и 56 ключей он увидел впервые.
        //
        //    > Сторож полноты всё это время считал пробелы **среди
        //    > ключей, о которых каталогу рассказали**, и честно
        //    > показывал ноль. Третий за день случай одной формы —
        //    > рядом с печатью границы выше: инструмент не падал,
        //    > а отвечал успехом, и был прав по своему тексту.
        //
        //    Шаг «извлечение запускали после правки строк» не сторожит
        //    никто, и это дыра МЕЖДУ ролями: разработчик заводит
        //    `String(localized:)`, переводчица закрывает переводы,
        //    за шаг посередине не отвечает ни один.
        //
        // Ноль падений здесь значит «эти шесть утверждений целы»,
        // а не «ступень проверена».
        #expect(Bool(true))
    }
}

/// Сценарий демо-базы, которым ступень тишины **можно снять кадром**.
///
/// **Зачем отдельный набор.** Выше проверено, что строки ведут себя
/// верно на собранных руками сигналах. Это ещё не значит, что ступень
/// достижима в живом приложении: три зелёные части не складываются
/// в зелёный сценарий, а стыков всегда больше, чем частей. Здесь
/// проверяется стык — демо-база → `Diary.signals` → вердикт → строки
/// снимка — на тех самых данных, с которыми запустится UI-тест.
///
/// Без этого набора кадр мог бы сняться с экрана, где стоит «записей
/// всего за 3 дня», и быть принят за кадр тишины: ровно так `silence`
/// пять дней выглядел сценарием про мочу, не будучи им.
@Suite("Сценарий urineSilence доводит приложение до ступени тишины")
@MainActor
struct UrineSilenceScenarioTests {

    private func сигналыСценария() throws -> NeedSignals {
        let container = SeedData.makePreviewContainer(.urineSilence)
        let собаки = try container.mainContext.fetch(FetchDescriptor<Dog>())
        let собака = try #require(собаки.first, "демо-база без собаки")
        return Diary.signals(собака.events, now: Date(), episodeActive: false)
    }

    /// Первой — что сценарий наполнил базу, и наполнил именно так.
    ///
    /// «Вердикт — тишина» истинно и на пустой базе по другой причине,
    /// поэтому сперва проверяется, что данные есть и что `guard`
    /// про нехватку данных пройден. Он и был настоящей причиной, по
    /// которой до ступени не доходил `silence`.
    @Test("Сценарий дал историю длиннее минимума и сутки молчания")
    func сценарийНаполненИПройденПорогДанных() throws {
        let s = try сигналыСценария()

        #expect(s.daysOfData >= VerdictEngine.minimumDaysOfData, """
            истории \(s.daysOfData) дней при минимуме \
            \(VerdictEngine.minimumDaysOfData) — вердикт ответит «записей
            мало» и до тишины не дойдёт. Ровно на этом спотыкался
            сценарий `silence`: два события, три дня.
            """)
        let моча = try #require(s.lastUrine, "в сценарии нет ни одной отметки мочи")
        let выход = try #require(s.lastOutingAt, "в сценарии нет ни одного выхода")
        #expect(s.now.timeIntervalSince(моча) >= UrineSilence.ceiling)
        #expect(s.now.timeIntervalSince(выход) >= UrineSilence.ceiling, """
            выход в сценарии свежее суток — тогда это не тишина, а
            настоящий сигнал «выходили, мочи не было», и гасить его нельзя.
            """)
        // Интервалы нужны настоящие: без них вердикт уходит в `.ambiguous`
        // через `guard` про `typical`, то есть опять не до тишины.
        //
        // Величина разворачивается ДО сравнения — `try` справа
        // от оператора внутри `#expect` в этом наборе уже давал красный
        // без дефекта.
        let медиана = try #require(s.typicalUrineInterval, """
            интервалов мочи в сценарии нет: вердикт уйдёт в `.ambiguous`
            через `guard` про `typical`, то есть опять не до тишины.
            """)
        #expect(медиана > Diary.sameEmptyingWindow)
    }

