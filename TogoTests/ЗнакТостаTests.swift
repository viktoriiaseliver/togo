import Testing
import Foundation
@testable import Togo

/// Знак на плашке говорит то же, что её слово.
///
/// # Что было измерено
///
/// Замер 09.10.2026 на `527abbd`. `UndoToastView` рисовал
/// `checkmark.circle.fill` цветом `Token.Action.doneText` **безусловно**,
/// а через ту же плашку идут сообщения об отказе:
///
/// ```
/// вызовов showUndo всего                                 51
/// из них ОТКАЗЫ (отрицание в тексте, прочитаны глазами)  28
///    из них помечены Haptics.warning выше вызова         28  ← 28 из 28
///    без Haptics.warning                                  0
/// кнопка «Отменить» безусловна, action == nil у           46
/// ```
///
/// Две независимые оси — отрицание в самом тексте и предупреждающая
/// вибрация строкой выше — сошлись **полностью**. То есть приложение
/// **знало**, что это отказ: ответ был уже вычислен в месте вызова
/// и до знака не доезжал.
///
/// > **У нас записано: направление не передаётся значком, только
/// > словом.** Здесь была обратная ошибка — слово верное, а значок
/// > говорил противоположное. И говорил громче: глаз берёт его раньше
/// > фразы.
///
/// Цена измерена на мамином пути. Она входит публичной ссылкой, то есть
/// приём случается на холодном старте; увидев «Приглашение не открылось»
/// под зелёной галочкой, она уходит уверенной, что вошла, — ровно
/// то состояние, которое `ShareAcceptanceOutcome` заводился лечить.
///
/// # Граница, без которой утверждение шире замера
///
/// Знак стоит под `.accessibilityHidden(true)` в обеих раскладках —
/// значит **ложного успеха не получает тот, кто слушает**: пользователю
/// VoiceOver его не произносят вовсе. Дефект знака **зрительный**,
/// а не всеобщий. Мёртвая кнопка «Отменить» при этом озвучивается
/// как кнопка, то есть из двух дефектов одной плашки знак врёт
/// смотрящему, а кнопка — обоим.
///
/// Поправка не косметическая: первая редакция этого разбора говорила
/// «приложение говорит человеку неправду», и это было шире измеренного.
/// Для мамы не меняется ничего — она смотрит.
///
/// # Почему сторож читает исходник, а не поведение
///
/// Предмет — что НАРИСОВАНО в плашке. Поведенческого шва тут нет:
/// `UndoToastView` строит `Image` внутри `body`, и собрать его в тесте
/// нечем. Сторож на исходник ловит «знак снова безусловен» и честно
/// не ловит «знак не тот, который нужен»; второе закрывается кадром,
/// и кадра на 09.10.2026 **нет**.
///
/// # Как принимать
///
/// Подделок **две, а не одна**, и это обязательно: знак и кнопка —
/// разные предметы у одной двери. Одна подделка покрасила бы оба
/// утверждения, они выглядели бы взаимозаменяемыми, и следующий снял бы
/// «лишнее».
///
/// ```
/// подделка «галочка снова безусловна»   краснеет ТОЛЬКО знакГоворитТоЖе
/// подделка «кнопка снова безусловна»    краснеет ТОЛЬКО кнопкаПриЖивомДействии
/// ```
@Suite("Знак плашки и дорога к постоянному месту")
struct ЗнакТостаTests {

    /// Первой, а не последней: набор, которому нечего проверять, молчит
    /// так же, как набор, у которого всё хорошо. Без этой проверки
    /// опечатка в пути сделала бы пять остальных зелёными и пустыми.
    @Test("Сторожу было что читать")
    func былоЧтоПроверять() throws {
        for имя in Self.файлы {
            let текст = try код(имя)
            #expect(!текст.isEmpty, "исходник не прочитан: \(имя)")
            #expect(текст.count > 500, "исходник подозрительно короткий: \(имя)")
        }
    }

    /// Знак берётся у тона. Обе ветки обязаны существовать: одна
    /// на успех, другая на отказ.
    @Test("Знак говорит то же, что слово")
    func знакГоворитТоЖе() throws {
        let код = try код("RootView.swift")
        #expect(код.contains("toast.tone == .успех"),
                "знак снова не спрашивает тон — значит стоит безусловно")
        #expect(код.contains("checkmark.circle.fill"), "ветка успеха исчезла")
        #expect(код.contains("exclamationmark.triangle.fill"),
                "ветки отказа нет: все плашки снова обещают успех")
    }

    /// Кнопка — только когда есть что отменять.
    ///
    /// Условие используется в ДВУХ раскладках (строкой и столбцом),
    /// поэтому упоминаний у него три: объявление и два применения.
    /// Меньше трёх — значит одну раскладку оставили без условия,
    /// и на крупном шрифте кнопка снова мёртвая.
    @Test("Кнопка «Отменить» показывается при живом действии")
    func кнопкаПриЖивомДействии() throws {
        let код = try код("RootView.swift")
        #expect(код.contains("toast.action != nil"),
                "условие у кнопки снято — она вернулась во все 51 плашку")
        let упоминаний = код.components(separatedBy: "естьЧтоОтменять").count - 1
        #expect(упоминаний >= 3,
                "условие объявлено, но применено не ко всем раскладкам: \(упоминаний)")
    }

    /// Отказ приёма приглашения не идёт через тост успеха.
    @Test("Отказ приёма показывается как отказ")
    func отказПриёмаНеУспех() throws {
        let код = try код("TogoApp.swift")
        #expect(код.contains("исход.принято_ли"),
                "развилка исхода снята: успех и отказ снова показываются одинаково")
        #expect(код.contains("appState.showFailure("),
                "отказ снова уходит в showUndo, то есть под галочку")
    }

    // MARK: Отказ записи — ось от ДАННЫХ, а не от прозы

    /// Единственная дверь дневника не подтверждает несуществующую запись.
    ///
    /// # Почему этого не нашли два предиката, сошедшиеся «28 из 28»
    ///
    /// Ось «отрицание в тексте» слепа здесь **по устройству**: все
    /// четыре текста написаны утвердительно, без «не» — «Это записывает
    /// тот, кому разрешено». Ось «`Haptics.warning` строкой выше»
    /// промахнулась иначе: в `EventLog` вибрация стоит строкой **ниже**
    /// вызова, а в `DayPlanActions.checkPermission` её нет вовсе.
    ///
    /// > **Согласие двух осей читалось как полнота перебора, а обе
    /// > опирались на прозу и порядок строк.** Это хуже обычного
    /// > «согласие сломанных половин сигнала не даёт»: здесь оно
    /// > выглядело независимой сверкой.
    ///
    /// Поэтому ось здесь — **данные**: ветка кончается `return nil`
    /// (запись не создана), значит плашка обязана быть отказом.
    ///
    /// # Чего стоил дефект
    ///
    /// `EventLog` — единственная дверь, которой запись попадает
    /// в дневник. До опознания из `CKShare` гость — `.observer`
    /// («читает всё, не пишет»). Значит второй человек жал «покормила»,
    /// **в дневник не попадало ничего, и приложение показывало зелёную
    /// галочку «готово»**. Это его основной путь, а не краевой.
    @Test("Отказ по правам в единственной двери дневника — не успех")
    func отказПоПравамНеУспех() throws {
        let тело = try #require(тело(функции: "record", в: try код("EventLog.swift")),
                                "тело record() не разобрано — проверки ниже пусты")

        #expect(тело.contains(#"showFailure("Это записывает тот, кому разрешено")"#), """
            отказ по правам снова уходит в showUndo, то есть под галочку
            «готово». Запись при этом не создана — ветка кончается
            `return nil`, — и человек считает, что отметил.
            """)
        #expect(!тело.contains(#"showUndo("Это записывает"#),
                "у отказа по правам вернулась плашка успеха")
    }

    /// Сторож дублей — та же дверь и та же причина.
    ///
    /// «Уже записана в 15:23» под галочкой читается как «записал ещё
    /// раз», а не как отказ: ветка кончается `return nil`.
    @Test("Сторож дублей говорит отказом, а не галочкой")
    func сторожДублейНеУспех() throws {
        let тело = try #require(тело(функции: "record", в: try код("EventLog.swift")))

        #expect(тело.contains("showFailure(DuplicateGuard.message("),
                "сообщение о дубле снова идёт плашкой успеха")
        #expect(!тело.contains("showUndo(DuplicateGuard.message("),
                "сообщение о дубле вернулось под галочку")
    }

    /// Отказ в плане дня. Здесь ось строгая: **вся функция — путь
    /// отказа**, она кончается `return false`, поэтому плашки успеха
    /// в ней не бывает ни одной.
    ///
    /// Проверка на ноль, а не на присутствие: присутствие `showFailure`
    /// выполнялось бы и при оставшемся рядом `showUndo`, то есть
    /// утверждение прошло бы при живом дефекте.
    @Test("В плане дня отказ прав не показывается успехом")
    func отказВПланеДняНеУспех() throws {
        let тело = try #require(тело(функции: "checkPermission", в: try код("DayPlanActions.swift")),
                                "тело checkPermission() не разобрано")

        #expect(тело.contains("showFailure("), "отказ прав в плане дня перестал быть отказом")
        #expect(!тело.contains("showUndo("), """
            в checkPermission вернулась плашка успеха. Функция целиком —
            путь отказа (кончается `return false`), и успеха в ней
            быть не может ни в одной ветке.
            """)
    }

    /// Путь к постоянному месту назван существующими ключами.
    ///
    /// Два требования сразу, и второе важнее первого: **новый ключ
    /// завёл бы пробелы на en/fr/uk**, а у француза русская строка
    /// читается как решение, а не как пропуск. Поэтому путь собран
    /// из двух ключей, которые в каталоге уже есть на всех четырёх
    /// языках, — и пара стала цитатой интерфейса, то есть местом,
    /// где две строки обязаны совпасть.
    @Test("Путь собран из существующих ключей, нового текста нет")
    func путьИзСуществующихКлючей() throws {
        let код = try код("TogoApp.swift")
        #expect(код.contains(#"String(localized: "Семья")"#),
                "первая половина пути больше не ключ каталога")
        #expect(код.contains(#"String(localized: "Общий дневник")"#),
                "вторая половина пути больше не ключ каталога")

        let каталог = try каталогКлючей()
        for ключ in ["Семья", "Общий дневник", "Не получилось"] {
            let языки = каталог[ключ] ?? []
            #expect(языки.contains("ru") && языки.contains("en")
                    && языки.contains("fr") && языки.contains("uk"),
                    "ключ «\(ключ)» переведён не на все языки: \(языки.sorted())")
        }
    }

    /// Причина отказа переживает мимолётный показ.
    ///
    /// `исходПрочитан()` снимает **только** плашку. Снимет он заодно
    /// и причину — постоянное место окажется пустым ровно у того,
    /// кто до него дошёл, потому что плашку не успел прочесть.
    @Test("Отказ не стирается прочтением плашки")
    func отказПереживаетПоказ() throws {
        // Имена местных значений НЕ повторяют имена функций `код`
        // и `тело`: связывание затеняет функцию до конца области,
        // и следующий вызов `код(…)` ушёл бы в строку. Сборка поймала
        // это ошибкой «cannot call value of non-function type 'String'» —
        // то есть затенение здесь не стиль, а дефект.
        let обмен = try код("FamilyShare.swift")
        #expect(обмен.contains("НеудачаПриёма.текущая = новый.принято_ли ? nil : новый"),
                "объявление исхода больше не сохраняет причину отказа")

        let прочитан = try #require(тело(функции: "исходПрочитан", в: обмен),
                                    "функция исходПрочитан не найдена")
        #expect(!прочитан.contains("НеудачаПриёма"),
                "прочтение плашки снова стирает причину — постоянное место будет пустым")

        let экран = try код("SharedDiaryScreen.swift")
        #expect(экран.contains("НеудачаПриёма.текущая"),
                "постоянное место больше не читает причину отказа")
    }

    // MARK: Чтение исходников

    private static let файлы = ["RootView.swift", "TogoApp.swift",
                                "FamilyShare.swift", "SharedDiaryScreen.swift",
                                // Добавлены 09.10.2026 вместе с проверками
                                // отказа записи: без них «Сторожу было что
                                // читать» молчал бы про два новых файла,
                                // и опечатка в имени сделала бы три
                                // утверждения зелёными и пустыми.
                                "EventLog.swift", "DayPlanActions.swift"]

    /// Исходник по имени файла, уже без комментариев.
    ///
    /// Вырезание обязательно: голова этого же набора цитирует
    /// `checkmark.circle.fill` и `НеудачаПриёма`, а соседние файлы
    /// объясняют прозой, почему знак теперь условный. Сторож,
    /// не вырезающий комментарии, остался бы зелёным на подделке —
    /// у нас это измерено: из четырёх проверок одного набора вырезание
    /// умела одна, и у трёх остальных тот же дефект разбора давал
    /// ложную ЗЕЛЕНЬ.
    private func код(_ имя: String) throws -> String {
        безКомментариев(try #require(исходники().first { $0.0 == имя }?.1,
                                     "исходник не найден: \(имя)"))
    }

    /// Разбор построчный: `/* … */` он не видит, и строка с `://`
    /// внутри обрежется. Для предмета этих проверок хватает, полный
    /// разбор Swift был бы второй реализацией компилятора.
    private func безКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    /// Тело функции по имени — по счёту фигурных скобок, а не до первой
    /// закрывающей: иначе вложенный `if` оборвал бы разбор на середине
    /// и проверка «тело не упоминает X» прошла бы, не дочитав.
    private func тело(функции имя: String, в код: String) -> String? {
        guard let начало = код.range(of: "func \(имя)(") else { return nil }
        guard let открытая = код.range(of: "{", range: начало.upperBound..<код.endIndex) else { return nil }
        var глубина = 0
        var i = открытая.lowerBound
        while i < код.endIndex {
            if код[i] == "{" { глубина += 1 }
            if код[i] == "}" {
                глубина -= 1
                if глубина == 0 { return String(код[открытая.upperBound..<i]) }
            }
            i = код.index(after: i)
        }
        return nil
    }

    private func исходники() -> [(String, String)] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [(String, String)] = []
        for каталог in ["Togo", "TogoShared"] {
            let папка = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil) else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                найдено.append((url.lastPathComponent, текст))
            }
        }
        return найдено
    }

    /// Ключ → языки, у которых есть запись. Читается из каталога,
    /// а не из копии списка: две копии разошлись бы молча.
    private func каталогКлючей() throws -> [String: Set<String>] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let путь = корень.appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let данные = try Data(contentsOf: путь)
        let разбор = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
        let строки = (разбор?["strings"] as? [String: Any]) ?? [:]
        var итог: [String: Set<String>] = [:]
        for (ключ, значение) in строки {
            let переводы = (значение as? [String: Any])?["localizations"] as? [String: Any]
            // `Set(…keys.map(String.init))` неоднозначен — у `String`
            // инициализаторов много, и компилятор не выбирает. Ключи
            // словаря уже `String`, преобразовывать нечего.
            итог[ключ] = переводы.map { Set($0.keys) } ?? []
        }
        return итог
    }
}
