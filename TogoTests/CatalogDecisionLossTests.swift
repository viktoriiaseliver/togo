import Foundation
import Testing

/// Решение «не переводится» не исчезает из каталога вместе с ключом.
///
/// **Чего не видит ни один сторож проекта — УДАЛЕНИЯ.** Счёт пробелов
/// (`LocalizationCoverageTests.пробеловНет`) спрашивает «у всех ли
/// ключей каталога есть перевод». Ключ, которого в каталоге больше
/// нет, под этот вопрос не попадает: считать нечего, и сторож зелен.
/// То же у `PlaceholderOriginTests.примерыПереведены` — он читает
/// пометку у тех ключей, которые нашёл.
///
/// ```
/// пометку СНЯЛИ, ключ остался   → у ключа нет переводов → пробелы → КРАСНОЕ
/// ключ УДАЛИЛИ вместе с пометкой → считать нечего        → ЗЕЛЁНОЕ
/// ```
///
/// Вторая строка — не теория. Замер 23.10.2026: в рабочем дереве
/// каталог был переписан сборкой Xcode, и из него пропали три записи
/// с решением — ` · `, `Pro`, `Togo`. Все три литерала при этом живы
/// в коде (`TodayHeader.swift:163`, `TrainingScreens.swift:189`,
/// `OnboardingSteps.swift:84`). Прогон не покраснел бы: пропажу видно
/// только тому, кто сравнит два состояния файла, а этого не делает
/// никто.
///
/// Это **пятый случай одного класса за четверо суток** — четыре первых
/// разобраны в голове `Tools/extract_texts.py`: 19.10 тем же унесло эти
/// самые три ключа, 20.10 — `Lévothyrox` с решением Виктории,
/// 23.10 — четыре аргумента запуска. Каждый раз чинили **инструмент,
/// которым потеряли**, и каждый раз следующая потеря приходила другим
/// инструментом. `extract_texts.py` теперь пометку бережёт; Xcode
/// о ней не знает и знать не будет, а каталог переписывают оба.
///
/// > **Починка инструмента защищает от этого инструмента.
/// > От потери защищает проверка предмета.**
///
/// Поэтому ось здесь — не «работает ли сборщик», а «лежит ли решение
/// в каталоге», и спрашивается она у каталога напрямую.
///
/// **Цена потери несимметрична и уже измерена.** Лишний ключ стоит
/// строки в дифе. Утраченная пометка на `Lévothyrox` стоит возврата
/// четырёх разных брендов левотироксина в медицинское поле, которое
/// потом читает врач; утраченная пометка на аргументах запуска —
/// стенда, который перестаёт заводиться на казахском и украинском
/// телефоне, причём отказ приходит в форме «онбординг не показывается».
@Suite("Решения каталога не исчезают")
struct CatalogDecisionLossTests {

    /// Ключи, потеря которых УЖЕ СЛУЧИЛАСЬ и уже стоила работы.
    ///
    /// Это не копия каталога и не список всех пометок — это список
    /// происшествий. Он растёт только тогда, когда что-то потеряли
    /// на самом деле, и поэтому не расходится с каталогом молча:
    /// у каждой строки есть дата и то, чем потеря кончилась.
    ///
    /// Копия всех двадцати двух пометок здесь была бы той самой второй
    /// копией, которая разойдётся с источником и начнёт врать
    /// уверенным тоном. Копия восьми происшествий разойтись не может:
    /// происшествие нельзя «обновить», его можно только добавить.
    ///
    /// Снять запись отсюда — решение человека, и принимать его надо
    /// вслух: пометку ставила Виктория, снимать её инструментом нельзя.
    private static let потерянныеРанее: [String: String] = [
        " · ": "разделитель. Унесён 19.10.2026 и 23.10.2026",
        "Pro": "имя продукта. Унесён 19.10.2026 и 23.10.2026",
        "Togo": "название приложения. Унесён 19.10.2026 и 23.10.2026",
        "Lévothyrox": "решение Виктории 15.10.2026, один бренд во всех языках. Унесён 20.10.2026",
        "-Сценарий": "аргумент запуска. Унесён 23.10.2026",
        "-Онбординг": "аргумент запуска. Унесён 23.10.2026",
        "-ИсходПриёма": "аргумент запуска. Унесён 23.10.2026",
        "-ЧужаяЗона": "аргумент запуска. Унесён 23.10.2026",
    ]

    private static func каталог() throws -> [String: [String: Any]] {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: url))
            as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]
        return строки.compactMapValues { $0 as? [String: Any] }
    }

    /// Первым в наборе — своё зрение.
    ///
    /// Сторож, которому нечего читать, молчит ровно так же, как
    /// сторож, которому не на что жаловаться. Отличает их только
    /// проверка, что предмет вообще нашёлся, и она обязана стоять
    /// до всякого вывода.
    @Test("Было что проверять: каталог прочитан и пометки в нём есть")
    func былоЧтоПроверять() throws {
        let строки = try Self.каталог()
        #expect(строки.count > 500, """
            каталог прочитан не весь (\(строки.count) ключей).
            Разбор не состоялся; всё, что ниже, — про мой путь к файлу,
            а не про каталог.
            """)

        let спометкой = строки.filter { ($0.value["shouldTranslate"] as? Bool) == false }
        #expect(спометкой.count >= 8, """
            ключей с пометкой «не переводится» найдено \(спометкой.count).
            Их должно быть не меньше, чем происшествий в списке
            (\(Self.потерянныеРанее.count)). Меньше — значит разбор
            не состоялся или пометки унесло целым пластом.
            """)

        #expect(!Self.потерянныеРанее.isEmpty, """
            список происшествий пуст — сторожу не на что смотреть.
            Пустой список делает оба теста ниже зелёными, не проверив
            ничего.
            """)
    }

    /// Предмет: решение лежит в каталоге, и причина при нём.
    @Test("Каждое потерянное ранее решение стоит в каталоге")
    func решенияНаМесте() throws {
        let строки = try Self.каталог()

        var пропали: [String] = []
        var безПометки: [String] = []
        var безПричины: [String] = []

        for (ключ, зачем) in Self.потерянныеРанее.sorted(by: { $0.key < $1.key }) {
            guard let запись = строки[ключ] else {
                пропали.append("  «\(ключ)» — \(зачем)")
                continue
            }
            guard (запись["shouldTranslate"] as? Bool) == false else {
                безПометки.append("  «\(ключ)» — \(зачем)")
                continue
            }
            // Причина обязательна не у всех: `Pro` вошёл в каталог
            // без неё и так в нём и лежит. Требовать её здесь значит
            // покраснеть на том, чего мы не ломали. Проверяется то,
            // что было: наличие ключа и наличие пометки.
            let причина = (запись["comment"] as? String ?? "")
                .trimmingCharacters(in: .whitespacesAndNewlines)
            if ключ != "Pro" && причина.count < 10 {
                безПричины.append("  «\(ключ)» — \(зачем)")
            }
        }

        #expect(пропали.isEmpty, """
            из каталога пропали ключи с решением человека: \(пропали.count).

            \(пропали.joined(separator: "\n"))

            Эти ключи уже теряли, и каждый раз — перезаписью каталога
            целиком: `make texts` либо извлечение строк сборкой Xcode.
            Ключ исчез молча, потому что удаление не видит ни один
            счёт пробелов: считать стало нечего.

            Вернуть ТЕКСТОМ, не `json.dump`: тот переписывает формат
            всего файла (94 951 строка дифа вместо двух). Прежний вид
            записи лежит в git — `git show <коммит>:TogoShared/Resources/Localizable.xcstrings`.
            """)

        #expect(безПометки.isEmpty, """
            у ключей есть запись, но пометка «не переводится» снята: \(безПометки.count).

            \(безПометки.joined(separator: "\n"))

            Снятая пометка — это не пустое место: следующая вычитка
            переведёт аргумент запуска, и стенд перестанет заводиться
            на казахском и украинском телефоне. Отказ придёт в форме
            «онбординг не показывается».
            """)

        #expect(безПричины.isEmpty, """
            пометка стоит, а причины при ней нет: \(безПричины.count).

            \(безПричины.joined(separator: "\n"))

            Пометка без причины — кнопка гашения сторожа: через месяц
            она неотличима от дыры, и её «починят» переводом.
            """)
    }

    /// Второй предмет: ключ, у которого словаря локализаций нет ВОВСЕ.
    ///
    /// **Это не то же самое, что пробел, и различие стоит отдельной
    /// оси.** Пробел — «локализация заведена, перевода в ней нет»:
    /// так выглядит работа, до которой не дошёл переводчик. Отсутствие
    /// словаря целиком — подпись другого события: ключ дописан
    /// в каталог **сборкой Xcode**, а не нашим `Tools/extract_texts.py`.
    ///
    /// Различить их важно, потому что чинятся они по-разному.
    /// `extract_texts.py` пишет `%@` на всякую интерполяцию — это
    /// названное упрощение, оно стоит в голове файла. Рантайм
    /// спрашивает у каталога другой ключ: `%lld` у целого, `%lf`
    /// у дробного. Значит ключи с числом внутри наш сборщик
    /// **не может произвести по устройству**, и приезжают они только
    /// сборкой — вместе с переписанным файлом целиком.
    ///
    /// Замер 23.10.2026: таких ключей в дереве было 73 при нуле
    /// в последнем коммите, и на кадрах витрины `en-US`, `fr-FR`,
    /// `uk`, `kk` стоял русский текст — «гулял в 08:15», «как часто
    /// гуляете», шесть строк на экране питания. Пробел молчит
    /// по-английски; ключ без словаря **показывает человеку русскую
    /// строку**, и выглядит она намеренной.
    ///
    /// **Счёт пробелов на это КРАСНЕЕТ, и наряд, по которому заведён
    /// этот сторож, утверждал обратное.** Наряд говорил: «у этих ключей
    /// заводить нечего — словаря нет вовсе, и инструмент их не видит
    /// по устройству». Посылку перемерили двумя способами, и оба
    /// её сняли:
    ///
    /// ```
    /// ось пробелов, пересчитанная питоном на состоянии ДО правки
    ///      304 пробела на 76 ключах   ← счётчик видел бы их
    /// подделка через make guard: снять localizations у «гулял в %@»
    ///      «Ни один ключ не остался без перевода» → КРАСНЫЙ
    ///      остальные семь того набора зелёные
    /// ```
    ///
    /// Слепым счётчик не был. Зелёным он был потому, что **мерили
    /// вершину** (3403 ключа), а 73 ключа лежали в рабочем дереве
    /// незакоммиченными: отчёт отвечал про коммит, а вывод сделали
    /// про дерево. Это наш записанный класс — «исходник говорит, что
    /// задумали; база — что записано», только здесь разошлись коммит
    /// и диск.
    ///
    /// Поэтому отдельная ось здесь — **не ради второго красного**,
    /// а ради имени причины в сообщении: без него следующий пойдёт
    /// искать переводчика там, где надо смотреть, что переписала
    /// сборка. Если когда-нибудь это перестанет окупаться — убрать
    /// этот тест можно целиком, не трогая два выше: они про удаление,
    /// и их не дублирует никто.
    @Test("Нет ключей, у которых словаря локализаций нет вовсе")
    func словарьЕстьУКаждого() throws {
        let строки = try Self.каталог()
        #expect(строки.count > 500,
                "каталог прочитан не весь (\(строки.count)) — разбор не состоялся")

        let безСловаря = строки
            .filter { _, запись in
                guard (запись["shouldTranslate"] as? Bool) != false else { return false }
                let словарь = запись["localizations"] as? [String: Any] ?? [:]
                // Русский не считается: ключ и есть русская строка.
                return словарь.keys.filter { $0 != "ru" }.isEmpty
            }
            .keys.sorted()

        #expect(безСловаря.isEmpty, """
            ключей без единой локализации: \(безСловаря.count).

            \(безСловаря.prefix(20).map { "  \($0.prefix(70))" }.joined(separator: "\n"))\
            \(безСловаря.count > 20 ? "\n  …и ещё \(безСловаря.count - 20)" : "")

            Такой ключ отдаёт человеку РУССКУЮ строку на его языке,
            а не пустоту: откат идёт на язык разработки.

            Прежде чем звать переводчика, проверь происхождение:
              · `make texts` дописывает ключи с `%@` на всякую
                подстановку — это его названное упрощение;
              · сборка Xcode дописывает те же фразы с `%lld` и `%lf`,
                и ИМЕННО ИХ спрашивает рантайм. Наш сборщик такие
                ключи произвести не может по устройству.
            Расхождение этих двух видов и есть обычная причина.
            """)
    }
}
