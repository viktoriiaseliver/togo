@testable import Togo

/// Кадр плана дня по отзыву 30.10.2026 — её случай целиком.
///
/// **Куда пишет:** `build/кадры-план-дня/` в дереве проекта, адресом
/// от `#filePath`. Каталог в `.gitignore` — годный кадр выносится
/// в `Дизайн/кадры-приёмки/` руками.
///
/// # Зачем кадр, когда есть зелёный набор
///
/// Правка меняет то, что человек ЧИТАЕТ. `ПромежутокВПланеДняTests`
/// доказывает, что сборщик довозит `Промежуток` до пункта; он
/// не видит, доехала ли строка до пикселей. У Togo это оплачено
/// дважды за один день 04.11: правка боковых кромок затемнения
/// не работала (`List` обрезал ячейку), и прогон был зелёным
/// в обеих версиях — различил только кадр.
///
/// # Чем эта проверка отличается от «посмотреть глазами»
///
/// Снимаются ДВА кадра одного и того же плана — с промежутком
/// и без него, — и сравниваются высоты. Строка, не дошедшая
/// до отрисовки, высоту не меняет: это тот самый названный заранее
/// числом признак, без которого зелёный неотличим от слепоты оси.
///
/// Глазами на кадр смотрят отдельно. Одно не заменяет другого:
/// высота скажет, что строка нарисовалась, и не скажет, что в ней
/// написано.
@Suite("Кадр плана дня: промежуток назван вслух")
@MainActor
struct КадрПланаДняПромежутокTests {

    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-план-дня")
    }

    private func время(_ минута: Int) -> Date {
        Calendar.current.date(byAdding: .minute, value: минута,
                              to: Calendar.current.startOfDay(for: Date()))!
    }

    /// Её собака с её расписанием: часы и марка корма с кадра отзыва.
    private func стич() -> Dog {
        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.mealsPerDay = 3
        dog.mealTimes = [570, 930, 1290]            // 09:30 · 15:30 · 21:30
        dog.wakeMinuteOfDay = 9 * 60
        dog.sleepMinuteOfDay = 23 * 60
        dog.dailyNormGrams = 240                    // порция выходит 80 г
        dog.foodBrand = "Эдгар Купер"
        return dog
    }

    private func еда(_ минута: Int) -> LogEvent {
        LogEvent(kind: .meal, date: время(минута), authorName: "Виктория")
    }

    /// Снять кадр и вернуть путь с высотой.
    ///
    /// **Ось — ВЫСОТА, и годится она не везде.** `TGCard` плана дня
    /// считает высоту сам, своего `frame` здесь нет, и лишняя строка
    /// подписи меняет её по устройству. У вида с ЗАДАННОЙ высотой
    /// эта ось мерила бы мой собственный `frame` и была бы зелёной
    /// при любом поведении продукта — разбор у снятого теста шторки
    /// ниже.
    private func снять<V: View>(_ вид: V, имя: String) throws
        -> (путь: URL, высота: Int) {
        var нарисованное: UIImage?
        UITraitCollection(userInterfaceStyle: .dark).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, .dark)
                    .frame(width: 360)
                    .padding(16)
                    .background(Color(white: 0.04))
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }
        let картинка = try #require(нарисованное, "ImageRenderer не отдал картинку")
        let данные = try #require(картинка.pngData(), "картинка не превратилась в PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        let путь = Self.каталог.appendingPathComponent("\(имя).png")
        try данные.write(to: путь)
        return (путь, try #require(картинка.cgImage).height)
    }

    @Test("Строка про промежуток доходит до пикселей")
    func строкаДоходитДоПикселей() throws {
        // СЧЁТ КАДРОВ ПЕЧАТАЕТСЯ ВСЕГДА, в том числе после падения:
        // «снято два» и «упал на втором, снято один» выглядят в логе
        // одинаково — во втором случае строки просто нет, а её
        // отсутствия никто не ищет.
        var снято: [String] = []
        defer { print("КАДРОВ СНЯТО: \(снято.count) из 2 · \(снято.joined(separator: ", "))") }

        let пункты = DayPlanBuilder.items(dog: стич(),
                                          events: [еда(570), еда(1080)],   // 09:30 и 18:00
                                          now: время(1110))                // 18:30

        // КОНТРОЛЬ ПЕРВЫМ: кадру было что рисовать и чем различаться.
        #expect(пункты.count == 3, """
            пунктов \(пункты.count) при трёх кормлениях: план дня \
            не собрался, и обе высоты ниже будут про пустую карточку.
            """)
        #expect(пункты.last?.промежуток?.стоитНазвать == true, """
            у ужина нет промежутка, который стоит называть, — значит \
            «с» и «без» рисуют ОДНО И ТО ЖЕ, высоты совпадут, \
            и совпадение прочитается как «строка не дошла».
            """)

        let без = пункты.map { пункт -> DayPlanItem in
            var копия = пункт
            копия.промежуток = nil
            return копия
        }

        let сКадр = try снять(план(пункты), имя: "план-дня-промежуток-есть")
        снято.append("план-дня-промежуток-есть")
        let безКадр = try снять(план(без), имя: "план-дня-промежуток-снят")
        снято.append("план-дня-промежуток-снят")

        // Число названо ЗАРАНЕЕ: подпись рисуется `AppFont.caption`,
        // и лишняя её строка при `scale = 2` стоит заведомо больше
        // шестнадцати точек растра. Порог тупой нарочно — он ловит
        // не высоту строки, а её отсутствие.
        #expect(сКадр.высота - безКадр.высота >= 16, """
            план с промежутком \(сКадр.высота) px, без промежутка \
            \(безКадр.высота) px — разница \
            \(сКадр.высота - безКадр.высота) px.

            Строка «после еды в 18:00 — 3 ч 30 мин вместо 6 ч» \
            до отрисовки не дошла: в модели она есть, на кадре её нет. \
            Ровно так 04.11.2026 прошла зелёной правка кромок \
            затемнения, которую обрезал `List`.

            Кадры: \(сКадр.путь.path) и \(безКадр.путь.path)
            """)

        print("КАДР ПЛАНА ДНЯ: \(сКадр.путь.path) · высота \(сКадр.высота) px "
              + "против \(безКадр.высота) px без строки")
    }

    /// Кадр второй правки по тому же отзыву: «только сегодня».
    ///
    /// **Предмет здесь не час, а СЛОВО.** Разовое исключение ставит
    /// ужин на 22:00, и сам по себе этот час на кадре выглядит
    /// расписанием — на втором телефоне это прямая неправда. Строку
    /// «только сегодня» человек читает, значит приёмка у неё кадр,
    /// а не зелёный набор.
    ///
    /// # Ось у соседа ВЫСОТА, а здесь она не годится — замер 05.11.2026
    ///
    /// Первая редакция копировала соседа и мерила высоту. Прогон дал
    /// «622 px против 622 px, разница 0» — то есть сторож сказал
    /// «строка до пикселей не дошла», а она дошла: кадры весят
    /// 58 578 и 51 016 байт, и на картинке слова стоят.
    ///
    /// ```
    /// у соседа   «после еды в 18:00 — 3 ч 30 мин вместо 6 ч»
    ///            ПЕРЕНОСИТСЯ на вторую строку → высота растёт
    /// здесь      «только сегодня» дописывается в ТУ ЖЕ строку
    ///            через « · » → высота не меняется по устройству
    /// ```
    ///
    /// > **Ложный красный, и пострадавший у него не тот, кто мерил:**
    /// > следующий пошёл бы чинить `DayPlan.subtitle`, который цел.
    /// > Ось берут под предмет, а не под соседа — даже когда предмет
    /// > выглядит тем же («строка дошла до пикселей»).
    ///
    /// Ось сменена на **число различающихся пикселей**, и порог назван
    /// заранее: «только сегодня» кеглем `AppFont.caption` при
    /// `scale = 2` занимает около 180×20 точек растра, чернила кроют
    /// заведомо больше двухсот из них. Порог тупой нарочно — он ловит
    /// не начертание, а отсутствие.
    @Test("Строка «только сегодня» доходит до пикселей")
    func словоТолькоСегодняДоходит() throws {
        var снято: [String] = []
        defer { print("КАДРОВ СНЯТО: \(снято.count) из 2 · \(снято.joined(separator: ", "))") }

        let dog = стич()
        dog.mealTimesOverrideDay = Calendar.current.startOfDay(for: Date())
        dog.mealTimesOverride = [570, 930, 22 * 60]

        let пункты = DayPlanBuilder.items(dog: dog, events: [], now: время(600))

        // КОНТРОЛЬ ПЕРВЫМ: кадру было что рисовать и чем различаться.
        #expect(пункты.filter { $0.kind == .meal }.count == 3, """
            пунктов еды не три: план дня не собрался, и обе высоты \
            ниже будут про пустую карточку.
            """)
        #expect(пункты.contains { $0.сегодняИначе }, """
            ни один пункт не помечен «сегодня иначе» — значит «с» \
            и «без» рисуют ОДНО И ТО ЖЕ, высоты совпадут, \
            и совпадение прочитается как «строка не дошла».
            """)

        let без = пункты.map { пункт -> DayPlanItem in
            var копия = пункт
            копия.сегодняИначе = false
            return копия
        }

        let сКадр = try снять(план(пункты, now: время(600)), имя: "план-дня-только-сегодня")
        снято.append("план-дня-только-сегодня")
        let безКадр = try снять(план(без, now: время(600)), имя: "план-дня-только-сегодня-снято")
        снято.append("план-дня-только-сегодня-снято")

        let разных = try Self.разныхПикселей(сКадр.путь, безКадр.путь)
        #expect(разных >= 200, """
            кадры «с пометкой» и «без» различаются \(разных) пикселями \
            при пороге 200.

            Слово «только сегодня» до отрисовки не дошло: в модели \
            оно есть, на кадре его нет. Тогда второй человек видит \
            «22:00» и читает это как новое расписание.

            Кадры: \(сКадр.путь.path) и \(безКадр.путь.path)
            """)

        print("КАДР «ТОЛЬКО СЕГОДНЯ»: \(сКадр.путь.path) · "
              + "различающихся пикселей \(разных) · высота \(сКадр.высота) px")
    }

    /// Сколько пикселей различают два кадра одного размера.
    ///
    /// Разные размеры — отказ, а не «различаются целиком»: это значит,
    /// что сравнивают не то, и молчаливо вернуть большое число значило
    /// бы выдать промах за находку.
    private static func разныхПикселей(_ левый: URL, _ правый: URL) throws -> Int {
        func пиксели(_ путь: URL) throws -> (Data, Int, Int) {
            let картинка = try #require(UIImage(data: try Data(contentsOf: путь))?.cgImage)
            let ш = картинка.width, в = картинка.height
            var байты = [UInt8](repeating: 0, count: ш * в * 4)
            let контекст = try #require(CGContext(
                data: &байты, width: ш, height: в, bitsPerComponent: 8,
                bytesPerRow: ш * 4, space: CGColorSpaceCreateDeviceRGB(),
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
            контекст.draw(картинка, in: CGRect(x: 0, y: 0, width: ш, height: в))
            return (Data(байты), ш, в)
        }
        let (а, шА, вА) = try пиксели(левый)
        let (б, шБ, вБ) = try пиксели(правый)
        #expect(шА == шБ && вА == вБ, """
            кадры разного размера: \(шА)×\(вА) и \(шБ)×\(вБ). \
            Сравнивать их попиксельно нельзя — число вышло бы \
            про размер, а не про содержимое.
            """)
        guard шА == шБ, вА == вБ else { return 0 }
        var разных = 0
        for i in stride(from: 0, to: а.count, by: 4) where
            а[i] != б[i] || а[i + 1] != б[i + 1] || а[i + 2] != б[i + 2] {
            разных += 1
        }
        return разных
    }

    // ТЕСТ ШТОРКИ «КОГДА ДАЛИ?» СНЯТ, И ВОТ ЧЕМ ЭТО ОПЛАЧЕНО.
    //
    // Вторая половина отзыва — «А обед отметить как Дан» — в продукте
    // ЕСТЬ и живёт с 28.09.2026: тап по кругу просроченного пункта →
    // `LateMarking.asksWhenGiven` → `GivenAtSheet` с выбором
    // «в 15:30, как назначено · сейчас · другое время».
    //
    // Снять её кадром отсюда НЕЛЬЗЯ. Замер 04.11.2026: `ImageRenderer`
    // отдаёт `TGSheet` ПУСТЫМ — на кадре только полоска `TGSheetHandle`
    // сверху и чернота; два кадра, «сегодня» и «прошлый день», вышли
    // БАЙТ В БАЙТ одинаковыми (28 038 б каждый). Ни содержимое
    // `ScrollView`, ни кнопка подвала не нарисовались.
    //
    // **Причина НЕ установлена** — `ScrollView` без хоста, окружение
    // шторки, `themeSurface` — кандидатов три, и назвать один из них
    // значило бы придумать объяснение к верному замеру.
    //
    // > **Тест, который краснеет не на продукте, дороже отсутствующего:**
    // > он уводит чинить `GivenAtSheet`, который цел. Поэтому здесь
    // > его нет, а долг назван: правило «в прошлом дне строки „Сейчас"
    // > быть не должно» по-прежнему не сторожит никто, и закрывается
    // > оно UI-прогоном, а не отрисовкой.
    //
    // Соседний кадр плана дня тем же `ImageRenderer` рисуется целиком —
    // значит дело в шторке, а не в способе съёмки.

    /// План дня ровно в том виде, в каком его видит человек.
    ///
    /// **«Сделано» здесь свёрнуто, и развернуть его кадром нельзя:**
    /// `showsDone` — внутреннее `@State`. Это не ограничение съёмки,
    /// а сам предмет. Закрытый обед несёт «покормлено в 18:00»,
    /// и он спрятан; видно только ужин. Ради этого строку про
    /// следствие и завели — причина у человека под свёрткой.
    ///
    /// **`now` аргументом, и это правка по кадру 05.11.2026.** Пока
    /// час был зашит в 18:30, кадр «только сегодня» строился
    /// на пунктах, собранных на 10:00, а раскрашивался на 18:30 —
    /// и завтрак с обедом желтели просрочкой, которой в этом сценарии
    /// нет. Кадр при этом был «снят и зелен»: у просрочки своя
    /// причина, и глазами она читается как часть предмета.
    private func план(_ пункты: [DayPlanItem], now: Date? = nil) -> some View {
        DayPlanList(items: пункты, now: now ?? время(1110), onComplete: { _ in })
    }
}
