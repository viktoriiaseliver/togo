import Testing
import Foundation
@testable import Togo

/// Фотографии Unsplash лежат в ресурсах — значит релиз пока нельзя.
///
/// **Этот сторож рождён КРАСНЫМ нарочно, как и `BackupContentsPromise`
/// в своё время.** 27.10.2026 Виктория попросила: «добавь из Unsplash,
/// потом заменим», и сама же назвала цену — её слова, записанные
/// дважды: «лицензия Unsplash — свободно для макетов, но НЕ ДЛЯ СТОРА
/// без замены».
///
/// > «Потом заменим» — это обещание без читателя. У него нет ни даты,
/// > ни места, ни того, кто заметит, что срок прошёл. Красный тест —
/// > и есть читатель: он спросит про замену на каждом прогоне.
///
/// Почему сторожем, а не записью в журнале: журнал читают, когда ищут,
/// а эти файлы уедут в сборку сами, в обычный день, вместе с любой
/// другой правкой. Отличить такую сборку от честной будет нечем —
/// фотография в бандле выглядит одинаково, чья бы она ни была.
///
/// # Как его погасить
///
/// Заменить фотографии на свои (или купленные) и убрать префикс
/// `unsplash-` из имён файлов и из `BackgroundBridge.фоныРазделов`.
/// Тест погаснет сам — он не знает никаких имён, кроме этого признака.
///
/// # Чего он НЕ проверяет
///
/// Лицензию как таковую. Он считает файлы по имени, и файл, названный
/// иначе, пройдёт насквозь — поэтому префикс и стоит в правиле
/// рядом с объявлением списка, а не только здесь.
@Suite("Unsplash в продукте")
struct UnsplashВПродуктеTests {

    /// Каталог ресурсов с подложками — от этого файла вверх и вбок,
    /// а не из бандла: тест обязан видеть то, что лежит в git,
    /// а не то, что собралось.
    private var каталогПодложек: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Подложки")
    }

    @Test("В ресурсах нет фотографий Unsplash")
    func unsplashУехалИзРесурсов() throws {
        let файлы = try FileManager.default
            .contentsOfDirectory(atPath: каталогПодложек.path)

        // Сканер, переставший что-либо находить, молчит так же,
        // как тот, кому нечего сказать: если каталог пуст или путь
        // сбился, «ноль Unsplash» означало бы не то же самое.
        #expect(!файлы.isEmpty, """
            каталог подложек пуст или не найден: \(каталогПодложек.path).
            Проверять нечего, и зелёный цвет здесь ничего не значит.
            """)

        let чужие = файлы.filter { $0.hasPrefix("unsplash-") }.sorted()

        #expect(чужие.isEmpty, """
            В ресурсах лежат \(чужие.count) фотографий Unsplash:
            \(чужие.joined(separator: ", "))

            Это ЗАГЛУШКИ ПРОТОТИПА, и релиз с ними выпускать нельзя —
            лицензия Unsplash позволяет макеты, но не App Store.
            Слова Виктории 27.10.2026: «добавь из Unsplash, потом
            заменим».

            Сейчас «потом» ещё не наступило, и это нормально: сторож
            держит обещание до дня замены, а не требует её сегодня.

            Чтобы погасить: заменить фотографии своими и убрать
            префикс `unsplash-` из имён и из
            `BackgroundBridge.фоныРазделов`.
            """)
    }

    /// Граница: список в коде и файлы на диске — две разные вещи.
    ///
    /// Можно убрать имя из `фоныРазделов` и забыть файл в каталоге —
    /// тогда он не показывается, но едет в бандле. Можно наоборот.
    /// Сторож выше смотрит на ДИСК, этот — на согласие двух списков.
    @Test("Список фонов в коде совпадает с файлами на диске")
    func списокСходитсяСДиском() throws {
        let файлы = Set(try FileManager.default
            .contentsOfDirectory(atPath: каталогПодложек.path))
        let названные = Set(BackgroundBridge.фоныРазделов)

        let названныеБезФайла = названные.subtracting(файлы).sorted()
        let файлыБезИмени = файлы
            .filter { $0.hasPrefix("unsplash-") }
            .subtracting(названные).sorted()

        #expect(названныеБезФайла.isEmpty, """
            в списке есть имена, которых НЕТ на диске:
            \(названныеБезФайла.joined(separator: ", ")).
            Человек увидит чёрный экран вместо фона.
            """)
        #expect(файлыБезИмени.isEmpty, """
            на диске лежат файлы Unsplash, которых нет в списке:
            \(файлыБезИмени.joined(separator: ", ")).
            Они не показываются, но ЕДУТ В БАНДЛЕ — то есть
            в App Store уедут тоже.
            """)
    }
}
