import Testing
import Foundation
@testable import Togo

/// Роль, назначенная НОВИЧКУ, не двигает того, кто уже вошёл.
///
/// # Чего стоил дефект
///
/// Замер 25.10.2026. `РолиВОбмене.назначение` падала на `наряд.новичкам`
/// всякий раз, когда в `поУчастникам` не было ключа участника, —
/// а `поУчастникам` **не пишет никто**. Это не предположение: так
/// сказано в доккомментарии `FamilyShare.назначитьНовичкам`
/// («поимённое назначение этим путём не делается, и причина
/// структурная»), и подтверждено тем, что `FamilyMember` убран
/// из обмена решением 08.10.2026 (`SharedDiary.swift:78`).
///
/// Значит ветка `поУчастникам` недостижима, и вошедший падал
/// на `новичкам` **бесконечно**:
///
/// ```
/// 1. Виктория зовёт Машу «наблюдателем»   новичкам = наблюдатель
/// 2. Маша входит                          поУчастникам пуст →
///                                         наблюдатель  ✔ верно
/// 3. позже зовёт маму «ухаживающей»       новичкам = ухаживающая
/// 4. телефон Маши синхронизируется        поУчастникам ПУСТ →
///                                         МАША СТАЛА УХАЖИВАЮЩЕЙ
/// ```
///
/// Шага 4 не выбирал никто. `обновитьНазначение` зовётся при каждой
/// синхронизации (`FamilySync.swift:288`), то есть повышение приезжает
/// само и молча, и ни один экран о нём не говорит. Цена: `.giveDose` —
/// это отметка дозы лекарства, её потом читает врач.
///
/// # Почему сторож стоит на чистом значении, а не на прогоне
///
/// Приватную базу CloudKit мы измерить не можем вовсе — ни ключ ASC,
/// ни токен GitHub её не открывают. Поэтому проверяется то, что
/// вынесено в чистое значение: **выбор назначения**. Что поле
/// на `CKShare` действительно приезжает на второй телефон, этим
/// не проверено и проверяется только у Виктории на двух телефонах.
///
/// Хранилище `НазначениеПоОбмену` здесь не трогается нарочно: оно
/// живёт в группе приложений, то есть в состоянии, общем на весь
/// прогон, и запись в него меняла бы ответ соседей по набору
/// (тот же довод стоит в `ПриехавшаяРольTests`). Приколотое назначение
/// передаётся **явно**, доводом `уже:`.
@Suite("Новичкам не двигает вошедших")
struct НовичкамНеДвигаетВошедшихTests {

    private let наблюдатель = НазначеннаяРоль(роль: .observer)
    private let ухаживающая = НазначеннаяРоль(роль: .caregiver)

    // MARK: - Контроль: без этого всё ниже зелено и при сломанном выборе

    @Test("Контроль: новичок БЕЗ приколотого получает новичкам")
    func новичокПолучаетНовичкам() {
        let наряд = НарядРолей(новичкам: ухаживающая)
        let вышло = РолиВОбмене.назначение(из: наряд, участник: "U-маша", уже: nil)
        #expect(вышло == ухаживающая, """
        Это единственная дорога решения Виктории «роль выбираете вы \
        при приглашении»: в момент приглашения участника ещё \
        не существует, и ключа, под который писать роль, нет ни у кого. \
        Сломайся она — приглашение перестало бы что-либо значить, \
        и остальные тесты набора этого НЕ ЗАМЕТИЛИ БЫ: у них \
        приколотое не пусто, они бы и дальше проходили.
        """)
    }

    @Test("Контроль: двух разных ролей в наборе не спутали")
    func ролиРазные() {
        #expect(наблюдатель != ухаживающая)
        #expect(наблюдатель.роль?.defaultPermissions.contains(.giveDose) == false,
                "наблюдатель дозу не отмечает — иначе весь предмет ниже пустой")
        #expect(ухаживающая.роль?.defaultPermissions.contains(.giveDose) == true,
                "ухаживающая отмечает — иначе повышение ничего не повышает")
    }

    // MARK: - Предмет

    @Test("Вошедшего наблюдателем не повышает приглашение ухаживающей")
    func вошедшегоНеПовышает() {
        // Виктория позвала маму ухаживающей — наряд новичкам изменился.
        let наряд = НарядРолей(новичкам: ухаживающая)
        // Телефон Маши синхронизируется. У неё уже приколот наблюдатель.
        let вышло = РолиВОбмене.назначение(из: наряд, участник: "U-маша",
                                           уже: наблюдатель)
        #expect(вышло == наблюдатель, """
        МОЛЧАЛИВОЕ ПОВЫШЕНИЕ. Маша вошла наблюдателем; Виктория \
        назначила роль МАМЕ, а приехало это Маше, потому что \
        `поУчастникам` не пишет никто и всякий вошедший остаётся \
        «тем, кого в списке ещё нет». Выбора не делал ни один человек. \
        Получила Маша `.giveDose` — отметку дозы лекарства, которую \
        потом читает врач.
        """)
    }

    @Test("Вошедшую ухаживающей не понижает приглашение наблюдателя")
    func вошедшегоНеПонижает() {
        let наряд = НарядРолей(новичкам: наблюдатель)
        let вышло = РолиВОбмене.назначение(из: наряд, участник: "U-мама",
                                           уже: ухаживающая)
        #expect(вышло == ухаживающая, """
        Обратная половина того же дефекта, и она тоже ничья: Виктория \
        позвала ситтера наблюдателем — у мамы пропало право на дозу. \
        Признак «право отозвали» и признак «назначили роль новому \
        человеку» в наряде НЕОТЛИЧИМЫ, и ошибаться надо в сторону \
        того, что человек видел у себя. Органа для отзыва на экране \
        нет вовсе: роль выбирается только в приглашении \
        (`FamilyScreen.swift:584`).
        """)
    }

    @Test("Поимённое сильнее приколотого — канал, когда он появится")
    func поимённоеСильнееПриколотого() {
        let наряд = НарядРолей(поУчастникам: ["U-маша": ухаживающая],
                               новичкам: наблюдатель)
        let вышло = РолиВОбмене.назначение(из: наряд, участник: "U-маша",
                                           уже: наблюдатель)
        #expect(вышло == ухаживающая, """
        Прикол обязан уступать поимённому, иначе правка 25.10 закрывает \
        дефект ценой того, что настоящий канал прав не заработает \
        никогда: сегодня `поУчастникам` не пишет никто, и если прикол \
        будет сильнее, то он не заработает и после того, как писателя \
        заведут. Это тот же класс, что «поле без читателя»: \
        недостижимая ветка выглядит рабочей.
        """)
    }

    @Test("Участник без идентификатора: прикол действует и на нём")
    func безИдентификатора() {
        let наряд = НарядРолей(новичкам: ухаживающая)
        let вышло = РолиВОбмене.назначение(из: наряд, участник: nil,
                                           уже: наблюдатель)
        #expect(вышло == наблюдатель, """
        `userRecordID` CloudKit отдаёт не всегда — слой это уже знает \
        про имя (`ShareAcceptance.чьёИмя`). Человек без \
        идентификатора НОВИЧКОМ от этого не становится: у него есть \
        приколотое, значит он входил. Иначе ровно те гости, у которых \
        облако не отдало идентификатор, повышались бы и дальше — \
        то есть дефект уцелел бы на самой непредсказуемой части людей.
        """)
    }

    @Test("Наряда не прочли — ответ пустой, прикол не трогаем")
    func нарядНеПрочли() {
        let вышло = РолиВОбмене.назначение(из: nil, участник: "U-маша",
                                           уже: ухаживающая)
        #expect(вышло == nil, """
        Пустой ответ здесь значит «писать в хранилище нечего», \
        а не «прав нет»: `обновитьНазначение` на `nil` выходит \
        НЕ ТРОНУВ `НазначениеПоОбмену.текущее` (`FamilyShare.swift`), \
        и приколотое переживает. Верни отсюда приколотое — и смысла \
        не изменится, но исчезнет различение «наряд не прочли» \
        и «наряд прочли и там это», а оно нужно для разбора отказов.
        """)
    }
}
