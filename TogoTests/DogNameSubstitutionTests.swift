/// Кличку человеку показывают через одну точку, а не напрямую из `name`.
///
/// **Повод не теоретический: отзыв TestFlight 06.10.2026 на сборке 271.**
/// У человека в списке стояли восемь строк без клички, а у девятой —
/// настоящей — кличка могла пропасть совсем: пустой снимок с поздним
/// `changedAt` побеждает в слиянии и затирает `name` живой собаки
/// (замер `togo-05`). Приём записи чинится у источника; этот сторож —
/// про вторую половину, про ПОКАЗ.
///
/// **Почему сторож понадобился, хотя поверхности уже нашли руками.**
/// Нашли их трижды и трижды ошиблись в числе: сперва две, потом три
/// (столько успели увидеть вдвоём), потом двадцать одна замером, потом
/// тридцать с расширениями. Каждое следующее число было больше
/// предыдущего, и ни одно из первых трёх не было замером. Список,
/// составленный руками, знает только то, что в него положили, —
/// а подстановка номер тридцать один будет написана завтра.
///
/// **Почему запрет, а не требование.** «Экран обязан звать
/// `displayName`» грепом не проверяется: у вызова десять форм,
/// и сторож на требование даёт шум — у нас это стоило семидесяти девяти
/// ложных находок на Timer. «Экран не смеет читать `dog.name`»
/// проверяется надёжно: запретное узнаётся по своему имени целиком.
///
/// **Почему счётом с храповиком, а не нулём.** Сторож, красный в день
/// рождения, учит не верить красному, а это дороже пропущенного дефекта.
/// В день записи подстановок двадцать девять; число пускается только
/// вниз. Цель — ноль, и до неё его надо подтягивать, а не ждать.
///
/// **Чего этот сторож не видит — последней строкой вывода и здесь:**
///
/// 1. Он читает исходник, а не экран. «Позвали правильную точку, а она
///    вернула пустоту» он не поймает — это наш класс «имя упомянуто,
///    и от упоминания ничего не происходит». Для него нужен кадр.
/// 2. Он не видит `WalkLiveActivity`: вид «острова» принимает
///    `ActivityViewContext` и вне живой активности не строится ничем.
///    Поверхность не непроверенная, а **непроверяемая**, и лечится это
///    входом, а не сторожем.
/// 3. Цепочку он закрывает одним образцом нарочно. `snapshot.dogName`
///    и `context.attributes.dogName` — не источники, а переносчики:
///    их наполняют `LiveActivityController` и `ReminderScheduler`,
///    и наполняют из `dog.name`, то есть из того, что сторож и ловит.
///    Ловить переносчиков отдельно значило бы краснеть дважды на один
///    дефект и шуметь на их объявлениях.
@Suite("Кличка показывается через одну точку")
