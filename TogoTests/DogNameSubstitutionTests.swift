    /// **Мало объявить исключение и мало проверить, что оно закрывает
    /// существующее, — надо проверить, что оно применяется.**
    ///
    /// Первый прогон этого сторожа 07.10.2026 нашёл у него самого ровно
    /// такой дефект: из-за симлинка `/tmp` → `/private/tmp` ключи
    /// `слоиДанных` не совпадали ни с одним файлом, и весь список
    /// исключений молча не работал. `разрешённыеСлоиСуществуют` при этом
    /// был зелёным: файлы-то на месте.
    ///
    /// Тот же класс, что слияние словарей у проверки обещаний —
    /// проверка осматривала половину и молчала как целая.
    @Test("Список исключений не просто объявлен, а срабатывает")
    func исключениеСрабатывает() {
        let (_, _, закрыто, _) = обход()
        #expect(закрыто.count >= 2, """
            исключением закрыто \(закрыто.count) файлов, а в день записи
            было не меньше двух (редактор клички и служебные метки
            прогрева — оба читают `dog.name` по делу). Ноль или один
            значит, что список исключений перестал применяться,
            а не что слои данных исчезли: это разные беды, и снаружи
            они неразличимы.

            Закрыто: \(закрыто.sorted().joined(separator: ", "))
            """)
    }

    /// **Мало завести пометку — надо проверить, что она применяется.**
    ///
    /// Утром 07.10 у этого же сторожа весь список файловых исключений
    /// молча не работал из-за симлинка `/tmp` → `/private/tmp`, и
    /// `разрешённыеСлоиСуществуют` был при этом зелёным: файлы-то
    /// на месте. Пометка — тот же класс риска, только строкой:
    /// опечатка в слове, и она перестанет находиться, а сторож
    /// покраснеет на верном коде либо пропустит дефект.
    @Test("Пометка «едет в слот» не просто заведена, а срабатывает")
    func пометкаСрабатывает() {
        let (_, _, _, вСлот) = обход()
        #expect(вСлот.count >= Self.записаноПомеченных, """
            пометкой закрыто \(вСлот.count) строк, а в день записи было \
            \(Self.записаноПомеченных) — четыре входа живой активности. \
            Ноль или меньше значит, что пометка перестала находиться \
            (опечатка, переименование, срез комментариев), а не что \
            входов не стало.

            Помечено: \(вСлот.sorted().joined(separator: ", "))
            """)
    }

