    /// Корень репозитория, с разрешёнными симлинками.
    ///
    /// **`resolvingSymlinksInPath()` здесь не аккуратность, а починка
    /// настоящего дефекта этого сторожа, пойманная его же первым
    /// прогоном 07.10.2026.** `#filePath` отдавал `/tmp/…`, а обходчик
    /// каталогов — `/private/tmp/…` (на macOS `/tmp` — симлинк).
    /// Обрезка префикса промахивалась, относительные имена выходили
    /// вида `/privateTogo/App/RootView.swift`, и **ни один ключ
    /// `слоиДанных` не совпадал ни разу**: весь список исключений
    /// молча не работал.
    ///
    /// Снаружи это не выглядело поломкой — сторож находил нарушения
    /// и печатал список. Разошлось только число: 33 вместо 29,
    /// ровно на четыре разрешённых строки. Совпади оно случайно —
    /// уехал бы сторож, у которого мёртв весь список исключений,
    /// а `разрешённыеСлоиСуществуют` при этом зелёный, потому что
    /// проверяет существование файлов, а не срабатывание исключения.
    ///
    /// Отсюда тест `исключениеСрабатывает` ниже: мало объявить
    /// исключение и мало проверить, что оно закрывает существующее, —
    /// надо проверить, что оно вообще применяется.
    /// Пометка «кличка едет в слот, а не на экран».
    ///
    /// **Третья категория появилась не из удобства, а из того, что два
    /// моих же сторожа разошлись на одном коде 07.10.2026.**
    /// `CaseSlotFallbackTests` требует передавать в живую активность
    /// СЫРОЕ имя: один вход кормит и именительный слот (ярлык
    /// с иконкой), и винительные (обе подписи), а падеж знает только
    /// слот. Этот сторож ровно это считал нарушением.
    ///
    /// > **Два сторожа, написанные против одного дефекта с двух
    /// > сторон, сходятся в точке, где требуют обратного друг другу.**
    /// > Поймать это может только прогон, где они красные
    /// > одновременно.
    ///
    /// Разрешено **строкой, а не файлом**. Файловое исключение здесь
    /// было бы дырой: `NeedsSheet`, `WalkMode` и `WalkIntents` несут
    /// и настоящий показ тоже, и он спрятался бы за разрешением.
    /// Пометка стоит вплотную — на той же строке или строкой выше, —
    /// и обязана нести причину: пустая пометка неотличима от дыры.
    private func помечена(строка индекс: Int, в строки: [String]) -> Bool {
        for i in [индекс, индекс - 1] where строки.indices.contains(i) {
            guard let место = строки[i].range(of: Self.пометка) else { continue }
            let причина = строки[i][место.upperBound...]
                .trimmingCharacters(in: .whitespaces)
            if причина.count >= 10 { return true }
        }
        return false
    }

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
            .resolvingSymlinksInPath()
    }

    /// Текст без комментариев.
    ///
    /// **Без этого сторож меряет прозу, а не код.** Класс выстрелил
    /// у нас уже дважды: сторож на вызов покраснел на комментарии
    /// «// НЕ `MapsApp.allCases`», мера отказов хранилища посчитала
    /// строку документации теста. В файлах ниже после 07.10 лежат
    /// комментарии со словом `dog.name` — включая этот.
    ///
    /// Вторая копия этого метода в наборе (первая —
    /// `ComponentTokenScopeTests`). Третья будет поводом вынести;
    /// две живут порознь нарочно, чтобы сторожа не падали вместе.
    private func безКомментариев(_ текст: String) -> [String] {
        var строки: [String] = []
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { строки.append(""); continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            строки.append(String(s))
        }
        return строки
    }

    /// Чтение клички у собаки — именем ЦЕЛИКОМ, а не префиксом.
    ///
    /// У Gamut сторож сверял `hasPrefix("struct Swatch")` и месяцами
    /// находил `struct SwatchRow`, то есть мерил другой компонент
    /// и молчал об этом. Рядом с `name` живут `nameKind` и `dogName`;
    /// граница слова обязательна.
    ///
    /// И регистр: `name` здесь строчное нарочно. Мой же греп 07.10
    /// по `'name'` не нашёл в виджетах ничего, потому что там `dogName`
    /// с большой N, — и это чуть не стало выводом, обратным правде.
    private static let чтение = try! NSRegularExpression(
        pattern: "\\b(dog|собака)\\??\\.name\\b")

    /// Запись — не показ: `dog.name = …` кличку задаёт, а не печатает.
    private static let запись = try! NSRegularExpression(
        pattern: "\\b(dog|собака)\\??\\.name\\s*=[^=]")

    private func обход() -> (подстановки: [String], файлов: Int,
                             закрытоИсключением: [String], вСлот: [String]) {
        let fm = FileManager.default
        var подстановки: [String] = []
        var закрытоИсключением: [String] = []
        var вСлот: [String] = []
        var файлов = 0
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                let путь = url.resolvingSymlinksInPath().path
                if путь.contains("/Generated/") { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                let имя = путь.replacingOccurrences(of: Self.корень.path + "/", with: "")
                // Пометки ищем в ИСХОДНОМ тексте: `безКомментариев`
                // их как раз и срезает.
                let сКомментариями = текст.components(separatedBy: .newlines)
                var найденные: [String] = []
                for (i, строка) in безКомментариев(текст).enumerated() {
                    let область = NSRange(строка.startIndex..., in: строка)
                    guard Self.чтение.firstMatch(in: строка, range: область) != nil,
                          Self.запись.firstMatch(in: строка, range: область) == nil
                    else { continue }
                    if помечена(строка: i, в: сКомментариями) {
                        вСлот.append("\(имя):\(i + 1)")
                        continue
                    }
                    найденные.append("\(имя):\(i + 1)  \(строка.trimmingCharacters(in: .whitespaces))")
                }
                guard !найденные.isEmpty else { continue }
                // Исключение считаем только тогда, когда ему БЫЛО что
                // закрывать: разрешённый файл без единого чтения клички
                // ничего не доказывает про работу списка.
                if Self.слоиДанных[имя] != nil {
                    закрытоИсключением.append(имя)
                } else {
                    подстановки.append(contentsOf: найденные)
                }
            }
        }
        return (подстановки, файлов, закрытоИсключением, вСлот)
    }

    // MARK: - 1. Проверка, что проверять было что

    @Test("Обход просмотрел файлы: подстановки клички")
    func былоЧтоПроверять() {
