import Foundation
import Testing
@testable import Togo

/// Пять причин отказа приглашения — пять разных текстов, и ни одного
/// совета там, где он не помогает.
///
/// **Почему сторож появился только 05.10, хотя правило старое.** Ту же
/// болезнь чинили 23.09 в `Persistence`: один текст на три причины,
/// и совет «включи iCloud Drive в системных настройках» двум из трёх
/// не помогал ничем. Починили **на одной поверхности из двух**:
/// `Persistence` знает пять причин с того дня, а `FamilyShare` всё это
/// время знал три — и бросал `notOwner` из трёх мест, два из которых
/// не про владельца.
///
/// > Правка, меняющая то, что человек читает, применяется ко всем
/// > поверхностям, где та же строка живёт. Комментарий о починке
/// > на одной из них доказательством для остальных не является.
@MainActor
@Suite("Тексты причин отказа приглашения")
struct ShareReasonTextTests {

    /// Все причины поимённо.
    ///
    /// Список руками знает только то, что в него положили, — поэтому
    /// рядом стоит `списокПричинНеОтстал`, который сверяет его длину
    /// с исходником. Без той проверки добавленная шестая причина
    /// прошла бы молча, и сторож остался бы зелёным, перестав
    /// что-либо охранять.
    static let всеПричины: [FamilyShare.ShareError] = [
        .noAccount,
        .noEntitlement,
        .notOwner,
        .linkNotReady,
        .saveFailed(code: 2),
    ]

    @Test("У каждой причины свой текст — одинаковых нет")
    func текстыРазные() throws {
        let тексты = Self.всеПричины.map { $0.errorDescription ?? "" }

        for текст in тексты {
            #expect(текст.isEmpty == false, "Причина без текста молчит, а молчание человек читает как «ничего не произошло».")
        }

        let уникальные = Set(тексты)
        #expect(уникальные.count == тексты.count,
                "Две причины говорят одно и то же: \(тексты.count) причин, \(уникальные.count) текстов. Значит одна из них даёт совет, неверный для другой.")
    }

    /// Написано от ЗАПРЕТА, а не от требования.
    ///
    /// «Текст обязан содержать нужное слово» у нас уже дало 79 ложных
    /// находок: у нужного слова десять форм. А «в тексте не должно быть
    /// запретного совета» проверяется надёжно — запретное узнаётся
    /// по корню.
    @Test("Совет про настройки iCloud не стоит там, где настройки ни при чём")
    func советТолькоТам() throws {
        // Где совет уместен: человеку правда надо пойти и войти.
        let уместен: Set<String> = ["noAccount"]

        for причина in Self.всеПричины {
            let текст = (причина.errorDescription ?? "").lowercased()
            let метка = FamilyShare.причина(причина)
            guard !уместен.contains(метка) else { continue }

            #expect(текст.contains("войди") == false,
                    "«\(метка)» советует войти в iCloud, хотя вход тут ни при чём: человек войдёт, ничего не изменится и решит, что сломано у него.")
            #expect(текст.contains("настройк") == false,
                    "«\(метка)» отправляет в настройки, где проверять нечего.")
        }
    }

    @Test("Отказ сохранения несёт код, а не «что-то пошло не так»")
    func кодОтказаВидно() throws {
        let сКодом = FamilyShare.ShareError.saveFailed(code: 15)
        #expect(FamilyShare.причина(сКодом) == "saveFailed15",
                "Без кода в журнале отказ неотличим от любого другого, и разбирать его будет нечем.")

        let безКода = FamilyShare.ShareError.saveFailed(code: nil)
        #expect(FamilyShare.причина(безКода) == "saveFailed")
    }

    /// Граница самого списка: он не должен отстать от перечисления.
    ///
    /// Считаем `case` в исходнике, а не доверяем памяти. `ShareError`
    /// несёт связанное значение, поэтому `CaseIterable` ей недоступна —
    /// и ровно поэтому список легко отстаёт молча.
    @Test("Список причин не отстал от самого перечисления")
    func списокПричинНеОтстал() throws {
        let исходник = try Self.исходникFamilyShare()
        guard let начало = исходник.range(of: "enum ShareError: LocalizedError {"),
              let конец = исходник.range(of: "var errorDescription: String? {",
                                         range: начало.upperBound ..< исходник.endIndex)
        else {
            Issue.record("Не нашёл тело ShareError. Сторож, переставший что-либо находить, молчит так же, как тот, кому нечего сказать.")
            return
        }

        let тело = исходник[начало.upperBound ..< конец.lowerBound]
        let объявлено = тело
            .split(separator: "\n")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { $0.hasPrefix("case ") }
            .count

        #expect(объявлено > 0, "Ноль найденных case — это про сканер, а не про код.")
        #expect(объявлено == Self.всеПричины.count,
                "В ShareError \(объявлено) причин, в списке теста \(Self.всеПричины.count). Добавленная причина не проверяется ничем, и её текст может совпасть с чужим.")
    }

    private static func исходникFamilyShare() throws -> String {
        // От файла теста вверх до корня репозитория: путь считается
        // от #filePath, а не от рабочего каталога — у прогона он чужой.
        let тест = URL(fileURLWithPath: #filePath)
        let корень = тест.deletingLastPathComponent().deletingLastPathComponent()
        let файл = корень
            .appendingPathComponent("TogoShared")
            .appendingPathComponent("Sync")
            .appendingPathComponent("FamilyShare.swift")
        return try String(contentsOf: файл, encoding: .utf8)
    }
}
