import Testing
import Foundation
import SwiftData
@testable import Togo

/// Группировка и сравнение по полю, у которого есть значение
/// по умолчанию.
///
/// **Класс дефектов, найденный 07.10.2026 перечислением, а не поиском.**
/// За день он выстрелил четыре раза, и каждый раз иначе:
///
/// ```
/// ворота Pro             dogs.isEmpty при фантомах — ложно → пейволл за ПЕРВУЮ собаку
/// слияние архива         Set(кличек) содержит "" → отметки уехали чужой записи
/// карточка дубликатов    grouping по \.name → «одна собака записана дважды» про пустые,
///                        и кнопка, переносящая связи. ЖИВАЯ, не под #if DEBUG
/// отладочное слияние     то же, плюс участники семьи
/// ```
///
/// > **Группировка по полю со значением по умолчанию собирает в одну
/// > группу всё, что это поле не заполнило.**
///
/// Опасно это там, где умолчание попадает **в ключ**, а не в показ:
/// в показе пустота видна человеку, в ключе — не видна никому.
///
/// **Этот сторож не ищет дефект, он требует РЕШЕНИЯ.** Каждое место,
/// где группируются модели по строковому полю, обязано быть
/// зарегистрировано: либо фильтрует пустые, либо названо исключением
/// с причиной. Новое место, появившееся завтра, упрётся в него —
/// а дефект, который ловится только перечислением, иначе вернётся.
@Suite("Группировка по полю с умолчанием")
struct GroupingByDefaultTests {

    /// Места группировки, которые ФИЛЬТРУЮТ пустое значение.
    ///
    /// Проверяется не список, а исходник: в КОДЕ каждого из этих файлов
    /// обязано стоять правило — `Fmt.notBlank` или `nameIfAny`,
    /// то есть любая из двух дорог к одной реализации.
    ///
    /// **Комментарии из проверки вырезаются, и это не придирка.**
    /// Первая редакция смотрела весь текст файла — и осталась бы зелёной,
    /// если фильтр снять, а упоминание оставить в объяснении. Ровно наш
    /// класс: сканирующий сторож, не различающий код и прозу, меряет
    /// прозу. В этом файле такой комментарий как раз появился через час
    /// после написания сторожа.
    private static let фильтруют: Set<String> = [
        "DuplicateDogCard.swift",
        "DuplicateMerge.swift",
    ]

    /// Места группировки, где фильтр не нужен, — **с причиной**.
    private static let безФильтраСПричиной: [String: String] = [
        // Группировка по началу суток: ключ вычисляется из даты,
        // а у даты нет «пустого» значения — `Date()` это момент,
        // а не отсутствие.
        "WalkRhythm.swift": "ключ — начало суток, вычисляется из даты; пустого значения у даты нет",
        // `incidentKind ?? .other` — явное отображение отсутствия
        // в НАЗВАННУЮ категорию. Две разные неизвестные причины
        // попадут в «прочее», и это решение продукта: человеку нужен
        // счёт происшествий, а не их таксономия.
        "AlarmThreshold.swift": "ключ — вид происшествия, отсутствие явно отображено в .other",
        "VetSummary.swift": "ключ — вид происшествия, отсутствие явно отображено в .other",
        // Место и человек у шага дрессировки по умолчанию `""`,
        // и группировка собирает их вместе. Но ключ здесь идёт
        // НА ПОКАЗ списком, а не в перенос данных: человек видит пустую
        // строку и может её поправить. Пустота видна — значит это
        // вопрос текста, а не ключа, и текст заморожен 07.10.2026.
        //
        // **Названо, а не пропущено:** если этот список когда-нибудь
        // начнёт решать что-то за человека, фильтр понадобится и здесь.
        //
        // `TrainingScreens.swift` снят 28.10.2026 вместе с файлом:
        // занятия удалены по решению Виктории. Запись УДАЛЕНА,
        // а не оставлена «на всякий случай»: исключение, пережившее
        // свой файл, молча разрешит группировку в новом файле с тем же
        // именем — и причина, написанная про другой предмет, будет
        // выглядеть продуманной.
        //
        // Ключ `Diary.поДням` — НАЧАЛО СУТОК, и пустым он не бывает
        // по устройству: `Date` не имеет значения «не заполнено»,
        // а удалённые записи отсеивает `Diary.active` до группировки.
        // То есть здесь нет того, от чего сторож защищает: группы
        // «всё, что поле не заполнило», образоваться не из чего.
        //
        // Проверяется это не на слово: у записи без даты поля `date`
        // просто нет — оно не опционально (`var date: Date = Date()`),
        // и строка без даты в дневник не попадает ни одним путём.
        "Diary.swift": "ключ — начало суток, пустым не бывает: Date без значения «не заполнено», а удалённые отсеяны до группировки",
    ]

    private func исходники() throws -> [URL] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var файлы: [URL] = []
        for подкаталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(подкаталог),
                includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                if элемент.pathExtension == "swift" { файлы.append(элемент) }
            }
        }
        return файлы
    }

    @Test("Каждая группировка моделей либо фильтрует пустое, либо названа с причиной")
    func каждаяГруппировкаРешена() throws {
        var сГруппировкой: Set<String> = []
        var безFmt: [String] = []

        for файл in try исходники() {
            guard let полный = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            // Проза из разбора вырезается: иначе снятый фильтр,
            // упомянутый в комментарии, читается как стоящий.
            let текст = полный.components(separatedBy: .newlines)
                .map { $0.components(separatedBy: "//")[0] }
                .joined(separator: "\n")
            guard текст.contains("Dictionary(grouping") else { continue }
            let имя = файл.lastPathComponent
            сГруппировкой.insert(имя)
            let правилоЕсть = текст.contains("Fmt.notBlank") || текст.contains("nameIfAny")
            if Self.фильтруют.contains(имя), !правилоЕсть {
                безFmt.append(имя)
            }
        }

        // Сканер, переставший что-либо находить, молчит так же, как
        // тот, кому нечего сказать.
        #expect(сГруппировкой.count >= 6, """
            файлов с группировкой найдено \(сГруппировкой.count) — разбор
            не состоялся, и сторож зелен впустую.
            """)

        #expect(безFmt.isEmpty, """
            файл числится фильтрующим пустое значение, а правила
            (`Fmt.notBlank` или `nameIfAny`) в его КОДЕ нет: \(безFmt).
            Либо фильтр сняли — и тогда группировка
            снова собирает в одну группу всё, что поле не заполнило, —
            либо его перенесли, и список протух.
            """)

        let нерешённые = сГруппировкой
            .subtracting(Self.фильтруют)
            .subtracting(Self.безФильтраСПричиной.keys)
            .sorted()
        #expect(нерешённые.isEmpty, """
            появилась группировка, про которую никто не решил: \(нерешённые).

            Спроси у ключа два вопроса:
              · есть ли у этого поля значение по умолчанию?
              · если да — что будет, когда его никто не заполнил?

            Умолчание в ключе не видит никто; умолчание в показе видит
            человек. Если ключ решает что-то за человека — фильтруй
            пустое (`Fmt.notBlank`) и впиши файл в `фильтруют`. Если нет —
            впиши в `безФильтраСПричиной` С ПРИЧИНОЙ.
            """)
    }

    @Test("У каждого «фильтр не нужен» записана причина")
    func причиныЕсть() {
        let безПричины = Self.безФильтраСПричиной
            .filter { $0.value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            .map(\.key).sorted()
        #expect(безПричины.isEmpty, "«фильтр не нужен» без причины: \(безПричины)")
    }

    // MARK: Поведение, а не текст

    /// Текстовый сторож выше ловит «фильтра нет вовсе» и слеп
    /// к «фильтр есть и не тот». Поэтому поведение проверяется отдельно
    /// и на самом дорогом месте — живой карточке дубликатов.
    @Test("Безымянные записи не считаются дубликатами друг друга")
    @MainActor
    func безымянныеНеДубликаты() throws {
        let context = ModelContext(Persistence.container())
        for _ in 0..<8 { context.insert(Dog(name: "", weightKg: 0)) }
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        try context.save()

        let собаки = try context.fetch(FetchDescriptor<Dog>())
        let дубликаты = Dictionary(grouping: собаки.compactMap { d in
            Fmt.notBlank(d.name).map { (d, $0) }
        }, by: \.1).mapValues { $0.map(\.0) }.filter { $0.value.count > 1 }

        #expect(дубликаты.isEmpty, """
            восемь безымянных записей сочтены дубликатами друг друга.
            Человеку это показывалось как «одна собака записана дважды»
            с кнопкой, переносящей связи, — ложная тревога
            с разрушительным действием.
            """)
    }

    /// Обратный край: настоящие дубликаты обязаны находиться, иначе
    /// «безымянные не дубликаты» выполняется и когда не находится
    /// ничего.
    @Test("Две собаки с одной настоящей кличкой — по-прежнему дубликаты")
    @MainActor
    func настоящиеДубликатыНаходятся() throws {
        let context = ModelContext(Persistence.container())
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        context.insert(Dog(name: "Стич", weightKg: 4.6))
        try context.save()

        let собаки = try context.fetch(FetchDescriptor<Dog>())
        let дубликаты = Dictionary(grouping: собаки.compactMap { d in
            Fmt.notBlank(d.name).map { (d, $0) }
        }, by: \.1).mapValues { $0.map(\.0) }.filter { $0.value.count > 1 }

        #expect(дубликаты.count == 1, """
            две «Стич» перестали считаться дубликатами — фильтр пустого
            закрыл дорогу всем. Замер 23.09.2026: такое у человека было,
            и записи разошлись пополам, 56 и 45.
            """)
    }
}
