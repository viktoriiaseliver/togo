/// Раскладка «экран → подложка» названа Викторией; имя на месте вызова
/// пишет разработка. Эти две строки обязаны совпасть, и совпадение
/// не проверял никто.
///
/// # Почему сторож появился только 04.11.2026
///
/// `BackgroundStore.swift` предупредил об этом классе **заранее**,
/// в доккомментарии к `ScreenKey`: «Имя экрана живёт ЗДЕСЬ и больше
/// нигде. Соблазн был написать `.sub("care")` и на месте вызова,
/// и в раскладке — это две копии одной строки, и расходятся такие
/// копии молча».
///
/// Разошлись. Замер 04.11.2026 по рабочему дереву:
///
/// ```
/// литералов .sub("…") на местах вызова        34
///   совпали с объявленным статиком            10
///   разошлись РЕГИСТРОМ                        2  doortag · howitworks
///   разошлись СЛОВОМ                           4  docs · handover · rx · visit
///   экраны, которым подложки не назначали     18
/// ```
///
/// Шесть разошедшихся экранов получали не ту подложку, которую им
/// назначила владелица, а умолчание — **и ни один тест не краснел**,
/// потому что умолчание есть законный ответ для неназванного экрана.
/// Снаружи «так и задумано» от «имя разъехалось» неотличимо.
///
/// > **Дефект был невидим вдвойне.** Поверх подложки у подэкранов
/// > лежит непрозрачное полотно `TGScreen` (`TGScaffolds.swift:153`),
/// > то есть фотографии не видно НИ ПРИ КАКОМ имени. Снимут полотно —
/// > и шесть экранов показали бы чужой кадр в первый же день.
///
/// # Чего этот сторож не делает
///
/// Он не требует, чтобы подложка была у каждого экрана: восемнадцати
/// её не назначали, и это решение владелицы, а не пробел. Он требует
/// другого — чтобы **выбор был сделан явно**: имя либо совпадает
/// с объявленным, либо названо здесь как «подложки нет».
@Suite("Имя экрана доходит до раскладки")
struct ИмяЭкранаДоходитДоРаскладкиTests {

    /// Экраны, которым подложку не назначали. Список не «разрешение
    /// на беспорядок», а **место, где выбор записан**: новое имя
    /// красит сторожа, и автор обязан либо завести статик, либо
    /// дописать сюда.
    ///
    /// Замер 04.11.2026: восемнадцать имён, все из `Togo/Features`.
    private static let экраныБезПодложки: Set<String> = [
        "about", "background", "backup", "dogs", "downgrade", "editors",
        "language", "legal", "notifications", "privacy", "profile",
        "protocol", "report", "schedule", "settings", "support",
        "usagelog", "whatsnew",
    ]

    /// Назначения раскладки, у которых сегодня нет читателя, —
    /// **с причиной у каждого, потому что причины РАЗНЫЕ**, а в общем
    /// счёте «семь без читателя» они выглядели бы одинаково.
    ///
    /// ```
    /// sharedDiary  экран ЕСТЬ и зовёт `family`      фон ТОТ ЖЕ (фонСемьи)
    /// foodStock    экран ЕСТЬ и зовёт `feeding`     фон ТОТ ЖЕ (фонКормления)
    /// labChart     экран ЕСТЬ и зовёт `labs`        фон ТОТ ЖЕ (фонЗдоровья)
    /// diaryAccess  экрана с таким именем НЕТ в дереве вовсе
    /// training     ФУНКЦИЯ УДАЛЕНА 28.10.2026 (`82ba1e46`)
    /// trainingMatrix   то же
    /// trainingLibrary  то же
    /// ```
    ///
    /// Первые три безвредны: экран берёт соседнее имя, которому
    /// назначен **тот же файл**, и человек видит ровно задуманное.
    /// Разница только в хэше режима «вперемешку».
    private static let назначенияБезЧитателя: Set<String> = [
        "sharedDiary", "foodStock", "labChart", "diaryAccess",
        "training", "trainingMatrix", "trainingLibrary",
    ]

    /// Подложки, которые лежат в бандле и не показываются никому.
    ///
    /// **`фонЗанятий` — живой случай, найденный этим сторожем
    /// 04.11.2026.** Раздаётся он только трём записям `training*`,
    /// а занятия удалены 28.10 (`82ba1e46`). Файл `фон-занятий.jpg`
    /// весит 312 КБ, едет и в приложении, и в расширении виджетов,
    /// и не показывается нигде.
    ///
    /// Запись здесь, а не удаление файла: кадр прислала Виктория
    /// 04.11 вместе с остальными девятью, то есть занятия она считает
    /// живыми либо собирается вернуть. **Хозяин решения — она:**
    /// вернуть занятия или снять фон вместе с тремя записями.
    private static let фоныБезПоказа: Set<String> = ["фон-занятий.jpg"]

    private var каталогИсходников: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("Togo")
    }

    /// Литералы `.sub("…")` и обращения `ScreenKey.…` по всему
    /// `Togo/`, кроме строк-комментариев.
    private func именаИзИсходников() throws -> (литералы: Set<String>,
                                                статики: Set<String>,
                                                файлов: Int) {
        var литералы: Set<String> = []
        var статики: Set<String> = []
        var файлов = 0

        let обход = FileManager.default.enumerator(
            at: каталогИсходников, includingPropertiesForKeys: nil)
        while let адрес = обход?.nextObject() as? URL {
            guard адрес.pathExtension == "swift" else { continue }
            guard let текст = try? String(contentsOf: адрес, encoding: .utf8)
            else { continue }
            файлов += 1
            for строка in текст.split(separator: "\n", omittingEmptySubsequences: false) {
                let обрезанная = строка.trimmingCharacters(in: .whitespaces)
                // Комментарий вырезаем ДО разбора: сторож, не
                // различающий код и прозу, запрещает писать про дефект
                // в файле, где его не совершают.
                if обрезанная.hasPrefix("//") { continue }
                литералы.formUnion(Self.вытащить(#".sub(""#, из: String(строка)))
                статики.formUnion(Self.вытащить("ScreenKey.", из: String(строка),
                                                доКавычки: false))
            }
        }
        return (литералы, статики, файлов)
    }

    /// Примитивный разбор без NSRegularExpression: предмет простой,
    /// а регулярка здесь была бы третьим местом, где можно ошибиться.
    private static func вытащить(_ начало: String, из строка: String,
                                 доКавычки: Bool = true) -> Set<String> {
        var итог: Set<String> = []
        var остаток = Substring(строка)
        while let место = остаток.range(of: начало) {
            остаток = остаток[место.upperBound...]
            if доКавычки {
                guard let конец = остаток.firstIndex(of: "\"") else { break }
                итог.insert(String(остаток[..<конец]))
            } else {
                let имя = остаток.prefix { $0.isLetter || $0.isNumber }
                if !имя.isEmpty { итог.insert(String(имя)) }
            }
        }
        return итог
    }

    /// Объявленные статики: имя в кавычках → имя свойства.
    private func объявленныеСтатики() throws -> [String: String] {
        let адрес = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Domain/BackgroundStore.swift")
        let текст = try String(contentsOf: адрес, encoding: .utf8)
        var итог: [String: String] = [:]
        for строка in текст.split(separator: "\n") {
            guard строка.contains("ScreenKey.sub(\""),
                  строка.contains("static let") else { continue }
            let послеLet = строка.components(separatedBy: "static let")
            guard послеLet.count > 1,
                  let свойство = послеLet[1].split(separator: " ").first,
                  let вКавычках = Self.вытащить("sub(\"", из: String(строка)).first
            else { continue }
            итог[вКавычках] = String(свойство)
        }
        return итог
    }

    // MARK: - Контроль первым

    @Test("Обход нашёл имена экранов, а не промолчал")
    func обходуБылоЧтоСчитать() throws {
        let (литералы, статики, файлов) = try именаИзИсходников()
        let объявлены = try объявленныеСтатики()

        #expect(файлов >= 150, """
            прочитано \(файлов) файлов Swift в Togo/ — обход сбился \
            или каталог не тот. Всё остальное в этом наборе меряет \
            не продукт, а собственный промах.
            """)
        #expect(литералы.count >= 20, """
            литералов .sub("…") нашлось \(литералы.count) — \
            на 04.11.2026 их было 28.
            """)
        #expect(статики.contains("today"), """
            среди обращений ScreenKey.… нет заведомо живого `today`: \
            разбор не работает.
            """)
        #expect(объявлены.count >= 20, """
            объявленных ScreenKey.sub прочитано \(объявлены.count), \
            на 04.11.2026 их 24.
            """)
    }

    // MARK: - Ось

    @Test("Каждое имя на месте вызова либо объявлено, либо названо экраном без подложки")
    func именаВызововНеРасходятся() throws {
        let (литералы, _, _) = try именаИзИсходников()
        let объявлены = try объявленныеСтатики()

        let безответные = литералы
            .filter { !объявлены.keys.contains($0) }
            .filter { !Self.экраныБезПодложки.contains($0) }
            .sorted()

        #expect(безответные.isEmpty, """
            на местах вызова стоят имена, которых нет ни среди \
            объявленных ScreenKey, ни в списке «экраны без подложки»:
            \(безответные.joined(separator: ", ")).

            Такой экран получает подложку по умолчанию, а не ту, \
            которую ему назначили, — и снаружи это неотличимо \
            от «так и задумано».

            Либо завести статик в BackgroundStore и звать его \
            (`ScreenKey.имя`), либо дописать имя в `экраныБезПодложки` \
            этого набора — то есть выбрать вслух.
            """)

        // Зеркало той же оси: имя, похожее на объявленное регистром,
        // — самый дешёвый способ разойтись, и ровно так случилось
        // с `doortag` и `howitworks`.
        let поРегистру = Dictionary(объявленныеПоНижнему(объявлены),
                                    uniquingKeysWith: { первое, _ in первое })
        let похожие = литералы
            .filter { !объявлены.keys.contains($0) }
            .compactMap { имя -> String? in
                guard let верное = поРегистру[имя.lowercased()] else { return nil }
                return "«\(имя)» вместо «\(верное)»"
            }
            .sorted()

        #expect(похожие.isEmpty, """
            имя на месте вызова отличается от объявленного ТОЛЬКО \
            регистром: \(похожие.joined(separator: ", ")).
            Для `ScreenKey` это два разных экрана.
            """)
    }

    private func объявленныеПоНижнему(_ объявлены: [String: String]) -> [(String, String)] {
        объявлены.keys.map { ($0.lowercased(), $0) }
    }

    @Test("Каждое назначение раскладки либо имеет читателя, либо названо исключением")
    func назначенияДоходятДоЭкранов() throws {
        let (литералы, статики, _) = try именаИзИсходников()
        let объявлены = try объявленныеСтатики()

        // Экран «зовёт» назначение двумя путями: литералом,
        // совпавшим с объявленным именем, или статиком по свойству.
        var зовут: Set<String> = []
        for литерал in литералы {
            if let свойство = объявлены[литерал] { зовут.insert(свойство) }
        }
        зовутИзСтатиков(статики, объявлены: объявлены, в: &зовут)

        let назначены = Set(BackgroundBridge.раскладкаРазделов.map(\.экран))
            .filter { $0.kind == .sub }
        let безЧитателя = назначены
            .compactMap { ключ -> String? in
                // `name` у подэкрана — это «sub:имя»; свойство ищем
                // по хвосту.
                let хвост = String(ключ.name.dropFirst("sub:".count))
                guard let свойство = объявлены[хвост] else { return хвост }
                return зовут.contains(свойство) ? nil : свойство
            }
            .filter { !Self.назначенияБезЧитателя.contains($0) }
            .sorted()

        #expect(безЧитателя.isEmpty, """
            Виктория назначила этим экранам подложку, а зовёт её \
            кто-нибудь: \(безЧитателя.joined(separator: ", ")).

            Решение записано, исполнителя у него нет — и молчит это \
            так же, как «подложки не назначали».

            Либо экран начинает звать своё имя, либо имя дописывается \
            в `назначенияБезЧитателя` ВМЕСТЕ С ПРИЧИНОЙ: причины у семи \
            нынешних исключений разные, и в общем счёте они выглядели бы \
            одинаково.
            """)
    }

    private func зовутИзСтатиков(_ статики: Set<String>,
                                 объявлены: [String: String],
                                 в зовут: inout Set<String>) {
        let свойства = Set(объявлены.values)
        зовут.formUnion(статики.filter { свойства.contains($0) })
    }

    @Test("Подложка, лежащая в бандле, показывается хотя бы одному экрану")
    func мёртвыхПодложекНет() throws {
        let объявлены = try объявленныеСтатики()
        let (литералы, статики, _) = try именаИзИсходников()

        var зовут: Set<String> = []
        for литерал in литералы {
            if let свойство = объявлены[литерал] { зовут.insert(свойство) }
        }
        зовутИзСтатиков(статики, объявлены: объявлены, в: &зовут)

        // Какие файлы достижимы хоть одним живым экраном.
        var живые: Set<String> = []
        for (экран, подложка) in BackgroundBridge.раскладкаРазделов {
            guard экран.kind == .sub else {
                живые.insert(подложка)   // today/dog/walk/widget зовутся всегда
                continue
            }
            let хвост = String(экран.name.dropFirst("sub:".count))
            guard let свойство = объявлены[хвост] else { continue }
            if зовут.contains(свойство) { живые.insert(подложка) }
        }

        let мёртвые = Set(BackgroundBridge.фоныРазделов)
            .subtracting(живые)
            .subtracting(Self.фоныБезПоказа)
            .sorted()

        #expect(мёртвые.isEmpty, """
            эти файлы лежат в ресурсах, едут в бандле — и не \
            показываются ни на одном живом экране:
            \(мёртвые.joined(separator: ", ")).

            Подложка без показа дороже, чем кажется: вес едет дважды \
            (приложение и расширение виджетов), а отсутствие картинки \
            на экране выглядит решением дизайна.

            Либо экран начинает звать своё имя, либо файл снимается, \
            либо имя дописывается в `фоныБезПоказа` с хозяином.
            """)

        // И зеркало: исключение не должно пережить свой предмет.
        let воскресшие = Self.фоныБезПоказа.intersection(живые).sorted()
        #expect(воскресшие.isEmpty, """
            файл числится в `фоныБезПоказа`, а показывается: \
            \(воскресшие.joined(separator: ", ")).
            Исключение пережило свою причину — убрать его из списка.
            """)
    }
