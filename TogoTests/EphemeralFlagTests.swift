import Testing
import Foundation
import SwiftData
@testable import Togo

/// Обратная половина флага «записи не сохранятся».
///
/// **Почему этот файл появился.** Замер 05.10.2026: `Persistence.isEphemeral`
/// утверждается в наборе дважды, и **оба раза равенством false** —
/// `Schema25Tests:95` и `SchemaMigrationTests:474`. Утверждения
/// `isEphemeral == true` не было нигде ни одного.
///
/// Оба прежних — запреты, и оба выполняются у функции, которая **никогда
/// не ставит флаг в true**: `openContainer` сбрасывает его на входе, и
/// ветка «файл есть, но не открылся» возвращает nil с тем же false. То есть
/// вырежи ветку памяти целиком — набор останется зелёным, а плашка «записи
/// не сохраняются» (`TodayScreen:181`) не появится никогда. Человек будет
/// записывать дозы в хранилище, которое их не хранит, и ничто ему
/// об этом не скажет.
///
/// Это наш записанный класс: отрицательное утверждение выполняется и при
/// отсутствии предмета. Рядом с «не все» у Kvit, которое истинно и при нуле.
///
/// Третий сторож того же флага — `CloudFallbackTests:79` — проверяет,
/// что имя `Persistence.isEphemeral` **упомянуто в исходнике экрана**.
/// Он видит упоминание и не видит, что от упоминания что-то происходит.
@Suite("Флаг «записи не сохранятся» умеет становиться истинным")
struct EphemeralFlagTests {

    /// Путь, по которому хранилище завести НЕЛЬЗЯ: каталог только на чтение.
    ///
    /// **Первая редакция стенда брала несуществующий каталог
    /// (`/dev/null/...`) и до ветки памяти не доходила.** Прогон 05.10:
    /// `контейнер != nil` прошёл, `isEphemeral == true` упал — то есть
    /// SwiftData такой путь не считает отказом и открывает хранилище
    /// где-то ещё. Красное тогда говорило о стенде, а не о коде, и принять
    /// его за находку значило бы доложить дефект, которого нет.
    ///
    /// Нужны ОБА условия разом: создание не удаётся И файла дневника нет.
    /// Каталог без права записи даёт ровно это.
    private func каталогБезЗаписи() throws -> URL {
        let папка = FileManager.default.temporaryDirectory
            .appendingPathComponent("togo-только-чтение-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: папка, withIntermediateDirectories: true)
        try FileManager.default.setAttributes([.posixPermissions: 0o500], ofItemAtPath: папка.path)
        return папка
    }

    private func вернутьПрава(_ папка: URL) {
        try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: папка.path)
        try? FileManager.default.removeItem(at: папка)
    }

    @Test("Когда хранилище не заводится и терять нечего — флаг истинен, а дневник открыт")
    func флагСтановитсяИстинным() throws {
        let папка = try каталогБезЗаписи()
        defer { вернутьПрава(папка) }
        let url = папка.appendingPathComponent("Togo.store")

        // Было что проверять, обе половины:
        // 1. файла и правда нет — иначе `openContainer` ушёл бы в ветку
        //    «файл есть, но не открылся» и вернул nil с флагом false;
        #expect(FileManager.default.fileExists(atPath: url.path(percentEncoded: false)) == false,
                "файл есть — значит проверяется не та ветка")
        // 2. флаг до замера ложен, иначе «истинен после» ничего не значит.
        //    `openContainer` сбрасывает его на входе сам, но полагаться
        //    на это здесь нельзя: именно эту строку и мог бы кто-нибудь
        //    убрать, а тест обязан увидеть ПЕРЕХОД, а не значение.
        _ = Persistence.openContainer(storeURL: nil, allowCloud: false)
        let доЗамера = Persistence.isEphemeral

        let контейнер = Persistence.openContainer(storeURL: url, allowCloud: false)

        #expect(контейнер != nil, """
            дневник не открылся вовсе. На первом запуске и на чистой установке
            терять нечего, и человек обязан увидеть приложение — пусть
            с плашкой «записи не сохранятся», а не пустой экран отказа.
            """)
        #expect(Persistence.isEphemeral == true, """
            хранилище в памяти, а флаг ложен (до замера он был \(доЗамера)).
            Значит плашка «записи не сохраняются» на главном не появится,
            и человек будет отмечать дозы в хранилище, которое их не хранит.

            Два прежних сторожа этого не поймают: оба утверждают
            `isEphemeral == false`, и оба зелены у функции, которая
            не ставит флаг в true никогда.
            """)
    }

    @Test("Повторное успешное открытие гасит флаг обратно")
    func флагГаснетПриУспехе() throws {
        // Та же ловушка с другой стороны, и она уже случалась: успешная
        // ветка iCloud флага не трогала, и при повторном открытии там
        // оставалось `true` от прошлого раза — плашка «записи не
        // сохраняются» висела поверх ИСПРАВНОГО хранилища. Сброс на входе
        // это чинит; тест держит починку.
        let закрытая = try каталогБезЗаписи()
        defer { вернутьПрава(закрытая) }
        _ = Persistence.openContainer(storeURL: закрытая.appendingPathComponent("Togo.store"),
                                      allowCloud: false)
        #expect(Persistence.isEphemeral == true, "стенд не привёл флаг в true — проверять нечего")

        let папка = FileManager.default.temporaryDirectory
            .appendingPathComponent("togo-эфемерность-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: папка, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: папка) }
        let рабочий = папка.appendingPathComponent("Togo.store")

        let контейнер = Persistence.openContainer(storeURL: рабочий, allowCloud: false)
        #expect(контейнер != nil, "исправный путь обязан открыться")
        #expect(Persistence.isEphemeral == false, """
            хранилище открылось на диске, а флаг остался истинным —
            плашка «записи не сохраняются» встанет поверх исправного
            дневника и научит человека её не читать.
            """)
    }

    @Test("Границы: чего этот набор НЕ проверяет")
    func границыНабора() {
        // 1. Ветка iCloud здесь не трогается вовсе: `allowCloud: false`
        //    во всех замерах. Снимет — тест с выданным правом на iCloud,
        //    а он требует окружения, которого у прогона нет.
        // 2. Набор проверяет ФЛАГ, а не плашку. Что `TodayScreen:181`
        //    и правда её рисует, здесь не доказано — доказано только,
        //    что величина, на которую она смотрит, умеет меняться.
        //    Снимет — кадр главного экрана при эфемерном хранилище;
        //    сценария под это в `SeedData` нет.
        // 3. Отказ создания получен несуществующим каталогом
        //    (`/dev/null/...`). Это не единственная причина отказа —
        //    права, место на диске, повреждённый файл дают свои, и они
        //    здесь не воспроизводятся.
        #expect(Bool(true))
    }
}
