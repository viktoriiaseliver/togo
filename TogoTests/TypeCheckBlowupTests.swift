import Testing
import Foundation

/// Сторож против выражений, на которых срывается типизатор Swift.
///
/// **Почему он нужен, хотя компилятор сам об этом говорит.** Потому
/// что говорит он не всегда и не у всех. Замер 07.10.2026: выражение
/// из одиннадцати слагаемых `(x?.count ?? 0)` в одной цепочке `+`
/// **собиралось локально** и не собиралось на раннере CI:
///
/// ```
/// The compiler is unable to type-check this expression
/// in reasonable time; try breaking up the expression
/// → Testing cancelled because the build failed
/// ```
///
/// Шесть прогонов CI подряд упали на этом, и ни один локальный прогон
/// не покраснел. Разница между машинами — загрузка, а не код.
///
/// > **Это единственный известный нам дефект, у которого присутствие
/// > в коде не означает присутствия в сборке.** Остальные либо там,
/// > либо нет.
///
/// Отсюда и форма сторожа: он ищет **форму выражения в исходнике**,
/// а не ждёт отказа компилятора. Отказ приходит позже, на другой
/// машине и в чужом прогоне.
///
/// **История, объясняющая порог.** Первую такую цепочку починили
/// в `DuplicateDogCard` (`420ce44`), вторую **назвали и не починили**
/// — и следующий прогон CI упал ровно на ней (`DuplicateMerge`).
/// То есть «названо, не сделано» в применении к сборке означает
/// «упадёт в следующий раз», а не «записано на потом».
@Suite("Сборка · выражения, на которых срывается типизатор")
struct TypeCheckBlowupTests {

    /// Сколько слагаемых с `??` в одной цепочке `+` считается опасным.
    ///
    /// Три, а не одиннадцать: у каждого слагаемого два возможных типа,
    /// перебор растёт **степенью**, и одиннадцать — это не «вдвое хуже
    /// трёх». Порог ниже наблюдённого нарочно: цена ложного
    /// срабатывания здесь — одна правка в цикл, цена пропуска — отказ
    /// сборки на чужой машине.
    static let предел = 3

    private static let корни = ["Togo", "TogoShared", "TogoWidgets"]

    /// Исходники проекта. Ищутся от файла теста вверх, а не от рабочего
    /// каталога: у прогона из Xcode и из `xcodebuild` они разные.
    static func исходники() throws -> [URL] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень проекта
        var файлы: [URL] = []
        for имя in корни {
            let папка = корень.appendingPathComponent(имя)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                            includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                файлы.append(url)
            }
        }
        return файлы
    }

    /// Цепочки `(… ?? …) + (… ?? …) + …` длиной от `предел`.
    ///
    /// Окно в восемь строк, потому что выражение переносится: в обоих
    /// найденных случаях оно занимало шесть строк.
    static func цепочки(в текст: String) -> [(строка: Int, слагаемых: Int)] {
        let строки = текст.components(separatedBy: "\n")
        let шаблон = try? NSRegularExpression(
            pattern: #"(?:\([^()\n]*\?\?[^()\n]*\)\s*\+\s*){\#(предел - 1),}\([^()\n]*\?\?[^()\n]*\)"#,
            options: [.dotMatchesLineSeparators])
        guard let шаблон else { return [] }
        var найдено: [(Int, Int)] = []
        var i = 0
        while i < строки.count {
            let окно = строки[i..<min(i + 8, строки.count)].joined(separator: "\n")
            let диапазон = NSRange(окно.startIndex..., in: окно)
            if let м = шаблон.firstMatch(in: окно, range: диапазон),
               let r = Range(м.range, in: окно) {
                найдено.append((i + 1, окно[r].components(separatedBy: "??").count - 1))
                i += 8
            } else {
                i += 1
            }
        }
        return найдено
    }

    /// Сколько файлов обход обязан найти.
    ///
    /// **Число измерено, и первая редакция этого теста его выдумала.**
    /// Я написал порог 200 со словами «на 07.10 файлов было около
    /// трёхсот» — и тест упал на собственном прогоне: их 194.
    ///
    /// ```
    /// 07.10.2026   Togo 104 · TogoShared 87 · TogoWidgets 3 = 194
    /// 07.09.2026   143   (коммит a6ab724, месяцем раньше)
    /// ```
    ///
    /// Порог 150, а не 194: он ловит **поломку обхода**, а не удаление
    /// файла. Набор растёт (143 → 194 за месяц), и порог у верхней
    /// границы краснел бы на каждой уборке — а сторож, который краснеет
    /// без дефекта, учит не верить красному, и это дороже пропущенного.
    ///
    /// Если файлов станет меньше 150 — это либо сломанный обход, либо
    /// половина проекта удалена, и оба случая стоят красноты.
    static let минимумФайлов = 150

    @Test("Обход видит исходники — иначе проверка ниже зелена на пустом множестве")
    func scanSeesSources() throws {
        let файлы = try Self.исходники()
        // Порог, а не «больше нуля»: переставший что-либо находить
        // молчит так же, как тот, кому нечего сказать.
        #expect(файлы.count >= Self.минимумФайлов,
                """
                Исходников найдено \(файлы.count), ожидалось не меньше \
                \(Self.минимумФайлов) — обход не состоялся, и проверка \
                цепочек ниже ничего не проверяет.
                """)
    }

    @Test("Разбор находит цепочку, когда она есть — проверка инструмента, не мира")
    func scanFindsAKnownChain() {
        // Образец ровно той формы, на которой падал CI. Если разбор
        // ослепнет, проверка ниже станет зелёной на пустом результате,
        // и мы узнаем об этом от раннера, а не от себя.
        let образец = """
            private func связанных(_ собака: Dog) -> Int {
                (собака.aStorage?.count ?? 0) + (собака.bStorage?.count ?? 0)
                    + (собака.cStorage?.count ?? 0) + (собака.dStorage?.count ?? 0)
            }
            """
        let найдено = Self.цепочки(в: образец)
        #expect(найдено.count == 1)
        #expect(найдено.first?.слагаемых == 4)
    }

    @Test("В проекте нет цепочек из трёх и более слагаемых с «??»")
    func noLongOptionalChains() throws {
        var нарушения: [String] = []
        for файл in try Self.исходники() {
            guard let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            let путь = файл.path.components(separatedBy: "/Togo/").last ?? файл.lastPathComponent
            for случай in Self.цепочки(в: текст) {
                нарушения.append("\(путь):\(случай.строка) — \(случай.слагаемых) слагаемых")
            }
        }
        #expect(нарушения.isEmpty,
                """
                Цепочка «(x ?? 0) + (y ?? 0) + …» из \(Self.предел) и более слагаемых:
                \(нарушения.joined(separator: "\n"))

                Типизатор Swift перебирает типы степенью от числа слагаемых.
                Такое выражение может собираться локально и не собираться
                на другой машине — 07.10.2026 это стоило шести прогонов CI.
                Лечится циклом: перебор исчезает целиком.
                """)
    }

    @Test("Границы: что этот сторож НЕ проверяет — цепочки с «??»")
    func limitsOfThisSuite() {
        // Печатается здесь, а не живёт в чьей-то памяти:
        //
        // • он ловит ОДНУ форму срыва — длинную цепочку `+` над `??`.
        //   Срыв бывает и на других: вложенные тернарники, длинные
        //   литералы массивов словарей, `reduce` с выводимым типом;
        // • он смотрит ИСХОДНИК, а не время типизации. Выражение из двух
        //   слагаемых, но с тяжёлыми обобщениями, он пропустит;
        // • настоящий ответ на «уложится ли компилятор» даёт только
        //   `-Xfrontend -warn-long-expression-type-checking`, и его
        //   у проекта нет. Этот сторож — замена дешевле, не точнее.
        #expect(Self.предел == 3)
    }
}
