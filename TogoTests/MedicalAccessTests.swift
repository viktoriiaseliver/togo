import Testing
import Foundation
@testable import Togo

/// Кто видит медицинское.
///
/// До 23.09 вкладка «Здоровье» открывалась одним условием —
/// `dog?.isOnTreatment == true`, — и права там не было вовсе. Ситтер
/// с ролью «помощник» увидел бы препараты, часы, окно натощак, дозы
/// и отчёт врачу. Сегодня это скрыто не правом, а тем, что собака
/// не уезжает в общий дневник; спринт «все видят всё» эту случайность
/// снимет.
///
/// Решение по всем пяти ролям и обоснование — `docs/матрица-ролей.md`.
/// Здесь оно закреплено: правило живёт в тесте, а не в памяти.
@Suite("Доступ к медицинскому")
@MainActor
struct MedicalAccessTests {

    private func состояние(_ роль: FamilyRole) -> AppState {
        let состояние = AppState.наСвоёмТелефоне()
        состояние.role = роль
        return состояние
    }

    @Test("Помощник медицинского не видит")
    func помощникНеВидит() {
        #expect(!состояние(.helper).can(.seeMedical))
    }

    @Test("Владелец, со-владелец, ухаживающий и наблюдатель — видят")
    func остальныеВидят() {
        for роль in [FamilyRole.owner, .coOwner, .caregiver, .observer] {
            #expect(состояние(роль).can(.seeMedical), "\(роль.title) должен видеть медицинское")
        }
    }

    @Test("Схему лечения по умолчанию меняет только владелец")
    func схемуМеняетВладелец() {
        #expect(состояние(.owner).can(.editTreatment))
        for роль in [FamilyRole.coOwner, .caregiver, .helper, .observer] {
            #expect(!состояние(роль).can(.editTreatment),
                    "\(роль.title) не должен менять схему лечения по умолчанию")
        }
    }

    @Test("Наблюдатель читает медицинское и не пишет ничего")
    func наблюдательТолькоЧитает() {
        let врач = состояние(.observer)
        #expect(врач.can(.seeMedical))
        #expect(!врач.can(.logBasics))
        #expect(!врач.can(.giveDose))
    }

    private static func rootView() throws -> [String] {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("Togo/App/RootView.swift")
        return try String(contentsOf: url, encoding: .utf8)
            .components(separatedBy: .newlines)
    }

    /// Строка условия показа «Здоровья» — найденная по самому экрану,
    /// а не по тексту условия.
    ///
    /// Прежняя редакция искала строку со `isOnTreatment == true`, то есть
    /// **по той части, которую решение 08.10 как раз убрало**: после
    /// правки она не находила условие вовсе и падала на `#require`.
    /// Якорем должно быть то, что не меняется, — показ `HealthScreen()`.
    private static func условиеЗдоровья(_ строки: [String]) throws -> String {
        let индекс = try #require(строки.firstIndex { $0.contains("HealthScreen()") },
                                  "в RootView нет показа HealthScreen() — разбор не состоялся")
        let выше = строки[..<индекс].reversed()
        return try #require(выше.first { $0.contains("if ") },
                            "над HealthScreen() нет условия — проверь, чем заменён показ вкладки")
    }

    /// Сторож на само место, а не только на набор прав: условие показа
    /// вкладки должно спрашивать право. Сломать его правкой `RootView`
    /// легко, и по набору прав этого не видно.
    @Test("Вкладка «Здоровье» закрыта правом И ТОЛЬКО правом")
    func вкладкаСпрашиваетТолькоПраво() throws {
        let условие = try Self.условиеЗдоровья(try Self.rootView())
        let голое = условие.trimmingCharacters(in: .whitespaces)

        #expect(условие.contains("can(.seeMedical)"), """
            вкладка «Здоровье» открывается без права: \(голое).
            Так помощник увидит препараты, дозы и отчёт врачу. Разбор —
            docs/матрица-ролей.md.
            """)

        // Решение Виктории 08.10.2026: условие лечения снято, вкладка
        // видна тому, кому можно, ВСЕГДА. Пока оно стояло, «Здоровье»
        // прятало историю лечения ровно тогда, когда курс кончился, —
        // то есть в тот момент, когда отчёт врачу и нужен.
        #expect(!условие.contains("isOnTreatment"), """
            условие показа «Здоровья» снова спрашивает лечение: \(голое).
            Снято решением Виктории 08.10.2026: держит вкладку ПРАВО,
            и только оно. Вернув лечение, мы снова закроем отчёт врачу
            в тот день, когда курс закончился.
            """)
    }

    /// Вторая половина того же решения.
    ///
    /// Возврат на «Сегодня» был следствием условия лечения: вкладка
    /// исчезала, и человека надо было куда-то увести. Без условия
    /// вкладка не исчезает — и увод становится скачком без причины,
    /// прямо из-под руки у того, кто читает историю курса.
    @Test("Конец курса не уводит человека с «Здоровья»")
    func конецКурсаНеУводит() throws {
        let строки = try Self.rootView()
        let уводы = строки.enumerated().filter {
            $0.element.contains("selection = .today")
        }
        for (номер, строка) in уводы {
            let окно = строки[max(0, номер - 4)...номер].joined(separator: " ")
            #expect(!окно.contains("isOnTreatment"), """
                конец лечения уводит с вкладки: RootView.swift:\(номер + 1) \
                — \(строка.trimmingCharacters(in: .whitespaces)).
                Вкладка больше не исчезает по концу курса, значит уводить
                человека неоткуда и незачем.
                """)
        }
    }

    /// И проверка, что этим двум было что проверять.
    @Test("RootView разобран, и обе роли различимы")
    func былоЧтоСторожить() throws {
        let строки = try Self.rootView()
        #expect(строки.count > 50, "RootView.swift прочитан на \(строки.count) строк — разбор не состоялся")

        // Обе роли, а не одна: право `seeMedical` теперь ЕДИНСТВЕННОЕ,
        // что держит вкладку, и сторож на него несёт больше веса,
        // чем раньше. Одна роль доказала бы половину.
        #expect(состояние(.owner).can(.seeMedical), "владелец обязан видеть медицинское")
        #expect(!состояние(.helper).can(.seeMedical), "помощник обязан НЕ видеть медицинское")
    }
}
