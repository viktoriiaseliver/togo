    /// добавить.
    @Test("Каждая вещь Pro достижима запросом")
    func каждаяВещьИмеетЗапрос() {
        let запросы: [ProRequest] = [
            .secondDog(dogsShown: 0),
            .familyBeyondTwo(familyMembers: 0),
        ]
        let покрыты = Set(запросы.map(\.feature.rawValue))
        let непокрытые = ProFeature.allCases
            .map(\.rawValue).filter { !покрыты.contains($0) }.sorted()

        #expect(непокрытые.isEmpty, """
            вещь Pro есть, а запроса к воротам у неё нет: \(непокрытые).
            Значит она либо не охраняется вовсе, либо охраняется
            `store.isPro` на месте — а это ровно то устройство,
            от которого уходили.
            """)
    }

    /// Подпись пейволла выводится отсюда, а не лежит копией.
    @Test("Подпись есть у каждой вещи и пейволл берёт именно её")
    func подписьНеРазошлась() {
        for вещь in ProFeature.allCases {
            let п = вещь.подпись
            #expect(!п.значок.isEmpty && !п.название.isEmpty && !п.пояснение.isEmpty,
                    "у \(вещь.rawValue) пустая часть подписи")
        }

        let изСтора = SubscriptionStore.proFeatures
        #expect(изСтора.count == ProFeature.allCases.count, """
            в пейволле \(изСтора.count) строк, вещей \
            \(ProFeature.allCases.count). Список обязан выводиться
            из ProFeature, а не лежать рядом копией: копия расходится
            молча, и оба списка зелёные, каждый про своё.
            """)
        // Через замыкания, а не key path: путь к элементу кортежа
        // (`\.1`, `\.подпись.название`) в Swift не существует.
        #expect(изСтора.map { $0.1 } == ProFeature.allCases.map { $0.подпись.название },
                "порядок или слова разошлись с ProFeature")
    }

    /// Список потерь при отмене — вторая половина того же правила.
    ///
    /// **Заведён 28.10.2026 по живой находке, а не для симметрии.**
    /// `lostOnDowngrade` лежал перечислением и первой строкой обещал
    /// потерю «Матрицы переноса навыка» — вещи, снятой из Pro
