    // MARK: Сторож на прямые обращения

    /// Прямых `isPro` во вью разрешено ровно столько, сколько записано,
    /// и у каждого файла причина.
    ///
    /// **Запрет, а не требование.** Спросить «нет ли здесь прямого
    /// обращения» можно надёжно; спросить «ворота ли это» — нельзя:
    /// сканер не знает, решает строка доступ или показывает состояние.
    /// Поэтому список закрытый, с числом на файл: появилось обращение
    /// там, где не записано, — красное; стало больше там, где
    /// записано, — тоже красное.
    ///
    /// Число на файл, а не просто имя файла, — потому что файловое
    /// исключение спрятало бы НОВЫЕ ворота в уже разрешённом файле.
    /// В `SettingsScreen` живут и раздел подписки, и отладочный
    /// тумблер, и там же лежали ворота второй собаки.
    private static let разрешено: [String: (сколько: Int, причина: String)] = [
        "PaywallScreen.swift": (3, """
            экран подписки показывает её состояние, а не решает доступ: \
            баннер «активна», погашенная кнопка покупки и закрытие \
            после успеха
            """),
        "SettingsScreen.swift": (2, """
            раздел подписки («активна» против кнопки пейволла) \
            и отладочный тумблер под `#if DEBUG`
            """),
    ]

    @Test("Прямых обращений к isPro во вью не больше записанного")
    func прямыхОбращенийНеБольше() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features")

        var прямые: [String: Int] = [:]
        var ворот = 0
        var файловОсмотрено = 0

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            файловОсмотрено += 1

            // **Проза отбрасывается до разбора.** Сканер, не различающий
            // код и комментарий, меряет комментарий: у Timer такой
            // сторож покраснел на строке «// НЕ `MapsApp.allCases`»,
            // то есть наказал за объяснение, почему так делать нельзя.
            // Здесь это не умозрительно — я сам написал рядом с воротами
            // «а не `store.isPro` на месте».
            let код = текст.components(separatedBy: .newlines)
                .map { строка -> String in
                    guard let i = строка.range(of: "//") else { return строка }
                    return String(строка[..<i.lowerBound])
                }
                .joined(separator: "\n")

            ворот += код.components(separatedBy: "ProGate.isOpen").count - 1

            // Вызовы `ProGate` вырезаются целиком: `isPro:` — их законный
            // аргумент, и считать его прямым обращением значило бы
            // краснеть ровно на починке.
            let безВорот = Self.безВызововВорот(код)
            let счёт = безВорот.components(separatedBy: "isPro").count - 1
            if счёт > 0 { прямые[файл.lastPathComponent] = счёт }
        }

        // Счётчик осмотренного — первым. Набор, которому нечего
        // проверять, молчит так же, как набор, у которого всё хорошо.
        // Порог снят замером: `find Togo/Features -name '*.swift' | wc -l`
        // → 64 на 07.10.2026. Числом, а не «больше нуля»: ноль файлов
        // дал бы ноль обращений и полную тишину.
        #expect(файловОсмотрено >= 60, """
            осмотрено файлов: \(файловОсмотрено) — разбор не состоялся,
            и тишина ниже ничего не значит.
            """)
        // Опущено 3 → 2 вместе со снятием матрицы из Pro, 24.10.2026.
        // Ворота матрицы стояли в `TrainingScreens.swift` и сняты
        // вместе с обещанием; вещей Pro осталось две.
        //
        // > **Число здесь обязано совпадать с числом случаев
        // > `ProFeature`, и совпадение это не проверяется ничем** —
        // > кроме соседнего теста `каждаяВещьИмеетЗапрос`, который
        // > краснеет, если вещь заведена, а запроса ей нет. Обратное
        // > — вещь снята, а число осталось — ловится только этой
        // > строкой, и ловится она красным на верном коде.
        #expect(ворот >= 2, """
            вызовов ProGate.isOpen найдено \(ворот), а вещей Pro две.
            Сканер, переставший что-либо находить, молчит так же, как
            тот, кому нечего сказать.
            """)

        let доля = """
            ворот через ProGate: \(ворот) · прямых isPro: \
            \(прямые.values.reduce(0, +)) в \(прямые.count) файлах \
            из \(файловОсмотрено) осмотренных
            """

        var беззаконные: [String] = []
        var выросли: [String] = []
        for (файл, счёт) in прямые.sorted(by: { $0.key < $1.key }) {
            guard let запись = Self.разрешено[файл] else {
                беззаконные.append("\(файл) — \(счёт)")
                continue
            }
            if счёт != запись.сколько {
                выросли.append("\(файл): записано \(запись.сколько), найдено \(счёт)")
            }
        }

        #expect(беззаконные.isEmpty, """
            \(доля)

            прямое обращение к isPro там, где оно не разрешено: \
            \(беззаконные).
            Если это ворота — позови ProGate: тогда «Pro открывает ровно
            три вещи» можно будет проверить. Если это показ состояния
            подписки — впиши файл в `разрешено` С ПРИЧИНОЙ: исключение
            без причины через месяц неотличимо от дыры.
            """)
        #expect(выросли.isEmpty, """
            \(доля)

            в разрешённом файле обращений стало больше: \(выросли).
            Число на файл стоит именно для этого: новые ворота
            в `SettingsScreen` иначе спрятались бы за старым
            исключением.
            """)
        #expect(Self.разрешено.allSatisfy { !$0.value.причина.isEmpty },
                "исключение без причины")

        // **Границы собственного умения — последней строкой.** Пока
        // их называет человек, они теряются при первой передаче.
        print("""
            \(доля)
            Чего этот сторож НЕ видит:
              · ворота ли строка или показ состояния — решает человек,
                сканер различает только «через ProGate» и «напрямую»;
              · обращение через обёртку с другим именем: сегодня
                обёрток нет ни одной (замер 07.10 — все `can*` идут
                через `appState.can`), но появится — он промолчит;
              · правильность самих порогов: это выше, в таблице.
            """)
    }

    // MARK: Сторож на двери, а не на правило

    /// У каждой двери, заводящей собаку, стоят ворота `secondDog`.
    ///
    /// **Заведён 29.10.2026 по живой дыре.** Соседний сторож выше
    /// спрашивает «нет ли прямого `isPro`» и отвечает на это верно —
    /// но у вопроса «а все ли двери закрыты» он слеп по устройству:
    /// дверь БЕЗ всякой проверки не содержит ни `isPro`, ни `ProGate`,
    /// то есть в его разборе выглядит ровно как файл, к подписке
    /// не относящийся. Замер того дня:
    ///
    /// ```
    /// ProGate.isOpen(.secondDog   1   SettingsScreen.swift:373
    /// DogEditorScreen()           2   SettingsScreen.swift:374
    ///                                 DogSwitcher.swift:162  ← без ворот
    /// ```
    ///
    /// Вторая дверь — экран «Собаки», и ведут к нему три входа:
    /// пилюля «+ Вторая собака» в переключателе, строка «Собаки»
    /// на вкладке собаки и список внутри. То есть мимо пейволла
    /// проходил **более короткий** путь, чем тот, который им закрыт.
    ///
    /// > **Ворота на одной двери из двух не слабее целых — их просто
    /// > нет.** И увидеть это нельзя ни компилятором, ни набором:
    /// > отсутствие проверки не оставляет следа, который можно искать.
    ///
    /// Ось выбрана от **создания**, а не от показа пейволла: сторож
    /// на «есть ли где-то `showPaywall`» гасился бы любым экраном,
    /// который пейволл просто показывает. Здесь на каждый `DogEditorScreen()`
    /// без собаки требуется вызов ворот в том же файле.
    ///
    /// **Чего этот сторож НЕ видит, названо здесь, а не у человека
    /// в голове:**
    ///
    /// * соседство в файле — это прокси для «дверь за воротами».
    ///   Два входа и одни ворота он ловит (считает оба числа),
    ///   а ворота, стоящие в соседней ветке `if`, — нет;
    /// * `DogEditorScreen(dog:)` он пропускает намеренно: это правка
    ///   существующей собаки, и ворот ей не нужно;
    /// * создание `Dog(...)` мимо экрана он не видит вовсе. Перепись
    ///   на коммите `0e0f8f3f`: **семь мест в шести файлах**, и ни одно
    ///   не дверь человека — онбординг (`OnboardingFlow:406`, первая
    ///   собака; повтор не пишет, `пишемВБазу`), приём чужого дневника
    ///   (`SharedDiaryPayloads:725` — чужая собака, её снимает `гость:`
    ///   в фабрике), восстановление из архива (`Backup:594` — свои же
    ///   записи) и четыре отладочных (`SeedData:368` и `:453`,
    ///   `CloudKitSchemaWarmup:144`, `MedicalRecordGallery:86`).
    ///   Перепись за минуту, с адресом коммита рядом с числом:
    ///   `git grep -n 'Dog(name:' <коммит> -- 'Togo/*.swift' 'TogoShared/*.swift'`;
    /// * переименуй `DogEditorScreen` — и сторож ослепнет. Поэтому
    ///   контроль ниже требует **не меньше двух** найденных дверей:
    ///   ослепший сканер обязан краснеть, а не молчать.
    ///
    /// Подделка (29.10.2026): снять `if ProGate.isOpen(.secondDog…)`
    /// из `DogsScreen` — краснеет этот тест строкой
    /// «DogSwitcher.swift: дверей 1, ворот 0», соседи по набору
    /// зелёные.
    @Test("Каждая дверь «завести собаку» стоит за воротами secondDog")
    func каждаяДверьСобакиЗаВоротами() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features")

        var двери: [String: Int] = [:]
        var ворота: [String: Int] = [:]
        var файловОсмотрено = 0

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            файловОсмотрено += 1

            // Проза вырезается до разбора — ровно по той же причине,
            // что у соседа: разбор этой дыры лежит доккомментарием
            // в `DogSwitcher.swift` и цитирует обе искомые строки.
            // Сканер, читающий прозу, покраснел бы на объяснении.
            let код = текст.components(separatedBy: .newlines)
                .map { строка -> String in
                    guard let i = строка.range(of: "//") else { return строка }
                    return String(строка[..<i.lowerBound])
                }
                .joined(separator: "\n")

            let дверей = код.components(separatedBy: "DogEditorScreen()").count - 1
            guard дверей > 0 else { continue }
            двери[файл.lastPathComponent] = дверей
            ворота[файл.lastPathComponent] =
                код.components(separatedBy: "ProGate.isOpen(.secondDog").count - 1
        }

        // Проверка, что проверять было что, — первой и двумя числами.
        // Пустой обход и закрытые двери выглядят одинаково: ноль
        // беззащитных.
        #expect(файловОсмотрено >= 60, """
            осмотрено файлов: \(файловОсмотрено) — обход не состоялся, \
            и тишина ниже ничего не значит.
            """)
        #expect(двери.count >= 2, """
            дверей `DogEditorScreen()` найдено \(двери.count), а их две: \
            «Настройки → Добавить собаку» и «Собаки → Завести ещё собаку». \
            Либо экран переименован, либо дверь убрали — сканер в обоих \
            случаях ослеп, и молчать ему нельзя.
            """)

        let беззащитные = двери.sorted { $0.key < $1.key }
            .compactMap { файл, дверей -> String? in
                let сторожей = ворота[файл] ?? 0
                return сторожей >= дверей ? nil : "\(файл): дверей \(дверей), ворот \(сторожей)"
            }
        #expect(беззащитные.isEmpty, """
            дверь, заводящая собаку, стоит без ворот Pro: \(беззащитные).

            Звать надо фабрику — `ProGate.isOpen(.secondDog(among: dogs), \
            isPro: store.isPro)`, а не писать `if store.isPro` на месте: \
            фильтр показа применяет сама фабрика, и `dogs.count` против \
            `dogs.shownToPerson.count` — один тип и разный смысл.
            «Вторая и следующие собаки» — первая из двух строк пейволла; \
            дверь без ворот делает его украшением.
            """)
    }

    /// Текст без вызовов `ProGate` — по балансу скобок.
    ///
    /// По скобкам, а не построчно: аргумент `isPro:` стоит на СЛЕДУЮЩЕЙ
    /// строке в `FamilyScreen`, и построчный разбор счёл бы его прямым
    /// обращением. Разбор по одной строке ошибается в сторону полноты —
    /// у нас это уже дало снимок схемы богаче настоящего.
    ///
    /// # Ось расширена 29.10.2026 с `ProGate.isOpen(` до любого `ProGate.`
    ///
    /// **Это четвёртая корзина, и поймана она на себе.** У `ProGate`
    /// появилась вторая точка входа — `сверхПредела(_:isPro:)`, —
    /// и сторож покраснел на ДВУХ файлах здорового кода: `FamilyScreen`
    /// и `SharedDiaryScreen` зовут её законно, а вырезался только
    /// `isOpen`, то есть `isPro:` в её аргументах читался как прямое
    /// обращение.
    ///
    /// ```
    /// маркер `ProGate.isOpen(`   SettingsScreen 2 · PaywallScreen 3
    ///                            FamilyScreen 2 · SharedDiaryScreen 2  ← ложный красный
    /// маркер `ProGate.`          SettingsScreen 2 · PaywallScreen 3
    /// ```
    ///
    /// > **Сторож требовал конкретное ИМЯ механизма, а правило говорит
    /// > про наблюдаемое свойство** — «обращение к `isPro` идёт через
    /// > `ProGate`, а не на месте». Такой краснеет от всякой замены
    /// > способа, в том числе от расширения на лучший, и в эталон его
    /// > вносить нельзя: запись узаконила бы красное под именем, которое
    /// > завтра покраснеет от настоящей потери.
    ///
    /// **Граница расширения названа:** вырезав любой `ProGate.…(…)`,
    /// сторож перестаёт видеть `isPro`, спрятанный в аргументах будущей
    /// функции `ProGate`. Это принято сознательно — `ProGate` закрытое
    /// перечисление чистых функций в одном файле, и «через `ProGate`»
    /// ровно то, чего правило требует. Прямое `store.isPro` во вью
    /// он ловит как и ловил.
    ///
    /// **Имя функции разбирается, а не ищется скобка вперёд.** Поиск
    /// ближайшей `(` после `ProGate.` проглотил бы остаток файла там,
    /// где `ProGate` упомянут без вызова, — и ослеп бы молча, ровно так,
    /// как предупреждает `guard закрылось` ниже.
    private static func безВызововВорот(_ текст: String) -> String {
        var итог = ""
        var остаток: Substring = текст[...]
        while let вызов = остаток.range(of: "ProGate.") {
            итог.append(contentsOf: остаток[..<вызов.lowerBound])

            // Имя функции: буквы, цифры, подчерк — и сразу за ним «(».
            var имя = вызов.upperBound
            while имя < остаток.endIndex,
                  остаток[имя].isLetter || остаток[имя].isNumber || остаток[имя] == "_" {
                имя = остаток.index(after: имя)
            }
            guard имя < остаток.endIndex, остаток[имя] == "(" else {
                // `ProGate` помянут без вызова — вырезать нечего.
                // Отдаём прочитанное обратно и идём дальше, иначе
                // упоминание типа съело бы файл до конца.
                итог.append(contentsOf: остаток[вызов.lowerBound..<имя])
                остаток = остаток[имя...]
                continue
            }

            var глубина = 0
            var i = имя                                        // указывает на «(»
            var закрылось = false
            while i < остаток.endIndex {
                if остаток[i] == "(" { глубина += 1 }
                if остаток[i] == ")" {
                    глубина -= 1
                    if глубина == 0 { закрылось = true; break }
                }
                i = остаток.index(after: i)
            }
            // Скобка не закрылась — вырезать нечего, иначе сканер
            // проглотил бы остаток файла и ослеп молча.
            guard закрылось else { return итог + остаток }
            остаток = остаток[остаток.index(after: i)...]
        }
        return итог + остаток
    }
    /// Подзаголовок пейволла считает число, а не повторяет его словом.
    ///
    /// # Чего стоил односторонний сторож
    ///
    /// До 25.10.2026 в шапке стоял литерал «ровно три вещи», а
    /// `ProFeature.allCases` дал **два** с 24.10: в тот день Виктория
    /// убрала перенос навыка из Pro. Подзаголовок обещал три
    /// и перечислял две.
    ///
    /// Доккомментарий шапки при этом говорил «четвёртая не может
    /// появиться в подписи, не появившись в воротах» — и это было
    /// ВЕРНО. От появления защита была. От исчезновения не было
    /// ничего: литерал не знает, сколько случаев в перечислении.
    ///
    /// > **Односторонний сторож выглядит как двусторонний.** Он
    /// > проверяет то, что легко придумать (прибавили), и молчит
    /// > о том, что случается чаще (убрали). У этого утверждения
    /// > обе стороны проверяются порознь — ниже два `#expect`,
    /// > и каждый краснеет на своём.
    ///
    /// Решение дизайна, круг 6, пункт 9: «Число не литерал: его считает
    /// код из `ProFeature.allCases.count` через склонение каталога.
    /// Тест падает и когда пункт появился, и когда пропал».
    @Test("Число в шапке пейволла равно числу случаев ProFeature")
    func числоВШапкеСчитаетсяИзПеречисления() {
        let сколько = ProFeature.allCases.count
        let подпись = PaywallScreen.сколькоВещей

        // Сторона первая: пункт ПРОПАЛ. Подпись обещает больше, чем
        // ворота открывают, — человек платит за то, чего нет.
        #expect(подпись.contains(String(сколько)), """
            шапка пейволла говорит «\(подпись)», а случаев
            в `ProFeature` — \(сколько). Если число в подписи больше,
            человек платит за то, чего в воротах нет.

            Число обязано считаться из перечисления, а не писаться
            словом: литерал не знает, сколько случаев осталось, и ровно
            так 24.10 подзаголовок прожил день с обещанием трёх вещей
            при двух живых.
            """)

        // Сторона вторая: ЛИТЕРАЛ ВЕРНУЛСЯ. Проверяется отдельно,
        // потому что числовая проверка выше прошла бы и на литерале
        // «ровно 2 вещи» — он содержит двойку и разойдётся молча
        // при следующей правке состава.
        for словом in ["три", "две", "одну", "одна", "два", "four", "three", "two"] {
            #expect(!подпись.lowercased().contains(словом), """
                в шапке пейволла число написано СЛОВОМ («\(словом)»),
                а не подставлено из `ProFeature.allCases.count`.
                Проверка «подпись содержит \(сколько)» такую подпись
                пропустит, если слово случайно совпало с текущим
                составом, — и разойдётся молча при следующей правке.
                Склонение держит каталог: ключ `ровно %lld вещи`
                несёт формы числа.
                """)
        }
    }

    /// Контроль: подпись вообще СОБРАЛАСЬ, а не вышла пустой.
    ///
    /// Без него оба утверждения выше зелены на пустой строке: пустая
    /// не содержит ни числа — нет, содержит… — ни запрещённых слов.
    /// Первое `#expect` её поймает, второе нет; значит контроль нужен
    /// именно второму, и стоит он отдельно, чтобы вердикт был точным.
    @Test("Контроль: подпись пейволла не пуста и несёт слово «вещ»")
    func подписьСобралась() {
        let подпись = PaywallScreen.сколькоВещей
        #expect(!подпись.isEmpty, "подпись пейволла пуста — ключ каталога не нашёлся")
        #expect(подпись.lowercased().contains("вещ"), """
            подпись «\(подпись)» не содержит корня «вещ» — значит
            вместо ключа `ровно %lld вещи` подставилось что-то другое,
            и проверки выше мерят не ту строку.
            """)
    }
}
