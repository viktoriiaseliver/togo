    @Test("Список потерь выводится из ProFeature и не обещает снятого")
    func потеряНеРазошлась() {
        for вещь in ProFeature.allCases {
            let п = вещь.подписьПотери
            #expect(!п.значок.isEmpty && !п.название.isEmpty && !п.пояснение.isEmpty,
