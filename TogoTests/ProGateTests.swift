import Testing
import Foundation
@testable import Togo

/// Ворота Pro: три вещи, одно правило, и ни одного `isPro` на месте.
///
/// **Чем это оплачено.** До 07.10.2026 правило было списано по восьми
/// `store.isPro` в четырёх вью, и трое из восьми были воротами. Из этого
/// следовали две уже заплаченные цены:
///
/// * `SettingsScreen` считал безымянные записи за собак, и человек
///   без подписки видел пейволл на ПЕРВОЙ настоящей собаке;
/// * подпись в пейволле и сами ворота жили врознь, и сверить
///   «Pro открывает ровно три вещи» было нечем — обещание «ссылка
///   ситтера» трижды уезжало в подпись без дороги в коде.
///
/// > **Пока правило списано по местам применения, «ровно три вещи» —
/// > утверждение, которое нечем проверить.**
@Suite("Ворота Pro открывают ровно три вещи")
struct ProGateTests {

    // MARK: Поведение

    /// Таблица, а не отдельные тесты: так видно, что проверены **оба**
    /// края порога. Условие «не все» выполняется и при нуле — у Kvit
    /// это уже стоило сторожа, который проходил при противоположном
    /// дефекте.
    @Test("Бесплатный план даёт одну собаку и двоих человек")
    func порогиБесплатногоПлана() {
        let таблица: [(ProRequest, Bool, Bool, String)] = [
            // запрос, подписка, ожидание, почему
            //
            // Матрица переноса была здесь третьей вещью и снята
            // 24.10.2026 решением Виктории: «убери обещание и матрицу,
            // это просто помощь». Строки убраны вместе со случаем,
            // а не закомментированы: тест, перечисляющий несуществующее,
            // не компилируется — и это правильная цена.
            (.secondDog(dogsShown: 0), false, true,
             "первая собака бесплатна — за неё денег не просят"),
            (.secondDog(dogsShown: 1), false, false, "вторая — за подписку"),
            (.secondDog(dogsShown: 8), false, false, "и восьмая тоже"),
            (.secondDog(dogsShown: 8), true, true, "с подпиской сколько угодно"),

            (.familyBeyondTwo(familyMembers: 0), false, true,
             "пустая семья — приглашать можно"),
            (.familyBeyondTwo(familyMembers: 1), false, true,
             "второго человека бесплатно"),
            (.familyBeyondTwo(familyMembers: 2), false, false,
             "третьего — за подписку"),
            (.familyBeyondTwo(familyMembers: 3), false, false, "и четвёртого"),
            (.familyBeyondTwo(familyMembers: 3), true, true,
             "с подпиской без предела"),
        ]

        // Проверка, что проверять было что, — первой. Иначе пустая
        // таблица даёт зелёный набор, ничего не проверивший.
        //
        // Порог опущен 11 → 9 вместе со снятием матрицы из Pro
        // (решение Виктории 24.10.2026). Две строки таблицы были её:
        // «закрыта целиком» и «с подпиской открыта». Убыль ЗАКОННАЯ,
        // и потому записана с причиной: храповик, опущенный без причины,
        // перестаёт быть храповиком.
        #expect(таблица.count >= 9, "таблица порогов усохла: \(таблица.count)")

        for (запрос, isPro, ожидание, почему) in таблица {
            #expect(ProGate.isOpen(запрос, isPro: isPro) == ожидание, """
                \(запрос) при isPro=\(isPro) должно быть \
                \(ожидание ? "ОТКРЫТО" : "закрыто"): \(почему).
                Пороги — ProLimit.dogs=\(ProLimit.dogs), \
                ProLimit.familyMembers=\(ProLimit.familyMembers); они сняты \
                с кода, который был, а не назначены заново.
                """)
        }
    }

    /// Регрессия 07.10.2026: **безымянные записи — не собаки.**
    ///
    /// Восемь пустых `Dog` в чужом дневнике сделали `dogs.isEmpty`
    /// ложным, и ворота запросили денег за первую настоящую собаку.
    /// Тест стоит на фабрике `secondDog(among:)`, а не на числе:
    /// фильтр показа обязан применяться ВНУТРИ входа, иначе
    /// `dogs.count` и `dogs.shownToPerson.count` — один тип и разный
    /// смысл, и промах между ними компилируется.
    /// `@MainActor` — потому что фабрика `secondDog(among:)` изолирована
    /// им намеренно: фильтр читает `@Model`, а модели не `Sendable`.
    @MainActor
    @Test("Восемь безымянных записей не делают первую собаку платной")
    func фантомыНеСчитаются() {
        let фантомы = (0..<8).map { _ in Dog(name: "", weightKg: 0) }
        #expect(фантомы.allSatisfy { !$0.canBeShown },
                "сценарий не наполнился: эти записи показываются, значит они не фантомы")

        #expect(ProGate.isOpen(.secondDog(among: фантомы), isPro: false), """
            ворота закрылись при восьми БЕЗЫМЯННЫХ записях и нуле
            показываемых собак — то есть за первую настоящую собаку
            просят денег. Именно это и чинили 07.10.
            """)

        let живая = Dog(name: "Стич", weightKg: 4.7)
        #expect(!ProGate.isOpen(.secondDog(among: фантомы + [живая]), isPro: false),
                "одна показываемая собака уже есть — вторая за подписку")
    }

    // MARK: Полнота

    /// У каждой вещи есть дорога к воротам.
    ///
    /// Четвёртая вещь в `ProFeature` компилятор заставит подписать
    /// (`подпись` перебирает все случаи), но **не** заставит завести
    /// ей запрос: `ProRequest` перебирается сам по себе. Этот тест
    /// и есть та недостающая половина — он краснеет и говорит, что
    /// добавить.
    @Test("Каждая вещь Pro достижима запросом")
    func каждаяВещьИмеетЗапрос() {
        let запросы: [ProRequest] = [
            .secondDog(dogsShown: 0),
            .familyBeyondTwo(familyMembers: 0),
        ]
        let покрыты = Set(запросы.map(\.feature.rawValue))
        let непокрытые = ProFeature.allCases
            .map(\.rawValue).filter { !покрыты.contains($0) }.sorted()

        #expect(непокрытые.isEmpty, """
            вещь Pro есть, а запроса к воротам у неё нет: \(непокрытые).
            Значит она либо не охраняется вовсе, либо охраняется
            `store.isPro` на месте — а это ровно то устройство,
            от которого уходили.
            """)
    }

    /// Подпись пейволла выводится отсюда, а не лежит копией.
    @Test("Подпись есть у каждой вещи и пейволл берёт именно её")
    func подписьНеРазошлась() {
        for вещь in ProFeature.allCases {
            let п = вещь.подпись
            #expect(!п.значок.isEmpty && !п.название.isEmpty && !п.пояснение.isEmpty,
                    "у \(вещь.rawValue) пустая часть подписи")
        }

        let изСтора = SubscriptionStore.proFeatures
        #expect(изСтора.count == ProFeature.allCases.count, """
            в пейволле \(изСтора.count) строк, вещей \
            \(ProFeature.allCases.count). Список обязан выводиться
            из ProFeature, а не лежать рядом копией: копия расходится
            молча, и оба списка зелёные, каждый про своё.
            """)
        // Через замыкания, а не key path: путь к элементу кортежа
        // (`\.1`, `\.подпись.название`) в Swift не существует.
        #expect(изСтора.map { $0.1 } == ProFeature.allCases.map { $0.подпись.название },
                "порядок или слова разошлись с ProFeature")
    }

    // MARK: Сторож на прямые обращения

    /// Прямых `isPro` во вью разрешено ровно столько, сколько записано,
    /// и у каждого файла причина.
    ///
    /// **Запрет, а не требование.** Спросить «нет ли здесь прямого
    /// обращения» можно надёжно; спросить «ворота ли это» — нельзя:
    /// сканер не знает, решает строка доступ или показывает состояние.
    /// Поэтому список закрытый, с числом на файл: появилось обращение
    /// там, где не записано, — красное; стало больше там, где
    /// записано, — тоже красное.
    ///
    /// Число на файл, а не просто имя файла, — потому что файловое
    /// исключение спрятало бы НОВЫЕ ворота в уже разрешённом файле.
    /// В `SettingsScreen` живут и раздел подписки, и отладочный
    /// тумблер, и там же лежали ворота второй собаки.
    private static let разрешено: [String: (сколько: Int, причина: String)] = [
        "PaywallScreen.swift": (3, """
            экран подписки показывает её состояние, а не решает доступ: \
            баннер «активна», погашенная кнопка покупки и закрытие \
            после успеха
            """),
        "SettingsScreen.swift": (2, """
            раздел подписки («активна» против кнопки пейволла) \
            и отладочный тумблер под `#if DEBUG`
            """),
    ]

    @Test("Прямых обращений к isPro во вью не больше записанного")
    func прямыхОбращенийНеБольше() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features")

        var прямые: [String: Int] = [:]
        var ворот = 0
        var файловОсмотрено = 0

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            файловОсмотрено += 1

            // **Проза отбрасывается до разбора.** Сканер, не различающий
            // код и комментарий, меряет комментарий: у Timer такой
            // сторож покраснел на строке «// НЕ `MapsApp.allCases`»,
            // то есть наказал за объяснение, почему так делать нельзя.
            // Здесь это не умозрительно — я сам написал рядом с воротами
            // «а не `store.isPro` на месте».
            let код = текст.components(separatedBy: .newlines)
                .map { строка -> String in
                    guard let i = строка.range(of: "//") else { return строка }
                    return String(строка[..<i.lowerBound])
                }
                .joined(separator: "\n")

            ворот += код.components(separatedBy: "ProGate.isOpen").count - 1

            // Вызовы ворот вырезаются целиком: `isPro:` — их законный
            // аргумент, и считать его прямым обращением значило бы
            // краснеть ровно на починке.
            let безВорот = Self.безВызововВорот(код)
            let счёт = безВорот.components(separatedBy: "isPro").count - 1
            if счёт > 0 { прямые[файл.lastPathComponent] = счёт }
        }

        // Счётчик осмотренного — первым. Набор, которому нечего
        // проверять, молчит так же, как набор, у которого всё хорошо.
        // Порог снят замером: `find Togo/Features -name '*.swift' | wc -l`
        // → 64 на 07.10.2026. Числом, а не «больше нуля»: ноль файлов
        // дал бы ноль обращений и полную тишину.
        #expect(файловОсмотрено >= 60, """
            осмотрено файлов: \(файловОсмотрено) — разбор не состоялся,
            и тишина ниже ничего не значит.
            """)
        // Опущено 3 → 2 вместе со снятием матрицы из Pro, 24.10.2026.
        // Ворота матрицы стояли в `TrainingScreens.swift` и сняты
        // вместе с обещанием; вещей Pro осталось две.
        //
        // > **Число здесь обязано совпадать с числом случаев
        // > `ProFeature`, и совпадение это не проверяется ничем** —
        // > кроме соседнего теста `каждаяВещьИмеетЗапрос`, который
        // > краснеет, если вещь заведена, а запроса ей нет. Обратное
        // > — вещь снята, а число осталось — ловится только этой
        // > строкой, и ловится она красным на верном коде.
        #expect(ворот >= 2, """
            вызовов ProGate.isOpen найдено \(ворот), а вещей Pro две.
            Сканер, переставший что-либо находить, молчит так же, как
            тот, кому нечего сказать.
            """)

        let доля = """
            ворот через ProGate: \(ворот) · прямых isPro: \
            \(прямые.values.reduce(0, +)) в \(прямые.count) файлах \
            из \(файловОсмотрено) осмотренных
            """

        var беззаконные: [String] = []
        var выросли: [String] = []
        for (файл, счёт) in прямые.sorted(by: { $0.key < $1.key }) {
            guard let запись = Self.разрешено[файл] else {
                беззаконные.append("\(файл) — \(счёт)")
                continue
            }
            if счёт != запись.сколько {
                выросли.append("\(файл): записано \(запись.сколько), найдено \(счёт)")
            }
        }

        #expect(беззаконные.isEmpty, """
            \(доля)

            прямое обращение к isPro там, где оно не разрешено: \
            \(беззаконные).
            Если это ворота — позови ProGate: тогда «Pro открывает ровно
            три вещи» можно будет проверить. Если это показ состояния
            подписки — впиши файл в `разрешено` С ПРИЧИНОЙ: исключение
            без причины через месяц неотличимо от дыры.
            """)
        #expect(выросли.isEmpty, """
            \(доля)

            в разрешённом файле обращений стало больше: \(выросли).
            Число на файл стоит именно для этого: новые ворота
            в `SettingsScreen` иначе спрятались бы за старым
            исключением.
            """)
        #expect(Self.разрешено.allSatisfy { !$0.value.причина.isEmpty },
                "исключение без причины")

        // **Границы собственного умения — последней строкой.** Пока
        // их называет человек, они теряются при первой передаче.
        print("""
            \(доля)
            Чего этот сторож НЕ видит:
              · ворота ли строка или показ состояния — решает человек,
                сканер различает только «через ProGate» и «напрямую»;
              · обращение через обёртку с другим именем: сегодня
                обёрток нет ни одной (замер 07.10 — все `can*` идут
                через `appState.can`), но появится — он промолчит;
              · правильность самих порогов: это выше, в таблице.
            """)
    }

    /// Текст без вызовов `ProGate.isOpen(...)` — по балансу скобок.
    ///
    /// По скобкам, а не построчно: аргумент `isPro:` стоит на СЛЕДУЮЩЕЙ
    /// строке в `FamilyScreen`, и построчный разбор счёл бы его прямым
    /// обращением. Разбор по одной строке ошибается в сторону полноты —
    /// у нас это уже дало снимок схемы богаче настоящего.
    private static func безВызововВорот(_ текст: String) -> String {
        var итог = ""
        var остаток: Substring = текст[...]
        while let вызов = остаток.range(of: "ProGate.isOpen(") {
            итог.append(contentsOf: остаток[..<вызов.lowerBound])
            var глубина = 0
            var i = остаток.index(before: вызов.upperBound)   // указывает на «(»
            var закрылось = false
            while i < остаток.endIndex {
                if остаток[i] == "(" { глубина += 1 }
                if остаток[i] == ")" {
                    глубина -= 1
                    if глубина == 0 { закрылось = true; break }
                }
                i = остаток.index(after: i)
            }
            // Скобка не закрылась — вырезать нечего, иначе сканер
            // проглотил бы остаток файла и ослеп молча.
            guard закрылось else { return итог + остаток }
            остаток = остаток[остаток.index(after: i)...]
        }
        return итог + остаток
    }
}
