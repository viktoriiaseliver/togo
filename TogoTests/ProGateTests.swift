    /// из двух списков, а разошёлся второй.
    ///
    /// > **Сторож, стоящий на одной копии из двух, молчит про вторую —
    /// > и молчание читается как согласие.**
    ///
    /// Подделка (28.10.2026): вернуть в `подписьПотери` случай
    /// с матрицей — краснеет счёт; поменять местами два случая —
