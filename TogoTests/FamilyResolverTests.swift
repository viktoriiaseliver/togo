import Testing
import Foundation
@testable import Togo

/// «Кто я и что мне можно» решается в одном месте.
///
/// До 23.09.2026 это решение жило дважды: в `AppState.adoptMe` — для
/// экранов, и в `QuickLog.можно` — для голоса и кнопки «Действие».
/// Написаны они были в один день одной рукой и **уже разошлись
/// в двух местах**, оба — на неполных данных:
///
/// 1. **Пустая семья.** На экранах у гостя это значило «наблюдатель»,
///    голосом — «можно всё».
/// 2. **Единственная карточка.** На экранах она считалась моей только
///    при `isMe`, голосом бралась любая.
///
/// Обе дыры открываются в один и тот же момент: гость уже принял
/// приглашение, а карточки семьи ещё не приехали или приехала одна —
/// естественно, карточка **владельца**. И обе выдавали право на дозу.
///
/// **Край и есть то место, ради которого правило пишут.** Две
/// реализации сходятся в середине и расходятся там, где данных мало.
@Suite("Кто я — решается одинаково везде")
struct FamilyResolverTests {

    private func семья() -> (FamilyMember, FamilyMember) {
        (FamilyMember(name: "Виктория", role: .owner, isMe: true),
         FamilyMember(name: "Мама", role: .coOwner))
    }

    // MARK: Край первый — семьи ещё нет

    @Test("У гостя без карточек семьи прав на запись нет")
    func пустаяСемьяУГостя() {
        let права = FamilyResolver.права(среди: [], запомненный: nil, гость: true)
        #expect(!права.contains(.logBasics), """
            гость, у которого карточки семьи ещё не приехали, пишет
            в чужой дневник. Момент короткий: приглашение принято,
            синхронизация не доехала — и в нём разрешалась доза.
            """)
        #expect(!права.contains(.giveDose))
        #expect(права.contains(.seeMedical), "читать гостю можно")
    }

    @Test("В своём дневнике без семьи можно всё")
    func пустаяСемьяУСебя() {
        let права = FamilyResolver.права(среди: [], запомненный: nil, гость: false)
        #expect(права.contains(.logBasics), """
            человек не может записать выход в собственном дневнике,
            где он просто не заводил участников.
            """)
        #expect(права.contains(.giveDose))
    }

    // MARK: Край второй — приехала одна карточка, и она чужая

    @Test("Единственная чужая карточка своей не считается")
    func однаЧужаяНеМоя() {
        let владелец = FamilyMember(name: "Виктория", role: .owner, isMe: true)
        // `isMe` приехал вместе с карточкой владельца — так уже было
        // на втором телефоне (`5c70324`). Для ГОСТЯ эта карточка чужая
        // при любом `isMe`: своей она станет, только если её
        // идентификатор запомнен на этом устройстве.
        let права = FamilyResolver.права(среди: [владелец],
                                         запомненный: nil, гость: true)
        #expect(!права.contains(.giveDose), """
            гость получил право давать дозу по чужой карточке.
            При частичной синхронизации единственная приехавшая
            карточка — как раз владельца.
            """)
        #expect(!права.contains(.editTreatment))
    }

    @Test("Единственная карточка без isMe не считается своей")
    func однаБезМетки() {
        let чужая = FamilyMember(name: "Мама", role: .coOwner)
        #expect(FamilyResolver.меня(среди: [чужая], запомненный: nil) == nil, """
            «единственная карточка» без `isMe` значит «любая
            приехавшая», а это чужие права.
            """)
    }

    @Test("Единственная своя карточка опознаётся")
    func однаСвоя() {
        let своя = FamilyMember(name: "Виктория", role: .owner, isMe: true)
        #expect(FamilyResolver.меня(среди: [своя], запомненный: nil)?.id == своя.id)
    }

    // MARK: Обычный путь

    @Test("Запомненная карточка сильнее метки isMe")
    func запомненныйСильнее() {
        let (хозяйка, мама) = семья()
        let мой = FamilyResolver.меня(среди: [хозяйка, мама], запомненный: мама.id)
        #expect(мой?.id == мама.id, """
            `isMe` хранится в модели и уезжает в общий дневник;
            запомненный идентификатор лежит на устройстве и не уезжает.
            """)
    }

    @Test("Права берутся у своей карточки, а не у роли по умолчанию")
    func праваИзКарточки() {
        let (хозяйка, мама) = семья()
        let права = FamilyResolver.права(среди: [хозяйка, мама],
                                         запомненный: мама.id, гость: true)
        #expect(права == мама.permissions)
        #expect(права.contains(.giveDose), "со-владелец даёт дозу")
        #expect(!права.contains(.editTreatment), "схему лечения — нет")
    }

    // MARK: Правило осталось одно

    /// Сторож на **вызов**, а не на правило: правило можно вынести
    /// и забыть позвать — сегодня это уже случалось с `DuplicateGuard`.
    @Test("Оба пути спрашивают общее решение")
    func обаЗовутОдно() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        for путь in ["Togo/App/AppState.swift", "Togo/Intents/QuickLogIntents.swift"] {
            let исходник = try String(
                contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
            // Без точки: вызов переносится на следующую строку, и
            // «FamilyResolver.» тогда не находится. Тест, ищущий
            // строку из исходника, ищет форматирование, а не смысл —
            // в этот же день так уже краснел сторож окна натощак,
            // споткнувшись о собственный комментарий.
            #expect(исходник.contains("FamilyResolver"), """
                \(путь) снова решает сам, кто я и что мне можно.
                Две реализации одного правила сходятся в середине
                и расходятся в краю — там, где данных мало, и где
                цена ошибки это доза.
                """)
            #expect(!исходник.contains("count == 1 ?"), """
                \(путь): «единственная карточка» разбирается на месте,
                мимо общего решения.
                """)
        }
    }
}
