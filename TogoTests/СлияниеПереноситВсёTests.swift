import Testing
import Foundation
import SwiftData
@testable import Togo

/// Слияние дубликатов обязано переносить ВСЕ записи, а не те,
/// про которые вспомнили.
///
/// # Что оплатило этого сторожа
///
/// Замер 28.10.2026. Перенос был написан дважды (отладочный
/// инструмент под `#if DEBUG` и релизный экран «Семья»), счёт
/// переносимого — ещё дважды. Четыре копии одного списка,
/// и все четыре неполны ОДИНАКОВО: одиннадцать связей из пятнадцати.
///
/// ```
/// не переносились   анализы · визиты · диагнозы · рецепты
/// у Стича это       140 + 40 + 7 + 40 = 227 записей
/// что видел человек «Перенесено записей: N. Дневник снова один»
/// ```
///
/// Записи при этом физически целы — удаление мягкое, надгробием.
/// Но они остаются на карточке с надгробием, а медицинский слой
/// показывает записи активной собаки: вся история исчезает
/// с экранов.
///
/// # Ось: модель против списка, а не список против себя
///
/// Сторож читает связи ИЗ ОПИСАНИЯ МОДЕЛИ (`Schema`) и сверяет
/// с рукописным списком `ОбъединениеСобак.переносимые`. Вывести
/// список из модели было бы проще — и бесполезно: тогда он проверял
/// бы код им же самим и зеленел бы на любой дыре.
///
/// > Сторож, у которого обе стороны сравнения растут из одного
/// > источника, не может покраснеть. Здесь стороны разные:
/// > описание модели и то, что человек написал руками.
@Suite("Слияние дубликатов переносит всё")
@MainActor
struct СлияниеПереноситВсёTests {

    /// Связи «ко многим» у `Dog` — из описания схемы, а не грепом
    /// по исходнику: греп читал бы текст, а перенос работает
    /// с моделью.
    private func связиСобаки() -> Set<String> {
        let схема = Schema([Dog.self])
        guard let сущность = схема.entitiesByName["Dog"] else { return [] }
        return Set(сущность.relationships.map(\.name))
    }

    @Test("Каждая связь собаки названа в переносе")
    func всеСвязиПереносятся() {
        let связи = связиСобаки()

        // КОНТРОЛЬ ПЕРВЫМ: описание модели прочиталось. Пустое
        // множество означало бы, что сверять нечем, а не «всё сошлось».
        #expect(связи.count >= 10, """
            у Dog прочитано \(связи.count) связей — описание модели
            не разобралось. Пустой список даёт зелёный цвет на любой
            дыре: сравнивать не с чем.
            """)

        let забыты = связи.subtracting(ОбъединениеСобак.переносимые)
        #expect(забыты.isEmpty, """
            слияние дубликатов НЕ переносит: \(забыты.sorted().joined(separator: ", ")).

            Эти записи останутся на карточке с надгробием и исчезнут
            со всех экранов — физически целые, но недостижимые.
            Человек увидит «Дневник снова один» и потеряет историю.

            Добавь связь в `ОбъединениеСобак.перенести` И в `связанных`
            (счёт обязан совпадать с переносом), затем в список
            `переносимые`.
            """)

        // И обратно: список не должен называть того, чего в модели нет.
        // Иначе он тихо протухнет вместе с удалённой связью.
        let лишние = ОбъединениеСобак.переносимые.subtracting(связи)
        #expect(лишние.isEmpty, """
            в списке переносимых есть имена, которых у модели нет:
            \(лишние.sorted().joined(separator: ", ")).
            Список протух — связь удалили, а запись осталась.
            """)
    }

    @Test("Счёт переносимого совпадает с тем, что переносится")
    func счётНеВрёт() throws {
        let контейнер = try ModelContainer(
            for: Persistence.schema,
            configurations: ModelConfiguration(isStoredInMemoryOnly: true,
                                               cloudKitDatabase: .none))
        let context = ModelContext(контейнер)

        let главная = Dog(name: "Стич", weightKg: 4.1)
        let лишняя = Dog(name: "Стич", weightKg: 4.1)
        context.insert(главная)
        context.insert(лишняя)

        // По записи КАЖДОГО медицинского вида — именно их и забывали.
        let анализ = LabResult(sampledOn: .now)
        анализ.dog = лишняя
        context.insert(анализ)
        let визит = VetVisit(date: .now)
        визит.dog = лишняя
        context.insert(визит)
        let диагноз = Diagnosis(wording: "Гипотиреоз")
        диагноз.dog = лишняя
        context.insert(диагноз)
        let рецепт = Prescription(date: .now)
        рецепт.dog = лишняя
        context.insert(рецепт)
        let запись = LogEvent(kind: .outing, date: .now, authorName: "Виктория")
        запись.dog = лишняя
        context.insert(запись)
        try context.save()

        let обещано = ОбъединениеСобак.связанных(лишняя)
        #expect(обещано == 5, "счёт нашёл \(обещано) записей вместо пяти")

        let перенесено = ОбъединениеСобак.перенести(с: лишняя, на: главная)
        try context.save()

        #expect(перенесено == обещано, """
            перенос вернул \(перенесено), а счёт обещал \(обещано):
            число в подтверждении разошлось с делом.
            """)
        #expect(ОбъединениеСобак.связанных(лишняя) == 0, """
            на лишней карточке осталось \(ОбъединениеСобак.связанных(лишняя))
            записей — они исчезнут с экранов вместе с ней.
            """)
        #expect(ОбъединениеСобак.связанных(главная) == 5,
                "на главную доехало не всё")
        // Поимённо: именно медицинские и забывали.
        #expect(анализ.dog?.persistentModelID == главная.persistentModelID,
                "анализ не переехал")
        #expect(визит.dog?.persistentModelID == главная.persistentModelID,
                "визит не переехал")
        #expect(диагноз.dog?.persistentModelID == главная.persistentModelID,
                "диагноз не переехал")
        #expect(рецепт.dog?.persistentModelID == главная.persistentModelID,
                "рецепт не переехал")
    }
}
