import Foundation
import Testing
@testable import Togo

/// Разбор числа с бланка анализа.
///
/// **Предмет — РАЗБОР ВВОДА, а не формат показа.** Разница названа
/// нарочно: 08.10.2026 у нас сторож сравнивал написание и выдавал это
/// за назначение (`единица("мин")` — показ, а не разбор), и час ушёл
/// на то, чтобы различить. Здесь проверяется путь «человек набрал →
/// легло в `Double?`», и ни одна проверка ниже не утверждает ничего
/// о том, как число выглядит на экране.
///
/// Зачем вообще: `Double("12,9")` возвращает `nil`. Это **молчаливый
/// путь** — поле заполнено, кнопка сохранения активна, в базе пусто,
/// и ни один код возврата об этом не скажет. Человек увидит «анализ
/// без числа» там, где набрал 12,9.
@Suite("Число с бланка · разбор ввода")
struct ЧислоСБланкаTests {

    // MARK: Оба разделителя приходят в одно поле

    /// На `.decimalPad` разделитель даёт раскладка системы, то есть
    /// выбрать один нельзя: оба придут в то же поле.
    @Test("Запятая и точка дают одно число")
    func обаРазделителя() {
        #expect(ЧислоСБланка.разобрать("12,9") == 12.9)
        #expect(ЧислоСБланка.разобрать("12.9") == 12.9)
        #expect(ЧислоСБланка.разобрать("51,48") == 51.48)
        #expect(ЧислоСБланка.разобрать("13") == 13)
    }

    /// Запятая без разбора — это `nil`, то есть «значения нет»
    /// при заполненном поле. Проверка от обратного: не «точка
    /// работает», а **запятая обязана дать число**.
    @Test("Запятая обязана дать число, а не nil")
    func запятаяНеТеряется() {
        let разобрано = ЧислоСБланка.разобрать("0,05")
        #expect(разобрано != nil, """
            запятая не разобралась: поле заполнено, значение пустое.
            Это молчаливый путь — человек набрал 0,05 и получит
            «анализ без числа».
            """)
        #expect(разобрано == 0.05)
    }

    // MARK: Пусто — это решение, а не ошибка

    /// У референса «не введено» значит «норма не указана»,
    /// и `LabNorm.Reference.unknown` скажет именно это, а не «в норме».
    /// Поэтому пустая строка обязана давать `nil`, а не ноль:
    /// ноль — это настоящая норма «от 0».
    @Test("Пустое поле — nil, а не ноль")
    func пустоЭтоНеНоль() {
        #expect(ЧислоСБланка.разобрать("") == nil)
        #expect(ЧислоСБланка.разобрать("   ") == nil)
        #expect(ЧислоСБланка.разобрать("") != 0, "ноль — это норма «от 0», а не отсутствие нормы")
    }

    /// Не число — тоже `nil`, и это правильное поведение, а не дефект:
    /// ослабить разбор до «взять первые цифры» значило бы получить тихо
    /// неверное число вместо видимо отсутствующего значения.
    @Test("Не число остаётся неразобранным, и это верно")
    func мусорНеПревращаетсяВЧисло() {
        #expect(ЧислоСБланка.разобрать("норма") == nil)
        #expect(ЧислоСБланка.разобрать("12,9–51,5") == nil, "диапазон — это два поля, а не одно число")
        // Предел прибора вводится ВИДОМ значения, а не числом со знаком:
        // «<0,1» не есть число, и разбор обязан это сказать пустотой.
        #expect(ЧислоСБланка.разобрать("<0,1") == nil)
    }

    // MARK: Вставка из PDF

    /// Числа вставляют из PDF бланка, и вместе с ними приезжают
    /// неразрывные пробелы. `trimmingCharacters(in: .whitespaces)`
    /// их не снимает — для Foundation это не пробелы.
    ///
    /// Тот же класс, что многобайтная кавычка, приклеившаяся к имени
    /// переменной: лишний байт пришёл не из числа, а из соседнего
    /// символа, и без обработки вышла бы пустота при заполненном поле.
    @Test("Неразрывные пробелы из PDF не ломают разбор")
    func неразрывныеПробелы() {
        #expect(ЧислоСБланка.разобрать("12,9\u{00A0}") == 12.9, "U+00A0 — неразрывный")
        #expect(ЧислоСБланка.разобрать("\u{202F}12,9") == 12.9, "U+202F — узкий неразрывный")
        #expect(ЧислоСБланка.разобрать("1 250") == 1250, "разряды пробелом")
    }

    // MARK: Показ сохраняет знаки

    /// **Не `Fmt.decimal`.** Он округляет до одного знака: референс
    /// Т4 в карте менялся трижды — `12,9–51,5`, `12,87–51,48`, `13–51`, —
    /// и через `Fmt.decimal` вторая запись стала бы первой МОЛЧА.
    ///
    /// Проверка стоит здесь, в наборе про разбор, нарочно: она
    /// про то, что `разобрать → показать` не теряет знаков, то есть
    /// про круг, а не про формат.
    /// Локаль НАЗЫВАЕТСЯ в каждом замере показа, а не берётся у хоста.
    ///
    /// До 26.10.2026 разделитель был прибит запятой, и проверки ниже
    /// сравнивали с `"12,87"` без локали. Пока запятая стояла в коде,
    /// это сходилось **у всех**; с локалью такие проверки стали бы
    /// зависеть от языка машины, где идёт прогон, — то есть краснели бы
    /// у одного и зеленели у другого, и причину никто бы не нашёл.
    ///
    /// > **Проверка без названной локали не «проверяет умолчание» —
    /// > она делает исход зависимым от стенда.** Умолчание проверяется
    /// > отдельно и нарочно, а не молчанием.
    private static let ру = Locale(identifier: "ru_RU")
    private static let ен = Locale(identifier: "en_US")

    @Test("Круг «разобрать → показать» не теряет знаков")
    func кругБезПотери() throws {
        let число = try #require(ЧислоСБланка.разобрать("12,87"))
        #expect(число == 12.87)
        #expect(ЧислоСБланка.показать(число, локаль: Self.ру) == "12,87", """
            показ потерял знак. Если здесь «12,9» — число прошло через
            округление до одного знака, и это потеря данных
            в медицинском числе, а не формат.
            """)
    }

    @Test("Целое показывается без разделителя на любой локали")
    func целоеБезЗапятой() throws {
        let число = try #require(ЧислоСБланка.разобрать("13"))
        // Обе локали в ОДНОМ замере: у целого разделителя нет вовсе,
        // и правка про локаль не должна была его завести.
        #expect(ЧислоСБланка.показать(число, локаль: Self.ру) == "13")
        #expect(ЧислоСБланка.показать(число, локаль: Self.ен) == "13")
    }

    /// Поле ввода отдаёт точку: человек правит то, что набрал,
    /// а `.decimalPad` примет оба вида. Показ и ввод — разные функции,
    /// и это проверяется, чтобы их не слили в одну.
    @Test("Текст для ввода и текст для показа — разные функции")
    func вводИПоказРазные() {
        #expect(ЧислоСБланка.текст(12.87) == "12.87")
        #expect(ЧислоСБланка.показать(12.87, локаль: Self.ру) == "12,87")
    }

    // MARK: Разделитель идёт по локали, а разбор — нет

    /// **Сторож на правку 26.10.2026, и ось у него ПАРНАЯ.**
    ///
    /// Прежде разделитель был прибит запятой: на английском человек
    /// видел `16,75 нмоль/л` вместо `16.75` — в медицинском числе,
    /// то есть там, где у нас красная линия.
    ///
    /// Проверяются **две половины в одном замере**, потому что чинить
    /// их по отдельности и значит завести дефект:
    ///
    /// ```
    /// ПОКАЗ    по локали человека     en → точка · ru → запятая
    /// РАЗБОР   терпим к ОБОИМ видам, по локали НЕ сужается
    /// ```
    ///
    /// > **Половина этой пары опаснее целой.** Сузь разбор по локали
    /// > «для единообразия» — и француз, вводящий число со своего
    /// > бланка при английском интерфейсе, получит пустое значение
    /// > при заполненном поле. Это молчаливый путь, он здесь уже
    /// > описан в голове типа, и однажды он уже стоил «анализа
    /// > без числа».
    ///
    /// Подделка, которая обязана покраснеть ровно здесь: вернуть
    /// в `показать` жёсткое `with: ","` — упадёт английская половина
    /// и **только она**, русская останется зелёной. Обратная подделка —
    /// сузить `разобрать` до локали — уронит половину про разбор
    /// и не тронет показ.
    @Test("Разделитель показа берётся у локали, а разбор принимает оба")
    func разделительПоЛокалиРазборПоОбоим() throws {
        // ПОКАЗ: одно и то же число, две локали, один замер.
        #expect(ЧислоСБланка.показать(16.75, локаль: Self.ен) == "16.75", """
            на английской локали показана запятая. Разделитель прибит \
            в коде вместо `локаль.decimalSeparator` — человек читает \
            число анализа в чужой записи.
            """)
        #expect(ЧислоСБланка.показать(16.75, локаль: Self.ру) == "16,75", """
            на русской локали показана точка — правка про локаль \
            перевернула умолчание вместо того, чтобы его сохранить.
            """)

        // РАЗБОР: оба вида приходят в одно поле и обязаны пройти.
        #expect(ЧислоСБланка.разобрать("16,75") == 16.75, """
            запятая перестала разбираться. Русский человек набирает \
            запятую, и это основной путь ввода.
            """)
        #expect(ЧислоСБланка.разобрать("16.75") == 16.75, """
            точка перестала разбираться. На `.decimalPad` разделитель \
            зависит от раскладки системы, то есть оба вида приходят \
            в одно и то же поле, и выбирать между ними нельзя.
            """)

        // СОСЕДНИЙ КОНТРОЛЬ, ответ на который известен заранее:
        // разрядность этой правкой не задета. Если здесь окажется
        // «16,8» — правка про разделитель уехала в округление,
        // а это потеря данных в медицинском числе.
        #expect(ЧислоСБланка.показать(16.75, локаль: Self.ру) != "16,8")
        #expect(ЧислоСБланка.показать(16.75, локаль: Self.ен) != "16.8")
    }

    // MARK: Граница

    /// Границы — печатаются, а не живут в чьей-то памяти.
    @Test("Границы: чего этот набор не проверяет")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит: строка из поля превращается в Double?
            предсказуемо, оба разделителя равноправны, пусто отличимо
            от нуля, и круг «разобрать → показать» не теряет знаков.

            НЕ проверяется:
            · что форма ЗОВЁТ этот разбор. Тест зовёт его сам и будет
              зелёным, даже если ни один экран его не вызывает, —
              для этого нужен сторож на вызов, не этот набор;
            · что человек увидит число на экране: это кадр;
            · локаль. Разбор нарочно НЕ идёт через NumberFormatter
              с текущей локалью: у француза разделитель запятая,
              у американца точка, а бланк может приехать любым.
              Принимаются оба вида всегда, и это решение, а не недосмотр.
            """
        #expect(границы.isEmpty == false)
        // Проверяется за минуту:
        //   grep -n "ЧислоСБланка.разобрать" Togo/Features/Health/*.swift
        // Ноль вызовов — значит разбор верен и бессилен.
    }
}
