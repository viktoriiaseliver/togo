import Foundation
import Testing

/// Числа анализа не показываются округлятором веса.
///
/// **Повод — живой дефект, найденный 08.10.2026.**
/// `MedicalRecordCards.swift:369-371` показывал значение анализа через
/// `Fmt.decimal`, а тот округляет до одного знака (`%.1f`,
/// `Formatting.swift:115`). То есть `16,75 нмоль/л` человек видел как
/// `16,8` — на экране «Здоровье → Сводка врачу», который открыт прямо
/// сейчас, и от этого числа считают дозу.
///
/// > **Форматирование, верное для одной величины, для другой является
/// > потерей данных.** Один знак после запятой — решение про вес
/// > и про «4 раза в день»; в медицину оно доехало только потому,
/// > что функция оказалась под рукой.
///
/// ## Почему сторож ТЕКСТОВЫЙ и почему от запрета
///
/// Поведенческого шва нет: `значение` — приватное вычисляемое свойство
/// вида, построить его из теста нечем. Текстовый ловит «позвали не то»,
/// и этого здесь достаточно: дефект был именно в имени функции.
///
/// Запрет, а не требование: «нет ли здесь запретного вызова» спрашивается
/// надёжно — он узнаётся по своему имени. «Есть ли нужный» спросить нельзя,
/// у показа десяток форм.
@Suite("Показ чисел анализа")
struct ПоказЧиселАнализаTests {

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()   // TogoTests
        .deletingLastPathComponent()   // Togo

    private static func текст(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Строки кода без комментариев: сторож, не различающий код и прозу,
    /// меряет прозу. У нас это уже оплачено — сторож на вызов покраснел
    /// на комментарии «// НЕ `MapsApp.allCases`», то есть наказал
    /// за объяснение, почему так делать нельзя. В этом же файле ниже
    /// `Fmt.decimal` упомянут в комментарии с причиной.
    private static func строкиКода(_ текст: String) -> [(номер: Int, строка: String)] {
        текст.split(separator: "\n", omittingEmptySubsequences: false)
            .enumerated()
            .map { (номер: $0.offset + 1, строка: String($0.element)) }
            .filter { пара in
                let обрезано = пара.строка.trimmingCharacters(in: .whitespaces)
                return !обрезано.hasPrefix("//") && !обрезано.hasPrefix("///")
                    && !обрезано.hasPrefix("*") && !обрезано.hasPrefix("/*")
            }
    }

    // MARK: Было что сторожить

    /// Первой — проверка, что сторожу было что сторожить.
    /// Набор, которому нечего проверять, молчит так же, как набор,
    /// у которого всё хорошо.
    @Test("Карточка медзаписей на месте и показывает значение анализа")
    func былоЧтоСторожить() throws {
        let исходник = try Self.текст("Togo/Features/Health/MedicalRecordCards.swift")
        let код = Self.строкиКода(исходник)
        #expect(код.count > 200, "файл подозрительно короткий — проверь путь, а не вывод")
        #expect(исходник.contains("анализ.value"),
                "карточка больше не показывает значение анализа — сторож сторожит пустоту")
        #expect(исходник.contains("анализ.belowLimit") && исходник.contains("анализ.aboveLimit"),
                "пределы прибора исчезли из показа; это отдельная находка, а не повод чинить сторожа")
    }

    // MARK: Запрет

    @Test("Показ значения анализа не идёт через округлятор веса")
    func округляторНеКрасит() throws {
        let исходник = try Self.текст("Togo/Features/Health/MedicalRecordCards.swift")
        let нарушения = Self.строкиКода(исходник)
            .filter { $0.строка.contains("Fmt.decimal") }
            .map { "  :\($0.номер) — \($0.строка.trimmingCharacters(in: .whitespaces))" }

        #expect(нарушения.isEmpty, """
            числа анализа показываются через `Fmt.decimal`, а он округляет
            до одного знака (%.1f) — это потеря данных в медицинском числе:

            \(нарушения.joined(separator: "\n"))

            Показывать через `ЧислоСБланка.показать` — он сохраняет все
            знаки и ставит запятую. `Fmt.decimal` оставлен для веса
            и счётных величин, где один знак верен.
            """)
    }

    /// **Исключение названо и сторожится, а не подразумевается.**
    /// `Fmt.decimal` в `Features/Health/` остаётся в одном месте —
    /// `VetSummaryScreen`, и там он про ВЕС в килограммах, где один знак
    /// верен («4,1 кг», а не «4,1000000001»).
    ///
    /// Запрет на весь каталог был бы шире правды и покраснел бы
    /// на верном вызове: девять ложных находок хуже одной пропущенной —
    /// после них сторожа перестают читать.
    @Test("Единственный оставшийся Fmt.decimal в «Здоровье» — про вес")
    func исключениеОстаётсяВерным() throws {
        let исходник = try Self.текст("Togo/Features/Health/VetSummaryScreen.swift")
        let строки = Self.строкиКода(исходник).filter { $0.строка.contains("Fmt.decimal") }

        #expect(строки.count == 1, """
            в VetSummaryScreen стало \(строки.count) вызовов Fmt.decimal вместо одного.
            Исключение заведено под ОДИН вызов про вес; появился второй —
            проверь, про вес ли он, и назови его здесь.
            """)
        #expect(строки.first?.строка.contains(".kg") == true, """
            вызов Fmt.decimal в VetSummaryScreen больше не про килограммы:
            \(строки.first?.строка ?? "—")
            Исключение держалось тем, что величина — вес. Условие отпало —
            снимай исключение, а не подпирай его.
            """)
    }

    // MARK: Граница

    @Test("Границы: чего этот сторож не умеет")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит: в карточке медзаписей нет вызова
            `Fmt.decimal`, и единственный такой вызов в «Здоровье»
            по-прежнему про вес. И только это.

            НЕ проверяется:
            · что человек увидит на экране. Сторож читает ИСХОДНИК —
              «значение верное, а вызов бессильный» он не видит
              по устройству, для этого нужен кадр;
            · другие округлители. Появится `Fmt.decimal2` или
              `String(format: "%.1f")` прямо в карточке — этот сторож
              промолчит: он знает одно имя, а не класс;
            · числа референса. Они сейчас не показываются ЧИСЛАМИ вовсе
              (замер 08.10: `bandBounds` идёт только в график, в текст
              карточки — лишь вердикт словом). Начнут показываться —
              их надо проверить отдельно, и этот сторож об этом
              не скажет.
            """
        #expect(границы.isEmpty == false)
        // Проверяется за минуту:
        //   grep -rn "Fmt.decimal" Togo/Features/Health/
        // Ожидается ровно одна строка — VetSummaryScreen, про кг.
    }
}
