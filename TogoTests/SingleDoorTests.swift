import Testing
import Foundation
@testable import Togo

/// Запись попадает в дневник только через `EventLog`.
///
/// На `EventLog.swift` написано: «права проверяются здесь, а не на
/// каждом экране: это **единственная дверь**, через которую в дневник
/// попадает запись». Замер 23.09.2026: дверей было **пять**.
///
/// Мимо всех трёх проверок `EventLog` — права, сторожа дубля и честного
/// ответа о несохранившемся — шли инцидент, занятие, стул и весь
/// голосовой путь. Каждый собирал `LogEvent` руками и звал
/// `context.insert` напрямую.
///
/// **Почему это не было заметно раньше.** Пока роль по умолчанию была
/// «владелец», проверка прав не меняла ничего: дверь стояла открытой,
/// и ходить мимо неё было незачем. Как только отказ стал закрывать,
/// у обхода появилась цена: гость-наблюдатель корректно получал отказ
/// на главном пути — и записывал инцидент, стул, занятие и всё голосом.
/// Хуже прочего голосовой: им пишется доза, и «дал» у того, кому
/// не разрешено, — это вторая таблетка.
///
/// Тот же класс, что «роль не трогаем вовсе»: **безопасность объявлена
/// комментарием, которому противоречит код.**
///
/// Сторож **от запрета, а не от требования**: список обходов выводится
/// из дерева и обязан быть пуст. Перечисленный руками знал бы только
/// то, что в него положили, — а находка была именно в том, чего никто
/// не перечислил.
@Suite("Дверь в дневник одна")
struct SingleDoorTests {

    /// Где заводить `LogEvent` напрямую можно, и почему.
    ///
    /// Список короткий намеренно: длинный список исключений — это
    /// сторож, который не может покраснеть.
    private static let можно: [String: String] = [
        "EventLog.swift": "сама дверь",
        "SeedData.swift": "демо-данные, человек их не пишет",
        "SharedDiaryPayloads.swift": "чужая запись, уже сделанная: отклонить её значило бы потерять данные",
        "CloudKitSchemaWarmup.swift": "отладочный прогрев схемы, только DEBUG",
        "Backup.swift": "восстановление своего архива: право спрашивать не у кого, а сторож дубля съел бы историю",
        "QuickLogIntents.swift": "голосовая дверь; спрашивает право и дубль сама — проверено ниже",
        "WalkRecorder.swift": "собирает прогулку с отметками; оба вызывающих спрашивают право — проверено ниже",
        "RecallWriter.swift": "дозапись написана и никуда не подключена — проверено ниже",
    ]

    /// Тот же текст без комментариев, строка в строку.
    ///
    /// **Заведено 08.10.2026, и заведено двумя разными ценами сразу.**
    ///
    /// `дверьОдна` вырезала комментарии у себя внутри — то есть правило
    /// знал один тест из четырёх, а остальные три читали прозу как код.
    /// Обе стороны этого ломаются, и по-разному:
    ///
    /// ```
    /// запрет (дозаписьМертва)   упоминание имени в КОММЕНТАРИИ красит
    ///                           сторожа: «дозапись подключили».
    ///                           Красный без дефекта — учит не верить
    ///                           красному
    /// требование (три проверки  комментарий «// НЕ guard можно(…)»
    /// «спрашивает право»)       УДОВЛЕТВОРЯЕТ contains → сторож зелен
    ///                           при снятом замке. Это хуже: ложная
    ///                           зелень на проверке прав
    /// ```
    ///
    /// Первая половина поймана живым случаем в тот же день: голова
    /// `RecallParser` получила абзац про то, почему дозапись не
    /// подключена, со ссылкой на соседний файл — и ссылка покрасила бы
    /// `дозаписьМертва`. Прозой, не кодом.
    ///
    /// Вторая не поймана никем и найдена чтением рядом: запрет
    /// и требование подвержены одному дефекту разбора, но обманывают
    /// в противоположные стороны, поэтому один случай нашёлся бы,
    /// а другой — нет.
    ///
    /// Разбор построчный, как и был: `/* … */` он не видит, и строка
    /// с `://` внутри обрежется. Для предмета этих проверок хватает,
    /// а полный разбор Swift здесь был бы второй реализацией компилятора.
    ///
    /// Прозу намеренно читает `обещаниеНаМесте` — ему сырой текст
    /// и нужен, и он зовёт `исходники()` напрямую.
    private func безКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    /// Исходник по имени файла, уже без комментариев.
    private func код(_ имя: String) throws -> String {
        безКомментариев(try #require(исходники().first { $0.0 == имя }?.1))
    }

    private func исходники() -> [(String, String)] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [(String, String)] = []
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(каталог), includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
                найдено.append((элемент.lastPathComponent, текст))
            }
        }
        return найдено
    }

    @Test("Никто не заводит запись дневника мимо EventLog")
    func дверьОдна() throws {
        let файлы = исходники()
        #expect(файлы.count > 50, "файлов прочитано \(файлы.count) — разбор не состоялся")

        var обходы: [String] = []
        for (имя, текст) in файлы where Self.можно[имя] == nil {
            // Комментарии не в счёт: тест, читающий рассказ о коде
            // как код, краснеет без дефекта — а красный без дефекта
            // учит не верить красному. Правило одно на все проверки
            // этого файла и живёт в `безКомментариев`, а не копией здесь.
            let строки = безКомментариев(текст).components(separatedBy: .newlines)
            for (номер, строка) in строки.enumerated() {
                guard строка.contains("LogEvent(kind:") else { continue }
                обходы.append("  \(имя):\(номер + 1) — \(строка.trimmingCharacters(in: .whitespaces))")
            }
        }

        #expect(обходы.isEmpty, """
            запись дневника заводится мимо `EventLog`:

            \(обходы.joined(separator: "\n"))

            Мимо проходят все три проверки разом: право, сторож дубля
            и честный ответ о несохранившемся. Заводи через
            `EventLog.record(_:dog:confirmation:)` — у него есть
            `configure:` для своих полей и возвращаемое значение,
            если запись нужна дальше.
            """)
    }

    /// Голосовой путь — четвёртая дверь, и своя: у интента нет
    /// `AppState`, поэтому право он спрашивает у карточки участника.
    @Test("Голосовой путь спрашивает право")
    func голосСпрашиваетПраво() throws {
        let исходник = try код("QuickLogIntents.swift")
        #expect(исходник.contains("guard можно("), """
            `QuickLog.record` пишет в дневник, не спросив права.
            Это единственный путь, которым доза попадает в дневник
            без экрана, и «дал голосом» у того, кому не разрешено, —
            это вторая таблетка.
            """)
        #expect(исходник.contains("DuplicateGuard.recent("),
                "голосовой путь не спрашивает о дубле")
    }

    /// Комментарий про единственную дверь обязан остаться правдой —
    /// или исчезнуть вместе с правилом.
    @Test("Обещание единственной двери записано там, где дверь")
    func обещаниеНаМесте() throws {
        let исходник = try #require(исходники().first { $0.0 == "EventLog.swift" }?.1)
        #expect(исходник.contains("дверь, через которую в дневник попадает запись"), """
            из `EventLog` исчезло обещание единственной двери.
            Если правило отменили — убери и этот тест; если нет —
            верни обещание туда, где его читают.
            """)
    }

    /// Вторая дверь прогулки — голосовая, и у неё свой замок.
    @Test("Голосовая прогулка спрашивает право")
    func прогулкаГолосомСпрашиваетПраво() throws {
        let исходник = try код("WalkIntents.swift")
        #expect(исходник.contains("QuickLog.можно(.walk"), """
            голосовая прогулка пишется мимо права. Экранная спрашивает
            его через `EventLog`, а здесь запись собирает `WalkRecorder`,
            и замка не было.
            """)
    }

    /// Причина, по которой `RecallWriter` в исключениях, — он мёртв.
    /// Если его подключат, исключение перестанет быть верным, и об этом
    /// должен узнать тот, кто подключает, а не тот, кто потом ищет дыру.
    @Test("Дозапись по-прежнему никуда не подключена")
    func дозаписьМертва() {
        let зовут = исходники()
            .filter { $0.0 != "RecallWriter.swift" }
            // Комментарии вырезаются: 08.10 абзац в голове `RecallParser`
            // про то, ПОЧЕМУ дозапись не подключена, сослался на соседний
            // файл по имени — и покрасил бы этот сторож прозой.
            .filter { безКомментариев($0.1).contains("RecallWriter.") }
            .map(\.0)
            .sorted()
        #expect(зовут.isEmpty, """
            `RecallWriter` подключили: \(зовут).

            Он заводит записи напрямую и стоит в исключениях именно
            потому, что не звался ниоткуда. Теперь либо проведи его
            через `EventLog`, либо спроси право у вызывающего —
            и перепиши причину исключения.
            """)
    }

    @Test("У каждого исключения двери в дневник есть причина и оно существует")
    func исключенияЧестные() {
        let имена = Set(исходники().map(\.0))
        for (файл, причина) in Self.можно {
            #expect(!причина.isEmpty, "\(файл): исключение без причины")
            #expect(имена.contains(файл), "\(файл) в исключениях, а файла нет — список протух")
        }
        #expect(Self.можно.count <= 8,
                "исключений \(Self.можно.count): длинный список — сторож, который не может покраснеть")
    }
}
