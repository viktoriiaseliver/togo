/// Контраст в четырёх режимах — числом, а не глазами.
///
/// **Почему этот набор мерит `Token.*`, а не `Dyn`.** Спрашивая `Dyn`,
/// он сверял бы наши же четыре числа с нашими же четырьмя числами, то
/// есть мерил бы себя. Он спрашивает `Token.Status.stockLowText` —
/// `Color`, который возьмёт экран, — и разрешает его против
/// `UITraitCollection`, как это сделает система. У нас записано:
/// **проверять одну реализацию наблюдениями за другой нельзя.**
///
/// **Первым идёт не замер, а проверка собственного зрения.** Ноль
/// непроходящих при четырёх режимах подозрителен так же, как «все
/// четырнадцать из четырнадцати»: и край диапазона, и круглое число —
/// симптомы инструмента. Поэтому сначала счётчик обязан воспроизвести
/// **известное непрохождение** из `docs/контраст-graphite.md`, снятое
/// другой сессией другим инструментом (по CSS пакета, а не по нашим
/// токенам). Не воспроизвёл — мерю себя, а не мир, и остальные числа
/// читать нельзя.
///
/// **Граница, названная вслух.** Это замер ЗНАЧЕНИЙ, а не кадра.
/// «Значение верное, а вызов бессильный» он не ловит: `opacity` на
/// тексте и перекрытие цвета стилем видно только на пикселе — так
/// `AppFont` однажды победил `foregroundStyle` предка, и главная кнопка
/// давала 1,68:1 при верном токене. Ещё он ничего не говорит про
/// виджет, «остров» и карточку Live Activity: трейты там системные,
/// и тема в них не наша.
@MainActor
@Suite("Контраст в четырёх режимах")
struct ThemeContrastTests {

    // MARK: Режимы

    struct Режим: Sendable {
        let имя: String
        let тёмная: Bool
        let контраст: Bool
    }

    static let режимы = [
        Режим(имя: "Dark", тёмная: true, контраст: false),
        Режим(имя: "Light", тёмная: false, контраст: false),
        Режим(имя: "Dark HC", тёмная: true, контраст: true),
        Режим(имя: "Light HC", тёмная: false, контраст: true),
    ]

    // MARK: Пары

    /// Пара «что на чём», порог и роль.
    ///
    /// Порог берётся у роли, а не у вкуса: текст — 4,5 (WCAG 1.4.3),
    /// крупный текст и графический элемент — 3,0 (1.4.11). Роль
    /// написана словами, потому что по именам токенов её не восстановить:
    /// `bar` это косточка, а не подпись, и порог у неё другой.
    struct Пара: Sendable {
        let что: Color
        let на: Color
        let порог: Double
        let роль: String
    }

    static let пары: [Пара] = [
        .init(что: Token.Ink.primary, на: Token.Surface.screen, порог: 4.5, роль: "основной текст на фоне"),
        .init(что: Token.Ink.primary, на: Token.Surface.card, порог: 4.5, роль: "основной текст на карточке"),
        .init(что: Token.Ink.secondary, на: Token.Surface.card, порог: 4.5, роль: "вторичный текст на карточке"),
        .init(что: Token.Action.primary, на: Token.Surface.screen, порог: 3.0, роль: "акцентная заливка на фоне"),
        .init(что: Token.Status.overdueText, на: Token.Surface.card, порог: 4.5, роль: "просрочка словами"),
        .init(что: Token.Status.overdueText, на: Token.Status.overdueBg, порог: 4.5, роль: "просрочка на своей плашке"),
        .init(что: Token.Status.waitingText, на: Token.Surface.card, порог: 4.5, роль: "«ждём» словами"),
        .init(что: Token.Status.stockLowText, на: Token.Surface.card, порог: 4.5, роль: "запас ≤7 дней, текст на карточке"),
        .init(что: Token.Status.stockLowText, на: Token.Status.stockLowBg, порог: 4.5, роль: "запас ≤7 дней на своей плашке"),
        .init(что: Token.Poster.label, на: Token.Poster.background, порог: 4.5, роль: "подпись плаката"),
        .init(что: Token.Poster.labelOnDose, на: Token.Poster.backgroundDose, порог: 4.5, роль: "подпись плаката на дозе — ИНВЕРСИЯ"),
    ]

    /// Непрохождения, **измеренные и названные**, с числом и хозяином.
    ///
    /// Не порог и не исключение: порог впитал бы следующее молча. Ключ —
    /// «роль · режим», значение — измеренное сегодня. Стало ХУЖЕ —
    /// краснеет; стало лучше — краснеет тоже, потому что запись устарела
    /// и её надо снять, иначе в неё можно вернуть дефект.
    ///
    /// Оба пришли из пакета Graphite вместе со светлой темой, и оба
    /// названы в `docs/контраст-graphite.md` до меня: `#B85400` —
    /// светлое значение `--stock-low`, и повышенный контраст его
    /// **не трогает**, потому что у продуктового слоя нет HC-блока.
    /// Это пробел ПАКЕТА, и хозяин ему — не светлая тема, а дизайн.
    static let известныеНепрохождения: [String: Double] = [
        "запас ≤7 дней, текст на карточке · Light": 4.1657,
        "запас ≤7 дней, текст на карточке · Light HC": 4.1657,
        "запас ≤7 дней на своей плашке · Light": 4.2119,
        "запас ≤7 дней на своей плашке · Light HC": 4.2119,
    ]

    // MARK: Проверки

    @Test("Счётчик воспроизводит известное непрохождение аудита")
    func инструментВидитИзвестное() throws {
        // `--stock-low` на `--bg-primary` в светлой: аудит другой сессии
        // по CSS пакета дал 4,17. Если здесь выйдет другое — сломан
        // либо разбор режимов, либо разрешение цвета, и ни одно число
        // ниже читать нельзя.
        let измерено = Self.контраст(Token.Status.stockLowText,
                                     на: Token.Surface.card,
                                     режим: Self.режимы[1])
        #expect(abs(измерено - 4.1657) < 0.01, """
            счётчик дал \(Self.два(измерено)) там, где аудит пакета дал 4,17.
            Это проверка МОЕГО зрения, а не проекта: расхождение значит,
            что сломано разрешение режима или разбор цвета.
            docs/контраст-graphite.md, строка «4,17 --stock-low / --bg-primary».
            """)

        // И второй край: тот же токен в тёмной обязан быть ВЫШЕ порога.
        // Без него проверка прошла бы и у счётчика, который всегда
        // возвращает 4,1657.
        let тёмный = Self.контраст(Token.Status.stockLowText,
                                   на: Token.Surface.card,
                                   режим: Self.режимы[0])
        #expect(тёмный > 8.0, """
            в тёмной тот же токен дал \(Self.два(тёмный)) — ожидалось больше 8.
            Счётчик, возвращающий одно число во всех режимах, прошёл бы
            проверку выше и не прошёл эту.
            """)
    }

    @Test("Каждая пара проходит порог в каждом из четырёх режимов")
    func всеПарыВоВсехРежимах() throws {
        var провалы: [String] = []
        var устаревшие: [String] = []
        var осмотрено = 0

        for пара in Self.пары {
            for режим in Self.режимы {
                осмотрено += 1
                let k = Self.контраст(пара.что, на: пара.на, режим: режим)
                let ключ = "\(пара.роль) · \(режим.имя)"
                if let записано = Self.известныеНепрохождения[ключ] {
                    if k < записано - 0.01 {
                        провалы.append("  \(ключ): \(Self.два(k)) — было \(Self.два(записано)), стало ХУЖЕ")
                    } else if k > записано + 0.01 {
                        устаревшие.append("  \(ключ): \(Self.два(k)) при записанных \(Self.два(записано)) — починено, убери из списка")
                    }
                    continue
                }
                if k < пара.порог {
                    провалы.append("  \(ключ): \(Self.два(k)) при пороге \(Self.два(пара.порог))")
                }
            }
        }

        #expect(осмотрено == Self.пары.count * Self.режимы.count, """
            осмотрено \(осмотрено) пар·режимов из \(Self.пары.count * Self.режимы.count).
            Набору, которому нечего проверять, молчать так же легко,
            как набору, у которого всё хорошо.
            """)

        #expect(провалы.isEmpty, """
            контраст ниже порога в \(провалы.count) парах·режимах:

            \(провалы.joined(separator: "\n"))

            Порог у роли, а не у вкуса: текст 4,5 (WCAG 1.4.3), графика
            и крупный текст 3,0 (1.4.11). Правку порога починкой считать
            нельзя.
            """)

        #expect(устаревшие.isEmpty, """
            записанные непрохождения стали лучше — список протух:

            \(устаревшие.joined(separator: "\n"))

            Запись, пережившая свой дефект, разрешает вернуть его обратно.
            """)

        print("""
            ГРАНИЦА: мерены ЗНАЧЕНИЯ токенов, разрешённые системой, \
            \(Self.пары.count) пар × \(Self.режимы.count) режима.
            НЕ мерено: `opacity` и перекрытие стилем (видно только на пикселе),
            виджет, «остров» и Live Activity (трейты там системные),
            и любая пара, которой нет в списке выше — список составлен руками.
            Ноль провалов — «эти \(Self.пары.count) пар целы», а не «контраст в порядке».
            """)
    }

    // MARK: Счёт

    /// Контраст по WCAG 2.1 между двумя разрешёнными цветами.
    ///
    /// Полупрозрачное **накладывается**, а не берётся как есть:
    /// `#666` под `opacity(0.85)` это уже `#7D7D7D` и 4,12:1. Считать
    /// надо composited-пару — цвет поверх своего фона после наложения.
    /// Фон, если он сам полупрозрачен, накладывается на страницу.
    static func контраст(_ что: Color, на фон: Color, режим: Режим) -> Double {
        let страница = Self.rgba(Token.Surface.screen, режим)
        let ф = Self.наложить(Self.rgba(фон, режим), на: страница)
        let ч = Self.наложить(Self.rgba(что, режим), на: ф)
        let l1 = Self.яркость(ч), l2 = Self.яркость(ф)
        return (max(l1, l2) + 0.05) / (min(l1, l2) + 0.05)
    }

    private static func rgba(_ цвет: Color, _ режим: Режим) -> (Double, Double, Double, Double) {
        #if canImport(UIKit)
        let hex = цвет.resolvedHex(dark: режим.тёмная, highContrast: режим.контраст)
        return (Double((hex >> 24) & 0xFF) / 255, Double((hex >> 16) & 0xFF) / 255,
                Double((hex >> 8) & 0xFF) / 255, Double(hex & 0xFF) / 255)
        #else
        return (0, 0, 0, 1)
        #endif
    }

    private static func наложить(_ верх: (Double, Double, Double, Double),
                                 на низ: (Double, Double, Double, Double))
        -> (Double, Double, Double, Double) {
        let a = верх.3
        return (верх.0 * a + низ.0 * (1 - a),
                верх.1 * a + низ.1 * (1 - a),
                верх.2 * a + низ.2 * (1 - a),
                1)
    }

    private static func яркость(_ c: (Double, Double, Double, Double)) -> Double {
        func лин(_ x: Double) -> Double {
            x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4)
        }
        return 0.2126 * лин(c.0) + 0.7152 * лин(c.1) + 0.0722 * лин(c.2)
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }
}
