/// Плашка контрола и утопленная область — разные цвета.
///
/// # Что здесь сторожат и чьим словом
///
/// Прямой ответ дизайна 23.10.2026 на наш вопрос, дословно:
/// «`surface-control` #3A3A3C, нажатие #48484A. `surface-sunken`
/// остаётся #2C2C2E. **Совпадение не задумано**»
/// (`Дизайн/редизайн-ios28/README.md`, раздел «Решения по вопросам
/// разработки», пункт 2). То есть ось здесь не моя и не из WCAG:
/// порога у пары «две поверхности» не назвал никто, а равенство байт
/// назвал дизайн.
///
/// # Ось — РАВЕНСТВО БАЙТ, а не порог
///
/// Та же причина, что у соседей `плашкаВыключеннойСуществует`
/// и `плашкаВторостепеннойСуществует`: порог ≥3:1 на паре поверхностей
/// не норма ничья — WCAG 1.4.11 говорит про границы интерактивных
/// элементов, а не про две заливки рядом, — и следующий снял бы пару
/// целиком вместе с дефектом. Равенство байт при этом не спорно:
/// одинаковые — значит на экране не различить ничем.
///
/// # Сторож проверен на БОЛЬНОМ коде, а не только на здоровом
///
/// До правки 23.10.2026 обе роли давали в тёмной `#2C2C2E` байт в байт
/// (`git show 0a369c0:DesignTokens/tokens.json`, `night3.dark` и
/// `night4.dark`), то есть этот набор на вчерашнем дереве краснел бы
/// в двух режимах из четырёх. Контроль того же замера: `night3.dark`
/// после правки остался `#2C2C2E` — значит различие не померещилось
/// разборщику.
///
/// ```
///                    Surface.control   Surface.sunken
/// Dark     до 23.10       #2C2C2E          #2C2C2E   СЛИПЛИСЬ
/// Dark HC  до 23.10       #2C2C2E          #2C2C2E   СЛИПЛИСЬ
/// Dark     после          #3A3A3C          #2C2C2E   ✓
/// Dark HC  после          #48484A          #363638   ✓
/// Light    и до и после   #FFFFFF          #E3E5E8   ✓
/// Light HC и до и после   #FFFFFF          #E3E5E8   ✓
/// ```
///
/// # Чего этот набор НЕ видит
///
/// Он мерит ЗНАЧЕНИЯ, разрешённые системой, а не пиксель. Плашку,
/// нарисованную `opacity` поверх, или стекло над фото он не поймает —
/// это видно только на кадре. И он ничего не говорит о светлой теме
/// по существу: там `Surface.control` равен `#FFFFFF`, то есть ровно
/// фону экрана, и плашки не существует вовсе — отдельный дефект
/// с хозяином, он сторожится в `ПовышенныйКонтрастМеняетЦветTests`.
@MainActor
@Suite("Плашка контрола и утопленная область различимы")
struct ПлашкиКонтролаTests {

    struct Режим: Sendable {
        let имя: String
        let тёмная: Bool
        let контраст: Bool
    }

    static let режимы = [
        Режим(имя: "Dark", тёмная: true, контраст: false),
        Режим(имя: "Light", тёмная: false, контраст: false),
        Режим(имя: "Dark HC", тёмная: true, контраст: true),
        Режим(имя: "Light HC", тёмная: false, контраст: true),
    ]

    /// Ноль найденного при нуле осмотренного — это «нечего было
    /// смотреть», а не «чисто».
    @Test("Было что сторожить: четыре режима различимы, разрешитель живой")
    func былоЧтоСторожить() throws {
        #expect(Self.режимы.count == 4, """
            режимов \(Self.режимы.count), ожидалось 4 — сломан список,
            и ни одно число ниже читать нельзя.
            """)

        // Положительный контроль: пара, заведомо РАЗЛИЧАЮЩАЯСЯ во всех
        // четырёх (фон экрана против карточки). Разрешитель, отдающий
        // одно и то же всегда, здесь провалится.
        for режим in Self.режимы {
            #expect(Self.байты(Token.Surface.screen, режим)
                    != Self.байты(Token.Surface.card, режим), """
                `Surface.screen` и `Surface.card` совпали в режиме
                \(режим.имя) — это заведомо разные значения, значит
                отвечает разрешитель, а не токены.
                """)
        }

        // Отрицательный контроль: пара, заведомо СОВПАДАЮЩАЯ — `sunken`
        // и `raised` сидят на одном примитиве `night3` нарочно (роли
        // разные, значение одно, так и в хендоффе). Разрешитель, который
        // всегда отвечает «различается», провалится тут.
        for режим in Self.режимы {
            #expect(Self.байты(Token.Surface.sunken, режим)
                    == Self.байты(Token.Surface.raised, режим), """
                `Surface.sunken` и `Surface.raised` разошлись в режиме
                \(режим.имя). Они обязаны совпадать по значению: один
                примитив `night3`, и у хендоффа `raised` и `sunken` —
                одно число в обеих шкалах. Разошлись — значит кто-то
                развёл их, не сказав, или сломан разрешитель.
                """)
        }
    }

    @Test("Плашка контрола не равна утопленной области ни в одном режиме")
    func контролНеРавенУтопленному() throws {
        var слиплись: [String] = []
        var замеры: [String] = []

        for режим in Self.режимы {
            let контрол = Self.байты(Token.Surface.control, режим)
            let утопленное = Self.байты(Token.Surface.sunken, режим)
            замеры.append("\(режим.имя): контрол \(Self.hex(контрол)) · "
                          + "утопленное \(Self.hex(утопленное))")
            if контрол == утопленное { слиплись.append(режим.имя) }
        }

        #expect(замеры.count == 4, "осмотрено режимов \(замеры.count), ожидалось 4.")

        #expect(слиплись.isEmpty, """
            ПЛАШКА КОНТРОЛА СОВПАЛА С УТОПЛЕННОЙ ОБЛАСТЬЮ байт в байт
            в режимах: \(слиплись.joined(separator: ", ")).

            Замеры: \(замеры.joined(separator: " · ")).

            Это прямое слово дизайна от 23.10.2026, а не наш вкус:
            «`surface-control` #3A3A3C, нажатие #48484A. `surface-sunken`
            остаётся #2C2C2E. Совпадение не задумано».

            ЧТО НЕ ВИДИТ ЧЕЛОВЕК, когда они слиплись: на «Сегодня»
            кружок категории в ожидании (CategoryBadge.swift:133)
            и утопленная область ленты — одна заливка; ползунок
            прогулки (WalkControls.swift:93) теряет дорожку.

            ПОЧИНКА — значение примитива `night4` в `DesignTokens/
            tokens.json`, не вёрстка. `Surface.sunken` НЕ ТРОГАТЬ:
            дизайн сказал, что он остаётся #2C2C2E, и за ним 22 места
            показа против 4 у контрола.
            """)
    }

    // MARK: Счёт

    /// `0xRRGGBBAA`, как его отдаст система тому, кто рисует.
    ///
    /// Спрашивается у `Color`, а не у `Dyn`: сторож, спрашивающий `Dyn`,
    /// сверял бы наши четыре числа с нашими же четырьмя, то есть мерил
    /// бы себя.
    static func байты(_ цвет: Color, _ режим: Режим) -> UInt32 {
        цвет.resolvedHex(dark: режим.тёмная, highContrast: режим.контраст)
    }

    static func hex(_ v: UInt32) -> String {
        String(format: "#%08X", v >> 8)
    }
}

/// Выключенная кнопка и второстепенная — разные цвета.
///
/// # ЭТОТ НАБОР РОЖДЁН КРАСНЫМ, И ЭТО НАЗВАНО, А НЕ УМОЛЧАНО
///
/// Он лежит отдельно от соседа сверху по той же причине, по которой
/// `ПовышенныйКонтрастМеняетЦветTests` лежит отдельно от
/// `ThemeContrastTests`: единица блокировки подделки — **НАБОР**,
/// а не запись (`check_guard.py:102` судит кодом возврата `xcodebuild
/// test -only-testing:<набор>`). Положи я эти два теста рядом —
/// я погасил бы возможность подделки у зелёного соседа, то есть
/// заплатил бы чужим сторожем за своего. Цена своего набора названа:
/// `make guard` здесь невозможен, пока запись красная.
///
/// # Что сломалось и кто его сломал
///
/// Сломал его я, 23.10.2026, и у поломки есть причина, а не оплошность.
/// Разводя `surface.control` с `surface.sunken` по слову дизайна,
/// `night4.dark` ушёл с `#2C2C2E` на `#3A3A3C` — а `#3A3A3C` это
/// значение `night5`, на котором через `semantic.surface.pressed`
/// сидит `component.button.disabled.background`.
///
/// ```
///                       Secondary.background   Disabled.background
/// Dark     до 23.10            #2C2C2E               #3A3A3C   ✓
/// Dark     после               #3A3A3C               #3A3A3C   СЛИПЛИСЬ
/// Dark HC  после               #48484A               #48484A   СЛИПЛИСЬ
/// Light    до и после          #FFFFFF               #D7DBE0   ✓
/// Light HC до и после          #FFFFFF               #D6D9DD   ✓
/// ```
///
/// **Разводили одну пару — свели другую.** 15.10.2026 Виктория увела
/// `Disabled.background` с `surface.control` на `surface.pressed`
/// ровно затем, чтобы выключенная кнопка не сливалась с плашкой
/// контрола. Её решение не отменено — отменено расстояние, на котором
/// оно держалось: в поколении Graphite `control` и `pressed` отличались
/// на ступень, в «Кино» хендофф даёт им ОДНО значение (`cinema.surface.
/// control` = `cinema.surface.pressed` = #3A3A3C).
///
/// # Готовый ответ есть, и он не мой
///
/// Та же присланная шкала даёт `cinema.surface.controlPressed`
/// (#48484A, HC #5A5A5E) — ступень выше `pressed`. Роль заведена
/// 23.10 как `Token.Surface.controlPressed` и **читателей у неё ноль**.
/// Перевести `Disabled.background` на неё — одна строка в `tokens.json`,
/// и этого хватит. Но **цвет кнопки — решение Виктории, а не
/// исполнителя**: ровно так это записано у соседних красных
/// (`ПовышенныйКонтрастМеняетЦветTests`, оба теста). Поэтому здесь
/// замер и запись, а не правка.
///
/// ХОЗЯИН: Виктория. ЧТО ДЕРЖИТ: вопрос «куда уводим выключенную
/// кнопку» не задан. В эталон прогона эта запись НЕ ВПИСАНА нарочно —
/// у неё нет хозяина, пока её не спросили, а «не спросили» значит
/// «не спросили», а не «нет».
///
/// # Чего этот набор НЕ видит
///
/// Цвет — не единственный признак выключенного: подпись выключенной
/// кнопки красится `Ink.secondary` против собственной подписи
/// второстепенной, и `.disabled(true)` снимает нажатие. Значит красное
/// здесь означает «ЗАЛИВКОЙ не различить», а не «не различить никак».
/// Снимать его по кадру, а не по рассуждению.
@MainActor
@Suite("Выключенная и второстепенная кнопки различимы")
struct ВыключеннаяИВторостепеннаяTests {

    @Test("Плашка выключенной кнопки не равна плашке второстепенной")
    func выключеннаяНеРавнаВторостепенной() throws {
        var слиплись: [String] = []
        var замеры: [String] = []

        for режим in ПлашкиКонтролаTests.режимы {
            let второстепенная = ПлашкиКонтролаTests
                .байты(Token.Component.Button.Secondary.background, режим)
            let выключенная = ПлашкиКонтролаTests
                .байты(Token.Component.Button.Disabled.background, режим)
            замеры.append("\(режим.имя): второстепенная "
                          + "\(ПлашкиКонтролаTests.hex(второстепенная)) · выключенная "
                          + "\(ПлашкиКонтролаTests.hex(выключенная))")
            if второстепенная == выключенная { слиплись.append(режим.имя) }
        }

        #expect(замеры.count == 4, "осмотрено режимов \(замеры.count), ожидалось 4.")

        #expect(слиплись.isEmpty, """
            ПЛАШКА ВЫКЛЮЧЕННОЙ КНОПКИ СОВПАЛА С ПЛАШКОЙ ВТОРОСТЕПЕННОЙ
            байт в байт в режимах: \(слиплись.joined(separator: ", ")).

            Замеры: \(замеры.joined(separator: " · ")).

            ЧТО НЕ ВИДИТ ЧЕЛОВЕК. На «Сегодня» кнопка «Гулять»
            (ActionGrid.swift:147, isPrimary: false) и любая кнопка,
            которую экран выключил, нарисованы одной заливкой.
            Нажимаемое и ненажимаемое выглядят одинаково — он узнаёт
            разницу только нажав, и только по тому, что ничего
            не произошло.

            ОТКУДА ЭТО ВЗЯЛОСЬ: 23.10.2026 `night4.dark` ушёл с #2C2C2E
            на #3A3A3C, разводя `Surface.control` с `Surface.sunken`
            по прямому слову дизайна. #3A3A3C — это значение `night5`,
            на котором сидит `Disabled.background` с 15.10.2026.
            Разводили одну пару — свели другую.

            ГОТОВЫЙ ОТВЕТ ЕСТЬ И ЖДЁТ СЛОВА: `Token.Surface.controlPressed`
            (`cinema.surface.controlPressed` #48484A, HC #5A5A5E) заведён
            23.10 и читателей не имеет. Перевод `Disabled.background`
            на него — одна строка в `DesignTokens/tokens.json`.

            НЕ ЯВЛЯЕТСЯ ПОЧИНКОЙ: вернуть `night4` на #2C2C2E. Тогда
            снова слипнутся плашка контрола и утопленная область —
            то, что дизайн 23.10 велел развести, и то, за чем стоит
            22 места показа.

            ХОЗЯИН — Виктория: значение цвета её решение, не исполнителя.
            Исполнителю здесь принадлежит замер и эта запись.
            """)
    }

    /// Печатается всегда, и нарочно в зелёном тесте: границы, лежащие
    /// только в доккомментарии, читает тот, кто открыл файл, а числа
    /// из лога читает тот, кто смотрит прогон, — это разные люди.
    @Test("Границы этих двух наборов названы")
    func границыНазваны() {
        print("""
            ГРАНИЦЫ НАБОРОВ «плашки контрола»:

            МЕРЕНО   значения токенов, разрешённые системой через
                     Color.resolvedHex, 4 режима, ось — равенство байт.
                     Две пары: контрол против утопленного (зелёная,
                     слово дизайна 23.10) и выключенная кнопка против
                     второстепенной (КРАСНАЯ, хозяин Виктория).

            НЕ МЕРЕНО
              пиксель        opacity поверх заливки и стекло над фото
                             видно только на кадре
              форма и текст  выключенность несёт и подпись, и отсутствие
                             отклика; красное значит «заливкой
                             не различить»
              светлая тема   `Surface.control` там равен #FFFFFF, то есть
                             фону экрана: плашки нет вовсе. Это другой
                             дефект, с хозяином, и сторожит его
                             `ПовышенныйКонтрастМеняетЦветTests`
              виджет, «остров», Live Activity — трейты там системные

            ПОДДЕЛКА. У первого набора она возможна и проверена логикой:
            на дереве до 23.10.2026 (`0a369c0`) `night3.dark` и
            `night4.dark` были оба #2C2C2E, то есть набор краснел бы
            в Dark и Dark HC. У второго подделка НЕВОЗМОЖНА, пока
            запись красная, — единица блокировки у `check_guard.py`
            это НАБОР, и поэтому наборы разведены по разным `@Suite`.
            """)
    }
}
