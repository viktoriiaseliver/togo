/// «Сегодня ужин в 22:00» — разовое исключение кормления на одни сутки.
///
/// # Чем оплачено
///
/// Отзыв 30.10.2026, сборка 289: «пусть приложение предложит либо
/// сдвинуть ужин пропорционально, или недокормить ужин, или кормить
/// по расписанию». Первая ветка на её расписании **пустая**, и это
/// замер 04.11 настоящим `MealSchedule`: последнее кормление сжатого
/// расписания стоит ровно на пределе `latestMeal` = отбой − 90 мин,
/// и двигать его вперёд некуда по устройству.
///
/// Решение Виктории 04.11.2026, прямым ответом: разовое исключение
/// **на дату**, два поля на `Dog`, схему править разрешено.
///
/// # Что здесь проверяется
///
/// Три разных предмета, и путать их нельзя:
///
/// ```
/// Dog.часыКормленийНа(_:)      подмена и ОТБРАСЫВАНИЕ чужого дня
/// DayPlanBuilder               что подмена доезжает до того, что видят
/// обмен и архив                что исключение видит второй человек
/// ```
///
/// Второе отдельно от первого не ради изоляции: без него поля были бы
/// «объявлены и пусты» — грепом находятся, выглядят подключёнными,
/// а входа в них не проверял бы никто.
@Suite("Разовое исключение кормления")
struct РазовоеИсключениеКормленияTests {

    /// Её расписание из отзыва, в минутах от полуночи.
    private static let ЕЁ_ЧАСЫ = [570, 930, 1290]   // 09:30 · 15:30 · 21:30
    private static let УЖИН_В_22 = 22 * 60

    private func сутки(_ сдвигДней: Int = 0) -> Date {
        let начало = Calendar.current.startOfDay(for: Date())
        return Calendar.current.date(byAdding: .day, value: сдвигДней, to: начало)!
    }

    private func стич() -> Dog {
        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.mealsPerDay = 3
        dog.mealTimes = Self.ЕЁ_ЧАСЫ
        dog.wakeMinuteOfDay = 9 * 60
        dog.sleepMinuteOfDay = 23 * 60
        return dog
    }

    // MARK: Контроль первым

    /// Без исключения читатель отдаёт расписание — и это **контроль,
    /// а не проверка расписания**.
    ///
    /// Сломайся `часыКормленийНа(_:)` в любую сторону, и все проверки
    /// ниже меряли бы собственный промах: «вернул расписание» читается
    /// как «исключения нет» и при неработающем методе тоже.
    @Test("Без исключения отдаётся расписание")
    func безИсключенияРасписание() {
        #expect(стич().часыКормленийНа(сутки()) == Self.ЕЁ_ЧАСЫ)
    }

    /// То, ради чего поле вообще заведено.
    @Test("Исключение этих суток подменяет расписание целиком")
    func исключениеПодменяет() {
        let dog = стич()
        dog.разовыеВременаДата = сутки()
        dog.разовыеВремена = [570, 930, Self.УЖИН_В_22]

        #expect(dog.часыКормленийНа(сутки()) == [570, 930, Self.УЖИН_В_22])
        #expect(dog.естьРазовоеИсключение(сутки()))
        #expect(dog.mealTimes == Self.ЕЁ_ЧАСЫ, """
            расписание изменилось. Исключение разовое: завтра собака \
            ест по-прежнему, и `mealTimes` трогать нельзя — иначе \
            «сегодня» молча станет «всегда».
            """)
    }

    /// Срок жизни «до конца суток» держится ЧИТАТЕЛЕМ, а не чистилкой.
    ///
    /// Чистилки по таймеру нет намеренно: это вторая механика, и её
    /// пришлось бы сторожить отдельно. Проверяется поэтому именно то,
    /// что делает срок настоящим, — что вчерашнее исключение не влияет
    /// на сегодня, а сегодняшнее не влияет на завтра.
    @Test("Чужой день отбрасывается: вчерашнее и завтрашнее исключение не действуют")
    func чужойДеньОтбрасывается() {
        let вчерашнее = стич()
        вчерашнее.разовыеВременаДата = сутки(-1)
        вчерашнее.разовыеВремена = [570, 930, Self.УЖИН_В_22]
        #expect(вчерашнее.часыКормленийНа(сутки()) == Self.ЕЁ_ЧАСЫ, """
            вчерашнее исключение действует сегодня. Так «сегодня ужин \
            в 22:00» становится постоянным расписанием, которого никто \
            не ставил, — и узнают об этом не раньше, чем собака \
            останется без ужина в свой час.
            """)
        #expect(вчерашнее.естьРазовоеИсключение(сутки()) == false)

        let сегодняшнее = стич()
        сегодняшнее.разовыеВременаДата = сутки()
        сегодняшнее.разовыеВремена = [570, 930, Self.УЖИН_В_22]
        #expect(сегодняшнее.часыКормленийНа(сутки(1)) == Self.ЕЁ_ЧАСЫ)

        // Контроль того же замера: на СВОЙ день оно действует. Без него
        // обе строки выше проходили бы и у метода, который не умеет
        // подменять вовсе.
        #expect(сегодняшнее.часыКормленийНа(сутки()) == [570, 930, Self.УЖИН_В_22])
    }

    /// Пустой список часов при заполненной дате — это «исключения нет»,
    /// а не «сегодня не кормить».
    ///
    /// Такой записи человек не создаёт; возникнуть она может от чужого
    /// снимка, от архива, от полуудавшейся правки. Голодный день
    /// по умолчанию — не то, что приложение вправе выдумать.
    @Test("Пустые часы при заполненной дате значат «исключения нет»")
    func пустыеЧасыНеГолодныйДень() {
        let dog = стич()
        dog.разовыеВременаДата = сутки()
        dog.разовыеВремена = []
        #expect(dog.часыКормленийНа(сутки()) == Self.ЕЁ_ЧАСЫ)
        #expect(dog.естьРазовоеИсключение(сутки()) == false)
    }

    /// **Зачем исключение вообще нужно, числом.**
    ///
    /// Ветка «сдвинуть пропорционально» упирается в предел расписания;
    /// слово человека его пробивает. Если однажды этот тест покраснеет
    /// на первой строке, значит предел сменился — и тогда надо
    /// перечитать развилку в `РазовыйЧасКормленияSheet`, а не чинить
    /// число здесь.
    @Test("Названный человеком час пробивает предел расписания")
    func часПробиваетПредел() {
        let dog = стич()
        let предел = MealSchedule.latestMeal(wake: dog.wakeMinuteOfDay,
                                             sleep: dog.sleepMinuteOfDay)
        #expect(предел == 21 * 60 + 30, """
            предел расписания стал \(предел) вместо 1290. Развилка \
            шторки стоит на том, что последнее кормление упирается \
            в него и двигать его вперёд автоматикой некуда.
            """)
        #expect(Self.УЖИН_В_22 > предел, "22:00 обязано быть ЗА пределом, иначе исключение не нужно")

        dog.разовыеВременаДата = сутки()
        dog.разовыеВремена = [570, 930, Self.УЖИН_В_22]
        #expect(dog.часыКормленийНа(сутки()).last == Self.УЖИН_В_22, """
            читатель обрезал названный человеком час по пределу \
            расписания. Тогда исключение не делает ровно того, ради \
            чего заведено.
            """)
    }
}

/// Подмена доезжает до того, что человек видит.
///
/// Отдельный набор, потому что предмет другой: выше проверялась
/// модель, здесь — что **сборщик плана дня её спрашивает**. Поле
/// с нулём читателей грепом находится один раз, в объявлении,
/// и выглядит подключённым.
@Suite("Исключение доезжает до плана дня")
@MainActor
struct ИсключениеВПланеДняTests {

    private func время(_ минута: Int) -> Date {
        Calendar.current.date(byAdding: .minute, value: минута,
                              to: Calendar.current.startOfDay(for: Date()))!
    }

    private func стич() -> Dog {
        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.mealsPerDay = 3
        dog.mealTimes = [570, 930, 1290]            // 09:30 · 15:30 · 21:30
        dog.wakeMinuteOfDay = 9 * 60
        dog.sleepMinuteOfDay = 23 * 60
        return dog
    }

    /// Контроль первым: без исключения часы в плане прежние, и ни один
    /// пункт не помечен «только сегодня».
    @Test("Без исключения план дня стоит по расписанию")
    func безИсключенияПланПрежний() {
        let пункты = DayPlanBuilder.items(dog: стич(), events: [], now: время(600))
        let еды = пункты.filter { $0.kind == .meal }
        #expect(еды.count == 3, """
            пунктов еды \(еды.count) при трёх кормлениях: план дня \
            не собрался, и всё ниже меряет собственный промах.
            """)
        #expect(еды.map(\.сегодняИначе) == [false, false, false])
    }

    @Test("План дня берёт часы исключения и говорит об этом словом")
    func планБерётИсключение() throws {
        let dog = стич()
        dog.разовыеВременаДата = Calendar.current.startOfDay(for: Date())
        dog.разовыеВремена = [570, 930, 22 * 60]

        let пункты = DayPlanBuilder.items(dog: dog, events: [], now: время(600))
        let еды = пункты.filter { $0.kind == .meal }
        #expect(еды.count == 3)

        let ужин = try #require(еды.last)
        let минутаУжина = Calendar.current.component(.hour, from: ужин.time) * 60
            + Calendar.current.component(.minute, from: ужин.time)
        #expect(минутаУжина == 22 * 60, """
            ужин в плане дня стоит на \(минутаУжина) минуте вместо 1320. \
            Значит сборщик по-прежнему читает `mealTimes`, и названный \
            человеком час никуда не доехал.
            """)

        // **И слово, а не только час.** «22:00» в одиночку говорит,
        // что расписание такое; на втором телефоне это прямая неправда.
        // Значение считается ДО `#expect` нарочно: макрос разворачивает
        // выражение в non-throwing autoclosure, и `allSatisfy` с его
        // `rethrows` внутри него не компилируется вовсе. Тот же приём
        // стоит в `DogPayloadParityTests` у `try`.
        let всеПомечены = еды.allSatisfy(\.сегодняИначе)
        #expect(всеПомечены, """
            пункты еды не помечены «только сегодня». Второй человек \
            прочитает сдвинутый ужин как новое расписание и либо \
            запомнит его, либо вернёт «как было».
            """)
    }

    /// Равенство пункта обязано видеть эту разницу: иначе строка
    /// не перерисуется, и правка будет работать через раз.
    ///
    /// Ровно та форма, что сломала `промежуток` 04.11: три поля
    /// из четырнадцати совпали, и `onChange` счёл пункт неизменным.
    @Test("Пункт, у которого сменилось только «сегодня иначе», не равен прежнему")
    func равенствоВидитИсключение() {
        let час = время(1290)
        let было = DayPlanItem(id: "meal-1290", time: час, title: "Еда",
                               kind: .meal, isDone: false)
        var стало = было
        стало.сегодняИначе = true
        #expect(было != стало, """
            пункт со сменившимся «только сегодня» равен прежнему — \
            значит строка не перерисуется, и подпись придёт только \
            при чужой перерисовке. Это и есть «работает через раз».
            """)
    }
}

/// Исключение видит второй человек.
///
/// Это главная причина, по которой оно живёт на `Dog`, а не
/// в настройках телефона: кормит собаку сегодня вечером тот, кто
/// рядом. Не поедет — собака получит две порции или ни одной.
@Suite("Исключение едет ко второму человеку и в архив")
@MainActor
struct ИсключениеЕдетTests {

    private var сутки: Date { Calendar.current.startOfDay(for: Date()) }

    private func снимок() -> DogPayload {
        DogPayload(
            id: UUID(), name: "Стич", breed: nil, birthDate: nil,
            sex: DogSex.unknown.rawValue, isNeutered: false, weightKg: 4.1,
            targetWeightLow: nil, targetWeightHigh: nil,
            foodBrand: "", portionGrams: 60, mealsPerDay: 3,
            mealTimes: [570, 930, 1290],
            разовыеВременаДата: сутки,
            разовыеВремена: [570, 930, 22 * 60],
            dailyNormGrams: nil, forbiddenFoods: [],
            wakeMinuteOfDay: 9 * 60, sleepMinuteOfDay: 23 * 60,
            isOnTreatment: false, chipNumber: nil,
            passportNumber: nil, insuranceNumber: nil,
            vetName: nil, vetPhone: nil,
            clinicName: nil, clinicPhone: nil, distinctiveMarks: nil,
            sitterFood: "", sitterDose: "", sitterWalks: "",
            sitterForbidden: "", sitterEscalation: "",
            rewards: [], markerKind: MarkerKind.clicker.rawValue,
            sessionLengthMinutes: 3, trainingFoodFromPortion: true,
            changedAt: Date()
        )
    }

    /// Слой нагрузки: `Dog` → `DogPayload` → `Dog`.
    @Test("Исключение переживает круг через нагрузку обмена")
    func кругЧерезНагрузку() throws {
        let context = ModelContext(Persistence.container())
        SharedDiaryInbox.accept(снимок(), context: context)

        let гостьСобака = try #require(try context.fetch(FetchDescriptor<Dog>()).first)
        #expect(гостьСобака.разовыеВремена == [570, 930, 1320], """
            у гостя исключения нет. Значит «сегодня ужин в 22:00» \
            знает один телефон, а кормить собаку вечером будет другой.
            """)
        let дата = try #require(гостьСобака.разовыеВременаДата)
        #expect(Calendar.current.isDate(дата, inSameDayAs: сутки))
        #expect(гостьСобака.часыКормленийНа(Date()) == [570, 930, 1320])

        // И обратно: то, что гость увидел, он же и отправляет дальше.
        #expect(гостьСобака.payload.разовыеВремена == [570, 930, 1320])
    }

    /// Слой записи CloudKit. Нагрузка и `CKRecord` — **разные слои**,
    /// и поле может лежать в нагрузке, не попав в запись: границу
    /// этого сторожит `DogPayloadParityTests`, а заполнение — вот это.
    ///
    /// Ключи записи латиницей, хотя поля по-русски: имя поля `CKRecord`
    /// — это имя в схеме CloudKit, и правило Apple для него кириллицей
    /// ничем на этой машине не проверено.
    @Test("Исключение переживает круг через запись CloudKit")
    func кругЧерезЗапись() throws {
        let зона = SharedDiaryRecords.zoneID(owner: "кто-то")
        let запись = SharedDiaryRecords.record(снимок(), in: зона)

        #expect(запись["mealTimesOverride"] as? [Int] == [570, 930, 1320], """
            часы исключения не легли в `CKRecord`. Нагрузка при этом \
            полна — именно этот разрыв `DogPayloadParityTests` \
            не проверяет и проверять не может.
            """)
        #expect(запись["mealTimesOverrideDay"] as? Date != nil)

        let обратно = try #require(SharedDiaryRecords.dogPayload(запись))
        #expect(обратно.разовыеВремена == [570, 930, 1320])
        let дата = try #require(обратно.разовыеВременаДата)
        #expect(Calendar.current.isDate(дата, inSameDayAs: сутки))
    }

    /// Запись от прежней сборки этих ключей не знает — и обязана
    /// читаться. Иначе обмен встанет у всех, у кого не обновлено.
    @Test("Запись без ключей исключения читается, и исключения в ней нет")
    func старуюЗаписьЧитаем() throws {
        let зона = SharedDiaryRecords.zoneID(owner: "кто-то")
        let запись = SharedDiaryRecords.record(снимок(), in: зона)
        запись["mealTimesOverride"] = nil
        запись["mealTimesOverrideDay"] = nil

        let обратно = try #require(SharedDiaryRecords.dogPayload(запись))
        #expect(обратно.разовыеВременаДата == nil)
        #expect(обратно.разовыеВремена.isEmpty)
        // Контроль: остальное из той же записи по-прежнему читается —
        // значит разбор не отказал целиком, а именно этих ключей нет.
        #expect(обратно.mealTimes == [570, 930, 1290])
    }
}
