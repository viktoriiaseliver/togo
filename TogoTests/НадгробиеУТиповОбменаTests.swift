import Foundation
import Testing

/// У каждого типа, который ездит в общем дневнике, есть чем выразить
/// удаление.
///
/// # Зачем этот сторож и почему его ось не `.deleteRecord`
///
/// Наряд от 24.09.2026 держал пункт «`.deleteRecord` не ставится нигде»
/// и был **прав по замеру**: три вхождения во всём дереве, все три
/// в доккомментариях, исполняемых ноль. Замер 15.10.2026 показал, что
/// этот пункт отвечает **про жёсткое удаление** и не отвечает
/// про предмет.
///
/// ```
/// LogEvent          удаление ЕДЕТ: deletedAt (:106), пять мест
///                   мягкого удаления, надгробие уходит обычной
///                   правкой и чтится на приёме (SharedDiary:679-682)
/// одиннадцать       надгробия нет: удаление жёсткое, context.delete,
/// остальных типов   и до второго человека не доезжает вовсе
/// ```
///
/// Механизм, по которому не доезжает, — **не пропущенный флаг**:
/// исходящая очередь собирается из `["inserted", "updated"]`
/// (`FamilySync.swift:312`, это весь список), а ключ `"deleted"`
/// уведомления `ModelContext.didSave` не читает никто — ноль вхождений
/// в `Togo/` и `TogoShared/` при живом контроле на `"inserted"`.
/// То есть удаление **не доходит до места, где флаг можно было бы
/// поставить**. `SharedDiaryOutbox.forget(_:)` объявлен и ждёт вызова.
///
/// > **Сторож, поставленный на `grep .deleteRecord`, позеленел бы
/// > от одной строки, не сдвинув предмет.** Это наша четвёртая корзина
/// > — «погас прокси»: сторож зелен, предмет жив. Прокси удовлетворяется
/// > любым действием, и гаснет тихо.
///
/// Поэтому ось здесь — **наличие надгробия у типа**, а не наличие
/// строки в обмене. Её нельзя удовлетворить ни комментарием,
/// ни дописыванием `"deleted"` в список ключей: она двигается только
/// тогда, когда у типа появляется поле, которым удаление **можно
/// выразить**.
///
/// # Что этот сторож НЕ утверждает
///
/// Зелёный здесь не значит «удаление доезжает». Он значит «удаление
/// есть чем выразить». Доезжает ли оно — вопрос двух телефонов, и он
/// **неизмерим без личного iCloud Виктории**: ни ключ ASC, ни токен
/// GitHub приватную и общую базу CloudKit не открывают, второго конца
/// у связи нет. Границы печатает `границыНазваны` ниже.
///
/// # Приёмка правила — прогон на живых данных и четыре подделки
///
/// Правило прогнано **прежде, чем стало тестом** (15.10.2026,
/// `projects-5d`), на здоровом коде и четырёх подделках:
///
/// ```
/// А  надгробие только в прозе внутри класса   НЕ зачтено  ✓
/// Б  настоящее `var deletedAt: Date?`          зачтено     ✓
/// В  надгробие у ВЛОЖЕННОГО типа в классе      зачтено     ← ГРАНИЦА
/// Г  перечисление переименовано                разобрано 0 → порог
///                                              краснеет ПЕРВЫМ ✓
/// ```
///
/// **Первая редакция приёмки была неверна, и неверна в сторону
/// тревоги.** Подделка А прошла зелёной, и читалось это как «правило
/// подвержено прозе». Виноват был стенд: подделку я кладу
/// в **сырой** текст, а первая редакция клала её после вырезания
/// комментариев — защита отрабатывала раньше подделки. Замер отвечал
/// про мой стенд, а не про правило. В прототипе стоит `assert`,
/// что подделка применилась.
///
/// # Вход с диска — назван нарочно
///
/// Тест читает `TogoShared/Sync/SharedDiary.swift` и всё
/// `TogoShared/Models/*.swift` через `#filePath`. Он сломается
/// от переноса этих каталогов, и сломается **не на своём предмете**.
@Suite("У типа общего дневника есть чем выразить удаление")
struct НадгробиеУТиповОбменаTests {

    // MARK: Источники

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
    }

    private static func исходник(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Комментарии вырезаются ДО разбора.
    ///
    /// Сторож, не различающий код и прозу, меряет прозу — и тогда
    /// запретить пришлось бы писать про надгробие в файле, где его нет.
    /// Это подделка А, и без этой строки она проходит зелёной.
    private static func безКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .filter {
                let голая = $0.trimmingCharacters(in: .whitespaces)
                return !голая.hasPrefix("//") && !голая.hasPrefix("*")
            }
            .joined(separator: "\n")
    }

    // MARK: Ось

    /// `case dog = "Dog"` → `["dog": "Dog"]`.
    ///
    /// Имя класса берётся из `rawValue`, а не списком руками: список
    /// знает только то, что в него положили, и первым же пропуском
    /// стал бы дырой ровно того размера, ради которого сторож заведён.
    private static func типыОбмена() throws -> [String: String] {
        let текст = безКомментариев(try исходник("TogoShared/Sync/SharedDiary.swift"))
        guard let начало = текст.range(of: "enum RecordType") else { return [:] }
        let хвост = текст[начало.upperBound...]
        guard let конец = хвост.range(of: "\n    }") else { return [:] }

        var найдено: [String: String] = [:]
        for строка in хвост[..<конец.lowerBound].components(separatedBy: .newlines) {
            let голая = строка.trimmingCharacters(in: .whitespaces)
            guard голая.hasPrefix("case ") else { continue }
            let после = голая.dropFirst(5)
            let кейс = после.prefix { $0.isLetter || $0.isNumber }
            guard !кейс.isEmpty,
                  let перваяКавычка = после.firstIndex(of: "\"") else { continue }
            let остаток = после[после.index(after: перваяКавычка)...]
            guard let втораяКавычка = остаток.firstIndex(of: "\"") else { continue }
            let класс = String(остаток[..<втораяКавычка])
            if !класс.isEmpty { найдено[String(кейс)] = класс }
        }
        return найдено
    }

    /// Все модели одним текстом — классы лежат в разных файлах.
    private static func текстМоделей() throws -> String {
        var куски: [String] = []
        let каталог = корень.appendingPathComponent("TogoShared/Models")
        guard let обход = FileManager.default.enumerator(
            at: каталог, includingPropertiesForKeys: nil) else { return "" }
        while let файл = обход.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            куски.append(безКомментариев(текст))
        }
        return куски.joined(separator: "\n")
    }

    /// Тело класса по счёту скобок.
    ///
    /// **Уровень тела — ПЕРВЫЙ, а не нулевой:** `final class X {` уже
    /// открыла скобку. На этой самой ошибке сторож полей моделей был
    /// зелёным при любом новом поле — поля не находились ни у одной
    /// модели, и «без решения» выходило ноль.
    private static func телоКласса(_ текст: String, _ имя: String) -> String? {
        guard let объявление = текст.range(of: "final class \(имя) {")
                ?? текст.range(of: "final class \(имя): ") else { return nil }
        guard let открывающая = текст[объявление.lowerBound...].firstIndex(of: "{") else { return nil }

        var глубина = 1
        var i = текст.index(after: открывающая)
        let начало = i
        while i < текст.endIndex, глубина > 0 {
            if текст[i] == "{" { глубина += 1 }
            else if текст[i] == "}" { глубина -= 1 }
            if глубина == 0 { return String(текст[начало..<i]) }
            i = текст.index(after: i)
        }
        return nil
    }

    /// Объявление поля, а не упоминание имени.
    private static func естьНадгробие(_ тело: String) -> Bool {
        тело.range(of: "var deletedAt: Date?") != nil
            || тело.range(of: "var deletedAt : Date?") != nil
    }

    /// Разбор целиком: кто с надгробием, кто без, у кого класс не нашёлся.
    private static func разбор() throws -> (
        типы: [String: String], сНадгробием: [String], безНадгробия: [String], неНайдены: [String]
    ) {
        let типы = try типыОбмена()
        let модели = try текстМоделей()

        var сНадгробием: [String] = []
        var безНадгробия: [String] = []
        var неНайдены: [String] = []
        for (кейс, класс) in типы.sorted(by: { $0.key < $1.key }) {
            guard let тело = телоКласса(модели, класс) else {
                неНайдены.append("\(кейс) (\(класс))")
                continue
            }
            if естьНадгробие(тело) { сНадгробием.append("\(кейс) (\(класс))") }
            else { безНадгробия.append("\(кейс) (\(класс))") }
        }
        return (типы, сНадгробием, безНадгробия, неНайдены)
    }

    // MARK: Надгробия нет НАРОЧНО — с причиной и датой

    /// Типы, у которых надгробия нет **по решению**.
    ///
    /// Форма та же, что у `RecordTypeUsedTests.объявленоНеСоздаётся`,
    /// и по той же причине: «не возим по решению» и «не возим, потому
    /// что не дошли руки» снаружи одинаковы. Каждой записи нужна
    /// **дата** — «не сделано» без даты не стареет вовсе, а с датой
    /// стареет громко.
    ///
    /// **Пусто с 15.10.2026, и пустота здесь — НАЧАЛО, а не результат.**
    /// Одиннадцать типов стоят в долге, хозяин — Виктория: надгробие
    /// трогает форму схемы (`SchemaVersions`), а это её решение
    /// и деплой поля в production, не правка разработчика.
    /// Запись в `Tools/эталон-прогона.json` держит этот долг видимым.
    private static let надгробияНетНарочно: [String: (заведён: String, причина: String)] = [:]

    // MARK: Проверки

    /// Первой — что сторожу было что сторожить.
    @Test("Перечисление типов и тела моделей разобраны")
    func былоЧтоСторожить() throws {
        let итог = try Self.разбор()

        #expect(итог.типы.count >= 10, """
            типов обмена разобрано \(итог.типы.count) — разбор \
            перечисления `RecordType` не состоялся. Сторож, переставший \
            что-либо находить, молчит так же, как тот, кому нечего \
            сказать: при нуле проверка ниже назвала бы долгом ПУСТОТУ \
            и позеленела.
            """)

        #expect(итог.неНайдены.isEmpty, """
            класс модели не найден по имени из `rawValue`: \
            \(итог.неНайдены.joined(separator: ", ")).

            Это отказ РАЗБОРА, а не находка о коде: модель \
            переименовали, перенесли из `TogoShared/Models/`, либо она \
            объявлена не как `final class`. Чинить разбор, а не обмен — \
            иначе тип молча выпадет из проверки и его долг станет \
            невидимым.
            """)
    }

    /// Запрет: тип ездит, удаление выразить нечем, и это нигде не названо.
    @Test("У каждого типа обмена есть надгробие либо названная причина его отсутствия")
    func уКаждогоТипаЕстьЧемВыразитьУдаление() throws {
        let итог = try Self.разбор()

        // Ослепший разбор не превращается в список находок.
        guard итог.типы.count >= 10, итог.неНайдены.isEmpty else {
            #expect(Bool(false), """
                разбор не состоялся (типов \(итог.типы.count), \
                ненайденных классов \(итог.неНайдены.count)). Смотреть \
                `былоЧтоСторожить`, а не этот тест.
                """)
            return
        }

        let долг = итог.безНадгробия
            .filter { имя in
                let кейс = имя.prefix { $0 != " " }
                return Self.надгробияНетНарочно[String(кейс)] == nil
            }
            .sorted()

        #expect(долг.isEmpty, """
            тип ездит в общем дневнике, а выразить его удаление нечем: \
            \(долг.joined(separator: ", ")).

            Значит удаление такого типа жёсткое (`context.delete`), \
            а исходящая очередь собирается только из \
            `["inserted", "updated"]` (`FamilySync.swift:312`) — ключ \
            `"deleted"` не читает никто. Человек удалил у себя схему \
            лечения, визит, анализ или собаку — у второго человека это \
            осталось, и останется навсегда.

            Самый дорогой случай назван отдельно: Виктория отменила \
            схему лечения, у мамы она жива, мама даёт препарат \
            и получает напоминания о дозах. Цена ошибки здесь та же, \
            которой проект мерит дозы.

            Либо заведи надгробие (это форма схемы `SchemaVersions` — \
            РЕШЕНИЕ ВИКТОРИИ, не правка), либо впиши тип \
            в `надгробияНетНарочно` С ПРИЧИНОЙ И ДАТОЙ. Третьего нет: \
            молчаливое отсутствие неотличимо от недоделки.

            Что НЕ является починкой: дописать `"deleted"` в список \
            ключей. Это удовлетворило бы прокси и оставило предмет \
            живым — ровно то, от чего эта ось и построена.
            """)
    }

    /// Обратная половина: причина на типе, которого больше нет, —
    /// лишняя дыра, про которую никто не помнит.
    @Test("Причина отсутствия надгробия стоит на живом типе, с датой")
    func причиныНеПротухли() throws {
        let итог = try Self.разбор()

        let призраки = Self.надгробияНетНарочно.keys
            .filter { итог.типы[$0] == nil }.sorted()
        #expect(призраки.isEmpty, """
            причина стоит на типах, которых в перечислении нет: \
            \(призраки.joined(separator: ", ")). Тип убрали или \
            переименовали, а разрешение осталось — и теперь оно молча \
            разрешает то, чего никто не разрешал.
            """)

        // И обратное-обратное: тип, у которого надгробие УЖЕ ЕСТЬ,
        // не должен числиться в долге. Иначе разрешение переживёт
        // починку и прикроет следующую поломку в этом месте.
        let сНадгробиемКейсы = Set(итог.сНадгробием.map { String($0.prefix { $0 != " " }) })
        let лишние = Self.надгробияНетНарочно.keys
            .filter { сНадгробиемКейсы.contains($0) }.sorted()
        #expect(лишние.isEmpty, """
            у типа есть надгробие и при этом он числится «надгробия нет \
            нарочно»: \(лишние.joined(separator: ", ")). Починили \
            и не убрали разрешение.
            """)

        var безПричины: [String] = []
        for (тип, запись) in Self.надгробияНетНарочно {
            if запись.заведён.count != 10 || !запись.заведён.hasPrefix("20") {
                безПричины.append("\(тип): дата «\(запись.заведён)»")
            }
            if запись.причина.trimmingCharacters(in: .whitespacesAndNewlines).count < 60 {
                безПричины.append("\(тип): причина короче, чем отговорка")
            }
        }
        #expect(безПричины.isEmpty, """
            «надгробия нет нарочно» без даты или без причины: \
            \(безПричины.sorted().joined(separator: "; ")).

            Дата нужна, чтобы запись старела громко. Порог длины — \
            против отговорок вида «так решили».
            """)
    }

    /// Граница собственного умения — печатается всегда.
    @Test("Границы сторожа надгробий названы")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит ровно одно: у каждого типа, который \
            ездит в общем дневнике, ЕСТЬ ЧЕМ выразить удаление — поле \
            `deletedAt` в теле класса модели, либо названная с датой \
            причина, почему его нет.

            НЕ проверяется:
            · ДОЕЗЖАЕТ ли удаление до второго человека. Это два \
              телефона, и это неизмеримо без личного iCloud Виктории: \
              приватная и общая база CloudKit не открываются ни ключом \
              ASC, ни токеном GitHub, второго конца у связи нет;
            · ставится ли надгробие ВЕЗДЕ, где человек удаляет. У \
              `LogEvent` пять мест мягкого удаления, и сторож не знает, \
              не появилось ли шестое место с жёстким;
            · уезжает ли поле надгробия в `CKRecord` — это соседний \
              слой (`SharedDiaryRecords`), и у него свои сторожа \
              чётности нагрузки;
            · чтит ли надгробие ПРИЁМ. У события чтит \
              (`SharedDiary:679-682`, «удаление сильнее правки»), \
              у остальных типов разрешителя удаления нет вовсе — \
              потому что нет и надгробия;
            · надгробие у ВЛОЖЕННОГО типа внутри класса зачитывается \
              как надгробие самого класса. Замерено подделкой В \
              15.10.2026, не починено нарочно: разбор вложенных тел \
              стоит дороже, чем ущерб от этой границы, и ни у одной \
              модели вложенного `deletedAt` сейчас нет.
            """
        #expect(границы.isEmpty == false)
    }
}
