    /// Снимок и нынешняя схема обязаны РАЗЛИЧАТЬСЯ — иначе стадия
    /// между ними не миграция, а пустое обещание.
    ///
    /// Стоит отдельным тестом, потому что ровно это и было дефектом
    /// до 26.10: V5 и нынешняя схема были одним и тем же объектом,
    /// и никакой тест этого не спрашивал. Вопрос «отличаются ли»
    /// не задавал никто, потому что ответ казался очевидным.
    @Test("Снимок V5 и нынешняя схема — разные формы, иначе стадия пустая")
    func снимокИНынешняяРазные() {
        let пятая = Self.замер(Schema(versionedSchema: TogoSchemaV5.self))
        let нынешняя = Self.замер()

        #expect(пятая.отпечаток != нынешняя.отпечаток, """
            форма снимка V5 и форма нынешней схемы СОВПАЛИ.

            Значит V5 опять ссылается на живые классы, и стадия
            V5 → V6 стоит между двумя одинаковыми формами — то есть
            не делает ничего, а старое хранилище по-прежнему
            не открывается. Это дефект 26.10.2026 в точности.
            """)
        // **Сравнение идёт с V6, а не с нынешней схемой, и это правка
        // ОСИ 27.10.2026.** Одиннадцать надгробий — это прирост стадии
        // V5 → V6, и пока она была последней, «нынешняя» и «V6» были
        // одним и тем же. С появлением V7 они разошлись: между V5
        // и нынешней теперь ДВЕ стадии, и число 11 стало ложным
        // не потому, что надгробия уехали, а потому что вопрос
        // перестал быть про них.
        //
        // Это наш класс «условие, привязанное к устройству дерева»:
        // проверка верна ровно до следующей версии схемы и ломается
        // молча — на здоровом коде. Теперь она спрашивает про СВОЮ
        // стадию и переживёт V8.
        let шестая = Self.замер(Schema(versionedSchema: TogoSchemaV6.self))
        #expect(шестая.свойств == пятая.свойств + 11, """
            V6 должна быть шире снимка V5 ровно на одиннадцать
            надгробий.
            снимок V5  \(пятая.свойств)
            снимок V6  \(шестая.свойств)   (ждём \(пятая.свойств + 11))

            Другое число значит, что вместе с надгробиями уехало
            что-то ещё, и морозить V5 этим снимком было нельзя.
            """)
        // И своя проверка у стадии V6 → V7: одно поле, `LogEvent.photo`.
        //
        // **Ось правлена 28.10.2026 по той же причине, по которой
        // днём раньше правили строку выше: спрашивать надо про СВОЮ
        // стадию.** Здесь стояло `нынешняя.свойств == шестая + 1`,
        // и это было верно ровно до появления V8 — ломалось оно
        // молча, на здоровом коде. Теперь обе стадии спрашивают
        // про себя, и обе переживут V9.
        let седьмая = Self.замер(Schema(versionedSchema: TogoSchemaV7.self))
        #expect(седьмая.свойств == шестая.свойств + 1, """
            V7 должна быть шире снимка V6 ровно на одно поле —
            `LogEvent.photo`, заведённое 27.10.2026.
            снимок V6  \(шестая.свойств)
            снимок V7  \(седьмая.свойств)   (ждём \(шестая.свойств + 1))
            """)

        // Своя проверка у стадии V7 → V8: четыре свойства.
        // Поимённо их сверяет `SchemaMigrationTests`; здесь — счёт,
        // потому что счёт ловит «уехало что-то ещё», а имена ловят
        // «уехало не то». Две разные ошибки, и ни одна проверка
        // не ловит обе.
        #expect(нынешняя.свойств == седьмая.свойств + 4, """
            нынешняя схема должна быть шире V7 ровно на четыре
            свойства, заведённые 28.10.2026:
            `DogDocument.occurredOn`, `DogDocument.directionRaw`,
            `DogDocument.clinic` и обратная сторона той же связи
            `Clinic.documentsStorage`.
            V7        \(седьмая.свойств)
            нынешняя  \(нынешняя.свойств)   (ждём \(седьмая.свойств + 4))

            Вышло ТРИ — скорее всего забыта обратная сторона связи,
            а без неё зеркало CloudKit не открывает хранилище вовсе
            (`CloudKit integration requires that all relationships
            have an inverse`, замер 07.10.2026). Вышло больше —
            уехало что-то ещё, и морозить V7 этим снимком было нельзя.
            """)
    }

