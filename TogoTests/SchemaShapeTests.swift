    @Test("Атрибутов без опциональности и без значения по умолчанию не прибавилось")
    func беззащитныхНеБольше() {
        var беззащитные: [String] = []

        for сущность in Persistence.schema.entities.sorted(by: { $0.name < $1.name }) {
            for свойство in сущность.properties.sorted(by: { $0.name < $1.name }) {
                guard !свойство.isRelationship, !свойство.isTransient else { continue }
                guard let атрибут = свойство as? Schema.Attribute else { continue }
                if !атрибут.isOptional, атрибут.defaultValue == nil {
                    беззащитные.append("\(сущность.name).\(свойство.name)")
                }
