import SwiftData
@testable import Togo

/// Форма, которой приложение открывает хранилище, заперта отпечатком.
///
/// **Чем это оплачено — подделкой 05.10.2026, а не рассуждением.**
/// В живую модель `Dog` добавлено одно поле — ровно то, что делает любой
/// новый экран. Пять тестов `SchemaFrozenTests` остались зелёными,
/// `** TEST SUCCEEDED **`, а в логе того же прогона стояло
/// `Cannot use staged migration with an unknown model version` (134504)
/// и «старт: локальное не открылось».
///
/// Хранилище не открылось, а набор напечатал успех.
///
/// **Почему прежние пять сторожей это пропускали.** Они сверяли номера
/// версий и соседние версии между собой:
///
/// - `хранилищеНаПоследней` — номера, а не формы. Номер не менялся.
/// - `соседиОтличаются` — снимок против живых классов. Новое поле
///   разводит их ещё сильнее, то есть **чем хуже дефект, тем зеленее**.
/// - `наборМоделейОдин`, `стадииБезДыр`, `changedAtПоявилсяВЧетвёртой`
///   — про шестнадцать сущностей, про число стадий и про одно поле.
///   Новое поле не трогает ни одно.
///
/// Здесь сверяется то, чего не сверял никто: **сама форма**, целиком,
/// против записанного числа.
@Suite("Форма хранилища заперта отпечатком")
struct SchemaShapeTests {

    // MARK: - Записанное состояние

    /// Версия, под которую снят отпечаток. Пара «версия + отпечаток»
    /// держится вместе нарочно: отпечаток без версии не отвечает
    /// на вопрос «той ли формы», а версия без отпечатка — на вопрос
    /// «та ли форма под этим номером». Второе и было дефектом 23.09.
    static let записаннаяВерсия = "5.0.0"

    /// Снят замером, а не выдуман. Обновлять только вместе с заморозкой
    /// прежней версии — порядок в сообщении теста ниже.
    static let записанныйОтпечаток = "62b34bd1e8f116082eee57e2f9bf0fc2"

    /// Сколько было в день записи. Нужно не для красоты: сканер,
    /// переставший что-либо находить, молчит так же, как тот, кому
    /// нечего сказать.
    static let записаноСущностей = 16
    static let записаноСвойствНеМенее = 150

    /// Атрибутов без опциональности и без значения по умолчанию.
    /// Держится счётом, который может только падать, а не требованием
    /// нуля: сторож, красный в день рождения, учит не верить красному.
    static let записаноБеззащитных = 0

    // MARK: - Замер

    /// Отпечаток формы: сущности и свойства в устойчивом порядке.
    ///
    /// Берётся у `Persistence.schema` — у той схемы, которой приложение
    /// **и правда** открывает хранилище, а не у последней версии плана.
    /// Это разные вещи: 05.10 в дереве лежало состояние, где
    /// `Persistence.schema` смотрела на V4, а последней в плане
    /// была уже V5.
    static func замер() -> (отпечаток: String, сущностей: Int, свойств: Int) {
        let схема = Persistence.schema
        var строки: [String] = []
        var свойств = 0

        for сущность in схема.entities.sorted(by: { $0.name < $1.name }) {
            var поля: [String] = []
            for свойство in сущность.properties.sorted(by: { $0.name < $1.name }) {
                свойств += 1
                // Тип берётся приведением, а не у протокола: `valueType`
                // объявлен у `Schema.Attribute` и `Schema.Relationship`,
                // а в `SchemaProperty` его нет — проверено по интерфейсу
                // SDK, а не по памяти.
                let тип: String
                if let атрибут = свойство as? Schema.Attribute {
                    тип = "\(атрибут.valueType)"
                } else if let связь = свойство as? Schema.Relationship {
                    тип = "\(связь.valueType)"
                } else {
                    тип = "типНеизвестен"
                }
                // `isTransient` в отпечатке нужен: превращение хранимого
                // в вычисляемое меняет форму так же, как удаление поля.
                поля.append([
                    свойство.name,
                    тип,
                    свойство.isOptional ? "опц" : "обяз",
                    свойство.isUnique ? "уник" : "—",
                    свойство.isRelationship ? "связь" : "атрибут",
                    свойство.isTransient ? "невхранилище" : "вхранилище",
                ].joined(separator: ":"))
            }
            строки.append("\(сущность.name){\(поля.joined(separator: "|"))}")
        }

        return (Self.хеш(строки.joined(separator: "\n")), схема.entities.count, свойств)
    }

    /// Свой отпечаток, а не `versionHash` Apple — **названная граница,
    /// а не недосмотр**. Настоящий `versionHash` наружу из SwiftData
    /// не отдаётся; снять его можно только из `Z_METADATA` живой базы,
    /// а база требует симулятора, а симулятор у нас общий на пять
    /// сессий — и 05.10 это уже стоило двух прогонов, упавших
    /// от соседа, а не от кода.
    ///
    /// Поэтому отпечаток считается в памяти, а сверка с базой делается
    /// отдельным замером руками (05.10 снята: `['4.0.0']`, шестнадцать
    /// хешей сущностей). Два наблюдения за одной вещью, и ни одно
    /// не проверяется другим автоматически.
    private static func хеш(_ строка: String) -> String {
        var h1: UInt64 = 0xcbf2_9ce4_8422_2325
        var h2: UInt64 = 0x9e37_79b9_7f4a_7c15
        for байт in Array(строка.utf8) {
            h1 = (h1 ^ UInt64(байт)) &* 0x100_0000_01b3
            h2 = (h2 &+ UInt64(байт) &+ 1) &* 0x9e37_79b9_7f4a_7c15
            h2 ^= h2 >> 29
        }
        return String(format: "%016llx%016llx", h1, h2)
    }

    // MARK: - 1. Было что проверять

    /// Стоит первым нарочно: набор, которому нечего проверять, молчит
    /// так же, как набор, у которого всё хорошо.
    @Test("Замер формы вообще что-то нашёл")
    func замерНеПустой() {
        let (отпечаток, сущностей, свойств) = Self.замер()

        #expect(сущностей == Self.записаноСущностей, """
            сущностей \(сущностей), а записано \(Self.записаноСущностей).
            Набор сущностей меняет форму сильнее любого поля,
            и `.lightweight` опирается на его неизменность прямо.
            """)
        #expect(свойств >= Self.записаноСвойствНеМенее, """
            свойств насчитано \(свойств) — меньше \(Self.записаноСвойствНеМенее)
            в день записи. Либо модели обеднели, либо замер перестал их
            видеть, и второе снаружи выглядит как первое.
            """)
        #expect(отпечаток.count == 32, "отпечаток пуст или короче, чем считает `хеш`")
    }

    // MARK: - 2. То, ради чего набор заведён

    @Test("Форма хранилища не менялась без заморозки и подъёма версии")
    func формаНеМеняласьМолча() {
        let (отпечаток, _, свойств) = Self.замер()
        let версия = "\(Persistence.schema.version)"

        #expect(версия == Self.записаннаяВерсия, """
            хранилище открывается версией \(версия), а отпечаток снят под
            \(Self.записаннаяВерсия). Сверять форму нечем: пара
            «версия + отпечаток» разъехалась.
            """)

        #expect(отпечаток == Self.записанныйОтпечаток, """
            ФОРМА ХРАНИЛИЩА ИЗМЕНИЛАСЬ, А ВЕРСИЯ ОСТАЛАСЬ \(версия).

            записано  \(Self.записанныйОтпечаток)
            замерено  \(отпечаток)   (\(свойств) свойств)

            Это дефект 23.09: форма стала другой под неизменным номером,
            SwiftData отвечает «Cannot use staged migration with an unknown
            model version», и на телефоне это НЕ падение — контейнер
            откатывается iCloud → локально → в память. Человек отмечает
            дозу, видит подтверждение, запись не сохраняется никуда.

            Если форму поменяли НАМЕРЕННО, порядок такой и только такой:

              1. заморозить нынешнюю версию снимком — своими `final class`
                 внутри `TogoSchemaVN`, а не ссылками на живые классы;
              2. завести следующую версию и стадию перехода к ней;
              3. перевести `Persistence.schema` на неё;
              4. и только теперь обновить `записаннаяВерсия`
                 и `записанныйОтпечаток` здесь.

            Обновить отпечаток первым — значит погасить сторож и оставить
            дефект. Шаг 4 последний не по вкусу: он снимает единственный
            признак, по которому заметны шаги 1–3.
            """)
    }

    // MARK: - 3. Поле, из-за которого не заведётся зеркало CloudKit

    @Test("Атрибутов без опциональности и без значения по умолчанию не прибавилось")
    func беззащитныхНеБольше() {
        var беззащитные: [String] = []

        for сущность in Persistence.schema.entities.sorted(by: { $0.name < $1.name }) {
            for свойство in сущность.properties.sorted(by: { $0.name < $1.name }) {
                guard !свойство.isRelationship, !свойство.isTransient else { continue }
                guard let атрибут = свойство as? Schema.Attribute else { continue }
                if !атрибут.isOptional, атрибут.defaultValue == nil {
                    беззащитные.append("\(сущность.name).\(свойство.name)")
                }
            }
        }

        #expect(беззащитные.count <= Self.записаноБеззащитных, """
            атрибутов без опциональности и без значения по умолчанию
            \(беззащитные.count), а было \(Self.записаноБеззащитных):

            \(беззащитные.joined(separator: "\n"))

            У прежних записей такое поле заполнить нечем, и зеркало
            CloudKit на нём не заводится. Счёт может только падать.
            """)
    }

    // MARK: - 4. Границы этого набора

    @Test("Границы: чего этот набор НЕ видит")
    func границыНабора() {
        // Стоит последним нарочно и печатает границы сам: пока границу
        // называет человек, она теряется при первой передаче. И каждая
        // граница обязана назвать, ЧТО ЕЁ СНИМЕТ, поимённо — правило
        // куплено 05.10 тем, что печать границы соврала в пользу
        // бездействия на пять дней.
        //
        // 1. Отпечаток — свой, не `versionHash` Apple.
        //    Снимет: сверка с `Z_METADATA` пустой базы. Руками сделана
        //    05.10 (16 хешей при `4.0.0`); автоматически — нет,
        //    и требует своего симулятора по имени СЕССИИ, не проекта:
        //    общий на пять сессий уже дал два прогона, упавших
        //    от соседа, а не от кода.
        //
        // 2. Внутренность Codable-слота не разбирается. `DoseSlot`
        //    (`minuteOfDay` + `quantity`) для `Schema` — ОДИН атрибут
        //    `Medication.doseSlotsData`. Разъехавшиеся длины или
        //    потерянную половину внутри него отпечаток не заметит.
        //    Снимет: круговой проход через хранилище — записать слоты,
        //    закрыть контейнер, открыть, прочитать, сверить `0.5`.
        //
        // 3. `defaultValue` отвечает «значение есть», а не «значение то».
        //    Отличить заданное в объявлении от подставленного SwiftData
        //    здесь нечем.
        //    Снимет: сверка с `Z_METADATA`, где лежит записанное.
        //
        // 4. Опции атрибута — `.externalStorage`,
        //    `.allowsCloudEncryption` — в отпечаток не входят:
        //    `isUnique` виден, остальные через протокол не отдаются.
        //    Снимет: разбор `Schema.Attribute.options`. Он доступен,
        //    и значит это дыра, а не решение.
        //
        // 5. Отпечаток говорит «форма та же» и не говорит «миграция
        //    работает». Но здесь — поправка к прежней редакции этой
        //    границы, и она измерена: миграция в проекте ПОКРЫТА
        //    (`SchemaMigrationTests` заводит базу формы, которой нет
        //    в плане, и утверждает, что она не подменяется пустым
        //    дневником; отдельно открывает базу сборки 46 нынешней
        //    схемой). Непокрыта ровно ОДНА форма — сборки 25, которой
        //    в плане нет вовсе, и она роздана внутренней группе «Свои»
        //    (17 сборок против 15 у внешних «Друзей»).
        //    Снимет: добавить форму 25 в тот же стенд.
        #expect(Bool(true))
    }
}
