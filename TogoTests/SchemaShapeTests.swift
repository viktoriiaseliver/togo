    /// оставлено прежним: вопрос «той ли формы мы открываем хранилище»
    /// задаётся чаще всех.
    static func замер(_ схема: Schema = Persistence.schema)
    -> (отпечаток: String, сущностей: Int, свойств: Int) {
        var строки: [String] = []
        var свойств = 0

        for сущность in схема.entities.sorted(by: { $0.name < $1.name }) {
            var поля: [String] = []
            for свойство in сущность.properties.sorted(by: { $0.name < $1.name }) {
                свойств += 1
                // Тип берётся приведением, а не у протокола: `valueType`
                // объявлен у `Schema.Attribute` и `Schema.Relationship`,
                // а в `SchemaProperty` его нет — проверено по интерфейсу
                // SDK, а не по памяти.
                let тип: String
                if let атрибут = свойство as? Schema.Attribute {
                    тип = "\(атрибут.valueType)"
                } else if let связь = свойство as? Schema.Relationship {
                    тип = "\(связь.valueType)"
                } else {
                    тип = "типНеизвестен"
                }
                // `isTransient` в отпечатке нужен: превращение хранимого
                // в вычисляемое меняет форму так же, как удаление поля.
                поля.append([
                    свойство.name,
                    тип,
                    свойство.isOptional ? "опц" : "обяз",
                    свойство.isUnique ? "уник" : "—",
                    свойство.isRelationship ? "связь" : "атрибут",
                    свойство.isTransient ? "невхранилище" : "вхранилище",
                ].joined(separator: ":"))
            }
            строки.append("\(сущность.name){\(поля.joined(separator: "|"))}")
        }

        return (Self.хеш(строки.joined(separator: "\n")), схема.entities.count, свойств)
    }

    /// Свой отпечаток, а не `versionHash` Apple — **названная граница,
    /// а не недосмотр**. Настоящий `versionHash` наружу из SwiftData
    /// не отдаётся; снять его можно только из `Z_METADATA` живой базы,
    /// а база требует симулятора, а симулятор у нас общий на пять
    /// сессий — и 05.10 это уже стоило двух прогонов, упавших
    /// от соседа, а не от кода.
    ///
    /// Поэтому отпечаток считается в памяти, а сверка с базой делается
    /// отдельным замером руками (05.10 снята: `['4.0.0']`, шестнадцать
    /// хешей сущностей). Два наблюдения за одной вещью, и ни одно
    /// не проверяется другим автоматически.
    private static func хеш(_ строка: String) -> String {
        var h1: UInt64 = 0xcbf2_9ce4_8422_2325
        var h2: UInt64 = 0x9e37_79b9_7f4a_7c15
        for байт in Array(строка.utf8) {
            h1 = (h1 ^ UInt64(байт)) &* 0x100_0000_01b3
            h2 = (h2 &+ UInt64(байт) &+ 1) &* 0x9e37_79b9_7f4a_7c15
            h2 ^= h2 >> 29
        }
        return String(format: "%016llx%016llx", h1, h2)
    }

