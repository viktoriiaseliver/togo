import Foundation
import Testing
@testable import Togo

/// Разбор `togo://…` — половина цепочки «тап по живой активности →
/// „На улице"», которую можно спросить прогоном.
///
/// # Повод: вторая половина цепочки восемь часов лежала одна
///
/// `WalkLiveActivity` ставил `.widgetURL(togo://walk)`, а
/// `RootView.handle` знал ровно один хост — `join`. Неизвестный хост
/// проваливался в `default: break`, и **отказа человек не видел**:
/// тап по карточке блокировки открывал просто приложение.
///
/// > Ни один сторож этого не ловил и не мог: «каким путём человек сюда
/// > попадает» не спрашивает ни тест, ни компилятор. Нашлось чтением
/// > двух файлов рядом, и чинить пришлось в третьем.
///
/// # Ось: АДРЕСАТ, а не наличие строки
///
/// Сторож на `grep "walk"` по `RootView.swift` был бы зелёным от
/// комментария — у Того это уже оплачено («сканирующий сторож меряет
/// прозу»). Здесь спрашивается значение, которое вернула функция.
///
/// # Чего этот набор НЕ доказывает
///
/// 1. **Что экран показался.** `адресат` отвечает «куда вести», а не
///    «довели». Показ держат `selection`, `@Binding` и `.sheet` —
///    три стыка, которых отсюда не видно.
/// 2. **Что ссылка дойдёт до приложения.** Схему объявляет
///    `Configuration` (`URL_SCHEME`), и бандл — отдельный свидетель
///    от исходника.
///
/// Приёмка целого — телефон: открыть живую активность и тапнуть.
@Suite("Глубокие ссылки")
struct ГлубокиеСсылкиTests {

    private static func ссылка(_ строка: String) throws -> URL {
        try #require(URL(string: строка), "«\(строка)» не стала URL — отказ стенда, не предмета")
    }

    /// **Первым: было ли что мерить.** Отрицательный контроль снят
    /// в том же замере, что предмет, и подвержен тому же отказу:
    /// если `адресат` всегда возвращает `nil` (хоть схему переименуй),
    /// покраснеют оба положительных теста, а этот останется зелёным —
    /// и несовместимость будет видна **без знания причины**.
    @Test("Чужая схема и неизвестный хост адресата не дают")
    func контроль() throws {
        #expect(RootView.адресат(try Self.ссылка("https://togo.app/walk")) == nil,
                "чужая схема прошла — сверка схемы не работает")
        #expect(RootView.адресат(try Self.ссылка("togo://такогоХостаНет")) == nil,
                "неизвестный хост получил адресата — ветки разошлись")
        #expect(RootView.адресат(try Self.ссылка("togo://")) == nil,
                "ссылка без хоста получила адресата")
    }

    /// Предмет этой правки: решение дизайна круга 2, §6 —
    /// «Тап по активности открывает „На улице"».
    @Test("togo://walk ведёт на прогулку")
    func прогулка() throws {
        let адрес = RootView.адресат(try Self.ссылка("togo://walk"))
        #expect(адрес == .прогулка, """
            `togo://walk` дал \(String(describing: адрес)) вместо `.прогулка`. \
            Это та самая дыра: тап по живой активности открывает просто \
            приложение, и ОТКАЗА ЧЕЛОВЕК НЕ ВИДИТ.
            """)
    }

    /// **Ссылка, которую ставит сам виджет, а не её копия руками.**
    ///
    /// Строку `"togo://walk"` выше печатал я; эту собирает продукт
    /// из `AppIdentifiers.urlScheme`. Разойдись схема в одном
    /// из трёх домов — верхний тест остался бы зелёным.
    @Test("Ссылка, которую ставит живая активность, разбирается этим же разбором")
    func ссылкаВиджетаИРазборСходятся() throws {
        // `WalkLiveActivity` живёт в расширении, в тест-таргет приложения
        // он не входит — значит берём ту же сборку адреса, что у него,
        // из того же единственного источника схемы.
        let собранная = try Self.ссылка("\(AppIdentifiers.urlScheme)://walk")
        #expect(RootView.адресат(собранная) == .прогулка,
                "схема из AppIdentifiers («\(AppIdentifiers.urlScheme)») разбором не принята")
    }

    /// Приглашение в семью — не предмет этой правки, и стоит здесь
    /// именно поэтому: **положительный контроль на том же инструменте.**
    /// Поломка разбора уронит обоих, и будет видно, что дело
    /// в инструменте, а не в новом хосте.
    @Test("togo://join/<token> по-прежнему ведёт в семью")
    func семья() throws {
        #expect(RootView.адресат(try Self.ссылка("togo://join/7KQ2-VX")) == .семья)
        #expect(RootView.адресат(try Self.ссылка("togo://join")) == .семья,
                "хост тот же, токена нет — адресат обязан быть тот же: токен читает экран")
    }
}
