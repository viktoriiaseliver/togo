import Testing
import Foundation
@testable import Togo

/// Подсказка в поле — пример, и у каждого примера записано, чем он
/// является.
///
/// **Почему это понадобилось.** За день нашлись четыре подсказки,
/// привязанные к одной стране, и каждая была найдена порознь:
///
/// | | что это | чем лечится |
/// |---|---|---|
/// | `+33…` | формат, которому надо **соответствовать** | перевода не существует → `+…` |
/// | `Ницца → Лион` | пример свободного текста | переводится, города остаются примером |
/// | `Lévothyrox` | торговое название | перевод **существует**: «Эутирокс», «L-тироксин» |
/// | `Dr. Ferrand` | имя человека | не переводится → заменено описанием |
///
/// Пятая нашлась бы завтра, и снова порознь. Поэтому здесь одно место
/// на все: **список выводится из исходника, а решение записывается
/// рукой.** Новая подсказка, о которой не подумали, упирается в этот
/// тест, а не в чью-то память.
///
/// **На грамматику сторожа не напишешь** — все четыре строки безупречны
/// и существуют; ловится только чтением на смысл, а его делает человек.
/// Зато можно потребовать, чтобы **решение было принято**: это и есть
/// то, что механизируется.
///
/// Разница, ради которой заведены виды: ошибка в **формате** делает
/// поле неверным (код страны, которого у человека нет), ошибка
/// в **примере** — всего лишь неузнаваемым. Первое чинится снятием
/// догадки, второе — переводом.
@Suite("У каждой подсказки записано, чем она является")
struct PlaceholderOriginTests {

    private enum Вид {
        /// Человек обязан соответствовать: формат, единицы, разделитель.
        /// Привязки к стране быть не должно, перевода — тоже.
        case формат
        /// Пример, который можно проигнорировать. Переводится целиком,
        /// и переводчик вправе взять местный.
        case пример
        /// Описание поля вместо примера. Переводится как обычный текст.
        case описание
    }

    /// Решение по каждой подсказке. Список ведётся рукой — в этом
    /// его смысл: он хранит то, чего из кода не вывести.
    private static let решения: [String: (Вид, String)] = [
        "+…": (.формат, "код страны был бы догадкой о том, где человек живёт"),
        "4,1": (.формат, "разделитель дробной части, вес собаки"),
        "4,0": (.формат, "разделитель дробной части, нижняя граница коридора веса"),
        "4,3": (.формат, "разделитель дробной части, верхняя граница коридора веса"),
        "16 мг": (.формат, "единицы дозы"),
        "66 мкг": (.формат, "единицы дозы"),

        "Стич": (.пример, "кличка; переводится, у каждого языка своя"),
        "Мама": (.пример, "имя участника семьи"),
        "Когти": (.пример, "дело ухода"),
        "Ницца → Лион": (.пример, "куда едете — свободный текст, города только пример"),
        "Lévothyrox": (.пример, "торговое название; у него перевод существует"),
        "курица, кукуруза": (.пример, "состав корма"),
        "сыр, индейка, мячик": (.пример, "чем награждать"),
        "отель, с собакой можно": (.пример, "где остановиться"),
        "когда стучат по полу": (.пример, "чего боится"),
        "срок действия, кто выдал": (.пример, "что писать про документ"),

        "имя": (.описание, "ярлыка у поля нет, подсказка его заменяет"),
        "название": (.описание, "то же"),
        "добавить": (.описание, "кнопка-поле"),
        "врач или клиника": (.описание, "было «Dr. Ferrand» — имя человека одной страны"),
        "не указан": (.описание, "пусто по-русски согласуется с родом"),
        "не указана": (.описание, "то же, женский род"),
        "необязательно": (.описание, "поле можно пропустить"),
        "можно пропустить": (.описание, "то же"),
        "Свой вопрос…": (.описание, "поле свободного ввода"),
        "что-то заметила": (.описание, "заметка"),
    ]

    private func подсказки() throws -> Set<String> {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo")
        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        let образец = try NSRegularExpression(pattern: #"TextField\("([^"]+)""#)

        var найдено: Set<String> = []
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
            let диапазон = NSRange(текст.startIndex..., in: текст)
            for совпадение in образец.matches(in: текст, range: диапазон) {
                if let r = Range(совпадение.range(at: 1), in: текст) {
                    найдено.insert(String(текст[r]))
                }
            }
        }
        return найдено
    }

    private func каталог() throws -> [String: [String: String]] {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: url))
            as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]
        var собрано: [String: [String: String]] = [:]
        for (ключ, запись) in строки {
            let локализации = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
            собрано[ключ] = локализации.compactMapValues {
                (($0 as? [String: Any])?["stringUnit"] as? [String: Any])?["value"] as? String
            }
        }
        return собрано
    }

    @Test("Каждая подсказка в коде названа в списке решений")
    func решениеПринято() throws {
        let вКоде = try подсказки()
        #expect(вКоде.count > 15, "подсказок найдено \(вКоде.count) — разбор не состоялся")

        let безРешения = вКоде.subtracting(Self.решения.keys).sorted()
        #expect(безРешения.isEmpty, """
            появилась подсказка, о которой не подумали: \(безРешения)

            Ответь на один вопрос и впиши решение:
              · человек обязан ей СООТВЕТСТВОВАТЬ (формат, единицы) —
                тогда привязки к стране быть не должно;
              · это ПРИМЕР, который можно проигнорировать — тогда
                переводится, и переводчик вправе взять местный;
              · это ОПИСАНИЕ поля — переводится как обычный текст.

            Четыре французских подсказки нашлись порознь за один день.
            Пятая найдётся завтра, если решение не записать.
            """)

        let протухшие = Set(Self.решения.keys).subtracting(вКоде).sorted()
        #expect(протухшие.isEmpty,
                "в списке числятся подсказки, которых в коде нет: \(протухшие). Убери их.")
    }

    /// Формат — это то, чему человек обязан соответствовать, и ошибка
    /// в нём делает поле неверным, а не неузнаваемым.
    @Test("В подсказках-форматах нет привязки к стране")
    func форматыНейтральны() throws {
        let плохие = Self.решения
            .filter { $0.value.0 == .формат }
            .map(\.key)
            .filter { $0.range(of: "^\\s*\\+[0-9]", options: .regularExpression) != nil }
            .sorted()
        #expect(плохие.isEmpty, """
            в подсказке-формате стоит код страны: \(плохие).
            Это предположение о том, где человек живёт; переводить его
            нельзя — перевод закрепит «язык значит страна».
            """)
    }

    /// Пример обязан быть переведён: непереведённый пример — это
    /// чужой язык посреди своего экрана, и выглядит он намеренным.
    @Test("Примеры переведены на все языки")
    func примерыПереведены() throws {
        let каталог = try каталог()
        let языки = Set(каталог.values.flatMap(\.keys)).subtracting(["ru"])

        var пробелы: [String] = []
        for (ключ, решение) in Self.решения where решение.0 == .пример {
            guard let переводы = каталог[ключ] else {
                пробелы.append("  «\(ключ)» — в каталоге нет вовсе")
                continue
            }
            for язык in языки.sorted() where переводы[язык] == nil {
                пробелы.append("  [\(язык)] «\(ключ)»")
            }
        }

        #expect(пробелы.isEmpty, """
            пример не переведён:

            \(пробелы.joined(separator: "\n"))

            Непереведённая подсказка откатится на язык разработки:
            человек прочитает русский посреди своего экрана.
            """)
    }

    @Test("У каждого решения записана причина")
    func причиныЕсть() {
        let безПричины = Self.решения.filter { $0.value.1.isEmpty }.map(\.key).sorted()
        #expect(безПричины.isEmpty, "решение без причины: \(безПричины)")
    }
}
