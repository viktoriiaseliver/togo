    @Test("В подсказках-форматах нет привязки к стране")
    func форматыНейтральны() throws {
        let плохие = Self.решения
            .filter { $0.value.0 == .формат }
            .map(\.key)
            .filter { $0.range(of: "^\\s*\\+[0-9]", options: .regularExpression) != nil }
            .sorted()
        #expect(плохие.isEmpty, """
            в подсказке-формате стоит код страны: \(плохие).
            Это предположение о том, где человек живёт; переводить его
            нельзя — перевод закрепит «язык значит страна».
            """)
    }

    /// Пример обязан быть переведён: непереведённый пример — это
    /// чужой язык посреди своего экрана, и выглядит он намеренным.
    ///
    /// Исключение одно и с адресом: ключ, у которого в каталоге стоит
    /// `shouldTranslate: false` **и названа причина** — см.
    /// `непереводимые()`.
    @Test("Примеры переведены на все языки")
    func примерыПереведены() throws {
        let каталог = try каталог()
        let пометки = try непереводимые()
        let языки = Set(каталог.values.flatMap(\.keys)).subtracting(["ru"])

        // Своё зрение первым. У соседнего теста такой порог есть, у этого
        // не было: убери из каталога en/fr/uk — множество `языки` станет
        // пустым, цикл не выполнится ни разу, и сторож объявит себя
        // зелёным, не проверив ничего. Три языка держат две записи
        // эталона с хозяином «перевод»; возвращаются они версией 1.1.
        #expect(языки.count >= 3, """
            языков в каталоге найдено \(языки.count) — \
            \(языки.sorted().joined(separator: ", ")). Разбор не состоялся: \
            сторож проверил бы ноль пар и позеленел.
            """)

        var пробелы: [String] = []
        for (ключ, решение) in Self.решения where решение.0 == .пример {
            // Решение «не переводится» с названной причиной — исполнение,
            // а не пробел. Пометка без причины сюда не попадает.
            if пометки[ключ] != nil { continue }
            guard let переводы = каталог[ключ] else {
                пробелы.append("  «\(ключ)» — в каталоге нет вовсе")
                continue
            }
            for язык in языки.sorted() where переводы[язык] == nil {
                пробелы.append("  [\(язык)] «\(ключ)»")
            }
        }

        #expect(пробелы.isEmpty, """
            пример не переведён:

            \(пробелы.joined(separator: "\n"))

            Непереведённая подсказка откатится на язык разработки:
            человек прочитает русский посреди своего экрана.
            """)
    }

    @Test("У каждого решения записана причина")
    func причиныЕсть() {
        let безПричины = Self.решения.filter { $0.value.1.isEmpty }.map(\.key).sorted()
        #expect(безПричины.isEmpty, "решение без причины: \(безПричины)")
    }
