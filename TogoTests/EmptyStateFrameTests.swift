                (ждём цвет \(String(format: "#%06X", контур))).
                Кадр: \(путь.path)
                """)
        }
    }

    /// Акцент переведён на индиго 07.10.2026 (`8f4d353`). Деталь
    /// иллюстрации обязана поехать за токеном **сама** — в этом и был
    /// смысл двух слоёв-шаблонов вместо запечённого цвета.
    @Test("Смена акцента доезжает до детали без пересборки картинок")
    func акцентДоезжает() throws {
        let акцент = цвет(Token.Action.primary, тёмная: false)
        let лайм = цвет(Color(red: 0xD4 / 255, green: 0xF7 / 255, blue: 0x5F / 255), тёмная: false)

        let (путь, кадр) = try снять(карточка(.history), имя: "история-light", схема: .light)

        #expect(кадр.сколько(близко: акцент) > 100,
                "деталь не покрашена текущим акцентом. Кадр: \(путь.path)")
        #expect(кадр.сколько(близко: лайм, допуск: 24) == 0, """
            на кадре остался прежний лайм `#D4F75F`.
            Значит цвет где-то запечён, и смена акцента до детали
            не доезжает — а два слоя-шаблона заведены ровно затем,
            чтобы доезжала. Кадр: \(путь.path)
            """)
    }

    // MARK: - Шапка-плакат

    /// Заголовок шапки читается на её же подложке — замером, не доводом.
    ///
    /// У плаката ТРИ семьи текста, и у токенов это написано прямо:
    /// `Poster.label` честен только на нейтральном блоке, на синем
    /// в светлой даёт **3,15**, а `Poster.caption` — **1,10**. Блок
    /// шапки цветной всегда. Перепутать семью здесь — это не опечатка,
    /// а нечитаемый заголовок экрана, и текстовый сторож такого
    /// не видит: имя токена в обоих случаях на месте.
    @Test("Шапка-плакат: заголовок и подзаголовок читаются на подложке")
    func шапкаЧитается() throws {
        func яркость(_ c: UInt32) -> Double {
            func к(_ x: UInt32) -> Double {
                let v = Double(x) / 255
                return v <= 0.04045 ? v / 12.92 : pow((v + 0.055) / 1.055, 2.4)
            }
            return 0.2126 * к((c >> 16) & 0xFF) + 0.7152 * к((c >> 8) & 0xFF)
                 + 0.0722 * к(c & 0xFF)
        }
        func контраст(_ a: UInt32, _ b: UInt32) -> Double {
            let (la, lb) = (яркость(a), яркость(b))
            return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
        }

        for (тёмная, подпись) in [(false, "светлая"), (true, "тёмная")] {
            let фон = цвет(Token.Poster.background, тёмная: тёмная)
            let заголовок = цвет(Token.Poster.labelOnColor, тёмная: тёмная)
            let подзаголовок = цвет(Token.Poster.captionOnColor, тёмная: тёмная)

            let (путь, кадр) = try снять(
                TGPosterHeader(title: "Настройки",
                               subtitle: "Язык, уведомления, перенос"),
                имя: "шапка-\(подпись)", схема: тёмная ? .dark : .light)

            #expect(кадр.сколько(близко: фон) > 1000,
                    "подложка шапки не залита `--poster-bg`. Кадр: \(путь.path)")
            #expect(кадр.сколько(близко: заголовок) > 100, """
                заголовок шапки не нарисован `labelOnColor` (\(подпись)).
                Если он взял `label` — на синем это 3,15, то есть
                заголовок экрана не читается. Кадр: \(путь.path)
                """)

            let кЗаголовка = контраст(заголовок, фон)
            let кПодписи = контраст(подзаголовок, фон)
            #expect(кЗаголовка >= 4.5, """
                заголовок шапки \(String(format: "%.2f", кЗаголовка)):1
                на подложке (\(подпись)). Кадр: \(путь.path)
                """)
            #expect(кПодписи >= 4.5, """
                подзаголовок шапки \(String(format: "%.2f", кПодписи)):1
                на подложке (\(подпись)). Кадр: \(путь.path)
                """)
            print("шапка \(подпись): фон #\(String(format: "%06X", фон)) · "
                  + "заголовок \(String(format: "%.2f", кЗаголовка)):1 · "
                  + "подпись \(String(format: "%.2f", кПодписи)):1 · \(путь.lastPathComponent)")
        }
    }

    @Test("Границы: чего не проверяет набор кадров пустых состояний")
    func границыНазваны() {
        // · Он мерит ЦВЕТ и счёт пикселей, а не рисунок. Что на кадре
        //   собака с предметом, а не клякса, видит только человек —
        //   кадр для этого и лежит файлом.
        // · Он мерит СВЕТЛУЮ тему. Тёмная, Dark HC и Light HC
        //   не сняты: для них нужен свой порог, а порог без замера —
        //   догадка.
        // · Он не ловит, что `Tools/иллюстрации.py` разложил слои
        //   по смыслу: инструмент делит по ЦВЕТУ, и ошейник
        //   контурного цвета уедет в контур. На кадре это видно
        //   глазом, а счётом пикселей — нет.
        // · Он не проверяет вид на устройстве: `ImageRenderer` рисует
        //   вне экрана, и системные эффекты (вибрантность, увеличенный
        //   шрифт) в кадр не попадают.
        #expect(Bool(true))
    }
