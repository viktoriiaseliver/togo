/// Кадр пустого состояния — снят, положен файлом и ЗАМЕРЕН.
///
/// **Зачем отдельно от текстового сторожа.** `EmptyStateIllustrationTests`
/// доказывает, что таблица одна и что экран не выбирает картинку.
/// Он не видит, нарисуется ли она: два слоя-шаблона красятся токенами
/// на отрисовке, и «значение верное, а вызов бессильный» у нас оплачено
/// кнопкой с контрастом 1,68:1 — токен был верен всегда, а `foregroundStyle`
/// предка побеждался стилем текста.
///
/// **Почему файлом, а не вложением.** `XCTAttachment` у нас измерен:
/// `xcresulttool export attachments` не выгрузился пять раз из девяти,
/// пакет `.xcresult` остаётся без `Info.plist`. Вложение, которое
/// не выгружается, — это кадр, которого нет. Здесь кадр пишется прямо
/// в дерево, и путь печатается в сообщении проверки: сообщение попадает
/// в лог всегда.
///
/// **И почему замер, а не взгляд.** Глаз соглашается с тем, что привык
/// видеть: кадры той кнопки снимались и раньше, подпись читали глазами
/// и соглашались. Поэтому здесь считаются пиксели, а на кадр я смотрю
/// отдельно — одно не заменяет другого.
/// **Имя набора шире имени файла нарочно.** Файл завёлся под пустые
/// состояния, а растеризация с замером пикселя понадобилась и шапке-
/// плакату. Разносить по файлам значило бы завести вторую копию
/// `снять`/`Кадр`/`цвет` — а два разбора одного вида у нас сегодня
/// уже ломались об одну кавычку, и два разрешителя цвета завелись
/// за четыре минуты. Пока помощники одни, набор один; имя приведено
/// к тому, что он проверяет, а не к тому, как назван файл.
@Suite("Кадры дизайна: что нарисовано и каким цветом")
@MainActor
struct EmptyStateFrameTests {

    /// Куда ложатся кадры. В дереве, а не в `.xcresult`.
    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/кадры-пустых-состояний")
    }

    /// Разобранный кадр: ширина, высота и счёт пикселей по цвету.
    private struct Кадр {
        let ширина: Int
        let высота: Int
        let пиксели: [UInt32]  // 0xRRGGBB

        func сколько(близко цель: UInt32, допуск: Int = 10) -> Int {
            пиксели.filter { расстояние($0, цель) <= допуск }.count
        }

        private func расстояние(_ a: UInt32, _ b: UInt32) -> Int {
            let dr = abs(Int((a >> 16) & 0xFF) - Int((b >> 16) & 0xFF))
            let dg = abs(Int((a >> 8) & 0xFF) - Int((b >> 8) & 0xFF))
            let db = abs(Int(a & 0xFF) - Int(b & 0xFF))
            return max(dr, max(dg, db))
        }
    }

    /// Цвет токена в заданной теме.
    ///
    /// **Замер, а не механизм.** Первая редакция просила светлую тему
    /// и получала тёмное значение: для `Token.Action.primary`
    /// (`Dyn(dark: 0xA2C1FE, light: 0x0E14A1)`) она вернула `#A2C1FE`.
    /// **Почему — не установлено:** соседний `resolvedHex` строит
    /// `UIColor(self).resolvedColor(with:)` так же и отвечает верно.
    /// Разница была где-то ещё, и выдумывать объяснение вместо замера
    /// я не стал — сегодня это уже стоило одной ложной записи
    /// в правилах.
    ///
    /// Цена ошибки была не в числе. Отрисовка уехала в тёмную тему
    /// ровно так же — и ожидание сошлось с кадром, потому что **обе
    /// половины сломались одинаково**. Проверка прошла, подпись
    /// «светлая тема» в выводе была ложной, и поймал это не замер,
    /// а взгляд на кадр.
    ///
    /// > Две половины проверки, сломанные одинаково, подтверждают
    /// > друг друга.
    ///
    /// **Разрешитель не свой.** `Color.resolvedHex(dark:highContrast:)`
    /// завёлся в `00ac9a3` за четыре минуты до первой редакции этого
    /// файла, и у него четыре режима и RGBA, а у моего было две темы
    /// и отброшенная альфа. Половина тёмных токенов задана долей
    /// белого — на полупрозрачном мой отдал бы цвет, которого на экране
    /// нет.
    ///
    /// Форма дня: утром два разбора литералов сломались об одну
    /// кавычку, к вечеру завелись два разрешителя цвета. Третья
    /// реализация сломается так же — поэтому не своя.
    private func цвет(_ c: Color, тёмная: Bool) -> UInt32 {
        c.resolvedHex(dark: тёмная, highContrast: false) >> 8  // RGBA → RGB
    }

    /// Снять кадр вида и положить файлом. Возвращает путь и разбор.
    private func снять<V: View>(_ вид: V, имя: String,
                                схема: ColorScheme) throws -> (путь: URL, кадр: Кадр) {
        // `.environment(\.colorScheme,)` одного мало: токены —
        // динамические `UIColor`, и разрешаются они по
        // `UITraitCollection.current`, а не по окружению SwiftUI.
        // Поэтому отрисовка идёт ВНУТРИ нужной коллекции.
        // `performAsCurrent` возвращает `Void` — значение из него
        // выносится переменной снаружи. Первая редакция ждала от него
        // результат, и компилятор вместо прямой ошибки сказал
        // «unable to type-check this expression in reasonable time»:
        // он перебирал перегрузки, пытаясь согласовать `UIImage`
        // с `Void`. Сообщение про время — СЛЕДСТВИЕ, а причина
        // в строке, на которую оно не указывает.
        let стиль: UIUserInterfaceStyle = схема == .dark ? .dark : .light
        var нарисованное: UIImage?
        UITraitCollection(userInterfaceStyle: стиль).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, схема)
                    .frame(width: 360)
                    .background(Color(white: схема == .dark ? 0.04 : 1))
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }

        let картинка = try #require(нарисованное, "ImageRenderer не отдал картинку")
        let данные = try #require(картинка.pngData(), "картинка не превратилась в PNG")

        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        let путь = Self.каталог.appendingPathComponent("\(имя).png")
        try данные.write(to: путь)

        // Разбор в известный формат: читать байты у чужого
        // `cgImage.dataProvider` — значит верить его порядку каналов.
        let cg = try #require(картинка.cgImage)
        let ш = cg.width, в = cg.height
        var байты = [UInt8](repeating: 0, count: ш * в * 4)
        let пространство = CGColorSpace(name: CGColorSpace.sRGB)!
        let контекст = try #require(CGContext(
            data: &байты, width: ш, height: в, bitsPerComponent: 8,
            bytesPerRow: ш * 4, space: пространство,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        контекст.draw(cg, in: CGRect(x: 0, y: 0, width: ш, height: в))

        var пиксели = [UInt32](); пиксели.reserveCapacity(ш * в)
        for i in stride(from: 0, to: байты.count, by: 4) {
            пиксели.append((UInt32(байты[i]) << 16)
                           | (UInt32(байты[i + 1]) << 8)
                           | UInt32(байты[i + 2]))
        }
        return (путь, Кадр(ширина: ш, высота: в, пиксели: пиксели))
    }

    private func карточка(_ предмет: EmptyStateCard.Subject) -> some View {
        EmptyStateCard(subject: предмет,
                       title: "Заголовок",
                       message: "Строка пояснения, которая объясняет, почему пусто.",
                       actionTitle: "Действие",
                       action: {})
    }

    /// Предметы, у которых по таблице стоит иллюстрация.
    private var сИллюстрацией: [(EmptyStateCard.Subject, TGIllustration.Scene)] {
        EmptyStateCard.Subject.allCases.compactMap { предмет in
            if case .illustration(let сцена) = предмет.look { return (предмет, сцена) }
            return nil
        }
    }

    @Test("Снимать было что: иллюстрации стоят не на нуле предметов")
    func былоЧтоСнимать() {
        #expect(сИллюстрацией.count >= 5, """
            предметов с иллюстрацией \(сИллюстрацией.count), а таблица
            заводилась с пятью. Меньше — значит либо таблицу урезали,
            либо `look` перестал отдавать `.illustration`, и замеры ниже
            зелены потому, что им нечего мерить.
            """)
    }

    /// Кадр снят в ТОЙ теме, которую просили, — и это измерено,
    /// а не написано в подписи.
    ///
    /// Первая редакция набора просила светлую, получала тёмную
    /// и печатала «КАДРЫ (светлая тема)». Числа при этом сходились:
    /// ожидание разрешалось в ту же тёмную тему. Проверки темы
    /// не было вовсе — её заменял ярлык в строке вывода.
    @Test("Кадр снят в той теме, которую просили")
    func темаТа() throws {
        func преобладающий(_ кадр: Кадр) -> Double {
            var счёт: [UInt32: Int] = [:]
            for (i, p) in кадр.пиксели.enumerated() where i % 7 == 0 {
                счёт[p, default: 0] += 1
            }
            let цвет = счёт.max { $0.value < $1.value }?.key ?? 0
            let r = Double((цвет >> 16) & 0xFF) / 255
            let g = Double((цвет >> 8) & 0xFF) / 255
            let b = Double(цвет & 0xFF) / 255
            return 0.2126 * r + 0.7152 * g + 0.0722 * b
        }

        let (путьСвет, светлый) = try снять(карточка(.history),
                                            имя: "history-светлая", схема: .light)
        let (путьТьма, тёмный) = try снять(карточка(.history),
                                           имя: "history-тёмная", схема: .dark)

        let яС = преобладающий(светлый), яТ = преобладающий(тёмный)
        #expect(яС > яТ, """
            преобладающий тон светлого кадра \(String(format: "%.3f", яС))
            не светлее тёмного \(String(format: "%.3f", яТ)).

            Значит тема не доехала до токенов, и остальные замеры этого
            набора мерят не ту тему, о которой говорят. `ImageRenderer`
            слушает `UITraitCollection.current`, а не `\\.colorScheme`.

            Кадры: \(путьСвет.path)
                   \(путьТьма.path)
            """)
        #expect(яС > 0.5, "светлый кадр не светлый: преобладает \(яС)")
        #expect(яТ < 0.3, "тёмный кадр не тёмный: преобладает \(яТ)")
    }

    @Test("Деталь иллюстрации нарисована АКЦЕНТОМ, а не чем попало")
    func детальАкцентом() throws {
        let акцент = цвет(Token.Action.primary, тёмная: false)
        var доклад: [String] = []

        for (предмет, сцена) in сИллюстрацией {
            let (путь, кадр) = try снять(карточка(предмет),
                                         имя: "\(предмет.rawValue)-light",
                                         схема: .light)
            let сколько = кадр.сколько(близко: акцент)
            доклад.append("  \(предмет.rawValue) → \(сцена.rawValue): "
                          + "акцентных пикселей \(сколько) · \(путь.lastPathComponent)")

            #expect(сколько > 100, """
                на кадре `\(предмет.rawValue)` акцентных пикселей \(сколько).

                Слой детали не нарисовался или покрашен не акцентом.
                Это ровно тот случай, который текстовый сторож
                не видит: имя упомянуто, а от упоминания ничего
                не происходит.

                Кадр лежит: \(путь.path)
                """)
        }

        // Пути — в сообщение, а не во вложение: сообщение доезжает всегда.
        print("""
            КАДРЫ (светлая тема), акцент \(String(format: "#%06X", акцент)):
            \(доклад.joined(separator: "\n"))
            Каталог: \(Self.каталог.path)
            """)
    }

    @Test("Контур иллюстрации нарисован приглушёнными чернилами")
    func контурЧернилами() throws {
        let контур = цвет(Token.Ink.secondary, тёмная: false)
        for (предмет, _) in сИллюстрацией {
            let (путь, кадр) = try снять(карточка(предмет),
