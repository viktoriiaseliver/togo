import SwiftData
@testable import Togo

/// Одна доза на слот схемы — после приёма записи от второго телефона.
///
/// **Почему этот набор заведён отдельно от `SharedDiarySyncTests`.**
/// Там уже есть два теста, которые выглядят приёмкой ровно этого места
/// и покраснеть на нём не могут по устройству:
///
/// ```
/// resendKeepsForeignGiven:228     let id = UUID()  — ОДИН id подставлен
///                                 обеим сторонам, то есть проверяется
///                                 слияние, когда id УЖЕ совпали
/// foreignGivenReachesTheDose:1288 #expect(doses.count == 1) — единица
///                                 выходит потому, что своей дозы
///                                 у телефона нет: тест её не заводит
/// ```
///
/// Оба зелёные, и оба зелены по причине, не связанной с дефектом.
/// Это наш записанный класс целиком: **проверка от утверждения,
/// которого дефект не нарушает.** Тест сам подставляет совпадающий id —
/// то самое, что в жизни не совпадает.
///
/// **Что в жизни.** `DoseRecord.id` — свежий `UUID()` у каждого телефона
/// (`Care.swift`), а `DoseScheduler.ensureDoses` заводит отметки лениво,
/// **при открытии экрана**, дедуплицируя по паре (схема, минута),
/// а не по `id`. Приём чужой дозы ищет только
/// `#Predicate { $0.id == id }`, и `SharedDiaryMerge.resolve`
/// начинается с `precondition(local.id == remote.id)`. Значит два
/// телефона, оба открывшие «Сегодня», держат **две** записи на один
/// слот, и спор между ними не формулирует никто.
///
/// Цена — не путаница в дневнике:
///
/// ```
/// alarmingDose  видит неотмеченную дозу → красное «не отмечена»
///               стоит, хотя таблетку дали
/// markGiven     берёт .first из двух, порядок не наш → приём
///               отмечается второй раз → ВТОРАЯ ТАБЛЕТКА
/// ```
///
/// **Требование сформулировано утвердительно, и это не стиль.**
/// «Дозы не дублируются» выполнялось бы и при отсутствии доз вовсе —
/// у нас это уже стоило порога 0 на Kvit, где «уходят не все» было
/// истинно при «не уходит ни одна».
/// # Чего эта починка НЕ закрывает, и оба случая найдены прогоном
///
/// Выяснилось не чтением: первый прогон ПОСЛЕ починки остался красным,
/// и разбор дал две границы. Ни одна не лечится устойчивым id в его
/// нынешнем виде, и обе названы здесь, чтобы следующий не считал
/// вопрос закрытым.
///
/// **1. Оба телефона обязаны иметь эту починку.** id выводится
/// из (схема, слот) на той стороне, которая запись создаёт. Телефон
/// без починки пришлёт случайный id, и дубль вернётся — то есть
/// Виктория на 274 и мама на 273 расходятся по-прежнему. Это цена
/// перехода, а не дефект, но она существует и её надо назвать вслух
/// при раздаче.
///
/// **2. Схема должна быть ОДНА, а не одноимённая.** id выводится
/// из `medication.id`, и если каждый завёл расписание своей рукой,
/// `id` у схем разные → выведенные id доз разные → дубль возвращается.
/// Обмен это допускает нарочно: `SharedDiaryInbox.medication(for:)`
/// ищет схему **по имени**, когда `id` не подошёл, — значит проект
/// уже признал имя ключом на тот случай, когда id разошлись.
///
/// > **Устойчивый id выведен из величины, которая сама по себе
/// > не обязана совпадать у двоих.** Он сходится там, где схема
/// > приехала обменом, и расходится там, где её набрали дважды.
///
/// Чинится это не здесь: либо выводить id из нормализованного ИМЕНИ
/// схемы (но имя правят, и тогда id поедет), либо сперва сливать
/// одноимённые схемы, а id оставить как есть. Выбор архитектурный,
/// за менеджером и Викторией; тестировщик его не делает.
@Suite("Общий дневник · одна доза на слот")
@MainActor
struct ДозаОдинНаСлотTests {

    /// Схема на 08:00, собака на лечении.
    private func setup() throws -> (ModelContext, Dog, Medication, Date) {
        let container = try ModelContainer(
            for: Dog.self,
            configurations: ModelConfiguration(isStoredInMemoryOnly: true)
        )
        let context = ModelContext(container)

        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.isOnTreatment = true
        context.insert(dog)

        let схема = Medication(name: "Ветмедин", doseText: "1 таб", times: [8 * 60])
        схема.dog = dog
        context.insert(схема)
        try context.save()

        let день = Calendar.current.startOfDay(for: Date())
        return (context, dog, схема, день)
    }

    /// Чужая доза на тот же слот — так, как её завёл бы **второй телефон
    /// с этой же починкой**: id выведен из (схема, слот), а не случайный.
    ///
    /// **Первая редакция этого помощника ставила `id: UUID()`, и тест
    /// остался красным после починки.** Причина не в починке: случайный
    /// id здесь описывал телефон, у которого починки НЕТ. Сам замер был
    /// верен, а сценарий — не тот, который чинили.
    ///
    /// > **Тест, моделирующий непочиненного соседа, не проверяет
    /// > починку.** Он проверяет совместимость версий, и это другой
    /// > вопрос — он ниже, отдельным тестом и с названной ценой.
    private func чужаяДоза(схема: Medication, слот: Date,
                           дано: Date?) -> DosePayload {
        DosePayload(
            id: DoseRecord.устойчивыйID(medication: схема.id, scheduledAt: слот),
            medicationID: схема.id, medicationName: схема.name,
            scheduledAt: слот, givenAt: дано, givenBy: дано == nil ? nil : "Мама",
            skippedAt: nil, skippedBy: nil, claimedBy: nil, claimedAt: nil,
            cancelledAt: nil, cancelReason: nil, changedAt: Date()
        )
    }

    private func дозыНаСлоте(_ схема: Medication, слот: Date) -> [DoseRecord] {
        схема.doses.filter {
            Calendar.current.isDate($0.scheduledAt, equalTo: слот,
                                    toGranularity: .minute)
        }
    }

    @Test("На слоте схемы ровно одна доза после приёма записи от второго телефона")
    func однаДозаНаСлот() throws {
        let (context, dog, схема, день) = try setup()
        let слот = Calendar.current.date(minuteOfDay: 8 * 60, on: день)

        // Наш телефон открыл «Сегодня» — отметка заводится здесь,
        // а не руками: руками подставленный id и есть то, чем слепы
        // два прежних теста.
        DoseScheduler.ensureDoses(for: dog, on: день, context: context)

        // Проверка, что этому тесту БЫЛО ЧТО ПРОВЕРЯТЬ. Без неё
        // требование ниже выполнялось бы на пустом месте: ноль доз
        // плюс одна приехавшая — это тоже «ровно одна».
        #expect(дозыНаСлоте(схема, слот: слот).count == 1,
                "сценарий не наполнился: ensureDoses не завела свою дозу, и дальше проверять нечего")

        // Мамин телефон завёл свою отметку на тот же слот и дал таблетку.
        let чужая = чужаяДоза(схема: схема, слот: слот,
                              дано: слот.addingTimeInterval(5 * 60))
        SharedDiaryInbox.accept(чужая, medication: схема, context: context)

        #expect(дозыНаСлоте(схема, слот: слот).count == 1, """
            на один слот схемы приходится больше одной отметки.
            Два телефона завели дозу каждый со своим UUID, а приём ищет
            только по id — значит markGiven возьмёт .first из двух
            и даст вторую таблетку.
            """)
    }

    @Test("Чужая отметка гасит баннер у второго человека")
    func чужоеДаноГаситБаннер() throws {
        let (context, dog, схема, день) = try setup()
        let слот = Calendar.current.date(minuteOfDay: 8 * 60, on: день)
        // Час, в который доза уже просрочена: эскалация со второй ступени.
        let сейчас = слот.addingTimeInterval(40 * 60)

        DoseScheduler.ensureDoses(for: dog, on: день, context: context)

        #expect(DoseScheduler.alarmingDose(among: [схема], now: сейчас) != nil,
                "сценарий не наполнился: без своей просроченной дозы гасить нечего")

        SharedDiaryInbox.accept(
            чужаяДоза(схема: схема, слот: слот, дано: слот.addingTimeInterval(5 * 60)),
            medication: схема, context: context
        )

        #expect(DoseScheduler.alarmingDose(among: [схема], now: сейчас) == nil, """
            таблетку дали, а красное «не отмечена» осталось.
            Своя неотмеченная доза живёт рядом с приехавшей отмеченной
            и выигрывает у alarmingDose как самая ранняя неотмеченная.
            """)
    }

    /// **Этот тест осмыслен только ПОСЛЕ детерминированного id, и его
    /// зелень до починки ничего не значила.**
    ///
    /// Прогон 08.10.2026 на `15f7f08`, до правки: два соседа покраснели,
    /// а этот **прошёл при живом дефекте**. `markGiven` берёт `.first`
    /// из связи `medication.doses`, и **порядок в ней не наш** — из двух
    /// отметок он взял приехавшую отмеченную. Повезло.
    ///
    /// > **Тест, исход которого решает неопределённый порядок, способен
    /// > зеленеть при живом дефекте — то есть он хуже отсутствующего.**
    /// > Ровно за это сняты `resendKeepsForeignGiven`
    /// > и `foreignGivenReachesTheDose`, и этот был третьим в том же ряду.
    ///
    /// Он оставлен **потому, что id теперь детерминированный**: отметка
    /// на слоте одна, `.first` однозначен, и выбор перестал быть
    /// лотереей. Не чини его «стабилизацией порядка» и не читай его
    /// зелень как доказательство, что порядок не важен: порядок важен,
    /// просто выбирать больше не из чего.
    @Test("Отметка приёма находит ту же дозу, которую отметил второй человек")
    func приёмНеСоздаётВторуюОтметку() throws {
        let (context, dog, схема, день) = try setup()
        let слот = Calendar.current.date(minuteOfDay: 8 * 60, on: день)

        DoseScheduler.ensureDoses(for: dog, on: день, context: context)
        SharedDiaryInbox.accept(
            чужаяДоза(схема: схема, слот: слот, дано: слот.addingTimeInterval(5 * 60)),
            medication: схема, context: context
        )

        // Виктория жмёт «дано» на том же слоте, не зная о маме.
        let отмеченная = DoseScheduler.markGiven(
            схема, scheduledAt: слот, by: "Виктория",
            at: слот.addingTimeInterval(45 * 60), context: context
        )

        #expect(отмеченная?.givenBy == "Мама", """
            приём попал в НАШУ пустую отметку вместо приехавшей:
            защита от двойной дозы смотрит на одну запись из двух,
            и человек даёт вторую таблетку, получив подтверждение.
            """)
    }
}
