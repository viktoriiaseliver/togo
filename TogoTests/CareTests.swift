import Testing
import Foundation
@testable import Togo

/// Уход бывает трёх разных сортов, и путать их нельзя. Раньше всё лежало
/// одной кучей — и приложение в первый же день кричало «сегодня» про всё
/// сразу, включая купание и комплексную прививку.
@Suite("Уход")
@MainActor
struct CareTests {
    private let calendar = Calendar.current

    private func днейНазад(_ дней: Int) -> Date {
        calendar.date(byAdding: .day, value: -дней, to: .now)!
    }

    // MARK: Каждый день

    @Test("Зубы чистят каждый день — и это привычка, а не просрочка")
    func dailyHasNoOverdue() {
        let зубы = CareTask(title: "Зубы", detail: "каждый день", kind: .daily)

        #expect(зубы.isDue())
        #expect(!зубы.isOverdue(), "у привычки нет долга")
        #expect(зубы.statusText() == "сегодня")
    }

    @Test("Отметили сегодня — дело уходит с главного")
    func dailyDoneToday() {
        let зубы = CareTask(title: "Зубы", detail: "", kind: .daily)
        зубы.markDone()

        #expect(зубы.isDoneToday())
        #expect(!зубы.isDue())
        #expect(зубы.streak == 1)
    }

    @Test("Серия растёт, только если делали вчера")
    func dailyStreak() {
        let зубы = CareTask(title: "Зубы", detail: "", kind: .daily)
        зубы.lastDone = днейНазад(1)
        зубы.streak = 4
        зубы.markDone()
        #expect(зубы.streak == 5)

        let после_пропуска = CareTask(title: "Зубы", detail: "", kind: .daily)
        после_пропуска.lastDone = днейНазад(4)
        после_пропуска.streak = 9
        после_пропуска.markDone()
        #expect(после_пропуска.streak == 1, "пропустил — серия начинается заново")
    }

    @Test("Серия видна в подписи, но не превращается в награду")
    func streakText() {
        let зубы = CareTask(title: "Зубы", detail: "", kind: .daily)
        зубы.lastDone = днейНазад(1)
        зубы.streak = 6
        зубы.markDone()
        #expect(зубы.statusText().contains("7"))
    }

    // MARK: Регулярно

    @Test("Ни разу не делали — это вопрос о дате, а не просрочка")
    func periodicNeverDone() {
        let когти = CareTask(title: "Когти", detail: "", kind: .periodic, intervalDays: 21)

        #expect(когти.isNeverDone)
        #expect(когти.dueDate == nil)
        #expect(!когти.isDue(), "не кричим в первый же день")
        #expect(!когти.isOverdue())
        // Формулировка поменялась: «ещё не делали» было тупиком, теперь
        // приложение спрашивает дату и начинает работать.
        #expect(когти.statusText() == "когда делали?")
    }

    @Test("Срок считается от последнего раза")
    func periodicFromLastDone() {
        let когти = CareTask(title: "Когти", detail: "", kind: .periodic, intervalDays: 21)
        когти.lastDone = днейНазад(10)

        #expect(когти.daysUntilDue() == 11)
        #expect(!когти.isDue())
        #expect(когти.statusText() == "через 11 дней")
    }

    @Test("Просрочка считается и называется по-человечески")
    func periodicOverdue() {
        let когти = CareTask(title: "Когти", detail: "", kind: .periodic, intervalDays: 21)
        когти.lastDone = днейНазад(25)

        #expect(когти.isDue())
        #expect(когти.isOverdue())
        #expect(когти.statusText() == "просрочено на 4 дня")
    }

    @Test("Сезонное вне сезона молчит совсем")
    func seasonalIsSilent() {
        let капли = CareTask(title: "Капли от клещей", detail: "", kind: .periodic,
                             intervalDays: 30, category: .medical)
        капли.seasonStartMonth = 4
        капли.seasonEndMonth = 10
        капли.lastDone = днейНазад(60)

        let январь = calendar.date(from: DateComponents(year: 2026, month: 1, day: 15))!
        #expect(!капли.isDue(on: январь))
        #expect(!капли.isOverdue(on: январь))
        #expect(капли.statusText(on: январь) == "вне сезона")
    }

    // MARK: По дате

    @Test("Прививка живёт по дате, а не «раз в год от последнего раза»")
    func datedTask() {
        let прививка = CareTask(title: "Бешенство", detail: "", kind: .dated,
                                intervalDays: 365, category: .medical)
        прививка.scheduledDate = calendar.date(byAdding: .day, value: 40, to: .now)

        #expect(прививка.daysUntilDue() == 40)
        #expect(!прививка.isDue(), "за 40 дней ещё рано")

        прививка.scheduledDate = calendar.date(byAdding: .day, value: 10, to: .now)
        #expect(прививка.isDue(), "за две недели уже пора напомнить")
    }

    @Test("Сделали прививку — дата уезжает на следующий год")
    func datedRolls() {
        let прививка = CareTask(title: "Бешенство", detail: "", kind: .dated,
                                intervalDays: 365, category: .medical)
        let сегодня = calendar.startOfDay(for: .now)
        прививка.scheduledDate = сегодня
        прививка.markDone()

        let следующая = calendar.dateComponents([.day], from: сегодня,
                                                to: прививка.scheduledDate!).day
        #expect(следующая == 365)
    }

    @Test("Разовый визит не повторяется")
    func datedOnce() {
        let визит = CareTask(title: "Осмотр", detail: "", kind: .dated,
                             intervalDays: 0, category: .medical)
        let дата = calendar.startOfDay(for: .now)
        визит.scheduledDate = дата
        визит.markDone()
        #expect(визит.scheduledDate == дата, "повторять не просили")
    }

    // MARK: Список предложений

    @Test("Предлагаем немного и по делу, а не девять дел разом")
    func suggestionsAreSane() {
        let предложения = SeedData.careSuggestions
        let поумолчанию = предложения.filter(\.isDefault)

        #expect(поумолчанию.count <= 7, "навязывать десяток дел на старте нельзя")
        #expect(предложения.contains { $0.title == "Зубы" && $0.kind == .daily },
                "зубы чистят каждый день")
        #expect(!предложения.contains { $0.title.contains("Уши и зубы") },
                "уши и зубы — разные дела с разной частотой")
        #expect(предложения.contains { $0.kind == .dated }, "прививки живут по дате")
    }

    @Test("Первый запуск не заводит ухода за человека")
    func firstRunAddsNoCare() {
        // Стартовый набор — это вес, а не девять напоминаний.
        // Уход человек выбирает сам, иначе он сразу становится шумом.
        #expect(SeedData.careSuggestions.allSatisfy { !$0.title.isEmpty })
    }
}

// MARK: - Срок годности: правило, которое было написано и не исполнялось

/// Из двух сроков действует ближний, и экран называет, который.
///
/// # Чем оплачено
///
/// Замер 05.11.2026: у `Medication.goodUntil()` **ноль читателей
/// во всём дереве**, включая тесты. При этом человек вводил срок
/// на упаковке (`Editors.swift:1282`) и «годен после вскрытия»
/// (`:1302`), всё сохранялось, а под полями стоял объяснитель
/// «Из двух сроков действует ближний» с комментарием, обещавшим:
/// «Человеку нужно знать правило, чтобы понимать, почему приложение
/// **потом назовёт именно эту дату**».
///
/// > **Дату не называл никто и никогда.** Это четвёртая форма
/// > «механизма без входа»: источник правды содержит решение,
/// > которого не исполняет ни один читатель. Хуже обычного мёртвого
/// > кода тем, что обещание ЧЕЛОВЕКУ уже дано вслух.
///
/// # Почему проверяется `срокГодности`, а не `goodUntil`
///
/// `goodUntil` отдаёт дату и молчит о том, ОТКУДА она. Экрану этого
/// недостаточно: вскрытый флакон портится раньше упаковки, и человек,
/// увидев дату, не совпадающую с флаконом, решит, что приложение
/// ошиблось. Поэтому предмет проверки — «какой срок победил
/// и истёк ли он», а не «минимум из двух».
///
/// Напоминаний здесь нет намеренно: `remindBeforeExpiry` («напомню
/// за месяц до конца срока») читателей по-прежнему не имеет,
/// а `ReminderScheduler` слова `expiry` не содержит вовсе (замер
/// того же дня). Это отдельное решение с отдельной ценой.
@Suite("Срок годности препарата")
struct СрокГодностиПрепаратаTests {

    private func день(_ сдвиг: Int) -> Date {
        Calendar.current.date(byAdding: .day, value: сдвиг,
                              to: Calendar.current.startOfDay(for: Date()))!
    }

    private func препарат() -> Medication {
        Medication(name: "Эутирокс", doseText: "50 мкг", times: [8 * 60])
    }

    // MARK: Контроль первым

    /// Без обоих сроков сказать нечего — и это НЕ «годен бессрочно».
    ///
    /// Контроль, а не проверка: отвечай метод «годен» на пустые поля,
    /// и все проверки ниже мерили бы собственный промах.
    @Test("Без названных сроков строки нет")
    func безСроковНичего() {
        #expect(препарат().срокГодности() == .нет)
    }

    // MARK: Предмет

    /// Один срок — он и действует.
    @Test("Срок с упаковки действует, когда вскрытия нет")
    func толькоУпаковка() {
        let м = препарат()
        м.expiry = день(30)
        #expect(м.срокГодности() == .годен(до: день(30), изВскрытия: false))
    }

    /// **То, ради чего правило написано: вскрытый флакон портится
    /// раньше.**
    @Test("Из двух сроков побеждает вскрытие, когда оно ближе")
    func вскрытиеБлиже() {
        let м = препарат()
        м.expiry = день(300)
        м.openedAt = день(-2)
        м.shelfAfterOpenDays = 28
        #expect(м.срокГодности() == .годен(до: день(26), изВскрытия: true), """
            победил не срок вскрытия. Флакон, вскрытый два дня назад \
            и годный 28 дней после вскрытия, кончается через 26 дней, \
            а не через 300 — и дать собаке испорченный препарат \
            приложение не должно предлагать молча.
            """)
    }

    /// И обратная сторона того же правила, без которой проверка выше
    /// прошла бы у метода, который всегда берёт вскрытие.
    @Test("Вскрытый за месяц до конца годности живёт до конца годности")
    func упаковкаБлиже() {
        let м = препарат()
        м.expiry = день(10)
        м.openedAt = день(0)
        м.shelfAfterOpenDays = 90
        #expect(м.срокГодности() == .годен(до: день(10), изВскрытия: false), """
            победило вскрытие, хотя упаковка кончается раньше. \
            Правило называется «действует БЛИЖНИЙ», и оно \
            двустороннее.
            """)
    }

    /// Истёкший срок — свой случай, а не «годен до вчера».
    ///
    /// Препарат дают собаке: нейтральная справка о прошедшей дате
    /// читается не как «не давай».
    @Test("Прошедший срок читается как истёкший")
    func срокИстёк() {
        let м = препарат()
        м.expiry = день(-1)
        #expect(м.срокГодности() == .истёк(когда: день(-1), изВскрытия: false))
    }

    /// Сегодняшний день — ещё годен. Граница названа явно: срок
    /// годности это ДЕНЬ, и «кончился в полночь» человек не имеет
    /// в виду, когда пишет месяц на упаковке.
    @Test("Последний день срока — ещё годен")
    func последнийДеньГоден() {
        let м = препарат()
        м.expiry = день(0)
        #expect(м.срокГодности() == .годен(до: день(0), изВскрытия: false))
    }

    /// `shelfAfterOpenDays == 0` значит «не указан», а не «портится
    /// в тот же день».
    ///
    /// Иначе человек, отметивший «флакон вскрыт» и не назвавший срок,
    /// немедленно получил бы «срок истёк» — то есть приложение
    /// придумало бы ему дефект.
    @Test("Ноль дней после вскрытия значит «не указан»")
    func нольДнейНеСрок() {
        let м = препарат()
        м.expiry = день(30)
        м.openedAt = день(0)
        м.shelfAfterOpenDays = 0
        #expect(м.срокГодности() == .годен(до: день(30), изВскрытия: false))
    }

    /// **Истечение ОТ ВСКРЫТИЯ при неназванной упаковке** — случай,
    /// которого в первой редакции этого набора не было, а автономный
    /// прогон его взял.
    ///
    /// Он самый правдоподобный из всех: флакон вскрыли сорок дней
    /// назад, срок на упаковке не вводили вовсе. Приложение обязано
    /// сказать и «истёк», и «после вскрытия» — иначе человек пойдёт
    /// искать дату на флаконе и не поймёт, откуда она взялась.
    @Test("Истечение от вскрытия при неназванной упаковке")
    func истёкОтВскрытия() {
        let м = препарат()
        м.openedAt = день(-40)
        м.shelfAfterOpenDays = 28
        #expect(м.срокГодности() == .истёк(когда: день(-12), изВскрытия: true))
    }

    /// Совпали оба срока — пишем «с упаковки».
    ///
    /// Спорить с флаконом приложению незачем: человек видит на нём
    /// ту же дату, и приписка «после вскрытия» только сбила бы.
    @Test("При совпадении сроков источником называется упаковка")
    func совпалиСроки() {
        let м = препарат()
        м.expiry = день(28)
        м.openedAt = день(0)
        м.shelfAfterOpenDays = 28
        #expect(м.срокГодности() == .годен(до: день(28), изВскрытия: false))
    }
}
