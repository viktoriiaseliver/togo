import Testing
import Foundation
@testable import Togo

/// Экран «Дневник не открылся» давал совет, уничтожающий то, что сам
/// же обещал сохранить. Этот набор сторожит, чтобы он не вернулся.
///
/// **Почему сторож обязателен, а не «мы же починили».** `steps` был
/// константой — то есть один текст на все причины отказа. У нас это
/// оплаченный класс: ступень отката iCloud говорила одним текстом
/// на три причины, и совет «включи iCloud Drive» двум из трёх
/// не помогал ничем. Там после починки завели сторожа на «пять причин —
/// пять текстов». Здесь причина была одна на всех, и цена ошибки выше:
/// не неверный совет, а удалённый дневник.
///
/// **Приёмка самого сторожа — подделкой, а не зелёным.** «Сторож есть»
/// и «сторож краснеет на дефекте» — разные утверждения, и сегодня
/// у нас уже был зелёный список исключений, который ничего не проверял.
/// Подделка здесь: вернуть третий пункт безусловным — и `советНеПоявляется`
/// обязан упасть.
@Suite("Совет на экране «Дневник не открылся»")
struct StorageFailureAdviceTests {

    /// Журнал, в котором удачное открытие с зеркалом было.
    private static let журналСОблаком = """
        12:00:01 общая группа есть
        12:00:01 открываю хранилище
        12:00:01 право на iCloud есть, пробую
        12:00:02 \(StorageFailureAdvice.признакОблака)
        """

    /// Журнал без следа облака. **Это не «iCloud нет»** — это
    /// «подтвердить нечем», и разница решает, можно ли советовать снос.
    private static let журналБезОблака = """
        12:00:01 общей группы нет — локально
        12:00:01 открываю хранилище
        12:00:01 права на iCloud нет — только локально (профиль: нет)
        """

    @Test("Признак облака читается из крошек запуска, а не из состояния сейчас")
    func признакИзЖурнала() {
        #expect(StorageFailureAdvice.возврат(журналЗапуска: Self.журналСОблаком) == .подтверждён)
        #expect(StorageFailureAdvice.возврат(журналЗапуска: Self.журналБезОблака) == .неизвестен)

        // Пустой журнал — тоже «неизвестен», а не «нет»: файл мог
        // не записаться вовсе, и по отсутствию строки вывода делать
        // нельзя. У самого `StartupLog` это записано ценой разбора
        // потери данных 28.09.
        #expect(StorageFailureAdvice.возврат(журналЗапуска: "") == .неизвестен)
    }

    @Test("Совет переустановить НЕ появляется, когда возвращать неоткуда")
    func советНеПоявляется() {
        let безОблака = StorageFailureAdvice.шаги(.неизвестен)
        let сОблаком = StorageFailureAdvice.шаги(.подтверждён)

        // Сперва — что проверять БЫЛО ЧТО. Набор, которому нечего
        // проверять, молчит так же, как набор, у которого всё хорошо:
        // пустые шаги прошли бы проверку ниже.
        #expect(безОблака.count >= 2, "шагов \(безОблака.count): безопасные пункты пропали вместе с опасным")
        #expect(сОблаком.count == безОблака.count + 1,
                "с подтверждённым возвратом шагов \(сОблаком.count), без него \(безОблака.count) — разница обязана быть ровно в одном пункте")

        for шаг in безОблака {
            #expect(!шаг.localizedLowercase.contains("переустанов"), """
                совет «переустановить» стоит там, где возвращать неоткуда:
                «\(шаг)»

                Переустановка сносит контейнер App Group. Совет — это
                действие, и его последствие опровергает обещание над ним.
                """)
        }

        #expect(сОблаком.contains { $0.localizedLowercase.contains("переустанов") }, """
            при подтверждённом возврате совета переустановить нет вовсе.
            Сторож, запрещающий совет ВСЕГДА, прошёл бы проверку выше
            и был бы неправ: там, где дневник уезжал в облако,
            переустановка — рабочий выход.
            """)
    }

    @Test("У каждого исхода свой текст, и обещание не переживает совет")
    func текстыРазные() throws {
        let подтв = StorageFailureAdvice.подзаголовок(.подтверждён)
        let неизв = StorageFailureAdvice.подзаголовок(.неизвестен)
        #expect(подтв != неизв, "один подзаголовок на оба исхода — это та же константа, только в другом месте")

        // Обещание «это не потеря данных» держится только там, где есть
        // откуда вернуть. Там, где нет, оно становится ложным ОТ
        // ВЫПОЛНЕНИЯ совета — поэтому его там быть не должно.
        #expect(!неизв.localizedLowercase.contains("не потеря данных"), """
            подзаголовок обещает «это не потеря данных» там, где вернуть
            неоткуда: «\(неизв)»
            """)
        #expect(неизв.localizedLowercase.contains("переустановка"), """
            подзаголовок не называет того единственного, что УНИЧТОЖИТ
            записи: «\(неизв)»
            """)

        #expect(StorageFailureAdvice.предупреждение(.подтверждён) == nil,
                "предупреждение стоит там, где опасности нет — а красное без дефекта учит не верить красному")
        let предупр = try #require(StorageFailureAdvice.предупреждение(.неизвестен))
        #expect(предупр.localizedLowercase.contains("выгруз"), """
            предупреждение не говорит, что выгрузить сейчас НЕЧЕМ:
            «\(предупр)»

            `BackupService.archive(context:)` требует `ModelContext` —
            то самое хранилище, которое не открылось. Совет «сперва
            сохрани файл» выполнить нельзя, и молчать об этом значит
            отправить человека искать кнопку, которой нет.
            """)
    }

    @Test("Признак облака не продублирован литералом: пишущий и читающий смотрят в одну константу")
    func признакНеРаздвоен() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var литералы: [String] = []
        for каталог in ["TogoShared", "Togo", "TogoWidget"] {
            let папка = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                // Файл с определением константы — единственное законное
                // место, где литерал стоит.
                if путь.lastPathComponent == "StorageFailureAdvice.swift" { continue }
                let текст = try String(contentsOf: путь, encoding: .utf8)
                for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                    let t = строка.trimmingCharacters(in: .whitespaces)
                    if t.hasPrefix("//") { continue }
                    if t.contains("\"\(StorageFailureAdvice.признакОблака)\"") {
                        литералы.append("\(путь.lastPathComponent):\(номер + 1)")
                    }
                }
            }
        }
        #expect(литералы.isEmpty, """
            признак облака написан литералом в \(литералы):

            По этой строке экран отказа решает, можно ли советовать
            переустановку. Пишущий и читающий обязаны смотреть в одну
            константу: два места, выражающих одну мысль разными
            литералами, расходятся на второй правке — а ценой
            расхождения здесь будет чужой дневник.
            """)

        print("""
            ГРАНИЦА: этот набор проверяет ТЕКСТЫ и развилку, а не экран.
            Что он НЕ видит: дошли ли эти строки до кадра, не перекрыл ли
            их стиль, и видно ли предупреждение без прокрутки. Утверждение
            о показе принимает только кадр живого экрана.
            """)
    }
}
