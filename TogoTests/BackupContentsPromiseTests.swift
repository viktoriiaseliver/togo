import Testing
import Foundation
@testable import Togo

/// Список «что внутри файла» обещает человеку то, что архив правда
/// хранит.
///
/// **Этот сторож рождён КРАСНЫМ нарочно, и его краснота — находка,
/// а не поломка.** Замер 07.10.2026: список в `BackupScreen` разошёлся
/// с составом снимка в пяти местах из одиннадцати.
///
/// ```
/// обещано и лежит                 6
/// НЕ обещано, но лежит            4   взвешивания, запас, течки, документы
/// НЕ обещано и НЕ лежало          1   выезды  ← починено 07.10
/// ```
///
/// Четыре расхождения «сохраняем больше, чем обещаем» безвредны сами —
/// и **ровно поэтому список не перечитывали: он выглядел скромным,
/// а не неверным.** Четыре молчания прикрывали пятое, из-за которого
/// человек терял все выезды при переезде на новый телефон.
///
/// **Два вида расхождения, и они стоят разного:**
///
/// ```
/// обещано и нет        → человек НЕ находит данные, которые ждал
/// есть и не обещано    → человек не знает, что они есть, и не доверяет файлу
/// ```
///
/// Первое теряет данные, второе теряет доверие к переносу целиком —
/// человек, не нашедший взвешиваний в описании, разумно решит, что
/// архив неполный, и будет искать второй способ.
///
/// **Текст список не правит, и это решение, а не недосмотр.** Виктория
/// заморозила тексты и дизайн 07.10; сторож держит находку числом
/// до разморозки. Иначе к тому дню про пять расхождений будет помнить
/// только переписка.
///
/// **Чинить тогда надо не абзац, а связь:** список обязан выводиться
/// из состава снимка, а не писаться руками. Пока он пишется руками,
/// он отдельная поверхность — и расходится, как всякая вторая копия.
@Suite("Обещание переноса против состава архива")
struct BackupContentsPromiseTests {

    /// Что список обещает — и какой коллекции снимка это соответствует.
    ///
    /// Отображение руками, потому что список написан прозой: «Уход
    /// и напоминания, схемы лечения и отметки приёмов» — одна строка
    /// про три коллекции. Машинно это не выводится, и это ещё один
    /// довод к тому, что список должен собираться из состава, а не
    /// наоборот.
    private static let обещано: [String: [String]] = [
        "Собака: кличка, вес, порода, порция, режим кормления, чем маркируешь": [],
        "Все записи ленты со временем и автором, включая удалённые — со следом": ["events"],
        "Уход и напоминания, схемы лечения и отметки приёмов": ["careTasks", "medications"],
        "Занятия, шаги обучения и накопленный прогресс": ["trainingSteps", "trainingSessions"],
        "Семья: имена, роли и выданные права": [],
        "Поездки и эпизоды": ["trips"],
    ]

    /// Коллекции снимка собаки — из исходника формата, а не списком.
    private func коллекцииСнимка() throws -> Set<String> {
        let файл = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Domain/BackupArchive.swift")
        let текст = try String(contentsOf: файл, encoding: .utf8)
        guard let начало = текст.range(of: "struct DogSnapshot") else { return [] }

        var коллекции: Set<String> = []
        for строка in текст[начало.upperBound...].components(separatedBy: .newlines) {
            if строка.hasPrefix("    }") { break }
            let голая = строка.trimmingCharacters(in: .whitespaces)
            guard голая.hasPrefix("var "),
                  let имя = голая.dropFirst(4).split(separator: ":").first
            else { continue }
            let тип = голая.drop(while: { $0 != ":" }).dropFirst()
                .trimmingCharacters(in: .whitespaces)
            // Коллекция снимков — массив типа `[…Snapshot]`, а не
            // `[Int]` у минут кормления и не `[String]` у запретов.
            guard тип.hasPrefix("["), тип.contains("Snapshot") else { continue }
            коллекции.insert(String(имя))
        }
        return коллекции
    }

    @Test("Список «что внутри файла» сходится с составом снимка")
    func обещаниеСходится() throws {
        let коллекции = try коллекцииСнимка()
        // Сканер, переставший что-либо находить, молчит так же, как
        // тот, кому нечего сказать.
        #expect(коллекции.count >= 10, """
            коллекций снимка разобрано \(коллекции.count) — разбор
            формата не состоялся, и сторож зелен впустую.
            """)

        let названные = Set(Self.обещано.values.flatMap { $0 })
        let необещанные = коллекции.subtracting(названные).sorted()
        let обещанныеВпустую = названные.subtracting(коллекции).sorted()

        #expect(обещанныеВпустую.isEmpty, """
            список обещает то, чего в архиве нет: \(обещанныеВпустую).
            Это худший из двух видов расхождения: человек НЕ НАХОДИТ
            данные, которые ждал, и узнаёт об этом через месяц.
            """)

        #expect(необещанные.isEmpty, """
            архив хранит, а список не обещает: \(необещанные).

            Это и есть находка 07.10.2026, и она держится красной
            НАРОЧНО: текст заморожен решением Виктории, сторож
            удерживает её числом до разморозки.

            Безвредно только на вид. Человек, не нашедший взвешиваний
            в описании файла, разумно решит, что перенос неполный,
            и будет искать второй способ — то есть мы теряем доверие
            к переносу целиком. А главное: ровно такие безвредные
            молчания прикрывали шестое, из-за которого человек терял
            все выезды и узнать об этом не мог.

            Чинить надо НЕ абзац, а связь: список обязан выводиться
            из состава снимка. Пока он пишется руками — он вторая
            копия и будет расходиться.
            """)
    }

    /// Граница: сторож сверяет СОСТАВ, а не полноту каждой коллекции.
    ///
    /// Поле, объявленное в снимке и ни разу не заполненное при сборке,
    /// пройдёт его насквозь. Это ловят круговые тесты `BackupTests`.
    @Test("Границы: сторож обещания сверяет состав, а не полноту коллекций")
    func границыНазваны() throws {
        let коллекции = try коллекцииСнимка()
        #expect(коллекции.contains("daysOut"), """
            выездов в составе снимка нет — либо правка 07.10 откатилась,
            либо разбор формата сломался.
            """)
        #expect(коллекции.contains("weights"), "взвешиваний нет в составе — разбор сломался")
    }
}
