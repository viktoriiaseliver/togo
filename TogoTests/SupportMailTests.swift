import Testing
import Foundation
@testable import Togo

/// «Написать в поддержку» не заканчивается системным алертом.
///
/// Отзыв: «Так же не работает ссылка. Аллерт». `mailto:` на телефоне
/// без настроенной почты не открывается ничем: iOS показывает свой алерт
/// «Нет учётной записи», и на этом всё. Приложение при этом молчало,
/// потому что `openURL(url)` без обработчика не знает, открылось ли.
/// Тупик получался полный: единственный адрес поддержки написан внутри
/// ссылки, которую нельзя открыть, и переписать его вручную неоткуда.
///
/// Мест, где та же строка живёт, два — экран поддержки и экран «Дневник
/// не открылся». Второй хуже: там дневник уже не открылся, и письмо —
/// последняя дверь. Правило проекта требует чинить все поверхности разом,
/// поэтому сторож перебирает оба файла.
@Suite("Письмо в поддержку не упирается в алерт")
struct SupportMailTests {

    private func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    private let поверхности = [
        "Togo/Features/Settings/DataPrivacyScreen.swift",
        "Togo/App/TogoApp.swift",
    ]

    @Test("Обе поверхности узнают, что письмо не открылось")
    func открытиеПроверяется() throws {
        for путь in поверхности {
            let текст = try исходник(путь)
            #expect(текст.contains("openURL(url) { открылось in"), """
                \(путь): `openURL` зовут без обработчика — «не открылось»
                неотличимо от «открылось», и ответом человеку остаётся
                системный алерт, за которым ничего нет.
                """)
            #expect(текст.contains("UIPasteboard.general.string"), """
                \(путь): адресу поддержки некуда деться, когда почты нет.
                Человеку нужен адрес, а не сообщение о неудаче.
                """)
        }
    }

    @Test("Адрес поддержки есть и он один")
    func адресОдин() {
        #expect(!Contacts.support.isEmpty)
        #expect(Contacts.support.contains("@"))
    }

    /// В буфер уходит адрес и диагностика — и ничего о собаке.
    /// Та же красная линия, что у журнала действий и крошек запуска.
    @Test("В буфер не уходит ничего о собаке")
    func вБуфереНетЛичного() throws {
        for путь in поверхности {
            let текст = try исходник(путь)
            #expect(!текст.contains("UIPasteboard.general.string = dog"),
                    "\(путь): в буфер попадает собака")
            #expect(текст.contains("UIPasteboard.general.string ="),
                    "\(путь): буфер перестал быть запасным выходом")
        }
        // Строки запуска — про этапы, а не про содержимое дневника:
        // это проверяет `StartupLogTests`. Здесь только адрес и они.
        let экран = try исходник("Togo/App/TogoApp.swift")
        #expect(экран.contains("StartupLog.read()"), """
            к письму с экрана «Дневник не открылся» перестали прикладывать
            строки запуска — без них причину не воспроизвести.
            """)
    }
}
