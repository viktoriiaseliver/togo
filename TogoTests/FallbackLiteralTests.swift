import Foundation
import Testing

/// Запасное слово в правой части `??` — третий способ обойти каталог.
///
/// **Почему понадобился отдельный сторож.** 07.10.2026 один и тот же
/// класс дефекта искали дважды и двумя разными способами:
/// перечислением поверхностей (нашли 33) и перечислением тех, кто
/// передаёт `dogName:` (нашли 34-ю — заглушку виджета). Запасное
/// значение в `??` не поймал ни один из двух, и не мог:
///
/// ```
/// поверхность   это экран            «собаку» не экран
/// аргумент      это передача         «собаку» никому не передают
/// ??            это ЗНАЧЕНИЕ по умолчанию, когда данных нет
/// ```
///
/// Нашлось оно третьим путём — красным храповиком долга, то есть
/// случайно, и только потому, что `WalkActivityView` переехал
/// в `TogoShared`, куда тот сторож смотрит. В слое приложения такие же
/// строки лежат без присмотра: `LocalizationDebtTests` ходит
/// по `TogoShared` и про `Togo/Features/**` не знает.
///
/// > **Два перечисления, сошедшиеся на одном классе, не доказывают,
/// > что класс исчерпан.** Они доказывают, что исчерпаны два способа
/// > перечислять.
///
/// **Почему условие такое, а не то, с которым сторожа заказывали.**
/// Заказана была тройка: литерал в правой части `??`, **рядом
/// локализованный вызов**, и **его нет ключом в каталоге**. Обе
/// добавочные половины измерены 07.10.2026 и обе оказались слепыми
/// зонами, а не сужением шума:
///
/// ```
/// кириллических литералов справа от ??                14
///   из них «нет ключом в каталоге»                     4   ← минус 10
///   из них ещё и «рядом локализованный вызов»          2   ← минус 2
/// ```
///
/// Клаузу «рядом локализованный вызов» отбрасывают два места, которые
/// она прячет: `DayTimeline.swift` и `EmergencyScreen.swift` — слева
/// там обычный `String?`, а не помощник перевода. Вторую, про ключ,
/// отбрасывает наше же записанное правило: **ключ в каталоге — не
/// признак перевода на экране.** Правая часть `??` даёт ЗНАЧЕНИЕ типа
/// `String`, а `Text(значение)` рисует его дословно, мимо каталога, —
/// есть ключ или нет. Десять из четырнадцати имеют ключ и всё равно
/// до него не доходят.
///
/// Поэтому условие одно и простое: **строковый литерал с кириллицей
/// в правой части `??` — долг.** Закрывается `String(localized:)`
/// на месте отката, как сделано в `WalkActivityView` 07.10.2026.
@Suite("Запасное слово в `??`")
struct FallbackLiteralTests {

    /// Долг по файлам. Замер 07.10.2026, **число может только
    /// уменьшаться.**
    ///
    /// Не порог на весь проект, а разбивка по файлам: общий порог
    /// впитал бы новое место молча, если бы в другом файле что-то
    /// починили. Такой сторож зелен на величину чужой работы.
    private let долг: [String: Int] = [
        // `WalkActivityView.swift` стоял здесь с долгом 2 и ушёл
        // в НОЛЬ 07.10.2026, в день рождения сторожа. Это был его
        // повод: внешний `tally ?? "…"` обеих поверхностей «острова».
        //
        // Закрыто не тем, чем я собирался. Я провёл через каталог
        // СЛОВО В ДЫРКЕ (`?? String(localized: "собаку")`) — механизм
        // закрылся, а француз продолжал читать русское: внешняя фраза
        // в каталог не шла вовсе, и готовый перевод `%@ вывела %@`
        // лежал там с `fr` и `uk`, не вызываемый ничем.
        //
        // `togo-02` (`ec3a928`) провела ЦЕЛЫЕ ФРАЗЫ. По-французски это
        // другая фраза, а не другое слово: `a sorti %@` против
        // `a sorti le chien` — обрывок «собаку» переводчику нечего
        // склонять. Ключ «собаку» после этого осиротел и снят.
        //
        // > Вызов пошёл в каталог, а каталог ответил тем же словом.
        // > Не «значение верное, вызов бессильный» — вызов верный,
        // > запись пустая, и снаружи выглядит как починка.

        // Слой приложения. Сюда `LocalizationDebtTests` не смотрит
        // вовсе, и до 07.10.2026 эти строки не числились нигде.
        "BackupScreen.swift": 1,
        "TodayScreen.swift": 1,
        // `DayTimeline.swift` стоял здесь с долгом 1 и снят 29.10.2026:
        // подпись озвучки «Сейчас …» проведена через каталог целиком.
        // `TrainingSessionScreen.swift` снят 28.10.2026 вместе с файлом:
        // занятия удалены по решению Виктории («удали блок и логику
        // занятия и перенос навыка полностью везде»), и трёх литералов,
        // которые здесь числились долгом, больше нет нигде.
        //
        // Запись удалена, а не обнулена до нуля: ноль означал бы
        // «файл есть, долга в нём нет» — утверждение о файле, которого
        // не существует. Такая запись пережила бы свой предмет
        // и молча разрешила бы вернуть литералы в файл с тем же именем.
        "AlarmThresholdScreen.swift": 1,
        "PillSupplyScreen.swift": 1,
        "LogSheets.swift": 1,

        // `FamilyScreen.swift` стоял здесь с долгом 1 и снят 23.10.2026
        // по замеру прогона: тест покраснел не на переборе, а на
        // `протухшие` — «долг числит больше, чем в файле есть».
        // Литерала справа от `??` там нет ни одного: оба места идут
        // через `?? String(localized: "собаки")` и `String(localized:
        // "Собака")`, починка легла `43b9abe` 07.10.2026 — в тот же
        // день, что и сам сторож, то есть запись родилась протухшей
        // и прожила так две недели, пока прогон не дошёл до этого
        // набора. Запись, пережившая свои строки, разрешает вернуть
        // то, что уже починено, — ровно это второе утверждение теста
        // и ловит.

        // `EmergencyScreen.swift` стоял здесь с долгом 1 и СНЯТ
        // 25.10.2026 починкой, а не правкой числа.
        //
        // Запись называла его худшим местом списка, и справедливо:
        // «Потерялась собака: …, метис, …» — текст, который читают
        // чужие люди, и в нём решается, вернут ли собаку. Строки
        // рядом шли через `String(localized:)`, эта нет: в одной
        // функции две переведены, третья нет.
        //
        // **Долг успел вырасти до двух, и вырастил его тот, кто чинил
        // другое.** 25.10 плакат получил второй ключ — двухместный,
        // для случая, когда вес не записан (`weightIfKnown`), — и вместе
        // с текстом удвоился литерал: `dog.breed ?? "метис"` стал стоять
        // в двух местах вместо одного. Сторож поймал это в том же
        // прогоне, которым проверяли совсем другое.
        //
        // > **Починка соседнего места удваивает долг, если долг живёт
        // > в копии текста.** Сторож на литерал сработал ровно там, где
        // > правка выглядела невинной: ключ, а не литерал, был предметом
        // > правки, и про литерал внутри ключа не подумал никто.
        //
        // Закрыто `?? String(localized: "метис")` в обоих местах плюс
        // ключ `метис` в каталоге на четырёх языках (`needs_review`:
        // носитель не читал). Запись снята целиком, а не обнулена:
        // второе утверждение этого теста краснеет на долге, числящем
        // больше, чем в файле есть.
    ]

    @Test("Запасное слово в `??` идёт через каталог, а не литералом")
    func запасноеСловоЧерезКаталог() throws {
        let (места, операторовВсего) = try Self.находки()

        // Сканер, переставший что-либо находить, молчит так же, как
        // тот, кому нечего сказать. Порог — по самому оператору,
        // а не по находкам: находки должны стремиться к нулю,
        // а `??` в проекте останется.
        #expect(операторовВсего >= 60, """
            найдено всего \(операторовВсего) вхождений `?? "литерал"`
            при 74 на 07.10.2026. Сканер читает не те файлы или
            не те строки — проверь обход, а не проект.
            """)

        var перебор: [String] = []
        for (файл, строки) in места.sorted(by: { $0.key < $1.key }) {
            let разрешено = долг[файл] ?? 0
            if строки.count > разрешено {
                перебор.append("""
                    \(файл): запасных слов литералом \(строки.count) \
                    при долге \(разрешено)
                    \(строки.map { "      \($0)" }.joined(separator: "\n"))
                    """)
            }
        }

        #expect(перебор.isEmpty, """
            запасное слово в `??` написано литералом и в каталог не идёт:

            \(перебор.joined(separator: "\n"))

            Правая часть `??` — это ЗНАЧЕНИЕ типа String, и `Text(значение)`
            рисует его дословно. Ключ в каталоге тут не помогает: до него
            никто не идёт. Закрывается `?? String(localized: "слово")`,
            как в `WalkActivityView` 07.10.2026 — падеж остаётся на месте
            вызова, слово идёт через каталог.

            Правку числа в долге считать починкой нельзя.
            """)

        // Закрытое обязано уйти из долга: запись, пережившая свои
        // строки, разрешает вернуть то, что уже починено.
        let протухшие = долг.keys
            .filter { (места[$0]?.count ?? 0) < (долг[$0] ?? 0) }
            .sorted()
        #expect(протухшие.isEmpty, """
            долг числит больше, чем в файле есть: \(протухшие).
            Затяни числа до измеренного — иначе в них можно дописать
            новый дефект, и сторож останется зелёным.
            """)

        print("""
            ГРАНИЦА: этот сторож видит только `?? "литерал"` на одной строке.
            Он НЕ видит: запасное слово, вынесенное в константу или свойство;
            `if let … else { "слово" }`; тернарник `x ? "а" : "б"`;
            и русский литерал, доехавший до экрана любым другим путём.
            Ноль здесь — «этот один способ обойти каталог закрыт».
            """)
    }

    // MARK: Разбор

    /// Файл → строки с кириллическим литералом справа от `??`,
    /// и рядом — сколько вхождений оператора найдено всего.
    ///
    /// Второе возвращается значением, а не копится в статической
    /// переменной: изменяемое статическое состояние в наборе — это
    /// и гонка под строгой проверкой, и зависимость результата
    /// от порядка тестов.
    ///
    /// Печатается строка целиком, а не разобранный литерал: у строки
    /// с интерполяцией внутри отката кавычки вложены, и «литерал»
    /// в выводе оказался бы обрезанным на первой из них. Человеку
    /// нужен адрес и строка, а не наша реконструкция.
    private static func находки() throws -> (места: [String: [String]], операторов: Int) {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var всего = 0
        var итог: [String: [String]] = [:]
        // `TogoWidgets`, а не `TogoWidget`: до 13.10.2026 здесь стояло
        // имя без «s», которого на диске нет. `enumerator(at:)`
        // по несуществующему пути отдаёт `nil`, `guard … else { continue }`
        // молчит, и порог `операторовВсего` промах не ловит — его
        // набирают вдвоём `Togo` и `TogoShared`. Находить там сегодня
        // нечего (ноль `?? "…"` с кириллицей), то есть это была слепая
        // зона, а не пропущенный дефект. Но цель, ради которой каталог
        // строк переехал в `TogoShared`, — именно бандл расширения.
        for каталог in ["TogoShared", "Togo", "TogoWidgets"] {
            let папка = корень.appendingPathComponent(каталог)
            // Каталог обязан существовать: ноль от несуществующего пути
            // неотличим от нуля про проект, и ровно так промах прожил
            // незамеченным. Проверяется до обхода — у `enumerator`
            // отказ и пустота дают одно и то же `nil`.
            #expect(FileManager.default.fileExists(atPath: папка.path), """
                каталога «\(каталог)» нет на диске — обход молча пропустил бы его целиком.
                Имя цели сменилось? Поправь список, а не порог.
                """)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                let текст = try String(contentsOf: путь, encoding: .utf8)
                for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                    let обрезанная = строка.trimmingCharacters(in: .whitespaces)
                    // Комментарий — не код. Сканирующий сторож,
                    // не различающий их, меряет прозу и запрещает
                    // писать про ошибку там, где её не совершают.
                    if обрезанная.hasPrefix("//") { continue }

                    // Пометка «внутреннее» — та же, что у соседнего
                    // сторожа, и РАЗБОР у неё тот же: два независимых
                    // разбора одного правила расходятся молча, и у нас
                    // это уже оплачено на литералах с интерполяцией.
                    //
                    // Нужна потому, что `??` стоит не только перед
                    // подписью: `SharedDiarySeed.swift:152` собирает им
                    // ИМЯ КЛЮЧА `UserDefaults`, и предписанное лечение
                    // (`?? String(localized:)`) сделало бы ключ
                    // зависящим от языка — то есть внесло бы дефект.
                    //
                    // Счёт `всего` при этом не трогается: порог меряет
                    // сам оператор и обязан остаться независимым
                    // от того, сколько находок мы объяснили.
                    let пометка = LocalizationDebtTests.пометкаВнутреннего(строка)
                    if let причина = пометка {
                        #expect(причина.count >= 10, """
                            пометка «внутреннее» без причины в \(путь.lastPathComponent):\(номер + 1).
                            Исключение без причины через месяц неотличимо от дыры.
                            """)
                    }

                    for литерал in литералыПослеОтката(строка) {
                        всего += 1
                        guard пометка == nil else { continue }
                        guard литерал.contains(where: { $0.isCyrillic }) else { continue }
                        // Литерал в выводе, а не только строка: на одной
                        // строке откатов бывает два (внешний и внутри
                        // интерполяции), и без него две находки выглядят
                        // одной, напечатанной дважды.
                        итог[путь.lastPathComponent, default: []]
                            .append("""
                                \(путь.lastPathComponent):\(номер + 1) \
                                «\(литерал.prefix(40))» \
                                — \(обрезанная.prefix(90))
                                """)
                    }
                }
            }
        }
        return (итог, всего)
    }

    /// Литералы, стоящие сразу справа от `??`.
    ///
    /// Руками, а не регуляркой: нужна неэкранированная закрывающая
    /// кавычка, а `\"` внутри отката — обычный символ.
    ///
    /// **Тело интерполяции разбирается РЕКУРСИВНО, как код, и первая
    /// редакция этого не делала.** Поймано приёмкой подделкой в день
    /// написания, и поймано на том самом месте, ради которого сторож
    /// заводился:
    ///
    /// ```
    /// tally ?? "\(startedBy) вывела \(Fmt.dogName(dogName) ?? "собаку")"
    ///       ↑ внешний — виден                              ↑ внутренний — НЕ был виден
    /// ```
    ///
    /// Чтение литерала глотало всё до первой кавычки, то есть вместе
    /// с телом интерполяции, и внутренний `??` в него попадал как проза.
    /// Подделка (вернуть голый литерал в обе строки `WalkActivityView`)
    /// оставила сторожа **зелёным**: 0,081 с против 21 с полного обхода —
    /// он не нашёл ничего и промолчал так же, как если бы всё было верно.
    ///
    /// > **Сторож на обход каталога сам обошёл каталог** — тем же
    /// > механизмом, который на соседнем стороже (`LocalizationDebtTests`)
    /// > починили утром `408907a`. Два независимых разбора литералов
    /// > сломались об одну и ту же вложенную кавычку.
    ///
    /// Своё, а не вызов соседнего: тот отвечает на вопрос «сколько
    /// непереведённых литералов», этот — «где запасное слово написано
    /// литералом», и общий у них только разбор. Но факт, что оба
    /// сломались одинаково, записан: третьему разбору литералов в этом
    /// наборе быть не должно.
    private static func литералыПослеОтката(_ строка: String) -> [String] {
        var итог: [String] = []
        let символы = Array(строка)
        var i = 0
        while i + 1 < символы.count {
            guard символы[i] == "?", символы[i + 1] == "?" else { i += 1; continue }
            var j = i + 2
            while j < символы.count, символы[j] == " " { j += 1 }
            guard j < символы.count, символы[j] == "\"" else { i += 2; continue }
            let (литерал, конец, вложенные) = Self.читатьЛитерал(символы, от: j + 1)
            итог.append(литерал)
            итог.append(contentsOf: вложенные)
            i = конец
        }
        return итог
    }

    /// Литерал от позиции `от` до неэкранированной закрывающей кавычки.
    ///
    /// Возвращает ещё и находки **внутри** интерполяций: тело `\(…)` —
    /// это код, и `??` в нём такой же, как снаружи. В текст литерала
    /// тело не попадает вовсе, иначе кириллица из имени функции читалась
    /// бы как перевод, которого нет.
    private static func читатьЛитерал(_ символы: [Character], от: Int)
        -> (текст: String, конец: Int, вложенные: [String]) {
        var текст = ""
        var вложенные: [String] = []
        var k = от
        var экран = false
        while k < символы.count {
            let c = символы[k]
            if экран { текст.append(c); экран = false; k += 1; continue }
            if c == "\\" {
                if k + 1 < символы.count, символы[k + 1] == "(" {
                    let (тело, после) = Self.телоИнтерполяции(символы, открывающая: k + 1)
                    вложенные.append(contentsOf: литералыПослеОтката(String(тело)))
                    k = после
                    continue
                }
                экран = true; k += 1; continue
            }
            if c == "\"" { return (текст, k, вложенные) }
            текст.append(c)
            k += 1
        }
        return (текст, k, вложенные)
    }

    /// Тело `\( … )` — со счётом скобок, но не теми, что в кавычках.
    ///
    /// Внутри `\(f(")"))` закрывающая скобка в кавычках скобкой
    /// не является: без этого разбор кончается на первой же и съедает
    /// остаток строки.
    private static func телоИнтерполяции(_ символы: [Character], открывающая: Int)
        -> (тело: ArraySlice<Character>, после: Int) {
        var глубина = 0
        var вСтроке = false
        var экран = false
        var i = открывающая
        while i < символы.count {
            let c = символы[i]
            if вСтроке {
                if экран { экран = false }
                else if c == "\\" { экран = true }
                else if c == "\"" { вСтроке = false }
                i += 1
                continue
            }
            if c == "\"" { вСтроке = true; i += 1; continue }
            if c == "(" { глубина += 1 }
            if c == ")" {
                глубина -= 1
                if глубина == 0 { return (символы[(открывающая + 1)..<i], i + 1) }
            }
            i += 1
        }
        return (символы[min(открывающая + 1, символы.count)..<символы.count], символы.count)
    }
}

private extension Character {
    var isCyrillic: Bool {
        unicodeScalars.contains { (0x0400...0x04FF).contains($0.value) }
    }
}
