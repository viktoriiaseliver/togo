import Testing
import Foundation
@testable import Togo

/// Разделы правовых документов: identity не рождается заново.
///
/// `LegalDocument.Section` до 05.11.2026 держал `let id = UUID()`,
/// а массивы собирались литералом внутри `body` вызывающего. То есть
/// `ForEach(sections)` на каждой перерисовке получал восемнадцать
/// структур с новыми идентификаторами и пересобирал все карточки
/// вместо сверки.
///
/// Поведение (ключ не меняется от пересборки) проверяется автономно,
/// без прогона схемы: `Tools/автономная-проверка-производительности.sh`
/// режет объявление `Section` текстом из файла и прогоняет его
/// на `swift`, а подделкой возвращает прежний `UUID()` и ждёт красного.
/// Здесь — то, что без модуля не проверить: что ключи **навешены**
/// на все разделы и не столкнулись.
@Suite("Правовые разделы: ключи навешены и не столкнулись")
@MainActor
struct ПравовыеРазделыTests {

    private var документы: [(имя: String, разделы: [LegalDocument.Section])] {
        [("политика", PrivacyPolicyScreen.разделы),
         ("условия", TermsScreen.разделы),
         ("дисклеймер", MedicalDisclaimerScreen.разделы),
         ("открытый код", AcknowledgementsScreen.разделы)]
    }

    @Test("Ключи непустые и разные")
    func ключиНепустыеИРазные() {
        // КОНТРОЛЬ ПЕРВЫМ: документы нашлись и разделы в них есть.
        // Пустой список дал бы «ни одного столкновения» как правду
        // о списке, а не о ключах.
        #expect(документы.count == 4)
        let всего = документы.reduce(0) { $0 + $1.разделы.count }
        #expect(всего == 18, "разделов \(всего), а их было 18 — пересчитать правку, а не число")

        var занятые: [String: String] = [:]
        for (имя, разделы) in документы {
            #expect(!разделы.isEmpty, "у документа «\(имя)» ни одного раздела")
            for раздел in разделы {
                // Пустой `id` — это состояние «забыли `.ключ(…)`»,
                // и два таких раздела `ForEach` склеит в один молча.
                #expect(!раздел.id.isEmpty,
                        "в документе «\(имя)» раздел без ключа — забыт вызов .ключ(…)")
                if let прежний = занятые[раздел.id] {
                    Issue.record("ключ «\(раздел.id)» занят дважды: «\(прежний)» и «\(имя)»")
                }
                занятые[раздел.id] = имя
            }
        }
        #expect(занятые.count == всего,
                "различных ключей \(занятые.count) при \(всего) разделах")
    }

    @Test("Ключ не зависит от того, сколько раз прочитали массив")
    func ключиНеМеняютсяМеждуЧтениями() {
        // `static let` строится один раз, но утверждение проверяется,
        // а не предполагается: два независимых чтения обязаны дать
        // ту же последовательность ключей.
        let первое = PrivacyPolicyScreen.разделы.map(\.id)
        let второе = PrivacyPolicyScreen.разделы.map(\.id)
        #expect(!первое.isEmpty, "массив пуст — сравнивать нечего")
        #expect(первое == второе, "ключи между чтениями разошлись: \(первое) и \(второе)")
    }
}
