/// Текст поверх фотографии на «Сегодня» — контраст **по пикселю**,
/// а не по паре токенов.
///
/// ## Почему именно кадром, а не `ThemeContrastTests`
///
/// Тот набор мерит **пару значений**: «что» на «чём», оба названы
/// руками. Здесь фона-значения нет вовсе: под текстом лежит композит —
/// полотно, фотография человека, градиент затемнения и подкраска тоном.
/// Назвать его токеном нельзя, он получается только отрисовкой.
/// Граница записана в голове `ThemeContrastTests` дословно: «это замер
/// значений, а не кадра; `opacity` он не видит».
///
/// ## Почему `performAsCurrent`, а не `.environment(\.colorScheme,)`
///
/// Токены — динамические `UIColor`, и разрешаются они
/// по `UITraitCollection.current`, а не по окружению SwiftUI. Тест,
/// просящий тёмную через `.environment`, **напечатает «тёмная»
/// и отрисует светлое**. Приём взят у `ОстровКадрTests`
/// и `КиноВиджетКадрTests` — третья реализация сломалась бы так же,
/// как первые две.
///
/// Тема с 23.10.2026 прибита тёмной (`UIUserInterfaceStyle = Dark`
/// в `Configuration/Togo-Info.plist` и `TogoWidgets-Info.plist`,
/// решение Виктории «Кино. Одна тема»), поэтому светлый столбец
/// токенов на устройство не попадает и здесь не мерится.
///
/// ## Чего этот набор НЕ доказывает
///
/// 1. **Как выглядит ЧУЖАЯ фотография.** Снимок здесь синтетический,
///    трёх известных светлот. Фото человека может быть любым, и потому
///    вывод делается по худшей из трёх, а не по средней.
/// 2. **Стеклянную панель.** `ImageRenderer` материал
///    (`.ultraThinMaterial`) рисует не так, как система, — значит про
///    текст НА ПАНЕЛИ этот кадр не отвечает вовсе, и мерить его здесь
///    нечем. Поэтому ось набора — только та полоса, где текст лежит
///    **прямо на фоне**: строка заголовка.
/// 3. **Что увидит человек на устройстве.** Кадр снят отрисовщиком,
///    а не телефоном.
///
/// Адрес входа: тест пишет кадры на диск через `#filePath`
/// (`build/кадры-чернила-на-фото`), и уборка каталога ломает его
/// не на его предмете.
@MainActor
@Suite("Чернила поверх фотографии на «Сегодня»")
struct ЧернилаНаФотоКадрTests {

    /// Порог WCAG 1.4.3 для обычного текста. Заголовок «Сегодня» —
    /// 36 pt bold, то есть формально крупный текст с порогом 3,0;
    /// проверяется он по **4,5**, потому что решение дизайна 23.10.2026
    /// («текст на фото — только `#FFFFFF`») порога не смягчает,
    /// а пилюля и чип в той же полосе крупными не бывают.
    static let порог = 4.5

    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
            .appendingPathComponent("build/кадры-чернила-на-фото")
    }

    /// Ширина iPhone 16 Pro в точках. Берётся числом нарочно: это
    /// условие стенда, а не величина продукта.
    private static let ширина: CGFloat = 402

    /// Высота кадра. Задаётся числом по той же причине, что ширина, —
    /// и ещё по одной: без неё два кадра одного вида выходят РАЗНОГО
    /// размера, потому что `.scaledToFill()` у снимка перерастает
    /// `minHeight` блока. Сравнивать их попиксельно тогда нечем.
    private static let высотаКадра: CGFloat = 360

    // MARK: - Фотографии известной светлоты

    /// Снимок сплошного цвета. **Сплошной, а не узор, и это выбор
    /// по замеру:** узор дал бы разброс фона внутри одной строки,
    /// и «худшее место» пришлось бы искать, а не считать.
    ///
    /// Три светлоты закрывают диапазон, а вывод делается по **худшей**:
    /// у фотографии человека светлоты не спрашивают.
    private static func снимок(_ светлота: UInt8) -> Data {
        let размер = CGSize(width: 40, height: 40)
        let рисовальщик = UIGraphicsImageRenderer(size: размер)
        let картинка = рисовальщик.image { ctx in
            UIColor(red: CGFloat(светлота) / 255,
                    green: CGFloat(светлота) / 255,
                    blue: CGFloat(светлота) / 255,
                    alpha: 1).setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
        }
        return картинка.pngData() ?? Data()
    }

    private static let фотографии: [(String, UInt8)] = [
        ("светлая", 0xF2),   // снег, небо, белая стена — худший случай для тёмных чернил
        ("средняя", 0x80),
        ("тёмная", 0x1A),
    ]

    // MARK: - Отрисовка

    /// Снять кадр вида в тёмной теме и отдать и картинку, и путь.
    ///
    /// Фон — явный `.black`, а не токен: токен по умолчанию вычислился
    /// бы **снаружи** `performAsCurrent`, и вышел бы кадр, половина
    /// которого знает про тёмную тему, а половина нет. Этот разбор
    /// оплачен в `КиноВиджетКадрTests`.
    @discardableResult
    private func снять<V: View>(_ вид: V, имя: String, высота: CGFloat?,
                                счёт: inout [String]) throws -> UIImage {
        var нарисованное: UIImage?
        UITraitCollection(userInterfaceStyle: .dark).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, .dark)
                    .frame(width: Self.ширина, height: высота)
                    .background(Color.black)
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }
        let картинка = try #require(нарисованное, "ImageRenderer не отдал картинку для «\(имя)»")
        let данные = try #require(картинка.pngData(), "картинка «\(имя)» не стала PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        try данные.write(to: Self.каталог.appendingPathComponent("\(имя).png"))
        счёт.append(имя)
        return картинка
    }

    /// Счёт снятого. Печатается **всегда**, в том числе после падения:
    /// «снято три» и «упал на втором, снято одно» выглядят в логе
    /// одинаково, потому что во втором случае строки про кадры просто
    /// нет, а её отсутствия никто не ищет.
    private func печатьСчёта(_ имена: [String], ожидалось: Int) {
        print("КАДРОВ СНЯТО: \(имена.count) из \(ожидалось) · \(имена.joined(separator: ", "))")
    }

    // MARK: - Разбор пикселей

    struct Точка: Sendable {
        let r: Double, g: Double, b: Double
    }

    /// Все пиксели кадра строками. Разворачивается один раз на кадр:
    /// повторный `CGContext` на каждый вопрос стоил бы дороже самого
    /// замера.
    private static func пиксели(_ картинка: UIImage) throws -> (точки: [Точка], ширина: Int, высота: Int) {
        let cg = try #require(картинка.cgImage, "у картинки нет CGImage — разбирать нечего")
        let w = cg.width, h = cg.height
        var буфер = [UInt8](repeating: 0, count: w * h * 4)
        // `&буфер` держится СНАРУЖИ `#require` нарочно: макрос
        // переписывает выражение, которое ему отдали, и `inout`
        // на массив через него не проходит.
        let нарисовано: Bool = буфер.withUnsafeMutableBytes { сырые -> Bool in
            guard let контекст = CGContext(
                data: сырые.baseAddress, width: w, height: h, bitsPerComponent: 8,
                bytesPerRow: w * 4, space: CGColorSpaceCreateDeviceRGB(),
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
            else { return false }
            контекст.draw(cg, in: CGRect(x: 0, y: 0, width: w, height: h))
            return true
        }
        try #require(нарисовано, "CGContext не завёлся — пиксели читать нечем")
        var точки: [Точка] = []
        точки.reserveCapacity(w * h)
        for i in stride(from: 0, to: буфер.count, by: 4) {
            точки.append(Точка(r: Double(буфер[i]) / 255,
                               g: Double(буфер[i + 1]) / 255,
                               b: Double(буфер[i + 2]) / 255))
        }
        return (точки, w, h)
    }

    /// Относительная яркость по WCAG 2.1.
    static func яркость(_ т: Точка) -> Double {
        func лин(_ x: Double) -> Double {
            x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4)
        }
        return 0.2126 * лин(т.r) + 0.7152 * лин(т.g) + 0.0722 * лин(т.b)
    }

    static func контраст(_ a: Точка, _ b: Точка) -> Double {
        let l1 = яркость(a), l2 = яркость(b)
        return (max(l1, l2) + 0.05) / (min(l1, l2) + 0.05)
    }

    /// Насколько далеко две точки друг от друга по каналам.
    private static func расстояние(_ a: Точка, _ b: Точка) -> Double {
        max(abs(a.r - b.r), max(abs(a.g - b.g), abs(a.b - b.b)))
    }

    /// Полоса строк кадра, в которых нашлись чернила искомого цвета.
    struct Полоса: Sendable {
        let верх: Int
        let низ: Int
        /// Сколько пикселей чернил в полосе.
        let чернил: Int
        /// Фон полосы — медиана тех её пикселей, что чернилами НЕ являются.
        let фон: Точка
    }

    /// Найти полосы, в которых стоит текст названного цвета.
    ///
    /// **Полосами, а не одной рамкой, и это не украшение.** Один
    /// и тот же цвет в `ReadingPanel` носят два разных текста —
    /// заголовок «Сегодня» (прямо на фоне) и показание (на стеклянной
    /// панели). Одна рамка на оба слепила бы их фоны в среднее,
    /// которого нет ни под одним. Полосы разводят их по вертикали,
    /// и дальше каждую видно отдельно.
    ///
    /// Допуск `0.04` — это ±10 из 255 на канал: антиалиасинг края
    /// глифа даёт промежуточные оттенки, и строгое равенство нашло бы
    /// только сердцевины штрихов.
    ///
    /// **Полоса ниже `минимумСтрок` — не текст, и это замер, а не вкус.**
    /// 23.10.2026 разбор выдавал полосы в ОДНУ строку по 6–8 пикселей —
    /// антиалиас на краю чипа и шум градиента, — а рядом настоящие
    /// строки давали 32 и 79 строк по 3192 и 6143 пикселя. Разница
    /// на два порядка, перепутать нечего. Стоила эта мелочь дорого:
    /// у восьмипиксельной «полосы» медианный фон выходит светлым
    /// (#7676BE), и на нём **порог не берёт даже чистый #FFFFFF** —
    /// обратный контроль дал 4,1134 при 4,5. То есть сторож краснел
    /// на числе, которое ни один цвет продукта исправить не может,
    /// а читалось это как «текст нечитаем».
    ///
    /// > Отсечка смотрит на ВЫСОТУ полосы, а не на число чернил:
    /// > при кегле 12 pt и scale 2 глиф занимает ≥ 24 строки, так что
    /// > шесть строк не спрячут ни одной настоящей подписи. Отсечка
    /// > по числу пикселей спрятала бы короткое слово.
    private static let минимумСтрок = 6

    private static func полосы(_ кадр: (точки: [Точка], ширина: Int, высота: Int),
                               чернила: Точка, допуск: Double = 0.04) -> [Полоса] {
        var вСтроке = [Int](repeating: 0, count: кадр.высота)
        for y in 0..<кадр.высота {
            var n = 0
            for x in 0..<кадр.ширина where расстояние(кадр.точки[y * кадр.ширина + x], чернила) <= допуск {
                n += 1
            }
            вСтроке[y] = n
        }

        // Строка считается «со строкой текста», когда чернил в ней
        // больше пяти: одиночные пиксели даёт шум градиента, а не глиф.
        var полосы: [Полоса] = []
        var начало: Int?
        var пусто = 0
        func закрыть(_ конец: Int) {
            guard let в = начало else { return }
            начало = nil
            // Шум отсекается ЗДЕСЬ, а не в приёмке: полоса ниже глифа
            // не является строкой текста, и её фон меряет не то место.
            guard конец - в + 1 >= минимумСтрок else { return }
            let всего = (в...конец).reduce(0) { $0 + вСтроке[$1] }
            полосы.append(Полоса(верх: в, низ: конец, чернил: всего,
                                 фон: фонПолосы(кадр, верх: в, низ: конец,
                                                чернила: чернила, допуск: допуск)))
        }
        for y in 0..<кадр.высота {
            if вСтроке[y] > 5 {
                if начало == nil { начало = y }
                пусто = 0
            } else if начало != nil {
                пусто += 1
                // Разрыв меньше восьми пикселей — это просвет внутри
                // строки (точка над «й»), а не конец полосы.
                if пусто >= 8 { закрыть(y - пусто) }
            }
        }
        закрыть(кадр.высота - 1)
        return полосы
    }

    /// Фон полосы — **медиана по яркости** тех пикселей, что чернилами
    /// не являются.
    ///
    /// Медиана, а не среднее: среднее сдвинулось бы к краям глифов
    /// и показало бы контраст выше настоящего. Медиана берёт то,
    /// чего в полосе больше всего, — а больше всего в ней фона.
    private static func фонПолосы(_ кадр: (точки: [Точка], ширина: Int, высота: Int),
                                  верх: Int, низ: Int,
                                  чернила: Точка, допуск: Double) -> Точка {
        var прочие: [(Double, Точка)] = []
        for y in верх...низ {
            for x in 0..<кадр.ширина {
                let т = кадр.точки[y * кадр.ширина + x]
                // Шире допуска вдвое: полутона края глифа — это ещё
                // не фон, и считать их фоном значило бы завысить контраст.
                if расстояние(т, чернила) > допуск * 2 { прочие.append((яркость(т), т)) }
            }
        }
        guard !прочие.isEmpty else { return чернила }
        прочие.sort { $0.0 < $1.0 }
        return прочие[прочие.count / 2].1
    }

    // MARK: - Было ли что разбирать

    /// **Ставится первой.** Кадр, на котором фотографии нет, разбирается
    /// так же успешно, как кадр с ней, — и даёт контраст текста
    /// с чёрным полотном, то есть ответ на чужой вопрос.
    ///
    /// Имя названо предметом, а не формой («было что рисовать»):
    /// сторож `Имена @Test уникальны` краснеет на повторе, потому что
    /// и эталон прогона, и `-only-testing` адресуют по имени.
    ///
    /// **Высота задана обоим кадрам числом, и это не косметика.**
    /// С `высота: nil` кадр со снимком выходил `804×804`, а без снимка
    /// `804×720`: `.scaledToFill()` у квадратного снимка просит 402×402,
    /// и блок перерастает свой `minHeight: 360`. Попиксельное сравнение
    /// при этом невозможно, и сторож краснел **на собственном стенде**
    /// при верном предмете — тот же прогон печатал «снимок меняет 96,8 %
    /// пикселей кадра» (замер 23.10.2026).
    ///
    /// > Отдельная находка, которую этот кадр НЕ проверяет и которая
    /// > осталась: высота блока показания следует за пропорцией
    /// > фотографии, а не за `size.hero` (360). У `ReadingPanel`
    /// > стоит `.frame(minHeight:)` без верхней границы, и снимок 4:3
    /// > даст 536 pt вместо 360. Хозяин — дизайн.
    @Test("Фотография доехала до пикселей панели показания")
    func фотоВиднoНаКадре() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 2) }

        let сФото = try снять(Self.панель(фото: Self.снимок(0xF2)),
                              имя: "00-контроль-со-снимком", высота: Self.высотаКадра,
                              счёт: &счёт)
        let безФото = try снять(Self.панель(фото: nil),
                                имя: "00-контроль-без-снимка", высота: Self.высотаКадра,
                                счёт: &счёт)

        let a = try Self.пиксели(сФото)
        let b = try Self.пиксели(безФото)
        #expect(a.ширина == b.ширина && a.высота == b.высота, """
            кадры со снимком и без разошлись размером (\(a.ширина)×\(a.высота) \
            против \(b.ширина)×\(b.высота)) — сравнивать их попиксельно нечем.
            """)

        let n = min(a.точки.count, b.точки.count)
        var разных = 0
        for i in 0..<n where Self.расстояние(a.точки[i], b.точки[i]) > 0.02 { разных += 1 }
        let доля = Double(разных) / Double(max(n, 1))

        #expect(доля > 0.2, """
            снимок изменил только \(Self.процент(доля)) пикселей кадра. \
            Значит фотография до пикселей не доехала, и всё, что набор \
            намерит дальше, — это контраст текста с ЧЁРНЫМ ПОЛОТНОМ, \
            а не с фотографией. Ноль при таком замере значил бы \
            «предмета нет там, куда я смотрю».
            """)
        print("ЗАМЕР: снимок меняет \(Self.процент(доля)) пикселей кадра — фото доехало")
    }

    // MARK: - Предмет

    /// Заголовок «Сегодня» и всё, что лежит на фотографии, читается
    /// на снимке любой светлоты.
    ///
    /// **Ось — пиксель, а не токен.** Под заголовком нет фона-значения:
    /// там композит из полотна, снимка, градиента затемнения
    /// и подкраски тоном. Единственный способ его спросить — отрисовать.
    ///
    /// Три контроля сняты **в этом же замере**, иначе ноль был бы
    /// неотличим от неработающего инструмента:
    ///
    /// ```
    /// отрицательный   цвета, которого в кадре быть не может → 0 полос
    /// положительный   чернил найдено больше порога          → разбор состоялся
    /// обратный        белый на ТЕХ ЖЕ фонах                 → контраст высокий
    /// ```
    ///
    /// **Обратный контроль переписан 23.10.2026, и прежний был ложным
    /// по устройству.** Он искал в кадре полосы цвета
    /// `Poster.labelOnColor` — цвета, которого `ReadingPanel` тогда
    /// не рисовала ни в одном месте. Находил 8 пикселей антиалиаса
    /// в одной строке и печатал по ним «3,7352», то есть сообщал
    /// об отказе счётчика там, где отказал его собственный поиск.
    /// Теперь контроль берёт **фоны, намеренные под самим предметом**,
    /// и считает на них заведомо читаемый `#FFFFFF`: он не может
    /// провалиться из-за того, что искомого цвета нет в кадре,
    /// и ломается ровно вместе с предметом, а не вместо него.
    @Test("Текст на фотографии «Сегодня» берёт порог на снимке любой светлоты")
    func чернилаНаФотоБерутПорог() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: Self.фотографии.count) }

        // Цвет берётся у ТОГО ЖЕ токена, который кладёт `ReadingPanel`,
        // а не у «белого вообще»: разойдись они — сторож искал бы
        // не тот текст и молчал бы при живом дефекте.
        let чернила = Self.точка(Token.Poster.labelOnColor)
        var провалы: [String] = []
        var замеры: [String] = []
        var фоны: [Точка] = []
        var разборов = 0

        for (имя, светлота) in Self.фотографии {
            // Высота СВОБОДНАЯ, в отличие от сравнения двух кадров выше:
            // прибитые 360 обрезают «Сегодня» сверху (замер 23.10: полоса
            // заголовка 32 строки вместо 57), и сторож мерил бы половину
            // глифов. Сравнивать здесь не с чем — значит и равнять нечего.
            let кадр = try снять(Self.панель(фото: Self.снимок(светлота)),
                                 имя: "01-заголовок-на-\(имя)", высота: nil,
                                 счёт: &счёт)
            let точки = try Self.пиксели(кадр)

            // Отрицательный контроль В ТОМ ЖЕ ЗАМЕРЕ: цвет, которого
            // в кадре нет ни у одного токена. Нашёлся — разбор ловит
            // не то, и числа ниже читать нельзя.
            let небывалый = Self.полосы(точки, чернила: Точка(r: 1, g: 0, b: 1))
            #expect(небывалый.isEmpty, """
                разбор нашёл \(небывалый.count) полос пурпурного (#FF00FF) \
                на кадре «\(имя)». Такого цвета в токенах нет ни одного — \
                значит ищется не цвет, и остальные числа этого прогона \
                ничего не значат.
                """)

            let полосы = Self.полосы(точки, чернила: чернила)
            #expect(!полосы.isEmpty, """
                на кадре «\(имя)» не нашлось ни одной полосы чернил \
                \(Self.hex(чернила)). Пусто здесь значит «разбор не состоялся», \
                а не «всё читается»: текст этим цветом в `ReadingPanel` \
                стоит в пяти местах.
                """)

            for (номер, полоса) in полосы.enumerated() {
                разборов += 1
                фоны.append(полоса.фон)
                let k = Self.контраст(чернила, полоса.фон)
                let строка = "\(имя) · полоса \(номер + 1) (y \(полоса.верх)…\(полоса.низ), "
                    + "\(полоса.чернил) px) на \(Self.hex(полоса.фон))"
                замеры.append("  \(Self.два(k).padding(toLength: 8, withPad: " ", startingAt: 0)) \(строка)")
                if k < Self.порог {
                    провалы.append("  \(строка): \(Self.два(k)) при пороге \(Self.два(Self.порог))")
                }
            }
        }

        #expect(разборов > 0, """
            разобрано ноль полос. Набору, которому нечего проверять, \
            молчать так же легко, как набору, у которого всё хорошо.
            """)

        // Обратный контроль, снятый в ТОМ ЖЕ замере и на ТЕХ ЖЕ фонах:
        // заведомо читаемый белый. Он не ищет в кадре ничего — значит
        // не может провалиться оттого, что искомого цвета там нет,
        // а это ровно то, на чём прежняя редакция давала ложный отказ.
        let белый = Точка(r: 1, g: 1, b: 1)
        let обратный = фоны.map { Self.контраст(белый, $0) }.min()
        #expect((обратный ?? 0) >= Self.порог, """
            обратный контроль провалился: белый #FFFFFF даёт \
            \(Self.два(обратный ?? 0)) на худшем из фонов, намеренных \
            под самим предметом. Это отказ счётчика или композита, \
            а не продукта — числа предмета читать нельзя.
            """)

        print("""
            ЗАМЕР пикселем, чернила \(Self.hex(чернила)) на композите \
            «полотно + снимок + затемнение»:

            \(замеры.joined(separator: "\n"))

            обратный контроль #FFFFFF на худшем из этих фонов: \(Self.два(обратный ?? 0))

            ГРАНИЦА: мерены полосы, где текст лежит ПРЯМО НА ФОНЕ. \
            `ImageRenderer` рисует `.ultraThinMaterial` не так, как система, \
            поэтому про текст на стеклянной панели этот кадр не отвечает.
            """)

        #expect(провалы.isEmpty, """
            \(провалы.count) полос текста на фотографии ниже порога:

            \(провалы.joined(separator: "\n"))

            Решение дизайна 23.10.2026 (`Дизайн/редизайн-ios28/README.md`, \
            «Решения по вопросам разработки», пункт 3): «текст на фото — \
            только `#FFFFFF`; `text-secondary` на фото не ставить». \
            Правь цвет у места вызова, а не порог: число, поднятое \
            под дефект, становится дырой ровно того размера.
            """)
    }

    // MARK: - Фикстура

    /// Панель показания обычного дня — ровно та, что рисует «Сегодня».
    ///
    /// Тон `.normal`, потому что он **единственный, у которого панель
    /// не крашена**: у дозы, тревоги и натощак под текстом лежит
    /// сплошная заливка, и её пару `ThemeContrastTests` уже мерит
    /// значениями. Фотография видна только у некрашеных тонов.
    private static func панель(фото: Data?) -> some View {
        ReadingPanel(
            tone: .normal,
            чип: .init(символ: "house", текст: "Дома"),
            пилюля: nil,
            показание: .часыМинуты(2 * 3600 + 11 * 60),
            откуда: "гулял в 15:44",
            докуда: "обычно до 22:44",
            доля: 0.4,
            фото: фото,
            шапка: { EmptyView() }
        )
    }

    // MARK: - Печать

    private static func точка(_ цвет: Color) -> Точка {
        let hex = цвет.resolvedHex(dark: true, highContrast: false)
        return Точка(r: Double((hex >> 24) & 0xFF) / 255,
                     g: Double((hex >> 16) & 0xFF) / 255,
                     b: Double((hex >> 8) & 0xFF) / 255)
    }

    private static func hex(_ т: Точка) -> String {
        String(format: "#%02X%02X%02X",
               Int((т.r * 255).rounded()), Int((т.g * 255).rounded()),
               Int((т.b * 255).rounded()))
    }

    private static func два(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }

    private static func процент(_ x: Double) -> String {
        String(format: "%.1f %%", x * 100).replacingOccurrences(of: ".", with: ",")
    }
