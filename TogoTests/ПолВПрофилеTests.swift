import Testing
import Foundation

/// Пол собаки можно задать не только в онбординге.
///
/// **Повод — замер по живой выгрузке 08.10.2026:** у всех шестнадцати
/// собак `sexRaw: unknown`, включая Стича, единственного с кличкой.
/// Причина оказалась не в том, что шаг пропустили: во всём `Togo/`
/// пол записывало **одно место** — онбординг. Поправить его потом
/// было нечем, и это половина беды.
///
/// Вторая половина хуже: `DogEditorScreen` — экран «создать, поправить,
/// удалить» — заводит вторую и следующих собак (`draft.makeDog()`),
/// а задать в черновике пол на этом экране было негде. Значит собака,
/// заведённая НЕ через онбординг, получала `unknown` **навсегда**,
/// а не «пока не поправили».
///
/// Само поле в `DogDraft` лежало с первого дня (`OnboardingFlow.swift`),
/// не хватало четырёх строк: двух в `load()` и двух в `save()`.
///
/// # Почему сторож именно здесь
///
/// Ветка «сука — считаем мочу, кобель — прогулка и есть туалет»
/// без заданного пола не выберет ни одну сторону. То есть эта правка —
/// не косметика профиля, а **вход** в логику, которую пишут следом;
/// уберут её обратно — развилка останется без ответа на всех
/// шестнадцати собаках, и выяснится это не на сборке, а у человека.
///
/// # Чего этот сторож НЕ умеет, и это важнее того, что умеет
///
/// Он читает **исходник**, то есть ловит «не пишет вовсе» и слеп
/// к «пишет не туда»: строка `dog.sex = draft.sex` его устроит и тогда,
/// когда экран её не покажет человеку, и тогда, когда пикер окажется
/// за ролью, которой у хозяйки нет. Настоящая приёмка — **кадр**:
/// профиль Стича с заданным полом. У нас это оплачено подписью кнопки,
/// которая была верна токеном и давала 1,68:1 на экране.
///
/// Комментарии вырезаются до разбора: в правке над строками лежит
/// объяснение, называющее `dog.sex` поимённо, и без вырезания сторож
/// прошёл бы на прозе о коде, а не на коде.
@Suite("Пол задаётся в профиле, а не только в онбординге")
struct ПолВПрофилеTests {

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()

    private static func текст(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    private static func строкиКода(_ текст: String) -> [String] {
        текст.split(separator: "\n", omittingEmptySubsequences: false)
            .map(String.init)
            .filter { строка in
                let о = строка.trimmingCharacters(in: .whitespaces)
                return !о.hasPrefix("//") && !о.hasPrefix("///")
                    && !о.hasPrefix("*") && !о.hasPrefix("/*")
            }
    }

    private static func редактор() throws -> [String] {
        строкиКода(try текст("Togo/Features/Profile/Editors.swift"))
    }

    @Test("Сканер прочитал файл, а не пустоту")
    func сканерВидитФайл() throws {
        let код = try Self.редактор()
        #expect(код.count > 200, """
            исходник редактора прочитан пустым или укоротился вдвое: \
            строк кода \(код.count). Сторож, переставший что-либо \
            находить, молчит так же, как тот, у кого всё хорошо.
            """)
        #expect(код.contains { $0.contains("struct DogEditorScreen") },
                "`DogEditorScreen` переименован или уехал из файла — сторож смотрит не туда")
    }

    @Test("Профиль СПРАШИВАЕТ пол, а не только хранит его")
    func профильСпрашиваетПол() throws {
        let код = try Self.редактор().joined(separator: "\n")
        #expect(код.contains("DogSex.allCases"), """
            в редакторе профиля нет выбора пола. Без него собака, \
            заведённая не через онбординг, остаётся `unknown` навсегда, \
            и развилка «сука/кобель» не выберет ни одну сторону.
            """)
    }

    @Test("Пол и кастрация читаются из собаки при открытии")
    func полЧитаетсяВЧерновик() throws {
        let код = try Self.редактор().joined(separator: "\n")
        #expect(код.contains("draft.sex = dog.sex"), """
            `load()` не кладёт пол в черновик: человек откроет профиль \
            кобеля и увидит «не знаю» — а сохранив, затрёт верное значение \
            умолчанием черновика.
            """)
        #expect(код.contains("draft.isNeutered = dog.isNeutered"),
                "`load()` не кладёт кастрацию — та же беда, что с полом")
    }

    @Test("Пол и кастрация записываются обратно и откатываются вместе со всеми")
    func полПишетсяИОткатывается() throws {
        let код = try Self.редактор().joined(separator: "\n")
        #expect(код.contains("dog.sex = draft.sex"), """
            `save()` не пишет пол: экран спрашивает и выбрасывает ответ. \
            Это наш класс «поле объявлено, писателя нет нигде», только \
            с экраном сверху.
            """)
        #expect(код.contains("dog.isNeutered ="), "`save()` не пишет кастрацию")

        // Откат — вторая половина сохранения, и забыть её легче, чем
        // запись: `context.persist(otherwise:)` возвращает поля назад,
        // когда хранилище отказало. Поле, которого нет в откате,
        // переживёт неудачное сохранение и разойдётся с тем, что
        // человек видит на экране.
        guard let откат = код.range(of: "otherwise:") else {
            Issue.record("в `save()` нет отката `persist(otherwise:)` — проверять нечего")
            return
        }
        let хвост = код[откат.lowerBound...]
        #expect(хвост.contains("dog.sex = былПол"), """
            пол не возвращается при отказе хранилища: сохранение не прошло, \
            а в памяти пол уже новый — экран и база разойдутся молча.
            """)
        #expect(хвост.contains("dog.isNeutered = былаКастрация"),
                "кастрация не возвращается при отказе хранилища")
    }

    @Test("Кастрация не переживает снятие пола")
    func кастрацияНеВиситБезПола() throws {
        let код = try Self.редактор().joined(separator: "\n")
        #expect(код.contains("draft.sex == .unknown ? false : draft.isNeutered"), """
            при поле «не знаю» строка «Кастрирован/Стерилизована» исчезает \
            с экрана — но значение остаётся в базе и уезжает в сводку врачу. \
            Утверждение о кастрации без пола не к чему отнести.
            """)
    }

    @Test("Границы: чего этот сторож не проверяет")
    func границы() {
        // Печатаются, а не хранятся в чьей-то памяти: у нас записано,
        // что граница, названная человеком, теряется при первой передаче,
        // а напечатанная инструментом доезжает до всех.
        let границы = """
            Сторож читает ИСХОДНИК. Он не знает:
            · показан ли пикер человеку (может стоять за ролью или
              под `#if DEBUG`) — это видно только на кадре;
            · сохранилось ли значение в базу — `persist` может отказать;
            · спросят ли пол там, где развилка «сука/кобель» его впервые
              потребует, — это отдельное решение, на 08.10 у Виктории.
            Зелёный здесь значит «четыре строки на месте», а не
            «человек может задать пол Стичу».
            """
        #expect(границы.contains("кадре"))
    }
}
