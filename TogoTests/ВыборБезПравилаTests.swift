import Testing
import Foundation
@testable import Togo

/// Сменщик и адресат брифинга выбираются ПРАВИЛОМ, а не порядком массива.
///
/// # Чего стоило отсутствие правила
///
/// Замер 25.10.2026. В `FamilyScreen` стояло
/// `@Query private var members: [FamilyMember]` — **без сортировки**,
/// и SwiftData отдавал участников в порядке, который меняется между
/// запусками. Померено на двух прогонах подряд:
///
/// ```
/// Ты · Dr.Ferrand · Мама · Тео · Виктория · Лея
/// Ты · Виктория · Лея · Мама · Dr.Ferrand · Тео
/// ```
///
/// Показ — меньшая половина. От порядка зависели два ВЫБОРА, и оба
/// человек видит:
///
/// ```
/// successor(after:)   кому перейдёт ДЕЖУРСТВО над собакой —
///                     то есть кто получит напоминания о дозах
/// заголовокБрифинга   «Брифинг для Ани» — имя адресата менялось само
/// ```
///
/// Оба звали `members.first { … }` по предикату, которому подходят
/// **несколько** человек.
///
/// > **`first` по многозначному предикату — это выбор без правила.**
/// > Он выглядит детерминированным, потому что код один и тот же,
/// > а меняется то, чего код не называет: порядок источника. Поэтому
/// > сторож на такой выбор нельзя построить, подав ему один список:
/// > он пройдёт. Различает только **тот же список в другом порядке**.
///
/// # Как устроена приёмка
///
/// Каждое утверждение гоняет правило на **двух перестановках одного
/// набора** и требует совпадения. Это та самая ось, которой не было:
/// проверка на одном порядке зелена и при отсутствии правила вовсе.
///
/// Перестановка берётся не случайная, а **обратная** — она гарантированно
/// отличается от прямой при двух и более элементах, тогда как
/// `shuffled()` мог бы вернуть тот же порядок и дать зелёный
/// без проверки.
@Suite("Выбор делается правилом, а не порядком массива")
@MainActor
struct ВыборБезПравилаTests {

    // Контейнера здесь НЕТ нарочно. Правило работает на массиве
    // значений — ровно как `SharedDiaryMerge` и остальной `FamilyResolver`,
    // и по той же причине: что можно вынести из CloudKit и SwiftData
    // в чистое значение, обязано быть вынесено. Контейнер в памяти
    // добавил бы общее состояние на весь прогон и ни одной проверки.

    /// Семья, в которой у КАЖДОГО правила по три кандидата.
    ///
    /// Состав подобран замером, а не на глаз (`defaultPermissions`,
    /// `Enums+Family.swift:109`):
    ///
    /// ```
    /// giveDose даёт        владелец · со-владелец · ухаживающий
    /// seeMedical НЕ даёт   только помощник
    /// ```
    ///
    /// Поэтому ухаживающих трое и помощников трое. **Первая редакция
    /// этой фикстуры была негодной:** помощник в ней был один,
    /// и проверка адресата брифинга на двух перестановках проходила
    /// бы при любом правиле — у единственного кандидата порядок
    /// ничего не меняет. Поймал не прогон, а счёт по `defaultPermissions`
    /// прежде прогона.
    ///
    /// Имена нарочно НЕ в алфавитном порядке в массиве: если правило
    /// исчезнет и вернётся «первый попавшийся», прямой порядок даст
    /// «Тео», а обратный — «Боря», и проверки покраснеют.
    private func семья() -> [FamilyMember] {
        [
            FamilyMember(name: "Тео", role: .coOwner),
            FamilyMember(name: "Виктория", role: .owner, isMe: true),
            FamilyMember(name: "Мама", role: .caregiver),
            FamilyMember(name: "Боря", role: .helper),
            FamilyMember(name: "Аркадий", role: .caregiver),
            FamilyMember(name: "Dr.Ferrand", role: .observer),
            FamilyMember(name: "Аня", role: .helper),
            FamilyMember(name: "Ян", role: .helper),
        ]
    }

    // MARK: - Контроль: было ли что сторожить

    @Test("Контроль: у каждого правила больше одного кандидата")
    func кандидатовБольшеОдного() {
        let все = семья()
        let текущий = все.first { $0.isMe }
        let дозу = все.filter { $0.id != текущий?.id && $0.can(.giveDose) }
        let брифинг = все.filter { !$0.isMe && !$0.can(.seeMedical) }

        #expect(дозу.count >= 3, """
            кандидатов на дежурство \(дозу.count) из \(все.count).
            При одном выбор однозначен сам по себе, и проверки ниже
            зелены при ЛЮБОМ правиле, включая его отсутствие.
            """)
        #expect(брифинг.count >= 3, """
            кандидатов на брифинг \(брифинг.count) из \(все.count).
            ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ФИКСТУРЫ ДАВАЛА ОДНОГО: `seeMedical`
            не даёт только роль помощника, а помощник был один.
            Проверка проходила бы при любом правиле.
            """)
    }

    @Test("Контроль: обратная перестановка правда отличается от прямой")
    func перестановкаОтличается() {
        let прямо = семья().map(\.name)
        let обратно = Array(прямо.reversed())
        #expect(прямо != обратно, """
            прямой и обратный порядок совпали — значит проверки ниже
            подают правилу один и тот же список дважды и не меряют
            ничего. Так было бы при одном элементе в фикстуре.
            """)
    }

    // MARK: - Предмет

    @Test("Сменщик один и тот же в любом порядке списка")
    func сменщикНеЗависитОтПорядка() throws {
        let все = семья()
        let текущий = try #require(все.first { $0.name == "Виктория" })

        let прямо = FamilyResolver.сменщик(после: текущий, среди: все)
        let обратно = FamilyResolver.сменщик(после: текущий, среди: все.reversed())

        #expect(прямо?.id == обратно?.id, """
            сменщик зависит от порядка списка: прямо «\(прямо?.name ?? "—")»,
            обратно «\(обратно?.name ?? "—")».

            Это выбор ПРО ДЕЖУРСТВО над собакой — кто получит
            напоминания о дозах. До 25.10.2026 он делался
            `members.first { … }` при `@Query` без сортировки, и человек
            каждый запуск видел в «Передать» другое имя.
            """)
        #expect(прямо?.name != текущий.name, "сменщиком предложен сам текущий")
    }

    @Test("Адресат брифинга один и тот же в любом порядке списка")
    func адресатНеЗависитОтПорядка() throws {
        let все = семья()

        let прямо = FamilyResolver.адресатБрифинга(среди: все)
        let обратно = FamilyResolver.адресатБрифинга(среди: все.reversed())

        #expect(прямо?.id == обратно?.id, """
            адресат брифинга зависит от порядка: прямо
            «\(прямо?.name ?? "—")», обратно «\(обратно?.name ?? "—")».

            Заголовок «Брифинг для …» называет ОДНОГО человека, и он
            читает его как адресованный себе. Имя не должно меняться
            само между запусками.
            """)
        #expect(прямо?.isMe != true, "адресатом брифинга предложен я сам")
    }

    /// Ожидание стоит ИМЕНЕМ, а не повтором реализации.
    ///
    /// Первая редакция считала ожидаемое тем же `filter`+`sorted`,
    /// что и резолвер, — то есть **повторяла реализацию вместо того,
    /// чтобы её сторожить**: поменяй правило в обоих местах, и набор
    /// останется зелёным, ничего не заметив. Имя в литерале делает
    /// проверку независимой: смена правила обязана покраснеть.
    ///
    /// Числа взяты счётом по `defaultPermissions`, а не угаданы:
    /// дозу дают владелец, со-владелец и ухаживающий; владелец здесь
    /// текущий и исключён; остаются Аркадий, Мама, Тео, и по имени
    /// первым идёт **Аркадий**.
    @Test("Правило названо: сменщик — «Аркадий», первый по имени")
    func правилоНазваноИмя() throws {
        let все = семья()
        let текущий = try #require(все.first { $0.name == "Виктория" })
        let выбран = FamilyResolver.сменщик(после: текущий, среди: все)

        #expect(выбран?.name == "Аркадий", """
            сменщик — «\(выбран?.name ?? "—")», а ждали «Аркадий»:
            из тех, кому роль даёт дозу (Аркадий · Мама · Тео),
            он первый по имени.

            Если правило сменили сознательно — менять надо И это имя,
            И доккомментарий `FamilyResolver.сменщик`, где сказано,
            почему имя, а не дата создания. Поля «кого завели раньше»
            у `FamilyMember` нет; завести — правка формы схемы, решение
            Виктории.
            """)
    }

    /// То же для брифинга, и тоже именем.
    @Test("Правило названо: адресат брифинга — «Аня», первая по имени")
    func адресатНазванИмя() {
        let выбран = FamilyResolver.адресатБрифинга(среди: семья())
        #expect(выбран?.name == "Аня", """
            адресат — «\(выбран?.name ?? "—")», а ждали «Аня»:
            `seeMedical` не даёт только роль помощника, помощников трое
            (Аня · Боря · Ян), и по имени первая — Аня.
            """)
    }
}
