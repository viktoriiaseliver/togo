import Testing
import Foundation

/// Примитивы отступа лежат на шкале ядра, а не рядом с ней.
///
/// **ОСЬ СМЕНЕНА 27.10.2026: сторож сторожит РОСТ, а не прошлое.**
///
/// Здесь стояло «этот сторож обязан краснеть в день рождения»: он
/// называл находку числом — пять примитивов вне шкалы хендоффа — и
/// должен был позеленеть после перевёрстки. Перевёрстки не будет,
/// и это решение Виктории 27.10.2026 с названной причиной:
///
/// > «Пять живых примитивов и 76 вызовов одного только `space.2`
/// > означают десятки перевёрсток с кадрами ради выравнивания,
/// > которого человек не увидит. Честнее перевести на явный список
/// > разрешённых исключений: эти пять известны и допустимы, а новых
/// > в коде появляться не должно».
///
/// Что это меняет по существу: двадцать дней сторож стоял красным
/// и **не мог поймать шестой** примитив полусетки — новый утонул бы
/// среди пяти старых в том же списке отказов. Теперь шестой краснеет
/// один и по имени.
///
/// **Чего ось НЕ разрешает.** Исключения названы поимённо и вместе
/// со значением; любое другое число вне шкалы — отказ. И сам список
/// проверяется с двух концов (`исключенияНеУстарели`), потому что
/// разрешение, пережившее свой предмет, — дыра ровно своего размера.
///
/// **Шкала берётся у ядра, а не зашивается шагом 4.** Файл
/// `DesignTokens/ядро-дизайна/tokens/spacing.css` в git, и если ядро
/// однажды заведёт полушаг, сторож позеленеет сам — вместо того чтобы
/// спорить с источником, который он охраняет. Зашитый шаг пришлось бы
/// править руками, а значит он однажды разошёлся бы с ядром молча.
///
/// **Адрес сменился 12.10.2026, и смена заодно починила привязку
/// к устаревшему поколению.** Было `docs/design-handoff/tokens/`;
/// в том же пакете рядом лежал `docs/design-handoff/design/tokens/`,
/// и `README.md:190` называл источником правды именно второй. Замер:
/// восемь файлов из девяти между двумя каталогами **разошлись**
/// (`typography.css` — 1234 против 6092 байт), то есть это два
/// поколения пакета, а не копия.
///
/// > Сторож читал поколение на двое суток старше того, которое
/// > источник объявляет правдой, — и не врал, потому что шкала
/// > `--space-N` в обоих совпала до числа.
///
/// Это «запись стареет молча» в чистом виде: неверный адрес ничего
/// не стоил ровно до того дня, когда поколения разошлись бы и в этой
/// части. Проверяется за минуту:
/// `cmp DesignTokens/ядро-дизайна/tokens/spacing.css <любая копия>`.
///
/// **Чего этот сторож НЕ утверждает — что округлять.** Замер 05.10:
/// все пять наших значений дают остаток 2 по модулю 4 и каждое стоит
/// **ровно посередине** между двумя соседями ядра (2 между 0 и 4,
/// 6 между 4 и 8, и так все пять). Это не пять случайных значений,
/// а **половинная сетка**, прожившая рядом с целой. Поэтому сообщение
/// называет **оба** соседа: выбор между ними — решение о вёрстке,
/// и арифметикой его не подменить.
///
/// **Исключения «линии 1–4 px» здесь нет нарочно.** Менеджер назвал его
/// как часть правила ядра, но замер 05.10 его в источнике не нашёл:
/// `grep -niE '1–4|hairline'` по `README.md`, `DECISIONS.md` и всем
/// `tokens/*.css` даёт ноль. Правило, которого источник не говорит,
/// в сторожа не вписывается — иначе сторож начнёт охранять нашу память
/// вместо хендоффа. Появится в источнике — появится здесь, и строкой
/// ниже написано, как.
///
/// **`screenPadding` — не наша забота.** Ядро задаёт его адаптивным
/// (16 на 320–374 pt, 20 от 375), у нас одно число и оси ширины нет.
/// Граница этому написана в `StructuralGapsTests.metricsMatchHandoff`
/// вместе с тем, что её снимет; здесь она не дублируется.
@Suite("Сетка отступов шага 4")
struct SpacingGridTests {

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().deletingLastPathComponent()

    /// Шкала отступов ядра — числа из `--space-N` хендоффа.
    private static func шкалаЯдра() throws -> Set<Int> {
        let путь = корень.appendingPathComponent(
            "DesignTokens/ядро-дизайна/tokens/spacing.css")
        let текст = try String(contentsOf: путь, encoding: .utf8)
        var найдено: Set<Int> = []
        let выражение = try NSRegularExpression(pattern: "--space-(\\d+)\\s*:")
        for совпадение in выражение.matches(
            in: текст, range: NSRange(текст.startIndex..., in: текст)) {
            if let диапазон = Range(совпадение.range(at: 1), in: текст),
               let число = Int(текст[диапазон]) {
                найдено.insert(число)
            }
        }
        return найдено
    }

    /// Наши примитивы отступа из источника правды по токенам.
    ///
    /// Читается `tokens.json`, а не `Tokens.generated.swift`: генерат
    /// производный, и сторож, меряющий производное, однажды померит
    /// свою же копию числа.
    private static func нашиОтступы() throws -> [(имя: String, пункты: Int)] {
        let данные = try Data(contentsOf: корень.appendingPathComponent(
            "DesignTokens/tokens.json"))
        let разбор = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
        let примитивы = ((разбор?["primitive"] as? [String: Any])?["space"]
            as? [String: Any]) ?? [:]
        var найдено: [(String, Int)] = []
        for (имя, узел) in примитивы {
            guard имя.hasPrefix("$") == false,
                  let значение = (узел as? [String: Any])?["$value"] as? String
            else { continue }
            let цифры = значение.prefix { $0.isNumber }
            if let пункты = Int(цифры) { найдено.append((имя, пункты)) }
        }
        return найдено.sorted { $0.1 < $1.1 }
    }

    /// Сколько раз примитив зовут из Swift — чтобы сообщение несло цену,
    /// а не только имя.
    private static func вызовов(_ имя: String) -> Int {
        var счёт = 0
        for место in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(место), includingPropertiesForKeys: nil)
            while let файл = обход?.nextObject() as? URL {
                guard файл.pathExtension == "swift",
                      файл.pathComponents.contains("Generated") == false,
                      let текст = try? String(contentsOf: файл, encoding: .utf8)
                else { continue }
                var остаток = Substring(текст)
                let искомое = "Space.s\(имя)"
                while let найдено = остаток.range(of: искомое) {
                    // Граница справа обязательна целиком: `Space.s1`
                    // внутри `Space.s16` — тот же класс, что `час`
                    // внутри `часто`.
                    let след = остаток[найдено.upperBound...].first
                    if след == nil || след!.isNumber == false { счёт += 1 }
                    остаток = остаток[найдено.upperBound...]
                }
            }
        }
        return счёт
    }

    // MARK: - 1. Запрет

    /// Пять примитивов половинной сетки, признанных допустимыми.
    ///
    /// **Решение Виктории 27.10.2026, дословно:** «Полусетку не трогать.
    /// Пять живых примитивов и 76 вызовов одного только `space.2`
    /// означают десятки перевёрсток с кадрами ради выравнивания,
    /// которого человек не увидит. Честнее перевести `SpacingGridTests`
    /// на явный список разрешённых исключений: эти пять известны
    /// и допустимы, а новых в коде появляться не должно. Тест тогда
    /// сторожит рост, а не прошлое».
    ///
    /// **Значение хранится рядом с именем нарочно.** Белый список —
    /// это вторая копия состояния, и разойтись с предметом он может
    /// двумя способами: примитив удалят (имя останется разрешать
    /// несуществующее) либо ему **сменят число** (разрешение уедет
    /// на значение, которого никто не обсуждал). Первое ловит
    /// `исключенияНеУстарели` ниже, второе — эта пара.
    ///
    /// Числа вызовов на 27.10.2026 — `space.2` 76, `space.6` 27,
    /// `space.10` 31, `space.14` 5, `space.18` 0 прямых. У последнего
    /// ноль прямых не значит «мёртв»: он держит
    /// `semantic.spacing.screenPadding`, живой в 24 файлах.
    private static let исключения: [String: Int] = [
        "2": 2, "6": 6, "10": 10, "14": 14, "18": 18,
    ]

    @Test("Новых примитивов отступа вне шкалы ядра не появляется")
    func примитивовВнеСеткиНет() throws {
        let ядро = try Self.шкалаЯдра()
        let наши = try Self.нашиОтступы()
        let вне = наши.filter { ядро.contains($0.пункты) == false }
            .filter { Self.исключения[$0.имя] != $0.пункты }

        for (имя, пункты) in вне {
            let низ = пунктыНиже(пункты, ядро)
            let верх = пунктыВыше(пункты, ядро)
            let соседи = [низ, верх].compactMap { $0 }
                .map(String.init).joined(separator: " или ")
            #expect(Bool(false), """
                НОВЫЙ примитив вне шкалы ядра: `primitive.space.\(имя)` \
                = \(пункты) pt. Зовут из Swift \(Self.вызовов(имя)) раз. \
                Соседи по шкале: \(соседи). Пять известных исключений \
                половинной сетки (2 · 6 · 10 · 14 · 18) разрешены \
                решением Виктории 27.10.2026 и перечислены в `исключения` \
                — этого среди них НЕТ. \
                Либо ставить значение на шкалу ядра, либо вносить \
                в `исключения` ВМЕСТЕ С РЕШЕНИЕМ, кто и когда разрешил: \
                список без имени решившего через месяц неотличим \
                от списка «так исторически сложилось».
                """)
        }
    }

    /// Белый список обязан устаревать ГРОМКО.
    ///
    /// Разрешение, пережившее свой предмет, — это дыра ровно того
    /// размера, что и само разрешение: примитив удалят или ядро заведёт
    /// полушаг, а список молча продолжит пускать имя. У нас это уже
    /// оплачено дважды в соседних местах: «погас прокси» у сторожа
    /// локализации и храповик, стоявший выше факта, —
    /// `DesignLiteralTests`, 27.10.2026.
    ///
    /// Поэтому каждое исключение проверяется с ДВУХ концов: оно ещё
    /// существует в `tokens.json` с тем же числом **и** оно ещё нужно,
    /// то есть ядро его по-прежнему не содержит.
    @Test("Исключения половинной сетки не устарели")
    func исключенияНеУстарели() throws {
        let ядро = try Self.шкалаЯдра()
        let наши = Dictionary(uniqueKeysWithValues:
            try Self.нашиОтступы().map { ($0.имя, $0.пункты) })

        for (имя, пункты) in Self.исключения.sorted(by: { $0.key < $1.key }) {
            #expect(наши[имя] == пункты, """
                исключение `primitive.space.\(имя)` = \(пункты) pt \
                разошлось с источником: в `tokens.json` сейчас \
                \(наши[имя].map { "\($0) pt" } ?? "его нет вовсе"). \
                Разрешение пережило свой предмет — снять его из \
                `исключения`, а не править число здесь.
                """)
            #expect(ядро.contains(пункты) == false, """
                исключение `primitive.space.\(имя)` = \(пункты) pt \
                больше НЕ НУЖНО: ядро завело этот шаг у себя, \
                значит значение стало законным само. Снять из \
                `исключения` — иначе список разрешает то, что уже \
                разрешено шкалой, и прячет следующий случай.
                """)
        }
    }

    private func пунктыНиже(_ значение: Int, _ шкала: Set<Int>) -> Int? {
        шкала.filter { $0 < значение }.max()
    }

    private func пунктыВыше(_ значение: Int, _ шкала: Set<Int>) -> Int? {
        шкала.filter { $0 > значение }.min()
    }

    // MARK: - 2. Было что проверять

    @Test("Разбор состоялся: шкала ядра и наши примитивы прочитаны")
    func разборСостоялся() throws {
        let ядро = try Self.шкалаЯдра()
        #expect(ядро.count >= 15, """
            шкала ядра прочитана как \(ядро.count) значений при 17 \
            на 05.10.2026 (0…64 шагом 4). Разбор `spacing.css` развалился — \
            запрет выше зелёный, потому что ему нечего запрещать.
            """)
        #expect(ядро.contains(4) && ядро.contains(32), """
            в шкале ядра нет 4 или 32 — прочитан не тот файл.
            """)

        let наши = try Self.нашиОтступы()
        #expect(наши.count >= 10, """
            наших примитивов отступа прочитано \(наши.count) при 13 \
            на 05.10.2026. Либо `tokens.json` разобран не весь, либо \
            примитивы переехали из `primitive.space`.
            """)

        // Сумма вызовов: если счётчик перестанет находить что-либо,
        // сообщения запрета обесценятся молча.
        let всего = наши.map { Self.вызовов($0.имя) }.reduce(0, +)
        #expect(всего >= 150, """
            вызовов отступов найдено \(всего) при 291 на 05.10.2026. \
            Счётчик вызовов ослеп — цена в сообщениях выше станет ложной.
            """)
    }

    // MARK: - 3. Границы

    @Test("Границы: чего не проверяет набор про шкалу отступов")
    func границыНабора() {
        // 1. **Числа в коде мимо токенов не видны.** Сторож читает
        //    `tokens.json`; `padding(18)` литералом во вью он не найдёт
        //    вовсе. То есть «вне сетки» здесь значит «вне сетки СРЕДИ
        //    ТОКЕНОВ».
        //    *Снимет границу:* сторож на числовые литералы в
        //    `padding`/`spacing`/`frame` у вью — его нет, и он даст
        //    ложных срабатываний много (размеры иконок, высоты строк),
        //    поэтому заводить его надо от списка модификаторов,
        //    а не от числа.
        //
        // 2. **Семантический и компонентный слои не проверяются.**
        //    Ссылка `{primitive.space.18}` из `semantic.spacing.*`
        //    пройдёт молча: запрет стоит на примитивах. Это нарочно —
        //    починка примитива лечит все ссылки разом, а запрет
        //    на ссылки покраснел бы дважды об одном.
        //
        // 3. **Что человек УВИДИТ — не проверено ничем здесь.** Сторож
        //    меряет числа в JSON. Что сдвиг на 9 кадрах из 10 — это
        //    замер `togo-5a` кадрами, и он в статусе, а не тут.
        //    *Снимет границу:* кадры по одному примитиву за прогон;
        //    час с лишним под нынешней загрузкой, и за ним решение
        //    `togo-5a`.
        //
        // 4. **`screenPadding` намеренно не здесь.** Ядро задаёт ось
        //    ширины (16 на 320–374, 20 от 375), у нас оси нет вовсе —
        //    это не округление, а новая величина. Граница живёт
        //    в `StructuralGapsTests.metricsMatchHandoff`, и дублировать
        //    её здесь значило бы завести второе место, которое
        //    устареет не вместе с первым.
        //
        // 5. **Исключение «линии 1–4 px» не закодировано, потому что
        //    в источнике его нет** (замер 05.10, grep по трём файлам
        //    хендоффа — ноль). *Снимет границу:* строка в
        //    `DesignTokens/ядро-дизайна/tokens/spacing.css` или в `Дизайн/КОНТРАКТ-ПАКЕТА.md`,
        //    называющая исключение; тогда сюда добавляется список имён
        //    примитивов, которым оно разрешено, — поимённо, а не
        //    диапазоном, чтобы «1–4» не прикрыло заодно `space.2`
        //    в роли зазора.
    }
}
