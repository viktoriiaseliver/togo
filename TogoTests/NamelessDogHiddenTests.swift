import Testing
import Foundation
import SwiftData
@testable import Togo

/// Безымянные записи о собаке **не показываются** — и не удаляются.
///
/// Отзыв TestFlight 06.10.2026 по сборке 271: «Много пустых собак» —
/// одна настоящая и восемь строк без подписи. Решение Виктории 07.10:
/// скрывать, а не стирать.
///
/// **Почему скрывать, хотя утром решили удалять.** Пустая запись может
/// быть настоящей собакой на полпути: зеркало CloudKit создаёт строку
/// и заполняет атрибуты не одновременно, и от фантома такая запись
/// неотличима ничем — ни кличкой, ни связями. Удаление необратимо
/// и уносит одиннадцать каскадов; «не показать» самоисправляется,
/// когда кличка доедет.
///
/// **Порядок тестов — часть смысла.** Сначала то, что обязано быть
/// ВИДНО: «безымянных не видно» выполняется и тогда, когда не видно
/// никого, и у нас это оплачено порогом 0 на Kvit.
@Suite("Безымянные собаки не показываются")
@MainActor
struct NamelessDogHiddenTests {

    private func контекст() -> ModelContext {
        ModelContext(Persistence.container())
    }

    private func состояние() -> AppState {
        let s = AppState()
        s.activeDogID = nil
        return s
    }

    // MARK: 1. Что обязано быть видно

    @Test("Собака с кличкой видна")
    func сКличкойВидна() throws {
        let context = контекст()
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        try context.save()

        let показываемые = try context.fetch(FetchDescriptor<Dog>()).shownToPerson
        #expect(показываемые.count == 1, "скрыли собаку с кличкой")
        #expect(показываемые.first?.name == "Стич")
    }

    /// **Самое опасное место скрытия.** Если безымянная запись окажется
    /// активной, человек получит пустой профиль и решит, что потерял
    /// собаку: экран не скажет «запись неполная», он просто ничего
    /// не покажет.
    @Test("Активной становится собака с кличкой, а не безымянная")
    func активнаяСКличкой() throws {
        let context = контекст()
        // Безымянная вставлена ПЕРВОЙ: `activeDog` при отсутствии выбора
        // берёт `first`, а порядок `@Query` без сортировки нам
        // не принадлежит. То есть без фильтра это не редкий случай,
        // а лотерея.
        context.insert(Dog(name: "", weightKg: 0))
        let стич = Dog(name: "Стич", weightKg: 4.7)
        context.insert(стич)
        try context.save()

        let собаки = try context.fetch(FetchDescriptor<Dog>())
        let активная = состояние().activeDog(from: собаки)

        #expect(активная?.id == стич.id, """
            активной оказалась безымянная запись. Человек открывает
            приложение и видит пустой профиль — и решает, что потерял
            собаку, а не что запись неполная.
            """)
    }

    @Test("Когда безымянная выбрана вручную, активной всё равно станет собака с кличкой")
    func выборНаБезымяннуюНеДержится() throws {
        let context = контекст()
        let пустая = Dog(name: "", weightKg: 0)
        context.insert(пустая)
        let стич = Dog(name: "Стич", weightKg: 4.7)
        context.insert(стич)
        try context.save()

        let состояние = состояние()
        состояние.activeDogID = пустая.id

        let активная = состояние.activeDog(from: try context.fetch(FetchDescriptor<Dog>()))
        #expect(активная?.id == стич.id, """
            выбор, сделанный до появления фильтра, держит безымянную
            запись активной. Выбор лежит в `UserDefaults` и переживает
            обновление приложения — значит человек, у которого она была
            выбрана, после обновления получил бы пустой экран.
            """)
    }

    // MARK: 2. Что обязано быть скрыто

    @Test("Безымянная запись не показывается")
    func безымяннаяСкрыта() throws {
        let context = контекст()
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        for кличка in ["", " ", "\u{00A0}", "\n"] {
            context.insert(Dog(name: кличка, weightKg: 0))
        }
        try context.save()

        let всего = try context.fetch(FetchDescriptor<Dog>())
        #expect(всего.count == 5, "записи не сохранились — проверять нечего")
        #expect(всего.shownToPerson.count == 1, """
            показываемых \(всего.shownToPerson.count) из одной.
            Кличка из одних пробелов — не кличка: неразрывный пробел
            U+00A0 приезжает опечаткой с французской клавиатуры
            и рисуется ровно так же пусто, как "".
            """)
    }

    /// **Делить безымянные на «с историей» и «без» больше незачем** —
    /// мы ничего не удаляем. Утром это деление было защитой
    /// от необратимости; теперь оно было бы лишним условием, которое
    /// однажды разойдётся с правилом показа.
    @Test("Безымянная с историей скрыта так же, как без неё")
    func безымяннаяСИсториейТожеСкрыта() throws {
        let context = контекст()
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        let затёртая = Dog(name: "", weightKg: 4.7)
        context.insert(затёртая)
        let отметка = LogEvent(kind: .meal, authorName: "Виктория")
        отметка.grams = 60
        отметка.dog = затёртая
        context.insert(отметка)
        try context.save()

        let всего = try context.fetch(FetchDescriptor<Dog>())
        #expect(всего.shownToPerson.count == 1)
        #expect(всего.count == 2, "запись с историей удалена — мы ничего не удаляем")
        #expect(затёртая.events.count == 1, "история пропала")
    }

    // MARK: 3. Самоисправление — то, ради чего всё поменялось

    @Test("Запись, у которой появилась кличка, появляется сама")
    func кличкаДоехалаИЗаписьПоявилась() throws {
        let context = контекст()
        let доезжающая = Dog(name: "", weightKg: 0)
        context.insert(доезжающая)
        try context.save()
        #expect(try context.fetch(FetchDescriptor<Dog>()).shownToPerson.isEmpty)

        // Зеркало доложило атрибуты.
        доезжающая.name = "Багира"
        доезжающая.weightKg = 5.2
        try context.save()

        let показываемые = try context.fetch(FetchDescriptor<Dog>()).shownToPerson
        #expect(показываемые.count == 1, """
            кличка доехала, а запись не появилась. Это и есть
            самоисправление, ради которого удаление заменили
            скрытием: удалённая запись не вернулась бы никогда.
            """)
        #expect(состояние().activeDog(from: показываемые)?.name == "Багира",
                "появилась в списке, но не стала активной — экран остался пустым")
    }

    // MARK: 4. Перепись считает и ничего не стирает

    @Test("Перепись находит безымянных и не удаляет ни одной")
    func переписьНеУдаляет() throws {
        let context = контекст()
        context.insert(Dog(name: "Стич", weightKg: 4.7))
        context.insert(Dog(name: "", weightKg: 0))
        context.insert(Dog(name: " ", weightKg: 0))
        try context.save()

        let найдено = NamelessDogAudit.перепись(in: context)

        #expect(найдено == 2, "перепись нашла \(найдено) безымянных из двух")
        #expect(try context.fetch(FetchDescriptor<Dog>()).count == 3, """
            перепись удалила записи. Она обязана только считать:
            скрытие ничего не стирает, и по её счётчику мы узнаём,
            копятся эти записи или живут по одному дню — вопрос,
            который до 07.10.2026 был неизмерим.
            """)
    }
}
