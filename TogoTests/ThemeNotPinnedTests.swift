import Testing
import Foundation

/// Тема выбирается системой, и ничто в приложении её не прибивает.
///
/// **Почему этот сторож существует.** 07.10.2026 заведены четыре режима:
/// 24 цветных примитива, 57 ссылок на 27 общих динамических цветов,
/// 19 пар контраста измерены в каждом из четырёх режимов, приёмка
/// зелёная. И всё это **не доходило до экрана**: в корне приложения
/// стоял `.preferredColorScheme(.dark)`, то есть схема была прибита
/// к тёмной при любой настройке телефона.
///
/// > **Значение верное, вызов бессильный.** Токены верны, сторож
/// > контраста зелен, инструкция тестировщику зовёт переключать тему —
/// > и ни одно из трёх не смотрит на то, СПРАШИВАЕТ ли приложение
/// > систему.
///
/// Рядом с этим стоял комментарий, верный в день написания: «макет
/// собран на чёрном, и светлой пары к нему нет». Светлая пара
/// появилась, комментарий остался — и **держал код**: он объяснял
/// строку, и потому строку не трогали.
///
/// **Чего этот сторож НЕ умеет, названо сразу.** Он читает исходник,
/// то есть ловит «модификатор вернулся», а не «тема не переключается».
/// Второе доказывает только кадр в двух положениях системы, и его
/// нет: у нас записано, что утверждение о показе принимает кадр.
/// Поэтому ноль здесь значит «корень схему не прибивает», а не
/// «светлая тема работает».
@Suite("Тема не прибита к тёмной")
struct ТемаНеПрибитаTests {

    /// Где смотрим. Виджет и расширения НЕ входят нарочно: у них своя
    /// среда, и системная тема там не наша — прибивать схему в галерее
    /// или превью законно.
    private static let каталоги = ["Togo", "TogoShared"]

    @Test("`preferredColorScheme` не прибивает схему в приложении")
    func схемаНеПрибита() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [String] = []
        var файлов = 0

        for каталог in Self.каталоги {
            let папка = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                файлов += 1
                let текст = try String(contentsOf: путь, encoding: .utf8)
                for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                    let t = строка.trimmingCharacters(in: .whitespaces)
                    // Комментарий — не код. Сканирующий сторож, который
                    // их не различает, запрещает ПИСАТЬ про ошибку там,
                    // где её не совершают, — а над этим местом как раз
                    // написано двадцать строк о том, почему так нельзя.
                    if t.hasPrefix("//") { continue }
                    guard t.contains("preferredColorScheme(") else { continue }
                    // Галерея и превью — законное место: они показывают
                    // оба положения нарочно.
                    let имя = путь.lastPathComponent
                    if имя.contains("Gallery") || имя.contains("Preview") { continue }
                    найдено.append("\(имя):\(номер + 1)  \(t.prefix(80))")
                }
            }
        }

        // Проверка, что было что проверять: сканер, читающий ноль файлов,
        // молчит так же, как сканер, которому нечего сказать.
        #expect(файлов >= 150, """
            прочитано \(файлов) файлов — обход читает не то дерево.
            Проверять надо инструмент, а не проект.
            """)

        #expect(найдено.isEmpty, """
            схема прибита в \(найдено.count) местах:

            \(найдено.joined(separator: "\n"))

            Тему выбирает СИСТЕМА. Четыре режима в токенах не доходят
            до экрана, если корень приложения прибивает схему: значение
            верное, вызов бессильный.

            Если нужно показать одно положение нарочно — это галерея
            или превью, и имя файла должно это называть.
            """)

        print("""
            ГРАНИЦА: читается ИСХОДНИК. Этот сторож ловит «модификатор \
            вернулся» и НЕ ловит «тема не переключается» — второе \
            доказывает только кадр в двух положениях системы, и его нет.
            Ноль здесь значит «корень схему не прибивает», а не «светлая \
            тема работает».
            """)
    }
}
