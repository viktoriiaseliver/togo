/// Что собака тянет за собой — то обязано уехать в архив.
///
/// **Чем это оплачено.** 07.10.2026 нашлось, что `DayOut` — выезды —
/// в архиве не было **вовсе**, при том что `TodayScreen` читает их
/// запросом и меняет по ним поведение главного экрана, а «Удалить все
/// данные» про них знает. Не знал только перенос.
///
/// Цена молчания: человек, переезжающий на новый телефон, терял все
/// выезды, и узнать об этом ему было негде. Это не дефект показа,
/// на который жалуются в тот же день, — это потеря данных, которую
/// обнаруживают через месяц, если вообще.
///
/// **Почему именно каскадные связи — опора.** У `Dog` одиннадцать
/// `@Relationship(deleteRule: .cascade)`, и каскад говорит прямо: эти
/// записи существуют только вместе с собакой и исчезают вместе с ней.
/// Значит ровно они и есть «её дневник», и ровно они обязаны переезжать.
/// Список выводится из исходника модели, а не перечисляется рядом:
/// перечисленный руками знает только то, что в него положили, и
/// двенадцатую связь не заметит.
///
/// Форма взята у `DogPayloadParityTests` (сторож паритета обмена,
/// `togo-1b`, 07.10): два списка, у каждого исключения причина,
/// и пороги «было что разбирать» — чтобы ослепший разбор сказал
/// «я ослеп», а не назвал потерянным всё.
@Suite("Паритет архива: что каскадно — то переезжает")
struct ArchiveParityTests {

    /// Связи, которых в архиве нет намеренно. У каждой — причина,
    /// и её непустота проверяется отдельным тестом.
    ///
    /// Пусто — и это не недосмотр: на 07.10.2026 **все одиннадцать**
    /// каскадных связей уезжают. Список существует, чтобы следующему
    /// было куда записать исключение **с причиной**, а не чтобы
    /// молча разрешить пропуск.
    private static let вАрхивеНетНамеренно: [String: String] = [:]

    /// Как связь модели называется в снимке архива.
    ///
    /// Нужно потому, что имена не совпадают по устройству: у модели
    /// хранимое свойство кончается на `Storage` (CloudKit требует
    /// опциональных связей), а в снимке лежит простое имя. Без этого
    /// отображения сторож назвал бы потерянными все одиннадцать —
    /// то есть дал бы одиннадцать ложных находок на верном коде,
    /// а после такого сторожей перестают читать.
    private static func вСнимке(_ связь: String) -> String {
        связь.hasSuffix("Storage") ? String(связь.dropLast("Storage".count)) : связь
    }

    /// Каскадные связи `Dog` — из исходника модели.
    private func каскадныеСвязи() throws -> [String] {
        let файл = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models/Dog.swift")
        let строки = try String(contentsOf: файл, encoding: .utf8)
            .components(separatedBy: .newlines)

        var связи: [String] = []
        for (i, строка) in строки.enumerated() where строка.contains("deleteRule: .cascade") {
            // Имя стоит строкой ниже атрибута: `var eventsStorage: [LogEvent]?`
            guard i + 1 < строки.count else { continue }
            let следующая = строки[i + 1].trimmingCharacters(in: .whitespaces)
            guard следующая.hasPrefix("var "),
                  let имя = следующая.dropFirst(4).split(separator: ":").first
            else { continue }
            связи.append(String(имя))
        }
        return связи
    }

    /// Поля снимка собаки — из исходника формата.
    private func полиСнимка() throws -> Set<String> {
        let файл = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Domain/BackupArchive.swift")
        let текст = try String(contentsOf: файл, encoding: .utf8)

        guard let начало = текст.range(of: "struct DogSnapshot") else { return [] }
        let хвост = текст[начало.upperBound...]
        // Тело кончается на первой строке с отступом в четыре пробела
        // и закрывающей скобкой: вложенные структуры лежат ниже.
        var поля: Set<String> = []
        for строка in хвост.components(separatedBy: .newlines) {
            if строка.hasPrefix("    }") { break }
            let голая = строка.trimmingCharacters(in: .whitespaces)
            guard голая.hasPrefix("var "),
                  let имя = голая.dropFirst(4).split(separator: ":").first
            else { continue }
            поля.insert(String(имя))
        }
        return поля
    }

    // MARK: Скаляры — то, из чего состоит медицинская карточка

    /// Поля моделей, которых в снимке нет НАМЕРЕННО, — с причиной.
    ///
    /// Ключ — `Модель.поле`.
    private static let вСнимкеНетНамеренно: [String: String] = [
        // Идентификатор записи. В архив не идёт нарочно: после
        // восстановления это ДРУГАЯ запись в другом хранилище, и `id`
        // у неё свой. У событий он как раз нужен и есть — по нему
        // работает дедупликация при «долить»; у собаки и схемы его
        // сохранение склеило бы записи между устройствами.
        "Dog.id": "после восстановления это другая запись; у события id есть и нужен для дедупликации",
        "CareTask.id": "см. Dog.id",
        "Medication.id": "см. Dog.id",
        "DoseRecord.id": "см. Dog.id",
        // Чего доза ждёт, если схема до неё не доехала.
        //
        // **Имя едет, id — НЕТ, и это решение.** `Medication.id`
        // в архив не идёт (строкой выше), значит восстановленный
        // `awaitedMedicationID` указывал бы в никуда — и выглядел бы
        // при этом валидным UUID, то есть хуже отсутствия: сшивка
        // по id молча не найдёт ничего.
        //
        // Сшивка в `SharedDiaryPayloads:962` смотрит пару «по id ИЛИ
        // по имени»; после восстановления сработает имя, и оно едет
        // (`DoseSnapshot.awaitedMedicationName`, 07.10.2026, `togo-1e`).
        // **УСЛОВИЕ, при котором это исключение перестанет быть верным:
        // если `Medication.id` начнёт ехать в архив.** Записано условием,
        // а не только причиной, по той же нужде, по которой комментарий
        // «пока нет X» обязан называть X поимённо: тогда исключение
        // находится грепом по условию, а не памятью читателя.
        //
        // Проверяется за минуту: `grep '"Medication.id"' <этот файл>` —
        // пока строка здесь, исключение в силе; исчезла — пересмотреть.
        "DoseRecord.awaitedMedicationID": "id схемы в архив не идёт (см. Medication.id) — восстановленная ссылка указывала бы в никуда; сшивка остаётся по имени. Перестанет быть верным, если Medication.id начнёт ехать в архив",
        // Когда телефон трогал запись. Факт про обмен, а не про собаку:
        // восстановленная запись изменена СЕЙЧАС, и врать об этом нельзя.
        "Dog.changedAt": "время правки на том телефоне; у восстановленной записи оно своё",
        "CareTask.changedAt": "см. Dog.changedAt",
        "WeightEntry.changedAt": "см. Dog.changedAt",
        "Medication.changedAt": "см. Dog.changedAt",
        "DoseRecord.changedAt": "см. Dog.changedAt",
        // Обратные связи: они восстанавливаются привязкой к собаке
        // и к схеме, а не значением поля.
        "CareTask.dog": "обратная связь, ставится при восстановлении",
        "Medication.dog": "обратная связь, ставится при восстановлении",
        "DoseRecord.medication": "обратная связь, ставится при восстановлении",
        "Medication.dosesStorage": "коллекция доз едет полем `doses` снимка схемы",
    ]

    /// Хранимые поля модели — из исходника, а не списком.
    private func поляМодели(_ файл: String, _ класс: String) throws -> [String] {
        let путь = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models/\(файл)")
        let строки = try String(contentsOf: путь, encoding: .utf8)
            .components(separatedBy: .newlines)
        guard let начало = строки.firstIndex(where: { $0.contains("final class \(класс)") })
        else { return [] }

        var глубина = 0
        var поля: [String] = []
        for (смещение, строка) in строки[начало...].enumerated() {
            // Уровень тела класса — единица: строка `final class X {`
            // уже открыла скобку.
            let член = глубина == 1 && строка.hasPrefix("    ")
                && !строка.hasPrefix("     ") && строка.trimmingCharacters(in: .whitespaces).isEmpty == false
            глубина += строка.filter { $0 == "{" }.count
            глубина -= строка.filter { $0 == "}" }.count
            if смещение > 0, глубина == 0 { break }
            guard член else { continue }
            let голая = строка.trimmingCharacters(in: .whitespaces)
                .replacingOccurrences(of: #"^@\w+\([^)]*\)\s*"#,
                                      with: "", options: .regularExpression)
            // Членом считается только то, что стоит на уровне тела:
            // разбор по одной строке не отличает поле от локальной
            // переменной внутри вычисляемого свойства и ошибается
            // в сторону полноты.
            guard !голая.contains("{"),
                  let поле = голая.firstMatchГруппа(#"^var (\w+): "#)
            else { continue }
            поля.append(поле)
        }
        return поля
    }

    /// Поля произвольной структуры снимка.
    private func поляСнимка(_ структура: String) throws -> Set<String> {
        let файл = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Domain/BackupArchive.swift")
        let текст = try String(contentsOf: файл, encoding: .utf8)
        guard let начало = текст.range(of: "struct \(структура)") else { return [] }

        var поля: Set<String> = []
        for строка in текст[начало.upperBound...].components(separatedBy: .newlines) {
            if строка.hasPrefix("    }") { break }
            let голая = строка.trimmingCharacters(in: .whitespaces)
            guard голая.hasPrefix("var "),
                  let имя = голая.dropFirst(4).split(separator: ":").first
            else { continue }
            поля.insert(String(имя))
        }
        return поля
    }

    /// **Сторож на связи не видит полей, а медицинская карточка состоит
    /// из полей.**
    ///
    /// Замер 07.10.2026: архив терял тридцать восемь скаляров —
    /// семнадцать у собаки, четыре у дела ухода, тринадцать у схемы
    /// лечения, четыре у дозы. Среди них номер чипа, номер страховки,
    /// врач с телефоном, **дата прививки**, **единица дозы**, срок
    /// курса, срок годности, запас и отметки пропущенных доз.
    ///
    /// Сторож на каскадные связи (выше) был прав и слеп к этому:
    /// он проверял, что уезжают КОЛЛЕКЦИИ. Тот же разрыв, что был
    /// между `DeviceLocalFieldTests` и нагрузкой обмена — один сторож
    /// делит поля, другой смотрит нагрузку, и между ними дыра.
    @Test("Каждое хранимое поле модели уезжает в архив или названо исключением")
    func скалярыУезжают() throws {
        let пары = [("Dog.swift", "Dog", "DogSnapshot"),
                    ("Care.swift", "CareTask", "CareTaskSnapshot"),
                    ("Care.swift", "Medication", "MedicationSnapshot"),
                    ("Care.swift", "DoseRecord", "DoseSnapshot")]

        // Как поле модели называется в снимке: `*Storage` у связей
        // и `doseSlotsData` → `doseSlots`.
        //
        // **`clinic` → `clinicName`, и это решение, а не косметика.**
        // Связь с клиникой хранится в файле ИМЕНЕМ, а не индексом:
        // архив человек открывает текстовым редактором — так он
        // задуман, — и «клиника № 3» в нём не значит ничего. Имя
        // клиники вдобавок ключ группировки в самой модели, то есть
        // второй сущности для сшивки не нужно.
        //
        // Без этой строки сторож называл `CareTask.clinic` потерянным
        // при живой и проверенной круговым тестом связи. Ложная находка
        // дороже пропущенной: после неё сторожа перестают читать.
        let переименования = ["doseSlotsData": "doseSlots", "clinic": "clinicName"]

        var потеряно: [String] = []
        var разобрано = 0

        for (файл, класс, снимок) in пары {
            let поля = try поляМодели(файл, класс)
            let вСнимке = try поляСнимка(снимок)
            #expect(поля.count >= 10, """
                у \(класс) разобрано \(поля.count) полей — разбор
                не состоялся, и сторож зелен впустую.
                """)
            #expect(вСнимке.count >= 5, "у \(снимок) разобрано \(вСнимке.count) полей")
            разобрано += поля.count

            for поле in поля {
                let ключ = "\(класс).\(поле)"
                if Self.вСнимкеНетНамеренно[ключ] != nil { continue }
                // Связи едут коллекциями: `eventsStorage` → `events`.
                let имя = переименования[поле]
                    ?? (поле.hasSuffix("Storage") ? String(поле.dropLast("Storage".count)) : поле)
                if вСнимке.contains(имя) { continue }
                потеряно.append(ключ)
            }
        }

        #expect(разобрано >= 90, "разобрано полей всего: \(разобрано) — разбор не состоялся")
        #expect(потеряно.isEmpty, """
            хранимое поле модели не уезжает в архив: \(потеряно.sorted()).

            Это молчаливая потеря данных при переносе на новый телефон:
            человек не увидит пустого места, он просто не найдёт поле
            через месяц. Так архив терял номер чипа, дату прививки
            и единицу дозы.

            Либо допиши поле в снимок (ОПЦИОНАЛЬНЫМ — старые файлы
            обязаны читаться), в сборку и в восстановление, либо впиши
            ключ в `вСнимкеНетНамеренно` С ПРИЧИНОЙ. Исключение без
            причины через месяц неотличимо от дыры.
            """)
    }

    @Test("У каждого «в снимке нет» записана причина")
    func причиныСкаляровЕсть() {
        let безПричины = Self.вСнимкеНетНамеренно
            .filter { $0.value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            .map(\.key).sorted()
        #expect(безПричины.isEmpty, "«в снимке нет» без причины: \(безПричины)")
    }

    @Test("Каждая каскадная связь собаки уезжает в архив")
    func каскадноеУезжает() throws {
        let связи = try каскадныеСвязи()
        let поля = try полиСнимка()

        // Сканер, переставший что-либо находить, молчит так же, как тот,
        // кому нечего сказать. Числа взяты от сегодняшнего состояния
        // и **только снизу**: связей пятнадцать (одиннадцать прежних
        // плюс четыре медицинских с 07.10.2026), полей снимка — больше
        // двадцати.
        //
        // Порог-минимум, а не равенство, и это выбор: равенство ловило
        // бы ещё и честный рост, то есть краснело бы на каждой новой
        // связи. Сегодня этот класс пришлось чинить дважды — «ровно
        // шестнадцать сущностей» и «V5 заводит тринадцать полей».
        #expect(связи.count >= 15, """
            каскадных связей разобрано \(связи.count) — разбор модели
            не состоялся. Сторож зелен впустую, а не потому, что всё
            на месте.
            """)
        #expect(поля.count >= 20, """
            полей снимка разобрано \(поля.count) — разбор формата
            не состоялся.
            """)

        var потеряно: [String] = []
        for связь in связи {
            let имя = Self.вСнимке(связь)
            if поля.contains(имя) { continue }
            if Self.вАрхивеНетНамеренно[связь] != nil { continue }
            потеряно.append(связь)
        }

        #expect(потеряно.isEmpty, """
            каскадная связь собаки не уезжает в архив: \(потеряно).

            Каскад означает, что эти записи существуют только вместе
            с собакой, — то есть они и есть её дневник. Не уехав, они
            теряются при переносе на новый телефон МОЛЧА: человек
            не увидит пустого места, он просто не найдёт их через месяц.

            Либо допиши поле в `BackupArchive.DogSnapshot` (и сборку,
            и восстановление), либо впиши связь в `вАрхивеНетНамеренно`
            с причиной. Исключение без причины через месяц неотличимо
            от дыры.
            """)
    }

    @Test("У каждого «в архив не уезжает» записана причина")
    func причиныЕсть() {
        let безПричины = Self.вАрхивеНетНамеренно
            .filter { $0.value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            .map(\.key).sorted()
        #expect(безПричины.isEmpty, "«не уезжает» без причины: \(безПричины)")
    }

    /// Граница этого сторожа, напечатанная им самим.
    ///
    /// Он сверяет **имена**: связь есть в модели, поле есть в снимке.
    /// Он **не** проверяет, что поле заполняется при сборке и читается
    /// при восстановлении. Поле, объявленное и ни разу не записанное,
    /// пройдёт его насквозь — ровно как `DogPayload` с полем, которое
    /// никто не кладёт в `CKRecord`.
    ///
    /// Это ловят круговые тесты в `BackupTests` (выгрузили →
    /// восстановили → сверили счёт), и для выездов такой тест заведён
    /// в тот же день.
    @Test("Границы: сторож паритета сверяет имена, а не заполнение")
    func границыНазваны() throws {
        let поля = try полиСнимка()
        #expect(поля.contains("daysOut"), """
            поля `daysOut` в снимке нет — значит либо правка 07.10.2026
            откатилась, либо разбор формата сломался. Оба случая стоят
            того, чтобы остановиться: первый — потеря данных при
            переносе, второй — слепой сторож.
            """)
    }
}


private extension String {
    /// Первая группа первого совпадения — или `nil`.
    func firstMatchГруппа(_ образец: String) -> String? {
        guard let re = try? NSRegularExpression(pattern: образец),
              let m = re.firstMatch(in: self, range: NSRange(startIndex..., in: self)),
              m.numberOfRanges > 1
        else { return nil }
        return Range(m.range(at: 1), in: self).map { String(self[$0]) }
    }
}
