/// У второстепенной кнопки есть ВИДИМАЯ ГРАНИЦА в обоих живых режимах.
///
/// # Чего стоил дефект
///
/// Замер 25.10.2026. `Button.Secondary.background` (`night4`)
/// и `Surface.screen` (`night1`) равны **байт в байт** в светлой теме
/// и в светлой HC, а в тёмных не дотягивают до порога границы органа:
///
/// ```
/// режим      заливка против экрана   порог WCAG 1.4.11 — 3:1
/// light                   1,0000:1   кнопки НЕ ВИДНО ВООБЩЕ
/// lightHC                 1,0000:1   кнопки НЕ ВИДНО ВООБЩЕ
/// dark                    1,8504:1   ниже порога
/// darkHC                  2,3014:1   ниже порога
/// ```
///
/// > **ПОПРАВКА 25.10, вечер: на устройстве режимов ДВА.**
/// > `UIUserInterfaceStyle = Dark` стоит в обоих plist решением Виктории
/// > 22–23.10 («Кино. Одна тема»), и светлые значения токенов на экран
/// > не попадают — они живут в превью Xcode, галерее компонентов
/// > и Фигме. Три свидетеля в одном проходе: исходник, СОБРАННЫЙ бандл
/// > (`plutil`) и пиксель. Значит строки `light`/`lightHC` ниже про то,
/// > чего человек не видит; живой была тёмная половина.
/// >
/// > **Этот набор всё равно мерит все четыре, и нарочно:** он сторожит
/// > ЗНАЧЕНИЕ токена, а значение уезжает дизайнеру в Фигму и рисуется
/// > в галерее. Неверное светлое значение вводит в заблуждение того,
/// > кто смотрит макет, — поэтому ось «все четыре» здесь верна, а вывод
/// > «человек не видит кнопку» относится только к тёмным.
/// >
/// > И вторая поправка: числа ниже — обводка против СВОЕЙ ЗАЛИВКИ,
/// > внутренняя граница. Против того, на чём кнопка лежит, в тёмных
/// > вдвое больше (12,47 и 17,67 по пикселю), а на экране вердикта
/// > кнопка лежит на панели, и там исходное было 1,45, а не 1,85.
/// > **У числа про контраст ось называется в той же строке.**
///
/// **Порога не брал ни один из четырёх режимов.** Запись в эталоне
/// (`ПовышенныйКонтрастМеняетЦветTests`, 15.10) считала тёмную
/// исправной — она мерила «видно ли плашку», а не порог, и отдельно
/// оговаривала, что порог 3,0 «покраснел бы и в тёмной, где плашка
/// видна». Оговорка была про ВЫКЛЮЧЕННУЮ кнопку, у которой WCAG 1.4.11
/// и правда не требует границы; второстепенная — действующая.
///
/// Подпись при этом держит 18,90:1: **слово человек читает прекрасно,
/// он не видит КНОПКУ.** Среди вызовов — «Понятно», «Добавить корм»,
/// «Это одно и то же», «Написать в поддержку», и «Закрыть» на экране
/// назначения, который там единственный выход.
///
/// Вызовов `variant: .secondary` на 25.10 — **тридцать**. В эталоне
/// записано десять, замером от 15.10: за десять дней втрое.
///
/// # Цвет контура — слово дизайна, круг 6, пункт 6
///
/// Контур 1 pt `Line.control` = `toggleOff` = `#767676` в тёмной,
/// `#8E8E93` в повышенном контрасте. **Нового цвета нет:** то же
/// значение держит дорожку выключенного переключателя, утверждённую
/// кругом 5.
///
/// ```
/// контур к экрану   #000000   дизайн 4,6   у нас 4,62   ✔
/// контур к карточке #1C1C1E   дизайн 3,7   у нас 3,75   ✔
/// HC к карточке     #242426   дизайн 4,7   у нас 4,75   ✔
/// контроль счётчика: #767676 на белом 4,54 · #777777 4,48 — оба
///                    совпали с документированной границей W3C
/// ```
///
/// # ЧЕМ ЭТО ЗАМЕНИЛО МОЙ ВЫБОР, и почему отклонение верное
///
/// 25.10 я поставила `Ink.secondary` — 6,74 к заливке. Дизайн отклонил
/// с названной причиной: «**6,74:1 спорит с белой главной кнопкой
/// и с кольцом фокуса**». То есть дефект был не в числе: орган второго
/// порядка начинал выглядеть первым, и «больше контраста» здесь
/// ухудшало экран.
///
/// > **Порог — нижняя граница, а не цель.** У числа контраста есть
/// > и верхний предел, заданный не нормой, а иерархией, и норма
/// > о нём молчит. Я мерила только снизу.
///
/// Заливку на `night5` вслед за выключенной перевести нельзя:
/// второстепенная и выключенная слиплись бы, и на это стоит
/// `ThemeContrastTests.нажатоеИВыключенноеНеСлипнутся`.
/// Стеклянные кнопки на фото («Гулять», «+») контур не получают —
/// то же слово дизайна.
///
/// # ЧЕГО ЭТОТ НАБОР НЕ ВИДИТ, и это названо, а не умолчано
///
/// 1. **Он не видит, НАРИСОВАНА ли обводка на экране.** Второй тест
///    читает исходник `TGButton.swift` и проверяет, что `strokeBorder`
///    там есть и берёт тот самый токен. Это ответ про исходник,
///    а не про пиксель: `.overlay` можно перекрыть, модификатор —
///    поставить в другом порядке, кнопку — нарисовать поверх чужим
///    фоном. ~~Приёмка такой правки — кадр, и кадра пока нет.~~
///    Кадр был снят (`3c05dc1`) и **доказывает ПРЕЖНИЙ контур**: разрез
///    через кромку дал три пикселя `#C7C7CC` — это `Ink.secondary`,
///    цвет, который дизайн отклонил. Нынешний контур `#767676`
///    на кадре НЕ ПРОВЕРЕН, и после смены цвета тот набор снова «до».
///    > **Кадр доказывает цвет, а не наличие.** Поэтому смена значения
///    > обнуляет приёмку так же, как снятие модификатора: разрез
///    > по-прежнему найдёт три пикселя, только не те. Приёмка этой
///    > правки — новый разрез на новом кадре, с проверкой байт против
///    > `#767676`, а не против «хоть чего-то светлого».
///
///    Что кадр всё-таки доказал и остаётся верным: обводка **рисуется**
///    (три пикселя — `hairline` 1 pt при @3x, прозрачность цвет
///    не съела) и **ветка `isEnabled` работает** — у выключенной пилюли
///    контура нет, и разрез там снят мимо глифа нарочно: через букву
///    он напечатал бы светлый пиксель и соврал бы.
/// 2. Комментарии вырезаются ПРЕЖДЕ разбора, и это не вежливость:
///    доккомментарий у самой правки в `TGButton.swift` называет
///    предмет словами, и сторож на прозе позеленел бы от него.
///    Класс оплачен дважды в этом проекте.
/// 3. Арифметика повторена здесь, а не позвана у соседнего набора, —
///    по его же доводу: набор, зовущий чужой private-счётчик,
///    краснеет от чужой правки.
@MainActor
@Suite("У второстепенной кнопки видна граница")
struct ГраницаВторостепеннойКнопкиTests {

    struct Режим: Sendable {
        let имя: String
        let тёмная: Bool
        let контраст: Bool
    }

    private static let режимы = [
        Режим(имя: "light", тёмная: false, контраст: false),
        Режим(имя: "lightHC", тёмная: false, контраст: true),
        Режим(имя: "dark", тёмная: true, контраст: false),
        Режим(имя: "darkHC", тёмная: true, контраст: true),
    ]

    /// Порог границы действующего органа. WCAG 2.1, 1.4.11
    /// Non-text Contrast.
    private static let порогГраницы = 3.0

    // MARK: - Контроль: было ли что сторожить

    @Test("Контроль: заливка второстепенной кнопки САМА порога не берёт")
    func заливкаПорогаНеБерёт() {
        var взяли: [String] = []
        for режим in Self.режимы {
            let к = Self.контрастЗаливки(режим: режим)
            if к >= Self.порогГраницы { взяли.append("\(режим.имя) \(Self.число(к))") }
        }
        #expect(взяли.isEmpty, """
        заливка взяла порог в режимах: \(взяли.joined(separator: ", ")).

        ЭТО НЕ ПОВОД РАДОВАТЬСЯ — это значит, что обводка больше
        не нужна и предмет у набора ниже исчез. Если Виктория дала
        второстепенной кнопке своё значение в рампе, обводку надо
        СНЯТЬ, а не держать поверх: две границы у одного органа —
        тот же класс «два механизма на одно дело», которым проект
        уже платил.
        """)
    }

    @Test("Контроль: арифметика воспроизводит документированную границу W3C")
    func арифметикаЖива() {
        // `#767676` на белом — граница 4,5, названная самим W3C;
        // соседний `#777777` её уже не проходит. Если счётчик уедет,
        // разойдутся обе, и числа выше замером не являются.
        let белый = Color(hex: 0xFFFFFFFF)
        let светлый = Режим(имя: "light", тёмная: false, контраст: false)
        let на = Self.контраст(Color(hex: 0x767676FF), на: белый, режим: светлый)
        let мимо = Self.контраст(Color(hex: 0x777777FF), на: белый, режим: светлый)
        #expect((на - 4.54).magnitude < 0.01, "ждали 4,54, вышло \(Self.число(на))")
        #expect(мимо < 4.5, "ждали ниже 4,5, вышло \(Self.число(мимо))")
    }

    // MARK: - Предмет

    /// Ось — против того, на чём кнопка ЛЕЖИТ, и только в живых режимах.
    ///
    /// # Прежняя редакция мерила не ту ось, и я это сделала сама
    ///
    /// Стояло «контур против своей ЗАЛИВКИ» во всех четырёх режимах.
    /// Две ошибки в одном утверждении:
    ///
    /// 1. **Внутренняя граница.** WCAG 1.4.11 говорит о границе
    ///    с СОСЕДНИМ цветом — тем, на чём орган лежит, — а не со своей
    ///    заливкой. Числа 6,74 и 7,68 были верны и отвечали не на тот
    ///    вопрос.
    /// 2. **Светлых режимов на устройстве нет.** `UIUserInterfaceStyle
    ///    = Dark` в обоих plist решением Виктории 22–23.10 («Кино. Одна
    ///    тема»). Светлые значения уезжают дизайнеру в Фигму и рисуются
    ///    в галерее, но человек их не видит.
    ///
    /// Поэтому порог здесь требуется от **двух живых режимов**,
    /// а светлые печатаются числом без требования: у `toggleOff` они
    /// взяты у `night5` и дизайном **не проверены** — так сказано
    /// в его собственном описании. Требовать порога от значения,
    /// которого дизайн не называл, значило бы покраснеть на своём
    /// наследстве и выдать это за дефект продукта.
    ///
    /// # Подложки взяты две, и обе названы дизайном
    ///
    /// ```
    /// экран    Surface.screen   #000000 dark · #000000 darkHC
    /// карточка Surface.card     #1C1C1E dark · #242426 darkHC
    /// дизайн назвал: 4,6 к чёрному · 3,7 к карточке · HC 4,7
    /// ```
    ///
    /// Карточка — худшая из двух, и именно она решает: на экране
    /// вердикта кнопка лежит не на фоне экрана, а на нижней панели,
    /// и там исходное было **1,45**, а не 1,85.
    @Test("Граница берёт 3:1 на экране и на карточке в обоих живых режимах")
    func границаБерётПорог() {
        let живые = Self.режимы.filter(\.тёмная)
        #expect(живые.count == 2, """
        живых режимов \(живые.count), а не два — список режимов правили,
        не поправив этот фильтр. Светлые на устройстве не рисуются
        (`UIUserInterfaceStyle = Dark` в обоих plist), и порога
        с них требовать нельзя.
        """)

        var мало: [String] = []
        for режим in живые {
            for (имяФона, фон) in [("экран", Token.Surface.screen),
                                   ("карточка", Token.Surface.card)] {
                let к = Self.контраст(Token.Line.control, на: фон, режим: режим)
                if к < Self.порогГраницы {
                    мало.append("\(режим.имя) на \(имяФона) \(Self.число(к))")
                }
            }
        }
        #expect(мало.isEmpty, """
        контур второстепенной кнопки ниже порога 3:1: \
        \(мало.joined(separator: ", ")).

        Без него кнопки не видно как кнопки: заливка `#3A3A3C` даёт
        к чёрному 1,84:1, а на нижней панели — 1,45:1. Подпись при этом
        держит 18,90:1 — человек видит СЛОВО и не видит ОРГАН, то есть
        не знает, что по нему можно нажать.

        Цвет контура — слово дизайна (круг 6, п. 6): `Line.control`,
        то же значение, что у дорожки выключенного переключателя.
        Поднимать его «чтобы прошло» нельзя: предыдущий контур был
        ярче и отклонён именно за это — он спорил с белой главной
        кнопкой и с кольцом фокуса.
        """)

        // Светлые — числом, без требования. Печатается всегда, в том
        // числе когда всё сошлось: молчащий замер неотличим от того,
        // которого не делали.
        // Значение считается ДО подстановки нарочно: интерполяция
        // `\(…)`, разбитая на строки, в обычном литерале не собирается,
        // и первая редакция этой строки дала пять ошибок сборки — rc=65
        // при НУЛЕ прибитых компиляторов и пустом списке красных,
        // потому что до тестов дело не дошло.
        let светлые = Self.режимы.filter { !$0.тёмная }.map { режим -> String in
            let к = Self.контраст(Token.Line.control, на: Token.Surface.screen, режим: режим)
            return "\(режим.имя) экран \(Self.число(к))"
        }
        print("""
            ГРАНИЦА · светлые режимы НЕ ТРЕБУЮТСЯ и вот их числа: \
            \(светлые.joined(separator: " · ")).
            На устройстве они не рисуются, а значения `toggleOff` в них
            взяты у `night5` и дизайном не проверены — так сказано
            в его описании. Числа здесь для того, кто повезёт токены
            в Фигму.
            """)
    }

    @Test("У токена границы есть живой читатель, и это та самая кнопка")
    func границаНарисована() throws {
        let исходник = try Self.кодБезКомментариев("Togo/DesignSystem/Components/TGButton.swift")

        #expect(исходник.contains("struct TGButton"), """
        прочитан не тот файл — замер не состоялся. Этот вопрос стоит
        первым нарочно: «подстроки нет» и «файла нет» дают один ответ.
        """)
        #expect(исходник.contains("strokeBorder("), """
        обводки у кнопки нет вовсе. Значение границы может быть
        прекрасным и не быть нарисованным ничем — поле без читателя
        грепом находится один раз, в объявлении, и выглядит рабочим.
        """)
        #expect(исходник.contains("Token.Line.control"), """
        контур рисуется, но не тем токеном, на котором стоит замер
        выше. Числа в этом наборе тогда не про то, что на экране.

        Цвет назвал дизайн, круг 6, п. 6: `Line.control`, то же
