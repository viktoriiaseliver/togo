import Testing
import Foundation
import SwiftUI
@testable import Togo

/// Пол кегля исполняется, а не только записан.
///
/// **Повод измерен 15.10.2026, и он про источник правды.** Стиль
/// `AppFont.micro` брал `Token.FontSize.meta` = 15, то есть ступень
/// `Token.FontSize.micro` = 14 **не читал в приложении никто** — живых
/// читателей ноль. Решение было осознанным и названным в доккомментарии
/// («мета сведена к пятнадцати»), но у него была цена, которой никто
/// не мерил.
///
/// Цена: ступень **уезжает дизайнеру** — `--primitive-font-size-micro:
/// 14px` в `tokens.css` и `font/size/micro` в `figma-variables.json`
/// (с описанием, которое читает плагин в Фигме). Значит дизайнер,
/// применивший `font/size/micro`, получал **14 в макете и 15
/// в приложении**: одно имя, два значения, по разные стороны границы.
/// Доккомментарий Swift в Фигму не уезжает, а ступень уезжает.
///
/// > **Источник правды может содержать решение, которого не исполняет
/// > ни один читатель.** Грепом это не видно: имя находится, значение
/// > находится, а вызова по имени нет. Опусти `FontSize.micro` назад
/// > до 12 — на экране не изменилось бы ничего, и ни один тест
/// > не покраснел бы.
///
/// Решение Виктории 15.10.2026, прямым вопросом: **«Пол 14, макет
/// поправить»**. Привязка сделана тем же днём, радиус — **50 вызовов
/// `AppFont.micro` в 34 файлах**.
///
/// # Почему ДВЕ оси, а не одна
///
/// Ни одна из двух не ловит то, что ловит другая, и это не
/// дублирование:
///
/// ```
/// по ЗНАЧЕНИЮ   AppFont.micro.size == Token.FontSize.micro
///               ловит откат на meta (15) — настоящую регрессию
///               СЛЕПА к подмене равнозначным: FontSize.caption тоже 14,
///               и с ним проверка прошла бы
/// по ИСХОДНИКУ  строка объявления называет Token.FontSize.micro
///               ловит подмену равнозначным токеном
///               СЛЕПА к написанию через псевдоним или через переменную
/// ```
///
/// # Чего НЕ проверяет ни одна
///
/// Обе отвечают «кегль взят оттуда», а не «человек видит 14».
/// Масштабирование Dynamic Type идёт через
/// `UIFontMetrics(forTextStyle: .footnote).scaledValue(for:)`, и на
/// крупных ступенях число другое по построению. **Приёмка правки —
/// кадр**, и на 15.10 его нет: 50 мест в 34 файлах положены
/// непроверенными, выбор назван вслух.
@Suite("Пол кегля исполняется, а не записан")
struct ПолКегляTests {

    private static var исходник: String {
        get throws {
            let корень = URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent().deletingLastPathComponent()
            return try String(
                contentsOf: корень.appendingPathComponent(
                    "Togo/DesignSystem/Typography.swift"),
                encoding: .utf8)
        }
    }

    /// Строки кода без комментариев: про этот токен в прозе написано
    /// больше, чем вызвано, и сторож без вырезания мерил бы прозу —
    /// в том числе собственное объяснение прямо над правкой.
    private static func код(_ текст: String) -> [String] {
        текст.components(separatedBy: "\n")
            .map { $0.components(separatedBy: "//")[0] }
    }

    @MainActor
    @Test("Стиль micro берёт ступень micro, а не соседнюю")
    func кегльИзСвоейСтупени() {
        // Своё зрение первым: если ступени равны между собой, проверка
        // ниже проходит тривиально и ничего не значит.
        #expect(Token.FontSize.micro != Token.FontSize.meta, """
            FontSize.micro (\(Token.FontSize.micro)) и FontSize.meta
            (\(Token.FontSize.meta)) стали равны — тогда проверка ниже
            проходит при любой привязке и ничего не доказывает.
            Сторожу нужна новая ось.
            """)

        #expect(AppFont.micro.size == Token.FontSize.micro, """
            стиль `AppFont.micro` берёт кегль \(AppFont.micro.size),
            а ступень `Token.FontSize.micro` — \(Token.FontSize.micro).

            Решение Виктории 15.10.2026: «Пол 14, макет поправить».
            До 15.10 стиль брал `meta` = 15, и ступень 14 не читал никто:
            дизайнер, применивший `font/size/micro` в Фигме, получал 14
            в макете и 15 в приложении.

            Если это откат — он обязан быть решением с хозяином,
            а не правкой: ступень уезжает дизайнеру в tokens.css
            и figma-variables.json, и расхождение увидит он, а не мы.
            """)
    }

    @Test("Привязка названа тем самым токеном, а не равнозначным")
    func привязкаИменем() throws {
        let строки = Self.код(try Self.исходник)

        // Было ли что сторожить. Ноль найденных объявлений значит
        // «нечего было смотреть», а не «чисто».
        let объявления = строки.filter {
            $0.range(of: #"\bstatic\s+let\s+micro\s*="#, options: .regularExpression) != nil
        }
        #expect(объявления.count == 1, """
            объявлений `static let micro =` в Typography.swift найдено
            \(объявления.count), ожидалось 1. Ноль — предмет переименован
            и сторож смотрит не туда; больше одного — предмет размножился.
            """)

        let строка = объявления.first ?? ""
        #expect(строка.contains("Token.FontSize.micro"), """
            объявление `AppFont.micro` не называет `Token.FontSize.micro`:

              \(строка.trimmingCharacters(in: .whitespaces))

            Проверка по значению этого не поймает: `FontSize.caption`
            тоже 14, и с ним кегль совпал бы, а привязка указывала бы
            не на ту ступень. Ступень `micro` уезжает дизайнеру под своим
            именем — значит и в коде она должна называться своим.
            """)
    }
}
