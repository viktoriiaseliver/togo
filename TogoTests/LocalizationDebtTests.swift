    /// **Проверка самого разбора, а не его результата.**
    ///
    /// До 07.10.2026 разбор переключал «внутри литерала» на каждой
    /// кавычке и потому ломался на строке с интерполяцией, внутри
    /// которой есть ещё кавычки. Кириллица в ИМЕНИ функции читалась
    /// как непереведённая строка: `Fmt.кличка` дала два ложных
    /// срабатывания в `SnapshotText` на верном коде, и чинили это
    /// переименованием, а не сторожем.
    ///
    /// Поэтому здесь не «сколько долга в проекте», а «что именно
    /// разбор считает строкой». У нас записано: проверять надо
    /// и результат, и границу инструмента, и вторая проверка делается
    /// реже первой примерно никогда.
    ///
    /// Оба края обязательны. Без первого разбор мог бы перестать
    /// считать что-либо вовсе и был бы зелёным; без второго —
    /// считать всё и краснеть на верном коде.
    /// Причина у пометки «внутреннее» — или `nil`, если пометки нет.
    ///
    /// Форма: `// внутреннее: <почему эту строку не переводят>`.
    ///
    /// **Зачем отдельный механизм рядом с исключениями по файлу.**
    /// Исключение файлом — это слепота на весь файл, и она растёт
    /// молча: в день, когда в «исключённый» файл допишут строку
    /// для человека, сторож промолчит. У `StorageFailureAdvice.swift`
    /// одна внутренняя строка (`"хранилище: iCloud"` — маркер
    /// для разбора крошек запуска) и шесть живых переводимых рядом.
    ///
    /// > **Пометка строкой говорит про строку. Исключение файлом
    /// > говорит про всё, что в файле когда-либо появится.**
    static func пометкаВнутреннего(_ строка: String) -> String? {
        guard let i = строка.range(of: "// внутреннее:") else { return nil }
        return String(строка[i.upperBound...]).trimmingCharacters(in: .whitespaces)
    }

