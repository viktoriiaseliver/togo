    @Test("Непереведённых строк в общем слое не становится больше")
    func долгНеРастёт() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("TogoShared")

        let ключи = try ключиКаталога()
        #expect(ключи.count > 500,
                "каталог прочитан не весь (\(ключи.count) ключей) — разбор не состоялся")

        var посчитано: [String: Int] = [:]
        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
            let имя = элемент.lastPathComponent
            guard исключения[имя] == nil else { continue }
            var n = 0
            for строка in текст.components(separatedBy: .newlines) {
                // **Пометка СТРОКОЙ, а не файлом.** Исключение файлом
                // ослепляет сторож на весь файл: в
                // `StorageFailureAdvice.swift` одна внутренняя строка
                // и ШЕСТЬ живых переводимых рядом — спрятав файл,
                // мы спрятали бы и их.
                //
                // Замечание togo-02 от 07.10, оплаченное на сторо́же
                // подстановок клички: «файловое исключение спрятало бы
                // и настоящий показ, который в тех же файлах есть».
                //
                // Проверяется до вырезания прозы нарочно: пометка
                // и есть проза, и после вырезания её не останется.
                if let причина = Self.пометкаВнутреннего(строка) {
                    #expect(причина.count >= 10, """
                        пометка «внутреннее» без причины в \(имя): «\(строка.trimmingCharacters(in: .whitespaces))».
                        Исключение без причины через месяц неотличимо
                        от дыры — у нас это записано ценой целого дня.
                        """)
                    continue
                }
                let код = строка.components(separatedBy: "//")[0]
                // Строка в журнал разработчика — не подпись. Её читает тот,
                // кто чинит, а не хозяин собаки; переводить её значит
                // превращать диагностику в текст для человека.
                // Тот же признак, что и у Tools/extract_texts.py.
                // `StartupLog.note` здесь по той же причине, что и
                // `log.*`: это крошки запуска. Их забирают с телефона
                // скриптом, когда приложение не поднялось, и читает их
                // тот, кто ищет причину. Файлы `StartupLog.swift`
                // и `DogOrigin.swift` исключены целиком именно за это —
                // а вызов из соседнего файла считался долгом, хотя
                // строка та же и читатель тот же.
                if код.contains("log.error(") || код.contains("log.notice(")
                    || код.contains("log.debug(") || код.contains("log.info(")
                    || код.contains("log.warning(")
                    || код.contains("StartupLog.note(") { continue }
                n += Self.русскиеЛитералы(в: код, ключиКаталога: ключи)
            }
            if n > 0 { посчитано[имя] = n }
        }

        for (файл, сколько) in посчитано.sorted(by: { $0.key < $1.key }) {
            let разрешено = долг[файл] ?? 0
            #expect(сколько <= разрешено, """
                \(файл): непереведённых строк \(сколько) при долге \(разрешено). \
                Либо переведи через String(localized:), либо, если это \
                внутреннее, добавь файл в исключения — с причиной, а не молча. \
                Правку числа в долге считать починкой нельзя.
                """)
        }

        // Долг, которого больше нет, надо убирать из списка: иначе он
        // разрешает вернуть то, что уже починено.
        let протухшие = долг.keys.filter { посчитано[$0] == nil }.sorted()
        #expect(протухшие.isEmpty,
                "в долге числятся файлы без непереведённых строк: \(протухшие). Убери их.")
    }

    /// Пометка «внутреннее» работает — и работает только с причиной.
    ///
    /// Ставится рядом с самим механизмом нарочно: сторож, у которого
    /// появился новый способ промолчать, обязан доказать, что молчит
    /// он там, где сказано, и нигде больше. Иначе это не исключение,
    /// а дыра с именем.
    @Test("Пометка «внутреннее» узнаётся, и без причины её нет")
    func пометкаРаботает() {
        #expect(Self.пометкаВнутреннего(
            #"    static let признак = "хранилище: iCloud"  // внутреннее: маркер для разбора крошек запуска"#
        ) != nil, "пометка не узнана на той самой строке, ради которой заведена")

        #expect(Self.пометкаВнутреннего(#"let x = "строка""#) == nil,
                "пометка найдена там, где её нет — сторож ослеп бы на обычной строке")

        // Пустая причина узнаётся как пометка — и ловится проверкой
        // длины в самом обходе, а не здесь: так красное называет файл
        // и строку, а не абстрактное «где-то».
        #expect(Self.пометкаВнутреннего("// внутреннее:")?.isEmpty == true,
                "пометка без причины должна узнаваться, чтобы на неё можно было покраснеть")
    }

    /// **Проверка самого разбора, а не его результата.**
    ///
    /// До 07.10.2026 разбор переключал «внутри литерала» на каждой
    /// кавычке и потому ломался на строке с интерполяцией, внутри
    /// которой есть ещё кавычки. Кириллица в ИМЕНИ функции читалась
    /// как непереведённая строка: `Fmt.кличка` дала два ложных
    /// срабатывания в `SnapshotText` на верном коде, и чинили это
    /// переименованием, а не сторожем.
    ///
    /// Поэтому здесь не «сколько долга в проекте», а «что именно
    /// разбор считает строкой». У нас записано: проверять надо
    /// и результат, и границу инструмента, и вторая проверка делается
    /// реже первой примерно никогда.
    ///
    /// Оба края обязательны. Без первого разбор мог бы перестать
    /// считать что-либо вовсе и был бы зелёным; без второго —
    /// считать всё и краснеть на верном коде.
    /// Причина у пометки «внутреннее» — или `nil`, если пометки нет.
    ///
    /// Форма: `// внутреннее: <почему эту строку не переводят>`.
    ///
    /// **Зачем отдельный механизм рядом с исключениями по файлу.**
    /// Исключение файлом — это слепота на весь файл, и она растёт
    /// молча: в день, когда в «исключённый» файл допишут строку
    /// для человека, сторож промолчит. У `StorageFailureAdvice.swift`
    /// одна внутренняя строка (`"хранилище: iCloud"` — маркер
    /// для разбора крошек запуска) и шесть живых переводимых рядом.
    ///
    /// > **Пометка строкой говорит про строку. Исключение файлом
    /// > говорит про всё, что в файле когда-либо появится.**
    static func пометкаВнутреннего(_ строка: String) -> String? {
        guard let i = строка.range(of: "// внутреннее:") else { return nil }
        return String(строка[i.upperBound...]).trimmingCharacters(in: .whitespaces)
    }

    @Test("Разбор отличает кириллицу в коде от кириллицы в строке")
    func разборРазличаетКодИСтроку() {
        let ключи: Set<String> = []

        // 1. Кириллица в ИМЕНИ внутри интерполяции — это код.
        //    Ровно та форма, на которой разбор врал.
        for код in [
            #"return "\(String(localized: "нет отметок")) · \(Fmt.кличка(снимок.dogName))""#,
            #"return "\(Fmt.duration(seconds)) · \(Fmt.кличкаИлиЗапасное(x))""#,
            #"let s = "\(кличка), \(Fmt.weight(вес)). ""#,
        ] {
            #expect(Self.русскиеЛитералы(в: код, ключиКаталога: ключи) == 0, """
                разбор счёл кириллическое ИМЯ внутри интерполяции
                непереведённой строкой: \(код)

                Сторож, который кричит там, где всё верно, читать
                перестают — это оплачено семьюдесятью девятью
                находками на Timer.
                """)
        }

        // 2. Настоящий непереведённый литерал — в том числе ВНУТРИ
        //    интерполяции, куда прежний разбор не заглядывал вовсе.
        #expect(Self.русскиеЛитералы(в: #"content.body = "Окно натощак закончилось.""#,
                                     ключиКаталога: ключи) == 1,
                "разбор перестал видеть обычный русский литерал")
        #expect(Self.русскиеЛитералы(в: #"let s = "\(String("не локализовано")) · \(x)""#,
                                     ключиКаталога: ключи) == 1, """
                разбор не видит литерал ВНУТРИ интерполяции. Прежний
                не видел его тоже, но по другой причине — он вместо
                этого видел имя функции. Новый обязан разбирать тело
                интерполяции как код: литерал в нём считается долгом,
                идентификатор — нет.
                """)
        #expect(Self.русскиеЛитералы(в: #"let s = "\(String(localized: "уже перевели")) · \(x)""#,
                                     ключиКаталога: ключи) == 0,
                "литерал в `String(localized:)` внутри интерполяции долгом не является")
    }

