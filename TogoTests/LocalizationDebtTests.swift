    /// Тип параметра, объявленный **в исходниках проекта**.
    ///
    /// > **Это ось, а не перечень известных мест.** Сторож не знает
    /// > про «тринадцать тостов»; он знает, что `showFailure` объявлен
    /// > принимать `String`. Четырнадцатый тост в файле, которого
    /// > сегодня нет, покраснеет сам.
    ///
    /// Чего опись НЕ знает — чужих объявлений: `Button`, `Text`,
    /// `.navigationTitle` живут в SwiftUI, и их типа в наших файлах
    /// не найти. Неизвестный сток считается **невиновным**: ложный
    /// красный здесь дороже пропуска, потому что он учит не верить
    /// красному. Цена границы названа: литерал в чужой строковый
    /// API (кроме `verbatim:`) сторож не увидит.
    struct ОписьСтоков: Sendable {
        /// «Тип.метка» или «функция.метка» → ВСЕ типы, под которыми
        /// это имя объявлено. Множество, а не одно значение: перегрузки
        /// и одноимённые поля разных типов — обычное дело.
        var поМетке: [String: Set<String>] = [:]
        /// «Тип» или «функция» → типы ПЕРВОГО безымянного параметра.
        var безымянный: [String: Set<String>] = [:]

        /// Имена, у которых перегрузка перекрывает строку ключом.
        /// Только здесь решения нет — и молчание дешевле ложного красного.
        var спорные: Set<String> {
            var итог: Set<String> = []
            for (ключ, типы) in поМетке where спорный(типы) { итог.insert(ключ) }
            for (ключ, типы) in безымянный where спорный(типы) { итог.insert(ключ) }
            return итог
        }

        private func спорный(_ типы: Set<String>) -> Bool {
            типы.contains("String") && !типы.isDisjoint(with: LocalizationDebtTests.локализующиеТипы)
        }
    }

    /// Типы, которые ПЕРЕВОДЯТ литерал сами: литерал становится ключом
    /// каталога, и долгом он не является.
    static let локализующиеТипы: Set<String> = [
        "LocalizedStringKey", "LocalizedStringResource", "Text", "AttributedString",
    ]

    /// Уедет ли РУССКИЙ ЛИТЕРАЛ в `String` при таком наборе объявлений.
    ///
    /// **Перегрузка перегрузке рознь, и это не придирка, а 18 строк
    /// долга.** Первая редакция молчала на всяком имени, объявленном
    /// дважды, — и онемела на `запись`, `record`, `save`, `show`.
    /// Но литерал по типу привязывается не ко всему подряд: `Date`
    /// или `Дневник` строкой быть не могут, и наличие такой перегрузки
    /// ничего не меняет. Выбор между `String` и `LocalizedStringKey`
    /// — единственный, которого отсюда не видно.
    static func строковыйСток(_ типы: Set<String>?) -> Bool {
        guard let типы, типы.contains("String") else { return false }
        return типы.isDisjoint(with: локализующиеТипы)
    }

    /// Чужие стоки, у которых тип известен и он строковый.
    ///
    /// `Text(verbatim:)` рисует строку дословно — это буквально
    /// «не переводить». Он здесь один нарочно: каждое имя в этом
    /// множестве — утверждение о ЧУЖОМ коде, и проверить его нечем,
    /// кроме документации Apple.
    static let чужиеСтроковыеСтоки: Set<String> = ["verbatim"]

    /// Опись стоков по объявлениям всех продуктовых корней.
    static func описьСтоков(корни: [String]) -> ОписьСтоков {
        var о = ОписьСтоков()
        func записать(_ ключ: String, _ тип: String, вМетки: Bool) {
            if вМетки { о.поМетке[ключ, default: []].insert(тип) }
            else { о.безымянный[ключ, default: []].insert(тип) }
        }
        for имяКорня in корни {
            let корень = репозиторий.appendingPathComponent(имяКорня)
            let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let исходник = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
                let строки = исходник.components(separatedBy: .newlines)
                    .map { $0.components(separatedBy: "//")[0].trimmingCharacters(in: .whitespaces) }
                var типСейчас: String?
                for (н, строка) in строки.enumerated() {
                    if let имя = имяОбъявленногоТипа(строка) { типСейчас = имя; continue }
                    if let (имя, тип) = свойствоСтроки(строка), let т = типСейчас {
                        записать("\(т).\(имя)", тип, вМетки: true)
                    }
                    guard let вид = объявлениеЗдесь(строка) else { continue }
                    // Список параметров переносят на следующие строки
                    // чаще, чем пишут в одну. Окно — восемь строк:
                    // подписи длиннее здесь нет, и это замер по дереву,
                    // а не оценка.
                    let окно = строки[н..<min(н + 8, строки.count)].joined(separator: " ")
                    if вид == "func",
                       let rf = окно.range(of: "func "),
                       let скобка = окно[rf.upperBound...].firstIndex(of: "("),
                       let тело = вСкобках(окно, от: скобка) {
                        let имя = окно[rf.upperBound..<скобка]
                            .prefix { $0.isLetter || $0.isNumber || $0 == "_" }
                        if !имя.isEmpty {
                            let разбор = параметрыОбъявления(тело)
                            for (метка, тип) in разбор.метки {
                                записать("\(имя).\(метка)", тип, вМетки: true)
                            }
                            if let б = разбор.безымянный { записать(String(имя), б, вМетки: false) }
                        }
                    }
                    if вид == "init", let т = типСейчас,
                       let ri = окно.range(of: "init"),
                       let скобка = окно[ri.upperBound...].firstIndex(of: "("),
                       let тело = вСкобках(окно, от: скобка) {
                        let разбор = параметрыОбъявления(тело)
                        for (метка, тип) in разбор.метки {
                            записать("\(т).\(метка)", тип, вМетки: true)
                        }
                        if let б = разбор.безымянный { записать(т, б, вМетки: false) }
                    }
                }
            }
        }
        return о
    }

    /// Начинает ли строка ОБЪЯВЛЕНИЕ — `"func"`, `"init"` или `nil`.
    ///
    /// **Различитель оплачен замером 03.11.2026, и он про тишину,
    /// а не про шум.** Без него строка `self.init(title: title,` —
    /// ВЫЗОВ — читалась как объявление, тип параметра выводился
    /// из имени аргумента (`title` → тип «title»), и `TGSheet.title`
    /// становился «спорным», то есть немым. Так молча онемели
    /// восемнадцать стоков дизайн-системы: `TGSheet.title`,
    /// `TGScreen.title`, `TGCheckRow.subtitle` и соседи.
    ///
    /// > Ошибка разбора объявлений даёт не красное, а ЗЕЛЁНОЕ: сторож
    /// > не краснеет на том, чего перестал понимать. Поэтому у разбора
    /// > свой тест на синтетике.
    static func объявлениеЗдесь(_ строка: String) -> String? {
        var слова = строка.split(separator: " ").map(String.init)
        let модификаторы: Set<String> = ["public", "private", "fileprivate", "internal",
                                         "static", "final", "open", "override", "required",
                                         "convenience", "nonisolated", "mutating", "class"]
        while let первое = слова.first, модификаторы.contains(первое) || первое.hasPrefix("@") {
            слова.removeFirst()
        }
        guard let первое = слова.first else { return nil }
        if первое == "func" { return "func" }
        if первое == "init" || первое.hasPrefix("init(") || первое.hasPrefix("init?(")
            || первое.hasPrefix("init!(") { return "init" }
        return nil
    }

    /// Имя типа, если строка его объявляет. Иначе `nil`.
    static func имяОбъявленногоТипа(_ строка: String) -> String? {
        var слова = строка.split(separator: " ").map(String.init)
        let модификаторы: Set<String> = ["public", "private", "fileprivate",
                                         "internal", "final", "open"]
        while let первое = слова.first, модификаторы.contains(первое) || первое.hasPrefix("@") {
            слова.removeFirst()
        }
        guard let вид = слова.first,
              ["struct", "class", "enum", "extension", "actor"].contains(вид),
              слова.count > 1 else { return nil }
        let имя = слова[1].prefix { $0.isLetter || $0.isNumber || $0 == "_" }
        return имя.isEmpty ? nil : String(имя)
    }

    /// «let имя: Тип» — объявление хранимого свойства с НАЗВАННЫМ типом.
    /// Выведенный тип (`let x = "…"`) пропускается: его здесь не узнать.
    static func свойствоСтроки(_ строка: String) -> (имя: String, тип: String)? {
        var слова = строка.split(separator: " ").map(String.init)
        let модификаторы: Set<String> = ["public", "private", "fileprivate", "internal",
                                         "static", "final", "lazy", "weak", "unowned", "open"]
        while let первое = слова.first, модификаторы.contains(первое) || первое.hasPrefix("@") {
            слова.removeFirst()
        }
        guard let ключевое = слова.first, ключевое == "let" || ключевое == "var",
              слова.count >= 3 else { return nil }
        let поле = слова[1]
        guard поле.hasSuffix(":") else { return nil }
        let имя = String(поле.dropLast())
        guard !имя.isEmpty,
              let тип = имяТипаПараметра(слова[2...].joined(separator: " ")[...]) else { return nil }
        return (имя, тип)
    }

    /// Разбор списка параметров объявления: «внешняя метка → тип».
    static func параметрыОбъявления(_ текст: Substring)
        -> (метки: [String: String], безымянный: String?) {
        var метки: [String: String] = [:]
        var безымянный: String?
        var куски: [String] = []
        var текущий = ""
        var глубина = 0
        for c in текст {
            if c == "(" || c == "[" || c == "{" { глубина += 1 }
            if c == ")" || c == "]" || c == "}" { глубина -= 1 }
            if c == "," && глубина == 0 { куски.append(текущий); текущий = "" } else { текущий.append(c) }
        }
        куски.append(текущий)
        for (номер, кусок) in куски.enumerated() {
            guard let д = двоеточиеВерхнегоУровня(кусок) else { continue }
            let слева = кусок[кусок.startIndex..<д].split(separator: " ")
            guard let внешняя = слева.first,
                  let тип = имяТипаПараметра(кусок[кусок.index(after: д)...]) else { continue }
            if внешняя == "_" {
                if номер == 0 { безымянный = тип }
            } else {
                метки[String(внешняя)] = тип
            }
        }
        return (метки, безымянный)
    }

    /// Первое двоеточие вне скобок: `[String: Int]` своим не считается.
    static func двоеточиеВерхнегоУровня(_ текст: String) -> String.Index? {
        var глубина = 0
        var i = текст.startIndex
        while i < текст.endIndex {
            let c = текст[i]
            if c == "(" || c == "[" || c == "{" { глубина += 1 }
            if c == ")" || c == "]" || c == "}" { глубина -= 1 }
            if c == ":" && глубина == 0 { return i }
            i = текст.index(after: i)
        }
        return nil
    }

    /// Имя типа из хвоста объявления: `@escaping some Foo?` → `Foo`.
    static func имяТипаПараметра(_ хвост: Substring) -> String? {
        var слова = хвост.split(separator: " ").map(String.init)
        let служебные: Set<String> = ["inout", "some", "any", "borrowing", "consuming"]
        while let первое = слова.first, служебные.contains(первое) || первое.hasPrefix("@") {
            слова.removeFirst()
        }
        guard let первое = слова.first else { return nil }
        let имя = первое.prefix { $0.isLetter || $0.isNumber || $0 == "_" }
        return имя.isEmpty ? nil : String(имя)
    }

    /// Текст внутри круглых скобок, открывающихся на позиции `от`.
    static func вСкобках(_ текст: String, от: String.Index) -> Substring? {
        guard от < текст.endIndex, текст[от] == "(" else { return nil }
        var глубина = 0
        var i = от
        while i < текст.endIndex {
            if текст[i] == "(" { глубина += 1 }
            if текст[i] == ")" {
                глубина -= 1
                if глубина == 0 { return текст[текст.index(after: от)..<i] }
            }
            i = текст.index(after: i)
        }
        return nil
    }

    // MARK: - Разрешение вызова на месте литерала

    /// Кто зовёт и под какой меткой — по тексту СЛЕВА от литерала.
    ///
    /// `TGStat(value: "…")` → (`TGStat`, `value`);
    /// `appState.showFailure("…")` → (`showFailure`, `nil`);
    /// `count > 1 ? "а" : "б"` внутри `showUndo(…)` → (`showUndo`, `nil`),
    /// потому что перед «б» стоит двоеточие ТЕРНАРНОГО оператора,
    /// а не метки: слева от него кавычка, а не имя.
    ///
    /// Граница названа: разбор идёт справа налево и про кавычки
    /// не знает. Строка со скобкой внутри литерала может увести счёт —
    /// исход тогда «вызов неизвестен», то есть невиновен.
    static func вызовИМетка(_ контекст: String) -> (вызов: String?, метка: String?) {
        var s = Substring(контекст)
        func обрезать() { while let п = s.last, п == " " || п == "\t" { s = s.dropLast() } }
        обрезать()
        var метка: String?
        if s.last == ":" {
            let без = s.dropLast()
            let слово = Self.хвостИмени(без)
            if !слово.isEmpty {
                метка = String(слово)
                s = без.dropLast(слово.count)
                обрезать()
            }
        }
        var глубина = 0
        var i = s.endIndex
        while i > s.startIndex {
            i = s.index(before: i)
            let c = s[i]
            if c == ")" || c == "]" || c == "}" { глубина += 1; continue }
            if c == "(" || c == "[" || c == "{" {
                if глубина > 0 { глубина -= 1; continue }
                guard c == "(" else { return (nil, метка) }
                let слово = Self.хвостИмени(s[s.startIndex..<i])
                return (слово.isEmpty ? nil : String(слово), метка)
            }
        }
        return (nil, метка)
    }

    /// Идентификатор, которым КОНЧАЕТСЯ текст. В стандартной библиотеке
    /// есть `prefix(while:)` и нет `suffix(while:)` — отсюда свой.
    static func хвостИмени(_ s: Substring) -> Substring {
        var i = s.endIndex
        while i > s.startIndex {
            let j = s.index(before: i)
            guard s[j].isLetter || s[j].isNumber || s[j] == "_" else { break }
            i = j
        }
        return s[i...]
    }

    /// Уезжает ли литерал в `String` — вердикт оси слоя экранов.
    static func уезжаетВString(перед: String, опись: ОписьСтоков) -> Bool {
        // `String(localized:)` — уже перевод, какой бы сток ни был дальше.
        if перед.hasSuffix("localized:") { return false }
        // Склейка строк: `kind.title + " · отменено"`. `Text` так
        // не склеивают — там `Text(…) + Text(…)`, и литерал тогда
        // стоит в `Text(`, а не у плюса.
        if перед.hasSuffix("+") { return true }
        let (вызов, метка) = вызовИМетка(перед)
        if let м = метка, чужиеСтроковыеСтоки.contains(м) { return true }
        guard let в = вызов else { return false }
        let ключ = метка.map { "\(в).\($0)" } ?? в
        let типы = метка == nil ? опись.безымянный[в] : опись.поМетке[ключ]
        return строковыйСток(типы)
    }

    // MARK: - Обход

    /// Что принёс обход одного набора корней.
    struct Счёт {
        var поФайлам: [String: Int] = [:]
        var файловПрочитано = 0
        var отладочных = 0
        var пометкиБезПричины: [String] = []
        /// Файлы, чей путь не удалось привести к ключу храповика.
        /// Пустым он должен быть всегда: ключ, сложенный неверно,
        /// краснеет **на здоровом файле** и называет имя, которого
        /// в долге нет никогда.
        var путьНеСложился: [String] = []
    }

    /// Путь файла относительно корня репозитория — ключ храповика.
    ///
    /// **`replacingOccurrences` здесь недостаточно, и это замер
    /// 03.11.2026, а не предосторожность.** В `git worktree` под `/tmp`
    /// обход отдаёт `/private/tmp/…`, а `#filePath` — `/tmp/…`:
    /// на macOS `/tmp` это символическая ссылка. Замена подстроки
    /// нашла хвост, и ключом вышло `/privateTogo/App/RootView.swift` —
    /// имя, которого в долге нет ни у кого, то есть **весь слой
    /// экранов покраснел на здоровом коде**.
    ///
    /// > Поймано worktree-прогоном, и ровно за этим свод велит мерить
    /// > в worktree: в рабочем дереве путь начинается с `/Users`,
    /// > и дефект не воспроизводится никогда.
    static func относительныйПуть(_ файл: URL, от корень: URL) -> String? {
        let к = корень.resolvingSymlinksInPath().path
        let ф = файл.resolvingSymlinksInPath().path
        guard ф.hasPrefix(к + "/") else { return nil }
        return String(ф.dropFirst(к.count + 1))
    }

    /// Файл целиком под `#if DEBUG` в Release-сборку не попадает —
    /// значит ни одной его строки человек не увидит.
    ///
    /// **Это правило, а не перечень.** Галерея компонентов, заведённая
    /// завтра, освободится сама, а продуктовый файл не освободится
    /// никогда — освобождение держится на том, чего в сборке нет,
    /// а не на имени файла.
    static func целикомОтладочный(_ текст: String) -> Bool {
        let содержательные = текст.components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty && !$0.hasPrefix("//") }
        return содержательные.first == "#if DEBUG" && содержательные.last == "#endif"
    }

    /// Сколько строк окна кода отдаётся разбору слева от литерала.
    ///
    /// Нужно потому, что вызов и его аргумент живут на разных строках
    /// чаще, чем на одной: `TGSheet(\n title: "…")`. Без окна разбор
    /// увидел бы метку без вызова и промолчал.
    static let окноКонтекста = 8

    static func посчитать(корни: [String], правило: Правило,
                          исключения: [String: String]) -> Счёт {
        var счёт = Счёт()
        for имяКорня in корни {
            let корень = репозиторий.appendingPathComponent(имяКорня)
            let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
                счёт.файловПрочитано += 1
                guard let путь = относительныйПуть(элемент, от: репозиторий) else {
                    счёт.путьНеСложился.append(элемент.path)
                    continue
                }
                guard исключения[путь] == nil else { continue }
                if целикомОтладочный(текст) { счёт.отладочных += 1; continue }

                var n = 0
                var окно: [String] = []
                for строка in текст.components(separatedBy: .newlines) {
                    // **Пометка СТРОКОЙ, а не файлом.** Исключение файлом
                    // ослепляет сторож на весь файл: в
                    // `StorageFailureAdvice.swift` одна внутренняя строка
                    // и ШЕСТЬ живых переводимых рядом — спрятав файл,
                    // мы спрятали бы и их.
                    //
                    // Замечание togo-02 от 07.10, оплаченное на сторо́же
                    // подстановок клички: «файловое исключение спрятало бы
                    // и настоящий показ, который в тех же файлах есть».
                    //
                    // Проверяется до вырезания прозы нарочно: пометка
                    // и есть проза, и после вырезания её не останется.
                    if let причина = пометкаВнутреннего(строка) {
                        if причина.count < 10 {
                            счёт.пометкиБезПричины.append("""
                                пометка «внутреннее» без причины в \(путь): \
                                «\(строка.trimmingCharacters(in: .whitespaces))». \
                                Исключение без причины через месяц неотличимо \
                                от дыры — у нас это записано ценой целого дня.
                                """)
                        }
                        continue
                    }
                    let код = строка.components(separatedBy: "//")[0]
                    // Строка в журнал разработчика — не подпись. Её читает тот,
                    // кто чинит, а не хозяин собаки; переводить её значит
                    // превращать диагностику в текст для человека.
                    // Тот же признак, что и у Tools/extract_texts.py.
                    // `StartupLog.note` здесь по той же причине, что и
                    // `log.*`: это крошки запуска. Их забирают с телефона
                    // скриптом, когда приложение не поднялось, и читает их
                    // тот, кто ищет причину. Файлы `StartupLog.swift`
                    // и `DogOrigin.swift` исключены целиком именно за это —
                    // а вызов из соседнего файла считался долгом, хотя
                    // строка та же и читатель тот же.
                    if код.contains("log.error(") || код.contains("log.notice(")
                        || код.contains("log.debug(") || код.contains("log.info(")
                        || код.contains("log.warning(")
                        || код.contains("StartupLog.note(") {
                        окно.append(код)
                        if окно.count > окноКонтекста { окно.removeFirst() }
                        continue
                    }
                    n += русскиеЛитералы(в: код,
                                         приставка: окно.joined(separator: " ") + " ",
                                         правило: правило)
                    окно.append(код)
                    if окно.count > окноКонтекста { окно.removeFirst() }
                }
                if n > 0 { счёт.поФайлам[путь] = n }
            }
        }
        return счёт
    }

    /// Русские литералы в строке кода, кроме уже обёрнутых в перевод.
    ///
    /// **Переведённым считается не только `String(localized:)`.**
    /// Замер 05.10.2026: сторож покраснел на `TodayWidgetView.swift`
    /// из-за строки `не кормить до %@`, переведённой на все четыре
    /// языка. `Text("литерал")` локализуется SwiftUI сам — литерал
    /// становится ключом, — а сторож искал только `localized:`
    /// и этого не видел.
    ///
    /// Правило писалось, когда в общем слое не было ни одной вью;
    /// `TodayWidgetView` — первая. **Сторож был прав по тексту
    /// и неправ по миру**, и это худший вид красного: он требует
    /// «починить» то, что цело, и учит не верить красному.
    ///
    /// Поэтому литерал без интерполяции, который **есть ключом
    /// в каталоге**, долгом не считается: раз он там есть, перевод
    /// у него проверяет сторож полноты, а не этот.
    ///
    /// Граница названа вслух: литерал **с** интерполяцией так проверить
    /// нельзя — ключ выводится из типа подставляемого (`%lld` у целого,
    /// `%@` у строки), а тип знает компилятор, не регулярка. Ровно эта
    /// граница породила 74 пары ключей-двойников. Такие литералы
    /// считаются долгом, как раньше.
    /// Удобный вход для проверок самого разбора: ось общего слоя,
    /// пустая приставка. Боевой обход зовёт полную форму.
    static func русскиеЛитералы(в код: String, ключиКаталога ключи: Set<String>) -> Int {
        русскиеЛитералы(в: код, приставка: "",
                        правило: Правило(ось: .общийСлой, ключи: ключи, опись: ОписьСтоков()))
    }

    /// - Parameter приставка: код СЛЕВА от строки — окно предыдущих
    ///   строк и, в рекурсии, начало текущей. Нужна затем, что вызов
    ///   и его аргумент стоят на разных строках чаще, чем на одной.
    static func русскиеЛитералы(в код: String, приставка: String,
                                правило: Правило) -> Int {
        let ключи = правило.ключи
        var счёт = 0
        var внутри = false
        var литерал = ""
        var предыдущий: Character = " "
        var началоЛитерала = код.startIndex
        var i = код.startIndex
        while i < код.endIndex {
            let c = код[i]
            if внутри, c == "\\",
               код.index(after: i) < код.endIndex,
               код[код.index(after: i)] == "(" {
                // **Интерполяция — это КОД, а не проза, и до 07.10.2026
                // разбор этого не знал.**
                //
                // Он переключал «внутри литерала» на каждой кавычке,
                // поэтому у строки с вложенной кавычкой —
                // `"\(String(localized: "нет отметок")) · \(x)"` —
                // куском «литерала» становилось `)) · \(x)`. Кириллица
                // в ИМЕНИ функции внутри интерполяции читалась как
                // непереведённая строка: `Fmt.кличка` дала два ложных
                // срабатывания в `SnapshotText` на верном коде, и чинить
                // это пришлось переименованием, а не сторожем.
                //
                // Сторож, который кричит там, где всё верно, читать
                // перестают — у нас это оплачено семьюдесятью девятью
                // находками на Timer. Поэтому тело интерполяции
                // разбирается РЕКУРСИВНО, как код: литерал внутри неё
                // проверяется теми же правилами, а идентификатор
                // литералом не считается.
                литерал.append("\\(")
                let тело = телоИнтерполяции(в: код, от: код.index(after: i))
                // Приставка тела — всё, что слева от него: окно плюс
                // начало строки. Иначе вложенный литерал потерял бы
                // свой вызов и всегда считался невиновным.
                счёт += русскиеЛитералы(в: String(код[тело.диапазон]),
                                        приставка: приставка + String(код[код.startIndex..<тело.диапазон.lowerBound]),
                                        правило: правило)
                i = тело.продолжать
                предыдущий = ")"
                continue
            }
            if внутри {
                if c == "\"" && предыдущий != "\\" {
                    внутри = false
                    if литерал.contains(where: { $0.isCyrillic }) {
                        let перед = (приставка + String(код[код.startIndex..<началоЛитерала]))
                            .trimmingCharacters(in: .whitespaces)
                        // `Text("…")` — ключ каталога: SwiftUI
                        // локализует литерал сам.
                        //
                        // **Три условия, и каждое обязательно.** Первая
                        // редакция этой проверки требовала только
                        // «литерал есть ключом в каталоге» — и сторож
                        // немедленно объявил семь файлов чистыми.
                        // Он был бы неправ, и неправ в самую дорогую
                        // сторону: `Tools/extract_texts.py` кладёт
                        // в каталог ВСЯКИЙ русский литерал из исходника,
                        // поэтому «есть ключом» не значит ничего о том,
                        // доезжает ли строка до экрана. Весь этот день
                        // ушёл на обратные примеры: 321 строка `d701bd7`,
                        // восемь строк `BackupScreen`, три текста
                        // магазина 30.09 — у всех ключ был, перевод был,
                        // на экране стоял русский.
                        //
                        // > **Ключ в каталоге — не признак перевода
                        // > на экране.** Признак — то, КУДА литерал
                        // > передан: `Text` локализует, `String`
                        // > рисует дословно.
                        //
                        // Поэтому: литерал стоит прямо в `Text(`,
                        // в нём нет интерполяции (выведенный ключ
                        // по тексту не восстановить — тип подставляемого
                        // знает компилятор, и ровно эта граница породила
                        // 74 пары ключей-двойников), и такой ключ
                        // в каталоге есть.
                        //
                        // **Проверено тремя подделками 05.10.2026**
                        // (`Tools/check_guard.py`, отдельное дерево),
                        // потому что в живом коде эта ветка не
                        // исполняется ни разу — зелёная она была
                        // от того, что её не звали:
                        //
                        //     Text("Не кормить до приёма")
                        //         → зелёно, и это верно: ключ есть
                        //     Text(verbatim: "Не кормить до приёма")
                        //         → красно: `verbatim` рисует дословно
                        //     Text("Не кормить до приёма ещё немного")
                        //         → красно: такого ключа в каталоге нет
                        //
                        // Первая — не «сторож не поймал»: подделка была
                        // законным кодом, и зелёное на ней и есть
                        // ответ. Инструмент подделок этого различить
                        // не умеет и честно требует решения от человека.
                        // Вторая и третья показывают, что ни одно
                        // из трёх условий не мёртвое.
                        let вText = перед.hasSuffix("Text(")
                        let ключОткрыт = вText
                            && !литерал.contains("\\(")
                            && ключи.contains(литерал)
                        switch правило.ось {
                        case .общийСлой:
                            if !перед.hasSuffix("localized:") && !ключОткрыт { счёт += 1 }
                        case .слойЭкранов:
                            // `Text(verbatim:)` ловится описью стоков,
                            // а `Text("ключ")` остаётся невиновным
                            // по той же причине, что и в общем слое.
                            if !ключОткрыт,
                               Self.уезжаетВString(перед: перед, опись: правило.опись) {
                                счёт += 1
                            }
                        }
                    }
                    литерал = ""
                } else {
                    литерал.append(c)
                }
            } else if c == "\"" {
                внутри = true
                началоЛитерала = i
            }
            предыдущий = c
            i = код.index(after: i)
        }
        return счёт
    }

    /// Тело интерполяции и место, с которого продолжать разбор строки.
    ///
    /// Скобки считаются с учётом вложенных строковых литералов: внутри
    /// `\(f(")"))` закрывающая скобка в кавычках скобкой не является.
    private static func телоИнтерполяции(
        в код: String, от открывающая: String.Index
    ) -> (диапазон: Range<String.Index>, продолжать: String.Index) {
        var глубина = 0
        var вСтроке = false
        var предыдущий: Character = " "
        var j = открывающая
        while j < код.endIndex {
            let c = код[j]
            if вСтроке {
                if c == "\"" && предыдущий != "\\" { вСтроке = false }
            } else if c == "\"" {
                вСтроке = true
            } else if c == "(" {
                глубина += 1
            } else if c == ")" {
                глубина -= 1
                if глубина == 0 {
                    return (код.index(after: открывающая)..<j, код.index(after: j))
                }
            }
            предыдущий = c
            j = код.index(after: j)
        }
        // Незакрытая интерполяция — строка оборвана переносом. Остаток
        // отдаём телом: пропустить его молча значило бы ослепнуть
        // ровно там, где разбор уже не понимает, что читает.
        return (код.index(after: открывающая)..<код.endIndex, код.endIndex)
    }
}

private extension Character {
    var isCyrillic: Bool {
        guard let скаляр = unicodeScalars.first else { return false }
        return (0x0410...0x044F).contains(Int(скаляр.value)) || скаляр.value == 0x0401 || скаляр.value == 0x0451
    }

