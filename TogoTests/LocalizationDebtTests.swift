        #expect(счёт.файловПрочитано > 80, """
            в TogoShared прочитано \(счёт.файловПрочитано) файлов — \
            обход не состоялся, и ноль долга сказал бы про обход, а не про долг.
            """)
        for жалоба in счёт.пометкиБезПричины { Issue.record("\(жалоба)") }
        #expect(счёт.путьНеСложился.isEmpty, """
            путь не привёлся к ключу храповика: \(счёт.путьНеСложился.prefix(3)). \
            Такой ключ краснеет на здоровом файле и называет имя, \
            которого в долге нет никогда.
            """)
        сверить(счёт.поФайлам, с: долг, чем: "String(localized:)")
    }

