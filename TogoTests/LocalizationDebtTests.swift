import Testing
import Foundation

/// Русская строка в общем слое — либо подпись, которую забыли перевести,
/// либо внутреннее, которое переводить нельзя. Граница между ними до
/// 23.09 держалась на памяти, а по ту сторону 443 литерала.
///
/// Сторож её закрепляет: у каждого исключения написана причина, а всё
/// остальное — долг, который не должен расти. Долг снимается переводом
/// через `String(localized:)`, а не правкой числа.
///
/// Чего сторож НЕ умеет: отличить подпись от внутренней строки внутри
/// одного файла. Поэтому исключения — по файлам, и список короткий
/// намеренно: длинный список исключений — это сторож, который не может
/// покраснеть.
@Suite("Долг локализации")
struct LocalizationDebtTests {

    /// Файлы, где русский текст — не подпись и переводу не подлежит.
    /// У каждого причина, и она важнее самого списка.
    private let исключения: [String: String] = [
        // Ключевые слова разбора дозаписи: человек пишет «был понос»,
        // парсер ищет «понос». Перевод сломает разбор для пишущих
        // по-русски. Украинцу нужен свой словарь, а не перевод этого.
        "RecallParser.swift": "слова разбора, а не подписи",
        // Тот же случай: словарь разбора по языкам. Слова здесь ищутся
        // в напечатанной фразе, а не показываются человеку.
        "RecallDictionary.swift": "слова разбора, а не подписи",
        // Журнал действий и отчёт по нему читает разработчик, не хозяин.
        // Диагностика, ставшая текстом для человека, — это дефект.
        "UsageLog.swift": "внутренний журнал",
        "UsageReport.swift": "внутренний журнал",
        // Крошки запуска: их забирают с телефона скриптом, когда
        // приложение не поднялось.
        "Persistence.swift": "крошки запуска",
        "StartupLog.swift": "крошки запуска",
        // Откуда взялась собака — тоже крошки: пишутся в тот же файл
        // и читаются тем, кто ищет причину дубликата, а не хозяином.
        "DogOrigin.swift": "крошки запуска",
    ]

    /// Сколько непереведённых строк осталось в каждом файле.
    /// Замер 23.09.2026. Число может только уменьшаться.
    private let долг: [String: Int] = [
        "AlarmThreshold.swift": 5, "CareMigration.swift": 14, "DayOutPlan.swift": 5,
        "DogDocument.swift": 22, "FamilyShare.swift": 4, "FamilySync.swift": 3,
        "Feeding.swift": 5, "ScheduleChange.swift": 9,
        "TimelineBuilder.swift": 9, "TreatmentCourse.swift": 10, "VetSummary.swift": 10, "WalkMarkIntent.swift": 8,
        // `WidgetSnapshot.swift` стоял здесь с долгом 3 и ушёл 07.10.2026:
        // три слова заглушки виджета («Собака», «Просится», «нет данных»)
        // рисовались по-русски на любом языке. Человек видит их в галерее
        // при добавлении виджета — `TodayWidget.swift:25` отдаёт `.empty`
        // из `placeholder(in:)`. Новых ключей правка не завела: все три
        // лежали в каталоге на четырёх языках, менялась только дорога.
        //
        // Строку убрал не из аккуратности: сторож потребовал сам —
        // «долг, которого больше нет, разрешает вернуть то, что уже
        // починено».
        "WalkRecorder.swift": 1,
    ]

    @Test("Непереведённых строк в общем слое не становится больше")
    func долгНеРастёт() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("TogoShared")

        let ключи = try ключиКаталога()
        #expect(ключи.count > 500,
                "каталог прочитан не весь (\(ключи.count) ключей) — разбор не состоялся")

        var посчитано: [String: Int] = [:]
        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
            let имя = элемент.lastPathComponent
            guard исключения[имя] == nil else { continue }
            var n = 0
            for строка in текст.components(separatedBy: .newlines) {
                let код = строка.components(separatedBy: "//")[0]
                // Строка в журнал разработчика — не подпись. Её читает тот,
                // кто чинит, а не хозяин собаки; переводить её значит
                // превращать диагностику в текст для человека.
                // Тот же признак, что и у Tools/extract_texts.py.
                // `StartupLog.note` здесь по той же причине, что и
                // `log.*`: это крошки запуска. Их забирают с телефона
                // скриптом, когда приложение не поднялось, и читает их
                // тот, кто ищет причину. Файлы `StartupLog.swift`
                // и `DogOrigin.swift` исключены целиком именно за это —
                // а вызов из соседнего файла считался долгом, хотя
                // строка та же и читатель тот же.
                if код.contains("log.error(") || код.contains("log.notice(")
                    || код.contains("log.debug(") || код.contains("log.info(")
                    || код.contains("log.warning(")
                    || код.contains("StartupLog.note(") { continue }
                n += Self.русскиеЛитералы(в: код, ключиКаталога: ключи)
            }
            if n > 0 { посчитано[имя] = n }
        }

        for (файл, сколько) in посчитано.sorted(by: { $0.key < $1.key }) {
            let разрешено = долг[файл] ?? 0
            #expect(сколько <= разрешено, """
                \(файл): непереведённых строк \(сколько) при долге \(разрешено). \
                Либо переведи через String(localized:), либо, если это \
                внутреннее, добавь файл в исключения — с причиной, а не молча. \
                Правку числа в долге считать починкой нельзя.
                """)
        }

        // Долг, которого больше нет, надо убирать из списка: иначе он
        // разрешает вернуть то, что уже починено.
        let протухшие = долг.keys.filter { посчитано[$0] == nil }.sorted()
        #expect(протухшие.isEmpty,
                "в долге числятся файлы без непереведённых строк: \(протухшие). Убери их.")
    }

    @Test("У каждого исключения есть причина и оно существует")
    func исключенияЧестные() {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared")
        for (файл, причина) in исключения {
            #expect(!причина.isEmpty, "\(файл): исключение без причины")
            let есть = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)?
                .compactMap { $0 as? URL }
                .contains { $0.lastPathComponent == файл } ?? false
            #expect(есть, "\(файл) в исключениях, а файла нет — список протух")
        }
        #expect(исключения.count <= 8,
                "исключений \(исключения.count): длинный список — это сторож, который не может покраснеть")
    }

    /// Ключи обоих каталогов проекта.
    ///
    /// Нужны, чтобы отличить `Text("не кормить до")` — литерал, который
    /// SwiftUI локализует сам, — от настоящего долга. Берутся из файла,
    /// а не списком: копия списка в тесте однажды отстанет.
    private func ключиКаталога() throws -> Set<String> {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var ключи: Set<String> = []
        for путь in ["TogoShared/Resources/Localizable.xcstrings",
                     "Togo/Resources/AppShortcuts.xcstrings"] {
            let данные = try Data(contentsOf: корень.appendingPathComponent(путь))
            let разбор = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
            ключи.formUnion((разбор?["strings"] as? [String: Any] ?? [:]).keys)
        }
        return ключи
    }

    /// Русские литералы в строке кода, кроме уже обёрнутых в перевод.
    ///
    /// **Переведённым считается не только `String(localized:)`.**
    /// Замер 05.10.2026: сторож покраснел на `TodayWidgetView.swift`
    /// из-за строки `не кормить до %@`, переведённой на все четыре
    /// языка. `Text("литерал")` локализуется SwiftUI сам — литерал
    /// становится ключом, — а сторож искал только `localized:`
    /// и этого не видел.
    ///
    /// Правило писалось, когда в общем слое не было ни одной вью;
    /// `TodayWidgetView` — первая. **Сторож был прав по тексту
    /// и неправ по миру**, и это худший вид красного: он требует
    /// «починить» то, что цело, и учит не верить красному.
    ///
    /// Поэтому литерал без интерполяции, который **есть ключом
    /// в каталоге**, долгом не считается: раз он там есть, перевод
    /// у него проверяет сторож полноты, а не этот.
    ///
    /// Граница названа вслух: литерал **с** интерполяцией так проверить
    /// нельзя — ключ выводится из типа подставляемого (`%lld` у целого,
    /// `%@` у строки), а тип знает компилятор, не регулярка. Ровно эта
    /// граница породила 74 пары ключей-двойников. Такие литералы
    /// считаются долгом, как раньше.
    private static func русскиеЛитералы(в код: String,
                                        ключиКаталога ключи: Set<String>) -> Int {
        var счёт = 0
        var внутри = false
        var литерал = ""
        var предыдущий: Character = " "
        var началоЛитерала = код.startIndex
        var i = код.startIndex
        while i < код.endIndex {
            let c = код[i]
            if внутри {
                if c == "\"" && предыдущий != "\\" {
                    внутри = false
                    if литерал.contains(where: { $0.isCyrillic }) {
                        let перед = код[код.startIndex..<началоЛитерала]
                            .trimmingCharacters(in: .whitespaces)
                        // `Text("…")` — ключ каталога: SwiftUI
                        // локализует литерал сам.
                        //
                        // **Три условия, и каждое обязательно.** Первая
                        // редакция этой проверки требовала только
                        // «литерал есть ключом в каталоге» — и сторож
                        // немедленно объявил семь файлов чистыми.
                        // Он был бы неправ, и неправ в самую дорогую
                        // сторону: `Tools/extract_texts.py` кладёт
                        // в каталог ВСЯКИЙ русский литерал из исходника,
                        // поэтому «есть ключом» не значит ничего о том,
                        // доезжает ли строка до экрана. Весь этот день
                        // ушёл на обратные примеры: 321 строка `d701bd7`,
                        // восемь строк `BackupScreen`, три текста
                        // магазина 30.09 — у всех ключ был, перевод был,
                        // на экране стоял русский.
                        //
                        // > **Ключ в каталоге — не признак перевода
                        // > на экране.** Признак — то, КУДА литерал
                        // > передан: `Text` локализует, `String`
                        // > рисует дословно.
                        //
                        // Поэтому: литерал стоит прямо в `Text(`,
                        // в нём нет интерполяции (выведенный ключ
                        // по тексту не восстановить — тип подставляемого
                        // знает компилятор, и ровно эта граница породила
                        // 74 пары ключей-двойников), и такой ключ
                        // в каталоге есть.
                        //
                        // **Проверено тремя подделками 05.10.2026**
                        // (`Tools/check_guard.py`, отдельное дерево),
                        // потому что в живом коде эта ветка не
                        // исполняется ни разу — зелёная она была
                        // от того, что её не звали:
                        //
                        //     Text("Не кормить до приёма")
                        //         → зелёно, и это верно: ключ есть
                        //     Text(verbatim: "Не кормить до приёма")
                        //         → красно: `verbatim` рисует дословно
                        //     Text("Не кормить до приёма ещё немного")
                        //         → красно: такого ключа в каталоге нет
                        //
                        // Первая — не «сторож не поймал»: подделка была
                        // законным кодом, и зелёное на ней и есть
                        // ответ. Инструмент подделок этого различить
                        // не умеет и честно требует решения от человека.
                        // Вторая и третья показывают, что ни одно
                        // из трёх условий не мёртвое.
                        let вText = перед.hasSuffix("Text(")
                        let ключОткрыт = вText
                            && !литерал.contains("\\(")
                            && ключи.contains(литерал)
                        if !перед.hasSuffix("localized:") && !ключОткрыт { счёт += 1 }
                    }
                    литерал = ""
                } else {
                    литерал.append(c)
                }
            } else if c == "\"" {
                внутри = true
                началоЛитерала = i
            }
            предыдущий = c
            i = код.index(after: i)
        }
        return счёт
    }
}

private extension Character {
    var isCyrillic: Bool {
        guard let скаляр = unicodeScalars.first else { return false }
        return (0x0410...0x044F).contains(Int(скаляр.value)) || скаляр.value == 0x0401 || скаляр.value == 0x0451
    }
}
