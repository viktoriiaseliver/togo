import Foundation
import Testing

/// Текст, уходящий в уведомление, обязан идти через каталог.
///
/// **Класс тот же, что у `СвойствоМимоКаталогаTests`, а форма другая —
/// и поэтому тот сторож его не видит.** Он сам это и называет у себя
/// в конце: «Он НЕ видит … аргумент вызова». Вот этот аргумент:
///
/// ```swift
/// NotificationCenterService.scheduleDose(
///     id: …, at: …,
///     title: "Через 10 минут доза",     // ← String, не LocalizedStringKey
///     body: "Отметь в Togo: дали или пропустили.")
/// ```
///
/// `scheduleDose(title:body:)` принимает `String`. Литерал на месте
/// вызова каталог не спрашивает **ни разу** — он просто становится
/// значением. Ключ при этом в каталоге есть и переведён на четыре
/// языка, то есть сторож полноты всё это время честно отвечал
/// «переведено» про строку, которая до перевода не доезжает.
///
/// Замер 29.10.2026 на `29ff00b4`: восемь таких литералов, все
/// в `ReminderScheduler.swift`, все с живыми переводами на en/fr/kk/uk
/// в каталоге. Пуш рисуется, когда приложение закрыто, и **ни один
/// кадр его не ловит** — поверхность непроверяемая, а не непроверенная.
///
/// ## Почему ось такая узкая, и это замер, а не осторожность
///
/// Замер 29.10.2026 по двум осям на одном дереве:
///
/// ```
/// «title:/body: с кириллицей» ПО ВСЕМУ ДЕРЕВУ     479 находок — шум
/// то же, но в файлах-постановщиках                  8 находок
/// ```
///
/// Четыреста семьдесят девять — это `TGBanner`, `TGButton`,
/// `TGSectionHeader`, `TGScreen`, `TGListRow`: у них параметр
/// `LocalizedStringKey`, и литерал в них идёт через каталог сам.
/// Сторож, который кричит пятьсот раз, читать перестанут, а это хуже
/// отсутствующего.
///
/// Разделяет их **не имя компонента, а тип параметра**, и узнаётся он
/// по одному признаку: собирает ли этот файл уведомление. Отсюда ось —
/// «файлы, которые ставят запрос в `UNUserNotificationCenter`».
///
/// > Чинится `String(localized:)` на месте вызова — ровно так, как это
/// > уже сделано у соседа `NotificationCenterService.fastingEndText`,
/// > где `String(localized:)` стоит ВНУТРИ функции и в доккомментарии
/// > объяснено почему: наружу уходит значение типа `String`, и литерал
/// > на месте вызова прошёл бы мимо каталога.
@Suite("Текст уведомления идёт через каталог")
struct ТекстУведомленияЧерезКаталогTests {

    /// Деревья обхода. Проверяются на существование **до** обхода.
    ///
    /// Причина — чужая и оплаченная: `FileManager.enumerator(at:)`
    /// по несуществующему пути отдаёт `nil`, и `guard … else { continue }`
    /// молчит. Так `FallbackLiteralTests` четверо суток обходил каталог,
    /// которого на диске нет.
    private static let деревья = ["Togo", "TogoShared", "TogoWidgets"]

    /// Кто ставит запрос в очередь уведомлений.
    ///
    /// **Это предикат обнаружения, а не реестр файлов.** Список файлов
    /// здесь нарочно не записан: реестр устаревает молча, и новый
    /// постановщик в другом файле не покраснел бы ничем. Файлы
    /// находятся замером при каждом прогоне.
    private static let постановщики = [
        "scheduleDose(",
        "scheduleMorningBrief(",
        "scheduleFastingEnd(",
        // Остановки в дороге, 29.10.2026 (`НапоминанияПоездки`).
        "scheduleTripStop(",
    ]

    @Test("Кириллический литерал не уходит в уведомление мимо каталога")
    func литераловМимоКаталогаНет() throws {
        let файлы = try Self.файлыПостановщиков()

        // КОНТРОЛЬ ОБХОДА, и он из предиката, а не из имени файла.
        // Имя стареет при переименовании и тогда врёт молча; «среди
        // найденного есть тот, кто собирает само уведомление» —
        // не стареет, пока жив `UserNotifications`.
        #expect(файлы.contains { $0.текст.contains("UNMutableNotificationContent") }, """
            среди файлов-постановщиков нет ни одного, который собирает \
            `UNMutableNotificationContent`. Значит обход не дошёл \
            до слоя уведомлений — проверь деревья и предикат, а не проект. \
            Найдено файлов: \(файлы.count).
            """)

        var всегоАргументов = 0
        var находки: [String] = []

        for файл in файлы {
            for (номер, строка) in файл.текст.components(separatedBy: .newlines).enumerated() {
                let обрезанная = строка.trimmingCharacters(in: .whitespaces)
                if обрезанная.hasPrefix("//") { continue }

                // Аргумент считается ДО проверки на литерал: порог
                // меряет ФОРМУ и обязан остаться независимым от того,
                // сколько мы уже починили. Порог, зависящий от исхода
                // работы, после сотни починок объявил бы «я ослеп»
                // на здоровом дереве — он мерил бы нас, а не проект.
                if Self.аргументЕсть(строка) { всегоАргументов += 1 }

                guard Self.голыйЛитералВАргументе(строка) else { continue }
                находки.append("\(файл.имя):\(номер + 1) — \(обрезанная.prefix(100))")
            }
        }

        // Число взято замером 29.10.2026 и одинаково ДО и ПОСЛЕ починки
        // восьми литералов: 14. Это и есть доказательство, что порог
        // не просядет от нашей же работы.
        #expect(всегоАргументов >= 10, """
            аргументов вида `title:`/`body:` найдено всего \(всегоАргументов) \
            при 14 на 29.10.2026. Сканер читает не те файлы или не те строки — \
            проверь обход и разбор, а не проект. Ноль находок при просевшем \
            пороге — это слепота, а не чистота.
            """)

        #expect(находки.isEmpty, """
            кириллический литерал уходит в уведомление мимо каталога:

            \(находки.joined(separator: "\n"))

            `scheduleDose(title:body:)` и соседи принимают `String`, \
            а не `LocalizedStringKey`: литерал на месте вызова каталог \
            не спрашивает вовсе. Ключ в каталоге тут не помогает — \
            до него никто не идёт.

            Лечится `String(localized: "…")` на месте вызова. Образец \
            рядом: `NotificationCenterService.fastingEndText(dogName:)`.

            Прежде починки убедиться, что ключ в каталоге уже есть \
            и переведён: новых строк эта правка вводить не должна.
            """)

        print("""
            ГРАНИЦА: этот сторож видит `title:`/`body:` и литерал \
            НА ОДНОЙ СТРОКЕ, и только в файлах, которые сами ставят \
            запрос уведомления (найдено: \(файлы.count)).
            Он НЕ видит: текст, пришедший переменной или функцией; \
            склейку `title: условие ? "а" : "б"`; и перенос литерала \
            на следующую строку после метки.
            Ноль здесь — «этот один способ обойти каталог закрыт», \
            а не «уведомления переведены».
            """)
    }

    // Имя названо предметом, а не формой («Разбор узнаёт обе формы
    // и не считает чужое» уже занято `ОтказВыборкиПоIdTests:177`).
    // Поймали это ДВА сторожа разом — `TestNameUniquenessTests`
    // и `ЭталонСсылаетсяНаЖивоеTests`, — и поймали на мне: имя
    // приехало копией вместе с образцом сканера. Одинаковые имена
    // в разных наборах опасны тем, что одна запись эталона гасит оба.
    @Test("Разбор узнаёт голый литерал в аргументе уведомления")
    func разборРазличаетФормы() {
        // Проверка самого разбора, а не его результата. Без неё сканер
        // мог бы перестать находить что-либо вовсе и остался бы зелёным.
        #expect(Self.голыйЛитералВАргументе(#"            title: "Через 10 минут доза","#) == true)
        #expect(Self.голыйЛитералВАргументе(#"body: "Отметь в Togo: дали или пропустили.""#) == true)

        // Литерал с подстановкой — такой же голый: интерполяция
        // от каталога не спасает. Эти три стоили проекту отдельного
        // замера: в задании их не было, нашлись рядом с названными.
        #expect(Self.голыйЛитералВАргументе(#"title: "Доза \(Fmt.clock(d)) пропущена","#) == true)

        // Через каталог — не находка.
        #expect(Self.голыйЛитералВАргументе(#"title: String(localized: "Через 10 минут доза"),"#) == false)
        #expect(Self.голыйЛитералВАргументе(#"body: String(localized: "Доза \(x) пропущена")"#) == false)

        // Латиница — не предмет: ключи, идентификаторы, коды.
        #expect(Self.голыйЛитералВАргументе(#"title: "dose-reminder","#) == false)

        // Объявление параметра — не аргумент: кавычки нет вовсе.
        #expect(Self.голыйЛитералВАргументе(#"static func scheduleDose(id: String, title: String, body: String)"#) == false)

        // Чужая метка, похожая хвостом. `subtitle:` НЕ предмет: у него
        // в проекте тип `LocalizedStringKey`, и `\b` обязан это
        // различать — иначе сторож потянул бы за собой весь интерфейс.
        #expect(Self.голыйЛитералВАргументе(#"TGBanner(tone: .alarm, subtitle: "Не получилось")"#) == false)

        // Порог считает метку НЕЗАВИСИМО от того, починена она или нет:
        // иначе каждая наша починка отнимала бы у него единицу.
        #expect(Self.аргументЕсть(#"title: String(localized: "Через 10 минут доза"),"#) == true)
        #expect(Self.аргументЕсть(#"title: "Через 10 минут доза","#) == true)

        // Комментарий не код, и обе половины сторожа обязаны думать так
        // одинаково. Голова этого файла цитирует голый литерал
        // в примере, и сторож, не различающий их, покраснел бы на себе.
        #expect(Self.аргументЕсть(#"код() // title: "Через 10 минут доза""#) == false)
        #expect(Self.голыйЛитералВАргументе(#"код() // title: "Через 10 минут доза""#) == false)
    }

    // MARK: Разбор

    /// Метка `title:`/`body:` на строке — без оглядки на то, что справа.
    ///
    /// Нужно только для порога «я ослеп», и именно поэтому правая часть
    /// не смотрится: порог, зависящий от того, литерал там или вызов
    /// каталога, падал бы от наших же починок.
    /// Хвостовой комментарий срезается — ровно как в
    /// `голыйЛитералВАргументе`. Две половины одного сторожа, читающие
    /// строку по-разному, разойдутся молча: порог набрал бы метки
    /// из комментариев, которых находка не видит, и просел бы в ту
    /// сторону, где его никто не проверяет.
    static func аргументЕсть(_ строка: String) -> Bool {
        строка.components(separatedBy: "//")[0]
            .range(of: #"\b(?:title|body)\s*:"#, options: .regularExpression) != nil
    }

    /// Голый кириллический литерал сразу за меткой `title:`/`body:`.
    static func голыйЛитералВАргументе(_ строка: String) -> Bool {
        let код = строка.components(separatedBy: "//")[0]
        guard let метка = код.range(of: #"\b(?:title|body)\s*:\s*""#,
                                    options: .regularExpression)
        else { return false }
        // Через каталог — не находка. Проверяется по тексту ЛЕВЕЕ
        // литерала: `String(localized:` стоит между меткой и кавычкой.
        guard !код[..<метка.upperBound].contains("localized:") else { return false }
        let хвост = код[код.index(before: метка.upperBound)...]
        guard let литерал = Self.первыйЛитерал(String(хвост)) else { return false }
        return естьКириллица(литерал)
    }

    /// Кириллица в строке.
    ///
    /// Четвёртая копия на проект, и я завожу её зная о трёх
    /// (`FallbackLiteralTests`, `LocalizationDebtTests`,
    /// `СвойствоМимоКаталогаTests` — все `fileprivate`/`static`).
    /// Свести четыре в одну — отдельная уборка, и делать её попутно
    /// значило бы править три чужих файла ради своего. Диапазон у всех
    /// один и тот же: U+0400…U+04FF.
    static func естьКириллица(_ строка: String) -> Bool {
        строка.unicodeScalars.contains { (0x0400...0x04FF).contains($0.value) }
    }

    /// Первый литерал строки целиком, с учётом экранированных кавычек.
    private static func первыйЛитерал(_ строка: String) -> String? {
        guard строка.first == "\"" else { return nil }
        var итог = ""
        var предыдущий: Character = " "
        for c in строка.dropFirst() {
            if c == "\"" && предыдущий != "\\" { return итог }
            итог.append(c)
            предыдущий = c
        }
        return nil
    }

    // MARK: Обнаружение

    struct Файл { let имя: String; let текст: String }

    /// Файлы, которые ставят запрос уведомления, — **найденные, а не
    /// перечисленные**.
    ///
    /// Имя постановщика ищется в коде, а не в комментариях: голова
    /// `ReminderScheduler` подробно разбирает `scheduleDoses`
    /// и `scheduleFastingEnd` словами, и обход по сырому тексту собрал
    /// бы файлы, где об уведомлениях только написано.
    static func файлыПостановщиков() throws -> [Файл] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var итог: [Файл] = []

        for дерево in деревья {
            let папка = корень.appendingPathComponent(дерево)
            #expect(FileManager.default.fileExists(atPath: папка.path), """
                каталога «\(дерево)» нет на диске — обход молча пропустил бы \
                его целиком. Имя цели сменилось? Поправь список, а не порог.
                """)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }

            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                let текст = try String(contentsOf: путь, encoding: .utf8)
                let код = текст.components(separatedBy: .newlines)
                    .filter { !$0.trimmingCharacters(in: .whitespaces).hasPrefix("//") }
                    .joined(separator: "\n")
                guard постановщики.contains(where: код.contains) else { continue }
                итог.append(Файл(имя: путь.lastPathComponent, текст: текст))
            }
        }
        return итог.sorted { $0.имя < $1.имя }
    }
}
