import Foundation
import Testing

/// У каждого объявленного типа записи есть место, где он создаётся.
///
/// # Зачем этот сторож. Четыре случая одной формы за один день
///
/// 07.10.2026 четыре раза подряд нашлось одно и то же: **поле или тип
/// объявлены, и писателя у них нет ни одного.**
///
/// ```
/// FamilyMember.accessExpiresAt  читается на экране, писать негде —
///                              и пейволл продавал «ситтер со сроком»
/// LogEvent.editedBy            объявлено, едет в архив, писателя нет
/// Medication.unitRaw           числилось «про семью», не ехало никуда
/// RecordType.weight · .member  объявлены, НИ ОДИН не создаётся
/// ```
///
/// > **Четыре за один день — это класс, а не совпадение.** Назвал его
/// > `projects-74`, и он же назвал лечение: у каждого объявленного типа
/// > записи должно быть доказуемое место, где он создаётся.
///
/// # Чем он отличается от соседей
///
/// `DogPayloadParityTests` спрашивает «есть ли поле в нагрузке».
/// `ArchiveParityTests` — «уезжает ли поле в архив». Оба смотрят
/// **поля** и оба зелены, пока нагрузка существует. Этот спрашивает
/// другое: **создаётся ли запись такого типа хоть где-нибудь.**
///
/// Нагрузка может быть полной, оба сторожа зелёными — и ни одной записи
/// этого типа не уедет никогда, потому что `CKRecord(recordType:)`
/// с ним не вызывается нигде. Ровно это и было с `weight`: перечисление
/// из семи читалось как семь едущих типов.
///
/// > **Список имён — это заявка, а не замер.**
///
/// # Границы, и они печатаются ниже тестом
///
/// Сторож ищет **текст** `RecordType.<case>` в `TogoShared/`. Он
/// доказывает, что имя упомянуто в коде создания записи, и **не**
/// доказывает, что путь достижим, что его зовут и что запись доедет.
/// Это следующий слой, и его закрывают круговые тесты обмена.
@Suite("Объявленный тип записи кем-то создаётся")
struct RecordTypeUsedTests {

    // MARK: Источники

    private static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь),
                          encoding: .utf8)
    }

    /// Все `case` перечисления `RecordType` — из исходника, а не списком.
    ///
    /// Список руками знает только то, что в него положили, — и первым
    /// же пропуском стал бы дырой ровно того размера, ради которого
    /// сторож заведён.
    private static func объявленные() throws -> Set<String> {
        let текст = try исходник("TogoShared/Sync/SharedDiary.swift")
        guard let начало = текст.range(of: "enum RecordType") else { return [] }
        let хвост = текст[начало.upperBound...]
        guard let конец = хвост.range(of: "\n    }") else { return [] }

        var найдено: Set<String> = []
        for строка in хвост[..<конец.lowerBound].components(separatedBy: .newlines) {
            let голая = строка.trimmingCharacters(in: .whitespaces)
            guard голая.hasPrefix("case ") else { continue }
            let имя = голая.dropFirst(5).prefix { $0.isLetter || $0.isNumber }
            if !имя.isEmpty { найдено.insert(String(имя)) }
        }
        return найдено
    }

    /// Какие типы упомянуты там, где создаётся запись.
    ///
    /// **Ищется не само имя, а пара «создание записи + имя типа»** —
    /// и это важно: `grep RecordType.weight` нашёл бы и объявление,
    /// и сравнение в сортировке, и комментарий о том, что тип не едет.
    /// Нам нужно место, где запись **появляется**.
    ///
    /// > **Ноль от поиска отвечает на вопрос «нет такой строки»,
    /// > а не «нет такого вызова».** Поэтому окно читается вокруг
    /// > `CKRecord(recordType:`, а не по всему файлу.
    private static func создаваемые() throws -> Set<String> {
        var найдено: Set<String> = []
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared")

        guard let обход = FileManager.default.enumerator(
            at: корень, includingPropertiesForKeys: nil) else { return [] }

        while let файл = обход.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            // Комментарии вырезаются до разбора: сканирующий сторож,
            // не различающий код и прозу, меряет прозу. У нас это уже
            // стоило красного на строке «// НЕ `MapsApp.allCases`».
            let код = текст.components(separatedBy: .newlines)
                .filter { !$0.trimmingCharacters(in: .whitespaces).hasPrefix("//") }
                .joined(separator: "\n")

            var откуда = код.startIndex
            while let вызов = код.range(of: "CKRecord(recordType:", range: откуда..<код.endIndex) {
                // Окно до конца вызова: имя типа стоит аргументом,
                // то есть в тех же скобках.
                let конец = код.index(вызов.upperBound,
                                      offsetBy: 200,
                                      limitedBy: код.endIndex) ?? код.endIndex
                let окно = код[вызов.upperBound..<конец]
                if let точка = окно.range(of: "RecordType.") {
                    let имя = окно[точка.upperBound...].prefix { $0.isLetter || $0.isNumber }
                    if !имя.isEmpty { найдено.insert(String(имя)) }
                }
                откуда = вызов.upperBound
            }
        }
        return найдено
    }

    // MARK: Объявлено и не создаётся — с причиной

    /// Типы, которые объявлены и **не создаются нарочно**.
    ///
    /// Каждому нужна причина и **дата**: «объявлен и не используется»
    /// без даты не стареет, а с датой стареет громко. Форма та же, что
    /// у долгов в `DogPayloadParityTests.неЕздитПока`, и по той же
    /// причине: «не возим по решению» и «не возим, потому что не дошли
    /// руки» снаружи одинаковы.
    /// **`weight` ушёл отсюда через полчаса после того, как сюда
    /// попал** — тем же вечером, 07.10.2026. Это и есть работа записи
    /// с датой: она назвала ущерб («доза считается от веса»), и ущерб
    /// решил порядок работ. Долг, который не называет ущерб, лежит,
    /// пока не выстрелит.
    private static let объявленоНеСоздаётся: [String: (заведён: String, причина: String)] = [
        "member": ("2026-10-07", """
            Состав семьи и права у каждого свои на каждом телефоне, \
            и это РЕШЕНИЕ, а не недоделка: «я» на втором телефоне \
            уже один раз оказалась карточкой владельца (`5c70324`). \
            Возить список — значит повторить это.

            Но тип объявлен, и объявление читается как обещание. \
            Проверить надо другое: участники приходят из `CKShare`, \
            и возможно, своего типа записи тут не нужно вовсе — тогда \
            `case member` надо УБРАТЬ, а не возить. До проверки это \
            запись здесь, а не чья-то память.
            """),
    ]

    // MARK: Проверки

    /// Первой — что сторожу было что сторожить.
    @Test("Сторожу было что сторожить")
    func былоЧтоСторожить() throws {
        let объявлено = try Self.объявленные()
        let создаётся = try Self.создаваемые()

        #expect(объявлено.count >= 10, """
            типов записи разобрано \(объявлено.count) — разбор \
            перечисления не состоялся. Сторож, переставший что-либо \
            находить, молчит так же, как тот, кому нечего сказать.
            """)
        #expect(создаётся.count >= 8, """
            мест создания разобрано \(создаётся.count) — разбор \
            `CKRecord(recordType:` не состоялся, и проверка ниже \
            назвала бы потерянными ВСЕ типы. Ослепший разбор обязан \
            сказать «я ослеп», а не выдать десять ложных имён.
            """)
    }

    /// Запрет: тип объявлен, нигде не создаётся и не назван исключением.
    @Test("Каждый объявленный тип записи создаётся либо назван с причиной")
    func каждыйТипСоздаётся() throws {
        let объявлено = try Self.объявленные()
        let создаётся = try Self.создаваемые()

        // Ослепший разбор не должен превращаться в список находок.
        guard создаётся.count >= 8 else {
            #expect(Bool(false), """
                разбор мест создания не состоялся (\(создаётся.count)). \
                Чинить `создаваемые()`, а не обмен.
                """)
            return
        }

        let мёртвые = объявлено
            .subtracting(создаётся)
            .subtracting(Self.объявленоНеСоздаётся.keys)
            .sorted()

        #expect(мёртвые.isEmpty, """
            тип записи объявлен и НИГДЕ не создаётся: \
            \(мёртвые.joined(separator: ", ")).

            Это значит, что ни одна запись такого типа не уедет \
            ко второму человеку никогда — при полной нагрузке \
            и зелёных соседних сторожах. Перечисление из семи \
            читалось как семь едущих типов: список имён это ЗАЯВКА, \
            а не замер.

            Либо заведи создание записи (`SharedDiaryRecords.record`, \
            отправку в `FamilySync` и разбор на приёме), либо впиши \
            тип в `объявленоНеСоздаётся` С ПРИЧИНОЙ И ДАТОЙ. Третьего \
            нет: молчаливое объявление неотличимо от обещания.
            """)
    }

    /// Обратная половина: исключение на тип, которого больше нет, —
    /// лишняя дыра, про которую никто не помнит.
    @Test("Исключение стоит на существующем типе, и у него есть дата с причиной")
    func исключенияНеПротухли() throws {
        let объявлено = try Self.объявленные()
        let призраки = Self.объявленоНеСоздаётся.keys
            .filter { !объявлено.contains($0) }.sorted()
        #expect(призраки.isEmpty, """
            исключения стоят на типах, которых в перечислении нет: \
            \(призраки.joined(separator: ", ")). Тип убрали или \
            переименовали, а исключение осталось — и теперь оно молча \
            разрешает то, чего никто не разрешал.
            """)

        // И обратное-обратное: тип, который УЖЕ создаётся, не должен
        // числиться исключением. Иначе разрешение переживёт починку
        // и будет прикрывать следующую поломку.
        let создаётся = try Self.создаваемые()
        let лишние = Self.объявленоНеСоздаётся.keys
            .filter { создаётся.contains($0) }.sorted()
        #expect(лишние.isEmpty, """
            тип создаётся и при этом числится «объявлен и не \
            создаётся»: \(лишние.joined(separator: ", ")). Починили \
            и не убрали разрешение — теперь оно прикроет следующую \
            поломку в этом месте.
            """)

        var безПричины: [String] = []
        for (тип, запись) in Self.объявленоНеСоздаётся {
            if запись.заведён.count != 10 || !запись.заведён.hasPrefix("20") {
                безПричины.append("\(тип): дата «\(запись.заведён)»")
            }
            if запись.причина.trimmingCharacters(in: .whitespacesAndNewlines).count < 60 {
                безПричины.append("\(тип): причина короче, чем отговорка")
            }
        }
        #expect(безПричины.isEmpty, """
            «объявлен и не создаётся» без даты или без причины: \
            \(безПричины.sorted().joined(separator: "; ")).

            Дата нужна, чтобы запись старела громко: «не используется» \
            без даты не стареет вовсе. Порог длины — против отговорок \
            вида «так надо».
            """)
    }

    /// Граница собственного умения — печатается всегда.
    @Test("Сторож называет, чего он не умеет")
    func границаНазвана() {
        let границы = """
            Зелёный здесь значит: у каждого объявленного типа записи \
            есть место, где он УПОМЯНУТ в создании `CKRecord`, либо он \
            назван с датой и причиной. И только это.

            НЕ проверяется:
            · достижим ли этот путь — место создания может быть \
              в функции, которую никто не зовёт. Так уже было: \
              `replaceInPool` у Gamut был прав, покрыт тестом \
              и не вызывался ниоткуда;
            · доедет ли запись до второго человека — это круговые \
              тесты обмена;
            · полна ли нагрузка этого типа — это `DogPayloadParityTests`;
            · создаётся ли запись В НУЖНЫЙ МОМЕНТ. Сторож на упоминание \
              ловит «не позвали» и слеп к «позвали не вовремя».
            """
        #expect(границы.isEmpty == false)
    }
}
