import Testing
import Foundation
import SwiftData
@testable import Togo

/// Отладочная запись прогрева схемы не уезжает ко второму человеку.
///
/// # Повод измерен по живым данным, а не предположен
///
/// Выгрузка с телефона Виктории, `~/Downloads/togo-2026-10-08.json`,
/// создана 08.10.2026 18:22, версия приложения 1.0.0:
///
/// ```
/// записей в дневнике            182
/// авторы      «Виктория» 94 · «Я» 87 · «ПРОГРЕВ СХЕМЫ» 1
/// dogs[0].events[42]            kindRaw note · date 2001-01-01
///                               authorName = incidentDetailRaw
///                                          = ПРОГРЕВ СХЕМЫ
/// собака                        «Стич» — та самая, видимая
/// вхождений метки и дат до 2002
/// во ВСЕЙ выгрузке              ровно три, все в этой одной записи
/// самая ранняя НАСТОЯЩАЯ запись 2026-09-01 → запас 24 года
/// ```
///
/// # Почему это не чинится там, где создано
///
/// `CloudKitSchemaWarmup` целиком под `#if DEBUG` — и `create`,
/// и `remove`, и метки `markerTitle`/`доПрограммы`. Значит
/// в продуктовой сборке запись **не создастся и не удалится**:
/// убрать её оттуда приложение не умеет вовсе.
///
/// ```
/// в Release СОЗДАТЬСЯ   не может   ← это верно и хорошо
/// в Release УБРАТЬСЯ    не может   ← remove() под DEBUG
/// фильтра в ленте, отчёте врачу, CSV   ни одного
/// ```
///
/// Отладочный артефакт отладочной сборки уже лежит в живых данных.
/// Единственное, что мы можем, — не отправлять его дальше.
///
/// # Форма — от запрета, и признак взят не тот, что бросается в глаза
///
/// Признак — **дата, а не имя автора**. Метка в поле автора есть,
/// но опираться на неё нельзя: `LogEvent` ездит в общий дневник,
/// и слияние переписывает `authorName` из приехавшего payload. Это
/// написано в голове самого прогрева (`CloudKitSchemaWarmup:35-40`)
/// и измерено там 23.09 — после «убрать прогрев» остались ровно
/// те два типа, что синхронизируются. Дату не переписывает никто.
///
/// # Чего этот набор НЕ делает
///
/// Он не убирает уехавшее. Уехала ли запись в зону уже —
/// **неизмеримо**, и это записано как неизмеренное, а не как «нет»:
/// `LogEvent.isSynced` объявлен `= true` по умолчанию и доставку
/// строки не отслеживает (`TGRows:274`), а приватную базу CloudKit
/// открывают права владельца данных, второго конца у связи нет.
///
/// # Этот набор про ОТПРАВКУ. Рядом живёт второй, про ПОКАЗ
///
/// Снаружи они выглядят одним предметом «служебная запись», и это
/// ловушка: читающий решит, что один из двух лишний.
///
/// ```
/// ЭТОТ набор      запись не УЕЗЖАЕТ маме
///                 TogoShared/Sync/ · ворота на обеих дверях наружу
/// набор про показ запись не ломает вердикт у СЕБЯ
///                 Diary.daysOfData считает от самой ранней активной,
///                 и дата 2001 даёт ≈9410 дней при двух настоящих
///                 событиях → красная линия «меньше четырёх дней —
///                 всегда „непонятно“» становится непроходимой вниз.
///                 Цепочка измерена `projects-a1` по коду
/// ```
///
/// > **Снимешь этот запрет — запись уедет маме. Снимешь тот —
/// > у неё же сломается вердикт.** Два запрета в разных слоях дешевле
/// > одного в узком месте, и приёмка требует снимать их по очереди,
/// > убеждаясь, что краснеет свой, а не оба разом.
///
/// Про остальной ПОКАЗ здесь не измерено ничего. Известно с той
/// стороны: в отчёт врачу запись не попадает (`VetSummary` фильтрует
/// окном, по умолчанию месяц), а в CSV-выгрузку попадает — окна у неё
/// нет вовсе. Фильтра по метке вне `DEBUG` нет ни одного.
@MainActor
@Suite("Отладочная запись прогрева не уезжает")
struct ОтладочнаяЗаписьНеУезжаетTests {

    /// Та же дата, что у живой находки: `2001-01-01`.
    private var отладочная: LogEvent {
        LogEvent(kind: .note,
                 date: Date(timeIntervalSinceReferenceDate: 0),
                 authorName: CloudKitSchemaWarmup.markerTitle)
    }

    // MARK: Запрет 1 · правило

    @Test("Запись раньше приложения наружу не годится, а настоящая годится")
    func правило() {
        #expect(!SharedDiaryOutgoing.sendable(отладочная), """
            ворота пропустили отладочную запись прогрева (01.01.2001).
            Без этого запрета засев отправит её маме ПЕРВОЙ записью
            истории: заметка от автора, которого она не знает, —
            в комнату, которую засев и должен был наполнить.
            """)

        // Самая ранняя настоящая запись живой выгрузки. Запас между
        // ней и меткой — двадцать четыре года, то есть порог не на краю.
        let настоящая = LogEvent(kind: .meal,
                                 date: Date(timeIntervalSince1970: 1_788_000_000), // 2026-09
                                 authorName: "Виктория")
        #expect(SharedDiaryOutgoing.sendable(настоящая), """
            ворота задержали НАСТОЯЩУЮ запись 2026 года. Это хуже
            пропуска: мама перестанет видеть то, что Виктория отметила,
            и симптом будет тот же, что у пустой комнаты.
            """)

        // Край называется числом, а не «примерно»: порог сдвинут —
        // тест обязан сказать, куда именно.
        #expect(SharedDiaryOutgoing.раньшеПриложения
                == Date(timeIntervalSince1970: 1_577_836_800), """
            порог «раньше приложения» сдвинут. Он стоит между меткой
            прогрева (2001) и самой ранней настоящей записью (2026-09-01);
            сдвинув его, проверь обе границы, а не одну.
            """)
    }

    // MARK: Запрет 2 · ДВЕ двери, и каждая проверяется отдельно

    /// Два пути наружу — два места для одного запрета.
    ///
    /// Поведенческий запрет выше поймает «правило пропустило». Он
    /// не поймает «ветку переписали без вызова ворот»: это даст
    /// зелёный на новом коде, которого тест не знает.
    ///
    /// **Проверки РАЗНЕСЕНЫ по дверям нарочно.** Сними вызов у одной
    /// двери — краснеет ровно одно утверждение и называет, какая.
    /// Сплошная проверка покраснела бы и не сказала, что именно сняли.
    @Test("Ворота зовут обе двери наружу, и каждая названа отдельно")
    func обеДвери() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        // Комментарии вырезаются до разбора: сторож, читающий исходник,
        // не отличает код от рассказа о коде — и краснеет на абзаце,
        // объясняющем, почему так делать нельзя. У нас это уже стоило
        // ложного красного и, хуже, ложной зелени в трёх тестах из четырёх.
        func код(_ путь: String) throws -> [String] {
            try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
                .components(separatedBy: "\n")
                .map { $0.components(separatedBy: "//")[0] }
        }

        let засев = try код("TogoShared/Sync/SharedDiarySeed.swift")
        let обмен = try код("TogoShared/Sync/FamilySync.swift")
        let реестр = try код("TogoShared/Sync/РеестрОбмена.swift")
        let правила = try код("TogoShared/Sync/SharedDiaryPayloads.swift")

        // Своё зрение первым: набор, которому нечего проверять, молчит
        // так же, как набор, у которого всё хорошо.
        #expect(засев.count > 60, "SharedDiarySeed прочитан пустым: \(засев.count) строк")
        #expect(обмен.count > 200, "FamilySync прочитан пустым: \(обмен.count) строк")
        #expect(реестр.count > 100, "РеестрОбмена прочитан пустым: \(реестр.count) строк")
        #expect(правила.count > 100, "SharedDiaryPayloads прочитан пустым: \(правила.count) строк")

        // Ось сменена 05.11.2026 («прокси наоборот»). Прежде здесь
        // требовались `as? LogEvent`, `собрать(LogEvent.self` с воротами
        // и `guard SharedDiaryOutgoing.sendable(event)` — имена механизма,
        // которого больше нет: двенадцать веток и двенадцать вызовов
        // сведены в `РеестрОбмена`, и ворота каждого типа —
        // его `годитсяНаружу`. Поведение каждой двери на отладочной
        // записи держит `РеестрОбменаTests`; здесь — что каждая дверь
        // идёт через реестр и что в каждой функции реестра ворота стоят.
        // Проверки по-прежнему РАЗНЕСЕНЫ по дверям.

        // ДВЕРЬ ПЕРВАЯ: засев уже лежащих записей. Он кладёт изменения
        // в движок напрямую, мимо `enqueueLocalChanges`.
        #expect(засев.contains { $0.contains("РеестрОбмена.всеГодные(") }, """
            ЗАСЕВ больше не идёт через `РеестрОбмена.всеГодные` — у него             свой список типов, и ворот на нём реестр не гарантирует.
            """)
        #expect(реестр.contains { $0.contains(".filter(\\.годитсяНаружу)") }, """
            ЗАСЕВ в реестре собирает без ворот. Это та дверь, которой
            уедет накопленное: 182 записи разом, включая отладочную.
            """)

        // ДВЕРЬ ВТОРАЯ: «сохранили → отправили».
        #expect(обмен.contains { $0.contains("РеестрОбмена.кОтправке(") }, """
            ИСХОДЯЩИЙ КРУГ больше не идёт через `РеестрОбмена.кОтправке`.
            """)
        #expect(реестр.contains { $0.contains("guard модель.годитсяНаружу else") }, """
            в ИСХОДЯЩЕМ КРУГЕ реестра нет ворот. Эта дверь отправляет
            по одной, по уведомлению хранилища, — и отладочная запись
            уедет по ней при зелёном стороже засева.
            """)

        // ДВЕРЬ ТРЕТЬЯ: сборка записи перед сервером (с 04.11.2026).
        #expect(обмен.contains { $0.contains("РеестрОбмена.запись(") }, """
            СБОРКА ЗАПИСИ больше не идёт через `РеестрОбмена.запись`.
            """)
        #expect(реестр.contains { $0.contains("guard модель.годитсяНаружу,") }, """
            в СБОРКЕ ЗАПИСИ реестра нет ворот: правка, вставшая в очередь             до того, как запись стала негодной, уедет.
            """)

        // И сами ворота остались одной функцией. Своя копия условия
        // у второй двери была бы хуже: два разбора одного правила
        // расходятся молча.
        #expect(правила.contains { $0.contains("static func sendable(_ event: LogEvent)") }, """
            ворота на записи перестали быть отдельной функцией. Пока
            они внутри одной двери, вторая их не позовёт — и уедет то,
            что здесь запрещено.
            """)
    }
}
