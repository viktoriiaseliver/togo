import Testing
import Foundation
@testable import Togo

/// Второй вход для фото собаки — жетон в шапке «Сегодня».
///
/// Решение дизайна 23.10.2026, пункт 9 (`Дизайн/редизайн-ios28/
/// ОТВЕТЫ-круг-2.md`, коммит `816a96a`): «тап по пустому
/// аватару-жетону в шапке „Сегодня“ открывает **тот же**
/// `PhotosPicker`».
///
/// # Почему сторож читает исходник, а не зовёт функцию
///
/// Предмет здесь — **что код делает одним вызовом, а не двумя
/// одинаковыми**. Тест, который сам позовёт `ФотоСобаки.положить`,
/// докажет, что она работает, и ничего не скажет о том, зовут ли её
/// оба входа: у Togo это записано — «тест, который сам зовёт функцию,
/// не проверяет, что её зовут».
///
/// Цена копии названа и измерима: фото собаки с 23.10.2026 —
/// подложка по умолчанию, её читает виджет, а расширение ограничено
/// по памяти. Снимок 3000 px разворачивается примерно в 36 МБ.
/// Второй вход без `ФонФото.ужать` убил бы виджет, и ни компилятор,
/// ни прогон этого не увидят.
///
/// # Чего сторож НЕ видит
///
/// Он не открывает системный лист выбора: `PhotosPicker` работает
/// в отдельном процессе, и стенд его не достаёт. Утверждение здесь
/// ровно одно — **дорога из шапки «Сегодня» ведёт в общий разбор
/// снимка**, и ни слова о том, что человек увидит, нажав.
@Suite("Жетон фото собаки · второй вход")
struct ЖетонФотоСобакиTests {

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private static func исходник(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Исходник **без прозы**.
    ///
    /// Это не аккуратность, а необходимость, и она измерена прямо
    /// здесь: в голове `DogTab.кнопкаСнимка` стоит строка замера
    /// `OnboardingFlow.swift:299   dog.photo = photo`, а в голове
    /// `ВыборФотоСобаки` — «1000 px по длинной стороне». Сторож,
    /// не различающий код и прозу, покраснел бы на обеих и запретил бы
    /// писать про ошибку в том файле, где её не совершают.
    ///
    /// Кавычки учитываются: `"togo://join"` — не комментарий.
    private static func код(_ путь: String) throws -> String {
        let текст = try исходник(путь)
        var вывод: [String] = []
        for строка in текст.split(separator: "\n", omittingEmptySubsequences: false) {
            var вКавычках = false
            var экран = false
            var чистая = ""
            var предыдущий: Character?
            for символ in строка {
                if экран { экран = false; чистая.append(символ); предыдущий = символ; continue }
                if символ == "\\" && вКавычках { экран = true; чистая.append(символ); continue }
                if символ == "\"" { вКавычках.toggle() }
                if !вКавычках, символ == "/", предыдущий == "/" {
                    чистая.removeLast()
                    break
                }
                чистая.append(символ)
                предыдущий = символ
            }
            вывод.append(чистая)
        }
        return вывод.joined(separator: "\n")
    }

    private static let общий = "Togo/Features/Profile/ВыборФотоСобаки.swift"
    private static let шапка = "Togo/Features/Today/TodayHeader.swift"
    private static let вкладка = "Togo/Features/Profile/DogTab.swift"

    @Test("Шапка «Сегодня» рисует жетон, а не немой аватар")
    func шапкаЗовётЖетон() throws {
        let текст = try Self.код(Self.шапка)
        // Контроль в том же замере: файл прочитан и это та самая шапка.
        #expect(текст.contains("struct TodayHeader"), "прочитано не то — замер не состоялся")

        #expect(текст.contains("ЖетонСобаки(dog: dog)"),
                "в шапке «Сегодня» снова немой аватар — второго входа нет")
        // Своего разбора снимка у шапки быть не должно: иначе это
        // копия, а не тот же путь.
        #expect(!текст.contains("loadTransferable"),
                "шапка завела собственный разбор снимка — это вторая копия правила")
        #expect(!текст.contains("ФонФото.ужать"),
                "ужатие переехало в шапку — значит у входов снова по своему пути")
    }

    @Test("Оба входа зовут ОДИН разбор снимка")
    func входовДваПутьОдин() throws {
        let вкладка = try Self.код(Self.вкладка)
        let шапка = try Self.код(Self.шапка)
        let общий = try Self.код(Self.общий)

        // Проверка, что проверять было что: оба файла живые.
        #expect(вкладка.contains("struct DogTab"))
        #expect(общий.contains("enum ФотоСобаки"))

        #expect(вкладка.contains("ФотоСобаки.положить"),
                "вкладка собаки пишет фото в обход общего разбора")
        #expect(общий.contains("ФотоСобаки.положить") || общий.contains("static func положить"),
                "общего разбора нет вовсе")
        // Жетон живёт в общем файле и зовёт оттуда же.
        #expect(общий.contains("struct ЖетонСобаки"))
        #expect(общий.contains("await ФотоСобаки.положить"),
                "жетон не зовёт общий разбор")
    }

    @Test("Ужатие стоит ровно в одном месте, и оно общее")
    func ужатиеОдно() throws {
        let общий = try Self.код(Self.общий)
        #expect(общий.contains("ФонФото.ужать"),
                "общий разбор не ужимает снимок — виджет это не переживёт")
        // Своего числа у входов нет: 1000 px и 0,8 живут в `ФонФото`.
        #expect(!общий.contains("1000"), "в общий разбор переехало число — вторая копия предела")

        let вкладка = try Self.код(Self.вкладка)
        #expect(!вкладка.contains("ФонФото.ужать"),
                "вкладка ужимает сама — значит разбор снова в двух местах")
    }

    @Test("Запись в `Dog.photo` идёт одним путём, и путь этот общий")
    func писательОдин() throws {
        // Где фото вообще присваивается. Восстановление из архива
        // и онбординг — не входы человека: первый переносит, второй
        // кладёт черновик, в который снимок никто не пишет (замер
        // 23.10.2026, `DogTab.кнопкаСнимка`).
        let разрешённые = ["Togo/Features/Profile/ВыборФотоСобаки.swift",
                           "TogoShared/Domain/Backup.swift",
                           "Togo/Features/Onboarding/OnboardingFlow.swift"]
        var найдено: [String] = []
        for файл in разрешённые {
            let текст = try Self.код(файл)
            #expect(!текст.isEmpty, "\(файл): прочитано пусто — замер не состоялся")
            if текст.contains(".photo = ") { найдено.append(файл) }
        }
        // Ось — от объявления, а не от вкуса: общий разбор ОБЯЗАН
        // присваивать, иначе он не писатель.
        #expect(найдено.contains("Togo/Features/Profile/ВыборФотоСобаки.swift"),
                "общий разбор не пишет в `Dog.photo` — значит пишет кто-то другой")

        // И ни вкладка, ни шапка не пишут сами.
        for файл in [Self.вкладка, Self.шапка] {
            let текст = try Self.код(файл)
            #expect(!текст.contains("dog.photo = "),
                    "\(файл): пишет в `Dog.photo` в обход общего разбора")
        }
    }

    @Test("Жетон открывает выбор только когда фотографии НЕТ")
    func толькоПустойЖетон() throws {
        let общий = try Self.код(Self.общий)
        #expect(общий.contains("dog.photo == nil"),
                "жетон стал кнопкой при любом состоянии — дизайн просил только пустой")
        #expect(общий.contains("PhotosPicker("),
                "жетон не открывает системный выбор")
        // У жетона должно быть имя для озвучки: `TGAvatar` прячет себя
        // от VoiceOver, и без явного элемента второго входа слепой
        // человек не нашёл бы вовсе.
        #expect(общий.contains("accessibilityLabel(\"Снимок собаки\")"),
                "у жетона нет имени для озвучки")
        // Ключ каталога тот же, что у первого входа: новых строк
        // в `Localizable.xcstrings` эта правка не заводит.
        let вкладка = try Self.код(Self.вкладка)
        #expect(вкладка.contains("accessibilityLabel(\"Снимок собаки\")"),
                "первый вход переименовали — ключи входов разошлись")
    }

    @Test("Онбординг не тронут: там по-прежнему только кличка и фраза")
    func онбордингНеТронут() throws {
        let поток = try Self.код("Togo/Features/Onboarding/OnboardingFlow.swift")
        #expect(поток.contains("struct OnboardingFlow"), "прочитано не то — замер не состоялся")
        #expect(!поток.contains("PhotosPicker"),
                "в онбординге завёлся выбор фото — дизайн просил его не трогать")
        #expect(!поток.contains("ЖетонСобаки"),
                "жетон уехал в онбординг — это третий вход, которого не просили")
    }
}
