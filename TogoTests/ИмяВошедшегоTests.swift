import Testing
import Foundation
@testable import Togo

/// Кто вошёл по приглашению — и почему приложение этого не знало.
///
/// # «Система считает меня анонимом», 29.10.2026
///
/// Замер того дня, контроль в той же команде:
///
/// ```
/// CKShare.currentUserParticipant   0 вхождений во всём дереве
/// контроль: share.participants    14 вхождений, rc=0 — запрос жив
/// currentUserName = …              ОДИН писатель: AppState.swift:201,
///                                  внутри adopt(_ member:)
/// FamilyMember(…)                  5 мест создания, и ни одного
///                                  на приёме приглашения
/// ```
///
/// Цепочка складывается в одно. Приглашение принято → `accepted(…)`
/// запомнил **владельца зоны** и включил обмен. Своей карточки
/// у вошедшего нет: `FamilyResolver.меня(…, гость: true)` опознаёт
/// только по `myMemberID`, а его пишет онбординг владельца и кнопка
/// «это я» — приглашённый ничего из этого не проходил. Значит
/// `adopt(_:)` не звался, значит единственный писатель имени молчал,
/// значит `currentUserName` остался `AppState.storedUserName` — «Я».
///
/// > **Роль `.observer` здесь ни при чём и правильна** (красная линия
/// > проекта). Аноним — это не узкая роль, а **отсутствие имени
/// > у того, кого CloudKit знает по имени**: записи второго телефона
/// > подписаны словом «Я», и «кто дал дозу» перестаёт быть вопросом
/// > с ответом.
///
/// # Чего эти тесты НЕ проверяют, и это названо, а не подразумевается
///
/// Приходит ли имя из облака — проверить нечем: приватная база CloudKit
/// неизмерима без её личного iCloud, второго конца у связи нет
/// (`Togo/CLAUDE.md`, «Источники правды»). Здесь проверено всё, что
/// вынесено из неизмеримого в чистое значение: **что делать с именем,
/// когда оно есть, и что делать, когда его нет.**
@Suite("Вошедший по приглашению перестаёт быть анонимом")
struct ИмяВошедшегоTests {

    /// Подпись автора записей живёт в `UserDefaults.standard`
    /// (`AppState.currentUserName.didSet`), то есть тест, меняющий её,
    /// пачкает симулятор соседям. Возвращаем как было.
    private static func сИмениВернув(_ тело: () -> Void) {
        let было = UserDefaults.standard.string(forKey: AppState.Keys.userName)
        defer {
            if let было { UserDefaults.standard.set(было, forKey: AppState.Keys.userName) }
            else { UserDefaults.standard.removeObject(forKey: AppState.Keys.userName) }
        }
        тело()
    }

    /// Состояние без наследства: `AppState()` читает `family.me`
    /// из `UserDefaults`, поэтому сброс стоит **после** конструктора —
    /// тот же порядок и та же причина, что в `PermissionTests`.
    @MainActor
    private static func состояние() -> AppState {
        let это = AppState()
        это.myMemberID = nil
        return это
    }

    // MARK: Имя

    @MainActor
    @Test("Гость без своей карточки подписывается именем из приглашения")
    func гостьБерётИмяИзПриглашения() {
        Self.сИмениВернув {
            let владелец = FamilyMember(name: "Виктория", role: .owner, isMe: true)
            let это = Self.состояние()

            // `гость: true`, `назначение: nil` — то состояние, в котором
            // человек оказывается сразу после приёма: наряд ролей ещё
            // не приехал, карточки семьи не его.
            это.adoptMe(from: [владелец], гость: true, назначение: nil,
                        имяВПриглашении: "Аня")

            #expect(это.currentUserName == "Аня", """
                вошедший по приглашению подписан «\(это.currentUserName)». \
                Имя приходит в `CKShare.Metadata` в минуту приёма \
                (`ShareAcceptance.моёИмя`), и до 29.10.2026 его \
                не спрашивал никто: все отметки второго телефона уходили \
                за подписью «Я».
                """)
            #expect(это.role == .observer, """
                роль гостя без опознания обязана остаться самой узкой. \
                Имя — это подпись записи, а не право: смешать их значило бы \
                выдать права по тому, что назвался.
                """)
        }
    }

    @MainActor
    @Test("Своя карточка сильнее имени из приглашения")
    func карточкаСильнееПриглашения() {
        Self.сИмениВернув {
            let моя = FamilyMember(name: "Маша", role: .caregiver)
            let владелец = FamilyMember(name: "Виктория", role: .owner, isMe: true)
            let это = Self.состояние()
            это.myMemberID = моя.id

            это.adoptMe(from: [владелец, моя], гость: true, назначение: nil,
                        имяВПриглашении: "Аня")

            #expect(это.currentUserName == "Маша", """
                имя взято из приглашения при живой своей карточке. \
                В карточке имя выбрал сам человек, в приглашении — \
                то, как его зовёт Apple ID; при расхождении верно первое.
                """)
        }
    }

    @MainActor
    @Test("В своём дневнике имя из приглашения не берётся")
    func вСвоёмДневникеНеБерётся() {
        Self.сИмениВернув {
            let это = Self.состояние()
            let прежнее = это.currentUserName

            это.adoptMe(from: [], гость: false, назначение: nil,
                        имяВПриглашении: "Аня")

            #expect(это.currentUserName == прежнее, """
                имя из чужого приглашения подставилось владельцу \
                собственного дневника: «\(это.currentUserName)» вместо \
                «\(прежнее)». Признак «мы в чужом дневнике» — \
                `SharedZoneOwner.isGuest`, и он стоит в условии первым \
                не для красоты.
                """)
            #expect(это.role == .owner, "в своём дневнике без карточек права остаются полными")
        }
    }

    @MainActor
    @Test("Пустое имя подпись не стирает")
    func пустоеИмяНеСтирает() {
        Self.сИмениВернув {
            let владелец = FamilyMember(name: "Виктория", role: .owner, isMe: true)
            let это = Self.состояние()
            let прежнее = это.currentUserName

            // CloudKit отдаёт `nameComponents` не всегда, и собранная
            // из пустых частей строка — это «не знаем», а не имя.
            это.adoptMe(from: [владелец], гость: true, назначение: nil,
                        имяВПриглашении: "   ")

            #expect(это.currentUserName == прежнее, """
                пустое имя из приглашения стёрло подпись автора: \
                «\(это.currentUserName)». Пустая подпись хуже «Я»: \
                у записи пропадает автор, и читает её потом врач.
                """)

            // Контроль в том же тесте: непустое имя проходит. Без него
            // проверка выше зелена и у ветки, которая не берёт имя никогда.
            это.adoptMe(from: [владелец], гость: true, назначение: nil,
                        имяВПриглашении: "Аня")
            #expect(это.currentUserName == "Аня",
                    "контроль: непустое имя обязано дойти, иначе проверка выше ничего не значит")
        }
    }

    // MARK: Хранилище

    @MainActor
    @Test("Имя по приглашению хранится и пустое не хранит")
    func хранилищеИмени() {
        let было = ИмяПоПриглашению.имя
        defer { ИмяПоПриглашению.имя = было }

        ИмяПоПриглашению.имя = "Аня"
        #expect(ИмяПоПриглашению.имя == "Аня", """
            имя не сохранилось. Оно приходит ровно в один момент — \
            когда приглашение принято, — и спросить его заново неоткуда: \
            второй вход в подпись записей (голос, кнопка «Действие», \
            виджет) живёт в чужом процессе.
            """)

        ИмяПоПриглашению.имя = "   "
        #expect(ИмяПоПриглашению.имя == nil, """
            пустая строка сохранилась как имя. «Не знаем» и «зовут \
            пробелом» — разные состояния, и второго не бывает.
            """)

        ИмяПоПриглашению.имя = "Аня"
        ИмяПоПриглашению.reset()
        #expect(ИмяПоПриглашению.имя == nil, "сброс не сработал")
    }

    // MARK: Сторож на вопрос, которого не задавали

    /// `CKShare.currentUserParticipant` спрашивается — и у имени есть
    /// и писатель, и читатель.
    ///
    /// **Три проверки, и ни одна не покрывает двух других**, потому что
    /// дыра была именно такой формы: хранилище без писателя, писатель
    /// без читателя и вопрос, которого не задавали, выглядят в коде
    /// одинаково — отсутствием строк. Это наш класс «механизм без
    /// входа», и ловится он только переписью входов.
    ///
    /// Подделка (29.10.2026): убрать `ИмяПоПриглашению.имя = моёИмя`
    /// из `ShareAcceptance.accepted` — краснеет «писателей 0», соседи
    /// по набору зелёные.
    @Test("У имени вошедшего есть источник, писатель и читатель")
    func механизмИмениИмеетВход() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()

        var вопросов = 0            // CKShare.currentUserParticipant
        var писателей = 0           // ИмяПоПриглашению.имя = …
        var читателей = 0           // ИмяПоПриглашению.имя в выражении
        var контроль = 0            // share.participants — заведомо живой запрос
        var файловОсмотрено = 0

        for каталог in ["Togo", "TogoShared"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(каталог), includingPropertiesForKeys: nil)
            while let файл = обход?.nextObject() as? URL {
                guard файл.pathExtension == "swift",
                      let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
                файловОсмотрено += 1

                // Проза режется до разбора — иначе сканер посчитал бы
                // за механизм доккомментарии, которые разбирают этот
                // самый дефект и цитируют все четыре искомые строки.
                let код = текст.components(separatedBy: .newlines)
                    .map { строка -> String in
                        guard let i = строка.range(of: "//") else { return строка }
                        return String(строка[..<i.lowerBound])
                    }
                    .joined(separator: "\n")

                вопросов += код.components(separatedBy: "currentUserParticipant").count - 1
                контроль += код.components(separatedBy: "share.participants").count - 1
                let всего = код.components(separatedBy: "ИмяПоПриглашению.имя").count - 1
                let записей = код.components(separatedBy: "ИмяПоПриглашению.имя =").count - 1
                писателей += записей
                читателей += всего - записей
            }
        }

        #expect(файловОсмотрено >= 150, """
            осмотрено файлов: \(файловОсмотрено) — обход не состоялся, \
            и тишина ниже ничего не значит.
            """)
        // Контроль того же семейства и в том же замере: запрос к составу
        // участников заведомо жив. Ноль здесь значит «сканер ослеп»,
        // а не «CloudKit у нас не спрашивают».
        #expect(контроль >= 3, """
            контроль не нашёлся: `share.participants` встречается \(контроль) раз, \
            а их не меньше трёх (`participants()`, `участники()`, `убрать()`). \
            Сканер ослеп — числа ниже не значат ничего.
            """)

        #expect(вопросов >= 1, """
            `CKShare.currentUserParticipant` не спрашивают нигде — ровно \
            то состояние, которым оплачен этот набор. Это единственный, \
            кто называет вошедшего по имени: локальной карточки \
            у приглашённого нет по построению, её заводят онбординг \
            владельца и кнопка «Добавить человека».
            """)
        #expect(писателей >= 1, """
            имя вошедшего никто не записывает (`ИмяПоПриглашению.имя = …` \
            найдено \(писателей) раз). Хранилище без писателя — это \
            «механизм без входа»: объявление есть, дороги нет, \
            и отличить это от рабочего нельзя ни компилятором, ни тестом.
            """)
        #expect(читателей >= 1, """
            имя вошедшего никто не читает (\(читателей) чтений). Поле \
            без читателя грепом находится один раз — в объявлении — \
            и выглядит живым.
            """)
    }
}
