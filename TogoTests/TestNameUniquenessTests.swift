import Testing
import Foundation

/// Имя теста — утверждение о поведении, и двух одинаковых быть не должно.
///
/// **Зачем сторож, а не договорённость.** `Tools/эталон-прогона.json`
/// хранит ожидаемо красные **по именам**, и `Tools/сверить_эталон.py`
/// сверяет по именам же. Значит два теста с одним именем — это
/// возможность погасить **двух** сторожей одной записью эталона,
/// и погаснет второй молча: в отчёте он выглядит как первый.
///
/// Замер 07.10.2026: 828 имён `@Test`, **шесть дублировались**
/// семнадцатью вхождениями. Худшее — «Границы: что этот набор
/// НЕ проверяет» в шести файлах разом. Ни одна запись эталона в тот
/// день не была двусмысленной, то есть **дыра была, выстрела не было**;
/// заводится сторож именно поэтому, а не после.
///
/// Переименованы предметом, а не номером: номер через месяц не скажет,
/// который из двух, предмет скажет.
///
/// Рядом с уже записанным «имя теста стареет молча»: **одинаковые
/// имена стареют вдвоём**, и правка одного из них выглядит правкой
/// обоих.
@Suite("Имена тестов уникальны")
struct TestNameUniquenessTests {

    /// В день написания: 845 имён в 99 файлах двух целей.
    ///
    /// Порог тупой нарочно — он ловит не рост, а **ослепший обход**.
    /// Сканер, переставший что-либо находить, молчит так же, как тот,
    /// кому нечего сказать.
    private static let именНеМенее = 800

    /// Маркер собирается из двух кусков НАРОЧНО.
    ///
    /// Напиши его литералом целиком — и обход нашёл бы его в этом самом
    /// файле, то есть сторож посчитал бы собственный исходник за тест
    /// и назвал бы его дублем. Это наш записанный класс: сканирующий
    /// сторож, не различающий код и прозу, меряет прозу — а здесь он
    /// мерил бы себя.
    private static let маркер = "@Test" + "(\""

    private func имена() -> (список: [(имя: String, где: String)], файлов: Int) {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [(имя: String, где: String)] = []
        var файлов = 0

        for цель in ["TogoTests", "TogoUITests"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(цель), includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8)
                else { continue }
                файлов += 1

                for строка in текст.components(separatedBy: .newlines) {
                    // Комментарии не в счёт: тест, читающий рассказ о коде
                    // как код, краснеет без дефекта — а красный без дефекта
                    // учит не верить красному.
                    let код = строка.components(separatedBy: "//")[0]
                    guard let начало = код.range(of: Self.маркер) else { continue }
                    let хвост = код[начало.upperBound...]
                    guard let конец = хвост.firstIndex(of: "\"") else { continue }
                    найдено.append((String(хвост[..<конец]),
                                    "\(цель)/\(элемент.lastPathComponent)"))
                }
            }
        }
        return (найдено, файлов)
    }

    @Test("Обход просмотрел имена тестов, а не промолчал")
    func былоЧтоПроверять() {
        let (список, файлов) = имена()
        #expect(файлов > 50, "файлов прочитано \(файлов) — обход не состоялся")
        #expect(список.count >= Self.именНеМенее, """
            имён `@Test` найдено \(список.count), а в день написания было
            не меньше \(Self.именНеМенее). Либо дерево переехало, либо
            обход перестал его видеть — и тогда проверка уникальности
            ниже зелена потому, что ей нечего смотреть.
            """)
    }

    @Test("Двух тестов с одним именем в проекте нет")
    func именаУникальны() {
        let (список, _) = имена()
        var где: [String: [String]] = [:]
        for запись in список { где[запись.имя, default: []].append(запись.где) }

        let дубли = где.filter { $0.value.count > 1 }
            .sorted { $0.key < $1.key }
        let рассказ = дубли.map { имя, файлы in
            "  «\(имя)»\n      " + файлы.sorted().joined(separator: "\n      ")
        }.joined(separator: "\n")

        #expect(дубли.isEmpty, """
            одно имя `@Test` на несколько тестов:

            \(рассказ)

            Эталон прогона сверяет красное ПО ИМЕНАМ: одна запись
            «ожидаемо красный» погасит их все, и лишние погаснут молча.
            Различай предметом, а не номером: номер через месяц
            не скажет, который из двух.
            """)
    }

    /// Границы — последней строкой, как у остальных сторожей проекта.
    @Test("Границы: чего не проверяет сторож имён тестов")
    func границыНазваны() {
        let (список, _) = имена()

        // Имя, собранное выражением, этот обход не видит по устройству:
        // он читает литерал. Проверяем, что таких нет, — иначе граница
        // из оговорки становится дырой.
        let собранные = список.filter { $0.имя.contains("\\(") }
        #expect(собранные.isEmpty, """
            имя теста собрано интерполяцией: \(собранные.map(\.где)).
            Такое имя обход читает как литерал с `\\(`, то есть сверяет
            не то, что увидит человек в логе.
            """)

        // Чего не проверяет и проверить не может — вслух:
        //
        // · что имя СООТВЕТСТВУЕТ телу. Уникальное имя может врать
        //   о поведении ровно так же, как одинаковое, — это ловится
        //   только чтением. Сегодня такой случай был: «Отметки
        //   на прогулке превращаются в записи один к одному» записей
        //   не проверял вовсе;
        // · имена XCTest-методов (`func testX`) — у них нет литерала,
        //   и в эталоне их сегодня нет ни одного;
        // · совпадение имени теста с именем в эталоне: это дело
        //   `Tools/сверить_эталон.py`, и у него свой источник — бандл.
    }
}
