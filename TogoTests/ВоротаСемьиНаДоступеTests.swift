import Testing
import Foundation
@testable import Togo

/// Ворота семьи стоят на **составе общего доступа**, а не на карточках
/// этого телефона.
///
/// # Чем это оплачено (замер 29.10.2026)
///
/// ```
/// ProGate.isOpen(…)        3   FamilyScreen:199 (.familyBeyondTwo)
///                              DogSwitcher:205 · SettingsScreen:373
/// ShareLink(item: invite)  2   FamilyScreen:573 · SharedDiaryScreen:186
///                              ← ни одного ProGate
/// контроль: ShareLink(item:) в EmergencyScreen — 2, запрос жив
/// ```
///
/// Единственные ворота семьи стерегли `TGButton("Добавить человека")`,
/// а он заводит **локальную карточку** `FamilyMember`. Доступ к дневнику
/// выдаёт `CKShare` через системный лист «Поделиться», и `FamilyMember`
/// по обмену не ездит с 08.10.2026 (`SharedDiary.swift:78`) — значит
/// `members.count` у владельца **от вошедшего не растёт никогда**.
/// Бесплатный план пускал в дневник сколько угодно людей и просил денег
/// за третье имя в списке, которое никому ничего не открывает.
///
/// > **Ворота стояли на прокси, и прокси не двигался.** Зеркало нашего
/// > «погасшего прокси»: там сторож зелен при живом предмете, здесь
/// > ворота открыты при живом предмете — и по той же причине, ось
/// > не про предмет.
///
/// # Границы этого набора названы здесь, а не в чужой голове
///
/// * **Ворота на входе в лист не ограничивают число, которое в нём
///   назовут.** Лист «Поделиться» принимает нескольких получателей
///   за раз и о своём исходе не говорит ничем. Поэтому ворот мало,
///   и второй половиной стоит `ProGate.сверхПредела` — он называет
///   превышение, когда состав стал известен;
/// * сканер ниже стоит на **соседстве в файле**: раздача и ворота
///   в одном файле. Ворота в соседней ветке `if` он не отличит
///   от настоящих — ровно та же граница, что у
///   `ProGateTests.каждаяДверьСобакиЗаВоротами`;
/// * **что именно считать участником, он не решает.** Это решает
///   `FamilyShare.участники()`, и пустой список у него значит и «никого»,
///   и «спросить не удалось». Разбор — в `ProRequest.familyBeyondTwo(среди:)`.
@Suite("Ворота семьи стоят на составе общего доступа")
struct ВоротаСемьиНаДоступеTests {

    /// Участник общего доступа — ровно столько полей, сколько нужно
    /// воротам. Имя и роль здесь ни на что не влияют: ворота считают
    /// **головы**, и это их предмет.
    private static func участник(_ номер: Int, владелец: Bool = false) -> УчастникДневника {
        УчастникДневника(id: "id:_участник\(номер)",
                         ключНаряда: "_участник\(номер)",
                         подпись: "Участник \(номер)",
                         владелец: владелец,
                         я: false,
                         принял: true,
                         назначено: nil)
    }

    private static func состав(_ сколько: Int) -> [УчастникДневника] {
        guard сколько > 0 else { return [] }
        // Первый — владелец: `CKShare.participants` всегда содержит его
        // самого, и предел «двое ВКЛЮЧАЯ СЕБЯ» считает именно так.
        return (1...сколько).map { участник($0, владелец: $0 == 1) }
    }

    // MARK: Порог

    /// Таблица, а не отдельные тесты: так видно, что проверены **оба**
    /// края порога. Условие «не всех пускаем» выполняется и при нуле.
    @Test("Двое в общем доступе — бесплатно, третий за подписку")
    func порогПоСоставу() {
        let таблица: [(Int, Bool, Bool, String)] = [
            // участников в CKShare, подписка, ожидание, почему
            (0, false, true, "делиться ещё не начали — звать можно"),
            (1, false, true, "в дневнике только владелец — второго бесплатно"),
            (2, false, false, "двое уже есть, третий — за подписку"),
            (3, false, false, "и четвёртый"),
            (7, false, false, "и восьмой"),
            (2, true, true, "с подпиской сколько угодно"),
            (3, true, true, "и с тремя тоже"),
            (0, true, true, "подписка не зависит от состава"),
        ]

        // Проверка, что проверять было что, — первой. Пустая таблица
        // даёт зелёный набор, ничего не проверивший.
        #expect(таблица.count >= 8, "таблица порогов усохла: \(таблица.count)")

        for (сколько, isPro, ожидание, почему) in таблица {
            let запрос = ProRequest.familyBeyondTwo(среди: Self.состав(сколько))
            #expect(ProGate.isOpen(запрос, isPro: isPro) == ожидание, """
                состав из \(сколько) при isPro=\(isPro) должен быть \
                \(ожидание ? "ОТКРЫТ" : "закрыт"): \(почему).
                Предел — ProLimit.familyMembers=\(ProLimit.familyMembers), \
                и считается он по участникам CKShare, а не по карточкам \
                FamilyMember: карточки по обмену не ездят, и у владельца \
                их число от вошедшего не меняется вовсе.
                """)
        }
    }

    /// Фабрика считает **головы в общем доступе**, а не что-нибудь
    /// похожее.
    ///
    /// Стоит отдельно от таблицы выше нарочно: таблица проверяет порог,
    /// а это — что на вход порога приехало то самое число. Подделка
    /// «вернуть ноль вместо `участники.count`» краснит обе, и это верно;
    /// подделка «считать только принявших» краснит только эту.
    @Test("Фабрика берёт число участников доступа, а не что-то похожее")
    func фабрикаСчитаетГоловы() {
        // Непринявший — тоже участник: доступ ему уже выдан, он просто
        // ещё не открыл ссылку. Не считать его значило бы разрешить
        // позвать сколько угодно людей, пока никто не вошёл.
        let непринявший = УчастникДневника(id: "mail:мама@example.com", ключНаряда: nil,
                                           подпись: "мама@example.com", владелец: false,
                                           я: false, принял: false, назначено: nil)
        let двое = [Self.участник(1, владелец: true), непринявший]

        #expect(!ProGate.isOpen(.familyBeyondTwo(среди: двое), isPro: false), """
            приглашённый, который ещё не вошёл, не посчитан за участника.
            Тогда предел обходится так: позвать троих разом и не ждать,
            пока они откроют ссылку, — доступ им уже выдан.
            """)

        // Контроль: тот же список без второго человека ворота открывает.
        // Без него проверка выше зелена и у ворот, закрытых всегда.
        #expect(ProGate.isOpen(.familyBeyondTwo(среди: [Self.участник(1, владелец: true)]),
                               isPro: false),
                "ворота закрыты при одном участнике — второго человека зовут бесплатно")
    }

    // MARK: Превышение

    /// «Ворота закрыты» и «предел уже перейдён» — **разные** величины.
    ///
    /// Путать их дорого: на двоих ворота закрыты, а превышения нет,
    /// и сказать человеку «в дневнике лишние» было бы неправдой.
    @Test("Превышение считается отдельно от закрытых ворот")
    func превышениеОтдельноОтВорот() {
        let таблица: [(Int, Bool, Int, String)] = [
            (0, false, 0, "никого — превышать нечем"),
            (1, false, 0, "один"),
            (2, false, 0, "двое — это и есть бесплатный предел"),
            (3, false, 1, "третий сверх предела"),
            (5, false, 3, "и так далее"),
            (5, true, 0, "с подпиской предела нет"),
        ]
        #expect(таблица.count >= 6, "таблица превышения усохла: \(таблица.count)")

        for (сколько, isPro, ожидание, почему) in таблица {
            let было = ProGate.сверхПредела(Self.состав(сколько), isPro: isPro)
            #expect(было == ожидание, """
                состав \(сколько) при isPro=\(isPro): сверх предела \(было), \
                ожидалось \(ожидание) — \(почему).
                """)
        }

        // Пара, которой и различаются две величины. Поодиночке каждая
        // строка зелена и при их склейке.
        #expect(!ProGate.isOpen(.familyBeyondTwo(среди: Self.состав(2)), isPro: false)
                && ProGate.сверхПредела(Self.состав(2), isPro: false) == 0, """
                на двоих ворота обязаны быть закрыты, а превышение — нулевым.
                Склей эти две величины — и человек, у которого ровно двое,
                прочитает, что в его дневнике лишние люди.
                """)
    }

    // MARK: Сторож на раздачу, а не на правило

    /// У каждой раздачи `DiaryInvite` в том же файле стоят ворота
    /// `familyBeyondTwo(среди:)`.
    ///
    /// **Ось — `DiaryInvite`, а не `ShareLink`, и это замер.** `ShareLink`
    /// в `Togo/Features` зовут 18 раз, и 16 из них отдают ТЕКСТ —
    /// выгрузку, отчёт врачу, вопрос ситтеру. Требовать ворот от них
    /// значило бы продавать подписку за «Отправить вопрос врачу».
    /// Доступ к дневнику раздаёт ровно один тип — `DiaryInvite`
    /// (`SharedDiaryScreen.swift:381`), и он несёт `CKShare`.
    ///
    /// Подделка (29.10.2026): снять `ProGate.isOpen(.familyBeyondTwo(среди: состав)`
    /// из `FamilyScreen.inviteCard` — краснеет строкой
    /// «FamilyScreen.swift: раздач 1, ворот 0», соседи по набору зелёные.
    ///
    /// **Чего этот сторож не видит**, названо здесь:
    ///
    /// * соседство в файле — прокси для «раздача за воротами». Ворота
    ///   в соседней ветке `if` он засчитает;
    /// * переименуй `DiaryInvite` — и он ослепнет. Поэтому контроль
    ///   ниже требует **не меньше двух** найденных раздач: ослепший
    ///   сканер обязан краснеть, а не молчать;
    /// * второй контроль — файлы с `ShareLink` БЕЗ `DiaryInvite`.
    ///   Их должно быть много. Если их ноль, значит разбор берёт
    ///   не то, и «все раздачи за воротами» ничего не значит.
    @Test("Каждая раздача приглашения стоит за воротами familyBeyondTwo")
    func каждаяРаздачаЗаВоротами() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features")

        var раздачи: [String: Int] = [:]
        var ворота: [String: Int] = [:]
        var файловСТекстовойРаздачей = 0
        var файловОсмотрено = 0

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            файловОсмотрено += 1

            // **Проза отбрасывается до разбора.** Разбор этой дыры лежит
            // доккомментарием в `ProGate.swift` и в обоих экранах
            // и цитирует все три искомые строки разом. Сканер, читающий
            // прозу, посчитал бы объяснение за механизм — и был бы
            // зелёным ровно там, где дыру описали словами.
            let код = Self.безПрозы(текст)

            let раздач = код.components(separatedBy: "ShareLink(").count - 1
            guard раздач > 0 else { continue }
            guard код.contains("DiaryInvite") else {
                файловСТекстовойРаздачей += 1
                continue
            }
            раздачи[файл.lastPathComponent] = раздач
            ворота[файл.lastPathComponent] =
                код.components(separatedBy: "ProGate.isOpen(.familyBeyondTwo(среди:").count - 1
        }

        #expect(файловОсмотрено >= 60, """
            осмотрено файлов: \(файловОсмотрено) — обход не состоялся, \
            и тишина ниже ничего не значит.
            """)
        #expect(раздачи.count >= 2, """
            файлов, раздающих `DiaryInvite`, найдено \(раздачи.count), \
            а их два: «Семья» и «Общий дневник». Либо тип переименован, \
            либо раздачу убрали — сканер в обоих случаях ослеп, и молчать \
            ему нельзя.
            """)
        #expect(файловСТекстовойРаздачей >= 5, """
            файлов с `ShareLink` без `DiaryInvite` найдено \
            \(файловСТекстовойРаздачей) — на замер 29.10.2026 их восемь \
            (выгрузка, журнал, копия, отчёт врачу, порог, доза, скорая, \
            пересменка). Ноль значит, что разбор берёт не то, и «все \
            раздачи за воротами» ничего не доказывает: у сканера, который \
            не отличает раздачу доступа от раздачи текста, ось не про предмет.
            """)

        let беззащитные = раздачи.sorted { $0.key < $1.key }
            .compactMap { файл, сколько -> String? in
                let сторожей = ворота[файл] ?? 0
                return сторожей >= сколько ? nil : "\(файл): раздач \(сколько), ворот \(сторожей)"
            }
        #expect(беззащитные.isEmpty, """
            раздача доступа к дневнику идёт без ворот Pro: \(беззащитные).

            Звать надо фабрику — `ProGate.isOpen(.familyBeyondTwo(среди: состав), \
            isPro: store.isPro)`, а не писать `members.count` на месте: \
            локальная карточка `FamilyMember` по обмену не ездит \
            (`SharedDiary.swift:78`), и у владельца её число от вошедшего \
            не растёт никогда. «Семья больше двух человек» — вторая из двух \
            строк пейволла; раздача без ворот делает его украшением.
            """)
    }

    /// Доступ у живого человека **не отнимается автоматически**.
    ///
    /// Это сторож на решение, а не на код: превышение бесплатного
    /// предела лечится показом и выбором человека, а не молчаливым
    /// отзывом. То же решение этот проект уже принимал 28.09.2026
    /// (`SubscriptionStore.lostOnDowngrade`): понизить участника
    /// за чужую отмену подписки значит отнять отметку дозы у того,
    /// кто ею пользуется.
    ///
    /// Ось — **откуда зовут**, а не сколько раз: второй рычаг на том же
    /// экране законен, рычаг на любом другом — нет.
    @Test("Отзыв доступа зовут только с экрана, где его подтверждает человек")
    func отзывДоступаТолькоРукой() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo")

        var вызовы: [String: Int] = [:]
        var файловОсмотрено = 0

        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        while let файл = обход?.nextObject() as? URL {
            guard файл.pathExtension == "swift",
                  let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
            файловОсмотрено += 1
            let сколько = Self.безПрозы(текст)
                .components(separatedBy: "FamilyShare.убрать(").count - 1
            if сколько > 0 { вызовы[файл.lastPathComponent] = сколько }
        }

        #expect(файловОсмотрено >= 100, """
            осмотрено файлов: \(файловОсмотрено) — обход не состоялся.
            """)
        // Контроль: вызов вообще нашёлся. Ноль вызовов и «все вызовы
        // на своём месте» выглядят одинаково зелёными, а значат
        // противоположное — поимённого отзыва нет вовсе.
        #expect(!вызовы.isEmpty, """
            `FamilyShare.убрать(` не найден ни разу. Либо поимённый отзыв \
            доступа удалён (и тогда у владельца снова один всеобщий рычаг), \
            либо функцию переименовали и сканер ослеп.
            """)

        let чужие = вызовы.keys.filter { $0 != "УчастникиДневника.swift" }.sorted()
        #expect(чужие.isEmpty, """
            отзыв доступа зовут вне экрана «Доступ к дневнику»: \(чужие).

            Отнимать доступ у живого человека молча нельзя — ни за \
            превышение бесплатного предела, ни за отмену подписки. \
            Решение этого проекта от 28.09.2026: «понизить участника \
            до наблюдателя — это отнять право у ЖИВОГО человека за чужую \
            отмену подписки… двое из четверых перестанут отмечать дозы — \
            и узнают об этом в тот момент, когда собаке нужна таблетка». \
            Превышение называется словом (`ProGate.сверхПредела`), а кого \
            убрать, владелец выбирает сам и поимённо.
            """)
    }

    /// Текст без комментариев. Отдельной функцией, потому что оба
    /// сканера выше режут прозу одинаково, а две копии одного разбора
    /// разошлись бы молча — и разошлись бы в сторону ложной зелени.
    private static func безПрозы(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { строка -> String in
                guard let i = строка.range(of: "//") else { return строка }
                return String(строка[..<i.lowerBound])
            }
            .joined(separator: "\n")
    }
}
