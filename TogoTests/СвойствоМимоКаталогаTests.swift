import Foundation
import Testing

/// Русский литерал, присвоенный свойству получателя, в каталог не идёт.
///
/// **Класс, который не видит ни один из трёх соседних сторожей, и это
/// не их пробел, а их исключение.**
///
/// `LocalizationDebtTests` нарочно не считает долгом литерал без
/// интерполяции, который есть ключом в каталоге: он стоит в `Text("…")`,
/// и SwiftUI локализует его сам. Исключение верное — без него сторож
/// кричал бы на каждом втором экране. Но под него попадает и вот это:
///
/// ```swift
/// content.title = "Togo · утренняя сводка"   // UNMutableNotificationContent
/// event.note    = "Забор крови"              // запись в дневник
/// share[CKShare.SystemFieldKey.title] = "Дневник · \(dogName)"
/// ```
///
/// SwiftUI тут нет. Это присвоение `String`-свойству объекта, и каталог
/// по дороге не спрашивается ни разу. Ключ при этом в каталоге **есть
/// и переведён** — то есть сторож полноты всё это время честно отвечал
/// «переведено» про строку, которая до перевода не доезжает.
///
/// > Контрправило у нас уже записано — `FallbackLiteralTests` говорит
/// > «ключ в каталоге не признак перевода на экране». Применено оно
/// > было к одной форме из двух: к `??`, но не к `=`.
///
/// Второй слепой угол: `LocalizationDebtTests` ходит только
/// по `TogoShared`, а `Notifications.swift` лежит в `Togo/`.
///
/// ## Ось — от запрета, и запрет измерен на шум
///
/// Замер 13.10.2026 по двум осям на одном дереве:
///
/// ```
/// «кириллица в аргументе title:/body:/text:/label:»   812 находок — шум
/// «кириллица справа от = у получателя»                 43 находки
/// ```
///
/// Требование («есть ли нужное») узнаётся по десяти формам и даёт
/// почти все находки ложными; запрет («нет ли запретного») узнаётся
/// по одной. Сторож, который кричит восемьсот раз, читать перестанут,
/// а это хуже отсутствующего.
///
/// Из 43 находок 31 лежит в файлах целиком под `#if DEBUG` (витрины
/// компонентов), 5 — в `SeedData.swift` (демо-собака: «Стич» и «Мама»
/// человек задаёт сам, и перевод превратил бы их в `Stitch` и `Maman`
/// у того, кто сам назвал собаку — та же причина, по которой файл
/// исключён в `Tools/extract_texts.py`). Остаётся семь.
@Suite("Присвоение свойству мимо каталога")
struct СвойствоМимоКаталогаTests {

    /// Деревья обхода. Проверяются на существование **до** обхода.
    ///
    /// `FileManager.enumerator(at:)` по несуществующему пути отдаёт
    /// `nil`, и `guard … else { continue }` молчит. Ровно так
    /// `FallbackLiteralTests` четверо суток обходил каталог
    /// «TogoWidget», которого на диске нет: порог «сколько операторов
    /// нашлось всего» промах не ловил — его набирали вдвоём два
    /// оставшихся дерева. Ноль от инструмента неотличим от нуля
    /// про мир, пока не спросишь инструмент про него самого.
    private static let деревья = ["Togo", "TogoShared", "TogoWidgets"]

    /// Файлы, исключённые целиком, и причина у каждого.
    ///
    /// Исключение файлом ослепляет на всё, что в файле когда-либо
    /// появится, поэтому их ровно один и причина цитируется,
    /// а не пересказывается.
    private static let исключения = [
        "SeedData.swift": """
            демо-собака и демо-семья — это ДАННЫЕ, а не подписи. \
            Та же причина, что в Tools/extract_texts.py:34
            """,
    ]

    /// Долг по файлам, замер 13.10.2026. Число может только уменьшаться.
    ///
    /// Все четыре строки уже числятся в `LocalizationDebtTests.долг`.
    /// Двойной счёт здесь **нарочно**: та ось меряет «сколько русского
    /// в файле», эта — «присвоено ли оно получателю». Один адрес, два
    /// разных утверждения; погаснут они одной правкой, и каждый
    /// храповик затянется сам.
    private let долг: [String: Int] = [
        "CareMigration.swift": 2,
        "TreatmentCourse.swift": 1,
        "WalkRecorder.swift": 1,
    ]

    @Test("Русский литерал не присваивается свойству, которое увидит человек")
    func присвоенийМимоКаталогаНеБольше() throws {
        let (места, присвоенийВсего) = try Self.находки()

        // Порог по САМОЙ ФОРМЕ, а не по находкам: находки должны
        // стремиться к нулю, а присваивания в проекте останутся.
        // Сканер, переставший находить, молчит так же, как тот,
        // кому нечего сказать.
        //
        // Считается присваивание получателю С ЛЮБЫМ правым значением,
        // а не только с литералом. Первая редакция порога считала
        // `x.y = "…"` — то есть просела бы от СВОИХ ЖЕ починок:
        // каждая замена литерала на `String(localized:)` убирает
        // единицу из порога, и после сотни починок сторож объявил бы
        // «я ослеп» на здоровом дереве. Порог обязан не зависеть
        // от исхода работы, иначе он меряет нас, а не проект.
        #expect(присвоенийВсего >= 1_000, """
            присваиваний вида `x.y = …` найдено всего \(присвоенийВсего) \
            при 1309 на 13.10.2026. Сканер читает не те файлы или не те \
            строки — проверь обход, а не проект.
            """)

        var перебор: [String] = []
        for (файл, строки) in места.sorted(by: { $0.key < $1.key }) {
            let разрешено = долг[файл] ?? 0
            if строки.count > разрешено {
                перебор.append("""
                    \(файл): присвоений литералом \(строки.count) при долге \(разрешено)
                    \(строки.map { "      \($0)" }.joined(separator: "\n"))
                    """)
            }
        }

        #expect(перебор.isEmpty, """
            русский литерал присвоен свойству и в каталог не идёт:

            \(перебор.joined(separator: "\n"))

            Присвоение `String`-свойству каталог не спрашивает. Ключ \
            в каталоге тут не помогает: до него никто не идёт — ровно \
            это и случилось с заголовком утреннего пуша, у которого \
            перевод на fr лежал всё время.

            Лечится `String(localized: "…")` — ИЛИ пометкой \
            `// внутреннее: <причина>`, если строка человеку не видна. \
            Второе — не отговорка: причина проверяется длиной, \
            и «служебное» без замера ею не является. Был случай, когда \
            предписанное лечение внесло бы дефект (SharedDiarySeed:152, \
            слово уходит в имя ключа UserDefaults).

            Правку числа в долге считать починкой нельзя.
            """)

        // Закрытое обязано уйти из долга: запись, пережившая свои
        // строки, разрешает вернуть то, что уже починено.
        let протухшие = долг.keys
            .filter { (места[$0]?.count ?? 0) < (долг[$0] ?? 0) }
            .sorted()
        #expect(протухшие.isEmpty, """
            долг числит больше, чем в файле есть: \(протухшие).
            Затяни числа до измеренного — иначе в них можно дописать \
            новый дефект, и сторож останется зелёным.
            """)

        print("""
            ГРАНИЦА: этот сторож видит `получатель.свойство = "литерал"` \
            и `получатель[ключ] = "литерал"` на ОДНОЙ строке.
            Он НЕ видит: присвоение через переменную (`let s = "…"; x.y = s`); \
            значение, пришедшее из функции или перечисления; \
            `x.y = условие ? "а" : "б"`; и аргумент вызова \
            (`showFailure("…")` — там 44 места, и это отдельный класс, \
            его ось «аргумент» даёт 812 находок и требует другого сторожа).
            Ноль здесь — «этот один способ обойти каталог закрыт».
            """)
    }

    @Test("Разбор узнаёт обе формы присвоения и не считает чужое")
    func разборРазличаетФормы() {
        // Проверка самого разбора, а не его результата. Без неё
        // сканер мог бы перестать считать что-либо вовсе и был бы
        // зелёным — у нас это оплачено на `MIN_CONTRACTS`.
        #expect(Self.кириллицаСправаОтПрисвоения(#"content.title = "Сводка""#) == true)
        #expect(Self.кириллицаСправаОтПрисвоения(#"share[CKShare.SystemFieldKey.title] = "Дневник""#) == true)

        // Литерал, идущий через каталог, — не находка.
        #expect(Self.кириллицаСправаОтПрисвоения(#"content.title = String(localized: "Сводка")"#) == false)

        // Сравнение — не присвоение. `==` справа от имени выглядит
        // похоже, и разбор, не различающий их, покраснел бы на каждом
        // `if event.note == "…"`.
        #expect(Self.кириллицаСправаОтПрисвоения(#"if event.note == "Забор крови" {"#) == false)

        // Латиница справа — не предмет: ключи, идентификаторы, коды.
        #expect(Self.кириллицаСправаОтПрисвоения(#"content.threadIdentifier = "morningBrief""#) == false)

        // Голая переменная без получателя — не предмет: это локальная
        // строка, она ещё никуда не присвоена.
        #expect(Self.кириллицаСправаОтПрисвоения(#"let подпись = "Забор крови""#) == false)
    }

    // MARK: Разбор

    /// Есть ли справа от присвоения получателю кириллический литерал.
    ///
    /// Получатель — это `что-то.свойство` или `что-то[ключ]`: именно
    /// наличие получателя отличает «положил в объект, который потом
    /// покажут» от «завёл локальную строку».
    static func кириллицаСправаОтПрисвоения(_ строка: String) -> Bool {
        let код = строка.components(separatedBy: "//")[0]
        // `=`, но не `==`, `!=`, `>=`, `<=`: сравнение присвоением
        // не является, а выглядит так же.
        let образец = #"(?:\w+(?:\.\w+)+|\w+\[[^\]]+\])\s*(?<![=!<>])=(?!=)\s*""#
        guard let re = try? NSRegularExpression(pattern: образец),
              let m = re.firstMatch(in: код, range: NSRange(код.startIndex..., in: код)),
              let диапазон = Range(m.range, in: код)
        else { return false }
        // Через каталог — не находка. Проверяется по тексту ЛЕВЕЕ
        // литерала: `String(localized:` стоит между `=` и кавычкой.
        guard !код[..<диапазон.upperBound].contains("localized:") else { return false }
        let хвост = код[код.index(before: диапазон.upperBound)...]
        guard let литерал = Self.первыйЛитерал(String(хвост)) else { return false }
        return литерал.contains(where: { $0.isCyrillic })
    }

    /// Первый литерал строки целиком, с учётом экранированных кавычек.
    private static func первыйЛитерал(_ строка: String) -> String? {
        guard строка.first == "\"" else { return nil }
        var итог = ""
        var предыдущий: Character = " "
        for c in строка.dropFirst() {
            if c == "\"" && предыдущий != "\\" { return итог }
            итог.append(c)
            предыдущий = c
        }
        return nil
    }

    /// Файл → строки с находкой, и рядом — сколько присваиваний
    /// получателю найдено всего.
    ///
    /// Второе возвращается значением, а не копится в статической
    /// переменной: изменяемое статическое состояние в наборе — это
    /// и гонка под строгой проверкой, и зависимость результата
    /// от порядка тестов.
    private static func находки() throws -> (места: [String: [String]], присвоений: Int) {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var всего = 0
        var итог: [String: [String]] = [:]

        for дерево in деревья {
            let папка = корень.appendingPathComponent(дерево)
            #expect(FileManager.default.fileExists(atPath: папка.path), """
                каталога «\(дерево)» нет на диске — обход молча пропустил бы его целиком.
                Имя цели сменилось? Поправь список, а не порог.
                """)
            guard let обход = FileManager.default.enumerator(at: папка,
                                                             includingPropertiesForKeys: nil)
            else { continue }

            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                let имя = путь.lastPathComponent
                guard исключения[имя] == nil else { continue }
                let текст = try String(contentsOf: путь, encoding: .utf8)
                let строки = текст.components(separatedBy: .newlines)
                guard !файлПодDEBUG(строки) else { continue }

                for (номер, строка) in строки.enumerated() {
                    let обрезанная = строка.trimmingCharacters(in: .whitespaces)
                    if обрезанная.hasPrefix("//") { continue }

                    // Присваивание считается ДО пометки: порог меряет
                    // форму и обязан остаться независимым от того,
                    // сколько находок мы объяснили.
                    if присвоениеЕсть(строка) { всего += 1 }

                    // Пометка — та же, что у двух соседних сторожей,
                    // и РАЗБОР у неё тот же. Третьей формы пометки
                    // в проекте быть не должно: два независимых
                    // разбора одного правила расходятся молча.
                    if let причина = LocalizationDebtTests.пометкаВнутреннего(строка) {
                        #expect(причина.count >= 10, """
                            пометка «внутреннее» без причины в \(имя):\(номер + 1).
                            Исключение без причины через месяц неотличимо от дыры.
                            """)
                        continue
                    }

                    guard кириллицаСправаОтПрисвоения(строка) else { continue }
                    итог[имя, default: []].append("\(имя):\(номер + 1) — \(обрезанная.prefix(90))")
                }
            }
        }
        return (итог, всего)
    }

    /// Есть ли на строке присвоение получателю — без оглядки на то,
    /// что справа. Нужно только для порога «я ослеп», и именно поэтому
    /// правая часть не смотрится: порог, зависящий от того, литерал
    /// там или вызов каталога, падал бы от наших же починок.
    private static func присвоениеЕсть(_ строка: String) -> Bool {
        let код = строка.components(separatedBy: "//")[0]
        let образец = #"(?:\w+(?:\.\w+)+|\w+\[[^\]]+\])\s*(?<![=!<>])=(?!=)"#
        guard let re = try? NSRegularExpression(pattern: образец) else { return false }
        return re.firstMatch(in: код, range: NSRange(код.startIndex..., in: код)) != nil
    }

    /// Весь файл под `#if DEBUG` — признак **меримый**, а не на вкус:
    /// первая содержательная строка `#if DEBUG`, последняя `#endif`.
    ///
    /// Витрины компонентов (`WidgetGallery`, `MedicalRecordGallery`
    /// и ещё четыре) несут 31 находку из 43 и в сборку не идут:
    /// их текст читает тот, кто правит дизайн, а не хозяин собаки.
    private static func файлПодDEBUG(_ строки: [String]) -> Bool {
        let содержательные = строки
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty && !$0.hasPrefix("//") }
        return содержательные.first?.hasPrefix("#if DEBUG") == true
            && содержательные.last == "#endif"
    }
}
