    @Test("Портрет прогулки: круг обязан быть кругом и при вертикальном фото")
    func кругПрогулки() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 2) }
        let фото = try Self.сПриметами()
        let собака = Self.собакаСФото(фото)

        let обычный = try снять(WalkRing(dog: собака).padding(),
                                имя: "01-круг-прогулки-обычный",
                                кегль: Self.обычный, счёт: &счёт)
        try снять(WalkRing(dog: nil).padding(),
                  имя: "02-круг-прогулки-без-фото",
                  кегль: Self.обычный, счёт: &счёт)

        let рамка = try Self.рамкаНеполотна(обычный)
        let перекос = abs(рамка.ш - рамка.в)
        print("РАМКА ПОРТРЕТА: \(рамка.ш)×\(рамка.в) px, перекос \(перекос) px — круг выходит: \(перекос <= 4 ? "да" : "НЕТ")")

        // # ПЕРВЫЙ ВОПРОС — ЕСТЬ ЛИ ЧТО МЕРИТЬ, и только потом перекос
        //
        // Замер подделкой 26.10.2026. Снял `.aspectRatio(1, .fit)`
        // у `WalkRing` — портрет схлопнулся, и набор ответил:
        //
        // ```
        // РАМКА ПОРТРЕТА: 0×0 px, перекос 0 px — круг выходит: ДА
        // ✔ Test run with 7 tests in 1 suite passed · rc=0
        // ```
        //
        // То есть сторож не промолчал — он выдал **положительный**
        // вердикт на разрушенной вёрстке. `рамкаНеполотна` при пустом
        // кадре возвращает `(0, 0)`, а `abs(0 − 0) = 0`, и ноль лучше
        // любого порога сверху.
        //
        // > **Пустая картинка даёт идеальный результат по этой оси.
        // > Ноль и ноль различаются на ноль.**
        //
        // И следствие, которое дороже самой дыры: утверждение
        // `#expect(перекос <= 4)`, которое здесь собирались завести,
        // **прошло бы на подделке зелёным**. Починка закрыла бы
        // симптом и оставила предмет живым.
        //
        // > **Отсутствие предмета удовлетворяет порог СВЕРХУ
        // > и нарушает порог СНИЗУ.** Поэтому `>= N` самозащитно,
        // > а `<= N` по двум ИЗМЕРЕННЫМ величинам требует второго
        // > вопроса. Проверено по всем сторожам проекта: прочие
        // > меряют разность с константой либо порогом снизу — уязвим
        // > был только этот.
        #expect(рамка.ш > 0 && рамка.в > 0, """
            портрета на кадре НЕТ ВОВСЕ: рамка \(рамка.ш)×\(рамка.в).
            Это не «круг неровный» — это пустое полотно, на котором
            перекос равен нулю и любой порог сверху выполняется.
            Смотреть надо вёрстку `WalkRing`, а не допуск здесь.
            """)

        // # ЭТА ОСЬ НЕ ПРОВЕРЯЕТ `доляШирины`, И ЭТО ЗАМЕР
        //
        // Первая редакция обещала «портрет занимает не меньше четверти
        // ОКНА, `WalkRing` просит 0,46 ширины». **Обещание ложно.**
        // Подделка 26.10.2026: `доляШирины` 0,46 → 0,10 —
        //
        // ```
        // здоровый код   РАМКА 555×556 px
        // доля 0,10      РАМКА 555×556 px   ← ТА ЖЕ, ось не шелохнулась
        // ```
        //
        // `ImageRenderer` рисует вид **без контейнера прокрутки**,
        // а `containerRelativeFrame(.horizontal)` без контейнера
        // не применяется вовсе: размер задаёт `.aspectRatio(1, .fit)`
        // внутри родительской рамки `Self.ширина`. Подтверждено
        // встречной подделкой: снятие `aspectRatio` схлопывает кадр
        // в `0×0`, снятие доли — не меняет ничего.
        //
        // > **Кадр не воспроизводит ту геометрию, которую задаёт
        // > `containerRelativeFrame`.** Доля ширины окна этим стендом
        // > не проверяется ни одним тестом — и сторожа на неё нет.
        //
        // Утверждение ниже оставлено, но говорит теперь ТО, ЧТО МЕРИТ:
        // портрет занимает заметную часть СНИМКА. Оно ловит схлопывание
        // (подделка 1 даёт здесь 0 px при окне 804) и ничего не знает
        // про долю настоящего экрана.
        let снимок = try Self.пиксели(обычный).ш
        #expect(рамка.ш * 4 >= снимок, """
            портрет занимает \(рамка.ш) px при ширине СНИМКА \(снимок) —
            меньше четверти. Это защита от схлопывания, а НЕ проверка
            `доляШирины`: `containerRelativeFrame` в `ImageRenderer`
            не применяется, замер 26.10.2026.
            """)

        #expect(перекос <= 4, """
            круг не круг: рамка \(рамка.ш)×\(рамка.в), перекос
            \(перекос) px при допуске 4. Вертикальное фото растянуло
            портрет — проверять порядок `clipShape` и `aspectRatio`
            в `WalkRing`.
            """)
    }

