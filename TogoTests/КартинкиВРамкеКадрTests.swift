import Foundation
import SwiftData
import SwiftUI
import Testing
import UIKit
@testable import Togo

/// Помещается ли картинка в рамку, которую ей дали, — **кадром
/// с приметами**, а не однотонным снимком.
///
/// # Почему ни один прежний кадр этого увидеть не мог
///
/// У Togo четыре набора снимают фотографию (`ШапкаНаФотоTests`,
/// `ЧернилаНаФотоКадрTests`, `КиноВиджетКадрTests`, `ОстровКадрTests`),
/// и все четыре кладут в `dog.photo` **однотонный** снимок — нарочно
/// и по верному доводу: их предмет контраст, а узор дал бы разброс
/// фона внутри строки.
///
/// > **Однотонное фото обрезается в себя самого.** Срежь ему верх,
/// > низ, бока, переверни его или сделай из круга эллипс — кадр
/// > не изменится ни на пиксель. Вопрос «помещается ли» в стенде
/// > не задавал никто, и ответа на него не было ни зелёного,
/// > ни красного.
///
/// Здесь снимок **вертикальный и с приметами**: красная полоса сверху,
/// синяя снизу, зелёная слева, жёлтая справа, белое перекрестье
/// в центре. Срез любого края виден и глазом, и числом.
///
/// # КРУПНЫЙ КЕГЛЬ: `.dynamicTypeSize()` ОДНОГО НЕ ХВАТАЕТ, И ЭТО ЗАМЕР
///
/// Первая редакция снимала «обычный» и «AX» одним только модификатором
/// `.dynamicTypeSize(.accessibility3)`. Замер 25.10.2026:
///
/// ```
/// 03-шапка-обычный.png   91 874 Б   md5 281873e7…
/// 04-шапка-AX-XL.png     91 874 Б   md5 281873e7…   ПОБАЙТОВО ТО ЖЕ
/// 06-пустое-обычный.png  48 864 Б   md5 64c551e4…
/// 07-пустое-AX-XL.png    48 864 Б   md5 64c551e4…   ПОБАЙТОВО ТО ЖЕ
/// ```
///
/// Два кадра из двух совпали хешем — значит кегль не доехал вовсе.
/// Причина та же, что у контраста в `ШапкаНаФотоTests`: шрифты
/// разрешаются через `UIFont` по `UITraitCollection.current`,
/// а `ImageRenderer` окружение SwiftUI в признаки UIKit не переносит.
///
/// > **Поймал не глаз, а контроль:** «AX» выглядел правдоподобно сам
/// > по себе. Отличить «крупный кегль ничего не ломает» от «крупного
/// > кегля не было» можно только сравнением с обычным кадром, и это
/// > сравнение обязано быть в том же замере.
///
/// Поэтому ставятся **обе** половины и они отвечают на разные вопросы:
///
/// ```
/// preferredContentSizeCategory  чем разрешаются ШРИФТЫ (UIFont)
/// .dynamicTypeSize(…)           что читают ВИДЫ (@Environment),
///                               например число колонок сетки снимков
/// ```
///
/// # СТЕНДОВ ЗДЕСЬ ДВА, И ВЫБОР МЕЖДУ НИМИ — НЕ ВКУС (29.10.2026)
///
/// ```
/// снять        ImageRenderer. Отдаёт СОБСТВЕННЫЙ размер вида — им
///              и только им меряется высота шапки, ряда аватаров,
///              карточки. Контейнера не даёт
/// снятьВОкне   UIHostingController в UIWindow. Контейнер даёт,
///              но отдаёт размер ОКНА: собственного размера вид
///              здесь не сообщает вовсе
/// ```
///
/// Переводить набор целиком на окно **нельзя**: четыре теста меряют
/// ровно собственную высоту вида (`а.size.height == г.size.height`),
/// и в окне эти высоты сравнялись бы сами — сторож погас бы зелёным.
/// Замер обоих путей с контролями — в голове `снятьВОкне`.
///
/// # Чего этот набор НЕ доказывает
///
/// 1. **Что так выйдет на устройстве.** Ни один из двух стендов —
///    не телефон: `ImageRenderer` рисует материал
///    (`.ultraThinMaterial`) не так, как система, безопасных зон
///    и тулбара не знает вовсе; окно геометрию знает, но безопасную
///    зону у него снимают нарочно (`safeAreaRegions = []`), иначе
///    в замер уезжает вырез того симулятора, который достался
///    сессии, — разбор и числа в голове `снятьВОкне`.
/// 2. **Как выглядит ЧУЖАЯ фотография.** Снимок синтетический.
///    Он отвечает на «куда делись края», а не на «красиво ли вышло».
/// 3. **Состояние `BackgroundScreen.окно`** — вид приватный, а экран,
///    который его строит, `ImageRenderer` не рисует вовсе: замер
///    25.10.2026 отдал кадр 402 × 760 с единственным знаком запрета
///    на жёлтом — заглушкой SwiftUI «этот вид отрисовать нельзя»
///    (в экране живёт `PhotosPicker`). Кадр при этом СОСТОЯЛСЯ:
///    файл записан, счёт напечатан, прогон зелёный.
///
///    > **Отказ отрисовки приходит в виде кадра.** Отличить «нарисовал»
///    > от «нарисовал заглушку» можно только посмотрев на картинку;
///    > ни `nil`, ни красного теста при этом нет. Тест снят, потому что
///    > кадр-заглушка хуже отсутствия кадра: он выглядит приёмкой.
///
///    Поэтому цепочка модификаторов проверяется повтором
///    (`порядокОверлеяИРамки`), и повтор назван повтором.
@MainActor
@Suite("Картинка в рамке: что срезалось")
struct КартинкиВРамкеКадрTests {

    /// iPhone 16 Pro. Число стенда, а не продукта.
    private static let ширина: CGFloat = 402

    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень
            .appendingPathComponent("build/кадры-картинки-в-рамке")
    }

    /// Счёт печатается всегда, в том числе после падения.
    private func печатьСчёта(_ имена: [String], ожидалось: Int) {
        print("КАДРОВ СНЯТО: \(имена.count) из \(ожидалось) · \(имена.joined(separator: ", "))")
    }

    // MARK: - Снимок с приметами

    /// Четыре края четырёх цветов плюс перекрестье. Вертикальный 3 : 4 —
    /// то же отношение, что у снимка с телефона в портрет.
    private static func сПриметами(ширина: CGFloat = 600,
                                   высота: CGFloat = 800) throws -> Data {
        let размер = CGSize(width: ширина, height: высота)
        let полоса = ширина * 0.12
        let формат = UIGraphicsImageRendererFormat.default()
        формат.scale = 1          // иначе помощник врёт о своём размере
        let картинка = UIGraphicsImageRenderer(size: размер, format: формат).image { ctx in
            UIColor(white: 0.5, alpha: 1).setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
            UIColor.red.setFill()
            ctx.fill(CGRect(x: 0, y: 0, width: ширина, height: полоса))
            UIColor.blue.setFill()
            ctx.fill(CGRect(x: 0, y: высота - полоса, width: ширина, height: полоса))
            UIColor.green.setFill()
            ctx.fill(CGRect(x: 0, y: 0, width: полоса, height: высота))
            UIColor.yellow.setFill()
            ctx.fill(CGRect(x: ширина - полоса, y: 0, width: полоса, height: высота))
            UIColor.white.setFill()
            ctx.fill(CGRect(x: ширина / 2 - 4, y: 0, width: 8, height: высота))
            ctx.fill(CGRect(x: 0, y: высота / 2 - 4, width: ширина, height: 8))
        }
        return try #require(картинка.pngData(), "снимок с приметами не стал PNG")
    }

    /// Обе половины крупного кегля — см. разбор в голове набора.
    private static func признаки(_ кегль: UIContentSizeCategory) -> UITraitCollection {
        UITraitCollection(traitsFrom: [
            UITraitCollection(userInterfaceStyle: .dark),
            UITraitCollection(preferredContentSizeCategory: кегль),
        ])
    }

    private static let обычный: (UIContentSizeCategory, DynamicTypeSize) = (.large, .large)
    private static let крупный: (UIContentSizeCategory, DynamicTypeSize) =
        (.accessibilityExtraLarge, .accessibility3)

    @discardableResult
    private func снять(_ вид: some View, имя: String,
                       кегль: (UIContentSizeCategory, DynamicTypeSize),
                       высота: CGFloat? = nil,
                       счёт: inout [String]) throws -> UIImage {
        var нарисованное: UIImage?
        Self.признаки(кегль.0).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, .dark)
                    .dynamicTypeSize(кегль.1)
                    .frame(width: Self.ширина, height: высота)
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }
        let картинка = try #require(нарисованное, "ImageRenderer не отдал «\(имя)»")
        let данные = try #require(картинка.pngData(), "«\(имя)» не стал PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        try данные.write(to: Self.каталог.appendingPathComponent("\(имя).png"))
        счёт.append(имя)
        print("КАДР: \(имя).png · \(Int(картинка.size.width))×\(Int(картинка.size.height)) pt · \(данные.count) байт · md5 \(Self.отпечаток(данные))")
        return картинка
    }

    /// Снимок **в настоящем окне**: `UIHostingController` в `UIWindow`.
    ///
    /// # Зачем второй стенд, когда есть `снять`
    ///
    /// `ImageRenderer` рисует вид **без контейнера**, и всё, что считает
    /// размер от контейнера (`containerRelativeFrame`), получает ноль.
    /// `UIHostingController` в окне контейнер даёт по устройству.
    /// Замер 29.10.2026, оба пути в одном прогоне, `WalkRing` и контроль
    /// `Circle().frame(200)` рядом:
    ///
    /// ```
    /// ОТРИСОВЩИК  WalkRing.padding()              рамка 0×0 px,   иных 0
    /// ОТРИСОВЩИК  ScrollView{WalkRing} 402×402    рамка 0×0 px,   иных 0
    /// ОТРИСОВЩИК  КОНТРОЛЬ Circle 200             рамка 400×400,  иных 126 168
    /// ОКНО        WalkRing 402×402                рамка 370×370,  иных 86 632
    /// ОКНО        КОНТРОЛЬ Circle 200             рамка 400×400,  иных 126 230
    /// ОКНО        ОТРИЦАТЕЛЬНЫЙ Color.clear       рамка 0×0 px,   иных 0
    /// ОКНО        WalkRing в окне 402×740         рамка 370×370  ← высота окна
    ///                                                              сторону не меняет
    /// ```
    ///
    /// Контроль стоит в **обоих** каналах нарочно: ноль у отрисовщика при
    /// живом контроле значит «предмета нет там, куда смотрю», а не «стенд
    /// умер». А отрицательный контроль окна (`Color.clear` → `0×0`)
    /// отвечает на встречный вопрос: окно не рисует квадрат само по себе,
    /// 370 px пришли от предмета. 370 px = 185 pt = 0,46 × 402 — ровно
    /// `WalkRing.доляШирины`.
    ///
    /// # Чем этот стенд НЕ заменяет `снять`, и это не вкус
    ///
    /// ```
    /// ImageRenderer   отдаёт СОБСТВЕННЫЙ размер вида — им меряют высоту
    ///                 шапки, ряда аватаров, карточки
    /// окно            отдаёт размер ОКНА — своего размера вид здесь
    ///                 не сообщает вовсе
    /// ```
    ///
    /// Четыре теста набора меряют именно собственную высоту вида
    /// (`а.size.height == г.size.height`), и в окне эта ось исчезает:
    /// высоты сравнялись бы сами, потому что обе равны окну. Поэтому
    /// стенда два, и каждый отвечает на свой вопрос.
    ///
    /// # ЧЕМ СНИМАТЬ: `layer.render`, а НЕ `drawHierarchy` — и это
    /// # оплачено упавшим прогоном, а не вкусом
    ///
    /// Первая редакция снимала `drawHierarchy(afterScreenUpdates: true)`
    /// по окну, которому перед этим делали `makeKeyAndVisible()`,
    /// и возвращала ключевое окно прежнему владельцу после снимка.
    /// **На отдельном прогоне набора это зелено, на полном — убивает
    /// процесс.** Замер 29.10.2026:
    ///
    /// ```
    /// -only-testing:КартинкиВРамкеКадрTests   8 тестов, passed, rc=0
    /// make unit (весь набор)                  21 тест из 800, падение
    ///                                         процесса ровно на разборе
    ///                                         моих же хостов, перезапуск,
    ///                                         «СВЕРЯТЬ НЕЧЕМ»
    /// ```
    ///
    /// Механика правдоподобна и названа правдоподобной: Swift Testing
    /// гоняет наборы **параллельно**, прогон идёт в хосте-приложении
    /// с живым окном, и забирать у него ключевое окно посреди чужих
    /// тестов — не то же самое, что делать это в одиночку.
    ///
    /// > **Зелёный на своём наборе ничего не сказал про прогон.**
    /// > Стенд, проверенный в одиночку, проверен в условиях, которых
    /// > в приёмке не бывает: там он живёт среди восьмисот соседей.
    ///
    /// `layer.render(in:)` ключевого окна не трогает вовсе. Разница
    /// в кадре измерена и ничтожна — 86 364 против 86 632 пикселей
    /// иных чем фон (0,3 %, сглаживание краёв). **Граница у него своя
    /// и настоящая:** `layer.render` не рисует `UIVisualEffectView`,
    /// то есть `.ultraThinMaterial` и стекло на таком кадре пропадут.
    /// Для `WalkRing` материала нет; тому, кто принесёт сюда стеклянный
    /// вид, это придётся перемерить.
    ///
    /// # БЕЗОПАСНАЯ ЗОНА ОКНА НЕ НУЛЕВАЯ, И ЕЁ СНИМАЮТ НАРОЧНО
    ///
    /// Первая редакция этого стенда считала её нулём — окно живёт без
    /// сцены, откуда бы ей взяться. Замер 29.10.2026 сказал обратное:
    /// метка под кругом легла на `494 px` вместо названных заранее
    /// `370`, то есть над кругом нашлось `124 px` = `62 pt` пустоты.
    ///
    /// ```
    /// без safeAreaRegions = []   метка на 494 px, над кругом 62 pt
    /// с  safeAreaRegions = []    метка на 370 px — ровно ширина круга
    /// хост.view.safeAreaInsets   верх 54 pt, низ 0, лево 0
    ///                            И ТАК ЖЕ ОТВЕЧАЕТ ПОСЛЕ СНЯТИЯ:
    ///                            значение UIKit за настройкой SwiftUI
    ///                            не следует и различителем не годится
    /// ```
    ///
    /// **Установлено:** строка `safeAreaRegions = []` сдвиг убирает
    /// целиком. **Не установлено:** откуда взялись 62 pt при вставке
    /// 54 pt — восемь точек разницы не объяснены, и домысливать им
    /// причину здесь не буду: объяснение, придуманное к верному замеру,
    /// наследует его достоверность и не имеет своей.
    ///
    /// > **Число, которого я не ждал, и оказалось оно не про предмет,
    /// > а про стенд.** Ошибись я в другую сторону — поправил бы допуск
    /// > и записал бы вырез чужого симулятора в свойства `WalkRing`.
    ///
    /// Вставка приходит от устройства симулятора, то есть **стенд
    /// зависел бы от того, какое устройство досталось сессии**,
    /// а `TOGO_SIM` раздаёт их по имени сессии.
    ///
    /// # КЕГЛЬ ЧЕРЕЗ ОКНО НЕ ДОЕЗЖАЕТ ТОЖЕ — замер, а не предположение
    ///
    /// Голова набора объясняет неподвижность кегля тем, что
    /// `ImageRenderer` не переносит окружение SwiftUI в признаки UIKit.
    /// Окно признаки UIKit несёт по устройству — значит через него
    /// кегль был обязан доехать. Замер 29.10.2026, та же строка
    /// `AppFont.cardTitle` в окне, четыре прогона:
    ///
    /// ```
    /// обычный, с traitOverrides     рамка 129×37 px, иных 2026
    /// крупный, с traitOverrides     рамка 129×37 px, иных 2026
    /// обычный, БЕЗ traitOverrides   рамка 129×37 px, иных 2026
    /// крупный, БЕЗ traitOverrides   рамка 129×37 px, иных 2026
    /// ```
    ///
    /// Четыре из четырёх совпали. **Механизм не установлен, и это
    /// пишется прямо, а не заменяется похожей причиной.** Правдоподобный
    /// кандидат — `TextStyleToken.font` считает `UIFontMetrics` в момент
    /// ПОСТРОЕНИЯ значения вида, а оно строится до `performAsCurrent`
    /// и до окна, — но **он не проверен ни одним замером**, и объяснение,
    /// придуманное к верному замеру, своей достоверности не имеет.
    ///
    /// Что отсюда следует для этого стенда: `traitOverrides` стоит,
    /// потому что признаки окна иначе не наши вовсе (схема, контраст),
    /// а **обещания про кегль он не даёт**. Тесту `кругПрогулки` это
    /// безразлично — он снимает только `Self.обычный`.
    ///
    /// `performAsCurrent` оставлен (токены — динамические `UIColor`,
    /// разрешаются по `UITraitCollection.current`), и к нему добавлены
    /// признаки самого окна: без них у UIKit-иерархии свои traits,
    /// а не наши.
    @discardableResult
    private func снятьВОкне(_ вид: some View, имя: String,
                            кегль: (UIContentSizeCategory, DynamicTypeSize),
                            размер: CGSize,
                            счёт: inout [String]) throws -> UIImage {
        var нарисованное: UIImage?
        Self.признаки(кегль.0).performAsCurrent {
            let хост = UIHostingController(rootView: вид
                .environment(\.colorScheme, .dark)
                .dynamicTypeSize(кегль.1))
            хост.view.frame = CGRect(origin: .zero, size: размер)
            // Полотно чёрное — то же, от которого считает `рамкаНеполотна`.
            хост.view.backgroundColor = .black
            хост.overrideUserInterfaceStyle = .dark
            хост.traitOverrides.preferredContentSizeCategory = кегль.0
            // Безопасная зона — вставка ЧУЖОГО телефона, см. разбор выше.
            // Без этой строки стенд меряет вырез симулятора заодно
            // с предметом и даёт разные числа на разных устройствах.
            хост.safeAreaRegions = []

            // КЛЮЧЕВОЕ ОКНО НЕ ТРОГАЕМ — см. разбор «ЧЕМ СНИМАТЬ» выше.
            let окно = UIWindow(frame: хост.view.frame)
            окно.overrideUserInterfaceStyle = .dark
            окно.rootViewController = хост
            окно.isHidden = false
            окно.layoutIfNeeded()
            хост.view.setNeedsLayout()
            хост.view.layoutIfNeeded()

            let формат = UIGraphicsImageRendererFormat.default()
            формат.scale = 2
            нарисованное = UIGraphicsImageRenderer(size: размер, format: формат).image { ctx in
                хост.view.layer.render(in: ctx.cgContext)
            }
            окно.isHidden = true
        }
        let картинка = try #require(нарисованное, "окно не отдало «\(имя)»")
        let данные = try #require(картинка.pngData(), "«\(имя)» не стал PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        try данные.write(to: Self.каталог.appendingPathComponent("\(имя).png"))
        счёт.append(имя)
        print("КАДР: \(имя).png · ОКНО \(Int(картинка.size.width))×\(Int(картинка.size.height)) pt · \(данные.count) байт · md5 \(Self.отпечаток(данные))")
        return картинка
    }

    /// Дешёвый отпечаток: два кадра одного вида, совпавшие по нему,
    /// значат, что различитель не сработал.
    private static func отпечаток(_ данные: Data) -> String {
        var хеш: UInt64 = 1469598103934665603
        for байт in данные {
            хеш = (хеш ^ UInt64(байт)) &* 1099511628211
