import Testing
import Foundation
@testable import Togo

/// Лента обязана дорожать ЛИНЕЙНО, а не квадратично.
///
/// # Почему это сторож, а не замер — в отличие от соседа
///
/// `ЦенаПроходовЗамер` печатает миллисекунды и никого не держит:
/// порог абсолютного времени на общей машине меряет занятость
/// соседей, а не код. Здесь ось другая — **отношение** двух замеров
/// на одних и тех же условиях:
///
/// ```
/// вчетверо больше записей, цена линейная     ×4
/// вчетверо больше записей, цена квадратичная ×16
/// ```
///
/// Занятость машины умножает ОБА замера одинаково и из отношения
/// сокращается. Поэтому порог здесь устойчив там, где порог времени
/// был бы ложной тревогой.
///
/// # Что оплатило этого сторожа
///
/// 28.10.2026, жалоба «скролл тормозит». В `TimelineBuilder.blocks`
/// нашлись ДВЕ квадратичности подряд:
///
/// ```
/// до починок                903 мс на 2100 записях
/// после первой              477 мс   ← вторая осталась в той же функции
/// после второй               17 мс
/// бюджет кадра при 60 к/с    16 мс
/// ```
///
/// > Починив одну квадратичность, легко доложить «ускорено вдвое»
/// > и не заметить вторую рядом. Этот сторож краснеет на обеих.
///
/// # Данные обязаны содержать ПРОГУЛКИ
///
/// Первая редакция замера не заводила ни одной `.walk` — и весь
/// дорогой код не выполнялся вовсе, честно печатая семь миллисекунд.
/// Поэтому здесь прогулки есть, и это проверяется первым
/// утверждением: замер на данных без предмета даёт верное число
/// и ложный вывод.
@Suite("Цена ленты растёт линейно")
@MainActor
struct РостЦеныЛентыTests {

    /// Дневник той формы, в которой его ведёт человек: выход,
    /// переросший в прогулку, и отметка внутри неё.
    private func дневник(_ сколько: Int) -> [LogEvent] {
        let начало = Date().addingTimeInterval(-Double(сколько) * 3_700)
        var записи: [LogEvent] = []
        записи.reserveCapacity(сколько * 2)
        for i in 0..<сколько {
            let когда = начало.addingTimeInterval(Double(i) * 3_700)
            if i % 2 == 0 {
                записи.append(LogEvent(kind: .outing, date: когда, authorName: "В"))
                let прогулка = LogEvent(kind: .walk,
                                        date: когда.addingTimeInterval(180),
                                        authorName: "В")
                записи.append(прогулка)
                let отметка = LogEvent(kind: .outing,
                                       date: когда.addingTimeInterval(300),
                                       authorName: "В")
                отметка.outcome = .urine
                отметка.walkEventID = прогулка.id
                записи.append(отметка)
            } else {
                записи.append(LogEvent(kind: .meal, date: когда, authorName: "В"))
            }
        }
        return записи
    }

    private func секунды(_ работа: () -> Void) -> Double {
        let старт = Date()
        работа()
        return Date().timeIntervalSince(старт)
    }

    @Test("Вчетверо больше записей — не больше чем вшестеро дороже")
    func ростЛинейный() {
        let малый = дневник(250)
        let большой = дневник(1000)

        // КОНТРОЛЬ ПЕРВЫМ: есть ли в данных то, что меряем.
        // Без прогулок дорогой код не выполняется вовсе, и сторож
        // зеленеет на пустом месте.
        let прогулок = большой.filter { $0.kind == .walk }.count
        #expect(прогулок > 100, """
            в данных \(прогулок) прогулок — мерить нечего.
            Весь дорогой код `blocks` перебирает именно прогулки;
            на дневнике без них он не выполняется ни разу
            и печатает честное маленькое число.
            """)
        #expect(большой.count > малый.count * 3, "наборы не различаются по объёму")

        // Прогрев: первый вызов платит за ленивую инициализацию
        // SwiftData-акцессоров, и без него отношение считает её,
        // а не рост сложности.
        _ = TimelineBuilder.blocks(малый)
        _ = TimelineBuilder.blocks(большой)

        let наМалом = секунды { _ = TimelineBuilder.blocks(малый) }
        let наБольшом = секунды { _ = TimelineBuilder.blocks(большой) }

        // Защита от деления на ноль: на быстрой машине малый замер
        // может уложиться в разрешение таймера.
        guard наМалом > 0.0005 else {
            print("РОСТ ЛЕНТЫ: малый замер \(Int(наМалом * 1_000_000)) мкс — "
                  + "ниже разрешения, отношение не считается")
            return
        }

        let отношение = наБольшом / наМалом
        print("""
            РОСТ ЦЕНЫ ЛЕНТЫ
              250 записей:  \(Int(наМалом * 1000)) мс
              1000 записей: \(Int(наБольшом * 1000)) мс
              отношение:    \(String(format: "%.1f", отношение)) (линейно ≈ 4, квадратично ≈ 16)
            """)

        // Порог шесть, а не четыре: между линейным ростом и квадратичным
        // лежит пропасть (4 против 16), и запас в полтора раза покрывает
        // накладные расходы, не пропуская настоящую квадратичность.
        #expect(отношение < 6, """
            лента дорожает быстрее, чем линейно: вчетверо больше записей
            дали рост в \(String(format: "%.1f", отношение)) раз.

            Так выглядит поиск по всей коллекции ВНУТРИ цикла по ней же.
            Дважды это уже находили в `TimelineBuilder.blocks` —
            `outingsThatBecameWalks` и `openings.values.contains` —
            и стоило это 903 мс на кадр при бюджете 16.

            Ищи линейный поиск (`first`, `last`, `contains`, `filter`)
            внутри `for`/`map` по той же коллекции.
            """)
    }
}
