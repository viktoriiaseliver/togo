@testable import Togo

/// Экран, кнопка или вкладка, названные адресом, существуют.
///
/// Сторож `QuotedNamesTests` сверяет цитату между языками: если русский
/// цитирует ключ каталога, перевод обязан цитировать перевод того же
/// ключа. Но он **согласует стороны, а не проверяет мир**: если русский
/// текст зовёт к кнопке, которой нет, а перевод зовёт к ней же, обе
/// стороны сойдутся и обе будут неправы.
///
/// Здесь проверяется вторая половина: **есть ли то, на что мы
/// показываем**. Замер 23.09.2026 нашёл одно место: экран «Вид ситтера»
/// писал «Кнопка „Написать владельцу" ведёт сразу в мессенджер» —
/// такой кнопки в приложении нет вовсе. Связь с хозяином на самом деле
/// живёт строкой «Если что» в брифинге, которую он заполняет сам.
///
/// **Почему правило узкое.** Первая редакция проверяла все цитаты
/// подряд и дала 61 «находку»: «дано», «просится», «не ел» — это
/// выделение голосом, а не адрес; «Настройки → собака → Питание
/// и режим» — путь; «%@» — подстановка. Сторож, кричащий в шестидесяти
/// одном месте из ничего, не сторож: после третьего ложного
/// срабатывания в него перестают смотреть, и **ложная тревога
/// становится дороже пропуска**.
///
/// Поэтому проверяется только то, что названо адресом прямо: перед
/// кавычками стоит «экран», «вкладка», «кнопка» или «раздел».
/// Таких цитат девятнадцать.
@Suite("То, на что показывают, существует")
struct AddressedQuotesTests {

    /// Имена, которых в нашем коде нет и быть не может: это чужой
    /// интерфейс. Список короткий и с причиной у каждого.
    private static let чужие: [String: String] = [
        "Действие": "аппаратная кнопка iPhone, её имя задаёт iOS",
        "Автоматизация": "вкладка в приложении «Команды» Apple",
    ]

    // «Данные и приватность» здесь стояло и убрано сразу: проверка
    // «исключение существует в текстах» показала, что адресной цитаты
    // с этим именем нет вовсе — оно встречается только внутри пути
    // «Настройки → Данные и приватность», а путь узкое правило
    // не ловит. Исключение, закрывающее то, чего нет, — это лишняя
    // дыра, про которую никто не помнит.

    private func исходники() -> [String] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo")
        let обход = FileManager.default.enumerator(at: корень, includingPropertiesForKeys: nil)
        var тексты: [String] = []
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
            тексты.append(текст)
        }
        return тексты
    }

    /// Подписи по видам, а не в одну кучу.
    ///
    /// **Первая редакция складывала всё подряд, включая `Text("…")`,
    /// и была почти беззубой.** Проверено подделкой: переименовал
    /// кнопку «Еда», на которую текст показывает прямо, — сторож
    /// промолчал, потому что слово «Еда» встречается в приложении
    /// ещё десятком мест как обычная надпись. Ловил он тогда ровно
    /// один случай: имя, которого нет **нигде вообще**.
    ///
    /// Теперь вид сверяется с видом: кнопку ищем среди кнопок, экран —
    /// среди заголовков, вкладку — среди вкладок. Мимо из пятнадцати
    /// адресных цитат проходят две, и обе — чужой интерфейс.
    ///
    /// **`BigAction` добавлен 23.10.2026 по красному прогону, и это
    /// была слепая зона, а не регрессия.** Сторож сказал «кнопка
    /// „Гулять" ← кнопка „Гулять"», то есть «текст зовёт к тому, чего
    /// в приложении нет». Кнопка при этом на месте с первого коммита
    /// проекта: `ActionGrid.swift:62`, `BigAction(title: "Гулять",
    /// systemImage: "figure.walk", isPrimary: false)`. Образца
    /// на `BigAction` в списке не было ни одного, а `SmallAction`
    /// был — пара разошлась молча. Покраснело это только 22.10, когда
    /// слияние пяти языков хендоффа (`f7f938d`) завезло в каталог ключ
    /// «кнопка «Гулять»»: до него адресной цитаты на эту кнопку
    /// не существовало, и дыру нечем было нащупать.
    ///
    /// > **Ложный красный здесь опаснее пропуска:** он обвиняет
    /// > живую кнопку и зовёт её переименовать. Чинится перечень
    /// > образцов, а не текст и не кнопка.
    /// **`BigAction` и `SmallAction` сняты 25.10.2026: их больше нет
    /// в проекте.** `ActionGrid` удалён как экран-сирота `17b415b`
    /// (24.10.2026), и вместе с ним ушли оба конструктора. Замер в ту же
    /// секунду, одним инструментом:
    ///
    /// ```
    /// struct|class|func BigAction|SmallAction   объявлений НЕТ
    /// struct TGButton                           TGButton.swift:8   ← КОНТРОЛЬ
    /// ```
    ///
    /// Упоминания, которые остались, — проза в комментариях
    /// (`MarkFill.swift:25`, `:80`), а не код.
    ///
    /// Взамен заведены две живые формы, и обе нашлись по красному
    /// прогону 25.10.2026:
    ///
    /// ```
    /// название: "…"   TodayBottomBar.Действие, 7 мест. Имя типа
    ///                 съедено выводом (`.init(название:)`) — цепляться
    ///                 не за что, кроме имени ПАРАМЕТРА
    /// строка("…")     локальный помощник RecordSheet, 4 места,
    ///                 и все четыре — обёртка над Button
    /// ```
    private static let образцыКнопок: [String] = [
        #"TGButton\(title: "([^"]+)""#,
        #"Button\("([^"]+)""#,
        #"TGCloseButton\(title: "([^"]+)""#,
        #"TGListRow\(title: "([^"]+)""#,
        #"NavigationLink\("([^"]+)""#,
        #"\.confirmationDialog\("([^"]+)""#,
        #"Label\("([^"]+)""#,
        #"название: "([^"]+)""#,
        #"строка\("([^"]+)""#,
    ]

    private static let образцыЭкранов: [String] = [
        #"navigationTitle\("([^"]+)"\)"#,
        #"TGSheet\(title: "([^"]+)""#,
        #"TGScreen\(title: "([^"]+)""#,
    ]

    private static let образцыВкладок: [String] = [#"tabItem\s*\{[^}]*?"([^"]+)""#]

    /// Подписи, которые кнопка берёт у ПЕРЕЧИСЛЕНИЯ, а не у литерала.
    ///
    /// **Третья слепая зона этого сторожа, и найдена она тем же
    /// способом, что две прежние, — красным прогоном 28.10.2026:**
    /// «кнопка «Еда» ← текста нет в приложении». Кнопка «Еда» есть
    /// у человека на главном экране с первого дня; её подпись —
    /// `LogKind.meal.title`, то есть `case .meal: String(localized:
    /// "Еда")` в `TogoShared/Models/Enums.swift`.
    ///
    /// Два промаха сразу, и каждого поодиночке хватило бы:
    ///
    /// ```
    /// исходники()        читают ТОЛЬКО каталог Togo; Enums.swift
    ///                    лежит в TogoShared и не читался вовсе
    /// образцы кнопок     ищут литерал ВНУТРИ вызова (TGButton(title:…),
    ///                    Button("…")); подпись из перечисления
    ///                    не лежит рядом ни с одним вызовом
    /// ```
    ///
    /// > Ложный красный здесь опаснее пропуска: он обвиняет живую
    /// > кнопку и зовёт переименовать её под сторожа. Чинится
    /// > перечень источников, а не текст и не кнопка.
    ///
    /// Читается ТОЛЬКО `TogoShared/Models/Enums*.swift`, а не весь
    /// общий слой: там и живут подписи видов, а широкий захват набрал
    /// бы в кнопки всякую строку домена и ослабил бы сторожа молча.
    private func подписиПеречислений() throws -> Set<String> {
        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models")
        let обход = FileManager.default.enumerator(at: каталог, includingPropertiesForKeys: nil)
        let re = try NSRegularExpression(
            pattern: #"case\s+\.\w+(?:,\s*\.\w+)*:\s*String\(localized:\s*"([^"]+)""#)
        var найдено: Set<String> = []
        while let элемент = обход?.nextObject() as? URL {
            guard элемент.lastPathComponent.hasPrefix("Enums"),
                  элемент.pathExtension == "swift",
                  let текст = try? String(contentsOf: элемент, encoding: .utf8) else { continue }
            let диапазон = NSRange(текст.startIndex..., in: текст)
            for совпадение in re.matches(in: текст, range: диапазон) {
                if let r = Range(совпадение.range(at: 1), in: текст) {
                    найдено.insert(String(текст[r]))
                }
            }
        }
        return найдено
    }

    private func кнопки() throws -> Set<String> {
        try подписи(Self.образцыКнопок).union(подписиПеречислений())
    }
    private func экраны() throws -> Set<String> { try подписи(Self.образцыЭкранов) }
    private func вкладки() throws -> Set<String> { try подписи(Self.образцыВкладок) }

    private func подписи(_ образцы: [String]) throws -> Set<String> {
        try поОбразцам(образцы).values.reduce(into: Set<String>()) { $0.formUnion($1) }
    }

    /// Находки **по каждому образцу отдельно**, а не общей кучей.
    ///
    /// Общая куча — это и есть то место, где сторож тихо слепнет: порог
    /// стоит на сумме, и смерть одного образца её не трогает. На 25.10.2026
    /// `TGButton` давал 94 совпадения, и на их фоне два образца, упавших
    /// в ноль, не сдвинули общее число ни на шаг от порога «больше ста».
    private func поОбразцам(_ образцы: [String]) throws -> [String: Set<String>] {
        let тексты = исходники()
        var итог: [String: Set<String>] = [:]
        for образец in образцы {
            let re = try NSRegularExpression(pattern: образец,
                                             options: [.dotMatchesLineSeparators])
            var найдено: Set<String> = []
            for текст in тексты {
                let диапазон = NSRange(текст.startIndex..., in: текст)
                for совпадение in re.matches(in: текст, range: диапазон) {
                    if let r = Range(совпадение.range(at: 1), in: текст) {
                        найдено.insert(String(текст[r]))
                    }
                }
            }
            итог[образец] = найдено
        }
        return итог
    }

    @Test("Кнопка, экран и вкладка, названные по имени, есть в приложении")
    func адресаСуществуют() throws {
        let кнопки = try кнопки(), экраны = try экраны(), вкладки = try вкладки()
        #expect(кнопки.count > 100 && экраны.count > 30 && вкладки.count >= 4, """
            подписей найдено: кнопок \(кнопки.count), экранов \(экраны.count),
            вкладок \(вкладки.count) — разбор не состоялся.
            Сканер, переставший находить, молчит так же, как тот,
            кому нечего сказать.
            """)

        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: каталог))
            as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]

        // Вид сверяется с видом. Вкладке разрешены и заголовки экранов:
        // вкладка и есть экран, и зовут её то так, то так.
        let правила: [(String, Set<String>, String)] = [
            ("кнопк\\w+\\s+«([^»]{2,45})»", кнопки, "кнопка"),
            ("(?:на\\s+)?экран\\w*\\s+«([^»]{2,45})»", экраны, "экран"),
            ("вкладк\\w+\\s+«([^»]{2,45})»", вкладки.union(экраны), "вкладка"),
        ]

        var мимо: [String] = []
        var проверено = 0
        for ключ in строки.keys.sorted() {
            for (образец, набор, что) in правила {
                let re = try NSRegularExpression(pattern: образец, options: [.caseInsensitive])
                let диапазон = NSRange(ключ.startIndex..., in: ключ)
                for совпадение in re.matches(in: ключ, range: диапазон) {
                    guard let r = Range(совпадение.range(at: 1), in: ключ) else { continue }
                    let имя = String(ключ[r]).trimmingCharacters(in: .whitespaces)
                    guard Self.чужие[имя] == nil else { continue }
                    проверено += 1
                    // Регистр первой буквы у кнопки и у текста про неё
                    // разный, и это не дефект: «закончить» в предложении
                    // и «Закончить» на кнопке — одно и то же место.
                    guard !набор.contains(where: { $0.lowercased() == имя.lowercased() })
                    else { continue }
                    мимо.append("  \(что) «\(имя)» ← \(ключ.prefix(65))")
                }
            }
        }

        #expect(проверено > 5, "адресных цитат найдено \(проверено) — разбор не состоялся")
        #expect(мимо.isEmpty, """
            текст зовёт к тому, чего в приложении нет:

            \(мимо.joined(separator: "\n"))

            Человек пойдёт искать и не найдёт. Обещать в текстах то,
            чего нет, дневнику с дозами нельзя.
            """)
    }

    /// **Образец, упавший в ноль, — это слепота, и до 25.10.2026 её
    /// не ловило ничто.**
    ///
    /// Порог в соседнем тесте стоит на СУММЕ найденных подписей, а сумму
    /// набирают `TGButton` (94) и `Button` (88). На их фоне `BigAction`
    /// и `SmallAction` ушли в ноль вместе с `ActionGrid` (`17b415b`,
    /// 24.10.2026), и сумма не дрогнула: порог «больше ста» остался
    /// выполненным. Сторож ослеп на двух формах и промолчал.
    ///
    /// Покраснело это не здесь, а в соседнем тесте и не тем боком:
    /// он сказал «кнопки „Гулять" в приложении нет» — то есть обвинил
    /// живую кнопку, которая на месте, и позвал её переименовать.
    ///
    /// > **Вердикт «чего-то нет» у сканера значит две разные вещи:
    /// > „предмета нет" и „я его больше не вижу". Различить их может
    /// > только проверка самих образцов, и ставится она ПЕРВОЙ.**
    ///
    /// Один образец = один способ построить подпись. Упал в ноль —
    /// либо способ умер и образец надо снять с замером в руках, либо
    /// он переименован и образец надо поправить. Третьего нет, и молча
    /// не остаётся ни одного.
    @Test("Ни один образец подписи не ослеп")
    func образцыЖивы() throws {
        let группы: [(String, [String])] = [
            ("кнопка", Self.образцыКнопок),
            ("экран", Self.образцыЭкранов),
            ("вкладка", Self.образцыВкладок),
        ]

        var мёртвые: [String] = []
        var всего = 0
        for (что, образцы) in группы {
            for (образец, найдено) in try поОбразцам(образцы) {
                всего += 1
                if найдено.isEmpty { мёртвые.append("  \(что): \(образец)") }
            }
        }

        #expect(всего >= 13, "образцов проверено \(всего) — список разобран не весь")
        #expect(мёртвые.isEmpty, """
            образец не находит в проекте ничего:

            \(мёртвые.joined(separator: "\n"))

            Сканер, переставший видеть форму, молчит так же, как тот,
            кому нечего сказать, — а соседний тест в это время обвиняет
            живые кнопки. Снять образец (назвав замер, что формы больше
            нет) либо поправить. Правка порога починкой не считается.
            """)
    }

    @Test("Список чужих имён не протух")
    func чужиеСуществуютВТекстах() throws {
        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: каталог))
            as? [String: Any]
        let ключи = (корень?["strings"] as? [String: Any] ?? [:]).keys.joined(separator: "\n")

        for (имя, причина) in Self.чужие {
            #expect(!причина.isEmpty, "\(имя): исключение без причины")
            #expect(ключи.contains("«\(имя)»"), """
                «\(имя)» в исключениях, а в текстах его нет — список протух.
                """)
        }
        #expect(Self.чужие.count <= 5,
                "исключений \(Self.чужие.count): длинный список — сторож, который не может покраснеть")
    }
}
