import Testing
import Foundation

/// Подпись показания не называет улицу над числом, которое значит «дома».
///
/// До 23.10.2026 это была подпись ПЛАКАТА; плакат снят редизайном
/// «Кино», правило переехало в чип панели показания. Разбор перевода —
/// ниже, в разделе «ОСЬ ПЕРЕВЕДЕНА».
///
/// **Чем это оплачено — сборкой, уехавшей к людям.** 07.10.2026 на
/// главном экране 273 стояло:
///
/// ```
/// 10 ч 17 мин
/// 🚶 на улице были          ← величина = timeIndoors, то есть ДОМА
/// ```
///
/// Пара читается сверху вниз и утверждает обратное правде. Прожило
/// это три зелёных прогона и доехало до телефона Виктории.
///
/// **Как оно возникло, и почему сторож нужен именно такой.** У героя
/// до переноса стояло «10 ч 17 мин **назад** · на улице были» —
/// и слово «назад» делало фразу истинной. Перенося показание в плакат,
/// его уронили: в макете для «назад» слота нет.
///
/// > **Слово уронено не правкой текста, а переносом текста в другую
/// > вёрстку.** Строку не меняли — изменилась рамка, в которую она
/// > встала. Поэтому ни сторож на строку, ни сверка с каталогом,
/// > ни словарь помочь не могли: все они смотрят на слова, а сломалась
/// > связь между словом и соседней величиной.
///
/// **Правило написано ОТ ЗАПРЕТА**, и это не стиль. «Подпись обязана
/// соответствовать величине» выполняется и при отсутствии подписи,
/// и при отсутствии величины — у Kvit такая формулировка уже
/// проходила при противоположном дефекте. Запрет же проверяется
/// надёжно: слово про улицу узнаётся по корню.
///
/// # ОСЬ ПЕРЕВЕДЕНА 23.10.2026: ПЛАКАТА НЕТ, ПРАВИЛО ЕСТЬ
///
/// Редизайн «Кино» снял плакат с «Сегодня» — на его месте панель
/// показания (`ReadingPanel`), а слот подписи под числом **упразднён**:
/// на кадре 01 слово «Дома» стоит чипом слева сверху. Свойства
/// `подписьПлаката` в `TodayScreen` больше нет вовсе, и сторож честно
/// краснел «разбор не состоялся» — он смотрел в пустоту.
///
/// ```
/// было   private var подписьПлаката   литералы в `text:`
/// стало  private var обычныйЧип       литералы в `текст:`
/// ```
///
/// **Снимать было нечего: предмет не умер, а переехал.** Правило
/// переехало вместе с ним дословно — разбор, который его оплатил,
/// стоит в `TodayScreen.чипСостояния` целиком. Переведена только ось.
///
/// ## Ось берётся у `обычныйЧип`, а НЕ у `чипСостояния` — и это замер
///
/// Соблазн взять верхнее свойство велик: подписей там тринадцать вместо
/// двух. Прогон разбора на здоровом коде 23.10.2026 показывает, чем это
/// кончится:
///
/// ```
/// обычныйЧип     «Дома» · «Сегодня»                          чисто
/// чипСостояния   … «На улице» … «Давно не выходили» …    ДВА ЛОЖНЫХ
/// ```
///
/// Обе найденные строки **верны**: `.walk` показывает таймер прогулки
/// (`.минутыСекунды`), а не `timeIndoors`, и «На улице» там правда;
/// `.silence` называет факт дня. Сторож на `чипСостояния` покраснел бы
/// на правде и был бы снят первым же, кто его прочтёт.
///
/// > **Запрет действует ровно там, где показание — `timeIndoors`.**
/// > У `обычныйЧип` это выражено `switch показаниеПанели`, и ветка
/// > `.часыМинуты` — единственная, где число голое и требует имени.
@Suite("Подпись показания не называет улицу над числом «дома»")
struct ПодписьПоказанияTests {

    /// Корни слов, которыми называют выход. Закрытый список —
    /// и он про ЗАПРЕТ, поэтому надёжен: спросить «нет ли здесь
    /// запретного корня» можно, спросить «есть ли нужное слово» —
    /// нельзя, у нужного десять форм.
    static let проУлицу = ["улиц", "выход", "выгул", "гуля", "прогул"]

    /// Нарушено ли правило. Чистая функция — **её и проверяем первой**,
    /// отдельно от файла.
    ///
    /// Условие намеренно двойное: запрет действует, только пока
    /// показание берётся из `timeIndoors`. Сменят величину на «сколько
    /// был на улице» — и «на улице были» станет верной подписью;
    /// сторож, не знающий этого, потребовал бы неверного.
    static func нарушение(подпись: String, показаниеИзВремениДома: Bool) -> String? {
        guard показаниеИзВремениДома else { return nil }
        let строка = подпись.lowercased()
        return проУлицу.first { строка.contains($0) }
    }

    // MARK: Сначала — срабатывает ли сам сторож

    /// **Проверка, что сторожу есть чем сработать.**
    ///
    /// Ставится первой нарочно. Утром 07.10 у соседнего сторожа весь
    /// список исключений молча не работал из-за симлинка, а проверка
    /// «исключения существуют» была зелёной: набор, которому нечего
    /// проверять, молчит так же, как набор, у которого всё хорошо.
    ///
    /// Здесь правило проверяется на **том самом тексте**, который уехал
    /// к людям, — а не на выдуманном примере.
    @Test("Сторож краснеет на подписи, которая уехала в 273")
    func сторожСрабатывает() {
        #expect(Self.нарушение(подпись: "на улице были",
                               показаниеИзВремениДома: true) != nil, """
            сторож НЕ видит ту самую подпись, из-за которой он заведён.
            Это не «правило соблюдено» — это правило, которому нечем
            сработать.
            """)

        // Каждый корень проверяется отдельно: список из пяти, у которого
        // работает один, краснеет так же, как полный.
        for корень in Self.проУлицу {
            #expect(Self.нарушение(подпись: "собака \(корень)ка сегодня",
                                   показаниеИзВремениДома: true) != nil,
                    "корень «\(корень)» в списке есть и не ловится")
        }

        #expect(Self.нарушение(подпись: "дома", показаниеИзВремениДома: true) == nil,
                "сторож краснеет на верной подписи — это хуже пропущенного дефекта")

        // Граница правила: величина другая — запрета нет.
        #expect(Self.нарушение(подпись: "на улице были",
                               показаниеИзВремениДома: false) == nil, """
            запрет сработал там, где показание НЕ из timeIndoors.
            Тогда «на улице были» — верная подпись, и сторож
            потребовал бы неверного.
            """)
    }

    // MARK: Потом — живой экран

    @Test("На «Сегодня» чип обычного дня не про улицу")
    func живойЭкранЧист() throws {
        let исходник = try Self.исходникЭкрана()

        // **Проза отбрасывается до разбора, и это не предосторожность
        // на будущее.** В этом самом файле и в `TodayScreen` стоят
        // комментарии, которые ЦИТИРУЮТ «на улице были» — объяснение,
        // почему так писать нельзя. Сканер, не различающий код и прозу,
        // покраснел бы на объяснении: у Timer такой сторож наказал
        // за строку «// НЕ `MapsApp.allCases`».
        let код = исходник.components(separatedBy: .newlines)
            .map { строка -> String in
                let без = строка.trimmingCharacters(in: .whitespaces)
                if без.hasPrefix("//") { return "" }
                guard let i = строка.range(of: "//") else { return строка }
                return String(строка[..<i.lowerBound])
            }
            .joined(separator: "\n")

        let показаниеИзВремениДома = код.contains("timeIndoors")
        #expect(показаниеИзВремениДома, """
            в `TodayScreen` больше нет `timeIndoors` — значит показание
            плаката берётся из чего-то другого, и этот сторож проверяет
            правило, которого уже нет. Перечитай его целиком, а не
            правь порог.
            """)

        let подписи = try Self.подписи(код)

        // Счётчик осмотренного: разбор, переставший что-либо находить,
        // молчит так же, как тот, кому нечего сказать.
        #expect(!подписи.isEmpty, """
            в `обычныйЧип` не нашлось ни одной подписи с текстом.
            Разбор не состоялся — тишина ниже ничего не значит.
            Если свойство переименовали или подпись перестала быть
            литералом, правь разбор, а не удаляй проверку.

            Так этот сторож уже краснел один раз: 23.10.2026 редизайн
            «Кино» переименовал `подписьПлаката` в `обычныйЧип`, и ось
            пришлось переводить. Предмет при этом был жив — ищи, куда
            он переехал, прежде чем снимать.
            """)

        // **Контроль, снятый В ТОМ ЖЕ замере и тем же разбором.**
        // Он ломается вместе с предметом: если разбор перестанет
        // находить литералы вовсе, оба счёта обнулятся разом — а это
        // невозможно при живом экране, и несовместимость видна БЕЗ
        // знания причины.
        //
        // Взят `чипСостояния` нарочно: там подписей тринадцать, и две
        // из них — «На улице» и «Давно не выходили» — наш запретный
        // корень несут ЗАКОННО. То есть контроль отвечает «разбор
        // видит текст» и заодно показывает, почему ось не там.
        let контроль = try Self.подписи(код, свойство: "чипСостояния")
        #expect(контроль.count > подписи.count, """
            в `чипСостояния` найдено \(контроль.count) подписей против
            \(подписи.count) в `обычныйЧип`. Верхнее свойство обязано
            давать их БОЛЬШЕ — оно перечисляет все состояния дня.
            Равенство или ноль значит, что разбор отвечает про себя,
            а не про экран.
            """)
        print("РАЗБОР: обычныйЧип \(подписи.count) · чипСостояния \(контроль.count) (контроль)")

        for подпись in подписи {
            let нарушено = Self.нарушение(подпись: подпись,
                                          показаниеИзВремениДома: показаниеИзВремениДома)
            #expect(нарушено == nil, """
                подпись обычного дня — «\(подпись)» — называет улицу
                словом «\(нарушено ?? "")», а показание берётся
                из `timeIndoors`, то есть это время ДОМА.

                Пара читается обратно правде, и ровно она уехала
                в сборке 273. Если величину поменяли на «сколько был
                на улице» — меняй и этот сторож, он про пару, а не
                про слово.
                """)
        }
    }

    // MARK: Разбор

    private static func исходникЭкрана() throws -> String {
        let путь = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Togo/Features/Today/TodayScreen.swift")
        return try String(contentsOf: путь, encoding: .utf8)
    }

    /// Все тексты подписи — из исходника, а не списком.
    ///
    /// **Разбор по ветке `.usual` снят 07.10.2026 вместе с самой
    /// веткой.** Подпись перестала зависеть от режима дня и зависит
    /// теперь от вида показания: имя нужно только голому числу часов.
    /// Сканер, искавший `case .usual:`, нашёл бы ноль — и порог
    /// «нашлось ли что осматривать» покраснел бы честно.
    ///
    /// Новая форма проще и строже: берём ВСЕ подписи, какие бы ветки
    /// ни появились. Запрет от этого не ослаб — он про пару «подпись
    /// и величина», а не про имя ветки.
    ///
    /// **23.10.2026 сменились и имя свойства, и имя метки** — плакат
    /// снят, подпись стала чипом панели показания:
    ///
    /// ```
    /// было   подписьПлаката   text:    (англ., параметр TGPoster)
    /// стало  обычныйЧип       текст:   (рус., поле ReadingPanel.Чип)
    /// ```
    ///
    /// Свойство — параметром, а не зашито: тот же разбор нужен
    /// контролю на `чипСостояния`, и две копии одного разбора
    /// разошлись бы молча.
    private static func подписи(_ код: String,
                                свойство: String = "обычныйЧип") throws -> [String] {
        guard let начало = код.range(of: "private var " + свойство) else { return [] }
        let тело = код[начало.upperBound...]
        // Конец свойства — следующее объявление того же уровня.
        let конец = тело.range(of: "\n    private var")?.lowerBound ?? тело.endIndex
        var найдено: [String] = []
        var остаток = тело[..<конец]
        while let метка = остаток.range(of: "текст:") {
            let после = остаток[метка.upperBound...]
            guard let открыть = после.firstIndex(of: "\""),
                  let закрыть = после[после.index(after: открыть)...].firstIndex(of: "\"")
            else { break }
            найдено.append(String(после[после.index(after: открыть)..<закрыть]))
            остаток = после[закрыть...]
        }
        return найдено
    }
}
