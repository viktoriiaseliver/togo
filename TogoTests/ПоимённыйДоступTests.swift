import Foundation
import CloudKit
import Testing
@testable import Togo

/// Владелец закрывает доступ **одному** человеку и меняет роль **уже
/// вошедшему**. Два пункта `ВОПРОСЫ.md`, закрытые 26.10.2026.
///
/// # Что было записано, и что из этого оказалось неверным
///
/// ```
/// 2-бис  «`removeParticipant` в проекте — ноль вхождений. Настоящий
///        рычаг один и он всеобщий»
///        → ВЕРНО как замер. Как вывод — «органа нет и не будет»
/// 1-бис  «Закрыть можно только полем в схеме»
///        → ЛОЖНО, и замера под этим не было ни одного
/// ```
///
/// Второе дороже первого, потому что стояло **в перечне измеренного**
/// в трёх местах сразу (`ВОПРОСЫ.md`, `FamilyShare.назначитьНовичкам`,
/// `FamilyScreen.swift:564`) и читалось как замер. Происхождение
/// у всех трёх одно: верное наблюдение «связи „локальная карточка
/// `FamilyMember` ↔ участник CloudKit“ нет» и вывод, который из него
/// не следует.
///
/// ```
/// ЧТО ВЕРНО    связи карточки с участником нет, и завести её —
///              правка формы схемы
/// ЧЕГО НЕ СЛЕДУЕТ
///              что роль нельзя назначить поимённо
/// ПОЧЕМУ       ключ наряда — `userRecordID.recordName`, и отдаёт его
///              САМ CloudKit (`share.participants[].userIdentity`),
///              а не карточка. Поле `НарядРолей.поУчастникам`
///              существует с первой версии наряда
/// ```
///
/// > **Карточка была нужна только затем, чтобы НАЗВАТЬ человека.**
/// > Назвать его умеет список участников, и дорога к роли не проходит
/// > через карточку вовсе.
///
/// Формы схемы правка не коснулась ни строкой: версия наряда прежняя,
/// состав полей тот же, поле `togoRoleAssignment` живёт
/// на `cloudkit.share` и в ось `deploy_cloudkit_schema.sh` не входит
/// (это сказано у `РолиВОбмене.полеНаряда`).
///
/// # Чего этот набор НЕ проверяет
///
/// Приватную базу CloudKit измерить без её личного iCloud нельзя
/// вовсе — второго конца у связи нет. Здесь проверяется то, что
/// вынесено в чистое значение и в локальные запреты: кому отказано,
/// что роль читается поимённо, и **есть ли у человека вход**. Что
/// облако ответит на `removeParticipant`, не знает ни один наш тест.
@MainActor
@Suite("Поимённый доступ и роль вошедшему")
struct ПоимённыйДоступTests {

    private static let чужой = "_ownerOfSomeoneElsesDiary"

    private func какГость<T>(_ тело: () async throws -> T) async rethrows -> T {
        let было = SharedZoneOwner.name
        SharedZoneOwner.name = Self.чужой
        defer { SharedZoneOwner.name = было }
        return try await тело()
    }

    private let наблюдатель = НазначеннаяРоль(роль: .observer)
    private let ухаживающая = НазначеннаяРоль(роль: .caregiver)

    // MARK: - Сначала проверка, что набору было что проверять

    @Test("Контроль: подстановка гостя действительно переключает роль")
    func оснасткаРаботает() async {
        await какГость {
            #expect(SharedZoneOwner.isGuest,
                    "Без этого запреты ниже зелены, ничего не проверив.")
        }
        #expect(SharedZoneOwner.name != Self.чужой, "подстановка не снялась за собой")
    }

    // MARK: - Запреты: оба локальны и потому проверяемы без облака

    /// Строго `notOwner`, а не «бросило что-нибудь».
    ///
    /// «Бросило» выполнялось бы и от `CKError` при отсутствии сети,
    /// то есть вопрос был бы слабее дефекта, который он ищет. Это же
    /// держит **порядок** проверок внутри: стоит гостевая позже права
    /// или входа — и человек получит совет не про то.
    @Test("Гость не отзывает доступ: это право владельца")
    func гостьНеОтзывает() async {
        await какГость {
            do {
                try await FamilyShare.убрать(участника: "id:_кто-нибудь")
                Issue.record("""
                    Отзыв доступа у гостя прошёл. Значит участник, \
                    которого позвали помогать, может закрыть дневник \
                    другому участнику — или самому себе, молча.
                    """)
            } catch {
                #expect(FamilyShare.причина(error) == "notOwner", """
                    Пришло «\(FamilyShare.причина(error))» вместо notOwner. \
                    Либо запрет снят, либо он стоит позже обращения \
                    к облаку — и тогда его нельзя проверить без её iCloud.
                    """)
            }
        }
    }

    @Test("Гость не назначает роли: это право владельца")
    func гостьНеНазначает() async {
        await какГость {
            do {
                try await FamilyShare.назначить(.coOwner, участнику: "_кто-нибудь")
                Issue.record("""
                    Назначение роли у гостя прошло. Гость мог бы \
                    выдать себе `coOwner` — и приехавшее сильнее \
                    карточки, то есть права он получил бы настоящие.
                    """)
            } catch {
                #expect(FamilyShare.причина(error) == "notOwner", """
                    Пришло «\(FamilyShare.причина(error))» вместо notOwner. \
                    Запрет обязан стоять ПЕРВОЙ строкой: за ним два \
                    обращения к облаку, и после них проверить его \
                    нечем — приватную базу мы не измеряем.
                    """)
            }
        }
    }

    // MARK: - Отказы говорят разное

    @Test("У двух новых отказов свои тексты, и они не повторяют прежние")
    func текстыОтказовРазные() {
        let все: [FamilyShare.ShareError] = [
            .noAccount, .noEntitlement, .notOwner, .linkNotReady,
            .saveFailed(code: nil), .нетТакогоУчастника, .нельзяУбратьВладельца
        ]
        let тексты = все.compactMap(\.errorDescription)
        #expect(тексты.count == все.count, "у отказа пропал текст")
        #expect(Set(тексты).count == тексты.count, """
            два отказа говорят одно и то же: \(тексты). Один текст \
            на несколько причин даёт совет, неверный для остальных, — \
            и это хуже молчания.
            """)

        // Самый дорогой из двух новых: «его уже убрали» — это НЕ отказ
        // настроек человека, и советовать ему что-то проверять у себя
        // было бы ложью.
        let нету = FamilyShare.ShareError.нетТакогоУчастника.errorDescription ?? ""
        for ложныйСовет in ["Войди в iCloud", "Проверь связь"] {
            #expect(!нету.contains(ложныйСовет), """
                «\(нету)» советует «\(ложныйСовет)» — совет не про эту \
                причину. Человека уже убрали с другого телефона, \
                и в его настройках менять нечего.
                """)
        }

        #expect(FamilyShare.причина(FamilyShare.ShareError.нетТакогоУчастника) == "нетУчастника")
        #expect(FamilyShare.причина(FamilyShare.ShareError.нельзяУбратьВладельца) == "владелец")
    }

    // MARK: - Роль поимённо доезжает и действует

    /// Сердце пункта 1-бис: правка роли **побеждает** то, что гость
    /// помнит о себе.
    ///
    /// Приколотое назначение — единственное, что отличало вошедшего
    /// от новичка, и оно же до этой правки делало вошедшего
    /// недосягаемым: `поУчастникам` не писал никто, значит ветка
    /// поимённого была недостижима, значит вошедшему нельзя было
    /// ни повысить, ни понизить роль.
    @Test("Понижение поимённо побеждает приколотое назначение гостя")
    func понижениеДоезжает() {
        let наряд = НарядРолей(поУчастникам: ["U-маша": наблюдатель],
                               новичкам: ухаживающая)
        let вышло = РолиВОбмене.назначение(из: наряд, участник: "U-маша",
                                           уже: ухаживающая)
        #expect(вышло == наблюдатель, """
            Понижение не доехало: гость остался ухаживающей, хотя \
            владелец назначил наблюдателя. Право `.giveDose` — это \
            отметка дозы лекарства, и её потом читает врач.
            """)
    }

    @Test("Повышение поимённо тоже доезжает — и только названному")
    func повышениеТолькоНазванному() {
        let наряд = НарядРолей(поУчастникам: ["U-маша": ухаживающая],
                               новичкам: наблюдатель)
        #expect(РолиВОбмене.назначение(из: наряд, участник: "U-маша",
                                       уже: наблюдатель) == ухаживающая)
        // Контроль в том же замере: сосед по дневнику не поехал
        // за Машей. Без него «повышение работает» означало бы
        // и «повышается кто попало».
        #expect(РолиВОбмене.назначение(из: наряд, участник: "U-тео",
                                       уже: наблюдатель) == наблюдатель, """
            Поимённое назначение Маши подействовало на Тео. Ключ \
            наряда перестал быть ключом — а это ровно тот дефект, \
            который `dd1a3db` закрывал с другого конца.
            """)
    }

    /// Наряд с поимённой записью **переживает кодирование**.
    ///
    /// Проверка не праздная: назначение едет строкой JSON на поле
    /// записи общего доступа, и если `поУчастникам` не доживёт
    /// до другого телефона, тесты выше останутся зелёными — они меряют
    /// значение, а не дорогу.
    @Test("Поимённая запись переживает дорогу в облако и обратно")
    func дорогаТудаИОбратно() throws {
        let наряд = НарядРолей(поУчастникам: ["U-маша": наблюдатель],
                               новичкам: ухаживающая)
        let строка = try #require(РолиВОбмене.закодировать(наряд))
        let обратно = try #require(РолиВОбмене.разобрать(строка))

        #expect(обратно == наряд, """
            наряд не доехал целым: туда \(наряд), обратно \(обратно). \
            Поимённая роль едет ЭТОЙ строкой и никак иначе.
            """)
        #expect(обратно.поУчастникам["U-маша"] == наблюдатель)
        #expect(обратно.версия == РолиВОбмене.текущаяВерсия, """
            версия наряда изменилась. Поимённое назначение формы схемы \
            не меняет, и если версия поехала — поехала она не от этой \
            правки, и у нового значения должен быть хозяин.
            """)
    }

    // MARK: - ВХОД. Тот самый, которого не было

    /// **Ось сторожа — вход, а не механизм.**
    ///
    /// Механизм здесь проверить тестом нельзя: он в приватной базе.
    /// А вход проверить можно, и именно он отсутствовал при готовом
    /// слое ниже — `назначитьНовичкам` приехал 25.10 и не звал его
    /// никто, что и названо в проекте «механизмом без входа».
    ///
    /// > Зелёные тесты выше не отличают «орган есть» от «органа нет»:
    /// > они зовут слой сами. Единственное, что это различает, —
    /// > **каким путём человек это делает**, и спросить про путь может
    /// > только разбор исходника.
    ///
    /// # Граница названа
    ///
    /// Текстовый сторож ловит «вход убрали из исходника» и слеп
    /// к «вход есть, но недостижим». Снимает её только проход
    /// по экрану, а симулятор 26.10 занят другой сессией.
    @Test("Рычаг отзыва и смена роли вызываются с экрана, а не только объявлены")
    func входыЕсть() throws {
        let слой = Self.код("TogoShared/Sync/FamilyShare.swift")
        let экран = Self.код("Togo/Features/Family/УчастникиДневника.swift")
        let семья = Self.код("Togo/Features/Family/FamilyScreen.swift")

        // Контроль прежде предмета, в том же замере: все три файла
        // прочитаны и разобраны, иначе «вызова нет» ниже сказало бы
        // про инструмент.
        #expect(слой.contains("enum FamilyShare"), "слой не прочитан или разобран в пустоту")
        #expect(экран.contains("struct УчастникиДневника"), "экран не прочитан")
        #expect(семья.contains("struct FamilyScreen"), "«Семья» не прочитана")

        #expect(слой.contains("removeParticipant("), """
            `removeParticipant` снова ноль вхождений. Поимённого \
            отзыва доступа нет, остаётся всеобщее «Перестать делиться» \
            — и владелец, которому надо убрать ситтера, закроет \
            дневник маме.
            """)
        #expect(слой.contains("поУчастникам[ключ] ="), """
            `НарядРолей.поУчастникам` снова не пишет никто. Ветка \
            поимённой роли становится недостижимой — и выглядит \
            рабочей, потому что тесты значений зелены.
            """)

        #expect(экран.contains("FamilyShare.убрать(участника:"), """
            экран «Кто имеет доступ» не зовёт отзыв. Рычаг объявлен \
            и не вызван — ровно то состояние, в котором `назначитьНовичкам` \
            прожил от 25.10 до 26.10.
            """)
        #expect(экран.contains("FamilyShare.назначить("), """
            экран не зовёт поимённое назначение роли.
            """)
        #expect(семья.contains("УчастникиДневника()"), """
            к экрану «Кто имеет доступ» нет ни одной дороги из «Семьи». \
            Экран, до которого нельзя дойти, от отсутствующего \
            не отличается ничем.
            """)
    }

    /// Приехавшее назначение надо ещё **применить**, и до 26.10.2026
    /// этого не делал никто.
    ///
    /// Замер: `adoptMe(from:)` звался из одного места — `.task`
    /// у `AppRoot`, то есть один раз за запуск. `FamilySync` при каждом
    /// обмене обновлял `НазначениеПоОбмену`, значение честно ложилось
    /// на диск, а `AppState.role` оставался прежним **до перезапуска
    /// приложения**.
    ///
    /// Отличить это от рабочего нельзя было ни тестом, ни компилятором:
    /// тесты зовут `adoptMe` сами и передают назначение аргументом.
    @Test("У «роль приехала» есть и писатель, и читатель")
    func приехавшееПрименяется() throws {
        let слой = Self.код("TogoShared/Sync/FamilyShare.swift")
        let корень = Self.код("Togo/App/TogoApp.swift")

        #expect(слой.contains("enum FamilyShare"), "слой не прочитан")
        #expect(корень.contains("struct AppRoot"), "корень не прочитан")

        #expect(слой.contains("post(name: .назначениеРолиПриехало"), """
            о приехавшей роли больше никто не сообщает.
            """)
        #expect(корень.contains("for: .назначениеРолиПриехало"), """
            у «роль приехала» нет читателя. Значение ложится на диск, \
            а человек видит прежнюю роль до перезапуска приложения — \
            и ни один тест этого не заметит, потому что тесты зовут \
            `adoptMe` сами.
            """)
        #expect(корень.contains("adoptMe(from: members)"), """
            читатель есть, а применения нет: уведомление ловят и ничего \
            не делают. Правило обязано жить ОДНОЙ функцией — за две \
            реализации одного правила этот проект платил дозой.
            """)
    }

    /// Строки, начинающиеся комментарием, выброшены до разбора:
    /// сторож, не различающий код и прозу, меряет прозу — а прозы
    /// про `removeParticipant` в этом проекте накопилось семь мест.
    private static func код(_ путь: String) -> String {
        (try? ПриёмПоСсылкеTests.исходник(путь))
            .map(ПриёмПоСсылкеTests.безКомментариев) ?? ""
    }
}
