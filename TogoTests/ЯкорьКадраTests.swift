import Testing
import Foundation
import CoreGraphics
@testable import Togo

/// Якорь кадрирования подложки: правило и его места вызова.
///
/// # Что здесь предмет, а что контроль
///
/// Предмет — **числа сдвига**, названные ПРЕЖДЕ прогона (разбор ниже
/// у каждого случая). Контроль — якорь `.центр`, который обязан дать
/// ноль на тех же окнах.
///
/// Пара держится взаимно, и это проверено попыткой её уронить, а не
/// заявлено:
///
/// ```
/// сломать так, чтобы сдвиг ВСЕГДА был ноль   предмет краснеет (58 ≠ 0)
///                                            контроль зелёный
/// сломать так, чтобы сдвиг был мусором       контроль краснеет
/// ```
///
/// > **Контроль, который не умеет покраснеть, — украшение.** Один
/// > `.центр → 0` без предмета зелен и у правила, и у заглушки,
/// > возвращающей `.zero`: оба ответа выглядят одинаково.
///
/// # Чего этот набор НЕ проверяет
///
/// Что человек увидит голову. Это вопрос кадра, а не числа: сдвиг
/// на 58 pt вниз и «макушка в кадре» — разные утверждения, и второе
/// доказывается только картинкой. Приёмка — `TogoUITests/ФоныИПодложки`,
/// кадры `02`–`05`, и она снята отдельно.
@Suite("Якорь кадрирования подложки")
struct ЯкорьКадраTests {

    /// Фикстура стенда: портрет 3 : 4 (`ФонФикстураСтенда.сПриметами`).
    /// Та же пропорция, на которой снят замер 25.10.2026.
    private static let портрет = CGSize(width: 600, height: 800)

    /// Четыре живых окна подложки. Ширина 402 — iPhone 17 Pro,
    /// на котором сняты кадры приёмки; высоты — `Token.Size.backdrop*`.
    private static let окноСегодня = CGSize(width: 402, height: 640)
    private static let окноВкладки = CGSize(width: 402, height: 420)
    private static let окноПодэкрана = CGSize(width: 402, height: 360)
    private static let окноВыгула = CGSize(width: 402, height: 520)

    private static let всеОкна = [окноСегодня, окноВкладки, окноПодэкрана, окноВыгула]

    // MARK: - Правило

    @Test("Доли берутся из прототипа: «Сегодня» 22 %, остальные 35 %, по горизонтали всегда середина")
    func доли() {
        #expect(ЯкорьКадра.по(виду: .today).y == 0.22)
        #expect(ЯкорьКадра.по(виду: .tab).y == 0.35)
        #expect(ЯкорьКадра.по(виду: .sub).y == 0.35)
        #expect(ЯкорьКадра.по(виду: .walk).y == 0.35)
        for вид in BackdropKind.allCases {
            #expect(ЯкорьКадра.по(виду: вид).x == 0.5,
                    "по горизонтали прототип даёт 50 % всем без исключения, а \(вид) получил другое")
        }
    }

    // MARK: - Предмет: числа сдвига, названные прежде прогона

    /// Портрет 600 × 800 в четырёх окнах. Числа выведены из геометрии
    /// и записаны ДО прогона — иначе зелёный не отличить от слепоты:
    ///
    /// ```
    /// окно 402×640  масштаб 0,80 → 480×640. По высоте ровно, избытка
    ///               нет вовсе → сдвиг 0. По ширине избыток 78,
    ///               доля 0,5 → тоже 0. ИТОГО .zero
    /// окно 402×420  масштаб 0,67 → 402×536. Избыток 116.
    ///               0,35·536 − 210 = −22,4 → прижато к верху (0),
    ///               сдвиг 58 ВНИЗ: снимок уезжает вниз, в кадре
    ///               остаётся макушка
    /// окно 402×360  избыток 176. 0,35·536 − 180 = 7,6 → сдвиг 80,4
    /// окно 402×520  избыток 16.  0,35·536 − 260 < 0 → сдвиг 8
    /// ```
    ///
    /// **«Сегодня» в этом списке — не пустая строка, а половина
    /// утверждения.** Замер 25.10.2026 говорит, что верх снимка там
    /// цел и без якоря; если правило начнёт двигать и его, значит
    /// доля применена не к той оси.
    @Test("Портрет 3 : 4: сдвиг по высоте там, где высота и режется")
    func сдвигПортрета() {
        let ожидание: [(CGSize, CGFloat, BackdropKind)] = [
            (Self.окноСегодня, 0, .today),
            (Self.окноВкладки, 58, .tab),
            (Self.окноПодэкрана, 80.4, .sub),
            (Self.окноВыгула, 8, .walk),
        ]
        for (окно, ждём, вид) in ожидание {
            let сдвиг = ЯкорьКадра.по(виду: вид).сдвиг(снимка: Self.портрет, в: окно)
            #expect(abs(сдвиг.height - ждём) < 0.1,
                    "окно \(окно.height): ждали сдвиг \(ждём), вышло \(сдвиг.height)")
            #expect(abs(сдвиг.width) < 0.1,
                    "окно \(окно.height): по ширине доля 0,5, сдвига быть не должно, вышло \(сдвиг.width)")
        }
    }

    /// Проверка, что проверять БЫЛО ЧТО, и она не декоративная.
    ///
    /// Правило, которое ни на одном живом окне ничего не двигает,
    /// зелено у всех тестов выше и при этом бесполезно. Такое уже
    /// бывало: правка `.background` → `.overlay` прошла разбор файла,
    /// не изменив ни одного числа.
    @Test("Хоть на одном живом окне правило РАБОТАЕТ, а не повторяет центр")
    func правилоНеПустое() {
        let сдвиги = Self.всеОкна.map { окно -> CGFloat in
            ЯкорьКадра.по(виду: .tab).сдвиг(снимка: Self.портрет, в: окно).height
        }
        #expect(сдвиги.contains { abs($0) > 1 }, """
            ни одно из четырёх живых окон не получило сдвига: правило \
            кадрирует ровно как центр, и вся правка ничего не меняет. \
            Сдвиги: \(сдвиги)
            """)
    }

    // MARK: - Контроль в том же заходе

    @Test("КОНТРОЛЬ: якорь-центр даёт ноль на всех четырёх окнах")
    func центрНеДвигает() {
        for окно in Self.всеОкна {
            let сдвиг = ЯкорьКадра.центр.сдвиг(снимка: Self.портрет, в: окно)
            #expect(abs(сдвиг.width) < 0.001 && abs(сдвиг.height) < 0.001,
                    "окно \(окно.height): центр обязан совпадать с прежним поведением, вышло \(сдвиг)")
        }
    }

    /// Горизонтальный снимок правило по вертикали не трогает — у него
    /// перерастает ШИРИНА, а по ширине якорь 50 %.
    ///
    /// Это не вырожденный случай: у `BackgroundScreen` в стенде лежат
    /// и пейзаж, и квадрат (`КартинкиВРамкеКадрTests`), и у человека
    /// половина снимков горизонтальные.
    @Test("КОНТРОЛЬ: пейзаж 4 : 3 остаётся ровно там, где был")
    func пейзажНеДвигается() {
        let пейзаж = CGSize(width: 800, height: 600)
        let сдвиг = ЯкорьКадра.по(виду: .tab).сдвиг(снимка: пейзаж, в: Self.окноВкладки)
        #expect(abs(сдвиг.width) < 0.001 && abs(сдвиг.height) < 0.001,
                "пейзаж перерастает окно по ширине, а по ширине доля 0,5: сдвиг \(сдвиг)")
    }

    @Test("КОНТРОЛЬ: нулевой снимок и нулевое окно дают ноль, а не деление на ноль")
    func вырожденное() {
        let якорь = ЯкорьКадра.по(виду: .tab)
        #expect(якорь.сдвиг(снимка: .zero, в: Self.окноВкладки) == .zero)
        #expect(якорь.сдвиг(снимка: Self.портрет, в: .zero) == .zero)
    }

    // MARK: - Места вызова

    /// Правило без читателей — наш записанный класс: имя есть,
    /// значение есть, вызова по имени нет.
    ///
    /// Сторож на ВЫЗОВ, а не на модель: тест выше зовёт `сдвиг` сам
    /// и останется зелёным, даже если подложка вернётся к центру.
    /// Ось — присутствие `КадрПоЯкорю` в обоих файлах показа; порог
    /// рядом, чтобы «ноль вхождений» от сломанного обхода не выглядел
    /// как «файлов нет».
    @Test("Подложка и фотошапка зовут КадрПоЯкорю, а не scaledToFill напрямую")
    func местаВызова() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let показ = [
            "Togo/Features/Settings/CinemaHeader.swift",
            "Togo/Features/Profile/ФотоШапка.swift",
        ]
        var всего = 0
        for путь in показ {
            let текст = try String(contentsOf: корень.appendingPathComponent(путь),
                                   encoding: .utf8)
            let есть = текст.contains("КадрПоЯкорю(")
            #expect(есть, """
                \(путь) не зовёт КадрПоЯкорю: подложка снова кадрируется \
                по центру, и на портретном снимке срежет голову — отзыв 28.10.2026.
                """)
            if есть { всего += 1 }
        }
        // Контроль обхода: файлы прочитаны и в них вообще что-то нашлось.
        // Без него «ноль вызовов» у переехавшего файла неотличимо
        // от «вызовов нет».
        #expect(всего == показ.count,
                "прочитано \(всего) файлов показа из \(показ.count)")
    }
}
