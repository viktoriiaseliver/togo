    // MARK: - Тон состояния

    /// **Тон фотографии кадром не проверен, и это не пропуск.**
    ///
    /// Требование дизайна называет «каждый тон состояния
    /// (`bd-tint-*`: dose, fasting, alarm, night)». Снять это кадром
    /// нельзя: тон на фото **не рисует ни один экран**. Замер
    /// 23.10.2026 — `Token.Component.Backdrop.tint` в коде вне
    /// комментариев: ноль вхождений при живом контроле
    /// (`Token.Surface.screen` — одиннадцать файлов).
    ///
    /// > Механизм без входа не «почти работает» — он не работает,
    /// > и кадра у него быть не может по устройству.
    ///
    /// Поэтому здесь две разные вещи, и обе названы:
    ///
    /// 1. **Арифметика**, а не кадр: на однотонном БЕЛОМ снимке тон
    ///    не делает фон светлее белого ни в одном из двух прочтений
    ///    смешивания. Значит белый снимок — худший случай, и замер
    ///    кадром выше накрывает все четыре тона для этого снимка.
    ///    Хендофф задаёт `blend: softLight`, а `softLight` поверх
    ///    чистого белого не меняет ничего вовсе (при `Cb = 1` формула
    ///    W3C даёт 1 при любом `Cs`); обычное смешивание по альфе
    ///    делает фон ТЕМНЕЕ. Оба исхода в нашу пользу.
    /// 2. **Растяжка**: как только у `Backdrop.tint` появится первый
    ///    читатель, этот тест покраснеет и скажет, что кадровый сторож
    ///    пора расширять на тоны. До тех пор он держит границу,
    ///    а не изображает покрытие.
    @Test("Тон фотографии не делает шапку светлее белого снимка")
    func тонНеДелаетСветлее() throws {
        // --- Арифметика: softLight поверх белого ---
        func softLight(_ cs: Double, _ cb: Double) -> Double {
            if cs <= 0.5 { return cb - (1 - 2 * cs) * cb * (1 - cb) }
            let d = cb <= 0.25 ? ((16 * cb - 12) * cb + 4) * cb : sqrt(cb)
            return cb + (2 * cs - 1) * (d - cb)
        }
        let тоны: [(String, Цвет, Double)] = [
            ("dose", Цвет(r: 31, g: 79, b: 255), 0.55),
            ("fasting", Цвет(r: 255, g: 194, b: 51), 0.55),
            ("alarm", Цвет(r: 213, g: 37, b: 25), 0.60),
            ("night", Цвет(r: 20, g: 20, b: 60), 0.60),
        ]
        let белый = Цвет(r: 255, g: 255, b: 255)
        for (имя, тон, альфа) in тоны {
            let мягко = Цвет(
                r: 255 * (1 + альфа * (softLight(тон.r / 255, 1) - 1)),
                g: 255 * (1 + альфа * (softLight(тон.g / 255, 1) - 1)),
                b: 255 * (1 + альфа * (softLight(тон.b / 255, 1) - 1)))
            let поАльфе = Цвет(r: альфа * тон.r + (1 - альфа) * 255,
                               g: альфа * тон.g + (1 - альфа) * 255,
                               b: альфа * тон.b + (1 - альфа) * 255)
            print(String(format: "ТОН %@: softLight %@ (%.0f) · по альфе %@ (%.0f) · белый 255",
                         имя, мягко.шестнадцатеричный, мягко.яркость,
                         поАльфе.шестнадцатеричный, поАльфе.яркость))
            #expect(мягко.яркость <= белый.яркость + 0.5,
