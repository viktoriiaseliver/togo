    /// Кто зовёт тон фотографии — по исходникам, с вырезанными
    /// комментариями.
    ///
    /// **Комментарии вырезаются до разбора, и это не аккуратность.**
    /// Про `Token.Component.Backdrop` написано прозой в голове
    /// `ФотоШапка.swift` семь раз — сторож, не различающий код
    /// и прозу, нашёл бы семь читателей там, где их ноль, и запретил бы
    /// писать про предмет в файле, где его не трогают.
    private static func читателиТона() throws -> [String] {
        var найдено: [String] = []
        for каталог in ["Togo", "TogoShared"] {
            let база = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: база,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let путь = случай as? URL, путь.pathExtension == "swift" else { continue }
                guard let текст = try? String(contentsOf: путь, encoding: .utf8) else { continue }
                let код = текст.split(separator: "\n", omittingEmptySubsequences: false)
                    .map { строка -> String in
                        guard let граница = строка.range(of: "//") else { return String(строка) }
                        return String(строка[строка.startIndex..<граница.lowerBound])
                    }
                    .joined(separator: "\n")
                if код.contains("Backdrop.tint") {
                    найдено.append(путь.lastPathComponent)
                }
            }
        }
        return найдено
    }
