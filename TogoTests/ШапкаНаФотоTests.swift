/// Читаемость шапки поверх фотографии — замером пикселя, а не арифметикой.
///
/// **Заведено 23.10.2026 по прямому требованию дизайна**
/// (`Дизайн/редизайн-ios28/README.md`, «Решения по вопросам разработки»,
/// пункт 3, коммит `943de49`):
///
/// > «Тест: шапка каждого экрана на однотонном `#FFFFFF` и в каждом тоне
/// > (`bd-tint-*`) → контраст пикселя под глифами ≥ 4.5 (HC ≥ 7).»
///
/// Повод не теоретический. Тем же решением дизайн **снял** прежнее
/// основание: восьми стопов `backdrop.scrimStops` для контраста
/// не хватает — на 10 % высоты α .52 даёт 4,3:1, на 25 % α .24 даёт
/// 1,8:1. То есть до слоя `headerScrim` шапка на светлом снимке была
/// нечитаема, и доказать это или опровергнуть было нечем: сторожа
/// на эту поверхность не было ни одного (замер 23.10.2026,
/// `git grep -l "scrim\|затемнен" -- TogoTests` — ноль файлов при живом
/// контроле: те же слова в `Togo/**` находятся в четырёх).
///
/// # Ось: ПИКСЕЛЬ ПОД ГЛИФОМ, а не значение токена
///
/// Проверить это вычислением нельзя, и это не предпочтение. Между
/// токеном и пикселем стоят четыре вещи, которых в токене нет:
/// где именно лёг текст, докуда достал слой затемнения, сколько
/// затемнений сложилось в этом месте и какой цвет дал композит.
/// Поэтому здесь **кадр**: вид рисуется `ImageRenderer`, кадр
/// разбирается по пикселям, и число приезжает из картинки.
///
/// > **Тест проверяет, верно ли посчитано; кадр — верно ли сказано.**
///
/// # Числа, которые тут ожидаются, и почему они НЕ те, что в README
///
/// ```
/// α .55  композит #737373   4,74:1     README обещает 4,76
/// α .70  композит #4D4D4D   8,45:1     README обещает 8,52
/// контроль α .30  #B2B2B2   2,12:1     порог 4,5 НЕ БЕРЁТ
/// ```
///
/// **Расхождение — не ошибка дизайна и не наша.** Дизайн считал композит
/// без округления до восьми бит (255 × 0,30 = 76,5), а в кадре канал
/// целый. Обе гарантии при этом держатся (≥ 4,5 и ≥ 7), но порог
/// в сторож надо ставить **требование** (4,5 и 7), а не **обещание**
/// (4,76 и 8,52): на обещании сторож покраснел бы на правде.
///
/// > Это наш класс «две копии одного числа разойдутся молча», только
/// > копии тут не равны по праву: округление делает экран, а не документ.
///
/// ## А кадр даёт ТРЕТЬЕ число, и ось у него другая
///
/// Таблица выше — про **слой шапки в одиночку**, поверх белого. Кадр
/// меряет **композит двух слоёв**: шапка стоит не на снимке, а на снимке
/// плюс общее затемнение блока (`затемнение`, .7 сверху). Поэтому
/// числа прогона выше табличных, и это не расхождение:
///
/// ```
/// замер 23.10.2026, 5 тестов, порог      кадр          слой один
/// 01-собака-белое-обычный  нужно 4,5     #424242 9,13  #737373 4,74
/// 02-собака-белое-HC       нужно 7,0     #2C2C2C 12,68 #4D4D4D 8,45
/// 03-подэкран-белое-обычный нужно 4,5    #4F4F63 7,25
/// 04-подэкран-белое-HC     нужно 7,0     #353542 10,96
/// ```
///
/// > **Две величины одного имени: «контраст шапки» слоя и «контраст
/// > шапки» кадра.** Прочитанные как одна, они дают «запас вдвое»,
/// > которого у слоя нет. Порог всё равно ставится по требованию
/// > (4,5 и 7), и сторож судит кадр — то, что увидит человек, —
/// > а не слой.
///
/// # Чего этот сторож НЕ доказывает
///
/// 1. **Что так выйдет на устройстве.** `ImageRenderer` — не
///    `UIHostingController`: он не знает ни безопасных зон, ни панели
///    навигации. Вертикальный сдвиг шапки подэкрана под панель здесь
///    **смоделирован** (`подПанелью`), а не измерен на телефоне.
///    Приёмка на устройстве остаётся отдельной работой.
/// 2. **Что состав экрана такой же.** Для `CinemaHeader` кадр
///    собирается тестом из тех же публичных частей, что собирает
///    `cinemaScreen(экран:)`, — но **собирает его тест**. Переставят
///    части на экране — здесь не покраснеет ничто. Это прокси,
///    и он назван.
/// 3. **Что тон фотографии проверен кадром.** Не проверен и не может
///    быть: тон (`Token.Component.Backdrop.tint`) не рисует ни один
///    экран — см. `тонНеДелаетСветлее`.
/// 4. **Что эталонные кадры дизайна это подтверждают.** Не подтверждают
///    и сверять с ними нельзя: «прототипы и кадры пока со старым
///    затемнением — слой шапки в них не добавлен» (README, тот же
///    пункт 3). `Дизайн/эталонные-кадры/ios28-кино-22.10/` годен
///    для всего остального и негоден для этого слоя.
///
/// Кадры ложатся в `build/кадры-шапка-на-фото/` через `#filePath` —
/// **адрес входа назван в голове нарочно**: тест пишет на диск,
/// и уборка каталога ломает его не на его предмете.
@MainActor
@Suite("Читаемость шапки на фото", .serialized)
struct ШапкаНаФотоTests {

    // MARK: - Пороги и числа стенда

    /// Требование дизайна для обычного режима.
    private static let порогОбычный = 4.5
    /// Требование дизайна для повышенного контраста.
    private static let порогHC = 7.0

    /// Ширина кадра. 402 pt — iPhone 16 Pro, на нём же дизайн мерил
    /// длину строк («прототип проверен на 402 pt», README, «Локализация»).
    private static let ширина: CGFloat = 402

    /// **Смоделированный** сдвиг шапки подэкрана вниз: статус-бар (59)
    /// плюс панель навигации в `inline` (44).
    ///
    /// Это не замер устройства, а модель, и она названа здесь, потому
    /// что от неё зависит, в какую часть затемнения попадёт текст.
    /// `CinemaBackdrop` уходит под статус-бар (`ignoresSafeArea`),
    /// а содержимое `ScrollView` — нет, и разница между ними и есть
    /// это число.
    private static let подПанелью: CGFloat = 103

    /// Выше этой яркости пиксель считается глифом, ниже — фоном,
    /// между — сглаживанием, и оно отбрасывается.
    ///
    /// Границы разведены нарочно широко. Белый текст шапки — `#F4F4F2`
    /// (244), самый светлый фон, который ещё берёт порог 4,5 на белом
    /// снимке, — около 118. Между ними сто двадцать ступеней, и ни одна
    /// настоящая величина в полосу неопределённости не попадает.
    private static let глифОт: Double = 230
    private static let фонДо: Double = 190

    // MARK: - Где лежат кадры

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    private static var каталог: URL {
        корень.appendingPathComponent("build/кадры-шапка-на-фото")
    }

    /// Счёт снятого. **Печатается всегда, в том числе после падения** —
    /// «снято четыре» и «упал на втором, снято одно» выглядят в логе
    /// одинаково, потому что во втором случае строки просто нет,
    /// а её отсутствия никто не ищет. Поэтому вызов стоит в `defer`.
    ///
    /// Счёт локальный для теста, а не общий на набор: общий изменяемый
    /// `static` печатал бы сумму чужих кадров как свою.
    private func печатьСчёта(_ имена: [String], ожидалось: Int) {
        print("КАДРОВ СНЯТО: \(имена.count) из \(ожидалось) · \(имена.joined(separator: ", "))")
    }

    // MARK: - Стенд

    /// Однотонный снимок — то самое «однотонное `#FFFFFF` фото»
    /// из требования.
    ///
    /// PNG, а не JPEG, и это замер, а не вкус: JPEG хранит цветность
    /// с прореживанием, и «чистый белый» после круга туда-обратно
    /// перестаёт быть ровно 255. Требование дизайна названо через
    /// точное значение, значит и кадр должен нести точное.
    private static func однотонное(_ цвет: UIColor, сторона: CGFloat = 1200) throws -> Data {
        let размер = CGSize(width: сторона, height: сторона)
        let картинка = UIGraphicsImageRenderer(size: размер).image { ctx in
            цвет.setFill()
            ctx.fill(CGRect(origin: .zero, size: размер))
        }
        return try #require(картинка.pngData(), "однотонный снимок не стал PNG")
    }

    /// Признаки, внутри которых идёт отрисовка.
    ///
    /// **Отрисовка внутри нужной `UITraitCollection` — не экономия
    /// на `.environment`, а единственный способ.** Токены это
    /// динамические `UIColor`, и разрешаются они по
    /// `UITraitCollection.current`. Тест, просящий повышенный контраст
    /// через окружение SwiftUI, напечатал бы «HC» и отрисовал обычное —
    /// и у нас это уже оплачено кадром, половина которого знала про
    /// тёмную тему, а половина нет (`КиноВиджетКадрTests`).
    ///
    /// # ЗДЕСЬ СТОЯЛО «`@Environment(\.colorSchemeContrast)` ПОЕДЕТ ЗА ЭТИМИ ПРИЗНАКАМИ». ЗАМЕР 23.10.2026 ГОВОРИТ: НЕ ПОЕДЕТ
    ///
    /// Оговорка была правильной — «утверждение, а не допущение», —
    /// и сторож, поставленный ею же (`повышенныйОтличаетсяОтОбычного`),
    /// её и снял:
    ///
    /// ```
    /// только performAsCurrent   обычный #424242 (9,13:1)
    ///                           повышенный #424242 (9,13:1)   СОВПАЛИ
    /// ```
    ///
    /// То есть `ImageRenderer` признаки UIKit в окружение SwiftUI
    /// **не переносит**: у него нет `UIHostingController`, а значит
    /// и моста трейтов. Видно это было только по совпадению двух чисел;
    /// оба при этом брали оба порога, и без контроля дыра жила бы молча.
    ///
    /// > **Признаки нужны по-прежнему, и это не «а заодно».** Токены —
    /// > динамические `UIColor`, они разрешаются по
    /// > `UITraitCollection.current` (`DynamicColor.swift`), а не
    /// > по окружению. Снять `performAsCurrent` — и `Token.Surface.screen`
    /// > приедет светлой темой. Поэтому обе половины ставятся вместе
    /// > и отвечают на разные вопросы:
    /// >
    /// > ```
    /// > performAsCurrent        чем РАЗРЕШАЮТСЯ токены (UIColor)
    /// > .environment(…)         что ЧИТАЮТ виды (@Environment)
    /// > ```
    ///
    /// # Ключ подчёркнутый, и это замер, а не вкус
    ///
    /// `\.colorSchemeContrast` в публичном API **только читается** —
    /// `.environment` требует `WritableKeyPath` и не компилируется.
    /// Сеттер есть у `\._colorSchemeContrast`. Замер 23.10.2026,
    /// контроль снят той же командой:
    ///
    /// ```
    /// \._colorSchemeContrast   rc=0   0 error:
    /// \.colorSchemeContrast    rc=1   4 error: cannot convert … to
    ///                                 expected argument type
    ///                                 'WritableKeyPath<EnvironmentValues, V>'
    /// ```
    ///
    /// Подчёркнутое имя — цена, и она названа: обновление SDK может
    /// его унести. **Покраснеет при этом компилятор, а не сторож
    /// молча** — то есть отказ придёт в виде, который нельзя
    /// не заметить. Это и есть довод в его пользу против подмены
    /// значения параметром вида: параметр пришлось бы завести
    /// в продукте ради теста, и он остался бы там навсегда.
    private static func признаки(повышенный: Bool) -> UITraitCollection {
        UITraitCollection(traitsFrom: [
            UITraitCollection(userInterfaceStyle: .dark),
            UITraitCollection(accessibilityContrast: повышенный ? .high : .normal),
        ])
    }

    @discardableResult
    private func снять(_ вид: some View, имя: String, повышенный: Bool,
                       счёт: inout [String]) throws -> UIImage {
        var нарисованное: UIImage?
        Self.признаки(повышенный: повышенный).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, .dark)
                    // Вторая половина, см. разбор у `признаки(повышенный:)`:
                    // признаки UIKit разрешают токены, окружение SwiftUI
                    // читают виды, и `ImageRenderer` одно в другое
                    // не переносит.
                    .environment(\._colorSchemeContrast,
                                 повышенный ? .increased : .standard)
                    .frame(width: Self.ширина)
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }
        let картинка = try #require(нарисованное, "ImageRenderer не отдал картинку для «\(имя)»")
        let данные = try #require(картинка.pngData(), "картинка «\(имя)» не стала PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        try данные.write(to: Self.каталог.appendingPathComponent("\(имя).png"))
        счёт.append(имя)
        return картинка
    }

    // MARK: - Разбор кадра

    private struct Цвет {
        var r: Double, g: Double, b: Double
        var яркость: Double { 0.2126 * r + 0.7152 * g + 0.0722 * b }
        var шестнадцатеричный: String {
            String(format: "#%02X%02X%02X", Int(r.rounded()), Int(g.rounded()), Int(b.rounded()))
        }
    }

    /// Что кадр сказал про полосу текста.
    private struct Замер {
        /// Сколько строк пикселей несут и глифы, и фон под ними.
        let строк: Int
        /// Сколько пикселей опознано глифами.
        let глифов: Int
        /// Самый СВЕТЛЫЙ фон среди строк с глифами — худший случай.
        /// Берётся по строкам, а не по кадру целиком: спад затемнения
        /// внизу слоя светлее ровной части, и усреднение его спрятало бы.
        let фон: Цвет
        /// Типичный цвет глифа.
        let глиф: Цвет
        let контраст: Double
        /// Номер худшей строки — чтобы на кадре было куда посмотреть.
        let худшаяСтрока: Int

        var словами: String {
            let исход = "композит \(фон.шестнадцатеричный) под \(глиф.шестнадцатеричный)"
            return String(format: "%.2f:1 — %@, строка %d, глифов %d в %d строках",
                          контраст, исход, худшаяСтрока, глифов, строк)
        }
    }

    private static func линейно(_ канал: Double) -> Double {
        let s = канал / 255
        return s <= 0.04045 ? s / 12.92 : pow((s + 0.055) / 1.055, 2.4)
    }

    private static func светлота(_ цвет: Цвет) -> Double {
        0.2126 * линейно(цвет.r) + 0.7152 * линейно(цвет.g) + 0.0722 * линейно(цвет.b)
    }

    private static func контраст(_ первый: Цвет, _ второй: Цвет) -> Double {
        let a = светлота(первый), b = светлота(второй)
        return (max(a, b) + 0.05) / (min(a, b) + 0.05)
    }

    /// Разобрать кадр: найти строки, где есть и глифы, и фон, и вернуть
    /// худшую из них.
    ///
    /// **Отказ здесь назван отдельно от «контраста не хватает», и это
    /// не педантизм.** Кадр без фона под глифами значит одно из двух:
    /// затемнения нет вовсе (фон слился с текстом) либо текста нет
    /// вовсе. Оба читаются как «ноль», и оба — не «контраст плохой»,
    /// а «мерить нечего». Сторож, печатающий в этом случае число,
    /// сообщил бы про себя, выдав это за факт об экране.
    private static func полосаТекста(_ картинка: UIImage) throws -> Замер {
        let cg = try #require(картинка.cgImage, "у кадра нет CGImage")
        let ш = cg.width, в = cg.height
        var байты = [UInt8](repeating: 0, count: ш * в * 4)
        let пространство = CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB()
        let контекст = try #require(
            CGContext(data: &байты, width: ш, height: в,
                      bitsPerComponent: 8, bytesPerRow: ш * 4, space: пространство,
                      bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue),
            "не завёлся CGContext под разбор кадра")
        контекст.draw(cg, in: CGRect(x: 0, y: 0, width: ш, height: в))

        var худшаяСтрока = -1
        var худшийФон = Цвет(r: 0, g: 0, b: 0)
        var строкСОбоими = 0
        var глифовВсего = 0
        var глифыКадра: [Цвет] = []

        for y in 0..<в {
            var фоновые: [Цвет] = []
            var глифовые: [Цвет] = []
            for x in 0..<ш {
                let i = (y * ш + x) * 4
                let цвет = Цвет(r: Double(байты[i]), g: Double(байты[i + 1]), b: Double(байты[i + 2]))
                if цвет.яркость >= глифОт { глифовые.append(цвет) }
                else if цвет.яркость <= фонДо { фоновые.append(цвет) }
            }
            // Три пикселя — это уже не шум сглаживания, а штрих буквы;
            // пятая часть строки под фон — это уже слой, а не кайма.
            guard глифовые.count >= 3, фоновые.count >= ш / 5 else { continue }
            строкСОбоими += 1
            глифовВсего += глифовые.count
            глифыКадра.append(contentsOf: глифовые)
            let середина = фоновые.sorted { $0.яркость < $1.яркость }[фоновые.count / 2]
            if худшаяСтрока < 0 || середина.яркость > худшийФон.яркость {
                худшийФон = середина
                худшаяСтрока = y
            }
        }

        try #require(худшаяСтрока >= 0, """
            В кадре не нашлось ни одной строки, где есть И глифы, И фон под ними. \
            Это НЕ «контраст плохой» — это «мерить нечего»: либо затемнения \
            под текстом нет вовсе и фон слился с белым текстом, либо текста \
            в кадре нет. Кадр лежит в \(каталог.path) — посмотреть на него \
            дешевле, чем гадать.
            """)
        let глиф = глифыКадра.sorted { $0.яркость < $1.яркость }[глифыКадра.count / 2]
        return Замер(строк: строкСОбоими, глифов: глифовВсего,
                     фон: худшийФон, глиф: глиф,
                     контраст: контраст(глиф, худшийФон),
                     худшаяСтрока: худшаяСтрока)
    }

    // MARK: - Виды под замером

    /// Шапка вкладки собаки и «Семьи» — `ФотоШапка`.
    ///
    /// Снимок приходит параметром, хранилище фона здесь ни при чём:
    /// у этого блока вход прямой.
    private func шапкаСобаки(фото: Data) -> some View {
        ФотоШапка(фото: фото,
                  высота: Token.Size.backdropTab,
                  надстрочник: "ШИППЕРКЕ · 3 ГОДА",
                  заголовок: .значение("Стич"))
    }

    /// Шапка подэкрана и вкладок — `CinemaHeader` поверх `CinemaBackdrop`.
    ///
    /// **Состав собран тестом, и это прокси.** `cinemaScreen(экран:)`
    /// кладёт `CinemaBackdrop` фоном под содержимое `ScrollView`,
    /// а `КиноЭкран` ставит в это содержимое `CinemaHeader` первой
    /// строкой. Здесь то же самое сложено руками, потому что ни тулбар,
    /// ни безопасные зоны `ImageRenderer` не знает.
    ///
    /// **Высота приходит параметром с 23.10.2026, и это починка дыры,
    /// а не обобщение «на будущее».** Прежняя редакция брала
    /// `Token.Size.backdropSub` безусловно и при этом утверждала
    /// в голове теста, что держит «плюс вкладки через `КиноЭкран`».
    /// Вкладка берёт `backdropTab` (420 против 360), а стопы затемнения
    /// `CinemaBackdrop` заданы долями ВЫСОТЫ — значит на вкладке текст
    /// шапки попадает в другую точку градиента, и замер подэкрана про
    /// неё ничего не говорит.
    ///
    /// > **Утверждение о покрытии — такое же утверждение о мире, как
    /// > число, и стареет так же.** Голова теста говорила «держит
    /// > вкладки», тело мерило подэкран, и расхождение не видел никто:
    /// > оба имени — `CinemaHeader`.
    private func шапкаКино(экран: ScreenKey, высота: CGFloat) -> some View {
        VStack(spacing: 0) {
            Color.clear.frame(height: Self.подПанелью)
            CinemaHeader("Настройки", надпись: "язык, уведомления, перенос", экран: экран)
            Spacer(minLength: 0)
        }
        .frame(height: высота)
        .background(alignment: .top) { CinemaBackdrop(экран: экран) }
    }

    /// Положить в общее хранилище фона однотонный снимок на время замера.
    ///
    /// **Вход у `CinemaHeader.наФото` один, и он глобальный** —
    /// `BackgroundStore.shared`. Инъекции у него нет, подменить нечем,
    /// поэтому хранилище правится по-настоящему и возвращается на место
    /// в `defer`. Названо, а не обойдено: сторож, рисующий фотографию
    /// мимо того хозяина, который её рисует на экране, проверял бы
    /// свою сборку, а не экран.
    ///
    /// > В памяти остаётся `choice` с нашим снимком до конца процесса —
    /// > вернуть её нечем, у хранилища нет перечитывания. Диск и
    /// > `UserDefaults` восстанавливаются полностью.
    ///
    /// **Ключ приходит параметром с 23.10.2026.** `background(for:)`
    /// разрешает имя через `choice.photoName(for:)`, и в режиме `single`
    /// (а первый же положенный снимок переводит режим именно в него)
    /// любой ключ отдаёт один и тот же снимок. То есть ключ здесь
    /// выбирает не фотографию, а **вид подложки** — от него зависит
    /// высота и, через неё, куда ляжет текст.
    private func сФотографией<Исход>(_ данные: Data,
                                     ключ: ScreenKey = .sub("сторож-читаемости"),
                                     _ тело: (ScreenKey) throws -> Исход) throws -> Исход {
        let былоНаДиске = BackgroundBridge.читатьВыбор()
        let хранилище = BackgroundStore.shared
        let положено = хранилище.добавить(данные)
        defer {
            if положено { хранилище.убратьМои() }
            BackgroundBridge.записатьВыбор(былоНаДиске)
        }
        try #require(положено, """
            Снимок не лёг в общее хранилище фона. Это отказ СТЕНДА, \
            а не экрана: либо контейнер группы недоступен, либо пять мест \
            уже заняты чужим тестом. Замер не состоялся — читать число \
            ниже нельзя.
            """)
        try #require(BackgroundStore.shared.background(for: ключ) != nil,
                     "хранилище фона снимок приняло и не отдаёт — замер не состоялся")
        return try тело(ключ)
    }

