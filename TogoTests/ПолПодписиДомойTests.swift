import Testing
import Foundation
import SwiftUI
import UIKit
@testable import Togo

/// Подпись «Домой» на слайдере не гаснет ниже порога читаемости
/// ни в одной живой теме.
///
/// # Почему этот сторож вообще может существовать
///
/// До 26.10.2026 его не было и быть не могло: подпись гасла
/// `1 − ход · 0,7` до нуля, то есть её прозрачность зависела
/// **от жеста**, а не от токена, и статическому замеру предъявить
/// было нечего. Решение Виктории 26.10 завело пол (`полПодписи`),
/// и этим предмет стал проверяемым арифметикой: у худшей точки жеста
/// появился адрес-константа.
///
/// ```
/// было    .opacity(1 − min(1, сдвиг/ход) · 0.7)          дно 0,0
/// стало   .opacity(max(полПодписи, 1 − … · 0.7))         дно 0,7
/// ```
///
/// # Что он мерит
///
/// **КОМПОЗИТ, а не цвет.** Контраст считается на том, что нарисовано:
/// белый с прозрачностью `полПодписи` накладывается на дорожку
/// (`Surface.control`), и сравнивается с той же дорожкой. Спрашивать
/// `Token.Ink.primary` как есть было бы замером не того предмета —
/// без прозрачности подпись даёт 11,35 и проходит всегда.
///
/// ```
/// белый на Surface.control, α =   1       0,545 (на пороге)   0,7 (пол)
/// dark      #3A3A3C            11,3490   4,6308 выходит     6,5030
/// darkHC    #48484A             9,1250   4,0105 НЕ ХВАТАЕТ   5,4620
/// ```
///
/// Худшая точка жеста — **конец хода**, и пол делает её равной
/// `полПодписи` в обоих режимах. Поэтому проверять достаточно пол:
/// всё, что выше него, выше и по контрасту (`1 − x · 0,7`
/// монотонна, а контраст по прозрачности на тёмной подложке растёт).
///
/// # Прозрачность берётся ИЗ ПРОДУКТА, а не повторяется числом
///
/// `WalkHomeSlider.полПодписи` читается напрямую. Сторож, несущий
/// свою копию `0.7`, мерил бы себя и остался бы зелёным, если пол
/// в продукте опустят, — ровно тот отказ, от которого этот набор
/// и ставится. По той же причине константа в продукте `internal`,
/// а не `private`.
///
/// Цвета спрашиваются у `Color.resolvedHex(dark:highContrast:)`, то есть
/// у системы, а не у нашего `Dyn`: сторож, спрашивающий `Dyn`, сверял бы
/// наши четыре числа с нашими же четырьмя.
///
/// # Почему набор ОТДЕЛЬНЫЙ
///
/// Не по вкусу, а по устройству приёмки. Единица блокировки подделки —
/// **набор**: `check_guard.py:102` судит кодом возврата
/// `xcodebuild test -only-testing:<набор>` и отказывается до подделки,
/// если у набора есть объявленное красное. У соседа по предмету
/// (`ПовышенныйКонтрастМеняетЦветTests`) объявленные красные были,
/// и, положи я сторожа туда, `make guard` на нём был бы невозможен.
///
/// Приёмка названа Викторией в задании дословно: **тест обязан
/// краснеть при `полПодписи = 0.6`**.
///
/// ```
/// make guard ФАЙЛ=Togo/Features/Needs/WalkControls.swift \
///            БЫЛО="полПодписи: Double = 0.7" \
///            СТАЛО="полПодписи: Double = 0.6" \
///            НАБОР=TogoTests/ПолПодписиДомойTests
/// ```
///
/// Ломать надо **прозрачность, а не цвет**: сторож мерит композит
/// белого с заливкой при данной прозрачности, и подмена одного конца
/// пары (скажем, заливки на чёрную) оставила бы его зелёным — белый
/// на чёрном читается прекрасно, и вывод «сторож слеп» был бы ложным.
///
/// # Чего этот сторож НЕ видит
///
/// - **Пиксель.** Он мерит значения, разрешённые системой. Перекрытие
///   цвета стилем и вторую прозрачность на предке он не поймает:
///   `AppFont` однажды победил `foregroundStyle` предка, и главная
///   кнопка давала 1,68:1 при верном токене. Приёмка поверхности —
///   кадр, и снимает его не автор.
/// - **Саму форму выражения.** Он проверяет, что `полПодписи` годится,
///   а не что её позвали. Вырежи `max(...)` из `.opacity` — набор
///   останется зелёным. Это осознанная граница: сторож на «позвали ли»
///   стоял бы на имени механизма и краснел бы от замены способа.
/// - **Светлые режимы.** Их здесь нет нарочно: `UIUserInterfaceStyle
///   = Dark` в обоих plist (решение Виктории 23.10), и значения
///   `light`/`lightHC` на устройство не попадают. Вернутся вместе
///   со светлой темой.
@MainActor
@Suite("Подпись «Домой» не гаснет ниже порога")
struct ПолПодписиДомойTests {

    /// Порог текста по WCAG 1.4.3. Подпись — 20 pt regular, то есть
    /// не крупный текст в смысле стандарта (крупный с 18 pt **bold**
    /// либо 24 pt), поэтому 4,5, а не 3,0.
    static let порог = 4.5

    struct Режим: Sendable {
        let имя: String
        let тёмная: Bool
        let контраст: Bool
    }

    /// Только живые режимы. Светлых на устройстве нет (см. голову).
    static let режимы = [
        Режим(имя: "Dark", тёмная: true, контраст: false),
        Режим(имя: "Dark HC", тёмная: true, контраст: true),
    ]

    // MARK: Было что сторожить

    /// Первым и всегда: набору, которому нечего мерить, молчать так же
    /// легко, как набору, у которого всё хорошо.
    ///
    /// Три проверки, и каждая с ответом, известным ДО прогона:
    /// инструмент различает режимы, пол лежит в своих границах,
    /// и арифметика **умеет краснеть**.
    @Test("Было что сторожить: режимы различимы, пол на месте, счёт умеет краснеть")
    func былоЧтоСторожить() throws {
        #expect(Self.режимы.count == 2, """
            режимов \(Self.режимы.count), ожидалось 2 — сломан список.
            """)

        // 1. Инструмент действительно разрешает два РАЗНЫХ режима.
        //    Если бы повышенный контраст не доходил, обе клетки
        //    совпали бы байт в байт и весь набор мерил бы один режим
        //    дважды.
        let дорожкаDark = Self.байты(Token.Surface.control, Self.режимы[0])
        let дорожкаHC = Self.байты(Token.Surface.control, Self.режимы[1])
        #expect(дорожкаDark != дорожкаHC, """
            ЗАЛИВКА ДОРОЖКИ ОДИНАКОВА В DARK И DARK HC: \
            \(Self.hex(дорожкаDark)) против \(Self.hex(дорожкаHC)).
            Либо повышенный контраст не доходит до разрешителя, либо
            у `Surface.control` пропала HC-ступень. В обоих случаях
            набор ниже мерит один режим дважды и его зелёное пусто.
            """)

        // 2. Пол — доля, а не что попало.
        #expect(WalkHomeSlider.полПодписи > 0 && WalkHomeSlider.полПодписи <= 1, """
            `полПодписи` = \(WalkHomeSlider.полПодписи) — не доля \
            прозрачности. Ожидалось (0; 1].
            """)

        // 3. ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ, снятый той же арифметикой и в том
        //    же замере, что предмет. 0,3 — это дно ПРЕЖНЕГО гашения
        //    (конец хода без пола). Если счёт при нём не краснеет,
        //    значит он не умеет краснеть вовсе, и зелёное предмета
        //    ничего не стоит.
        let дно = Self.контрастПодписи(альфа: 0.3, режим: Self.режимы[1])
        #expect(дно < Self.порог, """
            СЧЁТ НЕ УМЕЕТ КРАСНЕТЬ: при прозрачности 0,3 в Dark HC \
            он даёт \(Self.четыре(дно)) при пороге \(Self.порог).
            Ожидалось около 2,2790 — это прежнее дно гашения, заведомо
            непроходное. Значит сломан композит или разрешитель,
            и зелёное главной проверки — отчёт инструмента о себе.
            """)
    }

    // MARK: Предмет

    /// Подпись на полу гашения берёт порог в обоих живых режимах.
    @Test("Подпись «Домой» на полу прозрачности берёт порог 4,5")
    func подписьНаПолуБерётПорог() throws {
        var непрошли: [String] = []
        var замеры: [String] = []
        var осмотрено = 0

        for режим in Self.режимы {
            осмотрено += 1
            let v = Self.контрастПодписи(альфа: WalkHomeSlider.полПодписи, режим: режим)
            let исход = v >= Self.порог ? "выходит" : "НЕ ХВАТАЕТ"
            замеры.append("\(режим.имя) \(Self.четыре(v)) \(исход)")
            if v < Self.порог { непрошли.append("\(режим.имя): \(Self.четыре(v))") }
        }

        #expect(осмотрено == Self.режимы.count, """
            осмотрено \(осмотрено) режимов из \(Self.режимы.count).
            """)

        #expect(непрошли.isEmpty, """
            ПОДПИСЬ «ДОМОЙ» УХОДИТ ПОД ПОРОГ ЧИТАЕМОСТИ
            при прозрачности \(WalkHomeSlider.полПодписи) в режимах: \
            \(непрошли.joined(separator: ", ")) — порог \(Self.порог).

            Замеры: \(замеры.joined(separator: " · ")).

            ЧТО НЕ ВИДИТ ЧЕЛОВЕК. «Домой» — ЕДИНСТВЕННЫЙ путь закончить
            прогулку смахом, и гаснет подпись ровно там, где палец
            доводит жест (`порог` = 0,65). Хуже всего это бьёт по тому,
            кто включил «Повысить контраст»: в Dark HC заливка дорожки
            СВЕТЛЕЕ (#48484A против #3A3A3C), и гашеный белый на ней
            теряет больше. Он просил, чтобы читать стало легче.

            ПОЧЕМУ ПОЛ 0,7, А НЕ 0,6. Порог начинается с 0,6008:
            при 0,6 в Dark HC выходит 4,4927 — не хватает сотой.
            Решение Виктории 26.10.2026, и 0,6 отвергнуто ей замером,
            а не вкусом.

            НЕ ЯВЛЯЕТСЯ ПОЧИНКОЙ: опустить порог до 3,0. Подпись — 20 pt
            regular, крупным текстом в смысле WCAG 1.4.3 она не является
            (крупный — с 18 pt bold либо 24 pt), и 3,0 здесь было бы
            правкой числа вместо работы.

            НЕ ЯВЛЯЕТСЯ ПОЧИНКОЙ И ОСВЕТЛЕНИЕ ДОРОЖКИ: `#3A3A3C` —
            прямое слово дизайна от 23.10.2026, и за ним стоит
            разведение `Surface.control` с `Surface.sunken`.
            """)
    }

    // MARK: Границы

    /// Печатается всегда и нарочно в зелёном тесте: границы, лежащие
    /// только в доккомментарии, читает тот, кто открыл файл, а числа
    /// из лога — тот, кто смотрит прогон. Это разные люди.
    @Test("Границы набора про пол подписи «Домой» названы")
    func границыНазваны() {
        let dark = Self.контрастПодписи(альфа: WalkHomeSlider.полПодписи, режим: Self.режимы[0])
        let hc = Self.контрастПодписи(альфа: WalkHomeSlider.полПодписи, режим: Self.режимы[1])
        print("""
            ГРАНИЦЫ НАБОРА «подпись Домой не гаснет ниже порога»:

            МЕРЕНО   композит белого (`Ink.primary`) с прозрачностью
                     `WalkHomeSlider.полПодписи` = \(WalkHomeSlider.полПодписи)
                     на дорожке (`Surface.control`), два живых режима.
                     Прозрачность взята ИЗ ПРОДУКТА, не повторена числом.
                     Dark \(Self.четыре(dark)) · Dark HC \(Self.четыре(hc)),
                     порог \(Self.порог).

            НЕ МЕРЕНО
              пиксель        перекрытие цвета стилем и вторая
                             прозрачность на предке видны только на кадре
              вызов          что `полПодписи` ПОЗВАЛИ в `.opacity`,
                             сторож не проверяет — вырезанный `max`
                             оставит его зелёным. Сторож на имя
                             механизма краснел бы от замены способа
              светлые        `light`/`lightHC` на устройство не попадают
                             (UIUserInterfaceStyle = Dark, 23.10.2026)
              сам жест       что ход доходит до 0,65 и что ручка
                             достаётся большим — это кадр и рука

            ПРИЁМКА ПОДДЕЛКОЙ названа Викторией: краснеет при
            `полПодписи = 0.6`. Ломать прозрачность, а не цвет —
            сторож мерит ОТНОШЕНИЕ, и подмена одного конца пары
            оставила бы его зелёным.
            """)
    }

    // MARK: Счёт

    /// Контраст подписи при данной прозрачности на дорожке.
    ///
    /// Порядок наложения тот же, которым рисует система: дорожка
    /// ложится на страницу, подпись — на дорожку. Своя альфа чернил
    /// умножается на `альфа` жеста, иначе две прозрачности
    /// перемножились бы молча.
    private static func контрастПодписи(альфа: Double, режим: Режим) -> Double {
        let страница = Self.составляющие(Token.Surface.screen, режим)
        let дорожка = Self.наложить(Self.составляющие(Token.Surface.control, режим),
                                    на: страница)
        var чернила = Self.составляющие(Token.Ink.primary, режим)
        чернила.3 *= альфа
        let нарисовано = Self.наложить(чернила, на: дорожка)
        let l1 = Self.яркость(нарисовано), l2 = Self.яркость(дорожка)
        return (max(l1, l2) + 0.05) / (min(l1, l2) + 0.05)
    }

    /// `0xRRGGBBAA`, как его отдаст система тому, кто рисует.
    private static func байты(_ цвет: Color, _ режим: Режим) -> UInt32 {
        цвет.resolvedHex(dark: режим.тёмная, highContrast: режим.контраст)
    }

    private static func hex(_ v: UInt32) -> String {
        String(format: "#%08X", v)
    }

    private static func составляющие(_ цвет: Color, _ режим: Режим)
        -> (Double, Double, Double, Double) {
        let hex = Self.байты(цвет, режим)
        return (Double((hex >> 24) & 0xFF) / 255, Double((hex >> 16) & 0xFF) / 255,
                Double((hex >> 8) & 0xFF) / 255, Double(hex & 0xFF) / 255)
    }

    /// Арифметика повторена из `ПовышенныйКонтрастМеняетЦветTests`
    /// нарочно: набор, который зовёт чужой `private`-счётчик, краснеет
    /// от чужой правки.
    private static func наложить(_ верх: (Double, Double, Double, Double),
                                 на низ: (Double, Double, Double, Double))
        -> (Double, Double, Double, Double) {
        let a = верх.3
        return (верх.0 * a + низ.0 * (1 - a),
                верх.1 * a + низ.1 * (1 - a),
                верх.2 * a + низ.2 * (1 - a),
                1)
    }

    private static func яркость(_ c: (Double, Double, Double, Double)) -> Double {
        func лин(_ x: Double) -> Double {
            x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4)
        }
        return 0.2126 * лин(c.0) + 0.7152 * лин(c.1) + 0.0722 * лин(c.2)
    }

    private static func четыре(_ x: Double) -> String {
        String(format: "%.4f", x).replacingOccurrences(of: ".", with: ",")
    }
}
