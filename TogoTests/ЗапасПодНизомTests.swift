import Testing
import Foundation
@testable import Togo

/// Запас под закреплённым низом не задаётся числом.
///
/// **Повод измерен, а не предположен.** В `TGScreen` стояло
/// `.padding(.bottom, … : 120)`, а панель занимает сумму высот своих
/// блоков плюс отступы:
///
/// ```
/// OnboardingSteps:301  60 + 8 + 50 = 118  плюс нижний отступ 8  = 126   −6 ✗
/// OnboardingSteps:346  то же                                            −6 ✗
/// OnboardingSteps:130  60 + 8 + 44 = 112  плюс 8               = 120     0 ⚠
/// остальные десять слотов                                          +26…+62
/// ```
///
/// Различитель — не размер, а **достижимость**: у десяти слотов
/// последний блок выходит из-под панели, если прокрутить до упора,
/// а у `:301` и `:346` последние шесть точек не выходят никогда.
/// Терялись при этом шаг приглашения («за безопасность собаки денег
/// не берём»), строка про одно напоминание вместо восьми и объяснение
/// про вкладку «Здоровье» — то есть онбординг, первое, что увидит
/// приглашённый.
///
/// # Почему сторож стоит ЗДЕСЬ, а не на местах вызова
///
/// Первая мысль была считать слоты по `} bottom: {`. Так считал
/// и наряд, и число вышло верное — **случайно**: три файла со слотом
/// не содержат ни одного `TGScreen(`, потому что пишутся
/// `TGScreen { … }`, замыкающим замыканием без скобок. Совпади
/// у кого-нибудь `bottom: {` на одной строке с содержимым — слот
/// не нашёлся бы, и мы считали бы двенадцать, не зная об этом.
///
/// > **Шаблон, опирающийся на то, КАК отформатирован вызов, а не
/// > на то, ЧТО вызывается, бывает верен по счёту случайно.**
///
/// Поэтому ось взята от самого `TGScaffolds` — от места, где запас
/// задаётся. Тогда и тринадцатый слот, и четырнадцатый попадают
/// под правило сами, как бы их ни отформатировали.
///
/// # Форма — от запрета
///
/// Не «запас равен высоте панели» (требование: у верного десять форм,
/// и проверить его надёжно нельзя), а **«в запас не подставлено
/// число»**. Запрет узнаётся по своему корню.
///
/// # Чего этот сторож НЕ видит
///
/// Он читает исходник, то есть отвечает «запас выводится», а не
/// «текст виден». «Позвали высоту, а она вернула ноль» — не его класс;
/// для него нужен кадр, и снимает его не автор: три онбординговых
/// экрана **в конце прокрутки**, плюс контроль на проходящем слоте
/// (`:154`, запас +52) в том же прогоне. Если обрезаны оба — разница
/// про способ съёмки, а не про экраны.
@Suite("Запас под закреплённым низом выводится, а не задаётся")
struct ЗапасПодНизомTests {

    private static var исходник: String {
        get throws {
            let корень = URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent().deletingLastPathComponent()
            return try String(
                contentsOf: корень.appendingPathComponent(
                    "Togo/DesignSystem/Components/TGScaffolds.swift"),
                encoding: .utf8)
        }
    }

    /// Строки кода без комментариев: сторож, не различающий код
    /// и прозу, меряет прозу — а прямо над правкой стоит объяснение,
    /// в котором число 120 упомянуто как то, чего делать нельзя.
    private static func код(_ текст: String) -> [String] {
        текст.components(separatedBy: "\n")
            .map { $0.components(separatedBy: "//")[0] }
    }

    @Test("В запас под низом не подставлено число")
    func запасНеЧисло() throws {
        let строки = Self.код(try Self.исходник)

        // Своё зрение первым. Файл, который перестали находить, молчит
        // так же, как чистый; и вырезание комментариев, съевшее весь
        // файл, тоже.
        #expect(строки.count > 100, """
            в TGScaffolds.swift \(строки.count) строк кода — файл не тот
            или прочитан пустым.
            """)
        #expect(строки.contains { $0.contains("struct TGScreen<") }, """
            `TGScreen` переименован или уехал из файла — сторож смотрит
            в пустоту.
            """)

        // Было ли что сторожить: запас обязан существовать как строка.
        let запасы = строки.enumerated().filter { $0.element.contains(".padding(.bottom,") }
        #expect(!запасы.isEmpty, """
            ни одного `.padding(.bottom,` в каркасах. Ноль нарушений
            при нуле найденных запасов значит «нечего было смотреть»,
            а не «чисто».
            """)

        // Нарушение — ЧИСЛО в аргументе отступа. Токены цифру несут
        // в имени (`Token.Space.s24`), поэтому сперва вычёркиваются
        // имена целиком, и только в остатке ищется цифра.
        //
        // **Первая редакция правила была «цифра, не приклеенная
        // к букве», и она покраснела на `Token.Space.s28`:** у восьмёрки
        // слева двойка, справа скобка, ни одна не буква. Поймал это
        // не глаз, а прогон правила на живом файле до того, как оно
        // стало тестом.
        //
        // > **Вторую половину инструмента гонять на живых данных
        // > прежде, чем считать его готовым: чтением этот класс
        // > не ловится.**
        let имя = try! NSRegularExpression(pattern: "[A-Za-z_\\u0400-\\u04FF][A-Za-z0-9_\\u0400-\\u04FF.]*")
        var нарушения: [String] = []
        for (номер, строка) in запасы {
            guard let открывающая = строка.range(of: ".padding(.bottom,") else { continue }
            let аргумент = String(строка[открывающая.upperBound...])
            let остаток = имя.stringByReplacingMatches(
                in: аргумент,
                range: NSRange(аргумент.startIndex..., in: аргумент),
                withTemplate: " ")
            guard остаток.contains(where: \.isNumber) else { continue }
            нарушения.append("  TGScaffolds.swift:\(номер + 1): "
                             + строка.trimmingCharacters(in: .whitespaces))
        }

        #expect(нарушения.isEmpty, """
            запас под закреплённым низом задан числом в \(нарушения.count) местах:

            \(нарушения.joined(separator: "\n"))

            Число здесь не знает, что в слоте. Панель с двумя кнопками
            занимает 126 точек при константе 120, и шесть точек текста
            не выходят из-под неё НИКОГДА — на шаге приглашения
            в онбординге. Другая константа, побольше, закроет три
            сегодняшних слота и вернёт дефект на первом крупном кегле:
            при увеличенном Dynamic Type подпись растёт, кнопка идёт
            выше `minHeight`, и в минус уходят слоты с запасом +26.

            Запас берётся у настоящей высоты панели — `TGScreen.высотаНиза`,
            измеренной на отрисовке. Выводи, не подставляй.
            """)
    }

    @Test("Высота низа измеряется, а не считается по содержимому слота")
    func высотаИзмеряется() throws {
        let строки = Self.код(try Self.исходник)
        let тело = строки.joined(separator: "\n")

        // # ОСЬ СПРАШИВАЕТ СВОЙСТВО, А НЕ ИМЯ МЕХАНИЗМА
        //
        // Здесь до 26.10.2026 стояли три требования КОНКРЕТНЫХ ИМЁН:
        // `высотаНиза`, `GeometryReader`, `Color.clear`. Все три
        // покраснели на здоровом коде, когда каркас переехал
        // на `.safeAreaInset` (`654d4f5`, 25.10 20:39). Старый механизм
        // снят ЦЕЛИКОМ и нарочно — объяснение в `TGScaffolds.swift:187`:
        //
        // > «`safeAreaInset` не кладёт панель поверх — он УМЕНЬШАЕТ
        // > область», и потому `GeometryReader`, `@State высотаНиза`
        // > и `запасПодНизом` убраны вместе.
        //
        // **Новый способ низ не измеряет вовсе, и это не потеря,
        // а снятие задачи.** Ось «измеряется ли высота» спрашивала
        // про ИНСТРУМЕНТ, который перестал быть нужен.
        //
        // Наблюдаемое свойство, одно на оба способа: **низ получает
        // СВОЁ место, а не кладётся поверх содержимого.** Добивается
        // этого либо система (`safeAreaInset`), либо замер с отступом
        // (`GeometryReader` + сохранённая высота). Любой из двух годится.
        let своёМесто = тело.contains("safeAreaInset")
        let замерСОтступом = тело.contains("GeometryReader") && тело.contains("высотаНиза")

        #expect(своёМесто || замерСОтступом, """
            низ `TGScreen` не получает своего места НИ ОДНИМ способом:
            ни `.safeAreaInset`, ни замера высоты с отступом
            (`GeometryReader` + `высотаНиза`) в теле нет.

            Значит панель снова лежит ПОВЕРХ содержимого, и нижняя
            строка уходит под неё — ровно дефект, от которого этот
            набор заведён. Арифметика по числу кнопок его не ловит:
            она зелёная на `:130` и пропускает случай 112 против 112,
            то есть «две кнопки» — следствие, а не причина.

            Ось спрашивает СВОЙСТВО, а не имя: сменить способ можно,
            оставить низ поверх — нет.
            """)

        // Прозрачность слоя замера проверяется ТОЛЬКО при старом
        // способе: у `safeAreaInset` слоя замера не существует,
        // и требовать от него `Color.clear` значит требовать
        // присутствия снятого механизма — ровно та ошибка, от которой
        // лечится этот файл.
        if замерСОтступом && !своёМесто {
            #expect(тело.contains("Color.clear"), """
                слой замера перестал быть прозрачным. Он существует,
                чтобы отдать высоту, и не должен ничего рисовать:
                подложка у низа `TGScreen` — решение дизайна,
                у соседнего `TGSheet` она есть, здесь её нет.
                """)
        }

        // Граница, названная в самом сторожe: он видит СПОСОБ и не
        // видит, что вышло на экране. Ноль вместо высоты у старого
        // способа и нулевая панель у нового дали бы прежний дефект
        // при зелёном стороже — это ловится только кадром в конце
        // прокрутки.
        print("ЗАПАС ПОД НИЗОМ: своё место через \(своёМесто ? "safeAreaInset" : замерСОтступом ? "замер с отступом" : "НИЧЕГО")")
    }
}
