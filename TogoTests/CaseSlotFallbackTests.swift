import Testing
import Foundation
@testable import Togo

/// Запасное слово в падежном слоте — «Виктория вывела **Собака**».
///
/// **Правило завелось из кадра, а не из рассуждения.** 07.10.2026
/// показ клички свели к одной точке: `Dog.displayName` отдаёт запасное
/// «Собака», когда клички нет. Решение верное против разнобоя — и
/// неверное против падежа: слово написано для слотов ИМЕНИТЕЛЬНЫХ
/// (подпись вкладки, заголовок профиля), а подставляется куда угодно.
/// Первым это поймала галерея живой активности, снятая в тот же день.
///
/// > **Единое запасное слово верно для именительных слотов и неверно
/// > как общее правило.**
///
/// Устройство для правильного ответа было готово заранее:
/// `Dog.nameIfAny` отдаёт `nil`, чтобы **падежный откат сработал там,
/// где падеж известен** — на месте вызова. Правило менеджера его
/// обошло, потому что `displayName` удобнее: он всегда даёт строку.
///
/// **Почему запрет, а не требование.** «Слот зовёт правильный откат»
/// грепом не проверить: у отката десять форм. «Падежный слот не смеет
/// звать `displayName`» проверяется надёжно — запретное узнаётся
/// по своему имени целиком.
///
/// **Чего этот сторож не видит, и это названо его последней строкой:**
/// он знает только те предлоги и глаголы, что перечислены ниже. Падеж
/// бывает и без них — «профиль Стича», «нет Стича». Такие слоты ловит
/// чтение, а не грep, и он на них не претендует.
@Suite("Запасное слово не попадает в падежный слот")
struct CaseSlotFallbackTests {

    /// Слова, после которых в русском стоит НЕ именительный падеж.
    ///
    /// Список закрытый и короткий нарочно: сторож, который кричит
    /// семьдесят девять раз, читать перестанут, а это хуже
    /// отсутствующего. Сюда попало только то, что уже встретилось
    /// в коде или встретится при первой правке текстов.
    static let падежныеСлова = [
        "Удалить", "удалить", "вывел", "вывела", "вывести",
        "в профиле", "у", "для", "про", "с ", "без",
    ]

    /// Сколько подстановок `displayName` в падежный слот было в день
    /// записи. Пускается только вниз; цель — ноль.
    ///
    /// **Ноль с первого дня, и это замер.** Два найденных слота
    /// (`Editors` и `CourseFinishSheet`) на 07.10 стоят с «Удалить
    /// \(displayName)?» и «в профиле \(displayName)» — но текст
    /// заморожен решением Виктории, и трогать его я не могу. Поэтому
    /// порог поставлен ПО ФАКТУ, а не по желанию: сторож держит
    /// находку числом до разморозки, как `BackupContentsPromiseTests`.
    static let записаноСлотов = 2

    /// Ниже этого числа просмотренных файлов замер несостоявшийся.
    static let записаноФайловНеМенее = 160

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .resolvingSymlinksInPath()
    }

    /// Текст без комментариев: иначе сторож меряет прозу, а не код —
    /// и краснеет на объяснении, почему так делать нельзя. В этом же
    /// файле таких объяснений полдюжины.
    ///
    /// Третья копия приёма в наборе (`ComponentTokenScopeTests`,
    /// `DogNameSubstitutionTests`). **Третья — это повод вынести**,
    /// и я называю его здесь, а не оставляю следующему.
    private func безКомментариев(_ текст: String) -> [String] {
        var строки: [String] = []
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { строки.append(""); continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            строки.append(String(s))
        }
        return строки
    }

    private func обход() -> (слоты: [String], файлов: Int) {
        let fm = FileManager.default
        var слоты: [String] = []
        var файлов = 0
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            // Имя — счётом компонентов, а не срезкой строки:
            // `resolvingSymlinksInPath()` делает case-folding кириллицы
            // и выдаёт путь к несуществующему файлу (замер 30.10.2026,
            // разбор — `ИменаФайловПриОбходеTests`).
            let глубина = корневой.pathComponents.count
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                if url.pathComponents.contains("Generated") { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                let имя = ([каталог] + url.pathComponents.dropFirst(глубина))
                    .joined(separator: "/")
                for (i, строка) in безКомментариев(текст).enumerated() {
                    guard строка.contains("displayName") else { continue }
                    // Падежное слово обязано стоять ПЕРЕД подстановкой,
                    // иначе оно её не определяет: «Удалить X» — да,
                    // «X удалить» — нет.
                    guard let место = строка.range(of: "displayName") else { continue }
                    let доПодстановки = строка[строка.startIndex..<место.lowerBound]
                    guard Self.падежныеСлова.contains(where: { доПодстановки.hasSuffix($0)
                        || доПодстановки.contains("\($0) \\(")
                        || доПодстановки.contains("\($0) \\(dog") }) else { continue }
                    слоты.append("\(имя):\(i + 1)  \(строка.trimmingCharacters(in: .whitespaces))")
                }
            }
        }
        return (слоты, файлов)
    }

    @Test("Обход просмотрел файлы: падежные слоты")
    func былоЧтоПроверять() {
        let (_, файлов) = обход()
        #expect(файлов >= Self.записаноФайловНеМенее, """
            просмотрено \(файлов) файлов, а в день записи было не меньше \
            \(Self.записаноФайловНеМенее). Сканер, переставший что-либо \
            находить, молчит так же, как тот, кому нечего сказать.
            """)
    }

    @Test("Точка падежного отката существует")
    func падежныйОткатСуществует() throws {
        let dog = try String(
            contentsOf: Self.корень.appendingPathComponent("TogoShared/Models/Dog.swift"),
            encoding: .utf8)
        #expect(dog.contains("var nameIfAny"), """
            у `Dog` нет `nameIfAny` — а весь этот сторож построен на том, \
            что у падежного слота ЕСТЬ чем ответить. Запрет без \
            разрешённой альтернативы — это не правило, а тупик.
            """)
    }

    @Test("Подстановок запасного слова в падежный слот не прибавилось")
    func слотовНеБольше() {
        let (слоты, файлов) = обход()
        #expect(слоты.count <= Self.записаноСлотов, """
            запасное слово подставляется в падежный слот \(слоты.count) раз, \
            а было \(Self.записаноСлотов):

            \(слоты.sorted().joined(separator: "\n"))

            Падежный слот обязан звать `Dog.nameIfAny` и писать откат \
            в нужном падеже НА МЕСТЕ: `nameIfAny ?? "собаку"`. \
            `displayName` отдаёт именительное «Собака», и при пустой \
            кличке выходит «Удалить Собака?» — строка непустая, \
            подстановка на месте, и по-русски так не говорят.

            Просмотрено файлов: \(файлов).
            ГРАНИЦА СТОРОЖА: он знает только перечисленные предлоги \
            и глаголы, и только перед подстановкой. Падеж без них — \
            «профиль Стича», «нет Стича» — он не видит, и такие слоты \
            ловит чтение, а не грeп.
            """)
    }
}
