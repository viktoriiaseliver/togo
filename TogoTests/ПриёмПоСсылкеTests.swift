import Foundation
import Testing
@testable import Togo

/// Приглашение можно принять, вставив ссылку, — и разбор вставленного
/// не врёт ни в одну сторону.
///
/// # Что чинилось, и почему это не «новая фича»
///
/// До 26.10.2026 экран «Тебя позвали» был **указателем**: в нём стояла
/// строка `TGIconRow(symbol: "keyboard", title: "Адрес вводить негде")`,
/// а поля не было ни одного. Человек, открывший Togo раньше, чем нажал
/// ссылку, упирался в сообщение о том, что двери нет.
///
/// ```
/// ИЗМЕРЕНО      `togo.app/j/7KQ2-VX` из макета не существует
/// ВЫВЕДЕНО      «вводить негде»
/// НЕ ПРОВЕРЕНО  `CKContainer.shareMetadata(for:)` — одна строка,
///               и адрес CloudKit выдаёт настоящий, на `icloud.com`
/// ```
///
/// > **Отвергнут был вид адреса, а снят — вход.** Это обратная форма
/// > нашего «механизма без входа»: запрет, исполненный снятием входа,
/// > снаружи неотличим от сломанной дороги.
///
/// # Чего этот набор НЕ проверяет, и это названо здесь
///
/// Приём трогает приватную базу CloudKit, а она **неизмерима без её
/// личного iCloud** — второго конца у связи нет. Поэтому здесь
/// проверяется ровно то, что вынесено в чистое значение: разбор
/// вставленной строки. Что облако ответит на годный адрес — не знает
/// ни один наш тест, и писать «приём работает» по зелени этого набора
/// нельзя.
@Suite("Приём приглашения по вставленной ссылке")
struct ПриёмПоСсылкеTests {

    /// Настоящий вид, который выдаёт CloudKit.
    private static let живой = "https://www.icloud.com/share/0A1b2C3d4E5f6G7h8I9j"

    // MARK: - Сначала проверка, что набору было что проверять

    /// **Положительный и отрицательный контроль в ОДНОМ тесте**,
    /// и это не экономия на строках.
    ///
    /// Разбор отвечает перечислением, и у него есть исход, который
    /// получается при **любом** отказе сканера: `.неПриглашение`.
    /// Сломай разбор целиком — и половина набора ниже останется
    /// зелёной, потому что ждёт именно его. Поэтому сперва показываем,
    /// что две крайние точки различимы, и только потом меряем края.
    @Test("Контроль: живой адрес и мусор различимы")
    func оснасткаРаботает() {
        #expect(ПриёмПоСсылке.разобрать(Self.живой).годная != nil,
                """
                настоящий адрес CloudKit не опознан. Всё, что ниже ждёт \
                `.неПриглашение`, зелено бы и при полностью сломанном \
                разборе.
                """)
        #expect(ПриёмПоСсылке.разобрать("здравствуйте") == .неПриглашение)
    }

    // MARK: - Годное

    @Test("Голый адрес CloudKit годится")
    func голыйАдрес() {
        #expect(ПриёмПоСсылке.разобрать(Self.живой).годная?.absoluteString == Self.живой)
    }

    /// Так адрес показывает Safari и так его копируют из строки адреса.
    @Test("Адрес без схемы годится: его дописываем сами")
    func безСхемы() {
        let вставили = "www.icloud.com/share/0A1b2C3d"
        let разбор = ПриёмПоСсылке.разобрать(вставили)
        #expect(разбор.годная != nil, """
            адрес без «https://» не опознан. `URL(string:)` без схемы \
            отдаёт адрес БЕЗ хоста, то есть проверка домена получает \
            `nil` — и человек читает «это не похоже на приглашение» \
            про верную ссылку.
            """)
        #expect(разбор.годная?.host() == "www.icloud.com")
    }

    /// Человек копирует не адрес, а **сообщение**.
    @Test("Ссылка внутри фразы с точкой на конце годится")
    func вФразе() {
        let сообщение = """
            Привет! Вот приглашение в дневник Стича: \(Self.живой).
            Открой, пожалуйста.
            """
        #expect(ПриёмПоСсылке.разобрать(сообщение).годная?.absoluteString == Self.живой,
                """
                приклеенная точка сломала разбор. Это отказ НАШЕГО \
                сканера, поданный как «ссылка не годится» — то есть \
                инструмент отвечает про себя, а человек читает это \
                про свою ссылку.
                """)
    }

    @Test("Поддомен icloud.com годится")
    func поддомен() {
        #expect(ПриёмПоСсылке.разобрать("https://share.icloud.com/share/X1").годная != nil)
    }

    // MARK: - Края, в которых дешевле ошибиться в нашу сторону

    /// Самый дорогой из краёв.
    ///
    /// Отправь мы в облако любой адрес с `icloud.com` — на ссылку
    /// из «Фото» CloudKit ответит `unknownItem`, который у нас
    /// разбирается в `.сторонаПриложения`, то есть **«дело
    /// не в твоих настройках»**. Мы бы взяли на себя чужую опечатку,
    /// и человек перестал бы её искать.
    @Test("Ссылка на iCloud, но НЕ на приглашение, не уходит в облако")
    func iCloudНоНеПриглашение() {
        for чужое in ["https://www.icloud.com/photos/0abc",
                      "https://www.icloud.com/",
                      "https://www.icloud.com/iclouddrive/0xyz"] {
            #expect(ПриёмПоСсылке.разобрать(чужое) == .неПриглашение, """
                «\(чужое)» признан приглашением. Облако ответит \
                `unknownItem`, а это у нас «дело не в твоих \
                настройках» — ложь в самую дорогую сторону.
                """)
        }
    }

    /// Сравнение префиксом здесь уже оплачено в другом месте проекта:
    /// `hasPrefix("struct Swatch")` находит `struct SwatchRow`.
    @Test("Домен сравнивается целиком, а не началом и не вхождением")
    func доменЦеликом() {
        for подделка in ["https://icloud.com.phish.ru/share/X1",
                         "https://not-icloud.com/share/X1",
                         "https://icloudcom/share/X1"] {
            #expect(ПриёмПоСсылке.разобрать(подделка) == .неПриглашение,
                    "«\(подделка)» принят за icloud.com.")
        }
    }

    @Test("Пусто — это не ошибка человека, и у него свой исход")
    func пусто() {
        for ничего in ["", "   ", "\n\t "] {
            #expect(ПриёмПоСсылке.разобрать(ничего) == .пусто, """
                пустое поле разобрано как «\(ПриёмПоСсылке.разобрать(ничего))». \
                Человек ещё не начал, и красный текст под полем был бы \
                выговором за то, чего он не сделал.
                """)
        }
    }

    /// Вид из макета назван **своей** причиной, а не свален в «мусор».
    ///
    /// Причина не в аккуратности: этот вид человеку могли показать мы
    /// сами, и тогда отказ наш, а не его. Совет у двух причин разный —
    /// «возьми адрес на icloud.com» против «попроси прислать ссылку».
    @Test("Короткая ссылка из макета опознаётся отдельной причиной")
    func короткаяСсылка() {
        for вид in ["togo.app/j/7KQ2-VX",
                    "https://togo.app/j/7KQ2-VX",
                    "Вот ссылка: https://www.togo.app/j/7KQ2-VX"] {
            #expect(ПриёмПоСсылке.разобрать(вид) == .короткаяСсылка, """
                «\(вид)» разобран как \(ПриёмПоСсылке.разобрать(вид)), \
                а не как короткая ссылка. Совет «возьми адрес \
                на icloud.com» человек тогда не получит.
                """)
        }
    }

    /// Код приглашения — второй вход для того, кого уже позвали.
    ///
    /// Заведён 29.10.2026 по просьбе Виктории: «дай код, который я
    /// и мама можем ввести, если оно само не нашлось». Случай частый:
    /// iOS не передаёт ссылку через установку из App Store, а переписка
    /// ломает адрес точкой в конце фразы.
    ///
    /// Код — это ХВОСТ настоящего адреса (`icloud.com/share/<код>`),
    /// а не выдуманный короткий: короткий требует сервера, которого
    /// у Togo нет и не планируется.
    ///
    /// Подделка (29.10.2026): убрать из `разобрать` ветку кода —
    /// краснеет первая проверка, случай `togo.app/j/…` остаётся
    /// `.короткаяСсылка`, а «привет» остаётся `.неПриглашение`.
    @Test("Код приглашения принимается и достраивается в адрес")
    func кодомТоже() {
        // Токен настоящего вида: один кусок, законные знаки, длинный.
        let код = "0z1AbCdEfGhIjKlMnOpQrStUv"
        let разбор = ПриёмПоСсылке.разобрать(код)
        let адрес = try? #require(разбор.годная)
        #expect(адрес?.host()?.hasSuffix("icloud.com") == true, """
            код «\(код)» не стал адресом на icloud.com: разбор ответил \
            \(разбор). Человек, которому ссылка не доехала, остался \
            без второго входа.
            """)
        #expect(адрес?.path() == "/share/\(код)",
                "адрес собран не по виду icloud.com/share/<код>: \(адрес?.path() ?? "nil")")

        // Пробелы и мусор по краям — то, что приезжает из переписки.
        #expect(ПриёмПоСсылке.разобрать("  \(код)  ").годная != nil,
                "код с пробелами по краям обязан приниматься")
        #expect(ПриёмПоСсылке.разобрать("\(код).").годная != nil,
                "точка в конце фразы не должна ломать код")

        // А вот чего кодом считать НЕЛЬЗЯ — иначе облако ответит
        // «неизвестный элемент», и человек прочтёт это как нашу
        // поломку, хотя его просто не приглашали.
        for непохожее in ["привет", "ок", "да", "0z1AbCd", "два слова",
                          "icloud.com", "0z1AbCdEfGhIjKl.MnOp"] {
            #expect(ПриёмПоСсылке.разобрать(непохожее).годная == nil, """
                «\(непохожее)» принят за код приглашения. Приложение соберёт \
                из него адрес, облако ответит отказом, и отказ \
                прочитается как наш.
                """)
        }
    }

    /// Настоящий адрес рядом с выдуманным — настоящий сильнее.
    ///
    /// Отказать при живой ссылке в том же сообщении было бы отказом
    /// нашим: мы бы прочитали первое слово и не дочитали до рабочего.
    @Test("Настоящий адрес рядом с выдуманным побеждает")
    func настоящийСильнее() {
        let вперемешку = "короткая togo.app/j/7KQ2-VX, а полная \(Self.живой)"
        #expect(ПриёмПоСсылке.разобрать(вперемешку).годная?.absoluteString == Self.живой)
    }

    // MARK: - Тексты

    /// У `.годится` и `.пусто` текста нет **нарочно**.
    ///
    /// Подпись «всё верно» под полем, которое ещё ничего не сделало, —
    /// обещание вместо ответа: нажмёт и получит отказ облака. Исход
    /// приёма говорит `ShareAcceptanceOutcome`, и шестого текста для
    /// него не заводится.
    @Test("Говорящие исходы говорят разное, а молчащие молчат")
    func текстыРазные() {
        #expect(ПриёмПоСсылке.разобрать(Self.живой).текст == nil)
        #expect(ПриёмПоСсылке.Разбор.пусто.текст == nil)

        let тексты = [ПриёмПоСсылке.Разбор.короткаяСсылка.текст,
                      ПриёмПоСсылке.Разбор.неПриглашение.текст].compactMap { $0 }
        #expect(тексты.count == 2, "у говорящей причины пропал текст")
        #expect(Set(тексты).count == 2, """
            две причины говорят одно и то же: \(тексты). Один текст \
            на несколько причин даёт совет, неверный для остальных.
            """)
        for текст in тексты {
            #expect(текст.count > 20, "«\(текст)» слишком короткий, чтобы нести совет")
            #expect(текст.contains("icloud.com"), """
                «\(текст)» не называет, где взять правильный адрес. \
                Отказ без адреса не лечится.
                """)
        }
    }

    // MARK: - Вход. Тот самый, которого не было

    /// **Сторож стоит на ВХОДЕ, а не на механизме.**
    ///
    /// Механизм тут проверить тестом нельзя по устройству: приём идёт
    /// в приватную базу CloudKit. А вход — можно, и именно он восемь
    /// суток отсутствовал при полностью рабочем слое ниже.
    ///
    /// > Зелёный тест на `ПриёмПоСсылке` не отличает «поле есть»
    /// > от «поля нет»: тесты зовут разбор сами. Единственное, что это
    /// > различает, — **каким путём человек вставляет ссылку**,
    /// > и спросить про него может только разбор исходника экрана.
    ///
    /// # Граница сторожа названа, а не умолчана
    ///
    /// Текстовый сторож ловит «вход убрали из исходника» и слеп
    /// к «вход есть, но недостижим» — например если карточку обернут
    /// условием, которое никогда не истинно. Снимает эту границу
    /// только кадр, а кадра на поднятой клавиатуре у этого проекта
    /// нет ни одного годного.
    ///
    /// **Меряем КОД, а не прозу.** Комментарии вырезаны до разбора:
    /// сторож, не различающий код и объяснение, краснеет и зеленеет
    /// от доккомментария — а здесь доккомментарий как раз цитирует
    /// снятую строку «Адрес вводить негде», то есть сторож на сыром
    /// тексте отвечал бы про цитату.
    @Test("На экране «Тебя позвали» есть поле ввода и вызов приёма")
    func входЕсть() throws {
        let экран = try Self.исходник("Togo/Features/Onboarding/ПозвалиВСемью.swift")
        let код = Self.безКомментариев(экран)

        // Контроль: файл прочитан, это он, и вырезание комментариев
        // не съело код целиком. Без этого «строк нет» означало бы
        // отказ инструмента, а не отсутствие входа.
        #expect(экран.count > 2000, """
            экран прочитан на \(экран.count) знаков — чтение \
            не состоялось, и всё ниже сказало бы про инструмент.
            """)
        #expect(код.contains("struct ПозвалиВСемью"),
                "в коде без комментариев нет даже объявления экрана — разбор съел файл")

        #expect(код.contains("TextField"), """
            на экране «Тебя позвали» нет ни одного поля ввода. \
            Человек, открывший Togo раньше, чем нажал ссылку, снова \
            упирается в экран без двери.
            """)
        #expect(код.contains("принять(ссылку:"), """
            поле есть, а приёма нет: вставленный адрес никуда \
            не уходит. Это «вход есть, механизма нет» — и отказ \
            был бы наш, а не его.
            """)
        #expect(!код.contains("Адрес вводить негде"), """
            строка «Адрес вводить негде» вернулась в код экрана, \
            где поле уже есть. Два утверждения об одном органе, \
            и одно из них ложно.
            """)
    }

    /// И обратная половина: выдуманный адрес из макета не должен
    /// оказаться в подсказке поля.
    ///
    /// Человек введёт показанное и получит отказ — **и отказ будет
    /// нашим**. Это уже названный в проекте класс «вход есть,
    /// механизма нет», и ловился он не тестом, а пальцем.
    @Test("Подсказка поля не предлагает адрес, которого не бывает")
    func подсказкаНеВыдуманная() throws {
        let код = Self.безКомментариев(
            try Self.исходник("Togo/Features/Onboarding/ПозвалиВСемью.swift"))

        #expect(!код.contains("togo.app/j/"), """
            подсказка или текст экрана предлагает `togo.app/j/…` — \
            адрес, которого не существует. Человек введёт показанное \
            и получит отказ, и отказ будет наш.
            """)
        // Контроль того же разбора, в том же замере: настоящий вид
        // в коде ЕСТЬ. Иначе «выдуманного нет» означало бы, что нет
        // ничего.
        #expect(код.contains("icloud.com"), """
            после вырезания комментариев в коде экрана не осталось \
            даже `icloud.com` — разбор съел код, и проверка выше \
            сказала про сканер.
            """)
    }

    /// Строки, начинающиеся комментарием, выброшены.
    ///
    /// Грубо и нарочно: полноценный разбор Swift здесь не нужен,
    /// а один дефект разбора даёт ложный красный в одном тесте
    /// и ложную ЗЕЛЕНЬ в трёх. Хвостовые комментарии за кодом
    /// остаются — они короткие и имён вызовов в себе не несут.
    static func безКомментариев(_ исходник: String) -> String {
        исходник.split(separator: "\n", omittingEmptySubsequences: false)
            .map { String($0).trimmingCharacters(in: .whitespaces) }
            .filter { !$0.hasPrefix("//") }
            .joined(separator: "\n")
    }

    static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }
}
