import Testing
import Foundation
import SwiftData
@testable import Togo

/// Демо-набор Т4 — сверка заготовки приёмки с кадром дизайна.
///
/// Эталон — `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/14.png`
/// и пункт 10 `Дизайн/редизайн-ios28/ОТВЕТЫ-круг-2.md` (коммит
/// `816a96a`). Эти тесты не про показ: кадр судит человек. Они про то,
/// что **данные, на которых снимается кадр, те самые**, — иначе кадр
/// сверяется с эталоном по расстановке и молча расходится по числам.
///
/// # Чего эти тесты НЕ доказывают
///
/// Ни один из них не говорит, что заготовки нет в релизной сборке.
/// Тест компилируется в Debug и видит `#if DEBUG`-код по устройству;
/// утверждение о релизе проверяется символами в собранном бинарнике,
/// а не отсюда. Граница названа здесь, чтобы зелёный набор не читался
/// как ответ на тот вопрос.
@MainActor
@Suite("Демо-набор Т4 · заготовка приёмки")
struct ДемоТ4Tests {

    /// Собрать мир: янтарный сценарий (он несёт схему левотироксина
    /// с дозами 08:00 и 20:00) плюс заготовка поверх него.
    private func мир() throws -> (dog: Dog, медикаменты: [Medication]) {
        let контейнер = SeedData.makePreviewContainer(.amber)
        let контекст = контейнер.mainContext
        let собаки = try контекст.fetch(FetchDescriptor<Dog>())
        let собака = try #require(собаки.first { !$0.name.isEmpty })

        // **Проверка, что проверять было что, и она же контроль.**
        // До заготовки анализов быть не должно ни одного: если они
        // появятся из сценария, все числа ниже станут чужими,
        // а тесты продолжат зеленеть.
        #expect(собака.labResults.isEmpty,
                "сценарий amber завёл анализы сам — тогда ниже меряется не заготовка")

        SeedData.добавитьДемоТ4(to: собака, context: контекст)
        let медикаменты = try контекст.fetch(FetchDescriptor<Medication>())
        return (собака, медикаменты)
    }

    /// По возрастанию даты — так же, как читается таблица дизайна.
    private func поДате(_ собака: Dog) -> [LabResult] {
        собака.labResults.sorted { $0.sampledOn < $1.sampledOn }
    }

    @Test("Четыре точки с кадра 14: месяцы и числа один к одному")
    func четыреТочки() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)

        #expect(точки.count == 4, "на кадре 14 четыре строки Т4, а не \(точки.count)")
        #expect(точки.map(\.value) == [1.8, 2.6, 2.9, 3.1])

        let календарь = Calendar.current
        #expect(точки.map { календарь.component(.month, from: $0.sampledOn) } == [3, 5, 8, 10],
                "подписи на кадре — мар · май · авг · окт")

        #expect(точки.allSatisfy { $0.indicator == "Т4 общий" })
        #expect(точки.allSatisfy { $0.unit == "нмоль/л" })
        #expect(точки.allSatisfy { $0.dog?.persistentModelID == собака.persistentModelID })
    }

    @Test("Норма 1,0–4,5 у всех четырёх, и она СТОИТ, а не считается")
    func норма() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)

        #expect(точки.allSatisfy { $0.referenceLow == 1.0 && $0.referenceHigh == 4.5 })
        // Норма есть — значит экран скажет «норма 1,0–4,5», а не
        // «норма не указана». Обе ветки живые, и перепутать их легко.
        #expect(точки.allSatisfy { $0.reference == .range(low: 1.0, high: 4.5) })
    }

    @Test("Две точки из четырёх БЕЗ времени забора — нарочно")
    func двеБезВремени() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)

        // Красная линия проекта: не подставлять там, где подстановка
        // станет утверждением человека. Май и август пусты по решению
        // дизайна, а не по недосмотру, и экран обязан показать обе
        // ветки `LabSampleTiming` разом.
        #expect(точки.map { $0.sampledAt == nil } == [false, true, true, false])
    }

    @Test("Часы от дозы считаются в 3 и 5 — как подписано на кадре")
    func часыОтДозы() throws {
        let (собака, медикаменты) = try мир()
        let точки = поДате(собака)

        // Контроль инструмента: схема с утренней дозой действительно
        // активна. Без неё `sampleTiming` отвечал бы `.noTreatment`
        // на все четыре точки, и «не указано» ниже совпало бы
        // с ожидаемым ответом у двух из них — ложный ноль, совпавший
        // с ожиданием, не перепроверяет никто.
        let схемы = DoseScheduler.activeSchedules(of: собака, among: медикаменты)
        #expect(схемы.contains { $0.times.contains(SeedData.демоТ4УтренняяДоза) },
                "у собаки нет активной схемы с дозой 08:00 — часы считать не от чего")

        func время(_ анализ: LabResult) -> LabSampleTiming.Timing {
            DoseScheduler.sampleTiming(sampledAt: анализ.sampledAt,
                                       of: собака, among: медикаменты)
        }

        #expect(время(точки[0]) == .hoursSinceDose(3), "март: забор 11:00 при дозе 08:00")
        #expect(время(точки[1]) == .unknownDuringTreatment)
        #expect(время(точки[2]) == .unknownDuringTreatment)
        #expect(время(точки[3]) == .hoursSinceDose(5), "октябрь: забор 13:00 при дозе 08:00")
    }

    @Test("Маркеры графика выходят теми же, что на кадре: ● ○ ○ ■")
    func маркерыРазличимы() throws {
        let (собака, медикаменты) = try мир()
        let точки = поДате(собака)
        func время(_ анализ: LabResult) -> LabSampleTiming.Timing {
            DoseScheduler.sampleTiming(sampledAt: анализ.sampledAt,
                                       of: собака, among: медикаменты)
        }

        // Март (3 ч) и октябрь (5 ч) расходятся больше чем на порог
        // сравнимости — значит точки на графике НЕ сливаются в одну
        // линию без оговорки, и это ровно то, ради чего дизайн задал
        // две разные формы маркера.
        #expect(LabSampleTiming.comparable(время(точки[0]), время(точки[3])) == false)
        // А пустое время несравнимо ни с чем — пустой кружок.
        #expect(LabSampleTiming.comparable(время(точки[1]), время(точки[2])) == false)
        // График рисуется: точек больше одной.
        #expect(LabSampleTiming.chartMakesSense(resultCount: точки.count))
    }

    @Test("Ход в шапке — «↑ с 2,9»: предыдущая точка августовская")
    func ходСчитаетсяОтАвгуста() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)
        let последняя = try #require(точки.last)
        let предыдущая = try #require(точки.dropLast().last)

        #expect(последняя.value == 3.1)
        #expect(предыдущая.value == 2.9)
        #expect(предыдущая.sampledOn < последняя.sampledOn)
    }

    @Test("Лаборатория и номер бланка ПУСТЫ: дизайн их не называл")
    func ничегоНеВыдумано() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)

        #expect(точки.allSatisfy { $0.laboratory.isEmpty })
        #expect(точки.allSatisfy { $0.reportNumber.isEmpty })
        // Отметка лаборатории тоже пуста: показывать её можно только
        // рядом с нашим вердиктом и подписью «кто сказал», а на кадре
        // 14 ни того, ни другого нет.
        #expect(точки.allSatisfy { $0.labMark.isEmpty })
        // Метода нет ни у одной: поле без правила в графике тихо врёт.
        #expect(точки.allSatisfy { $0.method == nil })
    }

    @Test("Дозы с кадра сохранены заметкой — поля под них у модели нет")
    func дозыВЗаметке() throws {
        let (собака, _) = try мир()
        let точки = поДате(собака)

        // Экран списка заметку сегодня НЕ показывает — на кадре 14 доза
        // у каждой строки есть, в приложении её нет. Расхождение экрана
        // с макетом, не заготовки: числа лежат, показать их некому.
        #expect(точки.map(\.note) == ["доза 0,05 мг", "доза 0,1 мг",
                                      "доза 0,1 мг", "доза 0,1 мг"])
    }
}
