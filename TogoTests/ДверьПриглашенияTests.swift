import Testing
import Foundation

/// Дверь, через которую второй человек входит в дневник.
///
/// # Зачем сторож там, где всё написано верно
///
/// Приём приглашения на 08.10.2026 **цел и написан обеими половинами**
/// — это замерено, а не предположено. Сторож заводится не на дефект,
/// а на то, что его нечем удержать:
///
/// ```
/// снимается ОДНОЙ строкой   убрать configuration.delegateClass
/// симптом                   «нажала ссылку — ничего не произошло»
/// краснеет                  НИЧТО
/// исторически               ровно это уже случалось (TogoApp.swift)
/// ```
///
/// И кадром эта поверхность **непроверяема по устройству**: ссылку
/// открывает система, вне нашего процесса, на втором телефоне.
/// Значит текстовый сторож здесь не «слабая замена кадру», а
/// единственное, что вообще возможно.
///
/// # Три утверждения, и третье — главное
///
/// 1. горячий путь: `windowScene(_:userDidAcceptCloudKitShareWith:)`;
/// 2. холодный старт: `connectionOptions.cloudKitShareMetadata` —
///    при запуске **по ссылке** метод из пункта 1 не зовётся вовсе;
/// 3. **связка**: `configuration.delegateClass` присвоен классу делегата
///    сцены. Делегат, объявленный и не присвоенный, — это ровно прежний
///    дефект: обработчик стоял на делегате ПРИЛОЖЕНИЯ, и у приложения
///    со сценами он не зовётся никогда.
///
/// Первые два — «метод существует», третье — «его кто-то позовёт».
/// Без третьего первые два проверяют намерение.
///
/// # Почему разбор режет комментарии
///
/// В `TogoApp.swift` **оба имени стоят в прозе**: в головном
/// комментарии объясняется, почему дверей две и почему метод делегата
/// приложения не годится. Сторож, не различающий код и прозу, остался
/// бы зелёным на удалённом коде — у нас это уже было, и дважды:
/// `GroupingByDefaultTests` мерил свою же прозу, а сторож на вызов
/// краснел на комментарии о починке.
///
/// Проверяется это самим набором: тест `прозаНеСчитаетсяКодом` берёт
/// головной комментарий файла и требует, чтобы после вырезания в нём
/// не осталось ни одного искомого имени.
///
/// # Чего сторож НЕ доказывает
///
/// Что дверь **срабатывает** на живом приглашении. Это на слой выше
/// и проверяется только вторым телефоном: ссылку открывает iOS,
/// проверяя личность в iCloud. Сторож держит, что код написан
/// и связан, — то есть ровно то звено, которое снимается одной
/// строкой и никем не охраняется.
@Suite("Общий дневник · дверь приглашения")
struct ДверьПриглашенияTests {

    private static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь),
                          encoding: .utf8)
    }

    /// Код без комментариев: и `//`, и `///` режутся одинаково.
    ///
    /// Строковых литералов с `//` внутри в этом файле нет; если
    /// появятся — разбор придётся усложнить, и тогда об этом скажет
    /// `прозаНеСчитаетсяКодом`, а не чья-то память.
    private static func кодБезПрозы(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .joined(separator: "\n")
    }

    private static let файл = "Togo/App/TogoApp.swift"

    // MARK: Проверки

    /// Первой — что сторожу было что сторожить.
    @Test("Исходник двери разобран")
    func былоЧтоСторожить() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.файл))

        #expect(код.count > 500, """
            разбор `\(Self.файл)` дал \(код.count) знаков — файл не прочитан \
            или вырезание съело код целиком. Пустой результат за упавшим \
            разбором неотличим от пустого результата измеренного мира.
            """)
        #expect(код.contains("ShareAcceptSceneDelegate"), """
            в коде файла нет даже имени делегата сцены — дальше проверять \
            нечего, и все проверки ниже прошли бы на пустоте.
            """)
    }

    @Test("Горячий путь есть: приглашение приходит на делегат СЦЕНЫ")
    func горячийПуть() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.файл))

        #expect(код.contains("func windowScene("), """
            нет `windowScene(_:userDidAcceptCloudKitShareWith:)`. \
            Приглашение в открытое приложение не придёт никуда.
            """)
        #expect(код.contains("userDidAcceptCloudKitShareWith metadata"), """
            метод делегата сцены не принимает `CKShare.Metadata` — \
            значит это не та дверь.
            """)
    }

    @Test("Холодный старт есть: запуск ПО ССЫЛКЕ тоже доходит")
    func холодныйСтарт() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.файл))

        #expect(код.contains("connectionOptions.cloudKitShareMetadata"), """
            нет разбора `connectionOptions.cloudKitShareMetadata`. \
            При запуске приложения САМОЙ ССЫЛКОЙ метод делегата сцены \
            не зовётся вовсе — человек нажмёт приглашение на выключенном \
            телефоне и не попадёт в дневник ни разу.
            """)
    }

    /// Главное: делегат не просто объявлен, а присвоен.
    @Test("Делегат сцены присвоен конфигурации, а не только объявлен")
    func связкаНаМесте() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.файл))

        #expect(код.contains("configurationForConnecting"), """
            нет `application(_:configurationForConnecting:)` — \
            единственного способа SwiftUI подключить делегат сцены.
            """)
        // Имя целиком, а не префиксом: `hasPrefix` у нас находил
        // `SwatchRow` вместо `Swatch` и сверял другой компонент.
        #expect(код.contains("delegateClass = ShareAcceptSceneDelegate.self"), """
            `configuration.delegateClass` не присвоен \
            `ShareAcceptSceneDelegate`. Делегат объявлен и никем \
            не подключён — это ровно прежний дефект: обработчик стоял \
            на делегате ПРИЛОЖЕНИЯ, а у приложения со сценами он \
            не зовётся никогда. Снаружи это выглядит как «нажала \
            ссылку, и ничего не произошло».
            """)
    }

    @Test("Обе двери зовут один и тот же код приёма")
    func двериВедутВОдноМесто() throws {
        let код = Self.кодБезПрозы(try Self.исходник(Self.файл))
        let вызовов = код.components(separatedBy: "ShareAcceptance.accept(").count - 1

        #expect(вызовов >= 2, """
            `ShareAcceptance.accept(` зовётся \(вызовов) раз, а дверей две. \
            Дверь, которая никого не зовёт, — это метод, существующий \
            для вида.
            """)
    }

    /// Обратная половина: доказать, что разбор режет прозу.
    ///
    /// Без неё весь набор мог бы зеленеть на комментариях — и именно
    /// это у нас уже случалось. Проверка идёт на живом головном
    /// комментарии файла, а не на выдуманной строке.
    @Test("Проза не считается кодом в головном комментарии двери приглашения")
    func прозаНеСчитаетсяКодом() throws {
        let текст = try Self.исходник(Self.файл)
        guard let конец = текст.range(of: "final class ShareAcceptDelegate") else {
            #expect(Bool(false), "головной комментарий файла не найден — разбор не состоялся")
            return
        }
        let шапка = String(текст[..<конец.lowerBound])

        // Контроль: искомые имена в прозе ЕСТЬ. Если их там не станет,
        // эта проверка перестанет что-либо доказывать — и скажет об этом.
        #expect(шапка.contains("userDidAcceptCloudKitShareWith"), """
            в головном комментарии больше нет имени метода — контроль \
            пропал, и проверка ниже проходит на пустом месте.
            """)

        let безПрозы = Self.кодБезПрозы(шапка).trimmingCharacters(in: .whitespacesAndNewlines)
        #expect(!безПрозы.contains("userDidAcceptCloudKitShareWith"), """
            вырезание комментариев не работает: имя метода выжило \
            в прозе. Значит сторож выше мерит комментарий, а не код, \
            и останется зелёным на удалённой двери.
            """)
    }
}
