import Testing
import Foundation
@testable import Togo

/// Числа, написанные на экране «Семья» прописью, и их хозяин.
///
/// Кадр `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/12.png`
/// подписывает карточку ролей «Пять ролей, восемь прав», а карточку
/// брифинга — «пять строк без диагноза». Все три числа — **копии**:
/// настоящие живут в `FamilyRole.allCases`, `Permission.allCases`
/// и в полях `Dog.sitter*`. Две копии разойдутся молча, и разойдутся
/// они в тот день, когда кто-нибудь заведёт шестую роль, — а экран
/// будет по-прежнему обещать пять.
///
/// > **У числа про предмет хозяин называется в той же строке, где
/// > число стоит.** Здесь хозяин — это перечисление, а сторож —
/// > способ проверить за минуту, написанный рядом.
///
/// **Почему сторож на ПРОПИСЬ, а не на цифру.** Цифру экран не рисует:
/// на кадре слова, и слова же в коде. Сверять текст с числом иначе
/// нечем — значит сверять надо именно его, иначе храповика нет вовсе.
///
/// **Чего этот сторож не видит, последней строкой и здесь.** Он читает
/// исходник экрана, а не экран. «Строку позвали, а она вернула пустоту»
/// он не поймает — для этого нужен кадр. И он не знает других языков:
/// пропись в `en`, `fr`, `kk`, `uk` живёт в каталоге, который правит
/// другая сессия.
@Suite("Пропись на экране «Семья» сходится со счётом")
struct FamilyScreenCopyTests {

    /// Корень репозитория, с разрешёнными симлинками.
    ///
    /// `resolvingSymlinksInPath` — не аккуратность: на macOS `/tmp` это
    /// симлинк, и `#filePath` с обходчиком каталогов расходятся. Тот же
    /// дефект уже ловил `DogNameSubstitutionTests` своим первым прогоном.
    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .resolvingSymlinksInPath()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private static func текст(_ путь: String) throws -> String {
        let адрес = корень.appendingPathComponent(путь)
        return try String(contentsOf: адрес, encoding: .utf8)
    }

    /// Текст файла **без комментариев**.
    ///
    /// **Это починка, пойманная подделкой, а не предосторожность.**
    /// Первая редакция искала «Пять ролей, восемь прав» по всему файлу
    /// и прошла подделку насквозь:
    ///
    /// ```
    /// заменил на экране  Text("Шесть ролей, восемь прав")
    /// сторож             ✔ 4 из 4 passed, rc=0
    /// почему             над этой же строкой стоит доккомментарий
    ///                    «/// «Пять ролей, восемь прав» — кадр 12.»,
    ///                    и `contains` нашёл ЕГО
    /// ```
    ///
    /// То есть сторож мерил **прозу о коде вместо кода** — класс,
    /// который у Того уже выстрелил дважды, и оба раза комментарий
    /// с именем предмета красил сторожа зелёным. Запрещать писать
    /// про строку в том же файле нельзя: этим мы и заняты.
    ///
    /// > **Сторож, рождённый зелёным, учит не верить зелёному.
    /// > Отличить «ловит» от «не умеет» может только подделка.**
    private static func безКомментариев(_ текст: String) -> String {
        var вне = ""
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            вне += s + "\n"
        }
        return вне
    }

    /// Код экрана «Семья» без прозы.
    private static func кодЭкрана() throws -> String {
        безКомментариев(try текст("Togo/Features/Family/FamilyScreen.swift"))
    }

    /// Пропись для чисел, которые у нас на экране бывают.
    ///
    /// Словарь, а не алгоритм: числительных здесь ровно столько, сколько
    /// может вырасти перечисление за обозримое время, и «алгоритм
    /// прописи» был бы третьей реализацией правила, которого никто
    /// не просил. Нет числа в словаре — тест скажет это прямо, а не
    /// промолчит.
    private static let пропись: [Int: String] = [
        1: "одна", 2: "две", 3: "три", 4: "четыре", 5: "пять",
        6: "шесть", 7: "семь", 8: "восемь", 9: "девять", 10: "десять",
    ]

    @Test("«Пять ролей, восемь прав» — это счёт перечислений, а не слоган")
    func числаВКарточкеРолейСходятся() throws {
        let экран = try Self.кодЭкрана()

        let ролей = FamilyRole.allCases.count
        let прав = Permission.allCases.count

        let роли = try #require(Self.пропись[ролей],
                                "ролей стало \(ролей), а прописи для этого числа в тесте нет")
        let права = try #require(Self.пропись[прав],
                                 "прав стало \(прав), а прописи для этого числа в тесте нет")

        // Первая буква заглавная, потому что фраза начинает заголовок
        // карточки. Склонение существительных тест НЕ проверяет:
        // при шести ролях он покраснеет на числе, и фразу допишет
        // человек. Это и есть его работа — остановить, а не угадать.
        let ожидаемая = "\(роли.prefix(1).uppercased())\(роли.dropFirst()) ролей, \(права) прав"
        #expect(экран.contains(ожидаемая), """
            карточка ролей обязана говорить «\(ожидаемая)»: \
            FamilyRole.allCases = \(ролей), Permission.allCases = \(прав). \
            Разошлось — правится ТЕКСТ под перечисление, а не наоборот.
            """)
    }

    /// Контроль к замеру выше, и он в том же тесте нарочно.
    ///
    /// Сторож, который ищет строку в файле, молчит одинаково и когда
    /// строка на месте, и когда файл переехал, не читается или назван
    /// иначе. Без этой проверки зелёный выше ничего не доказывает.
    @Test("Было что читать: файл экрана на месте и не пуст")
    func файлЭкранаЧитается() throws {
        let экран = try Self.текст("Togo/Features/Family/FamilyScreen.swift")
        #expect(экран.count > 1000,
                "файл экрана «Семья» прочитан длиной \(экран.count) — это отказ чтения, а не короткий экран")
        #expect(экран.contains("struct FamilyScreen"),
                "в прочитанном файле нет объявления FamilyScreen — читается не тот файл")
    }

    /// «Пять строк без диагноза» — тоже число, и тоже копия.
    ///
    /// Полей ситтерского брифинга ровно пять, и диагноза среди них нет.
    /// Считается по модели, а не по экрану: экран — потребитель.
    @Test("Брифинг ситтера — пять полей, и диагноза среди них нет")
    func брифингПятьСтрок() throws {
        let модель = try Self.текст("TogoShared/Models/Dog.swift")

        let поля = ["sitterFood", "sitterDose", "sitterWalks",
                    "sitterForbidden", "sitterEscalation"]
        for поле in поля {
            #expect(модель.contains("var \(поле)"),
                    "поле брифинга \(поле) исчезло из Dog — подпись «пять строк» стала неверной")
        }

        // Шестого поля быть не должно: иначе «пять строк» на экране
        // врёт, а узнать об этом неоткуда.
        let всего = модель.components(separatedBy: "var sitter").count - 1
        #expect(всего == поля.count, """
            полей `sitter*` в Dog стало \(всего) при пяти на кадре 12. \
            Либо поправить подпись «пять строк без диагноза» \
            в FamilyScreen.swift, либо объяснить лишнее поле здесь.
            """)

        let экран = try Self.кодЭкрана()
        #expect(экран.contains("пять строк без диагноза"),
                "подпись брифинга с кадра 12 пропала с экрана")
    }

    /// Роли на экран приезжают из перечисления, а не печатаются рукой.
    ///
    /// Список, набранный руками, знает только то, что в него положили, —
    /// у Togo это записано трижды, и трижды число было заниженным.
    @Test("Пилюли ролей берутся из FamilyRole.allCases")
    func пилюлиИзПеречисления() throws {
        let экран = try Self.кодЭкрана()
        #expect(экран.contains("ForEach(FamilyRole.allCases"), """
            пилюли ролей собраны не из перечисления. Рукописный список \
            разойдётся с FamilyRole молча: добавленная роль просто \
            не появится, и никто не узнает.
            """)
    }
}
