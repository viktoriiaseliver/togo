import Testing
import Foundation

/// Время суток строится календарём, а не сложением секунд с полуночью.
///
/// **Правило существовало прозой и разъехалось дважды — поэтому сторож.**
/// `TogoShared/Domain/DayTime.swift:7` говорит прямо: «Превращать их
/// в дату сложением „начало дня плюс столько-то секунд" нельзя: в сутках
/// перевода часов не 24 часа, а 23 или 25, и восьмичасовая доза в такой
/// день оказывается в 07:00 или в 09:00. Календарь знает про перевод,
/// арифметика секунд — нет». Там же сказано, что сложение **уже было
/// скопировано в семь файлов** и «раз в полгода они разъезжались все
/// сразу».
///
/// Хелпер завели, семь копий убрали, а проверки не поставили — и 24.10.2026,
/// в сутки самого перевода, нашлись ещё три места:
///
/// ```
/// TripScreens.swift:217    выезд, а с ним ВСЕ окна «до выезда»   починено 93630f4
/// DayOutPlan.swift:38      сколько кормлений в окне → сколько корма   починено 93630f4
/// TreatmentTests.swift     наш собственный СТОРОЖ доз                 починено c2d0df0
/// ```
///
/// Третье дороже двух первых как улика: **сторож нарушал правило,
/// предмет которого стережёт**, и краснел на верном коде. Два дня в году
/// это выглядит как регрессия продукта, и ровно так и было прочитано,
/// пока не сняли замер двумя способами рядом.
///
/// **Почему запрет на форму, а не требование звать хелпер.** Требование
/// «зовите `date(minuteOfDay:on:)`» грепом не проверяется: у вычисления
/// времени суток десятки законных форм, и сторож на требование даёт шум.
/// Запрет узнаётся по имени целиком — это наш разобранный выбор, тот же,
/// что у `ComponentTokenScopeTests`.
///
/// **Почему счётом, а не нулём.** Законное вхождение одно — запасной путь
/// внутри самого хелпера, для минуты за пределами суток. Сторож, красный
/// в день рождения, учит не верить красному, а это дороже пропущенного
/// дефекта.
///
/// # Вторая форма, заведённая 24.10.2026: ДЕЛЕНИЕ на сутки
///
/// Сторож ловил сложение и был слеп к обратному действию. Нашлось
/// `TreatmentCourse.swift:147` — `Int(span / 86400)` на экране «Курс
/// завершён»: курс, перешагнувший воскресенье перевода часов вперёд,
/// терял час, ровно четырнадцать суток давали 13,96, `Int` отрезал
/// до 13 — и «2 недели позади» читалось как «13 дней позади».
///
/// **Почему эта форма годится в сторожа, а соседняя — нет.** Правило
/// прогнано на здоровом коде ПРЕЖДЕ, чем стало тестом (шаг оплачен
/// первой редакцией правила сложения, разбор выше). Замер 24.10.2026
/// по 223 файлам `Togo` · `TogoShared` · `TogoWidgets`:
///
/// ```
/// деление на сутки (86400 · 24*3600 · 24*60*60)
///   TreatmentCourse.swift:147   Int(span / 86400)      ← сам дефект
///   больше НИ ОДНОГО                                   → ложных нет
///
/// addingTimeInterval на ЦЕЛЫЕ СУТКИ — НЕ сторожим, и вот почему
///   AskSignalCard.swift:26,27   −7 и −14 суток         починено 24.10
///   FamilyScreen.swift:854      +24*3600 жизнь ссылки  ДЛИТЕЛЬНОСТЬ
///   UsageLog.swift:302          −keepDays*24*3600      ДЛИТЕЛЬНОСТЬ
/// ```
///
/// Две последние — такие же «двадцать минут после еды», как три места
/// медицинского слоя в разборе выше: срок жизни приглашения и глубина
/// хранения журнала меряются астрономическим временем, и перевод часов
/// их не задевает. Правило на эту форму родилось бы красным на двух
/// верных местах — то есть ровно тем, чего разбор выше велит не делать.
/// Запрет на деление ловит исход («сколько суток прошло») и не трогает
/// длительности вовсе: длительность на сутки никто не делит.
@Suite("Время суток считается календарём, а не секундами")
struct КалендарьПротивСекундTests {

    /// Сколько вхождений было в день записи, 24.10.2026, после починки
    /// `93630f4` и `c2d0df0`. Ноль: единственное законное место — сам
    /// `DayTime.swift`, и оно исключено ниже по имени файла.
    static let записаноНарушений = 0

    /// Делений длительности на сутки в день записи, 24.10.2026, после
    /// починки `TreatmentCourse.swift:147`. Ноль: законного места нет
    /// ни одного — сутки получают календарём, а не делением.
    static let записаноДелений = 0

    /// Ниже этого числа просмотренных файлов замер считается несостоявшимся.
    /// Сканер, переставший что-либо находить, молчит так же, как тот, кому
    /// нечего сказать. На 24.10.2026 обход видел 213 файлов.
    static let записаноФайловНеМенее = 180

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    /// Текст без комментариев.
    ///
    /// Без этого сторож меряет прозу: в этом файле запрещённая форма
    /// набрана в доккомментарии трижды, и сторож без вырезки покраснел бы
    /// на собственном объяснении. Класс оплачен дважды — сторож на вызов
    /// краснел на комментарии «// НЕ `MapsApp.allCases`».
    private func безКомментариев(_ текст: String) -> String {
        var вне = ""
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            вне += s + "\n"
        }
        return вне
    }

    /// Запрещено сложение **минут суток** с **началом суток**, и обе
    /// половины условия обязательны.
    ///
    /// # Первая редакция правила краснела на здоровом коде
    ///
    /// Она ловила «`.addingTimeInterval(Double(…)` с минутами в аргументе»
    /// и нашла три живых места, все в медицинском слое:
    ///
    /// ```
    /// DoseGate.swift:43       meal.date + minutesAfterMeal   «20 минут ПОСЛЕ еды»
    /// FeedingGate.swift:65    givenAt  + fastingMinutes      «натощак N минут»
    /// DoseScheduler.swift:413 givenAt  + fastingMinutes      то же
    /// ```
    ///
    /// **Все три верны.** Это ДЛИТЕЛЬНОСТИ, а не время суток: двадцать
    /// минут после еды — ровно двадцать астрономических минут, и перевод
    /// часов их не задевает вовсе. Сложение секунд тут не обход хелпера,
    /// а единственная правильная форма.
    ///
    /// > Это наш оплаченный шаг «прогнать правило на ЗДОРОВОМ коде,
    /// > прежде чем оно станет тестом». Прежде так покраснела первая
    /// > редакция «цифра, не приклеенная к букве» — на `Token.Space.s28`.
    /// > Без этого шага сторож родился бы красным на медицинском слое
    /// > и научил бы не верить красному.
    ///
    /// Различает **база сложения**: у дефекта слева полночь или день
    /// (`startOfDay`, `day`, `день`, `сутки`), у здорового кода — момент
    /// события (`meal.date`, `givenAt`, `now`).
    ///
    /// Контроли обоих знаков сняты в той же команде, что и замер:
    /// обе починенные 24.10 формы правило ловит, все три длительности
    /// пропускает, `now.addingTimeInterval(-7 * 24 * 3600)` пропускает.
    private func запрещено(_ строка: String) -> Bool {
        guard let граница = строка.range(of: ".addingTimeInterval(") else { return false }
        let база = строка[строка.startIndex..<граница.lowerBound].lowercased()
        let аргумент = строка[граница.lowerBound...].lowercased()
        let отСуток = база.contains("startofday") || база.contains("day")
            || база.contains("день") || база.contains("сутк")
        let вМинутах = аргумент.contains("minute") || аргумент.contains("минут")
        return отСуток && вМинутах
    }

    /// Запрещено **деление** длительности на сутки: так считают, сколько
    /// суток прошло, и так теряют час дважды в год.
    ///
    /// Пробелы и подчёркивания снимаются до сравнения, иначе `/ 86_400`
    /// и `/86400` — две разные строки для сторожа и одна для компилятора.
    /// Сравнение идёт по подстроке целиком, а не по префиксу: `hasPrefix`
    /// однажды нашёл `SwatchRow` вместо `Swatch`.
    private func запрещеноДеление(_ строка: String) -> Bool {
        let сжато = строка
            .replacingOccurrences(of: " ", with: "")
            .replacingOccurrences(of: "_", with: "")
        let сутки = ["86400", "24*3600", "24*60*60", "3600*24", "60*60*24"]
        for число in сутки where сжато.contains("/" + число) || сжато.contains("/(" + число + ")") {
            return true
        }
        return false
    }

    private func обход() -> (нарушения: [String], деления: [String], файлов: Int) {
        let fm = FileManager.default
        var нарушения: [String] = []
        var деления: [String] = []
        var файлов = 0
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                let путь = url.path
                // Сам хелпер — законный хозяин запасного пути: минута
                // за пределами суток календарём не ставится, и тогда
                // сложение верно. Исключение именем файла, а не префиксом:
                // `hasPrefix` однажды нашёл `SwatchRow` вместо `Swatch`.
                if url.lastPathComponent == "DayTime.swift" { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                for (i, строка) in безКомментариев(текст)
                    .components(separatedBy: .newlines).enumerated() {
                    let имя = путь.replacingOccurrences(of: Self.корень.path + "/", with: "")
                    if запрещено(строка) { нарушения.append("\(имя):\(i + 1)") }
                    if запрещеноДеление(строка) { деления.append("\(имя):\(i + 1)") }
                }
            }
        }
        return (нарушения, деления, файлов)
    }

    @Test("Обход просмотрел файлы: календарь против секунд")
    func былоЧтоПроверять() {
        let (_, _, файлов) = обход()
        #expect(файлов >= Self.записаноФайловНеМенее,
                """
                Обход увидел \(файлов) файлов при ожидаемых \
                \(Self.записаноФайловНеМенее)+. Это отказ сканера, \
                а не чистый код: пустой обход и здоровый обход дают \
                одинаковый зелёный на самом правиле.
                """)
    }

    /// Вторая ось того же правила: не сложение, а деление.
    ///
    /// Отдельный `@Test`, а не второе `#expect` в соседнем, — наш
    /// разобранный выбор: «запрет держит ДОРОГУ, число держит ЗНАЧЕНИЕ,
    /// и различает только подделка, нарушающая ровно одно из двух».
    /// Сплошной сторож краснеет весь и не говорит, что именно сняли.
    @Test("Сутки не получают делением длительности на 86 400")
    func делениемСуткиНеСчитают() {
        let (_, деления, _) = обход()
        #expect(деления.count <= Self.записаноДелений,
                """
                Длительность делят на сутки в \(деления.count) местах \
                при записанных \(Self.записаноДелений):
                \(деления.joined(separator: "\n"))

                В воскресенье перевода часов в сутках 23 или 25 часов: \
                ровно четырнадцать суток дают 13,96, и `Int` отрезает \
                до 13. Считать `Calendar.dateComponents([.day], from:to:)` \
                — например `TreatmentCourse.суток(от:до:)`.
                """)
    }

    @Test("Время суток не складывают с полуночью секундами")
    func секундамиСуткиНеСтроят() {
        let (нарушения, _, _) = обход()
        #expect(нарушения.count <= Self.записаноНарушений,
                """
                Время суток считается сложением секунд в \(нарушения.count) \
                местах при записанных \(Self.записаноНарушений):
                \(нарушения.joined(separator: "\n"))

                В сутки перевода часов таких не 24, а 23 или 25 — и час \
                уезжает у всего, что от этого времени отсчитывается. \
                Звать `Calendar.date(minuteOfDay:on:)` \
                (`TogoShared/Domain/DayTime.swift:20`).
                """)
    }
}
