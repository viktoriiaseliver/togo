import Testing
import Foundation

/// Сторож на ВЫЗОВ срока контроля и на выбор двух дней из окна.
///
/// `ControlWindow` был написан, покрыт тестами и имел **ноль мест
/// вызова**; `Prescription.prescribedControl` — мост к нему — тоже
/// не звал никто. Домен при этом зелен: тест зовёт функцию сам
/// и не замечает, что из приложения её не зовут вовсе.
///
/// **Что этот файл проверяет и чего не проверяет — названо, а не
/// подразумевается.**
///
/// ```
/// вызов есть в коде приложения          проверяется здесь
/// выбраны ровно два дня окна            проверяется здесь, на домене
/// строка доходит до сводки у живой
///   собаки с рецептом                   НЕ проверяется: нужен стор
/// человек её увидел                     НЕ проверяется ничем:
///                                       у сводки нет экрана
/// ```
///
/// Последнее берёт отладочный список (`Настройки · Отладка · что
/// запланировано в уведомлениях`) — единственный путь, смотрящий
/// мимо показа. Третья строка — честный долг, а не умолчание.
@Suite("Срок контроля доходит до сводки")
struct СрокКонтроляВСводкеTests {

    private var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private func код(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { String($0.components(separatedBy: "//")[0]) }
            .joined(separator: "\n")
    }

    @Test("Окно контроля считается из кода приложения, а не только из тестов")
    func окноВызвано() throws {
        let планировщик = try код("Togo/Store/ReminderScheduler.swift")
        #expect(планировщик.contains("ControlWindow.window"), """
            `ControlWindow.window` не вызывается из `ReminderScheduler` —
            значит срок контроля из назначения не доходит никуда,
            и человек по-прежнему считает недели в уме.

            Домен покрыт тестами и они зелёные: это ничего не значит
            про вызов. Если вызов переехал — впиши новый путь здесь,
            а не снимай проверку.
            """)
        #expect(планировщик.contains("prescribedControl"), """
            Мост `Prescription.prescribedControl` не используется.
            Поле `controlFromWeeks` объявлено, едет в архив — и если
            его никто не читает, это «объявлено, а читателя нет»:
            у Togo такой класс уже стоил трёх полей без хозяина.
            """)
    }

    @Test("Текст берётся у домена, а не пишется в планировщике")
    func текстНеДублируется() throws {
        let планировщик = try код("Togo/Store/ReminderScheduler.swift")
        #expect(планировщик.contains("ControlWindow.word"), """
            Планировщик не зовёт `ControlWindow.word` — значит текст
            про контроль написан на месте. Вторая поверхность
            («Здоровье», виджет) напишет свой, и две формулировки
            разойдутся молча.
            """)
        for своё in ["пора на контроль", "последний день контроля"] {
            #expect(!планировщик.contains("\"\(своё)\""), """
                В планировщике лежит литерал «\(своё)» — он обязан
                приходить из `ControlWindow.word`, иначе это вторая
                копия текста, и правка одной не поедет в другую.
                """)
        }
    }

    /// Выбор двух дней проверяется на домене — без стора, без экрана.
    ///
    /// ТЗ требует ровно двух напоминаний: в начале окна и в последний
    /// день. Проверка от ОБОИХ краёв и от середины: утверждение
    /// «напоминаем не каждый день» выполнялось бы и при нуле
    /// напоминаний, как у Kvit выполнялось «уходят не все» при пороге,
    /// не отправлявшем ни одной строки.
    @Test("Из всего окна говорят ровно два дня: открытие и последний")
    func ровноДваДня() throws {
        var календарь = Calendar(identifier: .gregorian)
        календарь.timeZone = TimeZone(identifier: "Europe/Paris")!
        let назначено = календарь.date(from: DateComponents(year: 2026, month: 10, day: 1))!

        let окно = try #require(ControlWindow.window(
            prescribedAt: назначено,
            .init(fromWeeks: 4, toWeeks: 6),
            calendar: календарь
        ))

        func ступень(_ дата: Date) -> ControlWindow.Stage {
            ControlWindow.stage(окно, now: дата, calendar: календарь)
        }
        func через(_ дней: Int) -> Date {
            календарь.date(byAdding: .day, value: дней, to: назначено)!
        }

        // 28-й день — открытие окна, 42-й — последний.
        #expect(ступень(через(27)) == .beforeWindow(opens: окно.opens),
                "за день до открытия окно обязано молчать")
        #expect(ступень(через(28)) == .open(closes: окно.closes),
                "в день открытия ступень обязана быть «можно идти»")
        #expect(ступень(через(35)) == .open(closes: окно.closes),
                "в середине окна ступень та же — и сводка о ней молчит")
        #expect(ступень(через(42)) == .lastDay,
                "в последний день ступень обязана отличаться от середины")
        #expect(ступень(через(43)) == .missed(closedAt: окно.closes),
                "после окна — «срок прошёл», и это экран, а не пуш")

        // Середина и открытие дают ОДНУ ступень — значит выбор дня
        // не может опираться на ступень одну. Это и есть причина,
        // по которой в планировщике стоит сверка с `окно.opens`:
        // без неё сводка говорила бы каждый день две недели.
        #expect(ступень(через(28)) == ступень(через(35)), """
            Ступени открытия и середины разошлись — значит правило
            в `ControlWindow` изменилось, и условие выбора дня
            в `ReminderScheduler.строкиКонтроля` надо перечитать:
            оно опирается ровно на то, что эти две ступени совпадают.
            """)
    }

    @Test("Разбору было что читать")
    func разборуБылоЧтоЧитать() throws {
        let текст = try код("Togo/Store/ReminderScheduler.swift")
        #expect(текст.count > 1000, """
            `ReminderScheduler.swift` прочитан как \(текст.count)
            знаков — это не файл. На пустом тексте все запреты выше
            выполняются, и зелёный тут означал бы обратное правде.
            """)
    }
}
