import Testing
import Foundation

/// Компонентные токены не спрашивает никто, кроме компонентов.
///
/// **Довод не теоретический, и он лежит в том самом файле, который сторож
/// и ловит.** В `ActionGrid` двадцатью строками выше ручной кнопки стоит
/// наш же комментарий: главная кнопка приложения давала **1,68:1**
/// и не читалась ни разу за всё время — при зелёном тесте, который
/// проверял ровно это место и требовал `label == Ink.onAccent`. Токен был
/// верен всегда. Экран его не звал, потому что **собрал кнопку сам**.
///
/// Отсюда правило: если `Token.Component.Button.Primary.background`
/// спрашивает экран, значит экран пересобирает кнопку — по определению,
/// а не по подозрению. Компонентные токены существуют для компонентов.
///
/// **Почему именно запрет, а не требование.** «Экран обязан звать
/// `TGButton`» грепом не проверяется: у вызова десять форм, и сторож
/// на требование даёт шум (у нас это стоило семидесяти девяти ложных
/// находок на Timer). «Экран не смеет звать `Token.Component.*`»
/// проверяется надёжно: запретное узнаётся по своему имени целиком.
///
/// **Почему счётом, а не нулём.** Сегодня нарушений десять, все в одном
/// файле. Сторож, красный в день рождения, учит не верить красному —
/// а это дороже пропущенного дефекта. Поэтому счёт держится и пускается
/// только вниз, как `двойниковНеБольше` у каталога.
@Suite("Компонентные токены не уходят за пределы дизайн-системы")
struct ComponentTokenScopeTests {

    /// Сколько обращений было в день записи, 05.10.2026.
    ///
    /// Все десять — `Togo/Features/Today/ActionGrid.swift:118…147`: ручная
    /// главная кнопка, собранная из `Button.Primary.label/height/radius/
    /// background` и тех же полей `Secondary`.
    static let записаноНарушений = 10

    /// Ниже этого числа просмотренных файлов замер считается несостоявшимся.
    /// Сканер, переставший что-либо находить, молчит так же, как тот, кому
    /// нечего сказать.
    static let записаноФайловНеМенее = 120

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    /// Текст без комментариев.
    ///
    /// **Без этого сторож меряет прозу, а не код** — класс, который у нас
    /// уже выстрелил дважды: сторож на вызов покраснел на комментарии
    /// «// НЕ `MapsApp.allCases`», а моя же мера отказов хранилища
    /// посчитала строку документации теста. Запрещать писать про ошибку
    /// в том же файле, где её не совершают, — значит наказывать ровно
    /// за то, чем мы заняты весь день.
    private func безКомментариев(_ текст: String) -> String {
        var вне = ""
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            вне += s + "\n"
        }
        return вне
    }

    private func обход() -> (нарушения: [String], файлов: Int) {
        let fm = FileManager.default
        var нарушения: [String] = []
        var файлов = 0
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                let путь = url.path
                // Дизайн-система — законный хозяин этих токенов.
                // Сгенерированное — их объявление, а не употребление.
                if путь.contains("/DesignSystem/") || путь.contains("/Generated/") { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                let код = безКомментариев(текст)
                for (i, строка) in код.components(separatedBy: .newlines).enumerated()
                where строка.contains("Token.Component.") {
                    let имя = путь.replacingOccurrences(of: Self.корень.path + "/", with: "")
                    нарушения.append("\(имя):\(i + 1)")
                }
            }
        }
        return (нарушения, файлов)
    }

    @Test("Обход вообще что-то просмотрел")
    func былоЧтоПроверять() {
        let (_, файлов) = обход()
        #expect(файлов >= Self.записаноФайловНеМенее, """
            просмотрено \(файлов) файлов, а в день записи было
            не меньше \(Self.записаноФайловНеМенее). Либо дерево
            переехало, либо обход перестал его видеть — и второе
            снаружи выглядит как первое.
            """)
    }

    @Test("Обращений к компонентным токенам вне дизайн-системы не прибавилось")
    func нарушенийНеБольше() {
        let (нарушения, _) = обход()
        #expect(нарушения.count <= Self.записаноНарушений, """
            экраны спрашивают компонентные токены \(нарушения.count) раз,
            а было \(Self.записаноНарушений):

            \(нарушения.joined(separator: "\n"))

            Экран, который берёт `Token.Component.Button.*`, пересобирает
            кнопку сам — и тогда любая починка внутри `TGButton` до него
            не доезжает. Так главная кнопка приложения давала 1,68:1
            при верном токене и зелёном тесте.

            Правильный ход — позвать компонент, а не скопировать его
            значения. Счёт может только падать.
            """)
    }

    @Test("Границы: чего этот сторож НЕ видит")
    func границыСторожа() {
        // Печатается последней строкой нарочно, и каждая граница обязана
        // назвать, ЧТО ЕЁ СНИМЕТ, — иначе через неделю она соврёт
        // в пользу бездействия, как уже было с печатью границы
        // `UrineSilenceTests`.
        //
        // 1. Сторож ловит пересборку КНОПКИ и слеп к пересборке ПЛИТКИ.
        //    У плитки обычные токены — `Radius.tile`, `Surface.sunken`, —
        //    и по ним экран от компонента не отличить ничем. Из шести
        //    ручных мест, найденных глазами, он краснеет на трёх.
        //    Снимет: компонентные токены у плитки, то есть
        //    `Token.Component.Tile.*` в `tokens.json`. Пока их нет,
        //    запрет здесь нечему нарушать.
        //
        // 2. Он видит ИМЯ, а не действие. Экран может взять значение
        //    через промежуточную переменную или собственную константу,
        //    и сторож промолчит — тот же слой, что «сторож на вызов
        //    слеп к „посчитали сами“».
        //    Снимет: сравнение нарисованного пикселя с токеном на кадре.
        //
        // 3. Он ничего не говорит о том, ПРАВИЛЬНО ли собран компонент
        //    внутри дизайн-системы: `TGTile` сегодня принимает `tone`
        //    и молча игнорирует `.done` и `.waiting` — сравнивает только
        //    с `.alarm` (`TGSurfaces.swift:66–69`). Запрет отсюда виден
        //    не будет никогда.
        //    Снимет: поведенческий тест на соответствие `TGTile.background`
        //    и `TGTone.background`.
        #expect(Bool(true))
    }
}
