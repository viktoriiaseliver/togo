/// Компонентные токены не спрашивает никто, кроме компонентов.
///
/// **Довод не теоретический, и он лежал в том самом файле, который сторож
/// и ловил** (`ActionGrid.swift`, удалён 24.10.2026 как сирота; текст ниже
/// взят оттуда до удаления). Двадцатью строками выше ручной кнопки стоял
/// наш же комментарий: главная кнопка приложения давала **1,68:1**
/// и не читалась ни разу за всё время — при зелёном тесте, который
/// проверял ровно это место и требовал `label == Ink.onAccent`. Токен был
/// верен всегда. Экран его не звал, потому что **собрал кнопку сам**.
///
/// Отсюда правило: если `Token.Component.Button.Primary.background`
/// спрашивает экран, значит экран пересобирает кнопку — по определению,
/// а не по подозрению. Компонентные токены существуют для компонентов.
///
/// **Почему именно запрет, а не требование.** «Экран обязан звать
/// `TGButton`» грепом не проверяется: у вызова десять форм, и сторож
/// на требование даёт шум (у нас это стоило семидесяти девяти ложных
/// находок на Timer). «Экран не смеет звать `Token.Component.*`»
/// проверяется надёжно: запретное узнаётся по своему имени целиком.
///
/// **Почему счётом, а не нулём.** В день записи нарушений было десять,
/// все в одном файле. Сторож, красный в день рождения, учит не верить
/// красному — а это дороже пропущенного дефекта. Поэтому счёт держится
/// и пускается только вниз, как `двойниковНеБольше` у каталога.
///
/// **24.10.2026 счёт опущен до нуля, и опущен он УДАЛЕНИЕМ, а не починкой.**
/// Это разные вещи, и разница тут важнее числа: ручную кнопку никто
/// не переписал на `TGButton` — исчез файл, в котором она стояла.
/// `ActionGrid.swift` оказался экраном-сиротой (ноль конструирований
/// обеими формами при живом контроле), то есть все десять обращений
/// принадлежали поверхности, до которой человек не доходил. Дефект
/// «экран пересобрал кнопку сам» не был исправлен — он перестал
/// существовать вместе со своим экраном.
@Suite("Компонентные токены не уходят за пределы дизайн-системы")
struct ComponentTokenScopeTests {

    /// Сколько обращений осталось после удаления `ActionGrid.swift`, 24.10.2026.
    ///
    /// Было десять, и все десять — `ActionGrid.swift:118…147`: ручная главная
    /// кнопка из `Button.Primary.label/height/radius/background` и тех же полей
    /// `Secondary`. Файл удалён — осталось ноль.
    ///
    /// ~~«Замер той же осью, что у `обход()`: остальные вхождения
    /// `Token.Component.` в дереве (`ФотоШапка` 5, `CategoryBadge` 4,
    /// `КиноЭкран` 2, `WalkActivityView`, `BackgroundStore`,
    /// `LabResultScreens` по 1) — все до одного в `///`-прозе, а проза
    /// вырезается `безКомментариев` до разбора».~~
    ///
    /// **Замер был верен, а «той же осью» — нет** (26.10.2026). Проза
    /// действительно была прозой; но `безКомментариев` в четырёх из шести
    /// названных файлов **не доходил до этих строк вовсе** — он слеп
    /// за `/**` в глобе. Ось была не та же: автор мерил глазами, сторож
    /// мерил другое, и сошлись они случайно. Разбор и подделка —
    /// у `безКомментариев` ниже, условие держит `разборНеОслеп()`.
    ///
    /// ~~«Проверить за минуту: `git grep -n "Token\.Component\."` и
    /// убедиться, что вне `/DesignSystem/` каждая строка начинается
    /// с `///`».~~ **Этот рецепт и давал ложную уверенность:** он
    /// проверяет, проза ли найденное, и не задаёт второго вопроса —
    /// дочитал ли сторож до него. Годный рецепт за минуту:
    /// `swift test --filter разборНеОслеп` либо
    /// `git grep -c -P "/\*" -- Togo TogoShared TogoWidgets` против
    /// `git grep -c -P "\*/"` — файл с открывающими и без закрывающих
    /// и есть слепое место.
    ///
    /// Ноль здесь — не «сторож перестал краснеть», а «запрету больше нечего
    /// прощать»: теперь ЛЮБОЕ обращение к `Token.Component.*` из экрана
    /// красит набор. Счёт по-прежнему может только падать, а падать ему уже некуда.
    /// **И «любое» стало правдой только 26.10.2026**: до починки разбора
    /// 4240 строк в восьми файлах нарушить запрет не могли по устройству.
    static let записаноНарушений = 0

    /// Ниже этого числа просмотренных файлов замер считается несостоявшимся.
    /// Сканер, переставший что-либо находить, молчит так же, как тот, кому
    /// нечего сказать.
    static let записаноФайловНеМенее = 120

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    /// Текст без комментариев.
    ///
    /// **Без этого сторож меряет прозу, а не код** — класс, который у нас
    /// уже выстрелил дважды: сторож на вызов покраснел на комментарии
    /// «// НЕ `MapsApp.allCases`», а моя же мера отказов хранилища
    /// посчитала строку документации теста. Запрещать писать про ошибку
    /// в том же файле, где её не совершают, — значит наказывать ровно
    /// за то, чем мы заняты весь день.
    ///
    /// **Разбор ослеп на `/**` ВНУТРИ `///`-прозы, и это замер 26.10.2026.**
    /// `CinemaHeader.swift:17` пишет про чужой каталог глобом —
    /// `` `Togo/DesignSystem/**` `` — а в `/**` лежит подстрока `/*`.
    /// Блок открывался, `*/` в файле не было ни одного, и **649 строк
    /// из 666 сторож не видел вовсе**. По дереву таких файлов нашлось
    /// восемь и 4240 невидимых строк:
    ///
    /// ```
    /// SchemaVersions.swift        ослеп с 56   проглочено 1653
    /// CinemaHeader.swift          ослеп с 17   проглочено  649
    /// WalkActivityView.swift      ослеп с 135  проглочено  449
    /// ФотоШапка.swift             ослеп с 16   проглочено  429
    /// PaywallScreen.swift         ослеп с 30   проглочено  373
    /// CloudKitSchemaWarmup.swift  ослеп с 211  проглочено  340
    /// КиноЭкран.swift             ослеп с 123  проглочено  203
    /// AccentChoice.swift          ослеп с 8    проглочено  144
    /// ```
    ///
    /// **Четыре из восьми — ровно те файлы, которые голова этого сторожа
    /// называет поимённо** («`ФотоШапка` 5, `КиноЭкран` 2,
    /// `WalkActivityView`… — все до одного в `///`-прозе»). Автор проверил
    /// глазами, что это проза, и был прав; но проверка **глазами** и была
    /// единственной, а сам сторож в эти файлы не смотрел. Ноль сходился
    /// по двум независимым причинам, а померена была одна.
    ///
    /// > **Ноль при живом контроле значит «предмета нет ТАМ, КУДА
    /// > я смотрю», и ни слова о том, туда ли я смотрю.**
    ///
    /// Подделка, 26.10.2026, на предикате (стенд не нужен — это разбор
    /// текста):
    ///
    /// ```
    ///                                              было  стало
    /// живой CinemaHeader.swift, как есть              0     0
    /// обращение дописано В КОНЕЦ файла (стр. 666)     0     1  ← ловится
    /// обращение дописано ДО строки 17                 1     1
    /// контроль: файл без `/**` в прозе                1     1
    /// отрицательный контроль, ничего не дописано      0     0
    /// ```
    ///
    /// Старая форма на подделке оставалась **зелёной**, и зелёный
    /// не вызывает вопросов. Две средние строки — контроль к самой
    /// подделке: они доказывают, что сторож не сломан вообще, а слеп
    /// ровно за `/**`.
    ///
    /// Починка: **строчный комментарий решается ПЕРВЫМ, если он начинается
    /// раньше `/*`.** Порядок веток и был всем дефектом — `/*` искали
    /// до `//`, то есть внутри уже закомментированной строки.
    ///
    /// Остаточная граница, названная, а не замолчанная: разбор смотрит
    /// на `/*` **один раз за строку**, поэтому `/* a */ /* b` сочтёт
    /// закрытым. Это даёт ложный КРАСНЫЙ (лишняя видимость), а не
    /// зелёный, и во всём дереве таких строк ноль. Снимет: посимвольный
    /// разбор вместо построчного — и до тех пор `разборНеОслеп()` ниже
    /// держит само условие, а не его причину.
    ///
    /// - Returns: текст без комментариев и признак `ослеп` — файл кончился
    ///   **внутри** незакрытого блока. Признак отдаётся отсюда, а не
    ///   считается вторым проходом, нарочно: порядок веток и есть весь
    ///   предмет, а вторая копия этого порядка разошлась бы с первой молча.
    private func безКомментариев(_ текст: String) -> (код: String, ослеп: Bool) {
        var вне = ""
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var s = Substring(строка)
            if вБлоке {
                guard let конец = s.range(of: "*/") else { continue }
                s = s[конец.upperBound...]
                вБлоке = false
            }
            // Строчный комментарий ПЕРВЫМ, если он раньше `/*`: иначе глоб
            // `DesignSystem/**` в прозе открывает блок, который никогда
            // не закроется. Разбор выше.
            if let черта = s.range(of: "//"),
               s.range(of: "/*").map({ черта.lowerBound < $0.lowerBound }) ?? true {
                s = s[s.startIndex..<черта.lowerBound]
            }
            if let начало = s.range(of: "/*") {
                if let конец = s.range(of: "*/", range: начало.upperBound..<s.endIndex) {
                    s = s[s.startIndex..<начало.lowerBound] + s[конец.upperBound...]
                } else {
                    s = s[s.startIndex..<начало.lowerBound]
                    вБлоке = true
                }
            }
            if let черта = s.range(of: "//") {
                s = s[s.startIndex..<черта.lowerBound]
            }
            вне += s + "\n"
        }
        return (вне, вБлоке)
    }

    private func обход() -> (нарушения: [String], файлов: Int, ослепшие: [String]) {
        let fm = FileManager.default
        var нарушения: [String] = []
        var ослепшие: [String] = []
        var файлов = 0
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                let путь = url.path
                // Дизайн-система — законный хозяин этих токенов.
                // Сгенерированное — их объявление, а не употребление.
                if путь.contains("/DesignSystem/") || путь.contains("/Generated/") { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                let имя = путь.replacingOccurrences(of: Self.корень.path + "/", with: "")
                let (код, ослеп) = безКомментариев(текст)
                if ослеп { ослепшие.append(имя) }
                for (i, строка) in код.components(separatedBy: .newlines).enumerated()
                where строка.contains("Token.Component.") {
                    нарушения.append("\(имя):\(i + 1)")
                }
            }
        }
        return (нарушения, файлов, ослепшие)
    }

    /// **Разбор дочитал каждый файл до конца.**
    ///
    /// Ставится рядом с запретом, а не вместо него, и держит другую ось:
    /// запрет считает НАЙДЕННОЕ, этот — осталось ли где искать. Файл,
    /// кончившийся внутри незакрытого блока, сторож не видел с некоторой
    /// строки и до конца, и **снаружи это выглядит как чистый файл**.
    ///
    /// Условие годится без списка эталонных имён: настоящий Swift-файл
    /// не кончается внутри блочного комментария — такой файл не собрался
    /// бы. Значит любое срабатывание здесь говорит про РАЗБОР, а не
    /// про код, и объяснять его не нужно: нечему быть исключением.
    ///
    /// Замер 26.10.2026: до починки `безКомментариев` таких файлов было
    /// **восемь** и 4240 невидимых строк, после — ноль из 197.
    @Test("Разбор дочитал файлы до конца: компонентные токены")
    func разборНеОслеп() {
        let (_, файлов, ослепшие) = обход()
        #expect(ослепшие.isEmpty, """
            разбор кончился внутри незакрытого блочного комментария
            в \(ослепшие.count) файлах из \(файлов):

            \(ослепшие.joined(separator: "\n"))

            Swift-файл не может кончаться внутри блока — он бы
            не собрался. Значит это дефект РАЗБОРА, и с той строки,
            где он ослеп, до конца файла сторож не видит ничего:
            обращение к `Token.Component.*` там останется зелёным.
            Так уже было — `/**` в глобе внутри `///`-прозы открывал
            блок, который не закрывался никогда.
            """)
    }

    @Test("Обход просмотрел файлы: компонентные токены")
    func былоЧтоПроверять() {
        let (_, файлов, _) = обход()
        #expect(файлов >= Self.записаноФайловНеМенее, """
            просмотрено \(файлов) файлов, а в день записи было
            не меньше \(Self.записаноФайловНеМенее). Либо дерево
            переехало, либо обход перестал его видеть — и второе
            снаружи выглядит как первое.
            """)
    }

    @Test("Обращений к компонентным токенам вне дизайн-системы не прибавилось")
    func нарушенийНеБольше() {
        let (нарушения, _, _) = обход()
        #expect(нарушения.count <= Self.записаноНарушений, """
            экраны спрашивают компонентные токены \(нарушения.count) раз,
            а было \(Self.записаноНарушений):

            \(нарушения.joined(separator: "\n"))

            Экран, который берёт `Token.Component.Button.*`, пересобирает
            кнопку сам — и тогда любая починка внутри `TGButton` до него
            не доезжает. Так главная кнопка приложения давала 1,68:1
            при верном токене и зелёном тесте.

            Правильный ход — позвать компонент, а не скопировать его
            значения. Счёт может только падать.
            """)
    }

    @Test("Границы: чего этот сторож НЕ видит")
    func границыСторожа() {
        // Печатается последней строкой нарочно, и каждая граница обязана
        // назвать, ЧТО ЕЁ СНИМЕТ, — иначе через неделю она соврёт
        // в пользу бездействия, как уже было с печатью границы
        // `UrineSilenceTests`.
        //
        // 1. Сторож ловит пересборку КНОПКИ и слеп к пересборке ПЛИТКИ.
        //    У плитки обычные токены — `Radius.tile`, `Surface.sunken`, —
        //    и по ним экран от компонента не отличить ничем. Из шести
        //    ручных мест, найденных глазами, он краснеет на трёх.
        //    Снимет: компонентные токены у плитки, то есть
        //    `Token.Component.Tile.*` в `tokens.json`. Пока их нет,
        //    запрет здесь нечему нарушать.
        //
        // 2. Он видит ИМЯ, а не действие. Экран может взять значение
        //    через промежуточную переменную или собственную константу,
        //    и сторож промолчит — тот же слой, что «сторож на вызов
        //    слеп к „посчитали сами“».
        //    Снимет: сравнение нарисованного пикселя с токеном на кадре.
        //
        // 3. Он ничего не говорит о том, ПРАВИЛЬНО ли собран компонент
        //    внутри дизайн-системы: `TGTile` сегодня принимает `tone`
        //    и молча игнорирует `.done` и `.waiting` — сравнивает только
        //    с `.alarm` (`TGSurfaces.swift:66–69`). Запрет отсюда виден
        //    не будет никогда.
        //    Снимет: поведенческий тест на соответствие `TGTile.background`
        //    и `TGTone.background`.
        //
        // 4. Он видит ровно столько, сколько дочитал `безКомментариев`.
        //    Это была не граница, а ДЕФЕКТ — 4240 строк в восьми файлах
        //    до 26.10.2026, — и он снят; остаточная граница разбора
        //    (`/*` ищется один раз за строку) названа в доккомментарии
        //    `безКомментариев` вместе с тем, что её снимет. Здесь
        //    не повторяется числом нарочно: вторая копия разошлась бы
        //    с первой молча, а условие держит `разборНеОслеп()`.
        #expect(Bool(true))
    }
