    /// Поля, объявленные «про семью», — берутся **у соседнего сторожа**,
    /// а не копией.
    ///
    /// Второй список разошёлся бы с первым при первой же правке, и
    /// разошёлся бы молча: оба были бы зелёными, каждый про своё.
    ///
    /// Точка в `"Dog."` **несущая**, и несущей её сделали шесть ключей
    /// `DogDocument.*` — первые в проекте, что начинаются на `Dog`
    /// и собакой не являются. Поэтому разбор идёт по первой точке,
    /// а не по префиксу: `hasPrefix("Dog")` сверял бы документ против
    /// нагрузки собаки — класс `hasPrefix("struct Swatch")` из Gamut,
    /// два дня сверявшего чужой компонент.
    private static var проСемьюПоМодели: [String: [String]] {
        var собрано: [String: [String]] = [:]
        for ключ in DeviceLocalFieldTests.проСемью {
            guard let точка = ключ.firstIndex(of: ".") else { continue }
            let модель = String(ключ[..<точка])
            let поле = String(ключ[ключ.index(after: точка)...])
            собрано[модель, default: []].append(поле)
        }
        return собрано.mapValues { $0.sorted() }
    }

    private static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь),
                          encoding: .utf8)
    }

    /// Хранимые поля структуры нагрузки — из исходника, а не списком.
    private static func поляНагрузки(_ структура: String) throws -> Set<String> {
        let текст = try исходник("TogoShared/Sync/SharedDiary.swift")
        guard let начало = текст.range(of: "struct \(структура)") else { return [] }
        let хвост = текст[начало.upperBound...]
        guard let конец = хвост.range(of: "\n}") else { return [] }
        let тело = хвост[..<конец.lowerBound]

        var найдено: Set<String> = []
        for строка in тело.components(separatedBy: .newlines) {
            // Членом считается только то, что стоит на уровне тела:
            // разбор по одной строке не отличает поле от локальной
            // переменной внутри вычисляемого свойства и ошибается
            // в сторону полноты. Наш замер 23.09: так снимок схемы
            // вышел богаче настоящего, и хранилище не открылось.
            guard строка.hasPrefix("    var "), !строка.hasPrefix("     ") else { continue }
            let голая = строка.dropFirst("    var ".count)
            guard let двоеточие = голая.firstIndex(of: ":") else { continue }
            найдено.insert(String(голая[..<двоеточие])
                .trimmingCharacters(in: .whitespaces))
        }
        return найдено
    }

    /// Хранимые поля всех моделей с **типами**: `[модель: [поле: тип]]`.
    ///
    /// Тип нужен ровно для одного вопроса, и без него сторож дал бы
    /// ложное разрешение: связь исключается не потому, что она связь,
    /// а потому, что **на другом конце модель, которая ездит**. См.
    /// `связьДоезжает`.
    private static func моделиСТипами() throws -> [String: [String: String]] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Models")
        var собрано: [String: [String: String]] = [:]

        let файлы = try FileManager.default
            .contentsOfDirectory(at: корень, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "swift" }

        for файл in файлы {
            let строки = try String(contentsOf: файл, encoding: .utf8)
                .components(separatedBy: .newlines)
            var текущий: String?
            for строка in строки {
                if let имя = строка.имяКласса() { текущий = имя; continue }
                if строка == "}" { текущий = nil; continue }
                guard let класс = текущий,
                      let (поле, тип) = строка.хранимоеПоле() else { continue }
                собрано[класс, default: [:]][поле] = тип
            }
        }
        return собрано
    }

