    /// Обратная половина: исключение, закрывающее поле, которого нет, —
    /// лишняя дыра, про которую никто не помнит.
    @Test("Исключение закрывает существующее поле")
    func исключенияНеПротухли() throws {
        let семья = DeviceLocalFieldTests.проСемью
        let лишние = Self.исключения.keys.filter { семья.contains($0) == false }
        #expect(лишние.isEmpty, """
            исключения стоят на полях, которых среди «про семью» нет: \
            \(лишние.sorted().joined(separator: ", ")). Поле переименовали \
            или убрали, а исключение осталось — и теперь оно молча \
            разрешает то, чего никто не разрешал.
            """)

        let модели = try Self.моделиСТипами()
        let призраки = (Set(Self.нагрузкаМодели.keys)
            .union(Self.неЕздитПока.keys)
            .union(Self.неЕздитНавсегда.keys))
            .filter { модели[$0] == nil }
        #expect(призраки.isEmpty, """
            решение записано про модели, которых в дереве нет: \
            \(призраки.sorted().joined(separator: ", ")).
            """)
    }

    /// Граница собственного умения — печатается всегда, а не хранится
    /// в чьей-то памяти.
    @Test("Сторож называет, чего он не умеет")
    func границаНазвана() {
        let границы = """
            Зелёный здесь значит: у пяти едущих моделей каждое поле \
            «про семью» лежит в своей нагрузке, а про остальные \
            двенадцать сказано вслух с датой. И только это.

            НЕ проверяется:
            · доехало ли поле на самом деле — `SharedDiaryRecords` \
              пишет и читает запись отдельно, и поле может лежать \
              в нагрузке, не попав в `CKRecord`. Это следующий слой, \
              и он не закрыт ничем;
            · верное ли значение приехало — паритет про имена, не про смысл;
            · правильны ли сами долги — сторож держит их видимыми \
              и не знает, какие из двенадцати моделей обязаны ехать. \
              Это вопрос продукта;
            · поля «про этот телефон» — их верность не наше дело: \
