    /// доезжающей связи, ни в исключениях с причиной, — не бывает.
    ///
    /// Проверяется только у моделей, которые **ездят**: требовать поле
    /// в нагрузке у модели без нагрузки значило бы выдать сто два
    /// красных на двенадцати моделях разом, и сторожа перестали бы
    /// читать. Их долг держит `каждаяМодельНазвана` одной строкой
    /// на модель.
    @Test("Каждое поле про семью едет, либо названо исключением с причиной")
    func каждоеПолеПроСемьюЕдет() throws {
        let модели = try Self.моделиСТипами()
        let имена = Set(модели.keys)
        var потерянные: [String] = []

        for (модель, нагрузкаИмя) in Self.нагрузкаМодели.sorted(by: { $0.key < $1.key }) {
            let нагрузка = try Self.поляНагрузки(нагрузкаИмя)
            let поля = Self.проСемьюПоМодели[модель] ?? []

            // Ослепший разбор обязан сказать «я ослеп», а не назвать все
            // поля потерянными.
            //
            // Без этой строки подделка, ломающая ЗРЕНИЕ (лишний пробел
            // в `struct  DogPayload` — компилируется, а `range(of:)`
            // промахивается), дала бы порог плюс ТРИДЦАТЬ ШЕСТЬ ложных
            // имён. Порог назвал бы причину, а тридцать шесть кричали бы
            // громче него — и сторожа перестали бы читать. Ложная
            // находка дороже пропущенной, а тридцать шесть ложных
            // дороже всего.
            //
            // Слабость названа `togo-02` при приёмке, до того как
            // выстрелила.
            guard нагрузка.count >= 5 else {
                #expect(Bool(false), """
                    разбор нагрузки `\(нагрузкаИмя)` не состоялся: \
                    полей \(нагрузка.count). Сторож ОСЛЕП, а не нашёл \
                    потерянные поля — не читай список ниже, его нет. \
                    Чинить `поляНагрузки(_:)`, а не модель.
                    """)
                return
            }

            for поле in поля {
                let ключ = "\(модель).\(поле)"
                if let причина = Self.исключения[ключ] {
                    #expect(причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false,
                            "у исключения `\(ключ)` пустая причина")
                    continue
                }
                if let тип = модели[модель]?[поле],
                   let доезжает = Self.связьДоезжает(тип, среди: имена) {
                    if доезжает { continue }
                    потерянные.append("\(ключ) → \(Self.модельСвязи(тип, среди: имена) ?? "?")")
                    continue
                }
                // `sexRaw` едет как `sex`, `markerKindRaw` — как `markerKind`:
                // в модели лежит строка сырого значения, в нагрузке — она же
                // под именем без суффикса. Не знай сторож этого отображения,
                // он дал бы две ложные находки на верном коде — а ложная
                // находка дороже пропущенной: после неё сторожа перестают
                // читать.
                let безRaw = поле.hasSuffix("Raw") ? String(поле.dropLast(3)) : поле
                if нагрузка.contains(поле) || нагрузка.contains(безRaw) { continue }
                потерянные.append(ключ)
            }
        }

        #expect(потерянные.isEmpty, """
            поля числятся «про семью» и не едут ко второму человеку: \
            \(потерянные.sorted().joined(separator: ", ")).

            Либо добавь их в нагрузку и в ОБА конца `SharedDiaryRecords`, \
            либо впиши в `исключения` с причиной. Третьего нет: \
            молчаливый пропуск неотличим от того, что про поле \
            не подумали.

            Стрелка `поле → Модель` значит другое: поле — связь, \
            и модель на другом конце не ездит вовсе. Чинить надо \
            не поле, а ту модель.

            Так 05.10.2026 не ехали двенадцать полей `Dog` разом, \
            включая весь лист для догситтера — функцию, которая \
            не работала в единственном сценарии, ради которого написана. \
            Так 07.10.2026 не поехали девять полей шага 0 медслоя.
            """)
    }

    /// Долг обязан нести дату и ущерб, а не описание.
    @Test("У каждого долга есть дата и названный ущерб")
    func долгиДатированы() {
        var безДаты: [String] = []
        for (модель, долг) in Self.неЕздитПока {
            if долг.заведён.count != 10 || долг.заведён.hasPrefix("20") == false {
                безДаты.append("\(модель): дата «\(долг.заведён)»")
            }
            if долг.ущерб.trimmingCharacters(in: .whitespacesAndNewlines).count < 40 {
                безДаты.append("\(модель): ущерб не назван")
            }
        }
        #expect(безДаты.isEmpty, """
            долги без даты или без названного ущерба: \
            \(безДаты.sorted().joined(separator: "; ")).

            Дата нужна, чтобы запись старела громко: «не ездит» \
            без даты не стареет вовсе. Ущерб нужен, чтобы по списку \
            можно было назначить порядок работ, — «нет типа записи» \
            отвечает на другой вопрос.
            """)

        var безАвтора: [String] = []
        for (модель, причина) in Self.неЕздитНавсегда
        where причина.contains("решени") == false && причина.contains("Виктори") == false {
            безАвтора.append(модель)
        }
        #expect(безАвтора.isEmpty, """
            «не ездит никогда» без автора решения: \
            \(безАвтора.sorted().joined(separator: ", ")). Исключение \
