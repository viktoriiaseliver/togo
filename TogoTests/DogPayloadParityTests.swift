    }

    // MARK: Разбор типа связи

    /// Является ли тип поля связью, и доезжает ли она.
    ///
    /// `nil` — поле не связь. `true` — связь, и модель на другом конце
    /// ездит. `false` — связь, и модель на другом конце не ездит:
    /// тогда поле потеряно, и чинить надо модель, а не поле.
    ///
    /// **Прежняя редакция исключала связи целиком**, с доводом «каждая
    /// связь ездит своим типом записи». Довод оказался неверным для
    /// девяти связей `Dog` из одиннадцати: типов записи пять, а связей
    /// одиннадцать. Исключение по форме поля разрешало то, чего никто
    /// не разрешал.
    private static func связьДоезжает(_ тип: String, среди имена: Set<String>) -> Bool? {
        guard let модель = модельСвязи(тип, среди: имена) else { return nil }
        return нагрузкаМодели[модель] != nil
    }

    /// Имя модели на другом конце связи — или `nil`, если поле не связь.
    ///
    /// Связь опознаётся **свойством, а не списком имён**: список
    /// из одиннадцати `…Storage` пришлось бы править руками при каждой
    /// новой связи. Связь — это поле, тип которого сам является нашей
    /// моделью; скаляры (`String`, `Date`, `Int`) и перечисления сюда
    /// не попадают, классом их в `TogoShared/Models` нет.
    private static func модельСвязи(_ тип: String, среди имена: Set<String>) -> String? {
        let голый = тип.trimmingCharacters(in: CharacterSet(charactersIn: "[]? "))
        return имена.contains(голый) ? голый : nil
    }
}

// MARK: - Разбор исходника

private extension String {

    /// `final class Dog {` → `Dog`. Только объявление на нулевом уровне.
    func имяКласса() -> String? {
        for образец in ["final class ", "class "] {
            guard hasPrefix(образец) else { continue }
            let хвост = dropFirst(образец.count)
            let имя = хвост.prefix { $0.isLetter || $0.isNumber || $0 == "_" }
            return имя.isEmpty ? nil : String(имя)
        }
        return nil
    }

    /// `    var name: String = ""` → `("name", "String")`.
    ///
    /// Членом класса считается только то, что стоит **на уровне тела**:
    /// разбор по одной строке не отличает поле от локальной переменной
    /// внутри вычисляемого свойства и ошибается в сторону полноты —
    /// то есть в сторону, которая выглядит безопаснее и не является.
    /// Замер 23.09: так снимок схемы вышел богаче настоящего, хеш
    /// сущности разошёлся, и хранилище не открылось.
    /// **`@Attribute(.externalStorage) var image: Data?` стоит в одной
    /// строке, и прежняя редакция его не видела.** Это третий раз,
    /// когда наш разбор полей спотыкается об атрибут перед `var`:
    /// 23.09 так вышел снимок схемы богаче настоящего и хранилище
    /// не открылось, в тот же день — деривер зеркала CloudKit.
    ///
    /// Поймал не глаз, а **сверка двух независимых разборов**: сосед
    /// назвал `DogDocument.image`, мой разбор его не нашёл. Чтением
    /// этот класс не ловится — ответ синтаксически правильный.
    func хранимоеПоле() -> (поле: String, тип: String)? {
        guard hasPrefix("    "), !hasPrefix("     ") else { return nil }
        var тело = Substring(dropFirst(4))

        // Атрибуты перед `var`: `@Attribute(.externalStorage)`,
        // `@Relationship(...)`, `@Transient`. Снимаются со счётом
        // скобок, а не до первой закрывающей: внутри атрибута бывают
        // вложенные вызовы.
        while тело.hasPrefix("@") {
            var i = тело.index(after: тело.startIndex)
            while i < тело.endIndex, тело[i].isLetter || тело[i].isNumber { i = тело.index(after: i) }
            if i < тело.endIndex, тело[i] == "(" {
                var глубина = 0
                while i < тело.endIndex {
                    if тело[i] == "(" { глубина += 1 }
                    if тело[i] == ")" { глубина -= 1; if глубина == 0 { i = тело.index(after: i); break } }
                    i = тело.index(after: i)
                }
            }
            тело = тело[i...].drop(while: { $0 == " " })
        }

        for модификатор in ["private(set) ", "public ", "internal "] where тело.hasPrefix(модификатор) {
            тело = тело.dropFirst(модификатор.count)
        }
        guard тело.hasPrefix("var ") else { return nil }
        тело = тело.dropFirst(4)
        guard let двоеточие = тело.firstIndex(of: ":") else { return nil }
        let поле = String(тело[..<двоеточие]).trimmingCharacters(in: .whitespaces)
        var тип = String(тело[тело.index(after: двоеточие)...])
            .trimmingCharacters(in: .whitespaces)
        // Вычисляемое свойство — не хранимое поле.
        if тип.contains("{") { return nil }
        if let знакРавно = тип.range(of: " =") { тип = String(тип[..<знакРавно.lowerBound]) }
        return (поле, тип.trimmingCharacters(in: .whitespaces))
    }
}
