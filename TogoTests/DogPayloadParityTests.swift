    /// **Разбор моделей проверяется разбором соседнего сторожа.**
    ///
    /// Поле, которое `DeviceLocalFieldTests` разобрал и назвал, а мой
    /// разбор не нашёл, — это слепота МОЕГО разбора, и она тихая:
    /// ненайденное поле просто не проверяется на паритет. Бесплатная
    /// сверка двух независимых разборов одного дерева.
    @Test("Мой разбор моделей видит каждое поле, которое назвал сосед")
    func разборНеСлепнет() throws {
        let модели = try Self.моделиСТипами()
        var невидимые: [String] = []
        for (модель, поля) in Self.проСемьюПоМодели {
            guard let разобраны = модели[модель] else {
                невидимые.append("\(модель) — модели нет вовсе")
                continue
            }
            for поле in поля where разобраны[поле] == nil {
                невидимые.append("\(модель).\(поле)")
            }
        }
        #expect(невидимые.isEmpty, """
            сосед эти поля назвал, а мой разбор их не видит: \
            \(невидимые.sorted().joined(separator: ", ")).

            Это слепота РАЗБОРА, не находка про модель: ненайденное \
            поле молча не проверяется на паритет. Чинить \
            `моделиСТипами()`, а не модель.
            """)
    }

    /// Про каждую модель с полями «про семью» сказано, ездит она
    /// или нет, — и сказано ровно в одном месте.
    @Test("Про каждую модель сказано, ездит она или нет")
    func каждаяМодельНазвана() throws {
        var безответные: [String] = []
        var вДвухМестах: [String] = []

        for модель in Self.проСемьюПоМодели.keys.sorted() {
            let мест = [Self.нагрузкаМодели[модель] != nil,
                        Self.неЕздитНавсегда[модель] != nil,
                        Self.неЕздитПока[модель] != nil].filter { $0 }.count
            if мест == 0 { безответные.append(модель) }
            if мест > 1 { вДвухМестах.append(модель) }
        }

        #expect(безответные.isEmpty, """
            у этих моделей есть поля «про семью», и про саму модель \
            не сказано ничего: \(безответные.joined(separator: ", ")).

            Молчание здесь неотличимо от решения. Назови её одним \
            из трёх способов, и третьего мало — он с датой:
              · `нагрузкаМодели` — ездит, вот чем;
              · `неЕздитНавсегда` — не положено, вот чьё решение;
              · `неЕздитПока` — долг, вот дата и вот ущерб.
            """)
        #expect(вДвухМестах.isEmpty, """
            модель названа дважды: \(вДвухМестах.joined(separator: ", ")). \
            Два ответа на один вопрос разойдутся молча.
            """)
    }

