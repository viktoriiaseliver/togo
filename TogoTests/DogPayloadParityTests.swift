/// Поле, числящееся «про семью», обязано ехать ко второму человеку.
///
/// **Зачем этот сторож появился.** 05.10.2026 сессия `togo-f5`
/// перечитала `Dog` поле за полем и нашла **двенадцать**, которые
/// числились «про семью» и не ехали никуда: весь лист для догситтера,
/// номера паспорта и страховки, четыре поля про занятия. Лист ситтера
/// существует ровно для того часа, когда хозяина нет рядом, — и на
/// втором телефоне был пуст. Нашли это **руками**, перечитав модель;
/// тринадцатое нашли бы так же.
///
/// Соседний `DeviceLocalFieldTests` на этот вопрос не отвечает и
/// отвечать не может: он делит поля на «про семью» и «про телефон»
/// и про нагрузку обмена не знает вовсе. `Dog.photo` и `Dog.createdAt`
/// лежат у него в «уезжать положено» и не едут ни одно.
///
/// # Что изменилось 07.10.2026: сторож перестал быть про одну модель
///
/// Он охранял `Dog` — **одну модель из семнадцати**, — и границу печатал
/// о себе сам, последней строкой: «поля других моделей здесь не
/// проверяются». Я эту строку не прочёл и завёл девять полей шага 0
/// медицинского слоя, записав их «про семью». Ни одно не поехало.
///
/// > **Я записал «про семью» и этим ничего не отправил.**
///
/// И то, как это стало возможным, дороже самой ошибки:
///
/// > **Границу, которую инструмент печатает о себе, читают реже всего —
/// > её печатают именно потому, что её не спрашивают.**
///
/// Обобщение вскрыло то, чего никто не искал, и это сильно больше
/// девяти полей (замер 07.10.2026, `grep CKRecord(` по всему дереву):
///
/// ```
/// типов записи в перечислении   7
/// типов, которые кто-то создаёт 5   dog · event · care · medication · dose
/// моделей с полями «про семью» 17
/// моделей, которые ездят        5
/// полей «про семью» у остальных двенадцати   102
/// ```
///
/// **И два механизма, которые до сих дня считались одним.** Путаница
/// между ними и есть причина, по которой сто два поля никого
/// не насторожили:
///
/// ```
/// SwiftData + .private(iCloud.app.togo.diary)
///     возит ВСЕ семнадцать моделей — но только между СВОИМИ
///     устройствами одного Apple ID: iPhone и iPad хозяйки
///
/// SharedDiary / CKSyncEngine, общая зона
///     возит ПЯТЬ типов — и только это видит ВТОРОЙ ЧЕЛОВЕК
/// ```
///
/// То есть у хозяйки всё сходится на двух своих устройствах, и проверка
/// «синхронизация работает» проходит. А мама, у которой свой Apple ID,
/// не видит ни взвешиваний, ни документов, ни клиник, ни выездов,
/// ни занятий. Рядом с записью в журнале «у гостя всё получалось
/// и ничего не происходило»: вот чем это объясняется наполовину.
///
/// **Чего этот сторож НЕ утверждает:** что двенадцать моделей обязаны
/// ехать. Это решение продукта, а не разработчика. Он требует другого —
/// чтобы про каждую было **сказано вслух, с датой или с причиной**,
/// и чтобы новая модель не могла присоединиться к долгу молча.
