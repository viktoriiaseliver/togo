import Foundation
import Testing

/// Поле `Dog`, числящееся «про семью», обязано ехать к гостю.
///
/// **Зачем этот сторож появился.** 05.10.2026 сессия `togo-f5`
/// перечитала `Dog` поле за полем и нашла **двенадцать**, которые
/// числились «про семью» и не ехали никуда: весь лист для догситтера,
/// номера паспорта и страховки, четыре поля про занятия. Лист ситтера
/// существует ровно для того часа, когда хозяина нет рядом, — и на
/// втором телефоне был пуст. Нашли это **руками**, перечитав модель;
/// тринадцатое нашли бы так же.
///
/// Соседний `DeviceLocalFieldTests` на этот вопрос не отвечает и
/// отвечать не может: он делит поля на «про семью» и «про телефон»
/// и про нагрузку обмена не знает вовсе. `Dog.photo` и `Dog.createdAt`
/// лежат у него в «уезжать положено» и не едут ни одно.
///
/// **Почему он зелёный в день рождения.** Потому что двенадцать полей
/// починили за два дня до него, а он охраняет тринадцатое. Ноль здесь
/// — не «не нашёл», а «нечего было находить»; работа сторожа начинается
/// со следующего поля, которое кто-нибудь добавит в модель и забудет
/// в нагрузке. Что он умеет краснеть, проверено подделкой, а не
/// надеждой: вырезанное поле нагрузки даёт красный с именем поля.
@Suite("Поле про семью едет к гостю")
struct DogPayloadParityTests {

    // MARK: Источники

    /// Поля `Dog`, объявленные «про семью», — берутся **у соседнего
    /// сторожа**, а не копией.
    ///
    /// Второй список разошёлся бы с первым при первой же правке, и
    /// разошёлся бы молча: оба были бы зелёными, каждый про своё.
    private static var проСемью: [String] {
        DeviceLocalFieldTests.проСемью
            .filter { $0.hasPrefix("Dog.") }
            .map { String($0.dropFirst("Dog.".count)) }
            .sorted()
    }

    private static func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь),
                          encoding: .utf8)
    }

    /// Хранимые поля `DogPayload` — из исходника, а не списком.
    private static func поляНагрузки() throws -> Set<String> {
        let текст = try исходник("TogoShared/Sync/SharedDiary.swift")
        guard let начало = текст.range(of: "nonisolated struct DogPayload") else { return [] }
        let хвост = текст[начало.upperBound...]
        guard let конец = хвост.range(of: "\n}") else { return [] }
        let тело = хвост[..<конец.lowerBound]

        var найдено: Set<String> = []
        for строка in тело.components(separatedBy: .newlines) {
            // Членом считается только то, что стоит на уровне тела:
            // разбор по одной строке не отличает поле от локальной
            // переменной внутри вычисляемого свойства и ошибается
            // в сторону полноты. Наш замер 23.09: так снимок схемы
            // вышел богаче настоящего, и хранилище не открылось.
            guard строка.hasPrefix("    var "), !строка.hasPrefix("     ") else { continue }
            let голая = строка.dropFirst("    var ".count)
            guard let двоеточие = голая.firstIndex(of: ":") else { continue }
            найдено.insert(String(голая[..<двоеточие])
                .trimmingCharacters(in: .whitespaces))
        }
        return найдено
    }

    /// Поля `Dog`, объявленные связью. Такие не лежат **внутри**
    /// нагрузки собаки по устройству: каждая связь ездит своим типом
    /// записи.
    ///
    /// Исключение опознаётся **свойством, а не списком имён**: список
    /// из одиннадцати `…Storage` пришлось бы править руками при каждой
    /// новой связи, а `@Relationship` стоит в исходнике и врать не умеет.
    private static func поляСвязей() throws -> Set<String> {
        let строки = try исходник("TogoShared/Models/Dog.swift")
            .components(separatedBy: .newlines)
        var найдено: Set<String> = []
        for (i, строка) in строки.enumerated() where строка.contains("@Relationship(") {
            // Имя стоит на следующей строке, объявленной полем.
            for j in (i + 1)..<min(i + 4, строки.count) {
                let голая = строки[j].trimmingCharacters(in: .whitespaces)
                guard голая.hasPrefix("var "),
                      let двоеточие = голая.firstIndex(of: ":") else { continue }
                найдено.insert(String(голая[голая.index(голая.startIndex, offsetBy: 4)..<двоеточие])
                    .trimmingCharacters(in: .whitespaces))
                break
            }
        }
        return найдено
    }

    /// Поля, которым уезжать не положено, и **причина у каждого**.
    ///
    /// Пустая причина — падение: исключение без довода неотличимо
    /// от дыры, и следующий прочтёт его как решение. Наш класс
    /// «пропуск с обоснованием читается как решение, а не как пропуск»:
    /// довод здесь обязателен именно затем, чтобы его можно было
    /// оспорить, а не затем, чтобы он закрывал вопрос.
    private static let исключения: [String: String] = [
        "photo": """
            Решение брифа 22.09: снимки сделали бы обмен тяжёлым ровно \
            там, где он должен быть мгновенным. Фото каждый ставит у себя.
            """,
        "createdAt": """
            Факт о ЗАПИСИ, а не о собаке. У гостя строка заводится \
            в момент приёма приглашения, и его «завели» — правда про его \
            дневник. Привезти сюда дату хозяйки значило бы сказать, что \
            дневник у гостя существует с даты, которой у него не было.
            """,
    ]

    // MARK: Проверки

    /// Первой — проверка, что сторожу было что сторожить.
    ///
    /// Без неё всё остальное зелено на пустых списках и молчит так же,
    /// как если бы всё было хорошо. Пороги взяты от замера 07.10.2026
    /// (49 полей про семью, 36 в нагрузке, 11 связей) с запасом вниз:
    /// они ловят «разбор не состоялся», а не «кто-то убрал поле».
    @Test("Сторожу было что сторожить")
    func былоЧтоСторожить() throws {
        let семья = Self.проСемью
        let нагрузка = try Self.поляНагрузки()
        let связи = try Self.поляСвязей()

        #expect(семья.count >= 40, """
            полей `Dog` про семью разобрано \(семья.count) — разбор \
            не состоялся. Сторож, переставший что-либо находить, \
            молчит так же, как тот, кому нечего сказать.
            """)
        #expect(нагрузка.count >= 30, """
            полей `DogPayload` разобрано \(нагрузка.count) — разбор \
            исходника не состоялся, и проверка паритета ниже зелена \
            на пустом множестве.
            """)
        #expect(связи.count >= 10, """
            связей `Dog` разобрано \(связи.count) — а их одиннадцать. \
            Разбор `@Relationship` не состоялся, и тогда одиннадцать \
            связей уедут в находки ложными.
            """)
    }

    /// Запрет: поля про семью, которого нет ни в нагрузке, ни в связях,
    /// ни в исключениях с причиной, — не бывает.
    @Test("Каждое поле про семью едет, либо названо исключением с причиной")
    func каждоеПолеПроСемьюЕдет() throws {
        let нагрузка = try Self.поляНагрузки()
        let связи = try Self.поляСвязей()

        var потерянные: [String] = []
        for поле in Self.проСемью {
            if связи.contains(поле) { continue }
            if let причина = Self.исключения[поле] {
                #expect(причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false,
                        "у исключения `\(поле)` пустая причина")
                continue
            }
            // `sexRaw` едет как `sex`, `markerKindRaw` — как `markerKind`:
            // в модели лежит строка сырого значения, в нагрузке — она же
            // под именем без суффикса. Не знай сторож этого отображения,
            // он дал бы две ложные находки на верном коде — а ложная
            // находка дороже пропущенной: после неё сторожа перестают
            // читать.
            let безRaw = поле.hasSuffix("Raw") ? String(поле.dropLast(3)) : поле
            if нагрузка.contains(поле) || нагрузка.contains(безRaw) { continue }
            потерянные.append(поле)
        }

        #expect(потерянные.isEmpty, """
            поля `Dog` числятся «про семью» и не едут к гостю: \
            \(потерянные.joined(separator: ", ")).

            Либо добавь их в `DogPayload` и в оба конца `SharedDiaryRecords`, \
            либо впиши сюда в `исключения` с причиной. Третьего нет: \
            молчаливый пропуск неотличим от того, что про поле не подумали.

            Так 05.10.2026 не ехали двенадцать полей разом, включая весь \
            лист для догситтера — функцию, которая не работала \
            в единственном сценарии, ради которого написана.
            """)
    }

    /// Обратная половина: исключение, закрывающее поле, которого нет, —
    /// лишняя дыра, про которую никто не помнит.
    @Test("Исключение закрывает существующее поле")
    func исключенияНеПротухли() throws {
        let семья = Set(Self.проСемью)
        let лишние = Self.исключения.keys.filter { семья.contains($0) == false }
        #expect(лишние.isEmpty, """
            исключения стоят на полях, которых среди «про семью» нет: \
            \(лишние.sorted().joined(separator: ", ")). Поле переименовали \
            или убрали, а исключение осталось — и теперь оно молча \
            разрешает то, чего никто не разрешал.
            """)
    }

    /// Граница собственного умения — печатается всегда, а не хранится
    /// в чьей-то памяти.
    @Test("Сторож называет, чего он не умеет")
    func границаНазвана() {
        let границы = """
            Зелёный здесь значит: каждое поле `Dog` про семью лежит \
            в `DogPayload` — и только это.

            НЕ проверяется:
            · доехало ли поле на самом деле — `SharedDiaryRecords` \
              пишет и читает запись отдельно, и поле может лежать \
              в нагрузке, не попав в `CKRecord`;
            · верное ли значение приехало — паритет про имена, не про смысл;
            · поля других моделей — здесь только `Dog`.
            """
        #expect(границы.isEmpty == false)
    }
}
