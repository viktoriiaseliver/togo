import Testing
import Foundation
@testable import Togo

/// Жест на всю карточку ставится только там, где он открывает.
///
/// Отзыв: «Нажатие на один из таймеров закрывает экран». Секундомер идущего
/// выхода лежит внутри карточки на главном экране, а на карточке висел
/// `onTapGesture(perform: onOpen)` — и у выхода `onOpen` означал не
/// «открыть», а `endOuting()`, то есть **завершить**. Палец попадал
/// в секундомер мимо кнопки «Стоп», выход заканчивался и поверх открывалась
/// шторка «Как сходил?». В тихие часы ещё тише: выход закрывается молча,
/// и экран меняется сам.
///
/// У прогулки тот же жест верен: там он и правда открывает режим обратно,
/// и потерять прогулку, свернув шторку, нельзя.
///
/// Проверяется исходником: жест в SwiftUI из теста не нажать, а условие
/// в нём — ровно то, что стоило человеку выхода.
@Suite("Тап по карточке сессии не завершает выход")
struct ActiveSessionTapTests {

    private func исходник(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        return try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    @Test("Жест на всю карточку спрашивает вид сессии")
    func жестСпрашиваетВид() throws {
        let текст = try исходник("Togo/Features/Needs/WalkMode.swift")

        #expect(!текст.contains(".onTapGesture(perform: onOpen)"), """
            тап по всей карточке снова зовёт onOpen без условия.
            У выхода onOpen — это завершение, а не открытие: человек
            попадает пальцем в секундомер и теряет выход.
            """)
        #expect(текст.contains("if session.kind == .walk { onOpen() }"), """
            условие на вид сессии исчезло. Жест на всю карточку ставится
            только там, где он открывает; завершение спрашивает кнопку.
            """)
    }

    /// Вторая половина того же дефекта: у выхода кнопка называется «Стоп»,
    /// и она обязана оставаться единственным способом его закончить.
    @Test("Кнопка выхода по-прежнему завершает, а прогулки — открывает")
    func кнопкаРазличаетВиды() throws {
        let текст = try исходник("Togo/Features/Needs/WalkMode.swift")
        #expect(текст.contains("session.kind == .walk ? onOpen() : onFinish()"), """
            кнопка перестала различать прогулку и выход: у прогулки она
            открывает режим, у выхода — заканчивает его.
            """)
    }
}
