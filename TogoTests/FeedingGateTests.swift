import Testing
import Foundation
@testable import Togo

@Suite("Кормление и окно натощак")
@MainActor
struct FeedingGateTests {

    private let календарь = Calendar.current

    private func момент(_ час: Int, _ минута: Int = 0) -> Date {
        календарь.date(bySettingHour: час, minute: минута, second: 0, of: Date())!
    }

    /// Схема: таблетка в 21:00, натощак час — значит и до, и после.
    private func схема(
        времена: [Int] = [21 * 60],
        после: Int = 60,
        до: Int? = nil
    ) -> Medication {
        let m = Medication(name: "Урсосан", doseText: "1 таблетка", times: времена)
        m.fastingMinutes = после
        if let до { m.fastingBeforeMinutes = до }
        return m
    }

    // MARK: - То, ради чего всё заведено

    /// Дефект, которого прежняя модель не видела: покормили в 20:55,
    /// таблетка в 21:00. Окно ПОСЛЕ соблюдено идеально — а таблетка
    /// уходит в полный желудок, то есть схема нарушена целиком.
    @Test("За час до дозы кормить нельзя — этого правила не было вовсе")
    func передДозойКормитьНельзя() {
        let блок = FeedingGate.block(for: [схема()], now: момент(20, 55), calendar: календарь)

        #expect(блок != nil, "еда за пять минут до дозы натощак должна быть заперта")
        #expect(блок?.medication == "Урсосан")
        if case .before(_, let доза) = блок {
            #expect(доза == момент(21, 0), "запирает ближайшая доза, а не какая-то другая")
        } else {
            Issue.record("ожидали причину «до дозы», пришло: \(String(describing: блок))")
        }
    }

    /// Граница окна принадлежит окну: ровно за час — уже нельзя.
    /// Иначе правило читается как «почти час», и человек кормит в 20:00.
    @Test("Граница окна «до» запирает, а минутой раньше — свободно")
    func границаОкнаДо() {
        #expect(FeedingGate.block(for: [схема()], now: момент(20, 0), calendar: календарь) != nil)
        #expect(FeedingGate.block(for: [схема()], now: момент(19, 59), calendar: календарь) == nil)
    }

    /// Сама доза окно закрывает: дальше решает отметка приёма,
    /// а не расписание.
    @Test("В момент дозы окно «до» кончается")
    func вМоментДозыСвободно() {
        #expect(FeedingGate.block(for: [схема()], now: момент(21, 0), calendar: календарь) == nil)
    }

    // MARK: - Прежнее поведение не сломано

    @Test("После отметки приёма кормить нельзя час, и причина — другая")
    func послеДозыКормитьНельзя() {
        let m = схема()
        let доза = DoseRecord(scheduledAt: момент(21, 0))
        доза.givenAt = момент(21, 12)   // `isGiven` вычисляется отсюда
        m.dosesStorage = [доза]

        let блок = FeedingGate.block(for: [m], now: момент(21, 30), calendar: календарь)

        if case .after(_, let дано, let до) = блок {
            // Отсчёт от ФАКТА, а не от расписания: дали в 21:12 —
            // свободно в 22:12, а не в 22:00.
            #expect(дано == момент(21, 12))
            #expect(до == момент(22, 12))
        } else {
            Issue.record("ожидали причину «после дозы», пришло: \(String(describing: блок))")
        }

        #expect(FeedingGate.block(for: [m], now: момент(22, 13), calendar: календарь) == nil)
    }

    /// Когда окна накладываются, человеку важнее уже случившееся.
    @Test("Выпитая доза перевешивает плановую")
    func фактВажнееПлана() {
        let m = схема(времена: [21 * 60, 22 * 60])
        let доза = DoseRecord(scheduledAt: момент(21, 0))
        доза.givenAt = момент(21, 5)
        m.dosesStorage = [доза]

        let блок = FeedingGate.block(for: [m], now: момент(21, 30), calendar: календарь)
        if case .after = блок {} else {
            Issue.record("ожидали «после дозы»: она уже выпита, план подождёт")
        }
    }

    // MARK: - Границы, на которых такое обычно и ломается

    /// Доза в 00:30 запирает еду с 23:30 ПРЕДЫДУЩЕГО дня. Без завтрашнего
    /// дня в расчёте этого окна не существовало бы вовсе.
    ///
    /// **Вечер строится часом на часах, а не прибавлением минут к полуночи.**
    /// До 25.10.2026 здесь стояло `date(byAdding: .minute, value: 23 * 60 + 45,
    /// to: startOfDay)` — и это РАЗНЫЕ величины ровно дважды в году. Замер
    /// 25.10.2026, Europe/Paris, в сутках 25 часов:
    ///
    /// ```
    /// startOfDay + 1425 минут      2026-10-25 22:45 GMT+1   ← предмет
    /// bySettingHour(23, 45)        2026-10-25 23:45 GMT+1   ← контроль
    /// то же построение 26.10       2026-10-26 23:45 GMT+1   ← обычные сутки, совпало
    /// ```
    ///
    /// Окно «до» открывается в 23:30, и 22:45 в него не попадает: сторож
    /// краснел на ВЕРНОМ коде. `FeedingGate.upcoming` считает дозу
    /// `date(minuteOfDay:on:)` с 22.09.2026 (`9d3ec6a`) — по стенным часам,
    /// то есть правильно; минуты складывал только сам тест.
    ///
    /// > **Сторож нарушал ровно то правило, которое стережёт.** Предмет
    /// > этого набора — «минуты от полуночи это час на часах, а не отрезок»,
    /// > и построение входа в тесте обязано держать его наравне с кодом.
    /// > Тот же класс и тем же днём разобран в `c2d0df0` на тесте доз.
    @Test("Окно переживает полночь")
    func окноЧерезПолночь() {
        let m = схема(времена: [30])
        #expect(FeedingGate.block(for: [m], now: момент(23, 45), calendar: календарь) != nil)
    }

    @Test("Приостановленная схема не запирает еду")
    func приостановленнаяНеЗапирает() {
        let m = схема()
        m.isPaused = true
        #expect(FeedingGate.block(for: [m], now: момент(20, 30), calendar: календарь) == nil)
    }

    @Test("Лекарство не натощак не запирает еду никогда")
    func обычноеЛекарствоНеЗапирает() {
        let m = схема(после: 0, до: 0)
        #expect(FeedingGate.block(for: [m], now: момент(20, 30), calendar: календарь) == nil)
    }

    /// Старые схемы поле «до» заполнить не могли — его не было.
    /// Отдавать по ним «кормить можно» значило бы отвечать неверно там,
    /// где ответ известен.
    @Test("У схемы без окна «до» оно равно окну «после»")
    func староеОкноЧитаетсяСимметрично() {
        let m = схема()
        #expect(m.fastingBeforeMinutes == 0, "поле и правда не заполнено")
        #expect(m.fastingBefore == 60, "но читается как симметричное")

        let свой = схема(после: 60, до: 30)
        #expect(свой.fastingBefore == 30, "явно заданное окно важнее умолчания")
    }

    /// Проверка подделкой: если убрать окно «до», тест выше обязан
    /// покраснеть. Здесь же — доказательство, что правило вообще
    /// что-то меняет, а не просто повторяет окно «после».
    @Test("Без окна «до» время перед дозой было бы свободным")
    func безОкнаДоБылоБыСвободно() {
        let без = схема(после: 60, до: 0)
        без.fastingMinutes = 0
        #expect(без.fastingBefore == 0)
        #expect(FeedingGate.block(for: [без], now: момент(20, 55), calendar: календарь) == nil,
                "подделка не сработала — значит первый тест держится не на окне «до»")
    }
}
