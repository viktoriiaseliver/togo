import Testing
import Foundation

/// Откатная конфигурация хранилища объявляет отсутствие облака ЯВНО.
///
/// **Чем это оплачено.** 08.10.2026 отказ стенда трижды сорвал прогон
/// на вершине: `NSInternalInconsistencyException · 'No eligible
/// connection available'`, восемь смертей, четыре выполненных теста
/// при пороге 800. Строка итога при этом сказала `passed`.
///
/// Причина не в коде тестов и не в симуляторе:
///
/// ```
/// «права на iCloud нет — только локально»   × 8    наше решение
/// «хранилище: локальное»                    × 6    наша запись
/// NSCloudKitMirroringDelegate               × 182  что происходило
/// CKAccountStatusNoAccount                  × 21
/// → Terminating app due to uncaught exception × 8
/// ```
///
/// > **Ветка отката называлась локальной и локальной не была.**
/// > Решение принималось верно, в исполнение приводилось не то.
///
/// Право на iCloud в бандле есть (`Togo.entitlements:9`),
/// а `ModelConfiguration(schema:url:)` без `cloudKitDatabase`
/// зеркалирование не отключает.
///
/// **Почему сторож текстовый, а не поведенческий.** Поведенческий
/// был бы сильнее, и его здесь нет не из лени: чтобы отличить
/// «зеркалирование выключено» от «включено и молчит», нужен прогон
/// без учётной записи iCloud **и** способ спросить контейнер, с каким
/// `cloudKitDatabase` он открыт. Второго у `ModelContainer` в публичном
/// интерфейсе нет. Поэтому здесь сторожится то, что проверяемо —
/// **объявление**, — и граница названа вслух, а не умолчана.
///
/// Это ровно тот класс, который у нас записан: «сторож на вызов видит,
/// что имя упомянуто, и не видит, что от упоминания ничего
/// не происходит». Приёмка самой починки — прогон, и он отдельно
/// от этого файла.
@Suite("Откат хранилища объявляет отсутствие облака")
struct ОткатБезОблакаTests {

    private var исходник: String {
        get throws {
            let корень = URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent()
                .deletingLastPathComponent()
            return try String(
                contentsOf: корень.appendingPathComponent("TogoShared/Domain/Persistence.swift"),
                encoding: .utf8
            )
        }
    }

    /// Код без комментариев: сканирующий сторож, не различающий код
    /// и прозу, меряет прозу. У Timer такой покраснел на строке
    /// «// НЕ `MapsApp.allCases`», то есть наказал за объяснение,
    /// почему так делать нельзя. Здесь это обязательно: в самой правке
    /// `cloudKitDatabase` упомянут в доккомментарии трижды.
    private var код: String {
        get throws {
            try исходник
                .split(separator: "\n", omittingEmptySubsequences: false)
                .map { String($0.components(separatedBy: "//")[0]) }
                .joined(separator: "\n")
        }
    }

    @Test("Разбору было что читать, и вырезание комментариев работает")
    func разборЦел() throws {
        let весь = try исходник
        let чистый = try код
        #expect(весь.count > 5000, """
            `Persistence.swift` прочитан как \(весь.count) знаков — это
            не файл. На пустом тексте все утверждения ниже выполняются,
            и зелёный здесь означал бы обратное правде.
            """)
        #expect(чистый.count < весь.count, """
            Вырезание комментариев не убрало ни одного знака — значит
            оно не работает, и сторож ниже меряет прозу вместе с кодом.
            """)
        // Доккомментарий правки содержит «cloudKitDatabase» — если
        // вырезание сломается, этот запрет поймает именно это.
        #expect(!чистый.contains("Ветка отката называлась локальной"), """
            Текст доккомментария пережил вырезание. Проверки ниже
            с этого момента меряют объяснение, а не код.
            """)
    }

    @Test("Откатная конфигурация объявляет cloudKitDatabase: .none")
    func откатОбъявляетОтсутствиеОблака() throws {
        let чистый = try код
        #expect(чистый.contains("cloudKitDatabase: .none"), """
            В `Persistence.swift` нет ни одного `cloudKitDatabase: .none`.

            Значит откатная ветка снова строит конфигурацию без явного
            отключения облака — и будет называться локальной, не будучи
            локальной. Это тот самый отказ: 182 вхождения
            `NSCloudKitMirroringDelegate` при шести строках «хранилище:
            локальное», и восемь смертей на `save()`.
            """)
    }

    @Test("Ни одна конфигурация не умалчивает про облако — и та, что в памяти, тоже")
    func нетКонфигурацийБезОблачногоПараметра() throws {
        let чистый = try код

        // Разбор от ОБЪЯВЛЕНИЯ: берём каждый вызов `ModelConfiguration(`
        // и смотрим его аргументы до закрывающей скобки. Шаблон по месту
        // вызова («как отформатировано») ломается от переноса строки —
        // у нас это уже стоило числа, верного по счёту случайно.
        var без_параметра: [String] = []
        var остаток = Substring(чистый)
        while let начало = остаток.range(of: "ModelConfiguration(") {
            var глубина = 0
            var конец = начало.upperBound
            var индекс = начало.lowerBound
            var внутри = Substring("")
            while индекс < остаток.endIndex {
                let символ = остаток[индекс]
                if символ == "(" { глубина += 1 }
                if символ == ")" {
                    глубина -= 1
                    if глубина == 0 {
                        конец = остаток.index(after: индекс)
                        внутри = остаток[начало.upperBound..<индекс]
                        break
                    }
                }
                индекс = остаток.index(after: индекс)
            }
            let вызов = String(внутри)
            // ИСКЛЮЧЕНИЯ ДЛЯ `isStoredInMemoryOnly` ЗДЕСЬ БОЛЬШЕ НЕТ.
            //
            // Оно стояло с доводом «в памяти облака нет по устройству:
            // хранилища на диске нет, зеркалить нечего» — и само назвало
            // условие, при котором довод перестаёт быть верным: «если
            // в логе прогона с ним появится `NSCloudKitMirroringDelegate`.
            // Проверяется грепом по логу, а не чтением».
            //
            // **Грепом по логу проверено 25.10.2026, и довод ложен**
            // (`build/logs/unit-20261025-144557-98906.log`, один
            // `make unit` на `2576ed9`):
            //
            // ```
            // разных NSCloudKitMirroringDelegate за прогон      213
            // из них с НАЗВАННЫМ хранилищем                      24
            //   и все 24 названы одинаково: file:///dev/null — это
            //   и есть хранилище в памяти
            // строк «store was removed …»                       770
            // адрес базы приложения (App Group) в тех же строках  0 ← контроль
            // ```
            //
            // Контроль здесь не из того же семейства, что предмет:
            // предмет — хранилище в памяти, контроль — адрес настоящей
            // базы приложения. Будь ноль у обоих, вопрос был бы не тот.
            //
            // Оговорка защищала ровно ту запись, в которой стояла,
            // и восемнадцать дней читалась как замер, потому что лежала
            // в сторожевом файле рядом с замерами. Запускать её было
            // некому: «проверяется грепом по логу» — это способ без
            // хозяина и без расписания.
            if !вызов.contains("cloudKitDatabase") {
                без_параметра.append(вызов.prefix(80) + "…")
            }
            остаток = остаток[конец...]
        }

        #expect(без_параметра.isEmpty, """
            Есть конфигурации хранилища, которые про облако умалчивают
            — \(без_параметра.count):

            \(без_параметра.joined(separator: "\n"))

            Умолчание здесь не нейтрально: право на iCloud в бандле
            есть, и конфигурация без `cloudKitDatabase` зеркалирование
            не выключает — **ни файловая, ни та, что в памяти**.
            Ветка будет называться локальной, не будучи ею.
            """)
    }

    /// Контроль «сторожу было что находить»: вызовов
    /// `ModelConfiguration(` в файле не ноль. Переставший что-либо
    /// находить разбор молчит так же, как тот, кому нечего сказать.
    @Test("Разбор нашёл конфигурации, а не промолчал")
    func разборНашёлВызовы() throws {
        let чистый = try код
        let сколько = чистый.components(separatedBy: "ModelConfiguration(").count - 1
        #expect(сколько >= 3, """
            Вызовов `ModelConfiguration(` найдено \(сколько). Их в файле
            не меньше трёх (облако · локальное с файлом · локальное без
            файла), плюс два в памяти. Меньше — значит разбор ослеп,
            и запрет выше выполняется на пустоте.
            """)
    }

    // MARK: - Весь репозиторий, а не один файл

    /// Все `.swift` дерева, кроме самого сторожа.
    ///
    /// **Почему сторож исключает себя, и это не поблажка.** Разбор ниже
    /// ищет текст `ModelConfiguration(` и читает его аргументы. В этом
    /// файле такой текст есть внутри строкового литерала
    /// (`range(of: "ModelConfiguration(")`), и после вырезания
    /// комментариев он остаётся кодом. Разбор прочёл бы литерал
    /// как вызов без `cloudKitDatabase` и покраснел бы на самом себе —
    /// красный, у которого нет предмета. Исключение именное и одно.
    private func файлыДерева() -> [URL] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        var итог: [URL] = []
        for каталог in ["Togo", "TogoShared", "TogoTests", "TogoUITests", "TogoWidgets"] {
            let путь = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(
                at: путь, includingPropertiesForKeys: nil) else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                if url.lastPathComponent == URL(fileURLWithPath: #filePath).lastPathComponent {
                    continue
                }
                итог.append(url)
            }
        }
        return итог
    }

    private func безКомментариев(_ текст: String) -> String {
        текст.split(separator: "\n", omittingEmptySubsequences: false)
            .map { String($0.components(separatedBy: "//")[0]) }
            .joined(separator: "\n")
    }

    /// Вызовы `ModelConfiguration(` файла и их аргументы — тем же
    /// разбором по скобкам, что и у `Persistence.swift` выше.
    private func вызовыКонфигураций(_ код: String) -> [String] {
        var найдено: [String] = []
        var остаток = Substring(код)
        while let начало = остаток.range(of: "ModelConfiguration(") {
            var глубина = 0
            var конец = начало.upperBound
            var индекс = начало.lowerBound
            var внутри = Substring("")
            while индекс < остаток.endIndex {
                let символ = остаток[индекс]
                if символ == "(" { глубина += 1 }
                if символ == ")" {
                    глубина -= 1
                    if глубина == 0 {
                        конец = остаток.index(after: индекс)
                        внутри = остаток[начало.upperBound..<индекс]
                        break
                    }
                }
                индекс = остаток.index(after: индекс)
            }
            найдено.append(String(внутри))
            остаток = остаток[конец...]
        }
        return найдено
    }

    /// **Почему запрет нужен на всё дерево, а не на один файл.**
    ///
    /// Сторож выше читал только `Persistence.swift` — и 25.10.2026
    /// выяснилось, чего это стоило: двадцать семь конфигураций в памяти
    /// жили в одиннадцати файлах `TogoTests`, ещё по одной
    /// в `ArchiveFieldValueTests` и в `MedicalRecordGallery` (это уже
    /// код приложения, не тест). Замер одного `make unit` на `2576ed9`:
    /// **213 разных `NSCloudKitMirroringDelegate` за прогон**, и все
    /// названные ими хранилища — `file:///dev/null`, то есть в памяти.
    ///
    /// Правка только `Persistence.container()` убрала 213 → 20,
    /// то есть 90 % приходило оттуда — и оставшиеся 20 показывают,
    /// что сторож на один файл закрывал один вход из тринадцати.
    @Test("Ни один файл дерева не заводит хранилище, умалчивая про облако")
    func нетУмолчанийВоВсёмДереве() throws {
        var умолчали: [String] = []
        var всегоВызовов = 0
        var прочитаноФайлов = 0

        for url in файлыДерева() {
            guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
            прочитаноФайлов += 1
            for вызов in вызовыКонфигураций(безКомментариев(текст)) {
                всегоВызовов += 1
                if !вызов.contains("cloudKitDatabase") {
                    умолчали.append("\(url.lastPathComponent): \(вызов.prefix(70))…")
                }
            }
        }

        // Контроль ПЕРВЫМ и в том же замере, что предмет: обход,
        // переставший находить файлы, молчит так же, как дерево без
        // нарушений. Числа здесь — нижние границы, не точные значения.
        #expect(прочитаноФайлов > 200, """
            Обход прочитал \(прочитаноФайлов) файлов `.swift` — это
            не дерево Того. Запрет ниже выполняется на пустоте.
            """)
        #expect(всегоВызовов >= 10, """
            Вызовов `ModelConfiguration(` во всём дереве найдено
            \(всегоВызовов). Их там десятки. Разбор ослеп.
            """)

        #expect(умолчали.isEmpty, """
            Конфигураций хранилища без `cloudKitDatabase` — \(умолчали.count):

            \(умолчали.joined(separator: "\n"))

            `isStoredInMemoryOnly` зеркалирование НЕ отключает: замер
            25.10.2026 дал 213 разных `NSCloudKitMirroringDelegate`
            за один `make unit`, и все названные хранилища были
            `file:///dev/null`. Каждый такой делегат не находит iCloud,
            не восстанавливается и убирает хранилище из координатора —
            а дальше таймер автосохранения SwiftData падает в `brk #1`
            внутри `-[ModelContext checkAutosaveConditions]`.
            """)
    }
}
