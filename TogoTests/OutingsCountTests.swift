import Testing
import Foundation
@testable import Togo

/// Счёт выходов за день — единая реализация (`6e8e402`).
///
/// До неё экран считал блоки сам, а карточка сводки — события `.outing`,
/// и на одном кадре отзыва стояло **«2 выхода из 4 за день» над
/// «3 выхода»**. Обе арифметики были верны порознь; расходились смыслы.
/// Дефект поймал кадр, и тест такого не видит по устройству — но
/// у самой величины сторожа не было вовсе, а она теперь одна на две
/// поверхности.
///
/// Утверждения парные нарочно. «Отметки не раздувают счёт» истинно
/// и у функции, возвращающей единицу всегда, — поэтому рядом стоит
/// случай, где выходов честно два.
@MainActor
@Suite("Счёт выходов за день")
struct OutingsCountTests {

    private var день: Date { Calendar.current.startOfDay(for: Date()) }

    private func прогулка(_ час: Int, минут: Int = 30) -> LogEvent {
        let e = LogEvent(kind: .walk,
                         date: день.addingTimeInterval(Double(час) * 3600),
                         authorName: "Виктория")
        e.durationSeconds = минут * 60
        return e
    }

    private func отметка(внутри прогулка: LogEvent, через секунд: Double) -> LogEvent {
        let e = LogEvent(kind: .outing,
                         date: прогулка.date.addingTimeInterval(секунд),
                         authorName: "Виктория")
        e.walkEventID = прогулка.id
        return e
    }

    @Test("Было что проверять: два настоящих выхода считаются как два")
    func дваВыходаЭтоДва() {
        // Первой проверкой. Без неё «три отметки дают один выход» зелено
        // и у функции, которая отвечает «один» на что угодно, — а такая
        // функция сказала бы человеку, что собаку вывели однажды,
        // при четырёх прогулках.
        let события = [прогулка(9), прогулка(14)]
        #expect(TimelineBuilder.outingsCount(события, on: день) == 2)
    }

    @Test("Три отметки внутри одной прогулки — это один выход")
    func отметкиНеРаздуваютСчёт() {
        // Дефект `6e8e402` дословно: считаются БЛОКИ, а не события.
        // Человек, отметивший мочу, стул и «поиграли» за одну прогулку,
        // не выходил трижды.
        let гуляли = прогулка(9)
        let отметки = [
            отметка(внутри: гуляли, через: 0),
            отметка(внутри: гуляли, через: 300),
            отметка(внутри: гуляли, через: 600)
        ]
        #expect(TimelineBuilder.outingsCount([гуляли] + отметки, on: день) == 1)
    }

    @Test("Отметки внутри второй прогулки не склеивают её с первой")
    func двеПрогулкиСОтметкамиОстаютсяДвумя() {
        // Соединение двух утверждений выше, и оно ловит то, чего
        // не ловит ни одно из них порознь: группировку, которая
        // схлопывает ВСЁ в один блок. При ней первый тест дал бы 2
        // (отметок нет), второй — 1 (одна прогулка), и оба были бы
        // зелёными при полностью сломанном счёте.
        let утро = прогулка(9)
        let вечер = прогулка(19)
        let события = [утро, вечер,
                       отметка(внутри: утро, через: 300),
                       отметка(внутри: вечер, через: 300)]
        #expect(TimelineBuilder.outingsCount(события, on: день) == 2)
    }

    @Test("День без выходов — ноль, а не пустота, выданная за единицу")
    func безВыходовНоль() {
        let кормёжка = LogEvent(kind: .meal, date: день.addingTimeInterval(8 * 3600),
                                authorName: "Виктория")
        #expect(TimelineBuilder.outingsCount([кормёжка], on: день) == 0)
        #expect(TimelineBuilder.outingsCount([], on: день) == 0)
    }

    @Test("Границы: чего не проверяет набор про счёт выходов")
    func границы() {
        // 1. **Что шапка и карточка сводки показывают ОДНО число.**
        //    Сейчас это держится структурой, а не проверкой:
        //    `TodaySummaryStrip` принимает `outings: Int` параметром,
        //    а считает его экран через `TimelineBuilder.outingsCount`.
        //    Заведи кто-нибудь второй расчёт внутри карточки — этот
        //    набор смолчит. Расхождение двух верных арифметик поймал
        //    кадр, и поймать его может только кадр.
        // 2. **Вторая арифметика выходов в приложении существует.**
        //    `HistoryScreen.swift:311` считает
        //    `events.filter { $0.kind == .outing }.count` — то есть
        //    СОБЫТИЯ, а не блоки. На дне с одной прогулкой и тремя
        //    отметками график истории покажет 3 там, где главный экран
        //    покажет 1. Намеренно это или нет — решать не тестировщику,
        //    но названо здесь, чтобы не считалось непойманным.
        #expect(Bool(true))
    }
}
