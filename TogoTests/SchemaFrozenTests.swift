import Testing
import Foundation
import SwiftData
@testable import Togo

/// Прежние версии схемы — снимки, а не ссылки на нынешние классы.
///
/// **Чем это оплачено.** До 23.09.2026 `TogoSchemaV3` перечисляла
/// настоящие классы приложения. Пока модель не менялась, всё работало
/// и выглядело экономно. Первая же правка — `Dog.changedAt` ради обмена
/// профилем — сломала не сборку, а **открытие хранилища**: форма классов
/// стала другой, версия осталась 3.0.0, и SwiftData ответила «Cannot use
/// staged migration with an unknown model version».
///
/// На телефоне это не падение. `Persistence.appContainer()` откатывается
/// iCloud → локально → в память: человек видит рабочий экран, отмечает
/// дозу, получает подтверждение — и запись не сохраняется никуда.
/// Тихая потеря дневника с лечением, и ровно ради этого случая план
/// миграции вообще появился 21.09.
///
/// Сторож ловит **возврат к ссылкам**, а не форму отдельного поля:
/// сломалось именно это, и повторить легко — следующая правка модели
/// обязана заморозить V4 и завести V5.
@Suite("Прежние версии схемы заморожены")
struct SchemaFrozenTests {

    private func поля(_ версия: any VersionedSchema.Type, _ сущность: String) -> Set<String> {
        let schema = Schema(versionedSchema: версия)
        guard let entity = schema.entities.first(where: { $0.name == сущность })
        else { return [] }
        return Set(entity.properties.map(\.name))
    }

    /// Две стадии подряд, и каждая добавляет своё.
    ///
    /// **Переписано 29.10.2026 при сведении двух линий.** Прежняя
    /// редакция утверждала «V8 отличается от V7 только датой начала
    /// схемы» — она пришла из облачной сессии, где `Medication.startedAt`
    /// был восьмой формой. Но номер 8 к тому часу уже уехал людям
    /// в сборке 284 с другим содержимым (поля документа), и дата начала
    /// стала девятой. Разбор — в шапке `TogoSchemaV9`.
    ///
    /// Снимки собраны машиной из предыдущих; этот тест — их приёмка
    /// на настоящей `Schema`, а не на разборе текста: разойдись снимок
    /// с живыми классами в любом другом поле — здесь появится лишняя
    /// разница, и `.lightweight` перестанет быть правдой про стадию.
    @Test("V8 добавляет поля документа, V9 — дату начала схемы")
    func стадииДобавляютСвоё() {
        // V7 → V8: четыре поля формы, уехавшей в 284.
        #expect(поля(TogoSchemaV8.self, "DogDocument")
                    .subtracting(поля(TogoSchemaV7.self, "DogDocument"))
                == ["occurredOn", "directionRaw", "clinic"])
        #expect(поля(TogoSchemaV8.self, "Clinic")
                    .subtracting(поля(TogoSchemaV7.self, "Clinic"))
                == ["documentsStorage"])

        // V8 → V9: одна дата начала схемы лечения.
        #expect(поля(TogoSchemaV9.self, "Medication")
                    .subtracting(поля(TogoSchemaV8.self, "Medication")) == ["startedAt"])
        #expect(поля(TogoSchemaV8.self, "Medication")
                    .subtracting(поля(TogoSchemaV9.self, "Medication")).isEmpty)

        // Прочие сущности между V8 и V9 не менялись ничем.
        let прочие = Schema(versionedSchema: TogoSchemaV9.self).entities.map(\.name)
            .filter { $0 != "Medication" }
        #expect(прочие.count == 20)
        for сущность in прочие {
            #expect(поля(TogoSchemaV8.self, сущность) == поля(TogoSchemaV9.self, сущность),
                    "снимок V8 разошёлся со снимком V9 в «\(сущность)»")
        }

        // V9 → V10: чей эпизод (29.10.2026). Остальные двадцать
        // сущностей — без единой разницы: снимок V9 собран машиной
        // и сверен с живыми классами, здесь его приёмка на `Schema`.
        #expect(поля(TogoSchemaV10.self, "Episode")
                    .subtracting(поля(TogoSchemaV9.self, "Episode")) == ["dogID"])
        #expect(поля(TogoSchemaV9.self, "Episode")
                    .subtracting(поля(TogoSchemaV10.self, "Episode")).isEmpty)
        let кромеЭпизода = Schema(versionedSchema: TogoSchemaV10.self).entities.map(\.name)
            .filter { $0 != "Episode" }
        #expect(кромеЭпизода.count == 20)
        for сущность in кромеЭпизода {
            #expect(поля(TogoSchemaV9.self, сущность) == поля(TogoSchemaV10.self, сущность),
                    "снимок V9 разошёлся со снимком V10 в «\(сущность)»")
        }

        // V10 → V11: разовое исключение кормления на дату (05.11.2026).
        // Два поля у собаки, остальные двадцать сущностей — без единой
        // разницы. Снимок V10 собран машиной из V9 плюс `Episode.dogID`
        // и сверен с живыми классами разбором хранимых полей
        // (321 против 322, расхождение одно); здесь его приёмка
        // на настоящей `Schema`.
        #expect(поля(TogoSchemaV11.self, "Dog")
                    .subtracting(поля(TogoSchemaV10.self, "Dog"))
                == ["разовыеВременаДата", "разовыеВремена"])
        #expect(поля(TogoSchemaV10.self, "Dog")
                    .subtracting(поля(TogoSchemaV11.self, "Dog")).isEmpty, """
            V11 потеряла поле, которое было в V10. Удаление поля
            `.lightweight` не выводит, а хранилище V10 несут все сборки
            после 285.
            """)
        let кромеСобаки = Schema(versionedSchema: TogoSchemaV11.self).entities.map(\.name)
            .filter { $0 != "Dog" }
        #expect(кромеСобаки.count == 20)
        for сущность in кромеСобаки {
            #expect(поля(TogoSchemaV10.self, сущность) == поля(TogoSchemaV11.self, сущность),
                    "снимок V10 разошёлся с живыми классами в «\(сущность)»")
        }
    }

    /// Нынешняя версия — последняя в плане, и она же у хранилища.
    /// Расхождение здесь значит, что схему подняли, а открывают старой.
    @Test("Хранилище открывается последней версией плана")
    func хранилищеНаПоследней() throws {
        let последняя = try #require(TogoMigrationPlan.schemas.last)
        #expect(Persistence.schema.version == последняя.versionIdentifier, """
            хранилище открывается версией \(Persistence.schema.version),
            а последняя в плане — \(последняя.versionIdentifier).
            Форма поменялась под неизменной версией: у тех, у кого стоит
            прежняя сборка, дневник молча не откроется.
            """)
    }

    /// Каждая пара соседних версий обязана чем-то отличаться. Две
    /// одинаковые версии — это план, который выглядит планом и ничего
    /// не переводит.
    @Test("Соседние версии схемы отличаются хотя бы одним полем")
    func соседиОтличаются() {
        let версии = TogoMigrationPlan.schemas
        #expect(версии.count >= 4, "версий в плане \(версии.count) — плана нет")

        for (левая, правая) in zip(версии, версии.dropFirst()) {
            var нашлось = false
            let слева = Schema(versionedSchema: левая)
            for сущность in слева.entities.map(\.name)
            where поля(левая, сущность) != поля(правая, сущность) {
                нашлось = true
                break
            }
            #expect(нашлось, """
                версии \(левая.versionIdentifier) и \(правая.versionIdentifier)
                описывают одну и ту же форму. Так бывает ровно в одном
                случае: обе ссылаются на нынешние классы вместо снимка.
                """)
        }
    }

    /// То, ради чего заведена V4.
    @Test("V3 не знает про changedAt у собаки, а V4 знает")
    func changedAtПоявилсяВЧетвёртой() {
        #expect(!поля(TogoSchemaV3.self, "Dog").contains("changedAt"), """
            V3 — это сборка 141, она у четверых тестировщиков, и поля
            `changedAt` в ней не было. Если оно здесь появилось, значит
            снимок снова стал ссылкой на нынешние классы.
            """)
        #expect(поля(TogoSchemaV4.self, "Dog").contains("changedAt"))
    }

    /// Набор сущностей во всех версиях один: ни одна модель не заводилась
    /// и не удалялась, и `.lightweight` на это опирается.
    /// Набор сущностей **может расти, но не сокращаться**, и каждый
    /// прирост назван поимённо.
    ///
    /// **Прежняя редакция требовала «во всех версиях ровно шестнадцать»,
    /// и это было утверждение не об инварианте, а о текущем дне.**
    /// Оно держалось пять версий и сломалось на шестой, когда появился
    /// справочник клиник, — то есть сломалось на первой же законной
    /// правке, а не на дефекте.
    ///
    /// > **Сторож, требующий «столько же, сколько сейчас», краснеет
    /// > не на ошибке, а на росте.** Инвариант здесь другой: сущность,
    /// > однажды появившаяся, не исчезает — иначе у пришедшего
    /// > с прежней версии её записи стирать нечем, и миграция
    /// > `.lightweight` такого не выводит.
    ///
    /// Прирост по версиям перечислен числом, чтобы «появилась
    /// семнадцатая» нельзя было протащить молча.
    ///
    /// **Правка 08.10.2026, и это ПРОЯВКА, а не регрессия.** Перечень
    /// держал `[16, 16, 16, 16, 17]` и разницу `["Clinic"]`, то есть
    /// состояние того часа, когда медицинский слой был заведён файлами
    /// и ещё не зарегистрирован в схеме. Регистрация прошла в тот же
    /// день (`660a14f`): V5 знает 21 сущность, и прирост к V4 —
    /// пять штук, а не одна.
    ///
    /// ```
    /// было в перечне   16 16 16 16 17   разница ["Clinic"]
    /// в схеме          16 16 16 16 21   разница пять имён
    /// ```
    ///
    /// Красное у этого теста означало **не «схема сломалась»,
    /// а «перечень отстал»** — и отличить одно от другого по имени
    /// упавшего теста нельзя: имя шага говорит, ЧТО упало, причину
    /// говорит замер. Сам инвариант правкой не ослаблен: «росла,
    /// не сокращалась» проверяется как раньше, и шестая сущность
    /// по-прежнему не пройдёт молча.
    @Test("Набор сущностей растёт и не сокращается, прирост назван")
    func наборМоделейРастёт() {
        let наборы = TogoMigrationPlan.schemas.map { версия in
            Set(Schema(versionedSchema: версия).entities.map(\.name))
        }
        // Шестое число добавлено 26.10.2026 вместе с V6. Набор сущностей
        // она не меняет: надгробия — поля, а не модели, и именно
        // поэтому стадия V5 → V6 облегчённая. Равенство 21 = 21 здесь
        // не «ничего не проверили», а проверяемое утверждение: новая
        // сущность в этой стадии была бы дефектом.
        // Седьмое число добавлено 27.10.2026 вместе с V7. Как и V6,
        // она не меняет набор сущностей: `LogEvent.photo` — поле,
        // а не модель, и поэтому стадия V6 → V7 тоже облегчённая.
        // Восьмое число добавлено 28.10.2026 вместе с V8. Четыре новых
        // свойства (`DogDocument.occurredOn`, `.directionRaw`,
        // `.clinic` и обратная сторона `Clinic.documentsStorage`) —
        // ПОЛЯ, а не модели: справочник клиник завёлся ещё в V5,
        // и новая связь на него сущности не добавляет. Поэтому стадия
        // V7 → V8 тоже облегчённая.
        // Десятое число добавлено 29.10.2026 вместе с V10: одно поле
        // `Episode.dogID`, набор сущностей прежний.
        // Девятое число добавлено 29.10.2026 вместе с V9. Одно новое
        // свойство `Medication.startedAt` — поле, а не модель, набор
        // сущностей прежний, стадия V8 → V9 облегчённая. Версия
        // пришла из облачной сессии под номером 8, и номер пришлось
        // сменить: восьмой уже уехал людям в сборке 284.
        // Одиннадцатое число добавлено 05.11.2026 вместе с V11: два
        // ПОЛЯ разового исключения кормления у собаки, набор сущностей
        // прежний, стадия V10 → V11 облегчённая.
        let ожидаемо = [16, 16, 16, 16, 21, 21, 21, 21, 21, 21, 21]
        #expect(наборы.count == ожидаемо.count, """
            версий в плане \(наборы.count), а перечень приростов
            написан на \(ожидаемо.count). Добавил версию — назови
            её прирост здесь же, иначе следующая сущность пройдёт
            молча.
            """)

        for (i, набор) in наборы.enumerated() where i < ожидаемо.count {
            #expect(набор.count == ожидаемо[i],
                    "в версии №\(i + 1) сущностей \(набор.count), ожидалось \(ожидаемо[i])")
            if i > 0 {
                let ушедшие = наборы[i - 1].subtracting(набор).sorted()
                #expect(ушедшие.isEmpty, """
                    из версии №\(i + 1) исчезли сущности: \(ушедшие).
                    У пришедшего с прежней версии их записи стирать нечем,
                    и `.lightweight` такого перехода не выводит.
                    """)
            }
        }

        // Пятая версия добавила справочник клиник и четыре модели
        // медицинского слоя — ПОИМЁННО, потому что число 21 сошлось бы
        // и при перепутанной сущности. Ровно так и ловится «пять
        // появилось, одна из них не та».
        let приростV5: Set<String> = [
            "Clinic",        // шаг 0 медслоя: справочник
            "LabResult",     // анализ
            "VetVisit",      // визит
            "Diagnosis",     // диагноз
            "Prescription",  // назначение
        ]
        #expect(наборы[4].subtracting(наборы[3]) == приростV5, """
            V5 отличается от V4 не справочником клиник и четырьмя
            моделями медслоя, а \(наборы[4].subtracting(наборы[3]).sorted()).

            Если имя новое и законное — допиши его сюда И подними
            число в `ожидаемо`. Если имя ИСЧЕЗЛО из прироста, смотри
            проверку выше: у пришедшего с прежней версии его записи
            стирать нечем.
            """)

        // И шестая не завела ни одной сущности — поимённо, пустым
        // множеством. Утверждение «прирост пуст» сильнее, чем
        // совпадение чисел 21 и 21: число сошлось бы и при обмене
        // одной сущности на другую.
        #expect(наборы[5].subtracting(наборы[4]).isEmpty, """
            V6 завела сущность: \(наборы[5].subtracting(наборы[4]).sorted()).
            В этой стадии заводятся только надгробия — поля. Новая
            сущность здесь означает, что форму меняют под уже поднятым
            номером.
            """)

        // И у двух последних стадий — тем же способом, пустым
        // множеством. Проверять надо КАЖДУЮ пару, а не последнюю:
        // прежняя редакция спрашивала только про V6, и V7 с V8
        // прошли бы молча, хотя число 21 в `ожидаемо` сошлось бы
        // и при обмене одной сущности на другую.
        #expect(наборы[6].subtracting(наборы[5]).isEmpty, """
            V7 завела сущность: \(наборы[6].subtracting(наборы[5]).sorted()).
            В этой стадии заводится одно поле — `LogEvent.photo`.
            """)
        #expect(наборы[7].subtracting(наборы[6]).isEmpty, """
            V8 завела сущность: \(наборы[7].subtracting(наборы[6]).sorted()).
            В этой стадии заводятся четыре ПОЛЯ у документа и клиники.
            Справочник клиник существует с V5 — новая связь на него
            сущности не добавляет.
            """)
        #expect(наборы[8].subtracting(наборы[7]).isEmpty, """
            V9 завела сущность: \(наборы[8].subtracting(наборы[7]).sorted()).
            В этой стадии заводится одно поле — `Medication.startedAt`.
            """)
        #expect(наборы[9].subtracting(наборы[8]).isEmpty, """
            V10 завела сущность: \(наборы[9].subtracting(наборы[8]).sorted()).
            В этой стадии заводится одно поле — `Episode.dogID`.
            """)
        #expect(наборы[10].subtracting(наборы[9]).isEmpty, """
            V11 завела сущность: \(наборы[10].subtracting(наборы[9]).sorted()).
            В этой стадии заводятся два ПОЛЯ разового исключения
            кормления у собаки. Новая `@Model` здесь была бы новым типом
            записи CloudKit и новым зеркалом `CD_*` — а его заводит
            только живой Apple ID на телефоне, руками.
            """)
    }

    /// Снимок V4 описывает форму розданных сборок — числом, а не на слово.
    ///
    /// **Чем это оплачено и почему записано здесь.** V4 заморожена
    /// 05.10.2026, когда её уже несли шесть розданных сборок
    /// (191, 216, 248, 256, 258, 271 — все `IN_BETA_TESTING`), а в коде
    /// рядом стояла оговорка «V4 не уезжала никуда». Оговорка была верна
    /// в момент написания и устарела через одиннадцать часов.
    ///
    /// Снимок собран не перенабором, а из блока V3 плюс измеренная
    /// разница, и сверен с моделями на коммите сборки 271 — 16 классов
    /// и 213 хранимых свойств, счётом по разбору исходника из git
    /// (не по `Schema.properties`: там к ним добавляются связи).
    /// Этот тест держит ту сверку, чтобы в следующий раз её не пришлось
    /// делать заново: правка снимка V4 **задним числом** — это правка
    /// рассказа о том, что лежит у людей на телефонах.
    ///
    /// Проверяется за минуту снаружи: форма моделей на коммите, у которого
    /// `git rev-list --count` = 271, против этого снимка.
    @Test("Снимок V4 — это форма, розданная шестью сборками")
    func снимокЧетвёртойЗаморожен() {
        let v4 = Schema(versionedSchema: TogoSchemaV4.self)
        #expect(v4.entities.count == 16)

        // Пять полей, которыми V4 отличается от V3, — поимённо.
        // Число сошлось бы и при перепутанных местах.
        #expect(поля(TogoSchemaV4.self, "Dog").subtracting(поля(TogoSchemaV3.self, "Dog"))
                == ["changedAt"])
        #expect(поля(TogoSchemaV4.self, "CareTask").subtracting(поля(TogoSchemaV3.self, "CareTask"))
                == ["changedAt"])
        #expect(поля(TogoSchemaV4.self, "Medication").subtracting(поля(TogoSchemaV3.self, "Medication"))
                == ["changedAt"])
        #expect(поля(TogoSchemaV4.self, "DoseRecord").subtracting(поля(TogoSchemaV3.self, "DoseRecord"))
                == ["awaitedMedicationID", "awaitedMedicationName"])

        // И ни одного удаления: удаление поля `.lightweight` не выводит,
        // а хранилища шести розданных сборок открываются именно им.
        for сущность in v4.entities.map(\.name) {
            #expect(поля(TogoSchemaV3.self, сущность)
                        .subtracting(поля(TogoSchemaV4.self, сущность)).isEmpty,
                    "в `\(сущность)` V4 потеряла поле, которое было в V3")
        }

        // Снимок обязан быть снимком: ни один его класс не должен быть
        // классом приложения. Если `Dog` здесь — это живой `Dog`,
        // то следующая правка модели сменит форму 4.0.0 задним числом,
        // и шесть розданных сборок перестанут открываться молча.
        // **Проверка переписана 07.10.2026, и прежняя была неверна
        // по смыслу, а не устарела.** Стояло равенство
        // `живые == v4.entities`, и оно держалось ровно до первой
        // законной правки: появился справочник клиник, живых сущностей
        // стало семнадцать, и сторож покраснел на РОСТЕ, а не на снятой
        // заморозке.
        //
        // Инвариант здесь другой: снимок — ПОДМНОЖЕСТВО живого набора.
        // Сущность, однажды появившаяся, не исчезает (иначе миграция
        // `.lightweight` не выводится), а новые в старом снимке
        // появиться не могут по определению.
        let живые = Set(Persistence.schema.entities.map(\.name))
        let вСнимке = Set(v4.entities.map(\.name))
        #expect(вСнимке.subtracting(живые).isEmpty, """
            в снимке V4 есть сущности, которых нет в живой схеме:
            \(вСнимке.subtracting(живые).sorted()). Сущность не может
            исчезнуть: у пришедшего с V4 её записи стирать нечем.
            """)
        #expect(вСнимке.count == 16, "в снимке V4 сущностей \(вСнимке.count), а розданные сборки несут 16")

        // Снимок обязан быть снимком: ни один его класс не должен быть
        // классом приложения. Сравнение идёт с ЖИВОЙ схемой, а не
        // с V5 — V5 сама заморожена 07.10, и две замороженные версии
        // отличаются друг от друга всегда, то есть проверка на V5
        // проходила бы и при снятой заморозке V4.
        #expect(поля(TogoSchemaV4.self, "Medication") != живыеПоля("Medication"), """
            снимок V4 и ЖИВАЯ схема описывают одну форму `Medication`.
            Так бывает ровно в одном случае: V4 снова ссылается на живые
            классы — то есть заморозка снята, и дефект 23.09 вернулся.
            """)
    }

    /// Поля ЖИВОЙ схемы по имени сущности.
    ///
    /// Нужен затем, что сравнивать снимок с другим снимком бессмысленно:
    /// две замороженные версии отличаются всегда, и такая проверка
    /// прошла бы и при снятой заморозке. Сравнивать надо с тем, что
    /// в коде сейчас.
    private func живыеПоля(_ сущность: String) -> Set<String> {
        Set(Persistence.schema.entities
            .first { $0.name == сущность }?
            .properties.map(\.name) ?? [])
    }

    /// Стадий ровно на одну меньше, чем версий, и они идут подряд.
    /// Пропущенная стадия — это хранилище, которому некуда перейти.
    @Test("Стадии перехода покрывают все версии подряд")
    func стадииБезДыр() {
        #expect(TogoMigrationPlan.stages.count == TogoMigrationPlan.schemas.count - 1, """
            версий \(TogoMigrationPlan.schemas.count),
            стадий \(TogoMigrationPlan.stages.count).
            Версия, до которой нет стадии, не откроется ни у кого.
            """)
    }
