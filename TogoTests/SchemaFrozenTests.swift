import Testing
import Foundation
import SwiftData
@testable import Togo

/// Прежние версии схемы — снимки, а не ссылки на нынешние классы.
///
/// **Чем это оплачено.** До 23.09.2026 `TogoSchemaV3` перечисляла
/// настоящие классы приложения. Пока модель не менялась, всё работало
/// и выглядело экономно. Первая же правка — `Dog.changedAt` ради обмена
/// профилем — сломала не сборку, а **открытие хранилища**: форма классов
/// стала другой, версия осталась 3.0.0, и SwiftData ответила «Cannot use
/// staged migration with an unknown model version».
///
/// На телефоне это не падение. `Persistence.appContainer()` откатывается
/// iCloud → локально → в память: человек видит рабочий экран, отмечает
/// дозу, получает подтверждение — и запись не сохраняется никуда.
/// Тихая потеря дневника с лечением, и ровно ради этого случая план
/// миграции вообще появился 21.09.
///
/// Сторож ловит **возврат к ссылкам**, а не форму отдельного поля:
/// сломалось именно это, и повторить легко — следующая правка модели
/// обязана заморозить V4 и завести V5.
@Suite("Прежние версии схемы заморожены")
struct SchemaFrozenTests {

    private func поля(_ версия: any VersionedSchema.Type, _ сущность: String) -> Set<String> {
        let schema = Schema(versionedSchema: версия)
        guard let entity = schema.entities.first(where: { $0.name == сущность })
        else { return [] }
        return Set(entity.properties.map(\.name))
    }

    /// Нынешняя версия — последняя в плане, и она же у хранилища.
    /// Расхождение здесь значит, что схему подняли, а открывают старой.
    @Test("Хранилище открывается последней версией плана")
    func хранилищеНаПоследней() throws {
        let последняя = try #require(TogoMigrationPlan.schemas.last)
        #expect(Persistence.schema.version == последняя.versionIdentifier, """
            хранилище открывается версией \(Persistence.schema.version),
            а последняя в плане — \(последняя.versionIdentifier).
            Форма поменялась под неизменной версией: у тех, у кого стоит
            прежняя сборка, дневник молча не откроется.
            """)
    }

    /// Каждая пара соседних версий обязана чем-то отличаться. Две
    /// одинаковые версии — это план, который выглядит планом и ничего
    /// не переводит.
    @Test("Соседние версии схемы отличаются хотя бы одним полем")
    func соседиОтличаются() {
        let версии = TogoMigrationPlan.schemas
        #expect(версии.count >= 4, "версий в плане \(версии.count) — плана нет")

        for (левая, правая) in zip(версии, версии.dropFirst()) {
            var нашлось = false
            let слева = Schema(versionedSchema: левая)
            for сущность in слева.entities.map(\.name)
            where поля(левая, сущность) != поля(правая, сущность) {
                нашлось = true
                break
            }
            #expect(нашлось, """
                версии \(левая.versionIdentifier) и \(правая.versionIdentifier)
                описывают одну и ту же форму. Так бывает ровно в одном
                случае: обе ссылаются на нынешние классы вместо снимка.
                """)
        }
    }

    /// То, ради чего заведена V4.
    @Test("V3 не знает про changedAt у собаки, а V4 знает")
    func changedAtПоявилсяВЧетвёртой() {
        #expect(!поля(TogoSchemaV3.self, "Dog").contains("changedAt"), """
            V3 — это сборка 141, она у четверых тестировщиков, и поля
            `changedAt` в ней не было. Если оно здесь появилось, значит
            снимок снова стал ссылкой на нынешние классы.
            """)
        #expect(поля(TogoSchemaV4.self, "Dog").contains("changedAt"))
    }

    /// Набор сущностей во всех версиях один: ни одна модель не заводилась
    /// и не удалялась, и `.lightweight` на это опирается.
    @Test("Все версии описывают те же шестнадцать моделей")
    func наборМоделейОдин() {
        let имена = TogoMigrationPlan.schemas.map { версия in
            Set(Schema(versionedSchema: версия).entities.map(\.name))
        }
        for (i, набор) in имена.enumerated() {
            #expect(набор.count == 16,
                    "в версии №\(i + 1) моделей \(набор.count), а не 16")
            #expect(набор == имена[0],
                    "набор сущностей разошёлся в версии №\(i + 1)")
        }
    }

    /// Стадий ровно на одну меньше, чем версий, и они идут подряд.
    /// Пропущенная стадия — это хранилище, которому некуда перейти.
    @Test("Стадии перехода покрывают все версии подряд")
    func стадииБезДыр() {
        #expect(TogoMigrationPlan.stages.count == TogoMigrationPlan.schemas.count - 1, """
            версий \(TogoMigrationPlan.schemas.count),
            стадий \(TogoMigrationPlan.stages.count).
            Версия, до которой нет стадии, не откроется ни у кого.
            """)
    }
}
