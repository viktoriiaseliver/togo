import Testing
import Foundation
@testable import Togo

/// Разбор дозаписи по языкам — и апостроф, который тестом из исходника
/// не ловится.
@Suite("Словарь разбора")
struct RecallDictionaryTests {

    // MARK: Апостроф

    /// Главная ловушка, и она единственная, которую нельзя поймать
    /// строкой из исходника: в коде апостроф U+0027, клавиатура iOS
    /// печатает U+2019, `contains` их равными не считает. Тест прошёл бы,
    /// человек не попал бы никогда.
    @Test("Апостроф с клавиатуры равен апострофу из кода")
    func апострофНормализуется() {
        let изКода = RecallDictionary.нормализовать("м'як")
        let сКлавиатуры = RecallDictionary.нормализовать("м\u{2019}як")
        let модификатор = RecallDictionary.нормализовать("м\u{02BC}як")
        #expect(изКода == сКлавиатуры)
        #expect(изКода == модификатор)
    }

    /// То же, но через сам разбор: основа записана в коде одним
    /// апострофом, человек напечатал другим — вид записи обязан найтись.
    @Test("Основа с апострофом находится во фразе с клавиатурным апострофом")
    func основаНаходитсяЧерезАпостроф() {
        let словарь = RecallDictionary(
            основы: [(.stool, ["м'як"])],
            сегодня: [], вчера: [], позавчера: [],
            началоПериода: [], конецПериода: []
        )
        #expect(RecallParser.kind(in: "вчора був м\u{2019}який стілець", словарь: словарь) == .stool,
                "апостроф с клавиатуры не совпал с апострофом из кода")
    }

    // MARK: Язык

    @Test("Неизвестный язык разбирается по-русски, а не молчит")
    func запасныйЯзыкРусский() {
        #expect(!RecallDictionary.дляЯзыка("de").пустой)
        #expect(RecallDictionary.дляЯзыка("de").основы.count
                == RecallDictionary.русский.основы.count)
    }

    @Test("Французский заведён, но слов пока нет")
    func французскийЖдётСлов() {
        #expect(RecallDictionary.дляЯзыка("fr").пустой,
                "появились французские основы — убери это ожидание и добавь разбор в тесты")
    }

    /// Украинский заполнен 23.09; прежнее ожидание «пустой» снято по его же
    /// указанию — «убери это ожидание и добавь разбор в тесты».
    ///
    /// Фразы взяты не из интерфейса, а из того, как пишут в переписке:
    /// разбор для того и заведён. «Годували», а не «годував» — первая
    /// редакция словаря писала форму вместо основы и это предложение
    /// не разбирала.
    @Test("Украинская фраза разбирается")
    func украинскийРазбор() {
        let сегодня = Date()
        #expect(!RecallDictionary.дляЯзыка("uk").пустой)
        #expect(RecallParser.kind(in: "13.09 був пронос", словарь: .украинский) == .stool)
        #expect(RecallParser.kind(in: "вчора годували двічі", словарь: .украинский) == .meal)
        #expect(RecallParser.kind(in: "собаку вирвало", словарь: .украинский) == .incident)
        #expect(RecallParser.day(in: "вчора гуляли", today: сегодня,
                                 словарь: .украинский) != nil)
        #expect(RecallParser.range(in: "годували з 04.09 по 20.09",
                                   today: сегодня, словарь: .украинский) != nil)
    }

    /// Девятнадцать фраз так, как их пишут, а не как названы в интерфейсе.
    ///
    /// Этот набор нашёл в словаре четыре дефекта, которых чтение списка
    /// не находило: «вийшли» мимо форм «вийшо»/«вийшла», отсутствие слова
    /// про консистенцию, отсутствие настоящего времени «їсть» — и, важнее
    /// всего, основу «рідк», которая ловила НАРЕЧИЕ «рідко» и делала
    /// «гуляли рідко» стулом.
    ///
    /// Поэтому набор и записан: следующая правка списка проверяется
    /// предложениями, а не взглядом.
    @Test("Украинские фразы разбираются так, как их пишут")
    func украинскиеФразы() {
        let ожидаем: [(String, LogKind?)] = [
            ("собаку вирвало вночі", .incident),
            ("вранці був пронос", .stool),
            ("погодувала о 7", .meal),
            ("дала таблетку", .dose),
            ("гуляли годину", .walk),
            ("вийшли на 10 хвилин", .outing),
            ("зважилися 12 кг", .weight),
            ("сьогодні не їв", .meal),
            ("учора рідкий стілець", .stool),
            ("нудило після їжі", .incident),
            ("випорожнення нормальне", .stool),
            ("дав ліки о 8", .dose),
            ("вигуляла перед сном", .walk),
            ("покакав двічі", .stool),
            ("важить 12", .weight),
            ("попісяв на балконі", .outing),
            ("не їсть другий день", .meal),
            // «рідко» — это «нечасто», а не консистенция. Ловушка глоссария
            // с другой стороны: не в переводе, а в разборе.
            ("рідко буває", nil),
            ("гуляли рідко", .walk),
            // Столкновения основ с чужими словами. Проверяются НАСТОЯЩИМ
            // парсером: предварительный прогон своей моделью пропустил
            // «сьогодні не їв», потому что не знал про пробел в основе.
            ("поїхали в Київ", nil),        // «Київ» содержит «їв»
            ("давно не гуляли", .walk),     // «давно» не должно стать дозой
            ("важко дихає", nil),           // «важко» не «важить»
            ("їжа закінчилася", .meal),     // а вот это как раз еда
        ]
        for (фраза, ждём) in ожидаем {
            #expect(RecallParser.kind(in: фраза, словарь: .украинский) == ждём,
                    "«\(фраза)» разобралась не так")
        }
    }

    @Test("Позавчора не путается с вчора")
    func позавчораРаньше() {
        let сегодня = Calendar.current.startOfDay(for: Date())
        let позавчора = RecallParser.day(in: "позавчора був пронос",
                                         today: сегодня, словарь: .украинский)
        #expect(позавчора == Calendar.current.date(byAdding: .day, value: -2, to: сегодня))
    }

    // MARK: Русский разбор не сломался

    @Test("Русская фраза разбирается как раньше")
    func русскийРазбор() {
        let сегодня = Date()
        #expect(RecallParser.kind(in: "13.09 был понос", словарь: .русский) == .stool)
        #expect(RecallParser.kind(in: "вчера кормил два раза", словарь: .русский) == .meal)
        #expect(RecallParser.day(in: "вчера гуляли", today: сегодня, словарь: .русский) != nil)
        #expect(RecallParser.range(in: "кормили с 04.09 по 20.09",
                                   today: сегодня, словарь: .русский) != nil)
    }

    @Test("Позавчера не путается со вчера")
    func позавчераРаньше() {
        let сегодня = Calendar.current.startOfDay(for: Date())
        let позавчера = RecallParser.day(in: "позавчера был понос",
                                         today: сегодня, словарь: .русский)
        #expect(позавчера == Calendar.current.date(byAdding: .day, value: -2, to: сегодня))
    }

    @Test("Пустой словарь не разбирает чужой язык по-русски")
    func пустойНеПритворяется() {
        #expect(RecallParser.kind(in: "il a vomi hier", словарь: .французский) == nil)
    }
}
