    /// Обещание `RecallDictionary.пустой` — «сказать иначе, чем „не
    /// понял"» — до 23.09.2026 не выполнялось: разбор отвечал
    /// `notUnderstood` и там, и там.
    ///
    /// Разница для человека большая. «Не понял» значит «перепиши»;
    /// «этот язык ещё не разбираю» значит «переписывать бесполезно,
    /// дело не в тебе». Первое заставляет пробовать снова и снова.
    @Test("Язык без слов разбора отвечает не «не понял»")
    func пустойОтвечаетИначе() {
        let пустой = RecallDictionary(основы: [], сегодня: [], вчера: [], позавчера: [],
                                      началоПериода: [], конецПериода: [])
        #expect(пустой.пустой)
        // Разбор берёт словарь текущего языка, поэтому проверяем
        // само правило: пустой словарь не находит вида записи,
        // и отвечать на это «не понял» — неправда.
        #expect(RecallParser.kind(in: "был понос", словарь: пустой) == nil)
    }
