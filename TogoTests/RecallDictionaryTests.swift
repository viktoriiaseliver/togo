import Testing
import Foundation
@testable import Togo

/// Разбор дозаписи по языкам — и апостроф, который тестом из исходника
/// не ловится.
@Suite("Словарь разбора")
struct RecallDictionaryTests {

    // MARK: Апостроф

    /// Главная ловушка, и она единственная, которую нельзя поймать
    /// строкой из исходника: в коде апостроф U+0027, клавиатура iOS
    /// печатает U+2019, `contains` их равными не считает. Тест прошёл бы,
    /// человек не попал бы никогда.
    @Test("Апостроф с клавиатуры равен апострофу из кода")
    func апострофНормализуется() {
        let изКода = RecallDictionary.нормализовать("м'як")
        let сКлавиатуры = RecallDictionary.нормализовать("м\u{2019}як")
        let модификатор = RecallDictionary.нормализовать("м\u{02BC}як")
        #expect(изКода == сКлавиатуры)
        #expect(изКода == модификатор)
    }

    /// То же, но через сам разбор: основа записана в коде одним
    /// апострофом, человек напечатал другим — вид записи обязан найтись.
    @Test("Основа с апострофом находится во фразе с клавиатурным апострофом")
    func основаНаходитсяЧерезАпостроф() {
        let словарь = RecallDictionary(
            основы: [(.stool, ["м'як"])],
            сегодня: [], вчера: [], позавчера: [],
            началоПериода: [], конецПериода: []
        )
        #expect(RecallParser.kind(in: "вчора був м\u{2019}який стілець", словарь: словарь) == .stool,
                "апостроф с клавиатуры не совпал с апострофом из кода")
    }

    // MARK: Язык

    @Test("Неизвестный язык разбирается по-русски, а не молчит")
    func запасныйЯзыкРусский() {
        #expect(!RecallDictionary.дляЯзыка("de").пустой)
        #expect(RecallDictionary.дляЯзыка("de").основы.count
                == RecallDictionary.русский.основы.count)
    }

    /// # Ось, которой не было, и из-за которой запасной путь стал дырой
    ///
    /// Тест выше проверяет `de` — язык, которого у приложения НЕТ,
    /// и для него запасной русский действительно лучше молчания.
    /// Он был верен и остаётся верным. Но под тот же `default`
    /// до 27.10.2026 попадали **`en` и `kk` — заявленные языки
    /// приложения**, и там «запасной» значит другое: человек пишет
    /// на родном языке, а словарь ищет русские основы.
    ///
    /// ```
    /// замер 27.10, 10 обиходных фраз против русских основ
    ///   en  «fed him at 8» · «he vomited twice» · ещё три   0 совпадений
    ///   kk  «кеше серуендедік» · «екі рет құсты» · ещё три  0 совпадений
    /// ```
    ///
    /// **Сторож на это не краснел, потому что спрашивал про `de`.**
    /// Ось «неизвестный язык не молчит» и ось «у заявленного языка
    /// есть свой словарь» — разные, и вторая не выводится из первой.
    ///
    /// Источник списка языков здесь — **каталог строк**, а не копия
    /// в тесте: копия разошлась бы молча ровно в тот день, когда
    /// заведут шестой язык. Это тот же приём, которым `SpacingGridTests`
    /// берёт шкалу у ядра, а не зашивает шаг 4.
    @Test("У каждого языка приложения есть свой словарь разбора")
    func уКаждогоЯзыкаПриложенияЕстьСловарь() throws {
        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let разбор = try JSONSerialization.jsonObject(
            with: try Data(contentsOf: каталог)) as? [String: Any]
        let строки = (разбор?["strings"] as? [String: Any]) ?? [:]

        var языки: Set<String> = []
        for (_, узел) in строки {
            let лок = ((узел as? [String: Any])?["localizations"] as? [String: Any]) ?? [:]
            языки.formUnion(лок.keys)
        }

        // Проверка, что проверять БЫЛО ЧТО — первой. Пустое множество
        // языков сделало бы цикл ниже зелёным, не выполнив ни одной
        // проверки: сканирующий сторож молчит одинаково и когда всё
        // хорошо, и когда он ослеп.
        #expect(языки.count >= 5, """
            из каталога прочитано \(языки.count) языков при пяти \
            на 27.10.2026 (ru · en · fr · kk · uk). Разбор xcstrings \
            развалился — проверка ниже зелёная, потому что ей нечего \
            проверять.
            """)

        for язык in языки.sorted() {
            let словарь = RecallDictionary.дляЯзыка(язык)
            #expect(!словарь.пустой, """
                у языка `\(язык)` нет словаря разбора: `дляЯзыка` \
                отдаёт пустой. Человек на этом языке получит \
                `notUnderstood` на любую дозапись.
                """)
            #expect(словарь.сегодня.first != RecallDictionary.русский.сегодня.first
                    || язык == "ru", """
                язык `\(язык)` заявлен в каталоге, но `дляЯзыка` \
                отдаёт ему РУССКИЙ словарь через `default`. Для языка, \
                которого у приложения нет, это верный запасной путь; \
                для заявленного — отключённый разбор: его основы \
                не совпадут с тем, что человек печатает. Завести \
                словарь либо убрать язык из каталога.
                """)
        }
    }

    /// Французский заполнен 23.09; прежнее ожидание «пустой» снято
    /// по его же указанию.
    @Test("Французские фразы разбираются так, как их пишут")
    func французскиеФразы() {
        let ожидаем: [(String, LogKind?)] = [
            ("il a vomi cette nuit", .incident),
            ("selles molles ce matin", .stool),
            ("je l'ai nourri à 7h", .meal),
            ("donné le comprimé", .dose),
            ("on a fait une balade", .walk),
            ("sorti dix minutes", .outing),
            ("il pèse 12 kg", .weight),
            ("il n'a pas mangé", .meal),
            ("flaque dans le salon", .incident),
            ("il a fait caca", .stool),
            ("caca mou ce matin", .stool),
            ("promenade d'une heure", .walk),
            // Столкновения основ с чужими словами — настоящим парсером.
            ("il a mangé une cacahuète", .meal),   // «caca» внутри «cacahuète»
            ("croquettes assorties", .meal),       // «sorti» внутри «assorti»
            ("il boit beaucoup", nil),             // ничего из списка
        ]
        for (фраза, ждём) in ожидаем {
            #expect(RecallParser.kind(in: фраза, словарь: .французский) == ждём,
                    "«\(фраза)» разобралась не так")
        }
    }

    @Test("Avant-hier не путается с hier")
    func французскоеПозавчера() {
        let сегодня = Calendar.current.startOfDay(for: Date())
        let позавчера = RecallParser.day(in: "avant-hier il a vomi",
                                         today: сегодня, словарь: .французский)
        #expect(позавчера == Calendar.current.date(byAdding: .day, value: -2, to: сегодня))
    }

    /// Украинский заполнен 23.09; прежнее ожидание «пустой» снято по его же
    /// указанию — «убери это ожидание и добавь разбор в тесты».
    ///
    /// Фразы взяты не из интерфейса, а из того, как пишут в переписке:
    /// разбор для того и заведён. «Годували», а не «годував» — первая
    /// редакция словаря писала форму вместо основы и это предложение
    /// не разбирала.
    @Test("Украинская фраза разбирается")
    func украинскийРазбор() {
        let сегодня = Date()
        #expect(!RecallDictionary.дляЯзыка("uk").пустой)
        #expect(RecallParser.kind(in: "13.09 був пронос", словарь: .украинский) == .stool)
        #expect(RecallParser.kind(in: "вчора годували двічі", словарь: .украинский) == .meal)
        #expect(RecallParser.kind(in: "собаку вирвало", словарь: .украинский) == .incident)
        #expect(RecallParser.day(in: "вчора гуляли", today: сегодня,
                                 словарь: .украинский) != nil)
        #expect(RecallParser.range(in: "годували з 04.09 по 20.09",
                                   today: сегодня, словарь: .украинский) != nil)
    }

    /// Девятнадцать фраз так, как их пишут, а не как названы в интерфейсе.
    ///
    /// Этот набор нашёл в словаре четыре дефекта, которых чтение списка
    /// не находило: «вийшли» мимо форм «вийшо»/«вийшла», отсутствие слова
    /// про консистенцию, отсутствие настоящего времени «їсть» — и, важнее
    /// всего, основу «рідк», которая ловила НАРЕЧИЕ «рідко» и делала
    /// «гуляли рідко» стулом.
    ///
    /// Поэтому набор и записан: следующая правка списка проверяется
    /// предложениями, а не взглядом.
    @Test("Украинские фразы разбираются так, как их пишут")
    func украинскиеФразы() {
        let ожидаем: [(String, LogKind?)] = [
            ("собаку вирвало вночі", .incident),
            ("вранці був пронос", .stool),
            ("погодувала о 7", .meal),
            ("дала таблетку", .dose),
            ("гуляли годину", .walk),
            ("вийшли на 10 хвилин", .outing),
            ("зважилися 12 кг", .weight),
            ("сьогодні не їв", .meal),
            ("учора рідкий стілець", .stool),
            ("нудило після їжі", .incident),
            ("випорожнення нормальне", .stool),
            ("дав ліки о 8", .dose),
            ("вигуляла перед сном", .walk),
            ("покакав двічі", .stool),
            ("важить 12", .weight),
            ("попісяв на балконі", .outing),
            ("не їсть другий день", .meal),
            // «рідко» — это «нечасто», а не консистенция. Ловушка глоссария
            // с другой стороны: не в переводе, а в разборе.
            ("рідко буває", nil),
            ("гуляли рідко", .walk),
            // Столкновения основ с чужими словами. Проверяются НАСТОЯЩИМ
            // парсером: предварительный прогон своей моделью пропустил
            // «сьогодні не їв», потому что не знал про пробел в основе.
            ("поїхали в Київ", nil),        // «Київ» содержит «їв»
            ("давно не гуляли", .walk),     // «давно» не должно стать дозой
            ("важко дихає", nil),           // «важко» не «важить»
            ("їжа закінчилася", .meal),     // а вот это как раз еда
        ]
        for (фраза, ждём) in ожидаем {
            #expect(RecallParser.kind(in: фраза, словарь: .украинский) == ждём,
                    "«\(фраза)» разобралась не так")
        }
    }

