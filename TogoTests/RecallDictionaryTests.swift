    // MARK: Основы не уезжают в каталог

    /// Основа разбора в каталоге — это перевод, которого никто
    /// не спрашивал.
    ///
    /// Замер 23.09.2026: в каталоге лежали пять основ, и все были
    /// переведены. `г\\b` стал по-французски `g\\b` — верно,
    /// но **верно случайно**: переводчик видел в выгрузке кусок
    /// регулярного выражения без всякого контекста. «час» стал
    /// по-украински «година» — слово верное, а разбор оно ломает,
    /// ровно как записано в своде про «час» и «години».
    ///
    /// И главное: разбор брал **зашитые литералы**, а не переводы.
    /// Перевод существовал, выглядел работающим и не значил ничего —
    /// та же форма, что у `Text(строка)` и `Fmt.plural`.
    @Test("Основ разбора в каталоге не осталось")
    func основыНеВКаталоге() throws {
        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: каталог))
            as? [String: Any]
        let ключи = Set((корень?["strings"] as? [String: Any] ?? [:]).keys)

        #expect(ключи.count > 500, "каталог прочитан не весь (\(ключи.count))")

        // Куски шаблона узнаются по обратному слешу: подписи его
        // не содержат, а `\\b` — граница слова.
        let шаблоны = ключи.filter { $0.contains("\\") }.sorted()
        #expect(шаблоны.isEmpty, """
            в каталоге лежит кусок регулярного выражения: \(шаблоны).
            Его переведут — и это будет выглядеть как перевод.
            Место основ разбора — `RecallDictionary`.
            """)

        // Сами единицы: если они снова окажутся переводимыми ключами,
        // разбор всё равно возьмёт словарь, но перевод будет врать.
        //
        // **Кроме одного случая, и он выяснен замером 07.10.2026.**
        // Проверка ловила «мин» — и была неправа: у плаката
        // `единица("мин")` это ПОКАЗ, `LocalizedStringKey`, а не разбор.
        // Слово одно, назначения два.
        //
        //     разбор    RecallDictionary.русский.минуты = ["мин"]
        //               подстрока, ловит «мин», «минут», «минуты»
        //     показ     TGPoster.swift  «2 ч 15 мин» крупно на плакате
        //
        // Предложенные развилки обе ведут в дефект. Удалить ключ —
        // француз увидит на плакате «мин» (и видит прямо сейчас:
        // у «ч» и «мин» нет ни fr, ни uk). Научить разбор брать
        // единицы из каталога — ещё хуже: русский ввод обязан
        // разбираться по-русски и тогда, когда интерфейс французский.
        // Словарь ключуется ЯЗЫКОМ ВВОДА, а не языком интерфейса.
        //
        // > **Проверка сравнивала написание и выдавала это за назначение.**
        // > Тот же класс, что `hasPrefix("struct Swatch")`, находивший
        // > `SwatchRow`: совпадение строки не значит совпадения смысла.
        //
        // Настоящий инвариант — «разбор не зависит от каталога» —
        // держится не этой строкой, а устройством: `RecallParser`
        // принимает словарь параметром и до каталога не дотягивается
        // вовсе. Сторож этого — `пустойНеРазбираетЕдиницы` ниже.
        // Здесь остаётся проверка слабее, и она честно слабее.
        let показ: Set<String> = ["мин"]
        let единицы = Set(RecallDictionary.русский.граммы
            + RecallDictionary.русский.разы
            + RecallDictionary.русский.часы
            + RecallDictionary.русский.минуты)
        let вернулись = единицы.subtracting(показ).intersection(ключи).sorted()
        #expect(вернулись.isEmpty, """
            единицы разбора снова в каталоге: \(вернулись).
            Разбор их оттуда не берёт — значит перевод существует
            и не значит ничего.
            """)
    }

    /// Исключение «мин» опирается на факт, а не на мнение.
    ///
    /// **Исключение без сторожа — дыра ровно своего размера.** У Togo
    /// это уже оплачено дважды: весь список файловых исключений одного
    /// сторожа молча не работал из-за симлинка, а проверка «исключения
    /// существуют» была зелёной — файлы-то на месте.
    ///
    /// Поэтому здесь проверяется не существование исключения, а обе
    /// причины, по которым оно заведено. Отпадёт любая — тест краснеет,
    /// и исключение надо снимать, а не подпирать.
    @Test("Исключение «мин» держится показом на плакате, а не словом в тесте")
    func исключениеМинОпираетсяНаПоказ() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()

        // Причина первая: «мин» ПОКАЗЫВАЕТСЯ плакатом как
        // `LocalizedStringKey`. Уйдёт показ — исключение станет
        // прикрытием для настоящей единицы разбора.
        let плакат = try String(contentsOf: корень
            .appendingPathComponent("Togo/DesignSystem/Components/TGPoster.swift"),
            encoding: .utf8)
        #expect(плакат.contains("единица(\"мин\")"), """
            на плакате больше нет `единица("мин")` — значит «мин»
            перестало быть показом, и исключение в `основыНеВКаталоге`
            прикрывает единицу разбора. Снять исключение, а не этот тест.
            """)
        #expect(плакат.contains("private func единица(_ слово: LocalizedStringKey)"), """
            `единица` больше не принимает `LocalizedStringKey` — значит
            показ перестал переводиться вовсе, и спор про каталог
            закрылся с другой стороны. Перечитать исключение целиком.
            """)

        // Причина вторая: ключ в каталоге действительно есть. Нет его —
        // исключение не покрывает ничего, то есть это лишняя дыра,
        // про которую никто не помнит.
        let каталог = try JSONSerialization.jsonObject(with: Data(contentsOf: корень
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")))
            as? [String: Any]
        let ключи = Set((каталог?["strings"] as? [String: Any] ?? [:]).keys)
        #expect(ключи.contains("мин"), """
            ключа «мин» в каталоге нет — исключение не покрывает ничего.
            Убрать его: исключение, закрывающее то, чего нет, — лишняя
            дыра, про которую никто не помнит.
            """)
    }

