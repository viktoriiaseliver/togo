import Testing
import Foundation
@testable import Togo

/// Отказ системы при постановке напоминания обязан куда-то доходить.
///
/// # Что было до 29.10.2026
///
/// ```
/// Notifications.swift:85    try? await center.add(request)    утренняя сводка
/// то же файл :101           try? await …add(…)                доза, .timeSensitive
/// то же файл :152           try? await …add(…)                окно натощак
/// числа 64 в файле          НЕТ                               потолок не считал никто
/// ```
///
/// Три формы `try?` — не сокращение, а **молчаливый путь**: функция
/// возвращала `Void`, отказ системы растворялся в месте вызова,
/// и узнать о нём было нечем ни человеку, ни разработчику. У сводки
/// цена этого — пропущенный груминг. У дозы — пропущенное лекарство,
/// и **человек не узнаёт об этом ничем**: уведомления, которого
/// не будет, не видно ни на одном экране.
///
/// И вторая половина, которую `try?` не закрывал бы и будучи `do/catch`:
/// **у переполнения очереди отказа нет вовсе.** iOS держит
/// `потолокОжидающих` ожидающих запросов на приложение; шестьдесят
/// пятый `add` принимает успехом, а система оставляет ближайшие
/// по времени и остальные выбрасывает молча. Ни исключения, ни кода
/// возврата. Поймать это может только счёт ожидающих, снятый **прежде**
/// постановки партии, — и он, а не `catch`, стережёт дозу.
///
/// # Почему осей две, и почему одной мало
///
/// ```
/// (а) значение   планПартии(ожидают:ставим:)  арифметика потолка,
///                                             чистая функция
/// (б) исходник   запрет `try?` и запрет
///                @discardableResult            форма, которой
///                                              дефект возвращается
/// ```
///
/// Ось (а) не краснеет от возврата `try?`: арифметика потолка про него
/// ничего не знает. Ось (б) не краснеет от ошибки в арифметике. Это
/// разные предметы, и покрывать их одним тестом значило бы покрыть
/// ни одного.
///
/// # Приёмка подделкой
///
/// Сторож, не краснеющий на подделке, не доказывает ничего.
/// Подделка возвращает ровно ту форму, ради которой набор заведён:
///
/// ```
/// ФАЙЛ=Togo/Store/Notifications.swift
/// БЫЛО='            try await UNUserNotificationCenter.current().add(запрос)'
/// СТАЛО='            try? await UNUserNotificationCenter.current().add(запрос)'
/// НАБОР=TogoTests/ОтказУведомленийДоходитTests
/// ```
///
/// Подделка **компилируется** — в этом и беда исходного дефекта:
/// ни компилятор, ни соседние наборы её не видят. Краснеет только
/// `нетНиОдногоТихогоTry`.
@Suite("Отказ уведомлений доходит до человека")
struct ОтказУведомленийДоходитTests {

    private static let служба = "Togo/Store/Notifications.swift"
    private static let планировщик = "Togo/Store/ReminderScheduler.swift"

    // MARK: - (а) Арифметика потолка

    /// **Стоит первым: все запреты ниже выполняются и у функции,
    /// которая всегда отвечает нулём.** «Лишних ноль» — ожидаемый
    /// ответ, а обрадовавший ноль не перепроверяет никто.
    @Test("Было что проверять: план отвечает про очередь, а не нулём на всё")
    func былоЧтоПроверять() {
        let план = NotificationCenterService.планПартии(
            ожидают: Set(["а", "б", "в"]),
            ставим: ["г", "д"]
        )
        #expect(план.ожидает == 3, """
            план не видит очереди: ожидает \(план.ожидает) при трёх \
            стоящих запросах. Тогда «лишних ноль» ниже верно по причине, \
            к потолку отношения не имеющей.
            """)
        #expect(план.лишних == 0, """
            пять запросов объявлены переполнением при потолке \
            \(NotificationCenterService.потолокОжидающих).
            """)
    }

    @Test("Потолок назван числом и это число iOS, а не наше удобство")
    func потолокЭтоЧислоСистемы() {
        #expect(NotificationCenterService.потолокОжидающих == 64, """
            потолок ожидающих уведомлений стал \
            \(NotificationCenterService.потолокОжидающих). Это величина \
            системы, а не наша настройка: iOS держит 64 ожидающих запроса \
            на приложение и лишние выбрасывает, ничего не сказав. \
            Менять её можно только вслед за Apple и с замером рядом.
            """)
    }

    @Test("Переполнение считается от потолка, а не от размера партии")
    func переполнениеСчитаетсяОтПотолка() {
        let очередь = Set((1...60).map { "уже-\($0)" })
        let партия = (1...10).map { "новый-\($0)" }

        let план = NotificationCenterService.планПартии(ожидают: очередь, ставим: партия)
        #expect(план.лишних == 6, """
            60 стоящих плюс 10 новых при потолке 64 — это 6 лишних, \
            а план насчитал \(план.лишних). Столько напоминаний система \
            выбросит молча, и ровно о них нужно сказать человеку.
            """)

        // Контроль ТЕМ ЖЕ замером и в другую сторону: подними потолок —
        // лишних не станет. Без него «6» могло бы быть чем угодно,
        // что совпало с шестёркой.
        let сЗапасом = NotificationCenterService.планПартии(
            ожидают: очередь, ставим: партия, потолок: 70)
        #expect(сЗапасом.лишних == 0, """
            при потолке 70 те же 70 запросов объявлены переполнением \
            (\(сЗапасом.лишних) лишних) — значит план считает не от потолка.
            """)
    }

    /// **Причина, по которой наивный счёт врал бы каждую пересборку.**
    ///
    /// У доз идентификаторы стабильные (`dose-<uuid>-t+30`), и partition
    /// почти целиком состоит из замен: `add` с тем же `id` заменяет
    /// стоящий запрос, а не прибавляет второй. Счёт
    /// «ожидает + размер партии» объявлял бы переполнение при каждом
    /// открытии главного экрана — и через неделю строку про полную
    /// очередь перестали бы читать.
    @Test("Замена стоящего запроса слота не занимает")
    func заменаСлотНеЗанимает() {
        let очередь = Set((1...64).map { "dose-\($0)-t+30" })
        let тоЖеСамое = (1...64).map { "dose-\($0)-t+30" }

        let план = NotificationCenterService.планПартии(ожидают: очередь, ставим: тоЖеСамое)
        #expect(план.лишних == 0, """
            повторная постановка тех же 64 запросов объявлена \
            переполнением на \(план.лишних). Это ложная тревога на каждой \
            пересборке напоминаний, то есть на каждом открытии экрана.
            """)

        // Один НОВЫЙ поверх полной очереди — уже переполнение.
        // Контроль к строке выше: ноль там не от того, что функция
        // всегда отвечает нулём.
        let сНовым = NotificationCenterService.планПартии(
            ожидают: очередь, ставим: тоЖеСамое + ["dose-65-t+30"])
        #expect(сНовым.лишних == 1, """
            шестьдесят пятый запрос поверх полной очереди не признан \
            лишним (\(сНовым.лишних)). Именно он теряется молча.
            """)
    }

    @Test("Граница проходит ровно по потолку, а не рядом с ним")
    func границаРовноНаПотолке() {
        let почтиПолная = Set((1...63).map { "уже-\($0)" })
        #expect(NotificationCenterService.планПартии(
            ожидают: почтиПолная, ставим: ["новый"]).лишних == 0,
            "шестьдесят четвёртый запрос обязан помещаться")

        let полная = Set((1...64).map { "уже-\($0)" })
        #expect(NotificationCenterService.планПартии(
            ожидают: полная, ставим: ["новый"]).лишних == 1,
            "шестьдесят пятый запрос обязан считаться лишним")
    }

    /// Партия приходит списком, а не множеством, и один и тот же
    /// идентификатор в ней встретиться может: ступени `t-10`, `t+30`
    /// и `t+60` собираются в цикле, и ошибка в `doseID` склеила бы их.
    /// Считать такое за три слота значило бы объявлять переполнение
    /// там, где его нет.
    @Test("Повтор внутри партии занимает один слот, а не три")
    func повторВПартииЗанимаетОдинСлот() {
        let полная = Set((1...63).map { "уже-\($0)" })
        let план = NotificationCenterService.планПартии(
            ожидают: полная, ставим: ["одинаковый", "одинаковый", "одинаковый"])
        #expect(план.лишних == 0, """
            три одинаковых идентификатора посчитаны за \(план.лишних + 1) \
            слотов вместо одного.
            """)
    }

    // MARK: - (б) Форма, которой дефект возвращается

    /// **Главная ось набора и единственная, которую валит подделка.**
    ///
    /// Запрет, а не наличие: проверять «есть ли `do/catch`» нельзя —
    /// такая проверка зеленеет от любого `do/catch` в файле, в том
    /// числе от чужого и от оставшегося рядом с возвращённым `try?`.
    @Test("В службе уведомлений не осталось ни одного тихого try?")
    func нетНиОдногоТихогоTry() throws {
        let строки = try Self.код(Self.служба)

        // КОНТРОЛЬ СНИМАЕТСЯ В ТОМ ЖЕ ЗАМЕРЕ и подвержен тому же
        // отказу: файл не прочитался, путь устарел, комментарии съели
        // весь текст — и тогда «ни одного try?» истинно по причине,
        // к предмету отношения не имеющей. Ноль при мёртвом инструменте
        // выглядит ровно как ноль при здоровом коде.
        let броски = строки.filter { $0.contains("try await") }
        #expect(!броски.isEmpty, """
            в `\(Self.служба)` не нашлось НИ ОДНОГО `try await`. \
            Это отказ замера, а не чистый файл: постановка запроса \
            в очередь — бросающий вызов, и он обязан быть виден. \
            Прочитано строк: \(строки.count).
            """)

        let тихие = строки.filter { $0.contains("try?") }
        #expect(тихие.isEmpty, """
            в `\(Self.служба)` вернулся `try?` — \(тихие.count) \
            вхождений:
            \(тихие.map { "  " + $0.trimmingCharacters(in: .whitespaces) }
                  .joined(separator: "\n"))

            `try?` здесь не сокращение. Он превращает отказ системы \
            в `Void`: место вызова не может узнать, что напоминания \
            не будет, и не скажет об этом человеку. У дозы \
            (`interruptionLevel = .timeSensitive`) цена этого — \
            пропущенное лекарство, о котором не узнал никто.

            Нужно записать иначе — верни значение `ИсходЗапроса`, \
            как это делают `поставить(_:)` и три `schedule*`.
            """)
    }

    /// Вторая половина того же запрета: мало вернуть исход — его
    /// не должно быть можно **не прочитать**.
    ///
    /// Ось та же, что у `СнятиеНапоминанийПодключеноTests`: у параметра
    /// нет умолчания — забыть его не даст компилятор. Здесь роль
    /// умолчания играет `@discardableResult`: с ним вызов
    /// `await scheduleDose(…)` снова становится законным выражением,
    /// всё собирается, тесты зелёные, а исход опять никто не читает.
    @Test("Исход возвращают все три постановки, и прочитать его обязаны")
    func исходНельзяНеПрочитать() throws {
        let строки = try Self.код(Self.служба)

        for имя in ["scheduleMorningBrief", "scheduleDose", "scheduleFastingEnd"] {
            let объявление = строки.filter {
                $0.contains("static func \(имя)(")
            }
            #expect(объявление.count == 1, """
                `\(имя)` объявлена \(объявление.count) раз вместо одного — \
                либо переименована, либо рядом завели вторую.
                """)

            // Возврат может стоять не на строке с `func`, если список
            // параметров перенесён. Ищем в окне от объявления до тела.
            guard let начало = строки.firstIndex(where: { $0.contains("static func \(имя)(") })
            else { continue }
            let окно = строки[начало..<min(начало + 4, строки.count)].joined(separator: " ")
            #expect(окно.contains("-> ИсходЗапроса"), """
                `\(имя)` больше не возвращает `ИсходЗапроса`:
                  \(окно.trimmingCharacters(in: .whitespaces))

                Без возврата отказ системы снова некуда девать, кроме \
                как проглотить, — и это тот же молчаливый путь, \
                только записанный через `do/catch`.
                """)
        }

        let сУмолчанием = строки.filter { $0.contains("@discardableResult") }
        #expect(сУмолчанием.isEmpty, """
            в `\(Self.служба)` появился `@discardableResult` \
            (\(сУмолчанием.count)). Он возвращает ровно тот дефект, \
            ради которого заведён возврат: исход снова можно не читать, \
            всё соберётся, и ни один тест этого не заметит. Забыть \
            исход не должен давать компилятор, а не внимательность.
            """)
    }

    /// Вернуть исход и никому его не сказать — та же тишина, только
    /// дороже: она выглядит починенной.
    @Test("Планировщик доводит отказ до человека, а не до одного лога")
    func отказДоходитДоЧеловека() throws {
        let строки = try Self.код(Self.планировщик)

        let вызовы = строки.reduce(into: 0) { итог, строка in
            итог += строка.components(separatedBy: "сообщить(").count - 1
        }
        // Объявление функции тоже содержит `сообщить(`, поэтому
        // мест постановки на единицу меньше: сводка, доза, окно
        // натощак, «как он сейчас» и переполнение очереди.
        #expect(вызовы >= 6, """
            исход доводится до человека \(вызовы - 1) раз при пяти \
            местах постановки (сводка, доза, окно натощак, \
            «как он сейчас») и переполнении очереди. Пропущенное место \
            молчит ровно так же, как молчал `try?`.
            """)

        let вЖурнал = строки.filter {
            $0.contains("UsageLog.note(.failure") || $0.contains("outcome: .failed")
        }
        #expect(вЖурнал.count >= 2, """
            отказ не уходит в журнал действий: найдено \(вЖурнал.count) \
            строк вместо двух (отказ системы и полная очередь).

            `log.error` читает разработчик у Xcode, человек его не видит \
            никогда. Единственная поверхность, до которой `Store` \
            достаёт без `AppState`, — «Настройки → Журнал действий», \
            раздел «Что чинить» (`UsageReport.frictionList`, корзина \
            `failure`). Уберёшь `UsageLog.note` — отказ снова \
            не доходит ни до кого.
            """)
    }

    /// Потолок надо не просто назвать, а спросить ПРЕЖДЕ постановки.
    ///
    /// Счёт, снятый после партии, отвечает на другой вопрос: очередь
    /// к тому моменту уже урезана системой до потолка, и переполнение
    /// из неё не видно никогда. Ось — **порядок**, а не наличие.
    @Test("Очередь считается прежде постановки партии, а не после")
    func очередьСчитаетсяПреждеПостановки() throws {
        let строки = try Self.код(Self.планировщик)

        guard let замер = строки.firstIndex(where: { $0.contains("NotificationCenterService.ожидающие()") })
        else {
            Issue.record("""
                `scheduleDoses` не спрашивает очередь вовсе: вызова \
                `NotificationCenterService.ожидающие()` в \
                `\(Self.планировщик)` нет. Тогда потолок 64 снова \
                не учитывает никто, и партия доз теряется молча — \
                без исключения и без кода возврата.
                """)
            return
        }
        guard let вывод = строки.firstIndex(where: { $0.contains("планПартии(") }) else {
            Issue.record("""
                очередь спрашивают, но плана по ней не строят: вызова \
                `планПартии(` в `\(Self.планировщик)` нет. Замер без \
                вывода — это замер, который не состоялся.
                """)
            return
        }

        #expect(замер < вывод, """
            очередь считают ПОСЛЕ постановки партии (строка \(замер) \
            против \(вывод)). К этому моменту система уже урезала \
            очередь до потолка, и переполнения в ней не видно никогда: \
            замер честный, вопрос не тот.
            """)
    }

    // MARK: - Разбор

    /// Строки файла без комментариев.
    ///
    /// Снимать обязательно: голова `Notifications.swift` объясняет
    /// именно этот дефект и приводит `try?` дословно. Сторож,
    /// считающий прозу, красит себя зелёным от объяснения — в Togo
    /// это уже случалось.
    private static func код(_ путь: String) throws -> [String] {
        let текст = try String(contentsOf: корень.appendingPathComponent(путь),
                               encoding: .utf8)
        return текст
            .components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
    }

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }
}
