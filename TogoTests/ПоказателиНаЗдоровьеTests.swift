import Foundation
import Testing
@testable import Togo

/// Какие карточки показателей стоят на «Здоровье» (29.10.2026).
///
/// **Предмет — чистый выбор, а не экран.** Проверяется, какие имена
/// выходят из `ПоказателиНаЗдоровье.карточки` при пустой настройке,
/// при исчезнувшем показателе и на пределе. Что экран рисует эти
/// имена карточками — кадр, не этот набор.
///
/// Главное обещание — **у того, кто не настраивал, не меняется
/// ничего**: одна карточка последнего сданного. Его и проверяет
/// первый тест; остальное — следствия выбора.
@Suite("Карточки показателей на «Здоровье» · выбор")
struct ПоказателиНаЗдоровьеTests {
    /// Свежие первыми — так их отдаёт `LabChartScreen.показатели`.
    private let показатели = ["ТТГ", "Т4 общий", "Креатинин"]

    @Test("Не настраивали — одна карточка последнего сданного, как до 29.10")
    func пустаяНастройкаКакБыло() {
        let незадано = ПоказателиНаЗдоровье.карточки(выбор: nil, показатели: показатели, естьВес: true)
        let пусто = ПоказателиНаЗдоровье.карточки(выбор: [], показатели: показатели, естьВес: true)
        #expect(незадано == ["ТТГ"], "без выбора — последний сданный, а не первый по алфавиту и не вес")
        #expect(пусто == незадано, "пустой выбор и «не настраивал» значат одно")
        // Контроль: без анализов карточек нет — и вес сам не встаёт.
        #expect(ПоказателиНаЗдоровье.карточки(выбор: nil, показатели: [], естьВес: true).isEmpty)
    }

    @Test("Выбор и порядок человека держатся, вес — наравне с анализами")
    func выборДержится() {
        let выбор = [ПоказателиНаЗдоровье.вес, "Т4 общий"]
        #expect(ПоказателиНаЗдоровье.карточки(выбор: выбор, показатели: показатели, естьВес: true) == выбор)
    }

    @Test("Исчезнувший показатель молча пропускается, а не рисуется пустым")
    func исчезнувшийПропускается() {
        let выбор = ["Т4 свободный", "Т4 общий", ПоказателиНаЗдоровье.вес]
        let карточки = ПоказателиНаЗдоровье.карточки(выбор: выбор, показатели: показатели, естьВес: false)
        #expect(карточки == ["Т4 общий"], "нет в данных ни «Т4 свободный», ни взвешиваний")
    }

    @Test("Исчезли ВСЕ выбранные — снова последний сданный, а не пустое место")
    func всеИсчезли() {
        let карточки = ПоказателиНаЗдоровье.карточки(выбор: ["Глюкоза"], показатели: показатели, естьВес: false)
        #expect(карточки == ["ТТГ"])
    }

    @Test("Больше предела не ставится — ни из хранилища, ни переключателем")
    func предел() {
        let пять = показатели + ["Глюкоза", ПоказателиНаЗдоровье.вес]
        let все = показатели + ["Глюкоза"]
        let карточки = ПоказателиНаЗдоровье.карточки(выбор: пять, показатели: все, естьВес: true)
        #expect(карточки.count == ПоказателиНаЗдоровье.предел)
        #expect(карточки == Array(пять.prefix(ПоказателиНаЗдоровье.предел)), "отрезается хвост, порядок цел")

        let полный = Array(пять.prefix(ПоказателиНаЗдоровье.предел))
        #expect(ПоказателиНаЗдоровье.переключить(ПоказателиНаЗдоровье.вес, в: полный) == полный,
                "пятый переключателем не добавляется")
        // Контроль: выключить на пределе можно.
        #expect(ПоказателиНаЗдоровье.переключить("ТТГ", в: полный).count == ПоказателиНаЗдоровье.предел - 1)
    }

    @Test("Повтор имени — одна карточка")
    func повторОдинРаз() {
        let карточки = ПоказателиНаЗдоровье.карточки(выбор: ["ТТГ", "ТТГ", "Т4 общий"],
                                                   показатели: показатели, естьВес: false)
        #expect(карточки == ["ТТГ", "Т4 общий"])
    }

    @Test("Сдвиг на шаг и не за край")
    func сдвиг() {
        let выбор = ["ТТГ", "Т4 общий", "Креатинин"]
        #expect(ПоказателиНаЗдоровье.сдвинуть("Т4 общий", на: -1, в: выбор) == ["Т4 общий", "ТТГ", "Креатинин"])
        #expect(ПоказателиНаЗдоровье.сдвинуть("ТТГ", на: -1, в: выбор) == выбор, "первый выше не уходит")
        #expect(ПоказателиНаЗдоровье.сдвинуть("Креатинин", на: 1, в: выбор) == выбор, "последний ниже не уходит")
    }

    /// Починка «пустых столбиков» ТТГ: ряд 0,1–0,4 при потолке 1
    /// у `КиноСтолбики` падал на минимальную высоту.
    @Test("Столбики — доля от наибольшего в ряду, ноль остаётся нулём")
    func доли() {
        let доли = ПоказателиНаЗдоровье.доли([0.1, 0.2, 0.4])
        #expect(доли == [0.25, 0.5, 1.0])
        #expect(ПоказателиНаЗдоровье.доли([0, 2]) == [0, 1])
        #expect(ПоказателиНаЗдоровье.доли([]).isEmpty)
    }

    @Test("Хранение — по собаке, пустой выбор не хранится")
    func хранение() throws {
        let имя = "test.ПоказателиНаЗдоровье.\(UUID().uuidString)"
        let хранилище = try #require(UserDefaults(suiteName: имя))
        defer { хранилище.removePersistentDomain(forName: имя) }
        let стич = UUID()
        let другая = UUID()

        ПоказателиНаЗдоровье.записать(["Т4 общий"], собака: стич, хранилище: хранилище)
        #expect(ПоказателиНаЗдоровье.прочитать(собака: стич, хранилище: хранилище) == ["Т4 общий"])
        #expect(ПоказателиНаЗдоровье.прочитать(собака: другая, хранилище: хранилище) == nil,
                "выбор одной собаки не едет другой")

        ПоказателиНаЗдоровье.записать([], собака: стич, хранилище: хранилище)
        #expect(ПоказателиНаЗдоровье.прочитать(собака: стич, хранилище: хранилище) == nil,
                "пустой выбор — «как было», а не пустой экран")
    }
}
