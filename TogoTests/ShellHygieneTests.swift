import Foundation
import Testing

/// Гигиена shell-скриптов `Tools/`: три отказа оболочки, которые
/// **не падают, а отвечают успехом**.
///
/// # Почему сторож появился только 09.10.2026
///
/// Правило «имена переменных только латиницей» записано в своде четырёх
/// проектов с 23.09 и рядом с ним стоит имя теста
/// `testShellScriptsHaveNoCyrillicVariables`. Поэтому запись читается
/// как «правило под охраной». Замер `projects-6e` 09.10:
///
/// ```
/// Gamut/Tests/UITestHygieneTests.swift:72   тест ЕСТЬ
/// Togo · Timer · Kvit                       НЕТ НИ ОДНОГО
/// Togo/Tools/прогон-ui.sh                   ССЫЛАЛСЯ на него
/// ```
///
/// > **Имя теста не состарилось — оно было верным и УЗКИМ с рождения.**
/// > Свод не сказал, в каком проекте сторож живёт, и из записи выходило,
/// > что он общий.
///
/// Сломалось соглашение ровно так, как и должно было: оно держалось
/// привычкой восемнадцати скриптов и сломалось на первом, кто пришёл
/// со стороны — девять кириллических имён в одном новом скрипте.
/// Спас `set -u`; без него скрипт поехал бы с пустыми путями и сделал
/// `git worktree add` с пустым именем.
///
/// # Три предмета, и они НЕ взаимозаменяемы
///
/// ```
/// имя            кириллица В ИМЕНИ: bash такое имя не принимает,
///                падает молча, следующая строка идёт как ни в чём
///                не бывало
/// прилипший      кириллица ВПЛОТНУЮ К ИМЕНИ при латинском имени:
/// символ         `"проба «$probe»"` → оболочка ищет `probe\xc2\xbb`.
///                Сторож на имена при этом ЗЕЛЁНЫЙ
/// set -u         без него оба класса молчат и дают пустую строку —
///                то есть вывод, ОБРАТНЫЙ правде, про сам инструмент
/// ```
///
/// Каждое утверждение проверено подделкой, нарушающей **ровно одно**:
/// иначе три выглядели бы взаимозаменяемыми, и следующий снял бы
/// «лишнее».
@Suite("Гигиена shell-скриптов")
struct ShellHygieneTests {

    /// Каталог скриптов. **Ось от каталога, а не от списка руками:**
    /// список знает только то, что в него положили, и следующий скрипт
    /// попадёт под сторожа сам.
    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("Tools")
    }

    private static func скрипты() throws -> [URL] {
        try FileManager.default
            .contentsOfDirectory(at: каталог, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "sh" }
            .sorted { $0.lastPathComponent < $1.lastPathComponent }
    }

    /// Строка без комментария. Пустая — если комментарий занял всю строку.
    ///
    /// **Сканирующий сторож, не различающий код и прозу, меряет прозу.**
    /// Здесь это не теория, а замер: оба предиката ниже, прогнанные
    /// на здоровых скриптах Togo **до** рождения теста, дали три
    /// срабатывания — и все три на комментариях, объясняющих это самое
    /// правило (`номер-сборки.sh:22`, `:50`, `check_bundle_languages.sh:67`).
    /// То есть без вырезания прозы сторож краснел бы на абзаце о том,
    /// как не надо делать.
    ///
    /// **Сделано своё, а не взято у Gamut, и причина измерена.**
    /// `UITestHygieneTests.withoutComment` вырезает `//` — комментарий
    /// **Swift**, — а применяется к shell-скриптам, где комментарий `#`.
    /// То есть у Gamut проза не вырезается вовсе; перенести его форму
    /// значило бы перенести и это.
    ///
    /// **Граница, и она названа до первой находки:** кавычки считаются
    /// простым переключателем, экранированная кавычка внутри строки
    /// (`\"`) переключит его неверно. Такой строки в `Tools/` сегодня
    /// нет ни одной; появится — сторож ошибётся **в сторону молчания**,
    /// то есть спрячет дефект, а не придумает его. Это выбор: ложная
    /// тревога дороже, после неё сторожа перестают читать.
    static func кодБезКомментария(_ строка: String) -> String {
        var код = ""
        var вОдинарных = false
        var вДвойных = false
        var предыдущий: Character?

        for символ in строка {
            if символ == "'" && !вДвойных {
                вОдинарных.toggle()
            } else if символ == "\"" && !вОдинарных {
                вДвойных.toggle()
            } else if символ == "#" && !вОдинарных && !вДвойных {
                // `#` начинает комментарий только в начале слова:
                // `a#b` — слово, `${#arr[@]}` — длина массива.
                if предыдущий == nil || предыдущий == " " || предыдущий == "\t" {
                    break
                }
            }
            код.append(символ)
            предыдущий = символ
        }
        return код
    }

    /// Первым — проверка, что сторожу **было что проверять**.
    ///
    /// Набор, которому нечего проверять, молчит так же, как набор,
    /// у которого всё хорошо. Порог тупой нарочно: он ловит не рост
    /// числа скриптов, а недоступный из этой среды каталог.
    @Test("Скрипты нашлись — сторожу было что проверять")
    func скриптыНашлись() throws {
        let найдено = try Self.скрипты()
        #expect(найдено.count >= 10, """
            в Tools/ найдено \(найдено.count) скриптов — разбор \
            не состоялся, и три сторожа ниже зелены впустую. \
            Каталог: \(Self.каталог.path)
            """)
    }

    @Test("Имена переменных в shell-скриптах только латиницей")
    func именаТолькоЛатиницей() throws {
        var найдено: [String] = []

        for файл in try Self.скрипты() {
            let текст = try String(contentsOf: файл, encoding: .utf8)
            for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                let код = Self.кодБезКомментария(строка)
                guard код.range(of: #"^\s*[А-Яа-яЁё_]+="#,
                                options: .regularExpression) != nil else { continue }
                найдено.append("\(файл.lastPathComponent):\(номер + 1) — \(код.trimmingCharacters(in: .whitespaces))")
            }
        }

        #expect(найдено.isEmpty, """
            кириллица в ИМЕНИ переменной shell: bash такое имя \
            не принимает, падает молча — «command not found» — \
            и следующая строка выполняется как ни в чём не бывало.
            23.09.2026 это стоило трёх заходов за один день: испорченный \
            рабочий файл без отката, непрочитанный журнал и пересъёмка \
            кадров в ноль.

            \(найдено.joined(separator: "\n"))
            """)
    }

    /// Вторая форма, которой сторож имён **не ловит**.
    ///
    /// Замер 07.10.2026 на Togo: имя было латиницей, а
    /// `echo "проба «$probe»"` дал `unbound variable` — оболочка искала
    /// переменную `probe\xc2\xbb`. **Лишний байт пришёл не из имени,
    /// а из соседнего символа**, и сторож на имена был зелёным.
    ///
    /// **Предикат сужён против записанного в своде, и это измерено.**
    /// Свод предлагает `grep -nE '\$[a-z_]+[^a-zA-Z0-9_{}"$ /)]'`.
    /// Прогон этой формы на здоровых скриптах Togo дал **пять
    /// срабатываний**: `$build,` и `$file.` — запятая и точка, которые
    /// bash разбирает верно, — плюс три на комментариях. То есть
    /// записанная команда годится человеку, который посмотрит глазами,
    /// и не годится сторожу.
    ///
    /// Здесь предмет назван прямо: имя переменной, к которому вплотную
    /// приклеен **не-ASCII** символ. ASCII-пунктуация законна.
    @Test("К имени переменной не приклеен многобайтный символ")
    func многобайтныйНеПриклеенКИмени() throws {
        var найдено: [String] = []

        for файл in try Self.скрипты() {
            let текст = try String(contentsOf: файл, encoding: .utf8)
            for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                let код = Self.кодБезКомментария(строка)
                guard код.range(of: #"\$[a-zA-Z_][a-zA-Z0-9_]*[^\x00-\x7F]"#,
                                options: .regularExpression) != nil else { continue }
                // Строка, СОЗДАЮЩАЯ подделку, — не дефект, а предмет
                // приёмки. `приёмка-6e-shellhygiene.sh:130` пишет
                // `printf '…echo "проба «$probe»"…' > Tools/zz-poddelka-b.sh`,
                // то есть дефект лежит внутри данных скрипта, а не в его
                // коде, и нужен там нарочно: без него нечем показать,
                // что этот сторож умеет краснеть.
                //
                // Признак узкий и меримый — запись в файл с именем
                // `zz-poddelka-`. Исключать файл приёмки целиком было бы
                // шире правды: в нём есть и собственный код, который
                // этому классу подвержен ровно так же.
                //
                // Это наш записанный класс: инструмент проверки
                // подвержен тому же, что ищет. 13.10.2026 он на этом
                // и покраснел — впервые, когда полный прогон дошёл
                // до конца.
                guard !код.contains("> Tools/zz-poddelka-") else { continue }
                найдено.append("\(файл.lastPathComponent):\(номер + 1) — \(код.trimmingCharacters(in: .whitespaces))")
            }
        }

        #expect(найдено.isEmpty, """
            к имени переменной вплотную приклеен многобайтный символ: \
            оболочка читает его ЧАСТЬЮ ИМЕНИ и ищет переменную, \
            которой нет. Правило «только латиницей» этого не видит — \
            имя там латиницей, лишний байт пришёл от соседа.
            Лечится фигурными скобками: `${name}»`, не `$name»`.

            \(найдено.joined(separator: "\n"))
            """)
    }

    /// `set -u` — то, без чего два класса выше **молчат**.
    ///
    /// Без него оболочка подставляет пустую строку и идёт дальше:
    /// отпечаток подделки читался бы как «не применилась», то есть
    /// вывод, обратный правде, про сам инструмент доверия.
    ///
    /// Спрашивается у скриптов, которые **что-то подставляют** — то есть
    /// содержат `$`. Скрипт без подстановок этим классом не болеет,
    /// и требовать от него `set -u` значило бы завести ложную тревогу
    /// ради единообразия. На 09.10.2026 подставляют все восемнадцать,
    /// и у всех восемнадцати `set -u` уже стоит.
    @Test("Скрипт, подставляющий переменные, объявляет set -u")
    func подстановкаТребуетSetU() throws {
        var безЗащиты: [String] = []

        for файл in try Self.скрипты() {
            let текст = try String(contentsOf: файл, encoding: .utf8)
            let строки = текст.components(separatedBy: .newlines)
            let кодом = строки.map(Self.кодБезКомментария)

            let подставляет = кодом.contains { $0.contains("$") }
            guard подставляет else { continue }

            let объявлен = кодом.contains {
                $0.range(of: #"^\s*set\s+(-[a-z]*u[a-z]*|-o\s+nounset)"#,
                         options: .regularExpression) != nil
            }
            if !объявлен { безЗащиты.append(файл.lastPathComponent) }
        }

        #expect(безЗащиты.isEmpty, """
            скрипт подставляет переменные и не объявляет `set -u`: \
            без него опечатка в имени даёт ПУСТУЮ СТРОКУ и нулевой код \
            возврата, а не отказ. Класс молчит, и молчание читается \
            как результат.

            \(безЗащиты.joined(separator: "\n"))
            """)
    }
}
