import Testing
import Foundation
@testable import Togo

/// Текст уведомления об окне натощак — первая проверка этой поверхности
/// за всё время, и до 07.10.2026 её нельзя было написать вовсе.
///
/// **Поверхность была непроверяемой, а не непроверенной.** Строка
/// собиралась внутри `scheduleFastingEnd`, укладывалась
/// в `UNMutableNotificationContent` и уходила в систему: наружу
/// не возвращалось ничего, кадром уведомление не снимается. Утверждать
/// про неё было нечем ни тестом, ни глазом.
///
/// Разница решает, что делать: «непроверенная» лечится взглядом,
/// «непроверяемая» — только переделкой входа. У Timer на этом месте
/// стояла карточка Live Activity, и отзыв «проблемы с виджетом» жил
/// незамеченным не потому, что плохо смотрели, а потому что смотреть
/// было не на что.
///
/// Шов — `NotificationCenterService.fastingEndText(dogName:)`,
/// заведён 07.10 ради этого набора. Сам текст не тронут ни на символ.
@Suite("Уведомление об окне натощак")
struct FastingNotificationTextTests {

    // MARK: - 1. Проверка, что проверять было что

    /// Стоит первой: все запреты ниже выполняются и у пустой строки.
    @Test("Шов возвращает непустой текст с кличкой")
    func былоЧтоПроверять() {
        let текст = NotificationCenterService.fastingEndText(dogName: "Стич")
        #expect(!текст.title.isEmpty, "заголовок пуст — шов отдаёт не то")
        #expect(!текст.body.isEmpty, "тело пусто — шов отдаёт не то")
        #expect(текст.body.contains("Стич"), """
            кличка не попала в тело уведомления: «\(текст.body)». \
            Тогда запреты ниже зелены по причине, к кличке отношения \
            не имеющей.
            """)
    }

    // MARK: - 2. Пустая кличка

    /// **От запрета, и иначе нельзя.** «Тело содержит кличку» при пустой
    /// кличке истинно у любой строки, включая пустую — замерено 07.10:
    /// `"15 ч · ".contains("")` → `true`. Проверяем то, что дефект
    /// нарушает: двойной пробел на месте выпавшего слова.
    ///
    /// Цена не косметическая. Уведомление об окне натощак — одно
    /// из трёх, которым разрешено прерывать человека
    /// (`interruptionLevel = .timeSensitive`). Оно будит, и прочитать
    /// его человек успевает один раз, с экрана блокировки.
    ///
    /// **Был красным утром 07.10.2026, позеленел к вечеру — запись
    /// правится, а не остаётся как была.** Утром функция принимала
    /// кличку как есть и отдавала «Окно натощак закончилось.  может
    /// есть.»; `togo-05` подставил `Fmt.dogNameOrFallback` внутри, как
    /// до того защитил `SnapshotText.inlineText`. Оставь я здесь слово
    /// «КРАСНЫЙ» — через неделю его прочтут как живой дефект, и это
    /// тот же обман, что комментарий о починке над сломанным кодом.
    ///
    /// **И то, чего починка НЕ сделала, — главное в этой записи.**
    /// Откат чинит текст и не делает его утверждаемым: строка
    /// по-прежнему собиралась внутри `scheduleFastingEnd` и никуда
    /// не возвращалась. Починить и дать проверить — два разных дела,
    /// и второе не следует из первого. Шов `fastingEndText(dogName:)`
    /// заведён отдельно и ровно для этого.
    @Test("Пустая кличка не оставляет в уведомлении дыру")
    func пустаяКличкаНеОставляетДыру() {
        let тело = NotificationCenterService.fastingEndText(dogName: "").body

        #expect(!тело.contains("  "), """
            уведомление говорит «\(тело)» — на месте клички двойной \
            пробел. Это одно из трёх уведомлений, которым разрешено \
            прерывать человека: он читает его один раз, с экрана \
            блокировки, и переспросить ему некого.
            """)
        #expect(!тело.contains(" ."), """
            уведомление говорит «\(тело)» — пробел перед точкой на месте \
            выпавшего слова.
            """)
    }

    // MARK: - 3. Граница набора

    /// Названа здесь, а не в чьей-то памяти.
    ///
    /// Зелёный в этом наборе значит: **шов собирает текст верно** —
    /// и только это. Он не говорит, что уведомление поставлено
    /// в расписание, что оно дошло до телефона и что человек его
    /// увидел: `scheduleFastingEnd` после шва делает ещё три вещи,
    /// и ни одна из них отсюда не видна.
    ///
    /// Тот же зазор, что между `inlineText` и видом «острова»: строка
    /// проверяема, поверхность — нет.
    @Test("Набор не притворяется проверкой доставки")
    func границаНазвана() {
        // Шов отдаёт текст и ничего не планирует — это и есть граница,
        // выраженная кодом, а не обещанием: функция чистая, позвать её
        // можно сколько угодно раз без единого побочного действия.
        let первый = NotificationCenterService.fastingEndText(dogName: "Стич")
        let второй = NotificationCenterService.fastingEndText(dogName: "Стич")
        #expect(первый.body == второй.body)
        #expect(первый.title == второй.title)
    }
}
