import Testing
import Foundation
@testable import Togo

/// Кеш опасен ровно одним — тем, что отдаёт вчерашний ответ сегодня.
///
/// `КешЛенты` заведён 28.10.2026, чтобы главный экран не проходил
/// дневник двадцать раз на кадр. Выигрыш там измеримый, а риск
/// у кеша всегда один и тот же: **устаревание выглядит как
/// работающий экран.** Ничего не падает, ничего не краснеет —
/// просто цифра не та.
///
/// # Почему ось именно такая
///
/// Проверять «кеш быстрее» бессмысленно: это меряло бы занятость
/// машины. Проверять надо то единственное, что кеш может сломать, —
/// **свежесть после правки, не меняющей состав массива.**
///
/// ```
/// отпечаток по events.count     правка времени прогулки его НЕ меняет
///                               → экран показал бы старое «дома 4 часа»
/// отпечаток по полям ленты      меняется → кеш пересчитает
/// ```
///
/// Первая форма и есть тот ложный кеш, от которого здесь сторож.
/// Он написан ОТ ОБРАТНОГО: не «кеш отвечает», а «кеш ОБЯЗАН
/// заметить правку».
@Suite("Кеш ленты не отдаёт старое")
@MainActor
struct КешЛентыTests {

    private func выход(_ часовНазад: Double) -> LogEvent {
        LogEvent(kind: .outing,
                 date: Date().addingTimeInterval(-часовНазад * 3600),
                 authorName: "Виктория")
    }

    @Test("Правка времени записи обновляет срез, хотя состав массива тот же")
    func правкаВремениВидна() {
        let кеш = КешЛенты()
        let сейчас = Date()
        let запись = выход(4)
        let события = [запись]

        let первый = кеш.срез(события, now: сейчас)
        // Контроль ПЕРВЫМ: было ли что считать. Без него сравнение
        // двух `nil` прошло бы как успех.
        #expect(первый.конецПоследнегоВыхода != nil, """
            срез не нашёл выхода на одной записи вида .outing —
            считать нечего, и совпадение двух пустых ответов
            ничего не доказывает.
            """)

        // Та же запись, другое время. Состав массива НЕ изменился:
        // ни одной записи не добавилось и не убавилось.
        запись.date = сейчас.addingTimeInterval(-1 * 3600)
        let второй = кеш.срез(события, now: сейчас)

        #expect(второй.конецПоследнегоВыхода != первый.конецПоследнегоВыхода, """
            кеш отдал прежний ответ после правки времени записи.
            Это и есть ложный кеш: экран показал бы «дома 4 часа»,
            когда собака вернулась час назад.
            """)
    }

    @Test("Удаление записи видно кешу")
    func удалениеВидно() {
        let кеш = КешЛенты()
        let сейчас = Date()
        let запись = выход(2)
        let события = [запись]

        let первый = кеш.срез(события, now: сейчас)
        #expect(первый.конецПоследнегоВыхода != nil, "сверять нечего")

        // `deletedAt` — поле, по которому запись уходит из `Diary.active`.
        // Массив при этом снова прежней длины.
        запись.deletedAt = сейчас
        let второй = кеш.срез(события, now: сейчас)

        #expect(второй.конецПоследнегоВыхода == nil, """
            удалённая запись осталась в срезе: кеш не заметил
            deletedAt, хотя Diary.active по нему и отбирает.
            """)
    }

    @Test("Один и тот же вопрос дважды даёт один ответ")
    func повторДаётТоЖе() {
        let кеш = КешЛенты()
        let сейчас = Date()
        let события = [выход(3), выход(9)]

        let первый = кеш.срез(события, now: сейчас)
        let второй = кеш.срез(события, now: сейчас)

        // Смысл кеша: при неизменном входе ответ обязан совпасть
        // ДОСЛОВНО. Проверяется не скорость, а то, что попадание
        // в кеш не меняет результата.
        #expect(первый.конецПоследнегоВыхода == второй.конецПоследнегоВыхода)
        #expect(первый.дома == второй.дома)
        #expect(первый.ритм == второй.ритм)
        #expect(первый.конецПоследнегоВыхода != nil, "сверять нечего")
    }

    @Test("Сдвиг «сейчас» меняет, сколько собака дома")
    func времяДвижется() {
        let кеш = КешЛенты()
        let сейчас = Date()
        let события = [выход(2)]

        let первый = кеш.срез(события, now: сейчас)
        let второй = кеш.срез(события, now: сейчас.addingTimeInterval(3600))

        #expect(первый.дома != nil, "сверять нечего: «дома» не посчиталось")
        guard let рано = первый.дома, let поздно = второй.дома else { return }
        #expect(поздно > рано, """
            через час дома стало не больше: `now` не попал в ключ кеша,
            и показание замерло бы на экране, который тикает
            раз в тридцать секунд.
            """)
    }
}
