import Testing
import Foundation
@testable import Togo

/// Неудачное чтение общего дневника обязано быть видимым.
///
/// **Замер 24.09.2026.** У второго человека два дня не появлялось
/// ничего из общего дневника; его экран при этом выглядел рабочим.
/// Различить «не пришло, потому что нечего» и «не пришло, потому что
/// упало» было нечем: в `fetchNow` стояло `try?`, ошибка уходила
/// в никуда, а состояние тут же становилось `idle(lastSync: сейчас)`.
/// Приложение говорило «синхронизировано» ровно в ту секунду, когда
/// синхронизация провалилась.
///
/// Это та же форма, что ступень «iCloud недоступен» с одним текстом
/// на три причины, только хуже: там неверный совет, здесь — бодрое
/// молчание.
@MainActor
@Suite("Отказ чтения общего дневника виден")
struct SharedDiaryFetchFailureTests {

    private struct Отказ: LocalizedError {
        var errorDescription: String? { "зона не найдена" }
    }

    @Test("Отказ становится failed, а не idle")
    func отказВиден() {
        let состояние = FamilySync.состояние(послеОтказов: [Отказ()], lastSync: Date())

        // От обратного: не «состояние как-то поменялось», а «оно НЕ idle».
        // «Поменялось» выполнялось бы и при переходе в syncing.
        if case .idle = состояние {
            Issue.record("""
                после отказа чтения состояние осталось idle — это и есть \
                та самая надпись «синхронизировано» поверх провалившейся \
                синхронизации
                """)
        }
        guard case .failed(let текст) = состояние else {
            Issue.record("ожидали failed, получили \(состояние)")
            return
        }
        #expect(текст.contains("зона не найдена"), """
            в тексте отказа нет причины: «\(текст)». Один текст на все причины \
            даёт совет, неверный для большинства из них, — у этого проекта \
            такое уже было на ступенях iCloud.
            """)
    }

    @Test("Без отказов состояние прежнее — иначе проверка выше ничего не значит")
    func безОтказовIdle() {
        let когда = Date(timeIntervalSince1970: 1_000_000)
        let состояние = FamilySync.состояние(послеОтказов: [], lastSync: когда)
        #expect(состояние == .idle(lastSync: когда))
    }

    /// Сторож на ВЫЗОВ, а не на модель: проверка выше зелена и тогда,
    /// когда `fetchNow` снова начнёт глотать ошибку через `try?` —
    /// она просто никогда не будет вызвана с непустым списком.
    ///
    /// Комментарии вырезаются до разбора, и это не педантизм: в этом же
    /// файле и в самом `FamilySync` строка `try? await engine.fetchChanges()`
    /// стоит в объяснении, почему так делать нельзя. Сканер, не
    /// различающий код и прозу, наказывал бы ровно за рассказ об ошибке.
    @Test("Чтение движка не завёрнуто в try?")
    func чтениеНеГлотается() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let исходник = try String(contentsOf: корень.appendingPathComponent(
            "TogoShared/Sync/FamilySync.swift"), encoding: .utf8)

        let код = исходник.split(separator: "\n", omittingEmptySubsequences: false)
            .filter { !$0.trimmingCharacters(in: .whitespaces).hasPrefix("//") }
            .joined(separator: "\n")

        let вызовы = код.components(separatedBy: "fetchChanges()").count - 1
        // Сканер, переставший что-либо находить, молчит так же, как тот,
        // у которого всё хорошо.
        #expect(вызовы >= 1, "в FamilySync не нашлось ни одного вызова fetchChanges() — сканер смотрит не туда")
        #expect(!код.contains("try? await engine.fetchChanges()"), """
            чтение снова завёрнуто в try?: ошибка уйдёт в никуда, и второй \
            человек опять два дня будет смотреть на экран, который выглядит \
            рабочим. Ошибку надо ловить и показывать.
            """)
    }
}
