import Testing
import Foundation
@testable import Togo

/// Сторож на правило `UrineSilence` (коммит `56d16f1`).
///
/// Поведение пришло без сторожа, требования выписал `togo-35`
/// в `docs/journal/2026-09-28.md`. Всё ниже — **от обратного**: «не
/// срочно» истинно и при пустых сигналах, поэтому каждый сценарий
/// сперва проверяется на наполненность, и проверка эта одна на весь
/// набор — `сценарийНаполнен`.
///
/// Что было сломано до `56d16f1`: на дневнике, молчащем восемнадцать
/// дней, вердикт выдавал «Выведи сейчас · срочно» и «Не писал 434 ч.
/// Это дольше, чем он когда-либо терпел» — медицинское утверждение
/// о собаке, выведенное из **отсутствия** записи. Путь дефекта —
/// ветка `since > longest` в `VerdictEngine.evaluate`.
///
/// **Почему Optional нигде не сравнивается напрямую.** Первая редакция
/// этого файла писала `#expect(s.sinceUrine == 434 * 3600)`, и проверка
/// краснела, тогда как та же величина, развёрнутая через `#require`,
/// сходилась. Сравнение `Optional<TimeInterval>` с числовым литералом
/// компилируется, читается верно и значит не то — то есть даёт
/// **красный без дефекта**, а он учит не верить красному и стоит дороже
/// пропущенной находки. Поэтому величины разворачиваются, а потом
/// сравниваются.
@Suite("Тишина дневника — не задержка мочи")
struct UrineSilenceTests {

    // MARK: - Один сценарий на весь набор

    /// Медиана шесть часов: `typicalUrineInterval` берёт `sorted[count / 2]`,
    /// то есть на трёх интервалах — средний. Самый долгий записанный
    /// интервал — семь часов, и это важно: ровно его превышение
    /// включало ветку `.urgent`.
    static let интервалы: [TimeInterval] = [5 * 3600, 6 * 3600, 7 * 3600]
    static let сейчас = Date(timeIntervalSince1970: 1_759_000_000)

    /// Сборка сигналов в одном месте: четыре теста строили её по копии,
    /// и разойтись эти копии могли молча — тогда набор проверял бы
    /// четыре разных мира под одними именами.
    static func сигналы(мочаЧасовНазад: Double,
                        выходЧасовНазад: Double? = nil,
                        выходДалРезультат: Bool = false,
                        едаЧасовНазад: Double? = nil,
                        прогулкаЧасовНазад: Double? = nil,
                        стулЧасовНазад: Double? = nil) -> NeedSignals {
        func назад(_ часов: Double?) -> Date? {
            часов.map { сейчас.addingTimeInterval(-$0 * 3600) }
        }
        return NeedSignals(now: сейчас,
                           lastUrine: сейчас.addingTimeInterval(-мочаЧасовНазад * 3600),
                           lastStool: назад(стулЧасовНазад),
                           lastMeal: назад(едаЧасовНазад),
                           lastWalk: назад(прогулкаЧасовНазад),
                           urineIntervals: интервалы,
                           daysOfData: 20,
                           lastOutingHadResult: выходДалРезультат,
                           lastOutingAt: назад(выходЧасовНазад))
    }

    /// Проверка, что проверять было что, — и она же возвращает величину,
    /// которой дальше пользуются тесты.
    ///
    /// Любой группе проверок нужна проверка, что ей было что проверять,
    /// и ставится она первой. Без неё «вердикт не срочный» зелено и там,
    /// где считать нечего: набор, которому нечего проверять, молчит так же,
    /// как набор, у которого всё хорошо.
    @discardableResult
    static func сценарийНаполнен(_ s: NeedSignals,
                                 мочаЧасовНазад: Double) throws -> TimeInterval {
        #expect(s.daysOfData >= VerdictEngine.minimumDaysOfData)
        let медиана = try #require(s.typicalUrineInterval)
        #expect(медиана == 6 * 3600)
        let самыйДолгий = try #require(s.longestUrineInterval)
        #expect(самыйДолгий == 7 * 3600)
        let прошло = try #require(s.sinceUrine)
        #expect(прошло == мочаЧасовНазад * 3600)
        // И что дефект достижим: величина больше самого долгого
        // записанного интервала, то есть ветка `since > longest`,
        // дававшая `.urgent`, лежит на пути сценария.
        #expect(прошло > самыйДолгий)
        return прошло
    }

    // MARK: - 1. Тишина обязана давать `.unknown(.silence)`

    @Test("Дневник молчит 434 часа — вердикт не срочный, а «нечего сказать»")
    func тишинаНеСтановитсяСрочностью() throws {
        let s = Self.сигналы(мочаЧасовНазад: 434)
        try Self.сценарийНаполнен(s, мочаЧасовНазад: 434)

        // Величина разворачивается ДО сравнения: `try` не может стоять
        // справа от оператора внутри `#expect`, а сравнивать Optional
        // с литералом нельзя по причине выше.
        let моча = try #require(s.lastUrine)
        #expect(s.urineSilence == моча)
        #expect(VerdictEngine.evaluate(s) == .unknown(reason: .silence(since: моча)))
    }

    // MARK: - 2. Настоящий сигнал обязан выживать

    @Test("Выход отмечен два часа назад и мочи в нём нет — ровно «срочно»")
    func настоящийСигналВыживает() throws {
        // Половина, которую Виктория просила сохранить, и заглушить её
        // легче всего: достаточно поставить правило тишины выше проверки
        // свежести выхода. Ради этого сигнала к врачу и идут.
        let s = Self.сигналы(мочаЧасовНазад: 26, выходЧасовНазад: 2)
        try Self.сценарийНаполнен(s, мочаЧасовНазад: 26)

        // Тишины тут нет — дневник ведут, выход свежий.
        #expect(s.urineSilence == nil)
        #expect(VerdictEngine.evaluate(s) == .urgent)
    }

    // MARK: - 3. Свежесть, а не порядок

    @Test("Выход позже мочи, но сам восемнадцатидневной давности — это тишина")
    func свежестьАНеПорядок() throws {
        // Первая редакция правила сравнивала выход с мочой по порядку
        // (`выход позже мочи`) и на паре «моча 3 сент. 10:00, выход
        // 3 сент. 18:00, now 21 сент.» оставляла ровно ту неправду,
        // от которой правило заведено: выход действительно позже мочи,
        // но сам он из той же заброшенной недели.
        let s = Self.сигналы(мочаЧасовНазад: 18 * 24,
                             выходЧасовНазад: 18 * 24 - 8)   // тот же день, вечером
        try Self.сценарийНаполнен(s, мочаЧасовНазад: 18 * 24)

        let моча = try #require(s.lastUrine)
        let выход = try #require(s.lastOutingAt)
        // Порядок именно тот, что обманывал: выход ПОЗЖЕ мочи, и оба давние.
        #expect(выход > моча)
        #expect(s.now.timeIntervalSince(выход) >= UrineSilence.ceiling)

        #expect(s.urineSilence == моча)
        #expect(VerdictEngine.evaluate(s) == .unknown(reason: .silence(since: моча)))
    }

    // MARK: - 4. Величина «сколько прошло» не доезжает до человека

    @Test("Под тишиной ни одна строка не несёт «сколько прошло»")
    func тишинаНеПоказываетЧисло() throws {
        let s = Self.сигналы(мочаЧасовНазад: 434)
        let прошлоСекунд = try Self.сценарийНаполнен(s, мочаЧасовНазад: 434)
        let вердикт = VerdictEngine.evaluate(s)

        // Проверяется РЕЗУЛЬТАТ строки, а не вызов: «имя упомянуто»
        // тут не доказывает ничего — поверхность могла бы посчитать
        // сама из `sinceUrineSeconds`, и это уже случившийся у Togo
        // дефект (виджет считал окно «не кормить» своей арифметикой).
        let объяснение = VerdictEngine.explanation(вердикт, s)
        let прошло = Fmt.duration(прошлоСекунд)
        #expect(прошло.isEmpty == false)

        // Запретом, а не требованием: у «сколько прошло» десять форм,
        // а запретное узнаётся по своей форме.
        #expect(объяснение.contains(прошло) == false)
        #expect(объяснение.contains("терпел") == false)
        #expect(вердикт.badge.contains(прошло) == false)
        #expect(вердикт.title.contains(прошло) == false)
        // Дата в объяснении — не «сколько прошло», а измеренное: она
        // обязана там быть, иначе человеку нечего сопоставить с памятью.
        let моча = try #require(s.lastUrine)
        #expect(объяснение.contains(Fmt.shortDay(моча)))

        // И обратная половина: при НАСТОЯЩЕЙ задержке величина обязана
        // печататься. Без этой проверки сторож остался бы зелёным
        // у поверхности, которая молчит про мочу всегда.
        let свежая = Self.сигналы(мочаЧасовНазад: 26, выходЧасовНазад: 2)
        let срочно = VerdictEngine.evaluate(свежая)
        #expect(срочно == .urgent)
        let свежаяВеличина = Fmt.duration(try #require(свежая.sinceUrine))
        #expect(VerdictEngine.explanation(срочно, свежая).contains(свежаяВеличина))
    }

    // MARK: - 5. Строка фактов под вердиктом

    /// Четвёртая поверхность того же правила, и нашёл её **кадр**,
    /// а не прогон.
    ///
    /// Под честным «приложение не знает, писал он» строка фактов
    /// печатала «ел 437 ч 19 мин назад» — число из отсутствия записи,
    /// да ещё с минутами, то есть с точностью, которой там неоткуда
    /// взяться. Сторожа не было: три прежние починки правила
    /// (выходы 21.09, моча 28.09, вердикт 30.09) эту функцию не трогали.
    @Test("На заброшенном дневнике строка фактов называет даты, а не часы")
    func строкаФактовНеПечатаетЧасыИзТишины() throws {
        let s = Self.сигналы(мочаЧасовНазад: 434,
                             едаЧасовНазад: 437,
                             прогулкаЧасовНазад: 440,
                             стулЧасовНазад: 441)
        // Было что проверять: все три величины в сигналах есть.
        let еда = try #require(s.lastMeal)
        let прогулка = try #require(s.lastWalk)
        _ = try #require(s.lastStool)

        let строка = VerdictEngine.factLine(s)

        // Запретом, а не требованием: у «сколько прошло» десять форм,
        // а запретное узнаётся по своей форме.
        #expect(строка.contains(Fmt.duration(437 * 3600)) == false, """
            строка фактов снова печатает «ел \(Fmt.duration(437 * 3600)) назад»
            на дневнике, который забросили. Минуты в этом числе обещают
            точность, которой у отсутствия записи быть не может.
            """)
        #expect(строка.contains(Fmt.duration(440 * 3600)) == false,
                "то же у прогулки — у неё разветвления не было вовсе")

        // И что сказано вместо числа: дата, а не молчание. Без неё
        // человеку нечего сопоставить с памятью.
        #expect(строка.contains(Fmt.shortDay(еда)))
        #expect(строка.contains(Fmt.shortDay(прогулка)))
    }

    /// Обратная половина. Без неё запрет выше был бы зелёным
    /// и у строки, которая не печатает «сколько прошло» никогда.
    @Test("Внутри суток строка фактов по-прежнему отвечает часами")
    func свежиеФактыОстаютсяЧасами() throws {
        let s = Self.сигналы(мочаЧасовНазад: 26, выходЧасовНазад: 2,
                             едаЧасовНазад: 3, прогулкаЧасовНазад: 5)
        let строка = VerdictEngine.factLine(s)

        #expect(строка.contains(Fmt.duration(3 * 3600)), """
            «ел 3 ч назад» — ровно тот вопрос, ради которого строку читают:
            пора ли кормить. Потолок не смеет гасить его вместе с 437 часами.
            """)
        #expect(строка.contains(Fmt.duration(5 * 3600)))
    }

    /// Находка того же кадра: `Fmt.shortDay` отдаёт сокращение месяца
    /// **со своей** точкой, а шаблон ставил свою — «с 17 сент.. Приложение».
    ///
    /// Проверяется запретом на две точки подряд, а не ожидаемой строкой:
    /// ожидаемая строка привязала бы сторож к русской формулировке,
    /// а дефект языконезависимый. Убрать точку из шаблона было нельзя —
    /// сокращение кончается точкой не во всех языках; снято структурой,
    /// дата больше не стоит последней.
    @Test("Объяснение тишины не даёт двух точек подряд")
    func объяснениеБезДвойнойТочки() throws {
        let s = Self.сигналы(мочаЧасовНазад: 434)
        let моча = try #require(s.lastUrine)
        let вердикт = VerdictEngine.evaluate(s)
        #expect(вердикт == .unknown(reason: .silence(since: моча)))

        let объяснение = VerdictEngine.explanation(вердикт, s)
        // Было что проверять: дата в строке есть, значит подстановка
        // случилась и запрет ниже осмыслен.
        #expect(объяснение.contains(Fmt.shortDay(моча)))
        #expect(объяснение.contains("..") == false, """
            «\(объяснение)» — две точки подряд: сокращение месяца принесло
            свою, а шаблон поставил вторую.
            """)
    }

    // MARK: - 6. Границы этого сторожа

    @Test("Границы: чего не проверяет набор про молчание о моче")
    func границыНабора() {
        // Стоит последним нарочно. Сторож видит арифметику и не видит,
        // что человек прочтёт, — а зелёный прогон трижды за день читали
        // как «проверено».
        //
        // **Правка 05.10: первая граница из трёх прожила семь часов
        // и врала пять дней.** Здесь было написано, что две строки
        // виджета — `private var` внутри `TogoWidgets` и недостижимы
        // «ни при какой формулировке». В день написания (28.09, 08:10)
        // это была правда. В 15:05 того же дня `10500d5` вынес их
        // в `TogoShared/Domain/SnapshotText.swift`, и граница стала
        // ложной — а читалась как действующая.
        //
        // > **Печать границы соврала в пользу бездействия.** Правило
        // > «сторож печатает границы последней строкой» работало:
        // > граница доехала до всех. Доехала устаревшая — и всякий,
        // > кто её читал, узнавал, что делать нечего. Поверхность
        // > перешла из «непроверяемой» в «проверяемую
        // > и непроверенную», и этого не заметил никто.
        //
        // Отсюда правило, которого у нас не было: **граница обязана
        // называть, что́ её снимет**, и называть поимённо. «Пока вход
        // не переделан» не находится ничем; «пока `sinceText` живёт
        // `private` в `TogoWidgets`» нашёл бы `grep` в день переезда.
        // Та же форма, что «комментарий „пока нет X“ обязан называть
        // X поимённо». Ниже границы переписаны так.
        //
        // НЕ проверено здесь:
        //
        // 1. ~~Две строки виджета недостижимы.~~ **Граница снята**
        //    `10500d5`: строки живут в `TogoShared`, сторож на них —
        //    `TogoTests/WidgetSilenceTextTests.swift` (05.10). Там же
        //    закрыто второе звено цепи: производитель снимка передаёт
        //    решение готовым, а не считает сам.
        // 2. **Что человек УВИДИТ — не проверено нигде, ни на одной
        //    из трёх поверхностей.** Проверено 05.10, и записанная
        //    ранее причина была не та: `-Сценарий silence` кладёт выход
        //    позавчера с `outcome = .both`, а `.both` считается мочой
        //    (`Diary.urineEvents`) — то есть `signals.urineSilence`
        //    там срабатывает. Не доезжает ВЕРДИКТ: событий два,
        //    `daysOfData` даёт 3, `minimumDaysOfData` равен 4, и `guard`
        //    про нехватку данных стоит выше тишины.
        //    *Снимет границу:* сценарий с историей от четырёх дней,
        //    у которого последние сутки пусты. Заводить отдельно
        //    от `silence`: добавить дни туда значило бы сдвинуть вердикт
        //    под живым UI-тестом `ТишинаДольшеСуток`.
        // 3. **Перевод этих строк не проверен здесь ничем.** Набор идёт
        //    на языке разработки. Состояние `fr` и `uk` не повторяется
        //    в этом комментарии нарочно: его знает
        //    `LocalizationCoverageTests`, и копия числа здесь протухла
        //    бы так же, как граница выше.
        //    *Снимет границу:* проверка, берущая ожидаемую строку
        //    из каталога, который собирается в бандл, — как сделано
        //    в `TogoUITests/ВосстановлениеПокупок.swift`.
        //
        // Ноль падений здесь значит «эти утверждения целы», а не
        // «ступень проверена».
        #expect(Bool(true))
    }
}
