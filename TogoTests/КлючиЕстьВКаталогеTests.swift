    @Test("Каждый ключ, который спрашивает код, есть в каталоге")
    func ключиКодаЗаведены() throws {
        let ключи = try Self.ключиКаталога()
        let нормализованные = Set(ключи.map(Self.нормализовать))

        // --- Рельсы. Все ПРЕЖДЕ сверки: пустой разбор иначе пройдёт
        // --- зелёным, и «ноль отсутствующих» будет про инструмент.
        #expect(ключи.count > 3000, """
            ключей в каталогах прочитано \(ключи.count) — разбор
            не состоялся. На 05.11.2026 их 4022.
            """)
        #expect(ключи.contains("только сегодня"), """
            положительный контроль не прошёл: заведомо живой ключ
            «только сегодня» в каталоге не найден — значит разбор
            каталога врёт, и ноль отсутствующих ничего не значит.
            """)
        #expect(!ключи.contains("ТакогоКлючаНетВовсеНигде"), """
            отрицательный контроль не прошёл: небывалый ключ
            «найден». Сверка отвечает утвердительно на что угодно.
            """)
        // Нормализация обязана РАЗЛИЧАТЬ спецификаторы, иначе она
        // склеила бы 87 групп и вернула ложный зелёный.
        let сLLD = ключи.filter { $0.contains("%lld") }.count
        let сAT = ключи.filter { $0.contains("%@") }.count
        #expect(сLLD >= 50 && сAT >= 50, """
            ключей с %lld — \(сLLD), с %@ — \(сAT). Обе группы обязаны
            быть непустыми: на этом стоит проверка, что нормализация
            не склеила каталог в одну строку.
            """)

        var отсутствуют: [Находка] = []
        var разобрано = 0
        var файловПрочитано = 0
        var пропущеноDEBUG = 0

        for место in Self.корни {
            let папка = Self.корневоеМесто(место)
            let обход = FileManager.default.enumerator(
                at: папка, includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift" else { continue }
                let сырой = try String(contentsOf: элемент, encoding: .utf8)
                let код = Self.безКомментариев(сырой)
                let подDEBUG = Self.строкиПодDEBUG(код)
                файловПрочитано += 1
                for (ключ, строка) in Self.литералыЛокализованных(в: код) {
                    if подDEBUG.contains(строка) {
                        пропущеноDEBUG += 1
                        continue
                    }
                    разобрано += 1
                    guard !нормализованные.contains(Self.нормализовать(ключ)) else { continue }
                    отсутствуют.append(Находка(
                        путь: Self.относительный(элемент),
                        строка: строка,
                        ключ: ключ.replacingOccurrences(
                            of: String(Self.заполнитель), with: "{}")))
                }
            }
        }

        #expect(файловПрочитано > 200, """
            файлов .swift прочитано \(файловПрочитано) — обход
            не состоялся. На 05.11.2026 их 254.
            """)
        #expect(разобрано >= 1000, """
            литералов `String(localized:)` разобрано \(разобрано) —
            разбор исходника не состоялся. На 05.11.2026 их 1102.
            """)
        // Освобождение под `#if DEBUG` обязано сработать и обязано
        // сработать НЕ НА ВСЁМ.
        #expect(пропущеноDEBUG > 0 && пропущеноDEBUG < разобрано / 4, """
            литералов под `#if DEBUG` — \(пропущеноDEBUG) из \(разобрано).
            Освобождение либо не сработало, либо освободило слишком
            многих.
            """)

        // Вердикт точный: адрес и ключ, а не число. «Пробелов 14»
        // не лечится, «ScheduleScreen.swift:67 → „Режим дня
        // не сохранился“» лечится за минуту.
        for находка in Self.поАдресам(отсутствуют) {
            Issue.record("""
                \(находка.путь):\(находка.строка) — ключа нет в каталоге:
                    «\(находка.ключ)»
                """)
        }
        #expect(отсутствуют.isEmpty, """
            ключей, которые код спрашивает, а в каталоге их нет:
            \(отсутствуют.count).

            Такая строка показывается ПО-РУССКИ на en, fr, uk, kk —
            и выглядит это намеренным, а не дырой. Лечится записью
            ключа в `TogoShared/Resources/Localizable.xcstrings`
            на четыре языка со статусом `needs_review`.

            Порога здесь нет нарочно: строка либо переведена, либо
            человек читает чужой язык.
            """)
    }

    /// Разбор читает код, а не прозу о нём.
    ///
    /// **Контроль, оплаченный за три минуты собственной ошибкой.**
    /// Первый заход разбора дал 15 адресов; пятнадцатым было
    /// `TodayScreen.swift:706`, где `String(localized: "Он")` стоит
    /// в комментарии, объясняющем **снятый** дефект.
    ///
    /// Обе стороны снимаются одним заходом нарочно: разбор,
    /// возвращающий пустоту всегда, прошёл бы половину про прозу
    /// и провалил вторую.
    @Test("Разбор вырезает прозу и видит живой код")
    func разборВырезаетПрозу() {
        let подделка = #"""
            // Здесь стояло `?? String(localized: "Он")`, и у суки
            // без клички карточка говорила «Он чаще просит спокойно»
            /* И в блочном тоже: String(localized: "Она") */
            let живое = String(localized: "Режим дня не сохранился")
            let сИнтерполяцией = String(localized: "Запас \(остаток)")
            """#
        let найдено = Self.литералыЛокализованных(в: Self.безКомментариев(подделка))
        let ключи = найдено.map(\.ключ)

        #expect(!ключи.contains("Он"), """
            разбор прочитал прозу: ключ «Он» взят из комментария.
            Сторож в таком виде запрещает писать про ошибку в файле,
            где её уже не совершают.
            """)
        #expect(!ключи.contains("Она"), """
            разбор прочитал блочный комментарий: ключ «Она» взят
            из `/* … */`.
            """)
        #expect(ключи.contains("Режим дня не сохранился"), """
            разбор не увидел живой `String(localized:)` — он возвращает
            пустоту, и проверка про прозу выше зелена по слепоте,
            а не по правильности.
            """)
        #expect(ключи.contains("Запас \(Self.заполнитель)"), """
            литерал с интерполяцией не приведён к заполнителю:
            \(ключи). Без этого всякая строка с `\\(…)` считалась бы
            отсутствующей.
            """)
    }

    /// Нормализация склеивает спецификаторы между собой и не склеивает
    /// разные строки.
    ///
    /// Вторая половина обязательна: нормализация, возвращающая пустоту,
    /// прошла бы первую и объявила бы каталог полным на любом ключе.
    @Test("Нормализация различает спецификаторы, но не склеивает строки")
    func нормализацияРазличает() {
        let п = String(Self.заполнитель)

        #expect(Self.нормализовать("Прошлые схемы · %lld") == "Прошлые схемы · \(п)")
        #expect(Self.нормализовать("Прошлые схемы · %@") == "Прошлые схемы · \(п)")
        #expect(Self.нормализовать("Оставить %1$@ из %2$lld") == "Оставить \(п) из \(п)")
        #expect(Self.нормализовать("Вес %.1f кг") == "Вес \(п) кг")

        // `%%` — это процент. Иначе «на 20%% меньше нормы» склеилось бы
        // с «на %lld меньше нормы», и сторож объявил бы ключ
        // существующим.
        #expect(Self.нормализовать("на 20%% меньше") == "на 20% меньше")
        #expect(Self.нормализовать("на %lld%% меньше") == "на \(п)% меньше")

        // Одинокий процент в прозе спецификатором не является.
        #expect(Self.нормализовать("100% собака") == "100% собака")

        // Разные строки остаются разными.
        #expect(Self.нормализовать("Запас %@") != Self.нормализовать("Запас"))
        #expect(Self.нормализовать("Дальше · через %@") != Self.нормализовать("Дальше · через"))
    }

    // MARK: - Мелочи пути

    private static func корневоеМесто(_ имя: String) -> URL {
        корневаяПапка().appendingPathComponent(имя)
    }

    /// Путь от корня репозитория.
    ///
    /// `standardizedFileURL` обязателен: у `/tmp` в worktree-прогоне
    /// приезжает `/private/tmp`, и ключ пути не сложился бы — дефект,
    /// которого в рабочем дереве не бывает по устройству (разбор
    /// у `LocalizationDebtTests.относительныйПуть`).
    private static func относительный(_ файл: URL) -> String {
        let корень = корневаяПапка().standardizedFileURL.path
        let путь = файл.standardizedFileURL.path
        guard путь.hasPrefix(корень) else { return файл.lastPathComponent }
        return String(путь.dropFirst(корень.count).drop(while: { $0 == "/" }))
    }

    private static func поАдресам(_ находки: [Находка]) -> [Находка] {
        находки.sorted { ($0.путь, $0.строка) < ($1.путь, $1.строка) }
    }
