private extension Character {
    /// Кириллица, включая `ё`/`Ё` и украинские буквы.
    ///
    /// Диапазон взят шире русского нарочно: у проекта четыре языка,
    /// и украинский `і` вне `0x0410...0x044F`.
    var кириллическая: Bool {
        guard let скаляр = unicodeScalars.first else { return false }
        return (0x0400...0x04FF).contains(Int(скаляр.value))
    }
