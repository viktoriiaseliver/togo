/// Ключ, который спрашивает код, заведён в каталоге.
///
/// **Третья ось локализации, и две существующие этот класс не видят
/// по устройству.** Предметы у них разные, и это не дублирование:
///
/// ```
/// LocalizationCoverageTests.пробеловНет()      ключ В КАТАЛОГЕ переведён
///                                              на каждый язык
/// LocalizationDebtTests.долгЭкрановНеРастёт()  литерал уехал в `String`
///                                              мимо каталога — храповик
///                                              ПО ФАЙЛАМ
/// этот сторож                                  КОД СПРАШИВАЕТ КЛЮЧ,
///                                              КОТОРОГО В КАТАЛОГЕ НЕТ
/// ```
///
/// Авторы первых двух сами записали, что дыра остаётся, —
/// `LocalizationCoverageTests.swift:1455-1460`: «`пробеловНет()`
/// проверяет только те ключи, что УЖЕ лежат, а `долгЭкрановНеРастёт()`
/// считает литерал в `LocalizedStringKey` здоровым независимо
/// от каталога».
///
/// > **Пробел виден как дыра, а отсутствующий ключ — как полнота.**
/// > Поэтому находят такое каждый раз случайно и каждый раз заново.
///
/// Цена измерена дважды и обе записи в журнале. 05.11.2026 нашлись
/// `покормлено в %@` и `Выход около %@` — оба живой
/// `String(localized:)`, оба показывались по-русски на всех четырёх
/// языках, и оба были **старше** той работы, в которой их случайно
/// заметили. `Tools/долг-локализации.py` их тоже не видит: он считает
/// `needs_review` и `new` среди **лежащих** ключей.
///
/// ## Почему оракул — КАТАЛОГ, а не бандл
///
/// Первая редакция плана этой работы ставила осью `Bundle.main`:
/// в нём лежит ровно то, что увидит человек, и он строже каталога —
/// ловит ещё и «ключ есть, а в сборку не попал».
///
/// **Ось сменена замером, который уже лежал в репозитории**
/// (`LocalizationCoverageTests.swift:1558-1576`): состав бандла
/// не одинаков у разных сборок одного кода. Четыре сборки 05.10.2026,
/// `en.lproj` был в одной:
///
/// ```
/// DerivedData                       нет
/// dd                                ЕСТЬ
/// dd-verify (каталог стёрт)         нет
/// архив 28.09                       нет
/// ```
///
/// Догадку «чистая против инкрементальной» та запись опровергла
/// третьей сборкой. Значит сторож на бандле краснел бы **то здесь,
/// то там, без всякой правки кода** — а это наш класс «условие,
/// привязанное к инструменту, меняет знак», и он учит не верить
/// красному.
///
/// Каталог же лежит в git, детерминирован и является источником
/// правды проекта. Красное на нём — настоящий долг.
///
/// **Граница названа вслух, потому что она остаётся:** этот сторож
/// отвечает «ключ ЗАВЕДЁН», а не «ключ ОТГРУЖЕН». Класс «в каталоге
/// есть, в `.strings` не доехало» он не видит, и закрыть его нужно
/// отдельной осью по бандлу — с рельсой, которая объявляет
/// непрочитанный бандл красным, а не тихо зелёным.
///
/// ## Ось нормализована, и это замер, а не осторожность
///
/// Наивная склейка «интерполяция = `%@`» даёт ложный красный на всяком
/// `\(Int)`. Замер по каталогу на 05.11.2026:
///
/// ```
/// нормализованных групп                                      3947
/// групп, где ВСЕ ключи несут %lld (наивное %@ → ложь)          87
/// ключей с %lld / с %@                                    161 / 407
/// ```
///
/// Поэтому и ключ каталога, и литерал кода приводятся к одному
/// заполнителю: `%lld`, `%@`, `%1$@`, `%.1f` и `\(x)` становятся
/// одним знаком. `%%` при этом защищается — иначе «100%% влажности»
/// превратилось бы в заполнитель.
///
/// Цена обратной ошибки тоже названа: без нормализации сторож вернул
/// бы 87 ложных красных, и его бы выключили в тот же день.
///
/// ## Комментарии вырезаются ДО разбора, и это отдельный контроль
///
/// Правило есть в `~/Projects/.claude/rules/сторожа-и-тесты.md`,
/// и автор этого файла наступил на него за три минуты. Первый заход
/// разбора дал **15** адресов, пятнадцатым было
/// `TodayScreen.swift:706` — а там **проза**:
///
/// ```swift
/// // Здесь стояло `?? String(localized: "Он")`, и у суки без клички
/// // карточка говорила «Он чаще просит спокойно»
/// ```
///
/// > **Сторож, не вырезающий комментарии, запрещает писать про ошибку
/// > в файле, где её уже не совершают.** Вырезание — не оптимизация
/// > разбора, а условие его честности.
///
/// Поэтому у вырезания свой тест (`разборВырезаетПрозу`), и он снимает
/// обе стороны одним заходом: проза найтись не должна, живой код —
/// должен. Порознь они бесполезны: разбор, возвращающий пустоту всегда,
/// прошёл бы половину про прозу и провалил вторую.
///
/// ## Приёмка разбора: два замера разными инструментами, 05.11.2026
///
/// Сторож писался при занятой машине (load 333 на подъёме, четыре
/// чужих `xcodebuild`), и прогона схемы у него на тот час не было.
/// Поэтому разбор принят **автономно и дважды** — независимой
/// реализацией на Python и этой же логикой, собранной в автономный
/// Swift-прогон **из этого файла текстом**. Копии не возникло:
/// две копии разошлись бы молча.
///
/// ```
///                            Python      Swift (эта логика)
/// ключей в каталогах           4022            4022
/// нормализованных групп        3947            3947
/// различимость %lld / %@    161 / 407       161 / 407
/// файлов .swift                 254             254
/// литералов localized:         1102            1102
/// АДРЕСОВ БЕЗ КЛЮЧА              14              14   ← дословно те же
/// ```
///
/// Расхождение было одно, и оно разобрано, а не списано: «пропущено
/// под `#if DEBUG`» — 14 против 7. Python считал оба вида литерала
/// (`String(localized:)` и `Text(`), Swift — только первый, 7 + 7.
/// Установлено чтением кода замерщика, а не догадкой.
///
/// > **Два своих замера, сошедшиеся до адреса, доказывают, что разбор
/// > не зависит от языка, на котором написан.** Прогон схемы остаётся
/// > обязательным, но он проверит уже другое: что сторож доехал
/// > до набора.
///
/// Доказательство красноты на старом коде лежит в истории: сторож
/// закоммичен ОТДЕЛЬНО от ключей, поэтому
/// `git worktree add /tmp/<имя> <коммит сторожа>` даёт дерево,
/// на котором он обязан назвать те самые 14 адресов — и это
/// проверяется в любой момент, а не только сегодня.
@Suite("Ключи, которые спрашивает код, заведены в каталоге")
struct КлючиЕстьВКаталогеTests {

    /// Корни продуктового кода. `TogoTests`/`TogoUITests` сюда
    /// не входят: тест вправе подавать ключ, которого нет, — он для
    /// этого и написан.
    private static let корни = ["Togo", "TogoShared", "TogoWidgets"]

    private static func корневаяПапка() -> URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    // MARK: - Каталог

    /// Все живые каталоги проекта, а не один.
    ///
    /// Способ взят у `LocalizationCoverageTests.каталоги()` намеренно:
    /// там он оплачен замером 23.09.2026, когда счёт по одному
    /// `Localizable` сказал «язык покрыт» при русских фразах Siri
    /// в `AppShortcuts.xcstrings`.
    private static func файлыКаталогов() -> [URL] {
        var найдено: [URL] = []
        for место in корни {
            let обход = FileManager.default.enumerator(
                at: корневаяПапка().appendingPathComponent(место),
                includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "xcstrings" else { continue }
                найдено.append(элемент)
            }
        }
        return найдено.sorted { $0.path < $1.path }
    }

    private static func ключиКаталога() throws -> Set<String> {
        var ключи: Set<String> = []
        for файл in файлыКаталогов() {
            let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: файл))
                as? [String: Any]
            for ключ in (корень?["strings"] as? [String: Any] ?? [:]).keys {
                ключи.insert(ключ)
            }
        }
        return ключи
    }

    // MARK: - Нормализация спецификаторов

    /// Заполнитель на месте любого спецификатора или интерполяции.
    ///
    /// Знак выбран непечатный, чтобы он не мог встретиться в живой
    /// строке и случайно склеить два разных ключа.
    static let заполнитель: Character = "\u{0}"

    /// `%lld`, `%@`, `%1$@`, `%.1f` → один заполнитель. `%%` остаётся
    /// процентом.
    ///
    /// Разбор посимвольный, а не регуляркой, по причине из общего
    /// свода: `NSRegularExpression` на кириллице и экранировании даёт
    /// свои сюрпризы, а грамматика printf коротка и проверяема глазом.
    static func нормализовать(_ строка: String) -> String {
        var итог = ""
        var i = строка.startIndex
        while i < строка.endIndex {
            guard строка[i] == "%" else {
                итог.append(строка[i])
                i = строка.index(after: i)
                continue
            }
            var j = строка.index(after: i)
            // `%%` — это процент, а не спецификатор.
            if j < строка.endIndex, строка[j] == "%" {
                итог.append("%")
                i = строка.index(after: j)
                continue
            }
            // Позиционный префикс `1$`.
            var позиция = j
            while позиция < строка.endIndex, строка[позиция].isNumber {
                позиция = строка.index(after: позиция)
            }
            if позиция < строка.endIndex, строка[позиция] == "$" {
                j = строка.index(after: позиция)
            }
            // Флаги, ширина, точность.
            while j < строка.endIndex, "-+ #0".contains(строка[j]) {
                j = строка.index(after: j)
            }
            while j < строка.endIndex, строка[j].isNumber {
                j = строка.index(after: j)
            }
            if j < строка.endIndex, строка[j] == "." {
                j = строка.index(after: j)
                while j < строка.endIndex, строка[j].isNumber {
                    j = строка.index(after: j)
                }
            }
            // Длина.
            for длина in ["ll", "hh", "l", "h", "z", "q", "t", "j"] {
                if строка[j...].hasPrefix(длина) {
                    j = строка.index(j, offsetBy: длина.count)
                    break
                }
            }
            guard j < строка.endIndex, "diouxXeEfgGaAcspn@".contains(строка[j]) else {
                // Не спецификатор — одинокий процент в прозе.
                итог.append("%")
                i = строка.index(after: i)
                continue
            }
            итог.append(заполнитель)
            i = строка.index(after: j)
        }
        return итог
    }

    // MARK: - Разбор исходника

    /// Код без комментариев, с сохранением длины и номеров строк.
    ///
    /// Посимвольно слева направо, с учётом строковых литералов:
    /// построчное «сперва `//`» съедает `https://`, а «сперва `/*`» —
    /// файл с первого доккомментария. На месте комментария остаются
    /// пробелы и переводы строк, чтобы номер строки не сдвинулся.
    static func безКомментариев(_ код: String) -> String {
        var итог = ""
        итог.reserveCapacity(код.count)
        var i = код.startIndex
        var вСтроке = false
        var многострочная = false

        func дальшеЕсть(_ образец: String, от место: String.Index) -> Bool {
            код[место...].hasPrefix(образец)
        }

        while i < код.endIndex {
            let c = код[i]
            if вСтроке {
                if c == "\\" {
                    итог.append(c)
                    let следующий = код.index(after: i)
                    if следующий < код.endIndex {
                        итог.append(код[следующий])
                        i = код.index(after: следующий)
                        continue
                    }
                    i = следующий
                    continue
                }
                if многострочная, дальшеЕсть("\"\"\"", от: i) {
                    итог.append("\"\"\"")
                    i = код.index(i, offsetBy: 3)
                    вСтроке = false
                    многострочная = false
                    continue
                }
                if !многострочная, c == "\"" {
                    вСтроке = false
                }
                итог.append(c)
                i = код.index(after: i)
                continue
            }
            if дальшеЕсть("\"\"\"", от: i) {
                итог.append("\"\"\"")
                i = код.index(i, offsetBy: 3)
                вСтроке = true
                многострочная = true
                continue
            }
            if c == "\"" {
                итог.append(c)
                i = код.index(after: i)
                вСтроке = true
                continue
            }
            if дальшеЕсть("//", от: i) {
                while i < код.endIndex, код[i] != "\n" {
                    итог.append(" ")
                    i = код.index(after: i)
                }
                continue
            }
            if дальшеЕсть("/*", от: i) {
                var глубина = 1
                итог.append("  ")
                i = код.index(i, offsetBy: 2)
                while i < код.endIndex, глубина > 0 {
                    if дальшеЕсть("/*", от: i) {
                        глубина += 1
                        итог.append("  ")
                        i = код.index(i, offsetBy: 2)
                    } else if дальшеЕсть("*/", от: i) {
                        глубина -= 1
                        итог.append("  ")
                        i = код.index(i, offsetBy: 2)
                    } else {
                        итог.append(код[i] == "\n" ? "\n" : " ")
                        i = код.index(after: i)
                    }
                }
                continue
            }
            итог.append(c)
            i = код.index(after: i)
        }
        return итог
    }

    /// Тело интерполяции: место, с которого продолжать разбор.
    ///
    /// Скобки считаются с учётом вложенных литералов — внутри
    /// `\(f(")"))` закрывающая скобка в кавычках скобкой не является.
    /// Способ тот же, что у `LocalizationDebtTests.телоИнтерполяции`.
    private static func послеИнтерполяции(_ код: String, от открывающая: String.Index) -> String.Index {
        var глубина = 0
        var вСтроке = false
        var предыдущий: Character = " "
        var j = открывающая
        while j < код.endIndex {
            let c = код[j]
            if вСтроке {
                if c == "\"", предыдущий != "\\" { вСтроке = false }
            } else if c == "\"" {
                вСтроке = true
            } else if c == "(" {
                глубина += 1
            } else if c == ")" {
                глубина -= 1
                if глубина == 0 { return код.index(after: j) }
            }
            предыдущий = c
            j = код.index(after: j)
        }
        // Незакрытая интерполяция — строка оборвана. Остаток отдаём
        // целиком: пропустить молча значило бы ослепнуть ровно там,
        // где разбор уже не понимает, что читает.
        return код.endIndex
    }

    struct Находка: Sendable, Hashable {
        let путь: String
        let строка: Int
        let ключ: String
    }

    /// Литералы, уехавшие в `String(localized:)`, с адресами.
    ///
    /// **Почему разбор свой, а не `LocalizationDebtTests.русскиеЛитералы`.**
    /// Та машинка возвращает ЧИСЛО — она храповик по файлам, и адрес
    /// литерала ей не нужен. Здесь вердикт обязан быть точным
    /// (`файл:строка` + ключ), иначе «пробелов 14» не лечится,
    /// а «`ScheduleScreen.swift:67` → „Режим дня не сохранился“»
    /// лечится за минуту. Устройство разбора взято оттуда дословно:
    /// интерполяция читается как КОД, а не проза.
    static func литералыЛокализованных(в код: String) -> [(ключ: String, строка: Int)] {
        var найдено: [(String, Int)] = []
        var i = код.startIndex
        var номер = 1

        /// Переносы в пропущенном куске обязаны попасть в счёт.
        ///
        /// Иначе номер съезжает на всякой МНОГОСТРОЧНОЙ интерполяции —
        /// а вердикт с неверной строкой хуже отсутствия вердикта:
        /// он посылает читать чужое место и выглядит точным.
        func учестьПереносы(с начало: String.Index, по конец: String.Index) {
            guard начало < конец else { return }
            номер += код[начало..<конец].filter(\.isNewline).count
        }

        while i < код.endIndex {
            if код[i] == "\n" { номер += 1 }
            if код[i] != "\"" {
                i = код.index(after: i)
                continue
            }
            // Многострочный литерал: ключом он не бывает, пропускаем
            // целиком вместе с его переносами.
            if код[i...].hasPrefix("\"\"\"") {
                var j = код.index(i, offsetBy: 3)
                while j < код.endIndex, !код[j...].hasPrefix("\"\"\"") {
                    if код[j] == "\n" { номер += 1 }
                    j = код.index(after: j)
                }
                i = j < код.endIndex ? код.index(j, offsetBy: 3) : код.endIndex
                continue
            }

            let началоЛитерала = i
            let номерЛитерала = номер
            var куски = ""
            var j = код.index(after: i)
            var закрыт = false
            while j < код.endIndex {
                let c = код[j]
                if c == "\\" {
                    let следующий = код.index(after: j)
                    guard следующий < код.endIndex else { break }
                    if код[следующий] == "(" {
                        куски.append(Self.заполнитель)
                        let после = послеИнтерполяции(код, от: следующий)
                        учестьПереносы(с: следующий, по: после)
                        j = после
                        continue
                    }
                    switch код[следующий] {
                    case "n": куски.append("\n")
                    case "t": куски.append("\t")
                    default: куски.append(код[следующий])
                    }
                    j = код.index(after: следующий)
                    continue
                }
                if c == "\"" {
                    закрыт = true
                    j = код.index(after: j)
                    break
                }
                // Перенос внутри односимвольного литерала — он оборван.
                if c == "\n" { break }
                куски.append(c)
                j = код.index(after: j)
            }

            if закрыт, куски.contains(where: \.кириллическая) {
                let началоОкна = код.index(
                    началоЛитерала,
                    offsetBy: -min(200, код.distance(from: код.startIndex, to: началоЛитерала)))
                let слева = код[началоОкна..<началоЛитерала]
                    .trimmingCharacters(in: .whitespacesAndNewlines)
                if слева.hasSuffix("localized:") {
                    найдено.append((куски, номерЛитерала))
                }
            }
            i = j
        }
        return найдено
    }

    /// Номера строк, лежащих внутри `#if DEBUG`, по вложенности.
    ///
    /// Важно считать вложенность, а не «файл начинается с `#if`»:
    /// освобождение, освобождающее всех, — это выключенный сторож.
    static func строкиПодDEBUG(_ код: String) -> Set<Int> {
        var под: Set<Int> = []
        var стек: [Bool] = []
        var глубинаDEBUG = 0
        for (индекс, строка) in код.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
            let голая = строка.trimmingCharacters(in: .whitespaces)
            if голая.hasPrefix("#if") {
                let этоDEBUG = голая.contains("DEBUG")
                стек.append(этоDEBUG)
                if этоDEBUG { глубинаDEBUG += 1 }
            } else if голая.hasPrefix("#endif"), let последний = стек.popLast() {
                if последний { глубинаDEBUG -= 1 }
            }
            if глубинаDEBUG > 0 { под.insert(индекс + 1) }
        }
        return под
    }

