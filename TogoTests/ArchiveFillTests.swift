import Foundation
import Testing
@testable import Togo

/// Поле снимка, которое ОБЪЯВЛЕНО и не заполняется, — ложная зелень.
///
/// **Заведено 07.10.2026 после предсказания, которое дождалось.** В моём
/// же перечне паритета (`docs/паритет-архива.md`) первым пунктом раздела
/// «чего этот замер не видит» стояло: «поле есть в снимке и НЕ
/// ЗАПОЛНЯЕТСЯ при сборке». Через несколько часов это материализовалось
/// на живых полях медкнижки — `vaccineBatch`, `vaccineValidUntil`,
/// `prescriptionNumber` были дописаны в структуру и не попали
/// в сборщик.
///
/// ```
/// было    поля нет в снимке         сторож паритета КРАСНЫЙ, данные не едут
/// стало   поле есть, не заполнено   сторож паритета ЗЕЛЁНЫЙ, данные не едут
/// ```
///
/// > **Краснота «поля нет» честна. Зелень «поле есть, не заполнено» —
/// > ложна.** И переход из первого состояния во второе выглядит
/// > как починка.
///
/// `ArchiveParityTests` этого не ловит и пишет о себе прямо (`:312`):
/// он сверяет имена, а не заполнение. Граница была напечатана и
/// прочитана не была — ни мной, ни соседом у другого сторожа.
///
/// ## Почему два направления, а не одно
///
/// Форму назвал `togo-05`, заплатив за неё дважды в тот же день:
///
/// ```
/// ноль от grep         отвечает «нет такой строки», а не «нет упоминания»
/// prescriptionNumber   совпадёт и с prescriptionNumberOld
/// совпадение имени     не значит чтения ЭТОГО поля: у чужого свойства имя то же
/// ```
///
/// Поэтому направления разделены — «объявлено и не заполнено»
/// и «заполнено и не читается» это РАЗНЫЕ ответы, и один вопрос на два
/// дефекта дал бы одну новость на две причины.
///
/// ```
/// записано    метка `<поле>:` на первом уровне вызова `XSnapshot(`   ← ПРОВЕРЯЕТСЯ
/// прочитано   поле вернулось в модель                               ← НЕ проверяется
/// ```
///
/// **Отправлено одно направление из двух, и это измеренное решение,
/// а не недоделка.** Второе в первой редакции дало 64 ложных из 167:
/// восстановление возвращает значения через инициализаторы, а не
/// присваиванием, и поля, пришедшие конструктором, разбору невидимы.
/// Разбор присваиваний оставлен в файле и проверен порогом — он
/// понадобится тому, кто закроет второе направление; что именно его
/// закроет, названо у теста `границаОбратногоНаправления`.
@Suite("Заполнение снимков архива")
struct ArchiveFillTests {

    /// Поля, которых в сборщике нет НАРОЧНО — с причиной у каждого.
    /// Пустая причина неотличима от дыры, поэтому требуется длина.
    static let незаполняетсяНамеренно: [String: String] = [
        // Версия формата ставится самим архивом при сборке, а не
        // переносится из модели: у снимка её нет в модели вовсе.
        "BackupArchive.formatVersion": "ставится сборщиком, в модели такого поля нет",
        "BackupArchive.createdAt": "время снятия архива, а не данные собаки",
        "BackupArchive.appVersion": "версия приложения на момент снятия",
    ]

    /// Снимков в архиве не меньше этого — иначе разбор ослеп.
    /// Минимум, а не равенство: равенство краснеет на честном росте,
    /// а вопрос у порога один — «разбор состоялся?».
    static let снимковНеМенее = 16
    /// Меток, собранных из сборщика, не меньше этого.
    static let метокНеМенее = 120
    /// Присваиваний, собранных из восстановления, не меньше этого.
    static let присваиванийНеМенее = 80

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .resolvingSymlinksInPath()
    }

    private static func текст(_ путь: String) throws -> String {
        try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
    }

    /// Поля каждой структуры снимка: имя структуры → имена полей.
    ///
    /// Разбор по скобкам, а не по строке: внутри `BackupArchive` живут
    /// вложенные структуры, и счёт по отступу сломался бы на первой
    /// же правке форматирования.
    private static func поляСнимков(_ код: String) -> [String: Set<String>] {
        var итог: [String: Set<String>] = [:]
        let строки = код.components(separatedBy: .newlines)
        for (начало, строка) in строки.enumerated() {
            guard let имя = строка.firstMatch(структура: "struct") else { continue }
            var глубина = 0
            var поля: Set<String> = []
            var начал = false
            for i in начало..<строки.count {
                let s = строки[i].безКомментария
                let открыто = s.filter { $0 == "{" }.count
                let закрыто = s.filter { $0 == "}" }.count
                if глубина == 1, let поле = s.firstMatch(поле: ()) { поля.insert(поле) }
                глубина += открыто - закрыто
                if открыто > 0 { начал = true }
                if начал, глубина <= 0 { break }
            }
            итог[имя] = поля
        }
        return итог
    }

    /// Метки на ПЕРВОМ уровне каждого вызова `XSnapshot(`.
    ///
    /// Уровень важен: внутри вызова бывают вложенные (`doses:
    /// medication.doses.map { DoseSnapshot(...) }`), и их метки
    /// принадлежат другому снимку. Считать их своими значило бы
    /// ошибиться в сторону полноты — то есть в сторону, которая
    /// выглядит безопаснее и не является.
    private static func меткиСборщика(_ код: String) -> [String: Set<String>] {
        var итог: [String: Set<String>] = [:]
        let символы = Array(код)
        var i = 0
        while i < символы.count {
            guard символы[i] == "(" else { i += 1; continue }
            // Имя перед скобкой.
            var j = i - 1
            var имя = ""
            while j >= 0, символы[j].isLetter || символы[j].isNumber {
                имя = String(символы[j]) + имя
                j -= 1
            }
            guard имя.hasSuffix("Snapshot") else { i += 1; continue }
            var глубина = 0
            var буфер = ""
            var метки: Set<String> = []
            var k = i
            while k < символы.count {
                let c = символы[k]
                if c == "(" { глубина += 1 }
                if c == ")" {
                    глубина -= 1
                    if глубина == 0 { break }
                }
                if глубина == 1 {
                    if c == ":" {
                        // Берётся ПОСЛЕДНИЙ идентификатор перед `:`,
                        // а не весь буфер: иначе `dog.clinicName:`
                        // склеивается в `DogclinicName`. Первая редакция
                        // так и сделала, и в списке появилось поле,
                        // которого нет нигде.
                        let слово = String(
                            буфер.reversed().prefix { $0.isLetter || $0.isNumber }.reversed()
                        )
                        if !слово.isEmpty { метки.insert(слово) }
                        буфер = ""
                    } else if c == "," || c == "\n" {
                        буфер = ""
                    } else {
                        буфер.append(c)
                    }
                }
                k += 1
            }
            итог[имя, default: []].formUnion(метки)
            // НЕ `i = k`. Вложенные вызовы живут ВНУТРИ внешнего
            // (`careTasks: dog.careTasks.map { CareTaskSnapshot(…) }`),
            // и прыжок за закрывающую скобку съедал их целиком.
            // Первая редакция так и делала: меток вышло 65 вместо 167,
            // и сторож объявил «не заполняется» про 131 поле из 131 —
            // круглое число, симптом разбора, а не мира.
            i += 1
        }
        return итог
    }

    /// Имена полей, которым при восстановлении присваивают значение.
    private static func присваивания(_ код: String) -> Set<String> {
        var итог: Set<String> = []
        for строка in код.components(separatedBy: .newlines) {
            let s = строка.безКомментария
            guard let знак = s.range(of: " = ") else { continue }
            let слева = s[s.startIndex..<знак.lowerBound]
                .trimmingCharacters(in: .whitespaces)
            let части = слева.split(separator: ".")
            guard части.count >= 2, let поле = части.last else { continue }
            итог.insert(String(поле))
        }
        return итог
    }

    // MARK: - 1. Проверка, что проверять было что

    @Test("Разбор сборщика и восстановления состоялся")
    func былоЧтоПроверять() throws {
        let снимки = Self.поляСнимков(try Self.текст("TogoShared/Domain/BackupArchive.swift"))
            .filter { $0.key.hasSuffix("Snapshot") }
        let сборщик = try Self.текст("TogoShared/Domain/Backup.swift")
        let метки = Self.меткиСборщика(сборщик).values.reduce(into: Set<String>()) {
            $0.formUnion($1)
        }
        let чтение = Self.присваивания(сборщик)

        #expect(снимки.count >= Self.снимковНеМенее, """
            разобрано структур снимка \(снимки.count), а их не меньше
            \(Self.снимковНеМенее). Разбор ослеп — список потерянных
            полей ниже читать нельзя: пустой он и у исправного кода.
            """)
        #expect(метки.count >= Self.метокНеМенее, """
            собрано меток сборщика \(метки.count) при пороге
            \(Self.метокНеМенее) — разбор вызовов `XSnapshot(` ослеп.
            """)
        #expect(чтение.count >= Self.присваиванийНеМенее, """
            собрано присваиваний \(чтение.count) при пороге
            \(Self.присваиванийНеМенее) — разбор восстановления ослеп.
            """)
    }

    // MARK: - 2. Поле снимка ложится в архив

    @Test("Каждое поле снимка заполняется сборщиком")
    func поляЗаполняются() throws {
        let снимки = Self.поляСнимков(try Self.текст("TogoShared/Domain/BackupArchive.swift"))
        let метки = Self.меткиСборщика(try Self.текст("TogoShared/Domain/Backup.swift"))
        var пустые: [String] = []
        for (снимок, поля) in снимки.sorted(by: { $0.key < $1.key })
        where снимок.hasSuffix("Snapshot") {
            for поле in поля.sorted() {
                let ключ = "\(снимок).\(поле)"
                if Self.незаполняетсяНамеренно[ключ] != nil { continue }
                if метки[снимок]?.contains(поле) == true { continue }
                пустые.append(ключ)
            }
        }
        #expect(пустые.isEmpty, """
            поле объявлено в снимке и НЕ ЗАПОЛНЯЕТСЯ сборщиком: \(пустые).
            Сторож паритета на это зелёный — он сверяет имена, а не
            заполнение, и пишет это о себе сам. Значит состояние хуже
            прежнего: краснота «поля нет» была честной, зелень «поле
            есть, не заполнено» — ложная.
            Либо заполни в `Backup.swift`, либо впиши в
            `незаполняетсяНамеренно` С ПРИЧИНОЙ.
            """)
    }

    // MARK: - 3. Второе направление НЕ ПРОВЕРЯЕТСЯ, и вот замер

    /// **«Заполняется и не читается» этот сторож не спрашивает, и это
    /// решение, а не недосмотр.** Первая редакция спрашивала — по
    /// присваиваниям `<что-то>.<поле> =` в восстановлении — и дала
    /// **64 ложных** из 167 меток.
    ///
    /// Причина измерена: восстановление возвращает значения **через
    /// инициализаторы** (`CareTask(title: care.title, detail: …)`,
    /// `Dog(name:weightKg:)`), а не присваиванием. Поля, пришедшие
    /// конструктором, для такого разбора невидимы — и каждое выглядело
    /// бы потерянным.
    ///
    /// > **Сторож, который кричит шестьдесят четыре раза, читать
    /// > перестанут — а это хуже отсутствующего.** У нас это оплачено
    /// > семьюдесятью девятью находками на Timer.
    ///
    /// Поэтому направление снято до формы, которая различает
    /// конструктор и присваивание. Что его закроет, названо поимённо,
    /// чтобы следующий не искал: метки вызовов моделей
    /// (`CareTask(`, `Dog(`, `Medication(`…) в `restore`, собранные тем
    /// же разбором по скобкам, плюс присваивания — и объединение,
    /// а не одно из двух.
    ///
    /// Что держит эту дыру сейчас: тест `togo-05` «Девять полей шага 0
    /// переезжают по значению» — он гоняет круг `archive → encode →
    /// decode → restore` и сверяет значения поимённо. Он сильнее
    /// текстового сторожа и слабее его же по охвату: девять полей
    /// против ста шестидесяти семи.
    @Test("Граница: обратное направление не проверяется, и почему")
    func границаОбратногоНаправления() {
        #expect(Self.снимковНеМенее > 0)
    }

    /// Границы — печатает сам сторож, а не помнит читатель.
    @Test("Границы: сторож смотрит текст, а не прогон")
    func границы() {
        // Он НЕ видит: что подставлено верное значение (`title: $0.detail`
        // пройдёт), что поле восстановлено той же записи, что снимок
        // вообще попал в файл. Для этого нужен круг archive → decode →
        // restore на значениях — он есть у `togo-05` в тесте девяти
        // полей шага 0, и этот сторож его не заменяет.
        #expect(Bool(true))
    }
}

private extension String {
    var безКомментария: String { components(separatedBy: "//")[0] }

    func firstMatch(структура ключ: String) -> String? {
        let части = trimmingCharacters(in: .whitespaces).split(separator: " ")
        guard let i = части.firstIndex(of: Substring(ключ)), i + 1 < части.count else {
            return nil
        }
        return String(части[i + 1].prefix { $0.isLetter || $0.isNumber })
    }

    /// Имя поля из строки объявления.
    ///
    /// **Атрибуты срезаются, а не запрещаются.** `@Attribute(.externalStorage)
    /// var image: Data?` стоит в одной строке, и разбор, требующий
    /// начала с `var`, такое поле не видит. Это ТРЕТИЙ раз за проект,
    /// когда тот же атрибут обманывает разбор исходника: первые два
    /// стоили снимка схемы и неоткрывшегося хранилища. Предупредил
    /// `togo-05` 07.10.2026, и предупреждение пришло раньше дефекта —
    /// у структур снимка таких полей сегодня нет ни одного, то есть
    /// сторож был слеп **потенциально**.
    ///
    /// > Разбор, который требует начала строки, ломается об атрибут,
    /// > стоящий перед объявлением, — и ответ у него синтаксически
    /// > правильный. Порог «нашёл не меньше N» такое не ловит: поле
    /// > одно, а порог про объём.
    func firstMatch(поле: ()) -> String? {
        var s = trimmingCharacters(in: .whitespaces)
        while s.hasPrefix("@") {
            // Срезается по СКОБКАМ, а не по первому пробелу: у атрибута
            // пробел бывает внутри — `@Relationship(deleteRule: .cascade,
            // inverse: \X.y) var …`. Первая редакция резала по пробелу
            // и теряла такое поле; нашла это собственная подделка,
            // вторым случаем, который я дописал наудачу.
            var глубина = 0
            var индекс = s.startIndex
            var встретилСкобку = false
            while индекс < s.endIndex {
                let c = s[индекс]
                if c == "(" { глубина += 1; встретилСкобку = true }
                if c == ")" { глубина -= 1 }
                индекс = s.index(after: индекс)
                if встретилСкобку, глубина == 0 { break }
                if !встретилСкобку, c == " " { break }
            }
            guard индекс < s.endIndex else { return nil }
            s = String(s[индекс...]).trimmingCharacters(in: .whitespaces)
        }
        for модификатор in ["public ", "private ", "internal ", "fileprivate "]
        where s.hasPrefix(модификатор) {
            s = String(s.dropFirst(модификатор.count))
        }
        guard s.hasPrefix("var ") else { return nil }
        let имя = s.dropFirst("var ".count).prefix { $0.isLetter || $0.isNumber }
        return имя.isEmpty ? nil : String(имя)
    }
}
