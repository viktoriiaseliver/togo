import Testing
import Foundation
@testable import Togo

/// Число в заголовке «УЧАСТНИКИ · N» и число строк под ним — одна
/// величина, и слово «владелец» на экране одно.
///
/// # Чем оплачен этот набор
///
/// Четыре кадра витрины 27.10.2026, снятые подряд на четырёх языках:
///
/// ```
/// витрина-вычитка-27.10/06-family.png             «УЧАСТНИКИ · 5»
/// витрина-три-языка-27.10/06-family-en-US.png     «MEMBERS · 5»
/// витрина-три-языка-27.10/06-family-fr-FR.png     «MEMBRES · 5»
/// витрина-три-языка-27.10/06-family-uk.png        «УЧАСТНИКИ · 5»
/// ```
///
/// Строк под заголовком на всех четырёх **шесть**: `Ты · владелец` ·
/// `Dr. Ferrand` · `Виктория · владелец · всё` · `Лея` · `Мама` · `Тео`.
///
/// Что это **регрессия**, а не замысел, доказывает собственный старый
/// кадр проекта — `Дизайн/кадры-приёмки/журнал-приёмки/
/// семья-низ-f0bda5c-ПОСЛЕ-3a72afc-ДЕФЕКТ-ЖИВ.png`: там «УЧАСТНИКИ · 5»
/// и ровно пять строк, строки «Ты» нет вовсе.
///
/// # Почему набор ставится на `РольВДневнике`, а не на экран
///
/// Оба решения жили выражениями внутри `FamilyScreen.membersCard`:
/// заголовок считал `members.count`, список рисовал на строку больше.
/// Пока их два, они расходятся молча — и разошлись. Правило вынесено
/// в тип, который уже носит утверждение «владелец один», и отсюда же
/// его берёт экран; здесь оно проверяется прямым вызовом.
///
/// **Чего этот набор НЕ доказывает.** Что `FamilyScreen` зовёт именно
/// эти две функции. Ось «вызывают ли» — другая, и у неё другой
/// инструмент; приёмка показа — кадр `06-family`, а не тест.
/// «Тест проверяет, верно ли посчитано; кадр — верно ли сказано».
@Suite("Своя строка в списке семьи: число сходится, «владелец» один")
struct СвояСтрокаВСемьеTests {

    /// Ровно тот состав, что на кадрах витрины: пятеро, один владелец.
    private func составВитрины() -> [FamilyMember] {
        [FamilyMember(name: "Dr. Ferrand", role: .observer),
         FamilyMember(name: "Виктория", role: .owner, isMe: true),
         FamilyMember(name: "Лея", role: .helper),
         FamilyMember(name: "Мама", role: .caregiver),
         FamilyMember(name: "Тео", role: .coOwner)]
    }

    // MARK: Было ли что проверять

    /// **Ставится первой.** Без неё остальные проверки выполняются
    /// на пустом составе и молчат так же легко, как на здоровом.
    @Test("Состав витрины собрался: пятеро и ровно один владелец")
    func составСобрался() {
        let состав = составВитрины()
        #expect(состав.count == 5, """
            фикстура дала \(состав.count) участников вместо пяти — \
            числа ниже ничего не значат.
            """)
        #expect(состав.filter { $0.role == .owner }.count == 1, """
            владельцев в фикстуре \(состав.filter { $0.role == .owner }.count), \
            а весь набор стоит на утверждении «владелец один».
            """)
    }

    // MARK: Предмет — число и строки

    @Test("Заголовок называет столько, сколько строк нарисовано")
    func числоСходитсяСоСтроками() {
        let состав = составВитрины()

        // Хозяин, НЕ прошедший онбординг: `myMemberID` не записан,
        // участников больше одного — `FamilyResolver.меня` возвращает
        // `nil`, и роль падает в `рольБезОпознания(гость: false)`.
        // Ровно это состояние снято на кадрах витрины.
        let своя = РольВДневнике.своя(роль: .owner, среди: состав, опознан: false)
        #expect(своя == nil, """
            своя строка встала НАД списком, в котором уже есть карточка \
            с ролью `.owner`. На экране это два «владельца» подряд, \
            и человек не может сказать, какая строка он, — а экран \
            решает, кто имеет право ставить дозу.
            """)
        #expect(РольВДневнике.строк(среди: состав, своя: своя) == 5, """
            заголовок напечатает \
            \(РольВДневнике.строк(среди: состав, своя: своя)) при пяти \
            нарисованных строках. Ровно это и показывают четыре кадра \
            витрины 27.10: «УЧАСТНИКИ · 5» над шестью строками.
            """)
    }

    @Test("У гостя своя строка остаётся, и число растёт вместе с ней")
    func гостьВидитСвоюСтрокуИСчитаетсяВЧисле() {
        let состав = составВитрины()
        // Роль гостя прибита потолком к `.observer`
        // (`FamilyResolver.потолокГостя`), совпасть с владельцем списка
        // ей нечем. Своей карточки у гостя нет по построению.
        let своя = РольВДневнике.своя(роль: .observer, среди: состав, опознан: false)
        #expect(своя != nil, """
            гость остался без строки о собственной роли. Это единственное \
            место, где он узнаёт, что ему здесь можно, — своей карточки \
            в чужом дневнике у него нет вовсе.
            """)
        #expect(РольВДневнике.строк(среди: состав, своя: своя) == 6, """
            строк рисуется шесть (пять карточек плюс своя), \
            а заголовок называет \
            \(РольВДневнике.строк(среди: состав, своя: своя)).
            """)
    }

    @Test("Хозяин, не заводивший себя в список, свою строку видит")
    func безВладельцаВСпискеСтрокаОстаётся() {
        // Список без карточки `.owner` — человек просто не завёл себя.
        // Удваивать нечего, и строка «Ты · владелец» здесь единственный
        // ответ на «а что мне тут можно».
        let состав = составВитрины().filter { $0.role != .owner }
        #expect(состав.count == 4, "контроль фикстуры: владельца убрали, осталось четверо")
        let своя = РольВДневнике.своя(роль: .owner, среди: состав, опознан: false)
        #expect(своя != nil, """
            строка пропала там, где удваивать нечего: в списке нет \
            ни одной карточки с ролью `.owner`. Условие сузилось \
            до «роль .owner», а оно про СОВПАДЕНИЕ с карточкой списка.
            """)
        #expect(РольВДневнике.строк(среди: состав, своя: своя) == 5)
    }

    @Test("Опознанной карточке своя строка не добавляется")
    func опознанныйНеУдваивается() {
        let состав = составВитрины()
        for роль in FamilyRole.allCases {
            #expect(РольВДневнике.своя(роль: роль, среди: состав, опознан: true) == nil, """
                роль \(роль.rawValue): своя карточка в списке НАЙДЕНА, \
                и рядом с ней встала ещё и своя строка — один человек \
                двумя строками.
                """)
            #expect(РольВДневнике.строк(среди: состав,
                                        своя: РольВДневнике.своя(роль: роль,
                                                                 среди: состав,
                                                                 опознан: true)) == 5)
        }
    }

    // MARK: Слово «владелец» на экране одно

    /// **Ось — текст, который человек читает, а не внутренняя роль.**
    ///
    /// Сравниваются готовые подписи: `роль.ты` («Ты · владелец») против
    /// `member.role.title` («Владелец»). Сторож на равенство enum'ов
    /// пропустил бы две разные роли, напечатанные одним словом, —
    /// а человек видит именно слово.
    @Test("Ни одна карточка списка не повторяет слово из своей строки")
    func словоРолиНеПовторяется() {
        let состав = составВитрины()
        var проверено = 0
        for роль in FamilyRole.allCases {
            guard let своя = РольВДневнике.своя(роль: роль, среди: состав, опознан: false)
            else { continue }
            проверено += 1
            let моёСлово = своя.роль.title.lowercased()
            let совпавшие = состав.filter { $0.role.title.lowercased() == моёСлово }
            #expect(совпавшие.isEmpty, """
                своя строка говорит «\(своя.ты)», и то же слово \
                «\(моёСлово)» стоит у \(совпавшие.count) карточк(и) \
                списка: \(совпавшие.map(\.name).joined(separator: ", ")). \
                Человек не может сказать, какая из строк он.
                """)
        }
        #expect(проверено > 0, """
            ни одна роль не дала своей строки — проверять было нечего, \
            и зелёный здесь значит «предмета нет там, куда смотрю».
            """)
    }
}
