import Foundation
import Testing

/// Отменить схему лечения вправе только то, что ставит **оба** поля.
///
/// # Что этот сторож держал сначала и что держит теперь
///
/// Заведён 15.10.2026 под риск: отмена по одной схеме была в работе,
/// а вся уборка напоминаний смотрит на `isPaused` и `cancelledAt` схемы
/// не спрашивает нигде (`ReminderScheduler:167`, `:240`,
/// `DoseRecord.ждётОтметкиСУчётомСхемы`).
///
/// > Кнопка, поставившая только `cancelledAt`, не погасила бы
/// > напоминания **ни у кого, включая хозяйку**.
///
/// **Этот риск закрыт в тот же день, и закрыт не сторожем, а методом:**
/// `Medication.отменить(в:заметка:)` ставит оба поля, `TreatmentCourse`
/// зовёт его вместо двух присваиваний. Мимо метода неверный путь
/// **не выражается**.
///
/// Сторож не снят, потому что держит теперь другое — и это **ось
/// та же, причина новая**:
///
/// ```
/// было    «не появилась ли отмена, которая ставит одно поле»
/// стало   «не появился ли писатель МИМО метода»
/// ```
///
/// Так уже было в этом проекте: сторож держал механизм, предмет после
/// починки стал держаться лучше, и ось переписали, а не удалили.
/// Удалённый сторож о себе не предупреждает.
///
/// # Почему ось ПО ФАЙЛАМ, а не по строкам
///
/// Построчную пробовал и снял — замер 15.10.2026: регулярка
/// по присваиванию дала **девять** попаданий при **одном** настоящем
/// писателе, путая сравнение `== nil`, слияние в разрешителе
/// и восстановление из архива. Здесь сторож полноты каталога соврал
/// трижды подряд, и после третьего раза в сторожа перестают смотреть.
///
/// Ось по файлам классифицировать присваивание не обязана: она
/// спрашивает «появился ли новый файл, который трогает это поле».
///
/// # Две формы присваивания, и вторую я чуть не потерял
///
/// Первая редакция искала только `.cancelledAt =` — **с точкой**.
/// Когда отмена переехала внутрь `Medication`, присваивание стало
/// `cancelledAt = момент`, без точки, и сторож **перестал видеть
/// собственного владельца предмета**: список писателей схлопнулся
/// с трёх файлов до двух, и `Care.swift` в нём не было.
///
/// > **Починка предмета сдвинула ось сторожа, и сторож этого
/// > не заметил бы.** Поймано только тем, что список перемерен
/// > после правки, а не до неё.
///
/// # Приёмка правила — прогон на живых данных и четыре подделки
///
/// ```
/// здоровый код                   4 файла, 7 присваиваний
/// А  новая отмена в экране       КРАСНЕЕТ и называет файл   ✓
/// Б  присваивание в комментарии  не зачтено                 ✓
/// В  сравнение == nil            не зачтено                 ✓
/// Г  поле переименовано          0 → порог краснеет ПЕРВЫМ  ✓
/// ```
///
/// # Вход с диска назван нарочно
///
/// Тест читает `Togo/`, `TogoShared/` и `TogoWidgets/` через `#filePath`
/// и сломается от переноса каталогов — то есть **не на своём предмете**.
@Suite("Отменять схему вправе только то, что ставит и паузу")
struct ОтменаСтавитОбаПоляTests {

    // MARK: Источники

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
    }

    private static func безКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .filter {
                let голая = $0.trimmingCharacters(in: .whitespaces)
                return !голая.hasPrefix("//") && !голая.hasPrefix("*")
            }
            .joined(separator: "\n")
    }

    /// Присваивание, а не сравнение, **в обеих формах**.
    ///
    /// `foo.cancelledAt = …` снаружи типа и голое `cancelledAt = …`
    /// внутри него. Вторая форма добавлена после того, как отмена
    /// переехала в модель и сторож потерял её из виду.
    ///
    /// Отсекаются: `==` (по символу ПОСЛЕ знака равенства), `!=`, `<=`,
    /// `>=` (по тому, что на месте `=` стоит другой символ), и имена
    /// вроде `myCancelledAt` (по символу ПЕРЕД именем).
    private static func присваиваний(_ код: String) -> Int {
        var счёт = 0
        var откуда = код.startIndex
        while let поле = код.range(of: "cancelledAt", range: откуда..<код.endIndex) {
            откуда = поле.upperBound

            // Граница имени слева: точка допустима, буква и цифра — нет.
            if поле.lowerBound > код.startIndex {
                let до = код[код.index(before: поле.lowerBound)]
                if до.isLetter || до.isNumber || до == "_" { continue }
            }

            var i = поле.upperBound
            while i < код.endIndex, код[i] == " " { i = код.index(after: i) }
            guard i < код.endIndex, код[i] == "=" else { continue }
            let после = код.index(after: i)
            if после < код.endIndex, код[после] == "=" { continue }
            счёт += 1
        }
        return счёт
    }

    private static func файлыПисатели() -> [String: Int] {
        var найдено: [String: Int] = [:]
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let адрес = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(
                at: адрес, includingPropertiesForKeys: nil) else { continue }
            while let файл = обход.nextObject() as? URL {
                guard файл.pathExtension == "swift",
                      let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
                let n = присваиваний(безКомментариев(текст))
                if n > 0 { найдено[файл.lastPathComponent, default: 0] += n }
            }
        }
        return найдено
    }

    // MARK: Кому можно и почему

    /// Файлы, которым присваивать `cancelledAt` **разрешено**, с причиной.
    ///
    /// Причина обязана быть длиннее отговорки: разрешение переживает
    /// своего автора, и читать его будет тот, кто не знает контекста.
    private static let разрешено: [String: String] = [
        "Care.swift": """
            Владелец предмета с 15.10.2026: `Medication.отменить(в:заметка:)` \
            и `вернутьВСтрой()` — единственная пара, которой отменяют \
            и возвращают схему. Оба метода ставят `isPaused` вместе \
            с `cancelledAt`, и мимо них неверный путь не выражается.
            """,
        "TreatmentCourse.swift": """
            Прямых присваиваний здесь больше нет с 15.10.2026: `finish` \
            и `resume` зовут методы модели. Разрешение не удалено \
            нарочно — оно держит `ожидаемоНеПишут` ниже, и если файл \
            снова появится среди писателей, значит кто-то вернул \
            присваивание вместо метода. Это находка, а не шум.
            """,
        "Backup.swift": """
            Восстановление из файла: поле переносится снимком как было, \
            вместе с `isPaused` из того же снимка. Это не отмена, \
            а возврат ранее записанного состояния.
            """,
        "SharedDiary.swift": """
            Разрешитель спора двух телефонов: `cancelledAt = local ?? \
            remote` рядом с `isPaused = local || remote` (`:905-908`) — \
            оба поля сливаются в одном месте и в одну сторону, \
            «не дать отменённую таблетку безопаснее, чем дать».
            """,
        "SharedDiaryPayloads.swift": """
            Приём приехавшей нагрузки: `apply(payload)` копирует поля \
            как есть, и `isPaused` копируется строкой выше (`:368`, \
            `:593`). Решения об отмене здесь не принимают — переносят \
            чужое, уже принятое.
            """,
    ]

    /// Разрешения, которые ОБЯЗАНЫ быть на несуществующем писателе.
    ///
    /// `TreatmentCourse.swift` присваивать перестал — и это результат
    /// починки, а не потеря. Обычная проверка «разрешение не протухло»
    /// такую запись сочла бы призраком и покраснела, поэтому она
    /// названа здесь: **ожидаемо отсутствующий писатель**. Если он
    /// вернётся в список — проверка ниже скажет об этом.
    private static let ожидаемоНеПишут: Set<String> = ["TreatmentCourse.swift"]

    // MARK: Проверки

    /// Первой — что сторожу было что сторожить.
    @Test("Присваивания cancelledAt найдены — разбор состоялся")
    func былоЧтоСторожить() {
        let найдено = Self.файлыПисатели()
        let всего = найдено.values.reduce(0, +)

        #expect(всего >= 3, """
            присваиваний `cancelledAt` найдено \(всего) — разбор \
            не состоялся. Поле переименовали, каталоги перенесли, либо \
            сломался разбор. Сторож, переставший что-либо находить, \
            молчит так же, как тот, кому нечего сказать: при нуле \
            проверка ниже не нашла бы НИ ОДНОГО лишнего файла \
            и позеленела.
            """)

        #expect(найдено["Care.swift"] != nil, """
            `Care.swift` не числится писателем `cancelledAt`, хотя \
            отмена схемы живёт именно там — `Medication.отменить`. \
            Это отказ РАЗБОРА, а не находка о коде, и ровно та форма, \
            на которой сторож однажды уже потерял владельца предмета: \
            внутри типа присваивание идёт БЕЗ точки.
            """)
    }

    /// Запрет: новый файл трогает `cancelledAt` и нигде не назван.
    @Test("Присваивать cancelledAt вправе только названные файлы")
    func новыйПисательНазванИлиКраснеет() {
        let найдено = Self.файлыПисатели()

        guard найдено.values.reduce(0, +) >= 3, найдено["Care.swift"] != nil else {
            #expect(Bool(false), """
                разбор не состоялся — смотреть `былоЧтоСторожить`, \
                а не этот тест.
                """)
            return
        }

        let лишние = найдено.keys
            .filter { Self.разрешено[$0] == nil }
            .sorted()

        #expect(лишние.isEmpty, """
            файл присваивает `cancelledAt` и не назван: \
            \(лишние.joined(separator: ", ")).

            Отменять схему вправе `Medication.отменить(в:заметка:)` — \
            он ставит `isPaused` вместе с `cancelledAt`. Вся уборка \
            напоминаний смотрит на `isPaused` и `cancelledAt` схемы \
            не спрашивает нигде: отмена без паузы не погасит запросы \
            НИ У КОГО, включая хозяйку, и человек будет получать \
            «Через 10 минут доза» по лечению, которого больше нет.

            Если это не отмена — впиши файл в `разрешено` С ПРИЧИНОЙ.
            """)
    }

    /// Обратная половина: разрешение на файл, который поле больше
    /// не трогает, — лишняя дыра, про которую никто не помнит.
    @Test("Разрешение стоит на живом писателе и несёт причину")
    func разрешенияНеПротухли() {
        let найдено = Self.файлыПисатели()

        let призраки = Self.разрешено.keys
            .filter { найдено[$0] == nil && !Self.ожидаемоНеПишут.contains($0) }
            .sorted()
        #expect(призраки.isEmpty, """
            разрешение стоит на файлах, которые `cancelledAt` больше \
            не присваивают: \(призраки.joined(separator: ", ")). Код \
            починили или перенесли, а разрешение осталось — и теперь \
            оно молча прикроет следующего писателя с тем же именем файла.
            """)

        // И обратное к ожидаемому отсутствию: если `TreatmentCourse`
        // снова начал присваивать — значит кто-то вернул два
        // присваивания вместо метода, и ровно это надо увидеть.
        let вернувшиеся = Self.ожидаемоНеПишут
            .filter { найдено[$0] != nil }.sorted()
        #expect(вернувшиеся.isEmpty, """
            файл снова присваивает `cancelledAt` напрямую: \
            \(вернувшиеся.joined(separator: ", ")). 15.10.2026 отсюда \
            убрали два присваивания и завели `Medication.отменить`, \
            чтобы отмену нельзя было выразить без паузы. Возврат \
            присваивания возвращает и ту возможность.
            """)

        let безПричины = Self.разрешено
            .filter { $0.value.trimmingCharacters(in: .whitespacesAndNewlines).count < 80 }
            .keys.sorted()
        #expect(безПричины.isEmpty, """
            разрешение без внятной причины: \
            \(безПричины.joined(separator: ", ")). Порог длины — против \
            отговорок вида «так надо».
            """)
    }

    /// Граница собственного умения — печатается всегда.
    @Test("Границы сторожа отмены названы")
    func границыНазваны() {
        let границы = """
            Зелёный здесь значит ровно одно: `cancelledAt` присваивают \
            только названные файлы. И только это.

            НЕ проверяется:
            · ставит ли названный файл `isPaused` РЯДОМ. Это держит \
              поведение: `TreatmentCourseTests:41-49` для `finish`, \
              и оно же теперь проверяет метод модели, потому что \
              `finish` зовёт именно его;
            · тот же файл с ДВУМЯ присваиваниями, одно из которых \
              без паузы. Ось по файлам этого не различает НАРОЧНО: \
              построчная дала девять попаданий при одном настоящем \
              писателе и была бы снята как врущая;
            · гаснут ли напоминания у ВТОРОГО человека. Это два \
              телефона, и это неизмеримо без личного iCloud Виктории;
            · момент, когда они гаснут. При закрытом приложении \
              не выполняется ничего — `CKSubscription` в коде ноль, \
              и отмена доходит, когда человек откроет приложение.
            """
        #expect(границы.isEmpty == false)
    }
}
