import Testing
import Foundation

/// Точка сокращения месяца не сталкивается с точкой шаблона.
///
/// **Повод.** 05.10.2026 кадр показал под вердиктом «С 17 сент. отметок
/// мочи нет.. Приложение не знает…» — две точки. `Fmt.shortDay` отдаёт
/// сокращение месяца со СВОЕЙ точкой, а шаблон ставил свою.
/// Починено `3d9fc28` — дата переехала в середину фразы, — и починка
/// держалась на комментарии, который обещал больше, чем правда:
///
/// > «решение верно во всех языках разом, а не принимается в каждом
/// > отдельно»
///
/// Замер 05.10, вечер: английский перевод того же ключа дату в хвост
/// как раз поставил — `No pee has been marked since %@.` Спасает его
/// не структура, а локаль: английское сокращение точки не несёт.
/// То есть обещание «разом во всех языках» неверно, а верно
/// «в трёх языках повезло».
///
/// **Почему сторож, а не комментарий.** Запись правила без сторожа
/// держится до первой правки, и правка тут приходит с той стороны,
/// которой правило не читали: дату в хвост ставит ПЕРЕВОДЧИК, а русский
/// исходник при этом цел. Это тот же класс, что «правят оригинал —
/// переводы не едут следом», только наоборот.
///
/// **Запрет, а не требование.** Спросить «нет ли даты вплотную перед
/// точкой» можно надёжно; спросить «стоит ли дата в правильном месте»
/// нельзя — правильных мест много и они разные в каждом языке.
///
/// **Не дубль `UrineSilenceTests.объяснениеБезДвойнойТочки` (`:239`),
/// а его расширение по языкам.** Граница между ними такая:
///
/// ```
/// :239 (не трогать)   одна строка, один язык (литерал разработки = ru),
///                     живой `VerdictEngine.explanation` → видит ПОВЕДЕНИЕ
/// этот набор          все места подстановки даты × 4 языка каталога,
///                     разбор исходника и JSON → поведения НЕ видит
/// ```
///
/// Два разных вопроса, и ни один не заменяет другой: `:239` поймает
/// дефект, собранный в рантайме из верных кусков, этот — перевод,
/// у которого русский исходник цел. Третьего сторожа на то же место
/// заводить не нужно; если он понадобится, то на поведение во всех
/// языках разом, а это требует каталога в бандле под тестом.
///
/// Чего набор НЕ проверяет — в `границыНабора()`, последним тестом.
@Suite("Точка сокращения даты против точки шаблона")
struct DateDotCollisionTests {

    // MARK: - Инструмент

    /// Языки витрины. Регион назван явно, потому что **формат даты
    /// берёт РЕГИОН, а не язык** (замер 05.10: `en_US` даёт «Sep 9»,
    /// `en_GB` — «9 Sep»). Человек может выбрать их вразнобой, и это
    /// названо границей ниже.
    private static let языки: [(код: String, локаль: String)] = [
        ("ru", "ru_RU"), ("en", "en_US"), ("fr", "fr_FR"), ("uk", "uk_UA"),
    ]

    /// Несёт ли сокращение месяца точку — измеряется на ВСЕХ ДВЕНАДЦАТИ
    /// месяцах, а не на одном.
    ///
    /// **Худший месяц не угадывается, а показывается.** Замер 05.10:
    /// у русского точку несут 8 месяцев из 12 — «17 янв.» несёт,
    /// «17 мая» не несёт; у французского тоже 8 («17 mai», «17 août»
    /// без точки); у украинского 12 из 12; у английского ноль.
    /// Сторож, написанный на майской дате, был бы зелёным в русском
    /// и французском и слепым весь год.
    private static func месяцыСТочкой(_ идентификатор: String) -> [String] {
        let локаль = Locale(identifier: идентификатор)
        let календарь = Calendar(identifier: .gregorian)
        var сТочкой: [String] = []
        for месяц in 1...12 {
            var части = DateComponents()
            части.year = 2026
            части.month = месяц
            части.day = 17
            guard let дата = календарь.date(from: части) else { continue }
            let текст = дата.formatted(
                .dateTime.day().month(.abbreviated).locale(локаль))
            if текст.hasSuffix(".") { сТочкой.append(текст) }
        }
        return сТочкой
    }

    /// Место подстановки даты в одном строковом литерале исходника.
    private struct Шаблон {
        /// Литерал как написан в коде, с интерполяциями.
        let литерал: String
        /// Он же в виде ключа каталога: интерполяции заменены на `%@`.
        let ключ: String
        /// Номера подстановок (с нуля), в которые уходит `Fmt.shortDay`.
        /// Перевод переставить их не может: `%@` без номера позиционен.
        let номераДаты: [Int]
        let место: String
    }

    private static let корень = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().deletingLastPathComponent()

    /// Все литералы исходника, куда подставляется дата.
    ///
    /// Выводится из исходника, а не перечисляется руками: **список
    /// руками знает только то, что в него положили**, а эта проверка
    /// нужна ровно для строк, которые напишут после неё.
    ///
    /// Комментарии вырезаются до разбора — иначе сторож краснеет
    /// на рассказе о дефекте в том же файле, где его не совершают.
    private static func шаблоны() -> [Шаблон] {
        let литерал = try! NSRegularExpression(pattern: "\"((?:[^\"\\\\]|\\\\.)*?)\"")
        let интерполяция = try! NSRegularExpression(
            pattern: "\\\\\\((?:[^()]|\\([^()]*\\))*\\)")
        var найдено: [Шаблон] = []

        for место in ["TogoShared", "Togo", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(место), includingPropertiesForKeys: nil)
            while let файл = обход?.nextObject() as? URL {
                guard файл.pathExtension == "swift",
                      let текст = try? String(contentsOf: файл, encoding: .utf8) else { continue }
                for (номер, строка) in текст.components(separatedBy: .newlines).enumerated() {
                    let код = строка.components(separatedBy: "//")[0]
                    guard код.contains("Fmt.shortDay") else { continue }
                    for кусок in совпадения(литерал, в: код, группа: 1) {
                        guard кусок.contains("Fmt.shortDay") else { continue }
                        let подстановки = совпадения(интерполяция, в: кусок, группа: 0)
                        let номера = подстановки.enumerated()
                            .filter { $0.element.contains("Fmt.shortDay") }
                            .map(\.offset)
                        guard !номера.isEmpty else { continue }
                        найдено.append(Шаблон(
                            литерал: кусок,
                            ключ: интерполяция.stringByReplacingMatches(
                                in: кусок, range: NSRange(кусок.startIndex..., in: кусок),
                                withTemplate: "%@"),
                            номераДаты: номера,
                            место: "\(файл.lastPathComponent):\(номер + 1)"))
                    }
                }
            }
        }
        return найдено
    }

    private static func совпадения(_ выражение: NSRegularExpression,
                                   в текст: String, группа: Int) -> [String] {
        выражение.matches(in: текст, range: NSRange(текст.startIndex..., in: текст))
            .compactMap { Range($0.range(at: группа), in: текст).map { String(текст[$0]) } }
    }

    /// Все переводы всех каталогов проекта.
    private static func каталог() throws -> [String: [String: String]] {
        var строки: [String: [String: String]] = [:]
        for путь in ["TogoShared/Resources/Localizable.xcstrings",
                     "Togo/Resources/AppShortcuts.xcstrings"] {
            let данные = try Data(contentsOf: корень.appendingPathComponent(путь))
            let разбор = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
            for (ключ, запись) in разбор?["strings"] as? [String: Any] ?? [:] {
                let переводы = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
                var собрано: [String: String] = [:]
                for (язык, значение) in переводы {
                    if let текст = ((значение as? [String: Any])?["stringUnit"]
                        as? [String: Any])?["value"] as? String {
                        собрано[язык] = текст
                    }
                }
                строки[ключ] = собрано
            }
        }
        return строки
    }

    /// Стоит ли подстановка номер `номер` вплотную перед точкой.
    ///
    /// Спрашивается про `.`, `?` и `!` разом: все три сталкиваются
    /// с точкой сокращения одинаково, и «Приложение не знает?» в вопросе
    /// даёт «17 сент.?» так же, как точка давала «17 сент..».
    private static func передТочкой(_ текст: String, подстановка номер: Int) -> Bool {
        var позиции: [String.Index] = []
        var курсор = текст.startIndex
        while let найдено = текст.range(of: "%@", range: курсор..<текст.endIndex) {
            позиции.append(найдено.upperBound)
            курсор = найдено.upperBound
        }
        guard номер < позиции.count else { return false }
        let хвост = текст[позиции[номер]...].drop { $0 == " " || $0 == "\u{202F}" || $0 == "\u{00A0}" }
        return хвост.first.map { ".?!".contains($0) } ?? false
    }

    // MARK: - 1. Запрет в исходнике

    /// Русский исходник — тоже язык с точкой (8 месяцев из 12).
    @Test("Дата не стоит вплотную перед точкой в исходнике")
    func датаНеПередТочкойВИсходнике() {
        let шаблоны = Self.шаблоны()
        for шаблон in шаблоны {
            for номер in шаблон.номераДаты {
                #expect(Self.передТочкой(шаблон.ключ, подстановка: номер) == false, """
                    \(шаблон.место): дата стоит вплотную перед точкой шаблона — \
                    «\(шаблон.ключ)». У русского сокращение несёт свою точку \
                    в 8 месяцах из 12 («17 янв.», но «17 мая»), и выйдет \
                    «17 янв..». Чинить переносом даты в середину фразы, \
                    а НЕ удалением точки из шаблона и НЕ правкой \
                    `Fmt.shortDay`: точка приходит из локали вместе \
                    с сокращением и стоит там по праву.
                    """)
            }
        }
    }

    // MARK: - 2. Запрет в переводах

    /// Та же проверка там, откуда дефект придёт на самом деле.
    ///
    /// Перевод переставляет слова свободно, и это правильно — порядок
    /// слов у каждого языка свой (замер 05.10: `с %@ мочу не отмечали`
    /// против `%@ · pipi non coché`). Запрещено ровно одно: дата
    /// вплотную перед точкой, и только в языках, где сокращение точку
    /// несёт.
    @Test("Дата не стоит вплотную перед точкой ни в одном переводе")
    func датаНеПередТочкойВПереводах() throws {
        let каталог = try Self.каталог()
        for шаблон in Self.шаблоны() {
            guard let переводы = каталог[шаблон.ключ] else { continue }
            for (код, идентификатор) in Self.языки {
                guard !Self.месяцыСТочкой(идентификатор).isEmpty else { continue }
                guard let текст = переводы[код] else { continue }
                for номер in шаблон.номераДаты {
                    #expect(Self.передТочкой(текст, подстановка: номер) == false, """
                        \(код) · \(шаблон.место): перевод поставил дату вплотную \
                        перед точкой — «\(текст)». В \(идентификатор) сокращение \
                        месяца несёт свою точку, и человек прочтёт две. \
                        Русский исходник при этом цел, поэтому не краснеет \
                        больше ничто. Чинить порядком слов в этом языке, \
                        а не выравниванием под русский.
                        """)
                }
            }
        }
    }

    // MARK: - 3. Инструменту было что проверять

    /// Любой группе проверок нужна проверка, что ей было что проверять:
    /// **сканер, переставший что-либо находить, молчит так же, как тот,
    /// кому нечего сказать.**
    @Test("Разбор состоялся: шаблоны найдены, языки измерены")
    func инструментИзмеряет() throws {
        let шаблоны = Self.шаблоны()
        #expect(шаблоны.count >= 25, """
            шаблонов с подстановкой даты найдено \(шаблоны.count) при 30 \
            на 05.10.2026. Разбор исходника развалился — проверка выше \
            зелёная, потому что ей нечего смотреть, а не потому что чисто.
            """)

        let каталог = try Self.каталог()
        var пар = 0
        for шаблон in шаблоны where каталог[шаблон.ключ] != nil {
            пар += каталог[шаблон.ключ]!.keys.filter { код in
                Self.языки.contains { $0.код == код }
            }.count
        }
        #expect(пар >= 60, """
            пар ключ×язык осмотрено \(пар) при 97 на 05.10.2026. \
            Либо каталог не прочитан, либо ключи разошлись с исходником \
            (их заводит компилятор при извлечении, а не скрипт).
            """)

        // Измеренное, а не записанное списком: если Apple однажды
        // поставит точку английскому, проверка переводов начнёт смотреть
        // и его — а строка `No pee has been marked since %@.` сразу
        // покраснеет, как и должна.
        for (код, идентификатор) in Self.языки {
            let месяцы = Self.месяцыСТочкой(идентификатор)
            if код == "en" {
                #expect(месяцы.isEmpty, """
                    у \(идентификатор) сокращение месяца теперь несёт точку \
                    (\(месяцы)). Это НЕ дефект сторожа: английский перевод \
                    ключа «С %@ отметок мочи нет…» ставит дату в хвост \
                    фразы, и до сих пор это было безопасно только \
                    из-за локали. Переставить дату в середину — и снять \
                    это ожидание.
                    """)
            } else {
                #expect(!месяцы.isEmpty, """
                    у \(идентификатор) ни один из 12 месяцев не несёт точку — \
                    значит проверка переводов этот язык больше НЕ смотрит \
                    и молчит об этом. Либо формат сменился, либо локаль \
                    не нашлась и `Locale` отдал запас.
                    """)
            }
        }
    }

    // MARK: - 4. Границы этого набора

    /// Стоит последним нарочно, и к каждой границе названо, **что её
    /// снимет** — иначе граница переживёт свою причину, как пережила
    /// печать `UrineSilenceTests` 28.09.
    @Test("Границы: чего не проверяет набор про столкновение точек дат")
    func границыНабора() {
        // 1. **Регион человека набор не знает.** Формат даты берёт
        //    регион, а не язык, и проверяются четыре пары из витрины
        //    (`ru_RU`, `en_US`, `fr_FR`, `uk_UA`). Француз в Канаде
        //    получит `fr_CA` — он точку несёт так же (замер 05.10),
        //    то есть вывод не меняется; англичанин во Франции получит
        //    английские месяцы в европейском порядке и тоже без точки.
        //    *Снимет границу:* перебор всех регионов, какие отдаёт
        //    `Locale.availableIdentifiers` для языка, вместо одной пары.
        //    Не сделано здесь, а не невозможно: четыре пары — это
        //    витрина, а не весь мир.
        //
        // 2. **Столкновение ищется только с точкой, запятой — нет.**
        //    «17 janv., aucun pipi» — нормальная французская типографика,
        //    и запрещать её нельзя. Но «17 sept.,» в языке, где запятая
        //    после сокращения не принята, набор пропустит.
        //    *Снимет границу:* мнение носителя о каждой паре
        //    «сокращение + знак», а не правило в коде. Инструментом
        //    этот вопрос не задаётся: оба символа существуют и
        //    написаны верно.
        //
        // 3. **Что человек УВИДИТ — не проверено.** Набор меряет строку
        //    в каталоге, а не кадр. Строки виджета рисует SpringBoard,
        //    и `app.screenshot()` до него не достаёт.
        //    *Снимет границу:* кадр `TodayWidgetView` в галерее отладки
        //    с подставленным снимком — так же, как это сделано для
        //    ступени тишины.
        //
        // 4. **Дата, собранная не через `Fmt.shortDay`, набору
        //    невидима.** Он идёт от имени функции в исходнике, то есть
        //    ловит «не позвали» и слеп к «посчитали сами»: строка,
        //    где месяц сокращён руками или `DateFormatter` заведён
        //    на месте, не попадёт в разбор вовсе.
        //    *Снимет границу:* сторож на `.month(.abbreviated)`
        //    и `DateFormatter` мимо `Fmt` — он скажет, что второй
        //    способ завели, и тогда сюда можно будет добавить его
        //    поимённо.
        //
        // 5. **Ноль здесь означает три связи, а не «чисто».** Проверено:
        //    дата не стоит перед точкой в исходнике, не стоит перед ней
        //    в переводах трёх языков с точкой, и разбор нашёл не меньше
        //    25 шаблонов. Слово, которое существует и значит не то,
        //    набор не видит; порядок слов, грамматичный и пустой, —
        //    тоже.
    }
}
