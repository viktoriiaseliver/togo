import Foundation
import Testing
@testable import Togo

/// «Значит ли это поле на другом телефоне то же самое» — для событий
/// с концом.
///
/// Вопрос поставил менеджер по раздаче моделей; ответ у `Trip`
/// и `HeatRecord` оказался «нет», и расходились они на целые сутки.
/// Дневник общий на семью, а семья бывает в разных поясах — поездка
/// это ровно тот случай, ради которого поля и заведены.
///
/// **Проверить это раньше было нечем:** все три расчёта брали
/// `Calendar.current` внутри себя, то есть подставить чужой пояс
/// было некуда. Непроверяемая поверхность чинится переделкой входа,
/// а не старанием, — календарь стал аргументом.
@Suite("День события у второго человека в другом поясе")
struct CrossTimeZoneDayTests {

    private static func календарь(_ смещениеЧасов: Int) -> Calendar {
        var c = Calendar(identifier: .gregorian)
        c.timeZone = TimeZone(secondsFromGMT: смещениеЧасов * 3600)!
        return c
    }

    private static let ницца = календарь(2)       // владелец
    private static let токио = календарь(9)       // восточнее
    private static let нью_йорк = календарь(-4)   // западнее
    private static let лос_анджелес = календарь(-7)

    /// 10 октября 2026 в заданном поясе, время суток — своё.
    private static func десятоеОктября(_ c: Calendar, час: Int) -> Date {
        c.date(from: DateComponents(year: 2026, month: 10, day: 10, hour: час))!
    }

    // MARK: - Сначала: было ли что проверять

    @Test("Пояса в оснастке действительно разные")
    func оснасткаРазличаетПояса() {
        #expect(Self.ницца.timeZone.secondsFromGMT() != Self.лос_анджелес.timeZone.secondsFromGMT(),
                "Без этого все проверки ниже зелены, ничего не проверив.")
        // И сам сдвиг суток существует: полночь в Ницце — ещё вчера в ЛА.
        let полночьВНицце = Self.десятоеОктября(Self.ницца, час: 0)
        let деньВЛА = Self.лос_анджелес.component(.day, from: полночьВНицце)
        #expect(деньВЛА == 9, "Полночь 10 окт в Ницце обязана быть 9 окт в Лос-Анджелесе, иначе оснастка не воспроизводит задачу.")
    }

    // MARK: - Якорь

    @Test("Полдень одного дня остаётся тем же днём во всех четырёх поясах")
    func якорьДержитДень() {
        let якорь = CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                         calendar: Self.ницца)

        for (имя, c) in [("Ницца", Self.ницца), ("Токио", Self.токио),
                         ("Нью-Йорк", Self.нью_йорк), ("Лос-Анджелес", Self.лос_анджелес)] {
            #expect(c.component(.day, from: якорь) == 10,
                    "В поясе «\(имя)» якорь попал на \(c.component(.day, from: якорь))-е вместо 10-го. Запас в двенадцать часов от полудня исчерпан — значит якорь выбран неверно.")
        }
    }

    /// Написано от ОБРАТНОГО: показываем, что без якоря день уезжает.
    /// Без этой проверки сторож выше был бы зелёным и на коде, где
    /// якоря нет вовсе, — то есть не охранял бы ничего.
    @Test("Без якоря день уезжает — и это тот самый дефект")
    func безЯкоряДеньУезжает() {
        let полночь = Self.десятоеОктября(Self.ницца, час: 0)
        #expect(Self.лос_анджелес.component(.day, from: полночь) == 9,
                "Если здесь 10, задача перестала воспроизводиться, и сторож ниже больше ничего не доказывает.")
    }

    // MARK: - Поездка

    @Test("Первый день поездки — первый у всей семьи, а не второй")
    func деньПоездкиОдинаков() {
        let trip = Trip(destination: "Канны",
                        startDate: CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                                        calendar: Self.ницца),
                        endDate: CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 23),
                                                      calendar: Self.ницца),
                        transport: .car)

        for (имя, c) in [("Ницца", Self.ницца), ("Токио", Self.токио),
                         ("Нью-Йорк", Self.нью_йорк), ("Лос-Анджелес", Self.лос_анджелес)] {
            // «Сегодня» у каждого своё — полдень 10 октября в его поясе.
            let сегодня = Self.десятоеОктября(c, час: 12)
            #expect(trip.dayNumber(on: сегодня, calendar: c) == 1,
                    "В поясе «\(имя)» первый день поездки показан как \(trip.dayNumber(on: сегодня, calendar: c))-й. Ситтер увидит «день 2 из 3» в день отъезда.")
            #expect(trip.dayCount(calendar: c) == 1,
                    "В поясе «\(имя)» однодневная поездка длится \(trip.dayCount(calendar: c) ?? -1) дней.")
        }
    }

    @Test("Поездка не открывается у семьи сутками раньше")
    func поездкаНеОткрываетсяРаньше() {
        let trip = Trip(destination: "Канны",
                        startDate: CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                                        calendar: Self.ницца),
                        endDate: CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                                      calendar: Self.ницца),
                        transport: .car)

        for (имя, c) in [("Ницца", Self.ницца), ("Лос-Анджелес", Self.лос_анджелес)] {
            let девятого = c.date(from: DateComponents(year: 2026, month: 10, day: 9, hour: 12))!
            #expect(trip.isActive(on: девятого, calendar: c) == false,
                    "В поясе «\(имя)» поездка считается идущей девятого, хотя начинается десятого.")
        }
    }

    // MARK: - Течка

    @Test("День цикла одинаков у всей семьи — на нём стоят опасные дни")
    func деньЦиклаОдинаков() {
        let запись = HeatRecord(startedAt: CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                                               calendar: Self.ницца))

        for (имя, c) in [("Ницца", Self.ницца), ("Токио", Self.токио),
                         ("Лос-Анджелес", Self.лос_анджелес)] {
            let черезНеделю = c.date(from: DateComponents(year: 2026, month: 10, day: 17, hour: 12))!
            #expect(запись.dayNumber(on: черезНеделю, calendar: c) == 8,
                    "В поясе «\(имя)» восьмой день цикла показан как \(запись.dayNumber(on: черезНеделю, calendar: c))-й. На этом числе стоят опасные дни.")
        }
    }

    // MARK: - Старые записи: без якоря, разрешаются при чтении

    /// Записи до 05.10 лежат без якоря. Стадии миграции НЕТ нарочно —
    /// разбор `togo-45`: `.lightweight` значения не переписывает, а
    /// `.custom` пришлось бы вести по форме, которую несут шесть
    /// розданных сборок; и главное, миграция **стёрла бы улику** —
    /// пока момент лежит у полуночи, расхождение заметно.
    ///
    /// Вместо этого день извлекается в фиксированном поясе дневника.
    /// Обнаруживать «старая или новая» не нужно вовсе: **признак, который
    /// не нужно вычислять, не может ошибиться.**
    @Test("Старая запись, заведённая в Ницце, читается верно и без якоря")
    func стараяЗаписьБезЯкоря() {
        // Так лежало до 05.10: полночь в поясе автора, якоря нет.
        let безЯкоря = Self.десятоеОктября(Self.ницца, час: 0)
        let trip = Trip(destination: "Канны", startDate: безЯкоря,
                        endDate: безЯкоря, transport: .car)

        let сегодня = Self.десятоеОктября(Self.ницца, час: 12)
        #expect(trip.dayNumber(on: сегодня) == 1,
                "Старая запись из Ниццы обязана читаться первым днём: на этом допущении стоит решение не делать миграцию.")
    }

    /// И то же — от обратного: допущение названо, потому что оно ЛОЖНО
    /// для записи, заведённой **восточнее** Парижа.
    ///
    /// **Первая редакция этого теста брала Лос-Анджелес и упала — права
    /// была она, а не я.** Я перенёс направление из соседней находки,
    /// где западнее был ЧИТАЮЩИЙ; у АВТОРА оно обратное. Незаякоренная
    /// запись лежит ровно на полуночи, поэтому её сдвигает назад любое
    /// смещение к востоку, а к западу — никакое.
    ///
    /// > **Запас у полуночи асимметричен: двенадцать часов в одну сторону
    /// > и ноль в другую.** Ломает уже Москва, один час. Это и есть довод
    /// > за якорь в полдень, который даёт двенадцать в обе.
    @Test("Старая запись, заведённая восточнее, уедет — и это известно")
    func стараяЗаписьВосточнееУезжает() {
        let безЯкоря = Self.десятоеОктября(Self.токио, час: 0)
        let trip = Trip(destination: "Канны", startDate: безЯкоря,
                        endDate: безЯкоря, transport: .car)

        let сегодня = Self.десятоеОктября(Self.токио, час: 12)
        #expect(trip.dayNumber(on: сегодня) != 1,
                "Если здесь 1, допущение «все прежние записи заведены в Ницце» перестало быть нужным — значит завели поле авторского пояса или миграцию. Тогда текст в CalendarDay.дневниковыйПояс устарел и его надо переписать.")
    }

    /// А с запада запаса хватает — и это тоже надо держать, иначе
    /// «уезжает» прочтут как «уезжает в обе стороны» и починят лишнее.
    @Test("Старая запись с запада читается верно — запас там полный")
    func стараяЗаписьЗападаЦела() {
        let безЯкоря = Self.десятоеОктября(Self.лос_анджелес, час: 0)
        let trip = Trip(destination: "Канны", startDate: безЯкоря,
                        endDate: безЯкоря, transport: .car)

        let сегодня = Self.десятоеОктября(Self.лос_анджелес, час: 12)
        #expect(trip.dayNumber(on: сегодня) == 1,
                "Полночь в Лос-Анджелесе — это уже утро в Париже того же числа. Если здесь не 1, асимметрия запаса описана неверно.")
    }

    @Test("Заякоренной записи пояс чтения безразличен — на том и стоит решение")
    func якорьНеЗависитОтПоясаЧтения() {
        let якорь = CalendarDay.anchored(Self.десятоеОктября(Self.ницца, час: 0),
                                         calendar: Self.ницца)
        let trip = Trip(destination: "Канны", startDate: якорь, endDate: якорь, transport: .car)

        for (имя, c) in [("Ницца", Self.ницца), ("Токио", Self.токио),
                         ("Лос-Анджелес", Self.лос_анджелес)] {
            #expect(trip.dayNumber(on: Self.десятоеОктября(c, час: 12), calendar: c) == 1,
                    "В поясе «\(имя)» заякоренная запись дала не первый день — значит устойчивость полудня к ±12 часам нарушена, и всё решение о фиксированном поясе надо пересматривать.")
        }
    }

    // MARK: - Граница этого набора

    /// **Чего он НЕ проверяет, и это надо знать до того, как читать
    /// его зелёным.**
    ///
    /// 1. Он проверяет РАСЧЁТ, а не данные. Поездки, заведённые до 05.10,
    ///    лежат в базе без якоря, и у них день по-прежнему уедет. Миграции
    ///    значений нет — её надо решать отдельно, и это зона схемы.
    /// 2. Моменты (`DayOut.startedAt`, `Episode.lastIncidentAt`) здесь
    ///    не проверяются вовсе: они абсолютны и одинаковы везде
    ///    по устройству. Если кто-то однажды начнёт считать от них
    ///    календарный день, сторож об этом не узнает.
    /// 3. Переход на летнее время не проверяется ни одним случаем:
    ///    все четыре пояса взяты с постоянным смещением
    ///    (`TimeZone(secondsFromGMT:)`). Снимет это набор на именованных
    ///    поясах вокруг последнего воскресенья октября.
    ///
    ///    **И сразу цена этой границы, иначе её прочтут как «вероятно
    ///    сломано».** Полдень выбран в том числе затем, чтобы перевод
    ///    часов до него не доставал: переводят ночью, 02:00–03:00,
    ///    то есть пропадающий или удваиваемый час лежит дальше всего
    ///    от полудня. Полночь ломается при любом сдвиге пояса; полдень
    ///    не ломается ни при сдвиге, ни при переводе, пока разница
    ///    меньше двенадцати часов — а обитаемых поясов дальше не бывает.
    ///    Довод назван `projects-0f`; случай всё равно стоит завести —
    ///    не ради красного, а как опора, когда понадобится.
    @Test("Границы набора названы в коде, а не в чьей-то памяти")
    func границыНазваны() {
        #expect(Bool(true), "Тест-носитель для докстринга выше: границу печатает инструмент, иначе она теряется при первой передаче.")
    }

    /// **Звено, которого в наборе сначала не было, и я это заметил
    /// только перегнав его.**
    ///
    /// Все проверки выше якорят дату САМИ, внутри теста, — то есть
    /// проверяют расчёт и ничего не говорят про то, якорит ли её экран.
    /// Убери `CalendarDay.anchored` из `TripScreens.save()` — и набор
    /// останется зелёным, а у ситтера снова уедет день.
    ///
    /// > Ровно то, на чём мы сидим весь вечер: **тест, который сам зовёт
    /// > функцию, не может проверить, что её зовут.** У Timer так вырезали
    /// > все шесть вызовов `rebuildDerived()` при зелёном наборе.
    ///
    /// Сторож текстовый, и его граница названа здесь: он видит
    /// «вызова нет вовсе» и слеп к «позвали не то значение» и «позвали
    /// не вовремя». Снимет её поведенческий тест над экраном — шва
    /// для него сейчас нет, `save()` приватный и пишет в контекст.
    @Test("Экраны якорят дату при заведении, а не только считают потом")
    func экраныЯкорятДату() throws {
        let места = [
            ("Togo/Features/Trip/TripScreens.swift", "поездка"),
            ("Togo/Features/Feeding/HeatScreen.swift", "течка"),
        ]

        for (путь, что) in места {
            let исходник = try Self.исходник(путь)
            let живые = исходник.split(separator: "\n")
                .map { String($0).trimmingCharacters(in: .whitespaces) }
                .filter { !$0.hasPrefix("//") && !$0.hasPrefix("///") }
                .filter { $0.contains("CalendarDay.anchored") }

            #expect(живые.isEmpty == false,
                    "В «\(что)» (\(путь)) дата заводится без CalendarDay.anchored. Расчёт останется верным, а данные уедут: у семьи западнее владельца день сместится на сутки.")
        }
    }

    private static func исходник(_ относительный: String) throws -> String {
        let тест = URL(fileURLWithPath: #filePath)
        let корень = тест.deletingLastPathComponent().deletingLastPathComponent()
        var файл = корень
        for часть in относительный.split(separator: "/") {
            файл.appendPathComponent(String(часть))
        }
        return try String(contentsOf: файл, encoding: .utf8)
    }
}
