import Testing
import Foundation
import SwiftData
@testable import Togo

/// Служебная запись прогрева не считается данными человека.
///
/// # Это ВТОРОЙ слой, и первый его нарочно не делал
///
/// Слой отправки закрыт 08.10.2026 (`c490e10`) и закрыт честно: маме
/// запись не уедет. В границах того коммита стоит прямо — **«про показ
/// здесь не измерено ничего»**, и его же тест
/// (`ОтладочнаяЗаписьНеУезжаетTests`) называет второй предмет поимённо:
///
///     ЭТОТ набор       запись не УЕЗЖАЕТ маме
///     набор про показ  запись не ломает вердикт у СЕБЯ
///
/// То есть причина отсутствия фильтра показа лежала **в тесте**, а не
/// в голове модуля: `Diary` и `NeedVerdict` о служебных записях молчали
/// оба. Состояние головы было третьим из трёх — «долг, но форма задана»,
/// и оно опаснее остальных, потому что читается как первое.
///
/// Формулировка, которую стоит держать точной: **второго слоя
/// не существовало вовсе** — фильтра по дате вне `#if DEBUG` в проекте
/// не было ни одного. Это не «починка сломалась», это ненаписанная
/// половина.
///
/// # Что ломалось, по живым данным
///
/// Выгрузка с телефона Виктории 08.10.2026 18:22: из 182 записей одна
/// служебная — автор `ПРОГРЕВ СХЕМЫ`, дата `2001-01-01`, у видимой
/// собаки «Стич». Самая ранняя настоящая запись — `2026-09-01`.
///
///     daysOfData         ≈9410 вместо 2
///     minimumDaysOfData  4
///     guard в NeedVerdict проходил ВСЕГДА
///
/// Красная линия Togo — «меньше четырёх дней данных: всегда „непонятно“,
/// приложение не знает лучше хозяина» — становилась **непроходимой
/// вниз**: при двух настоящих событиях приложение выдавало уверенный
/// вердикт. На живом телефоне, в розданной сборке.
///
/// # Якорь взят НЕ от `Diary.active`, и это не придирка
///
/// Правка снимает с `active` роль единственного фильтра, то есть
/// сторож, привязанный к `active`, после починки **ослеп бы, а не
/// покраснел** — а «я ослеп» и «стало хуже» читаются одинаково.
/// Поэтому утверждения стоят на том, чего правка не трогает:
/// на `daysOfData` и на самом факте выдачи вердикта.
///
/// # Два сторожа на одно место — не дублирование
///
///     У1 · предикат   ЗНАЧЕНИЕ: что считается служебным
///     У2 · daysOfData ДОРОГА: служебное не удлиняет историю
///     У3 · вердикт    ПРЕДМЕТ: красная линия проходится вниз
///     У4 · вторая     ДОРОГА-2: `onDayWithTraces` — единственная
///          дверь      функция `Diary` мимо `active`
///
/// Приёмка требует снимать их **по очереди**: подделка, нарушающая
/// ровно одно, — единственное, что отличает два сторожа от одного
/// переписанного дважды.
@MainActor
@Suite("Показ служебной записи")
struct ПоказСлужебнойЗаписиTests {

    /// Та же дата, что у живой находки.
    private var служебная: LogEvent {
        LogEvent(kind: .note,
                 date: Date(timeIntervalSinceReferenceDate: 0), // 2001-01-01
                 authorName: "ПРОГРЕВ СХЕМЫ")
    }

    private func настоящая(_ kind: LogKind, _ сдвигДней: Int,
                           now: Date) -> LogEvent {
        LogEvent(kind: kind,
                 date: now.addingTimeInterval(TimeInterval(-сдвигДней * 24 * 3600)),
                 authorName: "Виктория")
    }

    // MARK: Было ли что проверять

    /// Набор, которому нечего проверять, молчит так же, как набор,
    /// у которого всё хорошо. Поэтому первым — что заготовка правда
    /// несёт служебную запись и правда несёт настоящие.
    @Test("Заготовка несёт и служебную запись, и настоящие")
    func заготовкаНеПуста() {
        let now = Date()
        let события = [служебная, настоящая(.meal, 0, now: now),
                       настоящая(.outing, 1, now: now)]

        #expect(события.count == 3)
        #expect(события.filter { $0.date < Date(timeIntervalSince1970: 1_577_836_800) }.count == 1, """
            в заготовке нет ни одной записи раньше 2020 года — значит
            остальные утверждения этого набора проверяют пустоту
            и зелены, ничего не проверив.
            """)
    }

    // MARK: У1 · ЗНАЧЕНИЕ — что считается служебным

    @Test("Запись раньше приложения служебная, настоящая — нет")
    func предикат() {
        let now = Date()

        #expect(Diary.служебная(служебная), """
            предикат не узнал служебную запись прогрева (01.01.2001).
            Без этого остальные три утверждения опираются на фильтр,
            который ничего не фильтрует.
            """)

        #expect(!Diary.служебная(настоящая(.meal, 0, now: now)), """
            предикат объявил служебной НАСТОЯЩУЮ запись. Это хуже
            пропуска: человек перестанет видеть то, что сам отметил,
            а симптом будет тот же, что у пустого дневника.
            """)
    }

    // MARK: У2 · ДОРОГА — служебное не удлиняет историю

    @Test("Служебная запись не удлиняет историю данных")
    func историяНеРастёт() {
        let now = Date()
        let только1настоящая = [настоящая(.meal, 0, now: now)]
        let сСлужебной = [служебная, настоящая(.meal, 0, now: now)]

        #expect(Diary.daysOfData(только1настоящая, now: now) == 1)
        #expect(Diary.daysOfData(сСлужебной, now: now) == 1, """
            служебная запись удлинила историю: daysOfData дал \
            \(Diary.daysOfData(сСлужебной, now: now)) дней вместо одного.
            Отсюда и шло ≈9410: дата 01.01.2001 становилась началом
            истории дневника, а экран «Данные» печатал это человеку
            как правду о его данных.
            """)
    }

    // MARK: У3 · ПРЕДМЕТ — красная линия проходится вниз

    @Test("Два настоящих события плюс служебная дают «непонятно»")
    func краснаяЛиния() {
        let now = Date()
        let события = [служебная,
                       настоящая(.outing, 0, now: now),
                       настоящая(.meal, 1, now: now)]

        let сигналы = Diary.signals(события, now: now, episodeActive: false)
        let вердикт = VerdictEngine.evaluate(сигналы)

        #expect(сигналы.daysOfData < VerdictEngine.minimumDaysOfData, """
            данных по сигналам \(сигналы.daysOfData) дней при пороге \
            \(VerdictEngine.minimumDaysOfData) — ворота малых данных \
            не закрылись, и дальше вердикт считается по медиане,
            построенной на двух событиях.
            """)

        guard case .unknown(.notEnoughData) = вердикт else {
            Issue.record("""
                красная линия пробита: при двух настоящих событиях
                приложение выдало «\(вердикт)» вместо «непонятно».
                Это то самое «приложение знает лучше хозяина», которого
                Togo обещает не делать, — и выдаёт это уверенным тоном.
                """)
            return
        }
    }

    // MARK: У4 · ДОРОГА-2 — вторая дверь показа

    /// # Почему здесь нельзя проверять «день со смесью записей»
    ///
    /// Первая редакция этого теста клала на день `2001-01-01` служебную
    /// и «настоящую» запись и просила ленту не отдать служебную. Она
    /// **прошла бы и при снятом фильтре**: любая запись, попавшая
    /// на 1 января 2001 года, служебная по самому признаку, то есть
    /// «настоящей» среди них не бывает, лента пуста в обоих случаях.
    ///
    /// Это ровно тот класс, против которого набор и заводится:
    /// утверждение, выполняющееся при отсутствии предмета. Поймано
    /// до прогона, а не им.
    ///
    /// Верная форма — спросить **именно тот день, где служебная
    /// лежит**, и потребовать пусто; плюс контроль на настоящем дне,
    /// иначе «пусто» означало бы, что функция не отдаёт ничего никогда.
    @Test("Лента дня не отдаёт служебную запись")
    func втораяДверь() {
        let день2001 = Date(timeIntervalSinceReferenceDate: 0)
        let сегодня = Date()

        let лента = Diary.onDayWithTraces([служебная, настоящая(.meal, 0, now: сегодня)],
                                          день2001)

        // Контроль: на настоящем дне функция отдаёт настоящую запись.
        // Без него «пусто» ниже говорило бы о функции, а не о фильтре.
        let контроль = Diary.onDayWithTraces([служебная, настоящая(.meal, 0, now: сегодня)],
                                             сегодня)
        #expect(контроль.count == 1, """
            контроль не прошёл: на СЕГОДНЯШНЕМ дне лента отдала \
            \(контроль.count) записей вместо одной настоящей. Значит \
            проверка ниже меряет сломанную функцию, а не фильтр,
            и её «пусто» ничего не доказывает.
            """)

        #expect(лента.isEmpty, """
            `onDayWithTraces` отдала служебную запись. Это единственная
            функция `Diary`, которая не идёт через `active`, — то есть
            вторая дверь показа, и запрет обязан стоять в обеих.
            Сегодня она ничего не меняет (запись датирована 2001 годом,
            а функция ограничена показываемым днём), но запрет в одной
            двери из двух мы уже оплатили: вчера ворота стояли в одной
            из двух дорог наружу, вторая о них не знала, и чужой сторож
            оставался зелёным.
            """)
    }
}
