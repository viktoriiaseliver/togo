import Foundation
import SwiftUI
import Testing
import UIKit
import WidgetKit
@testable import Togo

/// Кадры виджета и «острова» под «Кино» — рядом с эталоном дизайна.
///
/// **Заведено 23.10.2026 вместе с редизайном, и повод тот же, что
/// у `ОстровКадрTests`: у виджета приёмки прогоном не бывает.** Виджет
/// рисует SpringBoard, `app.screenshot()` до него не достаёт, живую
/// активность вне `ActivityKit` не построить вовсе. Поверхность,
/// которую нельзя снять кадром, не проверял никто — и у Того это уже
/// оплачено: отзыв про виджет жил долго **только потому, что смотреть
/// было не на что**.
///
/// > **Тест проверяет, верно ли посчитано; кадр — верно ли сказано.**
/// > У правки, меняющей то, что человек читает, приёмка — кадр,
/// > и зелёный набор её не заменяет.
///
/// Эталон рядом: `Дизайн/эталонные-кадры/ios28-кино-22.10/screenshots/`,
/// кадр `16.png` («Виджеты и Live Activity») и `08.png` (живая пилюля).
///
/// ## Чего эти кадры НЕ доказывают
///
/// 1. **Что столько же влезет на настоящем «острове».** Его ширины
///    принадлежат системе; здесь они заданы рамкой по числам прототипа
///    (232 pt живая пилюля). Кадр отвечает «что написано и как
///    свёрстано», а не «влезет ли».
/// 2. **Что система нарисует наши цвета.** `.activityBackgroundTint` —
///    это **просьба**; поверх неё «остров» рисуется системным вибрантным
///    монохромом. На кадре видно, что отдаёт ПРИЛОЖЕНИЕ.
/// 3. **Что виджет получит столько же места.** Размеры плиток взяты
///    типовые для iPhone, а они зависят от модели и от кегля системы.
///
/// Граница названа здесь, а не оставлена читателю: кадр, принятый
/// за ответ на чужой вопрос, дороже отсутствующего.
@Suite("Кадры виджета и острова под «Кино»")
struct КиноВиджетКадрTests {

    /// Куда ложатся кадры — в дерево, а не в `.xcresult`: кадр
    /// существует, когда он снят И на него посмотрели, а в бандле
    /// на него не смотрит никто.
    ///
    /// **Адрес входа назван в голове нарочно** — тест пишет на диск
    /// через `#filePath`, и уборка каталога ломает его не на его
    /// предмете.
    private static var каталог: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
            .appendingPathComponent("build/кадры-кино-виджеты")
    }

    /// Час фиксирован: кадр, который нельзя повторить, нельзя и сравнить.
    private static let сейчас = Date(timeIntervalSince1970: 1_759_000_000)

    /// Начало выхода — **не** фиксированный час, и это разная природа
    /// с `сейчас`.
    ///
    /// `Text(_, style: .timer)` считает от переданной даты до
    /// НАСТОЯЩЕГО момента, а не до `сейчас`. Поставь сюда фиксу —
    /// и кадр покажет число, которое растёт каждый день и выжирает
    /// ширину, какой у настоящего таймера не бывает (замер 07.10.2026,
    /// вышло с первого раза).
    ///
    /// Двадцать три минуты — правдоподобная прогулка и устойчивая
    /// ширина: две цифры, двоеточие, две цифры.
    private static var началоВыхода: Date { Date().addingTimeInterval(-23 * 60) }

    /// Последний выход — два часа одиннадцать минут назад, ровно как
    /// на эталоне `16.png` («С прогулки · 2:11»).
    private static var последнийВыход: Date {
        Date().addingTimeInterval(-(2 * 3600 + 11 * 60))
    }

    // MARK: - Отрисовка

    /// Снять кадр вида в названной теме.
    ///
    /// Приём взят у `ОстровКадрTests` и `EmptyStateFrameTests` НЕ
    /// из экономии: третья реализация сломается так же, как первые две.
    /// Суть — отрисовка **внутри** нужной `UITraitCollection`: токены
    /// это динамические `UIColor`, и разрешаются они
    /// по `UITraitCollection.current`, а не по окружению SwiftUI.
    /// Тест, просящий тёмную через `.environment`, напечатал бы
    /// «тёмная» и отрисовал светлое.
    ///
    /// **`высота` необязательна, и это починка по кадру, а не вкус.**
    /// Первая редакция давала карточке блокировки 120 pt — меньше её
    /// собственной высоты (16 + 44 + 12 + 44 + 16 = 132). SwiftUI сжал
    /// содержимое, и с кадра пропали **заголовок и таймер**. Кадр при
    /// этом получился: непустой, с аватаром, подписью и двумя кнопками,
    /// то есть выглядел как приёмка, а не как отказ.
    ///
    /// > **Кадр, снятый в чужой рамке, отвечает про рамку.** Высота,
    /// > взятая из головы, молча превращает «вид не влезает в мои 120»
    /// > в «вид потерял заголовок». `nil` — значит вид меряет себя сам,
    /// > и тогда на кадре видно его НАСТОЯЩУЮ высоту. Фиксированная
    /// > остаётся только там, где рамку задаёт система: плитки виджета
    /// > (158×158, 338×158) и пилюля «острова» (37 pt).
    ///
    /// **Фон — явный `.black`, а не `Token.Surface.screen`, и это тоже
    /// замер.** В первой редакции токен стоял ЗНАЧЕНИЕМ ПО УМОЛЧАНИЮ,
    /// то есть вычислялся на месте вызова — **снаружи**
    /// `performAsCurrent`. Вышел кадр, где текст разрешился по тёмной
    /// (`Ink.secondary` = `#C7C7CC`), а фон по светлой (`#FFFFFF`):
    /// светло-серое по белому, почти нечитаемо. Половина кадра знала
    /// про тёмную тему, половина нет.
    ///
    /// `#000000` — не выдумка и не «прибитый цвет в продукте»: это
    /// замеренное значение фона «Кино» на эталоне `16.png` и значение
    /// `--surface-background` в пакете. Здесь он стоит в ТЕСТЕ, чтобы
    /// подложка была заведомо однозначной и кадр показывал разрешение
    /// токенов САМОГО ВИДА, а не ещё и подложки.
    @discardableResult
    private func снять<V: View>(_ вид: V, имя: String,
                                ширина: CGFloat, высота: CGFloat? = nil,
                                схема: ColorScheme = .dark,
                                счёт: inout [String]) throws -> URL {
        let стиль: UIUserInterfaceStyle = схема == .dark ? .dark : .light
        var нарисованное: UIImage?
        UITraitCollection(userInterfaceStyle: стиль).performAsCurrent {
            let отрисовщик = ImageRenderer(
                content: вид
                    .environment(\.colorScheme, схема)
                    .frame(width: ширина, height: высота)
                    .background(схема == .dark ? Color.black : Color.white)
            )
            отрисовщик.scale = 2
            нарисованное = отрисовщик.uiImage
        }
        let картинка = try #require(нарисованное, "ImageRenderer не отдал картинку для «\(имя)»")
        let данные = try #require(картинка.pngData(), "картинка «\(имя)» не стала PNG")
        try FileManager.default.createDirectory(at: Self.каталог,
                                                withIntermediateDirectories: true)
        let путь = Self.каталог.appendingPathComponent("\(имя).png")
        try данные.write(to: путь)
        счёт.append(имя)
        return путь
    }

    /// Счёт снятого. **Печатается всегда, в том числе после падения** —
    /// «снято шесть» и «упал на третьем, снято два» выглядят в логе
    /// одинаково, потому что во втором случае строки про кадры просто
    /// нет, **а её отсутствия никто не ищет**. Поэтому вызов стоит
    /// в `defer`, а не в конце тела.
    ///
    /// **Счёт локальный для теста, а не общий на набор, и это починка
    /// по правилу, а не стиль.** Swift Testing волен гнать `@Test`
    /// параллельно; общий изменяемый `static` был бы гонкой данных —
    /// и, что хуже для приёмки, печатал бы сумму чужих кадров как свою.
    /// Тогда «снято 12 из 12» означало бы «кто-то снял двенадцать»,
    /// а не «этот тест снял свои».
    private func печатьСчёта(_ имена: [String], ожидалось: Int) {
        print("КАДРОВ СНЯТО: \(имена.count) из \(ожидалось) · \(имена.joined(separator: ", "))")
    }

    // MARK: - Первым: было ли что рисовать

    /// **Ставится первой.** Пустая картинка весит мало и выглядит
    /// как кадр; без этой проверки остальные молчали бы так же,
    /// как при всём хорошем.
    @Test("Отрисовщику было что рисовать")
    func былоЧтоРисовать() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 1) }
        let путь = try снять(
            WalkActivityView(dogName: "Стич", startedBy: "Виктория",
                             startedAt: Self.началоВыхода, tally: nil),
            имя: "00-контроль", ширина: 360, счёт: &счёт)
        let вес = try FileManager.default.attributesOfItem(atPath: путь.path)[.size] as? Int ?? 0
        #expect(вес > 3000,
                "кадр весит \(вес) байт — для карточки с текстом это пустая картинка")
    }

    // MARK: - Живая активность

    /// Карточка блокировки — три состояния, как в галерее.
    ///
    /// Пустая кличка стоит третьей не для полноты: отзыв 06.10 пришёл
    /// про безымянные записи, а подпись и заголовок карточки собираются
    /// из клички — то есть это ровно то место, где дефект выходит
    /// на самую тесную поверхность продукта.
    @Test("Карточка блокировки под «Кино» — три состояния")
    func карточкаБлокировки() throws {
        let состояния: [(String, String, String?)] = [
            ("01-карточка-без-отметок", "Стич", nil),
            ("02-карточка-с-отметками", "Стич", "моча 2 · стул"),
            ("03-карточка-кличка-пустая", "", nil),
        ]
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: состояния.count) }
        for (имя, кличка, tally) in состояния {
            try снять(
                WalkActivityView(dogName: кличка, startedBy: "Виктория",
                                 startedAt: Self.началоВыхода, tally: tally),
                имя: имя, ширина: 360, счёт: &счёт)
        }
    }

    /// Свёрнутая пилюля — эталон `08.png`.
    ///
    /// Ширина 232 pt взята из прототипа (`Togo-RU.dc.html:747`),
    /// высота 37 — оттуда же. Это числа МАКЕТА, а не WidgetKit:
    /// настоящий бюджет свёрнутого «острова» принадлежит системе
    /// и зависит от модели телефона.
    @Test("Свёрнутая пилюля «острова» — зелёное время")
    func свёрнутаяПилюля() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 2) }
        try снять(
            HStack {
                WalkIslandView.CompactLeading()
                Spacer(minLength: 12)
                WalkIslandView.CompactTrailing(startedAt: Self.началоВыхода)
            }
            .padding(.horizontal, 14)
            .foregroundStyle(Token.Ink.primary),
            имя: "04-пилюля-свёрнутая", ширина: 232, высота: 37, счёт: &счёт)

        try снять(WalkIslandView.Minimal(),
                  имя: "05-пилюля-минимальная", ширина: 44, высота: 37, счёт: &счёт)
    }

    /// Развёрнутый «остров» — три области, каждая отдельно.
    ///
    /// Собрать их в один вид нельзя: `DynamicIslandExpandedRegion`
    /// принимает содержимое по одной области. Значит и кадром их надо
    /// брать порознь, иначе «сняли остров» будет значить «сняли треть».
    @Test("Развёрнутый «остров» — три области")
    func развёрнутыйОстров() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 1) }
        try снять(
            VStack(alignment: .leading, spacing: 6) {
                HStack {
                    WalkIslandView.Leading(dogName: "Стич")
                    Spacer(minLength: 0)
                    WalkIslandView.Trailing(startedAt: Self.началоВыхода)
                }
                WalkIslandView.Bottom(startedBy: "Виктория",
                                      dogName: "Стич", tally: "моча 2")
            }
            .padding(12)
            .foregroundStyle(Token.Ink.primary),
            имя: "06-остров-развёрнутый", ширина: 360, счёт: &счёт)
    }

    // MARK: - Виджет

    /// Малая плитка — четыре состояния, включая тишину.
    ///
    /// **Ступень тишины здесь не для полноты.** Это единственное
    /// состояние, в котором крупного числа нет вовсе и плитка переходит
    /// на слова; оно же — то, ради чего заводилась галерея виджета,
    /// и то, на котором виджет однажды печатал число из отсутствия
    /// записи.
    @Test("Малая плитка под «Кино» — четыре состояния")
    func малаяПлитка() throws {
        let состояния: [(String, WidgetSnapshot)] = [
            ("07-малая-на-улице", Self.наУлице),
            ("08-малая-с-прогулки", Self.сПрогулки),
            ("09-малая-натощак", Self.натощак),
            ("10-малая-тишина", Self.тишина),
        ]
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: состояния.count) }
        for (имя, снимок) in состояния {
            try снять(
                TodayWidgetView(snapshot: снимок, family: .systemSmall,
                                now: Self.сейчас)
                    .padding(14),
                имя: имя, ширина: 158, высота: 158, счёт: &счёт)
        }
    }

    /// Средний виджет — тот, которому макет отдал опознание собаки.
    @Test("Средний виджет под «Кино»")
    func среднийВиджет() throws {
        var счёт: [String] = []
        defer { печатьСчёта(счёт, ожидалось: 2) }
        try снять(
            TodayWidgetView(snapshot: Self.сПрогулки, family: .systemMedium,
                            now: Self.сейчас)
                .padding(.horizontal, 16)
                .padding(.vertical, 14),
            имя: "11-средний-с-прогулки", ширина: 338, высота: 158, счёт: &счёт)

        // Длинная кличка — переменная часть, и бюджет, померенный
        // коротким именем, есть не у всех собак.
        var длинная = Self.сПрогулки
        длинная.dogName = "Белладонна"
        try снять(
            TodayWidgetView(snapshot: длинная, family: .systemMedium,
                            now: Self.сейчас)
                .padding(.horizontal, 16)
                .padding(.vertical, 14),
            имя: "12-средний-длинная-кличка", ширина: 338, высота: 158, счёт: &счёт)
    }

    // MARK: - Снимки

    private static var основа: WidgetSnapshot {
        var s = WidgetSnapshot.empty
        s.dogName = "Стич"
        s.dogInitial = "С"   // ЧИТАТЕЛЯ-НЕТ-dogInitial: кадр его не покажет
        s.verdictTitle = "Скорее просится"
        s.mealsToday = 1
        s.mealsPlanned = 2
        s.lastMealAt = сейчас.addingTimeInterval(-3 * 3600)
        return s
    }

    /// Выход идёт прямо сейчас.
    private static var наУлице: WidgetSnapshot {
        var s = основа
        s.walkStartedAt = началоВыхода
        s.lastWalkAt = последнийВыход
        s.sinceUrineSeconds = 2 * 3600
        return s
    }

    /// Обычный день: два часа одиннадцать минут с прогулки — как
    /// на эталоне.
    private static var сПрогулки: WidgetSnapshot {
        var s = основа
        s.lastWalkAt = последнийВыход
        s.sinceUrineSeconds = 2 * 3600 + 11 * 60
        return s
    }

    /// Окно «не кормить» открыто — низ плитки обязан отдать его еде.
    private static var натощак: WidgetSnapshot {
        var s = сПрогулки
        s.fastingEndsAt = сейчас.addingTimeInterval(40 * 60)
        return s
    }

    /// Дневник забросили: отметок мочи нет восемнадцать дней,
    /// выходов тоже. Крупного числа нет — плитка говорит словами.
    private static var тишина: WidgetSnapshot {
        var s = основа
        s.verdictTitle = "Непонятно"
        s.lastWalkAt = nil
        s.sinceUrineSeconds = 434 * 3600
        s.urineSilenceSince = сейчас.addingTimeInterval(-434 * 3600)
        s.lastMealAt = сейчас.addingTimeInterval(-437 * 3600)
        return s
    }
}
