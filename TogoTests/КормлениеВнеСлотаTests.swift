    @Test("Одна запись не закрывает два слота даже при бесконечном окне")
    func однаЗаписьЗакрываетОдинСлот() {
        // ОКНО ПОДМЕНЕНО НАРОЧНО. После перехода на ячейки соседние окна
        // не пересекаются, и прежняя подделка («снять usedRecords»)
        // перестала краснеть сама собой — инвариант держится устройством.
        //
        // > **Сторож, у которого подделка больше не проходит, выглядит
        // > исправным и не сторожит ничего.** Инъекция окна возвращает
        // > ему зубы: окно держит ЗНАЧЕНИЕ, `usedRecords` держит ДВЕРЬ,
        // > и ломать их надо по отдельности.
        let часы = [660, 720, 780]              // 11:00 · 12:00 · 13:00
        let разметка = MealSchedule.разметить(
            planned: часы,
            logged: [время(725)],               // 12:05
            startOfDay: день(),
            окно: { _ in .infinity })

        #expect(разметка.done.filter { $0 }.count == 1, """
            при бесконечном окне одна запись закрыла \
            \(разметка.done.filter { $0 }.count) слота из трёх. \
            Правило «одна запись — ровно один пункт» держится \
            `usedRecords`, и держать его обязано оно, а не геометрия \
            окон.
            """)
    }

