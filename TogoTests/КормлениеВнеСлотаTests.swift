/// Запись о кормлении вне часа закрывает свой слот — и говорит, какая
/// именно запись его закрыла.
///
/// # Чем оплачено
///
/// Отзыв 30.10.2026, сборка 289, дословно: «2 раза покормила собаку,
/// пусть в другое время. Пусть приложение предложит либо сдвинуть ужин
/// пропорционально или недокормить ужин или кормить по расписанию.
/// А обед отметить как Дан».
///
/// ```
/// её часы            09:30 · 15:30 · 21:30   промежуток 360 мин
/// запись             18:00
/// до 15:30           150 мин  > 90 (прежний допуск)  → слот свободен
/// до 21:30           210 мин  > 90                   → слот свободен
/// ```
///
/// Человек покормил — приложение держало в плане дня ДВА незакрытых
/// пункта еды. Цена не косметическая: собака на заместительной
/// терапии, и двойное кормление здесь — медицинское событие.
///
/// # Что сменилось
///
/// Плоский допуск 90 минут заменён **окном слота**: полпути до соседа
/// в обе стороны по кругу суток, но не больше потолка в три часа.
/// Правило подстраивается под расписание само — 180 минут у трёх
/// кормлений, 30 минут у щенка с кормлениями в часе друг от друга.
///
/// # Чего эти тесты НЕ проверяют
///
/// Саму развилку «сдвинуть ужин · недокормить · оставить по
/// расписанию». Любой её выход, кроме «оставить», надо ЗАПОМНИТЬ
/// на сегодня, а места для разового исключения на дату в схеме нет.
/// Решение Виктории 04.11.2026: держать разовым исключением на дату,
/// а не считать от факта и не класть в настройки; поле под него —
/// отдельный вопрос, и схему без него не трогают.
///
/// Проверяется здесь **то, что от развилки не зависит**: приложение
/// называет исход вслух (`Промежуток`) и говорит правду о том, что
/// одна из трёх веток отзыва на её расписании не меняет ничего
/// (`сдвигПоследнегоКормленияУпираетсяВПредел`).
@Suite("Кормление вне слота")
struct КормлениеВнеСлотаTests {

    /// Её расписание из отзыва, в минутах от полуночи.
    private static let ЕЁ_ЧАСЫ = [570, 930, 1290]   // 09:30 · 15:30 · 21:30

    private func день() -> Date {
        Calendar.current.startOfDay(for: Date())
    }

    private func время(_ минута: Int) -> Date {
        Calendar.current.date(byAdding: .minute, value: минута, to: день())!
    }

