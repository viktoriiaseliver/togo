import Testing
import Foundation
@testable import Togo

/// Запись о кормлении вне часа закрывает свой слот — и говорит, какая
/// именно запись его закрыла.
///
/// # Чем оплачено
///
/// Отзыв 30.10.2026, сборка 289, дословно: «2 раза покормила собаку,
/// пусть в другое время. Пусть приложение предложит либо сдвинуть ужин
/// пропорционально или недокормить ужин или кормить по расписанию.
/// А обед отметить как Дан».
///
/// ```
/// её часы            09:30 · 15:30 · 21:30   промежуток 360 мин
/// запись             18:00
/// до 15:30           150 мин  > 90 (прежний допуск)  → слот свободен
/// до 21:30           210 мин  > 90                   → слот свободен
/// ```
///
/// Человек покормил — приложение держало в плане дня ДВА незакрытых
/// пункта еды. Цена не косметическая: собака на заместительной
/// терапии, и двойное кормление здесь — медицинское событие.
///
/// # Что сменилось
///
/// Плоский допуск 90 минут заменён **окном слота**: полпути до соседа
/// в обе стороны по кругу суток, но не больше потолка в три часа.
/// Правило подстраивается под расписание само — 180 минут у трёх
/// кормлений, 30 минут у щенка с кормлениями в часе друг от друга.
///
/// # Чего эти тесты НЕ проверяют
///
/// Вторую половину отзыва — развилку «сдвинуть ужин · недокормить ·
/// оставить по расписанию». Она требует хранения разового решения дня,
/// и место для него — решение Виктории (App Group против новой версии
/// схемы). Здесь закрыт дефект, а не исполнено пожелание.
@Suite("Кормление вне слота")
struct КормлениеВнеСлотаTests {

    /// Её расписание из отзыва, в минутах от полуночи.
    private static let ЕЁ_ЧАСЫ = [570, 930, 1290]   // 09:30 · 15:30 · 21:30

    private func день() -> Date {
        Calendar.current.startOfDay(for: Date())
    }

    private func время(_ минута: Int) -> Date {
        Calendar.current.date(byAdding: .minute, value: минута, to: день())!
    }

    // MARK: Контроль первым

    @Test("Разметке было что размечать")
    func былоЧтоРазмечать() {
        let разметка = MealSchedule.разметить(
            planned: Self.ЕЁ_ЧАСЫ,
            logged: [время(570)],
            startOfDay: день())

        #expect(разметка.закрыто.count == 3, """
            слотов в разметке \(разметка.закрыто.count) при трёх \
            запланированных: разбор не состоялся, и всё остальное \
            в этом наборе меряет собственный промах.
            """)
        #expect(разметка.done[0], """
            запись ровно в час слота его не закрыла — сломано само \
            сопоставление, а не окно.
            """)
    }

    // MARK: Ось

    @Test("Кормление в 18:00 закрывает слот 15:30")
    func обедВ18ЗакрываетСлот1530() {
        let разметка = MealSchedule.разметить(
            planned: Self.ЕЁ_ЧАСЫ,
            logged: [время(1080)],          // 18:00
            startOfDay: день())

        #expect(разметка.done == [false, true, false], """
            разметка \(разметка.done) при ожидаемой [false, true, false].

            Это предмет отзыва 30.10.2026: кормление в 18:00 отстоит \
            от слота 15:30 на 150 минут. Прежний плоский допуск \
            в 90 минут его не брал, и человек видел в плане дня два \
            незакрытых пункта еды после того, как покормил.
            """)
        #expect(разметка.закрыто[1] == 0, """
            слот закрыт, а какой записью — не сказано. Без этого \
            снятие отметки и итог смены ищут запись заново, каждый \
            по своему правилу.
            """)
    }

    @Test("Ночь слот не закрывает: окно упирается в потолок")
    func окноНеШирееПотолка() {
        // Половина ночного промежутка у трёх кормлений — 540 минут.
        // Без потолка запись в 00:30 закрыла бы завтрак в 09:30.
        let разметка = MealSchedule.разметить(
            planned: Self.ЕЁ_ЧАСЫ,
            logged: [время(30)],            // 00:30
            startOfDay: день())

        #expect(разметка.done == [false, false, false], """
            разметка \(разметка.done): запись в 00:30 закрыла слот. \
            Половина ночи — 540 минут, и без потолка «покормила ночью» \
            означало бы «позавтракала».
            """)
    }

    @Test("Щенку окно сжимается само")
    func частоКормятОкноУже() {
        // Пять кормлений с промежутком в час: окно обязано стать 30 мин,
        // иначе одна запись накроет соседние слоты.
        let часы = [480, 540, 600, 660, 720]    // 08:00 … 12:00
        let разметка = MealSchedule.разметить(
            planned: часы,
            logged: [время(545)],               // 09:05
            startOfDay: день())

        #expect(разметка.done.filter { $0 }.count == 1, """
            закрыто слотов \(разметка.done.filter { $0 }.count) при одной \
            записи. Окно обязано сжиматься вместе с расписанием: \
            это тот самый урок, ради которого `matchDone` и писали — \
            «у щенка с пятью кормлениями одна запись закрывала сразу два \
            пункта, день выглядел выполненным».
            """)
        #expect(разметка.done[1], "закрылся не тот слот: \(разметка.done)")
    }

    @Test("Одна запись не закрывает два слота даже при бесконечном окне")
    func однаЗаписьЗакрываетОдинСлот() {
        // ОКНО ПОДМЕНЕНО НАРОЧНО. После перехода на ячейки соседние окна
        // не пересекаются, и прежняя подделка («снять usedRecords»)
        // перестала краснеть сама собой — инвариант держится устройством.
        //
        // > **Сторож, у которого подделка больше не проходит, выглядит
        // > исправным и не сторожит ничего.** Инъекция окна возвращает
        // > ему зубы: окно держит ЗНАЧЕНИЕ, `usedRecords` держит ДВЕРЬ,
        // > и ломать их надо по отдельности.
        let часы = [660, 720, 780]              // 11:00 · 12:00 · 13:00
        let разметка = MealSchedule.разметить(
            planned: часы,
            logged: [время(725)],               // 12:05
            startOfDay: день(),
            окно: { _ in .infinity })

        #expect(разметка.done.filter { $0 }.count == 1, """
            при бесконечном окне одна запись закрыла \
            \(разметка.done.filter { $0 }.count) слота из трёх. \
            Правило «одна запись — ровно один пункт» держится \
            `usedRecords`, и держать его обязано оно, а не геометрия \
            окон.
            """)
    }

    @Test("Один слот в расписании работает по потолку")
    func одинСлотНеПадает() {
        let разметка = MealSchedule.разметить(
            planned: [720],                     // одно кормление в 12:00
            logged: [время(840)],               // 14:00 — два часа спустя
            startOfDay: день())

        #expect(разметка.done == [true], """
            у одного слота соседа нет, и окно обязано падать \
            на потолок в три часа. Получено \(разметка.done).
            """)
    }

    @Test("Окно слота считается по соседям, а не по константе")
    func окноСчитаетсяПоСоседям() {
        let широко = MealSchedule.окно(planned: Self.ЕЁ_ЧАСЫ, слот: 1)
        let узко = MealSchedule.окно(planned: [480, 540, 600], слот: 1)

        #expect(широко == 180 * 60, """
            окно слота 15:30 при промежутке 6 часов вышло \
            \(широко / 60) мин, ожидалось 180 (потолок).
            """)
        #expect(узко == 30 * 60, """
            окно слота 09:00 при промежутке 1 час вышло \(узко / 60) мин, \
            ожидалось 30 — полпути до соседа.
            """)
    }
}
