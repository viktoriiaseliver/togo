    // MARK: Ветка отзыва, которая ничего не меняет

    /// **Одна из трёх веток отзыва на её данных бесполезна, и причина
    /// не в арифметике сдвига.**
    ///
    /// Замер 04.11.2026, настоящим `MealSchedule` на коммите `3c5a2ad6`,
    /// с живыми контролями:
    ///
    /// ```
    /// её случай (обед съехал)       двинулось 0 кормлений из 1
    /// контроль: съехал ЗАВТРАК      обед 15:30 → 17:00, ужин не двинулся
    /// контроль: два кормления в день   19:30 → 21:00
    /// ```
    ///
    /// Механизм: последнее кормление **сжатого** расписания стоит ровно
    /// на `latestMeal` = отбой − `beforeSleep`. Двигать его вперёд
    /// некуда по устройству, и «сдвинуть пропорционально» у неё
    /// упирается в потолок всегда — потому что съехал предпоследний
    /// пункт, а оставшийся единственный и есть последний.
    ///
    /// > **Кнопка, которая ничего не меняет, хуже отсутствия кнопки.**
    /// > Поэтому развилку человеку рисовать из этих трёх веток нельзя:
    /// > различаются по исходу не три, а две.
    ///
    /// Решение Виктории («сегодня ужин в 22:00») этот потолок ПРОБИВАЕТ:
    /// 22:00 позже предела 21:30. Значит разовое исключение — не
    /// производная расписания, а слово человека, и считать его от факта
    /// нельзя по устройству.
    @Test("«Сдвинуть ужин» упирается в предел: последнее кормление уже на нём")
    func сдвигПоследнегоКормленияУпираетсяВПредел() throws {
        let подъём = 9 * 60, отбой = 23 * 60
        let часы = MealSchedule.evenTimes(mealsPerDay: 3, wake: подъём, sleep: отбой)
        let предел = MealSchedule.latestMeal(wake: подъём, sleep: отбой)

        #expect(часы == Self.ЕЁ_ЧАСЫ, """
            раскладка дала \(часы) вместо её часов \(Self.ЕЁ_ЧАСЫ). \
            Дальше меряется чужое расписание, а вывод уйдёт про её.
            """)
        // Опциональность снимается ДО сравнения — разбор формы
        // у `ужинПослеОбедаВнеЧаса`. Здесь это важнее вдвое: ниже
        // стоит `!=`, а он той же формой дал бы ложный ЗЕЛЁНЫЙ,
        // то есть контроль перестал бы уметь краснеть.
        let последнее = try #require(часы.last, "раскладка вернула пустой список часов")
        #expect(последнее == предел, """
            последнее кормление \(последнее) и предел еды \(предел) \
            разошлись. Если они разойдутся по-настоящему, «сдвинуть \
            ужин» начнёт двигать — и эту запись надо переписать, \
            а не удалить.
            """)

        // КОНТРОЛЬ В ДРУГОМ КАНАЛЕ: запас до предела бывает, и тогда
        // сдвигать есть куда. Без него «ноль сдвига» неотличим от
        // «сравнение всегда истинно».
        let двуразовое = MealSchedule.evenTimes(mealsPerDay: 2, wake: 7 * 60, sleep: отбой)
        let пределДвух = MealSchedule.latestMeal(wake: 7 * 60, sleep: отбой)
        let последнееДвух = try #require(двуразовое.last, "раскладка на два кормления пуста")
        #expect(последнееДвух != пределДвух, """
            у двух кормлений в день последнее тоже встало на предел \
            (\(двуразовое) при пределе \(пределДвух)). Тогда проверка \
            выше истинна при любом расписании и не сторожит ничего.
            """)
        #expect(пределДвух - последнееДвух == 120, """
            запас до предела \(пределДвух - последнееДвух) мин вместо \
            120. Число названо заранее: 19:30 против предела 21:30. \
            Без него «не равно» прошло бы и на разнице в минуту, \
            то есть контроль был бы украшением.
            """)
        #expect(MealSchedule.isCompressed(mealsPerDay: 3, wake: подъём, sleep: отбой), """
            её расписание перестало считаться сжатым. Именно сжатие \
            и прибивает последнее кормление к пределу — без него \
            вывод про бесполезность сдвига держаться не на чем.
            """)
        #expect(!MealSchedule.isCompressed(mealsPerDay: 2, wake: 7 * 60, sleep: отбой), """
            расписание на два кормления объявлено сжатым — тогда \
            контроль выше меряет то же самое, что предмет, и ломается \
            вместе с ним.
            """)
    }
}

/// Промежуток доезжает до пункта плана, а не только считается.
///
/// **Отдельный набор, потому что `DayPlanBuilder.items` — `@MainActor`.**
/// И отдельный он не ради изоляции: без него `Промежуток` был бы
/// «полем без читателя» — грепом находится в объявлении, выглядит
/// подключённым, а вход в него не проверял никто.
@Suite("Промежуток доезжает до плана дня")
@MainActor
struct ПромежутокВПланеДняTests {

    private func время(_ минута: Int) -> Date {
        Calendar.current.date(byAdding: .minute, value: минута,
                              to: Calendar.current.startOfDay(for: Date()))!
    }

    private func стич() -> Dog {
        let dog = Dog(name: "Стич", weightKg: 4.1)
        dog.mealsPerDay = 3
        dog.mealTimes = [570, 930, 1290]            // 09:30 · 15:30 · 21:30
        dog.wakeMinuteOfDay = 9 * 60
        dog.sleepMinuteOfDay = 23 * 60
        return dog
    }

    private func еда(_ минута: Int) -> LogEvent {
        LogEvent(kind: .meal, date: время(минута), authorName: "Виктория")
    }

    /// Опциональность снимается `try #require` ДО сравнения — разбор
    /// формы у `ужинПослеОбедаВнеЧаса`.
    @Test("Ужин несёт промежуток, завтрак — нет")
    func ужинНесётПромежуток() throws {
        let пункты = DayPlanBuilder.items(dog: стич(),
                                          events: [еда(570), еда(1080)],   // 09:30 и 18:00
                                          now: время(1110))                // 18:30
        let еды = пункты.filter { $0.kind == .meal }

        #expect(еды.count == 3, """
            пунктов еды \(еды.count) при трёх кормлениях в расписании: \
            план дня не собрался, и всё ниже меряет собственный промах.
            """)
        #expect(еды.first?.промежуток == nil, """
            у завтрака появился промежуток. Прошлого кормления в этих \
            сутках у него нет.
            """)

        let ужин = try #require(еды.last?.промежуток, """
            ужин пришёл из сборщика БЕЗ промежутка. Считает его \
            `MealSchedule`, а ДОВОЗИТ сюда сборщик — и ровно этого \
            довоза не проверял бы никто: поле осталось бы объявленным \
            и пустым, а строка в плане дня не появилась бы ни разу.
            """)
        #expect(ужин.стоитНазвать, """
            промежуток ужина доехал, но назвать его не предлагается: \
            расхождение \(ужин.расхождение / 60) мин при пороге \
            \(ужин.порог / 60) мин.
            """)
        #expect(ужин.выйдет == 210 * 60, """
            сборщик привёз \(ужин.выйдет / 60) мин вместо 210. \
            Считать надо от записи, закрывшей ПРЕДЫДУЩИЙ пункт, \
            а не от последней записи о еде.
            """)
    }
}
