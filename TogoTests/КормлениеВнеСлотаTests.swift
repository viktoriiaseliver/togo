    // MARK: Исход называется вслух

    /// Контроль первым: `промежуток` вообще что-то считает.
    ///
    /// Контроль **умеет покраснеть**: он требует неотрицательного
    /// `nil`-ответа там, где все входы законны. Отдай функция `nil`
    /// по любой причине — ошибка в `guard`, промах индекса, — и дальше
    /// каждый `#expect` этого раздела мерил бы `nil ?? false`,
    /// то есть собственный промах.
    @Test("Промежутку было что считать")
    func промежуткуБылоЧтоСчитать() {
        let п = MealSchedule.промежуток(planned: Self.ЕЁ_ЧАСЫ, слот: 2,
                                        фактПрошлого: время(930),   // ровно в час
                                        датаСлота: время(1290))

        #expect(п != nil, """
            промежуток не посчитался при трёх законных входах: \
            расписание из трёх часов, второй слот, факт ровно в час \
            предыдущего. Всё, что ниже в этом разделе, меряет \
            собственный промах, а не продукт.
            """)
        #expect(п?.стоитНазвать == false, """
            кормление РОВНО В ЧАС предыдущего слота дало расхождение \
            \((п?.расхождение ?? 0) / 60) мин. При нуле расхождения \
            говорить нечего, и строка в плане дня была бы шумом \
            на каждом здоровом дне.
            """)
    }

    /// **`#expect(опционал == целочисленное выражение)` даёт `false`
    /// при РАВНЫХ числах, и это замер 04.11.2026, а не осторожность.**
    ///
    /// Первая редакция этого теста писала `п?.выйдет == 210 * 60`
    /// и покраснела, напечатав собственные операнды рядом:
    ///
    /// ```
    /// п?.выйдет → 12600.0   some  → 12600.0
    /// 210 * 60  → 12600     value → 12600
    /// ```
    ///
    /// Контроли на той же форме (свободные обобщённые параметры
    /// по обе стороны, как в развёртке `#expect`):
    ///
    /// ```
    /// Double? против 210 * 60        false   ← предмет
    /// Double? против Double?         true    ← путь исправен
    /// Bool?   против true            true    ← почему соседний
    ///                                          `стоитНазвать` прошёл
    /// ```
    ///
    /// Механизм НЕ установлен и здесь не назван: объяснение, придуманное
    /// к верному замеру, наследует его достоверность и своей не имеет.
    /// Установлена **форма**: опционал слева, целочисленный литерал
    /// справа. Лечится не знанием, а формой — `try #require` снимает
    /// опциональность до сравнения.
    ///
    /// > **Врёт она в сторону ложного КРАСНОГО, а зеркало той же формы
    /// > (`!=`) дало бы ложный зелёный** — и его никто бы не искал.
    @Test("Ужин после обеда в 18:00: 3 ч 30 мин вместо шести — и это говорится")
    func ужинПослеОбедаВнеЧаса() throws {
        let п = try #require(MealSchedule.промежуток(planned: Self.ЕЁ_ЧАСЫ, слот: 2,
                                                     фактПрошлого: время(1080),  // 18:00
                                                     датаСлота: время(1290)),    // 21:30
                             "промежуток не посчитался на законных входах")

        #expect(п.выйдет == 210 * 60, """
            до ужина выйдет \(п.выйдет / 60) мин, ожидалось 210. \
            Это предмет второй половины отзыва 30.10: обед съехал \
            на 18:00, ужин остался в 21:30, и собака получает еду \
            через три с половиной часа вместо шести.
            """)
        #expect(п.поРасписанию == 360 * 60, """
            по расписанию между 15:30 и 21:30 вышло \
            \(п.поРасписанию / 60) мин вместо 360. Без второго \
            числа у первого нет оси: «3 ч 30 мин» в одиночку читается \
            как «через 3 ч 30 мин от сейчас».
            """)
        #expect(п.стоитНазвать, """
            расхождение \(п.расхождение / 60) мин при пороге \
            \(п.порог / 60) мин признано несущественным. \
            Молчание здесь — ровно тот дефект, о котором отзыв: \
            человек покормил не в час, приложение заметило это \
            на ЗАКРЫТОМ пункте (а он свёрнут под «сделано · N») \
            и ничего не сказало на том, который ещё впереди.
            """)
    }

