import Testing
import Foundation

/// Эталон прогона ссылается на живые тесты, а имена тестов уникальны.
///
/// # Чего стоило отсутствие этого сторожа
///
/// Замер 09.10.2026. В `Tools/эталон-прогона.json` лежала запись
/// `[DesignLiteralTests] «Размеры вне токенов не растут»` — **теста
/// с таким именем в проекте не существует**, имя жило только в самом
/// эталоне и в журнале.
///
/// Сверка сопоставляет **точным именем** (`ожидаемые = {з["тест"]: з}`).
/// Значит запись:
///
/// ```
/// совпасть не могла НИКОГДА  → каждый прогон печатал «ожидаемо
///                              красный ПОЗЕЛЕНЕЛ»
/// настоящий красный          → «Кеглей, радиусов и размеров числом
/// не покрывала                 не становится больше» выходил
///                              необъяснённым
/// ```
///
/// > В голове самой сверки написано: «запись, чья причина умерла,
/// > молча разрешает настоящую регрессию под тем же именем».
/// > Здесь причина **не умерла, а не рождалась**: запись не охраняла
/// > ничего с первой минуты — и при этом печатала о себе
/// > успокаивающее.
///
/// Цена: три часа и две сессии, чтобы найти то, что это утверждение
/// находит за секунду. Оно и заводится поэтому — не ради полноты,
/// а потому что **сторож, который сам себя не сторожит, молчит
/// убедительнее отсутствующего**.
///
/// # Почему второе утверждение здесь, а не отдельно
///
/// Дубли имён — не косметика: **и эталон, и `-only-testing` адресуют
/// по имени**. Пока имена не уникальны, оба инструмента адресуют
/// неоднозначно, то есть дубли подтачивают тот самый инструмент,
/// которым мы меряем всё остальное. На 09.10.2026 дублей было три
/// при 1061 тесте; переименованы в тот же день.
///
/// Оба утверждения про **адресуемость по имени** — это один предмет
/// с двух сторон: первое про то, что адрес ведёт куда-то, второе про
/// то, что он ведёт в одно место.
///
/// # Граница
///
/// Сторож читает **исходники**, а не собранный бандл: он отвечает
/// «такое имя написано в проекте», а не «тест с таким именем
/// исполнился». Прогон с нулём выполненных он не поймает — это
/// предмет сверки, и она его ловит числом против ожидаемого.
@Suite("Эталон ссылается на живое")
struct ЭталонСсылаетсяНаЖивоеTests {

    /// Первой: набору, которому нечего читать, молчать так же легко,
    /// как набору, у которого всё хорошо.
    @Test("Эталон и тесты прочитаны — было что сверять")
    func былоЧтоСверять() throws {
        let записи = try эталон()
        #expect(!записи.isEmpty, "в эталоне ноль записей — читать нечего")
        let имена = try всеИменаТестов()
        #expect(имена.count > 500,
                "имён @Test найдено \(имена.count) — разбор не состоялся")

        // Второй контроль — про НАБОР, и он отдельный нарочно: разбор
        // имён может быть жив, а определение объемлющего типа сломаться
        // целиком, и тогда «набор верен» зеленело бы на пустых строках,
        // сравнивая "" с "". Сторож, у которого ось обнулилась, молчит
        // так же, как сторож, у которого всё хорошо.
        let безнабора = имена.filter(\.набор.isEmpty)
        #expect(безнабора.count * 20 < имена.count, """
            у \(безнабора.count) из \(имена.count) тестов не определился \
            объемлющий тип — разбор набора сломан, и проверка «набор \
            верен» ничего не значит. Первые: \
            \(безнабора.prefix(5).map(\.адрес).joined(separator: ", ")).
            """)
    }

    @Test("Каждое имя из эталона существует среди @Test")
    func именаЭталонаЖивые() throws {
        let имена = Set(try всеИменаТестов().map(\.имя))
        var призраки: [String] = []
        for запись in try эталон() {
            guard let имя = запись["тест"] as? String else { continue }
            if !имена.contains(имя) { призраки.append(имя) }
        }
        #expect(призраки.isEmpty, """
            эталон ждёт красными тесты, которых НЕТ: \(призраки).
            Сверка матчит точным именем — такая запись не совпадёт
            никогда и будет печатать «ПОЗЕЛЕНЕЛ» на каждом прогоне,
            а настоящее красное под этим именем останется непокрытым.
            Чинится одной строкой: поставить в поле `тест` имя
            из @Test, а не пересказ смысла.
            """)
    }

    @Test("Имена @Test уникальны")
    func именаУникальны() throws {
        var где: [String: [String]] = [:]
        for т in try всеИменаТестов() { где[т.имя, default: []].append(т.адрес) }
        let дубли = где.filter { $0.value.count > 1 }
        #expect(дубли.isEmpty, """
            одно имя у нескольких тестов: \
            \(дубли.map { "«\($0.key)» → \($0.value.joined(separator: ", "))" }
                   .sorted().joined(separator: "; ")).
            И эталон, и -only-testing адресуют ПО ИМЕНИ: неуникальное
            имя делает оба адреса неоднозначными. Имя обязано называть
            ПРЕДМЕТ сторожа, а не его форму — «Границы: чего этот сторож
            не умеет» одинаково подходит двум разным сторожам.
            """)
    }

    /// Поле `набор` — тот адрес, по которому работает `make guard`.
    ///
    /// # Почему этого не хватало
    ///
    /// Замер 15.10.2026. Сторож читал из записи **одно** поле — `тест`
    /// (`:72`), а слова `набор` в нём не было ни разу. Между тем
    /// `check_guard.py:102` возвращает `готово.returncode == 0` после
    /// `xcodebuild test -only-testing:<набор>`, то есть **единица
    /// блокировки — набор**, и адресует инструмент именно по нему.
    ///
    /// ```
    /// имя теста живое + набор неверный → этот сторож ЗЕЛЁН
    ///                                    make guard подделает ЧУЖОЙ набор
    ///                                    и скажет «поймал» либо
    ///                                    «был сломан» про чужой предмет
    /// ```
    ///
    /// > Сторож сверял поле, которое **удобно читать**, а не поле,
    /// > по которому **адресуют**. Соседнее утверждение этого же файла
    /// > написано про то же — «и эталон, и `-only-testing` адресуют
    /// > по имени», — и про набор его никто не дочитал.
    ///
    /// # Приёмка этого утверждения
    ///
    /// Правило прогнано на живых данных **прежде**, чем стало тестом:
    /// одиннадцать записей эталона, расхождений ноль. И подделано —
    /// подменой одного набора на `ЧужойНабор`, ответ 1. Зелёный здесь
    /// значит «замер видит расхождение и его сегодня нет», а не
    /// «сверять было нечего».
    ///
    /// # Граница
    ///
    /// Набор берётся от **верхнего** уровня файла. Вложенные
    /// `struct Блок` и `struct Режим` внутри сюиты набором не являются,
    /// и разбор, который берёт последний встреченный тип, даёт на них
    /// ложное расхождение: первая редакция этого замера так и сделала
    /// и объявила неверными пять записей из одиннадцати. Та же ошибка,
    /// что однажды дала ложный ноль сторожу полей моделей, — «уровень
    /// тела класса считался нулевым, а он первый».
    @Test("Каждая запись эталона называет свой набор верно")
    func наборыЭталонаВерны() throws {
        let где = Dictionary(try всеИменаТестов().map { ($0.имя, $0) },
                             uniquingKeysWith: { перв, _ in перв })
        var мимо: [String] = []
        for запись in try эталон() {
            guard let имя = запись["тест"] as? String,
                  let заявлен = запись["набор"] as? String,
                  let тест = где[имя] else { continue }
            if тест.набор != заявлен {
                мимо.append("«\(имя)»: эталон говорит \(заявлен), "
                            + "а @Test лежит в \(тест.набор) (\(тест.адрес))")
            }
        }
        #expect(мимо.isEmpty, """
            запись эталона называет НЕ ТОТ набор: \(мимо.joined(separator: "; ")).

            Это не косметика: `make guard` адресует по набору
            (`check_guard.py:102`, `-only-testing:<набор>`), и по неверному
            полю он подделает чужой предмет, а скажет про ваш. Имя теста
            при этом живое, и соседнее утверждение этого файла зелено.

            Чинится одной строкой: поставить в поле `набор` имя типа
            ВЕРХНЕГО уровня, в котором лежит @Test, а не имя файла
            и не вложенный помощник.
            """)
    }

    // MARK: Чтение

    private struct Тест { let имя: String; let набор: String; let адрес: String }

    private func корень() -> URL {
        URL(fileURLWithPath: #filePath).deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    /// Пути к файлам, названные В ПРОЗЕ записи, ведут к живым файлам.
    ///
    /// # Чего стоило отсутствие этого утверждения
    ///
    /// Замер 25.10.2026. Запись про плашку второстепенной кнопки
    /// называла два живых места дефекта, и **первого из них не было
    /// с 24.10**: `ActionGrid.swift` удалён как сирота (сказано
    /// в `TodayRouter.swift:7`), `BigAction` вместе с ним. Запись
    /// при этом выглядела свежей и подробной.
    ///
    /// Соседние утверждения этого файла сторожат **имя теста**
    /// и **имя набора** — то, по чему адресуют инструменты. А по прозе
    /// причины адресует **человек**: он идёт читать названный файл,
    /// чтобы решить, жив ли предмет. Мёртвая ссылка отправляет его
    /// в пустоту, и ответ «такого файла нет» он прочтёт как «дефект
    /// починили», хотя тот жив и переехал.
    ///
    /// > **Сторож на адресуемость стоял для машин и не стоял
    /// > для человека.** Три утверждения про адрес в одном файле,
    /// > и четвёртое — ровно про того читателя, ради которого проза
    /// > и написана.
    ///
    /// # Контракт, а не запрет
    ///
    /// Сослаться на удалённый файл можно: история — законный предмет
    /// записи. Но тогда в ТОЙ ЖЕ записи обязана стоять пометка
    /// `ФАЙЛА НЕТ` — заглавными и дословно, чтобы читатель узнал
    /// об этом прежде, чем пойдёт искать. Условие проверяется
    /// по записи целиком, а не по соседству строк: соседство
    /// в прозе — то же прокси, которым мы уже платили.
    ///
    /// # Приёмка
    ///
    /// Правило прогнано на живых данных прежде, чем стало тестом:
    /// ссылок на `.swift` в эталоне восемь, живых семь, мёртвая одна —
    /// и ровно она помечена. Подделка: снять пометку из записи — тест
    /// обязан покраснеть и назвать файл поимённо.
    ///
    /// # Граница
    ///
    /// Проверяется **имя файла**, а не номер строки. Номера гниют
    /// быстрее всего и чинить их тестом бессмысленно: они сдвигаются
    /// от любой правки выше. И проверяется наличие в ДЕРЕВЕ, а не
    /// в коммите записи — файл, живший когда-то, этот сторож пропустит.
    @Test("Пути к файлам в прозе эталона ведут к живым файлам")
    func путиВПрозеЖивы() throws {
        var живые: Set<String> = []
        let fm = FileManager.default
        for каталог in ["Togo", "TogoShared", "TogoTests", "TogoUITests", "TogoWidgets"] {
            let корневой = корень().appendingPathComponent(каталог)
            guard let обход = fm.enumerator(at: корневой,
                                            includingPropertiesForKeys: nil) else { continue }
            while let элемент = обход.nextObject() as? URL {
                if элемент.pathExtension == "swift" { живые.insert(элемент.lastPathComponent) }
            }
        }
        #expect(живые.count > 100, """
            файлов .swift найдено \(живые.count) — обход не состоялся,             и «мёртвых ссылок нет» означало бы «искать было нечем».
            """)

        let шаблон = try NSRegularExpression(pattern: "[A-Za-zА-Яа-яЁё0-9_+]+\\.swift")
        var мёртвые: [String] = []
        for запись in try эталон() {
            // Вся проза записи одной строкой: условие про пометку
            // проверяется по записи ЦЕЛИКОМ, а не по соседней строке.
            let проза = запись.values.compactMap { $0 as? String }.joined(separator: " ")
            let помечена = проза.contains("ФАЙЛА НЕТ")
            let имя = (запись["тест"] as? String) ?? "<без имени>"
            let диапазон = NSRange(проза.startIndex..., in: проза)
            var названные: Set<String> = []
            for совпадение in шаблон.matches(in: проза, range: диапазон) {
                guard let r = Range(совпадение.range, in: проза) else { continue }
                названные.insert(String(проза[r]))
            }
            for файл in названные.sorted() where !живые.contains(файл) {
                if помечена { continue }
                мёртвые.append("«\(имя)» ссылается на \(файл)")
            }
        }

        #expect(мёртвые.isEmpty, """
            запись эталона называет файл, которого в дереве НЕТ:             \(мёртвые.joined(separator: "; ")).

            По прозе причины адресует ЧЕЛОВЕК: он идёт читать названный
            файл, чтобы решить, жив ли предмет. Не найдя файла, он
            прочтёт это как «дефект починили» — а тот мог переехать.
            Так 24.10 уехал `ActionGrid.swift`, и запись десять дней
            выглядела свежей.

            Чинится двумя способами, и оба законны: поправить путь
            на текущий, либо оставить историческую ссылку и поставить
            в записи пометку `ФАЙЛА НЕТ` заглавными — тогда читатель
            узнает об этом прежде, чем пойдёт искать.
            """)
    }

    private func эталон() throws -> [[String: Any]] {
        let путь = корень().appendingPathComponent("Tools/эталон-прогона.json")
        let данные = try Data(contentsOf: путь)
        let разбор = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
        return (разбор?["ожидаемо_красные"] as? [[String: Any]]) ?? []
    }

    /// Имена из `@Test("…")` по всему каталогу тестов.
    ///
    /// Разбор построчный и намеренно простой: `@Test` с первым
    /// строковым литералом. Многострочных имён у нас нет, а полный
    /// разбор Swift здесь был бы второй реализацией компилятора.
    private func всеИменаТестов() throws -> [Тест] {
        let каталог = корень().appendingPathComponent("TogoTests")
        guard let обход = FileManager.default.enumerator(at: каталог,
                                                         includingPropertiesForKeys: nil)
        else { return [] }
        var найдено: [Тест] = []
        for случай in обход {
            guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
            guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
            // Уровень вложенности и тип ВЕРХНЕГО уровня. Порядок внутри
            // витка важен: `@Test` приписывается типу, открытому РАНЬШЕ
            // него, поэтому счётчик двигается последней строкой.
            var уровень = 0
            var верх = ""
            for (н, строка) in текст.components(separatedBy: .newlines).enumerated() {
                let голая = строка.components(separatedBy: "//")[0]
                let безСтрок = Self.безЛитералов(голая)
                if уровень == 0, let тип = Self.объявленныйТип(безСтрок) { верх = тип }
                if голая.contains("@Test("),
                   let первая = голая.range(of: "\""),
                   let вторая = голая.range(of: "\"", range: первая.upperBound..<голая.endIndex) {
                    найдено.append(Тест(имя: String(голая[первая.upperBound..<вторая.lowerBound]),
                                        набор: верх,
                                        адрес: "\(url.lastPathComponent):\(н + 1)"))
                }
                уровень += безСтрок.filter { $0 == "{" }.count
                уровень -= безСтрок.filter { $0 == "}" }.count
            }
        }
        return найдено
    }

    /// Содержимое строковых литералов выкидывается до счёта скобок:
    /// `#expect(x == "{")` иначе сдвинул бы уровень навсегда, и все
    /// последующие типы файла перестали бы считаться верхними.
    private static func безЛитералов(_ строка: String) -> String {
        var итог = ""
        var вЛитерале = false
        for знак in строка {
            if знак == "\"" { вЛитерале.toggle(); continue }
            if !вЛитерале { итог.append(знак) }
        }
        return итог
    }

    /// Имя типа, объявленного в строке, либо `nil`.
    ///
    /// Слово берётся СЛЕДУЮЩИМ за ключевым, а не поиском по префиксу:
    /// `hasPrefix("struct Swatch")` находит `struct SwatchRow`, и это
    /// правило проекта, оплаченное отдельно.
    private static func объявленныйТип(_ строка: String) -> String? {
        let ключевые: Set<String> = ["struct", "class", "enum", "actor", "extension"]
        let слова = строка.split(whereSeparator: { $0 == " " || $0 == "\t" }).map(String.init)
        for (и, слово) in слова.enumerated() where ключевые.contains(слово) {
            guard и + 1 < слова.count else { continue }
            let имя = слова[и + 1].prefix { $0.isLetter || $0.isNumber || $0 == "_" }
            if !имя.isEmpty { return String(имя) }
        }
        return nil
    }
}
