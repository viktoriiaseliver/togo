import Foundation
import Testing

/// Обратный вызов «доза больше не ждёт» нельзя забыть подключить.
///
/// # Зачем сторож, если всё и так компилируется
///
/// В этом и дело. `FamilySync` живёт в `TogoShared`, а `TogoShared`
/// входит синхронизированной группой **в оба** таргета — `Togo`
/// и `TogoWidgetsExtension` (исключений членства в `project.pbxproj`
/// ноль). `ReminderScheduler` лежит в `Togo/Store/`, то есть только
/// в приложении. Прямой вызов из кода приёма не собрался бы
/// в расширении, и потому снятие напоминаний передаётся обратным
/// вызовом.
///
/// > **Обратный вызов, который можно не поставить, — это механизм
/// > без входа.** Он компилируется, тесты зелёные, и от рабочего
/// > он не отличается ни одним признаком. Отличает его только вопрос,
/// > которого не задаёт ни один сторож: каким путём это вообще
/// > включается.
///
/// # Что именно стряслось 14.10.2026, и почему оси здесь три
///
/// Замер: `ReminderScheduler.cancelDose` во всём дереве имел **один**
/// вызов — `DayPlanActions:286`, своя рука. Мама отмечает дозу у себя,
/// у Виктории телефон через полчаса звонит «не отмечена». Починка
/// `b9ecc5f` завела уборку `снятьНеждущие`, и ось у неё шире события:
/// «доза больше не ждёт» покрывает разом чужую отметку, паузу, отмену
/// схемы и выключенное лечение.
///
/// Но вход у той уборки **один, и это экран**: `снятьНеждущие`
/// ← `scheduleDoses` ← `refresh` ← `.task` главного экрана
/// (`TodayScreen:430`) либо своя отметка. То есть она срабатывает,
/// когда человек **откроет** приложение, а измеренный сценарий —
/// телефон в кармане. Приём чужой отметки расширяет вход до «пока
/// приложение работает».
///
/// ## Чего не закрывает ни то, ни другое, и это записано нарочно
///
/// При закрытом приложении на телефоне не выполняется **ничего**.
/// `UIBackgroundModes` с `remote-notification` в манифесте есть,
/// `aps-environment` есть, а `CKSubscription` в коде — ноль вхождений,
/// `didReceiveRemoteNotification` нет. **Право на фоновое пробуждение
/// есть, механизма, который им пользуется, нет.** Та же причина,
/// по которой не уезжают записи голосом: движок обмена создаётся
/// внутри `.task` сцены.
///
/// Поэтому вердикт у починки — три строки, а не одна, и ни одна
/// из них не «починено»:
///
/// ```
/// приложение открыто      закрыто b9ecc5f
/// приложение работает     закрыто этой правкой
/// приложение закрыто      ОТКРЫТО, причина — нет фонового входа
/// на двух телефонах       НЕ ПРОВЕРЯЛ НИКТО
/// ```
///
/// # Ось — от запрета
///
/// Проверять «есть ли строка установки хука в `TogoApp.swift`» нельзя:
/// такая проверка ломается от любого переезда файла и ломается
/// **зелёным**. Поэтому запреты, а не наличие:
///
/// ```
/// 1  у параметра НЕТ умолчания          забыть нельзя — решает компилятор
/// 2  хук зовётся из КАЖДОГО названного входа и больше ниоткуда
///    ловит и «не зовут» (ноль), и «завели третий вход молча»
/// 3  правило «доза ждёт» объявлено ОДИН раз
/// ```
///
/// Третий запрет — не про хук, а про то, чем он заряжен. 14.10 правило
/// «доза больше не ждёт» завелось в двух местах за один час: в уборке
/// и в приёме. Два разбора одного правила расходятся молча — у Togo
/// так жили три реализации «не кормить», и две из трёх молчали.
///
/// # Приёмка
///
/// Сторож обязан краснеть на подделке, а не только зеленеть на здоровом.
/// Проверяется `make guard`:
///
/// ```
/// ФАЙЛ=TogoShared/Sync/FamilySync.swift
/// БЫЛО='дозаБольшеНеЖдёт: @escaping @MainActor (DoseRecord) -> Void,'
/// СТАЛО='дозаБольшеНеЖдёт: @escaping @MainActor (DoseRecord) -> Void = { _ in },'
/// НАБОР=TogoTests/СнятиеНапоминанийПодключеноTests
/// ```
@Suite("Снятие напоминаний у приехавшей дозы подключено")
struct СнятиеНапоминанийПодключеноTests {

    private static let имяХука = "дозаБольшеНеЖдёт"

    @Test("У обратного вызова нет умолчания — забыть его компилятор не даст")
    func умолчанияНет() throws {
        let строки = try Self.код("TogoShared/Sync/FamilySync.swift")

        let объявления = строки.filter {
            $0.contains("\(Self.имяХука):") && $0.contains("@escaping")
        }

        #expect(объявления.count == 1, """
            параметр `\(Self.имяХука)` в `FamilySync.init` объявлен \
            \(объявления.count) раз вместо одного. Либо его переименовали, \
            либо завели второй — и тогда непонятно, какой из них живой.
            """)

        for строка in объявления {
            // `->` в типе замыкания `=` не содержит, поэтому любой `=`
            // на этой строке — это умолчание и ничто иное.
            #expect(!строка.contains("="), """
                у параметра `\(Self.имяХука)` появилось УМОЛЧАНИЕ:
                  \(строка.trimmingCharacters(in: .whitespaces))

                Умолчание возвращает ровно ту беду, от которой заведён \
                этот параметр: обратный вызов снова можно не поставить, \
                всё соберётся, тесты останутся зелёными, а напоминание \
                о дозе, которую второй человек уже дал, придёт через \
                полчаса. Механизм без входа от рабочего не отличается \
                ни тестом, ни компилятором.
                """)
        }
    }

    /// **Входов два, и это решение, а не дубль** (замер 21.10.2026).
    ///
    /// Прежняя ось требовала «ровно один вызов» и покраснела от правки
    /// `404430c` (15.10), которая завела второй вход. Шесть дней сторож
    /// числился красным сверх эталона с сообщением «одно и то же снятие
    /// идёт дважды» — а это неверно: по одной дозе двух срабатываний
    /// не бывает, потому что записи приезжают **разных типов**.
    ///
    /// ```
    /// ветка .medication   приехала СХЕМА (отмена, пауза) → все её дозы
    ///                     предикат ждётОтметкиСУчётомСхемы (составной)
    /// ветка .dose         приехала ОТМЕТКА одной дозы
    ///                     предикат ждётОтметки — про схему не спрашивает
    /// ```
    ///
    /// Ни один не покрывает другого: у доз отменённой схемы собственный
    /// `cancelledAt` пуст, и ветка `.dose` их не погасит; при чужой
    /// отметке дозы запись типа `Medication` не приезжает вовсе. Разбор
    /// стоит в самом продукте — `FamilySync.swift`, ветка `.medication`.
    ///
    /// Автор второго входа объявил этот вопрос открытым сам
    /// (`docs/journal/2026-10-15-zakrytie-5d-naryad-po-obmenu-i-rolyam.md:147`:
    /// «нужно ли расширять его ось после моей правки — не установлено»),
    /// то есть хозяин у красного был, и это «не спросили», а не «нет».
    ///
    /// **Ось «число вызовов» была прокси** к «правило объявлено один
    /// раз». Предмет держит `правилоОдно` — он смотрит на состав
    /// условия и зелен; мест с правилом одно, `Care.swift`. Прокси же
    /// гасится и **зажигается** чужим действием: здесь зажёгся.
    @Test("Обратный вызов зовут из двух названных входов и больше ниоткуда")
    func зовутРовноОдинРаз() throws {
        let строки = try Self.код("TogoShared/Sync/FamilySync.swift")

        // Считаются ВХОЖДЕНИЯ, а не строки с ними, и это поймала
        // подделка, а не чтение. Первая редакция фильтровала строки —
        // и подделка `хук(доза); хук(доза)` в одной строке прошла
        // зелёной: два вызова на одной строке дают одну строку.
        //
        // > Сторож, считающий строки, отвечает про РАЗМЕТКУ исходника,
        // > а утверждение он делает про число вызовов. Это те же две
        // > величины, которые читаются одна за другую.
        let вызовы = строки.reduce(into: 0) { итог, строка in
            итог += строка.components(separatedBy: "\(Self.имяХука)(").count - 1
        }
        let места = строки.filter { $0.contains("\(Self.имяХука)(") }

        #expect(вызовы >= 1, """
            обратный вызов `\(Self.имяХука)` не зовут НИ ОТКУДА, \
            и это тот самый дефект: мама отметила дозу, у владельца \
            телефон звонит «не отмечена».
            """)

        #expect(вызовы == 2, """
            обратный вызов `\(Self.имяХука)` зовут \(вызовы) раз \
            при ДВУХ названных входах (ветки `.medication` и `.dose`).

            Больше двух — завели третий вход, и его цена не названа \
            нигде: он либо дублирует снятие, либо гасит не то.
            Меньше двух при ненулевом счёте — один из входов убрали, \
            и тогда часть напоминаний перестала гаснуть молча.

            Найдено:
            \(места.map { "  " + $0.trimmingCharacters(in: .whitespaces) }.joined(separator: "\n"))
            """)

        // Каждый вход — под СВОИМ предикатом, иначе два входа и есть
        // «одно снятие дважды», от которого стоит этот сторож.
        //
        // Порядок фильтров значим: `ждётОтметки` — подстрока
        // `ждётОтметкиСУчётомСхемы`, тот же класс, что `Space.s1`
        // внутри `Space.s16`. Наивный `contains` даёт 2 там, где
        // простых предикатов один (воспроизведено замером 21.10.2026).
        let составные = строки.filter { $0.contains("ждётОтметкиСУчётомСхемы") }
        let простые = строки.filter {
            $0.contains("ждётОтметки") && !$0.contains("ждётОтметкиСУчётомСхемы")
        }

        #expect(составные.count == 1 && простые.count == 1, """
            входы перестали различаться предикатами: составной \
            \(составные.count), простой \(простые.count) при одном \
            и одном. Два входа под ОДНИМ предикатом — это и есть \
            «одно снятие дважды»; третий предикат означает третий \
            вход, у которого не названо, что он гасит.
            """)
    }

    @Test("Правило «доза ждёт отметки» объявлено один раз, и это модель")
    func правилоОдно() throws {
        // Ось — по составу условия, а не по имени свойства: имя можно
        // не трогать и всё равно завести вторую копию правила рядом.
        let приметы = ["skippedAt == nil", "cancelledAt == nil"]

        var места: [String] = []
        for файл in try Self.исходники() {
            for строка in try Self.код(файл.адрес) where приметы.allSatisfy(строка.contains) {
                места.append("\(файл.имя): \(строка.trimmingCharacters(in: .whitespaces))")
            }
        }

        #expect(места.count == 1, """
            условие «доза ещё ждёт отметки» объявлено \(места.count) раз \
            вместо одного.

            У него два читателя в разных таргетах: уборка запросов \
            `ReminderScheduler.снятьНеждущие` (цель приложения) и приём \
            чужой отметки `FamilySync.apply` (общий код). Вторая копия \
            переживает правку первой — за это в Togo уже заплачено \
            тремя реализациями «не кормить», из которых молчали две.

            Места:
            \(места.map { "  " + $0 }.joined(separator: "\n"))
            """)

        #expect(места.first?.contains("Care.swift") == true, """
            правило уехало из модели: оно обязано лежать там, куда \
            дотягиваются ОБА таргета. В `Togo/` его видит только \
            приложение, и приём чужой отметки завёл бы себе копию.
            """)
    }

    // MARK: Разбор

    /// Строки файла без комментариев.
    ///
    /// Снимать комментарии обязательно: голова `FamilySync.swift`
    /// объясняет этот самый механизм и называет `\(имяХука)` семь раз.
    /// Сторож, считающий прозу, красит себя зелёным от объяснения —
    /// у Togo это уже случалось, и направление ошибки там решило цену.
    private static func код(_ путь: String) throws -> [String] {
        try код(корень.appendingPathComponent(путь))
    }

    /// То же по готовому адресу — тому, который отдал обход.
    ///
    /// **Отдельный вход, потому что склейка пути заново и была
    /// дефектом.** Адрес от `enumerator` несёт имя ровно таким, как
    /// оно на диске; всё, что мы собираем из него строкой, рискует
    /// приехать другим.
    private static func код(_ адрес: URL) throws -> [String] {
        let текст = try String(contentsOf: адрес, encoding: .utf8)
        return текст
            .components(separatedBy: .newlines)
            .map { $0.components(separatedBy: "//")[0] }
            .filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
    }

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    /// Swift-исходники продукта: оба таргета, без тестов.
    ///
    /// Тесты исключены нарочно — они заводят условия сами, и сторож,
    /// считающий их, нашёл бы «вторую копию правила» в собственной
    /// проверке.
    /// **Симлинки снимаются у ОБОИХ путей, и это замер, а не осторожность.**
    ///
    /// `#filePath` даёт путь таким, каким его видел компилятор
    /// (`/tmp/togo-<сессия>/…` при прогоне из `git worktree`), а
    /// `FileManager.enumerator` отдаёт разрешённый — `/private/tmp/…`,
    /// потому что `/tmp` на macOS это симлинк на `private/tmp`. Срезка
    /// префикса тогда не совпадает ни на один символ, и сторож складывал:
    ///
    /// ```
    /// основание из #filePath   /tmp/togo-d3b/Togo
    /// адрес от enumerator      /private/tmp/togo-d3b/Togo/DesignSystem/Typography.swift
    /// что выходило             Togo//privateDesignSystem/Typography.swift
    /// открывается              НЕТ → Code=260 «такого файла не существует»
    /// ```
    ///
    /// Падал он **на первом же файле обхода**, то есть не проверял ничего,
    /// и в логе это выглядело дефектом продукта: «Caught error … Typography
    /// .swift». Замер 21.10.2026.
    ///
    /// И главное — **условие отказа ровно то, которое предписывает свод**:
    /// «мерить и собирать из `git worktree`». Четыре теста проекта уже
    /// зовут `resolvingSymlinksInPath` по этой же причине
    /// (`ArchiveFillTests`, `CaseSlotFallbackTests`,
    /// `DogNameSubstitutionTests`, `WidgetBundleCatalogTests`).
    ///
    /// # ЗНАК ПЕРЕВЕРНУЛСЯ 30.10.2026, И НА ТОЙ ЖЕ СТРОКЕ
    ///
    /// ~~«Из рабочего дерева (`/Users/…`) сторож работает, из worktree
    /// в `/tmp` — не работает никогда».~~ Ровно наоборот: из worktree
    /// работает, из рабочего дерева падал `Code=260` на
    /// `ПозваливСемью.swift` — файла с таким именем нет, на диске
    /// `ПозвалиВСемью.swift`, с заглавной «В».
    ///
    /// **`resolvingSymlinksInPath()` делает case-folding кириллицы.**
    /// Замер тем же обходом, что здесь, с печатью байтов:
    ///
    /// ```
    /// lastPathComponent          … d092 …   «В» заглавная, как на диске
    /// адрес.path                 … d092 …   верно
    /// resolvingSymlinksInPath()  … d0b2 …   «В» стала строчной «в»
    /// относительный (срезка)     … d0b2 …   унаследовано
    /// ```
    ///
    /// Почему это не замечали девять дней: том регистронезависим, и на
    /// хосте испорченное имя **открывается** — мой скрипт прочитал файл
    /// по нему, 10 442 символа. Тест бежит в симуляторе, и там тот же
    /// путь даёт «No such file or directory». В worktree под `/tmp`
    /// резолв проходит иначе и имя не портит — потому вчерашний прогон
    /// и был зелёным.
    ///
    /// > **Одна строка защищала от одного класса и вводила другой,
    /// > и оба отказа выглядят одинаково — `Code=260` на первом же
    /// > файле.** Потому починка 21.10 и читалась как полная: симптом
    /// > исчез там, где его мерили.
    ///
    /// Починено не отменой резолва (он нужен — см. замер 21.10 выше),
    /// а тем, что **имя больше не собирается строкой**: относительный
    /// путь считается числом компонентов, а файл читается по адресу,
    /// который отдал обход. Резолв остаётся ровно там, где нужен, —
    /// у основания, для подсчёта глубины.
    ///
    /// Кириллических имён в продукте **28** на 30.10.2026
    /// (`find Togo TogoShared TogoWidgets -name "*.swift" | grep -cP "[А-Яа-я]"`),
    /// то есть ловушка была заряжена на каждый двадцатый файл обхода.
    /// Остальные тесты с тем же приёмом держит отдельный сторож —
    /// `ИменаФайловПриОбходеTests`.
    private static func исходники() throws -> [(адрес: URL, имя: String)] {
        var итог: [(адрес: URL, имя: String)] = []
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let основание = корень.appendingPathComponent(каталог).resolvingSymlinksInPath()
            guard let обход = FileManager.default.enumerator(
                at: основание, includingPropertiesForKeys: nil) else { continue }
            let глубина = основание.pathComponents.count
            for случай in обход {
                guard let адрес = случай as? URL, адрес.pathExtension == "swift" else { continue }
                // Относительный путь — СЧЁТОМ КОМПОНЕНТОВ, а не срезкой
                // строки. Разбор у `ОшибкаОбхода.регистрИспорчен` ниже;
                // коротко: `resolvingSymlinksInPath()` портил имя, а
                // строковая срезка требовала звать его у обоих путей.
                let хвост = адрес.pathComponents.dropFirst(глубина)
                guard !хвост.isEmpty else {
                    throw ОшибкаОбхода.префиксНеСрезан(адрес: адрес.path,
                                                        основание: основание.path)
                }
                итог.append((адрес, каталог + "/" + хвост.joined(separator: "/")))
            }
        }
        return итог
    }

    enum ОшибкаОбхода: Error, CustomStringConvertible {
        case префиксНеСрезан(адрес: String, основание: String)

        var description: String {
            switch self {
            case let .префиксНеСрезан(адрес, основание):
                """
                обход не смог сделать путь относительным, и сторож проверил бы \
                не то: адрес «\(адрес)» не начинается с основания «\(основание)». \
                Снимать симлинки у обоих путей — см. комментарий у `исходники()`.
                """
            }
        }
    }
}
