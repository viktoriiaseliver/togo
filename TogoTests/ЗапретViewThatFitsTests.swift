import Foundation
import Testing

/// Красная линия проекта: **`ViewThatFits` запрещён.**
///
/// Причина оплачена дефектом, а не вкусом: `ViewThatFits` держит
/// в дереве **обе** раскладки одновременно, и озвучка находила **две
/// кнопки «Отменить»** — человек с VoiceOver не мог понять, какую
/// нажимает. Компилятор такого не видит, кадр без VoiceOver тоже:
/// вид правильный, дерево — нет.
///
/// Заменяется явным выбором по `@Environment(\.dynamicTypeSize)`
/// и `.isAccessibilitySize` — образец `UndoToastView`
/// в `Togo/App/RootView.swift`.
///
/// > **Почему не «подобрать размер».** `ViewThatFits` решает по МЕСТУ,
/// > а доступность — по НАСТРОЙКЕ человека. Эти два вопроса совпадают
/// > случайно и расходятся на узком экране с крупным кеглем, то есть
/// > ровно там, где человеку труднее всего.
///
/// # Этот тест ЧИТАЕТ ФАЙЛЫ С ДИСКА
///
/// Вход — все `.swift` в `Togo/`, `TogoShared/` и `TogoWidgets/`
/// от корня репозитория, найденного через `#filePath`. Значит тест
/// ломается от переноса каталогов, и ломается **не на своём
/// предмете**: первым идёт `былоЧтоПроверять()`, который отличает
/// «запрета никто не нарушил» от «сканер не прочёл ни одного файла».
///
/// # Два сторожа на одно место, и это не дублирование
///
/// `ниОдногоЖивогоВызова` держит **дорогу** — запрет самого вызова.
/// `раскладкаВыбираетсяПоНастройкеЧеловека` держит **значение** —
/// что на месте снятого стоит выбор по настройке, а не одна
/// оставшаяся ветка. Снять `ViewThatFits` и оставить только `HStack`
/// проходит первый сторож и ломает крупный кегль молча.
@Suite("Запрет ViewThatFits")
struct ЗапретViewThatFitsTests {

    // MARK: - Чтение дерева

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    /// Пути и содержимое всех исходников приложения.
    ///
    /// Тесты в обход не входят намеренно: запрет адресован тому, что
    /// человек видит, а не стенду. В `TogoUITests` имя `ViewThatFits`
    /// законно встречается в проверках.
    private static func исходники() -> [(путь: String, текст: String)] {
        var собрано: [(String, String)] = []
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            guard let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(каталог),
                includingPropertiesForKeys: nil
            ) else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.pathExtension == "swift",
                      let текст = try? String(contentsOf: url, encoding: .utf8)
                else { continue }
                собрано.append((url.path.replacingOccurrences(
                    of: корень.path + "/", with: ""), текст))
            }
        }
        return собрано
    }

    /// Комментарии вырезаются **до** разбора, иначе сторож меряет прозу.
    ///
    /// Это не предосторожность, а замер 23.10.2026: по голому `grep`
    /// в дереве было **8 вхождений в 6 файлах**, из них живых вызовов
    /// **два**. Шесть — объяснения вида «`ViewThatFits` здесь
    /// не применяется, он запрещён». Сторож без этой функции краснел бы
    /// на файлах, где запрет **соблюдён и описан**, то есть запрещал бы
    /// писать про ошибку там, где её не совершают.
    ///
    /// Режет и строчные (`//`, `///`), и блочные (`/* … */`): блочный
    /// комментарий переживает построчную резку целиком.
    static func безКомментариев(_ текст: String) -> [String] {
        var вБлоке = false
        return текст.split(separator: "\n", omittingEmptySubsequences: false).map { строка in
            var вывод = ""
            var i = строка.startIndex
            while i < строка.endIndex {
                let хвост = строка[i...]
                if вБлоке {
                    if хвост.hasPrefix("*/") {
                        вБлоке = false
                        i = строка.index(i, offsetBy: 2)
                    } else {
                        i = строка.index(after: i)
                    }
                } else if хвост.hasPrefix("/*") {
                    вБлоке = true
                    i = строка.index(i, offsetBy: 2)
                } else if хвост.hasPrefix("//") {
                    break                      // строчный — до конца строки
                } else {
                    вывод.append(строка[i])
                    i = строка.index(after: i)
                }
            }
            return вывод
        }
    }

    // MARK: - Было что проверять (идёт ПЕРВЫМ)

    /// Сканер, прочитавший ноль файлов, молчит так же, как тот, кому
    /// нечего сказать. Три признака разом: сколько файлов, сколько
    /// в них текста и жив ли положительный контроль.
    @Test("Было что проверять: сканер прочитал дерево, а не пустоту")
    func былоЧтоПроверять() throws {
        let все = Self.исходники()

        // Порог ниже текущего состава (223 на 23.10.2026), чтобы
        // удаление пары файлов не красило сторожа, но «прочитал
        // ничего» и «прочитал один каталог из трёх» не прошли.
        #expect(все.count >= 150, """
            сканер запрета ViewThatFits прочитал \(все.count) файлов \
            вместо ожидаемых 150+. Каталоги Togo/TogoShared/TogoWidgets \
            переехали или #filePath указывает не в корень — \
            ЗЕЛЁНОЕ НИЖЕ НИЧЕГО НЕ ЗНАЧИТ.
            """)

        for каталог in ["Togo/", "TogoShared/", "TogoWidgets/"] {
            #expect(все.contains { $0.путь.hasPrefix(каталог) },
                    "сканер не прочитал ни одного файла из \(каталог)")
        }

        // Положительный контроль ЗАМЕНЫ, снятый в том же замере, что
        // и предмет: ищем то, чем ViewThatFits заменён. Если ослепнет
        // разбор, обнулится и он — а обнулиться вместе они не могут:
        // нет вызовов isAccessibilitySize, значит нет и файлов.
        let сВыборомПоНастройке = все.filter {
            Self.безКомментариев($0.текст).contains { $0.contains("isAccessibilitySize") }
        }
        #expect(сВыборомПоНастройке.count >= 5, """
            живых вызовов .isAccessibilitySize найдено \
            \(сВыборомПоНастройке.count) при ожидаемых 5+. \
            Это КОНТРОЛЬ разбора, а не предмет: обнулился он — \
            значит ослеп вырезатель комментариев, и запрет ниже \
            зелен по той же причине.
            """)
    }

    // MARK: - Подделка разбора

    @Test("Вырезатель комментариев не оставляет имя в прозе и не съедает код")
    func комментарииВырезаются() {
        let проба = """
            ViewThatFits(in: .horizontal) {
            // ViewThatFits(in: .horizontal) {
            /// **`ViewThatFits` здесь не применяется** — он запрещён.
                let x = 1  // ViewThatFits в хвосте строки
            /* ViewThatFits(in: .horizontal) {
               вторая строка блочного комментария
               ViewThatFits снова */
            let y = 2
            """
        let строки = Self.безКомментариев(проба)
        let живые = строки.enumerated().filter { $0.element.contains("ViewThatFits") }

        // Живым обязан остаться ровно один — самый первый.
        #expect(живые.count == 1, """
            вырезатель комментариев оставил \(живые.count) вхождений \
            вместо одного: \(живые.map(\.offset))
            """)
        #expect(живые.first?.offset == 0)

        // И обратная половина: код не съеден.
        #expect(строки.contains { $0.contains("let x = 1") })
        #expect(строки.contains { $0.contains("let y = 2") })
    }

    // MARK: - Дорога: самого вызова нет нигде

    @Test("Ни одного живого вызова ViewThatFits в приложении")
    func ниОдногоЖивогоВызова() {
        var виноватые: [String] = []
        for (путь, текст) in Self.исходники() {
            for (номер, строка) in Self.безКомментариев(текст).enumerated()
            where строка.contains("ViewThatFits") {
                виноватые.append("\(путь):\(номер + 1): \(строка.trimmingCharacters(in: .whitespaces))")
            }
        }

        // Вердикт точный: сплошное «красная линия нарушена» не говорит,
        // что именно вернули.
        #expect(виноватые.isEmpty, """
            ViewThatFits вернулся в приложение — красная линия проекта:
            \(виноватые.joined(separator: "\n"))

            Он держит в дереве ОБЕ раскладки, и озвучка находит по два
            элемента на один орган: так появились две кнопки «Отменить».
            Заменять явным выбором по @Environment(\\.dynamicTypeSize)
            и .isAccessibilitySize — образец UndoToastView
            в Togo/App/RootView.swift.
            """)
    }

    // MARK: - Значение: на месте снятого стоит выбор, а не одна ветка

    /// Снять `ViewThatFits` и оставить одну раскладку — это пройти
    /// запрет и сломать крупный кегль **молча**. Поэтому у двух мест,
    /// откуда он снят 23.10.2026, проверяется ещё и замена.
    ///
    /// `TGListRow` взят не для полноты: его зовёт **каждая строка
    /// настроек**, то есть цена потери здесь выше, чем у любого экрана.
    @Test("Раскладка выбирается по настройке человека, а не по месту",
          arguments: [
            ("Togo/DesignSystem/Components/TGRows.swift", "TGListRow"),
            ("Togo/Features/Onboarding/OnboardingSteps.swift", "LabeledField"),
          ])
    func раскладкаВыбираетсяПоНастройкеЧеловека(путь: String, тип: String) throws {
        let файл = try #require(Self.исходники().first { $0.путь == путь },
                                "файл \(путь) не прочитан — сторож смотрит в пустоту")
        let код = Self.безКомментариев(файл.текст).joined(separator: "\n")

        #expect(код.contains("struct \(тип)"), """
            типа \(тип) в \(путь) больше нет — он переименован или уехал. \
            Сторож ниже про него молчит, и молчание тут ничего не значит.
            """)
        #expect(код.contains("isAccessibilitySize"), """
            \(тип) (\(путь)) перестал выбирать раскладку по \
            .isAccessibilitySize. Если ViewThatFits при этом тоже нет, \
            то осталась ОДНА раскладка — запрет зелен, а на крупном \
            системном кегле подпись и значение снова ужимаются \
            до нечитаемого.
            """)
        #expect(код.contains("dynamicTypeSize"), """
            \(тип) (\(путь)) больше не читает @Environment(\\.dynamicTypeSize)
            """)
    }
}
