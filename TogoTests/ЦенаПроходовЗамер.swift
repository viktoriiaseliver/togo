@testable import Togo

/// Разовый ЗАМЕР, а не сторож: печатает числа и никого не держит.
///
/// # Зачем отдельно от тестов
///
/// 28.10.2026 чинились три места, где цена росла от произведения
/// записей на число мест, где их спрашивают. Вопрос Виктории после
/// починки — «а приложение не виснет больше?» — требует ЧИСЛА,
/// а не обещания.
///
/// Сторожем это быть не может: порог времени на общей машине меряет
/// занятость соседей, а не код. Он краснел бы от чужого прогона
/// и зеленел бы на отдыхающей машине при вернувшейся квадратичности.
/// Поэтому здесь нет ни одного `#expect` про время — только печать.
///
/// > **Число без условий замера — предание.** Поэтому печатается
/// > и объём данных, и то, что считалось, а читать его надо рядом
/// > с загрузкой машины на тот момент.
///
/// Запуск:
/// ```
/// xcodebuild test -only-testing:TogoTests/ЦенаПроходовЗамер
/// ```
@Suite("Цена проходов по дневнику · замер, не сторож")
@MainActor
struct ЦенаПроходовЗамер {

    /// Столько записей дала карта Стича при восстановлении — это
    /// не круглое число для красоты, а измеренный объём живой базы.
    private static let записей = 1400

    /// Дневник с ПРОГУЛКАМИ, и это поправка к первой редакции замера.
    ///
    /// **Первая редакция не заводила ни одной `.walk`** — только
    /// `.outing`, `.meal`, `.stool`. Из-за этого самое дорогое место
    /// `TimelineBuilder.blocks` не выполнялось вовсе:
    /// `outingsThatBecameWalks` перебирает прогулки, а их было ноль,
    /// и функция возвращала пустой словарь, не сделав ничего.
    ///
    /// > **Замер на данных, в которых нет предмета, даёт честное число
    /// > и ложный вывод.** Семь миллисекунд были правдой про массив
    /// > без прогулок и неправдой про дневник живой собаки.
    ///
    /// Теперь каждая четвёртая запись — прогулка, и у каждой есть
    /// отметка внутри (`walkEventID`): так лента и выглядит у человека,
    /// который ведёт дневник режимом прогулки.
    private func дневник() -> [LogEvent] {
        let начало = Calendar.current.startOfDay(for: .now)
            .addingTimeInterval(-60 * 86_400)
        var записи: [LogEvent] = []
        записи.reserveCapacity(Self.записей)
        for i in 0..<Self.записей {
            let когда = начало.addingTimeInterval(Double(i) * 3_700)
            switch i % 4 {
            case 0:
                // Выход, который через три минуты перерос в прогулку:
                // ровно тот случай, который ищет `outingsThatBecameWalks`.
                записи.append(LogEvent(kind: .outing, date: когда, authorName: "Виктория"))
                let прогулка = LogEvent(kind: .walk,
                                        date: когда.addingTimeInterval(180),
                                        authorName: "Виктория")
                записи.append(прогулка)
                // Отметка мочи внутри прогулки: вид записи `.outing`,
                // исход `.urine` — так её пишет `WalkRecorder`.
                let отметка = LogEvent(kind: .outing,
                                       date: когда.addingTimeInterval(300),
                                       authorName: "Виктория")
                отметка.outcome = .urine
                отметка.walkEventID = прогулка.id
                записи.append(отметка)
            case 1: записи.append(LogEvent(kind: .meal, date: когда, authorName: "Виктория"))
            case 2: записи.append(LogEvent(kind: .stool, date: когда, authorName: "Виктория"))
            default: записи.append(LogEvent(kind: .water, date: когда, authorName: "Виктория"))
            }
        }
        return записи
    }

    private func секунды(_ работа: () -> Void) -> Double {
        let старт = Date()
        работа()
        return Date().timeIntervalSince(старт)
    }

    @Test("Календарь месяца: сорок две ячейки")
    func календарь() {
        let события = дневник()
        let календарь = Calendar.current
        let дни = (0..<42).compactMap {
            календарь.date(byAdding: .day, value: -$0, to: .now)
        }
        #expect(события.count >= Self.записей, "замер не состоялся: дневник пуст")
        #expect(дни.count == 42, "сетка календаря не собралась")

        // КАК БЫЛО: на каждую ячейку — полный проход по дневнику
        // с Calendar.isDate(_:inSameDayAs:).
        let было = секунды {
            for день in дни { _ = Diary.onDay(события, день) }
        }
        // КАК СТАЛО: один проход, дальше словарь.
        let стало = секунды {
            let индекс = Diary.поДням(события)
            for день in дни { _ = индекс[календарь.startOfDay(for: день)] ?? [] }
        }

        print("""
            ЗАМЕР · КАЛЕНДАРЬ ИСТОРИИ, \(события.count) записей, 42 ячейки
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
            """)
    }

    @Test("График тридцати дней")
    func график() {
        let события = дневник()
        let календарь = Calendar.current
        let дни = (0..<30).compactMap {
            календарь.date(byAdding: .day, value: -$0, to: .now)
        }
        #expect(события.count >= Self.записей, "замер не состоялся: дневник пуст")

        // КАК БЫЛО: `filtered` — вычисляемое свойство, то есть отбор
        // пересчитывался на каждый из тридцати дней заново.
        let было = секунды {
            for день in дни {
                let отобранные = Diary.active(события).filter { $0.kind == .outing }
                _ = Diary.onDay(отобранные, день)
            }
        }
        let стало = секунды {
            let индекс = Diary.поДням(события.filter { $0.kind == .outing })
            for день in дни { _ = индекс[календарь.startOfDay(for: день)] ?? [] }
        }

        print("""
            ЗАМЕР · ГРАФИК ИСТОРИИ, \(события.count) записей, 30 дней
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
            """)
    }

    /// Из чего складывается один проход по ленте.
    ///
    /// Кеш убрал ПОВТОРНЫЕ проходы, но первый остался — и он сам
    /// по себе дорог. Этот замер отвечает, чем именно: чинить надо
    /// причину, а не окно данных.
    @Test("Из чего состоит один проход по ленте")
    func разбивка() {
        let события = дневник()
        #expect(события.count >= Self.записей, "замер не состоялся: дневник пуст")
        let сейчас = Date()

        let живые = Diary.active(события)
        #expect(!живые.isEmpty, "после отбора не осталось записей — мерить нечего")

        let отбор = секунды { _ = Diary.active(события) }
        let сортировка = секунды {
            _ = живые.sorted { lhs, rhs in
                lhs.date == rhs.date ? lhs.id.uuidString < rhs.id.uuidString : lhs.date < rhs.date
            }
        }
        let блоки = секунды { _ = TimelineBuilder.blocks(живые) }
        let ритм = секунды { _ = WalkRhythmAnalyzer.rhythm(events: события, now: сейчас) }

        print("""
            ЗАМЕР · ИЗ ЧЕГО ПРОХОД, \(события.count) записей
              Diary.active:              \(Int(отбор * 1000)) мс
              только сортировка:         \(Int(сортировка * 1000)) мс
              TimelineBuilder.blocks:    \(Int(блоки * 1000)) мс  ← сортировка внутри
              WalkRhythmAnalyzer.rhythm: \(Int(ритм * 1000)) мс
            """)
    }

    @Test("Главный экран: лента и ритм за один кадр")
    func главный() {
        let события = дневник()
        #expect(события.count >= Self.записей, "замер не состоялся: дневник пуст")
        let сейчас = Date()

        // КАК БЫЛО: восемнадцать обращений к трём вычисляемым
        // свойствам, и каждое строило ленту заново.
        let было = секунды {
            for _ in 0..<18 {
                let живые = Diary.active(события)
                let блоки = TimelineBuilder.blocks(живые)
                _ = TimelineBuilder.timeIndoorsNow(блоки, now: сейчас, threshold: 0)
                _ = блоки.last(where: \.isOuting)?.endedAt
                _ = WalkRhythmAnalyzer.rhythm(events: события, now: сейчас)
            }
        }
        // КАК СТАЛО: память считает один раз, остальные семнадцать
        // обращений попадают в неё.
        //
        // **Замер переписан 05.11.2026 с `КешЛенты` на `ПамятьЛенты`,
        // и причина важнее правки.** 28.10 две сессии независимо
        // решили одно и сделали два механизма; выбрана `ПамятьЛенты`,
        // а `КешЛенты` остался без входа. Замер при этом продолжал
        // мерить ПРОИГРАВШИЙ механизм — то есть отвечал на вопрос
        // «а приложение не виснет?» про код, которого на экране нет.
        //
        // > **Замер без предмета хуже отсутствующего замера:** он
        // > печатает правдоподобное число и закрывает вопрос.
        let память = ПамятьЛенты()
        let стало = секунды {
            for _ in 0..<18 {
                память.сверить(события, now: сейчас, день: сейчас)
                _ = память.блоки { TimelineBuilder.blocks(Diary.active(события)) }
                _ = память.ритм { WalkRhythmAnalyzer.rhythm(events: события, now: сейчас) }
            }
        }

        print("""
            ЗАМЕР · ГЛАВНЫЙ ЭКРАН, \(события.count) записей, 18 обращений за кадр
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
              бюджет кадра при 60 к/с: 16 мс
            """)
    }
}
