import Testing
import Foundation
@testable import Togo

/// Разовый ЗАМЕР, а не сторож: печатает числа и никого не держит.
///
/// # Зачем отдельно от тестов
///
/// 28.10.2026 чинились три места, где цена росла от произведения
/// записей на число мест, где их спрашивают. Вопрос Виктории после
/// починки — «а приложение не виснет больше?» — требует ЧИСЛА,
/// а не обещания.
///
/// Сторожем это быть не может: порог времени на общей машине меряет
/// занятость соседей, а не код. Он краснел бы от чужого прогона
/// и зеленел бы на отдыхающей машине при вернувшейся квадратичности.
/// Поэтому здесь нет ни одного `#expect` про время — только печать.
///
/// > **Число без условий замера — предание.** Поэтому печатается
/// > и объём данных, и то, что считалось, а читать его надо рядом
/// > с загрузкой машины на тот момент.
///
/// Запуск:
/// ```
/// xcodebuild test -only-testing:TogoTests/ЦенаПроходовЗамер
/// ```
@Suite("Цена проходов по дневнику · замер, не сторож")
@MainActor
struct ЦенаПроходовЗамер {

    /// Столько записей дала карта Стича при восстановлении — это
    /// не круглое число для красоты, а измеренный объём живой базы.
    private static let записей = 1400

    private func дневник() -> [LogEvent] {
        let начало = Calendar.current.startOfDay(for: .now)
            .addingTimeInterval(-60 * 86_400)
        return (0..<Self.записей).map { i in
            LogEvent(kind: i % 3 == 0 ? .outing : (i % 3 == 1 ? .meal : .stool),
                     date: начало.addingTimeInterval(Double(i) * 3_700),
                     authorName: "Виктория")
        }
    }

    private func секунды(_ работа: () -> Void) -> Double {
        let старт = Date()
        работа()
        return Date().timeIntervalSince(старт)
    }

    @Test("Календарь месяца: сорок две ячейки")
    func календарь() {
        let события = дневник()
        let календарь = Calendar.current
        let дни = (0..<42).compactMap {
            календарь.date(byAdding: .day, value: -$0, to: .now)
        }
        #expect(события.count == Self.записей, "замер не состоялся: дневник пуст")
        #expect(дни.count == 42, "сетка календаря не собралась")

        // КАК БЫЛО: на каждую ячейку — полный проход по дневнику
        // с Calendar.isDate(_:inSameDayAs:).
        let было = секунды {
            for день in дни { _ = Diary.onDay(события, день) }
        }
        // КАК СТАЛО: один проход, дальше словарь.
        let стало = секунды {
            let индекс = Diary.поДням(события)
            for день in дни { _ = индекс[календарь.startOfDay(for: день)] ?? [] }
        }

        print("""
            ЗАМЕР · КАЛЕНДАРЬ ИСТОРИИ, \(Self.записей) записей, 42 ячейки
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
            """)
    }

    @Test("График тридцати дней")
    func график() {
        let события = дневник()
        let календарь = Calendar.current
        let дни = (0..<30).compactMap {
            календарь.date(byAdding: .day, value: -$0, to: .now)
        }
        #expect(события.count == Self.записей, "замер не состоялся: дневник пуст")

        // КАК БЫЛО: `filtered` — вычисляемое свойство, то есть отбор
        // пересчитывался на каждый из тридцати дней заново.
        let было = секунды {
            for день in дни {
                let отобранные = Diary.active(события).filter { $0.kind == .outing }
                _ = Diary.onDay(отобранные, день)
            }
        }
        let стало = секунды {
            let индекс = Diary.поДням(события.filter { $0.kind == .outing })
            for день in дни { _ = индекс[календарь.startOfDay(for: день)] ?? [] }
        }

        print("""
            ЗАМЕР · ГРАФИК ИСТОРИИ, \(Self.записей) записей, 30 дней
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
            """)
    }

    @Test("Главный экран: лента и ритм за один кадр")
    func главный() {
        let события = дневник()
        #expect(события.count == Self.записей, "замер не состоялся: дневник пуст")
        let сейчас = Date()

        // КАК БЫЛО: восемнадцать обращений к трём вычисляемым
        // свойствам, и каждое строило ленту заново.
        let было = секунды {
            for _ in 0..<18 {
                let живые = Diary.active(события)
                let блоки = TimelineBuilder.blocks(живые)
                _ = TimelineBuilder.timeIndoorsNow(блоки, now: сейчас, threshold: 0)
                _ = блоки.last(where: \.isOuting)?.endedAt
                _ = WalkRhythmAnalyzer.rhythm(events: события, now: сейчас)
            }
        }
        // КАК СТАЛО: кеш считает один раз, остальные семнадцать
        // обращений попадают в него.
        let кеш = КешЛенты()
        let стало = секунды {
            for _ in 0..<18 { _ = кеш.срез(события, now: сейчас) }
        }

        print("""
            ЗАМЕР · ГЛАВНЫЙ ЭКРАН, \(Self.записей) записей, 18 обращений за кадр
              было:  \(Int(было * 1000)) мс
              стало: \(Int(стало * 1000)) мс
              во сколько раз: \(стало > 0 ? String(format: "%.1f", было / стало) : "—")
              бюджет кадра при 60 к/с: 16 мс
            """)
    }
}
