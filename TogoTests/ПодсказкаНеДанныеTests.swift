import Testing
import Foundation

/// Подсказка поля не может БЫТЬ значением данных.
///
/// # Почему сторож на класс, а не на слова
///
/// 23.09.2026 пришёл отзыв `AEXYTDmy`: «Где-то stitch а где то Стич».
/// Ключ «Стич» получил переводы `en Stitch`, `fr Stitch` — и человек,
/// назвавший собаку так же, увидел, как приложение переводит его
/// собственное слово. Починили 23.10 в онбординге, 25.10 в редакторе
/// профиля (`de07411`).
///
/// > **Починка по адресу из отзыва закрывает адрес, а не класс.**
///
/// Класс нашёлся 25.10.2026, и он шире клички. Замер по 223 файлам
/// `Togo` · `TogoShared` · `TogoWidgets` (комментарии вырезаны):
/// подсказок `TextField("…"` — **60**, и среди них лежали данные живых
/// людей и документов, уже обработанные посторонним переводчиком:
///
/// ```
/// Кочубина      фамилия врача   en Kochubina · fr Kotchoubina · uk Кочубіна
/// Ницца → Лион  маршрут         en/fr Nice → Lyon · uk Ніцца → Ліон
/// VF120682      номер бланка    четыре локали
/// 8935331       номер рецепта   (НЕ номер чипа — `Prescription.number`)
/// 12,9 · 51,5   анализы Стича   по разу на язык вычитки
/// ```
///
/// Механизм известен и записан у соседей: `TextField(_ titleKey:)`
/// принимает `LocalizedStringKey`, поэтому **любая** подсказка-литерал
/// уходит в каталог. Это свойство подписи, а не оплошность автора —
/// 60 из 60, исключений ноль.
///
/// # Чего этот сторож НЕ ловит, и это не дыра, а граница
///
/// Он ловит ровно одно: **подсказка целиком является значением**.
/// Имя человека от любого другого слова не отличается ничем, что
/// видно машине, и «4 таблетки» — переводимая фраза, а не число.
///
/// ```
/// ловит           12,9 · 51,5 · 66 · 8935331 · VF120682 · 0,1 мг · 66 мкг
/// НЕ ловит        Кочубина          имя неотличимо от слова
/// НЕ ловит        4 таблетки        число ПЛЮС существительное
/// ```
///
/// Второе и третье держит `PlaceholderOriginTests`: он требует, чтобы
/// по каждой подсказке было **записано решение**. Два сторожа на одно
/// место — не дублирование: **этот держит ЗНАЧЕНИЕ, тот держит
/// ДОРОГУ** (решение принято человеком). Снимать по очереди.
///
/// # Правило прогнано на ЗДОРОВОМ коде ПРЕЖДЕ, чем стало тестом
///
/// Шаг оплачен соседями дважды: первая редакция «цифра, не приклеенная
/// к букве» покраснела на `Token.Space.s28`, первая редакция запрета
/// сложения — на трёх верных местах медслоя. Здесь он тоже отработал:
/// **первый вариант правила мерил ДОЛЮ цифр в строке, и она разводит
/// случаи в обратную сторону.**
///
/// ```
/// 4 таблетки   доля цифр 0,11   образец данных, подсказке не место
/// Т4 общий     доля цифр 0,14   название показателя, ЗАКОННО
/// ```
///
/// У законного случая доля ВЫШЕ, чем у дефекта. Порог по доле покрасил
/// бы «Т4 общий» и пропустил «4 таблетки» — то есть ровно наоборот.
///
/// Работающая ось другая: **цифра есть, а букв не больше четырёх**.
/// Всё, что не число, — это единица («мг», «мкг») или префикс номера
/// («VF»). Замер 25.10.2026, обе стороны сняты одной командой:
///
/// ```
/// больной код   de07411, до починок      14 значений
/// здоровый код  после трёх починок        2 значения — оба «4,1»
/// ```
///
/// Два оставшихся — не промах правила, а **решение с хозяином**:
/// у поля веса ярлыка нет, и десятичная запятая — единственное, что
/// подсказка сообщает. Для таких заведён единственный выход, и он
/// не «список исключений в тесте», а **пометка в каталоге**:
/// `shouldTranslate: false` С НАЗВАННОЙ ПРИЧИНОЙ. Причина обязательна
/// по той же цене, что у соседа: пометка без причины — кнопка гашения
/// сторожа, через месяц неотличимая от дыры.
///
/// # Вход, который этот тест читает с диска
///
/// Исходники `Togo` · `TogoShared` · `TogoWidgets` и каталог
/// `TogoShared/Resources/Localizable.xcstrings` — через `#filePath`.
/// Тест ломается от переноса каталогов, и ломается не на своём
/// предмете; адрес назван здесь нарочно.
@Suite("Подсказка поля не является значением данных")
struct ПодсказкаНеДанныеTests {

    /// Ниже этого числа просмотренных файлов замер не состоялся.
    /// Сканер, переставший что-либо находить, молчит так же, как тот,
    /// кому нечего сказать. На 25.10.2026 обход видел 225 файлов.
    static let записаноФайловНеМенее = 180

    /// Подсказок в живом коде на 25.10.2026 — 60 вхождений, 45 различных.
    /// Порог ниже замера нарочно: он ловит ослепший разбор, а не рост.
    static let записаноПодсказокНеМенее = 40

    private static var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // TogoTests
            .deletingLastPathComponent()   // корень репозитория
    }

    /// Текст без комментариев, разбор СЛЕВА НАПРАВО.
    ///
    /// Без вырезки сторож меряет прозу — и этот файл тому пример:
    /// запрещённые формы набраны выше в доккомментарии семь раз.
    ///
    /// **Порядок проверок обязателен: `//` ищется НАРАВНЕ с `/*`,
    /// и побеждает тот, кто левее.** Редакция, проверявшая `/*`
    /// раньше, слепла на 43 314 символах кода: строчный комментарий
    /// с `/**` внутри (конец любого glob-пути, `Togo/DesignSystem/**`)
    /// открывал блок, который уже не закрывался, и съедал файл
    /// до конца. Стоит такое как раз в головах тех файлов, что
    /// цитируют правила сторожей.
    /// Не `private` нарочно: `PlaceholderOriginTests` зовёт ту же
    /// вырезку. Две копии разбора разойдутся молча, и разошедшийся
    /// разбор даёт ложную ЗЕЛЕНЬ, а не красное.
    func безКомментариев(_ текст: String) -> String {
        var вне = ""
        var вБлоке = false
        for строка in текст.components(separatedBy: .newlines) {
            var остаток = Substring(строка)
            var годное = ""
            while !остаток.isEmpty {
                if вБлоке {
                    guard let конец = остаток.range(of: "*/") else { остаток = ""; break }
                    остаток = остаток[конец.upperBound...]
                    вБлоке = false
                    continue
                }
                let блок = остаток.range(of: "/*")
                let строчный = остаток.range(of: "//")
                if let с = строчный, блок == nil || с.lowerBound < блок!.lowerBound {
                    годное += остаток[остаток.startIndex..<с.lowerBound]
                    остаток = ""
                } else if let б = блок {
                    годное += остаток[остаток.startIndex..<б.lowerBound]
                    остаток = остаток[б.upperBound...]
                    вБлоке = true
                } else {
                    годное += остаток
                    остаток = ""
                }
            }
            вне += годное + "\n"
        }
        return вне
    }

    /// Подсказка ЦЕЛИКОМ является значением данных.
    ///
    /// Цифра есть, а букв не больше четырёх — то есть всё, что не
    /// число, это единица или префикс номера. Проверено на обеих
    /// сторонах: см. голову набора.
    func значениеДанных(_ подсказка: String) -> Bool {
        guard подсказка.contains(where: \.isNumber) else { return false }
        return подсказка.filter(\.isLetter).count <= 4
    }

    private struct Находка {
        let подсказка: String
        let адрес: String
    }

    private func подсказки() -> (все: [Находка], файлов: Int) {
        let fm = FileManager.default
        var все: [Находка] = []
        var файлов = 0
        // `TextField("…"` — литерал первым аргументом. Форма с ПЕРЕМЕННОЙ
        // (`TextField(подсказкаВеса, …)`) берёт перегрузку StringProtocol
        // и каталога не спрашивает вовсе — её здесь нет нарочно.
        let образец = try? NSRegularExpression(pattern: #"TextField\(\s*"([^"]*)""#)
        for каталог in ["Togo", "TogoShared", "TogoWidgets"] {
            let корневой = Self.корень.appendingPathComponent(каталог)
            guard let обходчик = fm.enumerator(at: корневой,
                                               includingPropertiesForKeys: nil) else { continue }
            for случай in обходчик {
                guard let url = случай as? URL, url.pathExtension == "swift",
                      let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                файлов += 1
                let имя = url.lastPathComponent
                for (i, строка) in безКомментариев(текст)
                    .components(separatedBy: .newlines).enumerated() {
                    let диапазон = NSRange(строка.startIndex..., in: строка)
                    for м in образец?.matches(in: строка, range: диапазон) ?? [] {
                        guard let r = Range(м.range(at: 1), in: строка) else { continue }
                        все.append(Находка(подсказка: String(строка[r]),
                                           адрес: "\(имя):\(i + 1)"))
                    }
                }
            }
        }
        return (все, файлов)
    }

    /// Ключи с `shouldTranslate: false` И названной причиной.
    ///
    /// Пустой `comment` пометкой не считается — иначе это кнопка
    /// гашения. Порог десять символов тот же, что у
    /// `PlaceholderOriginTests.непереводимые()`.
    private func помеченыБезПеревода() throws -> Set<String> {
        let url = Self.корень
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let корень = try JSONSerialization.jsonObject(with: Data(contentsOf: url))
            as? [String: Any]
        let строки = корень?["strings"] as? [String: Any] ?? [:]
        var собрано: Set<String> = []
        for (ключ, запись) in строки {
            guard let запись = запись as? [String: Any],
                  (запись["shouldTranslate"] as? Bool) == false,
                  let причина = запись["comment"] as? String,
                  причина.trimmingCharacters(in: .whitespacesAndNewlines).count >= 10
            else { continue }
            собрано.insert(ключ)
        }
        return собрано
    }

    @Test("Обход просмотрел файлы и нашёл подсказки")
    func былоЧтоПроверять() {
        let (все, файлов) = подсказки()
        #expect(файлов >= Self.записаноФайловНеМенее, """
            обход увидел \(файлов) файлов при пороге \
            \(Self.записаноФайловНеМенее) — замер не состоялся. \
            Сканер, переставший находить, молчит так же, как тот, \
            кому нечего сказать.
            """)
        #expect(все.count >= Self.записаноПодсказокНеМенее, """
            подсказок найдено \(все.count) при пороге \
            \(Self.записаноПодсказокНеМенее) — разбор ослеп. \
            Проверь вырезку комментариев: редакция, читавшая `/*` \
            раньше `//`, съедала файлы целиком.
            """)
    }

    @Test("Ни одна подсказка не является значением данных")
    func значенийВПодсказкахНет() throws {
        let (все, _) = подсказки()
        let помечены = try помеченыБезПеревода()

        // Контроль в ТОЙ ЖЕ команде, что и предмет, и подверженный
        // тому же отказу: если чтение каталога молча вернуло пусто,
        // escape «пометка в каталоге» перестанет работать — и сторож
        // покраснеет на верном коде вместо того, чтобы позеленеть
        // на неверном. Пустой разбор каталога обязан быть виден.
        #expect(!помечены.isEmpty, """
            в каталоге не нашлось НИ ОДНОЙ пометки `shouldTranslate: false` \
            с причиной. Либо разбор каталога отказал, либо причины у всех \
            стёрли — в обоих случаях выход для решений с хозяином закрыт.
            """)

        let нарушения = все
            .filter { значениеДанных($0.подсказка) && !помечены.contains($0.подсказка) }
            .map { "  \($0.адрес)\t«\($0.подсказка)»" }

        #expect(нарушения.isEmpty, """
            подсказка поля — это ЗНАЧЕНИЕ ДАННЫХ:

            \(нарушения.joined(separator: "\n"))

            `TextField(_ titleKey:)` принимает `LocalizedStringKey`, \
            поэтому литерал отсюда уходит в каталог строк и дальше \
            постороннему переводчику. Числу перевод не нужен, а вычитку \
            на четырёх языках оно просит; номеру и фамилии — тем более.

            Выбери одно:
              · подсказка про ФОРМАТ, а не пример («доза с единицей», \
            «только число», «с бланка») — так сделано с девятью 25.10.2026;
              · число нужно показать именно числом — тогда \
            `shouldTranslate: false` в каталоге И ПРИЧИНА рядом. \
            Пометка без причины не считается: через месяц она \
            неотличима от дыры.

            Разбор целиком — голова этого набора.
            """)
    }
}
