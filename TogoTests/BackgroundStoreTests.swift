    @Test("Снимок ужимается до тысячи точек и уезжает JPEG’ом")
    func снимокУжимается() throws {
        let большой = Self.картинка(width: 2400, height: 1600)
        let ужатое = try #require(ФонФото.ужать(большой))
        let картинка = try #require(UIImage(data: ужатое))
        #expect(max(картинка.size.width, картинка.size.height) <= ФонФото.maxSide)

        // **СРАВНИВАТЬ НАДО ОДИН ФОРМАТ С ОДНИМ, И ЭТО ЗАМЕР 23.10.2026.**
        // Прежняя редакция сравнивала `ужатое.count < большой.count`,
        // то есть JPEG уменьшенного против **PNG исходного**, и упала:
        //
        // ```
        // ужатое  442 466 Б      большой  350 846 Б
        // ```
        //
        // Причина — в фикстуре, а не в коде. Она рисует 8-пиксельные
        // блоки 97 оттенков: PNG жмёт плоские блоки отлично, а после
        // уменьшения в 2,4 раза они становятся высокочастотным
        // хроматическим шумом, который JPEG жмёт отвратительно.
        // Утверждение держало **две переменные разом** — смену формата
        // и смену размера, — и приписало одной то, что сделала другая.
        //
        // > Ровно то, что мы ловим у сторожей: ось выбрана не та.
        // > «Ужатое меньше исходного» — обещание продукта, но измерять
        // > его надо **вкладом ужатия**, а вклад формата держать
        // > постоянным.
        //
        // Поэтому эталон сравнения — тот же снимок, закодированный
        // JPEG’ом **без уменьшения**: разница между ним и результатом
        // и есть то, что сделало ужатие.
        let полныйJPEG = try #require(
            UIImage(data: большой)?.jpegData(compressionQuality: ФонФото.quality))
        #expect(ужатое.count < полныйJPEG.count, """
            ужатое \(ужатое.count) Б против полноразмерного JPEG \
            \(полныйJPEG.count) Б — уменьшение не дало выигрыша. \
            Сравнение идёт JPEG с JPEG нарочно: с PNG исходника оно \
            мерило бы смену формата, а не ужатие.
            """)

        // Фикстура не выродилась: однотонная заливка сжалась бы
        // до сотни байт, и «меньше исходного» стало бы истинным
        // при неработающем ужатии.
        #expect(большой.count > 10_000, """
            исходник \(большой.count) Б — фикстура выродилась, \
            и сравнение выше ничего не значит.
            """)

        // JPEG начинается с FF D8 FF. PNG прошёл бы по размеру
        // и занял бы втрое больше.
        #expect(ужатое.prefix(3) == Data([0xFF, 0xD8, 0xFF]))

        // Контроль в том же замере: маленькое не растягиваем.
        let маленький = Self.картинка(width: 300, height: 200)
        let какЕсть = try #require(ФонФото.ужать(маленький))
        let тот = try #require(UIImage(data: какЕсть))
        #expect(max(тот.size.width, тот.size.height) <= 300)

        // И отрицательный контроль: не картинка — не снимок.
        #expect(ФонФото.ужать(Data("это не картинка".utf8)) == nil)
    }

    /// **`scale = 1` — иначе помощник врёт о том, что он сделал.**
    /// `UIGraphicsImageRenderer` без формата рисует в масштабе
    /// устройства (3× на iPhone), и запрос «300×200» давал снимок
    /// **900×600 пикселей**. Утверждения выше писались в пикселях
    /// и при этом мерили результат, втрое больший запрошенного, —
    /// то есть проверка маленькой картинки проверяла не маленькую.
    ///
    /// Замер 23.10.2026: именно эта пара (тот же дефект в помощнике
    /// и в боевом `ФонФото.ужать`) дала «просили 1000, получили 3000»
    /// и «просили 300, получили 900». Множитель один и тот же, и это
    /// не совпадение — обе стороны звали один и тот же конструктор.
    ///
    /// > Помощник теста — такой же инструмент, как и предмет, и
    /// > **подвержен ровно тому классу, который ищет**.
    private static func картинка(width: CGFloat, height: CGFloat) -> Data {
        let формат = UIGraphicsImageRendererFormat.default()
        формат.scale = 1
        let renderer = UIGraphicsImageRenderer(size: CGSize(width: width, height: height),
                                               format: формат)
        let image = renderer.image { контекст in
            // Шум, а не заливка: однотонный PNG сжимается до сотни байт,
            // и «ужатое меньше исходного» стало бы ложным.
            for x in stride(from: 0, to: width, by: 8) {
                for y in stride(from: 0, to: height, by: 8) {
                    UIColor(hue: CGFloat((Int(x + y) % 97)) / 97,
                            saturation: 1, brightness: 1, alpha: 1).setFill()
                    контекст.fill(CGRect(x: x, y: y, width: 8, height: 8))
                }
            }
        }
        return image.pngData() ?? Data()
    }

