/// Повышенный контраст у роли, которой он нужен, **меняет цвет**.
///
/// # Почему этот набор отдельный, а не внутри `ThemeContrastTests`
///
/// Решение по замеру, не по вкусу. `ThemeContrastTests` сегодня зелёный
/// целиком, и `make guard` на нём работает. Эти два теста **рождены
/// красными**, а единица блокировки подделки — **НАБОР**, а не запись:
/// `check_guard.py:102` судит кодом возврата `xcodebuild test
/// -only-testing:<набор>` и отказывается до подделки, если у набора
/// есть объявленное красное. Положи я их рядом — я бы погасил
/// возможность подделки у `всеПарыВоВсехРежимах` и
/// у `плашкаВыключеннойСуществует`, то есть заплатил бы чужими
/// сторожами за своего. Цена своего набора: подделка невозможна
/// **здесь**, и это названо, а не умолчано.
///
/// # Чем этот набор отличается от соседнего по предмету
///
/// `ThemeContrastTests` спрашивает «проходит ли пара порог». Он
/// **по устройству** не может увидеть то, что здесь: пара, проходящая
/// порог в обоих светлых режимах одним и тем же числом, для него
/// в полном порядке.
///
/// ```
/// заголовок плаката на синем блоке   Light 5,9916   Light HC 5,9916
///                                    порог 4,5 — оба проходят
/// ```
///
/// > **Порог отвечает «читается ли». Он не отвечает «изменилось ли
/// > что-нибудь от того, что человек включил режим».**
///
/// Ось здесь — **от роли**, а не от счёта. «У N примитивов режимы
/// совпадают» гаснет от одной правки любого из N и ничего не говорит
/// о предмете; замер 15.10.2026 это и показал — число было 18 утром
/// и стало 17 днём от правки `arcticTint`, не имевшей к повышенному
/// контрасту отношения. Сторож на счёт сообщил бы о починке там,
/// где починки не было.
///
/// # Повышенный контраст ДОХОДИТ до экрана — это замерено, не выведено
///
/// Иначе весь набор был бы про следствие. `Dyn.uiColor`
/// (`TogoShared/DesignSystem/DynamicColor.swift:66-71`) спрашивает
/// `трейты.accessibilityContrast == .high` в момент отрисовки,
/// а приёмщик 08.10.2026 померил **пикселем**: `posterInkMuted`
/// в тёмной давал `#C8C8C4` при включённом «Увеличить контраст»
/// против `#B2B2AE` без него (`docs/journal/2026-10-08-chernila-shapki.md:538`).
/// То есть ось «контраст» живая. Ось «тема» проверена отдельно
/// и тоже живая — `ThemeNotPinnedTests`, после снятия двух прибивок.
/// Значит мёртвые значения — **причина, а не следствие**.
@MainActor
@Suite("Повышенный контраст меняет цвет у роли, которой он нужен")
struct ПовышенныйКонтрастМеняетЦветTests {

    struct Режим: Sendable {
        let имя: String
        let тёмная: Bool
        let контраст: Bool
    }

    static let режимы = [
        Режим(имя: "Dark", тёмная: true, контраст: false),
        Режим(имя: "Light", тёмная: false, контраст: false),
        Режим(имя: "Dark HC", тёмная: true, контраст: true),
        Режим(имя: "Light HC", тёмная: false, контраст: true),
    ]

    /// Три цветных блока плаката. Нейтральный и доза здесь не нужны:
    /// у них своя семья текста (`label`/`caption` и `labelOnDose`/
    /// `captionOnDose`), и у дозы повышенный контраст работает —
    /// 4,5140 → 10,0060, потому что ступень есть у подложки.
    struct Блок: Sendable {
        let имя: String
        let цвет: Color
    }

    static let цветныеБлоки: [Блок] = [
        Блок(имя: "синий", цвет: Token.Poster.background),
        Блок(имя: "тревожный", цвет: Token.Poster.backgroundAlarm),
        Блок(имя: "янтарный", цвет: Token.Poster.backgroundFasting),
    ]

    // MARK: Своё зрение первым

    /// Ноль найденного при нуле осмотренного — это «нечего было
    /// смотреть», а не «чисто». И отдельно: счётчик, который во всех
    /// режимах отдаёт одно число, прошёл бы оба теста ниже молча.
    @Test("Было что сторожить: четыре режима различимы, три блока на месте")
    func былоЧтоСторожить() throws {
        #expect(Self.режимы.count == 4, """
            режимов \(Self.режимы.count), ожидалось 4 — сломан список
            режимов, и ни одно число ниже читать нельзя.
            """)
        #expect(Self.цветныеБлоки.count == 3, """
            цветных блоков \(Self.цветныеБлоки.count), ожидалось 3.
            """)

        // Контроль на заведомо РАЗЛИЧАЮЩИХСЯ режимах: `inkMuted` имеет
        // ступень повышенного контраста во всех четырёх клетках, и она
        // измерена (Light 5,6533 → Light HC 7,8528). Счётчик, который
        // отвечает «совпадает» всегда, здесь провалится.
        var различий = 0
        for (а, б) in [(Self.режимы[1], Self.режимы[3]), (Self.режимы[0], Self.режимы[2])] {
            let x = Self.байты(Token.Ink.secondary, а)
            let y = Self.байты(Token.Ink.secondary, б)
            if x != y { различий += 1 }
        }
        #expect(различий == 2, """
            `Ink.secondary` обязан различаться между обычным и повышенным
            контрастом в ОБЕИХ темах — различий найдено \(различий) из 2.
            Это проверка МОЕГО зрения: счётчик, отдающий один цвет
            во всех режимах, прошёл бы оба теста ниже как зелёный.
            """)

        // И обратный контроль: `ink` в светлой заведомо СОВПАДАЕТ
        // (#101112 в обоих), и это не дефект — 18,90:1, расти некуда.
        // Счётчик, который всегда отвечает «различается», провалится тут.
        #expect(Self.байты(Token.Ink.primary, Self.режимы[1])
                == Self.байты(Token.Ink.primary, Self.режимы[3]), """
            `Ink.primary` в Light и Light HC обязан совпадать (#101112,
            18,90:1 — расти некуда). Он различается — значит счётчик
            отвечает про себя, а не про токены.
            """)
    }

    // MARK: Предмет первый — плашка второстепенной кнопки

    /// У второстепенной кнопки плашки нет, и повышенный контраст
    /// её не возвращает.
    ///
    /// **Ось — РАВЕНСТВО БАЙТ, а не порог**, и причина та же, по которой
    /// её выбрал сосед `плашкаВыключеннойСуществует`: порог 3,0
    /// покраснел бы и в тёмной, где плашка видна (1,4607:1, кадр 14.10),
    /// а WCAG 1.4.11 к тому же исключает неактивные элементы, и
    /// следующий снял бы пару целиком вместе с дефектом.
    ///
    /// ```
    ///            Button.Secondary.background × Surface.screen
    /// Dark       #2C2C2C на #050503    1,4607:1   плашка ВИДНА
    /// Light      #FFFFFF на #FFFFFF    1,0000:1   плашки НЕТ ВОВСЕ
    /// Dark HC    #2C2C2C на #050503    1,4607:1   видна
    /// Light HC   #FFFFFF на #FFFFFF    1,0000:1   НЕТ, и режим не помог
    /// ```
    ///
    /// **Светлая клетка — известный дефект; интересна вторая.** 15.10
    /// `Button.Disabled.background` увели с `night4` на `night5`
    /// решением Виктории, и выключенная кнопка плашку получила.
    /// `Surface.control` и `Button.Secondary.background` остались
    /// на `night4`, у которого `light` и `lightHC` равны `#FFFFFF`
    /// байт в байт — то есть **режим, который человек включает ровно
    /// затем, чтобы границы появились, не даёт ничего.**
    ///
    /// Происхождение то же, что у закрытого случая, и оно не чья-то
    /// невнимательность: `night4` = `color.fill.1` и `night1` =
    /// `color.bg.page` пришли из пакета Graphite, где контрол и страница
    /// — разные роли с одинаковым значением, потому что в Graphite
    /// карточки лежат на СЕРОЙ странице. Повышенного контраста
    /// у продуктового слоя пакета нет вовсе, и мы унаследовали пробел
    /// вместе со значениями.
    ///
    /// # Где это нарисовано — замер 15.10.2026
    ///
    /// ```
    /// Token.Component.Button.Secondary.background   2 живых читателя
    ///   TGButton.swift:112          variant .secondary, 10 вызовов
    ///   ActionGrid.swift:147        «Гулять», isPrimary: false
    /// Token.Surface.control                         1 живой читатель
    ///   DayTimeline.swift:231
    /// Token.Action.secondary · Chip.restBackground · ActionTile.background
    ///                                               по 0 читателей
    /// ```
    ///
    /// Поверхность под ними — `Surface.screen` (`night1`): TodayScreen:96,
    /// PrescriptionScreens:518, WalkMode:160, OnboardingFlow:157,
    /// SettingsScreen:35, LanguageScreen:108 — и `Component.Sheet.background`
    /// (`TGScaffolds.swift:59`), который тоже `night1`.
    ///
    /// # Чего этот сторож НЕ видит
    ///
    /// Он отвечает «значения различаются», а не «человек различает».
    /// `1,1707:1` у карточки на фоне он пропустит — и пропустит
    /// нарочно: про поверхности у нас ось равенство, потому что
    /// у роли «карточка на странице» порога не назвал никто, а
    /// придуманный порог был бы моим дизайн-решением. Появится кадр,
    /// говорящий, что 1,17 не видно, — ось меняется на порог, и вместе
    /// с ней меняется эта запись.
    ///
    /// Второе: он слеп к обводке. Плашку можно сделать различимой
    /// контуром вместо заливки, и тогда он останется красным при
    /// починенном экране. Лечится не ослаблением оси, а кадром:
    /// появится контур — запись снимается по кадру, а не по тесту.
    @Test("У второстепенной кнопки плашка есть в каждом из четырёх режимов")
    func плашкаВторостепеннойСуществует() throws {
        var слиплись: [String] = []
        var замеры: [String] = []

        for режим in Self.режимы {
            let плашка = Self.байты(Token.Component.Button.Secondary.background, режим)
            let фон = Self.байты(Token.Surface.screen, режим)
            замеры.append("\(режим.имя): \(Self.hex(плашка)) на \(Self.hex(фон))")
            if плашка == фон { слиплись.append(режим.имя) }
        }

        #expect(замеры.count == 4, """
            осмотрено режимов \(замеры.count), ожидалось 4.
            """)

        #expect(слиплись.isEmpty, """
            ПЛАШКА ВТОРОСТЕПЕННОЙ КНОПКИ СОВПАДАЕТ С ФОНОМ ЭКРАНА
            байт в байт в режимах: \(слиплись.joined(separator: ", ")).

            Замеры: \(замеры.joined(separator: " · ")).

            Это не «мало контраста», а РОВНО НОЛЬ разницы: 1,0000:1.
            `Button.Secondary.background` и `Surface.screen` оба сидят
            на значении `#FFFFFF` — `night4.light` и `night1.light`.

            ЧТО НЕ ВИДИТ ЧЕЛОВЕК. На главном экране «Сегодня» в светлой
            теме кнопка «Гулять» (ActionGrid.swift:62, isPrimary: false)
            нарисована белым на белом. Подпись держит 18,90:1, то есть
            СЛОВО он читает прекрасно — он не видит КНОПКУ. Рядом
            «Просится» лежит на акценте и плашку имеет; какая из двух
            надписей кнопка, а какая просто текст, различить нечем.
            То же у «Закрыть» на экране назначения (PrescriptionScreens:544,
            variant .secondary на Surface.screen) — единственный выход
            с экрана выглядит строкой текста.

            И ГЛАВНОЕ ПРО ЭТОТ НАБОР: человек включает «Увеличить
            контраст» именно затем, чтобы границы появились. В Light HC
            он получает ТЕ ЖЕ 1,0000:1 — `night4.lightHC` равен
            `night4.light` равен `#FFFFFF`. Режим не делает ничего
            у роли, которой он нужен больше всех.

            НЕ ЯВЛЯЕТСЯ ПОЧИНКОЙ: перевести Secondary на `night5`, как
            15.10 перевели Disabled. Тогда второстепенная кнопка
            и выключенная станут одного цвета, и это тот же класс
            дефекта на один шаг дальше — см. `ThemeContrastTests`,
            `нажатоеИВыключенноеНеСлипнутся`.

            ХОЗЯИН — Виктория: значение цвета её решение, не исполнителя.
            Исполнителю здесь принадлежит только замер и эта запись.
            """)
    }

    // MARK: Предмет второй — подпись плаката против его заголовка

    /// Подпись плаката остаётся тише заголовка во всех четырёх режимах.
    ///
    /// **Ось — ПОРЯДОК, а не порог и не равенство**, и она взята
    /// не у меня: инвариант записан в самом модуле,
    /// `TGPoster.swift:109-112` — «иерархия „показание громче подписи"
    /// держится на том, что у дозы это `captionOnDose` (6,19:1),
    /// а не `labelOnDose` (10,43:1): читаемы оба, но вторым подпись
    /// стала бы того же цвета, что число».
    ///
    /// Порог здесь не ось по замеру: все шесть светлых клеток порог
    /// **проходят**, и проходят с запасом.
    ///
    /// ```
    ///                       заголовок   подпись
    /// синий    · Light         5,9916    5,0397   тише ✓
    /// синий    · Light HC      5,9916    5,9916   ОДИН И ТОТ ЖЕ ЦВЕТ
    /// тревожный· Light         5,6162    4,7005   тише ✓
    /// тревожный· Light HC      5,6162    5,6162   ОДИН И ТОТ ЖЕ ЦВЕТ
    /// янтарный · Light         5,3703    4,5634   тише ✓
    /// янтарный · Light HC      5,3703    5,3703   ОДИН И ТОТ ЖЕ ЦВЕТ
    /// тёмные   · Dark/Dark HC  10,0–10,4 5,2–6,8  тише ✓
    /// ```
    ///
    /// Причина — в одном байте: `posterInk.lightHC` = `#FFFFFF`
    /// и `posterInkMuted.lightHC` = `#FFFFFF`. Заголовок белый
    /// по решению («блок остаётся цветным в обеих темах, поэтому текст
    /// на нём не следует за темой»), а подпись стала белой
    /// **08.10.2026 починкой контраста**: альфу сняли, `#FFFFFFE0 →
    /// #FFFFFF`, и подпись выросла 5,04 → 5,99. Замер тогда был верен
    /// и правка полезна — её мерили ПРОТИВ БЛОКА. Против СВОЕГО
    /// ЗАГОЛОВКА её не мерил никто, и единственное, чем подпись
    /// отличалась от заголовка, было ровно той альфой, которую сняли.
    ///
    /// > **Починка одной оси погасила другую, и обе про один пиксель.**
    /// > Белый — предел: «контрастнее» для подписи означало
    /// > «непрозрачнее», и дойдя до предела она догнала заголовок.
    /// > В тёмной этого не случилось, потому что там у подписи своя
    /// > ступень `#C8C8C4`, а предел далеко.
    ///
    /// # Почему откат не является починкой
    ///
    /// Вернуть `#FFFFFFE0` — значит вернуть подписи 5,04 / 4,70 / 4,56
    /// при пороге 4,5, то есть отдать назад запас, снятый с края
    /// (янтарь стоял в 0,06 от порога). Этот сторож от такого отката
    /// позеленеет, и позеленеет **неправильно**. Нужна третья величина:
    /// `lightHC` подписи, которая и выше 4,5 против блока, и тише
    /// заголовка. Такой величины сегодня нет, и придумать её —
    /// решение дизайна, а не замер.
    ///
    /// # Чего этот сторож НЕ видит
    ///
    /// Иерархию держит не только цвет: заголовок 40 pt bold rounded
    /// (`AppFont.posterHeaderTitle`), подпись 15 pt regular
    /// (`AppFont.posterHeaderSubtitle`). Кегль и начертание он
    /// не считает вовсе — значит его красное означает «цветом
    /// не различить», а не «не различить никак». Это и есть верная
    /// сила утверждения: проект сам назвал цвет носителем иерархии
    /// и записал для него числа, а правило «два значения разными
    /// методами нельзя рисовать одной линией» у нас уже оплачено.
    ///
    /// Второе: он мерит ЗНАЧЕНИЯ, разрешённые системой, а не пиксель.
    /// `opacity` на `Text` и перекрытие цвета стилем он не поймает —
    /// так `AppFont` однажды победил `foregroundStyle` предка,
    /// и главная кнопка давала 1,68:1 при верном токене.
    @Test("Подпись плаката тише заголовка в каждом из четырёх режимов")
    func подписьПлакатаТишеЗаголовка() throws {
        var сорвалось: [String] = []
        var осмотрено = 0

        for блок in Self.цветныеБлоки {
            for режим in Self.режимы {
                осмотрено += 1
                let з = Self.контраст(Token.Poster.labelOnColor, на: блок.цвет, режим: режим)
                let п = Self.контраст(Token.Poster.captionOnColor, на: блок.цвет, режим: режим)
                if п >= з - 0.0001 {
                    let равны = Self.байты(Token.Poster.captionOnColor, режим)
                        == Self.байты(Token.Poster.labelOnColor, режим)
                    let чем = равны ? " — ОДИН И ТОТ ЖЕ ЦВЕТ, байт в байт" : " — ПОДПИСЬ ГРОМЧЕ"
                    сорвалось.append("  \(блок.имя) блок · \(режим.имя): "
                                     + "заголовок \(Self.четыре(з)), подпись \(Self.четыре(п))\(чем)")
                }
            }
        }

        #expect(осмотрено == Self.цветныеБлоки.count * Self.режимы.count, """
            осмотрено \(осмотрено) блоков·режимов из \
            \(Self.цветныеБлоки.count * Self.режимы.count).
            Набору, которому нечего проверять, молчать так же легко,
            как набору, у которого всё хорошо.
            """)

        #expect(сорвалось.isEmpty, """
            ИЕРАРХИЯ «ЗАГОЛОВОК ГРОМЧЕ ПОДПИСИ» НЕ ДЕРЖИТСЯ
            в \(сорвалось.count) клетках:

            \(сорвалось.joined(separator: "\n"))

            Инвариант не мой: он записан в `TGPoster.swift:109-112`
            дословно — «читаемы оба, но вторым подпись стала бы того же
            цвета, что число».

            ЧТО НЕ ВИДИТ ЧЕЛОВЕК. Включив «Увеличить контраст»
            в светлой теме, он открывает «Сегодня» или «На улице»
            и получает шапку-плакат, где заголовок состояния и подпись
            под ним — ОДИН И ТОТ ЖЕ чистый белый `#FFFFFF` на цветном
            блоке. Оба читаются (5,99 и 5,99 при пороге 4,5) — и ничем
            не отличаются по цвету. Он включил режим, чтобы читать было
            легче, и потерял единственный цветовой признак того, что
            главное на этом экране, а что пояснение к нему. Без режима
            у него есть `#FFFFFFE0` против `#FFFFFF`; с режимом — нет.

