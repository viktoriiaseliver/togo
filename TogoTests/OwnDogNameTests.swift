import Testing
import Foundation
@testable import Togo

/// Кличка собаки Виктории не рассказывается чужому человеку.
///
/// Замер 23.09.2026. Пояснение в режиме дня говорило каждому: «Приложение
/// сравнит это с тем, как ты кормишь на самом деле, и скажет, **если Стич**
/// переедает». У человека собака Багира, и читает он про чужую. Во
/// французском каталоге это же место было переведено — «si Stitch mange
/// trop», — то есть кличка не просто утекла в текст, а поехала по языкам
/// вместе с ним. Отсюда и «где-то stitch, а где-то Стич».
///
/// Проверяем каталог, а не исходник: каталог — это ровно то, что человек
/// читает, на всех языках сразу. Три места, где кличка уместна, названы
/// поимённо ниже; четвёртого быть не должно, и появиться молча оно
/// не сможет.
@Suite("Своя собака не попадает в чужой экран")
struct OwnDogNameTests {

    /// Где кличка стоит намеренно.
    ///
    /// - `Стич` — сама кличка: подсказка в поле ввода («как у меня»)
    ///   и собака в демо-данных;
    /// - благодарность на экране «О приложении» — это подпись автора,
    ///   и обезличивать её незачем.
    private let разрешено: Set<String> = [
        "Стич",
        "Стичу — за то, что он терпел все версии этого приложения.",
    ]

    private var клички: [String] { ["Стич", "Стіч", "Stitch"] }

    @Test("В текстах приложения чужой клички нет")
    func кличкаНеУтеклаВТекст() throws {
        let каталог = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("TogoShared/Resources/Localizable.xcstrings")
        let данные = try Data(contentsOf: каталог)
        let разобранное = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
        let строки = разобранное?["strings"] as? [String: Any] ?? [:]

        #expect(строки.count > 500, """
            в каталоге \(строки.count) ключей — он прочитан не весь.
            Сканер, переставший что-либо находить, молчит так же,
            как тот, кому нечего сказать.
            """)

        var виноватые: [String] = []
        for (ключ, запись) in строки where !разрешено.contains(ключ) {
            var тексты = [ключ]
            let локализации = (запись as? [String: Any])?["localizations"] as? [String: Any] ?? [:]
            for (_, язык) in локализации {
                if let значение = ((язык as? [String: Any])?["stringUnit"]
                    as? [String: Any])?["value"] as? String {
                    тексты.append(значение)
                }
            }
            if тексты.contains(where: { текст in клички.contains { текст.contains($0) } }) {
                виноватые.append(ключ)
            }
        }

        #expect(виноватые.isEmpty, """
            кличка собаки автора попала в текст, который читают все:
            \(виноватые.joined(separator: "\n"))
            У человека собака зовут иначе, и он читает про чужую.
            """)
    }
}
