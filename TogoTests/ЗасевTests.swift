import Testing
import Foundation
import CloudKit
import SwiftData
@testable import Togo

/// Засев: накопленное до приглашения уезжает ко второму человеку.
///
/// # Что проверяется и почему именно это
///
/// Движок обмена в тест не поставить — ему нужны живой контейнер
/// CloudKit и вошедший аккаунт. Поэтому проверяется **решение**:
/// какие записи считаются накопленными. Отправка в `FamilySync.засеять()`
/// тонкая и держится на этом сборе.
///
/// Тот же приём, которым отделили `ShareAcceptance.accepted` от делегата
/// сцены: дверь непроверяема, решение проверяемо.
///
/// # Чего эти тесты НЕ доказывают, и это надо называть
///
/// Что засев **доедет**. Приёмка дозаливки — два телефона с разным
/// временем последней синхронизации, и их у нас нет; приватную базу
/// CloudKit консоль открывает правами владельца данных, второго конца
/// у этой связи нет.
///
/// > **Здесь принимается «очередь непуста и полна», а не «мама
/// > увидела».** Называть это приёмкой дозаливки нельзя.
@Suite("Общий дневник · засев накопленного")
@MainActor
struct ЗасевTests {

    private let zone = CKRecordZone.ID(zoneName: "проба", ownerName: "_хозяин")

    private func хранилище() throws -> (ModelContext, Dog) {
        let container = try ModelContainer(
            for: Dog.self,
            configurations: ModelConfiguration(isStoredInMemoryOnly: true)
        )
        let context = ModelContext(container)
        let dog = Dog(name: "Стич", weightKg: 4.1)
        context.insert(dog)
        try context.save()
        return (context, dog)
    }

    @Test("Пустое хранилище засевать нечем")
    func пустоеХранилище() throws {
        let container = try ModelContainer(
            for: Dog.self,
            configurations: ModelConfiguration(isStoredInMemoryOnly: true)
        )
        let изменения = SharedDiarySeed.изменения(
            context: ModelContext(container), zone: zone
        )
        #expect(изменения.isEmpty, """
            в пустом хранилище нашлось \(изменения.count) записей \
            к отправке — засев выдумывает то, чего нет.
            """)
    }

    /// Главное: собака, заведённая один раз и больше не тронутая.
    ///
    /// Ровно этот случай и был дефектом: профиль не правят, значит
    /// `didSave` по нему больше не случится, и мама не увидела бы
    /// даже собаку.
    @Test("Собака, которую никто не трогал после приглашения, уезжает")
    func собакаУезжает() throws {
        let (context, dog) = try хранилище()
        let изменения = SharedDiarySeed.изменения(context: context, zone: zone)

        let ожидаемый = SharedDiaryRecords.recordID(dog.id, in: zone)
        #expect(изменения.contains(.saveRecord(ожидаемый)), """
            собаки нет в засеве. Профиль заводят один раз и потом \
            не правят — значит без засева он не уедет НИКОГДА, \
            и приглашение ведёт в пустую комнату.
            """)
    }

    @Test("Записи адресуются в зону владельца, а не в свою")
    func адресВЗонуВладельца() throws {
        let (context, _) = try хранилище()
        let изменения = SharedDiarySeed.изменения(context: context, zone: zone)

        #expect(!изменения.isEmpty, "сценарий не наполнился: засевать нечего")
        for change in изменения {
            guard case .saveRecord(let id) = change else {
                #expect(Bool(false), "в засеве оказалось не сохранение: \(change)")
                continue
            }
            #expect(id.zoneID == zone, """
                запись засева адресована в \(id.zoneID), а не в зону \
                владельца \(zone). С чужой зоной она ляжет в личную базу \
                гостя, где её никто не читает.
                """)
        }
    }

    /// Засев обязан покрывать ВСЕ типы, которые умеют ездить.
    ///
    /// Иначе новый тип записи поедет только «вперёд», а накопленное
    /// по нему не уедет никогда — и снаружи это неотличимо от «обмен
    /// не работает».
    @Test("Засев покрывает все типы записи, которые умеют ездить")
    func покрытыВсеТипы() throws {
        let (context, dog) = try хранилище()

        // По одной записи каждого типа, чтобы пропуск был виден счётом.
        let событие = LogEvent(kind: .meal, authorName: "Вика")
        событие.dog = dog
        context.insert(событие)

        let дело = CareTask(title: "Взвесить", detail: "раз в неделю")
        дело.dog = dog
        context.insert(дело)

        let схема = Medication(name: "Ветмедин", doseText: "1 таб", times: [480])
        схема.dog = dog
        context.insert(схема)

        let доза = DoseRecord(scheduledAt: Date())
        доза.medication = схема
        context.insert(доза)

        let вес = WeightEntry(kg: 4.2)
        вес.dog = dog
        context.insert(вес)

        let клиника = Clinic(name: "Айболит")
        context.insert(клиника)

        try context.save()

        let изменения = SharedDiarySeed.изменения(context: context, zone: zone)
        let адреса = Set(изменения.compactMap { change -> String? in
            guard case .saveRecord(let id) = change else { return nil }
            return id.recordName
        })

        // Утвердительно и поимённо: каждая завёденная запись обязана
        // быть в засеве. «Записей стало больше» прошло бы и при пропуске
        // половины типов.
        let обязаны: [(String, UUID)] = [
            ("собака", dog.id), ("событие", событие.id), ("дело ухода", дело.id),
            ("схема", схема.id), ("доза", доза.id), ("взвешивание", вес.id),
            ("клиника", клиника.id),
        ]
        let нет = обязаны.filter { !адреса.contains($0.1.uuidString) }.map(\.0)
        #expect(нет.isEmpty, """
            засев не берёт: \(нет.joined(separator: " · ")).
            Накопленное по этим типам не уедет ко второму человеку \
            никогда, и снаружи это неотличимо от «обмен не работает».
            """)
    }

    /// Ворота наружу у засева те же, что у второй двери.
    ///
    /// **Форма утвердительная и с числом нарочно.** «Фантомы не уезжают»
    /// выполнялось бы и при пустом засеве — то есть и тогда, когда
    /// не уезжает вообще ничего. Поэтому требование: собак в засеве
    /// **ровно одна, и это та, у которой есть кличка**.
    ///
    /// Масштаб из живых данных (выгрузка 08.10.2026): шестнадцать
    /// записей, пятнадцать пустых. Без этих ворот засев отправил бы
    /// второму человеку пятнадцать фантомов — **при зелёном стороже
    /// соседней двери**, потому что он сторожит свой путь, а засев
    /// идёт мимо него.
    @Test("В засеве ровно одна собака — та, у которой есть кличка")
    func засевБерётТолькоНазваннуюСобаку() throws {
        let (context, dog) = try хранилище()

        // Пятнадцать безымянных рядом с одной названной — как в живых
        // данных, а не одна «для проверки».
        var фантомы: [Dog] = []
        for _ in 0..<15 {
            let пустая = Dog(name: "", weightKg: 0)
            context.insert(пустая)
            фантомы.append(пустая)
        }
        try context.save()

        // Контроль: сценарий наполнился. Без него «одна собака» прошло бы
        // и в хранилище, где фантомов не завелось вовсе.
        let всего = (try? context.fetch(FetchDescriptor<Dog>()))?.count ?? 0
        #expect(всего == 16, "сценарий не наполнился: собак в хранилище \(всего), ждали 16")

        let изменения = SharedDiarySeed.изменения(context: context, zone: zone)
        let адреса = Set(изменения.compactMap { change -> String? in
            guard case .saveRecord(let id) = change else { return nil }
            return id.recordName
        })

        let собакВЗасеве = ([dog] + фантомы).filter { адреса.contains($0.id.uuidString) }
        #expect(собакВЗасеве.count == 1, """
            собак в засеве \(собакВЗасеве.count), а должна быть РОВНО ОДНА. \
            Засев — вторая дверь наружу, и ворота `SharedDiaryOutgoing.sendable` \
            обязан звать и он: сторож соседней двери на это красным не станет, \
            он сторожит свой путь.
            """)
        #expect(адреса.contains(dog.id.uuidString), """
            в засеве нет НАЗВАННОЙ собаки — ворота отсекли не то. \
            Пустой засев проходит проверку «фантомов нет» и не делает \
            ничего полезного.
            """)
    }

    /// Флаг засева помнит, ЧЬЮ зону засеяли.
    @Test("Флаг засева различает зоны разных владельцев")
    func флагРазличаетВладельцев() {
        let первый = "_мама-" + UUID().uuidString
        let второй = "_подруга-" + UUID().uuidString
        defer {
            SyncSeedState.сбросить(владелец: первый)
            SyncSeedState.сбросить(владелец: второй)
        }

        #expect(!SyncSeedState.засеяно(владелец: первый), "флаг грязный до начала")
        SyncSeedState.отметить(владелец: первый)

        #expect(SyncSeedState.засеяно(владелец: первый))
        #expect(!SyncSeedState.засеяно(владелец: второй), """
            флаг засева одной зоны считается засевом ДРУГОЙ. \
            Человек выходит из одного дневника и входит в другой — \
            и накопленное во второй не уедет, потому что флаг сказал \
            «уже засеяли».
            """)

        SyncSeedState.сбросить(владелец: первый)
        #expect(!SyncSeedState.засеяно(владелец: первый), """
            сброс не работает. Он нужен на `stop()`: иначе включённый \
            заново обмен не отправит накопленное за время, пока он был \
            выключен.
            """)
    }
}
