import Testing
import Foundation

/// Шапка «Кино» стоит на экранах и **ни на одной шторке**.
///
/// Решение дизайна кончается запретом: «Шторки и системные поверхности
/// без плаката». Запрет и проверяется — **от обратного**, а не счётом
/// «сколько экранов получили шапку». Счёт выполняется и тогда, когда
/// шапку надели лишним местам: «применили везде» истинно и там, где
/// применять нельзя.
///
/// **Этот сторож не теоретический.** Раскатывая шапку на тридцать
/// восемь экранов, я пропустил ровно одну шторку — `WhatsNewScreen`, —
/// и пропустил по глупой причине: список исключений держал НОМЕР
/// СТРОКИ, а номера уехали от предыдущих вставок в том же файле.
/// Поймал этот счёт, а не чтение.
///
/// > Устаревший номер строки — третий случай за день. Адресовать
/// > место текстом, а не координатой: текст стареет громко, номер
/// > молча.
///
/// # ОСЬ ПЕРЕВЕДЕНА 23.10.2026: ПЛАКАТА НЕТ, ЗАПРЕТ ЕСТЬ
///
/// Набор звался `PosterHeaderScopeTests` и держал порог «вызовов
/// `.posterHeader(` не меньше 35». Редизайн «Кино» снял плакат
/// со всех экранов, и порог стал красным честно: сторож смотрел
/// в пустоту.
///
/// ```
/// замер 23.10.2026, после перевода последних 27 экранов
/// .posterHeader( во всём дереве       1   #Preview самого TGPosterHeader
///                                         (плюс 2 прозы, 2 в документах)
/// CinemaHeader( + КиноЭкран( в коде  43   в 32 файлах   ← новый предмет
/// шапка «Кино» на шторке              0
/// ```
///
/// **Запрет пережил предмет, на котором стоял.** Решение дизайна
/// говорит не «плакат не на шторке», а «шторки и системные поверхности
/// **без шапки**» — а шапка теперь другая. Поэтому набор не снят
/// и не переписан заново: ось переведена с `.posterHeader(`
/// на `CinemaHeader(` и `КиноЭкран(`, остальное дословно прежнее,
/// включая разбор про `WhatsNewScreen` выше.
///
/// > **Снять сторожа значило бы разрешить ровно то, от чего он
/// > поставлен.** Шторка с крупным заголовком 36 и фотографией под ним
/// > — это то, что человек увидит, а не то, что сломает компилятор.
///
/// ## Почему два имени, а не одно
///
/// `CinemaHeader` — шапка-строка для экранов на `List` и `TGScreen`;
/// `КиноЭкран` — каркас вкладок на `ScrollView`, который **ставит
/// ту же `CinemaHeader` внутрь себя**. Считать только первое значило бы
/// пропустить три вкладки, считать только второе — сорок подэкранов.
/// Вложенный вызов внутри `КиноЭкран` при этом считается дважды,
/// и это не дефект счёта: порог взят от измеренного итога, а не
/// от числа экранов.
@Suite("Шапка «Кино» — на экранах, и ни на одной шторке")
struct ШапкаКиноОбластьTests {

    /// В день перевода: 43 вызова в 32 файлах (замер 23.10.2026).
    ///
    /// Порог ниже факта на десятую часть — как у прежней редакции
    /// (39 экранов → порог 35). Он ловит снос раскатки, а не
    /// колебание в один экран.
    private static let вызововНеМенее = 38
    /// Файлов с шапкой в тот же замер — 32.
    private static let файловНеМенее = 25

    /// Имена, которыми зовут шапку «Кино». Оба — потому что `КиноЭкран`
    /// это каркас, который ставит `CinemaHeader` внутрь, и экран
    /// может звать любое из двух.
    private static let именаШапки = ["CinemaHeader(", "КиноЭкран("]

    private func исходники() -> [(имя: String, путь: String, текст: String)] {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var найдено: [(String, String, String)] = []
        for цель in ["Togo", "TogoShared", "TogoWidgets"] {
            let обход = FileManager.default.enumerator(
                at: корень.appendingPathComponent(цель), includingPropertiesForKeys: nil)
            while let элемент = обход?.nextObject() as? URL {
                guard элемент.pathExtension == "swift",
                      let текст = try? String(contentsOf: элемент, encoding: .utf8)
                else { continue }
                найдено.append((элемент.lastPathComponent,
                                "\(цель)/\(элемент.lastPathComponent)", текст))
            }
        }
        return найдено
    }

    /// Строка кода без прозы.
    ///
    /// **Комментарии режутся до разбора, и это оплачено.** У Того
    /// записано: сторож, не различающий код и прозу, меряет прозу —
    /// и запрещает писать про ошибку в файле, где её не совершают.
    /// В `LanguageScreen` и `SettingsScreen` стоят комментарии «Было
    /// `.posterHeader(…)` — снято решением», и сканер без этой строки
    /// считал бы их за вызовы.
    /// Сколько раз в тексте файла вызвана шапка «Кино» — по всем её именам.
    private func вызововШапки(в текст: String) -> Int {
        var счёт = 0
        for строка in текст.components(separatedBy: .newlines) {
            let к: String = код(строка)
            for имя in Self.именаШапки {
                счёт += к.components(separatedBy: имя).count - 1
            }
        }
        return счёт
    }

    private func код(_ строка: String) -> String {
        строка.components(separatedBy: "//")[0]
    }

    /// Какие виды показываются шторкой. Выводится из дерева, а не
    /// перечисляется: список руками знает только то, что в него
    /// положили, и `WhatsNewScreen` в него бы не попал — его
    /// показывают шторкой из `TogoApp`, а правят в `DataPrivacyScreen`.
    private func шторками() -> Set<String> {
        var имена: Set<String> = []
        for файл in исходники() {
            let строки = файл.текст.components(separatedBy: .newlines)
            for (i, строка) in строки.enumerated() {
                let код = код(строка)
                guard код.contains(".sheet(") || код.contains(".fullScreenCover(")
                else { continue }
                let окно = строки[i..<min(i + 8, строки.count)].joined(separator: "\n")
                for кусок in окно.components(separatedBy: CharacterSet(charactersIn: " (){}[]\n\t,")) {
                    if let первая = кусок.first, первая.isUppercase, кусок.count > 3 {
                        имена.insert(кусок)
                    }
                }
            }
        }
        return имена
    }

    /// Несёт ли строка кода вызов шапки.
    private func этоШапка(_ строкаКода: String) -> Bool {
        Self.именаШапки.contains { строкаКода.contains($0) }
    }

    @Test("Обход нашёл экраны с шапкой «Кино», а не промолчал")
    func былоЧтоПроверять() {
        let все = исходники()

        // Своё зрение первым: каталог, который перестали находить,
        // молчит так же, как чистый.
        #expect(все.count > 150, """
            обход прочитал \(все.count) файлов .swift в трёх целях —
            каталог не найден или прочитан не тот (замер 23.10.2026: 223).
            Ноль находок при нуле файлов значит «не смотрел».
            """)

        let сШапкой = все.filter { файл in
            файл.текст.components(separatedBy: .newlines).contains { этоШапка(код($0)) }
        }
        #expect(сШапкой.count >= Self.файловНеМенее, """
            файлов с шапкой «Кино» \(сШапкой.count) при ожидаемых
            \(Self.файловНеМенее)+ — обход не состоялся или раскатку
            откатили.
            """)

        // Счёт вынесен в функцию с типами: три вложенных `reduce`
        // без аннотаций типизировались 2,8 с на CI (04.11.2026).
        let всего: Int = сШапкой.reduce(0) { (сумма: Int, файл) -> Int in
            сумма + вызововШапки(в: файл.текст)
        }
        #expect(всего >= Self.вызововНеМенее, """
            вызовов шапки «Кино» \(всего), а раскатано было
            \(Self.вызововНеМенее)+. Стало меньше — шапку с экранов сняли.

            Это тот же порог, что прежде стоял на `.posterHeader(`,
            и переведён он 23.10.2026 вместе с осью. Если шапку опять
            заменили на третью — переводи порог, а не удаляй проверку:
            запрет ниже держится на том, что шапка в дереве ЕСТЬ.
            """)
        print("ШАПКА «КИНО»: \(всего) вызовов в \(сШапкой.count) файлах "
              + "из \(все.count) прочитанных")
    }

    @Test("Ни одна шторка не несёт шапку «Кино»")
    func шторкиБезШапки() {
        let шторки = шторками()
        var нарушения: [String] = []
        var осмотреноВызовов = 0

        for файл in исходники() {
            let строки = файл.текст.components(separatedBy: .newlines)
            var текущий: String?
            for (i, строка) in строки.enumerated() {
                if let m = строка.range(of: #"(?:private )?struct (\w+)"#,
                                        options: .regularExpression) {
                    текущий = String(строка[m]).components(separatedBy: " ").last
                }
                guard этоШапка(код(строка)) else { continue }
                осмотреноВызовов += 1
                if let текущий, шторки.contains(текущий) {
                    нарушения.append("  \(файл.путь):\(i + 1) — \(текущий) показывается шторкой")
                }
            }
        }

        // Контроль в ТОМ ЖЕ замере и тем же разбором: ноль нарушений
        // при нуле осмотренных вызовов значит «не смотрел», а не «чисто»,
        // и обнуляются эти два числа по разным причинам.
        #expect(осмотреноВызовов > 0, """
            разбор не нашёл ни одного вызова шапки «Кино» — тогда
            ноль нарушений ниже про разбор, а не про экраны.
            """)
        #expect(!шторки.isEmpty, """
            в дереве не нашлось ни одной `.sheet(` / `.fullScreenCover(` —
            список шторок пуст, и запрет проверять не на чем.
            """)

        #expect(нарушения.isEmpty, """
            шапка «Кино» надета на шторку в \(нарушения.count) местах:

            \(нарушения.joined(separator: "\n"))

            Решение дизайна: «Шторки и системные поверхности без
            плаката». Шапка сменилась, запрет остался. Если вид
            показывают и шторкой, и переходом — разводить явным
            параметром на месте показа, а не вешать шапку на вид.
            """)
    }

    @Test("Границы: чего не проверяет сторож области шапки")
    func границыНазваны() {
        // · Он сверяет ИМЕНА типов, а не показ. Вид, который показывают
        //   шторкой через промежуточную обёртку с другим именем,
        //   он не свяжет.
        // · Он не видит, как шапка ВЫГЛЯДИТ: это текст. Что заголовок
        //   не задвоился и что текст на фотографии читается — только
        //   кадр: `ШапкаНаФотоTests` меряет пиксель под глифами,
        //   `TogoUITests/ШапкаПлаката` — живой экран.
        // · Он не проверяет, что шапка есть у КАЖДОГО экрана: это
        //   требование от утверждения, а они у нас проверяются
        //   ненадёжно. Проверяется запрет и общее число.
        // · Он слеп к тому, С КАКИМ ключом экрана позвали шапку.
        //   `CinemaHeader` без `экран:` не показывает фотографию вовсе
        //   и красит текст нейтральными чернилами.
        //
        //   ЗДЕСЬ СТОЯЛО «это законно на каркасе `TGScreen`, который
        //   фото под собой не пропускает». Фраза была верна про каркас
        //   и ложна про замысел, а 04.11.2026 стала ложной целиком:
        //   полотно `TGScreen` сделано условным, и фотография теперь
        //   доходит до подэкранов. Безключевой вызов остался ровно
        //   один (`ВнеПриложения.swift:71`), и он теперь ВЫБОР,
        //   а не умолчание.
        //
        //   Слепота сторожа от этого не изменилась — изменилась цена:
        //   прежде неверный ключ ничего не показывал никому, теперь
        //   он покажет чужой кадр. Различает это по-прежнему только
        //   кадр, а имена стережёт `ИмяЭкранаДоходитДоРаскладкиTests`.
        #expect(Bool(true))
    }
}
