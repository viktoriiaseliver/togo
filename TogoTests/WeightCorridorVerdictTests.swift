import Foundation
import Testing
@testable import Togo

/// Экран говорил «в норме» о том, чего приложение не знает.
///
/// Находка `projects-53`, починка моя. Прежняя редакция обоих показов
/// спрашивала **предикат ворот** и всё остальное сваливала в `else`:
///
/// ```
/// HealthScreen    if !dog.isWeightInRange { «вне коридора» }
///                 else                    { «в норме» }
/// Dog.swift:497   guard let low, let high else { return true }
/// ```
///
/// > **`else` ловил ДВА состояния и говорил о них одно:** «вес внутри
/// > коридора» и «коридора не существует». У собаки без назначенного
/// > врачом коридора под её весом стояло зелёное «в норме» —
/// > утверждение, которого приложение сделать не может.
///
/// **Цена не абстрактная:** вес — та величина, от которой считается
/// доза лекарства, и зелёную подпись под ним читает человек,
/// принимающий решение о дозе.
///
/// # Чего этот сторож НЕ делает
///
/// Не проверяет `isWeightInRange`. Предикат **верен для ворот** —
/// «коридора нет, не тревожь» — и правка его не трогала. Якорь взят
/// от ПОКАЗА, а не от предиката: у нас записано, что сторож, привязанный
/// к тому, что правка снимает, после починки говорит не «стало хуже»,
/// а «я ослеп», и читается это одинаково.
@Suite("Коридор веса: три состояния, а не два")
struct WeightCorridorVerdictTests {

    private static func собака(вес: Double, низ: Double?, верх: Double?) -> Dog {
        let dog = Dog(name: "Стич", weightKg: вес)
        dog.targetWeightLow = низ
        dog.targetWeightHigh = верх
        return dog
    }

    // MARK: - 1. Три входа, и крайние два доказывают, что не перетянул

    @Test("Коридор задан и вес внутри — «в норме» остаётся")
    func внутриКоридора() {
        let dog = Self.собака(вес: 4.1, низ: 3.8, верх: 4.5)
        #expect(dog.weightVerdict == .withinRange, """
            вес 4,1 при коридоре 3,8–4,5 обязан давать .withinRange. \
            Если здесь не оно — починка ПЕРЕТЯНУЛА и забрала верное \
            «в норме» у собаки, которой врач коридор назвал.
            """)
    }

    @Test("Коридор задан и вес снаружи — «вне коридора» остаётся")
    func внеКоридора() {
        let ниже = Self.собака(вес: 3.2, низ: 3.8, верх: 4.5)
        let выше = Self.собака(вес: 5.0, низ: 3.8, верх: 4.5)
        #expect(ниже.weightVerdict == .below)
        #expect(выше.weightVerdict == .above, """
            вес вне коридора обязан различаться по стороне: .below \
            и .above — разные вещи для того, кто читает. Слить их \
            в одно значило бы потерять направление, а направление \
            у веса под лечением и есть предмет.
            """)
    }

    /// **Та самая починка.**
    @Test("Коридора НЕТ — это не «в норме», а отдельное состояние")
    func коридораНет() {
        for (низ, верх) in [(nil, nil), (3.8, nil), (nil, 4.5)] as [(Double?, Double?)] {
            let dog = Self.собака(вес: 4.1, низ: низ, верх: верх)
            // Числа в подпись складываются ЗАРАНЕЕ, а не внутри `#expect`.
            //
            // Первая редакция писала `низ.map(String.init) ?? "нет"`
            // прямо в интерполяции и дала
            // `error: failed to produce diagnostic for expression`
            // на `#expect`. Это наш записанный второй вид: **не перебор
            // от длины, а несходящийся тип, которому компилятор ещё
            // не выбрал имя ошибки** — у `String.init` для `Double`
            // перегрузок много, и внутри макроса выбор не делается.
            // Чинится типом, а не «упрощением выражения»: упрощать
            // здесь было бы нечего.
            let коридор = "(\(низ?.description ?? "нет"), \(верх?.description ?? "нет"))"
            #expect(dog.weightVerdict == .normUnknown, """
                коридор \(коридор) — неполный или отсутствующий, \
                и вердикт обязан быть .normUnknown.
                .withinRange здесь значит «приложение сказало „в норме“ \
                о том, чего не знает», а под этой подписью считают дозу.
                """)
        }
    }

    /// Предикат ворот не тронут, и это проверяется, а не обещается.
    @Test("Предикат ворот остался прежним: коридора нет — не тревожь")
    func воротаНеТронуты() {
        let безКоридора = Self.собака(вес: 4.1, низ: nil, верх: nil)
        #expect(безКоридора.isWeightInRange, """
            `isWeightInRange` обязан остаться `true` при отсутствующем \
            коридоре. Это его предмет: ворота не тревожат, когда \
            тревожиться не о чем. Починка была в ПОКАЗЕ, и если здесь \
            стало `false` — кто-то поправил предикат, и ворота начнут \
            кричать на каждой собаке без назначения врача.
            """)
    }

    // MARK: - 2. Якорь от ПОКАЗА, а не от предиката

    private static var экраны: [String] {
        ["Togo/Features/Health/HealthScreen.swift",
         "Togo/Features/Profile/ProfileScreen.swift"]
    }

    private static func текст(_ путь: String) throws -> String {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        return try String(contentsOf: корень.appending(path: путь), encoding: .utf8)
    }

    /// Код без комментариев.
    ///
    /// **Поймано прогоном правила на здоровом коде, а не чтением.**
    /// Первая редакция сторожа ниже покраснела на УЖЕ ПОЧИНЕННОМ коде:
    /// `isWeightInRange` нашёлся по разу в каждом экране — **в моих же
    /// комментариях о том, почему его больше не спрашивают.**
    ///
    /// ```
    /// HealthScreen    weightVerdict 2 · isWeightInRange 1 ← проза
    /// ProfileScreen   weightVerdict 1 · isWeightInRange 1 ← проза
    /// ```
    ///
    /// > **Сканирующий сторож, не различающий код и прозу, меряет
    /// > прозу** — и запрещает писать про ошибку в том же файле, где
    /// > её не совершают. Это второй раз за смену: тот же класс стоял
    /// > у сторожа гигиены shell, и там он тоже нашёлся прогоном
    /// > правила на живых файлах ДО рождения теста.
    ///
    /// Разбор простой нарочно: строковых литералов с `//` в этих двух
    /// экранах нет ни одного, и граница названа — появится такой,
    /// сторож ошибётся **в сторону молчания**, а не ложной тревоги.
    static func кодБезКомментариев(_ текст: String) -> String {
        текст.components(separatedBy: .newlines)
            .map { строка -> String in
                guard let край = строка.range(of: "//") else { return строка }
                return String(строка[..<край.lowerBound])
            }
            .joined(separator: "\n")
    }

    /// Первым — что сторожу **было что проверять**.
    ///
    /// Якорь взят от того, что правка ДОБАВИЛА (`weightVerdict`),
    /// а не от того, что она сняла. Переименуют файл или вынесут показ —
    /// сторож скажет об этом прямо, а не промолчит зелёным.
    @Test("Оба показа веса найдены и спрашивают вердикт показа")
    func показыНайдены() throws {
        for путь in Self.экраны {
            let текст = Self.кодБезКомментариев(try Self.текст(путь))
            #expect(текст.contains("weightVerdict"), """
                \(путь) не спрашивает `weightVerdict`. Либо показ веса \
                переехал, либо вернулись к предикату ворот. Сторож ниже \
                без этого зелен впустую.
                """)
        }
    }

    @Test("Показ веса не спрашивает предикат ворот")
    func показНеСпрашиваетВорота() throws {
        var нарушители: [String] = []
        for путь in Self.экраны
        where Self.кодБезКомментариев(try Self.текст(путь)).contains("isWeightInRange") {
            нарушители.append(путь)
        }
        #expect(нарушители.isEmpty, """
            показ веса спрашивает `isWeightInRange`: \
            \(нарушители.joined(separator: ", ")).

            Предикат отвечает `true` на ДВА состояния — «внутри \
            коридора» и «коридора нет», — и показ по нему печатает \
            одно слово на оба. Спрашивать надо `weightVerdict`: \
            у него три состояния, и `.normUnknown` среди них.

            Мест вызова предиката было РОВНО ДВА, и оба были показами. \
            Починка на одной поверхности из двух выглядит законченной.
            """)
    }
}
