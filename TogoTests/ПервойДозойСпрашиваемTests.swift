import Testing
import Foundation

/// Сторож на ВЫЗОВ правила «спрашиваем право на уведомления в момент
/// первой дозы», а не на само правило.
///
/// **Зачем отдельный сторож, когда у домена уже есть тесты.**
/// `NotificationPriming` покрыт `FinalV2DomainTests` — и всё это время
/// лежал с **нулём мест вызова**. Тест зовёт функцию сам и зелен, пока
/// вызов есть; когда вызова нет вовсе — зелен тоже. У Togo и Timer это
/// один и тот же оплаченный класс: вырезали шесть ручных вызовов
/// `rebuildDerived()` — набор остался зелёным, 375 тестов, ноль падений.
///
/// **Проверка от ЗАПРЕТА, а не от требования.** Запрет узнаётся
/// по своему корню надёжно, требование — нет: у нужного десять форм.
/// Здесь оба утверждения записаны так, что выполняются только при
/// наличии предмета:
///
/// 1. имя `shouldPrime` **обязано** встретиться в коде приложения —
///    отрицательная форма («вызовов не стало меньше») прошла бы
///    и при нуле;
/// 2. в онбординге его быть **не должно** — иначе правило снова
///    спросит не в тот момент.
///
/// **Комментарии вырезаются до разбора.** Сканирующий сторож, который
/// не различает код и прозу, меряет прозу: у Timer такой покраснел
/// на строке `// НЕ MapsApp.allCases`, то есть наказал за объяснение,
/// почему так делать нельзя. Здесь вырезание обязательно ещё и потому,
/// что в самих правках имя `shouldPrime` упоминается в доккомментарии
/// рядом с местом вызова.
///
/// **Чего этот сторож НЕ доказывает, и это печатается в его же
/// сообщениях.** Он видит, что имя вызвано из кода, и не видит, что
/// от вызова что-то происходит: достижимость ветки, порядок
/// относительно отметки дозы и факт показа системного окна им
/// не берутся. Их берёт отладочный список запланированных уведомлений
/// (`Настройки · Отладка · что запланировано в уведомлениях`) —
/// единственный путь, смотрящий мимо показа.
@Suite("Право на уведомления спрашивается первой дозой")
struct ПервойДозойСпрашиваемTests {

    /// Корень репозитория: файл теста лежит в `TogoTests/`.
    private var корень: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private func код(_ путь: String) throws -> String {
        let текст = try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
        // Режется и `//`, и `///`: достаточно отбросить всё от первой
        // пары слэшей в строке. Строковых литералов со слэшами
        // в проверяемых файлах нет; появятся — разбор придётся учить
        // литералам, и это надо будет сказать вслух, а не молча
        // расширить регулярку.
        return текст
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { String($0.components(separatedBy: "//")[0]) }
            .joined(separator: "\n")
    }

    @Test("Правило вызвано из кода приложения, а не только из тестов")
    func правилоВызвано() throws {
        let места = ["Togo/Features/Today/DayPlanActions.swift"]
        var найдено = 0
        for путь in места where try код(путь).contains("NotificationPriming.shouldPrime") {
            найдено += 1
        }
        #expect(найдено >= 1, """
            `NotificationPriming.shouldPrime` не вызывается из кода
            приложения ни разу — значит правило «спрашиваем в момент
            первой дозы» написано и не действует.

            Домен при этом покрыт тестами и они зелёные: тест зовёт
            функцию сам, и когда вызова нет вовсе, он зелен тоже.
            Проверено место: \(места.joined(separator: ", ")).

            Если вызов переехал — впиши новый путь здесь же, а не
            снимай проверку: список путей руками знает только то, что
            в него положили, и это его известная граница.
            """)
    }

    @Test("В онбординге правило не спрашивается: там нет повода")
    func вОнбордингеНеСпрашиваем() throws {
        let онбординг = try код("Togo/Features/Onboarding/OnboardingSteps.swift")
        #expect(!онбординг.contains("NotificationPriming.shouldPrime"), """
            В онбординге стоит вызов `shouldPrime`. Правило нового
            дизайна называет единственный повод — первую дозу;
            онбординг поводом не является, и спросить там значит
            потратить единственное системное окно до того, как
            человеку есть о чём напоминать.

            iOS показывает своё окно ОДИН раз на установку. Спрошенное
            не вовремя право не спрашивается больше никогда.
            """)
    }

    /// Запрет, без которого первый тест выполняется и при сломанном
    /// разборе: пустой текст не содержит ничего, и `!contains` на нём
    /// истинно.
    ///
    /// > **Любой группе проверок нужна проверка, что ей было что
    /// > проверять**, и ставится она не последней по важности.
    @Test("Разбор дошёл до файлов: им было что читать")
    func разборуБылоЧтоЧитать() throws {
        for путь in ["Togo/Features/Today/DayPlanActions.swift",
                     "Togo/Features/Onboarding/OnboardingSteps.swift"] {
            let текст = try код(путь)
            #expect(текст.count > 1000, """
                `\(путь)` прочитан как \(текст.count) знаков — это
                не файл. Пустой результат за сломанным разбором
                неотличим от измеренного мира: все запреты выше
                на пустом тексте выполняются.
                """)
        }
    }

    /// Вырезание комментариев проверяется на живом примере, а не
    /// на слово.
    ///
    /// У Togo уже был случай, когда «вырезание есть» и «вырезание
    /// работает» разошлись: список файловых исключений соседнего
    /// сторожа молча не работал из-за симлинка, а проверка
    /// «исключения существуют» была зелёной — файлы-то на месте.
    @Test("Комментарии действительно вырезаются")
    func комментарииВырезаются() {
        let строки = """
            let x = 1
            // NotificationPriming.shouldPrime в прозе
            /// и в доккомментарии тоже
            """
        let очищено = строки
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { String($0.components(separatedBy: "//")[0]) }
            .joined(separator: "\n")
        #expect(!очищено.contains("shouldPrime"), """
            Имя из комментария пережило вырезание. Значит сторож выше
            меряет прозу: он покраснеет на объяснении, почему так
            делать нельзя, и позеленеет от упоминания без вызова.
            """)
        #expect(очищено.contains("let x = 1"), """
            Вырезание съело код вместе с комментарием — тогда первый
            запрет выполняется на пустоте.
            """)
    }
}
