import Testing
import Foundation
@testable import Togo

/// Час после полудня в 12-часовой локали печатается верно.
///
/// # Повод, замер 04.11.2026
///
/// `Fmt.clock(_:)` год стоял как
/// `.hour(.twoDigits(amPM: .omitted)).minute(.twoDigits)`.
/// `.omitted` снимает **указатель** AM/PM и не переводит час
/// в 24-часовой вид — в `en_US` доза в 20:00 печаталась как «08:00».
/// Приложение записывает дозы лекарств и делает выгрузку врачу;
/// «доза в 8:00» вместо 20:00 — медицинская ошибка в нашем тексте,
/// а не косметика.
///
/// Дефект введён первым коммитом 25.08.2026 и прожил 71 день.
///
/// # Ось сторожа — различимость, а не отсутствие строки в коде
///
/// Соблазн тут сильный: написать «в дереве нет `amPM: .omitted`»
/// и успокоиться. Такой сторож зелен для **любой** новой сломанной
/// формы и гаснет от переименования — это наш класс «сторож на прокси
/// гасится чужим действием».
///
/// Ось здесь прямая: **20:00 и 08:00 обязаны печататься РАЗНО.**
/// Ровно это сломанная форма и теряла — она отображала два разных часа
/// в одну строку, то есть теряла данные. Проверка не называет ни одного
/// литерала, не зависит от версии ICU и не может быть удовлетворена
/// никаким 12-часовым видом без указателя.
///
/// # Почему дефект не поймали раньше — и что из этого следует для набора
///
/// ```
/// 09:22  en_US   «09:22»   ← до полудня оба вида СОВПАДАЮТ
/// 20:00  ru_RU   «20:00»   ← и во всех прочих наших языках тоже
/// ```
///
/// Четыре языка каталога из пяти (`ru`, `uk`, `fr`, `kk`) 24-часовые,
/// а витрину снимали на 09:22. То есть форма врала только после полудня
/// и только в одной локали — и была зелена у всех, кто туда не смотрел.
/// **Поэтому данные здесь взяты после полудня нарочно**, и утренний
/// случай оставлен отдельной строкой: он обязан совпасть, и его
/// совпадение — не признак здоровья.
///
/// # Ловушка, стоившая бы следующему заход: U+202F
///
/// `en_US` ставит перед «PM» узкий неразрывный пробел U+202F, а не
/// обычный. Литерал `"8:00 PM"`, набранный рукой, **не равен** выводу,
/// и в логе отказа обе строки выглядят одинаково. Поэтому якорные
/// литералы ниже написаны через `\u{202F}` явно, а основная ось
/// литералов не трогает вовсе.
@Suite struct ЧасПослеПолудняTests {

    // Локали: пять языков каталога плюс те же языки в американском
    // регионе. Вторая половина не для полноты — ею проверяется, что
    // цикл суток идёт от РЕГИОНА, а не от языка интерфейса: `ru_US`
    // обязан дать 12-часовой вид при русском тексте приложения.
    private static let двенадцатичасовые = ["en_US", "ru_US", "fr_US", "en_PH"]
    private static let двадцатичетырёхчасовые = ["ru_RU", "uk_UA", "fr_FR", "kk_KZ", "en_GB"]

    /// Дата с нужным часом в поясе УСТРОЙСТВА.
    ///
    /// `Calendar.current` несёт пояс симулятора, а `Fmt.clock(_:)`
    /// печатает в нём же — значит час на выходе равен запрошенному
    /// при любой настройке стенда. Середина июня взята нарочно: ни одна
    /// наша локаль не переводит часы в этот день, и опора не съезжает.
    private static func момент(часов: Int, минут: Int = 0) -> Date {
        Calendar.current.date(from: DateComponents(year: 2026, month: 6, day: 15,
                                                   hour: часов, minute: минут))!
    }

    // MARK: Ось

    /// **Главная проверка.** Два разных часа — две разных строки.
    @Test func часПослеПолудняНеСливаетсяСУтренним() {
        for код in Self.двенадцатичасовые + Self.двадцатичетырёхчасовые {
            let локаль = Locale(identifier: код)
            let вечер = Fmt.clock(Self.момент(часов: 20), локаль: локаль)
            let утро = Fmt.clock(Self.момент(часов: 8), локаль: локаль)
            #expect(вечер != утро, """
                \(код): 20:00 и 08:00 напечатались одинаково — «\(вечер)».
                Это не «непривычный вид», а ПОТЕРЯ ДАННЫХ: по строке
                нельзя сказать, когда давали дозу. Ровно так вела себя
                форма `.hour(.twoDigits(amPM: .omitted))` до 04.11.2026.
                """)
        }
    }

    /// То же для расписания доз — у него своя функция и свой вход.
    @Test func часПослеПолудняНеСливаетсяИУРасписания() {
        for код in Self.двенадцатичасовые + Self.двадцатичетырёхчасовые {
            let локаль = Locale(identifier: код)
            let вечер = Fmt.clock(minuteOfDay: 20 * 60, локаль: локаль)
            let утро = Fmt.clock(minuteOfDay: 8 * 60, локаль: локаль)
            #expect(вечер != утро,
                    "\(код): расписание напечатало 20:00 и 08:00 одинаково — «\(вечер)»")
        }
    }

    /// **Вторая половина дефекта.** Обе формы часа обязаны совпасть.
    ///
    /// До 04.11.2026 `clock(_:)` шёл через локаль (и терял полдень),
    /// а `clock(minuteOfDay:)` — через `String(format: "%02d:%02d")`
    /// и был 24-часовым всегда. На экране «Здоровье» время дозы
    /// из расписания и из журнала стояли рядом и расходились
    /// на двенадцать часов. Это было устройство, а не случай.
    @Test func двеФормыЧасаДаютОдноИТоЖе() {
        for код in Self.двенадцатичасовые + Self.двадцатичетырёхчасовые {
            let локаль = Locale(identifier: код)
            for (часов, минут) in [(20, 0), (15, 46), (9, 22), (0, 5), (12, 0), (23, 59)] {
                let поМоменту = Fmt.clock(Self.момент(часов: часов, минут: минут), локаль: локаль)
                let поРасписанию = Fmt.clock(minuteOfDay: часов * 60 + минут, локаль: локаль)
                #expect(поМоменту == поРасписанию, """
                    \(код), \(часов):\(минут): журнал печатает «\(поМоменту)»,
                    расписание — «\(поРасписанию)». Две формы одного часа
                    на одном экране.
                    """)
            }
        }
    }

    /// Расписание не зависит от пояса: `minuteOfDay` — время на часах,
    /// а не момент. Иначе перевод часов дважды в год сдвигал бы час дозы.
    @Test func минутыОтПолуночиНеЗависятОтПояса() {
        let ру = Locale(identifier: "ru_RU")
        #expect(Fmt.clock(minuteOfDay: 22 * 60, локаль: ру) == "22:00")
        #expect(Fmt.clock(minuteOfDay: 0, локаль: ру) == "00:00")
        #expect(Fmt.clock(minuteOfDay: 23 * 60 + 59, локаль: ру) == "23:59")
    }

    // MARK: Якоря — что именно прочитает человек

    /// Американец читает указатель, а не голый час.
    ///
    /// U+202F перед «PM» — не опечатка, см. шапку набора.
    @Test func американецЧитаетУказатель() {
        let сша = Locale(identifier: "en_US")
        #expect(Fmt.clock(Self.момент(часов: 20), локаль: сша) == "8:00\u{202F}PM")
        #expect(Fmt.clock(Self.момент(часов: 15, минут: 46), локаль: сша) == "3:46\u{202F}PM")
        #expect(Fmt.clock(minuteOfDay: 22 * 60, локаль: сша) == "10:00\u{202F}PM")
        // Утро — тоже с указателем: иначе «8:00» остаётся двусмысленным
        // в другую сторону.
        #expect(Fmt.clock(Self.момент(часов: 8), локаль: сша) == "8:00\u{202F}AM")
    }

    /// Четыре 24-часовых языка каталога не изменились НИ В ОДНОМ знаке.
    ///
    /// Это граница правки, и она важнее якорей выше: цена починки
    /// измеряется тем, что она НЕ задела. Прежняя форма давала здесь
    /// ровно эти строки.
    @Test func двадцатьЧетыреЧасаНеТронуты() {
        for код in ["ru_RU", "uk_UA", "fr_FR", "kk_KZ", "en_GB"] {
            let локаль = Locale(identifier: код)
            #expect(Fmt.clock(Self.момент(часов: 20), локаль: локаль) == "20:00", "\(код)")
            #expect(Fmt.clock(Self.момент(часов: 15, минут: 46), локаль: локаль) == "15:46", "\(код)")
            #expect(Fmt.clock(Self.момент(часов: 9, минут: 22), локаль: локаль) == "09:22", "\(код)")
            #expect(Fmt.clock(minuteOfDay: 20 * 60, локаль: локаль) == "20:00", "\(код)")
        }
    }

    // MARK: Поверхности, у которых свой вход

    /// Расписание схемы на экране «Здоровье» идёт через `Fmt`.
    ///
    /// `scheduleSummary` до 04.11.2026 печатал час сам
    /// (`String(format: "%02d:%02d")`) — третья копия одного правила
    /// и единственная, не знавшая про 12-часовые сутки.
    @Test func расписаниеСхемыИдётЧерезОбщийЧас() {
        let схема = Medication(name: "Эутирокс", doseText: "50 мкг", times: [8 * 60, 20 * 60])
        for минута in схема.times {
            #expect(схема.scheduleSummary.contains(Fmt.clock(minuteOfDay: минута)), """
                Расписание «\(схема.scheduleSummary)» не содержит
                \(Fmt.clock(minuteOfDay: минута)) — значит час печатается
                где-то ещё, мимо `Fmt`.
                """)
        }
    }

    /// Слот дозы — тоже через `Fmt`.
    @Test func слотДозыИдётЧерезОбщийЧас() {
        for минута in [8 * 60, 20 * 60, 0, 23 * 60 + 59] {
            #expect(DoseSlot(minuteOfDay: минута, quantity: 1).clock
                    == Fmt.clock(minuteOfDay: минута))
        }
    }

    // MARK: Проверка на вторую реализацию — прокси, и названа прокси

    /// Ручного `"%02d:%02d"` в дереве нет нигде, кроме `Formatting.swift`.
    ///
    /// **Это прокси, и он здесь на правах второго замера, а не оси.**
    /// Поведение проверено выше; эта проверка ловит другое — появление
    /// ЧЕТВЁРТОЙ копии правила в файле, который ещё не написан. Такую
    /// копию поведенческий тест не увидит: он зовёт `Fmt`, а новая копия
    /// будет звать себя.
    ///
    /// У проверки есть **положительный контроль**: законное вхождение
    /// внутри `Fmt.clock(minuteOfDay:)` обязано найтись. Без него
    /// «ноль нарушений» ничем не отличается от «сканер не прочитал
    /// ни одного файла» — ровно тот ложный ноль, который здесь
    /// ловят весь год.
    @Test func второйРеализацииЧасаВДеревеНет() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        var прочитано = 0
        var законных = 0
        var нарушения: [String] = []

        for каталог in ["TogoShared", "Togo", "TogoWidgets"] {
            let путь = корень.appendingPathComponent(каталог)
            guard let обход = FileManager.default.enumerator(at: путь,
                                                             includingPropertiesForKeys: nil)
            else { continue }
            for случай in обход {
                guard let url = случай as? URL, url.pathExtension == "swift" else { continue }
                guard let текст = try? String(contentsOf: url, encoding: .utf8) else { continue }
                прочитано += 1
                for (номер, строка) in текст.components(separatedBy: "\n").enumerated()
                where строка.contains(#""%02d:%02d""#) {
                    // Проза не считается реализацией. Поймано на себе
                    // в день написания: доккомментарий этой же правки
                    // («Здесь стояло `String(format: "%02d:%02d", …)`»)
                    // дал сканеру второе «законное» вхождение и уронил
                    // положительный контроль. Это наш измеренный класс
                    // «сканирующий сторож меряет прозу», только
                    // в красную сторону — что не лучше: сторож, краснеющий
                    // на упоминании, снимут первым же «да он всегда красный».
                    let начало = строка.trimmingCharacters(in: .whitespaces)
                    guard !начало.hasPrefix("//") else { continue }
                    if url.lastPathComponent == "Formatting.swift" {
                        законных += 1
                    } else {
                        нарушения.append("\(url.lastPathComponent):\(номер + 1)")
                    }
                }
            }
        }

        // Контроль снимается В ТОМ ЖЕ замере и подвержен тому же отказу:
        // не прочитались файлы — умрут оба, и несовместимость видна
        // без знания причины.
        #expect(прочитано > 100, "сканер прочитал \(прочитано) файлов — замер не состоялся")
        #expect(законных == 1, """
            Положительный контроль: в `Formatting.swift` ожидалось ровно
            одно законное `"%02d:%02d"` (запасная ветка
            `clock(minuteOfDay:)`), найдено \(законных). Если ноль —
            сканер ищет не то, и «ноль нарушений» ниже ничего не значит.
            """)
        #expect(нарушения.isEmpty, """
            Час собран руками мимо `Fmt`: \(нарушения.joined(separator: ", ")).
            `String(format: "%02d:%02d", …)` ВСЕГДА 24-часовой — рядом
            с `Fmt.clock` он даёт два формата на одном экране. Звать
            `Fmt.clock(minuteOfDay:)`.
            """)
    }
}
