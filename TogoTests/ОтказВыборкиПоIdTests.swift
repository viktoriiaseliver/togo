import Foundation
import Testing

/// Опознание записи по `id` не имеет права прятать отказ за `try?`.
///
/// ## Почему это не придирка к стилю
///
/// `@Attribute(.unique)` в проекте нет ни у одной модели, и завести его
/// нельзя: хранилище зеркалится в CloudKit (`Persistence.swift:211-214`,
/// `cloudKitDatabase: .private`), а зеркало уникальных ограничений
/// не допускает. Это записано тестом, а не комментарием —
/// `SharedDogTests:253-290`: **«хранилище не склеивает двух собак
/// с одним id — это делает наш код»**.
///
/// «Наш код» — это ровно выборка по `id` в `SharedDiaryInbox`. Она
/// единственная, и вот как она выглядела 14.10.2026 во всех
/// пятнадцати местах:
///
/// ```swift
/// let existing = try? context.fetch(
///     FetchDescriptor<Dog>(predicate: #Predicate { $0.id == id })
/// ).first
///
/// guard let local = existing else {
///     let dog = Dog(name: payload.name, weightKg: payload.weightKg)
///     dog.id = payload.id          // ← тот же id, НОВАЯ строка
///     context.insert(dog)
/// ```
///
/// `try?` превращает **отказ выборки** в `nil`, то есть в «такой собаки
/// нет». Ответ кода на «нет» — завести новую. Значит несостоявшийся
/// замер здесь не молчит, а **создаёт дубликат**, и дубликат уезжает
/// ко второму человеку.
///
/// > Отказ падает не в безопасную сторону, а ровно в ту, от которой
/// > стоит защита.
///
/// ## Асимметрия, которая делает это адресным
///
/// У **записи** проект этот класс закрыл нарочно и с объяснением —
/// `TogoShared/Domain/Persist.swift:48`, `persist(otherwise:)`: отказ
/// возвращает `false`, вызывающий откатывает вставку. Она же вызвана
/// строкой ниже, в `SharedDiaryPayloads:691`. У **чтения** такого
/// соглашения нет вовсе, и цена промаха у чтения выше: несохранённая
/// запись теряется, а несостоявшаяся выборка — размножается.
///
/// И проект уже снимал ровно этот `try?` однажды.
/// `SharedDiaryFetchFailureTests` заведён 24.09.2026 после двух суток
/// пустого экрана у второго человека: «в `fetchNow` стояло `try?`,
/// ошибка уходила в никуда, а состояние тут же становилось
/// `idle(lastSync: сейчас)`». **Класс закрыт в одном вызове
/// из двадцати восьми.**
///
/// ## Чего этот сторож НЕ доказывает
///
/// Он читает форму кода, а не поведение. Сторож на поведение требует
/// хранилища, умеющего отказать по команде, — это дороже и его здесь
/// нет. Поэтому ноль здесь значит «этот способ проглотить отказ
/// закрыт», а не «отказ разобран верно».
///
/// Девятикратность (девять строк под одним `id` в журнале с её
/// телефона, замер 09.10.2026) этим **не объяснена**. Установлено
/// только, что механизм, дающий ровно такую форму, существует
/// и достижим. Что сработал именно он — нет, и различителя у нас
/// не было никогда: запись в лог на ветке отказа не писалась, потому
/// что ветки нет.
@Suite("Отказ выборки по id не читается как «не нашлось»")
struct ОтказВыборкиПоIdTests {

    /// Дерево обхода. Проверяется на существование **до** обхода.
    ///
    /// `FileManager.enumerator(at:)` по несуществующему пути отдаёт
    /// `nil`, и `guard … else { continue }` молчит. Ровно так
    /// `FallbackLiteralTests:180` четверо суток обходил каталог
    /// «TogoWidget», которого на диске нет.
    private static let дерево = "TogoShared/Sync"

    /// Долг по файлам, замер 14.10.2026. Число может только уменьшаться.
    ///
    /// **Две записи — два РАЗНЫХ утверждения, и сводить их в одно
    /// число нельзя.** Ущерб у половин разный:
    ///
    /// ```
    /// SharedDiaryPayloads   опознать-или-вставить
    ///                       отказ → новая строка с тем же id → ДУБЛИКАТ
    /// FamilySync:492-554    перебор двенадцати типов: «какого типа
    ///                       эта запись». «Не нашлось» здесь ОЖИДАЕМО
    ///                       и верно для одиннадцати из двенадцати
    ///                       отказ → запись не уедет вовсе, молча
    /// ```
    ///
    /// Вторая половина тоже неправа, но её чинить второй: потеря
    /// отправки дешевле размножения, и запись вернётся следующей
    /// правкой, а дубликат не уйдёт никогда.
    private let долг: [String: Int] = [
        "SharedDiaryPayloads.swift": 15,
        "FamilySync.swift": 12,
    ]

    @Test("Опознание по id не прячет отказ выборки за try?")
    func отказовПодTryНеБольше() throws {
        let (места, файлов, строк) = try Self.находки()

        // Порог по САМОМУ ОБХОДУ, а не по находкам и не по числу
        // предикатов. Третье было бы ошибкой, которую проект уже
        // оплачивал: починка собирает пятнадцать предикатов в один
        // общий помощник, счёт падает до единицы, и сторож объявил бы
        // «я ослеп» на здоровом дереве.
        //
        // > Порог обязан не зависеть от исхода работы, иначе он мерит
        // > нас, а не проект.
        //
        // Файлы и строки от нашей правки не зависят: правка меняет
        // форму выражения, а не состав каталога.
        #expect(файлов >= 6, """
            в «\(Self.дерево)» просмотрено файлов \(файлов) при 9 \
            на 14.10.2026. Обход читает не тот каталог — проверь обход, \
            а не проект.
            """)
        #expect(строк >= 2_000, """
            в «\(Self.дерево)» просмотрено строк кода \(строк) при 2797 \
            на 14.10.2026. Сканер читает файлы и не видит их содержимого.
            """)

        var перебор: [String] = []
        for (файл, строки) in места.sorted(by: { $0.key < $1.key }) {
            let разрешено = долг[файл] ?? 0
            guard строки.count > разрешено else { continue }
            let адреса = строки.map { "      \(файл):\($0)" }.joined(separator: "\n")
            перебор.append("""
                \(файл): выборок по id под `try?` \(строки.count) при долге \(разрешено)
                \(адреса)
                """)
        }

        #expect(перебор.isEmpty, """
            опознание записи по id прячет отказ выборки за `try?`:

            \(перебор.joined(separator: "\n"))

            `try?` отдаёт `nil` и на «не нашлось», и на «не смог \
            посмотреть». Там, где на `nil` заводится новая запись \
            с тем же `id`, это не молчание, а дубликат — и он уезжает \
            ко второму человеку. Уникальности у `id` нет и быть \
            не может: хранилище зеркалится в CloudKit.

            Лечится тремя состояниями вместо двух — нашлось · не нашлось \
            · ОТВЕЧАТЬ НЕЧЕМ, по образцу `Persist.swift:48`. На третьем \
            состоянии запись пропускается и приедет следующим заходом: \
            пропущенная вернётся, дубликат не уйдёт никогда.

            Правку числа в долге считать починкой нельзя.
            """)

        // Закрытое обязано уйти из долга: запись, пережившая свои
        // строки, разрешает вернуть то, что уже починено.
        let протухшие = долг.keys
            .filter { (места[$0]?.count ?? 0) < (долг[$0] ?? 0) }
            .sorted()
        #expect(протухшие.isEmpty, """
            долг числит больше, чем в файле есть: \(протухшие). \
            Затяни числа до измеренного — иначе в них можно дописать \
            новый дефект, и сторож останется зелёным.
            """)

        print("""
            ГРАНИЦА: сторож видит `try?` перед выборкой, у которой \
            предикат `$0.id == …`, в пределах одного выражения.
            Он НЕ видит: `try?` на выборке без предиката по id; \
            отказ, проглоченный через `?? []`; и разобранную ошибку, \
            после которой всё равно идёт вставка.
            Ноль здесь — «этот один способ проглотить отказ закрыт», \
            а не «отказ разобран верно».
            """)
    }

    @Test("Разбор узнаёт обе формы и не считает чужое")
    func разборРазличаетФормы() {
        // Проверка самого разбора, а не его результата. Без неё сканер
        // мог бы перестать находить что-либо вовсе и был бы зелёным —
        // то есть неотличим от починенного дерева.
        let однойСтрокой = #"let d = try? ctx.fetch(FetchDescriptor<Dog>(predicate: #Predicate { $0.id == id })).first"#
        #expect(Self.отказСпрятан(однойСтрокой) == true)

        // Живая форма из проекта: `try?` и предикат на РАЗНЫХ строках.
        // Построчный разбор её не видит, и первая редакция этого
        // сторожа нашла бы ноль на дереве с пятнадцатью находками.
        let вНесколькоСтрок = """
            let existing = try? context.fetch(
                FetchDescriptor<Dog>(predicate: #Predicate { $0.id == id })
            ).first
            """
        #expect(Self.отказСпрятан(вНесколькоСтрок) == true)

        // Разобранный отказ — не находка: это и есть лечение.
        let разобрано = """
            let найдено = try context.fetch(
                FetchDescriptor<Dog>(predicate: #Predicate { $0.id == id })
            ).first
            """
        #expect(Self.отказСпрятан(разобрано) == false)

        // Выборка без предиката по id — другой класс и другой ущерб.
        // Считать её здесь значило бы развести шум: таких в проекте
        // ещё двадцать девять, и они не про опознание.
        #expect(Self.отказСпрятан(#"let все = try? ctx.fetch(FetchDescriptor<Dog>())"#) == false)

        // Комментарий, называющий форму, — не вызов. Этот класс проект
        // уже оплачивал: сканирующий сторож мерил прозу и красил себя
        // зелёным с упоминания имени вызова в тексте рядом.
        #expect(Self.отказСпрятан(#"// было: try? ctx.fetch(... #Predicate { $0.id == id })"#) == false)
    }

    // MARK: Разбор

    /// Спрятан ли отказ выборки, опознающей запись по `id`.
    ///
    /// Ищем предикат, а от него смотрим **назад**: `try?` стоит левее
    /// и часто строкой выше. Обратный порядок (искать `try?`, потом
    /// предикат) потребовал бы знать, где кончается выражение, —
    /// а это разбор языка, а не поиск.
    static func отказСпрятан(_ текст: String) -> Bool {
        !адресаОтказов(текст).isEmpty
    }

    /// Номера строк, на которых стоит предикат по `id` под `try?`.
    static func адресаОтказов(_ текст: String) -> [Int] {
        let строки = текст.components(separatedBy: "\n")
        let безКомментариев = строки.map { $0.components(separatedBy: "//")[0] }
        let код = безКомментариев.joined(separator: "\n")

        let образец = #"#Predicate\s*\{\s*\$0\.id\s*=="#
        guard let re = try? NSRegularExpression(pattern: образец) else { return [] }
        let область = NSRange(код.startIndex..., in: код)

        var адреса: [Int] = []
        for m in re.matches(in: код, range: область) {
            guard let начало = Range(m.range, in: код)?.lowerBound else { continue }
            // Назад — не дальше ста шестидесяти знаков: это длина
            // живого выражения с запасом. Брать весь файл нельзя,
            // иначе один `try?` в начале файла пометил бы всё.
            let левее = код[..<начало]
            let хвост = левее.suffix(160)
            guard хвост.contains("try?") else { continue }
            адреса.append(левее.filter { $0 == "\n" }.count + 1)
        }
        return адреса
    }

    /// Файл → строки с находкой, плюс сколько файлов и строк кода
    /// просмотрено.
    ///
    /// Второе и третье возвращаются значением, а не копятся
    /// в статической переменной: изменяемое статическое состояние
    /// в наборе — это и гонка под строгой проверкой, и зависимость
    /// результата от порядка тестов.
    private static func находки() throws -> (места: [String: [Int]], файлов: Int, строк: Int) {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        let папка = корень.appendingPathComponent(дерево)

        #expect(FileManager.default.fileExists(atPath: папка.path), """
            каталога «\(дерево)» нет на диске — обход молча пропустил бы \
            его целиком и сторож был бы зелёным. Путь сменился? Поправь \
            его, а не долг.
            """)

        var места: [String: [Int]] = [:]
        var файлов = 0
        var строкВсего = 0

        guard let обход = FileManager.default.enumerator(at: папка,
                                                         includingPropertiesForKeys: nil)
        else { return (места, файлов, строкВсего) }

        for случай in обход {
            guard let адрес = случай as? URL, адрес.pathExtension == "swift" else { continue }
            guard let текст = try? String(contentsOf: адрес, encoding: .utf8) else { continue }
            файлов += 1

            for строка in текст.components(separatedBy: "\n") {
                let код = строка.components(separatedBy: "//")[0]
                if !код.trimmingCharacters(in: .whitespaces).isEmpty { строкВсего += 1 }
            }

            let адреса = адресаОтказов(текст)
            if !адреса.isEmpty { места[адрес.lastPathComponent] = адреса }
        }

        return (места, файлов, строкВсего)
    }
}
