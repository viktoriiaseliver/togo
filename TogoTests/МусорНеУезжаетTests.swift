import Testing
import Foundation
import SwiftData
@testable import Togo

/// Безымянная собака не уезжает к человеку и не кормится нами.
///
/// # Повод измерен по живым данным, а не предположен
///
/// Выгрузка и журнал с телефона Виктории, 08.10.2026:
///
/// ```
/// собак 16 · без клички 15 · с кличкой одна («Стич»)
/// строк переписи 60 · разных id 7 · seenBefore=1 у 45 из 60 → КОПЯТСЯ
/// заполненных полей у всех 60     ровно одно: dailyNormGrams
/// связей у всех 60                ноль по всем одиннадцати
/// пять из семи несут ОДНО changed  2026-10-06T07:32:18Z
///                                  при ТРЁХ разных датах создания
/// у 5660DD79  changed РАНЬШЕ created (07:32:18 против 07:44:47)
/// ```
///
/// Одно `changed` на пять строк — это один пакетный проход. И проход
/// наш: `FeedingMigration` (`TogoApp:219`) шла по всем собакам без
/// разбора и писала фантому `setDailyGrams(0)`; `FamilySync:278` —
/// единственный писатель `Dog.changedAt` в дереве — ставил отметку
/// и кладёт запись в `pendingRecordZoneChanges`.
///
/// ```
/// FeedingMigration пишет фантому
///   → SwiftData видит изменение
///   → FamilySync ставит changedAt и queues saveRecord
///   → пятнадцать пустых собак уезжают в общую зону, к маме
/// ```
///
/// > **Мусор, который уходит от нас к человеку, хуже мусора, который
/// > лежит у нас.** Свои пустые записи мы хотя бы не показываем
/// > (`Dog.canBeShown`); уехавшие живут в чужом хранилище, где наше
/// > правило показа не действует.
///
/// # Форма — от запрета, и запрещены ДВЕ разные вещи
///
/// Не «миграция работает правильно» и не «обмен отправляет нужное»
/// (требование: у правильного десять форм), а два запрета, каждый
/// со своим предметом:
///
/// ```
/// обмен      в исходящий круг не попадает Dog без клички
/// миграция   запуск не меняет записи, которых человек не видит
/// ```
///
/// Второй нужен не ради экономии: пока миграция их трогает, SwiftData
/// считает их изменёнными, и **первый запрет пришлось бы держать
/// в одиночку против потока**. Два запрета в разных слоях дешевле
/// одного в узком месте.
///
/// # Чего эти запреты НЕ делают
///
/// Они **не чинят появление** фантомов: откуда они берутся, не
/// установлено. Девять записей созданы в одну секунду 07.10 16:53:36,
/// в ту же секунду открылся онбординг, и совпадение времени связью
/// не является. Решающий замер — проход онбординга на стёртом
/// симуляторе со счётом `Dog` после — **назначен**
/// `togo-review-frames-sync`.
///
/// И граница этого набора: он проверяет **правило**, а не дорогу.
/// «Позвали `hasUsableName`, а он пропустил» он поймает; «миграция
/// переехала в другое место и фильтр потеряли» — нет, для этого стоит
/// текстовый запрет ниже.
@MainActor
@Suite("Безымянная собака не уезжает и не кормится")
struct МусорНеУезжаетTests {

    /// Тот же стенд, что у соседа по предмету
    /// (`NamelessDogHiddenTests`): свой контейнер здесь завести нельзя
    /// — схема одна на проект, и вторая её сборка расходится с живой
    /// молча.
    private func стенд() -> ModelContext {
        ModelContext(Persistence.container())
    }

    // MARK: Запрет 1 · миграция не кормит фантомов

    @Test("Миграция запуска не трогает собаку без клички")
    func миграцияНеКормитФантома() throws {
        let context = стенд()
        let фантом = Dog(name: "", weightKg: 0)
        let живая = Dog(name: "Стич", weightKg: 4.7)
        context.insert(фантом)
        context.insert(живая)

        // Проверка, что стенд воспроизводит ИМЕННО то состояние,
        // которое пришло с телефона: поле пусто, связей нет.
        #expect(фантом.dailyNormGrams == nil, """
            стенд не воспроизводит фантома: dailyNormGrams уже заполнен,
            и тогда замер ниже ничего не проверяет.
            """)
        #expect(!фантом.canBeShown)
        #expect(живая.canBeShown)

        FeedingMigration.run(context: context)

        #expect(фантом.dailyNormGrams == nil, """
            миграция запуска заполнила `dailyNormGrams` у собаки без
            клички. Это ровно то, что отправляло пятнадцать пустых
            записей маме: заполненное поле → SwiftData видит изменение
            → FamilySync ставит changedAt и кладёт запись в отправку.

            И второе следствие: перепись безымянных печатает
            «fields [dailyNormGrams]» и читается как указание на семя,
            а заполнили его мы же на семнадцать строк раньше.
            """)

        // Своё зрение: миграция обязана была сделать свою работу
        // у живой. Иначе зелёный выше значит «миграция не запускалась».
        #expect(живая.dailyNormGrams != nil, """
            миграция не тронула и ЖИВУЮ собаку — значит она не делает
            ничего, и запрет выше проверен впустую.
            """)
    }

    // MARK: Запрет 2 · правило «годится ли в кличку» одно на всех

    @Test("Единственная реализация правила отвечает одинаково всем трём дорогам")
    func правилоОдно() {
        // У `hasUsableName` три звонящих: разбор записи CloudKit, приём
        // снимка и теперь исходящий круг. Если правило разойдётся,
        // мусор поедет по той дороге, которая спросила иначе.
        for пустая in ["", " ", "\n", "\u{00A0}"] {
            #expect(!DogPayload.hasUsableName(пустая), """
                `hasUsableName` пропустил «\(пустая.debugDescription)».
                Неразрывный пробел здесь не для красоты: им набрана вся
                французская типографика, и строка из одного такого
                пробела рисуется на экране ровно так же пусто, как "".
                """)
        }
        #expect(DogPayload.hasUsableName("Стич"))
        #expect(DogPayload.hasUsableName(" Стич "))
    }

    // MARK: Запрет 3 · текстом, потому что поведение не видит потерю фильтра

    /// Фильтры стоят там, где стоят, — и это проверяется текстом.
    ///
    /// Поведенческие запреты выше поймают «правило пропустило». Они
    /// не поймают «миграция переехала в другой файл, а `guard`
    /// потеряли» и «ветку `Dog` в исходящем круге переписали без
    /// проверки»: оба дадут зелёный на новом коде, которого тест
    /// не знает.
    @Test("Оба фильтра стоят в коде, а не только в замысле")
    func фильтрыНаМесте() throws {
        let корень = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
        func код(_ путь: String) throws -> [String] {
            try String(contentsOf: корень.appendingPathComponent(путь), encoding: .utf8)
                .components(separatedBy: "\n")
                .map { $0.components(separatedBy: "//")[0] }
        }

        let миграция = try код("TogoShared/Domain/FeedingMigration.swift")
        let обмен = try код("TogoShared/Sync/FamilySync.swift")

        // Своё зрение первым: файлы прочитаны и это те файлы.
        #expect(миграция.count > 40, "FeedingMigration прочитан пустым: \(миграция.count) строк")
        #expect(обмен.count > 200, "FamilySync прочитан пустым: \(обмен.count) строк")
        #expect(миграция.contains { $0.contains("static func run(context:") })
        #expect(обмен.contains { $0.contains("as? Dog") }, """
            в исходящем круге больше нет ветки `as? Dog` — сторож смотрит
            в пустоту, и запрет ниже ничего не значит.
            """)

        #expect(миграция.contains { $0.contains("guard dog.canBeShown else { continue }") }, """
            в `FeedingMigration` нет пропуска записей, которых человек
            не видит. Без него миграция снова начнёт писать фантомам
            `dailyNormGrams` на каждом запуске.
            """)
        #expect(обмен.contains { $0.contains("guard SharedDiaryOutgoing.sendable(dog)") }, """
            в исходящем круге нет ворот на кличку. Без них безымянная
            собака снова уедет в общую зону — и там наше правило показа
            не действует.
            """)

        // И ВТОРАЯ ДВЕРЬ. Запрет в одной двери второй не знает:
        // засев уже лежащих записей кладёт изменения в движок
        // напрямую, мимо `enqueueLocalChanges`. Пока засева в дереве
        // нет, проверка держит само правило — что ворота существуют
        // отдельной функцией, которую можно позвать из второго места.
        let правила = try код("TogoShared/Sync/SharedDiaryPayloads.swift")
        #expect(правила.contains { $0.contains("enum SharedDiaryOutgoing") }, """
            ворота наружу перестали быть отдельной функцией. Пока они
            внутри одной двери, вторая дверь их не позовёт — и уедет
            то, что здесь запрещено.
            """)
        #expect(правила.contains { $0.contains("DogPayload.hasUsableName(dog.name)") }, """
            ворота наружу перестали звать единственную реализацию
            правила «годится ли это в кличку». Своя копия условия
            разойдётся с разбором записи и приёмом снимка молча.
            """)

        // Своё зрение: файл правил прочитан и это он.
        #expect(правила.count > 100, "SharedDiaryPayloads прочитан пустым: \(правила.count) строк")
    }
}
